/**
 * СЧЁТ ПО БИБЛИОТЕКЕ: сколько утверждений высказано в `flang/stdlib`, сколько из
 * них ядро доказывает и сколько из доказанных что-то ЗНАЧИТ.
 *
 * Тот же вопрос, что задаёт `schyot-20.mjs` двадцати функциям замера, — только
 * заданный всей библиотеке. И тем же способом, механическим: тело функции
 * подменяется ЗАГЛУШКОЙ того же объявленного типа, подпись и текст утверждения
 * остаются прежними, ведомость считается заново.
 *
 *   утверждение и с заглушкой доказано → ОСЛАБЛЕННОЕ: верно про любую функцию
 *                                        этой подписи и про ЭТУ не говорит ничего;
 *   утверждение с заглушкой отпало     → СОДЕРЖАТЕЛЬНОЕ: отличает настоящее тело
 *                                        от подставного.
 *
 * ЧТО ЭТОТ СЧЁТ УМЕЕТ И ЧЕГО НЕ УМЕЕТ, названо прямо. Подмена отвечает только про
 * утверждение, которое ядро УЖЕ доказало: у недоказанного вердикт «сетка» и с
 * заглушкой останется «сетка», и подмена о нём не говорит ничего. Поэтому
 * содержательность считается СРЕДИ ДОКАЗАННЫХ, а общее число высказанных
 * печатается рядом — чтобы дробь была видна целиком, а не только её числитель.
 *
 * ПУСТАЯ ВЕДОМОСТЬ НЕ ЕСТЬ «ДОКАЗАНО 0». `flang check --proof` не печатает
 * ведомость у программы С ЗАМЕЧАНИЯМИ, и один красный пример гасит вердикты
 * ВСЕГО файла. До 26 августа счёт читал эту пустоту как «ничего не доказано» и
 * вычитал файл из меры МОЛЧА — на `11-unique.flang` и `13-even.flang` он так и
 * печатал `доказано 0`, где доказано не ноль. Теперь вердикт берётся у того же
 * файла БЕЗ примеров (как у двойника `count-20.flang`) и помечается вслух, а
 * файл, у которого ведомости нет и без примеров, назван отдельной строкой.
 *
 * Заглушка строится по объявленному типу результата, и типов у неё четыре.
 * Функция, возвращающая объявленную сумму, запись или параметр типа, помечается
 * НЕ ПРОВЕРЕНО — а не записывается в содержательные по умолчанию.
 *
 * Прогон:  LC_ALL=C.UTF-8 node benchmarks/proof-cost/count-library.mjs
 *
 * ПОФАЙЛОВО, и это не удобство, а правило дерева: счёт зовёт ведомость по разу
 * на КАЖДОЕ доказанное утверждение, а ведомость иного файла библиотеки идёт
 * минутами (`scram.flang` — пятнадцать). Всей библиотекой разом счёт занимает
 * часы и на общей машине упирается в память. Имена файлов доводами — считаются
 * только они:
 *
 *   LC_ALL=C.UTF-8 node benchmarks/proof-cost/count-library.mjs lists.flang higher-order.flang
 *
 * Без доводов берётся вся библиотека, как и прежде.
 */
import { execFileSync } from "node:child_process"
import { readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const корень = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..")
const каталог = join(корень, "flang", "stdlib")
const двоичный = join(корень, "bootstrap", "flang")

function позвать(доводы) {
  try {
    return execFileSync(двоичный, доводы, {
      encoding: "utf8",
      env: { ...process.env, LC_ALL: "C.UTF-8" },
      maxBuffer: 1 << 26,
      stdio: ["ignore", "pipe", "pipe"],
    })
  } catch (беда) {
    return (беда.stdout ?? "") + (беда.stderr ?? "")
  }
}

const разбор = (путь) => JSON.parse(позвать(["ast", путь]))
const ведомость = (путь) => позвать(["check", путь, "--proof"])

/** «функция|утверждение» → ДОКАЗАНО | СЕТКА | ОБЪЯВЛЕНО. */
function вердикты(текст) {
  const итог = new Map()
  for (const строка of текст.split("\n")) {
    const м = /^\s*(?:постусловие|предусловие) «([^»]+)» функции «([^»]+)» — (.*)$/.exec(строка)
    if (м === null) continue
    итог.set(
      м[2] + "|" + м[1],
      м[3].startsWith("доказано") ? "ДОКАЗАНО" : м[3].includes("на сетке") ? "СЕТКА" : "ОБЪЯВЛЕНО",
    )
  }
  return итог
}

/* ТАВТОЛОГИЯ — постусловие вида `результат равен Е`, где `Е` есть само тело
   функции, знак в знак. Такое утверждение не ложно — оно просто не независимо:
   спецификация и есть реализация, и проверять ей нечего. Подмена тела его
   ломает, поэтому без отдельного вопроса оно попало бы в содержательные. */
function безМест(узел) {
  if (Array.isArray(узел)) return узел.map(безМест)
  if (узел === null || typeof узел !== "object") return узел
  const итог = {}
  for (const ключ of Object.keys(узел).sort()) {
    if (ключ === "span") continue
    итог[ключ] = безМест(узел[ключ])
  }
  return итог
}
const РЕЗУЛЬТАТ = (у) => у?.kind === "var" && у.name === "результат"
function тавтология(постусловие, тело) {
  const в = постусловие.expr
  if (в?.kind !== "binary" || в.op !== "eq") return false
  const другая = РЕЗУЛЬТАТ(в.left) ? в.right : РЕЗУЛЬТАТ(в.right) ? в.left : null
  if (другая === null) return false
  return JSON.stringify(безМест(другая)) === JSON.stringify(безМест(тело))
}

const ЗАГЛУШКИ = new Map([
  ["number", "0"], ["string", '""'], ["flag", "нет"], ["list", "пустой список"],
  ["nat", "0"], ["integer", "0"], ["weight", "0"], ["cost", "0"],
])
function заглушка(тип) {
  if (тип?.kind === "named") return ЗАГЛУШКИ.get(тип.name) ?? null
  return ЗАГЛУШКИ.get(тип?.kind) ?? null
}

function границыТела(строки, первая) {
  let конец = строки.length
  for (let и = первая; и < строки.length; и += 1) {
    if (/^\S/.test(строки[и])) { конец = и; break }
  }
  while (конец > первая && строки[конец - 1].trim() === "") конец -= 1
  return конец
}

function сЗаглушкой(исходник, функция, текст) {
  const строки = исходник.split("\n")
  const первая = функция.body.span.line - 1
  const конец = границыТела(строки, первая)
  return [...строки.slice(0, первая), "  " + текст, ...строки.slice(конец)].join("\n")
}

/** Примеры описывают НАСТОЯЩЕЕ поведение: с заглушкой они краснеют все разом и
    до ведомости дело не доходит. Снимаются у ОБОИХ файлов — равное с равным. */
function безПримеров(исходник) {
  const строки = исходник.split("\n")
  const итог = []
  for (let и = 0; и < строки.length; и += 1) {
    const отступ = /^(\s*)(пример|example)(?:\s|$)/.exec(строки[и])
    if (отступ === null) { итог.push(строки[и]); continue }
    const глубина = отступ[1].length
    и += 1
    while (и < строки.length) {
      const строка = строки[и]
      if (строка.trim() !== "" && /^\s*/.exec(строка)[0].length <= глубина) break
      и += 1
    }
    и -= 1
  }
  return итог.join("\n")
}

const отбор = new Set(process.argv.slice(2).map((и) => и.replace(/^.*\//, "")))
// Расширений у программы четыре и они равноправны: `.flang`, `.fp`, `.фп`,
// `.фланг` (ADR-0016). Отбор по одному из них молча терял бы файлы, написанные
// остальными, — и замер выходил бы меньше дерева, ничего об этом не сказав.
const всеФайлы = readdirSync(каталог).filter((и) => /\.(flang|fp|фп|фланг)$/u.test(и)).sort()
for (const имя of отбор) {
  if (всеФайлы.includes(имя)) continue
  console.error(`нет такого файла библиотеки: ${имя}`)
  process.exit(2)
}
const файлы = отбор.size === 0 ? всеФайлы : всеФайлы.filter((и) => отбор.has(и))
const счёт = { высказано: 0, доказано: 0, содержательных: 0, ослабленных: 0, даровых: 0, непроверенных: 0, красных: 0, немых: 0 }
const строкиОтчёта = []

for (const имя of файлы) {
  const путь = join(каталог, имя)
  const исходник = readFileSync(путь, "utf8")
  const дерево = разбор(путь)
  const свои = new Map(
    дерево.functions.filter((ф) => (ф.postconditions ?? []).length > 0).map((ф) => [ф.name, ф]),
  )
  let высказано = 0
  for (const ф of свои.values()) высказано += ф.postconditions.length
  счёт.высказано += высказано

  /* Ведомость файла КАК ОН ЕСТЬ и его же БЕЗ ПРИМЕРОВ. Голый нужен дважды: с
     ним сравнивается подменённый — и им же спасается вердикт, когда ведомости
     как есть нет вовсе. Поэтому он считается ДО, а не после. */
  const какЕсть = вердикты(ведомость(путь))
  const времянка = join(каталог, "~zamer-" + имя)
  const голый = безПримеров(исходник)
  writeFileSync(времянка, голый)
  const безПрим = вердикты(ведомость(времянка))

  /* ПУСТАЯ ВЕДОМОСТЬ — ЭТО НЕ «ДОКАЗАНО 0», И МОЛЧАТЬ ОБ ЭТОМ НЕЛЬЗЯ.
     `flang check --proof` не печатает ведомость у программы С ЗАМЕЧАНИЯМИ, и
     один красный пример гасит вердикты ВСЕГО файла — не только той функции,
     чей пример покраснел. Прочитанная как «ничего не доказано», такая пустота
     вычитает файл из меры целиком и молча: ровно так счёт печатал `доказано 0`
     про `11-unique.flang` и `13-even.flang`, где доказано не ноль.

     Вердикт берётся у того же файла БЕЗ примеров — так делает двойник на flang
     (`count-20.flang`), — и рядом ставится отметка. Красный пример остаётся
     настоящей ошибкой библиотеки; терять из-за неё вердикт ядра значило бы
     мерить не то.

     Если ведомости нет и без примеров, счёт не знает о файле НИЧЕГО — и это
     говорится вслух отдельной строкой, а не нулём. Молчание тут та же болезнь,
     что ловит правило дерева: у ЗАМКНУТОЙ цели «объявлено» означает ложь, а не
     слабость. */
  const красные = какЕсть.size === 0 && безПрим.size > 0
  const немой = какЕсть.size === 0 && безПрим.size === 0
  if (красные) счёт.красных += 1
  if (немой) счёт.немых += 1
  const пункты = красные ? безПрим : какЕсть
  const доказанные = [...пункты.entries()].filter(([, в]) => в === "ДОКАЗАНО").map(([к]) => к)
  счёт.доказано += доказанные.length

  let содержательных = 0
  let ослабленных = 0
  let даровых = 0
  let непроверенных = 0
  for (const ключ of доказанные) {
    const [имяФ, имяУ] = ключ.split("|")
    const ф = свои.get(имяФ)
    const своё = ф === undefined ? null : (ф.postconditions ?? []).find((п) => п.name === имяУ)
    if (своё !== null && своё !== undefined && тавтология(своё, ф.body)) {
      даровых += 1
      строкиОтчёта.push(`  ${имя}: «${имяУ}» — ДАРОВОЕ (тело переписано в постусловие)`)
      continue
    }
    const текст = ф === undefined ? null : заглушка(ф.returns)
    if (текст === null || безПрим.get(ключ) !== "ДОКАЗАНО") {
      непроверенных += 1
      строкиОтчёта.push(`  ${имя}: «${имяУ}» — НЕ ПРОВЕРЕНО`)
      continue
    }
    writeFileSync(времянка, безПримеров(сЗаглушкой(исходник, ф, текст)))
    const сПодменой = вердикты(ведомость(времянка))
    /* Подменённый файл может быть отвергнут целиком — тогда ведомости нет вовсе,
       и «утверждение отпало» читалось бы там, где его просто не считали. Пустая
       ведомость — это НЕ ПРОВЕРЕНО, а не содержательное: умолчание в пользу
       своей работы и есть ошибка, ради которой счёт заведён. */
    if (сПодменой.size === 0) {
      непроверенных += 1
      строкиОтчёта.push(`  ${имя}: «${имяУ}» — НЕ ПРОВЕРЕНО (файл с заглушкой отвергнут целиком)`)
      continue
    }
    if (сПодменой.get(ключ) === "ДОКАЗАНО") {
      ослабленных += 1
      строкиОтчёта.push(`  ${имя}: «${имяУ}» — ОСЛАБЛЕННОЕ (доказано и при теле «${текст}»)`)
    } else {
      содержательных += 1
      строкиОтчёта.push(`  ${имя}: «${имяУ}» — СОДЕРЖАТЕЛЬНОЕ (при теле «${текст}» отпадает)`)
    }
  }
  unlinkSync(времянка)
  счёт.содержательных += содержательных
  счёт.ослабленных += ослабленных
  счёт.даровых += даровых
  счёт.непроверенных += непроверенных
  const отметка = красные
    ? "  [примеры файла красные: вердикт снят у копии без примеров]"
    : немой
      ? "  [ВЕДОМОСТИ НЕТ ВОВСЕ — про этот файл счёт не знает ничего]"
      : ""
  console.log(
    `${имя.padEnd(22)} высказано ${String(высказано).padStart(3)}  доказано ${String(доказанные.length).padStart(3)}` +
      `  содержательных ${String(содержательных).padStart(3)}  ослабленных ${String(ослабленных).padStart(3)}` +
      `  даровых ${даровых}  не проверено ${непроверенных}${отметка}`,
  )
}

