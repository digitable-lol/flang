/*
 * Второй слой: то, что добавляется к layer.c, когда программа не просто
 * считает, а СТРОИТ ТЕКСТ — то есть где-нибудь встречается «к строке» от
 * числа, «к числу», сравнение строк или разбор варианта по имени.
 *
 * Замер (nm -u, x86_64 Linux): чистое вычисление просит у libc 5 имён,
 * разбор /etc/fstab — 12. Семь добавившихся именно здесь:
 *   memset memcmp strcmp __errno_location strtol snprintf strtod
 *
 * Первые пять — по пять строк каждая. Вся цена сидит в последних двух, и
 * сидит она в ОДНОМ месте рантайма: fl_number_text переводит число в текст
 * по правилу ECMAScript Number::toString, а оно требует КРАТЧАЙШЕЙ записи,
 * которая читается обратно в то же самое число. Рантайм ищет её перебором
 * точности от 1 до 17, печатая «%.*e» и читая обратно strtod, — значит от
 * libc ему нужны обе половины задачи «double ↔ десятичная запись», и нужны
 * правильно округлёнными.
 *
 * ── ГРАНИЦА ЭТОГО ФАЙЛА, названная прямо ───────────────────────────────────
 * Здесь эта пара сделана ТОЛЬКО ДЛЯ ЦЕЛЫХ |v| ≤ 2^53, где десятичная запись
 * точна и считается целочисленной арифметикой. Этого хватает разбору fstab и
 * всякой программе, которая печатает счётчики. Этого НЕ хватает дробям:
 * общий случай — это задача Стила—Уайта (dtoa/Grisu/Ryu), отдельная работа
 * на тысячи строк с таблицами степеней десяти, и браться за неё здесь
 * незачем. Что происходит за границей — сказано в коде отказом, а не молча:
 * дробное значение уходит в NOT_INTEGER и печатается как «?».
 */
#include <stdarg.h>
#include <stddef.h>

#define POROG 9007199254740992.0 /* 2^53 */

/* ── пять мелких ─────────────────────────────────────────────────────────── */

void *memset(void *куда, int байт, size_t сколько) {
  unsigned char *к = (unsigned char *)куда;
  while (сколько--) *к++ = (unsigned char)байт;
  return куда;
}

int memcmp(const void *а, const void *б, size_t сколько) {
  const unsigned char *х = (const unsigned char *)а, *у = (const unsigned char *)б;
  while (сколько--) { if (*х != *у) return (int)*х - (int)*у; ++х; ++у; }
  return 0;
}

int strcmp(const char *а, const char *б) {
  while (*а && *а == *б) { ++а; ++б; }
  return (int)(unsigned char)*а - (int)(unsigned char)*б;
}

static int oshibka;
int *__errno_location(void) { return &oshibka; }

long strtol(const char *текст, char **конец, int основание) {
  long знак = 1, итог = 0;
  (void)основание; /* рантайм зовёт её только с 10 */
  while (*текст == ' ' || *текст == '\t') ++текст;
  if (*текст == '+' || *текст == '-') { if (*текст == '-') знак = -1; ++текст; }
  while (*текст >= '0' && *текст <= '9') { итог = итог * 10 + (*текст - '0'); ++текст; }
  if (конец) *конец = (char *)текст;
  return знак * итог;
}

/* ── целое из double, если оно там есть ──────────────────────────────────── */

static int celoe_iz(double значение, unsigned long long *куда) {
  unsigned long long ц;
  if (значение < 0.0 || значение >= POROG) return 0;
  ц = (unsigned long long)значение;
  if ((double)ц != значение) return 0;
  *куда = ц;
  return 1;
}

/* Десятичные цифры целого, старшая первой. Возвращает их число. */
static int cifry(unsigned long long ц, char *куда) {
  char обратно[24];
  int сколько = 0, i;
  if (ц == 0) { куда[0] = '0'; return 1; }
  while (ц) { обратно[сколько++] = (char)('0' + (ц % 10)); ц /= 10; }
  for (i = 0; i < сколько; ++i) куда[i] = обратно[сколько - 1 - i];
  return сколько;
}

/*
 * «%.*e» для целого: p цифр после точки, округление до чётного при ровной
 * половине — то же правило, что у printf на точной десятичной записи.
 */
static int kak_e(char *край, size_t место, int p, double значение) {
  char все[24], взято[32];
  unsigned long long ц;
  int всего, надо, перенос = 0, i, порядок, длина = 0;
  if (p < 0) p = 0;
  if (p > 24) p = 24;
  if (!celoe_iz(значение < 0 ? -значение : значение, &ц)) {
    if (место) край[0] = '?', край[1] = '\0';
    return 1; /* за границей файла — см. шапку */
  }
  всего = cifry(ц, все);
  порядок = всего - 1;
  надо = p + 1;
  for (i = 0; i < надо; ++i) взято[i] = (i < всего) ? все[i] : '0';
  if (надо < всего) {
    char следующая = все[надо];
    int больше_половины = следующая > '5';
    int ровно_половина = следующая == '5';
    if (ровно_половина) { for (i = надо + 1; i < всего; ++i) if (все[i] != '0') { больше_половины = 1; break; } }
    if (больше_половины || (ровно_половина && ((взято[надо - 1] - '0') % 2 == 1))) {
      for (i = надо - 1; i >= 0; --i) { if (взято[i] == '9') взято[i] = '0'; else { взято[i] += 1; break; } }
      if (i < 0) перенос = 1;
    }
  }
  if (перенос) { for (i = надо - 1; i > 0; --i) взято[i] = взято[i - 1]; взято[0] = '1'; порядок += 1; }
  if (значение < 0) край[длина++] = '-';
  край[длина++] = взято[0];
  if (p > 0) { край[длина++] = '.'; for (i = 1; i <= p; ++i) край[длина++] = взято[i]; }
  край[длина++] = 'e';
  край[длина++] = порядок < 0 ? '-' : '+';
  { int о = порядок < 0 ? -порядок : порядок;
    if (о < 10) край[длина++] = '0';
    длина += cifry((unsigned long long)о, край + длина); }
  край[длина] = '\0';
  (void)место;
  return длина;
}

/* ── strtod: обратная половина, точная в том же отрезке ──────────────────── */

double strtod(const char *текст, char **конец) {
  unsigned long long мантисса = 0;
  int цифр = 0, после_точки = 0, знак = 1, порядок = 0, i;
  double итог;
  while (*текст == ' ' || *текст == '\t' || *текст == '\n') ++текст;
  if (*текст == '+' || *текст == '-') { if (*текст == '-') знак = -1; ++текст; }
  while ((*текст >= '0' && *текст <= '9') || *текст == '.') {
    if (*текст == '.') { после_точки = 1; ++текст; continue; }
    if (цифр < 19) { мантисса = мантисса * 10 + (unsigned)(*текст - '0'); цифр += 1; if (после_точки) порядок -= 1; }
    else if (!после_точки) порядок += 1;
    ++текст;
  }
  if (*текст == 'e' || *текст == 'E') {
    char *после = (char *)0;
    порядок += (int)strtol(текст + 1, &после, 10);
    текст = после;
  }
  if (конец) *конец = (char *)текст;
  итог = (double)мантисса;
  /* Умножение и деление на 10 точны, пока и множитель, и итог целые в 2^53;
     дальше начинается общий случай, которого этот файл не берёт. */
  for (i = 0; i < порядок; ++i) итог *= 10.0;
  for (i = 0; i > порядок; --i) итог /= 10.0;
  return знак < 0 ? -итог : итог;
}

/* ── snprintf: «%.*e» плюс те же три подстановки, что в layer.c ───────────── */

int vsnprintf(char *край, size_t место, const char *формат, va_list доводы);

int snprintf(char *край, size_t место, const char *формат, ...) {
  va_list доводы;
  int итог;
  va_start(доводы, формат);
  if (формат[0] == '%' && формат[1] == '.' && формат[2] == '*' && формат[3] == 'e' && формат[4] == '\0') {
    int p = va_arg(доводы, int);
    итог = kak_e(край, место, p, va_arg(доводы, double));
  } else {
    итог = vsnprintf(край, место, формат, доводы);
  }
  va_end(доводы);
  return итог;
}
