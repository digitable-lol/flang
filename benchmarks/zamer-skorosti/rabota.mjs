/**
 * Замер времени РАБОТЫ: одна и та же задача на шести сборках.
 *
 *   flang              напечатанный C, собранный cc — как он выходит из коробки
 *   flang-без-шагов    он же, но счётчик шагов выключен ("steps":"0" в запросе:
 *                      рантайм понимает нулевой предел как «не считать»)
 *   flang-без-входа    сборка, где fl_enter/fl_leave вычеркнуты целиком —
 *                      ни шагов, ни глубины, ни сторожа стека
 *   эталон-c           те же четыре задачи, написанные на C руками
 *   python             python3
 *   node               node
 *
 * Меряется полное время процесса — от запуска до ответа, как его видит тот,
 * кто запускает программу. Разделять «запуск» и «счёт» здесь нечестно:
 * у собранного бинарника запуск почти бесплатен, а у Python и Node он стоит
 * заметных миллисекунд, и это их настоящее свойство. Отдельной строкой поэтому
 * меряется ПУСТАЯ задача каждого языка — сколько стоит просто запуститься.
 *
 * ── Про шум ────────────────────────────────────────────────────────────────
 * Машина занята другими работами, и это видно по разбросу. Поэтому:
 *   • сборки ЧЕРЕДУЮТСЯ внутри каждого круга, а не меряются блоками, — иначе
 *     всплеск нагрузки достался бы целиком одной из них;
 *   • приводится медиана, минимум и максимум, а не среднее: одно попадание в
 *     чужой всплеск сдвигает среднее и не сдвигает медиану.
 *
 * Запуск: node benchmarks/zamer-skorosti/rabota.mjs КАТАЛОГ-СБОРКИ [--кругов N]
 *         (каталог собирается скриптом sobrat.sh)
 */
import { spawnSync } from "node:child_process"
import { performance } from "node:perf_hooks"
import { fileURLToPath } from "node:url"

const программы = fileURLToPath(new URL("./programs/", import.meta.url))

const аргументы = process.argv.slice(2)
const сборка = аргументы[0]
if (сборка === undefined || сборка.startsWith("--")) {
  process.stderr.write("нужен каталог сборки: node rabota.mjs КАТАЛОГ [--кругов N] [--задача ИМЯ]\n")
  process.exit(2)
}
let кругов = 9
let толькоЗадача = null
for (let i = 1; i < аргументы.length; i += 1) {
  if (аргументы[i] === "--кругов") кругов = Number(аргументы[i + 1])
  if (аргументы[i] === "--задача") толькоЗадача = аргументы[i + 1]
}

/* Размеры подобраны так, чтобы самая быстрая из сборок считала заметно дольше
   собственного запуска: иначе замер мерил бы запуск, а не задачу. */
const ЗАДАЧИ = [
  { имя: "коллатц", размер: 50000, фн: "Коллатц" },
  { имя: "нод", размер: 300000, фн: "НОД обычный счёт" },
  { имя: "нод-доказанный", размер: 300000, фн: "НОД доказанный счёт", как: "нод" },
  { имя: "сортировка", размер: 100000, фн: "Сортировка обычная" },
  { имя: "сортировка-доказанная", размер: 100000, фн: "Сортировка доказанная", как: "сортировка" },
  { имя: "дерево", размер: 100000, фн: "Обход дерева" },
  { имя: "строки", размер: 18, фн: "Разбор строк" },
]

function прогон(команда, аргс, вход) {
  const т0 = performance.now()
  const итог = spawnSync(команда, аргс, {
    input: вход,
    encoding: "utf8",
    maxBuffer: 1 << 28,
    env: { ...process.env, LC_ALL: "C.UTF-8" },
  })
  const мс = performance.now() - т0
  if (итог.status !== 0) throw new Error(`${команда} ${аргс.join(" ")} → ${итог.status}: ${итог.stderr}`)
  return { мс, вывод: итог.stdout.trim() }
}

const запрос = (задача, добавка) =>
  `{"fn":"${задача.фн}","args":[{"n":"${задача.размер}"}]${добавка}}\n`

const сборки = {
  flang: (з) => прогон(`${сборка}/base/flang_cli`, ["--json"], запрос(з, "")),
  "flang-счёт-выключен": (з) => прогон(`${сборка}/base/flang_cli`, ["--json"], запрос(з, ',"steps":"0"')),
  "flang-без-счётчика": (з) => прогон(`${сборка}/bez-schetchika/flang_cli`, ["--json"], запрос(з, "")),
  "flang-без-пределов": (з) => прогон(`${сборка}/bez-vhoda/flang_cli`, ["--json"], запрос(з, "")),
  "flang-lto": (з) => прогон(`${сборка}/lto/flang_cli`, ["--json"], запрос(з, "")),
  "flang-lto-без-типов": (з) => прогон(`${сборка}/lto-bez-tipov/flang_cli`, ["--json"], запрос(з, "")),
  "эталон-c": (з) => прогон(`${сборка}/etalon`, [з.как ?? з.имя, String(з.размер)]),
  python: (з) => прогон("python3", [`${программы}zadachi.py`, з.как ?? з.имя, String(з.размер)]),
  node: (з) => прогон("node", [`${программы}zadachi.mjs`, з.как ?? з.имя, String(з.размер)]),
}

/** Пустая задача: сколько стоит просто запуститься и ничего не сделать. */
const пустые = {
  flang: () => прогон(`${сборка}/base/flang_cli`, ["--json"], "\n"),
  "эталон-c": () => прогон(`${сборка}/etalon`, ["коллатц", "0"]),
  python: () => прогон("python3", ["-c", "pass"]),
  node: () => прогон("node", ["-e", ""]),
}

function свод(значения) {
  const s = [...значения].sort((a, b) => a - b)
  const медиана = s.length % 2 === 1 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2
  return {
    медиана: Number(медиана.toFixed(1)),
    минимум: Number(s[0].toFixed(1)),
    максимум: Number(s[s.length - 1].toFixed(1)),
    прогонов: s.length,
  }
}

const итоги = {}
const ответы = {}

/* Прогрев: по одному прогону на каждую пару, чтобы файлы попали в кэш страниц.
   Его числа в свод не идут. */
for (const задача of ЗАДАЧИ) {
  if (толькоЗадача !== null && задача.имя !== толькоЗадача) continue
  for (const имя of Object.keys(сборки)) сборки[имя](задача)
}
for (const имя of Object.keys(пустые)) пустые[имя]()

for (let круг = 0; круг < кругов; круг += 1) {
  for (const имя of Object.keys(пустые)) {
    const { мс } = пустые[имя]()
    ;((итоги["ПУСТАЯ ЗАДАЧА"] ??= {})[имя] ??= []).push(мс)
  }
  for (const задача of ЗАДАЧИ) {
    if (толькоЗадача !== null && задача.имя !== толькоЗадача) continue
    const строка = (итоги[`${задача.имя} (${задача.размер})`] ??= {})
    for (const имя of Object.keys(сборки)) {
      const { мс, вывод } = сборки[имя](задача)
      ;(строка[имя] ??= []).push(мс)
      ответы[`${задача.имя}/${имя}`] = имя.startsWith("flang") ? JSON.parse(вывод).value.n : вывод
    }
  }
}

const вывод = {}
for (const [задача, сбор] of Object.entries(итоги)) {
  вывод[задача] = {}
  for (const [имя, значения] of Object.entries(сбор)) вывод[задача][имя] = свод(значения)
}

/* Все шесть сборок обязаны дать одно и то же число. Если не дали — замер
   сравнивал разные программы, и числа его недействительны. */
const расхождения = []
for (const задача of ЗАДАЧИ) {
  if (толькоЗадача !== null && задача.имя !== толькоЗадача) continue
  const набор = new Set(Object.keys(сборки).map((имя) => ответы[`${задача.имя}/${имя}`]))
  if (набор.size > 1) расхождения.push({ задача: задача.имя, ответы: [...набор] })
}

process.stdout.write(`${JSON.stringify({ кругов, расхождения, ответы, замеры: вывод }, null, 2)}\n`)
