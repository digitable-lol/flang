let итогТ = 0, итогД = 0, итогВТ = 0, итогВД = 0, итогПТ = 0, итогПД = 0
console.log("№  | строк тестов | строк док-ва | сек тестов | сек док-ва | попыток т/д")
for (const f of readdirSync(dir).filter((f) => f.endsWith(".flang")).sort()) {
  const н = f.slice(0, 2)
  const строки = readFileSync(dir + "/" + f, "utf8").split("\n")
  let вТестах = false, вТеореме = false, т = 0, д = 0
  for (const с of строки) {
    const голая = с.trim()
    if (голая.startsWith("// ── ТЕСТЫ")) { вТестах = true; continue }
    if (голая.startsWith("// ── КОНЕЦ ТЕСТОВ")) { вТестах = false; continue }
    if (голая.startsWith("//") || голая === "") { if (голая === "") вТеореме = false; continue }
    if (вТестах) { т++; continue }
    if (/^теорема\s/.test(с)) { вТеореме = true; д++; continue }
    if (вТеореме) { д++; continue }
    if (/^\s*(для всех .* обеспечивает|обеспечивает|требует)\s/.test(с)) { д++; continue }
  }
  т += ПРАВКИ[н]?.тесты ?? 0
  д += ПРАВКИ[н]?.док ?? 0
  const [вт, вд] = ВРЕМЯ[н], [пт, пд] = ПОПЫТКИ[н]
  console.log(
    н, "|", String(т).padStart(12), "|", String(д).padStart(12), "|",
    String(вт).padStart(10), "|", String(вд).padStart(10), "|", пт + "/" + пд,
  )
  итогТ += т; итогД += д; итогВТ += вт; итогВД += вд; итогПТ += пт; итогПД += пд
}
console.log("ИТОГО:", "строк тестов", итогТ, "| строк док-ва", итогД,
  "| сек тестов", итогВТ, "| сек док-ва", итогВД, "| попыток", итогПТ + "/" + итогПД)
console.log("на функцию: тесты", (итогТ / 20).toFixed(1), "строки /", (итогВТ / 20).toFixed(1), "с;",
  "док-во", (итогД / 20).toFixed(1), "строки /", (итогВД / 20).toFixed(1), "с")
