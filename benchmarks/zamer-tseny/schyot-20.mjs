/**
 * СЧЁТ ДВАДЦАТИ: сколько из двадцати функций замера доказано — и сколько из
 * доказанного что-то ЗНАЧИТ.
 *
 * ── Зачем этот счётчик, если число уже названо ──────────────────────────────
 *
 * Замер цены доказательства (`docs/benchmark-proof-cost-2.md`) назвал «2 из 20»
 * и сам же предупредил, чем это число опасно: **ядро закрывает тавтологию
 * бесплатно**. Постусловие `результат равен (0 минус х)` при теле `0 минус х`
 * сводится правилом тождества за один шаг, ведомость печатает «доказано обо
 * ВСЕХ входах», и цифру можно надуть до любого размера, переписав тело в
 * постусловие. Сырой счёт «сколько строк ведомости говорят „доказано“» поэтому
 * НЕ ОТВЕТ: сегодня он даёт девять, а честных среди них заметно меньше.
 *
 * Отделять содержательное от дарового СПИСКОМ ИМЁН нельзя — список ведёт рука,
 * а рука ошибается молча и в свою пользу. Здесь разделение делается ПРОГОНОМ, и
 * у него два вопроса, оба механические.
 *
 * ── Вопрос первый: не переписано ли тело в постусловие ──────────────────────
 *
 * ТАВТОЛОГИЯ — постусловие вида `результат равен Е`, где `Е` есть само тело
 * функции, знак в знак. Сравниваются деревья разбора без мест в исходнике.
 * Такое утверждение не ложно — оно просто не независимо: спецификация и есть
 * реализация, и проверять ей нечего.
 *
 * ── Вопрос второй: переживает ли утверждение ПОДМЕНУ ТЕЛА ───────────────────
 *
 * Это то же правило, по которому здесь проверяют всякую правку: снять её и
 * посмотреть, что покраснеет. Тело функции заменяется ЗАГЛУШКОЙ того же
 * объявленного типа (`0`, `""`, `нет`, `пустой список`), подпись и текст
 * утверждения остаются прежними, и ведомость считается заново.
 *
 *   утверждение и с заглушкой доказано  → ОСЛАБЛЕННОЕ: оно верно про любую
 *                                         функцию этой подписи и про ЭТУ не
 *                                         говорит ничего («длина результата
 *                                         неотрицательна» верно и для `""`);
 *   утверждение с заглушкой отпало      → СОДЕРЖАТЕЛЬНОЕ: оно отличает
 *                                         настоящее тело от подставного.
 *
 * ── Чего этот счёт не умеет, названо прямо ──────────────────────────────────
 *
 * Заглушка строится по объявленному типу результата, и типов у неё четыре. Если
 * функция возвращает объявленную сумму, запись или параметр типа, заглушки нет,
 * и такое утверждение помечается НЕ ПРОВЕРЕНО — а не записывается в
 * содержательные по умолчанию. Умолчание в пользу своей работы — ровно та
 * ошибка, ради которой счёт и заведён.
 *
 * ── ЧЕМ СЧИТАЕТСЯ, И ПОЧЕМУ ЭТО СМЕНИЛОСЬ ──────────────────────────────────
 *
 * До 20 августа счёт звал реализацию на JavaScript: разбор — `flang/src/parser.mjs`,
 * ведомость — `flang/bin/flang.mjs`. Ни того, ни другого в дереве больше нет:
 * компилятор один, двоичный. Обе двери переведены на него ровно так же, как у
 * свода ведомости (`flang/scripts/proof-ledger.mjs`): дерево спрашивается
 * командой `flang ast`, ведомость — командой `flang check --proof --json`.
 * Второго разбора языка здесь не заводится.
 *
 * Прогон:  LC_ALL=C.UTF-8 node benchmarks/zamer-tseny/schyot-20.mjs
 */
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { ведомость, дерево } from "../../flang/scripts/dvoichnyy.mjs"

const корень = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..")
const каталог = join(корень, "docs", "benchmark2")
const времянка = mkdtempSync(join(tmpdir(), "schyot-20-"))

/* ── ведомость одного файла ───────────────────────────────────────────────── */

/**
 * имя утверждения → вердикт ведомости: ДОКАЗАНО | СЕТКА | ОБЪЯВЛЕНО.
 *
 * Читается поле `verdict` у строки ведомости, а не строка вывода глазами.
 * Слов у вердикта шесть, и в три здешних они складываются так:
 *
 *   proved, proved-induction  → ДОКАЗАНО  (ядро закрыло цель обо ВСЕХ входах);
 *   grid                      → СЕТКА     (прогнано по значениям, не доказано);
 *   declared, refused, violated → ОБЪЯВЛЕНО (доказательства нет вовсе).
 *
 * Код возврата у `check` значащий, и ненулевой он здесь ЗАКОНЕН: файлы замера
 * краснеют нарочно — отвергнутая теорема оставлена в них уликой, а у функции 13
 * красный пример находит настоящую ошибку. Ведомость двоичный печатает и в
 * этом случае, если до неё дошёл, поэтому берётся она независимо от кода.
 */
function вердикты(путь) {
  const в = ведомость(путь)
  const итог = new Map()
  for (const запись of в.ведомость?.claims ?? []) {
    if (typeof запись?.name !== "string") continue
    итог.set(
      запись.name,
      запись.verdict === "proved" || запись.verdict === "proved-induction"
        ? "ДОКАЗАНО"
        : запись.verdict === "grid"
          ? "СЕТКА"
          : "ОБЪЯВЛЕНО",
    )
  }
  return итог
}

/* ── вопрос первый: тавтология ────────────────────────────────────────────── */

/** Дерево без мест в исходнике: место — не часть утверждения. */
function безМест(узел) {
  if (Array.isArray(узел)) return узел.map(безМест)
  if (узел === null || typeof узел !== "object") return узел
  const итог = {}
  for (const ключ of Object.keys(узел).sort()) {
    if (ключ === "span") continue
    итог[ключ] = безМест(узел[ключ])
  }
  return итог
}

const РЕЗУЛЬТАТ = (у) => у?.kind === "var" && у.name === "результат"

function тавтология(постусловие, тело) {
  const в = постусловие.expr
  if (в?.kind !== "binary" || в.op !== "eq") return false
  const другая = РЕЗУЛЬТАТ(в.left) ? в.right : РЕЗУЛЬТАТ(в.right) ? в.left : null
  if (другая === null) return false
  return JSON.stringify(безМест(другая)) === JSON.stringify(безМест(тело))
}

/* ── вопрос второй: подмена тела заглушкой ────────────────────────────────── */

const ЗАГЛУШКИ = new Map([
  ["number", "0"], ["string", '""'], ["flag", "нет"], ["list", "пустой список"],
  ["nat", "0"], ["integer", "0"], ["weight", "0"], ["cost", "0"],
])

/* Заглушка нужна ОТЛИЧНАЯ от настоящего тела и годная по типу. Объявленная
   сумма, запись и параметр типа сюда не попадают: собрать их значение можно
   только зная объявление, и угадывать его счётчик не будет. */
function заглушка(тип) {
  if (тип?.kind === "named") return ЗАГЛУШКИ.get(тип.name) ?? null
  return ЗАГЛУШКИ.get(тип?.kind) ?? null
}

/**
 * Границы тела в исходнике: от строки тела до следующего объявления.
 *
 * Тело у функции стоит последним, а всякое объявление начинается с первой
 * колонки — этим и мерится конец. Комментарий первой колонки телом тоже не
 * бывает, поэтому он кончает тело так же, как объявление.
 */
function границыТела(строки, первая) {
  let конец = строки.length
  for (let и = первая; и < строки.length; и += 1) {
    if (/^\S/.test(строки[и])) { конец = и; break }
  }
  while (конец > первая && строки[конец - 1].trim() === "") конец -= 1
  return конец
}

function сЗаглушкой(исходник, функция, текстЗаглушки) {
  const строки = исходник.split("\n")
  const первая = функция.body.span.line - 1
  const конец = границыТела(строки, первая)
  return [...строки.slice(0, первая), "  " + текстЗаглушки, ...строки.slice(конец)].join("\n")
}

/**
 * Тот же файл БЕЗ примеров.
 *
 * Примеры в этих файлах описывают НАСТОЯЩЕЕ поведение функции, поэтому у файла
 * с подменённым телом они краснеют все разом, оболочка обрывается на первом же
 * и до ведомости не доходит. Без снятия примеров подмена «сломала» бы любое
 * утверждение без разбора — и счёт записал бы в содержательные всё подряд, то
 * есть польстил бы работе ровно там, где её и надо проверять.
 *
 * Снимаются они у ОБОИХ файлов — и у настоящего, и у подменённого, — чтобы
 * сравнивалось равное с равным. Если утверждение при этом перестало
 * доказываться и у настоящего файла, значит его несли примеры (`по примеру`), и
 * такой случай помечается отдельно, а не считается ни за то, ни за другое.
 */
function безПримеров(исходник) {
  const строки = исходник.split("\n")
  const итог = []
  for (let и = 0; и < строки.length; и += 1) {
    /* Граница слова `\\b` здесь не годится: она определена по латинскому `\\w`, а
       после «пример» стоит кириллица — перехода «слово → не слово» нет, и
       выражение не срабатывает вовсе. Поэтому граница пишется явно. */
    const отступ = /^(\s*)(пример|example)(?:\s|$)/.exec(строки[и])
    if (отступ === null) { итог.push(строки[и]); continue }
    const глубина = отступ[1].length
    и += 1
    while (и < строки.length) {
      const строка = строки[и]
      const свой = /^\s*/.exec(строка)[0].length
      if (строка.trim() !== "" && свой <= глубина) break
      и += 1
    }
    и -= 1
  }
  return итог.join("\n")
}

/* ── счёт ─────────────────────────────────────────────────────────────────── */

const файлы = readdirSync(каталог).filter((и) => /^\d\d-.*\.flang$/.test(и)).sort()
const счёт = { содержательных: 0, ослабленных: 0, даровых: 0, непроверенных: 0 }
const пофайлам = []
/* Имя временного файла НЕ ПОВТОРЯЕТСЯ, и это не украшение. `ведомость` из
   `dvoichnyy.mjs` помнит ответ ПО ПУТИ: подмена тела второй функции того же
   файла, легшая по тому же имени, получила бы вердикт первой. Счётчик снимает
   это целиком. */
let счётчикВремянок = 0
const врем = (имя, текст) => {
  счётчикВремянок += 1
  const п = join(времянка, `${счётчикВремянок}-${имя}`)
  writeFileSync(п, текст)
  return п
}

for (const имя of файлы) {
  const путь = join(каталог, имя)
  const исходник = readFileSync(путь, "utf8")
  const д = дерево(путь)
  if (!д.ok) {
    console.log(имя.padEnd(34), "дерева нет:", д.why)
    continue
  }
  const какЕсть = вердикты(путь)
  const голый = вердикты(врем("golyy-" + имя, безПримеров(исходник)))
  const строки = []
  let лучшее = null

  for (const функция of д.дерево.functions ?? []) {
    for (const постусловие of функция.postconditions ?? []) {
      /* Вердикт берётся у файла как он есть; если оболочка оборвалась на
         красном примере и ведомости нет вовсе — у того же файла без примеров.
         Красный пример это НАСТОЯЩАЯ ошибка библиотеки (функция 13), и терять
         из-за неё вердикт ядра значило бы мерить не то. */
      const оборвалось = какЕсть.size === 0
      const вердикт = какЕсть.get(постусловие.name) ?? (оборвалось ? голый.get(постусловие.name) : undefined)
      if (вердикт !== "ДОКАЗАНО") continue
      let вид
      if (тавтология(постусловие, функция.body)) {
        вид = "ДАРОВОЕ (тело переписано в постусловие)"
      } else if (голый.get(постусловие.name) !== "ДОКАЗАНО") {
        вид = "НЕ ПРОВЕРЕНО (доказательство несут примеры, подмену не сравнить)"
      } else {
        const текст = заглушка(функция.returns)
        if (текст === null) {
          вид = "НЕ ПРОВЕРЕНО (заглушки для этого типа результата нет)"
        } else {
          const подменённый = врем("zaglushka-" + имя, безПримеров(сЗаглушкой(исходник, функция, текст)))
          вид = вердикты(подменённый).get(постусловие.name) === "ДОКАЗАНО"
            ? `ОСЛАБЛЕННОЕ (доказано и при теле «${текст}»)`
            : `СОДЕРЖАТЕЛЬНОЕ (при теле «${текст}» отпадает)`
        }
      }
      строки.push(`      «${постусловие.name}» — ${вид}` + (оборвалось ? "  [примеры файла красные]" : ""))
      const вес = вид.startsWith("СОДЕРЖАТЕЛЬНОЕ") ? 3 : вид.startsWith("НЕ ПРОВЕРЕНО") ? 2 : 1
      if (лучшее === null || вес > лучшее.вес) лучшее = { вес, вид }
      if (вид.startsWith("СОДЕРЖАТЕЛЬНОЕ")) счёт.содержательных += 1
      else if (вид.startsWith("ОСЛАБЛЕННОЕ")) счёт.ослабленных += 1
      else if (вид.startsWith("ДАРОВОЕ")) счёт.даровых += 1
      else счёт.непроверенных += 1
    }
  }

  пофайлам.push({ имя, лучшее })
  console.log(имя.padEnd(34), лучшее === null ? "не доказано ничего" : "доказано")
  for (const с of строки) console.log(с)
}

const доказано = пофайлам.filter((ф) => ф.лучшее !== null).length
const содержательно = пофайлам.filter((ф) => ф.лучшее?.вид.startsWith("СОДЕРЖАТЕЛЬНОЕ")).length
const непроверено = пофайлам.filter((ф) => ф.лучшее?.вид.startsWith("НЕ ПРОВЕРЕНО")).length

console.log("")
console.log("── по функциям (мера замера) ──")
console.log("  доказано хоть что-нибудь:", доказано, "из", файлы.length)
console.log("  из них СОДЕРЖАТЕЛЬНО:   ", содержательно, "из", файлы.length)
console.log("  из них не проверено:    ", непроверено)
console.log("── по утверждениям ──")
console.log("  содержательных:", счёт.содержательных, " ослабленных:", счёт.ослабленных,
  " даровых:", счёт.даровых, " не проверено:", счёт.непроверенных)

/* За собой убрано: сторож временных каталогов (`npm run tmp:check`) считает
   оставленное, и оставлять здесь нечего — подменённые файлы нужны ровно на один
   прогон оболочки. */
rmSync(времянка, { recursive: true, force: true })
