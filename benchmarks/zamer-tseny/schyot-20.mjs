/* СЧЁТ ДВАДЦАТИ: сколько из двадцати функций замера доказано СЕГОДНЯ.
 *
 * Замер (`docs/benchmark-proof-cost-2.md`) назвал число «2 из 20» словами и
 * двумя командами. Словами число не пересчитать: чтобы сказать «стало N из 20»
 * после правки языка, нужен прогон, который сам читает ведомость каждого из
 * двадцати файлов и складывает. Это он.
 *
 * Считается ровно то, что печатает ведомость `flang check --proof`:
 *   ДОКАЗАНО   — строка «доказано» у постусловия, то есть «обо ВСЕХ входах»;
 *   СЕТКА      — «на сетке»: прогнали по значениям, это не доказательство;
 *   ОБЪЯВЛЕНО  — «объявлено, не доказано»: ядру не хватило правил;
 *   ОТКАЗ      — файл не проходит проверку вовсе (в файле оставлена улика).
 *
 * Отдельным столбцом — ДАРОВОЕ против СОДЕРЖАТЕЛЬНОГО. Даровым считается
 * утверждение, чей текст дословно переписывает тело функции (тавтология вида
 * «результат равен <тело>»): ядро закрывает его правилом тождества за один шаг,
 * и о функции оно не говорит ничего. Список даровых ведётся здесь ИМЕНАМИ и
 * руками — угадать тавтологию машиной значит завести ещё одно место, где можно
 * ошибиться молча.
 *
 * Прогон:  LC_ALL=C.UTF-8 node benchmarks/zamer-tseny/schyot-20.mjs
 */
import { execFileSync } from "node:child_process"
import { readdirSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const корень = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..")
const каталог = join(корень, "docs", "benchmark2")

/* Даровые: постусловие дословно переписывает тело. Число из отчёта замера. */
const ДАРОВЫЕ = new Set([
  "05-protivopolozhnoe.flang", // «результат равен (0 минус х)» при теле `0 минус х`
])
/* Ослабленные заглушки: закрываются, но о функции не говорят (тоже из отчёта). */
const ОСЛАБЛЕННЫЕ = new Set([
  "01-klyuch-svyazi.flang",
  "02-klyuch-zvena.flang",
  "07-vstavit-po.flang",
])

const файлы = readdirSync(каталог).filter((и) => /^\d\d-.*\.flang$/.test(и)).sort()

function ведомость(путь) {
  try {
    return execFileSync(
      process.execPath,
      [join(корень, "flang", "bin", "flang.mjs"), "check", путь, "--proof", "--pretty"],
      { encoding: "utf8", env: { ...process.env, LC_ALL: "C.UTF-8" }, maxBuffer: 1 << 26 },
    )
  } catch (беда) {
    return (беда.stdout ?? "") + (беда.stderr ?? "")
  }
}

const счёт = { доказано: 0, сетка: 0, объявлено: 0, отказ: 0 }
const доказанные = []
for (const имя of файлы) {
  const текст = ведомость(join(каталог, имя))
  const строки = текст.split("\n")
  const начало = строки.findIndex((с) => с.includes("что высказано и чем это несётся"))
  const конец = строки.findIndex((с, и) => и > начало && с.trim() === "")
  const утверждения = начало < 0 ? [] : строки.slice(начало + 1, конец < 0 ? строки.length : конец)
  const есть = (что) => утверждения.some((с) => с.includes(что))
  let исход
  if (начало < 0) исход = "ОТКАЗ"
  else if (есть("— доказано")) исход = "ДОКАЗАНО"
  else if (есть("на сетке")) исход = "СЕТКА"
  else if (утверждения.length > 0) исход = "ОБЪЯВЛЕНО"
  else исход = "ОТКАЗ"
  if (исход === "ДОКАЗАНО") {
    счёт.доказано += 1
    доказанные.push(имя)
  } else if (исход === "СЕТКА") счёт.сетка += 1
  else if (исход === "ОБЪЯВЛЕНО") счёт.объявлено += 1
  else счёт.отказ += 1
  const метка = исход !== "ДОКАЗАНО" ? "" : ДАРОВЫЕ.has(имя) ? "  (даровое)" : ОСЛАБЛЕННЫЕ.has(имя) ? "  (ослабленное)" : "  (содержательное)"
  console.log(имя.padEnd(34), исход.padEnd(10) + метка)
}

const даром = доказанные.filter((и) => ДАРОВЫЕ.has(и)).length
const слабо = доказанные.filter((и) => ОСЛАБЛЕННЫЕ.has(и)).length
console.log("")
console.log("ДОКАЗАНО:", счёт.доказано, "из", файлы.length)
console.log("  из них содержательных:", счёт.доказано - даром - слабо, "; ослабленных:", слабо, "; даровых:", даром)
console.log("сетка:", счёт.сетка, " объявлено, не доказано:", счёт.объявлено, " отказ проверки:", счёт.отказ)
