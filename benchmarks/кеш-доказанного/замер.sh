#!/usr/bin/env bash
# Один замер прибором: ключ каждого обязательства (и, если попросить, его цена).
#
#   bash замер.sh <семя> <файл.flang> <куда-класть> [цена|ключи]
#
#     ключи — по умолчанию: неподвижная точка идёт, приговоры есть, цена целого
#             прогона не считается;
#     цена  — ещё и «Закрыть без теорем» целиком плюс повтор при кеше. Вдвое
#             дольше;
#     без-ядра — ядро не зовётся вовсе: одни ключи, приговор «-». Так и только
#             так по карману замыкание компилятора.
#
# ОТПЕЧАТОК ПРОВЕРЯЛЬЩИКА СНИМАЕТ САМ ПРИБОР — читает /proc/self/exe. Снаружи
# его больше не задают, и это правка Ч351: у Ч183 он приезжал переменной среды
# как sha256 четырёх файлов ЯДРА В ДЕРЕВЕ, а дерево и двоичный — разные вещи.
# Проба-ядром.sh на том и стоит: дерево побайтово одно, двоичных два, приговоров
# разошлось 49 из 103.
set -u
export LC_ALL=C.UTF-8
semya=${1:?семя}
vhod=${2:?файл}
kuda=${3:?куда}
chto=${4:-ключи}

case "$chto" in
  цена) rezhim="FLANG_KESH_TSENA=1" ;;
  без-ядра) rezhim="FLANG_KESH_TOLKO_KLYUCHI=1" ;;
  ключи) rezhim="" ;;
  *) echo "звать: bash замер.sh <семя> <файл> <куда> [ключи|цена|без-ядра]" >&2; exit 2 ;;
esac

env FLANG_KESH=1 FLANG_KESH_ONLY=1 $rezhim \
  "$semya/flang" check "$vhod" > /dev/null 2> "$kuda"
kod=$?
echo "замер: $vhod, режим «$chto», код возврата $kod"
/usr/bin/grep -a -v '^ОБЯЗ' "$kuda"
exit "$kod"
