# -*- coding: utf-8 -*-
"""Ключи кеша приговоров — по ИСХОДНИКАМ дерева, без прогона ядра.

Зачем не прибором: прогон прибора по замыканию компилятора требует разобрать
45 файлов на каждом из 30 коммитов, а машина общая. Здесь ключ считается по
ТЕКСТУ — быстро и без единого прогона.

ОГОВОРКА Ч183 ЗДЕСЬ СНЯТА. Ч183 писала: «это ВЕРХНЯЯ оценка попаданий, столько
кеш попал бы, если бы места из ключа убрали; нижнюю даёт прибор». Места из
ключа Ч351 УБРАНЫ (прибор.c, отличие А; замерено проба-местами.sh: полный ключ
совпал у 4 из 4 при сдвиге всех строк на одну). Значит верхняя и нижняя оценки
сошлись в одну, и это число — оценка ТОГО ЖЕ ключа, который считает прибор.

Что здесь ВСЁ ЕЩЁ приблизительно, и в какую сторону:
  • рёбра вызовов берутся по вхождению имени в ёлочках, а не разбором. Лишнее
    ребро — ЗАВЫШЕННОЕ замыкание, то есть заниженная доля попаданий: ошибка в
    безопасную сторону;
  • список НЕОПЛАЧЕННЫХ предусловий заменён признаком «есть ли `требует` вообще»:
    кто кому не заплатил, знает только проверяльщик. Это единственное место, где
    оценка может оказаться ВЫШЕ правды.

Ключ складывается из:
  • текста объявления самой функции (тело, подпись, постусловия, предусловия);
  • текстов ВСЕХ функций замыкания вызовов — их разворачивает нормализация
    («Развернуть телом», flang/self/proof-kernel.flang:1873) и с них берутся
    факты по вызову (flang/self/proofterm.flang:2455);
  • объявлений типов — по ним порождается принцип индукции;
  • объявлений законов — ПЯТИ видов, тех самых, что читает «Есть закон»
    (flang/self/proofterm.flang:228): моноид, монада, изоморфизм, вложение,
    пересечение. У Ч183 этот список был ПУСТ (переменная заводилась и не
    заполнялась ни разу), то есть законы в ключ не входили вовсе;
  • признака «есть неснятые предусловия»;
  • отпечатка ЯДРА — двоичного, которым проверяют.

Печатает по строке на обязательство:
    ОБЯЗ<таб>файл<таб>функция<таб>имя<таб>полный<таб>наивный<таб>размер замыкания
"""
import hashlib
import os
import re
import sys

НАЧАЛА = ('тотальная функция ', 'функция ', 'объект ', 'тип ', 'модуль ', 'теорема ',
          'моноид ', 'монада ', 'изоморфизм ', 'вложение ', 'пересечение ')
# Пять видов законов — те, что читает «Есть закон» (proofterm.flang:228).
ЗАКОНЫ = ('моноид', 'монада', 'изоморфизм', 'вложение', 'пересечение')
ИМЯ = re.compile(r'«([^»]*)»')


def читать(корень, файл):
    п = os.path.join(корень, файл)
    try:
        return open(п, encoding='utf-8', errors='replace').read()
    except OSError:
        return None


def замыкание_файлов(корень, вход):
    файлы = []
    for dp, dn, fn in os.walk(os.path.join(корень, 'flang')):
        for f in fn:
            if f.endswith('.flang') or f.endswith('.fp') or f.endswith('.фп') or f.endswith('.фланг'):
                файлы.append(os.path.relpath(os.path.join(dp, f), корень))
    файлы.sort()
    модуль_в = {}
    ввозы = {}
    пути = {}
    for f in файлы:
        текст = читать(корень, f)
        if текст is None:
            continue
        ввозы[f] = []
        пути[f] = []
        назван = False
        for строка in текст.split('\n'):
            if not назван:
                m = re.match(r'^модуль «([^»]*)»', строка)
                if m:
                    назван = True
                    модуль_в.setdefault(m.group(1), f)
                    continue
            m = re.match(r'^ *использует «([^»]*)»', строка)
            if m:
                ввозы[f].append(m.group(1))
                m2 = re.search(r'из *"([^"]*)"', строка)
                if m2:
                    пути[f].append(m2.group(1))
    видели = set()
    очередь = [вход]
    while очередь:
        f = очередь.pop(0)
        if f in видели:
            continue
        видели.add(f)
        if f not in ввозы:
            continue
        каталог = os.path.dirname(f) or '.'
        for p in пути[f]:
            очередь.append(p if p.startswith('/') else os.path.normpath(os.path.join(каталог, p)))
        for имя in ввозы[f]:
            if имя in модуль_в:
                очередь.append(модуль_в[имя])
    return sorted(видели)


def разбить(текст):
    """Верхние объявления файла: (вид, имя, строки без комментариев)."""
    блоки = []
    текущий = None
    for строка in текст.split('\n'):
        если_верх = строка.startswith(НАЧАЛА)
        if если_верх:
            вид = строка.split(' ', 1)[0]
            if вид == 'тотальная':
                вид = 'функция'
            m = ИМЯ.search(строка)
            текущий = [вид, m.group(1) if m else '', []]
            блоки.append(текущий)
        if текущий is None:
            continue
        # Комментарии ядру не видны вовсе: разбор их выбрасывает. Их правка
        # приговора не меняет, и в ключе им места нет.
        голая = строка.lstrip()
        if голая.startswith('//'):
            continue
        if голая == '':
            continue
        текущий[2].append(строка)
    return блоки


def хеш(*части):
    h = hashlib.sha256()
    for ч in части:
        h.update(ч.encode('utf-8') if isinstance(ч, str) else ч)
        h.update(b'\x00')
    return h.hexdigest()[:16]


def главное():
    корень = sys.argv[1]
    вход = sys.argv[2]
    отпечаток_ядра = sys.argv[3] if len(sys.argv) > 3 else 'ядро-не-названо'
    файлы = замыкание_файлов(корень, вход)
    sys.stderr.write('замыкание: %d файлов\n' % len(файлы))

    функции = {}       # имя → (файл, текст)
    типы = []
    законы = []
    есть_требует = False
    теоремы = set()
    for f in файлы:
        текст = читать(корень, f)
        if текст is None:
            continue
        for вид, имя, строки in разбить(текст):
            тело = '\n'.join(строки)
            if вид == 'функция':
                функции[имя] = (f, тело)
                if re.search(r'^ *требует ', тело, re.M):
                    есть_требует = True
            elif вид in ('объект', 'тип'):
                типы.append(тело)
            elif вид in ЗАКОНЫ:
                законы.append(тело)
            elif вид == 'теорема':
                теоремы.add(имя)
    общее = хеш(отпечаток_ядра, '\n'.join(типы), '\n'.join(законы), 'требует=%s' % есть_требует)
    sys.stderr.write('функций %d, типов %d, теорем %d, общая часть %s\n'
                     % (len(функции), len(типы), len(теоремы), общее))

    рёбра = {}
    for имя, (f, тело) in функции.items():
        рёбра[имя] = sorted({н for н in ИМЯ.findall(тело) if н in функции and н != имя})
    хеши = {имя: хеш(тело) for имя, (f, тело) in функции.items()}

    напечатано = 0
    for имя in sorted(функции):
        f, тело = функции[имя]
        свои = re.findall(r'^ *(?:для всех .*? )?обеспечивает «([^»]*)»', тело, re.M)
        if not свои:
            continue
        видели = set()
        очередь = [имя]
        while очередь:
            к = очередь.pop(0)
            if к in видели:
                continue
            видели.add(к)
            очередь.extend(рёбра.get(к, ()))
        замык = хеш(*[хеши[к] for к in sorted(видели)])
        for пост in свои:
            полный = хеш(общее, имя, пост, замык)
            наивный = хеш(имя, пост, хеши[имя])
            print('ОБЯЗ\t%s\t%s\t%s\t%s\t%s\t%d\t%d'
                  % (f, имя, пост, полный, наивный, len(видели), 1 if пост in теоремы else 0))
            напечатано += 1
    sys.stderr.write('обязательств %d\n' % напечатано)


главное()
