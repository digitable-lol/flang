#!/usr/bin/env bash
# ПОРЧЕНОЕ СЕМЯ для пробы ядром: тот же прибор, то же дерево, но ОДНО ПРАВИЛО
# ЯДРА переписано — «Предел ветвления» с 4 на 0 (flang/self/proof-kernel.flang:6800).
# Это правило, а не оформление: им ограничено ветвление при сведении цели.
#
# Правится СГЕНЕРИРОВАННЫЙ C в копии семени, а не дерево исходников: правка в
# flang/self доехала бы до двоичного только перепечаткой компилятора самим собой
# — часы на прогон. Своё дерево исходников не трогается ни одной строкой, и это
# ровно то, что проба и проверяет: дерево одно, проверяльщики разные.
#
# КОДЫ ВОЗВРАТА: 0 — семя собрано и порча применена; 3 — порча НЕ применилась
# (значит опыт ставить нечем).
#
#   bash порченое-семя.sh <куда-класть-семя>
set -e
export LC_ALL=C.UTF-8
here=$(cd "$(dirname "$0")" && pwd)
semya=${1:?куда класть семя}

bash "$here/встроить.sh" "$semya"

python3 - "$semya" <<'ПИТОН'
import sys

путь = sys.argv[1] + '/compiler_flang.c'
исходник = open(путь, encoding='utf-8').read()
якорь = ('fl_status compiler_flang_predel_vetvleniya(fl_ctx *ctx, fl_value *result, fl_error *error) {\n'
         '  (void)ctx;\n'
         '  (void)error;\n'
         '  *result = fl_number(4.0);\n')
if исходник.count(якорь) != 1:
    sys.stderr.write('ПОРЧА НЕ ПРИМЕНЕНА: якорь «Предел ветвления» встречается %d раз\n'
                     % исходник.count(якорь))
    sys.exit(3)
open(путь, 'w', encoding='utf-8').write(исходник.replace(якорь, якорь.replace('4.0', '0.0'), 1))
sys.stderr.write('порча применена: «Предел ветвления» 4 → 0\n')
ПИТОН

make -C "$semya" -j8
"$semya/flang" --version
echo "порченое семя готово: $semya"
