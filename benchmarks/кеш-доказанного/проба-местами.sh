#!/usr/bin/env bash
# ПРОБА МЕСТАМИ — ОГОВОРКА Ч183, ЗАКРЫТАЯ ЗАМЕРОМ.
#
# Ч183 замерила: одна пустая строка вверху файла — приговоры все до одного те
# же, ключи все до одного ИНЫЕ (4 из 4). Кеш с таким ключом не попал бы никогда.
# Просто выбросить места нельзя: кешированный отказ назовёт устаревшую строку.
#
# Проба спрашивает ТРИ вещи, и по отдельности:
#
#   1. КЛЮЧ НЕ ЗАВИСИТ ОТ МЕСТ. Полный ключ Ч351 обязан совпасть побайтово у
#      всех обязательств; ключ «с местами» (тот, что считала Ч183) обязан
#      разойтись у всех — иначе опыт не поставлен.
#   2. ПРИГОВОРЫ ОТ СДВИГА НЕ МЕНЯЮТСЯ — спрашивается у самого ядра. Если бы
#      менялись, места были бы частью правил, и выбрасывать их было бы ложью.
#   3. МЕСТО В ОТКАЗЕ СТОИТ СНАРУЖИ ТЕКСТА. Отказ ядра печатается как
#      «КОД в файле Ф, строка N, столбец M: текст». Съезжает N; ТЕКСТ обязан
#      остаться побайтово тем же. Тогда хранить отказ надо БЕЗ поля `span`, а
#      место приписывать при чтении — из сегодняшнего узла обязательства.
#
# Оба дерева лежат в РАЗНЫХ каталогах под ОДНИМ именем файла: иначе разошлось бы
# не место, а имя, и опыт мерил бы не то.
#
# ЧТО ЛЕЖИТ В `проба-места.flang`. Нарочно и то, и другое: обязательства БЕЗ
# теоремы (по ним прибор печатает ключи) и теорема, которую ядро ОТВЕРГАЕТ —
# «по предположению» стоит в базе «Пусто», где предположения индукции нет. Отказ
# ядра несёт место, и на нём проверяется, что в самом ТЕКСТЕ отказа места нет.
# Объяснение стоит здесь, а не в .flang: в .flang комментариев не пишут
# (scripts/no-comments-guard.sh, правило — .claude/skills/flang-code).
#
# КОДЫ ВОЗВРАТА: 0 — все три ответа как надо; 1 — ключ от сдвига поехал, либо
# приговор изменился, либо место влезло в текст отказа; 3 — опыт не поставлен
# (сдвиг не применился, прибор сорвался, ключ «с местами» не разошёлся).
#
#   bash проба-местами.sh <семя> <куда>
set -u
export LC_ALL=C.UTF-8
semya=${1:?семя}
kuda=${2:?куда}
here=$(cd "$(dirname "$0")" && pwd)
rm -rf "$kuda"
mkdir -p "$kuda/tsel" "$kuda/sdvig"
# ПУТИ АБСОЛЮТНЫМИ: замер идёт из каталога дерева, и относительный путь до семени
# или до вывода указал бы оттуда не туда.
semya=$(cd "$semya" && pwd)
kuda=$(cd "$kuda" && pwd)

for f in проба.flang проба-места.flang; do
  cp "$here/$f" "$kuda/tsel/$f"
  python3 - "$here/$f" "$kuda/sdvig/$f" <<'ПИТОН'
import sys
строки = open(sys.argv[1], encoding='utf-8').read().split('\n')
строки.insert(1, '')
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(строки))
ПИТОН
done

echo "── сдвиг применён? ──"
for f in проба.flang проба-места.flang; do
  if cmp -s "$kuda/tsel/$f" "$kuda/sdvig/$f"; then
    echo "  $f: СДВИГ НИЧЕГО НЕ СДВИНУЛ — опыт не поставлен"
    exit 3
  fi
  echo "  $f: строк было $(wc -l < "$kuda/tsel/$f"), стало $(wc -l < "$kuda/sdvig/$f")"
done

zamer() {  # <дерево> <метка>
  derevo=$1
  metka=$2
  ( cd "$kuda/$derevo" && FLANG_KESH=1 FLANG_KESH_ONLY=1 \
      "$semya/flang" check проба.flang > /dev/null 2> "$kuda/$metka.klyuchi" )
  kod=$?
  ( cd "$kuda/$derevo" && "$semya/flang" check проба.flang --proof > "$kuda/$metka.vedomost" 2>&1 )
  kod2=$?
  ( cd "$kuda/$derevo" && "$semya/flang" check проба-места.flang > "$kuda/$metka.otkaz" 2>&1 )
  kod3=$?
  /usr/bin/grep -a '^ОБЯЗ' "$kuda/$metka.klyuchi" | LC_ALL=C sort > "$kuda/$metka.oblig"
  echo "  «$metka»: ключи код $kod, ведомость код $kod2, отказ код $kod3, обязательств $(wc -l < "$kuda/$metka.oblig")"
  if /usr/bin/grep -a -q 'ПРИБОР СОРВАЛСЯ\|НЕ ПОЛОН\|НЕ СНЯТ' "$kuda/$metka.klyuchi"; then
    echo "  ПРИБОР СОРВАЛСЯ — замер «$metka» не годится"
    return 3
  fi
  return 0
}

echo
echo "── замеры ──"
zamer tsel tsel || exit 3
zamer sdvig sdvig || exit 3

echo
echo "── 1 и 2: ключи и приговоры ──"
python3 - "$kuda/tsel.oblig" "$kuda/sdvig.oblig" <<'ПИТОН'
import sys

КЛЮЧИ = [('полный', 7), ('наивный', 8), ('по дереву', 9),
         ('с местами', 10), ('без замыкания', 11)]


def читать(путь):
    вышло = {}
    for строка in open(путь, encoding='utf-8'):
        поля = строка.rstrip('\n').split('\t')
        вышло[(поля[1], поля[2])] = поля
    return вышло


а = читать(sys.argv[1])
б = читать(sys.argv[2])
общие = sorted(set(а) & set(б))
if not общие:
    print('  ОБЯЗАТЕЛЬСТВ НЕТ — опыт не поставлен')
    sys.exit(3)
приговор_сменился = [к for к in общие if а[к][3] != б[к][3]]
for к in общие:
    print('  %-18s %-38s приговор %s→%s  полный %s  с местами %s' % (
        к[0], к[1], а[к][3], б[к][3],
        'ТОТ ЖЕ' if а[к][7] == б[к][7] else 'ИНОЙ',
        'ТОТ ЖЕ' if а[к][10] == б[к][10] else 'иной'))
print('  сличений %d, приговор изменился у %d' % (len(общие), len(приговор_сменился)))
print('  %-16s %9s %9s' % ('КЛЮЧ', 'совпал', 'разошёлся'))
итог = 0
for имя, столбец in КЛЮЧИ:
    совпал = [к for к in общие if а[к][столбец] == б[к][столбец]]
    print('  %-16s %9d %9d' % (имя, len(совпал), len(общие) - len(совпал)))
    if имя == 'полный' and len(совпал) != len(общие):
        print('    ОТКАЗ: полный ключ поехал от сдвига строк — кеш не попадёт никогда')
        итог = 1
    if имя == 'с местами' and совпал:
        print('    ОПЫТ НЕ ПОСТАВЛЕН: ключ «с местами» обязан разойтись у всех, а совпал у %d'
              % len(совпал))
        итог = 3
if приговор_сменился:
    print('    ОТКАЗ: приговор изменился от сдвига строк у %d — места ЧАСТЬ ПРАВИЛ'
          % len(приговор_сменился))
    итог = 1
sys.exit(итог)
ПИТОН
kod=$?
itog=$kod

echo
echo "── ведомость: побайтовое сличение ──"
if cmp -s "$kuda/tsel.vedomost" "$kuda/sdvig.vedomost"; then
  echo "  ведомость от сдвига НЕ изменилась ни байтом ($(wc -c < "$kuda/tsel.vedomost") байт)"
else
  echo "  ведомость изменилась:"
  diff "$kuda/tsel.vedomost" "$kuda/sdvig.vedomost" | head -20 | sed 's/^/    /'
  itog=1
fi

echo
echo "── 3: место в отказе — снаружи текста или внутри ──"
cat "$kuda/tsel.otkaz" | sed 's/^/  цел:   /'
cat "$kuda/sdvig.otkaz" | sed 's/^/  сдвиг: /'
python3 - "$kuda/tsel.otkaz" "$kuda/sdvig.otkaz" <<'ПИТОН'
import re
import sys

МЕСТО = re.compile(r'^(?P<код>[A-Z_0-9]+) в файле (?P<файл>[^,]+), строка (?P<строка>\d+), '
                   r'столбец (?P<столбец>\d+): (?P<текст>.*)$')


def отказы(путь):
    вышло = []
    for строка in open(путь, encoding='utf-8'):
        м = МЕСТО.match(строка.rstrip('\n'))
        if м:
            вышло.append(м.groupdict())
    return вышло


а = отказы(sys.argv[1])
б = отказы(sys.argv[2])
if not а or len(а) != len(б):
    print('  ОТКАЗОВ С МЕСТОМ НЕТ ЛИБО РАЗНОЕ ЧИСЛО (%d и %d) — опыт не поставлен' % (len(а), len(б)))
    sys.exit(3)
итог = 0
for ра, рб in zip(а, б):
    съехало = int(рб['строка']) - int(ра['строка'])
    текст_тот_же = ра['текст'] == рб['текст']
    print('  %s: строка %s → %s (съехала на %+d), код %s, текст %s' % (
        ра['код'], ра['строка'], рб['строка'], съехало,
        'тот же' if ра['код'] == рб['код'] else 'ИНОЙ',
        'ТОТ ЖЕ побайтово (%d байт)' % len(ра['текст'].encode('utf-8'))
        if текст_тот_же else 'ИЗМЕНИЛСЯ'))
    if not текст_тот_же:
        print('    ОТКАЗ: место сидит ВНУТРИ текста отказа — хранить отказ без места нельзя')
        итог = 1
    if съехало != 1:
        print('    ОПЫТ НЕ ПОСТАВЛЕН: строка обязана съехать ровно на 1, а съехала на %d' % съехало)
        итог = 3
if итог == 0:
    print('  ВЫВОД: место стоит СНАРУЖИ текста отказа. Значит отказ хранится без поля `span`,')
    print('  а место приписывается при чтении из кеша — из сегодняшнего узла обязательства')
    print('  («Первое непустое» от постусловия и функции, flang/self/obligations.flang:228).')
sys.exit(итог)
ПИТОН
kod=$?
if [ "$kod" != 0 ]; then itog=$kod; fi

echo
echo "══ итог пробы местами: $itog ══"
exit "$itog"
