#!/usr/bin/env bash
# ПРОБА НА ПРОМАХ: каждая зависимость доказательства портится ПО ОДНОЙ, и с
# каждой спрашивается три ответа, снятых НЕЗАВИСИМО друг от друга:
#
#   1. ПОРЧА СЛУЧИЛАСЬ — файл правда изменился, и изменилась ровно одна
#      названная строка (`git diff --numstat`). Порча, которая ничего не
#      испортила, выглядит как успех — docs/zettel/a-sabotage-test-that-
#      sabotages-nothing-looks-like-success.md;
#   2. ПРИГОВОР ИЗМЕНИЛСЯ — ядро на испорченном дереве закрывает НЕ ТО, что
#      закрывало. Спрашивается у самого ядра, а не у ключа;
#   3. КЛЮЧ ИЗМЕНИЛСЯ — полный ключ обязан промахнуться. Рядом считаются
#      ПОДДЕЛКИ ключа, по одной на выброшенную составляющую: каждая показывает,
#      какой именно кеш отдал бы «доказано» на то, что уже не доказано.
#
# ЧТО СЧИТАЕТСЯ И ЧЕМ ЭТО РАЗНОЕ:
#   ЛОЖНОЕ ДОКАЗАТЕЛЬСТВО — приговор изменился, а ключ ТОТ ЖЕ. Кеш отдаст
#     «доказано» на недоказанное. Это отказ ключа, и он один делает пробу
#     красной.
#   ПРОМАХ НАПРАСНЫЙ — приговор НЕ изменился, а ключ иной. Кеш промахнётся зря:
#     это цена, а не ложь. Считается отдельно, потому что путать цену с ложью —
#     ровно та ошибка, из-за которой из ключа выбрасывают составляющие.
#
# ЧТО ЛЕЖИТ В `проба.flang`. Четыре функции, у каждой доказательство с
# зависимостью ЗА ПРЕДЕЛАМИ собственного текста — ровно то, чего не заметит кеш,
# чей ключ считает только свой текст:
#   «Двойной вес» стоит на ПОСТУСЛОВИИ «Вес мешка» (порча П1 — тело вызванной);
#   «Вес мешка» стоит на том, что поле объявлено `нат` (П2 — объявление типа);
#   «Через половину» стоит на снятом `требует` «Половины» (П3 — предусловие).
# Объяснение стоит здесь, а не в самом .flang: в .flang комментариев не пишут
# (scripts/no-comments-guard.sh, правило — .claude/skills/flang-code).
#
# Порча правится ПО НОМЕРУ СТРОКИ, а не по первому вхождению образца.
#
# Отпечаток проверяльщика прибор снимает САМ (/proc/self/exe), и снаружи его
# задавать не надо: у Ч183 он приезжал переменной среды, и забыть его было
# можно — цена забывчивости измерена в проба-ядром.sh.
#
# КОДЫ ВОЗВРАТА: 0 — ложных доказательств у полного ключа нет ни одного (так и
# должно быть); 1 — НАЙДЕНО ЛОЖНОЕ ДОКАЗАТЕЛЬСТВО у полного ключа; 3 — порча не
# применилась, то есть опыт НЕ ПРОВЕДЁН (не «зелено»).
#
#   bash проба-на-промах.sh <семя> <куда-складывать>
set -u
export LC_ALL=C.UTF-8
semya=${1:?семя}
kuda=${2:?куда}
here=$(cd "$(dirname "$0")" && pwd)
proba="$here/проба.flang"
mkdir -p "$kuda"

zamer() {  # <метка>
  metka=$1
  FLANG_KESH=1 FLANG_KESH_ONLY=1 \
    "$semya/flang" check "$proba" > /dev/null 2> "$kuda/$metka.klyuchi"
  kod=$?
  "$semya/flang" check "$proba" --proof > "$kuda/$metka.vedomost" 2>&1
  kod2=$?
  /usr/bin/grep -a '^ОБЯЗ' "$kuda/$metka.klyuchi" | LC_ALL=C sort > "$kuda/$metka.oblig"
  echo "  замер «$metka»: ключи код $kod, ведомость код $kod2, обязательств $(wc -l < "$kuda/$metka.oblig")"
  if /usr/bin/grep -a -q 'ПРИБОР СОРВАЛСЯ\|НЕ ПОЛОН\|НЕ СНЯТ' "$kuda/$metka.klyuchi"; then
    echo "  ПРИБОР СОРВАЛСЯ — замер «$metka» не годится"
    /usr/bin/grep -a 'ПРИБОР СОРВАЛСЯ\|НЕ ПОЛОН\|НЕ СНЯТ' "$kuda/$metka.klyuchi" | sed 's/^/    /'
    return 3
  fi
  return 0
}

sravnit() {  # <метка>
  metka=$1
  python3 - "$kuda/osnova.oblig" "$kuda/$metka.oblig" <<'ПИТОН'
import sys

# Столбцы прибора: 7 полный, 8 наивный, 9 по дереву (без отпечатка),
# 10 с местами (ключ Ч183), 11 без замыкания.
КЛЮЧИ = [('полный', 7), ('наивный', 8), ('по дереву', 9),
         ('с местами', 10), ('без замыкания', 11)]


def читать(путь):
    вышло = {}
    for строка in open(путь, encoding='utf-8'):
        поля = строка.rstrip('\n').split('\t')
        вышло[(поля[1], поля[2])] = поля
    return вышло


а = читать(sys.argv[1])
б = читать(sys.argv[2])
общие = sorted(set(а) & set(б))
пропало = sorted(set(а) ^ set(б))
for к in пропало:
    print('  %-18s %-38s ПОЯВИЛОСЬ/ПРОПАЛО' % (к[0], к[1]))

сменился = [к for к in общие if а[к][3] != б[к][3]]
for к in общие:
    print('  %-18s %-38s приговор %s→%s  полный %s' % (
        к[0], к[1], а[к][3], б[к][3],
        'ТОТ ЖЕ (промаха нет)' if а[к][7] == б[к][7] else 'ИНОЙ (промах)'))
print('  сличений %d, приговор изменился у %d' % (len(общие), len(сменился)))
print('  %-16s %9s %9s %9s' % ('КЛЮЧ', 'ложных', 'напрасных', 'промахов'))
ложных_у_полного = 0
for имя, столбец in КЛЮЧИ:
    ложных = [к for к in общие if а[к][3] != б[к][3] and а[к][столбец] == б[к][столбец]]
    напрасных = [к for к in общие if а[к][3] == б[к][3] and а[к][столбец] != б[к][столбец]]
    промахов = [к for к in общие if а[к][столбец] != б[к][столбец]]
    print('  %-16s %9d %9d %9d' % (имя, len(ложных), len(напрасных), len(промахов)))
    if имя == 'полный':
        ложных_у_полного = len(ложных)
    for к in ложных:
        print('    ЛОЖНОЕ ДОКАЗАТЕЛЬСТВО (%s): «%s»/«%s» — приговор изменился, ключ нет'
              % (имя, к[0], к[1]))
sys.exit(1 if ложных_у_полного else 0)
ПИТОН
}

isportit() {  # <номер строки> <новая строка> <что ждали в старой>
  nomer=$1
  novaya=$2
  zhdali=$3
  bylo=$(sed -n "${nomer}p" "$proba")
  case "$bylo" in
    *"$zhdali"*) ;;
    *) echo "  ПОРЧА НЕ ПРИМЕНЕНА: в строке $nomer нет «$zhdali», там «$bylo»"; return 3 ;;
  esac
  cp "$proba" "$kuda/цел.flang"
  python3 - "$proba" "$nomer" "$novaya" <<'ПИТОН'
import sys
p, n, s = sys.argv[1], int(sys.argv[2]), sys.argv[3]
lines = open(p, encoding='utf-8').read().split('\n')
lines[n - 1] = s
open(p, 'w', encoding='utf-8').write('\n'.join(lines))
ПИТОН
  if cmp -s "$proba" "$kuda/цел.flang"; then
    echo "  ПОРЧА НИЧЕГО НЕ ИСПОРТИЛА: файл побайтово тот же"
    return 3
  fi
  izmeneno=$(diff "$kuda/цел.flang" "$proba" | /usr/bin/grep -a -c '^[<>]')
  echo "  порча в строке $nomer применена, изменённых строк в diff: $izmeneno"
  return 0
}

vernut() {
  cp "$kuda/цел.flang" "$proba"
}

echo "══ основа (ничего не испорчено) ══"
zamer osnova
kod=$?
if [ "$kod" != 0 ]; then echo "══ итог пробы: 3 ══"; exit 3; fi
/usr/bin/grep -a 'постусловие' "$kuda/osnova.vedomost" | sed 's/^/  /'

itog=0

echo
echo "══ П1: испорчено ТЕЛО ВЫЗВАННОЙ («Вес мешка», строка 16) ══"
if isportit 16 '      то (гиря минус 1)' 'то гиря'; then
  zamer p1
  sravnit p1 || itog=1
  vernut
else
  itog=3
fi

echo
echo "══ П2: испорчено ОБЪЯВЛЕНИЕ ТИПА («Мешок», строка 5) ══"
if isportit 5 '  вариант «Полный» содержит вес: число' 'вес: нат'; then
  zamer p2
  sravnit p2 || itog=1
  vernut
else
  itog=3
fi

echo
echo "══ П3: испорчено ПРЕДУСЛОВИЕ ВЫЗВАННОЙ («Вес мешка», строка 10) ══"
if isportit 10 '  требует «мешок дан» 0 больше 100' 'требует «мешок дан»'; then
  zamer p3
  sravnit p3 || itog=1
  vernut
else
  itog=3
fi

echo
echo "══ итог пробы: $itog ══"
echo "  (сдвиг мест — отдельной пробой, проба-местами.sh: там он обязан НЕ менять ключа)"
exit "$itog"
