#!/usr/bin/env bash
# ПРОБА ПОВТОРА: ключ на НЕИЗМЕННОМ дереве, снятый дважды подряд, обязан совпасть
# ПОБАЙТОВО. Иначе кеш не попадёт никогда, и вся работа впустую — это условие
# сильнее всех прочих: ключ, зависящий от чего-то, кроме дерева и проверяльщика
# (адреса в памяти, порядок обхода, время), выглядит правильным на каждой пробе
# на промах и не даёт ни одного попадания.
#
# Сличаются ВСЕ пять столбцов ключей и приговор, строка в строку.
#
# КОДЫ ВОЗВРАТА: 0 — совпало побайтово; 1 — РАЗОШЛОСЬ; 3 — прибор сорвался.
#
#   bash проба-повтора.sh <семя> <вход.flang> <куда> [сколько прогонов]
set -u
export LC_ALL=C.UTF-8
semya=${1:?семя}
vhod=${2:?вход}
kuda=${3:?куда}
skolko=${4:-2}
mkdir -p "$kuda"

echo "── дерево ──"
sha256sum "$vhod" | sed 's/^/  /'

i=1
while [ "$i" -le "$skolko" ]; do
  FLANG_KESH=1 FLANG_KESH_ONLY=1 "$semya/flang" check "$vhod" > /dev/null 2> "$kuda/progon-$i.out"
  kod=$?
  /usr/bin/grep -a '^ОБЯЗ' "$kuda/progon-$i.out" > "$kuda/progon-$i.oblig"
  echo "  прогон $i: код $kod, обязательств $(wc -l < "$kuda/progon-$i.oblig")"
  if /usr/bin/grep -a -q 'ПРИБОР СОРВАЛСЯ\|НЕ ПОЛОН\|НЕ СНЯТ' "$kuda/progon-$i.out"; then
    echo "  ПРИБОР СОРВАЛСЯ — опыт не поставлен"
    exit 3
  fi
  i=$((i + 1))
done

if [ ! -s "$kuda/progon-1.oblig" ]; then
  echo "  ОБЯЗАТЕЛЬСТВ НЕТ — сличать нечего"
  exit 3
fi

# СЛИЧАЮТСЯ КЛЮЧИ И ПРИГОВОР, А НЕ ВЕСЬ ВЫВОД. Столбцы 4 (шагов) и 5 (попыток)
# — это ЦЕНА, и она замерена невоспроизводимой: `repl_ctx.steps` расходится
# между прогонами того же дерева на единицы шагов из миллионов. Ключа это не
# касается — он в столбцах 7—11, — но валить цену и ключ в один `cmp` значило бы
# красить пробу ключа за дрожание секундомера.
itog=0
i=2
while [ "$i" -le "$skolko" ]; do
  cut -f1,2,3,4,7,8,9,10,11,12 "$kuda/progon-1.oblig" > "$kuda/klyuchi-1.tsv"
  cut -f1,2,3,4,7,8,9,10,11,12 "$kuda/progon-$i.oblig" > "$kuda/klyuchi-$i.tsv"
  if cmp -s "$kuda/klyuchi-1.tsv" "$kuda/klyuchi-$i.tsv"; then
    echo "  прогон 1 и прогон $i: КЛЮЧИ И ПРИГОВОРЫ СОВПАЛИ побайтово ($(wc -c < "$kuda/klyuchi-1.tsv") байт, $(wc -l < "$kuda/klyuchi-1.tsv") строк)"
  else
    echo "  прогон 1 и прогон $i: КЛЮЧИ РАЗОШЛИСЬ"
    diff "$kuda/klyuchi-1.tsv" "$kuda/klyuchi-$i.tsv" | head -10 | sed 's/^/    /'
    itog=1
  fi
  i=$((i + 1))
done

echo "── цена (столбец «шагов»): воспроизводима ли ──"
python3 - "$kuda" "$skolko" <<'ПИТОН'
import os
import sys

kuda, сколько = sys.argv[1], int(sys.argv[2])


def читать(н):
    вышло = {}
    for строка in open(os.path.join(kuda, 'progon-%d.oblig' % н), encoding='utf-8'):
        поля = строка.rstrip('\n').split('\t')
        вышло[(поля[1], поля[2])] = int(поля[4])
    return вышло


первый = читать(1)
разошлось = 0
худшее = 0.0
худшая_пара = None
всего_шагов = sum(первый.values())
for н in range(2, сколько + 1):
    другой = читать(н)
    for к in первый:
        а = первый[к]
        б = другой.get(к)
        if б is None or а == б:
            continue
        разошлось += 1
        доля = abs(а - б) / float(max(а, 1))
        if доля > худшее:
            худшее = доля
            худшая_пара = (к, а, б)
print('  шагов всего на прогон: %d, обязательств %d' % (всего_шагов, len(первый)))
print('  строк, где счётчик шагов разошёлся между прогонами: %d' % разошлось)
if худшая_пара:
    (к, а, б) = худшая_пара
    print('  худшее расхождение: «%s»/«%s» — %d против %d (%.6f %%)'
          % (к[0], к[1], а, б, 100.0 * худшее))
    print('  ЦЕНА НЕВОСПРОИЗВОДИМА ДО ШАГА. Ключа это не касается, но числа цены')
    print('  надо называть с этой оговоркой.')
else:
    print('  счётчик шагов совпал у всех — цена воспроизводима до шага')
ПИТОН

echo "══ итог пробы повтора: $itog ══"
exit "$itog"
