#!/usr/bin/env bash
# ПРОБА ЯДРОМ — ПОРЧА ПРАВИЛА ПРОВЕРЯЛЬЩИКА. Дерево исходников НЕ ТРОГАЕТСЯ ни
# байтом; меняется ПРОВЕРЯЛЬЩИК: в копии семени «Предел ветвления»
# (flang/self/proof-kernel.flang:6800) переписан с 4 на 0 (порченое-семя.sh).
# Это правило ядра, а не оформление: им ограничено ветвление при сведении цели.
#
# Спрашивается ровно одно: меняются ли ПРИГОВОРЫ при неизменном дереве, и что на
# это отвечают два ключа:
#
#   ПОЛНЫЙ (столбец 7) — с отпечатком ПРОВЕРЯЛЬЩИКА, снятым с двоичного
#     (/proc/self/exe). Он обязан РАЗОЙТИСЬ у всех обязательств, чьи приговоры
#     это затронуло. Совпал хоть у одного из затронутых — кеш солгал бы, и это
#     красный ответ.
#   ПО ДЕРЕВУ (столбец 9) — тот же ключ БЕЗ отпечатка, то есть кеш, считающий
#     ключ только по исходникам. Он обязан СОВПАСТЬ у всех — тем и показано,
#     сколько ложных доказательств стоила бы забытая девятая составляющая.
#
# Заодно печатается «Версия ядра» (flang/self/proofterm.flang:73): годится ли
# она отпечатком правил. Ч183 замерила, что нет — там версия ФОРМАТА термов.
#
# КОДЫ ВОЗВРАТА: 0 — полный ключ разошёлся всюду, где сменился приговор (кеш не
# солгал бы); 1 — ПОЛНЫЙ КЛЮЧ ОТДАЛ БЫ ЛОЖНОЕ ДОКАЗАТЕЛЬСТВО; 3 — опыт не
# поставлен: дерево разное, приборы сорвались, либо приговоры не разошлись
# вовсе и мерить нечего.
#
#   bash проба-ядром.sh <целое-семя> <порченое-семя> <вход.flang> <куда>
set -u
export LC_ALL=C.UTF-8
tseloe=${1:?целое семя}
porchenoe=${2:?порченое семя}
vhod=${3:?вход}
kuda=${4:?куда}
mkdir -p "$kuda"

echo "── дерево одно и то же на оба прогона ──"
sha256sum "$vhod" | sed 's/^/  /'

for s in "$tseloe" "$porchenoe"; do
  metka=$(basename "$s")
  FLANG_KESH=1 FLANG_KESH_ONLY=1 \
    "$s/flang" check "$vhod" > /dev/null 2> "$kuda/yadro-$metka.klyuchi"
  kod=$?
  "$s/flang" check "$vhod" --proof --json > "$kuda/yadro-$metka.vedomost" 2>&1
  kod2=$?
  /usr/bin/grep -a '^ОБЯЗ' "$kuda/yadro-$metka.klyuchi" | LC_ALL=C sort > "$kuda/yadro-$metka.oblig"
  echo "  «$metka»: ключи код $kod, ведомость код $kod2, обязательств $(wc -l < "$kuda/yadro-$metka.oblig")"
  if /usr/bin/grep -a -q 'ПРИБОР СОРВАЛСЯ\|НЕ ПОЛОН\|НЕ СНЯТ' "$kuda/yadro-$metka.klyuchi"; then
    echo "  ПРИБОР СОРВАЛСЯ — опыт не поставлен"
    /usr/bin/grep -a 'ПРИБОР СОРВАЛСЯ\|НЕ ПОЛОН\|НЕ СНЯТ' "$kuda/yadro-$metka.klyuchi" | sed 's/^/    /'
    exit 3
  fi
done

echo "── отпечаток проверяльщика, снятый каждым двоичным с самого себя ──"
for s in "$tseloe" "$porchenoe"; do
  metka=$(basename "$s")
  /usr/bin/grep -a 'отпечаток проверяльщика' "$kuda/yadro-$metka.klyuchi" | sed "s/^/  $metka: /"
done

echo "── «Версия ядра», как её печатает каждый двоичный ──"
for s in "$tseloe" "$porchenoe"; do
  metka=$(basename "$s")
  echo "  $metka: $(/usr/bin/grep -a -o '"kernel":[0-9]*' "$kuda/yadro-$metka.vedomost" | head -1)"
done

python3 - "$kuda" "$(basename "$tseloe")" "$(basename "$porchenoe")" <<'ПИТОН'
import os
import sys

kuda, метка_а, метка_б = sys.argv[1], sys.argv[2], sys.argv[3]


def читать(метка):
    вышло = {}
    for строка in open(os.path.join(kuda, 'yadro-%s.oblig' % метка), encoding='utf-8'):
        поля = строка.rstrip('\n').split('\t')
        вышло[(поля[1], поля[2])] = поля
    return вышло


а, б = читать(метка_а), читать(метка_б)
общие = sorted(set(а) & set(б))
пропало = sorted(set(а) ^ set(б))
for к in пропало:
    print('  %-24s %-44s ПОЯВИЛОСЬ/ПРОПАЛО' % к)

сменился = [к for к in общие if а[к][3] != б[к][3]]
for к in общие:
    if а[к][3] != б[к][3]:
        print('  %-24s %-44s приговор %s→%s  полный %s  по дереву %s' % (
            к[0], к[1], а[к][3], б[к][3],
            'ИНОЙ' if а[к][7] != б[к][7] else 'ТОТ ЖЕ',
            'ТОТ ЖЕ' if а[к][9] == б[к][9] else 'иной'))
полный_совпал = [к for к in общие if а[к][7] == б[к][7]]
derevo_совпал = [к for к in общие if а[к][9] == б[к][9]]
ложных_полного = [к for к in сменился if а[к][7] == б[к][7]]
ложных_дерева = [к for к in сменился if а[к][9] == б[к][9]]
print('  ИТОГ: обязательств %d, приговор изменился у %d' % (len(общие), len(сменился)))
print('  %-16s %9s %11s' % ('КЛЮЧ', 'совпал', 'ЛОЖНЫХ'))
print('  %-16s %9d %11d' % ('полный', len(полный_совпал), len(ложных_полного)))
print('  %-16s %9d %11d' % ('по дереву', len(derevo_совпал), len(ложных_дерева)))
if not сменился:
    print('  ОПЫТ НЕ ПОСТАВЛЕН: приговоры не разошлись, порча правила ничего не изменила')
    sys.exit(3)
if ложных_полного:
    print('  ЛОЖНОЕ ДОКАЗАТЕЛЬСТВО у ПОЛНОГО ключа — %d штук. Отпечаток проверяльщика не работает.'
          % len(ложных_полного))
    sys.exit(1)
if ложных_дерева:
    print('  ЦЕНА ДЕВЯТОЙ СОСТАВЛЯЮЩЕЙ: кеш, чей ключ считан ТОЛЬКО по дереву, отдал бы')
    print('  %d ложных доказательства из %d на первой же пересборке проверяльщика.'
          % (len(ложных_дерева), len(общие)))
print('  Полный ключ разошёлся у всех %d затронутых — кеш промахнётся, а не солжёт.' % len(сменился))
sys.exit(0)
ПИТОН
