// Клиент VS Code к языковому серверу flang.
//
// ── Почему здесь вообще JavaScript ──────────────────────────────────────────
// В этом дереве на JavaScript ничего нового не пишут. Здесь исключение, и оно
// не про удобство, а про устройство самого VS Code: точка входа расширения —
// модуль, который редактор загружает в свой процесс Node, и другого способа
// подключиться у него нет. Плата названа и удерживается: файл целиком ниже,
// и в нём нет ни одного знания о языке.
//
// ── Что здесь НЕ делается и почему ──────────────────────────────────────────
// Ни разбора, ни подсказок, ни диагностики. Всё это умеет сервер (`flang lsp`),
// написанный на самом flang; расширение только запускает его и передаёт слова
// протокола. Подсветка тоже не отсюда: она в `syntaxes/flang.tmLanguage.json`,
// и тот файл напечатан из таблицы ключевых слов языка.
//
// Списка мест, где искать сервер, здесь тоже НЕТ, и это нарочно. Такой список
// живёт в `editors/vim/autoload/flang.vim` — пять мест по порядку, с
// объяснением, почему двоичный сервер сегодня не первый. Вторая копия списка
// разошлась бы с первой в первый же день, а разойдясь — молча: человек видел
// бы «сервер не найден» в одном редакторе и рабочие подсказки в другом.
// Поэтому здесь одна команда, и её можно поменять настройкой
// `flang.server.command`.

const vscode = require("vscode")
const { LanguageClient, TransportKind } = require("vscode-languageclient/node")

let клиент

exports.activate = () => {
  const настройки = vscode.workspace.getConfiguration("flang")
  if (настройки.get("server.enabled", true) === false) return

  клиент = new LanguageClient(
    "flang",
    "flang",
    {
      command: настройки.get("server.command", "flang-lsp"),
      args: настройки.get("server.args", ["--stdio"]),
      transport: TransportKind.stdio,
    },
    { documentSelector: [{ scheme: "file", language: "flang" }] },
  )
  return клиент.start()
}

exports.deactivate = () => клиент?.stop()
