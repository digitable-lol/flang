/**
 * Строка происхождения — одна на страницу, ставит её сборка.
 *
 * Что в ней есть: версия документации (она же версия выпуска), коммит дерева и
 * дата. Чего в ней нет: рассказа о том, когда агент что-то мерил. Числа
 * страницы сняты на ЭТОМ дереве и никаким другим быть не могут — за это
 * отвечает `./ярлык числа:проверка`, и сказано это один раз на отдельной
 * странице, а не на каждой.
 */
function происхождениеСтроки(с, сл) {
  const части = [`${сл.документация} ${ВЕРСИЯ}`];
  if (ПРОИСХОЖДЕНИЕ.дерево) {
    // «Сбоку от ствола» называется вслух, «на стволе» — нет: подвал говорит о
    // необычном, а обычное молчит. Неизвестное (ствола в клоне не нашлось) тоже
    // молчит: сказать «сбоку» там, где не смотрели, — та же ложь наоборот.
    const где = ПРОИСХОЖДЕНИЕ.наСтволе === false ? ` (${сл.внеСтвола})` : '';
    части.push(`${сл.дерево} <code>${ПРОИСХОЖДЕНИЕ.дерево}</code>${где} ${сл.от} ${ПРОИСХОЖДЕНИЕ.дата}`);
  } else {
    части.push(сл.безДерева);
  }
  части.push(`${сл.собрано} ${СОБРАНО}`);
  return части.join(' · ');
}

