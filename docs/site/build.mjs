#!/usr/bin/env node
// Сборка сайта документации flang.
//
//   node docs/site/build.mjs            собрать в docs/site/out
//   node docs/site/build.mjs --check    собрать и проверить ссылки, не записывая
//
// Зависимостей нет ни одной — намеренно. В этой среде `node_modules` ставится
// не всегда, и сайт, который не собирается без интернета, бесполезен ровно
// тогда, когда нужен.
//
// ── Двуязычность ────────────────────────────────────────────────────────────
// Уклад взят у руководства, где он уже работает: `имя.md` — английский текст,
// `имя.ru.md` — русский. Русская страница встаёт по своему адресу, английская —
// по `en/<имя английского файла>.html`. Второй объявляющей строки нет: пара
// выводится из имени файла, потому что два списка разъезжаются, а один — нет.
//
// Сторож здесь, а не отдельным скриптом, ровно потому, что сайт уже собирается
// в CI: вторая версия протухала за неделю, пока её никто не сторожил.
//
// Сборка ОТКАЗЫВАЕТ, а не предупреждает, если: исходного файла нет; ссылка ведёт
// в никуда; заметка базы знаний не вписана в указатель. Молчаливое ухудшение —
// то, ради чего этот проект вообще существует.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync, copyFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

import { разобрать, экранировать } from './markdown.mjs';
import { подставить, прочитатьЧисла } from './numbers.mjs';
import { собратьУказатель, печатьУказателя } from './poisk.mjs';
import { проверитьПоиск, проверитьОкно, ЖДЁМ } from './poisk-proverka.mjs';
import { РАЗДЕЛЫ, БАЗА_ЗНАНИЙ, ПРИМЕРЫ_НА_ГЛАВНОЙ, ПЕРЕЕЗДЫ, ПЕРЕЕЗДЫ_ЗАМЕТОК } from './sitemap.mjs';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ВЫХОД = join(КОРЕНЬ, 'docs', 'site', 'out');
const ТОЛЬКО_ПРОВЕРКА = process.argv.includes('--check');

const беды = [];
const читать = (путь) => {
  const полный = join(КОРЕНЬ, путь);
  if (!existsSync(полный)) {
    беды.push(`нет исходного файла: ${путь}`);
    return null;
  }
  return readFileSync(полный, 'utf8');
};

// ── Версия документации и происхождение страницы ────────────────────────────
// Читателю про страницу нужно знать ровно две вещи: к какой версии языка она
// относится и на каком дереве сняты её числа. Обе ставит СБОРКА — руками их не
// написать и, что важнее, не забыть обновить. До этого страницы вели дневник
// («обе правки сделаны 16 августа»), и дневник этот устаревал молча.
const числа = прочитатьЧисла();
const ВЕРСИЯ = числа['выпуск.версия'];

/**
 * Коммит и дата дерева. Без git — не беда: сборка обязана работать в выгрузке
 * (`git archive`), где `.git` нет вовсе. Тогда строка происхождения честно
 * говорит, что дерева не назвала, вместо того чтобы назвать неверное.
 */
function происхождение() {
  const гит = (доводы) =>
    execFileSync('git', доводы, { cwd: КОРЕНЬ, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  try {
    return { дерево: гит(['rev-parse', '--short', 'HEAD']), дата: гит(['log', '-1', '--format=%cd', '--date=short']) };
  } catch {
    return { дерево: null, дата: null };
  }
}
const ПРОИСХОЖДЕНИЕ = происхождение();
/** Дата сборки. ISO, а не прописью: это отметка машины, а не фраза прозы. */
const СОБРАНО = new Date().toISOString().slice(0, 10);

// ── Заголовок страницы берётся из первого заголовка первого уровня ──────────
const первыйЗаголовок = (текст) => {
  const м = /^#\s+(.+)$/m.exec(текст || '');
  return м ? м[1].trim().replace(/`/g, '') : null;
};

// ── Сбор страниц ────────────────────────────────────────────────────────────
const страницы = [];

for (const раздел of РАЗДЕЛЫ) {
  for (const с of раздел.страницы) {
    const исходник = читать(с.из);
    if (исходник === null) continue;
    страницы.push({ ...с, раздел: раздел.имя, исходник });
  }
}

// ── Английские половины ─────────────────────────────────────────────────────
// `docs/guide/limits.ru.md` → `docs/guide/limits.md` → `en/limits.html`.
const английскийИсточник = (из) => (из && из.endsWith('.ru.md') ? из.slice(0, -'.ru.md'.length) + '.md' : null);
const СВОИ = 'docs/site/';

for (const с of [...страницы]) {
  const англ = английскийИсточник(с.из);
  // `печатается` — страница из печати. Её перевод обязан приходить из печати же.
  const обязана = с.из.startsWith(СВОИ) && !с.печатается;
  if (!англ || !existsSync(join(КОРЕНЬ, англ))) {
    if (обязана) беды.push(`нет английской пары у страницы сайта: ${с.из} (ждали ${англ ?? с.из.replace(/\.md$/u, '.ru.md')})`);
    continue;
  }
  const английский = {
    адрес: `en/${basename(англ, '.md')}.html`,
    имя: null,
    раздел: с.раздел,
    из: англ,
    исходник: readFileSync(join(КОРЕНЬ, англ), 'utf8'),
    язык: 'en',
  };
  с.язык = 'ru';
  с.пара = английский.адрес;
  английский.пара = с.адрес;
  страницы.push(английский);
}

// База знаний: указатель плюс страница на каждую заметку
const заметки = [];
{
  const каталог = join(КОРЕНЬ, БАЗА_ЗНАНИЙ.каталог);
  if (!existsSync(каталог)) {
    беды.push(`нет каталога базы знаний: ${БАЗА_ЗНАНИЙ.каталог}`);
  } else {
    const указатель = читать(БАЗА_ЗНАНИЙ.указатель);
    if (указатель !== null) {
      страницы.push({
        адрес: БАЗА_ЗНАНИЙ.адресУказателя,
        имя: 'Указатель',
        раздел: БАЗА_ЗНАНИЙ.имяРаздела,
        исходник: указатель,
      });
    }
    for (const файл of readdirSync(каталог).sort()) {
      if (!файл.endsWith('.md') || файл === 'README.md') continue;
      const слаг = basename(файл, '.md');
      const исходник = readFileSync(join(каталог, файл), 'utf8');
      const запись = {
        адрес: БАЗА_ЗНАНИЙ.адресЗаметки(слаг),
        имя: первыйЗаголовок(исходник) || слаг,
        раздел: БАЗА_ЗНАНИЙ.имяРаздела,
        исходник,
        слаг,
        заметка: true,
      };
      страницы.push(запись);
      заметки.push(запись);
      // Заметка, не вписанная в указатель, недостижима при чтении по ссылкам.
      if (указатель && !указатель.includes(`(${файл})`)) {
        беды.push(`заметка не вписана в указатель базы знаний: ${файл}`);
      }
    }
  }
}

const адресаСтраниц = new Set(страницы.map((с) => с.адрес));

// ── Подстановка чисел ───────────────────────────────────────────────────────
// `{{корпус.функций}}` в тексте → измеренное число. Одно число живёт в одном
// месте (`docs/site/numbers.json`), и разъехаться двум страницам не в чем.
// Неизвестный ключ — отказ сборки: подстановка, доехавшая до читателя двойными
// скобками, хуже отсутствия числа.
for (const с of страницы) {
  const { текст, беды: бедыЧисел } = подставить(с.исходник, числа);
  с.исходник = текст;
  for (const б of бедыЧисел) беды.push(`${б} — на странице ${с.адрес}`);
}

// ── Разбор ──────────────────────────────────────────────────────────────────
for (const с of страницы) {
  const { html, оглавление, ссылки, беды: бедыРазбора } = разобрать(с.исходник);
  с.html = html;
  с.оглавление = оглавление;
  с.ссылки = ссылки;
  // Схема, которую не удалось разобрать, — такой же отказ, как битая ссылка.
  for (const б of бедыРазбора) беды.push(`${б} — на странице ${с.адрес}`);
  if (!с.имя) с.имя = первыйЗаголовок(с.исходник) || с.адрес;
}

// ── Разметка, не доехавшая до разметки ──────────────────────────────────────
/**
 * `**` в готовом HTML вне кода — это markdown, который не собрался.
 *
 * Ловится целый класс, а не один случай. Самый частый его вид — жирный вокруг
 * встроенного кода (`**\`flang check\`**`) — разбор чинить научили, и сегодня он
 * собирается; сторож всё равно нужен, потому что класс шире починки: незакрытая
 * пара, звёздочка внутри слова, жирный, разорванный ссылкой, — всё это доезжает
 * до читателя текстом. Полторы сотни таких пар на сорока страницах заметил
 * читатель, а не дерево: сборка проверяла ссылки и молчала о том, что печатает.
 *
 * Проверка стоит ПОСЛЕ разбора и до записи, поэтому красная сборка ничего не
 * публикует. Проверена порчей: незакрытая пара в тексте страницы роняет сборку
 * с именем страницы и куском текста вокруг.
 *
 * Внутри `<code>` и `<pre>` звёздочки законны: `flang/**\/*.flang` — это образец
 * пути, а `2**53` — возведение в степень. Поэтому проверяется то, что осталось
 * ПОСЛЕ вырезания кода, и только оно.
 */
function звёздочкиВнеКода(html) {
  const без = html
    .replace(/<pre[^>]*>[\s\S]*?<\/pre>/gu, '')
    .replace(/<code[^>]*>[\s\S]*?<\/code>/gu, '');
  const найдено = [];
  for (const м of без.matchAll(/\*\*/gu)) {
    найдено.push(без.slice(Math.max(0, м.index - 40), м.index + 40).replace(/\s+/gu, ' '));
  }
  return найдено;
}

for (const с of страницы) {
  for (const место of звёздочкиВнеКода(с.html)) {
    беды.push(`\`**\` в готовом HTML вне кода на ${с.адрес}: …${место}…`);
  }
}

// ── Проверка ссылок ─────────────────────────────────────────────────────────
// Ссылка базы знаний [[слаг]] обязана вести на существующую заметку.
// Ссылка на файл репозитория проверяется по дереву: документы ссылаются друг на
// друга путями, и они обязаны существовать, даже если страницы для них нет.
const слагиЗаметок = new Set(заметки.map((з) => з.слаг));
for (const с of страницы) {
  for (const ссылка of с.ссылки) {
    if (ссылка.вид === 'зеттель') {
      if (!слагиЗаметок.has(ссылка.цель)) беды.push(`битая ссылка базы знаний [[${ссылка.цель}]] на странице ${с.адрес}`);
      continue;
    }
    if (ссылка.цель.endsWith('.html')) {
      // Адрес считается от каталога страницы: `en/index.html` ссылается на
      // соседа просто именем, а на русскую половину — через `../`.
      const цель = join(dirname(с.адрес), ссылка.цель);
      if (!адресаСтраниц.has(цель)) беды.push(`ссылка на несуществующую страницу ${ссылка.цель} на ${с.адрес}`);
      continue;
    }
    // Ссылка на файл репозитория. Считаем от каталога САМОГО документа — иначе
    // проверка ругается на ссылку между соседями, стоит документам переехать
    // в подкаталог. Так и вышло, когда руководство уехало в docs/guide.
    const свойКаталог = с.из ? dirname(с.из) : 'docs';
    const варианты = [
      join(свойКаталог, ссылка.цель),
      ссылка.цель,
      join('docs', ссылка.цель),
      join('docs', 'zettel', ссылка.цель),
    ];
    if (!варианты.some((в) => existsSync(join(КОРЕНЬ, в)))) {
      беды.push(`ссылка в никуда: ${ссылка.цель} на странице ${с.адрес}`);
    }
  }
}

// ── Указатель поиска ────────────────────────────────────────────────────────
// Собирается ЗДЕСЬ, из тех же разобранных страниц, что печатаются в HTML:
// второго списка страниц нет, и разъехаться указателю с сайтом не в чем.
// Сторож рядом — настоящие запросы обязаны находить настоящие страницы, иначе
// сборка отказывает так же, как на битой ссылке.
const { указатель, меры } = собратьУказатель(страницы);
const текстУказателя = печатьУказателя(указатель);
for (const б of проверитьПоиск(указатель)) беды.push(б);
for (const б of проверитьОкно(текстУказателя)) беды.push(б);
// Вес печатается и в проверке, и в сборке: указатель растёт вместе с деревом, и
// если однажды вырастет в мегабайты, увидеть это надо в выводе, а не у
// читателя, который ждёт загрузки.
const весУказателя =
  `${(Buffer.byteLength(текстУказателя) / 1024).toFixed(0)} КиБ на ${меры.страниц} страниц ` +
  `(текста ${меры.положенныйТекст} знаков из ${меры.полныйТекст} — по ${указатель.предел} знаков с начала страницы)`;

// ── Оболочка страницы ───────────────────────────────────────────────────────
const порядокРазделов = [...РАЗДЕЛЫ.map((р) => р.имя), БАЗА_ЗНАНИЙ.имяРаздела];

const английскиеИмена = new Map(РАЗДЕЛЫ.filter((р) => р.англ).map((р) => [р.имя, р.англ]));

function боковое(текущий, язык) {
  const части = [];
  for (const имяРаздела of порядокРазделов) {
    // Английское меню показывает только английские страницы: пустой пункт,
    // ведущий на русский текст под английским именем, честнее не делает.
    const свои = страницы.filter((с) => с.раздел === имяРаздела && !с.заметка && (с.язык ?? 'ru') === язык);
    if (!свои.length) continue;
    const подпись = язык === 'en' ? (английскиеИмена.get(имяРаздела) ?? имяРаздела) : имяРаздела;
    части.push(`<div class="nav-group"><div class="nav-title">${экранировать(подпись)}</div><ul>`);
    for (const с of свои) {
      const текущая = с.адрес === текущий ? ' class="here"' : '';
      части.push(`<li><a${текущая} href="${относительно(текущий, с.адрес)}">${экранировать(с.имя)}</a></li>`);
    }
    if (имяРаздела === БАЗА_ЗНАНИЙ.имяРаздела) {
      части.push(`<li class="nav-count">${заметки.length} заметок</li>`);
    }
    части.push('</ul></div>');
  }
  return части.join('');
}

function оглавлениеСправа(пункты, язык) {
  if (пункты.length < 3) return '';
  const подпись = язык === 'en' ? 'On this page' : 'На этой странице';
  return (
    `<nav class="toc" aria-label="${подпись}"><div class="toc-title">${подпись}</div><ul>` +
    пункты
      .map((п) => `<li class="lvl${п.уровень}"><a href="#${п.якорь}">${п.html ?? экранировать(п.текст)}</a></li>`)
      .join('') +
    '</ul></nav>'
  );
}

/** Путь от одной страницы сайта к другой: `en/index.html` → `../overview.html`. */
function относительно(откуда, куда) {
  const свой = dirname(откуда);
  if (свой === dirname(куда)) return basename(куда);
  const вверх = свой === '.' ? '' : '../'.repeat(свой.split('/').length);
  return вверх + куда;
}

/** Слова оболочки. Двух шаблонов нет намеренно: разъезжается вёрстка, а не текст. */
