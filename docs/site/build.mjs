// ── Контраст подсветки ──────────────────────────────────────────────────────
// Цвета подсветки взяты из фирменной палитры Digitable, и проверяются они не
// глазом, а формулой WCAG. Замер написан НА ЯЗЫКЕ — `docs/site/storozh-kontrasta.flang`
// читает ту же таблицу стилей, что поедет на сайт, и требует 4.5:1 в каждой из
// трёх тем. Довод, почему без этого замера палитру трогать нельзя, записан в
// шапке того файла.
//
// Зовётся он прогоном плана, а не ввозом: у сборки нет и не будет второго
// разбора языка на JavaScript. Отказ плана (код 1) приезжает полем `error`,
// и каждая беда стоит в нём отдельной строкой за «  · ».
const ДВОИЧНЫЙ = process.env.FLANG_BINARY ?? join(КОРЕНЬ, 'bootstrap', 'flang');
/* Итоговая строка замера — последняя строка отчёта плана, и она приезжает и на
   зелёном, и на красном. Её печатает отчёт сборки, поэтому вынута отдельно. */
let КОНТРАСТ_СТРОКА = 'не мерен';
const итогЗамера = (текст) => {
  const строка = текст.split('\n').find((с) => с.startsWith('Контраст подсветки: '));
  return строка === undefined ? null : строка.slice('Контраст подсветки: '.length).replace(/\.$/u, '');
};
if (!existsSync(ДВОИЧНЫЙ)) {
  // Не молчание: «мне нечем смотреть» — это тоже отказ, иначе палитра уедет
  // на сайт непроверенной и никто об этом не узнает.
  беды.push(
    `контраст подсветки: двоичного нет (${ДВОИЧНЫЙ}) — палитру проверить нечем. ` +
      'Соберите — make -C bootstrap — или назовите свой в FLANG_BINARY',
  );
} else {
  const прогон = spawnSync(ДВОИЧНЫЙ, ['io', 'docs/site/storozh-kontrasta.flang'], {
    cwd: КОРЕНЬ,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (прогон.status === 1) {
    /* Отказ плана печатается в stderr, успех — в stdout. Берём оба: контракт
       кодов возврата у `flang io` жёсткий, а какой поток нести отказ — нет. */
    const сырое = прогон.stderr || прогон.stdout || '';
    let ответ = {};
    try {
      ответ = JSON.parse(сырое);
    } catch {
      ответ = {};
    }
    const текст = ответ.error ?? сырое;
    КОНТРАСТ_СТРОКА = итогЗамера(текст) ?? КОНТРАСТ_СТРОКА;
    const найденные = текст.split('\n').filter((с) => с.startsWith('  · ')).map((с) => с.slice(4));
    if (найденные.length) for (const б of найденные) беды.push(б);
    else беды.push(`контраст подсветки: план отказал, а бед не назвал — ${прогон.stderr || прогон.stdout}`);
  } else if (прогон.status !== 0) {
    беды.push(
      `контраст подсветки: прогон плана ответил кодом ${прогон.status} — ${прогон.stderr || прогон.stdout}`,
    );
  } else {
    let ответ = {};
    try {
      ответ = JSON.parse(прогон.stdout);
    } catch {
      ответ = {};
    }
    const итог = итогЗамера(ответ.result ?? '');
    if (итог === null) {
      /* Зелёный код при неразборчивом ответе — тоже беда: отчёт сборки назвал бы
         число, которого никто не мерил. */
      беды.push('контраст подсветки: план дошёл до конца, а итоговой строки не назвал');
    } else {
      КОНТРАСТ_СТРОКА = итог;
    }
  }
}

// ── Разметка, не доехавшая до разметки ──────────────────────────────────────
/**
 * `**` в готовом HTML вне кода — это markdown, который не собрался.
 *
 * Ловится целый класс, а не один случай. Самый частый его вид — жирный вокруг
 * встроенного кода (`**\`flang check\`**`) — разбор чинить научили, и сегодня он
 * собирается; сторож всё равно нужен, потому что класс шире починки: незакрытая
 * пара, звёздочка внутри слова, жирный, разорванный ссылкой, — всё это доезжает
 * до читателя текстом. Полторы сотни таких пар на сорока страницах заметил
 * читатель, а не дерево: сборка проверяла ссылки и молчала о том, что печатает.
 *
 * Проверка стоит ПОСЛЕ разбора и до записи, поэтому красная сборка ничего не
 * публикует. Проверена порчей: незакрытая пара в тексте страницы роняет сборку
 * с именем страницы и куском текста вокруг.
 *
 * Внутри `<code>` и `<pre>` звёздочки законны: `flang/**\/*.flang` — это образец
 * пути, а `2**53` — возведение в степень. Поэтому проверяется то, что осталось
 * ПОСЛЕ вырезания кода, и только оно.
 */
function звёздочкиВнеКода(html) {
  const без = html
    .replace(/<pre[^>]*>[\s\S]*?<\/pre>/gu, '')
    .replace(/<code[^>]*>[\s\S]*?<\/code>/gu, '');
  const найдено = [];
  for (const м of без.matchAll(/\*\*/gu)) {
    найдено.push(без.slice(Math.max(0, м.index - 40), м.index + 40).replace(/\s+/gu, ' '));
  }
  return найдено;
}

for (const с of страницы) {
  for (const место of звёздочкиВнеКода(с.html)) {
    беды.push(`\`**\` в готовом HTML вне кода на ${с.адрес}: …${место}…`);
  }
}

// ── Подстановка, доехавшая до читателя ──────────────────────────────────────
/**
 * Двойные скобки в готовом HTML вне кода — это подстановка, которая не сработала.
 *
 * Подстановка чисел уже отказывает на НЕИЗВЕСТНОМ ключе, и этого мало. Ключ
 * пишется по образцу `{{раздел.имя}}`; всё, что в образец не попало —
 * `{{ корпус.функций }}` с пробелами, `{{корпус}}` без точки, незакрытая пара, —
 * подстановка просто не замечает, и текст едет на страницу двойными скобками.
 * Такое доезжало до опубликованного сайта, и заметил это читатель, а не дерево.
 *
 * Внутри `<code>` и `<pre>` скобки законны: страница про сам этот приём обязана
 * показать `{{корпус.функций}}` как пример, а в блоках кода лежат чужие шаблоны
 * Rosetta. Поэтому проверяется то, что осталось ПОСЛЕ вырезания кода.
 */
function подстановкиВнеКода(html) {
  const без = html
    .replace(/<pre[^>]*>[\s\S]*?<\/pre>/gu, '')
    .replace(/<code[^>]*>[\s\S]*?<\/code>/gu, '');
  const найдено = [];
  for (const м of без.matchAll(/\{\{|\}\}/gu)) {
    найдено.push(без.slice(Math.max(0, м.index - 40), м.index + 40).replace(/\s+/gu, ' '));
  }
  return найдено;
}

/**
 * День месяца, которого не бывает: «199 августа 2026».
 *
 * Одна лишняя цифра рядом с датой не ломает ни ссылку, ни разметку, поэтому до
 * сих пор её ловил только глаз. А ловится она дешевле любой другой беды: день
 * больше 31 — это не спорный стиль, это опечатка.
 */
const МЕСЯЦЫ =
  'января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря|' +
  'January|February|March|April|May|June|July|August|September|October|November|December';
function невозможныеДаты(html) {
  const без = html
    .replace(/<pre[^>]*>[\s\S]*?<\/pre>/gu, '')
    .replace(/<code[^>]*>[\s\S]*?<\/code>/gu, '');
  const найдено = [];
  const образец = new RegExp(`(\\d+)\\s+(${МЕСЯЦЫ})|(${МЕСЯЦЫ})\\s+(\\d+)`, 'gu');
  for (const м of без.matchAll(образец)) {
    const день = Number(м[1] ?? м[4]);
    if (Number.isFinite(день) && день >= 1 && день <= 31) continue;
    // «August 2026» — это месяц с годом, а не день: год отсеиваем по величине.
    if (день >= 1000 && день <= 9999) continue;
    найдено.push(м[0]);
  }
  return найдено;
}

for (const с of страницы) {
  for (const место of подстановкиВнеКода(с.html)) {
    беды.push(`подстановка не сработала и доехала до страницы ${с.адрес}: …${место}…`);
  }
  for (const дата of невозможныеДаты(с.html)) {
    беды.push(`такого числа не бывает — «${дата}» на странице ${с.адрес}`);
  }
}

// ── Проверка ссылок ─────────────────────────────────────────────────────────
// Ссылка базы знаний [[слаг]] обязана вести на существующую заметку.
// Ссылка на файл репозитория проверяется по дереву: документы ссылаются друг на
// друга путями, и они обязаны существовать, даже если страницы для них нет.
const слагиЗаметок = new Set(заметки.map((з) => з.слаг));
for (const с of страницы) {
  for (const ссылка of с.ссылки) {
    if (ссылка.вид === 'зеттель') {
      if (!слагиЗаметок.has(ссылка.цель)) беды.push(`битая ссылка базы знаний [[${ссылка.цель}]] на странице ${с.адрес}`);
      continue;
    }
    if (ссылка.цель.endsWith('.html')) {
      // Адрес считается от каталога страницы: `en/index.html` ссылается на
      // соседа просто именем, а на русскую половину — через `../`.
      const цель = join(dirname(с.адрес), ссылка.цель);
      if (!адресаСтраниц.has(цель)) беды.push(`ссылка на несуществующую страницу ${ссылка.цель} на ${с.адрес}`);
      continue;
    }
    // Ссылка на файл репозитория. Считаем от каталога САМОГО документа — иначе
    // проверка ругается на ссылку между соседями, стоит документам переехать
    // в подкаталог. Так и вышло, когда руководство уехало в docs/guide.
    const свойКаталог = с.из ? dirname(с.из) : 'docs';
    const варианты = [
      join(свойКаталог, ссылка.цель),
      ссылка.цель,
      join('docs', ссылка.цель),
      join('docs', 'zettel', ссылка.цель),
    ];
    if (!варианты.some((в) => existsSync(join(КОРЕНЬ, в)))) {
      беды.push(`ссылка в никуда: ${ссылка.цель} на странице ${с.адрес}`);
    }
  }
}

// ── Указатель поиска ────────────────────────────────────────────────────────
// Собирается ЗДЕСЬ, из тех же разобранных страниц, что печатаются в HTML:
// второго списка страниц нет, и разъехаться указателю с сайтом не в чем.
// Сторож рядом — настоящие запросы обязаны находить настоящие страницы, иначе
// сборка отказывает так же, как на битой ссылке.
const { указатель, меры } = собратьУказатель(страницы);
const текстУказателя = печатьУказателя(указатель);
for (const б of проверитьПоиск(указатель)) беды.push(б);
for (const б of проверитьОкно(текстУказателя)) беды.push(б);
// Вес печатается и в проверке, и в сборке: указатель растёт вместе с деревом, и
// если однажды вырастет в мегабайты, увидеть это надо в выводе, а не у
// читателя, который ждёт загрузки.
const весУказателя =
  `${(Buffer.byteLength(текстУказателя) / 1024).toFixed(0)} КиБ на ${меры.страниц} страниц ` +
  `(текста ${меры.положенныйТекст} знаков из ${меры.полныйТекст} — по ${указатель.предел} знаков с начала страницы)`;

// ── Оболочка страницы ───────────────────────────────────────────────────────
const порядокРазделов = [...РАЗДЕЛЫ.map((р) => р.имя), БАЗА_ЗНАНИЙ.имяРаздела];

const английскиеИмена = new Map(РАЗДЕЛЫ.filter((р) => р.англ).map((р) => [р.имя, р.англ]));

// ── Два читателя, два меню ──────────────────────────────────────────────────
// У сайта два читателя, и хотят они разного. Пришедший посмотреть язык хочет
// знать, что это, чем отличается и как попробовать. Тот, кто язык делает, —
// во сколько раз мы медленнее Python, какой путь уже отвергнут и почему.
//
// Раньше меню было одно, и второй читатель стоял первым уровнем: «Замеры» и
// «База знаний» встречали всякого, кто открыл сайт. Читатель владельца назвал
// это прямо — «нейрослоп про какое-то исследование».
//
// Теперь разделы, помеченные `дляУчастников`, в меню новичка не разворачиваются
// вовсе: вместо них внизу стоит ОДНА строка — дверь. За дверью страница
// `contributing.html`, и уже она перечисляет всё внутреннее ссылками, которые
// сборка проверяет наравне с прочими. Ни одна страница не выброшена и ни одна
// не сменила адреса.
//
// Внутри же (на любой странице внутреннего раздела) меню показывает ВСЁ: тому,
// кто дошёл сюда, прятать нечего.
const ДВЕРЬ_УЧАСТНИКАМ = 'contributing.html';
const ВНУТРЕННИЕ_РАЗДЕЛЫ = new Set([
  ...РАЗДЕЛЫ.filter((р) => р.дляУчастников).map((р) => р.имя),
  ...(БАЗА_ЗНАНИЙ.дляУчастников ? [БАЗА_ЗНАНИЙ.имяРаздела] : []),
]);
const разделСтраницы = new Map(страницы.map((с) => [с.адрес, с.раздел]));

// Дверь обязана вести на существующую страницу: меню, у которого единственный
// вход во внутреннюю половину сломан, теряет её целиком.
if (ВНУТРЕННИЕ_РАЗДЕЛЫ.size && !адресаСтраниц.has(ДВЕРЬ_УЧАСТНИКАМ)) {
  беды.push(`дверь в половину для участников ведёт в никуда: нет страницы ${ДВЕРЬ_УЧАСТНИКАМ}`);
}

function боковое(текущий, язык) {
  const части = [];
  const яВнутри = ВНУТРЕННИЕ_РАЗДЕЛЫ.has(разделСтраницы.get(текущий));
  for (const имяРаздела of порядокРазделов) {
    if (ВНУТРЕННИЕ_РАЗДЕЛЫ.has(имяРаздела) && !яВнутри) continue;
    // Английское меню показывает только английские страницы: пустой пункт,
    // ведущий на русский текст под английским именем, честнее не делает.
    const свои = страницы.filter((с) => с.раздел === имяРаздела && !с.заметка && (с.язык ?? 'ru') === язык);
    if (!свои.length) continue;
    const подпись = язык === 'en' ? (английскиеИмена.get(имяРаздела) ?? имяРаздела) : имяРаздела;
    части.push(`<div class="nav-group"><div class="nav-title">${экранировать(подпись)}</div><ul>`);
    for (const с of свои) {
      const текущая = с.адрес === текущий ? ' class="here"' : '';
      части.push(`<li><a${текущая} href="${относительно(текущий, с.адрес)}">${экранировать(с.имя)}</a></li>`);
    }
    if (имяРаздела === БАЗА_ЗНАНИЙ.имяРаздела) {
      части.push(`<li class="nav-count">${заметки.length} заметок</li>`);
    }
    части.push('</ul></div>');
  }
  if (!яВнутри) {
    const адрес = язык === 'en' ? `en/${ДВЕРЬ_УЧАСТНИКАМ}` : ДВЕРЬ_УЧАСТНИКАМ;
    части.push(
      `<div class="nav-group nav-dver"><ul><li><a href="${относительно(текущий, адрес)}">` +
        `${экранировать(СЛОВА[язык].дверь)}</a></li></ul></div>`,
    );
  }
  return части.join('');
}

function оглавлениеСправа(пункты, язык) {
  if (пункты.length < 3) return '';
  const подпись = язык === 'en' ? 'On this page' : 'На этой странице';
  return (
    `<nav class="toc" aria-label="${подпись}"><div class="toc-title">${подпись}</div><ul>` +
    пункты
      .map((п) => `<li class="lvl${п.уровень}"><a href="#${п.якорь}">${п.html ?? экранировать(п.текст)}</a></li>`)
      .join('') +
    '</ul></nav>'
  );
}

/** Путь от одной страницы сайта к другой: `en/index.html` → `../overview.html`. */
function относительно(откуда, куда) {
  const свой = dirname(откуда);
  if (свой === dirname(куда)) return basename(куда);
  const вверх = свой === '.' ? '' : '../'.repeat(свой.split('/').length);
  return вверх + куда;
}

