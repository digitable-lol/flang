// ── Кто делает язык ─────────────────────────────────────────────────────────
// Подвал называет владельца, лицензию, год и два адреса. НИ ОДНО из этих слов
// здесь не набрано: правообладатель, год и имя лицензии читаются из `LICENSE`,
// оба адреса — из `package.json`. Набранный в шаблоне год протухает 1 января, а
// набранный адрес — в день переезда репозитория, и оба протухают молча.
//
// Не нашлось — БЕДА, а не пропуск: подвал, потерявший лицензию, хуже подвала,
// которого нет.
function правообладатель() {
  const текст = читать('LICENSE');
  const м = текст && /^Copyright \(c\) (\d{4}), (.+?)\s*$/mu.exec(текст);
  if (!м) {
    беды.push('в LICENSE не нашлась строка «Copyright (c) ГОД, ПРАВООБЛАДАТЕЛЬ» — подвалу нечего сказать');
    return { год: null, кто: null, лицензия: null };
  }
  // Имя лицензии — первой строкой файла: «BSD 2-Clause License» → «BSD 2-Clause».
  // Прописью, как в самом файле, а не опознавателем SPDX: подвал читает человек.
  const первая = (текст.split('\n')[0] ?? '').trim().replace(/\s+License$/u, '');
  if (!первая) беды.push('в LICENSE не названа лицензия первой строкой');
  return { год: м[1], кто: м[2], лицензия: первая || null };
}

function сведенияПакета() {
  const текст = читать('package.json');
  let пакет;
  try {
    пакет = JSON.parse(текст ?? 'null');
  } catch {
    беды.push('package.json не разбирается — подвалу неоткуда взять адреса');
    return {};
  }
  if (!пакет) return {};
  // `git+https://github.com/…/flang.git` → адрес, по которому открывается дерево.
  const исходники = (пакет.repository?.url ?? '').replace(/^git\+/u, '').replace(/\.git$/u, '');
  const ошибки = пакет.bugs?.url ?? '';
  for (const [имя, значение] of [['repository.url', исходники], ['bugs.url', ошибки], ['license', пакет.license]]) {
    if (!значение) беды.push(`в package.json нет ${имя} — подвал не назовёт ${имя === 'license' ? 'лицензию' : 'адрес'}`);
  }
  return { исходники, ошибки, опознаватель: пакет.license };
}

const ПРАВА = правообладатель();
const ПАКЕТ = сведенияПакета();

// Файл LICENSE и поле `license` пакета обязаны говорить одно и то же. Разошлись —
// отказ: подвал, называющий одну лицензию, пока пакет ставится под другой, врёт
// ровно в том месте, где ошибиться дороже всего.
if (ПРАВА.лицензия && ПАКЕТ.опознаватель && ПРАВА.лицензия.replace(/\s+/gu, '-') !== ПАКЕТ.опознаватель) {
  беды.push(`лицензия разошлась: в LICENSE «${ПРАВА.лицензия}», в package.json «${ПАКЕТ.опознаватель}»`);
}

/**
 * Коммит и дата дерева. Без git — не беда: сборка обязана работать в выгрузке
 * (`git archive`), где `.git` нет вовсе. Тогда строка происхождения честно
 * говорит, что дерева не назвала, вместо того чтобы назвать неверное.
 *
 * ── Почему тут спрашивается ещё и ствол ──────────────────────────────────────
 * Хеш в подвале читается как «вот дерево, по которому собрана эта страница,
 * посмотрите». 29 августа 2026 выяснилось, что читать его так нельзя: в подвале
 * опубликованного сайта стоял `478d23c8` — настоящий коммит от 23 августа, но
 * НЕ предок ствола. Историю перебрали, и коммита не стало вовсе: `git cat-file`
 * на него отвечает «Not a valid object name». Читатель, пошедший смотреть, не
 * находил ничего и узнать причину не мог.
 *
 * Подвал от переборки истории не защитит — она случается ПОСЛЕ сборки. Но
 * назвать своё положение он обязан: собрана страница со ствола или сбоку. Тогда
 * подвал, переживший переборку, хотя бы говорит, где искать, а сборка сбоку не
 * выдаёт себя за ствольную.
 *
 * «Ствол не найден» и «мы не на стволе» — РАЗНЫЕ исходы, и смешивать их нельзя:
 * `actions/checkout` кладёт отсоединённую голову и локальной ветки `main` может
 * не завести вовсе. Поэтому ствол ищется и среди `origin/*`, и если не нашёлся
 * ни один — подвал молчит о положении, а не объявляет дерево сторонним.
 */
function происхождение() {
  const гит = (доводы) =>
    execFileSync('git', доводы, { cwd: КОРЕНЬ, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  const есть = (доводы) => {
    try {
      гит(доводы);
      return true;
    } catch {
      return false;
    }
  };
  try {
    const дерево = гит(['rev-parse', '--short', 'HEAD']);
    const дата = гит(['log', '-1', '--format=%cd', '--date=short']);
    const ствол = ['refs/heads/main', 'refs/remotes/origin/main'].find((р) => есть(['rev-parse', '-q', '--verify', р]));
    const наСтволе = ствол ? есть(['merge-base', '--is-ancestor', 'HEAD', ствол]) : null;
    return { дерево, дата, наСтволе };
  } catch {
    return { дерево: null, дата: null, наСтволе: null };
  }
}
const ПРОИСХОЖДЕНИЕ = происхождение();
