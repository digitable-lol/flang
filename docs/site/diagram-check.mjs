// Сторож схем: каждая поддержанная форма обязана разобраться и нарисоваться, а
// каждая неподдержанная — ОТКАЗАТЬ с номером строки.
//
// Сторож стоит внутри сборки, а не отдельным скриптом, по той же причине, по
// которой там же стоят проверка ссылок и сторож поиска: сайт уже собирается в
// CI, а вторая версия протухает за неделю, пока её никто не сторожит.
//
// Проверяется ТРИ вещи, и третья — не про разбор.
//
//   РАЗБОР. Строка исходника → то, что из неё вышло: участники в порядке
//   объявления, вид стрелки, размещение заметки, вложенность рамок. Врать
//   здесь дешевле всего: разбор молча пропустил форму — и схема поехала на
//   страницу неполной.
//
//   ОТКАЗ. Каждая неподдержанная форма названа поимённо, и от каждой требуется
//   не просто исключение, а номер строки и сама строка в тексте отказа. Отказ
//   без места — это «где-то в схеме что-то не так», и читать его некому.
//   Отдельно проверяется, что отказ доезжает до СБОРКИ: `markdown.разобрать`
//   обязан положить беду в свой список, а не вывести исходник текстом.
//
//   КООРДИНАТЫ. Схема, у которой подпись вылезла за рамку или стрелка легла на
//   шапку участника, разбор проходит и сборку не красит — а читателю её не
//   прочесть. Поэтому готовый SVG разбирается обратно в прямоугольники,
//   строки и пути, и по ним считаются запреты (`ЗАПРЕТЫ` ниже; сколько их —
//   печатает сама сборка). Это же считается и по НАСТОЯЩИМ схемам сайта:
//   сборка зовёт `проверитьКартинку` на каждой отрисованной диаграмме
//   последовательности.
//
// Замер текста здесь не свой: ширина строки берётся у `diagram.mjs`, той же
// функцией, которой схема и рисовалась. Второй измеритель означал бы, что
// сторож меряет не то, что нарисовано.

