/**
 * Разбирает готовый SVG обратно в прямоугольники, надписи и пути.
 * Координаты приводятся к системе самой картинки: сдвиг `translate` учтён.
 */
export function разобратьКартинку(svg) {
  const рамка = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
  if (!рамка) throw new Error('у картинки нет viewBox');
  const сдвигМ = /translate\((-?[\d.]+) 0\)/.exec(svg);
  const сдвиг = сдвигМ ? Number(сдвигМ[1]) : 0;

  const прямоугольники = [];
  for (const м of svg.matchAll(/<rect class="([^"]+)" x="(-?[\d.]+)" y="(-?[\d.]+)" width="(-?[\d.]+)" height="(-?[\d.]+)"/g)) {
    прямоугольники.push({ класс: м[1], x: Number(м[2]) + сдвиг, y: Number(м[3]), ш: Number(м[4]), в: Number(м[5]) });
  }

  const надписи = [];
  for (const м of svg.matchAll(/<text class="([^"]+)" x="(-?[\d.]+)" y="(-?[\d.]+)">([^<]*)<\/text>/g)) {
    надписи.push({ класс: м[1], x: Number(м[2]) + сдвиг, база: Number(м[3]), текст: м[4] });
  }

  const пути = [];
  for (const м of svg.matchAll(/<path class="([^"]+)" d="([^"]+)"/g)) {
    const точки = [...м[2].matchAll(/[MVH](-?[\d.]+)(?:\s(-?[\d.]+))?/g)];
    const иксы = [];
    const игреки = [];
    for (const т of точки) {
      if (т[0][0] === 'M') {
        иксы.push(Number(т[1]) + сдвиг);
        игреки.push(Number(т[2]));
      } else if (т[0][0] === 'H') иксы.push(Number(т[1]) + сдвиг);
      else игреки.push(Number(т[1]));
    }
    пути.push({ класс: м[1], верх: Math.min(...игреки), низ: Math.max(...игреки), слева: Math.min(...иксы), справа: Math.max(...иксы) });
  }

  /* Коробка надписи: своя ширина по кеглю, высота — на глаз от базовой линии,
     чтобы запрет «вылезло за край» ловил и верх строки, и её хвосты. */
  const коробкиНадписей = надписи.map((н) => {
    const доля = КЕГЛИ.get(н.класс) ?? КЕГЛИ.get(н.класс.split(' ')[0]) ?? 0.885;
    const своя = ширина(н.текст) * доля;
    const x = ОТ_ТОЧКИ.has(н.класс) ? н.x : н.x - своя / 2;
    return { класс: н.класс, текст: н.текст, x, y: н.база - 11 * доля, ш: своя, в: 14 * доля };
  });
  for (const н of коробкиНадписей) {
    if (н.класс !== 'edge-label' && н.класс !== 'frame-label') continue;
    н.подложка = прямоугольники.find(
      (п) => п.класс === 'edge-label-bg' && н.y >= п.y - 3 && н.y + н.в <= п.y + п.в + 3,
    );
  }

  return { ш: Number(рамка[1]), в: Number(рамка[2]), сдвиг, прямоугольники, надписи, коробкиНадписей, пути };
}

/** Гоняет ЗАПРЕТЫ по одной картинке. Возвращает беды. */
export function проверитьКартинку(svg, откуда) {
  let картинка;
  try {
    картинка = разобратьКартинку(svg);
  } catch (ошибка) {
    return [`${откуда}: картинку не разобрать обратно — ${ошибка.message}`];
  }
  const беды = [];
  for (const з of ЗАПРЕТЫ) for (const б of з.судить(картинка)) беды.push(`${откуда}: ${з.имя} — ${б}`);
  return беды;
}

/** Вынимает из готового HTML страницы все диаграммы последовательности. */
export function выбратьПоследовательности(html) {
  return [...String(html).matchAll(/<svg [^>]*>(?:(?!<\/svg>)[\s\S])*?<\/svg>/g)]
    .map((м) => м[0])
    .filter((svg) => svg.includes('class="life"'));
}

/**
 * Прогоняет все случаи. Возвращает беды — сборка их складывает в свой список и
 * отказывает, как отказывает на битой ссылке.
 */
export function проверитьСхемы() {
  const беды = [];

  for (const с of РАЗБОР) {
    const исходник = с.исходник.join('\n');
    let схема;
    try {
      схема = разобратьПоследовательность(исходник);
    } catch (ошибка) {
      беды.push(`схемы, разбор «${с.имя}»: отказ там, где ждали разбор — ${ошибка.message}`);
      continue;
    }
    const ответ = с.ждём(схема);
    if (ответ !== true) беды.push(`схемы, разбор «${с.имя}»: ${ответ}`);
    try {
      const svg = схемаВSVG(исходник, с.имя);
      if (!svg.includes('role="img"')) беды.push(`схемы, разбор «${с.имя}»: у картинки нет role="img"`);
      if (!svg.includes(`<title>${экранировать(с.имя)}</title>`)) {
        беды.push(`схемы, разбор «${с.имя}»: подпись не доехала в <title>`);
      }
      for (const б of проверитьКартинку(svg, `схемы, разбор «${с.имя}»`)) беды.push(б);
    } catch (ошибка) {
      беды.push(`схемы, разбор «${с.имя}»: не рисуется — ${ошибка.message}`);
    }
  }

  for (const о of ОТКАЗЫ) {
    let сказало = null;
    try {
      разобратьПоследовательность(о.исходник.join('\n'));
    } catch (ошибка) {
      сказало = ошибка.message;
    }
    if (сказало === null) {
      беды.push(`схемы, отказ «${о.имя}»: разбор промолчал там, где обязан отказать`);
      continue;
    }
    if (!сказало.includes(`строка ${о.место}`)) {
      беды.push(`схемы, отказ «${о.имя}»: не назван номер строки ${о.место} — сказано «${сказало}»`);
    }
    if (!сказало.includes(о.кусок)) {
      беды.push(`схемы, отказ «${о.имя}»: в отказе нет «${о.кусок}» — сказано «${сказало}»`);
    }
  }

  /* Отказ обязан доехать до СБОРКИ, а не остаться исключением внутри разбора:
     страница с непонятой схемой не имеет права собраться. Номер строки здесь
     считается от начала блока ```mermaid, а не от начала страницы, — так же,
     как его считает и flowchart. */
  const страница = ['# Проба', '', '```mermaid Проба', 'sequenceDiagram', 'К->>Я: цель', 'К=>Я: нельзя', '```', ''].join('\n');
  const { беды: бедыСтраницы, html } = разобрать(страница, { ссылкиБазы: false });
  if (!бедыСтраницы.some((б) => б.includes('схема не рисуется') && б.includes('строка 3') && б.includes('К=>Я: нельзя'))) {
    беды.push(`схемы, отказ в сборке: markdown не покраснел как надо — беды вышли ${JSON.stringify(бедыСтраницы)}`);
  }
  if (html.includes('<svg')) беды.push('схемы, отказ в сборке: непонятая схема всё-таки нарисовалась');

  return беды;
}

/** Сколько случаев сторожит — для строки вывода сборки. */
export const СЛУЧАЕВ = РАЗБОР.length + ОТКАЗЫ.length;
