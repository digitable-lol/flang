// Схемы: подмножество mermaid — `flowchart` и `sequenceDiagram`, — отрисованное
// в inline-SVG во время сборки.
//
// ПОЧЕМУ НЕ НАСТОЯЩИЙ MERMAID. Цену померили: `mermaid@11/dist/mermaid.min.js`
// весит 3 566 058 байт. Это третья сторона, которая грузится в браузере на
// каждой из 107 страниц, рисует схему уже после загрузки — и, если сети нет
// или CDN закрыт, читатель видит вместо схемы её исходник текстом. Сайт языка,
// который хвалится нулём зависимостей и сборкой без интернета, не может
// зависеть от чужого мегабайта ради трёх картинок.
//
// ПОЧЕМУ ВСЁ-ТАКИ MERMAID НА ВХОДЕ. Исходник схемы остаётся обычным блоком
// ```mermaid в markdown. Значит, он же рисуется на GitHub, в редакторе и в
// любом просмотрщике — а на сайте его рисует эта сборка, в SVG, без единого
// байта времени работы. Платим один раз, при сборке.
//
// ЧТО ПОДДЕРЖАНО У FLOWCHART, и ни строкой больше (что у диаграммы
// последовательности — сказано в её шапке, ниже по файлу):
//   flowchart LR | TD          направление (и `graph` как синоним)
//   A[текст]                   прямоугольник
//   A(текст)                   скруглённый
//   A([текст])                 стадион
//   A{текст}                   ромб
//   A --> B                    стрелка
//   A -.-> B                   пунктирная стрелка
//   A ==> B                    жирная стрелка
//   A -->|подпись| B           подпись на стрелке
//   class A,B glavnoe          выделение (имена классов ниже, в КЛАССЫ)
//   classDef …                 принимается и не читается: цвета берём из темы
//   %% комментарий
//   <br> внутри подписи        перенос строки вручную
//
// ЧЕГО НЕТ НАМЕРЕННО: subgraph, стили в самом тексте схемы, произвольные формы,
// клики. Ни одного случая не понадобилось.
//
// Непонятая строка — ОТКАЗ сборки с номером строки, а не пропуск. Схема,
// отрисованная наполовину, хуже отсутствующей: она врёт молча.

import { экранировать } from './markdown.mjs';

/** Классы выделения. Имена ASCII — они уезжают в атрибут class. */
const КЛАССЫ = new Set([
  'glavnoe', // главный путь: заливка цветом ссылки
  'vyvod', // хороший исход
  'otkaz', // плохой исход
]);

const ФОРМЫ = [
  ['([', '])', 'стадион'],
  ['{', '}', 'ромб'],
  ['(', ')', 'скруглённый'],
  ['[', ']', 'прямоугольник'],
];

const КЕГЛЬ = 13;
const МЕЖСТРОЧНЫЙ = 17;
const ОТСТУП_X = 15;
const ОТСТУП_Y = 11;
// Между рангами. Сверху вниз зазор меньше: там ранги идут лентой, и с большим
// зазором схема из девяти шагов вытягивается в километр, который не читается.
const ЗАЗОР_РАНГА_LR = 62;
const ЗАЗОР_РАНГА_TD = 38;
const ЗАЗОР_В_РАНГЕ = 22;
const МАКС_ШИРИНА_ТЕКСТА = 168;
const ПОЛЕ = 6;

/**
 * Ширина строки в пикселях — приблизительно, по долям кегля.
 *
 * Точной её быть не может: шрифт выбирает браузер. Поэтому весь текст
 * центрируется (`text-anchor="middle"`), и ошибка замера только чуть сдвигает
 * центровку симметрично, а не рвёт вёрстку. Поля взяты с запасом.
 */
export function ширина(текст) {
  let сумма = 0;
  for (const с of текст) {
    if ('iIl|.,:;\'!`jtf()[]{}-'.includes(с)) сумма += 0.34;
    else if (с === ' ') сумма += 0.30;
    else if ('mwMWШЩЮЖ—«»@%'.includes(с)) сумма += 0.92;
    else if (с >= '0' && с <= '9') сумма += 0.57;
    else if (с.toLowerCase() !== с) сумма += 0.68; // прописная
    else сумма += 0.55;
  }
  return сумма * КЕГЛЬ;
}

/** Разбивает подпись на строки: сначала по `<br>`, потом по ширине. */
function строки(подпись) {
  const куски = подпись.split(/<br\s*\/?>/i).map((к) => к.trim());
  const готово = [];
  for (const кусок of куски) {
    const слова = кусок.split(/\s+/).filter(Boolean);
    if (!слова.length) continue;
    let текущая = слова[0];
    for (const слово of слова.slice(1)) {
      const проба = `${текущая} ${слово}`;
      if (ширина(проба) > МАКС_ШИРИНА_ТЕКСТА) {
        готово.push(текущая);
        текущая = слово;
      } else текущая = проба;
    }
    готово.push(текущая);
  }
  return готово.length ? готово : [''];
}

/** Разбор ссылки на узел: `A`, `A[текст]`, `A([текст])`, `A{текст}`. */
function узелИзТекста(текст, номер) {
  const т = текст.trim();
  const м = /^([A-Za-z0-9_]+)([\s\S]*)$/.exec(т);
  if (!м) throw new Error(`строка ${номер}: не разобрать узел «${т}»`);
  const id = м[1];
  const хвост = м[2].trim();
  if (!хвост) return { id };
  for (const [о, з, форма] of ФОРМЫ) {
    if (хвост.startsWith(о) && хвост.endsWith(з) && хвост.length >= о.length + з.length) {
      return { id, подпись: хвост.slice(о.length, хвост.length - з.length).trim(), форма };
    }
  }
  throw new Error(`строка ${номер}: непонятная форма узла «${т}»`);
}

/** Разбор исходника схемы в узлы и стрелки. Непонятая строка — исключение. */
export function разобратьСхему(исходник) {
  const все = String(исходник).split('\n');
  let направление = 'LR';
  const узлы = new Map();
  const стрелки = [];
  let шапкаБыла = false;

  const запомнить = ({ id, подпись, форма }) => {
    if (!узлы.has(id)) узлы.set(id, { id, подпись: id, форма: 'прямоугольник', классы: [] });
    const у = узлы.get(id);
    if (подпись !== undefined) у.подпись = подпись;
    if (форма !== undefined) у.форма = форма;
    return у;
  };

  for (let н = 0; н < все.length; н += 1) {
    const строка = все[н].trim();
    const номер = н + 1;
    if (!строка || строка.startsWith('%%')) continue;

    const шапка = /^(?:flowchart|graph)\s+(LR|TD|TB)\s*$/.exec(строка);
    if (шапка) {
      if (шапкаБыла) throw new Error(`строка ${номер}: вторая шапка схемы`);
      направление = шапка[1] === 'LR' ? 'LR' : 'TD';
      шапкаБыла = true;
      continue;
    }
    if (!шапкаБыла) throw new Error(`строка ${номер}: схема начинается не с «flowchart LR» или «flowchart TD»`);

    if (/^classDef\s/.test(строка)) continue; // цвета берём из темы, а не отсюда

    const выделение = /^class\s+([A-Za-z0-9_,\s]+?)\s+([A-Za-z0-9_]+)$/.exec(строка);
    if (выделение) {
      const имя = выделение[2];
      if (!КЛАССЫ.has(имя)) {
        throw new Error(`строка ${номер}: неизвестный класс «${имя}»; есть только ${[...КЛАССЫ].join(', ')}`);
      }
      for (const id of выделение[1].split(',').map((с) => с.trim()).filter(Boolean)) {
        запомнить({ id }).классы.push(имя);
      }
      continue;
    }

    const стрелка = /^([\s\S]+?)\s(-->|-\.->|==>)\s*(?:\|([^|]*)\|)?\s([\s\S]+)$/.exec(строка);
    if (стрелка) {
      const из = запомнить(узелИзТекста(стрелка[1], номер));
      const в = запомнить(узелИзТекста(стрелка[4], номер));
      стрелки.push({
        из: из.id,
        в: в.id,
        подпись: (стрелка[3] || '').trim(),
        вид: стрелка[2] === '-.->' ? 'пунктир' : стрелка[2] === '==>' ? 'жирная' : 'обычная',
      });
      continue;
    }

    // Одиночное объявление узла
    if (/^[A-Za-z0-9_]+\s*[[({]/.test(строка) || /^[A-Za-z0-9_]+$/.test(строка)) {
      запомнить(узелИзТекста(строка, номер));
      continue;
    }

    throw new Error(`строка ${номер}: не разобрать «${строка}»`);
  }

  if (!шапкаБыла) throw new Error('пустая схема: нет строки «flowchart LR» или «flowchart TD»');
  if (!узлы.size) throw new Error('в схеме нет ни одного узла');
  return { направление, узлы: [...узлы.values()], стрелки };
}

/**
 * Раскладка по рангам: ранг узла — длиннейший путь до него от узла без входа.
 *
 * Цикл здесь возможен (в схеме сверки он и есть), поэтому расслабление
 * ограничено числом узлов: дальше ранги всё равно не растут, а зациклиться
 * нельзя.
 */
function ранги(узлы, стрелки) {
  const ранг = new Map(узлы.map((у) => [у.id, 0]));
  for (let шаг = 0; шаг < узлы.length; шаг += 1) {
    let двинулось = false;
    for (const с of стрелки) {
      const надо = ранг.get(с.из) + 1;
      if (надо > ранг.get(с.в)) {
        ранг.set(с.в, надо);
        двинулось = true;
      }
    }
    if (!двинулось) break;
  }
  return ранг;
}

/** Рисует разобранную схему в SVG. */
export function нарисовать(схема, подпись) {
  const { направление, узлы, стрелки } = схема;
  const горизонтально = направление === 'LR';
  const ранг = ранги(узлы, стрелки);
  const ЗАЗОР_РАНГА = горизонтально ? ЗАЗОР_РАНГА_LR : ЗАЗОР_РАНГА_TD;

  for (const у of узлы) {
    у.строки = строки(у.подпись);
    у.ш = Math.max(...у.строки.map(ширина)) + ОТСТУП_X * 2;
    у.в = у.строки.length * МЕЖСТРОЧНЫЙ + ОТСТУП_Y * 2;
    if (у.форма === 'ромб') {
      у.ш += 26;
      у.в += 18;
    }
  }

  // Узлы по рангам, в порядке появления
  const поРангам = new Map();
  for (const у of узлы) {
    const р = ранг.get(у.id);
    if (!поРангам.has(р)) поРангам.set(р, []);
    поРангам.get(р).push(у);
  }
  const порядокРангов = [...поРангам.keys()].sort((а, б) => а - б);

  // Вдоль потока — ранг за рангом; поперёк — стопкой, по центру.
  const вдольРанга = new Map(); // ранг → размер поперёк
  const толщина = new Map(); // ранг → размер вдоль
  for (const р of порядокРангов) {
    const свои = поРангам.get(р);
    толщина.set(р, Math.max(...свои.map((у) => (горизонтально ? у.ш : у.в))));
    вдольРанга.set(
      р,
      свои.reduce((с, у) => с + (горизонтально ? у.в : у.ш), 0) + ЗАЗОР_В_РАНГЕ * (свои.length - 1),
    );
  }
  const поперёкВсего = Math.max(...порядокРангов.map((р) => вдольРанга.get(р)));

  let вдоль = ПОЛЕ;
  for (const р of порядокРангов) {
    const свои = поРангам.get(р);
    let поперёк = ПОЛЕ + (поперёкВсего - вдольРанга.get(р)) / 2;
    for (const у of свои) {
      const свояТолщина = горизонтально ? у.ш : у.в;
      const свояДлина = горизонтально ? у.в : у.ш;
      const центрВдоль = вдоль + толщина.get(р) / 2;
      const центрПоперёк = поперёк + свояДлина / 2;
      у.x = (горизонтально ? центрВдоль : центрПоперёк) - у.ш / 2;
      у.y = (горизонтально ? центрПоперёк : центрВдоль) - у.в / 2;
      у.цx = у.x + у.ш / 2;
      у.цy = у.y + у.в / 2;
      поперёк += свояДлина + ЗАЗОР_В_РАНГЕ;
      void свояТолщина;
    }
    вдоль += толщина.get(р) + ЗАЗОР_РАНГА;
  }

  const всегоВдоль = вдоль - ЗАЗОР_РАНГА + ПОЛЕ;
  const всегоПоперёк = поперёкВсего + ПОЛЕ * 2;
  const ширинаSVG = горизонтально ? всегоВдоль : всегоПоперёк;
  const высотаSVG = горизонтально ? всегоПоперёк : всегоВдоль;

  // ── Стрелки ───────────────────────────────────────────────────────────────
  const кускиСтрелок = [];
  const кускиПодписей = [];
  for (const с of стрелки) {
    const и = узлы.find((у) => у.id === с.из);
    const к = узлы.find((у) => у.id === с.в);
    const назад = ранг.get(с.в) <= ранг.get(с.из);

    let x1;
    let y1;
    let x2;
    let y2;
    let кx1;
    let кy1;
    let кx2;
    let кy2;
    if (горизонтально) {
      const впередиДальше = к.цx > и.цx;
      x1 = впередиДальше ? и.x + и.ш : и.x;
      x2 = впередиДальше ? к.x : к.x + к.ш;
      y1 = и.цy;
      y2 = к.цy;
      const плечо = Math.max(26, Math.abs(x2 - x1) * 0.45);
      кx1 = x1 + (впередиДальше ? плечо : -плечо);
      кx2 = x2 - (впередиДальше ? плечо : -плечо);
      кy1 = y1;
      кy2 = y2;
      if (назад) {
        // Обратная связь идёт понизу, чтобы не лечь на прямой путь
        const низ = Math.max(и.y + и.в, к.y + к.в) + 26;
        кy1 = низ;
        кy2 = низ;
        y1 = и.цy + и.в / 2 - и.в / 2 + и.в; // нижняя грань
        x1 = и.цx;
        y1 = и.y + и.в;
        x2 = к.цx;
        y2 = к.y + к.в;
        кx1 = x1;
        кx2 = x2;
      }
    } else {
      const внизДальше = к.цy > и.цy;
      y1 = внизДальше ? и.y + и.в : и.y;
      y2 = внизДальше ? к.y : к.y + к.в;
      x1 = и.цx;
      x2 = к.цx;
      const плечо = Math.max(24, Math.abs(y2 - y1) * 0.45);
      кy1 = y1 + (внизДальше ? плечо : -плечо);
      кy2 = y2 - (внизДальше ? плечо : -плечо);
      кx1 = x1;
      кx2 = x2;
      if (назад) {
        const бок = Math.max(и.x + и.ш, к.x + к.ш) + 26;
        x1 = и.x + и.ш;
        x2 = к.x + к.ш;
        y1 = и.цy;
        y2 = к.цy;
        кx1 = бок;
        кx2 = бок;
        кy1 = y1;
        кy2 = y2;
      }
    }

    const класс = `edge${с.вид === 'пунктир' ? ' dashed' : с.вид === 'жирная' ? ' thick' : ''}`;
    кускиСтрелок.push(
      `<path class="${класс}" d="M${x1.toFixed(1)} ${y1.toFixed(1)} C${кx1.toFixed(1)} ${кy1.toFixed(1)}, ${кx2.toFixed(1)} ${кy2.toFixed(1)}, ${x2.toFixed(1)} ${y2.toFixed(1)}" marker-end="url(#nakonechnik)"/>`,
    );

    if (с.подпись) {
      // Середина кубической кривой при t=0.5
      const сx = (x1 + 3 * кx1 + 3 * кx2 + x2) / 8;
      const сy = (y1 + 3 * кy1 + 3 * кy2 + y2) / 8;
      const ш = ширина(с.подпись) * 0.86 + 10;
      кускиПодписей.push(
        `<rect class="edge-label-bg" x="${(сx - ш / 2).toFixed(1)}" y="${(сy - 9).toFixed(1)}" width="${ш.toFixed(1)}" height="18" rx="4"/>` +
          `<text class="edge-label" x="${сx.toFixed(1)}" y="${(сy + 4).toFixed(1)}">${экранировать(с.подпись)}</text>`,
      );
    }
  }

  // ── Узлы ──────────────────────────────────────────────────────────────────
  const кускиУзлов = [];
  for (const у of узлы) {
    const классы = ['node', ...у.классы].join(' ');
    let фигура;
    if (у.форма === 'ромб') {
      const точки = [
        [у.цx, у.y],
        [у.x + у.ш, у.цy],
        [у.цx, у.y + у.в],
        [у.x, у.цy],
      ]
        .map(([а, б]) => `${а.toFixed(1)},${б.toFixed(1)}`)
        .join(' ');
      фигура = `<polygon class="${классы}" points="${точки}"/>`;
    } else {
      const скруг = у.форма === 'стадион' ? у.в / 2 : у.форма === 'скруглённый' ? 13 : 5;
      фигура = `<rect class="${классы}" x="${у.x.toFixed(1)}" y="${у.y.toFixed(1)}" width="${у.ш.toFixed(1)}" height="${у.в.toFixed(1)}" rx="${скруг.toFixed(1)}"/>`;
    }
    const первая = у.цy - ((у.строки.length - 1) * МЕЖСТРОЧНЫЙ) / 2 + 4.5;
    const текст = у.строки
      .map(
        (с, н) =>
          `<text class="node-text${у.классы.includes('glavnoe') ? ' on-accent' : ''}" x="${у.цx.toFixed(1)}" y="${(первая + н * МЕЖСТРОЧНЫЙ).toFixed(1)}">${экранировать(с)}</text>`,
      )
      .join('');
    кускиУзлов.push(фигура + текст);
  }

  const внутри = кускиСтрелок.join('') + кускиУзлов.join('') + кускиПодписей.join('');
  return вФигуру(внутри, ширинаSVG, высотаSVG, подпись, `<defs>${ОСТРИЁ_ЗАКРАШЕННОЕ}</defs>`);
}

/* Наконечники. Закрашенный достался от flowchart и у стрелок последовательности
   значит вызов; простой — только у `->` и `-->`. */
const ОСТРИЁ_ЗАКРАШЕННОЕ =
  '<marker id="nakonechnik" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path class="arrowhead" d="M0 1 L9 5 L0 9 z"/></marker>';
const ОСТРИЁ_ПРОСТОЕ =
  '<marker id="ostrie" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="8" markerHeight="8" orient="auto-start-reverse"><path class="arrowhead-line" d="M1 1 L9 5 L1 9"/></marker>';

/** Обёртка `<figure>` с SVG, заголовком и подписью — одна на оба рода схем. */
function вФигуру(внутренности, ширинаSVG, высотаSVG, подпись, defs) {
  const заголовок = подпись ? `<title>${экранировать(подпись)}</title>` : '';
  const роль = подпись ? `role="img" aria-label="${экранировать(подпись)}"` : 'role="img"';
  return (
    `<figure class="shema">` +
    `<svg ${роль} viewBox="0 0 ${ширинаSVG.toFixed(0)} ${высотаSVG.toFixed(0)}" width="${ширинаSVG.toFixed(0)}" height="${высотаSVG.toFixed(0)}" xmlns="http://www.w3.org/2000/svg">` +
    заголовок +
    defs +
    внутренности +
    `</svg>` +
    (подпись ? `<figcaption>${экранировать(подпись)}</figcaption>` : '') +
    `</figure>`
  );
}

// ── Диаграмма последовательности (sequenceDiagram) ──────────────────────────
//
// Второй род схемы: кто кому что шлёт и в каком порядке. Разбор и раскладка
// здесь свои, а мера текста, разбивка подписи на строки, обёртка `<figure>` и
// наконечники — общие с flowchart выше. Второго измерителя ширины заводить
// нельзя: два рода схем на одной странице разъедутся в мелочи, и заметит это
// читатель.
//
// ЧТО ПОДДЕРЖАНО, и ни строкой больше:
//   sequenceDiagram              шапка; по ней схема и отличается от flowchart
//   participant A as Подпись     столбец; порядок объявления — слева направо
//   participant A                подпись равна имени
//   A->>B: текст                 сплошная стрелка, закрашенное остриё (вызов)
//   A-->>B: текст                пунктирная стрелка, закрашенное остриё (ответ)
//   A->B: текст                  сплошная, простое остриё
//   A-->B: текст                 пунктирная, простое остриё
//   A->>A: текст                 петля справа от своей линии жизни
//   Note over A: текст           подпись поверх линии жизни
//   Note over A,B: текст         поверх двух столбцов
//   Note left of A: текст        сбоку от линии жизни
//   Note right of A: текст
//   loop подпись … end           рамка с ярлыком в левом верхнем углу
//   alt подпись … else подпись … end
//   opt подпись … end
//   %% комментарий
//   <br> внутри подписи          перенос строки вручную
//
// Участник, встреченный в стрелке или заметке и не объявленный, заводится на
// месте и встаёт столбцом правее прежних — так делает и настоящий mermaid.
//
// ЧЕГО НЕТ НАМЕРЕННО: активаций (`activate`/`deactivate`, `+` и `-` на
// стрелках), автонумерации (`autonumber`), участников-актёров (`actor`),
// ссылок и кликов, `par`, `critical`, `break`, `rect`, `box`. Ни одного случая
// не понадобилось.
//
// Непонятая строка — ОТКАЗ сборки с номером строки, как и у flowchart. Схема,
// отрисованная наполовину, хуже отсутствующей: она врёт молча.

/* 11.5px у подписей на стрелках и в заметках против КЕГЛЬ=13, на который
   меряет `ширина`; числа — из раздела про схемы в style.css. */
const МЕЛКИЙ = 0.885;
const МЕЖСТРОЧНЫЙ_МЕЛКИЙ = 14;
const МИН_ШИРИНА_СТОЛБЦА = 74;
const ЗАЗОР_СТОЛБЦОВ = 34;
const ВЕРХ_ПОТОКА = 24; // от низа шапок до первой стрелки
const НАД_СТРЕЛКОЙ = 8; // от верха подписи до отведённого ей места
const ПОДПИСЬ_НАД = 7; // от базовой линии нижней строки подписи до линии стрелки
const ПОД_СТРЕЛКОЙ = 18;
const ПЕТЛЯ_Ш = 34;
const ПЕТЛЯ_В = 26;
const ЗАМЕТКА_ОТСТУП_X = 12;
const ЗАМЕТКА_ОТСТУП_Y = 8;
const ЗАЗОР_ЗАМЕТКИ = 16; // на сколько заметка вылезает за линию жизни
const ВОКРУГ_ЗАМЕТКИ = 8;
const РАМКА_ПОЛЕ_X = 14;
const РАМКА_ЯРЛЫК = 24; // высота строки с ярлыком внутри рамки
const РАМКА_НИЗ = 12;
const ПОСЛЕ_РАМКИ = 8;

const ИМЯ_УЧАСТНИКА = /^[\p{L}\p{N}_]+$/u;

/*
 * Ширина надписи мелким кеглем — с запасом на неточность замера.
 *
 * `ширина` меряет приблизительно, шрифт выбирает браузер. У flowchart этого
 * хватает: там надпись только центрируется, и ошибка расходится симметрично.
 * Здесь же мера решает, ВЛЕЗЕТ ли надпись в подложку, в заметку и в рамку, —
 * заниженная мера значит, что не влезет.
 *
 * Запас снят прогоном по DejaVu Sans, самому широкому из стопки `--sans`
 * (`magick -font DejaVu-Sans -pointsize 11.5 label:… -format %w`, 13 подписей
 * этих схем): замер занижает ширину в среднем в 1,124 раза, худший случай —
 * 1,204 у «цель и допущения». Взят худший: подпись, вылезшая за подложку,
 * стоит дороже лишних восьми точек поля.
 */
const ЗАПАС_ЗАМЕРА = 1.2;
function мераМелко(текст) {
  return ширина(текст) * МЕЛКИЙ * ЗАПАС_ЗАМЕРА;
}

/** Ширина самой длинной строки подписи. */
function ширинаМелко(строкиПодписи) {
  return строкиПодписи.length ? Math.max(...строкиПодписи.map(мераМелко)) : 0;
}

/** Подпись рамки с подложкой: без неё линия жизни идёт прямо сквозь буквы. */
function подписьРамки({ отступ, текст }, x1, база) {
  if (!текст) return '';
  const x = x1 + отступ;
  return (
    `<rect class="edge-label-bg" x="${(x - 4).toFixed(1)}" y="${(база - 12).toFixed(1)}" width="${(мераМелко(текст) + 8).toFixed(1)}" height="16" rx="4"/>` +
    `<text class="frame-label" x="${x.toFixed(1)}" y="${база.toFixed(1)}">${экранировать(текст)}</text>`
  );
}

/**
 * Разбор исходника диаграммы последовательности в участников и шаги.
 * Непонятая строка — исключение с её номером и ею самой.
 */
export function разобратьПоследовательность(исходник) {
  const все = String(исходник).split('\n');
  const участники = new Map();
  const корень = [];
  // Стопка открытых рамок. Внизу лежит сама схема — тогда у шага всегда есть
  // адресат, и спрашивать «а есть ли открытая рамка» не приходится нигде.
  const стопка = [{ шаги: корень }];
  let шапкаБыла = false;

  const участник = (имя, номер) => {
    const и = имя.trim();
    if (!ИМЯ_УЧАСТНИКА.test(и)) throw new Error(`строка ${номер}: непонятное имя участника «${и}»`);
    if (!участники.has(и)) участники.set(и, { имя: и, подпись: и });
    return участники.get(и);
  };
  const добавить = (шаг) => стопка[стопка.length - 1].шаги.push(шаг);

  for (let н = 0; н < все.length; н += 1) {
    const строка = все[н].trim();
    const номер = н + 1;
    if (!строка || строка.startsWith('%%')) continue;

    if (/^sequenceDiagram$/.test(строка)) {
      if (шапкаБыла) throw new Error(`строка ${номер}: вторая шапка схемы`);
      шапкаБыла = true;
      continue;
    }
    if (!шапкаБыла) throw new Error(`строка ${номер}: схема начинается не с «sequenceDiagram»`);

    const объявление = /^participant\s+(\S+)(?:\s+as\s+([\s\S]+))?$/.exec(строка);
    if (объявление) {
      const у = участник(объявление[1], номер);
      if (объявление[2]) у.подпись = объявление[2].trim();
      continue;
    }

    const заметка = /^note\s+(over|left of|right of)\s+([^:]+):([\s\S]*)$/i.exec(строка);
    if (заметка) {
      const где = заметка[1].toLowerCase();
      const имена = заметка[2].split(',').map((с) => с.trim()).filter(Boolean);
      if (!имена.length) throw new Error(`строка ${номер}: заметка ни над кем: «${строка}»`);
      if (где !== 'over' && имена.length > 1) {
        throw new Error(`строка ${номер}: «${где}» берёт одного участника, названо ${имена.length}: «${строка}»`);
      }
      if (имена.length > 2) {
        throw new Error(
          `строка ${номер}: «Note over» берёт одного или двух участников, названо ${имена.length}: «${строка}»`,
        );
      }
      добавить({
        вид: 'заметка',
        размещение: где === 'over' ? 'над' : где === 'left of' ? 'слева' : 'справа',
        участники: имена.map((и) => участник(и, номер).имя),
        подпись: заметка[3].trim(),
      });
      continue;
    }

    const стрелка = /^([\p{L}\p{N}_]+)\s*(-->>|->>|-->|->)\s*([\p{L}\p{N}_]+)\s*:([\s\S]*)$/u.exec(строка);
    if (стрелка) {
      добавить({
        вид: 'стрелка',
        из: участник(стрелка[1], номер).имя,
        в: участник(стрелка[3], номер).имя,
        пунктир: стрелка[2].startsWith('--'),
        остриё: стрелка[2].endsWith('>>') ? 'закрашенное' : 'простое',
        подпись: стрелка[4].trim(),
      });
      continue;
    }

    const открытие = /^(loop|alt|opt)(?:\s([\s\S]*))?$/.exec(строка);
    if (открытие) {
      const рамка = {
        вид: 'рамка',
        род: открытие[1],
        номер,
        ветви: [{ подпись: (открытие[2] || '').trim(), шаги: [] }],
      };
      добавить(рамка);
      стопка.push({ рамка, шаги: рамка.ветви[0].шаги });
      continue;
    }

    const иначе = /^else(?:\s([\s\S]*))?$/.exec(строка);
    if (иначе) {
      const верх = стопка[стопка.length - 1];
      if (!верх.рамка || верх.рамка.род !== 'alt') {
        throw new Error(`строка ${номер}: «else» вне «alt»: «${строка}»`);
      }
      const ветвь = { подпись: (иначе[1] || '').trim(), шаги: [] };
      верх.рамка.ветви.push(ветвь);
      верх.шаги = ветвь.шаги;
      continue;
    }

    if (/^end$/.test(строка)) {
      if (стопка.length === 1) throw new Error(`строка ${номер}: «end» без открытой рамки`);
      стопка.pop();
      continue;
    }

    throw new Error(`строка ${номер}: не разобрать «${строка}»`);
  }

  if (!шапкаБыла) throw new Error('пустая схема: нет строки «sequenceDiagram»');
  if (стопка.length > 1) {
    const открыта = стопка[стопка.length - 1].рамка;
    throw new Error(`строка ${открыта.номер}: рамка «${открыта.род}» не закрыта словом «end»`);
  }
  if (!участники.size) throw new Error('в схеме нет ни одного участника');
  return { участники: [...участники.values()], шаги: корень };
}

/** Рисует разобранную диаграмму последовательности в SVG. */
export function нарисоватьПоследовательность(схема, подпись) {
  const { участники, шаги } = схема;
  const место = new Map(участники.map((у, и) => [у.имя, и]));

  for (const у of участники) {
    у.строки = строки(у.подпись);
    у.ш = Math.max(МИН_ШИРИНА_СТОЛБЦА, Math.max(...у.строки.map(ширина)) + ОТСТУП_X * 2);
  }
  const высотаШапки = Math.max(...участники.map((у) => у.строки.length)) * МЕЖСТРОЧНЫЙ + ОТСТУП_Y * 2;

  // ── Где стоят линии жизни ─────────────────────────────────────────────────
  // Столбцы расставляются ДО отрисовки, потому что ширину задаёт не только
  // шапка: подпись на стрелке, заметка и петля «сам себе» обязаны поместиться
  // между соседями, иначе они лягут на чужую линию жизни. Каждое требование —
  // это «между такими-то столбцами не меньше стольких-то точек», и оно
  // раскладывается поровну на промежутки, которые перекрывает.
  const расстояние = [];
  for (let и = 0; и + 1 < участники.length; и += 1) {
    расстояние.push(участники[и].ш / 2 + участники[и + 1].ш / 2 + ЗАЗОР_СТОЛБЦОВ);
  }
  const требовать = (а, б, нужно) => {
    if (а === б) return;
    const [л, п] = а < б ? [а, б] : [б, а];
    const доля = нужно / (п - л);
    for (let и = л; и < п; и += 1) расстояние[и] = Math.max(расстояние[и], доля);
  };
  const обойти = (список, дело) => {
    for (const ш of список) {
      if (ш.вид === 'рамка') for (const в of ш.ветви) обойти(в.шаги, дело);
      else дело(ш);
    }
  };
  обойти(шаги, (ш) => {
    if (ш.вид === 'стрелка') {
      const стр = ш.подпись ? строки(ш.подпись) : [];
      const а = место.get(ш.из);
      const б = место.get(ш.в);
      if (а !== б) требовать(а, б, ширинаМелко(стр) + 16);
      else if (а + 1 < участники.length) {
        // Петля с подписью вылетает вправо и обязана не дойти до соседа.
        требовать(а, а + 1, ПЕТЛЯ_Ш + 8 + ширинаМелко(стр) + 6 + участники[а + 1].ш / 2);
      }
      return;
    }
    const своя = ширинаМелко(строки(ш.подпись)) + ЗАМЕТКА_ОТСТУП_X * 2;
    // `Note over Б,А` законно написать и справа налево — важны столбцы, не порядок слов.
    const места = ш.участники.map((и) => место.get(и));
    const а = Math.min(...места);
    const б = Math.max(...места);
    if (ш.размещение === 'над') {
      if (а !== б) требовать(а, б, своя - ЗАЗОР_ЗАМЕТКИ * 2);
      else {
        if (а > 0) требовать(а - 1, а, своя / 2 + участники[а - 1].ш / 2 + 8);
        if (а + 1 < участники.length) требовать(а, а + 1, своя / 2 + участники[а + 1].ш / 2 + 8);
      }
    } else if (ш.размещение === 'справа') {
      if (а + 1 < участники.length) требовать(а, а + 1, своя + ЗАЗОР_ЗАМЕТКИ + 8 + участники[а + 1].ш / 2);
    } else if (а > 0) {
      требовать(а - 1, а, своя + ЗАЗОР_ЗАМЕТКИ + 8 + участники[а - 1].ш / 2);
    }
  });

  let шагX = ПОЛЕ + участники[0].ш / 2;
  участники[0].цx = шагX;
  for (let и = 1; и < участники.length; и += 1) {
    шагX += расстояние[и - 1];
    участники[и].цx = шагX;
  }

  // ── Отрисовка ─────────────────────────────────────────────────────────────
  const кускиРамок = [];
  const кускиСтрелок = [];
  const кускиЗаметок = [];
  const кускиПодписей = [];
  const последний = участники[участники.length - 1];
  let левее = ПОЛЕ;
  let правее = последний.цx + последний.ш / 2;
  let y = ПОЛЕ + высотаШапки + ВЕРХ_ПОТОКА;

  /* Подпись стоит НАД линией стрелки и по центру, подложкой скрывая линии
     жизни, которые стрелка пересекает. Нижняя строка подписи — ближайшая к
     стрелке, поэтому строки отсчитываются от линии вверх. */
  const подписатьСтрелку = (стр, сx, линия) => {
    if (!стр.length) return;
    // Подложка ОДНА на всю подпись, а не по подложке на строку: у соседних
    // строк они перекрывались бы, и сторож координат читал бы это как наезд
    // двух разных подписей.
    const своя = ширинаМелко(стр) + 10;
    const перваяБаза = линия + (1 - стр.length) * МЕЖСТРОЧНЫЙ_МЕЛКИЙ - ПОДПИСЬ_НАД;
    кускиПодписей.push(
      `<rect class="edge-label-bg" x="${(сx - своя / 2).toFixed(1)}" y="${(перваяБаза - 12).toFixed(1)}" width="${своя.toFixed(1)}" height="${((стр.length - 1) * МЕЖСТРОЧНЫЙ_МЕЛКИЙ + 16).toFixed(1)}" rx="4"/>` +
        стр
          .map(
            (с, н) =>
              `<text class="edge-label" x="${сx.toFixed(1)}" y="${(перваяБаза + н * МЕЖСТРОЧНЫЙ_МЕЛКИЙ).toFixed(1)}">${экранировать(с)}</text>`,
          )
          .join(''),
    );
  };

  /** Раскладывает список шагов сверху вниз; отдаёт занятую ими полосу по x. */
  const разложить = (список) => {
    let л = Infinity;
    let п = -Infinity;
    const шире = (а, б) => {
      л = Math.min(л, а);
      п = Math.max(п, б);
    };

    for (const ш of список) {
      if (ш.вид === 'стрелка') {
        const а = участники[место.get(ш.из)];
        const б = участники[место.get(ш.в)];
        const стр = ш.подпись ? строки(ш.подпись) : [];
        const класс = `edge${ш.пунктир ? ' dashed' : ''}`;
        const остриё = ш.остриё === 'закрашенное' ? 'nakonechnik' : 'ostrie';

        if (а === б) {
          const верх = y + 6;
          const низ = верх + ПЕТЛЯ_В;
          кускиСтрелок.push(
            `<path class="${класс}" d="M${а.цx.toFixed(1)} ${верх.toFixed(1)} H${(а.цx + ПЕТЛЯ_Ш).toFixed(1)} V${низ.toFixed(1)} H${(а.цx + 1).toFixed(1)}" marker-end="url(#${остриё})"/>`,
          );
          стр.forEach((с, н) => {
            const база =
              верх + ПЕТЛЯ_В / 2 - ((стр.length - 1) * МЕЖСТРОЧНЫЙ_МЕЛКИЙ) / 2 + н * МЕЖСТРОЧНЫЙ_МЕЛКИЙ + 4;
            кускиПодписей.push(
              `<text class="edge-label sleva" x="${(а.цx + ПЕТЛЯ_Ш + 8).toFixed(1)}" y="${база.toFixed(1)}">${экранировать(с)}</text>`,
            );
          });
          шире(а.цx, а.цx + ПЕТЛЯ_Ш + 8 + ширинаМелко(стр));
          y = низ + ПОД_СТРЕЛКОЙ;
          continue;
        }

        y += стр.length * МЕЖСТРОЧНЫЙ_МЕЛКИЙ + НАД_СТРЕЛКОЙ;
        const линия = y;
        const вправо = б.цx > а.цx;
        кускиСтрелок.push(
          `<path class="${класс}" d="M${а.цx.toFixed(1)} ${линия.toFixed(1)} H${(б.цx + (вправо ? -1 : 1)).toFixed(1)}" marker-end="url(#${остриё})"/>`,
        );
        const середина = (а.цx + б.цx) / 2;
        подписатьСтрелку(стр, середина, линия);
        шире(Math.min(а.цx, б.цx), Math.max(а.цx, б.цx));
        if (стр.length) шире(середина - ширинаМелко(стр) / 2 - 5, середина + ширинаМелко(стр) / 2 + 5);
        y = линия + ПОД_СТРЕЛКОЙ;
        continue;
      }

      if (ш.вид === 'заметка') {
        const стр = строки(ш.подпись);
        const места = ш.участники.map((и) => место.get(и));
        const а = участники[Math.min(...места)];
        const б = участники[Math.max(...места)];
        const своя = ширинаМелко(стр) + ЗАМЕТКА_ОТСТУП_X * 2;
        let x1;
        let x2;
        if (ш.размещение === 'над' && а !== б) {
          x1 = а.цx - ЗАЗОР_ЗАМЕТКИ;
          x2 = б.цx + ЗАЗОР_ЗАМЕТКИ;
        } else if (ш.размещение === 'над') {
          x1 = а.цx - своя / 2;
          x2 = а.цx + своя / 2;
        } else if (ш.размещение === 'справа') {
          x1 = а.цx + ЗАЗОР_ЗАМЕТКИ;
          x2 = x1 + своя;
        } else {
          x2 = а.цx - ЗАЗОР_ЗАМЕТКИ;
          x1 = x2 - своя;
        }
        y += ВОКРУГ_ЗАМЕТКИ;
        const высота = стр.length * МЕЖСТРОЧНЫЙ_МЕЛКИЙ + ЗАМЕТКА_ОТСТУП_Y * 2;
        кускиЗаметок.push(
          `<rect class="note" x="${x1.toFixed(1)}" y="${y.toFixed(1)}" width="${(x2 - x1).toFixed(1)}" height="${высота.toFixed(1)}" rx="4"/>` +
            стр
              .map(
                (с, н) =>
                  `<text class="note-text" x="${((x1 + x2) / 2).toFixed(1)}" y="${(y + ЗАМЕТКА_ОТСТУП_Y + 11 + н * МЕЖСТРОЧНЫЙ_МЕЛКИЙ).toFixed(1)}">${экранировать(с)}</text>`,
              )
              .join(''),
        );
        шире(x1, x2);
        y += высота + ВОКРУГ_ЗАМЕТКИ;
        continue;
      }

      /* Рамка. Вложенные шаги раскладываются ПЕРВЫМИ, и уже по занятой ими
         полосе считается ширина самой рамки — поэтому вложенная рамка выходит
         уже внешней сама, без счёта глубины. */
      const верх = y;
      const разделители = [];
      let вл = Infinity;
      let вп = -Infinity;
      ш.ветви.forEach((ветвь, н) => {
        if (н > 0) {
          y += 6;
          разделители.push({ y, подпись: ветвь.подпись });
          y += РАМКА_ЯРЛЫК - 6;
        } else y += РАМКА_ЯРЛЫК;
        const своё = разложить(ветвь.шаги);
        вл = Math.min(вл, своё.л);
        вп = Math.max(вп, своё.п);
      });
      y += РАМКА_НИЗ;
      const низ = y;
      if (!Number.isFinite(вл)) {
        вл = участники[0].цx;
        вп = последний.цx;
      }
      const ярлык = мераМелко(ш.род) + 14;
      // Первая ветвь подписана рядом с ярлыком, остальные — под разделителем и
      // со словом «else»: ширины рамке нужно столько, чтобы влезли обе.
      const подписи = ш.ветви.map((в, н) => ({
        отступ: н === 0 ? ярлык + 8 : 8,
        текст: в.подпись && (н === 0 ? в.подпись : `else ${в.подпись}`),
      }));
      const x1 = вл - РАМКА_ПОЛЕ_X;
      const x2 = Math.max(
        вп + РАМКА_ПОЛЕ_X,
        ...подписи.map((п) => (п.текст ? x1 + п.отступ + мераМелко(п.текст) + 12 : 0)),
      );
      кускиРамок.push(
        `<rect class="frame" x="${x1.toFixed(1)}" y="${верх.toFixed(1)}" width="${(x2 - x1).toFixed(1)}" height="${(низ - верх).toFixed(1)}" rx="4"/>` +
          `<rect class="frame-tag" x="${x1.toFixed(1)}" y="${верх.toFixed(1)}" width="${ярлык.toFixed(1)}" height="17" rx="4"/>` +
          `<text class="frame-tag-text" x="${(x1 + ярлык / 2).toFixed(1)}" y="${(верх + 12.5).toFixed(1)}">${экранировать(ш.род)}</text>` +
          подписьРамки(подписи[0], x1, верх + 13),
      );
      разделители.forEach((р, н) => {
        кускиРамок.push(
          `<path class="frame-split" d="M${x1.toFixed(1)} ${р.y.toFixed(1)} H${x2.toFixed(1)}"/>` +
            подписьРамки(подписи[н + 1], x1, р.y + 14),
        );
      });
      шире(x1, x2);
      y = низ + ПОСЛЕ_РАМКИ;
    }

    return { л, п };
  };

  const полоса = разложить(шаги);
  if (Number.isFinite(полоса.л)) {
    левее = Math.min(левее, полоса.л);
    правее = Math.max(правее, полоса.п);
  }

  const низСхемы = y + 4;
  // Заметка слева от первого столбца уходит за левый край; вместо того чтобы
  // двигать каждую координату, двигается вся схема разом.
  const сдвиг = Math.max(0, ПОЛЕ - левее);
  const ширинаSVG = правее + сдвиг + ПОЛЕ;
  const высотаSVG = низСхемы + ПОЛЕ;

  const шапки = участники
    .map((у) => {
      const первая = ПОЛЕ + высотаШапки / 2 - ((у.строки.length - 1) * МЕЖСТРОЧНЫЙ) / 2 + 4.5;
      return (
        `<rect class="node" x="${(у.цx - у.ш / 2).toFixed(1)}" y="${ПОЛЕ}" width="${у.ш.toFixed(1)}" height="${высотаШапки.toFixed(1)}" rx="5"/>` +
        у.строки
          .map(
            (с, н) =>
              `<text class="node-text" x="${у.цx.toFixed(1)}" y="${(первая + н * МЕЖСТРОЧНЫЙ).toFixed(1)}">${экранировать(с)}</text>`,
          )
          .join('')
      );
    })
    .join('');
  const жизни = участники
    .map((у) => `<path class="life" d="M${у.цx.toFixed(1)} ${ПОЛЕ + высотаШапки} V${низСхемы.toFixed(1)}"/>`)
    .join('');

  const внутри =
    `<g transform="translate(${сдвиг.toFixed(1)} 0)">` +
    жизни +
    кускиРамок.join('') +
    кускиСтрелок.join('') +
    кускиЗаметок.join('') +
    шапки +
    кускиПодписей.join('') +
    `</g>`;
  return вФигуру(внутри, ширинаSVG, высотаSVG, подпись, `<defs>${ОСТРИЁ_ЗАКРАШЕННОЕ}${ОСТРИЁ_ПРОСТОЕ}</defs>`);
}

/**
 * Полный путь: исходник mermaid → SVG.
 * Бросает исключение с внятной строкой, если схему не разобрать.
 *
 * Род схемы выбирается по первой содержательной строке — ровно так же, как его
 * читает сам mermaid: `sequenceDiagram` или `flowchart`/`graph`.
 */
export function схемаВSVG(исходник, подпись) {
  const первая =
    String(исходник)
      .split('\n')
      .map((с) => с.trim())
      .find((с) => с && !с.startsWith('%%')) || '';
  if (/^sequenceDiagram(?:\s|$)/.test(первая)) {
    return нарисоватьПоследовательность(разобратьПоследовательность(исходник), подпись);
  }
  return нарисовать(разобратьСхему(исходник), подпись);
}
