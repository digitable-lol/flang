/* ── Разбор таблицы из источника: разделы и порядок ──────────────────────── */

/**
 * Понятия в порядке таблицы, с разделом каждого.
 *
 * Разбор ПРОВЕРЯЕТ себя: набор найденных понятий обязан совпасть с `KEYWORDS`
 * в точности. Разбор, потерявший половину таблицы, напечатал бы половину
 * словаря и промолчал — ровно то, ради чего этот файл написан.
 */
export function разобратьТаблицу() {
  const строки = readFileSync(КОРЕНЬ + ИСТОЧНИК, "utf8").split("\n")
  const порядок = []
  const найдены = new Set()
  let раздел = null
  for (const строка of строки) {
    const заголовок = /^ {2}\/\/ ── (.+?) ─+$/u.exec(строка)
    if (заголовок) {
      раздел = заголовок[1].trim()
      continue
    }
    const понятие = /^ {2}([A-Za-z][A-Za-z0-9]*): \{/u.exec(строка)
    if (!понятие) continue
    const ид = понятие[1]
    if (!Object.hasOwn(KEYWORDS, ид) || найдены.has(ид)) continue
    найдены.add(ид)
    порядок.push({ ид, раздел })
  }

  const вТаблице = Object.keys(KEYWORDS)
  const потеряны = вТаблице.filter((и) => !найдены.has(и))
  if (потеряны.length) {
    throw new Error(
      `разбор ${ИСТОЧНИК} потерял понятия: ${потеряны.join(", ")}. ` +
        `Разбор половины таблицы напечатал бы половину словаря и промолчал.`,
    )
  }
  const безРаздела = порядок.filter((п) => !п.раздел).map((п) => п.ид)
  if (безРаздела.length) throw new Error(`понятия вне раздела таблицы: ${безРаздела.join(", ")}`)
  return порядок
}

/** Сторож полноты: у каждого понятия таблицы обязано быть пояснение. */
export function проверитьПолноту() {
  const нет = Object.keys(KEYWORDS).filter((ид) => !ПОЯСНЕНИЯ[ид])
  const лишние = Object.keys(ПОЯСНЕНИЯ).filter((ид) => !Object.hasOwn(KEYWORDS, ид))
  const беды = []
  if (нет.length) {
    беды.push(
      `в таблице есть, а в словаре нет — ${нет.length}: ${нет.join(", ")}\n` +
        `  Впишите пояснение в ПОЯСНЕНИЯ (${СТРАНИЦА.replace(/\.md$/u, ".mjs")} → docs/site/glossary.mjs).`,
    )
  }
  if (лишние.length) {
    беды.push(`в словаре есть, а в таблице нет — ${лишние.length}: ${лишние.join(", ")}`)
  }
  return беды
}

/* ── Печать страницы ─────────────────────────────────────────────────────── */

const экранировать = (т) => String(т).replace(/\|/gu, "\\|")

export function напечатать() {
  const порядок = разобратьТаблицу()
  const беды = проверитьПолноту()
  if (беды.length) throw new Error(беды.join("\n"))

  const покрытие = { 1: 0, 2: 0, 3: 0, 4: 0 }
  for (const { ид } of порядок) покрытие[SURFACE_ORDER.filter((п) => wordOn(ид, п) !== null).length]++
  const всего = порядок.length
  const доля = ((покрытие[4] / всего) * 100).toFixed(1)

  const ч = []
  ч.push("# Словарь языка")
  ч.push("")
  ч.push(
    /* ИМЁН ФАЙЛОВ РЕАЛИЗАЦИИ ЗДЕСЬ НЕТ, и это не забывчивость. Словарь описывает
       понятия ЯЗЫКА, а читатель, встречающий на странице языка `lexer.mjs`,
       делает единственный возможный вывод — что язык сделан на другом языке.
       Где лежит таблица и чем сверяется страница, сказано в разделе про
       устройство, а не между читателем и первым словом словаря. */
    "Все слова flang: слово, четыре поверхности записи, что делает и куда ведёт. " +
      "Страница **печатается** из таблицы поверхностей — той единственной, по которой " +
      "разбирается любой файл на flang. Руками её не правят: правку затрёт следующая " +
      "сборка, а проверка свежести не даст странице молча разойтись с таблицей.",
  )
  ч.push("")
  ч.push(`Понятий в таблице — **${всего}**. На всех четырёх поверхностях открыто **${покрытие[4]}** (${доля} %).`)
  ч.push(
    `На трёх — ${покрытие[3]}, на двух — ${покрытие[2]}, на одной — ${покрытие[1]}. ` +
      "Пустая клетка значит, что слова на этой поверхности **нет**, и это решение, а не пропуск: " +
      "придуманное слово хуже отсутствующего. Чем именно дырява таблица — на странице " +
      "[Четыре поверхности](surfaces.html).",
  )
  ч.push("")

  let раздел = null
  for (const { ид, раздел: р } of порядок) {
    if (р !== раздел) {
      раздел = р
      ч.push("")
      ч.push(`## ${раздел[0].toUpperCase()}${раздел.slice(1)}`)
      ч.push("")
      const куда = КУДА[раздел]
      if (куда) ч.push(`Ведёт: [${куда[1]}](${куда[0]}).`)
      ч.push("")
      ч.push(`| ${ПОВЕРХНОСТИ.map(([, имя]) => имя).join(" | ")} | Что делает |`)
      ч.push(`|${" --- |".repeat(ПОВЕРХНОСТИ.length + 1)}`)
    }
    const клетки = ПОВЕРХНОСТИ.map(([код]) => {
      const слово = wordOn(ид, код)
      if (!слово) return "—"
      // Синонимы: все прочие фразы этой поверхности, кроме первой.
      const прочие = KEYWORDS[ид].filter((ф) => ф !== слово && surfaceOfPhrase(ф) === код)
      const всё = [слово, ...прочие].map((ф) => `\`${экранировать(ф)}\``)
      return всё.join(", ")
    })
    ч.push(`| ${клетки.join(" | ")} | ${экранировать(ПОЯСНЕНИЯ[ид])} |`)
  }

  ч.push("")
  ч.push("---")
  ч.push("")
  ч.push(
    "Собрано из таблицы поверхностей печатью, а не набрано руками: слово, добавленное " +
      "в таблицу и не попавшее сюда, роняет сборку. Что проверка свежести умеет краснеть, " +
      "проверено отдельно — ей подкладывают лишнее понятие и испорченную страницу и " +
      "требуют отказа в обоих случаях. Чем таблица дырява и почему пустая клетка — " +
      "решение, а не пропуск: [Четыре поверхности записи](surfaces.html).",
  )
  ч.push("")
  return ч.join("\n")
}

/* ── Запуск ──────────────────────────────────────────────────────────────── */

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const проверка = process.argv.includes("--check")
  let текст
  try {
    текст = напечатать()
  } catch (беда) {
    console.error("Словарь ОТКАЗЫВАЕТ:")
    console.error("  · " + беда.message.split("\n").join("\n    "))
    process.exit(1)
  }

  if (!проверка) {
    writeFileSync(КОРЕНЬ + СТРАНИЦА, текст)
    console.log(`Словарь напечатан в ${СТРАНИЦА}: понятий ${Object.keys(KEYWORDS).length}.`)
    process.exit(0)
  }

  let записано = null
  try {
    записано = readFileSync(КОРЕНЬ + СТРАНИЦА, "utf8")
  } catch {
    console.error(`Словарь ОТКАЗЫВАЕТ: файла ${СТРАНИЦА} нет. Соберите: node docs/site/glossary.mjs`)
    process.exit(1)
  }
  if (записано !== текст) {
    console.error(`Словарь ОТКАЗЫВАЕТ: ${СТРАНИЦА} разошёлся с таблицей поверхностей.`)
    console.error("  Таблицу правили, словарь не пересобрали. Соберите: node docs/site/glossary.mjs")
    process.exit(1)
  }
  console.log(`словарь: чисто — ${СТРАНИЦА} сходится с таблицей, понятий ${Object.keys(KEYWORDS).length}.`)
}
