// Замер контраста подсветки flang — по формуле WCAG, а не на глаз.
//
// ── Зачем прогон, если цвета видно ──────────────────────────────────────────
// Приглушённый и нечитаемый различаются ТОЛЬКО числом: цвет, который в файле
// выглядит «просто спокойным», на своей подложке может давать 1.2 при норме
// 4.5, и чтением файла это не ловится. Так и вышло у Digitable, чью палитру
// эта таблица стилей теперь и берёт: замер нашёл 60 мест ниже нормы на ОДНОЙ
// статье (строка #032f62 на карточке #182027 — 1.24:1), и нашёл их уже после
// выкатки. Причина была одна: подсветка следовала за темой страницы, а
// карточка кода за темой не следовала.
//
// ── Что проверяется здесь ───────────────────────────────────────────────────
// 1. Полнота. Палитра карточки объявлена ЦЕЛИКОМ в каждом из трёх мест темы:
//    `:root`, `@media (prefers-color-scheme: dark) :root:not([data-theme=…])`
//    и `:root[data-theme="dark"]` — последнее и есть ветка живого
//    переключателя в шапке. Пропуск любой строки в любом из трёх — отказ:
//    так и получается половина темы.
// 2. Происхождение. Каждая роль обязана приезжать из фирменного токена
//    `--digitable-*`, а не из своего числа. Иначе слой токенов ничего не
//    держит: правка палитры на портале снова придётся искать по файлу.
// 3. Контраст. Каждый цвет ТЕКСТА карточки — к подложке САМОЙ КАРТОЧКИ,
//    в каждой из трёх тем, норма 4.5:1.
// 4. Несмешение. Цвет карточки не имеет права появиться вне карточки, а
//    карточка — покраситься палитрой страницы. Проверяется по селекторам:
//    `--flang-*` только там, где в селекторе есть `pre`; и наоборот, `pre`
//    красится только из `--flang-kod-*`.
//
// Рамка карточки (`--flang-kod-ramka`) под норму 4.5 не подводится и подводить
// её нечем: это не текст, а граница. Её число печатается справочно.

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Роли, которые обязаны быть объявлены в каждом месте темы. */
const ОБЯЗАТЕЛЬНЫЕ = [
  '--flang-kod-fon',
  '--flang-kod-tekst',
  '--flang-kod-ramka',
  '--flang-syn-slovo',
  '--flang-syn-imya',
  '--flang-syn-stroka',
  '--flang-syn-chislo',
  '--flang-syn-zametka',
];

/** Что из этого — ТЕКСТ на карточке (для него и норма 4.5). */
const ТЕКСТ = ОБЯЗАТЕЛЬНЫЕ.filter((и) => и !== '--flang-kod-fon' && и !== '--flang-kod-ramka');

const НОРМА = 4.5;

/** Человеческие имена ролей — для таблицы. */
export const РОЛИ = {
  '--flang-kod-tekst': 'текст карточки',
  '--flang-syn-slovo': 'ключевое слово',
  '--flang-syn-imya': 'имя в ёлочках',
  '--flang-syn-stroka': 'строка',
  '--flang-syn-chislo': 'число',
  '--flang-syn-zametka': 'комментарий',
};

/* ── Разбор CSS ──────────────────────────────────────────────────────────────
   Полноценный парсер здесь не нужен и был бы вторым описанием формата: нужно
   ровно две вещи — «какие переменные объявлены в этом селекторе» и «какой
   селектор что красит». Комментарии снимаются заранее, поэтому фигурные
   скобки внутри прозы (а её здесь много) разбору не мешают. */

const безКомментариев = (css) => css.replace(/\/\*[\s\S]*?\*\//gu, '');

/**
 * Правила таблицы: `{ обёртка, селектор, тело }`.
 * `обёртка` — селектор внешнего `@media`, если правило внутри него.
 */
function правила(css, обёртка = '') {
  const итог = [];
  let п = 0;
  while (п < css.length) {
    const открытие = css.indexOf('{', п);
    if (открытие === -1) break;
    let глубина = 1;
    let к = открытие + 1;
    while (к < css.length && глубина > 0) {
      if (css[к] === '{') глубина += 1;
      else if (css[к] === '}') глубина -= 1;
      к += 1;
    }
    const селектор = css.slice(п, открытие).trim();
    const тело = css.slice(открытие + 1, к - 1);
    if (селектор.startsWith('@')) итог.push(...правила(тело, селектор));
    else итог.push({ обёртка, селектор, тело });
    п = к;
  }
  return итог;
}

/** Объявления переменных внутри тела правила: `--имя: значение;`. */
function переменные(тело) {
  const карта = new Map();
  for (const [, имя, значение] of тело.matchAll(/(--[\w-]+)\s*:\s*([^;}]+)[;}]?/gu)) {
    карта.set(имя, значение.trim());
  }
  return карта;
}

/* ── Цвет и контраст ─────────────────────────────────────────────────────── */

/** `var(--имя)` → значение, по цепочке, пока не получится шестнадцатеричный код. */
function разрешить(имя, среда, путь = []) {
  const значение = среда.get(имя);
  if (значение === undefined) return { цвет: null, путь };
  const через = [...путь, имя];
  const ссылка = /^var\(\s*(--[\w-]+)\s*\)$/u.exec(значение);
  if (ссылка) return разрешить(ссылка[1], среда, через);
  return { цвет: /^#[0-9a-f]{6}$/iu.test(значение) ? значение.toLowerCase() : null, путь: через };
}

/** Относительная яркость по WCAG 2.1 (sRGB). */
function яркость(цвет) {
  const каналы = [1, 3, 5].map((i) => parseInt(цвет.slice(i, i + 2), 16) / 255);
  const [r, g, b] = каналы.map((к) => (к <= 0.03928 ? к / 12.92 : ((к + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Контраст двух цветов по WCAG 2.1: (светлее + 0.05) / (темнее + 0.05). */
export function контраст(а, б) {
  const я1 = яркость(а);
  const я2 = яркость(б);
  const [светлее, темнее] = я1 > я2 ? [я1, я2] : [я2, я1];
  return (светлее + 0.05) / (темнее + 0.05);
}

/* ── Замер ───────────────────────────────────────────────────────────────── */

/**
 * Меряет таблицу стилей. Возвращает `{ строка, беды, темы }`:
 * `темы` — по теме список `{ роль, токен, цвет, подложка, контраст }`.
 */
export function замерить(css) {
  const чистый = безКомментариев(css);
  const все = правила(чистый);
  const беды = [];

  const корни = все.filter((п) => п.обёртка === '' && п.селектор === ':root');
  const общее = new Map();
  for (const п of корни) for (const [к, з] of переменные(п.тело)) общее.set(к, з);

  const темнаяСистемная = все.find(
    (п) => /prefers-color-scheme:\s*dark/u.test(п.обёртка) && п.селектор === ':root:not([data-theme="light"])',
  );
  const темнаяКнопка = все.find((п) => п.обёртка === '' && п.селектор === ':root[data-theme="dark"]');

  const места = [
    { имя: 'светлая', правило: { тело: корни.map((п) => п.тело).join('\n') } },
    { имя: 'тёмная (система)', правило: темнаяСистемная },
    { имя: 'тёмная (переключатель)', правило: темнаяКнопка },
  ];

  const темы = new Map();
  for (const место of места) {
    if (!место.правило) {
      беды.push(`палитра карточки: не нашлось места темы «${место.имя}» — проверить нечего`);
      continue;
    }
    const свои = переменные(место.правило.тело);
    for (const имя of ОБЯЗАТЕЛЬНЫЕ) {
      if (!свои.has(имя)) {
        беды.push(`палитра карточки: в теме «${место.имя}» не объявлен ${имя} — тема выйдет половинной`);
      }
    }
    const среда = new Map([...общее, ...свои]);
    const фон = разрешить('--flang-kod-fon', среда);
    if (!фон.цвет) {
      беды.push(`палитра карточки: в теме «${место.имя}» не вычисляется подложка --flang-kod-fon`);
      continue;
    }
    const строки = [];
    for (const имя of [...ТЕКСТ, '--flang-kod-ramka']) {
      const { цвет, путь } = разрешить(имя, среда);
      if (!цвет) {
        беды.push(`палитра карточки: в теме «${место.имя}» не вычисляется ${имя}`);
        continue;
      }
      if (!путь.some((звено) => звено.startsWith('--digitable-'))) {
        беды.push(
          `палитра карточки: ${имя} в теме «${место.имя}» задан мимо фирменного токена (${путь.join(' → ')})`,
        );
      }
      const к = контраст(цвет, фон.цвет);
      const текст = имя !== '--flang-kod-ramka';
      строки.push({ роль: РОЛИ[имя] ?? 'рамка карточки', токен: имя, цвет, подложка: фон.цвет, контраст: к, текст });
      if (текст && к < НОРМА) {
        беды.push(
          `подсветка: ${имя} (${цвет}) на ${фон.цвет} даёт ${к.toFixed(2)}:1 при норме ${НОРМА} — тема «${место.имя}»`,
        );
      }
    }
    темы.set(место.имя, строки);
  }

  /* Несмешение палитр. Цвет карточки — только на карточке, палитра страницы —
     только на странице. Ловится по селекторам, потому что именно там беда и
     заводится: у Digitable цвет красился одним селектором, а подложка
     выдавалась другим, более узким. */
  for (const п of все) {
    if (п.селектор.startsWith(':root')) continue;
    const краситКарточкой = /var\(\s*--flang-/u.test(п.тело);
    const проКарточку = /\bpre\b/u.test(п.селектор);
    if (краситКарточкой && !проКарточку) {
      беды.push(`несмешение: «${п.селектор}» берёт цвет карточки кода, не будучи карточкой`);
    }
    if (!проКарточку) continue;
    for (const [, свойство, значение] of п.тело.matchAll(/\b(background|background-color|color)\s*:\s*([^;}]+)/gu)) {
      const з = значение.trim();
      if (/^(none|transparent|inherit|currentColor)$/iu.test(з)) continue;
      if (!/var\(\s*--flang-/u.test(з)) {
        беды.push(`несмешение: «${п.селектор}» красит ${свойство} мимо палитры карточки (${з})`);
      }
    }
  }

  const замеры = [...темы.values()].flat().filter((с) => с.текст);
  let худший = null;
  for (const з of замеры) if (худший === null || з.контраст < худший.контраст) худший = з;
  const строка =
    `палитра Digitable, карточка кода тёмная в обеих темах; ` +
    `замеров ${замеры.length} (мест темы ${темы.size} × цветов текста ${ТЕКСТ.length}), ` +
    `норма ${НОРМА}:1, ниже нормы ${беды.filter((б) => б.startsWith('подсветка:')).length}` +
    (худший ? `; худший — ${РОЛИ[худший.токен]} ${худший.контраст.toFixed(2)}:1` : '');

  return { строка, беды, темы };
}

/** Прочитать таблицу стилей дерева и померить её. */
export function замеритьТаблицу(корень) {
  return замерить(readFileSync(join(корень, 'docs', 'site', 'style.css'), 'utf8'));
}

/* Прогон руками: `node docs/site/kontrast.mjs` — таблица целиком. Внутри
   сборки печатается одна строка итога, а таблица нужна тогда, когда палитру
   правят: число рядом с цветом — единственное, чем «приглушённый» отличается
   от «нечитаемого». */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const корень = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const { строка, беды, темы } = замеритьТаблицу(корень);
  for (const [тема, строки] of темы) {
    console.log(`\n${тема}:`);
    console.log('  роль               цвет      подложка  контраст  норма');
    for (const с of строки) {
      const итог = с.текст ? (с.контраст >= НОРМА ? 'да' : 'НЕТ') : 'не текст';
      console.log(
        `  ${с.роль.padEnd(18)} ${с.цвет}   ${с.подложка}   ${с.контраст.toFixed(2).padStart(6)}   ${итог}`,
      );
    }
  }
  console.log(`\nКонтраст подсветки: ${строка}.`);
  for (const б of беды) console.error('  · ' + б);
  process.exit(беды.length ? 1 : 0);
}
