// ── Разбор исходника ────────────────────────────────────────────────────────
const СЛОВА_ЗАГОЛОВКА = new Set(['принимает', 'возвращает', 'требует', 'обеспечивает', 'пример', 'убывает', 'для']);

/** Объявления модуля: строка в нулевой колонке и всё, что под ней с отступом. */
function объявления(текст) {
  const блоки = [];
  let текущий = null;
  for (const строка of текст.replace(/\r\n/gu, '\n').split('\n')) {
    if (строка.trim() !== '' && !/^\s/u.test(строка)) {
      текущий = { шапка: строка, тело: [] };
      блоки.push(текущий);
    } else if (текущий) {
      текущий.тело.push(строка);
    }
  }
  for (const б of блоки) while (б.тело.length && б.тело[б.тело.length - 1].trim() === '') б.тело.pop();
  return блоки;
}

/** Части заголовка функции: слово первого отступа и его строки с продолжениями. */
function частиЗаголовка(тело) {
  const части = [];
  let текущая = null;
  for (const строка of тело) {
    const м = /^ {2}(\S+)(?: (.*))?$/u.exec(строка);
    if (м && !строка.startsWith('   ')) {
      if (!СЛОВА_ЗАГОЛОВКА.has(м[1])) break;
      текущая = { слово: м[1], строки: [м[2] ?? ''] };
      части.push(текущая);
    } else if (текущая && строка.trim() !== '') {
      текущая.строки.push(строка.trim());
    }
  }
  return части;
}

/** «название» и формула условия: `обеспечивает «название» формула`. */
function условие(строки) {
  const весь = строки.join(' ');
  const м = /^«([^»]*)»\s*(.*)$/u.exec(весь);
  return м ? { название: м[1], формула: м[2] } : { название: '', формула: весь };
}

/** Тест функции: имя, значения аргументов, ожидаемое. Строки хранятся как в исходнике. */
function тест(часть, исходныеСтроки) {
  const имя = /^«([^»]*)»/u.exec(часть.строки[0])?.[1] ?? '';
  const дано = [];
  let ожидается = null;
  let простой = true;
  let последний = null;
  for (const строка of исходныеСтроки) {
    const д = /^ {4}дано (\S+) равно (.*)$/u.exec(строка);
    const о = /^ {4}ожидается (.*)$/u.exec(строка);
    if (д) {
      последний = { имя: д[1], значение: д[2] };
      дано.push(последний);
    } else if (о) {
      последний = null;
      ожидается = о[1];
    } else if (строка.trim() !== '') {
      // Продолжение значения на следующей строке: такой тест в одну фразу не укладывается.
      простой = false;
    }
  }
  if (ожидается === null) простой = false;
  return { имя, дано, ожидается, простой, строки: исходныеСтроки };
}

/** Аргументы из строки `принимает`: запятая внутри скобок их не делит. */
function аргументы(текст) {
  const из = [];
  let глубина = 0;
  let начало = 0;
  for (let i = 0; i < текст.length; i += 1) {
    const з = текст[i];
    if (з === '(' || з === '[') глубина += 1;
    else if (з === ')' || з === ']') глубина -= 1;
    else if (з === ',' && глубина === 0) {
      из.push(текст.slice(начало, i).trim());
      начало = i + 1;
    }
  }
  const хвост = текст.slice(начало).trim();
  if (хвост) из.push(хвост);
  return из.map((а) => {
    const место = а.indexOf(':');
    return место < 0 ? { имя: а, тип: '' } : { имя: а.slice(0, место).trim(), тип: а.slice(место + 1).trim() };
  });
}

function функция(блок) {
  const м = /^(тотальная )?функция «([^»]+)»(.*)$/u.exec(блок.шапка);
  const части = частиЗаголовка(блок.тело);
  const принимает = части.find((ч) => ч.слово === 'принимает')?.строки.join(' ') ?? '';
  const возвращает = части.find((ч) => ч.слово === 'возвращает')?.строки.join(' ') ?? '';
  // Строки тестов нужны как в исходнике: по ним видно, уместилось ли значение в строку.
  const тесты = [];
  for (let i = 0; i < блок.тело.length; i += 1) {
    if (!/^ {2}пример( |$)/u.test(блок.тело[i])) continue;
    const свои = [];
    let j = i + 1;
    while (j < блок.тело.length && (блок.тело[j].startsWith('   ') || блок.тело[j].trim() === '')) свои.push(блок.тело[j++]);
    const часть = { строки: [блок.тело[i].replace(/^ {2}пример ?/u, '')] };
    тесты.push(тест(часть, свои.filter((с) => с.trim() !== '')));
  }
  return {
    имя: м[2],
    тотальная: Boolean(м[1]),
    обобщение: м[3].trim(),
    принимает,
    аргументы: аргументы(принимает),
    возвращает,
    требует: части.filter((ч) => ч.слово === 'требует').map((ч) => условие(ч.строки)),
    обеспечивает: части.filter((ч) => ч.слово === 'обеспечивает').map((ч) => условие(ч.строки)),
    тесты,
    текст: блок.тело.join('\n'),
  };
}

/**
 * Что в модуле служебное.
 *
 * Язык различие даёт: строка `экспортирует` в заголовке модуля. Ни один модуль
 * библиотеки её не пишет, поэтому наружу видно всё, и делить приходится по
 * соглашению об именах, которого библиотека держится сама: «Шаг …» — шаг
 * свёртки, «Ход …» — её состояние. Функция, которая принимает или возвращает
 * «Ход …», собирает или разбирает это состояние и вне свёртки не нужна.
 */
const служебныйТип = (имя) => имя.startsWith('Ход ');
function служебнаяФункция(ф) {
  if (ф.имя.startsWith('Шаг ')) return true;
  const подпись = `${ф.принимает} ${ф.возвращает}`;
  for (const м of подпись.matchAll(/«([^»]+)»/gu)) if (служебныйТип(м[1])) return true;
  return false;
}

function разобратьМодуль(файл, текст) {
  const блоки = объявления(текст);
  const шапка = блоки[0] ?? { шапка: '', тело: [] };
  const имя = /^модуль «([^»]+)»/u.exec(шапка.шапка)?.[1] ?? basename(файл, '.flang');
  const ввозит = [];
  for (const строка of шапка.тело) {
    const м = /^\s+использует «[^»]+» из "([^"]+)"/u.exec(строка);
    if (м) ввозит.push(м[1]);
  }
  const функции = [];
  const типы = [];
  const теоремы = [];
  for (const б of блоки.slice(1)) {
    if (/^(тотальная )?функция «/u.test(б.шапка)) функции.push(функция(б));
    else if (/^(тип|объект) «/u.test(б.шапка)) {
      типы.push({ имя: /«([^»]+)»/u.exec(б.шапка)[1], строки: [б.шапка, ...б.тело] });
    } else if (/^(теорема|утверждение) «/u.test(б.шапка)) {
      теоремы.push({ вид: б.шапка.split(' ')[0], имя: /«([^»]+)»/u.exec(б.шапка)[1] });
    }
  }
  for (const ф of функции) ф.служебная = служебнаяФункция(ф);
  for (const т of типы) т.служебный = служебныйТип(т.имя);
  return { файл, путь: `${КАТАЛОГ_БИБЛИОТЕКИ}/${файл}`, слаг: basename(файл, '.flang'), имя, текст, отпечаток: хеш(текст), ввозит, функции, типы, теоремы };
}

