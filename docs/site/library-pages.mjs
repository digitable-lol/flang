/** Все файлы flang в каталогах, где лежат программы: библиотека, компилятор, примеры, скрипты. */
function файлыДерева(корень) {
  const найдено = [];
  const обойти = (каталог) => {
    let имена;
    try {
      имена = readdirSync(join(корень, каталог), { withFileTypes: true });
    } catch {
      return;
    }
    for (const з of имена) {
      const путь = `${каталог}/${з.name}`;
      if (з.isDirectory()) {
        if (з.name === 'out' || з.name === 'node_modules' || путь === 'flang/test/fixtures' || путь === 'flang/self/bootstrap') continue;
        обойти(путь);
      } else if (/\.(flang|fscript)$/u.test(з.name)) {
        найдено.push(путь);
      }
    }
  };
  for (const к of ['flang', 'docs/examples', 'scripts', 'fspec']) обойти(к);
  return найдено.sort();
}

/**
 * Сколько файлов за пределами модуля зовут каждую его функцию.
 * Файл считается, если подключает модуль по имени; сами строки `использует`
 * (со списком `только`) вызовом не считаются.
 */
function посчитатьВызовы(корень, модули) {
  const поИмени = new Map(модули.map((м) => [м.имя, м]));
  for (const м of модули) for (const ф of м.функции) ф.зовутСнаружи = 0;
  for (const путь of файлыДерева(корень)) {
    let текст;
    try {
      текст = readFileSync(join(корень, путь), 'utf8');
    } catch {
      continue;
    }
    if (!текст.includes('использует «')) continue;
    const строки = текст.split('\n');
    const подключены = new Set();
    for (const строка of строки) {
      const м = /^\s+использует «([^»]+)»/u.exec(строка);
      if (м && поИмени.has(м[1]) && поИмени.get(м[1]).путь !== путь) подключены.add(м[1]);
    }
    if (!подключены.size) continue;
    const тело = строки.filter((с) => !/^\s+использует «/u.test(с)).join('\n');
    for (const имя of подключены) {
      for (const ф of поИмени.get(имя).функции) if (тело.includes(`«${ф.имя}»`)) ф.зовутСнаружи += 1;
    }
  }
}

// ── Статусы постусловий ─────────────────────────────────────────────────────
function прочитатьСтатусы(корень) {
  const поПути = new Map();
  const полный = join(корень, ПУТЬ_СТАТУСОВ);
  if (!existsSync(полный)) return поПути;
  for (const строка of readFileSync(полный, 'utf8').split('\n').slice(1)) {
    if (!строка) continue;
    const [путь, отпечаток, имя, название, статус] = строка.split('\t');
    if (!поПути.has(путь)) поПути.set(путь, { отпечаток: '', условия: new Map(), завершение: new Map() });
    const з = поПути.get(путь);
    if (отпечаток) з.отпечаток = отпечаток;
    if (название) з.условия.set(`${имя}\u0000${название}`, статус);
    else if (имя) з.завершение.set(имя, статус);
  }
  return поПути;
}

/** Слово записи статусов → ключ слова страницы. */
function ключСтатуса(слово) {
  if (слово === undefined) return 'неИзмерено';
  if (слово === 'доказано') return 'доказано';
  if (слово === 'сетка') return 'тесты';
  if (слово === 'нарушено' || слово === 'отвергнуто') return 'нарушено';
  return 'неДоказано';
}

// ── Пример страницы ─────────────────────────────────────────────────────────
const ПРОСТОЕ_ЗНАЧЕНИЕ = /^(-?\d+(\.\d+)?|"[^"]*"|да|нет|«[^»]+»|\[[^\[\]]*\])$/u;
const какАргумент = (значение) => (ПРОСТОЕ_ЗНАЧЕНИЕ.test(значение) && !значение.startsWith('-') ? значение : `(${значение})`);

/**
 * Тест, по которому функцию видно лучше всего: первый, что уместился в строку и
 * не берёт пустой список или пустую строку. Таких нет — просто первый.
 */
const ПУСТОЕ = new Set(['пустой список', '""', '[]']);
function показательныйТест(ф) {
  const годный = ф.тесты.find((т) => т.простой && т.дано.length && !т.дано.some((д) => ПУСТОЕ.has(д.значение)));
  return годный ?? ф.тесты[0];
}

/** Вызов функции со значениями теста: `«Сумма» от [1, 2, 3]`. */
function вызовПоТесту(ф, т) {
  if (!ф.аргументы.length) return `«${ф.имя}»`;
  const значения = [];
  for (const а of ф.аргументы) {
    const д = т.дано.find((з) => з.имя === а.имя);
    if (!д) return null;
    значения.push(какАргумент(д.значение));
  }
  return `«${ф.имя}» от ${значения.join(' и ')}`;
}

/** Годится ли функция для примера страницы: вызов и ответ умещаются в строку. */
export function годитсяВПример(ф) {
  if (ф.служебная || ф.обобщение || !ф.тесты.length || !ф.возвращает) return false;
  const т = показательныйТест(ф);
  if (!т.простой || т.дано.length !== ф.аргументы.length) return false;
  const вызов = вызовПоТесту(ф, т);
  return вызов !== null && вызов.length <= 100 && т.ожидается.length <= 90;
}

function выбратьПример(модуль, описание) {
  if (описание?.пример) {
    const названная = модуль.функции.find((ф) => ф.имя === описание.пример);
    if (названная && годитсяВПример(названная)) return названная;
  }
  const годные = модуль.функции.filter(годитсяВПример);
  if (!годные.length) return null;
  // Сначала то, что чаще зовут снаружи; при равенстве — раньше объявленное.
  return годные.reduce((лучшая, ф) => (ф.зовутСнаружи > лучшая.зовутСнаружи ? ф : лучшая), годные[0]);
}

/** Программа примера: модуль, подключение, одна функция с тестом из модуля. */
export function текстПримера(модуль, ф) {
  const т = показательныйТест(ф);
  return [
    'модуль «Пример»',
    `  использует «${модуль.имя}»`,
    '',
    `${ф.тотальная ? 'тотальная ' : ''}функция «Вызов из примера»`,
    `  возвращает ${ф.возвращает}`,
    `  пример «${т.имя || 'как в тесте модуля'}»`,
    `    ожидается ${т.ожидается}`,
    `  ${вызовПоТесту(ф, т)}`,
    '',
  ].join('\n');
}

/**
 * Пример страницы модуля: программа и функция, из теста которой она собрана.
 * Программа, записанная в каталоге целиком, функции не называет.
 */
function примерМодуля(модуль, описание) {
  if (описание?.программа) return { текст: описание.программа, функция: null };
  const ф = выбратьПример(модуль, описание);
  return ф ? { текст: текстПримера(модуль, ф), функция: ф } : null;
}

/** Отпечаток примера: его текст, текст модуля и всё, что модуль подключает. */
function отпечатокПримера(текст, модуль, поФайлу) {
  const виденные = new Set();
  const очередь = [модуль.файл];
  const части = [текст];
  while (очередь.length) {
    const файл = очередь.shift();
    if (виденные.has(файл)) continue;
    виденные.add(файл);
    const м = поФайлу.get(файл);
    if (!м) continue;
    части.push(`${файл} ${м.отпечаток}`);
    очередь.push(...м.ввозит);
  }
  return хеш(части.join('\n'));
}

function прочитатьЗапускиПримеров(корень) {
  const поПути = new Map();
  const полный = join(корень, ПУТЬ_ПРИМЕРОВ);
  if (!existsSync(полный)) return поПути;
  for (const строка of readFileSync(полный, 'utf8').split('\n').slice(1)) {
    if (!строка) continue;
    const [путь, отпечаток, тестов] = строка.split('\t');
    поПути.set(путь, { отпечаток, тестов: Number(тестов) });
  }
  return поПути;
}

// ── Печать страницы ─────────────────────────────────────────────────────────
/** Длинная строка сигнатуры переносится после запятой, продолжение — с отступом. */
function перенести(строка, отступ = '    ') {
  if (строка.length <= ШИРИНА) return [строка];
  const из = [];
  let текущая = '';
  for (const кусок of строка.split(/(?<=,) /u)) {
    if (текущая && (текущая + ' ' + кусок).length > ШИРИНА) {
      из.push(текущая);
      текущая = отступ + кусок;
    } else {
      текущая = текущая ? `${текущая} ${кусок}` : кусок;
    }
  }
  if (текущая) из.push(текущая);
  return из;
}

/** Обратная кавычка внутри встроенного кода закрыла бы его раньше времени. */
const вКод = (текст) => `\`${текст.replace(/`/gu, "'")}\``;

function заголовокФункции(ф) {
  return `«${ф.имя}»${ф.обобщение ? ` ${ф.обобщение}` : ''}`;
}

function фразаТеста(ф, сл) {
  const т = показательныйТест(ф);
  if (!т) return [];
  const короткий = т.простой && т.ожидается.length <= 120 && т.дано.every((д) => д.значение.length <= 80) && т.дано.length <= 4;
  if (короткий) {
    if (!т.дано.length) return [`${сл.безАргументов} ${вКод(т.ожидается)}.`, ''];
    const дано = т.дано.map((д) => вКод(`${д.имя} = ${д.значение}`)).join(', ');
    return [`${сл.тест}: ${сл.при} ${дано} ${сл.возвращает} ${вКод(т.ожидается)}.`, ''];
  }
  // Длинный тест показывается как записан, первые строки: формула на экран — не пример.
  const строки = т.строки.slice(0, 6).map((с) => {
    const без = с.replace(/^ {4}/u, '');
    return без.length > ШИРИНА ? `${без.slice(0, ШИРИНА - 2)} …` : без;
  });
  if (т.строки.length > 6) строки.push('…');
  return [`${сл.тест}${т.имя ? ` «${т.имя}»` : ''}:`, '', '```text', ...строки, '```', ''];
}

function разделФункции(ф, статусы, сл) {
  const строки = [`### ${заголовокФункции(ф)}`, '', '```sig'];
  if (ф.принимает) строки.push(...перенести(`принимает ${ф.принимает}`));
  строки.push(...перенести(`возвращает ${ф.возвращает}`), '```', '');
  строки.push(...фразаТеста(ф, сл));
  const пункты = [];
  for (const у of ф.требует) {
    const формула = у.формула && у.формула.length <= ПРЕДЕЛ_ФОРМУЛЫ ? `: ${вКод(у.формула)}` : '';
    пункты.push(`- ${сл.предусловие}${у.название ? ` «${у.название}»` : ''}${формула}`);
  }
  for (const у of ф.обеспечивает) {
    const слово = сл[ключСтатуса(статусы?.get(`${ф.имя}\u0000${у.название}`))];
    const формула = у.формула && у.формула.length <= ПРЕДЕЛ_ФОРМУЛЫ ? `: ${вКод(у.формула)}` : '';
    пункты.push(`- ${сл.постусловие} «${у.название}» — **${слово}**${формула}`);
  }
  if (пункты.length) строки.push(...пункты, '');
  if (!ф.тотальная) строки.push(сл.неТотальная, '');
  return строки;
}

/** Служебная функция одной строкой: имя, аргументы, результат. */
function строкаСлужебной(ф) {
  return перенести(`${заголовокФункции(ф)}: ${ф.принимает ? `(${ф.принимает}) ` : ''}→ ${ф.возвращает}`);
}

/** Знак начала и конца сворачиваемого блока. Сборка меняет абзац с ним на `<details>`. */
export const СВЕРНУТЬ = { начало: '⟦свернуть⟧', конец: '⟦развернуть⟧' };

function страницаМодуля(модуль, описание, язык, данные) {
  const сл = СЛОВА[язык];
  const { статусы, запуски, поФайлу } = данные;
  const запись = статусы.get(модуль.путь);
  const свежие = запись && запись.отпечаток === модуль.отпечаток ? запись.условия : null;
  const подсказка = язык === 'ru' && описание?.подсказка ? ` — ${описание.подсказка}` : '';
  const о = (язык === 'ru' ? описание?.о : описание?.about) ?? '';
  const строки = [`# ${модуль.имя}${подсказка}`, ''];
  if (о) строки.push(о, '');
  строки.push(`${сл.подключение}:`, '', '```text', `  использует «${модуль.имя}»`, '```', '');

  // Пример.
  const вызываемые = модуль.функции.filter((ф) => !ф.служебная);
  const служебные = модуль.функции.filter((ф) => ф.служебная);
  const пример = примерМодуля(модуль, описание);
  const изПримера = пример?.функция ?? null;
  let примерПроверен = false;
  строки.push(`## ${сл.пример}`, '');
  if (пример) {
    const текст = пример.текст;
    const запуск = запуски.get(модуль.путь);
    if (запуск && запуск.отпечаток === отпечатокПримера(текст, модуль, поФайлу)) {
      примерПроверен = true;
      строки.push(сл.файлПримера, '', '```flang', текст.trimEnd(), '```', '');
      строки.push('```text', '$ flang test example.flang');
      строки.push(`example.flang: примеров ${запуск.тестов}, прошло ${запуск.тестов}, не прошло 0`, '```', '');
      строки.push(сл.запускПримера(запуск.тестов, изПримера), '');
    } else if (изПримера) {
      строки.push(сл.примерНеЗапускался, '');
      строки.push('```text', `функция «${изПримера.имя}»`);
      строки.push(...показательныйТест(изПримера).строки.slice(0, 8).map((с) => с.replace(/^ {2}/u, '')), '```', '');
    } else {
      строки.push(сл.примерНеЗапускалсяВовсе, '');
    }
  } else if (!модуль.функции.length) {
    строки.push(сл.безПримера, '');
  } else {
    const первая = вызываемые.find((ф) => ф.тесты.length) ?? модуль.функции.find((ф) => ф.тесты.length);
    строки.push(сл.примерНеЗапускался, '');
    if (первая) {
      строки.push('```text', `функция «${первая.имя}»`);
      const свои = первая.тесты[0].строки.slice(0, 8).map((с) => {
        const без = с.replace(/^ {2}/u, '');
        return без.length > ШИРИНА ? `${без.slice(0, ШИРИНА - 2)} …` : без;
      });
      строки.push(...свои, '```', '');
    }
  }

  // Функции.
  if (вызываемые.length) {
    строки.push(`## ${сл.функции}`, '', сл.оФункциях(вызываемые.length, служебные.length), '');
    строки.push(запись && !свежие ? сл.статусыУстарели : сл.оСтатусах, '');
    const частые = вызываемые.filter((ф) => ф.зовутСнаружи > 0).sort((а, б) => б.зовутСнаружи - а.зовутСнаружи).slice(0, 6);
    if (частые.length >= 3) {
      // Якорь считается так же, как его считает разбор markdown: по тексту заголовка.
      const ссылки = частые.map((ф) => `[«${ф.имя}»](#${якорь(заголовокФункции(ф))})`);
      строки.push(`${сл.частые}: ${ссылки.join(', ')}.`, '');
    }
    // Сначала то, что уже зовут другие модули и примеры: в большом модуле это и
    // есть его вход, остальное — части, из которых он собран.
    const снаружи = вызываемые.filter((ф) => ф.зовутСнаружи > 0);
    const прочие = вызываемые.filter((ф) => ф.зовутСнаружи === 0);
    if (снаружи.length && прочие.length) {
      for (const ф of снаружи) строки.push(...разделФункции(ф, свежие, сл));
      строки.push(`## ${сл.остальные}`, '', сл.оОстальных, '');
      for (const ф of прочие) строки.push(...разделФункции(ф, свежие, сл));
    } else {
      for (const ф of вызываемые) строки.push(...разделФункции(ф, свежие, сл));
    }
  }

  // Типы, которые встречаются в сигнатурах.
  const открытые = модуль.типы.filter((т) => !т.служебный);
  if (открытые.length) {
    строки.push(`## ${сл.типы}`, '', '```flang');
    открытые.forEach((т, н) => {
      if (н) строки.push('');
      for (const с of т.строки) if (с.trim() !== '') строки.push(...перенести(с, '      '));
    });
    строки.push('```', '');
  }

  if (модуль.теоремы.length) {
    строки.push(`## ${сл.теоремы}`, '', сл.оТеоремах, '');
    for (const т of модуль.теоремы) строки.push(`- ${т.вид} «${т.имя}»`);
    строки.push('');
  }

  const закрытыеТипы = модуль.типы.filter((т) => т.служебный);
  if (служебные.length || закрытыеТипы.length) {
    строки.push(`## ${сл.служебные}`, '', сл.оСлужебных, '', СВЕРНУТЬ.начало, '', '```sig');
    for (const т of закрытыеТипы) строки.push(`тип «${т.имя}»`);
    for (const ф of служебные) строки.push(...строкаСлужебной(ф));
    строки.push('```', '', СВЕРНУТЬ.конец, '');
  }

  строки.push(`${сл.исходник}: \`${модуль.путь}\`. ${сл.всеМодули}: [${сл.обзор}](../stdlib.html).`, '');

  // Счёт постусловий страницы — он же идёт в сводку.
  const счёт = { доказано: 0, тесты: 0, неДоказано: 0, нарушено: 0, неИзмерено: 0 };
  for (const ф of модуль.функции) {
    for (const у of ф.обеспечивает) счёт[ключСтатуса(свежие?.get(`${ф.имя}\u0000${у.название}`))] += 1;
  }
  return { текст: строки.join('\n'), примерПроверен, счёт };
}

// ── Каталог, сводка, указатель старых адресов ───────────────────────────────
function раскладкаПоЗадачам(модули) {
  const поФайлу = new Map(модули.map((м) => [м.файл, м]));
  const занятые = new Set();
  const группы = [];
  for (const з of ЗАДАЧИ) {
    const свои = з.модули.map((ф) => поФайлу.get(ф)).filter(Boolean);
    for (const м of свои) занятые.add(м.файл);
    if (свои.length) группы.push({ ...з, модули: свои });
  }
  // Модуль, которого каталог не знает, не пропадает: он встаёт в последнюю группу.
  const прочие = модули.filter((м) => !занятые.has(м.файл));
  if (прочие.length) группы.push({ ...ПРОЧЕЕ, модули: прочие });
  return группы;
}

function каталог(модули, язык, откуда) {
  const сл = СЛОВА[язык];
  const строки = [];
  for (const г of раскладкаПоЗадачам(модули)) {
    строки.push(`### ${язык === 'ru' ? г.имя : г.name}`, '', `| ${сл.модуль} | ${сл.зачем} |`, '| --- | --- |');
    for (const м of г.модули) {
      const о = ОПИСАНИЯ[м.файл];
      const зачем = (язык === 'ru' ? о?.зачем : о?.why) ?? '';
      const подсказка = язык === 'ru' && о?.подсказка ? ` — ${о.подсказка}` : '';
      строки.push(`| [${м.имя}](${откуда}${КАТАЛОГ_СТРАНИЦ}/${м.слаг}.html)${подсказка} | ${зачем} |`);
    }
    строки.push('');
  }
  return строки.join('\n').trimEnd();
}

function сводка(модули, счёт, язык) {
  const сл = СЛОВА[язык];
  const с = сл.строкиСводки;
  const постусловий = Object.values(счёт).reduce((а, б) => а + б, 0);
  const строки = [
    `| ${сл.сводка[0]} | ${сл.сводка[1]} |`,
    '| --- | ---: |',
    `| ${с.модулей} | ${модули.length} |`,
    `| ${с.функций} | ${модули.reduce((а, м) => а + м.функции.length, 0)} |`,
    `| ${с.постусловий} | ${постусловий} |`,
    `| ${с.доказано} | ${счёт.доказано} |`,
    `| ${с.тесты} | ${счёт.тесты} |`,
    `| ${с.неДоказано} | ${счёт.неДоказано} |`,
  ];
  if (счёт.нарушено) строки.push(`| ${с.нарушено} | ${счёт.нарушено} |`);
  if (счёт.неИзмерено) строки.push(`| ${с.неИзмерено} | ${счёт.неИзмерено} |`);
  return строки.join('\n');
}

/**
 * Указатель для старого адреса `library-api.html`: заголовок на модуль, как на
 * прежней странице, — поэтому ссылка `library-api.html#lists` по-прежнему
 * попадает на строку своего модуля.
 */
function указатель(модули, язык) {
  const сл = СЛОВА[язык];
  const строки = [];
  for (const м of модули) {
    строки.push(`### «${м.имя}»`, '', `${сл.указатель}: [${м.имя}](${КАТАЛОГ_СТРАНИЦ}/${м.слаг}.html).`, '');
  }
  return строки.join('\n').trimEnd();
}

// ── Сбор ────────────────────────────────────────────────────────────────────
export function прочитатьМодули(корень = КОРЕНЬ) {
  const каталогМодулей = join(корень, КАТАЛОГ_БИБЛИОТЕКИ);
  const файлы = readdirSync(каталогМодулей).filter((ф) => ф.endsWith('.flang')).sort();
  const модули = файлы.map((ф) => разобратьМодуль(ф, readFileSync(join(каталогМодулей, ф), 'utf8')));
  посчитатьВызовы(корень, модули);
  return модули;
}

/**
 * Всё, что сборке нужно от библиотеки: страницы модулей на двух языках и
 * вставки для обзорной страницы и для указателя старого адреса.
 */
export function собратьБиблиотеку(корень = КОРЕНЬ) {
  const модули = прочитатьМодули(корень);
  const данные = {
    статусы: прочитатьСтатусы(корень),
    запуски: прочитатьЗапускиПримеров(корень),
    поФайлу: new Map(модули.map((м) => [м.файл, м])),
  };
  const страницы = [];
  const счёт = { доказано: 0, тесты: 0, неДоказано: 0, нарушено: 0, неИзмерено: 0 };
  const безПримера = [];
  const безОписания = [];
  const безФункций = модули.filter((м) => !м.функции.length).map((м) => м.файл);
  for (const м of модули) {
    const описание = ОПИСАНИЯ[м.файл];
    if (!описание) безОписания.push(м.файл);
    const ру = страницаМодуля(м, описание, 'ru', данные);
    const англ = страницаМодуля(м, описание, 'en', данные);
    for (const ключ of Object.keys(счёт)) счёт[ключ] += ру.счёт[ключ];
    if (!ру.примерПроверен && м.функции.length) безПримера.push(м.файл);
    const адрес = `${КАТАЛОГ_СТРАНИЦ}/${м.слаг}.html`;
    // В указатель поиска идёт назначение модуля, а не начало страницы: иначе
    // модуль находился бы по словам своего примера.
    const дляПоиска = (язык) => `${(язык === 'ru' ? описание?.о : описание?.about) ?? ''} ${(язык === 'ru' ? описание?.зачем : описание?.why) ?? ''}`;
    страницы.push({ адрес, язык: 'ru', пара: `en/${адрес}`, исходник: ру.текст, модуль: м.путь, текстПоиска: дляПоиска('ru') });
    страницы.push({ адрес: `en/${адрес}`, язык: 'en', пара: адрес, исходник: англ.текст, модуль: м.путь, текстПоиска: дляПоиска('en') });
  }
  const вставки = {};
  for (const язык of ['ru', 'en']) {
    вставки[язык] = {
      каталог: каталог(модули, язык, ''),
      сводка: сводка(модули, счёт, язык),
      указатель: указатель(модули, язык),
    };
  }
  return { модули, страницы, вставки, счёт, безПримера, безОписания, безФункций };
}

// ── Запуск примеров ─────────────────────────────────────────────────────────
function запустить(программа, доводы, где) {
  return new Promise((готово) => {
    execFile(программа, доводы, { cwd: где, encoding: 'utf8', maxBuffer: 1 << 26, timeout: 3600000 }, (ошибка, вывод, ошибки) => {
      готово({ код: ошибка ? (ошибка.code ?? 1) : 0, вывод: `${вывод}${ошибки}` });
    });
  });
}

async function проверитьПримеры(названные) {
  const двоичный = process.env.FLANG_BINARY ?? join(КОРЕНЬ, 'bootstrap', 'flang');
  const модули = прочитатьМодули(КОРЕНЬ);
  const поФайлу = new Map(модули.map((м) => [м.файл, м]));
  const прежние = прочитатьЗапускиПримеров(КОРЕНЬ);
  const работа = [];
  const записи = new Map();
  for (const м of модули) {
    const пример = примерМодуля(м, ОПИСАНИЯ[м.файл]);
    if (!пример) continue;
    const текст = пример.текст;
    const отпечаток = отпечатокПримера(текст, м, поФайлу);
    const прежняя = прежние.get(м.путь);
    const назван = названные.length ? названные.includes(м.файл) || названные.includes(м.путь) : true;
    if (прежняя && прежняя.отпечаток === отпечаток && !(названные.length && назван)) {
      записи.set(м.путь, прежняя);
      continue;
    }
    if (!назван) continue;
    работа.push({ м, текст, отпечаток });
  }
  // Запись кладётся после каждого прошедшего примера: оборванный запуск не теряет сделанного.
  const записать = () => {
    const строки = ['path\tdigest\ttests'];
    for (const путь of [...записи.keys()].sort()) строки.push(`${путь}\t${записи.get(путь).отпечаток}\t${записи.get(путь).тестов}`);
    writeFileSync(join(КОРЕНЬ, ПУТЬ_ПРИМЕРОВ), `${строки.join('\n')}\n`);
  };
  const рабочий = mkdtempSync(join(process.env.FLANG_TMP ?? tmpdir(), 'library-examples-'));
  const провалы = [];
  // Одновременно идёт не больше шести запусков, по умолчанию два. Число зашито,
  // а не берётся по числу ядер: `flang test` на большом модуле занимает до 6 ГБ
  // и сам порождает работников, так что двенадцать запусков разом заняли 200 ГБ.
  const ПОТОЛОК_ЗАПУСКОВ = 6;
  const одновременно = Math.max(1, Math.min(ПОТОЛОК_ЗАПУСКОВ, Number(process.env.LIBRARY_EXAMPLES_JOBS ?? 2) || 2));
  let следующая = 0;
  const работник = async () => {
    while (следующая < работа.length) {
      const { м, текст, отпечаток } = работа[следующая++];
      const где = join(рабочий, м.слаг);
      mkdirSync(где, { recursive: true });
      writeFileSync(join(где, 'example.flang'), текст);
      const { код, вывод } = await запустить(двоичный, ['test', 'example.flang'], где);
      const итог = /example\.flang: примеров (\d+), прошло (\d+), не прошло (\d+)/u.exec(вывод);
      if (код === 0 && итог && итог[1] === итог[2] && итог[3] === '0') {
        записи.set(м.путь, { отпечаток, тестов: Number(итог[1]) });
        записать();
        console.log(`  ${м.путь}: пример прошёл, тестов ${итог[1]}`);
      } else {
        const хвост = вывод.split('\n').filter((с) => с && !с.startsWith('шагов ')).slice(-6).join('\n    ');
        провалы.push(`${м.путь}: пример не прошёл, код ${код}\n    ${хвост}`);
        console.log(`  ${м.путь}: ПРИМЕР НЕ ПРОШЁЛ, код ${код}`);
      }
    }
  };
  await Promise.all(Array.from({ length: Math.min(одновременно, работа.length) }, работник));
  rmSync(рабочий, { recursive: true, force: true });
  записать();
  console.log(`Примеры страниц библиотеки: запущено ${работа.length}, не прошло ${провалы.length}; записей ${записи.size} — ${ПУТЬ_ПРИМЕРОВ}.`);
  if (провалы.length) {
    for (const п of провалы) console.error(`  · ${п}`);
    process.exit(1);
  }
}

function положитьСтраницы(куда) {
  const { страницы, вставки } = собратьБиблиотеку(КОРЕНЬ);
  for (const с of страницы) {
    const файл = join(куда, с.адрес.replace(/\.html$/u, с.язык === 'ru' ? '.ru.md' : '.md').replace(/^en\//u, ''));
    mkdirSync(dirname(файл), { recursive: true });
    writeFileSync(файл, с.исходник);
  }
  for (const язык of ['ru', 'en']) {
    for (const [имя, текст] of Object.entries(вставки[язык])) {
      writeFileSync(join(куда, `insert-${имя}${язык === 'ru' ? '.ru' : ''}.md`), `${текст}\n`);
    }
  }
  console.log(`Положено страниц ${страницы.length} в ${куда}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const доводы = process.argv.slice(2);
  if (доводы[0] === '--verify-examples') {
    await проверитьПримеры(доводы.slice(1));
  } else if (доводы[0] === '--dump' && доводы[1]) {
    положитьСтраницы(доводы[1]);
  } else {
    console.error('node docs/site/library-pages.mjs --verify-examples [файл…] | --dump <каталог>');
    process.exit(2);
  }
}
