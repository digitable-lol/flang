// Разбор markdown без единой зависимости.
//
// Почему свой, а не библиотека: в этой среде `node_modules` ставится не всегда
// и `tsc` отсутствует вовсе — из-за этого 14 проверок в дереве постоянно
// красные. Сайт документации, который не собирается без интернета, бесполезен
// ровно тогда, когда нужен. Поэтому здесь поддержано ровно то, что встречается
// в наших документах, и ни строкой больше.
//
// Что поддержано: заголовки, абзацы, списки (вложенные), нумерованные списки,
// блоки кода с указанием языка, таблицы, цитаты, разделители, ссылки, жирный,
// наклонный, встроенный код, ссылки базы знаний вида [[слаг]], схемы ```mermaid
// (рисуются в SVG во время сборки — см. diagram.mjs).
//
// Чего нет намеренно: сноски, определения ссылок, HTML внутри markdown,
// автоматические ссылки. Ни одного случая в дереве не нашлось.

import { схемаВSVG } from './diagram.mjs';
import { подсветить, снятьРазметку, целаяПрограмма } from './podsvetka.mjs';

const ЭКРАН = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };

export function экранировать(текст) {
  return String(текст).replace(/[&<>"]/g, (с) => ЭКРАН[с]);
}

/** Ссылка на другую страницу сайта: путь к файлу → адрес страницы. */
function адресСтраницы(цель, откуда) {
  if (/^(https?:|mailto:|#)/.test(цель)) return null;
  const [путь, якорь = ''] = цель.split('#');
  if (!путь) return null;
  return { путь, якорь };
}

/** Разбор строчных украшений: код, жирный, наклонный, ссылки. */
function строка(исходник, ссылки) {
  /* Встроенный код вырезается первым — внутри него разметка не действует, — но
     на его месте ОСТАЁТСЯ МЕТКА, а строка не рвётся на куски.
     Резалась она раньше, и каждый кусок размечался порознь. На тексте без кода
     это работало; на «**`слово`**» — нет: открывающие звёздочки оставались в
     одном куске, закрывающие в другом, и пара не сходилась ни разу. Читатель
     получал «**<code>тотальная</code><strong> — …</strong>проверяет**»: сами
     звёздочки текстом и жирный, начатый не там. Замер до правки — 158 пар
     звёздочек текстом на 40 собранных страницах, и первым из них открывается
     «Первая программа», то есть вторая страница, которую видит пришедший.
     Метка — знак, которого в markdown не бывает (U+0000): экранирование его не
     трогает, разметка его не видит, а код возвращается на место последним
     шагом — уже после того, как пары звёздочек сошлись. */
  const коды = [];
  let т = String(исходник).replace(/`([^`]+)`/g, (_, код) => `\u0000${коды.push(код) - 1}\u0000`);

  т = экранировать(т);
  // Ссылки базы знаний: [[слаг]]
  т = т.replace(/\[\[([^\]]+)\]\]/g, (_, слаг) => {
    ссылки?.push({ вид: 'зеттель', цель: слаг });
    return `<a class="zettel" href="knowledge-${слаг}.html">${экранировать(слаг)}</a>`;
  });
  // Обычные ссылки: [текст](цель)
  т = т.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, подпись, цель) => {
    const внутр = адресСтраницы(цель);
    if (внутр) ссылки?.push({ вид: 'файл', цель: внутр.путь, якорь: внутр.якорь });
    return `<a href="${экранировать(цель)}">${подпись}</a>`;
  });
  /* ОДИНОЧНАЯ ЗВЁЗДОЧКА ВНУТРИ ЖИРНОГО — ЗАКОННЫЙ ТЕКСТ, А НЕ РАЗМЕТКА.
     Здесь стояло `[^*]+`, то есть «внутри жирного звёздочек не бывает вовсе».
     На `**103 кода FLANG_*, 14 воспроизведены прогоном**` пара не сходилась, и
     обе звёздочки доезжали до читателя текстом; сторож `звёздочкиВнеКода` в
     `build.mjs` ловил это и валил сборку сайта. Заголовок слияния в журнал
     вливаний печатается жирным (`scripts/build-changelog-page.mjs`), а
     заголовки пишут люди — звёздочка в них появляется всякий раз, когда речь
     о наборе имён (`FLANG_*`, `flang/**`).
     Пара ищется НЕЖАДНО: содержимое теперь может нести звёздочку, и жадный
     разбор тянул бы жирный до последней пары в строке, склеивая соседние.
     Звёздочки внутри найденной пары прячутся меткой до конца разбора — иначе
     наклонный ниже возьмёт такую звёздочку за свою открывающую и порвёт уже
     собранный `<strong>`. Метка — U+0001, знак, которого в markdown не бывает,
     тот же приём, что и с встроенным кодом выше. */
  т = т.replace(
    /\*\*((?:[^*]|\*(?!\*))+?)\*\*/g,
    (_, внутри) => `<strong>${внутри.replaceAll('*', '\u0001')}</strong>`,
  );
  т = т.replace(/(^|[\s(])\*([^*\n]+)\*/g, '$1<em>$2</em>');

  return т
    .replace(/\u0000(\d+)\u0000/g, (_, н) => `<code>${экранировать(коды[Number(н)])}</code>`)
    .replaceAll('\u0001', '*');
}

/**
 * Убирает комментарии `<!-- … -->`.
 *
 * Комментарий в markdown невидим по определению — но HTML внутри markdown здесь
 * намеренно не поддержан, и без этой уборки комментарий доезжал бы до читателя
 * экранированным текстом. Это не мелочь оформления: шапка `CHANGELOG.md`
 * состоит ровно из такого комментария («файл печатается, править руками
 * бессмысленно»), и на странице сайта он вылезал бы первым абзацем.
 *
 * Комментарий внутри блока кода не трогается: там он часть показываемого
 * текста, а не разметка.
 */
export function убратьКомментарии(текст) {
  const части = текст.split(/(^```[\s\S]*?^```$)/mu);
  return части
    .map((часть, н) => (н % 2 === 1 ? часть : часть.replace(/<!--[\s\S]*?-->[ \t]*\n?/gu, '')))
    .join('');
}

/** Заголовок → якорь, пригодный для адреса. */
export function якорь(текст) {
  return String(текст)
    .toLowerCase()
    .replace(/`/g, '')
    .replace(/[^\p{L}\p{N}]+/gu, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 80);
}

/**
 * Разбирает markdown в HTML.
 * Возвращает { html, оглавление, ссылки, беды, подсветка } — оглавление собирается из
 * заголовков второго и третьего уровня, ссылки нужны проверке битых, беды —
 * это неразобранные схемы, от которых сборка обязана отказать.
 */
export function разобрать(исходник) {
  const строки = убратьКомментарии(String(исходник).replace(/\r\n/g, '\n')).split('\n');
  const вывод = [];
  const оглавление = [];
  const ссылки = [];
  const беды = [];
  // Счёт подсветки: сколько блоков признано своими, сколько окрашено, сколько
  // отказалось размечаться. Печатает его сборка — молчаливое ухудшение здесь
  // ровно так же нежелательно, как в ссылках.
  // `сверено` — сторож потери знаков, вынесенный в ЧИСЛО. Раньше сборка
  // утверждала прозой «в каждом окрашенном текст сверен знак в знак»; проза
  // не считается, а сверка обязана считаться, и не только на цветных: серый
  // блок тоже едет на страницу через экранирование и тоже может потерять знак.
  // Поэтому сверяется то, что доехало, — во всех блоках, а не в части.
  const подсветка = { всего: 0, помечено: 0, распознано: 0, окрашено: 0, отказано: 0, сверено: 0 };
  let i = 0;

  const занятыеЯкоря = new Set();
  const свободныйЯкорь = (текст) => {
    const основа = якорь(текст) || 'razdel';
    let имя = основа;
    let н = 2;
    while (занятыеЯкоря.has(имя)) имя = `${основа}-${н++}`;
    занятыеЯкоря.add(имя);
    return имя;
  };

  while (i < строки.length) {
    const с = строки[i];

    // Блок кода
    if (/^```/.test(с)) {
      const шапка = с.slice(3).trim();
      const язык = шапка.split(/\s+/)[0] || '';
      const тело = [];
      i += 1;
      while (i < строки.length && !/^```/.test(строки[i])) тело.push(строки[i++]);
      i += 1;

      // Схема. Всё, что стоит в шапке после слова `mermaid`, — подпись под
      // схемой: GitHub читает только первое слово, значит исходник остаётся
      // валидным mermaid и там.
      if (язык === 'mermaid') {
        try {
          вывод.push(схемаВSVG(тело.join('\n'), шапка.slice('mermaid'.length).trim()));
        } catch (ошибка) {
          // Молча оставить исходник схемы текстом нельзя: читатель увидит
          // мусор вместо картинки, а сборка позеленеет. Отказ — громкий.
          беды.push(`схема не рисуется: ${ошибка.message}`);
        }
        continue;
      }

      const исходникБлока = тело.join('\n');

      /* Подсветка flang. Красит СБОРКА настоящим лексером языка — см.
         `podsvetka.mjs`, там же и довод, почему не регулярками и почему блок
         без метки языка проверяется парсером, а не лексером. Здесь остаётся
         только решение «наш блок или чужой» и счёт для вывода сборки. */
      const помечен = язык === 'flang';
      const распознан = язык === '' && целаяПрограмма(исходникБлока);
      if (помечен || распознан) {
        подсветка.всего += 1;
        подсветка[помечен ? 'помечено' : 'распознано'] += 1;
        const окрашенный = подсветить(исходникБлока);
        подсветка[окрашенный === null ? 'отказано' : 'окрашено'] += 1;
        const доехало = окрашенный ?? экранировать(исходникБлока);
        if (снятьРазметку(доехало) === исходникБлока) подсветка.сверено += 1;
        вывод.push(`<pre class="lang-flang"><code>${доехало}</code></pre>`);
        continue;
      }

      const классЯзыка = язык ? ` class="lang-${экранировать(язык)}"` : '';
      вывод.push(`<pre${классЯзыка}><code>${экранировать(исходникБлока)}</code></pre>`);
      continue;
    }

    // Заголовок
    const заг = /^(#{1,6})\s+(.*)$/.exec(с);
    if (заг) {
      const уровень = заг[1].length;
      const текст = заг[2].trim();
      const я = свободныйЯкорь(текст);
      // Оглавление берёт РАЗОБРАННЫЙ заголовок, а не сырой. Раньше брало сырой,
      // и в оглавлении стояло `**СДЕЛАНО**` со звёздочками и `` `flang check` ``
      // с обратными кавычками: тот же класс, что жирный вокруг встроенного кода.
      // Ссылка внутри заголовка разворачивается в свой текст — вложенный <a>
      // внутри пункта оглавления был бы невалидной разметкой.
      if (уровень === 2 || уровень === 3) {
        const разобран = строка(текст, null).replace(/<a\b[^>]*>(.*?)<\/a>/gsu, '$1');
        оглавление.push({ уровень, текст, html: разобран, якорь: я });
      }
      вывод.push(`<h${уровень} id="${я}">${строка(текст, ссылки)}</h${уровень}>`);
      i += 1;
      continue;
    }

    // Разделитель
    if (/^(-{3,}|\*{3,}|_{3,})\s*$/.test(с)) {
      вывод.push('<hr>');
      i += 1;
      continue;
    }

    // Таблица: строка с | и следующая из дефисов
    if (/\|/.test(с) && i + 1 < строки.length && /^[\s|:-]+$/.test(строки[i + 1]) && /-/.test(строки[i + 1])) {
      const ячейки = (р) => р.replace(/^\||\|$/g, '').split('|').map((я) => я.trim());
      const шапка = ячейки(с);
      const выравнивание = ячейки(строки[i + 1]).map((я) =>
        /^:-+:$/.test(я) ? 'center' : /-+:$/.test(я) ? 'right' : 'left',
      );
      i += 2;
      const тело = [];
      while (i < строки.length && /\|/.test(строки[i]) && строки[i].trim()) тело.push(ячейки(строки[i++]));
      const кл = (н) => (выравнивание[н] && выравнивание[н] !== 'left' ? ` class="ta-${выравнивание[н]}"` : '');
      вывод.push(
        '<div class="tw"><table><thead><tr>' +
          шапка.map((я, н) => `<th${кл(н)}>${строка(я, ссылки)}</th>`).join('') +
          '</tr></thead><tbody>' +
          тело
            .map((р) => '<tr>' + р.map((я, н) => `<td${кл(н)}>${строка(я, ссылки)}</td>`).join('') + '</tr>')
            .join('') +
          '</tbody></table></div>',
      );
      continue;
    }

    // Цитата
    if (/^>\s?/.test(с)) {
      const тело = [];
      while (i < строки.length && /^>\s?/.test(строки[i])) тело.push(строки[i++].replace(/^>\s?/, ''));
      const внутри = разобрать(тело.join('\n'));
      ссылки.push(...внутри.ссылки);
      беды.push(...внутри.беды);
      вывод.push(`<blockquote>${внутри.html}</blockquote>`);
      continue;
    }

    // Списки — маркированные и нумерованные, с вложенностью по отступу
    const пункт = /^(\s*)([-*+]|\d+[.)])\s+(.*)$/.exec(с);
    if (пункт) {
      const { html, следующая } = список(строки, i, ссылки);
      вывод.push(html);
      i = следующая;
      continue;
    }

    // Пустая строка
    if (!с.trim()) {
      i += 1;
      continue;
    }

    // Абзац: до пустой строки или до начала другого блока
    const абзац = [];
    while (
      i < строки.length &&
      строки[i].trim() &&
      !/^(#{1,6}\s|```|>|\s*([-*+]|\d+[.)])\s)/.test(строки[i]) &&
      !/^(-{3,}|\*{3,}|_{3,})\s*$/.test(строки[i])
    ) {
      абзац.push(строки[i++]);
    }
    if (абзац.length) вывод.push(`<p>${строка(абзац.join(' '), ссылки)}</p>`);
  }

  return { html: вывод.join('\n'), оглавление, ссылки, беды, подсветка };
}

/** Собирает список, начиная со строки `начало`. Возвращает html и номер следующей строки. */
function список(строки, начало, ссылки) {
  const первый = /^(\s*)([-*+]|\d+[.)])\s+/.exec(строки[начало]);
  const отступ = первый[1].length;
  const нумерованный = /\d/.test(первый[2]);
  const пункты = [];
  let i = начало;

  while (i < строки.length) {
    const м = /^(\s*)([-*+]|\d+[.)])\s+(.*)$/.exec(строки[i]);
    if (!м) {
      // Продолжение пункта: непустая строка с отступом больше нашего
      if (строки[i].trim() && /^\s+/.test(строки[i]) && пункты.length) {
        пункты[пункты.length - 1].строки.push(строки[i].trim());
        i += 1;
        continue;
      }
      break;
    }
    const текущийОтступ = м[1].length;
    if (текущийОтступ < отступ) break;
    if (текущийОтступ > отступ) {
      // Вложенный список — собираем рекурсивно и вешаем на последний пункт
      const внутри = список(строки, i, ссылки);
      if (пункты.length) пункты[пункты.length - 1].вложенный = внутри.html;
      i = внутри.следующая;
      continue;
    }
    пункты.push({ строки: [м[3]], вложенный: '' });
    i += 1;
  }

  const тег = нумерованный ? 'ol' : 'ul';
  const html =
    `<${тег}>` +
    пункты.map((п) => `<li>${строка(п.строки.join(' '), ссылки)}${п.вложенный}</li>`).join('') +
    `</${тег}>`;
  return { html, следующая: i };
}
