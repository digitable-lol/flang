/**
 * Чтение и подстановка чисел сайта. Ни одного тяжёлого ввоза.
 *
 * ── Почему отдельный файл ───────────────────────────────────────────────────
 * ЗАМЕР чисел (`site-numbers.mjs`) загружает компилятор целиком: свод корпуса
 * считает `flang/scripts/proof-ledger.mjs`, а тот на верхнем уровне поднимает
 * слой ведомости. Это полминуты работы и всё дерево языка.
 *
 * СБОРКЕ сайта ничего этого не нужно: она читает готовый `numbers.json`. Если
 * бы она ввозила замер ради двух функций, обещание «сайт собирается одной
 * командой без единой зависимости» перестало бы быть правдой — сборка стала бы
 * зависеть от того, чтобы компилятор в этом дереве вообще загружался.
 *
 * Поэтому здесь лежит ровно то, что нужно сборке, и ничего больше.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Версия состава полей. Растёт, когда меняется набор чисел. */
export const ФОРМАТ = 1;

export const ПУТЬ_ЧИСЕЛ = fileURLToPath(new URL('./numbers.json', import.meta.url));

/** Числа для сборки. Отказывает словами: сборка не обязана гадать. */
export function прочитатьЧисла() {
  let сырое;
  try {
    сырое = readFileSync(ПУТЬ_ЧИСЕЛ, 'utf8');
  } catch (беда) {
    throw new Error(`docs/site/numbers.json не читается (${беда.code}). Лечится: ./ярлык numbers`);
  }
  const замер = JSON.parse(сырое);
  if (замер.формат !== ФОРМАТ) {
    throw new Error(
      `docs/site/numbers.json написан в формате ${замер.формат}, а ждали ${ФОРМАТ}. Лечится: ./ярлык numbers`,
    );
  }
  return замер.числа;
}

/**
 * Что считается подстановкой.
 *
 * Точка в ключе обязательна, и это не украшение: в дереве есть документы с
 * `{{incorrect}}` и `{{header|flang}}` — это чужие шаблоны Rosetta, и трогать
 * их нельзя. Ключ с точкой ни с одним из них не совпадает.
 */
const ПОДСТАНОВКА = /\{\{([а-яёa-z]+(?:\.[а-яёА-ЯЁa-zA-Z]+)+)(?:\|([а-яё]+))?\}\}/gu;

/**
 * ПРИМЕР, А НЕ ЧИСЛО, помечается восклицательным знаком: `{{!корпус.функций}}`
 * доезжает до читателя как `{{корпус.функций}}` и значения не получает.
 *
 * Раньше пример узнавался ПО МЕСТУ: подстановка не работала внутри кода, чтобы
 * страницу про сам приём можно было написать. Место — плохая примета: 23 августа
 * 2026 читатель нашёл на опубликованной странице установки `flang
 * {{выпуск.версия}}` в обратных кавычках, и это была не примета, а утечка.
 * Той же дырой утекали ещё три места (`install` и `getting-started`, обе
 * половины), и ни одно из них не поймал ни один сторож: подстановка код
 * пропускала, сторож двойных скобок — тоже.
 *
 * Теперь пример узнаётся ПО ЗНАКУ, который автор поставил сам. Место больше ни
 * при чём: подстановка идёт по всему тексту, включая код.
 */
const ПРИМЕР = /\{\{!([^{}\n]*)\}\}/gu;

/** Разрядами: 116303 → «116 303». Так большие числа стоят во всей этой прозе. */
export const разрядами = (н) => String(н).replace(/\B(?=(\d{3})+(?!\d))/gu, ' ');

/**
 * Подставляет числа в текст страницы.
 *
 * Неизвестный ключ — БЕДА, а не пропуск: подстановка, оставшаяся в тексте,
 * доезжает до читателя двойными скобками, и заметит её он, а не дерево.
 */
export function подставить(текст, числа) {
  const беды = [];
  const заменить = (кусок) =>
    кусок.replace(ПОДСТАНОВКА, (всё, ключ, вид) => {
      if (!(ключ in числа)) {
        беды.push(`неизвестное число ${всё}`);
        return всё;
      }
      const значение = числа[ключ];
      if (вид === undefined) return String(значение);
      if (вид === 'разрядами') return разрядами(значение);
      беды.push(`неизвестный вид числа ${всё}`);
      return всё;
    });

  // Пример прячется под метку, которую образец подстановки не узнаёт, и
  // возвращается на место уже после замены. Так пример не получает значения, а
  // всё остальное получает — где бы оно ни стояло, в прозе или в коде.
  const примеры = [];
  const спрятано = текст.replace(ПРИМЕР, (всё, ключ) => {
    примеры.push(ключ);
    return `\u0000ПРИМЕР${примеры.length - 1}\u0000`;
  });
  const подставлено = заменить(спрятано);
  const готово = подставлено.replace(
    /\u0000ПРИМЕР(\d+)\u0000/gu,
    (всё, н) => `{{${примеры[Number(н)]}}}`,
  );
  return { текст: готово, беды };
}
