// Подсветка flang на страницах сайта — во время СБОРКИ, не в браузере.
//
// ── Почему красит лексер языка, а не набор правил ───────────────────────────
// Подсветка, написанная отдельными правилами (регулярками, списком слов в
// таблице темы), — это ВТОРОЕ описание языка. Второе описание расходится с
// первым в тот день, когда в язык добавят слово: таблица слов лексера ведёт
// сотню с лишним понятий на четырёх поверхностях записи, и ни один список,
// переписанный сюда руками, не переживёт первого пополнения. Поэтому здесь
// зовётся НАСТОЯЩИЙ `tokenize` из `flang/src/lexer.mjs` — тот самый, которым
// язык читает свои файлы. Разойтись ему не с чем: он и есть язык.
//
// Отсюда же и цена: подсветка знает ровно то, что знает лексер. Комментарии
// лексер выбрасывает молча (токена у них нет), поэтому их границы считаются
// здесь отдельно — но и это делается НЕ угадыванием: в исходнике, который
// лексер прочитал целиком, знак `/` не встречается больше нигде, кроме
// комментария и внутренности кавычек. Кавычки известны по токенам, значит
// остальные `/` — комментарии, и других вариантов нет.
//
// ── Какой блок считается flang ──────────────────────────────────────────────
// Метка на ограде (```flang) — слово автора, ей верят: блок отдаётся лексеру.
// Метка ЧУЖОГО языка (```bash, ```json, ```js, ```c…) — запрет: такой блок не
// трогается вовсе, ни при каких обстоятельствах.
// Метки нет — блок отдаётся ПАРСЕРУ языка, и красится, только если тот принял
// его как целую программу. Это не вкусовщина, а замер: на дереве из 509 блоков
// парсер принял 0 (ноль) блоков, помеченных чужим языком, и 77 блоков без
// метки — ровно тех, где лежат программы (справочник, учебник, операции).
// Требование «целая программа» здесь строже лексера намеренно: вывод команды
// («функций 99: тотальных 95») лексер читает без единой жалобы и красит в нём
// случайно совпавшие слова, а парсер такой блок отвергает.
//
// ── Отказ ───────────────────────────────────────────────────────────────────
// Блок, который не удалось разметить, остаётся ровно тем, чем был: серым
// текстом. Сборка от этого не краснеет — она печатает, сколько таких. Цветной
// текст, у которого потерялся знак, был бы хуже серого, поэтому каждая
// размётка ПРОВЕРЯЕТСЯ перед выдачей: снять теги — обязано получиться слово в
// слово то, что пришло. Не получилось — блок отдаётся серым.

import { tokenize } from '../../flang/src/lexer.mjs';
import { parse } from '../../flang/src/parser.mjs';

/* Тот же набор, что у `markdown.mjs`: серый блок и цветной обязаны показывать
   одни и те же знаки. Списан, а не ввезён, чтобы не заводить круг ввоза
   (markdown ввозит подсветку) — а что списан верно, проверяется на каждом
   блоке: `снятьРазметку` обязана вернуть исходник знак в знак, иначе блок
   отдаётся серым. Разъехаться молча этим двум наборам не на чем. */
const ЭКРАН = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
const экранировать = (т) => String(т).replace(/[&<>"]/g, (с) => ЭКРАН[с]);

/**
 * Виды токенов → классы разметки. Латиницей: классы едут в CSS и в HTML.
 *
 * ЦВЕТА ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО. Класс называет РОЛЬ («это строка»), а чем
 * роль покрашена — дело таблицы стилей: у роли две подложки (светлая тема и
 * тёмная) и один замер контраста на каждую, и всё это живёт в одном месте —
 * `docs/site/style.css`, слой `--flang-syn-*`. Появись цвет ещё и здесь,
 * палитру пришлось бы править в двух файлах, а расходятся такие пары молча.
 *
 * Сами роли розданы не заново: сопоставление взято у Digitable как есть
 * (`--course-syn-*`, courses-v2.css) — ключевое слово синий, имя циан, строка
 * зелёный, число оранжевый, комментарий приглушённый. Шестой роли портала
 * («объявление», фиолетовый) здесь нет соответствия: лексер flang такого вида
 * токена не выдаёт, и придумывать его подсветке нельзя — она красит ровно то,
 * что язык прочитал, иначе это второе описание языка (см. шапку файла).
 */
const КЛАССЫ = {
  слово: 'tok-slovo', // ключевое слово языка
  имя: 'tok-imya', // имя в ёлочках «…»
  строка: 'tok-stroka',
  число: 'tok-chislo',
  комментарий: 'tok-kommentariy',
};

/**
 * Тот же перевод строк, что делает лексер первым действием. Если он что-то
 * меняет, значит смещения токенов считаются не от того текста, который поедет
 * на страницу, — и красить нельзя.
 */
const нормализовать = (т) => String(т).replace(/^\uFEFF/u, '').replace(/\r\n?/gu, '\n');

/**
 * Считает ли ПАРСЕР языка этот текст целой программой.
 *
 * Нужно ровно для блоков без метки языка. Парсер здесь — не украшение: он
 * единственный, кто отличает программу от вывода команды, не заводя для этого
 * второго описания языка.
 */
export function целаяПрограмма(исходник) {
  try {
    parse(нормализовать(исходник));
    return true;
  } catch {
    return false;
  }
}

/** Смещения начал строк: `span {line, column}` → смещение в строке текста. */
function началаСтрок(текст) {
  const начала = [0, 0]; // строки нумеруются с единицы
  for (let i = 0; i < текст.length; i += 1) if (текст[i] === '\n') начала.push(i + 1);
  return начала;
}

/**
 * Конец закавыченного токена: от открывающей кавычки до закрывающей.
 * Правило снятия косой черты — то же, что у `readQuoted` лексера: `\` съедает
 * следующий знак, а `\uXXXX` — ещё четыре.
 */
function конецКавычки(текст, начало, закрывающая) {
  let п = начало + 1;
  while (п < текст.length) {
    const з = текст[п];
    п += 1;
    if (з === закрывающая) return п;
    if (з === '\\' && п < текст.length) {
      const снятый = текст[п];
      п += 1;
      if (снятый === 'u') п += 4;
    }
  }
  return null; // лексер такого не пропустит, но верить на слово нечему
}

/**
 * Отрезки, которые надо покрасить, по токенам.
 * Возвращает null, если хоть один отрезок не сошёлся с исходником, — тогда
 * блок остаётся серым целиком, а не наполовину.
 */
function отрезкиПоТокенам(текст, токены) {
  const начала = началаСтрок(текст);
  const отрезки = [];
  const кавычки = []; // где стоят строки и «имена» — там комментариев не ищут

  const смещение = (место) => {
    const строка = начала[место.line];
    if (строка === undefined) return null;
    const с = строка + место.column - 1;
    return с <= текст.length ? с : null;
  };

  for (const т of токены) {
    const начало = смещение(т.span);
    if (начало === null) return null;

    if (т.kind === 'keyword') {
      // Фраза («не меньше», «отображается в поле») склеена лексером из слов, и
      // в `text` лежат сами слова исходника. Красится КАЖДОЕ слово по
      // отдельности: между ними может стоять пробел или блочный комментарий, и
      // накрывать их одним отрезком значило бы красить и его.
      let п = начало;
      for (const слово of т.text.split(' ')) {
        while (п < текст.length && /[\s]/u.test(текст[п])) п += 1;
        if (текст[п] === '/' && текст[п + 1] === '*') {
          const конец = текст.indexOf('*/', п + 2);
          if (конец === -1) return null;
          п = конец + 2;
          continue;
        }
        if (!текст.startsWith(слово, п)) return null;
        отрезки.push({ начало: п, конец: п + слово.length, класс: КЛАССЫ.слово });
        п += слово.length;
      }
      continue;
    }

    if (т.kind === 'name' && т.quoted) {
      const конец = конецКавычки(текст, начало, '»');
      if (конец === null || текст[начало] !== '«') return null;
      отрезки.push({ начало, конец, класс: КЛАССЫ.имя });
      кавычки.push({ начало, конец });
      continue;
    }

    if (т.kind === 'string') {
      const открывающая = текст[начало];
      if (открывающая !== '"' && открывающая !== "'") return null;
      const конец = конецКавычки(текст, начало, открывающая);
      if (конец === null) return null;
      отрезки.push({ начало, конец, класс: КЛАССЫ.строка });
      кавычки.push({ начало, конец });
      continue;
    }

    if (т.kind === 'number') {
      // У числа лексер сохранил исходную запись (`text`), а не только значение:
      // `1e3` и `1000` — одно значение и разная длина в исходнике.
      if (!текст.startsWith(т.text, начало)) return null;
      отрезки.push({ начало, конец: начало + т.text.length, класс: КЛАССЫ.число });
      continue;
    }
    // Имена без кавычек, знаки, стрелки, отступы — не красятся: спокойный
    // текст важнее пёстрого.
  }

  return { отрезки, кавычки };
}

/**
 * Комментарии. Токена у них нет — лексер их выбрасывает, — поэтому границы
 * считаются здесь. Угадывания в этом нет: в исходнике, прочитанном лексером
 * целиком, `/` бывает только в комментарии и внутри кавычек. Кавычки уже
 * известны по токенам, значит всё остальное — комментарий, и промахнуться
 * не на чем.
 */
function отрезкиКомментариев(текст, кавычки) {
  const порядок = [...кавычки].sort((а, б) => а.начало - б.начало);
  const отрезки = [];
  let п = 0;
  let к = 0;
  while (п < текст.length) {
    while (к < порядок.length && порядок[к].конец <= п) к += 1;
    if (к < порядок.length && п >= порядок[к].начало) {
      п = порядок[к].конец;
      continue;
    }
    if (текст[п] === '/' && текст[п + 1] === '/') {
      const перевод = текст.indexOf('\n', п);
      const конец = перевод === -1 ? текст.length : перевод;
      отрезки.push({ начало: п, конец, класс: КЛАССЫ.комментарий });
      п = конец;
      continue;
    }
    if (текст[п] === '/' && текст[п + 1] === '*') {
      const закрытие = текст.indexOf('*/', п + 2);
      const конец = закрытие === -1 ? текст.length : закрытие + 2;
      отрезки.push({ начало: п, конец, класс: КЛАССЫ.комментарий });
      п = конец;
      continue;
    }
    п += 1;
  }
  return отрезки;
}

/** Снять теги и вернуть знаки на место — тем же, чем их экранировали. */
export function снятьРазметку(html) {
  return String(html)
    .replace(/<span class="[a-z-]+">/gu, '')
    .replace(/<\/span>/gu, '')
    .replace(/&lt;/gu, '<')
    .replace(/&gt;/gu, '>')
    .replace(/&quot;/gu, '"')
    .replace(/&amp;/gu, '&');
}

/**
 * Размечает исходник flang. Возвращает готовое содержимое `<code>` — или null,
 * если разметить не вышло: тогда блок печатается серым, как печатался раньше.
 */
export function подсветить(исходник) {
  const текст = нормализовать(исходник);
  if (текст !== String(исходник)) return null;

  let токены;
  try {
    токены = tokenize(текст);
  } catch {
    return null;
  }

  const посчитано = отрезкиПоТокенам(текст, токены);
  if (посчитано === null) return null;

  const все = [...посчитано.отрезки, ...отрезкиКомментариев(текст, посчитано.кавычки)].sort(
    (а, б) => а.начало - б.начало,
  );

  const части = [];
  let п = 0;
  for (const о of все) {
    if (о.начало < п) return null; // отрезки наложились — красить нечестно
    if (о.начало > п) части.push(экранировать(текст.slice(п, о.начало)));
    части.push(`<span class="${о.класс}">${экранировать(текст.slice(о.начало, о.конец))}</span>`);
    п = о.конец;
  }
  части.push(экранировать(текст.slice(п)));
  const html = части.join('');

  // Сторож потери знаков. Стоит ЗДЕСЬ, а не в отдельной проверке, потому что
  // цветной текст с потерянным знаком доедет до читателя молча, а серый — нет.
  // Сколько блоков эту сверку прошли — печатает сборка числом («сверено N из
  // N»), и сверяет она не только цветные: серый блок тоже едет через
  // экранирование. Прозе «всё сверено» верить нечем, числу — есть.
  if (снятьРазметку(html) !== текст) return null;

  return html;
}
