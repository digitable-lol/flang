// Сторож поиска: настоящие запросы обязаны находить настоящие страницы.
//
// Проверяется ТОТ ЖЕ файл, что читает браузер, — `poisk.js` целиком, вместе с
// приведением «ё»/«е» и отсечением окончаний. Он для этого и написан так, чтобы
// половина, говорящая с окном, включалась только при наличии `document`: в node
// его нет, и остаются чистые функции.
//
// Сторож стоит внутри сборки, а не отдельным скриптом, по той же причине, по
// которой там же стоит проверка ссылок: сайт уже собирается в CI, а вторая
// версия протухает за неделю, пока её никто не сторожит.
//
// Список запросов — не выдумка. «Свёртка» проверяет букву «ё» (в дереве есть и
// «свёртка», и «свертка»), «свертка» — её же с другой стороны, «сокращатель» —
// слово, которое стоит только в подзаголовке разбора случаев, «mkdtemp» —
// латинское имя внутри заметки базы знаний, до которого отсечение окончаний
// доходить не должно.

import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createContext, runInContext } from 'node:vm';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));

/** Поднимает `poisk.js` в node и отдаёт его чистые функции. */
export function поднятьПоиск() {
  const код = readFileSync(join(ЗДЕСЬ, 'poisk.js'), 'utf8');
  const окружение = createContext({ console });
  runInContext(код, окружение, { filename: 'poisk.js' });
  const поиск = окружение.флангПоиск;
  if (!поиск || typeof поиск.искать !== 'function') throw new Error('poisk.js не выложил флангПоиск');
  return поиск;
}

/**
 * Запрос → страница, которая обязана найтись, и место не ниже которого.
 *
 * У «свёртки» место пятое, а не первое, и это не уступка: две заметки базы
 * знаний названы свёрткой в заголовке («Свёртка в flang левая…»), и они по
 * делу стоят выше раздела справочника, где свёртка — один подзаголовок из
 * сорока. Сторожится то, что справочник ВИДЕН в ответе, а не то, что он первый.
 */
export const ЖДЁМ = [
  { запрос: 'свёртка', адрес: 'language.html', неНиже: 5 },
  { запрос: 'свертка', адрес: 'language.html', неНиже: 5 },
  { запрос: 'сокращатель', адрес: 'case-studies.html', неНиже: 2 },
  { запрос: 'тотальность', адрес: 'totality.html', неНиже: 2 },
  { запрос: 'mkdtemp', адрес: 'knowledge-a-feature-macro-that-opens-on-glibc-closes-on-darwin.html', неНиже: 2 },
];

/**
 * Прогоняет ожидания по настоящему указателю. Возвращает беды — сборка их
 * складывает в свой список и отказывает, как отказывает на битой ссылке.
 */
export function проверитьПоиск(указатель) {
  const поиск = поднятьПоиск();
  const разобранный = поиск.разобратьУказатель(указатель);
  const беды = [];
  for (const ж of ЖДЁМ) {
    const найдено = поиск.искать(разобранный, ж.запрос, { язык: 'ru', сколько: 12 });
    const место = найдено.findIndex((н) => н.адрес === ж.адрес);
    if (место < 0) {
      беды.push(`поиск «${ж.запрос}» не нашёл ${ж.адрес} (нашлось: ${найдено.slice(0, 3).map((н) => н.адрес).join(', ') || 'ничего'})`);
    } else if (место >= ж.неНиже) {
      беды.push(`поиск «${ж.запрос}» поставил ${ж.адрес} на ${место + 1}-е место, ждали не ниже ${ж.неНиже}-го`);
    }
  }
  return беды;
}

// ── Оконная половина ────────────────────────────────────────────────────────
// Отбор проверен выше; здесь проверяется СВЯЗЬ — та часть, которая ломается
// молча: поле не открылось, указатель не подгрузился, Enter никуда не увёл.
// Браузера в этой среде нет, поэтому DOM подменяется заглушкой на сотню строк:
// она умеет ровно то, чего просит `poisk.js`, и ни строкой больше. Это не
// замена настоящему браузеру — это защита от того, что скрипт перестанет
// вызывать то, что вызывал.

/** Узел-заглушка. Знает только то, чем пользуется `poisk.js`. */
function узел(имя) {
  return {
    tagName: String(имя).toUpperCase(),
    className: '', id: '', innerHTML: '', value: '', hidden: false,
    дети: [], атрибуты: {}, слушатели: {},
    setAttribute(и, з) { this.атрибуты[и] = String(з); },
    getAttribute(и) { return и in this.атрибуты ? this.атрибуты[и] : null; },
    removeAttribute(и) { delete this.атрибуты[и]; },
    appendChild(у) { this.дети.push(у); if (this.приДобавлении) this.приДобавлении(у); return у; },
    contains(у) { return у === this; },
    addEventListener(и, ф) { (this.слушатели[и] = this.слушатели[и] || []).push(ф); },
    послать(и, е) { for (const ф of this.слушатели[и] || []) ф(е || {}); },
    focus() {}, blur() {}, select() {}, querySelector() { return null; },
  };
}

/**
 * Прогоняет `poisk.js` целиком на заглушке DOM с настоящим указателем.
 * `текстУказателя` — тот самый файл, что ляжет рядом со страницами.
 */
export function проверитьОкно(текстУказателя) {
  const короб = узел('form');
  короб.className = 'poisk';
  короб.hidden = true;
  короб.setAttribute('data-koren', '');
  const поле = узел('input');
  короб.querySelector = () => поле;

  const голова = узел('head');
  const окружение = createContext({
    console,
    window: { location: { href: '' } },
    document: {
      documentElement: { lang: 'ru' },
      head: голова,
      activeElement: null,
      querySelector: (что) => (что === '.poisk' ? короб : null),
      createElement: (имя) => узел(имя),
      addEventListener: () => {},
    },
  });
  // Указатель приезжает тем же путём, что в браузере: тег `<script src>`, а на
  // его `onload` — уже готовая глобальная переменная.
  голова.приДобавлении = (тег) => {
    if (!/poisk-ukazatel\.js$/u.test(тег.src || '')) return;
    runInContext(текстУказателя, окружение, { filename: 'poisk-ukazatel.js' });
    тег.onload();
  };
  runInContext(readFileSync(join(ЗДЕСЬ, 'poisk.js'), 'utf8'), окружение, { filename: 'poisk.js' });

  const беды = [];
  const ждём = (что, вышло) => { if (!вышло) беды.push(`поиск в окне: ${что}`); };

  ждём('скрипт открыл поле (сняв hidden с формы)', короб.hidden === false);
  const вывод = короб.дети[0];
  ждём('скрипт создал вывод и оставил его закрытым', !!вывод && вывод.hidden === true);
  if (!вывод) return беды;

  поле.value = ЖДЁМ[0].запрос;
  поле.послать('input');
  ждём('набранный запрос открыл вывод', вывод.hidden === false);
  ждём('вывод объявлен раскрытым для чтения с экрана', поле.getAttribute('aria-expanded') === 'true');
  ждём('первая строка ответа выбрана', /poisk-otvet vybran/u.test(вывод.innerHTML));

  поле.послать('keydown', { key: 'ArrowDown', preventDefault() {} });
  ждём('стрелка вниз сдвинула выбор', /id="poisk-o1"[^>]*aria-selected="true"/u.test(вывод.innerHTML));

  поле.послать('keydown', { key: 'Enter', preventDefault() {} });
  ждём('Enter увёл на страницу', /\.html$/u.test(окружение.window.location.href));

  поле.value = '';
  поле.послать('input');
  ждём('пустой запрос закрыл вывод', вывод.hidden === true);

  // Слово, которого в дереве нет ни на одной странице.
  поле.value = 'зурбаган';
  поле.послать('input');
  ждём('на слово, которого нет, сказано «ничего не нашлось»', /ничего не нашлось/u.test(вывод.innerHTML));

  return беды;
}
