/* Поиск по документации flang — целиком в браузере.
 *
 * Сервера нет: сайт лежит на GitHub Pages. Библиотек тоже нет — ни одной, и это
 * то же решение, что у разбора markdown и у схем: страница обязана работать без
 * сети, кроме себя самой. CDN — это сеть.
 *
 * Указатель (`poisk-ukazatel.js`) подгружается ЛЕНИВО, при первом касании поля:
 * пришедшему читать страницу он не нужен, а весит сотни килобайт. Загруженный
 * один раз, он лежит в кеше браузера и на остальных страницах берётся оттуда.
 *
 * ── Русский язык ────────────────────────────────────────────────────────────
 * Ищут по-русски, и это главный случай, а не запасной. Отсюда два правила
 * приведения: «ё» и «е» — одна буква (в дереве есть и «свёртка», и «свертка», в
 * словаре языка они стоят соседними ячейками одной строки), и слово
 * сравнивается по ОСНОВЕ, а не целиком: набравший «свёртка» обязан найти
 * «свёртке». Основа берётся отсечением одного русского окончания — это не
 * морфология, а её дешёвая тень, и её хватает: список окончаний закрывает
 * падежи существительных и прилагательных, а латинские имена (`mkdtemp`) не
 * трогает вовсе.
 *
 * ── Без JavaScript ──────────────────────────────────────────────────────────
 * Поле поиска размечено `hidden`, открывает его ЭТОТ скрипт. Не загрузился —
 * поля нет, и страница выглядит ровно как до поиска: боковое оглавление на
 * месте, читать можно всё. Мёртвое поле, которое принимает буквы и не отвечает,
 * хуже отсутствующего.
 *
 * ── Проверяемость ───────────────────────────────────────────────────────────
 * Приведение и отбор — чистые функции, выложенные в `window.флангПоиск`. Тот же
 * файл, что читает браузер, читает и проверка в node (`vm.runInContext` без
 * `document`), поэтому поиск проверяется прогоном и без браузера.
 */
(function () {
  'use strict';

  /* ── Приведение ──────────────────────────────────────────────────────────
     Регистр не мешает; «ё» приравнена к «е»; всё, что не буква и не цифра,
     становится пробелом — так `flang check`, `flang-check` и `flang.check`
     ищутся одинаково. `ПоЗнакам` не склеивает пробелы и не обрезает края:
     длина сохраняется, и место совпадения годится для куска исходного текста. */
  function привестиПоЗнакам(текст) {
    return String(текст).toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\p{N}_]/gu, ' ');
  }

  function привести(текст) {
    return привестиПоЗнакам(текст).replace(/\s+/g, ' ').trim();
  }

  /* Окончания отсекаются по одному, от длинных к коротким, и только если
     остаток не короче четырёх знаков: иначе «поле» стало бы «пол», а это другое
     слово. Латиницы в списке нет намеренно — `mkdtemp` и `check` сравниваются
     как есть. */
  var ОКОНЧАНИЯ = [
    'иями', 'ями', 'ами', 'иях', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими',
    'ях', 'ах', 'ой', 'ей', 'ый', 'ий', 'ая', 'яя', 'ое', 'ее', 'ую', 'юю',
    'ам', 'ям', 'ов', 'ев', 'ью', 'ье', 'ья', 'ии', 'ие', 'ия', 'ые', 'ых',
    'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'й', 'ь'
  ];

  function основа(слово) {
    for (var i = 0; i < ОКОНЧАНИЯ.length; i++) {
      var к = ОКОНЧАНИЯ[i];
      if (слово.length - к.length >= 4 && слово.slice(слово.length - к.length) === к) {
        return слово.slice(0, слово.length - к.length);
      }
    }
    return слово;
  }

  /** Строка → массив основ. Пустая строка даёт пустой массив. */
  function основыСтроки(текст) {
    var приведённая = привести(текст);
    if (!приведённая) return [];
    var слова = приведённая.split(' ');
    var из = [];
    for (var i = 0; i < слова.length; i++) if (слова[i]) из.push(основа(слова[i]));
    return из;
  }

  /* ── Совпадение ──────────────────────────────────────────────────────────
     Слово поля совпало, если его основа НАЧИНАЕТСЯ с основы запроса. Начало, а
     не равенство: ответ показывается по мере набора, и «свёр» обязан находить
     свёртку раньше, чем слово дописано.

     Обратное начало — тоже совпадение, но только от четырёх знаков. Причина
     измерена: «тотальность» и «тотальная» — разные части речи, отсечение даёт
     «тотальност» и «тотальн», и одностороннее правило не находило страницу
     «Что даёт признак „тотальная“» по слову «тотальность» вовсе. Порог в
     четыре знака держит правило от превращения в «совпадает всё»: основа
     короче четырёх — это предлог или обрубок, начатый с клавиатуры. */
  function встречается(основыПоля, искомая) {
    for (var i = 0; i < основыПоля.length; i++) {
      var поле = основыПоля[i];
      if (поле.length >= искомая.length) {
        if (поле.slice(0, искомая.length) === искомая) return true;
      } else if (поле.length >= 4 && искомая.slice(0, поле.length) === поле) {
        return true;
      }
    }
    return false;
  }

  /* Вес поля. Имя страницы весит вдесятеро против текста: если слово стоит в
     имени, страница про него, а не упоминает его по дороге. */
  var ВЕС_ИМЕНИ = 10;
  var ВЕС_ЗАГОЛОВКОВ = 4;
  var ВЕС_РАЗДЕЛА = 2;
  var ВЕС_ТЕКСТА = 1;
  var ВЕС_СВОЕГО_ЯЗЫКА = 3;
  /* Страница раздела выше заметки базы знаний при равном совпадении. Не вкус, а
     счёт: заметок 189 против 55 страниц разделов, и без этой добавки любое
     общее слово («пакеты», «типы») отдаёт четыре заметки и ни одного
     справочника. Заметки не прячутся — они идут следом. */
  var ВЕС_СПРАВОЧНИКА = 4;

  /** Указатель → разобранные основы полей. Считается один раз на страницу. */
  function разобратьУказатель(указатель) {
    var из = [];
    var страницы = (указатель && указатель.страницы) || [];
    for (var i = 0; i < страницы.length; i++) {
      var з = страницы[i];
      из.push({
        адрес: з[0], имя: з[1], раздел: з[2], язык: з[3], заголовки: з[4], текст: з[5], заметка: !!з[6],
        основыИмени: основыСтроки(з[1]),
        основыЗаголовков: основыСтроки(з[4]),
        основыРаздела: основыСтроки(з[2]),
        основыТекста: основыСтроки(з[5])
      });
    }
    return из;
  }

  /**
   * Отбор. Страница попадает в ответ, только если найдено КАЖДОЕ слово запроса
   * (иначе «свёртка списка» вернула бы всё, где есть список); порядок — по
   * сумме весов полей, в которых слова нашлись.
   */
  function искать(разобранный, запрос, настройки) {
    var основы = основыСтроки(запрос);
    if (!основы.length) return [];
    var язык = (настройки && настройки.язык) || 'ru';
    var сколько = (настройки && настройки.сколько) || 12;
    var ответ = [];
    for (var i = 0; i < разобранный.length; i++) {
      var с = разобранный[i];
      var вес = 0;
      var всеНашлись = true;
      for (var j = 0; j < основы.length; j++) {
        var о = основы[j];
        var своё = 0;
        if (встречается(с.основыИмени, о)) своё += ВЕС_ИМЕНИ;
        if (встречается(с.основыЗаголовков, о)) своё += ВЕС_ЗАГОЛОВКОВ;
        if (встречается(с.основыРаздела, о)) своё += ВЕС_РАЗДЕЛА;
        if (встречается(с.основыТекста, о)) своё += ВЕС_ТЕКСТА;
        if (!своё) { всеНашлись = false; break; }
        вес += своё;
      }
      if (!всеНашлись) continue;
      // Страница того же языка, что открытая, — выше: читающий по-русски ищет
      // по-русски, а английская половина ему второй ответ, не первый.
      if (с.язык === язык) вес += ВЕС_СВОЕГО_ЯЗЫКА;
      if (!с.заметка) вес += ВЕС_СПРАВОЧНИКА;
      ответ.push({ страница: с, вес: вес });
    }
    // Сортировка устойчива (ES2019): при равном весе порядок остаётся тем, что
    // в указателе, а там страницы разделов стоят раньше заметок базы знаний.
    ответ.sort(function (а, б) { return б.вес - а.вес; });
    var из = [];
    for (var k = 0; k < ответ.length && k < сколько; k++) {
      var с2 = ответ[k].страница;
      из.push({
        адрес: с2.адрес, имя: с2.имя, раздел: с2.раздел, язык: с2.язык,
        вес: ответ[k].вес, кусок: кусокВокруг(с2.текст, основы)
      });
    }
    return из;
  }

  /** Кусок текста вокруг первого совпадения — чтобы видеть, за что нашлось. */
  function кусокВокруг(текст, основы) {
    if (!текст) return '';
    var приведённый = привестиПоЗнакам(текст);
    var место = -1;
    for (var i = 0; i < основы.length && место < 0; i++) место = приведённый.indexOf(основы[i]);
    if (место < 0) место = 0;
    var от = Math.max(0, место - 45);
    var до = Math.min(текст.length, место + 105);
    return (от > 0 ? '…' : '') + текст.slice(от, до).trim() + (до < текст.length ? '…' : '');
  }

  var флангПоиск = {
    привести: привести,
    основа: основа,
    основыСтроки: основыСтроки,
    разобратьУказатель: разобратьУказатель,
    искать: искать
  };
  if (typeof window !== 'undefined') window.флангПоиск = флангПоиск;
  else if (typeof globalThis !== 'undefined') globalThis.флангПоиск = флангПоиск;

  /* ── Ниже — только связь с окном. В node этой части нет. ────────────────── */
  if (typeof document === 'undefined') return;

  var короб = document.querySelector('.poisk');
  var поле = короб && короб.querySelector('input');
  if (!короб || !поле) return;

  var вывод = document.createElement('div');
  вывод.className = 'poisk-vyvod';
  вывод.id = 'poisk-vyvod';
  вывод.setAttribute('role', 'listbox');
  вывод.hidden = true;
  короб.appendChild(вывод);
  поле.setAttribute('aria-controls', 'poisk-vyvod');
  поле.setAttribute('aria-expanded', 'false');

  var язык = document.documentElement.lang === 'en' ? 'en' : 'ru';
  var СЛОВА = язык === 'en'
    ? { грузим: 'loading the index…', нет: 'nothing found', беда: 'the index did not load' }
    : { грузим: 'указатель грузится…', нет: 'ничего не нашлось', беда: 'указатель не загрузился' };

  var корень = короб.getAttribute('data-koren') || '';
  var разобранный = null;
  var грузится = false;
  var найдено = [];
  var выбран = -1;

  // Поле открывается только теперь: до этой строки его в разметке не видно.
  короб.hidden = false;

  function грузить(потом, сказатьЧтоГрузится) {
    if (разобранный) { потом(); return; }
    if (сказатьЧтоГрузится) показать('<div class="poisk-pusto">' + СЛОВА.грузим + '</div>');
    if (грузится) return;
    грузится = true;
    var тег = document.createElement('script');
    тег.src = корень + 'poisk-ukazatel.js';
    тег.onload = function () {
      разобранный = флангПоиск.разобратьУказатель(window.ФЛАНГ_УКАЗАТЕЛЬ);
      грузится = false;
      потом();
    };
    тег.onerror = function () {
      грузится = false;
      показать('<div class="poisk-pusto">' + СЛОВА.беда + '</div>');
    };
    document.head.appendChild(тег);
  }

  function экранировать(текст) {
    return String(текст).replace(/[&<>"]/g, function (з) {
      return з === '&' ? '&amp;' : з === '<' ? '&lt;' : з === '>' ? '&gt;' : '&quot;';
    });
  }

  function показать(html) {
    вывод.innerHTML = html;
    вывод.hidden = false;
    поле.setAttribute('aria-expanded', 'true');
  }

  function спрятать() {
    вывод.hidden = true;
    поле.setAttribute('aria-expanded', 'false');
    поле.removeAttribute('aria-activedescendant');
    выбран = -1;
  }

  function перерисовать() {
    if (!найдено.length) {
      показать('<div class="poisk-pusto">' + СЛОВА.нет + '</div>');
      return;
    }
    var части = [];
    for (var i = 0; i < найдено.length; i++) {
      var н = найдено[i];
      части.push(
        '<a class="poisk-otvet' + (i === выбран ? ' vybran' : '') + '" role="option" id="poisk-o' + i +
        '" aria-selected="' + (i === выбран ? 'true' : 'false') +
        '" href="' + экранировать(корень + н.адрес) + '">' +
        '<span class="poisk-imya">' + экранировать(н.имя) + '</span>' +
        '<span class="poisk-razdel">' + экранировать(н.раздел) + '</span>' +
        (н.кусок ? '<span class="poisk-kusok">' + экранировать(н.кусок) + '</span>' : '') +
        '</a>'
      );
    }
    показать(части.join(''));
    if (выбран >= 0) поле.setAttribute('aria-activedescendant', 'poisk-o' + выбран);
  }

  function искатьСейчас() {
    if (!привести(поле.value)) { спрятать(); return; }
    грузить(function () {
      найдено = флангПоиск.искать(разобранный, поле.value, { язык: язык, сколько: 12 });
      выбран = найдено.length ? 0 : -1;
      перерисовать();
    }, true);
  }

  поле.addEventListener('input', искатьСейчас);
  // Касание поля — повод достать указатель заранее, но не повод что-то
  // показывать: пустому запросу отвечать нечем.
  поле.addEventListener('focus', function () { грузить(function () { искатьСейчас(); }, false); });

  поле.addEventListener('keydown', function (е) {
    if (е.key === 'Escape') { спрятать(); поле.blur(); return; }
    if (вывод.hidden || !найдено.length) return;
    if (е.key === 'ArrowDown') { е.preventDefault(); выбран = (выбран + 1) % найдено.length; перерисовать(); }
    else if (е.key === 'ArrowUp') { е.preventDefault(); выбран = (выбран - 1 + найдено.length) % найдено.length; перерисовать(); }
    else if (е.key === 'Enter') {
      е.preventDefault();
      var н = найдено[выбран >= 0 ? выбран : 0];
      if (н) window.location.href = корень + н.адрес;
    }
  });

  // Отправлять форму некуда — сервера нет. Enter разобран выше; здесь только
  // запрет перезагрузки страницы.
  if (короб.tagName === 'FORM') короб.addEventListener('submit', function (е) { е.preventDefault(); });

  document.addEventListener('click', function (е) { if (!короб.contains(е.target)) спрятать(); });

  // «/» ставит курсор в поле. Привычка из читалок кода; печатающему в поле не
  // мешает — там клавиша остаётся знаком.
  document.addEventListener('keydown', function (е) {
    if (е.key !== '/' || е.ctrlKey || е.metaKey || е.altKey) return;
    var где = document.activeElement;
    if (где && (где.tagName === 'INPUT' || где.tagName === 'TEXTAREA' || где.isContentEditable)) return;
    е.preventDefault();
    поле.focus();
    поле.select();
  });
})();
