// Указатель поиска: что сборка кладёт рядом со страницами, чтобы браузер мог
// искать без сервера.
//
// Сайт живёт на GitHub Pages — сервера нет, только статика. Значит, искать
// может либо сервер (которого нет), либо браузер по заранее собранному
// указателю. Указатель собирается ЗДЕСЬ, во время сборки, из тех же страниц,
// что печатаются в HTML: второго списка страниц нет, и разъехаться нечему.
//
// ── Что кладётся в указатель, и почему не весь текст ────────────────────────
// Страниц 244. Полный текст всех — 1.9 МБ; указатель весом в два мегабайта
// грузился бы дольше, чем читается страница, ради которой его открыли.
// Поэтому в записи страницы лежит заголовок, раздел, все подзаголовки и ПЕРВЫЕ
// ЗНАКИ текста — ровно `ПРЕДЕЛ_ТЕКСТА` штук. Числа обеих мер печатает сборка.
//
// Отрезание оправдано укладом дерева, а не только весом: заметка базы знаний
// начинается с утверждения, а страница сайта — с того, о чём она. Слово,
// которого нет ни в заголовках, ни в первом абзаце, почти всегда не про эту
// страницу, а упомянуто по дороге.
//
// ── Формат ──────────────────────────────────────────────────────────────────
// Не JSON, а `.js`, присваивающий глобальную переменную. Причина измеримая:
// `fetch('poisk.json')` из `file://` запрещён браузером, то есть собранный
// сайт, открытый двойным щелчком с диска, искать бы не умел. `<script src>`
// работает и с диска, и с Pages.
//
// Запись страницы — массив, а не объект: имена полей, повторённые 244 раза,
// весят больше самих полей.

import { убратьКомментарии } from './markdown.mjs';

/** Сколько знаков текста страницы попадает в указатель. */
export const ПРЕДЕЛ_ТЕКСТА = 700;

/** Поля записи по порядку — тот же порядок читает `poisk.js`. */
export const ПОЛЯ = ['адрес', 'имя', 'раздел', 'язык', 'заголовки', 'текст', 'заметка'];

/**
 * Markdown → голый текст для поиска.
 *
 * Блоки кода выбрасываются целиком: `flang check` в примере на двадцать строк
 * не делает страницу страницей про проверку, а вес указателя удваивает.
 * Встроенный код, наоборот, остаётся без обратных кавычек — имена вроде
 * `mkdtemp` в тексте пишутся только так, и без них поиск по имени невозможен.
 *
 * ПОДЧЁРКИВАНИЕ ВНУТРИ СЛОВА НЕ ТРОГАЕТСЯ. Оно стояло в одном ряду с `*` и
 * `#` — как украшение строки, — и `FLANG_PROOF_NO_GOAL` ложился в указатель
 * четырьмя словами «FLANG PROOF NO GOAL». Запрос при этом подчёркивание
 * СОХРАНЯЕТ (`poisk.js`, `привестиПоЗнакам` держит `_` нарочно: код отказа —
 * одно имя, а не четыре слова), и совпасть эти две записи не могли никогда:
 * поиск по коду отказа не находил страницу, где этот код разобран, ни разу из
 * тринадцати. Курсив подчёркиванием в этой документации не пишется — эмфаза
 * везде звёздочками, — а имена с подчёркиванием стоят на каждой странице про
 * замечания компилятора и про встраивание (`fl_arena_init`). Поэтому пробелом
 * заменяется только одинокое подчёркивание, у которого сбоку не буква и не
 * цифра.
 */
export function голыйТекст(markdown) {
  return (
    убратьКомментарии(String(markdown).replace(/\r\n/gu, '\n'))
      // Блоки кода и схемы.
      .replace(/^```[\s\S]*?^```$/gmu, ' ')
      // Ссылки: остаётся подпись, адрес выбрасывается.
      .replace(/\[\[([^\]]+)\]\]/gu, '$1')
      .replace(/\[([^\]]*)\]\([^)\s]*\)/gu, '$1')
      // Украшения строки.
      .replace(/[`*>#|]/gu, ' ')
      .replace(/(?<![\p{L}\p{N}])_|_(?![\p{L}\p{N}])/gu, ' ')
      .replace(/^\s*[-+]\s+/gmu, ' ')
      .replace(/^\s*\d+\.\s+/gmu, ' ')
      .replace(/-{3,}/gu, ' ')
      .replace(/\s+/gu, ' ')
      .trim()
  );
}

/** Заголовки второго и третьего уровня — из готового оглавления страницы. */
function заголовкиСтраницы(с) {
  return (с.оглавление ?? [])
    .map((п) => String(п.текст ?? '').replace(/`/gu, '').trim())
    .filter(Boolean)
    .join(' · ');
}

/**
 * Собирает указатель. Возвращает и сам указатель, и меры: полный вес текста
 * против отрезанного — чтобы решение об отрезании называлось числом, а не
 * словом «много».
 */
export function собратьУказатель(страницы, предел = ПРЕДЕЛ_ТЕКСТА) {
  const записи = [];
  let полныйТекст = 0;
  let положенныйТекст = 0;
  for (const с of страницы) {
    const текст = голыйТекст(с.исходник);
    полныйТекст += текст.length;
    const кусок = текст.length > предел ? текст.slice(0, предел) : текст;
    положенныйТекст += кусок.length;
    // Последнее поле — «это заметка базы знаний»: 0 или 1, потому что 244 раза
    // повторённое слово весит больше, чем весь признак стоит.
    записи.push([с.адрес, с.имя, с.раздел, с.язык ?? 'ru', заголовкиСтраницы(с), кусок, с.заметка ? 1 : 0]);
  }
  return {
    указатель: { поля: ПОЛЯ, предел, страницы: записи },
    меры: { страниц: записи.length, полныйТекст, положенныйТекст },
  };
}

/** Файл указателя: одна строка присваивания, читаемая и с диска, и с Pages. */
export function печатьУказателя(указатель) {
  return `window.ФЛАНГ_УКАЗАТЕЛЬ=${JSON.stringify(указатель)};\n`;
}
