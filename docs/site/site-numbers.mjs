/**
 * Числа сайта: один замер, один файл, одно место правды.
 *
 *   node docs/site/site-numbers.mjs           напечатать измеренное
 *   node docs/site/site-numbers.mjs --write    перемерить и записать numbers.json
 *   node docs/site/site-numbers.mjs --check    сверить numbers.json с деревом
 *
 * ── Что здесь изменилось и почему ───────────────────────────────────────────
 * Раньше числа НАБИРАЛИСЬ на каждой странице руками, а этот скрипт собирал из
 * замера фразу и требовал найти её в тексте буква в букву. Сторож был верный, а
 * уклад — нет: одно и то же число стояло на четырёх страницах в четырёх местах,
 * и правка требовала четырёх правок. Цена измерена: 18 августа 2026 главная
 * называла 8018 функций корпуса, роадмап на том же сайте — 8490, а дерево в тот
 * же час считало 8535. Три числа об одном.
 *
 * Теперь число на странице не набирается вовсе. В тексте стоит ПОДСТАНОВКА
 * `{{корпус.функций}}`, а значение приезжает при сборке из `numbers.json`.
 * Убрать число со страницы нельзя молча (`ОБЯЗАТЕЛЬНЫЕ` ниже), написать другое
 * — негде, разойтись двум страницам — не в чем.
 *
 * Сама подстановка живёт в `docs/site/numbers.mjs` — отдельно и нарочно: там
 * нет ни одного тяжёлого ввоза, и сборка сайта берёт числа, не поднимая
 * компилятор. Этот файл, наоборот, поднимает: он МЕРЯЕТ.
 *
 * ── Почему замер лежит в файле, а не считается сборкой ──────────────────────
 * Свод корпуса — это загрузка и анализ всего дерева: 52 секунды на этой машине.
 * Сборка сайта идёт без единой зависимости и обязана работать в клоне без
 * компилятора; вешать на неё минуту анализа значило бы сломать её там, где она
 * нужнее всего. Поэтому замер снимается отдельной командой и кладётся в
 * `numbers.json`, а сборка его только читает.
 *
 * Файл не имеет права протухнуть: `--check` перемеряет дерево заново и краснеет
 * на первом разошедшемся числе. То есть записанное в `numbers.json` — это не
 * «числа на какой-то день», а «числа этого дерева», и другими они быть не
 * могут.
 *
 * ── Чем меряется ────────────────────────────────────────────────────────────
 * Корпус — `flang/scripts/proof-ledger.mjs`, тот же измеритель, что у
 * `count-guard`. Считать корпус на ходу нельзя: ад-хок счёт трижды за сутки
 * соврал, один раз вдвое, потому что связывание импортов приписывало функции
 * модуля каждому импортёру. Цели печати — по каталогу `flang/src/emit/`,
 * близнецы — по `flang/self/emit-*.flang`. Словарь — `покрытие()` из
 * `surfaces-run.mjs`.
 */
