      "словарь.дырявых": с.понятий - с.наЧетырёх,

      // Разговор с базой: один модуль библиотеки и один план рядом с ним.
      "база.строк": база.строк,
      "база.функций": база.функций,
      "база.тотальных": база.тотальных,
