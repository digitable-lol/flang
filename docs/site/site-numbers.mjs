const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))
const прочесть = (путь) => readFileSync(КОРЕНЬ + путь, "utf8")

export { ФОРМАТ, прочитатьЧисла }

/* ── Измерители ──────────────────────────────────────────────────────────── */

/**
 * Цели печати — по каталогу бэкендов, а не по списку в прозе.
 *
 * Считались файлы `flang/src/emit/<цель>.mjs`. Таких файлов больше нет: у
 * каждой цели теперь свой КАТАЛОГ с рантаймом (`flang/src/emit/c/`,
 * `flang/src/emit/js/` и так далее), а печать живёт в `flang/self/emit-*.flang`.
 * Пока измеритель искал `.mjs`, он отдавал ноль целей — и число «восемь» на
 * страницах держалось только тем, что записанное в `numbers.json` никто не
 * перемерял.
 */
export function цели() {
  const все = readdirSync(КОРЕНЬ + "flang/src/emit", { withFileTypes: true })
    .filter((з) => з.isDirectory())
    .map((з) => з.name)
    .sort()
  const близнецы = readdirSync(КОРЕНЬ + "flang/self")
    .filter((ф) => /^emit-.+\.flang$/u.test(ф))
    .map((ф) => ф.replace(/^emit-|\.flang$/gu, ""))
    .sort()
  return { все, близнецы, безБлизнеца: все.filter((ц) => !близнецы.includes(ц)) }
}

/** Строк в тексте — так же, как считает `wc -l`: последний перевод не строка. */
function строкВ(текст) {
  const строки = текст.split("\n")
  if (строки.length > 0 && строки[строки.length - 1] === "") строки.pop()
  return строки.length
}

/** Стандартная библиотека: файлы, строки, объявления функций. */
export function библиотека() {
  let функций = 0
  let строк = 0
  let файлов = 0
  for (const ф of readdirSync(КОРЕНЬ + "flang/stdlib")) {
    // Четыре равноправных расширения программы: `.flang`, `.fp`, `.фп`, `.фланг` (ADR-0016).
    if (!/\.(flang|fp|фп|фланг)$/u.test(ф)) continue
    файлов += 1
    const текст = readFileSync(`${КОРЕНЬ}flang/stdlib/${ф}`, "utf8")
    функций += (текст.match(/^\s*(?:тотальная функция|функция)\s/gmu) ?? []).length
    строк += строкВ(текст)
  }
  return { файлов, строк, функций }
}

/**
 * Корпус на flang: те же файлы, по которым считаны функции.
 *
 * Набор берётся у `proof-ledger`, а не собственным обходом дерева: два набора
 * разъезжаются молча, и тогда «столько-то функций в столько-то файлах» говорит
 * про два разных дерева.
 */
export function корпусФайлами() {
  let строк = 0
  for (const путь of ФАЙЛЫ) строк += строкВ(readFileSync(КОРЕНЬ + путь, "utf8"))
  return { файлов: ФАЙЛЫ.length, строк }
}

/**
 * Один файл языка: строки, объявления функций, примеры.
 *
 * Нужен страницам, которые пишут ПРО ОДИН модуль — про разговор с базой, про
 * планировщик, про связь узлов. Раньше такие числа набирались в тексте руками и
 * ровно так же тухли: строк в файле становится больше на первой же правке.
 */
export function модуль(путь) {
  const текст = прочесть(путь)
  return {
    строк: строкВ(текст),
    функций: (текст.match(/^\s*(?:тотальная функция|функция)\s/gmu) ?? []).length,
    тотальных: (текст.match(/^\s*тотальная функция\s/gmu) ?? []).length,
    примеров: (текст.match(/^\s*пример\s/gmu) ?? []).length,
  }
}

/**
 * Сколько вариантов у одного типа-суммы в файле языка.
 *
 * Считается по тексту объявления: заголовок `тип «Имя»` и всё, что под ним с
 * отступом, — другого признака конца объявления в записи языка нет. Так число
 * «одиннадцать событий» на странице про процессы держится за сам тип, а не за
 * память писавшего.
 */
export function вариантов(путь, имя) {
  const строки = прочесть(путь).split("\n")
  const начало = строки.findIndex((с) => new RegExp(`^тип\\s+«${имя}»\\s*$`, "u").test(с))
  if (начало < 0) throw new Error(`в ${путь} нет типа «${имя}» — числу вариантов неоткуда взяться`)
  let счёт = 0
  for (let и = начало + 1; и < строки.length; и += 1) {
    const с = строки[и]
    if (с.trim() !== "" && !/^\s/u.test(с)) break
    if (/^\s+вариант\s/u.test(с)) счёт += 1
  }
  return счёт
}

/**
 * Сколько разных отказов умеет напечатать ядро доказательств.
 *
 * Страница «Ядро отказало» обещает читателю ПОЛНЫЙ список — а полнота, набранная
 * рукой, живёт до первого нового кода. Считается по самим строкам, которыми
 * компилятор эти коды называет, и по двум файлам, в которых они объявлены и
 * больше нигде: слой обязательств (теорема не сошлась с функцией) и слой вывода
 * (вывод не построен). Появится в компиляторе четырнадцатый — число на странице
 * разойдётся с деревом, и `--check` покраснеет.
 */
export function отказыЯдра() {
  const коды = (путь) =>
    new Set((прочесть(путь).match(/"FLANG_PROOF_[A-Z_]+"/gu) ?? []).map((с) => с.slice(1, -1)))
  const обязательств = коды("flang/self/obligations.flang")
  const вывода = коды("flang/self/proofterm.flang")
  const все = new Set([...обязательств, ...вывода])
  if (все.size !== обязательств.size + вывода.size) {
    throw new Error("один и тот же отказ ядра объявлен в обоих слоях — считать его дважды нельзя")
  }
  return { всего: все.size, обязательств: обязательств.size, вывода: вывода.size }
}

/** Версия выпуска — из `package.json`, а не из памяти. */
export function версияВыпуска() {
  return JSON.parse(прочесть("package.json")).version
}

