      "утверждения.приУсловии": и.claims["proved-conditional"] ?? 0,
      "утверждения.сеткой": и.claims.grid,
      "утверждения.отвергнуто": и.claims.refused ?? 0,
      "законы.наВеру": и.laws.assumed,

      "носители.композиция": и.carriers.composition,
      "носители.структура": и.carriers.structure,
      "носители.точныйШаг": и.carriers.exact,
      "носители.постоянныйШаг": и.carriers.step,
      "носители.мера": и.carriers.measure,
      "сторож.мест": и.guardSites,
      "сторож.функций": и.carriers.step + и.carriers.measure,

      "библиотека.функций": б.функций,
      "библиотека.файлов": б.файлов,
