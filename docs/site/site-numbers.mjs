/**
 * Страницы, на которых число всё ещё НАБРАНО, и собранная фраза его сторожит.
 *
 * Приём прежний: фраза собирается из замера и обязана найтись буква в букву.
 * Список закрыт и должен пустеть: каждая строка отсюда — число, которое ещё не
 * переведено на подстановку. Пустой список — цель, а не мечта.
 */
export function набранныеРуками(числа) {
  return [
    [
      "docs/site/getting-started.ru.md",
      "целей печати списком",
      `Целей ${числа["цели.словом"]}: ${числа["цели.список"]}.`,
    ],
    [
      "docs/site/getting-started.md",
      "targets",
      `There are ${числа["цели.поАнглийски"]} targets: ${числа["цели.список"]}.`,
    ],
  ]
}

const плоско = (текст) => текст.replace(/\s+/gu, " ")

/* ── Сверка ──────────────────────────────────────────────────────────────── */

export async function сверить() {
  const беды = []
  const свежий = await измерить()

  let записанные = null
  try {
    записанные = прочитатьЧисла()
  } catch (беда) {
    беды.push(беда.message)
  }

  if (записанные) {
    const ключи = new Set([...Object.keys(записанные), ...Object.keys(свежий.числа)])
    for (const ключ of [...ключи].sort()) {
      const было = записанные[ключ]
      const стало = свежий.числа[ключ]
      if (было === стало) continue
      беды.push(`${ключ}: в numbers.json ${JSON.stringify(было)}, в дереве ${JSON.stringify(стало)}`)
    }
  }

  const числа = записанные ?? свежий.числа

  // Подстановка на месте? Число, убранное со страницы, иначе не краснеет нигде.
  const кэш = new Map()
  const текст = (файл) => {
    if (!кэш.has(файл)) кэш.set(файл, прочесть(файл))
    return кэш.get(файл)
  }
  for (const [файл, ключ] of ОБЯЗАТЕЛЬНЫЕ) {
    if (!текст(файл).includes(`{{${ключ}}}`)) беды.push(`${файл}: пропала подстановка {{${ключ}}}`)
  }

  // Ещё не переведённое на подстановку сторожится собранной фразой.
  for (const [файл, имя, фраза] of набранныеРуками(числа)) {
    if (!плоско(текст(файл)).includes(плоско(фраза))) беды.push(`${файл} — ${имя}: нет фразы «${фраза}»`)
  }

  // Ни одна страница сайта не вправе называть цели печати семью: их восемь.
  for (const файл of [
    "docs/site/index.md",
    "docs/site/getting-started.md",
    "docs/site/proofs.md",
    "docs/site/roadmap.md",
  ]) {
    const врёт = /emitted\s+(?:in)?to\s+seven\s+(?:language|target)/iu.exec(текст(файл))
    if (врёт) беды.push(`${файл}: «${врёт[0]}» — целей печати ${числа["цели.всего"]}, а не семь`)
  }
  for (const файл of ["docs/site/index.ru.md", "docs/site/getting-started.ru.md", "docs/site/proofs.ru.md"]) {
    const врёт = /печата[а-я]*\s+(?:во?\s+)?сем[ьи]\s+(?:язык|цел)/iu.exec(текст(файл))
    if (врёт) беды.push(`${файл}: «${врёт[0]}» — целей печати ${числа["цели.всего"]}, а не семь`)
  }

  return беды
}

/* ── Запуск ──────────────────────────────────────────────────────────────── */

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const беды = await сверить()
    if (беды.length) {
      console.error("Числа сайта ОТКАЗЫВАЮТ — записанное разошлось с деревом:")
      for (const б of беды) console.error("  · " + б)
      console.error(`\nвсего бед: ${беды.length}. Лечится одной командой: npm run numbers`)
      process.exit(1)
    }
    const числа = прочитатьЧисла()
    console.log(
      `числа сайта: чисто — ${Object.keys(числа).length} чисел numbers.json сошлись с деревом, ` +
        `подстановок на страницах ${ОБЯЗАТЕЛЬНЫЕ.length}, набранных руками ${набранныеРуками(числа).length}.`,
    )
    process.exit(0)
  }

  const замер = await измерить()

  if (process.argv.includes("--write")) {
    writeFileSync(ПУТЬ_ЧИСЕЛ, сериализовать(замер))
    console.log(`Записано docs/site/numbers.json: чисел ${Object.keys(замер.числа).length}.`)
    process.exit(0)
  }

  for (const [ключ, значение] of Object.entries(замер.числа)) {
    console.log(`${ключ.padEnd(26)} ${значение}`)
  }
}
