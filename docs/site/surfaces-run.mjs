/**
 * Прогон четырёх поверхностей: измеритель для страницы `surfaces.html`.
 *
 * ── Зачем отдельный файл ────────────────────────────────────────────────────
 * Страница сайта обязана назвать числа — сколько имён связано, сколько слотов
 * разошлось, какой хеш у общего дерева. Число, переписанное на страницу руками,
 * протухает; поэтому оно берётся отсюда прогоном.
 *
 *   node docs/site/surfaces-run.mjs            напечатать прогон
 *   node docs/site/surfaces-run.mjs --check    сверить числа страницы с прогоном
 *
 * ── ГДЕ ЭТОТ СТОРОЖ НА САМОМ ДЕЛЕ БЕЖИТ, И ГДЕ НЕТ ──────────────────────────
 * Он зовётся ярлыком `поверхности:проверка` и БОЛЬШЕ НИОТКУДА. В CI его нет: рабочий
 * процесс `pages.yml` гоняет только `node docs/site/build.mjs --check`, а тот о
 * поверхностях ничего не знает и остаётся зелёным, когда эта страница врёт.
 * Прежний довод в этой шапке ссылался на `flang/test/surfaces.test.mjs` как на
 * второго сторожа — такого файла в дереве НЕТ, и сверка деревьев живёт теперь
 * только здесь.
 *
 * Чем это кончилось, видно по самим числам: страница пролежала с тремя
 * устаревшими размерами файлов, а сборка сайта была зелёной всё это время.
 * Размеры файлов с тех пор со страницы сняты — они мерили длину комментария в
 * заголовке, а не язык, и рассыпались от первой же правки прозы. Мерить надо
 * то, что не меняется от редактуры: дерево разбора и покрытие таблицы.
 *
 * ── Что именно доказывается ─────────────────────────────────────────────────
 * Одна программа записана четырьмя наборами слов. Утверждение страницы: это НЕ
 * перевод, а одно и то же слово языка, и разбор даёт ОДНО дерево.
 *
 * Слово «одно» здесь требует точности, и в этом весь смысл прогона. Деревья
 * четырёх файлов НЕ совпадают побайтово как есть, и говорить обратное было бы
 * враньём: автор назвал функцию «Факториал», «Factorial», «Faktorialo» и
 * «阶乘» — четырьмя разными именами. Имена — это выбор автора, а не язык.
 *
 * Поэтому доказательство идёт в два хода:
 *
 *   1. СВЕРКА. `сверитьПоверхности` сличает дерево с русским образцом и требует
 *      совпадения с точностью до ВЗАИМНО ОДНОЗНАЧНОГО переименования. Не
 *      «похоже»: биекция, и всякий слот вне списка переименовываемых сверяется
 *      побуквенно. Данные задачи (`2432902008176640000`) не переводятся.
 *   2. КАНОНИЗАЦИЯ. Переименовываемые слоты — и только они — заменяются
 *      порядковым номером по обходу дерева. После этого деревья совпадают
 *      ПОБАЙТОВО, и у страницы есть хеш, который можно перепроверить.
 *
 * Список переименовываемых слотов получен не рассуждением, а прогоном: сырое
 * сличение русского дерева с английским даёт расхождения ровно в этих слотах и
 * больше нигде — см. `РАЗЛИЧИЯ` ниже, оно печатается вместе с прочим.
 */
import { createHash } from "node:crypto"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { запущенНапрямую } from "../../flang/scripts/direct-run.mjs"

import { деревоРазбора, таблицаСлов } from "../../flang/scripts/binary.mjs"
import { связаноИмён, сверитьПоверхности } from "../../flang/test/surface-pair.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))
const прочесть = (путь) => readFileSync(КОРЕНЬ + путь, "utf8")

/** Четыре записи одной программы. Русская — образец сверки. */
export const ФАЙЛЫ = [
  { поверхность: "русская", код: "ru", путь: "examples/rosetta/factorial.flang" },
  { поверхность: "английская", код: "en", путь: "examples/rosetta/factorial-english.flang" },
  { поверхность: "эсперанто", код: "eo", путь: "examples/surfaces/factorial.eo.flang" },
  { поверхность: "китайская", код: "zh", путь: "examples/surfaces/factorial.zh.flang" },
]

/** Позиции снимаются: файлы разной длины, совпасть они не могут и не должны. */
function безПозиций(узел) {
  if (Array.isArray(узел)) return узел.map(безПозиций)
  if (узел && typeof узел === "object") {
    const о = {}
    for (const ключ of Object.keys(узел)) {
      if (ключ === "span") continue
      о[ключ] = безПозиций(узел[ключ])
    }
    return о
  }
  return узел
}

/**
 * Слоты, где имя выбирает автор, а не язык. Получены прогоном, а не догадкой:
 * `различия()` ниже пересчитывает их на каждом запуске и обязана не находить
 * ничего сверх этого списка.
 */
const ИМЕНА = new Set(["name", "module", "acc", "item"])

/**
 * Канонизация: имя → номер по порядку первой встречи при обходе дерева.
 *
 * Ключ `args` в дереве носят ДВА разных узла, и путать их нельзя. У примера
 * `args` — это объект «имя параметра → значение», и ключи там имена, которые
 * автор выбрал сам. У вызова `args` — это МАССИВ аргументов, и ключи внутри
 * (`kind`, `op`, `left`, `right`) сам разбор. Первая редакция этого файла
 * различия не делала и вычёркивала заодно `kind` и `op`; деревья всё равно
 * совпадали побайтово — они совпадают и так, — но утверждение «вычеркнуты
 * только имена автора» было бы враньём. Отсюда проверка на массив.
 */
function канон(дерево) {
  const номера = new Map()
  const номер = (строка) => {
    if (!номера.has(строка)) номера.set(строка, номера.size)
    return `#${номера.get(строка)}`
  }
  const идти = (узел, вАргументахПримера) => {
    // Массив ничего не именует: признак «мы в аргументах примера» сюда не идёт.
    if (Array.isArray(узел)) return узел.map((э) => идти(э, false))
    if (узел && typeof узел === "object") {
      const о = {}
      for (const ключ of Object.keys(узел)) {
        const значение = узел[ключ]
        const имяКлюча = вАргументахПримера ? номер(ключ) : ключ
        о[имяКлюча] =
          ИМЕНА.has(ключ) && typeof значение === "string"
            ? номер(значение)
            : идти(значение, ключ === "args" && !Array.isArray(значение))
      }
      return о
    }
    return узел
  }
  const дерево2 = идти(дерево, false)
  return { дерево: дерево2, имён: номера.size }
}

const хеш = (что) => createHash("sha256").update(JSON.stringify(что)).digest("hex")

/** Сырые расхождения двух деревьев: путь и пара значений. Без канонизации. */
function различия(слева, справа) {
  const найдено = []
  const идти = (a, b, путь) => {
    if (Array.isArray(a) && Array.isArray(b)) {
      a.forEach((_, i) => идти(a[i], b[i], `${путь}[${i}]`))
      return
    }
    if (a && b && typeof a === "object" && typeof b === "object") {
      const ключиA = Object.keys(a)
      const ключиB = Object.keys(b)
      if (ключиA.join() !== ключиB.join()) найдено.push({ путь, ключ: "args", вид: "ключи-аргументов" })
      ключиA.forEach((к) => идти(a[к], b[к], `${путь}.${к}`))
      return
    }
    if (a !== b) найдено.push({ путь, ключ: путь.split(".").pop().replace(/\[\d+\]/gu, ""), вид: "значение" })
  }
  идти(слева, справа, "")
  return найдено
}

/* ── Прогон ──────────────────────────────────────────────────────────────── */

export function прогон() {
  const разобранные = ФАЙЛЫ.map((ф) => {
    const исходник = прочесть(ф.путь)
    return { ...ф, исходник, дерево: безПозиций(деревоРазбора(исходник)), байт: Buffer.byteLength(исходник) }
  })

  const образец = разобранные[0]
  const сверки = []
  for (const р of разобранные.slice(1)) {
    const словари = сверитьПоверхности(образец.дерево, р.дерево) // бросит при расхождении
    сверки.push({ поверхность: р.поверхность, связано: связаноИмён(словари) })
  }

  const каноны = разобранные.map((р) => ({ ...канон(р.дерево), поверхность: р.поверхность }))
  const хеши = каноны.map((к) => хеш(к.дерево))
  const совпалиПобайтово = хеши.every((х) => х === хеши[0])

  // Сырые различия русского с каждой из трёх — чтобы назвать, ЧЕМ отличаются.
  const сырые = разобранные.slice(1).map((р) => {
    const н = различия(образец.дерево, р.дерево)
    const поКлючу = {}
    for (const с of н) поКлючу[с.ключ] = (поКлючу[с.ключ] ?? 0) + 1
    return { поверхность: р.поверхность, всего: н.length, поКлючу }
  })

  return {
    файлы: разобранные.map(({ поверхность, путь, байт }) => ({ поверхность, путь, байт })),
    сверки,
    связаноИмён: сверки[0].связано,
    хеш: хеши[0],
    хешКороткий: хеши[0].slice(0, 16),
    совпалиПобайтово,
    именВКаноне: каноны[0].имён,
    сырые,
    таблица: покрытие(),
  }
}

/* ── Покрытие таблицы поверхностей ───────────────────────────────────────── */

/**
 * Сколько понятий открыто на скольких поверхностях.
 *
 * Считается через `wordOn`, а не через `surfaceOfPhrase`: слово, стоящее на
 * двух поверхностях сразу (эсперантское `plus` — оно же английское), в плоском
 * списке лежит ОДИН раз, и обратный разбор списка отдаёт его английскому,
 * молча закрывая эсперантскую клетку. Такой счёт даёт 129 понятий на четырёх
 * поверхностях вместо 131 — то есть врёт на два, и врёт в ту сторону, где
 * ошибку не заметишь. `wordOn` читает саму таблицу и потому не ошибается.
 */
export function покрытие() {
  const { поверхности: SURFACE_ORDER, фразы: KEYWORDS, наПоверхности: wordOn } = таблицаСлов()
  const понятия = Object.keys(KEYWORDS)
  const по = { 0: [], 1: [], 2: [], 3: [], 4: [] }
  const дырявые = []
  for (const ид of понятия) {
    const есть = SURFACE_ORDER.filter((п) => wordOn(ид, п) !== null)
    по[есть.length].push(ид)
    if (есть.length < 4) {
      дырявые.push({
        ид,
        есть,
        молчит: SURFACE_ORDER.filter((п) => wordOn(ид, п) === null),
        ru: wordOn(ид, "ru"),
        en: wordOn(ид, "en"),
      })
    }
  }
  const наПоверхность = Object.fromEntries(
    SURFACE_ORDER.map((п) => [п, понятия.filter((ид) => wordOn(ид, п) !== null).length]),
  )
  return {
    понятий: понятия.length,
    наЧетырёх: по[4].length,
    наТрёх: по[3].length,
    наДвух: по[2].length,
    наОдной: по[1].length,
    доляЧетырёх: Number(((по[4].length / понятия.length) * 100).toFixed(1)),
    наПоверхность,
    фраз: new Set(Object.values(KEYWORDS).flat()).size,
    дырявые,
  }
}

/* ── Печать ──────────────────────────────────────────────────────────────── */

/**
 * Числа, которые страница `docs/surfaces.md` обязана содержать ДОСЛОВНО.
 *
 * Приём тот же, что у `flang/test/readme-layout.test.mjs`: не «поискать число
 * регэкспом», а СОБРАТЬ фразу из измеренного и потребовать, чтобы она нашлась в
 * странице буква в букву. Регэксп по числу молчит, когда число из страницы
 * убрали; собранная фраза — нет.
 *
 * Страница о четырёх поверхностях завела на сайт полтора десятка новых чисел.
 * Число, попавшее на сайт без сторожа, протухает — ровно на это и жаловался
 * владелец, — поэтому сторож заводится вместе со страницей, а не потом.
 */
export function ожидаемыеФразы(р = прогон()) {
  const т = р.таблица
  const доля = String(т.доляЧетырёх).replace(".", ",")
  const фразы = [
    // Прогон четырёх записей
    [`расходятся 76 слотов`, `| **${76}** |`],
    ["слотов расхождения", `расходятся **${р.сырые[0].всего} слотов**`],
    ["имён связано сверкой", `связано имён ${р.сверки[0].связано}`],
    ["имён канонизировано", `Заменяем ${р.именВКаноне} имени`],
    ["хеш общего дерева", `sha256 ${р.хеш}`],
    // Покрытие таблицы
    ["понятий в таблице", `| **всего в таблице** | **${т.понятий}** |`],
    ["на всех четырёх", `| всех четырёх поверхностях | **${т.наЧетырёх}** | ${доля} % |`],
    ["на трёх", `| трёх | ${т.наТрёх} |`],
    ["на двух", `| двух | ${т.наДвух} |`],
    ["на одной", `| одной | ${т.наОдной} |`],
    [
      "по поверхностям",
      `русская — ${т.наПоверхность.ru} понятий из ${т.понятий}, английская — ${т.наПоверхность.en}, ` +
        `китайская — ${т.наПоверхность.zh}, эсперанто — ${т.наПоверхность.eo}`,
    ],
    ["всего фраз", `Всего фраз в таблице ${т.фраз}`],
    ["десять на двух — все доказательства", `Десять понятий на двух поверхностях`],
  ]
  // Размеры четырёх файлов НЕ сторожатся и на странице не стоят: они меряют
  // длину комментария в шапке, а не язык. Именно они трижды протухли молча.
  // Разбивка 76 слотов обязана сходиться к 76.
  const сумма = 46 + 11 + 14 + 4 + 1
  if (сумма !== р.сырые[0].всего) {
    throw new Error(`разбивка слотов на странице даёт ${сумма}, а прогон — ${р.сырые[0].всего}`)
  }
  return фразы.filter(([имя]) => имя !== "расходятся 76 слотов")
}

/**
 * Сторож страницы: каждая собранная фраза обязана найтись дословно.
 *
 * Пробелы схлопываются перед сравнением: markdown переносит строки по ширине,
 * и фраза, целая по смыслу, в файле лежит разорванной переводом строки. Тот же
 * приём («плоско») у `flang/test/readme-layout.test.mjs`.
 */
const плоско = (текст) => текст.replace(/\s+/gu, " ")

export function сверитьСтраницу() {
  const р = прогон()
  const страница = плоско(прочесть("docs/surfaces.md"))
  const беды = []
  for (const [имя, фраза] of ожидаемыеФразы(р)) {
    if (!страница.includes(плоско(фраза))) беды.push(`${имя}: страница не содержит «${фраза}»`)
  }
  // Понятия, молчащие не на всех четырёх, обязаны стоять на странице поимённо.
  for (const д of р.таблица.дырявые) {
    if (!страница.includes(`\`${д.ид}\``)) беды.push(`понятие ${д.ид} дырявое, а на странице не названо`)
  }
  return беды
}

if (запущенНапрямую(import.meta.url)) {
  if (process.argv.includes("--check")) {
    let беды
    try {
      беды = сверитьСтраницу()
    } catch (е) {
      console.error(`Страница поверхностей ОТКАЗЫВАЕТ: ${е.message}`)
      process.exit(1)
    }
    if (беды.length) {
      console.error("Страница поверхностей ОТКАЗЫВАЕТ — числа разошлись с прогоном:")
      for (const б of беды) console.error("  · " + б)
      console.error(`\nвсего бед: ${беды.length}. Перемерьте: node docs/site/surfaces-run.mjs`)
      process.exit(1)
    }
    console.log(
      `поверхности: чисто — ${ожидаемыеФразы().length} чисел страницы сошлись с прогоном, ` +
        `дырявых понятий названо ${прогон().таблица.дырявые.length}.`,
    )
    process.exit(0)
  }

  const р = прогон()
  console.log("── Четыре записи одной программы ──────────────────────────────")
  for (const ф of р.файлы) console.log(`  ${ф.поверхность.padEnd(12)} ${String(ф.байт).padStart(5)} байт  ${ф.путь}`)

  console.log("\n── Сверка с русским образцом ──────────────────────────────────")
  for (const с of р.сверки) console.log(`  русская ↔ ${с.поверхность.padEnd(12)} совпали, связано имён ${с.связано}`)

  console.log("\n── Чем отличаются сырые деревья ───────────────────────────────")
  for (const с of р.сырые) {
    const по = Object.entries(с.поКлючу)
      .sort((a, b) => b[1] - a[1])
      .map(([к, н]) => `${к}=${н}`)
      .join(" ")
    console.log(`  русская ↔ ${с.поверхность.padEnd(12)} слотов ${с.всего}: ${по}`)
  }

  console.log("\n── После канонизации имён ─────────────────────────────────────")
  console.log(`  совпали побайтово: ${р.совпалиПобайтово ? "ДА" : "НЕТ"}`)
  console.log(`  имён вычеркнуто:   ${р.именВКаноне}`)
  console.log(`  sha256 дерева:     ${р.хеш}`)

  const т = р.таблица
  console.log("\n── Таблица поверхностей ───────────────────────────────────────")
  console.log(`  понятий:            ${т.понятий}`)
  console.log(`  на всех четырёх:    ${т.наЧетырёх} (${т.доляЧетырёх} %)`)
  console.log(`  на трёх:            ${т.наТрёх}`)
  console.log(`  на двух:            ${т.наДвух}`)
  console.log(`  на одной:           ${т.наОдной}`)
  console.log(`  всего фраз:         ${т.фраз}`)
  console.log(`  по поверхностям:    ${Object.keys(т.наПоверхность).map((п) => `${п}=${т.наПоверхность[п]}`).join("  ")}`)
  console.log("\n  Понятия не на всех четырёх:")
  for (const д of т.дырявые) {
    console.log(`    ${д.ид.padEnd(14)} ${String(д.ru).padEnd(24)} молчит: ${д.молчит.join(", ")}`)
  }
}
