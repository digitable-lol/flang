"""Разрез доли доказанного по ПЕРВОМУ СЛОВУ ТЕЛА функции и по форме цели.

Вход: каталог с `flang ast <файл>` (JSON) и каталог с `flang check <файл> --proof`.
Имя обоих — путь файла с `/`, заменённым на `_`.

Счёт файла берётся ТОЛЬКО по его собственным функциям (тот же приём, что у
`flang/scripts/per-file-proof-share.py`): ведомость печатает и ввезённые.
Файл идёт в сумму, ТОЛЬКО если счёт приговоров о своих функциях сошёлся с числом
обязательств, написанных в его исходнике; иначе он выводится отдельно, с причиной.
"""
import collections, glob, json, os, re, sys

СТРОКА = re.compile(r'^  (постусловие|предусловие|закон|утверждение)\s+«(.*)»\s+функции\s+«([^»]*)»\s+—\s+(.*)$')
НАЧАЛО = 'что высказано и чем это несётся:'
ОБЯЗАТЕЛЬСТВО = re.compile(r'^\s+(обеспечивает|требует|закон)\b')


# `flang ast` печатает дерево ВМЕСТЕ с ввезёнными файлами: у `crl.flang`
# 32 объявленные функции и 150 в дереве. Своей файл считает только ту, чьё
# объявление стоит в нём самом, — имя И НОМЕР СТРОКИ, а не одно имя: имена по
# ввозу совпадают, а пара «имя + строка» — нет.
ОБЪЯВЛЕНА = re.compile(r'^(?:тотальная\s+)?функция\s+«([^»]+)»')


def свои_объявления(путь):
    свои = set()
    with open(путь, encoding='utf-8', errors='replace') as ф:
        for н, с in enumerate(ф, 1):
            m = ОБЪЯВЛЕНА.match(с)
            if m: свои.add((m.group(1), н))
    return свои

СВЯЗЫВАТЕЛИ = {'let', 'fold', 'map', 'filter', 'match'}
СЛОВО = {'let': 'пусть', 'fold': 'свёртка', 'map': 'отобразить', 'filter': 'отфильтровать',
         'match': 'разбор', 'if': 'если', 'call': 'вызов', 'binary': 'арифметика',
         'builtin': 'встроенная', 'record': 'запись', 'construct': 'построение',
         'list': 'список', 'literal': 'литерал', 'var': 'имя', 'field': 'поле',
         'apply': 'применение', 'string': 'строка'}


def слово(вид):
    return СЛОВО.get(вид, вид or '—')


def вердикт(хвост):
    if хвост.startswith('доказано ПРИ УСЛОВИИ'): return 'при условии'
    if хвост.startswith('доказано'): return 'доказано'
    if хвост.startswith('сетка'): return 'сетка'
    if хвост.startswith('на веру'): return 'на веру'
    return 'объявлено'


def читать_ведомость(путь):
    строки, внутри = [], False
    with open(путь, encoding='utf-8', errors='replace') as ф:
        for с in ф:
            с = с.rstrip('\n')
            if с.startswith(НАЧАЛО): внутри = True; continue
            if внутри and с and not с.startswith('  '): внутри = False
            if not (внутри and с.startswith('  ')): continue
            m = СТРОКА.match(с)
            строки.append((m.group(1), m.group(2), m.group(3), вердикт(m.group(4)))
                          if m else ('?', с.strip(), None, вердикт(с.strip())))
    return строки


def обязательств_в_исходнике(путь):
    n = 0
    with open(путь, encoding='utf-8', errors='replace') as ф:
        for с in ф:
            if с.lstrip().startswith('//'): continue
            if ОБЯЗАТЕЛЬСТВО.match(с): n += 1
    return n


def собрать(корень, ка, кв, образцы):
    тело = collections.Counter()      # (вид тела, вердикт)
    цель_под = collections.Counter()  # (вид тела, вид цели, вердикт)
    всего_тел = collections.Counter()
    сошлось, расх, строки = [], [], []
    пути = []
    for о in образцы:
        пути += glob.glob(os.path.join(корень, о))
    for путь in sorted(set(пути)):
        отн = os.path.relpath(путь, корень)
        k = отн.replace('/', '_')
        фа = os.path.join(ка, k + '.json')
        фв = os.path.join(кв, k + '.out')
        написано = обязательств_в_исходнике(путь)
        if написано == 0: continue
        if not (os.path.exists(фа) and os.path.getsize(фа)):
            расх.append((отн, написано, None, 'дерева нет')); continue
        if not (os.path.exists(фв) and os.path.getsize(фв)):
            расх.append((отн, написано, None, 'ведомости нет')); continue
        d = json.load(open(фа, encoding='utf-8'))
        объявлены = свои_объявления(путь)
        вид_тела, вид_цели = {}, {}
        for f in d.get('functions', []):
            if (f['name'], (f.get('span') or {}).get('line')) not in объявлены: continue
            вид_тела[f['name']] = (f.get('body') or {}).get('kind', '—')
            for pc in f.get('postconditions', []):
                вид_цели[(f['name'], pc.get('name'))] = (pc.get('expr') or {}).get('kind', '—')
        свои = set(вид_тела)
        своё = [(в, имя, ф, вер) for в, имя, ф, вер in читать_ведомость(фв) if ф in свои]
        if len(своё) != написано:
            расх.append((отн, написано, len(своё), 'счёты не сошлись')); continue
        сошлось.append(отн)
        for в, имя, ф, вер in своё:
            т = вид_тела[ф]
            ц = вид_цели.get((ф, имя), '—')
            тело[(т, вер)] += 1
            всего_тел[т] += 1
            цель_под[(т, ц, вер)] += 1
            строки.append((отн, ф, т, ц, вер))
    return тело, всего_тел, цель_под, сошлось, расх, строки


def печать(тело, всего_тел, цель_под, сошлось, расх, строки, образцы):
    сумма = sum(всего_тел.values())
    дказ = sum(тело[(т, 'доказано')] for т in всего_тел)
    print('область:', ' '.join(образцы))
    print(f'файлов учтено (оба счёта сошлись): {len(сошлось)}; не учтено: {len(расх)}')
    if not сумма:
        print('учтённых обязательств нет'); return
    print(f'обязательств учтено: {сумма}; ДОКАЗАНО {дказ} = {100*дказ/сумма:.1f} %; '
          f'НЕДОКАЗАНО {сумма-дказ}')
    print()
    print(f'{"первое слово тела":18s} {"всего":>6s} {"дказ":>6s} {"доля":>7s} {"сетка":>6s} {"объявл":>7s} {"НЕДОКАЗ":>8s}')
    for т, н in всего_тел.most_common():
        d = тело[(т, 'доказано')]
        мет = ' ⟵ связыватель' if т in СВЯЗЫВАТЕЛИ else ''
        print(f'{слово(т):18s} {н:6d} {d:6d} {100*d/н:6.1f}% {тело[(т,"сетка")]:6d} '
              f'{тело[(т,"объявлено")]:7d} {н-d:8d}{мет}')
    св = sum(н for т, н in всего_тел.items() if т in СВЯЗЫВАТЕЛИ)
    свд = sum(тело[(т, 'доказано')] for т in всего_тел if т in СВЯЗЫВАТЕЛИ)
    print(f'{"ВСЕ СВЯЗЫВАТЕЛИ":18s} {св:6d} {свд:6d} {100*свд/св if св else 0:6.1f}% '
          f'{sum(тело[(т,"сетка")] for т in всего_тел if т in СВЯЗЫВАТЕЛИ):6d} '
          f'{sum(тело[(т,"объявлено")] for т in всего_тел if т in СВЯЗЫВАТЕЛИ):7d} {св-свд:8d}')
    print(f'{"ИТОГО":18s} {сумма:6d} {дказ:6d} {100*дказ/сумма:6.1f}% '
          f'{sum(тело[(т,"сетка")] for т in всего_тел):6d} '
          f'{sum(тело[(т,"объявлено")] for т in всего_тел):7d} {сумма-дказ:8d}')
    print()
    print('НЕДОКАЗАННЫЕ ПОД СВЯЗЫВАТЕЛЕМ, по форме цели:')
    формы = collections.Counter()
    for (т, ц, вер), н in цель_под.items():
        if т in СВЯЗЫВАТЕЛИ and вер != 'доказано':
            формы[(слово(т), ц)] += н
    for (т, ц), н in формы.most_common(20):
        print(f'  {т:14s} цель {ц:10s} {н:5d}')
    условных = sum(н for (т, ц), н in формы.items() if ц == 'if')
    print(f'  из них цель условная («если … иначе да»): {условных}')
    if расх:
        print(f'\nНЕ УЧТЕНО, {len(расх)} файлов:')
        for п, надо, вышло, поч in расх:
            print(f'  {надо:5d} обязательств  {поч:18s} {п}'
                  + (f' (приговоров {вышло})' if вышло is not None else ''))


if __name__ == '__main__':
    корень, ка, кв = sys.argv[1], sys.argv[2], sys.argv[3]
    образцы = sys.argv[4:] or ['flang/stdlib/*.flang']
    т, вт, цп, с, р, стр = собрать(корень, ка, кв, образцы)
    печать(т, вт, цп, с, р, стр, образцы)
    with open(os.path.join(os.path.dirname(ка) or '.', 'razrez.tsv'), 'w', encoding='utf-8') as ф:
        ф.write('файл\tфункция\tвид тела\tвид цели\tвердикт\n')
        for r in стр: ф.write('\t'.join(r) + '\n')
