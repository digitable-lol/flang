/**
 * Мост к flang: загрузить входной модуль библиотеки проекта и звать его
 * функции.
 *
 * Это всё, что хозяину положено знать о языке. Он не разбирает исходники, не
 * ходит по AST и не знает про isbn.flang, query.flang и catalog.flang: у
 * библиотеки один вход — lib/api.flang, — и связывание `использует … из "…"`
 * подтягивает остальное само.
 *
 * Загрузка идёт один раз при старте, а не на каждый запрос. Причина не в
 * скорости: программа, разобранная заново на каждом запросе, могла бы стать
 * разной в пределах одного процесса — файл на диске меняют, а первые запросы
 * уже ответили по старому. Одна загрузка на процесс делает поведение
 * воспроизводимым.
 */
import { fileURLToPath } from "node:url"
import { loadProgram } from "../../../flang/bin/flang.mjs"
import { evaluateFlang, runExamples } from "../../../flang/src/compat.mjs"

/* Путь, а не URL: `loadProgram` смотрит на расширение и разрешает относительные
   `использует … из "…"` через node:path, которому нужен именно путь. */
const ВХОД = fileURLToPath(new URL("../lib/api.flang", import.meta.url))

/**
 * Загруженная библиотека: `звать(имя, аргументы)` и ничего больше.
 *
 * Примеры прогоняются прямо здесь, при старте. Это не дублирование `npm test`,
 * а отказ поднимать сервер на библиотеке, которая не сходится со своими же
 * примерами: упасть на старте дешевле, чем отдавать неверные ответы.
 */
export async function загрузитьБиблиотеку(файл = ВХОД) {
  const программа = await loadProgram(файл)
  const примеры = runExamples(программа)
  if (!примеры.valid) {
    const плохие = примеры.results.filter((итог) => !итог.passed)
    throw new Error(
      `примеры flang не сошлись (${плохие.length} из ${примеры.total}): ` +
        плохие.map((итог) => `${итог.function} / ${итог.example}`).join(", "),
    )
  }
  return {
    файл,
    функции: (программа.functions ?? []).map((функция) => функция.name),
    примеров: примеры.total,
    звать: (имя, аргументы) => evaluateFlang(программа, имя, аргументы),
  }
}
