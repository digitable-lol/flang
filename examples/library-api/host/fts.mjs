/**
 * Мост к FTS: посчитать утилиту и получить сертификат на команду.
 *
 * Две модели — два разных вопроса, и обе спрашиваются здесь:
 *
 *   • «сколько» — `executeUtility` по domain/late-fee.fts. Утилита чистая и
 *     детерминированная, поэтому хозяину достаточно передать поля объекта;
 *   • «можно ли» — `certify` + `assertVerified` по domain/loan-permission.fts.
 *     Ответ — не признак, а сертификат: предпосылки, путь по морфизмам, вывод
 *     и отпечаток. Отказ тоже осмысленный: «witness does not match context»
 *     называет то поле снимка, из-за которого вывод не строится.
 *
 * Примеры модели прогоняются при загрузке — по той же причине, что и примеры
 * flang в host/flang.mjs: сервер, поднявшийся на модели, которая не сходится
 * со своими примерами, врёт вежливо и незаметно.
 */
import { readFile } from "node:fs/promises"
import { assertValid, assertVerified, certify, compile, executeUtility, testUtilities } from "../../../dist/src/index.js"

const ШТРАФЫ = new URL("../domain/late-fee.fts", import.meta.url)
const ВЫДАЧА = new URL("../domain/loan-permission.fts", import.meta.url)

/**
 * Куда класть запись, чтобы теорема её нашла, — спрашивается у самой теоремы.
 *
 * Соблазн написать здесь `{ выдачи: [{ ...запись, этап: "рассмотрение" }] }`
 * велик и обходится дорого: раздел контекста и значение селектора оказались бы
 * записаны и в модели, и в хозяине, а расходятся такие пары всегда. Между тем
 * скомпилированный документ несёт готовый путь к свидетельству —
 * `["выдачи", {"этап": "рассмотрение"}, "читатель допущен"]`, — и из него
 * читается и раздел, и селектор.
 *
 * Теорема может быть композицией морфизмов, поэтому до свидетельства
 * спускаемся по `arg`: у `apply` и `compose` оно лежит внутри.
 */
function путьТеоремы(документ) {
  let утверждение = документ.proposition
  while (утверждение !== null && утверждение.kind !== "witness") утверждение = утверждение.arg
  if (утверждение === null) throw new Error("в модели нет теоремы")
  const путь = утверждение.path ?? []
  const раздел = путь.find((шаг) => typeof шаг === "string")
  const селектор = путь.find((шаг) => типЗаписи(шаг))
  if (раздел === undefined) throw new Error("теорема не называет раздел данных")
  return { раздел, селектор: селектор ?? {} }
}

const типЗаписи = (значение) => typeof значение === "object" && значение !== null && !Array.isArray(значение)

async function загрузитьМодель(файл) {
  const документ = assertValid(compile(await readFile(файл, "utf8")))
  /* Примеры есть только у утилит: в модели с морфизмами и теоремой их нет, и
     `testUtilities` на ней отказывает кодом FTS_NO_UTILITIES. Проверку такой
     модели делает сам `compile` — теорема, чей вывод не совпал с объявленным,
     до этой строки не доживает. */
  if ((документ.utilities ?? []).length > 0) {
    const примеры = testUtilities(документ)
    if (!примеры.valid) throw new Error(`примеры модели ${файл.pathname} не сошлись`)
  }
  return документ
}

export async function загрузитьПредметнуюОбласть() {
  const штрафы = await загрузитьМодель(ШТРАФЫ)
  const выдача = await загрузитьМодель(ВЫДАЧА)
  const { раздел, селектор } = путьТеоремы(выдача)

  return {
    /** Штраф за просрочку — ровно то, что написано в domain/late-fee.fts. */
    штраф: (просроченнаяВыдача) => executeUtility(штрафы, "Рассчитать штраф", просроченнаяВыдача),

    /**
     * Разрешена ли выдача. Снимок данных строится здесь, а решение — нет.
     *
     * Хозяин делает ровно одно: кладёт входящую заявку в тот раздел снимка и
     * под тем селектором, которые назвала сама теорема. Селектор ставит сервер,
     * а не клиент: иначе клиент, приславший чужой этап, менял бы то, о чём
     * вообще спрашивают.
     */
    разрешитьВыдачу(запись) {
      const контекст = { [раздел]: [{ ...запись, ...селектор }] }
      try {
        const сертификат = certify(выдача, контекст)
        const проверка = assertVerified(выдача, сертификат, контекст)
        return {
          разрешено: проверка.valid && проверка.status === "verified",
          команда: сертификат.conclusion.type,
          вывод: сертификат.conclusion.term,
          предпосылки: сертификат.assumptions,
          отпечаток: сертификат.certificate_digest,
        }
      } catch (ошибка) {
        return { разрешено: false, причина: ошибка instanceof Error ? ошибка.message : String(ошибка) }
      }
    },
  }
}
