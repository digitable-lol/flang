/**
 * HTTP-хозяин библиотеки.
 *
 * Что здесь есть и почему именно здесь: сокет, маршруты, коды ответов,
 * percent-декодирование, чтение тела запроса, хранилище. Ничего из этого в
 * flang не выражается, и это не временное состояние: язык сознательно
 * остановлен там, где начинается внешний мир.
 *
 * У языка с 7 августа 2026 эффекты есть — описанием, которое исполняет хозяин
 * (`flang/cat/SPEC.md`, «Эффекты и HTTP»). Здесь это ничего не меняет, и
 * причина в направлении: набор поручений закрыт и описывает ИСХОДЯЩИЕ действия
 * («прочитать файл», «сходить по адресу»). Сервер — обратное: ожидание
 * входящих. Поручения «слушать порт» в наборе нет и не будет — исполнить его
 * обязан был бы каждый из восьми хозяев, включая напечатанного в C.
 *
 * Что здесь СОЗНАТЕЛЬНО отсутствует, хотя написать это на JavaScript было бы
 * на пять строк короче:
 *
 *   • разбор строки запроса — lib/query.flang;
 *   • отбор книг, сводка, карточки — lib/catalog.flang и lib/api.flang;
 *   • проверка ISBN — lib/isbn.flang;
 *   • сумма штрафа — lib/fine.flang;
 *   • право выдать книгу — lib/loan.flang.
 *
 * Правило, по которому проведена граница: если у куска логики может быть
 * пример, кусок уезжает в модель или в модуль языка, где пример выполняется
 * набором. На хозяине остаётся то, у чего примера быть не может, — работа с
 * внешним миром.
 *
 * Маршруты:
 *   GET  /health
 *   GET  /books?author=Стругацкие&shelf=yes
 *   GET  /books/summary
 *   POST /books           {"код","автор","название","год"}
 *   POST /loans           {"номер","читатель","книга","долгов нет","читатель допущен"}
 *   POST /returns         {"книга","дней просрочки","книга редкая"}
 */
import { createServer } from "node:http"
import { pathToFileURL } from "node:url"
import { загрузитьБиблиотеку } from "./flang.mjs"
import { создатьХранилище } from "./storage.mjs"

export async function создатьСервер({ хранилище = создатьХранилище() } = {}) {
  const библиотека = await загрузитьБиблиотеку()

  const маршруты = {
    "GET /health": () => ответ(200, { ok: true, функций: библиотека.функции.length, примеров: библиотека.примеров }),

    /* Строку запроса режет flang, а percent-декодирование делает хозяин:
       decodeURIComponent — примитив платформы, уже написанный правильно, и
       переписывать таблицу кодовых точек на flang значило бы завести второй
       источник истины ради принципа. Порядок важен: сначала разрезать по «&»
       и «=», потом декодировать куски, иначе «%26» внутри значения разорвал бы
       параметр надвое. */
    "GET /books": (запрос) => {
      const параметры = библиотека
        .звать("Разобрать запрос", { запрос: строкаЗапроса(запрос.url) })
        .map((параметр) => ({ имя: раскодировать(параметр.имя), значение: раскодировать(параметр.значение) }))
      const книги = библиотека.звать("Отобрать", { книги: хранилище.книги(), параметры })
      return ответ(200, { книги, карточки: библиотека.звать("Карточки", { книги }) })
    },

    "GET /books/summary": () => ответ(200, библиотека.звать("Сводка каталога", { книги: хранилище.книги() })),

    "POST /books": (_запрос, тело) => {
      const код = String(тело["код"] ?? "")
      /* Что такое годный ISBN, решает lib/isbn.flang, а не эта строка. */
      if (!библиотека.звать("Заявка принята", { код })) {
        return ответ(422, { ошибка: "ISBN не проходит проверку контрольной цифры", код })
      }
      const книга = {
        код: библиотека.звать("Ключ книги", { код }),
        автор: String(тело["автор"] ?? ""),
        название: String(тело["название"] ?? ""),
        год: Number(тело["год"] ?? 0),
        "на полке": true,
      }
      const итог = хранилище.добавитьКнигу(книга)
      if (!итог.добавлена) return ответ(409, { ошибка: итог.причина, код: книга.код })
      return ответ(201, { книга: итог.книга, карточка: библиотека.звать("Карточка", { книга: итог.книга }) })
    },

    /* Право выдать книгу решает язык, а не условие в этой функции: см.
       lib/loan.flang. До 16 августа 2026 решение принимала не функция, а
       ДОКАЗАТЕЛЬСТВО — модель `domain/loan-permission.fts` строила по снимку
       данных сертификат с отпечатком, и хозяин исполнял названную им команду.
       Способность ушла вместе со старым проектом; довод записан в шапке
       lib/loan.flang, а не спрятан здесь. */
    "POST /loans": (_запрос, тело) => {
      const разрешено = библиотека.звать("Выдача разрешена", {
        "заявка": {
          "читатель допущен": тело["читатель допущен"] === true,
          "долгов нет": тело["долгов нет"] === true,
        },
      })
      if (разрешено !== true) return ответ(403, { ошибка: "выдача не разрешена", разрешено: false })
      const ключ = библиотека.звать("Ключ книги", { код: String(тело["книга"] ?? "") })
      const снятие = хранилище.снятьСПолки(ключ)
      if (!снятие.снята) return ответ(409, { ошибка: снятие.причина, книга: ключ })
      const выдача = хранилище.записатьВыдачу({ ...тело, книга: ключ })
      return ответ(201, { выдача, разрешено: true })
    },

    /* Сумму штрафа считает язык (lib/fine.flang). Здесь нет ни одного числа из
       тарифа — появись оно тут, заведующая правила бы тариф, а сервер отвечал
       бы по-старому. */
    "POST /returns": (_запрос, тело) => {
      const ключ = библиотека.звать("Ключ книги", { код: String(тело["книга"] ?? "") })
      const возврат = хранилище.вернутьНаПолку(ключ)
      if (!возврат.возвращена) return ответ(404, { ошибка: возврат.причина, книга: ключ })
      const штраф = библиотека.звать("Рассчитать штраф", {
        "выдача": {
          "дней просрочки": Number(тело["дней просрочки"] ?? 0),
          "книга редкая": тело["книга редкая"] === true,
        },
      })
      return ответ(200, { книга: возврат.книга, штраф })
    },
  }

  return createServer(async (запрос, ответНаружу) => {
    try {
      const ключ = `${запрос.method} ${путь(запрос.url)}`
      const обработчик = маршруты[ключ]
      if (обработчик === undefined) {
        return отправить(ответНаружу, ответ(404, { ошибка: "нет такого маршрута", маршруты: Object.keys(маршруты) }))
      }
      const тело = запрос.method === "POST" ? JSON.parse(await прочитатьТело(запрос)) : null
      return отправить(ответНаружу, обработчик(запрос, тело))
    } catch (ошибка) {
      return отправить(ответНаружу, ответ(400, { ошибка: ошибка instanceof Error ? ошибка.message : String(ошибка) }))
    }
  })
}

const ответ = (код, тело) => ({ код, тело })

const путь = (url) => String(url ?? "/").split("?")[0]

const строкаЗапроса = (url) => String(url ?? "").split("?").slice(1).join("?")

/* Клиент вправе прислать и «Стругацкие», и «%D0%A1%D1%82%…»: это одно и то же
   значение в разной записи. Битую последовательность оставляем как есть —
   отвечать 400 на кривой процент дороже, чем не найти книгу. */
function раскодировать(текст) {
  try {
    return decodeURIComponent(String(текст).replaceAll("+", " "))
  } catch {
    return String(текст)
  }
}

async function прочитатьТело(запрос) {
  const куски = []
  let размер = 0
  for await (const кусок of запрос) {
    размер += кусок.length
    if (размер > 1_000_000) throw new Error("тело запроса больше 1 МБ")
    куски.push(кусок)
  }
  const текст = Buffer.concat(куски).toString("utf8")
  return текст === "" ? "null" : текст
}

function отправить(ответНаружу, { код, тело }) {
  ответНаружу.writeHead(код, { "content-type": "application/json; charset=utf-8" })
  ответНаружу.end(`${JSON.stringify(тело, null, 2)}\n`)
}

const запущенныйФайл = process.argv[1]
if (запущенныйФайл !== undefined && import.meta.url === pathToFileURL(запущенныйФайл).href) {
  const порт = Number.parseInt(process.env.LIBRARY_PORT ?? "8797", 10)
  const сервер = await создатьСервер()
  сервер.listen(порт, "127.0.0.1", () => process.stdout.write(`Библиотека: http://127.0.0.1:${порт}\n`))
}
