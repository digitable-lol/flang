/**
 * Хранилище — в памяти процесса.
 *
 * Здесь оно нарочно самое простое, какое бывает: в примере важно не то, чем
 * заменить Postgres, а то, что хранение вообще не относится ни к FTS, ни к
 * flang. У языка нет эффектов; «положить книгу и увидеть её в следующем
 * запросе» — эффект в чистом виде, и живёт он тут.
 *
 * Форма записей — ровно та, что объявлена в lib/catalog.flang («Книга»), и это
 * не совпадение: библиотека получает записи хранилища как есть, без
 * перекладывания полей. Второй словарь имён («code» вместо «код») пришлось бы
 * держать в согласии вручную, а рассогласование двух словарей — беда, которую
 * не ловит ни один тип.
 */

const НАЧАЛЬНЫЕ_КНИГИ = [
  {
    код: "9785171183660",
    автор: "Стругацкие",
    название: "Пикник на обочине",
    год: 1972,
    "на полке": true,
  },
  {
    код: "9785040892839",
    автор: "Булгаков",
    название: "Мастер и Маргарита",
    год: 1967,
    "на полке": true,
  },
  {
    код: "9785170854189",
    автор: "Стругацкие",
    название: "Понедельник начинается в субботу",
    год: 1965,
    "на полке": false,
  },
]

export function создатьХранилище(книги = НАЧАЛЬНЫЕ_КНИГИ) {
  /* Копия, а не сам массив: два сервера в одном процессе (так их поднимает
     тест) не должны видеть чужие записи. */
  const каталог = книги.map((книга) => ({ ...книга }))
  const выдачи = []

  return {
    книги: () => каталог.map((книга) => ({ ...книга })),
    выдачи: () => выдачи.map((выдача) => ({ ...выдача })),
    добавитьКнигу(книга) {
      const уже = каталог.find((запись) => запись.код === книга.код)
      if (уже !== undefined) return { добавлена: false, причина: "книга с таким кодом уже есть" }
      каталог.push({ ...книга })
      return { добавлена: true, книга: { ...книга } }
    },
    снятьСПолки(ключ) {
      const книга = каталог.find((запись) => запись.код === ключ)
      if (книга === undefined) return { снята: false, причина: "книги с таким кодом нет" }
      if (!книга["на полке"]) return { снята: false, причина: "книга уже выдана" }
      книга["на полке"] = false
      return { снята: true, книга: { ...книга } }
    },
    вернутьНаПолку(ключ) {
      const книга = каталог.find((запись) => запись.код === ключ)
      if (книга === undefined) return { возвращена: false, причина: "книги с таким кодом нет" }
      книга["на полке"] = true
      return { возвращена: true, книга: { ...книга } }
    },
    записатьВыдачу(выдача) {
      выдачи.push({ ...выдача })
      return { ...выдача }
    },
  }
}
