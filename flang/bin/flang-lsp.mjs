/**
 * flang-lsp — языковой сервер flang по стандартному вводу-выводу.
 *
 * Здесь только транспорт: рамки `Content-Length`, разбор JSON и склейка
 * входящего потока. Всё, что решает, чем является сообщение и что на него
 * ответить, живёт в `src/lsp.mjs` — поэтому сервер проверяется и без процесса,
 * а процесс проверяется отдельным тестом, который говорит с ним по-настоящему.
 *
 *   flang-lsp            запуск по stdio (так его запускают редакторы)
 *   flang-lsp --stdio    то же самое; ключ понимают не все редакторы, но
 *                        присылают его почти все, и падать на нём нельзя
 *
 * Печатать что-либо в stdout, кроме сообщений протокола, нельзя: редактор
 * читает оттуда рамки и на первом же лишнем байте теряет связь. Поэтому всё
 * человеческое — в stderr.
 */
import { realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { createServer, SERVER_NAME } from "../src/lsp.mjs"

const HELP = `${SERVER_NAME} — языковой сервер flang (LSP) для файлов .flang

Использование:
  flang-lsp [--stdio]

Других доводов не принимает: любой лишний — отказ с кодом 2, а не молчаливый
запуск. Молчащая команда неотличима от сломанной.

Сервер разговаривает по стандартному вводу-выводу рамками Content-Length, как
требует спецификация LSP. Запускается редактором, а не человеком: вручную его
запускать незачем — он будет молча ждать сообщений.

Умеет: диагностику той же дорогой, что «flang check» (разбор, типы,
завершаемость, процессы и надзор), дополнение (ключевые слова, имена модуля и
импортированных модулей, поля записей, варианты в «разбор»), наведение с
сигнатурой и переход к объявлению.
`

export async function main(argv = process.argv.slice(2)) {
  if (argv.includes("--help") || argv.includes("-h")) {
    process.stdout.write(HELP)
    return 0
  }
  /* Непонятое отвергается ЛЮБОЕ, а не только начинающееся с дефиса.
     Раньше проверка смотрела на ключи, и слово без дефиса — `flang-lsp help` —
     проходило насквозь: сервер уходил ждать сообщения на стандартном вводе, на
     закрытом вводе получал конец потока и завершался кодом 0, не сказав ни
     байта. Это ровно та немота, из-за которой заведён
     `flang/test/bin-through-symlink.test.mjs`: команда, молчащая при коде 0,
     неотличима от сломанной. Поймано тем же тестом, когда список команд в нём
     перестал быть написанным руками и стал читаться из package.json. */
  const неизвестный = argv.find((довод) => довод !== "--stdio")
  if (неизвестный !== undefined) {
    process.stderr.write(`${SERVER_NAME}: неизвестный довод ${неизвестный}\n\n${HELP}`)
    return 2
  }

  /* Прощание: `exit` не убивает процесс и не рвёт поток. Убить его нельзя,
     потому что ответ на `shutdown` мог ещё не уйти в редактор; разорвать ввод
     тоже нельзя — чтение получило бы «преждевременное закрытие» и сервер
     завершился бы ошибкой после совершенно нормального прощания. Поэтому
     чтение просто перестаёт ждать, и процесс заканчивается сам, когда допишет
     последнее сообщение. */
  let попрощаться = () => {}
  const прощание = new Promise((решить) => {
    попрощаться = решить
  })

  const сервер = createServer({
    send: (сообщение) => написать(сообщение),
    exit: (код) => {
      process.exitCode = код
      попрощаться()
    },
  })

  /* Очередь на один шаг: сообщения обрабатываются строго по порядку. Редактор
     присылает «изменился текст» и сразу «дополни» — обработав их вперемешку,
     сервер дополнял бы по предыдущей версии файла. */
  let очередь = Promise.resolve()
  const обработать = (сообщение) => {
    очередь = очередь.then(() => сервер.receive(сообщение)).catch((ошибка) => {
      process.stderr.write(`${SERVER_NAME}: ${ошибка instanceof Error ? ошибка.stack : String(ошибка)}\n`)
    })
    return очередь
  }

  await Promise.race([читать(process.stdin, обработать), прощание])
  await очередь
  /* Ввод больше не нужен и не должен держать процесс на плаву. */
  process.stdin.pause()
  process.stdin.unref()
  return process.exitCode ?? 0
}

/* ─────────────────────────────── рамки LSP ──────────────────────────────── */

const РАЗДЕЛИТЕЛИ = ["\r\n\r\n", "\n\n"]

/**
 * Поток байтов → сообщения.
 *
 * Длина в заголовке — в БАЙТАХ, а не в символах: в исходниках flang имена
 * русские, и на первом же «использует» посчитанная в символах длина обрезала
 * бы сообщение на середине. Поэтому копим Buffer и режем его по байтам, а в
 * строку переводим только готовое тело.
 */
export async function читать(поток, обработать) {
  let буфер = Buffer.alloc(0)

  const разобрать = async () => {
    for (;;) {
      const шапка = найтиРазделитель(буфер)
      if (шапка === null) return
      const заголовки = буфер.subarray(0, шапка.конец).toString("utf8")
      const длина = длинаТела(заголовки)
      if (длина === null) {
        /* Рамка без длины — единственное, чего протокол не позволяет починить:
           где кончается тело, неизвестно. Выбрасываем шапку и ищем следующую,
           иначе сервер завис бы навсегда на первом мусорном байте. */
        process.stderr.write(`${SERVER_NAME}: рамка без Content-Length, пропущена\n`)
        буфер = буфер.subarray(шапка.конец)
        continue
      }
      const начало = шапка.конец
      if (буфер.length < начало + длина) return
      const тело = буфер.subarray(начало, начало + длина).toString("utf8")
      буфер = буфер.subarray(начало + длина)
      let сообщение
      try {
        сообщение = JSON.parse(тело)
      } catch (ошибка) {
        process.stderr.write(`${SERVER_NAME}: неразобранный JSON — ${ошибка.message}\n`)
        continue
      }
      await обработать(сообщение)
    }
  }

  for await (const кусок of поток) {
    буфер = Buffer.concat([буфер, Buffer.isBuffer(кусок) ? кусок : Buffer.from(кусок)])
    await разобрать()
  }
}

function найтиРазделитель(буфер) {
  let лучшее = null
  for (const разделитель of РАЗДЕЛИТЕЛИ) {
    const где = буфер.indexOf(разделитель, 0, "utf8")
    if (где === -1) continue
    if (лучшее === null || где < лучшее.где) лучшее = { где, конец: где + разделитель.length }
  }
  return лучшее
}

function длинаТела(заголовки) {
  const совпадение = /content-length:\s*(\d+)/iu.exec(заголовки)
  return совпадение === null ? null : Number(совпадение[1])
}

function написать(сообщение) {
  const тело = Buffer.from(JSON.stringify(сообщение), "utf8")
  process.stdout.write(`Content-Length: ${тело.length}\r\n\r\n`)
  process.stdout.write(тело)
}

/* Сравниваем разрешённые пути, а не строки: npm ставит объявленные в bin
   команды символьными ссылками, и argv[1] (путь ссылки) с import.meta.url
   (путь файла) не совпадают — ровно та же ловушка, что описана в flang.mjs. */
const вызван = process.argv[1]
let запущенКакПрограмма = false
if (вызван !== undefined) {
  try {
    запущенКакПрограмма = realpathSync(fileURLToPath(import.meta.url)) === realpathSync(вызван)
  } catch {
    запущенКакПрограмма = false
  }
}
if (запущенКакПрограмма) {
  process.exitCode = await main()
}
