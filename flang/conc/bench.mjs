/**
 * Измерение модели конкурентности — шаг 7 контракта (`flang/conc/SPEC.md`).
 *
 * Контракт требует три числа: сколько процессов помещается, сколько стоит
 * отправка, сколько — переключение. И он же требует, чтобы до измерения они не
 * назывались. Здесь они измеряются.
 *
 * ── Главное правило этого файла: число без условий измерения — не число ─────
 *
 * Машина, на которой это писалось, бывала занята чужой работой (средняя
 * нагрузка доходила до шестидесяти на восьми ядрах). Секунда, измеренная на
 * такой машине, не говорит ни о чём: она говорит о соседе. Поэтому основные
 * числа здесь — те, которые от нагрузки НЕ ЗАВИСЯТ:
 *
 *   • витки интерпретатора на пробег обработчика — единица самого языка, та
 *     самая, которой меряется `с запасом N витков`. Считается не таймером, а
 *     двоичным поиском по запасу: наименьший запас, на котором обработчик ещё
 *     не падает с FLANG_BUDGET_EXHAUSTED, и есть точное число витков;
 *   • редукции BEAM на доставку — собственная валюта машины
 *     (`:erlang.statistics(:reductions)`);
 *   • байты процесса — спрошенные у него самого (`Process.info(pid, :memory)`),
 *     а не вычтенные из общего итога: разность двух общих замеров мерила
 *     момент сборки мусора и однажды вышла отрицательной;
 *   • пробеги и доставки планировщика эталона — целые числа, не измерения.
 *
 * Одно число из счётчиков BEAM в этот список НЕ попало, и врать об этом нельзя:
 * `:erlang.statistics(:context_switches)` от нагрузки ЗАВИСИТ — чем занятее
 * машина, тем чаще ядро отбирает поток у планировщика BEAM. Печатается оно
 * поэтому парой (голый GenServer и процесс flang в одном прогоне): устойчива
 * тут разница между двумя строками, а не каждая по отдельности.
 *
 * Секунды тоже измеряются, но: берётся МИНИМУМ из повторов (минимум ближе всего
 * к незанятой машине — помеха может только замедлить), и рядом печатается
 * средняя нагрузка на момент замера. Отношение двух времён, снятых подряд,
 * устойчивее каждого из них по отдельности, поэтому «отправка стоит столько-то
 * ОТ пробега» — утверждение более твёрдое, чем «отправка стоит столько-то
 * микросекунд».
 *
 * ── Что здесь НЕ измеряется и почему ────────────────────────────────────────
 *
 * «Сколько процессов помещается» у модели упирается не в память. `породить` в
 * модели нет (шаг 1, и это записано в границе честности), поэтому набор
 * процессов задан ОБЪЯВЛЕНИЕМ: чтобы их стало миллион, миллион объявлений надо
 * написать в исходнике и провести через разбор, проверку типов и печать.
 * Поэтому здесь меряются обе стенки: и байты на процесс, и цена объявления —
 * сколько времени и памяти стоит довести программу с P процессами до запуска.
 *
 * ── Почему этот файл лежит не в `flang/src/` ───────────────────────────────
 *
 * `AGENTS.md` требует от ядра языка детерминированности и отсутствия доступа к
 * файловой системе, сети и внешним зависимостям. Мерка нарушает всё это сразу:
 * пишет исходники во временный каталог, зовёт `elixirc` и `elixir`, читает
 * часы. Поэтому она стоит рядом с контрактом, который объясняет её числа, а не
 * внутри реализации — как инструменты в `tools/`, а не как `flang/src/`.
 *
 * Запуск:
 *     node --expose-gc flang/conc/bench.mjs            # эталон и BEAM
 *     node --expose-gc flang/conc/bench.mjs --эталон   # без BEAM
 *
 * Без `--expose-gc` числа памяти врут, и файл говорит об этом первой строкой
 * отчёта, а не молчит.
 */

