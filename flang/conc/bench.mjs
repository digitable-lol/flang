/* ══════════ 5. цена вытеснения: стек, переключение, проверка кванта ═══════ */

/**
 * Шаг В1 карты (`RESILIENCE.md`): измерить, чего стоит вытеснение, ПРЕЖДЕ чем
 * его писать.
 *
 * Почему порядок именно такой, а не «напишем и посмотрим». Вытеснение по витку
 * — это отказ от единственного, что сегодня делает пробег дешёвым: обработчик
 * зовётся обычным вызовом C (`plan->call` в `fl_conc_run`), живёт на стеке
 * вызывающего и возвращает управление сам. Снять его на середине можно только
 * так: дать каждому процессу СВОЙ машинный стек и переключаться между ними. Всё
 * остальное — про то, во что это обойдётся, и три числа ниже ровно про это.
 *
 * ── Что меряется и почему именно это ───────────────────────────────────────
 *
 *   • ПЕРЕКЛЮЧЕНИЕ (`swapcontext`) — цена самого снятия. Рядом меряется голый
 *     `sigprocmask`, и не для красоты: `swapcontext` по стандарту сохраняет и
 *     восстанавливает маску сигналов, то есть делает СИСТЕМНЫЙ ВЫЗОВ на каждом
 *     переключении. Если эти два числа окажутся одного порядка, значит почти всё
 *     переключение — это маска, и её можно не платить (`_setjmp`/`_longjmp`
 *     маску не трогают). Без второго числа первое нечем объяснить.
 *
 *   • СТЕК НА ПРОЦЕСС — цена того, чтобы снятие вообще было возможно. Меряется
 *     не «сколько зарезервировано» (резерв ничего не стоит: страницы отдаёт
 *     ядро по касанию), а сколько байт процесс ДЕЙСТВИТЕЛЬНО трогает. Два
 *     прибора: закраска стека сопрограммы известным байтом (точный, от нагрузки
 *     не зависит вовсе) и прирост RSS на тысячах сопрограмм (грубый, зато
 *     считает страницы так же, как их считает ядро).
 *
 *   • ЗАВЕДЕНИЕ КОНТЕКСТА (`getcontext` + `makecontext`) — это то, что платится
 *     один раз на процесс, и его надо знать отдельно от переключения: у
 *     объявленных процессов оно платится при запуске, у порождённых (Б1) — на
 *     каждое `породить`.
 *
 * Это НЕ переносимый C99: `ucontext.h` — POSIX XSI, и в POSIX.1-2008 он объявлен
 * устаревшим. Именно поэтому мерка стоит здесь, рядом с картой, а не в рантайме:
 * рантайм обязан собираться где угодно, а решение «стек на процесс» принимается
 * один раз и с числами на руках.
 */
const ВЫТЕСНЕНИЕ_C = `#define _XOPEN_SOURCE 700
#include <signal.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <sys/mman.h>
#include <ucontext.h>
#include <unistd.h>

/* Закраска: байт, которого в живых данных заведомо не бывает целыми
   страницами. Нетронутый хвост стека остаётся закрашенным, и высшая точка
   находится сканированием, а не догадкой. */
#define PAINT 0xA5

static ucontext_t home;
static ucontext_t guest;
static long rounds = 500000;

/* Через swapcontext переменная возвращается «как из longjmp», и gcc с
   -Werror=clobbered прав: значение в регистре пережить переключение не обязано.
   Поэтому всё, что живёт ПОПЕРЁК переключения, лежит в памяти, а не в кадре
   main. */
static size_t high = 0;
static long before = 0;
static long after = 0;

static double now_ns(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return (double)ts.tv_sec * 1e9 + (double)ts.tv_nsec;
}

static long resident_bytes(void) {
  FILE *file = fopen("/proc/self/statm", "r");
  long total = 0;
  long resident = 0;
  if (file == NULL) {
    return -1;
  }
  if (fscanf(file, "%ld %ld", &total, &resident) != 2) {
    resident = -1;
  }
  fclose(file);
  return resident < 0 ? -1 : resident * (long)sysconf(_SC_PAGESIZE);
}

/* Сопрограмма качелей: только и делает, что отдаёт управление обратно. Меньше
   в ней быть не может, поэтому её высшая точка стека — это ПОЛ цены, ниже
   которого не опустится никакой обработчик. */
static void seesaw(void) {
  long index = 0;
  for (index = 0; index < rounds; index += 1) {
    swapcontext(&guest, &home);
  }
}

/* Один заход и обратно: ровно то, что делает вытесненный процесс, когда его
   снимают и возвращают. */
static void once(void) {
  swapcontext(&guest, &home);
}

/** Сколько байт закрашенного стека оказались тронуты. */
static size_t touched(const char *bottom, size_t size) {
  size_t index = 0;
  for (index = 0; index < size; index += 1) {
    if ((unsigned char)bottom[index] != PAINT) {
      return size - index;
    }
  }
  return 0;
}

int main(void) {
  static char stack[256 * 1024];
  double start = 0.0;
  double switching = 0.0;
  double mask = 0.0;
  double creation = 0.0;
  long index = 0;
  const long coroutines = 4096;
  const size_t stack_size = 64 * 1024;
  char *painted = NULL;
  sigset_t set;
  sigset_t previous;

  /* ── переключение ── */
  getcontext(&guest);
  guest.uc_stack.ss_sp = stack;
  guest.uc_stack.ss_size = sizeof stack;
  guest.uc_link = &home;
  makecontext(&guest, seesaw, 0);
  start = now_ns();
  for (index = 0; index < rounds; index += 1) {
    swapcontext(&home, &guest);
  }
  /* Круг — это ДВА переключения: туда и обратно. */
  switching = (now_ns() - start) / ((double)rounds * 2.0);

  /* ── голая маска сигналов: из чего это переключение состоит ── */
  sigemptyset(&set);
  start = now_ns();
  for (index = 0; index < rounds; index += 1) {
    sigprocmask(SIG_SETMASK, &set, &previous);
  }
  mask = (now_ns() - start) / (double)rounds;

  /* ── заведение контекста ── */
  start = now_ns();
  for (index = 0; index < rounds; index += 1) {
    ucontext_t one;
    getcontext(&one);
    one.uc_stack.ss_sp = stack;
    one.uc_stack.ss_size = sizeof stack;
    one.uc_link = &home;
    makecontext(&one, once, 0);
  }
  creation = (now_ns() - start) / (double)rounds;

  /* ── точный прибор: высшая точка стека одной сопрограммы ── */
  painted = mmap(NULL, stack_size, PROT_READ | PROT_WRITE,
                 MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
  if (painted == MAP_FAILED) {
    return 1;
  }
  memset(painted, PAINT, stack_size);
  getcontext(&guest);
  guest.uc_stack.ss_sp = painted;
  guest.uc_stack.ss_size = stack_size;
  guest.uc_link = &home;
  makecontext(&guest, once, 0);
  swapcontext(&home, &guest);
  swapcontext(&home, &guest);
  high = touched(painted, stack_size);
  munmap(painted, stack_size);

  /* ── грубый прибор: RSS на тысячах сопрограмм ── */
  {
    ucontext_t *contexts = malloc((size_t)coroutines * sizeof *contexts);
    char **stacks = malloc((size_t)coroutines * sizeof *stacks);
    if (contexts == NULL || stacks == NULL) {
      free(contexts);
      free(stacks);
      return 1;
    }
    /* Стеки берутся у ядра напрямую, а не у malloc, и это не вкусовщина.
       Соседний кусок malloc пишет свой заголовок сразу ЗА концом нашего, то
       есть на ту же страницу, куда придётся вершина нашего стека: страница
       оказывается резидентной ещё до того, как сопрограмма пущена, и прирост
       RSS считает не нас. С mmap каждый стек — своё отображение, и ни одна его
       страница не тронута никем, кроме сопрограммы. */
    for (index = 0; index < coroutines; index += 1) {
      stacks[index] = mmap(NULL, stack_size, PROT_READ | PROT_WRITE,
                           MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
      if (stacks[index] == MAP_FAILED) {
        return 1;
      }
    }
    before = resident_bytes();
    for (index = 0; index < coroutines; index += 1) {
      getcontext(&contexts[index]);
      contexts[index].uc_stack.ss_sp = stacks[index];
      contexts[index].uc_stack.ss_size = stack_size;
      contexts[index].uc_link = &home;
      makecontext(&contexts[index], once, 0);
      /* Запустить и снять: именно запуск трогает страницы. Сопрограмма, которую
         только завели, не стоит ни байта резидентной памяти, и число «64 КиБ на
         процесс» было бы враньём. */
      swapcontext(&home, &contexts[index]);
    }
    after = resident_bytes();
    for (index = 0; index < coroutines; index += 1) {
      munmap(stacks[index], stack_size);
    }
    free(contexts);
    free(stacks);
  }

  printf("%.1f\\t%.1f\\t%.1f\\t%lu\\t%ld\\t%ld\\t%ld\\n", switching, mask, creation,
         (unsigned long)high, coroutines, before, after);
  return 0;
}
`

/**
 * Два `fl_tick`, отличающиеся ровно одной ветвью, — и это весь замер.
 *
 * Сегодня `fl_tick` (`emit/c/flang_runtime.c`) считает витки и сверяет счёт с
 * одним пределом — запасом. Вытеснение добавляет ВТОРОЙ предел, квант, и вопрос
 * В1 в том, сколько стоит его проверять: этот код зовётся на каждом входе в
 * функцию, каждом обороте хвостовой петли и каждом отскоке батута, то есть чаще
 * всего остального в рантайме вместе взятого.
 *
 * Обе функции лежат в ОТДЕЛЬНОМ файле от главного, и это не мелочь: в одном
 * файле -O2 подставил бы их в цикл целиком, ветвь ушла бы вместе с вызовом, и
 * замер показал бы ноль по причине, к вытеснению не относящейся. В напечатанном
 * C `fl_tick` — тоже вызов через границу файла.
 *
 * Третьего варианта здесь нет намеренно. «Слияние» — это когда квант не
 * проверяется отдельно, а вносится в тот же предел (`max_steps = min(запас,
 * квант)`), и различаются они уже ПОСЛЕ отказа, по тому, что именно кончилось.
 * Мерить его нечем: горячий путь у него — та же самая функция `tick_plain`,
 * байт в байт. Именно поэтому он и назван в отчёте: цена у него ноль не по
 * замеру, а по построению.
 */
const ТИК_C = `#include "tick.h"

int tick_plain(tick_ctx *ctx) {
  if (ctx->max_steps == 0) {
    return 0;
  }
  ctx->steps += 1;
  if (ctx->steps > ctx->max_steps) {
    return 1;
  }
  return 0;
}

/* Двойник tick_plain — тот же код под другим именем. Он не измеряет
   вытеснение вовсе: он измеряет ПРИБОР. Разница между двумя прогонами
   ОДИНАКОВОЙ функции — это шум, и без неё «ветвь стоит столько-то» нечем
   отличить от «столько-то показал случай». */
int tick_twin(tick_ctx *ctx) {
  if (ctx->max_steps == 0) {
    return 0;
  }
  ctx->steps += 1;
  if (ctx->steps > ctx->max_steps) {
    return 1;
  }
  return 0;
}

int tick_quantum(tick_ctx *ctx) {
  if (ctx->max_steps == 0) {
    return 0;
  }
  ctx->steps += 1;
  if (ctx->steps > ctx->max_steps) {
    return 1;
  }
  if (ctx->quantum != 0 && ctx->steps >= ctx->quantum) {
    return 2;
  }
  return 0;
}
`

const ТИК_H = `#ifndef FLANG_BENCH_TICK_H
#define FLANG_BENCH_TICK_H

typedef struct {
  unsigned long steps;
  unsigned long max_steps;
  unsigned long quantum;
} tick_ctx;

int tick_plain(tick_ctx *ctx);
int tick_twin(tick_ctx *ctx);
int tick_quantum(tick_ctx *ctx);

#endif
`

const ТИК_ГЛАВНОЕ_C = `#define _POSIX_C_SOURCE 200809L
#include <stdio.h>
#include <time.h>

#include "tick.h"

static double now_ns(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return (double)ts.tv_sec * 1e9 + (double)ts.tv_nsec;
}

int main(void) {
  const long ticks = 50000000L;
  const int rounds = 9;
  long index = 0;
  int round = 0;
  double start = 0.0;
  double one = 0.0;
  double plain = 1e18;
  double twin = 1e18;
  double quantum = 1e18;
  tick_ctx ctx;
  int guard = 0;

  ctx.max_steps = 0xFFFFFFFFUL;
  ctx.quantum = 0xFFFFFFFUL;
  /* Два цикла ЧЕРЕДУЮТСЯ, а не идут один за другим, и берётся минимум из
     повторов. Подряд первый платит за холодный кэш и разогрев предсказателя
     переходов, и разность двух таких замеров однажды вышла ОТРИЦАТЕЛЬНОЙ —
     проверка кванта «ускорила» виток на 19 %. Число, которое бывает
     отрицательным там, где отрицательным быть не может, мерит не то, что
     названо. */
  /* Порядок трёх циклов ПЕРЕВОРАЧИВАЕТСЯ через круг. Идя всегда одной чередой,
     последний цикл систематически выигрывал у первого — не своей ветвью, а
     местом в очереди (кэш, разогретый предсказатель), и разность выходила
     отрицательной устойчиво. Симметричный порядок это место обнуляет. */
  for (round = 0; round < rounds; round += 1) {
    int slot = 0;
    for (slot = 0; slot < 3; slot += 1) {
      const int which = (round % 2 == 0) ? slot : 2 - slot;
      ctx.steps = 0;
      start = now_ns();
      if (which == 0) {
        for (index = 0; index < ticks; index += 1) {
          guard |= tick_plain(&ctx);
        }
      } else if (which == 1) {
        for (index = 0; index < ticks; index += 1) {
          guard |= tick_twin(&ctx);
        }
      } else {
        for (index = 0; index < ticks; index += 1) {
          guard |= tick_quantum(&ctx);
        }
      }
      one = (now_ns() - start) / (double)ticks;
      if (which == 0 && one < plain) {
        plain = one;
      }
      if (which == 1 && one < twin) {
        twin = one;
      }
      if (which == 2 && one < quantum) {
        quantum = one;
      }
    }
  }

  printf("%.4f\\t%.4f\\t%.4f\\t%d\\n", plain, twin, quantum, guard);
  return 0;
}
`

function меркаКонтекстов(повторов) {
  const cc = findExecutable("cc") ?? findExecutable("gcc")
  if (cc === null) return null
  const каталог = mkdtempSync(join(tmpdir(), "flang-bench-контекст-"))
  try {
    writeFileSync(join(каталог, "context.c"), ВЫТЕСНЕНИЕ_C)
    execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O2",
                      "context.c", "-o", "context"], { cwd: каталог, stdio: ["ignore", "pipe", "pipe"] })
    let переключение = Infinity
    let маска = Infinity
    let заведение = Infinity
    let высшая = Infinity
    let наСопрограмму = Infinity
    let сопрограмм = 0
    for (let раз = 0; раз < повторов; раз += 1) {
      const [п, м, з, в, с, было, стало] = execFileSync(join(каталог, "context"), { encoding: "utf8" })
        .trim().split("\t").map(Number)
      переключение = Math.min(переключение, п)
      маска = Math.min(маска, м)
      заведение = Math.min(заведение, з)
      /* Высшая точка — не измерение, а счёт тронутых байт: повторы обязаны
         совпасть до байта, и минимум здесь взят только чтобы не заводить
         отдельной проверки на это. */
      высшая = Math.min(высшая, в)
      сопрограмм = с
      if (было >= 0 && стало >= 0) наСопрограмму = Math.min(наСопрограмму, (стало - было) / с)
    }
    return { переключение, маска, заведение, высшая, сопрограмм, наСопрограмму }
  } catch {
    /* `ucontext.h` может не найтись вовсе — это не поломка мерки, а отсутствие
       того, чем вытеснение делалось бы на этой платформе. */
    return null
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

