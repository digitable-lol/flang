      скажи(`  передача работы другому потоку (mutex+condvar): ${(м.передача / 1000).toFixed(2)} мкс`)
      скажи(`  взять незанятый замок:                          ${м.замок.toFixed(0)} нс`)
      скажи(`  завести и убрать поток:                         ${(м.заведение / 1000).toFixed(2)} мкс`)
