/**
 * Сколько байт арены стоит один пробег — и возвращается ли хоть один из них.
 *
 * Это не про скорость, а про то, может ли процесс flang жить долго. Арена
 * рантайма C освобождается целиком и только вместе с вызывающим
 * (`flang_conc.h`, раздел «Память»): у неё есть `fl_arena_reset`, но нет
 * освобождения по одному значению. Значит вопрос «сколько байт на пробег»
 * равнозначен вопросу «с какой скоростью течёт долгоживущий процесс», и ответ
 * на него до сих пор не измерялся ни разу.
 *
 * ── Два прибора, и у них нет ничего общего ─────────────────────────────────
 * `valgrind` называет ТОЧНОЕ число байт, выданных malloc за весь процесс. Оно
 * не зависит от нагрузки вовсе — это счётчик, а не измерение, — и потому стоит
 * здесь первым, рядом с витками и редукциями. Пиковый RSS (`/usr/bin/time`)
 * меряет другое и другим: сколько страниц процесс отобрал у ядра. Совпадение
 * двух наклонов — единственная причина верить любому из них.
 *
 * Valgrind медленный, поэтому точный прибор идёт по тысячам пробегов, а грубый
 * — по миллионам: у первого важна точность, у второго — плечо.
 */
function меркаЖизни() {
  const cc = findExecutable("cc") ?? findExecutable("gcc")
  const valgrind = findExecutable("valgrind")
  const time = findExecutable("time") ?? "/usr/bin/time"
  if (cc === null) return null
  const каталог = mkdtempSync(join(tmpdir(), "flang-bench-жизнь-"))
  try {
    const путь = join(каталог, "p")
    mkdirSync(путь, { recursive: true })
    const напечатано = emitC(parse(пингПонг(), "мерка.flang"))
    const исходники = []
    for (const файл of напечатано.files) {
      writeFileSync(join(путь, файл.path), файл.content)
      if (файл.path.endsWith(".c")) исходники.push(файл.path)
    }
    execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O2", ...исходники,
                      "-o", "flang_cli", "-lm"], { cwd: путь, stdio: ["ignore", "pipe", "pipe"] })
    const бинарник = join(путь, "flang_cli")
    const вход = (сколько) => `${JSON.stringify({ run: "мерка", seed: "1", turns: String(сколько) })}\n`

    const байты = []
    if (valgrind !== null) {
      for (const пробегов of [500, 1000, 2000, 4000, 8000]) {
        const р = spawnSync(valgrind, ["--tool=memcheck", бинарник],
          { input: вход(пробегов), encoding: "utf8", maxBuffer: 1 << 28 })
        const строка = (р.stderr ?? "").split("\n").find((с) => с.includes("total heap usage"))
        const разбор = /([\d,]+) allocs, ([\d,]+) frees, ([\d,]+) bytes allocated/.exec(строка ?? "")
        if (разбор === null) continue
        байты.push({
          пробегов,
          выделений: Number(разбор[1].replace(/,/g, "")),
          освобождений: Number(разбор[2].replace(/,/g, "")),
          байт: Number(разбор[3].replace(/,/g, "")),
        })
      }
    }

    const страницы = []
    for (const пробегов of [10000, 100000, 1000000]) {
      /* Вывод в /dev/null: журнал прогона печатается целиком, и на миллионе
         пробегов он сам по себе — сотни мегабайт трубы. Мерить надо память
         процесса, а не буфер читателя. */
      const р = spawnSync(time, ["-f", "%M", "sh", "-c", `exec ${JSON.stringify(бинарник)} > /dev/null`],
        { input: вход(пробегов), encoding: "utf8", maxBuffer: 1 << 28 })
      const киб = Number((р.stderr ?? "").trim().split("\n").pop())
      if (Number.isFinite(киб)) страницы.push({ пробегов, киб })
    }
    return { байты, страницы }
  } catch {
    return null
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

function меркаBEAM(процессов) {
  const elixirc = findExecutable("elixirc")
  const elixir = findExecutable("elixir")
  if (elixirc === null || elixir === null) return null

  const каталог = mkdtempSync(join(tmpdir(), "flang-conc-bench-"))
  try {
    const программа = parse(кольцо(процессов, false), "мерка.flang")
    const беды = checkTypes(программа).diagnostics
    if (беды.length > 0) throw new Error(`программа не прошла проверки: ${JSON.stringify(беды)}`)
    const напечатано = emitElixir(программа, { module: "Мерка" }) /* модуль печатается как Merka */

    const исходники = join(каталог, "src")
    const сборка = join(каталог, "ebin")
    mkdirSync(исходники, { recursive: true })
    mkdirSync(сборка, { recursive: true })
    const файлы = []
    for (const файл of напечатано.files) {
      if (!файл.path.endsWith(".ex")) continue
      const путь = join(исходники, файл.path)
      mkdirSync(join(путь, ".."), { recursive: true })
      writeFileSync(путь, файл.content)
      файлы.push(путь)
    }

    /* Сборка идёт в чужом процессе, а `process.cpuUsage()` считает только своё:
       мерить её тем же прибором, что и остальное, значило бы получить ноль.
       Здесь настенные часы, и потому это единственное число отчёта, которое от
       нагрузки зависит целиком. */
    const началоСборки = Date.now()
    execFileSync(elixirc, ["-o", сборка, ...файлы], {
      stdio: ["ignore", "pipe", "pipe"],
      env: { ...process.env, MIX_ENV: "prod" },
    })
    const собрано = Date.now() - началоСборки

    const скрипт = join(каталог, "замер.exs")
    writeFileSync(скрипт, ЗАМЕР_EX)
    const вывод = execFileSync(elixir, ["-pa", сборка, скрипт], {
      encoding: "utf8",
      env: { ...process.env, MIX_ENV: "prod", ERL_CRASH_DUMP_SECONDS: "0" },
      timeout: 600_000,
    })

    const метки = ["ЗАМЕР", "ЁМКОСТЬ", "ГОЛАЯ_ЁМКОСТЬ", "ПРЕДЕЛ", "НАБЛЮДЕНИЕ"]
    const строки = вывод.split("\n").filter((с) => метки.some((метка) => с.startsWith(метка)))
    return { процессов, мсСборки: собрано, строки, вывод }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

