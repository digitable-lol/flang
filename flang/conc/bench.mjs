/* Ядра называются двумя числами, и оба печатаются в отчёт.
 
   Разница между ними бывает велика и меняет смысл нагрузки: на этой машине
   `/proc/cpuinfo` и `os.cpus()` видят восемь процессоров, а `nproc --all` —
   сто двадцать (окружение показывает процессу часть машины). «Нагрузка 40» на
   восьми ядрах и на ста двадцати означает совершенно разное, и умалчивать,
   каких именно ядер восемь, нельзя. Ровно поэтому главные числа отчёта
   выбраны так, чтобы нагрузка на них не влияла вовсе: спор о том, чья это
   нагрузка, их не касается. */
const ядерВсего = cpus().length
const ядерНам = availableParallelism()

const нагрузка = () => loadavg().map((н) => н.toFixed(2)).join(" / ")

function гc() {
  if (typeof global.gc === "function") global.gc()
}

/** Куча после сборки мусора: без неё замер меряет мусор, а не живое. */
function куча() {
  гc()
  гc()
  return process.memoryUsage().heapUsed
}

/**
 * Минимум ПРОЦЕССОРНОГО времени из повторов — не настенного и не среднего.
 *
 * Две поправки на занятую машину, и обе обязательны.
 *
 * Первая: `process.cpuUsage()` считает время, которое ядро отдало ИМЕННО НАМ, а
 * не время по стенным часам. Пока чужая работа держит процессор, наш счётчик
 * стоит. Полностью от соседа это не спасает (кэш и память общие), но убирает
 * главное — ожидание очереди планировщика ОС, а на нагрузке 30 при восьми ядрах
 * ожидание и есть почти всё измерение.
 *
 * Вторая: минимум, а не среднее. Помеха может замер только удлинить — отнять
 * работу у соседа и посчитать меньше положенного нельзя. Значит минимум из K
 * повторов — оценка снизу, и она тем ближе к правде, чем больше K. Среднее на
 * занятой машине не значит ничего.
 */
function минимум(повторов, дело) {
  let лучшее = Infinity
  for (let раз = 0; раз < повторов; раз += 1) {
    const начало = process.cpuUsage()
    дело()
    const прошло = process.cpuUsage(начало)
    const мс = (прошло.user + прошло.system) / 1000
    if (мс < лучшее) лучшее = мс
  }
  return лучшее
}

/**
 * Два дела, замеряемые ВПЕРЕМЕЖКУ.
 *
 * Разность двух времён, снятых порознь, на занятой машине не значит ничего:
 * между замерами нагрузка успевает измениться, и разность становится разностью
 * нагрузок, а не работы. Здесь повторы чередуются, поэтому оба дела видят
 * примерно одну и ту же машину, и разность их минимумов — это разность работы.
 */
function минимумПары(повторов, первое, второе) {
  let лучшееПервое = Infinity
  let лучшееВторое = Infinity
  for (let раз = 0; раз < повторов; раз += 1) {
    лучшееПервое = Math.min(лучшееПервое, минимум(1, первое))
    лучшееВторое = Math.min(лучшееВторое, минимум(1, второе))
  }
  return [лучшееПервое, лучшееВторое]
}

