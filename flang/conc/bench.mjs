/**
 * Программа из P процессов на одном обработчике.
 *
 * Один обработчик на всех — не экономия строк, а условие измерения: разные
 * обработчики стоили бы разного, и «пробег» перестал бы быть одной величиной.
 * Процессы объявляются по одному, потому что иначе их и не завести: `породить`
 * в модели нет.
 *
 * @param {number} процессов сколько объявить
 * @param {boolean} сОтправкой шлёт ли обработчик сообщение «Стоку»
 */
function кольцо(процессов, сОтправкой) {
  const строки = [
    "модуль «Мерка»",
    "",
    "объект «Счёт»",
    "  «всего»: число",
    "",
    "тип «Тик»",
    "  вариант «тик»",
    "",
    "объект «Отклик»",
    "  «состояние»: «Счёт»",
    "  «действия»: список «Действие»",
    "",
    "процесс «Сток»",
    "  состояние «Счёт»",
    "  начинает с «нуль»",
    "  принимает «Тик»",
    "  обрабатывает «тихий шаг»",
    "",
  ]
  for (let номер = 1; номер <= процессов; номер += 1) {
    строки.push(
      `процесс «П${номер}»`,
      "  состояние «Счёт»",
      "  начинает с «нуль»",
      "  принимает «Тик»",
      `  обрабатывает «${сОтправкой ? "шумный шаг" : "тихий шаг"}»`,
      "",
    )
  }
  строки.push(
    "тотальная функция «нуль»",
    "  возвращает «Счёт»",
    "  запись «Счёт» с «всего» равным 0",
    "",
    "тотальная функция «тихий шаг»",
    "  принимает счёт: «Счёт», сообщение: «Тик»",
    "  возвращает «Отклик»",
    "  пусть новое равно (запись «Счёт» с «всего» равным (счёт.«всего» плюс 1))",
    "  запись «Отклик» с «состояние» равным новое и «действия» равным []",
    "",
    "тотальная функция «шумный шаг»",
    "  принимает счёт: «Счёт», сообщение: «Тик»",
    "  возвращает «Отклик»",
    "  пусть новое равно (запись «Счёт» с «всего» равным (счёт.«всего» плюс 1))",
    '  пусть письмо равно (вариант «отправить» с «кому» равным "Сток" и «что» равным (вариант «тик»))',
    "  запись «Отклик» с «состояние» равным новое и «действия» равным [письмо]",
    "",
  )
  return строки.join("\n")
}

/** Прогон: M сообщений в ящик «П1» и ни одного больше. */
function прогонИз(сообщений) {
  const ящик = []
  for (let раз = 0; раз < сообщений; раз += 1) {
    ящик.push({ process: "П1", message: { variant: "тик", fields: {} } })
  }
  return { kind: "run", name: "мерка", seed: 1, seedTo: null, inbox: ящик, expected: [] }
}

/* ═══════════════ 1. витки: единица языка, от нагрузки не зависит ══════════ */

/**
 * Точное число витков интерпретатора на один вызов функции.
 *
 * Двоичный поиск по запасу: при запасе меньше нужного вызов падает с
 * FLANG_RECURSION_LIMIT, при достаточном — возвращает значение. Граница между
 * ними и есть искомое число. Оно ДЕТЕРМИНИРОВАНО: сколько бы ни была занята
 * машина, витков будет столько же, потому что виток — шаг машины, а не время.
 */
function витков(программа, имя, аргументы) {
  const проходит = (запас) => {
    try {
      createRuntime(программа, { maxSteps: запас }).call(имя, аргументы)
      return true
    } catch {
      return false
    }
  }
  let верх = 1
  while (!проходит(верх)) верх *= 2
  let низ = Math.floor(верх / 2)
  while (низ + 1 < верх) {
    const середина = Math.floor((низ + верх) / 2)
    if (проходит(середина)) верх = середина
    else низ = середина
  }
  return верх
}

function меркаВитков() {
  const тихая = parse(кольцо(1, false), "мерка.flang")
  const шумная = parse(кольцо(1, true), "мерка.flang")
  const счёт = { "всего": 0 }
  const тик = { variant: "тик", fields: {} }
  const тихий = витков(тихая, "тихий шаг", [счёт, тик])
  const шумный = витков(шумная, "шумный шаг", [счёт, тик])
  return { тихий, шумный, разница: шумный - тихий }
}

/* ═════════════ 2. планировщик свидетеля: пробеги, доставки, время ═══════════ */

function меркаСвидетеля(процессов, сообщений, повторов) {
  const тихая = parse(кольцо(процессов, false), "мерка.flang")
  const шумная = parse(кольцо(процессов, true), "мерка.flang")

  /* Тихий прогон: 2M пробегов, ни одной отправки. Шумный: те же 2M пробегов
     (M у «П1» и M у «Стока»), но M из них с отправкой. Разница — ровно цена M
     отправок вместе с постройкой описывающего их значения, и делить её на что-то
     ещё было бы враньём: в этой модели отправка И ЕСТЬ построенное значение
     плюс работа планировщика по нему. */
  const тихийПрогон = прогонИз(сообщений * 2)
  const шумныйПрогон = прогонИз(сообщений)
  const настройки = { maxTurns: сообщений * 4 + 16 }

  const тихийИтог = runConcurrent(тихая, тихийПрогон, настройки)
  const шумныйИтог = runConcurrent(шумная, шумныйПрогон, настройки)

  const [тихо, шумно] = минимумПары(
    повторов,
    () => runConcurrent(тихая, тихийПрогон, настройки),
    () => runConcurrent(шумная, шумныйПрогон, настройки),
  )

  /* Отправка считается ОТНОШЕНИЕМ, а не разностью в микросекундах, и это не
     придирка к оформлению. Оба прогона делают ровно 2M пробегов; в шумном
     половина из них с отправкой. Значит отношение времён равно 1 + r/2, где r —
     насколько пробег с отправкой дороже пробега без неё. Отношение двух чисел,
     снятых вперемежку, переживает чужую нагрузку куда лучше их разности:
     помеха умножает оба замера примерно одинаково и из отношения уходит. */
  const доля = шумно / тихо
  return {
    процессов,
    пробеговТихо: тихийИтог.пробегов,
    пробеговШумно: шумныйИтог.пробегов,
    отправок: сообщений,
    мкснаПробег: (тихо * 1000) / тихийИтог.пробегов,
    дорожеСОтправкой: 2 * (доля - 1),
    тихо,
    шумно,
  }
}

/* ═════════════ 3. цена объявления: разбор, типы, печать, память ═══════════ */

function меркаОбъявления(процессов) {
  const источник = кольцо(процессов, false)
  const доРазбора = куча()
  const разобрать = минимум(3, () => parse(источник, "мерка.flang"))
  const программа = parse(источник, "мерка.flang")
  const послеРазбора = куча()

  const беды = checkTypes(программа).diagnostics
  const типы = минимум(3, () => checkTypes(программа))
  const печать = минимум(3, () => emitElixir(программа, { module: "Мерка" }))

  /* Состояния в итоге — по записи на процесс: это и есть то, что планировщик
     обязан держать живым, пока программа работает. */
  const итог = runConcurrent(программа, прогонИз(0), { maxTurns: 16 })
  const послеПрогона = куча()

  return {
    процессов,
    байтИсходника: Buffer.byteLength(источник),
    байтНаПроцессВИсходнике: Buffer.byteLength(источник) / процессов,
    байтНаПроцессВAST: (послеРазбора - доРазбора) / процессов,
    байтНаПроцессВИтоге: (послеПрогона - послеРазбора) / процессов,
    мсРазбор: разобрать,
    мсТипы: типы,
    мсПечать: печать,
    диагностик: беды.length,
    состояний: Object.keys(итог.состояния).length,
  }
}

/* ═══════════ 3½. планировщик в рантайме C: пробег и очередь готовых ═══════ */

/**
 * Кольцо с ПРОГОНОМ в исходнике: планировщику C прогон приезжает данными плана,
 * а не собирается на месте, как у свидетеля (`прогонИз`). Поэтому здесь та же
 * программа, но с объявленным `прогон`.
 */
function кольцоСПрогоном(процессов, сообщений) {
  const строки = кольцо(процессов, false).split("\n")
  строки.push("прогон «мерка»", "  семя 1")
  for (let раз = 0; раз < сообщений; раз += 1) строки.push("  дано «П1» принимает (вариант «тик»)")
  строки.push(`  ожидается «П1» равен (запись «Счёт» с «всего» равным ${сообщений})`, "")
  return строки.join("\n")
}

/**
 * Цена пробега у планировщика в рантайме C, и главное — её зависимость от числа
 * ОБЪЯВЛЕННЫХ процессов.
 *
 * У свидетеля эта зависимость линейна и измерена выше: очередь готовых
 * пересобирается полным перебором на каждом пробеге. В C очередь готовых
 * поддерживается списком, поэтому пробег обязан стоить O(готовых), а не
 * O(объявленных), — и «обязан» здесь проверяется наклоном прямой, а не чтением
 * кода.
 *
 * ── Чем это меряется и почему не тем же, чем свидетель ────────────────────────
 * `process.cpuUsage()` считает время НАШЕГО процесса, а работа идёт в чужом:
 * этим прибором вышел бы ноль. Поэтому здесь настенные часы — и, чтобы они
 * что-то значили, из замера вычитается второй замер той же программы с ящиком
 * из одного сообщения. Разность убирает всё, что не пробег: запуск процесса,
 * разбор запроса, вычисление P начальных состояний, выделение таблиц на P
 * процессов. Берётся минимум из повторов — помеха может замер только удлинить.
 */
function меркаC(процессов, сообщений, запросов, повторов) {
  const cc = findExecutable("cc") ?? findExecutable("gcc")
  if (cc === null) return null
  const каталог = mkdtempSync(join(tmpdir(), "flang-bench-c-"))
  try {
    const собрать = (сколько, куда) => {
      const путь = join(каталог, куда)
      mkdirSync(путь, { recursive: true })
      const программа = parse(кольцоСПрогоном(процессов, сколько), "мерка.flang")
      const напечатано = emitC(программа)
      const исходники = []
      for (const файл of напечатано.files) {
        writeFileSync(join(путь, файл.path), файл.content)
        if (файл.path.endsWith(".c")) исходники.push(файл.path)
      }
      const начало = Date.now()
      execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O2", ...исходники,
                        "-o", "flang_cli", "-lm"], { cwd: путь, stdio: ["ignore", "pipe", "pipe"] })
      return { бинарник: join(путь, "flang_cli"), мсСборки: Date.now() - начало }
    }
    const полный = собрать(сообщений, "full")
    const пустой = собрать(1, "base")
    const вход = `${Array.from({ length: запросов },
      () => JSON.stringify({ run: "мерка", seed: "1", turns: String(сообщений * 4 + 16) })).join("\n")}\n`

    /* Замеры чередуются, как и у свидетеля: помеха видит оба одинаково и из
       разности уходит. */
    let сПолным = Infinity
    let сПустым = Infinity
    const настенно = (что) => {
      const было = process.hrtime.bigint()
      что()
      return Number(process.hrtime.bigint() - было) / 1e6
    }
    for (let раз = 0; раз < повторов; раз += 1) {
      сПолным = Math.min(сПолным, настенно(() =>
        execFileSync(полный.бинарник, { input: вход, stdio: ["pipe", "ignore", "pipe"] })))
      сПустым = Math.min(сПустым, настенно(() =>
        execFileSync(пустой.бинарник, { input: вход, stdio: ["pipe", "ignore", "pipe"] })))
    }
    const пробегов = запросов * (сообщений - 1)
    return {
      процессов,
      мкснаПробег: ((сПолным - сПустым) * 1000) / пробегов,
      мсПолный: сПолным,
      мсПустой: сПустым,
      мсСборки: полный.мсСборки,
      пробегов,
    }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/**
 * Во что обошёлся бы РАБОЧИЙ режим на потоках ОС — и почему проверочный режим
 * сделан кооперативным.
 *
 * Контракт называет два режима: проверочный «одним потоком, чередование по
 * семени» и рабочий «параллельно, сколько даёт среда». Сделан первый; довод
 * «побайтовая сверка с потоками невозможна» верен, но недостаточен — надо ещё
 * знать, СКОЛЬКО стоит второй. Здесь меряются три числа, и все три на той же
 * машине и в тот же момент, что и пробег выше:
 *
 *   • передача работы между двумя потоками (mutex + condvar, туда и обратно) —
 *     это то, что пул платил бы на каждом пробеге, если бы пробеги раздавались;
 *   • взятие незанятого замка — это то, что планировщик платил бы за то, чтобы
 *     просто СТАТЬ потокобезопасным, не раздавая ничего;
 *   • заведение и уборка потока — цена «по потоку на процесс».
 *
 * Ни одно из трёх не берётся из головы и ни одно не берётся из чужих замеров:
 * futex на разных ядрах и в разных виртуалках стоит по-разному, и число из
 * статьи здесь ничего не решило бы.
 *
 * Это НЕ переносимый C99: pthread — POSIX. Поэтому мерка и стоит здесь, рядом с
 * контрактом, а не в рантайме: рантайм обязан собираться где угодно.
 */
const ПОТОКИ_C = `#define _POSIX_C_SOURCE 200809L
#include <pthread.h>
#include <stdio.h>
#include <time.h>

static pthread_mutex_t lock = PTHREAD_MUTEX_INITIALIZER;
static pthread_cond_t ping = PTHREAD_COND_INITIALIZER;
static pthread_cond_t pong = PTHREAD_COND_INITIALIZER;
static long turn = 0;
static long rounds = 200000;

static double now_ns(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return (double)ts.tv_sec * 1e9 + (double)ts.tv_nsec;
}

static void *nothing(void *ignored) { (void)ignored; return NULL; }

static void *worker(void *ignored) {
  long index = 0;
  (void)ignored;
  for (index = 0; index < rounds; index += 1) {
    pthread_mutex_lock(&lock);
    while (turn != 1) { pthread_cond_wait(&ping, &lock); }
    turn = 0;
    pthread_cond_signal(&pong);
    pthread_mutex_unlock(&lock);
  }
  return NULL;
}

int main(void) {
  pthread_t thread;
  long index = 0;
  double start = 0.0, handoff = 0.0, alone = 0.0, creation = 0.0;

  pthread_create(&thread, NULL, worker, NULL);
  start = now_ns();
  for (index = 0; index < rounds; index += 1) {
    pthread_mutex_lock(&lock);
    turn = 1;
    pthread_cond_signal(&ping);
    while (turn != 0) { pthread_cond_wait(&pong, &lock); }
    pthread_mutex_unlock(&lock);
  }
  handoff = (now_ns() - start) / (double)rounds;
  pthread_join(thread, NULL);

  start = now_ns();
  for (index = 0; index < rounds; index += 1) {
    pthread_mutex_lock(&lock);
    turn += 1;
    pthread_mutex_unlock(&lock);
  }
  alone = (now_ns() - start) / (double)rounds;

  start = now_ns();
  for (index = 0; index < 2000; index += 1) {
    pthread_t one;
    pthread_create(&one, NULL, nothing, NULL);
    pthread_join(one, NULL);
  }
  creation = (now_ns() - start) / 2000.0;

  printf("%.0f\\t%.0f\\t%.0f\\n", handoff, alone, creation);
  return 0;
}
`

function меркаПотоков(повторов) {
  const cc = findExecutable("cc") ?? findExecutable("gcc")
  if (cc === null) return null
  const каталог = mkdtempSync(join(tmpdir(), "flang-bench-threads-"))
  try {
    writeFileSync(join(каталог, "потоки.c"), ПОТОКИ_C)
    execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O2", "-pthread",
                      "потоки.c", "-o", "потоки"], { cwd: каталог, stdio: ["ignore", "pipe", "pipe"] })
    let передача = Infinity
    let замок = Infinity
    let заведение = Infinity
    for (let раз = 0; раз < повторов; раз += 1) {
      const [п, з, зав] = execFileSync(join(каталог, "потоки"), { encoding: "utf8" }).trim().split("\t").map(Number)
      передача = Math.min(передача, п)
      замок = Math.min(замок, з)
      заведение = Math.min(заведение, зав)
    }
    return { передача, замок, заведение }
  } catch {
    /* pthread может не собраться (не POSIX, нет -pthread) — это не поломка
       мерки, а отсутствие того, что она мерит. Молчать об этом нельзя, но и
       валить весь отчёт незачем. */
    return null
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

