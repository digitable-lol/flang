/* Наклон прямой «мкс/пробег от числа процессов». Из кода планировщика он
   ожидается ненулевым: очередь готовых пересобирается ПОЛНЫМ перебором
   процессов на каждом пробеге (`порядок.filter(…)` в `runConcurrent`), то есть
   переключение стоит O(P), а не O(1). Наклон — это цена одного процесса в
   одном переключении, и он устойчивее каждого отдельного замера: помеха
   поднимает все точки разом, а прямую наклоняет слабо. */
{
  const n = точки.length
  const сумX = точки.reduce((с, [x]) => с + x, 0)
  const сумY = точки.reduce((с, [, y]) => с + y, 0)
  const сумXY = точки.reduce((с, [x, y]) => с + x * y, 0)
  const сумXX = точки.reduce((с, [x]) => с + x * x, 0)
  const наклон = (n * сумXY - сумX * сумY) / (n * сумXX - сумX * сумX)
  const сдвиг = (сумY - наклон * сумX) / n
  скажи(
    `  прямая: ${сдвиг.toFixed(3)} мкс + ${(наклон * 1000).toFixed(1)} нс на процесс — ` +
      `переключение у эталона стоит O(числа процессов), а не O(1)`,
  )
}
