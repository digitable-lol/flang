/**
 * Программа, у которой глубина рекурсии обработчика задаётся длиной входного
 * списка: `сумма` складывает список НЕ хвостовым вызовом, поэтому каждый
 * элемент — это кадр на машинном стеке.
 *
 * Хвостовая форма здесь не подошла бы вовсе: `emit/c.mjs` превращает хвостовой
 * самовызов в петлю, кадр не растёт, и мерить было бы нечего. Нужен именно тот
 * случай, ради которого стек и заводится, — обработчик, который держит на стеке
 * работу, начатую до вытеснения.
 */
function глубина(длина) {
  const числа = Array.from({ length: длина }, () => 1).join(", ")
  return [
    "модуль «Глубина»", "",
    "объект «Счёт»", "  «всего»: число", "",
    "тип «Весть»", "  вариант «сложить» содержит «числа»: список числа", "",
    "объект «Отклик»", "  «состояние»: «Счёт»", "  «действия»: список «Действие»", "",
    "процесс «Глубокий»", "  состояние «Счёт»", "  начинает с «нуль»",
    "  принимает «Весть»", "  обрабатывает «шаг»", "",
    "тотальная функция «нуль»", "  возвращает «Счёт»",
    "  запись «Счёт» с «всего» равным 0", "",
    "тотальная функция «сумма»", "  принимает элементы: список числа", "  возвращает число",
    "  разбор элементы",
    "    случай пусто", "      то 0",
    "    случай голова и хвост", "      то голова плюс «сумма» от хвост", "",
    "тотальная функция «шаг»", "  принимает счёт: «Счёт», весть: «Весть»", "  возвращает «Отклик»",
    "  разбор весть",
    "    случай вариант «сложить» с «числа» как набор",
    "      пусть итог равно «сумма» от набор",
    "      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным итог) и «действия» равным []",
    "",
    "прогон «глубина»", "  семя 1",
    `  дано «Глубокий» принимает (вариант «сложить» с «числа» равным [${числа}])`,
    `  ожидается «Глубокий» равен (запись «Счёт» с «всего» равным ${длина})`, "",
  ].join("\n")
}

/**
 * Сколько машинного стека стоит один виток глубины у напечатанного C.
 *
 * Прибор — двоичный поиск по `ulimit -s`, и выбран он по той же причине, по
 * которой витки ищутся двоичным поиском по запасу: это НЕ измерение, а поиск
 * границы. Наименьший предел стека, на котором программа ещё доходит до конца,
 * — точное число, оно не зависит ни от нагрузки, ни от повторов, и повторяется
 * до килобайта.
 *
 * Меряется НАКЛОН по нескольким глубинам, а не одна точка: постоянная часть
 * (запуск libc, разбор запроса, кадры планировщика) в наклон не входит, а
 * именно она и мешала бы сравнивать. Наклон — это цена одного кадра
 * напечатанной функции, и он же — то, что придётся умножать на объявленную
 * глубину, когда стек станет принадлежать процессу.
 */
function меркаСтека(глубины) {
  const cc = findExecutable("cc") ?? findExecutable("gcc")
  if (cc === null) return null
  const каталог = mkdtempSync(join(tmpdir(), "flang-bench-стек-"))
  try {
    const точки = []
    for (const длина of глубины) {
      const путь = join(каталог, `d${длина}`)
      mkdirSync(путь, { recursive: true })
      const напечатано = emitC(parse(глубина(длина), "глубина.flang"))
      const исходники = []
      for (const файл of напечатано.files) {
        writeFileSync(join(путь, файл.path), файл.content)
        if (файл.path.endsWith(".c")) исходники.push(файл.path)
      }
      execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O2", ...исходники,
                        "-o", "flang_cli", "-lm"], { cwd: путь, stdio: ["ignore", "pipe", "pipe"] })
      const вход = `${JSON.stringify({ run: "глубина", seed: "1" })}\n`
      const доходит = (киб) => {
        const р = spawnSync("/bin/sh", ["-c", `ulimit -s ${киб} 2>/dev/null || exit 99; exec ./flang_cli`],
                            { cwd: путь, input: вход, encoding: "utf8" })
        return р.status === 0 && typeof р.stdout === "string" && р.stdout.includes('"исход"')
      }
      /* Верхняя граница ищется удвоением: угадывать её числом значило бы
         подгонять прибор под ожидаемый ответ. */
      let верх = 16
      while (верх <= 65536 && !доходит(верх)) верх *= 2
      if (верх > 65536) return null
      let низ = верх === 16 ? 0 : верх / 2
      while (верх - низ > 1) {
        const середина = Math.floor((низ + верх) / 2)
        if (доходит(середина)) верх = середина
        else низ = середина
      }
      точки.push([длина, верх])
    }
    return точки
  } catch {
    return null
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Наклон и сдвиг прямой по точкам `[x, y]` — обычный МНК. */
function прямая(точки) {
  const n = точки.length
  const сумX = точки.reduce((с, [x]) => с + x, 0)
  const сумY = точки.reduce((с, [, y]) => с + y, 0)
  const сумXY = точки.reduce((с, [x, y]) => с + x * y, 0)
  const сумXX = точки.reduce((с, [x]) => с + x * x, 0)
  const наклон = (n * сумXY - сумX * сумY) / (n * сумXX - сумX * сумX)
  return { наклон, сдвиг: (сумY - наклон * сумX) / n }
}

