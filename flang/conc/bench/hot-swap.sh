#!/bin/bash
# ПРОГОН: ГОРЯЧАЯ ЗАМЕНА ОБРАБОТЧИКА НА ЖИВОМ УЗЛЕ. Не пример и не проба —
# настоящий узел, поднятый хозяином, которому между двумя письмами велят
# подменить обработчик процесса.
#
# Вопрос один: доезжает ли веление замены от `flang/conc/hotswap-node.flang` до
# планировщика и исполняется ли оно, не перезапуская процесс. Ответ виден в
# состоянии «Счётчика»:
#
#   старый вид  «замерить N» прибавляет N;
#   новый вид   «замерить N» прибавляет N вдвое.
#
# Порядок нарочно такой, чтобы обе половины ответа были ВИДНЫ:
#
#   0,0 с  замерить 2  старым обработчиком      → всего 2
#   0,8 с  просят заменить, предел витков 0     → ОТКАЗ «граница витков не названа»
#   1,6 с  просят заменить, предел 8, перенос   → ПРИНЯТО
#   2,4 с  замерить 3  новым обработчиком       → всего 2 + 3·2 = 8
#   3,2 с  замерить 4  новым обработчиком       → всего 8 + 4·2 = 16
#
# Что процесс НЕ перезапускался, видно двумя независимыми способами: «всего»
# продолжилось с 2, а не с нуля (после перезапуска вышло бы 14, а не 16), и в
# журнале нет ни записи «отказ», ни записи «надзор».
#
# Запуск:  bash flang/conc/bench/hot-swap.sh
#          FLANG=<двоичный>  — если брать не `bootstrap/flang` дерева.
#
# Цель здесь одна — `js`: ключ `--заменить-позже` есть только у хозяина
# `flang/conc/bin/node.js`. Остальные семь хозяев вид процесса в таблицу кладут,
# но просьбы о замене не принимают; названо в `RESILIENCE.md`, шаг Е2.
set -u
export LC_ALL=C.UTF-8
KOREN=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
RAB=$(mktemp -d -p /srv/tmp goryachaya-zamena-XXXXXX)

echo "== печать узла в цель js"
"$FLANG" emit "$KOREN/flang/conc/node-benchmark.flang" --target js --out "$RAB/uzel" >"$RAB/pechat.log" 2>&1
kod=$?
if [ $kod -ne 0 ]; then echo "печать отказала, код $kod"; tail -20 "$RAB/pechat.log"; exit 1; fi
cp "$KOREN/flang/conc/bin/node.js" "$RAB/uzel/"
# Без этого Node прочтёт напечатанный `.js` как модуль старого вида и споткнётся
# на первом же `export`.
printf '{"type":"module"}\n' >"$RAB/uzel/package.json"

cat >"$RAB/uzel/plan.json" <<'JSON'
{"процессы":[{"имя":"Счётчик","начальное":"Начальный счёт","обработчик":"Обработчик счёта","ящик":null},
             {"имя":"Учётчик","начальное":"Начальные записи","обработчик":"Обработчик учёта","ящик":null}]}
JSON

SRAZU='[{"кому":"Счётчик","что":["в","замерить",{"сколько":["ч",2]}]}]'
POZZHE='[{"через":2400,"кому":"Счётчик","что":["в","замерить",{"сколько":["ч",3]}]},
         {"через":3200,"кому":"Счётчик","что":["в","замерить",{"сколько":["ч",4]}]}]'
ZAMENY='[{"через":800,"кого":"Счётчик","вид":"Обработчик счёта вдвое","предел":0,"перенос":"Перенос счёта"},
         {"через":1600,"кого":"Счётчик","вид":"Обработчик счёта вдвое","предел":8,"перенос":"Перенос счёта"}]'

echo "== узел «счёт» поднят, жить 5 с"
( cd "$RAB/uzel" && exec env LC_ALL=C.UTF-8 node node.js \
    --я счёт --хэш 0123456789abcdef \
    --план-файл plan.json --размещение '{"Счётчик":"счёт","Учётчик":"счёт"}' \
    --вбросить "$SRAZU" --вбросить-позже "$POZZHE" --заменить-позже "$ZAMENY" \
    --срок 2000 --пульс 200 --жить 5 ) >"$RAB/uzel.jsonl" 2>"$RAB/uzel.err"
kod=$?
echo "код возврата узла: $kod"
[ -s "$RAB/uzel.err" ] && { echo "-- stderr --"; cat "$RAB/uzel.err"; }
echo
echo "════ журнал узла ════"
cat "$RAB/uzel.jsonl"
echo
echo "════ приговор ════"
itog=$(grep '"в":"конец"' "$RAB/uzel.jsonl" | tail -1)
case "$itog" in
  *'"всего":["ч",16]'*) echo "замена доехала: всего 16 — новый вид считает вдвое" ;;
  *'"всего":["ч",14]'*) echo "ОТКАЗ: всего 14 — процесс перезапустился, состояние потеряно"; exit 1 ;;
  *'"всего":["ч",9]'*)  echo "ОТКАЗ: всего 9 — замена не доехала, считает старый вид"; exit 1 ;;
  *) echo "ОТКАЗ: итог не узнан: $itog"; exit 1 ;;
esac
grep -q '"в":"замена отвергнута"' "$RAB/uzel.jsonl" || { echo "ОТКАЗ: отвергнутой просьбы в журнале нет"; exit 1; }
grep -q '"в":"отказ"' "$RAB/uzel.jsonl" && { echo "ОТКАЗ: в журнале есть падение процесса"; exit 1; }
grep -q '"в":"надзор"' "$RAB/uzel.jsonl" && { echo "ОТКАЗ: в журнале есть работа надзора — процесс перезапускали"; exit 1; }
echo "процесс не перезапускался: ни «отказ», ни «надзор» в журнале не встретились"
rm -rf "$RAB"
