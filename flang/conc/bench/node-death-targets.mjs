/**
 * СМЕРТЬ СОСЕДНЕГО УЗЛА НА ВСЕХ ВОСЬМИ ЦЕЛЯХ ПЕЧАТИ — прогон, не проверка.
 *
 * Печатает таблицу и число. Ничего не утверждает и никого не гоняет: смотреть
 * на итог человеку.
 *
 * ── Что здесь меряется, и почему именно это ─────────────────────────────────
 *
 * `flang/conc/bench/node-death.sh` показывает полный ответ — что работа ПОСЛЕ
 * смерти соседа снова доходит, — но умеет только те две цели, где хозяина не
 * надо собирать, и опирается на ключ `--вбросить-позже`, который есть у
 * хозяев python и js. Остальным шести письмо по часам подавать нечем.
 *
 * Поэтому здесь меряется то, что видно БЕЗ новой работы и одинаково на всех
 * восьми: сосед убит по-настоящему (SIGKILL), и выживший узел
 *
 *   1. доложил о потере связи;
 *   2. дал надзору РЕШИТЬ — в журнале «решено», с именем надзора и стратегией;
 *   3. ПОДХВАТИЛ чужой процесс: к концу прогона «Учётчик» стоит в состояниях
 *      выжившего узла, хотя размещением он отдан мёртвому соседу.
 *
 * Третий пункт — не запись в журнале, а наблюдаемое состояние: до этой работы
 * его там не было вовсе.
 *
 * ── Оснастка чужая ──────────────────────────────────────────────────────────
 *
 * Сборка и подъём берутся из `flang/test/uzel-osnastka.mjs` — того же файла,
 * которым пользуются прогоны узла. Своей копии рецептов здесь нет намеренно:
 * разойдись они — и этот прогон мерил бы другой узел.
 *
 * Запуск: node flang/conc/bench/node-death-targets.mjs [имя цели ...]
 */
import { rmSync } from "node:fs"
import { createHash } from "node:crypto"

import { findExecutable } from "../../test/toolchain-guard.mjs"
import { рабочийКаталог } from "../../test/tempdir.mjs"
import {
  ОПОРА,
  ЦЕЛИ,
  напечатаннаяПрограмма,
  новаяЗапись,
  поднятьУзел,
  собратьУзел,
} from "../../test/uzel-osnastka.mjs"

const ПРОЦЕССЫ = [
  { имя: "Счётчик", начальное: "Начальный счёт", обработчик: "Обработчик счёта", ящик: null },
  { имя: "Учётчик", начальное: "Начальные записи", обработчик: "Обработчик учёта", ящик: null },
]

/** Дерево надзора — слово в слово как объявлено в `examples/distributed.flang`. */
const ПЛАНЫ = {
  "plan.json": {
    процессы: ПРОЦЕССЫ,
    надзоры: [
      { имя: "Связь", порог: 2, окно: 5000, иначе: "передать выше",
        процессы: [{ кто: "Учётчик", стратегия: "перезапустить" }], надзоры: [] },
      { имя: "Цех", порог: 1, окно: 5000, иначе: "передать выше",
        процессы: [{ кто: "Счётчик", стратегия: "перезапустить" }],
        надзоры: [{ кто: "Связь", стратегия: "передать выше" }] },
    ],
  },
}

const ВБРОС = JSON.stringify([{ кому: "Счётчик", что: ["в", "замерить", { сколько: ["ч", 2] }] }])

const хотим = process.argv.slice(2)
const все = [ОПОРА, ...ЦЕЛИ]
const очередь = хотим.length === 0 ? все : все.filter((ц) => хотим.includes(ц.имя))

const строки = []

for (const цель of очередь) {
  const чем = цель.ищем.map((это) => findExecutable(это)).find((это) => это !== null && это !== undefined)
  const чемОпора = ОПОРА.ищем.map((это) => findExecutable(это)).find((это) => это !== null && это !== undefined)
  if (чем === undefined || чемОпора === undefined) {
    строки.push({ цель: цель.имя, итог: "тулчейна нет" })
    continue
  }

  const каталог = рабочийКаталог(`smert-${цель.имя}`)
  const каталогОпоры = рабочийКаталог(`smert-opora-${цель.имя}`)
  const узлы = []
  try {
    собратьУзел(каталог, цель, ПЛАНЫ)
    собратьУзел(каталогОпоры, ОПОРА, ПЛАНЫ)
    const хэш = createHash("sha256").update(напечатаннаяПрограмма(каталог), "utf8").digest("hex")

    /* Умирать будет ОПОРА: она несёт «Учётчика», а смотрим мы на узел цели. */
    const опора = поднятьУзел(ОПОРА, чемОпора, каталогОпоры, [
      "--я", "учёт", "--слушать", "127.0.0.1:0", "--хэш", хэш, "--план-файл", "plan.json",
      "--размещение", JSON.stringify({ "Счётчик": "счёт", "Учётчик": "учёт" }),
      "--срок", "2000", "--пульс", "200", "--жить", "20",
    ], узлы)
    const поднят = await новаяЗапись(опора.записи, (з) => з.в === "поднят", 30_000)

    const новый = поднятьУзел(цель, чем, каталог, [
      "--я", "счёт", "--слушать", "127.0.0.1:0", "--хэш", хэш, "--план-файл", "plan.json",
      "--размещение", JSON.stringify({
        "Счётчик": "счёт", "Учётчик": "учёт", звонить: { "учёт": `127.0.0.1:${поднят.порт}` },
      }),
      "--вбросить", ВБРОС, "--срок", "2000", "--пульс", "200", "--жить", "12",
    ], узлы)
    await новаяЗапись(новый.записи, (з) => з.в === "связь" && з.что === "заведена", 30_000)

    await new Promise((готово) => setTimeout(готово, 2000))
    опора.процесс.kill("SIGKILL")   // НАСТОЯЩАЯ смерть, а не прощание
    const убит = опора.процесс.pid

    const потеря = await новаяЗапись(новый.записи, (з) => з.в === "связь" && з.что === "потеряна", 15_000)
    const решено = await новаяЗапись(
      новый.записи, (з) => з.в === "надзор" && з.что === "решено" && з.кто === "Учётчик", 15_000)
    await новаяЗапись(новый.записи, (з) => з.в === "надзор" && з.что === "поднят" && з.кто === "Учётчик", 15_000)
    const конец = await новаяЗапись(новый.записи, (з) => з.в === "конец", 30_000)

    строки.push({
      цель: цель.имя,
      убит,
      почему: потеря.почему,
      надзор: `${решено.надзор}/${решено.стратегия}`,
      подхвачен: конец.состояния["Учётчик"] !== undefined,
      итог: конец.состояния["Учётчик"] !== undefined ? "подхвачен" : "НЕ подхвачен",
    })
  } catch (беда) {
    строки.push({ цель: цель.имя, итог: `ОТКАЗ: ${беда.message.split("\n")[0]}` })
  } finally {
    for (const п of узлы) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }
    rmSync(каталог, { recursive: true, force: true })
    rmSync(каталогОпоры, { recursive: true, force: true })
  }
}

console.log("")
console.log("цель      pid убитого  почему потеряна связь            надзор решил        чужой процесс")
for (const с of строки) {
  console.log(
    `${(с.цель ?? "").padEnd(9)} ${String(с.убит ?? "—").padEnd(12)} ${(с.почему ?? "—").padEnd(32)}` +
    ` ${(с.надзор ?? "—").padEnd(19)} ${с.итог}`,
  )
}
const сошлось = строки.filter((с) => с.подхвачен === true).map((с) => с.цель)
console.log("")
console.log(`НАДЗОР ПЕРЕЖИВАЕТ СМЕРТЬ СОСЕДНЕГО УЗЛА НА ${сошлось.length} ЦЕЛЯХ ИЗ 8: ${сошлось.join(", ")}`)
process.exit(сошлось.length === очередь.length ? 0 : 1)
