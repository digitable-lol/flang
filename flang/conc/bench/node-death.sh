#!/bin/bash
# ПРОГОН: СМЕРТЬ СОСЕДНЕГО УЗЛА. Не пример и не проба — настоящие два процесса,
# настоящий сокет, настоящий SIGKILL.
#
# Вопрос один: переживает ли дерево процессов под надзором смерть узла, на
# котором жила часть работы. Ответ виден числом в состоянии «Счётчика»:
#
#   «всего»        растёт всегда — замеры приходят своему процессу;
#   «подтверждено» растёт только тогда, когда доклад ДОШЁЛ до «Учётчика».
#
# Убиваем узел «учёт». Письма «Счётчику» приходят ПОСЛЕ смерти (по часам, ключ
# `--вбросить-позже`), и разница видна:
#
#   без надзора  подтверждено стоит: доклады уходят в никуда, «Учётчик» на узле
#                «счёт» так и числится живым представителем мёртвого узла;
#   с надзором   пропажа узла доезжает до объявленного надзора «Связь», тот
#                велит «перезапустить», и «Учётчик» ПОДХВАТЫВАЕТСЯ узлом «счёт»
#                — доклады снова доходят, подтверждено растёт.
#
# Четыре случая, и все четыре различаются наблюдаемо:
#
#   bez        улика ДО: то же убийство, надзор не объявлен;
#   nadzor     надзор объявлен и обязан сработать;
#   tiho       ПОДДЕЛКА: узел жив, но молчит МЕНЬШЕ срока (SIGSTOP/SIGCONT).
#              Объявлять его мёртвым раньше срока нельзя;
#   dolgo      тот же SIGSTOP, но дольше срока: тут объявить обязаны.
#
# Запуск:  bash flang/conc/bench/node-death.sh [случай ...]
#          без доводов — все четыре.
#
# Свои процессы снимаются ПОИМЁННО по номеру и только после сверки рабочего
# каталога: `pkill` по имени здесь запрещён, машина общая.
#
# Имена переменных и функций латиницей не по вкусу, а по устройству: имя
# переменной оболочки обязано быть из [A-Za-z_0-9], и кириллическое присваивание
# bash читает как команду.
set -u

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
# Цели без сборки: хозяин кладётся рядом с напечатанным и запускается как есть.
# Остальные шесть целей требуют тулчейна и своей сборки — их прогоняет
# `flang/test/uzel-celi.test.mjs` со своей оснасткой, и повторять её здесь не
# надо: решения у всех восьми одни и те же, напечатанные.
CEL=${CEL:-python}
case "$CEL" in
  python) HOZ=node.py; RUN=(python3 -B node.py) ;;
  js)     HOZ=node.js; RUN=(node node.js) ;;
  *) echo "цель «$CEL» этим прогоном не поднимается: нужен тулчейн и сборка"; exit 2 ;;
esac
SROK=${SROK:-2000}
PULS=${PULS:-200}
HESH=${HESH:-0123456789abcdef}

RAB=$(mktemp -d -p /srv/tmp smert-uzla-XXXXXX)
# Ссылки раскрываются ЗДЕСЬ, потому что ниже этот путь сличается с ответом
# `readlink -f /proc/<номер>/cwd`, а тот раскрыт всегда. Слева раскрыто, справа
# нет — совпадений не бывает ни одного, и уборщик молча оставляет узлы живыми:
# ни строки вывода, ни ненулевого кода. `/srv/tmp` на этой машине ссылкой не
# является, поэтому здесь этого не видно; на машине, где временный каталог
# лежит за ссылкой, не работает НИКОГДА. Проверено прогоном на паре входов,
# различающихся только ссылкой: без неё узел убит, за ней — жив.
RAB=$(readlink -f "$RAB")
MOI=()

pribrat() {
  local p
  for p in "${MOI[@]:-}"; do
    [ -n "$p" ] || continue
    case "$(readlink -f "/proc/$p/cwd" 2>/dev/null)" in
      "$RAB"/*) kill -KILL "$p" 2>/dev/null ;;
    esac
  done
  MOI=()
}
trap 'pribrat' EXIT

echo "== печать узла в цель $CEL"
"$ROOT/bootstrap/flang" emit "$ROOT/flang/conc/node-benchmark.flang" --target "$CEL" --out "$RAB/uchyot" >"$RAB/pechat.log" 2>&1
kod=$?
if [ $kod -ne 0 ]; then echo "печать отказала, код $kod"; tail -20 "$RAB/pechat.log"; exit 1; fi
cp -r "$RAB/uchyot" "$RAB/schyot"
cp "$ROOT/flang/conc/bin/$HOZ" "$RAB/uchyot/"
cp "$ROOT/flang/conc/bin/$HOZ" "$RAB/schyot/"
# Без этого Node прочтёт напечатанный `.js` как модуль старого вида и споткнётся
# на первом же `export`.
if [ "$CEL" = js ]; then
  printf '{"type":"module"}\n' >"$RAB/uchyot/package.json"
  printf '{"type":"module"}\n' >"$RAB/schyot/package.json"
fi

# Дерево надзора — данные, слово в слово как объявлено в
# `flang/conc/examples/distributed.flang`: «Связь» ведёт «Учётчика» с
# перезапуском, «Цех» ведёт «Счётчика» и передаёт «Связь» выше.
cat >"$RAB/plan.json" <<'JSON'
{"процессы":[{"имя":"Счётчик","начальное":"Начальный счёт","обработчик":"Обработчик счёта","ящик":null},
             {"имя":"Учётчик","начальное":"Начальные записи","обработчик":"Обработчик учёта","ящик":null}],
 "надзоры":[{"имя":"Связь","порог":2,"окно":5000,"иначе":"передать выше",
             "процессы":[{"кто":"Учётчик","стратегия":"перезапустить"}],"надзоры":[]},
            {"имя":"Цех","порог":1,"окно":5000,"иначе":"передать выше",
             "процессы":[{"кто":"Счётчик","стратегия":"перезапустить"}],
             "надзоры":[{"кто":"Связь","стратегия":"передать выше"}]}]}
JSON
cat >"$RAB/plan-bez.json" <<'JSON'
{"процессы":[{"имя":"Счётчик","начальное":"Начальный счёт","обработчик":"Обработчик счёта","ящик":null},
             {"имя":"Учётчик","начальное":"Начальные записи","обработчик":"Обработчик учёта","ящик":null}]}
JSON
cp "$RAB/plan.json" "$RAB/plan-bez.json" "$RAB/uchyot/"
cp "$RAB/plan.json" "$RAB/plan-bez.json" "$RAB/schyot/"

# Один замер сразу и два ПОСЛЕ смерти соседа.
POZZHE='[{"через":6000,"кому":"Счётчик","что":["в","замерить",{"сколько":["ч",5]}]},
         {"через":7000,"кому":"Счётчик","что":["в","замерить",{"сколько":["ч",6]}]}]'
SRAZU='[{"кому":"Счётчик","что":["в","замерить",{"сколько":["ч",2]}]}]'

# Образец читается grep -E: пробел после двоеточия печатает python, а js — нет,
# и прогон обязан быть одним на обе цели.
zhdat() { # файл, образец (ERE), секунд
  local kray=$((SECONDS + $3))
  while [ $SECONDS -lt "$kray" ]; do
    grep -Eq "$2" "$1" 2>/dev/null && return 0
    sleep 0.1
  done
  return 1
}

sluchay() { # имя, план, удар
  local imya=$1 plan=$2 udar=$3
  echo
  echo "════ случай «$imya»: план $plan, удар «$udar» ════"
  local ju="$RAB/$imya-uchyot.jsonl" js="$RAB/$imya-schyot.jsonl"
  : >"$ju"; : >"$js"

  ( cd "$RAB/uchyot" && exec env LC_ALL=C.UTF-8 PYTHONIOENCODING=utf-8 \
      "${RUN[@]}" --я учёт --слушать 127.0.0.1:0 --хэш "$HESH" \
      --план-файл "$plan" --размещение '{"Счётчик":"счёт","Учётчик":"учёт"}' \
      --срок "$SROK" --пульс "$PULS" --жить 16 >"$ju" 2>"$RAB/$imya-uchyot.err" ) &
  local pu=$!
  MOI+=("$pu")
  zhdat "$ju" '"в": *"поднят"' 20 || { echo "учёт не поднялся"; cat "$RAB/$imya-uchyot.err"; return 1; }
  local port; port=$(grep -o '"порт": *[0-9]*' "$ju" | tail -1 | grep -o '[0-9]*$')
  # `exec` выше означает, что pid подоболочки И ЕСТЬ pid узла — снимать будем
  # именно его, а не угадывать по имени.
  echo "учёт поднят: pid $pu, порт $port, cwd $(readlink -f "/proc/$pu/cwd")"

  ( cd "$RAB/schyot" && exec env LC_ALL=C.UTF-8 PYTHONIOENCODING=utf-8 \
      "${RUN[@]}" --я счёт --слушать 127.0.0.1:0 --хэш "$HESH" \
      --план-файл "$plan" \
      --размещение "{\"Счётчик\":\"счёт\",\"Учётчик\":\"учёт\",\"звонить\":{\"учёт\":\"127.0.0.1:$port\"}}" \
      --вбросить "$SRAZU" --вбросить-позже "$POZZHE" \
      --срок "$SROK" --пульс "$PULS" --жить 14 >"$js" 2>"$RAB/$imya-schyot.err" ) &
  local ps=$!
  MOI+=("$ps")
  zhdat "$js" '"что": *"заведена"' 20 || { echo "связь не завелась"; cat "$RAB/$imya-schyot.err"; return 1; }
  echo "счёт поднят: pid $ps, связь заведена"

  sleep 2
  case "$udar" in
    ubit)
      echo "→ SIGKILL узлу «учёт», pid $pu"
      kill -KILL "$pu" ;;
    tiho)
      echo "→ SIGSTOP узлу «учёт» на 1000 мс при сроке $SROK мс"
      kill -STOP "$pu"; sleep 1; kill -CONT "$pu" ;;
    dolgo)
      echo "→ SIGSTOP узлу «учёт» на 4000 мс при сроке $SROK мс"
      kill -STOP "$pu"; sleep 4; kill -CONT "$pu" ;;
  esac

  wait "$ps" 2>/dev/null
  local kods=$?
  echo "счёт завершился, код возврата $kods"
  # Ждём и «учёта»: если он пережил удар, его состояние — вторая половина
  # ответа. Ждать безопасно, свой срок жизни у него на две секунды длиннее.
  wait "$pu" 2>/dev/null
  local kodu=$?
  echo "учёт завершился, код возврата $kodu"

  echo "── журнал узла «счёт»: связь, надзор, потери, конец ──"
  # `uniq -c` не для красоты: после смерти соседа хозяин звонит заново каждым
  # витком круга без паузы, и одна и та же строка «сокет прибран» повторяется
  # десятками. Это отдельный изъян слоя связи («Звонок не удался» при
  # состоявшемся знакомстве не ставит «Позвонить снова»), он назван в отчёте и
  # здесь только сворачивается, а не прячется — число повторов видно.
  grep -E '"в": *("связь"|"надзор"|"потеря"|"конец")' "$js" | uniq -c || echo "  (пусто)"
  echo "── чем кончил узел «учёт» ──"
  grep -E '"в": *"конец"' "$ju" || echo "  узел «учёт» до конца не дожил"
  if [ -s "$RAB/$imya-schyot.err" ]; then echo "── stderr счёта ──"; tail -5 "$RAB/$imya-schyot.err"; fi
}

VSE=(bez nadzor tiho dolgo)
HOTIM=("$@")
[ ${#HOTIM[@]} -eq 0 ] && HOTIM=("${VSE[@]}")

for i in "${HOTIM[@]}"; do
  case "$i" in
    bez)    sluchay bez    plan-bez.json ubit ;;
    nadzor) sluchay nadzor plan.json     ubit ;;
    tiho)   sluchay tiho   plan.json     tiho ;;
    dolgo)  sluchay dolgo  plan.json     dolgo ;;
    *) echo "неизвестный случай «$i»"; exit 2 ;;
  esac
done

echo
echo "каталог прогона: $RAB"
