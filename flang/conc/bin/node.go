// ── граница значений ───────────────────────────────────────────────────────

func поле(значение rt.Value, имя string) rt.Value {
	for _, п := range значение.Fields {
		if п.Name == имя {
			return п.Value
		}
	}
	return rt.Nothing()
}

func сказать(запись map[string]any) {
	строка, _ := json.Marshal(запись)
	fmt.Fprintln(os.Stdout, string(строка)) // МИР
}

// часы — единственное чтение часов во всём файле.
func часы() float64 { return float64(time.Now().UnixMilli()) } // МИР

// ── провод: те же метки, что у узла на JavaScript ──────────────────────────
// Перевод, а не решение: правило «у каждого значения метка одной буквой» живёт
// в `flang/conc/distributed.mjs`, и разойтись с ним нельзя.

func закодировать(значение rt.Value) any {
	switch значение.Tag {
	case rt.TagNothing:
		return []any{"н"}
	case rt.TagFlag:
		return []any{"п", значение.Flag}
	case rt.TagString:
		return []any{"с", значение.Str}
	case rt.TagNumber:
		ч := значение.Num
		switch {
		case math.IsNaN(ч):
			return []any{"ч", "NaN"}
		case math.IsInf(ч, 1):
			return []any{"ч", "+∞"}
		case math.IsInf(ч, -1):
			return []any{"ч", "-∞"}
		}
		return []any{"ч", ч}
	case rt.TagList:
		элементы := make([]any, 0, len(значение.List))
		for _, э := range значение.List {
			элементы = append(элементы, закодировать(э))
		}
		return []any{"л", элементы}
	case rt.TagRecord:
		return []any{"з", поляНаружу(значение)}
	case rt.TagVariant:
		return []any{"в", значение.Str, поляНаружу(значение)}
	}
	panic("нечего кодировать")
}

func поляНаружу(значение rt.Value) map[string]any {
	поля := map[string]any{}
	for _, п := range значение.Fields {
		поля[п.Name] = закодировать(п.Value)
	}
	return поля
}

func раскодировать(код any) rt.Value {
	кусок, годно := код.([]any)
	if !годно || len(кусок) == 0 {
		return rt.Nothing()
	}
	метка, _ := кусок[0].(string)
	switch метка {
	case "н":
		return rt.Nothing()
	case "п":
		признак, _ := кусок[1].(bool)
		return rt.Flag(признак)
	case "с":
		строка, _ := кусок[1].(string)
		return rt.Text(строка)
	case "ч":
		switch ч := кусок[1].(type) {
		case float64:
			return rt.Number(ч)
		case string:
			switch ч {
			case "NaN":
				return rt.Number(math.NaN())
			case "+∞":
				return rt.Number(math.Inf(1))
			case "-∞":
				return rt.Number(math.Inf(-1))
			}
		}
		return rt.Number(0)
	case "л":
		сырые, _ := кусок[1].([]any)
		элементы := make([]rt.Value, 0, len(сырые))
		for _, э := range сырые {
			элементы = append(элементы, раскодировать(э))
		}
		return rt.List(элементы)
	case "з":
		return rt.Record(поляВнутрь(кусок[1]))
	case "в":
		имя, _ := кусок[1].(string)
		var сыро any
		if len(кусок) > 2 {
			сыро = кусок[2]
		}
		return rt.Variant(имя, поляВнутрь(сыро))
	}
	return rt.Nothing()
}

func поляВнутрь(сыро any) []rt.Field {
	словарь, _ := сыро.(map[string]any)
	поля := make([]rt.Field, 0, len(словарь))
	for имя, значение := range словарь {
		поля = append(поля, rt.Field{Name: имя, Value: раскодировать(значение)})
	}
	return поля
}

// случайное — mulberry32, тот же генератор, что у свидетеля. Это не мир: на
// входе число, на выходе число.
type жребий struct{ состояние uint32 }

func (ж *жребий) дальше() float64 {
	ж.состояние += 0x6D2B79F5
	т := ж.состояние
	т = (т ^ (т >> 15)) * (т | 1)
	т ^= т + (т^(т>>7))*(т|61)
	return float64((т^(т>>14))&0xFFFFFFFF) / 4294967296.0
}

