// событиеПровода — одна очередь на всё, что приезжает из сети: принятое
// соединение, кусок байтов, конец. Одна, потому что ПОРЯДОК этих событий
// наблюдаем, а две очереди порядок между собой не держат.
type событиеПровода struct {
	канал      *канал
	что        string // "принято" | "байты" | "конец"
	кусок      string
	почему     string
	соединение net.Conn
}

type узелFlang struct {
	имя, хэш           string
	срок, пульс, пауза int
	ctx                *rt.Ctx
	узел               rt.Value
	состояния          map[string]rt.Value
	каналы             map[string]*канал
	порядок            []string
	план               планУзла
	жребий             жребий
	билет              int
	грузы              map[int]rt.Value
	таймеры            []таймер
	последнийКадр      map[string]any
	дерево             rt.Value
	работает           bool
	вход               chan событиеПровода
	слушатель          net.Listener
}

type таймер struct {
	когда float64
	кому  string
	билет float64
}

type процессПлана struct {
	Имя        string `json:"имя"`
	Начальное  string `json:"начальное"`
	Обработчик string `json:"обработчик"`
	Ящик       *int   `json:"ящик"`
}

type связьПлана struct {
	Кто       string `json:"кто"`
	Стратегия string `json:"стратегия"`
}

type надзорПлана struct {
	Имя      string       `json:"имя"`
	Порог    float64      `json:"порог"`
	Окно     float64      `json:"окно"`
	Иначе    string       `json:"иначе"`
	Процессы []связьПлана `json:"процессы"`
	Надзоры  []связьПлана `json:"надзоры"`
}

type планУзла struct {
	Процессы []процессПлана `json:"процессы"`
	Надзоры  []надзорПлана  `json:"надзоры"`
}

func позвать(у *узелFlang, имя string, доводы ...rt.Value) rt.Value {
	значение, беда := prog.Call(у.ctx, имя, доводы)
	if беда != nil {
		panic(fmt.Sprintf("эталон отказал на «%s»: %v", имя, беда))
	}
	return значение
}

func вариант(имя string, поля ...rt.Field) rt.Value {
	return rt.Variant(имя, поля)
}

func полеЗн(имя string, значение rt.Value) rt.Field {
	return rt.Field{Name: имя, Value: значение}
}

func завести(имя string, план планУзла, размещение map[string]string, звонить map[string]string,
	хэш string, срок, пульс, пауза, семя int) *узелFlang {
	у := &узелFlang{
		имя: имя, хэш: хэш, срок: срок, пульс: пульс, пауза: пауза,
		ctx: prog.NewContext(), состояния: map[string]rt.Value{},
		каналы: map[string]*канал{}, план: план, жребий: жребий{состояние: uint32(семя)},
		грузы: map[int]rt.Value{}, работает: true,
		вход: make(chan событиеПровода, 256),
	}
	процессы := make([]rt.Value, 0, len(план.Процессы))
	for _, п := range план.Процессы {
		где := размещение[п.Имя]
		свой := где == имя
		накаком := ""
		if !свой {
			накаком = где
		}
		потолок := 0.0
		if п.Ящик != nil {
			потолок = float64(*п.Ящик)
		}
		процессы = append(процессы, позвать(у, "Процесс узла",
			rt.Text(п.Имя), rt.Flag(свой), rt.Text(накаком), rt.Flag(true), rt.Text(""),
			rt.Number(потолок), rt.Number(0), rt.List(nil)))
		if свой {
			у.состояния[п.Имя] = позвать(у, п.Начальное)
		} else if _, есть := у.каналы[где]; !есть {
			у.каналы[где] = &канал{кто: где, адрес: звонить[где],
				состояние: позвать(у, "Связь узла заново", rt.Text(где), rt.Flag(false), rt.Flag(false),
					rt.Flag(false), rt.Flag(false), rt.Flag(false), rt.Number(0))}
			у.порядок = append(у.порядок, где)
		}
	}
	у.узел = позвать(у, "Узел заново", rt.Text(имя), rt.List(процессы), rt.List(nil),
		rt.Text(""), rt.Number(0), rt.Flag(true))

	// Дерево надзора — данные, ровно как размещение. Решает по нему
	// напечатанный `nadzor.flang`, а не этот файл.
	надзиратели := make([]rt.Value, 0, len(план.Надзоры))
	надПроцессом := make([]rt.Value, 0)
	надНадзором := make([]rt.Value, 0)
	for _, н := range план.Надзоры {
		иначе := н.Иначе
		if иначе == "" {
			иначе = "остановить"
		}
		надзиратели = append(надзиратели, позвать(у, "Надзиратель узла",
			rt.Text(н.Имя), rt.Number(н.Порог), rt.Number(н.Окно), rt.Text(иначе)))
		for _, с := range н.Процессы {
			надПроцессом = append(надПроцессом, позвать(у, "Связь надзора узла",
				rt.Text(с.Кто), rt.Text(н.Имя), rt.Text(с.Стратегия)))
		}
		for _, с := range н.Надзоры {
			надНадзором = append(надНадзором, позвать(у, "Связь надзора узла",
				rt.Text(с.Кто), rt.Text(н.Имя), rt.Text(с.Стратегия)))
		}
	}
	у.дерево = позвать(у, "Дерево надзора узла", rt.List(надзиратели), rt.List(надПроцессом), rt.List(надНадзором))
	return у
}

// ── мир: сокеты. Все обращения к сети — в этих пяти методах ────────────────

func (у *узелFlang) слушать(адрес string) int {
	слушатель, беда := net.Listen("tcp", адрес) // МИР
	if беда != nil {
		panic(беда)
	}
	у.слушатель = слушатель
	go func() {
		for {
			соединение, беда := слушатель.Accept() // МИР
			if беда != nil {
				return
			}
			у.вход <- событиеПровода{что: "принято", соединение: соединение}
		}
	}()
	return слушатель.Addr().(*net.TCPAddr).Port // МИР
}

func (у *узелFlang) позвонить(к *канал) {
	if к.соединение != nil || !у.работает || к.адрес == "" {
		return
	}
	соединение, беда := net.DialTimeout("tcp", к.адрес, time.Second) // МИР
	if беда != nil {
		у.связьСлучилась(к, вариант("Звонок не удался"))
		return
	}
	у.приладить(к, соединение)
}

func (у *узелFlang) приладить(к *канал, соединение net.Conn) {
	к.соединение = соединение
	go у.читать(к, соединение)
	у.связьСлучилась(к, вариант("Сокет завёлся", полеЗн("сейчас", rt.Number(часы()))))
}

func (у *узелFlang) читать(к *канал, соединение net.Conn) {
	читатель := bufio.NewReader(соединение)
	буфер := make([]byte, 65536)
	for {
		сколько, беда := читатель.Read(буфер) // МИР
		if сколько > 0 {
			у.вход <- событиеПровода{канал: к, что: "байты", кусок: string(буфер[:сколько])}
		}
		if беда != nil {
			у.вход <- событиеПровода{канал: к, что: "конец", почему: "сокет закрыт"}
			return
		}
	}
}

func (у *узелFlang) послать(к *канал, кадр map[string]any) {
	if к.соединение == nil {
		return
	}
	if !поле(к.состояние, "готова").Flag && кадр["в"] != "привет" {
		return
	}
	строка, _ := json.Marshal(кадр)
	if _, беда := к.соединение.Write(append(строка, '\n')); беда != nil { // МИР
		у.связьСлучилась(к, вариант("Сокет отказал", полеЗн("почему", rt.Text("запись в сокет отказала"))))
	}
}

func (у *узелFlang) прибрать(к *канал) {
	if к.соединение != nil {
		_ = к.соединение.Close() // МИР
		к.соединение = nil
	}
	к.хвост = ""
}

// ── перевод: кадр провода → вариант эталона связи ──────────────────────────

func (у *узелFlang) кадром(к *канал, кадр map[string]any) {
	строкой := func(имя, поумолчанию string) rt.Value {
		if значение, есть := кадр[имя].(string); есть {
			return rt.Text(значение)
		}
		return rt.Text(поумолчанию)
	}
	вид, _ := кадр["в"].(string)
	у.последнийКадр = кадр
	switch вид {
	case "привет":
		у.связьСлучилась(к, вариант("Пришёл привет", полеЗн("узел", строкой("узел", "")), полеЗн("хэш", строкой("хэш", ""))))
	case "пульс":
		у.связьСлучилась(к, вариант("Пришёл пульс"))
	case "письмо":
		у.связьСлучилась(к, вариант("Пришло письмо", полеЗн("кому", строкой("кому", ""))))
	case "отбой":
		у.связьСлучилась(к, вариант("Пришёл отбой", полеЗн("почему", строкой("почему", "без причины"))))
	default:
		у.связьСлучилась(к, вариант("Пришёл чужой кадр", полеЗн("вид", rt.Text(вид))))
	}
}

// ── единственная дорога от мира к решению о связи ──────────────────────────

func (у *узелFlang) связьСлучилась(к *канал, событие rt.Value) {
	ход := позвать(у, "Шаг связи узла", к.состояние, событие, rt.Text(у.хэш),
		rt.Number(float64(у.срок)), rt.Number(float64(у.пауза)), rt.Flag(у.работает))
	к.состояние = поле(ход, "связь")
	for _, веление := range поле(ход, "веления").List {
		у.исполнитьСвязь(к, веление)
	}
}

func (у *узелFlang) исполнитьСвязь(к *канал, веление rt.Value) {
	строка := func(имя string) string { return поле(веление, имя).Str }
	switch веление.Str {
	case "Послать привет":
		у.послать(к, map[string]any{"в": "привет", "узел": у.имя, "хэш": у.хэш})
	case "Прибрать":
		у.прибрать(к)
		у.узелСлучился(вариант("Связь потеряна", полеЗн("узел", rt.Text(к.кто)), полеЗн("почему", rt.Text("сокет прибран"))))
	case "Связь заведена":
		сказать(map[string]any{"в": "связь", "узел": у.имя, "цель": цель, "сосед": к.кто, "что": "заведена"})
		у.узелСлучился(вариант("Связь готова", полеЗн("узел", rt.Text(к.кто))))
	case "Связь отвергнута":
		сказать(map[string]any{"в": "связь", "узел": у.имя, "цель": цель, "сосед": строка("сосед"),
			"что": "отвергнута", "почему": строка("почему")})
	case "Доложить о потере":
		сказать(map[string]any{"в": "связь", "узел": у.имя, "цель": цель, "сосед": к.кто,
			"что": "потеряна", "почему": строка("почему")})
	case "Доложить о несостоявшемся знакомстве":
		сказать(map[string]any{"в": "связь", "узел": у.имя, "цель": цель, "сосед": к.кто,
			"что": "не состоялась", "почему": строка("почему")})
	case "Позвонить снова":
		к.когдаЗвонить = часы() + поле(веление, "пауза").Num
	case "Доставить письмо":
		груз := раскодировать(у.последнийКадр["что"])
		у.узелСлучился(вариант("Письмо снаружи", полеЗн("кому", rt.Text(строка("кому"))),
			полеЗн("билет", rt.Number(у.новыйБилет(груз)))))
	default:
		panic("узел не знает веления связи «" + веление.Str + "»")
	}
}

// ── билеты: груз живёт у хозяина, в таблице едет число ─────────────────────

func (у *узелFlang) новыйБилет(груз rt.Value) float64 {
	у.билет++
	у.грузы[у.билет] = груз
	return float64(у.билет)
}

// ── единственная дорога от мира к решению о процессах ──────────────────────

func (у *узелFlang) узелСлучился(событие rt.Value) {
	ход := позвать(у, "Шаг узла целиком", у.узел, событие)
	у.узел = поле(ход, "узел")
	for _, веление := range поле(ход, "веления").List {
		у.исполнитьУзел(веление)
	}
}

func (у *узелFlang) исполнитьУзел(веление rt.Value) {
	строка := func(имя string) string { return поле(веление, имя).Str }
	число := func(имя string) float64 { return поле(веление, имя).Num }
	switch веление.Str {
	case "Позвать обработчик":
		у.позватьОбработчик(строка("кто"), int(число("билет")))
	case "Послать по проводу":
		к, есть := у.каналы[строка("узел")]
		груз, естьГруз := у.грузы[int(число("билет"))]
		if есть && естьГруз {
			у.послать(к, map[string]any{"в": "письмо", "кому": строка("кому"), "что": закодировать(груз)})
		}
	case "Поставить таймер":
		у.таймеры = append(у.таймеры, таймер{когда: часы() + число("задержка"), кому: строка("кому"), билет: число("билет")})
	case "Записать в журнал":
		сказать(map[string]any{"в": строка("вид"), "узел": у.имя, "цель": цель,
			"кто": строка("кто"), "почему": строка("почему")})
	case "Уронить процесс":
		сказать(map[string]any{"в": "отказ", "узел": у.имя, "цель": цель, "процесс": строка("кто"),
			"код": строка("код"), "текст": строка("текст")})
		// Отказ уходит НАДЗОРУ, а не в журнал: решает напечатанный
		// `nadzor.flang`, здесь только дорога к нему.
		у.надзорСлучился(строка("кто"), строка("код"))
	case "Письмо пропало":
		сказать(map[string]any{"в": "потеря", "узел": у.имя, "цель": цель,
			"кому": строка("кому"), "почему": строка("почему")})
	default:
		panic("узел не знает веления планировщика «" + веление.Str + "»")
	}
}

// ── единственная дорога от отказа к решению надзора ────────────────────────

func (у *узелFlang) надзорСлучился(кто, код string) {
	ход := позвать(у, "Шаг надзора узла", у.дерево, rt.Text(кто), rt.Text(код), rt.Number(часы()))
	у.дерево = поле(ход, "дерево")
	for _, веление := range поле(ход, "веления").List {
		у.исполнитьНадзор(веление)
	}
}

func (у *узелFlang) исполнитьНадзор(веление rt.Value) {
	строка := func(имя string) string { return поле(веление, имя).Str }
	switch веление.Str {
	case "Поднять":
		// Перезапуск трогает состояние и не трогает ящик — это решено на flang;
		// здесь состояние берётся тем же путём, что при подъёме узла.
		у.узел = позвать(у, "Оживить процесс узла", у.узел, rt.Text(строка("кто")))
		for _, п := range у.план.Процессы {
			if п.Имя == строка("кто") {
				у.состояния[п.Имя] = позвать(у, п.Начальное)
			}
		}
		сказать(map[string]any{"в": "надзор", "узел": у.имя, "цель": цель, "что": "поднят", "кто": строка("кто")})
	case "Уложить":
		у.узел = позвать(у, "Уложить процесс узла", у.узел, rt.Text(строка("кто")), rt.Text("остановлен надзором"))
		сказать(map[string]any{"в": "надзор", "узел": у.имя, "цель": цель, "что": "уложен",
			"кто": строка("кто"), "надзор": строка("надзор")})
	case "Решено":
		сказать(map[string]any{"в": "надзор", "узел": у.имя, "цель": цель, "что": "решено",
			"кто": строка("кто"), "надзор": строка("надзор"), "стратегия": строка("стратегия")})
	case "Некому надзирать":
		у.узел = позвать(у, "Остановить узел целиком", у.узел)
		у.работает = false
		сказать(map[string]any{"в": "надзор", "узел": у.имя, "цель": цель, "что": "некому",
			"кто": строка("кто"), "надзор": строка("надзор")})
	default:
		panic("узел не знает веления надзора «" + веление.Str + "»")
	}
}

// ── вызов обработчика по имени: та самая граница языка ─────────────────────

func (у *узелFlang) позватьОбработчик(кто string, билет int) {
	имя := ""
	for _, п := range у.план.Процессы {
		if п.Имя == кто {
			имя = п.Обработчик
		}
	}
	груз, есть := у.грузы[билет]
	if имя == "" || !есть {
		у.узелСлучился(вариант("Обработчик отказал", полеЗн("код", rt.Text("FLANG_PROCESS")),
			полеЗн("текст", rt.Text("обработчика или груза нет"))))
		return
	}
	итог, беда := prog.Call(у.ctx, имя, []rt.Value{у.состояния[кто], груз})
	if беда != nil {
		код := "FLANG_INTERNAL"
		if сбой, годно := беда.(*rt.Error); годно {
			код = сбой.Code
		}
		у.узелСлучился(вариант("Обработчик отказал", полеЗн("код", rt.Text(код)),
			полеЗн("текст", rt.Text(беда.Error()))))
		return
	}
	у.состояния[кто] = поле(итог, "состояние")
	действия := поле(итог, "действия").List
	переведённые := make([]rt.Value, 0, len(действия))
	for _, д := range действия {
		переведённые = append(переведённые, у.вДействие(д))
	}
	у.узелСлучился(вариант("Обработчик вернул", полеЗн("действия", rt.List(переведённые))))
}

// вДействие — действие языка → действие планировщика. Перевод, а не решение:
// имена разные нарочно, иначе словарь действий языка и тип планировщика не
// собрались бы в один модуль.
func (у *узелFlang) вДействие(д rt.Value) rt.Value {
	switch д.Str {
	case "отправить":
		return вариант("Велено слать", полеЗн("кому", поле(д, "кому")),
			полеЗн("билет", rt.Number(у.новыйБилет(поле(д, "что")))))
	case "через":
		return вариант("Велено слать позже", полеЗн("кому", поле(д, "кому")),
			полеЗн("билет", rt.Number(у.новыйБилет(поле(д, "что")))),
			полеЗн("задержка", поле(д, "задержка")))
	case "отложить":
		return вариант("Велено отложить")
	case "продолжить":
		return вариант("Велено продолжить")
	case "остановить":
		return вариант("Велено остановить", полеЗн("почему", поле(д, "почему")))
	}
	panic("узел не знает действия «" + д.Str + "»")
}

// ── круг: сокеты, часы, таймеры и очередь готовых ──────────────────────────

func (у *узелFlang) свободныйКанал() *канал {
	for _, имя := range у.порядок {
		if у.каналы[имя].соединение == nil {
			return у.каналы[имя]
		}
	}
	return nil
}

func (у *узелFlang) байты(к *канал, кусок string) {
	у.связьСлучилась(к, вариант("Байты пришли", полеЗн("сейчас", rt.Number(часы()))))
	к.хвост += кусок
	for strings.Contains(к.хвост, "\n") && к.соединение != nil {
		край := strings.Index(к.хвост, "\n")
		строка := strings.TrimSpace(к.хвост[:край])
		к.хвост = к.хвост[край+1:]
		if строка == "" {
			continue
		}
		var кадр map[string]any
		if json.Unmarshal([]byte(строка), &кадр) != nil {
			у.связьСлучилась(к, вариант("Сокет отказал", полеЗн("почему", rt.Text("кадр не разобран"))))
			return
		}
		у.кадром(к, кадр)
	}
}

func (у *узелFlang) круг(доколе float64) {
	период := у.срок / 5
	if период < 20 {
		период = 20
	}
	следующийСторож := часы() + float64(период)
	тик := time.NewTicker(time.Duration(период) * time.Millisecond) // МИР
	defer тик.Stop()
	for часы() < доколе && у.работает {
		for _, имя := range у.порядок {
			к := у.каналы[имя]
			if к.соединение == nil && часы() >= к.когдаЗвонить {
				у.позвонить(к)
			}
		}
		select {
		case событие := <-у.вход:
			у.поСобытию(событие)
		case <-тик.C:
		}
		сейчас := часы()
		оставшиеся := у.таймеры[:0]
		for _, т := range у.таймеры {
			if т.когда <= сейчас {
				у.узелСлучился(вариант("Таймер сработал", полеЗн("кому", rt.Text(т.кому)), полеЗн("билет", rt.Number(т.билет))))
			} else {
				оставшиеся = append(оставшиеся, т)
			}
		}
		у.таймеры = оставшиеся
		for _, имя := range у.порядок {
			к := у.каналы[имя]
			if к.соединение != nil && поле(к.состояние, "готова").Flag {
				if сейчас-к.последнийПульс >= float64(у.пульс) {
					к.последнийПульс = сейчас
					у.послать(к, map[string]any{"в": "пульс"})
				}
			}
		}
		if сейчас >= следующийСторож {
			следующийСторож = сейчас + float64(период)
			for _, имя := range у.порядок {
				if к := у.каналы[имя]; к.соединение != nil {
					у.связьСлучилась(к, вариант("Сторож проснулся", полеЗн("сейчас", rt.Number(сейчас))))
				}
			}
		}
		// Пробеги — до покоя, но с уступкой миру после каждого: иначе пульс не
		// уйдёт, и связь порвалась бы от собственной занятости.
		for витков := 0; витков < 64; витков++ {
			было := у.узел
			у.узелСлучился(вариант("Пора бежать", полеЗн("жребий", rt.Number(у.жребий.дальше()))))
			if rt.Equal(было, у.узел) {
				break
			}
		}
	}
}

func (у *узелFlang) поСобытию(событие событиеПровода) {
	switch событие.что {
	case "принято":
		к := у.свободныйКанал()
		if к == nil {
			_ = событие.соединение.Close() // МИР
			return
		}
		у.приладить(к, событие.соединение)
	case "байты":
		if событие.канал.соединение != nil {
			у.байты(событие.канал, событие.кусок)
		}
	case "конец":
		if событие.канал.соединение != nil {
			у.связьСлучилась(событие.канал, вариант("Сокет отказал", полеЗн("почему", rt.Text(событие.почему))))
		}
	}
}

// ── доводы ─────────────────────────────────────────────────────────────────

func main() {
	ключи := map[string]string{}
	имя := ""
	for _, довод := range os.Args[1:] {
		if strings.HasPrefix(довод, "--") {
			имя = довод[2:]
			ключи[имя] = "да"
		} else if имя != "" {
			ключи[имя] = довод
			имя = ""
		}
	}
	сырой, беда := os.ReadFile(ключи["план-файл"]) // МИР
	if беда != nil {
		panic(беда)
	}
	var план планУзла
	if json.Unmarshal(сырой, &план) != nil {
		panic("план не разобран")
	}
	var размещение map[string]any
	if json.Unmarshal([]byte(ключи["размещение"]), &размещение) != nil {
		panic("размещение не разобрано")
	}
	где := map[string]string{}
	звонить := map[string]string{}
	for ключ, значение := range размещение {
		if ключ == "звонить" {
			for сосед, адрес := range значение.(map[string]any) {
				звонить[сосед] = адрес.(string)
			}
			continue
		}
		где[ключ] = значение.(string)
	}
	число := func(ключ string, поумолчанию int) int {
		значение := поумолчанию
		if строка, есть := ключи[ключ]; есть {
			_, _ = fmt.Sscanf(строка, "%d", &значение)
		}
		return значение
	}
	у := завести(ключи["я"], план, где, звонить, ключи["хэш"],
		число("срок", 1000), число("пульс", 200), число("пауза", 250), число("семя", 7))
	порт := 0
	if адрес, есть := ключи["слушать"]; есть {
		порт = у.слушать(адрес)
	}
	хэшКоротко := ключи["хэш"]
	if len(хэшКоротко) > 12 {
		хэшКоротко = хэшКоротко[:12]
	}
	сказать(map[string]any{"в": "поднят", "узел": у.имя, "цель": цель, "порт": порт, "хэш": хэшКоротко})
	if вброшенное, есть := ключи["вбросить"]; есть {
		var письма []map[string]any
		if json.Unmarshal([]byte(вброшенное), &письма) == nil {
			for _, письмо := range письма {
				кому, _ := письмо["кому"].(string)
				у.узелСлучился(вариант("Письмо снаружи", полеЗн("кому", rt.Text(кому)),
					полеЗн("билет", rt.Number(у.новыйБилет(раскодировать(письмо["что"]))))))
			}
		}
	}
	жить := 5.0
	if строка, есть := ключи["жить"]; есть {
		_, _ = fmt.Sscanf(строка, "%f", &жить)
	}
	у.круг(часы() + жить*1000)
	состояния := map[string]any{}
	for имя, значение := range у.состояния {
		состояния[имя] = закодировать(значение)
	}
	сказать(map[string]any{"в": "конец", "узел": у.имя, "цель": цель, "состояния": состояния})
}
