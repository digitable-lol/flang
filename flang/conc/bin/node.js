/* ── провод: метка одной буквой у каждого значения ────────────────────────
   Перевод, а не решение: правило записано в `flang/conc/DISTRIBUTED.md`, и
   разойтись с ним нельзя — иначе письмо с одной цели другая не прочтёт. */
function закодировать(значение) {
  if (значение === null || значение === undefined) return ["н"]
  if (typeof значение === "boolean") return ["п", значение]
  if (typeof значение === "string") return ["с", значение]
  if (typeof значение === "number") {
    if (Number.isNaN(значение)) return ["ч", "NaN"]
    if (значение === Infinity) return ["ч", "+∞"]
    if (значение === -Infinity) return ["ч", "-∞"]
    if (Object.is(значение, -0)) return ["ч", "-0"]
    return ["ч", значение]
  }
  if (Array.isArray(значение)) return ["л", значение.map(закодировать)]
  if (typeof значение === "object") {
    const поля = {}
    if (typeof значение.variant === "string" && значение.fields !== undefined) {
      for (const [имя, поле] of Object.entries(значение.fields)) поля[имя] = закодировать(поле)
      return ["в", значение.variant, поля]
    }
    for (const [имя, поле] of Object.entries(значение)) поля[имя] = закодировать(поле)
    return ["з", поля]
  }
  throw new Error(`нечего кодировать: ${typeof значение}`)
}

/** Вариант в напечатанном JavaScript — экземпляр класса, а не объект с полями:
 *  `разбор` проверяет его `instanceof`, и голый объект обработчик не сопоставит
 *  ни с одним образцом. Поэтому вариант собирается конструктором ТОГО САМОГО
 *  модуля. */
function раскодировать(код) {
  if (!Array.isArray(код) || код.length === 0) throw new Error("не значение на проводе")
  switch (код[0]) {
    case "н": return null
    case "п": return код[1] === true
    case "с": return String(код[1])
    case "ч": {
      if (код[1] === "NaN") return NaN
      if (код[1] === "+∞") return Infinity
      if (код[1] === "-∞") return -Infinity
      if (код[1] === "-0") return -0
      return Number(код[1])
    }
    case "л": return (код[1] ?? []).map(раскодировать)
    case "з": {
      const запись = {}
      for (const [имя, поле] of Object.entries(код[1] ?? {})) запись[имя] = раскодировать(поле)
      return запись
    }
    case "в": {
      const собрать = КОНСТРУКТОРЫ.get(код[1])
      if (собрать === undefined) {
        throw new Error(`варианта «${код[1]}» в напечатанном модуле нет: письмо не от этой программы`)
      }
      const поля = {}
      for (const [имя, поле] of Object.entries(код[2] ?? {})) поля[имя] = раскодировать(поле)
      return собрать(поля)
    }
    default: throw new Error(`неизвестная метка значения «${код[0]}»`)
  }
}

/** Словарь «имя варианта → конструктор» — пробой, а не по списку: правило
 *  переименования имён в латиницу принадлежит печати, и повторять его здесь
 *  значило бы завести второй источник правды о нём. */
function конструкторыВариантов(модуль) {
  const словарь = new Map()
  for (const [имя, значение] of Object.entries(модуль)) {
    if (typeof значение !== "function" || значение.length !== 0) continue
    if (имя.startsWith("$")) continue
    try {
      const проба = значение({})
      if (проба !== null && typeof проба === "object" && typeof проба.variant === "string") {
        словарь.set(проба.variant, значение)
      }
    } catch { /* не конструктор варианта — и хорошо: проба на то и проба */ }
  }
  return словарь
}

