class Узел {
  constructor(имя, план, размещение, хэш, сроки, семя) {
    this.имя = имя
    this.план = план
    this.хэш = хэш
    this.срок = сроки.срок
    this.пульс = сроки.пульс
    this.пауза = сроки.пауза
    this.работает = true
    this.жребий = случайное(семя)

    /* Таблица процессов — значение эталона. Свои и представители различаются
       признаком, а не двумя списками: так решено на flang. */
    const процессы = []
    this.состояния = {}
    for (const узел of план.процессы) {
      const где = размещение[узел.имя]
      const свой = где === имя
      процессы.push(реш.processUzla(узел.имя, свой, свой ? "" : где, true, "", узел.ящик ?? 0, 0, []))
      if (свой) this.состояния[узел.имя] = позватьПоИмени(узел.начальное, [])
    }
    this.узел = реш.uzelZanovo(имя, процессы, [], "", 0, true)

    /* Соседи считаются по ПРЕДСТАВИТЕЛЯМ, а не по «звонить»: узел, которого
       набирает сосед, ждёт его ровно так же, и место под связь ему нужно такое
       же. Без этого принимающая сторона отказывала бы в соединении. */
    this.каналы = new Map()
    for (const узел of план.процессы) {
      const где = размещение[узел.имя]
      if (где !== имя && !this.каналы.has(где)) {
        this.каналы.set(где, new Канал(где, (размещение.звонить ?? {})[где] ?? ""))
      }
    }
    this.сервер = null
    this.билет = 0
    this.грузы = new Map()
    this.таймеры = []
    this.последнийКадр = null
    this.следующийСторож = 0
  }

  // ── мир: сокеты ────────────────────────────────────────────────────────
  слушать(адрес, готово) {
    const [хозяин, порт] = разделитьАдрес(адрес)
    this.сервер = createServer((сокет) => this.принять(сокет))  // МИР
    this.сервер.listen(порт, хозяин, () => готово(this.сервер.address().port))  // МИР
  }

  /* Сокет становится сокетом КАНАЛА только после «connect», а до тех пор канал
     помечен «звоним». Иначе сторож увидел бы связь с сокетом, которой эталон ещё
     не сказал «Сокет завёлся»: «последний байт» у неё нулевой, молчание выходит
     длиной во всё время от начала эпохи, и связь рвётся, не успев завестись.
     Это и есть разница с хозяевами, где `connect` синхронный. */
  позвонить(канал) {
    if (канал.сокет !== null || канал.звоним || !this.работает) return
    const [хозяин, порт] = разделитьАдрес(канал.адрес)
    const сокет = createConnection({ host: хозяин, port: порт })  // МИР
    сокет.setNoDelay(true)  // МИР
    канал.звоним = true
    сокет.on("connect", () => {
      канал.звоним = false
      канал.сокет = сокет
      this.связьСлучилась(канал, реш.SoketZavyolsya({ "сейчас": часы() }))
    })
    сокет.on("data", (кусок) => { this.прочесть(канал, кусок); this.пробеги() })
    сокет.on("error", () => { /* об отказе скажет «close» — один раз, а не два */ })
    сокет.on("close", () => {
      if (канал.звоним) {
        канал.звоним = false
        this.связьСлучилась(канал, реш.ZvonokNeUdalsya({}))
        this.пробеги()
        return
      }
      if (канал.сокет !== сокет) return
      канал.сокет = null
      канал.хвост = ""
      this.связьСлучилась(канал, реш.SoketOtkazal({ "почему": "сокет закрыт" }))
      this.пробеги()
    })
  }

  /* Кто позвонил, скажет его «привет»; до него связь безымянная, и место для
     неё берётся первое свободное. */
  принять(сокет) {
    const канал = [...this.каналы.values()].find((это) => это.сокет === null)
    if (канал === undefined) { сокет.destroy(); return }  // МИР
    сокет.setNoDelay(true)  // МИР
    канал.сокет = сокет
    сокет.on("data", (кусок) => { this.прочесть(канал, кусок); this.пробеги() })
    сокет.on("error", () => { /* об отказе скажет «close» */ })
    сокет.on("close", () => {
      if (канал.сокет !== сокет) return
      канал.сокет = null
      канал.хвост = ""
      this.связьСлучилась(канал, реш.SoketOtkazal({ "почему": "сокет закрыт" }))
      this.пробеги()
    })
    this.связьСлучилась(канал, реш.SoketZavyolsya({ "сейчас": часы() }))
  }

  послать(канал, кадр) {
    if (канал.сокет === null) return
    if (!канал.состояние["готова"] && кадр.в !== "привет") return
    канал.сокет.write(`${JSON.stringify(кадр)}\n`)  // МИР
  }

  прочесть(канал, кусок) {
    this.связьСлучилась(канал, реш.BaytyPrishli({ "сейчас": часы() }))
    канал.хвост += кусок.toString("utf8")
    while (канал.хвост.includes("\n") && канал.сокет !== null) {
      const край = канал.хвост.indexOf("\n")
      const строка = канал.хвост.slice(0, край).trim()
      канал.хвост = канал.хвост.slice(край + 1)
      if (строка === "") continue
      let кадр = null
      try { кадр = JSON.parse(строка) } catch {
        this.связьСлучилась(канал, реш.SoketOtkazal({ "почему": "кадр не разобран" }))
        return
      }
      this.последнийКадр = кадр
      this.кадром(канал, кадр)
    }
  }

  прибрать(канал) {
    if (канал.сокет !== null) {
      const сокет = канал.сокет
      канал.сокет = null
      сокет.destroy()  // МИР
    }
    канал.хвост = ""
  }

  // ── перевод: кадр провода → вариант эталона связи ──────────────────────
  кадром(канал, кадр) {
    switch (кадр.в) {
      case "привет":
        this.связьСлучилась(канал, реш.PrishyolPrivet({
          "узел": String(кадр.узел ?? ""), "хэш": String(кадр.хэш ?? ""),
        }))
        break
      case "пульс": this.связьСлучилась(канал, реш.PrishyolPuls({})); break
      case "письмо": this.связьСлучилась(канал, реш.PrishloPismo({ "кому": String(кадр.кому ?? "") })); break
      case "отбой":
        this.связьСлучилась(канал, реш.PrishyolOtboy({ "почему": String(кадр.почему ?? "без причины") }))
        break
      default: this.связьСлучилась(канал, реш.PrishyolChuzhoyKadr({ "вид": String(кадр.в) }))
    }
  }

  // ── единственная дорога от мира к решению о связи ──────────────────────
  связьСлучилась(канал, событие) {
    const ход = реш.shagSvyaziUzla(канал.состояние, событие, this.хэш, this.срок, this.пауза, this.работает)
    канал.состояние = ход["связь"]
    for (const веление of ход["веления"]) this.исполнитьСвязь(канал, веление)
  }

  исполнитьСвязь(канал, веление) {
    const поля = веление.fields
    switch (веление.variant) {
      case "Послать привет":
        this.послать(канал, { в: "привет", узел: this.имя, хэш: this.хэш })
        break
      case "Прибрать":
        this.прибрать(канал)
        this.узелСлучился(реш.SvyazPoteryana({ "узел": канал.кто, "почему": "сокет прибран" }))
        break
      case "Связь заведена":
        сказать({ в: "связь", узел: this.имя, цель: ЦЕЛЬ, сосед: канал.кто, что: "заведена" })
        this.узелСлучился(реш.SvyazGotova({ "узел": канал.кто }))
        break
      case "Связь отвергнута":
        сказать({
          в: "связь", узел: this.имя, цель: ЦЕЛЬ, сосед: поля["сосед"],
          что: "отвергнута", почему: поля["почему"],
        })
        break
      case "Доложить о потере":
        сказать({ в: "связь", узел: this.имя, цель: ЦЕЛЬ, сосед: канал.кто, что: "потеряна", почему: поля["почему"] })
        break
      case "Доложить о несостоявшемся знакомстве":
        сказать({
          в: "связь", узел: this.имя, цель: ЦЕЛЬ, сосед: канал.кто,
          что: "не состоялась", почему: поля["почему"],
        })
        break
      case "Позвонить снова":
        канал.когдаЗвонить = часы() + поля["пауза"]
        break
      case "Доставить письмо": {
        /* Эталон связи назвал АДРЕСАТА, груз оставил узлу — вот он. */
        const груз = раскодировать(this.последнийКадр.что)
        this.узелСлучился(реш.PismoSnaruzhi({ "кому": поля["кому"], "билет": this.новыйБилет(груз) }))
        break
      }
      default: throw new Error(`узел не знает веления связи «${веление.variant}»`)
    }
  }

  // ── билеты: груз живёт у хозяина, в таблице едет число ─────────────────
  новыйБилет(груз) {
    this.билет += 1
    this.грузы.set(this.билет, груз)
    return this.билет
  }

  // ── единственная дорога от мира к решению о процессах ──────────────────
  узелСлучился(событие) {
    const ход = реш.shagUzlaCelikom(this.узел, событие)
    this.узел = ход["узел"]
    for (const веление of ход["веления"]) this.исполнитьУзел(веление)
  }

  исполнитьУзел(веление) {
    const поля = веление.fields
    switch (веление.variant) {
      case "Позвать обработчик":
        this.позвать(поля["кто"], поля["билет"])
        break
      case "Послать по проводу": {
        const канал = this.каналы.get(поля["узел"])
        const груз = this.грузы.get(поля["билет"])
        if (канал !== undefined && груз !== undefined) {
          this.послать(канал, { в: "письмо", кому: поля["кому"], что: закодировать(груз) })
        }
        break
      }
      case "Поставить таймер":
        this.таймеры.push([часы() + поля["задержка"], поля["кому"], поля["билет"]])
        break
      case "Записать в журнал":
        сказать({ в: поля["вид"], узел: this.имя, цель: ЦЕЛЬ, кто: поля["кто"], почему: поля["почему"] })
        break
      case "Уронить процесс":
        /* Надзора на этой цели нет — назван в шапке. Отказ виден в журнале. */
        сказать({
          в: "отказ", узел: this.имя, цель: ЦЕЛЬ, процесс: поля["кто"],
          код: поля["код"], текст: поля["текст"],
        })
        break
      case "Письмо пропало":
        сказать({ в: "потеря", узел: this.имя, цель: ЦЕЛЬ, кому: поля["кому"], почему: поля["почему"] })
        break
      default: throw new Error(`узел не знает веления планировщика «${веление.variant}»`)
    }
  }

  // ── вызов обработчика по имени: та самая граница языка ─────────────────
  позвать(кто, билет) {
    const обработчик = (this.план.процессы.find((это) => это.имя === кто) ?? {}).обработчик
    const груз = this.грузы.get(билет)
    if (обработчик === undefined || груз === undefined) {
      this.узелСлучился(реш.ObrabotchikOtkazal({ "код": "FLANG_PROCESS", "текст": "обработчика или груза нет" }))
      return
    }
    let итог = null
    try {
      итог = позватьПоИмени(обработчик, [this.состояния[кто], груз])
    } catch (беда) {
      this.узелСлучился(реш.ObrabotchikOtkazal({
        "код": String(беда.code ?? "FLANG_INTERNAL"), "текст": String(беда.message ?? беда),
      }))
      return
    }
    this.состояния[кто] = итог["состояние"]
    this.узелСлучился(реш.ObrabotchikVernul({ "действия": итог["действия"].map((д) => this.вДействие(д)) }))
  }

  /** Действие языка → действие планировщика. Перевод, а не решение: имена
   *  разные нарочно, иначе словарь действий языка и тип планировщика не
   *  собрались бы в один модуль. */
  вДействие(д) {
    const поля = д.fields
    switch (д.variant) {
      case "отправить":
        return реш.VelenoSlat({ "кому": поля["кому"], "билет": this.новыйБилет(поля["что"]) })
      case "через":
        return реш.VelenoSlatPozzhe({
          "кому": поля["кому"], "билет": this.новыйБилет(поля["что"]), "задержка": поля["задержка"],
        })
      case "отложить": return реш.VelenoOtlozhit({})
      case "продолжить": return реш.VelenoProdolzhit({})
      case "остановить": return реш.VelenoOstanovit({ "почему": поля["почему"] })
      default: throw new Error(`узел не знает действия «${д.variant}»`)
    }
  }

  // ── круг: часы, таймеры и очередь готовых ──────────────────────────────
  /** Пробеги — до покоя. Уступка миру здесь не нужна: сокеты и часы приходят
   *  событиями, а не опросом, и пульс уйдёт из своего тика. */
  пробеги() {
    for (let шаг = 0; шаг < 64; шаг += 1) {
      const было = this.узел
      this.узелСлучился(реш.PoraBezhat({ "жребий": this.жребий() }))
      if (this.узел === было) return
    }
  }

  /* Первый шаг круга у остальных хозяев — НАБРАТЬ, и только потом ждать мира и
     бежать. Здесь он вынесен отдельно, потому что зовётся дважды: сразу после
     подъёма и дальше каждым тиком. Порядок тот же, и он важен: у хозяев с
     синхронным `connect` знакомство успевает сойтись внутри ожидания мира, а
     здесь — между подъёмом и первым тиком. */
  звонки() {
    const сейчас = часы()
    for (const канал of this.каналы.values()) {
      if (канал.сокет === null && сейчас >= канал.когдаЗвонить && канал.адрес !== "") this.позвонить(канал)
    }
  }

  тик() {
    const сейчас = часы()
    this.звонки()
    for (const [отметка, кому, билет] of this.таймеры.filter((т) => т[0] <= сейчас)) {
      this.узелСлучился(реш.TaymerSrabotal({ "кому": кому, "билет": билет }))
    }
    this.таймеры = this.таймеры.filter((т) => т[0] > сейчас)
    for (const канал of this.каналы.values()) {
      if (канал.сокет !== null && канал.состояние["готова"] && сейчас - канал.последнийПульс >= this.пульс) {
        канал.последнийПульс = сейчас
        this.послать(канал, { в: "пульс" })
      }
    }
    if (сейчас >= this.следующийСторож) {
      this.следующийСторож = сейчас + Math.max(20, Math.floor(this.срок / 5))
      for (const канал of this.каналы.values()) {
        if (канал.сокет !== null) this.связьСлучилась(канал, реш.StorozhProsnulsya({ "сейчас": сейчас }))
      }
    }
    this.пробеги()
  }

  состоянияНаружу() {
    const итог = {}
    for (const [имя, зн] of Object.entries(this.состояния)) итог[имя] = закодировать(зн)
    return итог
  }

  прибратьВсё() {
    for (const канал of this.каналы.values()) this.прибрать(канал)
    if (this.сервер !== null) this.сервер.close()  // МИР
  }
}

function позватьПоИмени(имя, доводы) {
  const функция = реш.$PROGRAM.functions.get(имя)
  if (функция === undefined) throw new Error(`не найдена функция «${имя}»`)
  return функция(...доводы)
}

function разделитьАдрес(строка) {
  const край = String(строка).lastIndexOf(":")
  if (край < 0) throw new Error(`адрес «${строка}» без порта`)
  return [строка.slice(0, край), Number(строка.slice(край + 1))]
}

function разобратьДоводы(доводы) {
  const итог = {}
  let имя = null
  for (const довод of доводы) {
    if (довод.startsWith("--")) { имя = довод.slice(2); итог[имя] = true; continue }
    if (имя !== null) { итог[имя] = довод; имя = null }
  }
  return итог
}

function главное(доводы) {
  const ключи = разобратьДоводы(доводы)
  const план = typeof ключи["план"] === "string"
    ? JSON.parse(ключи["план"])
    : JSON.parse(readFileSync(ключи["план-файл"], "utf8"))  // МИР
  const размещение = JSON.parse(ключи["размещение"])
  const сроки = {
    срок: Number(ключи["срок"] ?? 1000),
    пульс: Number(ключи["пульс"] ?? 200),
    пауза: Number(ключи["пауза"] ?? 250),
  }
  const узел = new Узел(ключи["я"], план, размещение, ключи["хэш"], сроки, Number(ключи["семя"] ?? 7))

  const поднялся = (порт) => {
    сказать({ в: "поднят", узел: узел.имя, цель: ЦЕЛЬ, порт, хэш: узел.хэш.slice(0, 12), сроки })
    /* Начальные письма — тем же путём, каким приходят письма с провода. */
    for (const вброс of JSON.parse(ключи["вбросить"] ?? "[]")) {
      узел.узелСлучился(реш.PismoSnaruzhi({
        "кому": вброс.кому, "билет": узел.новыйБилет(раскодировать(вброс.что)),
      }))
    }
    узел.звонки()
    const период = Math.max(20, Math.min(Math.floor(сроки.срок / 5), сроки.пульс))
    const тикер = setInterval(() => узел.тик(), период)  // МИР
    setTimeout(() => {  // МИР
      clearInterval(тикер)  // МИР
      узел.прибратьВсё()
      сказать({ в: "конец", узел: узел.имя, цель: ЦЕЛЬ, состояния: узел.состоянияНаружу() })
    }, Number(ключи["жить"] ?? 5) * 1000)
  }

  if (typeof ключи["слушать"] === "string") узел.слушать(ключи["слушать"], поднялся)
  else поднялся(0)
}

