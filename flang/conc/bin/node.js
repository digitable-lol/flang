/** mulberry32 — тот же генератор, что у остальных хозяев, чтобы чередование при
 *  одном семени совпадало. Не решение о мире: на входе число, на выходе число. */
function случайное(семя) {
  let состояние = семя >>> 0
  return () => {
    состояние = (состояние + 0x6D2B79F5) >>> 0
    let т = состояние
    т = Math.imul(т ^ (т >>> 15), т | 1)
    т ^= т + Math.imul(т ^ (т >>> 7), т | 61)
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296
  }
}

