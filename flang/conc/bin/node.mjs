/**
 * Один узел flang: печатает программу в JavaScript, загружает напечатанное и
 * держит на нём свои процессы.
 *
 * Контракт — `flang/conc/DISTRIBUTED.md`. Узел устроен в
 * `flang/conc/distributed.mjs`; здесь только передний край: разбор доводов,
 * печать программы, журнал наружу и команды снаружи.
 *
 *   node flang/conc/bin/node.mjs \
 *     --размещение flang/conc/examples/distributed.json \
 *     --я «счёт» --слушать 127.0.0.1:9001 --сосед «учёт»=127.0.0.1:9002
 *
 * Журнал уходит в stdout по строке JSON на событие — это и есть то, чем
 * испытание смотрит, увидел ли надзор отказ. Команды приходят в stdin тем же
 * видом: `вбросить`, `состояния`, `связи`, `стоп`.
 *
 * Программа ПРОВЕРЯЕТСЯ перед запуском теми же проверками, что у `flang check`:
 * узел, поднявший непроверенную программу, был бы дырой в том самом месте, ради
 * которого весь язык и затевался.
 */
import { createHash } from "node:crypto"
import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgram } from "../../bin/flang.mjs"
import { emitJs } from "../../src/emit/js.mjs"
import { СРОКИ, разделитьАдрес, размещениеУзла, создатьУзел } from "../distributed.mjs"

const корень = fileURLToPath(new URL("../../..", import.meta.url))

/* ── доводы ─────────────────────────────────────────────────────────────── */

function разобратьДоводы(доводы) {
  const итог = { соседи: {} }
  for (let i = 0; i < доводы.length; i += 1) {
    const довод = доводы[i]
    const дальше = () => {
      const значение = доводы[i + 1]
      if (значение === undefined) {
        throw new Error(`довод «${довод}» без значения`)
      }
      i += 1
      return значение
    }
    switch (довод) {
      case "--размещение": итог.размещение = дальше(); break
      case "--я": итог.я = снятьКавычки(дальше()); break
      case "--программа": итог.программа = дальше(); break
      case "--слушать": итог.слушать = дальше(); break
      case "--сосед": {
        const пара = дальше()
        const край = пара.indexOf("=")
        if (край < 0) throw new Error(`--сосед «${пара}»: ожидалось имя=хозяин:порт`)
        итог.соседи[снятьКавычки(пара.slice(0, край))] = пара.slice(край + 1)
        break
      }
      case "--семя": итог.семя = Number(дальше()); break
      case "--срок": итог.срок = Number(дальше()); break
      case "--пульс": итог.пульс = Number(дальше()); break
      case "--пауза": итог.пауза = Number(дальше()); break
      case "--знакомство": итог.знакомство = Number(дальше()); break
      default: throw new Error(`неизвестный довод «${довод}»`)
    }
  }
  if (итог.размещение === undefined) throw new Error("нет довода --размещение")
  if (итог.я === undefined) throw new Error("нет довода --я: узел обязан знать своё имя")
  return итог
}

/** Имена узлов пишутся кавычками-ёлочками, как всё в языке; оболочке они лишние. */
function снятьКавычки(строка) {
  const это = String(строка)
  return это.startsWith("«") && это.endsWith("»") ? это.slice(1, -1) : это
}

/* ── подъём ─────────────────────────────────────────────────────────────── */

const доводы = разобратьДоводы(process.argv.slice(2))
const путьРазмещения = resolve(доводы.размещение)
const размещениеФайла = JSON.parse(readFileSync(путьРазмещения, "utf8"))

/* Где какой процесс — обратной таблицей: размещение объявляет «узел → процессы»,
   а узлу нужно «процесс → узел». Адреса соседей: из размещения, поверх — из
   доводов, потому что порты в файле нулевые: настоящие раздаёт хозяин. */
const размещение = размещениеУзла(размещениеФайла, доводы.я, доводы.соседи)
const гдеПроцесс = размещение.процессы

const путьПрограммы = resolve(
  доводы.программа ?? resolve(корень, размещениеФайла.программа ?? ""),
)

const [хозяин, порт] = разделитьАдрес(доводы.слушать ?? размещение.слушать ?? "127.0.0.1:0")

/* ── печать и проверка ──────────────────────────────────────────────────── */

const программа = await loadProgram(путьПрограммы)
/* Размещение едет проверке вторым доводом, и это то самое «откуда анализ узнаёт
   размещение», которого не было (`DISTRIBUTED.md`, «Порядок дальнейших работ»,
   пункт 1). Узел — единственное место, где программа и размещение сходятся
   ОБЯЗАТЕЛЬНО: `flang check --размещение` автор может и забыть, а поднять узел
   мимо этой строки нельзя. Поэтому непокрытый надзором представитель здесь не
   предупреждение, а отказ подъёма — тем же кодом FLANG_UNCOVERED_FAILURE, каким
   отвергается непокрытый местный процесс. */
const внешнее = await externalChecks(программа, { размещение: размещениеФайла })
const беды = внешнее.diagnostics.filter((беда) => беда?.severity !== "warning")
if (беды.length > 0) {
  for (const беда of беды) {
    process.stdout.write(`${JSON.stringify({ в: "проверка", узел: доводы.я, код: беда.code, текст: беда.message })}\n`)
  }
  process.exit(1)
}

const напечатано = emitJs(программа).files[0].content
/* Хэш напечатанного, а не исходника: рукопожатие обязано сравнивать то, что
   узлы РЕАЛЬНО исполняют. Два разных исходника, дающих один и тот же модуль, —
   одна и та же программа, и мешать им говорить не за что. */
const хэш = createHash("sha256").update(напечатано, "utf8").digest("hex")
const модуль = await import(
  `data:text/javascript;charset=utf-8;base64,${Buffer.from(напечатано, "utf8").toString("base64")}`
)

/**
 * Журнал наружу — и заодно единственное место, где узел кончается.
 *
 * «Конец» печатает и надзор (отказ дошёл доверху), и команда `стоп`. Оба раза
 * узлу больше нечего делать, но процесс хозяина держит открытый stdin, и без
 * этой строки узел, остановившийся по своему же решению, висел бы живым — то
 * есть врал бы про собственный исход. `process.exit` здесь не годится: он
 * оборвал бы недописанный журнал, а журнал — это то, чем испытание смотрит.
 */
const сказать = (запись) => {
  process.stdout.write(`${JSON.stringify(запись)}\n`)
  if (запись.в === "конец") process.stdin.pause()
}

/* Узел, которому нечего нести или у которого процесс без места, обязан
   отказать НАЗВАННО и в журнал, а не выпасть наружу следом вызовов: журнал —
   это то, чем за узлом смотрят, и молчаливая смерть в нём неотличима от
   «поднялся и работает». */
let узел = null
try {
  узел = создатьУзел({
    имя: доводы.я,
    модуль,
    хэш,
    размещение,
    семя: доводы.семя ?? 0,
    срок: доводы.срок ?? СРОКИ.срок,
    пульс: доводы.пульс ?? СРОКИ.пульс,
    пауза: доводы.пауза ?? СРОКИ.пауза,
    знакомство: доводы.знакомство ?? СРОКИ.знакомство,
    сказать,
  })
} catch (беда) {
  сказать({ в: "беда", узел: доводы.я, текст: беда.message })
  process.exit(1)
}

const адрес = await узел.слушать(хозяин, порт)
сказать({
  в: "поднят",
  узел: доводы.я,
  /* Часы узла в записи о подъёме — не украшение: срок первого знакомства
     заводится сразу после неё, и сверять его наблюдателю больше не с чем.
     Собственные часы наблюдателя тут не годятся — они идут позже. */
  часы: Date.now(),
  адрес: `${адрес.address}:${адрес.port}`,
  хэш: хэш.slice(0, 12),
  свои: Object.entries(гдеПроцесс).filter(([, где]) => где === доводы.я).map(([имя]) => имя),
  чужие: Object.entries(гдеПроцесс).filter(([, где]) => где !== доводы.я).map(([имя]) => имя),
  сроки: {
    пульс: доводы.пульс ?? СРОКИ.пульс,
    срок: доводы.срок ?? СРОКИ.срок,
    пауза: доводы.пауза ?? СРОКИ.пауза,
    знакомство: доводы.знакомство ?? СРОКИ.знакомство,
  },
})
узел.звонить()

/* ── команды снаружи ────────────────────────────────────────────────────── */

let хвост = ""
process.stdin.setEncoding("utf8")
process.stdin.on("data", (кусок) => {
  хвост += кусок
  let край = хвост.indexOf("\n")
  while (край >= 0) {
    const строка = хвост.slice(0, край).trim()
    хвост = хвост.slice(край + 1)
    if (строка !== "") {
      let команда = null
      try {
        команда = JSON.parse(строка)
      } catch (беда) {
        сказать({ в: "беда", узел: доводы.я, текст: `команда не разобрана: ${беда.message}` })
        край = хвост.indexOf("\n")
        continue
      }
      исполнить(команда)
    }
    край = хвост.indexOf("\n")
  }
})

function исполнить(команда) {
  switch (команда?.в) {
    case "вбросить": {
      try {
        const итог = узел.вбросить(String(команда.кому), команда.что)
        сказать({ в: "вброшено", узел: доводы.я, кому: команда.кому, итог })
      } catch (беда) {
        сказать({ в: "беда", узел: доводы.я, текст: `вбросить не вышло: ${беда.message}` })
      }
      return
    }
    case "состояния":
      сказать({ в: "состояния", узел: доводы.я, метка: команда.метка ?? null, это: узел.состояния() })
      return
    case "связи":
      сказать({ в: "связи", узел: доводы.я, метка: команда.метка ?? null, это: узел.связи() })
      return
    case "стоп":
      сказать({ в: "конец", узел: доводы.я, исход: узел.исход() === "работает" ? "остановлен снаружи" : узел.исход() })
      узел.остановиться()
      process.stdin.pause()
      return
    default:
      сказать({ в: "беда", узел: доводы.я, текст: `неизвестная команда «${String(команда?.в)}»` })
  }
}

process.on("SIGTERM", () => { узел.остановиться(); process.exit(0) })
process.on("SIGINT", () => { узел.остановиться(); process.exit(0) })
