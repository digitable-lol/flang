"""Конец связи узла — на ВТОРОЙ цели печати. Замер, а не пример.

Вопрос, ради которого это написано, один: сколько стоит мир на новой цели,
если решение о мире печатает компилятор. Предшественник оценил цену второй
цели в 459 строк и оценку не проверял. Здесь она не оценивается, а СЧИТАЕТСЯ:
ниже — всё, что понадобилось, и ни строкой больше.

Этот файл НЕ узел. У узла есть таблица процессов и планировщик, и они на flang
не выражаются по названной причине: адресат `отправить` обязан быть литералом,
а узел кладёт письмо процессу, чьё имя приехало с провода. Здесь только СЛОЙ
СВЯЗИ — сокет, часы, таймеры, — то есть ровно то, что предшественник назвал
непереносимым.

Решений здесь нет ни одного. Рукопожатие, сроки, молчание, разрыв, повторный
звонок — всё это считает `svyaz_uzlov.py`, напечатанный компилятором из
`flang/conc/svyaz.flang` в цель python. Тот же исходник печатается в остальные
семь целей и отвечает там так же (`flang/test/svyaz-celi.test.mjs`, 8256 сверок).

Работа этого файла — три вещи и только они:

  1. держать сокет, часы и два срока;
  2. переводить события сокета в 10 вариантов «Что случилось со связью»;
  3. исполнять 7 велений, которые вернул «Шаг связи».

Запуск (журнал построчным JSON на stdout, как у узла на JavaScript):

    python3 peer.py --я счёт --сосед 127.0.0.1:9002 --хэш <hex> \
        [--срок 1000] [--пульс 200] [--пауза 250] [--письмо '{...}'] [--жить 5]
"""
import json
import os
import socket
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svyaz_uzlov as реш  # печать компилятора: решения о связи
import flang_runtime as rt

ЦЕЛЬ = "python"

# ── граница значений: снаружи Python, внутри значения flang ────────────────
# Пять строк на весь перевод. Значение flang — это тег плюс нагрузка, и наружу
# нужны ровно три вида: строка, число, признак; внутрь — поле записи и список.
вн = lambda это: это.data                                    # значение → Python
поле = lambda зн, имя: зн.data[имя]                          # поле записи
велено = rt.list_items                                       # список велений


def сказать(запись):
    sys.stdout.write(json.dumps(запись, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def часы():
    """Единственное чтение часов во всём файле."""
    return float(int(time.time() * 1000))


class Конец:
    """Один конец связи: сокет, буфер и состояние, посчитанное эталоном."""

    def __init__(self, я, кто, адрес, хэш, срок, пульс, пауза):
        self.я, self.кто, self.адрес, self.хэш = я, кто, адрес, хэш
        self.срок, self.пульс, self.пауза = срок, пульс, пауза
        self.ctx = реш.new_context()
        self.связь = реш.fn_svyaz_zanovo(
            self.ctx, rt.text(кто), rt.flag(False), rt.flag(False),
            rt.flag(False), rt.flag(False), rt.number(0.0),
        )
        self.сокет = None
        self.хвост = ""
        self.работает = True
        self.когдаЗвонить = 0.0
        self.последнийПульс = 0.0
        self.писем = 0

    # ── мир: три вызова, и все три здесь ──────────────────────────────────
    def позвонить(self):
        if self.сокет is not None or not self.работает:
            return
        хозяин, порт = self.адрес.rsplit(":", 1)
        сок = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        сок.settimeout(1.0)
        try:
            сок.connect((хозяин, int(порт)))
        except OSError:
            сок.close()
            self.случилось(реш.v_zvonok_ne_udalsya())
            return
        сок.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        сок.setblocking(False)
        self.сокет = сок
        self.случилось(реш.v_soket_zavyolsya(rt.number(часы())))

    def послать(self, кадр):
        """Кадр в провод. Что ПОЗВОЛЕНО слать до рукопожатия, решает не этот
        код: «привет» уходит велением, остальное — только когда связь готова."""
        if self.сокет is None:
            return
        if not вн(поле(self.связь, "готова")) and кадр["в"] != "привет":
            return
        try:
            self.сокет.sendall((json.dumps(кадр, ensure_ascii=False) + "\n").encode("utf-8"))
        except OSError:
            self.случилось(реш.v_soket_otkazal(rt.text("запись в сокет отказала")))

    def прибрать(self):
        if self.сокет is not None:
            try:
                self.сокет.close()
            except OSError:
                pass
            self.сокет = None
        self.хвост = ""

    # ── перевод: событие мира → вариант эталона ───────────────────────────
    def прочесть(self):
        try:
            кусок = self.сокет.recv(65536)
        except BlockingIOError:
            return
        except OSError:
            self.случилось(реш.v_soket_otkazal(rt.text("сокет отказал")))
            return
        if кусок == b"":
            self.случилось(реш.v_soket_otkazal(rt.text("сокет закрыт")))
            return
        self.случилось(реш.v_bayty_prishli(rt.number(часы())))
        self.хвост += кусок.decode("utf-8", "replace")
        while "\n" in self.хвост and self.сокет is not None:
            строка, self.хвост = self.хвост.split("\n", 1)
            if строка.strip() == "":
                continue
            try:
                кадр = json.loads(строка)
            except ValueError:
                self.случилось(реш.v_soket_otkazal(rt.text("кадр не разобран")))
                return
            self.кадром(кадр)

    def кадром(self, кадр):
        вид = кадр.get("в")
        if вид == "привет":
            self.случилось(реш.v_prishyol_privet(rt.text(str(кадр.get("узел", ""))), rt.text(str(кадр.get("хэш", "")))))
        elif вид == "пульс":
            self.случилось(реш.v_prishyol_puls())
        elif вид == "письмо":
            self.случилось(реш.v_prishlo_pismo(rt.text(str(кадр.get("кому", "")))))
        elif вид == "отбой":
            self.случилось(реш.v_prishyol_otboy(rt.text(str(кадр.get("почему", "без причины")))))
        else:
            self.случилось(реш.v_prishyol_chuzhoy_kadr(rt.text(str(вид))))

    # ── единственная дорога от мира к решению ─────────────────────────────
    def случилось(self, событие):
        ход = реш.fn_shag_svyazi(
            self.ctx, self.связь, событие, rt.text(self.хэш),
            rt.number(float(self.срок)), rt.number(float(self.пауза)), rt.flag(self.работает),
        )
        self.связь = поле(ход, "связь")
        for веление in велено(поле(ход, "веления")):
            self.исполнить(веление)

    def исполнить(self, веление):
        имя = веление.name
        поля = {ключ: вн(зн) for ключ, зн in веление.data.items()}
        if имя == "Послать привет":
            self.послать({"в": "привет", "узел": self.я, "хэш": self.хэш})
        elif имя == "Прибрать":
            self.прибрать()
        elif имя == "Связь заведена":
            сказать({"в": "связь", "узел": self.я, "цель": ЦЕЛЬ, "сосед": self.кто, "что": "заведена"})
        elif имя == "Связь отвергнута":
            сказать({"в": "связь", "узел": self.я, "цель": ЦЕЛЬ, "сосед": поля["сосед"],
                     "что": "отвергнута", "почему": поля["почему"]})
        elif имя == "Доложить о потере":
            сказать({"в": "связь", "узел": self.я, "цель": ЦЕЛЬ, "сосед": self.кто,
                     "что": "потеряна", "почему": поля["почему"]})
        elif имя == "Доставить письмо":
            self.писем += 1
            сказать({"в": "письмо", "узел": self.я, "цель": ЦЕЛЬ, "кому": поля["кому"], "всего": self.писем})
        elif имя == "Позвонить снова":
            self.когдаЗвонить = часы() + float(поля["пауза"])
        else:
            raise SystemExit(f"конец связи не знает веления «{имя}»")

    # ── круг: сокет, часы, два срока ──────────────────────────────────────
    def круг(self, доколе, письмо):
        период = max(20, self.срок // 5)
        следующийСторож = часы() + период
        послано = письмо is None
        while часы() < доколе:
            if self.сокет is None and часы() >= self.когдаЗвонить:
                self.позвонить()
            ждать = min(период, self.пульс) / 1000.0
            if self.сокет is not None:
                готовы = __import__("select").select([self.сокет], [], [], ждать)[0]
                if готовы:
                    self.прочесть()
            else:
                time.sleep(ждать)
            сейчас = часы()
            if self.сокет is not None and вн(поле(self.связь, "готова")):
                if not послано:
                    self.послать(письмо)
                    послано = True
                if сейчас - self.последнийПульс >= self.пульс:
                    self.последнийПульс = сейчас
                    self.послать({"в": "пульс"})
            if сейчас >= следующийСторож:
                следующийСторож = сейчас + период
                if self.сокет is not None:
                    self.случилось(реш.v_storozh_prosnulsya(rt.number(сейчас)))


def главное(доводы):
    ключи = {}
    имя = None
    for довод in доводы:
        if довод.startswith("--"):
            имя = довод[2:]
            ключи[имя] = True
        elif имя is not None:
            ключи[имя] = довод
            имя = None
    конец = Конец(
        ключи["я"], ключи.get("сосед-имя", "учёт"), ключи["сосед"], ключи["хэш"],
        int(ключи.get("срок", 1000)), int(ключи.get("пульс", 200)), int(ключи.get("пауза", 250)),
    )
    письмо = json.loads(ключи["письмо"]) if "письмо" in ключи and ключи["письмо"] is not True else None
    сказать({"в": "поднят", "узел": конец.я, "цель": ЦЕЛЬ, "сосед": конец.адрес,
             "хэш": конец.хэш[:12], "сроки": {"пульс": конец.пульс, "срок": конец.срок, "пауза": конец.пауза}})
    конец.круг(часы() + float(ключи.get("жить", 5)) * 1000.0, письмо)
    сказать({"в": "конец", "узел": конец.я, "цель": ЦЕЛЬ,
             "готова": вн(поле(конец.связь, "готова")), "виделись": вн(поле(конец.связь, "виделись"))})


if __name__ == "__main__":
    главное(sys.argv[1:])
