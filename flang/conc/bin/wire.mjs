/**
 * Провод: связь между двумя узлами, которую можно порвать снаружи.
 *
 * Зачем он вообще нужен, если можно убить узел. Затем, что «узел умер» и «связь
 * порвалась» — РАЗНЫЕ события, и вся честность `flang/conc/DISTRIBUTED.md`
 * держится на том, что различить их нечем. Испытание, которое рвёт связь
 * убийством узла, проверяет только первое и молча притворяется, что проверило
 * второе. Здесь оба узла остаются живыми и здоровыми, а рвётся ровно провод —
 * и тогда видно, что узел «счёт» объявил отказ, а узел «учёт» в этот момент
 * работал как ни в чём не бывало. Это и есть разделение мозга, предъявленное, а
 * не описанное.
 *
 *   node flang/conc/bin/wire.mjs --слушать 127.0.0.1:9001 --на 127.0.0.1:9002
 *
 * Команды в stdin, по строке JSON:
 *
 *   {"в":"резать"}   порвать всё и не принимать новых: провод перекушен;
 *   {"в":"чинить"}   принимать снова;
 *   {"в":"морозить"} НЕ передавать байты ни в одну сторону, но сокеты держать
 *                    открытыми и всё копить: узел жив, отвечает, просто «медленный»;
 *   {"в":"оттаять"}  отдать накопленное;
 *   {"в":"стоп"}     закончить.
 *
 * «Морозить» — самая важная из пяти, и ради неё провод и написан. Перекушенный
 * провод честно закрывает сокет, и отказ виден мгновенно и без всякого срока;
 * замороженный не даёт НИ ОДНОГО признака, кроме тишины, — а тишина неотличима
 * от медленного узла по построению. Испытание на замороженном проводе проверяет
 * не «умеем ли мы заметить закрытый сокет», а именно выбранный срок.
 */
import { createConnection, createServer } from "node:net"

function разобратьДоводы(доводы) {
  const итог = {}
  for (let i = 0; i < доводы.length; i += 1) {
    if (доводы[i] === "--слушать") { итог.слушать = доводы[i + 1]; i += 1; continue }
    if (доводы[i] === "--на") { итог.на = доводы[i + 1]; i += 1; continue }
    throw new Error(`неизвестный довод «${доводы[i]}»`)
  }
  if (итог.слушать === undefined || итог.на === undefined) {
    throw new Error("нужны --слушать хозяин:порт и --на хозяин:порт")
  }
  return итог
}

function разделитьАдрес(строка) {
  const край = String(строка).lastIndexOf(":")
  if (край < 0) throw new Error(`адрес «${строка}» без порта`)
  return [строка.slice(0, край), Number(строка.slice(край + 1))]
}

const доводы = разобратьДоводы(process.argv.slice(2))
const [хозяинСлушать, портСлушать] = разделитьАдрес(доводы.слушать)
const [хозяинНа, портНа] = разделитьАдрес(доводы.на)

/* Часы в каждой записи: испытание меряет по ним, через сколько после заморозки
   узел объявил отказ, а «через сколько» — это и есть проверяемое число. */
const сказать = (запись) => process.stdout.write(`${JSON.stringify({ в: "провод", часы: Date.now(), ...запись })}\n`)

/** Пары сокетов: слева тот, кто позвонил нам, справа тот, кому звоним мы. */
const пары = new Set()
let принимаем = true
let заморожен = false

const сервер = createServer((слева) => {
  if (!принимаем) {
    сказать({ что: "отказано", почему: "провод перекушен" })
    слева.destroy()
    return
  }
  const справа = createConnection({ host: хозяинНа, port: портНа })
  const пара = { слева, справа, копилка: [], живая: true }
  пары.add(пара)
  слева.setNoDelay(true)
  справа.setNoDelay(true)

  const переслать = (куда, кусок) => {
    if (заморожен) { пара.копилка.push([куда, кусок]); return }
    if (!куда.destroyed) куда.write(кусок)
  }
  слева.on("data", (кусок) => переслать(справа, кусок))
  справа.on("data", (кусок) => переслать(слева, кусок))

  const закрыть = (почему) => {
    if (!пара.живая) return
    пара.живая = false
    пары.delete(пара)
    слева.destroy()
    справа.destroy()
    сказать({ что: "пара закрыта", почему })
  }
  слева.on("error", () => закрыть("слева отказал"))
  справа.on("error", () => закрыть("справа отказал"))
  слева.on("close", () => закрыть("слева закрыт"))
  справа.on("close", () => закрыть("справа закрыт"))
  справа.on("connect", () => сказать({ что: "пара заведена", пар: пары.size }))
})

сервер.listen(портСлушать, хозяинСлушать, () => {
  const адрес = сервер.address()
  сказать({ что: "поднят", адрес: `${адрес.address}:${адрес.port}`, на: `${хозяинНа}:${портНа}` })
})

function резать() {
  принимаем = false
  const было = пары.size
  for (const пара of [...пары]) {
    пара.живая = false
    пары.delete(пара)
    пара.слева.destroy()
    пара.справа.destroy()
  }
  сказать({ что: "перекушен", пар: было })
}

function оттаять() {
  заморожен = false
  let отдано = 0
  for (const пара of пары) {
    for (const [куда, кусок] of пара.копилка) {
      if (!куда.destroyed) { куда.write(кусок); отдано += 1 }
    }
    пара.копилка = []
  }
  сказать({ что: "оттаял", отдано })
}

let хвост = ""
process.stdin.setEncoding("utf8")
process.stdin.on("data", (кусок) => {
  хвост += кусок
  let край = хвост.indexOf("\n")
  while (край >= 0) {
    const строка = хвост.slice(0, край).trim()
    хвост = хвост.slice(край + 1)
    if (строка !== "") {
      let команда = null
      try { команда = JSON.parse(строка) } catch { команда = { в: строка } }
      switch (команда.в) {
        case "резать": резать(); break
        case "чинить": принимаем = true; сказать({ что: "починен" }); break
        case "морозить": заморожен = true; сказать({ что: "заморожен", пар: пары.size }); break
        case "оттаять": оттаять(); break
        case "стоп":
          резать()
          сервер.close()
          process.stdin.pause()
          сказать({ что: "конец" })
          break
        default: сказать({ что: "беда", почему: `неизвестная команда «${String(команда.в)}»` })
      }
    }
    край = хвост.indexOf("\n")
  }
})

process.on("SIGTERM", () => { резать(); сервер.close(); process.exit(0) })
