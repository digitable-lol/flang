/**
 * Кодирование значений — метка на каждом значении, а не «похоже на JSON».
 *
 * Голый JSON здесь не годится по двум причинам, и обе настоящие. Первая: запись
 * flang — обычный объект, вариант — тоже объект, и различить их в JSON нечем,
 * кроме служебного поля, которое может столкнуться с полем автора (имена полей
 * в flang произвольны). Вторая: числа языка — IEEE-754, а JSON не умеет ни
 * `NaN`, ни бесконечностей, ни минус нуля, и молча превратил бы их в `null`.
 *
 * Поэтому у каждого значения метка одной буквой:
 * `ч` число, `с` строка, `п` признак, `н` ничто, `л` список, `з` запись,
 * `в` вариант.
 *
 * Цена — размер, и она СЧИТАНА, а не оценена на глаз, потому что оценка на глаз
 * здесь ошиблась бы в обе стороны. Кадр с вариантом «записать» и строкой «142»:
 * 76 байт с метками против 85 без них — метки ДЕШЕВЛЕ, потому что слова
 * `variant` и `fields` длиннее любой из них. Запись `{всего, подтверждено}`:
 * 48 байт против 30, то есть в 1,6 раза дороже. Общего множителя нет, и
 * называть его было бы выдумкой.
 */
export function закодировать(значение) {
  if (значение === null || значение === undefined) return ["н"]
  if (typeof значение === "boolean") return ["п", значение]
  if (typeof значение === "string") return ["с", значение]
  if (typeof значение === "number") {
    if (Number.isNaN(значение)) return ["ч", "NaN"]
    if (значение === Infinity) return ["ч", "+∞"]
    if (значение === -Infinity) return ["ч", "-∞"]
    if (Object.is(значение, -0)) return ["ч", "-0"]
    return ["ч", значение]
  }
  if (Array.isArray(значение)) return ["л", значение.map(закодировать)]
  if (typeof значение === "object") {
    if (typeof значение.variant === "string" && значение.fields !== undefined) {
      const поля = {}
      for (const [имя, поле] of Object.entries(значение.fields)) поля[имя] = закодировать(поле)
      return ["в", значение.variant, поля]
    }
    const поля = {}
    for (const [имя, поле] of Object.entries(значение)) поля[имя] = закодировать(поле)
    return ["з", поля]
  }
  throw new Error(`нечего кодировать: ${typeof значение}`)
}

/**
 * Раскодирование — с конструкторами напечатанного модуля.
 *
 * Вариант в напечатанном JavaScript — экземпляр класса (`$FlangVariant`), а не
 * объект с полями: `разбор` проверяет его `instanceof`, и голый объект с теми же
 * полями обработчик не сопоставит ни с одним образцом (проверено:
 * `FLANG_MATCH_NOT_EXHAUSTIVE`, «разбор не покрывает значение запись {variant,
 * fields}»). Поэтому вариант обязан собираться конструктором ТОГО САМОГО модуля.
 *
 * @param {*} код закодированное значение
 * @param {Map<string, Function>} конструкторы имя варианта → конструктор модуля
 */
export function раскодировать(код, конструкторы) {
  if (!Array.isArray(код) || код.length === 0) throw new Error("не значение на проводе")
  switch (код[0]) {
    case "н": return null
    case "п": return код[1] === true
    case "с": return String(код[1])
    case "ч": {
      if (код[1] === "NaN") return NaN
      if (код[1] === "+∞") return Infinity
      if (код[1] === "-∞") return -Infinity
      if (код[1] === "-0") return -0
      return Number(код[1])
    }
    case "л": return (код[1] ?? []).map((это) => раскодировать(это, конструкторы))
    case "з": {
      const запись = {}
      for (const [имя, поле] of Object.entries(код[1] ?? {})) запись[имя] = раскодировать(поле, конструкторы)
      return запись
    }
    case "в": {
      const собрать = конструкторы.get(код[1])
      if (собрать === undefined) {
        throw new Error(`варианта «${код[1]}» в напечатанном модуле нет: письмо не от этой программы`)
      }
      const поля = {}
      for (const [имя, поле] of Object.entries(код[2] ?? {})) поля[имя] = раскодировать(поле, конструкторы)
      return собрать(поля)
    }
    default: throw new Error(`неизвестная метка значения «${код[0]}»`)
  }
}

/**
 * Словарь «имя варианта → конструктор» — пробой, а не по списку.
 *
 * Напечатанный модуль реестра типов наружу НЕ отдаёт: `concPlan()` описывает
 * процессы и надзоры, а конструкторы вариантов лежат обычными экспортами с
 * переименованными в латиницу именами (`Pribavit` — это «прибавить»). Повторять
 * здесь правило переименования значило бы завести второй источник правды о нём,
 * который разойдётся с `emit/js.mjs` на первой же правке.
 *
 * Поэтому словарь строится пробой: каждая экспортированная функция нулевой
 * арности зовётся с пустой записью полей, и если вернулся вариант — его имя
 * известно от него самого. Это безопасно: конструкторы и функции без параметров
 * в flang чисты, а `concRun` и `$newContext` исключены поимённо.
 *
 * Честная цена приёма записана в контракте: правильным решением было бы
 * попросить у `emit/js.mjs` реестр одной строкой — но `emit/js.mjs` не наш файл
 * в этой работе, и приём выбран так, чтобы не трогать печать вовсе.
 */
export function конструкторыВариантов(модуль) {
  const словарь = new Map()
  for (const [имя, значение] of Object.entries(модуль)) {
    if (typeof значение !== "function" || значение.length !== 0) continue
    if (имя === "concPlan" || имя === "$newContext") continue
    try {
      const проба = значение({})
      if (проба !== null && typeof проба === "object" && typeof проба.variant === "string") {
        словарь.set(проба.variant, значение)
      }
    } catch {
      /* Не конструктор варианта — и хорошо: проба на то и проба. */
    }
  }
  return словарь
}

