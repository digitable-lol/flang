/**
 * distributed.mjs — узел flang: тот же план, что печатает цель JavaScript, плюс
 * связь с другими узлами.
 *
 * Контракт — `flang/conc/DISTRIBUTED.md`. Здесь сделано ровно то, что там
 * помечено «сделано и испытано», и ни строкой больше: два узла, обмен
 * сообщениями через границу, надзор над связью и разрыв, который испытан, а не
 * описан (`flang/conc/distributed.test.mjs`).
 *
 * ── Что такое узел и чего он НЕ делает ──────────────────────────────────────
 *
 * Узел — процесс операционной системы, несущий ПОДМНОЖЕСТВО объявленных
 * процессов программы. Программа при этом одна и та же на всех узлах, до байта:
 * распределённость не добавила языку ни одного слова, потому что добавлять было
 * некуда — множество процессов закрыто объявлением (`породить` нет), значит имя
 * процесса уже уникально во всей программе, и адресовать по нему можно откуда
 * угодно. Кто где живёт — сказано РАЗМЕЩЕНИЕМ, данными узла, а не текстом
 * программы.
 *
 * Отсюда всё остальное устройство:
 *
 *   • процесс, размещённый здесь, — обычный процесс: состояние, ящик,
 *     обработчик из напечатанного модуля;
 *   • процесс, размещённый на другом узле, — ПРЕДСТАВИТЕЛЬ: запись в той же
 *     таблице, у которой нет ни состояния, ни ящика, ни обработчика. У него
 *     есть только связь, и он умеет ровно одно — отказать, когда связь потеряна
 *     (`FLANG_LINK_DOWN`). Тем самым надзор через границу узла не потребовал
 *     ни нового понятия, ни новой стратегии: представитель стоит в таблице
 *     процессов, значит его накрывает обычный `надзор`, объявленный в
 *     программе, обычными тремя стратегиями и обычным порогом.
 *
 * Чего узел не делает и не притворяется, что делает: не переносит процессы
 * между узлами, не маршрутизирует чужие письма (связь только прямая), не
 * повторяет доставку, не нумерует сообщения и не обнаруживает пропажу. Всё это
 * названо ведомостью контракта как «объявлено, не сделано».
 *
 * ── Почему цель печати — JavaScript ─────────────────────────────────────────
 *
 * Довод не «нам так привычнее», а счёт, и он записан в контракте целиком.
 * Коротко: напечатанный модуль ОТДАЁТ свой план (`concPlan()`) — процессы,
 * надзоры и обработчики функциями-значениями, — поэтому узлу не нужно ни одной
 * новой строки печати: `flang/src/emit/js.mjs` не тронут вовсе. Плюс сокеты в
 * стандартной библиотеке хозяина и значения того же вида, что у свидетеля.
 * Elixir дал бы распределённость даром — и вместе с ней ЧУЖИЕ ответы на три
 * вопроса, на которых такие системы ломаются; отвечать на них обязаны мы.
 *
 * ── Что общего со свидетелем, буквально ────────────────────────────────────────
 *
 * Решение надзора принимает `надзорВДействии` из `flang/src/conc.mjs` — тот же
 * код, что у прогона свидетеля, а не его копия. Разница ровно в двух подставленных
 * действиях: «перезапустить» для местного процесса — вернуть начальное
 * состояние, для представителя — завести связь заново. Порог, поддерево,
 * «передать выше» и «отказ дошёл доверху» приезжают из свидетеля целиком.
 *
 * ── Чего у узла нет по сравнению с прогоном ─────────────────────────────────
 *
 * Виртуального времени: узел живёт по настоящим часам, потому что двум узлам
 * нечем разделить одно виртуальное время. Значит `через` — настоящая задержка, а
 * окно порога отказов — настоящие миллисекунды (у прогона это пробеги).
 * Воспроизводимости по семени: семя упорядочивает готовые процессы ВНУТРИ узла,
 * а порядок прихода писем выбирает сеть. Счёта витков на пробег: предел ставится
 * через `$newContext` напечатанного модуля, а показание счётчика модуль наружу
 * не отдаёт.
 */

