/** Разборщик потока в кадры: TCP не сохраняет границ записей, разделитель — \n. */
function собиратель(наКадр, наБеду) {
  let хвост = ""
  return (кусок) => {
    хвост += кусок
    let край = хвост.indexOf("\n")
    while (край >= 0) {
      const строка = хвост.slice(0, край)
      хвост = хвост.slice(край + 1)
      if (строка.trim() !== "") {
        let кадр = null
        try {
          кадр = JSON.parse(строка)
        } catch (беда) {
          наБеду(`кадр не разобран: ${беда.message}`)
          return
        }
        наКадр(кадр)
      }
      край = хвост.indexOf("\n")
    }
  }
}

