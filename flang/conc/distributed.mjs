/**
 * Надзоры напечатанного плана — в том виде, в каком их читает свидетель.
 *
 * План печатает надзор парами (`процессы: [[имя, стратегия]]`), а
 * `построитьНадзор` читает разбор (`watch: [{process, strategy}]`). Перевод
 * здесь, в шесть строк, — и это ВЕСЬ перевод: дерево, порог и «выше» считает
 * свидетельский код, а не второй его экземпляр.
 */
function надзорыИзПлана(план) {
  return {
    supervisors: (план.надзоры ?? []).map((узел) => ({
      name: узел.имя,
      watch: (узел.процессы ?? []).map(([process, strategy]) => ({ process, strategy })),
      nested: (узел.вложенные ?? []).map(([supervisor, strategy]) => ({ supervisor, strategy })),
      threshold: узел.порог === null || узел.порог === undefined
        ? null
        : { failures: узел.порог.отказов, window: узел.порог.окно, otherwise: узел.порог.иначе },
    })),
  }
}

/**
 * Завести узел.
 *
 * @param {object} настройки
 * @param {string} настройки.имя имя этого узла
 * @param {object} настройки.модуль напечатанный модуль программы
 * @param {string} настройки.хэш хэш напечатанного текста — рукопожатие
 * @param {{процессы: Record<string,string>, звонить: Record<string,string>}} настройки.размещение
 * @param {number} [настройки.семя] чередование готовых процессов ВНУТРИ узла
 * @param {(запись: object) => void} настройки.сказать журнал наблюдателю
 * @returns {object} узел: `слушать`, `вбросить`, `состояния`, `остановиться`
 */
export function создатьУзел(настройки) {
  const имяУзла = настройки.имя
  const модуль = настройки.модуль
  /* Плана в модуле может не быть вовсе: печать кладёт планировщик и `concPlan`
     ТОЛЬКО в программу с процессами (`emit/js.mjs`). Узел без плана — это не
     «пустой узел», а программа, поднятая не туда, и сказать об этом надо
     здесь, а не отказом «concPlan is not a function» из чужого модуля. */
  if (typeof модуль.concPlan !== "function") {
    throw new Error("в программе нет ни одного процесса: узлу нечего нести")
  }
  const план = модуль.concPlan()
  const хэш = настройки.хэш
  const размещение = настройки.размещение
  const сказать = настройки.сказать ?? (() => {})
  const пульс = настройки.пульс ?? СРОКИ.пульс
  const срок = настройки.срок ?? СРОКИ.срок
  const пауза = настройки.пауза ?? СРОКИ.пауза
  const часы = настройки.часы ?? (() => Date.now())
  const случайное = makeRandom(настройки.семя ?? 0)
  const конструкторы = конструкторыВариантов(модуль)

  /* ── таблица процессов: свои и представители ───────────────────────────
     Один порядок на всё — порядок объявления, ровно как у свидетеля: очередь
     готовых, перечисление состояний, журнал. */
  if (план.процессы.length === 0) {
    /* Тот же отказ, что у прогона свидетеля, и по той же причине: узел без
       процессов — это не «пустой узел», а программа, поднятая не туда. */
    throw new Error("в программе нет ни одного процесса: узлу нечего нести")
  }
  const порядок = план.процессы.map((узел) => узел.имя)
  const процессы = new Map()
  const свои = []
  for (const узел of план.процессы) {
    const где = размещение.процессы[узел.имя]
    if (где === undefined) {
      throw new Error(
        `размещение молчит про процесс «${узел.имя}»: у каждого объявленного процесса ` +
          `обязан быть ровно один узел, иначе имя не значит ничего`,
      )
    }
    if (где === имяУзла) {
      свои.push(узел.имя)
      процессы.set(узел.имя, {
        вид: "свой",
        имя: узел.имя,
        узел,
        начальное: узел.завести(),
        состояние: null,
        ящик: [],
        начатые: [],
        жив: true,
        причина: null,
        потолок: Number.isInteger(узел.ящик) && узел.ящик > 0 ? узел.ящик : null,
        вЛёте: 0,
      })
      процессы.get(узел.имя).состояние = процессы.get(узел.имя).начальное
    } else {
      процессы.set(узел.имя, {
        вид: "представитель",
        имя: узел.имя,
        накаком: где,
        /* «Жив» у представителя значит «связью ещё занимаемся»: надзор мог
           решить «остановить», и тогда звонить больше некуда и незачем. */
        жив: true,
        причина: null,
      })
    }
  }

  /* ── связи ──────────────────────────────────────────────────────────── */
  const связи = new Map()
  const связь = (кто) => {
    let это = связи.get(кто)
    if (это === undefined) {
      /* Ручки МИРА и только они: сокет и два таймера. Всё, по чему связь
         принимает решения — готова ли, виделись ли, ждём ли решения надзора,
         когда пришёл последний байт, — живёт в поле `состояние` значением
         эталона «Связь» и меняется только тем, что вернул «Шаг связи».
         Разделение не косметическое: раньше эти пять полей меняли семь разных
         замыканий, и порядок изменений был свойством файла, а не программы. */
      это = {
        кто,
        сокет: null,
        сторож: null,
        сердце: null,
        состояние: svyazZanovo(кто, false, false, false, false, 0),
      }
      связи.set(кто, это)
    }
    return это
  }

  let работает = true
  let исход = "работает"
  let сервер = null
  /* Тело письма, пока эталон решает, кому его нести. Эталон называет АДРЕСАТА,
     а груз оставляет узлу: раскодировать письмо можно только конструкторами
     напечатанного модуля программы, и они не его дело. */
  let последнееПисьмо = null

  /* ── надзор: тот же код, что у прогона свидетеля ─────────────────────────── */
  const надзор = построитьНадзор(надзорыИзПлана(план), процессы)
  const суд = надзорВДействии(надзор, {
    перезапустить: (имя) => {
      const это = процессы.get(имя)
      if (это === undefined) return
      if (это.вид === "свой") {
        /* Перезапуск точен: то же самое значение, что при первом запуске. Ящик
           не трогается — решение свидетеля, и менять его на узле не за что. */
        это.состояние = это.начальное
        это.жив = true
        это.причина = null
        разбудить()
      } else {
        это.жив = true
        это.причина = null
        /* «Перезапустить» для представителя — завести связь заново. Через
           паузу: без неё порванный провод сжёг бы порог за микросекунды.
           Снятие `ждёмРешения` — здесь и только здесь: решение принято, значит
           следующий неудавшийся звонок будет НОВЫМ отказом, а не эхом старого. */
        const канал = связь(это.накаком)
        канал.состояние = svyazZanovo(
          канал.кто, канал.состояние["готова"], канал.состояние["звоним"],
          канал.состояние["виделись"], false, канал.состояние["последний байт"],
        )
        if (!канал.состояние["готова"] && !канал.состояние["звоним"]) {
          const отсрочка = setTimeout(() => позвонить(это.накаком), пауза)
          отсрочка.unref?.()
        }
      }
    },
    остановить: (имя, причина) => {
      const это = процессы.get(имя)
      if (это === undefined) return
      это.жив = false
      это.причина = причина
    },
  })

  /* ── журнал ─────────────────────────────────────────────────────────── */
  const запись = (вид, поля) => сказать({ в: вид, узел: имяУзла, часы: часы(), ...поля })

  /* ── доставка ───────────────────────────────────────────────────────── */

  /**
   * Положить сообщение в местный ящик. Исходы те же три, что у свидетеля.
   */
  const положить = (имя, сообщение, вПередЯщика, местоЗанято = false, начатое = false) => {
    const это = процессы.get(имя)
    if (это === undefined || это.вид !== "свой" || !это.жив) return "некому"
    if (!местоЗанято && это.потолок !== null && это.ящик.length + это.вЛёте >= это.потолок) return "полон"
    if (вПередЯщика) {
      это.ящик.unshift(сообщение)
      это.начатые.unshift(начатое)
    } else {
      это.ящик.push(сообщение)
      это.начатые.push(начатое)
    }
    разбудить()
    return "легло"
  }

  /**
   * Отправить — не глядя, свой адресат или чужой.
   *
   * Ровно здесь живёт «не больше одного»: письмо чужому уходит в сокет и
   * НИКТО не ждёт подтверждения. Порванная связь, мёртвый представитель,
   * несуществующее имя — всё это «некому», то есть ровно то, что делает
   * свидетель с отправкой мёртвому процессу. Разного смысла у `отправить`
   * в зависимости от размещения быть не должно.
   */
  const отправить = (кому, что) => {
    const это = процессы.get(кому)
    if (это === undefined) return "некому"
    if (это.вид === "свой") return положить(кому, что, false)
    if (!это.жив) return "некому"
    const канал = связи.get(это.накаком)
    if (канал === undefined || !канал.состояние["готова"]) {
      запись("потеря", { кому, почему: "связи нет", узелАдресата: это.накаком })
      return "некому"
    }
    послать(канал, { в: КАДР.письмо, кому, что: закодировать(что) })
    return "легло"
  }

  /* ── планировщик ────────────────────────────────────────────────────── */

  let разбужен = false
  const разбудить = () => {
    if (разбужен || !работает) return
    разбужен = true
    setImmediate(() => {
      разбужен = false
      шаг()
    })
  }

  /**
   * Один пробег — и уступить событийному циклу.
   *
   * Вот главное отличие от прогона свидетеля: тот крутит цикл до покоя, а узел
   * ОБЯЗАН вернуть управление хозяину после каждого пробега — иначе пульс не
   * уйдёт, письмо не придёт, и связь порвалась бы сама собой от собственной
   * занятости. Наблюдаемая семантика от этого не меняется: чередование
   * атомарных пробегов остаётся чередованием атомарных пробегов.
   */
  const шаг = () => {
    if (!работает) return
    const готовые = свои.filter((имя) => {
      const это = процессы.get(имя)
      return это.жив && это.ящик.length > 0
    })
    if (готовые.length === 0) return

    const имя = готовые[Math.floor(случайное() * готовые.length)]
    const это = процессы.get(имя)
    const сообщение = это.ящик.shift()
    это.начатые.shift()
    const когда = часы()

    const запас = это.узел.тотальный || !(это.узел.запас > 0) ? undefined : это.узел.запас
    let отказ = null
    let отклик = null
    try {
      /* Предел витков ставится тем же прибором, что у обычной программы:
         счётчик модуля. Показание наружу модуль не отдаёт, поэтому витков на
         пробег у узла в журнале нет — названо в контракте. */
      модуль.$newContext(запас === undefined ? {} : { maxSteps: запас })
      отклик = это.узел.вызвать(это.состояние, сообщение)
    } catch (ошибка) {
      const код = typeof ошибка?.code === "string" ? ошибка.code : "FLANG_INTERNAL"
      const бюджет = код === "FLANG_RECURSION_LIMIT" && !это.узел.тотальный
      отказ = { код: бюджет ? "FLANG_BUDGET_EXHAUSTED" : код, текст: String(ошибка?.message ?? ошибка) }
    }

    if (отказ === null) {
      const беда = разобратьОтклик(отклик, { handler: это.узел.обработчик })
      if (беда !== null) отказ = { код: "FLANG_PROCESS", текст: беда }
    }

    if (отказ === null) {
      это.состояние = отклик["состояние"]
      запись("пробег", { процесс: имя, исход: "обработано" })
      for (const действие of отклик["действия"]) {
        const вид = действие?.variant
        if (вид === "отправить") {
          const кому = String(действие.fields["кому"])
          if (отправить(кому, действие.fields["что"]) === "полон") {
            отказ = отказ ?? { код: MAILBOX_FULL_CODE, текст: `ящик процесса «${кому}» полон` }
          }
          continue
        }
        if (вид === "через") {
          const кому = String(действие.fields["кому"])
          const что = действие.fields["что"]
          /* Задержка настоящая: виртуального времени у узла нет. */
          setTimeout(() => {
            if (!работает) return
            отправить(кому, что)
          }, Number(действие.fields["задержка"])).unref?.()
          continue
        }
        if (вид === "отложить") {
          это.ящик.push(сообщение)
          это.начатые.push(true)
          continue
        }
        if (вид === "продолжить") {
          это.ящик.unshift(сообщение)
          это.начатые.unshift(true)
          continue
        }
        if (вид === "остановить") {
          const почему = String(действие.fields["почему"])
          это.жив = false
          это.причина = почему
          if (почему !== NORMAL_STOP) отказ = отказ ?? { код: STOPPED_CODE, текст: почему }
          else запись("пробег", { процесс: имя, исход: "остановлено" })
          continue
        }
      }
    }

    if (отказ !== null) {
      это.жив = false
      это.причина = отказ.код
      уронить(имя, отказ.код, отказ.текст, когда)
    }
    разбудить()
  }

  /**
   * Отказ — местного процесса или представителя — уходит в тот же надзор.
   *
   * Одна дорога на оба вида отказа, и это не экономия строк: две дороги
   * разошлись бы, и «надзор через границу узла» перестал бы значить то же
   * самое, что надзор внутри узла.
   */
  const уронить = (имя, код, текст, когда) => {
    запись("отказ", { процесс: имя, код, текст })
    const было = суд.решения.length
    const итог = суд.применить(имя, код, когда)
    for (const решение of суд.решения.slice(было)) {
      запись("решение", {
        процесс: решение.процесс,
        надзор: решение.надзор,
        стратегия: решение.стратегия,
        код: решение.код,
      })
    }
    if (итог.доверху) {
      исход = "отказ дошёл доверху"
      запись("конец", { исход, наверх: суд.наверх() })
      остановиться()
    }
  }

  /* ── связь: завести, держать, потерять ──────────────────────────────── */

  const послать = (канал, кадр) => {
    if (канал.сокет === null) return
    /* До рукопожатия по проводу уходит только само рукопожатие: письмо,
       посланное узлу, который ещё не назвался, ушло бы неизвестно кому. */
    if (!канал.состояние["готова"] && кадр.в !== КАДР.привет) return
    try {
      канал.сокет.write(`${JSON.stringify(кадр)}\n`)
    } catch {
      случилось(канал, SoketOtkazal({ "почему": "запись в сокет отказала" }))
    }
  }

  /** Снять сокет и сторожей — без единого решения надзора: это уборка.
      Поля решения здесь больше не трогаются: их ставит «Шаг связи». */
  const прибрать = (канал) => {
    if (канал.сторож !== null) { clearInterval(канал.сторож); канал.сторож = null }
    if (канал.сердце !== null) { clearInterval(канал.сердце); канал.сердце = null }
    if (канал.сокет !== null) {
      const сокет = канал.сокет
      канал.сокет = null
      сокет.removeAllListeners()
      сокет.destroy()
    }
  }

  const сторожить = (канал) => {
    if (канал.сторож !== null) clearInterval(канал.сторож)
    if (канал.сердце !== null) clearInterval(канал.сердце)
    канал.сердце = setInterval(() => послать(канал, { в: КАДР.пульс }), пульс)
    канал.сердце.unref?.()
    /* Проверять чаще, чем срок: иначе объявленный срок в 1000 мс на деле
       означал бы до 2000 мс — «через сколько» перестало бы быть числом. Само
       СРАВНЕНИЕ молчания со сроком здесь не считается: его считает эталон,
       а таймер только будит. */
    канал.сторож = setInterval(() => случилось(канал, StorozhProsnulsya({ "сейчас": часы() })),
      Math.max(20, Math.floor(срок / 5)))
    канал.сторож.unref?.()
  }

  /** Повесить на сокет разбор кадров, сторожа и сердце. Одна дорога на оба
      конца связи: тот, кто позвонил, и тот, кому позвонили, дальше равны. */
  const приладить = (канал, сокет) => {
    канал.сокет = сокет
    сокет.setNoDelay(true)
    сокет.setEncoding("utf8")
    const разобрать = собиратель(
      (кадр) => принять(канал, кадр),
      (беда) => случилось(канал, SoketOtkazal({ "почему": беда })),
    )
    сокет.on("data", (кусок) => {
      случилось(канал, BaytyPrishli({ "сейчас": часы() }))
      разобрать(кусок)
    })
    сокет.on("error", () => случилось(канал, SoketOtkazal({ "почему": "сокет отказал" })))
    сокет.on("close", () => случилось(канал, SoketOtkazal({ "почему": "сокет закрыт" })))
    сторожить(канал)
    случилось(канал, SoketZavyolsya({ "сейчас": часы() }))
  }

  const позвонить = (кто) => {
    if (!работает) return
    const канал = связь(кто)
    if (канал.состояние["готова"] || канал.состояние["звоним"]) return
    const куда = размещение.звонить?.[кто]
    /* Звонить некому — не отказ: размещение назначило этот конец слушающим.
       Связь заведёт сосед, а этот узел ждёт. Названо в контракте как цена. */
    if (куда === undefined) return
    const [хозяин, порт] = разделитьАдрес(куда)
    канал.состояние = svyazZanovo(
      канал.кто, канал.состояние["готова"], true, канал.состояние["виделись"],
      канал.состояние["ждём решения"], канал.состояние["последний байт"],
    )
    const сокет = createConnection({ host: хозяин, port: порт })
    сокет.on("connect", () => {
      сокет.removeAllListeners("error")
      приладить(канал, сокет)
    })
    /* Дозвониться не удалось. Что из этого следует — ещё один отказ надзору
       или молчаливое ожидание — решает эталон по полю «виделись», а не этот
       обработчик: связь, которой ни разу не было, потерять нельзя. */
    сокет.on("error", () => {
      сокет.destroy()
      случилось(канал, ZvonokNeUdalsya({}))
    })
  }

  /**
   * Доложить о потере: то, что велел эталон, — уборка уже сделана им же.
   *
   * Решать, докладывать ли, здесь больше нечего, и это главная перемена. Три
   * случая, когда доклада НЕ бывает, — узел останавливается, ни разу не
   * виделись, об этом разрыве уже доложено, — назывались тут же, рядом с
   * сокетом, и проверялись тремя `if`. Теперь их считает «Докладывать ли о
   * разрыве» в эталоне, а сюда доходит только следствие.
   */
  const доложитьОПотере = (кто, почему) => {
    запись("связь", { сосед: кто, что: СВЯЗЬ.потеряна, почему })
    const когда = часы()
    for (const имя of порядок) {
      const это = процессы.get(имя)
      if (это.вид !== "представитель" || это.накаком !== кто || !это.жив) continue
      это.жив = false
      это.причина = LINK_DOWN_CODE
      уронить(имя, LINK_DOWN_CODE, `связь с узлом «${кто}» потеряна: ${почему}`, когда)
      if (!работает) return
    }
  }

  /**
   * Кадр с провода → событие эталона. Перевод и ничего больше: решать, что из
   * кадра следует, — дело «Шага связи», а не этой функции.
   *
   * Единственное, что решается ЗДЕСЬ, — доставка письма своему процессу, и
   * решается не потому, что эталон не может, а потому, что для этого нужна
   * таблица процессов: она у узла, а не у языка. Эталон говорит «Доставить
   * письмо» и называет адресата, а несёт письмо узел.
   */
  const принять = (канал, кадр) => {
    const вид = кадр?.в
    if (вид === КАДР.привет) {
      случилось(канал, PrishyolPrivet({ "узел": String(кадр.узел ?? ""), "хэш": String(кадр.хэш ?? "") }))
      return
    }
    if (вид === КАДР.пульс) { случилось(канал, PrishyolPuls({})); return }
    if (вид === КАДР.отбой) {
      случилось(канал, PrishyolOtboy({ "почему": String(кадр.почему ?? "без причины") }))
      return
    }
    if (вид === КАДР.письмо) {
      последнееПисьмо = кадр
      случилось(канал, PrishloPismo({ "кому": String(кадр.кому) }))
      последнееПисьмо = null
      return
    }
    случилось(канал, PrishyolChuzhoyKadr({ "вид": String(вид) }))
  }

  /**
   * Что случилось со связью — единственная дорога от мира к решению.
   *
   * Ровно две строки работы: спросить напечатанный эталон, что теперь, и
   * исполнить веления. Раньше это решали семь замыканий, каждое из которых
   * держало ручку сокета и меняло поля канала в своём порядке; теперь порядок —
   * свойство ПРОГРАММЫ, а не файла.
   */
  const случилось = (канал, событие) => {
    const ход = shagSvyazi(канал.состояние, событие, хэш, срок, пауза, работает)
    канал.состояние = ход["связь"]
    for (const веление of ход["веления"]) исполнить(канал, веление)
  }

  /** Исполнить веление эталона. Разбор полный: неизвестное веление — беда. */
  const исполнить = (канал, веление) => {
    switch (веление.variant) {
      case "Послать привет":
        послать(канал, { в: КАДР.привет, узел: имяУзла, хэш })
        return
      case "Прибрать":
        прибрать(канал)
        return
      case "Связь заведена":
        запись("связь", { сосед: канал.кто, что: СВЯЗЬ.заведена })
        return
      case "Связь отвергнута":
        запись("связь", {
          сосед: веление.fields["сосед"],
          что: СВЯЗЬ.отвергнута,
          почему: веление.fields["почему"],
        })
        return
      case "Доложить о потере":
        доложитьОПотере(канал.кто, веление.fields["почему"])
        return
      case "Доставить письмо":
        доставить(канал, веление.fields["кому"])
        return
      case "Позвонить снова": {
        const отсрочка = setTimeout(() => позвонить(канал.кто), веление.fields["пауза"])
        отсрочка.unref?.()
        return
      }
      default:
        /* Веление, которого хозяин не знает, — расхождение хозяина с эталоном,
           и молчать о нём нельзя: связь бы просто перестала что-то делать. */
        throw new Error(`узел не знает веления «${веление.variant}»`)
    }
  }

  /**
   * Донести письмо своему процессу. Тело кадра сюда не едет через эталон
   * нарочно: раскодирование требует конструкторов вариантов напечатанного
   * модуля, а они принадлежат ПРОГРАММЕ, не узлу.
   */
  const доставить = (канал, кому) => {
    const кадр = последнееПисьмо
    const это = процессы.get(кому)
    if (это === undefined || это.вид !== "свой") {
      /* Маршрутизации нет: письмо не тому узлу пропадает, и это ВИДНО в
         журнале. Молча выбросить значило бы спрятать ошибку размещения. */
      запись("потеря", { кому, почему: "процесс размещён не здесь", отправитель: канал.кто })
      return
    }
    let что = null
    try {
      что = раскодировать(кадр.что, конструкторы)
    } catch (беда) {
      запись("потеря", { кому, почему: `письмо не раскодировано: ${беда.message}` })
      return
    }
    const итог = положить(кому, что, false)
    if (итог !== "легло") {
      /* Ящик за границей узла потолка не соблюдает: отказать отправителю нечем
         — он на другом узле, и «не больше одного» позволяет письму пропасть.
         Названо в контракте, а в журнале видно. */
      запись("потеря", { кому, почему: итог === "полон" ? "ящик полон" : "адресата нет" })
    }
  }

  /* ── наружу ─────────────────────────────────────────────────────────── */

  /**
   * Слушать. Кто позвонил — известно только из «привет», поэтому разборщик
   * кадров ставится ОДИН и до знакомства: пришедший кусок может нести и
   * рукопожатие, и письмо сразу, и второй разборщик потерял бы второе.
   */
  const слушать = (хозяин, порт) => new Promise((готово) => {
    сервер = createServer((сокет) => {
      сокет.setNoDelay(true)
      сокет.setEncoding("utf8")
      let канал = null
      const разобрать = собиратель(
        (кадр) => {
          if (канал === null) {
            if (кадр?.в !== КАДР.привет) { сокет.destroy(); return }
            канал = связь(String(кадр.узел))
            прибрать(канал)
            канал.сокет = сокет
            сторожить(канал)
            /* Тот же вход, что у позвонившего конца: «Сокет завёлся» ставит
               отметку часов и велит поздороваться. Одна дорога на оба конца
               связи — теперь буквально одна, а не «устроено одинаково». */
            случилось(канал, SoketZavyolsya({ "сейчас": часы() }))
          }
          принять(канал, кадр)
        },
        (беда) => { if (канал === null) сокет.destroy(); else случилось(канал, SoketOtkazal({ "почему": беда })) },
      )
      сокет.on("data", (кусок) => {
        if (канал !== null) случилось(канал, BaytyPrishli({ "сейчас": часы() }))
        разобрать(кусок)
      })
      сокет.on("error", () => { if (канал === null) сокет.destroy(); else случилось(канал, SoketOtkazal({ "почему": "сокет отказал" })) })
      сокет.on("close", () => { if (канал !== null) случилось(канал, SoketOtkazal({ "почему": "сокет закрыт" })) })
    })
    сервер.listen(порт, хозяин, () => готово(сервер.address()))
  })

  const остановиться = () => {
    if (!работает) return
    работает = false
    for (const канал of связи.values()) {
      if (канал.сторож !== null) clearInterval(канал.сторож)
      if (канал.сердце !== null) clearInterval(канал.сердце)
      if (канал.сокет !== null) {
        try { канал.сокет.write(`${JSON.stringify({ в: КАДР.отбой, почему: исход })}\n`) } catch { /* уже некуда */ }
        канал.сокет.removeAllListeners()
        канал.сокет.destroy()
      }
    }
    if (сервер !== null) сервер.close()
  }

  return {
    имя: имяУзла,
    слушать,
    /** Позвонить всем, кому положено по размещению. */
    звонить: () => { for (const кто of Object.keys(размещение.звонить ?? {})) позвонить(кто) },
    /**
     * Вбросить сообщение снаружи — так испытание играет роль внешнего мира.
     * Значение подаётся ЗАКОДИРОВАННЫМ, тем же кодом, что ходит по проводу:
     * второй способ построить значение означал бы второй способ ошибиться.
     */
    вбросить: (кому, код) => отправить(кому, раскодировать(код, конструкторы)),
    /** Состояния своих процессов — закодированными, чтобы уехали наблюдателю. */
    состояния: () => {
      const итог = {}
      for (const имя of порядок) {
        const это = процессы.get(имя)
        if (это.вид !== "свой") continue
        итог[имя] = { жив: это.жив, состояние: закодировать(это.состояние) }
      }
      return итог
    },
    /** Что узел думает про соседей и представителей. */
    связи: () => {
      const итог = {}
      for (const [кто, канал] of связи) итог[кто] = { готова: канал.состояние["готова"], виделись: канал.состояние["виделись"] }
      for (const имя of порядок) {
        const это = процессы.get(имя)
        if (это.вид === "представитель") итог[`представитель:${имя}`] = { жив: это.жив, узел: это.накаком }
      }
      return итог
    },
    исход: () => исход,
    решения: () => суд.решения,
    остановиться,
  }
}

/**
 * Размещение файла → размещение узла: «узел → процессы» становится
 * «процесс → узел».
 *
 * Отдельной функцией, а не строчкой в переднем крае, по одной причине: здесь
 * ловится процесс, размещённый ДВАЖДЫ, а это ровно то место, где имя перестаёт
 * быть адресом. Проверка такого рода обязана быть испытуемой без сокетов и
 * подпроцессов, значит обязана быть отдельной.
 *
 * @param {{узлы: Record<string, {процессы?: string[], звонить?: Record<string,string>}>}} файл
 * @param {string} имяУзла чей узел собираем
 * @param {Record<string,string>} [поверх] адреса соседей из доводов, поверх файла
 */
export function размещениеУзла(файл, имяУзла, поверх = {}) {
  const мой = файл?.узлы?.[имяУзла]
  if (мой === undefined) {
    throw new Error(
      `узла «${имяУзла}» в размещении нет; объявлены: ${Object.keys(файл?.узлы ?? {}).join(", ") || "ни одного"}`,
    )
  }
  const процессы = {}
  for (const [узел, описание] of Object.entries(файл.узлы)) {
    for (const процесс of описание.процессы ?? []) {
      if (процессы[процесс] !== undefined) {
        throw new Error(`процесс «${процесс}» размещён дважды — на «${процессы[процесс]}» и на «${узел}»`)
      }
      процессы[процесс] = узел
    }
  }
  return { процессы, звонить: { ...(мой.звонить ?? {}), ...поверх }, слушать: мой.слушать }
}

/** «127.0.0.1:9001» → ["127.0.0.1", 9001]. Адрес всегда с портом: гадать нечего. */
export function разделитьАдрес(строка) {
  const край = String(строка).lastIndexOf(":")
  if (край < 0) throw new Error(`адрес «${строка}» без порта`)
  return [строка.slice(0, край), Number(строка.slice(край + 1))]
}
