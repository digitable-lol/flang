    "  «состояние»: «Счёт»",
    "  «действия»: список «Действие»",
    "",
    "процесс «Звонарь»",
    "  состояние «Счёт»",
    "  начинает с «нуль»",
    "  принимает «Весть»",
    "  обрабатывает «шаг»",
    "",
    "процесс «Слушатель»",
    "  состояние «Счёт»",
    "  начинает с «нуль»",
    "  принимает «Весть»",
    "  обрабатывает «шаг»",
    "",
    "НАДЗОР",
    "тотальная функция «нуль»",
    "  возвращает «Счёт»",
    "  запись «Счёт» с «сколько» равным 0",
    "",
    "тотальная функция «шаг»",
    "  принимает текущее: «Счёт», сообщение: «Весть»",
    "  возвращает «Отклик»",
    "  разбор сообщение",
    "    случай вариант «звонок» с «раз» как раз",
    "      пусть новое равно (запись «Счёт» с «сколько» равным (текущее.«сколько» плюс раз))",
