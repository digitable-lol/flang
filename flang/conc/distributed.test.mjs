/* ══════════ 6. значения на проводе ══════════ */

test("значение переживает провод туда-обратно, включая то, чего нет в JSON", async () => {
  const текст = readFileSync(`${корень}${ПРОГРАММА}`, "utf8")
  const напечатано = emitJs(parse(текст, ПРОГРАММА)).files[0].content
  const модуль = await import(
    `data:text/javascript;charset=utf-8;base64,${Buffer.from(напечатано, "utf8").toString("base64")}`
  )
  const конструкторы = конструкторыВариантов(модуль)

  /* Словарь построен пробой, и вот что она нашла: все варианты программы плюс
     все действия языка. Если печать перестанет их экспортировать, испытание
     покраснеет здесь, а не в трёх узлах через сеть.
     «породить» приехал шагом Б1 и стоит здесь наравне с остальными действиями:
     на проводе он такой же вариант, как «отправить», — узел не исполняет его
     сам, но обязан уметь разобрать. */
  assert.deepEqual([...конструкторы.keys()].sort(),
    ["замерить", "записать", "остановить", "отложить", "отправить", "породить", "принято",
     "продолжить", "через"])

  const кругом = (значение) => раскодировать(JSON.parse(JSON.stringify(закодировать(значение))), конструкторы)

  assert.equal(кругом(42), 42)
  assert.equal(кругом("текст"), "текст")
  assert.equal(кругом(true), true)
  assert.equal(кругом(null), null)
  assert.deepEqual(кругом([1, "два", [3]]), [1, "два", [3]])
  assert.deepEqual(кругом({ "всего": 5, "подтверждено": 2 }), { "всего": 5, "подтверждено": 2 })

  /* Числа языка — IEEE-754, а голый JSON не умеет ни NaN, ни бесконечностей,
     ни минус нуля: он превратил бы их в null молча. Метка «ч» их переживает. */
  assert.ok(Number.isNaN(кругом(NaN)))
  assert.equal(кругом(Infinity), Infinity)
  assert.equal(кругом(-Infinity), -Infinity)
  assert.ok(Object.is(кругом(-0), -0))

  /* Вариант обязан вернуться КЛАССОМ модуля, иначе обработчик его не разберёт:
     это не придирка, а предъявленный отказ FLANG_MATCH_NOT_EXHAUSTIVE. */
  const вариант = кругом(модуль.Zamerit({ "сколько": 7 }))
  assert.equal(вариант.variant, "замерить")
  assert.deepEqual(вариант.fields, { "сколько": 7 })
  const отклик = модуль.shagSchyota(модуль.pustoySchyot(), вариант)
  assert.deepEqual(отклик["состояние"], { "всего": 7, "подтверждено": 0 })
})

