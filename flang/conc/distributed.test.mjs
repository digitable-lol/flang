/**
 * Ящик за границей узла потолка НЕ соблюдает — и это надо было предъявить, а не
 * объявить. Ветка в `distributed.mjs` написана давно; прогона на неё не было, а
 * написанное без прогона — не сделанное, а заявленное.
 *
 * Устроено так, чтобы переполнение случилось наверняка, а не по удаче: провод
 * ЗАМОРАЖИВАЕТСЯ, письма копятся в нём, и `оттаять` отдаёт их одним куском.
 * Разборщик кадров у получателя проходит весь кусок синхронно, а планировщик
 * узла просыпается только следующим `setImmediate`, — значит ящик наполняется
 * раньше, чем из него успевают взять хоть одно сообщение.
 *
 * Главное здесь — то, чего НЕ происходит: отправитель не отказывает. Отказ
 * `FLANG_MAILBOX_FULL` достаётся отправителю, а он на другом узле, и отказать
 * ему в тот момент, когда ящик полон, нечем.
 */
test("ящик за границей узла потолка не соблюдает: письмо пропадает, а отправитель об этом не узнаёт", async () => {
  const каталог = каталогПределов(РАЗМЕЩЕНИЕ_ПРЕДЕЛОВ)
  const журнал = []
  const { край, провод, толк } = await стендПределов(журнал, каталог)

  провод.сказать({ в: "морозить" })
  await дождаться(журнал, (з) => з.кто === "провод" && з.что === "заморожен", "провод заморожен")

  const письма = 5
  for (let и = 0; и < письма; и += 1) толк.сказать(толкнуть(`п${и}`))
  await ждать(500)

  провод.сказать({ в: "оттаять" })
  await ждать(700)

  толк.сказать({ в: "состояния", метка: "после залпа" })
  край.сказать({ в: "состояния", метка: "после залпа" })
  const состояниеТолка = await дождаться(журнал,
    (з) => з.кто === "толк" && з.в === "состояния" && з.метка === "после залпа", "состояние «толка»")
  const состояниеКрая = await дождаться(журнал,
    (з) => з.кто === "край" && з.в === "состояния" && з.метка === "после залпа", "состояние «края»")

  /* Отправитель отработал все пять и ни разу не отказал: «не больше одного»
     позволяет письму пропасть, и отправитель об этом не узнаёт. */
  assert.deepEqual(состояниеТолка.это["Толкач"].состояние,
    ["з", { "послано": ["ч", письма], "сделано": ["ч", 0] }])
  assert.deepEqual(журнал.filter((з) => з.кто === "толк" && з.в === "отказ"), [],
    "отправитель отказал — а отказать ему через границу нечем")

  /* У получателя леглo ровно столько, сколько объявлено ящиком, а остальное
     пропало и НАЗВАНО в журнале: молча выбросить значило бы спрятать потерю. */
  const принято = состояниеКрая.это["Приёмник"].состояние[1]["принято"][1]
  const потери = журнал.filter((з) => з.кто === "край" && з.в === "потеря" && з.почему === "ящик полон")
  /* Ровного числа здесь не обещается, и обещать его было бы враньём: сколько
     писем успеет лечь, зависит от того, сколько кусков сделает из залпа TCP и
     успел ли планировщик проснуться между ними. Обещается ДРУГОЕ, и оно точное:
     каждое письмо либо легло, либо НАЗВАНО потерянным, и сверх потолка что-то
     потеряно обязательно. */
  assert.ok(потери.length >= 1, "полный ящик не потерял ни одного письма — потолок не сработал вовсе")
  assert.equal(принято.length + потери.length, письма,
    `письма разошлись: легло ${принято.length}, потеряно ${потери.length}, послано ${письма}`)
  assert.ok(принято.length < письма, "легли все — значит ящик потолка не имеет")
  assert.ok(журнал.every((з) => !(з.кто === "край" && з.в === "отказ")),
    "получатель отказал — а он ни при чём: полный ящик роняет письмо, а не процесс")

  console.log(`обратное давление: послано ${письма}, ящик 2, легло ${принято.length}, потерь «ящик полон» ${потери.length}, отказов у отправителя 0`)
  for (const дитя of [толк, край, провод]) дитя.сказать({ в: "стоп" })
  await ждать(300)
  rmSync(каталог, { recursive: true, force: true })
})

/* ══════════ 16. «через N» на узле — настоящая задержка ══════════ */

/**
 * У прогона свидетеля время виртуальное: он прыгает к ближайшему сроку таймера
 * и не ждёт ни миллисекунды. Двум узлам разделить одно виртуальное время
 * нечем, поэтому на узле `через N` обязано быть НАСТОЯЩЕЙ задержкой в N
 * миллисекунд. В ведомости это стояло «написано, прогона нет»; вот прогон.
 *
 * Обе стороны обязательны: «дошло» без «не раньше» зелено и у кода, который
 * шлёт немедленно, а «не раньше» без «дошло» зелено у кода, который не шлёт
 * вовсе. Узел здесь один, сокетов нет, пульса нет — задержке не с чем спутаться.
 */
test("«через N» на узле — настоящая задержка в N миллисекунд, а не виртуальное время", async () => {
  const каталог = каталогПределов(РАЗМЕЩЕНИЕ_ОДНОГО)
  const журнал = []
  const узел = await одинУзел(журнал, каталог)

  const задержка = 700
  const пущено = Date.now()
  узел.сказать({ в: "вбросить", кому: "Толкач", что: ["в", "завести", { "задержка": ["ч", задержка] }] })
  await дождаться(журнал, (з) => з.кто === "оба" && з.в === "пробег" && з.процесс === "Толкач", "«завести» отработано")

  /* Середина срока: будильник ещё не звонил. */
  await ждать(задержка / 2)
  узел.сказать({ в: "состояния", метка: "середина" })
  const середина = await дождаться(журнал,
    (з) => з.кто === "оба" && з.в === "состояния" && з.метка === "середина", "состояние в середине срока")
  assert.deepEqual(середина.это["Толкач"].состояние, ["з", { "послано": ["ч", 0], "сделано": ["ч", 0] }],
    "будильник зазвонил раньше половины срока — значит задержка не настоящая")

  /* И конец срока: будильник звонит, и «Приёмник» получает то, что тот послал. */
  await ждать(задержка)
  узел.сказать({ в: "состояния", метка: "после срока" })
  const после = await дождаться(журнал,
    (з) => з.кто === "оба" && з.в === "состояния" && з.метка === "после срока", "состояние после срока")
  const прошло = Date.now() - пущено
  assert.deepEqual(после.это["Толкач"].состояние, ["з", { "послано": ["ч", 1], "сделано": ["ч", 0] }],
    "будильник не зазвонил вовсе")
  assert.deepEqual(после.это["Приёмник"].состояние, ["з", { "принято": ["л", [["с", "будильник"]]] }])
  assert.ok(прошло >= задержка, `будильник отработал за ${прошло} мс при задержке ${задержка}`)

  console.log(`«через N» на узле: задержка ${задержка} мс, в середине послано 0, после срока 1, всего ${прошло} мс`)
  узел.сказать({ в: "стоп" })
  await ждать(200)
  rmSync(каталог, { recursive: true, force: true })
})

/* ══════════ 17. запас витков на узле ══════════ */

/**
 * Предел витков ставится тем же прибором, что у обычной напечатанной
 * программы, — счётчиком модуля через `$newContext`. Ветка написана, прогона на
 * неё не было: обработчики примера «Замер и учёт» тотальны и коротки, и запас у
 * них не объявлен вовсе.
 *
 * Обе половины опять обязательны: «непосильное роняет» без «посильное проходит»
 * зелено и у узла, который роняет всё подряд.
 */
test("запас витков на узле: посильное проходит, непосильное роняет процесс названным отказом", async () => {
  const каталог = каталогПределов(РАЗМЕЩЕНИЕ_ОДНОГО)
  const журнал = []
  const узел = await одинУзел(журнал, каталог)

  узел.сказать({ в: "вбросить", кому: "Толкач", что: ["в", "крутить", { "сколько": ["ч", 5] }] })
  await дождаться(журнал, (з) => з.кто === "оба" && з.в === "пробег" && з.исход === "обработано", "посильное обработано")
  узел.сказать({ в: "состояния", метка: "посильное" })
  const посильное = await дождаться(журнал,
    (з) => з.кто === "оба" && з.в === "состояния" && з.метка === "посильное", "состояние после посильного")
  /* «сделано» равно 1, а не 6: «крутить» возвращает ноль, потратив витки. Число
     здесь не важно — важно, что пробег ЗАВЕРШИЛСЯ и состояние сменилось. */
  assert.deepEqual(посильное.это["Толкач"].состояние, ["з", { "послано": ["ч", 0], "сделано": ["ч", 1] }])

  /* А теперь виток, которого нет: «крутить» от −1 не завершается вовсе. */
  узел.сказать({ в: "вбросить", кому: "Толкач", что: ["в", "крутить", { "сколько": ["ч", -1] }] })
  const отказ = await дождаться(журнал, (з) => з.кто === "оба" && з.в === "отказ", "запас исчерпан")
  assert.equal(отказ.код, "FLANG_BUDGET_EXHAUSTED")
  assert.equal(отказ.процесс, "Толкач")
  const решение = await дождаться(журнал, (з) => з.кто === "оба" && з.в === "решение", "надзор решил")
  assert.equal(решение.надзор, "Край")
  assert.equal(решение.стратегия, "остановить")

  узел.сказать({ в: "состояния", метка: "после запаса" })
  const после = await дождаться(журнал,
    (з) => з.кто === "оба" && з.в === "состояния" && з.метка === "после запаса", "состояние после исчерпания")
  assert.equal(после.это["Толкач"].жив, false, "процесс, исчерпавший запас, остался живым")
  /* Половины изменения не бывает: сообщение отвергнуто целиком. */
  assert.deepEqual(после.это["Толкач"].состояние, ["з", { "послано": ["ч", 0], "сделано": ["ч", 1] }])
  assert.equal(после.это["Приёмник"].жив, true, "сосед по узлу пострадал ни за что")

  console.log(`запас витков на узле: запас 2000, посильное «сделано» 1, непосильное — ${отказ.код}, решение «${решение.надзор}/${решение.стратегия}»`)
  узел.сказать({ в: "стоп" })
  await ждать(200)
  rmSync(каталог, { recursive: true, force: true })
})

/* ══════════ 18. «остановить» над представителем ══════════ */

/**
 * Третья строка таблицы стратегий, у которой прогона не было. У примера «Замер
 * и учёт» за связью объявлено `перезапустить`, и `остановить` над
 * представителем в прогонах просто не случалось.
 *
 * Что оно значит, сказано в контракте двумя обещаниями, и оба здесь проверены:
 * БОЛЬШЕ НЕ ЗВОНИТЬ (провод чинится, и связь всё равно не заводится) и ПИСЬМА
 * ТУДА ПРОПАДАЮТ (`отправить` отвечает «некому», как мёртвому местному
 * процессу). Третье, не менее важное, — что узел при этом ЖИВ: остановлен
 * представитель, а не хозяин.
 */
test("«остановить» над представителем: узел больше не звонит, а письма туда отвечают «некому»", async () => {
  const каталог = каталогПределов(РАЗМЕЩЕНИЕ_ПРЕДЕЛОВ)
  const журнал = []
  const { край, провод, толк } = await стендПределов(журнал, каталог, { пауза: 200 })

  толк.сказать(толкнуть("до обрыва"))
  await ждать(400)

  провод.сказать({ в: "резать" })
  const решение = await дождаться(журнал, (з) => з.кто === "толк" && з.в === "решение", "надзор решил про представителя")
  assert.equal(решение.процесс, "Приёмник")
  assert.equal(решение.надзор, "Край")
  assert.equal(решение.стратегия, "остановить")

  /* Провод чинится — и это ЗУБ: если бы узел продолжал звонить, связь завелась
     бы заново, и «остановить» ничем не отличалось бы от «перезапустить». */
  провод.сказать({ в: "чинить" })
  await ждать(1500)
  assert.ok(!журнал.some((з) => з.кто === "толк" && з.в === "связь" && з.что === СВЯЗЬ.заведена && з.номер > решение.номер),
    "узел позвонил заново после «остановить»")
  assert.equal(журнал.filter((з) => з.кто === "толк" && з.в === "решение").length, 1,
    "решений больше одного — значит узел всё-таки звонил и падал снова")

  /* Письмо туда теперь «некому» — ровно то же слово, каким отвечает отправка
     мёртвому МЕСТНОМУ процессу: смысл `отправить` от размещения не зависит. */
  толк.сказать(толкнуть("после обрыва"))
  const вброшено = await дождаться(журнал, (з) => з.кто === "толк" && з.в === "вброшено", "письмо вброшено")
  assert.equal(вброшено.итог, "легло", "вбрасывали в «Толкача», а он свой и жив")
  await ждать(300)
  толк.сказать({ в: "связи", метка: "после остановки" })
  const связи = await дождаться(журнал,
    (з) => з.кто === "толк" && з.в === "связи" && з.метка === "после остановки", "связи «толка»")
  assert.equal(связи.это["представитель:Приёмник"].жив, false, "представитель жив после «остановить»")

  /* И узел при этом работает: остановлен представитель, а не хозяин. */
  толк.сказать({ в: "состояния", метка: "узел жив" })
  const состояния = await дождаться(журнал,
    (з) => з.кто === "толк" && з.в === "состояния" && з.метка === "узел жив", "состояние «толка»")
  assert.equal(состояния.это["Толкач"].жив, true)
  assert.deepEqual(состояния.это["Толкач"].состояние, ["з", { "послано": ["ч", 2], "сделано": ["ч", 0] }],
    "«Толкач» не отработал оба письма — а он свой, и границы его не касаются")
  assert.ok(!журнал.some((з) => з.кто === "толк" && з.в === "конец"), "узел кончился, а обязан работать")

  const потериСвязи = журнал.filter((з) => з.кто === "толк" && з.в === "потеря" && з.почему === "связи нет")
  console.log(`«остановить» над представителем: решений ${журнал.filter((з) => з.кто === "толк" && з.в === "решение").length}, `
    + `связь после починки не завелась, потерь «связи нет» ${потериСвязи.length}, узел работает`)

  for (const дитя of [толк, край, провод]) дитя.сказать({ в: "стоп" })
  await ждать(300)
  rmSync(каталог, { recursive: true, force: true })
})
