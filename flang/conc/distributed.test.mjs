/**
 * Испытание распределённости: два узла, обмен через границу и РАЗРЫВ, который
 * рвётся по-настоящему.
 *
 * Запуск: node --test flang/conc/distributed.test.mjs
 *
 * ── Почему это отдельный файл, а не строка в flang/test ─────────────────────
 *
 * Прогоны в `flang/test/*.test.mjs` — чистые: разобрал, посчитал, сравнил. Здесь
 * поднимаются процессы операционной системы, открываются сокеты и меряется
 * настоящее время. Смешивать это с корпусом проверок языка не стоит: у них
 * разная цена и разная причина краснеть. Цена того, что этот файл не подхватывает
 * `npm run test:flang` (шаблон там — `flang/test/*.test.mjs`), названа в
 * `DISTRIBUTED.md` ведомостью, а не умолчана.
 *
 * ── Что здесь испытывается, и почему именно так ─────────────────────────────
 *
 * 1. Обмен через границу узла: письмо уходит с одного узла и меняет состояние
 *    процесса на другом. Без этого остальное не имеет смысла.
 * 2. РАЗРЫВ ПРОВОДА — оба узла живы, рвётся связь. Разрыв делается не
 *    убийством узла: «узел умер» и «связь порвалась» — разные события, и весь
 *    контракт держится на том, что различить их нечем. Испытание, рвущее связь
 *    убийством, проверяет первое и притворяется, что проверило второе.
 * 3. МОЛЧАНИЕ вместо разрыва: провод заморожен, сокеты целы, байты копятся.
 *    Здесь нет ни одного признака отказа, кроме тишины, — а тишина неотличима
 *    от медленного узла. Этим проверяется ВЫБРАННЫЙ СРОК, а не умение заметить
 *    закрытый сокет. И этим же предъявляется цена выбора: замороженные письма
 *    доходят ПОСЛЕ того, как отказ объявлен.
 * 4. Разделение мозга: пока один узел объявил отказ и остановился по своей же
 *    объявленной стратегии, другой был жив, работал и сохранил состояние.
 * 5. Сосед, которого ещё нет: потерять можно только то, что было, поэтому
 *    несостоявшееся первое знакомство надзор не будит и порог не жжёт.
 * 6. Рукопожатие: два узла с разными программами не разговаривают.
 * 7. Значения на проводе: туда-обратно, включая NaN, бесконечности и минус ноль.
 * 8. Отказы подъёма: программа без процессов, размещение без места, имя с двумя
 *    местами — каждый назван и виден в журнале.
 */
