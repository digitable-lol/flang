const дети = new Set()
after(() => { for (const дитя of дети) дитя.kill("SIGKILL") })

const ждать = (мс) => new Promise((готово) => setTimeout(готово, мс))

/**
 * Поднять процесс и разобрать его stdout в журнал.
 *
 * Журнал общий на всё испытание и с отметкой, кто сказал: утверждения вида
 * «пока один объявил отказ, другой работал» проверяются порядком записей, а
 * два раздельных журнала пришлось бы сшивать по часам.
 */
function поднять(журнал, имя, доводы) {
  const дитя = spawn(process.execPath, доводы, { cwd: корень, stdio: ["pipe", "pipe", "pipe"] })
  дети.add(дитя)
  let хвост = ""
  дитя.stdout.setEncoding("utf8")
  дитя.stdout.on("data", (кусок) => {
    хвост += кусок
    let край = хвост.indexOf("\n")
    while (край >= 0) {
      const строка = хвост.slice(0, край).trim()
      хвост = хвост.slice(край + 1)
      if (строка !== "") {
        try {
          журнал.push({ кто: имя, номер: журнал.length, ...JSON.parse(строка) })
        } catch {
          журнал.push({ кто: имя, номер: журнал.length, в: "мусор", текст: строка })
        }
      }
      край = хвост.indexOf("\n")
    }
  })
  дитя.stderr.setEncoding("utf8")
  дитя.stderr.on("data", (кусок) => журнал.push({ кто: имя, номер: журнал.length, в: "беда", текст: кусок }))
  дитя.on("exit", (код) => журнал.push({ кто: имя, номер: журнал.length, в: "вышел", код }))
  дитя.сказать = (что) => { if (!дитя.killed && дитя.stdin.writable) дитя.stdin.write(`${JSON.stringify(что)}\n`) }
  return дитя
}

/** Дождаться записи в журнале. Срок щедрый: машина под нагрузкой — не отказ. */
async function дождаться(журнал, условие, что, срок = 15000) {
  const край = Date.now() + срок
  for (;;) {
    const найдено = журнал.find(условие)
    if (найдено !== undefined) return найдено
    if (Date.now() > край) {
      assert.fail(`не дождались: ${что}\nжурнал:\n${журнал.map((з) => JSON.stringify(з)).join("\n")}`)
    }
    await ждать(20)
  }
}

const порт = (адрес) => Number(String(адрес).split(":").pop())

/**
 * Поднять стенд: узел «учёт», провод к нему и узел «счёт», звонящий в провод.
 *
 * Провод посередине — это и есть то, что можно порвать, не трогая узлы.
 * Все адреса — 127.0.0.1, порты нулевые: их раздаёт хозяин.
 */
async function стенд(журнал, { пауза = 400, срок = 1000, срокУчёта = срок, пульс = 200 } = {}) {
  const общее = (свойСрок) => [
    "--размещение", РАЗМЕЩЕНИЕ, "--слушать", "127.0.0.1:0",
    "--пауза", String(пауза), "--срок", String(свойСрок), "--пульс", String(пульс),
  ]

  const учёт = поднять(журнал, "учёт", ["flang/conc/bin/node.mjs", "--я", "учёт", ...общее(срокУчёта)])
  const поднятУчёт = await дождаться(журнал, (з) => з.кто === "учёт" && з.в === "поднят", "узел «учёт» поднялся")

  const провод = поднять(журнал, "провод",
    ["flang/conc/bin/wire.mjs", "--слушать", "127.0.0.1:0", "--на", `127.0.0.1:${порт(поднятУчёт.адрес)}`])
  const поднятПровод = await дождаться(журнал, (з) => з.кто === "провод" && з.что === "поднят", "провод поднялся")

  const счёт = поднять(журнал, "счёт",
    ["flang/conc/bin/node.mjs", "--я", "счёт", "--сосед", `учёт=127.0.0.1:${порт(поднятПровод.адрес)}`, ...общее(срок)])

  await дождаться(журнал, (з) => з.кто === "счёт" && з.в === "связь" && з.что === СВЯЗЬ.заведена, "связь заведена")
  return { учёт, провод, счёт, поднятУчёт, поднятПровод }
}

const замерить = (сколько) => ({ в: "вбросить", кому: "Счётчик", что: ["в", "замерить", { "сколько": ["ч", сколько] }] })

/* ══════════ 1. письмо переходит границу узла ══════════ */

test("два узла: письмо переходит границу и меняет состояние на той стороне", async () => {
  const журнал = []
  const { учёт, провод, счёт } = await стенд(журнал)

  счёт.сказать(замерить(2))
  счёт.сказать(замерить(3))

  /* Ждём, пока подтверждение вернётся: это доказывает обе стороны обмена —
     письмо ушло на «учёт» и ответ пришёл обратно на «счёт». */
  await дождаться(журнал, (з) => з.кто === "счёт" && з.в === "пробег", "«Счётчик» отработал")
  await ждать(600)

  счёт.сказать({ в: "состояния", метка: "после обмена" })
  учёт.сказать({ в: "состояния", метка: "после обмена" })
  const состояниеСчёта = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "состояния" && з.метка === "после обмена", "состояние «счёта»")
  const состояниеУчёта = await дождаться(журнал,
    (з) => з.кто === "учёт" && з.в === "состояния" && з.метка === "после обмена", "состояние «учёта»")

  /* Оба узла напечатали ОДИН и тот же хэш программы: текст программы от
     размещения не зависит вовсе, а размещение — данные узла. */
  const хэши = журнал.filter((з) => з.в === "поднят").map((з) => з.хэш)
  assert.equal(хэши.length, 2)
  assert.equal(хэши[0], хэши[1], "узлы несут разные программы — рукопожатие было бы невозможно")

  assert.deepEqual(состояниеСчёта.это["Счётчик"].состояние,
    ["з", { "всего": ["ч", 5], "подтверждено": ["ч", 2] }],
    "на «счёте» не сошлись замеры или не вернулись подтверждения")
  assert.deepEqual(состояниеУчёта.это["Учётчик"].состояние,
    ["з", { "строки": ["л", [["с", "2"], ["с", "5"]]]}],
    "на «учёте» не сошлись записи: письма через границу не дошли")

  /* «Учётчика» на узле «счёт» нет вовсе — он там представитель, и в перечне
     состояний его быть не должно: у представителя состояния нет по устройству. */
  assert.equal(состояниеСчёта.это["Учётчик"], undefined)
  assert.equal(состояниеУчёта.это["Счётчик"], undefined)

  for (const дитя of [счёт, учёт, провод]) дитя.сказать({ в: "стоп" })
  await ждать(300)
})

/* ══════════ 2. провод перекушен: надзор увидел и отработал ══════════ */

test("провод перекушен: надзор увидел отказ и отработал по объявленной стратегии", async () => {
  const журнал = []
  const { учёт, провод, счёт } = await стенд(журнал, { пауза: 400 })

  счёт.сказать(замерить(2))
  счёт.сказать(замерить(3))
  await ждать(600)

  /* ── РЕЖЕМ. Оба узла живы; умирает ровно провод. ── */
  провод.сказать({ в: "резать" })
  const перекушен = await дождаться(журнал, (з) => з.кто === "провод" && з.что === "перекушен", "провод перекушен")

  /* Надзор УВИДЕЛ: отказ назван кодом связи, а не чем-то безымянным. */
  const отказ = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "отказ" && з.код === "FLANG_LINK_DOWN", "«счёт» увидел отказ связи")
  assert.equal(отказ.процесс, "Учётчик", "отказал не представитель чужого процесса")
  assert.ok(отказ.номер > перекушен.номер, "отказ объявлен раньше, чем провод перекушен")

  /* Пока связи нет, а представитель ещё жив (надзор решил «перезапустить»),
     отправка НЕ отказывает — она молча пропадает, и единственный след остаётся
     в журнале узла. Это и есть «не больше одного», предъявленное на месте
     отправителя: программа об этом не узнаёт никак. */
  счёт.сказать(замерить(7))
  const потеря = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "потеря" && з.кому === "Учётчик", "письмо в порванную связь пропало")
  assert.match(потеря.почему, /связи нет/)
  const вброшено = журнал.find((з) => з.кто === "счёт" && з.в === "вброшено" && з.номер > перекушен.номер)
  assert.equal(вброшено?.итог, "легло",
    "местная доставка «Счётчику» обязана пройти как обычно: разрыв касается только границы")

  /* Надзор ОТРАБОТАЛ, и ровно по объявленному: «Связь» даёт два перезапуска
     (порог 2 за 5000 мс), третий отказ уходит выше, «Цех» передаёт выше некому —
     значит узел останавливается весь. Всё это объявлено в distributed.flang. */
  const конец = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "конец", "«счёт» кончился объявленным исходом")
  assert.equal(конец.исход, "отказ дошёл доверху")

  const решения = журнал.filter((з) => з.кто === "счёт" && з.в === "решение")
    .map((з) => `${з.надзор}/${з.стратегия}`)
  assert.deepEqual(решения, [
    "Связь/перезапустить",
    "Связь/перезапустить",
    "Связь/передать выше",
    "Цех/передать выше",
  ], "надзор отработал не по объявленной стратегии")

  /* Каждый перезапуск — это НАСТОЯЩАЯ попытка дозвониться, а не отметка в
     журнале: их отказы и есть второй и третий отказ в окне порога. */
  const отказы = журнал.filter((з) => з.кто === "счёт" && з.в === "отказ")
  assert.equal(отказы.length, 3, "порог считает не те отказы")
  assert.ok(отказы[2].часы - отказы[0].часы >= 700,
    `три отказа уложились в ${отказы[2].часы - отказы[0].часы} мс — пауза между попытками не соблюдена`)

  /* ── РАЗДЕЛЕНИЕ МОЗГА, предъявленное. Узел «счёт» объявил отказ и умер по
     собственной объявленной стратегии; узел «учёт» всё это время был жив,
     здоров и сохранил состояние. Ни один из них не ошибся — оба выполнили
     объявленное, и именно в этом цена выбора «связь, а не узел». ── */
  await дождаться(журнал, (з) => з.кто === "счёт" && з.в === "вышел", "«счёт» вышел")
  учёт.сказать({ в: "состояния", метка: "после смерти соседа" })
  const живой = await дождаться(журнал,
    (з) => з.кто === "учёт" && з.в === "состояния" && з.метка === "после смерти соседа",
    "«учёт» отвечает после смерти соседа")
  assert.deepEqual(живой.это["Учётчик"].состояние, ["з", { "строки": ["л", [["с", "2"], ["с", "5"]]]}],
    "у живого узла пропало состояние — а он ничего не терял")
  assert.ok(журнал.every((з) => !(з.кто === "учёт" && з.в === "вышел")), "«учёт» тоже умер: разрыв убил оба узла")

  /* И «учёт» тоже увидел разрыв — своей стороной и своим надзором. Порог
     «Цеха» даёт ему ровно один перезапуск, звонить ему некому по размещению,
     поэтому он ждёт. Это объявленное поведение, а не случайность. */
  const егоРешения = журнал.filter((з) => з.кто === "учёт" && з.в === "решение")
  assert.deepEqual(егоРешения.map((з) => `${з.процесс}/${з.надзор}/${з.стратегия}`),
    ["Счётчик/Цех/перезапустить"])

  for (const дитя of [учёт, провод]) дитя.сказать({ в: "стоп" })
  await ждать(300)
})

/* ══════════ 3. молчание вместо разрыва: испытывается СРОК ══════════ */

test("провод заморожен: отказ объявлен по сроку, а не по событию сети", async () => {
  const журнал = []
  const СРОК = 1000
  /* Срок у «учёта» заведомо больше времени испытания: молчание должно
     обнаружить РОВНО ОДИН узел, иначе непонятно, чей сторож сработал первым. */
  const { учёт, провод, счёт } = await стенд(журнал, { пауза: 400, срок: СРОК, срокУчёта: 60000 })

  счёт.сказать(замерить(2))
  await ждать(600)

  /* ── МОРОЗИМ. Сокеты целы, узлы живы, байты копятся в проводе. Единственный
     признак — тишина, а тишина неотличима от медленного узла. ── */
  провод.сказать({ в: "морозить" })
  const заморожен = await дождаться(журнал, (з) => з.кто === "провод" && з.что === "заморожен", "провод заморожен")

  /* Письмо, посланное в замороженный провод, уходит БЕЗ ОШИБКИ: отправитель
     ничего не узнаёт, и в этом весь смысл «не больше одного». Это «42» не
     дойдёт никогда, и никто об этом не скажет. */
  счёт.сказать(замерить(40))

  const потеряна = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "связь" && з.что === СВЯЗЬ.потеряна, "«счёт» объявил связь потерянной")
  const счётМолчания = /молчание (\d+) мс при сроке 1000 мс/.exec(потеряна.почему)
  assert.ok(счётМолчания !== null,
    `связь объявлена потерянной не по сроку, а по событию сети: «${потеряна.почему}»`)

  /* Первое утверждение — ровно то, что обещает контракт: связь объявляется
     потерянной не раньше, чем после `срок` миллисекунд молчания. Меряет его
     сам узел, от последнего ПРИНЯТОГО байта. */
  assert.ok(Number(счётМолчания[1]) >= СРОК,
    `узел объявил отказ, промолчав ${счётМолчания[1]} мс при сроке ${СРОК} мс`)

  /* Второе — по часам испытания, и нижняя граница здесь на пульс меньше срока,
     причём не по слабости проверки, а по устройству: молчание началось не
     когда провод заморозили, а когда пришёл последний байт, а он мог прийти
     на пульс раньше. Требовать от испытания больше, чем есть в природе,
     значило бы получить проверку, которая краснеет от собственной неправды. */
  const молчали = потеряна.часы - заморожен.часы
  assert.ok(молчали >= СРОК - 200,
    `отказ объявлен через ${молчали} мс после заморозки — раньше, чем позволяют срок ${СРОК} мс и пульс 200 мс`)
  assert.ok(молчали < СРОК * 3, `отказ объявлен через ${молчали} мс — сильно позже объявленного срока`)

  /* ── А ТЕПЕРЬ САМОЕ ГЛАВНОЕ. Провод в этот момент был ЦЕЛ: он закрылся
     ПОСЛЕ объявления и потому, что «счёт» сам положил трубку. То есть разрыв
     не случился с нами — мы его ОБЪЯВИЛИ. Ровно это и написано в контракте
     словами «мы никогда не утверждаем, что узел мёртв». ── */
  const параЗакрыта = await дождаться(журнал,
    (з) => з.кто === "провод" && з.что === "пара закрыта", "провод закрыл пару")
  assert.ok(параЗакрыта.номер > потеряна.номер,
    "провод закрылся раньше объявления — тогда это был обычный разрыв, а не срок")
  assert.match(параЗакрыта.почему, /слева/,
    "пару закрыл не тот конец: трубку обязан был положить объявивший отказ")

  /* И сосед узнал об этом только с нашей подачи: до объявления у «учёта» нет
     ни одной записи об отказе. Он был здоров всё это время. */
  const егоОтказ = журнал.find((з) => з.кто === "учёт" && з.в === "отказ")
  if (егоОтказ !== undefined) {
    assert.ok(егоОтказ.номер > потеряна.номер,
      "сосед объявил отказ раньше нас — значит молчание заметил он, а не мы")
  }

  /* ── ОТТАИВАЕМ. Провод снова передаёт байты, «счёт» дозванивается по решению
     своего же надзора, и обмен продолжается. А «42» не дошло и не дойдёт:
     оно было в пути, когда трубку положили. Потеря видна в состоянии обоих
     процессов — и это и есть «не больше одного», предъявленное числом. ── */
  провод.сказать({ в: "оттаять" })
  await дождаться(журнал, (з) => з.кто === "провод" && з.что === "оттаял", "провод оттаял")
  const снова = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "связь" && з.что === СВЯЗЬ.заведена && з.номер > потеряна.номер,
    "«счёт» дозвонился заново по решению надзора")
  assert.ok(снова.номер > потеряна.номер)

  счёт.сказать(замерить(100))
  await ждать(700)
  счёт.сказать({ в: "состояния", метка: "после оттаивания" })
  учёт.сказать({ в: "состояния", метка: "после оттаивания" })
  const уСчёта = await дождаться(журнал,
    (з) => з.кто === "счёт" && з.в === "состояния" && з.метка === "после оттаивания", "состояние «счёта»")
  const уУчёта = await дождаться(журнал,
    (з) => з.кто === "учёт" && з.в === "состояния" && з.метка === "после оттаивания", "состояние «учёта»")

  const строки = уУчёта.это["Учётчик"].состояние[1]["строки"][1].map((з) => з[1])
  assert.deepEqual(строки, ["2", "142"],
    "у «учёта» не то, что ожидалось: «42» должно было пропасть, «142» — дойти")
  assert.deepEqual(уСчёта.это["Счётчик"].состояние,
    ["з", { "всего": ["ч", 142], "подтверждено": ["ч", 2] }],
    "«всего» считает все три замера, «подтверждено» — только дошедшие: ровно так «не больше одного» и выглядит")

  for (const дитя of [счёт, учёт, провод]) дитя.сказать({ в: "стоп" })
  await ждать(300)
})

