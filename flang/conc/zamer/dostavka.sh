#!/bin/bash
# Цена ОДНОЙ доставки в микросекундах — наклоном, одной строкой на стенд.
#
# То же, что `naklon.sh`, только считает разность за тебя: один и тот же
# двоичник зовётся с двумя пределами пробегов, берётся минимум процессорного
# времени из повторов, разность делится на разность пробегов. Всё, что не
# зависит от числа пробегов (загрузка, заведение процессов, печать итога), из
# разности уходит целиком.
#
# $1 мало пробегов, $2 много пробегов, дальше — каталоги сборок.
# REP — повторов (по умолчанию 5).
set -u
source "$(dirname "${BASH_SOURCE[0]}")/obshchee.sh"
LOW=$1; HIGH=$2; shift 2
REP=${REP:-5}
мин() {
  bash "$FLANG/flang/conc/zamer/mera.sh" "$1" "$2" 0 "$REP" | awk '{print $2 + $3}' | sort -g | head -1
}
printf '%-28s %10s %10s %12s\n' стенд "мало,с" "много,с" "мкс/доставку"
for d in "$@"; do
  DIR=$(stend "$d")
  a=$(мин "$DIR" "$LOW")
  b=$(мин "$DIR" "$HIGH")
  awk -v n="$d" -v a="$a" -v b="$b" -v l="$LOW" -v h="$HIGH" \
    'BEGIN { printf "%-28s %10.2f %10.2f %12.3f\n", n, a, b, (b - a) * 1000000 / (h - l) }'
done
