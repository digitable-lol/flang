/**
 * Генератор стендов: программа flang с N процессами.
 *
 * --вид:
 *   тихо  — N процессов, одно сообщение первому: прогон кончается за один пробег.
 *           Меряет память покоя и цену завода процесса.
 *   себе  — N процессов, каждый шлёт сам себе: ГОТОВЫ всегда все N.
 *           Меряет цену переключения при R = N готовых.
 *   пинг  — N процессов объявлено, работают двое (А и Б, пинг-понг).
 *           Меряет цену переключения при R = 2 и P = N объявленных.
 *   ждут  — N процессов, каждый ОТКЛАДЫВАЕТ своё сообщение: ящик не пустеет
 *           никогда, значит ГОТОВЫ всегда все N. То же, что «себе», но без
 *           N начальных функций — поэтому доходит до миллиона, а «себе» нет.
 *   рой   — ОДИН объявленный сервер, который порождает работников на ходу
 *           (шаг Б1). N здесь не значит ничего: сколько процессов заведётся,
 *           решает предел пробегов запроса, а не исходник. Меряет цену
 *           порождения — и то, растёт ли она с числом уже заведённых.
 */
import { writeFileSync } from "node:fs"

const дов = new Map()
for (const кусок of process.argv.slice(2)) {
  const [имя, значение] = кусок.replace(/^--/, "").split("=")
  дов.set(имя, значение)
}

const N = Number(дов.get("n") ?? 10)
const вид = дов.get("вид") ?? "тихо"
const выход = дов.get("out") ?? "/dev/stdout"

const шапка = `модуль «Стенд»

объект «Сч»
  «всего»: число

тип «Кмд»
  вариант «тик» содержит «шаг»: число

объект «Отклик»
  «состояние»: «Сч»
  «действия»: список «Действие»

тотальная функция «пусто»
  возвращает «Сч»
  запись «Сч» с «всего» равным 0

тотальная функция «шаг»
  принимает текущее: «Сч», сообщение: «Кмд»
  возвращает «Отклик»
  разбор сообщение
    случай вариант «тик» с «шаг» как ш
      запись «Отклик» с «состояние» равным (запись «Сч» с «всего» равным (текущее.«всего» плюс ш)) и «действия» равным []
`

/* Состояние с адресом: так один обработчик служит любому числу процессов. */
const адресный = `
объект «Пара»
  «всего»: число
  «кому»: строка

объект «Отклик пары»
  «состояние»: «Пара»
  «действия»: список «Действие»

тотальная функция «отбить»
  принимает текущее: «Пара», сообщение: «Кмд»
  возвращает «Отклик пары»
  разбор сообщение
    случай вариант «тик» с «шаг» как ш
      пусть новое равно (запись «Пара» с «всего» равным (текущее.«всего» плюс 1) и «кому» равным текущее.«кому»)
      пусть письмо равно (вариант «отправить» с «кому» равным текущее.«кому» и «что» равным (вариант «тик» с «шаг» равным ш))
      запись «Отклик пары» с «состояние» равным новое и «действия» равным [письмо]
`

const части = [шапка]

if (вид === "тихо") {
  for (let i = 1; i <= N; i += 1) {
    части.push(`процесс «П${i}»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «шаг»\n`)
  }
  части.push(`прогон «стенд»
  семя 1
  дано «П1» принимает (вариант «тик» с «шаг» равным 1)
  ожидается «П1» равен (запись «Сч» с «всего» равным 1)
`)
} else if (вид === "себе") {
  части.push(адресный)
  for (let i = 1; i <= N; i += 1) {
    части.push(`тотальная функция «н${i}»\n  возвращает «Пара»\n  запись «Пара» с «всего» равным 0 и «кому» равным "П${i}"\n`)
    части.push(`процесс «П${i}»\n  состояние «Пара»\n  начинает с «н${i}»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
  }
  const строки = ["прогон «стенд»", "  семя 1"]
  for (let i = 1; i <= N; i += 1) строки.push(`  дано «П${i}» принимает (вариант «тик» с «шаг» равным 1)`)
  строки.push(`  ожидается «П1» равен (запись «Пара» с «всего» равным 0 и «кому» равным "П1")`)
  части.push(строки.join("\n") + "\n")
} else if (вид === "цепь") {
  /* Одно-единственное «дано» будит ВСЕ N процессов: адрес соседа обработчик
     считает из сообщения (`соединить "П" с (к строке (ш плюс 1))`), а не берёт
     из состояния. Это единственный способ поднять больше 31 349 процессов —
     ровно столько сообщений «дано» ещё печатается в C (стенка emitC). */
  части.push(`
тотальная функция «цепь»
  принимает текущее: «Сч», сообщение: «Кмд»
  возвращает «Отклик»
  разбор сообщение
    случай вариант «тик» с «шаг» как ш
      пусть адрес равно (соединить "П" с (к строке (ш плюс 1)))
      пусть письмо равно (вариант «отправить» с «кому» равным адрес и «что» равным (вариант «тик» с «шаг» равным (ш плюс 1)))
      запись «Отклик» с «состояние» равным (запись «Сч» с «всего» равным ш) и «действия» равным [письмо]
`)
  for (let i = 1; i <= N; i += 1) {
    части.push(`процесс «П${i}»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «цепь»\n`)
  }
  части.push(`прогон «стенд»
  семя 1
  дано «П1» принимает (вариант «тик» с «шаг» равным 1)
  ожидается «П1» равен (запись «Сч» с «всего» равным 1)
`)
} else if (вид === "ждут") {
  части.push(`
тотальная функция «ждать»
  принимает текущее: «Сч», сообщение: «Кмд»
  возвращает «Отклик»
  разбор сообщение
    случай вариант «тик» с «шаг» как ш
      запись «Отклик» с «состояние» равным текущее и «действия» равным [вариант «отложить»]
`)
  for (let i = 1; i <= N; i += 1) {
    части.push(`процесс «П${i}»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «ждать»\n`)
  }
  const строки = ["прогон «стенд»", "  семя 1"]
  for (let i = 1; i <= N; i += 1) строки.push(`  дано «П${i}» принимает (вариант «тик» с «шаг» равным 1)`)
  строки.push(`  ожидается «П1» равен (запись «Сч» с «всего» равным 0)`)
  части.push(строки.join("\n") + "\n")
} else if (вид === "рой") {
  /* Стенд порождения. Исходник ПОСТОЯННОГО размера — два объявления, — и в
     этом вся суть шага Б1: сколько процессов заведётся, решает прогон, а не
     компилятор. До Б1 стенд на миллион процессов был 166 МБ исходника и минута
     компиляции; здесь 700 байт и мгновение.

     Сервер на каждом пробеге делает ровно два дела: порождает работника с
     новым именем и будит себя следующим тиком. Значит на два пробега
     приходится одно порождение, и наклон по пределу пробегов даёт цену
     порождения напрямую. Работник просыпается один раз и замолкает — он
     МОЛЧАЩИЙ процесс, и цена его жизни та же, что в стенде «тихо».

     Ради чего стенд заведён: имя работника каждый раз НОВОЕ, а сервер зовётся
     по имени. При поиске адресата перебором таблицы цена пробега росла бы с
     числом уже заведённых — то есть порождение делало бы хуже, а не лучше.
     Указатель имён это и проверяет: наклон обязан быть ровным. */
  части.push(`
тотальная функция «плодить»
  принимает текущее: «Сч», сообщение: «Кмд»
  возвращает «Отклик»
  разбор сообщение
    случай вариант «тик» с «шаг» как ш
      пусть имя равно (соединить "р" с (к строке ш))
      пусть завести равно (вариант «породить» с «вид» равным "Работник" и «имя» равным имя и «что» равным (вариант «тик» с «шаг» равным ш))
      пусть ещё равно (вариант «отправить» с «кому» равным "Сервер" и «что» равным (вариант «тик» с «шаг» равным (ш плюс 1)))
      запись «Отклик» с «состояние» равным (запись «Сч» с «всего» равным ш) и «действия» равным [завести, ещё]
`)
  части.push(`процесс «Сервер»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «плодить»\n`)
  части.push(`процесс «Работник»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «шаг»\n`)
  /* Надзор обязателен: у «породить» есть свои достижимые отказы (занятое имя,
     предел числа процессов), и без надзора проверка типов отвергла бы стенд
     кодом FLANG_UNCOVERED_FAILURE. */
  части.push(`надзор «Присмотр»\n  процесс «Сервер» стратегия «остановить»\n`)
  части.push(`прогон «стенд»
  семя 1
  дано «Сервер» принимает (вариант «тик» с «шаг» равным 1)
  ожидается «Сервер» стратегия «остановить» 0 раз
`)
} else if (вид === "пингконец") {
  /* Тот же пинг-понг, но А и Б объявлены ПОСЛЕДНИМИ. Разница с «пинг» — ровно
     цена поиска адресата: `fl_conc_address` перебирает таблицу процессов
     сверху, поэтому имя в начале находится сразу, а имя в конце — за P шагов. */
  части.push(адресный)
  for (let i = 1; i <= N; i += 1) {
    части.push(`процесс «П${i}»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «шаг»\n`)
  }
  части.push(`тотальная функция «нА»\n  возвращает «Пара»\n  запись «Пара» с «всего» равным 0 и «кому» равным "Б"\n`)
  части.push(`тотальная функция «нБ»\n  возвращает «Пара»\n  запись «Пара» с «всего» равным 0 и «кому» равным "А"\n`)
  части.push(`процесс «А»\n  состояние «Пара»\n  начинает с «нА»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
  части.push(`процесс «Б»\n  состояние «Пара»\n  начинает с «нБ»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
  части.push(`прогон «стенд»
  семя 1
  дано «А» принимает (вариант «тик» с «шаг» равным 1)
  ожидается «А» равен (запись «Пара» с «всего» равным 0 и «кому» равным "Б")
`)
} else if (вид === "пинг") {
  части.push(адресный)
  части.push(`тотальная функция «нА»\n  возвращает «Пара»\n  запись «Пара» с «всего» равным 0 и «кому» равным "Б"\n`)
  части.push(`тотальная функция «нБ»\n  возвращает «Пара»\n  запись «Пара» с «всего» равным 0 и «кому» равным "А"\n`)
  части.push(`процесс «А»\n  состояние «Пара»\n  начинает с «нА»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
  части.push(`процесс «Б»\n  состояние «Пара»\n  начинает с «нБ»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
  for (let i = 1; i <= N; i += 1) {
    части.push(`процесс «П${i}»\n  состояние «Сч»\n  начинает с «пусто»\n  принимает «Кмд»\n  обрабатывает «шаг»\n`)
  }
  части.push(`прогон «стенд»
  семя 1
  дано «А» принимает (вариант «тик» с «шаг» равным 1)
  ожидается «А» равен (запись «Пара» с «всего» равным 0 и «кому» равным "Б")
`)
}

writeFileSync(выход, части.join("\n"), "utf8")
