#!/bin/bash
# Порог окупаемости пула: при каком K рабочий режим обгоняет проверочный.
#
# Вопрос шага Д1 карты. Порог был ПОСЧИТАН из двух чисел замера шага 6 —
# передача работы потоку против цены пробега, — и вышел «K больше 4 / 6 / 14» на
# 16 / 256 / 8 ядрах. Здесь он МЕРЯЕТСЯ, и мерить его надо потому, что
# «передача» того замера — mutex с условной переменной туда и обратно, а
# реализованная передача не будит никого вовсе.
#
# Стенд один и тот же (`пачка`), меняется одно — K, то есть сколько пробегов
# приходится на одну передачу процесса потоку. Столбцы: настенное время
# проверочного режима, настенное рабочего, отношение. Отношение больше единицы —
# пул окупился.
#
# КОНТРОЛЬНАЯ СУММА обязательна и проверяется на КАЖДОМ прогоне: сумма поля
# «всего» по всем процессам равна числу пробегов, потому что каждый пробег
# прибавляет ровно единицу ровно одному процессу. Без неё «быстрее» означало бы
# «сделало меньше», и замер мерил бы скорость чего-то другого.
#
# $1 — предел пробегов, $2 — сколько потоков в рабочем режиме, дальше — список K.
# N   — сколько процессов в стенде (должно совпадать с тем, что собрано).
# REP — сколько повторов; берётся минимум, потому что помеха может замер только
#       удлинить.
set -u
source "$(dirname "${BASH_SOURCE[0]}")/obshchee.sh"
TURNS=$1; shift
W=$1; shift
N=${N:-1024}
REP=${REP:-3}
# Метка тяжести обработчика: пусто — дешёвый стенд `b-пачка-kK-N`, число —
# дорогой `b-пачка-kK-tT-N`. Порог считается отношением цены передачи к цене
# ПРОБЕГА, значит мерить его надо на обоих концах, а не на одном.
TYAZH=${TYAZH:-}

# Один прогон: печатает настенное время, либо «ОТКАЗ»/«СУММА» с диагностикой.
# $1 каталог, $2 число потоков (0 — проверочный режим)
razok() {
  local dir=$1 workers=$2 more="" out err code w
  if [ "$workers" != 0 ]; then more=",\"workers\":\"$workers\""; fi
  local req="{\"run\":\"стенд\",\"seed\":\"1\",\"turns\":\"$TURNS\",\"journal\":\"0\"$more}"
  out=$(mktemp); err=$(mktemp)
  echo "$req" | /usr/bin/time -f '%e' "$dir/flang_cli" > "$out" 2>"$err"
  code=$?
  if [ $code -ne 0 ]; then echo "ОТКАЗ код=$code $(head -c 200 "$err")"; rm -f "$out" "$err"; return 1; fi
  # Контрольная сумма: Σ«всего» обязана сойтись с числом пробегов.
  if ! python3 - "$out" "$TURNS" <<'PY'
import json, sys
итог = json.load(open(sys.argv[1], encoding="utf-8"))
пробегов = int(итог["пробегов"])
сумма = sum(int(float(поле[1]["n"])) for _, сост in итог["состояния"] for поле in сост["r"] if поле[0] == "всего")
if пробегов != int(sys.argv[2]) or сумма != пробегов:
    sys.exit(f"СУММА не сошлась: пробегов {пробегов}, объявлено {sys.argv[2]}, Σвсего {сумма}")
PY
  then rm -f "$out" "$err"; return 1; fi
  w=$(tail -1 "$err")
  rm -f "$out" "$err"
  printf '%s' "$w"
}

menshe() { [ 1 -eq "$(awk -v x="$1" -v y="$2" 'BEGIN{print (x<y)?1:0}')" ]; }

echo "--- порог окупаемости: пробегов $TURNS, процессов $N, потоков $W, повторов $REP, тяжесть «${TYAZH:-нет}»"
printf '%4s %12s %12s %10s %14s\n' K "проверочн,с" "рабочий,с" "раз" "пробегов/с"
for K in "$@"; do
  if [ -n "$TYAZH" ]; then DIR=$(stend "b-пачка-k$K-t$TYAZH-$N"); else DIR=$(stend "b-пачка-k$K-$N"); fi
  ODIN=""; MNOGO=""
  # Режимы чередуются ВНУТРИ повтора, а не меряются блоками. Машина под чужой
  # нагрузкой, и нагрузка эта гуляет: измерив сперва все повторы одного режима,
  # а потом все повторы другого, мы сравнили бы разные минуты, а не два режима.
  for _ in $(seq 1 "$REP"); do
    A=$(razok "$DIR" 0)      || { echo "K=$K проверочный: $A"; exit 1; }
    B=$(razok "$DIR" "$W")   || { echo "K=$K рабочий: $B"; exit 1; }
    if [ -z "$ODIN" ]  || menshe "$A" "$ODIN";  then ODIN=$A;  fi
    if [ -z "$MNOGO" ] || menshe "$B" "$MNOGO"; then MNOGO=$B; fi
  done
  awk -v k="$K" -v a="$ODIN" -v b="$MNOGO" -v t="$TURNS" \
    'BEGIN { printf "%4s %12.3f %12.3f %9.2fx %14.0f\n", k, a, b, a/b, t/b }'
done
