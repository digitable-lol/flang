#!/bin/bash
# Цена порождения и её РОВНОСТЬ: стенд «рой» на нескольких пределах пробегов.
#
# Наклон здесь считается не по двум точкам, а по нескольким подряд, и не ради
# точности. Вопрос стенда — не «сколько стоит порождение», а «растёт ли оно с
# числом уже заведённых»: при поиске адресата перебором таблицы каждый
# следующий пробег дороже предыдущего, и разности между соседними точками
# расходятся. При указателе имён они совпадают.
#
# $1 каталог сборки, дальше — пределы пробегов. Повторов задаётся REP (по
# умолчанию 5), предел числа процессов — PROCS (по умолчанию два миллиона:
# столько, чтобы упереться в пробеги, а не в предел).
set -u
source "$(dirname "${BASH_SOURCE[0]}")/obshchee.sh"
DIR=$(stend "$1"); shift
REP=${REP:-5}
PROCS=${PROCS:-2000000}
echo "--- $DIR  повторов $REP, предел процессов $PROCS"
for T in "$@"; do
  printf 'пробегов %s: ' "$T"
  bash "$FLANG/flang/conc/zamer/mera.sh" "$DIR" "$T" 0 "$REP" "$PROCS" |
    awk '{print $2 + $3}' | sort -g | head -1 | tr -d '\n'
  printf ' с процессорного (минимум из %s)\n' "$REP"
done
