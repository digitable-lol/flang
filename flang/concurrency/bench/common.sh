# Общее для всех замерялок. Подключается точкой, самостоятельно не запускается.
#
# ZAMER — каталог, где лежат собранные стенды (`b-<вид>-<N>`). По умолчанию —
# текущий каталог, чтобы команды из docs/scheduler-benchmark.md работали как
# написаны. FLANG — корень дерева flang; по умолчанию два уровня вверх от
# этого файла.
ZAMER=${ZAMER:-$PWD}
FLANG=${FLANG:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}

# Путь к стенду: имя каталога ищется сперва как есть, потом внутри ZAMER.
stend() {
  if [ -x "$1/flang_cli" ]; then printf '%s' "$1"; else printf '%s/%s' "$ZAMER" "$1"; fi
}
