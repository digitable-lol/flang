#!/bin/bash
# Сколько процессов прогон ТЯНЕТ, если заводит их сам (шаг Б1).
#
# Стенд «рой» заводит по одному процессу на два пробега, поэтому число
# процессов задаётся пределом пробегов, а не исходником. На каждую точку
# печатается: пробегов, заведённых процессов, процессорное время, пиковый RSS и
# байт на процесс по RSS.
#
# Это ответ на вопрос «сколько тянем числом», и отвечает он прогоном: до Б1
# такой вопрос упирался в компилятор (миллион объявлений — 166 МБ исходника и
# минута сборки), а не в планировщик.
#
# $1 каталог сборки, дальше — пределы пробегов. PROCS — предел числа процессов.
set -u
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
DIR=$(stend "$1"); shift
PROCS=${PROCS:-8000000}
ERR=$(mktemp)
printf '%10s %10s %8s %12s %10s\n' пробегов процессов "цпу,с" "RSS,КиБ" "Б/процесс"
for T in "$@"; do
  REQ="{\"run\":\"стенд\",\"seed\":\"1\",\"turns\":\"$T\",\"journal\":\"0\",\"processes\":\"$PROCS\"}"
  N=$(echo "$REQ" | "$DIR/flang_cli" 2>"$ERR" | tr ',' '\n' | grep -c '^\["р')
  echo "$REQ" | /usr/bin/time -f "%U %S %M" "$DIR/flang_cli" > /dev/null 2>"$ERR"
  read -r u s m < <(tail -1 "$ERR")
  awk -v t="$T" -v n="$N" -v u="$u" -v s="$s" -v m="$m" \
    'BEGIN { b = 0; if (n > 0) { b = m * 1024 / n }; printf "%10d %10d %8.2f %12d %10.0f\n", t, n, u + s, m, b }'
done
rm -f "$ERR"
