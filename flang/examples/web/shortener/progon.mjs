/**
 * ХОЗЯИН СЛУЖБЫ — четырнадцать запросов подряд, включая четыре злонамеренных.
 *
 * Это НЕ сервер: порта здесь нет, сокет не открывается, соединения не
 * принимаются. Это тот самый цикл, который в настоящем сервере стоял бы за
 * `accept`, — и он показывает ровно то, ради чего служба написана на flang:
 *
 *   сервер есть БЕСКОНЕЧНАЯ ПОСЛЕДОВАТЕЛЬНОСТЬ ЗАВЕРШАЮЩИХСЯ ПРОГРАММ.
 *
 * Незавершаемость живёт здесь, в цикле хозяина (`for (const …)` ниже, а в
 * настоящем сервере — `while (true) accept()`). Обработчик завершается всегда,
 * и это не надежда, а вывод `flang check`: каждая функция службы помечена
 * `тотальная`, и проверка типов отказалась бы собирать программу, если бы хоть
 * одна пометку не несла.
 *
 * Состояние передаётся из витка в виток ЗНАЧЕНИЕМ — так же, как его передаёт
 * планировщик конкурентности процессу (`server.flang`) и хозяин ввода-вывода
 * плану (`plan.flang`). Три разных хозяина, один и тот же уклад.
 *
 * Запуск:  node flang/examples/web/shortener/progon.mjs
 */
import { fileURLToPath } from "node:url"
import { dirname, resolve } from "node:path"
import { loadProgram } from "../../../bin/flang.mjs"
import { evaluateFlang } from "../../../src/compat.mjs"

const здесь = dirname(fileURLToPath(import.meta.url))
const служба = resolve(здесь, "service.flang")

/* Программа читается ОДИН раз, а не на каждый запрос: в настоящем сервере
   разбор исходника тоже случается при запуске, а не при соединении. */
const программа = await loadProgram(служба)

const ПУСТО = { записи: [], выдано: 0 }

/** Один виток: состояние и байты запроса — новое состояние и байты ответа. */
function обслужить(состояние, текст) {
  return evaluateFlang(программа, "Обслужить", { хранилище: состояние, текст }, { maxSteps: 40000000 })
}

/* Content-Length считается ПО ТЕЛУ, а не пишется руками. Единица здесь — ЗНАК,
   а не октет, потому что `длина` в языке считает знаки: тот самый зазор, что
   назван числом в service.flang. Хозяин, говорящий с настоящей сетью, обязан
   был бы считать октеты — и это работа хозяина ровно до тех пор, пока в языке
   нет функции «сколько байтов в строке UTF-8». */
const почтой = (тело) => `POST /ссылки HTTP/1.1\r\nContent-Length: ${[...тело].length}\r\n\r\n${тело}`

const СЦЕНАРИЙ = [
  ["здоровье",               "GET /здоровье HTTP/1.1\r\nHost: п\r\n\r\n"],
  ["создание ссылки",        почтой("адрес=https://пример.рф/док")],
  ["переход по коду",        "GET /с/к1 HTTP/1.1\r\n\r\n"],
  ["список ссылок",          "GET /ссылки HTTP/1.1\r\n\r\n"],
  ["чужой код",              "GET /с/нету HTTP/1.1\r\n\r\n"],
  ["метод не тот",           "PUT /ссылки HTTP/1.1\r\n\r\n"],
  ["нет такого пути",        "GET /админка HTTP/1.1\r\n\r\n"],
  ["ЗЛАЯ СХЕМА javascript:", почтой("адрес=javascript:alert(1)")],
  ["код занят",              почтой("адрес=https://п.рф&код=к1")],
  ["ТЕЛО ЗАПРОСА В МЕГАБАЙТ", почтой("адрес=https://п.рф/" + "ы".repeat(1000000))],
  ["ОБРЕЗАННЫЙ ЗАПРОС",      "GET /здор"],
  ["ДВЕ ДЛИНЫ ТЕЛА",         "POST /ссылки HTTP/1.1\r\nContent-Length: 2\r\ncontent-length: 2\r\n\r\nаб"],
  ["ЗАГОЛОВОК В МЕГАБАЙТ",   "GET / HTTP/1.1\r\nX-Ж: " + "a".repeat(1000000) + "\r\n\r\n"],
  ["СТО ОДИН ЗАГОЛОВОК",     "GET / HTTP/1.1\r\n" + Array.from({ length: 101 }, (_, i) => `X-${i}: 1`).join("\r\n") + "\r\n\r\n"],
  ["удаление",               "DELETE /ссылки/к1 HTTP/1.1\r\n\r\n"],
  ["переход после удаления", "GET /с/к1 HTTP/1.1\r\n\r\n"],
]

let состояние = ПУСТО
console.log("код | запрос                  | строка состояния ответа")
console.log("----+-------------------------+" + "-".repeat(46))
for (const [имя, текст] of СЦЕНАРИЙ) {
  const о = обслужить(состояние, текст)
  состояние = о["состояние"]
  const строка = (о["ответ"] || "").split("\r\n")[0] || "(молчание — запрос не доехал)"
  console.log(String(о["код"]).padStart(3) + " | " + имя.padEnd(23) + " | " + строка)
}
console.log("\nхранилище после шестнадцати запросов: " + JSON.stringify(состояние))
