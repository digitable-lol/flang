/**
 * СЛУЖБА С ЖУРНАЛОМ — три прогона, и весь смысл в том, что их три.
 *
 * Рядом лежит `serve-network.mjs`: та же служба по тому же TCP, но всё, что она
 * нажила, исчезает вместе с планом. Здесь план кончается и запускается ЗАНОВО,
 * а состояние остаётся, — и это единственное, что здесь проверяется.
 *
 *   ПРОГОН 1  журнала нет вовсе. Служба создаёт ссылку, считает переход,
 *             создаёт вторую, удаляет вторую. Порт закрывается — план кончился.
 *   ПРОГОН 2  ТОТ ЖЕ файл журнала, НОВЫЙ план с нуля. Ни одного байта состояния
 *             из прогона 1 в него не передано — только файл. `GET /ссылки`
 *             обязан отдать ровно то же, что отдавал в конце прогона 1.
 *   ПРОГОН 3  хозяин, у которого запись файла ВСЕГДА отказывает. Создание
 *             обязано ответить 503, а не 201, и хранилище обязано остаться
 *             пустым: изменение, которого не приняли в журнал, не совершено.
 *
 * ЧЕГО ЭТОТ ПРОГОН НЕ ПОКАЗЫВАЕТ, и это надо сказать здесь же: питания никто не
 * выключал. Отклик «Записано» значит «хозяин сказал, что записал», и ни одно
 * слово ниже не про пластину диска.
 *
 * Запуск:  node flang/examples/web/shortener/serve-durable.mjs
 */
import assert from "node:assert/strict"
import { connect } from "node:net"
import { mkdtempSync, readFileSync, rmSync, existsSync } from "node:fs"
import { tmpdir } from "node:os"
import { fileURLToPath } from "node:url"
import { dirname, resolve, join } from "node:path"
import { loadProgram } from "../../../bin/flang.mjs"
import { runPlan } from "../../../src/io.mjs"
import { nodeHost } from "../../../src/host/node.mjs"

const здесь = dirname(fileURLToPath(import.meta.url))
const программа = await loadProgram(resolve(здесь, "plan-durable.flang"))

const изПрограммы = (имя) => {
  const значение = (программа.functions ?? []).find((ф) => ф.name === имя)?.body?.value
  if (значение === undefined) throw new Error(`в программе не найдено «${имя}»`)
  return значение
}
const ПОРТ = Number(изПрограммы("Порт службы с журналом"))
const ЖУРНАЛ = String(изПрограммы("Журнал службы"))

const почтой = (тело) => `POST /ссылки HTTP/1.1\r\nContent-Length: ${[...тело].length}\r\n\r\n${тело}`

function однаСвязь(текст) {
  return new Promise((решить, отказать) => {
    const куски = []
    const связь = connect({ port: ПОРТ, host: "127.0.0.1" }, () => связь.end(Buffer.from(текст, "utf8")))
    связь.on("data", (кусок) => куски.push(кусок))
    связь.on("close", () => решить(Buffer.concat(куски).toString("utf8")))
    связь.on("error", отказать)
  })
}

/* Порт открывает ХОЗЯИН, и открывает он его тогда, когда план выдаст первое
   «Принять связь», — а до того план успевает сходить за журналом. Клиент,
   постучавшийся раньше, получает ECONNREFUSED, и это не отказ службы, а гонка
   прогона. Поэтому первая связь ждёт порта, а не падает. */
async function запросом(текст) {
  for (let попытка = 0; ; попытка += 1) {
    try {
      return await однаСвязь(текст)
    } catch (беда) {
      if (беда?.code !== "ECONNREFUSED" || попытка >= 200) throw беда
      await new Promise((дальше) => setTimeout(дальше, 20))
    }
  }
}

const кодОтвета = (ответ) => (ответ.length === 0 ? 0 : Number(ответ.split("\r\n")[0].split(" ")[1] ?? 0))
const телоОтвета = (ответ) => ответ.split("\r\n\r\n").slice(1).join("\r\n\r\n")

/** Один прогон плана: поднять службу, отдать сценарий, закрыть порт. */
async function прогон(имя, каталог, сценарий, обёртка = (х) => х) {
  const хозяин = обёртка(nodeHost({ base: каталог }))
  const служба = runPlan(программа, "Обслужить с журналом", хозяин, { maxSteps: 200_000_000 })
  const ответы = []
  for (const [что, текст] of сценарий) {
    const ответ = await запросом(текст)
    ответы.push({ что, код: кодОтвета(ответ), тело: телоОтвета(ответ) })
  }
  хозяин.закрыть()
  const итог = await служба
  const поручений = итог.журнал.reduce((с, з) => {
    с[з.поручение.variant] = (с[з.поручение.variant] ?? 0) + 1
    return с
  }, {})
  console.log(`\n── ${имя} ` + "─".repeat(Math.max(0, 62 - имя.length)))
  for (const о of ответы) {
    console.log("  " + String(о.код).padStart(3) + "  " + о.что.padEnd(28) + "  " + JSON.stringify(о.тело).slice(0, 60))
  }
  console.log("  связей обслужено: " + итог.значение + "; поручений: " + JSON.stringify(поручений))
  return ответы
}

const каталог = mkdtempSync(join(tmpdir(), "flang-durable-"))
const путьЖурнала = join(каталог, ЖУРНАЛ)

try {
  /* ── ПРОГОН 1: журнала нет, служба его заводит ────────────────────────── */
  assert.equal(existsSync(путьЖурнала), false, "журнал не должен существовать до первого прогона")

  const первый = await прогон("ПРОГОН 1 — журнала не было", каталог, [
    ["здоровье (не в журнал)", "GET /здоровье HTTP/1.1\r\n\r\n"],
    ["создание к1", почтой("адрес=https://пример.рф/док")],
    ["переход по к1", "GET /с/к1 HTTP/1.1\r\n\r\n"],
    ["переход по к1 ещё раз", "GET /с/к1 HTTP/1.1\r\n\r\n"],
    ["создание к2", почтой("адрес=https://пример.рф/два")],
    ["удаление к2", "DELETE /ссылки/к2 HTTP/1.1\r\n\r\n"],
    ["чужой код (не в журнал)", "GET /с/нету HTTP/1.1\r\n\r\n"],
    ["список ссылок", "GET /ссылки HTTP/1.1\r\n\r\n"],
  ])
  assert.deepEqual(первый.map((о) => о.код), [200, 201, 301, 301, 201, 204, 404, 200])

  const журнал = readFileSync(путьЖурнала, "utf8")
  const записей = (журнал.match(/(^|;)#\d+:/g) ?? []).length
  console.log("\n  журнал на диске: " + [...журнал].length + " знаков, записей " + записей)
  console.log("  первые 90 знаков: " + JSON.stringify(журнал.slice(0, 90)))
  assert.equal(записей, 5, "в журнал обязаны были лечь ровно пять меняющих запросов из восьми")

  /* ── ПРОГОН 2: тот же файл, план с нуля ───────────────────────────────── */
  const второй = await прогон("ПРОГОН 2 — план с нуля, журнал тот же", каталог, [
    ["список ссылок после перезапуска", "GET /ссылки HTTP/1.1\r\n\r\n"],
  ])
  assert.equal(второй[0].код, 200)

  console.log("\n  список в конце прогона 1: " + JSON.stringify(первый.at(-1).тело))
  console.log("  список в начале прогона 2: " + JSON.stringify(второй[0].тело))
  assert.equal(
    второй[0].тело,
    первый.at(-1).тело,
    "состояние не пережило перезапуск: список после восстановления разошёлся со списком до него",
  )

  /* ── ПРОГОН 3: журнал отказывает ──────────────────────────────────────── */
  const глухой = (хозяин) => {
    const обёрнутый = async (поручение) =>
      поручение.variant === "Записать файл"
        ? { variant: "Сбой", fields: { код: "FLANG_IO_WRITE", сообщение: "диск полон" } }
        : хозяин(поручение)
    обёрнутый.закрыть = () => хозяин.закрыть()
    return обёрнутый
  }
  const каталог3 = mkdtempSync(join(tmpdir(), "flang-durable-глухой-"))
  const третий = await прогон("ПРОГОН 3 — журнал не принимает записей", каталог3, [
    ["создание при мёртвом журнале", почтой("адрес=https://пример.рф/док")],
    ["список после отказа", "GET /ссылки HTTP/1.1\r\n\r\n"],
  ], глухой)
  assert.deepEqual(третий.map((о) => о.код), [503, 200], "отказ журнала обязан дать 503, а не 201")
  assert.equal(третий[1].тело, "", "хранилище изменилось, хотя журнал запись не принял")
  assert.equal(existsSync(join(каталог3, ЖУРНАЛ)), false)
  rmSync(каталог3, { recursive: true, force: true })

  console.log("\n" + "═".repeat(70))
  console.log("СОШЛОСЬ:")
  console.log("  • пять меняющих запросов из восьми легли в журнал, три — нет;")
  console.log("  • план запущен ЗАНОВО с пустого состояния и восстановил тот же список,")
  console.log("    включая счётчик переходов (2) и то, что к2 удалена;")
  console.log("  • при отказе журнала служба ответила 503 и НЕ изменила состояния.")
  console.log("НЕ ПОКАЗАНО: питание не выключалось. «Записано» значит «хозяин сказал,")
  console.log("что записал», и ничего про пластину диска здесь не утверждается.")
} finally {
  rmSync(каталог, { recursive: true, force: true })
}
