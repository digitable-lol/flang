/**
 * СЛУЖБА ПО СЕТИ — те же шестнадцать запросов, но через настоящий сокет.
 *
 * Рядом лежит `serve.mjs` — тот же сценарий, но байты там передавались
 * ЗНАЧЕНИЕМ, из массива в вызов функции. Здесь между сценарием и службой стоит
 * TCP: клиент открывает соединение на 127.0.0.1, пишет байты, получает байты и
 * закрывает соединение. Ни один ответ этой таблицы не взят из памяти — все
 * шестнадцать
 * прочитаны из сокета.
 *
 * ЧТО ЗДЕСЬ ЧЕГО СТОИТ, и это надо сказать точно:
 *
 *   сервер     — `runPlan` над `plan-network.flang` с настоящим хозяином
 *                (`nodeHost`); порт открывает хозяин, поручение выдаёт план;
 *   клиент     — шестнадцать соединений подряд, по одному на запрос;
 *   конец      — `хозяин.закрыть()`: слушающий сокет закрывается, ждущее
 *                `«Принять соединение»` получает `«Сбой»`, план кончается числом
 *                обслуженных соединений. Сервер кончается СНАРУЖИ, и это видно.
 *
 * Незавершаемости здесь нет ни в одной функции flang: цикл живёт в `runPlan`,
 * а каждая функция плана и службы помечена `тотальная`. Сервер есть бесконечная
 * последовательность завершающихся программ, и здесь это буквально устройство
 * прогона, а не оборот речи.
 *
 * Запуск:  node flang/examples/web/shortener/serve-network.mjs
 */
import { connect } from "node:net"
import { fileURLToPath } from "node:url"
import { dirname, resolve } from "node:path"
import { loadProgram } from "../../../bin/flang.mjs"
import { runPlan } from "../../../src/io.mjs"
import { nodeHost } from "../../../src/host/node.mjs"

const здесь = dirname(fileURLToPath(import.meta.url))
const программа = await loadProgram(resolve(здесь, "plan-network.flang"))

/* Порт назван в САМОЙ ПРОГРАММЕ (`«Порт службы»`), и берём мы его оттуда же, а
   не из константы рядом: разойдись они — клиент стучался бы не туда, и виноват
   был бы этот файл, а не служба. */
const ПОРТ = Number(
  (программа.functions ?? []).find((ф) => ф.name === "Порт службы")?.body?.value,
)
if (!Number.isInteger(ПОРТ)) throw new Error("в программе не найден «Порт службы»")

/* Content-Length считается ПО ТЕЛУ, а не пишется руками, и единица здесь ЗНАК,
   а не октет: `длина` в языке считает знаки — тот самый зазор, что назван
   числом в service.flang и сетью не закрыт. */
const почтой = (тело) => `POST /ссылки HTTP/1.1\r\nContent-Length: ${[...тело].length}\r\n\r\n${тело}`

const СЦЕНАРИЙ = [
  ["здоровье",               "GET /здоровье HTTP/1.1\r\nHost: п\r\n\r\n"],
  ["создание ссылки",        почтой("адрес=https://пример.рф/док")],
  ["переход по коду",        "GET /с/к1 HTTP/1.1\r\n\r\n"],
  ["список ссылок",          "GET /ссылки HTTP/1.1\r\n\r\n"],
  ["чужой код",              "GET /с/нету HTTP/1.1\r\n\r\n"],
  ["метод не тот",           "PUT /ссылки HTTP/1.1\r\n\r\n"],
  ["нет такого пути",        "GET /админка HTTP/1.1\r\n\r\n"],
  ["ЗЛАЯ СХЕМА javascript:", почтой("адрес=javascript:alert(1)")],
  ["код занят",              почтой("адрес=https://п.рф&код=к1")],
  ["ТЕЛО ЗАПРОСА В МЕГАБАЙТ", почтой("адрес=https://п.рф/" + "ы".repeat(1000000))],
  ["ОБРЕЗАННЫЙ ЗАПРОС",      "GET /здор"],
  ["ДВЕ ДЛИНЫ ТЕЛА",         "POST /ссылки HTTP/1.1\r\nContent-Length: 2\r\ncontent-length: 2\r\n\r\nаб"],
  ["ЗАГОЛОВОК В МЕГАБАЙТ",   "GET / HTTP/1.1\r\nX-Ж: " + "a".repeat(1000000) + "\r\n\r\n"],
  ["СТО ОДИН ЗАГОЛОВОК",     "GET / HTTP/1.1\r\n" + Array.from({ length: 101 }, (_, i) => `X-${i}: 1`).join("\r\n") + "\r\n\r\n"],
  ["удаление",               "DELETE /ссылки/к1 HTTP/1.1\r\n\r\n"],
  ["переход после удаления", "GET /с/к1 HTTP/1.1\r\n\r\n"],
]

/**
 * Один запрос — одно соединение.
 *
 * Пишется всё разом и сразу закрывается ПОЛОВИНА соединения (`end`): клиент
 * говорит
 * «больше от меня байтов не будет» и продолжает слушать. Без этого обрезанный
 * запрос висел бы вечно и был бы прав: служба ждёт продолжения, а клиент ждёт
 * ответа. FIN — это и есть то, чем обрезанный запрос отличается от медленного.
 */
function запросом(текст) {
  return new Promise((решить, отказать) => {
    const куски = []
    const соединение = connect({ port: ПОРТ, host: "127.0.0.1" }, () => {
      соединение.end(Buffer.from(текст, "utf8"))
    })
    соединение.on("data", (кусок) => куски.push(кусок))
    соединение.on("close", () => решить(Buffer.concat(куски)))
    соединение.on("error", отказать)
  })
}

const хозяин = nodeHost({ base: здесь })

/* Служба поднимается ПЕРВОЙ и работает всё время, пока идёт сценарий. Ждать её
   здесь нельзя — она не кончится, пока не закроют порт. */
const служба = runPlan(программа, "Обслужить по сети", хозяин, { maxSteps: 200_000_000 })

const началось = Date.now()
console.log(`служба слушает 127.0.0.1:${ПОРТ} — шестнадцать соединений, по одному на запрос\n`)
console.log("код | запрос                   | байт | строка состояния ответа")
console.log("----+--------------------------+------+" + "-".repeat(46))

const сводка = []
for (const [имя, текст] of СЦЕНАРИЙ) {
  const ответ = await запросом(текст)
  const строка = ответ.length === 0 ? "(молчание — соединение закрыто без байтов)" : ответ.toString("utf8").split("\r\n")[0]
  const код = ответ.length === 0 ? 0 : Number(строка.split(" ")[1] ?? 0)
  сводка.push({ имя, код, байт: ответ.length })
  console.log(
    String(код).padStart(3) + " | " + имя.padEnd(24) + " | " +
    String(ответ.length).padStart(4) + " | " + строка,
  )
}

/* Порт отдаётся обратно системе, и это единственный способ закончить план:
   ждущее «Принять соединение» получает «Сбой», план отвечает «Конец работы». */
хозяин.закрыть()
const итог = await служба

const поручений = итог.журнал.reduce((с, з) => {
  с[з.поручение.variant] = (с[з.поручение.variant] ?? 0) + 1
  return с
}, {})

console.log("\nплан кончился сам, когда закрыли порт:")
console.log("  соединений обслужено (итог плана):  " + итог.значение)
console.log("  поручений выдано всего:         " + итог.поручений)
for (const [имя, сколько] of Object.entries(поручений)) {
  console.log("    " + имя.padEnd(26) + сколько)
}
console.log("  секунд на шестнадцать соединений:   " + ((Date.now() - началось) / 1000).toFixed(1))
console.log("  коды по порядку:                " + сводка.map((с) => с.код).join(" "))

/*
 * ПОСЛЕДНЕЕ, И РАДИ ЧЕГО ВСЁ. Утверждение «та же служба, только байты пришли из
 * сокета» проверяется не глазами: коды сверяются с теми, что даёт `serve.mjs`,
 * где байты передавались значением, из массива в вызов функции. Разойдись они
 * хоть на один — прогон падает, и падает громко.
 */
import assert from "node:assert/strict"

const ЧЕРЕЗ_ЗНАЧЕНИЕ = [200, 201, 301, 200, 404, 405, 404, 422, 409, 413, 0, 400, 431, 431, 204, 404]
assert.deepEqual(
  сводка.map((с) => с.код),
  ЧЕРЕЗ_ЗНАЧЕНИЕ,
  "коды по сети разошлись с кодами того же сценария через значение (serve.mjs)",
)
console.log("\nсверка с serve.mjs (те же шестнадцать через значение): коды сошлись все шестнадцать")
