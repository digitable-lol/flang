def слинкован(строки):
    """Есть ли у модуля импорты — читается ЗАГОЛОВОК МОДУЛЯ, не дерево.

    ЗАЧЕМ ЭТОТ ОТБОР ВООБЩЕ СУЩЕСТВУЕТ. `flang ast` печатает программу
    РАЗОБРАННУЮ И СЛИНКОВАННУЮ: у модуля с импортами в дереве лежат
    объявления ЧУЖИХ файлов, и метки «из какого файла узел» у них НЕТ ни
    одной. Их места (строка, столбец) указывают в чужой файл, а разложенные
    по сетке этого — молча портят число. Замер 26 сентября 2026 на
    `flang/self/emit-ts.flang` (32 строки): в дереве 985 функций, 35 344
    места, самое дальнее — строка 6043, и 68 мест падают в полосу 1…32
    этого файла, не будучи его местами.

    Поэтому файл с импортами НЕ меряется вовсе и числится отдельно: нуль в
    числителе был бы неправдой, а смешанное число — неправдой вдвойне.
    Это не оговорка прибора, а препятствие на пути самой задачи 1307:
    пока дерево не помнит, из какого файла узел, «напечатать дерево обратно
    в файл» не выражается даже как вопрос.

    Заголовок читается текстом, а не двоичным, нарочно: иначе за каждый
    отсев платили бы полной линковкой — тем самым, чего отсев избегает.
    """
    видели_заголовок = False
    for с in строки:
        голая = с.strip()
        if голая == "" or голая.startswith("//"):
            continue
        if not с[:1].isspace():
            if видели_заголовок:
                return False        # заголовок модуля кончился
            видели_заголовок = True
            continue
        слова = голая.split()
        if слова and слова[0] in СЛОВА_ИМПОРТА:
            return True
    return False


def имя_в_кавычках(имя):
    return "«%s»" % имя


def поверхность_литерала(з):
    if з is True:
        return "да"
    if з is False:
        return "нет"
    if isinstance(з, str):
        э = (з.replace("\\", "\\\\").replace('"', '\\"')
              .replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r"))
        return '"' + э + '"'
    if isinstance(з, float) and з.is_integer():
        return str(int(з))
    return str(з)


def поверхность_узла(у, путь=""):
    """Поверхность одного узла дерева, или None — если узел не текст.

    Отдаёт ещё и вид, под которым узел учтён, — для списка «видов без
    правила»: узел, которому поверхности не нашлось, обязан быть назван.
    """
    в = у.get("kind")
    if в == "literal":
        return поверхность_литерала(у.get("value"))
    if в == "var":
        return у.get("name", "")
    if в == "call":
        # `«Длина» от результат`, но у зова без доводов слова «от» нет вовсе:
        # `(«Заглавные»)`. Моя же ошибка первого захода — ставила «от» всегда.
        имя = имя_в_кавычках(у.get("name", ""))
        return имя + " от" if у.get("args") else имя
    if в == "builtin":
        return у.get("name", "")
    if в == "field":
        return "." + имя_в_кавычках(у.get("field", ""))
    if в == "binary":
        return ОПЕРАТОРЫ.get(у.get("op"))
    if в == "list":
        # `[` у непустого списка, `пустой список` у пустого: закрывающей
        # скобки в дереве нет, и она теряется — это потеря дерева, не прибора.
        return "[" if у.get("items") else "пустой список"
    if в == "record":
        # Одно и то же `kind` под `types` — ОБЪЯВЛЕНИЕ типа, а в выражении —
        # построение значения; слова у них разные, и различить их можно
        # только местом узла в дереве.
        слово_ = "объект " if путь == "types" else "запись "
        return слово_ + имя_в_кавычках(у.get("name", ""))
    if в == "sum":
        return "тип " + имя_в_кавычках(у.get("name", ""))
    if в == "theorem":
        return "теорема " + имя_в_кавычках(у.get("name", ""))
    if в == "ftsLegacy":
        if у.get("construct") == "moduleHeader":
            з = у.get("value") or {}
            имя = з.get("name", "") if isinstance(з, dict) else str(з)
            return "модуль " + имя_в_кавычках(имя)
        return None
    if в in СЛОВА_УЗЛОВ:
        return СЛОВА_УЗЛОВ[в]
    if в in ВИДЫ_ТИПОВ:
        return None
    if в == "apply":
        return None          # ведущее слово даёт вложенный узел `fn`
    return None


def места_дерева(дерево):
    """Все (строка, столбец, поверхность) дерева разбора, и что не разобрано.

    Обходится ВСЁ дерево, включая `functions`, `types`, `theorems`, `legacy`:
    узел с `span` может лежать где угодно, и пропуск ветки был бы занижением
    числа по вине прибора, а не дерева.
    """
    места = []
    без_правила = {}
    операторы_без_слова = set()

    def слово(путь, узел):
        """Поверхность узлов, у которых нет поля kind: они узнаются местом."""
        if путь == "functions":
            return ("тотальная функция " if узел.get("total") else "функция ") + \
                   имя_в_кавычках(узел.get("name", ""))
        if путь == "params":
            return узел.get("name", "")
        if путь == "postconditions":
            return "обеспечивает " + имя_в_кавычках(узел.get("name", ""))
        if путь == "preconditions":
            return "требует " + имя_в_кавычках(узел.get("name", ""))
        if путь == "examples":
            return "пример " + имя_в_кавычках(узел.get("name", ""))
        if путь == "fields":
            return узел.get("name", "")
        if путь == "cases":
            return "случай " + имя_в_кавычках(узел.get("name", ""))
        if путь == "variants":
            return "вариант " + имя_в_кавычках(узел.get("name", ""))
        if путь == "steps":
            довод = узел.get("by") or {}
            слово_довода = ДОВОДЫ_ШАГА.get(довод.get("rule"))
            if слово_довода is None:
                return None
            текст, с_именем = слово_довода
            if с_именем and довод.get("name"):
                return текст + " " + имя_в_кавычках(довод["name"])
            return текст
        if путь == "claim":
            return "утверждаем"
        return None

    def обойти(узел, путь):
        if isinstance(узел, dict):
            м = узел.get("span")
            if isinstance(м, dict) and "line" in м and "column" in м:
                с = (поверхность_узла(узел, путь) if узел.get("kind")
                     else слово(путь, узел))
                if с:
                    места.append((м["line"], м["column"], с))
                else:
                    ключ = узел.get("kind") or ("<" + путь + ">")
                    if узел.get("kind") == "binary":
                        операторы_без_слова.add(узел.get("op"))
                        ключ = "binary/" + str(узел.get("op"))
                    без_правила[ключ] = без_правила.get(ключ, 0) + 1
            for к, з in узел.items():
                if к != "span":
                    обойти(з, к)
        elif isinstance(узел, list):
            for з in узел:
                обойти(з, путь)

    обойти(дерево, "")
    return места, без_правила, операторы_без_слова

def разряд(строка):
    голая = строка.replace(" ", "").replace("\t", "").replace("\r", "")
    if голая == "":
        return "пусто"
    if "//" in строка:
        return "комментарий"
    return "код"


# Слова языка по-русски — для разбора причин, а не для сборки. Список нужен
# ровно затем, чтобы отличить «дерево не помнит написание слова языка» от
# «потеряно имя»; полнота списка на числа кругооборота не влияет.
СЛОВА_ЯЗЫКА = {
    "модуль", "тип", "запись", "функция", "тотальная", "принимает",
    "возвращает", "даёт", "обеспечивает", "требует", "пример", "дано",
    "ожидается", "пусть", "равно", "если", "то", "иначе", "разбор",
    "случай", "свёртка", "начиная", "с", "как", "и", "или", "от", "на",
    "отобразить", "отфильтровать", "вариант", "теорема", "утверждаем",
    "по", "следовательно", "доказано", "индукция", "предположению",
    "примеру", "свойству", "теореме", "определению", "экспорт", "импорт",
}


def причина_дерева(исходная, собранная):
    """Почему строка не собралась ИЗ ДЕРЕВА — по тому, что именно пропало."""
    без_скобок = исходная.replace("(", "").replace(")", "")
    if без_скобок.split() == собранная.split():
        return "скобки (дерево их не хранит)"
    собрано = собранная.split()
    for слово in без_скобок.split():
        if слово in собрано:
            continue
        if слово.strip(",.:") in СЛОВА_ЯЗЫКА:
            return "слово языка не восстановлено: «%s»" % слово.strip(",.:")
        if слово.startswith("«") and слово.strip("«»") in собрано:
            return "кавычки имени (выбор автора, дерево его не хранит)"
        return "потеряно: «%s»" % слово
    return "порядок или пробелы"


def причина(исходная, собранная, есть_место=True, лад="токены"):
    if "//" in исходная:
        return "строчный комментарий"
    if "/*" in исходная or "*/" in исходная:
        return "блочный комментарий"
    if not есть_место and исходная.strip() != "":
        return "строка без единого места в дереве"
    if собранная.strip() == "" and исходная.strip() != "":
        return "строка пропала целиком"
    if лад == "дерево":
        return причина_дерева(исходная, собранная)
    if "\\u" in исходная or "\\x" in исходная:
        return "форма экранирования \\uXXXX"
    if any(з in исходная for з in ШИРОКИЕ):
        return "широкая пунктуация"
    if re.search(r'\\[nrt0abfv\\"/]', исходная):
        return "форма экранирования короткая"
    return "прочее"


def знаки_на_месте(исходная, собранная):
    """Сколько знаков строки собраны НА СВОЁМ МЕСТЕ.

    Линейка нарочно строгая: знак учтён, только если он стоит в том же
    столбце. Пропущенная скобка портит весь хвост строки — и это правда о
    сборке, а не придирка: текст, сдвинутый на знак, не равен исходному.
    """
    всего = len(исходная)
    на_месте = sum(1 for а, б in zip(исходная, собранная) if а == б)
    return всего, на_месте


def снять(путь, каталог, лад, предел):
    """Позвать двоичный за токенами или за деревом разбора.

    Отдаёт (дерево, код, секунды). Код `None` — не уложился в предел:
    у такого файла НЕТ числа, и нулём в числителе он не идёт.
    """
    подкоманда = "ast" if лад == "дерево" else "tokens"
    ключ = os.path.relpath(путь, КОРЕНЬ).replace("/", "__")[:-6]
    цель = os.path.join(каталог, ключ + "." + подкоманда + ".json")
    доводы = [ДВОИЧНЫЙ, подкоманда, путь]
    if подкоманда == "tokens":
        доводы.append("--json")
    начало = time.time()
    with open(цель, "wb") as вых:
        ход = subprocess.Popen(доводы, stdout=вых,
                               stderr=subprocess.DEVNULL, cwd=КОРЕНЬ)
        try:
            код = ход.wait(timeout=предел)
        except subprocess.TimeoutExpired:
            ход.kill()
            ход.wait()
            return None, None, time.time() - начало
    ушло = time.time() - начало
    if код != 0:
        return None, код, ушло
    try:
        with open(цель, encoding="utf-8") as ф:
            return json.load(ф), 0, ушло
    except Exception:
        return None, -1, ушло


def сличить(путь, дерево, лад):
    текст = open(путь, encoding="utf-8").read()
    строки = текст.split("\n")
    if строки and строки[-1] == "":
        строки = строки[:-1]
    if лад == "дерево":
        места, без_правила, _ = места_дерева(дерево)
        собранные = сетка(места, len(строки))
        неизв = без_правила
        со_местом = {м[0] for м in места}
    else:
        собранные, виды, со_местом = собрать(дерево["tokens"], len(строки))
        неизв = {в: 1 for в in виды}
    счёт = {"код": [0, 0], "комментарий": [0, 0], "пусто": [0, 0]}
    знаки = [0, 0]
    строк_с_местом = 0
    кода_с_местом = 0
    расхождения = []
    for н, (о, в) in enumerate(zip(строки, собранные), 1):
        р = разряд(о)
        счёт[р][0] += 1
        if н in со_местом:
            строк_с_местом += 1
            if р == "код":
                кода_с_местом += 1
        всего, на_месте = знаки_на_месте(о, в)
        знаки[0] += всего
        знаки[1] += на_месте
        if о == в:
            счёт[р][1] += 1
        else:
            расхождения.append((н, о, в, н in со_местом))
    целиком = all(с[0] == с[1] for с in счёт.values())
    весь_код = счёт["код"][0] == счёт["код"][1]
    return {"счёт": счёт, "знаки": знаки, "целиком": целиком,
            "весь код": весь_код, "строк с местом": строк_с_местом,
            "кода с местом": кода_с_местом,
            "без правила": неизв, "расхождения": расхождения,
            "строк": len(строки)}


