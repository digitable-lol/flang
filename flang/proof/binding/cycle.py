def поверхность(т):
    в = т["kind"]
    if в in ("newline", "indent", "dedent", "eof"):
        return None
    if в == "keyword":
        return т.get("text", "")
    if в == "name":
        з = т.get("value", "")
        return ("«%s»" % з) if т.get("quoted") else з
    if в == "number":
        return т.get("text", "")
    if в == "string":
        з = т.get("value", "")
        if not isinstance(з, str):
            з = str(з)
        э = (з.replace("\\", "\\\\").replace('"', '\\"')
              .replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r"))
        return '"' + э + '"'
    if в == "punct":
        з = т.get("value", "")
        return з if isinstance(з, str) else str(з)
    return т.get("text", "") or str(т.get("value", ""))


def сетка(места, число_строк):
    """Положить каждую поверхность на свою строку в свой столбец.

    Один и тот же код кладёт и токены, и узлы дерева: правило раскладки
    обязано быть одно, иначе два числа несравнимы по построению.
    """
    по_строкам = {}
    for строка, столбец, с in места:
        по_строкам.setdefault(строка, []).append((столбец, с))
    строки = []
    for н in range(1, число_строк + 1):
        буф = ""
        for столбец, с in sorted(по_строкам.get(н, [])):
            if len(буф) < столбец - 1:
                буф += " " * (столбец - 1 - len(буф))
            буф = буф[:столбец - 1] + с if len(буф) >= столбец - 1 else буф + с
        строки.append(буф)
    return строки


def собрать(токены, число_строк):
    места = []
    неизвестные = set()
    for т in токены:
        с = поверхность(т)
        if с is None or с == "":
            if т["kind"] not in ("newline", "indent", "dedent", "eof"):
                неизвестные.add(т["kind"])
            continue
        места.append((т["span"]["line"], т["span"]["column"], с))
    return сетка(места, число_строк), неизвестные, {м[0] for м in места}



