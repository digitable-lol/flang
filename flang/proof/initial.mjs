/**
 * initial.mjs — начальная алгебра: принцип индукции ЧИТАЕТСЯ с объявления суммы.
 *
 * ── Почему принципа здесь не выдумано ни одного ─────────────────────────────
 * Объявленная сумма — это начальная алгебра полиномиального функтора. Функтор
 * читается с объявления буквально и без выбора:
 *
 *     тип «Дерево чисел»
 *       вариант «Пустое»
 *       вариант «Развилка» содержит значение: число, меньшие: «Дерево чисел»,
 *                                             большие: «Дерево чисел»
 *
 *     F(X) = 1 + (число × X × X)
 *
 * Сумма по вариантам, произведение по полям, `X` на месте каждого поля, чей тип
 * — сам объявляемый тип. Выбирать здесь не из чего: это переписанное другими
 * знаками то же объявление.
 *
 * У начальной алгебры такого функтора есть универсальное свойство, и оно даёт
 * СРАЗУ ДВЕ вещи, а не одну. Первая — свёртка (катаморфизм): она в языке с
 * самого начала, словом `свёртка … начиная с …`. Вторая — принцип индукции, и
 * его в языке не было. Это одна и та же теорема, прочитанная в двух разных
 * категориях, поэтому индукция не заводится здесь новым понятием: раз свёртка
 * законна, законен и принцип, и оба следуют из объявления, а не из соглашения.
 *
 * Отсюда главное решение этого файла: принцип — ДАННЫЕ, а не правило. Он
 * порождается по объявлению как терм (`принципИндукции`), и ядро его СВОРАЧИВАЕТ
 * ровно так же, как сворачивает всякий другой терм. Правило в JavaScript
 * пришлось бы читать целиком, чтобы поверить ему; терм ядро проверяет.
 *
 * ── Что порождается, буквально ──────────────────────────────────────────────
 * Для суммы T с конструкторами C₁…Cₙ и цели P(x) при x: T принцип таков:
 *
 *   для каждого Cᵢ — посылка:
 *     из P(ч₁) … P(ч_k)  (по одному допущению на каждое поле типа T)
 *     следует P(Cᵢ(…))
 *   вывод: для всех x: T верно P(x)
 *
 * Посылка без допущений называется БАЗОЙ, посылка с допущениями — ШАГОМ. Это не
 * два разных правила: и то, и другое — одна и та же посылка функтора, у которой
 * `X` встретился ноль раз или больше нуля. Именно поэтому перечисление
 * (`«Светофор»`) доказывается тем же принципом, что и дерево, а не «конечным
 * исчерпанием как особым случаем»: у перечисления просто нет шагов.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 * Ни одной проверки. Этот файл только ЧИТАЕТ объявление и строит терм; принять
 * или отвергнуть доказательство — работа ядра (`flang/src/proofterm.mjs`), и
 * держать это порознь нужно затем, чтобы порождение принципа можно было
 * прочитать, не читая проверяльщика, и наоборот.
 *
 * Ни одного поиска. Все подстановки читаются: поле рекурсивно или нет — сказано
 * типом поля; ветвь разбора отвечает варианту — сказано именем варианта; имя
 * части — сказано образцом. Подбирать не из чего.
 */

import { ИМЕНА_НАТ, ТОЧНАЯ_СЕТКА } from "../src/types.mjs"
