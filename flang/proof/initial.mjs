/**
 * initial.mjs — начальная алгебра: принцип индукции ЧИТАЕТСЯ с объявления суммы.
 *
 * ── Почему принципа здесь не выдумано ни одного ─────────────────────────────
 * Объявленная сумма — это начальная алгебра полиномиального функтора. Функтор
 * читается с объявления буквально и без выбора:
 *
 *     тип «Дерево чисел»
 *       вариант «Пустое»
 *       вариант «Развилка» содержит значение: число, меньшие: «Дерево чисел»,
 *                                             большие: «Дерево чисел»
 *
 *     F(X) = 1 + (число × X × X)
 *
 * Сумма по вариантам, произведение по полям, `X` на месте каждого поля, чей тип
 * — сам объявляемый тип. Выбирать здесь не из чего: это переписанное другими
 * знаками то же объявление.
 *
 * У начальной алгебры такого функтора есть универсальное свойство, и оно даёт
 * СРАЗУ ДВЕ вещи, а не одну. Первая — свёртка (катаморфизм): она в языке с
 * самого начала, словом `свёртка … начиная с …`. Вторая — принцип индукции, и
 * его в языке не было. Это одна и та же теорема, прочитанная в двух разных
 * категориях, поэтому индукция не заводится здесь новым понятием: раз свёртка
 * законна, законен и принцип, и оба следуют из объявления, а не из соглашения.
 *
 * Отсюда главное решение этого файла: принцип — ДАННЫЕ, а не правило. Он
 * порождается по объявлению как терм (`принципИндукции`), и ядро его СВОРАЧИВАЕТ
 * ровно так же, как сворачивает всякий другой терм. Правило в JavaScript
 * пришлось бы читать целиком, чтобы поверить ему; терм ядро проверяет.
 *
 * ── Что порождается, буквально ──────────────────────────────────────────────
 * Для суммы T с конструкторами C₁…Cₙ и цели P(x) при x: T принцип таков:
 *
 *   для каждого Cᵢ — посылка:
 *     из P(ч₁) … P(ч_k)  (по одному допущению на каждое поле типа T)
 *     следует P(Cᵢ(…))
 *   вывод: для всех x: T верно P(x)
 *
 * Посылка без допущений называется БАЗОЙ, посылка с допущениями — ШАГОМ. Это не
 * два разных правила: и то, и другое — одна и та же посылка функтора, у которой
 * `X` встретился ноль раз или больше нуля. Именно поэтому перечисление
 * (`«Светофор»`) доказывается тем же принципом, что и дерево, а не «конечным
 * исчерпанием как особым случаем»: у перечисления просто нет шагов.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 * Ни одной проверки. Этот файл только ЧИТАЕТ объявление и строит терм; принять
 * или отвергнуть доказательство — работа ядра (`flang/src/proofterm.mjs`), и
 * держать это порознь нужно затем, чтобы порождение принципа можно было
 * прочитать, не читая проверяльщика, и наоборот.
 *
 * Ни одного поиска. Все подстановки читаются: поле рекурсивно или нет — сказано
 * типом поля; ветвь разбора отвечает варианту — сказано именем варианта; имя
 * части — сказано образцом. Подбирать не из чего.
 */

import { одинаковы } from "../src/obligations.mjs"
import { СПИСОК, нормализовать, образецВарианта, связанныеОбразцом } from "./reduce.mjs"

/** Версия формата принципа: его читает ядро и близнец, значит она названа. */
export const АЛГЕБРА = 1

/** Имя встроенного списка в вердикте — то же слово, каким тип пишется. */
export const ИМЯ_СПИСКА = "список"

/**
 * ОБЪЯВЛЕНИЕ ВСТРОЕННОГО СПИСКА — прочитанное, а не постулированное.
 *
 * ── Почему это чтение, а не аксиома ─────────────────────────────────────────
 * Аксиома — утверждение, принятое без доказательства; его нельзя проверить, и
 * ложная аксиома отравляет всё, что из неё выведено (`х плюс 1 не меньше х`
 * ЛОЖНО при |x| от 2⁵³ — ровно поэтому список аксиом ядра пуст и остаётся
 * пуст). Здесь же не утверждается ничего нового: три факта о списке уже
 * объявлены языком, СЧИТАЮТСЯ им сегодня и держат на себе другие слои. Эта
 * функция их переписывает в ту же форму, в какой автор пишет `тип … вариант …`:
 *
 *   1. КОНСТРУКТОРОВ РОВНО ДВА. Говорит типизатор: `разбор` списка исчерпан
 *      тогда и только тогда, когда покрыты `пусто` и `голова и хвост`
 *      (`flang/src/types.mjs`, `reportExhaustiveness`). Третьего образца у
 *      списка нет ни в разборщике (`parsePattern`), ни в одной из восьми целей
 *      печати. Значит посылок у принципа ровно две — столько же, сколько
 *      конструкторов, как и у объявленной суммы.
 *   2. ПОЛЯ ЗВЕНА И ИХ ТИПЫ. Говорит тот же типизатор (`bindPattern`, случай
 *      `cons`): при разборе `список Э` голова получает тип `Э`, хвост — тип
 *      `список Э`. Отсюда функтор читается буквально и без выбора:
 *
 *          F(X) = 1 + (Э × X)
 *
 *      Место `X` — хвост, потому что его тип есть САМ разбираемый тип; голова —
 *      коэффициент, потому что её тип другой. Правило то же самое, что у
 *      объявленной суммы, и применяется той же строкой кода.
 *   3. ХВОСТ — ЧАСТЬ ЗНАЧЕНИЯ, СТРОГО МЕНЬШАЯ ЦЕЛОГО. Говорит анализ
 *      завершаемости (`flang/src/totality.mjs`, `bindPattern`: голова и хвост
 *      помечаются `deeper`), и на этом факте стоит обещание «тотальная,
 *      структурой» у 212 функций корпуса. Допущение индукции о хвосте законно
 *      ровно постольку, поскольку законно это обещание, — довод один и тот же.
 *
 * То есть форма списка была известна разборщику, типизатору и анализу
 * завершаемости; не знало её одно ядро доказательства. Здесь оно её узнаёт из
 * тех же трёх мест, а не из четвёртого решения. Если язык когда-нибудь заведёт
 * списку третий образец, это чтение станет неправдой — и покраснеет проверка,
 * которая сверяет два конструктора с исчерпывающностью типизатора
 * (`flang/test/proof-kernel.test.mjs`), а не пользователь на своей программе.
 *
 * ── Чего здесь нарочно нет ──────────────────────────────────────────────────
 * СТРОКИ. Тот же типизатор исчерпывает `разбор` строки теми же двумя
 * образцами, и соблазн отдать ей ту же алгебру велик. Но функтор у неё ДРУГОЙ:
 * у строки голова — тоже строка, то есть по правилу «поле того же типа» местом
 * `X` оказались бы ОБА поля, и принцип потребовал бы два допущения вместо
 * одного. Это отдельная работа с отдельным доводом, и делать её заодно значило
 * бы протащить непрочитанное решение под видом прочитанного. Строка отвергается
 * с названной причиной, и 19 функций `strings.flang` ждут своей очереди.
 *
 * @param {object} тип узел типа `{ kind: "list", of: <тип элемента> }`
 * @returns {object} объявление в той же форме, какую даёт `тип … вариант …`
 */
export function объявлениеСписка(тип) {
  const элемент = тип?.of ?? null
  return {
    kind: "sum",
    name: ИМЯ_СПИСКА,
    /* Сам тип — затем, что у встроенного списка имени в поле нет: хвост
       объявлен не словом «список», а типом `список Э`, и место `X` узнаётся
       сравнением с этим типом. У объявленной суммы `self` нет, и там работает
       сравнение по имени — то самое, что работало до сих пор. */
    self: тип ?? null,
    variants: [
      { name: СПИСОК.пусто, fields: [] },
      {
        name: СПИСОК.звено,
        fields: [
          { name: СПИСОК.голова, type: элемент },
          { name: СПИСОК.хвост, type: тип ?? null },
        ],
      },
    ],
  }
}

/**
 * Сигнатура функтора суммы: F(X) = Σ по вариантам Π по полям.
 *
 * Единственное, что здесь решается, — какое поле считать местом `X`: поле, чей
 * тип есть САМ объявляемый тип. Не «похожий», не «содержащий его внутри»:
 * `меньшие: «Дерево чисел»` — это `X`, а `дети: список «Дерево чисел»` — нет,
 * потому что за списком стоит другой функтор, и допущение о его элементах —
 * другое допущение. Граница названа прямо и стоит рядом с той же границей у
 * монады (`monad.mjs`: параметр обязан стоять в поле ЦЕЛИКОМ).
 *
 * @param {object} сумма объявление типа-суммы из AST
 * @returns {{ type: string, variants: object[], base: number, step: number }}
 */
export function сигнатураФунктора(сумма) {
  const варианты = (сумма?.variants ?? []).map((вариант) => {
    const поля = вариант.fields ?? []
    const рекурсивные = поля.filter((поле) => местоX(поле.type, сумма))
    const прочие = поля.filter((поле) => !местоX(поле.type, сумма))
    return {
      name: вариант.name,
      /* Поля-места `X`: по одному допущению индукции на каждое. */
      recursive: рекурсивные.map((поле) => поле.name),
      /* Поля-коэффициенты: они переносятся в посылку как есть и допущения не
         несут. Значение в них не меньше и не больше целого — оно другого типа. */
      carried: прочие.map((поле) => ({ name: поле.name, type: поле.type ?? null })),
      arity: рекурсивные.length,
    }
  })
  return {
    algebra: АЛГЕБРА,
    type: сумма?.name ?? null,
    variants: варианты,
    /* База и шаг — не два вида посылок, а одно число: сколько раз в посылке
       встретился `X`. Ноль — база. */
    base: варианты.filter((в) => в.arity === 0).length,
    step: варианты.filter((в) => в.arity > 0).length,
  }
}

/**
 * Принцип индукции для цели — как ТЕРМ.
 *
 * Собирается из трёх прочитанных мест и ни одного угаданного:
 *   1. объявление суммы — сколько посылок и у какой сколько допущений;
 *   2. образец случая — какими именами автор назвал части значения;
 *   3. тело функции — чем `результат` оказывается в этой ветви разбора.
 *
 * Третье и есть то, из-за чего принцип нельзя было бы записать раз и навсегда
 * таблицей: утверждение говорит о `результат`, а `результат` в каждом случае
 * СВОЙ — это ветвь `разбор` по тому же самому параметру. Подстановка читается с
 * узла, а не подбирается: ветвь названа тем же именем варианта, что и случай.
 *
 * @param {object} параметры
 * @param {object} параметры.сумма объявление суммы
 * @param {object} параметры.функция функция, чьё постусловие доказывается
 * @param {object} параметры.обязательство обязательство из `obligations.mjs`
 * @param {object} параметры.индукция узел `индукция по …` из теоремы
 * @returns {object} терм принципа
 */
export function принципИндукции({ сумма, функция, обязательство, индукция }) {
  const функтор = сигнатураФунктора(сумма)
  const ветви = ветвиРазбора(функция, индукция.param)
  const образцы = new Map()
  for (const случай of индукция.cases ?? []) {
    const прочитано = образецВарианта(случай?.pattern)
    if (прочитано === null) continue
    образцы.set(прочитано.name, случай)
  }

  const посылки = функтор.variants.map((вариант) => {
    const случай = образцы.get(вариант.name) ?? null
    const ветвь = ветви.get(вариант.name) ?? null
    /* Имена частей: как их назвал автор образцом случая. Если случая нет (автор
       пропустил вариант), берутся имена ветви разбора — посылка обязана быть
       порождена всё равно, иначе ядру нечего было бы предъявить как пропущенное. */
    const связиСлучая = образецВарианта(случай?.pattern)?.bind ?? null
    const связиВетви = образецВарианта(ветвь?.pattern)?.bind ?? {}
    const связи = связиСлучая ?? связиВетви
    const переименование = ветвь === null ? new Map() : сличитьИмена(связиВетви, связи)
    const части = вариант.recursive.map((поле) => связи[поле] ?? связиВетви[поле] ?? поле)

    return {
      kind: вариант.arity === 0 ? "base" : "step",
      variant: вариант.name,
      arity: вариант.arity,
      /* Имя переменной индукции лежит у каждой посылки, а не только у принципа:
         посылку читают порознь (её отдают правилам шага одну), и доставать имя
         обратно из объемлющего узла значило бы связать читателя с тем, что
         посылка всегда лежит внутри принципа. */
      param: индукция.param,
      binds: связи,
      parts: части,
      /* Замкнут ли случай: у посылки без единого связанного имени значение ровно
         одно, и утверждение о нём — утверждение обо всём случае. Это и есть то,
         что позволяет закрыть базу вычислением. */
      closed: Object.keys(связи).length === 0,
      /* Объявления, видимые в заключении этой посылки, — с типами, как их
         написал автор. Их два вида, и оба читаются, а не выводятся:
         параметры функции (кроме самой переменной индукции — она в заключении
         уже заменена конструктором) и ПОЛЯ-КОЭФФИЦИЕНТЫ варианта под теми
         именами, какими их назвал образец случая.
         Тип поля — это факт о нём ровно в той же мере, в какой тип параметра —
         факт о параметре: `вариант «Слой» содержит вес: нат` говорит «вес не
         меньше 0» так же, как `принимает вес: нат`. Ядро эти факты не выводит,
         оно их читает (`reduce.mjs`, `известноеПоТипу`). */
      declarations: [
        ...(функция?.params ?? [])
          .filter((п) => п.name !== индукция.param)
          .map((п) => ({ name: п.name, type: п.type ?? null })),
        ...вариант.carried.map((поле) => ({ name: связи[поле.name] ?? поле.name, type: поле.type })),
      ],
      /* Допущения индукции: по одному на место `X`, и каждое — ТА ЖЕ цель,
         в которой переменная индукции заменена частью. Ядро их СТРОИТ, а не
         сличает: построить — единственный способ не дать назвать допущением что
         угодно. */
      hypotheses: части.map((часть) => ({
        kind: "hypothesis",
        of: обязательство.name,
        param: индукция.param,
        part: часть,
        /* Утверждение допущения: ТА ЖЕ цель, в которой переменная индукции стала
           частью, а `результат` — результатом той же функции на этой части.
           Две подстановки, а не одна: цель вправе говорить и о `результат`, и о
           самой переменной («результат равно стопка»), и забыть вторую значило бы
           получить допущение о другом значении — то есть принять ложь. */
        claim: подставить(обязательство.goal, {
          [обязательство.bind ?? "результат"]: {
            kind: "call",
            name: обязательство.of,
            args: аргументыНаЧасти(функция, индукция.param, часть),
          },
          [индукция.param]: { kind: "var", name: часть },
        }),
      })),
      /* Заключение посылки: та же цель, в которой переменная индукции стала
         КОНСТРУКТОРОМ этого варианта с полями образца, а `результат` — телом
         ветви разбора, переименованным в имена образца.
         Порядок здесь значим и потому записан явно: тело ветви само вправе
         упоминать переменную индукции (`случай …  то «Уравновесить» от узел`),
         поэтому конструктор подставляется В ТЕЛО прежде, чем тело встанет на
         место `результат`. Одной подстановкой этого не сделать: подставленное
         поддерево второй раз не обходится — иначе подстановка могла бы
         зациклиться на себе. */
      conclusion:
        ветвь === null
          ? null
          : подставить(обязательство.goal, {
              [обязательство.bind ?? "результат"]: подставить(
                подставитьИмена(ветвь.body, переименование),
                { [индукция.param]: конструктор(вариант, связи) },
              ),
              [индукция.param]: конструктор(вариант, связи),
            }),
      /* Ветвь могла не найтись: тело функции разбирает не тот параметр или не
         разбирает вовсе. Это не ошибка автора теоремы, а факт о функции, и
         назвать его обязано ядро — здесь он просто записан. */
      branch: ветвь === null ? null : вариант.name,
      case: случай,
    }
  })

  return {
    kind: "induction",
    algebra: АЛГЕБРА,
    type: функтор.type,
    functor: функтор,
    param: индукция.param,
    of: обязательство.of,
    name: обязательство.name,
    premises: посылки,
    /* Вывод принципа — то самое, ради чего он и порождался: утверждение обо ВСЕХ
       значениях типа, а не о написанных. */
    conclusion: { forall: индукция.param, type: функтор.type, goal: обязательство.goal },
    /* Разобрано ли тело функции по переменной индукции. Ноль ветвей значит, что
       посылки не с чем сводить, и ядро обязано сказать это словами. */
    matched: ветви.size > 0,
  }
}

/**
 * Ветви `разбор` по переменной индукции — из тела функции.
 *
 * Ищется ровно один узел: `разбор <переменная индукции>` на верхнем уровне тела.
 * Не «где-нибудь внутри»: разбор, спрятанный под условием, отвечает не за все
 * значения переменной, и брать из него ветвь значило бы приписать случаю тело,
 * до которого вычисление может и не дойти. Такой поиск был бы не чтением, а
 * догадкой.
 */
function ветвиРазбора(функция, параметр) {
  const ветви = new Map()
  /* Тело нормализуется перед чтением: `пусть` перед разбором — обычная запись
     («Уравновесить слева» в `stdlib/tree.flang` начинается именно так), и
     отказывать ей значило бы отказывать не по существу. Нормализация разворачивает
     `пусть` и ничего не вычисляет, поэтому разбор остаётся тем же разбором. */
  const тело = нормализовать(функция?.body ?? null)
  if (тело?.kind !== "match") return ветви
  if (тело.target?.kind !== "var" || тело.target.name !== параметр) return ветви
  for (const случай of тело.cases ?? []) {
    const прочитано = образецВарианта(случай?.pattern)
    if (прочитано === null) continue
    ветви.set(прочитано.name, случай)
  }
  return ветви
}

/**
 * Переименование связей ветви функции в связи образца теоремы — по ПОЛЮ.
 *
 * Автор теоремы вправе назвать части иначе, чем названы они в теле функции:
 * `случай вариант «Развилка» с меньшие как левое` при теле, где то же поле
 * связано как `м`. Соответствие читается по имени ПОЛЯ, а не по порядку: порядок
 * полей в образце автор писать не обязан.
 */
function сличитьИмена(связиВетви, связиСлучая) {
  const карта = new Map()
  for (const [поле, имя] of Object.entries(связиВетви)) {
    const целевое = связиСлучая[поле]
    if (typeof целевое === "string" && целевое !== имя) карта.set(имя, целевое)
  }
  return карта
}

/**
 * Уравнение образца, записанное значением: переменная индукции РАВНА конструктору
 * с полями, названными образцом.
 *
 * Это не вывод и не догадка: так написал автор словом `случай`, и типизатор уже
 * сказал, что такой вариант у суммы есть. Поле, которое образец не назвал,
 * получает имя самого поля — оно всё равно остаётся непрозрачным именем, и
 * назвать его как-то надо, чтобы конструктор был выражением, а не дыркой.
 */
function конструктор(вариант, связи) {
  const поля = {}
  for (const имя of [...вариант.recursive, ...вариант.carried.map((п) => п.name)]) {
    поля[имя] = { kind: "var", name: связи[имя] ?? имя }
  }
  return { kind: "construct", variant: вариант.name, fields: поля }
}

/**
 * Аргументы вызова функции на части значения.
 *
 * Переменная индукции заменяется частью, остальные параметры остаются собой:
 * допущение говорит о том же вызове с теми же прочими аргументами, иначе оно
 * было бы допущением о другой функции.
 */
function аргументыНаЧасти(функция, параметр, часть) {
  return (функция?.params ?? []).map((п) =>
    п.name === параметр ? { kind: "var", name: часть } : { kind: "var", name: п.name },
  )
}

/**
 * Подстановка выражений вместо свободных имён — с уважением к связывающим узлам.
 *
 * Захвата здесь быть не может: под `пусть`, под образцом `разбор` и под
 * `свёртка` связанное имя из подстановки ВЫЧЁРКИВАЕТСЯ, потому что внутри оно
 * означает уже не то, что снаружи. Без этого правила подстановка молча
 * переименовывала бы чужую переменную — тот самый сорт ошибки, который в
 * проверяльщике доказательств стоит дороже всего.
 *
 * @param {object} выражение узел AST
 * @param {Record<string, object>} замены имя → выражение
 * @returns {object} новый узел
 */
export function подставить(выражение, замены) {
  const карта = new Map(Object.entries(замены ?? {}))
  return пройти(выражение, карта, (узел, текущие) => {
    if (узел?.kind !== "var") return undefined
    const замена = текущие.get(узел.name)
    return замена === undefined ? undefined : замена
  })
}

/** То же самое, но заменяются ИМЕНА на имена: переименование частей. */
export function подставитьИмена(выражение, карта) {
  if (!(карта instanceof Map) || карта.size === 0) return выражение
  return пройти(выражение, new Map(карта), (узел, текущие) => {
    if (узел?.kind !== "var") return undefined
    const имя = текущие.get(узел.name)
    return имя === undefined ? undefined : { ...узел, name: имя }
  })
}

/**
 * СВОБОДНЫЕ ИМЕНА выражения — те, что означают что-то за его пределами.
 *
 * Нужны ровно для одного вопроса, и вопрос этот решает, доказательство перед
 * нами или пример: у выражения БЕЗ свободных имён значение одно, и вычисление
 * отвечает про него обо всём случае; со свободными именами значений столько же,
 * сколько подстановок, и один прогон говорит об одной из них.
 *
 * Связыватели те же четыре, что и у подстановки, и читаются они той же строкой
 * (`связанныеОбразцом`) — иначе на один вопрос «какие имена здесь связаны»
 * было бы два ответа.
 *
 * @param {object} выражение узел AST
 * @returns {Set<string>} имена, свободные в нём
 */
export function свободныеИмена(выражение) {
  const имена = new Set()
  собрать(выражение, new Set(), имена)
  return имена
}

function собрать(узел, связанные, имена) {
  if (узел === null || узел === undefined || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) собрать(элемент, связанные, имена)
    return
  }
  if (узел.kind === "var") {
    if (typeof узел.name === "string" && !связанные.has(узел.name)) имена.add(узел.name)
    return
  }
  if (узел.kind === "let" && typeof узел.name === "string") {
    собрать(узел.value, связанные, имена)
    собрать(узел.in, new Set([...связанные, узел.name]), имена)
    return
  }
  if (узел.kind === "fold") {
    собрать(узел.over, связанные, имена)
    собрать(узел.init, связанные, имена)
    const внутри = new Set(связанные)
    if (typeof узел.acc === "string") внутри.add(узел.acc)
    if (typeof узел.item === "string") внутри.add(узел.item)
    собрать(узел.body, внутри, имена)
    return
  }
  if (узел.kind === "map" || узел.kind === "filter") {
    собрать(узел.over, связанные, имена)
    const внутри = new Set(связанные)
    if (typeof узел.item === "string") внутри.add(узел.item)
    собрать(узел.body, внутри, имена)
    return
  }
  if (узел.kind === "match") {
    собрать(узел.target, связанные, имена)
    for (const случай of узел.cases ?? []) {
      собрать(случай?.body, new Set([...связанные, ...связанныеОбразцом(случай?.pattern)]), имена)
    }
    return
  }
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ !== "span") собрать(значение, связанные, имена)
  }
}

/**
 * Обход выражения с вычёркиванием связанных имён.
 *
 * Связывают четыре узла и только они: `пусть` (`let`), образец случая внутри
 * `разбор` (`match`), `свёртка` (`fold`) и элемент `отобразить`/`отфильтровать`
 * (`map`/`filter`). Список закрыт нарочно: появись в языке пятый связыватель,
 * здесь обязан появиться отказ, а не молчаливый пропуск, — поэтому неизвестные
 * узлы обходятся как есть, но связей не заводят, и если такой узел когда-нибудь
 * свяжет имя, это заметит негативный тест ядра, а не пользователь.
 */
function пройти(узел, связанные, заменить) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => пройти(элемент, связанные, заменить))

  const прямая = заменить(узел, связанные)
  if (прямая !== undefined) return прямая

  if (узел.kind === "let" && typeof узел.name === "string") {
    const внутри = new Map(связанные)
    внутри.delete(узел.name)
    return { ...узел, value: пройти(узел.value, связанные, заменить), in: пройти(узел.in, внутри, заменить) }
  }
  if (узел.kind === "fold") {
    const внутри = new Map(связанные)
    if (typeof узел.acc === "string") внутри.delete(узел.acc)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return {
      ...узел,
      over: пройти(узел.over, связанные, заменить),
      init: пройти(узел.init, связанные, заменить),
      body: пройти(узел.body, внутри, заменить),
    }
  }
  if (узел.kind === "map" || узел.kind === "filter") {
    const внутри = new Map(связанные)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return { ...узел, over: пройти(узел.over, связанные, заменить), body: пройти(узел.body, внутри, заменить) }
  }
  if (узел.kind === "match") {
    return {
      ...узел,
      target: пройти(узел.target, связанные, заменить),
      cases: (узел.cases ?? []).map((случай) => {
        const внутри = new Map(связанные)
        for (const имя of связанныеОбразцом(случай?.pattern)) внутри.delete(имя)
        return { ...случай, body: пройти(случай.body, внутри, заменить) }
      }),
    }
  }

  const собрано = {}
  for (const [ключ, значение] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? значение : пройти(значение, связанные, заменить)
  }
  return собрано
}

function имяИменованного(тип) {
  if (тип === null || тип === undefined) return null
  if (тип.kind === "named") return тип.name
  return null
}

/**
 * Место `X` функтора: поле, чей тип есть САМ объявляемый тип.
 *
 * Одно правило и два способа узнать «тот же тип», потому что типы записаны
 * двумя способами, а не потому, что правил два. У объявленной суммы тип поля
 * назван ИМЕНЕМ (`хвост: «Стопка»`), и совпасть должно имя. У встроенного
 * списка имени нет вовсе — тип написан целиком (`хвост: список Э`), и совпасть
 * должен тип. Сравнение типов — то же синтаксическое равенство, каким слой
 * обязательств сверяет тип переменной теоремы с типом параметра: решать, что
 * два разных типа «означают одно и то же», здесь нечем и не должно быть чем.
 *
 * Граница прежняя и здесь не сдвинута: `дети: список «Дерево»` местом `X` НЕ
 * является ни по одному из двух способов — за списком стоит другой функтор, и
 * допущение о его элементах было бы другим допущением.
 */
function местоX(тип, сумма) {
  if (имяИменованного(тип) === сумма?.name) return true
  const сам = сумма?.self ?? null
  return сам !== null && одинаковы(тип, сам)
}
