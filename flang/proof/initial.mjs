/* Принцип по ОТРЕЗКУ: индукция по `нат`                               */
/* ------------------------------------------------------------------ */

/**
 * ── Почему принцип по числу здесь ВООБЩЕ ЕСТЬ, и почему он не аксиома ────────
 *
 * У `нат` нет объявленных вариантов, поэтому начальную алгебру с него не
 * прочитать: функтора нет, посылок нет, `сигнатураФунктора` вернула бы пустоту.
 * Отсюда мог бы следовать вывод «завести аксиому индукции по числу» — и это
 * был бы худший из возможных выводов, потому что у ядра аксиом ноль и держится
 * этот ноль на прямой причине: числа flang — IEEE-754, и почти все привычные
 * утверждения о них ЛОЖНЫ на краю. `х плюс 1 больше х` неправда при |х| от 2⁵³;
 * `х минус 1 меньше х` неправда там же (при х = 2⁵³+4 округление к ближайшему
 * возвращает то же самое х). Индукция по числу БЕЗ ВЕРХНЕЙ ГРАНИЦЫ — ровно та
 * же ошибка, только больше: она позволила бы спускаться по цепочке, которая
 * никуда не спускается.
 *
 * Поэтому принцип читается не с числа, а с ОБЪЯВЛЕННОГО ТИПА `нат`, и читается
 * с него целиком:
 *
 *     нат = { целые из [0, 2⁵³−1] }        (`types.mjs`, `NAT`)
 *
 * Это КОНЕЧНОЕ множество. У конечного линейно упорядоченного множества всякая
 * строго убывающая цепочка конечна — не потому, что так принято, а потому что
 * иначе в нём было бы бесконечно много различных значений. Значит принцип
 *
 *     P(дно) для всех значений дна  ∧  (для п выше дна: P(п−1) ⟹ P(п))
 *     ⟹  для всех п из нат: P(п)
 *
 * — теорема о конечном отрезке, а не соглашение. Оба множителя её посылки ядро
 * ПРОВЕРЯЕТ, и ни одного не принимает на слово.
 *
 * ── Где здесь ровно та ловушка, из-за которой аксиом ноль ───────────────────
 * Убывание обязано быть СТРОГИМ и обязано оставаться ВНУТРИ отрезка, и оба
 * условия держатся не общими словами, а двумя границами объявленного типа:
 *
 *   ПОТОЛОК 2⁵³−1 даёт строгость. Внутри [0, 2⁵³−1] соседние целые
 *     представимы точно, поэтому `п минус 1` вычисляется ТОЧНО и строго меньше
 *     `п`. За 2⁵³ это перестаёт быть правдой — и ровно там же кончается `нат`.
 *     Индукция по `число` или по `целое` здесь ОТВЕРГАЕТСЯ, и не из
 *     осторожности: у `число` в носителе живут `+∞` (у которого `∞ минус 1`
 *     равно `∞` — спуска нет вовсе) и `не число` (несравнимое ни с чем).
 *
 *   ДНО 0 даёт останов. Цепочка п, п−1, … обязана дойти до дна, а не проскочить
 *     его: поэтому условие дна читается закрытым списком форм, у каждой из
 *     которых верх дна не отрицателен, а шаг вниз — ровно единица. При шаге
 *     вниз на единицу из `п` выше дна получается `п−1`, которое дна ещё не
 *     ниже, — то есть цепочка не выходит из отрезка ни на одном витке.
 *
 * ── Что читается, и ни одного поиска ────────────────────────────────────────
 * Пять мест, и все пять прочитаны, а не подобраны:
 *   1. тип переменной индукции — написан в подписи функции;
 *   2. мера — написана автором словом `убывает` (слово в языке уже есть);
 *   3. условие дна — написано в теле первым же `если` по этой переменной;
 *   4. какая ветвь база — сказано ФОРМОЙ условия, а не догадкой о содержимом;
 *   5. на чём стоит рекурсивный вызов — написано в аргументе вызова.
 *
 * Проверок этот файл по-прежнему не делает НИ ОДНОЙ: всё, чего прочитать не
 * удалось, уезжает в поле `unread` вместе с кодом и словами, а отказывает
 * ядро (`proofterm.mjs`). Держать это порознь надо затем же, зачем и у суммы:
 * порождение читается без проверяльщика, проверяльщик — без порождения.
 */

/**
 * Формы условия дна — СПИСОК ЗАКРЫТ, и у каждой строки свой довод.
 *
 * `К` — конечный числовой литерал, `п` — переменная индукции. `верх` — то
 * наибольшее значение, при котором вычисление уходит в базу; оно же становится
 * фактом посылки базы («п не больше верх»), и оно же обязано быть не
 * отрицательным, иначе цепочка спуска вышла бы за дно отрезка.
 *
 * `годно` — условие на `К`, при котором форма читается. Оно не про удобство:
 * `если п меньше 0` при `п: нат` дало бы базу ПУСТУЮ (значений ниже нуля у
 * `нат` нет), и цепочка спуска не кончилась бы никогда — она уходила бы в
 * отрицательные, которых у типа не бывает.
 *
 * ── ПОЧЕМУ ДВЕ ФОРМЫ ТРЕБУЮТ ЦЕЛОГО «К», И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО ───
 * Две формы получают `верх` вычитанием единицы (`п меньше К` и `п не меньше К`),
 * и при ДРОБНОМ `К` это вычитание врёт. `если п меньше 2.5` при `п: нат`
 * отправляет в базу значения 0, 1 и 2 — а `верх` считается как `2.5 − 1 = 1.5`, и
 * посылка базы получает ФАКТ «п не больше 1.5», ложный ровно на `п = 2`.
 *
 * Это не рассуждение о возможном: до этой строки ядро на такой записи ПЕЧАТАЛО
 * «доказано индукцией» об утверждении, которое рантайм тут же отвергал
 * `FLANG_PROPERTY` на `н = 2`. Улика исполняемая и стоит подделкой в
 * `flang/test/proof-kernel.test.mjs` («ПОДДЕЛКА: дробное дно…»).
 *
 * Починка — отказ, а не подгонка. Взять `Math.ceil(К) − 1` было бы верно для
 * `нат`, но это уже вывод О ЗНАЧЕНИЯХ ТИПА, а не чтение написанного, и он тихо
 * стал бы ложью, приди сюда отрезок нецелых. Форма, у которой дно вычисляется
 * вычитанием единицы, читается только при целом `К`; всё прочее уезжает в
 * `unread` и отвергается кодом `FLANG_PROOF_INDUCTION_BRANCH`. Цена отказа —
 * одна строка, которую автор напишет как `если п не больше 2`.
 *
 * Формам `п не больше К` и `п больше К` целость не нужна: у них `верх = К`, и
 * факт «п не больше К» истинен на всей базе при любом конечном `К`.
 */
const ДНО = Object.freeze([
  { op: "lte", ветвь: "then", верх: (к) => к, годно: (к) => к >= 0, как: "п не больше К" },
  { op: "lt", ветвь: "then", верх: (к) => к - 1, годно: (к) => к >= 1 && Number.isInteger(к), как: "п меньше К" },
  { op: "eq", ветвь: "then", верх: (к) => к, годно: (к) => к === 0, как: "п равно 0" },
  { op: "gt", ветвь: "else", верх: (к) => к, годно: (к) => к >= 0, как: "п больше К" },
  { op: "gte", ветвь: "else", верх: (к) => к - 1, годно: (к) => к >= 1 && Number.isInteger(к), как: "п не меньше К" },
])

/** Шаг вниз: ровно единица, и это не круглое число, а условие останова. */
const ШАГ_ВНИЗ = 1

/**
 * Объявлен ли тип отрезком `нат` — тем же словарём, каким его читает типизатор.
 *
 * Список имён берётся у `types.mjs` (`ИМЕНА_НАТ`), а не переписывается здесь, и
 * по той же причине, по какой его не переписывает `reduce.mjs`: второй список
 * разошёлся бы с первым молча, и `自然数` перестал бы быть отрезком для ядра,
 * оставшись им для типизатора.
 */
export function отрезокНата(имяТипа) {
  return typeof имяТипа === "string" && названоНатуральным(имяТипа)
}

/**
 * Принцип индукции по отрезку `нат` — как ТЕРМ, той же формы, что у суммы.
 *
 * @param {object} параметры
 * @param {string} параметры.тип имя типа, как его написал автор («нат», «nat», …)
 * @param {object} параметры.функция функция, чьё постусловие доказывается
 * @param {object} параметры.обязательство обязательство из `obligations.mjs`
 * @param {object} параметры.индукция узел `индукция по … убывает …`
 * @returns {object} терм принципа; `unread` не `null`, если прочитать не удалось
 */
export function принципПоЧислу({ тип, функция, обязательство, индукция }) {
  const параметры = (функция?.params ?? []).map((п) => п.name)
  const место = параметры.indexOf(индукция.param)
  const каркас = {
    kind: "induction",
    carrier: "segment",
    algebra: АЛГЕБРА,
    segment: { низ: 0, верх: точныйПотолок(), целое: true, step: ШАГ_ВНИЗ },
    type: тип,
    functor: null,
    param: индукция.param,
    of: обязательство.of,
    name: обязательство.name,
    premises: [],
    unmatched: индукция.cases ?? [],
    conclusion: { forall: индукция.param, type: тип, goal: обязательство.goal },
    matched: false,
    unread: null,
  }
  const нечитаемо = (code, why) => ({ ...каркас, unread: { code, why } })

  if (место < 0) {
    return нечитаемо(
      "param",
      `«${индукция.param}» не параметр функции «${обязательство.of}»:`
        + " спуск по числу читается с аргумента рекурсивного вызова, а у не-параметра аргумента нет",
    )
  }

  /* ЧТЕНИЕ 2: мера. По объявленной сумме её писать не надо — часть значения
     меньше значения по построению. По числу надо: убывает не часть, а число, и
     что именно убывает, обязан НАЗВАТЬ автор. Слово для этого в языке уже
     стоит (`убывает`, оно же у меры функции), поэтому девятого слова
     поверхности принцип по отрезку не потребовал ни одного. */
  const мера = индукция.measure ?? null
  if (мера === null) {
    return нечитаемо(
      "measure",
      `индукция по «${индукция.param}» идёт по отрезку «${тип}», а не по объявленной сумме:`
        + " у отрезка нет конструкторов, и убывание не следует из построения значения —"
        + ` его надо назвать. Допишите «убывает ${индукция.param}»`,
    )
  }
  if (мера.kind !== "var" || мера.name !== индукция.param) {
    return нечитаемо(
      "measure",
      `мера индукции — не сама переменная «${индукция.param}»:`
        + " спуск ядро сверяет с аргументом рекурсивного вызова, а сверять с вычисляемой мерой"
        + " ему нечем — это был бы решатель, которого у ядра нет",
    )
  }

  /* ЧТЕНИЕ 3: условие дна. Тело нормализуется — `пусть` перед `если` обычная
     запись, — но не вычисляется: развёртки определений здесь нет нарочно, тем
     же решением, каким её нет у `ветвиРазбора`. */
  const тело = нормализовать(функция?.body ?? null)
  if (тело?.kind !== "if") {
    return нечитаемо(
      "branch",
      `тело функции «${обязательство.of}» на верхнем уровне — не «если»,`
        + ` поэтому дна отрезка в нём не видно: по числу принцип читается с условия «если» по «${индукция.param}»`,
    )
  }
  const форма = формаДна(тело.cond, индукция.param)
  if (форма === null) {
    return нечитаемо(
      "branch",
      `условие «если» в теле «${обязательство.of}» не даёт дна отрезка по «${индукция.param}».`
        + ` Формы, которые ядро читает: ${ДНО.map((ф) => `«${ф.как}»`).join(", ")}`
        + " при конечном литерале К, у которого верх дна не отрицателен —"
        + " иначе цепочка спуска ушла бы ниже нуля, а ниже нуля значений у «нат» нет."
        + " У двух форм («п меньше К» и «п не меньше К») К обязан быть ещё и ЦЕЛЫМ:"
        + " верх дна у них считается как «К минус 1», и при дробном К этот верх врёт —"
        + " «если п меньше 2.5» отправляет в базу и п = 2, а верх вышел бы 1.5",
    )
  }

  const базаТело = форма.правило.ветвь === "then" ? тело.then : тело.else
  const шагТело = форма.правило.ветвь === "then" ? тело.else : тело.then

  /* ЧТЕНИЕ 5: на чём стоит рекурсивный вызов. Здесь и есть та проверка, без
     которой весь принцип был бы подделкой: допущение говорит о значении
     `п минус 1`, и если вызов стоит на чём-то другом — на `п плюс 1`, на
     `п минус 0`, на другом имени, — то допущение говорит не о том вызове,
     который стоит в теле, и «доказано» означало бы «принято на слово». */
  const вЗаключении = вызовыСебя(шагТело, обязательство.of)
  const вБазе = вызовыСебя(базаТело, обязательство.of)
  if (вБазе.length > 0) {
    return нечитаемо(
      "descent",
      `база «${обязательство.of}» зовёт себя же: дно отрезка — это то место, где спуск КОНЧАЕТСЯ,`
        + " и вызов в нём означает, что условие прочитано не как дно",
    )
  }
  if (вЗаключении.length === 0) {
    return нечитаемо(
      "descent",
      `шаг «${обязательство.of}» не зовёт себя ни разу: спускаться нечему,`
        + " и допущение индукции строить не о чем — по отрезку доказывать здесь нечего",
    )
  }
  for (const вызов of вЗаключении) {
    const беда = спускНеСтрогий(вызов, место, индукция.param, параметры.length)
    if (беда !== null) {
      return нечитаемо(
        "descent",
        `спуск в шаге «${обязательство.of}» не строгий: ${беда}.`
          + ` Ядро читает ровно «${индукция.param} минус ${ШАГ_ВНИЗ}» и ничего кроме:`
          + " убывание на единицу внутри [0, 2⁵³−1] точно (соседние целые там представимы),"
          + " и цепочка спуска дна не проскакивает. Всё прочее — либо не убывание,"
          + " либо убывание, которого IEEE-754 не обещает",
      )
    }
  }

  const убывшее = { kind: "binary", op: "sub", left: { kind: "var", name: индукция.param }, right: { kind: "literal", value: ШАГ_ВНИЗ } }
  const слова = `${индукция.param} минус ${ШАГ_ВНИЗ}`
  const объявления = (функция?.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
  const цель = обязательство.goal
  const имяРезультата = обязательство.bind ?? "результат"

  /* ПОСЫЛКА ДНА. Переменная индукции в ней НЕ заменяется: дно — это, вообще
     говоря, не одно значение, а весь отрезок [0, верх], и утверждать надо обо
     всём отрезке сразу. Зато о переменной становится известен ФАКТ — «п не
     больше верх», — и он приезжает в `свести` наравне с объявленным типом:
     это не догадка, а прочитанное условие той самой ветви, в которую попало
     вычисление. */
  const заключениеДна = подставить(цель, { [имяРезультата]: базаТело })
  const дно = {
    kind: "base",
    variant: null,
    label: "дно",
    arity: 0,
    param: индукция.param,
    binds: {},
    parts: [],
    closed: true,
    free: [...свободныеИмена(заключениеДна)],
    declarations: объявления,
    facts: [
      {
        kind: "segment",
        of: обязательство.name,
        param: индукция.param,
        claim: {
          kind: "binary",
          op: "lte",
          left: { kind: "var", name: индукция.param },
          right: { kind: "literal", value: форма.верх },
        },
      },
    ],
    hypotheses: [],
    conclusion: заключениеДна,
    branch: форма.правило.ветвь,
    bound: форма.верх,
    condition: тело.cond,
    case: null,
  }

  /* ПОСЫЛКА ШАГА. Переменная индукции здесь тоже остаётся собой — шаг говорит о
     ПРОИЗВОЛЬНОМ значении выше дна, — а допущение строится по одному на каждый
     рекурсивный вызов и говорит ровно о том вызове, который в теле стоит: цель,
     в которой `результат` заменён этим вызовом, а переменная — убывшим
     значением. Двух подстановок здесь ровно столько же и по той же причине, что
     у суммы: цель вправе говорить и о `результат`, и о самой переменной.

     И У ШАГА ТОЖЕ ЕСТЬ СВОЙ ФАКТ, прочитанный с того же `если`, с которого
     прочитано дно. Раньше поле `facts` у шага стояло пустым, и это была потеря
     написанного: в ветвь спуска вычисление попадает РОВНО ТОГДА, когда условие
     дна ЛОЖНО. Отрицание условия — не вывод и не догадка, а вторая половина той
     же прочитанной формы, и для всех пяти форм таблицы `ДНО` она записывается
     одинаково: «п больше верх».

     ПОЧЕМУ ОДИНАКОВО, ПО СТРОКАМ ТАБЛИЦЫ:
       «п не больше К» (верх = К):  ложно ⟹ п больше К          = п больше верх
       «п меньше К»    (верх = К−1, К целое): ложно ⟹ п не меньше К,
                                    а К больше К−1              ⟹ п больше верх
       «п равно 0»     (верх = 0):  ложно ⟹ п не равно 0, и п из «нат»
                                    не меньше 0                 ⟹ п больше верх
       «п больше К»    (верх = К):  база — ветвь «иначе», спуск — «то»: п больше К
       «п не меньше К» (верх = К−1, К целое): спуск — «то»: п не меньше К
                                                                ⟹ п больше верх
     Целость `К` у двух форм здесь не для строгости, а потому что без неё врёт
     сам `верх` (довод при таблице `ДНО`).

     ЗАЧЕМ ЭТОТ ФАКТ ВООБЩЕ НУЖЕН. Без него шаг «Факториала» не замыкается ничем:
     `н умножить на («Факториал» от (н минус 1))` требует, чтобы хотя бы один
     сомножитель был СТРОГО положителен, а `н: нат` даёт только «не меньше 0» —
     ноль в отрезке живёт. Факт `н больше 1` — единственный источник строгой
     положительности, какой у ядра есть (`reduce.mjs`, `строгоПоложительное`). */
  const заключениеШага = подставить(цель, { [имяРезультата]: шагТело })
  const допущения = []
  const виденные = new Set()
  for (const вызов of вЗаключении) {
    const ключ = JSON.stringify(вызов.args ?? [])
    if (виденные.has(ключ)) continue
    виденные.add(ключ)
    допущения.push({
      kind: "hypothesis",
      of: обязательство.name,
      param: индукция.param,
      part: слова,
      claim: подставить(цель, { [имяРезультата]: вызов, [индукция.param]: убывшее }),
    })
  }
  const шаг = {
    kind: "step",
    variant: null,
    label: "спуск",
    arity: допущения.length,
    param: индукция.param,
    binds: {},
    parts: [слова],
    closed: false,
    free: [...свободныеИмена(заключениеШага)],
    declarations: объявления,
    facts: [
      {
        kind: "segment",
        of: обязательство.name,
        param: индукция.param,
        claim: {
          kind: "binary",
          op: "gt",
          left: { kind: "var", name: индукция.param },
          right: { kind: "literal", value: форма.верх },
        },
      },
    ],
    hypotheses: допущения,
    conclusion: заключениеШага,
    branch: форма.правило.ветвь === "then" ? "else" : "then",
    bound: форма.верх,
    condition: тело.cond,
    case: null,
  }

  /* Случаи автора. Образцов у отрезка два, и оба уже стоят в языке: литерал
     (`случай 0`) — дно, `любое` (`случай любое`) — спуск. Своих образцов
     принцип по числу не завёл ни одного. */
  const лишние = []
  for (const случай of индукция.cases ?? []) {
    const образец = случай?.pattern
    const вид = образец?.kind
    if (вид === "literal" && дно.case === null && числоДна(образец.value, форма)) дно.case = случай
    /* `случай любое` — спуск, и ИМЕНИ у него быть не должно. Связывать в нём
       нечего: значение одно и оно уже названо переменной индукции, а второе имя
       для того же значения читатель принял бы за часть значения, которой у
       числа нет. Молча пропустить такое имя нельзя — оно уедет в лишние, и ядро
       скажет о нём вслух. */
    else if (вид === "any" && шаг.case === null && (образец.bind === undefined || образец.bind === null)) {
      шаг.case = случай
    } else лишние.push(случай)
  }

  return {
    ...каркас,
    premises: [дно, шаг],
    unmatched: лишние,
    matched: true,
    measure: мера,
    floor: { как: форма.правило.как, верх: форма.верх, шаг: ШАГ_ВНИЗ },
  }
}

/**
 * Форма условия дна — или `null`, если ни одна из пяти не подошла.
 *
 * Читается СЛЕВА НАПРАВО и только так: `если п не больше 0` и `если 0 не меньше
 * п` — одно и то же по смыслу, но второе ядро не читает, и это осознанный
 * отказ. Разворачивать неравенство значило бы завести здесь первую крупицу
 * решателя, а цена отказа — одна строка, которую автор напишет иначе.
 */
function формаДна(условие, параметр) {
  if (условие?.kind !== "binary") return null
  if (условие.left?.kind !== "var" || условие.left.name !== параметр) return null
  if (условие.right?.kind !== "literal") return null
  const к = условие.right.value
  if (typeof к !== "number" || !Number.isFinite(к)) return null
  const правило = ДНО.find((форма) => форма.op === условие.op)
  if (правило === undefined || !правило.годно(к)) return null
  return { правило, к, верх: правило.верх(к) }
}

/** Отвечает ли литерал образца дну: значение обязано в дно попадать. */
function числоДна(значение, форма) {
  if (typeof значение !== "number" || !Number.isFinite(значение)) return false
  return значение >= 0 && значение <= форма.верх
}

/**
 * Чем спуск НЕ строгий — словами, или `null`, если строгий.
 *
 * Строгим считается ровно одно: аргумент на месте переменной индукции есть
 * `<переменная> минус <ШАГ_ВНИЗ>`. Ни `плюс`, ни `минус 0`, ни другое имя, ни
 * вычисление. Список закрыт, и это не скупость: всё, что сюда добавится, обязано
 * приехать с доказательством о IEEE-754 — тем же самым, каким открыт этот.
 */
function спускНеСтрогий(вызов, место, параметр, сколькоПараметров) {
  const аргументы = вызов.args ?? []
  if (аргументы.length !== сколькоПараметров) {
    return `вызов на ${аргументы.length} аргументах при ${сколькоПараметров} параметрах`
  }
  const аргумент = аргументы[место]
  if (аргумент?.kind === "var" && аргумент.name === параметр) {
    return `вызов стоит на самом «${параметр}» — это не спуск, а тот же виток`
  }
  if (аргумент?.kind !== "binary" || аргумент.op !== "sub") {
    return `на месте «${параметр}» стоит не вычитание`
  }
  if (аргумент.left?.kind !== "var" || аргумент.left.name !== параметр) {
    return `вычитают не из «${параметр}»`
  }
  if (аргумент.right?.kind !== "literal" || аргумент.right.value !== ШАГ_ВНИЗ) {
    const что = аргумент.right?.kind === "literal" ? `на ${аргумент.right.value}` : "на вычисляемое"
    return `вычитают ${что}, а не на ${ШАГ_ВНИЗ}`
  }
  return null
}

/**
 * ДОПУЩЕНИЕ ИНДУКЦИИ ПО МЕСТУ ВЫЗОВА — то же допущение, но при ДРУГИХ прочих
 * аргументах.
 *
 * ── Что чинится, и почему это не поблажка ───────────────────────────────────
 * Допущение выше строится с прочими параметрами КАК ОНИ НАЗВАНЫ В ПОДПИСИ:
 * «Взять первые» от хвост и сколько. А тело зовёт себя иначе — «Взять первые»
 * от хвост и (сколько минус 1), — и два терма не сличаются знак в знак, потому
 * что второй аргумент разный. Утверждение при этом верно, доказательство есть,
 * а ядро отвечало «не свелось»: допущение говорило о другом значении второго
 * параметра.
 *
 * ── ПОЧЕМУ ЭТО ТЕОРЕМА, А НЕ ВТОРАЯ АКСИОМА ─────────────────────────────────
 * Доказывается утверждение «для всех элементы, для всех сколько», а не «для
 * всех элементы при данном сколько»: прочие параметры стоят в посылке
 * СВОБОДНЫМИ именами, ядро сводит посылку, ничего о них не зная, и потому
 * закрытая посылка закрыта сразу для всех их значений. Значит и допущение о
 * части — тоже «для всех прочих», и взять его при любых прочих аргументах
 * законно. Это обычное обобщение по параметру, каким структурная индукция
 * пользуется везде, а не новое доверие.
 *
 * ── ПОИСКА ЗДЕСЬ НОЛЬ, И ЭТО ГЛАВНОЕ ────────────────────────────────────────
 * Подстановка не подбирается: её НАЗЫВАЕТ САМ ВЫЗОВ, стоящий в заключении.
 * Сколько в заключении вызовов себя, столько и допущений — ни одним больше.
 * Тот же приём, каким работает «по свойству» (сличение по месту вызова) и
 * правило постусловия вызванного.
 *
 * ── ЧЕТЫРЕ УСЛОВИЯ, И НИ ОДНО НЕ УКРАШЕНИЕ ──────────────────────────────────
 *   СПУСК       на месте переменной индукции у вызова обязана стоять РОВНО ТА
 *               ЧАСТЬ, которую связал образец случая (`хвост`), — то есть
 *               значение, уменьшившееся ПО ПОСТРОЕНИЮ. Вызов на самом значении
 *               или на построенном заново — это круг, и допущением он не станет.
 *   НЕ ПОД      вызов берётся только тот, до которого обход дошёл, НИ РАЗУ не
 *   СВЯЗЫВАТЕЛЕМ  войдя внутрь `пусть`, `разбор`, `свёртка`,
 *               `отобразить`/`отфильтровать`. Под связывателем аргументы вызова
 *               означают своё на каждом витке, и допущение, вынесенное наружу,
 *               говорило бы не о том. Список связывателей тот же закрытый, что у
 *               `пройти` и `собрать` в этом файле.
 *   ЧИСЛО       аргументов у вызова столько же, сколько параметров у функции.
 *   БЕЗ ЗАХВАТА подстановка идёт тем же `подставить`, что и везде, и при захвате
 *               имени отказывает — допущение тогда просто не заводится.
 *
 * @returns {object[]} допущения формы `hypotheses`; пусто — вызовов не нашлось
 */
function допущенияПоВызовам({ заключение, функция, обязательство, параметр, части }) {
  if (заключение === null || заключение === undefined) return []
  const параметры = функция?.params ?? []
  const место = параметры.findIndex((п) => п.name === параметр)
  if (место < 0) return []
  const свои = new Set(части)
  const итог = []
  const видано = new Set()
  for (const вызов of вызовыСебяСнаружиСвязывателей(заключение, обязательство.of)) {
    const аргументы = вызов.args ?? []
    if (аргументы.length !== параметры.length) continue
    const наМесте = аргументы[место]
    /* СПУСК: часть, названная образцом случая, и ничто другое. */
    if (наМесте?.kind !== "var" || !свои.has(наМесте.name)) continue
    const замены = {}
    параметры.forEach((п, и) => { замены[п.name] = аргументы[и] })
    const поПараметрам = подставить(обязательство.goal, замены)
    if (поПараметрам === null) continue
    const утверждение = подставить(поПараметрам, { [обязательство.bind ?? "результат"]: вызов })
    if (утверждение === null) continue
    const ключ = JSON.stringify(безМестВУзле(утверждение))
    if (видано.has(ключ)) continue
    видано.add(ключ)
    итог.push({
      kind: "hypothesis",
      of: обязательство.name,
      param: параметр,
      part: наМесте.name,
      /* Чем это допущение отличается от соседнего — полем, а не разбором текста:
         отчёт обязан называть источник, а «допущение» без уточнения не отличает
         построенное по подписи от построенного по месту вызова. */
      at: "call",
      claim: утверждение,
    })
  }
  return итог
}

/** Дерево без мест в исходнике — чтобы два одинаковых допущения считались одним. */
function безМестВУзле(узел) {
  if (Array.isArray(узел)) return узел.map(безМестВУзле)
  if (узел === null || typeof узел !== "object") return узел
  const итог = {}
  for (const ключ of Object.keys(узел).sort()) {
    if (ключ === "span") continue
    итог[ключ] = безМестВУзле(узел[ключ])
  }
  return итог
}

/**
 * Вызовы функции самой себя, до которых обход дошёл СНАРУЖИ всех связывателей.
 *
 * Список связывателей тот же закрытый, что у `пройти` и `собрать`, и разойтись
 * им нельзя: под связывателем у аргумента вызова нет одного значения.
 */
function вызовыСебяСнаружиСвязывателей(узел, имя) {
  const найдено = []
  собратьСнаружи(узел, имя, найдено)
  return найдено
}

function собратьСнаружи(узел, имя, найдено) {
  if (узел === null || узел === undefined || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) собратьСнаружи(элемент, имя, найдено)
    return
  }
  if (узел.kind === "let" || узел.kind === "match" || узел.kind === "fold"
    || узел.kind === "map" || узел.kind === "filter") return
  if (узел.kind === "call" && узел.name === имя) найдено.push(узел)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span") continue
    собратьСнаружи(значение, имя, найдено)
  }
}

/** Все вызовы функции самой себя внутри выражения — обходом, без разбора связей. */
function вызовыСебя(узел, имя) {
  const найдено = []
  собратьВызовы(узел, имя, найдено)
  return найдено
}

function собратьВызовы(узел, имя, найдено) {
  if (узел === null || узел === undefined || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) собратьВызовы(элемент, имя, найдено)
    return
  }
  if (узел.kind === "call" && узел.name === имя) найдено.push(узел)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span") continue
    собратьВызовы(значение, имя, найдено)
  }
}

/**
 * Ветви `разбор` по переменной индукции — из тела функции.
 *
 * Ищется ровно один узел: `разбор <переменная индукции>` на верхнем уровне тела.
 * Не «где-нибудь внутри»: разбор, спрятанный под условием, отвечает не за все
 * значения переменной, и брать из него ветвь значило бы приписать случаю тело,
 * до которого вычисление может и не дойти. Такой поиск был бы не чтением, а
 * догадкой.
 */
function ветвиРазбора(функция, параметр) {
  const ветви = new Map()
  /* Тело нормализуется перед чтением: `пусть` перед разбором — обычная запись
     («Уравновесить слева» в `stdlib/tree.flang` начинается именно так), и
     отказывать ей значило бы отказывать не по существу. Нормализация разворачивает
     `пусть` и ничего не вычисляет, поэтому разбор остаётся тем же разбором. */
  const тело = нормализовать(функция?.body ?? null)
  if (тело?.kind !== "match") return ветви
  if (тело.target?.kind !== "var" || тело.target.name !== параметр) return ветви
  for (const случай of тело.cases ?? []) {
    const прочитано = образецВарианта(случай?.pattern)
    if (прочитано === null) continue
    ветви.set(прочитано.name, случай)
  }
  return ветви
}

/**
 * Переименование связей ветви функции в связи образца теоремы — по ПОЛЮ.
 *
 * Автор теоремы вправе назвать части иначе, чем названы они в теле функции:
 * `случай вариант «Развилка» с меньшие как левое` при теле, где то же поле
 * связано как `м`. Соответствие читается по имени ПОЛЯ, а не по порядку: порядок
 * полей в образце автор писать не обязан.
 */
function сличитьИмена(связиВетви, связиСлучая) {
  const карта = new Map()
  for (const [поле, имя] of Object.entries(связиВетви)) {
    const целевое = связиСлучая[поле]
    if (typeof целевое === "string" && целевое !== имя) карта.set(имя, целевое)
  }
  return карта
}

/**
 * Уравнение образца, записанное значением: переменная индукции РАВНА конструктору
 * с полями, названными образцом.
 *
 * Это не вывод и не догадка: так написал автор словом `случай`, и типизатор уже
 * сказал, что такой вариант у суммы есть. Поле, которое образец не назвал,
 * получает имя самого поля — оно всё равно остаётся непрозрачным именем, и
 * назвать его как-то надо, чтобы конструктор был выражением, а не дыркой.
 */
function конструктор(вариант, связи) {
  const поля = {}
  for (const имя of [...вариант.recursive, ...вариант.carried.map((п) => п.name)]) {
    поля[имя] = { kind: "var", name: связи[имя] ?? имя }
  }
  return { kind: "construct", variant: вариант.name, fields: поля }
}

/**
 * Аргументы вызова функции на части значения.
 *
 * Переменная индукции заменяется частью, остальные параметры остаются собой:
 * допущение говорит о том же вызове с теми же прочими аргументами, иначе оно
 * было бы допущением о другой функции.
 */
function аргументыНаЧасти(функция, параметр, часть) {
  return (функция?.params ?? []).map((п) =>
    п.name === параметр ? { kind: "var", name: часть } : { kind: "var", name: п.name },
  )
}

/**
 * Захватит ли подстановка чужое имя — вопрос, который обязан задаваться ДО неё.
 *
 * ── Что такое захват и почему он дороже всего ───────────────────────────────
 * Вычёркивание связанного имени (`пройти`) стережёт одну половину дела: имя
 * КЛЮЧА под связывателем означает уже не то, что снаружи, и подставлять его туда
 * нельзя. Вторая половина — имена ЗНАЧЕНИЯ, и её здесь не стерёг никто.
 * Подставляя `результат := х` в цель, у которой внутри стоит
 * `свёртка … как акк и х → результат`, ядро загоняло свободный `х` под чужой
 * связыватель: снаружи это параметр функции, внутри — элемент свёртки. Два
 * разных значения под одним именем, и терм после такой подстановки говорит уже
 * не о том, о чём его написали.
 *
 * ── Улика, измеренная программой ────────────────────────────────────────────
 * Цель `(свёртка [1] начиная с 0 как акк и х → результат) равно
 * (свёртка [1] начиная с 0 как акк и х → х)` означает «результат равен 1».
 * После захвата обе стороны становятся ОДНИМ И ТЕМ ЖЕ термом, правило тождества
 * сходится знак в знак, и ведомость печатает «доказано». Ловилось это на обоих
 * путях сразу: и без теоремы («доказано сведением цели с телом функции»), и с
 * теоремой («доказано индукцией по «Дерево» … обо ВСЕХ входах типа «Дерево»») —
 * причём во втором случае захват ещё и ПРЯТАЛ свободное имя от проверки
 * `посылка.free`, из-за чего базу пускало правило `по примеру`. `flang run` на
 * том же файле отвечал FLANG_PROPERTY на первом же значении, кроме единицы.
 *
 * ── Почему ОТКАЗ, а не переименование ───────────────────────────────────────
 * Переименование — обычный ответ на захват, и здесь он запрещён по той же
 * причине, по какой запрещён у развёртки (`reduce.mjs`, ОГРАНИЧИТЕЛЬ 4):
 * выдуманное имя не сличить с допущением, а сличение синтаксическое. Ядро
 * поэтому отказывается подставлять и возвращает `null`; вызывающий обязан
 * прочесть это как «заключения нет», а не как «заключение пусто».
 *
 * Проверка КОНСЕРВАТИВНА нарочно: она говорит «захват» и тогда, когда
 * подстановка до опасного места, может быть, и не дошла бы. Ошибка в эту сторону
 * стоит одного недоказанного утверждения, в другую — слова «доказано» о лжи.
 *
 * @param {object} выражение узел AST, в который подставляют
 * @param {Record<string, object>|Map<string, object>} замены имя → выражение
 * @returns {boolean}
 */
export function захватывает(выражение, замены) {
  const карта = замены instanceof Map ? new Map(замены) : new Map(Object.entries(замены ?? {}))
  const свободные = new Map()
  for (const [имя, значение] of карта) {
    /* Подставлять нечего — значит подставлять нельзя: `null` приезжает сюда от
       ВЛОЖЕННОЙ подстановки, которая сама отказалась, и подставить его значило бы
       поставить дыру на место терма. */
    if (значение === null || значение === undefined) return true
    свободные.set(имя, свободныеИмена(значение))
  }
  return подЗахватом(выражение, карта, свободные)
}

/** Связыватель захватывает, если значение попадёт под него, а имя ключа туда доходит. */
function захватитБы(тело, карта, свободные, связанные) {
  const внутри = new Map(карта)
  for (const имя of связанные) внутри.delete(имя)
  if (внутри.size === 0) return false
  const достижимые = свободныеИмена(тело)
  for (const [ключ, имена] of свободные) {
    if (!внутри.has(ключ)) continue
    if (!достижимые.has(ключ)) continue
    for (const имя of связанные) if (имена.has(имя)) return true
  }
  return подЗахватом(тело, внутри, свободные)
}

function подЗахватом(узел, карта, свободные) {
  if (карта.size === 0) return false
  if (узел === null || узел === undefined || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some((элемент) => подЗахватом(элемент, карта, свободные))
  if (узел.kind === "var") return false

  if (узел.kind === "let" && typeof узел.name === "string") {
    return подЗахватом(узел.value, карта, свободные)
      || захватитБы(узел.in, карта, свободные, [узел.name])
  }
  if (узел.kind === "fold") {
    const связанные = [узел.acc, узел.item].filter((имя) => typeof имя === "string")
    return подЗахватом(узел.over, карта, свободные)
      || подЗахватом(узел.init, карта, свободные)
      || захватитБы(узел.body, карта, свободные, связанные)
  }
  if (узел.kind === "map" || узел.kind === "filter") {
    const связанные = typeof узел.item === "string" ? [узел.item] : []
    return подЗахватом(узел.over, карта, свободные)
      || захватитБы(узел.body, карта, свободные, связанные)
  }
  if (узел.kind === "match") {
    if (подЗахватом(узел.target, карта, свободные)) return true
    return (узел.cases ?? []).some((случай) =>
      захватитБы(случай?.body, карта, свободные, [...связанныеОбразцом(случай?.pattern)]))
  }

  return Object.entries(узел).some(([ключ, значение]) => ключ !== "span" && подЗахватом(значение, карта, свободные))
}

/**
 * Подстановка выражений вместо свободных имён — с уважением к связывающим узлам.
 *
 * Вычёркивание связанного имени стережёт КЛЮЧ подстановки: под `пусть`, под
 * образцом `разбор`, под `свёртка` и под `отобразить`/`отфильтровать` имя ключа
 * означает уже не то, что снаружи, и подставлять туда нечего. Имена ЗНАЧЕНИЯ
 * стережёт `захватывает` (см. выше), и без неё подстановка молча загоняла чужую
 * переменную под чужой связыватель — ошибка, которая в проверяльщике
 * доказательств стоит дороже всего, и стоила: ведомость печатала «доказано» о
 * ложном утверждении.
 *
 * @param {object} выражение узел AST
 * @param {Record<string, object>} замены имя → выражение
 * @returns {object|null} новый узел или `null`, если подстановка захватила бы имя
 */
export function подставить(выражение, замены) {
  const карта = new Map(Object.entries(замены ?? {}))
  if (захватывает(выражение, карта)) return null
  return пройти(выражение, карта, (узел, текущие) => {
    if (узел?.kind !== "var") return undefined
    const замена = текущие.get(узел.name)
    return замена === undefined ? undefined : замена
  })
}

/** То же самое, но заменяются ИМЕНА на имена: переименование частей. */
export function подставитьИмена(выражение, карта) {
  if (!(карта instanceof Map) || карта.size === 0) return выражение
  return пройти(выражение, new Map(карта), (узел, текущие) => {
    if (узел?.kind !== "var") return undefined
    const имя = текущие.get(узел.name)
    return имя === undefined ? undefined : { ...узел, name: имя }
  })
}

/**
 * СВОБОДНЫЕ ИМЕНА выражения — те, что означают что-то за его пределами.
 *
 * Нужны ровно для одного вопроса, и вопрос этот решает, доказательство перед
 * нами или пример: у выражения БЕЗ свободных имён значение одно, и вычисление
 * отвечает про него обо всём случае; со свободными именами значений столько же,
 * сколько подстановок, и один прогон говорит об одной из них.
 *
 * Связыватели те же четыре, что и у подстановки, и читаются они той же строкой
 * (`связанныеОбразцом`) — иначе на один вопрос «какие имена здесь связаны»
 * было бы два ответа.
 *
 * @param {object} выражение узел AST
 * @returns {Set<string>} имена, свободные в нём
 */
export function свободныеИмена(выражение) {
  const имена = new Set()
  собрать(выражение, new Set(), имена)
  return имена
}

function собрать(узел, связанные, имена) {
  if (узел === null || узел === undefined || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) собрать(элемент, связанные, имена)
    return
  }
  if (узел.kind === "var") {
    if (typeof узел.name === "string" && !связанные.has(узел.name)) имена.add(узел.name)
    return
  }
  if (узел.kind === "let" && typeof узел.name === "string") {
    собрать(узел.value, связанные, имена)
    собрать(узел.in, new Set([...связанные, узел.name]), имена)
    return
  }
  if (узел.kind === "fold") {
    собрать(узел.over, связанные, имена)
    собрать(узел.init, связанные, имена)
    const внутри = new Set(связанные)
    if (typeof узел.acc === "string") внутри.add(узел.acc)
    if (typeof узел.item === "string") внутри.add(узел.item)
    собрать(узел.body, внутри, имена)
    return
  }
  if (узел.kind === "map" || узел.kind === "filter") {
    собрать(узел.over, связанные, имена)
    const внутри = new Set(связанные)
    if (typeof узел.item === "string") внутри.add(узел.item)
    собрать(узел.body, внутри, имена)
    return
  }
  if (узел.kind === "match") {
    собрать(узел.target, связанные, имена)
    for (const случай of узел.cases ?? []) {
      собрать(случай?.body, new Set([...связанные, ...связанныеОбразцом(случай?.pattern)]), имена)
    }
    return
  }
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ !== "span") собрать(значение, связанные, имена)
  }
}

/**
 * Обход выражения с вычёркиванием связанных имён.
 *
 * Связывают четыре узла и только они: `пусть` (`let`), образец случая внутри
 * `разбор` (`match`), `свёртка` (`fold`) и элемент `отобразить`/`отфильтровать`
 * (`map`/`filter`). Список закрыт нарочно: появись в языке пятый связыватель,
 * здесь обязан появиться отказ, а не молчаливый пропуск, — поэтому неизвестные
 * узлы обходятся как есть, но связей не заводят, и если такой узел когда-нибудь
 * свяжет имя, это заметит негативный тест ядра, а не пользователь.
 */
function пройти(узел, связанные, заменить) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => пройти(элемент, связанные, заменить))

  const прямая = заменить(узел, связанные)
  if (прямая !== undefined) return прямая

  if (узел.kind === "let" && typeof узел.name === "string") {
    const внутри = new Map(связанные)
    внутри.delete(узел.name)
    return { ...узел, value: пройти(узел.value, связанные, заменить), in: пройти(узел.in, внутри, заменить) }
  }
  if (узел.kind === "fold") {
    const внутри = new Map(связанные)
    if (typeof узел.acc === "string") внутри.delete(узел.acc)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return {
      ...узел,
      over: пройти(узел.over, связанные, заменить),
      init: пройти(узел.init, связанные, заменить),
      body: пройти(узел.body, внутри, заменить),
    }
  }
  if (узел.kind === "map" || узел.kind === "filter") {
    const внутри = new Map(связанные)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return { ...узел, over: пройти(узел.over, связанные, заменить), body: пройти(узел.body, внутри, заменить) }
  }
  if (узел.kind === "match") {
    return {
      ...узел,
      target: пройти(узел.target, связанные, заменить),
      cases: (узел.cases ?? []).map((случай) => {
        const внутри = new Map(связанные)
        for (const имя of связанныеОбразцом(случай?.pattern)) внутри.delete(имя)
        return { ...случай, body: пройти(случай.body, внутри, заменить) }
      }),
    }
  }

  const собрано = {}
  for (const [ключ, значение] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? значение : пройти(значение, связанные, заменить)
  }
  return собрано
}

function имяИменованного(тип) {
  if (тип === null || тип === undefined) return null
  if (тип.kind === "named") return тип.name
  return null
}

/**
 * Место `X` функтора: поле, чей тип есть САМ объявляемый тип.
 *
 * Одно правило и два способа узнать «тот же тип», потому что типы записаны
 * двумя способами, а не потому, что правил два. У объявленной суммы тип поля
 * назван ИМЕНЕМ (`хвост: «Стопка»`), и совпасть должно имя. У встроенного
 * списка имени нет вовсе — тип написан целиком (`хвост: список Э`), и совпасть
 * должен тип. Сравнение типов — то же синтаксическое равенство, каким слой
 * обязательств сверяет тип переменной теоремы с типом параметра: решать, что
 * два разных типа «означают одно и то же», здесь нечем и не должно быть чем.
 *
 * Граница прежняя и здесь не сдвинута: `дети: список «Дерево»` местом `X` НЕ
 * является ни по одному из двух способов — за списком стоит другой функтор, и
 * допущение о его элементах было бы другим допущением.
 */
function местоX(тип, сумма) {
  if (имяИменованного(тип) === сумма?.name) return true
  const сам = сумма?.self ?? null
  return сам !== null && одинаковы(тип, сам)
}
