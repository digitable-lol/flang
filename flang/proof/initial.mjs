/**
 * Версия принципа по СВЁРТКЕ. Названа отдельно от `АЛГЕБРА` и от `ОТРЕЗОК` по
 * той же причине: это третий принцип, прочитанный с третьего места, и меняется
 * он не вместе с ними.
 */
export const СВЁРТКА = 1

/**
 * Тело функции как `свёртка` по переменной индукции — или `null`.
 *
 * Читается ровно один узел: `свёртка <переменная индукции> начиная с …` на
 * ВЕРХНЕМ уровне тела. Не «где-нибудь внутри», и по той же причине, по какой
 * `ветвиРазбора` не ищет разбор под условием: свёртка, спрятанная под `если`,
 * отвечает не за все входы, и брать её начало за базу значило бы приписать
 * случаю значение, до которого вычисление может и не дойти.
 *
 * `пусть` перед свёрткой разворачивается нормализацией — это обычная запись
 * («Обрезать слева» в `stdlib/strings.flang` начинается именно так).
 */
export function свёрткаПоПеременной(функция, параметр) {
  const тело = нормализовать(функция?.body ?? null)
  if (тело?.kind !== "fold") return null
  if (тело.over?.kind !== "var" || тело.over.name !== параметр) return null
  return тело
}

/**
 * Принцип индукции для тела-СВЁРТКИ — как ТЕРМ, той же формы, что у суммы.
 *
 * ── Зачем это понадобилось, числом ──────────────────────────────────────────
 * Замер цены доказательства (`docs/benchmark-proof-cost-2.md`) назвал главную помеху со
 * знаменателем: ядро строит заключение посылки ТОЛЬКО с ветвей `разбор` по
 * переменной индукции, а таких тел в `flang/stdlib` **58 из 208**. Свёрткой
 * написано **45**, и ни к одной из них принцип не цеплялся ничем.
 *
 * ── Что здесь читается, и почему это НЕ индукция по списку ──────────────────
 * Сказать честно надо сразу: это НЕ принцип индукции по списку, и выдавать его
 * за него нельзя. Свёртка в flang — ЛЕВАЯ (`interpret.mjs`, `stepFold`: обход
 * идёт от нулевой ячейки, накопитель переписывается на каждом витке), и её
 * определяющие уравнения таковы:
 *
 *     свёртка пусто          начиная с И как а и э → Т   =   И
 *     свёртка (г : х)        начиная с И как а и э → Т   =   свёртка х начиная с Т[а:=И, э:=г] …
 *
 * Второе уравнение меняет НАЧАЛО, а не только список. Поэтому допущение
 * индукции по списку («утверждение верно о свёртке ХВОСТА при том же начале»)
 * говорит о другом терме, чем заключение («свёртка хвоста при ДРУГОМ начале»),
 * и свести одно к другому нечем. Это не пробел ядра, а свойство левой свёртки:
 * доказательство по списку требует обобщения утверждения по накопителю, а
 * обобщение — это уже поиск инварианта, которого у ядра нет и не будет.
 *
 * Читается здесь другой принцип, и держится он на другом:
 *
 *     P(И)  ∧  (для любых а и э: P(а) ⟹ P(Т))   ⟹   P(свёртка с начиная с И …)
 *
 * Это индукция ПО ЧИСЛУ ВИТКОВ свёртки, а витков ровно столько, сколько ячеек
 * в списке, — то есть конечное число (обход снимает длину ОДИН раз, до первого
 * витка, `снимокОбхода`). Начало вычисляется до первого витка, каждый виток
 * заменяет накопитель телом, значит утверждение, истинное о начале и
 * сохраняемое витком, истинно о результате. Ни одного нового доверия здесь нет:
 * тот же самый ход ядро УЖЕ делает внутри правила неотрицательности
 * (`reduce.mjs`, `неотрицательнаяСвёртка`) — эта функция вынимает его оттуда в
 * построение посылки, чтобы он работал не для одного правила, а для всех трёх.
 *
 * ── Переменная индукции остаётся СВОБОДНОЙ, и это законно ───────────────────
 * Ни в базе, ни в шаге список не заменяется ничем. Инвариант доказывается при
 * ФИКСИРОВАННОМ списке: P(·) может упоминать его сколько угодно, лишь бы оно
 * означало одно и то же во всех трёх местах. Отсюда, впрочем, следует и
 * ГРАНИЦА этого принципа, и она измерена: утверждение, связывающее результат со
 * списком («длина результата равна длине входа плюс один»), инвариантом
 * накопителя не доказывается, потому что при пустом списке оно о начале ЛОЖНО.
 * Из шести функций замера, написанных свёрткой, такую форму имеют пять.
 *
 * ── Три отказа, и каждый закрывает способ получить ложь ─────────────────────
 *   1. имена накопителя и элемента обязаны быть именами и быть РАЗНЫМИ:
 *      вычислитель связывает элемент ПОСЛЕ накопителя, и при одном имени тело
 *      говорит об элементе, а допущение легло бы на накопитель. Тот же отказ и
 *      по той же причине стоит в `неотрицательнаяСвёртка`;
 *   2. ни `акк`, ни `эл` не имеют права быть свободными в САМОЙ цели: тогда имя
 *      снаружи и имя витка совпали бы знак в знак, и утверждение о параметре
 *      стало бы утверждением об элементе списка;
 *   3. объявленные типы `акк` и `эл` в посылки НЕ едут: снаружи так мог быть
 *      назван параметр, и его тип сказал бы о витке неправду.
 *
 * @param {object} параметры
 * @param {object} параметры.свёртка узел `fold` из нормализованного тела
 * @param {object} параметры.функция функция, чьё постусловие доказывается
 * @param {object} параметры.обязательство обязательство из `obligations.mjs`
 * @param {object} параметры.индукция узел `индукция по …` из теоремы
 * @returns {object} терм принципа; `unread` не `null`, если прочитать не удалось
 */
export function принципПоСвёртке({ свёртка, функция, обязательство, индукция }) {
  const каркас = {
    kind: "induction",
    carrier: "fold",
    algebra: СВЁРТКА,
    type: ИМЯ_СПИСКА,
    functor: null,
    param: индукция.param,
    of: обязательство.of,
    name: обязательство.name,
    premises: [],
    unmatched: индукция.cases ?? [],
    conclusion: { forall: индукция.param, type: ИМЯ_СПИСКА, goal: обязательство.goal },
    matched: false,
    unread: null,
  }
  const нечитаемо = (code, why) => ({ ...каркас, unread: { code, why } })

  const накопитель = свёртка.acc
  const элемент = свёртка.item
  if (typeof накопитель !== "string" || typeof элемент !== "string") {
    return нечитаемо("branch", "у свёртки в теле не названы накопитель и элемент — читать нечего")
  }
  if (накопитель === элемент) {
    return нечитаемо(
      "branch",
      `накопитель и элемент свёртки названы одним именем «${накопитель}»:`
        + " вычислитель связывает элемент ПОСЛЕ накопителя, значит тело говорит об элементе,"
        + " а допущение легло бы на накопитель — это разные значения под одним именем",
    )
  }

  const вЦели = свободныеИмена(обязательство.goal)
  const занятые = [накопитель, элемент].filter((имя) => вЦели.has(имя))
  if (занятые.length > 0) {
    return нечитаемо(
      "branch",
      `в самой цели свободны ${занятые.map((и) => `«${и}»`).join(", ")}, а этими именами свёртка называет`
        + " накопитель и элемент витка. Снаружи это одно значение, внутри витка — другое,"
        + " и посылка говорила бы не о том, о чём её написали."
        + " Назовите накопитель и элемент свёртки иначе, чем параметры функции",
    )
  }

  const имяРезультата = обязательство.bind ?? "результат"
  const цель = обязательство.goal
  /* Объявления: параметры функции, КРОМЕ названных именами витка. Тип
     параметра — факт о параметре, и приписать его накопителю значило бы сказать
     о витке то, чего никто не обещал. Сам список остаётся объявленным: он в
     посылках свободен и означает ровно себя. */
  const объявления = (функция?.params ?? [])
    .filter((п) => п.name !== накопитель && п.name !== элемент)
    .map((п) => ({ name: п.name, type: п.type ?? null }))

  const заключениеНачала = подставить(цель, { [имяРезультата]: свёртка.init })
  const начало = {
    kind: "base",
    /* Вариант назван именем конструктора списка нарочно: `свёртка пусто начиная
       с И` РАВНА `И` — первое определяющее уравнение, — поэтому случай автора
       `случай пусто` отвечает этой посылке буквально, и пример с пустым списком
       закрывает её по делу. */
    variant: СПИСОК.пусто,
    label: "начало свёртки",
    arity: 0,
    param: индукция.param,
    binds: {},
    parts: [],
    closed: true,
    free: [...свободныеИмена(заключениеНачала)],
    declarations: объявления,
    facts: [],
    hypotheses: [],
    conclusion: заключениеНачала,
    branch: "init",
    case: null,
  }

  const заключениеШага = подставить(цель, { [имяРезультата]: свёртка.body })
  const шаг = {
    kind: "step",
    variant: СПИСОК.звено,
    label: "шаг свёртки",
    arity: 1,
    param: индукция.param,
    binds: {},
    parts: [накопитель],
    closed: false,
    free: [...свободныеИмена(заключениеШага)],
    declarations: объявления,
    facts: [],
    hypotheses: [
      {
        kind: "hypothesis",
        of: обязательство.name,
        param: индукция.param,
        part: накопитель,
        /* Допущение — ТА ЖЕ цель, в которой `результат` стал накопителем витка.
           Второй подстановки (переменной на часть) здесь нет и быть не должно:
           список в посылке остаётся собой, инвариант доказывается при
           фиксированном списке. */
        claim: подставить(цель, { [имяРезультата]: { kind: "var", name: накопитель } }),
      },
    ],
    conclusion: заключениеШага,
    branch: "step",
    case: null,
  }

  /* Случаи автора. Образцов у свёртки два, и оба уже стоят в языке: `пусто` —
     начало, `голова и хвост` — виток. Своих образцов принцип по свёртке не
     завёл ни одного, и девятого слова поверхности не потребовал. */
  const лишние = []
  for (const случай of индукция.cases ?? []) {
    const прочитано = образецВарианта(случай?.pattern)
    if (прочитано?.name === СПИСОК.пусто && начало.case === null) начало.case = случай
    else if (прочитано?.name === СПИСОК.звено && шаг.case === null) шаг.case = случай
    else лишние.push(случай)
  }

  return { ...каркас, premises: [начало, шаг], unmatched: лишние, matched: true }
}

