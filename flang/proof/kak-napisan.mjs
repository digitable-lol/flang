/**
 * «ОДИНАКОВО ЛИ НАПИСАНО» — структурное равенство узлов дерева.
 *
 * Жила эта функция в `flang/src/as-written.mjs`, вместе с реализацией на
 * JavaScript, и уехала вместе с ней 20 августа. Ядро доказательства на
 * JavaScript (`flang/proof/`) осталось, и без неё не грузится ни один его файл.
 *
 * ПЕРЕНЕСЕНА, А НЕ НАПИСАНА ЗАНОВО, и переносить её можно: это не разбор
 * `.flang` и не правило языка, а обычное глубокое сравнение двух объектов,
 * которое ничего о языке не знает. Единственное, что она знает, — какие ключи
 * дописал АНАЛИЗ, а не автор; их и не сравнивает.
 *
 * Почему отметки анализа выбрасываются. Цель постусловия анализ видит — она
 * вычисляется во время работы; утверждение теоремы он не видит вовсе — оно не
 * вычисляется. Одни и те же слова в двух местах приезжают сюда с разным набором
 * отметок, и сравнение отметок означало бы проверять «одинаково написано» по
 * тому, что дописал анализ. Улика, а не опасение: без этой строки свод по
 * корпусу терял 60 утверждений из 138 — каждую теорему, в чьём утверждении есть
 * арифметика или сравнение.
 */
const ОТМЕТКИ_АНАЛИЗА = new Set(["span", "доказана", "числовая", "measure", "descent"])

export function одинаковы(левое, правое) {
  if (левое === правое) return true
  if (левое === null || правое === null) return false
  if (typeof левое !== "object" || typeof правое !== "object") return false
  if (Array.isArray(левое) !== Array.isArray(правое)) return false
  if (Array.isArray(левое)) {
    if (левое.length !== правое.length) return false
    return левое.every((элемент, и) => одинаковы(элемент, правое[и]))
  }
  const ключи = (узел) => Object.keys(узел).filter((ключ) => !ОТМЕТКИ_АНАЛИЗА.has(ключ)).sort()
  const левые = ключи(левое)
  const правые = ключи(правое)
  if (левые.length !== правые.length) return false
  return левые.every((ключ, и) => правые[и] === ключ && одинаковы(левое[ключ], правое[ключ]))
}
