# ПРОБЫ СТРОГОГО РЕЖИМА (задача 5502, пункт 5 внешнего аудита).
#
#   sh flang/proof/probes/strict/run.sh
#   FLANG_BIN=<путь> sh flang/proof/probes/strict/run.sh
#
# Код 0 — сошлось всё; 1 — хоть одна проба разошлась, и она названа строкой;
# 2 — не смог измерить (нет двоичного, нет таблицы).
#
# ── ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ ────────────────────────────────────────────────────
# Внешний аудит, пункт 5, требует различать четыре исхода — «доказано»,
# «опровергнуто», «не удалось доказать», «не поддерживается» — и запрещает
# успех без независимой проверки всех обязательств. Словами все четыре были
# названы и раньше; кодами возврата они не разъезжались, и два разных исхода
# ехали нулём. Сборочный сценарий читает `$?`, а не слова.
#
# ДЫРА, СНЯТАЯ ПРОГОНОМ 19 сентября 2026 (двоичный из этого дерева). Программа
# `programs/false-postcondition.flang` лжёт постусловием: обещает «результат не
# больше 100» при теле `н плюс н`, и опровергается на н = 100. Ответы приборов
# ДО правки:
#
#   flang check                              код 0
#   flang check --proof                      код 0  ПРОВЕРЕНО С ОПОРОЙ, И ОПОРА
#                                                   НЕ СУДИЛАСЬ (спросить: --строго)
#   flang check --proof --строго             код 4  ПРОВЕРЕНО С ОПОРОЙ
#   сверщик (по записи того же прогона)      код 0  ПРОВЕРЕНО ВПУСТУЮ
#   flang run --args '{"н": 100}'            код 3  не доказано: утверждений 1
#   то же с --на-веру                        код 1  FLANG_PROPERTY: нарушено свойство
#
# Ноль ПОКУПАЛСЯ примером: тот же файл без строк `пример`
# (`programs/false-postcondition-without-examples.flang`) давал 3 и без всякого ключа.
# Пара этих двух файлов и держит разницу: одинаковая ложь, одинаковый приговор
# под `--строго` — и разный в умолчании.
#
# ── ЧЕГО ЭТОТ НАБОР НЕ ПРОВЕРЯЕТ ───────────────────────────────────────────
# Он проверяет ОДИН прибор из двух — компилятор. Вторая половина исхода живёт в
# независимом сверщике (`flang/proof/checker/checker.c`): это он переигрывает
# снятия предусловий и он отвечает `ПРОВЕРЕНО ВПУСТУЮ` кодом 0 на записи, где
# доказанным не числится ничего. Ключ `--строго` у сверщика — отдельная работа,
# и пока её нет, строка «сверщик» из таблицы выше остаётся нулём. Говорить об
# этом надо вслух: строгий компилятор при мягком сверщике закрывает цепь не до
# конца.
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах
# (снято 17 сентября 2026 на соседнем наборе, `probes/run/run.sh`).
set -u

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../../../.." && pwd)
FLANG=${FLANG_BIN:-${FLANG:-$KOREN/bootstrap/flang}}
PROBY=$KOREN/flang/proof/probes/strict
export LC_ALL=C.UTF-8

[ -x "$FLANG" ] || { echo "нет двоичного: $FLANG (собрать: make -C bootstrap)" >&2; exit 2; }
[ -f "$PROBY/expected.tsv" ] || { echo "нет таблицы ожиданий: $PROBY/expected.tsv" >&2; exit 2; }

RAB=$(mktemp -d -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" proby-strogogo.XXXXXX) || exit 2
trap 'rm -rf "$RAB"' EXIT INT TERM

BAD=0; N=0
awk -F'\t' '!/^#/ && $1 != "программа" && NF >= 4' "$PROBY/expected.tsv" > "$RAB/ожидание.tsv"

while IFS="$(printf '\t')" read -r prog klyuchi kod slovo; do
  N=$((N+1))
  f=$PROBY/programs/$prog
  if [ ! -f "$f" ]; then
    printf '✗ %-34s НЕТ ПРОГРАММЫ: %s\n' "$prog" "$f"
    BAD=$((BAD+1)); continue
  fi
  # «—» в колонке ключей значит «без ключей»: пустое поле съела бы таблица.
  [ "$klyuchi" = "—" ] && klyuchi=""
  # Ключи разворачиваются намеренно без кавычек: в них нет ни пробелов внутри
  # довода, ни образцов оболочки — только «--proof», «--строго», «--быстро».
  out=$("$FLANG" check "$f" $klyuchi 2>&1); k=$?
  if [ "$k" = "$kod" ] && printf '%s' "$out" | grep -q -a -F -- "$slovo"; then
    printf '✓ %-34s %-18s код %s, есть «%s»\n' "$prog" "${klyuchi:-без ключей}" "$k" "$slovo"
  else
    printf '✗ %-34s %-18s ждали код %s и «%s», вышло код %s: %s\n' \
      "$prog" "${klyuchi:-без ключей}" "$kod" "$slovo" "$k" \
      "$(printf '%s' "$out" | tr '\n' ' ' | cut -c1-200)"
    BAD=$((BAD+1))
  fi
done < "$RAB/ожидание.tsv"

# ── Сверка с каталогом в обе стороны ───────────────────────────────────────
# Программа, лежащая в каталоге и не названная в таблице, — дыра в надзоре:
# ровно так заводится файл, о котором никто не спросил ни одного кода.
for f in "$PROBY"/programs/*.flang; do
  [ -e "$f" ] || continue
  imya=$(basename "$f")
  if ! cut -f1 "$RAB/ожидание.tsv" | grep -q -a -F -x -- "$imya"; then
    printf '✗ НЕЗАЯВЛЕННАЯ ПРОГРАММА: %s лежит в каталоге, а строки о ней в expected.tsv нет\n' "$imya"
    BAD=$((BAD+1))
  fi
done

echo
if [ "$BAD" -eq 0 ]; then
  echo "сошлось всё: проб $N, разошлось 0"
  exit 0
fi
echo "НЕ СОШЛОСЬ: проб $N, разошлось $BAD"
exit 1
