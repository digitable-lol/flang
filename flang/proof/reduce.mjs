/**
 * reduce.mjs — сведение заключения посылки к допущениям индукции.
 *
 * ── Что это и чем оно НЕ является ───────────────────────────────────────────
 * Здесь два решающих правила и одна нормализация, и ни одного поиска. Решающее
 * правило — это не тактика: тактика ворочает состояние цели перебором и потому
 * нетотальна, а правило ниже — структурная свёртка по выражению, которая
 * отвечает да или нет и всегда останавливается. Разница ровно та же, что между
 * `разбор` и циклом с условием: у первого число ветвей известно из объявления.
 *
 * Оба правила закрыты списком и печатаются в отказе поимённо. Правило, которое
 * нельзя перечислить, ничем не отличается от «ядро решило, что так можно».
 *
 * ── Нормализация: развёртка того, что уже написано ──────────────────────────
 * Три переписки, и все три — чтение, а не вывод:
 *
 *   `пусть и равно З; Т`      →  Т, в котором `и` заменено на З
 *   `разбор (вариант «C» …)`  →  тело ветви «C» со связанными полями
 *   `если да то А иначе Б`    →  А (условие уже вычислилось в значение)
 *
 * Ни одна из них не разворачивает ВЫЗОВ функции, и это главное ограничение
 * файла, названное прямо. Развернуть вызов значило бы начать вычисление, а
 * вычисление рекурсивной функции на незамкнутом значении не заканчивается: у
 * `«Высота» от м` при неизвестном `м` нет нормальной формы. Поэтому вызов
 * остаётся непрозрачным термом — и именно поэтому нужны допущения индукции: они
 * и есть то, что о непрозрачном терме известно.
 *
 * ── Правило 1: неотрицательность по построению ──────────────────────────────
 * Цель вида `Е не меньше 0` выводится, если `Е` собрано из неотрицательных:
 *
 *   литерал ≥ 0                                    неотрицателен
 *   терм, о котором ЕСТЬ допущение `… не меньше 0` неотрицателен
 *   имя, ОБЪЯВЛЕННОЕ типом `нат`                   неотрицательно
 *   `а плюс б` при неотрицательных `а` и `б`       неотрицателен
 *   `если у то а иначе б` при неотрицательных обоих неотрицателен
 *
 * ── Третья строка: объявленный тип — это ФАКТ, а не подсказка ───────────────
 * До неё у ядра было два источника известного — литерал и допущение индукции, —
 * и оба приезжали изнутри доказательства. Объявление параметра не приезжало
 * никак, и постусловие «результат не меньше 0» у функции, складывающей два
 * `нат`, стояло в ведомости сеткой примеров: посчитанным на трёх входах из
 * 2^53 × 2^53, хотя доказуемым одним сложением.
 *
 * Это НЕ аксиома и не новое доверие. `нат` — не имя, а отрезок [0, 2^53−1]
 * (`types.mjs`, `NAT`): написав `принимает первое: нат`, автор написал факт
 * «первое не меньше 0», и типизатор его уже проверил на каждом вызове. Ядро
 * этот факт не выдумывает и не выводит — оно ЧИТАЕТ его там, где он написан.
 * Правило шага «без названного факта — отказ» тем самым не нарушено: факт
 * назван подписью функции.
 *
 * ЧТО ФАКТОМ НЕ СТАНОВИТСЯ. Только `нат`, и список имён берётся из словаря
 * типизатора (`ИМЕНА_НАТ`), а не переписывается здесь: разойдись два списка —
 * ядро сочло бы натуральным то, что типизатор натуральным не считает.
 * `целое` — это [−2^53+1, 2^53−1], `число` — вообще всё, включая NaN и −∞:
 * ни то, ни другое ничего о знаке не обещает, и трактовать их как факт значило
 * бы принимать ложь на первом же отрицательном входе.
 *
 * ПОЧЕМУ ЭТО ПРАВДА В ЧИСЛАХ FLANG, А НЕ ТОЛЬКО В МАТЕМАТИКЕ. Числа языка —
 * IEEE-754, и в них ложны почти все привычные аксиомы порядка: `х плюс 1
 * больше х` неправда при большом |х|, `х минус 1 меньше х` — тоже. Ровно
 * поэтому список аксиом ядра был и остаётся пуст. Но перечисленное выше в
 * IEEE-754 ИСТИННО, и это проверяется рассуждением, а не надеждой:
 * `а не меньше 0` истинно только для не-NaN значений из [0, +∞] — NaN не
 * сравним ни с чем, и посылка на нём ложна. Сумма двух значений из [0, +∞] под
 * округлением к ближайшему снова лежит в [0, +∞]: переполнение даёт +∞, а не
 * отрицательное, и знака здесь потерять негде. Условное выражение вообще не
 * арифметика — это выбор одной из двух ветвей, и если обе неотрицательны, то
 * неотрицателен и выбор.
 *
 * ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ. Умножения: `0 умножить на +∞` даёт NaN, и правило
 * «произведение неотрицательных неотрицательно» было бы ЛОЖНЫМ. Вычитания и
 * деления — по той же причине. Аксиома, которая иногда ложна, делает ложным всё,
 * что из неё выведено, и одна такая строка обесценила бы каждое «доказано» в
 * ведомости. Список правил закрыт, и расширять его можно только тем же
 * рассуждением, каким открыт этот.
 *
 * Объявленный тип этого не меняет ни на знак, и проверить это можно на самом
 * корпусе: в `flang/examples/measure/natural.flang` рядом стоят «Сумма пары»
 * (`первое плюс второе`) и «Разность пары» (`первое минус второе`) — те же два
 * `нат`. У первой «результат не меньше 0» доказуемо, у второй ЛОЖНО, и пример
 * `2 минус 3 = −1` стоит там же. Отсюда негативная проверка ядра: то же самое с
 * `минус` вместо `плюс` обязано быть отвергнуто.
 *
 * ── Правило 2: тождество после переписки допущением ─────────────────────────
 * Цель вида `А равно Б` выводится, если после переписки допущениями индукции
 * (каждое допущение — равенство, применяется слева направо ко всем вхождениям,
 * по одному проходу на допущение) нормальные формы `А` и `Б` совпадают
 * СИНТАКСИЧЕСКИ. Совпадение по значению здесь не рассматривается и не может:
 * равенство вычислений на бесконечном носителе неразрешимо, и притвориться, что
 * это не так, значило бы завести решатель, которого нет.
 *
 * Проход по одному на допущение — не экономия, а условие останова: переписка
 * равенством в обе стороны или до неподвижной точки не заканчивается на
 * `х равно х`, и проверяльщик перестал бы быть тотальной программой.
 */

import { одинаковы } from "../src/obligations.mjs"
/* Имена натурального типа берутся у типизатора, а не переписываются здесь.
   Свой список — это второй ответ на тот же вопрос, и разойтись они могут молча:
   ядро сочло бы натуральным то, что типизатор натуральным не считает. Круга
   импортов здесь нет (`types.mjs` о слое доказательства не знает), поэтому и
   копии, какую держит `totality.mjs`, здесь не нужно. */
import { ИМЕНА_НАТ } from "../src/types.mjs"

/**
 * Версия набора правил: их читает ведомость и негативный тест, значит она названа.
 *
 * 2 — у правила неотрицательности появился третий источник известного:
 * объявленный тип имени (`нат`). Решающих правил по-прежнему два.
 */
export const ПРАВИЛА = 2

/**
 * Имена правил — для отказа и для отчёта. Латиницей код, словом человек: тот же
 * приём, что у носителей обещания в ведомости.
 */
export const ПРАВИЛО = Object.freeze({
  nonneg: "неотрицательность по построению",
  identity: "тождество после переписки допущением",
})

/**
 * Свести заключение посылки к допущениям.
 *
 * @param {object} заключение выражение-цель случая (уже с подставленным телом ветви)
 * @param {object[]} допущения утверждения допущений индукции
 * @param {{name: string, type: object|null}[]} [объявления] имена, видимые в цели,
 *   с типами, КАК ИХ ОБЪЯВИЛ АВТОР: параметры функции и поля образца случая.
 *   Тип — тоже факт, и приезжает он сюда наравне с допущениями, а не вместо них.
 * @returns {{ ok: boolean, rule: string|null, why: string|null }}
 */
export function свести(заключение, допущения, объявления = []) {
  const цель = нормализовать(заключение)
  const факты = (допущения ?? []).map((д) => нормализовать(д?.claim ?? д))

  if (цель?.kind === "binary" && цель.op === "gte" && ноль(цель.right)) {
    const известные = [
      ...факты
        .filter((факт) => факт?.kind === "binary" && факт.op === "gte" && ноль(факт.right))
        .map((факт) => факт.left),
      ...известноеПоТипу(объявления),
    ]
    if (неотрицательно(цель.left, известные)) return { ok: true, rule: ПРАВИЛО.nonneg, why: null }
    return {
      ok: false,
      rule: null,
      why:
        `${ПРАВИЛО.nonneg} не проходит: выражение случая собрано не только из неотрицательного.`
        + " Неотрицательны литерал не меньше нуля, терм с допущением «не меньше 0»,"
        + " имя, объявленное типом «нат», их сумма и выбор из них;"
        + " умножения и вычитания в этом списке нет и не будет"
        + " (в IEEE-754 «ноль умножить на бесконечность» даёт не число,"
        + " а разность двух натуральных отрицательна уже на 2 минус 3)",
    }
  }

  if (цель?.kind === "binary" && цель.op === "eq") {
    let левое = цель.left
    let правое = цель.right
    for (const факт of факты) {
      if (факт?.kind !== "binary" || факт.op !== "eq") continue
      левое = переписать(левое, факт.left, факт.right)
      правое = переписать(правое, факт.left, факт.right)
    }
    if (одинаковы(нормализовать(левое), нормализовать(правое))) {
      return { ok: true, rule: ПРАВИЛО.identity, why: null }
    }
    return {
      ok: false,
      rule: null,
      why:
        `${ПРАВИЛО.identity} не проходит: после переписки допущениями стороны равенства`
        + " остались разными термами. Ядро сличает синтаксически и равенства вычислений не решает",
    }
  }

  return {
    ok: false,
    rule: null,
    why:
      "у цели этого случая нет вида, к которому у ядра есть правило:"
      + " правил два — «не меньше 0» и «равно», и оба названы в отказе, чтобы список был виден целиком",
  }
}

