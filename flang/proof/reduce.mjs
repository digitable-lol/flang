/**
 * Разбор цели по условию: цель с `если` делится надвое и обе половины сводятся.
 *
 * ── Почему это законно, и почему это НЕ то, что уже измерено нулём ──────────
 * В `docs/zettel/reading-if-conditions-closed-zero-goals.md` записан измеренный отрицательный
 * результат: чтение условий `если` КАК ФАКТОВ закрывает ноль целей, и ветвь
 * `иначе` читать нельзя вовсе — на `не число` ложны обе стороны сравнения, так
 * что из «не (х меньше у)» не следует «х не меньше у».
 *
 * Здесь другой ход, и разница существенная: НИКАКОЙ ФАКТ ИЗ УСЛОВИЯ НЕ
 * ВЫВОДИТСЯ. Условие `У` — выражение типа `признак` (это проверил типизатор:
 * у `если` условие обязано быть признаком), а у признака значений ровно два.
 * Значит цель `Ц` при любом входе совпадает либо с `Ц`, в которой `У` заменено
 * на `да`, либо с `Ц`, в которой `У` заменено на `нет`. Доказав обе, мы доказали
 * `Ц` — и ни разу не сказали, ЧТО следует из истинности или ложности `У`.
 * Ловушка `не число` сюда не достаёт: она про перевод отрицания сравнения в
 * другое сравнение, а здесь отрицания нет вовсе — есть подстановка значения.
 *
 * ── Три условия, и ни одно не украшение ─────────────────────────────────────
 *   НЕ ПОД СВЯЗЫВАТЕЛЕМ. Условие берётся только с того `если`, до которого
 *     обход дошёл, НИ РАЗУ не войдя внутрь `разбор`, `свёртка`,
 *     `отобразить`/`отфильтровать` или `пусть`. Под связывателем у выражения
 *     нет одного значения: `эл равно искомое` внутри свёртки означает своё на
 *     каждом элементе, и заменять его одним `да` значило бы говорить о списке
 *     из одинаковых элементов. Тем же обходом ограничена и ЗАМЕНА: занятые
 *     связывателем поддеревья не трогаются вовсе.
 *   ЧИСТОТА. Язык чист, поэтому одно и то же выражение в одном и том же
 *     окружении имеет одно и то же значение, и заменять его во ВСЕХ доступных
 *     местах законно. Ровно на этом стоит закрытие цели «это классическая
 *     импликация»: `посылка` встречается в цели трижды, и все три раза это одно
 *     значение.
 *   ПРЕДЕЛ. Деления считаются, и при исчерпании ход отказывает СЛОВАМИ
 *     (`ПРЕДЕЛ_ВЕТВЛЕНИЯ`).
 *
 * ── Что считается закрытой половиной ────────────────────────────────────────
 * Ровно две вещи: половина, сведённая теми же тремя правилами (или ходами ниже
 * их), и половина, ставшая литералом `да`. Второе — не поблажка: `да` это уже
 * значение утверждения, а не утверждение о значении, и спорить о нём не о чем.
 * Половина, ставшая литералом `нет`, ЛОЖНА, и отказ говорит именно это.
 *
 * @returns {{ok: boolean, why: string|null}|null} `null` — условия в цели нет
 *   вовсе, и ходу не за что взяться; тогда отказ о нём не пишется ни слова.
 */
function поУсловию(заключение, допущения, объявления, определения, вычислитель, витков) {
  /* Витков не дали вовсе — хода нет, и молчать о нём надо ПОЛНОСТЬЮ: ни слова в
     отказе. На этом стоит побайтовая сверка с близнецом, у которого хода нет. */
  if (!(витков > 0)) return null
  const цель = нормализовать(заключение, определения)
  const условие = условиеЦели(цель)
  if (условие === null) return null

  const половины = [
    { имя: "условие истинно", цель: подставитьУсловие(цель, условие, ДА) },
    { имя: "условие ложно", цель: подставитьУсловие(цель, условие, НЕТ) },
  ]
  for (const половина of половины) {
    const итог = свестиПоловину(половина.цель, допущения, объявления, определения, вычислитель, витков - 1)
    if (итог.ok) continue
    /* УПЁРЛИСЬ В ПРЕДЕЛ — и сказать об этом надо словами, а не молчанием. Виток
       у половины последний, а условие в ней ещё осталось: значит ядро не
       досчитало, а не опровергло, и автору эти два ответа надо различать. */
    const упёрлись = витков === 1 && условиеЦели(нормализовать(половина.цель, определения)) !== null
    return {
      ok: false,
      why:
        `${ВЕТВЛЕНИЕМ} не прошёл: половина «${половина.имя}» не сведена: ${итог.why}`
        + (упёрлись
          ? `. Дальше делить нельзя: предел ветвления (${ПРЕДЕЛ_ВЕТВЛЕНИЯ}) исчерпан —`
            + " деление остановлено, а не продолжено молча"
          : ""),
    }
  }
  return { ok: true, why: null }
}

/** Одна половина разбора: литерал `да` закрыт сам, всё прочее сводится. */
function свестиПоловину(цель, допущения, объявления, определения, вычислитель, витков) {
  const форма = нормализовать(цель, определения)
  if (форма?.kind === "literal" && форма.value === true) return { ok: true, why: null }
  if (форма?.kind === "literal" && форма.value === false) {
    return { ok: false, why: "она стала литералом «нет», то есть ЛОЖНА — доказывать нечего, надо чинить" }
  }
  return свести(цель, допущения, объявления, определения, вычислитель, витков)
}

/**
 * Условие первого `если`, до которого обход дошёл, не входя ни в один
 * связыватель, — или `null`.
 *
 * Первого, а не «подходящего»: перебирать условия значило бы завести здесь
 * поиск, а его у ядра нет ни одного. Вложенные условия ход достаёт сам —
 * заменив внешнее значением, он зовётся снова, и следующее становится первым.
 */
function условиеЦели(узел) {
  if (узел === null || узел === undefined || typeof узел !== "object") return null
  if (Array.isArray(узел)) {
    for (const элемент of узел) {
      const найдено = условиеЦели(элемент)
      if (найдено !== null) return найдено
    }
    return null
  }
  if (СВЯЗЫВАЮЩИЕ.has(узел.kind)) return null
  if (узел.kind === "if") {
    /* Условие, уже ставшее литералом, делить не на что: нормализация такое
       `если` схлопывает, и попасть сюда оно может только литералом в исходном
       тексте. Делить по нему значило бы получить две одинаковые половины и
       съесть виток предела ни на чём. То же и у условия, которое САМО
       связыватель (`если (свёртка …) то …`): замена его не тронет — она в
       связыватели не входит, — и обе половины вышли бы теми же, что цель. */
    const условие = узел.cond ?? null
    if (условие?.kind === "literal" || СВЯЗЫВАЮЩИЕ.has(условие?.kind)) {
      return условиеЦели(узел.then) ?? условиеЦели(узел.else)
    }
    return условие
  }
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span") continue
    const найдено = условиеЦели(значение)
    if (найдено !== null) return найдено
  }
  return null
}

/**
 * Заменить условие его значением ВЕЗДЕ, куда обход дотягивается.
 *
 * Связыватели тот же список и та же граница, что у `условиеЦели`: под ними у
 * выражения нет одного значения, и подменять его там нельзя.
 */
function подставитьУсловие(узел, условие, значение) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => подставитьУсловие(элемент, условие, значение))
  if (СВЯЗЫВАЮЩИЕ.has(узел.kind)) return узел
  if (одинаковы(узел, условие)) return значение
  const собрано = {}
  for (const [ключ, поле] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? поле : подставитьУсловие(поле, условие, значение)
  }
  return собрано
}

/**
 * Узлы, СВЯЗЫВАЮЩИЕ имя, — тот же закрытый список, что у подстановки и у сбора
 * свободных имён (`initial.mjs`, `пройти` и `собрать`).
 *
 * Список закрыт нарочно и обязан оставаться закрытым: появись в языке пятый
 * связыватель, разбор по условию начал бы заменять выражение там, где у него
 * больше нет одного значения. Что списки не разошлись, проверяет отдельный тест
 * («ДРЕЙФ СПИСКОВ» в `flang/test/proof-soundness.test.mjs`).
 */
const СВЯЗЫВАЮЩИЕ = new Set(["let", "match", "fold", "map", "filter"])

/**
 * Три решающих правила — то же, чем `свести` была до четвёртого хода.
 *
 * Вынесено отдельной функцией ровно затем, чтобы ход вычисления стоял ПОСЛЕ
 * правил одной строкой, а не был вписан в каждый из четырёх отказов по копии.
 */
function поПравилам(заключение, допущения, объявления, определения) {
  const форма = нормальнаяФорма(заключение, определения)
  const цель = форма.выражение
  const факты = (допущения ?? []).map((д) => нормализовать(д?.claim ?? д, определения))
  const развёрнуто = [...форма.развёрнуто]
  /* О пределе говорится в отказе, а не в молчании: «не свелось, потому что
     дальше разворачивать запрещено» и «не свелось, потому что неправда» — разные
     ответы, и автор вправе их различать. */
  const оПределе = форма.предел
    ? ` Предел развёртки (${ПРЕДЕЛ_РАЗВЁРТКИ}) достигнут: развёртка остановлена,`
      + " а не продолжена молча — определение разворачивает себя быстрее, чем съедает конструкторы"
    : ""

  /* ПРАВИЛО 5 — «цель есть допущение», и стоит оно ПЕРВЫМ из пяти нарочно.
     Вида цели оно не спрашивает вовсе (четыре правила ниже заведены каждое под
     свой вид), поэтому разбирать выражение до него незачем: доказательство и
     разбор ветвей ниже — работа, а сличение с готовым списком фактов её не требует.
     Довод, почему это ТЕОРЕМА, а не аксиома, — при `естьДопущением`. */
  if (естьДопущением(цель, факты)) {
    return { ok: true, rule: ПРАВИЛО.assumption, why: null, unfolded: развёрнуто }
  }

  /* Оба списка известного собираются ОДИН раз на вызов и уезжают в оба правила.
     Дно и «конечный потолок» — разные вопросы к одним и тем же данным, и правило
     умножения спрашивает ОБА: без дна `а` бывает отрицательным, без конечного
     потолка — бесконечным, а `0 умножить на +∞` есть NaN. */
  const снизу = известноеСнизу(факты, объявления)
  const конечные = конечноеСверху(факты, объявления)
  /* Третий список, и объявления в него не входят НИ ОДНИМ именем: строгой
     положительности не обещает ни один тип языка — `нат` есть [0, 2⁵³−1], и ноль
     в нём живёт. Источник у этого списка ровно один — названный факт посылки. */
  const положительные = строгоПоложительное(факты)
  /* Четвёртый факт той же подписи — ЦЕЛОСТЬ — собирается один раз на оба
     правила: они спрашивают о ней одно и то же. */
  const целые = целоеПоТипу(объявления)

  if (цель?.kind === "binary" && цель.op === "gte" && ноль(цель.right)) {
    if (неотрицательно(цель.left, снизу, конечные, положительные, целые)) {
      return { ok: true, rule: ПРАВИЛО.nonneg, why: null, unfolded: развёрнуто }
    }
    return {
      ok: false,
      rule: null,
      unfolded: развёрнуто,
      why:
        `${ПРАВИЛО.nonneg} не проходит: выражение случая собрано не только из неотрицательного.`
        + " Неотрицательны литерал не меньше нуля, терм с допущением «не меньше 0»,"
        + " имя, объявленное типом с дном («нат», «вес»),"
        + " встроенная форма с объявленным от нуля результатом («длина», «код символа»),"
        + " их сумма, выбор из них"
        + " и свёртка с неотрицательным началом и сохраняющим знак шагом;"
        + " умножение берётся двумя способами и только ими: либо КАЖДЫЙ сомножитель лежит"
        + " в отрезке [0, конечное] — то есть о нём известны ОБЕ границы, а не одна"
        + " (в IEEE-754 «ноль умножить на бесконечность» даёт не число, и одного дна мало), —"
        + " либо ОДИН сомножитель лежит в (0, конечное], и тогда второму хватает дна;"
        + " строгую положительность не даёт ни один объявленный тип (ноль лежит и в «нат»),"
        + " её даёт только названный факт вида «терм больше К» при К не меньше нуля;"
        + " остаток от деления конечного целого неотрицательного на ненулевой целый литерал"
        + " (целость обещают точные типы: «нат», «целое», «сотых», «тысячных»);"
        + " вычитания в этом списке нет и не будет"
        + " (разность двух натуральных отрицательна уже на 2 минус 3)"
        + оПределе,
    }
  }

  if (цель?.kind === "binary" && цель.op === "lte" && конечныйЛитерал(цель.right)) {
    const потолок = цель.right.value
    const ограниченные = известноеСверху(факты, объявления, потолок)
    if (ограничено(цель.left, потолок, ограниченные, снизу, конечные, положительные, целые)) {
      return { ok: true, rule: ПРАВИЛО.bounded, why: null, unfolded: развёрнуто }
    }
    return {
      ok: false,
      rule: null,
      unfolded: развёрнуто,
      why:
        `${ПРАВИЛО.bounded} не проходит: выражение случая собрано не только из ограниченного сверху.`
        + " Ограничены литерал не больше границы, терм с допущением «не больше» той же или меньшей границы,"
        + " имя, объявленное точным типом («нат», «сотых», «тысячных») при границе не ниже 2^53−1,"
        + " выбор из ограниченных, разность, у которой уменьшаемое ограничено, а вычитаемое неотрицательно,"
        + " и остаток от деления неотрицательного ЦЕЛОГО на положительный целый литерал"
        + " (целость здесь несёт вес: «5.5 остаток от 2» равно 1.5, а это больше единицы);"
        + " СЛОЖЕНИЯ в этом списке нет и не будет — сумма двух «нат» выходит за потолок законно"
        + " (2^53−1 плюс 2^53−1 за точной сеткой, и тип результата от этого расширяется до «число»)"
        + оПределе,
    }
  }

  /* ПРАВИЛО 4: порядок по построению, граница — ТЕРМ. Стоит ПОСЛЕ правила 3
     нарочно: у конечного литерала есть своё правило, и отдавать его сюда значило
     бы завести второй ответ на тот же вопрос. */
  if (цель?.kind === "binary" && цель.op === "lte" && !конечныйЛитерал(цель.right)) {
    const левое = развернутьДлинуЗвена(цель.left)
    const правое = развернутьДлинуЗвена(цель.right)
    const порядки = факты.map(развернутьДлинуЗвена)
    if (поПорядку(левое, правое, порядки, снизу, конечные, положительные, целые)) {
      return { ok: true, rule: ПРАВИЛО.order, why: null, unfolded: развёрнуто }
    }
    return {
      ok: false,
      rule: null,
      unfolded: развёрнуто,
      why:
        `${ПРАВИЛО.order} не проходит: цель не сведена к порядку, известному по построению.`
        + " Граница здесь ТЕРМ, а не конечный литерал, и потому известного о ней у ядра ровно столько,"
        + " сколько дают три правила выше. Выводятся: допущение «то же слева, та же граница справа»;"
        + " тождество сторон при границе, о которой доказано «не меньше 0» (у не-числа порядка нет вовсе,"
        + " и «Е не больше Е» без этой посылки ложно на «не число»); выбор, у которого обе ветви под границей;"
        + " литерал, не превосходящий ДНА границы (дно даёт неотрицательность и сумма дон);"
        + " прибавление ОДНОГО И ТОГО ЖЕ конечного литерала к обеим сторонам известного порядка;"
        + " прибавление к ГРАНИЦЕ неотрицательного конечного литерала при уже известном порядке."
        + " Плюс МЕРА СПИСКА, и список её случаев тоже закрыт: разбор, у которого КАЖДАЯ ветвь под границей"
        + " (внутри ветви разбираемое ИМЯ читается конструктором: это уравнение написано словом «случай»,"
        + " и делается оно только для встроенного списка, у которого части названы целиком);"
        + " длина отбора против длины того же списка (отбор не удлиняет);"
        + " и свёртка по ТОМУ ЖЕ списку, у которой начало есть НОЛЬ, а шаг прибавляет не больше единицы"
        + " и не портит знака (индукция по списку: после «и» витков накопитель не больше «и»)."
        + " Длина при этом переписывается РАВНЫМ выражением только у форм, где считается точно:"
        + " выписанный список, строка-литерал, выбор, разбор, отображение, «добавить», «приписать»."
        + " Ни вычитания, ни умножения в этом списке нет:"
        + " границы-терма о конечности не обещает никто, а без неё «а минус б» даёт не-число на двух бесконечностях"
        + оПределе,
    }
  }

  if (цель?.kind === "binary" && цель.op === "eq") {
    let левое = цель.left
    let правое = цель.right
    for (const факт of факты) {
      if (факт?.kind !== "binary" || факт.op !== "eq") continue
      левое = переписать(левое, факт.left, факт.right)
      правое = переписать(правое, факт.left, факт.right)
    }
    /* ДЛИНА ЧИТАЕТСЯ КАК МЕРА и здесь, а не только у правила порядка, и это не
       послабление тождества, а та же самая переписка. `развернутьДлинуЗвена`
       заменяет `длина(…)` РАВНЫМ выражением (`мераПостроения`: список выписан
       целиком, строка-литерал, выбор, разбор, отображение, `добавить`,
       `приписать`), а тождество сличает стороны ПОСЛЕ нормализации — то есть
       после всякой другой переписки ядра ровно так же.

       ПОЧЕМУ ЗДЕСЬ НЕ НУЖНА ПОСЫЛКА «НЕ NaN», хотя у порядка она нужна. `равен`
       языка — это `Object.is` (`flang/src/builtins.mjs`, `valuesEqual`), и на
       нём `не число равно не число` ИСТИННО, а `0 равно −0` ЛОЖНО. Значит
       рефлексивность равенства — теорема без всяких посылок, в отличие от
       рефлексивности порядка, где `NaN не больше NaN` ложно. Проверено
       вычислением, а не памятью. */
    if (одинаковы(
      нормализовать(развернутьДлинуЗвена(левое), определения),
      нормализовать(развернутьДлинуЗвена(правое), определения),
    )) {
      return { ok: true, rule: ПРАВИЛО.identity, why: null, unfolded: развёрнуто }
    }
    return {
      ok: false,
      rule: null,
      unfolded: развёрнуто,
      why:
        `${ПРАВИЛО.identity} не проходит: после переписки допущениями стороны равенства`
        + " остались разными термами. Ядро сличает синтаксически и равенства вычислений не решает"
        + оПределе,
    }
  }

  return {
    ok: false,
    rule: null,
    unfolded: развёрнуто,
    why:
      "у цели этого случая нет вида, к которому у ядра есть правило:"
      + " правил четыре — «не меньше 0», «не больше конечного литерала», «не больше терма» и «равно»,"
      + " и все четыре названы в отказе, чтобы список был виден целиком."
      + ` Вида цели не спрашивает только пятое, «${ПРАВИЛО.assumption}»,`
      + " и оно тоже не прошло: ни одно допущение не совпало с целью знак в знак",
  }
}

