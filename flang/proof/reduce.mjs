/**
 * Что известно неотрицательным — допущениями И объявлениями, одним списком.
 *
 * Два источника собираются здесь, а не в двух местах: правило одно, и список
 * известного у него один. Второе место, где тот же список собирался бы заново,
 * — это второй ответ на тот же вопрос.
 */
function известноеСнизу(факты, объявления) {
  return [
    ...(факты ?? [])
      .filter((факт) => факт?.kind === "binary" && факт.op === "gte" && ноль(факт.right))
      .map((факт) => факт.left),
    ...известноеПоТипу(объявления),
  ]
}

/**
 * Что известно неотрицательным ИЗ ОБЪЯВЛЕНИЙ — по одному факту на имя типа `нат`.
 *
 * Здесь ровно одно решение, и оно закрыто списком: натуральный тип даёт факт,
 * все прочие не дают ничего. Имена берутся у типизатора (`ИМЕНА_НАТ`), так что
 * четыре поверхности языка (`нат`, `nat`, `naturo`, `自然数`) читаются одинаково
 * и без второго словаря.
 *
 * ПОЧЕМУ ФАКТ ЗДЕСЬ — ИМЕННО «ИМЯ НЕ МЕНЬШЕ 0». `нат` обещает отрезок
 * [0, 2^53−1], то есть и дно, и потолок; эта функция отдаёт ДНО, потому что
 * правило неотрицательности спрашивает только про знак. Потолок отдаёт
 * `ограниченноеПоТипу` ниже — своим правилом и с другим списком случаев, и
 * разница между списками не косметическая: дно переживает сложение, потолок нет.
 * Одной функцией на оба факта здесь было бы «имя типа `нат` — это хорошо», а
 * такого правила у ядра нет.
 *
 * ГДЕ ЭТИ ФАКТЫ БЕЗОПАСНО ПРИМЕНЯТЬ. Только к именам, СВОБОДНЫМ в цели, и это
 * не пожелание, а свойство `неотрицательно` ниже: она не спускается ни под один
 * связыватель (`пусть` к её приходу уже развёрнут нормализацией, а `разбор` и
 * `свёртка` дают `false` целиком). Значит всякое имя, до которого она доходит,
 * — то самое, что объявлено в подписи, а не одноимённое связанное. Свойство
 * держится тестом («правило не спускается под связыватель…»), а не обещанием:
 * начни она однажды заходить в ветви `разбор`, факт об имени параметра мог бы
 * лечь на чужое имя, и это была бы принятая ложь.
 *
 * @param {{name: string, type: object|null}[]} объявления
 * @returns {object[]} термы-имена, о которых известно «не меньше 0»
 */
export function известноеПоТипу(объявления) {
  const известные = []
  for (const объявление of объявления ?? []) {
    if (typeof объявление?.name !== "string") continue
    if (!натуральный(объявление.type)) continue
    известные.push({ kind: "var", name: объявление.name })
  }
  return известные
}

/**
 * Объявлен ли тип натуральным — по написанному имени, тем же словарём, каким его
 * читает типизатор.
 *
 * Узел `named` — это то, что строит парсер: имена уточнённых типов НЕ ключевые
 * слова (`types.mjs`, «Имена уточнённых типов»), и в позиции типа `нат`
 * разбирается ровно так же, как «Возможно» или любой объявленный тип.
 * Объявить свой тип с таким именем и подменить смысл нельзя: `namedOrScalar`
 * смотрит в словарь ДО объявлений модуля, поэтому здесь и там `нат` — одно и то
 * же.
 */
function натуральный(тип) {
  if (тип === null || тип === undefined) return false
  if (тип.kind !== "named") return false
  return ИМЕНА_НАТ.includes(тип.name)
}

/**
 * Что известно ограниченным сверху КОНЕЧНОЙ границей — какой именно, неважно.
 *
 * Это третий список известного, и он отвечает на СВОЙ вопрос, а не на вопрос
 * `известноеСверху`. Тому нужно «не больше П» для конкретного П из цели; правилу
 * умножения нужно только одно — что величина КОНЕЧНА, потому что бесконечность
 * есть единственный способ получить NaN из произведения неотрицательных.
 * Отсюда и разница в отборе: допущение `Т не больше 1e300` для цели с потолком
 * 2^53−1 бесполезно, а для умножения годится вполне — оно исключает `+∞`.
 *
 * Из объявлений факт берётся тем же `ограниченноеПоТипу` и с потолком типа: `нат`
 * есть [0, `ТОЧНЫЙ_ПОТОЛОК`], и второй раз это число здесь не переписано.
 */
function конечноеСверху(факты, объявления) {
  return [
    ...(факты ?? [])
      .filter((факт) => факт?.kind === "binary" && факт.op === "lte" && конечныйЛитерал(факт.right))
      .map((факт) => факт.left),
    ...ограниченноеПоТипу(объявления, ТОЧНАЯ_СЕТКА.верх),
  ]
}

/**
 * Лежит ли выражение в отрезке [0, КОНЕЧНОЕ] — посылка правила умножения.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ СВЁРТКА, А НЕ ДВА ВЫЗОВА ПРЕЖНИХ. Вопрос здесь ОДИН и он
 * составной: величина обязана быть и неотрицательной, и конечной. Спросить это
 * двумя отдельными свёртками нельзя — они разошлись бы на составных выражениях:
 * `н плюс м` неотрицательно и `н плюс м` при двух `нат` ограничено ничем, потому
 * что сумма переполняется в `+∞`. Свёртка, отвечающая «да» на такое, отдала бы
 * умножению бесконечный сомножитель, и `0 умножить на (н плюс м)` дало бы NaN.
 *
 * ПОЭТОМУ СПИСОК СЛУЧАЕВ КОРОЧЕ ОБОИХ СОСЕДЕЙ, и короче он намеренно:
 *
 *   конечный литерал ≥ 0                                  в отрезке
 *   терм, о котором известно И дно, И конечный потолок     в отрезке
 *   `если у то а иначе б` при обоих в отрезке              в отрезке
 *
 * Ни сложения, ни умножения: обе операции выводят из отрезка переполнением, а
 * `+∞` — ровно то значение, ради исключения которого посылка и заведена.
 * Вычитания нет по другой причине: оно выводит из отрезка вниз (`2 минус 3`).
 * Выбор берётся потому, что он не арифметика: значение равно одной из ветвей,
 * обе в отрезке — значит и выбор в нём, и никакого округления не происходит.
 *
 * ПОД СВЯЗЫВАТЕЛИ НЕ СПУСКАЕТСЯ — как и оба соседа, и по той же причине: факт об
 * имени параметра, положенный на одноимённое связанное имя, был бы принятой ложью.
 *
 * @param {object} выражение
 * @param {object[]} снизу термы, о которых известно «не меньше 0»
 * @param {object[]} конечные термы, о которых известно «не больше конечного»
 */
export function вОтрезке(выражение, снизу, конечные) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    /* `Number.isFinite` отсекает и NaN, и обе бесконечности разом — оба вида
       значений, на которых правило умножения было бы ложным. */
    return typeof выражение.value === "number" && Number.isFinite(выражение.value) && выражение.value >= 0
  }
  const знаком = (список) => (список ?? []).some((известное) => одинаковы(известное, выражение))
  if (знаком(снизу) && знаком(конечные)) return true
  if (выражение.kind === "if") {
    return вОтрезке(выражение.then, снизу, конечные) && вОтрезке(выражение.else, снизу, конечные)
  }
  return false
}

/**
 * Неотрицательно ли выражение — по построению, а не по значению.
 *
 * Свёртка по конечному дереву выражения: пять случаев, ни одного перебора.
 * Всё, что не подошло ни под один, неотрицательным НЕ считается — отказ по
 * умолчанию, потому что противоположное умолчание («не знаю, значит ладно») и
 * есть способ принять ложь.
 *
 * Имя, объявленное как `нат`, попадает сюда уже фактом в `снизу`
 * (`известноеПоТипу`), а не отдельным случаем: источник у факта другой, а
 * правило — то же самое, и разводить их на две ветви значило бы иметь два
 * правила неотрицательности вместо одного.
 *
 * УМНОЖЕНИЕ СТОИТ НА ДРУГОЙ ПОСЫЛКЕ, ЧЕМ СЛОЖЕНИЕ, и это главное место функции.
 * Сложению хватает дна: сумма двух значений из [0, +∞] снова в [0, +∞], и
 * переполнение в `+∞` знака не портит. Умножению дна МАЛО: `0 умножить на +∞`
 * даёт NaN, а `+∞ не меньше 0` — истинная посылка, то есть дно бесконечности не
 * исключает. Поэтому у сомножителей спрашивается `вОтрезке` — обе границы
 * сразу, — и спрашивается у КАЖДОГО: одного конечного сомножителя мало, второй
 * бесконечный даёт тот же NaN.
 *
 * @param {object} выражение
 * @param {object[]} снизу термы, о которых известно «не меньше 0»
 * @param {object[]} [конечные] термы, о которых известно «не больше конечного».
 *   Не дали — умножение не выводится вовсе: без второй границы правило ложно, и
 *   умолчание здесь «нечего», а не «ладно».
 */
export function неотрицательно(выражение, снизу, конечные = []) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && !Number.isNaN(выражение.value) && выражение.value >= 0
  }
  if ((снизу ?? []).some((известное) => одинаковы(известное, выражение))) return true
  if (выражение.kind === "binary" && выражение.op === "add") {
    return неотрицательно(выражение.left, снизу, конечные) && неотрицательно(выражение.right, снизу, конечные)
  }
  if (выражение.kind === "binary" && выражение.op === "mul") {
    return вОтрезке(выражение.left, снизу, конечные) && вОтрезке(выражение.right, снизу, конечные)
  }
  if (выражение.kind === "if") {
    return неотрицательно(выражение.then, снизу, конечные) && неотрицательно(выражение.else, снизу, конечные)
  }
  return false
}

