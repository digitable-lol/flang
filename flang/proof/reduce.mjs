/**
 * Заменить все вхождения `откуда` на `куда` — ровно один проход.
 *
 * Один проход, а не до неподвижной точки: переписка равенством до неподвижной
 * точки не заканчивается на тождестве вида `х равно х`, а проверяльщик обязан
 * останавливаться всегда. Одного прохода хватает, потому что допущение индукции
 * говорит о ЧАСТИ значения, и вложенных вхождений одной части в другую у
 * конечного дерева не бывает.
 */
export function переписать(узел, откуда, куда) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (одинаковы(узел, откуда)) return куда
  if (Array.isArray(узел)) return узел.map((элемент) => переписать(элемент, откуда, куда))
  const собрано = {}
  for (const [ключ, значение] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? значение : переписать(значение, откуда, куда)
  }
  return собрано
}

