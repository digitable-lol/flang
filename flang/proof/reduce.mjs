/**
 * Свести заключение посылки к допущениям.
 *
 * @param {object} заключение выражение-цель случая (уже с подставленным телом ветви)
 * @param {object[]} допущения утверждения допущений индукции
 * @param {{name: string, type: object|null}[]} [объявления] имена, видимые в цели,
 *   с типами, КАК ИХ ОБЪЯВИЛ АВТОР: параметры функции и поля образца случая.
 *   Тип — тоже факт, и приезжает он сюда наравне с допущениями, а не вместо них.
 * @param {Map<string, object>|null} [определения] функции модуля — то, что ядру
 *   разрешено РАЗВЕРНУТЬ. Ничего не передали — развёртки нет вовсе: ядро не
 *   ходит за определениями само, их ему дают, и это тот же приём, каким сюда
 *   приезжают допущения и объявления.
 * @param {((цель: object) => {ok: boolean, why: string|null})|null} [вычислитель]
 *   ЧЕТВЁРТЫЙ ХОД, и приезжает он сюда тем же способом, что определения:
 *   данными, а не походом за ними. Спрашивается ПОСЛЕ трёх правил и только при
 *   их отказе — правило по построению дешевле вычисления и работает при живых
 *   именах. Не дали вычислителя — хода нет, и ответ этой функции тот же, знак в
 *   знак, каким был до его появления: на этом стоит сверка с близнецом на flang.
 * @param {number} [витков] ПЯТЫЙ ХОД — разбор цели по условию, и включается он
 *   ТЕМ ЖЕ СПОСОБОМ, что четвёртый, и по той же причине. Ноль по умолчанию
 *   значит «хода нет», и тогда ответ этой функции знак в знак тот же, каким был
 *   до его появления. Так держится побайтовая сверка с близнецом на flang: у
 *   близнеца этого хода НЕТ, и долг назван вслух (`flang/proof/SPEC.md`), а не
 *   спрятан ослаблением сверки. Ядро зовёт этот вход с `ПРЕДЕЛ_ВЕТВЛЕНИЯ`.
 * @returns {{ ok: boolean, rule: string|null, why: string|null, unfolded: string[] }}
 */
export function свести(
  заключение,
  допущения,
  объявления = [],
  определения = null,
  вычислитель = null,
  витков = 0,
) {
  const итог = поПравилам(заключение, допущения, объявления, определения)
  if (итог.ok) return итог

  let счётом = null
  if (typeof вычислитель === "function") {
    /* Вычислителю отдаётся цель КАК ПРИШЛА, а не её нормальная форма, и это не
       мелочь порядка. Нормализация — переписка ядра, и всё, что она делает,
       вычислителю не нужно: интерпретатор языка сам разворачивает и `пусть`, и
       разбор, и вызов, и делает это правилами языка, а не ядра. Считая
       написанное, ход не зависит от нормализации ВОВСЕ — в том числе от её
       ограничителя на захват имени, — и класс ошибок «развёртка молча
       переименовала чужую переменную» до вычисления не доходит. */
    счётом = вычислитель(заключение)
    if (счётом.ok) return { ok: true, rule: ВЫЧИСЛЕНИЕМ, why: null, unfolded: итог.unfolded }
  }

  /* ПЯТЫЙ ХОД — разбор цели по условию. Стоит ПОСЛЕ вычисления нарочно: у
     замкнутой цели значение одно, и посчитать её дешевле, чем делить надвое и
     сводить обе половины. */
  const ветвлением = поУсловию(заключение, допущения, объявления, определения, вычислитель, витков)
  if (ветвлением !== null && ветвлением.ok) {
    return { ok: true, rule: ВЕТВЛЕНИЕМ, why: null, unfolded: итог.unfolded }
  }

  /* Отказы ходов ДОПИСЫВАЮТСЯ к отказу правил, а не заменяют его: автору нужны
     все ответы. «Правило не прошло» говорит, чего не хватило выводу, «вычислить
     не вышло» — почему цель не решилась счётом, «половина не сведена» — какая
     именно ветвь условия осталась недоказанной, и это разные починки. */
  const хвост = [счётом?.why, ветвлением?.why].filter((слова) => typeof слова === "string")
  return хвост.length === 0 ? итог : { ...итог, why: [итог.why, ...хвост].join(". ") }
}

