/**
 * Нормальная форма выражения: развёрнуты `пусть`, разбор известного варианта,
 * условие с уже вычисленным условием и — если ядру дали определения — вызов.
 *
 * @param {object} выражение
 * @param {Map<string, object>|null} [определения] функции модуля; без них
 *   развёртки нет, и нормализация та же самая, что была до этой работы.
 */
export function нормализовать(выражение, определения = null) {
  return нормальнаяФорма(выражение, определения).выражение
}

/**
 * То же самое, но с ОТЧЁТОМ: что развёрнуто и достигнут ли предел.
 *
 * Отчёт нужен не для красоты. Отказ «не свелось» и отказ «не свелось, потому что
 * дальше разворачивать нельзя» — разные ответы автору, и различить их может
 * только тот, кто разворачивал.
 *
 * @returns {{ выражение: object, развёрнуто: string[], предел: boolean }}
 */
export function нормальнаяФорма(выражение, определения = null) {
  const состояние = {
    определения: определения instanceof Map ? определения : null,
    осталось: ПРЕДЕЛ_РАЗВЁРТКИ,
    развёрнуто: [],
    предел: false,
    /* Плоское ли определение — вопрос о функции, а не о вызове, и ответ на него
       один на всю нормализацию. Считать его заново на каждом вызове значило бы
       обходить одно и то же тело столько раз, сколько раз функция позвана. */
    плоские: new Map(),
  }
  return {
    выражение: шаг(выражение, new Map(), состояние),
    развёрнуто: состояние.развёрнуто,
    предел: состояние.предел,
  }
}

function шаг(узел, окружение, состояние) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => шаг(элемент, окружение, состояние))

  if (узел.kind === "var") {
    const значение = окружение.get(узел.name)
    return значение === undefined ? узел : значение
  }

  if (узел.kind === "let" && typeof узел.name === "string") {
    /* Значение нормализуется ДО подстановки: иначе одно и то же поддерево
       нормализовалось бы столько раз, сколько раз имя встретилось в теле. */
    const внутри = new Map(окружение)
    внутри.set(узел.name, шаг(узел.value, окружение, состояние))
    return шаг(узел.in, внутри, состояние)
  }

  if (узел.kind === "match") {
    const цель = шаг(узел.target, окружение, состояние)
    if (цель?.kind === "construct") {
      /* Ветвь ищется по ИМЕНИ КОНСТРУКТОРА, прочитанному с образца, а не по виду
         узла: у списка тот же самый вопрос записывается словами `случай пусто`,
         и разбирать его вторым способом значило бы получить второй ответ. */
      const ветвь = (узел.cases ?? []).find((случай) => образецВарианта(случай?.pattern)?.name === цель.variant)
      if (ветвь !== undefined) {
        const внутри = new Map(окружение)
        const поля = полями(цель)
        for (const [поле, имя] of Object.entries(образецВарианта(ветвь.pattern)?.bind ?? {})) {
          const значение = поля.get(поле)
          /* Поле, которого у конструкции нет, остаётся собой: это не ошибка ядра,
             а незаполненное поле, и подставлять вместо него нечего. */
          внутри.set(имя, значение === undefined ? { kind: "var", name: имя } : шаг(значение, окружение, состояние))
        }
        return шаг(ветвь.body, внутри, состояние)
      }
    }
    return {
      ...узел,
      target: цель,
      cases: (узел.cases ?? []).map((случай) => {
        const внутри = new Map(окружение)
        /* Имена образца берутся `связанныеОбразцом` (`work/list-algebra`): у
           образца списка `голова и хвост` связок нет в `bind`, и старое чтение
           по `bind` их не видело. Состояние развёртки (`work/kernel-unfold`)
           при этом передаётся дальше — иначе четвёртая переписка теряла бы счёт
           внутри `разбор`. */
        for (const имя of связанныеОбразцом(случай?.pattern)) внутри.delete(имя)
        return { ...случай, body: шаг(случай.body, внутри, состояние) }
      }),
    }
  }

  if (узел.kind === "if") {
    const условие = шаг(узел.cond, окружение, состояние)
    if (условие?.kind === "literal" && условие.value === true) return шаг(узел.then, окружение, состояние)
    if (условие?.kind === "literal" && условие.value === false) return шаг(узел.else, окружение, состояние)
    return {
      ...узел,
      cond: условие,
      then: шаг(узел.then, окружение, состояние),
      else: шаг(узел.else, окружение, состояние),
    }
  }

  if (узел.kind === "fold") {
    const внутри = new Map(окружение)
    if (typeof узел.acc === "string") внутри.delete(узел.acc)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return {
      ...узел,
      over: шаг(узел.over, окружение, состояние),
      init: шаг(узел.init, окружение, состояние),
      body: шаг(узел.body, внутри, состояние),
    }
  }

  /* `отобразить`/`отфильтровать` связывают элемент ровно так же, как свёртка —
     накопитель, и пропускать их значило бы подставлять снаружи внутрь чужого
     имени. Списочные функции библиотеки написаны этими двумя формами чаще
     всего («Без значения» — `отфильтровать элементы где эл → …`), так что до
     начальной алгебры списка промах здесь просто не мог сработать. */
  if (узел.kind === "map" || узел.kind === "filter") {
    const внутри = new Map(окружение)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return { ...узел, over: шаг(узел.over, окружение), body: шаг(узел.body, внутри) }
  }

  const собрано = {}
  for (const [ключ, значение] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? значение : шаг(значение, окружение, состояние)
  }
  /* Развёртка стоит ПОСЛЕ обхода аргументов, и это не мелочь порядка: аргументы
     к этому времени уже нормальны, поэтому развёртка «по конструктору» видит
     конструктор там, где он был спрятан за `пусть` или за разбором, а плоская
     развёртка не размножает ненормализованных поддеревьев. */
  if (собрано.kind === "call") {
    const развёрнуто = развернуть(собрано, состояние)
    if (развёрнуто !== null) return развёрнуто
  }
  return собрано
}

/* ------------------------------------------------------------------ */
/* Четвёртая переписка: развёртка определения                          */
/* ------------------------------------------------------------------ */

/**
 * Развернуть вызов — заменить его телом функции с подстановкой аргументов.
 *
 * Каждое `null` ниже — НАЗВАННЫЙ ограничитель, а не «почему-то не вышло», и у
 * каждого стоит свой тест. Подстановка при этом не своя: она делается тем же
 * `шаг`, что и всё остальное, поэтому связанные имена тела вычёркиваются из
 * окружения ровно так же, как под `пусть`.
 *
 * @returns {object|null} нормализованное тело или `null`, если развёртки нет
 */
function развернуть(вызов, состояние) {
  const определения = состояние?.определения
  if (!(определения instanceof Map)) return null
  const функция = определения.get(вызов.name)
  if (функция === null || функция === undefined) return null

  /* ОГРАНИЧИТЕЛЬ 1: только объявленное ТОТАЛЬНЫМ. Обещание завершения дало не
     ядро — его доказал анализ завершаемости, и ядро читает написанное слово. */
  if (функция.total !== true) return null

  const тело = функция.body
  if (тело === null || тело === undefined) return null
  const параметры = (функция.params ?? []).map((п) => п.name)
  const аргументы = вызов.args ?? []
  /* Вызов не по числу параметров — не развёртка, а другая ошибка, и ловит её
     типизатор. Ядро тут молчит: подставлять некуда. */
  if (параметры.length !== аргументы.length) return null

  /* ОГРАНИЧИТЕЛЬ 2: два вида развёртки, список закрыт. */
  const правило = правилоРазвёртки(функция, параметры, аргументы, состояние)
  if (правило === null) return null

  /* ОГРАНИЧИТЕЛЬ 3: названный предел. Считаются ПОПЫТКИ, а не удачи: попытка
     стоит того же обхода, и предел стережёт именно работу. */
  if (состояние.осталось <= 0) {
    состояние.предел = true
    return null
  }
  состояние.осталось -= 1

  const окружение = new Map()
  параметры.forEach((имя, и) => окружение.set(имя, аргументы[и]))
  const развёрнуто = шаг(тело, окружение, состояние)

  /* ОГРАНИЧИТЕЛЬ 4: захват имени. Связыватель, переживший подстановку, не имеет
     права связывать имя, свободное в аргументе, — иначе аргумент говорил бы уже
     не о том, о чём его написали. Переименовывать ядро не станет: выдуманные
     имена сличать с допущениями нельзя. */
  if (связывает(развёрнуто, именаАргументов(аргументы))) return null

  состояние.развёрнуто.push(`${вызов.name}: ${правило}`)
  return развёрнуто
}

/**
 * Каким правилом разворачивается этот вызов — или `null`, если ни одним.
 *
 * Оба правила читаются с написанного и ничего не перебирают:
 *
 *   ПО КОНСТРУКТОРУ. Тело есть `разбор <параметр>`, и на месте этого параметра
 *     стоит конструктор. Тогда развёртка не вычисляет ничего: она читает ветвь,
 *     названную объявлением, и конструктор при этом съедается. Рекурсивный вызов
 *     в ветви стоит на ЧАСТИ значения — на имени, — и второй раз не разворачивается.
 *
 *   ПЛОСКОЕ ОПРЕДЕЛЕНИЕ. В теле нет ни одного вызова. Такая развёртка новых
 *     вызовов не заводит: всё, что окажется в развёрнутом теле, уже стояло в
 *     аргументах, а они к этому времени нормальны.
 *
 * Тело берётся КАК НАПИСАНО, без нормализации: `пусть` перед `разбор` развёртку
 * отменит, и это осознанный отказ в пользу простоты — правило, которое читается
 * с одного взгляда на тело, дороже одного лишнего доказательства.
 */
function правилоРазвёртки(функция, параметры, аргументы, состояние) {
  const место = разборПоПараметру(функция.body, параметры)
  if (место >= 0 && аргументы[место]?.kind === "construct") return РАЗВЁРТКА.constructor
  if (!зоветЛи(функция, состояние)) return РАЗВЁРТКА.flat
  return null
}

/** Номер параметра, по которому тело разбирает значение, или −1. */
function разборПоПараметру(тело, параметры) {
  if (тело?.kind !== "match") return -1
  if (тело.target?.kind !== "var") return -1
  return параметры.indexOf(тело.target.name)
}

/**
 * Есть ли в теле функции хоть один вызов чужого тела.
 *
 * Список видов закрыт и назван: за каждым из них стоит ТЕЛО, которого здесь
 * нет, — и значит развёртка такого тела могла бы завести новый вызов. Встроенные
 * (`builtin`) в список не входят: своего тела у них в языке нет вовсе, разворачивать
 * там нечего, и остановке они не мешают.
 */
const ВЫЗОВЫ = Object.freeze(["call", "apply", "compose", "composition", "fnref", "morphism"])

function зоветЛи(функция, состояние) {
  const готово = состояние.плоские.get(функция.name)
  if (готово !== undefined) return готово
  const ответ = естьВызов(функция.body)
  состояние.плоские.set(функция.name, ответ)
  return ответ
}

function естьВызов(узел) {
  if (узел === null || узел === undefined || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some((элемент) => естьВызов(элемент))
  if (typeof узел.kind === "string" && ВЫЗОВЫ.includes(узел.kind)) return true
  return Object.entries(узел).some(([ключ, значение]) => ключ !== "span" && естьВызов(значение))
}

/** Все имена, встречающиеся в аргументах вызова, — сверху, без разбора связей. */
function именаАргументов(аргументы) {
  const имена = new Set()
  собратьИмена(аргументы, имена)
  return имена
}

function собратьИмена(узел, имена) {
  if (узел === null || узел === undefined || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) собратьИмена(элемент, имена)
    return
  }
  if (узел.kind === "var" && typeof узел.name === "string") имена.add(узел.name)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span") continue
    собратьИмена(значение, имена)
  }
}

/**
 * Связывает ли развёрнутое тело хоть одно из этих имён.
 *
 * Связывателей в языке три, и список тот же, что у подстановки в `initial.mjs`:
 * `пусть`, образец случая внутри `разбор` и `свёртка`. Появись четвёртый — эта
 * проверка его не увидит, и потому список назван здесь прямо, а не выведен.
 */
function связывает(узел, имена) {
  if (имена.size === 0) return false
  if (узел === null || узел === undefined || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some((элемент) => связывает(элемент, имена))
  if (узел.kind === "let" && имена.has(узел.name)) return true
  if (узел.kind === "fold" && (имена.has(узел.acc) || имена.has(узел.item))) return true
  if (узел.kind === "match") {
    for (const случай of узел.cases ?? []) {
      for (const имя of Object.values(случай?.pattern?.bind ?? {})) {
        if (имена.has(имя)) return true
      }
    }
  }
  return Object.entries(узел).some(([ключ, значение]) => ключ !== "span" && связывает(значение, имена))
}

