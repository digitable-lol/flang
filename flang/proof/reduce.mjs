/**
 * reduce.mjs — сведение заключения посылки к допущениям индукции.
 *
 * ── Что это и чем оно НЕ является ───────────────────────────────────────────
 * Здесь два решающих правила и одна нормализация, и ни одного поиска. Решающее
 * правило — это не тактика: тактика ворочает состояние цели перебором и потому
 * нетотальна, а правило ниже — структурная свёртка по выражению, которая
 * отвечает да или нет и всегда останавливается. Разница ровно та же, что между
 * `разбор` и циклом с условием: у первого число ветвей известно из объявления.
 *
 * Оба правила закрыты списком и печатаются в отказе поимённо. Правило, которое
 * нельзя перечислить, ничем не отличается от «ядро решило, что так можно».
 *
 * ── Нормализация: развёртка того, что уже написано ──────────────────────────
 * Три переписки, и все три — чтение, а не вывод:
 *
 *   `пусть и равно З; Т`      →  Т, в котором `и` заменено на З
 *   `разбор (вариант «C» …)`  →  тело ветви «C» со связанными полями
 *   `если да то А иначе Б`    →  А (условие уже вычислилось в значение)
 *
 * Ни одна из них не разворачивает ВЫЗОВ функции, и это главное ограничение
 * файла, названное прямо. Развернуть вызов значило бы начать вычисление, а
 * вычисление рекурсивной функции на незамкнутом значении не заканчивается: у
 * `«Высота» от м` при неизвестном `м` нет нормальной формы. Поэтому вызов
 * остаётся непрозрачным термом — и именно поэтому нужны допущения индукции: они
 * и есть то, что о непрозрачном терме известно.
 *
 * ── Правило 1: неотрицательность по построению ──────────────────────────────
 * Цель вида `Е не меньше 0` выводится, если `Е` собрано из неотрицательных:
 *
 *   литерал ≥ 0                                    неотрицателен
 *   терм, о котором ЕСТЬ допущение `… не меньше 0` неотрицателен
 *   `а плюс б` при неотрицательных `а` и `б`       неотрицателен
 *   `если у то а иначе б` при неотрицательных обоих неотрицателен
 *
 * ПОЧЕМУ ЭТО ПРАВДА В ЧИСЛАХ FLANG, А НЕ ТОЛЬКО В МАТЕМАТИКЕ. Числа языка —
 * IEEE-754, и в них ложны почти все привычные аксиомы порядка: `х плюс 1
 * больше х` неправда при большом |х|, `х минус 1 меньше х` — тоже. Ровно
 * поэтому список аксиом ядра был и остаётся пуст. Но перечисленное выше в
 * IEEE-754 ИСТИННО, и это проверяется рассуждением, а не надеждой:
 * `а не меньше 0` истинно только для не-NaN значений из [0, +∞] — NaN не
 * сравним ни с чем, и посылка на нём ложна. Сумма двух значений из [0, +∞] под
 * округлением к ближайшему снова лежит в [0, +∞]: переполнение даёт +∞, а не
 * отрицательное, и знака здесь потерять негде. Условное выражение вообще не
 * арифметика — это выбор одной из двух ветвей, и если обе неотрицательны, то
 * неотрицателен и выбор.
 *
 * ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ. Умножения: `0 умножить на +∞` даёт NaN, и правило
 * «произведение неотрицательных неотрицательно» было бы ЛОЖНЫМ. Вычитания и
 * деления — по той же причине. Аксиома, которая иногда ложна, делает ложным всё,
 * что из неё выведено, и одна такая строка обесценила бы каждое «доказано» в
 * ведомости. Список правил закрыт, и расширять его можно только тем же
 * рассуждением, каким открыт этот.
 *
 * ── Правило 2: тождество после переписки допущением ─────────────────────────
 * Цель вида `А равно Б` выводится, если после переписки допущениями индукции
 * (каждое допущение — равенство, применяется слева направо ко всем вхождениям,
 * по одному проходу на допущение) нормальные формы `А` и `Б` совпадают
 * СИНТАКСИЧЕСКИ. Совпадение по значению здесь не рассматривается и не может:
 * равенство вычислений на бесконечном носителе неразрешимо, и притвориться, что
 * это не так, значило бы завести решатель, которого нет.
 *
 * Проход по одному на допущение — не экономия, а условие останова: переписка
 * равенством в обе стороны или до неподвижной точки не заканчивается на
 * `х равно х`, и проверяльщик перестал бы быть тотальной программой.
 */

import { одинаковы } from "../src/obligations.mjs"

/** Версия набора правил: их читает ведомость и негативный тест, значит она названа. */
export const ПРАВИЛА = 1

/**
 * ДВА КОНСТРУКТОРА ВСТРОЕННОГО СПИСКА — теми же словами, какими их пишет образец.
 *
 * Это не объявление нового типа и не аксиома: это ИМЕНА того, что у языка уже
 * есть. `разбор` по списку исчерпывается ровно двумя образцами — `пусто` и
 * `голова и хвост`, третьего нет, — и говорит это не здесь, а типизатор
 * (`flang/src/types.mjs`, `reportExhaustiveness`: «разбор списка не покрывает
 * «пусто» и «голова и хвост»»). Печатает он их теми же двумя словами
 * (`patternName`), и они взяты сюда буквально, чтобы у вопроса «как называются
 * конструкторы списка» был ОДИН ответ на всё дерево.
 *
 * Имена полей звена — тоже не выдумка: `голова` и `хвост` пишет сам образец, а
 * их типы объявляет тот же типизатор (`bindPattern`, случай `cons`: голова —
 * элемент, хвост — список того же элемента). Отсюда и читается функтор
 * (`flang/proof/initial.mjs`, `объявлениеСписка`).
 */
export const СПИСОК = Object.freeze({
  пусто: "пусто",
  звено: "голова и хвост",
  голова: "голова",
  хвост: "хвост",
})

/**
 * Образец случая, прочитанный КАК КОНСТРУКТОР: имя и связи «поле → имя».
 *
 * Одно место на всё ядро, и это главное его свойство. `разбор` пишется тремя
 * разными образцами — `вариант «C» с полем как имя`, `пусто`, `голова и хвост`,
 * — но принцип индукции читает их одинаково: «какой конструктор назвал автор и
 * как он назвал части». Разложи это чтение по двум файлам — и ответов на один
 * вопрос станет два, а разойдутся они молча.
 *
 * `любое` конструктором НЕ является и возвращает `null`: оно не разбирает
 * значение, а даёт ему второе имя. Случай `любое` внутри индукции ловит
 * покрытие: у принципа посылок ровно столько, сколько конструкторов, и лишний
 * образец не сойдётся с объявлением.
 *
 * @param {object} образец узел `pattern` из AST
 * @returns {{ name: string, bind: Record<string,string> }|null}
 */
export function образецВарианта(образец) {
  if (образец === null || образец === undefined) return null
  if (образец.kind === "variant") {
    return typeof образец.name === "string" ? { name: образец.name, bind: образец.bind ?? {} } : null
  }
  if (образец.kind === "empty") return { name: СПИСОК.пусто, bind: {} }
  if (образец.kind === "cons") {
    const bind = {}
    if (typeof образец.head === "string") bind[СПИСОК.голова] = образец.head
    if (typeof образец.tail === "string") bind[СПИСОК.хвост] = образец.tail
    return { name: СПИСОК.звено, bind }
  }
  return null
}

/**
 * Имена, которые образец СВЯЗЫВАЕТ, — все, включая `любое`.
 *
 * Отдельно от `образецВарианта`, потому что вопросы разные: там «какой это
 * конструктор», здесь «какие имена внутри случая означают уже не то, что
 * снаружи». Второе нужно подстановке и сбору свободных имён, и ошибиться в нём
 * значит молча переименовать чужую переменную.
 *
 * До этого места оба обхода читали `Object.values(образец.bind)`, и это было
 * неверно дважды: у `голова и хвост` поля `bind` нет вовсе (имена лежат в
 * `head`/`tail`), а у `любое х` в `bind` лежит СТРОКА, и `Object.values` от
 * строки даёт её буквы — то есть на образце `любое элемент` вычёркивались имена
 * «э», «л», «е»… вместо «элемент».
 */
export function связанныеОбразцом(образец) {
  if (образец === null || образец === undefined) return []
  if (образец.kind === "any") return typeof образец.bind === "string" ? [образец.bind] : []
  const прочитано = образецВарианта(образец)
  if (прочитано === null) return []
  return Object.values(прочитано.bind).filter((имя) => typeof имя === "string")
}

/**
 * Имена правил — для отказа и для отчёта. Латиницей код, словом человек: тот же
 * приём, что у носителей обещания в ведомости.
 */
export const ПРАВИЛО = Object.freeze({
  nonneg: "неотрицательность по построению",
  identity: "тождество после переписки допущением",
})

/**
 * Свести заключение посылки к допущениям.
 *
 * @param {object} заключение выражение-цель случая (уже с подставленным телом ветви)
 * @param {object[]} допущения утверждения допущений индукции
 * @returns {{ ok: boolean, rule: string|null, why: string|null }}
 */
export function свести(заключение, допущения) {
  const цель = нормализовать(заключение)
  const факты = (допущения ?? []).map((д) => нормализовать(д?.claim ?? д))

  if (цель?.kind === "binary" && цель.op === "gte" && ноль(цель.right)) {
    const известные = факты
      .filter((факт) => факт?.kind === "binary" && факт.op === "gte" && ноль(факт.right))
      .map((факт) => факт.left)
    if (неотрицательно(цель.left, известные)) return { ok: true, rule: ПРАВИЛО.nonneg, why: null }
    return {
      ok: false,
      rule: null,
      why:
        `${ПРАВИЛО.nonneg} не проходит: выражение случая собрано не только из неотрицательного.`
        + " Неотрицательны литерал не меньше нуля, терм с допущением «не меньше 0»,"
        + " их сумма и выбор из них; умножения и вычитания в этом списке нет и не будет"
        + " (в IEEE-754 «ноль умножить на бесконечность» даёт не число)",
    }
  }

  if (цель?.kind === "binary" && цель.op === "eq") {
    let левое = цель.left
    let правое = цель.right
    for (const факт of факты) {
      if (факт?.kind !== "binary" || факт.op !== "eq") continue
      левое = переписать(левое, факт.left, факт.right)
      правое = переписать(правое, факт.left, факт.right)
    }
    if (одинаковы(нормализовать(левое), нормализовать(правое))) {
      return { ok: true, rule: ПРАВИЛО.identity, why: null }
    }
    return {
      ok: false,
      rule: null,
      why:
        `${ПРАВИЛО.identity} не проходит: после переписки допущениями стороны равенства`
        + " остались разными термами. Ядро сличает синтаксически и равенства вычислений не решает",
    }
  }

  return {
    ok: false,
    rule: null,
    why:
      "у цели этого случая нет вида, к которому у ядра есть правило:"
      + " правил два — «не меньше 0» и «равно», и оба названы в отказе, чтобы список был виден целиком",
  }
}

/* ------------------------------------------------------------------ */
/* Правило 1: неотрицательность                                        */
/* ------------------------------------------------------------------ */

/**
 * Неотрицательно ли выражение — по построению, а не по значению.
 *
 * Свёртка по конечному дереву выражения: четыре случая, ни одного перебора.
 * Всё, что не подошло ни под один, неотрицательным НЕ считается — отказ по
 * умолчанию, потому что противоположное умолчание («не знаю, значит ладно») и
 * есть способ принять ложь.
 */
export function неотрицательно(выражение, известные) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && !Number.isNaN(выражение.value) && выражение.value >= 0
  }
  if ((известные ?? []).some((известное) => одинаковы(известное, выражение))) return true
  if (выражение.kind === "binary" && выражение.op === "add") {
    return неотрицательно(выражение.left, известные) && неотрицательно(выражение.right, известные)
  }
  if (выражение.kind === "if") {
    return неотрицательно(выражение.then, известные) && неотрицательно(выражение.else, известные)
  }
  return false
}

/* ------------------------------------------------------------------ */
/* Нормализация: три переписки, все три — чтение                       */
/* ------------------------------------------------------------------ */

/**
 * Нормальная форма выражения: развёрнуты `пусть`, разбор известного варианта и
 * условие с уже вычисленным условием.
 *
 * Останов виден глазами: каждая переписка либо уменьшает дерево, либо заменяет
 * имя на УЖЕ нормализованное поддерево, а вызовы не разворачиваются вовсе.
 * Поэтому нормализация — та же структурная свёртка, что и всё остальное ядро, и
 * счётчика шагов ей не нужно.
 */
export function нормализовать(выражение) {
  return шаг(выражение, new Map())
}

function шаг(узел, окружение) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => шаг(элемент, окружение))

  if (узел.kind === "var") {
    const значение = окружение.get(узел.name)
    return значение === undefined ? узел : значение
  }

  if (узел.kind === "let" && typeof узел.name === "string") {
    /* Значение нормализуется ДО подстановки: иначе одно и то же поддерево
       нормализовалось бы столько раз, сколько раз имя встретилось в теле. */
    const внутри = new Map(окружение)
    внутри.set(узел.name, шаг(узел.value, окружение))
    return шаг(узел.in, внутри)
  }

  if (узел.kind === "match") {
    const цель = шаг(узел.target, окружение)
    if (цель?.kind === "construct") {
      /* Ветвь ищется по ИМЕНИ КОНСТРУКТОРА, прочитанному с образца, а не по виду
         узла: у списка тот же самый вопрос записывается словами `случай пусто`,
         и разбирать его вторым способом значило бы получить второй ответ. */
      const ветвь = (узел.cases ?? []).find((случай) => образецВарианта(случай?.pattern)?.name === цель.variant)
      if (ветвь !== undefined) {
        const внутри = new Map(окружение)
        const поля = полями(цель)
        for (const [поле, имя] of Object.entries(образецВарианта(ветвь.pattern)?.bind ?? {})) {
          const значение = поля.get(поле)
          /* Поле, которого у конструкции нет, остаётся собой: это не ошибка ядра,
             а незаполненное поле, и подставлять вместо него нечего. */
          внутри.set(имя, значение === undefined ? { kind: "var", name: имя } : шаг(значение, окружение))
        }
        return шаг(ветвь.body, внутри)
      }
    }
    return {
      ...узел,
      target: цель,
      cases: (узел.cases ?? []).map((случай) => {
        const внутри = new Map(окружение)
        for (const имя of связанныеОбразцом(случай?.pattern)) внутри.delete(имя)
        return { ...случай, body: шаг(случай.body, внутри) }
      }),
    }
  }

  if (узел.kind === "if") {
    const условие = шаг(узел.cond, окружение)
    if (условие?.kind === "literal" && условие.value === true) return шаг(узел.then, окружение)
    if (условие?.kind === "literal" && условие.value === false) return шаг(узел.else, окружение)
    return { ...узел, cond: условие, then: шаг(узел.then, окружение), else: шаг(узел.else, окружение) }
  }

  if (узел.kind === "fold") {
    const внутри = new Map(окружение)
    if (typeof узел.acc === "string") внутри.delete(узел.acc)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return { ...узел, over: шаг(узел.over, окружение), init: шаг(узел.init, окружение), body: шаг(узел.body, внутри) }
  }

  /* `отобразить`/`отфильтровать` связывают элемент ровно так же, как свёртка —
     накопитель, и пропускать их значило бы подставлять снаружи внутрь чужого
     имени. Списочные функции библиотеки написаны этими двумя формами чаще
     всего («Без значения» — `отфильтровать элементы где эл → …`), так что до
     начальной алгебры списка промах здесь просто не мог сработать. */
  if (узел.kind === "map" || узел.kind === "filter") {
    const внутри = new Map(окружение)
    if (typeof узел.item === "string") внутри.delete(узел.item)
    return { ...узел, over: шаг(узел.over, окружение), body: шаг(узел.body, внутри) }
  }

  const собрано = {}
  for (const [ключ, значение] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? значение : шаг(значение, окружение)
  }
  return собрано
}

/* ------------------------------------------------------------------ */
/* Переписка равенством: один проход, слева направо                    */
/* ------------------------------------------------------------------ */

/**
 * Заменить все вхождения `откуда` на `куда` — ровно один проход.
 *
 * Один проход, а не до неподвижной точки: переписка равенством до неподвижной
 * точки не заканчивается на тождестве вида `х равно х`, а проверяльщик обязан
 * останавливаться всегда. Одного прохода хватает, потому что допущение индукции
 * говорит о ЧАСТИ значения, и вложенных вхождений одной части в другую у
 * конечного дерева не бывает.
 */
export function переписать(узел, откуда, куда) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (одинаковы(узел, откуда)) return куда
  if (Array.isArray(узел)) return узел.map((элемент) => переписать(элемент, откуда, куда))
  const собрано = {}
  for (const [ключ, значение] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? значение : переписать(значение, откуда, куда)
  }
  return собрано
}

/* ------------------------------------------------------------------ */
/* Мелочи                                                              */
/* ------------------------------------------------------------------ */

function ноль(узел) {
  return узел?.kind === "literal" && узел.value === 0
}

/** Поля конструкции варианта — картой, чтобы отсутствие поля отличалось от `undefined`. */
function полями(конструкция) {
  return new Map(Object.entries(конструкция?.fields ?? {}))
}
