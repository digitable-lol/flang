/**
 * Что известно неотрицательным — допущениями И объявлениями, одним списком.
 *
 * Два источника собираются здесь, а не в двух местах: правило одно, и список
 * известного у него один. Второе место, где тот же список собирался бы заново,
 * — это второй ответ на тот же вопрос.
 */
function известноеСнизу(факты, объявления) {
  return [
    ...(факты ?? [])
      .filter((факт) => факт?.kind === "binary" && факт.op === "gte" && ноль(факт.right))
      .map((факт) => факт.left),
    ...известноеПоТипу(объявления),
  ]
}

/**
 * Что известно неотрицательным ИЗ ОБЪЯВЛЕНИЙ — по одному факту на имя типа `нат`.
 *
 * Здесь ровно одно решение, и оно закрыто списком: натуральный тип даёт факт,
 * все прочие не дают ничего. Имена берутся у типизатора (`ИМЕНА_НАТ`), так что
 * четыре поверхности языка (`нат`, `nat`, `naturo`, `自然数`) читаются одинаково
 * и без второго словаря.
 *
 * ПОЧЕМУ ФАКТ ЗДЕСЬ — ИМЕННО «ИМЯ НЕ МЕНЬШЕ 0». `нат` обещает отрезок
 * [0, 2^53−1], то есть и дно, и потолок; эта функция отдаёт ДНО, потому что
 * правило неотрицательности спрашивает только про знак. Потолок отдаёт
 * `ограниченноеПоТипу` ниже — своим правилом и с другим списком случаев, и
 * разница между списками не косметическая: дно переживает сложение, потолок нет.
 * Одной функцией на оба факта здесь было бы «имя типа `нат` — это хорошо», а
 * такого правила у ядра нет.
 *
 * ГДЕ ЭТИ ФАКТЫ БЕЗОПАСНО ПРИМЕНЯТЬ. Только к именам, СВОБОДНЫМ в том месте,
 * где факт читается, и это не пожелание, а свойство `неотрицательно` ниже.
 * Связывателей в языке три, и с каждым она обходится названным способом:
 * `пусть` к её приходу уже развёрнут нормализацией; `разбор` даёт `false`
 * целиком; в `свёртка` она заходит (16 августа 2026, правило индукции по
 * списку) — и ровно поэтому ВЫЧЁРКИВАЕТ оттуда всякий факт, чьё имя свёртка
 * пересвязала. Значит всякое имя, до которого факт доходит, — то самое, что
 * объявлено в подписи, а не одноимённое связанное. Свойство держится тестом
 * («факт о внешнем имени не переживает пересвязки свёрткой»), а не обещанием:
 * пусти она факт под чужой связыватель — это была бы принятая ложь, и
 * контрпример у неё однострочный.
 *
 * @param {{name: string, type: object|null}[]} объявления
 * @returns {object[]} термы-имена, о которых известно «не меньше 0»
 */
export function известноеПоТипу(объявления) {
  const известные = []
  for (const объявление of объявления ?? []) {
    if (typeof объявление?.name !== "string") continue
    if (!сДномПоТипу(объявление.type)) continue
    известные.push({ kind: "var", name: объявление.name })
  }
  return известные
}

/**
 * Обещает ли объявленный тип ДНО 0 — и это спрашивается отдельно от потолка.
 *
 * Типов с дном в языке два, и список закрыт ровно ими: `нат` — отрезок
 * [0, 2^53−1], `вес` — отрезок [0, +∞]. Оба дна равны нулю, и записаны они в
 * одном месте (`types.mjs`), откуда имена сюда и импортированы.
 *
 * ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ `натуральный`. Потому что вопросов ДВА, и
 * ответы у них разные: у `вес` дно есть, а ПОТОЛКА НЕТ ВОВСЕ — `+∞` там
 * значение, а не край. Спроси правило ограниченности тем же предикатом — и ядро
 * доказало бы «вес не больше 2^53−1», то есть ложь о первой же бесконечности.
 * Поэтому `натуральный` остаётся при потолке и при посылке умножения (там нужна
 * конечность), а дно спрашивается здесь.
 *
 * ЭТО НЕ АКСИОМА. Факт ВЫВЕДЕН из двух проверяемых шагов: тип объявлен отрезком
 * с дном 0, и значение на такой позиции проверено типизатором при каждом вызове
 * (`годится` пропускает только вложенный отрезок; NaN не вложен ни в какой).
 * Опора названа вслух, как она названа у точного шага в `totality.mjs`: снимите
 * проверку типов — и это доказательство станет неверным.
 */
function сДномПоТипу(тип) {
  if (тип === null || тип === undefined) return false
  if (тип.kind !== "named" || typeof тип.name !== "string") return false
  return ИМЕНА_НАТ.includes(тип.name)
    || ИМЕНА_ВЕСА.includes(тип.name)
    || ИМЕНА_ТОЧНЫХ_ДЕСЯТИЧНЫХ.includes(тип.name)
}

/**
 * Объявлен ли тип натуральным — по написанному имени, тем же словарём, каким его
 * читает типизатор.
 *
 * Узел `named` — это то, что строит парсер: имена уточнённых типов НЕ ключевые
 * слова (`types.mjs`, «Имена уточнённых типов»), и в позиции типа `нат`
 * разбирается ровно так же, как «Возможно» или любой объявленный тип.
 * Объявить свой тип с таким именем и подменить смысл нельзя: `namedOrScalar`
 * смотрит в словарь ДО объявлений модуля, поэтому здесь и там `нат` — одно и то
 * же.
 */
function натуральный(тип) {
  if (тип === null || тип === undefined) return false
  if (тип.kind !== "named") return false
  /* Точный десятичный стоит здесь по ОТРЕЗКУ, а не по родству имён: `сотых` —
     это [0, 2^53−1] ровно как `нат` (`types.mjs`, `СОТЫХ`), и оба факта этого
     отрезка — дно и потолок — читаются с него теми же двумя правилами. Масштаб
     на знак и на границы не влияет вовсе: он единица измерения, а не число. */
  return ИМЕНА_НАТ.includes(тип.name) || ИМЕНА_ТОЧНЫХ_ДЕСЯТИЧНЫХ.includes(тип.name)
}

/**
 * Обещает ли объявленный тип ЦЕЛОЕ значение — третий факт той же подписи.
 *
 * Отдельной функцией и отдельным списком, потому что вопрос третий. Дно
 * спрашивает про знак, потолок — про величину, а этот — про сетку: `принимает
 * сумма: сотых` говорит «сумма есть целое число копеек», и без этого слова
 * правило остатка ниже ложно на первом же дробном входе.
 *
 * Список шире, чем у двух других: целость обещают ВСЕ четыре точных имени, а
 * `целое` — [−2^53+1, 2^53−1] — обещает её, не обещая знака. Ровно поэтому
 * третий факт и не сведён с первым: разные списки и разные правила.
 */
function целостный(тип) {
  if (тип === null || тип === undefined) return false
  if (тип.kind !== "named") return false
  return ИМЕНА_НАТ.includes(тип.name)
    || ИМЕНА_ЦЕЛОГО.includes(тип.name)
    || ИМЕНА_ТОЧНЫХ_ДЕСЯТИЧНЫХ.includes(тип.name)
}

/**
 * Имена, о которых из объявлений известно «это конечное целое».
 *
 * Тот же приём, что у `известноеПоТипу`: по одному факту на имя, и ни одного
 * перебора. КОНЕЧНОСТЬ здесь не приписка, а половина утверждения: все четыре
 * точных имени объявлены отрезком внутри [−(2^53−1), 2^53−1], значит `+∞` и
 * `NaN` в них не помещаются. Без этой половины правило остатка снова ложно:
 * `+∞ остаток от 100` — это NaN, а NaN не меньше нуля и не больше 99.
 *
 * @param {{name: string, type: object|null}[]} объявления
 * @returns {object[]} термы-имена, о которых известно «конечное целое»
 */
export function целоеПоТипу(объявления) {
  const известные = []
  for (const объявление of объявления ?? []) {
    if (typeof объявление?.name !== "string") continue
    if (!целостный(объявление.type)) continue
    известные.push({ kind: "var", name: объявление.name })
  }
  return известные
}

/**
 * Конечное ли целое это выражение — по построению, как и два соседних правила.
 *
 * СПИСОК НАРОЧНО КОРОТКИЙ, и короток он ради конечности, а не ради целости.
 * Сложение и умножение целых дают целое, но НЕ ОБЯЗАТЕЛЬНО конечное: в IEEE-754
 * `1e308 плюс 1e308` — это `+∞`, а `+∞` целым не является. Взяв их сюда, ядро
 * получило бы посылку «конечное целое», ложную на переполнении, и правило
 * остатка стало бы доказывать ложь ровно там, где переполнение и случается.
 * Поэтому здесь только то, конечность чего видна прямо: конечный целый литерал,
 * имя с объявленным точным типом, выбор из таких и остаток от таких.
 *
 * Правый операнд остатка обязан быть НЕНУЛЕВЫМ ЛИТЕРАЛОМ: `а остаток от 0` —
 * это NaN, и «делитель не ноль» ядру взять неоткуда, кроме как из написанного
 * числа. Имя типа `нат` нулём быть вправе.
 */
export function конечноеЦелое(выражение, известные) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") return целыйЛитерал(выражение)
  if ((известные ?? []).some((известное) => одинаковы(известное, выражение))) return true
  if (выражение.kind === "if") {
    return конечноеЦелое(выражение.then, известные) && конечноеЦелое(выражение.else, известные)
  }
  if (выражение.kind === "binary" && выражение.op === "mod") {
    return конечноеЦелое(выражение.left, известные) && ненулевойЦелыйЛитерал(выражение.right)
  }
  return false
}

/** Конечный целый литерал — то, из чего конечность видна прямо в тексте. */
function целыйЛитерал(узел) {
  return узел?.kind === "literal" && typeof узел.value === "number" && Number.isInteger(узел.value)
}

/** Он же, но не ноль: делитель нулём быть не вправе — иначе остаток это NaN. */
function ненулевойЦелыйЛитерал(узел) {
  return целыйЛитерал(узел) && узел.value !== 0
}

/**
 * Что известно ограниченным сверху КОНЕЧНОЙ границей — какой именно, неважно.
 *
 * Это третий список известного, и он отвечает на СВОЙ вопрос, а не на вопрос
 * `известноеСверху`. Тому нужно «не больше П» для конкретного П из цели; правилу
 * умножения нужно только одно — что величина КОНЕЧНА, потому что бесконечность
 * есть единственный способ получить NaN из произведения неотрицательных.
 * Отсюда и разница в отборе: допущение `Т не больше 1e300` для цели с потолком
 * 2^53−1 бесполезно, а для умножения годится вполне — оно исключает `+∞`.
 *
 * Из объявлений факт берётся тем же `ограниченноеПоТипу` и с потолком типа: `нат`
 * есть [0, `ТОЧНЫЙ_ПОТОЛОК`], и второй раз это число здесь не переписано.
 */
function конечноеСверху(факты, объявления) {
  return [
    ...(факты ?? [])
      .filter((факт) => факт?.kind === "binary" && факт.op === "lte" && конечныйЛитерал(факт.right))
      .map((факт) => факт.left),
    ...ограниченноеПоТипу(объявления, ТОЧНАЯ_СЕТКА.верх),
  ]
}

/**
 * Лежит ли выражение в отрезке [0, КОНЕЧНОЕ] — посылка правила умножения.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ СВЁРТКА, А НЕ ДВА ВЫЗОВА ПРЕЖНИХ. Вопрос здесь ОДИН и он
 * составной: величина обязана быть и неотрицательной, и конечной. Спросить это
 * двумя отдельными свёртками нельзя — они разошлись бы на составных выражениях:
 * `н плюс м` неотрицательно и `н плюс м` при двух `нат` ограничено ничем, потому
 * что сумма переполняется в `+∞`. Свёртка, отвечающая «да» на такое, отдала бы
 * умножению бесконечный сомножитель, и `0 умножить на (н плюс м)` дало бы NaN.
 *
 * ПОЭТОМУ СПИСОК СЛУЧАЕВ КОРОЧЕ ОБОИХ СОСЕДЕЙ, и короче он намеренно:
 *
 *   конечный литерал ≥ 0                                  в отрезке
 *   терм, о котором известно И дно, И конечный потолок     в отрезке
 *   `если у то а иначе б` при обоих в отрезке              в отрезке
 *
 * Ни сложения, ни умножения: обе операции выводят из отрезка переполнением, а
 * `+∞` — ровно то значение, ради исключения которого посылка и заведена.
 * Вычитания нет по другой причине: оно выводит из отрезка вниз (`2 минус 3`).
 * Выбор берётся потому, что он не арифметика: значение равно одной из ветвей,
 * обе в отрезке — значит и выбор в нём, и никакого округления не происходит.
 *
 * ПОД СВЯЗЫВАТЕЛИ НЕ СПУСКАЕТСЯ — как и оба соседа, и по той же причине: факт об
 * имени параметра, положенный на одноимённое связанное имя, был бы принятой ложью.
 *
 * @param {object} выражение
 * @param {object[]} снизу термы, о которых известно «не меньше 0»
 * @param {object[]} конечные термы, о которых известно «не больше конечного»
 */
export function вОтрезке(выражение, снизу, конечные) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    /* `Number.isFinite` отсекает и NaN, и обе бесконечности разом — оба вида
       значений, на которых правило умножения было бы ложным. */
    return typeof выражение.value === "number" && Number.isFinite(выражение.value) && выражение.value >= 0
  }
  const знаком = (список) => (список ?? []).some((известное) => одинаковы(известное, выражение))
  if (знаком(снизу) && знаком(конечные)) return true
  if (выражение.kind === "if") {
    return вОтрезке(выражение.then, снизу, конечные) && вОтрезке(выражение.else, снизу, конечные)
  }
  return false
}

/**
 * Что известно СТРОГО положительным — и только фактами, названными в посылке.
 *
 * Четвёртый список известного, и он единственный, в который НЕ попадает ни одно
 * объявление. Это не упущение и не осторожность: строгой положительности не
 * обещает ни один тип языка. `нат` — это отрезок [0, 2⁵³−1], и ноль в нём живёт;
 * прочти ядро `нат` как «больше нуля» — оно доказывало бы ложь на первом же
 * `«Факториал» от 0`.
 *
 * Годится факт вида `Т больше К`, где `К` — конечный литерал не меньше нуля:
 * `Т > К ≥ 0` даёт `Т > 0`, и весь вывод здесь — это сравнение литерала с нулём.
 * Сравнение идёт на литералах, а не на термах, по той же причине, что у
 * `известноеСверху`: границу, записанную выражением, ядро читать не умеет и не
 * должно — это был бы решатель, которого у него нет.
 *
 * ОТКУДА ТАКОЙ ФАКТ ВООБЩЕ БЕРЁТСЯ. Из посылки принципа по отрезку: в ветви
 * СПУСКА условие дна ложно, и ядро кладёт в посылку факт `п больше верх`
 * (`initial.mjs`). Больше ниоткуда — и это стоит проверять изъятием, а не
 * помнить: правило, у которого посылку неоткуда взять, ничего не доказывает.
 */
function строгоПоложительное(факты) {
  return (факты ?? [])
    .filter((факт) => факт?.kind === "binary" && факт.op === "gt" && конечныйЛитерал(факт.right))
    .filter((факт) => факт.right.value >= 0)
    .map((факт) => факт.left)
}

/**
 * Лежит ли выражение в отрезке (0, КОНЕЧНОЕ] — посылка второго случая умножения.
 *
 * Отличие от `вОтрезке` ровно одно и всё: ноль сюда не попадает. Ради этого
 * список случаев и заведён отдельным, а не флагом у соседа — ноль и не-ноль
 * различаются в КАЖДОМ случае, а не в одном:
 *
 *   конечный литерал > 0                                      в (0, конечное]
 *   терм, о котором известно И «больше К ≥ 0», И «не больше конечного»
 *   `если у то а иначе б` при обоих в (0, конечное]           в (0, конечное]
 *
 * Ни сложения, ни умножения, ни вычитания — по тем же трём доводам, что у
 * `вОтрезке`: сумма и произведение выводят из отрезка вверх переполнением, а
 * вычитание вниз (`2 минус 3`), и здесь ещё и через ноль (`2 минус 2`).
 * Выбор берётся потому, что он не арифметика: значение равно одной из ветвей.
 *
 * ПОД СВЯЗЫВАТЕЛИ НЕ СПУСКАЕТСЯ — как и все соседи, и по той же причине.
 *
 * @param {object} выражение
 * @param {object[]} положительные термы, о которых известно «больше 0»
 * @param {object[]} конечные термы, о которых известно «не больше конечного»
 */
export function вОтрезкеБезНуля(выражение, положительные, конечные) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && Number.isFinite(выражение.value) && выражение.value > 0
  }
  const знаком = (список) => (список ?? []).some((известное) => одинаковы(известное, выражение))
  if (знаком(положительные) && знаком(конечные)) return true
  if (выражение.kind === "if") {
    return вОтрезкеБезНуля(выражение.then, положительные, конечные)
      && вОтрезкеБезНуля(выражение.else, положительные, конечные)
  }
  return false
}

/**
 * Неотрицательно ли выражение — по построению, а не по значению.
 *
 * Свёртка по конечному дереву выражения: пять случаев, ни одного перебора.
 * Всё, что не подошло ни под один, неотрицательным НЕ считается — отказ по
 * умолчанию, потому что противоположное умолчание («не знаю, значит ладно») и
 * есть способ принять ложь.
 *
 * Имя, объявленное как `нат`, попадает сюда уже фактом в `снизу`
 * (`известноеПоТипу`), а не отдельным случаем: источник у факта другой, а
 * правило — то же самое, и разводить их на две ветви значило бы иметь два
 * правила неотрицательности вместо одного.
 *
 * УМНОЖЕНИЕ СТОИТ НА ДРУГОЙ ПОСЫЛКЕ, ЧЕМ СЛОЖЕНИЕ, и это главное место функции.
 * Сложению хватает дна: сумма двух значений из [0, +∞] снова в [0, +∞], и
 * переполнение в `+∞` знака не портит. Умножению дна МАЛО: `0 умножить на +∞`
 * даёт NaN, а `+∞ не меньше 0` — истинная посылка, то есть дно бесконечности не
 * исключает.
 *
 * Поэтому посылок у умножения ДВЕ, и ни одна не поглощает другую:
 *
 *   ОБА в [0, конечное]. Тогда бесконечности нет ни у одного сомножителя, и
 *     `0 × ∞` взяться неоткуда. Так берётся `н умножить на м` при двух `нат`.
 *   ОДИН в (0, конечное], ВТОРОЙ просто не меньше 0. Тогда нуля нет у первого, а
 *     бесконечности у него нет по конечности — и `0 × ∞` снова взяться неоткуда,
 *     хотя о втором сомножителе известно одно только дно. Так берётся
 *     `н умножить на («Факториал» от (н минус 1))`: о результате вызова себя же
 *     нет и не может быть верхней границы (факториал переполняется в `+∞`), а
 *     `н больше 1` в ветви спуска — прочитанный факт посылки.
 *
 * Порядок проверок значения не имеет, а вот НЕСИММЕТРИЧНОСТЬ второй посылки
 * имеет: спрашивается она у каждого сомножителя по очереди, потому что автор
 * вправе написать произведение в любом порядке, а правило от порядка не зависит.
 *
 * @param {object} выражение
 * @param {object[]} снизу термы, о которых известно «не меньше 0»
 * @param {object[]} [конечные] термы, о которых известно «не больше конечного».
 *   Не дали — умножение не выводится вовсе: без второй границы правило ложно, и
 *   умолчание здесь «нечего», а не «ладно».
 * @param {object[]} [положительные] термы, о которых известно «больше 0». Не
 *   дали — второй посылки умножения нет, и ядро остаётся тем, каким было.
 */
export function неотрицательно(выражение, снизу, конечные = [], положительные = [], целые = []) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && !Number.isNaN(выражение.value) && выражение.value >= 0
  }
  if ((снизу ?? []).some((известное) => одинаковы(известное, выражение))) return true
  if (выражение.kind === "builtin") return неотрицательнаяФорма(выражение)
  if (выражение.kind === "binary" && выражение.op === "add") {
    return неотрицательно(выражение.left, снизу, конечные, положительные, целые)
      && неотрицательно(выражение.right, снизу, конечные, положительные, целые)
  }
  if (выражение.kind === "binary" && выражение.op === "mul") {
    const левое = выражение.left
    const правое = выражение.right
    if (вОтрезке(левое, снизу, конечные) && вОтрезке(правое, снизу, конечные)) return true
    if (вОтрезкеБезНуля(левое, положительные, конечные) && неотрицательно(правое, снизу, конечные, положительные, целые)) {
      return true
    }
    if (вОтрезкеБезНуля(правое, положительные, конечные) && неотрицательно(левое, снизу, конечные, положительные, целые)) {
      return true
    }
    return false
  }
  /* ОСТАТОК. `а остаток от Л` при неотрицательном КОНЕЧНОМ ЦЕЛОМ `а` и ненулевом
     целом литерале `Л` неотрицателен — теорема о IEEE-754: остаток вычисляется
     ТОЧНО и повторяет знак делимого. Обе посылки несут вес: без конечности
     `+∞ остаток от 100` даёт не-число, без ненулевого делителя — тоже. */
  if (выражение.kind === "binary" && выражение.op === "mod") {
    return неотрицательно(выражение.left, снизу, конечные, положительные, целые)
      && конечноеЦелое(выражение.left, целые)
      && ненулевойЦелыйЛитерал(выражение.right)
  }
  if (выражение.kind === "if") {
    return неотрицательно(выражение.then, снизу, конечные, положительные, целые)
      && неотрицательно(выражение.else, снизу, конечные, положительные, целые)
  }
  /* РАЗБОР — тот же довод, что у выбора, и та же строка вычислителя: значение
     есть значение тела ровно одной ветви, третьего нет. Про знак этого хватает
     целиком: уравнение ветви («разбираемое имя — это конструктор») знаку не
     нужно, оно нужно только сравнению с границей (`поРазбору` ниже).
     ИЗВЕСТНОЕ О ПЕРЕСВЯЗАННЫХ ИМЕНАХ ВЫЧЁРКИВАЕТСЯ — по той же причине, по
     какой его вычёркивает свёртка: факт «х не меньше 0» о параметре не говорит
     ничего о части значения, названной в образце тем же словом. */
  if (выражение.kind === "match") {
    const случаи = выражение.cases ?? []
    if (случаи.length === 0) return false
    return случаи.every((случай) => {
      const связанные = new Set(связанныеОбразцом(случай?.pattern))
      const снаружи = (список) => (список ?? []).filter((факт) => !упоминаетИмена(факт, связанные))
      return неотрицательно(случай?.body, снаружи(снизу), снаружи(конечные), снаружи(положительные), снаружи(целые))
    })
  }
  if (выражение.kind === "fold") return неотрицательнаяСвёртка(выражение, снизу, конечные, положительные)
  return false
}

/**
 * Встроенная форма, чей результат неотрицателен ПРИ ЛЮБОМ аргументе.
 *
 * Аргументы здесь не смотрятся вовсе, и это не упущение: в таблице лежат ровно
 * те формы, у которых тип результата от аргументов не зависит (`types.mjs`,
 * `ТИП_РЕЗУЛЬТАТА_ФОРМЫ`). Форма, чей результат зависит от входа, в таблицу не
 * попадает — значит и здесь о ней ответ один: нет.
 *
 * Аргумент негодного типа формы не пропускают: `длина` от числа прекращает
 * вычисление отказом, результата не возникает вовсе, и говорить о его знаке
 * нечего. Утверждение «результат не меньше 0» о значении, которого нет, не
 * ложно и не истинно — оно не высказано.
 */
function неотрицательнаяФорма(узел) {
  const канон = каноническаяФорма(узел?.name)
  if (typeof канон !== "string") return false
  if (!Object.hasOwn(ТИП_РЕЗУЛЬТАТА_ФОРМЫ, канон)) return false
  return отНуля(ТИП_РЕЗУЛЬТАТА_ФОРМЫ[канон])
}

/**
 * Обещает ли ТИП, что значение не меньше нуля.
 *
 * Читается ровно одно поле — нижняя граница отрезка, — и читается так же, как
 * его пишет типизатор. `−0` отсеивается отдельно и по той же причине, по какой
 * его отсеивает `отрезок` в `types.mjs`: `−0 >= 0` в JavaScript истинно, и без
 * этой проверки границу можно было бы получить из округления отрицательного.
 */
function отНуля(тип) {
  if (тип?.kind !== "number") return false
  if (typeof тип.низ !== "number" || Number.isNaN(тип.низ)) return false
  return тип.низ >= 0 && !Object.is(тип.низ, -0)
}

/**
 * Свёртка: индукция по списку двумя посылками — начало и шаг.
 *
 * Доказательство правила целиком стоит в шапке файла. Здесь — три отказа, и
 * каждый из них закрывает способ получить ложь:
 *
 *   1. имена накопителя и элемента обязаны быть именами и быть РАЗНЫМИ:
 *      вычислитель связывает элемент ПОСЛЕ накопителя, и при одном имени тело
 *      говорит об элементе, а факт лёг бы на накопитель;
 *   2. начало обязано быть неотрицательным по ВНЕШНИМ фактам — оно и вычисляется
 *      снаружи, до первого шага;
 *   3. известное о внешних именах, которые свёртка ПЕРЕСВЯЗАЛА, вычёркивается.
 *      Факт «х не меньше 0» о параметре не говорит ничего об элементе списка,
 *      названном тем же `х`, — а именно так выглядит принятая ложь.
 *
 * Факта об элементе не добавляется ни одного, и это не осторожность, а условие
 * правды: вывод обязан быть верен при любом элементе, потому что элементы —
 * содержимое списка, о котором не известно ничего.
 *
 * ПРИ СЛИЯНИИ С ПРАВИЛОМ УМНОЖЕНИЯ (`work/kernel-mul-field`) — ДВЕ СТРОКИ, И
 * ОБЕ ОБЯЗАТЕЛЬНЫ. Там у `неотрицательно` появляется ВТОРОЙ список фактов
 * (`конечные`: термы, о которых известно «не больше конечного»). Его надо
 * вычёркивать здесь ТЕМ ЖЕ `связаноВнутри` — иначе факт о внешнем имени
 * переживёт пересвязку, и дыра будет ровно та, которую эта функция закрывает.
 * И НАКОПИТЕЛЬ В `конечные` НЕ КЛАДЁТСЯ: индукция даёт про него «не меньше 0»,
 * а конечности не даёт — сложение конечных переполняется в `+∞` законно.
 * Положи его туда — правило умножения стало бы ложным на `+∞ умножить на 0`.
 */
function неотрицательнаяСвёртка(свёртка, снизу, конечные, положительные) {
  const накопитель = свёртка.acc
  const элемент = свёртка.item
  if (typeof накопитель !== "string" || typeof элемент !== "string") return false
  if (накопитель === элемент) return false
  if (!неотрицательно(свёртка.init, снизу, конечные, положительные)) return false
  const снаружи = (список) => (список ?? []).filter((факт) => !связаноВнутри(факт, накопитель, элемент))
  /* Накопитель кладётся ТОЛЬКО в «снизу»: индукция даёт про него «не меньше 0» и
     НЕ даёт конечности — сложение конечных переполняется в `+∞` законно. Положи
     его в «конечные» — и правило умножения стало бы ложным на `+∞ умножить на 0`.
     Строгой положительности индукция не даёт тем более: начало бывает нулём. */
  const внутри = [...снаружи(снизу), { kind: "var", name: накопитель }]
  return неотрицательно(свёртка.body, внутри, снаружи(конечные), снаружи(положительные))
}

/** Упоминает ли известный терм хоть одно из пересвязанных имён. */
function упоминаетИмена(терм, имена) {
  if (имена.size === 0) return false
  const свои = new Set()
  собратьИмена(терм, свои)
  for (const имя of свои) if (имена.has(имя)) return true
  return false
}

/** Упоминает ли известный терм хоть одно из двух пересвязанных имён. */
function связаноВнутри(терм, накопитель, элемент) {
  const имена = new Set()
  собратьИмена(терм, имена)
  return имена.has(накопитель) || имена.has(элемент)
}

