/**
 * Цель дословно совпала с одним из допущений — значит она выведена.
 *
 * ── ПОЧЕМУ ЭТО ТЕОРЕМА, А НЕ АКСИОМА ────────────────────────────────────────
 * Список `АКСИОМЫ` пуст, и это правило его не открывает.
 *
 * Сначала надо отвести подозрение в РЕФЛЕКСИВНОСТИ, потому что подозрение
 * законное. Правило неотрицательности приехало с разбором про NaN: «Е не больше
 * Е» в IEEE-754 НЕ теорема — на `не число` сравнение ложно, и рефлексивность
 * порядка держится только посылкой «не NaN». Похоже, что «цель есть допущение» —
 * та же рефлексивность, только про утверждения, и что у неё обязан быть свой
 * NaN. Его нет, и разница точная: рефлексивность порядка говорит нечто ОБ
 * ОПЕРАЦИИ `не больше`, применённой к двум копиям значения, и потому зависит от
 * того, как эта операция ведёт себя на краю носителя. Правило ниже не применяет
 * НИ ОДНОЙ операции языка. Оно говорит, что одно и то же выражение имеет одно и
 * то же значение, — и `не число` в это утверждение попасть неоткуда: сравнения в
 * нём нет вовсе, а `одинаковы` сличает ДЕРЕВЬЯ, а не числа (и числа внутри
 * деревьев — через `===`, чей ответ на NaN тот же самый с обеих сторон).
 *
 * Само доказательство после этого в две строки. Допущение `A` значит здесь ровно
 * одно: «выражение `A` при данном входе вычисляется в `да`» — признаком его
 * объявил не автор, а типизатор (и постусловие, и предусловие, и утверждение
 * шага обязаны быть признаком). Цель `A` значит то же самое о том же выражении.
 * Значит при истинном допущении цель истинна — и не «следует», а СОВПАДАЕТ: это
 * одно утверждение, записанное дважды. Теоремой это делает то, что совпадение
 * ПРОВЕРЯЕТСЯ узел в узел, а не объявляется.
 *
 * ── ЧЕМ ДЕРЖИТСЯ, И ОПОРА НАЗВАНА ВСЛУХ ─────────────────────────────────────
 * Посылок у доказательства две, и обе уже несут вес в этом ядре — то есть новых
 * допущений правило не заводит:
 *
 *   (1) ОДНО ОКРУЖЕНИЕ. «Одно и то же выражение» значит «в одной и той же
 *       среде»: имена цели и имена допущения обязаны означать одно. Требование
 *       не новое — на нём стоит правило тождества, переписывающее стороны ЦЕЛИ
 *       равенствами ИЗ ДОПУЩЕНИЙ, и на нём же стоит разбор по условию («язык
 *       чист, поэтому одно и то же выражение в одном и том же окружении имеет
 *       одно и то же значение»). Ломается оно ровно одним способом — ЗАХВАТОМ
 *       ИМЕНИ, — и захват стережётся не здесь, а там, где возникает: в
 *       подстановке (`initial.mjs`, `подставить`) и в развёртке (ОГРАНИЧИТЕЛЬ 4
 *       ниже). Обе сторожевые проверки написаны по уликам и стоят подделками
 *       в `flang/test/proof-soundness.test.mjs`. Снимите любую — и это
 *       доказательство станет неверным: это объявленная зависимость одного места
 *       от другого, как у точного шага в `totality.mjs`, а не скрытое допущение.
 *   (2) ДОПУЩЕНИЕ ДЕЙСТВИТЕЛЬНО ДОПУЩЕНО. Список `допущения` ядро не принимает
 *       от автора на слово ни одним путём: посылку индукции оно СТРОИТ само
 *       (`по предположению` — «единственный способ не дать назвать
 *       предположением что угодно»), а предусловие берётся с объявления
 *       `требует` и снимается на КАЖДОМ месте вызова (`снятьПредусловия`).
 *       Круга нет и завестись ему негде: доказываемое сейчас постусловие в
 *       `допущения` не попадает, а ссылку на себя отдельно отвергает
 *       `по свойству`.
 *
 * БЕЗ ВТОРОЙ ПОСЫЛКИ это было бы ровно той аксиомой, из-за которой список аксиом
 * пуст: правилу, которому «допущение» подаёт сам автор, доказуемо что угодно,
 * начиная с `нет`. Поэтому подделка на правило — программа, где `требует`
 * объявлено ложью, — обязана краснеть на месте ВЫЗОВА, а не проходить здесь.
 *
 * ── ЧТО НЕ ЗАСЧИТЫВАЕТСЯ ────────────────────────────────────────────────────
 * Цель, которой нет вовсе (`null`/`undefined` после нормализации), не совпадает
 * ни с чем: `одинаковы(undefined, undefined)` истинно, и без этой проверки
 * пустая цель закрывалась бы пустым допущением. Узел здесь обязан быть узлом.
 */
function естьДопущением(цель, факты) {
  if (цель === null || цель === undefined || typeof цель !== "object") return false
  return факты.some((факт) => одинаковы(факт, цель))
}

