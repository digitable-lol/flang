/**
 * reduce.mjs — сведение заключения посылки к допущениям индукции.
 *
 * ── Что это и чем оно НЕ является ───────────────────────────────────────────
 * Здесь три решающих правила и одна нормализация, и ни одного поиска. Решающее
 * правило — это не тактика: тактика ворочает состояние цели перебором и потому
 * нетотальна, а правило ниже — структурная свёртка по выражению, которая
 * отвечает да или нет и всегда останавливается. Разница ровно та же, что между
 * `разбор` и циклом с условием: у первого число ветвей известно из объявления.
 *
 * Все три правила закрыты списком и печатаются в отказе поимённо. Правило,
 * которое нельзя перечислить, ничем не отличается от «ядро решило, что так
 * можно».
 *
 * ── Нормализация: развёртка того, что уже написано ──────────────────────────
 * Четыре переписки, и все четыре — чтение, а не вывод:
 *
 *   `пусть и равно З; Т`      →  Т, в котором `и` заменено на З
 *   `разбор (вариант «C» …)`  →  тело ветви «C» со связанными полями
 *   `если да то А иначе Б`    →  А (условие уже вычислилось в значение)
 *   `«Ф» от а₁ … аₙ`          →  тело «Ф», в котором параметры стали аргументами
 *
 * ── Четвёртая переписка: развёртка ОПРЕДЕЛЕНИЯ ──────────────────────────────
 * Здесь до этой работы стояло «ни одна из переписок не разворачивает ВЫЗОВ
 * функции, и это главное ограничение файла». Ограничение стоило двух утверждений
 * корпуса, и обе улики были измерены, а не вспомнены:
 *
 *   «высота копии равна высоте оригинала» (`proof/examples/stack.flang`) —
 *   шаг требует знать, чему равна «Высота» НА КОНСТРУКТОРЕ, и без этого стороны
 *   равенства остаются разными термами;
 *
 *   «глубина дерева неотрицательна» (`stdlib/tree.flang`) — шаг упирается в
 *   `«Глубже» от двух допущений`, и о результате чужой функции ядро не знает
 *   ничего, хотя тело её написано в трёх строках рядом.
 *
 * Развёртка — НЕ вычисление и не новая вера. `«Ф» от а` и тело «Ф» с
 * подставленным `а` — это одно и то же выражение, записанное дважды: так
 * определил автор, и типизатор эту подпись уже проверил. Ядро читает написанное
 * ровно так же, как читает ветвь `разбор` по известному конструктору. Список
 * `АКСИОМЫ` от этого не пополнился ни на строку.
 *
 * ── Чем развёртка ограничена: четыре ограничителя, каждый назван ────────────
 * Бесконечная развёртка рекурсии — главная опасность этой переписки: у
 * `«Высота» от м` при неизвестном `м` нормальной формы нет, и разворачивать её
 * значило бы не заканчиваться. Поэтому у развёртки четыре ограничителя, и
 * каждый из них — отдельная строка в коде и отдельный тест:
 *
 *   1. ТОЛЬКО ТОТАЛЬНОЕ. Разворачивается вызов функции, объявленной
 *      `тотальная`. Обещание завершения даёт не ядро — его доказал анализ
 *      завершаемости до всякого доказательства. Подставить вместо вызова тело,
 *      которого вызов, может быть, никогда не досчитает, значило бы говорить о
 *      значении, которого нет.
 *
 *   2. ТОЛЬКО ДВА ВИДА ВЫЗОВА, и список закрыт:
 *        «по конструктору» — тело есть `разбор <параметр>`, а на месте этого
 *          параметра стоит КОНСТРУКТОР. Развёртка тогда не вычисляет, а читает
 *          ветвь, которую выбрало объявление, и конструктор при этом СЪЕДАЕТСЯ.
 *          Рекурсивный вызов в выбранной ветви стоит уже на ЧАСТИ значения —
 *          на имени, а не на конструкторе, — и потому второй раз не
 *          разворачивается. Ровно один виток, и он тот самый, который нужен
 *          шагу индукции;
 *        «плоское определение» — в теле нет ни одного вызова. Такая развёртка
 *          новых вызовов не заводит: всё, что в ней есть, уже стояло в
 *          аргументах. Именно этим разворачивается `«Глубже»`.
 *      Всё остальное остаётся непрозрачным термом — и именно поэтому нужны
 *      допущения индукции: они и есть то, что о непрозрачном терме известно.
 *
 *   3. НАЗВАННЫЙ ПРЕДЕЛ `ПРЕДЕЛ_РАЗВЁРТКИ`. Правило «по конструктору» съедает
 *      конструктор, но тело вправе конструктор и ПОСТРОИТЬ (`«Ф» от (вариант
 *      «Звено» с хвост равным х)`), и тогда витку не будет конца. Предел стоит
 *      именно поэтому, он назван числом, и достижение его не проходит молча:
 *      развёртка останавливается, а отказ `свести` говорит, что предел достигнут.
 *      Соврать предел не может: развёртка только ЧИТАЕТ определение, поэтому
 *      остановиться раньше — значит доказать меньше, а не доказать ложное.
 *
 *   4. ЗАХВАТ ИМЕНИ. Подстановка аргументов идёт под связыватели тела, и если в
 *      развёрнутом теле остался связыватель, связывающий имя, свободное в
 *      аргументе, ядро развёртку ОТМЕНЯЕТ. Не переименовывает: переименование —
 *      это выдумывание имён, которых автор не писал, а сличать с допущениями
 *      надо ровно те термы, которые он написал. Молча переименованная чужая
 *      переменная — самая дорогая ошибка проверяльщика, и цена отказа здесь
 *      несравнимо ниже.
 *
 * Останов виден глазами и без счётчика шагов: `пусть` уменьшает дерево, разбор
 * известного конструктора выбирает ветвь, условие с вычисленным условием
 * выбирает ветвь, а развёртка либо съедает конструктор, либо не заводит новых
 * вызовов — и над всем этим стоит названный предел.
 *
 * ── Правило 1: неотрицательность по построению ──────────────────────────────
 * Цель вида `Е не меньше 0` выводится, если `Е` собрано из неотрицательных:
 *
 *   литерал ≥ 0                                    неотрицателен
 *   терм, о котором ЕСТЬ допущение `… не меньше 0` неотрицателен
 *   имя, ОБЪЯВЛЕННОЕ типом `нат`                   неотрицательно
 *   `а плюс б` при неотрицательных `а` и `б`       неотрицателен
 *   `если у то а иначе б` при неотрицательных обоих неотрицателен
 *   `а умножить на б`, когда `а` и `б` лежат в ОТРЕЗКЕ [0, конечное] — неотрицателен
 *
 * ── Третья строка: объявленный тип — это ФАКТ, а не подсказка ───────────────
 * До неё у ядра было два источника известного — литерал и допущение индукции, —
 * и оба приезжали изнутри доказательства. Объявление параметра не приезжало
 * никак, и постусловие «результат не меньше 0» у функции, складывающей два
 * `нат`, стояло в ведомости сеткой примеров: посчитанным на трёх входах из
 * 2^53 × 2^53, хотя доказуемым одним сложением.
 *
 * Это НЕ аксиома и не новое доверие. `нат` — не имя, а отрезок [0, 2^53−1]
 * (`types.mjs`, `NAT`): написав `принимает первое: нат`, автор написал факт
 * «первое не меньше 0», и типизатор его уже проверил на каждом вызове. Ядро
 * этот факт не выдумывает и не выводит — оно ЧИТАЕТ его там, где он написан.
 * Правило шага «без названного факта — отказ» тем самым не нарушено: факт
 * назван подписью функции.
 *
 * ЧТО ФАКТОМ НЕ СТАНОВИТСЯ. Только `нат`, и список имён берётся из словаря
 * типизатора (`ИМЕНА_НАТ`), а не переписывается здесь: разойдись два списка —
 * ядро сочло бы натуральным то, что типизатор натуральным не считает.
 * `целое` — это [−2^53+1, 2^53−1], `число` — вообще всё, включая NaN и −∞:
 * ни то, ни другое ничего о знаке не обещает, и трактовать их как факт значило
 * бы принимать ложь на первом же отрицательном входе.
 *
 * ПОЧЕМУ ЭТО ПРАВДА В ЧИСЛАХ FLANG, А НЕ ТОЛЬКО В МАТЕМАТИКЕ. Числа языка —
 * IEEE-754, и в них ложны почти все привычные аксиомы порядка: `х плюс 1
 * больше х` неправда при большом |х|, `х минус 1 меньше х` — тоже. Ровно
 * поэтому список аксиом ядра был и остаётся пуст. Но перечисленное выше в
 * IEEE-754 ИСТИННО, и это проверяется рассуждением, а не надеждой:
 * `а не меньше 0` истинно только для не-NaN значений из [0, +∞] — NaN не
 * сравним ни с чем, и посылка на нём ложна. Сумма двух значений из [0, +∞] под
 * округлением к ближайшему снова лежит в [0, +∞]: переполнение даёт +∞, а не
 * отрицательное, и знака здесь потерять негде. Условное выражение вообще не
 * арифметика — это выбор одной из двух ветвей, и если обе неотрицательны, то
 * неотрицателен и выбор.
 *
 * ── Шестая строка: умножение, и на какой посылке оно взято ──────────────────
 * Здесь стояло «умножения нет и не будет», и довод был верный: `0 умножить на
 * +∞` даёт NaN, поэтому «произведение неотрицательных неотрицательно» — ЛОЖЬ.
 * Ложным это утверждение делает ровно один вход — бесконечность, — и посылка
 * `не меньше 0` её не исключает: `+∞ не меньше 0` истинно.
 *
 * Но у ядра с некоторых пор есть ВТОРОЙ факт из той же подписи: `нат` — это
 * отрезок [0, 2^53−1], и потолок читается наравне с дном (`ограниченноеПоТипу`).
 * Две границы вместе исключают бесконечность, а не одна, и правило становится
 * истинным:
 *
 *   ЕСЛИ `а` и `б` каждый не меньше 0 И не больше КОНЕЧНОЙ границы,
 *   ТО `а умножить на б` не меньше 0.
 *
 * ДОКАЗАТЕЛЬСТВО, а не надежда. Посылка `а не меньше 0` истинна только для
 * не-NaN значений из [0, +∞]; посылка «`а` не больше конечного» отсекает `+∞`.
 * Значит `а` — КОНЕЧНОЕ неотрицательное, и то же самое `б`. Точное произведение
 * двух конечных неотрицательных вещественных неотрицательно; NaN получить негде
 * — умножение даёт NaN только из `0 × ∞` (обе бесконечности исключены посылкой)
 * или из NaN в аргументе (исключён посылкой `не меньше 0`). Округление к
 * ближайшему монотонно и ноль оставляет нулём, поэтому `fl(а·б)` лежит в
 * [0, +∞]: переполнение даёт `+∞`, а не отрицательное, и знака терять негде.
 * Оба нуля тоже проходят: `−0 не меньше 0` истинно, `−0 × 5 = −0`, и `−0 не
 * меньше 0` снова истинно.
 *
 * ЧЕМ ЭТО ОГРАНИЧЕНО, И ГРАНИЦА ЗДЕСЬ НЕ КОСМЕТИЧЕСКАЯ. Посылка требуется от
 * КАЖДОГО сомножителя и требует ДВУХ фактов сразу. Одного дна мало: допущение
 * индукции `Т не меньше 0` ничего не говорит о конечности `Т`, и `0 умножить на
 * Т` при `Т = +∞` даёт NaN. Поэтому сомножителем годится не всё, что
 * неотрицательно, а только то, что лежит в отрезке [0, конечное] —
 * это отдельная свёртка `вОтрезке`, и список её случаев КОРОЧЕ списка
 * неотрицательности:
 *
 *   конечный литерал ≥ 0                                    в отрезке
 *   терм, о котором известно И «не меньше 0», И «не больше конечного»  в отрезке
 *   `если у то а иначе б` при обоих в отрезке                в отрезке
 *
 * СЛОЖЕНИЯ И УМНОЖЕНИЯ В ЭТОМ СПИСКЕ НЕТ, и это не забывчивость: сумма и
 * произведение двух конечных БЫВАЮТ бесконечны (переполнение), а `+∞` из отрезка
 * [0, конечное] выпадает. Неотрицательности переполнение не мешает — `+∞` не
 * меньше 0, — а посылке умножения мешает, потому что следующее умножение на
 * ноль дало бы NaN. Отсюда и разные списки: `н умножить на м` при двух `нат`
 * доказуемо, `(н плюс м) умножить на к` — нет.
 *
 * ЧЕГО ЗДЕСЬ ПО-ПРЕЖНЕМУ НЕТ. Вычитания: разность двух `нат` отрицательна уже
 * на `2 минус 3`, и никакая ограниченность этого не чинит. Деления: `1 делить
 * на 0` — и рассуждения о нуле в знаменателе у ядра нет. Список правил закрыт, и
 * расширять его можно только тем же рассуждением, каким открыт этот: аксиома,
 * которая иногда ложна, делает ложным всё, что из неё выведено, и одна такая
 * строка обесценила бы каждое «доказано» в ведомости.
 *
 * Объявленный тип этого не меняет ни на знак, и проверить это можно на самом
 * корпусе: в `flang/examples/measure/natural.flang` рядом стоят «Сумма пары»
 * (`первое плюс второе`) и «Разность пары» (`первое минус второе`) — те же два
 * `нат`. У первой «результат не меньше 0» доказуемо, у второй ЛОЖНО, и пример
 * `2 минус 3 = −1` стоит там же. Отсюда негативная проверка ядра: то же самое с
 * `минус` вместо `плюс` обязано быть отвергнуто.
 *
 * ── Правило 3: ограниченность точным потолком по построению ─────────────────
 * Третье по времени и второе по родству: оно читает ТЕ ЖЕ объявления, что и
 * первое, и стоит здесь потому, что `нат` — это отрезок, а у отрезка две
 * границы. Цель вида `Е не больше П`, где `П` — КОНЕЧНЫЙ числовой литерал,
 * выводится, если `Е` собрано из ограниченного сверху:
 *
 *   литерал не больше П                             ограничен
 *   терм, о котором ЕСТЬ допущение `… не больше Л`  ограничен (при Л ≤ П)
 *   имя, ОБЪЯВЛЕННОЕ типом `нат`                    ограничено (при 2^53−1 ≤ П)
 *   `если у то а иначе б` при ограниченных обоих    ограничен
 *   `а минус б` при ограниченном `а` и НЕОТРИЦАТЕЛЬНОМ `б`  ограничен
 *
 * ПОЧЕМУ ПОТОЛОК ОТДАН ЯДРУ ТОЛЬКО СЕЙЧАС. Дно (`не меньше 0`) ядро получило
 * раньше, потолок — нет, и довод был назван прямо: «факт, которым никто не
 * пользуется, — доверие, за которое некому отвечать». Отвечать за него стало
 * кому: граница входа сверяет `--args` с объявленным типом ДО вычисления
 * (`checkArguments`, ветка `work/entry-types-113`, сюда ещё не влитая). Прежде
 * `--args '{"н": 1e300}'` втекало в программу молча и ломало доказательство
 * ТОТАЛЬНОЙ функции; теперь значение вне `нат` до тела не доходит. Потолок
 * ровно потому и стал фактом, что у него появился проверяющий.
 *
 * И заметить надо, чего эта зависимость НЕ означает. Ядро не проверяет входа и
 * не обязано: оно верит объявленному типу — иначе объявленный тип не значит
 * ничего. Но верить дну и не верить потолку было бы верой наполовину, а
 * держатся оба на одной и той же подписи.
 *
 * ГЛАВНОЕ, ЧЕГО ЗДЕСЬ НЕТ, И ПОЧЕМУ: СЛОЖЕНИЯ. Потолок — факт про АРГУМЕНТ, а
 * не про результат. Правило 1 берёт сумму, и это верно: сумма неотрицательных
 * неотрицательна. Правило 3 сумму НЕ берёт, и это тоже верно: сумма двух `нат`
 * выходит за потолок ЗАКОННО. Написано это не мною, а автором языка в корпусе
 * (`flang/examples/measure/natural.flang`, раздел 5): «Сложение двух
 * натуральных натуральным быть не обязано: 2^53−1 плюс 2^53−1 выходит за точную
 * сетку double… Анализ это видит и РАСШИРЯЕТ тип до `число`». Возьми ядро сумму
 * — оно доказывало бы ЛОЖЬ о «Сумме пары», и одна эта строка обесценила бы
 * каждое «доказано» в ведомости. Отсюда негативная проверка: `а плюс б` при
 * двух `нат` обязано быть ОТВЕРГНУТО целью `результат не больше 2^53−1`.
 *
 * ПОЧЕМУ ВЫЧИТАНИЕ — БЕРЁТ, И ЭТО НЕ ПОБЛАЖКА. Правило `а минус б ≤ П` стоит
 * на двух посылках сразу: `а ≤ П` и `б ≥ 0`, и вторая — факт правила 1. В
 * IEEE-754 это истинно, и доказывается монотонностью округления: при `б ≥ 0`
 * точное `а − б` не больше `а`, округление к ближайшему монотонно, а `а`
 * представимо, значит `fl(а − б) ≤ а ≤ П`. NaN здесь появиться негде: `а ≤ П`
 * при конечном `П` исключает `+∞` у `а`, `б ≥ 0` исключает NaN и `−∞` у `б`, а
 * `∞ − ∞` — единственный способ получить NaN вычитанием. Ровно поэтому `П`
 * обязан быть КОНЕЧНЫМ литералом: с `П = +∞` посылка перестала бы исключать
 * `а = +∞`, и правило стало бы ложным на `∞ минус ∞`.
 *
 * Убери одну из двух посылок — и правило ложно: при `б: число` вычитаемое может
 * быть `−5`, и `(2^53−1) минус (−5)` больше потолка. Это отдельное изъятие в
 * `flang/test/proof-kernel.test.mjs`, а не обещание.
 *
 * ЧЕГО ЗДЕСЬ НЕТ СВЕРХ ТОГО: умножения и деления. Произведение ограниченных
 * ограниченным не бывает (`(2^53−1) умножить на 2`), а частное упирается в
 * деление на ноль. Список закрыт тем же способом, что у правила 1: расширять
 * его можно только доказательством о IEEE-754, а не удобством.
 *
 * И ЗАМЕТИТЬ НАДО РАСХОЖДЕНИЕ СПИСКОВ, потому что оно теперь двустороннее.
 * Правило 1 берёт сложение и НЕ берёт его правило 3; правило 1 берёт умножение
 * ограниченных, и правило 3 не берёт его тем более. Сводить два списка в один
 * было бы удобно и ложно в обе стороны сразу: сумма двух `нат` за потолком, а
 * произведение — тем более.
 *
 * ── Правило 2: тождество после переписки допущением ─────────────────────────
 * Цель вида `А равно Б` выводится, если после переписки допущениями индукции
 * (каждое допущение — равенство, применяется слева направо ко всем вхождениям,
 * по одному проходу на допущение) нормальные формы `А` и `Б` совпадают
 * СИНТАКСИЧЕСКИ. Совпадение по значению здесь не рассматривается и не может:
 * равенство вычислений на бесконечном носителе неразрешимо, и притвориться, что
 * это не так, значило бы завести решатель, которого нет.
 *
 * Проход по одному на допущение — не экономия, а условие останова: переписка
 * равенством в обе стороны или до неподвижной точки не заканчивается на
 * `х равно х`, и проверяльщик перестал бы быть тотальной программой.
 *
 * ── ЧЕТВЁРТЫЙ ХОД: ЗАМКНУТАЯ ЦЕЛЬ ВЫЧИСЛЯЕТСЯ ───────────────────────────────
 * И сразу, первой строкой, самое важное о нём: РЕШАЮЩИХ ПРАВИЛ ПО-ПРЕЖНЕМУ ТРИ.
 * Четвёртым здесь стоит не правило вывода, а ВЫЧИСЛЕНИЕ, и в ядре оно не новое:
 * им уже решает `по примеру` (`flang/src/proofterm.mjs`) — «закрытый терм это
 * значение, спорить о нём не о чем, надо посчитать». Новое ровно одно: тот же
 * ход позван из `свести`. Доверенного здесь не прибавилось ни на строку —
 * интерпретатор языка ядро и так считает своим вычислителем, а `АКСИОМЫ`
 * остались пусты.
 *
 * ЧЕМ ЭТОТ ХОД ОТЛИЧАЕТСЯ ОТ ТРЁХ ПРАВИЛ, и почему его нельзя дописать к ним
 * четвёртой строкой таблицы. Правила решают ПО ПОСТРОЕНИЮ и работают при ЖИВЫХ
 * свободных именах: «имя объявлено как `нат`» — утверждение обо всех значениях
 * этого имени. Вычисление наоборот: оно отвечает только там, где имён не
 * осталось вовсе, зато отвечает при ЛЮБОМ виде цели — `начинается с`, `входит
 * в`, `длина`, чего у правил нет и не предвидится.
 *
 * ЦЕНА ЭТОГО ХОДА — ЗАМКНУТОСТЬ, И ОНА ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. Считает
 * не этот файл: вычислитель приезжает сюда ДАННЫМИ, пятым доводом, ровно как
 * определения приезжают четвёртым. Не дали вычислителя — хода нет вовсе, и
 * отказ остаётся тем же, знак в знак, каким был до этой работы (на этом стоит
 * сверка с близнецом на flang: она зовёт `свести` двумя доводами). Что вычислитель
 * обязан проверить прежде вычисления — свободные имена цели, предел шагов и
 * отказ вычисления, — записано там, где он написан.
 *
 * ПОЧЕМУ ЭТО НЕ ДЕЛАЕТ ЯДРО СЛАБЕЕ. Вычисление замкнутого терма не может
 * доказать ложь: у терма без свободных имён значение ровно одно, и «посчитали и
 * вышло `да`» — это и есть утверждение обо всём носителе цели. Ровно тем же
 * доводом держится `по примеру`, и другого у него нет.
 */

