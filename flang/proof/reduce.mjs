/**
 * Что известно неотрицательным — допущениями И объявлениями, одним списком.
 *
 * Два источника собираются здесь, а не в двух местах: правило одно, и список
 * известного у него один. Второе место, где тот же список собирался бы заново,
 * — это второй ответ на тот же вопрос.
 */
function известноеСнизу(факты, объявления) {
  return [
    ...(факты ?? [])
      .filter((факт) => факт?.kind === "binary" && факт.op === "gte" && ноль(факт.right))
      .map((факт) => факт.left),
    ...известноеПоТипу(объявления),
  ]
}

/**
 * Что известно неотрицательным ИЗ ОБЪЯВЛЕНИЙ — по одному факту на имя типа `нат`.
 *
 * Здесь ровно одно решение, и оно закрыто списком: натуральный тип даёт факт,
 * все прочие не дают ничего. Имена берутся у типизатора (`ИМЕНА_НАТ`), так что
 * четыре поверхности языка (`нат`, `nat`, `naturo`, `自然数`) читаются одинаково
 * и без второго словаря.
 *
 * ПОЧЕМУ ФАКТ ЗДЕСЬ — ИМЕННО «ИМЯ НЕ МЕНЬШЕ 0». `нат` обещает отрезок
 * [0, 2^53−1], то есть и дно, и потолок; эта функция отдаёт ДНО, потому что
 * правило неотрицательности спрашивает только про знак. Потолок отдаёт
 * `ограниченноеПоТипу` ниже — своим правилом и с другим списком случаев, и
 * разница между списками не косметическая: дно переживает сложение, потолок нет.
 * Одной функцией на оба факта здесь было бы «имя типа `нат` — это хорошо», а
 * такого правила у ядра нет.
 *
 * ГДЕ ЭТИ ФАКТЫ БЕЗОПАСНО ПРИМЕНЯТЬ. Только к именам, СВОБОДНЫМ в том месте,
 * где факт читается, и это не пожелание, а свойство `неотрицательно` ниже.
 * Связывателей в языке три, и с каждым она обходится названным способом:
 * `пусть` к её приходу уже развёрнут нормализацией; `разбор` даёт `false`
 * целиком; в `свёртка` она заходит (16 августа 2026, правило индукции по
 * списку) — и ровно поэтому ВЫЧЁРКИВАЕТ оттуда всякий факт, чьё имя свёртка
 * пересвязала. Значит всякое имя, до которого факт доходит, — то самое, что
 * объявлено в подписи, а не одноимённое связанное. Свойство держится тестом
 * («факт о внешнем имени не переживает пересвязки свёрткой»), а не обещанием:
 * пусти она факт под чужой связыватель — это была бы принятая ложь, и
 * контрпример у неё однострочный.
 *
 * @param {{name: string, type: object|null}[]} объявления
 * @returns {object[]} термы-имена, о которых известно «не меньше 0»
 */
export function известноеПоТипу(объявления) {
  const известные = []
  for (const объявление of объявления ?? []) {
    if (typeof объявление?.name !== "string") continue
    if (!натуральный(объявление.type)) continue
    известные.push({ kind: "var", name: объявление.name })
  }
  return известные
}

/**
 * Объявлен ли тип натуральным — по написанному имени, тем же словарём, каким его
 * читает типизатор.
 *
 * Узел `named` — это то, что строит парсер: имена уточнённых типов НЕ ключевые
 * слова (`types.mjs`, «Имена уточнённых типов»), и в позиции типа `нат`
 * разбирается ровно так же, как «Возможно» или любой объявленный тип.
 * Объявить свой тип с таким именем и подменить смысл нельзя: `namedOrScalar`
 * смотрит в словарь ДО объявлений модуля, поэтому здесь и там `нат` — одно и то
 * же.
 */
function натуральный(тип) {
  if (тип === null || тип === undefined) return false
  if (тип.kind !== "named") return false
  return ИМЕНА_НАТ.includes(тип.name)
}

/**
 * Неотрицательно ли выражение — по построению, а не по значению.
 *
 * Свёртка по конечному дереву выражения: четыре случая, ни одного перебора.
 * Всё, что не подошло ни под один, неотрицательным НЕ считается — отказ по
 * умолчанию, потому что противоположное умолчание («не знаю, значит ладно») и
 * есть способ принять ложь.
 *
 * Имя, объявленное как `нат`, попадает сюда уже фактом в `известные`
 * (`известноеПоТипу`), а не отдельным случаем: источник у факта другой, а
 * правило — то же самое, и разводить их на две ветви значило бы иметь два
 * правила неотрицательности вместо одного.
 */
export function неотрицательно(выражение, известные) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && !Number.isNaN(выражение.value) && выражение.value >= 0
  }
  if ((известные ?? []).some((известное) => одинаковы(известное, выражение))) return true
  if (выражение.kind === "builtin") return неотрицательнаяФорма(выражение)
  if (выражение.kind === "binary" && выражение.op === "add") {
    return неотрицательно(выражение.left, известные) && неотрицательно(выражение.right, известные)
  }
  if (выражение.kind === "if") {
    return неотрицательно(выражение.then, известные) && неотрицательно(выражение.else, известные)
  }
  if (выражение.kind === "fold") return неотрицательнаяСвёртка(выражение, известные)
  return false
}

/**
 * Встроенная форма, чей результат неотрицателен ПРИ ЛЮБОМ аргументе.
 *
 * Аргументы здесь не смотрятся вовсе, и это не упущение: в таблице лежат ровно
 * те формы, у которых тип результата от аргументов не зависит (`types.mjs`,
 * `ТИП_РЕЗУЛЬТАТА_ФОРМЫ`). Форма, чей результат зависит от входа, в таблицу не
 * попадает — значит и здесь о ней ответ один: нет.
 *
 * Аргумент негодного типа формы не пропускают: `длина` от числа прекращает
 * вычисление отказом, результата не возникает вовсе, и говорить о его знаке
 * нечего. Утверждение «результат не меньше 0» о значении, которого нет, не
 * ложно и не истинно — оно не высказано.
 */
function неотрицательнаяФорма(узел) {
  const канон = каноническаяФорма(узел?.name)
  if (typeof канон !== "string") return false
  if (!Object.hasOwn(ТИП_РЕЗУЛЬТАТА_ФОРМЫ, канон)) return false
  return отНуля(ТИП_РЕЗУЛЬТАТА_ФОРМЫ[канон])
}

/**
 * Обещает ли ТИП, что значение не меньше нуля.
 *
 * Читается ровно одно поле — нижняя граница отрезка, — и читается так же, как
 * его пишет типизатор. `−0` отсеивается отдельно и по той же причине, по какой
 * его отсеивает `отрезок` в `types.mjs`: `−0 >= 0` в JavaScript истинно, и без
 * этой проверки границу можно было бы получить из округления отрицательного.
 */
function отНуля(тип) {
  if (тип?.kind !== "number") return false
  if (typeof тип.низ !== "number" || Number.isNaN(тип.низ)) return false
  return тип.низ >= 0 && !Object.is(тип.низ, -0)
}

/**
 * Свёртка: индукция по списку двумя посылками — начало и шаг.
 *
 * Доказательство правила целиком стоит в шапке файла. Здесь — три отказа, и
 * каждый из них закрывает способ получить ложь:
 *
 *   1. имена накопителя и элемента обязаны быть именами и быть РАЗНЫМИ:
 *      вычислитель связывает элемент ПОСЛЕ накопителя, и при одном имени тело
 *      говорит об элементе, а факт лёг бы на накопитель;
 *   2. начало обязано быть неотрицательным по ВНЕШНИМ фактам — оно и вычисляется
 *      снаружи, до первого шага;
 *   3. известное о внешних именах, которые свёртка ПЕРЕСВЯЗАЛА, вычёркивается.
 *      Факт «х не меньше 0» о параметре не говорит ничего об элементе списка,
 *      названном тем же `х`, — а именно так выглядит принятая ложь.
 *
 * Факта об элементе не добавляется ни одного, и это не осторожность, а условие
 * правды: вывод обязан быть верен при любом элементе, потому что элементы —
 * содержимое списка, о котором не известно ничего.
 */
function неотрицательнаяСвёртка(свёртка, известные) {
  const накопитель = свёртка.acc
  const элемент = свёртка.item
  if (typeof накопитель !== "string" || typeof элемент !== "string") return false
  if (накопитель === элемент) return false
  if (!неотрицательно(свёртка.init, известные)) return false
  const внутри = [
    ...(известные ?? []).filter((факт) => !связаноВнутри(факт, накопитель, элемент)),
    { kind: "var", name: накопитель },
  ]
  return неотрицательно(свёртка.body, внутри)
}

/** Упоминает ли известный терм хоть одно из двух пересвязанных имён. */
function связаноВнутри(терм, накопитель, элемент) {
  const имена = new Set()
  собратьИмена(терм, имена)
  return имена.has(накопитель) || имена.has(элемент)
}

