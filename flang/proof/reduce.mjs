function ноль(узел) {
  return узел?.kind === "literal" && узел.value === 0
}

/**
 * Конечный числовой литерал — та граница, о которой правило 3 умеет отвечать.
 *
 * Конечность здесь не придирка, а посылка доказательства: с границей `+∞`
 * условие «уменьшаемое не больше границы» перестало бы исключать `+∞` у самого
 * уменьшаемого, и правило разности стало бы ложным на `∞ минус ∞` (NaN не
 * меньше и не больше ничего). NaN исключается тем же вызовом.
 */
function конечныйЛитерал(узел) {
  return узел?.kind === "literal" && typeof узел.value === "number" && Number.isFinite(узел.value)
}

/** Поля конструкции варианта — картой, чтобы отсутствие поля отличалось от `undefined`. */
function полями(конструкция) {
  return new Map(Object.entries(конструкция?.fields ?? {}))
}
