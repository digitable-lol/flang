/* Правило 3: ограниченность точным потолком                           */
/* ------------------------------------------------------------------ */

/**
 * Что известно ограниченным СВЕРХУ границей `потолок` — допущениями и объявлениями.
 *
 * Допущение годится не всякое: `Т не больше Л` даёт «Т не больше потолка» только
 * при `Л ≤ потолок`. Сравнение здесь и есть весь вывод, и делается оно на
 * литералах, а не на термах: границы, записанной выражением, ядро не читает —
 * читать её значило бы сравнивать вычисления, чего оно не умеет и не должно.
 */
function известноеСверху(факты, объявления, потолок) {
  return [
    ...(факты ?? [])
      .filter((факт) => факт?.kind === "binary" && факт.op === "lte" && конечныйЛитерал(факт.right))
      .filter((факт) => факт.right.value <= потолок)
      .map((факт) => факт.left),
    ...ограниченноеПоТипу(объявления, потолок),
  ]
}

/**
 * Что известно ограниченным сверху ИЗ ОБЪЯВЛЕНИЙ — по одному факту на имя `нат`.
 *
 * Второй факт того же объявления и той же силы: `принимает первое: нат` — это
 * написанное автором «первое не меньше 0» И «первое не больше 2^53−1», потому
 * что `нат` есть отрезок [0, `ТОЧНЫЙ_ПОТОЛОК`], а не признак знака. Ядро и здесь
 * ничего не выдумывает — оно читает написанное, тем же словарём имён и тем же
 * числом, каким тип построен в `types.mjs`.
 *
 * ПОЧЕМУ ГРАНИЦА СРАВНИВАЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ. Факт даёт `имя ≤ 2^53−1`, и
 * цели `имя не больше 10` он не закрывает: натуральное бывает и одиннадцатью.
 * Поэтому имя попадает в известные, только если спрошенная граница не ниже
 * потолка типа. Без этого сравнения правило принимало бы ложь на первой же цели
 * с маленькой границей — и это отдельная проверка, а не рассуждение
 * (`flang/test/proof-kernel.test.mjs`: граница на единицу ниже потолка отвергается).
 *
 * @param {{name: string, type: object|null}[]} объявления
 * @param {number} потолок граница, о которой спрашивает цель
 * @returns {object[]} термы-имена, о которых известно «не больше потолка»
 */
export function ограниченноеПоТипу(объявления, потолок) {
  if (typeof потолок !== "number" || !Number.isFinite(потолок)) return []
  if (!(ТОЧНАЯ_СЕТКА.верх <= потолок)) return []
  const известные = []
  for (const объявление of объявления ?? []) {
    if (typeof объявление?.name !== "string") continue
    if (!натуральный(объявление.type)) continue
    известные.push({ kind: "var", name: объявление.name })
  }
  return известные
}

/**
 * Ограничено ли выражение сверху — по построению, а не по значению.
 *
 * Свёртка по конечному дереву, как и у правила 1, и с тем же отказом по
 * умолчанию. Отличие ровно одно и оно всё: СЛОЖЕНИЯ здесь нет. Сумма
 * неотрицательных неотрицательна, сумма ограниченных ограниченной НЕ бывает —
 * `(2^53−1) плюс (2^53−1)` за потолком, — и перенести правило 1 сюда целиком
 * значило бы начать доказывать ложь о «Сумме пары» из корпуса.
 *
 * Вычитание берётся, и на двух посылках сразу: уменьшаемое ограничено, а
 * вычитаемое НЕОТРИЦАТЕЛЬНО — второе спрашивается у правила 1 тем же списком
 * известного. Одной посылки мало: при вычитаемом `число` разность бывает больше
 * уменьшаемого (`(2^53−1) минус (−5)`).
 *
 * @param {object} выражение
 * @param {number} потолок конечная граница из цели
 * @param {object[]} сверху термы, о которых известно «не больше потолка»
 * @param {object[]} снизу термы, о которых известно «не меньше 0»
 * @param {object[]} [конечные] термы, о которых известно «не больше конечного»,
 *   — ими пользуется правило умножения внутри `неотрицательно`. Список едет
 *   насквозь, а не собирается здесь заново: второй ответ на тот же вопрос
 *   разошёлся бы с первым молча.
 */
export function ограничено(выражение, потолок, сверху, снизу, конечные = []) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && !Number.isNaN(выражение.value) && выражение.value <= потолок
  }
  if ((сверху ?? []).some((известное) => одинаковы(известное, выражение))) return true
  if (выражение.kind === "if") {
    return ограничено(выражение.then, потолок, сверху, снизу, конечные)
      && ограничено(выражение.else, потолок, сверху, снизу, конечные)
  }
  if (выражение.kind === "binary" && выражение.op === "sub") {
    return ограничено(выражение.left, потолок, сверху, снизу, конечные)
      && неотрицательно(выражение.right, снизу, конечные)
  }
  return false
}

