/**
 * `Е не больше Г`, где `Г` — ТЕРМ, а не конечный литерал.
 *
 * ── ПОЧЕМУ ЭТО ТЕОРЕМА, А НЕ АКСИОМА, И ГДЕ ЗДЕСЬ ЛЕГЧЕ ВСЕГО СОЛГАТЬ ────────
 * Первое, что надо сказать вслух: в IEEE-754 `Е не больше Е` — НЕ ТЕОРЕМА.
 * На `не число` оно ЛОЖНО: NaN не сравним ни с чем, и `NaN ≤ NaN` даёт `нет`.
 * Значит рефлексивность — не «очевидное свойство порядка», а утверждение,
 * требующее посылки «Г не есть NaN», и правило, написанное без неё, было бы той
 * самой дырой, ради которой список аксиом держат пустым.
 *
 * Свидетельства «не NaN» ядро себе не заводит: единственный источник — тот же,
 * что у правила 1. Терм, о котором ВЫВЕДЕНО `Г не меньше 0`, не есть NaN, потому
 * что `NaN не меньше 0` ложно (см. доказательство правила 1 в шапке файла). Ни
 * одного НОВОГО источника фактов это правило не открывает — оно спрашивает
 * `неотрицательно`, то есть ровно то, что ядро уже умеет доказывать.
 *
 * Список случаев закрыт, и каждый — отдельная теорема о IEEE-754:
 *
 *   ДОПУЩЕНИЕ. Факт `Е не больше Г` уже назван посылкой. Выводить нечего.
 *
 *   ТОЖДЕСТВО. `Е ≡ Г` синтаксически И `Г не меньше 0` выведено. Тогда `Г` —
 *     не-NaN значение из [0, +∞], и `Г ≤ Г` истинно, включая `+∞ ≤ +∞`. Убери
 *     вторую посылку — и правило доказывало бы `(0 делить на 0) ≤ (0 делить на
 *     0)`, то есть ЛОЖЬ. Это отдельное изъятие в тесте, а не обещание.
 *
 *   ВЫБОР. `если у то а иначе б` не больше `Г`, если под `Г` обе ветви. Значение
 *     выражения — значение одной из них, третьего нет.
 *
 *   ЛИТЕРАЛ ПОД ДНОМ ГРАНИЦЫ. `Л не больше Г`, если `Л` не превосходит
 *     ДОКАЗАННОГО дна `Г` (`дноТерма` ниже). Транзитивность на не-NaN: `Л ≤ дно ≤ Г`.
 *
 *   ПРИБАВЛЕНИЕ ОДНОГО И ТОГО ЖЕ КОНЕЧНОГО ЛИТЕРАЛА. Из `А не больше Б` следует
 *     `А плюс К не больше Б плюс К` при КОНЕЧНОМ литерале `К`. Доказательство:
 *     посылка `А ≤ Б` истинна только для не-NaN `А` и `Б`; при конечном `К`
 *     ни `А плюс К`, ни `Б плюс К` не может стать NaN (единственный способ —
 *     `∞ плюс (−∞)`, а `К` конечен); точное `А+К ≤ Б+К`, а округление к
 *     ближайшему монотонно, значит `fl(А+К) ≤ fl(Б+К)`. Конечность `К`
 *     обязательна: при `К = +∞` из `−∞ ≤ 5` вышло бы `NaN ≤ +∞`, то есть ложь.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Вычитания: `а минус б ≤ Г` при `а ≤ Г` и `б ≥ 0`
 * верно ТОЛЬКО при конечном `Г` (иначе `а` и `б` бывают обе `+∞`, и разность —
 * NaN), а о конечности ТЕРМА-границы ядру не обещает никто: `вес` есть [0, +∞].
 * Правило 3 берёт вычитание ровно потому, что там граница — конечный литерал.
 * Умножения нет по той же причине, что у правила 3: произведение ограниченных
 * ограниченным не бывает. Свёртки нет: инвариант накопителя доказывает только
 * то, что говорит о результате, а `Е ≤ длина(список)` говорит ещё и о списке.
 *
 * ГРАНИЦА ЧЕСТНОСТИ, НАЗВАННАЯ ПРЯМО. Транзитивности через ЧУЖОЙ терм здесь
 * нет: из `Е ≤ Д` и `Д ≤ Г` ядро вывода не делает, потому что искать `Д` значило
 * бы завести перебор, а поиска у ядра нет ни одного.
 *
 * @param {object} левое левая половина цели
 * @param {object} правое ГРАНИЦА — терм, а не литерал
 * @param {object[]} порядки нормализованные допущения (все, не только `lte`)
 */
function поПорядку(левое, правое, порядки, снизу, конечные, положительные, целые) {
  if (левое === null || левое === undefined) return false
  if (правое === null || правое === undefined) return false

  /* ДОПУЩЕНИЕ: ровно этот порядок уже назван посылкой. */
  for (const факт of порядки ?? []) {
    if (факт?.kind !== "binary" || факт.op !== "lte") continue
    if (одинаковы(факт.left, левое) && одинаковы(факт.right, правое)) return true
  }

  /* ТОЖДЕСТВО — и только при доказанной неотрицательности границы. */
  if (одинаковы(левое, правое)) {
    return неотрицательно(правое, снизу, конечные, положительные, целые)
  }

  /* ВЫБОР: значение — значение одной из двух ветвей, третьего нет. */
  if (левое.kind === "if") {
    return поПорядку(левое.then, правое, порядки, снизу, конечные, положительные, целые)
      && поПорядку(левое.else, правое, порядки, снизу, конечные, положительные, целые)
  }

  /* ПРИБАВЛЕНИЕ ОДНОГО И ТОГО ЖЕ КОНЕЧНОГО ЛИТЕРАЛА к обеим сторонам. Слагаемое
     ищется в обеих позициях у обеих сторон, потому что сложение коммутативно и
     развёртка кладёт литерал то слева, то справа: `1 плюс длина(х)` у одного
     определения и `длина(х) плюс 1` у другого — одно и то же число. */
  if (левое.kind === "binary" && левое.op === "add" && правое.kind === "binary" && правое.op === "add") {
    for (const [слеваЛит, слеваОст] of [[левое.left, левое.right], [левое.right, левое.left]]) {
      if (!конечныйЛитерал(слеваЛит)) continue
      for (const [справаЛит, справаОст] of [[правое.left, правое.right], [правое.right, правое.left]]) {
        if (!конечныйЛитерал(справаЛит)) continue
        if (!Object.is(слеваЛит.value, справаЛит.value)) continue
        if (поПорядку(слеваОст, справаОст, порядки, снизу, конечные, положительные, целые)) return true
      }
    }
  }

  /* ЛИТЕРАЛ ПОД ДНОМ ГРАНИЦЫ. */
  if (левое.kind === "literal") {
    if (typeof левое.value !== "number" || Number.isNaN(левое.value)) return false
    const дно = дноТерма(правое, снизу, конечные, положительные, целые)
    return дно !== null && левое.value <= дно
  }

  /* РАЗБОР: значение — значение ровно одной ветви, и в этой ветви про
     разбираемое имя известно, КАКИМ конструктором оно собрано. */
  if (левое.kind === "match") {
    return поРазбору(левое, правое, порядки, снизу, конечные, положительные, целые)
  }

  /* СВЁРТКА, РАСТУЩАЯ НЕ БЫСТРЕЕ СПИСКА. */
  if (свёрткаНеБыстрееСписка(левое, правое, порядки, снизу, конечные, положительные, целые)) return true

  /* ФИЛЬТР ПОД ДЛИНОЙ: отбор не удлиняет. */
  if (левое.kind === "builtin" && каноническаяФорма(левое.name) === "длина") {
    const внутри = (левое.args ?? []).length === 1 ? левое.args[0] : null
    if (внутри?.kind === "filter") {
      const короче = { ...левое, args: [внутри.over] }
      if (поПорядку(короче, правое, порядки, снизу, конечные, положительные, целые)) return true
    }
  }

  /* ПРИБАВЛЕНИЕ НЕОТРИЦАТЕЛЬНОГО КОНЕЧНОГО ЛИТЕРАЛА К ГРАНИЦЕ. Из `Е не больше Г`
     следует `Е не больше К плюс Г` при конечном литерале `К` не меньше нуля.
     Посылку «Г не есть NaN» несёт сам доказанный порядок: если `Е ≤ Г` ИСТИННО,
     то ни `Е`, ни `Г` не NaN — с не-числом всякое сравнение ложно. Дальше
     `fl(К+Г) ≥ Г` при `К ≥ 0`: точное `К+Г ≥ Г`, округление к ближайшему
     монотонно, а обе бесконечности дают `∞ ≥ ∞` и `−∞ ≥ −∞`. Транзитивность
     на не-числах законна. КОНЕЧНОСТЬ `К` обязательна: при `К = +∞` и `Г = −∞`
     сумма есть NaN, и вывод стал бы ложью. */
  if (правое.kind === "binary" && правое.op === "add") {
    for (const [литерал, остаток] of [[правое.left, правое.right], [правое.right, правое.left]]) {
      if (!конечныйЛитерал(литерал)) continue
      if (!(литерал.value >= 0) || Object.is(литерал.value, -0)) continue
      if (поПорядку(левое, остаток, порядки, снизу, конечные, положительные, целые)) return true
    }
  }

  return false
}

/**
 * СВЁРТКА, КОТОРАЯ РАСТЁТ НЕ БЫСТРЕЕ СПИСКА: `свёртка L … не больше длина(L)`.
 *
 * ── Что доказывается ────────────────────────────────────────────────────────
 * Индукция по списку, ровно теми же двумя посылками, какими её берёт правило
 * неотрицательности (`неотрицательнаяСвёртка` выше), только несёт она не знак, а
 * ЧИСЛО ВИТКОВ:
 *
 *     начало:  М(Н) есть НОЛЬ
 *     шаг:     М(Ш) не больше М(акк) плюс 1   при допущении «М(акк) не меньше 0»
 *     инвариант знака: М(Ш) не меньше 0        при том же допущении
 *     ─────────────────────────────────────────────────────────────────────────
 *     итог:    М(итог) не больше длина(L)
 *
 * Доказательство: после `и` витков `М(акк) ≤ и`. База — `М(Н) = 0`. Шаг: из
 * `М(акк) ≤ и` и `М(Ш) ≤ М(акк) + 1` монотонность округления даёт
 * `М(Ш) ≤ fl(и + 1) = и + 1` — сложение точное, потому что `и + 1` не выходит за
 * 2⁵³ (витков ровно `длина(L)`, а длина списка есть целое из [0, 2⁵³−1]).
 * Витков ровно `длина(L)` — так их считает `flang/src/interpret.mjs`
 * (`stepFold`: один виток на элемент, ни одного лишнего).
 *
 * ── Зачем ТРЕТЬЯ посылка (инвариант знака) ──────────────────────────────────
 * Без неё вывод был бы ложью на «не числе». `М(акк) ≤ М(акк) + 1` в IEEE-754 не
 * теорема: на NaN оно ложно. Допущение «М(акк) не меньше 0» и есть свидетельство
 * не-NaN — то же самое, каким пользуется правило порядка (`поПорядку`), — но
 * взять его даром нельзя: оно само доказывается индукцией, и потому её вторая
 * посылка проверяется здесь наравне с первой. Убери проверку знака шага — и
 * правило приняло бы свёртку, накопитель которой на втором витке становится
 * `0 делить на 0`.
 *
 * ── МЕРА, И ПОЧЕМУ ИХ РОВНО ДВЕ ─────────────────────────────────────────────
 * `М` — то, чем меряется накопитель, и список закрыт двумя:
 *   САМО ЗНАЧЕНИЕ  накопитель — число («Считать где»: сколько подошло);
 *   ЕГО ДЛИНА      накопитель — список («Убрать»: что осталось).
 * Третьей меры нет, и завести её значило бы доказать про неё то же самое: что
 * начало есть ноль, что шаг прибавляет не больше одного и что мера не бывает
 * не-числом.
 *
 * ── ГРАНИЦА ОБЯЗАНА БЫТЬ ДЛИНОЙ ТОГО ЖЕ СПИСКА ──────────────────────────────
 * Сверяется `одинаковы` — знак в знак. Иначе счёт витков не связан с границей
 * ничем, и правило говорило бы о числе, которого не считало.
 *
 * @param {object} левое левая половина цели: `свёртка` или `длина(свёртка)`
 * @param {object} правое граница: обязана быть `длина(того же списка)`
 */
function свёрткаНеБыстрееСписка(левое, правое, порядки, снизу, конечные, положительные, целые) {
  if (правое?.kind !== "builtin" || каноническаяФорма(правое.name) !== "длина") return false
  const поКоторому = (правое.args ?? []).length === 1 ? правое.args[0] : null
  if (поКоторому === null) return false

  /* Мера читается по тому, как написана цель, а не угадывается по типу. */
  let свёртка = null
  let мера = (что) => что
  if (левое?.kind === "fold") {
    свёртка = левое
  } else if (левое?.kind === "builtin" && каноническаяФорма(левое.name) === "длина") {
    const внутри = (левое.args ?? []).length === 1 ? левое.args[0] : null
    if (внутри?.kind !== "fold") return false
    свёртка = внутри
    мера = (что) => ({ ...левое, args: [что] })
  } else {
    return false
  }

  const накопитель = свёртка.acc
  const элемент = свёртка.item
  if (typeof накопитель !== "string" || typeof элемент !== "string") return false
  if (накопитель === элемент) return false
  if (!одинаковы(свёртка.over, поКоторому)) return false

  /* НАЧАЛО ЕСТЬ НОЛЬ — и считается это той же перепиской, какой ядро читает
     длину: `длина(пустой список)` есть `0`, а `0` есть `0`. Ничего слабее сюда
     не годится: при начале `Б` итог был бы `Б плюс длина(L)`, а цель говорит про
     `длина(L)`. */
  const начало = развернутьДлинуЗвена(мера(свёртка.init))
  if (начало?.kind !== "literal" || !Object.is(начало.value, 0)) return false

  /* Известное о ПЕРЕСВЯЗАННЫХ именах вычёркивается — тот же довод и та же
     строка, что у `неотрицательнаяСвёртка`: факт о параметре `х` не говорит
     ничего об элементе списка, названном в свёртке тем же словом. */
  const снаружи = (список) => (список ?? []).filter((факт) => !связаноВнутри(факт, накопитель, элемент))
  const мераНакопителя = мера({ kind: "var", name: накопитель })
  const снизуВнутри = [...снаружи(снизу), мераНакопителя]

  /* ПОСЫЛКА ЗНАКА. */
  if (!неотрицательно(развернутьДлинуЗвена(мера(свёртка.body)), снизуВнутри, снаружи(конечные), снаружи(положительные), снаружи(целые))) {
    return false
  }
  /* ПОСЫЛКА РОСТА. */
  const наОдин = { kind: "binary", op: "add", left: мераНакопителя, right: { kind: "literal", value: 1 } }
  return поПорядку(
    развернутьДлинуЗвена(мера(свёртка.body)),
    наОдин,
    снаружи(порядки),
    снизуВнутри,
    снаружи(конечные),
    снаружи(положительные),
    снаружи(целые),
  )
}

/**
 * РАЗБОР ПОД ГРАНИЦЕЙ: `разбор х (случаи) не больше Г`.
 *
 * ── Почему это теорема ──────────────────────────────────────────────────────
 * Значение `разбор`а есть значение ТЕЛА ровно одной ветви — так его считает
 * `flang/src/interpret.mjs` (`stepMatch`), третьего значения не бывает. Значит
 * доказать `тело не больше Г` в КАЖДОЙ ветви и есть доказать цель.
 *
 * ── Что прибавляется в ветви, и почему это чтение, а не допущение ───────────
 * Внутри `случай голова и хвост` про разбираемое имя известно, чем оно
 * оказалось: вычислитель попал в эту ветвь ровно потому, что значение собрано
 * этим конструктором, а части его связаны названными именами. Поэтому в ГРАНИЦЕ
 * имя заменяется конструкцией — той же самой подстановкой, какой её строит
 * принцип индукции (`flang/proof/initial.mjs`, `конструктор`). Это не новый
 * факт: это уравнение, которое автор написал словом `случай`.
 *
 * ── СПИСОК КОНСТРУКТОРОВ ЗАКРЫТ ДВУМЯ, И ЭТО ЧАСТЬ ПРАВИЛА ──────────────────
 * Подстановка делается только для встроенного списка (`пусто` и `голова и
 * хвост`), у которого поля названы целиком и всегда. У образца `вариант «C» с
 * полем как имя` автор вправе назвать НЕ ВСЕ поля, и собранная из названного
 * конструкция была бы НЕ ТЕМ значением — уравнение оказалось бы ложью. Такая
 * ветвь берётся без подстановки: цель в ней просто слабее, и если она не
 * доказывается — правило отвечает «нет».
 *
 * ── ЗАХВАТ ИМЕНИ ОТВЕРГАЕТСЯ, А НЕ ОБХОДИТСЯ ────────────────────────────────
 * Если образец связывает имя, которое встречается в границе, то одно и то же
 * слово снаружи и внутри ветви значит разное, и сравнивать их нельзя. Проверка
 * груба нарочно: она смотрит ЛЮБОЕ вхождение имени, связанное оно там или нет.
 * Грубость здесь безопасна — она делает правило отказывающим чаще, а не реже.
 *
 * @param {object} разбор узел `match`
 * @param {object} правое граница
 */
function поРазбору(разбор, правое, порядки, снизу, конечные, положительные, целые) {
  const случаи = разбор.cases ?? []
  if (случаи.length === 0) return false
  const разбираемое = разбор.target
  for (const случай of случаи) {
    const тело = случай?.body
    if (тело === null || тело === undefined) return false
    for (const имя of связанныеОбразцом(случай?.pattern)) {
      if (встречаетсяИмя(правое, имя)) return false
    }
    /* Уравнение ветви переписывает ОБЕ стороны, а не одну границу: имя внутри
       ветви значит конструкцию везде, где написано, и тело зовёт его наравне с
       целью (`случай голова и хвост то элементы` — законное тело). Переписать
       одну сторону значило бы читать уравнение наполовину. */
    if (связываетИмя(тело, разбираемое?.name)) return false
    const левоеВетви = развернутьДлинуЗвена(вВетви(тело, разбираемое, случай?.pattern))
    const граница = развернутьДлинуЗвена(вВетви(правое, разбираемое, случай?.pattern))
    if (!поПорядку(левоеВетви, граница, порядки, снизу, конечные, положительные, целые)) {
      return false
    }
  }
  return true
}

/**
 * Граница, переписанная УРАВНЕНИЕМ ВЕТВИ: разбираемое имя — это конструктор.
 *
 * Возвращает границу как есть, когда переписывать нечего или НЕЛЬЗЯ: разбирается
 * не имя, образец не конструктор, конструктор не из встроенного списка, или у
 * звена не названа хотя бы одна из двух частей.
 */
function вВетви(граница, разбираемое, образец) {
  if (разбираемое?.kind !== "var" || typeof разбираемое.name !== "string") return граница
  const прочитано = образецВарианта(образец)
  if (прочитано === null) return граница
  if (прочитано.name === СПИСОК.пусто) {
    return заменитьИмя(граница, разбираемое.name, { kind: "construct", variant: СПИСОК.пусто, fields: {} })
  }
  if (прочитано.name !== СПИСОК.звено) return граница
  const голова = прочитано.bind?.[СПИСОК.голова]
  const хвост = прочитано.bind?.[СПИСОК.хвост]
  if (typeof голова !== "string" || typeof хвост !== "string") return граница
  const звено = {
    kind: "construct",
    variant: СПИСОК.звено,
    fields: { [СПИСОК.голова]: { kind: "var", name: голова }, [СПИСОК.хвост]: { kind: "var", name: хвост } },
  }
  return заменитьИмя(граница, разбираемое.name, звено)
}

/**
 * СВЯЗЫВАЕТ ли дерево это имя заново — то есть значит ли слово внутри что-то
 * своё.
 *
 * Спрашивается перед подстановкой уравнения ветви в ТЕЛО: если тело завело
 * своё `элементы`, то `элементы` снаружи и `элементы` внутри — разные значения,
 * и заменять второе первым значило бы молча переименовать чужую переменную.
 * Связыватели те же пять, что и у `СВЯЗЫВАЮЩИЕ` выше, и читаются они той же
 * строкой (`связанныеОбразцом`), чтобы ответ был один.
 */
function связываетИмя(узел, имя) {
  if (typeof имя !== "string") return false
  if (узел === null || узел === undefined || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some((элемент) => связываетИмя(элемент, имя))
  if (узел.kind === "let" && узел.name === имя) return true
  if (узел.kind === "fold" && (узел.acc === имя || узел.item === имя)) return true
  if ((узел.kind === "map" || узел.kind === "filter") && узел.item === имя) return true
  if (узел.kind === "match") {
    for (const случай of узел.cases ?? []) {
      if (связанныеОбразцом(случай?.pattern).includes(имя)) return true
    }
  }
  return Object.entries(узел).some(([ключ, поле]) => ключ !== "span" && связываетИмя(поле, имя))
}

/** Встречается ли имя в дереве хоть раз — грубо, без счёта связывателей. */
function встречаетсяИмя(узел, имя) {
  if (узел === null || узел === undefined || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some((элемент) => встречаетсяИмя(элемент, имя))
  if (узел.kind === "var" && узел.name === имя) return true
  return Object.entries(узел).some(([ключ, поле]) => ключ !== "span" && встречаетсяИмя(поле, имя))
}

/**
 * Замена ИМЕНИ на выражение по всему дереву.
 *
 * Своя, а не `подставить` из `initial.mjs`: тот файл читает этот, и обратный
 * импорт замкнул бы круг. Разница с ним названа и намеренна — здесь замена идёт
 * по всему дереву без счёта связывателей, потому что вызывающий уже отверг
 * ветвь, где связыватель мог бы перехватить это имя (`поРазбору`, «захват»).
 */
function заменитьИмя(узел, имя, чем) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => заменитьИмя(элемент, имя, чем))
  if (узел.kind === "var" && узел.name === имя) return чем
  const собрано = {}
  for (const [ключ, поле] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? поле : заменитьИмя(поле, имя, чем)
  }
  return собрано
}

/**
 * ДОКАЗАННОЕ ДНО терма — число, не меньше которого терм заведомо оказывается.
 *
 * Источник у дна ровно один, и он не новый: правило 1. Терм, о котором выведено
 * `не меньше 0`, имеет дно 0 — и заодно не есть NaN, потому что `NaN не меньше 0`
 * ложно. Сумма дон складывается ТЕМ ЖЕ сложением, каким её посчитает машина:
 * `fl(а+б) ≥ fl(дноА+дноБ)` по монотонности округления, и вычислить правую часть
 * надо ровно так же, как её вычислит IEEE-754, а не «примерно».
 *
 * Список закрыт двумя случаями. Вычитания здесь нет: дно разности не собирается
 * из дон (`0 минус 5`). Умножения нет: `0 умножить на +∞` есть NaN.
 *
 * @returns {number|null} доказанное дно или `null` — «о дне ничего не известно»
 */
function дноТерма(выражение, снизу, конечные, положительные, целые) {
  if (выражение === null || выражение === undefined) return null
  /* Литерал сам себе дно — и это не поблажка, а точность: сказать про `1` только
     «не меньше нуля» значило бы потерять единицу, которой звено длиннее хвоста. */
  if (выражение.kind === "literal") {
    if (typeof выражение.value !== "number" || Number.isNaN(выражение.value)) return null
    return выражение.value
  }
  if (выражение.kind === "binary" && выражение.op === "add") {
    const слева = дноТерма(выражение.left, снизу, конечные, положительные, целые)
    if (слева === null) return null
    const справа = дноТерма(выражение.right, снизу, конечные, положительные, целые)
    if (справа === null) return null
    const сумма = слева + справа
    return Number.isNaN(сумма) ? null : сумма
  }
  if (неотрицательно(выражение, снизу, конечные, положительные, целые)) return 0
  return null
}

/**
 * `длина` ОТ КОНСТРУКЦИИ ЗВЕНА — прочитанная своим значением, а не оставленная
 * непрозрачной.
 *
 * ЭТО НЕ АКСИОМА И НЕ НОВЫЙ ИСТОЧНИК ФАКТОВ. Конструкторов у встроенного списка
 * два, и имена их ядро не выдумывает, а читает у типизатора (`СПИСОК` выше).
 * Значение `длина` на них — не соглашение, а то, что СЧИТАЕТ интерпретатор:
 * список звена есть список хвоста, удлинённый на один элемент, поэтому
 * `длина(звено{г, х})` есть `1 плюс длина(х)`, а `длина(пусто)` есть `0`.
 * В IEEE-754 равенство точное: длина списка — целое из [0, 2⁵³−1], и прибавление
 * единицы к нему в сетку double укладывается.
 *
 * ПОЧЕМУ ЭТА ПЕРЕПИСКА ЖИВЁТ ЗДЕСЬ, А НЕ В `нормализовать`. Нормализация — общий
 * ход всего ядра, и всякая её правка меняет нормальные формы у всех четырёх
 * правил разом. Здесь же переписка нужна ровно одному правилу и ровно затем,
 * чтобы посылка индукции (она говорит о ХВОСТЕ) и цель (она говорит о ЗВЕНЕ)
 * оказались об одном и том же числе. Правило, которому посылку неоткуда взять,
 * — это правило, которого нет; ход, который нужен одному правилу, живёт при нём.
 *
 * Переписка идёт по всему дереву, и связыватели ей не помеха: она не подставляет
 * имён, а заменяет замкнутую по смыслу форму её значением.
 */
function развернутьДлинуЗвена(узел) {
  if (узел === null || узел === undefined || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map(развернутьДлинуЗвена)
  if (узел.kind === "builtin" && каноническаяФорма(узел.name) === "длина") {
    const аргументы = узел.args ?? []
    const внутри = аргументы.length === 1 ? аргументы[0] : null
    if (внутри?.kind === "construct" && внутри.variant === СПИСОК.пусто) {
      return { kind: "literal", value: 0 }
    }
    if (внутри?.kind === "construct" && внутри.variant === СПИСОК.звено) {
      const хвост = полями(внутри).get(СПИСОК.хвост)
      if (хвост !== undefined) {
        return {
          kind: "binary",
          op: "add",
          left: { kind: "literal", value: 1 },
          right: { ...узел, args: [развернутьДлинуЗвена(хвост)] },
        }
      }
    }
    const мера = мераПостроения(узел, внутри)
    if (мера !== null) return развернутьДлинуЗвена(мера)
  }
  const собрано = {}
  for (const [ключ, поле] of Object.entries(узел)) {
    собрано[ключ] = ключ === "span" ? поле : развернутьДлинуЗвена(поле)
  }
  return собрано
}


/**
 * ДЛИНА ОТ ФОРМЫ, У КОТОРОЙ ОНА СЧИТАЕТСЯ РОВНО — переписанная своим значением.
 *
 * ЭТО НЕ АКСИОМА И НЕ НОВЫЙ ИСТОЧНИК ФАКТОВ, и довод тот же, каким оправдана
 * переписка `длина(звено)` выше: здесь не «принято считать», а ПРОЧИТАНО У
 * ВЫЧИСЛИТЕЛЯ. Каждый случай — равенство, которое `flang/src/interpret.mjs` и
 * `flang/src/builtins.mjs` вычисляют буквально, и каждый выписан со ссылкой на
 * ту строку, которая его вычисляет.
 *
 * СПИСОК ЗАКРЫТ, И ЭТО ЧАСТЬ ПРАВИЛА, А НЕ ОГОВОРКА. В него попадает только та
 * форма, у которой длина итога определяется длиной аргумента ТОЧНО. Формы, где
 * длина итога зависит от данных (`отфильтровать`, `свёртка`, `разделить`), сюда
 * не попадают ни одной строкой: у них есть только НЕРАВЕНСТВО, и живёт оно в
 * `поПорядку`, где посылки видно.
 *
 *   `длина(если у то А иначе Б)` = `если у то длина(А) иначе длина(Б)`
 *     Вычислитель считает условие, потом ОДНУ ветвь (`interpret.mjs`, `case "if"`),
 *     и длина итога есть длина значения этой ветви. Третьего значения нет.
 *
 *   `длина(разбор х ...)` = `разбор х (случай к → длина(тело к))`
 *     Тот же довод и та же строка вычислителя (`stepMatch`): выбирается ровно
 *     одна ветвь, значение выражения есть значение её тела.
 *
 *   `длина(отобразить L как ф)` = `длина(L)`
 *     `stepLoop` в `interpret.mjs` при `mode === "map"` кладёт в итог РОВНО
 *     ОДНО значение на каждый виток, а витков столько, сколько элементов
 *     (`обход.длина`). Ни пропустить, ни удвоить он не может: ветви `if` в этом
 *     месте нет вовсе.
 *
 *   `длина(добавить х к L)` = `1 плюс длина(L)`, и то же у `приписать`
 *     `builtins.mjs`: `продлить(list, х)` и `приписать(list, х)` дописывают
 *     ровно одно значение — в конец и в начало соответственно. Прибавление
 *     единицы точно: длина списка есть целое из [0, 2⁵³−1].
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Строки: `длина` берёт и строку тоже, но `отобразить` и
 * `добавить` строк не принимают вовсе (`requireList`, `expectList`), поэтому
 * спорного случая не возникает — на строке вычисление прекращается отказом, и
 * значения, о длине которого шла бы речь, не появляется.
 *
 * @param {object} узел сам вызов `длина`
 * @param {object|null} внутри его единственный аргумент
 * @returns {object|null} равное выражение или `null` — «этой формы в списке нет»
 */
function мераПостроения(узел, внутри) {
  if (внутри === null || внутри === undefined) return null
  const длинаОт = (что) => ({ ...узел, args: [что] })

  /* СПИСОК, ВЫПИСАННЫЙ ЦЕЛИКОМ. `[а, б, в]` вычислитель собирает из РОВНО этих
     элементов (`interpret.mjs`, `case "list"`: `startSeq` по `items`), поэтому
     длина его — число написанных элементов, и число это известно на разборе. */
  if (внутри.kind === "list") return { kind: "literal", value: (внутри.items ?? []).length }
  /* СТРОКА-ЛИТЕРАЛ. `длина` режет строку по кодовым точкам (`builtins.mjs`,
     `Array.from`), и здесь считается ТЕМ ЖЕ `Array.from`, а не `.length`:
     у суррогатной пары числа разошлись бы. */
  if (внутри.kind === "literal" && typeof внутри.value === "string") {
    return { kind: "literal", value: Array.from(внутри.value).length }
  }

  if (внутри.kind === "if") {
    return { kind: "if", cond: внутри.cond, then: длинаОт(внутри.then), else: длинаОт(внутри.else) }
  }
  if (внутри.kind === "match") {
    return {
      ...внутри,
      cases: (внутри.cases ?? []).map((случай) => ({ ...случай, body: длинаОт(случай.body) })),
    }
  }
  if (внутри.kind === "map") return длинаОт(внутри.over)
  if (внутри.kind === "builtin") {
    const форма = каноническаяФорма(внутри.name)
    const аргументы = внутри.args ?? []
    if ((форма === "добавить" || форма === "приписать") && аргументы.length === 2) {
      return { kind: "binary", op: "add", left: { kind: "literal", value: 1 }, right: длинаОт(аргументы[1]) }
    }
  }
  return null
}

