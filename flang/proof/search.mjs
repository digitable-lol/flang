/**
 * Скелет — форма кандидата без обоснований: по чему идёт индукция и какие у неё
 * случаи. Случаи берутся НЕ придуманные, а те самые, которыми тело функции
 * разбирает переменную: чужой образец пришлось бы переименовывать, а молча
 * переименованная переменная — самая дорогая ошибка проверяльщика.
 */
function* скелетыИндукции(функция, обязательство, программа) {
  for (const переменная of обязательство.vars ?? []) {
    if (!естьАлгебра(переменная.type, программа)) continue
    const ветви = ветвиРазбора(функция, переменная.name)
    if (ветви.length === 0) continue
    yield { вид: "индукция", параметр: переменная, ветви, случаев: ветви.length }
  }
}

/**
 * Доказательство БЕЗ индукции — цепочка при цели. Годится ровно там, где
 * утверждение имеет одно значение: у функции без параметров. Ядро проверяет это
 * само (`поПримеру`, «примером закрывается только утверждение с ОДНИМ
 * значением»), и оракул не повторяет проверку, а просто не тратит на остальных
 * предел.
 */
function* скелетБезИндукции(функция, обязательство) {
  if ((обязательство.vars ?? []).length > 0) return
  if ((функция.examples ?? []).length === 0) return
  yield { вид: "цепочка", параметр: null, ветви: [], случаев: 1 }
}

function естьАлгебра(тип, программа) {
  if (тип?.kind === "list") return true
  if (тип?.kind !== "named") return false
  return (программа?.types ?? []).some((т) => т?.kind === "sum" && т.name === тип.name)
}

/**
 * Ветви `разбор <параметр>` на верхнем уровне тела — теми же двумя строками,
 * какими их читает `initial.mjs`. Своего чтения здесь нет нарочно: разойдись оно
 * с ядром — оракул предлагал бы случаи, которых ядро в теле не видит.
 */
function ветвиРазбора(функция, параметр) {
  const тело = нормализовать(функция?.body ?? null)
  if (тело?.kind !== "match") return []
  if (тело.target?.kind !== "var" || тело.target.name !== параметр) return []
  return (тело.cases ?? []).filter((случай) => образецВарианта(случай?.pattern) !== null)
}

