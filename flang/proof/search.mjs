/**
 * Перебор в глубину: уровень — случай, ветка — обоснование.
 *
 * Отсекает не эвристика оракула, а САМО ЯДРО: у вердикта есть вердикт КАЖДОГО
 * случая порознь (`проверитьИндукцию`, поле `cases`), и спуск читает именно его.
 * Поэтому неудачная ветка отбрасывается на своём уровне, а не после того, как
 * достроен весь кандидат, и перебор из степенного становится линейным. Это
 * эвристика, и доказывать её корректность не нужно: она может только не найти —
 * принимает по-прежнему ядро, и принимает оно кандидата ЦЕЛИКОМ.
 */
function спуск(скелет, обязательство, программа, состояние, пределШагов) {
  const функция = (программа.functions ?? []).find((ф) => ф.name === обязательство.of)
  const варианты = обоснованияСлучая(функция)
  const выбрано = new Array(Math.max(скелет.случаев, 1)).fill(null)

  const глубже = (уровень) => {
    if (уровень >= скелет.случаев) return проверитьЦеликом(выбрано)
    for (const обоснование of варианты) {
      if (состояние.шагов >= пределШагов) {
        состояние.предел = true
        return false
      }
      выбрано[уровень] = обоснование
      состояние.шагов += 1
      if (!случайЗакрыт(уровень, выбрано, скелет, обязательство, программа)) continue
      if (глубже(уровень + 1)) return true
    }
    выбрано[уровень] = null
    return false
  }

  const проверитьЦеликом = (обоснования) => {
    const вердикт = спроситьЯдро(обоснования, скелет, обязательство, программа)
    return вердикт?.verdict === СИЛА.proved
  }

  if (!глубже(0)) return null
  return [...выбрано]
}

/**
 * Закрыт ли ОДИН случай — по вердикту ядра об этом случае, а не по своему мнению.
 *
 * Недостающие уровни заполняются первым обоснованием: вердикт нужного случая от
 * них не зависит (посылку ядро проверяет по её собственным шагам), а кандидат
 * обязан быть целым — принцип сворачивается только при точном покрытии.
 */
function случайЗакрыт(уровень, выбрано, скелет, обязательство, программа) {
  const функция = (программа.functions ?? []).find((ф) => ф.name === обязательство.of)
  const первое = обоснованияСлучая(функция)[0]
  const полный = выбрано.map((о, и) => (и <= уровень ? (о ?? первое) : первое))
  const вердикт = спроситьЯдро(полный, скелет, обязательство, программа)
  if (скелет.вид !== "индукция") return вердикт?.verdict === СИЛА.proved
  const имя = образецВарианта(скелет.ветви[уровень]?.pattern)?.name ?? null
  const случай = (вердикт?.cases ?? []).find((с) => с.variant === имя)
  return случай?.verdict === СИЛА.proved
}

/** Обоснования, какие у языка есть для одного случая, — в порядке перебора. */
function обоснованияСлучая(функция) {
  const список = []
  if (ОБОСНОВАНИЯ.includes("hypothesis")) список.push({ rule: "hypothesis" })
  if (ОБОСНОВАНИЯ.includes("example")) {
    for (const пример of функция?.examples ?? []) список.push({ rule: "example", name: пример.name })
  }
  return список
}

/**
 * Спросить ЯДРО — то самое, которым проверяется написанное человеком.
 *
 * Второго проверяльщика здесь нет и быть не должно: реши оракул сам, годится ли
 * кандидат, — и он стал бы частью контура доверия, ради выхода из которого всё
 * это и затевалось.
 */
function спроситьЯдро(обоснования, скелет, обязательство, программа) {
  const теорема = скелет.вид === "индукция"
    ? {
        kind: "theorem",
        name: обязательство.name,
        claim: { expr: обязательство.goal },
        induction: {
          param: скелет.параметр.name,
          cases: скелет.ветви.map((ветвь, и) => ({ pattern: ветвь.pattern, steps: [{ by: обоснования[и] }] })),
        },
        qed: true,
      }
    : {
        kind: "theorem",
        name: обязательство.name,
        claim: { expr: обязательство.goal },
        steps: [{ by: обоснования[0] }],
        qed: true,
      }
  const копия = { ...обязательство, proof: теорема, hypotheses: [], discharge: null }
  try {
    return checkProofs(программа, [копия]).checked[0] ?? null
  } catch {
    /* Кандидат оказался таким, что ядро на нём сорвалось. Это находка про
       кандидата, а не про программу: следующий. */
    return null
  }
}

/** Подмена шага — только для изъятия (`ЛГАТЬ`), и больше ни для чего. */
function соврать(обоснования, как) {
  const испорчено = [...обоснования]
  const последний = испорчено.length - 1
  if (как === ЛГАТЬ.перестановкой && последний > 0) {
    испорчено[0] = обоснования[последний]
    испорчено[последний] = обоснования[0]
  }
  if (как === ЛГАТЬ.примером) испорчено[последний] = { rule: "example", name: "примера с таким именем нет" }
  return испорчено
}

