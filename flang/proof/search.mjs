/**
 * search.mjs — ПОИСК ДОКАЗАТЕЛЬСТВА: недоверенный оракул над ядром.
 *
 * ── Что это и чем оно не является ───────────────────────────────────────────
 * Ядро (`flang/src/proofterm.mjs`) не ищет ничего и не будет: поиск и есть то,
 * из-за чего проверяльщику нельзя доверять, не прочитав его целиком. Этот файл —
 * НЕ часть ядра. Он предлагает кандидата: цепочку шагов, записанную теми же
 * восемью словами языка, какими её пишет человек. Ядро проверяет её ТЕМ ЖЕ
 * кодом, каким проверяет написанную рукой, и если оракул соврал, ошибся или
 * пошутил — отвергает.
 *
 * Отсюда главное свойство, ради которого затея вообще безопасна: **корректность
 * поиска доказывать не нужно**. Он вправе быть перебором, эвристикой, чем
 * угодно; в контур доверия он не входит ни одной строкой. Проверяется это не
 * словами, а изъятием: заставьте оракул выдать ЛОЖНОГО кандидата (`ЛГАТЬ` ниже)
 * — ядро отвергнет, и слова «доказано» в ведомости не появится
 * (`flang/test/proof-search.test.mjs`).
 *
 * ── Почему кандидат — ТЕКСТ, а не дерево ────────────────────────────────────
 * Оракул мог бы отдавать ядру готовый узел AST. Он отдаёт СТРОКИ на языке — те
 * самые, которые человек впишет в файл, — и это не украшение, а вторая половина
 * недоверия. Текст проезжает ОБЫЧНЫЙ разборщик и ОБЫЧНЫЙ слой обязательств, а
 * там стоят проверки, которых у ядра нет: утверждение теоремы обязано совпасть
 * с постусловием слово в слово (`FLANG_PROOF_CLAIM_MISMATCH`), переменная —
 * с параметром по имени И типу (`FLANG_PROOF_VAR_TYPE`). Соври печать хоть в
 * одном знаке — кандидат не доедет до ядра вовсе.
 *
 * И то же самое с другой стороны: найденное доказательство можно ПРОЧИТАТЬ и
 * вписать в файл руками. Поиск, который «доказал», но не оставил проверяемого
 * следа, здесь не считается за находку.
 *
 * ── Строка `утверждаем` НЕ печатается, а вырезается из исходника ────────────
 * Печати выражений на flang в дереве нет (восемь целей печатают в чужие языки),
 * и заводить её здесь значило бы отвечать за неё в самом опасном месте: цель
 * доказательства. Поэтому цель берётся ТЕКСТОМ АВТОРА — куском той же строки,
 * где он написал `обеспечивает «имя» <утверждение>`, после закрывающей ёлочки.
 * Оракул тут ничего не сочиняет: он переписывает написанное, а совпадение
 * проверяет слой обязательств, сличая разобранное с целью.
 *
 * ── Пределы названы числами, а не спрятаны ──────────────────────────────────
 * Их два, и оба печатаются в отказе, когда упёрлись, — тем же приёмом, каким
 * говорит о себе `ПРЕДЕЛ_РАЗВЁРТКИ` в `reduce.mjs`. «Не нашёл» и «не искал
 * дальше» — разные ответы, и автор вправе их различать.
 */

