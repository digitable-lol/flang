/**
 * Цель ТЕКСТОМ АВТОРА: кусок строки `обеспечивает «имя» …` после ёлочки.
 *
 * Вырезается, а не печатается, и довод стоит в шапке файла: печати выражений на
 * flang в дереве нет, а сочинённая цель — единственная ошибка оракула, которую
 * ядро не поймало бы (оно проверяет доказательство ОТНОСИТЕЛЬНО цели). Слой
 * обязательств сличает разобранное с постусловием слово в слово, поэтому вырезка
 * либо совпадает, либо кандидат отвергается ещё до ядра.
 */
function целиком(обязательство, исходник) {
  if (typeof исходник !== "string") return null
  const строка = исходник.split("\n")[(обязательство.span?.line ?? 0) - 1]
  if (typeof строка !== "string") return null
  const метка = `«${обязательство.name}»`
  const место = строка.indexOf(метка)
  if (место < 0) return null
  const хвост = строка.slice(место + метка.length).trim()
  return хвост.length === 0 ? null : хвост
}

/**
 * Переменные теоремы: те параметры, чьи имена свободны в цели, плюс переменная
 * индукции. Лишних не пишется ни одной — слой обязательств сверяет каждую с
 * параметром по имени И типу, и лишняя строка была бы лишним местом для ошибки.
 */
function переменныеТеоремы(обязательство, скелет) {
  const нужны = свободныеИмена(обязательство.goal)
  const имена = new Set([...нужны].filter((имя) => имя !== (обязательство.bind ?? "результат")))
  if (скелет.параметр !== null) имена.add(скелет.параметр.name)
  return (обязательство.vars ?? []).filter((п) => имена.has(п.name))
}

/**
 * Теорема словами языка — та самая запись, которую человек впишет в файл.
 *
 * @returns {string|null} текст или `null`, если что-то не записывается словами
 */
export function текстТеоремы({ имя, цель, переменные, скелет, обоснования }) {
  const строки = [`теорема «${имя}»`]
  for (const переменная of переменные) {
    const тип = типСловами(переменная.type)
    if (тип === null) return null
    строки.push(`  дано ${имяСловами(переменная.name)}: ${тип}`)
  }
  строки.push(`  утверждаем ${цель}`)
  if (скелет.вид === "индукция") {
    строки.push(`  индукция по ${имяСловами(скелет.параметр.name)}`)
    for (const [и, ветвь] of скелет.ветви.entries()) {
      const образец = образецСловами(ветвь.pattern)
      if (образец === null) return null
      строки.push(`    случай ${образец}`)
      строки.push(`      то ${обоснованиеСловами(обоснования[и])}`)
    }
  } else {
    строки.push(`  ${обоснованиеСловами(обоснования[0])}`)
  }
  строки.push("  следовательно доказано")
  return `${строки.join("\n")}\n`
}

/**
 * Имя в записи языка. Ёлочки ставятся ВСЕГДА: закавыченное имя ключевым словом
 * не станет никогда, а голое `хвост` или `голова` — станет, и разбор поедет не
 * туда. Разбор от ёлочек не меняется — имя то же самое.
 *
 * ГРАНИЦА ПЕЧАТИ, названная прямо: слова здесь только РУССКИЕ. Строка
 * `утверждаем` берётся у автора и остаётся на его поверхности, значит в
 * английском файле нашлась бы теорема с русским скелетом и английским
 * утверждением. Разбору это не мешает — таблица ключевых слов одна на обе
 * поверхности, — читателю мешает. Сегодня на это не попасть (у английских файлов
 * корпуса поиск не берёт ни одного утверждения), поэтому граница названа, но НЕ
 * измерена: сказать «работает на двух поверхностях» было бы неправдой.
 */
const имяСловами = (имя) => `«${имя}»`

/**
 * Тип словами языка.
 *
 * Список видов закрыт, и неизвестный вид НЕ выдумывается: оракул честно
 * отказывается написать то, чего не умеет, — вместо того чтобы напечатать
 * похожее. Ошибка здесь ловится слоем обязательств (`FLANG_PROOF_VAR_TYPE`),
 * но ловить её лучше не приходилось бы.
 */
function типСловами(тип) {
  if (тип === null || typeof тип !== "object") return null
  if (тип.kind === "named") {
    if (!Array.isArray(тип.args) || тип.args.length === 0) return имяСловами(тип.name)
    const аргументы = тип.args.map(типСловами)
    if (аргументы.some((а) => а === null)) return null
    return `${имяСловами(тип.name)} от ${аргументы.join(" и ")}`
  }
  if (тип.kind === "list") {
    const элемент = типСловами(тип.of)
    return элемент === null ? null : `список ${элемент}`
  }
  /* Уточнённые скаляры (`Деньги`, `Дата`) пишутся своими словами, и написать их
     видом узла нельзя: у `{kind:"number", fts:"Деньги"}` и у `число` вид один. */
  if (тип.fts !== undefined) return null
  if (тип.kind === "number") return "число"
  if (тип.kind === "string") return "строка"
  if (тип.kind === "flag") return "признак"
  return null
}

/** Образец словами языка — теми же тремя формами, какими его пишет `разбор`. */
function образецСловами(образец) {
  if (образец?.kind === "empty") return "пусто"
  if (образец?.kind === "cons") {
    /* `голова и хвост` — одно ключевое слово, и имена оно связывает само; писать
       `голова «голова» и хвост «хвост»` значило бы сказать то же самое длиннее. */
    if (образец.head === СПИСОК.голова && образец.tail === СПИСОК.хвост) return "голова и хвост"
    return `голова ${имяСловами(образец.head)} и хвост ${имяСловами(образец.tail)}`
  }
  if (образец?.kind === "variant") {
    const связи = Object.entries(образец.bind ?? {})
    const голова = `вариант ${имяСловами(образец.name)}`
    if (связи.length === 0) return голова
    return `${голова} с ${связи.map(([поле, имя]) => `${имяСловами(поле)} как ${имяСловами(имя)}`).join(" и ")}`
  }
  return null
}

/** Обоснование словами языка. Словарь тот же, каким они названы в отчёте. */
function обоснованиеСловами(обоснование) {
  const слова = СЛОВАМИ[обоснование?.rule] ?? СЛОВАМИ.hypothesis
  return typeof обоснование?.name === "string" ? `${слова} ${имяСловами(обоснование.name)}` : слова
}
