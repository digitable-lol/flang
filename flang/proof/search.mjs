/** Версия формата находки: её читает скрипт и тест, значит она названа. */
export const ПОИСК = 1

/**
 * Сколько кандидатов оракул вправе предъявить ядру на одно обязательство.
 *
 * ПОЧЕМУ ПРЕДЕЛ ВООБЩЕ ЕСТЬ. Обоснований у случая столько, сколько у функции
 * примеров, плюс одно (`по предположению`), а случаев — сколько у суммы
 * конструкторов. Перебор всех сочетаний растёт степенью, и на функции с десятью
 * примерами и четырьмя вариантами это 14 641 прогон ядра. Предел — единственное,
 * что стоит между инструментом и получасовым молчанием.
 *
 * ПОЧЕМУ ИМЕННО СТОЛЬКО. Число НЕ про состоятельность: оракул ничего не
 * доказывает, поэтому остановиться раньше — значит найти МЕНЬШЕ, а не найти
 * ложное. Оно про то, докуда доходит честный перебор. Замер по корпусу: самая
 * дорогая находка (`«Штраф»` светофора и `«Ступень»` из `four-words.flang`)
 * стоит 9 кандидатов со спуском и 28 без него, и ни одна не стоит больше.
 * Запас взят с большим избытком нарочно: предел обязан ловить ВЫРОЖДЕННЫЙ
 * случай (много примеров при многих вариантах), а не подрезать обычный.
 */
export const ПРЕДЕЛ_ШАГОВ = 256

/**
 * Докуда оракул спускается вглубь: сколько случаев подряд он вправе закрывать.
 *
 * Спуск идёт ПО СЛУЧАЯМ: уровень — один случай индукции, ветка — одно
 * обоснование. Глубина дерева перебора равна числу конструкторов суммы, и предел
 * назван именно на неё, а не на «шаги вообще»: у суммы с двадцатью вариантами
 * перебор был бы честным и всё равно бесполезным.
 *
 * ЦЕПОЧКА ВНУТРИ СЛУЧАЯ ДЛИНОЙ В ОДИН ШАГ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ.
 * Цепочка из двух шагов имела бы смысл там, где первый шаг ДОБАВЛЯЕТ факт,
 * которым пользуется второй. Сегодня такого правила нет ни одного: `по
 * предположению` сводит заключение к допущениям посылки, `по примеру` считает
 * закрытый терм, и ни то, ни другое не читает списка `известно`
 * (`proofterm.mjs`, `проверитьЦепочку`). Значит второй шаг мог бы только
 * ослабить вердикт, и перебирать его — платить за то, чего не бывает. Появится
 * правило, которое читает `известно`, — здесь придётся завести второй предел, и
 * это будет решение, а не случайность.
 */
export const ПРЕДЕЛ_ГЛУБИНЫ = 8

/**
 * Обоснования, которыми оракул вправе закрывать случай, — СПИСОК ЗАКРЫТ.
 *
 * Их у языка четыре, а здесь два, и оба недостающих названы с доводом, чтобы
 * список не выглядел закрытым по лени:
 *
 *   `по закону «…»`   — ядро такой терм ПРИНИМАЕТ, но ослабляет вердикт до
 *                       сетки: закон посчитан на конечной сетке автора. Находка,
 *                       которая не даёт «доказано», не находка, а трата предела.
 *   `по свойству «…»` — ядро сегодня отвергает его всегда: свести `результат`
 *                       шага с результатом другой функции ему нечем
 *                       (`proofterm.mjs`, «сличение по вызову»). Перебирать
 *                       заведомо отвергаемое — то же самое.
 *
 * Появится у ядра сличение по вызову — строка `по свойству` встанет сюда, и
 * находок станет больше без единой правки в ядре. Ровно за этим оракул и отделён
 * от него.
 */
export const ОБОСНОВАНИЯ = Object.freeze(["hypothesis", "example"])

/**
 * Те же правила словами языка. Латиницей код, словом человек — тот же приём, что
 * у имён правил сведения (`reduce.mjs`, `ПРАВИЛО`): отказ и отчёт обязаны
 * называть правило теми же словами, какими автор пишет его в файле.
 */
export const СЛОВАМИ = Object.freeze({
  hypothesis: "по предположению",
  example: "по примеру",
  property: "по свойству",
  law: "по закону",
})

/**
 * ЛГАТЬ — рубильник изъятия, и он здесь не для отладки.
 *
 * Главное свойство этой работы — «ядро не верит оракулу ни на грамм» — нельзя
 * показать, пока оракул честен: зелёный цвет тогда означает только, что оба
 * согласны. Поэтому у оракула есть режим, в котором он выдаёт кандидата
 * ЗАВЕДОМО ЛОЖНОГО: подменяет обоснование одного случая на такое, которым этот
 * случай не закрывается. Ядро обязано отвергнуть, и в ведомости не должно
 * появиться ни одного «доказано» — это проверяется, а не обещается
 * (`flang/test/proof-search.test.mjs`).
 *
 * Рубильник приезжает НАСТРОЙКОЙ, а не глобальным состоянием: два вызова в одном
 * прогоне обязаны не мешать друг другу, иначе изъятие красило бы соседний тест.
 */
export const ЛГАТЬ = Object.freeze({
  нет: "нет",
  /* ПОДМЕНА ОДНОГО ШАГА — та самая ложь, про которую спрашивают: обоснования
     первого и последнего случая меняются местами. База закрывалась вычислением,
     шаг — допущением; после перестановки в базе стоит `по предположению`
     (предполагать не о чем), а в шаге — `по примеру` (заключение не замкнуто).
     Оба отказа у ядра свои и названы разными кодами. */
  перестановкой: "перестановкой",
  /* Сослаться на пример, которого у функции нет. */
  примером: "примером",
  /* Соврать в самой ЦЕЛИ: написать `утверждаем` не то, что обещает функция.
     Сюда ядро даже не доедет — отвергнет слой обязательств. */
  целью: "целью",
})

/**
 * Убрать из исходника блок одной теоремы — по строке её объявления.
 *
 * Нужно ровно для ПЕРЕВЫВОДА: чтобы спросить оракула о том, что уже доказано
 * рукой, доказательство надо СНЯТЬ, иначе постусловие закрывается дважды и слой
 * обязательств честно отказывает. Границей блока служит отступ — тот же признак,
 * которым язык отделяет объявления друг от друга.
 *
 * Живёт здесь, а не в скрипте, по причине скучной и дорогой: модуль языка
 * положено импортировать, не запуская, а скрипт при импорте ЗАПУСКАЕТСЯ — обход
 * всего корпуса ради одной вспомогательной функции.
 *
 * @param {string} исходник текст модуля
 * @param {number} строкаОбъявления строка, на которой стоит слово `теорема`
 * @returns {string|null} исходник без этого блока
 */
export function безТеоремы(исходник, строкаОбъявления) {
  const строки = исходник.split("\n")
  const начало = строкаОбъявления - 1
  if (начало < 0 || начало >= строки.length) return null
  let конец = начало + 1
  while (конец < строки.length && (строки[конец].trim() === "" || /^\s/u.test(строки[конец]))) конец += 1
  return [...строки.slice(0, начало), ...строки.slice(конец)].join("\n")
}

/**
 * Найти доказательство обязательства — или честно сказать, что не нашёл.
 *
 * @param {object} обязательство обязательство из `obligations.mjs` (постусловие)
 * @param {object} программа AST модуля
 * @param {string} исходник текст модуля — из него берётся строка `утверждаем`
 * @param {{ лгать?: string, пределШагов?: number, пределГлубины?: number }} [настройки]
 * @returns {{ ok: boolean, текст: string|null, шагов: number, why: string|null }}
 */
export function искатьДоказательство(обязательство, программа, исходник, настройки = {}) {
  const пределШагов = настройки.пределШагов ?? ПРЕДЕЛ_ШАГОВ
  const пределГлубины = настройки.пределГлубины ?? ПРЕДЕЛ_ГЛУБИНЫ
  const лгать = настройки.лгать ?? ЛГАТЬ.нет
  /* Пределы едут в состояние, а не читаются из модуля при печати отказа: назови
     отказ число, которого в этом прогоне не было, — и он соврал бы про причину
     ровно в том месте, ради которого его и печатают. */
  const состояние = { шагов: 0, предел: false, пределШагов, пределГлубины }

  if (обязательство?.kind !== "postcondition") {
    return отказ(состояние, "искать нечего: это не постусловие, а обязательство другого рода")
  }
  if (обязательство.proof !== null && обязательство.proof !== undefined) {
    return отказ(состояние, "у этого постусловия теорема уже написана автором — искать за него нечего")
  }
  const функция = (программа?.functions ?? []).find((ф) => ф.name === обязательство.of)
  if (функция === undefined || функция.body === null || функция.body === undefined) {
    return отказ(состояние, `функции «${обязательство.of}» с телом в модуле нет`)
  }

  const цель = целиком(обязательство, исходник)
  if (цель === null) {
    return отказ(
      состояние,
      "строку `утверждаем` взять неоткуда: постусловие написано не одной строкой,"
        + " а сочинять цель за автора оракул не станет — это единственное место, где ошибка печати"
        + " стоила бы доказательства не того утверждения",
    )
  }

  const скелеты = [...скелетыИндукции(функция, обязательство, программа), ...скелетБезИндукции(функция, обязательство)]
  if (скелеты.length === 0) {
    return отказ(
      состояние,
      `начинать не с чего: ни один параметр «${обязательство.of}» не имеет начальной алгебры`
        + " с разбором по нему на верхнем уровне тела, а без параметров функция тоже не написана."
        + " Индукция читается с объявления суммы или встроенного списка, и брать её больше неоткуда",
    )
  }

  for (const скелет of скелеты) {
    if (скелет.случаев > пределГлубины) {
      состояние.предел = true
      continue
    }
    const найдено = спуск(скелет, обязательство, программа, состояние, пределШагов)
    if (найдено === null) continue
    /* ИЗЪЯТИЕ ПОРТИТ НАЙДЕННОЕ, А НЕ ПОИСК. Врать надо ровно там, где оракул
       выдаёт результат: подмени шаг раньше — и перебор просто не нашёл бы
       ничего, то есть изъятие показывало бы не то. Здесь цепочка уже найдена
       честно, и один её шаг подменяется перед самой выдачей. */
    const выдать = лгать === ЛГАТЬ.нет ? найдено : соврать(найдено, лгать)
    /* Изъятие целью: подменяется САМА цель. Слой обязательств обязан отвергнуть
       такого кандидата прежде ядра — сличение утверждения теоремы с постусловием
       у него синтаксическое и слово в слово. */
    const пишем = лгать === ЛГАТЬ.целью ? "результат не меньше 1" : цель
    const текст = текстТеоремы({
      имя: обязательство.name,
      цель: пишем,
      переменные: переменныеТеоремы(обязательство, скелет),
      скелет,
      обоснования: выдать,
    })
    if (текст === null) {
      return отказ(
        состояние,
        "найденное не записывается словами языка:"
          + " у образца или типа нет формы, которую оракул умеет написать",
      )
    }
    return { ok: true, текст, шагов: состояние.шагов, why: null }
  }

  return отказ(
    состояние,
    "цепочки, которую бы ядро приняло, среди перебранных нет:"
      + ` обоснования закрыты списком (${ОБОСНОВАНИЯ.map((п) => СЛОВАМИ[п]).join(", ")}),`
      + " и ни одно не закрыло всех случаев",
  )
}

function отказ(состояние, почему) {
  const оПределе = состояние.предел
    ? ` Предел перебора достигнут (шагов ${состояние.пределШагов}, глубина ${состояние.пределГлубины}):`
      + " перебор остановлен, а не продолжен молча — «не нашёл» и «не искал дальше» разные ответы"
    : ""
  return { ok: false, текст: null, шагов: состояние.шагов, why: `${почему}.${оПределе}` }
}

