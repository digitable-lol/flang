  sh "$self" --корень "$rab/Д" --ведомость "$rab/Д.tsv" --набор корпус >"$rab/Д.out" 2>&1; k=$?
  if [ "$k" -eq 0 ]; then
    echo "дыра: вердикт снят у ЧАСТИ утверждений	ПОКАЗАНА (оба сторожа молчат, код 0)"
