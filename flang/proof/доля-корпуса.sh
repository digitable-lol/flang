    d=$(/usr/bin/grep -a -m1 '^исходник ' "$root/$zrel" | cut -d' ' -f2-)
    [ -n "$d" ] && printf '%s\n' "$d"
  done < "$tmp/записи-дерева.txt" | sort -u > "$tmp/дела-ядра.txt"

  vsego=0; ne_iz_dereva=0; sudimo=0; zeleno=0; otvergnuto=0; ogovoreno=0; nedokazano=0
  bedy=""; usnulo=""
  while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    vsego=$((vsego+1))
    otp=$(v_sha "$rel")
    if [ -z "$otp" ]; then ne_iz_dereva=$((ne_iz_dereva+1)); continue; fi
    if [ ! -f "$root/$rel" ] || [ "$(sha256sum "$root/$rel" | cut -d' ' -f1)" != "$otp" ]; then
      bedy="$bedy
  РАЗОШЁЛСЯ С КОММИТОМ, судить нечего: $rel"; continue; fi
    sudimo=$((sudimo+1))
    # 7102: судить НАДО тем же ключом, о котором спрашивает гейт. Голый `check`
    # проверяет строение и типы; доказательства он не спрашивает вовсе и на
    # файле, где не доказано ни одного утверждения, отвечает кодом 0. Замер 6
    # сентября 2026: из 101 файла, «принятого ядром» без ключа, 24 разворачива-
    # ются в код 3 с `--proof`, 19 из них — «доказано 0». То есть прибор
    # заверял файлы, на которых ядро ничего не доказало.
    ( cd "$root" && "$yadro" check --proof "$rel" ) >/dev/null 2>&1; k=$?
    if /usr/bin/grep -aqxF "$rel" "$tmp/оговорки.txt"; then
      ogovoreno=$((ogovoreno+1))
      [ "$k" -eq 0 ] && usnulo="$usnulo
  ОГОВОРКА ПРОСНУЛАСЬ (ядро больше не отвергает — проба протухла): $rel"
      continue
    fi
    # ТРИ ИСХОДА, А НЕ ДВА, И РАЗНИЦА МЕЖДУ НИМИ — ВСЯ ОХРАНА. Код 1 ядра есть
    # ОПРОВЕРЖЕНИЕ с названным контрпримером: он снимает сертификат, и на нём
    # прогон краснеет. Код 3 — «не доказано»: это не вина файла, а тот же
    # пустой числитель, только со стороны ядра, и записывать его в вину значило
    # бы уронить прогон на всех пробах подделок, которые в дереве лежат
    # законно. Поэтому он считается ОТДЕЛЬНО и печатается числом: молчать о нём
    # нельзя, судить им — тоже.
    if [ "$k" -eq 0 ]; then zeleno=$((zeleno+1))
    elif [ "$k" -eq 3 ]; then nedokazano=$((nedokazano+1))
    else
      otvergnuto=$((otvergnuto+1))
      bedy="$bedy
  ЯДРО ОТВЕРГАЕТ ФАЙЛ (код $k), а запись о нём лежит в дереве: $rel"
    fi
  done < "$tmp/дела-ядра.txt"

  echo "═══ ПРИГОВОР ЯДРА НА ФАЙЛАХ, НАЗВАННЫХ ЗАПИСЯМИ ═══"
  echo "ведомость дела	$vedimya"
  echo "исходников названо записями дерева	$vsego"
  echo "  из них дела в дереве нет (ведомость молчит)	$ne_iz_dereva"
  echo "судимо ядром	$sudimo"
  echo "  ядро приняло (код 0)	$zeleno"
  echo "  ядро приняло, но НЕ ДОКАЗАЛО ничего (код 3 с --proof)	$nedokazano"
  echo "  ядро отвергло, оговорено поимённо	$ogovoreno"
  echo "  ЯДРО ОТВЕРГЛО БЕЗ ОГОВОРКИ	$otvergnuto"
  [ -n "$bedy" ] && printf '%s\n' "$bedy"
  [ -n "$usnulo" ] && printf '%s\n' "$usnulo"
  if [ -n "$bedy" ] || [ -n "$usnulo" ]; then
    echo ""
    echo "ЯДРО СУДИТ ФАЙЛ САМО: запись о файле, который ядро отвергает, проверенной не считается"
    return 1
  fi
  echo "приговор ядра: ни один судимый файл ядром не опровергнут, оговорки на месте"
  echo "  (это ВСЯ охрана: «не опровергнут» — не «доказан». Файлов, на которых"
  echo "   ядро не доказало ничего, здесь $nedokazano, и они прошли эту дверь честно.)"
  return 0
}

# Шапка исходника ТЕМ ЖЕ СЧЁТОМ, что у чекера (`сверщик.c`: znakov, otpechatok):
# строк, знаков-кодовых-точек, два многочлена, SHA-256. Нужна только пробе —
# подделыватель переподписывает шапку записи, и проба обязана уметь то же.
shapka_ishodnika() {
  od -An -tu1 -v < "$1" | awk -v sha="$(sha256sum "$1" | cut -d' ' -f1)" '
    { for (i = 1; i <= NF; i++) b[++n] = $i + 0 }
    END{
      strok = 1; znakov = 0; h1 = 7; h2 = 7; i = 1
      while (i <= n) {
        v = b[i]
        if      (v < 128) { c = v;      k = 1 }
        else if (v < 224) { c = v % 32; k = 2 }
        else if (v < 240) { c = v % 16; k = 3 }
        else              { c = v % 8;  k = 4 }
        for (j = 1; j < k; j++) c = c * 64 + (b[i+j] % 64)
        i += k; znakov++
        if (c == 10) strok++
        h1 = (h1 * 131 + c) % 1000000007
        h2 = (h2 * 137 + c) % 998244353
      }
      printf "%d %d %d %d %s\n", strok, znakov, h1, h2, sha
    }'
}

# ── ПРОБА ПОРЧИ НА ПРИГОВОР ЯДРА ────────────────────────────────────────────
# Подделыватель здесь не подменяет дела и не лжёт в записи НИ ОДНИМ ПОЛЕМ. Он
# дописывает к честному исходнику функцию с ложным постусловием и добавляет в
# запись честное утверждение о ней — «нет вердикта». Оба файла кладутся в
# коммит; ведомость подтверждает их обоих, чекер даёт код 0 «ПРОВЕРЕНО», ядро
# на файле даёт код 1 с названным контрпримером.
#
# Три ответа подряд, и средний — не охрана, а ПОКАЗАННАЯ ДЫРА:
#   контроль  честный файл          — линейка Р0 код 0, приговор ядра код 0
#   дыра      подделка в коммите    — линейка Р0 код 0  (ведомость её НЕ ловит)
#   охрана    та же подделка        — приговор ядра код 1
# Без контроля покрасневший приговор читался бы как работа охраны на чём
# угодно; без «дыры» — нельзя было бы показать, что ведомости тут не хватает.
podlog_yadra() {
  yadro=$root/bootstrap/flang
  [ -x "$yadro" ] || { echo "нет двоичного ядра $yadro — собрать: make -C bootstrap" >&2; return 2; }
  rab=$tmp/подлог-ядра
  ish=flang/proof/examples/corpus-natural.flang
  zap=$root/flang/proof/чекер/пробы/записи/корпус/corpus-natural.запись
  [ -f "$root/$ish" ] && [ -f "$zap" ] \
    || { echo "ПОДЛОГ НЕ СОБРАЛСЯ: нет «$ish» или его записи — поправить пробу, линейка ни при чём" >&2; return 1; }

  for d in ч г; do
    mkdir -p "$rab/$d/$(dirname "$ish")" "$rab/$d/записи" "$rab/$d/flang/proof/чекер" "$rab/$d/bootstrap" || return 1
    cp "$checker" "$rab/$d/flang/proof/чекер/сверщик" || return 1
    ln -sf "$yadro" "$rab/$d/bootstrap/flang" || return 1
  done
  cp "$root/$ish" "$rab/ч/$ish" || return 1
  cp "$zap" "$rab/ч/записи/проба.запись" || return 1

  # Ложь дописывается В КОНЕЦ: номера строк честной части не съезжают, и чекеру
  # нечего заметить. Постусловие ложно по IEEE-754 — «не число» живёт в типе
  # «число» и стоит вне порядка; ядро называет контрпример словами.
  { cat "$root/$ish"
    printf '\nтотальная функция «Ложь 2390»\n  принимает первое: число, второе: число\n'
    printf '  возвращает число\n  обеспечивает «ложь 2390 неотрицательна» результат не меньше 0\n'
    printf '  первое плюс второе\n'; } > "$rab/г/$ish"
  ( cd "$rab/г" && ./bootstrap/flang check "$ish" ) >/dev/null 2>&1
  if [ $? -eq 0 ]; then
    echo "ПОДЛОГ НЕ СОБРАЛСЯ: ядро приняло файл с ложным постусловием — поправить пробу, линейка ни при чём" >&2
    return 1; fi
  nl=$(/usr/bin/grep -an '^  обеспечивает «ложь 2390' "$rab/г/$ish" | cut -d: -f1)
  [ -n "$nl" ] || { echo "ПОДЛОГ НЕ СОБРАЛСЯ: дописка не легла в файл" >&2; return 1; }
  # Запись остаётся ЧЕСТНОЙ: «нет вердикта» — правда, шапка пересчитана честно.
  set -- $(shapka_ishodnika "$rab/г/$ish")
  awk -v s="$1" -v z="$2" -v p1="$3" -v p2="$4" -v sh="$5" -v nl="$nl" '
    /^строк /       { print "строк " s; next }
    /^знаков /      { print "знаков " z; next }
    /^отпечаток256 /{ print "отпечаток256 " sh; next }
    /^отпечаток /   { print "отпечаток " p1 " " p2; next }
    /^утверждений / { print "утверждений " ($2 + 1); next }
    /^конец записи$/{ printf "утверждение «ложь 2390 неотрицательна» функции «Ложь 2390» строка %s\n", nl
                      print "  вид postcondition"; print "  вердикт нет вердикта"
                      print "  теоремы нет"; print "конец утверждения"; print ""
                      print; next }
                    { print }' "$zap" > "$rab/г/записи/проба.запись"

  vedom() { # каталог → ведомость того же вида, что строит git archive
    ( cd "$1" && find . -type f \( -name '*.flang' -o -name '*.запись' \) -print0 \
      | LC_ALL=C sort -z | xargs -0 sha256sum ) | sed 's|  \./|\t|' > "$2"
  }
  vedom "$rab/ч" "$rab/ч.tsv" || return 1
  vedom "$rab/г" "$rab/г.tsv" || return 1

  razr() { awk -F'\t' -v r="$2" 'NR>1 && $16==r {n++} END{print n+0}' "$1"; }
  bad=0
  sh "$self" --корень "$rab/ч" --ведомость "$rab/ч.tsv" --набор "$rab/ч/записи" \
     --разбор "$rab/ч.tsv.разбор" >"$rab/ч.out" 2>&1; k=$?
  sh "$self" --корень "$rab/ч" --ведомость "$rab/ч.tsv" --приговор-ядра >"$rab/ч.ядро" 2>&1; ky=$?
  if [ "$k" -eq 0 ] && [ "$(razr "$rab/ч.tsv.разбор" Р0)" -eq 1 ] && [ "$ky" -eq 0 ]; then
    echo "контроль: честный файл в коммите	ЦЕЛА (линейка Р0 код 0, приговор ядра код 0)"
  else
    echo "контроль: честный файл в коммите	ПРОВАЛ (линейка код $k, Р0=$(razr "$rab/ч.tsv.разбор" Р0), приговор код $ky)"; bad=1; fi

  sh "$self" --корень "$rab/г" --ведомость "$rab/г.tsv" --набор "$rab/г/записи" \
     --разбор "$rab/г.tsv.разбор" >"$rab/г.out" 2>&1; k=$?
  if [ "$k" -eq 0 ] && [ "$(razr "$rab/г.tsv.разбор" Р0)" -eq 1 ]; then
    echo "дыра: ложь в коммите, ведомость её НЕ ловит	ПОКАЗАНА (линейка Р0 код 0, Р5 ноль)"
  else
    echo "дыра: ложь в коммите, ведомость её НЕ ловит	НЕ ПОКАЗАНА (код $k, Р0=$(razr "$rab/г.tsv.разбор" Р0)) — подделка не собралась либо линейку правили"; bad=1; fi

  sh "$self" --корень "$rab/г" --ведомость "$rab/г.tsv" --приговор-ядра >"$rab/г.ядро" 2>&1; ky=$?
  if [ "$ky" -eq 1 ] && /usr/bin/grep -aq 'ЯДРО ОТВЕРГАЕТ ФАЙЛ' "$rab/г.ядро"; then
    echo "охрана: приговор ядра на той же подделке	ОТВЕРГНУТА (код 1)"
  else
    echo "охрана: приговор ядра на той же подделке	ПРОШЛА — охраны нет (код $ky)"; bad=1; fi

  [ "$bad" -eq 0 ] && echo "проба порчи на приговор ядра: дыра показана, охрана краснеет, честный файл зелен"
  return $bad
}

