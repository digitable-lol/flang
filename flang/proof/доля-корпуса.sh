  [ "$bad" -eq 0 ] && echo "проба на снятый вердикт: обе подделки отвергнуты, честные записи зелены, остаток назван"
  return $bad
}

# ── ПРОБА НА ПУСТОЙ ЧИСЛИТЕЛЬ (заказ надагента, 6 сентября 2026) ────────────
# ИНВАРИАНТ: запись, засчитанная в числитель Г4 (разряд Р0), обязана иметь
# «доказанными» больше нуля. Линейка пустоту уже печатает числом, но печать —
# не сторож: ни одна проба самопроверки не спрашивала «а не пуста ли запись,
# которую мы засчитали», и через эту щель прошла накрутка 7116 — снятые в
# записях слова «вердикт доказано» растили мерку с 49 до 56, и не краснел никто.
#
# Три ответа подряд, и средний — единственный, ради которого проба заведена:
#   контроль  честная непустая запись Р0        — прогон зелёный
#   подлог    та же запись с обнулёнными вердиктами: Р0 при «доказанными 0»,
#             имя в поимённом списке не значится — прогон КРАСНЫЙ
#   показ     настоящая пустая запись корпуса   — Р0 при «доказанными 0», но
#             названа поимённо, и потому прогон зелёный ЗАКОННО
# Третий ответ печатается нарочно: он показывает, что инвариант нарушается в
# дереве шестнадцать раз, и каждый раз — по названному разрешению, а не молча.
# Число 53 из 86 и знаменатель 86 проба не трогает: решение, считать ли пустые,
# остаётся владельцу, а проба лишь не даёт добавить к ним семнадцатую тихо.
proba_pustogo_chislitelya() {
  rab=$tmp/пустой-числитель
  korp=flang/proof/чекер/пробы/записи/корпус
  zap_ch=$root/$korp/corpus-alphabet.запись
  zap_n=$root/$korp/corpus-natural.запись
  zap_p=$root/$korp/poddelka-refleksivnost.запись
  for f in "$zap_ch" "$zap_n" "$zap_p"; do
    [ -f "$f" ] || { echo "ПРОБА НЕ СОБРАЛАСЬ: нет «$f»" >&2; return 1; }
  done
  ish_ch=$(grep -a -m1 '^исходник ' "$zap_ch" | cut -d' ' -f2-)
  ish_n=$(grep -a -m1 '^исходник ' "$zap_n" | cut -d' ' -f2-)
  ish_p=$(grep -a -m1 '^исходник ' "$zap_p" | cut -d' ' -f2-)
  bad=0
  for d in ч п з; do
    mkdir -p "$rab/$d/$korp" "$rab/$d/$(dirname "$ish_ch")" "$rab/$d/$(dirname "$ish_n")" \
             "$rab/$d/$(dirname "$ish_p")" "$rab/$d/flang/proof/чекер" || return 1
    cp "$checker" "$rab/$d/flang/proof/чекер/сверщик" || return 1
    cp "$root/$ish_ch" "$rab/$d/$ish_ch" || return 1
    cp "$root/$ish_n" "$rab/$d/$ish_n" || return 1
    cp "$root/$ish_p" "$rab/$d/$ish_p" || return 1
  done
  cp "$zap_ch" "$rab/ч/$korp/corpus-alphabet.запись" || return 1
  cp "$zap_p"  "$rab/з/$korp/poddelka-refleksivnost.запись" || return 1
  # ПОДЛОГ ДЕЛАЕТСЯ ТАК, ЧТОБЫ КРАСНЕЛ РОВНО ОДИН СТОРОЖ — ТОТ, КОТОРЫЙ
  # СТОРОЖИТ ПУСТОТУ. Снять у записи слово «доказано» и оставить следы разбора
  # мало: тогда краснеет ПРИМЕТА снятого вердикта, и проба зеленела бы даже
  # с выключенным сторожем пустоты — проверено мутантом. Поэтому берётся
  # запись, у которой утверждения идут БЕЗ теоремы (`corpus-natural`), и следы
  # снимаются вместе с вердиктом: примета молчит, чекер по-прежнему даёт код 0,
  # а доказанным не числится ничего. У записи с теоремами так нельзя —
  # «следовательно доказано» входит в перечень строк, сличаемый с исходником,
  # и её изъятие дало бы код 1 «НЕ СОШЛОСЬ» по постороннему поводу.
  awk '{ if ($0 ~ /^[ \t]*вердикт доказано[ \t]*$/) { print "  вердикт нет вердикта"; next }
         if ($0 ~ /^[ \t]*правило «/ || $0 ~ /^[ \t]*по объявлению / || $0 ~ /^[ \t]*следовательно доказано/) next
         print }' "$zap_n" > "$rab/п/$korp/corpus-natural.запись" || return 1
  if cmp -s "$zap_n" "$rab/п/$korp/corpus-natural.запись"; then
    echo "ПРОБА НЕ СОБРАЛАСЬ: в «corpus-natural.запись» больше нет «вердикт доказано»" >&2; return 1; fi

  vedom_p() {
    ( cd "$1" && find . -type f \( -name '*.flang' -o -name '*.запись' \) -print0 \
      | LC_ALL=C sort -z | xargs -0 sha256sum ) | sed 's|  \./|\t|' > "$2"
  }
  # Инвариант читается ПО РАЗБОРУ, тем же TSV, каким линейка отвечает всем:
  # запись разряда Р0 (столбец 16) с «доказанными» (столбец 6), равным нулю.
  pustyh_v_r0() { awk -F'\t' 'NR>1 && $16=="Р0" && $6+0==0 {n++} END{print n+0}' "$1"; }

  for d in ч п з; do vedom_p "$rab/$d" "$rab/$d.tsv" || return 1; done

  sh "$self" --корень "$rab/ч" --ведомость "$rab/ч.tsv" --набор корпус \
     --разбор "$rab/ч.разбор" >"$rab/ч.out" 2>&1; k=$?
  if [ "$k" -eq 0 ] && [ "$(pustyh_v_r0 "$rab/ч.разбор")" -eq 0 ]; then
    echo "контроль: честная непустая запись в числителе	ЦЕЛА (Р0, доказанными 7, код 0)"
  else
    echo "контроль: честная непустая запись в числителе	ПРОВАЛ (код $k, пустых в Р0 $(pustyh_v_r0 "$rab/ч.разбор"))"; bad=1; fi

  sh "$self" --корень "$rab/п" --ведомость "$rab/п.tsv" --набор корпус \
     --разбор "$rab/п.разбор" >"$rab/п.out" 2>&1; k=$?
  if [ "$k" -eq 1 ] && [ "$(pustyh_v_r0 "$rab/п.разбор")" -gt 0 ] \
     && /usr/bin/grep -aq 'ПУСТАЯ В ЧИСЛИТЕЛЕ' "$rab/п.out"; then
    echo "подлог: пустая запись просочилась в числитель	ОТВЕРГНУТ (Р0 при доказанными 0, код 1)"
  else
    echo "подлог: пустая запись просочилась в числитель	ПРОШЁЛ — охраны нет (код $k, пустых в Р0 $(pustyh_v_r0 "$rab/п.разбор"))"; bad=1; fi

  sh "$self" --корень "$rab/з" --ведомость "$rab/з.tsv" --набор корпус \
     --разбор "$rab/з.разбор" >"$rab/з.out" 2>&1; k=$?
  if [ "$k" -eq 0 ] && [ "$(pustyh_v_r0 "$rab/з.разбор")" -gt 0 ]; then
    echo "показ: пустая, но названная поимённо	ЗАКОННА (Р0 при доказанными 0, код 0)"
  else
    echo "показ: пустая, но названная поимённо	ПРОВАЛ (код $k) — список разошёлся с корпусом"; bad=1; fi

  [ "$bad" -eq 0 ] && echo "проба на пустой числитель: незаявленная пустота красна, честная зелена, заявленная законна"
  return $bad
}

