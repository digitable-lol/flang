#!/bin/sh
# ЛИНЕЙКА Г4 — «доля корпуса, проверенная независимым чекером».
#
# Гейт Г4 спрашивает долю, а доля есть дробь, и у дроби есть ЗНАМЕНАТЕЛЬ.
# Знаменателей в дереве два, и они отличаются вдвое:
#
#   набор «корпус»  — 86 готовых записей flang/proof/чекер/пробы/записи/корпус
#                     (43 исходника из flang/proof/examples, 35 из
#                      flang/test/fixtures, 8 из flang/proof/map);
#   набор «примеры» — 43 записи, которые ядро печатает из flang/proof/examples
#                     (файлов там 45, на двух печать отказывает).
#
# Линейка НЕ выбирает между ними. Она меряет ОБА одним прибором и печатает оба
# числа рядом, каждое со своим знаменателем. Выбор — за человеком; линейка
# нужна ровно затем, чтобы выбор был дешёвым, а не чтобы его подменить.
#
# Звать:
#   sh flang/proof/доля-корпуса.sh --набор корпус     # 86 готовых записей
#   sh flang/proof/доля-корпуса.sh --набор примеры    # 43, печатает ядром
#   sh flang/proof/доля-корпуса.sh --набор КАТАЛОГ    # любой каталог с *.запись
#   sh flang/proof/доля-корпуса.sh --оба              # корпус и примеры рядом
#   sh flang/proof/доля-корпуса.sh --вложенность      # вложен ли меньший набор в больший
#   sh flang/proof/доля-корпуса.sh --самопроверка     # десять проб на сам прибор
# Ключи:
#   --разбор ФАЙЛ   положить построчный разбор (TSV) в ФАЙЛ
#   --корень ПУТЬ   корень дерева (по умолчанию — два уровня вверх от скрипта)
#   --коммит X      из какого коммита строить ведомость (по умолчанию HEAD)
#   --ведомость Ф   взять готовую ведомость из файла, а не строить из коммита
#   --выписать-ведомость Ф   положить построенную ведомость в файл
#   --подлог        проба порчи на саму ведомость: подделка обязана получить
#                   отказ, честная запись — зелёный
#   --приговор-ядра   ядро судит САМ ФАЙЛ: всякий исходник, названный записью
#                   дерева, обязан получить у ядра код 0. Нужен bootstrap/flang
#   --подлог-ядра   проба порчи на приговор ядра: подделка, проведённая в
#                   коммит вместе с записью, обязана покраснеть
#
# ЦЕНА ЗАМЕРА, И ГДЕ ОНА ЛЕЖИТ. Прогон чекера по 86 записям — единицы секунд.
# Дорога не проверка, а ПЕЧАТЬ: сборка ядра (`make -C bootstrap`, один файл в
# 707 тысяч строк, серийная LTO-сшивка) идёт минуты, и без неё набор «примеры»
# не собрать. Поэтому набор «корпус» меряется всегда и мгновенно, а «примеры» —
# только когда двоичный уже собран. Замер одной записи «за 12–20 минут» — это
# замер сборки, отнесённый на одну запись.
#
# ЧТО МЕРЯЕТСЯ. Чекер даёт четыре исхода: 0 ПРОВЕРЕНО, 1 НЕ СОШЛОСЬ,
# 3 НЕ ПРОВЕРЕНО, 2 кривой вызов. Коды 2, 3 и всё, что больше 3 (126, 127,
# 128+N — оболочка и сигналы), — НЕ приговоры, и линейка считает их ОТДЕЛЬНО.
# Свалить их в «не прошло» значило бы записать молчание прибора в вину записи.
#
# ДВА ПРОГОНА НА КАЖДУЮ ЗАПИСЬ, и в этом весь смысл линейки:
#   «как есть»     — чекер зовётся двумя доводами, как зовёт его оснастка;
#   «с отпечатком» — тем же чекером, но sha256 исходника подан ТРЕТЬИМ доводом,
#                    и берётся он ИЗ ВЕДОМОСТИ КОММИТА, а не из проверяемой
#                    записи: проверяемое не заверяет само себя.
#
# ВЕДОМОСТЬ: ДЕЛО НАЗЫВАЕТ ДЕРЕВО, А НЕ ПОДСУДИМЫЙ (задача 4820).
# До 5 сентября 2026 линейка брала путь исходника из строки «исходник» самой
# проверяемой записи и снимала отпечаток с того, на что запись показала.
# Отпечаток при этом был честный — и в этом была вся беда: подсудимый выбирал
# себе дело. Прогон, показавший изъян: строка «исходник» переписана на
# нетронутую копию вне коммита, а файл дерева `corpus-natural.flang` заменён
# ложью (`минус` вместо `плюс`). Ядро на файле дерева — код 1 с контрпримером
# «нарушено свойство «сумма пары неотрицательна»»; линейка — Р0 «ПРОВЕРЕНО»,
# и общий счёт не дрогнул: 28 из 86 и до, и после.
#
# Теперь дело называет дерево. Ведомость строится ИЗ КОММИТА
# (`git archive` + `sha256sum`, ни одна запись при этом не читается) и держит
# отпечаток каждого `*.flang` и `*.запись` дерева. На каждую запись линейка:
#   1. ищет названный ею путь В ВЕДОМОСТИ — нет там, значит дела нет: Р5;
#   2. сличает файл рабочего дерева с отпечатком коммита — разошлись: Р5;
#   3. подаёт чекеру третьим доводом отпечаток ИЗ ВЕДОМОСТИ;
#   4. если сама запись лежит внутри дерева — требует того же и от неё.
# Р5 — «не берусь»: это не приговор записи, а отказ судить дело, за которое
# дерево не отвечает. Р5 больше нуля роняет прогон кодом 1.
#
# ЧЕГО ВЕДОМОСТЬ НЕ ЗАКРЫВАЕТ, И ЭТО НЕ ЧИНИТСЯ ВЕДОМОСТЬЮ ВООБЩЕ (задача 2390).
# Подделыватель, который ПРОВЁЛ свой файл в коммит вместе с записью, попадёт в
# ведомость честно, отпечаток сойдётся, и линейка его пропустит. Ведомость
# закрывает подмену дела, а не приём в дерево.
#
# Довод, почему это НЕ чинится усилением ведомости, показан прогоном, а не
# рассуждением. Подделка задачи 2390: к честному исходнику дописана функция с
# ЛОЖНЫМ постусловием, а в запись добавлено утверждение о ней с вердиктом «нет
# вердикта». В ЗАПИСИ ПРИ ЭТОМ НЕТ НИ ОДНОГО ЛОЖНОГО ПОЛЯ: путь верен, строк и
# знаков верны, оба многочлена верны, отпечаток256 верен, «нет вердикта» —
# правда. Ядро на файле: код 1, «постусловие «…» ЛОЖНО, и контрпример назван».
# Чекер: код 0 «ПРОВЕРЕНО». Линейка: Р0, Р5 ноль, код 0.
#
# Ведомость удостоверяет «файл такой, каким его положили», а не «положенное
# истинно», и первое здесь ПРАВДА. Ловить такое нечем, кроме одного: ядро
# обязано судить сам файл. Вопрос переходит из «что проверяет чекер» в «кто и
# когда обязан прогнать ядро» — и на это заведён ключ `--приговор-ядра`.
#
# ПРИГОВОР ЯДРА — ОХРАНА ОДНОСТОРОННЯЯ, и это сказано вслух. Код 1 ядра есть
# ОПРОВЕРЖЕНИЕ с названным контрпримером; код 0 ядра доверия не прибавляет
# ничему. Поэтому правило «запись не считается проверенной, если ядро сам файл
# отвергает» умеет только СНИМАТЬ сертификаты и не умеет их выдавать — круга
# «подсудимый заверяет сам себя» здесь нет. Сертификат после правки значит
# «запись сверена И ядро файла не опровергает», и большего не значит: файл с
# ложью, которую ядро не ловит, пройдёт обе двери, и это остаток другой породы.
#
# ПОЧЕМУ НА ОБОЛОЧКЕ, А НЕ НА FLANG. Ведомость обязана строиться там, где
# компилятора нет и не должно быть: работа CI `proof-checker` заведена без
# `make -C bootstrap` нарочно — ответ о записи, полученный тем же двоичным, о
# котором спрашивают, ничего не стоит. Ведомость на flang потребовала бы
# `bootstrap/flang`, то есть ровно того слова, которое мы отказываемся брать.
# Второй прогон отвечает на вопрос «каким станет числитель, если снять первый
# разряд помех — нехватку строки «отпечаток256»». Это ЗАМЕР, а не оценка:
# чекер ставит признак криптопривязки от поданного доводом отпечатка ровно так
# же, как от строки в записи (сверщик.c, main → sverit, ветка `if (zhdyom)`).
#
# РАЗРЯДЫ ПОМЕХ. Код 0 чекер даёт ровно при двух условиях сразу (сверщик.c,
# ветвление вердикта): привязка криптографическая И мест «на слово ядра» ноль.
# Отсюда разряды, и они взаимоисключающи:
#   Р0 — принято кодом 0;
#   Р1 — мешает ТОЛЬКО нехватка «отпечаток256»; мест на слово ядра нет;
#   Р2 — то же плюс места на слово ядра;
#   Р3 — найдено противоречие (код 1);
#   Р4 — не приговор (код 2 либо больше 3).
# Внутри Р2 линейка называет породы мест — своим разбором текста записи, а не
# переписыванием чисел чекера (сверщик.c: bez_teoremy → na_slovo++;
# posylki_na_slovo → na_slovo; sverit_shagi → shagov_na_slovo):
#   П1 «доказано», а теоремы в записи нет         — на утверждение;
#   П2 посылка с названным правилом и без ходов   — на посылку;
#   П3 шаг «по примеру», «по свойству», «по закону» — на шаг;
#   П5 шаг с ЛЮБЫМ иным обоснованием (сегодня «по предположению») — на шаг.
# Ряды номеров у ПОРОД и у ПРОБ самопроверки независимы и совпадают случайно:
# порода П5 — про шаги, проба П5 — про отпечаток доводом. Общего у них ничего.
#
# ПОЧЕМУ П5 — ОТДЕЛЬНАЯ ПОРОДА, А НЕ ХВОСТ П3. У П3 есть путь в «проверено по
# существу» (привязка `пример строка N`, `свойство строка N`), и потому у неё
# есть что вычитать. У П5 такого пути нет вовсе: сверщик её обоснование не
# проигрывает и кладёт место в долг безусловно. Сложить их в одну породу
# значило бы обещать вычет, которого не бывает.
#
# ТОЖДЕСТВО ОДНО, А НЕ ДВА, И ЭТО ПРАВКА 6 СЕНТЯБРЯ 2026 (7104/7102). Прежде
# их было два — отдельно посылочные места, отдельно шаговые:
#   П1+П2 минус снятое = «на слово: посылок и утверждений»;
#   П3    минус «по примеру по существу» = «на слово: шагов».
# Держались они, пока снятое приёмом было только посылочным. Работник 7104
# закрыл рецепт накрутки, и проигранный узел вердикта стал снимать со слова
# ТАКЖЕ шаги своей теоремы, печатая их тем же одним числом «снято со слова
# ядра мест». Разложить это число обратно на посылочное и шаговое нечем —
# значит и сличать надо общей суммой мест:
#
#   П1 + П2 + ВСЕ шаги = «на слово: посылок и утв.» + «на слово: шагов»
#                        + снято + «по примеру по существу»
#                        + «по свойству по существу»
#
# Слева — все места, какие видит текст записи; справа — куда чекер их разложил.
# Замер на своде пяти веток: сходится на всех 86, тогда как два прежних
# тождества расходились на 16, и `precondition` показывала это чище всех —
# поле чекера «шагов» 3 при старой П3, равной нулю.
# Слагаемое «по свойству» до 7102 не бралось вовсе: в корпусе таких снятий
# было ноль, и тождество сходилось случайно.
# Расхождение печатается словом РАСХОЖДЕНИЕ и роняет прогон кодом 1: два прибора
# на одном числе — это проверка, а один прибор — это мнение.
#
# П4 значение «по объявлению да|нет» — считается ОТДЕЛЬНОЙ строкой (9616-Б), но
# В ТОЖДЕСТВО НЕ ВХОДИТ. Маршрут «по объявлению» всегда без теоремы, значит
# место уже подписано текстовым П1 («доказано»+«теоремы нет») — своего
# слагаемого у П4 нет, сложить его с П1 значило бы посчитать одно и то же место
# дважды (первая редакция 9616-Б так и ошиблась: безусловная прибавка роняла
# код 0→3 на 11 записях, где `perepiskoy`/`razborom_celi` уже проиграли ту же
# цель другим приёмом). byType-значение чекер не проверяет ничем — читать его
# нечем (второй сводитель, см. sverit_obyavlenie); П4 лишь считает, сколько
# таких строк есть, для видимости.
# ЕДИНИЦА ДОЛИ. Гейт спрашивает про УТВЕРЖДЕНИЯ, а не про записи, и эти два
# счёта отвечают по-разному до противоположности. Поэтому печатаются оба: доля
# записей и доля утверждений. Знаменатель по утверждениям — поле чекера
# «Числятся доказанными» (записи, где доказанным не числится ничего, в
# знаменатель идти не за чем). Числитель — сумма того же поля по записям,
# принятым кодом 0.
set -u
LC_ALL=C.UTF-8; export LC_ALL

self=$0
root=$(CDPATH= cd -- "$(dirname -- "$self")/../.." && pwd)
nabor=""; dump=""; oba=0; selftest=0; vlozh=0
kommit=HEAD; vedfile=""; vedout=""; podlog=0; prigovor=0; podlog_yad=0

while [ $# -gt 0 ]; do
  case $1 in
    --набор)  nabor=${2:-}; shift 2 ;;
    --разбор) dump=${2:-}; shift 2 ;;
    --корень) root=${2:-}; shift 2 ;;
    --коммит) kommit=${2:-}; shift 2 ;;
    --ведомость) vedfile=${2:-}; shift 2 ;;
    --выписать-ведомость) vedout=${2:-}; shift 2 ;;
    --оба)    oba=1; shift ;;
    --подлог) podlog=1; shift ;;
    --приговор-ядра) prigovor=1; shift ;;
    --подлог-ядра)   podlog_yad=1; shift ;;
    --вложенность)  vlozh=1; shift ;;
    --самопроверка) selftest=1; shift ;;
    *) echo "линейка не знает ключа «$1»" >&2
       echo "ключи: --набор {корпус|примеры|КАТАЛОГ} --оба --вложенность --разбор ФАЙЛ --корень ПУТЬ --самопроверка" >&2
       echo "       --коммит X --ведомость Ф --выписать-ведомость Ф --подлог" >&2
       echo "       --приговор-ядра --подлог-ядра" >&2
       exit 2 ;;
  esac
done

checker=$root/flang/proof/чекер/сверщик
[ -x "$checker" ] || { echo "нет чекера $checker — собрать: make -C flang/proof/чекер" >&2; exit 2; }

tmp=${TMPDIR:-/tmp}/доля-корпуса.$$
mkdir -p "$tmp" || exit 2
trap 'rm -rf "$tmp"' 0 2 3 15

# ── ВЕДОМОСТЬ ДЕРЕВА: отпечатки из КОММИТА, ни одной прочитанной записи ──────
# Строка ведомости: sha256 <TAB> путь от корня дерева. Берётся содержимое
# коммита (`git archive`), а не файлы рабочего дерева: файл на диске
# подделыватель правит, содержимое коммита — нет.
#
# Через `git archive | tar`, а не `git ls-tree` + `git cat-file` на файл:
# замер на этом дереве — 0,28 с против 3,6 с, и `ls-tree --name-only` вдобавок
# ЭКРАНИРУЕТ кириллические пути кавычками, отчего отбор по `*.запись` терял их
# молча (745 файлов вместо 1256).
ved=$tmp/ведомость.tsv
sdelat_vedomost() {
  if [ -n "$vedfile" ]; then
    [ -f "$vedfile" ] || { echo "ведомости нет: $vedfile" >&2; return 2; }
    ved=$vedfile; return 0
  fi
  git -C "$root" rev-parse --verify -q "$kommit^{commit}" >/dev/null 2>&1 || {
    echo "ведомость не построена: «$kommit» не коммит дерева «$root»." >&2
    echo "готовую ведомость можно подать ключом --ведомость ФАЙЛ" >&2
    return 2; }
  d=$tmp/дерево; mkdir -p "$d" || return 2
  git -C "$root" archive "$kommit" -- '*.flang' '*.запись' 2>/dev/null | tar -x -C "$d" || {
    echo "ведомость не построена: git archive «$kommit» не отдал дерево" >&2; return 2; }
  ( cd "$d" && find . -type f -print0 | LC_ALL=C sort -z | xargs -0 sha256sum ) \
    | sed 's|  \./|\t|' > "$ved" || return 2
  # sha256sum помечает косой чертой имена с `\` и переводом строки и экранирует
  # их. Снять пометку значило бы записать в ведомость НЕ ТОТ путь и молча; такое
  # дерево линейка не судит вовсе.
  if /usr/bin/grep -aq '^\\' "$ved"; then
    echo "ведомость не построена: в коммите есть имя с косой чертой или переводом строки" >&2
    return 2; fi
  [ -s "$ved" ] || { echo "ведомость пуста: в коммите «$kommit» нет ни одного *.flang" >&2; return 2; }
  return 0
}

# Отпечаток пути ПО ВЕДОМОСТИ. Пусто — значит дела в дереве нет.
v_sha() { awk -F'\t' -v p="$1" '$2==p{print $1; exit}' "$ved"; }

sdelat_vedomost || exit 2
[ -n "$vedout" ] && cp "$ved" "$vedout"
vedstrok=$(wc -l < "$ved" | tr -d ' ')
vedimya=${vedfile:-"коммит $(git -C "$root" rev-parse --short "$kommit" 2>/dev/null || echo "$kommit")"}

# ── столбец вердикта: РОВНО ОДНА строка, чего бы чекер ни напечатал ─────────
# ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ РУЧКОЙ. Вердикт чекера НЕ ВСЕГДА одна строка: при непустом
# «НЕ ВЗЯЛСЯ» (сверщик.c, main) впереди идёт своя строка, и таких приёмов у
# чекера будет только больше. Прежде столбец брался как `cut -c1-64` прямо с
# многострочного вывода — и перевод строки уезжал ВНУТРЬ поля TSV. Одна запись
# рассыпалась на две, `записей в наборе` тихо росло (86 → 92 на замере Ч363,
# 86 → 87 на одном мутанте), знаменатель «по ЗАПИСЯМ» врал, и НИ ОДНА проба на
# это не краснела: прибор считал не то и молчал.
# Здесь вывод СНАЧАЛА сплющивается в одну строку и лишь потом режется по длине;
# режется он `substr`, а не `cut -c`, потому что `cut -c` считает БАЙТЫ и рвёт
# кириллицу посреди знака (`cut -c1-3` от «абвгд» даёт полтора знака).
odna_stroka() {
  awk '{ s = (NR == 1 ? $0 : s " " $0) }
       END { gsub(/\t/, " ", s); printf "%s", substr(s, 1, 64) }'
}

# ── СУММА ЧИСЕЛ ПО МЕТКЕ: ОДИН КОНВЕЙЕР НА ВСЕ МЕСТА ────────────────────────
# Приёмов, снимающих места со слова ядра, у чекера уже три, и меток, по которым
# линейка складывает его числа, две. Прежде конвейер был написан ТРИЖДЫ: дважды
# в замере и в третий раз внутри пробы П7 — своим текстом, по выдуманной
# строке. Правка настоящего конвейера пробу не красила: она сторожила копию.
# Теперь текст один, и П7 зовёт именно его — на настоящем выводе чекера.
# Число берётся последним словом найденного куска: метка кончается числом, и
# `sed 's/.* //'` режет по последнему пробелу, не зная про её слова ничего.
summa_po_metke() { # метка; текст — на входе
  /usr/bin/grep -ao "$1 [0-9]*" | sed 's/.* //' | awk '{ s += $1 } END { print s + 0 }'
}

# ── породы мест «на слово ядра»: счёт по тексту записи ───────────────────────
# Второй прибор на те же числа. Зеркалит сверщик.c, но читает запись сам.
porody() {
  awk '
    function trim(s){ sub(/^[ \t]+/,"",s); sub(/[ \t]+$/,"",s); return s }
    function yol(s,n,  a,b){ n=n+1; split(s,a,"«"); split(a[n],b,"»"); return b[1] }
    function w(s,n,  a){ split(trim(s),a," "); return a[n] }
    function tail(s,n,  a,i,r){ split(trim(s),a," "); r=""
      for(i=n+1;i<=length(a);i++) r=(r==""?a[i]:r" "a[i]); return r }
    BEGIN{ p1=0; p2=0; p3=0; p4=0; pv=0; inb=0 }
    {
      l=trim($0)
      if (l ~ /^утверждение «/) { inb=1; verd=""; notheorem=0; rule=0; hody=0; debt=0
                                 prav=0; sled=0; obyav=0; next }
      if (!inb) next
      if (l == "конец утверждения") {
        if (rule && !hody) debt++
        p2 += debt
        if (notheorem && verd == "доказано") p1++
        # ПРИМЕТА СНЯТОГО ВЕРДИКТА (задача 7102). Разряд Р0 решают два счётчика
        # чекера, а оба они растут ТОЛЬКО у утверждения с вердиктом «доказано»
        # (сверщик.c, bez_teoremy: `else if (dokazano) s->na_slovo++`). Значит
        # запись переводится из Р2 в Р0 не доводом, а вычёркиванием слова
        # «доказано» — и оба прибора линейки падают синхронно, потому что
        # текстовый счёт пород читает то же слово. Ловится это не счётом, а
        # СТРОЕНИЕМ блока: следы разбора — «правило «…»», «по объявлению …»,
        # «следовательно доказано …» — печать ядра кладёт только там, где
        # вердикт «доказано». Замер 6 сентября 2026: на 251 записи дерева
        # (1029 утверждений) таких мест НОЛЬ, значит примета чиста и краснеет
        # только на подделке. Полного закрытия она не даёт: подделыватель
        # снимет и эти строки — тогда остаётся один свидетель, печать ядра
        # (`--вложенность`), и её цену надо называть отдельно.
        if (verd != "доказано" && (prav || obyav || sled)) pv++
        inb=0; next
      }
      if (l ~ /^вердикт /)    verd = w(l,2)
      if (l == "теоремы нет") notheorem = 1
      if (l ~ /^посылка /) {
        if (rule && !hody) debt++
        rule = (yol(l,3) != "") ? 1 : 0
        hody = 0
      }
      if (l == "ход конец") hody = 1
      # П4: значение «по объявлению да|нет» — вывод изъятия, которое сверщик
      # не переигрывает (сверщик.c: sverit_obyavlenie, врезка про Ч27). Зеркалит
      # `if (*po) s->na_slovo++` буквально: одна строка — одно место, парой с
      # «правило» или нет — сверщик считает его на слово в обоих случаях, и
      # текстовый счёт обязан считать так же, иначе сойдётся не всегда.
      if (l ~ /^по объявлению /) { p4++; obyav=1 }
      # Следы разбора, которые печать кладёт только под вердикт «доказано»:
      # они и держат примету снятого вердикта выше.
      if (l ~ /^правило «/)             prav = 1
      if (l ~ /^следовательно доказано/) sled = 1
      if (l ~ /^шаг /) {
        # ШАГИ СЧИТАЮТСЯ ВСЕ, А НЕ ТРИ ЗНАКОМЫХ ИМЕНИ (7104/7102). До 6 сентября
        # 2026 у чекера была цепочка `по примеру` → `по свойству` → `по закону`,
        # и шаг с ЛЮБЫМ четвёртым обоснованием (в корпусе это «по предположению»,
        # 25 мест) не попадал ни в одну ветвь: ни проверен, ни положен в долг.
        # Через эту дыру шёл рабочий рецепт накрутки Г4 — пять дописанных строк
        # переводили запись из Р2 в Р0, не проиграв ничего. Работник 7104 закрыл
        # её ветвью `else`, которая ловит любое обоснование, и счёт чекера
        # «на слово ядра — шагов» перестал зависеть от списка имён. Текстовое
        # зеркало обязано было поехать следом, иначе тождество двух приборов
        # рушится на честной записи: у `precondition` поле чекера «шагов» 3, а
        # старая П3 давала 0. Поэтому шаги считаются ВСЕ (`vsh`), а три знакомых
        # имени остаются подсчётом внутри — для разбивки, а не для тождества.
        vsh++
        o = tail(l,5)
        if (o ~ /^по примеру/)  { p3++; pr++ }
        if (o ~ /^по свойству/) { p3++; sv++ }
        if (o ~ /^по закону/)   { p3++; zk++ }
      }
    }
    END{ printf "%d %d %d %d %d %d %d %d %d\n", p1, p2, p3, pr+0, sv+0, zk+0, p4, pv, vsh+0 }
  ' "$1"
}

# ── КТО ВПРАВЕ ЛЕЖАТЬ В ЧИСЛИТЕЛЕ ПУСТЫМ (задача 7102) ──────────────────────
