#!/bin/sh
# ЛИНЕЙКА Г4 — «доля корпуса, проверенная независимым чекером».
#
# Гейт Г4 спрашивает долю, а доля есть дробь, и у дроби есть ЗНАМЕНАТЕЛЬ.
# Знаменателей в дереве два, и они отличаются вдвое:
#
#   набор «корпус»  — 86 готовых записей flang/proof/чекер/пробы/записи/корпус
#                     (43 исходника из flang/proof/examples, 35 из
#                      flang/test/fixtures, 8 из flang/proof/map);
#   набор «примеры» — 43 записи, которые ядро печатает из flang/proof/examples
#                     (файлов там 45, на двух печать отказывает).
#
# Линейка НЕ выбирает между ними. Она меряет ОБА одним прибором и печатает оба
# числа рядом, каждое со своим знаменателем. Выбор — за человеком; линейка
# нужна ровно затем, чтобы выбор был дешёвым, а не чтобы его подменить.
#
# Звать:
#   sh flang/proof/доля-корпуса.sh --набор корпус     # 86 готовых записей
#   sh flang/proof/доля-корпуса.sh --набор примеры    # 43, печатает ядром
#   sh flang/proof/доля-корпуса.sh --набор КАТАЛОГ    # любой каталог с *.запись
#   sh flang/proof/доля-корпуса.sh --оба              # корпус и примеры рядом
#   sh flang/proof/доля-корпуса.sh --вложенность      # вложен ли меньший набор в больший
#   sh flang/proof/доля-корпуса.sh --самопроверка     # десять проб на сам прибор
# Ключи:
#   --разбор ФАЙЛ   положить построчный разбор (TSV) в ФАЙЛ
#   --корень ПУТЬ   корень дерева (по умолчанию — два уровня вверх от скрипта)
#   --коммит X      из какого коммита строить ведомость (по умолчанию HEAD)
#   --ведомость Ф   взять готовую ведомость из файла, а не строить из коммита
#   --выписать-ведомость Ф   положить построенную ведомость в файл
#   --подлог        проба порчи на саму ведомость: подделка обязана получить
#                   отказ, честная запись — зелёный
#   --приговор-ядра   ядро судит САМ ФАЙЛ: всякий исходник, названный записью
#                   дерева, обязан получить у ядра код 0. Нужен bootstrap/flang
#   --подлог-ядра   проба порчи на приговор ядра: подделка, проведённая в
#                   коммит вместе с записью, обязана покраснеть
#
# ЦЕНА ЗАМЕРА, И ГДЕ ОНА ЛЕЖИТ. Прогон чекера по 86 записям — единицы секунд.
# Дорога не проверка, а ПЕЧАТЬ: сборка ядра (`make -C bootstrap`, один файл в
# 707 тысяч строк, серийная LTO-сшивка) идёт минуты, и без неё набор «примеры»
# не собрать. Поэтому набор «корпус» меряется всегда и мгновенно, а «примеры» —
# только когда двоичный уже собран. Замер одной записи «за 12–20 минут» — это
# замер сборки, отнесённый на одну запись.
#
# ЧТО МЕРЯЕТСЯ. Чекер даёт четыре исхода: 0 ПРОВЕРЕНО, 1 НЕ СОШЛОСЬ,
# 3 НЕ ПРОВЕРЕНО, 2 кривой вызов. Коды 2, 3 и всё, что больше 3 (126, 127,
# 128+N — оболочка и сигналы), — НЕ приговоры, и линейка считает их ОТДЕЛЬНО.
# Свалить их в «не прошло» значило бы записать молчание прибора в вину записи.
#
# ДВА ПРОГОНА НА КАЖДУЮ ЗАПИСЬ, и в этом весь смысл линейки:
#   «как есть»     — чекер зовётся двумя доводами, как зовёт его оснастка;
#   «с отпечатком» — тем же чекером, но sha256 исходника подан ТРЕТЬИМ доводом,
#                    и берётся он ИЗ ВЕДОМОСТИ КОММИТА, а не из проверяемой
#                    записи: проверяемое не заверяет само себя.
#
# ВЕДОМОСТЬ: ДЕЛО НАЗЫВАЕТ ДЕРЕВО, А НЕ ПОДСУДИМЫЙ (задача 4820).
# До 5 сентября 2026 линейка брала путь исходника из строки «исходник» самой
# проверяемой записи и снимала отпечаток с того, на что запись показала.
# Отпечаток при этом был честный — и в этом была вся беда: подсудимый выбирал
# себе дело. Прогон, показавший изъян: строка «исходник» переписана на
# нетронутую копию вне коммита, а файл дерева `corpus-natural.flang` заменён
# ложью (`минус` вместо `плюс`). Ядро на файле дерева — код 1 с контрпримером
# «нарушено свойство «сумма пары неотрицательна»»; линейка — Р0 «ПРОВЕРЕНО»,
# и общий счёт не дрогнул: 28 из 86 и до, и после.
#
# Теперь дело называет дерево. Ведомость строится ИЗ КОММИТА
# (`git archive` + `sha256sum`, ни одна запись при этом не читается) и держит
# отпечаток каждого `*.flang` и `*.запись` дерева. На каждую запись линейка:
#   1. ищет названный ею путь В ВЕДОМОСТИ — нет там, значит дела нет: Р5;
#   2. сличает файл рабочего дерева с отпечатком коммита — разошлись: Р5;
#   3. подаёт чекеру третьим доводом отпечаток ИЗ ВЕДОМОСТИ;
#   4. если сама запись лежит внутри дерева — требует того же и от неё.
# Р5 — «не берусь»: это не приговор записи, а отказ судить дело, за которое
# дерево не отвечает. Р5 больше нуля роняет прогон кодом 1.
#
# ЧЕГО ВЕДОМОСТЬ НЕ ЗАКРЫВАЕТ, И ЭТО НЕ ЧИНИТСЯ ВЕДОМОСТЬЮ ВООБЩЕ (задача 2390).
# Подделыватель, который ПРОВЁЛ свой файл в коммит вместе с записью, попадёт в
# ведомость честно, отпечаток сойдётся, и линейка его пропустит. Ведомость
# закрывает подмену дела, а не приём в дерево.
#
# Довод, почему это НЕ чинится усилением ведомости, показан прогоном, а не
# рассуждением. Подделка задачи 2390: к честному исходнику дописана функция с
# ЛОЖНЫМ постусловием, а в запись добавлено утверждение о ней с вердиктом «нет
# вердикта». В ЗАПИСИ ПРИ ЭТОМ НЕТ НИ ОДНОГО ЛОЖНОГО ПОЛЯ: путь верен, строк и
# знаков верны, оба многочлена верны, отпечаток256 верен, «нет вердикта» —
# правда. Ядро на файле: код 1, «постусловие «…» ЛОЖНО, и контрпример назван».
# Чекер: код 0 «ПРОВЕРЕНО». Линейка: Р0, Р5 ноль, код 0.
#
# Ведомость удостоверяет «файл такой, каким его положили», а не «положенное
# истинно», и первое здесь ПРАВДА. Ловить такое нечем, кроме одного: ядро
# обязано судить сам файл. Вопрос переходит из «что проверяет чекер» в «кто и
# когда обязан прогнать ядро» — и на это заведён ключ `--приговор-ядра`.
#
# ПРИГОВОР ЯДРА — ОХРАНА ОДНОСТОРОННЯЯ, и это сказано вслух. Код 1 ядра есть
# ОПРОВЕРЖЕНИЕ с названным контрпримером; код 0 ядра доверия не прибавляет
# ничему. Поэтому правило «запись не считается проверенной, если ядро сам файл
# отвергает» умеет только СНИМАТЬ сертификаты и не умеет их выдавать — круга
# «подсудимый заверяет сам себя» здесь нет. Сертификат после правки значит
# «запись сверена И ядро файла не опровергает», и большего не значит: файл с
# ложью, которую ядро не ловит, пройдёт обе двери, и это остаток другой породы.
#
# ПОЧЕМУ НА ОБОЛОЧКЕ, А НЕ НА FLANG. Ведомость обязана строиться там, где
# компилятора нет и не должно быть: работа CI `proof-checker` заведена без
# `make -C bootstrap` нарочно — ответ о записи, полученный тем же двоичным, о
# котором спрашивают, ничего не стоит. Ведомость на flang потребовала бы
# `bootstrap/flang`, то есть ровно того слова, которое мы отказываемся брать.
# Второй прогон отвечает на вопрос «каким станет числитель, если снять первый
# разряд помех — нехватку строки «отпечаток256»». Это ЗАМЕР, а не оценка:
# чекер ставит признак криптопривязки от поданного доводом отпечатка ровно так
# же, как от строки в записи (сверщик.c, main → sverit, ветка `if (zhdyom)`).
#
# РАЗРЯДЫ ПОМЕХ. Код 0 чекер даёт ровно при двух условиях сразу (сверщик.c,
# ветвление вердикта): привязка криптографическая И мест «на слово ядра» ноль.
# Отсюда разряды, и они взаимоисключающи:
#   Р0 — принято кодом 0;
#   Р1 — мешает ТОЛЬКО нехватка «отпечаток256»; мест на слово ядра нет;
#   Р2 — то же плюс места на слово ядра;
#   Р3 — найдено противоречие (код 1);
#   Р4 — не приговор (код 2 либо больше 3).
# Внутри Р2 линейка называет породы мест — своим разбором текста записи, а не
# переписыванием чисел чекера (сверщик.c: bez_teoremy → na_slovo++;
# posylki_na_slovo → na_slovo; sverit_shagi → shagov_na_slovo):
#   П1 «доказано», а теоремы в записи нет         — на утверждение;
#   П2 посылка с названным правилом и без ходов   — на посылку;
#   П3 шаг «по примеру», «по свойству», «по закону» — на шаг.
# Сходятся два прибора не в лоб: чекер УМЕЕТ снимать места со слова ядра, а
# порода места от этого не меняется. Поэтому тождеств два, и в обоих вычитается
# снятое самим чекером, его же числами:
#   П1+П2 минус «снято со слова ядра мест» = «на слово ядра: посылок и утверждений»;
#   П3    минус «Шагов по примеру проверено по существу» = «на слово ядра: шагов».
# Второе вычитание заведено 6 сентября (задача 8802): до перепечатки записей
# корпуса ни один шаг не нёс привязки `пример строка N`, снимать было нечего, и
# тождество без вычитания сходилось само собой. После перепечатки 18 записей из
# 86 разошлись — и разошлись верно.
# Расхождение печатается словом РАСХОЖДЕНИЕ и роняет прогон кодом 1: два прибора
# на одном числе — это проверка, а один прибор — это мнение.
#
# ЕДИНИЦА ДОЛИ. Гейт спрашивает про УТВЕРЖДЕНИЯ, а не про записи, и эти два
# счёта отвечают по-разному до противоположности. Поэтому печатаются оба: доля
# записей и доля утверждений. Знаменатель по утверждениям — поле чекера
# «Числятся доказанными» (записи, где доказанным не числится ничего, в
# знаменатель идти не за чем). Числитель — сумма того же поля по записям,
# принятым кодом 0.
set -u
