  }
  mkdir -p "$rab/Д/$korp" "$rab/Д/flang/proof/examples" "$rab/Д/flang/proof/map" "$rab/Д/flang/proof/чекер" || return 1
  cp "$checker" "$rab/Д/flang/proof/чекер/сверщик" || return 1
