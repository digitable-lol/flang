# ПОДДЕЛКИ ПОШАГОВОГО СВЕДЕНИЯ — настоящим прогоном, а не описанием.
#
#   sh flang/proof/подделки/сведение.sh
#   код 0 — обе честные записи приняты, все подделки отвергнуты;
#   код 1 — что-то из этого неверно, и оно названо строкой.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ПРОГОН. Соседний `прогон.sh` проверяет запись как ОТЧЁТ: те ли
# строки исходника, тот ли шаг, закрыта ли цель. Здесь проверяется другое —
# ПРОИГРЫВАНИЕ СВЕДЕНИЯ: сверщик заново применяет каждый ход к цели и обязан
# упереться, если ход подменён, пропущен или взят не из исходника.
#
# ЧЕСТНАЯ ПОЛОВИНА ОБЯЗАТЕЛЬНА, и её здесь две программы. Проигрыватель,
# отвергающий всё подряд, выглядел бы исправным на одних подделках; принимающий
# всё подряд — хуже отсутствующего.
#
# ── ТРЕТЬЯ ЧЕСТНАЯ ЗАПИСЬ СНИМАЕТСЯ ЯДРОМ ПРЯМО ЗДЕСЬ ───────────────────────
# Здесь стояло: «ядро таких записей не выдаёт, ходы набраны руками». Долг закрыт
# больше чем наполовину, и часть названа числом: `flang check … --proof
# --записать` выписывает ходы сам для ДВУХ видов цели — неотрицательности
# «Т не меньше 0» и равенства «Ф» от результат равно «Ф» от вход — у посылки,
# закрытой шагами автора, — и ниже эта запись снимается прогоном и проигрывается
# тем же сверщиком. Прочие виды целей по-прежнему уезжают одним именем правила,
# и сверщик считает их числом «принято на слово ядра».
#
# ДВЕ ПЕРВЫЕ ЗАПИСИ ОСТАЮТСЯ РУЧНЫМИ, и они не лишние: в них стоят ходы, которых
# ядро не выписывает вовсе — `соседи`, `деление`, `выбор`. Снять их значило бы
# перестать проверять три хода из семи. Ходы `замена` и `закрыть тождеством`
# ядро теперь выписывает само: на `examples/stack.flang` свежая запись ядра
# совпадает со `стопка.запись` во всём, кроме порядка двух развёрток, которые
# переставимы — каждая берёт свой подтерм.
#
# ОТСЮДА ХРУПКОСТЬ, названная заранее: `стопка.запись` привязана отпечатком к
# `flang/proof/examples/stack.flang`. Правка того файла ломает эту запись, и
# ломает ГРОМКО — отпечаток не сойдётся, прогон покраснеет. Чинится так: снять
# свежую запись двоичным (`flang check … --proof --записать`) и перенести в неё
# блоки `ход` из старой, поправив номера строк.
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах.
set -eu

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd)
SVERIT=$KOREN/flang/proof/сверить.sh
STOPKA=$KOREN/flang/proof/examples/stack.flang
STOPKA_Z=$KOREN/flang/proof/подделки/стопка.запись
DELEN=$KOREN/flang/proof/подделки/делением.flang
DELEN_Z=$KOREN/flang/proof/подделки/делением.запись
TOZH=$KOREN/flang/proof/подделки/тождеством.flang
TOZH_Z=$KOREN/flang/proof/подделки/тождеством.запись

RABOTA=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" svedenie.XXXXXX)
trap 'rm -rf "$RABOTA"' EXIT INT TERM

BAD=0
say() { printf '%s\n' "$*"; }

# Один опыт: имя, исходник, запись, ожидаемый код возврата сверщика.
sverit() {
  imya=$1; ish=$2; zap=$3; zhdyom=$4
  vyvod=$(sh "$SVERIT" "$ish" "$zap" 2>&1) && kod=0 || kod=$?
  if [ "$kod" -eq "$zhdyom" ]; then
    say "СОШЛОСЬ  $imya — код $kod"
  else
    say "ПРОВАЛ   $imya — ждали код $zhdyom, получили $kod"
    BAD=$((BAD + 1))
  fi
  say "         $(printf '%s' "$vyvod" | head -1 | cut -c1-260)"
}

# Подделка: имя, исходник, исходная запись, sed-выражение. Правка ОБЯЗАНА что-то
# изменить — иначе опыт ничего не значит, и это ошибка самого прогона.
poddelka() {
  imya=$1; ish=$2; zap=$3; pravka=$4
  fayl=$RABOTA/podd.$$
  sed "$pravka" "$zap" > "$fayl"
  if cmp -s "$zap" "$fayl"; then
    say "ПОДДЕЛКА НЕ СОБРАЛАСЬ: $imya — правка «$pravka» ничего не изменила"
    BAD=$((BAD + 1))
    return 0
  fi
  sverit "$imya" "$ish" "$fayl" 1
}

say "── честная половина: сведение записано пошагово и проигрывается ──"
# ТОЖДЕСТВОМ ИДЁТ ПЕРВЫМ, и это не порядок ради порядка: пара маленькая, её
# запись СНЯТА ЯДРОМ (руками не набрана), и сверка её кончается за минуты — тогда
# как «стопка» ниже в бюджет `сверить.sh` не укладывается вовсе (два прогона
# 31 августа 2026 шли по 8 ч 20 мин и вердикта не дали). Кто гоняет этот прогон
# руками и не может ждать сутки — смотрит на первую строку.
sverit "честная 1: тождество после переписки допущением" "$TOZH" "$TOZH_Z" 0
sverit "честная 2: стопка, семь ходов на четыре посылки" "$STOPKA" "$STOPKA_Z" 0
sverit "честная 3: деление цели по условию и выбор ветви" "$DELEN" "$DELEN_Z" 0

# ── КРУГ ЦЕЛИКОМ: ЯДРО ЗАПИСАЛО — СВЕРЩИК ПРОИГРАЛ ──────────────────────────
# Запись снимается ПРЯМО СЕЙЧАС, а не лежит в дереве: проверяется сегодняшнее
# ядро, а не вчерашняя копия его ответа. Порча идёт по этой же свежей записи —
# сверщик, принимающий всё подряд, хуже отсутствующего.
say ""
say "── круг целиком: ядро записало ходы, сверщик их проиграл ──"
FLANG=${FLANG:-$KOREN/bootstrap/flang}
[ -x "$FLANG" ] || { echo "двоичного нет: $FLANG" >&2; exit 2; }
YADRO=$RABOTA/ядро.запись
"$FLANG" check "$STOPKA" --proof --записать "$YADRO" > /dev/null
HODOV=$(grep -c "^ *ход " "$YADRO" || true)
say "ядро выписало строк «ход»: $HODOV"
if [ "$HODOV" -eq 0 ]; then
  say "ПРОВАЛ   ядро не записало ни одного хода — проигрывать нечего"
  BAD=$((BAD + 1))
fi
sverit "честная 4: запись снята ядром сейчас же и проиграна" "$STOPKA" "$YADRO" 0

say ""
say "── порча свежей записи ядра ──"
poddelka "порча: закон подменён чужим" "$STOPKA" "$YADRO" \
  '0,/закон «литерал неотрицателен»/s//закон «сумма неотрицательных»/'
poddelka "порча: развёртка взята с чужой строки" "$STOPKA" "$YADRO" \
  's/ строка 56$/ строка 58/'
poddelka "порча: снят ход, закрывающий цель допущением" "$STOPKA" "$YADRO" \
  '/ход 3 закрыть дано 1/d'
poddelka "порча: допущение о НЕрекурсивной части" "$STOPKA" "$YADRO" \
  's/ход дано 1 предположение по «х»/ход дано 1 предположение по «г»/'

say ""
say "── подделки: подменённый ход ──"
poddelka "подмена: переписка чужим допущением" "$STOPKA" "$STOPKA_Z" \
  's/ход 4 замена по дано 1/ход 4 замена по дано 2/'
poddelka "подмена: развёртка не того терма" "$STOPKA" "$STOPKA_Z" \
  's|развернуть ⟨«Копия» от (вариант «Звено» с голова равным г и хвост равным х)⟩|развернуть ⟨«Копия» от (вариант «Пусто»)⟩|'
poddelka "подмена: соседи там, где нет соседей" "$STOPKA" "$STOPKA_Z" \
  's|соседи ⟨(«Высота» от х) плюс 1⟩|соседи ⟨«Высота» от х⟩|'
poddelka "подмена: выбор не той ветви" "$DELEN" "$DELEN_Z" \
  's|выбор ⟨если да то («Сколько» от н) плюс 2 иначе («Сколько» от н) плюс 1⟩|выбор ⟨если да то («Сколько» от н) плюс 1 иначе («Сколько» от н) плюс 2⟩|'
poddelka "подмена: деление по тому, что условием не стоит" "$DELEN" "$DELEN_Z" \
  's|деление ⟨(«Сколько» от н) больше 100⟩|деление ⟨«Сколько» от н⟩|'

say ""
say "── подделки: тело взято не оттуда ──"
poddelka "чужая строка: тело другого случая той же функции" "$STOPKA" "$STOPKA_Z" \
  '0,/ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 58/s//ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 56/'
poddelka "чужая строка: тело другой функции" "$STOPKA" "$STOPKA_Z" \
  '0,/ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 58/s//ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 102/'

say ""
say "── подделки: ход пропущен, лишний или переставлен ──"
poddelka "пропуск: снят ход посередине (номера сбиты)" "$STOPKA" "$STOPKA_Z" \
  '/ход 2 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным («Копия» от х))⟩ строка 58/d'
poddelka "пропуск: снят последний ход — цель осталась незакрытой" "$STOPKA" "$STOPKA_Z" \
  '/ход 5 закрыть дано 1/d'
poddelka "лишний: ход, которому нечего закрывать" "$STOPKA" "$STOPKA_Z" \
  's|ход 5 закрыть дано 1|ход 5 закрыть дано 1\
    ход 6 закрыть дано 1|'

# Снятая переписка С ПЕРЕНУМЕРАЦИЕЙ: счёт ходов сойдётся, и упереться сверщик
# обязан НА ДЕЛЕ — на том, что стороны равенства не совпали.
say ""
say "── подделка, которую счётом ходов не поймать ──"
sed -e '/ход 4 замена по дано 1/d' -e 's/ход 5 закрыть тождеством/ход 4 закрыть тождеством/' \
  "$STOPKA_Z" > "$RABOTA/bez-perepiski"
if cmp -s "$STOPKA_Z" "$RABOTA/bez-perepiski"; then
  say "ПОДДЕЛКА НЕ СОБРАЛАСЬ: снятая переписка"
  BAD=$((BAD + 1))
else
  sverit "снята переписка, номера подогнаны" "$STOPKA" "$RABOTA/bez-perepiski" 1
fi

say ""
say "── подделки: ходы цели-равенства ──"
poddelka "снят ход, закрывающий тождеством" "$TOZH" "$TOZH_Z" \
  '0,/ход 2 закрыть тождеством/d'
poddelka "тождество названо там, где стороны разные" "$TOZH" "$TOZH_Z" \
  's/ход 4 замена по дано 1/ход 4 закрыть тождеством/'
poddelka "переписка чужим допущением" "$TOZH" "$TOZH_Z" \
  's/ход 4 замена по дано 1/ход 4 замена по дано 2/'

say ""
say "── подделки: закон и допущение ──"
poddelka "закон, которого сверщик не знает" "$STOPKA" "$STOPKA_Z" \
  '0,/закон «сумма неотрицательных»/s//закон «сумма любых»/'
poddelka "допущение о НЕрекурсивной части — это не индукция, а круг" "$STOPKA" "$STOPKA_Z" \
  '0,/ход дано 1 предположение по «х»/s//ход дано 1 предположение по «г»/'
poddelka "обрыв: «ход конец» снят, сведение не доведено" "$STOPKA" "$STOPKA_Z" \
  '0,/^    ход конец$/s///'

say ""
if [ "$BAD" -eq 0 ]; then
  say "сошлось всё: три честные записи приняты (третью снял сам ядро-компилятор), подделки отвергнуты все"
  exit 0
fi
say "опытов не сошлось: $BAD"
exit 1
