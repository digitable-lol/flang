"""Ч9987: чинит привязка-широкая.py (Ч413)/привязка.py (Ч332) — обе гуляли по
ВСЕМУ дереву `flang ast`, включая функции из чужих файлов (плоское замыкание
импортов), и сверяли их span с текстом ЗАПРОШЕННОГО файла — почти всегда мимо.
Подтверждено: `flang ast <файл>` не несёт поля "файл" на функции вовсе (замерено
Ч9987 на живом дампе), так что различить чужую функцию от своей по самому
дереву нечем. Обходной путь дешевле правки компилятора: имя функции уникально
внутри её файла и всегда объявлено СТРОКОЙ С НАЧАЛА («тотальная функция «Имя»»
или «функция «Имя»») — вытащить эти имена из ИСХОДНОГО ТЕКСТА самого файла
(без компилятора вообще) и пропускать через привязку только те функции дерева,
чьё имя — среди своих. Не решает то же самое для types/legacy/plans/theorems/
measures — они тоже плоское замыкание (см. «откуда типов» в link.flang), но
if-узлы, которые эта проверка ищет, практически всегда живут в теле функции,
не в объявлении типа — вне рассмотрения этой правки, названо прямо, не скрыто.
"""
import json, re, sys, os

СЛОВО = {'or': 'или', 'andAlso': 'и притом'}
ИМЯ_ФУНКЦИИ = re.compile(r'^(?:тотальная |частичная )?функция «([^»]+)»', re.M)


def свои_имена(исходник_путь):
    текст = open(исходник_путь, encoding='utf-8').read()
    return set(ИМЯ_ФУНКЦИИ.findall(текст))


def узлы(n, вид):
    if isinstance(n, dict):
        if n.get('kind') == вид:
            yield n
        for v in n.values():
            yield from узлы(v, вид)
    elif isinstance(n, list):
        for v in n:
            yield from узлы(v, вид)


def узлы_своих_функций(дерево, имена, вид):
    for ф in дерево.get('functions', []):
        if ф.get('name') in имена:
            yield from узлы(ф, вид)


def слово_в(ст, номер, столбец, слово):
    if номер - 1 < 0 or номер - 1 >= len(ст):
        return False
    s = ст[номер - 1]
    i = столбец - 1
    if i < 0 or i + len(слово) > len(s):
        return False
    if s[i:i + len(слово)] != слово:
        return False
    хвост = s[i + len(слово):i + len(слово) + 1]
    return хвост == '' or хвост == ' '


def сравнить_места(a, b):
    if a['line'] != b['line']:
        return a['line'] < b['line']
    return a['column'] <= b['column']


def проверить(дерево_путь, исходник_путь):
    д = json.load(open(дерево_путь, encoding='utf-8'))
    ст = open(исходник_путь, encoding='utf-8').read().split('\n')
    имена = свои_имена(исходник_путь)
    всего_в_дереве = sum(1 for _ in узлы(д, 'if'))
    итог = {'или_и_притом': 0, 'сошлось': 0, 'разошлось': 0, 'не_узлов': 0,
            'не_сошлось': 0, 'не_разошлось': 0, 'без_мест': 0, 'чужих_пропущено': 0}
    беды = []
    свои = list(узлы_своих_функций(д, имена, 'if'))
    итог['чужих_пропущено'] = всего_в_дереве - len(свои)

    for u in свои:
        s = u.get('span')
        t = (u.get('then') or {})
        e = (u.get('else') or {})
        if not (s and t.get('span') and e.get('span')):
            итог['без_мест'] += 1
            continue
        if слово_в(ст, s['line'], s['column'], 'если'):
            continue
        if слово_в(ст, s['line'], s['column'], 'не'):
            итог['не_узлов'] += 1
            причины = []
            cond = u.get('cond') or {}
            if t.get('span') != s or e.get('span') != s:
                причины.append('ветки «не» не синтезированы на месте узла')
            if cond.get('span') and сравнить_места(cond['span'], s):
                причины.append('условие «не» стоит РАНЬШЕ слова «не»')
            if причины:
                итог['не_разошлось'] += 1
                беды.append('  не строка %d столбец %d: %s' % (s['line'], s['column'], '; '.join(причины)))
            else:
                итог['не_сошлось'] += 1
            continue
        сошлось_словом = False
        for ключ, слово_рус in СЛОВО.items():
            if слово_в(ст, s['line'], s['column'], слово_рус):
                сошлось_словом = True
                итог['или_и_притом'] += 1
                причины = []
                if слово_рус == 'или':
                    синтет, настоящая = t, e
                else:
                    настоящая, синтет = t, e
                if синтет.get('span') != s:
                    причины.append('синтезированная ветка не на месте узла')
                конец_слова_столбец = s['column'] + len(слово_рус)
                нс = настоящая.get('span')
                if нс and нс['line'] == s['line'] and нс['column'] < конец_слова_столбец:
                    причины.append('настоящая ветка раньше конца слова «%s»' % слово_рус)
                if нс and нс['line'] < s['line']:
                    причины.append('настоящая ветка выше слова «%s»' % слово_рус)
                if синтет.get('kind') != 'literal':
                    причины.append('синтезированная ветка — не literal (%r)' % синтет.get('kind'))
                if причины:
                    итог['разошлось'] += 1
                    беды.append('  %s строка %d столбец %d: %s' % (слово_рус, s['line'], s['column'], '; '.join(причины)))
                else:
                    итог['сошлось'] += 1
                break
        if not сошлось_словом:
            итог['без_мест'] += 1
    return итог, беды


