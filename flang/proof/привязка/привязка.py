import json, re, sys, os

СЛОВО = {'or': 'или', 'andAlso': 'и притом'}
ИМЯ_ФУНКЦИИ = re.compile(r'^(?:тотальная |частичная )?функция «([^»]+)»', re.M)


def свои_имена(исходник_путь):
    return set(ИМЯ_ФУНКЦИИ.findall(open(исходник_путь, encoding='utf-8').read()))


def узлы(n, вид):
    if isinstance(n, dict):
        if n.get('kind') == вид:
            yield n
        for v in n.values():
            yield from узлы(v, вид)
    elif isinstance(n, list):
        for v in n:
            yield from узлы(v, вид)


def узлы_своих_функций(дерево, имена, вид):
    for ф in дерево.get('functions', []):
        if ф.get('name') in имена:
            yield from узлы(ф, вид)


def слово_в(ст, номер, столбец, слово):
    if номер - 1 < 0 or номер - 1 >= len(ст):
        return False
    s = ст[номер - 1]
    i = столбец - 1
    if i < 0 or i + len(слово) > len(s):
        return False
    if s[i:i + len(слово)] != слово:
        return False
    хвост = s[i + len(слово):i + len(слово) + 1]
    return хвост == '' or хвост == ' '


def колонка_ссылки(ст, номер, столбец):
    """Ч9987c: «если» после «иначе »/«то » той же строки («иначе если…»,
    «то если…» как тело case) — опорная колонка для дочерних то/иначе есть
    колонка ЭТОГО предшествующего слова, не колонка самого «если». Проверено
    на живых flang/self/link.flang:49 (иначе если, опора 5) и
    interpret.flang:347 (то если, опора 7) — дочерние то/иначе стоят на
    опора+2 в обоих случаях, не на (колонка «если»)+2."""
    if номер - 1 < 0 or номер - 1 >= len(ст):
        return столбец
    s = ст[номер - 1]
    i = столбец - 1
    for слово in ('иначе', 'то'):
        j = i - len(слово) - 1
        if j >= 0 and s[j:j + len(слово)] == слово and s[j + len(слово)] == ' ':
            return j + 1
    return столбец


def проверить(дерево_путь, исходник_путь):
    д = json.load(open(дерево_путь, encoding='utf-8'))
    ст = open(исходник_путь, encoding='utf-8').read().split('\n')
    имена = свои_имена(исходник_путь)
    всего_в_дереве = sum(1 for _ in узлы(д, 'if'))
    свои = list(узлы_своих_функций(д, имена, 'if'))
    итог = {'если_всего': 0, 'если_сошлось': 0, 'если_разошлось': 0,
            'в_строку': 0, 'разложенных': 0,
            'или_и_притом': 0, 'или_сошлось': 0, 'или_разошлось': 0,
            'не_узлов': 0, 'не_сошлось': 0, 'не_разошлось': 0,
            'не_опознано': 0, 'чужих_пропущено': всего_в_дереве - len(свои)}
    беды = []

    for u in свои:
        s, t, e = u.get('span'), (u.get('then') or {}), (u.get('else') or {})
        ts, es = t.get('span'), e.get('span')
        if not (s and ts and es):
            итог['не_опознано'] += 1
            continue

        if слово_в(ст, s['line'], s['column'], 'если'):
            if ts['line'] == s['line'] and es['line'] == s['line']:
                итог['в_строку'] += 1
                continue
            итог['если_всего'] += 1
            C = колонка_ссылки(ст, s['line'], s['column'])
            причины = []
            стр_то = [n for n in range(s['line'], ts['line'] + 1) if слово_в(ст, n, C + 2, 'то')]
            if not стр_то:
                причины.append('нет «то» в столбце %d на строках %d–%d' % (C + 2, s['line'], ts['line']))
            стр_иначе = [n for n in range(s['line'], es['line'] + 1) if слово_в(ст, n, C + 2, 'иначе')]
            if not стр_иначе:
                причины.append('нет «иначе» в столбце %d на строках %d–%d' % (C + 2, s['line'], es['line']))
            else:
                ли = стр_иначе[-1]
                if ли == es['line'] and es['column'] < C + 8:
                    причины.append('ветвь раньше конца слова «иначе»')
                if ли < es['line'] and es['column'] <= C + 2:
                    причины.append('отступ ветви не глубже «иначе»')
            if стр_то and стр_иначе and стр_то[-1] > стр_иначе[-1]:
                причины.append('«то» ниже «иначе»')
            if причины:
                итог['если_разошлось'] += 1
                беды.append('  если строка %d столбец %d: %s' % (s['line'], C, '; '.join(причины)))
            else:
                итог['если_сошлось'] += 1
            continue

        if слово_в(ст, s['line'], s['column'], 'не'):
            итог['не_узлов'] += 1
            причины = []
            cond = u.get('cond') or {}
            if ts != s or es != s:
                причины.append('ветки «не» не на месте узла')
            if cond.get('span') and (cond['span']['line'], cond['span']['column']) <= (s['line'], s['column']):
                причины.append('условие «не» раньше слова «не»')
            if причины:
                итог['не_разошлось'] += 1
                беды.append('  не строка %d столбец %d: %s' % (s['line'], s['column'], '; '.join(причины)))
            else:
                итог['не_сошлось'] += 1
            continue

        сошлось_словом = False
        for ключ, слово_рус in СЛОВО.items():
            if слово_в(ст, s['line'], s['column'], слово_рус):
                сошлось_словом = True
                итог['или_и_притом'] += 1
                синтет, настоящая = (t, e) if слово_рус == 'или' else (e, t)
                причины = []
                if синтет.get('span') != s:
                    причины.append('синтезированная ветка не на месте узла')
                нс = настоящая.get('span')
                конец = s['column'] + len(слово_рус)
                if нс and нс['line'] == s['line'] and нс['column'] < конец:
                    причины.append('настоящая ветка раньше конца слова «%s»' % слово_рус)
                if нс and нс['line'] < s['line']:
                    причины.append('настоящая ветка выше слова «%s»' % слово_рус)
                if синтет.get('kind') != 'literal':
                    причины.append('синтезированная ветка — не literal')
                if причины:
                    итог['или_разошлось'] += 1
                    беды.append('  %s строка %d столбец %d: %s' % (слово_рус, s['line'], s['column'], '; '.join(причины)))
                else:
                    итог['или_сошлось'] += 1
                break
        if not сошлось_словом:
            итог['разложенных' if False else 'не_опознано'] += 1
    return итог, беды


