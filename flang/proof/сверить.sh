# Позвать сверщика: сверить записанное доказательство с исходником.
#
#   sh flang/proof/сверить.sh <исходник.flang> <запись>
#   код 0 — сошлось; 1 — не сошлось (беда названа); 2 — кривой вызов.
#
# ── Зачем оболочка ───────────────────────────────────────────────────────────
# Решает всё программа на flang (`сверщик.flang`). Оболочка только ВОЗИТ: у
# `flang io` нет способа принять довод — ни `--args`, ни хвоста строки, —
# поэтому пути приезжают файлом «наряд», а относительные пути `flang io`
# разрешает ОТНОСИТЕЛЬНО ВХОДНОГО ФАЙЛА. Отсюда рабочий каталог: туда кладётся
# наряд и туда же копируется сверщик. Копия побайтово та же — сверщик не ввозит
# ни одного модуля именно затем, чтобы копироваться одним файлом.
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах.
set -eu

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)

if [ "$#" -ne 2 ]; then
  echo "звать: sh flang/proof/сверить.sh <исходник.flang> <запись>" >&2
  exit 2
fi

polnyy() { (CDPATH= cd -- "$(dirname -- "$1")" && printf '%s/%s\n' "$(pwd)" "$(basename -- "$1")"); }

ISHODNIK=$1
ZAPIS=$2
[ -f "$ISHODNIK" ] || { echo "исходника нет: $ISHODNIK" >&2; exit 2; }
[ -f "$ZAPIS" ] || { echo "записи нет: $ZAPIS" >&2; exit 2; }

FLANG=${FLANG:-$KOREN/bootstrap/flang}
[ -x "$FLANG" ] || { echo "двоичного нет: $FLANG" >&2; exit 2; }

# Сам сверщик — тоже перекрываемый путь, и не для красоты: `сверка-правил.sh`
# снимает с него правку и смотрит, покраснеет ли. Сторож, которого не пробовали
# сломать, ничего не сторожит.
SVERSHCHIK=${SVERSHCHIK:-$KOREN/flang/proof/сверщик.flang}
[ -f "$SVERSHCHIK" ] || { echo "сверщика нет: $SVERSHCHIK" >&2; exit 2; }

RABOTA=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" sverka.XXXXXX)
trap 'rm -rf "$RABOTA"' EXIT INT TERM

cp "$SVERSHCHIK" "$RABOTA/сверщик.flang"
printf '%s\n%s\n' "$(polnyy "$ISHODNIK")" "$(polnyy "$ZAPIS")" > "$RABOTA/наряд"

# Хозяин планов отдаёт итог строкой JSON и кладёт туда же весь журнал поручений
# — вместе с текстом прочитанных файлов. Человеку нужен ответ, а не журнал,
# поэтому здесь из ответа берётся ровно вердикт. Код возврата — тот же, что у
# хозяина: 0 — сошлось, 1 — программа сдалась сама и назвала беду.
#
# ── ПРЕДЕЛ ШАГОВ: СТЕН ДВЕ, И СЕГОДНЯ ОСТАНАВЛИВАЕТ НЕ ТА, КОТОРУЮ НАЗЫВАЮТ ──
#
# Здесь стояло `--max-steps 200000000`, и этого НЕ ХВАТАЕТ. На честной записи
# `подделки/стопка.запись` к программе `examples/stack.flang` прогон кончается
# кодом 3: «Обрезать пробелы» исчерпала предел на глубине вызовов 11. Отсюда
# красный ярлык `сведение:проверка`. Соседний `запись:проверка` в двести
# миллионов укладывается — его честная половина (`examples/body-forms.flang`)
# много меньше, и трогать её незачем.
#
# Стены здесь ДВЕ, и разница между ними стоила отдельного разбора:
#
#   БЮДЖЕТ ВЫЧИСЛИТЕЛЯ — ключ `--max-steps` в строке ниже. Считает шаги ПЛАНА.
#                        Перепечатка семени его НЕ меняет — замерено.
#   ПОТОЛОК ДВОИЧНОГО  — `#define FL_MAX_STEPS` в семени, сегодня миллиард.
#                        Вот его перепечатка меняет: новое семя считает ещё и
#                        заряд, а потолок берёт из `scripts/raskrutka.sh`.
#
# Замеры 29 августа 2026. При бюджете в 200 млн прогон тратит 3 020 699 155
# шагов двоичного, из них 773 822 785 витков, — около 15,1 шага двоичного на
# один шаг вычислителя. Нынешнее семя заряд не считает и потому упирается
# витками: миллиард витков кончается примерно на 258 млн шагов вычислителя.
# Проверено прямо, а не выведено: с ключом `--max-steps 400000000` прогон под
# семенем умирает НЕ бюджетом, а потолком — «Шаг плана» съел 1 000 000 001 виток
# из 1 000 000 000.
#
# ОТСЮДА ГЛАВНОЕ: под НЫНЕШНИМ семенем этот прогон зелёным не станет никаким
# ключом — он упрётся в потолок двоичного раньше. Он ЖДЁТ перепечатки, а не
# ломается ею. Следующее семя несёт потолок в триста миллиардов шагов, и при
# 15,1 шага двоичного на шаг вычислителя это около 19,9 млрд шагов вычислителя
# — то есть после перепечатки решает уже ключ ниже, а не потолок.
#
# ОТКУДА ЧЕТЫРЕ МИЛЛИАРДА. Снизу: прогон прибором, у которого потолок 20 млрд,
# прошёл 346 млн шагов вычислителя и на них НЕ кончился — значит честная работа
# заведомо дороже трёхсот миллионов. Сверху: 4 млрд впятеро ниже той самой
# стены в 19,9 млрд, то есть зациклившийся план всё ещё ловится этим ключом, а
# не потолком двоичного, и ловится с понятным сообщением.
#
# ЧЕГО ЗДЕСЬ НЕ СНЯТО, И ЭТО НАЗВАНО. Сколько шагов нужно на ВЕСЬ прогон —
# неизвестно: замер до конца не дошёл. И сама цена подозрительна: соседний
# `сличить.sh` делает работу того же рода на том же `stack.flang` за
# 338 302 508 шагов двоичного и доходит до конца, а здесь их уже больше пяти
# миллиардов. Похоже, дорог не предел, а сам сверщик; это отдельная работа, и
# число выше придётся вывести заново, когда она будет сделана.
VYVOD=$("$FLANG" io "$RABOTA/сверщик.flang" --max-steps 4000000000 --max-depth 20000 2>&1) && KOD=0 || KOD=$?

case "$VYVOD" in
  '{"error":'*) printf '%s\n' "$VYVOD" | sed 's/^{"error":"\([^"]*\)".*/НЕ СОШЛОСЬ: \1/' ;;
  '{"plan":'*)  printf '%s\n' "$VYVOD" | sed 's/^{"plan":"[^"]*","result":"\([^"]*\)".*/\1/' ;;
  *)            printf '%s\n' "$VYVOD" ;;
esac

exit "$KOD"
