    say "        sha256sum flang/proof/ПРАВИЛА-ВЫВОДА.tsv | cut -d' ' -f1 > flang/proof/ПРАВИЛА-ВЫВОДА.отпечаток"
  fi
  say ""
}

# ═══════════════ С-5: ИМЕНА ВСТРОЕННОГО ОТРЕЗКА (6203, ADR-0026) ═══════════════
# Отрезок [0, 2⁵³−1] зовётся несколькими именами, и список этот — знание о языке:
# он живёт и в ядре («Названо натуральным»), и в сверщике на C (НАТУРАЛЬНОЕ[]).
# До 9 сентября 2026 ядро знало шесть имён, сверщик — два, и честный файл с
# «натуральное» уходил на слово ядра: дубль разошёлся молча. Таблица
# flang/proof/ОТРЕЗКИ.tsv объявляет список, а этот сторож сличает три копии в
# обе стороны — тем же приёмом, каким С-1 сличает имена правил. Потолок таблицы
# обязан равняться «Точному потолку» ядра (та же копия, что стережёт С-2).
storozh_5() {
  say "── С-5: имена встроенного отрезка — таблица, ядро, сверщик на C ──"
  grep -v '^#' "$OTREZKI" | awk -F'\t' '$1 != "имя" && NF >= 5 { print $1 }' | sort -u > "$RABOTA/отрезки-таблица"
  # Ядро: тело «Названо натуральным» — один строковый литерал "|а|б|…|".
  awk '/^тотальная функция «Названо натуральным»$/ { v = 1; next }
       v && /"\|/ { s = $0; sub(/^[^"]*"\|/, "", s); sub(/\|".*$/, "", s)
                    n = split(s, a, "|"); for (i = 1; i <= n; i++) if (a[i] != "") print a[i]; exit }' \
    "$YADRO" | sort -u > "$RABOTA/отрезки-ядро"
  # Сверщик на C: литералы массива НАТУРАЛЬНОЕ[] — тем же разбором, что ПРАВИЛА[].
  awk '/static const char \*НАТУРАЛЬНОЕ\[\] = \{/ { v = 1; next } v && /^\};/ { exit }
       v { s = $0; while (match(s, /"[^"]*"/)) { t = substr(s, RSTART + 1, RLENGTH - 2); if (t != "") print t; s = substr(s, RSTART + RLENGTH) } }' \
    "$SVERSHCHIK_C" | sort -u > "$RABOTA/отрезки-c"
  N=$(grep -c . < "$RABOTA/отрезки-таблица"); NY=$(grep -c . < "$RABOTA/отрезки-ядро"); NC=$(grep -c . < "$RABOTA/отрезки-c")
  say "   имён: в таблице $N, у ядра $NY, у сверщика на C $NC"
  [ "$N" -ge 2 ]  || plocho "таблица ОТРЕЗКИ.tsv вычитана в $N имён — разбор сломан либо таблица пуста"
  [ "$NY" -ge 2 ] || plocho "из ядра вычитано $NY имён — разбор «Названо натуральным» сломан"
  [ "$NC" -ge 2 ] || plocho "из сверщика вычитано $NC имён — массива НАТУРАЛЬНОЕ[] нет либо разбор сломан"
  if ! diff -q "$RABOTA/отрезки-таблица" "$RABOTA/отрезки-ядро" > /dev/null; then
    plocho "имена отрезка: таблица разошлась с ядром («Названо натуральным»):"
    diff "$RABOTA/отрезки-таблица" "$RABOTA/отрезки-ядро" | sed 's/^/          /'
  fi
  if ! diff -q "$RABOTA/отрезки-таблица" "$RABOTA/отрезки-c" > /dev/null; then
    plocho "имена отрезка: таблица разошлась с НАТУРАЛЬНОЕ[] сверщика на C:"
    diff "$RABOTA/отрезки-таблица" "$RABOTA/отрезки-c" | sed 's/^/          /'
  fi
  # Дно и потолок: у каждого имени дно 0, потолок — «Точный потолок» ядра.
  P_YADRO=$(awk '/^тотальная функция «Точный потолок»$/ { v = 1; next }
                 v && /^  [0-9]+$/ { gsub(/ /, "", $0); print; exit }' "$YADRO")
  grep -v '^#' "$OTREZKI" | awk -F'\t' -v p="$P_YADRO" '$1 != "имя" && NF >= 5 {
      if ($2 != "0") printf "БЕДА\tимя «%s»: дно «%s», а у встроенного отрезка дно 0\n", $1, $2
      if ($3 != p)   printf "БЕДА\tимя «%s»: потолок «%s», а «Точный потолок» ядра — %s\n", $1, $3, p
      if ($4 != "целое" && $4 != "дробное") printf "БЕДА\tимя «%s»: целость «%s» вне {целое, дробное}\n", $1, $4
      if ($1 in bylo) printf "БЕДА\tимя «%s» стоит в таблице дважды\n", $1
      bylo[$1] = 1 }' > "$RABOTA/с5"
  while IFS="	" read -r metka text; do
    [ "${metka:-}" = "БЕДА" ] && plocho "$text"
  done < "$RABOTA/с5"
  say ""
}

# ═══════════ С-6: ПОТОЛОК ДОВЕРЕННОЙ БАЗЫ СВЕРЩИКА (К9, кластер 6202/6203) ═══════════
# Сверщик — то, чему верят вместо ядра, и верят ему РАЗМЕРОМ. Размер стережётся
# двумя числами из flang/proof/чекер/ХРАПОВИК.txt: строк в сверщик.c не больше
# потолка (абсолютного: считаются все строки, чьи бы правки ни лежали), примитивов
# языка в ПРИМИТИВЫ[] — ровно столько, сколько названо. Потолок двигает только
# владелец решением; ячейка, которая не влезает, останавливается, а не растит его.
storozh_6() {
  say "── С-6: потолок доверенной базы — строк и примитивов сверщика на C ──"
  P_STROK=$(awk '$1 == "строк" { print $2; exit }' "$POTOLOK")
  P_PRIM=$(awk '$1 == "примитивов" { print $2; exit }' "$POTOLOK")
  STROK=$(wc -l < "$SVERSHCHIK_C" | tr -d ' ')
  PRIM=$(awk '/static const char \*ПРИМИТИВЫ\[\] = \{/ { v = 1; next } v && /^\};/ { exit }
              v { s = $0; while (match(s, /"[^"]*"/)) { t = substr(s, RSTART + 1, RLENGTH - 2); if (t != "") n++; s = substr(s, RSTART + RLENGTH) } }
              END { print n + 0 }' "$SVERSHCHIK_C")
  case "$P_STROK" in *[!0-9]*|"") plocho "храповик не называет потолка строк: «$P_STROK»"; P_STROK=0 ;; esac
  case "$P_PRIM"  in *[!0-9]*|"") plocho "храповик не называет числа примитивов: «$P_PRIM»"; P_PRIM=0 ;; esac
  say "   сверщик.c: $STROK строк, до потолка $((P_STROK - STROK)) (потолок $P_STROK); примитивов $PRIM (названо $P_PRIM)"
  [ "$STROK" -le "$P_STROK" ] || plocho "сверщик.c вырос до $STROK строк при потолке $P_STROK — доверенная база выше мандата на $((STROK - P_STROK)); потолок двигает владелец решением, не ячейка"
  [ "$PRIM" -eq "$P_PRIM" ]   || plocho "в ПРИМИТИВЫ[] сверщика $PRIM имён при названных $P_PRIM — граница доверия сдвинута молча"
  say ""
}

# ═══════════════════════ пробы на подлог ═══════════════════════
proba() {
  nomer=$1; chto=$2; shift 2
  vyvod=$("$@" 2>&1) && kod=0 || kod=$?
  if [ "$kod" -eq 1 ]; then
    prichina=$(printf '%s\n' "$vyvod" | grep -m1 '^КРАСНО' | cut -c1-150)
    say "СОШЛОСЬ  подлог $nomer ($chto) — код 1"
    say "         $prichina"
  else
    say "ПРОВАЛ   подлог $nomer ($chto) — ждали код 1, получили $kod"
    BEDA=$((BEDA + 1))
  fi
}

podlogi() {
  say "── восемь проб на подлог: портятся КОПИИ, дерево не тронуто ──"
  say ""
  SAM=$KOREN/flang/proof/сверка-ведомости.sh
  D=$RABOTA/подлог
  mkdir -p "$D"

  # 1. С-1: имя правила, которого ядро не ставит.
  cp "$VEDOMOST" "$D/1.tsv"
  sed -i '$a\Х1\tН\tправило\tразбор цели по настроению\t—\tΓ ⊢ Т : неотр\t—\tстрелка\tстрелка\t0\tproof-kernel.flang:2309 «Литерал неотрицателен»\tкод' "$D/1.tsv"
  proba 1 "лишнее имя правила в ведомости" \
    env VEDOMOST="$D/1.tsv" OTPECHATOK="$OTPECHATOK" FLANG=/несуществующий sh "$SAM" --сторож С-1

  # 2. С-1: опора съехала на строку.
  cp "$VEDOMOST" "$D/2.tsv"
  sed -i 's/proof-kernel\.flang:2309 «Литерал неотрицателен»/proof-kernel.flang:2310 «Литерал неотрицателен»/' "$D/2.tsv"
  proba 2 "опора правила указывает не на ту строку ядра" \
    env VEDOMOST="$D/2.tsv" OTPECHATOK="$OTPECHATOK" FLANG=/несуществующий sh "$SAM" --сторож С-1

  # 3. С-2: имя правила стоит дважды.
  cp "$VEDOMOST" "$D/3.tsv"
  grep -m1 '^Н5	' "$VEDOMOST" >> "$D/3.tsv"
  proba 3 "имя правила в ведомости дважды" \
    env VEDOMOST="$D/3.tsv" OTPECHATOK="$OTPECHATOK" sh "$SAM" --сторож С-2

  # 4. С-2: точный потолок ядра изменён на единицу (находка 2 ADR-0022 §2.4).
  cp "$YADRO" "$D/ядро.flang"
  sed -i 's/^  9007199254740991$/  9007199254740990/' "$D/ядро.flang"
  cmp -s "$YADRO" "$D/ядро.flang" && { say "ПРОВАЛ   подлог 4 не собрался: потолок в копии ядра не изменился"; BEDA=$((BEDA + 1)); } || \
  proba 4 "точный потолок ядра изменён на единицу" \
    env VEDOMOST="$VEDOMOST" OTPECHATOK="$OTPECHATOK" YADRO="$D/ядро.flang" sh "$SAM" --сторож С-2

  # 5. С-3: у правила убрана одна посылка из логической колонки.
  cp "$VEDOMOST" "$D/5.tsv"
  awk -F'\t' 'BEGIN{OFS="\t"} $1=="Н5"{$5="1) Л : неотр"} {print}' "$VEDOMOST" > "$D/5.tsv"
  cmp -s "$VEDOMOST" "$D/5.tsv" && { say "ПРОВАЛ   подлог 5 не собрался"; BEDA=$((BEDA + 1)); } || \
  proba 5 "у правила Н5 убрана одна посылка" \
    env VEDOMOST="$D/5.tsv" OTPECHATOK="$OTPECHATOK" sh "$SAM" --сторож С-3

  # 6. С-3: конструкция вне закрытых девяти.
  awk -F'\t' 'BEGIN{OFS="\t"} $1=="Н6"{$9="копроизведение+монада"} {print}' "$VEDOMOST" > "$D/6.tsv"
  proba 6 "категорная колонка зовёт конструкцию вне закрытых девяти" \
    env VEDOMOST="$D/6.tsv" OTPECHATOK="$OTPECHATOK" sh "$SAM" --сторож С-3

  # 8. С-3, ПРОБА ПО СУЩЕСТВУ: посылку убрали И число входов поправили, так что
  #    расходятся РОВНО две нотации, и ничто больше. Без неё подлог 5 доказывал
  #    бы лишь то, что сторож умеет считать до двух.
  awk -F'\t' 'BEGIN{OFS="\t"} $1=="Н5"{$5="1) Л : неотр"; $10="1"} {print}' "$VEDOMOST" > "$D/8.tsv"
  proba 8 "посылка убрана и «входов» поправлено — расходятся только нотации" \
    env VEDOMOST="$D/8.tsv" OTPECHATOK="$OTPECHATOK" sh "$SAM" --сторож С-3

  # 9. С-5: из таблицы имён отрезка убрано одно имя — ядро и сверщик его знают.
  grep -v '^натуральное	' "$OTREZKI" > "$D/9.tsv"
  proba 9 "имя отрезка убрано из таблицы, ядро его знает" \
    env OTREZKI="$D/9.tsv" VEDOMOST="$VEDOMOST" OTPECHATOK="$OTPECHATOK" sh "$SAM" --сторож С-5

  # 10. С-6: копия сверщика на одну строку выше потолка.
  P10=$(awk '$1 == "строк" { print $2; exit }' "$POTOLOK")
  cp "$SVERSHCHIK_C" "$D/10.c"
  while [ "$(wc -l < "$D/10.c" | tr -d ' ')" -le "$P10" ]; do printf '/* строка сверх потолка */\n' >> "$D/10.c"; done
  proba 10 "сверщик.c на строку выше потолка ($(wc -l < "$D/10.c" | tr -d ' ') при $P10)" \
    env SVERSHCHIK_C="$D/10.c" POTOLOK="$POTOLOK" sh "$SAM" --сторож С-6

  # 11. С-6: в ПРИМИТИВЫ[] дописан шестнадцатый примитив.
  sed 's/^static const char \*ПРИМИТИВЫ\[\] = {$/&\n  "шестнадцатый",/' "$SVERSHCHIK_C" > "$D/11.c"
  proba 11 "в ПРИМИТИВЫ[] сверщика дописано имя" \
    env SVERSHCHIK_C="$D/11.c" POTOLOK="$POTOLOK" sh "$SAM" --сторож С-6

  # 7. С-4: ведомость правлена, отпечаток при ней нет.
  cp "$VEDOMOST" "$D/7.tsv"
  printf '# правка без пересъёма отпечатка\n' >> "$D/7.tsv"
  proba 7 "ведомость правлена, отпечаток не переснят" \
    env VEDOMOST="$D/7.tsv" OTPECHATOK="$OTPECHATOK" sh "$SAM" --сторож С-4
  say ""
}

