# ШЕСТЬ СТОРОЖЕЙ НАД ВЕДОМОСТЬЮ ПРАВИЛ ВЫВОДА (flang/proof/ПРАВИЛА-ВЫВОДА.tsv),
# таблицей имён отрезка (flang/proof/ОТРЕЗКИ.tsv) и размером сверщика на C.
#
#   sh flang/proof/сверка-ведомости.sh              все шесть
#   sh flang/proof/сверка-ведомости.sh --сторож С-2 один по имени
#   sh flang/proof/сверка-ведомости.sh --подлоги    одиннадцать проб на подлог
#   код 0 — сошлось; 1 — разошлось, и расхождение названо; 2 — кривой вызов.
#
# ── ЧТО СТЕРЕЖЁТСЯ ──────────────────────────────────────────────────────────
# С-1 ПОЛНОТА. Каждая строка ведомости опирается на НАСТОЯЩЕЕ место ядра
#     (колонка «опора»: функция с таким именем стоит в `proof-kernel.flang` на
#     этой строке), а имена в колонке «правило_ядра» — ровно те, что ядро
#     СПОСОБНО положить в поле `rule`, и они же стоят в закрытых списках ОБОИХ
#     сверщиков. В обе стороны: имя ведомости вне набора ядра — красно; имя
#     ядра, ни разу не названное ведомостью, — красно.
# С-2 НЕПРОТИВОРЕЧИВОСТЬ ЗАПИСИ. Двенадцать колонок у каждой строки, ни одной
#     пустой, имена ЕДИНСТВЕННЫ, значения закрытых колонок из закрытых списков,
#     счёт по ADR-0022 §3 сходится (55 правил и 5 запретов), и заодно — что две
#     копии точного потолка (ядро и типизатор) не разошлись.
# С-3 СОГЛАСИЕ ДВУХ НОТАЦИЙ, И ОНО ПРОВЕРЯЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ. Каждая
#     посылка логической записи обязана иметь НАЗВАННОЕ МЕСТО в категорной:
#     посылка i упоминается там как ⟨i⟩. Сторож требует РАВЕНСТВА множеств:
#     ссылок ровно столько же, сколько посылок, и ни одной лишней. Убери
#     посылку — осиротеет ссылка; допиши — останется неупомянутой; в обоих
#     случаях красно с названным правилом. Плюс: колонка «конструкции» берётся
#     только из закрытых девяти (ADR-0022 §5, сторож С-2 задачи 6130), и третьим
#     свидетелем стоит число в колонке «входов».
#     ЧЕГО ЭТОТ СТОРОЖ НЕ ГОВОРИТ: что категорная запись ВЕРНА. Он говорит, что
#     она полна относительно логической и не ссылается на пустое место. Верность
#     самих стрелок судится парными образцами (ADR-0022 §5, сторож С-4), и их
#     здесь нет — см. «чего не проверено» в конце вывода.
# С-4 ОТПЕЧАТОК НЕ РАЗОШЁЛСЯ. sha256 ведомости против записанного в
#     `ПРАВИЛА-ВЫВОДА.отпечаток`. Запись доказательства ссылается на ведомость
#     этим числом (ADR-0022 §8А, п. 5), и молчаливая правка ведомости обесценила
#     бы всякую ссылку.
#     ОТПЕЧАТОК ЭТОТ СТОРОЖ НЕ ПЕРЕСНИМАЕТ НИКОГДА. Прибор, гасящий свою же
#     красноту, — известная порода беды (AGENTS.md, «чего этот отряд не имеет
#     права повторить», п. 4). Переснять — отдельное действие руками:
#         sha256sum flang/proof/ПРАВИЛА-ВЫВОДА.tsv | cut -d' ' -f1 \
#           > flang/proof/ПРАВИЛА-ВЫВОДА.отпечаток
# С-5 ИМЕНА ВСТРОЕННОГО ОТРЕЗКА (задача 6203, ADR-0026). Таблица
#     `flang/proof/ОТРЕЗКИ.tsv`, «Названо натуральным» ядра и НАТУРАЛЬНОЕ[] сверщика
#     на C — один и тот же список, сличается в обе стороны; потолок таблицы равен
#     «Точному потолку» ядра. До 9 сентября 2026 ядро знало шесть имён, сверщик —
#     два, и расхождение не видел никто.
# С-6 ПОТОЛОК ДОВЕРЕННОЙ БАЗЫ (К9, кластер 6202/6203). Строк в `сверщик.c` не
#     больше названного в `flang/proof/чекер/ХРАПОВИК.txt` (абсолютно, чьи бы
#     правки ни лежали), примитивов языка в ПРИМИТИВЫ[] — ровно столько, сколько
#     названо. Потолок двигает владелец решением; сторож его не переснимает.
#
# ── ВЕЛИЧИНА ВЕДОМОСТИ, ПРИМЕТОЙ, А НЕ НА ПАМЯТЬ ────────────────────────────
# В ведомости 166 строк файла, из них 79 строк правил: 67 правил вывода и 12
# запретов. По ADR-0022 §3 из них 55 и 5; остальные девятнадцать найдены в коде и
# в ADR §3 не названы. Счёт по ADR стережёт сторож С-2, счёт по файлу — примета:
# СНЯТО 2026-09-09 строк flang/proof/ПРАВИЛА-ВЫВОДА.tsv = 166
#
# ── ЭТОТ ФАЙЛ — ДОЛГ, И ЭТО СКАЗАНО ВСЛУХ ───────────────────────────────────
# Сторож на оболочке долгом БЫВАЕТ: `scripts/tree-inventory.flang:140–190` даёт
# ровно одно основание для не-долга — КРУГ (файл судит или собирает то, чем его
# самого пришлось бы исполнять), и здесь круга нет: ведомость читается awk-ом
# только потому, что двоичного в этом дереве не собрано. Дом у этой проверки —
# `flang/proof/сверка-правил.flang` (задача 6130, п. 4 «расширить, не писать
# заново»), и переезд туда снимет одну строку долга оболочки. Пока не переехал —
# долг вырос на файл и на 447 строк, и опись это несёт:
# docs/tree-inventory.md строки 1, 6, 68, 131, 187.
#
# ── ПОЧЕМУ БЕЗ ДВОИЧНОГО ────────────────────────────────────────────────────
# Сторож читается `awk`-ом и работает в дереве, где `bootstrap/flang` не собран
# (33 МБ C, 5–6 минут). Там, где двоичный ЕСТЬ, сторож зовёт соседа
# `сверка-правил.sh --только-первая` и требует согласия с ним: сосед — власть по
# вопросу «набор ядра против списка сверщика», и второе прочтение того же
# вопроса заведено не вместо него, а поверх.
#
# ── ПРОБЫ НА ПОДЛОГ ─────────────────────────────────────────────────────────
# Сторож, которого нельзя покрасить, неотличим от выключенного
# (`scripts/storozha-bez-podloga.sh`). Поэтому `--подлоги` портит КОПИИ входов —
# исходное дерево не трогается ни разу — и требует, чтобы на каждой порче
# сторож дал код 1 с названной причиной. Пути входов перекрываются извне
# НАРОЧНО, тем же приёмом, что у `сверка-правил.sh`.
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах.
set -eu

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
VEDOMOST=${VEDOMOST:-$KOREN/flang/proof/ПРАВИЛА-ВЫВОДА.tsv}
OTPECHATOK=${OTPECHATOK:-$KOREN/flang/proof/ПРАВИЛА-ВЫВОДА.отпечаток}
YADRO=${YADRO:-$KOREN/flang/self/proof-kernel.flang}
TIPY=${TIPY:-$KOREN/flang/self/types.flang}
SVERSHCHIK_C=${SVERSHCHIK_C:-$KOREN/flang/proof/чекер/сверщик.c}
SVERSHCHIK_F=${SVERSHCHIK_F:-$KOREN/flang/proof/сверщик.flang}
FLANG=${FLANG:-$KOREN/bootstrap/flang}

ODIN=""
PODLOGI=0
for kluch in ${1+"$@"}; do
  case "$kluch" in
    --подлоги) PODLOGI=1 ;;
    --сторож) : ;;
    С-1|С-2|С-3|С-4|С-5|С-6) ODIN=$kluch ;;
    *)
      printf '%s\n' "не знаю ключа: $kluch" >&2
      printf '%s\n' "звать: sh flang/proof/сверка-ведомости.sh [--сторож С-1|С-2|С-3|С-4|С-5|С-6] [--подлоги]" >&2
      exit 2 ;;
  esac
done

# С-5 (6203): имена встроенного отрезка — таблица, ядро и сверщик на C.
OTREZKI=${OTREZKI:-$KOREN/flang/proof/ОТРЕЗКИ.tsv}
# С-6 (К9): потолок доверенной базы сверщика — строк и примитивов.
POTOLOK=${POTOLOK:-$KOREN/flang/proof/чекер/ХРАПОВИК.txt}

for f in "$VEDOMOST" "$OTPECHATOK" "$YADRO" "$TIPY" "$SVERSHCHIK_C" "$SVERSHCHIK_F" "$OTREZKI" "$POTOLOK"; do
  [ -f "$f" ] || { printf '%s\n' "файла нет: $f" >&2; exit 2; }
done

RABOTA=$(mktemp -d "${FLANG_TMP:-/tmp}/vedomost.XXXXXX")
trap 'rm -rf "$RABOTA"' EXIT INT TERM
BEDA=0
say() { printf '%s\n' "$*"; }
plocho() { printf 'КРАСНО  %s\n' "$*"; BEDA=$((BEDA + 1)); }

# ── набор имён, которые ядро способно положить в поле `rule` ────────────────
# Поле заполняет РОВНО одна функция — «Принято правилом» (proof-kernel.flang:5519);
# довод у неё либо вызов функции-имени без доводов, чьё тело есть один строковый
# литерал, либо пустая строка. Тот же разбор, что у `сверка-правил.flang`.
nabor_yadra() {
  awk '
    /«Принято правилом» от \(«/ {
      s = $0
      while (match(s, /«Принято правилом» от \(«[^»]+»\)/)) {
        t = substr(s, RSTART, RLENGTH); sub(/.*от \(«/, "", t); sub(/»\)$/, "", t)
        nuzhno[t] = 1; s = substr(s, RSTART + RLENGTH)
      }
    }
    { stroka[NR] = $0 }
    END {
      for (i = 1; i <= NR; i++) {
        if (stroka[i] !~ /^(тотальная )?функция «/) continue
        f = stroka[i]; sub(/^(тотальная )?функция «/, "", f); sub(/».*$/, "", f)
        if (!(f in nuzhno)) continue
        for (j = i + 1; j <= NR && j < i + 20; j++)
          if (stroka[j] ~ /^  "/) { v = stroka[j]; sub(/^  "/, "", v); sub(/"$/, "", v); print v; break }
      }
    }' "$YADRO" | sort -u
}

# Закрытый список сверщика на C: между строкой `static const char *ПРАВИЛА[] = {`
# и `};` берутся все литералы в кавычках.
spisok_c() {
  awk '/static const char \*ПРАВИЛА\[\] = \{/ { v = 1; next } v && /^\};/ { exit }
       v { s = $0; while (match(s, /"[^"]*"/)) { t = substr(s, RSTART + 1, RLENGTH - 2); if (t != "") print t; s = substr(s, RSTART + RLENGTH) } }' \
    "$SVERSHCHIK_C" | sort -u
}

# Тот же список на flang: от строки `тотальная функция «Правила сведения»` до
# строки со скобкой «]». Разбор дословно тот же, что у соседа.
spisok_f() {
  awk '/^тотальная функция «Правила сведения»$/ { v = 1; next } v && /\]/ { p = 1 }
       v { s = $0; while (match(s, /"[^"]*"/)) { t = substr(s, RSTART + 1, RLENGTH - 2); if (t != "") print t; s = substr(s, RSTART + RLENGTH) } }
       p { exit }' "$SVERSHCHIK_F" | sort -u
}

stroki() { grep -v '^#' "$VEDOMOST"; }

# ═══════════════════════════ С-1: ПОЛНОТА ═══════════════════════════
storozh_1() {
  say "── С-1: полнота — ведомость против ядра и обоих сверщиков ──"
  nabor_yadra > "$RABOTA/ядро"
  spisok_c > "$RABOTA/сверщик-c"
  spisok_f > "$RABOTA/сверщик-flang"
  YA=$(grep -c . < "$RABOTA/ядро")
  say "   набор ядра: $YA имён (плюс пустое)"
  [ "$YA" -ge 8 ] || plocho "из ядра вычитано $YA имён — разбор «Принято правилом» сломан"

  if ! diff -q "$RABOTA/ядро" "$RABOTA/сверщик-c" > /dev/null; then
    plocho "набор ядра разошёлся с ПРАВИЛА[] сверщика на C:"
    diff "$RABOTA/ядро" "$RABOTA/сверщик-c" | sed 's/^/          /'
  fi
  if ! diff -q "$RABOTA/ядро" "$RABOTA/сверщик-flang" > /dev/null; then
    plocho "набор ядра разошёлся со списком «Правила сведения» сверщика на flang:"
    diff "$RABOTA/ядро" "$RABOTA/сверщик-flang" | sed 's/^/          /'
  fi

  # Имена ведомости ⊆ набор ядра. «—» значит «в поле `rule` не попадает вовсе».
  stroki | awk -F'\t' '{ print $1 "\t" $4 }' > "$RABOTA/пары"
  : > "$RABOTA/названные"
  while IFS="	" read -r imya pravila; do
    [ "$pravila" = "—" ] && continue
    printf '%s\n' "$pravila" | tr '|' '\n' | while IFS= read -r p; do
      [ -n "$p" ] || continue
      grep -qxF "$p" "$RABOTA/ядро" || printf 'ЧУЖОЕ\t%s\t%s\n' "$imya" "$p"
      printf '%s\n' "$p" >> "$RABOTA/названные"
    done
  done < "$RABOTA/пары" > "$RABOTA/чужие"
  while IFS="	" read -r metka imya p; do
    [ -n "${metka:-}" ] || continue
    plocho "правило «$imya» ссылается на имя, которого ядро не ставит: «$p»"
  done < "$RABOTA/чужие"

  # Восемь семейств типовых законов обязаны быть названы (ADR-0022 §1).
  for imya in "неотрицательность по построению" "ограниченность точным потолком по построению" \
              "порядок по построению" "строгий порядок по построению" \
              "порядок соседних по построению" "вхождение по построению" \
              "начало по построению" "цель есть допущение"; do
    grep -qxF "$imya" "$RABOTA/названные" || plocho "ни одна строка ведомости не закрывает правило ядра «$imya»"
  done

  # Имена развёртки в поле `rule` не попадают и в списках сверщиков стоять не
  # должны — та же проба, что во второй половине `сверка-правил.sh`.
  for imya in "развёртка по конструктору" "развёртка определения без вызовов"; do
    if grep -qxF "$imya" "$RABOTA/сверщик-c"; then
      plocho "«$imya» стоит в ПРАВИЛА[] сверщика, хотя ядро в поле rule его не кладёт"
    fi
  done

  # Опора каждой строки обязана указывать на настоящее место ядра.
  stroki | awk -F'\t' '{ print $1 "\t" $11 }' | while IFS="	" read -r imya opora; do
    nomer=$(printf '%s' "$opora" | sed -n 's/^proof-kernel\.flang:\([0-9]\{1,\}\) .*$/\1/p')
    fn=$(printf '%s' "$opora" | sed -n 's/^proof-kernel\.flang:[0-9]\{1,\} «\([^»]*\)».*$/\1/p')
    if [ -z "$nomer" ] || [ -z "$fn" ]; then
      printf 'БЕДА\tопора правила «%s» не читается: %s\n' "$imya" "$opora"; continue
    fi
    est=$(sed -n "${nomer}p" "$YADRO")
    case "$est" in
      "функция «$fn»"|"тотальная функция «$fn»") : ;;
      *) printf 'БЕДА\tопора правила «%s» не сошлась: %s:%s — там «%s»\n' "$imya" "proof-kernel.flang" "$nomer" "$est" ;;
    esac
  done > "$RABOTA/опоры"
  while IFS="	" read -r metka text; do
    [ -n "${metka:-}" ] || continue
    plocho "$text"
  done < "$RABOTA/опоры"

  # Где двоичный есть — сосед спрашивается и обязан согласиться.
  if [ -x "$FLANG" ]; then
    if sh "$KOREN/flang/proof/сверка-правил.sh" --только-первая > "$RABOTA/сосед" 2>&1; then
      say "   сосед «сверка-правил.sh --только-первая» согласен (код 0)"
    else
      plocho "сосед «сверка-правил.sh --только-первая» покраснел — верить надо ЕМУ:"
      tail -5 "$RABOTA/сосед" | sed 's/^/          /'
    fi
  else
    say "   двоичного нет ($FLANG) — сосед «сверка-правил.sh» не спрошен;"
    say "   сличение набора ядра со списками сверщиков сделано здесь, текстом"
  fi
  say ""
}

# ═══════════════════ С-2: НЕПРОТИВОРЕЧИВОСТЬ ЗАПИСИ ═══════════════════
storozh_2() {
  say "── С-2: непротиворечивость записи ведомости ──"
  stroki | awk -F'\t' '
    BEGIN {
      split("Н Кон П Пред О Д С СС В Ч Разв Т Р", s, " "); for (i in s) semya[s[i]] = 1
      split("код код-шире код-строже код-уже нет-в-ADR нет-в-коде", v, " "); for (i in v) vid[v[i]] = 1
    }
    {
      if (NF != 12) { printf "БЕДА\tстрока %d: колонок %d, а надо 12\n", NR, NF; next }
      for (i = 1; i <= 12; i++) if ($i == "") printf "БЕДА\tправило «%s»: колонка %d пуста\n", $1, i
      if ($1 in bylo) printf "БЕДА\tимя «%s» стоит в ведомости дважды (строки %d и %d)\n", $1, bylo[$1], NR
      bylo[$1] = NR
      if (!($2 in semya)) printf "БЕДА\tправило «%s»: семейство «%s» вне закрытого списка\n", $1, $2
      if ($3 != "правило" && $3 != "запрет") printf "БЕДА\tправило «%s»: вид «%s» вне {правило, запрет}\n", $1, $3
      if ($10 !~ /^[0-9]+$/) printf "БЕДА\tправило «%s»: «входов» = «%s» — не число\n", $1, $10
      if ($11 !~ /^proof-kernel\.flang:[0-9]+ «/) printf "БЕДА\tправило «%s»: опора «%s» не той формы\n", $1, $11
      if (!($12 in vid)) printf "БЕДА\tправило «%s»: «сверено» = «%s» вне закрытого списка\n", $1, $12
      if ($3 == "правило") { pravil++; if ($12 != "нет-в-ADR") pravil_adr++ }
      if ($3 == "запрет")  { zapretov++; if ($12 != "нет-в-ADR") zapret_adr++ }
      if ($1 == "Н✗" || $1 == "П✗" || $1 == "С✗" || $1 == "С✗✗" || $1 == "Ч✗") pyat[$1] = 1
    }
    END {
      if (pravil_adr != 55) printf "БЕДА\tправил из ADR-0022 §3 в ведомости %d, а названо 55\n", pravil_adr
      if (zapret_adr != 5)  printf "БЕДА\tзапретов из ADR-0022 §3 в ведомости %d, а названо 5\n", zapret_adr
      split("Н✗ П✗ С✗ С✗✗ Ч✗", p, " ")
      for (i in p) if (!(p[i] in pyat)) printf "БЕДА\tименованного запрета ADR-0022 §3 «%s» в ведомости нет\n", p[i]
      printf "ЧИСЛА\tправил %d (из них по ADR §3 — %d), запретов %d (из них по ADR §3 — %d)\n", pravil, pravil_adr, zapretov, zapret_adr
    }' > "$RABOTA/с2"
  while IFS="	" read -r metka text; do
    case "$metka" in
      БЕДА) plocho "$text" ;;
      ЧИСЛА) say "   $text" ;;
    esac
  done < "$RABOTA/с2"

  # Находка 2 ADR-0022 §2.4: ядро и типизатор держат ДВЕ копии точного потолка,
  # и сторожа между ними не было. Теперь есть, и стоит он трёх строк.
  P_YADRO=$(awk '/^тотальная функция «Точный потолок»$/ { v = 1; next }
                 v && /^  [0-9]+$/ { gsub(/ /, "", $0); print; exit }' "$YADRO")
  P_TIPY=$(awk '/^тотальная функция «Потолок точных»$/ { v = 1; next }
                v && /^  [0-9]+$/ { gsub(/ /, "", $0); print; exit }' "$TIPY")
  if [ -z "$P_YADRO" ] || [ -z "$P_TIPY" ]; then
    plocho "точный потолок не вычитан: ядро «$P_YADRO», типизатор «$P_TIPY»"
  elif [ "$P_YADRO" != "$P_TIPY" ]; then
    plocho "точный потолок разошёлся: ядро $P_YADRO, типизатор $P_TIPY"
  else
    say "   точный потолок сошёлся: ядро и типизатор оба $P_YADRO"
  fi
  say ""
}

# ═══════════════ С-3: СОГЛАСИЕ ДВУХ НОТАЦИЙ ═══════════════
storozh_3() {
  say "── С-3: согласие логической и категорной записей ──"
  stroki | awk -F'\t' '
    BEGIN {
      split("объект стрелка произведение копроизведение экспонента начальный конечный подобъект начальная-алгебра", k, " ")
      for (i in k) mozhno[k[i]] = 1
    }
    {
      if ($6 == "—" || $6 == "") printf "БЕДА\tправило «%s»: заключение пусто\n", $1
      if ($8 == "—" || $8 == "") printf "БЕДА\tправило «%s»: категорная запись пуста\n", $1

      # колонка «конструкции» — только из закрытых девяти
      n = split($9, ch, "+")
      for (i = 1; i <= n; i++) if (!(ch[i] in mozhno)) printf "БЕДА\tправило «%s»: конструкция «%s» вне закрытых девяти\n", $1, ch[i]

      # число посылок логической записи
      p = 0
      if ($5 != "—") { s = $5; while (match(s, /(^|; )[0-9]+\)/)) { p++; s = substr(s, RSTART + RLENGTH) } }

      # ссылки ⟨i⟩ категорной записи
      delete ssylka; maks = 0; vsego = 0
      s = $8
      while (match(s, /⟨[0-9]+⟩/)) {
        t = substr(s, RSTART, RLENGTH); gsub(/[⟨⟩]/, "", t) + 0
        ssylka[t + 0] = 1; if (t + 0 > maks) maks = t + 0
        s = substr(s, RSTART + RLENGTH)
      }
      for (i in ssylka) vsego++

      if (p != $10 + 0) printf "БЕДА\tправило «%s»: посылок в логической записи %d, а «входов» %s\n", $1, p, $10
      if (vsego != p) printf "БЕДА\tправило «%s»: посылок %d, а разных ссылок ⟨i⟩ в категорной записи %d\n", $1, p, vsego
      for (i = 1; i <= p; i++) if (!(i in ssylka)) printf "БЕДА\tправило «%s»: посылка %d нигде не упомянута в категорной записи\n", $1, i
      if (maks > p) printf "БЕДА\tправило «%s»: категорная запись ссылается на ⟨%d⟩, а посылок всего %d\n", $1, maks, p
      vhodov += p
    }
    END { printf "ЧИСЛА\tвходов у всех стрелок вместе: %d\n", vhodov }' > "$RABOTA/с3"
  while IFS="	" read -r metka text; do
    case "$metka" in
      БЕДА) plocho "$text" ;;
      ЧИСЛА) say "   $text" ;;
    esac
  done < "$RABOTA/с3"
  say ""
}

# ═══════════════════════ С-4: ОТПЕЧАТОК ═══════════════════════
storozh_4() {
