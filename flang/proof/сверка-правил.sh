# СТОРОЖ РАСХОЖДЕНИЯ: закрытый список правил сверщика против набора имён, которые
# ядро СПОСОБНО поставить в поле правила.
#
#   sh flang/proof/сверка-правил.sh
#   код 0 — сошлось; 1 — разошлось (расхождение названо); 2 — кривой вызов.
#
# ── ЗАПАС ПО ШАГАМ У ПЕРВОЙ ПОЛОВИНЫ НАЗВАН ЧИСЛОМ ──────────────────────────
# Замер 29 августа 2026 прибором, считающим и виток, и заряд: сличение списков
# доходит до конца, потратив 1 025 358 574 шага двоичного (219 997 427 витков и
# 805 361 147 заряда), и в зашитые ниже двести миллионов бюджета вычислителя
# укладывается. После перепечатки потолок двоичного идёт с миллиарда до трёхсот
# миллиардов (число из `scripts/raskrutka.sh`), и этот миллиард шагов — 0,34 %
# потолка, запас 293 раза.
#
# ВТОРАЯ ПОЛОВИНА — не здесь: она зовёт `flang/proof/сверить.sh`, и предел шагов
# у неё свой. Смотреть надо туда.
#
# ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
# 23 августа прогоном выяснилось, что списки разошлись НЕ С ОДНОЙ стороны:
# честная запись честной программы (`flang/test/fixtures/ohrana-daet-fakt.flang`)
# была отвергнута сверщиком как подделка, потому что ядро закрыло её посылку
# правилом «разбор цели по условию», которого в списке не было. А два имени в
# списке числились и не встречались никогда. Разошлись они молча.
#
# ── ДВЕ ПОЛОВИНЫ, И ОДНА БЕЗ ДРУГОЙ НИЧЕГО НЕ ЗНАЧИТ ────────────────────────
# ПЕРВАЯ — сличение списков: имена берутся из исходника ядра (доводы «Принято
# правилом»), список — из исходника сверщика, и они сличаются знак в знак.
# ВТОРАЯ — живой прогон: каждое имя, названное первой половиной, подставляется в
# НАСТОЯЩУЮ запись доказательства, и сверщик обязан её принять; имя вне набора —
# и сверщик обязан её отвергнуть, назвав имя. Без второй половины «сошлось»
# означало бы лишь «два текста похожи»; без первой — что список сверяется сам с
# собой.
#
# Живая половина идёт ДВУМЯ дорогами, потому что у сверщика их две: утверждение
# с написанной теоремой и утверждение без неё. Вторая дорога закрытый список не
# спрашивала вовсе — это третья беда, найденная тем же прогоном.
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах.
set -eu

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
SVERIT=$KOREN/flang/proof/сверить.sh
# Пути перекрываются извне НАРОЧНО: порча ядра проверяется на КОПИИ, потому что
# сам `proof-kernel.flang` править нельзя, а сторож, которого не пробовали
# сломать, ничего не сторожит.
YADRO=${YADRO:-$KOREN/flang/self/proof-kernel.flang}
TERM_=${TERM_:-$KOREN/flang/self/proofterm.flang}
SVERSHCHIK=${SVERSHCHIK:-$KOREN/flang/proof/сверщик.flang}
# Живая половина обязана звать ТОТ ЖЕ сверщик, который сличала первая: иначе
# порча сверщика краснела бы в одной половине и оставалась незамеченной в другой.
export SVERSHCHIK
# Программа, чью посылку ядро закрывает правилом «разбор цели по условию» — тем
# самым, на котором сверщик и попался. Запись с ним обязана быть ПРИНЯТА.
ISHODNIK=${ISHODNIK:-$KOREN/flang/test/fixtures/ohrana-daet-fakt.flang}
# Имя правила, стоящее в этой записи: его и подменяют по очереди.
ESTNOE=${ESTNOE:-разбор цели по условию}
# Вторая программа — с ДРУГОЙ дороги: у её утверждения «С5 сохранение» теоремы в
# исходнике нет ни строки, а посылка с названным правилом есть. Эта дорога у
# сверщика закрытый список не спрашивала вовсе, и запись без теоремы могла
# назвать правило какое угодно.
BEZ_TEOREMY=${BEZ_TEOREMY:-$KOREN/flang/proof/map/substantive.flang}

[ -x "$FLANG" ] || { echo "двоичного нет: $FLANG" >&2; exit 2; }
for f in "$YADRO" "$TERM_" "$SVERSHCHIK" "$ISHODNIK" "$BEZ_TEOREMY" "$SVERIT"; do
  [ -f "$f" ] || { echo "файла нет: $f" >&2; exit 2; }
done

RABOTA=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" pravila.XXXXXX)
trap 'rm -rf "$RABOTA"' EXIT INT TERM

BAD=0
say() { printf '%s\n' "$*"; }

# ── половина первая: сличение списков ───────────────────────────────────────
cp "$KOREN/flang/proof/сверка-правил.flang" "$RABOTA/сверка-правил.flang"
printf '%s\n%s\n%s\n' "$YADRO" "$TERM_" "$SVERSHCHIK" > "$RABOTA/наряд"

say "── половина первая: список сверщика против набора ядра ──"
say "   ядро:    $YADRO"
say "   терм:    $TERM_"
say "   сверщик: $SVERSHCHIK"
VYVOD=$("$FLANG" io "$RABOTA/сверка-правил.flang" --max-steps 200000000 --max-depth 20000 2>&1) && KOD=0 || KOD=$?

case "$VYVOD" in
  '{"error":'*)
    printf '%s\n' "$VYVOD" | sed 's/^{"error":"\([^"]*\)".*/РАЗОШЛОСЬ: \1/'
    exit 1 ;;
  '{"plan":'*)
    OTVET=$(printf '%s\n' "$VYVOD" | sed 's/^{"plan":"[^"]*","result":"\([^"]*\)".*/\1/') ;;
  *)
    printf '%s\n' "$VYVOD"
    exit "${KOD:-1}" ;;
esac
[ "$KOD" -eq 0 ] || { printf '%s\n' "$VYVOD"; exit "$KOD"; }

say "$OTVET"
printf '%s\n' "$OTVET" | sed 's/^.*имена: //' | tr '|' '\n' > "$RABOTA/имена"
SKOLKO=$(grep -c . < "$RABOTA/имена")
say ""

# ── половина вторая: живой прогон каждым именем ─────────────────────────────
say "── половина вторая: настоящая запись, подменённое имя правила ──"
say "   исходник: $ISHODNIK"
"$FLANG" check "$ISHODNIK" --proof --записать "$RABOTA/честная" > /dev/null
say "   записано доказательство: $(wc -l < "$RABOTA/честная") строк"
grep -q "правило «$ESTNOE»" "$RABOTA/честная" || {
  say "ОСТАНОВКА: в записи нет строки «правило «$ESTNOE»» — подменять нечего,"
  say "           и молча сделать вид, что опыт состоялся, нельзя."
  exit 1
}
say ""

# Один опыт: имя, ожидаемый код возврата сверщика.
opyt() {
  imya=$1; zhdyom=$2
  sed "s/правило «$ESTNOE»/правило «$imya»/" "$RABOTA/честная" > "$RABOTA/проба"
  vyvod=$(sh "$SVERIT" "$ISHODNIK" "$RABOTA/проба" 2>&1) && kod=0 || kod=$?
  if [ "$kod" -eq "$zhdyom" ]; then
    say "СОШЛОСЬ  правило «$imya» — код $kod, как и ждали"
  else
    say "ПРОВАЛ   правило «$imya» — ждали код $zhdyom, получили $kod"
    say "         $(printf '%s' "$vyvod" | head -1 | cut -c1-200)"
    BAD=$((BAD + 1))
  fi
}

# Честная половина: КАЖДОЕ имя из набора ядра обязано быть принято.
say "честное: $SKOLKO имён набора ядра, каждое обязано быть принято"
while IFS= read -r imya; do
  [ -n "$imya" ] || continue
  opyt "$imya" 0
done < "$RABOTA/имена"

# Пустое имя правила стоит в этой записи и без подмены: у базовой посылки
# «правило «»». Значит честный прогон без подмены и есть опыт на пустое имя.
vyvod=$(sh "$SVERIT" "$ISHODNIK" "$RABOTA/честная" 2>&1) && kod=0 || kod=$?
if [ "$kod" -eq 0 ]; then
  say "СОШЛОСЬ  запись без подмены (в ней же пустое имя правила) — код 0"
else
  say "ПРОВАЛ   запись без подмены отвергнута — код $kod"
  say "         $(printf '%s' "$vyvod" | head -1 | cut -c1-200)"
  BAD=$((BAD + 1))
fi
say ""

# ── порча: имя вне набора обязано быть отвергнуто ───────────────────────────
say "порча: имена вне набора ядра, каждое обязано быть отвергнуто"
opyt "разбор цели по настроению" 1
# Ровно те два имени, что числились в списке восьми и не попадали в поле правила
# никогда. Убраны — значит обязаны отвергаться, как всякое чужое имя.
opyt "развёртка по конструктору" 1
opyt "развёртка определения без вызовов" 1

# ── вторая дорога: утверждение без теоремы ──────────────────────────────────
say ""
say "── дорога без теоремы: $BEZ_TEOREMY ──"
"$FLANG" check "$BEZ_TEOREMY" --proof --записать "$RABOTA/без-теоремы" > /dev/null
grep -q "правило «$ESTNOE»" "$RABOTA/без-теоремы" || {
  say "ОСТАНОВКА: в записи без теоремы нет строки «правило «$ESTNOE»» — подменять нечего"
  exit 1
}
grep -q "теоремы нет" "$RABOTA/без-теоремы" || {
  say "ОСТАНОВКА: в записи нет ни одного утверждения «теоремы нет» — дорога не та"
  exit 1
}
vyvod=$(sh "$SVERIT" "$BEZ_TEOREMY" "$RABOTA/без-теоремы" 2>&1) && kod=0 || kod=$?
if [ "$kod" -eq 0 ]; then
  say "СОШЛОСЬ  честная запись без теоремы принята — код 0"
else
  say "ПРОВАЛ   честная запись без теоремы отвергнута — код $kod"
  say "         $(printf '%s' "$vyvod" | head -1 | cut -c1-200)"
  BAD=$((BAD + 1))
fi
sed "s/правило «$ESTNOE»/правило «правило моего сочинения»/" "$RABOTA/без-теоремы" > "$RABOTA/проба"
vyvod=$(sh "$SVERIT" "$BEZ_TEOREMY" "$RABOTA/проба" 2>&1) && kod=0 || kod=$?
case "$kod:$vyvod" in
  1:*"утверждение «"*"правило моего сочинения"*)
    say "СОШЛОСЬ  чужое правило у утверждения БЕЗ теоремы отвергнуто и названо — код 1" ;;
  *)
    say "ПРОВАЛ   чужое правило у утверждения без теоремы не отвергнуто как надо — код $kod"
    say "         $(printf '%s' "$vyvod" | head -1 | cut -c1-200)"
    BAD=$((BAD + 1)) ;;
esac
say ""

# Порча называет имя, а не отделывается общими словами.
sed "s/правило «$ESTNOE»/правило «разбор цели по настроению»/" "$RABOTA/честная" > "$RABOTA/проба"
vyvod=$(sh "$SVERIT" "$ISHODNIK" "$RABOTA/проба" 2>&1) || true
case "$vyvod" in
  *"разбор цели по настроению"*) say "СОШЛОСЬ  отказ называет подставленное имя" ;;
  *) say "ПРОВАЛ   отказ не называет имя: $(printf '%s' "$vyvod" | head -1 | cut -c1-200)"; BAD=$((BAD + 1)) ;;
esac

say ""
if [ "$BAD" -eq 0 ]; then
  say "сошлось всё: список сверщика равен набору ядра ($SKOLKO правил и пустое имя),"
  say "каждое имя принято живой записью, чужое имя отвергнуто и названо —"
  say "и на дороге с теоремой, и на дороге без неё"
  exit 0
fi
say "опытов не сошлось: $BAD"
exit 1
