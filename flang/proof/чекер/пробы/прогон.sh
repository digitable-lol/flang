# Обе правки читают ИСХОДНИК шире прежнего, а не запись, и опасность у обеих
# одна: новая терпимость к написанию могла бы протечь в приём лжи. Проба
# правит ИСХОДНИК, а не запись, и переподписывает шапку записи ТЕМ ЖЕ СЧЁТОМ,
# каким её ведёт сам чекер (сверщик.c: znakov, otpechatok) — иначе испорченная
# пара отклонялась бы разошедшимся отпечатком, а не проверкой по существу, и
# проба доказывала бы не то. Тот же счёт уже независимо переписан для
# `доля-корпуса.sh:shapka_ishodnika` — здесь он написан порознь в третий раз,
# тем же приёмом, каким сам чекер сверяет свою печать (сверщик.c: «Тот же
# счёт, что у пишущей стороны; написан порознь нарочно»).
#
# НАХОДКА 9992: код возврата слеп к тихому зачёту. Проба А меняет ЧИСЛО «на
# слово ядра: шагов», а не только код — запись остаётся 3 и до, и после.
shapka_5044() { # исходник → «строк знаков h1 h2 sha256»
  od -An -tu1 -v < "$1" | awk -v sha="$(sha256sum "$1" | cut -d' ' -f1)" '
    { for (i = 1; i <= NF; i++) b[++n] = $i + 0 }
    END{
      strok = 1; znakov = 0; h1 = 7; h2 = 7; i = 1
      while (i <= n) {
        v = b[i]
        if      (v < 128) { c = v;      k = 1 }
        else if (v < 224) { c = v % 32; k = 2 }
        else if (v < 240) { c = v % 16; k = 3 }
        else              { c = v % 8;  k = 4 }
        for (j = 1; j < k; j++) c = c * 64 + (b[i+j] % 64)
        i += k; znakov++
        if (c == 10) strok++
        h1 = (h1 * 131 + c) % 1000000007
        h2 = (h2 * 137 + c) % 998244353
      }
      printf "%d %d %d %d %s\n", strok, znakov, h1, h2, sha
    }'
}
shagov_na_slovo_5044() { # исходник, запись → «на слово ядра: шагов»
  set +e; v=$("$C" "$1" "$2" 2>&1); set -e
  printf '%s' "$v" | sed -n 's/.*посылок и утверждений [0-9]*, шагов \([0-9]*\)\..*/\1/p'
}
# ЖИВОЙ ПОДДЕЛЫВАТЕЛЬ ИСХОДНИКА. Правит ИСХОДНИК sed-правкой и переподписывает
# шапку записи под него, чтобы отклик проверял ЧТЕНИЕ, а не разошедшийся
# отпечаток. Результат — в глобальных FAYL_ISH_5044/FAYL_ZAP_5044 (не в stdout:
# `X=$(...)` под `set -e` уронил бы весь прогон при неудаче правки).
poddelka_ishodnika_5044() { # имя, исходник, запись, sed-правка-исходника
  imya=$1; ish=$2; zap=$3; pravka=$4
  n=$(printf '%s' "$imya" | tr -c 'a-zA-Z0-9' '-')
  FAYL_ISH_5044=$RABOTA/$n.flang; FAYL_ZAP_5044=$RABOTA/$n.запись
  sed "$pravka" "$ish" > "$FAYL_ISH_5044"
  if cmp -s "$ish" "$FAYL_ISH_5044"; then
    say "ПОРЧА НЕ СОБРАЛАСЬ: $imya"; BAD=$((BAD+1)); FAYL_ISH_5044=""; return 0
  fi
  set -- $(shapka_5044 "$FAYL_ISH_5044")
  sed -e "s/^строк .*/строк $1/" -e "s/^знаков .*/знаков $2/" \
      -e "s/^отпечаток [0-9].*/отпечаток $3 $4/" -e "s/^отпечаток256 .*/отпечаток256 $5/" \
      "$zap" > "$FAYL_ZAP_5044"
}

