# ── МУТАНТЫ ПРИЁМОВ, ПРОИГРЫВАЮЩИХ УЗЕЛ ВЕРДИКТА (Ч363, Ч365) ──
#
# Эти пробы ломают по одной посылке САМОГО ПРИЁМА, а не запись. До
# 3 сентября они жили в каталогах ячеек и их не гонял никто: проба порчей,
# которую не запускают, — украшение, а не проба.
#
# Чекеру нужен ТРЕТИЙ довод — отпечаток исходника. Без него он не даёт
# кода 0 никому, и надзорный неотличим от порченого: проверено, все
# семнадцать дают 3. Поэтому отпечаток считается здесь же.
#
# Ожидаемые коды сняты прогоном 3 сентября на свежесобранном чекере.
# Смена кода — не поломка пробы, а СИГНАЛ: приём стал вести себя иначе,
# и это надо объяснить, а не подогнать.
otp() { sha256sum "$1" | cut -d' ' -f1; }
opyt_otp() { # класс, имя, ожидаемый код, исходник, запись
  opyt "$1" "$2" "$3" "$4" "$5" "$(otp "$4")"
}
mut() { # каталог, имя пробы, ожидаемый код, класс
  d=$ZAP/$1; opyt_otp "$4" "$1 $2" "$3" "$d/$2.flang" "$d/$2.запись"
}

