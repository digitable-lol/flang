# ЗАЧЕМ ОТДЕЛЬНЫЙ РАЗРЯД. Механизм opyt сверяет КОД ВОЗВРАТА — и слеп к целому
# роду дыр: подделка, которую чекер молча ЗАСЧИТЫВАЕТ доказанной, возвращает
# тот же код, что честная запись, а расходится только ЧИСЛО в отчёте. Пока
# такую дыру нельзя выразить через opyt, её нет и в наборе — то есть набор
# зелен не потому, что дыры нет, а потому, что смотреть нечем.
#
# Ведомость двусторонняя, как flang/scripts/cli-keys-debt.json: сегодняшнее
# число записано, и расхождение в ЛЮБУЮ сторону — беда. Дыра на месте — набор
# не краснеет (иначе CI встал бы на честно известном долге, binary.yml:903), но
# строка печатается громко. Дыра закрылась — БЕДА, и это правильно: значит
# пробу пора поднять из долга в настоящие, а число здесь снять.
DOLG=0
dolg() { # имя, ожидаемое сегодня «числятся доказанными», задача, исходник, запись
  imya=$1; zhdem=$2; zadacha=$3; shift 3
  set +e; vyvod=$("$C" "$@" 2>&1); set -e
  bylo=$(printf '%s' "$vyvod" | sed -n 's/.*Числятся доказанными \([0-9]*\).*/\1/p')
  DOLG=$((DOLG+1))
  if [ "$bylo" = "$zhdem" ]; then
    say "  ДЫРА НА МЕСТЕ ($zadacha): $imya — числятся доказанными $bylo"
  else
    say "ДЫРА ИЗМЕНИЛАСЬ ($zadacha): $imya — было $zhdem, стало ${bylo:-«числа нет»}."
    say "  Если её закрыли — перенесите пробу из долга в настоящие (opyt) и снимите строку."
    BAD=$((BAD+1))
  fi
}
# То же, но по числу «НА СЛОВО ЯДРА»: дыра бывает и в обратную сторону — не
# «счёт вырос», а «долг спрятан», и сверять её надо другим числом отчёта.
dolg_na_slovo() { # имя, ожидаемое сегодня «на слово ядра», задача, исходник, запись
  imya=$1; zhdem=$2; zadacha=$3; shift 3
  set +e; vyvod=$("$C" "$@" 2>&1); set -e
  bylo=$(printf '%s' "$vyvod" | sed -n 's/.*НА СЛОВО ЯДРА: посылок и утверждений \([0-9]*\).*/\1/p')
  DOLG=$((DOLG+1))
  if [ "$bylo" = "$zhdem" ]; then
    say "  ДЫРА НА МЕСТЕ ($zadacha): $imya — на слово ядра $bylo"
  else
    say "ДЫРА ИЗМЕНИЛАСЬ ($zadacha): $imya — было $zhdem, стало ${bylo:-«числа нет»}."
    say "  Если её закрыли — перенесите пробу из долга в настоящие (opyt) и снимите строку."
    BAD=$((BAD+1))
  fi
}
