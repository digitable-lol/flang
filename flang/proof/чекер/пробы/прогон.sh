# ВЕСЬ НАБОР ПРОБ ЧЕКЕРА ОДНОЙ КОМАНДОЙ.
#
#   sh flang/proof/чекер/пробы/прогон.sh
#   ./ярлык чекер:проверка
#
# Код 0 — сошлось всё: ни одна подделка не принята, ни одна честная запись не
# отвергнута. Код 1 — что-то из этого неверно, и оно названо строкой.
#
# ── Почему исходов ТРИ, а не два ────────────────────────────────────────────
# Чекер отвечает не «да/нет», а тремя словами: ПРОВЕРЕНО (0), НЕ ПРОВЕРЕНО (3),
# НЕ СОШЛОСЬ (1). Третий исход — это «противоречий не нашлось, но проверено не
# всё, и непроверенное названо». Слить его с нулём значит соврать про запись,
# слить с единицей — оболгать честную. Поэтому здесь считаются все три числа, и
# порознь для подделок и для честных: «отвергнуто 61» без «честных отвергнуто 0»
# не значит ничего, а «принято 95» без «подделок принято 0» — тем более.
#
# ── Что нужно для прогона ───────────────────────────────────────────────────
# Компилятор C99 и POSIX sh. Двоичный компилятора flang НЕ нужен ни на одном
# шаге и не зовётся: в этом весь смысл отдельного чекера. Записи лежат в дереве
# готовыми, подделки, которые дешевле породить, чем хранить, порождаются здесь
# же правкой одной строки — и каждая такая правка проверяется на то, что она
# ВООБЩЕ ПРИМЕНИЛАСЬ (иначе проба сравнивала бы запись саму с собой).
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах.
set -eu

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../../../.." && pwd)
CHEK=$KOREN/flang/proof/чекер
C=${SVERSCHIK:-$CHEK/сверщик}
ZAP=$CHEK/пробы/записи
PROG=$CHEK/пробы/программы

# Двоичного нет — собираем сами, одним вызовом компилятора и без make: у чекера
# ровно один файл исходника и ноль зависимостей вне libc.
if [ ! -x "$C" ] && [ -z "${SVERSCHIK:-}" ]; then
  ${CC:-cc} -std=c99 -Wall -Wextra -Werror -pedantic -O2 -o "$C" "$CHEK/сверщик.c"
fi
[ -x "$C" ] || { echo "чекера нет и собрать не вышло: $C" >&2; exit 2; }

RABOTA=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" chekker.XXXXXX)
trap 'rm -rf "$RABOTA"' EXIT INT TERM
cd "$KOREN"

BAD=0

# ── НАБОР ПОДДЕЛОК ЧИТАЕТСЯ ИЗ МАНИФЕСТА, А НЕ ИЗ ИМЕНИ ФАЙЛА (ADR-0023, Ш2) ──
# До 8 сентября 2026 класс подделки в корпусном цикле ниже решала одна строка
# `case "$b" in poddelka-svyortka-*)`. Имя файла решало, кого нельзя принять
# кодом 0, — и переименование файла было самой дешёвой и самой незаметной в
# диффе накруткой. Теперь решает объявленный список под храповиком:
# flang/proof/подделки/НАБОР.tsv. Имя файла не решает ничего; оно лишь ключ
# строки этого списка.
NABOR_TSV=$KOREN/flang/proof/подделки/НАБОР.tsv
NABOR_RAB=$RABOTA/набор.tsv
NABOR_KORP=flang/proof/чекер/пробы/записи/корпус
if [ ! -f "$NABOR_TSV" ]; then
  printf '%s\n' "ПРОВАЛ: манифеста набора подделок нет — $NABOR_TSV"
  printf '%s\n' "  без него прогон не знает, кого нельзя принять кодом 0. Это НЕ «проб нет»,"
  printf '%s\n' "  это «сторож потерян»: ADR-0023 §6, сторож 1."
  exit 1
fi
# Пять полей на строку: имя файла записи (ключ), исходник, запись, ожидаемый
# исход, класс. Строки-примечания «#» и заголовок столбцов не в счёт.
awk -F'\t' '
  /^#/ { next }
  $1 == "имя" { next }
  NF >= 6 { n = split($3, ch, "/"); print ch[n] "\t" $2 "\t" $3 "\t" $5 "\t" $6 }
' "$NABOR_TSV" > "$NABOR_RAB"
NABOR_STROK=$(wc -l < "$NABOR_RAB" | tr -d ' ')
[ "$NABOR_STROK" -gt 0 ] || { printf '%s\n' "ПРОВАЛ: манифест набора пуст — $NABOR_TSV"; exit 1; }
# Класс и ожидаемый исход по имени файла записи; пусто — записи в наборе нет.
iz_nabora() { # имя файла записи; печатает «исход<TAB>класс»
  awk -F'\t' -v b="$1" '$1 == b { print $4 "\t" $5; exit }' "$NABOR_RAB"
}

# Исходы по всем пробам разом.
N0=0; N1=0; N3=0; N2=0
# Классы объявляются явно: P — подделка (её нельзя принять кодом 0),
# C — честная запись (её нельзя отвергнуть кодом 1).
PODD=0; POTV=0; PTRI=0; PPRO=0
CHEST=0; CPRIN=0; COTV=0

say() { printf '%s\n' "$*"; }
# ПРОБА ПО ЧИСЛУ, А НЕ ПО КОДУ ВОЗВРАТА. Целый род подделок кодом неразличим:
# запись исходнику не противоречит и получает те же 3, что честная, а лжёт
# ЧИСЛОМ — прячет долг ниже честного уровня. Ведомость долга (ниже) такие дыры
# только ПОМЕЧАЕТ; эта проба их СТОРОЖИТ: число названо, и расхождение в любую
# сторону — провал набора.
na_slovo_ravno() { # имя, ожидаемое «на слово ядра», довод...
  imya=$1; zhdem=$2; shift 2
  set +e; vyvod=$("$C" "$@" 2>&1); set -e
  bylo=$(printf '%s' "$vyvod" | sed -n 's/.*НА СЛОВО ЯДРА: посылок и утверждений \([0-9]*\).*/\1/p')
  if [ "$bylo" = "$zhdem" ]; then
    say "  на слово ядра $bylo, как обещано: $imya"
  else
    say "ПРОВАЛ: $imya — «на слово ядра» обещано $zhdem, вышло ${bylo:-«числа нет»}"
    BAD=$((BAD+1))
  fi
}
na_slovo_bolshe() { # имя, доводы подделки одной строкой, доводы честной одной строкой
  imya=$1
  set +e
  # shellcheck disable=SC2086
  vp=$("$C" $2 2>&1); vch=$("$C" $3 2>&1)
  set -e
  bp=$(printf '%s' "$vp"  | sed -n 's/.*НА СЛОВО ЯДРА: посылок и утверждений \([0-9]*\).*/\1/p')
  bch=$(printf '%s' "$vch" | sed -n 's/.*НА СЛОВО ЯДРА: посылок и утверждений \([0-9]*\).*/\1/p')
  if [ -n "$bp" ] && [ -n "$bch" ] && [ "$bp" -gt "$bch" ]; then
    say "  долг подделки $bp больше долга честной $bch: $imya"
  else
    say "ПРОВАЛ: $imya — у подделки ${bp:-«числа нет»}, у честной ${bch:-«числа нет»}"
    BAD=$((BAD+1))
  fi
}
kod() { set +e; "$C" "$@" >/dev/null 2>&1; k=$?; set -e; echo "$k"; }
schet() { # исход
  case "$1" in 0) N0=$((N0+1));; 1) N1=$((N1+1));; 3) N3=$((N3+1));; *) N2=$((N2+1));; esac
}
opyt() { # класс, имя, ожидаемый код, довод...
  kl=$1; imya=$2; z=$3; shift 3
  k=$(kod "$@"); schet "$k"
  if [ "$kl" = P ]; then
    PODD=$((PODD+1))
    case "$k" in 0) PPRO=$((PPRO+1));; 1) POTV=$((POTV+1));; *) PTRI=$((PTRI+1));; esac
  else
    CHEST=$((CHEST+1))
    case "$k" in 1) COTV=$((COTV+1));; *) CPRIN=$((CPRIN+1));; esac
  fi
  if [ "$k" -ne "$z" ]; then say "ПРОВАЛ $imya — ждали $z, вышло $k"; BAD=$((BAD+1)); fi
}
podd() { # имя, исходник, запись, правка sed — всегда класс P
  n=$(printf '%s' "$1" | tr -c 'a-zA-Z0-9' '-'); f=$RABOTA/$n
  sed "$4" "$3" > "$f"
  if cmp -s "$3" "$f"; then say "ПОДДЕЛКА НЕ СОБРАЛАСЬ: $1"; BAD=$((BAD+1)); return 0; fi
  opyt P "$1" 1 "$2" "$f"
}
# ПОДДЕЛКА С ПРИЧИНОЙ: код 1, и отказ обязан НАЗВАТЬ расхождение (подстрокой).
# Код один и тот же у «строка не узнана» и у «строка сличена и не сошлась» —
# разница видна только текстом (6203-Ш2: до сверки все эталонные подделки
# давали 1 по чужой причине, и проверки за этим кодом не было).
prichina() { # имя, подстрока причины, довод...
  imya=$1; zhdem=$2; shift 2
  opyt P "$imya" 1 "$@"
  set +e; vyvod=$("$C" "$@" 2>&1); set -e
  case "$vyvod" in *"$zhdem"*) ;; *) say "ПРОВАЛ $imya — причина не названа: ждали «$zhdem»"; BAD=$((BAD+1));; esac
  case "$vyvod" in *"не узнана"*) say "ПРОВАЛ $imya — «не узнана»: строку не сличили, а отвергли не читая"; BAD=$((BAD+1));; esac
}
# «на слово ядра: посылок и утверждений N» — числом, а не кодом (находка 9992:
# код один и тот же у записи с провалом и без него, число — нет).
naslovo() { # исходник запись [отпечаток]
  set +e; "$C" "$@" 2>&1 | sed -n 's/.*посылок и утверждений \([0-9]*\),.*/\1/p'; set -e
}
chislo() { # имя, ждём, вышло
  if [ "$2" = "$3" ]; then say "$1 — ЦЕЛА (на слове ядра $3)"
  else say "ПРОВАЛ $1 — ждали на слове ядра $2, вышло $3"; BAD=$((BAD+1)); fi
}

NAT=flang/proof/examples/corpus-natural.flang
TREE=flang/proof/examples/corpus-tree.flang
STACK=flang/proof/examples/stack.flang
BODY=flang/proof/examples/body-forms.flang
DELIM=flang/proof/подделки/делением.flang

say "── поля записи (Ч19): 30 подделок → 1, 2 честные → 3 ──"
for f in "$ZAP"/Ч19/*.запись; do
  b=$(basename "$f")
  case "$b" in дерево-*) I=$TREE;; *) I=$NAT;; esac
  case "$b" in *честная*) opyt C "честная $b" 3 "$I" "$f";;
                       *) opyt P "подделка $b" 1 "$I" "$f";; esac
done

say "── доказательство лжи (Ч40): 4 записи, ни одна не вправе получить код 0 ──"
# Ч40 замерила: свёртка ядра тут столкнута, ловить нечем — это третий исход,
# а не отказ. Код 0 не вправе получить ни одна из четырёх.
opyt P "ложь-1-вердикт"        3 "$PROG/lozh-raznost-chistaya.flang" "$ZAP/Ч40/lozh-1-verdikt.запись"
opyt P "ложь-2-переадресована" 1 "$PROG/lozh-raznost-chistaya.flang" "$ZAP/Ч40/lozh-2-pereadresovana.запись"
opyt P "ложь-4-теорема"        1 "$PROG/lozh-derevo.flang"           "$ZAP/Ч40/lozh-4-teorema.запись"
opyt P "ложь-8-столкновение"   1 "$PROG/lozh-stolknovenie.flang"     "$ZAP/Ч40/lozh-8-chestnaya-zapis-natural.запись"

say "── сведение по шагам: 2 честные → 3, 14 подделок → 1 ──"
SZ=flang/proof/подделки/стопка.запись
DZ=flang/proof/подделки/делением.запись
opyt C "честная: стопка, семь ходов" 3 "$STACK" "$SZ"
opyt C "честная: деление и выбор"    3 "$DELIM" "$DZ"
podd "подмена-переписки" "$STACK" "$SZ" 's/ход 4 замена по дано 1/ход 4 замена по дано 2/'
podd "подмена-развёртки" "$STACK" "$SZ" 's|развернуть ⟨«Копия» от (вариант «Звено» с голова равным г и хвост равным х)⟩|развернуть ⟨«Копия» от (вариант «Пусто»)⟩|'
podd "подмена-соседей" "$STACK" "$SZ" 's|соседи ⟨(«Высота» от х) плюс 1⟩|соседи ⟨«Высота» от х⟩|'
podd "подмена-выбора" "$DELIM" "$DZ" 's|выбор ⟨если да то («Сколько» от н) плюс 2 иначе («Сколько» от н) плюс 1⟩|выбор ⟨если да то («Сколько» от н) плюс 1 иначе («Сколько» от н) плюс 2⟩|'
podd "подмена-деления" "$DELIM" "$DZ" 's|деление ⟨(«Сколько» от н) больше 100⟩|деление ⟨«Сколько» от н⟩|'
podd "чужая-строка-другой-случай" "$STACK" "$SZ" '0,/ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 58/s//ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 56/'
podd "чужая-строка-другая-функция" "$STACK" "$SZ" '0,/ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 58/s//ход 1 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным х)⟩ строка 102/'
podd "пропуск-хода-посередине" "$STACK" "$SZ" '/ход 2 развернуть ⟨«Высота» от (вариант «Звено» с голова равным г и хвост равным («Копия» от х))⟩ строка 58/d'
podd "пропуск-последнего-хода" "$STACK" "$SZ" '/ход 5 закрыть дано 1/d'
podd "лишний-ход" "$STACK" "$SZ" 's|ход 5 закрыть дано 1|ход 5 закрыть дано 1\
    ход 6 закрыть дано 1|'
sed -e '/ход 4 замена по дано 1/d' -e 's/ход 5 закрыть тождеством/ход 4 закрыть тождеством/' "$SZ" > "$RABOTA/без-переписки"
opyt P "снята переписка, номера подогнаны" 1 "$STACK" "$RABOTA/без-переписки"
podd "чужой-закон" "$STACK" "$SZ" '0,/закон «сумма неотрицательных»/s//закон «сумма любых»/'
podd "допущение-о-нерекурсивной-части" "$STACK" "$SZ" '0,/ход дано 1 предположение по «х»/s//ход дано 1 предположение по «г»/'
podd "обрыв-ход-конец" "$STACK" "$SZ" '0,/^    ход конец$/s///'

say "── запись, снятая ядром: 1 честная → 3, 4 порчи → 1 ──"
Y=$ZAP/ядро/yadro.запись
opyt C "честная: запись снята ядром" 3 "$STACK" "$Y"
podd "порча-закон-подменён" "$STACK" "$Y" '0,/закон «литерал неотрицателен»/s//закон «сумма неотрицательных»/'
podd "порча-развёртка-с-чужой-строки" "$STACK" "$Y" 's/ строка 56$/ строка 58/'
podd "порча-снят-ход-закрывающий" "$STACK" "$Y" '/ход 3 закрыть дано 1/d'
podd "порча-допущение-нерекурсивное" "$STACK" "$Y" 's/ход дано 1 предположение по «х»/ход дано 1 предположение по «г»/'

say "── доказательство настоящей программы: 1 честная → 3, 4 подделки → 1 ──"
BZ=$ZAP/ядро/body-forms.запись
opyt C "честная: доказательство body-forms" 3 "$BODY" "$BZ"
podd "подменённый-шаг" "$BODY" "$BZ" '0,/^\( *\)шаг \(.*\) по предположению$/s//\1шаг \2 по свойству «высота неотрицательна»/'
opyt P "верная запись подложена к другому исходнику" 1 flang/proof/examples/corpus-factorial.flang "$BZ"
NOM=$(grep -n '^ *шаг ' "$BZ" | tail -1 | cut -d: -f1)
sed "${NOM}d" "$BZ" > "$RABOTA/обрубленная"
opyt P "обрубленное доказательство" 1 "$BODY" "$RABOTA/обрубленная"
opyt P "шаг обосновывает сам себя (круг)" 1 flang/proof/подделки/круг.flang flang/proof/подделки/круг.запись

say "── привязка к программе (Ч48/Ч55): путь — примета только при сошедшемся хеше ──"
# Ждали 3 до правила «цель следует из объявленного о доводах»: у этой записи
# оставалось одно место на слово ядра. Правило его закрыло, и запись стала 0.
# Проба про ПРИВЯЗКУ, а не про долю: класс C считает отказом только код 1,
# так что «принимается» подтверждается кодом 0 ровно так же, как кодом 3.
opyt C "О4 чужой путь + отпечаток256 → принимается"        0 "$NAT" "$ZAP/Ч48/V-chestnaya.запись"
opyt P "О5 та же запись против ДРУГОЙ программы → отказ"   1 "$PROG/lozh-stolknovenie.flang" "$ZAP/Ч48/V-chestnaya.запись"
opyt P "О5б отпечаток честного при ложной программе → отказ" 1 "$PROG/lozh-stolknovenie.flang" "$ZAP/Ч48/B-s-256.запись"
# О6 — контроль: БЕЗ отпечатка256 чужой путь обязан отвергаться по-прежнему.
# Путь подделывается здесь же: в дереве все записи лежат с путями дерева.
sed -e '2s|^исходник |исходник /чужой/клон/|' -e '/^отпечаток256 /d' "$ZAP/корпус/corpus-natural.запись" > "$RABOTA/чужой-путь"
cmp -s "$ZAP/корпус/corpus-natural.запись" "$RABOTA/чужой-путь" && { say "ПОДДЕЛКА НЕ СОБРАЛАСЬ: О6"; BAD=$((BAD+1)); }
opyt P "О6 без отпечатка256 чужой путь → отказ" 1 "$NAT" "$RABOTA/чужой-путь"
# О6б: подмена, которую свёртка ядра не ловит. Это не отказ и не приёмка —
# это ровно третий исход, и причина обязана быть НАЗВАНА, а не подразумеваться.
opyt P "О6б подмена без отпечатка256 → 3, причина названа" 3 "$PROG/lozh-stolknovenie.flang" "$ZAP/Ч48/A-bez-256.запись"
"$C" "$PROG/lozh-stolknovenie.flang" "$ZAP/Ч48/A-bez-256.запись" 2>/dev/null \
  | grep -q "привязка к программе не криптографическая" \
  || { say "ПРОВАЛ О6б: чекер о привязке смолчал"; BAD=$((BAD+1)); }
# Отпечаток, поданный доводом, — такая же криптопривязка, как строка шапки.
H_NAT=$("$C" "$NAT" "$ZAP/Ч48/otn-put.запись" 2>/dev/null | sed -n 's/.*sha256 исходника \([0-9a-f]*\).*/\1/p')
# Тот же сдвиг 3 → 0 и по той же причине. Само утверждение пробы — что путь
# понижен до приметы — проверяется строкой ниже, на ДРУГОЙ записи (otn-put),
# и от кода здесь не зависит.
opyt C "отпечаток доводом: путь понижен до приметы" 0 "$NAT" "$ZAP/Ч48/V-chestnaya.запись" "$H_NAT"
"$C" "$NAT" "$ZAP/Ч48/otn-put.запись" "$H_NAT" 2>/dev/null \
  | grep -q "Привязка к программе: SHA-256 сошёлся" \
  || { say "ПРОВАЛ довод не засчитан криптопривязкой"; BAD=$((BAD+1)); }
# Запись, у которой на слово ядра не взято НИЧЕГО, с отпечатком получает 0:
# значит третий исход — именно про недостающую привязку, а не «всё подряд».
