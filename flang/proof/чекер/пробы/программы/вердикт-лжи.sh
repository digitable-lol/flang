# ТРИ ПРОГРАММЫ ЛЖИ ЯЧЕЙКИ Ч40 — ЗАКРЫТЫЙ СПИСОК С ИМЕНОВАННЫМ ВЕРДИКТОМ.
#
# Эти три lozh-*.flang лежат здесь как ВХОД для проб независимого чекера
# (../записи/Ч40/*.запись — записи доказательства ОБ этих программах, часть
# которых сама подделка). Программы не образцы корпуса: они НЕ ОБЯЗАНЫ и не
# должны доказывать то, что утверждают, — в этом их работа. Но живой
# `flang check` их тоже видит, и у него на КАЖДУЮ есть точный вердикт,
# записанный здесь и сверенный прогоном — тем же способом, каким
# `flang/scripts/kernel-forgeries.flang` держит вердикт для каждой
# `poddelka-*.flang` в `flang/test/fixtures` (закрытый список, сверенный с
# каталогом в обе стороны, вердикт называется словами, а не просто «код не 0»).
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Если однажды заведут ворота «flang check проходит на каждом
# файле дерева» (сегодня таких нет — см. flang/proof/чекер/ЧИТАТЬ.md, раздел
# про Ч67), они наткнутся на эти три файла. Без этого списка два красных
# исхода выглядели бы как поломка дерева, и кто-то «починил» бы файлы — а
# исправленная lozh-derevo.flang или lozh-stolknovenie.flang перестала бы
# годиться как подделка для проб чекера, и набор проб перестал бы проверять то,
# ради чего заведён. Список говорит будущим воротам: этим двум СЛЕДУЕТ падать
# ИМЕННО так, а этой одной следует проходить, честно не доказав постусловие
# (см. вывод «сетка N значение… Это не доказательство»).
#
# Вердикт для каждой программы — код возврата `flang check --proof` И подстрока
# его вывода, называющая ПРИЧИНУ, а не просто факт отказа: смена причины при
# том же коде — тоже расхождение, а не тишина (тот же довод, что у
# kernel-forgeries.flang: «обещание пережило свою реализацию» ловится словами).
#
#   sh вердикт-лжи.sh
#   код 0 — все три вердикта сошлись с записанным, лишних lozh-*.flang в
#           каталоге нет; 1 — расхождение, названо строкой.
#
# Прогон стоит миллисекунды на файл: три программы по 15-40 строк, флаг
# `--proof` без `flang test` над каталогом (тот дорог — см. ЧИТАТЬ.md).
set -eu
LC_ALL=C.UTF-8
export LC_ALL

TUT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
KOREN=$(CDPATH= cd -- "$TUT/../../../../.." && pwd)
FLANG=${FLANG_BIN:-$KOREN/bootstrap/flang}
[ -x "$FLANG" ] || { echo "двоичного нет: $FLANG (собрать: make -C bootstrap)" >&2; exit 2; }

BAD=0
say() { printf '%s\n' "$*"; }

# имя файла  ожидаемый код возврата  подстрока причины в выводе `check --proof`
proverit() {
  imya=$1; ozhkod=$2; podstroka=$3
  vyvod=$("$FLANG" check "$TUT/$imya" --proof 2>&1) && kod=0 || kod=$?
  if [ "$kod" != "$ozhkod" ]; then
    say "ПРОВАЛ   $imya — ждали код $ozhkod, получили $kod"
    say "         $(printf '%s' "$vyvod" | head -1 | cut -c1-200)"
    BAD=$((BAD + 1))
    return 0
  fi
  case "$vyvod" in
    *"$podstroka"*)
      say "СОШЛОСЬ $imya — код $kod, причина «$podstroka» на месте" ;;
    *)
      say "ПРОВАЛ   $imya — код $kod совпал, а слов «$podstroka» в выводе нет (причина другая)"
      BAD=$((BAD + 1)) ;;
  esac
}

# лживое дерево: индукция ложна ИЗНУТРИ — «Лист» не даёт «размер больше 0»
proverit "lozh-derevo.flang" 1 "FLANG_PROOF_STEP"

# лживая разность: пример подобран удачно, постусловие — только «на сетке»,
# ядро честно говорит «это не доказательство» и НЕ падает — вердикт «принято»,
# но не «доказано». Ровно эту ловушку и держит проба.
proverit "lozh-raznost-chistaya.flang" 0 "сетка 1 значение"

# лживое столкновение: тело нарочно «минус» вместо «плюс» — не проходит
# собственный пример, отдельно от вопроса о хеш-коллизии сверщика
proverit "lozh-stolknovenie.flang" 1 "FLANG_PROPERTY"

# ── сверка с каталогом: незарегистрированная lozh-*.flang — дыра в надзоре ──
NAZVANNYE=" lozh-derevo.flang lozh-raznost-chistaya.flang lozh-stolknovenie.flang "
for f in "$TUT"/lozh-*.flang; do
  [ -e "$f" ] || continue
  imya=$(basename "$f")
  case "$NAZVANNYE" in
    *" $imya "*) : ;;
    *)
      say "НЕЗАРЕГИСТРИРОВАННАЯ ЛОЖЬ: $imya лежит в каталоге, а вердикта для неё в этом списке нет — впишите его"
      BAD=$((BAD + 1)) ;;
  esac
done

say ""
if [ "$BAD" -eq 0 ]; then
  say "сошлось: вердикты трёх программ лжи Ч40 те же, что записаны здесь"
  exit 0
fi
say "расхождений: $BAD"
exit 1
