if (запущенНапрямую(import.meta.url)) {
  const итог = числа()
  const нарушения = проверить()
  console.log(
    `правил у бинарника: ${итог.бинарник}; поверхностей в РАЗНИЦА: ${итог.поверхностей}; ` +
    `подделок: ${итог.подделок}, из них названо ${итог.названо}, глухих ${итог.глухих}`,
  )
  for (const н of нарушения) console.log(`${н.род}: ${н.что} — ${н.почему}`)
  console.log(нарушения.length === 0 ? "нарушений нет" : `нарушений: ${нарушения.length}`)
  process.exitCode = нарушения.length === 0 ? 0 : 1
}
