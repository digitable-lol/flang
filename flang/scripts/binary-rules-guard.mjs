/** Текст без комментариев: код, названный прозой, — рассказ, а не правило. */
export function безКомментариев(путь, текст) {
  if (путь.endsWith(".mjs") || путь.endsWith(".c") || путь.endsWith(".h")) {
    return текст.replace(/\/\*[\s\S]*?\*\//gu, "").replace(/(?<!:)\/\/[^\n]*/gu, "")
  }
  return текст.replace(/\/\/[^\n]*/gu, "")
}

/** Коды из строковых литералов файла. */
export function кодыФайла(путь, текст) {
  const код = безКомментариев(путь, текст)
  const найдено = new Set()
  const литералы = [
    ...код.matchAll(/"((?:[^"\\\n]|\\.)*)"/gu),
    ...код.matchAll(/`([^`]*)`/gu),
  ]
  for (const литерал of литералы) for (const имя of литерал[1].match(ИМЯ_КОДА) ?? []) найдено.add(имя)
  return найдено
}

/** Замыкание импортов `.flang` от одного входа. */
export function замыкание(вход, корень = КОРЕНЬ) {
  const виден = new Set()
  const очередь = [resolve(корень, вход)]
  while (очередь.length > 0) {
    const путь = очередь.pop()
    if (виден.has(путь) || !existsSync(путь)) continue
    виден.add(путь)
    const текст = readFileSync(путь, "utf8")
    for (const строка of текст.matchAll(/использует\s+«[^»]+»\s+из\s+"([^"]+)"/gu)) {
      очередь.push(resolve(dirname(путь), строка[1]))
    }
  }
  return [...виден].sort()
}

/**
 * Что бинарник отвечает на одной подделке: код и названные им ключи.
 *
 * Ключи вынимаются из его же слов: «в программе объявлено то, чего бинарник не
 * судит вовсе — monoids». Читать его сообщение, а не считать что-то своё, —
 * условие честности сторожа: он проверяет, что бинарник СКАЗАЛ, а не что он
 * должен был бы сказать.
 */
export function ответНаПодделку(путь) {
  const { код, вывод, ошибки } = позвать(["check", путь])
  const текст = `${вывод}${ошибки}`
  /*
   * ФРАЗ ДВЕ, И ЭТО НЕ ДВА СПОСОБА СКАЗАТЬ ОДНО.
   *
   * «чего бинарник не судит вовсе — …» — поверхность не судится никак.
   * «УСТРОЙСТВО этих объявлений бинарник не судит вовсе — …» — ЗАКОН посчитан
   * на сетке, а устройство не сверялось. Вторая появилась вместе с ввозом
   * `self/setoid.flang`: до неё бинарник о категориях молчал целиком, теперь
   * судит половину — и обязан называть, какую именно половину не судит.
   *
   * Для этого сторожа обе фразы значат одно: поверхность НАЗВАНА. Ловим обе,
   * ключи складываем.
   */
  const ключи = []
  for (const м of текст.matchAll(/не суди[а-я]* вовсе — ([a-z, ]+)/gu)) {
    for (const ключ of м[1].split(",").map((к) => к.trim()).filter(Boolean)) {
      if (!ключи.includes(ключ)) ключи.push(ключ)
    }
  }
  return { код, ключи, текст }
}

/**
 * Что ПЕЧАТЬ отвечает на одной подделке: код и названные ею ключи.
 *
 * Вопрос здесь другой, чем у `check`, и он второй половиной той же дыры.
 * Проверка научилась отвечать «я не судила» кодом 2, печать научилась не
 * выпускать НЕ ПРОШЕДШЕЕ проверку кодом 1 — а между ними осталась щель: код 2
 * печать не останавливал, и программа с непосуждённой поверхностью выходила
 * кодом 0 со словами «проверено перед печатью». Замер 20 августа 2026: 41
 * программа дерева из 951 (26 из 294 в корпусе ведомости) — и все 41
 * печатались кодом 0.
 *
 * Требуется от печати НЕ отказ: отказывай она, как на не прошедшей проверку, —
 * категорную и процессную часть языка стало бы нечем собрать без Node.
 * Требуется НЕМОЛЧАНИЕ: файлы напечатаны, пробел назван поимённо, код 3.
 *
 * Каталог вывода уезжает во временное место и убирается сразу: сторожу нужен
 * код и слова, а не файлы.
 */
export function ответПечатиНаПодделку(путь) {
  const корень = process.env.FLANG_TEST_TMPDIR ?? tmpdir()
  const где = mkdtempSync(join(корень, "flang-rules-emit-"))
  try {
    const { код, вывод, ошибки } = позвать(["emit", путь, "--target", "c", "--out", где])
    const текст = `${вывод}${ошибки}`
    const м = /не суди[а-я]* вовсе — ([a-z, ]+)/u.exec(текст)
    const ключи = м === null ? [] : м[1].split(",").map((к) => к.trim()).filter(Boolean)
    return { код, ключи, текст }
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
}

/** Все подделки корпуса — по имени файла. */
export function подделки(корень = КОРЕНЬ) {
  const где = join(корень, ПОДДЕЛКИ)
  let свои = []
  try {
    /* Четыре равноправных расширения программы: `.flang`, `.fp`, `.фп`, `.фланг` (ADR-0016). */
    свои = readdirSync(где).filter((и) => /\.(flang|fp|фп|фланг)$/u.test(и)).sort().map((и) => join(где, и))
  } catch {
    свои = []
  }
  return [...свои, ...ПОДДЕЛКИ_ВРОЗЬ.map((п) => join(корень, п))].filter((п) => existsSync(п))
}

/**
 * ГЛУХИЕ ЗАЗОРЫ — поверхности, о которых бинарник не умеет сказать даже «не
 * проверял». Их две, обе названы в его же справке (`flang check --help`), и
 * обе ведутся здесь ПОИМЁННО, а не молча помилованы: подделка на такой
 * поверхности проходит с кодом 0, и это сегодня правда, а не описка.
 *
 * Список сверяется В ОБЕ СТОРОНЫ. Подделка, которую бинарник начал отвергать,
 * обязана уйти отсюда — запись, пережившая свою причину, врёт ровно так же, как
 * запись, которой не хватает.
 */
export const ГЛУХИЕ_ПОДДЕЛКИ = Object.freeze([
  {
    файл: "scale-mismatch.flang",
    почему:
      "уточнённые числовые типы («сотых», «вес») стоят типом в подписи, а не отдельной "
      + "строкой: программу с ними от обычной по объявлениям не отличить, и назвать "
      + "пробел бинарнику нечем — он отвечает «замечаний нет» и кодом 0",
  },
])

/** Правила бинарника: коды отказа во всём замыкании его точки входа. */
export function правилаБинарника(корень = КОРЕНЬ) {
  const где = new Map()
  for (const путь of замыкание(ВХОД_БИНАРНИКА, корень)) {
    for (const код of кодыФайла(путь, readFileSync(путь, "utf8"))) {
      if (!где.has(код)) где.set(код, [])
      где.get(код).push(путь.replace(корень, ""))
    }
  }
  return где
}

/** Ключи AST, о которых эталон говорит «этого я не проверял». */
export function ключиЭталона(корень = КОРЕНЬ) {
  const текст = readFileSync(join(корень, ЭТАЛОН_ПРЕПЯТСТВИЯ), "utf8")
  const место = текст.indexOf("тотальная функция «Ключи поверхностей»")
  if (место === -1) return []
  const кусок = текст.slice(место, место + 2000)
  const список = /\[([^\]]*)\]/u.exec(кусок)
  const ключи = список === null ? [] : [...список[1].matchAll(/"([a-z]+)"/gu)].map((м) => м[1])
  /* Связь модулей ловится не ключом, а узлом `legacy`; имя она носит то же. */
  if (текст.includes('добавить "functors"')) ключи.push("functors")
  return ключи
}

/** Текст справки бинарника — оба этажа сразу. */
export function справка() {
  /* СПРАШИВАЕТСЯ У САМОГО ДВОИЧНОГО, а не читается из исходника справки.
     Раньше здесь открывался `flang/src/emit/c/flang_repl.c` — текст, из которого
     справка ПЕЧАТАЕТСЯ. Между текстом и тем, что человек увидит, стоит сборка, и
     сторож, читающий исходник, стережёт намерение, а не ответ. Спросить готовый
     двоичный и дешевле, и вернее: он отвечает за 7 мс. */
  return ["--help", "check --help"]
    .map((ключи) => позвать(ключи.split(" ")))
    .map(({ вывод, ошибки }) => `${вывод}${ошибки}`)
    .join("\n")
}

/* ── сама проверка ───────────────────────────────────────────────────────── */

/**
 * Нарушения; род у каждого свой:
 *
 *   `не названо`      — правило есть у свидетеля, нет у бинарника, и нет в РАЗНИЦА;
 *   `запись протухла` — правило из РАЗНИЦА появилось у бинарника: долг закрыт;
 *   `лишнее у бинарника` — код бинарника не назван ни свидетелем, ни списком;
 *   `справка молчит`  — поверхность из РАЗНИЦА не названа в справке бинарника;
 *   `эталон молчит`   — ключ поверхности не назван в «Названия непосчитанного»;
 *   `зазор без довода`— поверхность без ключей и без объяснения, почему их нет;
 *   `код дважды`      — один код назван двумя записями РАЗНИЦА.
 */
export function проверить(корень = КОРЕНЬ) {
  const бинарник = правилаБинарника(корень)
  const нарушения = []

  const названные = new Map()
  for (const запись of РАЗНИЦА) {
    for (const код of запись.коды) {
      if (названные.has(код)) {
        нарушения.push({
          род: "код дважды",
          что: код,
          почему: `${код} назван и записью «${названные.get(код).поверхность}», и «${запись.поверхность}»`,
        })
        continue
      }
      названные.set(код, запись)
    }
    if (запись.ключи.length === 0 && (запись.зазор ?? "").length < 40) {
      нарушения.push({
        род: "зазор без довода",
        что: запись.поверхность,
        почему: `поверхность «${запись.поверхность}» не ловится ни одним ключом AST, и почему — не сказано`,
      })
    }
  }

  /* ── ПОДДЕЛКИ: бинарник обязан НАЗВАТЬ то, чего не судил ────────────────
     Раньше здесь стояло вычитание кодов свидетеля из кодов бинарника. Свидетеля
     нет; вопрос спрашивается прогоном — сильнее, чем чтением текстов, потому что
     меряет ответ, а не намерение. */
  const глухие = new Map(ГЛУХИЕ_ПОДДЕЛКИ.map((з) => [з.файл, з]))
  const названныеКлючи = new Set()
  const все = подделки(корень)
  if (все.length === 0) {
    нарушения.push({
      род: "улик нет",
      что: ПОДДЕЛКИ,
      почему: "корпуса подделок нет вовсе — сторож остался бы зелёным ровно потому, что проверять стало нечего",
    })
  }
  for (const путь of все) {
    const имя = путь.split("/").at(-1)
    const ответ = ответНаПодделку(путь)
    const глухая = глухие.get(имя)
    if (ответ.код === 0) {
      if (глухая === undefined) {
        нарушения.push({
          род: "принято молча",
          что: имя,
          почему:
            "бинарник ответил «замечаний нет» и кодом 0 на ПОДДЕЛКЕ — программа со сломанным "
            + "объявлением прошла как проверенная. Либо чините бинарник, либо заведите запись "
            + "в ГЛУХИЕ_ПОДДЕЛКИ с доводом, почему назвать пробел ему нечем",
        })
      }
      continue
    }
    if (глухая !== undefined) {
      нарушения.push({
        род: "надгробие",
        что: имя,
        почему:
          `бинарник ОТВЕРГ эту подделку (код ${ответ.код}), а она числится в ГЛУХИЕ_ПОДДЕЛКИ — `
          + "запись пережила свою причину, снимите её",
      })
      continue
    }
    if (ответ.ключи.length === 0) {
      нарушения.push({
        род: "отказ без имени",
        что: имя,
        почему: `бинарник отказал кодом ${ответ.код}, но поверхность не назвал: «${ответ.текст.trim().slice(0, 120)}»`,
      })
      continue
    }
    for (const ключ of ответ.ключи) {
      названныеКлючи.add(ключ)
      if (РАЗНИЦА.some((запись) => запись.ключи.includes(ключ))) continue
      нарушения.push({
        род: "поверхность не записана",
        что: `${имя}/${ключ}`,
        почему: `бинарник назвал ключ «${ключ}», а в РАЗНИЦА такой поверхности нет — список разошёлся`,
      })
    }

    /* ── ВТОРАЯ ПОЛОВИНА ВОПРОСА: ВЫПУСТИТ ЛИ ПЕЧАТЬ ЭТУ ЖЕ ПОДДЕЛКУ МОЛЧА ──
       Проверка о подделке уже сказала (мы здесь ровно потому, что сказала).
       Печать до 20 августа 2026 говорила «проверено перед печатью» и отдавала
       код 0 на всех таких программах — то есть повторяла ту же дыру на выходе,
       которую проверка закрыла на входе. Требуется от неё не отказ, а немолчание:
       код 3 и названный пробел. */
    const печать = ответПечатиНаПодделку(путь)
    if (печать.код === 0) {
      нарушения.push({
        род: "напечатано молча",
        что: имя,
        почему:
          "печать выпустила ПОДДЕЛКУ кодом 0, хотя проверка о ней сказала (код "
          + `${ответ.код}): программа с непосуждённой поверхностью вышла из печати как полностью `
          + "проверенная. Ждём код 3 и названный пробел",
      })
    } else if (печать.ключи.length === 0) {
      нарушения.push({
        род: "печать без имени",
        что: имя,
        почему: `печать ответила кодом ${печать.код}, но поверхность не назвала: «${печать.текст.trim().slice(0, 120)}»`,
      })
    }
  }
  /* И обратная сторона: поверхность, у которой ключ есть, а улики нет, — это
     правило, которое никто не прогонял. */
  for (const запись of РАЗНИЦА) {
    if (запись.ключи.length === 0) continue
    if (запись.ключи.some((к) => названныеКлючи.has(к))) continue
    нарушения.push({
      род: "поверхность без улики",
      что: запись.поверхность,
      почему:
        `ни одна подделка в ${ПОДДЕЛКИ} не заставила бинарник назвать `
        + `${запись.ключи.map((к) => `«${к}»`).join(" или ")} — правило этой поверхности не прогоняется вовсе`,
    })
  }


  /* «ЛИШНЕЕ У БИНАРНИКА» БОЛЬШЕ НЕ СПРАШИВАЕТСЯ, и это не послабление, а
     следствие. Вопрос звучал «есть ли у бинарника код, которого нет у
     свидетеля»; свидетеля нет, и относительно него лишним стало ВСЁ — проверка
     обратилась бы в перечисление всех кодов дерева. Половина списка при этом
     живая: запись `ТОЛЬКО_У_БИНАРНИКА` называет код поимённо, и код, из
     бинарника ИСЧЕЗНУВШИЙ, оставляет запись врать. Её и сверяем. */
  for (const { код } of ТОЛЬКО_У_БИНАРНИКА) {
    if (бинарник.has(код)) continue
    нарушения.push({
      род: "запись протухла",
      что: код,
      почему: `${код} числится за бинарником, а в его замыкании такого кода нет — снимите запись`,
    })
  }

  /*
   * ВТОРАЯ СТОРОНА ДОЛГА, И ОНА НЕ ТРЕБУЕТ СВИДЕТЕЛЯ.
   *
   * Шапка обещала сверку в обе стороны: «правило из РАЗНИЦА, ПОЯВИВШЕЕСЯ у
   * бинарника, — тоже красно: долг закрыт, значит запись о долге стала
   * неправдой». Спрашивалась эта сторона вычитанием кодов свидетеля и вместе с
   * ним умерла — а спрашивать её можно и без него: список кодов бинарника
   * посчитан строкой выше, и запись из РАЗНИЦА, чей код в нём есть, врёт.
   *
   * Найдено прогоном, а не вычиткой: 21 августа в замыкание въехал
   * `self/setoid.flang`, и шесть кодов РАЗНИЦА («категория» — пять, «преобразование»
   * — один) оказались у бинарника. Ни одна проверка этого не назвала.
   */
  for (const запись of РАЗНИЦА) {
    for (const код of запись.коды) {
      if (!бинарник.has(код)) continue
      нарушения.push({
        род: "долг закрыт",
        что: `${запись.поверхность}/${код}`,
        почему:
          `${код} числится в РАЗНИЦА как то, чего у бинарника нет, — а в его замыкании этот код ЕСТЬ. `
          + "Правило переехало: снимите код из записи, иначе список долга врёт",
      })
    }
  }

  /* Регистр не считается: справка пишет «Уточнённые числовые типы» с прописной,
     когда слово начинает абзац, и требовать от неё строчной значило бы стеречь
     вёрстку, а не содержание. */
  /* Пробелы схлопываются ДО поиска: справка печатается с переносами по ширине
     терминала, и «связь модулей» разорвано на «связь\nмодулей». Поиск подстроки
     не находил слова, которое стоит на месте, — сторож краснел на переносе
     строки. Перенос — вёрстка, а сторож про состав. */
  const текстСправки = справка().toLowerCase().replace(/\s+/gu, " ")
  const ключи = ключиЭталона(корень)
  for (const запись of РАЗНИЦА) {
    if (!текстСправки.includes(запись.слово.toLowerCase())) {
      нарушения.push({
        род: "справка молчит",
        что: запись.поверхность,
        почему: `справка бинарника не называет «${запись.слово}» — человек считает такую программу проверенной`,
      })
    }
    for (const ключ of запись.ключи) {
      if (ключи.includes(ключ)) continue
      нарушения.push({
        род: "эталон молчит",
        что: `${запись.поверхность}/${ключ}`,
        почему: `ключ «${ключ}» не назван в «Названия непосчитанного» — бинарник промолчит о такой программе`,
      })
    }
  }
  for (const ключ of ключи) {
    if (РАЗНИЦА.some((запись) => запись.ключи.includes(ключ))) continue
    нарушения.push({
      род: "эталон молчит",
      что: ключ,
      почему: `эталон называет ключ «${ключ}», а в РАЗНИЦА такой поверхности нет — список разошёлся`,
    })
  }

  return нарушения
}

/** Числа для отчёта: сколько правил у бинарника, сколько подделок и глухих. */
export function числа(корень = КОРЕНЬ) {
  const бинарник = правилаБинарника(корень)
  const все = подделки(корень)
  let названо = 0
  for (const путь of все) if (ответНаПодделку(путь).код !== 0) названо += 1
  return {
    бинарник: бинарник.size,
    подделок: все.length,
    названо,
    глухих: ГЛУХИЕ_ПОДДЕЛКИ.length,
    поверхностей: РАЗНИЦА.length,
  }
}

