/** Текст без комментариев: код, названный прозой, — рассказ, а не правило. */
export function безКомментариев(путь, текст) {
  if (путь.endsWith(".mjs") || путь.endsWith(".c") || путь.endsWith(".h")) {
    return текст.replace(/\/\*[\s\S]*?\*\//gu, "").replace(/(?<!:)\/\/[^\n]*/gu, "")
  }
  return текст.replace(/\/\/[^\n]*/gu, "")
}

/** Коды из строковых литералов файла. */
export function кодыФайла(путь, текст) {
  const код = безКомментариев(путь, текст)
  const найдено = new Set()
  const литералы = [
    ...код.matchAll(/"((?:[^"\\\n]|\\.)*)"/gu),
    ...код.matchAll(/`([^`]*)`/gu),
  ]
  for (const литерал of литералы) for (const имя of литерал[1].match(ИМЯ_КОДА) ?? []) найдено.add(имя)
  return найдено
}

/**
 * ФРАЗЫ, КОТОРЫМИ БИНАРНИК НАЗЫВАЕТ НЕПОСУЖДЁННОЕ.
 *
 * ── Порода, ради которой этот список заведён ───────────────────────────────
 * Сторож, который ищет ФРАЗУ, сторожит фразу, а не правило. Исчезни фраза — он
 * не покраснеет и не позеленеет: он просто перестанет считать, оставшись
 * зелёным по этой части. Так и вышло: сторож ловил одну форму («не суди… вовсе
 * — X»), а задача 1853 ввезла судью процессов, и о процессах бинарник заговорил
 * второй формой — «объявления эти сверены НЕ ДО КОНЦА — processes: …». Сторож
 * этого не увидел и выдал ДВЕ ложных находки разом: «отказ без имени» на
 * `handler-without-budget.flang`, где поверхность названа, и «поверхность без
 * улики» на процессах, у которых улика есть.
 *
 * Поэтому формы не просто перечислены — каждая СВЕРЯЕТСЯ С ЭТАЛОНОМ. Пропала
 * форма из `flang/self/bootstrap/compiler.flang` — сторож краснеет родом
 * «форма ответа пропала», а не тихо перестаёт считать. Появилась третья — её
 * найдёт первая же подделка, которую перестанут называть.
 */
export const ФОРМЫ_ОТВЕТА = Object.freeze([
  {
    зачем: "поверхность не судится никак; так же говорит и печать, кодом 3",
    метка: "чего бинарник не судит вовсе — ",
    ловит: /не суди[а-я]* вовсе — ([a-z, ]+)/gu,
  },
  {
    зачем: "ЗАКОН посчитан на сетке, а устройство объявления не сверялось",
    метка: "УСТРОЙСТВО этих объявлений бинарник не судит вовсе — ",
    ловит: /не суди[а-я]* вовсе — ([a-z, ]+)/gu,
  },
  {
    зачем: "поверхность судится, но не до конца: часть правил названа, часть — нет",
    метка: "объявления эти сверены НЕ ДО КОНЦА — ",
    ловит: /сверены НЕ ДО КОНЦА — ([a-z, ]+)/gu,
  },
])

/** Ключи поверхностей из слов бинарника — всеми формами сразу. */
export function ключиИзОтвета(текст) {
  const ключи = []
  for (const форма of ФОРМЫ_ОТВЕТА) {
    for (const м of текст.matchAll(форма.ловит)) {
      for (const ключ of м[1].split(",").map((к) => к.trim()).filter(Boolean)) {
        if (!ключи.includes(ключ)) ключи.push(ключ)
      }
    }
  }
  return ключи
}

/**
 * Что бинарник отвечает на одной подделке: код и названные им ключи.
 *
 * Ключи вынимаются из его же слов: «в программе объявлено то, чего бинарник не
 * судит вовсе — monoids». Читать его сообщение, а не считать что-то своё, —
 * условие честности сторожа: он проверяет, что бинарник СКАЗАЛ, а не что он
 * должен был бы сказать.
 */
export function ответНаПодделку(путь) {
  const { код, вывод, ошибки } = позвать(["check", путь])
  const текст = `${вывод}${ошибки}`
  /*
   * ФОРМ ТРИ, И ЭТО НЕ ТРИ СПОСОБА СКАЗАТЬ ОДНО — см. `ФОРМЫ_ОТВЕТА`. Для
   * этого сторожа все три значат одно: поверхность НАЗВАНА. Ловим все, ключи
   * складываем.
   */
  return { код, ключи: ключиИзОтвета(текст), текст }
}

/**
 * Что ПЕЧАТЬ отвечает на одной подделке: код и названные ею ключи.
 *
 * Вопрос здесь другой, чем у `check`, и он второй половиной той же дыры.
 * Проверка научилась отвечать «я не судила» кодом 2, печать научилась не
 * выпускать НЕ ПРОШЕДШЕЕ проверку кодом 1 — а между ними осталась щель: код 2
 * печать не останавливал, и программа с непосуждённой поверхностью выходила
 * кодом 0 со словами «проверено перед печатью». Замер 20 августа 2026: 41
 * программа дерева из 951 (26 из 294 в корпусе ведомости) — и все 41
 * печатались кодом 0.
 *
 * Требуется от печати НЕ отказ: отказывай она, как на не прошедшей проверку, —
 * категорную и процессную часть языка стало бы нечем собрать без Node.
 * Требуется НЕМОЛЧАНИЕ: файлы напечатаны, пробел назван поимённо, код 3.
 *
 * Каталог вывода уезжает во временное место и убирается сразу: сторожу нужен
 * код и слова, а не файлы.
 */
export function ответПечатиНаПодделку(путь) {
  const корень = process.env.FLANG_TEST_TMPDIR ?? tmpdir()
  const где = mkdtempSync(join(корень, "flang-rules-emit-"))
  try {
    const { код, вывод, ошибки } = позвать(["emit", путь, "--target", "c", "--out", где])
    const текст = `${вывод}${ошибки}`
    return { код, ключи: ключиИзОтвета(текст), текст }
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
}

/** Все подделки корпуса — по имени файла. */
export function подделки(корень = КОРЕНЬ) {
  const где = join(корень, ПОДДЕЛКИ)
  let свои = []
  try {
    /* Четыре равноправных расширения программы: `.flang`, `.fp`, `.фп`, `.фланг` (ADR-0016). */
    свои = readdirSync(где).filter((и) => /\.(flang|fp|фп|фланг)$/u.test(и)).sort().map((и) => join(где, и))
  } catch {
    свои = []
  }
  return [...свои, ...ПОДДЕЛКИ_ВРОЗЬ.map((п) => join(корень, п))].filter((п) => existsSync(п))
}

