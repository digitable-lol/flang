/**
 * Нарушения; род у каждого свой:
 *
 *   `не названо`      — правило есть у свидетеля, нет у бинарника, и нет в РАЗНИЦА;
 *   `запись протухла` — правило из РАЗНИЦА появилось у бинарника: долг закрыт;
 *   `лишнее у бинарника` — код бинарника не назван ни свидетелем, ни списком;
 *   `справка молчит`  — поверхность из РАЗНИЦА не названа в справке бинарника;
 *   `эталон молчит`   — ключ поверхности не назван в «Ключи поверхностей»;
 *   `зазор без довода`— поверхность без ключей и без объяснения, почему их нет;
 *   `код дважды`      — один код назван двумя записями РАЗНИЦА;
 *   `смотреть не во что` — напечатанного компилятора нет: состав правил снять неоткуда;
 *   `форма ответа пропала` — эталон больше не говорит фразой, которую сторож ловит.
 */
export function проверить(корень = КОРЕНЬ) {
  const бинарник = правилаБинарника(корень)
  const нарушения = []

  /* ── СМОТРЕТЬ ЕСТЬ ВО ЧТО ───────────────────────────────────────────────
     Пустой список правил обесточивает разом две проверки ниже — и обе они при
     этом остались бы ЗЕЛЁНЫМИ по своей части. Это ровно тот способ, каким
     сторож ослеп в прошлый раз, поэтому спрашивается прямо. */
  if (бинарник.size === 0) {
    нарушения.push({
      род: "смотреть не во что",
      что: НАПЕЧАТАННЫЙ_КОМПИЛЯТОР,
      почему:
        "напечатанного компилятора нет или в нём ни одного кода отказа — состав правил бинарника "
        + "снять неоткуда, и проверки «запись протухла» и «долг закрыт» промолчали бы зелёными. "
        + "Перепечатайте точку раскрутки: sh scripts/bootstrap-c.sh",
    })
  }

  /* ── ФОРМЫ ОТВЕТА ЖИВЫ ──────────────────────────────────────────────────
     Сторож ловит слова бинарника, а слова меняются. Пока форма стоит в
     эталоне — ловля осмысленна; исчезла — сторож обязан покраснеть, а не
     перестать считать. Довод целиком — над `ФОРМЫ_ОТВЕТА`. */
  {
    const эталон = readFileSync(join(корень, ЭТАЛОН_ПРЕПЯТСТВИЯ), "utf8")
    for (const форма of ФОРМЫ_ОТВЕТА) {
      if (эталон.includes(форма.метка)) continue
      нарушения.push({
        род: "форма ответа пропала",
        что: форма.метка,
        почему:
          `эталон больше не говорит «${форма.метка}» (${форма.зачем}) — сторож ловит эту фразу и `
          + "с её исчезновением перестал бы считать эту часть МОЛЧА, оставшись зелёным. Либо "
          + "поправьте ФОРМЫ_ОТВЕТА под новые слова, либо верните фразу",
      })
    }
  }

  const названные = new Map()
  for (const запись of РАЗНИЦА) {
    for (const код of запись.коды) {
      if (названные.has(код)) {
        нарушения.push({
          род: "код дважды",
          что: код,
          почему: `${код} назван и записью «${названные.get(код).поверхность}», и «${запись.поверхность}»`,
        })
        continue
      }
      названные.set(код, запись)
    }
    if (запись.ключи.length === 0 && (запись.зазор ?? "").length < 40) {
      нарушения.push({
        род: "зазор без довода",
        что: запись.поверхность,
        почему: `поверхность «${запись.поверхность}» не ловится ни одним ключом AST, и почему — не сказано`,
      })
    }
  }

  /* ── ПОДДЕЛКИ: бинарник обязан НАЗВАТЬ то, чего не судил ────────────────
     Раньше здесь стояло вычитание кодов свидетеля из кодов бинарника. Свидетеля
     нет; вопрос спрашивается прогоном — сильнее, чем чтением текстов, потому что
     меряет ответ, а не намерение. */
  const глухие = new Map(ГЛУХИЕ_ПОДДЕЛКИ.map((з) => [з.файл, з]))
  const названныеКлючи = new Set()
  const все = подделки(корень)
  if (все.length === 0) {
    нарушения.push({
      род: "улик нет",
      что: ПОДДЕЛКИ,
      почему: "корпуса подделок нет вовсе — сторож остался бы зелёным ровно потому, что проверять стало нечего",
    })
  }
  for (const путь of все) {
    const имя = путь.split("/").at(-1)
    const ответ = ответНаПодделку(путь)
    const глухая = глухие.get(имя)
    if (ответ.код === 0) {
      if (глухая === undefined) {
        нарушения.push({
          род: "принято молча",
          что: имя,
          почему:
            "бинарник ответил «замечаний нет» и кодом 0 на ПОДДЕЛКЕ — программа со сломанным "
            + "объявлением прошла как проверенная. Либо чините бинарник, либо заведите запись "
            + "в ГЛУХИЕ_ПОДДЕЛКИ с доводом, почему назвать пробел ему нечем",
        })
      }
      continue
    }
    if (глухая !== undefined) {
      нарушения.push({
        род: "надгробие",
        что: имя,
        почему:
          `бинарник ОТВЕРГ эту подделку (код ${ответ.код}), а она числится в ГЛУХИЕ_ПОДДЕЛКИ — `
          + "запись пережила свою причину, снимите её",
      })
      continue
    }
    if (ответ.ключи.length === 0) {
      нарушения.push({
        род: "отказ без имени",
        что: имя,
        почему: `бинарник отказал кодом ${ответ.код}, но поверхность не назвал: «${ответ.текст.trim().slice(0, 120)}»`,
      })
      continue
    }
    for (const ключ of ответ.ключи) {
      названныеКлючи.add(ключ)
      if (РАЗНИЦА.some((запись) => запись.ключи.includes(ключ))) continue
      нарушения.push({
        род: "поверхность не записана",
        что: `${имя}/${ключ}`,
        почему: `бинарник назвал ключ «${ключ}», а в РАЗНИЦА такой поверхности нет — список разошёлся`,
      })
    }

    /* ── ВТОРАЯ ПОЛОВИНА ВОПРОСА: ВЫПУСТИТ ЛИ ПЕЧАТЬ ЭТУ ЖЕ ПОДДЕЛКУ МОЛЧА ──
       Проверка о подделке уже сказала (мы здесь ровно потому, что сказала).
       Печать до 20 августа 2026 говорила «проверено перед печатью» и отдавала
       код 0 на всех таких программах — то есть повторяла ту же дыру на выходе,
       которую проверка закрыла на входе. Требуется от неё не отказ, а немолчание:
       код 3 и названный пробел. */
    const печать = ответПечатиНаПодделку(путь)
    if (печать.код === 0) {
      нарушения.push({
        род: "напечатано молча",
        что: имя,
        почему:
          "печать выпустила ПОДДЕЛКУ кодом 0, хотя проверка о ней сказала (код "
          + `${ответ.код}): программа с непосуждённой поверхностью вышла из печати как полностью `
          + "проверенная. Ждём код 3 и названный пробел",
      })
    } else if (печать.код !== 1 && печать.ключи.length === 0) {
      нарушения.push({
        род: "печать без имени",
        что: имя,
        почему: `печать ВЫПУСТИЛА файлы кодом ${печать.код}, но поверхность не назвала: «${печать.текст.trim().slice(0, 120)}»`,
      })
    }
    /* КОД 1 — ЭТО ОТКАЗ, А НЕ МОЛЧАНИЕ, И ТРЕБОВАТЬ С НЕГО ИМЯ ЗНАЧИЛО БЫ
       СТЕРЕЧЬ НЕ ТО. Вопрос этой половины сторожа один: не вышла ли
       непосуждённая программа из печати как полностью проверенная. Печать,
       сказавшая «печать отменена — программа не проходит проверку», не выпустила
       ничего, и называть в отказе непосуждённые поверхности ей незачем — их
       называет `check`, к которому она же и отсылает. Требование стояло, и
       давало ДВЕ ложных находки на подделках сломанного ЗАКОНА
       (`equality-not-symmetric.flang`, `transform-not-natural.flang`): бинарник
       отвергает их кодом 1 с названным контрпримером — то есть работает ровно
       так, как надо, — а сторож звал это «печать без имени». Замер 6 сентября
       2026, обе проверены прогоном порознь. */
  }
  /* И обратная сторона: поверхность, у которой ключ есть, а улики нет, — это
     правило, которое никто не прогонял. */
  for (const запись of РАЗНИЦА) {
    if (запись.ключи.length === 0) continue
    if (запись.ключи.some((к) => названныеКлючи.has(к))) continue
    нарушения.push({
      род: "поверхность без улики",
      что: запись.поверхность,
      почему:
        `ни одна подделка в ${ПОДДЕЛКИ} не заставила бинарник назвать `
        + `${запись.ключи.map((к) => `«${к}»`).join(" или ")} — правило этой поверхности не прогоняется вовсе`,
    })
  }


  /* «ЛИШНЕЕ У БИНАРНИКА» БОЛЬШЕ НЕ СПРАШИВАЕТСЯ, и это не послабление, а
     следствие. Вопрос звучал «есть ли у бинарника код, которого нет у
     свидетеля»; свидетеля нет, и относительно него лишним стало ВСЁ — проверка
     обратилась бы в перечисление всех кодов дерева. Половина списка при этом
     живая: запись `ТОЛЬКО_У_БИНАРНИКА` называет код поимённо, и код, из
     бинарника ИСЧЕЗНУВШИЙ, оставляет запись врать. Её и сверяем. */
  for (const { код } of ТОЛЬКО_У_БИНАРНИКА) {
    if (бинарник.has(код)) continue
    нарушения.push({
      род: "запись протухла",
      что: код,
      почему: `${код} числится за бинарником, а в его замыкании такого кода нет — снимите запись`,
    })
  }

  /*
   * ВТОРАЯ СТОРОНА ДОЛГА, И ОНА НЕ ТРЕБУЕТ СВИДЕТЕЛЯ.
   *
   * Шапка обещала сверку в обе стороны: «правило из РАЗНИЦА, ПОЯВИВШЕЕСЯ у
   * бинарника, — тоже красно: долг закрыт, значит запись о долге стала
   * неправдой». Спрашивалась эта сторона вычитанием кодов свидетеля и вместе с
   * ним умерла — а спрашивать её можно и без него: список кодов бинарника
   * посчитан строкой выше, и запись из РАЗНИЦА, чей код в нём есть, врёт.
   *
   * Найдено прогоном, а не вычиткой: 21 августа в замыкание въехал
   * `self/setoid.flang`, и шесть кодов РАЗНИЦА («категория» — пять, «преобразование»
   * — один) оказались у бинарника. Ни одна проверка этого не назвала.
   */
  for (const запись of РАЗНИЦА) {
    for (const код of запись.коды) {
      if (!бинарник.has(код)) continue
      нарушения.push({
        род: "долг закрыт",
        что: `${запись.поверхность}/${код}`,
        почему:
          `${код} числится в РАЗНИЦА как то, чего у бинарника нет, — а в его замыкании этот код ЕСТЬ. `
          + "Правило переехало: снимите код из записи, иначе список долга врёт",
      })
    }
  }

  /* Регистр не считается: справка пишет «Уточнённые числовые типы» с прописной,
     когда слово начинает абзац, и требовать от неё строчной значило бы стеречь
     вёрстку, а не содержание. */
  /* Пробелы схлопываются ДО поиска: справка печатается с переносами по ширине
     терминала, и «связь модулей» разорвано на «связь\nмодулей». Поиск подстроки
     не находил слова, которое стоит на месте, — сторож краснел на переносе
     строки. Перенос — вёрстка, а сторож про состав. */
  const текстСправки = справка().toLowerCase().replace(/\s+/gu, " ")
  const ключи = ключиЭталона(корень)
  for (const запись of РАЗНИЦА) {
    if (!текстСправки.includes(запись.слово.toLowerCase())) {
      нарушения.push({
        род: "справка молчит",
        что: запись.поверхность,
        почему: `справка бинарника не называет «${запись.слово}» — человек считает такую программу проверенной`,
      })
    }
    for (const ключ of запись.ключи) {
      if (ключи.includes(ключ)) continue
      нарушения.push({
        род: "эталон молчит",
        что: `${запись.поверхность}/${ключ}`,
        почему: `ключ «${ключ}» не назван в «Ключи поверхностей» — бинарник промолчит о такой программе`,
      })
    }
  }
  for (const ключ of ключи) {
    if (РАЗНИЦА.some((запись) => запись.ключи.includes(ключ))) continue
    нарушения.push({
      род: "эталон молчит",
      что: ключ,
      почему: `эталон называет ключ «${ключ}», а в РАЗНИЦА такой поверхности нет — список разошёлся`,
    })
  }

  return нарушения
}

/** Числа для отчёта: сколько правил у бинарника, сколько подделок и глухих. */
export function числа(корень = КОРЕНЬ) {
  const бинарник = правилаБинарника(корень)
  const все = подделки(корень)
  let названо = 0
  for (const путь of все) if (ответНаПодделку(путь).код !== 0) названо += 1
  return {
    бинарник: бинарник.size,
    подделок: все.length,
    названо,
    глухих: ГЛУХИЕ_ПОДДЕЛКИ.length,
    поверхностей: РАЗНИЦА.length,
  }
}

