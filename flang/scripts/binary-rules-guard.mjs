/* ── чтение исходников ───────────────────────────────────────────────────── */

/** Текст без комментариев: код, названный прозой, — рассказ, а не правило. */
export function безКомментариев(путь, текст) {
  if (путь.endsWith(".mjs") || путь.endsWith(".c") || путь.endsWith(".h")) {
    return текст.replace(/\/\*[\s\S]*?\*\//gu, "").replace(/(?<!:)\/\/[^\n]*/gu, "")
  }
  return текст.replace(/\/\/[^\n]*/gu, "")
}

/** Коды из строковых литералов файла. */
export function кодыФайла(путь, текст) {
  const код = безКомментариев(путь, текст)
  const найдено = new Set()
  const литералы = [
    ...код.matchAll(/"((?:[^"\\\n]|\\.)*)"/gu),
    ...код.matchAll(/`([^`]*)`/gu),
  ]
  for (const литерал of литералы) for (const имя of литерал[1].match(ИМЯ_КОДА) ?? []) найдено.add(имя)
  return найдено
}

/** Замыкание импортов `.flang` от одного входа. */
export function замыкание(вход, корень = КОРЕНЬ) {
  const виден = new Set()
  const очередь = [resolve(корень, вход)]
  while (очередь.length > 0) {
    const путь = очередь.pop()
    if (виден.has(путь) || !existsSync(путь)) continue
    виден.add(путь)
    const текст = readFileSync(путь, "utf8")
    for (const строка of текст.matchAll(/использует\s+«[^»]+»\s+из\s+"([^"]+)"/gu)) {
      очередь.push(resolve(dirname(путь), строка[1]))
    }
  }
  return [...виден].sort()
}

/**
 * Слои на flang, которые зовёт рабочий путь свидетеля, — читаются из
 * `flang/src/self.mjs`, а не выписываются здесь.
 */
export function слоиСвидетеля(корень = КОРЕНЬ) {
  const текст = readFileSync(join(корень, "flang/src/self.mjs"), "utf8")
  const имена = new Set([
    ...[...текст.matchAll(/\.\.\/self\/([a-z-]+\.flang)/gu)].map((м) => м[1]),
    ...[...текст.matchAll(/"([a-z-]+\.flang)"/gu)].map((м) => м[1]),
  ])
  const файлы = new Set()
  for (const имя of имена) for (const путь of замыкание(`flang/self/${имя}`, корень)) файлы.add(путь)
  return [...файлы].sort()
}

/** Правила свидетеля: судящие файлы плюс слои на flang. */
export function правилаСвидетеля(корень = КОРЕНЬ) {
  const где = new Map()
  const добавить = (путь) => {
    if (!existsSync(путь)) return
    for (const код of кодыФайла(путь, readFileSync(путь, "utf8"))) {
      if (!где.has(код)) где.set(код, [])
      где.get(код).push(путь.replace(корень, ""))
    }
  }
  for (const отн of СУДЬИ_СВИДЕТЕЛЯ) добавить(join(корень, отн))
  for (const путь of слоиСвидетеля(корень)) добавить(путь)
  return где
}

/** Правила бинарника: замыкание точки входа. */
export function правилаБинарника(корень = КОРЕНЬ) {
  const где = new Map()
  for (const путь of замыкание(ВХОД_БИНАРНИКА, корень)) {
    for (const код of кодыФайла(путь, readFileSync(путь, "utf8"))) {
      if (!где.has(код)) где.set(код, [])
      где.get(код).push(путь.replace(корень, ""))
    }
  }
  return где
}

/** Ключи AST, о которых эталон говорит «этого я не проверял». */
export function ключиЭталона(корень = КОРЕНЬ) {
  const текст = readFileSync(join(корень, ЭТАЛОН_ПРЕПЯТСТВИЯ), "utf8")
  const место = текст.indexOf("тотальная функция «Ключи поверхностей»")
  if (место === -1) return []
  const кусок = текст.slice(место, место + 2000)
  const список = /\[([^\]]*)\]/u.exec(кусок)
  const ключи = список === null ? [] : [...список[1].matchAll(/"([a-z]+)"/gu)].map((м) => м[1])
  /* Связь модулей ловится не ключом, а узлом `legacy`; имя она носит то же. */
  if (текст.includes('добавить "functors"')) ключи.push("functors")
  return ключи
}

/** Текст справки бинарника — оба этажа сразу. */
export function справка(корень = КОРЕНЬ) {
  return readFileSync(join(корень, СПРАВКА), "utf8")
}

/* ── сама проверка ───────────────────────────────────────────────────────── */

/**
 * Нарушения; род у каждого свой:
 *
 *   `не названо`      — правило есть у свидетеля, нет у бинарника, и нет в РАЗНИЦА;
 *   `запись протухла` — правило из РАЗНИЦА появилось у бинарника: долг закрыт;
 *   `лишнее у бинарника` — код бинарника не назван ни свидетелем, ни списком;
 *   `справка молчит`  — поверхность из РАЗНИЦА не названа в справке бинарника;
 *   `эталон молчит`   — ключ поверхности не назван в «Названия непосчитанного»;
 *   `зазор без довода`— поверхность без ключей и без объяснения, почему их нет;
 *   `код дважды`      — один код назван двумя записями РАЗНИЦА.
 */
export function проверить(корень = КОРЕНЬ) {
  const свидетель = правилаСвидетеля(корень)
  const бинарник = правилаБинарника(корень)
  const нарушения = []

  const названные = new Map()
  for (const запись of РАЗНИЦА) {
    for (const код of запись.коды) {
      if (названные.has(код)) {
        нарушения.push({
          род: "код дважды",
          что: код,
          почему: `${код} назван и записью «${названные.get(код).поверхность}», и «${запись.поверхность}»`,
        })
        continue
      }
      названные.set(код, запись)
    }
    if (запись.ключи.length === 0 && (запись.зазор ?? "").length < 40) {
      нарушения.push({
        род: "зазор без довода",
        что: запись.поверхность,
        почему: `поверхность «${запись.поверхность}» не ловится ни одним ключом AST, и почему — не сказано`,
      })
    }
  }

  const нетУБинарника = [...свидетель.keys()].filter((код) => !бинарник.has(код)).sort()
  for (const код of нетУБинарника) {
    if (названные.has(код)) continue
    нарушения.push({
      род: "не названо",
      что: код,
      почему:
        `${код} есть у свидетеля (${свидетель.get(код).join(", ")}) и нет у бинарника, ` +
        "а в РАЗНИЦА не назван: бинарник примет такую программу молча",
    })
  }
  for (const [код, запись] of названные) {
    if (!бинарник.has(код)) continue
    нарушения.push({
      род: "запись протухла",
      что: код,
      почему:
        `${код} появился у бинарника (${бинарник.get(код).join(", ")}), а запись «${запись.поверхность}» ` +
        "по-прежнему числит его в долгах — снимите запись",
    })
  }

  const свои = new Set(ТОЛЬКО_У_БИНАРНИКА.map((з) => з.код))
  for (const код of [...бинарник.keys()].sort()) {
    if (свидетель.has(код) || свои.has(код)) continue
    нарушения.push({
      род: "лишнее у бинарника",
      что: код,
      почему: `${код} есть у бинарника (${бинарник.get(код).join(", ")}) и не назван ни свидетелем, ни списком ТОЛЬКО_У_БИНАРНИКА`,
    })
  }
  for (const { код } of ТОЛЬКО_У_БИНАРНИКА) {
    if (бинарник.has(код) && !свидетель.has(код)) continue
    нарушения.push({
      род: "запись протухла",
      что: код,
      почему: `${код} числится «только у бинарника», а это уже неправда — снимите запись`,
    })
  }

  /* Регистр не считается: справка пишет «Уточнённые числовые типы» с прописной,
     когда слово начинает абзац, и требовать от неё строчной значило бы стеречь
     вёрстку, а не содержание. */
  const текстСправки = справка(корень).toLowerCase()
  const ключи = ключиЭталона(корень)
  for (const запись of РАЗНИЦА) {
    if (!текстСправки.includes(запись.слово.toLowerCase())) {
      нарушения.push({
        род: "справка молчит",
        что: запись.поверхность,
        почему: `справка бинарника не называет «${запись.слово}» — человек считает такую программу проверенной`,
      })
    }
    for (const ключ of запись.ключи) {
      if (ключи.includes(ключ)) continue
      нарушения.push({
        род: "эталон молчит",
        что: `${запись.поверхность}/${ключ}`,
        почему: `ключ «${ключ}» не назван в «Названия непосчитанного» — бинарник промолчит о такой программе`,
      })
    }
  }
  for (const ключ of ключи) {
    if (РАЗНИЦА.some((запись) => запись.ключи.includes(ключ))) continue
    нарушения.push({
      род: "эталон молчит",
      что: ключ,
      почему: `эталон называет ключ «${ключ}», а в РАЗНИЦА такой поверхности нет — список разошёлся`,
    })
  }

  return нарушения
}

/** Числа для отчёта: сколько правил у кого и сколько расходится. */
export function числа(корень = КОРЕНЬ) {
  const свидетель = правилаСвидетеля(корень)
  const бинарник = правилаБинарника(корень)
  return {
    свидетель: свидетель.size,
    бинарник: бинарник.size,
    расходится: [...свидетель.keys()].filter((код) => !бинарник.has(код)).length,
    поверхностей: РАЗНИЦА.length,
  }
}

/* ── запуск из командной строки ──────────────────────────────────────────── */
if (import.meta.url === `file://${process.argv[1]}`) {
  const итог = числа()
  const нарушения = проверить()
  console.log(
    `правил у свидетеля: ${итог.свидетель}; у бинарника: ${итог.бинарник}; ` +
    `расходится: ${итог.расходится} на ${итог.поверхностей} поверхностях`,
  )
  for (const н of нарушения) console.log(`${н.род}: ${н.что} — ${н.почему}`)
  console.log(нарушения.length === 0 ? "нарушений нет" : `нарушений: ${нарушения.length}`)
  process.exitCode = нарушения.length === 0 ? 0 : 1
}
