/**
 * Сторож СОСТАВА ПРАВИЛ: чем судит свидетель на Node и чем судит бинарник.
 *
 * ── Дыра, ради которой он написан ───────────────────────────────────────────
 *
 * Собранный бинарник — тот, что человек ставит через Homebrew, — МОЛЧА
 * ПРИНИМАЛ сломанные программы. Улика, снятая прогоном на свежем `github/main`:
 * 13 подделок, по одной на объявление (`flang/test/fixtures/binary-rules/` и
 * `flang/examples/web/shortener/handler-without-budget.flang`). Свидетель на
 * Node отверг ВСЕ 13 с названным кодом; бинарник ответил
 * «проверено — замечаний нет» и кодом 0 на ВСЕХ 13.
 *
 * Причина не в одном пропущенном слое. Проверка типов у бинарника СВОЯ
 * (`flang/self/types.flang`), и категорной поверхности она не знает вовсе:
 * `flang/src/types.mjs` печатает 58 кодов отказа, эталон на flang — 10.
 * Плюс девять слоёв законов (`monoid`, `iso`, `functor`, `setoid`, `sets`,
 * пять свойств), которые свидетель зовёт из `flang/src/self.mjs`, а в замыкание
 * `flang/self/bootstrap/compiler.flang` не втащен ни один.
 *
 * ── Почему сверка этого не ловила ───────────────────────────────────────────
 *
 * `flang/test/self-bootstrap.test.mjs`, тест «flang₁ выносит те же вердикты и
 * диагностики, что свидетель», СТРОИТ ОЖИДАЕМЫЙ ОТВЕТ САМ:
 *
 *     const ждём = [...беды связывания, ...checkTypes(…), ...checkTotality(…)]
 *
 * — то есть тремя правилами из тех, что есть у ОБОИХ. Всё, что свидетель
 * добавляет сверх них (девять слоёв законов, словарь связи модулей, процессы),
 * вычитается из сравнения ДО сравнения. Тот же род дыры, что описан в шапке
 * `flang/scripts/comparison-guard.mjs`: сверка спрашивает «одинаково ли вы
 * делаете то, что делаете одинаково». Второй замок: корпус там чистый, а набор
 * СЛОМАННЫХ прибит списком из шести кодов, и ни один из них не категорный.
 *
 * ── Что сторожится здесь ────────────────────────────────────────────────────
 *
 * Не «список того, чего нет», набранный руками, — такой протухает. Сверяется
 * СОСТАВ ПРАВИЛ двух реализаций, и сверяется В ОБЕ СТОРОНЫ:
 *
 *   • правило, дописанное свидетелю и не названное в `РАЗНИЦА`, — красно;
 *   • правило из `РАЗНИЦА`, ПОЯВИВШЕЕСЯ у бинарника, — тоже красно: долг
 *     закрыт, значит запись о долге стала неправдой, и убрать её обязан тот,
 *     кто долг закрыл.
 *
 * Правилом считается КОД ОТКАЗА, встреченный в строковом литерале судящего
 * файла. Комментарии снимаются: код, названный прозой, — это рассказ о правиле,
 * а не правило.
 *
 * И третья половина, ради которой сторож и заводился: каждая поверхность из
 * `РАЗНИЦА` обязана быть НАЗВАНА В СПРАВКЕ БИНАРНИКА и (если она ловится по
 * объявлению) в списке `«Названия непосчитанного»` эталона. Справка, молчащая
 * о том, чего в бинарнике нет, хуже отсутствующей: по ней человек считает
 * программу проверенной.
 *
 * ── Чего сторож НЕ делает ───────────────────────────────────────────────────
 *
 * • Он НЕ проверяет достижимость ветки: существование кода в исходнике — не то
 *   же, что «этот код когда-нибудь напечатается». Что подделка правда
 *   отвергается, проверяется прогоном — `flang/test/binary-rules.test.mjs`.
 * • Он НЕ судит команды `io`, `lock`, `package`, `emit`: их коды — про вызов и
 *   про хозяина, а не про программу. Судящими считаются ровно те файлы, что
 *   названы в `СУДЬИ_*`.
 *
 * Запуск: `node flang/scripts/binary-rules-guard.mjs` (или `npm run rules:check`).
 * Проверяется он сам — `flang/test/binary-rules-guard.test.mjs`.
 */
