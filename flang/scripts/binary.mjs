/**
 * ЧЕМ СТОРОЖА ЧИТАЮТ `.flang` ПОСЛЕ УДАЛЕНИЯ РЕАЛИЗАЦИИ НА JAVASCRIPT.
 *
 * До 20 августа 2026 сторожа звали `parse` из `flang/src/parser.mjs` и читали
 * дерево в своём же процессе. Реализации на JavaScript больше нет — компилятор
 * один, двоичный, собранный из `bootstrap/`. Второй разбор `.flang` заводить
 * нельзя: он и есть то, что владелец велел убрать, и разойдётся с настоящим на
 * первой же правке языка.
 *
 * Поэтому здесь ровно один приём: СПРОСИТЬ ДВОИЧНЫЙ и прочитать его JSON.
 *
 *   flang ast <файл>                дерево, разобранное и СВЯЗАННОЕ
 *   flang tokens <файл> --json      поток токенов, БЕЗ связывания
 *   flang tokens --keyword «фраза»  ключевое ли это слово
 *   flang check <файл> --proof --json   ведомость доказательств
 *   flang test <корпус> --json          прогон примеров числами
 *
 * ── Связывание, и почему из-за него нужна ВЫЧИТАЛКА ─────────────────────────
 *
 * `flang ast` отдаёт дерево ПОСЛЕ связывания: у файла с «использует … из "…"»
 * в `functions` лежат и чужие функции — те, что приехали из подключённых
 * файлов. Сторожу имён это испортило бы счёт (чужая функция посчиталась бы
 * столько раз, сколько файлов её подключили), а места указали бы на строки
 * ЧУЖОГО файла: собственных строк у приезжей функции в этом файле нет.
 *
 * Отделить своё от чужого можно точно, и без разбора: `legacy` того же дерева
 * содержит шапку модуля со списком подключений. Значит,
 *
 *     своё(Ф) = функции(дерево(Ф)) МИНУС ⋃ функции(дерево(П)) по подключениям П
 *
 * — и это верно ровно потому, что дерево подключённого файла тоже связано:
 * оно уже содержит всё, что тот файл притащил за собой. Столкновение имён
 * здесь не мешает: связывание его само и отвергает.
 *
 * ── Цена ───────────────────────────────────────────────────────────────────
 *
 * Один вызов — один процесс. Запуск двоичного стоит 7 мс, разбор — от 5 мс на
 * коротком файле до 600 мс на `flang/stdlib/lists.flang` (1200 строк). Разбор и
 * СНЯТО 2026-08-31 строк flang/stdlib/lists.flang = 1200
 * есть цена, и она та же, что была у `parse`. Поэтому здесь ПАМЯТЬ на путь:
 * `flang/stdlib/lists.flang` подключают 30 файлов, и без памяти сторож имён
 * разбирал бы его тридцать раз.
 */
import { spawnSync } from "node:child_process"
import { cpus, freemem, tmpdir } from "node:os"
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

export const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), "../..")

/** Где двоичный. `FLANG_BINARY` — для прогона против другой сборки. */
export function путьДвоичного() {
  const назван = process.env.FLANG_BINARY
  if (назван) return назван
  const свой = join(КОРЕНЬ, "bootstrap/flang")
  if (existsSync(свой)) return свой
  throw new Error(
    `двоичного нет: ${свой}. Соберите — make -C bootstrap -j8 — или назовите свой в FLANG_BINARY.`,
  )
}

/** Позвать двоичный. Возвращает `{код, вывод, ошибки}` и НЕ бросает на коде ≠ 0. */
export function позвать(аргументы, настройки = {}) {
  const итог = spawnSync(путьДвоичного(), аргументы, {
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 512,
    cwd: настройки.каталог ?? КОРЕНЬ,
    input: настройки.вход,
    timeout: настройки.предел ?? 30 * 60 * 1000,
  })
  if (итог.error) throw итог.error
  return { код: итог.status ?? 1, вывод: итог.stdout ?? "", ошибки: итог.stderr ?? "" }
}

/**
 * СКОЛЬКО ПОТОКОВ ПУСКАТЬ В ВЕЕР — считается по ПАМЯТИ, а не по числу ядер.
 *
 * Было: `Math.max(1, Math.min(64, cpus().length))` — то есть на этой машине
 * ровно 64, потому что ядер 256. Веер из 64 вызовов `flang check --proof`
 * ценой 5–11 ГиБ каждый просит от 320 до 700 ГиБ. Оперативной памяти 499 ГиБ.
 *
 * Это не рассуждение, это разбор ночи 21 августа 2026: машина стояла 87 минут,
 * убийца памяти снял за ночь 24 процесса flang размером от 26,0 до 57,4 ГиБ,
 * и в каждой записи `constraint=CONSTRAINT_NONE` — кончалась вся память
 * машины. Ядер много, памяти на два порядка меньше, чем нужно такому вееру.
 *
 * Стало: потолок берётся с ТРЁХ сторон, и побеждает наименьшая.
 *   1. сколько ядер — как было;
 *   2. сколько прогонов по названной цене влезает в СВОБОДНУЮ память;
 *   3. общий потолок 64 — как было.
 *
 * Половина свободного, а не всё: машина общая, на ней работают под разными
 * учётными записями, и веер, съевший всё до последнего байта, кладёт чужое.
 *
 * ЦЕНА У КАЖДОГО ВЕЕРА СВОЯ, и это не мелочь: разница между ними — два порядка.
 * Одно общее число либо задушило бы дешёвые вееры, либо не удержало дорогой.
 * Замерено 21 августа на этом дереве, пик берётся у ядра (`memory.peak`
 * контрольной группы, `scripts/memory-limit.sh`), а не у `ps` — `ps` мигает
 * и на том же прогоне показывал 13,7 ГиБ вместо 28,7:
 *
 *   flang tokens <файл> --json                    0,1 ГиБ   1 с
 *   flang ast   <файл>                            0,5 ГиБ   4 с   (мелкий файл)
 *   flang ast   <файл>                           13,1 ГиБ         (крупный: замер
 *                                                                  `ps` по живым
 *                                                                  прогонам соседей)
 *   flang check <файл> --proof                   28,7 ГиБ  14 м 30 с
 *
 * Отсюда цены ниже. Перебить — `FLANG_CENA_PROGONA` (байты, общая на все
 * вееры), число потоков напрямую — `FLANG_POTOKOV`.
 */
const ГиБ = 1024 * 1024 * 1024
const ЦЕНА_НАЗВАНА = Number(process.env.FLANG_CENA_PROGONA) || 0
/** Разбор дерева: мелкий файл 0,5 ГиБ, крупный — до 13,1. Берём верх замера. */
const ЦЕНА_ДЕРЕВА = 14 * ГиБ
/** Ведомость доказательств: замерено 28,7 ГиБ. Округлено вверх. */
const ЦЕНА_ВЕДОМОСТИ = 30 * ГиБ
/** Поток токенов: связывания нет, замерено 0,1 ГиБ. С запасом. */
const ЦЕНА_ТОКЕНОВ = 1 * ГиБ

/**
 * Свободная память в байтах. Именно MemAvailable, а не `os.freemem()`:
 * `freemem()` отдаёт MemFree, а страничный кэш ядро вернёт по первому запросу,
 * и на машине с 45 ГиБ кэша MemFree занижает свободное в разы. Где /proc нет
 * (macOS, Windows) — остаётся `freemem()`.
 */
function свободнойПамяти() {
  try {
    const мета = readFileSync("/proc/meminfo", "utf8")
    const строка = /^MemAvailable:\s+(\d+) kB$/m.exec(мета)
    if (строка) return Number(строка[1]) * 1024
  } catch {
    /* не Linux либо /proc не смонтирован — падать здесь незачем */
  }
  return freemem()
}

export function потоковВеера(цена = ЦЕНА_ВЕДОМОСТИ, потолок = 64) {
  const названо = Number(process.env.FLANG_POTOKOV)
  if (Number.isFinite(названо) && названо >= 1) return Math.floor(названо)
  const поПамяти = Math.floor(свободнойПамяти() / 2 / (ЦЕНА_НАЗВАНА || цена))
  return Math.max(1, Math.min(потолок, cpus().length, поПамяти))
}

const памятьДеревьев = new Map()
const памятьВедомостей = new Map()

/**
 * ПРОГРЕВ: разобрать много файлов СРАЗУ, в несколько процессов.
 *
 * Один `flang ast` на `flang/self/emit-c.flang` идёт десятки секунд: файл
 * подключает половину компилятора, и связанное дерево выходит в тридцать тысяч
 * строк. Сторожу имён таких файлов 226, и по одному он шёл больше десяти минут
 * — то есть его перестали бы звать, а сторож, которого не зовут, ничем не
 * отличается от снятого.
 *
 * Параллельность взята НЕ обещаниями Node: `долгКорпуса` и `связывания` зовут
 * тесты обычным вызовом, и переписать их в `await` значило бы тронуть чужой
 * файл ради скорости. Поэтому прогрев синхронен снаружи и параллелен внутри:
 * `xargs -P` разводит вызовы по ядрам, ответы ложатся в отдельные файлы, и
 * дальше всё читается из памяти. Если `xargs` нет, прогрев молча ничего не
 * делает — дерево тогда возьмётся по одному, как и раньше.
 */
export function прогреть(пути, потоков = 0) {
  const нужны = [...new Set(пути.map((п) => resolve(КОРЕНЬ, п)))].filter((п) => !памятьДеревьев.has(п))
  if (нужны.length < 2) return
  const сколько = потоков || потоковВеера(ЦЕНА_ДЕРЕВА)
  const где = mkdtempSync(join(tmpdir(), "flang-progrev-"))
  try {
    const задания = нужны.map((путь, и) => `${путь}\0${join(где, `${и}.json`)}\0`).join("")
    const итог = spawnSync(
      "xargs",
      ["-0", "-n", "2", "-P", String(сколько), "sh", "-c", `exec ${JSON.stringify(путьДвоичного())} ast "$1" >"$2" 2>"$2.err"`, "sh"],
      { input: задания, encoding: "utf8", maxBuffer: 1024 * 1024 * 64 },
    )
    if (итог.error) return /* xargs нет — прогрева не будет, разбор пойдёт по одному */
    нужны.forEach((путь, и) => {
      const файл = join(где, `${и}.json`)
      let ответ
      try {
        ответ = { ok: true, дерево: JSON.parse(readFileSync(файл, "utf8")) }
      } catch {
        let почему = ""
        try {
          почему = `${readFileSync(`${файл}.err`, "utf8")}${readFileSync(файл, "utf8")}`.trim()
        } catch {
          почему = "двоичный не ответил"
        }
        ответ = { ok: false, why: почему }
      }
      памятьДеревьев.set(путь, ответ)
    })
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
}


/**
 * СВЯЗАННОЕ дерево файла — то же, что видит печать в целевой язык.
 * Отказывает только на разборе и на связывании: типов и завершаемости
 * `flang ast` не судит намеренно.
 */
export function дерево(путь) {
  const ключ = resolve(КОРЕНЬ, путь)
  if (памятьДеревьев.has(ключ)) return памятьДеревьев.get(ключ)
  const { код, вывод, ошибки } = позвать(["ast", ключ])
  let ответ
  if (код !== 0) {
    ответ = { ok: false, why: (ошибки || вывод).trim() }
  } else {
    try {
      ответ = { ok: true, дерево: JSON.parse(вывод) }
    } catch (беда) {
      ответ = { ok: false, why: `дерево не разобралось как JSON: ${беда.message}` }
    }
  }
  памятьДеревьев.set(ключ, ответ)
  return ответ
}

/** То же дерево для ИСХОДНИКА, которого нет на диске: через временный файл.
    Каталог заводится РЯДОМ с образцом, а не в `/tmp`: относительные пути в
    «использует … из "…"» считаются от места файла, и проба, унесённая в
    системный временный каталог, не связалась бы. */
export function деревоИсходника(исходник, рядомС) {
  const где = рядомС ? dirname(resolve(КОРЕНЬ, рядомС)) : КОРЕНЬ
  const каталог = mkdtempSync(join(где, ".flang-storozh-"))
  const файл = join(каталог, "проба.flang")
  try {
    writeFileSync(файл, исходник)
    const { код, вывод, ошибки } = позвать(["ast", файл])
    if (код !== 0) return { ok: false, why: (ошибки || вывод).trim() }
    return { ok: true, дерево: JSON.parse(вывод) }
  } catch (беда) {
    return { ok: false, why: беда.message }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Подключения файла — из шапки модуля, лежащей в `legacy` дерева. */
export function подключения(д) {
  const шапка = (д?.legacy ?? []).find((з) => з?.construct === "moduleHeader")
  return (шапка?.value?.imports ?? []).map((и) => и.from).filter((п) => typeof п === "string")
}

/**
 * ТОЛЬКО СВОИ объявления файла: связанное дерево минус всё, что приехало
 * подключениями. Возвращает `{ok, module, types, functions, legacy, why}`.
 */
export function своё(путь) {
  const полный = resolve(КОРЕНЬ, путь)
  const д = дерево(полный)
  if (!д.ok) return { ok: false, why: д.why }
  return { ok: true, ...отсеятьЧужое(д.дерево, полный) }
}

/** Та же вычиталка для дерева, уже взятого на руки (например, у куска файла). */
export function отсеятьЧужое(д, откуда) {
  const чужиеФункции = new Set()
  const чужиеТипы = new Set()
  for (const путь of подключения(д)) {
    const сосед = resolve(dirname(resolve(КОРЕНЬ, откуда)), путь)
    const их = дерево(сосед)
    if (!их.ok) continue
    for (const ф of их.дерево.functions ?? []) чужиеФункции.add(ф.name)
    for (const т of их.дерево.types ?? []) чужиеТипы.add(т.name)
  }
  return {
    module: д.module,
    types: (д.types ?? []).filter((т) => !чужиеТипы.has(т.name)),
    functions: (д.functions ?? []).filter((ф) => !чужиеФункции.has(ф.name)),
    legacy: д.legacy ?? [],
    measures: д.measures ?? [],
  }
}

/**
 * ПРОГРЕВ ВЕДОМОСТЕЙ — тем же приёмом и по той же причине, что прогрев деревьев.
 *
 * `flang check --proof` считает типы, завершаемость и ядро доказательства; на
 * корпусе из 277 файлов по одному это часы. Разводится по ядрам тем же
 * `xargs -P`. Код возврата у `check` значащий (1 — программа не прошла, 2 —
 * названный пробел), поэтому он сохраняется рядом с выводом и читается отсюда.
 */
export function прогретьВедомости(пути, потоков = 0) {
  const нужны = [...new Set(пути.map((п) => resolve(КОРЕНЬ, п)))].filter((п) => !памятьВедомостей.has(п))
  if (нужны.length < 2) return
  const сколько = потоков || потоковВеера(ЦЕНА_ВЕДОМОСТИ)
  const где = mkdtempSync(join(tmpdir(), "flang-vedomosti-"))
  try {
    const задания = нужны.map((путь, и) => `${путь}\0${join(где, `${и}`)}\0`).join("")
    const итог = spawnSync(
      "xargs",
      ["-0", "-n", "2", "-P", String(сколько), "sh", "-c",
        `${JSON.stringify(путьДвоичного())} check "$1" --proof --json >"$2.json" 2>"$2.err"; echo $? >"$2.kod"`, "sh"],
      { input: задания, encoding: "utf8", maxBuffer: 1024 * 1024 * 64 },
    )
    if (итог.error) return
    нужны.forEach((путь, и) => {
      const имя = join(где, `${и}`)
      let код = 1
      try {
        код = Number.parseInt(readFileSync(`${имя}.kod`, "utf8").trim(), 10)
      } catch {
        return /* xargs до этого файла не дошёл — возьмётся по одному */
      }
      let ответ
      try {
        ответ = { ok: код === 0, код, ведомость: JSON.parse(readFileSync(`${имя}.json`, "utf8")), why: код === 0 ? null : readFileSync(`${имя}.err`, "utf8").trim() }
      } catch {
        let почему = ""
        try {
          почему = `${readFileSync(`${имя}.err`, "utf8")}${readFileSync(`${имя}.json`, "utf8")}`.trim()
        } catch {
          почему = "двоичный не ответил"
        }
        ответ = { ok: false, код, why: почему }
      }
      памятьВедомостей.set(путь, ответ)
    })
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
}

/** Ведомость доказательств: `flang check --proof --json`. */
export function ведомость(путь) {
  const ключ = resolve(КОРЕНЬ, путь)
  if (памятьВедомостей.has(ключ)) return памятьВедомостей.get(ключ)
  const { код, вывод, ошибки } = позвать(["check", ключ, "--proof", "--json"])
  let ответ
  try {
    ответ = { ok: код === 0, код, ведомость: JSON.parse(вывод), why: код === 0 ? null : (ошибки || "").trim() }
  } catch {
    ответ = { ok: false, код, why: (ошибки || вывод).trim() }
  }
  памятьВедомостей.set(ключ, ответ)
  return ответ
}

/** Ведомость для ИСХОДНИКА, которого нет на диске: через временный файл рядом. */
export function ведомостьИсходника(текст, рядомС) {
  const где = рядомС ? dirname(resolve(КОРЕНЬ, рядомС)) : КОРЕНЬ
  const каталог = mkdtempSync(join(где, ".flang-storozh-"))
  const файл = join(каталог, "проба.flang")
  try {
    writeFileSync(файл, текст)
    const { код, вывод, ошибки } = позвать(["check", файл, "--proof", "--json"])
    try {
      return { ok: код === 0, код, ведомость: JSON.parse(вывод) }
    } catch {
      return { ok: false, код, why: (ошибки || вывод).trim() }
    }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Проверка без ведомости: `flang check`. Замечания приходят текстом. */
export function проверка(путь) {
  const { код, вывод, ошибки } = позвать(["check", resolve(КОРЕНЬ, путь)])
  return { ok: код === 0, код, текст: `${вывод}${ошибки}`.trim() }
}

/**
 * Та же проверка для ИСХОДНИКА, которого нет на диске.
 *
 * Коды замечаний вынимаются из текста, а не из JSON, и намеренно: ведомость
 * (`--proof --json`) у программы с замечаниями НЕ ПЕЧАТАЕТСЯ вовсе — а спросить
 * надо как раз про программу, которая обязана быть отвергнута. Текст отказа
 * начинается кодом, и это часть договора всех команд.
 */
export function проверкаИсходника(текст, рядомС) {
  const где = рядомС ? dirname(resolve(КОРЕНЬ, рядомС)) : КОРЕНЬ
  const каталог = mkdtempSync(join(где, ".flang-storozh-"))
  const файл = join(каталог, "проба.flang")
  try {
    writeFileSync(файл, текст)
    const { код, вывод, ошибки } = позвать(["check", файл])
    const ответ = `${вывод}${ошибки}`
    return { ok: код === 0, код, текст: ответ.trim(), коды: [...new Set(ответ.match(/FLANG_[A-Z_]+/gu) ?? [])] }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Прогон примеров корпуса: `flang test <маска> --json`. */
export function прогон(маска, ключи = []) {
  const { код, вывод, ошибки } = позвать(["test", маска, "--json", ...ключи])
  try {
    return { код, итог: JSON.parse(вывод) }
  } catch {
    return { код, why: (ошибки || вывод).trim() }
  }
}

/** Исходник файла — рядом, чтобы сторожу не заводить свой `readFileSync`. */
export function исходник(путь) {
  return readFileSync(resolve(КОРЕНЬ, путь), "utf8")
}

/**
 * ПОТОК ТОКЕНОВ — `flang tokens <файл> --json`.
 *
 * Вопрос, ради которого это здесь: чем СТАЛО слово, когда его прочитал язык.
 * Грепом он не решается, и это замерено при заведении `убывает` — текста
 * «убывает» в дереве было 58 вхождений, а голым именем ни одного: слово в
 * комментарии, слово внутри литерала и имя в ёлочках ключевым не становятся
 * никогда. Отвечает на него только лексер, и лексер здесь один — тот, что
 * внутри двоичного.
 *
 * Дерево (`flang ast`) на этот вопрос не годится вдвойне: оно СВЯЗЫВАЕТ (то
 * есть тащит соседние файлы) и стоит вчетверо дороже — 34 секунды против 9 на
 * `flang/self/parser.flang`. Токенам связывание не нужно вовсе: поток токенов
 * файла от его подключений не зависит.
 *
 * Ключи те же, что были у `tokenize` образца: `kind`, `value`, `quoted`,
 * `text`, `span` со строкой и столбцом.
 */
export function токены(путь) {
  const { код, вывод, ошибки } = позвать(["tokens", resolve(КОРЕНЬ, путь), "--json"])
  return прочитатьТокены(вывод, ошибки, код)
}

function прочитатьТокены(вывод, ошибки, код) {
  let разобрано
  try {
    разобрано = JSON.parse(вывод)
  } catch {
    return { ok: false, поток: [], беды: [], why: (ошибки || вывод).trim() || "двоичный не ответил" }
  }
  const беды = разобрано.diagnostics ?? []
  return {
    ok: беды.length === 0 && код === 0,
    поток: разобрано.tokens ?? [],
    беды,
    why: беды.length > 0 ? беды.map((б) => б.message).join("; ") : (код === 0 ? null : (ошибки || "").trim()),
  }
}

/**
 * ТОКЕНЫ МНОГИХ ФАЙЛОВ СРАЗУ — по ядрам, тем же `xargs -P`, что у прогрева
 * деревьев. Возвращает Map: путь (как его дали) → ответ.
 *
 * Памяти здесь НЕ ВЫДЕЛЯЕТСЯ впрок, и это отличие от `прогреть` намеренное.
 * Поток токенов `flang/self/parser.flang` — шесть мегабайт JSON; удержать
 * восемьсот файлов корпуса разом значило бы держать в памяти гигабайты ради
 * счёта, которому каждый файл нужен ровно один раз. Поэтому ответы не оседают
 * в памяти модуля: зовущий берёт пачку, считает по ней и отпускает.
 *
 * Замер на этом дереве: 845 файлов, 32 потока — 10 секунд. По одному вызову на
 * файл было бы около семи минут.
 */
export function токеныМногих(пути, потоков = 0) {
  const итог = new Map()
  const нужны = [...new Set(пути)]
  if (нужны.length === 0) return итог
  if (нужны.length === 1) {
    итог.set(нужны[0], токены(нужны[0]))
    return итог
  }
  const сколько = потоков || потоковВеера(ЦЕНА_ТОКЕНОВ)
  const где = mkdtempSync(join(tmpdir(), "flang-tokeny-"))
  try {
    const задания = нужны.map((путь, и) => `${resolve(КОРЕНЬ, путь)}\0${join(где, `${и}`)}\0`).join("")
    const прогон = spawnSync(
      "xargs",
      ["-0", "-n", "2", "-P", String(сколько), "sh", "-c",
        `${JSON.stringify(путьДвоичного())} tokens "$1" --json >"$2.json" 2>"$2.err"; echo $? >"$2.kod"`, "sh"],
      { input: задания, encoding: "utf8", maxBuffer: 1024 * 1024 * 64 },
    )
    if (прогон.error) {
      /* `xargs` нет — берём по одному, как и раньше. */
      for (const путь of нужны) итог.set(путь, токены(путь))
      return итог
    }
    нужны.forEach((путь, и) => {
      const имя = join(где, `${и}`)
      let код = 1
      try {
        код = Number.parseInt(readFileSync(`${имя}.kod`, "utf8").trim(), 10)
      } catch {
        итог.set(путь, токены(путь)) /* xargs до этого файла не дошёл */
        return
      }
      let вывод = ""
      let ошибки = ""
      try {
        вывод = readFileSync(`${имя}.json`, "utf8")
        ошибки = readFileSync(`${имя}.err`, "utf8")
      } catch {
        ошибки = "двоичный не ответил"
      }
      итог.set(путь, прочитатьТокены(вывод, ошибки, код))
    })
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
  return итог
}

const памятьСлов = new Map()

/**
 * КЛЮЧЕВОЕ ЛИ ЭТО СЛОВО — `flang tokens --keyword «фраза»`.
 *
 * Возвращает имя конструкции языка или `null`. Спрашивается ПРОГОНОМ лексера, а
 * не заглядыванием в таблицу: таблица — ещё одно место, которое может
 * разъехаться с языком, а поток токенов разъехаться с ним не может.
 *
 * Фраза из нескольких слов проверяется как фраза, и требуется РОВНО ОДИН
 * значащий токен. `код символа` — одно слово из двух частей, лексер отдаёт его
 * одним токеном, и форма такая есть. `элемент или беда` — три ключевых слова
 * подряд, каждое настоящее, а формы такой нет вовсе.
 */
export function ключевоеСлово(фраза) {
  const ключ = String(фраза).trim()
  if (памятьСлов.has(ключ)) return памятьСлов.get(ключ)
  const { код, вывод, ошибки } = позвать(["tokens", "--keyword", ключ, "--json"])
  // НЕ СПРОСИЛИ — ЭТО НЕ «СЛОВА НЕТ». Лексер отвечает кодом 0 и на настоящее
  // слово, и на выдуманное: разница в поле `keyword`, а не в коде возврата
  // (замер: «если» → 0 и "if"; «абракадабра» → 0 и null). Значит код ≠ 0 или
  // неразобранный ответ означает ровно одно — СПРОСИТЬ НЕ УДАЛОСЬ, и молчать
  // об этом нельзя. Прежде здесь стоял `ответ = null`, и это делало сторожа
  // утверждений зелёным при мёртвом двоичном: каждое «в языке нет такой формы»
  // подтверждалось тем, что лексер не ответил. Замер 29 августа 2026:
  // FLANG_BINARY=/bin/false → «чисто — ни одна проза не отрицает формы»,
  // код 0, при живом двоичном — код 1 и два протухших утверждения.
  if (код !== 0) {
    throw new Error(
      `лексер не ответил про «${ключ}»: код ${код}. ` +
        `Это не «слова нет в языке» — это невозможность спросить. ` +
        (ошибки.trim() ? `Сказано: ${ошибки.trim().split("\n")[0]}` : "Ответа нет вовсе."),
    )
  }
  let ответ = null
  try {
    ответ = JSON.parse(вывод).keyword ?? null
  } catch {
    throw new Error(
      `лексер ответил про «${ключ}» неразборчиво: ${вывод.slice(0, 200)}. ` +
        `Это не «слова нет в языке» — это невозможность спросить.`,
    )
  }
  памятьСлов.set(ключ, ответ)
  return ответ
}

/* ── ПРОГОНЩИК: любая функция замыкания компилятора по имени ──────────────────
 *
 * У двоичного есть второй вход, кроме команд: без доводов и без терминала на
 * входе он читает JSON со стандартного ввода — запрос на строку, ответ на
 * строку. Через него открыто ВСЁ замыкание компилятора: лексер, разбор, слой
 * типов, ядро доказательства и все восемь генераторов.
 *
 *   printf '{"fn":"Идентификатор фразы","args":[{"s":"если"}]}' | bootstrap/flang
 *   {"ok":true,"value":{"s":"if"}}
 *
 * Это важнее, чем кажется: новую команду заводить надо только тогда, когда у
 * ответа есть СВОЙ вид вывода (как у `flang tokens --json`). Всё остальное —
 * таблица слов языка, порядок поверхностей, «на какой поверхности это слово» —
 * достаётся отсюда и без единой правки двоичного.
 *
 * Значения размечены тегами, потому что JSON беднее flang: `{"s":…}` строка,
 * `{"n":"…"}` число строкой (иначе потерялись бы NaN, Infinity и −0),
 * `{"l":[…]}` список, `{"r":[["поле",…]]}` запись, `{"v":"Имя","f":[…]}`
 * вариант. Метки снимаются здесь, чтобы зовущий работал с обычными значениями.
 */

/** Снять метки прогонщика: размеченное значение → обычное значение JavaScript. */
export function снятьМетки(значение) {
  if (значение === null || typeof значение !== "object") return значение
  if (Array.isArray(значение)) return значение.map(снятьМетки)
  if ("s" in значение) return значение.s
  if ("n" in значение) return Number(значение.n)
  if ("l" in значение) return значение.l.map(снятьМетки)
  if ("r" in значение) return Object.fromEntries(значение.r.map(([ключ, з]) => [ключ, снятьМетки(з)]))
  if ("v" in значение) {
    return { вариант: значение.v, ...Object.fromEntries((значение.f ?? []).map(([ключ, з]) => [ключ, снятьМетки(з)])) }
  }
  return значение
}

/**
 * Позвать функции замыкания ПАЧКОЙ — один процесс на всю пачку.
 *
 * Замер на этом дереве: одиночный вызов 7,6 мс (из них запуск процесса — почти
 * всё), пачка из 500 вызовов «Коды разбора» одним процессом — 1,0 с, то есть
 * 2 мс на вызов. Сборке сайта это разница между секундами и минутой.
 *
 * @param {Array<{fn: string, args: object[]}>} запросы
 * @returns {Array<{ok: boolean, значение?: any, код?: string, сообщение?: string}>}
 */
export function позватьФункции(запросы) {
  if (запросы.length === 0) return []
  const строка = запросы.map((з) => JSON.stringify({ fn: з.fn, args: з.args ?? [] })).join("\n")
  const { вывод, ошибки } = позвать([], { вход: `${строка}\n` })
  const строки = вывод.split("\n").filter((с) => с.trim() !== "")
  return запросы.map((_, и) => {
    const ответ = строки[и]
    if (ответ === undefined) return { ok: false, код: "FLANG_CLI", сообщение: (ошибки || "прогонщик не ответил").trim() }
    let разобрано
    try {
      разобрано = JSON.parse(ответ)
    } catch {
      return { ok: false, код: "FLANG_CLI", сообщение: `ответ прогонщика не разобрался: ${ответ.slice(0, 200)}` }
    }
    if (разобрано.ok !== true) return { ok: false, код: разобрано.code ?? "FLANG_CLI", сообщение: разобрано.message ?? "" }
    return { ok: true, значение: снятьМетки(разобрано.value) }
  })
}

/** Одна функция замыкания. Бросает, если прогонщик отказал: звать нечего дальше. */
export function позватьФункцию(имя, доводы = []) {
  const [ответ] = позватьФункции([{ fn: имя, args: доводы }])
  if (!ответ.ok) throw new Error(`${имя}: ${ответ.код} ${ответ.сообщение}`)
  return ответ.значение
}

/* ОТКАЗ ПРОГОНЩИКА И ОТСУТСТВИЕ ДВОИЧНОГО — РАЗНЫЕ СОБЫТИЯ, и путать их нельзя.
 *
 * Прогонщик отвечает `{"ok":false,"code":…}`, когда сама программа отказалась
 * считать: текст `1e999` роняет встроенную «к числу» прямо в лексере, и это
 * ОТВЕТ ПРО ТЕКСТ — «целой программой он не является». Двоичного нет вовсе —
 * это отсутствие ответа, и оно бросается наружу: зовущий обязан узнать, что
 * спрашивать было не у кого, а не принять молчание за «нет».
 */

/**
 * Поток токенов ИСХОДНИКА, которого нет на диске (кусок страницы, кусок ввода).
 *
 * Тем же лексером и с теми же ключами, что у `flang tokens <файл> --json`, —
 * только через прогонщик, потому что файла здесь нет вовсе.
 *
 * `поток` равен `null`, если лексер отказался читать этот текст.
 */
export function токеныИсходника(текст) {
  const [ответ] = позватьФункции([{ fn: "Печать токенов исходника", args: [{ s: текст }, { s: "" }] }])
  if (!ответ.ok) return { поток: null, беды: [{ code: ответ.код, message: ответ.сообщение }] }
  const разобрано = JSON.parse(ответ.значение)
  return { поток: разобрано.tokens ?? [], беды: разобрано.diagnostics ?? [] }
}

/**
 * Коды бед разбора ИСХОДНИКА: пустой список значит «разобралось и связалось».
 *
 * Это ответ на вопрос «целая ли это программа», и отвечает на него настоящий
 * разбор языка, а не догадка по виду текста. Вывод команды («функций 99») лексер
 * читает без единой жалобы, а разбор его отвергает — потому подсветка сайта
 * спрашивает именно разбор.
 */
export function кодыРазбора(текст) {
  const [ответ] = позватьФункции([{ fn: "Коды разбора", args: [{ s: текст }] }])
  return ответ.ok ? ответ.значение : [ответ.код ?? "FLANG_CLI"]
}

/**
 * Дерево разбора ИСХОДНИКА — то же, что даёт `flang ast`, но БЕЗ связывания и
 * без файла на диске.
 *
 * Связывания здесь нет намеренно: спрашивают об этом дереве там, где сверяют
 * запись одной и той же программы на разных поверхностях языка, а подключений
 * у таких программ нет вовсе.
 */
export function деревоРазбора(текст) {
  return JSON.parse(позватьФункцию("Печать разбора исходника", [{ s: текст }]))
}

/* ── ТАБЛИЦА СЛОВ ЯЗЫКА ───────────────────────────────────────────────────────
 *
 * Понятие языка (`if`, `total`, `charCode`) записывается на четырёх
 * поверхностях: русской, английской, эсперантской и китайской. Спрашивают про
 * это словарь сайта, прогон поверхностей и дополнение редактора.
 *
 * Отдельной команды у двоичного под это нет и не нужно: таблица достаётся
 * прогонщиком, как и всё остальное замыкание. Здесь она собирается в вид,
 * удобный зовущему, и собирается ОДИН раз за прогон.
 *
 * ЧТО РАЗБИРАЕТСЯ ЗДЕСЬ, А ЧТО СПРАШИВАЕТСЯ У ЯЗЫКА. Разбирается ровно одно —
 * запись самой таблицы (`|фраза:идентификатор|`), и это не второе описание
 * языка, а чтение его собственных данных в его же записи, того рода что
 * `JSON.parse` над выводом `flang ast`. Всё, что является ОТВЕТОМ НА ВОПРОС
 * («какое слово у этого понятия по-китайски», «на какой поверхности стоит эта
 * фраза»), спрашивается у языка прогоном: ответ зависит от правил, а правила
 * живут там.
 */

let памятьТаблицы = null

/**
 * Таблица слов языка.
 *
 * @returns {{
 *   поверхности: string[],
 *   понятия: string[],
 *   фразы: Record<string, string[]>,
 *   наПоверхности: (понятие: string, поверхность: string) => string|null,
 *   поверхностьФразы: (фраза: string) => string|null,
 * }}
 */
export function таблицаСлов() {
  if (памятьТаблицы !== null) return памятьТаблицы

  const поверхности = позватьФункцию("Все поверхности")
  const куски = позватьФункцию("Куски таблицы")

  /* Порядок — порядок таблицы, и он значащий: первая победившая фраза остаётся
     за своим понятием, а перечисляющие таблицу (словарь сайта, дополнение
     редактора) печатают её этим порядком. */
  const фразы = {}
  for (const кусок of куски) {
    for (const пара of кусок.split("|")) {
      if (пара === "") continue
      const двоеточие = пара.lastIndexOf(":")
      if (двоеточие <= 0) continue
      const фраза = пара.slice(0, двоеточие)
      const понятие = пара.slice(двоеточие + 1)
      ;(фразы[понятие] ??= []).push(фраза)
    }
  }
  const понятия = Object.keys(фразы)

  /* Слова по поверхностям — ПАЧКОЙ и одним процессом: понятий полторы сотни,
     поверхностей четыре, и по одному вызову это были бы минуты. */
  const запросы = []
  for (const понятие of понятия) {
    for (const поверхность of поверхности) {
      запросы.push({ fn: "Слово на поверхности", args: [{ s: понятие }, { s: поверхность }] })
    }
  }
  const ответы = позватьФункции(запросы)
  const слова = new Map()
  запросы.forEach((з, и) => {
    const ответ = ответы[и]
    /* Пусто у языка значит «эта поверхность про это понятие молчит»; здесь это
       `null`, чтобы отличалось от найденной пустой строки. */
    слова.set(`${з.args[0].s} ${з.args[1].s}`, ответ.ok && ответ.значение !== "" ? ответ.значение : null)
  })

  const памятьПоверхностей = new Map()
  памятьТаблицы = {
    поверхности,
    понятия,
    фразы,
    наПоверхности: (понятие, поверхность) => слова.get(`${понятие} ${поверхность}`) ?? null,
    поверхностьФразы: (фраза) => {
      if (!памятьПоверхностей.has(фраза)) {
        const ответ = позватьФункцию("Поверхность фразы", [{ s: фраза }])
        памятьПоверхностей.set(фраза, ответ === "" ? null : ответ)
      }
      return памятьПоверхностей.get(фраза)
    },
  }
  return памятьТаблицы
}

