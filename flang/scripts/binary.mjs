/**
 * Спросить пачку разом: [{имя, аргументы}] → список значений в том же порядке.
 * Уже спрошенное второй раз не спрашивается.
 */
export function спроситьПачкой(вопросы) {
  const новые = []
  for (const { имя, аргументы = [] } of вопросы) {
    const ключ = ключВопроса(имя, аргументы)
    if (памятьОтветов.has(ключ)) continue
    if (новые.some((в) => ключВопроса(в.имя, в.аргументы) === ключ)) continue
    новые.push({ имя, аргументы })
  }
  if (новые.length > 0) {
    const строки = новые.map(({ имя, аргументы }) =>
      JSON.stringify({ fn: имя, args: аргументы.map((а) => вЗначение(а)) }))
    const { вывод, ошибки } = позвать([], { вход: `${строки.join("\n")}\n` })
    const ответы = вывод.split("\n").filter((с) => с.trim().length > 0)
    if (ответы.length !== новые.length) {
      throw new Error(
        `двоичный ответил ${ответы.length} раз на ${новые.length} вопросов: ${(ошибки || вывод).slice(0, 300)}`,
      )
    }
    новые.forEach(({ имя, аргументы }, и) => {
      let разобрано
      try {
        разобрано = JSON.parse(ответы[и])
      } catch {
        throw new Error(`ответ двоичного на «${имя}» не разобрался: ${ответы[и].slice(0, 200)}`)
      }
      if (разобрано.ok !== true) {
        throw new Error(`двоичный отказал на «${имя}»: ${разобрано.code ?? ""} ${разобрано.message ?? ""}`)
      }
      памятьОтветов.set(ключВопроса(имя, аргументы), изЗначения(разобрано.value))
    })
  }
  return вопросы.map(({ имя, аргументы = [] }) => памятьОтветов.get(ключВопроса(имя, аргументы)))
}

