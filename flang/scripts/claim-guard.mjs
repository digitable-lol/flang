/**
 * Сторож утверждений о недостаче — для КОММЕНТАРИЕВ и ПРОЗЫ.
 *
 * ── Чего не хватало ─────────────────────────────────────────────────────────
 *
 * `flang/test/missing.test.mjs` стережёт каталог недостач программами-уликами,
 * `flang/test/claims.test.mjs` — девять поимённо выбранных фраз. Обоим нужен
 * человек: кто-то должен ЗАМЕТИТЬ утверждение и завести на него запись. Пока он
 * не заметил, комментарий «такой формы в языке нет» не проверяется ничем, потому
 * что комментарии не исполняются. Это и есть DGT-FLANG-19.
 *
 * ── Почему не «улика на каждое утверждение» ─────────────────────────────────
 *
 * Замерено на этом дереве 9 августа 2026: оборотов «нельзя / невозможно / не
 * помогает / в языке нет / нечем» — 904 в 219 файлах. Требовать программу к
 * каждому — это шум, который перестанут читать через неделю, и он же запретит
 * объяснять устройство языка обычными словами. (Заодно: в шапке claims.test.mjs
 * стоит число 211; посчитано оно было по трём словам и четырём каталогам, и как
 * оценка всей поверхности неверно — здесь считаны все обороты по всему дереву.)
 *
 * ── Что вместо ──────────────────────────────────────────────────────────────
 *
 * Из 904 выделяется подкласс, у которого улику писать НЕ НАДО, потому что она
 * уже написана и называется лексером: утверждение вида «формы «X» в языке нет»,
 * где `X` назван кавычками — той самой записью, которой в этом дереве называют
 * кусок языка. Такое утверждение решается ПРОГОНОМ: спросить у настоящего
 * лексера языка, что такое `X`. Вышло ключевое слово — значит форма есть, и
 * утверждение неправда.
 *
 * Спрашивается лексер у ДВОИЧНОГО — `flang tokens --keyword «X»`. Своего
 * разбора `.flang` здесь нет и заводить его нельзя: второй разбор разъехался бы
 * с настоящим на первой же правке языка, и разъехался бы молча — то есть ровно
 * той бедой, ради которой этот сторож и написан.
 *
 * Замер того же дня: таких фраз 48, различных мест — 13, и СЕМЬ из них были
 * ложью, причём шесть про одно и то же. Форма `код символа` появилась 9 августа
 * 2026; три места это записали (`src/builtins.mjs`, `stdlib/sets.flang`,
 * `self/SPEC.md`), а шесть других продолжали утверждать, что её нет. Ровно тот
 * случай, ради которого задача и заведена: правку внесли, а обещания читателю,
 * розданные в шести местах, протухли молча.
 *
 * ── Три вывода, и они разные ────────────────────────────────────────────────
 *
 *   • ФОРМА ЕСТЬ, а фраза говорит, что её нет → отказ. Правьте прозу, не сторожа:
 *     лексер здесь не мнение, а исполняемая часть языка.
 *   • ФОРМЫ НЕТ (лексер отдал имя, а не ключевое слово) → сторож молчит. Улику
 *     на такое утверждение он потребовать не может и не требует: слово, которого
 *     в языке нет, ничем, кроме программы, не проверяется, а программу пишет
 *     человек — в `claims.test.mjs`.
 *   • Фраза НЕ УТВЕРЖДАЕТ, а вспоминает снятое утверждение → сторож молчит.
 *
 * ── Про третий случай, он же единственная новая условность ──────────────────
 *
 * Запись «здесь стояло, что …, и это больше не правда» — не утверждение, а его
 * НАДГРОБИЕ, и она обязана быть разрешена: без неё сторож заставил бы стирать
 * историю правок, то есть ровно ту память, которой этот проект и держится.
 * Слова для надгробия не выдуманы здесь — они уже в ходу: «Здесь стояло»,
 * «БОЛЬШЕ НЕ ПРАВДА», «перестало быть правдой», «это неправда», «УБРАНА». Их
 * 25 в дереве, и сторож просто научен их читать.
 *
 * ── Чего сторож НЕ делает ───────────────────────────────────────────────────
 *
 * Он не отличает смысл слова от его написания. `и` — ключевое слово, но
 * логической конъюнкцией голое `и` не является (ею стало составное `и притом`),
 * и утверждение «инфиксного `и` в языке нет» верно, хотя лексер слово знает.
 * Такие места перечислены в `УЗКИЕ` поимённо, с доводом и с прогоном при
 * каждом — то есть по правилу claims.test.mjs, а не в обход него. Список
 * закрытый: он не пополняется молча, потому что каждая запись обязана назвать,
 * какая ИМЕННО узкая правда имеется в виду, и чем она проверена.
 *
 * Запуск: `node flang/scripts/claim-guard.mjs` (или `./ярлык утверждения:проверка`).
 * Проверяется он же тестом `flang/test/claim-guard.test.mjs`, включая
 * самопроверку на подложенных случаях: сторож, который не ловит, — это сторож,
 * выглядящий ровно как сторож, у которого всё хорошо.
 */
