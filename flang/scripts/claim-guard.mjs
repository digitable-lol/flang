/**
 * Комментарии JavaScript — с оглядкой на строковые литералы.
 *
 * Наивный поиск `/*` находит его и внутри строки, а строка с таким содержимым в
 * этом дереве есть: тесты самого сторожа подкладывают ему комментарии текстом.
 * Сторож, краснеющий на СВОИХ ЖЕ приманках, — не строгость, а поломка, поэтому
 * литералы здесь пропускаются целиком: `"…"`, `'…'` и `` `…` ``.
 *
 * Разбором JavaScript это не является и быть не пытается: подстановка `${…}`
 * внутри шаблонной строки считается частью строки. Для поиска комментариев
 * этого достаточно, а больше отсюда ничего и не требуется.
 */
export function комментарииJS(текст) {
  const из = []
  let строка = 1
  let i = 0
  const н = текст.length
  while (i < н) {
    const с = текст[i]
    if (с === "\n") {
      строка++
      i++
      continue
    }
    /* Строковый литерал — пропускаем целиком вместе с экранированием. */
    if (с === '"' || с === "'" || с === "`") {
      const кавычка = с
      i++
      while (i < н) {
        if (текст[i] === "\\") {
          i += 2
          continue
        }
        if (текст[i] === "\n") строка++
        if (текст[i] === кавычка) {
          i++
          break
        }
        i++
      }
      continue
    }
    if (с === "/" && текст[i + 1] === "*") {
      const начало = строка
      const конец = текст.indexOf("*/", i + 2)
      const тело = текст.slice(i + 2, конец < 0 ? н : конец)
      тело.split("\n").forEach((т, k) => {
        const очищено = т.replace(/^\s*\*? ?/u, "").trim()
        if (очищено) из.push({ строка: начало + k, текст: очищено })
      })
      строка += (тело.match(/\n/gu) ?? []).length
      i = конец < 0 ? н : конец + 2
      continue
    }
    if (с === "/" && текст[i + 1] === "/") {
      let конец = текст.indexOf("\n", i)
      if (конец < 0) конец = н
      const тело = текст.slice(i + 2, конец).trim()
      if (тело) из.push({ строка, текст: тело })
      i = конец
      continue
    }
    i++
  }
  return из
}

/** Обход дерева. */
function файлыДерева(каталог, собранное = []) {
  for (const имя of readdirSync(каталог)) {
    if (ПРОПУСК.has(имя)) continue
    if (ПЕЧАТАЕТСЯ_ИЗ_ИСТОРИИ.has(имя)) continue
    const путь = join(каталог, имя)
    if (statSync(путь).isDirectory()) файлыДерева(путь, собранное)
    else if (РАСШИРЕНИЯ.has(extname(путь))) собранное.push(путь)
  }
  return собранное
}

/**
 * Куски прозы файла: для кода — только комментарии, для `.md` — весь текст.
 *
 * Соседние строки комментария склеиваются в один кусок, иначе утверждение,
 * перенесённое на вторую строку, не прочитается целиком — а переносят их
 * постоянно.
 */
export function кускиПрозы(путь, текст) {
  const ext = extname(путь)
  const строки = текст.split("\n")
  const сырые = []

  if (ext === ".md") {
    строки.forEach((с, i) => сырые.push({ строка: i + 1, текст: с }))
  } else if (ext === ".flang" || ext === ".fts") {
    строки.forEach((с, i) => {
      const м = с.match(/^\s*\/\/ ?(.*)$/)
      if (м) сырые.push({ строка: i + 1, текст: м[1] })
    })
  } else if (ext === ".json") {
    строки.forEach((с, i) => {
      if (/"(причина|чего|почему|приём|замысел)"\s*:/u.test(с)) сырые.push({ строка: i + 1, текст: с })
    })
  } else {
    for (const с of комментарииJS(текст)) сырые.push(с)
  }

  /* Склейка соседних строк в кусок: разрыв — пустая строка или пропуск номера. */
  const куски = []
  for (const с of сырые) {
    const последний = куски.at(-1)
    if (последний && с.строка === последний.конец + 1 && с.текст.trim() !== "") {
      последний.текст += " " + с.текст.trim()
      последний.конец = с.строка
    } else if (с.текст.trim() !== "") {
      куски.push({ строка: с.строка, конец: с.строка, текст: с.текст.trim() })
    }
  }
  return куски
}

/** Дробление куска на фразы: утверждение живёт во фразе, а не в абзаце. */
function фразы(кусок) {
  return кусок.текст
    .split(/(?<=[.;!?])\s+/u)
    .map((т) => т.trim())
    .filter(Boolean)
    .map((т) => ({ строка: кусок.строка, текст: т }))
}

/** Названные кавычками куски языка. */
function названныеФормы(фраза) {
  return [...фраза.matchAll(/[«`]([^»`\n]{1,40})[»`]/gu)].map((м) => м[1].trim()).filter(Boolean)
}

/**
 * Лежит ли отрезок [от; до) целиком внутри пары «…».
 *
 * Нужно ровно для надгробий: `src/builtins.mjs` пишет «Здесь стояло, что …,
 * «потому что формы «код символа» в языке нет вовсе». Форма появилась». Внешние
 * кавычки означают, что фраза ПЕРЕСКАЗЫВАЕТ утверждение, а не делает его, и
 * краснеть на пересказе — это заставлять стирать историю правок.
 */
function вЦитате(текст, от, до) {
  let глубина = 0
  for (let i = 0; i < текст.length; i++) {
    if (i === от) {
      if (глубина > 0) {
        /* Открыта кавычка — проверим, что она закрывается ПОСЛЕ конца отрезка. */
        let г = глубина
        for (let j = i; j < текст.length; j++) {
          if (текст[j] === "«") г++
          else if (текст[j] === "»") {
            г--
            if (г === 0) return j >= до
          }
        }
        return false
      }
      return false
    }
    if (текст[i] === "«") глубина++
    else if (текст[i] === "»") глубина = Math.max(0, глубина - 1)
  }
  return false
}

/**
 * Знает ли форму НАСТОЯЩИЙ лексер языка.
 *
 * Спрашивается прогоном двоичного, а не таблицей: таблица — это ещё одно место,
 * которое может разъехаться с языком, а поток токенов разъехаться с ним не
 * может.
 *
 * Требуется РОВНО ОДНО ключевое слово, и это не придирка. `код символа` —
 * одно слово из двух частей, лексер отдаёт его одним токеном, и форма такая
 * есть. `элемент или беда` — три ключевых слова подряд, каждое настоящее, а
 * формы такой нет вовсе. Считать вторую существующей значило бы краснеть на
 * верном утверждении, то есть завести сторожа, которого выключат через неделю.
 * Считает это сам двоичный: `flang tokens --keyword` отвечает именем конструкции
 * только тогда, когда значащий токен ровно один и он ключевой.
 */
export function лексерЗнает(форма) {
  return ключевоеСлово(форма) !== null
}

/** Собрать все утверждения «формы X нет» по дереву. */
export function собратьУтверждения(корень = КОРЕНЬ) {
  const найдено = []
  for (const путь of файлыДерева(корень)) {
    const отн = relative(корень, путь).split("\\").join("/")
    let текст
    try {
      текст = readFileSync(путь, "utf8")
    } catch {
      continue
    }
    for (const кусок of кускиПрозы(отн, текст)) {
      for (const фраза of фразы(кусок)) {
        if (НАДГРОБИЯ.some((р) => р.test(фраза.текст))) continue
        const известные = new Set()
        for (const р of ОТРИЦАНИЯ) {
          р.lastIndex = 0
          let м
          while ((м = р.exec(фраза.текст)) !== null) {
            /* Хвост решает, о языке ли речь: «слова «шаг» здесь нет» — о файле. */
            if (НЕ_О_ЯЗЫКЕ.test(фраза.текст.slice(м.index + м[0].length))) continue
            if (ПРО_ПРОГРАММУ.test(фраза.текст.slice(0, м.index))) continue
            /* Утверждение целиком внутри «…» — это ЦИТАТА чужих слов, а не свои.
               Ею пишут надгробие: «здесь стояло, что формы «X» в языке нет». */
            if (вЦитате(фраза.текст, м.index, м.index + м[0].length)) continue
            /* Формы берутся ИЗ САМОГО совпадения, а не из фразы: иначе кавычки,
               стоящие в предложении по другому поводу, приписались бы отрицанию. */
            for (const ф of названныеФормы(м[1] ?? "")) if (лексерЗнает(ф)) известные.add(ф)
          }
        }
        if (известные.size === 0) continue
        найдено.push({ файл: отн, строка: фраза.строка, текст: фраза.текст, известные: [...известные] })
      }
    }
  }
  return найдено
}

/** Отсев поимённых узких мест. */
export function отсеятьУзкие(найдено) {
  return найдено.filter(
    (н) => !УЗКИЕ.some((у) => н.файл === у.где && н.известные.length === 1 && н.известные[0] === у.форма),
  )
}

/** Проверка целиком. Возвращает список нарушений. */
export function проверить(корень = КОРЕНЬ) {
  return отсеятьУзкие(собратьУтверждения(корень))
}

