/**
 * ЗАКОННОЕ РАСХОЖДЕНИЕ, и оно ровно одно: ключ, который справка двоичного
 * называет ТОЛЬКО в разделах команд, неизвестных эталону. Тогда ключа нет у
 * эталона потому, что у него нет КОМАНДЫ, — и это уже посчитано выше.
 * Раздел «(общая)» не в счёт: общая справка не команда.
 * Всё прочее — беда, как бы ни хотелось назвать её задумкой.
 */
function законноеОтсутствие(ключ) {
  const где = Д.где.get(ключ);
  if (!где) return false;
  const разделы = [...где].filter(р => р !== '(общая)');
  return разделы.length > 0 && разделы.every(р => незнакомаяЭталону.has(р));
}

