/**
 * Сторож НАБОРА КЛЮЧЕЙ: сходятся ли ключи командной строки у двух реализаций.
 *
 * ── Дыра, ради которой он написан ──────────────────────────────────────────
 *
 * Разбор командной строки в дереве описан ДВАЖДЫ:
 *
 *   • рукописная оболочка на C — `flang/src/emit/c/flang_repl.c` и
 *     `flang/src/emit/c/flang_cli.c`; из неё собран двоичный, и именно она
 *     отвечает человеку;
 *   • эталон на самом языке — `flang/self/cli.flang`, «чистая половина»
 *     командной строки.
 *
 * Сверял их когда-то побайтовый тест `flang/test/self-cli-args.test.mjs` —
 * против свидетеля на JavaScript (`flang/bin/flang.mjs`). Свидетеля сняли
 * 20 августа 2026, и вместе с ним ушёл тест. С тех пор наборы ключей двух
 * реализаций не сверяет НИКТО: ключ, дописанный в C, эталону неизвестен, и
 * узнают об этом от человека, а не от проверки.
 *
 * Что расхождение это не выдумка, записано в `docs/adr/0010-…`, раздел «Четыре
 * расхождения командной строки»: там та же таблица, сличённая ЧТЕНИЕМ и
 * от руки. Здесь она снимается прогоном и разбором, и краснеет сама.
 *
 * ── Откуда берутся наборы ──────────────────────────────────────────────────
 *
 * НИ ОДИН из трёх наборов не вписан в этот файл руками — иначе сторож стал бы
 * ещё одним списком, набранным руками, и отстал бы первым:
 *
 *   Э  эталон   — разбором `flang/self/cli.flang`: перечни-семейства
 *                 («|--a|--b|») плюс точные постоянные вида "--ключ";
 *   Р  разбор C — разбором `flang_repl.c`/`flang_cli.c`: сравнения `strcmp`
 *                 с доводом плюс `human_word`/`human_flag`;
 *   Д  двоичный — ПРОГОНОМ: `flang --help`, затем `flang <команда> --help`
 *                 по каждой команде, названной первым этажом справки. Список
 *                 команд тоже читается из справки, а не вписан сюда.
 *
 * ── Что спрашивается ───────────────────────────────────────────────────────
 *
 *   1. Ключ разбирается в C и неизвестен эталону        (разряд 1);
 *   2. ключ известен эталону и не разбирается в C       (разряд 2);
 *   3. ключ есть у обоих, но значит РАЗНОЕ              (разряд 3) — а именно:
 *        • сломана ПАРА написаний: латинское и кириллическое написание одного
 *          ключа, и одно из них есть у обоих, а второе только у одного;
 *        • расходится «берёт ли ключ значение».
 *      Третий разряд опаснее первых двух: вызов проходит и делает не то.
 *   4. ключ разбирается в C, но справка двоичного о нём МОЛЧИТ;
 *   5. команда известна одному и неизвестна другому.
 *
 * ── Ведомость долга ────────────────────────────────────────────────────────
 *
 * Расхождения, уже известные и записанные, лежат в
 * `flang/scripts/cli-keys-debt.json`. Ведомость эта — НЕ источник наборов: она
 * только гасит уже названное. Сверяется она В ОБЕ СТОРОНЫ, как у
 * `binary-rules-guard.mjs`:
 *
 *   • расхождение, которого в ведомости нет, — красно (новое);
 *   • запись ведомости, расхождения по которой БОЛЬШЕ НЕТ, — тоже красна:
 *     долг закрыт, значит запись стала неправдой, и убрать её обязан тот, кто
 *     долг закрыл. Иначе ведомость превращается в кладбище.
 *
 * ── Коды возврата ──────────────────────────────────────────────────────────
 *
 *   0  наборы сошлись (с точностью до записанного долга);
 *   1  наборы разошлись — расхождения названы поимённо и числом;
 *   2  спросить не удалось: нет двоичного, нет исходника, справка не читается.
 *      Это НЕ «наборы сошлись» и НЕ «наборы разошлись».
 */

