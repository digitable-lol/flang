function судить(имя, найдено, ключИмени = х => х) {
  const вЖизни = new Set(найдено.map(ключИмени));
  const вДолге = записано(имя);
  const новые = порядок([...вЖизни].filter(к => !вДолге.has(к)));
  const надгробия = порядок([...вДолге].filter(к => !вЖизни.has(к)));
  return { вЖизни, новые, надгробия };
}

