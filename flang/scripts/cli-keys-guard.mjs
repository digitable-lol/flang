/** Ключ ли это слово: «--слово» или «-б». Не значение, не проза, не чужая программа. */
const ключЛи = с => /^--\p{L}[\p{L}\p{N}-]*$/u.test(с) || /^-\p{L}$/u.test(с);
const порядок = м => [...м].sort((а, б) => а.localeCompare(б, 'ru'));

function не_смог(что) {
  process.stderr.write(`сторож ключей: спросить не удалось — ${что}\n`);
  process.exit(2);
}

// ═══════════════════ Э: эталон на самом языке ═══════════════════

function снятьЭталон() {
  if (!existsSync(ЭТАЛОН)) не_смог(`нет ${ЭТАЛОН}`);
  const текст = readFileSync(ЭТАЛОН, 'utf8');

  // перечни-семейства: "|--a|--b|"
  const семейства = [...текст.matchAll(/"\|((?:--[^"|]+\|)+)"/gu)]
    .map(м => м[1].split('|').filter(Boolean));
  // точные постоянные: "--ключ", "-h"
  const точные = [...текст.matchAll(/"(-{1,2}[^\s"|]+)"/gu)].map(м => м[1]).filter(ключЛи);

  const ключи = new Set([...точные, ...семейства.flat().filter(ключЛи)]);

  // самый длинный перечень внутри названной функции — её тело, а не «содержит»
  const тело = имя => {
    const м = текст.match(new RegExp(`тотальная функция «${имя}»[\\s\\S]*?(?=\\n\\n|$)`, 'u'));
    if (!м) не_смог(`в эталоне нет функции «${имя}»`);
    const строки = [...м[0].matchAll(/"\|([^"]*?)\|"/gu)].map(x => x[1].split('|').filter(Boolean));
    if (строки.length === 0) не_смог(`у функции «${имя}» эталона не нашлось перечня`);
    return строки.reduce((а, б) => (б.length > а.length ? б : а), []);
  };

  const соЗначением = new Set([...тело('Строковые ключи'), ...тело('Числовые ключи'), ...тело('Ключи JSON')].filter(ключЛи));
  const безЗначения = new Set([...тело('Ключи-переключатели'), ...тело('Ключи полномочий')].filter(ключЛи));
  const команды = new Set(тело('Известные команды'));

  // пары написаний: («что-то» равен "A") или («что-то» равен "B")
  const пары = new Set();
  for (const м of текст.matchAll(/«[^»]+» равен "(-{1,2}[^"]+)"\)\s*или\s*\(«[^»]+» равен "(-{1,2}[^"]+)"/gu)) {
    if (ключЛи(м[1]) && ключЛи(м[2])) пары.add([м[1], м[2]].sort().join('/'));
  }

  return { ключи, соЗначением, безЗначения, команды, пары };
}

// ═══════════════════ Р: рукописный разбор на C ═══════════════════

/** Тело ветви `else if (…)` — от места сравнения до следующей ветви цепочки. */
function телоВетви(текст, с) {
  const конец = текст.indexOf('} else if (strcmp(', с + 1);
  const конец2 = текст.indexOf('} else {', с + 1);
  const к = [конец, конец2].filter(x => x > 0).sort((a, b) => a - b)[0];
  return текст.slice(с, к > 0 ? к : Math.min(с + 4000, текст.length));
}

/**
 * БЕРЁТ ЛИ КЛЮЧ ЗНАЧЕНИЕ. Читается по телу ветви, а не по догадке, и идиом в
 * этом дереве три, все три встречаются живьём:
 *   `strcmp(argv[i], "--k") == 0 && i + 1 < argc`      — условие само говорит;
 *   `… { i += 1; … argv[i] … }`                        — сдвиг внутри ветви;
 *   `const char *word = argv[read]; … argv[read + 1] … read += 2;`
 *                                                      — счётчик у ДРУГОГО имени.
 * Пропустить идиому — значит проглядеть ключ, который у одной реализации берёт
 * значение, а у другой нет: это третий разряд, самый опасный.
 */
function беретЗначение(текст, что, ветвь) {
  const экран = с => с.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
  const подпись = /\[([^\]]+)\]/u.exec(что);
  let счётчик = подпись ? подпись[1].trim() : что;
  if (!подпись) {
    // имя вроде `word` — найти, из какого счётчика оно взято: `word = argv[read]`
    const откуда = new RegExp(`${экран(что)}\\s*=\\s*argv\\[([^\\]]+)\\]`, 'u').exec(текст);
    if (откуда) счётчик = откуда[1].trim();
  }
  const с = экран(счётчик);
  if (/\+\s*1\s*<\s*argc/u.test(ветвь.slice(0, 300))) return true;
  if (new RegExp(`(?:^|[^\\w])${с}\\s*\\+=\\s*[12]\\s*;`, 'u').test(ветвь)) return true;
  if (new RegExp(`argv\\[\\s*${с}\\s*\\+\\s*1\\s*\\]`, 'u').test(ветвь)) return true;
  if (new RegExp(`${с}\\s*\\+\\s*1\\s*>=\\s*(?:argc|count)`, 'u').test(ветвь)) return true;
  return false;
}

function снятьРазборC() {
  const ключи = new Set(), соЗначением = new Set(), команды = new Set(), пары = new Set();
  for (const файл of ИСХОДНИКИ_C) {
    if (!existsSync(файл)) не_смог(`нет ${файл}`);
    const текст = readFileSync(файл, 'utf8');

    // сравнение довода с постоянной
    const сравнение = /strcmp\(\s*([A-Za-z_][A-Za-z0-9_]*(?:\[[^\]]+\])?)\s*,\s*"(-{1,2}[^"]+)"\s*\)\s*(==|!=)\s*0/gu;
    for (const м of текст.matchAll(сравнение)) {
      const [, что, слово] = м;
      if (!ключЛи(слово)) continue;
      // сравнение с `command`/`topic` — это ИМЯ КОМАНДЫ или тема справки,
      // а не ключ: `flang --mcp-mode`, `flang --машина` стоят в позиции команды.
      if (что === 'command' || что === 'topic') continue;
      ключи.add(слово);
      const ветвь = телоВетви(текст, м.index);
      if (беретЗначение(текст, что, ветвь)) соЗначением.add(слово);
    }
    // ИМЕНА КОМАНД: слово, с которым сравнивают `command` (= argv[1]).
    // `flang --mcp-mode` и `flang --машина` стоят В ПОЗИЦИИ КОМАНДЫ, а не ключа,
    // и сличать их надо с перечнем команд эталона, а не с перечнем ключей.
    for (const м of текст.matchAll(/strcmp\(\s*command\s*,\s*"([^"]+)"\s*\)\s*==\s*0/gu)) команды.add(м[1]);
    // пары написаний в одной ветви: strcmp(x,"A")==0 || strcmp(x,"B")==0
    for (const м of текст.matchAll(/strcmp\(\s*([A-Za-z_][A-Za-z0-9_]*(?:\[[^\]]+\])?)\s*,\s*"(-{1,2}[^"]+)"\s*\)\s*==\s*0\s*\|\|\s*strcmp\(\s*[^,]+,\s*"(-{1,2}[^"]+)"\s*\)\s*==\s*0/gu)) {
      if (ключЛи(м[2]) && ключЛи(м[3])) пары.add([м[2], м[3]].sort().join('/'));
    }
    // человеческие слова: human_word(слово, "--полное", "-к", "голое")
    for (const м of текст.matchAll(/human_word\(\s*[^,]+,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)/gu)) {
      if (ключЛи(м[1])) ключи.add(м[1]);
      if (ключЛи(м[2])) ключи.add(м[2]);
      if (ключЛи(м[1]) && ключЛи(м[2])) пары.add([м[1], м[2]].sort().join('/'));
      команды.add(м[3]);
    }
    for (const м of текст.matchAll(/human_flag\(\s*argc\s*,\s*argv\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)/gu)) {
      if (ключЛи(м[1])) ключи.add(м[1]);
      if (ключЛи(м[2])) ключи.add(м[2]);
      if (ключЛи(м[1]) && ключЛи(м[2])) пары.add([м[1], м[2]].sort().join('/'));
    }
  }
  if (ключи.size === 0) не_смог('в исходниках C не нашлось ни одного разбора ключа — разбор изменил вид');
  return { ключи, соЗначением, команды, пары };
}

// ═══════════════════ Д: двоичный, прогоном ═══════════════════

function снятьДвоичный() {
  if (!existsSync(ДВОИЧНЫЙ)) не_смог(`нет двоичного ${ДВОИЧНЫЙ} (FLANG_BINARY укажет другой)`);
  const прогон = доводы => {
    try {
      return execFileSync(ДВОИЧНЫЙ, доводы, {
        cwd: КОРЕНЬ, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
        maxBuffer: 64 * 1024 * 1024, timeout: 60_000,
      });
    } catch (е) {
      if (е.code === 'ETIMEDOUT') не_смог(`«flang ${доводы.join(' ')}» не ответил за 60 с`);
      return (е.stdout || '') + (е.stderr || '');
    }
  };
  const общая = прогон(['--help']);
  if (!/flang <команда>|flang check/u.test(общая)) не_смог('«flang --help» не похож на справку — прогон не удался');

  // команды читаются ИЗ САМОЙ СПРАВКИ, а не вписаны сюда
  const команды = [...new Set([...общая.matchAll(/^ {2}flang ([a-z][a-z0-9-]*)/gmu)].map(м => м[1]))];
  if (команды.length === 0) не_смог('первый этаж справки не назвал ни одной команды');

  const тексты = new Map([['(общая)', общая]]);
  for (const к of команды) тексты.set(к, прогон([к, '--help']));

  const ключи = new Set(), где = new Map();
  for (const [имя, текст] of тексты) {
    for (const м of текст.matchAll(/(?<![\p{L}\p{N}-])(--\p{L}[\p{L}\p{N}.-]*)/gu)) {
      const ключ = м[1].replace(/\.+$/u, '');
      if (!ключЛи(ключ)) continue;
      ключи.add(ключ);
      if (!где.has(ключ)) где.set(ключ, new Set());
      где.get(ключ).add(имя);
    }
  }
  return { ключи, команды: new Set(команды), где };
}

