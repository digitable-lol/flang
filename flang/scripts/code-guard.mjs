/**
 * Сторож КОДОВ ОТКАЗА, названных прозой: код из `.md` обязан существовать.
 *
 * ── Чего не хватало ─────────────────────────────────────────────────────────
 *
 * `flang/test/manpage.test.mjs` уже требует этого от страницы руководства:
 * каждый `FLANG_*` из раздела «ДИАГНОСТИКА» обязан встречаться в исходниках,
 * потому что «выдуманный код в документации хуже отсутствующего: по нему ищут и
 * не находят». Проверка эта стоит на ОДНОМ файле — `packaging/flang.1`, — а имён
 * `FLANG_*` проза называет 69 на 24 файла `.md`, и два из них не существуют
 * нигде:
 *
 *   • `FLANG_LAW_LIMIT` — `flang/cat/SPEC.md` обещает отдельную диагностику на
 *     упор в лимит шагов при проверке закона. Проверка законов при упоре просто
 *     прекращалась (`break авария` в `flang/src/monoid.mjs`) — то есть выходил
 *     ровно тот молчаливый успех, против которого решение и записано;
 *   • `FLANG_NODE_DEAD` — `flang/conc/DISTRIBUTED.md` называет его, чтобы
 *     ОТВЕРГНУТЬ: «код отказа поэтому `FLANG_LINK_DOWN`, а не `FLANG_NODE_DEAD`:
 *     второе было бы неправдой, которую нечем проверить».
 *
 * Два разных случая, и оба обязаны быть видны. Ни одному нельзя дать молчать.
 *
 * ПЕРВОГО В СПИСКЕ БОЛЬШЕ НЕТ, И ЭТО РАБОТА СТОРОЖА, А НЕ ПОБЛАЖКА ЕМУ.
 * `FLANG_LAW_LIMIT` заведён по-настоящему (`flang/src/compat.mjs`,
 * `work/declared-codes`): не досчитанный закон стал отличим от нарушенного.
 * Вторая половина проверки — «код из списка ПОЯВИЛСЯ» — на этом и сработала,
 * назвав запись неправдой; запись снята при сборке `work/svodka2`. Остаток
 * долга (тот же код в НАПЕЧАТАННОМ коде) кодом не измеряется и потому здесь
 * не числится: он записан шагом 5 «Порядка работ» в `flang/cat/SPEC.md`.
 *
 * ── Как устроено ────────────────────────────────────────────────────────────
 *
 * Каждый `FLANG_*` из любого `.md` ищется во всех НЕ-`.md` файлах дерева, кроме
 * тестов. Тесты исключены намеренно: тест, называющий код в комментарии, —
 * такая же проза, и засчитывать её за существование значило бы разрешить прозе
 * подтверждать саму себя.
 *
 * Код, которого в исходниках нет, обязан стоять в `ОБЪЯВЛЕНО_НЕ_СДЕЛАНО` —
 * поимённо, с местом и с доводом. Список закрытый и проверяется В ОБЕ СТОРОНЫ:
 *   • код из списка, которого нет, — прозе разрешено его называть;
 *   • код из списка, который ПОЯВИЛСЯ, — отказ. Долг закрыт, значит запись о
 *     долге стала неправдой, и убрать её обязан тот, кто долг закрыл.
 * Без второй половины список превратился бы в свалку, куда сваливают всё, что
 * покраснело, — то есть в выключатель сторожа.
 *
 * ── Чего сторож НЕ делает ───────────────────────────────────────────────────
 *
 * Он не проверяет, что код КОГДА-НИБУДЬ печатается: существование имени в
 * исходнике — не то же, что достижимость ветки, и утверждать обратное значило
 * бы обещать анализ достижимости, которого здесь нет. Что коды доходят до
 * пользователя, стерегут другие проверки — `flang/test/emit-conc-refuse.test.mjs`
 * (печать бросает именно тот код, который назван таблицей возможностей) и
 * `flang/test/failures.test.mjs`.
 *
 * Запуск: `node flang/scripts/code-guard.mjs` (или `npm run codes:check`).
 * Проверяется он сам — тестом `flang/test/code-guard.test.mjs`.
 */
import { readdirSync, readFileSync, statSync } from "node:fs"
import { extname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

export const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))

/** Каталоги, которых в дереве исходников нет: чужое, собранное, временное. */
/* `.claude` — рабочие копии репозитория, которые заводит себе оснастка агента:
   на этой машине их в дереве 88 штук, и в каждой лежит полный `flang/`. Сторож,
   заходящий туда, считает одну и ту же прозу девяносто раз и жалуется на
   вчерашние копии как на сегодняшнее дерево. Тот же род каталога, что
   `node_modules` и `dist`: не исходник, а следствие работы инструмента. */
const ПРОПУСК = new Set(["node_modules", ".git", ".claude", "dist", "output", "coverage"])

/** Имя кода: `FLANG_` и заглавные латинские дальше. */
const ИМЯ_КОДА = /\bFLANG_[A-Z0-9_]+\b/gu

/**
 * Коды, названные прозой и НЕ существующие в исходниках, — поимённо.
 *
 * Каждая запись обязана назвать РОД, место и довод. Довод «так исторически»
 * здесь не довод: запись без него — это способ заткнуть сторожа, а не объяснить
 * дерево.
 *
 * Родов ровно два, и путать их нельзя:
 *   • `"долг"` — код обещан прозой и ещё не написан. Такая запись обязывает
 *     прозу сказать читателю «объявлено, не сделано» ТАМ ЖЕ, где обещание:
 *     в список читатель контракта не заглянет;
 *   • `"отвергнут"` — код назван прозой затем, чтобы объяснить, почему его НЕ
 *     будет. Пометки долга такой записи не нужно: проза и так отвергает.
 * Разница проверяется `flang/test/code-guard.test.mjs`.
 */
export const ОБЪЯВЛЕНО_НЕ_СДЕЛАНО = [
  {
    код: "FLANG_NODE_DEAD",
    род: "отвергнут",
    где: "flang/conc/DISTRIBUTED.md",
    почему:
      "код назван, чтобы быть ОТВЕРГНУТЫМ: узел видит молчание связи, а не смерть чужого узла, " +
      "и обещать второе значило бы обещать знание, которого нет. Существовать он не должен, и " +
      "его появление в исходниках — повод пересмотреть прозу, а не пополнить список",
  },
]

/** Обход дерева. */
function файлыДерева(каталог, собранное = []) {
  for (const имя of readdirSync(каталог)) {
    if (ПРОПУСК.has(имя)) continue
    const путь = join(каталог, имя)
    let сведения
    try {
      сведения = statSync(путь)
    } catch {
      continue
    }
    if (сведения.isDirectory()) файлыДерева(путь, собранное)
    else собранное.push(путь)
  }
  return собранное
}

/**
 * Файлы, которые сами говорят о кодах, а не печатают их.
 *
 * Тест — это проза, а не улика существования кода. Сам сторож — тем более:
 * первый его прогон дал «не существует: 0», потому что `ОБЪЯВЛЕНО_НЕ_СДЕЛАНО`
 * называет `FLANG_LAW_LIMIT` и `FLANG_NODE_DEAD` — и сторож нашёл их в
 * СОБСТВЕННОМ исходнике, приняв свой список исключений за реализацию. Это тот
 * самый дефект, которым страдали гейты `digitwm` и `blender-mcp`: цитата строки
 * SPDX в шапке удовлетворяла проверку на наличие SPDX. Проверка, довольная
 * собой, выглядит ровно как проверка, у которой всё хорошо.
 */
const САМ = new Set(["flang/scripts/code-guard.mjs"])

function этоПрозаОКодах(отн) {
  if (САМ.has(отн)) return true
  return /(^|\/)test(s)?\//u.test(отн) || /\.test\.[a-z]+$/u.test(отн) || /(^|\/)__tests__\//u.test(отн)
}

/**
 * Что где названо.
 *
 * @returns {{ вПрозе: Map<string, Array<{файл: string, строка: number}>>, вИсходниках: Map<string, string[]> }}
 */
export function собрать(корень = КОРЕНЬ) {
  const вПрозе = new Map()
  const вИсходниках = new Map()
  for (const путь of файлыДерева(корень)) {
    const отн = relative(корень, путь).split("\\").join("/")
    let текст
    try {
      текст = readFileSync(путь, "utf8")
    } catch {
      continue
    }
    if (extname(отн) === ".md") {
      текст.split("\n").forEach((строка, i) => {
        for (const м of строка.matchAll(ИМЯ_КОДА)) {
          if (!вПрозе.has(м[0])) вПрозе.set(м[0], [])
          вПрозе.get(м[0]).push({ файл: отн, строка: i + 1 })
        }
      })
      continue
    }
    if (этоПрозаОКодах(отн)) continue
    for (const м of текст.matchAll(ИМЯ_КОДА)) {
      if (!вИсходниках.has(м[0])) вИсходниках.set(м[0], [])
      const где = вИсходниках.get(м[0])
      if (!где.includes(отн)) где.push(отн)
    }
  }
  return { вПрозе, вИсходниках }
}

/**
 * Проверка целиком. Возвращает список нарушений двух родов:
 *   `выдуман`  — проза называет код, которого нет и который нигде не объявлен долгом;
 *   `долг закрыт` — код из списка «объявлено, не сделано» появился в исходниках.
 */
export function проверить(корень = КОРЕНЬ) {
  const { вПрозе, вИсходниках } = собрать(корень)
  const нарушения = []

  for (const [код, места] of вПрозе) {
    if (вИсходниках.has(код)) continue
    const запись = ОБЪЯВЛЕНО_НЕ_СДЕЛАНО.find((з) => з.код === код)
    if (запись !== undefined) continue
    нарушения.push({ род: "выдуман", код, места })
  }

  for (const запись of ОБЪЯВЛЕНО_НЕ_СДЕЛАНО) {
    const где = вИсходниках.get(запись.код)
    if (где === undefined) continue
    нарушения.push({ род: "долг закрыт", код: запись.код, места: где.map((ф) => ({ файл: ф, строка: 0 })) })
  }

  return нарушения
}

/* ── запуск из командной строки ─────────────────────────────────────────── */
if (import.meta.url === `file://${process.argv[1]}`) {
  const нарушения = проверить()
  if (нарушения.length === 0) {
    const { вПрозе } = собрать()
    console.log(
      `сторож кодов: чисто — все ${вПрозе.size} имён FLANG_* из прозы либо есть в исходниках, ` +
        `либо помечены «объявлено, не сделано» (${ОБЪЯВЛЕНО_НЕ_СДЕЛАНО.length})`,
    )
    process.exit(0)
  }
  console.error(`сторож кодов: ${нарушения.length} нарушени(й)\n`)
  for (const н of нарушения) {
    if (н.род === "выдуман") {
      console.error(`${н.код} — назван прозой, но в исходниках его НЕТ`)
      for (const м of н.места) console.error(`  ${м.файл}:${м.строка}`)
      console.error("  Либо код появился под другим именем — правьте прозу; либо это обещание,")
      console.error("  а не факт — пометьте его в прозе «объявлено, не сделано» и заведите запись")
      console.error("  в ОБЪЯВЛЕНО_НЕ_СДЕЛАНО с доводом.")
    } else {
      console.error(`${н.код} — числится «объявлено, не сделано», а в исходниках УЖЕ ЕСТЬ:`)
      for (const м of н.места) console.error(`  ${м.файл}`)
      console.error("  Долг закрыт: снимите запись из ОБЪЯВЛЕНО_НЕ_СДЕЛАНО и пометку из прозы.")
    }
    console.error("")
  }
  process.exit(1)
}
