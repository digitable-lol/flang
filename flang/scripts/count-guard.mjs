export function проверить(корень = КОРЕНЬ, свод = null) {
  const расхождения = []
  const пределы = пределыДерева(корень)
  for (const путьФайла of прозаДерева(корень)) {
    const отн = relative(корень, путьФайла).split("\\").join("/")
    let текст
    try {
      текст = readFileSync(путьФайла, "utf8")
    } catch {
      continue
    }

    /* Потолок шагов сверяется и в `.md`, и во врезке скрипта: он живёт в обоих
       родах прозы, а протухает одинаково. Правила о СТРОКАХ остаются у `.md` —
       во врезке кода путь рядом с числом почти всегда говорит не о размере
       файла, и сторож краснел бы на верном тексте. */
    расхождения.push(...потолокВПрозе(отн, текст, пределы))
    if (extname(путьФайла) !== ".md") continue

    for (const абзац of абзацы(текст)) {
      if (НАДГРОБИЯ.some((р) => р.test(абзац.текст))) continue
      if (НЕ_РАЗМЕРЫ.test(абзац.текст)) continue
      for (const { путь, сказано } of строкиПроПуть(абзац)) {
        const измерено = строкПод(путь, корень, основыДля(отн))
        if (измерено === null) continue
        if (измерено !== сказано)
          расхождения.push({ файл: отн, строка: абзац.строка, род: "строк", про: путь, сказано, измерено })
      }
      if (свод !== null) {
        for (const правило of ВЕДОМОСТЬ) {
          const м = абзац.текст.match(правило.образец)
          if (м === null) continue
          const измерено = поПути(свод, правило.поле)
          if (измерено === undefined) continue
          if (Number(м[1]) !== измерено)
            расхождения.push({
              файл: отн,
              строка: абзац.строка,
              род: правило.что,
              про: правило.поле,
              сказано: Number(м[1]),
              измерено,
            })
        }
      }
    }

    for (const { строка, путь, сказано } of строкиТаблиц(текст)) {
      const измерено = строкПод(путь, корень, основыДля(отн))
      if (измерено === null) continue
      if (измерено !== сказано)
        расхождения.push({ файл: отн, строка, род: "строк (таблица)", про: путь, сказано, измерено })
    }
  }
  return расхождения
}

/* ── починка ────────────────────────────────────────────────────────────── */

/**
 * Почему у сторожа есть `--fix`.
 *
 * Число прозы правят руками, и правка эта — переписывание того, что дерево уже
 * посчитало. За сутки такая правка трижды соврала: считали не тем набором
 * файлов. Сторож ЗНАЕТ измеренное — он же его и посчитал; значит переписать
 * число может он, а не человек.
 *
 * Починка нарочно ТРУСЛИВАЯ. Она правит только то место, где написание числа в
 * границах абзаца одно. Два одинаковых числа в абзаце — повод позвать человека,
 * а не угадывать, какое из них про этот путь: сторож, который угадал неверно,
 * хуже сторожа, который промолчал.
 */

/**
 * Куда починка НЕ ходит, и это не список любимчиков, а правило.
 *
 * `tasks/` и `docs/zettel/` — ДАТИРОВАННЫЕ записи, и довод у них один: они
 * пишут ИЗМЕРЕННОЕ ТОГДА. Заметка базы знаний говорит «чем подтверждено — 516
 * строк такого-то файла»; закрытая задача говорит, что было правдой в час,
 * когда её брали, и остаётся в дереве нарочно, вместе со своим доводом
 * (`tasks/README.md`). Переписать в них число сегодняшним значит стереть улику
 * и оставить запись, у которой нечем проверить довод. Правятся они поправкой,
 * где видно и старое, и новое, а поправку пишет человек.
 *
 * Это тот же список, что `НЕ_ПРО_ПОТОЛОК` выше, и его примечание на этот довод
 * прямо ссылается. 5 сентября 2026 оказалось, что ссылается оно в пустоту:
 * `tasks/` стоял ТАМ и не стоял ЗДЕСЬ, хотя довод один и назван в обоих
 * местах. Правило знало, список — нет.
 *
 * Всё остальное `--fix` трогает — и всё равно ЧИТАЕТСЯ ГЛАЗАМИ до коммита:
 * число рядом с путём бывает не о размере файла, а о том, сколько строк
 * пришлось ПРАВИТЬ. Такие места сторож не отличает и отличать не умеет; их
 * помечают в самом документе (см. `НЕ_РАЗМЕРЫ` ниже).
 */
const НЕ_ЧИНИТЬ = [/^tasks\//u, /^docs\/zettel\//u]

/** Разрядами: 24379 → «24 379». Разделитель берётся тот, что стоит в прозе. */
const разрядами = (н, разделитель) => String(н).replace(/\B(?=(\d{3})+(?!\d))/gu, разделитель)

/** Написания одного числа, встречающиеся в этой прозе. */
function написания(н) {
  return [...new Set([String(н), разрядами(н, " "), разрядами(н, "\u00a0")])]
}

/** Границы абзаца, начинающегося со строки `номер` (1-based), в строках файла. */
function границыАбзаца(строки, номер) {
  let от = номер - 1
  let до = от
  while (до + 1 < строки.length && строки[до + 1].trim() !== "" && !/^\s*```/u.test(строки[до + 1])) до += 1
  return { от, до }
}

/**
 * Заменяет `сказано` на `измерено` в границах строк [от, до].
 *
 * Возвращает `true`, если заменил. `false` — если места не одно или его нет
 * вовсе: тогда число остаётся красным, и это правильно.
 */
export function заменитьЧисло(строки, от, до, сказано, измерено) {
  const места = []
  for (let i = от; i <= до && i < строки.length; i++) {
    for (const вид of написания(сказано)) {
      for (let место = строки[i].indexOf(вид); место !== -1; место = строки[i].indexOf(вид, место + 1)) {
        // Цифра вплотную слева или справа означает, что это другое число.
        if (/\d/u.test(строки[i][место - 1] ?? "")) continue
        if (/\d/u.test(строки[i][место + вид.length] ?? "")) continue
        if (места.some((м) => м.i === i && м.место === место)) continue
        места.push({ i, место, вид })
      }
    }
  }
  if (места.length !== 1) return false
  const { i, место, вид } = места[0]
  const разделитель = вид.includes("\u00a0") ? "\u00a0" : вид.includes(" ") ? " " : ""
  const стало = разделитель === "" ? String(измерено) : разрядами(измерено, разделитель)
  строки[i] = строки[i].slice(0, место) + стало + строки[i].slice(место + вид.length)
  return true
}

/**
 * Переписывает числа прозы измеренными. Возвращает, что починено и что нет.
 */
export function починить(расхождения, корень = КОРЕНЬ) {
  const поФайлам = new Map()
  for (const р of расхождения) {
    if (!поФайлам.has(р.файл)) поФайлам.set(р.файл, [])
    поФайлам.get(р.файл).push(р)
  }
  const починено = []
  const осталось = []
  for (const [файл, свои] of поФайлам) {
    if (НЕ_ЧИНИТЬ.some((р) => р.test(файл))) {
      осталось.push(...свои)
      continue
    }
    const путь = join(корень, файл)
    const строки = readFileSync(путь, "utf8").split("\n")
    let тронут = false
    /* Сверху вниз, но каждое расхождение ищется заново по своим границам:
       замена не двигает номера строк, потому что строк не прибавляется. */
    for (const р of свои) {
      /* Потолок шагов `--fix` не трогает НАРОЧНО. Рядом с этим числом всегда
         стоит выведенный из него довод — «запас 23,8 раза», «стена в 19,9 млрд»,
         — и переписать одни цифры значит оставить довод неверным, а вид у него
         сделать свежий. Такое место зовёт человека. */
      if (р.написание !== undefined) {
        осталось.push(р)
        continue
      }
      const { от, до } =
        р.род === "строк (таблица)" ? { от: р.строка - 1, до: р.строка - 1 } : границыАбзаца(строки, р.строка)
      if (заменитьЧисло(строки, от, до, р.сказано, р.измерено)) {
        починено.push(р)
        тронут = true
      } else {
        осталось.push(р)
      }
    }
    if (тронут) writeFileSync(путь, строки.join("\n"))
  }
  return { починено, осталось }
}

/* ── запуск из командной строки ─────────────────────────────────────────── */
if (запущенНапрямую(import.meta.url)) {
  /*
   * `--дерево <путь>` — прогнать сторожа над ДРУГИМ деревом.
   *
   * Заведён не для удобства. Сторож, которого нельзя натравить на подложенный
   * случай, проверить нечем: единственный способ узнать, умеет ли он краснеть,
   * — подложить неверное число, а подкладывать его в рабочее дерево значит
   * пачкать дерево и надеяться, что откат не оборвут. Второе применение —
   * прогон по своей рабочей копии, не трогая общую.
   *
   * Правила ВЕДОМОСТИ в этом случае стоят, и сторож говорит об этом вслух: свод
   * `proof-ledger.mjs` считается по корпусу ЭТОГО репозитория, у чужого дерева
   * такого корпуса нет, и молча выдать его за измеритель значило бы соврать.
   */
  const где = process.argv.indexOf("--дерево")
  if (где !== -1 && где + 1 >= process.argv.length) {
    console.error("сторож чисел: --дерево названо без пути")
    process.exit(2)
  }
  const корень = где === -1 ? КОРЕНЬ : `${resolve(process.argv[где + 1])}/`
  const своё = корень === КОРЕНЬ
  let свод = null
  if (своё) {
    const { сводКорпуса } = await import("./proof-ledger.mjs")
    свод = (await сводКорпуса()).итог
  } else {
    console.log(`сторож чисел: дерево ${корень}`)
    console.log("сторож чисел: правила ведомости стоят — свод корпуса считается только по своему дереву")
  }
  let расхождения = проверить(корень, свод)

  if (process.argv.includes("--fix") && расхождения.length > 0) {
    const { починено, осталось } = починить(расхождения, корень)
    console.log(`сторож чисел: переписано измеренным ${починено.length}, осталось руками ${осталось.length}`)
    for (const р of осталось) {
      console.log(`  руками: ${р.файл}:${р.строка}  ${р.род} про ${р.про}: ${р.сказано} → ${р.измерено}`)
    }
    расхождения = проверить(корень, свод)
  }

  if (расхождения.length === 0) {
    console.log("сторож чисел: чисто — каждое проверяемое число прозы сошлось с измерителем")
    process.exit(0)
  }
  console.error(`сторож чисел: ${расхождения.length} числ(о/а) прозы разошлись с деревом\n`)
  for (const р of расхождения) {
    console.error(`${р.файл}:${р.строка}  ${р.род} про ${р.про}`)
    console.error(`  сказано:  ${р.сказано}${р.написание === undefined ? "" : `  («${р.написание}»)`}`)
    console.error(`  измерено: ${р.измерено}`)
    console.error("")
  }
  console.error(
    "Правьте прозу, а не сторожа: измеритель — это дерево, а число в предложении — " +
      "пересказ, который не исполняется и потому не ломается сам.",
  )
  process.exit(1)
}
