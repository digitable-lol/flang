/** Разбирает написание суммы в число. `null` — если разбор не однозначен. */
export function разобратьСумму(текст) {
  const t = текст.trim().toLowerCase().replace(/[  ]/gu, " ")
  const масштабИз = (слово) => {
    for (const [образец, множитель] of МАСШТАБЫ) if (образец.test(слово)) return множитель
    return null
  }
  const цифрами = t.match(new RegExp(`^(\\d[\\d ]*(?:[.,]\\d+)?)\\s*(${МАСШТАБ_ИСТ})?$`, "u"))
  if (цифрами !== null) {
    const н = Number(цифрами[1].replace(/ /gu, "").replace(",", "."))
    if (!Number.isFinite(н)) return null
    const масштаб = цифрами[2] === undefined ? 1 : масштабИз(цифрами[2])
    if (масштаб === null) return null
    return Math.round(н * масштаб)
  }
  const словами = t.match(new RegExp(`^(?:(${СЛОВО_ИСТ})\\s+)?(${МАСШТАБ_ИСТ})$`, "u"))
  if (словами !== null) {
    const масштаб = масштабИз(словами[2])
    if (масштаб === null) return null
    const множитель = словами[1] === undefined ? 1 : (МНОЖИТЕЛИ.get(словами[1]) ?? null)
    if (множитель === null) return null
    return Math.round(множитель * масштаб)
  }
  return null
}

