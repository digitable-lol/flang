/**
 * Куски файла, в которых ищется утверждение о потолке.
 *
 * У `.md` — абзац: предложение переносят на вторую строку, и половина
 * утверждения без второй половины не читается. У скрипта — ВРЕЗКА, то есть
 * подряд идущие строки комментария, склеенные в одну. Строки кода правило
 * потолка не смотрит вовсе: `MAX_STEPS=$MAX_STEPS` — это работа, а не проза.
 */
export function куски(текст, расширение) {
  const строки = текст.split("\n")
  const врезка = ВРЕЗКИ.get(расширение)
  const из = []
  let текущий = null
  for (let i = 0; i < строки.length; i++) {
    let содержимое = null
    if (врезка === undefined) {
      содержимое = строки[i].trim() === "" ? null : строки[i].trim()
    } else {
      const м = строки[i].match(врезка)
      содержимое = м === null ? null : м[1].trim()
    }
    /* Пустая строка комментария (`//` или `#` в одиночку) делит врезку так же,
       как пустая строка делит абзац. Без этого шапка `ярлыки.flang` — шестьдесят
       строк подряд — читалась бы одним куском, номер места указывал бы на её
       начало, а одно надгробие в середине гасило бы всю шапку разом. */
    if (содержимое === null || содержимое === "") {
      текущий = null
      continue
    }
    if (текущий === null) {
      текущий = { строка: i + 1, текст: содержимое }
      из.push(текущий)
    } else {
      текущий.текст += " " + содержимое
    }
  }
  return из
}

/** Расхождения по потолку в одном файле. */
export function потолокВПрозе(отн, текст, пределы) {
  if (НЕ_ПРО_ПОТОЛОК.some((р) => р.test(отн))) return []
  const расхождения = []
  const правила = [...ПОТОЛОК, ...ПРИСВОЕНИЯ]
  for (const кусок of куски(текст, extname(отн))) {
    if (НАДГРОБИЯ.some((р) => р.test(кусок.текст))) continue
    if (ПРОШЛОЕ_ПОТОЛКА.some((р) => р.test(кусок.текст))) continue
    if (НЕ_РАЗМЕРЫ.test(кусок.текст)) continue
    for (const правило of правила) {
      const м = кусок.текст.match(правило.образец)
      if (м === null) continue
      if (правило.при !== undefined && !правило.при.test(кусок.текст)) continue
      const сказано = разобратьСумму(м[1])
      const измерено = пределы[правило.поле]
      if (сказано === null || измерено === null || измерено === undefined) continue
      if (сказано !== измерено)
        расхождения.push({
          файл: отн,
          строка: кусок.строка,
          род: правило.что,
          про: правило.поле,
          сказано,
          измерено,
          написание: м[1].trim(),
        })
    }
  }
  return расхождения
}

