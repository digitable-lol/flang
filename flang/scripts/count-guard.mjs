/**
 * Сторож ЧИСЕЛ в прозе: число, названное про измеримое, сверяется с измерителем.
 *
 * ── Чего не хватало ─────────────────────────────────────────────────────────
 *
 * За одни сутки в этом дереве нашли одиннадцать мест, где проза расходилась с
 * деревом, и каждое — случайно: агенту велели воспроизвести улику, а не поверить
 * написанному. Числа в этом списке занимают половину: «`src/*.ts`, 3155 строк»,
 * «24379 строк в `flang/src/*.mjs`», «высказано 4 утверждения». Числа тухнут
 * быстрее прочей прозы, потому что дерево растёт каждый день, а предложение,
 * однажды написанное, не исполняется и потому не ломается.
 *
 * Приём здесь тот же, что у `flang/test/manpage.test.mjs` (код, названный
 * страницей, обязан существовать в исходниках) и у `flang/scripts/claim-guard.mjs`
 * (форму, названную прозой, спрашивают у лексера прогоном): у прозы есть
 * ИЗМЕРИТЕЛЬ, и спорят не мнения, а прогон.
 *
 * ── Что сверяется, и почему именно это ──────────────────────────────────────
 *
 * Сверяется не всякое число — только то, у которого измеритель ОДНОЗНАЧЕН:
 *
 *   1. «N строк» рядом с названным путём или образцом: `wc -l` по образцу.
 *      Две записи, обе живые в дереве:
 *        • `` `flang/core/` `` — 4590 строк   (путь слева, число справа);
 *        • 24379 строк в `` `flang/src/*.mjs` ``  (число слева, путь справа).
 *   2. Строка таблицы, у которой столбец назван «Строк», а первая клетка —
 *      путь в кавычках. Такой таблицей в `flang/cat/POLY.md` меряют слои, и
 *      каждое её число протухло ровно так же, как прочие.
 *   3. Числа ведомости доказательств, названные словами: «высказано N
 *      утверждений, из них M доказаны ядром…». Измеритель —
 *      `flang/scripts/proof-ledger.mjs`, тот же, что у свода корпуса.
 *
 * ── Чего сторож НЕ делает, и это решение, а не недоделка ────────────────────
 *
 * • ЧИСЛО ФАЙЛОВ он не сверяет. «AST всех 60 файлов `.flang` репозитория
 *   напечатан до и после правки» — не утверждение о размере дерева, а запись о
 *   том, что ПОКРЫЛ прошлый прогон. Дерево с тех пор выросло до 168 файлов, но
 *   прогон-то был на шестидесяти, и подставить туда 168 значило бы соврать про
 *   работу, которой не делали. Отличить «столько в дереве» от «столько прошло
 *   через прогон» нечем, кроме чтения, — значит сторож сюда не лезет.
 * • ЧИСЛО ФУНКЦИЙ у отдельного файла он не сверяет: свод корпуса
 *   (`proof-ledger.mjs`) считает по всему дереву, а не по образцу, и завести
 *   второй счётчик функций значило бы завести второе место, которое разъедется
 *   с первым.
 * • ПРИБЛИЖЕНИЯ — «~70 строк», «10—18 строк», «+55/−14 строк» — пропускаются.
 *   Приближение честно называет себя приближением; требовать от него точности
 *   значит требовать переписать его во что-то другое.
 * • НАДГРОБИЯ снятых чисел («здесь стояло «217 функций»») пропускаются по тем
 *   же словам, что и в `claim-guard.mjs`: память о правке — не утверждение.
 *
 * Запуск: `node flang/scripts/count-guard.mjs` (или `npm run counts:check`).
 * Проверяется он сам — тестом `flang/test/count-guard.test.mjs`, включая
 * подложенные случаи: сторож, который не умеет краснеть, выглядит ровно как
 * сторож, у которого всё хорошо.
 */
import { readdirSync, readFileSync, statSync } from "node:fs"
import { extname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

import { globSync } from "../test/glob.mjs"

export const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))

/** Каталоги, которых в дереве исходников нет: чужое, собранное, временное. */
const ПРОПУСК = new Set(["node_modules", ".git", "dist", "output", "coverage"])

/**
 * Надгробия — те же слова, что у сторожа утверждений. Список общий намеренно:
 * два сторожа с разными списками разошлись бы, и один стал бы требовать стирать
 * то, что другой разрешает помнить.
 */
const НАДГРОБИЯ = [
  /здесь стоял[оаи]?/iu,
  /больше не правда/iu,
  /перестал[оа] быть правдой/iu,
  /это неправда/iu,
  /стало неправдой/iu,
  /было неправдой/iu,
  /в первой редакции/iu,
  /устарел[оа]/iu,
]

/** Приближение или разность — не точное число, и сверять его нечем. */
const ПРИБЛИЖЕНИЕ =
  /[~≈+±−-]\s*$|около\s*$|примерно\s*$|более\s*$|менее\s*$|до\s*$|about\s*$|approximately\s*$|roughly\s*$|over\s*$|under\s*$|some\s*$/iu

/** Похоже ли на путь или образец: с косой чертой либо с расширением. */
function похожеНаПуть(текст) {
  if (/\s/u.test(текст)) return false
  return /\//u.test(текст) || /\.(?:mjs|js|ts|flang|fts|c|h|rs|go|py|java|cs|ex|md|json)$/u.test(текст)
}

/**
 * Число из прозы: пробелы и неразрывные пробелы внутри — разряды («22 316»).
 * Возвращает `null`, если разбор не однозначен.
 */
function число(текст) {
  const чистое = текст.replace(/[\s\u00a0\u202f]/gu, "")
  if (!/^\d+$/u.test(чистое)) return null
  return Number(чистое)
}

/* ── измеритель строк ───────────────────────────────────────────────────── */

/** Строк в файле — ровно как считает `wc -l`: по переводам строки. */
function строкФайла(путь) {
  const текст = readFileSync(путь, "utf8")
  let н = 0
  for (let i = 0; i < текст.length; i++) if (текст[i] === "\n") н++
  return н
}

/**
 * Расширения, которые считаются «исходником» при измерении каталога.
 *
 * Каталог, названный прозой (`flang/core/`), меряется по своим исходникам, а не
 * по всему содержимому: спецификация рядом с кодом — не код, и складывать её в
 * размер слоя значит мерять не то, о чём идёт речь.
 */
const ИСХОДНИКИ = new Set([".mjs", ".js", ".ts", ".flang", ".fts", ".c", ".h", ".rs", ".go", ".py", ".java", ".cs", ".ex"])

/**
 * Измеритель: сколько строк накрывает названный прозой путь.
 *
 * Путь может быть файлом, каталогом (тогда — его исходники, без вложенных
 * каталогов) или образцом со звёздочкой. Возвращает `null`, если под путём нет
 * ни одного файла: это не расхождение чисел, а отдельная беда, и сторож о ней
 * говорит отдельными словами.
 */
export function строкПод(путь, корень = КОРЕНЬ, основы = [""]) {
  for (const основа of основы) {
    const из = строкПодОсновой(основа === "" ? путь : `${основа}/${путь}`, корень)
    if (из !== null) return из
  }
  return null
}

/**
 * Основы, относительно которых читается путь из прозы файла.
 *
 * Репозиторий держит два дерева с каталогом `src/`: корневой — ядро FTS на
 * TypeScript, и `flang/src/` — компилятор языка. Проза `flang/cat/POLY.md`
 * пишет `src/lexer.mjs`, имея в виду второй, а `flang/core/SPEC.md` пишет
 * `src/*.ts`, имея в виду первый. Обе записи верны в своём месте, и решает
 * место: путь читается сперва от корня репозитория, потом от каталогов, в
 * которых лежит документ, — от верхнего к тому, где он лежит. Первая основа,
 * под которой путь существует, и выигрывает.
 */
export function основыДля(отн) {
  const части = отн.split("/").slice(0, -1)
  const из = [""]
  for (let к = 1; к <= части.length; к++) из.push(части.slice(0, к).join("/"))
  return из
}

function строкПодОсновой(путь, корень) {
  const очищен = путь.replace(/^\.\//u, "")
  let файлы
  if (очищен.includes("*")) {
    файлы = globSync(очищен, { cwd: корень })
  } else {
    let сведения = null
    try {
      сведения = statSync(join(корень, очищен))
    } catch {
      return null
    }
    if (сведения.isDirectory()) {
      файлы = readdirSync(join(корень, очищен))
        .filter((имя) => ИСХОДНИКИ.has(extname(имя)))
        .map((имя) => `${очищен.replace(/\/$/u, "")}/${имя}`)
        .filter((п) => {
          try {
            return statSync(join(корень, п)).isFile()
          } catch {
            return false
          }
        })
    } else {
      файлы = [очищен]
    }
  }
  if (файлы.length === 0) return null
  let всего = 0
  for (const ф of файлы) {
    try {
      всего += строкФайла(join(корень, ф))
    } catch {
      return null
    }
  }
  return всего
}

/* ── разбор прозы ───────────────────────────────────────────────────────── */

/** Обход дерева: только `.md` — проза о дереве живёт там. */
function прозаДерева(каталог, собранное = []) {
  for (const имя of readdirSync(каталог)) {
    if (ПРОПУСК.has(имя)) continue
    const путь = join(каталог, имя)
    let сведения
    try {
      сведения = statSync(путь)
    } catch {
      continue
    }
    if (сведения.isDirectory()) прозаДерева(путь, собранное)
    else if (extname(путь) === ".md") собранное.push(путь)
  }
  return собранное
}

/**
 * Абзацы файла: подряд идущие непустые строки — один абзац.
 *
 * Иначе утверждение, перенесённое на вторую строку, не прочитается целиком, а
 * переносят их постоянно: в `flang/self/SPEC.md` число и путь одного и того же
 * утверждения про размер `flang/src/*.mjs` стоят на разных строках.
 */
export function абзацы(текст) {
  const строки = текст.split("\n")
  const из = []
  let текущий = null
  let вКоде = false
  for (let i = 0; i < строки.length; i++) {
    const с = строки[i]
    if (/^\s*```/u.test(с)) {
      вКоде = !вКоде
      текущий = null
      continue
    }
    if (вКоде || с.trim() === "") {
      текущий = null
      continue
    }
    if (текущий === null) {
      текущий = { строка: i + 1, текст: с.trim() }
      из.push(текущий)
    } else {
      текущий.текст += " " + с.trim()
    }
  }
  return из
}

/**
 * Слово «строка» — на обоих языках дерева.
 *
 * Английский README и английские README инструментов — такая же проза, и
 * стареет она так же. Сторож, знающий одно слово из двух, был бы зелёным на
 * половине дерева от незнания, а не от чистоты.
 */
const СЛОВО_СТРОК = "(?:строк(?:а|и|ах|ами|е|ой|у)?|lines?)"

/** Предлог перед путём: «строк В `x`» и «lines IN `x`». */
const ПРЕДЛОГ = "(?:в|in|of)\\s+"

/**
 * Утверждения «N строк про ПУТЬ» из одного абзаца.
 *
 * Две записи и только они. Зазор между путём и числом ограничен: без предела
 * число приписалось бы пути из соседнего предложения, и сторож назвал бы не то
 * место — ровно та беда, из-за которой сторож перестают читать.
 */
export function строкиПроПуть(абзац) {
  const найдено = []
  const добавить = (путь, сырое, место) => {
    const н = число(сырое)
    if (н === null) return
    if (ПРИБЛИЖЕНИЕ.test(абзац.текст.slice(Math.max(0, место - 12), место))) return
    if (!похожеНаПуть(путь)) return
    найдено.push({ путь, сказано: н })
  }
  /* Путь слева: «`flang/core/` — 4590 строк», «`src/*.ts`, 3155 строк». */
  for (const м of абзац.текст.matchAll(
    new RegExp(`[«\`]([^»\`\\n]{1,60})[»\`][^«\`.;!?]{0,24}?(\\d[\\d\\s\\u00a0]*)\\s*${СЛОВО_СТРОК}(?![\\p{L}])`, "giu"),
  )) {
    добавить(м[1].trim(), м[2], м.index + м[0].indexOf(м[2]))
  }
  /* Число слева: «24379 строк в `flang/src/*.mjs`», «1294 строк `src/conc.mjs`».
     Между словом и путём допускается только предлог «в» — и это не придирка, а
     единственное, что отделяет размер файла от куска внутри него: «плюс 269
     строк СКЛЕЙКИ в `js.mjs`» говорит не о размере `js.mjs`, и приписать ему
     269 значило бы завести сторожа, который краснеет на верной фразе. */
  for (const м of абзац.текст.matchAll(
    new RegExp(`(\\d[\\d\\s\\u00a0]*)\\s*${СЛОВО_СТРОК}\\s+(?:${ПРЕДЛОГ})?[«\`]([^»\`\\n]{1,60})[»\`]`, "giu"),
  )) {
    добавить(м[2].trim(), м[1], м.index)
  }
  return найдено
}

/**
 * Строки таблиц, у которых столбец назван «Строк», а первая клетка — путь.
 *
 * Разделительная строка (`|---|`) отделяет заголовок от тела; без неё это не
 * таблица, а просто палки.
 */
export function строкиТаблиц(текст) {
  const строки = текст.split("\n")
  const найдено = []
  let столбец = -1
  let вКоде = false
  for (let i = 0; i < строки.length; i++) {
    const с = строки[i]
    if (/^\s*```/u.test(с)) {
      вКоде = !вКоде
      continue
    }
    if (вКоде) continue
    if (!с.trim().startsWith("|")) {
      столбец = -1
      continue
    }
    const клетки = с.trim().replace(/^\||\|$/gu, "").split("|").map((к) => к.trim())
    if (/^[\s|:-]+$/u.test(с)) continue
    if (столбец === -1) {
      const k = клетки.findIndex((к) => new RegExp(`^${СЛОВО_СТРОК}$`, "iu").test(к.replace(/\*/gu, "")))
      /* Заголовок засчитывается только если следующая строка — разделитель. */
      if (k >= 0 && /^[\s|:-]+$/u.test(строки[i + 1] ?? "")) столбец = k
      continue
    }
    if (клетки.length <= столбец) continue
    const путь = (клетки[0].match(/^[«`]([^»`]+)[»`]/u) ?? [])[1]
    if (путь === undefined || !похожеНаПуть(путь.trim())) continue
    const клетка = клетки[столбец]
    if (ПРИБЛИЖЕНИЕ.test(клетка.replace(/[\d\s\u00a0]+$/u, ""))) continue
    const н = число(клетка.replace(/\*/gu, ""))
    if (н === null) continue
    найдено.push({ строка: i + 1, путь: путь.trim(), сказано: н })
  }
  return найдено
}

/* ── измеритель ведомости ──────────────────────────────────────────────── */

/**
 * Числа ведомости, названные словами прозы.
 *
 * Список закрытый: каждая запись обязана назвать, КАКОЕ поле свода имеется в
 * виду. Открытый поиск «N утверждений» ловил бы предложения про утверждения
 * вообще, а свод — про утверждения в корпусе, и это разные числа.
 */
export const ВЕДОМОСТЬ = [
  { образец: /высказано\s+(\d+)\s+утвержд/iu, поле: "claims.total", что: "утверждений высказано в корпусе" },
  { образец: /(\d+)\s+доказан[ыо]\s+ядром/iu, поле: "claims.proved", что: "доказано ядром" },
  { образец: /(\d+)\s+ид(?:ёт|ут)\s+сеткой/iu, поле: "claims.grid", что: "идёт сеткой примеров" },
  { образец: /(\d+)\s+объявлено\s+и\s+не\s+доказано/iu, поле: "claims.declared", что: "объявлено, не доказано" },
]

/** Значение по пути вида `claims.total`. */
function поПути(объект, путь) {
  return путь.split(".").reduce((о, к) => (о === undefined || о === null ? undefined : о[к]), объект)
}

/* ── проверка ──────────────────────────────────────────────────────────── */

/**
 * Собрать расхождения по дереву.
 *
 * `свод` — итог `proof-ledger.mjs`; когда его не передали, правило ведомости
 * молчит (сторож не обязан считать корпус, чтобы проверить размеры файлов).
 */
export function проверить(корень = КОРЕНЬ, свод = null) {
  const расхождения = []
  for (const путьФайла of прозаДерева(корень)) {
    const отн = relative(корень, путьФайла).split("\\").join("/")
    let текст
    try {
      текст = readFileSync(путьФайла, "utf8")
    } catch {
      continue
    }

    for (const абзац of абзацы(текст)) {
      if (НАДГРОБИЯ.some((р) => р.test(абзац.текст))) continue
      for (const { путь, сказано } of строкиПроПуть(абзац)) {
        const измерено = строкПод(путь, корень, основыДля(отн))
        if (измерено === null) continue
        if (измерено !== сказано)
          расхождения.push({ файл: отн, строка: абзац.строка, род: "строк", про: путь, сказано, измерено })
      }
      if (свод !== null) {
        for (const правило of ВЕДОМОСТЬ) {
          const м = абзац.текст.match(правило.образец)
          if (м === null) continue
          const измерено = поПути(свод, правило.поле)
          if (измерено === undefined) continue
          if (Number(м[1]) !== измерено)
            расхождения.push({
              файл: отн,
              строка: абзац.строка,
              род: правило.что,
              про: правило.поле,
              сказано: Number(м[1]),
              измерено,
            })
        }
      }
    }

    for (const { строка, путь, сказано } of строкиТаблиц(текст)) {
      const измерено = строкПод(путь, корень, основыДля(отн))
      if (измерено === null) continue
      if (измерено !== сказано)
        расхождения.push({ файл: отн, строка, род: "строк (таблица)", про: путь, сказано, измерено })
    }
  }
  return расхождения
}

/* ── запуск из командной строки ─────────────────────────────────────────── */
if (import.meta.url === `file://${process.argv[1]}`) {
  const { сводКорпуса } = await import("./proof-ledger.mjs")
  const свод = (await сводКорпуса()).итог
  const расхождения = проверить(КОРЕНЬ, свод)
  if (расхождения.length === 0) {
    console.log("сторож чисел: чисто — каждое проверяемое число прозы сошлось с измерителем")
    process.exit(0)
  }
  console.error(`сторож чисел: ${расхождения.length} числ(о/а) прозы разошлись с деревом\n`)
  for (const р of расхождения) {
    console.error(`${р.файл}:${р.строка}  ${р.род} про ${р.про}`)
    console.error(`  сказано:  ${р.сказано}`)
    console.error(`  измерено: ${р.измерено}`)
    console.error("")
  }
  console.error(
    "Правьте прозу, а не сторожа: измеритель — это дерево, а число в предложении — " +
      "пересказ, который не исполняется и потому не ломается сам.",
  )
  process.exit(1)
}
