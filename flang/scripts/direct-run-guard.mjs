/**
 * СТОРОЖ ПРОТИВ ВОЗВРАТА: «меня запустили напрямую?» пишется одним словом.
 *
 * ── Порода, ради которой сторож заведён ────────────────────────────────────
 * Всякий скрипт дерева кончается строкой «если меня ЗАПУСТИЛИ — работать; если
 * меня ВВЕЗЛИ модулем — молчать». Вопрос выглядит пустяковым, и ровно поэтому
 * его написали ПЯТНАДЦАТЬ раз ШЕСТЬЮ способами. Верен ровно один, и он уже
 * лежал в дереве дважды, с объяснением в комментарии, — его просто не прочли.
 *
 * Таблица истинности шести написаний (замер 31 августа 2026, это дерево):
 *
 *   способ                                              кириллица  ссылка  мест
 *   А  import.meta.url === `file://${process.argv[1]}`      НЕМ      НЕМ     5
 *   Б  process.argv[1] === fileURLToPath(import.meta.url)   цел      НЕМ     4
 *   В  resolve(argv[1]) === resolve(fileURLToPath(url))     цел      НЕМ     2
 *   Г  import.meta.url === pathToFileURL(argv[1]).href      цел      НЕМ     1
 *   Д  pathToFileURL(resolve(argv[1])).href === url         цел      НЕМ     1
 *   Е  realpathSync(fileURLToPath(url)) === realpath(a1)    цел      цел     2
 *
 * «НЕМ» — не просто «неверно»: тело не исполняется, скрипт выходит КОДОМ 0, не
 * напечатав ни строки. Молчащий сторож неотличим от чистого дерева, и именно
 * поэтому породу нельзя закрывать по одному месту — только запретом писать
 * вопрос иначе.
 *
 * Почему немеет А: `import.meta.url` — адрес, он кодирует процентами всё, что
 * не входит в ASCII-набор адреса (кириллическая буква → `%D0%A7`, пробел →
 * `%20`); `process.argv[1]` — путь, он не кодирует ничего.
 * Почему немеют Б…Д: Node разрешает символьные ссылки для `import.meta.url` и
 * НЕ разрешает для `process.argv[1]`. npm ставит команды и пакеты из каталога
 * именно ссылками.
 *
 * На раннере GitHub путь латинский, без пробелов и без ссылок — там не видно
 * НИЧЕГО из этого. У человека видно всегда и молча.
 *
 * ── Что здесь считается бедой ──────────────────────────────────────────────
 * Беда — ЛЮБОЕ упоминание `process.argv[1]` в коде вне единственной функции
 * `запущенНапрямую`, а также `require.main` и `import.meta.main` где угодно.
 *
 * Правило нарочно шире вопроса. Сторож, ловивший бы «argv[1] рядом с
 * import.meta.url», пропускал бы седьмое написание — то, где свой адрес сперва
 * кладут в переменную, а сравнивают строкой ниже. Породу закрывает не список
 * пяти известных ошибок, а запрет на само сырьё: `process.argv[1]` — это
 * ВСЕГДА «кем меня назвали в строке запуска», и другого применения у него не
 * бывает (первый довод человека лежит в `argv[2]`). Значит и разрешать его
 * незачем нигде, кроме одного места, где на вопрос отвечают правильно.
 *
 * `import.meta.main` тоже беда, хотя выглядит как верный ответ: в Node 20,
 * который объявлен в `engines`, его нет вовсе — выражение молча `undefined`,
 * то есть немота той же породы.
 *
 * Беда называется файлом и НОМЕРОМ СТРОКИ, код возврата 1. Молча сторож не
 * выходит никогда: на чистом дереве он печатает, сколько мест нашёл.
 *
 * ── Две законные копии образца, и почему они законны ───────────────────────
 * Образец живёт в `flang/scripts/direct-run.mjs`. Ввезти его может не всякий:
 * каталога `flang/scripts` НЕТ в разделе `files` пакета (`package.json`), и
 * `import` из установленного пакета упал бы с ERR_MODULE_NOT_FOUND. Файлы,
 * которые уезжают в пакет, пишут ту же функцию у себя:
 *
 *   packaging/postinstall.mjs        — сборка компилятора при установке;
 *   flang/src/emit/js/flang_cli.js   — прогонщик, копируемый рядом с
 *                                      напечатанной программой.
 *
 * Это не список исключений, который разойдётся с деревом: сторож САМ смотрит в
 * `package.json`, кто уезжает в пакет, и сам сличает тело копии с образцом
 * слово в слово. Копия, разошедшаяся с образцом, — беда. Копия там, где можно
 * было ввезти, — беда. Ввоз `direct-run.mjs` в файл, уезжающий в пакет, —
 * беда, потому что он сломал бы установку.
 *
 * ── Как проверить самого сторожа ───────────────────────────────────────────
 *   node flang/scripts/direct-run-guard.mjs --порча
 * Прогоняет все шесть написаний через тот же разбор, которым идёт проверка, и
 * требует: пять названы, шестое пропущено. Плюс подкладывает старое написание в
 * настоящий файл во временном дереве и требует, чтобы сторож назвал его
 * поимённо. Сузьте поиск — и подлог перестанет находиться, а `--порча` покраснеет.
 * Сторож, разучившийся краснеть, зеленеет ровно как чистое дерево.
 *
 * Запуск:
 *   node flang/scripts/direct-run-guard.mjs          проверить дерево
 *   node flang/scripts/direct-run-guard.mjs --порча  проверить самого сторожа
 */
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { запущенНапрямую } from "./direct-run.mjs"

export const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
export const ОБРАЗЕЦ = "flang/scripts/direct-run.mjs"

/* Расширения, где вопрос вообще может стоять. */
const РАСШИРЕНИЯ = new Set([".mjs", ".js", ".cjs"])

/* Каталоги, в которые не ходим: чужое, порождённое и история. */
const МИМО = new Set([".git", "node_modules", "dvoichnyy", ".cache", "target"])

/* ── 1. Код без комментариев и строк ───────────────────────────────────────
 *
 * Оба слова вопроса встречаются в ПРОЗЕ этого дерева десятки раз — в шапках,
 * которые объясняют, как писать не надо (в том числе в шапке над этой строкой).
 * Сторож, читающий текст целиком, кричал бы на объяснение и молчал бы о коде,
 * если бы кто-то спрятал вопрос в строку. Поэтому текст сперва раскрашивается:
 * всё, что не код, заменяется пробелами — длина сохраняется, и смещение
 * по-прежнему переводится в номер строки.
 *
 * Литерал регулярного выражения разбирается по обычному признаку: `/` начинает
 * его, только если перед ним (не считая пробелов) стоит знак, после которого
 * значения быть не может. Иначе `/` — деление.
 */
export function толькоКод(текст) {
  const код = new Array(текст.length)
  const бланк = (j) => {
    код[j] = текст[j] === "\n" ? "\n" : " "
  }
  /* Знак, после которого `/` начинает образец, а не деление. */
  const переднийКрай = "(,=:[!&|?{};+-*%~^<>"
  const стек = [] /* сколько фигурных скобок было открыто снаружи подстановки */
  let режим = "код"
  let кавычка = ""
  let скобки = 0
  let предыдущий = ""
  let i = 0
  while (i < текст.length) {
    const з = текст[i]
    if (режим === "строка" || режим === "шаблон") {
      if (з === "\\") {
        бланк(i)
        if (i + 1 < текст.length) бланк(i + 1)
        i += 2
        continue
      }
      if (режим === "шаблон" && з === "$" && текст[i + 1] === "{") {
        бланк(i)
        бланк(i + 1)
        стек.push(скобки)
        скобки = 0
        режим = "код"
        предыдущий = ""
        i += 2
        continue
      }
      бланк(i)
      if ((режим === "строка" && з === кавычка) || (режим === "шаблон" && з === "`")) {
        режим = "код"
        предыдущий = "«строка»"
      }
      i += 1
      continue
    }
    if (з === "/" && текст[i + 1] === "/") {
      let к = текст.indexOf("\n", i)
      if (к === -1) к = текст.length
      for (let j = i; j < к; j += 1) бланк(j)
      i = к
      continue
    }
    if (з === "/" && текст[i + 1] === "*") {
      let к = текст.indexOf("*/", i + 2)
      к = к === -1 ? текст.length : к + 2
      for (let j = i; j < к; j += 1) бланк(j)
      i = к
      continue
    }
    if (з === '"' || з === "'") {
      бланк(i)
      режим = "строка"
      кавычка = з
      i += 1
      continue
    }
    if (з === "`") {
      бланк(i)
      режим = "шаблон"
      i += 1
      continue
    }
    if (з === "/" && (предыдущий === "" || переднийКрай.includes(предыдущий))) {
      let j = i + 1
      let вКлассе = false
      while (j < текст.length) {
        if (текст[j] === "\\") {
          j += 2
          continue
        }
        if (текст[j] === "[") вКлассе = true
        else if (текст[j] === "]") вКлассе = false
        else if (текст[j] === "\n") break
        else if (текст[j] === "/" && !вКлассе) break
        j += 1
      }
      const к = Math.min(j + 1, текст.length)
      for (let n = i; n < к; n += 1) бланк(n)
      i = к
      предыдущий = "«образец»"
      continue
    }
    if (з === "{") скобки += 1
    else if (з === "}") {
      if (скобки === 0 && стек.length > 0) {
        бланк(i)
        скобки = стек.pop()
        режим = "шаблон"
        предыдущий = "«строка»"
        i += 1
        continue
      }
      скобки -= 1
    }
    код[i] = з
    if (!/\s/.test(з)) предыдущий = з
    i += 1
  }
  return код.join("")
}

const номерСтроки = (текст, смещение) => текст.slice(0, смещение).split("\n").length

/* ── 2. Где берут путь запуска ─────────────────────────────────────────────
 *
 * Ищется САМО СЫРЬЁ, а не пять известных написаний поверх него: `process.argv[1]`
 * (в скобках или через `.at(1)`), `require.main` и `import.meta.main`. Рядом ли
 * стоит `import.meta.url` — влияет только на ТЕКСТ беды, а не на то, беда ли это.
 *
 * ОКНО — насколько далеко может стоять вторая сторона вопроса, чтобы беду
 * назвать «вопрос задан не тем словом», а не «путь запуска взят сырьём».
 */
const ОКНО = 260
const СВОЙ_АДРЕС = /import\.meta\.(url|filename|dirname)/
const СЫРЬЁ = /process\.argv\s*(\[\s*1\s*\]|\.at\(\s*1\s*\))|require\.main|import\.meta\.main/g

/*
 * ЗАКОННЫЕ МЕСТА, ГДЕ СЫРЬЁ НУЖНО НЕ РАДИ ЭТОГО ВОПРОСА, — ЗАКРЫТЫЙ СПИСОК.
 *
 * Сейчас он пуст, и это не заготовка на будущее, а измеренное состояние: во
 * всех 56 файлах дерева `process.argv[1]` встречается только внутри ответа на
 * вопрос о прямом запуске. Список закрытый: неизвестное место роняет сторожа,
 * а не проходит молча, — то же правило, что у прочих списков имён дерева.
 */
export const ЗАКОННЫЕ = new Set([])

/**
 * Все места файла, где берут путь запуска.
 * @returns {{строка:number, смещение:number, рядомАдрес:boolean, кусок:string}[]}
 */
export function вопросы(текст) {
  const код = толькоКод(текст)
  const найдено = []
  СЫРЬЁ.lastIndex = 0
  let м
  while ((м = СЫРЬЁ.exec(код)) !== null) {
    const i = м.index
    const окно = код.slice(Math.max(0, i - ОКНО), i + ОКНО)
    найдено.push({
      строка: номерСтроки(код, i),
      смещение: i,
      рядомАдрес: СВОЙ_АДРЕС.test(окно),
      кусок: текст.slice(i, i + 90).split("\n").slice(0, 2).join(" ").trim(),
    })
  }
  return найдено
}

/* ── 3. Тело образца и его копий ───────────────────────────────────────────
 *
 * Тело берётся счётом скобок по КОДУ (комментарии и строки уже стёрты), и
 * сравнивается со свёрнутыми пробелами. Значение имеет написанное, а не то,
 * как его расставил форматтер.
 */
const ОБЪЯВЛЕНИЕ = /function\s+запущенНапрямую\s*\(/g

export function телаФункции(текст) {
  const код = толькоКод(текст)
  const тела = []
  ОБЪЯВЛЕНИЕ.lastIndex = 0
  let м
  while ((м = ОБЪЯВЛЕНИЕ.exec(код)) !== null) {
    const начало = код.indexOf("{", м.index)
    if (начало === -1) continue
    let глубина = 0
    let к = начало
    for (; к < код.length; к += 1) {
      if (код[к] === "{") глубина += 1
      else if (код[к] === "}") {
        глубина -= 1
        if (глубина === 0) break
      }
    }
    тела.push({
      от: м.index,
      до: Math.min(к + 1, код.length),
      строка: номерСтроки(код, м.index),
      тело: код.slice(начало, Math.min(к + 1, код.length)).replace(/\s+/g, " ").trim(),
    })
  }
  return тела
}

/** Тело образца — то, с чем сличаются все копии. */
export function эталон(корень = КОРЕНЬ) {
  const тела = телаФункции(readFileSync(join(корень, ОБРАЗЕЦ), "utf8"))
  if (тела.length !== 1) {
    throw new Error(`в ${ОБРАЗЕЦ} ожидалась ровно одна функция «запущенНапрямую», найдено ${тела.length}`)
  }
  return тела[0].тело
}

/* ── 4. Кто уезжает в пакет ────────────────────────────────────────────────
 *
 * Разбор раздела `files` НАМЕРЕННО узкий, ровно как у `bin` в
 * `scripts/commands-via-symlink.flang`: там плоский список путей и каталогов
 * плюс два отрицания, начинающихся с восклицательного знака. Полного движка масок здесь нет и не нужно —
 * второе место, где живёт формат раскладки пакета, разошлось бы с первым.
 * Список читается из package.json, а не переписывается сюда руками: список
 * руками пережил бы переезд каталога молча.
 */
export function уезжаетВПакет(путь, корень = КОРЕНЬ) {
  const настройка = JSON.parse(readFileSync(join(корень, "package.json"), "utf8"))
  const записи = настройка.files ?? []
  const команды = Object.values(настройка.bin ?? {}).map((п) => п.replace(/^\.\//, ""))
  let внутри = команды.includes(путь)
  for (const запись of записи) {
    if (запись.startsWith("!")) continue
    const чистая = запись.replace(/^\.\//, "").replace(/\/$/, "")
    if (путь === чистая || путь.startsWith(`${чистая}/`)) внутри = true
  }
  for (const запись of записи) {
    if (!запись.startsWith("!")) continue
    const маска = запись.slice(1)
    if (маска === "**/test" && /(^|\/)test\//.test(путь)) внутри = false
    if (маска === "**/*.test.mjs" && путь.endsWith(".test.mjs")) внутри = false
  }
  return внутри
}

/* ── 5. Обход дерева ───────────────────────────────────────────────────────*/
export function файлы(корень = КОРЕНЬ) {
  const собрано = []
  const обойти = (каталог) => {
    let записи
    try {
      записи = readdirSync(каталог, { withFileTypes: true })
    } catch {
      return
    }
    for (const запись of записи) {
      const путь = join(каталог, запись.name)
      if (запись.isDirectory()) {
        if (МИМО.has(запись.name)) continue
        обойти(путь)
        continue
      }
      if (!запись.isFile()) continue
      const точка = запись.name.lastIndexOf(".")
      if (точка === -1 || !РАСШИРЕНИЯ.has(запись.name.slice(точка))) continue
      собрано.push(relative(корень, путь).split("\\").join("/"))
    }
  }
  обойти(корень)
  return собрано.sort()
}

/* ── 6. Проверка ───────────────────────────────────────────────────────────*/
/**
 * @returns {{беды:string[], вопросов:number, копий:number, файлов:number}}
 */
export function проверить(корень = КОРЕНЬ) {
  const беды = []
  const эт = эталон(корень)
  let вопросов = 0
  let копий = 0
  const список = файлы(корень)
  for (const путь of список) {
    let текст
    try {
      текст = readFileSync(join(корень, путь), "utf8")
    } catch {
      continue
    }
    if (!текст.includes("argv") && !текст.includes("import.meta") && !текст.includes("require.main")) continue

    const тела = телаФункции(текст)
    const свой = путь === ОБРАЗЕЦ
    const вПакет = уезжаетВПакет(путь, корень)

    for (const тело of тела) {
      копий += 1
      if (тело.тело !== эт) {
        беды.push(
          `${путь}:${тело.строка}: копия образца разошлась с ${ОБРАЗЕЦ} — ` +
            "сличается слово в слово, чинится списыванием оттуда",
        )
      }
      if (!свой && !вПакет) {
        беды.push(
          `${путь}:${тело.строка}: своя копия там, где можно ввезти образец — ` +
            `этот файл в пакет не уезжает, пишите import { запущенНапрямую } from "…/${ОБРАЗЕЦ}"`,
        )
      }
    }

    for (const вопрос of вопросы(текст)) {
      вопросов += 1
      const внутриФункции = тела.some((т) => вопрос.смещение >= т.от && вопрос.смещение < т.до)
      if (внутриФункции) continue
      if (ЗАКОННЫЕ.has(`${путь}:${вопрос.строка}`)) continue
      беды.push(
        вопрос.рядомАдрес
          ? `${путь}:${вопрос.строка}: вопрос «запущен ли я напрямую» задан не тем словом: ${вопрос.кусок}`
          : `${путь}:${вопрос.строка}: путь запуска взят сырьём — ${вопрос.кусок}`,
      )
    }

    const зовёт = /запущенНапрямую\s*\(/.test(толькоКод(текст))
    const ввозит = /from\s+["'][^"']*direct-run\.mjs["']/.test(текст)
    if (зовёт && !ввозит && тела.length === 0) {
      беды.push(`${путь}: зовёт «запущенНапрямую», но ни ввоза образца, ни своей копии в файле нет`)
    }
    if (ввозит && вПакет) {
      беды.push(
        `${путь}: уезжает в пакет и ввозит ${ОБРАЗЕЦ}, которого в пакете нет — ` +
          "установка упала бы с ERR_MODULE_NOT_FOUND; напишите копию у себя",
      )
    }
  }
  return { беды, вопросов, копий, файлов: список.length }
}

/* ── 7. Порча: сторож обязан краснеть ──────────────────────────────────────
 *
 * Шесть написаний из таблицы истинности прогоняются через ТОТ ЖЕ разбор,
 * которым идёт проверка. Пять обязаны быть названы, шестое — пропущено.
 * Сверх таблицы старое написание подкладывается в настоящий файл во временном
 * дереве: таблица проверяет разбор, подкладка — обход, чтение и то, что беда
 * названа именем файла и номером строки.
 */
export const ТАБЛИЦА = [
  ["А", "if (import.meta.url === `file://${process.argv[1]}`) работать()", true],
  ["Б", "if (process.argv[1] === fileURLToPath(import.meta.url)) работать()", true],
  ["В", "if (process.argv[1] !== undefined\n  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) работать()", true],
  ["Г", "if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) работать()", true],
  ["Д", "if (isMainThread && typeof process.argv[1] === \"string\"\n  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) работать()", true],
  ["Е", "if (запущенНапрямую(import.meta.url)) работать()", false],
]

function порча(корень) {
  const беды = []

  for (const [имя, написание, ждём] of ТАБЛИЦА) {
    const нашли = вопросы(написание).length > 0
    if (нашли !== ждём) {
      беды.push(
        `таблица истинности, способ ${имя}: сторож ${нашли ? "назвал" : "пропустил"}, ` +
          `а должен был ${ждём ? "назвать" : "пропустить"} — поиск сузили`,
      )
    }
  }

  /* То же написание, спрятанное в комментарий и в строку, названо быть НЕ
     должно: иначе сторож кричал бы на объяснения в шапках и на этот файл. */
  const вПрозе = `/* if (import.meta.url === \`file://\${process.argv[1]}\`) */\nconst с = "process.argv[1] === fileURLToPath(import.meta.url)"\n`
  if (вопросы(вПрозе).length !== 0) {
    беды.push("сторож кричит на объяснение в комментарии и на строку — он читает не код")
  }

  /* Подкладка в настоящее дерево-однодневку. */
  const корзина = mkdtempSync(join(process.env.FLANG_TMP ?? tmpdir(), "direct-run-porcha-"))
  try {
    writeFileSync(join(корзина, "package.json"), readFileSync(join(корень, "package.json")))
    const куда = join(корзина, "flang", "scripts")
    mkdirSync(куда, { recursive: true })
    writeFileSync(join(куда, "direct-run.mjs"), readFileSync(join(корень, ОБРАЗЕЦ)))
    writeFileSync(
      join(корзина, "podlog.mjs"),
      '/* подложено сторожем, см. --порча */\nimport { fileURLToPath } from "node:url"\n\n' +
        "if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(1)\n",
    )
    const итог = проверить(корзина)
    const названо = итог.беды.filter((б) => б.startsWith("podlog.mjs:"))
    if (названо.length === 0) {
      беды.push("подложенное старое написание НЕ названо: обход или чтение сторожа сломаны")
    } else if (!/podlog\.mjs:4:/.test(названо[0])) {
      беды.push(`подлог назван без верного номера строки: ${названо[0]}`)
    }
  } finally {
    rmSync(корзина, { recursive: true, force: true })
  }

  if (беды.length > 0) {
    console.error("СТОРОЖ ПРЯМОГО ЗАПУСКА РАЗУЧИЛСЯ КРАСНЕТЬ:")
    for (const б of беды) console.error(`  ✗ ${б}`)
    return 1
  }
  console.log(
    `порча: сторож краснеет на всех пяти неверных написаниях, молчит на верном, ` +
      "не кричит на прозу и называет подлог файлом и строкой",
  )
  return 0
}

/* ── 8. Запуск ─────────────────────────────────────────────────────────────*/
function главная(аргументы) {
  const КЛЮЧИ = new Set(["--порча"])
  const чужие = аргументы.filter((арг) => !КЛЮЧИ.has(арг))
  if (чужие.length > 0) {
    console.error(`сторож прямого запуска: неизвестный ключ ${чужие.join(" ")}`)
    console.error("  node flang/scripts/direct-run-guard.mjs          проверить дерево")
    console.error("  node flang/scripts/direct-run-guard.mjs --порча  проверить самого сторожа")
    return 2
  }
  if (аргументы.includes("--порча")) return порча(КОРЕНЬ)

  const итог = проверить(КОРЕНЬ)
  if (итог.беды.length > 0) {
    console.error("Вопрос «запущен ли я напрямую» задан не одним словом:")
    for (const беда of итог.беды) console.error(`  ✗ ${беда}`)
    console.error("")
    console.error(`Верное написание одно: запущенНапрямую(import.meta.url) из ${ОБРАЗЕЦ}.`)
    console.error("Остальные немеют на кириллице, пробеле или символьной ссылке — кодом 0 и без строк.")
    return 1
  }
  console.log(
    `сторож прямого запуска: чисто — ${итог.вопросов} место(а) с путём запуска в ${итог.файлов} файлах, ` +
      `все заданы одним словом; копий образца ${итог.копий}, все сошлись с ${ОБРАЗЕЦ}`,
  )
  return 0
}

if (запущенНапрямую(import.meta.url)) {
  process.exit(главная(process.argv.slice(2)))
}
