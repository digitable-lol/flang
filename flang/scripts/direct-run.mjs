/*
 * «Меня запустили напрямую?» — один ответ на всё дерево.
 *
 * Каждый сторож-скрипт кончается строкой «если меня запустили напрямую —
 * работать; если меня ввезли модулем — молчать». Вопрос выглядит пустяковым, и
 * ровно поэтому его двенадцать раз написали по-разному, а пять раз — неверно:
 *
 *     if (import.meta.url === `file://${process.argv[1]}`)   // НЕВЕРНО
 *
 * `import.meta.url` — адрес, и всё, что не входит в ASCII-набор адреса, он
 * кодирует процентами: кириллическая буква становится тремя-шестью знаками
 * «%D1%81», пробел — «%20». `process.argv[1]` — путь, он не кодирует ничего.
 * На пути `/srv/tmp/Ч82/clon` две стороны выглядят так:
 *
 *     file:///srv/tmp/%D0%A782/clon/flang/scripts/claim-guard.mjs
 *     file:///srv/tmp/Ч82/clon/flang/scripts/claim-guard.mjs
 *
 * Равенство ложно, тело не исполняется, и сторож ВЫХОДИТ КОДОМ 0, не напечатав
 * ни строки. Он молчит не там, где не знает, а там, где знает, — то есть врёт.
 * На раннере GitHub путь латинский и без пробелов, поэтому в сборке этого не
 * видно никогда; у человека видно всегда и молча.
 *
 * Здесь сравниваются РАЗРЕШЁННЫЕ пути, а не строки:
 *   • `fileURLToPath` снимает процентное кодирование — обе стороны становятся
 *     путями, и кириллица с пробелом перестают что-либо решать;
 *   • `realpathSync` с обеих сторон снимает символьные ссылки. Это не запас:
 *     npm ставит команды ссылками, и путь ссылки с путём файла не совпадает.
 *     Node разрешает ссылки для `import.meta.url`, но НЕ для `process.argv[1]`,
 *     так что сравнение строк тут ломается вторым, независимым способом.
 *
 * Отказ (`process.argv[1]` нет — `node --eval`; путь исчез между запуском и
 * вопросом) отвечает «нет»: не запускать чужую работу — безопасный исход, а
 * запустить сторожа, которого никто не звал, — нет.
 */

import { realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"

/**
 * @param {string} адресМодуля — всегда `import.meta.url` вызывающего файла.
 * @returns {boolean} правда, если этот самый файл назван в командной строке.
 */
export function запущенНапрямую(адресМодуля) {
  const запуск = process.argv[1]
  if (запуск === undefined || запуск === "") return false
  try {
    return realpathSync(fileURLToPath(адресМодуля)) === realpathSync(запуск)
  } catch {
    return false
  }
}

export default запущенНапрямую
