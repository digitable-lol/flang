const работник = async () => {
  for (;;) {
    const дело = очередь.shift()
    if (!дело) return
    const о = await запуск(["check", дело.файл, "--proof", "--json"])
    let вердикт
    if (о.код === 0) {
      const i = о.вывод.indexOf("{")
      try {
        const к = (JSON.parse(о.вывод.slice(i)).claims ?? []).find((c) => c.name === "утверждение")
        вердикт = к ? к.verdict : "нет в отчёте"
      } catch { вердикт = "отчёт не разобран" }
    } else {
      дело.отказ = (о.ошибки || о.вывод).split("\n")[0].slice(0, 200)
      /* Отвергнутая теорема — это РАБОТА ядра, а не сор порождения: написанное
         доказательство, которое не сходится, ядро обязано отвергнуть. Сваливать
         это в одну кучу с ошибкой разбора значило бы прятать главный ответ. */
      вердикт = /FLANG_PROOF/u.test(дело.отказ) ? "доказательство отвергнуто" : "отказ"
    }
    /* Спрашивается вычислением КАЖДОЕ утверждение, а не только доказанное.
       Иначе у зелёного ответа не было бы знаменателя: «ноль расхождений» на
       непрогнанных входах — это не ноль, это молчание. */
    /* Нарушение читается ПОИМЁННО: `нарушено свойство «утверждение»`, а не любой
       FLANG_PROPERTY. Иначе сработавшее постусловие соседней функции засчиталось
       бы этому утверждению, и «дыра» оказалась бы чужой. */
    const нарушено = []
    const чужое = []
    if (вердикт !== "отказ" && вердикт !== "доказательство отвергнуто") {
      for (const п of дело.пробы) {
        const р = await запуск(["run", дело.файл, "--function", `«${п.имя}»`, "--args", "{}"])
        const текст = р.вывод + р.ошибки
        if (текст.includes("нарушено свойство «утверждение»")) нарушено.push(п.метка)
        else if (текст.includes("FLANG_PROPERTY")) чужое.push(п.метка)
      }
    }
    итоги.push({ ...дело, вердикт, нарушено, чужое })
  }
}

