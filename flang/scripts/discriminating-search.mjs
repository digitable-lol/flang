/* ── ВТОРОЙ ВОПРОС: А ЧТО ИМЕННО ДОКАЗАНО ───────────────────────────────────
 *
 * «Доказано» и «сказано о предмете» — разные вещи. Утверждение, которое
 * остаётся доказанным ПОСЛЕ ПОДМЕНЫ ТЕЛА ЗАГЛУШКОЙ ТОЙ ЖЕ ПОДПИСИ, верно и про
 * программу, которая не делает ничего: оно про подпись, а не про функцию.
 * Тавтология — второй вид пустого: спека, переписанная с тела знак в знак
 * («результат равен х» при теле «х»), принимается даром и не значит ничего.
 *
 * Мера здесь честная и с третьим ответом: подмена может СЛОМАТЬ файл (у
 * семейства с теоремой заглушка сносит шаг индукции), и тогда ответ —
 * «не установлено», а не «содержательно».
 *
 * И ЧТО ЭТА МЕРА ГОВОРИТ, А ЧТО НЕТ. Она говорит ровно одно: утверждение НЕ
 * ОТЛИЧАЕТ эту функцию от программы той же подписи, которая не делает ничего.
 * «Бессмысленно» — это не то же самое: «(длина результат) не больше (длина л)»
 * про отбор полезно, хотя заглушке оно тоже годится. Поэтому пустое здесь не
 * повод удалять спеку, а повод дописать ту её половину, которая заглушке не
 * годится.
 */
const убратьСкобки = (т) => т.replace(/[()\s]+/gu, "")
