/**
 * РАЗЛИЧИТЕЛЬНЫЙ ПОИСК: ЯДРО ПРОТИВ ВЫЧИСЛИТЕЛЯ.
 *
 *   node flang/scripts/discriminating-search.mjs
 *
 * Код возврата 0 — расхождений «доказано, а нарушается» нет; 1 — есть, и каждое
 * названо файлом, целью, утверждением и входом, на котором нарушилось.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Ядро говорит «доказано». Доказано ЧЕГО? Того, что при вычислении свойство не
 * нарушится. Связь между «ядро приняло терм» и «вычислитель не нарушит
 * свойство» держалась до сих пор ТОЛЬКО на подделках — программах, написанных
 * руками по одной на правило. Это испытание, а не доказательство, и оно уже раз
 * не сработало: 21 августа 2026 ядро отвечало «доказано обо ВСЕХ входах» там,
 * где доказательство состояло из одного примера, а запуск давал FLANG_PROPERTY.
 *
 * Здесь то же самое спрашивается МЕХАНИЧЕСКИ и много раз. Утверждения о
 * функциях порождаются перебором — заведомо ложные вперемешку с истинными, — и
 * на каждом сверяются ДВА независимых ответа:
 *
 *     что говорит ядро            `flang check --proof --json` → вердикт
 *     что говорит вычисление      `flang run --function …`     → FLANG_PROPERTY
 *
 * Расхождение вида «ядро доказало, а вычисление нарушило» — ДЫРА. Обратное
 * расхождение («не доказало, а не нарушилось») дырой не является: ядро имеет
 * право быть неполным, оно не имеет права быть неверным.
 *
 * Мера успеха здесь — сколько дыр нашлось, а не «расхождений нет». Ноль на малом
 * числе не значит ничего; ноль на большом — начало основания.
 *
 * ── ПОЧЕМУ ВЫЧИСЛЕНИЕ ВООБЩЕ ВИДИТ НАРУШЕНИЕ ДОКАЗАННОГО ────────────────────
 *
 * Потому что вычислитель проверяет постусловие ПОСЛЕ КАЖДОГО возврата и не
 * спрашивает, доказано оно или нет: `flang/self/interpret.flang`, «Шаг
 * постусловия при вычислении» берёт список постусловий прямо из разобранной
 * функции («Постусловия функции» от поля `postconditions`) и проходит его весь.
 * Отбора по доказанности там нет ни строкой. Снятие сторожа с доказанного
 * постусловия происходит только в ПЕЧАТИ и только при доказательстве С
 * ПРИМЕРАМИ — поэтому у порождённых здесь функций примеров нет ни одного.
 *
 * Не будь этого, проверка была бы слепа ровно в том месте, ради которого
 * заведена, и зелёный её ответ не значил бы ничего.
 *
 * ── Враждебные входы, которые уже кусали ────────────────────────────────────
 *
 * Пустое, один элемент, минус ноль, «не число», обе бесконечности, дробное,
 * край диапазона `неотрицательное`, смайлик в четыре октета. Часть из них НЕЛЬЗЯ втащить
 * через `--args` (в JSON нет «не числа»), поэтому вход добывается ИЗНУТРИ
 * ЯЗЫКА: `0 делить на 0`, `1 делить на 0`, `0 умножить на (0 минус 1)`.
 *
 * Одинокой половины суррогатной пары в этом списке нет, и это ответ, а не
 * пропуск: лексер её не принимает вовсе — `"\uD83D"` даёт FLANG_LEX «неверный
 * Unicode-escape». Втащить такое значение в программу нечем.
 *
 * ── Что здесь замерено попутно ──────────────────────────────────────────────
 *
 * `равен` у языка — НЕ равенство IEEE-754. `(0 делить на 0) равен (0 делить на
 * 0)` даёт `да`, а `(0 умножить на (0 минус 1)) равен 0` даёт `нет`. То есть это
 * сличение значений, а не машинное `==`, и правило рефлексивности ядра на «не
 * числе» законно. Порядок — наоборот, машинный: `(0 делить на 0) не меньше 0`
 * даёт `нет`, и на нём ложны обе стороны сравнения. Отсюда и берётся почти вся
 * ложь, которую ядро обязано не брать.
 */
