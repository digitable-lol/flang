/**
 * Печать всех восьми целей на одной программе.
 *
 * Функция печати берётся ПО ИМЕНИ, а не первой попавшейся из экспортов: модуль
 * эмиттера экспортирует не только её, и «первая функция модуля» — это способ
 * однажды померять не то и не заметить. Имени нет — падаем здесь, а не тихо.
 *
 * `корень` задаёт, откуда взять программу-улику; сами эмиттеры всегда берутся из
 * этого дерева — они и есть то, что проверяется.
 */
export async function печатьВсех(корень = КОРЕНЬ) {
  const { parse } = await import(new URL("../src/parser.mjs", import.meta.url))
  const исходник = readFileSync(new URL(ПРИМЕР, `file://${корень}`), "utf8")
  const программа = parse(исходник, ПРИМЕР)
  const из = new Map()
  for (const цель of ЦЕЛИ) {
    const мод = await import(new URL(`../src/emit/${цель.модуль}`, import.meta.url))
    const печать = мод[цель.печать]
    if (typeof печать !== "function") {
      throw new Error(`эмиттер ${цель.имя} больше не экспортирует «${цель.печать}» — сторож меряет не то`)
    }
    const файлы = печать(программа).files.map((ф) => ф.path)
    const имена = файлы.map((п) => п.split("/").at(-1))
    из.set(цель.имя, {
      файлы,
      сборка: имена.filter((и) => и === "Makefile"),
      манифесты: имена.filter(
        (и) => и !== "Makefile" && !цель.расширения.some((р) => и.endsWith(р)),
      ),
    })
  }
  return из
}

