/** Имена целей в порядке разбора: `C#` раньше `C`, иначе `C` съест решётку. */
const ИМЕНА_ЦЕЛЕЙ = ["вычислитель", "C#", "JS", "Go", "Rust", "Python", "Java", "C"]

/** Строка таблицы стоимостей про `хвост` из `flang/SPEC.md`. */
export function строкаХвоста(текст) {
  const м = текст.match(/^\|\s*`хвост`\s*\|([^|]*)\|([^|]*)\|\s*$/mu)
  return м === null ? null : { общая: м[1].trim(), elixir: м[2].trim() }
}

/** Имена целей, названные скобкой «(срез без копии в C, Go и Rust)». */
export function целиИсключения(общая) {
  const скобка = общая.match(/\(срез без копии в ([^)]*)\)/u)
  if (скобка === null) return null
  const найдено = []
  /* Найденное имя вычёркивается из строки, иначе `C` нашлась бы внутри `C#`, и
     сторож назвал бы цель, которой в скобке нет. */
  let хвост = скобка[1]
  for (const имя of ИМЕНА_ЦЕЛЕЙ) {
    const где = хвост.indexOf(имя)
    if (где < 0) continue
    найдено.push(имя)
    хвост = хвост.slice(0, где) + " ".repeat(имя.length) + хвост.slice(где + имя.length)
  }
  return найдено
}

/* ── проверка ──────────────────────────────────────────────────────────────── */

export async function проверить(корень = КОРЕНЬ) {
  const нарушения = []
  const печать = await печатьВсех(корень)

  for (const обещание of ОБЕЩАНИЯ) {
    const текст = прочитать(обещание.файл)
    if (!обещание.образец.test(текст)) {
      нарушения.push({
        род: "обещание пропало",
        файл: обещание.файл,
        что: обещание.что,
        весть: "фразы, которую стерёг сторож, в файле больше нет — перепишите сторожа вместе с прозой, а не молчком",
      })
      continue
    }
    const сказано = обещание.сколько()
    const измерено = обещание.измерить(печать)
    if (сказано !== измерено) {
      нарушения.push({ род: "разошлось с печатью", файл: обещание.файл, что: обещание.что, сказано, измерено })
    }
  }

  const напечатанные = [...печать.values()].flatMap((п) => п.манифесты).sort()
  for (const запись of МАНИФЕСТЫ) {
    const текст = прочитать(запись.файл)
    const м = текст.match(запись.образец)
    if (м === null) {
      нарушения.push({
        род: "обещание пропало",
        файл: запись.файл,
        что: "перечень манифестов пакета",
        весть: "скобка с именами манифестов исчезла из фразы про семь бэкендов",
      })
      continue
    }
    const названные = [...м[0].matchAll(/`([^`]+)`/gu)].map((н) => н[1]).sort()
    if (названные.join(", ") !== напечатанные.join(", ")) {
      нарушения.push({
        род: "разошлось с печатью",
        файл: запись.файл,
        что: "перечень манифестов пакета",
        сказано: названные.join(", "),
        измерено: напечатанные.join(", "),
      })
    }
  }

  /* Каждая из семи печатает файл сборки — это часть той же фразы. */
  for (const [имя, п] of печать) {
    if (имя === "js") continue
    if (п.сборка.length !== 1) {
      нарушения.push({
        род: "разошлось с печатью",
        файл: "README.ru.md",
        что: `цель ${имя}: файл сборки`,
        сказано: "ровно один Makefile",
        измерено: `${п.сборка.length}`,
      })
    }
  }

  /* Стоимость `хвоста`: улики на месте, и таблица называет ровно те цели. */
  for (const запись of СТОИМОСТЬ_ХВОСТА) {
    const исходник = прочитать(запись.файл)
    if (!исходник.includes(запись.улика)) {
      нарушения.push({
        род: "улика стоимости пропала",
        файл: запись.файл,
        что: `${запись.цель}: «хвост» — ${запись.класс}`,
        весть: `в исходнике больше нет «${запись.улика}» — реализация сменилась, таблицу стоимостей надо пересмотреть`,
      })
    }
  }
  const spec = прочитать("flang/SPEC.md")
  const строка = строкаХвоста(spec)
  if (строка === null) {
    нарушения.push({
      род: "обещание пропало",
      файл: "flang/SPEC.md",
      что: "строка таблицы стоимостей про `хвост`",
      весть: "строки в таблице нет — сторож стерёг фразу, которой не стало",
    })
  } else {
    const названные = целиИсключения(строка.общая)
    const срезом = СТОИМОСТЬ_ХВОСТА.filter((з) => з.класс === "срез").map((з) => з.цель)
    if (названные === null) {
      нарушения.push({
        род: "обещание пропало",
        файл: "flang/SPEC.md",
        что: "скобка «срез без копии в …»",
        весть: `строка есть, скобки нет: «${строка.общая}»`,
      })
    } else if ([...названные].sort().join(", ") !== [...срезом].sort().join(", ")) {
      нарушения.push({
        род: "разошлось с исходниками",
        файл: "flang/SPEC.md",
        что: "какие цели берут `хвост` срезом без копии",
        сказано: [...названные].sort().join(", "),
        измерено: [...срезом].sort().join(", "),
      })
    }
  }

  return нарушения
}

/* ── запуск из командной строки ─────────────────────────────────────────── */
if (import.meta.url === `file://${process.argv[1]}`) {
  const нарушения = await проверить()
  if (нарушения.length === 0) {
    console.log("сторож печати: чисто — обещания о числе файлов и о стоимости форм сошлись с прогоном")
    process.exit(0)
  }
  console.error(`сторож печати: ${нарушения.length} расхождени(й)\n`)
  for (const н of нарушения) {
    console.error(`${н.файл} — ${н.что} [${н.род}]`)
    if (н.весть !== undefined) console.error(`  ${н.весть}`)
    else {
      console.error(`  сказано:  ${н.сказано}`)
      console.error(`  напечатано: ${н.измерено}`)
    }
    console.error("")
  }
  process.exit(1)
}
