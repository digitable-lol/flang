/**
 * Печать всех восьми целей на одной программе.
 *
 * ПЕЧАТАЕТ ДВОИЧНЫЙ, и других печатников в дереве нет. До 20 августа сторож
 * ввозил модуль эмиттера по имени файла и звал функцию печати по имени
 * (`emitC`, `emitGo`, …) — модулей этих больше нет. Спрашивается ровно то же
 * самое и той же командой, какой печатает человек:
 *
 *   flang emit <файл> --target <цель> --out <каталог>
 *
 * Список файлов берётся с диска обходом каталога, а не из ответа печати: у Go
 * и Rust файлы лежат в подкаталогах (`cli/main.go`, `src/lib.rs`), и плоский
 * список имён посчитал бы не то. Проверять «имя функции печати на месте» стало
 * нечего и незачем: цель, которой двоичный не знает, отвечает отказом сама.
 *
 * `корень` задаёт, откуда взять программу-улику.
 */
export async function печатьВсех(корень = КОРЕНЬ) {
  const из = new Map()
  const где = mkdtempSync(join(tmpdir(), "flang-emit-guard-"))
  try {
    for (const цель of ЦЕЛИ) {
      const куда = join(где, цель.имя)
      const { код, вывод, ошибки } = позвать(["emit", join(корень, ПРИМЕР), "--target", цель.имя, "--out", куда])
      if (код !== 0) {
        throw new Error(`двоичный не напечатал цель «${цель.имя}» — сторож меряет не то: ${(ошибки || вывод).trim()}`)
      }
      const файлы = обходКаталога(куда).sort()
      const имена = файлы.map((п) => п.split("/").at(-1))
      из.set(цель.имя, {
        файлы,
        сборка: имена.filter((и) => и === "Makefile"),
        манифесты: имена.filter(
          (и) => и !== "Makefile" && !цель.расширения.some((р) => и.endsWith(р)),
        ),
      })
    }
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
  return из
}

/** Все файлы каталога вглубь, путями от него самого. */
function обходКаталога(каталог, приставка = "") {
  const найдено = []
  for (const запись of readdirSync(каталог)) {
    const полный = join(каталог, запись)
    const отн = приставка === "" ? запись : `${приставка}/${запись}`
    if (statSync(полный).isDirectory()) найдено.push(...обходКаталога(полный, отн))
    else найдено.push(отн)
  }
  return найдено
}

