/**
 * Сторож ОБЕЩАНИЙ О ПЕЧАТИ: сколько файлов печатает цель и чего стоят формы.
 *
 * ── Чего не хватало ─────────────────────────────────────────────────────────
 *
 * Оба README обещают: «Семь бэкендов печатают модуль, рантайм, прогонщик, файл
 * сборки и — там, где у цели такое есть, — манифест пакета; бэкенд JavaScript
 * печатает один самодостаточный файл». Это утверждение о ПОВЕДЕНИИ, и проверить
 * его стоит одного прогона восьми эмиттеров — но не проверял никто: тесты целей
 * смотрят каждый на свою цель, а «семь и один» — утверждение обо всех сразу.
 * Читатель же ставит на него: он запускает `flang emit` и ждёт ровно этого.
 *
 * Рядом — таблица стоимостей в `flang/SPEC.md` («Стоимость встроенных форм — она
 * НЕ одинакова у восьми целей»). Она обещала `хвост` копией суффикса всюду,
 * кроме C и Rust. А `BTail` в `flang/src/emit/go/flang_runtime.go` возвращает
 * `items[1:]` — срез без копии, ровно как в C и Rust. Ошибка не безобидная: по
 * этой таблице выбирают цель для горячего пути.
 *
 * ── Как устроено ────────────────────────────────────────────────────────────
 *
 * ПЕЧАТЬ. Восемь эмиттеров зовутся на одной программе, и обещания прозы читаются
 * из самой прозы: число «семь» вынимается из фразы, имена манифестов — из её
 * скобок. Разойдись проза с печатью — сторож назовёт место. Пропади фраза из
 * README — сторож тоже назовёт место: обещание, которое переписали, обязано быть
 * перепроверено, а не потеряно.
 *
 * СТОИМОСТЬ. У каждой цели в `СТОИМОСТЬ_ХВОСТА` стоит УЛИКА — точный кусок её
 * рантайма, — и класс: срез или копия. Улика проверяется в исходнике: сменится
 * реализация — сторож покраснеет и потребует пересмотреть таблицу. Скобка
 * таблицы («срез без копии в C, Go и Rust») разбирается на имена целей, и этот
 * набор обязан совпасть с набором целей класса «срез» знак в знак.
 *
 * ── Чего сторож НЕ делает ───────────────────────────────────────────────────
 *
 * Он не МЕРЯЕТ время. «Срез дешевле копии» — утверждение о классе сложности, а
 * замер времени на общей машине, у которой ночью отбирают 81% процессора, даёт
 * не класс, а погоду. Класс здесь берётся из кода: `items[1:]` в Go разделяет
 * массив, `Arrays.copyOfRange` в Java копирует, и обе записи однозначны. Что
 * взятие по номеру у массива и у односвязного списка стоит разного, меряют
 * временем `flang/test/emit-c.test.mjs` и `flang/test/emit-elixir.test.mjs` —
 * там на это есть настоящая программа.
 *
 * Запуск: `node flang/scripts/emit-guard.mjs` (или `npm run emit:check`).
 * Проверяется он сам — тестом `flang/test/emit-guard.test.mjs`.
 */
