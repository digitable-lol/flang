/**
 * Все `.flang` дерева. Служебные каталоги пропускаются, вглубь — идёт.
 *
 * В списке пропусков НЕТ `bootstrap`, и это поймано прогоном, а не вычиткой:
 * с ним обход терял `flang/self/bootstrap/compiler.flang` — тот самый вход,
 * ради которого сторож заведён (956 файлов вместо 958, 129 входов вместо 131,
 * и точка входа компилятора среди них отсутствовала). Каталог `bootstrap/` в
 * корне держит НАПЕЧАТАННЫЙ C, а `.flang` в нём нет ни одного — отбор по
 * расширению справляется без имени каталога.
 */
export function файлыДерева(корень = КОРЕНЬ, мимо = [".git", "node_modules"]) {
  const итог = []
  const обход = (дир) => {
    let записи = []
    try {
      записи = readdirSync(resolve(корень, дир === "" ? "." : дир)).sort()
    } catch {
      return
    }
    for (const имя of записи) {
      if (мимо.includes(имя)) continue
      const путь = дир === "" ? имя : `${дир}/${имя}`
      let это
      try {
        это = statSync(resolve(корень, путь))
      } catch {
        continue
      }
      if (это.isDirectory()) обход(путь)
      else if (/\.(flang|fp|фп|фланг)$/u.test(имя)) итог.push(путь)
    }
  }
  обход("")
  return итог
}

/**
 * Программы дерева, у которых есть хоть один ввоз: с них и начинают обход.
 *
 * Входом считается только файл с заголовком `модуль «…»`. Без этого условия в
 * список попадал `benchmarks/model-authoring/out/M4/г/r2/b3-maksimum.flang` —
 * запись того, что НАПИСАЛА модель на замере: файл начинается `категория «…»`,
 * не разбирается вовсе (FLANG_PARSE, строка 4) и несёт `использует` внутри
 * `объект`. Связывание такой файл за программу не считает, и сторож не должен.
 */
export function входыДерева(корень = КОРЕНЬ) {
  return файлыДерева(корень).filter((путь) => {
    try {
      const текст = readFileSync(resolve(корень, путь), "utf8")
      return имяМодуля(текст) !== null && шапка(текст).импорты.length > 0
    } catch {
      return false
    }
  })
}

/* ── БИБЛИОТЕКА ЦЕЛИКОМ: ВХОД, КОТОРОГО НА ДИСКЕ НЕТ ───────────────────────────

   Обхода настоящих программ мало, и вот почему, числом. Ни одна программа
   дерева не ввозит `flang/stdlib` целиком, поэтому столкновения МЕЖДУ
   библиотечными модулями обходу не видны: он честно говорит «ноль», а свести
   библиотеку в одну программу нельзя — связывание отвечает FLANG_DUPLICATE_NAME.

   Ровно это уже случилось. Работа «разведение имён» (ветка `u/imena-razvesti`,
   запись `docs/zettel/biblioteka-ne-svyazyvaetsya-sama-s-soboy-…`) свела 15
   столкновений к нулю, а сведение веток вернуло десять из них обратно —
   молча, потому что сторожить их было нечем. Мерой в той работе был ровно
   такой выдуманный вход, и она жила в тексте записи, а не в прогоне; здесь она
   становится прогоном: на стволе `0446d33f` он называет десять столкновений
   поимённо, на этой ветке — ноль.

   Вход этот на диске НЕ ЗАВОДИТСЯ, и это не жеманство: файл `.flang`, ввозящий
   двадцать четыре модуля, попал бы в приёмку `flang test flang/stdlib/` и стоил
   бы там всей библиотеки на каждом прогоне. Чтение подменяется тем же способом,
   каким сторож уже сверяется с выдуманными деревьями (`настройки.читать`). */

/** Выдуманный вход: `использует` на каждый модуль `flang/stdlib`. */
export function библиотекаЦеликом(корень = КОРЕНЬ) {
  const путь = "flang/stdlib/(вся библиотека сразу).flang"
  const строки = ["модуль «Вся библиотека сразу»"]
  for (const файл of readdirSync(resolve(корень, "flang/stdlib")).sort()) {
    if (!/\.(flang|fp|фп|фланг)$/u.test(файл)) continue
    const имя = имяМодуля(readFileSync(resolve(корень, "flang/stdlib", файл), "utf8"))
    if (имя !== null) строки.push(`  использует «${имя}»`)
  }
  return { путь, текст: `${строки.join("\n")}\n` }
}

/**
 * Настройки чтения, при которых выдуманный вход виден наравне с файлами диска.
 *
 * `подложка` — чтение, которое стоит ПОД выдуманным входом. Обычно это диск, но
 * при нарочной порче (`--порча`) снизу лежит уже подменённое чтение, и без этого
 * довода порча до выдуманного входа не доезжала бы: склейка библиотеки читала бы
 * с диска и порчи не видела.
 */
export function сНачинкой(вход, корень = КОРЕНЬ, подложка = null) {
  const снизу = подложка ?? ((путь) => readFileSync(resolve(корень, путь), "utf8"))
  return {
    читать: (путь) => (путь === вход.путь ? вход.текст : снизу(путь)),
    есть: (путь) => путь === вход.путь || existsSync(resolve(корень, путь)),
  }
}

/**
 * Столкновения по ВСЕМУ дереву — ДВУМЯ РАЗРЯДАМИ, а не одной кучей.
 *
 * ── Зачем разряды, и что стоило их отсутствие ───────────────────────────────
 *
 * Сторож считает две РАЗНЫЕ вещи и до 29 августа 2026 складывал их в один
 * список: столкновения в замыканиях НАСТОЯЩИХ программ дерева и столкновения в
 * ВЫДУМАННОЙ программе «вся библиотека сразу». Разница между ними не
 * оттеночная:
 *
 *   • НАСТОЯЩЕЕ — имя, которое связывание видит дважды в программе, лежащей на
 *     диске. Оно уже ломает сборку этой программы; попади оно в замыкание
 *     `flang/self/bootstrap/compiler.flang` — падает перепечатка, и узнаётся
 *     это через десять с лишним минут. КРАСИТ работу.
 *
 *   • ОТЗВУК СЛИЯНИЯ — имя, обе стороны которого сходятся ТОЛЬКО в выдуманной
 *     склейке библиотеки. Ни одна программа дерева не ввозит обе стороны, и
 *     связывание о такой паре молчит. ПРЕДУПРЕЖДЕНИЕ, кода не меняет.
 *
 * Цена смешения названа летописью, а не опасением. 23 августа 2026 в
 * библиотеку приехали `x25519`, `ecdsa`, `rsa` — сторож покраснел 54 отзвуками
 * слияния. 26 августа `168b6748` завёл НАСТОЯЩЕЕ столкновение «В ёлочках» в
 * `link.flang`: отчёт вырос с 54 строк до 55, работа `imena` как была красной,
 * так и осталась, и разницы не увидел никто. 28 августа то же столкновение
 * нашла перепечатка — за 10 мин 47 с. Сторож, который всегда красный, не
 * сторож.
 *
 * Кроме общего списка возвращает `настоящие` (у каждого — `программы`, в чьих
 * замыканиях оно случается) и `библиотечные`.
 */
export function поДереву(настройки = {}) {
  const корень = настройки.корень ?? КОРЕНЬ
  const входы = настройки.входы ?? входыДерева(корень)
  const настоящие = new Map()
  const пропали = []
  const циклы = []
  const споры = []
  let файлов = 0
  let видимых = 0
  for (const вход of входы) {
    const итог = столкновения(вход, настройки)
    файлов += итог.файлов
    видимых += итог.видимых
    for (const п of итог.пропали) пропали.push(`${п} — ввозит ${вход}`)
    for (const ц of итог.циклы) циклы.push(`${ц} — от ${вход}`)
    for (const с of итог.споры) споры.push(`${с} — от ${вход}`)
    /* Одно и то же столкновение, видное с трёх входов, называется один раз —
       ключ у него тот же, что в файле долга, — но ВСЕ три программы за ним
       записываются: по ним и читается цена. */
    for (const с of итог.столкновения) {
      const к = ключ(с)
      if (!настоящие.has(к)) настоящие.set(к, { ...с, программы: [] })
      настоящие.get(к).программы.push(вход)
    }
  }

  /* Сорок с лишним модулей библиотеки в одной программе — вход выдуманный, и
     потому идёт последним и отдельно: на диске такого файла нет. Его находки
     попадают во ВТОРОЙ разряд — и только те, которых не нашлось ни в одном
     настоящем замыкании: пара, случающаяся и там и там, настоящая. */
  const библиотечные = []
  let библиотека = null
  if (настройки.безБиблиотеки !== true) {
    const выдумка = настройки.выдумка ?? библиотекаЦеликом(корень)
    /* `безВидимости` здесь ОБЯЗАТЕЛЕН, и это не упрощение — без него сторож
       зелёный по неверной причине. Проверено порчей: верни в
       `higher-order.flang` имя «Сумма» (оно же в `lists.flang`) — и обход с
       видимостью молчит. Молчит потому, что `higher-order` сам ввозит
       `«Списки» только «Приписать в начало»`, доходит до `lists.flang` ПЕРВЫМ
       и сужает его до одного имени; собственное ребро выдуманного входа
       видимость уже не расширяет («решает первый импорт»). Ответ тогда зависит
       от того, в каком порядке лежат имена файлов в каталоге, а вопрос здесь
       другой: МОЖНО ЛИ вообще свести библиотеку в одну программу. На него
       отвечает плоская таблица всех объявлений всех модулей. */
    библиотека = столкновения(выдумка.путь, { ...настройки, ...сНачинкой(выдумка, корень, настройки.читать ?? null), безВидимости: true })
    файлов += библиотека.файлов
    видимых += библиотека.видимых
    for (const п of библиотека.пропали) пропали.push(`${п} — ввозит ${выдумка.путь}`)
    for (const ц of библиотека.циклы) циклы.push(`${ц} — от ${выдумка.путь}`)
    for (const с of библиотека.споры) споры.push(`${с} — от ${выдумка.путь}`)
    const взяты = new Set()
    for (const с of библиотека.столкновения) {
      const к = ключ(с)
      if (настоящие.has(к) || взяты.has(к)) continue
      взяты.add(к)
      библиотечные.push(с)
    }
  }

  return {
    вход: `всё дерево: ${входы.length} программ с ввозами`
      + (библиотека === null ? "" : ` + вся библиотека одной программой (${библиотека.файлов} модулей)`),
    файлов,
    видимых,
    программ: входы.length,
    настоящие: [...настоящие.values()],
    библиотечные,
    столкновения: [...настоящие.values(), ...библиотечные],
    пропали,
    циклы,
    споры,
  }
}

/* ── сам счёт ────────────────────────────────────────────────────────────────── */

/**
 * Столкновения имён в замыкании: имя, оба файла и обе строки.
 * Повтор ИЗ ТОГО ЖЕ ФАЙЛА столкновением не считается — так у свидетеля
 * (`Повтор функции`: `прежний равен файл` кладётся молча).
 */
export function столкновения(вход = ВХОД_ПО_УМОЛЧАНИЮ, настройки = {}) {
  const { порядок, пропали, циклы, споры } = замыкание(вход, настройки)
  const таблицы = new Map(РОДЫ.map((род) => [род.поле, new Map()]))
  const найдено = []
  let видимых = 0

  const слепо = настройки.безВидимости === true
  for (const файл of порядок) {
    for (const объявление of файл.объявления) {
      /* Вариант виден ровно тогда, когда виден его тип: своим именем в `только`
         он не приезжает никогда. */
      const поВидимости = объявление.владелец ?? объявление.имя
      if (!слепо && файл.видимость !== null && !файл.видимость.includes(поВидимости)) continue
      видимых += 1
      const таблица = таблицы.get(объявление.поле)
      const прежнее = таблица.get(объявление.имя)
      if (прежнее === undefined) {
        таблица.set(объявление.имя, { файл: файл.путь, строка: объявление.строка })
        continue
      }
      if (прежнее.файл === файл.путь) continue
      const род = РОДЫ.find((р) => р.поле === объявление.поле)
      найдено.push({
        поле: объявление.поле,
        слово: род.слово,
        объявлено: род.объявлено,
        имя: объявление.имя,
        первый: прежнее,
        второй: { файл: файл.путь, строка: объявление.строка },
      })
    }
  }

  return { вход, файлов: порядок.length, видимых, столкновения: найдено, пропали, циклы, споры }
}

/** Сообщение — слово в слово как у связывания, плюс обе строки. */
export function сообщение(с) {
  return `${с.слово} «${с.имя}» ${с.объявлено} в двух модулях: ${с.первый.файл} и ${с.второй.файл}`
}

/**
 * Во что столкновение обойдётся — строкой, которую читают глазами.
 *
 * Вопрос, на который сторож обязан отвечать за секунду: сломана НАСТОЯЩАЯ
 * программа или это отзвук выдуманной склейки библиотеки. Ответ считается по
 * списку программ, в чьих замыканиях имя случается.
 */
export function цена(с) {
  const программы = с.программы ?? []
  if (программы.includes(ВХОД_ПО_УМОЛЧАНИЮ)) {
    return "РОНЯЕТ ПЕРЕПЕЧАТКУ: имя стоит в замыкании компилятора — связывание ответит FLANG_DUPLICATE_NAME"
  }
  if (программы.length > 0) {
    return `роняет сборку ${программы.length === 1 ? "этой программы" : "этих программ"}; замыкания перепечатки не касается`
  }
  return "пока не стоит ничего: обе стороны не сходятся ни в одной программе дерева"
}

/** Столкновение в четыре строки: имя, оба места, где случается, и цена. */
function поимённо(с, отступ = "") {
  const строки = [`${отступ}${сообщение(с)}`]
  строки.push(`${отступ}  ${с.первый.файл}:${с.первый.строка}`)
  строки.push(`${отступ}  ${с.второй.файл}:${с.второй.строка}`)
  const программы = с.программы ?? []
  if (программы.length > 0) {
    строки.push(`${отступ}  в замыкании ${программы.length === 1 ? "программы" : `${программы.length} программ`}: ${программы.join(", ")}`)
  }
  строки.push(`${отступ}  цена: ${цена(с)}`)
  return строки
}

export function отчёт(итог) {
  const строки = [
    `вход: ${итог.вход}`,
    `замыкание: ${итог.файлов} файлов, видимых объявлений ${итог.видимых}`,
  ]
  for (const путь of итог.пропали) строки.push(`НЕ НАЙДЕН модуль: ${путь}`)
  for (const спор of итог.споры ?? []) строки.push(`ИМЯ НОСЯТ ДВА МОДУЛЯ: ${спор}`)
  for (const цикл of итог.циклы) строки.push(`циклический импорт: ${цикл}`)

  /* Один вход — разряд ровно один, и разделять нечего: всё, что нашлось,
     нашлось в НАСТОЯЩЕЙ программе. Два разряда бывают только у обхода дерева,
     потому что только там есть выдуманная склейка библиотеки. */
  if (итог.настоящие === undefined) {
    строки.push(`столкновений: ${итог.столкновения.length}`)
    for (const с of итог.столкновения) {
      строки.push("")
      строки.push(...поимённо(с))
    }
    return строки.join("\n")
  }

  строки.push("")
  строки.push(`── РАЗРЯД 1: в замыканиях настоящих программ — ${итог.настоящие.length} ──`)
  строки.push("Эти имена связывание видит дважды в программе, лежащей на диске.")
  строки.push("Работу КРАСЯТ они и только они.")
  if (итог.настоящие.length === 0) {
    строки.push("")
    строки.push("  ни одного.")
  }
  for (const с of итог.настоящие) {
    строки.push("")
    строки.push(...поимённо(с, "  "))
  }

  строки.push("")
  строки.push(`── РАЗРЯД 2: в слитой библиотеке — ${итог.библиотечные.length} ──`)
  строки.push("Обе стороны такой пары не сходятся ни в одной программе дерева: они видны")
  строки.push("только в выдуманном входе «вся библиотека сразу». Связывание о них молчит,")
  строки.push("и работы они НЕ КРАСЯТ. Красным станет тот день, когда обе стороны сойдутся")
  строки.push("в одном замыкании — тогда пара переедет в разряд 1 сама.")
  if (итог.библиотечные.length === 0) {
    строки.push("")
    строки.push("  ни одного.")
  }
  for (const с of итог.библиотечные) {
    строки.push(`  ${с.слово} «${с.имя}»: ${с.первый.файл}:${с.первый.строка} и ${с.второй.файл}:${с.второй.строка}`)
  }

  строки.push("")
  строки.push(`столкновений всего: ${итог.столкновения.length} = ${итог.настоящие.length} настоящих + ${итог.библиотечные.length} в слитой библиотеке`)
  return строки.join("\n")
}

/* ── долг ────────────────────────────────────────────────────────────────────
   На стволе 20 августа столкновений ТРИ, и они настоящие: связывание называет
   ровно их. Чинить их этой работой нельзя — правка `flang/self/**` идёт своей
   работой, — а сторож, который краснеет с первого дня и не зеленеет неделю,
   будет снят вместе со всем остальным. Поэтому долг записан ПОИМЕННО, сверка
   идёт разностью списков, и краснит сторож на ЧЕТВЁРТОМ столкновении.

   Ключ долга — род, имя и пара файлов, БЕЗ строк: строки едут от любой правки
   выше по файлу, и файл долга пришлось бы переписывать каждым коммитом. */
export const ФАЙЛ_ДОЛГА = resolve(КОРЕНЬ, "flang/scripts/link-collision-debt.json")

/** Ключ без строк: «род | имя | файл + файл». */
export function ключ(с) {
  return `${с.поле}|${с.имя}|${[с.первый.файл, с.второй.файл].sort().join(" + ")}`
}

export function записьДолга(с) {
  return { kind: с.поле, name: с.имя, files: [с.первый.файл, с.второй.файл].sort() }
}

export function ключЗаписи(з) {
  return `${з.kind}|${з.name}|${[...з.files].sort().join(" + ")}`
}

export function прочитатьДолг(файл = ФАЙЛ_ДОЛГА) {
  if (!existsSync(файл)) return []
  return JSON.parse(readFileSync(файл, "utf8")).collisions ?? []
}

/** Что нового против записанного и что из записанного уже снято. */
export function сверитьСДолгом(найдено, долг) {
  const сейчас = new Map(найдено.map((с) => [ключ(с), с]))
  const было = new Set(долг.map((з) => ключЗаписи(з)))
  return {
    новые: найдено.filter((с) => !было.has(ключ(с))),
    снятые: долг.filter((з) => !сейчас.has(ключЗаписи(з))),
  }
}

/* ── НАРОЧНАЯ ПОЛОМКА ────────────────────────────────────────────────────────

   Сторож, которого никогда не проверяли на настоящей поломке, ничего не стоит:
   он мог бы отвечать «столкновений 0» на любом входе, и разницы никто бы не
   заметил. Ровно это уже было — пока в родах объявлений не было вариантов
   суммы, сторож отвечал «0» там, где связывание называло шесть.

   Порча делается ЧТЕНИЕМ, а не записью на диск: подменяется текст одного файла
   (`настройки.читать`), дерево остаётся нетронутым. Тем же способом сторож уже
   сверялся с выдуманными деревьями.

   Порч три, и каждая проверяет своё:

     1. НАСТОЯЩАЯ В ЗАМЫКАНИИ ПЕРЕПЕЧАТКИ. Имя, уже видимое в замыкании
        `compiler.flang`, объявляется в нём заново. Сторож обязан покраснеть,
        положить находку в РАЗРЯД 1 и назвать цену словами «РОНЯЕТ ПЕРЕПЕЧАТКУ».

     2. НАСТОЯЩАЯ В ЧУЖОЙ ПРОГРАММЕ. То же самое, но во входе, которого нет в
        замыкании перепечатки. Разряд 1, краснеет, но цена другая.

     3. ОТЗВУК СЛИЯНИЯ. Новое имя заводится сразу в двух модулях библиотеки,
        которые не сходятся ни в одной программе дерева. Сторож обязан положить
        это в РАЗРЯД 2 и НЕ покраснеть: связывание о такой паре молчит.

   Третья порча — не украшение. Без неё «разделение на разряды» проверялось бы
   только тем, что сегодня и так зелено, а работа 4929 заведена ровно на то, что
   красное и зелёное перепутали. */

/** Первое видимое имя функции, объявленное НЕ во входе: его и удваиваем. */
function ЧужоеИмя(вход, настройки = {}) {
  const { порядок } = замыкание(вход, настройки)
  for (const файл of порядок) {
    if (файл.путь === вход) continue
    for (const о of файл.объявления) {
      if (о.поле !== "functions") continue
      if (файл.видимость !== null && !файл.видимость.includes(о.имя)) continue
      return { имя: о.имя, откуда: файл.путь }
    }
  }
  return null
}

/** Объявление-пустышка: сторож читает строкой, и большего ему не нужно. */
function пустышка(имя) {
  return ["", `тотальная функция «${имя}»`, "  принимает «х»: число", "  возвращает число", "  «х»", ""].join("\n")
}

/** Один и тот же файл, но с приписанным объявлением. */
function сПриписью(корень, приписи) {
  return (путь) => {
    const текст = readFileSync(resolve(корень, путь), "utf8")
    return приписи.has(путь) ? `${текст}${приписи.get(путь)}` : текст
  }
}

export function порчи(корень = КОРЕНЬ) {
  const чужое = ЧужоеИмя(ВХОД_ПО_УМОЛЧАНИЮ, { корень })
  const другойВход = "flang/self/conc.flang"
  const чужое2 = ЧужоеИмя(другойВход, { корень })
  const свежее = "Порченое имя, которого в дереве нет"
  return [
    {
      имя: "настоящая в замыкании перепечатки",
      приписи: new Map([[ВХОД_ПО_УМОЛЧАНИЮ, пустышка(чужое.имя)]]),
      ждём: { разряд: 1, код: 1, цена: "РОНЯЕТ ПЕРЕПЕЧАТКУ" },
      что: `«${чужое.имя}» из ${чужое.откуда} объявлена заново в ${ВХОД_ПО_УМОЛЧАНИЮ}`,
    },
    {
      имя: "настоящая в чужой программе",
      приписи: new Map([[другойВход, пустышка(чужое2.имя)]]),
      ждём: { разряд: 1, код: 1, цена: "роняет сборку" },
      что: `«${чужое2.имя}» из ${чужое2.откуда} объявлена заново в ${другойВход}`,
    },
    {
      имя: "отзвук слияния библиотеки",
      приписи: new Map([
        ["flang/stdlib/ecdsa.flang", пустышка(свежее)],
        ["flang/stdlib/rsa.flang", пустышка(свежее)],
      ]),
      ждём: { разряд: 2, код: 0, цена: "не сходятся ни в одной программе" },
      что: `«${свежее}» заведено сразу в ecdsa.flang и rsa.flang — они не сходятся ни в одной программе`,
    },
  ]
}

/** Прогон всех порч: что сторож ответил и что обязан был ответить. */
export function проверитьПорчей(корень = КОРЕНЬ) {
  const чисто = поДереву({ корень })
  const строки = [
    `чисто: разряд 1 — ${чисто.настоящие.length}, разряд 2 — ${чисто.библиотечные.length}`,
  ]
  let сошлось = true
  for (const порча of порчи(корень)) {
    const итог = поДереву({ корень, читать: сПриписью(корень, порча.приписи) })
    const новые = сверитьСДолгом(итог.настоящие, прочитатьДолг()).новые
    const код = новые.length > 0 ? 1 : 0
    const прирост1 = итог.настоящие.length - чисто.настоящие.length
    const прирост2 = итог.библиотечные.length - чисто.библиотечные.length
    const попало = порча.ждём.разряд === 1 ? прирост1 : прирост2
    const нетронут = порча.ждём.разряд === 1 ? прирост2 : прирост1
    const где = порча.ждём.разряд === 1 ? итог.настоящие : итог.библиотечные
    const свежие = где.filter((с) => !чисто[порча.ждём.разряд === 1 ? "настоящие" : "библиотечные"].some((б) => ключ(б) === ключ(с)))
    const ценаСошлась = свежие.length > 0 && свежие.every((с) => цена(с).includes(порча.ждём.цена))
    const ладно = попало === 1 && нетронут === 0 && код === порча.ждём.код && ценаСошлась
    сошлось = сошлось && ладно
    строки.push("")
    строки.push(`${ладно ? "СОШЛОСЬ" : "РАЗОШЛОСЬ"} — порча «${порча.имя}»`)
    строки.push(`  что подложено: ${порча.что}`)
    строки.push(`  разряд 1: ${чисто.настоящие.length} → ${итог.настоящие.length}; разряд 2: ${чисто.библиотечные.length} → ${итог.библиотечные.length}`)
    строки.push(`  код возврата: ${код} (ждали ${порча.ждём.код})`)
    for (const с of свежие) строки.push(`  найдено: ${сообщение(с)}`)
    for (const с of свежие) строки.push(`  цена: ${цена(с)}`)
    if (!ладно) строки.push("  ЖДАЛИ: одна находка в своём разряде, второй разряд не тронут, цена со словами: " + порча.ждём.цена)
  }
  return { сошлось, отчёт: строки.join("\n") }
}

function главная(аргументы) {
  const джейсон = аргументы.includes("--json")
  const позиционные = аргументы.filter((а) => !а.startsWith("--"))
  let вход = позиционные[0] ?? ВХОД_ПО_УМОЛЧАНИЮ
  if (isAbsolute(вход)) вход = relative(КОРЕНЬ, вход).split("\\").join("/")

  const дерево = аргументы.includes("--дерево") || аргументы.includes("--tree")

  if (аргументы.includes("--порча")) {
    const { сошлось, отчёт: текст } = проверитьПорчей()
    process.stdout.write(`── сторож столкновений имён: НАРОЧНАЯ ПОЛОМКА ──\n${текст}\n`)
    process.stdout.write(сошлось ? "\nВсе порчи пойманы там, где ждали.\n" : "\nСТОРОЖ ОТВЕТИЛ НЕ ТО, ЧТО ОБЯЗАН.\n")
    return сошлось ? 0 : 1
  }

  const начало = Date.now()
  const настройки = { безВидимости: аргументы.includes("--без-только") }
  const итог = дерево ? поДереву(настройки) : столкновения(вход, настройки)
  const мс = Date.now() - начало

  /* Долг заведён на ствол; чужой вход судится начисто. Обход всего дерева
     включает ствол целиком, поэтому долг ему тот же. */
  const свой = (дерево || вход === ВХОД_ПО_УМОЛЧАНИЮ) && !аргументы.includes("--без-только")
  const долг = свой ? прочитатьДолг() : []

  /* СУДИТСЯ ТОЛЬКО ПЕРВЫЙ РАЗРЯД, и это вся суть работы 4929.

     Долг заведён на настоящие столкновения — те, что уже ломают сборку хоть
     одной программы дерева. Отзвуки слитой библиотеки в долг не пишутся: довод
     нынешнего пустого долга («список обязан пустеть») верен для настоящих и
     принуждать записывать туда склейку не должен. Разряд 2 живёт числом в
     отчёте, а не строкой в файле. */
  const судимые = итог.настоящие ?? итог.столкновения

  if (аргументы.includes("--debt")) {
    /* Довод из файла долга ПЕРЕПИСЫВАНИЕ НЕ СЪЕДАЕТ. Раньше съедало: запись шла
       одним полем `collisions`, и текст «список обязан пустеть — запись о
       столкновении, которого нет, врёт так же, как молчание о том, которое
       есть» пропадал с первым же `--debt`. Долг без довода — просто список
       имён, а довод здесь и есть половина смысла. */
    const прежний = existsSync(ФАЙЛ_ДОЛГА) ? JSON.parse(readFileSync(ФАЙЛ_ДОЛГА, "utf8")) : {}
    const новый = { ...прежний, collisions: судимые.map(записьДолга) }
    writeFileSync(ФАЙЛ_ДОЛГА, `${JSON.stringify(новый, null, 2)}\n`)
    process.stdout.write(`долг переписан: ${судимые.length} настоящих столкновений\n`)
    return 0
  }

  const { новые, снятые } = сверитьСДолгом(судимые, долг)

  if (джейсон) {
    process.stdout.write(`${JSON.stringify({ ...итог, мс, новые, снятые }, null, 2)}\n`)
  } else {
    process.stdout.write(`── сторож столкновений имён ──\n${отчёт(итог)}\nсчитано за ${мс} мс\n`)
    if (долг.length > 0) process.stdout.write(`из настоящих записано долгом: ${долг.length}\n`)
    if (итог.библиотечные !== undefined && итог.библиотечные.length > 0) {
      process.stdout.write(`ПРЕДУПРЕЖДЕНИЕ (кода не меняет): ${итог.библиотечные.length} столкновений в слитой библиотеке — разряд 2 выше.\n`)
    }
    if (новые.length > 0) {
      process.stderr.write(`\nНОВЫЕ НАСТОЯЩИЕ столкновения — ${новые.length}, поимённо:\n`)
      for (const с of новые) {
        process.stderr.write(`  ${сообщение(с)}\n`)
        process.stderr.write(`    ${с.первый.файл}:${с.первый.строка}\n`)
        process.stderr.write(`    ${с.второй.файл}:${с.второй.строка}\n`)
        process.stderr.write(`    цена: ${цена(с)}\n`)
      }
    }
    if (снятые.length > 0) {
      process.stdout.write(`\nВЫПОЛНЕНО — ${снятые.length} снято; перепишите долг: --debt\n`)
    }
    if (новые.length === 0 && итог.пропали.length === 0 && итог.циклы.length === 0 && итог.споры.length === 0) {
      process.stdout.write("\nНовых настоящих столкновений нет.\n")
    }
  }

  const плохо = новые.length > 0 || итог.пропали.length > 0 || итог.циклы.length > 0 || итог.споры.length > 0
  return плохо ? 1 : 0
}

/* Запущен как программа, а не как модуль.

   Код возврата ставится полем, а НЕ `process.exit`: на трубе вывод уходит
   порциями, и `process.exit` рубит его на полуслове — поймано прогоном, `--json`
   на дереве с сотней столкновений приезжал обрезанным посреди строки. */
if (process.argv[1] !== undefined
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  process.exitCode = главная(process.argv.slice(2))
}
