/**
 * Сторож СТОЛКНОВЕНИЙ ИМЁН: два модуля завели одно имя — сказать до сборки.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Связывание сливает объявления всех подключённых файлов в ОДНО ПЛОСКОЕ
 * пространство имён. Две работы, каждая в своём слое, заводят функцию с одним
 * именем; по отдельности обе зелёные, вместе — «объявлена в двух модулях».
 * Узнаётся это от связывания, то есть на перепечатке компилятора, а она идёт
 * семнадцать минут. За один день так упало шесть перепечаток подряд.
 *
 * Здесь то же самое считается ОБХОДОМ ТЕКСТА, за доли секунды и без собранного
 * двоичного — в этом весь смысл: сторож обязан успеть ДО печати, иначе он
 * повторяет то, что и так скажут, только позже.
 *
 * ── Что он повторяет за связыванием, и почему повторяет именно так ──────────
 *
 * Свидетель — `flang/self/link.flang`. Оттуда взяты четыре правила, и без
 * любого из них сторож врал бы:
 *
 *   1. ЗАМЫКАНИЕ, а не каталог. Считаются только файлы, до которых доходит
 *      `использует … из "…"` от входного файла. Каталог `flang/` — это 313
 *      файлов, замыкание компилятора — 29; ругаться на имя, которого в
 *      программе нет, значит завести сторожа, которого снимут.
 *
 *   2. ПРОСТРАНСТВА РАЗНЫЕ. Типы, функции и восемь родов теорката (плюс
 *      функторы) сливаются каждый в свою таблицу — `Слить программу`. Тип
 *      «Место» и функция «Место» друг другу не мешают, и ругаться на них
 *      нельзя.
 *
 *   3. ВИДИМОСТЬ. В таблицу попадает не всё объявление файла, а видимое:
 *      `экспортирует` модуля ∩ `только` импорта (`Сузить видимость`). Имя, не
 *      ввезённое выборочно, столкновением быть не может — его в программе нет.
 *
 *   4. РЕШАЕТ ПЕРВЫЙ ИМПОРТ. Просьба `только` запоминается ровно тем ребром,
 *      которое привело к файлу ПЕРВЫМ в обходе; для уже загруженного файла она
 *      не расширяется (`Шаг импорта`: загруженный файл не грузится второй раз,
 *      и `Запомнить просьбу` для него не зовётся). Отсюда порядок строк
 *      `использует` в `flang/self/bootstrap/compiler.flang` — требование, а не
 *      украшение, и обход обязан идти тем же порядком: в глубину, импорты
 *      файла слева направо, своё сливается ПОСЛЕ чужого.
 *
 * ── Насколько он сошёлся со связыванием ─────────────────────────────────────
 *
 * Сверено ПРОГОНОМ обоих, а не вычиткой. На стволе связывание называет три
 * столкновения за 6 мин 23 с; обход называет те же три за 0,1 с, и вторая
 * строка у каждого совпадает с той единственной, что называет связывание.
 * Кроме ствола сверено 387 поддельных деревьев (одинаковые модули, случайные
 * пары, случайный `только`) — 1989 имён, расхождений ноль. Три ошибки нашла
 * ровно эта сверка, и вычиткой они не находились: цепочка морфизмов, `единица
 * «Х»` и естественное преобразование, которое стрелкой не является.
 *
 * ── Чего он не делает, и это названо, а не умолчано ─────────────────────────
 *
 * РАЗБОРА ЗДЕСЬ НЕТ. Второй разбор `.flang` в дереве заводить нельзя — он и
 * есть то, что убрано вместе с реализацией на JavaScript. Объявления читаются
 * СТРОКОЙ: объявление верхнего уровня начинается с первой колонки, а всё
 * остальное в языке с отступом. Отсюда три известные границы:
 *
 *   • ФАЙЛ, КОТОРЫЙ НЕ РАЗБИРАЕТСЯ. Связывание до слияния не доходит и говорит
 *     FLANG_PARSE; сторож текст всё равно прочтёт и может назвать столкновение,
 *     которого в такой программе ещё нет. Это ЛИШНЕЕ имя на уже красном
 *     дереве, а не пропущенное на зелёном.
 *
 *   • ЧЕГО НЕТ В ТЕКСТЕ БУКВАЛЬНО. Служебные звенья цепочек («Оформление · шаг
 *     1») и встроенная сумма «Действие» процессов. Связывание о них молчит
 *     тоже: звенья оно гасит намеренно, встроенный тип пропускает по признаку
 *     `builtin`.
 *
 *   • ЧЕГО СВЯЗЫВАНИЕ НЕ СЛИВАЕТ. Теоремы едут за своей функцией; процессы,
 *     надзоры, прогоны, планы и `требует` берутся у входного файла и только у
 *     него. Столкновений этих родов нет ни у связывания, ни здесь.
 *
 * Повтор имени ВНУТРИ одного файла столкновением не считается — так у
 * свидетеля («прежний равен файл» кладётся молча); об этом говорят типы.
 *
 * Ключевые слова берутся не наугад: у языка четыре письма (русское,
 * английское, эсперанто, китайское), и списки ниже взяты из «Куски таблицы»
 * (`flang/self/lexer.flang`).
 *
 * ЭТА СТРОЧКА ИСПРАВЛЕНА 29 августа 2026, потому что врала. Здесь стояло, что
 * списки «сверяются с таблицей лексера прогоном —
 * `flang/test/link-collision-guard.test.mjs`». Файла нет: он снят вместе с
 * реализацией на JavaScript, а строка в шапке осталась. Прогона, сверяющего
 * слова с лексером, сегодня НЕТ, и расхождение поймает не он, а тишина сторожа
 * на входе, который он перестал понимать. Самопроверку порчей — то, ради чего
 * тот файл в основном и держали, — теперь делает `--порча` ниже.
 *
 * Запуск:
 *   node flang/scripts/link-collision-guard.mjs [вход.flang] [--json]
 *   node flang/scripts/link-collision-guard.mjs --дерево  все программы дерева
 *   node flang/scripts/link-collision-guard.mjs --порча   нарочная поломка: ловит ли
 *   node flang/scripts/link-collision-guard.mjs --debt   переписать файл долга
 */
