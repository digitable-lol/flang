/**
 * Все `.flang` дерева. Служебные каталоги пропускаются, вглубь — идёт.
 *
 * В списке пропусков НЕТ `bootstrap`, и это поймано прогоном, а не вычиткой:
 * с ним обход терял `flang/self/bootstrap/compiler.flang` — тот самый вход,
 * ради которого сторож заведён (956 файлов вместо 958, 129 входов вместо 131,
 * и точка входа компилятора среди них отсутствовала). Каталог `bootstrap/` в
 * корне держит НАПЕЧАТАННЫЙ C, а `.flang` в нём нет ни одного — отбор по
 * расширению справляется без имени каталога.
 */
export function файлыДерева(корень = КОРЕНЬ, мимо = [".git", "node_modules"]) {
  const итог = []
  const обход = (дир) => {
    let записи = []
    try {
      записи = readdirSync(resolve(корень, дир === "" ? "." : дир)).sort()
    } catch {
      return
    }
    for (const имя of записи) {
      if (мимо.includes(имя)) continue
      const путь = дир === "" ? имя : `${дир}/${имя}`
      let это
      try {
        это = statSync(resolve(корень, путь))
      } catch {
        continue
      }
      if (это.isDirectory()) обход(путь)
      else if (/\.(flang|fp|фп|фланг)$/u.test(имя)) итог.push(путь)
    }
  }
  обход("")
  return итог
}

/**
 * Программы дерева, у которых есть хоть один ввоз: с них и начинают обход.
 *
 * Входом считается только файл с заголовком `модуль «…»`. Без этого условия в
 * список попадал `benchmarks/model-authoring/out/M4/г/r2/b3-maksimum.flang` —
 * запись того, что НАПИСАЛА модель на замере: файл начинается `категория «…»`,
 * не разбирается вовсе (FLANG_PARSE, строка 4) и несёт `использует` внутри
 * `объект`. Связывание такой файл за программу не считает, и сторож не должен.
 */
export function входыДерева(корень = КОРЕНЬ) {
  return файлыДерева(корень).filter((путь) => {
    try {
      const текст = readFileSync(resolve(корень, путь), "utf8")
      return имяМодуля(текст) !== null && шапка(текст).импорты.length > 0
    } catch {
      return false
    }
  })
}

/* ── БИБЛИОТЕКА ЦЕЛИКОМ: ВХОД, КОТОРОГО НА ДИСКЕ НЕТ ───────────────────────────

   Обхода настоящих программ мало, и вот почему, числом. Ни одна программа
   дерева не ввозит `flang/stdlib` целиком, поэтому столкновения МЕЖДУ
   библиотечными модулями обходу не видны: он честно говорит «ноль», а свести
   библиотеку в одну программу нельзя — связывание отвечает FLANG_DUPLICATE_NAME.

   Ровно это уже случилось. Работа «разведение имён» (ветка `u/imena-razvesti`,
   запись `docs/zettel/biblioteka-ne-svyazyvaetsya-sama-s-soboy-…`) свела 15
   столкновений к нулю, а сведение веток вернуло десять из них обратно —
   молча, потому что сторожить их было нечем. Мерой в той работе был ровно
   такой выдуманный вход, и она жила в тексте записи, а не в прогоне; здесь она
   становится прогоном: на стволе `0446d33f` он называет десять столкновений
   поимённо, на этой ветке — ноль.

   Вход этот на диске НЕ ЗАВОДИТСЯ, и это не жеманство: файл `.flang`, ввозящий
   двадцать четыре модуля, попал бы в приёмку `flang test flang/stdlib/` и стоил
   бы там всей библиотеки на каждом прогоне. Чтение подменяется тем же способом,
   каким сторож уже сверяется с выдуманными деревьями (`настройки.читать`). */

/** Выдуманный вход: `использует` на каждый модуль `flang/stdlib`. */
export function библиотекаЦеликом(корень = КОРЕНЬ) {
  const путь = "flang/stdlib/(вся библиотека сразу).flang"
  const строки = ["модуль «Вся библиотека сразу»"]
  for (const файл of readdirSync(resolve(корень, "flang/stdlib")).sort()) {
    if (!/\.(flang|fp|фп|фланг)$/u.test(файл)) continue
    const имя = имяМодуля(readFileSync(resolve(корень, "flang/stdlib", файл), "utf8"))
    if (имя !== null) строки.push(`  использует «${имя}»`)
  }
  return { путь, текст: `${строки.join("\n")}\n` }
}

/** Настройки чтения, при которых выдуманный вход виден наравне с файлами диска. */
export function сНачинкой(вход, корень = КОРЕНЬ) {
  return {
    читать: (путь) => (путь === вход.путь ? вход.текст : readFileSync(resolve(корень, путь), "utf8")),
    есть: (путь) => путь === вход.путь || existsSync(resolve(корень, путь)),
  }
}

/**
 * Столкновения по ВСЕМУ дереву: каждая программа с ввозами — свой вход, итоги
 * сливаются. Одно и то же столкновение, видное с трёх входов, называется один
 * раз — ключ у него тот же, что в файле долга.
 */
export function поДереву(настройки = {}) {
  const корень = настройки.корень ?? КОРЕНЬ
  const входы = настройки.входы ?? входыДерева(корень)
  const собрано = new Map()
  const пропали = []
  const циклы = []
  const споры = []
  let файлов = 0
  let видимых = 0
  for (const вход of входы) {
    const итог = столкновения(вход, настройки)
    файлов += итог.файлов
    видимых += итог.видимых
    for (const п of итог.пропали) пропали.push(`${п} — ввозит ${вход}`)
    for (const ц of итог.циклы) циклы.push(`${ц} — от ${вход}`)
    for (const с of итог.споры) споры.push(`${с} — от ${вход}`)
    for (const с of итог.столкновения) if (!собрано.has(ключ(с))) собрано.set(ключ(с), с)
  }

  /* Двадцать четыре модуля библиотеки в одной программе — вход выдуманный, и
     потому идёт последним и отдельно: на диске такого файла нет. */
  let библиотека = null
  if (настройки.безБиблиотеки !== true) {
    const выдумка = настройки.выдумка ?? библиотекаЦеликом(корень)
    /* `безВидимости` здесь ОБЯЗАТЕЛЕН, и это не упрощение — без него сторож
       зелёный по неверной причине. Проверено порчей: верни в
       `higher-order.flang` имя «Сумма» (оно же в `lists.flang`) — и обход с
       видимостью молчит. Молчит потому, что `higher-order` сам ввозит
       `«Списки» только «Приписать в начало»`, доходит до `lists.flang` ПЕРВЫМ
       и сужает его до одного имени; собственное ребро выдуманного входа
       видимость уже не расширяет («решает первый импорт»). Ответ тогда зависит
       от того, в каком порядке лежат имена файлов в каталоге, а вопрос здесь
       другой: МОЖНО ЛИ вообще свести библиотеку в одну программу. На него
       отвечает плоская таблица всех объявлений всех модулей. */
    библиотека = столкновения(выдумка.путь, { ...настройки, ...сНачинкой(выдумка, корень), безВидимости: true })
    файлов += библиотека.файлов
    видимых += библиотека.видимых
    for (const п of библиотека.пропали) пропали.push(`${п} — ввозит ${выдумка.путь}`)
    for (const ц of библиотека.циклы) циклы.push(`${ц} — от ${выдумка.путь}`)
    for (const с of библиотека.споры) споры.push(`${с} — от ${выдумка.путь}`)
    for (const с of библиотека.столкновения) if (!собрано.has(ключ(с))) собрано.set(ключ(с), с)
  }

  return {
    вход: `всё дерево: ${входы.length} программ с ввозами`
      + (библиотека === null ? "" : ` + вся библиотека одной программой (${библиотека.файлов} модулей)`),
    файлов,
    видимых,
    столкновения: [...собрано.values()],
    пропали,
    циклы,
    споры,
  }
}

/* ── сам счёт ────────────────────────────────────────────────────────────────── */

/**
 * Столкновения имён в замыкании: имя, оба файла и обе строки.
 * Повтор ИЗ ТОГО ЖЕ ФАЙЛА столкновением не считается — так у свидетеля
 * (`Повтор функции`: `прежний равен файл` кладётся молча).
 */
export function столкновения(вход = ВХОД_ПО_УМОЛЧАНИЮ, настройки = {}) {
  const { порядок, пропали, циклы, споры } = замыкание(вход, настройки)
  const таблицы = new Map(РОДЫ.map((род) => [род.поле, new Map()]))
  const найдено = []
  let видимых = 0

  const слепо = настройки.безВидимости === true
  for (const файл of порядок) {
    for (const объявление of файл.объявления) {
      /* Вариант виден ровно тогда, когда виден его тип: своим именем в `только`
         он не приезжает никогда. */
      const поВидимости = объявление.владелец ?? объявление.имя
      if (!слепо && файл.видимость !== null && !файл.видимость.includes(поВидимости)) continue
      видимых += 1
      const таблица = таблицы.get(объявление.поле)
      const прежнее = таблица.get(объявление.имя)
      if (прежнее === undefined) {
        таблица.set(объявление.имя, { файл: файл.путь, строка: объявление.строка })
        continue
      }
      if (прежнее.файл === файл.путь) continue
      const род = РОДЫ.find((р) => р.поле === объявление.поле)
      найдено.push({
        поле: объявление.поле,
        слово: род.слово,
        объявлено: род.объявлено,
        имя: объявление.имя,
        первый: прежнее,
        второй: { файл: файл.путь, строка: объявление.строка },
      })
    }
  }

  return { вход, файлов: порядок.length, видимых, столкновения: найдено, пропали, циклы, споры }
}

/** Сообщение — слово в слово как у связывания, плюс обе строки. */
export function сообщение(с) {
  return `${с.слово} «${с.имя}» ${с.объявлено} в двух модулях: ${с.первый.файл} и ${с.второй.файл}`
}

export function отчёт(итог) {
  const строки = [
    `вход: ${итог.вход}`,
    `замыкание: ${итог.файлов} файлов, видимых объявлений ${итог.видимых}`,
  ]
  for (const путь of итог.пропали) строки.push(`НЕ НАЙДЕН модуль: ${путь}`)
  for (const спор of итог.споры ?? []) строки.push(`ИМЯ НОСЯТ ДВА МОДУЛЯ: ${спор}`)
  for (const цикл of итог.циклы) строки.push(`циклический импорт: ${цикл}`)
  строки.push(`столкновений: ${итог.столкновения.length}`)
  for (const с of итог.столкновения) {
    строки.push("")
    строки.push(сообщение(с))
    строки.push(`  ${с.первый.файл}:${с.первый.строка}`)
    строки.push(`  ${с.второй.файл}:${с.второй.строка}`)
  }
  return строки.join("\n")
}

/* ── долг ────────────────────────────────────────────────────────────────────
   На стволе 20 августа столкновений ТРИ, и они настоящие: связывание называет
   ровно их. Чинить их этой работой нельзя — правка `flang/self/**` идёт своей
   работой, — а сторож, который краснеет с первого дня и не зеленеет неделю,
   будет снят вместе со всем остальным. Поэтому долг записан ПОИМЕННО, сверка
   идёт разностью списков, и краснит сторож на ЧЕТВЁРТОМ столкновении.

   Ключ долга — род, имя и пара файлов, БЕЗ строк: строки едут от любой правки
   выше по файлу, и файл долга пришлось бы переписывать каждым коммитом. */
export const ФАЙЛ_ДОЛГА = resolve(КОРЕНЬ, "flang/scripts/link-collision-debt.json")

/** Ключ без строк: «род | имя | файл + файл». */
export function ключ(с) {
  return `${с.поле}|${с.имя}|${[с.первый.файл, с.второй.файл].sort().join(" + ")}`
}

export function записьДолга(с) {
  return { kind: с.поле, name: с.имя, files: [с.первый.файл, с.второй.файл].sort() }
}

export function ключЗаписи(з) {
  return `${з.kind}|${з.name}|${[...з.files].sort().join(" + ")}`
}

export function прочитатьДолг(файл = ФАЙЛ_ДОЛГА) {
  if (!existsSync(файл)) return []
  return JSON.parse(readFileSync(файл, "utf8")).collisions ?? []
}

/** Что нового против записанного и что из записанного уже снято. */
export function сверитьСДолгом(найдено, долг) {
  const сейчас = new Map(найдено.map((с) => [ключ(с), с]))
  const было = new Set(долг.map((з) => ключЗаписи(з)))
  return {
    новые: найдено.filter((с) => !было.has(ключ(с))),
    снятые: долг.filter((з) => !сейчас.has(ключЗаписи(з))),
  }
}

function главная(аргументы) {
  const джейсон = аргументы.includes("--json")
  const позиционные = аргументы.filter((а) => !а.startsWith("--"))
  let вход = позиционные[0] ?? ВХОД_ПО_УМОЛЧАНИЮ
  if (isAbsolute(вход)) вход = relative(КОРЕНЬ, вход).split("\\").join("/")

  const дерево = аргументы.includes("--дерево") || аргументы.includes("--tree")

  const начало = Date.now()
  const настройки = { безВидимости: аргументы.includes("--без-только") }
  const итог = дерево ? поДереву(настройки) : столкновения(вход, настройки)
  const мс = Date.now() - начало

  /* Долг заведён на ствол; чужой вход судится начисто. Обход всего дерева
     включает ствол целиком, поэтому долг ему тот же. */
  const свой = (дерево || вход === ВХОД_ПО_УМОЛЧАНИЮ) && !аргументы.includes("--без-только")
  const долг = свой ? прочитатьДолг() : []

  if (аргументы.includes("--debt")) {
    writeFileSync(ФАЙЛ_ДОЛГА, `${JSON.stringify({ collisions: итог.столкновения.map(записьДолга) }, null, 2)}\n`)
    process.stdout.write(`долг переписан: ${итог.столкновения.length} столкновений\n`)
    return 0
  }

  const { новые, снятые } = сверитьСДолгом(итог.столкновения, долг)

  if (джейсон) {
    process.stdout.write(`${JSON.stringify({ ...итог, мс, новые, снятые }, null, 2)}\n`)
  } else {
    process.stdout.write(`── сторож столкновений имён ──\n${отчёт(итог)}\nсчитано за ${мс} мс\n`)
    if (долг.length > 0) process.stdout.write(`из них записано долгом: ${долг.length}\n`)
    if (новые.length > 0) {
      process.stderr.write(`\nНОВЫЕ столкновения — ${новые.length}, поимённо:\n`)
      for (const с of новые) {
        process.stderr.write(`  ${сообщение(с)}\n`)
        process.stderr.write(`    ${с.первый.файл}:${с.первый.строка}\n`)
        process.stderr.write(`    ${с.второй.файл}:${с.второй.строка}\n`)
      }
    }
    if (снятые.length > 0) {
      process.stdout.write(`\nВЫПОЛНЕНО — ${снятые.length} снято; перепишите долг: --debt\n`)
    }
    if (новые.length === 0 && итог.пропали.length === 0 && итог.циклы.length === 0 && итог.споры.length === 0) {
      process.stdout.write("\nНовых столкновений нет.\n")
    }
  }

  const плохо = новые.length > 0 || итог.пропали.length > 0 || итог.циклы.length > 0 || итог.споры.length > 0
  return плохо ? 1 : 0
}

/* Запущен как программа, а не как модуль.

   Код возврата ставится полем, а НЕ `process.exit`: на трубе вывод уходит
   порциями, и `process.exit` рубит его на полуслове — поймано прогоном, `--json`
   на дереве с сотней столкновений приезжал обрезанным посреди строки. */
if (process.argv[1] !== undefined
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  process.exitCode = главная(process.argv.slice(2))
}
