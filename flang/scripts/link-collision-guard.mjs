/** Слова длиннее — первыми: `функтора` не должно откусываться как `функтор`. */
function ветвь(слова) {
  return [...слова]
    .sort((а, б) => б.length - а.length)
    .map((с) => с.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&"))
    .join("|")
}

/* Путь НЕОБЯЗАТЕЛЕН: `использует «Списки»` ищет модуль по имени. Группа пути
   стоит целиком в `(?:…)?`, и её отсутствие — это `undefined`, а не пустая
   строка: пустая означала бы «путь есть, он пустой», то есть каталог файла. */
const ИМПОРТ = new RegExp(
  `^[ \\t]*(?:${ветвь(СЛОВА.uses)})\\s+«([^»]+)»(?:\\s+(?:${ветвь(СЛОВА.from)})\\s+"([^"]+)")?(.*)$`,
  "u",
)
const МОДУЛЬ = new RegExp(`^[ \\t]*(?:${ветвь(["модуль", "module", "模块"])})\\s+«([^»]+)»`, "u")
const ЭКСПОРТ = new RegExp(`^[ \\t]*(?:${ветвь(СЛОВА.exports)})\\s+(.*)$`, "u")
const ТОЛЬКО = new RegExp(`^\\s*(?:${ветвь(СЛОВА.only)})\\s+(.*)$`, "u")
const ИМЕНА = /«([^»]+)»/gu

const ОБЪЯВЛЕНИЯ = РОДЫ.filter((род) => род.жетоны.length > 0).map((род) => ({
  род,
  правило: new RegExp(
    `^(?:(?:${ветвь(СЛОВА.total)})\\s+)?(?:${ветвь(род.жетоны.flatMap((ж) => СЛОВА[ж]))})\\s*«([^»]+)»(.*)$`,
    "u",
  ),
}))

/* Конец слова. `\\b` здесь не годится: он считает словом только ASCII, и после
   «функтора» либо «с» границы не находит вовсе — то есть правило молчало бы
   всегда. Поймано сверкой со связыванием, а не вычиткой. */
const КОНЕЦ_СЛОВА = "(?![\\p{L}\\p{N}_])"

/** `  вариант «Имя» содержит …` внутри `тип «Х»`: с отступом, а не с колонки. */
const ВАРИАНТ = new RegExp(`^[ \\t]+(?:${ветвь(СЛОВА.variant)})\\s+«([^»]+)»`, "u")

/** `запись «Х» с …` — это построение записи, а не объявление типа. */
const ПОСТРОЕНИЕ = new RegExp(`^\\s*(?:с|with|kun|带有)${КОНЕЦ_СЛОВА}`, "u")

/* `морфизм «в копейки» ИЗ ФУНКТОРА «В рублях» в функтор «В копейках»` — это
   ЕСТЕСТВЕННОЕ ПРЕОБРАЗОВАНИЕ, а не стрелка: разбор кладёт его в
   `transformations`, а связывание этот ключ не сливает вовсе (его нет в «Роды
   объявлений»). Различает формы один взгляд вперёд — за `из` стоит слово
   `функтора`, — и он же стоит в разборе (`flang/self/parser.flang`).
   Поймано сверкой со связыванием на 197 деревьях: без этой строки сторож
   называл лишнее имя на двух из них. */
const ПРЕОБРАЗОВАНИЕ = new RegExp(
  `^\\s*(?:${ветвь(СЛОВА.from)})\\s+(?:${ветвь(СЛОВА.functor)})${КОНЕЦ_СЛОВА}`,
  "u",
)

/* ── разбор строки ──────────────────────────────────────────────────────────── */

/**
 * Имя модуля файла: первая ЗНАЧАЩАЯ строка, `модуль «Имя»`.
 *
 * По нему и ищется `использует «Списки»` без пути. Пустые строки и `//`
 * пропускаются; первая же непустая обязана быть заголовком — так требует язык.
 */
export function имяМодуля(текст) {
  for (const строка of текст.split("\n")) {
    if (строка.trim() === "") continue
    if (/^[ \t]*\/\//u.test(строка)) continue
    const м = МОДУЛЬ.exec(строка)
    return м ? м[1] : null
  }
  return null
}

/** Имена в «ёлочках» из хвоста `только` либо `экспортирует`. */
export function именаИзСписка(текст) {
  return [...текст.matchAll(ИМЕНА)].map((м) => м[1])
}

/**
 * Шапка файла: импорты (с просьбой `только`) и `экспортирует`.
 * Комментарий начинается с `//` и потому под правило не подходит; строк
 * `использует` внутри комментариев в дереве пять, и все они мимо.
 */
export function шапка(текст) {
  const импорты = []
  let экспорт = null
  const строки = текст.split("\n")
  for (let и = 0; и < строки.length; и += 1) {
    const строка = строки[и]
    if (/^[ \t]*\/\//u.test(строка)) continue
    const имп = ИМПОРТ.exec(строка)
    if (имп) {
      const хвост = ТОЛЬКО.exec(имп[3] ?? "")
      импорты.push({
        модуль: имп[1],
        путь: имп[2] ?? null,
        только: хвост ? именаИзСписка(хвост[1]) : null,
        строка: и + 1,
      })
      continue
    }
    if (экспорт === null) {
      const эксп = ЭКСПОРТ.exec(строка)
      /* `экспортирует` без имён — ограничения нет, как у свидетеля. */
      if (эксп) экспорт = именаИзСписка(эксп[1])
    }
  }
  return { импорты, экспорт: экспорт !== null && экспорт.length > 0 ? экспорт : null }
}

/**
 * Объявления верхнего уровня. Правило одно: объявление стоит С ПЕРВОЙ КОЛОНКИ,
 * тело и поля — с отступом. Комментарии отсеиваются тем же правилом, потому что
 * начинаются с `//`.
 */
export function объявления(текст) {
  const итог = []
  const строки = текст.split("\n")
  /* Чей это вариант. Держится ровно до следующего объявления с первой колонки:
     тело типа кончается там же, где начинается соседнее объявление. */
  let владелец = null
  for (let и = 0; и < строки.length; и += 1) {
    const строка = строки[и]
    if (строка.length === 0) continue
    if (строка[0] === " " || строка[0] === "\t") {
      if (владелец === null) continue
      if (/^[ \t]*\/\//u.test(строка)) continue
      const в = ВАРИАНТ.exec(строка)
      if (в) итог.push({ поле: "variants", имя: в[1], строка: и + 1, владелец })
      continue
    }
    if (строка[0] === "/") continue
    владелец = null
    for (const { род, правило } of ОБЪЯВЛЕНИЯ) {
      const м = правило.exec(строка)
      if (!м) continue
      if (род.поле === "types" && ПОСТРОЕНИЕ.test(м[2] ?? "")) break
      if (род.поле === "morphisms" && ПРЕОБРАЗОВАНИЕ.test(м[2] ?? "")) break
      итог.push({ поле: род.поле, имя: `${род.приставка ?? ""}${м[1]}`, строка: и + 1 })
      /* Варианты бывают только у суммы, и объявляется она словом `тип`;
         `объект` и `запись` — произведения, вариантов внутри у них нет. */
      if (род.поле === "types") владелец = м[1]
      break
    }
  }
  return итог
}

/* ── видимость ──────────────────────────────────────────────────────────────
   «Всё видно» — это `null`: ограничения нет. */

/** `narrow` свидетеля: просьба не расширяет экспорт. */
export function сузить(экспорт, просьба) {
  if (просьба === null) return экспорт
  if (экспорт === null) return просьба
  return просьба.filter((имя) => экспорт.includes(имя))
}

