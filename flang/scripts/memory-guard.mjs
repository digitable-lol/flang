/**
 * Сторож ПИКА ПАМЯТИ: число про память, названное прозой, сверяется с прогоном.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * За одни сутки документ соврал числом про память трижды, и механизм каждый раз
 * один: замер сделали, правку сделали, число осталось от замера. Самый дорогой
 * случай — «Сортировка вставками»: `docs/zamer-skorosti.md` три дня писал
 * «на 4 000 набрала 178 ГиБ и не досчитала», а дерево к тому времени считало те
 * же 4 000 за 710 МиБ. Число успело попасть в задание, где его назвали
 * доказательством непригодности языка.
 *
 * Сторожа на числа в дереве есть (`count-guard.mjs`, `claim-guard.mjs`,
 * `code-guard.mjs`), но пик памяти НЕ МЕРИЛ НИКТО — потому число и прожило три
 * дня после того, как стало неправдой. Этот сторож закрывает ровно этот зазор.
 *
 * ── Приём ───────────────────────────────────────────────────────────────────
 *
 * Тот же, по которому в дереве уже стоят пределы витков: порог вдвое от
 * измеренного. Вдвое, а не впритык, потому что пик зависит от куска арены
 * (64 КиБ), выравнивания и того, сколько страниц процесс держит помимо расчёта;
 * разброс между прогонами на этих задачах — единицы процентов, а двукратный
 * запас ловит именно смену ПОРЯДКА, ради которой сторож и заводится.
 *
 * Порог тухнет так же, как проза, и это не изъян: он тухнет ГРОМКО. Правка,
 * которая память улучшила, красит сторожа зелёным и оставляет запас; правка,
 * которая её испортила, красит красным в тот же прогон, а не через три дня.
 * Улучшив память, ОБЯЗАТЕЛЬНО пересними порог — иначе он перестанет ловить
 * возврат к прежнему.
 *
 * ── Запуск ──────────────────────────────────────────────────────────────────
 *
 *   node flang/scripts/memory-guard.mjs            — 250 и 1 000, около 5 с
 *   node flang/scripts/memory-guard.mjs --полный   — плюс 4 000, около 4 минут
 *
 * Нужен `cc` и `/usr/bin/time`. Где их нет, сторож честно говорит «не мерил» и
 * даёт ноль: молчаливое «зелено» на неизмеренном — ровно та беда, от которой он
 * заводится.
 */
import { execFileSync, spawnSync } from "node:child_process"
import { mkdtempSync, rmSync, existsSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const КОРЕНЬ = fileURLToPath(new URL("../..", import.meta.url))

/**
 * Замеры сняты 18 августа на дереве с областью на накопитель свёртки
 * (`fl_region_recycle`). Порог — вдвое от измеренного, округлённый вверх.
 */
const ЗАМЕРЫ = [
  {
    программа: "flang/examples/rosetta/quicksort.flang",
    функция: "Сортировка вставками",
    точки: [
      { элементов: 250, измерено: 6232, порог: 12500, полный: false },
      { элементов: 1000, измерено: 6232, порог: 12500, полный: false },
      { элементов: 4000, измерено: 8192, порог: 16400, полный: true },
    ],
  },
  {
    программа: "flang/examples/rosetta/merge-sort.flang",
    функция: "Сортировка слиянием",
    точки: [
      { элементов: 1000, измерено: 6252, порог: 12600, полный: false },
      { элементов: 4000, измерено: 6232, порог: 12600, полный: false },
    ],
  },
]

/** Тот же генератор чисел, что у `benchmarks/zamer-skorosti/arena.sh`. */
function запрос(функция, сколько) {
  const элементы = []
  let x = 12345
  for (let i = 0; i < сколько; i += 1) {
    x = (25173 * x + 13849) % 65536
    элементы.push({ n: String(x) })
  }
  return `${JSON.stringify({ fn: функция, args: [{ l: элементы }] })}\n`
}

function собрать(программа, каталог) {
  execFileSync(
    process.execPath,
    [join(КОРЕНЬ, "flang/bin/flang.mjs"), "emit", join(КОРЕНЬ, программа), "--target", "c", "--out", каталог, "--max-steps", "2000000000"],
    { stdio: "pipe", env: { ...process.env, LC_ALL: "C.UTF-8" } },
  )
  execFileSync("make", ["-C", каталог, "-j4"], { stdio: "pipe" })
}

/** Пик резидентной памяти, КиБ. null — если мерить нечем. */
function пик(бинарник, ввод) {
  const итог = spawnSync("/usr/bin/time", ["-f", "%M", бинарник, "--json"], {
    input: ввод,
    encoding: "utf8",
    maxBuffer: 1 << 28,
    env: { ...process.env, LC_ALL: "C.UTF-8" },
  })
  if (итог.error !== undefined || итог.status !== 0) {
    return null
  }
  const строки = String(итог.stderr).trim().split("\n")
  const число = Number.parseInt(строки[строки.length - 1], 10)
  return Number.isFinite(число) ? { киБ: число, ответ: String(итог.stdout) } : null
}

function главное() {
  const полный = process.argv.includes("--полный")
  if (!existsSync("/usr/bin/time")) {
    process.stdout.write("сторож пика памяти: НЕ МЕРИЛ — нет /usr/bin/time\n")
    return 0
  }
  const беды = []
  let сверено = 0
  for (const замер of ЗАМЕРЫ) {
    const точки = замер.точки.filter((точка) => полный || !точка.полный)
    if (точки.length === 0) {
      continue
    }
    const каталог = mkdtempSync(join(tmpdir(), "flang-pamyat-"))
    try {
      собрать(замер.программа, каталог)
      const бинарник = join(каталог, "flang_cli")
      for (const точка of точки) {
        const снято = пик(бинарник, запрос(замер.функция, точка.элементов))
        if (снято === null) {
          беды.push(`${замер.функция}, ${точка.элементов}: прогон не дал числа`)
          continue
        }
        сверено += 1
        if (!снято.ответ.includes('"ok":true')) {
          беды.push(`${замер.функция}, ${точка.элементов}: не досчитала — ${снято.ответ.slice(0, 80)}`)
          continue
        }
        if (снято.киБ > точка.порог) {
          беды.push(
            `${замер.функция}, ${точка.элементов} элем.: пик ${снято.киБ} КиБ при пороге ${точка.порог}\n` +
              `    записано измеренным: ${точка.измерено} КиБ; порог — вдвое от него`,
          )
        }
      }
    } finally {
      rmSync(каталог, { recursive: true, force: true })
    }
  }
  if (беды.length > 0) {
    process.stdout.write(`сторож пика памяти: ${беды.length} замер(ов) вышли за порог\n\n`)
    for (const беда of беды) {
      process.stdout.write(`  ${беда}\n`)
    }
    process.stdout.write(
      "\nПорог — вдвое от измеренного, и он в flang/scripts/memory-guard.mjs. Стало лучше —\n" +
        "пересними и порог, и прозу вместе: непереснятый порог перестаёт ловить возврат назад.\n",
    )
    return 1
  }
  process.stdout.write(
    `сторож пика памяти: чисто — ${сверено} замер(ов) внутри порога${полный ? "" : " (без 4 000: нужен --полный)"}\n`,
  )
  return 0
}

process.exit(главное())
