export const ПОТЕРИ = []

const БУКВЫ = (имя) => [...имя.normalize("NFC")].filter((з) => /\p{L}/u.test(з))
const СЛОВА = (имя) => имя.normalize("NFC").split(/[^\p{L}\p{N}]+/u).filter(Boolean)
const ЭТО_ХАНЬ = (слово) => БУКВЫ(слово).some((з) => /\p{Script=Han}/u.test(з))
const ЭТО_СОКРАЩЕНИЕ = (слово) =>
  /^[\p{Script=Latin}\p{N}]+$/u.test(слово) && слово === слово.toUpperCase() && /\p{L}/u.test(слово)
/* Кириллица и латиница внутри ОДНОГО слова: `сkind` — это кириллическое `с`,
   приклеенное к латинскому `kind`, и от `ckind` оно неотличимо на глаз. Пара
   `с/c`, `о/o`, `р/p`, `а/a`, `е/e`, `х/x` — двойники, и разница видна только
   поиску, который ничего не найдёт.

   ХАНЬ С ЛАТИНИЦЕЙ СЮДА НЕ ВХОДИТ, и это измерено, а не решено на вкус.
   Первая редакция правила краснела на `二十的阶乘在double中仍然精确` — здоровом
   китайском имени примера. В китайском между словами нет пробела, поэтому
   латинский термин внутри китайской фразы ОБЯЗАН стоять слитно, разделителя
   ему взять неоткуда. И двойников у ханьских знаков с латиницей нет: опасность
   Р4 — не смешение письменностей само по себе, а НЕОТЛИЧИМОСТЬ. */
const ДВЕ_ПИСЬМЕННОСТИ = (слово) => {
  const б = БУКВЫ(слово)
  return б.some((з) => /\p{Script=Cyrillic}/u.test(з)) && б.some((з) => /\p{Script=Latin}/u.test(з))
}

/** Порог снизу для одного слова, в единицах его собственной письменности. */
function короткоеСлово(слово) {
  if (ЭТО_СОКРАЩЕНИЕ(слово)) return false /* `C`, `AST`, `IEEE` — имя собственное */
  const длина = БУКВЫ(слово).length
  if (длина === 0) return false /* чистое число: `2`, `754` — не имя, а часть имени */
  return ЭТО_ХАНЬ(слово) ? длина < 2 : длина < 3
}

/** Правила, применённые к одному связыванию. Возвращает список кодов. */
export function нарушения({ role, name }) {
  const коды = []
  const слова = СЛОВА(name)
  const локальное = ЛОКАЛЬНЫЕ.has(role)
  if (локальное && слова.length > 0 && слова.every(короткоеСлово)) {
    коды.push(БУКВЫ(name).length === 1 && !ЭТО_ХАНЬ(name) ? "Р1-одна-буква" : "Р2-короче-трёх")
  }
  if (локальное && слова.some((с) => ОБРУБКИ.has(с.toLowerCase()))) коды.push("Р3-обрубок")
  if (слова.some(ДВЕ_ПИСЬМЕННОСТИ)) коды.push("Р4-две-письменности")
  const потолок = role === "пример" ? ПОТОЛОК_ПРИМЕРА : ПОТОЛОК_ИМЕНИ
  if (БУКВЫ(name).length > потолок) коды.push(role === "пример" ? "Р6-длинный-пример" : "Р5-длинное-имя")
  return коды
}

/* ─────────────────────────── чтение корпуса ─────────────────────────── */

function обход(каталог, найдено = []) {
  for (const запись of readdirSync(каталог).sort()) {
    const путь = join(каталог, запись)
    if (statSync(путь).isDirectory()) обход(путь, найдено)
    /* Четыре равноправных расширения программы: `.flang`, `.fp`, `.фп`, `.фланг` (ADR-0016). */
    else if (/\.(flang|fp|фп|фланг)$/u.test(путь)) найдено.push(путь)
  }
  return найдено
}

/** Разбор с отступлением: целиком, а если не вышло — по одной функции.
    Отступление стоит дорого (файл на диск и вызов двоичного на каждую
    функцию), поэтому берётся оно только когда целый файл НЕ взялся. */
function разобрать(путь) {
  const целиком = своё(путь)
  if (целиком.ok) return { деревья: [{ дерево: целиком, сдвиг: 0, объявления: true }], потери: [] }

  const текст = readFileSync(путь, "utf8")
  const строки = текст.split("\n")
  const начала = []
  строки.forEach((строка, номер) => {
    if (/^(тотальная\s+)?функция\s/.test(строка)) начала.push(номер)
  })
  const шапка = строки.slice(0, начала[0] ?? строки.length)
  const деревья = []
  const потери = []
  const кусочек = (текст) => деревоИсходника(текст, путь)
  const шапкой = кусочек(шапка.join("\n"))
  if (шапкой.ok) деревья.push({ дерево: отсеятьЧужое(шапкой.дерево, путь), сдвиг: 0, объявления: true })
  /* шапка без единой функции не разбирается — типы этого файла не увидим */
  for (let и = 0; и < начала.length; и++) {
    const от = начала[и]
    const до = и + 1 < начала.length ? начала[и + 1] : строки.length
    const взято = кусочек(`${шапка.join("\n")}\n${строки.slice(от, до).join("\n")}`)
    if (взято.ok) деревья.push({ дерево: отсеятьЧужое(взято.дерево, путь), сдвиг: от - шапка.length, объявления: false })
    else потери.push({ line: от + 1, text: строки[от].trim(), why: взято.why })
  }
  return { деревья, потери }
}

function связыванияВыражения(добавить, узел) {
  if (Array.isArray(узел)) {
    for (const э of узел) связыванияВыражения(добавить, э)
    return
  }
  if (!узел || typeof узел !== "object") return
  switch (узел.kind) {
    case "let":
      добавить("пусть", узел.name, узел.span)
      break
    case "fold":
      добавить("свёртка-накопитель", узел.acc, узел.span)
      добавить("свёртка-элемент", узел.item, узел.span)
      break
    case "map":
      добавить("отображение-элемент", узел.item, узел.span)
      break
    case "filter":
      добавить("отбор-элемент", узел.item, узел.span)
      break
    case "match":
      for (const случай of узел.cases ?? []) {
        const образец = случай.pattern
        if (!образец) continue
        const место = случай.body?.span ?? узел.span
        if (образец.kind === "cons") {
          добавить("случай-голова", образец.head, место)
          добавить("случай-хвост", образец.tail, место)
        }
        if (образец.kind === "variant") {
          const связь = образец.bind
          if (typeof связь === "string") добавить("случай-поле", связь, место)
          else if (Array.isArray(связь)) for (const с of связь) добавить("случай-поле", typeof с === "string" ? с : с?.name, место)
          else if (связь && typeof связь === "object") for (const [ключ, значение] of Object.entries(связь)) добавить("случай-поле", typeof значение === "string" ? значение : ключ, место)
        }
      }
      break
    default:
      break
  }
  for (const [ключ, значение] of Object.entries(узел)) if (ключ !== "span") связыванияВыражения(добавить, значение)
}

/** Все связывания корпуса: `{file, line, role, name}`. */
export function связывания(корень = КОРЕНЬ, каталоги = КАТАЛОГИ) {
  const файлы = каталоги.flatMap((к) => обход(join(корень, к)))
  прогреть(файлы) /* 226 разборов в один заход, а не по одному: см. binary.mjs */
  const собрано = []
  const потери = []
  for (const путь of файлы) {
    const файл = relative(корень, путь)
    const { деревья, потери: свои } = разобрать(путь)
    for (const п of свои) потери.push({ file: файл, ...п })
    for (const { дерево, сдвиг, объявления } of деревья) {
      const добавить = (роль, имя, место) => {
        if (typeof имя !== "string" || имя === "") return
        собрано.push({ file: файл, line: (место?.line ?? 0) + сдвиг, role: роль, name: имя })
      }
      if (объявления) {
        if (дерево.module) добавить("модуль", дерево.module, { line: 1 })
        for (const тип of дерево.types ?? []) {
          добавить("тип", тип.name, тип.span)
          for (const вариант of тип.variants ?? []) {
            добавить("вариант", вариант.name, вариант.span)
            for (const поле of вариант.fields ?? []) добавить("поле", поле.name, вариант.span)
          }
          for (const поле of тип.fields ?? []) добавить("поле", поле.name, тип.span)
        }
      }
      for (const функция of дерево.functions ?? []) {
        добавить("функция", функция.name, функция.span)
        for (const параметр of функция.params ?? []) добавить("параметр", параметр.name, параметр.span)
        for (const пример of функция.examples ?? []) добавить("пример", пример.name, пример.span)
        связыванияВыражения(добавить, функция.body)
      }
    }
  }
  return { файлы: файлы.length, связывания: собрано, потери }
}

/** Сколько `.flang` в дереве всего и сколько из них сторож смотрит. */
export function охват(корень = КОРЕНЬ, каталоги = КАТАЛОГИ) {
  const все = []
  const обходДерева = (каталог) => {
    for (const запись of readdirSync(каталог).sort()) {
      /* `.claude` — рабочие копии дерева, которые заводит себе оснастка агента
         под параллельную работу. В каждой лежит полный `flang/`, и сторож,
         зашедший туда, считает одни и те же файлы столько раз, сколько копий:
         замер «файлов .flang в дереве» скакнул с 809 до 9708, то есть в
         двенадцать раз, и охват «220 из 809» стал читаться как «220 из 9708».
         Тот же род каталога, что `node_modules`: следствие работы инструмента,
         а не исходник. Так же поступает `flang/scripts/claim-guard.mjs`. */
      if (запись === "node_modules" || запись === ".git" || запись === ".claude") continue
      const путь = join(каталог, запись)
      if (statSync(путь).isDirectory()) обходДерева(путь)
      else if (/\.(flang|fp|фп|фланг)$/u.test(путь)) все.push(relative(корень, путь))
    }
  }
  обходДерева(корень)
  const смотрим = каталоги.flatMap((к) => обход(join(корень, к))).map((п) => relative(корень, п))
  const вне = все.filter((ф) => !смотрим.includes(ф))
  const корни = {}
  for (const ф of вне) {
    const ключ = ф.startsWith("benchmarks/") || ф.startsWith("docs/benchmark")
      ? "печать замеров"
      : ф.startsWith("flang/test/fixtures/")
        ? "образцы тестов"
        : "рукописное вне четырёх каталогов"
    корни[ключ] = (корни[ключ] ?? 0) + 1
  }
  return { всего: все.length, смотрим: смотрим.length, вне: вне.length, поРодам: корни }
}

/** Долг: `файл → отсортированные имена`. Ключ без счётчика — см. шапку. */
export function долгКорпуса(корень = КОРЕНЬ, каталоги = КАТАЛОГИ) {
  const { файлы, связывания: все, потери } = связывания(корень, каталоги)
  const найдено = []
  let помиловано = 0
  for (const место of все) {
    const коды = нарушения(место)
    if (!коды.length) continue
    if (ИСКЛЮЧЕНИЯ.get(место.file)?.has(место.name)) {
      помиловано += 1
      continue
    }
    найдено.push({ ...место, коды })
  }
  const долг = {}
  for (const место of найдено) {
    if (место.коды.every((к) => к === "Р5-длинное-имя" || к === "Р6-длинный-пример")) continue
    ;(долг[место.file] ??= new Set()).add(место.name)
  }
  const свод = {}
  for (const [файл, имена] of Object.entries(долг).sort()) свод[файл] = [...имена].sort()
  return { файлы, найдено, долг: свод, потери, помиловано }
}

/* ────────────────────────────── прогон ────────────────────────────── */

function главная(аргументы) {
  const { файлы, найдено, долг, потери, помиловано } = долгКорпуса()
  const записанный = JSON.parse(readFileSync(ФАЙЛ_ДОЛГА, "utf8")).files

  if (аргументы.includes("--debt")) {
    writeFileSync(ФАЙЛ_ДОЛГА, `${JSON.stringify({ files: долг }, null, 2)}\n`)
    console.log(`долг переписан: ${Object.keys(долг).length} файлов`)
    return 0
  }

  const всеФайлы = new Set([...Object.keys(долг), ...Object.keys(записанный)])
  const новые = []
  const снятые = []
  for (const файл of [...всеФайлы].sort()) {
    const сейчас = new Set(долг[файл] ?? [])
    const было = new Set(записанный[файл] ?? [])
    for (const имя of [...сейчас].sort()) if (!было.has(имя)) новые.push({ файл, имя })
    for (const имя of [...было].sort()) if (!сейчас.has(имя)) снятые.push({ файл, имя })
  }
  const потолки = найдено.filter((м) => м.коды.some((к) => к === "Р5-длинное-имя" || к === "Р6-длинный-пример"))
  const лишниеПотери = потери.filter((п) => !ПОТЕРИ.includes(`${п.file}:${п.line}`))
  const надгробия = ПОТЕРИ.filter((з) => !потери.some((п) => `${п.file}:${п.line}` === з))

  if (аргументы.includes("--list")) {
    for (const [файл, имена] of Object.entries(долг)) console.log(String(имена.length).padStart(4), файл, "—", имена.join(", "))
  }

  const мест = найдено.filter((м) => !м.коды.every((к) => к === "Р5-длинное-имя" || к === "Р6-длинный-пример")).length
  const поКодам = {}
  for (const м of найдено) for (const к of м.коды) поКодам[к] = (поКодам[к] ?? 0) + 1
  console.log(`Сторож имён: ${файлы} файлов, ${мест} мест долга в ${Object.keys(долг).length} файлах.`)
  for (const [код, счёт] of Object.entries(поКодам).sort()) console.log(`  ${код.padEnd(28)} ${счёт}`)
  console.log(`  ${"помиловано (правило неверно)".padEnd(28)} ${помиловано}`)
  console.log(`  ${"не разобрано функций".padEnd(28)} ${потери.length} (записано ${ПОТЕРИ.length})`)
  const о = охват()
  console.log(`  ${"охват".padEnd(28)} ${о.смотрим} файлов из ${о.всего} в дереве; вне охвата ${о.вне} — ${Object.entries(о.поРодам).map(([к, ч]) => `${к} ${ч}`).join(", ")}`)

  let красный = false
  if (новые.length) {
    красный = true
    console.error(`\nНОВЫЕ нарушения — ${новые.length}, поимённо:`)
    for (const { файл, имя } of новые) console.error(`  ${файл}: «${имя}»`)
  }
  if (потолки.length) {
    красный = true
    console.error(`\nВЕРХНЯЯ граница пробита — ${потолки.length}, долга у неё нет:`)
    for (const м of потолки) console.error(`  ${м.file}:${м.line} ${м.коды.join(",")} «${м.name}»`)
  }
  if (лишниеПотери.length) {
    красный = true
    console.error(`\nНЕ РАЗОБРАНО сверх записанного — ${лишниеПотери.length}; проверки этих функций исчезли:`)
    for (const п of лишниеПотери) console.error(`  ${п.file}:${п.line} — ${п.why}`)
  }
  if (надгробия.length) {
    красный = true
    console.error(`\nНАДГРОБИЯ в ПОТЕРЯХ — ${надгробия.length}; эти функции уже разбираются, запись пережила причину:`)
    for (const з of надгробия) console.error(`  ${з}`)
  }
  if (снятые.length) console.log(`\nВЫПОЛНЕНО — ${снятые.length} имён снято; перепишите долг: --debt`)
  if (!красный) console.log("\nНовых нарушений нет.")
  return красный ? 1 : 0
}

