"""Доля ФАЙЛА в отчёте о доказательствах, а не доля его замыкания по ввозу.

ЗАЧЕМ. `flang check <файл> --proof` судит файл вместе с теми ввезёнными
функциями, которые названы, и печатает ОДИН общий блок «итог:» на всё сразу.
Складывать такие итоги по файлам нельзя: файл, который ввозят трое, попадает в
сумму трижды. Замерено на стволе: `wire.flang` считался трижды, `sha256.flang`
четырежды, а `x509.flang` вырос с 205 утверждений до 230 без единой изменённой
строки — вырос его сосед.

КАК ЗДЕСЬ. Числа берутся НЕ из блока «итог:», а из раздела «что высказано и чем
это несётся»: каждая его строка называет функцию, о которой говорит. Функция
сопоставляется с файлом, где она объявлена, и в долю файла идут только строки
его собственных функций.

ПРОВЕРКА САМОГО СЕБЯ. У файла есть второй, независимый счёт обязательств —
строки `обеспечивает`, `требует` и `закон` в его исходнике. Файл засчитывается
в сумму, ТОЛЬКО если оба счёта сошлись; иначе он выводится отдельно, с
причиной. Так расхождение не может тихо попасть в число.

ЗВАТЬ:
    # снять отчёты (по одному файлу за раз, через очередь тяжёлых прогонов)
    ./bootstrap/flang check <файл> --proof > отчёты/<файл с _ вместо />.out

    python3 flang/scripts/per-file-proof-share.py . отчёты/
"""
import collections
import os
import re
import sys

ФУНКЦИЯ = re.compile(r'^\s*(?:тотальная\s+)?функция\s+«([^»]+)»')
ОБЯЗАТЕЛЬСТВО = re.compile(r'^\s+(обеспечивает|требует|закон)\b')
СТРОКА_ПРИГОВОРА = re.compile(r'функции «([^»]*)» —')
НАЧАЛО_РАЗДЕЛА = 'что высказано и чем это несётся:'


def разобрать_исходник(путь):
    """(имена функций файла, сколько обязательств в нём написано)"""
    имена, обязательств = set(), 0
    # errors='replace': в flang/self/link.flang есть байт NUL, и grep на нём молчит
    with open(путь, encoding='utf-8', errors='replace') as ф:
        for строка in ф:
            if строка.lstrip().startswith('//'):
                continue
            если_функция = ФУНКЦИЯ.match(строка)
            if если_функция:
                имена.add(если_функция.group(1))
            if ОБЯЗАТЕЛЬСТВО.match(строка):
                обязательств += 1
    return имена, обязательств


def разобрать_отчёт(путь):
    """[(имя функции, вердикт)] из раздела «что высказано и чем это несётся»"""
    строки, внутри = [], False
    with open(путь, encoding='utf-8', errors='replace') as ф:
        for строка in ф:
            строка = строка.rstrip('\n')
            if строка.startswith(НАЧАЛО_РАЗДЕЛА):
                внутри = True
                continue
            if внутри and строка and not строка.startswith('  '):
                внутри = False
            if not (внутри and строка.startswith('  ')):
                continue
            имя = СТРОКА_ПРИГОВОРА.search(строка)
            хвост = строка.split('» —', 1)[-1].strip() if '» —' in строка else строка.strip()
            # «доказано ПРИ УСЛОВИИ» — ЧЕТВЁРТЫЙ вердикт: вывод верен, но опёрся
            # на недоказанную посылку. В «доказано» он не входит.
            if хвост.startswith('доказано ПРИ УСЛОВИИ'):
                вердикт = 'при условии'
            elif хвост.startswith('доказано'):
                вердикт = 'доказано'
            elif хвост.startswith('сетка'):
                вердикт = 'сетка'
            else:
                вердикт = 'объявлено'
            строки.append((имя.group(1) if имя else None, вердикт))
    return строки


def main(корень, отчёты):
    свои, написано = {}, {}
    for где, _, файлы in os.walk(корень):
        if '/.git' in где:
            continue
        for имя_файла in файлы:
            if not имя_файла.endswith('.flang'):
                continue
            путь = os.path.relpath(os.path.join(где, имя_файла), корень)
            свои[путь], написано[путь] = разобрать_исходник(os.path.join(корень, путь))

    итог, расхождения, чужих = collections.Counter(), [], collections.Counter()
    сошлось = 0
    for путь in sorted(написано):
        if написано[путь] == 0:
            continue  # доля такого файла равна нулю по построению
        отчёт = os.path.join(отчёты, путь.replace('/', '_') + '.out')
        if not os.path.exists(отчёт):
            расхождения.append((путь, написано[путь], None, 'отчёта нет'))
            continue
        своё = collections.Counter()
        for имя, вердикт in разобрать_отчёт(отчёт):
            if имя is not None and имя in свои[путь]:
                своё[вердикт] += 1
            else:
                чужих[вердикт] += 1
        всего = sum(своё.values())
        if всего != написано[путь]:
            расхождения.append((путь, написано[путь], всего, 'счёты не сошлись'))
            continue
        итог.update(своё)
        сошлось += 1

    всего_обязательств = sum(н for н in написано.values() if н)
    доказано = итог['доказано']
    print(f'файлов с обязательствами: {sum(1 for н in написано.values() if н)}')
    print(f'из них сошлось двумя счётами и учтено: {сошлось}')
    print(f'ДОКАЗАНО {доказано} из {всего_обязательств} '
          f'= {100 * доказано / всего_обязательств:.1f} %')
    print(f'  проверка при работе (сетка): {итог["сетка"]}')
    print(f'  объявлено, не доказано:      {итог["объявлено"]}')
    print(f'  доказано ПРИ УСЛОВИИ:        {итог["при условии"]}  (в число не входит)')
    print(f'строк приговора о ВВЕЗЁННЫХ файлах, отброшено как двойной счёт: {sum(чужих.values())}')
    if расхождения:
        print(f'\nНЕ УЧТЕНО, {len(расхождения)} файлов:')
        for путь, надо, вышло, почему in расхождения:
            print(f'  {надо:5d} обязательств  {почему:18s} {путь}'
                  + (f' (приговоров {вышло})' if вышло is not None else ''))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
