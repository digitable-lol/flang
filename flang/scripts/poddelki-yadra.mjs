/**
 * ПОДДЕЛКИ НА ПРАВИЛА ЯДРА: программы, которые пытаются сказать ложь и обязаны
 * остаться недоказанными.
 *
 * ── Зачем отдельный сторож, если подделки уже лежали в тестах ────────────────
 * Лежали они в `flang/test/proof-soundness.test.mjs`, а тот зовёт
 * `flang/src/*.mjs` — реализацию на JavaScript, удалённую из ствола коммитом
 * fe8e8a37. Прогон падает на первом же `import`, то есть подделки не
 * проверяются вовсе. Сторож, который не сравнивает, зеленеет — и это ровно тот
 * класс беды, ради которого подделки и заведены.
 *
 * Здесь тот же вопрос задан ДВОИЧНОМУ: он и есть компилятор, и его вердикт и
 * есть вердикт `flang check`.
 *
 * ── Что проверяется, по одной строке на правило ─────────────────────────────
 *   1. ЦЕЛЬ-ВЫБОР С ИСТИННОЙ ВЕТВЬЮ. Ход выводит `если У то да иначе Б` из
 *      выведенного `У`. Граница вся в одном: ветвь `то` обязана быть литералом
 *      `да`. Подделка ставит туда `нет` при выводимом условии — утверждение
 *      ложно на ВСЯКОМ входе, и доказать его нельзя.
 *   2. РАВЕНСТВО В ПОЗИЦИИ УТВЕРЖДЕНИЯ. Запрет «сравнивать на равенство можно
 *      только скаляры» снят в постусловии. Снятие запрета на РЕЧЬ не даёт ядру
 *      ни одного нового права на ВЫВОД: равенство двух РАЗНЫХ термов обязано
 *      остаться невыведенным.
 *   3. ТО ЖЕ РАВЕНСТВО В ТЕЛЕ. Запрет там остаётся, и файл обязан быть отвергнут
 *      диагностикой FLANG_TYPE. Без этой половины первая проверялась бы на
 *      правиле вдвое шире объявленного.
 *   4. КОНТРАКТ НЕ ПРОВЕРЯЕТСЯ, ПОКА СЧИТАЕТСЯ КОНТРАКТ. Постусловие, зовущее
 *      свою же функцию, прежде давало FLANG_RECURSION_LIMIT; развязка заводит
 *      двойника без постусловий. Проверяется ОБЕИМИ половинами: истинный круг
 *      обязан пройти, ЛОЖНЫЙ — быть пойман словами FLANG_PROPERTY. Одной первой
 *      половины мало: файл, который просто проходит, прошёл бы и при выключенных
 *      постусловиях вовсе.
 *   5а. ПОРЯДОК СОСЕДНИХ ПО ПОСТРОЕНИЮ. Правило выводит «Г : Х не убывает» из
 *      «Х не убывает» и «Г не больше головы Х». Границ у него две, и обе
 *      проверяются: ветвь `иначе` фактом НЕ читается (из «не (а не больше б)» не
 *      следует «б не больше а» — на «не числе» ложны обе стороны), и второе
 *      обязательство «Г не больше головы Х» не пропускается. Отдельной подделкой
 *      стоит самое желанное утверждение библиотеки — «результат сортировки не
 *      убывает»: оно ЛОЖНО («Сортировать» от [не число, 1] даёт [не число, 1]),
 *      и ядро обязано его не взять.
 *   5. ДОКАЗАННОЕ ПОСТУСЛОВИЕ В НАПЕЧАТАННЫЙ КОД НЕ ЕДЕТ. Границ у правила две, и
 *      обе обязаны СОХРАНИТЬ сторожа: недоказанное утверждение и утверждение
 *      функции БЕЗ примеров. Спрашивается это у настоящей команды —
 *      `flang emit … --target c`, — а не у отдельного пробника.
 *
 * Прогон: node flang/scripts/poddelki-yadra.mjs
 */
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs"
import { join } from "node:path"

import { КОРЕНЬ, ведомость, проверка } from "./dvoichnyy.mjs"

const ЖДЁМ_НЕ_ДОКАЗАНО = [
  {
    файл: "flang/test/fixtures/poddelka-istinnaya-vetv.flang",
    правило: "цель-выбор с истинной ветвью",
    утверждения: ["выбор с ложной ветвью", "одно из двух"],
  },
  {
    файл: "flang/test/fixtures/poddelka-refleksivnost.flang",
    правило: "равенство в позиции утверждения",
    утверждения: ["первый и есть второй", "а и есть б"],
  },
  {
    файл: "flang/test/fixtures/poddelka-porjadok-sosednih.flang",
    правило: "порядок соседних по построению",
    утверждения: ["пара не убывает", "приписанное не ломает порядок"],
  },
  {
    файл: "flang/test/fixtures/poddelka-sortirovka-ne-ubyvaet.flang",
    правило: "порядок соседних по построению (граница: у настоящей сортировки утверждение ЛОЖНО на «не числе»)",
    утверждения: ["сортировка упорядочивает"],
  },
]

const ЖДЁМ_ОТКАЗ = [
  {
    файл: "flang/test/fixtures/poddelka-ravenstvo-v-tele.flang",
    правило: "равенство в позиции утверждения (граница: тело не утверждение)",
    слова: "сравнивать на равенство можно только скаляры",
  },
  {
    файл: "flang/test/fixtures/poddelka-razvyazka-postusloviy.flang",
    правило: "контракт не проверяется, пока считается контракт (ложный круг обязан быть пойман)",
    слова: "круг переворота лжёт",
  },
]

/* Вторая половина того же правила: истинный круг обязан ПРОЙТИ. Прежде этот файл
   давал FLANG_RECURSION_LIMIT — то есть круг «туда и обратно» был невыразим. */
const ЖДЁМ_ПРОХОД = [
  {
    файл: "flang/test/fixtures/krug-tuda-i-obratno.flang",
    правило: "контракт не проверяется, пока считается контракт (истинный круг обязан пройти)",
  },
]

/* ПЕЧАТЬ: у какого утверждения сторож снимается, а у какого обязан остаться.
   Спрашивается настоящей командой печати, а не пробником: вердикт берётся
   оттуда же, откуда его берёт человек. */
const ЖДЁМ_В_ПЕЧАТИ = [
  {
    файл: "flang/test/fixtures/poddelka-snyatie-storozha.flang",
    правило: "доказанное постусловие в напечатанный код не едет",
    снято: ["противоположное есть нуль минус вход"],
    осталось: ["это и есть вхождение", "и это нуль минус вход"],
  },
]

let бед = 0
const плохо = (текст) => { console.error("  • " + текст); бед += 1 }

for (const { файл, правило, утверждения } of ЖДЁМ_НЕ_ДОКАЗАНО) {
  const ответ = ведомость(файл)
  if (!ответ.ok) { плохо(`${файл}: ведомость не сложилась — ${ответ.why ?? "код " + ответ.код}`); continue }
  const свои = new Map((ответ.ведомость.claims ?? []).map((к) => [к.name, к.verdict]))
  for (const имя of утверждения) {
    if (!свои.has(имя)) { плохо(`${файл}: утверждения «${имя}» в ведомости нет — подделка разошлась со сторожем`); continue }
    const вердикт = свои.get(имя)
    /* «Доказано» здесь и есть дыра: ложь, о которой ядро сказало «обо ВСЕХ
       входах». Прочие вердикты («declared», «grid») означают, что ядро её не
       взяло, — это и требуется. */
    if (String(вердикт).startsWith("proved")) плохо(`${файл}: «${имя}» ДОКАЗАНО (${вердикт}) — правило «${правило}» берёт ложь`)
    else console.log(`  ${файл}: «${имя}» — ${вердикт} (правило «${правило}» её не взяло)`)
  }
}

for (const { файл, правило, слова } of ЖДЁМ_ОТКАЗ) {
  const ответ = проверка(файл)
  if (ответ.ok) плохо(`${файл}: принят без замечаний — правило «${правило}» шире объявленного`)
  else if (!ответ.текст.includes(слова)) плохо(`${файл}: отвергнут, но не теми словами: ждали «${слова}»`)
  else console.log(`  ${файл}: отвергнут словами «${слова}» (граница правила «${правило}» на месте)`)
}

for (const { файл, правило } of ЖДЁМ_ПРОХОД) {
  const ответ = проверка(файл)
  if (!ответ.ok) плохо(`${файл}: отвергнут, а обязан пройти — правило «${правило}» не работает: ${ответ.текст.split("\n")[0]}`)
  else console.log(`  ${файл}: проверен без замечаний (правило «${правило}» работает)`)
}

for (const { файл, правило, снято, осталось } of ЖДЁМ_В_ПЕЧАТИ) {
  const каталог = mkdtempSync(join(КОРЕНЬ, ".flang-pechat-"))
  try {
    execFileSync(join(КОРЕНЬ, "bootstrap/flang"), ["emit", join(КОРЕНЬ, файл), "--target", "c", "--out", каталог], {
      encoding: "utf8",
      env: { ...process.env, LC_ALL: "C.UTF-8" },
      maxBuffer: 1 << 26,
      stdio: ["ignore", "pipe", "pipe"],
    })
    let текст = ""
    for (const имя of readdirSync(каталог)) if (имя.endsWith(".c")) текст += readFileSync(join(каталог, имя), "utf8")
    for (const имя of снято) {
      if (текст.includes(`постусловие «${имя}»`)) плохо(`${файл}: сторож «${имя}» напечатан, а утверждение доказано и проверено примерами — правило «${правило}» не сработало`)
      else console.log(`  ${файл}: «${имя}» — сторожа в напечатанном коде НЕТ (доказано + примеры)`)
    }
    for (const имя of осталось) {
      if (!текст.includes(`постусловие «${имя}»`)) плохо(`${файл}: сторож «${имя}» СНЯТ, а сниматься не должен — правило «${правило}» шире объявленного`)
      else console.log(`  ${файл}: «${имя}» — сторож на месте (граница правила «${правило}»)`)
    }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/* ── ПРОВЕРКА ОБЯЗАНА ОСТАТЬСЯ ЖИВОЙ В НАПЕЧАТАННОМ КОДЕ ─────────────────────
 *
 * Развязка постусловий снимает контракты у ДВОЙНИКОВ. Снимись они шире — круг
 * «туда и обратно» перестал бы проверяться вовсе, и `flang check` этого не
 * увидел бы: примеры автора нарушающего входа не содержат. Поэтому здесь
 * программа ПЕЧАТАЕТСЯ, СОБИРАЕТСЯ и ЗОВЁТСЯ на входе, который утверждение
 * нарушает, — и обязана ответить FLANG_PROPERTY.
 */
{
  const файл = "flang/test/fixtures/poddelka-krug-pri-rabote.flang"
  const каталог = mkdtempSync(join(КОРЕНЬ, ".flang-rabota-"))
  try {
    execFileSync(join(КОРЕНЬ, "bootstrap/flang"), ["emit", join(КОРЕНЬ, файл), "--target", "c", "--out", каталог], {
      encoding: "utf8", env: { ...process.env, LC_ALL: "C.UTF-8" }, maxBuffer: 1 << 26, stdio: ["ignore", "pipe", "pipe"],
    })
    execFileSync("make", ["-C", каталог, "-j4"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] })
    const спросить = (вход) =>
      execFileSync(join(каталог, "flang_cli"), [], {
        encoding: "utf8", input: вход + "\n", env: { ...process.env, LC_ALL: "C.UTF-8" },
      }).trim()
    const сходится = спросить('{"fn":"Переворот хитрец","args":[{"l":[{"n":"1"}]}]}')
    const нет = спросить('{"fn":"Переворот хитрец","args":[{"l":[{"n":"1"},{"n":"2"}]}]}')
    if (!сходится.includes('"ok":true')) плохо(`${файл}: на [1] собранная программа отказала — ${сходится}`)
    else console.log(`  ${файл}: на [1] круг сходится, ответ получен`)
    if (!нет.includes("FLANG_PROPERTY") || !нет.includes("круг сходится"))
      плохо(`${файл}: на [1, 2] нарушение НЕ поймано — развязка сняла проверку шире объявленного: ${нет}`)
    else console.log(`  ${файл}: на [1, 2] собранная программа отвечает FLANG_PROPERTY (проверка жива в напечатанном коде)`)
  } catch (беда) {
    плохо(`${файл}: печать или сборка не прошли — ${(беда.stderr ?? беда.message ?? "").toString().split("\n")[0]}`)
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/* ── АКСИОМ НОЛЬ, И ЭТО ПРОВЕРЯЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ ────────────────────────
 *
 * Аксиома — утверждение, принятое БЕЗ доказательства. Ложная аксиома отравляет
 * всё, что из неё выведено: `х плюс 1 не меньше х` в IEEE-754 неправда при |х|
 * от 2^53, и ровно поэтому список аксиом ядра пуст и остаётся пустым.
 *
 * Держится это тем, что слова «аксиом» в исходнике ядра нет — кроме НАЗВАННЫХ
 * доводов, объясняющих, почему то или иное правило теорема, а не аксиома. Такой
 * довод без этого слова не написать, поэтому вычёркиваются не упоминания, а
 * блоки комментария от заголовка довода до следующего заголовка или до первой
 * строки кода. Список заголовков закрыт: дописать в него строку значит написать
 * ещё один довод.
 *
 * Проверка перенесена сюда из `flang/test/self-proof-kernel.test.mjs`: тот файл
 * зовёт удалённую реализацию на JavaScript и не прогоняется вовсе.
 */
const ДОВОДЫ = [
  "── Аксиом ноль, и это не упущение ──",
  "── ПОЧЕМУ ТЕОРЕМА, А НЕ АКСИОМА ──",
  "── ПОЧЕМУ СЧЁТ НЕ АКСИОМА ──",
  "── ПОЧЕМУ ЭТО НЕ АКСИОМА ──",
]
const ядро = readFileSync(join(КОРЕНЬ, "flang/self/proof-kernel.flang"), "utf8")
for (const заголовок of ДОВОДЫ) {
  if (!ядро.includes(заголовок)) плохо(`довод «${заголовок}» пропал, а слово «аксиома» вычёркивается по нему`)
}
const вне = []
let внутриДовода = false
for (const строка of ядро.split("\n")) {
  const комментарий = /^\s*\/\//u.test(строка)
  if (!комментарий) внутриДовода = false
  else if (ДОВОДЫ.some((заголовок) => строка.includes(заголовок))) внутриДовода = true
  else if (строка.includes("──")) внутриДовода = false
  if (!внутриДовода) вне.push(строка)
}
if (/аксиом/iu.test(вне.join("\n"))) плохо("в ядре завелась аксиома вне названного довода")
else console.log("  аксиом ноль: слово «аксиома» в ядре стоит только под названными доводами")

console.log("")
if (бед === 0) {
  console.log(`подделки отвергнуты: ${ЖДЁМ_НЕ_ДОКАЗАНО.length + ЖДЁМ_ОТКАЗ.length + ЖДЁМ_ПРОХОД.length + ЖДЁМ_В_ПЕЧАТИ.length + 1} файлов, аксиом ноль, нарушений 0`)
  process.exit(0)
}
console.error(`нарушений: ${бед}`)
process.exit(1)
