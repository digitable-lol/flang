/**
 * ПОДДЕЛКИ НА ПРАВИЛА ЯДРА: программы, которые пытаются сказать ложь и обязаны
 * остаться недоказанными.
 *
 * ── Зачем отдельный сторож, если подделки уже лежали в тестах ────────────────
 * Лежали они в `flang/test/proof-soundness.test.mjs`, а тот зовёт
 * `flang/src/*.mjs` — реализацию на JavaScript, удалённую из ствола коммитом
 * fe8e8a37. Прогон падает на первом же `import`, то есть подделки не
 * проверяются вовсе. Сторож, который не сравнивает, зеленеет — и это ровно тот
 * класс беды, ради которого подделки и заведены.
 *
 * Здесь тот же вопрос задан ДВОИЧНОМУ: он и есть компилятор, и его вердикт и
 * есть вердикт `flang check`.
 *
 * ── Что проверяется, по одной строке на правило ─────────────────────────────
 *   1. ЦЕЛЬ-ВЫБОР С ИСТИННОЙ ВЕТВЬЮ. Ход выводит `если У то да иначе Б` из
 *      выведенного `У`. Граница вся в одном: ветвь `то` обязана быть литералом
 *      `да`. Подделка ставит туда `нет` при выводимом условии — утверждение
 *      ложно на ВСЯКОМ входе, и доказать его нельзя.
 *   2. РАВЕНСТВО В ПОЗИЦИИ УТВЕРЖДЕНИЯ. Запрет «сравнивать на равенство можно
 *      только скаляры» снят в постусловии. Снятие запрета на РЕЧЬ не даёт ядру
 *      ни одного нового права на ВЫВОД: равенство двух РАЗНЫХ термов обязано
 *      остаться невыведенным.
 *   3. ТО ЖЕ РАВЕНСТВО В ТЕЛЕ. Запрет там остаётся, и файл обязан быть отвергнут
 *      диагностикой FLANG_TYPE. Без этой половины первая проверялась бы на
 *      правиле вдвое шире объявленного.
 *
 * Прогон: node flang/scripts/poddelki-yadra.mjs
 */
import { readFileSync } from "node:fs"
import { join } from "node:path"

import { КОРЕНЬ, ведомость, проверка } from "./dvoichnyy.mjs"

const ЖДЁМ_НЕ_ДОКАЗАНО = [
  {
    файл: "flang/test/fixtures/poddelka-istinnaya-vetv.flang",
    правило: "цель-выбор с истинной ветвью",
    утверждения: ["выбор с ложной ветвью", "одно из двух"],
  },
  {
    файл: "flang/test/fixtures/poddelka-refleksivnost.flang",
    правило: "равенство в позиции утверждения",
    утверждения: ["первый и есть второй", "а и есть б"],
  },
]

const ЖДЁМ_ОТКАЗ = [
  {
    файл: "flang/test/fixtures/poddelka-ravenstvo-v-tele.flang",
    правило: "равенство в позиции утверждения (граница: тело не утверждение)",
    слова: "сравнивать на равенство можно только скаляры",
  },
]

let бед = 0
const плохо = (текст) => { console.error("  • " + текст); бед += 1 }

for (const { файл, правило, утверждения } of ЖДЁМ_НЕ_ДОКАЗАНО) {
  const ответ = ведомость(файл)
  if (!ответ.ok) { плохо(`${файл}: ведомость не сложилась — ${ответ.why ?? "код " + ответ.код}`); continue }
  const свои = new Map((ответ.ведомость.claims ?? []).map((к) => [к.name, к.verdict]))
  for (const имя of утверждения) {
    if (!свои.has(имя)) { плохо(`${файл}: утверждения «${имя}» в ведомости нет — подделка разошлась со сторожем`); continue }
    const вердикт = свои.get(имя)
    /* «Доказано» здесь и есть дыра: ложь, о которой ядро сказало «обо ВСЕХ
       входах». Прочие вердикты («declared», «grid») означают, что ядро её не
       взяло, — это и требуется. */
    if (String(вердикт).startsWith("proved")) плохо(`${файл}: «${имя}» ДОКАЗАНО (${вердикт}) — правило «${правило}» берёт ложь`)
    else console.log(`  ${файл}: «${имя}» — ${вердикт} (правило «${правило}» её не взяло)`)
  }
}

for (const { файл, правило, слова } of ЖДЁМ_ОТКАЗ) {
  const ответ = проверка(файл)
  if (ответ.ok) плохо(`${файл}: принят без замечаний — правило «${правило}» шире объявленного`)
  else if (!ответ.текст.includes(слова)) плохо(`${файл}: отвергнут, но не теми словами: ждали «${слова}»`)
  else console.log(`  ${файл}: отвергнут словами «${слова}» (граница правила «${правило}» на месте)`)
}

/* ── АКСИОМ НОЛЬ, И ЭТО ПРОВЕРЯЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ ────────────────────────
 *
 * Аксиома — утверждение, принятое БЕЗ доказательства. Ложная аксиома отравляет
 * всё, что из неё выведено: `х плюс 1 не меньше х` в IEEE-754 неправда при |х|
 * от 2^53, и ровно поэтому список аксиом ядра пуст и остаётся пустым.
 *
 * Держится это тем, что слова «аксиом» в исходнике ядра нет — кроме НАЗВАННЫХ
 * доводов, объясняющих, почему то или иное правило теорема, а не аксиома. Такой
 * довод без этого слова не написать, поэтому вычёркиваются не упоминания, а
 * блоки комментария от заголовка довода до следующего заголовка или до первой
 * строки кода. Список заголовков закрыт: дописать в него строку значит написать
 * ещё один довод.
 *
 * Проверка перенесена сюда из `flang/test/self-proof-kernel.test.mjs`: тот файл
 * зовёт удалённую реализацию на JavaScript и не прогоняется вовсе.
 */
const ДОВОДЫ = [
  "── Аксиом ноль, и это не упущение ──",
  "── ПОЧЕМУ ТЕОРЕМА, А НЕ АКСИОМА ──",
  "── ПОЧЕМУ СЧЁТ НЕ АКСИОМА ──",
  "── ПОЧЕМУ ЭТО НЕ АКСИОМА ──",
]
const ядро = readFileSync(join(КОРЕНЬ, "flang/self/proof-kernel.flang"), "utf8")
for (const заголовок of ДОВОДЫ) {
  if (!ядро.includes(заголовок)) плохо(`довод «${заголовок}» пропал, а слово «аксиома» вычёркивается по нему`)
}
const вне = []
let внутриДовода = false
for (const строка of ядро.split("\n")) {
  const комментарий = /^\s*\/\//u.test(строка)
  if (!комментарий) внутриДовода = false
  else if (ДОВОДЫ.some((заголовок) => строка.includes(заголовок))) внутриДовода = true
  else if (строка.includes("──")) внутриДовода = false
  if (!внутриДовода) вне.push(строка)
}
if (/аксиом/iu.test(вне.join("\n"))) плохо("в ядре завелась аксиома вне названного довода")
else console.log("  аксиом ноль: слово «аксиома» в ядре стоит только под названными доводами")

console.log("")
if (бед === 0) {
  console.log(`подделки отвергнуты: ${ЖДЁМ_НЕ_ДОКАЗАНО.length + ЖДЁМ_ОТКАЗ.length} файла, аксиом ноль, нарушений 0`)
  process.exit(0)
}
console.error(`нарушений: ${бед}`)
process.exit(1)
