/**
 * Досягаемость предусловия: сколько функций корпуса стало ВЫСКАЗЫВАЕМЫМИ.
 *
 * Вопрос, на который отвечает эта программа, один и он не про слово, а про
 * язык: у скольких уже написанных функций утверждение о результате нельзя было
 * высказать ИСТИННЫМ, пока не появилось `требует`?
 *
 * ── Почему это вообще считается, а не оценивается на глаз ───────────────────
 * «Невысказываемо» звучит как впечатление, а является свойством дерева.
 * Утверждение о результате функции истинно ОБО ВСЕХ входах ровно тогда, когда
 * входы ограничены. Ограничить их можно двумя способами: ТИПОМ (`нат` даёт дно
 * нулём, объявленная сумма даёт конечный перебор) или УСЛОВИЕМ (`требует`).
 * Второго способа у языка не было, значит функция, у которой ограничение НЕ
 * даётся типом, до этой работы могла высказать о себе только безусловное
 * утверждение — то есть либо истинное по типам, либо ложное.
 *
 * Отсюда счёт: функции делятся по тому, чем ограничен их вход, и группы
 * называются числами. Ни одна из групп не «оценка полезности» — все они
 * читаются с дерева и повторяются одной командой.
 *
 * ── Четыре числа, и каждое отвечает на свой вопрос ──────────────────────────
 *   ОТКРЫТЫЙ ВХОД     у функции есть хотя бы один параметр типа `число` без
 *                     сужения (не `нат`, не отрезок). Тип не даёт о нём НИЧЕГО:
 *                     ни знака, ни дна, ни потолка. Всякое утверждение о
 *                     порядке результата такой функции безусловно ложно или
 *                     безусловно тривиально — до `требует` третьего не было.
 *                     Это и есть верхняя граница досягаемости слова.
 *   ПРАВДА НА ВЕТВИ   тело функции на верхнем уровне — `если`. Истинность
 *                     утверждения о результате держится тогда условием
 *                     ветвления, а не типами, и высказать её без «если» нечем.
 *                     Подмножество открытого входа, названное отдельно, потому
 *                     что это самая частая форма («Сколько дополнить»).
 *   БАЗА СО СВОБОДНЫМ ИМЕНЕМ  тело — `разбор` объявленной суммы, и хотя бы одна
 *                     ветвь БЕЗ рекурсивных полей возвращает голое имя
 *                     (параметр). Ровно этот случай ядро не могло закрыть
 *                     ничем: примером нельзя (значений бесконечно много),
 *                     предположением индукции нельзя (частей нет). Предусловие
 *                     его закрывает, и это не обещание — так доказана
 *                     «Высота от дна» в `flang/proof/examples/precondition.flang`.
 *   УЖЕ СКАЗАНО       функций, при которых `требует` уже стоит. Число растёт
 *                     работой, а не измерением, и стоит рядом затем, чтобы
 *                     досягаемость и достигнутое не путались.
 *
 * ── Чего этот счёт НЕ утверждает ────────────────────────────────────────────
 * Не утверждает, что все эти функции надо снабдить предусловием: у многих
 * утверждения о результате нет и не нужно. Утверждает ровно то, что написано:
 * у стольких-то функций истинное утверждение о результате было НЕЧЕМ записать,
 * а теперь есть чем. Это верхняя граница, и она названа верхней.
 *
 * Запуск:
 *   node flang/scripts/precondition-reach.mjs
 *   node flang/scripts/precondition-reach.mjs --json
 *   node flang/scripts/precondition-reach.mjs --list база
 */
import { readFileSync, realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { parse } from "../src/parser.mjs"
import { globSync } from "../test/glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/**
 * Файлы корпуса — те же, что у `word-occupancy.mjs`, и по той же причине:
 * функция ограничена входом там, где она написана, а склеенный самоприменением
 * компилятор — это сборка остальных файлов, и его функции посчитались бы дважды.
 */
export const ФАЙЛЫ = globSync("**/*.flang", { cwd: корень })
  .filter((путь) => путь !== "flang/self/bootstrap/compiler.flang")
  .filter((путь) => !путь.startsWith("node_modules/"))
  .sort()

/** Открыт ли тип: `число` без единого сужения. */
function открытоеЧисло(тип) {
  if (тип === null || тип === undefined || typeof тип !== "object") return false
  if (тип.kind !== "number") return false
  /* Сужения парсер кладёт полями узла: `нат` даёт дно и целость, отрезок —
     дно и потолок. Что именно названо — здесь неважно; важно, что названо хоть
     что-то: тогда тип о значении уже говорит, и слово `требует` не единственный
     способ это сказать. */
  return тип.min === undefined && тип.max === undefined && тип.integer !== true && тип.fts === undefined
}

/** Возвращает ли ветвь голое имя параметра. */
function голоеИмя(узел) {
  return узел !== null && typeof узел === "object" && узел.kind === "var" && typeof узел.name === "string"
}

/** Есть ли у варианта поле типа самой суммы — то есть даёт ли он предположение. */
function рекурсивный(вариант, имяСуммы) {
  return (вариант?.fields ?? []).some((поле) => поле?.type?.kind === "named" && поле.type.name === имяСуммы)
}

export function досягаемость(файлы = ФАЙЛЫ, корневой = корень) {
  const итог = {
    файлов: 0,
    функций: 0,
    открытыйВход: [],
    правдаНаВетви: [],
    базаСоСвободнымИменем: [],
    ужеСказано: [],
    отказы: [],
  }

  for (const путь of файлы) {
    let программа
    try {
      программа = parse(readFileSync(`${корневой}${корневой.endsWith("/") ? "" : "/"}${путь}`, "utf8"), путь)
    } catch (беда) {
      итог.отказы.push(`${путь}: ${беда?.message ?? String(беда)}`)
      continue
    }
    итог.файлов += 1

    const суммы = new Map()
    for (const тип of программа.types ?? []) {
      if (тип?.kind === "sum") суммы.set(тип.name, тип)
    }

    for (const fn of программа.functions ?? []) {
      итог.функций += 1
      const где = `${путь} — «${fn.name}»`

      if ((fn.preconditions ?? []).length > 0) итог.ужеСказано.push(где)

      const параметры = fn.params ?? []
      const открыт = параметры.some((п) => открытоеЧисло(п.type))
      if (открыт) итог.открытыйВход.push(где)

      /* Подмножество открытого входа, а не отдельная группа: `если` при входе,
         уже ограниченном типом, о досягаемости слова ничего не говорит. */
      if (открыт && fn.body?.kind === "if") итог.правдаНаВетви.push(где)

      if (fn.body?.kind === "match" && fn.body.target?.kind === "var") {
        const имяПараметра = fn.body.target.name
        const параметр = параметры.find((п) => п.name === имяПараметра)
        const имяСуммы = параметр?.type?.kind === "named" ? параметр.type.name : null
        const сумма = имяСуммы === null ? undefined : суммы.get(имяСуммы)
        if (сумма !== undefined) {
          const базы = new Set(
            (сумма.variants ?? []).filter((в) => !рекурсивный(в, имяСуммы)).map((в) => в.name),
          )
          const есть = (fn.body.cases ?? []).some(
            (случай) =>
              случай?.pattern?.kind === "variant"
              && базы.has(случай.pattern.name)
              && голоеИмя(случай.body)
              && параметры.some((п) => п.name === случай.body.name),
          )
          if (есть) итог.базаСоСвободнымИменем.push(где)
        }
      }
    }
  }

  return итог
}

function печать(итог) {
  const строки = [
    "── досягаемость предусловия по корпусу ──",
    `файлов прочитано: ${итог.файлов}, функций: ${итог.функций}`,
    "",
    "стало ВЫСКАЗЫВАЕМО (верхняя граница — вход не ограничен типом):",
    `  открытый вход (параметр «число» без сужения): ${итог.открытыйВход.length}`,
    `  из них правда держится ветвлением (тело — «если»): ${итог.правдаНаВетви.length}`,
    "",
    "стало ДОКАЗУЕМО ядром (раньше не закрывалось ничем):",
    `  база разбора возвращает свободное имя: ${итог.базаСоСвободнымИменем.length}`,
    "",
    `уже сказано словом «требует»: ${итог.ужеСказано.length}`,
  ]
  if (итог.отказы.length > 0) {
    строки.push("", `не разобрались (в корпусе есть намеренно сломанные модели): ${итог.отказы.length}`)
  }
  return строки.join("\n")
}

const этоЗапуск = (() => {
  try {
    return realpathSync(process.argv[1] ?? "") === realpathSync(fileURLToPath(import.meta.url))
  } catch {
    return false
  }
})()

if (этоЗапуск) {
  const итог = досягаемость()
  if (process.argv.includes("--json")) {
    process.stdout.write(`${JSON.stringify(итог, null, 2)}\n`)
  } else {
    const где = process.argv.indexOf("--list")
    process.stdout.write(`${печать(итог)}\n`)
    if (где !== -1) {
      const какой = process.argv[где + 1] ?? "база"
      const списки = {
        открытый: итог.открытыйВход,
        ветвь: итог.правдаНаВетви,
        база: итог.базаСоСвободнымИменем,
        сказано: итог.ужеСказано,
      }
      const список = списки[какой] ?? списки.база
      process.stdout.write(`\n── ${какой} (${список.length}) ──\n${список.join("\n")}\n`)
    }
  }
}
