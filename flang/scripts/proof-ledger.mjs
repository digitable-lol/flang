/**
 * Ведомость одного файла, суженная до его собственных объявлений.
 *
 * @param {string} путь путь от корня репозитория
 * @returns {Promise<{путь: string, ведомость: object|null, беда: string|null}>}
 */
export async function ведомостьФайла(путь) {
  const полный = `${корень}${путь}`
  /* Свои имена — из СВЯЗАННОГО дерева минус подключения: `flang ast` связывает,
     а нам нужно ровно то, что объявлено здесь. Вычитает `своё`. */
  const мои = своё(полный)
  if (!мои.ok) return { путь, ведомость: null, беда: `разбор: ${мои.why}` }
  const свои = собственные(мои)

  const в = ведомость(полный)
  if (!в.ok) {
    /* Отвергнутое ядром считается и здесь, у файла без ведомости: иначе строка
       свода «отвергнуто ядром: 0» была бы тавтологией. Двоичный печатает
       ведомость даже когда отказывает, если дошёл до неё, — тогда счёт берётся
       из неё; если не дошёл, беда называется словами. */
    const отвергнуто = (в.ведомость?.claims ?? []).filter((з) => з?.verdict === "refused").length
    return { путь, ведомость: null, беда: `проверка: ${в.why ?? `код ${в.код}`}`, отвергнуто }
  }
  return { путь, ведомость: сузить(счастичными(в.ведомость, полный), свои), беда: null }
}

/**
 * Ведомость, к каждой строке которой дописано «проверка встретится и у тех,
 * кого функция зовёт».
 *
 * Само число мест частичных форм приезжает готовым — ключ `partialSites` в
 * строке функции, — и здесь не пересчитывается. Считает его двоичный по
 * программе, у которой доказанные места уже отмечены (`flang/self/proof.flang`,
 * «Строка с местами»), и это единственное место, где такой счёт вообще
 * возможен: отметки `доказана` в дереве `flang ast` нет.
 *
 * Дописывается здесь только замыкание по вызовам: оно про КОРПУС, а не про
 * модуль, и ведомости одного файла знать его неоткуда.
 */
function счастичными(ведомость, полный) {
  const д = дерево(полный)
  const функции = д.ok ? (д.дерево.functions ?? []) : []
  const сквозь = сквозьВызовы(ведомость, функции)
  return {
    ...ведомость,
    functions: ведомость.functions.map((строка) => ({
      ...строка,
      deepClean: !сквозь.has(строка.name),
    })),
  }
}

/**
 * Имена, при работе которых проверка ВСТРЕТИТСЯ — своя или чужая.
 *
 * Считается обратной достижимостью, а не обходом от каждой функции: разметить
 * весь граф от мест проверки назад — один проход, а спрашивать про каждую
 * функцию отдельно значит платить за граф столько раз, сколько в нём вершин.
 * Ответ тот же самый, стоит он линейно, и взаимная рекурсия ему не помеха:
 * пройденное второй раз не берётся.
 *
 * Оценка СВЕРХУ, ровно как у множества отказов процесса (`src/failures.mjs`):
 * «проверка встретится» здесь значит «в достижимом коде есть место проверки», а
 * не «есть вход, на котором она сработает». Второе неразрешимо, и ошибаться
 * безопасно можно только в эту сторону — назвать проверяющей ту, что могла бы и
 * не проверить, но никогда не назвать чистой ту, которая проверяет.
 */
function сквозьВызовы(ведомость, функции) {
  /* Посев — ОБЕ породы проверок. Посеять его одними сторожами меры значило бы
     назвать чистой функцию, которая зовёт `голова` у списка, — ровно ту ошибку,
     от которой это число заведено защищать. */
  const сторож = new Map(
    ведомость.functions.map((строка) => [строка.name, (строка.guardSites ?? 0) + (строка.partialSites ?? 0)]),
  )
  const обратные = new Map()
  const очередь = []
  for (const функция of функции) {
    const имя = функция?.name
    if (typeof имя !== "string") continue
    if ((сторож.get(имя) ?? 0) > 0) очередь.push(имя)
    for (const кого of именаВызовов(функция)) {
      if (!обратные.has(кого)) обратные.set(кого, new Set())
      обратные.get(кого).add(имя)
    }
  }
  const проверяют = new Set()
  while (очередь.length > 0) {
    const имя = очередь.pop()
    if (проверяют.has(имя)) continue
    проверяют.add(имя)
    for (const зовущий of обратные.get(имя) ?? []) очередь.push(зовущий)
  }
  return проверяют
}

/**
 * Кого функция зовёт — по дереву, которое отдал двоичный.
 *
 * Обход здесь ЧИСТО СТРУКТУРНЫЙ: берутся узлы вида `call` и `fnref`, и никакой
 * таблицы языка он не заводит. Тем он и отличается от счёта частичных форм,
 * который заводить нельзя: тому нужен список частичных форм и отметка
 * `доказана`, то есть знание языка, а этому — только вид узла.
 *
 * `fnref` наравне с `call`: функция, отданная в `отобразить` значением, БУДЕТ
 * вызвана, и её проверки — часть работы того, кто её отдал.
 */
function именаВызовов(функция) {
  const имена = new Set()
  const обойти = (узел) => {
    if (Array.isArray(узел)) {
      for (const э of узел) обойти(э)
      return
    }
    if (!узел || typeof узел !== "object") return
    if ((узел.kind === "call" || узел.kind === "fnref") && typeof узел.name === "string") имена.add(узел.name)
    for (const [ключ, значение] of Object.entries(узел)) if (ключ !== "span") обойти(значение)
  }
  обойти(функция?.body ?? null)
  return имена
}

/**
 * Имена, объявленные в самом файле.
 *
 * ЗАКОНОВ ЗДЕСЬ БОЛЬШЕ НЕТ, и это не упущение. Моноиды, монады, изоморфизмы,
 * вложения, пересечения и объявленные свойства — категорная поверхность, а её
 * двоичный НЕ СУДИТ ВОВСЕ: программу с такими объявлениями `flang check`
 * отвергает кодом 2 и называет пробел вслух. Значит, до сужения такой файл не
 * доезжает — он попадает в отказы поимённо, — а у файла, который доехал,
 * законов в ведомости не будет.
 *
 * Молча выбрасывать закон, если он всё-таки появился, нельзя: это ровно тот
 * случай, когда свод перестал бы считать и остался зелёным. Поэтому `сузить`
 * ниже на такой закон КРАСНЕЕТ, а не фильтрует.
 */
function собственные(программа) {
  const имена = (список, поле) =>
    new Set((Array.isArray(список) ? список : []).map((узел) => узел?.[поле]).filter((имя) => typeof имя === "string"))
  return { функции: имена(программа?.functions, "name") }
}

/**
 * Ведомость связанной программы, суженная до своих объявлений.
 *
 * Итоги пересчитываются, а не режутся: сумма по суженным строкам — это и есть
 * итог файла, а взять его из полной ведомости значило бы посчитать чужое.
 */
function сузить(ведомость, свои) {
  /* Закон в ведомости двоичного — событие, которого быть не может (см.
     `собственные`). Если оно случилось, значит поверхность в двоичный въехала,
     и свод обязан об этом сказать, а не отфильтровать по пустому списку имён. */
  const законов = (ведомость.laws?.length ?? 0) + (ведомость.assumed?.length ?? 0)
  if (законов > 0) {
    throw new Error(
      `двоичный напечатал ${законов} закон(ов) — категорная поверхность въехала в него,`
        + " и сужение свода по своим именам больше не годится: чинить `собственные`",
    )
  }
  const суженная = {
    ...ведомость,
    functions: ведомость.functions.filter((строка) => свои.функции.has(строка.name)),
    laws: [],
    assumed: [],
  }
  /* Утверждения сужаются по функции, а не по имени: имя постусловия уникально
     внутри функции, а не внутри программы, и сужать по нему значило бы терять
     одноимённые утверждения соседних модулей. Теорема наследия FTS функции не
     имеет вовсе — она остаётся, потому что живёт в самом файле. */
  if (Array.isArray(ведомость.claims)) {
    const свои_ = ведомость.claims.filter((з) => з.of === null || свои.функции.has(з.of))
    if (свои_.length > 0) суженная.claims = свои_
    else delete суженная.claims
  }
  /* Разрешения сужаются по тому же имени, что законы: разрешение выдано за
     закон и живёт там же, где он. Раздел исчезает целиком, когда своих
     разрешений в файле не осталось, — по тому же правилу, по какому он не
     появляется у программы, ничего не объявившей. */
  if (Array.isArray(ведомость.permits)) {
    const свои_ = ведомость.permits.filter((з) => свои.законы.has(з.name))
    if (свои_.length > 0) суженная.permits = свои_
    else delete суженная.permits
  }
  return { ...суженная, totals: сложить([{ ведомость: суженная }]) }
}

/** Свод итогов по любому набору ведомостей — тем же счётом, что в одной. */
function сложить(записи) {
  const итог = {
    functions: 0,
    total: 0,
    ordinary: 0,
    carriers: { composition: 0, structure: 0, exact: 0, step: 0, measure: 0 },
    unaccounted: 0,
    guardSites: 0,
    /* Второй сторож рантайма, и он многочисленнее первого. Считается ОТДЕЛЬНО
       от `guardSites`, а не вместе с ним: сторож меры стоит там, где анализ
       доказал завершение и оставил надзор за IEEE-754, а частичная форма — там,
       где обещания не давалось вовсе, и `тотальная` держится на честном отказе
       (`тотальная` значит «завершится или честно откажет», SPEC раздел 3).
       Сложить их в одно число значило бы вернуть тот самый `valid: true` на две
       разные вещи, ради различения которых ведомость и написана.

       `partialFunctions` и `partialTotal` — не «то же самое, поделённое иначе»:
       мест на функцию бывает до десяти, и число функций из числа мест не
       выводится. `noRuntimeCheck` — тотальные, у которых НЕТ НИ ОДНОГО места
       ни того, ни другого сторожа: это и есть то число, которым меряется цель
       языка, и до сегодня его не считал никто. */
    partialSites: 0,
    partialFunctions: 0,
    partialTotal: 0,
    noRuntimeCheck: 0,
    /* И то же самое, спрошенное честно до конца. «Во время работы не проверяет
       ничего» читается про РАБОТУ, а работа функции — это и работа тех, кого
       она зовёт: тотальная функция без единого места в теле, зовущая `«Голова
       списка»` из stdlib, во время работы проверку встретит. `noRuntimeCheck`
       отвечает про тело, `noRuntimeCheckDeep` — про замыкание вызовов: 2013 и
       1737. Оба нужны: первое говорит, чего стоит сама функция, второе — чего
       стоит её вызвать. */
    noRuntimeCheckDeep: 0,
    /* `violated` в законах — счёт ОПРОВЕРГНУТЫХ контрпримером (`work/ledger-honest`);
       снять его отсюда значило бы вернуть «нарушений не найдено» без поиска. */
    laws: { grid: 0, assumed: 0, violated: 0, permits: 0, gridValues: 0, gridPoints: 0 },
    /* Ключ `proved-induction` стоит здесь наравне с прочими, а не сворачивается
       в `proved`: пятое слово ведомости отвечает на другой вопрос — сколькими
       утверждениями покрыт БЕСКОНЕЧНЫЙ носитель, — и свернув его, свод вернул бы
       ту самую потерю различий, ради устранения которой он и написан. */
    claims: {
      total: 0,
      proved: 0,
      "proved-induction": 0,
      /* Разбивка `proved-induction` по НОСИТЕЛЮ принципа, и она не косметическая.
         «Индукцией по объявленной сумме» и «индукцией по отрезку «неотрицательное»»
         держатся на разном: первое — на начальности (часть значения меньше
         значения), второе — на конечности [0, 2⁵³−1] и строгом спуске, который
         ядро проверяет. Сложи их в одно число — и строка свода «индукцией по
         объявленной сумме» стала бы врать о каждом доказательстве по числу. */
      "proved-induction-algebra": 0,
      "proved-induction-segment": 0,
      /* И ТРЕТИЙ НОСИТЕЛЬ, и он тоже держится на своём: тело-свёртка даёт
         принцип по числу ВИТКОВ, а не по начальности списка. Сложи его с
         объявленной суммой — и строка свода сказала бы, что доказательство
         стоит на части значения, тогда как оно стоит на конечности обхода. */
      "proved-induction-fold": 0,
      "proved-declaration": 0,
      "proved-by-type": 0,
      /* ЧЕТВЁРТЫЙ ВЕРДИКТ, и стоит он ОТДЕЛЬНОЙ кучей, а не внутри `proved`.
         Утверждение с ним выведено, но вывод засчитал фактом посылку, которой
         ядро не доказало: обо всех входах оно верно ровно настолько, насколько
         верна посылка. Сложи его с `proved` — и число «доказано» стало бы
         больше знания ровно на эту кучу; до появления вердикта так и было. */
      "proved-conditional": 0,
      grid: 0,
      declared: 0,
      refused: 0,
      /* Утверждения, у которых ПРОГОН ПРИМЕРОВ нашёл контрпример. Число это про
         факт, а не про доказательство, и ноль в нём — единственное значение, при
         котором остальные числа свода что-то значат. */
      violated: 0,
      steps: 0,
    },
  }
  for (const { ведомость, отвергнуто } of записи) {
    /* Файл без ведомости считается ровно одним числом — отвергнутыми ядром
       утверждениями, — и считается ДО `continue`: иначе строка свода
       «отвергнуто ядром» отвечала бы только про файлы, где отвергать было
       нечего. */
    итог.claims.refused += отвергнуто ?? 0
    if (ведомость === null) continue
    for (const строка of ведомость.functions) {
      итог.functions += 1
      /* Частичные формы считаются и у ОБЫЧНЫХ функций: место проверки во время
         работы от пометки не зависит, и молчать про него у обычной значило бы
         мерить не рантайм, а обещания. Их в корпусе немного — ровно потому, что
         обычных функций мало, а не потому, что вопрос неважный. */
      const частичных = строка.partialSites ?? 0
      итог.partialSites += частичных
      if (частичных > 0) итог.partialFunctions += 1
      if (строка.total !== true) {
        итог.ordinary += 1
        continue
      }
      итог.total += 1
      итог.guardSites += строка.guardSites
      if (частичных > 0) итог.partialTotal += 1
      /* Главное число: тотальная, у которой во время работы не проверяется
         НИЧЕГО — ни сторожа меры, ни частичной формы. И оно же, спрошенное до
         конца: и у тех, кого она зовёт. */
      if (строка.guardSites === 0 && частичных === 0) итог.noRuntimeCheck += 1
      if (строка.deepClean === true) итог.noRuntimeCheckDeep += 1
      if (строка.carrier === null) итог.unaccounted += 1
      else итог.carriers[строка.carrier] += 1
    }
    for (const закон of ведомость.laws) {
      /* Закон, у которого контрпример НАЙДЕН, считается отдельно и не идёт ни в
         «на сетке», ни в значения: сложить его с посчитанными значило бы
         отчитаться о нарушенном законе как о чистом — ровно та неправда, из-за
         которой заведён этот счёт. Так же считает и ведомость одного файла
         (`proof.mjs`, `итоги_`), и расходиться этим двум счётам нельзя. */
      if (закон.verdict === "violated") {
        итог.laws.violated += 1
        continue
      }
      итог.laws.grid += 1
      итог.laws.gridValues += закон.grid?.values ?? 0
      итог.laws.gridPoints += закон.grid?.points ?? 0
    }
    итог.laws.assumed += ведомость.assumed.length
    итог.laws.permits += (ведомость.permits ?? []).length
    for (const запись of ведомость.claims ?? []) {
      итог.claims.total += 1
      итог.claims.steps += запись.steps ?? 0
      /* Вердикт кладётся по своему ключу, а не по «плохой/хороший»: разница
         между «доказано», «сетка» и «объявлено, не доказано» и есть весь смысл
         этого счёта, и свернуть её в два числа значило бы вернуть тот самый
         один `valid: true` на три разные вещи.

         Одно исключение, и оно названо: доказанное индукцией считается ДВАЖДЫ —
         в `proved` и в `proved-induction`. Не описка: `proved` отвечает на
         вопрос «сколько утверждений верны обо всех входах», а `proved-induction`
         — на другой, «у скольких из них носитель бесконечен». Так же считает и
         ведомость одного файла (`proof.mjs`, `итоги_`), и расходиться этим двум
         счётам нельзя. */
      if (запись.verdict === "proved-induction") {
        итог.claims["proved-induction"] += 1
        /* Носитель приезжает сюда из вердикта ядра, а не решается здесь заново:
           второй ответ на тот же вопрос разошёлся бы с первым молча. */
        const носитель = запись.induction?.carrier === "segment"
          ? "segment"
          : запись.induction?.carrier === "fold" ? "fold" : "algebra"
        итог.claims[`proved-induction-${носитель}`] += 1
      }
      /* И второе такое же уточнение, по той же причине: `proved-declaration`
         отвечает на вопрос «сколько утверждений выведено БЕЗ единого написанного
         терма — одним сведением цели с телом функции». Оно тоже считается
         дважды — в `proved` и здесь, — потому что доказанность у них одна, а
         способ разный.

         `proved-by-type` — подсчёт внутри него, и заведён он потому, что своими
         словами эти два числа разные. Утверждение «результат не меньше 0» у
         функции над `строка` сводится восемью литералами под выбором и НИ ОДНОГО
         объявления не читает; сложи их в одно — и свод сказал бы «по объявленным
         типам» о доказательстве, которому объявления не понадобились. Считает не
         свод: `proofterm.mjs` спрашивает у `свести` тот же вопрос без
         объявлений, а сюда приезжает ответ. */
      if (запись.by === "declaration") итог.claims["proved-declaration"] += 1
      if (запись.byType === true) итог.claims["proved-by-type"] += 1
      if (запись.verdict === "proved-induction") итог.claims.proved += 1
      else if (запись.verdict in итог.claims) итог.claims[запись.verdict] += 1
    }
  }
  return итог
}

/**
 * ПОДМЕНА СЛОВА: строка утверждения, названная словом не своего вердикта.
 *
 * Считается ЗДЕСЬ, на всём корпусе, а не только на подделке: словарь, за
 * которым следят в одном файле, разъезжается во всех остальных. Правило и
 * словарь лежат одним экземпляром в `flang/scripts/word-guard.mjs` — второй
 * список слов разошёлся бы с первым молча.
 *
 * Найденное — не замечание к программе, а РАСХОЖДЕНИЕ ведомости с собой, и свод
 * от него краснеет: число «доказано N» при подмене слова ничего не стоит.
 */
export function подменыСлов(файлы) {
  const беды = []
  for (const { путь, ведомость: в } of файлы) {
    for (const з of в?.claims ?? []) {
      const ждём = СЛОВАРЬ.get(з.verdict)
      if (ждём === undefined) { беды.push(`${путь}: «${з.name}» — вердикт «${з.verdict}» словарю неизвестен`); continue }
      const сказано = словоСтроки(з.says)
      if (сказано === null) { беды.push(`${путь}: «${з.name}» — строка начата словом вне словаря: «${String(з.says).slice(0, 40)}…»`); continue }
      if (сказано !== ждём.слово) беды.push(`${путь}: «${з.name}» — вердикт ${з.verdict} (${ждём.сила}), а сказано словом «${сказано}»`)
      /* «Доказано ПРИ УСЛОВИИ» начинается словом «доказано» законно: слово
         своё, и словарь его знает. Красить надо не его, а сетку и объявленное,
         в которых это слово стоять не имеет права. */
      else if (з.verdict !== "proved" && з.verdict !== "proved-induction" && з.verdict !== "proved-conditional" && говоритДоказано(з.says))
        беды.push(`${путь}: «${з.name}» — вердикт ${з.verdict}, а в строке сказано «доказано»`)
    }
  }
  return беды
}

/**
 * ПУСТОТА по названной маске: сколько из доказанного что-то ЗНАЧИТ.
 *
 * Спрашивается прогоном — тело заменяется заглушкой того же объявленного типа,
 * — и потому стоит дорого: два прогона проверки на каждое доказанное
 * утверждение. Поэтому не по всему корпусу, а по маске, и обсчитанное
 * подмножество называется в выводе поимённо: подмена молчания на «чисто» и есть
 * то, ради чего этот счёт заведён.
 */
export async function пустотаПоМаске(маска) {
  const { readFileSync } = await import("node:fs")
  const пути = globSync(маска, { cwd: корень }).filter((п) => !п.startsWith("flang/test/fixtures/")).sort()
  const счёт = { файлов: пути.length, доказано: 0, содержательное: 0, "про подпись": 0, даровое: 0, "не судили": 0 }
  const строки = []
  for (const путь of пути) {
    const в = ведомость(`${корень}${путь}`)
    if (!в.ok) { строки.push(`  ${путь}: ведомости нет — не судили`); continue }
    const д = дерево(`${корень}${путь}`)
    if (!д.ok) { строки.push(`  ${путь}: дерева нет — не судили`); continue }
    const исходник = readFileSync(`${корень}${путь}`, "utf8")
    for (const з of в.ведомость.claims ?? []) {
      if (!String(з.verdict).startsWith("proved")) continue
      счёт.доказано += 1
      const { куча, почему } = пустота(путь, з, д.дерево, исходник)
      счёт[куча] += 1
      строки.push(`  ${путь}: «${з.name}» — ${куча.toUpperCase()} (${почему})`)
    }
  }
  return { счёт, строки }
}

/**
 * СКОЛЬКО ПРОВЕРОК РАЗОМ, и почему это стало ключом среды.
 *
 * Прогрев вееров `binary.mjs` пускает по умолчанию до 64 проверок
 * одновременно. Одна проверка крупного файла берёт 5—25 ГиБ, и на общей машине
 * такой веер — это ровно тот случай, каким 21 августа 2026 машина встала на 87
 * минут: двенадцать срабатываний убийцы памяти, `constraint=CONSTRAINT_NONE`,
 * то есть кончилась ВСЯ память, а не предел какой-то группы.
 *
 * Умолчание не тронуто — на пустой машине веер и есть то, ради чего свод
 * считается пять минут, а не час. Но у зовущего теперь есть чем его прижать:
 *
 *   FLANG_POTOKOV=4 node flang/scripts/proof-ledger.mjs
 *
 * Свод, которым нельзя воспользоваться, не считая машину, — это несчитанный
 * свод.
 */
const ПОТОКОВ = Number.parseInt(process.env.FLANG_POTOKOV ?? "", 10) || 0

/**
 * Свод по всему корпусу.
 *
 * @returns {Promise<{файлы: object[], итог: object, подмены: string[], отказы: object[]}>}
 */
export async function сводКорпуса() {
  const все = ФАЙЛЫ.map((путь) => `${корень}${путь}`)
  прогретьВедомости(все, ПОТОКОВ)
  прогреть(все, ПОТОКОВ)
  const файлы = []
  for (const путь of ФАЙЛЫ) файлы.push(await ведомостьФайла(путь))
  return {
    файлы,
    итог: сложить(файлы),
    подмены: подменыСлов(файлы),
    /* Файл, о котором ведомости нет, называется отдельно и по имени. Тихо
       пропущенный файл — это охват, который меняется молча, и число, которое
       нельзя перепроверить (та же беда, что у корпуса моделей ядра). */
    отказы: файлы.filter((запись) => запись.ведомость === null),
  }
}

function печать(свод, поФайлам) {
  const и = свод.итог
  const строки = ["── свод ведомости доказательства по корпусу ──"]
  if (поФайлам) {
    for (const запись of свод.файлы) {
      if (запись.ведомость === null) {
        строки.push(`  ${запись.путь}: ведомости нет — ${запись.беда}`)
        continue
      }
      const ф = сложить([запись])
      строки.push(
        `  ${запись.путь}: функций ${ф.functions}, тотальных ${ф.total} `
          + `(композиция ${ф.carriers.composition}, структура ${ф.carriers.structure}, `
          + `точный шаг ${ф.carriers.exact}, шаг ${ф.carriers.step}, мера ${ф.carriers.measure}), `
          + `сторожей меры ${ф.guardSites}, частичных форм ${ф.partialSites}, `
          + `законов на сетке ${ф.laws.grid}, на веру ${ф.laws.assumed}`
          /* ТРИ ЧИСЛА, А НЕ ОДНО. «Утверждений N (доказано D)» умалчивало о том,
             чем несётся разница N − D, а несётся она двумя РАЗНЫМИ вещами:
             счётом на сетке и голым объявлением. Сложенные под одним молчанием,
             они читаются как «почти доказано». */
          + `${ф.claims.total === 0 ? "" : `, утверждений ${ф.claims.total} (доказано ядром ${ф.claims.proved}, на сетке ${ф.claims.grid}, объявлено ${ф.claims.declared})`}`,
      )
    }
    строки.push("")
  }
  строки.push(
    `файлов в корпусе: ${свод.файлы.length}, из них с ведомостью: ${свод.файлы.length - свод.отказы.length}`,
    `функций: ${и.functions} — тотальных ${и.total}, обычных ${и.ordinary}`,
    `чем несётся обещание «тотальная» (доказано — про ВСЕ входы):`,
    `  композицией (рекурсии нет):        ${и.carriers.composition}`,
    `  структурой (часть значения):       ${и.carriers.structure}`,
    `  точным шагом («неотрицательное», сторожа нет):  ${и.carriers.exact}`,
    `  постоянным шагом (число + сторож): ${и.carriers.step}`,
    `  объявленной мерой (+ сторож):      ${и.carriers.measure}`,
    `что проверяется во время работы (обещание «тотальная» — «завершится или честно откажет»):`,
    `  сторож меры:      ${и.guardSites} мест у ${и.carriers.step + и.carriers.measure} функций`,
    `  частичная форма:  ${и.partialSites} мест у ${и.partialFunctions} функций (тотальных среди них ${и.partialTotal})`,
    `  всего:            ${и.guardSites + и.partialSites} мест`,
    `тотальных, у которых во время работы не проверяется НИЧЕГО: ${и.noRuntimeCheck}`,
    `  из них не проверяется ничего и у тех, кого они зовут: ${и.noRuntimeCheckDeep}`,
    `законы (сетка конечна, доказательством не является):`,
    `  на сетке: ${и.laws.grid}, значений в сетках ${и.laws.gridValues}, точек ${и.laws.gridPoints}`,
    `  на веру:  ${и.laws.assumed}`,
    `  НАРУШЕНО (контрпример найден): ${и.laws.violated}`,
    `утверждения о поведении (постусловия и теоремы):`,
    `  доказано ядром (обо ВСЕХ входах):  ${и.claims.proved}`,
    `  из них индукцией: ${и.claims["proved-induction"]}`,
    `    по объявленной сумме (начальность): ${и.claims["proved-induction-algebra"]}`,
    `    по отрезку «неотрицательное» (конечность и строгий спуск): ${и.claims["proved-induction-segment"]}`,
    `    по свёртке тела (конечность числа витков): ${и.claims["proved-induction-fold"]}`,
    `  из них без теоремы (цель сведена с телом): ${и.claims["proved-declaration"]}`,
    `    из них факт дал объявленный тип аргумента: ${и.claims["proved-by-type"]}`,
    /* Отдельная строка, и она обязана стоять СРАЗУ за «доказано ядром»:
       читатель, дошедший до сетки, число «доказано» уже принял. */
    `  доказано ПРИ УСЛОВИИ (опёрлось на недоказанную посылку): ${и.claims["proved-conditional"]}`,
    `  сетка (примеры или закон):         ${и.claims.grid}`,
    `  объявлено, не доказано:            ${и.claims.declared}`,
    `  отвергнуто ядром:                  ${и.claims.refused}`,
    /* Шестая строка, и она про факт: у скольких утверждений ПРОГОН примеров
       нашёл контрпример. До появления поиска ведомость этого не знала вовсе и
       печатала о таком утверждении «сетка N значений: нарушений не найдено». */
    `  НАРУШЕНО на примерах автора:       ${и.claims.violated}`,
    `  всего высказано: ${и.claims.total}, шагов в принятых термах: ${и.claims.steps}`,
    /* ЧЕТВЁРТОЕ РАЗЛИЧИЕ, И МОЛЧАТЬ О НЁМ НЕЛЬЗЯ. Внутри «доказано ядром» лежат
       утверждения, верные про ЛЮБУЮ функцию этой подписи: «результат не меньше
       нуля» у функции, объявленной возвращающей «неотрицательное», доказывается и при
       выброшенном теле. Отделяется это ПРОГОНОМ с заглушкой, прогон стоит два
       вызова проверки на утверждение, и по всему корпусу свод его не гоняет.
       Тогда единственный честный ответ — «не судили», а не молчание: молчание
       читается как «всё содержательно», и число «доказано» становится верхней
       оценкой, выданной за точную. */
    `  ПУСТОТА (пережило ли утверждение подмену тела заглушкой) НЕ СУДИЛАСЬ ни у одного из ${и.claims.proved}:`,
    `    свод её не гоняет — два прогона проверки на каждое доказанное утверждение;`,
    `    спросить по маске:  node flang/scripts/proof-ledger.mjs --pustota 'flang/stdlib/*.flang'`,
    `    пока не спрошено, «доказано ядром ${и.claims.proved}» — ВЕРХНЯЯ оценка знания, а не точная`,
  )
  if (и.unaccounted > 0) строки.push(`РАСХОЖДЕНИЕ: носитель не назван у ${и.unaccounted} тотальных функций`)
  /* Подмена слова считается тем же прогоном и красит его: число «доказано N»
     при вердикте, названном чужим словом, не стоит ничего. */
  if ((свод.подмены ?? []).length > 0) {
    строки.push(`РАСХОЖДЕНИЕ: слово вердикта подменено в ${свод.подмены.length} мест(ах):`)
    for (const беда of свод.подмены) строки.push(`  ${беда}`)
  } else строки.push("слово вердикта нигде не подменено: сильное слово про слабое основание не сказано ни разу")
  for (const запись of свод.отказы) строки.push(`без ведомости: ${запись.путь} — ${запись.беда}`)
  return `${строки.join("\n")}\n`
}

/* Сравниваются РАЗРЕШЁННЫЕ пути, а не строки, — по той же причине, что в
   `flang/bin/flang.mjs`: npm ставит команды символьными ссылками, и путь ссылки с
   путём файла не совпадает. Сравнение строк дало бы ложь, свод не запустился бы и
   вышел с кодом 0, не напечатав ни байта. */
let запущен = false
if (process.argv[1] !== undefined) {
  try {
    запущен = realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
  } catch {
    запущен = false
  }
}
if (запущен) {
  /* ПУСТОТА — отдельный, дорогой вопрос, и задаётся он по маске. Свод корпуса
     при нём не считается: смешать в одном прогоне пятиминутный обход и обход
     с двумя проверками на утверждение значило бы не спросить ни одного из
     двух. */
  const где = process.argv.indexOf("--pustota")
  if (где !== -1) {
    const маска = process.argv[где + 1] ?? "flang/stdlib/*.flang"
    const { счёт, строки } = await пустотаПоМаске(маска)
    /* МАСКА, НЕ НАКРЫВШАЯ НИ ОДНОГО ФАЙЛА, — ЭТО ОТКАЗ, А НЕ ЧИСТОТА. Иначе
       опечатка в маске (или фигурные скобки, которых `globSync` дерева не
       понимает) печатала бы четыре нуля и код 0 — счёт, физически не способный
       показать провал. Поймано на себе: маска `{logic,optional}.flang` дала
       «файлов: 0, доказано 0» и зелёный код. */
    if (счёт.файлов === 0) {
      process.stderr.write(`маска «${маска}» не накрыла ни одного файла — это ОТКАЗ, а не «нечего судить».\n`)
      process.stderr.write("Фигурные скобки обходчик дерева не понимает; пишите звёздочкой: 'flang/stdlib/*.flang'.\n")
      process.exitCode = 2
    } else {
    process.stdout.write(`${строки.join("\n")}\n\n`)
    process.stdout.write(
      [
        `── пустота по маске «${маска}» ──`,
        `файлов: ${счёт.файлов}`,
        `доказано ядром:                    ${счёт.доказано}`,
        `  СОДЕРЖАТЕЛЬНЫХ (с заглушкой отпадает):   ${счёт.содержательное}`,
        `  про подпись (с заглушкой остаётся):      ${счёт["про подпись"]}`,
        `  даровых (спека переписана с тела):       ${счёт.даровое}`,
        `  НЕ СУДИЛИ (заглушки для типа нет):       ${счёт["не судили"]}`,
        "«не судили» — это не «замечаний нет»: куча названа отдельно нарочно.",
        "",
      ].join("\n"),
    )
    process.exitCode = 0
    }
  } else {
    const свод = await сводКорпуса()
    if (process.argv.includes("--json")) {
      process.stdout.write(`${JSON.stringify({ итог: свод.итог, подмены: свод.подмены, отказы: свод.отказы.map((з) => ({ путь: з.путь, беда: з.беда })) }, null, 2)}\n`)
    } else {
      process.stdout.write(печать(свод, process.argv.includes("--files")))
    }
    /* НИЖНЯЯ ГРАНИЦА КОРПУСА — то же правило, что тремя десятками строк выше
       про маску, только здесь его не было. Прежде код возврата зависел ТОЛЬКО
       от `unaccounted` и подмен, а файлы БЕЗ ВЕДОМОСТИ печатались строкой и на
       приговор не влияли вовсе. Значит прогон, в котором двоичный не ответил
       НИ РАЗУ, выходил зелёным: складывать нечего — расхождений ноль.

       Замер 29 августа 2026 на этой машине: FLANG_BINARY на программу, всегда
       отвечающую кодом 1, — все файлы корпуса ушли в «без ведомости», и
       `echo $?` показал 0.

       Код 2, а не 1: корпус не разошёлся, его нечем было посчитать. */
    const всего = свод.файлы.length
    const безВедомости = свод.отказы.length
    if (всего === 0 || безВедомости === всего) {
      process.stderr.write(
        `\nВЕДОМОСТЬ НЕ СНЯТА НИ У ОДНОГО ФАЙЛА: файлов ${всего}, без ведомости ${безВедомости}.\n`,
      )
      process.stderr.write(
        "Это ОТКАЗ, а не «расхождений нет»: считать было нечего, и нули выше — нули пустого счёта,\n" +
          "а не доказанная чистота. Проверьте, что двоичный на месте и отвечает: bootstrap/flang --version.\n",
      )
      process.exitCode = 2
    } else {
      process.exitCode = свод.итог.unaccounted === 0 && свод.подмены.length === 0 ? 0 : 1
    }
  }
}
