/**
 * Свод ведомости доказательства по всему корпусу `.flang`.
 *
 * `flang check --proof` печатает ведомость одного модуля. Этапы плана меряются
 * не модулем, а корпусом, и складывать вывод глазами — то же самое, что не
 * мерить: числа надо получать одной командой и одним способом.
 *
 * ── Почему свод считает не так, как первый замер ─────────────────────────────
 * Первый замер поверхности доказуемости разбирал каждый файл ОТДЕЛЬНО и не
 * связывал импорты. На восьми файлах корпуса это даёт другой ответ, и ответ
 * этот неверный: `flang/self/lexer.flang` зовёт функции из
 * `flang/self/strings.flang`, и в одиночку его тотальные функции не проходят
 * анализ вовсе («вызывает неизвестную функцию»). Недоказанность заразна, весь
 * цикл уходит в отказ, и рекурсия, которую он несёт, в свод рекурсий не
 * попадает. Замер при этом считал рекурсию своим обходом AST, без анализа, и
 * потому её видел — а сторожа брал из анализа, уже отфильтрованного. Две
 * половины одного числа считались по разным правилам.
 *
 * Здесь программа загружается ТЕМ ЖЕ загрузчиком, что у `flang check`: со
 * связыванием, с отметкой меры, целиком. Цена — импортированные функции
 * приезжают в программу вместе со своими, поэтому в свод от каждого файла
 * берутся только СВОИ объявления: те, что есть в его собственном разборе. Иначе
 * `flang/stdlib/lists.flang` посчитался бы столько раз, сколько модулей его
 * зовут.
 *
 * ── Сторожей в рантайме ДВА, и до 16 августа свод считал один ───────────────
 * Строка «сторожей в рантайме: 100 мест» была неполной, и разница у неё не в
 * оттенке, а в разы. Проверок во время работы в напечатанном коде две породы:
 *
 *   СТОРОЖ МЕРЫ — 100 мест у 66 функций. Ставит его понижение (`src/defunc.mjs`,
 *     `renderGuard` и `renderDescentGuard`) на рекурсивный вызов, чьё завершение
 *     доказано ЧИСЛОМ: в вещественных числах доказательство полное, в IEEE-754
 *     `x − 1` при большом |x| равен `x`, и надзор остаётся за этим.
 *   ЧАСТИЧНАЯ ФОРМА — 280 мест у 155 функций, то есть почти втрое больше.
 *     Встроенная форма, определённая не на всех значениях своего типа: `голова`
 *     пустого списка, `элемент` за концом, `к числу` от строки, которая числом
 *     не является. Список их закрыт и назван (`ЧАСТИЧНЫЕ` в `src/failures.mjs`),
 *     а место каждой — проверка в напечатанном коде и в интерпретаторе.
 *
 * Считать надо обе, и порознь. Обе — «где `тотальная` честно откажет» (SPEC,
 * раздел 3: `тотальная` значит «завершится либо честно отказывает»), но несут
 * они разное: сторож меры стоит там, где завершение ДОКАЗАНО и надзор остался за
 * представлением чисел, а частичная форма — там, где о непустоте списка не
 * доказано ничего и вся разница между «работает» и «отказывает» решается на
 * входе. Сложенные в одно число, они снова дают тот самый `valid: true` на две
 * разные вещи.
 *
 * Мест частичных форм СНИМАЕТСЯ НОЛЬ: анализа непустоты в языке нет вовсе, и
 * печать проверена на этом — каждое место частичной формы в дереве становится
 * ровно одним вызовом стерегущего помощника в напечатанном коде, ни одно не
 * исчезает (`flang/test/proof.test.mjs`, «каждое место частичной формы …»).
 * Поэтому главное число проекта — не «тотальных минус мест сторожа» (так
 * получалось 2096, и это вычитание МЕСТ из ФУНКЦИЙ), а `noRuntimeCheck`:
 * тотальные, у которых нет ни одного места ни того сторожа, ни другого. Их 2013.
 *
 * Запуск:
 *   node flang/scripts/proof-ledger.mjs             свод словами
 *   node flang/scripts/proof-ledger.mjs --json      свод машине
 *   node flang/scripts/proof-ledger.mjs --files     ещё и по файлу на строку
 */
import { readFileSync, realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgram } from "../bin/flang.mjs"
import { именаВызовов, местЧастичныхФорм } from "../src/failures.mjs"
import { parse } from "../src/parser.mjs"
import { proofLedger } from "../src/proof.mjs"
import { globSync } from "../test/glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/**
 * Файлы корпуса.
 *
 * Склеенный самоприменением компилятор исключён по той же причине, по которой
 * его исключал первый замер: это не отдельный модуль, а сборка всех остальных,
 * и его функции посчитались бы дважды.
 */
export const ФАЙЛЫ = globSync("flang/**/*.flang", { cwd: корень })
  .filter((путь) => путь !== "flang/self/bootstrap/compiler.flang")
  .sort()

/**
 * Ведомость одного файла, суженная до его собственных объявлений.
 *
 * @param {string} путь путь от корня репозитория
 * @returns {Promise<{путь: string, ведомость: object|null, беда: string|null}>}
 */
export async function ведомостьФайла(путь) {
  const полный = `${корень}${путь}`
  let свои
  try {
    /* Свои имена — из ОДИНОЧНОГО разбора: связанная программа не помнит, что в
       ней откуда, а нам нужно ровно то, что объявлено здесь. */
    свои = собственные(parse(readFileSync(полный, "utf8"), путь))
  } catch (беда) {
    return { путь, ведомость: null, беда: `разбор: ${беда?.message ?? String(беда)}` }
  }
  let программа
  try {
    программа = await loadProgram(полный)
  } catch (беда) {
    return { путь, ведомость: null, беда: `загрузка: ${беда?.message ?? String(беда)}` }
  }
  const внешнее = await externalChecks(программа)
  const отказы = внешнее.diagnostics.filter((беда) => беда?.severity !== "warning")
  if (отказы.length > 0) {
    /* ОТВЕРГНУТОЕ ЯДРОМ СЧИТАЕТСЯ И ЗДЕСЬ, У ФАЙЛА БЕЗ ВЕДОМОСТИ. Без этого
       строка свода «отвергнуто ядром: 0» была тавтологией: отвергнутый терм —
       это отказ, у отказного файла ведомости нет, а свод складывал только
       ведомости. Ноль в такой строке означал не «искали и не нашли», а «сюда
       такое не попадает» — та же неправда, что и «нарушений не найдено» без
       поиска, только в своде. Теперь ноль означает ровно то, что написано. */
    const отвергнуто = (внешнее.results?.proofs?.checked ?? [])
      .filter((з) => з?.verdict === "отвергнуто").length
    return { путь, ведомость: null, беда: `проверка: ${отказы[0].message}`, отвергнуто }
  }
  return { путь, ведомость: сузить(счастичными(proofLedger(программа, внешнее.results), программа), свои), беда: null }
}

/**
 * Ведомость, к каждой строке которой дописано число мест частичных форм.
 *
 * Дописывается здесь, а не в `proof.mjs`, и это названная граница, а не лень:
 * ведомость модуля печатается ещё и на самом flang (`flang/self/proof.flang`), и
 * её строка сверяется с эталоном ПОБАЙТОВО. Новое поле в строке значит новое
 * поле у близнеца, а обхода дерева по списку частичных форм у него нет. Свод же
 * — инструмент корпуса, близнеца у него нет вовсе, и считать он обязан всё, что
 * во время работы проверяется, иначе его главное число неправда.
 *
 * Тело берётся у СВЯЗАННОЙ программы, то есть у той, что уезжает в печать: на
 * ней уже стоит отметка меры, и частичная форма внутри объявленной меры
 * считается столько раз, сколько раз мера считается на витке. По корпусу это
 * ровно два места сверх исходника — оба в `«Полоса слоя»`
 * (`examples/leetcode/733-flood-fill.flang`), где мера читает `элемент ряд в
 * сетка`.
 */
function счастичными(ведомость, программа) {
  const мест = new Map()
  for (const функция of программа?.functions ?? []) {
    if (typeof функция?.name === "string") мест.set(функция.name, местЧастичныхФорм(функция))
  }
  const сквозь = сквозьВызовы(ведомость, программа, мест)
  return {
    ...ведомость,
    functions: ведомость.functions.map((строка) => ({
      ...строка,
      partialSites: мест.get(строка.name) ?? 0,
      /* Не «есть ли проверка у неё», а «доберётся ли работа до проверки»:
         функция без единого места в теле работает через тех, кого зовёт, и их
         проверки — часть её работы. */
      deepClean: !сквозь.has(строка.name),
    })),
  }
}

/**
 * Имена, при работе которых проверка ВСТРЕТИТСЯ — своя или чужая.
 *
 * Считается обратной достижимостью, а не обходом от каждой функции: разметить
 * весь граф от мест проверки назад — один проход, а спрашивать про каждую
 * функцию отдельно значит платить за граф столько раз, сколько в нём вершин.
 * Ответ тот же самый, стоит он линейно, и взаимная рекурсия ему не помеха:
 * пройденное второй раз не берётся.
 *
 * Оценка СВЕРХУ, ровно как у множества отказов процесса (`src/failures.mjs`):
 * «проверка встретится» здесь значит «в достижимом коде есть место проверки», а
 * не «есть вход, на котором она сработает». Второе неразрешимо, и ошибаться
 * безопасно можно только в эту сторону — назвать проверяющей ту, что могла бы и
 * не проверить, но никогда не назвать чистой ту, которая проверяет.
 */
function сквозьВызовы(ведомость, программа, мест) {
  const сторож = new Map(ведомость.functions.map((строка) => [строка.name, строка.guardSites ?? 0]))
  const обратные = new Map()
  const очередь = []
  for (const функция of программа?.functions ?? []) {
    const имя = функция?.name
    if (typeof имя !== "string") continue
    if ((мест.get(имя) ?? 0) > 0 || (сторож.get(имя) ?? 0) > 0) очередь.push(имя)
    for (const кого of именаВызовов(функция)) {
      if (!обратные.has(кого)) обратные.set(кого, new Set())
      обратные.get(кого).add(имя)
    }
  }
  const проверяют = new Set()
  while (очередь.length > 0) {
    const имя = очередь.pop()
    if (проверяют.has(имя)) continue
    проверяют.add(имя)
    for (const зовущий of обратные.get(имя) ?? []) очередь.push(зовущий)
  }
  return проверяют
}

/** Имена, объявленные в самом файле: функции и все виды законов. */
function собственные(программа) {
  const имена = (список, поле) =>
    new Set((Array.isArray(список) ? список : []).map((узел) => узел?.[поле]).filter((имя) => typeof имя === "string"))
  return {
    функции: имена(программа?.functions, "name"),
    законы: new Set([
      ...имена(программа?.monoids, "name"),
      ...имена(программа?.monads, "name"),
      ...имена(программа?.isomorphisms, "name"),
      ...имена(программа?.embeddings, "name"),
      ...имена(программа?.intersections, "name"),
      /* Объявленное свойство зовётся по той функции, о которой говорит, — своего
         имени у него нет и быть не должно: закон об «Начислить» и есть закон об
         «Начислить». Значит и в свод он попадает по имени операции. Забыть эту
         строку значило бы вырезать пять законов из свода молча — свод остался бы
         зелёным и перестал бы считать то, ради чего заводился. */
      ...имена(программа?.properties, "operation"),
      ...имена(программа?.properties, "function"),
    ]),
  }
}

/**
 * Ведомость связанной программы, суженная до своих объявлений.
 *
 * Итоги пересчитываются, а не режутся: сумма по суженным строкам — это и есть
 * итог файла, а взять его из полной ведомости значило бы посчитать чужое.
 */
function сузить(ведомость, свои) {
  const суженная = {
    ...ведомость,
    functions: ведомость.functions.filter((строка) => свои.функции.has(строка.name)),
    laws: ведомость.laws.filter((закон) => свои.законы.has(закон.name)),
    assumed: ведомость.assumed.filter((запись) => свои.законы.has(запись.name)),
  }
  /* Утверждения сужаются по функции, а не по имени: имя постусловия уникально
     внутри функции, а не внутри программы, и сужать по нему значило бы терять
     одноимённые утверждения соседних модулей. Теорема наследия FTS функции не
     имеет вовсе — она остаётся, потому что живёт в самом файле. */
  if (Array.isArray(ведомость.claims)) {
    const свои_ = ведомость.claims.filter((з) => з.of === null || свои.функции.has(з.of))
    if (свои_.length > 0) суженная.claims = свои_
    else delete суженная.claims
  }
  /* Разрешения сужаются по тому же имени, что законы: разрешение выдано за
     закон и живёт там же, где он. Раздел исчезает целиком, когда своих
     разрешений в файле не осталось, — по тому же правилу, по какому он не
     появляется у программы, ничего не объявившей. */
  if (Array.isArray(ведомость.permits)) {
    const свои_ = ведомость.permits.filter((з) => свои.законы.has(з.name))
    if (свои_.length > 0) суженная.permits = свои_
    else delete суженная.permits
  }
  return { ...суженная, totals: сложить([{ ведомость: суженная }]) }
}

/** Свод итогов по любому набору ведомостей — тем же счётом, что в одной. */
function сложить(записи) {
  const итог = {
    functions: 0,
    total: 0,
    ordinary: 0,
    carriers: { composition: 0, structure: 0, exact: 0, step: 0, measure: 0 },
    unaccounted: 0,
    guardSites: 0,
    /* Второй сторож рантайма, и он многочисленнее первого. Считается ОТДЕЛЬНО
       от `guardSites`, а не вместе с ним: сторож меры стоит там, где анализ
       доказал завершение и оставил надзор за IEEE-754, а частичная форма — там,
       где обещания не давалось вовсе, и `тотальная` держится на честном отказе
       (`тотальная` значит «завершится или честно откажет», SPEC раздел 3).
       Сложить их в одно число значило бы вернуть тот самый `valid: true` на две
       разные вещи, ради различения которых ведомость и написана.

       `partialFunctions` и `partialTotal` — не «то же самое, поделённое иначе»:
       мест на функцию бывает до десяти, и число функций из числа мест не
       выводится. `noRuntimeCheck` — тотальные, у которых НЕТ НИ ОДНОГО места
       ни того, ни другого сторожа: это и есть то число, которым меряется цель
       языка, и до сегодня его не считал никто. */
    partialSites: 0,
    partialFunctions: 0,
    partialTotal: { functions: 0, sites: 0 },
    noRuntimeCheck: 0,
    /* И то же самое, спрошенное честно до конца. «Во время работы не проверяет
       ничего» читается про РАБОТУ, а работа функции — это и работа тех, кого
       она зовёт: тотальная функция без единого места в теле, зовущая `«Голова
       списка»` из stdlib, во время работы проверку встретит. `noRuntimeCheck`
       отвечает про тело, `noRuntimeCheckDeep` — про замыкание вызовов: 2013 и
       1737. Оба нужны: первое говорит, чего стоит сама функция, второе — чего
       стоит её вызвать. */
    noRuntimeCheckDeep: 0,
    /* `violated` в законах — счёт ОПРОВЕРГНУТЫХ контрпримером (`work/ledger-honest`);
       снять его отсюда значило бы вернуть «нарушений не найдено» без поиска. */
    laws: { grid: 0, assumed: 0, violated: 0, gridValues: 0, gridPoints: 0 },
    /* Ключ `proved-induction` стоит здесь наравне с прочими, а не сворачивается
       в `proved`: пятое слово ведомости отвечает на другой вопрос — сколькими
       утверждениями покрыт БЕСКОНЕЧНЫЙ носитель, — и свернув его, свод вернул бы
       ту самую потерю различий, ради устранения которой он и написан. */
    claims: {
      total: 0,
      proved: 0,
      "proved-induction": 0,
      /* Разбивка `proved-induction` по НОСИТЕЛЮ принципа, и она не косметическая.
         «Индукцией по объявленной сумме» и «индукцией по отрезку «нат»»
         держатся на разном: первое — на начальности (часть значения меньше
         значения), второе — на конечности [0, 2⁵³−1] и строгом спуске, который
         ядро проверяет. Сложи их в одно число — и строка свода «индукцией по
         объявленной сумме» стала бы врать о каждом доказательстве по числу. */
      "proved-induction-algebra": 0,
      "proved-induction-segment": 0,
      "proved-declaration": 0,
      "proved-by-type": 0,
      grid: 0,
      declared: 0,
      refused: 0,
      /* Утверждения, у которых ПРОГОН ПРИМЕРОВ нашёл контрпример. Число это про
         факт, а не про доказательство, и ноль в нём — единственное значение, при
         котором остальные числа свода что-то значат. */
      violated: 0,
      steps: 0,
    },
  }
  for (const { ведомость, отвергнуто } of записи) {
    /* Файл без ведомости считается ровно одним числом — отвергнутыми ядром
       утверждениями, — и считается ДО `continue`: иначе строка свода
       «отвергнуто ядром» отвечала бы только про файлы, где отвергать было
       нечего. */
    итог.claims.refused += отвергнуто ?? 0
    if (ведомость === null) continue
    for (const строка of ведомость.functions) {
      итог.functions += 1
      /* Частичные формы считаются и у ОБЫЧНЫХ функций: место проверки во время
         работы от пометки не зависит, и молчать про него у обычной значило бы
         мерить не рантайм, а обещания. Их в корпусе четыре у трёх функций —
         число маленькое ровно потому, что обычных функций мало, а не потому,
         что вопрос неважный. */
      const части = строка.partialSites ?? 0
      итог.partialSites += части
      if (части > 0) итог.partialFunctions += 1
      if (строка.total !== true) {
        итог.ordinary += 1
        continue
      }
      итог.total += 1
      итог.guardSites += строка.guardSites
      if (части > 0) {
        итог.partialTotal.functions += 1
        итог.partialTotal.sites += части
      }
      if (части === 0 && строка.guardSites === 0) итог.noRuntimeCheck += 1
      if (строка.deepClean === true) итог.noRuntimeCheckDeep += 1
      if (строка.carrier === null) итог.unaccounted += 1
      else итог.carriers[строка.carrier] += 1
    }
    for (const закон of ведомость.laws) {
      /* Закон, у которого контрпример НАЙДЕН, считается отдельно и не идёт ни в
         «на сетке», ни в значения: сложить его с посчитанными значило бы
         отчитаться о нарушенном законе как о чистом — ровно та неправда, из-за
         которой заведён этот счёт. Так же считает и ведомость одного файла
         (`proof.mjs`, `итоги_`), и расходиться этим двум счётам нельзя. */
      if (закон.verdict === "violated") {
        итог.laws.violated += 1
        continue
      }
      итог.laws.grid += 1
      итог.laws.gridValues += закон.grid?.values ?? 0
      итог.laws.gridPoints += закон.grid?.points ?? 0
    }
    итог.laws.assumed += ведомость.assumed.length
    итог.laws.permits += (ведомость.permits ?? []).length
    for (const запись of ведомость.claims ?? []) {
      итог.claims.total += 1
      итог.claims.steps += запись.steps ?? 0
      /* Вердикт кладётся по своему ключу, а не по «плохой/хороший»: разница
         между «доказано», «сетка» и «объявлено, не доказано» и есть весь смысл
         этого счёта, и свернуть её в два числа значило бы вернуть тот самый
         один `valid: true` на три разные вещи.

         Одно исключение, и оно названо: доказанное индукцией считается ДВАЖДЫ —
         в `proved` и в `proved-induction`. Не описка: `proved` отвечает на
         вопрос «сколько утверждений верны обо всех входах», а `proved-induction`
         — на другой, «у скольких из них носитель бесконечен». Так же считает и
         ведомость одного файла (`proof.mjs`, `итоги_`), и расходиться этим двум
         счётам нельзя. */
      if (запись.verdict === "proved-induction") {
        итог.claims["proved-induction"] += 1
        /* Носитель приезжает сюда из вердикта ядра, а не решается здесь заново:
           второй ответ на тот же вопрос разошёлся бы с первым молча. */
        const носитель = запись.induction?.carrier === "segment" ? "segment" : "algebra"
        итог.claims[`proved-induction-${носитель}`] += 1
      }
      /* И второе такое же уточнение, по той же причине: `proved-declaration`
         отвечает на вопрос «сколько утверждений выведено БЕЗ единого написанного
         терма — одним сведением цели с телом функции». Оно тоже считается
         дважды — в `proved` и здесь, — потому что доказанность у них одна, а
         способ разный.

         `proved-by-type` — подсчёт внутри него, и заведён он потому, что своими
         словами эти два числа разные. Утверждение «результат не меньше 0» у
         функции над `строка` сводится восемью литералами под выбором и НИ ОДНОГО
         объявления не читает; сложи их в одно — и свод сказал бы «по объявленным
         типам» о доказательстве, которому объявления не понадобились. Считает не
         свод: `proofterm.mjs` спрашивает у `свести` тот же вопрос без
         объявлений, а сюда приезжает ответ. */
      if (запись.by === "declaration") итог.claims["proved-declaration"] += 1
      if (запись.byType === true) итог.claims["proved-by-type"] += 1
      if (запись.verdict === "proved-induction") итог.claims.proved += 1
      else if (запись.verdict in итог.claims) итог.claims[запись.verdict] += 1
    }
  }
  return итог
}

/**
 * Свод по всему корпусу.
 *
 * @returns {Promise<{файлы: object[], итог: object, отказы: object[]}>}
 */
export async function сводКорпуса() {
  const файлы = []
  for (const путь of ФАЙЛЫ) файлы.push(await ведомостьФайла(путь))
  return {
    файлы,
    итог: сложить(файлы),
    /* Файл, о котором ведомости нет, называется отдельно и по имени. Тихо
       пропущенный файл — это охват, который меняется молча, и число, которое
       нельзя перепроверить (та же беда, что у корпуса моделей ядра). */
    отказы: файлы.filter((запись) => запись.ведомость === null),
  }
}

function печать(свод, поФайлам) {
  const и = свод.итог
  const строки = ["── свод ведомости доказательства по корпусу ──"]
  if (поФайлам) {
    for (const запись of свод.файлы) {
      if (запись.ведомость === null) {
        строки.push(`  ${запись.путь}: ведомости нет — ${запись.беда}`)
        continue
      }
      const ф = сложить([запись])
      строки.push(
        `  ${запись.путь}: функций ${ф.functions}, тотальных ${ф.total} `
          + `(композиция ${ф.carriers.composition}, структура ${ф.carriers.structure}, `
          + `точный шаг ${ф.carriers.exact}, шаг ${ф.carriers.step}, мера ${ф.carriers.measure}), `
          + `сторожей меры ${ф.guardSites}, частичных форм ${ф.partialSites}, `
          + `законов на сетке ${ф.laws.grid}, на веру ${ф.laws.assumed}`
          + `${ф.claims.total === 0 ? "" : `, утверждений ${ф.claims.total} (доказано ${ф.claims.proved})`}`,
      )
    }
    строки.push("")
  }
  строки.push(
    `файлов в корпусе: ${свод.файлы.length}, из них с ведомостью: ${свод.файлы.length - свод.отказы.length}`,
    `функций: ${и.functions} — тотальных ${и.total}, обычных ${и.ordinary}`,
    `чем несётся обещание «тотальная» (доказано — про ВСЕ входы):`,
    `  композицией (рекурсии нет):        ${и.carriers.composition}`,
    `  структурой (часть значения):       ${и.carriers.structure}`,
    `  точным шагом («нат», сторожа нет):  ${и.carriers.exact}`,
    `  постоянным шагом (число + сторож): ${и.carriers.step}`,
    `  объявленной мерой (+ сторож):      ${и.carriers.measure}`,
    `что проверяется во время работы (обещание «тотальная» — «завершится или честно откажет»):`,
    `  сторож меры:      ${и.guardSites} мест у ${и.carriers.step + и.carriers.measure} функций`,
    `  частичная форма:  ${и.partialSites} мест у ${и.partialFunctions} функций`
      + ` (у тотальных ${и.partialTotal.sites} у ${и.partialTotal.functions})`,
    `  всего:            ${и.guardSites + и.partialSites} мест`,
    `тотальных, у которых во время работы не проверяется НИЧЕГО: ${и.noRuntimeCheck} из ${и.total}`,
    `  из них не проверяется ничего и у тех, кого они зовут: ${и.noRuntimeCheckDeep}`,
    `законы (сетка конечна, доказательством не является):`,
    `  на сетке: ${и.laws.grid}, значений в сетках ${и.laws.gridValues}, точек ${и.laws.gridPoints}`,
    `  на веру:  ${и.laws.assumed}`,
    `  НАРУШЕНО (контрпример найден): ${и.laws.violated}`,
    `утверждения о поведении (постусловия и теоремы):`,
    `  доказано ядром (обо ВСЕХ входах):  ${и.claims.proved}`,
    `  из них индукцией: ${и.claims["proved-induction"]}`,
    `    по объявленной сумме (начальность): ${и.claims["proved-induction-algebra"]}`,
    `    по отрезку «нат» (конечность и строгий спуск): ${и.claims["proved-induction-segment"]}`,
    `  из них без теоремы (цель сведена с телом): ${и.claims["proved-declaration"]}`,
    `    из них факт дал объявленный тип аргумента: ${и.claims["proved-by-type"]}`,
    `  сетка (примеры или закон):         ${и.claims.grid}`,
    `  объявлено, не доказано:            ${и.claims.declared}`,
    `  отвергнуто ядром:                  ${и.claims.refused}`,
    /* Шестая строка, и она про факт: у скольких утверждений ПРОГОН примеров
       нашёл контрпример. До появления поиска ведомость этого не знала вовсе и
       печатала о таком утверждении «сетка N значений: нарушений не найдено». */
    `  НАРУШЕНО на примерах автора:       ${и.claims.violated}`,
    `  всего высказано: ${и.claims.total}, шагов в принятых термах: ${и.claims.steps}`,
  )
  if (и.unaccounted > 0) строки.push(`РАСХОЖДЕНИЕ: носитель не назван у ${и.unaccounted} тотальных функций`)
  for (const запись of свод.отказы) строки.push(`без ведомости: ${запись.путь} — ${запись.беда}`)
  return `${строки.join("\n")}\n`
}

/* Сравниваются РАЗРЕШЁННЫЕ пути, а не строки, — по той же причине, что в
   `flang/bin/flang.mjs`: npm ставит команды символьными ссылками, и путь ссылки с
   путём файла не совпадает. Сравнение строк дало бы ложь, свод не запустился бы и
   вышел с кодом 0, не напечатав ни байта. */
let запущен = false
if (process.argv[1] !== undefined) {
  try {
    запущен = realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
  } catch {
    запущен = false
  }
}
if (запущен) {
  const свод = await сводКорпуса()
  if (process.argv.includes("--json")) {
    process.stdout.write(`${JSON.stringify({ итог: свод.итог, отказы: свод.отказы.map((з) => ({ путь: з.путь, беда: з.беда })) }, null, 2)}\n`)
  } else {
    process.stdout.write(печать(свод, process.argv.includes("--files")))
  }
  process.exitCode = свод.итог.unaccounted === 0 ? 0 : 1
}
