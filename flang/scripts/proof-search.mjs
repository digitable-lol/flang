/**
 * Поиск доказательства по корпусу — и ПРОВЕРКА найденного обычным путём.
 *
 * ── Зачем отдельный инструмент, а не флаг у `flang check` ────────────────────
 * Поиск не входит в контур доверия, и ведомость не имеет права от него меняться:
 * «доказано» в `flang check --proof` означает «доказательство написано в файле и
 * принято ядром», а не «инструмент сумел бы его написать». Поэтому оракул стоит
 * рядом, а не внутри: ничего не нашёл — программа ведёт себя ровно как сегодня,
 * нашёл — печатает ТЕКСТ, который человек впишет в файл сам (или впишет `--write`).
 *
 * ── Как проверяется найденное ───────────────────────────────────────────────
 * Ровно тем же путём, каким проверяется написанное рукой, и другого пути здесь
 * нет: текст находки дописывается к ИСХОДНИКУ, исходник разбирается обычным
 * разборщиком, проезжает обычный `externalChecks` и обычную `proofLedger`.
 * Вердикт `proved-induction` в ведомости — единственное, что считается находкой.
 * Скажи оракул «нашёл», а обычный путь не согласись — это печатается словом
 * «ОРАКУЛ СОВРАЛ» и считается отдельным числом, потому что молчаливое
 * расхождение здесь и было бы той самой дырой, ради закрытия которой ядро своё.
 *
 * ── Второе число: ПЕРЕВЫВОД ─────────────────────────────────────────────────
 * «Нашёл 0 нового» само по себе не говорит, работает ли поиск вообще. Поэтому
 * считается и обратное: у доказательств, написанных РУКОЙ, теорема снимается из
 * исходника, и оракул ищет её заново. Число «нашёл заново из скольких» и есть
 * мера того, сколько ручной работы поиск снимает; ноль в нём означал бы, что
 * инструмента нет.
 *
 * Запуск:
 *   node flang/scripts/proof-search.mjs               по всему корпусу
 *   node flang/scripts/proof-search.mjs <путь.flang>  по одному файлу
 *   node flang/scripts/proof-search.mjs --write <путь.flang>  вписать найденное
 *   node flang/scripts/proof-search.mjs --json        машине
 */
import { readFileSync, realpathSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgramFromSource } from "../bin/flang.mjs"
import {
  ОБОСНОВАНИЯ,
  ПОИСК,
  ПРЕДЕЛ_ГЛУБИНЫ,
  ПРЕДЕЛ_ШАГОВ,
  СЛОВАМИ,
  безТеоремы,
  искатьДоказательство,
} from "../proof/search.mjs"
import { parse } from "../src/parser.mjs"
import { proofLedger, ФАЙЛЫ } from "./proof-ledger.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/**
 * Проверить находку ОБЫЧНЫМ путём: дописать текст к исходнику и спросить
 * ведомость. Своей проверки здесь нет ни строки — иначе инструмент отвечал бы на
 * свой вопрос, а не на вопрос языка.
 */
async function сверить(исходник, текст, путь, имя) {
  const собрано = `${исходник.replace(/\s*$/u, "")}\n\n${текст}`
  try {
    const программа = await loadProgramFromSource(собрано, путь)
    const внешнее = await externalChecks(программа)
    const отказы = внешнее.diagnostics.filter((беда) => беда?.severity !== "warning")
    if (отказы.length > 0) return { ok: false, why: отказы[0].message, коды: отказы.map((б) => б.code), собрано }
    const з = (proofLedger(программа, внешнее.results).claims ?? []).find((к) => к.name === имя)
    if (з?.verdict !== "proved-induction" && з?.verdict !== "proved") {
      return { ok: false, why: `ведомость сказала «${з?.says ?? "ничего"}»`, коды: [], собрано }
    }
    return { ok: true, says: з.says, verdict: з.verdict, собрано }
  } catch (беда) {
    return { ok: false, why: беда?.message ?? String(беда), коды: [], собрано }
  }
}

/** Постусловия одного файла — свои, не приехавшие импортом. */
async function обязательстваФайла(исходник, путь) {
  const свои = new Set(parse(исходник, путь).functions?.map((ф) => ф.name) ?? [])
  const программа = await loadProgramFromSource(исходник, путь)
  const внешнее = await externalChecks(программа)
  if (внешнее.diagnostics.some((беда) => беда?.severity !== "warning")) return null
  const список = (внешнее.results?.obligations?.obligations ?? [])
    .filter((о) => о.kind === "postcondition" && свои.has(о.of))
  return { программа, список }
}

/**
 * ЕСТЬ ЛИ У ЯДРА ПРАВИЛО ПОД ЭТУ ФОРМУ ЦЕЛИ — вопрос НЕ к поиску.
 *
 * Правил у `reduce.mjs` три, и все три названы в его собственном отказе:
 * «не меньше 0», «не больше конечного литерала», «равно» (тождество после
 * переписки допущением). Первые два решают сравнение с ЛИТЕРАЛОМ; третье
 * сличает две стороны СИНТАКСИЧЕСКИ и арифметику не решает. Значит цель вида
 * `(длина результат) не больше (длина элементы)` не выводится ни одним
 * кандидатом: правая часть — не литерал, а левая с правой синтаксически разные.
 *
 * Проверка ЗДЕСЬ, а не в `search.mjs`: поиск обязан оставаться перебором и
 * ничего о правилах ядра не знать — реши он сам, стоит ли пробовать, он стал бы
 * вторым проверяльщиком. Здесь же это измерение, а не решение: число печатается,
 * перебор от него не меняется ни на один кандидат.
 *
 * Ответ намеренно ГРУБЫЙ в одну сторону: «правило есть» означает «форма
 * подходит», а не «выведется». Ошибиться можно только в сторону завышения числа
 * целей, которые поиску вообще имело смысл поручать, — то есть не в свою пользу.
 */
function правилоЕсть(цель) {
  if (цель?.kind !== "binary") return false
  const литерал = (узел) => узел?.kind === "number" || (узел?.kind === "literal" && typeof узел.value === "number")
  /* Правила 1 и 2: сравнение с литералом — снизу нулём, сверху потолком. */
  if ((цель.op === "gte" || цель.op === "gt" || цель.op === "lte" || цель.op === "lt") && литерал(цель.right)) return true
  /* Правило 3 берётся только за равенство, и решает его перепиской, а не счётом. */
  return цель.op === "eq"
}

/** Форма цели одним словом — для раскладки, тем же именем узла, что у разбора. */
function формаЦели(цель) {
  if (цель?.kind !== "binary") return `не сравнение (${цель?.kind ?? "нет"})`
  const литерал = цель.right?.kind === "number" || (цель.right?.kind === "literal" && typeof цель.right.value === "number")
  return `${цель.op} ${литерал ? "литерал" : `выражение (${цель.right?.kind ?? "нет"})`}`
}

async function поФайлу(путь, писать) {
  const полный = `${корень}${путь}`
  let исходник
  try {
    исходник = readFileSync(полный, "utf8")
  } catch {
    return null
  }
  let собрано
  try {
    собрано = await обязательстваФайла(исходник, путь)
  } catch {
    return null
  }
  if (собрано === null) return null

  const итог = { путь, закрыто: 0, открыто: 0, найдено: [], отказы: [], соврал: 0, рукой: 0, перевывод: [], формы: [] }
  const дерево = parse(исходник, путь)

  for (const о of собрано.список) {
    if (о.discharge !== null && о.discharge !== undefined) {
      итог.закрыто += 1
      /* ПЕРЕВЫВОД. Доказано рукой и индукцией — снимаем теорему и спрашиваем
         оракула, найдёт ли он её сам. Считается только индукция: у остальных
         теоремы нет вовсе, снимать нечего. */
      const теорема = (дерево.theorems ?? []).find((т) => т.name === о.name && т.induction !== undefined)
      if (теорема === undefined) continue
      итог.рукой += 1
      const без = безТеоремы(исходник, теорема.span?.line ?? -1)
      if (без === null) continue
      let снято
      try {
        снято = await обязательстваФайла(без, путь)
      } catch {
        continue
      }
      if (снято === null) continue
      const цель = снято.список.find((ц) => ц.name === о.name)
      if (цель === undefined || (цель.discharge !== null && цель.discharge !== undefined)) continue
      const найдено = искатьДоказательство(цель, снято.программа, без)
      if (!найдено.ok) continue
      const проверка = await сверить(без, найдено.текст, путь, о.name)
      if (проверка.ok) итог.перевывод.push({ имя: о.name, шагов: найдено.шагов, текст: найдено.текст })
      continue
    }

    итог.открыто += 1
    /* ФОРМА ЦЕЛИ — снимается ДО поиска и независимо от него, потому что отвечает
       на другой вопрос. «Поиск не нашёл» может значить и «перебрал не то», и
       «перебирать было нечего»: у ядра правил ТРИ (`reduce.mjs`, `ПРАВИЛО`), и
       цель, чья форма не попадает ни в одно, не выводится НИКАКИМ кандидатом.
       Такую цель поиску не поручали, и записывать её в его неудачи — врать про
       причину ноля. Число снимается формой узла, а не разбором отказа. */
    итог.формы.push({ имя: о.name, of: о.of, форма: формаЦели(о.goal), правило: правилоЕсть(о.goal) })
    const найдено = искатьДоказательство(о, собрано.программа, исходник)
    if (!найдено.ok) {
      итог.отказы.push({ имя: о.name, of: о.of, why: найдено.why, шагов: найдено.шагов })
      continue
    }
    const проверка = await сверить(исходник, найдено.текст, путь, о.name)
    if (!проверка.ok) {
      итог.соврал += 1
      итог.отказы.push({ имя: о.name, of: о.of, why: `ОРАКУЛ СОВРАЛ: ${проверка.why}`, шагов: найдено.шагов })
      continue
    }
    итог.найдено.push({ имя: о.name, of: о.of, шагов: найдено.шагов, текст: найдено.текст, says: проверка.says })
    if (писать) {
      writeFileSync(полный, проверка.собрано, "utf8")
      исходник = проверка.собрано
    }
  }
  return итог
}

/* ЗАПУЩЕН, А НЕ ИМПОРТИРОВАН. Сравниваются РАЗРЕШЁННЫЕ пути, а не строки, — тем
   же приёмом и по той же причине, что в `proof-ledger.mjs`: npm ставит команды
   символьными ссылками. Без этой развилки один `import` ради вспомогательной
   функции запускал бы обход всего корпуса — семь секунд и лишний вывод в чужом
   прогоне; ровно это и случилось, пока `безТеоремы` жила здесь. */
let запущен = false
if (process.argv[1] !== undefined) {
  try {
    запущен = realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
  } catch {
    запущен = false
  }
}
if (запущен) {
  const доводы = process.argv.slice(2)
  const писать = доводы.includes("--write")
  const машине = доводы.includes("--json")
  const пути = доводы.filter((д) => !д.startsWith("--"))
  const список = пути.length > 0 ? пути.map((п) => п.replace(/^\.\//u, "")) : ФАЙЛЫ

  const своды = []
  for (const путь of список) {
    const итог = await поФайлу(путь, писать)
    if (итог !== null) своды.push(итог)
  }

  const сумма = (поле) => своды.reduce((всего, и) => всего + (Array.isArray(и[поле]) ? и[поле].length : и[поле]), 0)

  if (машине) {
    console.log(JSON.stringify({ поиск: ПОИСК, пределы: { шагов: ПРЕДЕЛ_ШАГОВ, глубина: ПРЕДЕЛ_ГЛУБИНЫ }, файлы: своды }, null, 2))
  } else {
    console.log("── поиск доказательства: оракул предлагает, ядро принимает ──")
    console.log(
      `пределы: шагов ${ПРЕДЕЛ_ШАГОВ}, глубина ${ПРЕДЕЛ_ГЛУБИНЫ};`
      + ` обоснования: ${ОБОСНОВАНИЯ.map((п) => СЛОВАМИ[п]).join(", ")}`,
    )
    console.log(`файлов просмотрено: ${своды.length}`)
    console.log(`утверждений: ${сумма("закрыто") + сумма("открыто")} — закрыто ядром ${сумма("закрыто")}, без доказательства ${сумма("открыто")}`)
    console.log(`НАЙДЕНО цепочек (проверено обычным путём): ${сумма("найдено")}`)
    /* РАСКЛАДКА ОТКАЗОВ, а не только их число. «Двадцать не нашлось» — настроение;
       «четырнадцать не с чего начать, шесть не сводятся» — измерение, и по нему
       видно, во что упирается работа: в чтение объявлений или в правила ядра. */
    const поПричине = new Map()
    for (const свод of своды) {
      for (const отказ of свод.отказы) {
        const вид = /начинать не с чего/u.test(отказ.why)
          ? "начинать не с чего (нет параметра с алгеброй и разбора по нему)"
          : (/ОРАКУЛ СОВРАЛ/u.test(отказ.why) ? "оракул соврал" : "цепочки нет (заключение не сводится правилами ядра)")
        поПричине.set(вид, (поПричине.get(вид) ?? 0) + 1)
      }
    }
    for (const [вид, сколько] of поПричине) console.log(`  ${вид}: ${сколько}`)
    /* ПРИЧИНА НОЛЯ, А НЕ ЕГО ПОВТОРЕНИЕ. Раскладка выше говорит, где ОСТАНОВИЛСЯ
       поиск; эта — сколько целей ему вообще имело смысл поручать. Пока второе
       число мало, первое ничего не значит: улучшать перебор там, где у ядра нет
       правила под форму цели, — работа, которая не может дать находки. */
    const формы = своды.flatMap((с) => с.формы)
    const подПравило = формы.filter((ф) => ф.правило)
    console.log(
      `ФОРМА ЦЕЛИ (правил у ядра три: «не меньше 0», «не больше конечного литерала», «равно»):`
      + ` под правило подходит ${подПравило.length} из ${формы.length},`
      + ` вне правил ${формы.length - подПравило.length}`,
    )
    const поФорме = new Map()
    for (const ф of формы) поФорме.set(ф.форма, (поФорме.get(ф.форма) ?? 0) + 1)
    for (const [форма, сколько] of [...поФорме].sort((а, б) => б[1] - а[1])) {
      console.log(`  ${форма}: ${сколько}`)
    }
    console.log(`оракул соврал (сказал «нашёл», обычный путь не принял): ${сумма("соврал")}`)
    console.log(`ПЕРЕВЫВОД: доказательств индукцией рукой ${сумма("рукой")}, оракул нашёл заново ${сумма("перевывод")}`)
    for (const свод of своды) {
      for (const находка of свод.найдено) {
        console.log(`\n${свод.путь} «${находка.имя}» (${находка.of}) — ${находка.шагов} кандидатов`)
        console.log(находка.текст.replace(/\n$/u, "").split("\n").map((с) => `  ${с}`).join("\n"))
        console.log(`  → ${находка.says}`)
      }
    }
    if (пути.length > 0) {
      for (const свод of своды) {
        for (const отказ of свод.отказы) console.log(`\n${свод.путь} «${отказ.имя}» — не найдено (${отказ.шагов} кандидатов): ${отказ.why}`)
      }
    }
  }
}
