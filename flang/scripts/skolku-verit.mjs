/**
 * СКОЛЬКИМ СТРОКАМ ЯДРА ПРИХОДИТСЯ ВЕРИТЬ — ЧИСЛОМ, А НЕ НА ГЛАЗ.
 *
 *   node flang/scripts/skolku-verit.mjs            сверить с записанным потолком
 *   node flang/scripts/skolku-verit.mjs --spisok   назвать функции ядра решений
 *   node flang/scripts/skolku-verit.mjs --write    переписать потолок (только вниз)
 *
 * Код возврата 0 — потолок не пробит; 1 — ядру, которому надо верить, стало
 * больше, и это названо числом.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * От поиска в проверяльщике отказались ради одного довода: «прочитать целиком
 * можно только маленький». Довод честный, но он работает, только если
 * «маленький» — это число, которое кто-то держит. Сегодня три файла ядра — это
 * почти десять тысяч строк, а прочитать десять тысяч нельзя.
 *
 * Здесь эти строки разложены на то, чему верить НАДО, и то, чему не обязательно,
 * и разложены механически, чтобы число нельзя было улучшить словами.
 *
 * ── Как считается, и что каждое число значит ────────────────────────────────
 *
 *   ВСЕГО СТРОК     — как их видит `wc -l`. Это число и звучит в разговорах.
 *   КОД             — минус комментарий и пустые. Комментарий тут не balast:
 *                     в нём доводы, почему правило — теорема, а не аксиома. Но
 *                     ошибиться в комментарии нельзя, и верить ему не надо.
 *   ДОСТИЖИМО       — код функций, до которых доходит вызов от поверхности
 *                     ядра (имён, которые зовёт `compiler.flang`). Недостижимое
 *                     не влияет ни на один вердикт по построению.
 *   ЯДРО РЕШЕНИЙ    — код функций, достижимых от тех, что отвечают ДА или НЕТ
 *                     (возвращают `признак`). Вердикт «выведено ли это» —
 *                     именно такой ответ, и всё, что на него влияет, лежит
 *                     здесь. ЭТО И ЕСТЬ ЧИСЛО, КОТОРОМУ ПРИХОДИТСЯ ВЕРИТЬ.
 *   ТОЛЬКО СЛОВА    — функции, возвращающие строку и НЕ достижимые ни от одного
 *                     ответа да/нет. Соврать они могут только в тексте отказа.
 *   РАЗБОР ФОРМЫ     — строки ядра решений, где у бесформенного узла
 *                     «Значение» спрашивают, какой он формы: «Это запись»,
 *                     «Есть поле у узла», «Взять поле», «Вид узла». Это и есть
 *                     ответ на вопрос «а не сделать ли негодный терм
 *                     невыразимым»: столько уйдёт, если терм станет
 *                     типизированным, и НЕ БОЛЬШЕ. Правила вывода — отношение
 *                     между термами, а не их форма, и типами они не снимаются.
 *
 * ── Чего этот счёт НЕ утверждает ────────────────────────────────────────────
 *
 * Он не говорит «остальному верить не надо». Он говорит слабее и точнее: до
 * остального не доходит ни одна цепочка от ответа да/нет — значит соврать
 * вердиктом оно не может, а испортить сообщение может. Разделение считается по
 * ВЫЗОВАМ, а вызовы читаются из текста: имя в ёлочках внутри тела функции. У
 * такого чтения есть цена — имя поля записи выглядит как вызов, и счёт от этого
 * идёт В БОЛЬШУЮ сторону. То есть «ядро решений» здесь — верхняя оценка того,
 * чему надо верить, а не нижняя, и ошибается она в безопасную сторону.
 */
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const КОРЕНЬ = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..")
const ПОТОЛОК = join(КОРЕНЬ, "flang/scripts/skolku-verit-potolok.json")
const СПИСКОМ = process.argv.includes("--spisok")
const ПИСАТЬ = process.argv.includes("--write")

const ЯДРО = ["flang/self/proofterm.flang", "flang/self/proof-kernel.flang", "flang/self/proof-initial.flang"]
/* Поверхность ядра — не список здесь, а то, что ДЕЙСТВИТЕЛЬНО зовёт компилятор.
   Список рукой разошёлся бы с деревом в первый же день. */
const ЗОВУЩИЙ = "flang/self/bootstrap/compiler.flang"

const ЗАГОЛОВОК = /^(?:тотальная\s+)?функция\s+«([^»]+)»/u
const ВОЗВРАТ = /^\s+возвращает\s+(.+?)\s*$/u
const ИМЯ = /«([^»]+)»/gu
const БЕЗ_СТРОК = (с) => с.replace(/"(?:[^"\\]|\\.)*"/gu, '""')

const функции = new Map()
const порядок = []
let всегоСтрок = 0
let комментарий = 0
let пусто = 0

for (const путь of ЯДРО) {
  const строки = readFileSync(join(КОРЕНЬ, путь), "utf8").split("\n")
  всегоСтрок += строки.length
  for (const с of строки) {
    const т = с.trim()
    if (т === "") пусто += 1
    else if (т.startsWith("//")) комментарий += 1
  }
  let текущая = null
  for (let и = 0; и < строки.length; и += 1) {
    const м = ЗАГОЛОВОК.exec(строки[и])
    if (м) {
      if (текущая) текущая.конец = и
      текущая = { путь, имя: м[1], начало: и, конец: строки.length, возврат: null, строки }
      функции.set(м[1], текущая)
      порядок.push(текущая)
      continue
    }
    if (текущая && /^[^\s/]/u.test(строки[и])) { текущая.конец = и; текущая = null }
    if (текущая && текущая.возврат === null) {
      const в = ВОЗВРАТ.exec(строки[и])
      if (в) текущая.возврат = в[1]
    }
  }
  if (текущая) текущая.конец = строки.length
}

const код = (ф) =>
  ф.строки.slice(ф.начало, ф.конец).filter((с) => s(с)).length
const s = (с) => c(с) !== "" && !c(с).startsWith("//")
const c = (с) => с.trim()

for (const ф of порядок) {
  const зовёт = new Set()
  for (const с of ф.строки.slice(ф.начало, ф.конец)) {
    if (c(с).startsWith("//")) continue
    for (const м of БЕЗ_СТРОК(с).matchAll(ИМЯ)) if (функции.has(м[1]) && м[1] !== ф.имя) зовёт.add(м[1])
  }
  ф.зовёт = зовёт
}

const замыкание = (начало) => {
  const дошли = new Set()
  const стек = [...начало]
  while (стек.length > 0) {
    const и = стек.pop()
    if (дошли.has(и)) continue
    дошли.add(и)
    for (const с of функции.get(и).зовёт) if (!дошли.has(с)) стек.push(с)
  }
  return дошли
}

const текстЗовущего = БЕЗ_СТРОК(readFileSync(join(КОРЕНЬ, ЗОВУЩИЙ), "utf8"))
const поверхность = new Set([...текстЗовущего.matchAll(ИМЯ)].map((м) => м[1]).filter((и) => функции.has(и)))
const решения = new Set([...функции.keys()].filter((и) => функции.get(и).возврат === "признак"))

const достижимо = замыкание(поверхность)
const ядроРешений = замыкание(решения)
const строкПо = (набор) => [...набор].reduce((с, и) => с + код(функции.get(и)), 0)

/* Спрашивание формы у бесформенного узла: имена берутся из «Печать в C», их
   ввозит `proofterm.flang` первой же строкой. */
const ДОСТУП_К_УЗЛУ = [
  "Это запись", "Это список", "Это строка", "Это ничто", "Есть поле у узла", "Взять поле", "Вид узла",
  "Строка поля", "Элементы поля", "Поля узла", "Элементы узла", "Строка узла", "Число узла", "Первое из полей", "Поле узла",
]
const строкРазбораФормы = [...ядроРешений].reduce((с, и) => {
  const ф = функции.get(и)
  return с + ф.строки.slice(ф.начало, ф.конец).filter((л) => s(л) && ДОСТУП_К_УЗЛУ.some((д) => л.includes(`«${д}»`))).length
}, 0)
const сПодписьюУзла = [...ядроРешений].filter((и) => {
  const ф = функции.get(и)
  return ф.строки.slice(ф.начало, Math.min(ф.начало + 6, ф.конец)).some((л) => л.includes("«Значение»"))
}).length

const толькоСлова = [...функции.keys()].filter(
  (и) => !ядроРешений.has(и) && ["строка", "список строки"].includes(функции.get(и).возврат ?? ""),
)

const счёт = {
  всегоСтрок,
  код: всегоСтрок - комментарий - пусто,
  функций: порядок.length,
  поверхность: поверхность.size,
  достижимоСтрок: строкПо(достижимо),
  ядроРешенийФункций: ядроРешений.size,
  ядроРешенийСтрок: строкПо(ядроРешений),
  толькоСловаСтрок: толькоСлова.reduce((с, и) => с + код(функции.get(и)), 0),
  разборФормыСтрок: строкРазбораФормы,
  сПодписьюУзла,
}

console.log(`три файла ядра доказательств: ${ЯДРО.join(", ")}`)
console.log(`  всего строк:                       ${счёт.всегоСтрок}`)
console.log(`  из них комментарий:                ${комментарий}`)
console.log(`  из них пустых:                     ${пусто}`)
console.log(`  КОД:                               ${счёт.код}   (функций ${счёт.функций})`)
console.log(`  достижимо от поверхности ядра:     ${счёт.достижимоСтрок}   (поверхность — ${счёт.поверхность} имён, их зовёт compiler.flang)`)
console.log(`  ЯДРО РЕШЕНИЙ — верить надо ему:    ${счёт.ядроРешенийСтрок}   (функций ${счёт.ядроРешенийФункций})`)
console.log(`  только слова (текст отказов):      ${счёт.толькоСловаСтрок}   (функций ${толькоСлова.length})`)
console.log(`  из ядра решений — разбор формы:    ${счёт.разборФормыСтрок}   (${Math.round((100 * счёт.разборФормыСтрок) / счёт.ядроРешенийСтрок)}% ядра решений; столько снял бы типизированный терм, и не больше)`)
console.log(`  функций с «Значением» в подписи:   ${счёт.сПодписьюУзла} из ${счёт.ядроРешенийФункций}`)

if (СПИСКОМ) {
  console.log("\nядро решений поимённо:")
  for (const и of [...ядроРешений].sort()) console.log(`  ${String(код(функции.get(и))).padStart(4)}  ${и}`)
}

if (ПИСАТЬ) {
  writeFileSync(ПОТОЛОК, JSON.stringify(счёт, null, 2) + "\n")
  console.log("\nпотолок переписан")
  process.exit(0)
}

if (!existsSync(ПОТОЛОК)) {
  console.error("\nпотолка нет — запишите его: --write")
  process.exit(1)
}
const прежде = JSON.parse(readFileSync(ПОТОЛОК, "utf8"))
const выросло = ["ядроРешенийСтрок", "достижимоСтрок"].filter((к) => счёт[к] > прежде[к])
if (выросло.length > 0) {
  console.error("\nВЕРИТЬ ПРИХОДИТСЯ БОЛЬШЕМУ, ЧЕМ ВЧЕРА:")
  for (const к of выросло) console.error(`  • ${к}: было ${прежде[к]}, стало ${счёт[к]} (+${счёт[к] - прежде[к]})`)
  console.error("\nПотолок ползёт только вниз. Либо перенесите работу из ядра решений")
  console.error("в то, что вердикта не касается, либо напишите довод и --write.")
  process.exit(1)
}
const упало = ["ядроРешенийСтрок", "достижимоСтрок"].filter((к) => счёт[к] < прежде[к])
if (упало.length > 0) {
  console.log("\nстало МЕНЬШЕ — перепишите потолок (--write):")
  for (const к of упало) console.log(`  ${к}: было ${прежде[к]}, стало ${счёт[к]} (−${прежде[к] - счёт[к]})`)
  process.exit(1)
}
console.log("\nпотолок не пробит")
process.exit(0)
