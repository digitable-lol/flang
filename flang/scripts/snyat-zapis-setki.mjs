function файлыКорпуса(каталог, найдено = []) {
  for (const имя of readdirSync(каталог)) {
    if (имя === "node_modules" || имя === ".git" || имя === ".claude" || имя === "dist") continue
    const путь = join(каталог, имя)
    if (statSync(путь).isDirectory()) файлыКорпуса(путь, найдено)
    else if (имя.endsWith(".flang")) найдено.push(путь)
  }
  return найдено
}

/** Один вход корпуса: имя для отказа, разобранная программа и обязательства. */
export async function собратьКорпус() {
  const корпус = []
  for (const путь of [...файлыКорпуса(join(корень, "flang")), ...файлыКорпуса(join(корень, "examples"))]) {
    let программа
    try {
      программа = await loadProgram(путь)
    } catch {
      continue
    }
    корпус.push({ имя: путь.slice(корень.length + 1), программа })
  }
  for (const [имя, исходник] of Object.entries(ДУРНЫЕ)) {
    корпус.push({ имя: `нарочная — ${имя}`, программа: parse(исходник) })
  }
  for (const вход of корпус) {
    let спуски = []
    try {
      спуски = checkTotality(вход.программа)?.descents ?? []
    } catch {
      спуски = []
    }
    вход.обязательства = obligations(вход.программа, { totality: { descents: спуски } }).obligations
  }
  return корпус
}

const отпечаток = (текст) => createHash("sha256").update(текст).digest("hex")

/**
 * Снять запись. `свидетель` приходит снаружи: пока `src/grid.mjs` в дереве, это
 * `checkGrid`; после удаления звать эту функцию будет некому, и запись останется
 * тем единственным, с чем сверяется эталон.
 */
export async function снять(свидетель, корпус = undefined) {
  const входы = корпус ?? (await собратьКорпус())
  const ответы = {}
  const поток = []
  let постусловий = 0
  let нарушений = 0
  let неискали = 0
  const исходы = { нашли: 0, неИскали: 0, неНашли: 0, пустых: 0 }
  for (const вход of входы) {
    const ответ = свидетель(вход.программа, вход.обязательства)
    const текст = JSON.stringify(ответ)
    ответы[вход.имя] = отпечаток(текст)
    поток.push(`${вход.имя} ${ответы[вход.имя]}`)
    постусловий += ответ.checked.length
    for (const з of ответ.checked) {
      нарушений += з.violations.length
      неискали += з.unsearched.length
      if (з.violations.length > 0) исходы.нашли += 1
      else if (з.unsearched.length > 0) исходы.неИскали += 1
      else if (з.examples > 0) исходы.неНашли += 1
      else исходы.пустых += 1
    }
  }
  return {
    программ: входы.length,
    пути: входы.map((вход) => вход.имя),
    постусловий,
    нарушений,
    неискали,
    исходы,
    отпечаток: отпечаток(поток.join("\n")),
    ответы,
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { checkGrid } = await import(new URL("../src/grid.mjs", import.meta.url).href)
  const запись = await снять(checkGrid)
  const куда = fileURLToPath(new URL("../test/fixtures/zapis-setki.json", import.meta.url))
  writeFileSync(куда, `${JSON.stringify(запись, null, 2)}\n`)
  process.stdout.write(
    `снято: программ ${запись.программ}, постусловий ${запись.постусловий}, ` +
      `нарушений ${запись.нарушений}, не искали ${запись.неискали}\n` +
      `исходы: нашли ${запись.исходы.нашли}, не искали ${запись.исходы.неИскали}, ` +
      `не нашли ${запись.исходы.неНашли}, сетка пуста ${запись.исходы.пустых}\n` +
      `отпечаток ${запись.отпечаток}\n`,
  )
}