/**
 * ПОВРЕЖДЕНИЯ ОТ СЛИЯНИЯ: ДВОЙНОЕ ОБЪЯВЛЕНИЕ И ЗВАНЫЙ, КОТОРОГО НЕТ.
 *
 *   node flang/scripts/srashchivanie.mjs            сверить с записанным долгом
 *   node flang/scripts/srashchivanie.mjs --spisok   назвать каждое место
 *   node flang/scripts/srashchivanie.mjs --write    переписать долг после чистки
 *
 * Код возврата 0 — новых повреждений нет; 1 — есть, и каждое названо файлом и
 * строкой.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Слияние двух веток, тронувших одно место, git разводит без единого знака
 * конфликта двумя способами, и оба ломают программу молча:
 *
 *   • ОБЕ ветки добавили функцию с одним именем → в файле два объявления. Язык
 *     это ловит («функция «Х» объявлена дважды», FLANG_TYPE, код 1), но ловит
 *     ТОЛЬКО когда кто-то позовёт `flang check` именно на этом файле;
 *   • одна ветка функцию УБРАЛА, другая оставила вызовы → зовущие висят в
 *     пустоту. Язык и это ловит (FLANG_UNKNOWN_NAME + FLANG_NOT_TOTAL, код 1) —
 *     и снова только на том файле, который кто-то проверил.
 *
 * А проверяет их не кто-то, а список: `flang/проверки/ведомость-примеров.txt`
 * держит 774 файла, тогда как в дереве `.flang` — 958. Файл, в список не
 * попавший, не проверяется вовсе, и повреждение в нём доживает до сборки.
 * Замерено на этом дереве: `flang/examples/db/postgres-scram-plan.flang` зовёт
 * «Начало SASL» и «Ответ SASL», которых нет НИ В ОДНОМ файле дерева, — и это
 * лежит в стволе зелёным.
 *
 * ── Почему текстом, а не компилятором ───────────────────────────────────────
 *
 * Спросить компилятор про все 958 файлов честнее, но дороже: полный обход
 * дерева идёт больше часа и потому стоит на теге, а не на пуше. Оба
 * повреждения, однако, видны БЕЗ типизации — по объявлениям и по местам вызова.
 * Разбор объявлений здесь не свой: берётся тот же, которым считает столкновения
 * имён `link-collision-guard.mjs`, чтобы вторая запись правил не разошлась с
 * первой.
 *
 * ── Чего проверка НЕ ловит, и это сказано прямо ─────────────────────────────
 *
 * • Имя, объявленное ГДЕ-ТО в дереве, но не видимое из зовущего файла: это
 *   вопрос замыкания подключений, и на него отвечает `collisions:check`.
 * • Вызов без слова `от` — нульместный, записанный как `(«Имя»)`. Такая запись
 *   неотличима от ссылки на связанное имя (`(«начато»)` в `interpret.flang`),
 *   и правило на неё дало бы ложные срабатывания вместо повреждений.
 */
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { объявления } from "./link-collision-guard.mjs"

const КОРЕНЬ = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..")
const ФАЙЛ_ДОЛГА = join(КОРЕНЬ, "flang/scripts/srashchivanie-dolg.json")
const СПИСКОМ = process.argv.includes("--spisok")
const ПИСАТЬ = process.argv.includes("--write")

/* ВЫВОДЫ МОДЕЛИ — НЕ НАШ КОД. `benchmarks/model-authoring/out` держит то, что
   написала модель в замере авторства, вместе с заведомо негодными программами:
   отчёт о примерах отмечает их словом «отказ». Судить их правилами дерева
   значило бы мерить не то. */
const ВНЕ_СЧЁТА = [/^benchmarks\/model-authoring\/out\//u]

const файлы = execFileSync("git", ["-C", КОРЕНЬ, "-c", "core.quotePath=false", "ls-files", "*.flang"], { encoding: "utf8" })
  .split("\n")
  .filter(Boolean)
  .filter((путь) => !ВНЕ_СЧЁТА.some((п) => п.test(путь)))

/* ── 1. одно имя объявлено дважды в одном файле ─────────────────────────── */

const объявленоВДереве = new Set()
const двойные = []
for (const путь of файлы) {
  const текст = readFileSync(join(КОРЕНЬ, путь), "utf8")
  const прежде = new Map()
  for (const о of объявления(текст)) {
    объявленоВДереве.add(о.имя)
    const ключ = `${о.поле}|${о.имя}`
    if (прежде.has(ключ)) двойные.push({ путь, имя: о.имя, поле: о.поле, строка: о.строка, прежде: прежде.get(ключ) })
    else прежде.set(ключ, о.строка)
  }
}

/* ── 2. званый, которого нет ни в одном файле дерева ────────────────────── */

/* Вызов с доводами: `«Имя» от …`. Слово `от` обязано кончаться границей слова,
   иначе `отбор` сошёл бы за вызов. */
const ЗОВ = /«([^»]+)»\s+(?:от|from|de|从)(?![\p{L}\p{N}_])/gu

const пропавшие = []
for (const путь of файлы) {
  const строки = readFileSync(join(КОРЕНЬ, путь), "utf8").split("\n")
  for (let и = 0; и < строки.length; и += 1) {
    if (/^\s*\/\//u.test(строки[и])) continue
    /* Строковые литералы вычёркиваются: имя внутри кавычек — это текст
       сообщения, а не вызов. */
    const строка = строки[и].replace(/"(?:[^"\\]|\\.)*"/gu, '""')
    ЗОВ.lastIndex = 0
    let м
    while ((м = ЗОВ.exec(строка)) !== null)
      if (!объявленоВДереве.has(м[1])) пропавшие.push({ путь, имя: м[1], строка: и + 1 })
  }
}

/* ── долг: потолок ползёт только вниз ───────────────────────────────────── */

const метка = (б) => `${б.путь}:${б.имя}`
const беды = [
  ...двойные.map((б) => ({ ...б, род: "двойное объявление" })),
  ...пропавшие.map((б) => ({ ...б, род: "званый, которого нет" })),
]
const сейчас = {}
for (const б of беды) сейчас[метка(б)] = б.род

/* Долг держит не число, а ЗАПИСЬ С ДОВОДОМ на каждое место. Голое число дало бы
   обменять починенное на новое повреждение при том же счёте; запись с доводом
   этого не позволяет — и заодно не даёт спрятать настоящий дефект под словом
   «известно». Довод пишется рукой, ключ `--write` его сохраняет. */
const прежний = existsSync(ФАЙЛ_ДОЛГА) ? JSON.parse(readFileSync(ФАЙЛ_ДОЛГА, "utf8")) : {}

if (ПИСАТЬ) {
  const новый = {}
  for (const к of Object.keys(сейчас).sort())
    новый[к] = { род: сейчас[к], довод: прежний[к]?.довод ?? "ДОВОД НЕ НАПИСАН — напишите, почему это здесь законно или почему не чинится сейчас" }
  writeFileSync(ФАЙЛ_ДОЛГА, JSON.stringify(новый, null, 2) + "\n")
  console.log(`долг переписан: записей ${Object.keys(новый).length}`)
  process.exit(0)
}

const долг = прежний

console.log(`файлов на flang под счётом: ${файлы.length}`)
console.log(`объявленных имён в дереве:  ${объявленоВДереве.size}`)
console.log(`двойных объявлений:         ${двойные.length}`)
console.log(`званых, которых нет:        ${пропавшие.length}`)

if (СПИСКОМ) for (const б of беды) console.log(`  ${б.род}: ${б.путь}:${б.строка} «${б.имя}»${б.прежде ? ` — уже было на строке ${б.прежде}` : ""}`)

const новые = беды.filter((б) => долг[метка(б)] === undefined)
const ушедшие = Object.keys(долг).filter((к) => сейчас[к] === undefined)

if (новые.length > 0) {
  console.error("\nНОВЫЕ ПОВРЕЖДЕНИЯ — этого в записанном долге нет:")
  for (const б of новые)
    console.error(`  • ${б.род}: ${б.путь}:${б.строка} «${б.имя}»${б.прежде ? ` — уже объявлено на строке ${б.прежде}` : ""}`)
  console.error("\nЛибо это поломка от слияния — почините её; либо имя законно и его надо")
  console.error("объявить. Вписать в долг молча нельзя: долг переписывается только")
  console.error("ключом --write и только после того, как счёт стал МЕНЬШЕ.")
  process.exit(1)
}

const безДовода = Object.entries(долг).filter(([, з]) => !з.довод || з.довод.startsWith("ДОВОД НЕ НАПИСАН"))
if (безДовода.length > 0) {
  console.error("\nВ ДОЛГЕ ЕСТЬ ЗАПИСИ БЕЗ ДОВОДА — так долг превращается в свалку:")
  for (const [к] of безДовода) console.error(`  • ${к}`)
  process.exit(1)
}

if (ушедшие.length > 0) {
  console.log(`\nПОЧИНЕНО с прошлого замера: ${ушедшие.length}`)
  for (const к of ушедшие) console.log(`  ${к}`)
  console.log("Долг устарел в лучшую сторону — перепишите его: --write")
  process.exit(1)
}

console.log(`\nновых повреждений нет; в записанном долге ${Object.keys(долг).length}, у каждой записи довод:`)
for (const [к, з] of Object.entries(долг)) console.log(`  ${к} — ${з.довод}`)
process.exit(0)
