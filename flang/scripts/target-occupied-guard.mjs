/**
 * Сторож ЗАНЯТЫХ ЦЕЛЬЮ ИМЁН: сколько модулей корпуса столкнулись бы у каждой цели.
 *
 * ── Что он меряет ───────────────────────────────────────────────────────────
 *
 * Имя модуля flang доезжает до цели именем файла, класса или алиаса. Часть этого
 * пространства у цели ЗАНЯТА (`flang/src/emit/target-occupied.mjs`). Сторож берёт
 * ВСЕ модули корпуса — `flang/stdlib`, `flang/core`, `flang/examples` — и по
 * каждой из восьми целей считает, сколько имён попало бы в занятое.
 *
 * Число сегодня — ноль по всем восьми, и это не заслуга печати, а везение:
 * модулей мало и названы они по-русски, а транслитерация русского слова в
 * `json` или в `Enum` не попадает. Библиотека растёт, и `модуль «JSON»` придёт —
 * он уже пришёл на ветке `work/stdlib-json-time`. Сторож печатает не «ноль», а
 * СПИСОК: разъедься список с числом — виновата строка, а не итог.
 *
 * ── Что он проверяет сверх счёта ────────────────────────────────────────────
 *
 * Обход обязан быть ТОЖДЕСТВЕННЫМ на свободном имени: если бы он трогал имена,
 * которых цель не занимала, побайтовая сверка печати покраснела бы у всего
 * корпуса разом. Сторож проверяет это на всех именах корпуса по всем восьми
 * целям и называет число сверок.
 *
 * Запуск: `node flang/scripts/target-occupied-guard.mjs` (или `npm run occupied:check`).
 */
import { readdirSync, readFileSync, statSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { pascal, snake } from "../src/naming.mjs"
import { ЗАНЯТО_ЦЕЛЬЮ, занятоЦелью, обойтиЗанятоеЦелью, обходСнимаетЗанятость } from "../src/emit/target-occupied.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../", import.meta.url))

/** Каталоги корпуса: ровно те три, о которых спрашивают. */
export const КАТАЛОГИ = ["stdlib", "core", "examples"]

/** Rust режет имя по своим правилам, Elixir — по точкам; остальные берут прямо. */
const rustSnake = (имя) => snake(имя)
const pascalModule = (имя) =>
  String(имя)
    .split(".")
    .map((часть) => pascal(часть))
    .map((часть) => (/^[A-Z]/u.test(часть) ? часть : `M${часть}`))
    .join(".")

/**
 * Как имя модуля flang становится именем в цели. Ровно те же преобразования,
 * что в `flang/src/emit/*.mjs`: расхождение здесь сделало бы счёт выдумкой.
 */
export const ИМЯ_В_ЦЕЛИ = {
  c: snake,
  go: snake,
  rust: rustSnake,
  python: snake,
  java: pascal,
  csharp: pascal,
  elixir: pascalModule,
  js: snake,
}

/** Все модули корпуса: путь файла → имя модуля. */
export function модулиКорпуса(корень = КОРЕНЬ) {
  const найденные = []
  const обойти = (каталог) => {
    for (const запись of readdirSync(каталог).sort()) {
      const путь = `${каталог}/${запись}`
      if (statSync(путь).isDirectory()) {
        обойти(путь)
        continue
      }
      if (!запись.endsWith(".flang")) continue
      const текст = readFileSync(путь, "utf8")
      const совпадение = /^модуль\s+«([^»]+)»/mu.exec(текст)
      if (совпадение === null) continue
      найденные.push({ путь: путь.slice(корень.length), модуль: совпадение[1] })
    }
  }
  for (const каталог of КАТАЛОГИ) обойти(`${корень}${каталог}`)
  return найденные
}

/** Счёт столкновений по каждой цели и список тождественных обходов. */
export function померить(модули) {
  const итог = {}
  let тождественных = 0
  for (const цель of Object.keys(ЗАНЯТО_ЦЕЛЬЮ)) {
    const набор = ЗАНЯТО_ЦЕЛЬЮ[цель]
    const столкнулись = []
    for (const { путь, модуль } of модули) {
      const имя = ИМЯ_В_ЦЕЛИ[цель](модуль)
      const обойдённое = обойтиЗанятоеЦелью(имя, цель)
      if (занятоЦелью(имя, набор)) столкнулись.push({ путь, модуль, имя, обойдённое })
      else if (обойдённое === имя) тождественных += 1
    }
    итог[цель] = { занятых: набор.имена.length + набор.хвосты.length, столкнулись }
  }
  return { итог, тождественных }
}

export function отчёт(корень = КОРЕНЬ) {
  const модули = модулиКорпуса(корень)
  const { итог, тождественных } = померить(модули)
  const строки = [`Модулей в корпусе (${КАТАЛОГИ.join(", ")}): ${модули.length}`, ""]
  let всего = 0
  for (const [цель, { занятых, столкнулись }] of Object.entries(итог)) {
    всего += столкнулись.length
    строки.push(`${цель.padEnd(7)} занято целью: ${String(занятых).padStart(3)}   столкнулось: ${столкнулись.length}`)
    for (const { модуль, имя, обойдённое } of столкнулись) {
      строки.push(`          «${модуль}» → ${имя} → обход ${обойдённое}`)
    }
  }
  const снятие = обходСнимаетЗанятость()
  const занятых = снятие.reduce((сумма, { занятых: сколько }) => сумма + сколько, 0)
  const снято = снятие.reduce((сумма, { снято: сколько }) => сумма + сколько, 0)
  строки.push("", `Всего столкновений по восьми целям: ${всего}`)
  строки.push(`Обход тождествен на свободном имени: ${тождественных} сверок из ${модули.length * 8 - всего}`)
  строки.push(`Один шаг обхода снимает занятость: ${снято} из ${занятых}`)
  return { текст: строки.join("\n"), всего, модулей: модули.length, тождественных, занятых, снято, итог }
}

if (process.argv[1] !== undefined && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  const { текст, тождественных, модулей, всего, занятых, снято } = отчёт()
  console.log(текст)
  if (тождественных !== модулей * 8 - всего) {
    console.error("ОБХОД НЕ ТОЖДЕСТВЕН на свободном имени — печать сменила бы вывод там, где смысл не менялся")
    process.exit(1)
  }
  if (снято !== занятых) {
    console.error("ОДИН ШАГ ОБХОДА НЕ СНИМАЕТ ЗАНЯТОСТЬ — обойдённое имя цель по-прежнему занимает")
    process.exit(1)
  }
}
