/**
 * Сторож ЗАНЯТЫХ ЦЕЛЬЮ ИМЁН: сколько модулей корпуса столкнулись бы у каждой цели.
 *
 * ── Что он меряет ───────────────────────────────────────────────────────────
 *
 * Имя модуля flang доезжает до цели именем файла, класса или псевдонима. Часть
 * этого пространства у цели ЗАНЯТА: `stdio` в C, `Enum` в Java, `ast` в Python,
 * хвост `_linux` в Go. Сторож берёт ВСЕ модули корпуса — `flang/stdlib`,
 * `flang/core`, `flang/examples` — и по каждой из восьми целей считает, сколько
 * имён попало бы в занятое.
 *
 * Число сегодня — ноль по всем восьми, и это не заслуга печати, а везение:
 * модулей мало и названы они по-русски, а транслитерация русского слова в
 * `json` или в `Enum` не попадает. Библиотека растёт, и `модуль «JSON»` придёт.
 * Сторож печатает не «ноль», а СПИСОК: разъедься список с числом — виновата
 * строка, а не итог.
 *
 * ── Откуда он берёт имена и таблицы ПОСЛЕ УДАЛЕНИЯ ВТОРОЙ РЕАЛИЗАЦИИ ────────
 *
 * До 20 августа сторож ввозил `pascal`/`snake` из `flang/src/naming.mjs` и
 * таблицы занятого из `flang/src/target-occupied.mjs`. Обоих файлов больше нет:
 * компилятор один, двоичный. Переписать таблицы сюда было бы худшим из
 * возможных решений именно для этого сторожа — он заведён затем, чтобы сверять
 * корпус с НАСТОЯЩИМ набором занятого у цели, а сверка с копией набора не
 * проверяет ничего.
 *
 * Поэтому и преобразование имени, и таблица, и обход спрашиваются у двоичного
 * прогонщиком (`dvoichnyy.mjs`, «Спросить двоичный о значении функции языка»).
 * Спрашиваются РОВНО ТЕ функции, которыми это делает сама печать:
 *
 *   c       «Змейка» → «Обойти занятое целью C»
 *   go      «Змейка» → «Обойти занятое целью Go»
 *   rust    «Змейка Rust» → «Обойти занятое целью Rust»
 *   python  «Змейка Python» → «Безопасный идентификатор Python» → обход
 *   js      «Змейка» → «Обойти занятое целью JS»
 *   java    «Паскаль Java» → «Безопасный идентификатор Java» → обход
 *   csharp  «Паскаль CSharp» → «Безопасный идентификатор CSharp» → обход
 *   elixir  «Модуль Elixir» → «Обойти занятое целью Elixir»
 *
 * Это СТРОЖЕ прежнего: раньше цепочки были переписаны здесь по образцу печати и
 * могли с ней разойтись молча; теперь считает та же цепочка, что печатает.
 *
 * ── Что он проверяет сверх счёта: две сверки данных с поведением ────────────
 *
 * У цели две независимые вещи: ТАБЛИЦА занятого (данные, «Занято целью C») и
 * ОБХОД (поведение, «Обойти занятое целью C»). Разъедься они — печать либо
 * тронула бы свободное имя, либо оставила бы занятое. Поэтому:
 *
 *   ОБХОД ТРОГАЕТ ТОЛЬКО НАЗВАННОЕ. Обход изменил имя ⇒ таблица это имя
 *     называет. Названным считается имя, стоящее в таблице целиком либо
 *     кончающееся на «_» плюс запись таблицы: у Go занято не имя, а хвост
 *     сборки (`программа_linux.go` компилятор Go читает как файл только для
 *     Linux). Это отношение строк, а не правило цели, — правил здесь не
 *     переписано ни одного.
 *
 *   ОДИН ШАГ ОБХОДА СНИМАЕТ ЗАНЯТОСТЬ. Проверяется на пробах, взятых из самой
 *     таблицы: сама запись и она же с приставкой «м_» (вторая нужна хвостовым
 *     целям, где голая запись занятой не считается). Занята ли проба, решает
 *     двоичный, а не наше мнение: занята та, которую обход изменил. Дальше
 *     требуется, чтобы второй обход уже ничего не менял.
 *
 * Запуск: `node flang/scripts/target-occupied-guard.mjs` (или `npm run occupied:check`).
 */
import { readdirSync, readFileSync, statSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { спросить, спроситьПачкой } from "./dvoichnyy.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../", import.meta.url))

/** Каталоги корпуса: ровно те три, о которых спрашивают. */
export const КАТАЛОГИ = ["stdlib", "core", "examples"]

/**
 * Восемь целей: чем имя модуля становится именем в цели, чем обходится занятое
 * и какими таблицами занятое названо. Ни одного имени языка здесь нет — только
 * имена функций двоичного, у которого всё это и спрашивается.
 */
export const ЦЕЛИ = Object.freeze({
  c: { имя: ["Змейка"], обход: "Обойти занятое целью C", таблицы: ["Занято целью C"] },
  go: { имя: ["Змейка"], обход: "Обойти занятое целью Go", таблицы: ["Хвосты сборки Go"] },
  rust: { имя: ["Змейка Rust"], обход: "Обойти занятое целью Rust", таблицы: ["Занято целью Rust"] },
  python: {
    имя: ["Змейка Python", "Безопасный идентификатор Python"],
    обход: "Обойти занятое целью Python",
    таблицы: ["Занято целью Python"],
  },
  java: {
    имя: ["Паскаль Java", "Безопасный идентификатор Java"],
    обход: "Обойти занятое целью Java",
    таблицы: ["Занято целью Java"],
  },
  csharp: {
    имя: ["Паскаль CSharp", "Безопасный идентификатор CSharp"],
    обход: "Обойти занятое целью CSharp",
    таблицы: ["Занято целью CSharp"],
  },
  elixir: { имя: ["Модуль Elixir"], обход: "Обойти занятое целью Elixir", таблицы: ["Занято целью Elixir"] },
  js: { имя: ["Змейка"], обход: "Обойти занятое целью JS", таблицы: ["Занято целью JS"] },
})

/** Имя модуля в цели: цепочка преобразований двоичного, слева направо. */
export function имяВЦели(модуль, цель) {
  let имя = модуль
  for (const шаг of ЦЕЛИ[цель].имя) имя = спросить(шаг, имя)
  return имя
}

/** Занятое целью, одним списком: у Go это хвосты сборки, у прочих — имена. */
export function занятоеЦелью(цель) {
  return ЦЕЛИ[цель].таблицы.flatMap((имя) => спросить(имя))
}

/** Обход занятого — тем же шагом, каким его делает печать. */
export const обойти = (имя, цель) => спросить(ЦЕЛИ[цель].обход, имя)

/**
 * Названо ли имя таблицей: целиком либо хвостом после «_». Второе — про Go, и
 * записано отношением строк, а не правилом цели.
 */
export const названоТаблицей = (имя, занятое) =>
  занятое.some((запись) => имя === запись || имя.endsWith(`_${запись}`))

/** Все модули корпуса: путь файла → имя модуля. */
export function модулиКорпуса(корень = КОРЕНЬ) {
  const найденные = []
  const обойтиКаталог = (каталог) => {
    for (const запись of readdirSync(каталог).sort()) {
      const путь = `${каталог}/${запись}`
      if (statSync(путь).isDirectory()) {
        обойтиКаталог(путь)
        continue
      }
      if (!запись.endsWith(".flang")) continue
      const текст = readFileSync(путь, "utf8")
      const совпадение = /^модуль\s+«([^»]+)»/mu.exec(текст)
      if (совпадение === null) continue
      найденные.push({ путь: путь.slice(корень.length), модуль: совпадение[1] })
    }
  }
  for (const каталог of КАТАЛОГИ) обойтиКаталог(`${корень}${каталог}`)
  return найденные
}

/**
 * Вопросы задаются ПАЧКОЙ.
 *
 * Восемь целей на полсотни модулей — это больше восьмисот вызовов, и по
 * процессу на каждый сторож стоил бы минуты. Прогонщик двоичного отвечает
 * построчно, поэтому все они умещаются в один процесс. Цепочка имён
 * прогревается по шагам: второй шаг спрашивается о том, что вернул первый.
 */
function прогреть(модули) {
  спроситьПачкой(
    Object.keys(ЦЕЛИ).flatMap((цель) => ЦЕЛИ[цель].таблицы.map((имя) => ({ имя, аргументы: [] }))),
  )
  for (const цель of Object.keys(ЦЕЛИ)) {
    let имена = модули.map(({ модуль }) => модуль)
    for (const шаг of ЦЕЛИ[цель].имя) {
      имена = спроситьПачкой(имена.map((имя) => ({ имя: шаг, аргументы: [имя] })))
    }
    спроситьПачкой(имена.map((имя) => ({ имя: ЦЕЛИ[цель].обход, аргументы: [имя] })))
  }
}

/** Счёт столкновений по каждой цели и сверка обхода с таблицей. */
export function померить(модули) {
  const итог = {}
  let тождественных = 0
  const самовольных = []
  for (const цель of Object.keys(ЦЕЛИ)) {
    const занятое = занятоеЦелью(цель)
    const столкнулись = []
    for (const { путь, модуль } of модули) {
      const имя = имяВЦели(модуль, цель)
      const обойдённое = обойти(имя, цель)
      if (обойдённое === имя) {
        тождественных += 1
        continue
      }
      столкнулись.push({ путь, модуль, имя, обойдённое })
      /* Обход изменил имя — таблица обязана его называть. Иначе печать
         переименовывает свободное имя, побайтовая сверка покраснела бы разом у
         всего корпуса, а причина осталась бы ненайденной. */
      if (!названоТаблицей(имя, занятое)) самовольных.push({ цель, модуль, имя, обойдённое })
    }
    итог[цель] = { занятых: занятое.length, столкнулись }
  }
  return { итог, тождественных, самовольных }
}

/**
 * Один шаг обхода обязан СНИМАТЬ занятость.
 *
 * Пробы берутся из самой таблицы: запись как есть и она же с приставкой «м_».
 * Вторая нужна хвостовым целям — у Go занят хвост, и голое `linux` занятым не
 * считается, а `м_linux` считается. Какая проба занята, решает двоичный: занята
 * та, которую обход изменил.
 */
export function обходСнимаетЗанятость() {
  const строки = []
  for (const цель of Object.keys(ЦЕЛИ)) {
    const пробы = занятоеЦелью(цель).flatMap((запись) => [запись, `м_${запись}`])
    спроситьПачкой(пробы.map((проба) => ({ имя: ЦЕЛИ[цель].обход, аргументы: [проба] })))
    let занятых = 0
    let снято = 0
    for (const проба of пробы) {
      const один = обойти(проба, цель)
      if (один === проба) continue
      занятых += 1
      if (обойти(один, цель) === один) снято += 1
    }
    строки.push({ цель, занятых, снято })
  }
  return строки
}

export function отчёт(корень = КОРЕНЬ) {
  const модули = модулиКорпуса(корень)
  прогреть(модули)
  const { итог, тождественных, самовольных } = померить(модули)
  const строки = [`Модулей в корпусе (${КАТАЛОГИ.join(", ")}): ${модули.length}`, ""]
  let всего = 0
  for (const [цель, { занятых, столкнулись }] of Object.entries(итог)) {
    всего += столкнулись.length
    строки.push(`${цель.padEnd(7)} занято целью: ${String(занятых).padStart(3)}   столкнулось: ${столкнулись.length}`)
    for (const { модуль, имя, обойдённое } of столкнулись) {
      строки.push(`          «${модуль}» → ${имя} → обход ${обойдённое}`)
    }
  }
  const снятие = обходСнимаетЗанятость()
  const занятых = снятие.reduce((сумма, { занятых: сколько }) => сумма + сколько, 0)
  const снято = снятие.reduce((сумма, { снято: сколько }) => сумма + сколько, 0)
  строки.push("", `Всего столкновений по восьми целям: ${всего}`)
  строки.push(`Обход тождествен на свободном имени: ${тождественных} сверок из ${модули.length * 8 - всего}`)
  строки.push(`Обход трогает только названное таблицей: самовольных ${самовольных.length}`)
  for (const { цель, модуль, имя, обойдённое } of самовольных) {
    строки.push(`          ${цель}: «${модуль}» → ${имя} → ${обойдённое}, а таблица этого имени не называет`)
  }
  строки.push(`Один шаг обхода снимает занятость: ${снято} из ${занятых}`)
  return { текст: строки.join("\n"), всего, модулей: модули.length, тождественных, самовольных, занятых, снято, итог }
}

if (process.argv[1] !== undefined && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  const { текст, тождественных, модулей, всего, самовольных, занятых, снято } = отчёт()
  console.log(текст)
  if (тождественных !== модулей * 8 - всего) {
    console.error("ОБХОД НЕ ТОЖДЕСТВЕН на свободном имени — печать сменила бы вывод там, где смысл не менялся")
    process.exit(1)
  }
  if (самовольных.length > 0) {
    console.error("ОБХОД ТРОГАЕТ ИМЯ, КОТОРОГО ТАБЛИЦА НЕ НАЗЫВАЕТ — таблица занятого и обход разошлись")
    process.exit(1)
  }
  if (снято !== занятых) {
    console.error("ОДИН ШАГ ОБХОДА НЕ СНИМАЕТ ЗАНЯТОСТЬ — обойдённое имя цель по-прежнему занимает")
    process.exit(1)
  }
  if (занятых === 0) {
    console.error("НИ ОДНА ПРОБА НЕ ОКАЗАЛАСЬ ЗАНЯТОЙ — сверка снятия прошла вхолостую")
    process.exit(1)
  }
}
