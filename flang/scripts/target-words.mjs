/**
 * СТОРОЖ ЗАНЯТЫХ СЛОВ: собирается ли напечатанное, когда имена в модели совпали
 * с ключевыми словами цели.
 *
 * ── Что было не закрыто ─────────────────────────────────────────────────────
 *
 * Обещание языка — «печать не выпускает непроверенное». Программа из шести
 * строк его ломала:
 *
 *     тотальная функция «Сумма»
 *       принимает до: неотрицательное
 *       ...
 *           иначе до плюс («Сумма» от (до минус 1))
 *
 * `flang check` — «замечаний нет». `flang emit --target c` + `make` —
 * `error: expected ';' before 'do'`: имя `до` транслитерируется в `do`, а
 * подпись тела рекурсивной функции называла параметр БЕЗ экранирования, хотя
 * вызов десятью строками ниже звал его `do_2`. Про дефект узнавал чужой
 * компилятор, а не наш.
 *
 * Проверялось это раньше только глазами: у каждой из восьми целей свой список
 * занятого, у C к нему добавлены имена, которые печать раздаёт СЕБЕ (`args`
 * батута, `bounce`, `values` фабрики, `region` области, `out` фабрики), и
 * сойтись список печати со списком проверки могли только случайно.
 *
 * ── Что делает сторож ───────────────────────────────────────────────────────
 *
 *   1. ПОДДЕЛКА. `flang/test/fixtures/poddelka-slova-celey.flang` — программа,
 *      называющая параметры, связки, поля записи и поля варианта занятыми
 *      словами. Печатается во все восемь целей и СОБИРАЕТСЯ каждой из них её
 *      собственным `make`. Не собралось — сторож красный.
 *
 *   2. ИСЧЕРПЫВАЮЩЕ, ПО СПИСКУ САМОЙ ПЕЧАТИ. Список занятого спрашивается у
 *      ДВОИЧНОГО — `«Зарезервировано в C»`, `«Занято в теле»`,
 *      `«Зарезервировано в Go»` и так далее, — а не переписывается сюда.
 *      Копия списка не проверяет ничего: разъедься она с печатью, сторож
 *      зеленел бы ровно на тех словах, ради которых заведён. По списку
 *      строится программа, ставящая КАЖДОЕ слово в каждую опасную позицию, и
 *      она тоже печатается и собирается.
 *
 *   3. ИМЯ МОДУЛЯ. Оно доезжает до цели именем файла, именем класса или
 *      идентификатором `mod`, и занято там своё: ключевые слова цели, имена её
 *      библиотеки И имена файлов, которые печать кладёт рядом. Проверяются
 *      НАЗВАННЫЕ имена — по одному на каждую РАЗНУЮ причину, с уликой при
 *      каждом (перечень `ИМЕНА_МОДУЛЕЙ` ниже). Сверх сборки считается число
 *      напечатанных файлов: имя, совпавшее с именем соседнего файла, ложится
 *      поверх него — сборка при этом молчит.
 *
 * Проверка позиций закрыта: параметр простой функции, параметр рекурсивной
 * (тело уезжает в отдельную функцию — там дефект и был), параметр взаимной
 * рекурсии (значения едут через массив батута), связка `пусть`, поле записи и
 * поле варианта (фабрика и конструктор печатают их параметрами).
 *
 * ── Чего сторож НЕ делает ───────────────────────────────────────────────────
 *
 * Не запускает собранное. Вопрос здесь один — СОБИРАЕТСЯ ЛИ, и на него отвечает
 * компилятор цели. Что напечатанное считает верно, меряют примеры библиотеки.
 *
 * Цели, чьего компилятора на машине нет, называются и пропускаются: молча
 * пропущенная цель — это зелёный сторож, ничего не проверивший.
 *
 * Запуск: node flang/scripts/target-words.mjs
 *         node flang/scripts/target-words.mjs --tolko-poddelka   (без п. 2)
 *         node flang/scripts/target-words.mjs --cel=rust      (одна цель)
 *
 * Ярлык: ./ярлык слова:проверка
 */
