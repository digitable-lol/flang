/** Напечатать программу в цель. Возвращает `{ok, текст}`. */
function напечатать(файл, цель, куда) {
  const итог = spawnSync(путьДвоичного(), ["emit", файл, "--target", цель, "--out", куда], {
    encoding: "utf8",
    cwd: КОРЕНЬ,
    maxBuffer: 1 << 28,
    env: { ...process.env, LC_ALL: "C.UTF-8" },
  })
  return { ok: (итог.status ?? 1) === 0, текст: ((итог.stdout ?? "") + (итог.stderr ?? "")).trim() }
}

/**
 * Собрать напечатанное её же файлом сборки. У JavaScript сборки нет — разбор.
 *
 * `TMPDIR` уводится в тот же каталог: `dotnet` и `cargo` иначе сыплют в общий
 * временный каталог машины, и убрать за собой уже нечем.
 */
function собрать(цель, куда) {
  if (цель.сборка === null) {
    for (const имя of readdirSync(куда)) {
      if (!имя.endsWith(".js")) continue
      const итог = spawnSync("node", ["--check", join(куда, имя)], { encoding: "utf8" })
      if ((итог.status ?? 1) !== 0) return { ok: false, текст: (итог.stderr ?? "").trim() }
    }
    return { ok: true, текст: "" }
  }
  const свой = join(куда, ".vremennoe")
  mkdirSync(свой, { recursive: true })
  const итог = spawnSync(цель.сборка[0], ["-C", куда], {
    encoding: "utf8",
    maxBuffer: 1 << 28,
    env: { ...process.env, TMPDIR: свой, TEMP: свой, TMP: свой },
  })
  return { ok: (итог.status ?? 1) === 0, текст: ((итог.stdout ?? "") + (итог.stderr ?? "")).trim() }
}

/** Первые строки чужой диагностики: без них «не собралось» ничего не говорит. */
const первые = (текст, сколько = 6) =>
  текст.split("\n").filter((с) => /error|Error|ошибк|отказ/.test(с)).slice(0, сколько).join("\n      ") ||
  текст.split("\n").slice(-сколько).join("\n      ")

/** Сколько файлов цель кладёт в каталог (считая вложенные каталоги Go и Rust). */
function сколькоФайлов(куда) {
  let сколько = 0
  for (const запись of readdirSync(куда, { withFileTypes: true })) {
    if (запись.isDirectory()) сколько += сколькоФайлов(join(куда, запись.name))
    else сколько += 1
  }
  return сколько
}

/**
 * Один прогон: напечатать файл в цель и собрать.
 *
 * `ждём файлов` — сколько файлов печать даёт на программе с НЕЗАНЯТЫМ именем.
 * Без этого счёта имя модуля, совпавшее с именем файла, который печать кладёт
 * рядом, проходит молча: `модуль «Flang cli»` печатал программу ПОВЕРХ
 * прогонщика, в каталоге оставался один файл вместо двух, и `node --check` на
 * уцелевшем проходил.
 */
function прогнать(файл, цель, метка, ждёмФайлов = 0) {
  const куда = mkdtempSync(join(КОРЕНЬ, ".flang-slova-"))
  try {
    const печать = напечатать(файл, цель.имя, куда)
    if (!печать.ok) {
      плохо(`${метка}: ${цель.имя} — ПЕЧАТЬ ОТКАЗАЛА\n      ${первые(печать.текст, 3)}`)
      return
    }
    const сколько = сколькоФайлов(куда)
    if (ждёмФайлов > 0 && сколько !== ждёмФайлов) {
      плохо(`${метка}: ${цель.имя} — файлов ${сколько}, а на незанятом имени ${ждёмФайлов}: печать легла поверх того, что кладёт рядом`)
      return
    }
    const сборка = собрать(цель, куда)
    if (!сборка.ok) плохо(`${метка}: ${цель.имя} — НАПЕЧАТАННОЕ НЕ СОБИРАЕТСЯ\n      ${первые(сборка.текст)}`)
    else console.log(`  ${метка}: ${цель.имя} — напечатано и собрано`)
  } finally {
    rmSync(куда, { recursive: true, force: true })
  }
}

/** Сколько файлов цель кладёт на программе с заведомо свободным именем модуля. */
function образцовыйСчёт(цель, где) {
  const файл = join(где, `obrazec-${цель.имя}.flang`)
  writeFileSync(файл, "модуль «Образец счёта файлов»\n\nтотальная функция «Удвоить»\n  принимает «а»: число\n  возвращает число\n  «а» умножить на 2\n", "utf8")
  const куда = mkdtempSync(join(КОРЕНЬ, ".flang-slova-"))
  try {
    const печать = напечатать(файл, цель.имя, куда)
    if (!печать.ok) { плохо(`образец счёта: ${цель.имя} — печать отказала`); return 0 }
    return сколькоФайлов(куда)
  } finally {
    rmSync(куда, { recursive: true, force: true })
  }
}

/**
 * Программа по списку занятого: каждое слово в каждой опасной позиции.
 *
 * Имена ставятся В ЁЛОЧКАХ: часть занятых слов цели — ещё и слова самого языка
 * (`if`, `return`, `match`, `type`, `result`, `list`), и голыми они именами не
 * бывают. В ёлочках именем становится любое.
 *
 * Слова, различающиеся только регистром (`Double` и `double` у Java), берутся
 * по одному: у цели они дают один идентификатор, и печать отказывает по другой
 * причине — столкновению имён модели, а не по экранированию.
 */
function программаПоСписку(цель, слова) {
  const набор = []
  const видано = new Set()
  for (const с of слова) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(с)) continue
    const н = с.toLowerCase()
    if (видано.has(н)) continue
    видано.add(н)
    набор.push(с)
  }
  const куски = []
  for (let и = 0; и < набор.length; и += 10) куски.push(набор.slice(и, и + 10))

  let т = `модуль «Занятое у ${цель.имя}»\n`
  т += `\nобъект «Поля записи»\n${набор.map((с) => `  «${с}»: число\n`).join("")}`
  т += `\nтип «Поля варианта»\n  вариант «Ничего»\n  вариант «Всё» содержит ${набор.map((с) => `«${с}»: число`).join(", ")}\n`
  т += `\nтотальная функция «Собрать запись»\n  принимает «а»: число\n  возвращает «Поля записи»\n  запись «Поля записи» с ${набор.map((с) => `«${с}» равным «а»`).join(" и ")}\n`
  т += `\nтотальная функция «Собрать вариант»\n  принимает «а»: число\n  возвращает «Поля варианта»\n  «Всё» с ${набор.map((с) => `«${с}» равным «а»`).join(" и ")}\n`
  куски.forEach((кусок, к) => {
    const сумма = (имена) => имена.map((с) => `«${с}»`).reduce((л, п) => `(${л} плюс ${п})`)
    т += `\nтотальная функция «Простая ${к}»\n  принимает ${кусок.map((с) => `«${с}»: число`).join(", ")}\n  возвращает число\n  ${сумма(кусок)}\n`
    т += `\nтотальная функция «Вглубь ${к}»\n  принимает «${кусок[0]}»: нат\n  возвращает число\n  если «${кусок[0]}» не больше 0\n    то 0\n    иначе «${кусок[0]}» плюс («Вглубь ${к}» от («${кусок[0]}» минус 1))\n`
    т += `\nтотальная функция «Чётное ${к}»\n  принимает «${кусок[0]}»: нат\n  возвращает признак\n  убывает «${кусок[0]}»\n  если «${кусок[0]}» не больше 0\n    то да\n    иначе «Нечётное ${к}» от («${кусок[0]}» минус 1)\n`
    т += `\nтотальная функция «Нечётное ${к}»\n  принимает «${кусок[кусок.length - 1]}»: нат\n  возвращает признак\n  убывает «${кусок[кусок.length - 1]}»\n  если «${кусок[кусок.length - 1]}» не больше 0\n    то нет\n    иначе «Чётное ${к}» от («${кусок[кусок.length - 1]}» минус 1)\n`
    т += `\nтотальная функция «Связки ${к}»\n  принимает «а»: число\n  возвращает число\n${кусок.map((с, и) => `  пусть «${с}» равно («${и === 0 ? "а" : кусок[и - 1]}» плюс 1)\n`).join("")}  «${кусок[кусок.length - 1]}» плюс 1\n`
  })
  return { текст: т, слов: набор.length }
}

