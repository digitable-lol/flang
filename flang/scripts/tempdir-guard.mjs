/**
 * Сторож ВРЕМЕННЫХ КАТАЛОГОВ: прогон, оставивший мусор, обязан сказать об этом
 * числом.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * /tmp здесь — tmpfs на 1 048 576 инодов. Когда прогоны печати перестают
 * убирать за собой, иноды кончаются раньше места (192 ГБ свободно, а `mkdir`
 * отвечает ENOSPC), и падает не тот прогон, который намусорил, а СОСЕДНИЙ.
 * Разбирать чужую беду по коду ошибки, который врёт про диск, — потерянный
 * заход; это уже стоило заходов троим.
 *
 * Уборка, которую никто не проверяет, ломается молча и ровно тогда, когда
 * что-то другое уже сломано. Поэтому счёт ведётся всегда и называется числом.
 *
 * ── Как считается ───────────────────────────────────────────────────────────
 *
 * Сторож заводит прогону ОДИН корень — `/tmp/flang-run-<pid>-XXXXXX` — и
 * передаёт его вниз через `FLANG_TEST_TMPDIR`. Помощник `flang/test/tempdir.mjs`
 * кладёт туда свои каталоги, а `средаСборки()` уводит туда же `TMPDIR` чужих
 * тулчейнов. Значит, весь мусор прогона обязан лежать в этом корне.
 *
 * Отсюда две меры, и первая из них НЕДВУСМЫСЛЕННА:
 *
 *   1. СВОЁ — сколько всего осталось в корне прогона. На машине работают чужие
 *      сессии, и по общему счёту /tmp своё от чужого не отличить; по своему
 *      корню — отличить точно. Больше нуля — красное с именами;
 *
 *   2. МИМО КОРНЯ — что появилось прямо в /tmp за время прогона и похоже на
 *      след печати: `flang-*` (кроме своего корня), `MSBuildTemp*`,
 *      `NuGetScratch*`, `go-build#`. Это ловит код, который завёл каталог мимо
 *      помощника. Красным эта мера НЕ становится: приписать чужой каталог себе
 *      здесь нельзя — соседняя сессия, гоняющая непочиненное дерево, кладёт
 *      ровно такие же имена, и сторож, краснеющий от соседа, перестают читать.
 *      Имена печатаются всегда, и по ним видно, чей это след; `FTS_TMP_STRICT=1`
 *      делает и эту меру красной — для машины, где прогон один.
 *
 * Общий счёт каталогов в /tmp до и после печатается всегда: он шумный (соседи),
 * но это ровно то число, которым мерили беду.
 *
 * ── Чего сторож НЕ делает ───────────────────────────────────────────────────
 *
 * Он не убирает ЧУЖОЕ. Каталог, заведённый минуту назад, может быть живым, и
 * снести его — это ровно та же беда, только со сменившимся виновником. Сторож
 * убирает свой корень и больше ничего.
 *
 * Запуск:
 *
 *   node flang/scripts/tempdir-guard.mjs                    — прогон бэкендов
 *   node flang/scripts/tempdir-guard.mjs -- <команда...>     — своя команда
 *
 * Или `npm run tmp:check`. Проверяется он сам — тестом
 * `flang/test/tempdir-guard.test.mjs`.
 */
import { spawnSync } from "node:child_process"
import { mkdtempSync, readdirSync, realpathSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

/** Имена, по которым узнаётся след печати, оставленный МИМО корня прогона. */
export const СЛЕДЫ = [
  { имя: "каталоги тестов печати", образец: /^flang-/u },
  { имя: "MSBuild", образец: /^MSBuildTemp/u },
  { имя: "NuGet", образец: /^NuGetScratch/u },
  { имя: "сборка Go", образец: /^go-build\d+$/u },
]

/** Имена подкаталогов `корень` — по ним и считается мусор. */
export function перепись(корень) {
  try {
    return readdirSync(корень, { withFileTypes: true })
      .filter((вход) => вход.isDirectory())
      .map((вход) => вход.name)
      .sort()
  } catch {
    return []
  }
}

/** Что из `имена` похоже на след печати — по видам. */
export function поВидам(имена) {
  const итог = []
  for (const { имя, образец } of СЛЕДЫ) {
    const свои = имена.filter((н) => образец.test(н))
    if (свои.length > 0) итог.push({ вид: имя, сколько: свои.length, имена: свои })
  }
  return итог
}

/**
 * Посчитать мусор прогона.
 *
 * `корень` — каталог прогона; `до`/`после` — переписи /tmp вокруг прогона.
 * Возвращает `{ своё, мимо, чисто }`, где `чисто` — единственный вывод, ради
 * которого сторож существует.
 */
export function счёт({ корень, имяКорня, до, после, строго = false }) {
  const своё = перепись(корень)
  const новые = после.filter((н) => !до.includes(н) && н !== имяКорня)
  const мимо = поВидам(новые)
  return {
    своё,
    мимо,
    новых: новые.length,
    строго,
    /* Красным делает только СВОЁ: чужой каталог с тем же именем сторожу не
       принадлежит, и краснеть за соседа значит перестать быть читаемым. */
    чисто: своё.length === 0 && (!строго || мимо.length === 0),
  }
}

/** Отчёт числами — то, что читает человек и по чему краснеет прогон. */
export function отчёт({ доВсего, послеВсего, итог }) {
  const строки = [
    `каталогов в ${tmpdir()}: до ${доВсего}, после ${послеВсего}`,
    `своих осталось: ${итог.своё.length}`,
  ]
  if (итог.своё.length > 0) {
    строки.push(`  ${итог.своё.slice(0, 20).join(", ")}${итог.своё.length > 20 ? ` … и ещё ${итог.своё.length - 20}` : ""}`)
  }
  for (const { вид, сколько, имена } of итог.мимо) {
    строки.push(`мимо корня, ${вид}: ${сколько}${итог.строго ? "" : " (не наше — счёт, не приговор)"}`)
    строки.push(`  ${имена.slice(0, 20).join(", ")}${имена.length > 20 ? ` … и ещё ${имена.length - 20}` : ""}`)
  }
  строки.push(итог.чисто ? "чисто: прогон убрал за собой всё" : "ГРЯЗНО: прогон оставил каталоги — имена выше")
  return строки.join("\n")
}

/** Команда по умолчанию — тот самый прогон, который травил соседей. */
export const ПРОГОН_ПО_УМОЛЧАНИЮ = [
  process.execPath,
  "--test",
  "--test-timeout=1800000",
  "flang/test/emit-*.test.mjs",
  "flang/test/self-emit-*.test.mjs",
]

function главная(аргументы) {
  const черта = аргументы.indexOf("--")
  const команда = черта === -1 ? ПРОГОН_ПО_УМОЛЧАНИЮ : аргументы.slice(черта + 1)
  if (команда.length === 0) {
    process.stderr.write("нечего запускать: после `--` пусто\n")
    return 2
  }

  const корень = mkdtempSync(join(tmpdir(), `flang-run-${process.pid}-`))
  const имяКорня = корень.slice(tmpdir().length + 1)
  const до = перепись(tmpdir())

  let код = 0
  try {
    const итогЗапуска = spawnSync(команда[0], команда.slice(1), {
      stdio: "inherit",
      env: { ...process.env, FLANG_TEST_TMPDIR: корень },
      shell: команда === ПРОГОН_ПО_УМОЛЧАНИЮ,
    })
    код = итогЗапуска.status ?? 1
  } finally {
    const после = перепись(tmpdir())
    const итог = счёт({ корень, имяКорня, до, после, строго: process.env.FTS_TMP_STRICT === "1" })
    process.stdout.write(`\n── сторож временных каталогов ──\n${отчёт({
      доВсего: до.length,
      послеВсего: после.length,
      итог,
    })}\n`)
    /* Свой корень — единственное, что сторож вправе снести. */
    try {
      rmSync(корень, { recursive: true, force: true, maxRetries: 3 })
    } catch {
      /* Не наше дело ронять прогон об уборку. */
    }
    if (!итог.чисто && код === 0) код = 1
  }
  return код
}

/* Запущен как программа, а не как модуль. Сравниваются пути, а не имена: файл
   с тем же именем в другом каталоге — не этот файл. */
if (process.argv[1] !== undefined
  && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  process.exit(главная(process.argv.slice(2)))
}
