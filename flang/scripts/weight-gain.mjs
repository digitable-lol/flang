/**
 * Замер: сколько функций корпуса становятся ДОКАЗУЕМО неотрицательными, если
 * объявить их числовые параметры типом `вес` вместо `число`.
 *
 * ── Зачем нужен отдельный замер, а не свод ведомости ────────────────────────
 * `flang/scripts/proof-ledger.mjs` считает то, что в корпусе НАПИСАНО:
 * утверждений там девять, и ни одно из них не про `вес` — потому что до этой
 * работы такого типа не было. Вопрос же стоит про сослагательное наклонение:
 * «сколько СТАЛО БЫ доказуемо, объяви мы их иначе». Ответ на такой вопрос
 * получается не чтением, а ПЕРЕОБЪЯВЛЕНИЕМ, и считать его надо явно.
 *
 * ── Что именно считается ────────────────────────────────────────────────────
 * Для каждой функции корпуса, возвращающей число, спрашивается у ядра
 * доказательства (`flang/proof/reduce.mjs`, правило «неотрицательность по
 * построению») один и тот же вопрос — «выводимо ли `результат не меньше 0`» — в
 * двух постановках:
 *
 *   КАК ЕСТЬ    фактов из объявления столько, сколько даёт нынешняя подпись:
 *               `нат` даёт, `число` и `целое` не дают;
 *   НА ВЕСЕ     каждый числовой параметр объявлен `вес`, то есть даёт факт.
 *
 * Разница этих двух чисел и есть цена типа, выраженная в функциях. Считает то
 * же самое ядро и то же самое правило — второго решателя здесь нет.
 *
 * ── Чего этот замер НЕ утверждает ───────────────────────────────────────────
 * Он не утверждает, что все посчитанные функции СЛЕДУЕТ переобъявить: у функции
 * может быть причина принимать отрицательное. Он отвечает ровно на то, что
 * спрошено, — на скольких функциях корпуса объявление `вес` превращает
 * недоказуемое в доказанное. Функции, у которых вывод проходит и без него,
 * считаются отдельной строкой, чтобы прирост не приписывался типу дважды.
 *
 * Запуск:
 *   node flang/scripts/weight-gain.mjs           словами
 *   node flang/scripts/weight-gain.mjs --json    машине
 *   node flang/scripts/weight-gain.mjs --files   ещё и по функции на строку
 */
import { readFileSync, realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { неотрицательно, нормализовать, сДном } from "../proof/reduce.mjs"
import { parse } from "../src/parser.mjs"
import { globSync } from "../test/glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/** Файлы корпуса — тем же списком и с тем же исключением, что у свода ведомости. */
export const ФАЙЛЫ = globSync("flang/**/*.flang", { cwd: корень })
  .filter((путь) => путь !== "flang/self/bootstrap/compiler.flang")
  .sort()

/**
 * Числовой ли объявленный тип — по имени, как его видит ядро.
 *
 * Ключевое слово `число` приезжает узлом `{kind: "number"}`; имена уточнений —
 * узлом `{kind: "named"}`. Оба вида здесь и перечислены; всё прочее (строка,
 * признак, список, запись) в замер не входит, потому что «не меньше 0» про них
 * не утверждение, а бессмыслица.
 */
const ЧИСЛОВЫЕ_ИМЕНА = new Set([
  "число", "number", "Число", "Деньги",
  "нат", "натуральное", "nat", "naturo", "自然数",
  "целое", "integer", "entjero", "整数",
  "вес", "стоимость", "weight", "pezo", "权重",
])

function числовойТип(тип) {
  if (тип === null || тип === undefined) return false
  if (тип.kind === "number") return true
  return тип.kind === "named" && typeof тип.name === "string" && ЧИСЛОВЫЕ_ИМЕНА.has(тип.name)
}

/** Та же подпись, но каждый числовой параметр объявлен `вес`. */
function наВесе(параметры) {
  return (параметры ?? []).map((параметр) =>
    числовойТип(параметр?.type) ? { ...параметр, type: { kind: "named", name: "вес" } } : параметр)
}

/**
 * Приговор одной функции: выводимо ли «тело не меньше 0» в двух постановках.
 *
 * Спрашивается ровно то же, что спрашивает ядро у постусловия `обеспечивает …
 * результат не меньше 0`: правило свёртки по телу, без вычисления и без поиска.
 */
export function приговор(функция) {
  const тело = нормализовать(функция?.body)
  return {
    какЕсть: неотрицательно(тело, сДном(функция?.params)),
    наВесе: неотрицательно(тело, сДном(наВесе(функция?.params))),
  }
}

/**
 * Свод по всему корпусу.
 *
 * Программы разбираются ПООТДЕЛЬНОСТИ и без связывания — намеренно, и это
 * отличие от свода ведомости названо: правило неотрицательности смотрит только
 * на тело функции и на объявления её собственных параметров, а импортированные
 * имена в нём остаются непрозрачными термами при любом связывании. Связывать
 * было бы лишней работой с тем же ответом, а каждая функция посчиталась бы
 * столько раз, сколько модулей её зовёт.
 */
export function свод() {
  const строки = []
  const отказы = []
  for (const путь of ФАЙЛЫ) {
    let программа
    try {
      программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    } catch (беда) {
      отказы.push({ путь, беда: беда?.message ?? String(беда) })
      continue
    }
    for (const функция of программа?.functions ?? []) {
      if (!числовойТип(функция?.returns)) continue
      const числовых = (функция.params ?? []).filter((п) => числовойТип(п?.type)).length
      if (числовых === 0) continue
      строки.push({ путь, имя: функция.name, числовых, ...приговор(функция) })
    }
  }
  const итог = {
    функций: строки.length,
    какЕсть: строки.filter((с) => с.какЕсть).length,
    наВесе: строки.filter((с) => с.наВесе).length,
    прирост: строки.filter((с) => с.наВесе && !с.какЕсть).length,
    /* Потерь быть не может — факт только ДОБАВЛЯЕТСЯ, — но считаются они всё
       равно: строка, которая обязана быть нулём, обязана и печататься. */
    потерь: строки.filter((с) => с.какЕсть && !с.наВесе).length,
  }
  return { строки, итог, отказы }
}

function печать(с, поФункциям) {
  const и = с.итог
  const текст = ["── что даёт объявление «вес»: замер по корпусу ──"]
  if (поФункциям) {
    for (const строка of с.строки.filter((з) => з.наВесе && !з.какЕсть)) {
      текст.push(`  + ${строка.путь} «${строка.имя}» (числовых параметров ${строка.числовых})`)
    }
    текст.push("")
  }
  текст.push(
    `файлов в корпусе: ${ФАЙЛЫ.length}`,
    `функций, возвращающих число и принимающих число: ${и.функций}`,
    "у скольких из них ядро выводит «результат не меньше 0»:",
    `  как объявлено сейчас:              ${и.какЕсть}`,
    `  если числовые параметры — «вес»:   ${и.наВесе}`,
    `  ПРИРОСТ (стало доказуемо):         ${и.прирост}`,
    `  потерь:                            ${и.потерь}`,
  )
  for (const отказ of с.отказы) текст.push(`не разобрано: ${отказ.путь} — ${отказ.беда}`)
  return `${текст.join("\n")}\n`
}

let запущен = false
if (process.argv[1] !== undefined) {
  try {
    запущен = realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
  } catch {
    запущен = false
  }
}
if (запущен) {
  const итог = свод()
  if (process.argv.includes("--json")) {
    process.stdout.write(`${JSON.stringify({ итог: итог.итог, отказы: итог.отказы }, null, 2)}\n`)
  } else {
    process.stdout.write(печать(итог, process.argv.includes("--files")))
  }
  process.exitCode = итог.отказы.length === 0 ? 0 : 1
}
