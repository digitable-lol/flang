/**
 * СТОРОЖ СЛОВ О ДОКАЗАННОСТИ: сильное слово нельзя сказать про слабое основание.
 *
 * ── Улика, ради которой сторож заведён ──────────────────────────────────────
 * В дереве уживаются вещи РАЗНОЙ СИЛЫ, и часть из них норовит назваться одним
 * словом:
 *
 *     терм принят ядром        вывод из правил, обо ВСЕХ входах
 *     счёт на сетке            проверено перебором значений — НЕ доказательство
 *     объявлено                сказано, доказательства нет вовсе
 *     ничего не смотрели       и это НЕ «замечаний нет»
 *
 * Число «доказано N» — то самое, по которому решают, заслужено ли слово
 * «формально-доказуемый». Подмешай в него счёт — и число станет ложью, а
 * поймать её будет нечем: словарь, за которым никто не следит, разъезжается за
 * месяц.
 *
 * ── ЧЕТВЁРТОЕ РАЗЛИЧИЕ, И ОНО ВНУТРИ «ДОКАЗАНО» ─────────────────────────────
 * Мало отделить доказанное от посчитанного. Внутри доказанного лежат
 * утверждения, верные про ЛЮБУЮ функцию этой подписи: «результат не меньше
 * нуля» у функции, объявленной возвращающей «нат», доказывается и тогда, когда
 * тело выброшено целиком. Слово «доказано» о нём законно — ложью оно не
 * становится, — но считать его наравне с содержательным значит сделать счёт
 * больше знания.
 *
 * Отличается это ПРОГОНОМ, а не мнением: тело функции заменяется ЗАГЛУШКОЙ того
 * же объявленного типа, подпись и текст утверждения остаются, ведомость
 * считается заново.
 *
 *     с заглушкой утверждение ОТПАЛО   → СОДЕРЖАТЕЛЬНОЕ: отличает настоящее
 *                                        тело от подставного;
 *     с заглушкой ОСТАЛОСЬ доказанным  → ПРО ПОДПИСЬ: про эту функцию не
 *                                        говорит ничего;
 *     спецификация дословно есть тело  → ДАРОВОЕ: спека и есть реализация;
 *     заглушки для типа нет            → НЕ СУДИЛИ. Отдельная куча, и молчать
 *                                        о ней нельзя: «не смотрели» ≠ «чисто».
 *
 * Приём подмены не выдуман здесь: он уже работает в
 * `benchmarks/proof-cost/count-library.mjs`. Там он МЕРЯЕТ и всегда отдаёт
 * код 0; здесь он СТЕРЕЖЁТ и краснеет.
 *
 * ── Что проверяется, по одной строке на правило ─────────────────────────────
 *   1. СЛОВО ↔ ВЕРДИКТ. Словарь закрыт: у каждого вердикта ровно одно
 *      начальное слово строки ведомости. Строка, начатая чужим словом или
 *      словом неизвестным, — красная. Так «доказано» физически не сказать про
 *      вердикт «grid».
 *   2. ЧИСЛО ↔ ВЕРДИКТ. Итог, напечатанный двоичным, пересчитывается из строк
 *      утверждений заново. «Доказано» обязано равняться числу вердиктов
 *      `proved` и `proved-induction` и не содержать НИ ОДНОГО `grid`.
 *   3. ПРОЗА ↔ МАШИНА. Человек читает не JSON, а строку «утверждений N:
 *      доказано D, сетка G, объявлено, не доказано O». Она сверяется с
 *      машинным видом: разъехаться им нельзя.
 *   4. ПУСТОТА. Прогон с заглушкой; куча каждого доказанного утверждения
 *      обязана совпасть с записанной в каталоге.
 *   5. СОДЕРЖАНИЕ, А НЕ ИМЯ. Каталог держит ОТПЕЧАТОК ЦЕЛИ (полный AST без
 *      мест). Ослабь спеку под тем же именем («не больше 30» → «не больше
 *      1000») — отпечаток разойдётся, и сторож покраснеет. Сверка по именам
 *      этого не ловит, и ровно так уже проезжали.
 *   6. КАТАЛОГ ПОЛОН. Подделка, забытая в каталоге, никем не проверяется:
 *      файл `flang/test/fixtures/poddelka-*.flang` обязан быть назван в
 *      `poddelki-yadra.mjs`, в `kernel-forgeries.flang` или здесь. Не названный
 *      нигде — красный. Названный в разделе «подделки без сторожа» с ПРИЧИНОЙ —
 *      это долг: он печатается в каждом прогоне и не даёт себя забыть.
 *      Этим правилом на этом дереве сразу нашлись ЧЕТЫРЕ подделки, которые не
 *      прогоняет никто, — и о трёх из них заметки утверждают обратное.
 *   7. ДОЛГ ЯДРА. Место, где сама ведомость говорит больше, чем знает, а
 *      починка стоит перепечатки точки раскрутки. Записывается долгом с
 *      ДОСЛОВНЫМИ словами и печатается в каждом прогоне. Долг
 *      самозакрывающийся: убрали негодные слова из ядра — сторож требует убрать
 *      и запись, иначе список долгов зарастёт закрытыми пунктами.
 *
 * ── ПОКАЗ ПОРЧИ: зелёный без неё ничего не значит ───────────────────────────
 * Сторож, который не может покраснеть, от отсутствующего неотличим. Поэтому у
 * него есть ключ `--porcha <вид>`: он портит ДАННЫЕ (не сторожа) ровно тем
 * способом, ради которого сторож написан, и обязан покраснеть.
 *
 *   --porcha slovo     вердикт «grid» переписан в «proved», слова оставлены
 *                      сеточные — правило 1 обязано поймать;
 *   --porcha chislo    в итоге прибавлена единица к «доказано» — правило 2;
 *   --porcha proza     в человеческой строке «доказано D» подменено число —
 *                      правило 3;
 *   --porcha pustota   в каталоге «про подпись» переписано в
 *                      «содержательное» — правило 4;
 *   --porcha spek      цель утверждения ослаблена под тем же именем —
 *                      правило 5;
 *   --porcha dolg      шапка словаря вычеркнута, будто долг ядра закрыт —
 *                      правило 7 обязано потребовать убрать запись о долге.
 *
 * Порча живёт в памяти прогона и на диске ничего не меняет, кроме `spek`: та
 * пишет ослабленную копию файла во ВРЕМЕННЫЙ каталог рядом и убирает за собой.
 *
 * ── ПЕРЕПИСЬ ───────────────────────────────────────────────────────────────
 * `--perepis` отвечает обходом на вопрос «сколько в дереве мест, где рядом со
 * словом „доказано“ стоит число, и сколько из них кто-нибудь проверяет».
 * Замер 21 августа 2026: мест 84 в 43 файлах, под сторожем чисел — 2.
 *
 * Прогон:
 *   node flang/scripts/word-guard.mjs                 сторож, обе половины молчат
 *   node flang/scripts/word-guard.mjs --porcha vse    обе половины: чисто и порча
 *   node flang/scripts/word-guard.mjs --porcha slovo  одна порча
 *   node flang/scripts/word-guard.mjs --perepis       перепись мест в прозе
 */
