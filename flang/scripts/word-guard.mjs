/* ── 1. СЛОВАРЬ: у каждого вердикта ровно одно начальное слово ───────────── */

/**
 * Закрытая таблица «вердикт → слово, которым обязана начинаться строка».
 *
 * Закрытая — значит новое слово в ядре краснеет здесь, а не расходится молча.
 * Порядок внутри строки важен: «доказано индукцией» проверяется до «доказано»,
 * иначе второе съело бы первое.
 */
export const СЛОВАРЬ = new Map([
  ["proved", { слово: "доказано", сила: "вывод обо ВСЕХ входах" }],
  ["proved-induction", { слово: "доказано индукцией", сила: "вывод обо всех входах бесконечного носителя" }],
  /* Четвёртый вердикт ядра, и слово у него СВОЁ, а не «доказано» с оговоркой в
     хвосте. Строка начинается «доказано ПРИ УСЛОВИИ», и проверяется это слово
     ДО «доказано индукцией» и «доказано»: иначе оба съели бы его началом, и
     условное доказательство прочиталось бы безусловным — ровно та подмена, от
     которой заведён этот словарь. */
  ["proved-conditional", { слово: "доказано ПРИ УСЛОВИИ", сила: "вывод верен ровно настолько, насколько доказана посылка" }],
  ["grid", { слово: "сетка", сила: "счёт на конечной сетке — НЕ доказательство" }],
  ["declared", { слово: "объявлено, не доказано", сила: "доказательства нет вовсе" }],
  ["violated", { слово: "НАРУШЕНО", сила: "прогон нашёл контрпример" }],
  ["refused", { слово: "отвергнуто", сила: "ядро не свело цель" }],
])

/** Начальное слово строки ведомости, или `null`, если слово неизвестно. */
export function словоСтроки(говорит) {
  const текст = String(говорит ?? "")
  if (текст.startsWith("доказано ПРИ УСЛОВИИ")) return "доказано ПРИ УСЛОВИИ"
  if (текст.startsWith("доказано индукцией")) return "доказано индукцией"
  if (текст.startsWith("доказано")) return "доказано"
  if (текст.startsWith("сетка")) return "сетка"
  /* «на сетке» — та же сетка, только у ЗАКОНА: судья категорий говорит
     «ПОСЧИТАНО НА СЕТКЕ», и слово у него то же по силе. */
  if (текст.startsWith("на сетке") || текст.startsWith("ПОСЧИТАНО НА СЕТКЕ")) return "сетка"
  if (текст.startsWith("объявлено, не доказано")) return "объявлено, не доказано"
  if (текст.startsWith("НАРУШЕНО")) return "НАРУШЕНО"
  if (текст.startsWith("отвергнуто")) return "отвергнуто"
  return null
}

/**
 * Слово «доказано» вне сочетания «не доказано» и «не доказательство».
 *
 * Строка сетки обязана СКАЗАТЬ, что доказательством она не является, — то есть
 * слово «доказательство» в ней стоит законно. А вот утверждение «доказано»
 * внутри неё — уже подмена, и ловится оно именно так: сначала вычёркиваются
 * отрицания, потом ищется утверждение.
 */
export function говоритДоказано(говорит) {
  const без = String(говорит ?? "")
    .replace(/не\s+доказано/giu, " ")
    .replace(/не\s+доказательство/giu, " ")
    .replace(/не\s+является\s+доказательством/giu, " ")
    .replace(/недоказ\p{L}*/giu, " ")
  return /доказан[оы]\b/iu.test(без)
}

/* ── отпечаток цели: содержание, а не имя ─────────────────────────────────── */

/** Тот же узел без мест: место двигается при всякой правке выше по файлу. */
export function безМест(узел) {
  if (Array.isArray(узел)) return узел.map(безМест)
  if (узел === null || typeof узел !== "object") return узел
  const итог = {}
  for (const ключ of Object.keys(узел).sort()) {
    if (ключ === "span") continue
    итог[ключ] = безМест(узел[ключ])
  }
  return итог
}

export const отпечаток = (цель) => createHash("sha256").update(JSON.stringify(безМест(цель))).digest("hex").slice(0, 16)

/* ── заглушки для проверки на пустоту ─────────────────────────────────────── */

/**
 * Заглушка по объявленному типу результата.
 *
 * Ключи ИМЕНОВАННЫХ типов — кириллические, и это не вкус: `flang ast` отдаёт
 * `{"kind":"named","name":"нат"}`, а не `"nat"`. Латинские имена в этой таблице
 * не совпали бы ни разу, и всякая функция, объявленная возвращающей `нат` или
 * `вес`, молча ушла бы в кучу «не судили» — то есть счёт «не смотрели» рос бы
 * там, где смотреть было чем. Латинские оставлены синонимами: они ничего не
 * стоят, а если печать имён когда-нибудь сменится, таблица не онемеет.
 *
 * Типов с дном в языке шесть («нат», «целое», «вес», «стоимость», «сотых»,
 * «тысячных» — `flang/self/proof-kernel.flang`), и у всех дно ноль.
 */
const ЗАГЛУШКИ = new Map([
  ["number", "0"], ["string", '""'], ["flag", "нет"], ["list", "пустой список"],
  ["неотрицательное", "0"], ["нат", "0"], ["целое", "0"], ["вес", "0"], ["стоимость", "0"], ["сотых", "0"], ["тысячных", "0"],
  ["nat", "0"], ["integer", "0"], ["weight", "0"], ["cost", "0"],
])

export function заглушка(тип) {
  if (тип?.kind === "named") return ЗАГЛУШКИ.get(тип.name) ?? null
  return ЗАГЛУШКИ.get(тип?.kind) ?? null
}

/** Строки тела функции: от строки тела до первой строки без отступа. */
function конецТела(строки, первая) {
  let конец = строки.length
  for (let и = первая; и < строки.length; и += 1) {
    if (/^\S/u.test(строки[и])) { конец = и; break }
  }
  while (конец > первая && строки[конец - 1].trim() === "") конец -= 1
  return конец
}

export function сЗаглушкой(исходник, функция, текст) {
  const строки = исходник.split("\n")
  const первая = функция.body.span.line - 1
  return [...строки.slice(0, первая), "  " + текст, ...строки.slice(конецТела(строки, первая))].join("\n")
}

/**
 * Тот же исходник без единого `пример`.
 *
 * Примеры описывают НАСТОЯЩЕЕ поведение: с заглушкой они краснеют все разом, и
 * до ведомости дело не доходит вовсе. Снимаются у ОБОИХ исходников — равное
 * сравнивается с равным, иначе «отпало» читалось бы там, где просто не считали.
 */
export function безПримеров(исходник) {
  const строки = исходник.split("\n")
  const итог = []
  for (let и = 0; и < строки.length; и += 1) {
    const шапка = /^(\s*)(пример|example)(?:\s|$)/u.exec(строки[и])
    if (шапка === null) { итог.push(строки[и]); continue }
    const глубина = шапка[1].length
    и += 1
    while (и < строки.length) {
      const строка = строки[и]
      if (строка.trim() !== "" && /^\s*/u.exec(строка)[0].length <= глубина) break
      и += 1
    }
    и -= 1
  }
  return итог.join("\n")
}

/* ── суд над одной ведомостью: правила 1—3 и 5 ────────────────────────────── */

const ключ = (з) => `${з.of ?? ""}|${з.name ?? ""}`

/**
 * Правила, которым довольно машинного вида. Чистая функция: ей всё равно,
 * приехала ведомость от двоичного или её испортили нарочно.
 *
 * @param {string} файл путь от корня, для сообщений
 * @param {object} в ведомость (`check --proof --json`)
 * @param {string} проза человеческий вывод (`check --proof`)
 * @param {object|null} запись каталога для этого файла
 */
export function судить(файл, в, проза, запись) {
  const беды = []
  const плохо = (текст) => беды.push(`${файл}: ${текст}`)
  const заявки = в.claims ?? []

  /* 1. СЛОВО ↔ ВЕРДИКТ. */
  for (const з of заявки) {
    const ждём = СЛОВАРЬ.get(з.verdict)
    if (ждём === undefined) { плохо(`«${з.name}»: вердикт «${з.verdict}» словарю неизвестен — словарь закрыт, впишите слово или почините ядро`); continue }
    const сказано = словоСтроки(з.says)
    if (сказано === null) { плохо(`«${з.name}»: строка начата словом вне словаря — «${String(з.says).slice(0, 40)}…»`); continue }
    if (сказано !== ждём.слово) плохо(`«${з.name}»: вердикт ${з.verdict} (${ждём.сила}), а сказано словом «${сказано}» — сильное слово про слабое основание`)
    if (з.verdict === "grid" && говоритДоказано(з.says)) сказаноДоказано(плохо, з)
    if (з.verdict === "declared" && говоритДоказано(з.says)) сказаноДоказано(плохо, з)
  }

  /* 2. ЧИСЛО ↔ ВЕРДИКТ: итог пересчитывается из строк, а не берётся на слово. */
  const счёт = { proved: 0, grid: 0, declared: 0, violated: 0, refused: 0, "proved-conditional": 0 }
  let индукцией = 0
  for (const з of заявки) {
    if (з.verdict === "proved" || з.verdict === "proved-induction") счёт.proved += 1
    if (з.verdict === "proved-induction") индукцией += 1
    if (з.verdict in счёт && з.verdict !== "proved") счёт[з.verdict] += 1
  }
  const итог = в.totals?.claims ?? {}
  for (const имя of ["proved", "grid", "declared", "violated", "refused"]) {
    if ((итог[имя] ?? 0) !== счёт[имя]) плохо(`итог «${имя}» = ${итог[имя]}, а строк с таким вердиктом ${счёт[имя]} — счёт разошёлся с тем, что напечатано построчно`)
  }
  /* Условное считается ОТДЕЛЬНОЙ графой, и в машинном виде она зовётся
     `conditional`, а не `proved-conditional`: ключ итога короче вердикта. Без
     этой проверки графа могла бы разъехаться со строками молча — а именно из-за
     неё число «доказано» и падает. */
  if ((итог.conditional ?? 0) !== счёт["proved-conditional"]) плохо(`итог «conditional» = ${итог.conditional}, а строк с вердиктом proved-conditional ${счёт["proved-conditional"]} — счёт разошёлся с тем, что напечатано построчно`)
  /* И то же самое с другой стороны: НИ ОДНО условное не имеет права оказаться
     внутри числа «доказано». Ради этого правила и заведён вердикт. */
  if (счёт.proved + счёт["proved-conditional"] > заявки.length) плохо("доказанных и условных вместе больше, чем утверждений — условное посчитано дважды")
  if ((итог.total ?? 0) !== заявки.length) плохо(`итог «total» = ${итог.total}, а строк ${заявки.length}`)
  if ((итог.induction ?? 0) !== индукцией) плохо(`итог «induction» = ${итог.induction}, а строк индукцией ${индукцией}`)
  /* И то же самое, спрошенное с другой стороны: НИ ОДНО утверждение с вердиктом
     «сетка» не имеет права оказаться внутри числа «доказано». */
  const сетка = заявки.filter((з) => з.verdict === "grid")
  if (счёт.proved + сетка.length > заявки.length) плохо("доказанных и сеточных вместе больше, чем утверждений — сетка посчитана дважды")

  /* 3. ПРОЗА ↔ МАШИНА: человек читает строку итога, а не JSON. */
  if (проза !== null) {
    /* Скобочных пояснений у «доказано» столько, сколько ядро сочло нужным
       напечатать («из них индукцией», «из них без теоремы»), — поэтому их
       группа повторяемая, а не одиночная. За ними может стоять ЧЕТВЁРТЫЙ
       вердикт со своим числом и своей скобкой; когда условных ноль, ядро эту
       графу не печатает вовсе, и она необязательна. */
    const м = /утверждений (\d+): доказано (\d+)(?: \([^)]*\))*(?:, доказано ПРИ УСЛОВИИ (\d+)(?: \([^)]*\))?)?, сетка (\d+), объявлено, не доказано (\d+)/u.exec(проза)
    if (м === null) {
      if (заявки.length > 0) плохо("в человеческом выводе нет строки итога утверждений — число, которого не видно, проверить нечем")
    } else {
      const [, всего, док, условно, сет, объ] = м.map((з) => (з === undefined ? 0 : Number(з)))
      if (всего !== заявки.length) плохо(`проза говорит «утверждений ${всего}», машина — ${заявки.length}`)
      if (док !== счёт.proved) плохо(`проза говорит «доказано ${док}», машина — ${счёт.proved}`)
      if (условно !== счёт["proved-conditional"]) плохо(`проза говорит «доказано ПРИ УСЛОВИИ ${условно}», машина — ${счёт["proved-conditional"]}`)
      if (сет !== счёт.grid) плохо(`проза говорит «сетка ${сет}», машина — ${счёт.grid}`)
      if (объ !== счёт.declared) плохо(`проза говорит «объявлено, не доказано ${объ}», машина — ${счёт.declared}`)
    }
  }

  /* 5. СОДЕРЖАНИЕ, А НЕ ИМЯ. */
  if (запись !== null && запись !== undefined) {
    const цели = new Map((в.obligations ?? []).map((о) => [ключ(о), отпечаток(о.goal)]))
    const вКаталоге = new Map(запись.утверждения.map((у) => [`${у.чья}|${у.имя}`, у]))
    for (const з of заявки) {
      const у = вКаталоге.get(ключ(з))
      if (у === undefined) { плохо(`«${з.name}» функции «${з.of}» НЕЗАРЕГИСТРИРОВАНО в каталоге слов — забытую запись никто не поймает`); continue }
      if (у.вердикт !== з.verdict) плохо(`«${з.name}»: в каталоге вердикт ${у.вердикт}, у двоичного ${з.verdict}`)
      const был = цели.get(ключ(з))
      if (был === undefined) плохо(`«${з.name}»: цели в машинном виде нет — сверять содержание нечем`)
      else if (был !== у.отпечаток) плохо(`«${з.name}»: ЦЕЛЬ ИЗМЕНИЛАСЬ под тем же именем (отпечаток ${у.отпечаток} → ${был}) — спеку ослабили, а имя оставили`)
    }
    for (const у of запись.утверждения) {
      if (!заявки.some((з) => ключ(з) === `${у.чья}|${у.имя}`)) плохо(`«${у.имя}» функции «${у.чья}» есть в каталоге, а в ведомости его нет — сторож смотрит в пустоту`)
    }
  }
  return беды
}

function сказаноДоказано(плохо, з) {
  плохо(`«${з.name}»: вердикт ${з.verdict}, а в строке сказано «доказано» — слабое основание названо словом вывода`)
}

/* ── правило 4: пустота, настоящим прогоном ───────────────────────────────── */

/**
 * Куча одного доказанного утверждения: содержательное, про подпись, даровое
 * или «не судили».
 */
export function пустота(файл, з, д, исходник) {
  const ф = (д.functions ?? []).find((и) => и.name === з.of)
  if (ф === undefined) return { куча: "не судили", почему: "функции с таким именем в дереве нет" }

  /* ДАРОВОЕ отбирается ДО подмены: тавтологию `результат равен <тело>` подмена
     ломает, и без отдельного вопроса она записалась бы в содержательные. */
  const своё = (ф.postconditions ?? []).find((п) => п.name === з.name)
  if (своё !== undefined && тавтология(своё, ф.body)) return { куча: "даровое", почему: "спецификация переписана с тела знак в знак" }

  const текст = заглушка(ф.returns)
  if (текст === null) return { куча: "не судили", почему: `заглушки для типа ${JSON.stringify(ф.returns)} нет` }

  const голый = безПримеров(исходник)
  const до = ведомостьИсходника(голый, файл)
  if (!до.ok) return { куча: "не судили", почему: "исходник без примеров ведомости не даёт" }
  const былоДоказано = (до.ведомость.claims ?? []).some((и) => ключ(и) === ключ(з) && String(и.verdict).startsWith("proved"))
  if (!былоДоказано) return { куча: "не судили", почему: "без примеров утверждение и так не доказано — подмена о нём не говорит ничего" }

  const после = ведомостьИсходника(безПримеров(сЗаглушкой(исходник, ф, текст)), файл)
  if (!после.ok) return { куча: "не судили", почему: "исходник с заглушкой отвергнут целиком" }
  const строки = после.ведомость.claims ?? []
  if (строки.length === 0) return { куча: "не судили", почему: "у исходника с заглушкой ведомость пуста" }
  const осталось = строки.some((и) => ключ(и) === ключ(з) && String(и.verdict).startsWith("proved"))
  return осталось
    ? { куча: "про подпись", почему: `доказано и при теле «${текст}» — верно про любую функцию этой подписи` }
    : { куча: "содержательное", почему: `при теле «${текст}» отпадает — отличает настоящее тело от подставного` }
}

const РЕЗУЛЬТАТ = (у) => у?.kind === "var" && у.name === "результат"
export function тавтология(постусловие, тело) {
  const в = постусловие.expr
  if (в?.kind !== "binary" || в.op !== "eq") return false
  const другая = РЕЗУЛЬТАТ(в.left) ? в.right : РЕЗУЛЬТАТ(в.right) ? в.left : null
  if (другая === null) return false
  return JSON.stringify(безМест(другая)) === JSON.stringify(безМест(тело))
}

/* ── правило 7: шапка словаря не обещает больше, чем говорят строки ───────── */

/**
 * ДОЛГ ЯДРА: место, где сама ведомость говорит больше, чем знает.
 *
 * Шапку словаря печатает двоичный (`flang/self/proof.flang`), и поправить её
 * можно только перепечаткой точки раскрутки — семнадцать минут и 20—25 ГиБ
 * памяти. Поэтому найденное записывается ДОЛГОМ и печатается в каждом прогоне:
 * молча ждать удобного случая — то же самое, что не найти.
 *
 * Долг САМОЗАКРЫВАЮЩИЙСЯ: сторож проверяет, что негодные слова ЕЩЁ стоят на
 * месте. Починили ядро — запись повисла в пустоте, и сторож требует её убрать.
 * Без этой половины список долгов зарастает закрытыми пунктами и перестаёт
 * читаться.
 */
export function долгиЯдра(проза, долги) {
  const стоят = []
  const пропали = []
  for (const { слова, беда } of долги) {
    if (проза.includes(слова)) стоят.push(`«${слова}» — ${беда}`)
    else пропали.push(слова)
  }
  return { стоят, пропали }
}

/* ── правило 6: каталог подделок полон ────────────────────────────────────── */

export function незарегистрированныеПодделки(корень, свои, долг) {
  const каталог = join(корень, "flang/test/fixtures")
  /* Четыре равноправных расширения программы: `.flang`, `.fp`, `.фп`, `.фланг` (ADR-0016). */
  const лежит = readdirSync(каталог).filter((и) => и.startsWith("poddelka-") && /\.(flang|fp|фп|фланг)$/u.test(и)).sort()
  /* Каталог подделок в дереве ОДИН: `kernel-forgeries.flang`, он зовётся ярлыком
     `подделки:проверка`. Двойник на JavaScript снят 23 августа 2026 (`fe870a05`),
     и этот сторож восемь часов падал на его чтении: файла нет — падает весь
     прогон, а не одно правило. Отсюда чтение через try: пропавший каталог
     называется бедой и роняет сторожа НАЗВАННО, а не стек-трейсом node. */
  const путиКаталогов = ["flang/scripts/kernel-forgeries.flang"]
  const пропали = []
  const каталоги = путиКаталогов
    .map((путь) => {
      try {
        return readFileSync(join(корень, путь), "utf8")
      } catch {
        пропали.push(путь)
        return ""
      }
    })
    .join("\n")
  const забытые = []
  const безСторожа = []
  for (const имя of лежит) {
    const путь = `flang/test/fixtures/${имя}`
    if (каталоги.includes(путь) || свои.has(путь)) continue
    /* НАЗВАННЫЙ ДОЛГ И ЗАБЫТАЯ ЗАПИСЬ — РАЗНОЕ. Подделка, о которой в дереве
       записано, ПОЧЕМУ сторожа при ней нет, — это долг: он печатается в каждом
       прогоне и не даёт себя забыть. Подделка, о которой не записано ничего,
       красная: именно так забытая запись и пропадает из виду. */
    if (Object.hasOwn(долг, путь)) безСторожа.push(`${путь} — ${долг[путь]}`)
    else забытые.push(путь)
  }
  for (const путь of Object.keys(долг)) {
    if (!лежит.includes(путь.split("/").pop())) забытые.push(`${путь}: записан в долг, а файла в дереве нет — долг смотрит в пустоту`)
  }
  for (const путь of пропали) забытые.push(`${путь}: каталог подделок пропал из дерева — сторож не видит, что в нём было записано`)
  return { забытые, безСторожа }
}

/* ── перепись: кто в дереве произносит слово «доказано» ───────────────────── */

/**
 * ПЕРЕПИСЬ ОБХОДОМ, А НЕ ГЛАЗАМИ.
 *
 * Вопрос простой и неприятный: сколько в дереве мест, где рядом со словом
 * «доказано» стоит ЧИСЛО, — и сколько из них кто-нибудь проверяет.
 *
 * Проверяет их `flang/scripts/count-guard.mjs`, и список его образцов ЗАКРЫТ
 * намеренно: открытый поиск «N утверждений» ловил бы предложения про
 * утверждения вообще, а свод — про утверждения корпуса, и это разные числа.
 * Цена закрытости — всё, что мимо образца, не проверяется ничем, и перепись
 * называет это числом, а не умолчанием.
 *
 * Образцы берутся у самого сторожа чисел (`ВЕДОМОСТЬ`), а не переписываются
 * сюда: второй список разошёлся бы с первым молча.
 */
export async function перепись(корень) {
  const { ВЕДОМОСТЬ } = await import("./count-guard.mjs")
  const { execFileSync } = await import("node:child_process")
  const файлы = execFileSync("git", ["-c", "core.quotePath=false", "ls-files", "*.md"], { cwd: корень, encoding: "utf8" })
    .split("\n").filter(Boolean)
  const ЧИСЛО_РЯДОМ = /(?:доказан\p{L}*\s+\d+|\d+\s+доказан\p{L}*)/giu
  let всего = 0
  let подСторожем = 0
  const поФайлам = new Map()
  for (const путь of файлы) {
    let текст
    try { текст = readFileSync(join(корень, путь), "utf8") } catch { continue }
    /* Считается ПО СТРОКАМ, а не по коротким совпадениям: образцы сторожа
       чисел ловят фразу целиком («N доказаны ядром»), и обрезок «N доказаны»
       не подошёл бы ни под один — перепись показала бы ноль проверяемых там,
       где их два, то есть соврала бы в свою пользу. */
    for (const строка of текст.split("\n")) {
      ЧИСЛО_РЯДОМ.lastIndex = 0
      if (!ЧИСЛО_РЯДОМ.test(строка)) continue
      ЧИСЛО_РЯДОМ.lastIndex = 0
      const сколько = (строка.match(ЧИСЛО_РЯДОМ) ?? []).length
      всего += сколько
      if (ВЕДОМОСТЬ.some(({ образец }) => образец.test(строка))) {
        подСторожем += сколько
        вКучу(поФайлам, путь, "под сторожем", сколько)
      } else вКучу(поФайлам, путь, "вне сторожа", сколько)
    }
  }
  return { всего, подСторожем, вне: всего - подСторожем, файлов: поФайлам.size, поФайлам }
}

function вКучу(поФайлам, путь, куча, сколько) {
  const было = поФайлам.get(путь) ?? { "под сторожем": 0, "вне сторожа": 0 }
  было[куча] += сколько
  поФайлам.set(путь, было)
}

/* ── прогон ───────────────────────────────────────────────────────────────── */

const ПУТЬ_КАТАЛОГА = join(КОРЕНЬ, "flang/scripts/proof-words.json")

/** Человеческий вывод той же команды: его читает не машина, а человек. */
function прозаВедомости(путь) {
  const { вывод } = позвать(["check", resolve(КОРЕНЬ, путь), "--proof"])
  return вывод
}

/** Ослабить цель утверждения прямо в исходнике — для показа порчи `spek`. */
function ослабить(исходник) {
  return исходник.replace("(длина результат) равен 4", "(длина результат) не меньше 0")
}

/** Виды порчи — по одному на правило, которое обязано её поймать. */
export const ПОРЧИ = ["slovo", "chislo", "proza", "pustota", "spek", "dolg"]

async function судПоКаталогу(порча) {
  const каталог = JSON.parse(readFileSync(ПУТЬ_КАТАЛОГА, "utf8"))
  const беды = []
  const хорошо = []
  let перваяПроза = ""

  for (const [файл, запись] of Object.entries(каталог.файлы)) {
    let исходник = readFileSync(join(КОРЕНЬ, файл), "utf8")
    let гдеСмотреть = файл
    let времянка = null
    if (порча === "spek") {
      времянка = mkdtempSync(join(dirname(join(КОРЕНЬ, файл)), ".porcha-"))
      гдеСмотреть = join(времянка, "проба.flang")
      исходник = ослабить(исходник)
      writeFileSync(гдеСмотреть, исходник)
    }
    try {
      const ответ = ведомость(гдеСмотреть)
      if (!ответ.ok) { беды.push(`${файл}: ведомость не сложилась — ${ответ.why ?? "код " + ответ.код}`); continue }
      const в = JSON.parse(JSON.stringify(ответ.ведомость))
      let проза = прозаВедомости(гдеСмотреть)

      if (порча === "slovo") for (const з of в.claims) if (з.verdict === "grid") з.verdict = "proved"
      if (порча === "chislo") в.totals.claims.proved += 1
      if (порча === "proza") проза = проза.replace(/доказано (\d+)/u, (_, н) => `доказано ${Number(н) + 1}`)
      /* «Долг закрыт» подделывается вычёркиванием шапки словаря: тогда записи
         каталога повисают в пустоте, и сторож обязан потребовать их убрать. */
      if (порча === "dolg") проза = проза.replace(/слова ведомости[\s\S]*?\n\n/u, "\n")
      if (перваяПроза === "") перваяПроза = проза

      беды.push(...судить(файл, в, проза, запись))

      /* 4. ПУСТОТА — настоящим прогоном, по одному на доказанное утверждение. */
      const д = дерево(гдеСмотреть)
      if (!д.ok) { беды.push(`${файл}: дерево не разобралось — ${д.why}`); continue }
      const вКаталоге = new Map(запись.утверждения.map((у) => [`${у.чья}|${у.имя}`, у]))
      for (const з of в.claims) {
        const у = вКаталоге.get(ключ(з))
        if (у === undefined) continue
        const ждём = порча === "pustota" && у.основание === "про подпись" ? "содержательное" : у.основание
        if (!String(з.verdict).startsWith("proved")) {
          /* Недоказанному подмена ничего не говорит: и с заглушкой у него
             останется «сетка». Каталог обязан звать это своим словом. */
          if (ждём !== "не доказано") беды.push(`${файл}: «${з.name}» — вердикт ${з.verdict}, а в каталоге основание «${ждём}»; у недоказанного основание одно: «не доказано»`)
          else хорошо.push(`  ${файл}: «${з.name}» — ${з.verdict.toUpperCase()}, в счёт «доказано» НЕ идёт`)
          continue
        }
        const { куча, почему } = пустота(гдеСмотреть, з, д.дерево, исходник)
        if (куча !== ждём) беды.push(`${файл}: «${з.name}» — прогон с заглушкой говорит «${куча}» (${почему}), а каталог ждёт «${ждём}»`)
        else хорошо.push(`  ${файл}: «${з.name}» — ДОКАЗАНО, ${куча} (${почему})`)
      }
    } finally {
      if (времянка !== null) rmSync(времянка, { recursive: true, force: true })
    }
  }

  /* 7. ДОЛГИ ЯДРА: шапка словаря, обещающая больше, чем говорят строки. */
  const { стоят, пропали } = долгиЯдра(перваяПроза, каталог["долг ядра"] ?? [])
  for (const слова of пропали) беды.push(`долг ядра «${слова}» закрыт, а запись о нём осталась — уберите её из каталога, иначе список долгов зарастёт`)
  if (стоят.length > 0) {
    хорошо.push(`  ДОЛГОВ ЯДРА: ${стоят.length} — ведомость говорит больше, чем знает, и починка стоит перепечатки точки раскрутки:`)
    for (const строка of стоят) хорошо.push(`    ${строка}`)
  }

  /* 6. КАТАЛОГ ПОЛОН. */
  const { забытые, безСторожа } = незарегистрированныеПодделки(
    КОРЕНЬ,
    new Set(Object.keys(каталог.файлы)),
    каталог["подделки без сторожа"] ?? {},
  )
  for (const путь of забытые) беды.push(`${путь}: НЕЗАРЕГИСТРИРОВАННАЯ ПОДДЕЛКА — не названа ни в одном каталоге, значит не проверяется никем`)
  if (забытые.length === 0) хорошо.push("  каталоги подделок полны: каждая подделка дерева названа поимённо или записана в долг")
  if (безСторожа.length > 0) {
    хорошо.push(`  ПОДДЕЛОК БЕЗ СТОРОЖА: ${безСторожа.length} — это НЕ «замечаний нет», это названный долг:`)
    for (const строка of безСторожа) хорошо.push(`    ${строка}`)
  }

  return { беды, хорошо, файлов: Object.keys(каталог.файлы).length, утверждений: Object.values(каталог.файлы).reduce((с, з) => с + з.утверждения.length, 0) }
}

/**
 * ПОДЛОГ: сторож обязан покраснеть на КАЖДОЙ из пяти порч.
 *
 * Половина «молчит, когда чисто» без половины «краснеет, когда грязно» не
 * значит ничего: сторож, который не может покраснеть, от отсутствующего
 * неотличим. Обе половины спрашиваются одной командой.
 */
async function подлог() {
  let бед = 0
  const чисто = await судПоКаталогу(null)
  if (чисто.беды.length !== 0) {
    console.error(`  • без порчи сторож УЖЕ красный (${чисто.беды.length}) — мерить подлогом нечего`)
    for (const беда of чисто.беды) console.error(`      ${беда}`)
    бед += 1
  } else console.log("  без порчи: нарушений 0 (половина «молчит, когда чисто»)")
  for (const порча of ПОРЧИ) {
    const { беды } = await судПоКаталогу(порча)
    if (беды.length === 0) {
      console.error(`  • порча «${порча}» НЕ ПОЙМАНА — сторож слеп ровно к тому, ради чего написан`)
      бед += 1
    } else console.log(`  порча «${порча}»: поймана, нарушений ${беды.length} — ${беды[0].slice(0, 160)}`)
  }
  console.log("")
  if (бед === 0) {
    console.log(`подлог слов: обе половины на месте — чисто молчит, ${ПОРЧИ.length} порч(и) пойманы`)
    process.exit(0)
  }
  console.error(`подлог слов: не сработало ${бед}`)
  process.exit(1)
}

