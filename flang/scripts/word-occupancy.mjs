/**
 * Занятость слова-кандидата — не `grep`-ом, а тем же `tokenize`, каким корпус
 * читает язык.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. Каждое новое ключевое слово в `lexer.mjs` снабжено
 * строкой «проверено токенизацией всех файлов репозитория: голых вхождений
 * столько». Проверка делалась руками и её результат жил только в комментарии,
 * поэтому повторить её было нельзя, а число в комментарии нечем было
 * опровергнуть. Скрипт делает ровно то же и печатает то же число.
 *
 * ЧТО СЧИТАЕТСЯ ЗАНЯТОСТЬЮ. Слово занято, если стоит в корпусе ГОЛЫМ — токеном
 * `name` с `quoted: false`: переменной, параметром, полем, именем одним словом.
 * Такое слово, став ключевым, сломает файл, к нововведению отношения не
 * имеющий. Закавыченное имя ключевым словом стать не может никогда, поэтому
 * «ёлочки», обычные кавычки и комментарии не считаются вовсе — именно этим
 * счёт отличается от `grep`, который их считает и потому всегда завышен.
 *
 * ФРАЗА ИЗ ДВУХ СЛОВ проверяется как последовательность соседних токенов.
 * Фразой из двух слов переменную не назвать (в языке это уже довод: так
 * появились `порог отказов`, `код символа`, `обратный элемент`), но пара может
 * случайно сложиться из двух уже стоящих рядом слов, и это надо увидеть
 * глазами, а не узнать после правки таблицы.
 *
 * Запуск: `node flang/scripts/word-occupancy.mjs слово «фраза из слов» …`
 */
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { keywordId, tokenize } from "../src/lexer.mjs"
import { globSync } from "../test/glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

const КАНДИДАТЫ = process.argv.slice(2)
if (КАНДИДАТЫ.length === 0) {
  console.error("укажите слова-кандидаты аргументами: node flang/scripts/word-occupancy.mjs убывает «код символа»")
  process.exit(2)
}

const файлы = [
  ...globSync("**/*.flang", { cwd: корень, exclude: (путь) => путь.includes("node_modules") }),
  ...globSync("**/*.fts", { cwd: корень, exclude: (путь) => путь.includes("node_modules") }),
].sort()

/* Слово токена в том виде, в каком его видит склейка ключевых слов: у `name` —
   значение, у `keyword` — исходный текст. Второе нужно, чтобы отличить
   «кандидат стоит голым» от «кандидат столкнулся с уже занятым словом». */
const слово = (токен) => {
  if (токен.kind === "name") return String(токен.value ?? "").toLowerCase()
  if (токен.kind === "keyword") return String(токен.text ?? "").toLowerCase()
  return null
}

const итог = new Map(
  КАНДИДАТЫ.map((кандидат) => [кандидат, { голых: 0, столкновений: 0, места: [], уже: keywordId(кандидат) }]),
)
const сломано = []
let разобрано = 0

for (const путь of файлы) {
  let токены
  try {
    токены = tokenize(readFileSync(`${корень}${путь}`, "utf8"))
  } catch (ошибка) {
    /* В корпусе есть намеренно сломанные модели — они часть проверок отказа.
       Молча пропустить их нельзя: тогда охват уменьшился бы неизвестно на
       сколько, а это ровно та беда, из-за которой корпус печатает свой охват. */
    сломано.push(`${путь}: ${ошибка.message}`)
    continue
  }
  разобрано += 1
  const поток = токены.map((токен) => ({ токен, текст: слово(токен) }))

  for (const кандидат of КАНДИДАТЫ) {
    const части = кандидат.toLowerCase().split(" ")
    for (let и = 0; и + части.length <= поток.length; и += 1) {
      let сошлось = true
      for (let ж = 0; ж < части.length; ж += 1) {
        if (поток[и + ж].текст !== части[ж]) { сошлось = false; break }
      }
      if (!сошлось) continue
      const узлы = части.map((_, ж) => поток[и + ж].токен)
      /* «Ёлочки» отпадают здесь: лексер отдаёт их тем же `name`, но с
         `quoted: true`, и ключевым словом такое имя не станет никогда. */
      if (узлы.some((узел) => узел.kind === "name" && узел.quoted === true)) continue
      const место = `${путь}:${узлы[0].span?.line ?? "?"}`
      if (узлы.every((узел) => узел.kind === "name")) {
        итог.get(кандидат).голых += 1
        итог.get(кандидат).места.push(место)
      } else {
        итог.get(кандидат).столкновений += 1
        итог.get(кандидат).места.push(`${место} — столкновение с ключевым`)
      }
    }
  }
}

console.log(`корпус: ${разобрано} файлов .flang и .fts разобрано, ${сломано.length} не разобралось`)
for (const строка of сломано) console.log(`  не разобралось — ${строка}`)
console.log("")
for (const [кандидат, данные] of итог) {
  const уже = данные.уже === null ? "" : `  [УЖЕ КЛЮЧЕВОЕ: ${данные.уже}]`
  const хвост = данные.столкновений === 0 ? "" : `, столкновений с ключевыми ${данные.столкновений}`
  console.log(`«${кандидат}»: голых вхождений ${данные.голых}${хвост}${уже}`)
  for (const место of данные.места.slice(0, 10)) console.log(`    ${место}`)
  if (данные.места.length > 10) console.log(`    … ещё ${данные.места.length - 10}`)
}
