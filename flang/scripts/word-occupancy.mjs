/**
 * Занятость слова в корпусе `.flang`.
 *
 * Вопрос, на который отвечает эта программа, один: если сделать это слово
 * ключевым, сколько уже написанных программ сломается?
 *
 * ── Почему не грепом ───────────────────────────────────────────────────────
 *
 * Греп считает вхождения текста, а ломает программу не текст, а ТОКЕН. Слово в
 * комментарии, слово внутри строкового литерала и имя в ёлочках («Нат») ключевым
 * словом не становятся никогда — лексер их даже не рассматривает
 * (`foldKeywords` пропускает `quoted`). Ломается ровно одно: ГОЛОЕ слово,
 * стоящее в потоке токенов именем. Поэтому корпус читается тем же
 * `tokenize`, каким его читает язык, и считаются только голые имена.
 *
 * Тот же счёт уже применялся к языку руками — при заведении `убывает`
 * («голого `убывает` в репозитории нет ни одного: все 58 вхождений —
 * комментарии, строковые литералы и имена в ёлочках») и при заведении
 * `код символа` («голых вхождений „код“ — 226, у пары „код символа“ — ноль»).
 * Здесь он сведён в команду, чтобы владелец языка получал это число одним
 * запуском, а не пересчётом глазами.
 *
 * ── Что считается ──────────────────────────────────────────────────────────
 *
 *   голым именем    — СЛОМАЕТСЯ. Слово стоит в программе именем, и ключевым
 *                     оно станет прямо у автора под руками.
 *   в ёлочках       — безопасно: закавыченное имя ключевым не становится.
 *   в строке        — безопасно: литерал лексер не разбирает.
 *   в комментарии   — безопасно: комментарий не даёт токенов вовсе.
 *   уже ключевое    — слово занято другой конструкцией языка; это отказ, а не
 *                     число: одна фраза не вправе означать две конструкции.
 *
 * Фраза из нескольких слов проверяется как фраза: голыми обязаны стоять ВСЕ её
 * слова подряд. Именно поэтому пара `код символа` прошла там, где одинокое
 * `код` было занято 226 раз.
 *
 * Запуск:
 *   node flang/scripts/word-occupancy.mjs нат натуральное «целое число»
 *   node flang/scripts/word-occupancy.mjs --json нат целое
 */
import { readFileSync, realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { keywordId, tokenize } from "../src/lexer.mjs"
import { globSync } from "../test/glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/**
 * Файлы корпуса.
 *
 * Берутся ВСЕ `.flang` дерева, а не только те, что в `flang/`: слово ломает
 * программу там, где она написана, и `examples/library-api/` — такая же
 * написанная программа, как `flang/stdlib/`. Склеенный самоприменением
 * компилятор исключён по той же причине, что в своде ведомости: это сборка
 * остальных файлов, и его слова посчитались бы дважды.
 */
export const ФАЙЛЫ = globSync("**/*.flang", { cwd: корень })
  .filter((путь) => путь !== "flang/self/bootstrap/compiler.flang")
  .filter((путь) => !путь.startsWith("node_modules/"))
  .sort()

/**
 * Занятость одной фразы.
 *
 * @param {string} фраза слово или фраза из нескольких слов
 * @param {string[]} файлы пути от корня репозитория
 * @param {string} корневой каталог, от которого читаются пути — свой у проверки
 *   самого замера: подложенный файл обязан считаться теми же правилами, что
 *   корпус, иначе проверка проверяет не то, чем меряют.
 * @returns {object} счёт по видам вхождений и места голых
 */
export function занятость(фраза, файлы = ФАЙЛЫ, корневой = корень) {
  const слова = фраза.trim().toLowerCase().split(/\s+/u)
  /* Внутри строки и комментария слово ищется ЦЕЛИКОМ, а не подстрокой. Без
     границы «нат» нашлось бы в «координат» и «начать» тридцать четыре раза, и
     число, стоящее рядом с настоящим счётом голых имён, читалось бы как счёт
     того же рода. Граница — «не буква и не цифра»: язык пишется кириллицей,
     латиницей и иероглифами сразу, поэтому \b здесь не годится. */
  const целиком = новыйПоиск(слова.join(" "))
  const итог = {
    фраза,
    ключевое: keywordId(фраза.trim()),
    голым: 0,
    вЁлочках: 0,
    вСтроке: 0,
    вКомментарии: 0,
    места: [],
  }

  for (const путь of файлы) {
    const исходник = readFileSync(`${корневой}${корневой.endsWith("/") ? "" : "/"}${путь}`, "utf8")
    /* Дешёвый отсев: файла без единого вхождения текста можно не токенизировать.
       На 156 файлах это разница между секундой и десятком. */
    if (!исходник.toLowerCase().includes(слова[0])) continue

    let токены
    try {
      токены = tokenize(исходник)
    } catch (беда) {
      итог.места.push(`${путь}: не разобрался лексером — ${беда?.message ?? String(беда)}`)
      continue
    }

    for (let i = 0; i < токены.length; i += 1) {
      const токен = токены[i]
      if (токен.kind === "string" && typeof токен.value === "string") {
        if (целиком.test(токен.value)) итог.вСтроке += 1
        continue
      }
      if (токен.kind === "name" && токен.quoted === true) {
        if (String(токен.value).toLowerCase() === слова.join(" ")) итог.вЁлочках += 1
        continue
      }
      if (токен.kind !== "name" || токен.quoted === true) continue
      /* Голая фраза: все слова подряд, все незакавыченные имена. Проверять
         `keyword` здесь незачем — ключевым слово ещё не стало, иначе `keywordId`
         выше уже сказал бы об этом. */
      let совпало = true
      for (let ш = 0; ш < слова.length; ш += 1) {
        const т = токены[i + ш]
        if (!т || т.kind !== "name" || т.quoted === true || String(т.value).toLowerCase() !== слова[ш]) {
          совпало = false
          break
        }
      }
      if (!совпало) continue
      итог.голым += 1
      итог.места.push(`${путь}:${токен.span?.line ?? "?"}`)
      i += слова.length - 1
    }

    итог.вКомментарии += вКомментариях(исходник, целиком)
  }
  return итог
}

/**
 * Вхождения фразы в комментарии — `//` до конца строки и `/* … *\/` блоком.
 *
 * Это единственное место замера, где счёт идёт не по токенам, и он здесь
 * уместен ровно потому, что комментарий токенов НЕ ДАЁТ: лексер их выбрасывает,
 * и спросить его о них нельзя. Цена такого вхождения — ноль, а знать их число
 * надо: без него непонятно, откуда берётся разница между этим замером и грепом,
 * и число «голых» выглядит подозрительно маленьким.
 *
 * Строковый литерал здесь пропускается намеренно: `"…//…"` — не комментарий, а
 * данные, и посчитать его комментарием значило бы назвать безопасным не то.
 */
function вКомментариях(исходник, целиком) {
  let счёт = 0
  let i = 0
  while (i < исходник.length) {
    const символ = исходник[i]
    if (символ === '"') {
      i += 1
      while (i < исходник.length && исходник[i] !== '"') i += исходник[i] === "\\" ? 2 : 1
      i += 1
      continue
    }
    if (символ === "/" && исходник[i + 1] === "/") {
      const конец = исходник.indexOf("\n", i)
      const кусок = исходник.slice(i, конец < 0 ? исходник.length : конец)
      if (целиком.test(кусок)) счёт += 1
      i = конец < 0 ? исходник.length : конец
      continue
    }
    if (символ === "/" && исходник[i + 1] === "*") {
      const конец = исходник.indexOf("*/", i + 2)
      const кусок = исходник.slice(i, конец < 0 ? исходник.length : конец + 2)
      if (целиком.test(кусок)) счёт += 1
      i = конец < 0 ? исходник.length : конец + 2
      continue
    }
    i += 1
  }
  return счёт
}

/**
 * Поиск фразы ЦЕЛИКОМ: границей служит всё, что не буква и не цифра.
 *
 * `\b` не годится — он знает только латиницу с подчёркиванием, а язык пишется
 * ещё кириллицей и иероглифами, и «число» внутри «числовой» он бы не отличил.
 */
function новыйПоиск(фраза) {
  const экранированная = фраза.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")
  return new RegExp(`(?<![\\p{L}\\p{N}])${экранированная}(?![\\p{L}\\p{N}])`, "iu")
}

function печать(записи) {
  const строки = ["── занятость слова в корпусе ──", `файлов прочитано: ${ФАЙЛЫ.length}`, ""]
  for (const з of записи) {
    строки.push(`«${з.фраза}»`)
    if (з.ключевое !== null) {
      строки.push(`  ЗАНЯТО: слово уже ключевое — конструкция «${з.ключевое}». Одна фраза не вправе означать две конструкции.`)
    }
    строки.push(
      `  голым именем:  ${з.голым}${з.голым === 0 ? "  — свободно: поток токенов корпуса не меняется" : "  — СЛОМАЕТСЯ столько мест"}`,
      `  в ёлочках:     ${з.вЁлочках}  (безопасно)`,
      `  в строке:      ${з.вСтроке}  (безопасно)`,
      `  в комментарии: ${з.вКомментарии}  (безопасно)`,
    )
    if (з.голым > 0) {
      const показать = з.места.slice(0, 12)
      строки.push(`  где голым: ${показать.join(", ")}${з.места.length > показать.length ? `, … ещё ${з.места.length - показать.length}` : ""}`)
    }
    строки.push("")
  }
  return `${строки.join("\n")}\n`
}

let запущен = false
if (process.argv[1] !== undefined) {
  try {
    запущен = realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
  } catch {
    запущен = false
  }
}
if (запущен) {
  const слова = process.argv.slice(2).filter((арг) => арг !== "--json")
  if (слова.length === 0) {
    process.stderr.write("нужно хотя бы одно слово: node flang/scripts/word-occupancy.mjs нат целое\n")
    process.exitCode = 2
  } else {
    const записи = слова.map((слово) => занятость(слово))
    if (process.argv.includes("--json")) {
      process.stdout.write(`${JSON.stringify(записи, null, 2)}\n`)
    } else {
      process.stdout.write(печать(записи))
    }
    /* Код возврата — ответ на вопрос владельца: свободно ли слово. Ненулевой,
       если хоть одно из спрошенных занято. */
    process.exitCode = записи.some((з) => з.голым > 0 || з.ключевое !== null) ? 1 : 0
  }
}
