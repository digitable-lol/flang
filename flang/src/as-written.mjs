/**
 * as-written.mjs — как автор НАПИСАЛ: чтение поверхности, без единого решения.
 *
 * ── Почему это отдельный файл ───────────────────────────────────────────────
 * Обе функции ниже жили в `obligations.mjs`, и вместе с ними в рабочий путь
 * `flang check` приезжал весь этот файл — 373 строки, — хотя САМИ
 * ОБЯЗАТЕЛЬСТВА оттуда уже никто не спрашивает: их считает близнец на flang
 * (`flang/self/obligations.flang` через `flang/src/self.mjs`). «Вынут из
 * решения» и «вынут из загрузки» — два разных события, и второго не было ровно
 * из-за двух вспомогательных функций, которые к обязательствам отношения не
 * имеют: их берут ядро (`proofterm.mjs`), вывод типов (`types.mjs`) и оба
 * модуля `flang/proof`.
 *
 * Разделение — не переключение слоя: близнеца у этих двух функций нет и не
 * нужно, потому что решения они не принимают. Всё, что они делают, — читают то,
 * что автор написал, и отвечают про написанное.
 *
 * ── Что здесь есть, и что общего у этих двоих ───────────────────────────────
 *   `какНаписан`  тип словами автора, а не словами типизатора;
 *   `одинаковы`   «в двух местах написано одно и то же» — синтаксически, без
 *                 нормализации и без вычислений.
 *
 * Общее у них — ПОВЕРХНОСТЬ: обе смотрят на дерево разбора до всякого
 * разрешения имён и до всякого упрощения. Ни одна не знает ни про
 * обязательства, ни про теоремы, ни про ядро; ни одна ничего не решает.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 * Ни нормализации, ни приведения, ни вычислений. Всё это живёт в ядре
 * (`flang/proof/reduce.mjs`), и вторая копия разошлась бы с первой молча.
 *
 * ── Байты этого файла входят в адрес проверяющего ───────────────────────────
 * `flang/src/proofcache.mjs`, `адресПроверяющего` хеширует байты ядра, чтобы
 * вердикт из кеша не пережил правку ядра. `одинаковы` решает, закрывает ли
 * теорема цель, — правка в нём меняет вердикты, значит файл обязан стоять в том
 * списке. Он там стоит; уберите его — и старые вердикты доживут до первой
 * ошибки, о которой никто не узнает.
 */

/**
 * Тип — КАК ЕГО НАПИСАЛ АВТОР.
 *
 * `typeName` из `types.mjs` сюда не годится, и это не вкусовщина: он называет
 * РАЗРЕШЁННЫЙ тип, а здесь тип приходит с поверхности — тот, что построил
 * парсер, до всякого разрешения имён. Словари у них разные (`признак` парсер
 * кладёт как `flag`, типизатор как `boolean`), и на `«Светофор»` — `named` —
 * `typeName` отвечает «неизвестный тип», потому что до разрешения не знает,
 * сумма это или запись. А сказать здесь надо ровно то, что стоит в строке
 * `дано`, чтобы сообщение можно было сверить с ней глазами.
 *
 * Неизвестный вид не выдумывается: сообщение обязано остаться правдой и на
 * дереве, собранном руками, где вида может не быть вовсе.
 */
export function какНаписан(тип) {
  if (тип === null || typeof тип !== "object") return "тип без объявления"
  switch (тип.kind) {
    case "number": return тип.fts === undefined ? "число" : тип.fts
    case "string": return тип.fts === undefined ? "строка" : тип.fts
    case "flag": return "признак"
    case "nothing": return "ничто"
    case "list": return `список из ${какНаписан(тип.of)}`
    case "named": {
      const имя = `«${тип.name}»`
      if (!Array.isArray(тип.args) || тип.args.length === 0) return имя
      return `${имя} от ${тип.args.map(какНаписан).join(" и ")}`
    }
    /* Две записи одного типа функции — долг парсера, названный у него же
       (`parseTypeExpression`, «Два узла на один тип»). Здесь обе читаются, а
       не выбирается одна: сообщение не место, где долг чинят. */
    case "fn": {
      const входы = Array.isArray(тип.params) ? тип.params : (тип.from === undefined ? [] : [тип.from])
      const выход = тип.returns ?? тип.to
      const из = входы.length === 0 ? "" : ` из ${входы.map(какНаписан).join(" и ")}`
      return `функция${из} в ${какНаписан(выход)}`
    }
    default: return "тип без объявления"
  }
}

/**
 * Синтаксическое равенство двух выражений — без нормализации и без вычислений.
 *
 * ПОЧЕМУ БЕЗ НОРМАЛИЗАЦИИ. Сравнивать «с точностью до переименования» или «до
 * приведения» значило бы завести здесь второй упрощатель — тот самый, что
 * живёт в ядре, — и разошлись бы они молча. Здесь нужно ровно одно: сказать,
 * что автор написал в двух местах одно и то же. Он либо написал, либо нет.
 *
 * `span` не сравнивается: одно и то же утверждение в двух местах файла стоит на
 * разных строках, и требовать совпадения строк было бы требованием невозможного.
 *
 * ОТМЕТКИ АНАЛИЗА не сравниваются по той же причине, и это не мелочь. Анализ
 * дописывает на узлы поля уже ПОСЛЕ разбора: `доказана` и `числовая` кладёт
 * вывод типов (`types.mjs`, `markProven`), `measure` и `descent` — анализ
 * завершаемости (`totality.mjs`, `markMeasureGuards`). Цель постусловия анализ
 * видит — она вычисляется во время работы; утверждение теоремы он не видит
 * вовсе — оно не вычисляется. Значит одни и те же слова в двух местах приезжают
 * сюда с разным набором отметок, и сравнение отметок означало бы «одинаково
 * написано» проверять по тому, что дописал анализ.
 *
 * Улика, а не опасение: без этой строки свод по корпусу теряет 60 утверждений
 * из 138 — каждую теорему, в чьём утверждении есть арифметика или сравнение,
 * то есть почти каждую.
 */
const ОТМЕТКИ_АНАЛИЗА = new Set(["span", "доказана", "числовая", "measure", "descent"])

export function одинаковы(левое, правое) {
  if (левое === правое) return true
  if (левое === null || правое === null) return false
  if (typeof левое !== "object" || typeof правое !== "object") return false
  if (Array.isArray(левое) !== Array.isArray(правое)) return false
  if (Array.isArray(левое)) {
    if (левое.length !== правое.length) return false
    return левое.every((элемент, и) => одинаковы(элемент, правое[и]))
  }
  const ключи = (узел) => Object.keys(узел).filter((ключ) => !ОТМЕТКИ_АНАЛИЗА.has(ключ)).sort()
  const левые = ключи(левое)
  const правые = ключи(правое)
  if (левые.length !== правые.length) return false
  return левые.every((ключ, и) => правые[и] === ключ && одинаковы(левое[ключ], правое[ключ]))
}
