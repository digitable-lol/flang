/**
 * Двунаправленные управляющие символы Unicode в напечатанном коде.
 *
 * ── Откуда файл здесь ───────────────────────────────────────────────────────
 * Написан он был для старого проекта FTS и лежал в `tools/ftsc/src/bidi.mjs`.
 * Проект вынесен из репозитория (тег `fts-pered-udaleniem`), а файл ПЕРЕЕХАЛ,
 * а не скопировался: восемь целей печати языка зовут именно его, и второй
 * копии быть не должно — разъехавшиеся копии дали бы расхождение не в момент
 * правки, а в момент печати чужой программы.
 *
 * Правило одно на все восемь целей печати языка:
 * двунаправленные управляющие — U+061C, U+200E, U+200F, U+202A…U+202E,
 * U+2066…U+2069 — в целевой код сырыми не печатаются. Места они не занимают, а
 * раскладку текста меняют, и потому файл читается не так, как исполняется. Это
 * «Trojan Source», CVE-2021-42574.
 *
 * ── Почему это касается и комментариев ──────────────────────────────────────
 * Комментарий не исполняется — ровно поэтому он и опасен: его читают первым и
 * ему верят, а проверить его исполнением нельзя. Русское имя попадает в комментарий
 * у каждого бэкенда («правило «…»», «Функция flang «…»»), и оттуда управляющий
 * символ переставляет на экране не свою строку, а соседний код.
 *
 * ── Что об этом думают сами компиляторы (проверено на этой машине) ──────────
 *   • rustc 1.96 — ОШИБКА и в комментарии, и в doc-комментарии:
 *     `text_direction_codepoint_in_comment` и `…_in_literal` deny-by-default.
 *     Сырой символ в комментарии означает, что напечатанный код не собирается
 *     вовсе;
 *   • elixirc 1.20.2 — ОТКАЗ разбора и в строке, и в комментарии: «invalid
 *     bidirectional formatting character in comment/string»;
 *   • gcc 13.3 под `-Werror` — ошибка на НЕПАРНЫХ управляющих (в комментариях
 *     тоже: `-Wbidi-chars=unpaired` включён по умолчанию). Парную пару
 *     RLO…PDF пропускает молча, поэтому полагаться на него нельзя;
 *   • javac 25, python 3.12, node 24 — молчат. Это не смягчающее
 *     обстоятельство, а отягчающее: ради этого молчания атаку и придумали.
 *
 * ── Почему набор один, а формы разные ───────────────────────────────────────
 * Набор кодовых точек общий: он определён Unicode, а не языком. Форма записи
 * общей быть не может — у языков она разная, и ниже их ровно три. Выбирает
 * форму бэкенд: он один знает, что понимает его компилятор.
 *
 * Экранирование меняет ЗАПИСЬ, а не значение: и кодовая точка, и байты остаются
 * теми же (в комментарии значения нет вовсе, но человек, читающий комментарий,
 * обязан суметь восстановить имя дословно). Это проверяется общим тестом —
 * flang/test/emit-bidi.test.mjs: он разбирает напечатанное обратно и сверяет с
 * источником по всем восьми целям.
 *
 * Сырых двунаправленных в самом этом файле нет: набор задан кодами, а не
 * символами, — иначе он воспроизводил бы ровно ту беду, от которой стережёт.
 */

/**
 * Двенадцать управляющих: ALM из арабского блока, восемь из блока
 * U+2000…U+207F и четыре изолята U+2066…U+2069. Именно этот набор считают
 * опасным rustc, gcc и elixirc, и именно он перечислен в CVE-2021-42574.
 */
export const BIDI_CONTROLS = new Set([
  0x061c /* ALM  */, 0x200e /* LRM  */, 0x200f /* RLM  */, 0x202a /* LRE  */, 0x202b /* RLE  */,
  0x202c /* PDF  */, 0x202d /* LRO  */, 0x202e /* RLO  */, 0x2066 /* LRI  */, 0x2067 /* RLI  */,
  0x2068 /* FSI  */, 0x2069 /* PDI  */,
])

/** Есть ли в тексте хоть один сырой двунаправленный управляющий. */
export function hasRawBidi(text) {
  for (const character of String(text)) {
    if (BIDI_CONTROLS.has(character.codePointAt(0))) return true
  }
  return false
}

/**
 * Общая часть всех трёх форм: посимвольный проход, замена только управляющих.
 *
 * По кодовым точкам, а не по единицам UTF-16: все двенадцать лежат в BMP, но
 * проход по точкам обязателен, чтобы суррогатная пара соседнего символа не
 * распалась на две половины.
 */
function replaceControls(text, render) {
  const value = String(text)
  /* Быстрый путь: в подавляющем большинстве файлов управляющих нет вовсе, и
     пересобирать строку посимвольно незачем. */
  if (!hasRawBidi(value)) return value
  let result = ""
  for (const character of value) {
    const code = character.codePointAt(0)
    result += BIDI_CONTROLS.has(code) ? render(code) : character
  }
  return result
}

/**
 * `\uXXXX` — Java, C#, Go, Python, JavaScript и TypeScript.
 *
 * Ровно четыре шестнадцатеричные цифры, поэтому цифра, стоящая в тексте следом,
 * к экранированию не приклеится (у `\x` в C# и Python длина переменная, и он бы
 * её проглотил). Для Java эта форма к тому же единственная: `\xNN` язык не
 * знает, а восьмеричные кончаются на `\377` и U+202E не выражают.
 */
export function escapeBidiUnicode4(text) {
  return replaceControls(text, (code) => `\\u${code.toString(16).padStart(4, "0")}`)
}

/**
 * `\u{XXXX}` — Rust и Elixir.
 *
 * Скобки закрывают экранирование, поэтому шестнадцатеричная цифра, стоящая
 * следом, к нему не приклеится. Ту же форму предлагают в тексте своих отказов
 * оба компилятора — и elixirc, и rustc.
 */
export function escapeBidiBraced(text) {
  return replaceControls(text, (code) => `\\u{${code.toString(16)}}`)
}

const utf8 = new TextEncoder()

/**
 * `\NNN` побайтно — C.
 *
 * В C99 узкая строка байт-точна только так: `\uXXXX` там тоже есть, но
 * превращается в символ исполняющей кодировки (какие байты выйдут — решает
 * реализация), а `\xNN` жадный и съедает сколько угодно цифр подряд. Байты
 * берутся из UTF-8 и печатаются тремя восьмеричными цифрами каждый: все
 * двенадцать управляющих дают байты не меньше 0300, то есть ровно три цифры, и
 * цифра, стоящая в строке следом, к экранированию не приклеится (C читает не
 * больше трёх).
 *
 * Та же форма идёт и в комментарий: в одном языке — одна запись, иначе
 * читающему пришлось бы держать в голове две.
 */
export function escapeBidiOctalBytes(text) {
  return replaceControls(text, (code) =>
    [...utf8.encode(String.fromCodePoint(code))].map((byte) => `\\${byte.toString(8).padStart(3, "0")}`).join(""),
  )
}

/**
 * Последний шаг печати: снять сырые двунаправленные со ВСЕГО вывода бэкенда.
 *
 * Почему фильтром на выходе, а не заботой в каждом месте склейки текста: мест,
 * где русское имя попадает в напечатанный файл, у одного бэкенда десятки —
 * шапка файла, документация модуля, комментарий к правилу, подпись примера,
 * строковый литерал в прогонщике, — и правило, записанное в каждом из них,
 * держится ровно до следующего нового места. Здесь оно записано один раз и на
 * весь файл.
 *
 * К моменту вызова строковые литералы уже экранированы своей функцией литерала
 * (она обязана сохранять значение и знает про кавычки и слэши), поэтому сырым
 * управляющий здесь остаётся только в тексте, который язык не разбирает, —
 * прежде всего в комментариях. Экранирование, вставленное сюда, не удваивается:
 * обратный слэш печатается ДО этого шага, и добавить его этот шаг может только
 * там, где сырой символ ещё есть.
 *
 * Пути файлов не трогаются намеренно: они собираются транслитерацией
 * (naming.mjs) и состоят из ASCII, а экранирование в имени файла разошлось бы с
 * тем, чего ждут компилятор и Makefile. Что сырых там нет, проверяют общие
 * тесты, а не этот фильтр.
 *
 * @param {Array<{path: string, content: string}>} files
 * @param {(text: string) => string} escape — форма записи целевого языка
 */
export function escapeBidiInFiles(files, escape) {
  return files.map((file) => ({ ...file, content: escape(file.content) }))
}
