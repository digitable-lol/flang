/**
 * bounded.mjs — ОГРАНИЧЕННОСТЬ функции: оценка сверху на витки от размера входа.
 *
 * Шаг В3 карты (`flang/conc/RESILIENCE.md`). Свойство это отдельное от
 * тотальности, и весь смысл файла в том, насколько отдельное.
 *
 * ── Зачем, если тотальность уже доказана ───────────────────────────────────
 *
 * Тотальность обещает «завершится». Она НЕ обещает «завершится скоро»: функция
 * Аккермана тотальна, и тотальная `фиб` от 34 доказанно завершается — упираясь
 * при этом в предел планировщика в миллион витков. Для операционной системы,
 * ради которой затевается вся карта, «когда-нибудь вернётся» не значит ничего:
 * там надо знать, уложится ли обработчик в квант, ДО того, как он его займёт.
 *
 * Отсюда и дыра, которую этот файл закрывает. `failures.mjs` считает множество
 * отказов процесса замкнутым и перечислимым, и это правда ровно настолько,
 * насколько язык знает про ограниченность: тотальный обработчик может отказать
 * `FLANG_RECURSION_LIMIT`, и предела этого нет в исходнике — он константа
 * планировщика. Пока оценки витков не было, такой отказ было не назвать, и
 * анализ честно считал три вида вместо четырёх. Теперь считает четыре.
 *
 * ── Что здесь считается витком ─────────────────────────────────────────────
 *
 * Ровно то же, что считает планировщик эталона: один оборот машины
 * `interpret.mjs` — один снятый с очереди кадр работы (`run`, `machine.steps`).
 * Это та же единица, в которой пишется `с запасом N витков`, и та же, которой
 * меряется `TOTAL_HANDLER_STEPS`. Витков рантайма C всегда МЕНЬШЕ (`fl_tick`
 * считает вход в функцию, оборот хвостовой петли и отскок батута —
 * `flang/test/emit-c-conc.test.mjs`), поэтому оценка, верная для эталона, верна
 * и для напечатанного C. Расхождение одностороннее, и это проверено.
 *
 * ── Что такое «размер входа» ───────────────────────────────────────────────
 *
 * Одно число `н` — структурный размер всех аргументов вместе: скаляр весит
 * единицу, список и запись — единицу плюс размеры частей (`размерЗначения`
 * ниже). Оценка — многочлен от `н` с ЧИСЛОВЫМИ коэффициентами, а не «O(n)»:
 * `витков ≤ 12·н + 7` можно сверить с квантом, а «линейна» — нельзя.
 *
 * Размер берётся один на все аргументы, а не по одному на параметр, и это
 * упрощение названо прямо: `н` — верхняя граница размера ЛЮБОГО аргумента,
 * поэтому подстановка её вместо каждого размера оценку только завышает. Оценка
 * сверху от завышения остаётся оценкой сверху.
 *
 * ── ЧАСТНЫЙ СЛУЧАЙ, который здесь покрыт, и общий, который не покрыт ───────
 *
 * Оценка сверху на время работы в общем случае неразрешима, и файл, который
 * делает вид, что решил её, — враньё. Покрыто:
 *
 *   • функции без рекурсии — оценка постоянная, считается сложением по дереву;
 *   • САМОрекурсия со структурным спуском по данным: аргумент рекурсивного
 *     вызова получен разбором параметра (`хвост`, `голова`, поле варианта,
 *     поле записи), значит его структурный размер строго меньше. Глубина такой
 *     рекурсии не больше `н`, и оценка выходит `(н+1)·(тело без вызова)`;
 *   • свёртка, отображение и фильтр — цикл по списку, длина которого не больше
 *     размера входа: множитель `н` и не более;
 *   • вызовы других функций — подстановкой их оценок, снизу вверх по графу.
 *
 * НЕ покрыто, и каждый пункт — сознательно оставленный, а не забытый:
 *
 *   • РЕКУРСИЯ ПО ЧИСЛУ. `фиб`, Аккерман, `НОД` с объявленной мерой `убывает б`
 *     — всё это тотально и всё это здесь без оценки. Причина точная: структурный
 *     размер числа равен единице и от вычитания не убывает, а оценка сверху на
 *     витки через ЗНАЧЕНИЕ числа требует знать границу этого значения, которой в
 *     типе `число` нет. Дать её мог бы объявленный диапазон — его в языке нет;
 *   • ВЕТВЯЩАЯСЯ РЕКУРСИЯ: два и более рекурсивных вызова на одном пути
 *     вычисления. Даже со структурным спуском это дерево, и оценка у него
 *     показательная, а не многочленная. Отвергается по счёту вызовов на пути,
 *     а не по догадке;
 *   • ВЗАИМНАЯ рекурсия — цикл в графе вызовов длиннее одной функции. Спуск в
 *     нём доказуем, а вот сколько тела чьё — уже нет без раскрутки цикла;
 *   • рекурсивный вызов ВНУТРИ свёртки, отображения или фильтра: их тело
 *     выполняется столько раз, какова длина списка, и произведение двух
 *     неизвестных глубин здесь не считается;
 *   • применение функции-значения (`apply`): какая именно функция приедет
 *     тегом, известно дефункционализации, а не этому файлу;
 *   • РАСТУЩИЙ АРГУМЕНТ рекурсии. Спуск по одному аргументу ограничивает
 *     глубину, но не цену тела: накапливающий параметр, которому на каждом шаге
 *     дописывают целый список, разбухает до н², и тело, идущее по нему, стоит
 *     н² вместо н. Поэтому каждый аргумент рекурсивного вызова обязан быть
 *     частью входа либо постоянного размера. Свёртка с накоплением от этого не
 *     страдает — она пишется `свёрткой`, а не рекурсией с аккумулятором;
 *   • ЗНАЧЕНИЕ, РАЗМЕР КОТОРОГО НЕ ВЫВЕДЕН ИЗ ВХОДА, в цикле или в аргументе
 *     вызова с растущей оценкой. Длина цикла — это длина того, по чему цикл
 *     идёт, а не размер входа: программа, которая свёрткой строит список из н²
 *     элементов и потом идёт по нему, крутится н² раз.
 *
 * И одна оговорка, без которой числа выше были бы враньём. Виток — это оборот
 * машины, а не единица работы: встроенная форма выполняется ЦЕЛИКОМ за один
 * виток, включая `добавить … к …` и `приписать … к …`, которые копируют список
 * (в бэкенде C — не копируют, там запас в арене). Значит оценка витков
 * — это оценка на то, чем режет планировщик, и она НЕ переводится в секунды
 * умножением на цену витка там, где в теле стоят списочные встроенные формы.
 * Сказать это надо здесь, а не в примечании к отчёту.
 */

/* ───────────────────────────── многочлены ───────────────────────────── */

/**
 * Многочлен от `н` — массив неотрицательных коэффициентов от младшего к
 * старшему: `[7, 12]` это `12·н + 7`.
 *
 * Коэффициенты неотрицательны все и всегда, и на этом стоит `максимум` ниже:
 * почленный максимум двух многочленов мажорирует оба только при неотрицательных
 * `н` и неотрицательных коэффициентах. Оба условия здесь выполнены — `н` это
 * размер, он не бывает отрицательным.
 */
const НОЛЬ = Object.freeze([0])

/** Постоянная оценка. */
export function константа(значение) {
  return [значение]
}

/** Многочлен `н`. */
export function размерВхода() {
  return [0, 1]
}

export function сложить(первый, второй) {
  const длина = Math.max(первый.length, второй.length)
  const итог = new Array(длина).fill(0)
  for (let степень = 0; степень < длина; степень += 1) {
    итог[степень] = (первый[степень] ?? 0) + (второй[степень] ?? 0)
  }
  return итог
}

export function умножить(первый, второй) {
  const итог = new Array(первый.length + второй.length - 1).fill(0)
  for (let i = 0; i < первый.length; i += 1) {
    for (let j = 0; j < второй.length; j += 1) {
      итог[i + j] += первый[i] * второй[j]
    }
  }
  return итог
}

/**
 * Почленный максимум — оценка сверху для развилки.
 *
 * Ветку выбирает вход, а какую именно — здесь не известно, поэтому берётся та,
 * что дороже. Почленно, а не сравнением значений: сравнить два многочлена
 * числом нельзя, не назвав `н`, а `н` тут как раз и неизвестно.
 */
export function максимум(первый, второй) {
  const длина = Math.max(первый.length, второй.length)
  const итог = new Array(длина).fill(0)
  for (let степень = 0; степень < длина; степень += 1) {
    итог[степень] = Math.max(первый[степень] ?? 0, второй[степень] ?? 0)
  }
  return итог
}

/**
 * Подстановка многочлена в многочлен (схема Горнера над многочленами).
 *
 * Нужна там, где размер аргумента сам зависит от размера входа: оценка вызванной
 * функции написана от ЕЁ входа, а её вход — это выражение у нас. Подставить одно
 * в другое — единственный способ не соврать ни в ту, ни в другую сторону.
 */
export function подставить(многочлен, аргумент) {
  let итог = НОЛЬ
  for (let i = многочлен.length - 1; i >= 0; i -= 1) {
    итог = сложить(умножить(итог, аргумент), константа(многочлен[i]))
  }
  return итог
}

/** Значение многочлена при данном размере входа. */
export function значение(многочлен, н) {
  let итог = 0
  for (let степень = многочлен.length - 1; степень >= 0; степень -= 1) {
    итог = итог * н + многочлен[степень]
  }
  return итог
}

/** Степень многочлена: 0 — постоянная оценка, 1 — линейная, и так далее. */
export function степень(многочлен) {
  let старшая = 0
  for (let i = 0; i < многочлен.length; i += 1) {
    if (многочлен[i] !== 0) старшая = i
  }
  return старшая
}

const СТЕПЕНИ = ["", "н", "н²", "н³", "н⁴", "н⁵"]

/** Оценка словами: «12·н + 7». Печатается в диагностику и в отчёт мерки. */
export function текстОценки(многочлен) {
  const части = []
  for (let i = многочлен.length - 1; i >= 0; i -= 1) {
    const коэффициент = многочлен[i]
    if (коэффициент === 0 && i !== 0) continue
    if (i === 0) {
      if (коэффициент !== 0 || части.length === 0) части.push(String(коэффициент))
      continue
    }
    const имя = СТЕПЕНИ[i] ?? `н^${i}`
    части.push(коэффициент === 1 ? имя : `${коэффициент}·${имя}`)
  }
  return части.join(" + ")
}

/* ───────────────────────── размер значения ───────────────────────── */

/**
 * Структурный размер значения: то самое `н`, от которого написана оценка.
 *
 * Считается по значению, а не по типу, и это принципиально: у типа «список
 * числа» размера нет вовсе, а у пришедшего сообщения — есть. Именно этот размер
 * подставляется в оценку, когда рантайму надо решить, влезет ли пробег в квант.
 */
export function размерЗначения(значениеВхода) {
  if (Array.isArray(значениеВхода)) {
    let итог = 1
    for (const элемент of значениеВхода) итог += размерЗначения(элемент)
    return итог
  }
  if (значениеВхода !== null && typeof значениеВхода === "object") {
    /* Вариант из `interpret.mjs` — это объект с полем `fields`; запись — просто
       объект. Считаются одинаково: единица за узел плюс части. */
    const части = Object.hasOwn(значениеВхода, "fields") ? значениеВхода.fields : значениеВхода
    let итог = 1
    for (const ключ of Object.keys(части ?? {})) итог += размерЗначения(части[ключ])
    return итог
  }
  /* Строка — скаляр, а не список символов: `разбор` её по «голова и хвост»
     разбирает, но встроенные формы над ней стоят один виток, а не длину. */
  return 1
}

/* ─────────────────────── причины отсутствия оценки ─────────────────────── */

export const ПРИЧИНЫ = Object.freeze({
  ЧИСЛОВАЯ: "рекурсия по числу, а не по данным: структурный размер числа не убывает",
  ВЕТВЯЩАЯСЯ: "рекурсия ветвится: на одном пути больше одного рекурсивного вызова",
  ВЗАИМНАЯ: "взаимная рекурсия: цикл в графе вызовов длиннее одной функции",
  В_ЦИКЛЕ: "рекурсивный вызов внутри свёртки, отображения или фильтра",
  ПРИМЕНЕНИЕ: "применение функции-значения: какая приедет тегом, здесь не известно",
  РАСТУЩИЙ: "аргумент рекурсивного вызова не выведен из входа: он может расти с каждым вызовом",
  ЧЕРЕЗ: "зовёт функцию без оценки",
  НЕИЗВЕСТНАЯ: "зовёт неизвестную функцию",
  РАЗМЕР: "размер значения не выведен из размера входа",
})

/* ───────────────────────────── анализ ───────────────────────────── */

/**
 * Оценки витков для всех функций программы.
 *
 * @param {object} program AST с `functions`
 * @returns {Map<string, {оценка: number[]|null, причина: string|null, спуск: number|null}>}
 *   `оценка` — многочлен от размера входа либо `null`, если её нет; `причина`
 *   названа тогда и только тогда, когда оценки нет; `спуск` — позиция параметра,
 *   по которому доказан структурный спуск, у саморекурсивной функции.
 */
export function оценитьВитки(program) {
  const функции = Array.isArray(program?.functions) ? program.functions : []
  const поИмени = new Map()
  for (const фн of функции) {
    if (typeof фн?.name === "string" && !поИмени.has(фн.name)) поИмени.set(фн.name, фн)
  }

  const итог = new Map()
  const вРаботе = new Set()

  const оценить = (имя) => {
    if (итог.has(имя)) return итог.get(имя)
    const фн = поИмени.get(имя)
    if (фн === undefined) {
      const нет = { оценка: null, причина: ПРИЧИНЫ.НЕИЗВЕСТНАЯ, спуск: null }
      итог.set(имя, нет)
      return нет
    }
    if (вРаботе.has(имя)) {
      /* Мы уже внутри этой функции — значит цикл. Самоцикл разбирает
         `оценитьФункцию` отдельным путём (он знает, что вызов рекурсивный), а
         сюда попадает только цикл через кого-то ещё, то есть взаимная рекурсия. */
      return { оценка: null, причина: ПРИЧИНЫ.ВЗАИМНАЯ, спуск: null }
    }
    вРаботе.add(имя)
    let результат
    try {
      результат = оценитьФункцию(фн, оценить)
    } finally {
      вРаботе.delete(имя)
    }
    итог.set(имя, результат)
    return результат
  }

  for (const фн of функции) {
    if (typeof фн?.name === "string") оценить(фн.name)
  }
  return итог
}

/**
 * Оценка одной функции — цена ВЫЗОВА, а не тела.
 *
 * Схема ровно та, что описана в шапке: тело считается ОДИН раз, рекурсивные
 * вызовы при этом только пересчитываются (их цена в тело не входит), а потом,
 * если рекурсия одна на путь и есть структурный спуск, тело умножается на
 * `н+1` — глубину, больше которой спуск по данным не даёт.
 *
 * И сверху прибавляется ОДИН виток — кадр самого вызова. Это не поправка на
 * всякий случай, а починенное занижение, и вот в чём оно состояло. Внутри
 * программы цена вызова считалась правильно: на месте вызова стояло
 * `1 + оценка вызванной`, где единица и есть кадр. А у САМОГО ВЕРХНЕГО вызова
 * места вызова нет — его делает планировщик (или `рантайм.call`), — и его кадр
 * не платил никто. У рекурсивных функций это тонуло в постоянном запасе на
 * пять-семнадцать витков, а у прямых оценка точна, и там занижение на виток
 * оказалось голым: `с запасом ровно столько, сколько обещано` не проходило.
 * Теперь единицу платит сама оценка, а место вызова её больше не платит —
 * иначе она считалась бы дважды. Сторож на прямые функции стоит в
 * `flang/test/bounded.test.mjs` и требует ТОЧНОГО совпадения, а не «не меньше».
 */
function оценитьФункцию(фн, оценить) {
  const параметры = Array.isArray(фн?.params) ? фн.params.map((п) => п?.name) : []
  const среда = new Map()
  параметры.forEach((имя, позиция) => {
    if (typeof имя === "string") среда.set(имя, { параметр: позиция, глубина: 0 })
  })

  const состояние = {
    имя: фн.name,
    оценить,
    /* Позиции параметров, по которым спуск доказан на КАЖДОМ рекурсивном
       вызове. Начинается со всех, сужается каждым вызовом — то же правило, что
       у проверки тотальности: убывать обязан один и тот же аргумент, а не
       разные в разных местах. */
    спуски: new Set(параметры.map((_, позиция) => позиция)),
    рекурсивных: 0,
    беда: null,
  }

  const тело = считать(фн?.body, среда, состояние, false)
  if (состояние.беда !== null) {
    return { оценка: null, причина: состояние.беда, спуск: null }
  }
  if (тело.рекурсий === 0) {
    return { оценка: сложить(тело.витки, КАДР), причина: null, спуск: null }
  }
  if (тело.рекурсий > 1) {
    return { оценка: null, причина: ПРИЧИНЫ.ВЕТВЯЩАЯСЯ, спуск: null }
  }
  const спуск = [...состояние.спуски].sort((а, б) => а - б)[0]
  if (спуск === undefined) {
    return { оценка: null, причина: ПРИЧИНЫ.ЧИСЛОВАЯ, спуск: null }
  }
  /* Глубина рекурсии не больше `н`: структурный размер аргумента убывает хотя
     бы на единицу за вызов и не бывает отрицательным. Значит активаций тела не
     больше `н+1`, и каждая стоит не больше, чем стоит тело без вложенного
     вызова. */
  return { оценка: сложить(умножить([1, 1], тело.витки), КАДР), причина: null, спуск }
}

/**
 * Кадр вызова — один виток.
 *
 * Отдельным именем, а не единицей на месте: та же величина стоит на месте
 * рекурсивного вызова (`считать`, случай `call`), и если она когда-нибудь
 * перестанет быть единицей, менять придётся оба места разом.
 */
const КАДР = Object.freeze([1])

/**
 * Витки одного выражения и число рекурсивных вызовов на самом дорогом пути.
 *
 * Возвращает `{ витки, рекурсий }`. `витки` — многочлен, `рекурсий` — целое:
 * сколько раз на одном пути вычисления встретится вызов той же функции. Пути
 * складываются последовательно и максимизируются на развилках, потому что
 * развилку выбирает вход.
 *
 * `вЦикле` — признак того, что выражение стоит в теле свёртки, отображения или
 * фильтра. Рекурсивный вызов там означал бы глубину, умноженную на длину
 * списка; такой случай не покрыт, и признак нужен, чтобы сказать это точно, а
 * не посчитать неправду.
 */
function считать(выражение, среда, состояние, вЦикле) {
  if (выражение === null || typeof выражение !== "object") {
    return { витки: константа(1), рекурсий: 0 }
  }
  switch (выражение.kind) {
    case "literal":
    case "var":
    case "fnref":
      /* Один оборот машины и всё: значение уже есть. */
      return { витки: константа(1), рекурсий: 0 }

    case "field": {
      const цель = считать(выражение.target, среда, состояние, вЦикле)
      return { витки: сложить(цель.витки, константа(2)), рекурсий: цель.рекурсий }
    }

    case "let": {
      const значениеЛет = считать(выражение.value, среда, состояние, вЦикле)
      const внутри = new Map(среда)
      внутри.set(выражение.name, происхождение(выражение.value, среда))
      const тело = считать(выражение.in ?? выражение.body, внутри, состояние, вЦикле)
      return {
        витки: сложить(сложить(значениеЛет.витки, тело.витки), константа(2)),
        рекурсий: значениеЛет.рекурсий + тело.рекурсий,
      }
    }

    case "if": {
      const условие = считать(выражение.cond, среда, состояние, вЦикле)
      const тогда = считать(выражение.then, среда, состояние, вЦикле)
      const иначе = считать(выражение.else, среда, состояние, вЦикле)
      return {
        витки: сложить(сложить(условие.витки, максимум(тогда.витки, иначе.витки)), константа(2)),
        рекурсий: условие.рекурсий + Math.max(тогда.рекурсий, иначе.рекурсий),
      }
    }

    case "match": {
      const цель = считать(выражение.target, среда, состояние, вЦикле)
      let ветви = НОЛЬ
      let рекурсийВетви = 0
      for (const случай of выражение.cases ?? []) {
        const внутри = связать(случай.pattern, выражение.target, среда)
        const ветвь = считать(случай.body, внутри, состояние, вЦикле)
        ветви = максимум(ветви, ветвь.витки)
        рекурсийВетви = Math.max(рекурсийВетви, ветвь.рекурсий)
      }
      return {
        витки: сложить(сложить(цель.витки, ветви), константа(2)),
        рекурсий: цель.рекурсий + рекурсийВетви,
      }
    }

    case "binary":
      return последовательно([выражение.left, выражение.right], среда, состояние, вЦикле)

    case "list":
      return последовательно(выражение.items ?? [], среда, состояние, вЦикле)

    case "record":
      return последовательно(Object.values(выражение.fields ?? {}), среда, состояние, вЦикле)

    case "construct":
      return последовательно(Object.values(выражение.fields ?? {}), среда, состояние, вЦикле)

    case "builtin":
      /* Встроенная форма считается за один виток вместе с аргументами — она
         выполняется в `finishSeq`, не снимая кадра. Что она при этом может
         скопировать список, оговорено в шапке файла. */
      return последовательно(выражение.args ?? [], среда, состояние, вЦикле)

    case "apply": {
      состояние.беда = состояние.беда ?? ПРИЧИНЫ.ПРИМЕНЕНИЕ
      return { витки: константа(1), рекурсий: 0 }
    }

    case "call": {
      const аргументы = последовательно(выражение.args ?? [], среда, состояние, вЦикле)
      if (выражение.name === состояние.имя) {
        if (вЦикле) {
          состояние.беда = состояние.беда ?? ПРИЧИНЫ.В_ЦИКЛЕ
          return { витки: аргументы.витки, рекурсий: 0 }
        }
        /* Спуск по ОДНОМУ аргументу ограничивает глубину, но не цену тела:
           остальные аргументы за это время могут вырасти. Накапливающий
           параметр, которому на каждом шаге дописывают целый список, разбухает
           до н², и тело, идущее по нему, стоит н² вместо н — оценка выходит
           меньше факта. Проверено программой (`flang/test/bounded.test.mjs`).
           Поэтому требуется, чтобы КАЖДЫЙ аргумент рекурсивного вызова был либо
           частью входа, либо постоянного размера: тогда размеры по ходу
           рекурсии не растут, и `н` остаётся верхней границей для всех. */
        for (const аргумент of выражение.args ?? []) {
          if (происхождение(аргумент, среда) !== null) continue
          const размер = размерСверху(аргумент, среда, состояние)
          if (размер !== null && степень(размер) === 0) continue
          состояние.беда = состояние.беда ?? ПРИЧИНЫ.РАСТУЩИЙ
          return { витки: аргументы.витки, рекурсий: аргументы.рекурсий }
        }
        сузитьСпуски(выражение, среда, состояние)
        /* Цена самого вызова (кадр) считается, цена его ТЕЛА — нет: тело
           появится множителем `н+1` в `оценитьФункцию`. Здесь кадр платится на
           месте, потому что оценки вызванной у нас нет — вызванная это мы. */
        return { витки: сложить(аргументы.витки, КАДР), рекурсий: аргументы.рекурсий + 1 }
      }
      const чужая = состояние.оценить(выражение.name)
      if (чужая.оценка === null) {
        состояние.беда = состояние.беда ?? `${ПРИЧИНЫ.ЧЕРЕЗ} «${выражение.name}»`
        return { витки: аргументы.витки, рекурсий: аргументы.рекурсий }
      }
      /* Оценка вызванной написана от ЕЁ размера входа, а не от нашего. Пока она
         постоянна, это неважно; как только она растёт, подставлять надо размер
         того, что мы ей передаём, — иначе цена вызова с раздутым аргументом
         окажется занижена ровно так же, как цена цикла по раздутому списку. */
      let цена = чужая.оценка
      if (степень(чужая.оценка) > 0) {
        let размерАргументов = константа(0)
        for (const аргумент of выражение.args ?? []) {
          const размер = размерСверху(аргумент, среда, состояние)
          if (размер === null) {
            состояние.беда = состояние.беда ?? ПРИЧИНЫ.РАЗМЕР
            return { витки: аргументы.витки, рекурсий: аргументы.рекурсий }
          }
          размерАргументов = сложить(размерАргументов, размер)
        }
        цена = подставить(чужая.оценка, размерАргументов)
      }
      /* Кадр вызванной входит в ЕЁ оценку (`оценитьФункцию`), поэтому здесь он
         не прибавляется: иначе один и тот же виток был бы посчитан дважды. */
      return {
        витки: сложить(аргументы.витки, цена),
        рекурсий: аргументы.рекурсий,
      }
    }

    case "fold": {
      const по = считать(выражение.over, среда, состояние, вЦикле)
      const начало = считать(выражение.init, среда, состояние, вЦикле)
      const внутри = new Map(среда)
      внутри.set(выражение.acc, null)
      внутри.set(выражение.item, null)
      const тело = считать(выражение.body, внутри, состояние, true)
      const оборот = сложить(тело.витки, константа(1))
      /* Сколько раз крутится цикл — это ДЛИНА того, по чему он идёт, а не размер
         входа. Разница не педантическая: программа, которая свёрткой строит
         список из н² элементов и потом идёт по нему, крутится н² раз, и оценка
         «не больше н» на ней была бы просто ложной. Проверено программой, она
         лежит в `flang/test/bounded.test.mjs`. */
      const длина = размерСверху(выражение.over, среда, состояние)
      if (длина === null) {
        состояние.беда = состояние.беда ?? ПРИЧИНЫ.РАЗМЕР
        return { витки: константа(1), рекурсий: 0 }
      }
      return {
        витки: сложить(сложить(сложить(по.витки, начало.витки), константа(4)),
                       умножить(длина, оборот)),
        рекурсий: по.рекурсий + начало.рекурсий,
      }
    }

    case "map":
    case "filter": {
      const по = считать(выражение.over, среда, состояние, вЦикле)
      const внутри = new Map(среда)
      внутри.set(выражение.item, null)
      const тело = считать(выражение.body, внутри, состояние, true)
      const оборот = сложить(тело.витки, константа(1))
      const длина = размерСверху(выражение.over, среда, состояние)
      if (длина === null) {
        состояние.беда = состояние.беда ?? ПРИЧИНЫ.РАЗМЕР
        return { витки: константа(1), рекурсий: 0 }
      }
      return {
        витки: сложить(сложить(по.витки, константа(3)), умножить(длина, оборот)),
        рекурсий: по.рекурсий,
      }
    }

    default:
      /* Неизвестный вид узла — не повод посчитать ноль. Оценки у такой функции
         нет, и сказано это будет прямо. */
      состояние.беда = состояние.беда ?? `неизвестный вид выражения «${выражение.kind}»`
      return { витки: константа(1), рекурсий: 0 }
  }
}

/**
 * Строгое вычисление списка выражений слева направо: один виток на узел, один
 * на каждый снятый кадр последовательности, плюс сами аргументы.
 */
function последовательно(выражения, среда, состояние, вЦикле) {
  let витки = константа(1 + выражения.length)
  let рекурсий = 0
  for (const выражение of выражения) {
    const часть = считать(выражение, среда, состояние, вЦикле)
    витки = сложить(витки, часть.витки)
    рекурсий += часть.рекурсий
  }
  return { витки, рекурсий }
}

/**
 * Оценка сверху на СТРУКТУРНЫЙ РАЗМЕР значения выражения — многочлен от `н`
 * либо `null`, если вывести его нечем.
 *
 * Правило одно и оно грубое нарочно: размер известен у того, что пришло со
 * входа (целиком или частью), и у того, что построено из известного по частям.
 * Всё, что построено циклом или вернулось из функции, здесь неизвестно, и это
 * НЕ лень — просто оценка размера результата функции требует отдельного
 * неподвижного счёта по графу вызовов, а без него подстановка «н вместо
 * чего угодно» лжёт в опасную сторону.
 *
 * Что из-за этого теряется, названо честно: `«Сумма» от («Удвоить» от список)`
 * оценки не получает, хотя `Удвоить` длины не меняет. Лучше отказать там, где
 * можно было бы посчитать, чем посчитать там, где нельзя.
 */
function размерСверху(выражение, среда, состояние) {
  if (выражение === null || typeof выражение !== "object") return null
  /* Часть входа не больше входа — это и есть весь смысл `н`. */
  if (происхождение(выражение, среда) !== null) return размерВхода()
  switch (выражение.kind) {
    case "literal":
      return константа(размерЗначения(выражение.value))
    case "list": {
      let итог = константа(1)
      for (const элемент of выражение.items ?? []) {
        const часть = размерСверху(элемент, среда, состояние)
        if (часть === null) return null
        итог = сложить(итог, часть)
      }
      return итог
    }
    case "record":
    case "construct": {
      let итог = константа(1)
      for (const поле of Object.values(выражение.fields ?? {})) {
        const часть = размерСверху(поле, среда, состояние)
        if (часть === null) return null
        итог = сложить(итог, часть)
      }
      return итог
    }
    case "if": {
      const тогда = размерСверху(выражение.then, среда, состояние)
      const иначе = размерСверху(выражение.else, среда, состояние)
      return тогда === null || иначе === null ? null : максимум(тогда, иначе)
    }
    case "binary":
      /* Двуместная операция всегда даёт СКАЛЯР: число, признак или строку
         (`applyBinary` в `interpret.mjs` — список ею не построить, соединение
         списков это встроенная форма, а не операция). Скаляр весит единицу, и
         это не догадка: так же его считает `размерЗначения` выше. */
      return константа(1)
    default:
      return null
  }
}

/* ─────────────────── происхождение значения и спуск ─────────────────── */

/**
 * Откуда взялось значение: из какого параметра и через сколько разборов.
 *
 * `{ параметр, глубина }` с глубиной больше нуля означает «строго меньшая часть
 * этого параметра». Правило то же, что у проверки тотальности: часть меньше
 * целого, и это единственное, что здесь нужно, — точный размер не важен, важно
 * строгое убывание.
 */
function происхождение(выражение, среда) {
  if (выражение === null || typeof выражение !== "object") return null
  switch (выражение.kind) {
    case "var":
      return среда.get(выражение.name) ?? null
    case "field": {
      const цель = происхождение(выражение.target, среда)
      return цель === null ? null : { параметр: цель.параметр, глубина: цель.глубина + 1 }
    }
    case "builtin": {
      /* Разбирающие формы дают часть, все остальные — новое значение. */
      const разбирающие = { "хвост": 0, "голова": 0, "элемент": 0 }
      if (!Object.hasOwn(разбирающие, выражение.name)) return null
      const цель = происхождение((выражение.args ?? [])[разбирающие[выражение.name]], среда)
      return цель === null ? null : { параметр: цель.параметр, глубина: цель.глубина + 1 }
    }
    default:
      return null
  }
}

/** Связывание образца: всё, что образец достал, — часть разбираемого. */
function связать(образец, цель, среда) {
  const внутри = new Map(среда)
  const откуда = происхождение(цель, среда)
  const часть = откуда === null ? null : { параметр: откуда.параметр, глубина: откуда.глубина + 1 }
  if (образец === null || typeof образец !== "object") return внутри
  switch (образец.kind) {
    case "cons":
      if (typeof образец.head === "string") внутри.set(образец.head, часть)
      if (typeof образец.tail === "string") внутри.set(образец.tail, часть)
      return внутри
    case "variant": {
      const связи = образец.bind ?? {}
      const пары = Array.isArray(связи) ? связи.map((поле) => [поле, поле]) : Object.entries(связи)
      for (const [, имя] of пары) внутри.set(имя, часть)
      return внутри
    }
    case "any":
      if (typeof образец.bind === "string") внутри.set(образец.bind, откуда)
      return внутри
    default:
      return внутри
  }
}

/**
 * Сузить множество позиций, по которым спуск доказан.
 *
 * Позиция остаётся только если аргумент в ней — строго меньшая часть ТОГО ЖЕ
 * параметра. Пересечение по всем вызовам: убывать обязан один и тот же
 * аргумент, иначе глубина рекурсии не ограничена ничем.
 */
function сузитьСпуски(вызов, среда, состояние) {
  const аргументы = вызов.args ?? []
  const держатся = new Set()
  for (const позиция of состояние.спуски) {
    const откуда = происхождение(аргументы[позиция], среда)
    if (откуда !== null && откуда.параметр === позиция && откуда.глубина > 0) держатся.add(позиция)
  }
  состояние.спуски = держатся
}
