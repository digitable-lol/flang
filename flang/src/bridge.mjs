/**
 * Мост между двумя представлениями одних и тех же данных.
 *
 * ── Зачем он есть ───────────────────────────────────────────────────────────
 *
 * Дерево разбора, обязательства и вердикты живут в двух видах сразу. Снаружи, у
 * прогонщика на JavaScript, это обычные объекты и массивы. Внутри, у слоёв,
 * написанных на самом flang, это тип «Значение» из `flang/core/json.flang`:
 * сумма из скаляра, списка, записи и варианта. Перевод между ними механический
 * — форма в форму, ключ в ключ, порядок в порядок, — и решений он не принимает
 * ни одного.
 *
 * ── Почему он в дереве, а не в проверках ────────────────────────────────────
 *
 * Он жил в девятнадцати файлах проверок, каждый со своей копией. Пока звать
 * слои на flang умели только проверки, этого хватало. Как только их зовёт сама
 * команда `flang check`, копия в проверке перестаёт быть достаточной: рабочий
 * путь не может зависеть от файла, которого нет в поставке.
 *
 * Есть и вторая причина, важнее первой. Девятнадцать копий — это девятнадцать
 * мест, где перевод может разойтись, и разойтись молча: сверка сравнила бы
 * ответ эталона, переведённый одним переводом, с ответом свидетеля, а
 * рабочий путь пользовался бы другим. Копия одна — расходиться нечему.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 *
 * Ни одного решения о доказательствах, типах, завершении или печати. Только
 * перевод. Если сюда попадёт условие, зависящее от смысла узла, — это ошибка:
 * смысл читают слои, мост носит данные.
 */
import { isVariant, variant } from "./builtins.mjs"

/* ─────────────────────── JSON → «Значение» ─────────────────────── */

function скаляр(значение) {
  if (значение === null) return variant("Скаляр ничто", {})
  if (typeof значение === "string") return variant("Скаляр строка", { значение })
  if (typeof значение === "number") return variant("Скаляр число", { значение })
  if (typeof значение === "boolean") return variant("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/**
 * Узел дерева разбора → «Значение».
 *
 * `undefined` здесь пропускается ровно там, где его пропустил бы
 * `JSON.stringify`: ключ со значением `undefined` в выводе свидетеля не
 * появляется вовсе, и появиться его копии у эталона значило бы разойтись с
 * свидетелем на каждом узле, у которого нет места в исходнике.
 */
export function вЗначение(узел) {
  if (узел === undefined) return variant("Значение скаляра", { скаляр: скаляр(null) })
  if (isVariant(узел)) return вЗначение({ variant: узел.variant, fields: узел.fields })
  if (Array.isArray(узел)) return variant("Значение списка", { элементы: узел.map(вЗначение) })
  if (узел !== null && typeof узел === "object") {
    return variant("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: вЗначение(вложенное) })),
    })
  }
  return variant("Значение скаляра", { скаляр: скаляр(узел) })
}

/**
 * Аргументы вызова — НЕ то же самое, что узел дерева, и разница здесь не мелочь.
 *
 * У дерева «ключа нет» означает `undefined` свидетеля, поэтому перевод узла ключи
 * с `undefined` выбрасывает. У аргументов правило свидетеля другое: он спрашивает
 * `Object.hasOwn`, и ключ, выставленный в `undefined` руками, для него ЕСТЬ —
 * значение приезжает «ничем», и функция получает «ничто», а не отказ «не задан
 * аргумент». Оракул законов выставляет такие ключи нарочно (недостающий
 * аргумент — «пустое место»), поэтому здесь ключи сохраняются все до единого.
 */
export function аргументыВЗначение(аргументы) {
  return variant("Значение записи", {
    поля: Object.keys(аргументы ?? {}).map((ключ) => ({ ключ, значение: вЗначение(аргументы[ключ]) })),
  })
}

/* ─────────────────────── «Значение» → JSON ─────────────────────── */

/**
 * «Значение» → обычные объекты JavaScript.
 *
 * Принимает и готовое значение времени выполнения (`FlangVariant`), и его
 * запись `{ variant, fields }`: слой на flang возвращает первое, а разобранное
 * дерево несёт второе, и разводить два входа значило бы завести два перевода.
 */
export function изЗначения(узел) {
  if (Array.isArray(узел)) return узел.map(изЗначения)
  const имяВарианта = узел?.variant ?? узел?.constructor?.name
  const поля = узел?.fields ?? узел
  if (имяВарианта === "Значение скаляра") {
    const внутри = поля.скаляр
    const вид = внутри?.variant ?? внутри?.constructor?.name
    if (вид === "Скаляр ничто") return null
    return (внутри.fields ?? внутри).значение
  }
  if (имяВарианта === "Значение списка") return (поля.элементы ?? []).map(изЗначения)
  if (имяВарианта === "Значение записи") {
    const собрано = {}
    for (const поле of поля.поля ?? []) собрано[поле.ключ] = изЗначения(поле.значение)
    return собрано
  }
  throw new Error(`не «Значение»: ${JSON.stringify(узел)?.slice(0, 120)}`)
}

/** «Знач» вычислителя на flang → значение времени выполнения свидетеля. */
export function изЗнач(зн) {
  const вид = зн?.variant ?? зн?.constructor?.name
  const поля = зн?.fields ?? зн
  if (вид === "Знач число") return поля["число"]
  if (вид === "Знач строка") return поля["текст"]
  if (вид === "Знач признак") return поля["признак"]
  if (вид === "Знач ничто") return null
  if (вид === "Знач список") return поля["элементы"].map(изЗнач)
  if (вид === "Знач запись") {
    const запись = {}
    for (const поле of поля["поля"]) запись[поле["ключ"]] = изЗнач(поле["значение"])
    return запись
  }
  if (вид === "Знач вариант") {
    const собрано = {}
    for (const поле of поля["поля"]) собрано[поле["ключ"]] = изЗнач(поле["значение"])
    return variant(поля["имя"], собрано)
  }
  throw new Error(`неизвестный вид «Знач»: ${вид}`)
}
