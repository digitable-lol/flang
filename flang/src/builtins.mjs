// Вариант суммы типов — отдельный класс, а не объект с меткой: запись flang
// это обычный JS-объект (так значения совпадают с FtsValue ядра и сериализуются
// в JSON без потерь), поэтому служебное поле-метка могло бы столкнуться с
// пользовательским полем.
export class FlangVariant {
  constructor(name, fields = {}) {
    this.variant = name
    this.fields = fields
  }
}

export function variant(name, fields = {}) {
  return new FlangVariant(name, fields)
}

export function isVariant(value) {
  return value instanceof FlangVariant
}

/**
 * ── Список с запасом: «добавить» и «приписать» за амортизированное постоянное
 *    время ────────────────────────────────────────────────────────────────
 *
 * Список flang — это массив JS. Так значения совпадают с FtsValue ядра и
 * сериализуются в JSON без потерь, и менять это нельзя. Но «добавить … к …»
 * СТРОИЛО НОВЫЙ МАССИВ ЦЕЛИКОМ (`[...list, item]`), а значит накопление списка
 * из н элементов стоило O(н²) — и это не теория, а измерение на этом самом
 * вычислителе: 50 000 «добавить» — 14 375 мс, 100 000 — 48 668 мс,
 * 200 000 — 229 634 мс. Показатель роста при удвоении 1,76 и 2,24, то есть
 * квадрат. Из-за той же дыры у целей печати предел шагов переставал быть
 * СРОКОМ: 5 000 000 шагов на накопителе брались двадцать минут вместо секунды.
 *
 * Здесь тот же приём, каким это закрыто у C (`fl_b_dobavit`, «запас +
 * заполнено»), Rust и Go (`Items` с концом поверх общего массива):
 *
 *   общий массив `буфер` — это ячейки, УЖЕ кем-то занятые; их число только
 *   растёт, а занять ячейку `конец` вправе единственный список — тот, чей
 *   `конец` совпал с `буфер.length`.
 *
 * У буфера ДВА водораздела, а не один, потому что «приписать … к …» — та же
 * задача с другого конца, и хвостовой запас ей не годится ничем. Второй —
 * `буфер.низ`, первая занятая кем-то ячейка слева; он только УБЫВАЕТ, и занять
 * ячейку `низ − 1` вправе единственный список — тот, чьё `начало` совпало с
 * `низ`. Отсюда у списка два поля вместо одного (`начало` и `конец`), и оба
 * читаются за постоянное время. Целиком правило приписывания — над `приписать`.
 *
 * Отсюда неизменяемость, а она в языке не пожелание: ячейки `0…конец−1` не
 * переписывает никто и никогда, ячейку за концом занимают не более одного раза
 * за жизнь буфера, поэтому ветвление
 *
 *     пусть один равно (добавить 1 к основа)   ← занял ячейку н, занято = н+1
 *     пусть два  равно (добавить 2 к основа)   ← конец н ≠ занято → копия
 *
 * даёт два независимых списка, и «основа» после обоих та же самая. Удвоение
 * запаса берёт на себя сам массив JS, поэтому за н «добавить» память
 * перевыделяется log₂н раз, а не н.
 *
 * ГРАНИЦА. Наружу — вызывающему `createRuntime().call` — этот вид не выходит
 * ВООБЩЕ: `материализовать` переводит его в обычный массив на выходе из
 * вычисления (`interpret.mjs`). Значит ни один читатель значений (тесты, `flang
 * run`, сверка с восемью целями печати, факт-чекинг) о нём не знает и знать не
 * обязан, а внутри машины список ходит видом. Цена границы — один обход
 * результата; цена её отсутствия — представление значений, о котором пришлось
 * бы договариваться со всем деревом.
 */
export class Список {
  constructor(буфер, начало, конец) {
    this.буфер = буфер
    this.начало = начало
    this.конец = конец
  }
}

export function isList(value) {
  return Array.isArray(value) || value instanceof Список
}

/** Длина списка — постоянное время для обоих видов. */
export function длинаСписка(значение) {
  return значение instanceof Список ? значение.конец - значение.начало : значение.length
}

/** Элемент по номеру от нуля — постоянное время для обоих видов. */
export function элементСписка(значение, номер) {
  return значение instanceof Список ? значение.буфер[значение.начало + номер] : значение[номер]
}

/**
 * Обычный массив с элементами списка, начиная с `начало`.
 *
 * Для плоского списка при `начало === 0` это ОН САМ, без копии, — поэтому
 * менять полученное нельзя ни при каких обстоятельствах. Вызывается там, где
 * обход всё равно стоит длины (`соединить`, `содержит`, `хвост`).
 */
export function элементыСписка(значение, начало = 0) {
  if (значение instanceof Список) return значение.буфер.slice(значение.начало + начало, значение.конец)
  return начало === 0 ? значение : значение.slice(начало)
}

/**
 * Ячейки списка БЕЗ КОПИИ: у вида это общий массив, у обычного списка — он сам.
 *
 * Острый угол, и потому один вызывающий — снимок обхода в `interpret.mjs`.
 * Правила три, все обязательны: начинать с `началоСписка`, читать не дальше чем
 * на `длинаСписка` вперёд (по обе стороны от списка в общем массиве лежат чужие
 * ячейки) и не менять ничего. Взамен обход свёртки и «отобразить» не платит ни
 * копией, ни проверкой вида на каждом элементе.
 */
export function ячейкиСписка(значение) {
  return значение instanceof Список ? значение.буфер : значение
}

/** Номер первой ячейки списка в общем массиве. У плоского списка — ноль. */
export function началоСписка(значение) {
  return значение instanceof Список ? значение.начало : 0
}

/**
 * Свободных ячеек, которые «приписать» берёт впереди, когда копия всё равно
 * неизбежна. Запас равен длине, то есть удваивается, — отсюда `log₂н`
 * перевыделений на н приписываний, а не `н`.
 */
const ПЕРВЫЙ_ЗАПАС = 4

/** Список, продлённый одним значением. Исходный не меняется — см. шапку выше. */
function продлить(список, значение) {
  /* Быстрый путь: наш конец — это и конец занятого, значит ячейка за концом
     ничья, и занять её вправе только мы. */
  if (список instanceof Список && список.конец === список.буфер.length) {
    список.буфер[список.конец] = значение
    return new Список(список.буфер, список.начало, список.конец + 1)
  }
  const буфер = список instanceof Список ? список.буфер.slice(список.начало, список.конец) : список.slice()
  буфер.push(значение)
  return new Список(буфер, 0, буфер.length)
}

/**
 * Список, продлённый одним значением СПЕРЕДИ. Исходный не меняется.
 *
 * Зеркало `продлить`, и держится на второй половине того же инварианта. У общего
 * массива два водораздела, а не один:
 *
 *   `буфер.length` — ячеек занято СПРАВА; только растёт. Занять ячейку за
 *     концом вправе тот единственный список, чей `конец` совпал с ним.
 *   `буфер.низ` — первая занятая кем-то ячейка СЛЕВА; только убывает. Занять
 *     ячейку `низ − 1` вправе тот единственный список, чьё `начало` совпало с
 *     `низ`.
 *
 * Отсюда неизменяемость с обеих сторон: ячейки `начало…конец−1` не переписывает
 * никто, ячейку перед началом занимают не более одного раза за жизнь буфера, и
 * ветвление
 *
 *     пусть один равно (приписать 1 к основа)   ← занял ячейку низ−1, низ−−
 *     пусть два  равно (приписать 2 к основа)   ← начало ≠ низ → копия
 *
 * даёт два независимых списка, а «основа» после обоих та же самая.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `продлить`. Ровно одним: массив JS растёт только вправо,
 * `push` слева не бывает. Поэтому весь запас «приписать» берёт заранее — копия
 * кладётся в КОНЕЦ свежего массива, и всё свободное место остаётся перед ней.
 * Тот же приём и по той же причине стоит в `fl_b_pripisat` (C), только там
 * водоразделы лежат в общей записи `fl_grow`, а здесь — в самом массиве
 * (`length` и `низ`).
 *
 * Свободные ячейки заполняются `null`, а не остаются дырами: массив с дырами V8
 * переводит в словарное представление, и тогда чтение элемента перестаёт быть
 * обращением к массиву у ВСЕХ списков, которые этот буфер делят. Плата — один
 * проход по запасу на перевыделение, то есть тот же порядок, что у самой копии.
 */
function приписать(список, значение) {
  /* Быстрый путь: ячейка перед началом принадлежит этому массиву и ничья. */
  if (список instanceof Список && список.начало > 0 && список.начало === список.буфер.низ) {
    const низ = список.начало - 1
    список.буфер[низ] = значение
    список.буфер.низ = низ
    return new Список(список.буфер, низ, список.конец)
  }
  const элементы = список instanceof Список ? список.буфер : список
  const от = список instanceof Список ? список.начало : 0
  const длина = длинаСписка(список)
  const запас = длина < ПЕРВЫЙ_ЗАПАС ? ПЕРВЫЙ_ЗАПАС : длина
  const буфер = new Array(запас + длина).fill(null)
  for (let номер = 0; номер < длина; номер += 1) буфер[запас + номер] = элементы[от + номер]
  буфер[запас - 1] = значение
  буфер.низ = запас - 1
  return new Список(буфер, запас - 1, запас + длина)
}

/**
 * Значение без списков с запасом — обычными массивами, вглубь.
 *
 * Пересобирается только то, внутри чего вид действительно есть: программа, ни
 * разу не позвавшая «добавить» и «приписать», не платит за границу ничем, кроме
 * обхода результата.
 */
export function материализовать(значение) {
  if (значение === null || значение === undefined || isScalar(значение)) return значение
  if (значение instanceof Список) {
    return значение.буфер.slice(значение.начало, значение.конец).map((элемент) => материализовать(элемент))
  }
  if (Array.isArray(значение)) {
    let изменилось = false
    const элементы = значение.map((элемент) => {
      const новый = материализовать(элемент)
      if (новый !== элемент) изменилось = true
      return новый
    })
    return изменилось ? элементы : значение
  }
  if (значение instanceof FlangVariant) {
    let изменилось = false
    const поля = {}
    for (const [имя, поле] of Object.entries(значение.fields)) {
      поля[имя] = материализовать(поле)
      if (поля[имя] !== поле) изменилось = true
    }
    return изменилось ? new FlangVariant(значение.variant, поля) : значение
  }
  if (!isRecord(значение)) return значение
  let изменилось = false
  const запись = {}
  for (const [имя, поле] of Object.entries(значение)) {
    запись[имя] = материализовать(поле)
    if (запись[имя] !== поле) изменилось = true
  }
  return изменилось ? запись : значение
}

export function isRecord(value) {
  return typeof value === "object" && value !== null && !isList(value) && !(value instanceof FlangVariant)
}

// Значение варианта в JSON. Классов JSON не знает, а значения ходят через JSON
// сразу в трёх местах: значение примера в AST («пример … ожидается вариант …»),
// `--args` командной строки и факты для факт-чекинга. Поэтому у варианта есть
// ровно одна запись — { "variant": "Имя", "fields": { … } }, и это в точности
// то, что даёт JSON.stringify(new FlangVariant(…)): печать и чтение обратны
// друг другу, а не «похожи».
//
// Форма узнаётся строго: объект ровно с двумя полями, «variant» — непустая
// строка, «fields» — запись. Запись программы ровно с такими двумя полями от
// варианта неотличима — это цена одного представления вместо двух; заводить
// служебную метку внутри записи нельзя по причине из шапки модуля (запись
// flang — обычный объект JS, метка столкнулась бы с полем пользователя).
function encodedVariant(value) {
  if (!isRecord(value)) return null
  const keys = Object.keys(value)
  if (keys.length !== 2 || !keys.includes("variant") || !keys.includes("fields")) return null
  if (typeof value.variant !== "string" || value.variant === "" || !isRecord(value.fields)) return null
  return value
}

// JSON-значение → значение времени выполнения. Скаляр возвращается как есть
// (это подавляющее большинство вызовов), составное обходится вглубь и
// пересобирается, только если внутри что-то изменилось: иначе каждый литерал
// в теле функции копировал бы свой список на каждом шаге.
//
// Рекурсия по данным, как и у valuesEqual: её глубина ограничена вложенностью
// значения, а не длиной вычисления, поэтому стек JS ей не грозит.
export function reifyValue(value) {
  if (value === undefined) return null
  if (isScalar(value) || isVariant(value)) return value
  /* Список с запасом сюда приходить не может: JSON его не знает, а строит его
     только «добавить» из уже приведённых значений. Пропускаем как есть — иначе
     пришлось бы разворачивать вид ради обхода, который ничего не изменит. */
  if (value instanceof Список) return value
  if (isList(value)) {
    let changed = false
    const items = value.map((item) => {
      const next = reifyValue(item)
      if (next !== item) changed = true
      return next
    })
    return changed ? items : value
  }
  if (!isRecord(value)) return value
  const encoded = encodedVariant(value)
  if (encoded !== null) {
    const fields = {}
    for (const [name, field] of Object.entries(encoded.fields)) fields[name] = reifyValue(field)
    return new FlangVariant(encoded.variant, fields)
  }
  let changed = false
  const record = {}
  for (const [name, field] of Object.entries(value)) {
    record[name] = reifyValue(field)
    if (record[name] !== field) changed = true
  }
  return changed ? record : value
}

export function isScalar(value) {
  return value === null || typeof value === "string" || typeof value === "number" || typeof value === "boolean"
}

export function typeName(value) {
  if (value === null) return "ничто"
  if (typeof value === "string") return "строка"
  if (typeof value === "number") return "число"
  if (typeof value === "boolean") return "признак"
  if (isList(value)) return "список"
  if (isVariant(value)) return `вариант «${value.variant}»`
  if (isRecord(value)) return "запись"
  return "неизвестное значение"
}

// Короткое описание значения для сообщений об ошибках.
export function describeValue(value) {
  if (typeof value === "string") return JSON.stringify(value)
  if (isVariant(value)) {
    const fields = Object.keys(value.fields)
    return fields.length === 0 ? value.variant : `${value.variant}(${fields.join(", ")})`
  }
  if (isList(value)) return `список из ${длинаСписка(value)}`
  if (isRecord(value)) return `запись {${Object.keys(value).join(", ")}}`
  if (value === null) return "ничто"
  if (value === true) return "да"
  if (value === false) return "нет"
  return String(value)
}

// Равенство. Скаляры сравниваем через Object.is — ровно как compare() ядра
// (src/utility.ts): NaN равен NaN, 0 не равен -0. Составные значения ядро не
// сравнивает вовсе, поэтому здесь мы расширяем семантику структурно.
// Рекурсия по данным (не по программе) — её глубина ограничена вложенностью
// значения, а не длиной вычисления, поэтому стек JS ей не грозит.
export function valuesEqual(left, right) {
  if (isScalar(left) || isScalar(right)) {
    if (!isScalar(left) || !isScalar(right)) return false
    return Object.is(left, right)
  }
  if (isList(left) && isList(right)) {
    const длина = длинаСписка(left)
    if (длина !== длинаСписка(right)) return false
    for (let index = 0; index < длина; index += 1) {
      if (!valuesEqual(элементСписка(left, index), элементСписка(right, index))) return false
    }
    return true
  }
  if (isVariant(left) && isVariant(right)) {
    if (left.variant !== right.variant) return false
    return recordsEqual(left.fields, right.fields)
  }
  if (isRecord(left) && isRecord(right)) return recordsEqual(left, right)
  return false
}

function recordsEqual(left, right) {
  const leftKeys = Object.keys(left)
  const rightKeys = Object.keys(right)
  if (leftKeys.length !== rightKeys.length) return false
  return leftKeys.every((key) => key in right && valuesEqual(left[key], right[key]))
}

// ───────────────────────────── числа ─────────────────────────────

// Порядок операций скопирован из src/utility.ts: (percent / 100) * value.
// Переписать в value * percent / 100 нельзя — меняется последний бит мантиссы,
// и совместимость с уже сгенерированным кодом ломается.
export function percentOf(percent, value) {
  return (percent / 100) * value
}

// Остаток — обычный оператор JS: печать в JS должна давать тот же результат,
// поэтому деление на ноль здесь даёт NaN, а не ошибку (это значение IEEE-754,
// а не «забыли обработать»).
export function remainderOf(left, right) {
  return left % right
}

// ───────────────────────────── проверка аргументов ─────────────────────────────

function plural(count, one, few, many) {
  const mod100 = Math.abs(count) % 100
  const mod10 = mod100 % 10
  if (mod100 >= 11 && mod100 <= 14) return many
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}

function expectArity(name, args, count, span) {
  if (args.length !== count) {
    const word = plural(count, "аргумент", "аргумента", "аргументов")
    throw flangError(
      "FLANG_BUILTIN_ARGS",
      `«${name}» ожидает ${count} ${word}, получено ${args.length}`,
      span,
    )
  }
}

function expectString(name, value, role, span) {
  if (typeof value !== "string") {
    throw flangError("FLANG_BUILTIN_ARGS", `«${name}»: ${role} должна быть строкой, получено ${typeName(value)}`, span)
  }
  return value
}

function expectNumber(name, value, role, span) {
  if (typeof value !== "number") {
    throw flangError("FLANG_BUILTIN_ARGS", `«${name}»: ${role} должно быть числом, получено ${typeName(value)}`, span)
  }
  return value
}

function expectInteger(name, value, role, span) {
  expectNumber(name, value, role, span)
  if (!Number.isInteger(value)) {
    throw flangError("FLANG_BUILTIN_ARGS", `«${name}»: ${role} должно быть целым числом, получено ${value}`, span)
  }
  return value
}

function expectList(name, value, role, span) {
  if (!isList(value)) {
    throw flangError("FLANG_BUILTIN_ARGS", `«${name}»: ${role} должен быть списком, получено ${typeName(value)}`, span)
  }
  return value
}

// Индексация человекочитаемая — от 1 и включительно с обоих концов: язык пишут
// на русском, «символ 1 в строке» читается как первый символ. Ноль-базовую
// схему можно включить через options.indexBase = 0 (тогда «по» — исключающая
// граница, как в JS slice).
function indexBase(options) {
  return options && options.indexBase === 0 ? 0 : 1
}

// ───────────────────────────── реализации ─────────────────────────────

// Строки режем по кодовым точкам (Array.from), а не по UTF-16: язык русский,
// и «длина» для «привет» обязана быть 6, а для суррогатных пар — числом
// символов, а не единиц кодирования.
const IMPLEMENTATIONS = {
  "длина": (args, span) => {
    expectArity("длина", args, 1, span)
    const value = args[0]
    if (typeof value === "string") return Array.from(value).length
    if (isList(value)) return длинаСписка(value)
    throw flangError("FLANG_BUILTIN_ARGS", `«длина»: ожидается строка или список, получено ${typeName(value)}`, span)
  },

  "символ": (args, span, options) => {
    expectArity("символ", args, 2, span)
    const index = expectInteger("символ", args[0], "индекс", span)
    const text = expectString("символ", args[1], "строка", span)
    const chars = Array.from(text)
    const at = index - indexBase(options)
    if (at < 0 || at >= chars.length) {
      throw flangError(
        "FLANG_BUILTIN_ARGS",
        `«символ»: индекс ${index} вне строки длиной ${chars.length}`,
        span,
      )
    }
    return chars[at]
  },

  /*
   * Разложение строки в список односимвольных строк — по кодовым точкам, как и
   * всё остальное в этом файле.
   *
   * Пустая строка даёт пустой список, а не список из одной пустой строки: иначе
   * «Длина» от «символы» разошлась бы с «длина» от самой строки на пустом
   * входе, и всякая свёртка по символам получила бы лишний виток из ниоткуда.
   */
  "символы": (args, span) => {
    expectArity("символы", args, 1, span)
    const text = expectString("символы", args[0], "строка", span)
    return Array.from(text)
  },

  /*
   * Кодовая точка первого символа строки — единственный мост из строк в числа.
   *
   * ЗАЧЕМ ОНА НУЖНА, ЕСЛИ ЕСТЬ «символы». Без числа от символа строка остаётся
   * для программы непрозрачной: сравнить две строки можно только на равенство,
   * а посчитать по строке что-нибудь — вообще нечем. Из этого следовали ДВЕ
   * недостачи разом, обе записаны в `flang/examples/leetcode/index.json`: хеша
   * не построить («кода символа язык не даёт вовсе») и порядка на строках нет,
   * значит нет ни двоичного поиска по ключу-строке, ни дерева. Одна форма
   * закрывает обе: порядок пишется НА ЯЗЫКЕ рекурсией по хвосту строки и
   * доказывается тотальным (`flang/stdlib/strings.flang`, «Строка раньше»), а
   * хеш — свёрткой по `разложить … на символы`.
   *
   * ПОЧЕМУ ПЕРВЫЙ СИМВОЛ, А НЕ «РОВНО ОДИН». Требовать строку длиной один
   * значило бы завести ещё один отказ на ровном месте: и `голова` строки, и
   * элемент `разложить … на символы`, и `символ N в …` уже дают ровно один
   * символ, а на всём остальном «первый» — то же самое, что `символ 1 в …`.
   * Одно понятие — один ответ.
   *
   * ПОЧЕМУ КОДОВАЯ ТОЧКА, А НЕ ЕДИНИЦА UTF-16. Потому что так во всём файле:
   * `длина` считает точки, `символ` режет по точкам, `символы` раскладывает по
   * точкам. Эмодзи обязано дать одно число, а не два суррогата, — иначе восемь
   * целей печати разойдутся между собой на первом же непростом входе.
   *
   * ОБРАТНАЯ ФОРМА («символ по коду») ТЕПЕРЬ ЕСТЬ, и здесь же, ниже. Довод, по
   * которому её не заводили, разобран и оказался верным лишь наполовину: хешу и
   * порядку она правда не нужна — обе задачи идут из строк в числа и обратно не
   * возвращаются. Но есть третья задача, и в ней всё наоборот. В СЕТИ кодовая
   * точка приезжает ЧИСЛОМ СНАРУЖИ: `%D0%9C` в адресе — это байты 208 и 156, из
   * них складывается точка 1052, и другого пути к букве «М» у программы нет.
   * Задача появилась — появилась и форма.
   *
   * ОБРАТНЫЙ ХОД ЗАМКНУТ НЕ ВЕЗДЕ, и это названо у самой обратной формы: здесь
   * результат — весь отрезок [0, 0x10FFFF], включая половины суррогатных пар,
   * а обратно из половины пары символа не построить ни в одной цели с UTF-8
   * внутри.
   */
  "код символа": (args, span) => {
    expectArity("код символа", args, 1, span)
    const text = expectString("код символа", args[0], "строка", span)
    const first = Array.from(text)[0]
    if (first === undefined) {
      throw flangError("FLANG_BUILTIN_ARGS", "«код символа»: строка пуста", span)
    }
    return first.codePointAt(0)
  },

  /**
   * «символ по коду» — строка ровно из одного символа по его кодовой точке.
   *
   * ЧТО ВОЗВРАЩАЕТ. Строку. Отдельного СКАЛЯРНОГО ТИПА для одного знака у
   * языка нет, и заводить его ради одной формы значило бы добавить пятый вид
   * значения во все восемь целей печати. `символы` уже раскладывает строку в
   * список ОДНОСИМВОЛЬНЫХ СТРОК, `символ N в S` тоже отдаёт строку — форма не
   * расходится с ними, а встаёт в тот же ряд.
   *
   * ЧТО ДЕЛАЕТ С НЕДОПУСТИМЫМ КОДОМ — ОТКАЗЫВАЕТ, а не подставляет замену.
   * Отказ, а не «вернуть пустую строку» и не «вернуть U+FFFD»: пустая строка
   * ломает обещание «ровно один символ», а молчаливая подмена — это ровно тот
   * дефект, который в `stdlib/http.flang` назван прямым текстом («испортить
   * молча хуже, чем не тронуть»). Отказ виден и приходит с кодом
   * `FLANG_BUILTIN_ARGS` — тем же, каким отказывают все восемь остальных
   * частичных форм, то есть множество отказов языка форма НЕ РАСШИРЯЕТ: вид
   * первый как был, так и остался, прибавилось место, а не вид.
   *
   * ГРАНИЦА ОТКАЗА — ровно четыре условия:
   *
   *   • не число или не целое      `символ по коду 65.5` — половины точки нет;
   *   • меньше нуля                 отрицательной кодовой точки не бывает;
   *   • больше 0x10FFFF             Unicode кончается здесь;
   *   • 0xD800…0xDFFF               суррогат — не символ.
   *
   * ПРО СУРРОГАТЫ РЕШЕНО ОТКАЗЫВАТЬ, И РЕШАЛОСЬ ЭТО ДВАЖДЫ. Сначала было
   * принято обратное — пропускать, — и довод был такой: `код символа` УЖЕ
   * отдаёт числа 55296…57343, потому что одинокая половина пары приезжает
   * снаружи, и отказ разорвал бы обратный ход там, где язык сам признаёт такие
   * числа. Довод верен и всё-таки перебит, вот чем.
   *
   * Спецификация языка обещает: «одинаковые ЗНАЧЕНИЯ и одинаковые тексты
   * отказов» у всех восьми целей (`flang/SPEC.md`, стоимость встроенных форм).
   * А одинокий суррогат в четырёх целях из восьми НЕ ПРЕДСТАВИМ ВОВСЕ: строка в
   * C, Go, Rust и Elixir — это UTF-8 (`flang/src/emit/c/flang_runtime.h`:
   * «строка — UTF-8, длина в байтах и в кодовых точках»), а суррогат в UTF-8 не
   * записывается по определению кодировки. `char::from_u32(0xD800)` в Rust
   * отдаёт `None`, `string(rune(0xD800))` в Go отдаёт U+FFFD. То есть
   * «пропускать» означало бы: три цели с UTF-16 внутри (JavaScript, Java, C#)
   * дают значение, четыре с UTF-8 — не дают, и обещание языка сломано на самом
   * первом непростом входе. Отказ же одинаков во всех восьми, потому что
   * отказывать умеют все.
   *
   * И вторая половина того же довода: суррогат не является символом и по самому
   * Unicode. Скалярное значение (D76) — это любая кодовая точка, КРОМЕ половин
   * суррогатной пары. Форма отдаёт символ, значит её область — скалярные
   * значения, и их 1 112 064, а не 1 114 112.
   *
   * ЧТО ЭТО СТОИЛО. Дырка посередине отрезка: уточнение числа умеет сказать
   * «целое из [низ, верх]» и не умеет «из [низ, верх] мимо дырки». Поэтому
   * `символ по коду (код символа знак)` доказать типом НЕЛЬЗЯ — тип `код
   * символа` есть весь отрезок [0, 0x10FFFF], дырку он не обходит. Что
   * доказывается: всё, о чём известен отрезок ЦЕЛИКОМ по одну сторону дырки, —
   * а это литералы, `нат`-аргументы с объявленной границей и арифметика над
   * ними. Цена названа здесь, чтобы её не искали в диагностике.
   *
   * МИНУС НОЛЬ проверен, как того требует правило для всякой формы, читающей
   * число: `-0` целый, не меньше нуля и даёт U+0000 — тот же символ, что и `0`.
   */
  "символ по коду": (args, span) => {
    expectArity("символ по коду", args, 1, span)
    const код = expectInteger("символ по коду", args[0], "код", span)
    if (код < 0 || код > 0x10ffff) {
      throw flangError(
        "FLANG_BUILTIN_ARGS",
        `«символ по коду»: код ${код} вне диапазона Unicode [0, 1114111]`,
        span,
      )
    }
    if (код >= 0xd800 && код <= 0xdfff) {
      throw flangError(
        "FLANG_BUILTIN_ARGS",
        `«символ по коду»: код ${код} — половина суррогатной пары, а не символ`,
        span,
      )
    }
    return String.fromCodePoint(код)
  },

  "подстрока": (args, span, options) => {
    expectArity("подстрока", args, 3, span)
    const text = expectString("подстрока", args[0], "строка", span)
    const from = expectInteger("подстрока", args[1], "начало", span)
    const to = expectInteger("подстрока", args[2], "конец", span)
    const chars = Array.from(text)
    // При базе 1 «по» включительно, при базе 0 — исключительно; в обоих случаях
    // исключающая граница совпадает с самим «по», сдвигается только начало.
    const start = from - indexBase(options)
    const end = to
    if (start < 0 || start > chars.length) {
      throw flangError("FLANG_BUILTIN_ARGS", `«подстрока»: начало ${from} вне строки длиной ${chars.length}`, span)
    }
    if (end < start || end > chars.length) {
      throw flangError("FLANG_BUILTIN_ARGS", `«подстрока»: конец ${to} вне диапазона [${from}, ${chars.length}]`, span)
    }
    return chars.slice(start, end).join("")
  },

  "соединить": (args, span) => {
    expectArity("соединить", args, 2, span)
    // Две формы: «соединить строку с строкой» и «соединить список с
    // разделителем». Различаем по типу первого аргумента.
    if (isList(args[0])) {
      const separator = expectString("соединить", args[1], "разделитель", span)
      const parts = элементыСписка(args[0]).map((item, index) => {
        if (typeof item !== "string") {
          throw flangError(
            "FLANG_BUILTIN_ARGS",
            `«соединить»: элемент ${index + 1} списка должен быть строкой, получено ${typeName(item)}`,
            span,
          )
        }
        return item
      })
      return parts.join(separator)
    }
    const left = expectString("соединить", args[0], "первая строка", span)
    const right = expectString("соединить", args[1], "вторая строка", span)
    return left + right
  },

  "разделить": (args, span) => {
    expectArity("разделить", args, 2, span)
    const text = expectString("разделить", args[0], "строка", span)
    const separator = expectString("разделить", args[1], "разделитель", span)
    if (separator === "") {
      throw flangError("FLANG_BUILTIN_ARGS", "«разделить»: разделитель не может быть пустым", span)
    }
    return text.split(separator)
  },

  "содержит": (args, span) => {
    expectArity("содержит", args, 2, span)
    if (isList(args[0])) {
      const длина = длинаСписка(args[0])
      for (let номер = 0; номер < длина; номер += 1) {
        if (valuesEqual(элементСписка(args[0], номер), args[1])) return true
      }
      return false
    }
    const text = expectString("содержит", args[0], "строка или список", span)
    const part = expectString("содержит", args[1], "искомая подстрока", span)
    return text.includes(part)
  },

  "начинается с": (args, span) => {
    expectArity("начинается с", args, 2, span)
    const text = expectString("начинается с", args[0], "строка", span)
    const prefix = expectString("начинается с", args[1], "префикс", span)
    return text.startsWith(prefix)
  },

  "к числу": (args, span) => {
    expectArity("к числу", args, 1, span)
    const text = expectString("к числу", args[0], "строка", span)
    const trimmed = text.trim()
    // Строгий разбор: без Infinity, NaN, шестнадцатеричных и пустой строки —
    // иначе «к числу» молча превращает мусор в значение.
    if (!/^[+-]?(\d+(\.\d+)?|\.\d+)([eE][+-]?\d+)?$/u.test(trimmed)) {
      throw flangError("FLANG_BUILTIN_ARGS", `«к числу»: строка ${JSON.stringify(text)} не является числом`, span)
    }
    const result = Number(trimmed)
    if (!Number.isFinite(result)) {
      throw flangError("FLANG_BUILTIN_ARGS", `«к числу»: строка ${JSON.stringify(text)} не является конечным числом`, span)
    }
    return result
  },

  /*
   * «к числу», чей отказ стал значением. Обоснование формы — в шапке модуля,
   * раздел «отказ, ставший значением».
   *
   * Тело здесь буквально одно: вызвать «к числу» и перевести её отказ в
   * вариант. Переписывать разбор второй раз было бы дефектом по построению —
   * два разбора одной строки рано или поздно разошлись бы, а обещано ровно
   * обратное: те же значения и те же тексты.
   *
   * Ловится ЛЮБОЙ отказ «к числу», включая «аргумент не строка». Так форма
   * действительно не может отказать — а «почти не может» здесь ничем не лучше
   * прежнего: программа снова не знала бы, надо ли проверять заранее.
   */
  "к числу или беда": (args, span) => {
    expectArity("к числу или беда", args, 1, span)
    try {
      return variant(OUTCOME_PARSED, { значение: IMPLEMENTATIONS["к числу"](args, span) })
    } catch (беда) {
      return variant(OUTCOME_FAILED, {
        код: беда?.code ?? "FLANG_BUILTIN_ARGS",
        сообщение: String(беда?.message ?? ""),
      })
    }
  },

  "к строке": (args, span) => {
    expectArity("к строке", args, 1, span)
    const value = args[0]
    if (typeof value === "string") return value
    if (typeof value === "number") return String(value)
    // Признак печатаем по-русски: поверхность языка знает «да» и «нет», а не
    // true и false.
    if (typeof value === "boolean") return value ? "да" : "нет"
    if (value === null) return "ничто"
    throw flangError("FLANG_BUILTIN_ARGS", `«к строке»: ожидается скаляр, получено ${typeName(value)}`, span)
  },

  "пусто": (args, span) => {
    expectArity("пусто", args, 1, span)
    const value = args[0]
    if (isList(value)) return длинаСписка(value) === 0
    if (typeof value === "string") return Array.from(value).length === 0
    throw flangError("FLANG_BUILTIN_ARGS", `«пусто»: ожидается строка или список, получено ${typeName(value)}`, span)
  },

  "голова": (args, span) => {
    expectArity("голова", args, 1, span)
    const list = expectList("голова", args[0], "аргумент", span)
    if (длинаСписка(list) === 0) throw flangError("FLANG_BUILTIN_ARGS", "«голова»: список пуст", span)
    return элементСписка(list, 0)
  },

  // «хвост» копирует, и здесь это осталось: разделение с суффиксом — это второе
  // поле вида (начало), а закрывалась дыра ПРИПИСЫВАНИЯ. Значит рекурсия
  // «голова и хвост» по длинному списку по-прежнему квадратична; для больших
  // данных язык даёт линейные «свёртка», «отобразить» и «отфильтровать»,
  // которые ничего не копируют.
  "хвост": (args, span) => {
    expectArity("хвост", args, 1, span)
    const list = expectList("хвост", args[0], "аргумент", span)
    if (длинаСписка(list) === 0) throw flangError("FLANG_BUILTIN_ARGS", "«хвост»: список пуст", span)
    return элементыСписка(list, 1)
  },

  /*
   * Элемент по номеру. Индексация с 1 и включительно — та же, что у «символ»,
   * и по той же причине: язык пишут по-русски, «элемент 1 в списке» читается
   * как первый.
   *
   * ЧТО ЭТА ФОРМА ОБЕЩАЕТ, А ЧТО НЕТ. Обещает она ЗНАЧЕНИЕ, а не стоимость:
   * «взять N-й» без обхода — это свойство представления списка в цели печати,
   * а не языка. Здесь, в вычислителе, список — массив JS, и обращение стоит
   * одного шага; в семи целях из восьми — тоже (массив в C, срез в Go, `Vec` с
   * началом в Rust, `list` в Python, массивы в Java и C#, массив в JS). В
   * восьмой, Elixir, список BEAM односвязный, и обращение к N-му стоит N
   * переходов; там же и `длина` стоит обхода. Цифры измерены и записаны в
   * SPEC, раздел «Стоимость встроенных форм» — обещать «быстро» там, где цель
   * этого не даёт, значит врать одному из восьми читателей.
   *
   * ОТКАЗ. Номер вне списка прекращает вычисление, как и у «символ»: проверка
   * заранее здесь ничего не повторяет — `не больше (длина элементы)` выразимо
   * одной строкой, и это ровно тот случай, о котором сказано в шапке файла.
   */
  "элемент": (args, span, options) => {
    expectArity("элемент", args, 2, span)
    const index = expectInteger("элемент", args[0], "индекс", span)
    const list = expectList("элемент", args[1], "список", span)
    const длина = длинаСписка(list)
    const at = index - indexBase(options)
    if (at < 0 || at >= длина) {
      throw flangError("FLANG_BUILTIN_ARGS", `«элемент»: индекс ${index} вне списка длиной ${длина}`, span)
    }
    return элементСписка(list, at)
  },

  "добавить": (args, span) => {
    expectArity("добавить", args, 2, span)
    const list = expectList("добавить", args[1], "второй аргумент", span)
    // «добавить x к списку» читается как дописать в конец; исходный список не
    // изменяется — значения flang неизменяемы. За постоянное время, приёмом
    // «занять ячейку за концом общего массива»: см. шапку «Список с запасом».
    return продлить(list, args[0])
  },

  "приписать": (args, span) => {
    expectArity("приписать", args, 2, span)
    const list = expectList("приписать", args[1], "второй аргумент", span)
    // «приписать x к списку» читается как дописать в НАЧАЛО; исходный список не
    // изменяется — значения flang неизменяемы. За амортизированное постоянное
    // время, приёмом «занять ячейку перед началом общего массива»: см. шапку
    // «Список с запасом» и довод над `приписать`.
    return приписать(list, args[0])
  },

  "остаток от": (args, span) => {
    expectArity("остаток от", args, 2, span)
    const left = expectNumber("остаток от", args[0], "делимое", span)
    const right = expectNumber("остаток от", args[1], "делитель", span)
    return remainderOf(left, right)
  },

  "процентов от": (args, span) => {
    expectArity("процентов от", args, 2, span)
    const percent = expectNumber("процентов от", args[0], "процент", span)
    const value = expectNumber("процентов от", args[1], "значение", span)
    return percentOf(percent, value)
  },
}

// Синонимы: парсер может отдавать как краткую, так и полную форму имени.
const ALIASES = new Map([
  ["символ в", "символ"],
  ["элемент в", "элемент"],
  ["начинается", "начинается с"],
  ["остаток", "остаток от"],
  ["процентов", "процентов от"],
  ["код_символа", "код символа"],
  ["charCode", "код символа"],
  ["символ_по_коду", "символ по коду"],
  ["charFromCode", "символ по коду"],
  ["к_числу", "к числу"],
  ["к_числу_или_беда", "к числу или беда"],
  ["к_строке", "к строке"],
])

export const BUILTIN_NAMES = Object.freeze(Object.keys(IMPLEMENTATIONS))

export function canonicalBuiltinName(name) {
  return ALIASES.get(name) ?? name
}

export function hasBuiltin(name) {
  return Object.hasOwn(IMPLEMENTATIONS, canonicalBuiltinName(name))
}

/**
 * ── Формы, чью частичность снимает доказанная непустота ─────────────────────
 *
 * Частичных форм в языке восемь (`src/failures.mjs`, `ЧАСТИЧНЫЕ`), а здесь их
 * четыре, и отбор не произвольный: у этих четырёх условие отказа ОДНО И ТО ЖЕ —
 * «длина ноль». `голова` и `хвост` отказывают на пустом списке, `код символа` —
 * на пустой строке, `разделить` — на пустом РАЗДЕЛИТЕЛЕ (делить можно и пустую
 * строку). Значит и доказываются они одним и тем же уточнением типа
 * (`src/types.mjs`, `длинаНиз`), а не четырьмя частными случаями.
 *
 * Остальные четыре этим средством не снимаются вовсе: `элемент`, `символ` и
 * `подстрока` требуют ДВУСТОРОННЕЙ границы номера — это другой анализ, — а
 * `к числу` частична неустранимо: никакой тип строки не обещает, что она
 * записывает число.
 *
 * Список живёт здесь, в файле без единого импорта, потому что читают его двое,
 * которым иначе пришлось бы держать по своей копии: проверка типов (кто ставит
 * отметку) и все восемь бэкендов (кто её читает). Две копии разошлись бы молча
 * в тот день, когда список пополнится.
 */
export const СНИМАЮТСЯ_НЕПУСТОТОЙ = Object.freeze(["голова", "хвост", "разделить", "код символа"])

/**
 * Имя помощника, которого печать зовёт на этом месте.
 *
 * Правило одно на восемь целей: доказанное место зовёт того же помощника с
 * приставленным суффиксом. Суффикс задаёт цель, потому что стиль имён у целей
 * разный (`fl_b_golova` в C, `BHead` в Go), а правило — общее, и держать в
 * каждой цели вторую таблицу имён значило бы завести восемь мест, где можно
 * ошибиться поодиночке.
 *
 * @param {string} canonical каноническое имя формы
 * @param {object} node узел выражения — на нём стоит отметка `доказана`
 * @param {Map<string,string>} помощники таблица имён этой цели
 * @param {string} суффикс приставка имени доказанного пути у этой цели
 * @returns {string|undefined} имя помощника
 */
export function помощникФормы(canonical, node, помощники, суффикс) {
  const имя = помощники.get(canonical)
  if (имя === undefined) return имя
  if (node?.доказана !== true || !СНИМАЮТСЯ_НЕПУСТОТОЙ.includes(canonical)) return имя
  return `${имя}${суффикс}`
}

export function callBuiltin(name, args, span, options) {
  const canonical = canonicalBuiltinName(name)
  if (!Object.hasOwn(IMPLEMENTATIONS, canonical)) {
    throw flangError("FLANG_UNKNOWN_NAME", `неизвестная встроенная форма «${name}»`, span)
  }
  if (!Array.isArray(args)) {
    throw flangError("FLANG_BUILTIN_ARGS", `«${name}»: аргументы должны быть списком`, span)
  }
  return IMPLEMENTATIONS[canonical](args, span, options ?? {})
}
