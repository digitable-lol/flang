/**
 * Коммутативность: `а∘б = б∘а`.
 *
 * ── Улика, снятая прогоном ДО работы, и она с историей ──────────────────────
 *
 * Это НЕ новая недостача, а записанная. `flang/cat/SPEC.md` в таблице
 * персистентных структур называет множество «моноидом, КОММУТАТИВНЫМ», — а
 * сказать этого языком было нечем: в объявлении моноида коммутативности нет, и
 * добавить её строкой туда нельзя, потому что моноид объявляет ТРИ вещи разом и
 * получает три закона, а коммутативность — свойство одной операции.
 *
 * Прогон это подтверждал: моноид «Вычитание чисел», операция которого заведомо
 * не коммутативна, проходил `flang check --proof` с вердиктом
 * «ассоциативность, нейтральность: нарушений не найдено» — и о порядке
 * аргументов отчёт не говорил ничего.
 *
 * ── Ради чего это свойство ──────────────────────────────────────────────────
 *
 * Разрешение РАЗЛОЖИТЬ СВЁРТКУ. Свёртка по ассоциативной операции разбивается на
 * дерево — считать можно кусками; но кусок, посчитанный вторым ядром и
 * приехавший первым, попадёт в свёртку не на своё место, и без коммутативности
 * результат от этого меняется. Ассоциативность разрешает менять СКОБКИ,
 * коммутативность — ПОРЯДОК, и разложить свёртку по ядрам можно ровно тогда,
 * когда есть обе.
 *
 * Поэтому проверка эта дешёвая, а следствие у неё чужое: моноид, чья операция
 * объявлена коммутативной и посчитана чистой, называет её в СВОЕЙ строке
 * законов (`proof.mjs`). Первое место, где объявленное свойство меняет вердикт
 * о другой конструкции языка.
 *
 * ── Что здесь ПРОВЕРЯЕТСЯ, а не доказывается ────────────────────────────────
 *
 * Закон. Устройство доказано раньше и в другом месте (`types.mjs`). Здесь —
 * равенство вычислений на всех парах значений носителя, а оно неразрешимо:
 * значит конечная сетка, квадратичная по ней, и ведомость обязана называть
 * размер сетки строкой, оканчивающейся словами «Это не доказательство».
 */
import { valuesEqual } from "./builtins.mjs"
import { ПРЕДЕЛ_СЕТКИ, объявления, основа, покажи, пусто } from "./svoystva.mjs"

export { ПРЕДЕЛ_СЕТКИ }

/** Имя свойства — то самое, что автор пишет в ёлочках. */
export const ИМЯ = "коммутативность"

/**
 * Проверка коммутативности всех операций, её объявивших.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object>,
 *   assumed: Array<object>, permits: Array<object> }}
 */
export function checkCommutativity(программа, пределы = {}) {
  const узлы = объявления(программа, ИМЯ)
  const итог = пусто()
  if (узлы.length === 0) return итог

  const { найти, звать, сетка } = основа(программа, пределы)

  for (const узел of узлы) {
    const функция = найти(узел.operation)
    if (функция === undefined || (функция.params ?? []).length !== 2) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation ?? null,
        why: "устройство операции не сошлось: об этом сказала проверка типов",
      })
      continue
    }

    const значения = сетка([узел.operation])
    if (значения.length === 0) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation,
        why: `у «${узел.operation}» нет примеров: сетка пуста, менять местами было нечего`,
      })
      continue
    }

    const доБед = итог.diagnostics.length
    let оборвано = null
    let пар = 0
    /* Пары берутся ВСЕ, включая «сам с собой» и обе стороны: `а∘б` и `б∘а` —
       это и есть два вызова, которые сравниваются, и сокращать перебор до
       верхнего треугольника нельзя, потому что треугольник и есть проверка. */
    пары: for (const а of значения) {
      for (const б of значения) {
        пар += 1
        const туда = звать(узел.operation, а, б)
        const назад = звать(узел.operation, б, а)
        if (туда.ошибка || назад.ошибка) {
          оборвано = `«${узел.operation}» отказала на значении сетки: ${туда.ошибка ?? назад.ошибка}`
          break пары
        }
        if (valuesEqual(туда.значение, назад.значение)) continue
        итог.diagnostics.push({
          code: "FLANG_NOT_COMMUTATIVE",
          message: `свойство «${ИМЯ}»: «${узел.operation}» не коммутативна: на ${покажи(а)} и ${покажи(б)} ` +
            `вышло ${покажи(туда.значение)}, а в обратном порядке — ${покажи(назад.значение)} — ` +
            `свёртку по такой операции нельзя разложить по ядрам: порядок кусков меняет ответ`,
          severity: "error",
          span: узел.span,
        })
        break пары
      }
    }

    const нарушений = итог.diagnostics.length - доБед
    итог.checked.push({
      property: ИМЯ,
      subject: узел.operation,
      values: значения.length,
      points: пар,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
    if (нарушений > 0 || оборвано !== null) continue
    итог.permits.push({
      permit: "разложить",
      property: ИМЯ,
      subject: узел.operation,
      says: `свёртку по «${узел.operation}» можно разложить по ядрам: порядок кусков ответа не меняет`,
    })
  }

  return итог
}
