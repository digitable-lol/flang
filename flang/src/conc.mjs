/**
 * conc.mjs — модель конкурентности flang: словарь действий и планировщик эталона.
 *
 * Контракт — `flang/conc/SPEC.md`. Здесь сделан шаг 1: поверхность разбирается
 * (parser.mjs), проверяется (types.mjs) и исполняется вот этим планировщиком.
 * Печати в Elixir и C, супервизоров в рантайме и распределённости здесь нет —
 * что именно сделано и чем разошлось с контрактом, перечислено в разделе
 * контракта «Что сделано в шаге 1».
 *
 * ── Почему словарь действий встроенный, а не объявляемый ────────────────────
 *
 * Действие описывается, а не выполняется (контракт, «Семантика»). Значит
 * обработчик обязан вернуть значение, у которого есть тип, а тип обязан быть
 * объявлен. Объявлять его в каждой программе заново — значит позволить двум
 * программам называть отправку по-разному, и тогда планировщик перестанет быть
 * общим: ему пришлось бы угадывать, какой из вариантов «отправить». Поэтому
 * сумма «Действие» вводится языком, а не пользователем, и парсер приписывает её
 * к типам программы, как только в файле есть хоть один `процесс`.
 *
 * Тип сообщения в «отправить» — джокер (`любое`). Полиморфизма в языке нет
 * (SPEC, раздел 3), поэтому «сообщение любого типа» иначе не выражается. Потеря
 * не такая большая, как кажется: проверка типов сверяет сообщение с объявленным
 * `принимает` адресата по имени процесса (types.mjs, `sendActionType`), то есть
 * ровно там, где адресат известен.
 *
 * ── Чего в наборе действий нет и почему ─────────────────────────────────────
 *
 * «породить» в контракте описан как «создать процесс, вернуть его имя». Вернуть
 * что-либо описанное действие не может по построению: оно описывается, а
 * исполняет его планировщик. Честного способа отдать имя обратно чистому
 * обработчику в шаге 1 не нашлось, поэтому «породить» не сделан вовсе — вместо
 * половинчатой формы, которая называлась бы порождением, но им не была. Это
 * записано и в контракте, в разделе «Граница честности».
 *
 * «продолжить» сделан без поля. В контракте у него есть «с чем» — продолжение
 * как значение. Но отклик уже несёт новое состояние, и второе поле означало бы
 * два источника правды об одном и том же: если они разойдутся, планировщику
 * придётся выбирать, и выбор будет произволом. Поэтому продолжение — это
 * состояние из отклика, а само действие говорит только «я не доделал»:
 * сообщение возвращается в голову ящика, а планировщик получает управление.
 *
 * ── Планировщик: почему семя и что именно оно определяет ────────────────────
 *
 * Обработчик атомарен в пределах своего процесса, процессы идут параллельно,
 * наблюдаемая семантика — любое чередование атомарных пробегов. Проверочный
 * режим обязан уметь предъявить конкретное чередование и повторить его, иначе
 * конкурентный код проверяется словами «иногда падает».
 *
 * Здесь единственный источник недетерминизма — выбор процесса из очереди
 * готовых, и он берётся из генератора, заведённого семенем. Всё остальное
 * (порядок ящика, порядок действий отклика, порядок срабатывания таймеров при
 * равном времени) строго определено. Отсюда: одно семя — один журнал доставок,
 * побайтово.
 */

import { FlangError, flangError, reifyValue, valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Имя суммы, которую язык приписывает программе с процессами. */
export const ACTION_TYPE_NAME = "Действие"

/** Поля отклика обработчика. Имена — часть контракта, а не соглашение. */
export const RESPONSE_STATE = "состояние"
export const RESPONSE_ACTIONS = "действия"

/** Стратегии надзора. Их ровно три — контракт, раздел «Отказ, надзор, перезапуск». */
export const STRATEGIES = ["перезапустить", "остановить", "передать выше"]

/**
 * Сумма «Действие» — словарь языка, а не объявление пользователя.
 *
 * `builtin: true` нужен связыванию модулей: два файла с процессами приписали бы
 * эту сумму каждый себе, и слияние объявило бы её объявленной дважды. Пометка
 * говорит `link.mjs`, что повтор здесь — не конфликт.
 */
export const ACTION_TYPE = Object.freeze({
  kind: "sum",
  name: ACTION_TYPE_NAME,
  builtin: true,
  variants: [
    {
      name: "отправить",
      fields: [
        { name: "кому", type: { kind: "string" } },
        { name: "что", type: { kind: "any" } },
      ],
    },
    {
      name: "через",
      fields: [
        { name: "задержка", type: { kind: "number" } },
        { name: "кому", type: { kind: "string" } },
        { name: "что", type: { kind: "any" } },
      ],
    },
    { name: "остановить", fields: [{ name: "почему", type: { kind: "string" } }] },
    { name: "отложить", fields: [] },
    { name: "продолжить", fields: [] },
  ],
})

/** Действия, у которых есть адресат: их проверка типов сверяет по имени процесса. */
export const ADDRESSED_ACTIONS = new Set(["отправить", "через"])

/**
 * Приписать словарь действий к программе. Идемпотентно: повторный вызов ничего
 * не меняет, поэтому его можно звать и из парсера, и из связывания.
 */
export function withActionType(program) {
  const types = Array.isArray(program?.types) ? program.types : []
  if (types.some((type) => type?.name === ACTION_TYPE_NAME)) return program
  return { ...program, types: [...types, ACTION_TYPE] }
}

