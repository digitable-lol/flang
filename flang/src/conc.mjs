/**
 * Расхождения одного семени с ожиданиями прогона.
 *
 * Вынесено отдельной функцией, потому что зовётся на каждое семя сетки:
 * ожидание «равен» и ожидание «стратегия» обязаны сбываться на КАЖДОМ
 * чередовании, а не на одном выбранном.
 */
function расхожденияСемени(итог, ожидания) {
  const расхождения = []
  for (const ожидание of ожидания) {
    if (ожидание.kind === "oneOf") continue
    if (ожидание.kind === "strategy") {
      const было = итог.решения.filter(
        (р) => р.процесс === ожидание.process && р.стратегия === ожидание.strategy,
      ).length
      if (было !== ожидание.times) {
        расхождения.push({
          процесс: ожидание.process,
          стратегия: ожидание.strategy,
          ожидалось: ожидание.times,
          получено: было,
        })
      }
      continue
    }
    const было = итог.состояния[ожидание.process]
    if (!valuesEqual(было, reifyValue(ожидание.state))) {
      расхождения.push({ процесс: ожидание.process, ожидалось: ожидание.state, получено: было })
    }
  }
  return расхождения
}

/**
 * Прогоны программы как примеры: семя (или сетка семян), входные сообщения,
 * ожидаемый итог.
 *
 * Форма результата повторяет `runExamples` из `compat.mjs` — это тот же аппарат
 * проверки, а не отдельный: конкурентность не должна становиться местом, где
 * проверки заканчиваются (контракт, «Что проверяется и чем»).
 *
 * ── Ожиданий три вида ───────────────────────────────────────────────────────
 *
 * Состояние — `ожидается «П» равен значение`. Исход надзора — `ожидается «П»
 * стратегия «X» N раз`; без него «состояние вернулось к начальному» ничего не
 * доказывало бы, потому что у процесса, которому вообще ничего не приходило,
 * состояние тоже начальное. Множество итогов — `ожидается «П» любое из [ … ]`
 * (шаг 5); оно и есть та самая «сетка семян» из пункта 3 контракта.
 *
 * ── Почему множество проверяется в обе стороны ──────────────────────────────
 *
 * Одностороннее «каждый итог лежит в множестве» сбывается тем легче, чем шире
 * множество: дописав в него десять лишних значений, автор ослабляет проверку и
 * ничего об этом не узнаёт. Поэтому вторая половина обязательна: каждое
 * названное значение обязано где-то встретиться. Тогда список в исходнике —
 * это ИМЕННО множество достижимых итогов, а не верхняя оценка на него.
 *
 * Цена честная и названа здесь: половина «встретилось» зависит от того,
 * насытилась ли сетка. Не насытилась — прогон падает с «значение не встретилось
 * ни на одном семени», и автор либо расширяет сетку, либо убирает значение,
 * которого не бывает. Ошибаться в эту сторону безопасно: непроверенное
 * утверждение краснеет, а не зеленеет.
 */
export function runConcurrentExamples(program, options = {}) {
  const результаты = []
  for (const прогон of program?.runs ?? []) {
    const от = прогон.seed
    const до = прогон.seedTo === null || прогон.seedTo === undefined ? прогон.seed : прогон.seedTo
    const ожидания = прогон.expected ?? []
    const множества = ожидания.filter((о) => о.kind === "oneOf")

    /* Что встретилось на сетке. Различаются итоги тем же `valuesEqual`, каким
       сверяется «равен», а не сравнением строк: два способа считать значения
       одинаковыми разошлись бы рано или поздно, и разошлись бы молча. Список, а
       не Map с ключом-строкой, поэтому и вышел — различных итогов у прогона
       единицы, и линейный поиск здесь дешевле правильного ключа.

       Семя запоминается не для отчётности: именно им найденное чередование
       предъявляется потом поодиночке (`семя 4172`). */
    const встречено = множества.map(() => [])
    const лишние = множества.map(() => [])
    const запомнить = (куда, значение, семя) => {
      if (куда.some((виданное) => valuesEqual(виданное.значение, значение))) return
      куда.push({ значение, семя })
    }

    let семян = 0
    let первоеРасхождение = null
    let последний = null
    try {
      for (let семя = от; семя <= до; семя += 1) {
        const итог = runConcurrent(program, { ...прогон, seed: семя }, options)
        семян += 1
        последний = итог
        const расхождения = расхожденияСемени(итог, ожидания)
        if (расхождения.length > 0 && первоеРасхождение === null) {
          первоеРасхождение = { семя, расхождения }
        }
        множества.forEach((ожидание, номер) => {
          const было = итог.состояния[ожидание.process]
          const названо = (ожидание.states ?? []).some((вариант) => valuesEqual(было, reifyValue(вариант)))
          запомнить(названо ? встречено[номер] : лишние[номер], было, семя)
        })
      }

      const расхождения = первоеРасхождение === null ? [] : первоеРасхождение.расхождения
      множества.forEach((ожидание, номер) => {
        for (const { семя, значение } of лишние[номер]) {
          расхождения.push({ процесс: ожидание.process, семя, вне: значение })
        }
        for (const вариант of ожидание.states ?? []) {
          const значение = reifyValue(вариант)
          if (!встречено[номер].some((виданное) => valuesEqual(виданное.значение, значение))) {
            расхождения.push({ процесс: ожидание.process, неВстретилось: вариант })
          }
        }
      })

      результаты.push({
        run: прогон.name,
        seed: прогон.seed,
        семян,
        /* `доСемени` — признак того, что прогон был сеткой, а не одним семенем.
           Ставится по объявленному отрезку (`до > от`), а не по числу пройденных
           семян: сорвавшаяся на третьем семени сетка из тысячи всё равно сетка, и
           подписывать её «семя 1» значило бы прятать, чем она была. */
        ...(до > от ? { доСемени: до } : {}),
        passed: расхождения.length === 0,
        ...(первоеРасхождение === null ? {} : { наСемени: первоеРасхождение.семя }),
        /* Исход, доставки и решения — с ПОСЛЕДНЕГО семени сетки, а не сводка по
           всей. Сводкой их сделать нельзя: у разных семян исходы разные, и
           «покой у 998 семян из 1000» — это уже не отчёт о прогоне, а второе
           ожидание, которого автор не писал. Что проверено на всей сетке,
           говорят `семян` и `итогов`. */
        исход: последний?.исход ?? "покой",
        доставок: последний?.журнал.length ?? 0,
        решений: последний?.решения.length ?? 0,
        ...(множества.length > 0
          ? { итогов: множества.map((_, номер) => встречено[номер].length + лишние[номер].length) }
          : {}),
        расхождения,
      })
    } catch (ошибка) {
      результаты.push({
        run: прогон.name,
        seed: прогон.seed,
        семян,
        /* `доСемени` ставится и здесь, а не только на удачном пути: без него
           отчёт о сорвавшейся сетке подписывался бы «семя от 1 до undefined». */
        ...(до > от ? { доСемени: до } : {}),
        /* Семя, на котором прогон сорвался, — самое ценное, что тут есть: без
           него сетка из тысячи семян сообщала бы «где-то сломалось». Семян
           пройдено `семян`, значит сорвалось на следующем; при нуле пройденных
           это первое семя сетки, и формула даёт его же. */
        наСемени: от + семян,
        passed: false,
        error: текстОшибки(ошибка),
        code: кодОшибки(ошибка),
      })
    }
  }
  return результаты
}
