/**
 * Генератор псевдослучайных чисел из семени (mulberry32).
 *
 * Выбран не за качество распределения — оно здесь ни на что не влияет, — а за
 * то, что укладывается в шесть строк целочисленной арифметики и потому
 * повторяется где угодно один в один. Планировщик в рантайме C обязан выдать
 * тот же журнал доставок на том же семени (контракт, «Что проверяется и чем»,
 * пункт 2), и генератор, который нельзя переписать на C за десять минут, сделал
 * бы это обещание невыполнимым.
 */
export function makeRandom(seed) {
  let state = (Math.trunc(seed) >>> 0) || 0x9e3779b9
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

