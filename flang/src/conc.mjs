/**
 * Прогоны программы как примеры: семя, входные сообщения, ожидаемый итог.
 *
 * Форма результата повторяет `runExamples` из `compat.mjs` — это тот же аппарат
 * проверки, а не отдельный: конкурентность не должна становиться местом, где
 * проверки заканчиваются (контракт, «Что проверяется и чем»).
 */
export function runConcurrentExamples(program, options = {}) {
  const результаты = []
  for (const прогон of program?.runs ?? []) {
    try {
      const итог = runConcurrent(program, прогон, options)
      const расхождения = []
      for (const ожидание of прогон.expected ?? []) {
        const было = итог.состояния[ожидание.process]
        if (!valuesEqual(было, reifyValue(ожидание.state))) {
          расхождения.push({ процесс: ожидание.process, ожидалось: ожидание.state, получено: было })
        }
      }
      результаты.push({
        run: прогон.name,
        seed: прогон.seed,
        passed: расхождения.length === 0,
        исход: итог.исход,
        доставок: итог.журнал.length,
        расхождения,
      })
    } catch (ошибка) {
      результаты.push({
        run: прогон.name,
        seed: прогон.seed,
        passed: false,
        error: текстОшибки(ошибка),
        code: кодОшибки(ошибка),
      })
    }
  }
  return результаты
}
