/**
 * Приписать словарь действий к программе. Идемпотентно: повторный вызов ничего
 * не меняет, поэтому его можно звать и из парсера, и из связывания.
 *
 * `словарь` — какой именно словарь приписать: шесть действий (умолчание) или
 * семь (`actionTypeWithOrder()` из `io.mjs`). Подаётся, а не выбирается здесь,
 * по тому же доводу, по которому седьмое действие живёт в `io.mjs`: его поле
 * объявлено типом из словаря поручений, а ввоз оттуда сюда замыкает круг.
 */
export function withActionType(program, словарь = ACTION_TYPE) {
  const types = Array.isArray(program?.types) ? program.types : []
  if (types.some((type) => type?.name === ACTION_TYPE_NAME)) return program
  return { ...program, types: [...types, словарь] }
}

