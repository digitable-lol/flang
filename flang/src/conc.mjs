/**
 * Отказ печати, если у цели нет планировщика, а в программе есть процессы.
 *
 * ── Что было до этого отказа ─────────────────────────────────────────────────
 *
 * Шесть целей из восьми ТЕРЯЛИ процессы молча. `emit --target go` на
 * `flang/conc/examples/supervision.flang` кончался кодом 0 и печатал 80 155
 * байт Go, в которых имя процесса «Работник» не встречалось ни разу, «Учётчик» —
 * один раз, и только строковым литералом адреса внутри тела обработчика
 * (`Value: rt.Text("Учётчик")`). Ни процесса, ни состояния, ни ящика, ни
 * надзора: `процессы|supervisors` в `c.mjs` встречается 15 раз, в `elixir.mjs`
 * 10, в остальных шести — ноль.
 *
 * Это худший из возможных исходов, потому что он выглядит успехом. Программа
 * компилируется целевым компилятором, запускается и делает НЕ ТО, что написано:
 * обработчики стали обычными функциями, которых никто не зовёт. Отказ здесь —
 * не строгость, а единственный честный ответ: печать в цель без планировщика
 * невозможна, и сказать об этом должна печать, а не пользователь, обнаруживший
 * молчащую программу.
 *
 * ── Почему отказ живёт в бэкенде, а не в команде ─────────────────────────────
 *
 * Бэкенды — библиотека: их зовут напрямую из Node (`emitGo(program)`), и тесты
 * репозитория зовут именно так. Отказ в `bin/flang.mjs` закрыл бы только
 * командную строку, а молчаливая потеря процессов осталась бы у всех, кто
 * печатает программно.
 *
 * @param {object} program AST flang
 * @param {string} цель идентификатор цели печати (имя модуля в `src/emit`)
 * @throws {Error} с кодом `FLANG_CONC_UNSUPPORTED`, если печатать нечем
 */
export function требуетПланировщика(program, цель) {
  const сколько = (поле) => (Array.isArray(program?.[поле]) ? program[поле].length : 0)
  const процессов = сколько("processes")
  const надзоров = сколько("supervisors")
  const прогонов = сколько("runs")
  if (процессов === 0 && надзоров === 0 && прогонов === 0) return

  /* Первый процесс называется по имени и со своим местом: отказ обязан говорить,
     ЧТО именно не напечатано, а не «в программе есть конкурентность». */
  const первый = (program.processes ?? [])[0] ?? null
  const что = [
    процессов > 0 ? `процессов ${процессов}` : null,
    надзоров > 0 ? `надзоров ${надзоров}` : null,
    прогонов > 0 ? `прогонов ${прогонов}` : null,
  ].filter((часть) => часть !== null).join(", ")
  throw flangError(
    CONC_UNSUPPORTED_CODE,
    `у цели «${цель}» нет планировщика конкурентности, а в программе объявлена конкурентность (${что})` +
      (первый?.name === undefined ? "" : `, первый — процесс «${первый.name}»`) +
      `. Напечатать процессы в «${цель}» нечем: обработчик стал бы обычной функцией, которую никто не зовёт, ` +
      `и программа собралась бы, делая не то, что написано. Цели с планировщиком: ` +
      `${ЦЕЛИ_С_ПЛАНИРОВЩИКОМ.join(", ")}`,
    первый?.span,
  )
}

/**
 * Отказ печати, если в программе есть `поручить`, а у цели нет хозяина.
 *
 * Вторая половина того же сторожа, что `требуетПланировщика`, и заведена по той
 * же улике: молчаливая потеря — худший исход, потому что выглядит успехом.
 * Elixir и JavaScript печатают процессы честно, а `поручить` в их планировщиках
 * не значится вовсе (`emit/elixir/flang_conc.ex`, `emit/js/flang_conc.js`
 * перечисляют известные действия списком) — то есть напечатанная программа
 * собралась бы, дошла до поручения и упала бы на «неизвестном действии» уже в
 * бою. Отказ печати говорит об этом там, где это ещё можно изменить.
 *
 * Считается по ТЕКСТУ программы, а не по словарю: словарь из семи действий
 * приписывается только той программе, где `поручить` написано, поэтому вопрос
 * «выдаёт ли эта программа поручения» решается наличием варианта в дереве.
 *
 * @param {object} program AST flang
 * @param {string} цель идентификатор цели печати (имя модуля в `src/emit`)
 * @throws {Error} с кодом `FLANG_IO_UNSUPPORTED`, если исполнять поручение нечем
 */
export function требуетХозяина(program, цель) {
  if (ЦЕЛИ_С_ХОЗЯИНОМ.includes(цель)) return
  const где = гдеПоручение(program)
  if (где === null) return
  throw flangError(
    IO_UNSUPPORTED_CODE,
    `у цели «${цель}» нет хозяина ввода-вывода, а процесс «${где.процесс ?? "?"}» выдаёт поручение ` +
      `(функция «${где.функция}»). Поручение ОПИСЫВАЕТСЯ языком, а исполняет его хозяин — среда, ` +
      `в которую напечатан модуль; у этой цели такой среды нет, и напечатанная программа дошла бы ` +
      `до поручения и упала на неизвестном действии. Цели с хозяином: ${ЦЕЛИ_С_ХОЗЯИНОМ.join(", ")}`,
    где.span ?? null,
  )
}

/**
 * Первое место в программе, где строится `поручить`, — с именем функции и
 * процессом, чей обработчик до него дотягивается.
 *
 * Процесс ищется по прямому обработчику, а не по замыканию вызовов: диагностика
 * печати обязана назвать место, а не построить анализ, — и точный ответ на
 * «какой процесс виноват» уже есть у `failures.mjs`. Не нашли процесса — говорим
 * про функцию, и это всё равно точнее, чем «в программе есть поручение».
 */
function гдеПоручение(program) {
  const функции = Array.isArray(program?.functions) ? program.functions : []
  for (const фн of функции) {
    const место = найтиПоручение(фн?.body ?? null)
    if (место === null) continue
    const процесс = (program?.processes ?? []).find((узел) => узел?.handler === фн?.name)
    return { функция: фн?.name ?? "?", процесс: процесс?.name ?? null, span: место.span ?? фн?.span ?? null }
  }
  return null
}

function найтиПоручение(узел) {
  if (Array.isArray(узел)) {
    for (const элемент of узел) {
      const найдено = найтиПоручение(элемент)
      if (найдено !== null) return найдено
    }
    return null
  }
  if (узел === null || typeof узел !== "object") return null
  if (узел.kind === "construct" && узел.variant === ORDER_ACTION) return узел
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span" || ключ === "meta") continue
    if (значение !== null && typeof значение === "object") {
      const найдено = найтиПоручение(значение)
      if (найдено !== null) return найдено
    }
  }
  return null
}

/**
 * Прогон программы: процессы, ящики, виртуальное время, семя.
 *
 * @param {object} program AST с полями `processes` и `supervisors`
 * @param {object} run узел `{ kind: "run", seed, inbox, expected }`
 * @param {{maxTurns?: number}} options
 * @returns {{
 *   журнал: object[], состояния: object, исход: string, время: number,
 *   пробегов: number, отказы: object[], живые: string[], решения: object[],
 *   наверх: object|null
 * }}
 *   `журнал` — журнал доставок: по записи на каждый пробег обработчика, в том
 *   порядке, в каком пробеги случились. Это и есть чередование, и именно его
 *   обязано воспроизвести одно и то же семя. `исход` — «покой» (работы больше
 *   нет), «предел пробегов» (её слишком много) или «отказ дошёл доверху»
 *   (надзор передал отказ выше, а выше никого); зависания нет ни в одном
 *   случае. `решения` — что именно надзор сделал и когда: по записи на каждый
 *   затронутый процесс, в порядке принятия.
 */
export function runConcurrent(program, run, options = {}) {
  const maxTurns = options.maxTurns ?? DEFAULT_MAX_TURNS
  const maxProcesses = options.maxProcesses ?? DEFAULT_MAX_PROCESSES
  /* Горячая замена под работающим планировщиком (шаг Е1 карты). Запрос —
     `{ после, процесс, проверить }`; собирает такой запрос `замена()` из
     `hotswap.mjs`, и оттуда же приезжает `проверить`.
     Проверялка ПОДАЁТСЯ, а не импортируется, и это не вкус: `parser.mjs` и
     `types.mjs` импортируют этот файл, а `hotswap.mjs` импортирует их — значит
     импорт отсюда в обратную сторону замкнул бы круг. Планировщику про замену
     и не надо знать ничего, кроме трёх вещей: КОГДА спросить, У КОГО спросить и
     что делать с ответом. */
  const запросыЗамен = Array.isArray(options.замены) ? [...options.замены] : []
  /* Вытеснение по витку (шаг В2 карты). По умолчанию его НЕТ, и это не
     осторожность: без кванта планировщик обязан вести себя ровно так, как вёл
     до В2, иначе побайтовая сверка напечатанного C с эталоном перестала бы
     что-либо значить. Квант включается запросом и только им. */
  const квант = Number.isInteger(options.квант) && options.квант > 0 ? options.квант : null
  /* ПОТОЛОК ЗАДЕРЖКИ (шаг В4 карты). Квант сам по себе его не даёт: снятый
     пробег начинается заново с вдвое бо́льшим квантом, значит последняя попытка
     идёт от начала до конца и стоит ровно столько же, сколько стоила бы без
     всякого вытеснения (В2, и это прибито отдельной проверкой). `доигрывать`
     меняет ровно одно: снятый пробег НЕ переигрывается, а ДОИГРЫВАЕТСЯ с того
     витка, на котором его сняли. Отсюда потолок: ни один пробег не длиннее
     кванта — не «в среднем», а ни один.

     Возможно это потому, что вычислитель — цикл над явным стеком кадров
     (`interpret.mjs`, шапка), а не рекурсия по стеку JS. «Сохранить стек
     пробега» здесь означает не завести сопрограмму за 278 нс на переключение и
     290 байт на виток глубины (замер В1), а не выбрасывать объект машины,
     который и так уже существует. Цену этой сделки надо назвать, а не
     умолчать: платится ПАМЯТЬЮ — незавершённый пробег держит свой стек кадров,
     пока не доиграет, — и меряется она отдельной проверкой.

     По умолчанию выключено, как и сам квант: без него планировщик обязан вести
     себя ровно так, как вёл, иначе побайтовая сверка напечатанного C с эталоном
     перестала бы что-либо значить. */
  const доигрывать = options.доигрывать === true && квант !== null
  /* Хозяин (седьмое действие). ПОДАЁТСЯ, а не берётся: файлы, часы и сеть живут
     в среде, а этот модуль не импортирует из Node ни одной строки — то же
     правило, по которому устроен `runPlan` (`io.mjs`), и ровно то, чем чистота
     языка измеряется. Хозяина не подали — поручение отвечает названным сбоем, и
     прогон остаётся детерминированным; именно поэтому прогон, объявленный в
     исходнике, годится в эталон для побайтовой сверки с напечатанным C.
     Функция ОБЯЗАНА быть синхронной: планировщик синхронен весь, и сделать его
     асинхронным ради поручения значило бы переписать всех, кто его зовёт, —
     включая побайтовую сверку. Цена названа: сетевое поручение синхронному
     хозяину не даётся, и хозяин отвечает на него сбоем, а не ждёт. */
  const исполнить = typeof options.исполнить === "function" ? options.исполнить : null
  const declared = Array.isArray(program?.processes) ? program.processes : []
  if (declared.length === 0) {
    throw flangError("FLANG_PROCESS", "в программе нет ни одного процесса: прогонять нечего", run?.span)
  }

  /* Программа, рантайм и множество тотальных — не константы прогона, а его
     ТЕКУЩЕЕ состояние: горячая замена меняет все три разом. Дерево надзора и
     список процессов в этот перечень не входят, и замена их не трогает
     (`hotswap.mjs` отвергает такую замену поимённо). */
  let программаСейчас = program
  let runtime = createRuntime(программаСейчас, { maxSteps: TOTAL_HANDLER_STEPS, maxDepth: TOTAL_HANDLER_DEPTH })
  let totals = new Set(
    (программаСейчас.functions ?? []).filter((fn) => fn?.total === true).map((fn) => fn.name),
  )

  /* Порядок объявления — единственный порядок, в котором процессы перечисляются
     где бы то ни было: очередь готовых, итоговые состояния, отчёт о прогоне.
     Один порядок на всё — условие того, чтобы журнал зависел от семени и больше
     ни от чего. Поэтому список, а не перебор объекта: порядок ключей объекта
     задан спецификацией JS, но повторить его в рантайме C будет нечем.

     С шага Б1 список РАСТЁТ: `породить` дописывает имя в конец, и порядок
     объявления продлевается порядком рождения. Продлевается, а не
     перемешивается — новый процесс всегда последний, поэтому чередование до его
     рождения не меняется ни на одном семени, и старые прогоны остаются
     побайтово теми же. */
  const порядок = declared.map((узел) => узел.name)
  const процессы = new Map()
  for (const узел of declared) {
    /* Начальное состояние вычисляется РОВНО ОДИН РАЗ. Функция без параметров
       чиста, поэтому пересчёт дал бы то же самое значение; но храня его, мы
       делаем обещание контракта буквальным: перезапуск возвращает не «такое
       же», а то же самое значение, что было при первом запуске. */
    const начальное = завестиНачальное(runtime, узел)
    процессы.set(узел.name, {
      узел,
      начальное,
      состояние: начальное,
      ящик: [],
      /* Отметка «это сообщение уже трогали» — по одной на место в ящике, в том
         же порядке. Ставится там же, где `продолжить` и `отложить` возвращают
         сообщение в ящик, и читается барьером замены: сообщение, начатое одним
         видом кода и доигранное другим, обязано быть НАЗВАНО (`наСередине` в
         отчёте о замене), раз уж помешать этому нечем. Массив, а не пометка на
         самом значении: два одинаковых числа в ящике — два разных места, и
         различить их можно только позицией. */
      начатые: [],
      жив: true,
      причина: null,
      /* Квант этого процесса на СЛЕДУЮЩИЙ пробег. Растёт удвоением, пока пробег
         снимается, и возвращается к объявленному, как только пробег дошёл до
         конца. Ноль означает «вытеснения нет» и в предел не вносится. */
      квант: квант ?? 0,
      /* Незавершённый пробег этого процесса (шаг В4: `доигрывать`). `null` —
         пробега на паузе нет, и это единственное состояние, возможное без
         `доигрывать`. Внутри: машина вычислителя, сообщение, которое она
         обрабатывает, отметка «уже трогали» и запас, с которым пробег начат.
         Запас лежит ЗДЕСЬ, а не берётся заново на каждой дольке: горячая замена
         (Е1) может сменить вид процесса между дольками, а пробег обязан
         доиграть на тех правилах, на которых начат. */
      доигрыш: null,
      /* Потолок ящика (А3). `null` — неограничен, как было до А3. */
      потолок: Number.isInteger(узел.mailbox) && узел.mailbox > 0 ? узел.mailbox : null,
      /* Сколько мест в ящике занято письмами, которые ещё не пришли («через»).
         Место занимается в тот момент, когда действие выполнено, а не когда
         таймер сработал, и это не бухгалтерия ради бухгалтерии: иначе
         переполнение случалось бы вне пробега — в тишине, между процессами, —
         и отказывать было бы некому. Так же считает и BEAM-овская интуиция
         «сообщение в пути уже занято место», только у BEAM места бесконечны. */
      вЛёте: 0,
    })
  }

  /**
   * ГРАНИЦА ХОЗЯИНА: значение, приехавшее в прогон не из программы.
   *
   * Сообщения планировщик не сверяет вовсе, и правильно: тип груза `отправить`
   * сверяется в ИСХОДНИКЕ, по объявлению адресата, — там, где ошибку можно
   * назвать местом. У поручения так нельзя: отклик приносит ХОЗЯИН — среда, в
   * которую напечатан модуль, — а хозяев столько же, сколько целей печати, плюс
   * всякий, кто встроит планировщик в свою программу. Компилятор не видел ни
   * одного из них.
   *
   * Улика, ради которой проверка написана, та же самая, что записана у
   * `входШага` в `io.mjs`: хозяин, вернувший `«Отметка времени» с миллисекунды
   * равным "вчера"`, доводил план до конца и печатал ложь про тип в ответе. У
   * процесса та же ложь ехала бы дальше и тише — она стала бы СОСТОЯНИЕМ, и
   * первый же разбор споткнулся бы о неё через десять пробегов после причины.
   *
   * Сверяется отклик с ОБЪЯВЛЕНИЕМ АДРЕСАТА (`принимает «T»`), а не со словарём
   * ввода-вывода, и это не обход круга модулей, а более сильное утверждение:
   * граница здесь общая — «что приходит извне, обязано подходить объявленному
   * типу входящих», — и она останется верной, если поручение когда-нибудь
   * научится приносить не только «Отклик». Что адресат `поручить` объявляет
   * именно «Отклик», отвечает проверка типов (`types.mjs`), а не этот виток.
   *
   * Чего проверка НЕ делает: не сужает набор вариантов. «Записано» там, где ждали
   * «Прочитано», — работа программы, её ветка разбора. Иначе вместе с ложью
   * исчез бы путь «поручение не удалось», ради которого отказ хозяина и сделан
   * ОТКЛИКОМ, а не исключением.
   *
   * Отказ здесь — исключение, а не отклик, и это не противоречие: «поручение не
   * удалось» — событие модели, «хозяин вернул не то» — дефект среды. Поэтому
   * этого кода нет и не должно быть в множестве достижимых отказов процесса
   * (`failures.mjs`): множество считается при исправном хозяине ровно так же,
   * как при исправном вычислителе.
   */
  const суммы = new Map(
    (Array.isArray(program?.types) ? program.types : [])
      .filter((тип) => тип?.kind === "sum" && typeof тип.name === "string")
      .map((тип) => [тип.name, тип]),
  )
  const границаХозяина = (значение, поручение, кому) => {
    const чьё = `«${поручение?.variant ?? "?"}»`
    const ожидается = процессы.get(кому)?.узел?.accepts
    const сумма = typeof ожидается === "string" ? суммы.get(ожидается) : undefined
    /* Адресата нет или его тип не сумма — сверять нечем, и молчание здесь то же
       самое, каким `checkValue` отвечает на `unknown`: про это уже сказала
       проверка типов, и второй раз незачем. Отклик всё равно попадёт в
       `поручения`, а положить его будет некуда. */
    if (сумма === undefined) return значение
    if (!isVariant(значение)) {
      throw flangError(
        "FLANG_IO",
        `хозяин вернул не вариант «${ожидается}» на поручение ${чьё} процессу «${кому}»`,
        run?.span,
      )
    }
    const объявлен = сумма.variants.find((в) => в.name === значение.variant)
    if (объявлен === undefined) {
      throw flangError(
        "FLANG_IO",
        `хозяин вернул «${значение.variant}» на поручение ${чьё}, а процесс «${кому}» принимает ` +
          `«${ожидается}»: такого варианта в этой сумме нет`,
        run?.span,
      )
    }
    for (const поле of объявлен.fields ?? []) {
      const есть = (значение.fields ?? {})[поле.name]
      if (есть === undefined) {
        throw flangError(
          "FLANG_IO",
          `отклик «${значение.variant}» хозяина на поручение ${чьё} не несёт поля «${поле.name}»`,
          run?.span,
        )
      }
      const беда = поле.type?.kind === "string" && typeof есть !== "string" ? "строка"
        : поле.type?.kind === "number" && typeof есть !== "number" ? "число"
        : null
      if (беда !== null) {
        throw flangError(
          "FLANG_IO",
          `поле «${поле.name}» отклика «${значение.variant}» хозяина на поручение ${чьё}: ожидалось ${беда}`,
          run?.span,
        )
      }
    }
    return значение
  }

  const журнал = []
  const отказы = []
  /* Что было поручено и что на это ответили — ОТДЕЛЬНЫМ полем итога, а не
     записью в журнале доставок. Довод тот же, которым стали полями `витки` и
     `замены`: журнал сверяется с напечатанным C побайтово, и новое поле в нём
     развалило бы 2400 совпадений на ровном месте. Список тот же по смыслу, что
     `журнал` у `runPlan` (`io.mjs`), и назван так же — чтобы прогон плана и
     прогон процессов сравнивались напрямую. */
  const поручения = []
  /* Что вышло у каждой замены — не запись в журнале доставок, а отдельное поле
     итога, ровно по тому же доводу, по которому им стали `витки` в В2: журнал
     сверяется с напечатанным C побайтово, а горячей замены у напечатанного C нет
     и не будет (`conc/SPEC.md`, «Чего у нас не будет»). Запись в журнале
     развалила бы 2400 совпадений на ровном месте. */
  const замены = []
  let время = 0
  let пробегов = 0
  /* Витки каждого пробега по порядку и число вытеснений — это НЕ журнал, а
     отдельные поля итога. Разница принципиальная: журнал доставок сверяется с
     напечатанным C побайтово (шаг 6), и запись в нём поля, которого у C нет,
     развалила бы 2400 совпадений на ровном месте. Задержку же мерить нечем без
     витков на пробег, а «короткий обработчик получает свои пробеги» без числа —
     обещание, а не проверка. */
  const витки = []
  /* Сколько кадров стека пробег держит ПОСЛЕ каждого пробега: ноль — пробег
     кончился и не держит ничего, больше нуля — стоит на паузе (В4). Это и есть
     цена потолка задержки, названная счётом: у переигрывания (В2) здесь нули
     всегда, потому что снятый пробег бросается целиком. Отдельное поле итога, а
     не запись в журнале, — по тому же доводу, что и `витки`: журнал сверяется с
     напечатанным C побайтово. */
  const кадров = []
  let вытеснений = 0
  const таймеры = []
  const случайное = makeRandom(run?.seed ?? 0)

  const надзор = построитьНадзор(program, процессы)

  /**
   * Положить сообщение в ящик. Три исхода, и все три названы.
   *
   * `«легло»` — положено. `«некому»` — адресата нет или он мёртв; это НЕ ошибка
   * отправителя, он не обязан знать, что адресат остановился, ровно как в BEAM.
   * `«полон»` — ящик объявлен ограниченным (А3) и в нём нет места: отправитель
   * отказывает, потому что потеря сообщения молча — худший из исходов.
   *
   * Занятость ящика — это лежащие в нём сообщения ПЛЮС письма в пути (`вЛёте`),
   * иначе объявленный потолок не был бы потолком: тысяча таймеров на один
   * процесс переполнила бы ящик на два в тот момент, когда сработала бы, то
   * есть вне всякого пробега.
   *
   * `начатое` — сообщение уже побывало у обработчика и вернулось недоделанным
   * (`продолжить`, `отложить`). Извне так класть нельзя: доставка приносит
   * только нетронутое, и оба места, где отметка ставится, лежат внутри пробега
   * и кладут сообщение в ящик напрямую, мимо этой функции. Отметка едет РЯДОМ с
   * сообщением, место в место, и потому ставится ровно там же, где сообщение
   * ложится, — а на исходах «некому» и «полон» не ставится вовсе, потому что не
   * легло и само сообщение.
   */
  const положить = (имя, сообщение, вПередЯщика, местоЗанято = false, начатое = false) => {
    const процесс = процессы.get(имя)
    if (процесс === undefined || !процесс.жив) return "некому"
    if (!местоЗанято && процесс.потолок !== null &&
        процесс.ящик.length + процесс.вЛёте >= процесс.потолок) {
      return "полон"
    }
    if (вПередЯщика) {
      процесс.ящик.unshift(сообщение)
      процесс.начатые.unshift(начатое)
    } else {
      процесс.ящик.push(сообщение)
      процесс.начатые.push(начатое)
    }
    return "легло"
  }

  for (const запись of run?.inbox ?? []) {
    /* Переполнение «дано» отвергает проверка типов (types.mjs, `checkRuns`):
       сколько сообщений названо, столько и ляжет, и посчитать это можно до
       прогона. Здесь — определённое поведение на НЕРАЗОБРАННОМ AST, ровно по
       тому же доводу, по которому планировщик защищается от круга в надзоре. */
    if (положить(запись.process, reifyValue(запись.message), false) === "полон") {
      throw flangError(
        "FLANG_PROCESS",
        `«дано» переполняет ящик процесса «${запись.process}»: объявлен на ${процессы.get(запись.process).потолок}`,
        run?.span,
      )
    }
  }

  const срокТаймеров = () => (таймеры.length === 0 ? null : Math.min(...таймеры.map((т) => т.время)))

  const выдатьТаймеры = () => {
    /* Порядок при равном сроке — порядок постановки: два таймера на одно и то
       же время не соревнуются, иначе журнал зависел бы от сортировки. */
    for (let i = 0; i < таймеры.length; ) {
      if (таймеры[i].время > время) {
        i += 1
        continue
      }
      const таймер = таймеры.splice(i, 1)[0]
      /* Место в ящике было занято ещё при выполнении «через», поэтому здесь
         оно только освобождается и тут же заполняется: переполниться этот путь
         не может по построению. */
      if (таймер.занято === true) процессы.get(таймер.кому).вЛёте -= 1
      положить(таймер.кому, таймер.что, false, таймер.занято === true)
    }
  }

  /* ── Надзор в действии ──────────────────────────────────────────────────
     Перезапуск возвращает состояние и жизнь, и больше ничего: ящик и таймеры
     принадлежат доставке, а не процессу, и терять их было бы потерей данных
     без нужды (см. шапку файла). */
  const перезапустить = (имя) => {
    const процесс = процессы.get(имя)
    процесс.состояние = процесс.начальное
    процесс.жив = true
    процесс.причина = null
    /* Незавершённый пробег бросается, и бросается ЗДЕСЬ, а не «как-нибудь
       потом»: он считает от состояния, которого после перезапуска больше нет.
       Доиграть его значило бы записать в поднятый процесс итог, посчитанный по
       умершему. Сообщение при этом теряется, и это тот же исход, что у пробега,
       оборвавшегося отказом, — а не новый вид потери. */
    процесс.доигрыш = null
  }

  const остановить = (имя, причина) => {
    const процесс = процессы.get(имя)
    процесс.жив = false
    процесс.причина = причина
    процесс.доигрыш = null
  }

  /* ── Барьер горячей замены ───────────────────────────────────────────────
     Стоит МЕЖДУ пробегами, и единица атомарности у него — ПРОБЕГ, а не
     сообщение. Обработчик чист и возвращает состояние значением: пока пробег не
     вернулся, не изменено ничего, — тот же довод, которым В2 обосновал снятие
     пробега по кванту. Отсюда доказанное: ни один пробег не выполняется
     наполовину старым видом и наполовину новым, а пробег, снятый по кванту,
     брошен целиком, сообщение вернулось в голову ящика нетронутым, и новый вид
     переиграет его от начала.

     ЧЕГО ЗДЕСЬ НЕТ, и раньше стояло. Стояло: «ни одно СООБЩЕНИЕ не
     обрабатывается наполовину старым видом и наполовину новым». Это неправда, и
     опровергнута она счётом, а не рассуждением. Сообщение единицей атомарности
     не является: `продолжить` возвращает его в голову ящика, `отложить` — за
     уже пришедшие, и оба делают это ПОСЛЕ того, как состояние из отклика
     зафиксировано. Значит одно сообщение растягивается на несколько пробегов, а
     барьер стоит между ними. Счёт: одно сообщение, обработчик прибавляет 1 и
     отвечает `продолжить`, замена после двух пробегов прибавляет 100 — выходит
     1 + 1 + 100 = 102, то есть вклад обоих видов в одно сообщение. То же у
     `отложить` (`flang/test/hotswap.test.mjs`).

     Починить это барьером нельзя, и в этом суть. Ждать, пока процесс доиграет
     начатое, значит дать программе с `отложить` не принять замену никогда —
     ровно та беда, ради которой BEAM и держит две версии модуля рядом. Не
     фиксировать состояние на `продолжить` значит отобрать у `продолжить` смысл:
     продолжение — это и есть состояние из отклика (см. шапку файла). Поэтому
     свойство не восстановлено, а вычеркнуто, и вместо него барьер НАЗЫВАЕТ
     случай: `наСередине` в отчёте о замене говорит, что в ящике процесса лежало
     сообщение, которое старый вид уже трогал. Обещания нет — есть отметка, и её
     можно проверить.

     Что от прежнего вывода осталось: две версии кода рядом нам всё так же не
     нужны, но довод теперь другой и слабее. Не «сообщение цело», а «пробег
     цел»: начавшийся пробег не обязан дочитываться в старом виде, потому что он
     ничего не менял, — а вот начатое СООБЩЕНИЕ мы честно делим. */
  const применитьЗамены = () => {
    while (запросыЗамен.length > 0 && (запросыЗамен[0].после ?? 0) <= пробегов) {
      /* Пробег на паузе (В4) отодвигает барьер, а не проходит сквозь него.
         Иначе замена записала бы процессу перенесённое состояние, а доигравший
         пробег тут же затёр бы его тем, что посчитал по СТАРОМУ, — то есть
         «замена атомарна» перестало бы быть правдой.
         Ждать здесь можно, а на `отложить` было нельзя, и разница не в
         аккуратности, а в счёте: доигрыш кончается не позже чем через
         ⌈запас / квант⌉ пробегов, потому что витки его копятся и упираются в
         запас. У `отложить` такой границы нет вовсе — программа вправе
         откладывать вечно, — и потому там ожидание значило бы «никогда». */
      const ждёт = процессы.get(запросыЗамен[0].процесс)
      if (ждёт !== undefined && ждёт.доигрыш !== null) break
      const запрос = запросыЗамен.shift()
      const процесс = процессы.get(запрос.процесс)
      if (процесс === undefined) {
        замены.push({
          пробег: пробегов,
          процесс: запрос.процесс,
          принято: false,
          наСередине: false,
          оценка: null,
          перенос: null,
          программа: null,
          диагностики: [{
            code: ЗАМЕНА_НЕ_ЛЕГЛА,
            message: `процесса «${запрос.процесс}» в прогоне нет: менять нечего`,
            severity: "error",
            span: null,
          }],
        })
        continue
      }

      /* Проверялке отдаётся ТЕКУЩЕЕ состояние процесса — то самое накопленное,
         ради которого замена и называется горячей. По нему же считается цена
         переноса: он зовётся один раз и ровно на этом значении. */
      const итог = запрос.проверить(программаСейчас, запрос.процесс, процесс.состояние)
      замены.push({
        пробег: пробегов,
        процесс: запрос.процесс,
        принято: итог?.принято === true,
        /* Единственное честное слово о том свойстве, которого нет: в ящике
           лежит сообщение, которое старый вид уже трогал (`продолжить`,
           `отложить`), значит доиграет его новый. Отметка стоит РЯДОМ с
           «принято», а не в диагностике: это не отказ и не предупреждение
           проверки, а факт о прогоне. */
        наСередине: процесс.начатые.some(Boolean),
        оценка: итог?.оценка ?? null,
        перенос: итог?.перенос ?? null,
        программа: итог?.программа ?? null,
        диагностики: итог?.диагностики ?? [],
      })
      if (итог?.принято !== true) continue

      программаСейчас = итог.программа
      runtime = createRuntime(программаСейчас, { maxSteps: TOTAL_HANDLER_STEPS, maxDepth: TOTAL_HANDLER_DEPTH })
      totals = new Set(
        (программаСейчас.functions ?? []).filter((fn) => fn?.total === true).map((fn) => fn.name),
      )
      процесс.узел = итог.узел ?? процесс.узел
      if (итог.состояние !== undefined) процесс.состояние = итог.состояние
      /* Начальное состояние ПЕРЕСЧИТЫВАЕТСЯ, и забыть это нельзя. Оно вычислено
         один раз на прогон, потому что контракт требует от перезапуска не
         «такого же» значения, а того же самого; но замена, сменившая вид
         состояния, сменила и «начинает с», и старое вычисленное начальное после
         неё — мусор чужого вида. Надзор поднял бы процесс в том виде, которого
         в программе больше нет, и увидеть это можно только на отказе. */
      процесс.начальное = завестиНачальное(runtime, процесс.узел)
      /* Квант НЕ сбрасывается. Он растёт удвоением ради прогресса (В2), и
         поток замен, сбрасывающий его к объявленному, мог бы держать пробег от
         завершения сколь угодно долго. */
    }
  }

  const суд = надзорВДействии(надзор, { перезапустить, остановить })
  const решения = суд.решения
  const применитьНадзор = суд.применить

  let исход = "покой"

  for (;;) {
    применитьЗамены()
    выдатьТаймеры()
    const готовые = порядок.filter((имя) => {
      const процесс = процессы.get(имя)
      /* Незавершённый пробег (В4) делает процесс готовым при ПУСТОМ ящике:
         работа у него есть, она просто не в ящике, а на середине. Без этого
         слагаемого прогон объявил бы «покой» при живом недосчитанном пробеге —
         то есть соврал бы исходом. */
      return процесс.жив && (процесс.ящик.length > 0 || процесс.доигрыш !== null)
    })

    if (готовые.length === 0) {
      const срок = срокТаймеров()
      if (срок === null) break
      /* Тишина: скачок сразу к ближайшему сроку. Таймер на пять секунд в
         проверке не ждёт пяти секунд — он ждёт, когда планировщику станет
         нечего делать (контракт, «Воспроизводимость»). */
      время = Math.max(время, срок)
      continue
    }

    if (пробегов >= maxTurns) {
      исход = "предел пробегов"
      break
    }

    /* Единственное место, где решает семя. Всё остальное определено. */
    const имя = готовые[Math.floor(случайное() * готовые.length)]
    const процесс = процессы.get(имя)
    /* Пробег на паузе (В4) продолжается ТЕМ ЖЕ сообщением: из ящика оно ушло
       ещё на первой дольке, и брать оттуда второе значило бы обрабатывать два
       сообщения одним пробегом. */
    const доигрыш = процесс.доигрыш
    const сообщение = доигрыш === null ? процесс.ящик.shift() : доигрыш.сообщение
    const началось = доигрыш === null ? процесс.начатые.shift() === true : доигрыш.началось
    пробегов += 1

    const запись = { время, процесс: имя, сообщение, исход: "обработано" }
    журнал.push(запись)

    const тотальный = totals.has(процесс.узел.handler)
    const запас = доигрыш !== null
      ? доигрыш.запас
      : (тотальный ? TOTAL_HANDLER_STEPS : (процесс.узел.budget ?? TOTAL_HANDLER_STEPS))
    /* Предел этого пробега: запас, а при включённом вытеснении — меньшее из
       запаса и кванта. Именно СЛИЯНИЕ, а не вторая проверка рядом: замер В1
       (`flang/conc/bench.mjs`) назвал цену отдельной ветви в `fl_tick`, а у
       слияния цена ноль — горячий путь остаётся тем же кодом. */
    const предел = квант === null ? запас : Math.min(запас, процесс.квант)

    /* Отказ этого пробега, если он случился: код и текст. Все три вида отказа
       из контракта сходятся сюда — исчерпание запаса, ошибка выполнения и
       явное «остановить» с ненормальной причиной, — чтобы дальше их обрабатывал
       один кусок кода. Три разных пути к надзору означали бы три разных
       поведения надзора, и они бы разошлись. */
    let отказ = null
    let отклик = null
    let снят = false
    const отчёт = { витки: 0 }

    try {
      if (доигрывать) {
        /* Потолок задержки (В4). Пробег живёт машиной вычислителя, и машина эта
           переживает границу пробега: сняли на витке q — доиграем с витка q+1,
           а не с первого. Отсюда и потолок: `витков` — жёсткий, а не средний.

           Машина держит свой `rt`, поэтому `доиграть` зовётся у ТЕКУЩЕГО
           планировщика, а считает по тому виду кода, которым пробег начат.
           Горячей замене (Е1) это ничего не ломает: начатый пробег доигрывает
           старым видом целиком, то есть барьер «пробег не бывает наполовину
           старым, наполовину новым» становится СТРОЖЕ, а не слабее. */
        const машина = доигрыш === null
          ? runtime.начать(процесс.узел.handler, [процесс.состояние, сообщение], { maxSteps: запас })
          : доигрыш.машина
        const итог = runtime.доиграть(машина, { витков: квант, отчёт })
        if (итог.готово) {
          процесс.доигрыш = null
          отклик = итог.значение
        } else {
          процесс.доигрыш = { машина, сообщение, началось, запас }
          снят = true
        }
      } else {
        отклик = runtime.call(процесс.узел.handler, [процесс.состояние, сообщение],
                              { maxSteps: предел, отчёт })
      }
    } catch (ошибка) {
      /* Пробег, который упал, доигрывать нечего: машина его умерла вместе с
         ним. Снимается отметка ДО разбора кода — иначе отказ, случившийся на
         третьей дольке, оставил бы процесс вечно «готовым». */
      процесс.доигрыш = null
      const код = кодОшибки(ошибка)
      /* Три разных смысла у одного и того же FLANG_RECURSION_LIMIT, и различить
         их можно только по тому, ЧЕЙ предел сработал:
           • сработал квант (он меньше запаса) — это вытеснение, а не отказ;
           • сработал объявленный запас у нетотального — «запас исчерпан»;
           • сработал предел планировщика у тотального — тот самый отказ, о
             котором говорит шаг В3: тотальность обещала завершение, но не срок.
         В режиме `доигрывать` первого смысла здесь нет вовсе: снятие по кванту
         приходит не исключением, а ответом `{ готово: false }`, — и это не
         мелочь, а ровно то, чем потолок отличается от переигрывания. */
      if (!доигрывать && квант !== null && код === "FLANG_RECURSION_LIMIT" && предел < запас) {
        снят = true
      } else {
        const бюджет = код === "FLANG_RECURSION_LIMIT" && !тотальный
        отказ = { код: бюджет ? "FLANG_BUDGET_EXHAUSTED" : код, сообщение: текстОшибки(ошибка) }
        запись.исход = бюджет ? "запас исчерпан" : "отказ"
      }
    }
    витки.push(отчёт.витки)
    кадров.push(отчёт.кадров ?? 0)

    if (снят) {
      /* Вытеснение целиком: сообщение возвращается в ГОЛОВУ ящика, состояние не
         тронуто, и пробег начнётся заново — с вдвое большим квантом.
         Почему это законно и почему у BEAM так нельзя. Обработчик flang чист и
         возвращает новое состояние значением: пока он не вернулся, не изменено
         ничего, и брошенный на середине пробег не оставляет половины изменения.
         Значит сохранять его стек незачем — достаточно бросить и повторить.
         Замер В1 назвал цену того, чего мы этим не платим: стек на процесс
         (шесть с лишним килобайт плюс 291 байт на виток глубины) и переключение
         (279 нс, из них 222 — маска сигналов в `swapcontext`).
         Цена, которую платим взамен, тоже названа и посчитана: попытки идут с
         квантами q, 2q, 4q … 2^k·q, снимаются все, кроме последней, и брошено
         оказывается меньше двух истинных цен пробега, а сделано всего — меньше
         трёх. Прогресс гарантирован: квант растёт до запаса, а на запасе пробег
         либо кончается, либо честно отказывает.
         И чего это НЕ даёт, чтобы не пришлось выяснять потом: потолка задержки.
         Последняя попытка не снимается ни разу и стоит ровно столько же, сколько
         стоил бы пробег без вытеснения. Потолок даёт ограниченность (В3), а не
         это. */
      /* Отметка «уже трогали» возвращается ТОЙ ЖЕ, какой пришла, а не ставится
         заново: снятый по кванту пробег не изменил ничего, значит сообщение он и
         не начинал. Ровно это отличает вытеснение от `продолжить` — и ровно на
         этом отличии держится единственное, что барьер замены ещё обещает. */
      /* А при `доигрывать` (В4) не делается ни того, ни другого: сообщение НЕ
         возвращается в ящик — оно у пробега, который стоит на паузе, — и квант
         НЕ удваивается, потому что удвоение было ценой переигрывания, а
         переигрывания больше нет. Ровно из этих двух «не» и складывается
         потолок задержки. */
      if (!доигрывать) {
        процесс.ящик.unshift(сообщение)
        процесс.начатые.unshift(началось)
        процесс.квант = Math.min(процесс.квант * 2, запас)
      }
      запись.исход = "снято по кванту"
      вытеснений += 1
      время += 1
      continue
    }
    /* Пробег дошёл до конца — следующему сообщению квант выдаётся заново. */
    процесс.квант = квант ?? 0

    if (отказ === null) {
      const беда = разобратьОтклик(отклик, процесс.узел)
      if (беда !== null) {
        отказ = { код: "FLANG_PROCESS", сообщение: беда }
        запись.исход = "отказ"
      }
    }

    if (отказ === null) {
      процесс.состояние = отклик[RESPONSE_STATE]
      /* Пробег обработчика стоит единицу виртуального времени. В контракте этого
         не было: там время шло только в тишине. Без этого правила таймер не
         сработал бы никогда в программе, которой всё время есть чем заняться, —
         например, в той, что откладывает сообщения по кругу: готовые есть всегда,
         тишины не наступает, и «через 5000» означало бы «никогда». */
      время += 1

      /* Переполнение ящика — отказ ОТПРАВИТЕЛЯ, и он ставится ровно так же, как
         отказ от «остановить» с ненормальной причиной: первый выигрывает,
         остальные действия отклика доигрываются. Разного поведения у двух
         отказов внутри одного списка действий быть не должно — иначе порядок
         действий начал бы решать, каким кодом упадёт процесс. */
      const сорвался = (код, сообщение) => {
        if (отказ !== null) return
        отказ = { код, сообщение }
        запись.исход = "отказ"
        процесс.жив = false
        процесс.причина = код
      }

      const переполнил = (кому) => {
        сорвался(
          MAILBOX_FULL_CODE,
          `ящик процесса «${кому}» полон: объявлен на ${процессы.get(кому).потолок}`,
        )
      }

      /**
       * Завести экземпляр объявленного вида (шаг Б1).
       *
       * Порядок проверок здесь — часть наблюдаемого поведения, потому что от
       * него зависит КОД отказа, а код уходит в журнал: «вида нет», «имя
       * пустое», «упёрлись в предел», «имя занято». Тот же порядок в
       * напечатанном C (`fl_conc_spawn`), и это не совпадение, а условие
       * побайтовой сверки.
       */
      const породить = (видИмя, имяНового, первое) => {
        const образец = процессы.get(видИмя)
        if (образец === undefined || образец.порождён === true) {
          сорвался("FLANG_PROCESS", `породить нечего: вида «${видИмя}» среди объявленных процессов нет`)
          return
        }
        if (имяНового === "") {
          сорвался(BAD_NAME_CODE, "имя порождённого процесса пусто, а адресоваться к пустому имени нечем")
          return
        }
        if (имяНового.includes("\u0000")) {
          сорвался(
            BAD_NAME_CODE,
            "в имени порождённого процесса нулевой байт: имя процесса — адрес, " +
              "и адрес обязан быть строкой без дыр",
          )
          return
        }
        if (порядок.length >= maxProcesses) {
          сорвался(
            PROCESS_LIMIT_CODE,
            `предел числа процессов: объявлено и порождено ${порядок.length} при пределе ${maxProcesses}`,
          )
          return
        }
        if (процессы.has(имяНового)) {
          сорвался(NAME_TAKEN_CODE, `имя «${имяНового}» уже занято процессом`)
          return
        }
        /* Экземпляр берёт у вида ВСЁ, кроме имени: узел (а значит обработчик,
           запас витков и объявленный ящик) и вычисленное начальное состояние —
           то же самое значение, а не пересчитанное. */
        процессы.set(имяНового, {
          узел: образец.узел,
          начальное: образец.начальное,
          состояние: образец.начальное,
          ящик: [],
          начатые: [],
          жив: true,
          причина: null,
          квант: квант ?? 0,
          доигрыш: null,
          потолок: образец.потолок,
          вЛёте: 0,
          порождён: true,
        })
        порядок.push(имяНового)
        /* Надзор наследуется у вида (шаг Б2): дерево объявлено данными, и
           объявление одно на вид. Приписывать экземпляру свой надзор значило бы
           завести второе место правды об одном и том же. */
        const связь = надзор.надПроцессом.get(видИмя)
        if (связь !== undefined) надзор.надПроцессом.set(имяНового, связь)
        /* Первое сообщение кладётся тем же путём, что всякое другое: без него
           процесс не побежит никогда — обработчик зовётся на сообщение. */
        if (положить(имяНового, первое, false) === "полон") переполнил(имяНового)
      }

      for (const действие of отклик[RESPONSE_ACTIONS]) {
        const вид = действие?.variant
        if (вид === "отправить") {
          const кому = String(действие.fields["кому"])
          if (положить(кому, действие.fields["что"], false) === "полон") переполнил(кому)
          continue
        }
        if (вид === ORDER_ACTION) {
          /* Поручение исполняется ЗДЕСЬ, на месте выполнения действия, и отклик
             ложится в ящик названного адресата обычным сообщением — тем же
             `положить`, каким ложится всё остальное. Отсюда три следствия, и
             все три названы:
               • отказ адресата с полным ящиком — отказ ТОГО, КТО ПОРУЧИЛ, ровно
                 как у `отправить`: он попросил принести отклик, а принести его
                 некуда, и решает это надзор над ним. Нового вида отказа
                 поручение не заводит — оно пользуется пятым;
               • мёртвый или необъявленный адресат («некому») отказом не
                 является. Отклик пропадает так же, как пропадает отправка
                 мёртвому, и это не молчаливая потеря: поручение всё равно
                 записано в `поручения`;
               • пробег на время исполнения поручения СТОИТ: хозяин синхронен,
                 и медленное поручение держит планировщик. Цена та же, что у
                 длинного обработчика (контракт, «Цена, которую платим»), и
                 названа по той же причине — молчать о ней было бы обманом. */
          const кому = String(действие.fields["кому"])
          const поручение = действие.fields["поручение"]
          const отклик = исполнить === null
            ? variant(HOST_FAILURE_VARIANT, {
              [HOST_FAILURE_FIELDS[0]]: NO_HOST_CODE,
              [HOST_FAILURE_FIELDS[1]]: NO_HOST_TEXT,
            })
            : границаХозяина(reifyValue(исполнить(поручение)), поручение, кому)
          поручения.push({ процесс: имя, кому, поручение, отклик })
          if (положить(кому, отклик, false) === "полон") переполнил(кому)
          continue
        }
        if (вид === "через") {
          const кому = String(действие.fields["кому"])
          const адресат = процессы.get(кому)
          /* Место занимается СЕЙЧАС, а не когда таймер сработает. Живость
             адресата при этом не смотрится вовсе, и это нарочно: мёртвый
             процесс может быть поднят надзором раньше срока письма, и тогда
             незанятое место дало бы ящику переполниться мимо потолка. Письмо
             мёртвому пропадёт в свой срок — так же, как пропадает отправка. */
          const занято = адресат !== undefined && адресат.потолок !== null
          if (занято && адресат.ящик.length + адресат.вЛёте >= адресат.потолок) {
            переполнил(кому)
            continue
          }
          if (занято) адресат.вЛёте += 1
          таймеры.push({
            время: время + Number(действие.fields["задержка"]),
            кому,
            что: действие.fields["что"],
            занято,
          })
          continue
        }
        if (вид === "отложить") {
          /* За уже пришедшие, а не в голову: цена откладывания обязана быть
             видимой, иначе выборочный приём вернулся бы через заднюю дверь.
             Отметка «НАЧАТО» — потому что состояние из отклика уже записано
             строкой выше: это сообщение старый вид уже трогал, и доиграет его
             тот вид, который будет стоять, когда очередь дойдёт снова. */
          процесс.ящик.push(сообщение)
          процесс.начатые.push(true)
          запись.исход = "отложено"
          continue
        }
        if (вид === "продолжить") {
          процесс.ящик.unshift(сообщение)
          процесс.начатые.unshift(true)
          запись.исход = "продолжено"
          continue
        }
        if (вид === SPAWN_ACTION) {
          породить(
            String(действие.fields["вид"]),
            String(действие.fields["имя"]),
            действие.fields["что"],
          )
          continue
        }
        if (вид === "остановить") {
          const почему = String(действие.fields["почему"])
          процесс.жив = false
          процесс.причина = почему
          /* Нормальная остановка — не отказ, надзор о ней не узнаёт. Любая
             другая причина — отказ (контракт, «Отказ, надзор, перезапуск»). */
          if (почему === NORMAL_STOP) {
            запись.исход = "остановлено"
          } else {
            отказ = { код: STOPPED_CODE, сообщение: почему }
            запись.исход = "отказ"
          }
          continue
        }
      }
    } else {
      /* Пробег, кончившийся отказом, всё равно был пробегом: время идёт и
         здесь. Иначе окно порога отказов не двигалось бы у процесса, который
         только и делает, что падает, — и «три отказа за 5000 миллисекунд»
         означало бы «три отказа за всю жизнь». */
      время += 1
      процесс.жив = false
      процесс.причина = отказ.код
    }

    if (отказ !== null) {
      запись.код = отказ.код
      запись.сообщениеОбОшибке = отказ.сообщение
      отказы.push({ процесс: имя, код: отказ.код, сообщение: отказ.сообщение, время: запись.время })
      const было = решения.length
      const итог = применитьНадзор(имя, отказ.код, запись.время)
      запись.решения = решения.slice(было).map((р) => ({ процесс: р.процесс, надзор: р.надзор, стратегия: р.стратегия }))
      if (итог.доверху) {
        /* Отказ дошёл доверху: останавливается вся программа. Это исход, а не
           зависание, и он назван — иначе прогон отличал бы «надзор не справился»
           от «работа кончилась» только по итоговым состояниям. */
        исход = "отказ дошёл доверху"
        for (const кого of порядок) {
          if (процессы.get(кого).жив) остановить(кого, "программа остановлена: отказ дошёл доверху")
        }
        break
      }
    }
  }

  /* Замена, до которой очередь не дошла, — не пропуск, а отказ с названной
     причиной. Иначе `после: 99` в прогоне на четыре пробега молча ничего не
     делал бы, и проверка вокруг него зеленела бы, ничего не проверяя. */
  for (const запрос of запросыЗамен) {
    замены.push({
      пробег: null,
      процесс: запрос.процесс,
      принято: false,
      оценка: null,
      перенос: null,
      программа: null,
      диагностики: [{
        code: ЗАМЕНА_НЕ_ЛЕГЛА,
        message: `замена процесса «${запрос.процесс}» назначена после ${запрос.после ?? 0} пробегов, ` +
          `а прогон кончился на ${пробегов}: не легла`,
        severity: "error",
        span: null,
      }],
    })
  }

  const состояния = {}
  for (const имя of порядок) состояния[имя] = процессы.get(имя).состояние
  const живые = порядок.filter((имя) => процессы.get(имя).жив)

  return {
    журнал, состояния, исход, время, пробегов, отказы, живые, решения, наверх: суд.наверх(),
    витки, кадров, вытеснений, замены, поручения,
  }
}

/**
 * Дерево надзора: кто над кем и кого поднимать при перезапуске поддерева.
 *
 * Строится один раз на прогон и дальше только читается. Отдельной функцией — не
 * ради красоты: планировщик в рантайме C (шаг 6) обязан получить то же дерево из
 * того же AST, и место, где оно строится, должно быть одно и называться.
 */
export function построитьНадзор(program, процессы) {
  const объявленные = Array.isArray(program?.supervisors) ? program.supervisors : []
  const надзоры = new Map()
  const надПроцессом = new Map()
  const надНадзором = new Map()

  for (const узел of объявленные) {
    if (надзоры.has(узел.name)) continue
    надзоры.set(узел.name, { узел, отказы: [] })
  }
  for (const узел of объявленные) {
    for (const запись of узел.watch ?? []) {
      /* Первое объявление выигрывает. Двух надзоров над одним процессом
         проверка типов не пропустит; здесь важно лишь, чтобы на неразобранном
         AST планировщик вёл себя определённо, а не как получится. */
      if (!надПроцессом.has(запись.process)) {
        надПроцессом.set(запись.process, { надзор: узел.name, стратегия: запись.strategy })
      }
    }
    for (const запись of узел.nested ?? []) {
      if (запись.supervisor !== узел.name && !надНадзором.has(запись.supervisor)) {
        надНадзором.set(запись.supervisor, { надзор: узел.name, стратегия: запись.strategy })
      }
    }
  }

  /* Поддерево надзора — процессы в порядке объявления, сначала свои, потом
     чужие через вложенные надзоры. Порядок здесь важен так же, как везде: по
     нему идут записи в журнале решений, а журнал обязан совпадать побайтово. */
  const подопечные = (имя, виденные = new Set()) => {
    if (виденные.has(имя)) return []
    виденные.add(имя)
    const узел = надзоры.get(имя)?.узел
    if (узел === undefined) return []
    const собранные = []
    for (const запись of узел.watch ?? []) {
      if (процессы.has(запись.process) && !собранные.includes(запись.process)) собранные.push(запись.process)
    }
    /* Порождённые (шаг Б2). В `watch` их нет и быть не может — надзор объявлен
       в исходнике, а они завелись на ходу, — поэтому они добавляются здесь, по
       наследованной связи и в порядке рождения. Без этого перезапуск поддерева
       поднимал бы вид и оставлял его экземпляры лежать. Тот же порядок и в
       напечатанном C (`fl_conc_subtree`): сперва объявленные, потом рождённые,
       потом чужие через вложенные надзоры. */
    for (const [имяПроцесса, процесс] of процессы) {
      if (процесс.порождён !== true) continue
      if (надПроцессом.get(имяПроцесса)?.надзор !== имя) continue
      if (!собранные.includes(имяПроцесса)) собранные.push(имяПроцесса)
    }
    for (const запись of узел.nested ?? []) {
      for (const дальше of подопечные(запись.supervisor, виденные)) {
        if (!собранные.includes(дальше)) собранные.push(дальше)
      }
    }
    return собранные
  }

  return { надзоры, надПроцессом, надНадзором, подопечные }
}

/**
 * Надзор в действии: порог, поддерево, «выше» и решения.
 *
 * ── Почему это отдельная функция, а не кусок планировщика ───────────────────
 *
 * До распределённости она была замыканием внутри `runConcurrent`, и это было
 * правильно: надзор действовал в одном-единственном месте. Мест стало два —
 * прогон (`runConcurrent`) и УЗЕЛ (`flang/conc/distributed.mjs`), — а надзор
 * обязан остаться ОДНИМ. Второй экземпляр тех же двадцати строк разошёлся бы с
 * первым на первой же правке порога, и тогда «надзор через границу узла»
 * означал бы не то же самое, что надзор внутри узла. Поэтому вынесено, а не
 * переписано: и прогон, и узел зовут вот этот код, буквально этот.
 *
 * Что подаётся — только два действия над процессом: `перезапустить` и
 * `остановить`. Больше надзору знать не о чем, и в этом всё дело: у прогона
 * «перезапустить» значит «вернуть начальное состояние», у узла — «завести
 * связь заново», а решение принимается одинаково, потому что принимается ЗДЕСЬ.
 *
 * `когда` — единица времени того, кто зовёт: у прогона это пробеги (см.
 * `conc/SPEC.md`, «Что сделано в шаге 3»), у узла — настоящие миллисекунды.
 * Порог считает вычитанием, а не часами, поэтому обе единицы ему годятся —
 * но расхождение это НАЗВАНО в `conc/DISTRIBUTED.md`, а не спрятано.
 *
 * @param {object} надзор дерево из `построитьНадзор`
 * @param {{перезапустить: (имя: string) => void, остановить: (имя: string, причина: string) => void}} действия
 * @returns {{решения: object[], применить: (упавший: string, код: string, когда: number) => {доверху: boolean}, наверх: () => object|null}}
 */
export function надзорВДействии(надзор, { перезапустить, остановить }) {
  const решения = []
  let наверх = null

  /**
   * Порог отказов по времени того, кто зовёт.
   *
   * «N за M миллисекунд» значит: пока отказов в окне не больше N, работает
   * стратегия, названная за процессом; отказ номер N+1 в том же окне уходит на
   * запасную. Окно скользящее: отказы старше `время − M` в счёт не идут, потому
   * что «три отказа за час» и «три отказа за всё время работы» — разные
   * утверждения, и надзор обязан различать их.
   */
  const порог = (узелНадзора, состояниеНадзора, базовая, когда) => {
    const правило = узелНадзора.threshold
    if (правило === null || правило === undefined) return базовая
    состояниеНадзора.отказы = состояниеНадзора.отказы.filter((т) => т > когда - правило.window)
    состояниеНадзора.отказы.push(когда)
    return состояниеНадзора.отказы.length > правило.failures ? правило.otherwise : базовая
  }

  /**
   * Отказ дошёл до надзора: кто решает и что из этого вышло.
   *
   * Возвращает `{ доверху }`: `доверху` значит, что «передать выше» упёрлось в
   * надзор, над которым никого нет, — тогда останавливается вся программа.
   * Решения дописываются в общий журнал `решения`, по записи на каждый
   * затронутый процесс: перезапуск поддерева обязан быть виден поимённо, иначе
   * прогон не смог бы проверить, что вместе с упавшим подняли и соседа.
   */
  const применить = (упавший, код, когда) => {
    let цель = { вид: "процесс", имя: упавший }
    const пройденные = new Set()
    for (;;) {
      const связь = цель.вид === "процесс"
        ? надзор.надПроцессом.get(цель.имя)
        : надзор.надНадзором.get(цель.имя)

      if (связь === undefined) {
        /* Процесс без надзора остаётся остановленным — так было и в шаге 1.
           Надзор, над которым никого нет, — конец программы: отказ обязан
           кончиться исходом, а не тем, что о нём забыли. */
        if (цель.вид === "процесс") return { доверху: false }
        наверх = { процесс: упавший, надзор: цель.имя, код, время: когда }
        return { доверху: true }
      }

      const состояниеНадзора = надзор.надзоры.get(связь.надзор)
      /* Круг в надзоре проверка типов отвергает; здесь — защита на случай, если
         планировщик позвали на неразобранном AST: круг обязан кончиться
         исходом, а не вечным циклом. */
      if (пройденные.has(связь.надзор)) {
        наверх = { процесс: упавший, надзор: связь.надзор, код, время: когда }
        return { доверху: true }
      }
      пройденные.add(связь.надзор)

      const стратегия = порог(состояниеНадзора.узел, состояниеНадзора, связь.стратегия, когда)

      if (стратегия === "передать выше") {
        решения.push({ время: когда, процесс: упавший, надзор: связь.надзор, стратегия, код })
        цель = { вид: "надзор", имя: связь.надзор }
        continue
      }

      const затронутые = цель.вид === "процесс" ? [цель.имя] : надзор.подопечные(цель.имя)
      for (const имяПроцесса of затронутые) {
        решения.push({ время: когда, процесс: имяПроцесса, надзор: связь.надзор, стратегия, код })
        if (стратегия === "перезапустить") перезапустить(имяПроцесса)
        else остановить(имяПроцесса, `остановлен надзором «${связь.надзор}»`)
      }
      return { доверху: false }
    }
  }

  return { решения, применить, наверх: () => наверх }
}

/**
 * Начальное состояние процесса — и что делать, если его вычисление отказало.
 *
 * Отдельной функцией не ради краткости: здесь стояло голое `runtime.call`, и
 * отказ из него уходил НАРУЖУ `runConcurrent`, то есть убивал всю программу, а
 * не процесс. Предъявлено прогоном: `начинает с «нуль»`, где «нуль» берёт
 * девятый элемент трёхэлементного списка, — проверка молчит, анализ отказов
 * молчит (функцию из `начинает с` он не смотрел вовсе), а прогон бросает
 * `FLANG_BUILTIN_ARGS` мимо надзора.
 *
 * Закрыто с двух сторон. Со стороны проверки — `failures.mjs` теперь считает и
 * замыкание `начинает с`, и `types.mjs` отвергает программу, чьё начальное
 * состояние может отказать (`FLANG_INITIAL_FAILURE`): надзор такому процессу не
 * поможет, потому что перезапуск возвращает ТО ЖЕ вычисленное значение, а его
 * нет. Со стороны прогона — вот это место: отказ остаётся отказом ПРОГРАММЫ (и
 * это правильно: процесса ещё не существует, надзирать не над кем), но теперь он
 * назван, а не приходит анонимным исключением из чужого модуля.
 */
export function завестиНачальное(runtime, узел) {
  try {
    return runtime.call(узел.initial, [])
  } catch (ошибка) {
    throw flangError(
      "FLANG_PROCESS",
      `начальное состояние «${узел.initial}» процесса «${узел.name}» отказало ` +
        `(${кодОшибки(ошибка)}): ${текстОшибки(ошибка)}. Процесса ещё нет, надзирать не над кем — ` +
        `это отказ программы, а не процесса, и проверка обязана была его отвергнуть`,
      узел.span ?? null,
    )
  }
}

/** Отклик обязан быть записью из нового состояния и списка действий. */
export function разобратьОтклик(отклик, узел) {
  if (отклик === null || typeof отклик !== "object" || Array.isArray(отклик)) {
    return `обработчик «${узел.handler}» вернул не запись отклика`
  }
  if (!Object.hasOwn(отклик, RESPONSE_STATE)) {
    return `отклик обработчика «${узел.handler}» не содержит поле «${RESPONSE_STATE}»`
  }
  if (!Array.isArray(отклик[RESPONSE_ACTIONS])) {
    return `поле «${RESPONSE_ACTIONS}» отклика обработчика «${узел.handler}» должно быть списком действий`
  }
  for (const действие of отклик[RESPONSE_ACTIONS]) {
    if (действие === null || typeof действие !== "object" || typeof действие.variant !== "string") {
      return `в списке «${RESPONSE_ACTIONS}» обработчика «${узел.handler}» не действие`
    }
    /* Семь имён, а не шесть: словарь программе приписывается по её тексту (шесть
       действий либо семь), а планировщик один на все программы и обязан узнавать
       всякое действие языка. Спрашивать здесь у ПРИПИСАННОГО словаря нельзя:
       AST может приехать не от парсера вовсе, и тогда «поручить» стало бы
       «неизвестным действием» на ровном месте. */
    if (!ИЗВЕСТНЫЕ_ДЕЙСТВИЯ.has(действие.variant)) {
      return `неизвестное действие «${действие.variant}» в отклике обработчика «${узел.handler}»`
    }
  }
  return null
}

export function кодОшибки(ошибка) {
  if (ошибка instanceof FlangError && Array.isArray(ошибка.diagnostics)) {
    return ошибка.diagnostics[0]?.code ?? "FLANG_INTERNAL"
  }
  return "FLANG_INTERNAL"
}

export function текстОшибки(ошибка) {
  return ошибка instanceof Error ? ошибка.message : String(ошибка)
}

