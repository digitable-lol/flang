/**
 * Приписать словарь действий к программе. Идемпотентно: повторный вызов ничего
 * не меняет, поэтому его можно звать и из парсера, и из связывания.
 */
export function withActionType(program) {
  const types = Array.isArray(program?.types) ? program.types : []
  if (types.some((type) => type?.name === ACTION_TYPE_NAME)) return program
  return { ...program, types: [...types, ACTION_TYPE] }
}

