/**
 * Сумма «Действие» — словарь языка, а не объявление пользователя.
 *
 * `builtin: true` нужен связыванию модулей: два файла с процессами приписали бы
 * эту сумму каждый себе, и слияние объявило бы её объявленной дважды. Пометка
 * говорит `link.mjs`, что повтор здесь — не конфликт.
 */
export const ACTION_TYPE = Object.freeze({
  kind: "sum",
  name: ACTION_TYPE_NAME,
  builtin: true,
  variants: [
    {
      name: "отправить",
      fields: [
        { name: "кому", type: { kind: "string" } },
        { name: "что", type: { kind: "any" } },
      ],
    },
    {
      name: "через",
      fields: [
        { name: "задержка", type: { kind: "number" } },
        { name: "кому", type: { kind: "string" } },
        { name: "что", type: { kind: "any" } },
      ],
    },
    { name: "остановить", fields: [{ name: "почему", type: { kind: "string" } }] },
    { name: "отложить", fields: [] },
    { name: "продолжить", fields: [] },
  ],
})

/** Действия, у которых есть адресат: их проверка типов сверяет по имени процесса. */
export const ADDRESSED_ACTIONS = new Set(["отправить", "через"])

/**
 * Приписать словарь действий к программе. Идемпотентно: повторный вызов ничего
 * не меняет, поэтому его можно звать и из парсера, и из связывания.
 */
export function withActionType(program) {
  const types = Array.isArray(program?.types) ? program.types : []
  if (types.some((type) => type?.name === ACTION_TYPE_NAME)) return program
  return { ...program, types: [...types, ACTION_TYPE] }
}

