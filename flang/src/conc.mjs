/**
 * conc.mjs — модель конкурентности flang: словарь действий и планировщик эталона.
 *
 * Контракт — `flang/conc/SPEC.md`. Здесь сделаны шаги 1–3 и 5: поверхность
 * разбирается (parser.mjs), проверяется (types.mjs), исполняется вот этим
 * планировщиком, надзор не только объявляется, но и действует, а прогон умеет
 * перебирать сетку семян. Что именно сделано и чем разошлось с контрактом,
 * перечислено в разделах контракта «Что сделано в шаге 1», «в шаге 3» и «в
 * шаге 5».
 *
 * С шага 4 этот планировщик — ЭТАЛОН в буквальном смысле: программа с
 * процессами печатается в Elixir (`emit/elixir.mjs`), идёт на настоящей BEAM, и
 * каждый её исход обязан лежать в множестве исходов, которое вот этот код даёт
 * на переборе семян (`flang/test/emit-elixir-conc.test.mjs`). Поэтому всякое
 * изменение здесь — изменение того, с чем сверяется напечатанное, и сверять
 * его надо не только с примерами, но и с BEAM.
 *
 * ── Почему словарь действий встроенный, а не объявляемый ────────────────────
 *
 * Действие описывается, а не выполняется (контракт, «Семантика»). Значит
 * обработчик обязан вернуть значение, у которого есть тип, а тип обязан быть
 * объявлен. Объявлять его в каждой программе заново — значит позволить двум
 * программам называть отправку по-разному, и тогда планировщик перестанет быть
 * общим: ему пришлось бы угадывать, какой из вариантов «отправить». Поэтому
 * сумма «Действие» вводится языком, а не пользователем, и парсер приписывает её
 * к типам программы, как только в файле есть хоть один `процесс`.
 *
 * Тип сообщения в «отправить» — джокер (`любое`). Полиморфизма в языке нет
 * (SPEC, раздел 3), поэтому «сообщение любого типа» иначе не выражается. Потеря
 * не такая большая, как кажется: проверка типов сверяет сообщение с объявленным
 * `принимает` адресата по имени процесса (types.mjs, `addresseeOf`), то есть
 * ровно там, где адресат известен. То же и у `породить`: там имя процесса
 * называет не адресата, а ВИД, и `принимает` вида становится типом первого
 * сообщения — поле, по которому искать, названо в `ACTION_PROCESS_FIELD`.
 *
 * ── «породить»: почему имя даётся, а не возвращается ────────────────────────
 *
 * «породить» в контракте был описан как «создать процесс, вернуть его имя», и
 * ровно на этом слове шаг стоял: вернуть что-либо описанное действие не может по
 * построению — оно описывается, а исполняет его планировщик, когда обработчик
 * уже вернулся. Половинчатой формы, которая называлась бы порождением, но им не
 * была, заводить не стали.
 *
 * Развязка оказалась не в том, чтобы научиться возвращать, а в том, чтобы не
 * возвращать вовсе: имя порождённому даёт РОДИТЕЛЬ. Адрес и так строка
 * (`отправить`), значит нового вида значений не появляется, таблицы pid'ов не
 * появляется, и вопрос «что значит pid мёртвого процесса» не появляется тоже.
 * Родитель может писать порождённому в том же списке действий — он знает имя,
 * потому что сам его и придумал; у BEAM это возможно только после того, как
 * `spawn` вернул pid.
 *
 * Цена названа: уникальность имени — дело программы, а занятое имя — отказ
 * порождающего (`FLANG_NAME_TAKEN`). Так же устроен `register/2` в BEAM.
 *
 * Второе решение того же шага: `породить` несёт ПЕРВОЕ СООБЩЕНИЕ, а не
 * начальное состояние. Обработчик зовётся на сообщение, поэтому процесс,
 * рождённый с пустым ящиком, не побежал бы никогда.
 *
 * «продолжить» сделан без поля. В контракте у него есть «с чем» — продолжение
 * как значение. Но отклик уже несёт новое состояние, и второе поле означало бы
 * два источника правды об одном и том же: если они разойдутся, планировщику
 * придётся выбирать, и выбор будет произволом. Поэтому продолжение — это
 * состояние из отклика, а само действие говорит только «я не доделал»:
 * сообщение возвращается в голову ящика, а планировщик получает управление.
 *
 * ── Планировщик: почему семя и что именно оно определяет ────────────────────
 *
 * Обработчик атомарен в пределах своего процесса, процессы идут параллельно,
 * наблюдаемая семантика — любое чередование атомарных пробегов. Проверочный
 * режим обязан уметь предъявить конкретное чередование и повторить его, иначе
 * конкурентный код проверяется словами «иногда падает».
 *
 * Здесь единственный источник недетерминизма — выбор процесса из очереди
 * готовых, и он берётся из генератора, заведённого семенем. Всё остальное
 * (порядок ящика, порядок действий отклика, порядок срабатывания таймеров при
 * равном времени) строго определено. Отсюда: одно семя — один журнал доставок,
 * побайтово.
 *
 * ── Надзор: три стратегии, порог и «выше» ───────────────────────────────────
 *
 * Отказом считается ровно то, что названо контрактом: исчерпание запаса витков,
 * ошибка выполнения и явное `остановить` с причиной, отличной от нормальной.
 * Нормальная причина — строка «норма», одна и та же для всей модели: так же
 * устроен BEAM (`exit(:normal)` не отказ, любая другая причина — отказ), и
 * заводить своё соглашение там, где чужое уже проверено тридцатью годами,
 * незачем.
 *
 * Перезапуск трогает ТОЛЬКО состояние, и это самое главное свойство модели,
 * которого нет у систем с изменяемым состоянием: состояние — значение,
 * начальное состояние — то же самое значение, что и при первом запуске. Оно
 * даже вычисляется один раз, при заводе процесса, и на перезапуске берётся то
 * же самое — не «пересчитанное так же», а буквально то же. Дочищать нечего:
 * наполовину применённой мутации не бывает, потому что мутаций нет.
 *
 * Ящик перезапуск НЕ трогает, и это осознанное отличие от BEAM, где ящик
 * умирает вместе с процессом. Причина в устройстве: здесь сообщение — значение
 * в общей арене, а не копия в чужой куче, и терять уже принятые сообщения из-за
 * того, что обработчик споткнулся об одно из них, было бы потерей данных без
 * всякой на то технической нужды. Сообщение, на котором процесс упал, при этом
 * не возвращается: оно уже снято с ящика, и вечного цикла «упал — перезапустили
 * — упал на том же» не выходит. Ядовитое сообщение в очереди из трёх таких
 * упрётся в порог отказов, а не будет проглочено молча.
 *
 * «Выше» — это надзор над надзором: строка `надзор «X» стратегия «…»` внутри
 * надзора. Без неё стратегия «передать выше» не значила бы ничего, потому что
 * передавать было бы некому. Перезапуск надзора перезапускает всё его
 * поддерево — как в OTP, где падение супервизора поднимает всех его детей.
 * Если передавать некому и наверху, вся программа останавливается с исходом
 * «отказ дошёл доверху»: определённый конец, а не молчаливое продолжение с
 * мёртвым процессом.
 */

