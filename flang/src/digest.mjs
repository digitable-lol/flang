/**
 * АДРЕС ОПРЕДЕЛЕНИЯ — хеш нормализованного разбора, а не текста.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Не ради пакетов. Ради КЕША ДОКАЗАТЕЛЬСТВ: доказательство стоит на порядки
 * дороже теста, а кешировать его сегодня не по чему. Ключ обязан быть таким,
 * чтобы переименование параметра его не сдвинуло (иначе кеш пуст после каждой
 * косметической правки), а правка тела — сдвинула обязательно (иначе кеш
 * отдаёт вердикт о другой функции, и это уже не кеш, а ложь).
 *
 * ── Самое тонкое место: поверхностей четыре ─────────────────────────────────
 * `модуль` / `module` / `modulo` / `模块`. Один и тот же алгоритм, набранный
 * русскими и китайскими словами, — ОДНА функция, и адрес обязан быть один.
 * Иначе экосистема расколется на четыре несовместимые, и одна библиотека ляжет
 * в хранилище четырежды.
 *
 * Что расходится у сырых деревьев четырёх поверхностей — измерено, а не
 * предположено (`flang/test/digest.test.mjs`): расходятся ТОЛЬКО имена,
 * выбранные автором. Ни `kind`, ни `op`, ни `builtin.name`, ни данные примеров
 * не расходятся ни в одном слоте. Значит нормализация обязана вычеркнуть ровно
 * имена автора — и НИЧЕГО СВЕРХ ТОГО.
 *
 * ── Почему таблица слотов, а не «выкинуть все name» ─────────────────────────
 * Первая редакция канонизатора выкидывала ключи по имени ключа, и у узла вызова
 * вместе с `name` под нож попадали `kind` и `op`: деревья всё равно совпадали,
 * и проверка была зелёной. Но утверждение «вычеркнуты только имена автора»
 * стало бы при этом неправдой, а вслед за ним — и чувствительность: `op` есть
 * САМ РАЗБОР, и стёртый `op` означал бы, что «плюс» и «минус» получают один
 * адрес.
 *
 * Поэтому таблица ниже ключуется ПАРОЙ «род узла + ключ», а не одним ключом, и
 * всё, чего в ней нет, едет в хеш ПОБУКВЕННО. Незнакомый слот обязан ломать
 * сверку поверхностей, а не молча превращаться в «переименование».
 *
 * Проверяется это механически, а не глазами: тест перебирает КАЖДЫЙ строковый
 * слот дерева, портит его на один знак и требует, чтобы адрес сдвинулся —
 * кроме ровно тех слотов, что объявлены здесь именами автора.
 *
 * ── Что входит в адрес и что не входит ──────────────────────────────────────
 * ВХОДЯТ: тело, типы, пометка тотальности, объявленная мера, предусловия и
 * постусловия. Постусловие — не примечание, а обязательство, на которое
 * вызывающий имеет право опереться; функция с постусловием и такая же без него
 * — разные обязательства, и путать их адресом нельзя. Цена признаётся прямо:
 * дописал постусловие — сменился адрес, и всё зависимое пересчиталось.
 *
 * НЕ ВХОДЯТ: имена (свои, параметров, локальных, примеров, утверждений, типов,
 * полей, модуля), позиции (`span`), порядок объявлений в файле и ТЕОРЕМА.
 * Теорема — не поле функции, а определение верхнего уровня, ссылающееся на
 * функцию; у неё свой адрес, а внутри — ссылка по адресу. Так же устроено у
 * Unison с `f.doc` и `f.tests.ex1`, и по той же причине.
 *
 * ── Клубки ──────────────────────────────────────────────────────────────────
 * Вызов по имени заменяется вызовом по адресу, а взаимно рекурсивный клубок
 * хешируется целиком: члены нумеруются порядком, полученным сортировкой по их
 * собственным адресам с вырезанным клубком. Следствие, и оно обязано быть
 * таким: перестановка функций внутри клубка не меняет ничьих адресов,
 * добавление функции в клубок меняет адреса всех его членов.
 *
 * ── Чего этот файл НЕ обещает ───────────────────────────────────────────────
 * Адрес даёт ТОЖДЕСТВО, а не ЭКВИВАЛЕНТНОСТЬ: две разные реализации сортировки
 * получают два разных адреса, и никакая адресация этого не изменит.
 *
 * И одно ограничение названо прямо, потому что оно принципиальное, а не
 * недоделанное: тип здесь хешируется СТРУКТУРНО, значит запись `{ значение:
 * число }` под именем «Метры» и такая же под именем «Секунды» получают один
 * адрес. Иначе нельзя: имя типа переводится между поверхностями, и различать
 * типы именем значило бы расколоть экосистему ровно там, ради чего всё
 * затевалось. Unison прошёл этот путь до конца и вернулся к `unique` со
 * случайным GUID в хеше; тот же ход придётся сделать и здесь, но GUID — это
 * новое поле в синтаксисе, а шаг 1 не меняет ни синтаксиса, ни печати.
 */
import { createHash } from "node:crypto"

import { КАНОН_СКАЛЯРА } from "./types.mjs"

/** Версия схемы нормализации. Меняется — меняются все адреса, и это правильно. */
export const СХЕМА = 1

/**
 * Слоты, где стоит ИМЯ, ВЫБРАННОЕ АВТОРОМ. Всё, чего здесь нет, — побуквенно.
 *
 * Разряды:
 *   `стереть`  — имя выбрасывается вовсе (своё имя, имя примера, имя модуля);
 *   `связать`  — имя ВВОДИТ локальное, заменяется номером связывания;
 *   `ссылка`   — имя ССЫЛАЕТСЯ на связанное, заменяется тем же номером;
 *   `функция`  — имя вызываемой функции, заменяется её адресом;
 *   `тип`      — имя типа, заменяется структурным адресом типа;
 *   `поле`     — имя поля записи, заменяется номером поля в объявлении типа.
 */
export const ИМЕННЫЕ_СЛОТЫ = Object.freeze({
  /* Верхний уровень: у объявлений нет `kind`, их различает путь. */
  путями: Object.freeze([
    ["", "module", "стереть"],
    [/^\.legacy\[\d+\]\.value$/u, "name", "стереть"],
    [/^\.functions\[\d+\]$/u, "name", "стереть"],
    [/^\.functions\[\d+\]\.params\[\d+\]$/u, "name", "связать"],
    [/^\.functions\[\d+\]\.examples\[\d+\]$/u, "name", "стереть"],
    [/^\.functions\[\d+\]\.(pre|post)conditions\[\d+\]$/u, "name", "стереть"],
    [/^\.functions\[\d+\]\.(pre|post)conditions\[\d+\]$/u, "message", "стереть"],
    [/^\.functions\[\d+\]\.(pre|post)conditions\[\d+\]$/u, "forall", "связать"],
    /* Объявление типа и объявление поля — НАЗЫВАЮЩИЕ места, а не подписи: на
       них ссылаются, и правка одного места без другого — другая программа.
       В хеш они всё равно не едут именем (тип раскрывается в устройство, поле
       — в пары «адрес типа, номер»), но разряд у них тот же, что у ссылки. */
    [/^\.types\[\d+\]$/u, "name", "тип"],
    [/^\.types\[\d+\]\.fields\[\d+\]$/u, "name", "поле"],
    [/^\.theorems\[\d+\]$/u, "name", "стереть"],
    [/^\.theorems\[\d+\]\.vars\[\d+\]$/u, "name", "связать"],
    [/^\.theorems\[\d+\]\.induction$/u, "param", "ссылка"],
  ]),
  /* Выражения: их различает `kind`, путь у них произвольной глубины. */
  родами: Object.freeze({
    call: Object.freeze({ name: "функция" }),
    named: Object.freeze({ name: "тип" }),
    record: Object.freeze({ name: "тип", type: "тип" }),
    field: Object.freeze({ field: "поле" }),
    var: Object.freeze({ name: "ссылка" }),
    let: Object.freeze({ name: "связать" }),
    fold: Object.freeze({ acc: "связать", item: "связать" }),
    map: Object.freeze({ item: "связать" }),
    filter: Object.freeze({ item: "связать" }),
    cons: Object.freeze({ head: "связать", tail: "связать" }),
  }),
})

/** Какой разряд у слота; `null` — слот не именной, едет в хеш побуквенно. */
export function разрядСлота(путь, ключ, узел) {
  const род = typeof узел?.kind === "string" ? узел.kind : null
  if (род !== null) {
    /* Узел с `kind` разбирается ТОЛЬКО по роду: сюда попадают `args`, `op`,
       `items` и прочее, и ни один из них не смеет уехать по путевому правилу. */
    return ИМЕННЫЕ_СЛОТЫ.родами[род]?.[ключ] ?? null
  }
  for (const [шаблон, слот, разряд] of ИМЕННЫЕ_СЛОТЫ.путями) {
    if (слот !== ключ) continue
    if (typeof шаблон === "string" ? путь === шаблон : шаблон.test(путь)) return разряд
  }
  return null
}

/** Канонический JSON: ключи по порядку кодовых точек, без пробелов. */
export function каноническийJSON(значение) {
  if (значение === undefined) return "null"
  if (значение === null || typeof значение !== "object") return JSON.stringify(значение) ?? "null"
  if (Array.isArray(значение)) return `[${значение.map(каноническийJSON).join(",")}]`
  const ключи = Object.keys(значение).sort()
  return `{${ключи.map((к) => `${JSON.stringify(к)}:${каноническийJSON(значение[к])}`).join(",")}}`
}

/** sha256 канонического JSON — шестнадцатеричной строкой. */
export function хеш(значение) {
  return createHash("sha256").update(`flang-digest-${СХЕМА} ${каноническийJSON(значение)}`, "utf8").digest("hex")
}

/* ─────────────────────────────── типы ──────────────────────────────────── */

/**
 * Структурный адрес типа. Имя объявленного типа раскрывается в его устройство,
 * рекурсия обрывается меткой глубины — иначе список списков не досчитался бы.
 */
function адресаТипов(program) {
  const объявленные = new Map()
  for (const тип of program?.types ?? []) if (typeof тип?.name === "string") объявленные.set(тип.name, тип)
  const раскрыть = (узел, стек) => {
    if (узел === null || узел === undefined) return null
    if (Array.isArray(узел)) return узел.map((э) => раскрыть(э, стек))
    if (typeof узел !== "object") return узел
    const свод = {}
    for (const ключ of Object.keys(узел).sort()) {
      if (ключ === "span") continue
      if ((узел.kind === "named" || узел.kind === "record") && (ключ === "name" || ключ === "type")) {
        const имя = узел[ключ]
        if (объявленные.has(имя)) {
          const место = стек.indexOf(имя)
          свод[ключ] = место >= 0 ? { "«назад»": стек.length - место } : { "«тип»": устройство(имя, стек) }
          continue
        }
        /* Имя типа, которого в программе нет: встроенный или привозной. Едет
           побуквенно — расхождение поверхностей на нём обязано быть видно. */
        свод[ключ] = { "«имя»": имя }
        continue
      }
      if (ключ === "fields" && Array.isArray(узел.fields)) {
        свод.fields = узел.fields.map((поле, номер) => {
          const без = { ...поле }
          delete без.name
          return { "«поле»": номер, устройство: раскрыть(без, стек) }
        })
        continue
      }
      свод[ключ] = раскрыть(узел[ключ], стек)
    }
    return свод
  }
  const устройство = (имя, стек) => {
    const без = { ...объявленные.get(имя) }
    delete без.name
    return раскрыть(без, [...стек, имя])
  }
  const адреса = new Map()
  for (const имя of объявленные.keys()) адреса.set(имя, хеш(устройство(имя, [])))
  /* Поле → ЧЕМ ОНО СТОИТ В ОБЪЯВЛЕНИЯХ: список пар «адрес типа, номер поля» по
     всем типам, где это имя встретилось. Имя поля переводится, а пара — нет.
     Одним номером здесь обойтись нельзя, и это не запас прочности: в
     `run-length-encoding.flang` поле «счёт» стоит третьим у «Сжатия» и вторым у
     «Разжатия», и таблица «имя → номер» объявила бы его спорным, после чего имя
     уехало бы в хеш побуквенно — то есть по-русски. */
  const поля = new Map()
  for (const [имя, тип] of объявленные) {
    ;(тип.fields ?? []).forEach((поле, номер) => {
      if (typeof поле?.name !== "string") return
      if (!поля.has(поле.name)) поля.set(поле.name, [])
      поля.get(поле.name).push([адреса.get(имя), номер])
    })
  }
  const токены = new Map()
  for (const [имя, места] of поля) {
    токены.set(имя, хеш([...места].sort((л, п) => (каноническийJSON(л) < каноническийJSON(п) ? -1 : 1))))
  }
  return { адреса, поля: токены }
}

/* ────────────────────────── нормализация функции ───────────────────────── */

/**
 * Нормализованное определение: позиции сняты, имена автора вычеркнуты,
 * локальные заменены номерами связывания, вызовы — адресами вызываемых.
 *
 * `адресВызова` — «имя → чем заменить»; члену клубка она отдаёт метку клубка.
 */
function нормализоватьФункцию(fn, номерФункции, обстановка) {
  const { адресВызова, типы } = обстановка
  let связей = 0
  const среда = new Map()
  const идти = (узел, путь) => {
    if (узел === null || узел === undefined) return null
    if (Array.isArray(узел)) return узел.map((э, н) => идти(э, `${путь}[${н}]`))
    if (typeof узел !== "object") return узел
    /* ДАННЫЕ ПРИМЕРА — это значения, а не разбор, и переименовывать в них можно
       ровно одно: имена полей записи, стоящие КЛЮЧАМИ объекта. «Fizz» и «MCMXC»
       обязаны совпасть буква в букву, а `диск`/`disk` — это то же поле того же
       типа, написанное на двух поверхностях. Улика: до этой ветки
       `towers-of-hanoi.flang` расходился со своим английским близнецом на
       записях в `дано` и `ожидается`, и больше ни на чём. */
    if (узел.kind === undefined && /\.examples\[\d+\]\./u.test(путь)) {
      const свод = {}
      for (const ключ of Object.keys(узел)) {
        const токен = типы.поля.get(ключ)
        свод[токен === undefined ? ключ : `«поле»${токен}`] = идти(узел[ключ], `${путь}.${ключ}`)
      }
      return свод
    }
    const свод = {}
    /* СНАЧАЛА СВЯЗЫВАЮЩИЕ СЛОТЫ, потом всё остальное — и это не косметика
       порядка. Ключи узла обходятся по алфавиту, а у свёртки `body` стоит
       раньше `item`: обойди в лоб — и `эл` внутри тела оказался бы «свободным»,
       то есть уехал бы в хеш СВОИМ ИМЕНЕМ. Русская запись дала бы «эл»,
       английская «elem», и адрес разошёлся бы ровно там, ради чего всё
       затевалось. Улика: до этой строки `factorial.flang` и его английский
       близнец давали разные адреса у двух функций из пяти.

       `pattern` идёт здесь же и по той же причине, хотя сам связывающим слотом
       не является: у случая разбора связывает ОБРАЗЕЦ (`случай голова гп и
       хвост хп`), а тело стоит ему СОСЕДНИМ ключом и по алфавиту раньше.
       Улика та же и мерена так же: из четырнадцати пар «русская — английская»
       расходились восемь, и все восемь — на именах, связанных образцом. */
    const ключи = Object.keys(узел).sort()
    const связывающие = ключи.filter(
      (ключ) => разрядСлота(путь, ключ, узел) === "связать" || ключ === "pattern",
    )
    for (const ключ of [...связывающие, ...ключи.filter((ключ) => !связывающие.includes(ключ))]) {
      if (ключ === "span") continue
      const значение = узел[ключ]
      /* `дано` примера: КЛЮЧИ — имена параметров, значения — данные задачи.
         Ключи заменяются номером параметра, значения едут буква в букву. */
      if (ключ === "args" && узел.kind === undefined && /examples\[\d+\]$/u.test(путь)) {
        свод.args = Object.keys(значение ?? {}).map((имя, номер) => ({
          "«довод»": среда.get(имя) ?? номер,
          значение: идти(значение[имя], `${путь}.args.${имя}`),
        }))
        continue
      }
      /* Построение записи: ключи — имена полей, значения — выражения. */
      if (ключ === "fields" && узел.kind === "record" && !Array.isArray(значение)) {
        свод.fields = Object.keys(значение ?? {}).map((поле, номер) => ({
          "«поле»": типы.поля.get(поле) ?? { "«имя»": поле, "«место»": номер },
          значение: идти(значение[поле], `${путь}.fields.${поле}`),
        }))
        continue
      }
      if (typeof значение === "string") {
        const разряд = разрядСлота(путь, ключ, узел)
        if (разряд === "стереть") continue
        if (разряд === "связать") {
          среда.set(значение, связей)
          свод[ключ] = { "«связь»": связей }
          связей += 1
          continue
        }
        if (разряд === "ссылка") {
          const номер = среда.get(значение)
          /* Свободное имя — не локальное. Едет побуквенно: молчать о нём
             нельзя, оно обязано покраснеть сверкой поверхностей. */
          свод[ключ] = номер === undefined ? { "«свободно»": значение } : { "«связь»": номер }
          continue
        }
        if (разряд === "функция") {
          свод[ключ] = { "«зовёт»": адресВызова(значение) }
          continue
        }
        if (разряд === "тип") {
          if (типы.адреса.has(значение)) {
            свод[ключ] = { "«тип»": типы.адреса.get(значение) }
            continue
          }
          /* Скаляр языка (`нат`/`nat`/`naturo`/`自然数`) — одно понятие на
             четырёх поверхностях, и таблица его канона живёт ОДНА, в types.mjs.
             Своё имя типа, которого в программе нет, едет побуквенно: молчать о
             нём нельзя, оно обязано покраснеть сверкой поверхностей. */
          свод[ключ] = { "«имя»": КАНОН_СКАЛЯРА[значение] ?? значение }
          continue
        }
        if (разряд === "поле") {
          const токен = типы.поля.get(значение)
          свод[ключ] = токен === undefined ? { "«имя»": значение } : { "«поле»": токен }
          continue
        }
        свод[ключ] = значение
        continue
      }
      свод[ключ] = идти(значение, `${путь}.${ключ}`)
    }
    return свод
  }
  /* Параметры связываются первыми и в объявленном порядке — их номера суть
     номера доводов, и на них ссылается `дано` примера. */
  const корень = `.functions[${номерФункции}]`
  const params = (fn.params ?? []).map((п, н) => идти(п, `${корень}.params[${н}]`))
  const прочее = {}
  for (const ключ of Object.keys(fn).sort()) {
    if (ключ === "span" || ключ === "params" || ключ === "name") continue
    прочее[ключ] = идти(fn[ключ], `${корень}.${ключ}`)
  }
  return { "«схема»": СХЕМА, params, ...прочее }
}

/* ──────────────────────────────── клубки ───────────────────────────────── */

/** Кого зовёт функция — по именам, среди объявленных в программе. */
function зовёт(fn, свои) {
  const найдено = new Set()
  const идти = (узел) => {
    if (узел === null || typeof узел !== "object") return
    if (Array.isArray(узел)) {
      узел.forEach(идти)
      return
    }
    if (узел.kind === "call" && typeof узел.name === "string" && свои.has(узел.name)) найдено.add(узел.name)
    for (const ключ of Object.keys(узел)) if (ключ !== "span") идти(узел[ключ])
  }
  идти(fn)
  return найдено
}

/** Компоненты сильной связности — Тарьяном, без рекурсии по стеку JS. */
function клубки(имена, рёбра) {
  const индекс = new Map()
  const низ = new Map()
  const наСтеке = new Set()
  const стек = []
  const итог = []
  let счёт = 0
  const открыть = (имя) => {
    индекс.set(имя, счёт)
    низ.set(имя, счёт)
    счёт += 1
    стек.push(имя)
    наСтеке.add(имя)
  }
  for (const старт of имена) {
    if (индекс.has(старт)) continue
    открыть(старт)
    const работа = [{ имя: старт, дети: [...(рёбра.get(старт) ?? [])], шаг: 0 }]
    while (работа.length > 0) {
      const кадр = работа[работа.length - 1]
      if (кадр.шаг < кадр.дети.length) {
        const ребёнок = кадр.дети[кадр.шаг]
        кадр.шаг += 1
        if (!индекс.has(ребёнок)) {
          открыть(ребёнок)
          работа.push({ имя: ребёнок, дети: [...(рёбра.get(ребёнок) ?? [])], шаг: 0 })
        } else if (наСтеке.has(ребёнок)) {
          низ.set(кадр.имя, Math.min(низ.get(кадр.имя), индекс.get(ребёнок)))
        }
        continue
      }
      работа.pop()
      if (работа.length > 0) {
        const родитель = работа[работа.length - 1].имя
        низ.set(родитель, Math.min(низ.get(родитель), низ.get(кадр.имя)))
      }
      if (низ.get(кадр.имя) === индекс.get(кадр.имя)) {
        const группа = []
        for (;;) {
          const имя = стек.pop()
          наСтеке.delete(имя)
          группа.push(имя)
          if (имя === кадр.имя) break
        }
        итог.push(группа)
      }
    }
  }
  /* Тарьян отдаёт компоненты в обратном топологическом порядке — то есть
     зависимости РАНЬШЕ зависящих. Это ровно тот порядок, какой нужен. */
  return итог
}

/* ─────────────────────────────── наружу ────────────────────────────────── */

/**
 * Адреса всех определений программы.
 *
 * @param {object} program разобранное (и связанное) дерево
 * @returns {{ функции: Map<string,string>, типы: Map<string,string>, теоремы: Map<string,string> }}
 */
export function адресаОпределений(program) {
  const функции = program?.functions ?? []
  const порядок = new Map(функции.map((fn, номер) => [fn.name, номер]))
  const типы = адресаТипов(program)
  const рёбра = new Map(функции.map((fn) => [fn.name, зовёт(fn, порядок)]))
  const адреса = new Map()
  /* Нормализованные определения отдаются наружу тем же путём, каким считаются
     адреса: тест сверки поверхностей обязан смотреть на ТО ЖЕ, что и хеш, а не
     на второй его пересчёт. */
  const нормализованные = new Map()
  for (const группа of клубки([...порядок.keys()], рёбра)) {
    const вКлубке = new Set(группа)
    const рекурсия = группа.length > 1 || рёбра.get(группа[0])?.has(группа[0]) === true
    const нормой = (пометка) => (имя) => {
      if (вКлубке.has(имя)) return пометка(имя)
      if (адреса.has(имя)) return адреса.get(имя)
      /* Имя, которого в программе нет: встроенная форма или ещё не связанный
         привозной модуль. Едет побуквенно — иначе адрес соврал бы. */
      return `имя:${имя}`
    }
    const норма = (имя, пометка) =>
      нормализоватьФункцию(функции[порядок.get(имя)], порядок.get(имя), {
        адресВызова: нормой(пометка),
        типы,
      })
    if (!рекурсия) {
      const свод = норма(группа[0], () => "«клубок»")
      нормализованные.set(группа[0], свод)
      адреса.set(группа[0], хеш(свод))
      continue
    }
    /* Клубок: сначала пробные адреса с вырезанным клубком — они дают ПОРЯДОК,
       не зависящий от того, как автор расставил функции в файле. */
    const пробные = группа.map((имя) => ({ имя, пробный: хеш(норма(имя, () => "«клубок»")) }))
    пробные.sort((л, п) => (л.пробный < п.пробный ? -1 : л.пробный > п.пробный ? 1 : 0))
    const номерВКлубке = new Map(пробные.map(({ имя }, номер) => [имя, номер]))
    const сводки = пробные.map(({ имя }) => норма(имя, (кого) => `«клубок»#${номерВКлубке.get(кого)}`))
    пробные.forEach(({ имя }, номер) => нормализованные.set(имя, сводки[номер]))
    const адресКлубка = хеш(сводки)
    пробные.forEach(({ имя }, номер) => адреса.set(имя, хеш({ "«клубок»": адресКлубка, "«номер»": номер })))
  }
  /* Теорема — определение верхнего уровня, а не поле функции: свой адрес, а
     внутри — ссылка на функцию ПО АДРЕСУ. */
  const теоремы = new Map()
  ;(program?.theorems ?? []).forEach((теорема, номер) => {
    const о = теорема?.about ?? теорема?.of ?? теорема?.function
    const без = { ...теорема }
    delete без.name
    теоремы.set(теорема?.name ?? `#${номер}`, хеш({
      "«теорема»": нормализоватьФункцию(без, номер, {
        адресВызова: (имя) => адреса.get(имя) ?? `имя:${имя}`,
        типы,
      }),
      "«о»": typeof о === "string" ? (адреса.get(о) ?? `имя:${о}`) : null,
    }))
  })
  return { функции: адреса, типы: типы.адреса, теоремы, нормализованные }
}

/**
 * Адрес УТВЕРЖДЕНИЯ обязательства — второй ключ тройки.
 *
 * Один адрес функции ключом кеша был бы неверен: у функции может быть два
 * постусловия, и вердикт у них разный.
 */
export function адресУтверждения(обязательство, адресаФункций) {
  return хеш({
    "«род»": обязательство?.kind ?? null,
    "«о»": адресаФункций.get(обязательство?.of) ?? `имя:${обязательство?.of}`,
    "«цель»": снятьПозиции(обязательство?.goal ?? обязательство?.claim ?? null),
    "«терм»": снятьПозиции(обязательство?.proof ?? null),
  })
}

/** Позиции — не содержимое; в адрес утверждения они ехать не должны. */
export function снятьПозиции(узел) {
  if (узел === null || узел === undefined) return null
  if (typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map(снятьПозиции)
  const свод = {}
  for (const ключ of Object.keys(узел).sort()) if (ключ !== "span") свод[ключ] = снятьПозиции(узел[ключ])
  return свод
}
