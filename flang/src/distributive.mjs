/**
 * Дистрибутивность: `а×(б+в) = а×б + а×в`.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Программа, где «скидка на сумму заказа» и «сумма скидок на позиции» считаются
 * ДВУМЯ функциями и обязаны совпадать, проходила `flang check --proof` со
 * строкой «нет объявленных законов». Обещание «считать можно как угодно —
 * ответ один» ни во что не превращалось: сказать его языку было нечем.
 *
 * ── Ради чего это свойство ──────────────────────────────────────────────────
 *
 * Разрешение ПЕРЕПИСЫВАТЬ ВЫРАЖЕНИЯ. Одна и та же величина в коде считается
 * двумя дорогами — по целому и по частям, — и выбирают между ними по цене:
 * «раскрыть скобки» дешевле там, где `б+в` уже посчитано; «свернуть» дешевле
 * там, где `а×` дорого. Заменять одну дорогу другой разрешено ровно тогда, когда
 * обе дают один ответ, и это ровно дистрибутивность.
 *
 * Проверка честно называет свою СТОРОНУ: считается ЛЕВАЯ дистрибутивность,
 * `а×(б+в) = а×б + а×в`, и ПРАВАЯ, `(б+в)×а = б×а + в×а`. Обе, а не одна:
 * у некоммутативной операции они разные утверждения, и проверив одну, о второй
 * сказать нечего.
 *
 * ── Что здесь ПРОВЕРЯЕТСЯ, а не доказывается ────────────────────────────────
 *
 * Закон. Устройство доказано раньше и в другом месте (`types.mjs`). Здесь —
 * равенство вычислений на всех ТРОЙКАХ значений носителя, а оно неразрешимо:
 * значит конечная сетка, кубическая по ней, и ведомость обязана называть её
 * размер строкой, оканчивающейся словами «Это не доказательство».
 *
 * СЕТКА БЕРЁТСЯ ИЗ ОБЕИХ ОПЕРАЦИЙ, и это не удобство. Закон говорит об их
 * СОВМЕСТНОМ поведении; краевые случаи, из-за которых он ломается, автор писал
 * при той из двух, где они краевые, — ноль при умножении, пустая строка при
 * склейке, — и взять только одну сторону значило бы потерять ровно половину
 * написанного.
 */
import { valuesEqual } from "./builtins.mjs"
import { ПРЕДЕЛ_СЕТКИ, объявления, основа, покажи, пусто } from "./svoystva.mjs"

export { ПРЕДЕЛ_СЕТКИ }

/** Имя свойства — то самое, что автор пишет в ёлочках. */
export const ИМЯ = "дистрибутивность"

/**
 * Проверка дистрибутивности всех пар операций, её объявивших.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object>,
 *   assumed: Array<object>, permits: Array<object> }}
 */
export function checkDistributivity(программа, пределы = {}) {
  const узлы = объявления(программа, ИМЯ)
  const итог = пусто()
  if (узлы.length === 0) return итог

  const { найти, звать, сетка } = основа(программа, пределы)

  for (const узел of узлы) {
    const двухвходовая = (имя) => (найти(имя)?.params ?? []).length === 2
    if (!двухвходовая(узел.operation) || !двухвходовая(узел.over)) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation ?? null,
        why: "устройство одной из двух операций не сошлось: об этом сказала проверка типов",
      })
      continue
    }

    const значения = сетка([узел.operation, узел.over])
    if (значения.length === 0) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation,
        why: `ни у «${узел.operation}», ни у «${узел.over}» нет примеров: сетка пуста, раскрывать было нечего`,
      })
      continue
    }

    const доБед = итог.diagnostics.length
    let оборвано = null
    let троек = 0
    const умножить = (а, б) => звать(узел.operation, а, б)
    const сложить = (а, б) => звать(узел.over, а, б)

    тройки: for (const а of значения) {
      for (const б of значения) {
        for (const в of значения) {
          троек += 1
          /* Слева и справа собираются ПОРОЗНЬ и до сравнения: это два разных
             выражения, и сравнивать их надо как выражения, а не как один путь
             вычисления с общим подвыражением. */
          const сумма = сложить(б, в)
          if (сумма.ошибка) {
            оборвано = `«${узел.over}» отказала на значении сетки: ${сумма.ошибка}`
            break тройки
          }
          for (const [сторона, свёрнуто, части] of [
            ["левая", () => умножить(а, сумма.значение), () => [умножить(а, б), умножить(а, в)]],
            ["правая", () => умножить(сумма.значение, а), () => [умножить(б, а), умножить(в, а)]],
          ]) {
            const целиком = свёрнуто()
            const [первая, вторая] = части()
            if (целиком.ошибка || первая.ошибка || вторая.ошибка) {
              оборвано = `«${узел.operation}» отказала на значении сетки: `
                + `${целиком.ошибка ?? первая.ошибка ?? вторая.ошибка}`
              break тройки
            }
            const раскрыто = сложить(первая.значение, вторая.значение)
            if (раскрыто.ошибка) {
              оборвано = `«${узел.over}» отказала на раскрытом выражении: ${раскрыто.ошибка}`
              break тройки
            }
            if (valuesEqual(целиком.значение, раскрыто.значение)) continue
            const скобки = сторона === "левая"
              ? `${покажи(а)} × (${покажи(б)} + ${покажи(в)})`
              : `(${покажи(б)} + ${покажи(в)}) × ${покажи(а)}`
            итог.diagnostics.push({
              code: "FLANG_NOT_DISTRIBUTIVE",
              message: `свойство «${ИМЯ}»: «${узел.operation}» не дистрибутивна по «${узел.over}» ` +
                `(${сторона} сторона): ${скобки} дало ${покажи(целиком.значение)}, ` +
                `а то же самое раскрытым — ${покажи(раскрыто.значение)} — ` +
                `переписывать такое выражение нельзя: две дороги дают разные ответы`,
              severity: "error",
              span: узел.span,
            })
            break тройки
          }
        }
      }
    }

    const нарушений = итог.diagnostics.length - доБед
    итог.checked.push({
      property: ИМЯ,
      subject: узел.operation,
      over: узел.over,
      values: значения.length,
      points: троек,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
    if (нарушений > 0 || оборвано !== null) continue
    итог.permits.push({
      permit: "переписать",
      property: ИМЯ,
      subject: узел.operation,
      says: `выражение с «${узел.operation}» и «${узел.over}» можно переписывать в обе стороны: ` +
        `свёрнутая и раскрытая записи дают один ответ`,
    })
  }

  return итог
}
