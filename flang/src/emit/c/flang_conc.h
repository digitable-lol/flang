/*
 * Планировщик конкурентности flang для бэкенда C — заголовок.
 *
 * Контракт модели — `flang/conc/SPEC.md`, шаг 6. Этот файл печатается бэкендом
 * как есть, байт в байт, и только той программе, в которой есть хоть один
 * `процесс`: программе без процессов планировщик не нужен, и возить его ей
 * значило бы возить неисполнимый код.
 *
 * ── Почему один поток, а не пул ────────────────────────────────────────────
 * Контракт называет два режима: проверочный — «одним потоком, чередование по
 * семени», рабочий — «параллельно, сколько даёт среда». Здесь сделан ПЕРВЫЙ, и
 * это не полумера, а то единственное, что вообще поддаётся дифференциальной
 * сверке: пункт 2 раздела «Что проверяется и чем» требует ПОБАЙТОВО того же
 * журнала доставок при том же семени, что у эталона. У пула потоков семени нет
 * — чередование выбирает планировщик ОС, — и требовать от него журнала с семени
 * 4172 было бы требованием, которого модель не предъявляет.
 *
 * Отсюда устройство: единственный источник недетерминизма — выбор процесса из
 * очереди готовых, и он берётся из генератора, заведённого семенем. Всё
 * остальное (порядок ящика, порядок действий отклика, порядок срабатывания
 * таймеров при равном сроке, порядок перечисления процессов) определено жёстко
 * и повторяет `flang/src/conc.mjs` строка в строку.
 *
 * ── Что здесь лучше эталона: очередь готовых, а не перебор ─────────────────
 * Эталон на КАЖДОМ пробеге пересобирает очередь готовых полным перебором всех
 * объявленных процессов (`порядок.filter(…)`), и измерение шага 7 записало это
 * как найденное: переключение стоит O(числа процессов), около 2 мкс + 12–13 нс
 * на процесс. Здесь очередь готовых поддерживается СПИСКОМ, отсортированным по
 * порядку объявления: пробег стоит O(числа готовых), а не O(числа объявленных).
 *
 * Наблюдаемо это НЕ меняет ничего, и в этом весь смысл: содержимое очереди
 * готовых на каждом пробеге в точности то же самое, что даёт перебор эталона, —
 * тот же список в том же порядке, — поэтому семя выбирает тот же процесс, и
 * журнал совпадает побайтово. Быстрее стал способ получить список, а не список.
 *
 * ── Память ────────────────────────────────────────────────────────────────
 * Всё живёт в арене вызывающего и умирает вместе с ней. Состояния процессов,
 * сообщения в ящиках и записи журнала — значения flang, а значения flang
 * неизменяемы и лежат в арене; освобождать их по одному нечем и незачем.
 * Отсюда правило для вызывающего: `fl_conc_result` годен до ближайшего
 * `fl_arena_reset`, ровно как и всякое другое значение из рантайма.
 */
#ifndef FLANG_CONC_H
#define FLANG_CONC_H

#include "flang_runtime.h"

/* ───────────────────────────── план программы ─────────────────────────────
   Процессы, надзоры и прогоны печатаются ДАННЫМИ — одной таблицей на программу.
   Ровно так же они печатаются в Elixir (`conc_plan/0`), и по той же причине:
   надзор в flang — объявление, и одно объявление обязано остаться одним местом
   в напечатанном коде. Печать готовых функций-планировщиков размазала бы его по
   файлу и превратила правку одной строки исходника в правку десяти строк
   вывода. */

/** Вызов функции программы по её исходному имени flang (`<префикс>_call`). */
typedef fl_status (*fl_conc_call)(fl_ctx *ctx, const char *name, const fl_value *args, size_t count,
                                  fl_value *result, fl_error *error);

typedef struct fl_conc_process {
  const char *name;    /* имя процесса — оно же адрес в «отправить» */
  const char *handler; /* имя функции-обработчика */
  const char *initial; /* имя функции без параметров: начальное состояние */
  bool total;          /* завершение обработчика доказано */
  /* Запас витков нетотального обработчика; у тотального — 0, и это не «нет
     запаса», а «считать нечего»: планировщик подставит общий предел. */
  size_t budget;
} fl_conc_process;

/** Ребёнок надзора: процесс или вложенный надзор со своей стратегией. */
typedef struct fl_conc_child {
  const char *name;
  const char *strategy; /* «перезапустить» | «остановить» | «передать выше» */
} fl_conc_child;

typedef struct fl_conc_supervisor {
  const char *name;
  const fl_conc_child *watch;
  size_t watch_count;
  const fl_conc_child *nested;
  size_t nested_count;
  bool threshold;       /* объявлен ли порог отказов */
  double failures;      /* N в «порог отказов N за M» */
  double window;        /* M, в единицах виртуального времени планировщика */
  const char *otherwise; /* стратегия сверх порога */
} fl_conc_supervisor;

/**
 * Построитель входных сообщений прогона: заполняет `messages[0..count-1]`.
 *
 * Функцией, а не таблицей значений: сообщение — значение flang, а значения
 * flang строятся в арене и до вызова не существуют. Печатается она тем же
 * `emitLiteral`, что и всякий другой литерал программы, — иначе «дано» в
 * исходнике и «дано» в напечатанном коде разошлись бы на первом же варианте с
 * полями.
 */
typedef fl_status (*fl_conc_inbox)(fl_ctx *ctx, fl_value *messages, fl_error *error);

typedef struct fl_conc_run_spec {
  const char *name;
  double seed;    /* «семя N» либо начало отрезка «семя от N до M» */
  double seed_to; /* конец отрезка; равен seed, если семя одно */
  const char *const *targets; /* кому какое сообщение — параллельно messages */
  size_t count;
  fl_conc_inbox build;
} fl_conc_run_spec;

typedef struct fl_conc_plan {
  const fl_conc_process *processes;
  size_t process_count;
  const fl_conc_supervisor *supervisors;
  size_t supervisor_count;
  const fl_conc_run_spec *runs;
  size_t run_count;
  fl_conc_call call;
} fl_conc_plan;

/* ───────────────────────────── итог прогона ─────────────────────────────
   Всё, что наблюдаемо снаружи, — и ничего больше. Числа здесь `double`, потому
   что виртуальное время в модели — число flang, а число flang это IEEE-754:
   считать его в size_t значило бы завести второй вид арифметики рядом с
   первым. */

/** Одна запись журнала доставок: один пробег обработчика. */
typedef struct fl_conc_entry {
  double time;
  size_t process;      /* индекс в plan->processes */
  const char *outcome; /* «обработано» | «отложено» | «продолжено» | … */
  const char *code;    /* NULL, если отказа не было */
  const char *reason;  /* текст отказа; NULL, если отказа не было */
  fl_value message;    /* доставленное сообщение */
} fl_conc_entry;

typedef struct fl_conc_failure {
  size_t process;
  const char *code;
  const char *reason;
  double time;
} fl_conc_failure;

/** Решение надзора: по записи на каждый затронутый процесс, в порядке принятия. */
typedef struct fl_conc_decision {
  double time;
  size_t process;
  const char *supervisor;
  const char *strategy;
  const char *code;
} fl_conc_decision;

typedef struct fl_conc_result {
  /* «покой» | «предел пробегов» | «отказ дошёл доверху» — зависания нет ни в
     одном случае, и это требование контракта, а не удобство. */
  const char *outcome;
  double time;
  size_t turns;
  const fl_value *states; /* по процессу, в порядке объявления */
  const bool *alive;      /* по процессу, в порядке объявления */
  /* Журнал вели или нет. Признак нужен потому, что «ни одного пробега» и
     «пробеги были, но журнала не вели» дают одинаковые `journal_count == 0`, а
     это разные вещи: по журналу сверяются с эталоном побайтово, и сверка,
     сравнившая пустоту с пустотой, промолчала бы вместо того, чтобы покраснеть. */
  bool journal_kept;
  const fl_conc_entry *journal;
  size_t journal_count;
  const fl_conc_failure *failures;
  size_t failure_count;
  const fl_conc_decision *decisions;
  size_t decision_count;
} fl_conc_result;

/** Сколько пробегов планировщик делает, прежде чем сдаться (как у эталона). */
#define FL_CONC_MAX_TURNS 10000

/**
 * Один прогон: разнести входные сообщения, крутить пробеги, снять итог.
 *
 * `max_turns` в 0 означает `FL_CONC_MAX_TURNS`. FL_ERROR возвращается только на
 * том, что к модели отношения не имеет, — нет такого прогона, кончилась память,
 * не построилось начальное состояние. Отказ ПРОЦЕССА ошибкой не является:
 * он записан в итоге, потому что отказ обязан кончаться исходом, а не статусом.
 *
 * `journal` — вести ли журнал доставок. Это НАБЛЮДЕНИЕ, а не работа, и стоит
 * оно памяти на каждом пробеге: арена не возвращает ничего, поэтому долгий
 * процесс с журналом течёт тем быстрее, чем дольше живёт. В режиме прогона
 * журнал обязателен — по нему идёт побайтовая сверка с эталоном, — в рабочем
 * режиме он не нужен вовсе. На наблюдаемое поведение он не влияет ничем: те же
 * исходы, те же состояния, те же решения надзора при том же семени.
 */
fl_status fl_conc_run(fl_ctx *ctx, const fl_conc_plan *plan, const char *run, double seed, size_t max_turns,
                      bool journal, fl_conc_result *out, fl_error *error);

/** Индекс процесса по имени; SIZE_MAX — нет такого. Нужен прогонщику. */
size_t fl_conc_find(const fl_conc_plan *plan, const char *name);

#endif /* FLANG_CONC_H */
