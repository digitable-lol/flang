void fl_watch_open(fl_ctx *ctx);

/**
 * Имя шага, которым хозяин назвал бы всю работу целиком («Ведомость
 * исходников», «Шаг плана»). Снимок печатает его отдельной строкой, когда оно
 * отличается от имени идущей функции. NULL стирает.
 */
void fl_watch_step(const char *name);

/**
 * Спрашивали ли с прошлого раза. Читает И СБРАСЫВАЕТ: хозяин, у которого есть
 * безопасное место (граница витка плана, конец шага), отвечает там подробнее,
 * чем вправе обработчик сигнала. Обработчик отвечает сразу и сам — эти два
 * ответа не заменяют друг друга: тесный расчёт до границы витка не дойдёт.
 */
bool fl_watch_asked(void);

/**
 * Строка «повторить» — готовый вызов, которым этот расчёт начался.
 *
 * Ставит её тот, кто знает команду целиком. Рантайм собирает её сам только в
 * двери программы (`fl_check_entry`), и там ему известны имя и доводы, но не
 * файл: файл знает хозяин. `flang run` ставит сюда всю строку, и снимок
 * подключения печатает вызов, который можно вставить и повторить.
 *
 * NULL стирает. Длиннее буфера — обрезается, и обрезанное видно многоточием.
 */
void fl_watch_repeat_set(const char *line);

/* ── печать без stdio: то, что законно внутри обработчика сигнала ──
 *
 * Общее на рантайм и на хозяев. Числа пробелами по три разряда, память —
 * двоичными приставками, как её называет остальное дерево. Своего разбора у
 * хозяина быть не должно: разойдись эти две печати, одно и то же число
 * выглядело бы в двух строках по-разному. */
size_t fl_say_text(char *out, size_t room, size_t at, const char *text);
size_t fl_say_number(char *out, size_t room, size_t at, unsigned long value);
size_t fl_say_size(char *out, size_t room, size_t at, unsigned long bytes);

/** Сколько памяти держит процесс, байтами. 0 — узнать нечем (нет /proc). */
unsigned long fl_say_resident(void);

/** Размер страницы, снятый ВНЕ обработчика: `sysconf` внутри сигнала незаконен. */
void fl_say_page_ready(void);

