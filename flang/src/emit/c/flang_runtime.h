/*
 * Арена плюс два счётчика: глубина и шаги. Ни один не украшение.
 *
 * Глубина: нехвостовая рекурсия в C идёт по настоящему стеку, и его
 * переполнение это не исключение, а падение процесса. Интерпретатор в том же
 * месте даёт FLANG_RECURSION_LIMIT, и сгенерированный код обязан давать его же.
 *
 * Шаги: обычная (не тотальная) функция flang может не завершаться, и глубину
 * при этом не растить — хвостовой самовызов и взаимная хвостовая рекурсия идут
 * в постоянной глубине. Интерпретатор ловит это лимитом шагов; без такого же
 * счётчика напечатанная программа в том же месте крутилась бы вечно. Ровно это
 * и делала: «Вечность» из курса собиралась и зависала.
 *
 * Оговорка о шаге. Шаг интерпретатора — итерация его машины, а не применение
 * функции: одно применение стоит там многих шагов. Здесь шагом считается вход в
 * функцию, виток цикла хвостового самовызова и отскок батута. Значит счётчик
 * здесь всегда МЕНЬШЕ счётчика интерпретатора на том же вычислении, и при
 * одинаковом пределе интерпретатор упирается в лимит первым. Расхождение
 * одностороннее и безопасное: напечатанный код не объявит исчерпанным то, что
 * интерпретатор досчитал до конца. Тот же порядок выбран в бэкендах Go, Rust и
 * Python — иначе три из пяти целей печати расходились бы с двумя.
 *
 * Стек: третье поле того же прибора, а не третий прибор. Счётчик глубины считает
 * КАДРЫ, а несёт их стек, и сколько их влезет — зависит от программы: замер
 * холодными процессами при стеке 8 МиБ дал 23 807 кадров у функции с одним
 * параметром и 1 518 у функции с сорока связываниями (5 526 байт на кадр против
 * 352 — разница шестнадцатикратная). При объявленном пределе 10 000 вторая
 * умирала по SIGSEGV — без кода, без текста, без возможности перехвата, — то
 * есть объявленный предел глубины пределом НЕ БЫЛ.
 * Поэтому `fl_enter` — та же и единственная точка, где сходятся все пределы, —
 * смотрит ещё и на то, сколько стека осталось, и переводит его исчерпание в
 * объявленный FLANG_RECURSION_LIMIT. Заводить для стека отдельный механизм
 * незачем: место проверки одно, вид отказа один, набор видов отказа закрыт.
 */
typedef struct fl_ctx {
  fl_arena *arena;
  size_t depth;
  size_t max_depth;
  size_t steps;
  size_t max_steps;
  /*
   * Сторож стека. `stack_base` — отметка, снятая на входе в расчёт
   * (`fl_ctx_init`); `stack_room` — сколько байт стека под ней, 0 выключает
   * сторожа. `stack_step` — наибольшая измеренная толщина ОДНОГО кадра этой
   * программы: запас под последним входом обязан быть не меньше нескольких
   * таких кадров, иначе между двумя проверками стек кончится у программы с
   * толстым кадром, а именно она и падала.
   */
  const char *stack_base;
  size_t stack_room;
  size_t stack_seen;
  size_t stack_step;
} fl_ctx;

void fl_ctx_init(fl_ctx *ctx, fl_arena *arena);

