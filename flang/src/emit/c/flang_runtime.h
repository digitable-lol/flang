/**
 * Снимает отметку арены и объявляет область открытой. Стоит ровно пять
 * присваиваний: всё, что дороже, делает `fl_region_close`, и только когда
 * есть за что платить.
 */
fl_mark fl_region_open(fl_ctx *ctx);

/**
 * Закрывает область: перекладывает результат вниз и отдаёт всё остальное.
 *
 * Возвращает `status` вызывающему как есть — область НИКОГДА не превращает
 * удачный расчёт в отказ и никогда не меняет ответ. Если переложить нельзя или
 * невыгодно, она просто не делает ничего (полный список случаев — над
 * реализацией). Единственное исключение — FLANG_MEMORY, если памяти не хватило
 * уже на самой перекладке; там отказ честнее молчания.
 *
 * `status` — то, чем кончилось тело. При отказе откат не делается: текст
 * диагностики лежит в арене выше отметки.
 */
fl_status fl_region_close(fl_ctx *ctx, fl_mark mark, fl_status status, fl_value *result, fl_error *error);

/**
 * Закрывает область и тут же открывает её заново той же отметкой.
 *
 * Нужна одному месту — накопителю свёртки (см. `fl_region_recycle` в
 * flang_runtime.c). Одним `fl_region_close` тут не обойтись: он возвращает
 * границу ОБЪЕМЛЮЩЕЙ области, и второй виток цикла пошёл бы без сторожа —
 * `fl_arena_extend` продлил бы на месте блок, лежащий ниже отметки, а его
 * вот-вот откатят.
 */
fl_status fl_region_recycle(fl_ctx *ctx, fl_mark mark, fl_value *result, fl_error *error);

/*
 * Виток вычисления: вход в функцию, оборот цикла хвостового самовызова, отскок
 * батута. Считается отдельно от глубины — хвостовая рекурсия глубину не растит,
 * но завершаться от этого не начинает. Предел 0 отключает счёт.
 *
 * Имя `fl_tick`, а не `fl_step`: `fl_step` уже занят типом функции-шага батута
 * ниже, и второй смысл у того же имени читался бы как ошибка.
 */
fl_status fl_tick(fl_ctx *ctx, const char *function, fl_error *error);

/*
 * Витки цикла по списку: заряд на `count` витков разом, без отказа.
 *
 * Зовёт её `fl_require_list` — вход всех трёх циклов по списку. Отказа здесь
 * нет намеренно: имени объемлющей функции у рантайма нет, а текст отказа обязан
 * называть её дословно как толкователь. Предел ловит ближайший `fl_tick`;
 * подробности и замер — у `fl_charge` в flang_runtime.c.
 */
void fl_charge(fl_ctx *ctx, size_t count);

/*
 * Ранний возврат по ошибке. Сгенерированный код состоит из него на треть,
 * поэтому макрос: без него каждая строка обросла бы четырьмя.
 */
#define FL_TRY(expression)                 \
  do {                                     \
    const fl_status fl_try_status_ = (expression); \
    if (fl_try_status_ != FL_OK) {         \
      return fl_try_status_;               \
    }                                      \
  } while (0)

