/* ───────────────────────────── арена ───────────────────────────── */

typedef struct fl_chunk fl_chunk;

typedef struct fl_arena {
  fl_chunk *chunks;  /* односвязный список всех купленных кусков */
  fl_chunk *current; /* кусок, из которого идёт выдача */
  size_t reserved;   /* сколько байт всего куплено у malloc */
  /*
   * Сколько байт сейчас выдано и ещё не откачено. Растёт на каждой выдаче,
   * падает до отметки на откате, обнуляется на reset. Нужен ровно одному —
   * `fl_region_close`, чтобы одним вычитанием узнать, сколько наросла область,
   * и решить, окупится ли откат. Обходить куски ради этого было бы дороже
   * самой области.
   */
  size_t handed;
  /*
   * Нижняя граница ближайшей ОТКРЫТОЙ области: (кусок, занято в нём). NULL в
   * `guard_chunk` означает «областей нет» — тогда граница не сторожит ничего.
   * Смотрит на неё только `fl_arena_extend`: продлить на месте блок, лежащий
   * ниже границы, нельзя (объяснение — там же).
   */
  fl_chunk *guard_chunk;
  size_t guard_used;
  /*
   * Буфер под перекладывание результата при откате. Живёт между откатами, чтобы
   * не покупать его у malloc на каждом вызове, и отдаётся системе в
   * `fl_arena_release` — иначе valgrind насчитал бы недостижимое.
   */
  char *staging;
  size_t staging_size;
  /*
   * Отказная памятка обмера: одно доказанное «этому значению мало столько-то».
   * Заполняется `fl_region_close`/`fl_region_recycle` при отказе обмера, читается
   * самим обмером. Разбор — над `fl_region_deny` в flang_runtime.c.
   */
  struct fl_deny *deny;
  /*
   * ОТСТУП ОБМЕРА В СВЁРТКЕ: при какой наросшей величине пробовать обмер снова
   * и для какой области это записано.
   *
   * Зачем. `fl_region_recycle` зовётся на КАЖДОМ витке свёртки и обмеряет живое
   * с бюджетом «наросло ÷ 16». У свёртки-накопления обмер отказывает всегда, но
   * «наросло» растёт с каждым витком — значит растёт и бюджет, и обмер на витке
   * k стоит O(k). Сумма по всем виткам — КВАДРАТ, и платит его любая свёртка с
   * растущим накопителем, какой бы дешёвый алгоритм в ней ни стоял.
   *
   * Лечение: после отказа не пробовать снова, пока наросшее не удвоится. Тогда
   * попытки идут при G, 2G, 4G…, их суммарная цена — около 2N/16, то есть
   * ЛИНЕЙНАЯ. Платой за это идёт отложенная уборка: между попытками область
   * может вырасти вдвое сверх той, при которой откат случился бы сразу.
   */
  size_t recycle_mark;
  size_t recycle_next;
  /* Каким куском покупать в следующий раз. Раньше это была одна константа на
     все арены сразу (64 КиБ), и для главной арены она правильна: программа,
     считающая список, берёт куски пачками, и мелкие куски означали бы поход к
     malloc на каждый шаг.

     Для КУЧИ ПРОЦЕССА она в триста раз велика. Замер планировщика
     (`docs/scheduler-benchmark.md`, раздел 2) назвал цену числом: 131 062
     байта на работающий процесс, ровно два куска по 64 КиБ — по одному на
     половину кучи, — притом что типичный процесс держит запись из двух полей.
     Отсюда поле вместо константы: `fl_arena_init_small` заводит арену с мелким
     первым куском, а дальше кусок УДВАИВАЕТСЯ до общего минимума, поэтому
     процесс, которому и правда нужны килобайты, доходит до них за десяток
     покупок, а не платит за них с рождения. */
  size_t least;
} fl_arena;

/*
 * Отметка арены: точка, к которой можно вернуть всё выданное после неё.
 * Снимается `fl_region_open`, предъявляется `fl_region_close`. Лежит на стеке
 * вызывающего — своей памяти у отметки нет.
 */
typedef struct fl_mark {
  fl_chunk *chunk;       /* кусок, из которого шла выдача на отметке */
  size_t used;           /* сколько в нём было занято */
  size_t handed;         /* сколько всего было выдано ареной */
  fl_chunk *guard_chunk; /* граница ОБЪЕМЛЮЩЕЙ области — восстановить на выходе */
  size_t guard_used;
} fl_mark;

/** Арену можно держать на стеке: init/release, без выделения под саму арену. */
void fl_arena_init(fl_arena *arena);

/**
 * Та же арена, но первый кусок — `least` байт, а не общий минимум.
 *
 * Заведена ради куч процессов (`flang_conc.c`): их у прогона две на процесс, и
 * при миллионе процессов разница между 64 КиБ и полукилобайтом — это разница
 * между ста сорока шестью гигабайтами адресного пространства и одним.
 * Ноль и всё, что больше общего минимума, означают обычную арену.
 */
void fl_arena_init_small(fl_arena *arena, size_t least);

/** Выдаёт выровненный блок; NULL — кончилась память (единственная причина). */
void *fl_arena_alloc(fl_arena *arena, size_t size);

/**
 * Продлевает на месте блок, выданный последним. Если `block` длиной `size` —
 * ровно то, что арена отдала в последний раз, и в том же куске лежит ещё
 * `extra` байт, блок вырастает без копирования и функция даёт true; иначе она
 * не меняет ничего и даёт false. Всё, что арена умеет отменить, — это
 * последняя выдача, поэтому продление и ограничено ею.
 *
 * Нужна ровно одному месту — «добавить» (см. fl_b_dobavit): накопление списка
 * в цикле не выделяет ничего, пока хватает куска.
 */
bool fl_arena_extend(fl_arena *arena, const void *block, size_t size, size_t extra);

/** Освобождает всё выданное, но оставляет куски себе: следующий вызов дешевле. */
void fl_arena_reset(fl_arena *arena);

/** Возвращает память системе. После неё арена снова пригодна к fl_arena_init. */
void fl_arena_release(fl_arena *arena);

/* ───────────────────────────── значения ───────────────────────────── */

typedef enum fl_tag {
  FL_NOTHING = 0, /* «ничто» */
  FL_NUMBER,      /* число — IEEE-754 double, как в ядре FTS */
  FL_FLAG,        /* признак */
  FL_STRING,      /* строка — UTF-8, длина в байтах и в кодовых точках */
  FL_LIST,        /* список — однородный по типу, но не по представлению */
  FL_RECORD,      /* запись — объект FTS */
  FL_VARIANT      /* вариант — конструктор суммы типов */
} fl_tag;

typedef struct fl_value fl_value;
typedef struct fl_field fl_field;
typedef struct fl_record fl_record;
typedef struct fl_variant fl_variant;

/*
 * Запас массива списка — с ДВУХ концов: сколько в нём ячеек всего, сколько
 * занято за концом списка и сколько свободно перед его началом. Устройство
 * спрятано в flang_runtime.c — снаружи это непрозрачная пометка «этот список
 * можно удлинить, не копируя»; правило, по которому удлинение остаётся
 * безопасным, объяснено над `fl_b_dobavit` и работает в обе стороны:
 * «добавить» занимает ячейку за концом, «приписать» — перед началом.
 */
typedef struct fl_grow fl_grow;

struct fl_value {
  fl_tag tag;
  union {
    double number;
    bool flag;
    struct {
      /* НЕ обязана заканчиваться нулём: подстрока и хвост — это срезы. */
      const char *utf8;
      size_t bytes;
      size_t points;
    } string;
    struct {
      const fl_value *items;
      size_t count;
      /* Запас за концом и перед началом; NULL — запаса нет, «добавить» и
         «приписать» скопируют. Поле не наблюдаемо: равенство, длина и печать
         смотрят только на items и count. Ширину значения оно не меняет —
         строка и без него занимает три слова. */
      fl_grow *grow;
    } list;
    const fl_record *record;
    const fl_variant *variant;
  } as;
};

/* Имена полей всегда заканчиваются нулём: они приходят из модели, а не из
   данных, и печатаются в диагностиках через %s. */
struct fl_field {
  const char *name;
  fl_value value;
};

struct fl_record {
  size_t count;
  const fl_field *fields;
};

struct fl_variant {
  const char *name;
  size_t count;
  const fl_field *fields;
};

