// Поле записи или варианта: имя из модели и значение.
//
// Именно массив пар, а не Dictionary: порядок полей наблюдаем — он попадает в
// текст диагностики («запись {цена, количество}») и в размеченный JSON
// прогонщика, а тексты сверяются с интерпретатором дословно. Полей у записи
// единицы, и линейный поиск по массиву дешевле хеширования кириллической
// строки; равенство же записей и так идёт по именам, а не по порядку
// (Value.FieldsEqual).
//
// readonly struct, а не class, — и это ровно тот случай, где структура
// уместна, в отличие от самого Value (см. Value.cs): пара из двух ссылок
// занимает шестнадцать байт, состояния по умолчанию у неё не бывает (массив
// полей строится целиком либо не строится вовсе), и рекурсии в ней нет.
#nullable enable

/// <summary>Поле записи или варианта.</summary>
public readonly struct Field
{
    /// <summary>Имя поля — как в модели flang, кириллицей и с пробелами.</summary>
    public readonly string Name;

    /// <summary>Значение поля.</summary>
    public readonly Value Value;

    public Field(string name, Value value)
    {
        Name = name;
        Value = value;
    }
}
