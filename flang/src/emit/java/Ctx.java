/**
 * Счётчики пределов и настройка индексации строк.
 *
 * Пределы — не украшение. Обычная (не тотальная) функция flang может не
 * завершаться, и интерпретатор ловит это лимитом шагов и глубины. Без счётчиков
 * напечатанная программа в том же месте либо крутилась бы вечно, либо падала бы
 * по стеку — то есть давала бы не FLANG_RECURSION_LIMIT, а зависание или
 * StackOverflowError.
 *
 * ── Предел стека JVM не имеет права подменять предел языка ──────────────────
 * У потока JVM стек задан при создании (по умолчанию около мегабайта, ключ
 * -Xss), и глубина 10⁴ кадров напечатанного кода в него не помещается: кадр
 * несёт контекст, параметры и временные. StackOverflowError при этом — не
 * диагностика языка, а Error, который вылетает в произвольной точке и может
 * оставить любую промежуточную структуру недостроенной. Поэтому прогонщик
 * считает вычисление в потоке с явно заданным большим стеком
 * (Flang.withDeepStack), а предел глубины считает этот класс — и упирается в
 * него первым, там же, где интерпретатор.
 *
 * ── Оговорка о шаге ─────────────────────────────────────────────────────────
 * Шаг интерпретатора — итерация его машины, а не вызов функции: одно применение
 * функции стоит там многих шагов. Здесь шагом считается вход в функцию, виток
 * цикла хвостового самовызова и отскок батута. Значит счётчик здесь всегда
 * МЕНЬШЕ счётчика интерпретатора при том же вычислении, и при одинаковом
 * пределе интерпретатор упирается в лимит первым. Расхождение одностороннее и
 * безопасное: напечатанный код не объявит исчерпанным то, что интерпретатор
 * досчитал до конца.
 */
public final class Ctx {

  /** Значения по умолчанию — те же, что у интерпретатора (interpret.mjs). */
  public static final int DEFAULT_MAX_DEPTH = 10000;
  public static final long DEFAULT_MAX_STEPS = 1000000L;
  public static final int DEFAULT_INDEX_BASE = 1;

  /** База индексации строк: 1 (SPEC, раздел 5) либо 0, если так напечатали. */
  public int indexBase = DEFAULT_INDEX_BASE;
  /** Предел глубины вызовов; 0 и меньше — предела нет. */
  public int maxDepth = DEFAULT_MAX_DEPTH;
  /** Предел шагов; 0 и меньше — предела нет. */
  public long maxSteps = DEFAULT_MAX_STEPS;

  /** Текущая глубина вызовов. */
  public int depth;
  /** Сделано шагов. */
  public long steps;

  /** Вход в функцию, способную к рекурсии. */
  public void enter(String function) {
    step(function);
    if (maxDepth > 0 && depth + 1 > maxDepth) {
      throw new FlangError(
          FlangError.CODE_RECURSION_LIMIT,
          "функция «" + function + "» превысила предел глубины вызовов (" + maxDepth
              + ") на глубине " + (depth + 1));
    }
    depth += 1;
  }

  /**
   * Выход из функции.
   *
   * Вызывается и на ошибке (через finally): счётчик глубины обязан вернуться
   * назад, иначе первая же пойманная ошибка навсегда съела бы предел.
   */
  public void leave() {
    depth -= 1;
  }

  /**
   * Виток вычисления: вход в функцию, цикл самовызова, отскок батута.
   *
   * Считается отдельно от глубины: хвостовая рекурсия глубину не растит, но
   * завершаться от этого не начинает.
   */
  public void step(String function) {
    steps += 1;
    if (maxSteps > 0 && steps > maxSteps) {
      throw new FlangError(
          FlangError.CODE_RECURSION_LIMIT,
          "функция «" + function + "» исчерпала лимит шагов (" + maxSteps
              + ") на глубине вызовов " + depth);
    }
  }
}
