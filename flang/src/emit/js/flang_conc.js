/* ── планировщик конкурентности: процессы, ящики, надзор ──
   Печатается целиком и только программе, у которой есть процессы. Это ПОРТ
   свидетеля (`flang/src/conc.mjs`, `runConcurrent`) на представление значений
   напечатанного модуля, а не второй планировщик: строчки свидетеля стоят здесь в
   том же порядке, с теми же именами и теми же исходами, потому что на одном
   семени журнал доставок обязан совпасть со свидетельским ПОБАЙТОВО
   (`flang/test/emit-js-conc.test.mjs`).

   Чем этот планировщик отличается от свидетельского по устройству:

     • обработчик — обычная функция этого модуля, а не вызов интерпретатора.
       Поэтому плану отдаётся сама функция, а не её имя: искать функцию по имени
       в напечатанном модуле было бы вторым словарём рядом с уже существующим;
     • витки считает не свой счётчик, а ОБЩИЙ счётчик модуля (`$step` из
       рантайма, `emit/js.mjs`): вход в функцию, способную к рекурсии, оборот
       хвостового цикла и шаг батута. Планировщик только ставит ему предел на
       время пробега и читает показание. Второй счётчик здесь означал бы два
       разных числа предела в одном модуле — обработчик отказал бы по одному
       прибору, досчитав по другому, — и разъезд был бы молчаливым: пределы
       названы в разных местах, а виток у них один и тот же. Единица КРУПНЕЕ,
       чем виток интерпретатора, ровно как в C (`flang_runtime.c`, `fl_tick`), и
       расхождение от этого одностороннее: напечатанное не объявит исчерпанным
       то, что свидетель досчитал;
     • конкурентность здесь есть, а параллелизма нет и не будет: один поток.
       Это записано машиночитаемо (таблица возможностей цели в выводе `emit`), а
       не абзацем в спецификации. Наблюдаемая семантика от этого не страдает:
       набор возможных исходов определён ЧЕРЕДОВАНИЕМ, а не числом ядер, и
       чередование здесь выбирает семя.

   Чего здесь нет намеренно: горячей замены (`hotswap.mjs`) и вытеснения по
   кванту. Оба — свойства свидетеля, и у напечатанного C их тоже нет; журнал
   доставок от их отсутствия не меняется ни на байт. */

/* Запас витков ТОТАЛЬНОГО обработчика и всякого, у кого запас не назван.
   То же число, что у свидетеля (`TOTAL_HANDLER_STEPS`) и у C
   (`FL_CONC_TOTAL_STEPS`): тотальность даёт завершение, но не даёт срока, и
   предел здесь настоящий, а не формальный. */
const $КОНК_ЗАПАС_ТОТАЛЬНОГО = 1000000

/** Сколько пробегов обработчика планировщик делает, прежде чем сдаться. */
const $КОНК_ПРОБЕГОВ = 10000

/** Причина остановки, которая НЕ отказ (свидетель, `NORMAL_STOP`; в BEAM `:normal`). */
const $КОНК_НОРМА = "норма"

/** Действия, которые планировщик умеет исполнять. Список — часть контракта. */
const $КОНК_ДЕЙСТВИЯ = ["отправить", "через", "остановить", "отложить", "продолжить"]

/**
 * Код отказа из ошибки: свои несут `code`, чужие — нет.
 *
 * `RangeError` здесь НЕ разбирается, и это не забывчивость. Переполнение стека
 * JS — предел ГЛУБИНЫ, и переводит его в объявленный FLANG_RECURSION_LIMIT одно
 * место на весь модуль: `$hostDepth` на границе расчёта (`$top`), через которую
 * пробег обработчика и идёт. Два перевода одного и того же означали бы два
 * правила, расходящихся молча: у `$hostDepth` правило строже — он не называет
 * пределом глубины `RangeError`, пришедший с двух кадров, потому что у движка
 * есть свои `RangeError` (длина строки, длина массива), и врать про предел
 * нельзя. Сильным должно быть одно правило, а не два.
 */
function $concКод(ошибка) {
  if (ошибка !== null && typeof ошибка === "object" && typeof ошибка.code === "string") return ошибка.code
  return "FLANG_INTERNAL"
}

function $concТекст(ошибка) {
  return ошибка instanceof Error ? ошибка.message : String(ошибка)
}

/**
 * Генератор чередований из семени (mulberry32).
 *
 * Тот же, что у свидетеля и у C, до последнего бита: одно семя обязано давать один
 * журнал доставок во всех трёх местах, иначе сверять было бы нечего.
 */
function $concСлучайное(семя) {
  let состояние = (Math.trunc(семя) >>> 0) || 0x9e3779b9
  return () => {
    состояние = (состояние + 0x6d2b79f5) >>> 0
    let t = состояние
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/**
 * Дерево надзора: кто над кем и кого поднимать при перезапуске поддерева.
 *
 * Порт `построитьНадзор` свидетеля строка в строку, включая правило «первое
 * объявление выигрывает»: круг и двойной надзор отвергает проверка типов, но
 * планировщик обязан вести себя определённо и на неразобранном плане.
 */
function $concНадзор(план, процессы) {
  const объявленные = план.надзоры
  const надзоры = new Map()
  const надПроцессом = new Map()
  const надНадзором = new Map()

  for (const узел of объявленные) {
    if (надзоры.has(узел.имя)) continue
    надзоры.set(узел.имя, { узел, отказы: [] })
  }
  for (const узел of объявленные) {
    for (const [процесс, стратегия] of узел.процессы) {
      if (!надПроцессом.has(процесс)) надПроцессом.set(процесс, { надзор: узел.имя, стратегия })
    }
    for (const [вложенный, стратегия] of узел.вложенные) {
      if (вложенный !== узел.имя && !надНадзором.has(вложенный)) {
        надНадзором.set(вложенный, { надзор: узел.имя, стратегия })
      }
    }
  }

  /* Поддерево — процессы в порядке объявления, сначала свои, потом чужие через
     вложенные надзоры. Порядок важен так же, как везде: по нему идут записи в
     журнале решений, а журнал сверяется побайтово. */
  const подопечные = (имя, виденные = new Set()) => {
    if (виденные.has(имя)) return []
    виденные.add(имя)
    const узел = надзоры.get(имя)?.узел
    if (узел === undefined) return []
    const собранные = []
    for (const [процесс] of узел.процессы) {
      if (процессы.has(процесс) && !собранные.includes(процесс)) собранные.push(процесс)
    }
    for (const [вложенный] of узел.вложенные) {
      for (const дальше of подопечные(вложенный, виденные)) {
        if (!собранные.includes(дальше)) собранные.push(дальше)
      }
    }
    return собранные
  }

  return { надзоры, надПроцессом, надНадзором, подопечные }
}

/**
 * Прогон программы: процессы, ящики, виртуальное время, семя.
 *
 * @param {object} план план конкурентности этого модуля (`concPlan()`)
 * @param {string} имяПрогона имя объявленного прогона
 * @param {{ семя?: number, пробегов?: number, журнал?: boolean }} [настройки]
 * @returns {object} итог: исход, состояния, живые, отказы, решения, наверх,
 *   время, пробегов, витки и — если не отключён — журнал доставок.
 */
function $concПрогон(план, имяПрогона, настройки = {}) {
  const объявленный = план.прогоны.find((прогон) => прогон.имя === имяПрогона)
  if (объявленный === undefined) {
    $fail("FLANG_PROCESS", `прогона «${имяПрогона}» в программе нет; объявлены: ${
      план.прогоны.map((прогон) => `«${прогон.имя}»`).join(", ") || "ни одного"}`)
  }
  const семя = Number.isFinite(настройки.семя) ? Math.trunc(настройки.семя) : объявленный.семя
  const пределПробегов = Number.isInteger(настройки.пробегов) && настройки.пробегов > 0
    ? настройки.пробегов
    : $КОНК_ПРОБЕГОВ
  /* Журнал — НАБЛЮДЕНИЕ, и в рабочем режиме он не нужен: за него платится
     памятью на каждом пробеге. Выключенный журнал — это ОТСУТСТВИЕ поля, а не
     пустой список: пустой список означал бы «пробегов не было», и сверка,
     сравнив пустоту с пустотой, промолчала бы вместо того, чтобы покраснеть. */
  const вестиЖурнал = настройки.журнал !== false

  if (план.процессы.length === 0) {
    $fail("FLANG_PROCESS", "в программе нет ни одного процесса: прогонять нечего")
  }

  /* Порядок объявления — единственный порядок, в котором процессы
     перечисляются где бы то ни было: очередь готовых, итоговые состояния, отчёт
     о прогоне. Один порядок на всё — условие того, чтобы журнал зависел от
     семени и больше ни от чего. */
  const порядок = план.процессы.map((узел) => узел.имя)
  const процессы = new Map()
  for (const узел of план.процессы) {
    /* Начальное состояние вычисляется РОВНО ОДИН РАЗ. Функция без параметров
       чиста, поэтому пересчёт дал бы то же значение; но храня его, мы делаем
       обещание контракта буквальным: перезапуск возвращает не «такое же», а то
       же самое значение, что было при первом запуске. */
    let начальное = null
    try {
      начальное = узел.завести()
    } catch (ошибка) {
      /* Процесса ещё нет, надзирать не над кем — это отказ ПРОГРАММЫ, и он
         обязан быть назван, а не прийти анонимным исключением из чужого кода.
         Проверка (`types.mjs`, `FLANG_INITIAL_FAILURE`) такую программу
         отвергает; здесь — определённое поведение, если её собрали мимо
         проверки. */
      $fail(
        "FLANG_PROCESS",
        `начальное состояние «${узел.начало}» процесса «${узел.имя}» отказало ` +
          `(${$concКод(ошибка)}): ${$concТекст(ошибка)}`,
      )
    }
    процессы.set(узел.имя, {
      узел,
      начальное,
      состояние: начальное,
      ящик: [],
      /* Отметка «это сообщение уже трогали» — по одной на место в ящике, в том
         же порядке. Здесь она нужна не барьеру замены (замены нет), а тому же,
         чему в свидетеле: различить сообщение, вернувшееся недоделанным, от
         нетронутого. Массив, а не пометка на значении: два одинаковых числа в
         ящике — два разных места. */
      начатые: [],
      жив: true,
      причина: null,
      /* Потолок ящика: `null` — неограничен. Ноль в плане значит «неограничен»,
         а не «ни одного сообщения»: ящик в ноль сообщений проверка типов не
         пропускает, поэтому два смысла нуля здесь не сталкиваются. */
      потолок: Number.isInteger(узел.ящик) && узел.ящик > 0 ? узел.ящик : null,
      /* Мест занято письмами, которые ещё не пришли («через»). Место занимается
         в тот момент, когда действие выполнено, а не когда таймер сработал:
         иначе переполнение случалось бы вне пробега — в тишине, между
         процессами, — и отказывать было бы некому. */
      вЛёте: 0,
    })
  }

  const журнал = []
  const отказы = []
  const решения = []
  const витки = []
  let наверх = null
  let время = 0
  let пробегов = 0
  const таймеры = []
  const случайное = $concСлучайное(семя)
  const надзор = $concНадзор(план, процессы)

  /**
   * Положить сообщение в ящик. Три исхода, и все три названы.
   *
   * `легло` — положено. `некому` — адресата нет или он мёртв; это НЕ ошибка
   * отправителя, он не обязан знать, что адресат остановился, ровно как в BEAM.
   * `полон` — ящик объявлен ограниченным и в нём нет места: отказывает
   * ОТПРАВИТЕЛЬ, потому что молча потерять сообщение — худший из исходов.
   */
  const положить = (имя, сообщение, вПередЯщика, местоЗанято = false, начатое = false) => {
    const процесс = процессы.get(имя)
    if (процесс === undefined || !процесс.жив) return "некому"
    if (!местоЗанято && процесс.потолок !== null &&
        процесс.ящик.length + процесс.вЛёте >= процесс.потолок) {
      return "полон"
    }
    if (вПередЯщика) {
      процесс.ящик.unshift(сообщение)
      процесс.начатые.unshift(начатое)
    } else {
      процесс.ящик.push(сообщение)
      процесс.начатые.push(начатое)
    }
    return "легло"
  }

  for (const [кому, сообщение] of объявленный.вход()) {
    /* Переполнение «дано» отвергает проверка типов: сколько сообщений названо,
       столько и ляжет, и посчитать это можно до прогона. Здесь — определённое
       поведение, если план собрали мимо проверки. */
    if (положить(кому, сообщение, false) === "полон") {
      $fail(
        "FLANG_PROCESS",
        `«дано» переполняет ящик процесса «${кому}»: объявлен на ${процессы.get(кому).потолок}`,
      )
    }
  }

  const срокТаймеров = () => {
    let срок = null
    for (const таймер of таймеры) {
      if (срок === null || таймер.время < срок) срок = таймер.время
    }
    return срок
  }

  const выдатьТаймеры = () => {
    /* Порядок при равном сроке — порядок постановки: два таймера на одно и то
       же время не соревнуются, иначе журнал зависел бы от сортировки. */
    for (let i = 0; i < таймеры.length; ) {
      if (таймеры[i].время > время) {
        i += 1
        continue
      }
      const таймер = таймеры.splice(i, 1)[0]
      /* Место было занято ещё при выполнении «через», поэтому здесь оно только
         освобождается и тут же заполняется: переполниться этот путь не может по
         построению. */
      if (таймер.занято === true) процессы.get(таймер.кому).вЛёте -= 1
      положить(таймер.кому, таймер.что, false, таймер.занято === true)
    }
  }

  /* Перезапуск возвращает состояние и жизнь, и больше ничего: ящик и таймеры
     принадлежат доставке, а не процессу, и терять их было бы потерей данных без
     нужды. Сообщение, на котором процесс упал, при этом не возвращается — оно
     уже снято с ящика, и вечного цикла «упал — подняли — упал на том же» не
     выходит. */
  const перезапустить = (имя) => {
    const процесс = процессы.get(имя)
    процесс.состояние = процесс.начальное
    процесс.жив = true
    процесс.причина = null
  }

  const остановить = (имя, причина) => {
    const процесс = процессы.get(имя)
    процесс.жив = false
    процесс.причина = причина
  }

  /**
   * Порог отказов по виртуальному времени планировщика.
   *
   * «N за M миллисекунд» значит: пока отказов в окне не больше N, работает
   * стратегия, названная за процессом; отказ номер N+1 в том же окне уходит на
   * запасную. Окно скользящее: «три отказа за час» и «три отказа за всё время
   * работы» — разные утверждения, и надзор обязан их различать.
   */
  const порог = (узелНадзора, состояниеНадзора, базовая, когда) => {
    const правило = узелНадзора.порог
    if (правило === null || правило === undefined) return базовая
    состояниеНадзора.отказы = состояниеНадзора.отказы.filter((т) => т > когда - правило.окно)
    состояниеНадзора.отказы.push(когда)
    return состояниеНадзора.отказы.length > правило.отказов ? правило.иначе : базовая
  }

  /**
   * Отказ дошёл до надзора: кто решает и что из этого вышло.
   *
   * Возвращает `{ доверху }`: `доверху` значит, что «передать выше» упёрлось в
   * надзор, над которым никого нет, — тогда останавливается вся программа.
   * Решения дописываются в общий журнал, по записи на каждый затронутый
   * процесс: перезапуск поддерева обязан быть виден поимённо.
   */
  const применитьНадзор = (упавший, код, когда) => {
    let цель = { вид: "процесс", имя: упавший }
    const пройденные = new Set()
    for (;;) {
      const связь = цель.вид === "процесс"
        ? надзор.надПроцессом.get(цель.имя)
        : надзор.надНадзором.get(цель.имя)

      if (связь === undefined) {
        /* Процесс без надзора остаётся остановленным. Надзор, над которым
           никого нет, — конец программы: отказ обязан кончиться исходом, а не
           тем, что о нём забыли. */
        if (цель.вид === "процесс") return { доверху: false }
        наверх = { процесс: упавший, надзор: цель.имя, код, время: когда }
        return { доверху: true }
      }

      const состояниеНадзора = надзор.надзоры.get(связь.надзор)
      /* Круг в надзоре отвергает проверка типов; здесь — защита на случай плана,
         собранного мимо неё: круг обязан кончиться исходом, а не вечным циклом. */
      if (пройденные.has(связь.надзор)) {
        наверх = { процесс: упавший, надзор: связь.надзор, код, время: когда }
        return { доверху: true }
      }
      пройденные.add(связь.надзор)

      const стратегия = порог(состояниеНадзора.узел, состояниеНадзора, связь.стратегия, когда)

      if (стратегия === "передать выше") {
        решения.push({ время: когда, процесс: упавший, надзор: связь.надзор, стратегия, код })
        цель = { вид: "надзор", имя: связь.надзор }
        continue
      }

      const затронутые = цель.вид === "процесс" ? [цель.имя] : надзор.подопечные(цель.имя)
      for (const имяПроцесса of затронутые) {
        решения.push({ время: когда, процесс: имяПроцесса, надзор: связь.надзор, стратегия, код })
        if (стратегия === "перезапустить") перезапустить(имяПроцесса)
        else остановить(имяПроцесса, `остановлен надзором «${связь.надзор}»`)
      }
      return { доверху: false }
    }
  }

  /** Отклик обязан быть записью из нового состояния и списка действий. */
  const разобратьОтклик = (отклик, узел) => {
    if (отклик === null || typeof отклик !== "object" || Array.isArray(отклик)) {
      return `обработчик «${узел.обработчик}» вернул не запись отклика`
    }
    if (!Object.hasOwn(отклик, "состояние")) {
      return `отклик обработчика «${узел.обработчик}» не содержит поле «состояние»`
    }
    if (!Array.isArray(отклик["действия"])) {
      return `поле «действия» отклика обработчика «${узел.обработчик}» должно быть списком действий`
    }
    for (const действие of отклик["действия"]) {
      if (действие === null || typeof действие !== "object" || typeof действие.variant !== "string") {
        return `в списке «действия» обработчика «${узел.обработчик}» не действие`
      }
      if (!$КОНК_ДЕЙСТВИЯ.includes(действие.variant)) {
        return `неизвестное действие «${действие.variant}» в отклике обработчика «${узел.обработчик}»`
      }
    }
    return null
  }

  let исход = "покой"

  for (;;) {
    выдатьТаймеры()
    const готовые = порядок.filter((имя) => {
      const процесс = процессы.get(имя)
      return процесс.жив && процесс.ящик.length > 0
    })

    if (готовые.length === 0) {
      const срок = срокТаймеров()
      if (срок === null) break
      /* Тишина: скачок сразу к ближайшему сроку. Таймер на пять секунд в
         проверке не ждёт пяти секунд — он ждёт, когда планировщику станет
         нечего делать. */
      время = Math.max(время, срок)
      continue
    }

    if (пробегов >= пределПробегов) {
      исход = "предел пробегов"
      break
    }

    /* Единственное место, где решает семя. Всё остальное определено. */
    const имя = готовые[Math.floor(случайное() * готовые.length)]
    const процесс = процессы.get(имя)
    const сообщение = процесс.ящик.shift()
    процесс.начатые.shift()
    пробегов += 1

    const запись = { время, процесс: имя, сообщение, исход: "обработано" }
    if (вестиЖурнал) журнал.push(запись)

    const тотальный = процесс.узел.тотальный === true
    const запас = тотальный || !(процесс.узел.запас > 0)
      ? $КОНК_ЗАПАС_ТОТАЛЬНОГО
      : процесс.узел.запас

    /* Отказ этого пробега, если он случился: код и текст. Все три вида отказа
       из контракта сходятся сюда — исчерпание запаса, ошибка выполнения и явное
       «остановить» с ненормальной причиной, — чтобы дальше их обрабатывал один
       кусок кода. Три разных пути к надзору означали бы три разных поведения
       надзора, и они бы разошлись. */
    let отказ = null
    let отклик = null

    /* Предел ставится ОБЩЕМУ счётчику модуля, и на время одного пробега: своего
       счётчика у планировщика нет. Прежнее значение возвращается сразу после
       пробега — предел мог быть задан вызывающим (`$newContext`, ключ
       `--max-steps`), и съесть его пробегом значило бы менять поведение модуля
       вне прогона.

       Сам пробег идёт через `$top` — ту же границу расчёта, которую ставит вызов
       рекурсивной функции извне. Отсюда три вещи сразу, и все три нужны:
       счётчики витков и глубины сброшены на начало пробега; переполнение стека
       хозяина переведено в объявленный отказ ОДНИМ местом (`$hostDepth`); и
       граница уже стоит, поэтому внутренние вызовы её не ставят заново — иначе
       запас пробега обнулялся бы на каждой рекурсивной функции обработчика, и
       считалась бы не работа пробега, а последняя цепочка вызовов в нём. */
    const пределБыл = $maxSteps
    $maxSteps = запас
    try {
      отклик = $top(процесс.узел.вызвать, [процесс.состояние, сообщение], процесс.узел.обработчик)
    } catch (ошибка) {
      const код = $concКод(ошибка)
      /* Нетотальный обработчик, упёршийся в предел, — это «запас исчерпан», и
         код у него свой. Тотальный, упёршийся в тот же предел, — тот самый
         отказ, о котором говорит контракт: тотальность обещала завершение, но
         не обещала срока. */
      const бюджет = код === "FLANG_RECURSION_LIMIT" && !тотальный
      отказ = { код: бюджет ? "FLANG_BUDGET_EXHAUSTED" : код, сообщение: $concТекст(ошибка) }
      запись.исход = бюджет ? "запас исчерпан" : "отказ"
    }
    витки.push($steps)
    $maxSteps = пределБыл

    if (отказ === null) {
      const беда = разобратьОтклик(отклик, процесс.узел)
      if (беда !== null) {
        отказ = { код: "FLANG_PROCESS", сообщение: беда }
        запись.исход = "отказ"
      }
    }

    if (отказ === null) {
      процесс.состояние = отклик["состояние"]
      /* Пробег обработчика стоит единицу виртуального времени: без этого правила
         таймер не сработал бы никогда в программе, которой всё время есть чем
         заняться. */
      время += 1

      /* Переполнение ящика — отказ ОТПРАВИТЕЛЯ, и ставится он так же, как отказ
         от «остановить» с ненормальной причиной: первый выигрывает, остальные
         действия отклика доигрываются. Иначе порядок действий начал бы решать,
         каким кодом упадёт процесс. */
      const переполнил = (кому) => {
        if (отказ !== null) return
        отказ = {
          код: "FLANG_MAILBOX_FULL",
          сообщение: `ящик процесса «${кому}» полон: объявлен на ${процессы.get(кому).потолок}`,
        }
        запись.исход = "отказ"
        процесс.жив = false
        процесс.причина = "FLANG_MAILBOX_FULL"
      }

      for (const действие of отклик["действия"]) {
        const вид = действие.variant
        if (вид === "отправить") {
          const кому = String(действие.fields["кому"])
          if (положить(кому, действие.fields["что"], false) === "полон") переполнил(кому)
          continue
        }
        if (вид === "через") {
          const кому = String(действие.fields["кому"])
          const адресат = процессы.get(кому)
          /* Место занимается СЕЙЧАС, а не когда таймер сработает. Живость
             адресата при этом не смотрится вовсе, и это нарочно: мёртвый процесс
             может быть поднят надзором раньше срока письма, и тогда незанятое
             место дало бы ящику переполниться мимо потолка. */
          const занято = адресат !== undefined && адресат.потолок !== null
          if (занято && адресат.ящик.length + адресат.вЛёте >= адресат.потолок) {
            переполнил(кому)
            continue
          }
          if (занято) адресат.вЛёте += 1
          таймеры.push({
            время: время + Number(действие.fields["задержка"]),
            кому,
            что: действие.fields["что"],
            занято,
          })
          continue
        }
        if (вид === "отложить") {
          /* За уже пришедшие, а не в голову: цена откладывания обязана быть
             видимой, иначе выборочный приём вернулся бы через заднюю дверь. */
          процесс.ящик.push(сообщение)
          процесс.начатые.push(true)
          запись.исход = "отложено"
          continue
        }
        if (вид === "продолжить") {
          процесс.ящик.unshift(сообщение)
          процесс.начатые.unshift(true)
          запись.исход = "продолжено"
          continue
        }
        if (вид === "остановить") {
          const почему = String(действие.fields["почему"])
          процесс.жив = false
          процесс.причина = почему
          /* Нормальная остановка — не отказ, надзор о ней не узнаёт. Любая
             другая причина — отказ. */
          if (почему === $КОНК_НОРМА) {
            запись.исход = "остановлено"
          } else {
            отказ = { код: "FLANG_STOPPED", сообщение: почему }
            запись.исход = "отказ"
          }
          continue
        }
      }
    } else {
      /* Пробег, кончившийся отказом, всё равно был пробегом: время идёт и здесь.
         Иначе окно порога отказов не двигалось бы у процесса, который только и
         делает, что падает. */
      время += 1
      процесс.жив = false
      процесс.причина = отказ.код
    }

    if (отказ !== null) {
      запись.код = отказ.код
      запись.сообщениеОбОшибке = отказ.сообщение
      отказы.push({ процесс: имя, код: отказ.код, сообщение: отказ.сообщение, время: запись.время })
      const было = решения.length
      const итог = применитьНадзор(имя, отказ.код, запись.время)
      запись.решения = решения.slice(было)
        .map((р) => ({ процесс: р.процесс, надзор: р.надзор, стратегия: р.стратегия }))
      if (итог.доверху) {
        /* Отказ дошёл доверху: останавливается вся программа. Это исход, а не
           зависание, и он назван — иначе прогон отличал бы «надзор не справился»
           от «работа кончилась» только по итоговым состояниям. */
        исход = "отказ дошёл доверху"
        for (const кого of порядок) {
          if (процессы.get(кого).жив) остановить(кого, "программа остановлена: отказ дошёл доверху")
        }
        break
      }
    }
  }

  const состояния = {}
  for (const имя of порядок) состояния[имя] = процессы.get(имя).состояние
  const живые = порядок.filter((имя) => процессы.get(имя).жив)

  return {
    ...(вестиЖурнал ? { журнал } : {}),
    состояния,
    исход,
    время,
    пробегов,
    отказы,
    живые,
    решения,
    наверх,
    витки,
  }
}
