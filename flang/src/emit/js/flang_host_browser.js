/**
 * flang_host_browser.js — хозяин для вкладки: функция «поручение → отклик».
 *
 * Устройство ровно то же, что у хозяина Node, и это не подражание, а требование:
 * хозяин — это функция «поручение → отклик», и никакого другого договора у него
 * с языком нет. Программа на flang по-прежнему не имеет доступа к миру; она
 * СТРОИТ описание действия, а здесь оно исполняется.
 *
 * ── Почему файл лежит здесь и почему у него НОЛЬ ввозов ────────────────────
 *
 * Потому что это единственное, что во вкладку ехать обязано, — и единственное,
 * чему ехать туда нельзя было вместе с компилятором. Прежний хозяин
 * (`src/host/browser.mjs`) ввозил `variant`, `сбой` и `makeRandom` из второй
 * реализации языка, и вместе с тремя именами во вкладку приезжала она вся:
 * замерено в браузере — 16 файлов, 1 692 153 байта из 1 752 748, которые везла
 * страница. Напечатанный тем же деревом модуль того же приложения весит
 * 53 877 байт. То есть браузер тащил компилятор, чтобы исполнить приложение на
 * пятьдесят килобайт.
 *
 * Убраны все три ввоза, и убраны они РАЗНЫМИ способами, потому что нужны были
 * за разное:
 *
 *   `variant` строил отклик. Теперь фабрика приходит параметром `вариант` —
 *      её отдаёт сам напечатанный модуль (`ioPlan().вариант`), и это честнее
 *      ввоза: отклик обязан быть построен ТЕМ ЖЕ представлением значений, в
 *      котором работает программа, а представлений два (интерпретатор и
 *      напечатанный модуль);
 *   `сбой` был одной строкой поверх `variant` и стал одной строкой здесь;
 *   `makeRandom` давал повторимые кости по семени. Теперь бросок приходит
 *      параметром `бросить`. Второй копии генератора здесь НЕТ намеренно: их и
 *      так две (свидетель и напечатанный планировщик), третья разошлась бы с
 *      обеими молча.
 *
 * ── Что здесь есть браузерного и почему это не протекло в язык ──────────────
 *
 * `document`, `addEventListener`, `textContent` — всё в этом файле, и ни одно из
 * этих слов не встречается ни в словаре языка, ни в спецификации, ни в одной
 * программе на flang. Программа называет МЕСТО — строку, которую придумала
 * сама («экран», «строка ввода»), — а сопоставляет имя с узлом страницы хозяин,
 * по разметке `данные-место` и `данные-событие`. Граница та же, что между
 * `путь` и файловым дескриптором: имя придумывает программа, смысл ему придаёт
 * хозяин.
 *
 * Проверяется это буквально: подставь вместо `документ` объект с двумя
 * методами — и тот же план прогонится без браузера. Так и устроена проверка
 * (`flang/test/host-browser.test.mjs`), поэтому приложение в браузере имеет
 * прогон без рук.
 *
 * ── Толкающий цикл на тянущем исполнителе ──────────────────────────────────
 *
 * Главное здесь — то, чего в файле НЕТ: правки исполнителя плана. Цикл
 * поручений тянущий (программа просит следующее поручение), браузер толкающий
 * (события зовут программу), и переворот стоил нуля строк в исполнителе, потому
 * что тот ЖДЁТ хозяина: `отклик = await исполнить(поручение)`. Обещание,
 * которое разрешает `addEventListener`, — это и есть инверсия управления. Пока
 * план ждёт события, стек пуст, вкладка жива и отзывчива.
 *
 * ── Почему ожидание одно ────────────────────────────────────────────────────
 *
 * Поручение `«Ждать событие»` несёт срок, и это не удобство, а следствие:
 * `«Продолжение»` несёт ОДНО поручение, значит машина продолжений ждёт ровно
 * одного. Часы и человек — два источника, поэтому они сведены в одно ожидание:
 * что раньше, то и разбудит. Отсюда `«Срок вышел»` отдельным откликом.
 *
 * ── Чего у вкладки нет, и об этом сказано кодом, а не молчанием ─────────────
 *
 * Файлов, процессов и сырых сокетов. Все три отказа НАЗВАНЫ —
 * `FLANG_IO_NO_FILES`, `FLANG_IO_NO_SPAWN` и `FLANG_IO_NO_SOCKETS`, — и разница
 * между ними и `FLANG_IO_UNKNOWN` не педантизм: «знаю поручение, но у меня
 * этого нет» означает, что программа просит невозможного ЗДЕСЬ и может
 * попросить другого хозяина, а «не знаю поручения» означает, что хозяин отстал
 * от словаря языка и его надо чинить. Слить их значило бы сделать неотличимой
 * поломку от границы среды.
 */

/** Что хозяину позволено. Файлов у вкладки нет — и права такого нет. */
const ПОЛНЫЕ_ПРАВА = Object.freeze({
  экран: true,
  сеть: true,
  время: true,
  случайность: true,
})

/** Разметка, по которой хозяин узнаёт места и источники событий. */
const ПРИЗНАК_МЕСТА = "данные-место"
const ПРИЗНАК_СОБЫТИЯ = "данные-событие"

/**
 * Хозяин для браузера: функция «поручение → отклик».
 *
 * @param {{
 *   документ?: object, разрешено?: object, seed?: number,
 *   таймаут?: number, fetch?: Function, часы?: Function,
 *   отложить?: Function, снять?: Function, очередь?: number
 * }} options
 *   `документ` подменяем — иначе проверить хозяина можно было бы только в
 *   браузере, а прогон, для которого нужны руки, прогоном не считается.
 *   `очередь` — сколько событий копить, пока план занят; свыше самое старое
 *   выбрасывается. Ноль означал бы «терять всё, что случилось не в момент
 *   ожидания», а человек нажимает и во время счёта.
 */
export function хозяинВкладки(options = {}) {
  const документ = options.документ ?? globalThis.document
  /* Фабрика варианта — ЕДИНСТВЕННОЕ, чего хозяин не может сделать сам, и
     единственное, чего он не берёт ввозом. Отдаёт её тот, чью программу он
     обслуживает: напечатанный модуль — полем `вариант` описателя `ioPlan()`,
     интерпретатор — своей `variant`. Умолчания здесь нет намеренно: молча
     построить отклик «не тем» представлением значит соврать программе о типе,
     а поймать это некому — оба представления снаружи выглядят объектом. */
  const вариант = options.вариант
  if (typeof вариант !== "function") {
    throw new Error("хозяину вкладки нужна фабрика варианта: настройка «вариант»")
  }
  /* Отклик «хозяин не смог»: код и текст, а не исключение. Программа обязана
     уметь встретить неудачу поручения, и путь у неё один. */
  const сбой = (код, сообщение) => вариант("Сбой", { код: String(код), сообщение: String(сообщение) })
  const можно = { ...ПОЛНЫЕ_ПРАВА, ...(options.разрешено ?? {}) }
  const таймаут = options.таймаут ?? 30_000
  const сходить = options.fetch ?? globalThis.fetch
  const часы = options.часы ?? (() => Date.now())
  const отложить = options.отложить ?? ((что, через) => setTimeout(что, через))
  const снять = options.снять ?? ((метка) => clearTimeout(метка))
  const бросить = typeof options.бросить === "function" ? options.бросить : () => {
    const октеты = crypto.getRandomValues(new Uint32Array(2))
    return ((октеты[0] >>> 5) * 67108864 + (октеты[1] >>> 6)) / 9007199254740992
  }
  const вместимость = options.очередь ?? 64

  /* Случившееся, но ещё не отданное плану. Пока план считает, человек нажимает,
     и терять эти нажатия нельзя: страница выглядела бы залипшей. */
  const копилка = []
  /* Кому отдать следующее событие, если план уже ждёт. Одно на всю вкладку:
     машина продолжений ждёт ровно одного. */
  let ожидающий = null
  let подписаны = false

  const случилось = (место, значение) => {
    if (ожидающий !== null) {
      const кому = ожидающий
      ожидающий = null
      кому(вариант("Случилось", { откуда: String(место), значение: String(значение) }))
      return
    }
    копилка.push({ место: String(место), значение: String(значение) })
    if (копилка.length > вместимость) копилка.shift()
  }

  /**
   * Подписка на страницу — ОДИН раз на хозяина, а не на поручение.
   *
   * Иначе каждое ожидание вешало бы ещё один обработчик на те же кнопки, и
   * после сотни витков одно нажатие приходило бы сотней событий. Это не
   * теоретическая опасность: цикл «показать → ждать» проходит виток на каждое
   * действие человека.
   */
  const подписаться = () => {
    if (подписаны || документ === undefined || документ === null) return
    подписаны = true
    for (const узел of документ.querySelectorAll(`[${ПРИЗНАК_СОБЫТИЯ}]`)) {
      const место = узел.getAttribute(ПРИЗНАК_СОБЫТИЯ)
      узел.addEventListener("click", () => случилось(место, значениеУзла(узел)))
      /* Поле ввода шлёт событие на каждое изменение: программа хочет видеть,
         что человек печатает, а не только что он закончил. */
      узел.addEventListener("input", () => случилось(место, значениеУзла(узел)))
    }
  }

  return async function исполнить(поручение) {
    const поля = поручение.fields ?? {}
    switch (поручение.variant) {
      case "Показать": {
        if (!можно.экран) return сбой("FLANG_IO_DENIED", "хозяину запрещено писать на экран")
        const место = поля["место"]
        if (typeof место !== "string" || место === "") {
          return сбой("FLANG_IO_PLACE", "поручению «Показать» нужно непустое имя места")
        }
        const узел = документ?.querySelector?.(`[${ПРИЗНАК_МЕСТА}="${место}"]`) ?? null
        if (узел === null) {
          /* Места нет — отклик, а не исключение: разметка страницы хозяину не
             подчиняется, и «такого места на странице нет» ничем не отличается
             от «файла нет». Программа решит сама. */
          return сбой("FLANG_IO_PLACE", `на странице нет места «${место}»`)
        }
        /* `textContent`, а не `innerHTML`, и это не осторожность, а контракт:
           поручение несёт ТЕКСТ. Разрешить разметку значило бы втащить в
           словарь второй язык, на котором программа не писана и который никто
           не проверяет. */
        узел.textContent = String(поля["текст"] ?? "")
        return вариант("Показано", {})
      }

      case "Ждать событие": {
        if (!можно.экран) return сбой("FLANG_IO_DENIED", "хозяину запрещено слушать экран")
        подписаться()
        const накопленное = копилка.shift()
        if (накопленное !== undefined) {
          return вариант("Случилось", { откуда: накопленное.место, значение: накопленное.значение })
        }
        const срок = Number(поля["срок"] ?? 0)
        return await new Promise((готово) => {
          /* ВОТ ЗДЕСЬ тянущий цикл становится толкающим. Всё, что для этого
             понадобилось, — обещание: `runPlan` ждёт его на `await`, стек
             пуст, вкладка отзывчива, и разбудит план не программа, а человек
             либо часы. Ни одной правки в исполнителе плана. */
          let метка = null
          ожидающий = (отклик) => {
            if (метка !== null) снять(метка)
            готово(отклик)
          }
          if (Number.isFinite(срок) && срок > 0) {
            метка = отложить(() => {
              ожидающий = null
              готово(вариант("Срок вышел", {}))
            }, срок)
          }
        })
      }

      case "Запросить": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        if (typeof сходить !== "function") {
          return сбой("FLANG_IO_NET", "у хозяина нет способа сходить в сеть")
        }
        const способ = String(поля["способ"] ?? "GET").toUpperCase()
        const адрес = String(поля["адрес"] ?? "")
        const тело = String(поля["тело"] ?? "")
        try {
          const запрос = { method: способ, signal: AbortSignal.timeout(таймаут) }
          if (тело !== "" && способ !== "GET" && способ !== "HEAD") запрос.body = тело
          const ответ = await сходить(адрес, запрос)
          return вариант("Ответ сети", { код: ответ.status, тело: await ответ.text() })
        } catch (ошибка) {
          return сбой("FLANG_IO_NET", текст(ошибка))
        }
      }

      case "Текущее время": {
        if (!можно.время) return сбой("FLANG_IO_DENIED", "хозяину запрещено смотреть на часы")
        return вариант("Отметка времени", { миллисекунды: часы() })
      }

      case "Случайное число": {
        if (!можно.случайность) return сбой("FLANG_IO_DENIED", "хозяину запрещено бросать кости")
        return вариант("Выпало", { значение: бросить() })
      }

      case "Случайные октеты": {
        if (!можно.случайность) return сбой("FLANG_IO_DENIED", "хозяину запрещено бросать кости")
        const сколько = поля["сколько"]
        if (!Number.isInteger(сколько) || сколько < 0 || сколько > 65536) {
          return сбой("FLANG_IO_ENTROPY", "«сколько» — целое от 0 до 65536")
        }
        const октеты = new Uint8Array(сколько)
        for (let начало = 0; начало < сколько; начало += 65536) {
          crypto.getRandomValues(октеты.subarray(начало, Math.min(сколько, начало + 65536)))
        }
        return вариант("Октеты", { октеты: Array.from(октеты) })
      }

      /* ── файлов у вкладки нет ────────────────────────────────────────────────
         Отклик, а не исключение, и с ОТДЕЛЬНЫМ кодом: «у меня этого нет» — не
         то же, что «мне это запрещено» и не то же, что «я такого поручения не
         знаю». Подменять файл памятью браузера хозяин не станет: программа
         просила файл, а не хранилище вкладки, и молча подсунуть второе значило
         бы соврать о том, переживёт ли запись закрытие вкладки. */
      case "Прочитать файл":
      case "Записать файл":
      /* Перечисление каталога — то же самое «файлов нет», и код у него тот же:
         каталог — это файловая система, а не третья сущность. Стояло здесь до
         этого молчание (`FLANG_IO_UNKNOWN` из ветки по умолчанию), и сторож
         «хозяин браузера отвечает на все поручения словаря» краснел на нём. */
      case "Перечислить каталог":
        return сбой(
          "FLANG_IO_NO_FILES",
          `у хозяина браузера нет файлов: поручение «${поручение.variant}» исполнить нечем`,
        )

      /* Процессов у вкладки нет, и код СВОЙ: «нет файлов» и «нет процессов» —
         разные границы среды, и программа, увидевшая первое, может попробовать
         второе. Сливать их значило бы отнять у неё это различение. */
      case "Запустить процесс":
      case "Запустить процесс с вводом":
      case "Запустить процесс с пределом":
        return сбой(
          "FLANG_IO_NO_SPAWN",
          "у хозяина браузера нет процессов: поручение «Запустить процесс» исполнить нечем",
        )

      /* ── сырых сокетов у вкладки нет ────────────────────────────────────────
         НАЗВАННЫЙ отказ, и здесь он важнее, чем где бы то ни было ещё, потому
         что тут был настоящий соблазн сделать вид. У вкладки есть `fetch` и
         есть `WebSocket`, и на любом из них можно было бы изобразить открытое
         соединение. Изобразить — значит соврать в самом контракте: поручение
         просит СЫРЫЕ байты, `fetch` — это HTTP, а `WebSocket` — своё
         рукопожатие, на которое сервер базы данных не ответит. Программа,
         получившая номер соединения, вправе писать в него что угодно; хозяин,
         который тайком завернёт это «что угодно» в HTTP-запрос, соврёт не в
         мелочи.

         Код СВОЙ, а не `FLANG_IO_NO_FILES` и не `FLANG_IO_UNKNOWN`: «знаю
         поручение, но сокетов у меня нет» — это ни «мне запрещено», ни «я
         отстал от словаря языка». Различать их программе нужнее, чем нам
         экономить на константе. */
      case "Открыть соединение":
      case "Принять соединение":
      case "Прочитать из соединения":
      case "Ответить в соединение":
      /* Октетная пара стоит в той же ветке, и это не экономия на строках:
         причина у вкладки ОДНА И ТА ЖЕ — нет сырого сокета. Развести их по
         разным сообщениям значило бы сделать вид, что причин две. */
      case "Прочитать октеты из соединения":
      case "Ответить октетами в соединение":
      case "Отправить датаграмму":
      case "Принять датаграмму":
        return сбой(
          "FLANG_IO_NO_SOCKETS",
          `у хозяина браузера нет сырых сокетов: поручение «${поручение.variant}» исполнить нечем`,
        )

      default:
        return сбой("FLANG_IO_UNKNOWN", `хозяин не знает поручения «${поручение.variant}»`)
    }
  }
}

/**
 * Что узел принёс с событием.
 *
 * Порядок здесь не произволен, и стоил он одного упавшего прогона в настоящем
 * браузере. Сначала спрашивается ОБЪЯВЛЕННОЕ страницей `данные-значение`, и
 * только потом содержимое поля ввода: у кнопки в HTML тоже есть свойство
 * `value`, и оно пустая строка. Спроси сначала его — и всякое нажатие кнопки
 * приходило бы программе пустым значением. Подставной документ проверки этого
 * не ловил: у него `value` не бывает вовсе.
 *
 * Смысл же порядка простой: сказанное страницей ЯВНО важнее того, что нашлось
 * у узла само.
 */
function значениеУзла(узел) {
  const объявлено = узел?.getAttribute?.("данные-значение")
  if (typeof объявлено === "string" && объявлено !== "") return объявлено
  const введённое = узел?.value
  if (typeof введённое === "string") return введённое
  return String(узел?.textContent ?? "")
}

function текст(ошибка) {
  return ошибка instanceof Error ? ошибка.message : String(ошибка)
}

/**
 * ── САМОЗАПУСК СТРАНИЦЫ: ЗАЧЕМ ЭТИ ПЯТНАДЦАТЬ СТРОК И ЧТО ОНИ УБИРАЮТ ───────
 *
 * Браузер исполняет JavaScript, и другого способа завести программу во вкладке
 * нет. Значит какие-то строки на JavaScript в браузере будут ВСЕГДА, и вопрос
 * только в том, СКОЛЬКО их и ГДЕ они лежат. Было — по четыре-шесть строк на
 * КАЖДОЙ странице, прямо в разметке: ввоз напечатанного модуля, ввоз хозяина,
 * сборка фабрики варианта, прогон плана, показ отказа. Пять раз одно и то же,
 * и каждая новая страница переписывала их заново, с шансом разойтись.
 *
 * Стало — ноль строк на странице. Страница несёт ТЕГ С ДВУМЯ ПРИЗНАКАМИ:
 *
 *   <script type="module" src="…/flang_host_browser.js"
 *           данные-модуль="./gradiny.js"></script>
 *
 * `src` — этот файл, `данные-модуль` — что завести. Тела у тега нет вовсе,
 * поэтому «сколько на странице своего JavaScript» стало вопросом с ответом
 * НОЛЬ, а не «четыре строки, но они простые».
 *
 * ЗАПУСК ЖИВЁТ ЗДЕСЬ, А НЕ ОТДЕЛЬНЫМ ФАЙЛОМ, по той же причине, по которой у
 * этого файла ноль ввозов: всякий новый файл на JavaScript — ещё одна вещь,
 * которую надо везти во вкладку и держать в согласии с остальными. Здесь он
 * рядом с тем единственным, что и так обязано ехать.
 *
 * ФАЙЛ ОСТАЛСЯ БИБЛИОТЕКОЙ. Самозапуск включает не сам ввоз, а НАЛИЧИЕ тега с
 * признаком `данные-модуль`. Нет тега — ничего не происходит, и `хозяинВкладки`
 * зовётся как звался. Поэтому проверка хозяина подставным документом работает
 * по-прежнему.
 */
async function завестиИзРазметки() {
  const тег = document.querySelector("script[данные-модуль]")
  if (тег === null) return
  const адрес = тег.getAttribute("данные-модуль")
  /* Место для отказа названо страницей, а не выдумано здесь: разметка
     подчиняется странице, и «куда писать беду» — её решение. Нет признака —
     нет и места, и тогда беда уходит в консоль, как ушла бы без нас. */
  const местоОтказа = тег.getAttribute("данные-место-отказа") ?? "итог"
  try {
    /* Адрес модуля считается от САМОЙ СТРАНИЦЫ, а не от этого файла: пишет его
       автор страницы, и «рядом со мной» для него значит рядом со страницей.
       Без `new URL` ввоз искал бы модуль рядом с хозяином, то есть в
       `flang/src/emit/js/`. */
    const модуль = await import(new URL(адрес, document.baseURI).href)
    const хозяин = хозяинВкладки({ документ: document, вариант: модуль.ioPlan().вариант })
    /* Предел поручений снят нулём. Умолчание исполнителя — 10 000 поручений на
       прогон — мера ПАКЕТНОЙ программы, которая кончается. Вкладка не
       кончается, и то же число здесь означало бы «приложение умрёт после
       нескольких тысяч нажатий». */
    await модуль.ioRun("", хозяин, { поручений: 0 })
  } catch (беда) {
    /* Отказ плана — такой же результат, как ответ, и он показывается человеку,
       а не прячется в консоль. */
    const узел = документМеста(местоОтказа)
    const текстБеды = `${беда?.code ?? "FLANG"}: ${беда?.message ?? String(беда)}`
    if (узел !== null) узел.textContent = текстБеды
    else console.error(текстБеды)
  }
}

