      const сверка = await прогнать(ПЕСОЧНИЦА_ФАЙЛЫ.сверщик, доводы, файлы)
      return { код: сверка.код, строки: [строкаКоманды(доводы), сверка.вывод.replace(/\n$/u, ""), ...хвостКода(сверка.код)] }
