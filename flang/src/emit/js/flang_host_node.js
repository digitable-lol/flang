/**
 * flang_host_node.js — хозяин для Node: функция «поручение → отклик».
 *
 * Устройство то же, что у соседа по каталогу (`flang_host_browser.js`), и это
 * не подражание, а требование: хозяин — это функция «поручение → отклик», и
 * никакого другого договора у него с языком нет. Программа на flang побочных
 * действий не имеет; она СТРОИТ описание действия, а исполняется оно здесь.
 *
 * ── ЗАЧЕМ ФАЙЛ ЗАВЕДЁН, И ЭТО ЗАМЕР, А НЕ ЗАМЫСЕЛ ──────────────────────────
 *
 * План печатает РОВНО ОДНА цель из девяти — `js`. В go, rust, java, csharp,
 * elixir, python и cpp программа с планом не печатается вовсе: код 2,
 * `FLANG_PLAN_UNSUPPORTED`. Значит каркас хозяина имеет смысл ровно для
 * JavaScript, и выбор языка здесь предрешён замером.
 *
 * А в самой цели `js` хозяина не было ни одного. Печаталось три файла рантайма:
 * `flang_conc.js` (планировщик) и `flang_io.js` (цикл поручений) вшиваются в
 * модуль, `flang_cli.js` уезжает рядом. Ни один из трёх хозяином не является:
 * `flang_io.js` — это ЦИКЛ, он поручение только ВЫДАЁТ наружу, а `flang_cli.js`
 * про план не знает вовсе — ноль упоминаний `ioRun` и `ioPlan` на 534 строки.
 * То есть человек, напечатавший в JS программу с планом, получал цикл БЕЗ
 * хозяина и обязан был написать «поручение → отклик» сам, с нуля и без образца:
 * единственный образец в дереве (`flang_host_browser.js`) обслуживает вкладку и
 * наружу не едет.
 *
 * ── ЧТО ЭТОТ ХОЗЯИН ИСПОЛНЯЕТ, А ЧЕМУ ОТКАЗЫВАЕТ — ЧИСЛОМ ──────────────────
 *
 * Родов поручений в словаре языка 22 (`flang/self/parser.flang:6440`).
 * Исполняются ДЕВЯТЬ, и все девять — обиходные и дешёвые под `node:fs`:
 *
 *   Прочитать файл · Записать файл · Перечислить каталог · Удалить файл ·
 *   Завести временный каталог · Текущее время · Случайное число ·
 *   Прочитать переменную среды · Прочитать доводы
 *
 * Остальным ТРИНАДЦАТИ — внятный отказ, называющий род поручения и причину.
 * Молчаливого пропуска здесь нет ни одного: `case` заведён на все 22 имени
 * словаря, и ветка по умолчанию значит только одно — хозяин отстал от языка.
 *
 * ДВА ПОРУЧЕНИЯ ЭТОТ ХОЗЯИН ИСПОЛНЯЕТ ПЕРВЫМ В ДЕРЕВЕ: «Прочитать переменную
 * среды» и «Прочитать доводы». В словарь их ввели, а применить не успели —
 * `flang/self/parser.flang` про оба говорит «ВВЕДЕНО, И НИГДЕ НЕ ПРИМЕНЕНО»,
 * двоичный хозяин (`flang io`) отвечает на них `FLANG_IO_UNKNOWN`, хозяин
 * вкладки — тоже. Здесь они исполняются, и задача 8291 закрывается на шаге
 * третьем именно этим файлом.
 *
 * ── ЧЕТЫРЕ КОДА ОТКАЗА, И РАЗЛИЧАТЬ ИХ ВАЖНЕЕ, ЧЕМ ЭКОНОМИТЬ ──────────────
 *
 *   FLANG_IO_DENIED     — род умею, но мне это запрещено настройкой хозяина;
 *   FLANG_IO_NO_SCREEN  — род умею назвать, но СРЕДЫ для него нет: у процесса
 *                         Node нет страницы с местами и событиями;
 *   FLANG_IO_NOT_WIRED  — род умею назвать, СРЕДА ЕГО УМЕЕТ, а этот каркас его
 *                         не заводит. Единственный код, где виноват хозяин, а
 *                         не программа и не среда, — и потому он свой. Сказать
 *                         про сокеты «у Node нет сокетов» было бы прямой ложью:
 *                         `node:net` есть, не написано здесь. То же поручение
 *                         исполняет двоичный (`flang io`), и отказ на него
 *                         указывает — человеку это ответ, а не тупик;
 *   FLANG_IO_UNKNOWN    — рода НЕ ЗНАЮ. Значит словарь языка вырос, а хозяин
 *                         отстал, и чинить надо хозяина.
 *
 * Слить их значило бы сделать неотличимой поломку от границы среды и от
 * ненаписанного — а различает их не педантизм, а то, кому идти чинить.
 *
 * ── ЧТО СВЕРЕНО С ДВОИЧНЫМ ХОЗЯИНОМ ПОБУКВЕННО ────────────────────────────
 *
 * Девять исполняемых родов отвечают ровно тем же, чем `flang_repl.c`:
 *   · «сколько» у записи — КОДОВЫЕ ТОЧКИ, а не октеты (SPEC, раздел 5);
 *   · имена каталога СОРТИРОВАНЫ по кодовым точкам — `readdir` порядка не
 *     обещает ни там, ни здесь, а журнал поручений двух хозяев обязан сойтись;
 *   · «Заведено» отдаёт путь В ТЕХ ЖЕ КООРДИНАТАХ, в каких дан образец, —
 *     относительный, а не полный, иначе план сложил бы из него имя, которого
 *     чужой хозяин под правилом «внутри каталога» уже не примет;
 *   · «Удалить файл» убирает ИМЯ, чем бы оно ни было (файл или пустой каталог),
 *     без рекурсии — ровно `remove(3)`;
 *   · кости с семенем — mulberry32 той же целочисленной арифметикой, что в
 *     `flang_repl.c:io_random`: прогон с семенем обязан дать ту же
 *     последовательность у всех целей печати, иначе «повторимо» значило бы
 *     «повторимо в одном месте».
 *
 * ── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ──────────────────────────────────────────────
 *
 * Ни одного ввоза из дерева. Файл КОПИРУЕТСЯ рядом с напечатанной программой,
 * где никакого `flang/` нет вовсе, и всякий `import` оттуда упал бы
 * ERR_MODULE_NOT_FOUND. По той же причине фабрика отклика приходит параметром
 * `вариант`, а не ввозится: отклик обязан быть построен ТЕМ ЖЕ представлением
 * значений, в котором работает программа, и подсунуть чужое было бы враньём о
 * типе, которое поймать некому.
 */

import { mkdtempSync, readFileSync, readdirSync, realpathSync, rmdirSync, unlinkSync, writeFileSync } from "node:fs"
import { dirname, isAbsolute, join, resolve, sep } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

/** Что хозяину позволено. Умолчание — можно всё: запуск и есть согласие. */
const ПОЛНЫЕ_ПРАВА = Object.freeze({
  читать: true,
  писать: true,
  время: true,
  случайность: true,
  среда: true,
  доводы: true,
})

/**
 * Хозяин для Node: функция «поручение → отклик».
 *
 * @param {{
 *   вариант: Function, корень?: string, вКаталоге?: boolean,
 *   разрешено?: object, доводы?: string[], среда?: object,
 *   часы?: Function, бросить?: Function, семя?: number
 * }} options
 *   `корень` — от какого каталога считаются пути поручений; умолчание —
 *   каталог запуска. `вКаталоге` — запретить путям выходить за него, тот же
 *   ключ, что `flang io --in-dir`. `среда` и `доводы` подменяемы, иначе
 *   проверить хозяина можно было бы только настоящим окружением, а прогон,
 *   которому нужна машина, прогоном не считается.
 */
export function хозяинУзла(options = {}) {
  /* Фабрика варианта — единственное, чего хозяин не может сделать сам, и
     единственное, чего он не берёт ввозом. Отдаёт её тот, чью программу он
     обслуживает: напечатанный модуль — полем `вариант` описателя `ioPlan()`.
     Умолчания здесь нет намеренно, см. шапку. */
  const вариант = options.вариант
  if (typeof вариант !== "function") {
    throw new Error("хозяину Node нужна фабрика варианта: настройка «вариант»")
  }
  /* Отклик «хозяин не смог»: код и текст, а не исключение. Программа обязана
     уметь встретить неудачу поручения, и путь у неё один. */
  const сбой = (код, сообщение) => вариант("Сбой", { код: String(код), сообщение: String(сообщение) })
  const можно = { ...ПОЛНЫЕ_ПРАВА, ...(options.разрешено ?? {}) }
  const корень = resolve(options.корень ?? process.cwd())
  const вКаталоге = options.вКаталоге === true
  const доводы = Array.isArray(options.доводы) ? options.доводы.map(String) : []
  const среда = options.среда ?? process.env
  const часы = options.часы ?? (() => Date.now())
  const бросить = typeof options.бросить === "function" ? options.бросить : кости(options.семя)

  /* Путь под правилом «внутри каталога» — тот же разбор, что `io_path` в
     `flang_repl.c`, и те же два отказа теми же словами. Возвращается ЛИБО
     путь, ЛИБО готовый отклик: у беды здесь нет второго вида. */
  const путь = (данный) => {
    if (typeof данный !== "string" || данный === "") {
      return { беда: сбой("FLANG_IO_PATH", "поручению нужен непустой путь") }
    }
    const полный = resolve(корень, данный)
    if (вКаталоге && полный !== корень && !полный.startsWith(корень + sep)) {
      return { беда: сбой("FLANG_IO_DENIED", `путь «${данный}» ведёт за пределы каталога работы`) }
    }
    return { полный }
  }

  return async function исполнить(поручение) {
    const поля = поручение.fields ?? {}
    switch (поручение.variant) {
      /* ── файлы ─────────────────────────────────────────────────────────── */

      case "Прочитать файл": {
        if (!можно.читать) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать файлы")
        const где = путь(поля["путь"])
        if (где.беда !== undefined) return где.беда
        let октеты = null
        try {
          октеты = readFileSync(где.полный)
        } catch (ошибка) {
          return сбой("FLANG_IO_READ", `файл не прочитан: ${текст(ошибка)}`)
        }
        /* СТРОГОЕ раскодирование, а не `readFileSync(путь, "utf8")`. Умолчание
           Node меняет всякий не-UTF-8 октет на U+FFFD МОЛЧА: двоичный файл
           проезжал бы сквозь текстовую пару испорченным, и `длина` считала бы
           знаки, которых в файле не было. Отказ лучше испорченного файла — то
           же решение и теми же словами принято в двоичном хозяине. */
        try {
          const содержимое = new TextDecoder("utf-8", { fatal: true }).decode(октеты)
          return вариант("Прочитано", { содержимое })
        } catch {
          return сбой(
            "FLANG_IO_NOT_TEXT",
            `файл не текст: ${октеты.length} октет(ов) не складываются в UTF-8; октеты возит «Прочитать октеты из файла»`,
          )
        }
      }

      case "Записать файл": {
        if (!можно.писать) return сбой("FLANG_IO_DENIED", "хозяину запрещено писать файлы")
        const содержимое = String(поля["содержимое"] ?? "")
        /* Одинокая половина суррогатной пары — единственное, что строка
           JavaScript выражает, а UTF-8 не выражает. Node заменил бы её на
           U+FFFD молча; здесь она отказ, как и всякий другой не-текст. */
        const рвано = одинокийСуррогат(содержимое)
        if (рвано >= 0) {
          return сбой(
            "FLANG_IO_NOT_TEXT",
            `содержимое не текст: знак ${рвано + 1} — одинокая половина суррогатной пары; октеты возит «Записать октеты в файл»`,
          )
        }
        const где = путь(поля["путь"])
        if (где.беда !== undefined) return где.беда
        try {
          writeFileSync(где.полный, содержимое, "utf8")
        } catch (ошибка) {
          return сбой("FLANG_IO_WRITE", `файл не записан: ${текст(ошибка)}`)
        }
        /* КОДОВЫЕ ТОЧКИ, а не октеты и не единицы UTF-16: «сколько» обязано
           совпасть с тем, что о том же тексте скажет `длина` языка. */
        return вариант("Записано", { сколько: Array.from(содержимое).length })
      }

      case "Перечислить каталог": {
        if (!можно.читать) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать файлы")
        const где = путь(поля["путь"])
        if (где.беда !== undefined) return где.беда
        try {
          /* Сортировка — не причёсывание вывода, а условие сравнимости: ни
             `readdir(3)`, ни `readdirSync` порядка не обещают, а журналы двух
             хозяев на одном плане обязаны сойтись строка в строку. */
          return вариант("Перечислено", { имена: readdirSync(где.полный).sort(поТочкам) })
        } catch (ошибка) {
          return сбой("FLANG_IO_LIST", `каталог не открыт: ${текст(ошибка)}`)
        }
      }

      case "Удалить файл": {
        /* Разрешение спрашивается ТО ЖЕ, что у записи: удаление — это запись в
           дерево, и хозяин, которому писать запрещено, удалять тем более не
           вправе. Рекурсии здесь нет и не будет: «Перечислить каталог» отдаёт
           имена без признака каталога, и обход дерева стоял бы на догадке. */
        if (!можно.писать) return сбой("FLANG_IO_DENIED", "хозяину запрещено писать файлы")
        const где = путь(поля["путь"])
        if (где.беда !== undefined) return где.беда
        try {
          unlinkSync(где.полный)
          return вариант("Убрано", {})
        } catch (первая) {
          /* `remove(3)` в POSIX — это «убрать имя, чем бы оно ни было», и
             различать файл с пустым каталогом хозяину незачем: план назвал
             путь, а не вид узла. В Node на два вида два вызова, и второй
             пробуется ровно там, где первый отказал по виду узла. */
          try {
            rmdirSync(где.полный)
            return вариант("Убрано", {})
          } catch {
            return сбой("FLANG_IO_REMOVE", `имя не убрано: ${текст(первая)}`)
          }
        }
      }

      case "Завести временный каталог": {
        if (!можно.писать) return сбой("FLANG_IO_DENIED", "хозяину запрещено писать файлы")
        const образец = поля["образец"]
        const где = путь(образец)
        if (где.беда !== undefined) return где.беда
        try {
          const полный = mkdtempSync(где.полный)
          /* Обратно едет ОБРАЗЕЦ ПЛЮС ХВОСТ, а не полный путь: план дал имя в
             своих координатах и в них же обязан получить ответ, иначе сложенное
             из ответа имя не примет чужой хозяин под правилом «внутри
             каталога». Шесть знаков хвоста досочинил хозяин — это договор
             `mkdtemp`, а не имя, которое выбирал план. */
          return вариант("Заведено", { путь: `${образец}${полный.slice(полный.length - 6)}` })
        } catch (ошибка) {
          return сбой("FLANG_IO_TEMPDIR", `временный каталог не заведён: ${текст(ошибка)}`)
        }
      }

      /* ── часы, кости, среда, доводы ────────────────────────────────────── */

      case "Текущее время": {
        if (!можно.время) return сбой("FLANG_IO_DENIED", "хозяину запрещено смотреть на часы")
        return вариант("Отметка времени", { миллисекунды: часы() })
      }

      case "Случайное число": {
        if (!можно.случайность) return сбой("FLANG_IO_DENIED", "хозяину запрещено бросать кости")
        return вариант("Выпало", { значение: бросить() })
      }

      case "Прочитать переменную среды": {
        if (!можно.среда) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать среду")
        const имя = поля["имя"]
        if (typeof имя !== "string" || имя === "") {
          return сбой("FLANG_IO_ENV", "поручению нужно непустое имя переменной")
        }
        /* Переменную просят ПО ИМЕНИ, и отдаётся ровно она. Хозяин, отдающий
           среду целиком, отдал бы вместе с ней ключи и пароли, которых план не
           спрашивал. «Не задана» — ОТДЕЛЬНЫЙ отклик, а не пустая строка: это
           разные вещи, и обе выразимы. */
        const значение = Object.hasOwn(среда, имя) ? среда[имя] : undefined
        if (значение === undefined) return вариант("Переменной среды нет", {})
        return вариант("Значение среды", { значение: String(значение) })
      }

      case "Прочитать доводы": {
        if (!можно.доводы) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать доводы")
        /* Имени программы в списке нет: план знает, каким файлом он запущен, и
           первый довод — первый, а не нулевой. Пустой список — обычный исход, а
           не беда, поэтому второго отклика вроде «доводов нет» не заведено. */
        return вариант("Доводы", { доводы: [...доводы] })
      }

      /* ── ЭКРАНА У ПРОЦЕССА НЕТ ─────────────────────────────────────────────
         Тот же код и тот же довод, что у двоичного хозяина: «Показать» просит
         МЕСТО — имя, которое программа придумала сама, — а мест у потока вывода
         не бывает. Написать текст в stdout и назвать это «Показано» значило бы
         соврать: место было бы потеряно, а программа считала бы, что её поняли.
         «Ждать событие» — та же граница с другой стороны: события шлёт страница,
         а не труба. */
      case "Показать":
      case "Ждать событие":
        return сбой(
          "FLANG_IO_NO_SCREEN",
          `у хозяина Node нет экрана: поручение «${поручение.variant}» исполнить нечем`,
        )

      /* ── ЧЕГО ЭТОТ КАРКАС НЕ ЗАВОДИТ ──────────────────────────────────────
         Здесь отказ признаётся В СВОЙ АДРЕС, и это главное отличие от соседа по
         каталогу. У вкладки сокетов НЕТ, и `FLANG_IO_NO_SOCKETS` там — правда о
         среде. У Node есть и `node:net`, и `node:child_process`, и `fetch`;
         сказать про них «нет» было бы ложью, а промолчать — хуже лжи. Поэтому
         код свой и говорит ровно то, что есть: род известен, среда его умеет,
         каркас его не завёл, а исполняет его сегодня двоичный (`flang io`). */
      case "Прочитать октеты из файла":
      case "Записать октеты в файл":
      case "Запросить":
      case "Запустить процесс":
      case "Запустить процесс с вводом":
      case "Открыть соединение":
      case "Принять соединение":
      case "Прочитать из соединения":
      case "Ответить в соединение":
      case "Прочитать октеты из соединения":
      case "Ответить октетами в соединение":
        return сбой(
          "FLANG_IO_NOT_WIRED",
          `поручение «${поручение.variant}» в этом каркасе не заведено: Node его умеет, а хозяин — нет. `
            + "Допишите ветку здесь либо исполните план двоичным: flang io <файл.flang>",
        )

      /* Ветка по умолчанию значит РОВНО ОДНО: словарь языка вырос, а хозяин
         отстал. Ни одно из 22 имён сюда не попадает — они все названы выше. */
      default:
        return сбой("FLANG_IO_UNKNOWN", `хозяин не знает поручения «${поручение.variant}»`)
    }
  }
}

/* ── мелочи, которым место рядом ────────────────────────────────────────── */

function текст(ошибка) {
  return ошибка instanceof Error ? ошибка.message : String(ошибка)
}

/**
 * Порядок по КОДОВЫМ ТОЧКАМ, а не по единицам UTF-16.
 *
 * Умолчание `Array.sort` сравнивает единицы UTF-16, и на них знак за пределами
 * основной плоскости (U+10000 и выше) оказывается МЕНЬШЕ знака из области
 * U+E000…U+FFFF — потому что его высокая половина начинается с 0xD800.
 * Двоичный хозяин сортирует байты UTF-8, а их порядок совпадает с порядком
 * кодовых точек. Разошлись бы два хозяина ровно на тех именах, которые никто не
 * заводит нарочно, — и разошлись бы молча.
 */
function поТочкам(левое, правое) {
  const л = Array.from(левое)
  const п = Array.from(правое)
  const общая = Math.min(л.length, п.length)
  for (let i = 0; i < общая; i += 1) {
    const а = л[i].codePointAt(0)
    const б = п[i].codePointAt(0)
    if (а !== б) return а < б ? -1 : 1
  }
  return л.length - п.length
}

/** Первая одинокая половина суррогатной пары; -1, если строка выразима в UTF-8. */
function одинокийСуррогат(строка) {
  for (let i = 0; i < строка.length; i += 1) {
    const код = строка.charCodeAt(i)
    if (код < 0xd800 || код > 0xdfff) continue
    if (код >= 0xdc00) return i
    const следом = строка.charCodeAt(i + 1)
    if (!(следом >= 0xdc00 && следом <= 0xdfff)) return i
    i += 1
  }
  return -1
}

/**
 * Кости: без семени — `Math.random`, с семенем — mulberry32.
 *
 * Тот же генератор и та же целочисленная арифметика, что в
 * `flang_repl.c:io_random`; `Math.imul` здесь не украшение, а необходимость —
 * обычное умножение двух 32-битных чисел не помещается в мантиссу double и
 * дало бы другую последовательность на той же формуле.
 */
function кости(семя) {
  if (typeof семя !== "number" || !Number.isFinite(семя)) return Math.random
  /* Семя 0 подменяется тем же числом, что в двоичном: у mulberry32 нулевое
     состояние — законное, но `flang io --seed 0` берёт 0x9e3779b9, и разойтись
     двум хозяевам на одном ключе нельзя. */
  let состояние = (семя | 0) === 0 ? 0x9e3779b9 | 0 : семя | 0
  return () => {
    состояние = (состояние + 0x6d2b79f5) | 0
    let т = Math.imul(состояние ^ (состояние >>> 15), 1 | состояние)
    т = (т + Math.imul(т ^ (т >>> 7), 61 | т)) ^ т
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296
  }
}

/*
 * ── САМОЗАПУСК: ПОЧЕМУ ХОЗЯИН ЕЩЁ И КОМАНДА ───────────────────────────────
 *
 * Потому что иначе он остаётся библиотекой, которую некому позвать. Прогонщик
 * `flang_cli.js` план не исполняет — он отвечает на запросы к чистым функциям,
 * и `ioRun` в нём не упомянут ни разу. Значит человек, напечатавший программу с
 * планом, должен был бы дописать ещё и точку входа: ввезти модуль, достать
 * фабрику варианта, свести её с хозяином, позвать `ioRun`, разобрать беду и
 * выставить код возврата. Шесть строк, которые у всех одинаковы и у каждого
 * свои, — ровно та работа, которую хозяин обязан снять.
 *
 *   node flang_host_node.js ./моя-программа.js [--план «Имя»] [довод…]
 *
 * КОДЫ ВОЗВРАТА — ТЕ ЖЕ, ЧТО У `flang io`, и это не совпадение, а договор:
 *   0 — план дошёл до конца;
 *   1 — ПРОГРАММА СДАЛАСЬ САМА («Провал»), то есть нашла беду и назвала её;
 *   2 — кривой вызов;
 *   3 — сломался инструмент ЛИБО программа сказала «Не проверено».
 * Первое и второе различает не код отказа, а то, КТО принял решение; второе и
 * третье — то, ЧТО решено: «нашёл беду» против «не смог посмотреть».
 *
 * ФАЙЛ ОСТАЛСЯ БИБЛИОТЕКОЙ: тело ниже включает не ввоз, а ЗАПУСК. Ввезите его
 * модулем — и `хозяинУзла` зовётся как звался, ничего не происходит.
 */
async function главная(доводы) {
  const свои = доводы.slice(2)
  const файл = свои[0]
  if (файл === undefined || файл === "" || файл.startsWith("-")) {
    process.stderr.write("flang_host_node.js <модуль.js> [--план «Имя»] [довод…]\n")
    return 2
  }
  let имяПлана = ""
  let остальные = свои.slice(1)
  if (остальные[0] === "--план" || остальные[0] === "--plan") {
    имяПлана = остальные[1] ?? ""
    остальные = остальные.slice(2)
  }
  const адрес = pathToFileURL(isAbsolute(файл) ? файл : join(process.cwd(), файл)).href
  let модуль = null
  try {
    модуль = await import(адрес)
  } catch (беда) {
    process.stderr.write(`не прочитан модуль программы «${файл}»: ${текст(беда)}\n`)
    return 2
  }
  if (typeof модуль.ioRun !== "function" || typeof модуль.ioPlan !== "function") {
    /* Отказ обязан НАЗЫВАТЬ причину. Модуль без плана печатается тем же
       `emit --target js` и выглядит точно так же — разница только в том, что
       цикл поручений в него не вшит. Человеку нужно знать это, а не «не
       вышло». */
    process.stderr.write(`в модуле «${файл}» нет плана: ioRun и ioPlan не напечатаны\n`)
    return 2
  }
  try {
    /* Пути поручений считаются от каталога МОДУЛЯ, а не от каталога запуска, —
       ровно как `flang io` считает их от каталога файла плана. Один и тот же
       план обязан ходить по одним и тем же файлам под обоими хозяевами. */
    const хозяин = хозяинУзла({
      вариант: модуль.ioPlan().вариант,
      корень: dirname(fileURLToPath(адрес)),
      доводы: остальные,
    })
    const итог = await модуль.ioRun(имяПлана, хозяин, {})
    process.stdout.write(`${JSON.stringify({ result: итог.значение, orders: итог.поручений })}\n`)
    return 0
  } catch (беда) {
    process.stderr.write(`${JSON.stringify({ error: беда?.message ?? String(беда), code: беда?.code ?? "FLANG_IO" })}\n`)
    /* Признак `сдался` ставит цикл поручений и только «Провалу»: там решение
       приняла ПРОГРАММА. Всё прочее — сломанный инструмент, и это код 3. */
    return беда?.сдался === true ? 1 : 3
  }
}

/*
 * «Меня запустили напрямую?» — образец лежит в `flang/scripts/direct-run.mjs`,
 * а здесь его законная КОПИЯ: файл покидает дерево вместе с напечатанной
 * программой, и `import` оттуда упал бы ERR_MODULE_NOT_FOUND. Копия сверяется с
 * образцом телом в тело (`flang/scripts/direct-run-guard.mjs`), и разойтись ей
 * не дадут.
 *
 * Сравниваются РАЗРЕШЁННЫЕ пути, а не строки: `import.meta.url` кодирует
 * процентами всё, что не входит в ASCII-набор адреса (кириллическая буква —
 * тремя-шестью знаками), а путь не кодирует ничего; и Node разрешает
 * символьные ссылки для `import.meta.url`, но не для строки запуска. Сравнение
 * строк немеет обоими способами — молча, с кодом 0.
 */
function запущенНапрямую(адресМодуля) {
  const запуск = process.argv[1]
  if (запуск === undefined || запуск === "") return false
  try {
    return realpathSync(fileURLToPath(адресМодуля)) === realpathSync(запуск)
  } catch {
    return false
  }
}

if (запущенНапрямую(import.meta.url)) {
  process.exitCode = await главная(process.argv)
}
