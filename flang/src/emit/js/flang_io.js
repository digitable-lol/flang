/* ── исполнитель плана: цикл поручений ──
   Печатается целиком и только программе, у которой есть `план`. Это ПОРТ
   свидетеля (`flang/src/io.mjs`, `runPlan`) на представление значений
   напечатанного модуля, а не второй ввод-вывод: шаги стоят здесь в том же
   порядке, с теми же именами и теми же исходами.

   ── Почему цикл вообще напечатан, а не оставлен хозяину ────────────────────

   Потому что он ОДИН и тот же у всякого хозяина. Хозяин отвечает на поручение —
   это его работа и его среда; а «взять начальное состояние, позвать шаг,
   разобрать продолжение, отдать поручение наружу и вернуться с откликом» —
   работа языка, и написать её заново в каждой вкладке значило бы раздать
   семантику плана по хозяевам. Двоичный это уже прошёл: в C цикл лежит у
   хозяина (`flang_repl.c`), и на стороне flang остались ровно три точки —
   найти план, взять начало, сделать шаг. Здесь те же три точки, только цикл
   вокруг них напечатан, потому что печатать его есть куда.

   ── Чем этот исполнитель отличается от свидетельского ──────────────────────

     • шаг — обычная функция этого модуля, а не вызов интерпретатора. Поэтому
       плану отдаётся сама функция, а не её имя: искать функцию по имени в
       напечатанном модуле было бы вторым словарём рядом с уже существующим
       (`$PROGRAM.functions`), и разошлись бы они молча;
     • ЖУРНАЛА ПО УМОЛЧАНИЮ НЕТ. Свидетель копит каждое поручение с откликом,
       и для пакетной программы это правильно: журнал — то, чем прогон
       сверяется. Вкладка живёт часами, и тот же журнал в ней — течь, растущая
       со скоростью действий человека. Поэтому он включается признаком
       `журнал`, а не выключается им: умолчание обязано годиться тому, кто про
       ключ не прочитал;
     • ПРЕДЕЛ ПОРУЧЕНИЙ СНИМАЕТСЯ НУЛЁМ. Умолчание то же, что у свидетеля
       (10 000), потому что мера пакетной программы должна остаться мерой;
       ноль и отрицательное значат «без предела», и это ровно тот ключ, который
       нужен вкладке.

   ── Чего здесь нет намеренно, и это НАЗВАННЫЙ ДОЛГ ─────────────────────────

   Сверки значения с ОБЪЯВЛЕННЫМ типом на входе шага (`входШага` у свидетеля).
   Свидетель ловит ею хозяина, вернувшего «Отметку времени» со строкой вместо
   числа: без неё план доходит до конца и печатает «мс: вчера», не сказав ни
   слова. Здесь эта сверка требует таблицы границы входа — она в модуле есть
   (`$PROGRAM.entry`), но печатается только вместе с прогонщиком, а разбирает её
   `checkEntry` из `flang_cli.js`, то есть файл, который во вкладку не едет.
   Что проверяется здесь: отклик — это «Отклик», продолжение — это
   «Продолжение», поручение — это «Поручение». То есть ФОРМА, но не тип полей.
   Долг закрывается переносом `checkEntry` сюда либо в общий сосед, и до тех
   пор он назван здесь, а не умолчан. */

/** Сколько поручений исполнитель выдаёт, прежде чем сдаться. То же число, что у свидетеля. */
const $ИО_ПРЕДЕЛ = 10000

/** Отклик, с которым план начинает: ещё ничего не случилось. */
const $ИО_НАЧАЛО = "Пока ничего"

/** Варианты «Продолжение» — что шаг может ответить. Список — часть контракта. */
const $ИО_СДЕЛАТЬ = "Сделать"
const $ИО_КОНЕЦ = "Конец работы"
const $ИО_ПРОВАЛ = "Провал"
/* ЧЕТВЁРТЫЙ ИСХОД. «Провал» — «посмотрел и нашёл беду», «Не проверено» — «не
   смог посмотреть». Признак `сдался` ставится только первому: он и есть та
   отметка, по которой беда превращается в код 1. У «Не проверено» её нет, и
   потому оно уезжает кодом 3 — тем же, каким отвечает сломавшийся хозяин. */
const $ИО_НЕ_ПРОВЕРЕНО = "Не проверено"

