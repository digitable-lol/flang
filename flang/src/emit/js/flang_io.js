/**
 * План по имени; без имени — единственный объявленный.
 *
 * Ровно то же правило, что у свидетеля (`findPlan`), и то же по причине: имя
 * плана — это то, что называет ЗАПУСКАЮЩИЙ, а не программа, и при одном плане
 * заставлять его повторять имя незачем.
 */
function $ioНайти($io, имя) {
  const планы = $io.планы
  if (планы.length === 0) $fail("FLANG_UNKNOWN_PLAN", "в программе нет ни одного плана: исполнять нечего")
  if (имя === undefined || имя === null || имя === "") {
    if (планы.length === 1) return планы[0]
    $fail("FLANG_UNKNOWN_PLAN", `планов несколько (${планы.map((п) => `«${п.имя}»`).join(", ")}) — назовите нужный`)
  }
  const найден = планы.find((план) => план.имя === имя)
  if (найден === undefined) $fail("FLANG_UNKNOWN_PLAN", `не найден план «${имя}»`)
  return найден
}

/** Значение — вариант с этим именем из этого набора? */
function $ioИзНабора(значение, набор) {
  return $isVariant(значение) && набор.includes(значение.variant)
}

/**
 * Прогнать план, отдавая поручения наружу.
 *
 * `исполнить` — функция хозяина: поручение → отклик; может быть асинхронной.
 * Ни одного эффекта сам исполнитель не делает, и в этом весь смысл: подставь
 * список заготовленных откликов — и тот же план прогоняется без экрана, без
 * файлов и без сети.
 *
 * ВОТ ЗДЕСЬ тянущий цикл становится толкающим: `await исполнить(поручение)`.
 * Хозяину, который ждёт нажатия, достаточно вернуть обещание — стек на это
 * время пуст, вкладка жива и отзывчива, и ни одной строки исполнителя менять не
 * приходится.
 *
 * @param {object} $io описатель планов модуля (`ioPlan()`)
 * @param {string} имя имя объявленного плана; пусто — единственный
 * @param {(поручение: object) => object|Promise<object>} исполнить хозяин
 * @param {{ поручений?: number, журнал?: boolean }} [настройки]
 * @returns {Promise<{значение: unknown, поручений: number, журнал: object[]}>}
 */
async function $ioПрогон($io, имя, исполнить, настройки = {}) {
  const план = $ioНайти($io, имя)
  if (typeof исполнить !== "function") {
    $fail("FLANG_IO", "исполнителю плана нужна функция «выполнить поручение»")
  }
  const заявлено = настройки.поручений
  const предел = typeof заявлено === "number" ? заявлено : $ИО_ПРЕДЕЛ
  const безПредела = !(предел > 0)
  const вестиЖурнал = настройки.журнал === true
  const журнал = []
  let выдано = 0

  let состояние = план.начало()
  let отклик = $io.вариант($ИО_НАЧАЛО, {})

  for (;;) {
    const продолжение = план.шаг(состояние, отклик)
    if (!$ioИзНабора(продолжение, [$ИО_СДЕЛАТЬ, $ИО_КОНЕЦ, $ИО_ПРОВАЛ, $ИО_НЕ_ПРОВЕРЕНО])) {
      $fail("FLANG_IO", `шаг плана «${план.имя}» вернул не «Продолжение»`)
    }

    if (продолжение.variant === $ИО_КОНЕЦ) {
      return { значение: продолжение.fields["значение"] ?? null, поручений: выдано, журнал }
    }
    if (продолжение.variant === $ИО_ПРОВАЛ) {
      /* Код берётся у программы, а не назначается здесь: программа сдаётся
         сама, и она же лучше знает, чем именно. Признак `сдался` ставится
         РЯДОМ с бедой и только здесь — только здесь известно, что решение
         принято программой, а не сломался исполнитель. Читает его тот, кто
         превращает беду в код выхода. */
      const код = продолжение.fields["код"]
      const сообщение = продолжение.fields["сообщение"]
      try {
        $fail(
          typeof код === "string" && код !== "" ? код : "FLANG_IO_FAILED",
          typeof сообщение === "string" ? сообщение : `план «${план.имя}» отказался продолжать`,
        )
      } catch (беда) {
        беда.сдался = true
        throw беда
      }
    }

    if (продолжение.variant === $ИО_НЕ_ПРОВЕРЕНО) {
      const код = продолжение.fields["код"]
      const сообщение = продолжение.fields["сообщение"]
      $fail(
        typeof код === "string" && код !== "" ? код : "FLANG_IO_NOT_CHECKED",
        typeof сообщение === "string" ? сообщение : `план «${план.имя}» не смог проверить предмет`,
      )
    }

    if (!безПредела && выдано >= предел) {
      $fail("FLANG_IO_LIMIT", `план «${план.имя}» исчерпал предел поручений (${предел})`)
    }

    const поручение = продолжение.fields["поручение"]
    if (!$ioИзНабора(поручение, $ИО_ПОРУЧЕНИЯ)) {
      /* ОТКАЗ ОБЯЗАН НАЗЫВАТЬ. Прежде здесь стояло «просит выполнить не
         поручение» — без имени, и читатель шёл править программу, тогда как
         отставал этот список. Имя варианта у значения есть всегда; когда его
         нет вовсе, так и сказано. */
      const чтоПришло = $isVariant(поручение) ? `вариант «${поручение.variant}»` : "не вариант суммы"
      $fail("FLANG_IO", `план «${план.имя}» просит выполнить не поручение: ${чтоПришло}`)
    }
    состояние = продолжение.fields["потом"] ?? null
    const ответ = await исполнить(поручение)
    if (!$ioИзНабора(ответ, $ИО_ОТКЛИКИ)) {
      $fail("FLANG_IO", `хозяин вернул не «Отклик» на поручение «${поручение.variant}» плана «${план.имя}»`)
    }
    отклик = ответ
    выдано += 1
    if (вестиЖурнал) журнал.push({ поручение, отклик })
  }
}
