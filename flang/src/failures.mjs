/**
 * Предел одного пробега, с которым сводится оценка витков.
 *
 * МЕНЬШЕЕ из двух, и в этом вся починка. Планировщик режет пробег двумя
 * независимыми пределами — миллион витков (`TOTAL_HANDLER_STEPS`) и десять тысяч
 * кадров глубины (`TOTAL_HANDLER_DEPTH`), — а здесь сводился только первый.
 * Отсюда дыра, предъявленная прогоном: обработчик с ПОСТОЯННОЙ оценкой в 260 036
 * витков анализ объявлял безотказным, а прогон ронял процесс
 * `FLANG_RECURSION_LIMIT` на глубине 10 001, и список решений надзора оставался
 * пустым.
 *
 * Почему меньшего ДОСТАТОЧНО, а не «примерно достаточно». Глубина не бывает
 * больше числа витков: каждый нехвостовой вызов растит её ровно на единицу и
 * стоит при этом хотя бы один оборот машины (`interpret.mjs`, `finishCall`).
 * Значит постоянная оценка `С` мажорирует и витки, и глубину разом, и `С` меньше
 * меньшего из пределов доказывает, что не сработает ни один.
 */
export const ПРЕДЕЛ_ПРОБЕГА = Math.min(TOTAL_HANDLER_STEPS, TOTAL_HANDLER_DEPTH)

