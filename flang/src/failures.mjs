/**
 * failures.mjs — множество отказов процесса как ВЫЧИСЛИМОЕ множество.
 *
 * Ради чего этот файл вообще есть. В Erlang множество отказов процесса открыто:
 * `badmatch`, `badarg`, `function_clause`, `undef`, что угодно из NIF. Перечислить,
 * чем именно может упасть данный процесс, там нельзя в принципе — и отсюда «let it
 * crash»: супервизор обязан быть механизмом общего назначения, потому что он не
 * знает, от чего спасает.
 *
 * В flang это множество замкнуто и перечислимо, и его можно посчитать до запуска.
 * Тогда надзор перестаёт быть только механизмом времени выполнения и становится
 * ещё и АНАЛИЗОМ: процесс, который может упасть, а надзора над ним нет, — ошибка
 * проверки, а не сюрприз в бою (`flang/conc/RESILIENCE.md`, шаг Г1). У OTP такого
 * не может быть никогда: сводить не с чем.
 *
 * ── Множество отказов: три вида, и все три проверены прогоном ───────────────
 *
 * Не переписаны из контракта, а предъявлены: на каждый вид есть программа,
 * которая им падает, и она лежит в `flang/test/failures.test.mjs`. Контракт в
 * двух местах говорил не то, что делает планировщик, и оба места названы ниже.
 *
 *   1. «запас витков» — `FLANG_BUDGET_EXHAUSTED`. Обработчик без признака
 *      `тотальная` обязан назвать запас (types.mjs), и запас может кончиться.
 *      У тотального обработчика этого вида нет: завершение доказано.
 *
 *   2. «частичная форма» — `FLANG_BUILTIN_ARGS`. Встроенная форма, определённая
 *      не на всех значениях своего типа: `элемент` за концом списка, `голова`
 *      пустого, `к числу` от строки, которая числом не является. Список этих
 *      форм закрыт (`ЧАСТИЧНЫЕ` ниже) и сверяется с `builtins.mjs` прогоном:
 *      появится восьмая — тест назовёт её.
 *
 *   3. «остановлен» — `FLANG_STOPPED`. Явное `остановить` с причиной, отличной
 *      от «норма». Причина-литерал «норма» отказом не является, и это видно на
 *      этапе проверки: значит `остановить` с нормой множество отказов НЕ
 *      расширяет, а `остановить` с любой другой причиной — расширяет.
 *
 * Чего в множестве НЕТ, хотя контракт это называет:
 *
 *   • «деление на ноль». Его не бывает: деление в flang — IEEE-754, и `1 делить
 *     на 0` даёт бесконечность, а не отказ (builtins.mjs, `remainderOf` и
 *     соседи). Контракт (`flang/conc/SPEC.md`, «Отказ, надзор, перезапуск») и
 *     карта (`RESILIENCE.md`) называют его отказом — это неверно, и проверено
 *     прогоном.
 *
 *   • «деление структуры не того варианта» и неполный разбор. Их исключает
 *     проверка типов: `FLANG_MATCH_NOT_EXHAUSTIVE` — ошибка компиляции
 *     (types.mjs), а поля варианта достаются только через `разбор`. До прогона
 *     такой отказ не доживает.
 *
 * ── Чего этот анализ НЕ ловит, и это дыра, а не упрощение ───────────────────
 *
 * Тотальный обработчик тоже может упасть — `FLANG_RECURSION_LIMIT`, — и этого
 * вида в перечислении нет ни у контракта, ни здесь. Причина в том, что он
 * НЕПЕРЕЧИСЛИМ из текста программы: предел в миллион витков не объявлен нигде в
 * исходнике, он константа планировщика (`conc.mjs`, `TOTAL_HANDLER_STEPS`).
 * Тотальность даёт «завершится», а не «завершится скоро»: тотальная `фиб` от 34
 * доказанно завершается и при этом упирается в миллион. Программа, которая это
 * показывает, лежит в тестах и падает сегодня.
 *
 * Закрыть дыру нечем, пока нет ОГРАНИЧЕННОСТИ — оценки сверху на витки от
 * размера входа (`RESILIENCE.md`, шаг В3). Поэтому здесь она названа, а не
 * замазана: анализ честно говорит «три вида», а не «все».
 *
 * ── Почему достижимость считается по графу вызовов, а не по телу обработчика ─
 *
 * Отказ случается там, где стоит частичная форма, а стоять она может в функции,
 * которую обработчик зовёт через три перехода. Значит считать надо транзитивное
 * замыкание — то самое, которым уже пользуются дефункционализация и проверка
 * тотальности. Замыкание берёт и `fnref`: функция, отданная как значение в
 * `отобразить`, будет вызвана, и её отказы — отказы этого процесса.
 *
 * Оценка СВЕРХУ, и это сказано прямо: «может упасть» здесь значит «в достижимом
 * коде есть место, где отказ этого вида возможен», а не «есть вход, на котором
 * он случится». Второе неразрешимо. Ошибаться в эту сторону безопасно: анализ
 * требует надзора там, где отказа может и не быть, но никогда не молчит там,
 * где он может быть.
 */

/** Виды отказа. Список закрыт: третьего источника у отказа процесса нет. */
export const ВИДЫ_ОТКАЗА = Object.freeze({
  ЗАПАС: "запас витков",
  ЧАСТИЧНАЯ: "частичная форма",
  ОСТАНОВЛЕН: "остановлен",
})

/** Код диагностики: у процесса есть достижимый отказ, а надзора над ним нет. */
export const UNCOVERED_CODE = "FLANG_UNCOVERED_FAILURE"

/**
 * Встроенные формы, определённые не на всех значениях своего типа.
 *
 * Закрытый список, и он обязан совпадать с `builtins.mjs`: форма, которая
 * бросает `FLANG_BUILTIN_ARGS` на правильно типизированном входе, обязана быть
 * здесь. Сверка — в `flang/test/failures.test.mjs`, и она смотрит на сам
 * `builtins.mjs`, а не на копию списка.
 *
 * Формы, которых здесь нет, партиальными не являются: `длина`, `символы`,
 * `содержит`, `начинается с`, `пусто`, `добавить`, `остаток от`, `процентов от`,
 * `к строке`, `к числу или беда` — все они определены всюду, где проверка типов
 * их пропускает. Отдельно про `к числу или беда`: она для того и заведена,
 * чтобы отказа НЕ было — беда возвращается значением.
 */
export const ЧАСТИЧНЫЕ = Object.freeze(
  new Map([
    ["элемент", "номер может выйти за список"],
    ["символ", "номер может выйти за строку"],
    ["подстрока", "границы могут выйти за строку"],
    ["разделить", "разделитель может оказаться пустым"],
    ["к числу", "строка может не быть числом"],
    ["голова", "список может оказаться пустым"],
    ["хвост", "список может оказаться пустым"],
  ]),
)

/** Причина `остановить`, которая отказом не является (conc.mjs, `NORMAL_STOP`). */
const НОРМА = "норма"

/**
 * Достижимые отказы каждого процесса программы.
 *
 * @param {object} program AST с `processes` и `functions`
 * @returns {Map<string, Array<{вид: string, почему: string, где: object|null, функция: string|null}>>}
 *   Ключ — имя процесса, значение — виды отказа в порядке видов, по одной записи
 *   на вид: первое найденное место каждого вида. Одной записи хватает, потому
 *   что решение надзора одно на вид, а не на место; остальные места нашлись бы
 *   тем же анализом, но диагностику они бы только удлинили.
 */
export function достижимыеОтказы(program) {
  const процессы = Array.isArray(program?.processes) ? program.processes : []
  const итог = new Map()
  if (процессы.length === 0) return итог

  const функции = program?.functions ?? []
  const тотальные = new Set(функции.filter((фн) => фн?.total === true).map((фн) => фн.name))
  /* Тело каждой функции обходится РОВНО ОДИН РАЗ на всю программу, а не по разу
     на каждый процесс, который до неё дотягивается. Разница не косметическая:
     пятьсот процессов над общей цепочкой из ста функций — это пятьдесят тысяч
     обходов AST против шестисот. Замерено на такой программе: 38,0 мс до
     разделения, 5,6 мс после, при 9,2 мс на всю остальную проверку типов.

     Что осталось и почему это не чинится здесь: замыкание всё ещё считается по
     разу на обработчик, то есть O(процессов × достижимых функций) переходов по
     готовой таблице. На той же синтетике это те самые 5,6 мс; на живых
     программах, где процессов десятки, а не сотни, это десятые доли
     миллисекунды. Убрать множитель можно только сложением замыканий снизу вверх
     по конденсации графа вызовов, а это отдельная работа с циклами, и делать её
     ради синтетики значило бы усложнять по догадке. */
  const собственные = new Map()
  for (const фн of функции) {
    if (typeof фн?.name === "string" && !собственные.has(фн.name)) {
      собственные.set(фн.name, своиОтказы(фн))
    }
  }
  /* Замыкание считается один раз на ОБРАБОТЧИК: в `escalate.flang` три процесса
     делят один обработчик, и считать его трижды значило бы платить втрое за один
     и тот же ответ. */
  const разобранные = new Map()

  for (const узел of процессы) {
    if (typeof узел?.name !== "string") continue
    const отказы = []

    /* 1. Запас витков. Тотальность его снимает целиком — не «делает
       маловероятным», а именно снимает: планировщик не считает витки тому, про
       кого доказано, что он вернётся (conc.mjs). */
    if (!тотальные.has(узел.handler) && узел.budget !== null && узел.budget !== undefined) {
      отказы.push({
        вид: ВИДЫ_ОТКАЗА.ЗАПАС,
        почему: `обработчик «${узел.handler}» не тотален и работает по запасу в ${узел.budget} витков`,
        где: узел.span ?? null,
        функция: узел.handler ?? null,
      })
    }

    for (const запись of замыканиеОтказов(узел.handler, собственные, разобранные)) отказы.push(запись)
    итог.set(узел.name, отказы)
  }
  return итог
}

/**
 * Что функция может сама по себе: кого зовёт и чем падает.
 *
 * Считается один раз на функцию, потому что это её свойство, а не свойство
 * процесса. Порядок обхода — порядок узлов в теле, и он же становится порядком
 * записей в диагностике: на одном исходнике она обязана быть одной и той же,
 * иначе её нельзя сверить.
 */
function своиОтказы(фн) {
  const вызовы = []
  const частичные = new Map()
  let остановка = null

  обойти(фн.body, (узел) => {
    /* `fnref` наравне с `call`: функция, отданная значением в «отобразить»,
       будет вызвана, и её отказы — отказы того, кто её отдал. */
    if ((узел.kind === "call" || узел.kind === "fnref") && typeof узел.name === "string") {
      вызовы.push(узел.name)
    }
    if (узел.kind === "builtin" && ЧАСТИЧНЫЕ.has(узел.name) && !частичные.has(узел.name)) {
      частичные.set(узел.name, {
        вид: ВИДЫ_ОТКАЗА.ЧАСТИЧНАЯ,
        почему: `«${узел.name}»: ${ЧАСТИЧНЫЕ.get(узел.name)}`,
        где: узел.span ?? фн.span ?? null,
        функция: фн.name,
      })
    }
    if (узел.kind === "construct" && узел.variant === "остановить" && остановка === null) {
      const причина = причинаОстановки(узел)
      if (причина.отказ) {
        остановка = {
          вид: ВИДЫ_ОТКАЗА.ОСТАНОВЛЕН,
          почему: причина.почему,
          где: узел.span ?? фн.span ?? null,
          функция: фн.name,
        }
      }
    }
  })

  return { вызовы, частичные, остановка }
}

/**
 * Отказы, достижимые из функции: она сама и всё, до чего дотягивается.
 *
 * Обход в ширину по уже посчитанным таблицам, без единого захода в AST. Круг в
 * вызовах ему не страшен: `пройденные` обрывает повтор, а взаимная рекурсия для
 * этого анализа ничем не отличается от обычного вызова — множество отказов у
 * цикла то же самое, что у его звеньев вместе.
 */
function замыканиеОтказов(имя, собственные, кэш) {
  if (typeof имя !== "string") return []
  const готовое = кэш.get(имя)
  if (готовое !== undefined) return готовое

  const пройденные = new Set()
  const очередь = [имя]
  const частичные = new Map()
  let остановка = null

  while (очередь.length > 0) {
    const текущее = очередь.shift()
    if (пройденные.has(текущее)) continue
    пройденные.add(текущее)
    const своё = собственные.get(текущее)
    if (своё === undefined) continue
    for (const дальше of своё.вызовы) очередь.push(дальше)
    for (const [форма, запись] of своё.частичные) {
      if (!частичные.has(форма)) частичные.set(форма, запись)
    }
    if (остановка === null && своё.остановка !== null) остановка = своё.остановка
  }

  /* Порядок видов постоянен: сначала частичные формы в порядке обнаружения,
     потом остановка. «Запас витков» дописывается снаружи, потому что он
     свойство процесса, а не функции: один и тот же обработчик у двух процессов
     может стоять с запасом и без. */
  const ответ = [...частичные.values()]
  if (остановка !== null) ответ.push(остановка)
  кэш.set(имя, ответ)
  return ответ
}

/**
 * Отказ ли это `остановить`.
 *
 * Литеральная «норма» — не отказ, и это решается здесь, а не в прогоне. Любой
 * другой литерал — отказ с названной причиной. Вычисляемая причина — отказ, и
 * это единственное честное решение: значение строки заранее неизвестно, а
 * молчать про «может быть отказ» анализ не имеет права.
 */
function причинаОстановки(узел) {
  const поле = узел.fields?.["почему"]
  if (поле?.kind === "literal") {
    if (поле.value === НОРМА) return { отказ: false, почему: "" }
    return { отказ: true, почему: `«остановить» с причиной «${String(поле.value)}»` }
  }
  return {
    отказ: true,
    почему: "«остановить» с вычисляемой причиной: она может оказаться не «нормой»",
  }
}

/**
 * Обход выражений. Тот же приём, что в `tags.mjs`: узлы AST — обычные объекты,
 * и обходить их вглубь дешевле, чем держать список видов узлов, который
 * разойдётся с парсером на первом же новом виде.
 */
function обойти(узел, посетить) {
  if (Array.isArray(узел)) {
    for (const элемент of узел) обойти(элемент, посетить)
    return
  }
  if (узел === null || typeof узел !== "object") return
  if (typeof узел.kind === "string") посетить(узел)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span" || ключ === "meta") continue
    if (значение !== null && typeof значение === "object") обойти(значение, посетить)
  }
}
