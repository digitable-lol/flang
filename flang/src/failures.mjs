/**
 * Сколько МЕСТ частичных форм в теле функции.
 *
 * Считается по местам, а не по формам, и это не педантизм: в напечатанном коде
 * каждое место — своя проверка во время работы, и десять обращений `элемент`
 * стоят десяти проверок, а не одной. Множеству отказов процесса хватает вопроса
 * «может ли», поэтому там формы схлопываются в `Map` по имени; ведомости
 * доказательства нужен вопрос «сколько», и ответ на него другой.
 *
 * Живёт эта функция здесь, а не у ведомости, по той же причине, по которой
 * здесь живёт сам список: место частичной формы — это то и только то, что
 * названо в `ЧАСТИЧНЫЕ`. Второй обход в другом файле разошёлся бы с этим
 * списком молча в тот день, когда список пополнится.
 *
 * Тело берётся то, которое ИСПОЛНЯЕТСЯ: `body` вместе с отметкой меры, если
 * загрузчик её уже поставил (`markMeasureGuards`). Мера считается на каждом
 * витке, и частичная форма внутри неё — такое же место проверки, как в теле.
 *
 * МЕСТО С ОТМЕТКОЙ `доказана` НЕ СЧИТАЕТСЯ, и это то самое, ради чего отметка
 * заведена. Отметку кладёт передний край по выводу проверки типов
 * (`src/types.mjs`, `markNonEmpty`): непустота списка или строки доказана, и
 * печать зовёт там помощника без сторожа (`emit/*.mjs`, `ДОКАЗАННЫЕ_ПОМОЩНИКИ`).
 * Считать такое место проверкой значило бы называть проверкой то, чего в
 * напечатанном коде нет. Программа, до которой отметка не доехала (разбор без
 * загрузчика), считается ровно как раньше — поле просто отсутствует.
 *
 * @param {object} функция узел объявления функции
 * @returns {number} мест частичных форм в её теле
 */
export function местЧастичныхФорм(функция) {
  let мест = 0
  обойти(функция?.body ?? null, (узел) => {
    if (узел.kind === "builtin" && ЧАСТИЧНЫЕ.has(узел.name) && узел.доказана !== true) мест += 1
  })
  return мест
}

/**
 * Кого функция зовёт: имена вызовов и функций, отданных значением.
 *
 * `fnref` наравне с `call`, и по той же причине, по которой их считает вместе
 * замыкание отказов ниже: функция, отданная в `отобразить` значением, БУДЕТ
 * вызвана, и всё, что она проверяет во время работы, проверяется при работе
 * того, кто её отдал. На сегодняшнем корпусе `fnref` не меняет ни одного числа
 * (свод даёт 1737 и с ним, и без него) — сказано это здесь затем, чтобы никто
 * не считал его проверенным: он стоит по правилу, а не по улике.
 *
 * Живёт здесь, а не у ведомости, потому что вопрос тот же самый, на который
 * этот файл отвечает процессам: «до чего дотягивается достижимый код». Разница
 * только в том, откуда начинать обход, — и вот её каждый спрашивающий решает
 * сам.
 *
 * @param {object} функция узел объявления функции
 * @returns {Set<string>} имена, до которых её тело дотягивается за один шаг
 */
export function именаВызовов(функция) {
  const имена = new Set()
  обойти(функция?.body ?? null, (узел) => {
    if ((узел.kind === "call" || узел.kind === "fnref") && typeof узел.name === "string") имена.add(узел.name)
  })
  return имена
}

/** Причина `остановить`, которая отказом не является (conc.mjs, `NORMAL_STOP`). */
const НОРМА = "норма"

/**
 * Процессы с ОБЪЯВЛЕННЫМ ящиком (А3) и объявленный потолок каждого.
 *
 * Считается по программе, а не по функции, потому что «отправить» знает только
 * имя адресата, а потолок объявлен у адресата. Адресат в действии обязан быть
 * литералом (types.mjs, `addresseeOf`), поэтому вопрос «может ли эта функция
 * упереться в чужой ящик» решается по тексту, а не гаданием.
 *
 * Отдельной функцией потому, что таблица нужна ОБОИМ анализам — и обработчику,
 * и начальному состоянию. Два одинаковых цикла разошлись бы молча, а расхождение
 * здесь стоит дорого: анализ, у которого таблица пуста, перестаёт видеть пятый
 * вид отказа вовсе и молчит там, где обязан говорить.
 */
/**
 * Функции, чьё доказательство завершения держится на ЧИСЛОВОЙ мере.
 *
 * Ровно те, на чьи вызовы понижение поставит сторожа (`defunc.mjs`), — потому
 * что источник тут один и тот же: `guards` (постоянный шаг) и `descents`
 * (объявленная мера) из анализа завершаемости. Тот же список читает
 * `markMeasureGuards`, и разойтись они не могут: он не скопирован, а взят.
 *
 * Спрашивается именно у анализа, а не у текста программы, и это не педантизм.
 * По тексту видно только `убывает`, и видно неверно в обе стороны: постоянный
 * шаг в тексте не написан вовсе (`н минус 1` — обычная арифметика), а
 * объявленная мера у функции, чью рекурсию доказала СТРУКТУРА, сторожа не
 * получает — анализ пробует меру последней, и «объявить её там, где доказывает
 * структура, не значит начать платить за сторожа» (`flang/SPEC.md`). Считать по
 * тексту значило бы требовать надзора там, где отказ невозможен.
 *
 * Цену платят только программы с процессами: оба анализа этого файла выходят до
 * первого вычисления, если процессов нет (`достижимыеОтказы`,
 * `отказыНачального`), а конкурентные программы малы.
 *
 * @param {object} program AST flang
 * @returns {Map<string, string>} имя функции → чем именно она стережётся
 */
function стережённыеМерой(program) {
  const итог = new Map()
  const проверка = checkTotality(program)
  const добавить = (имя, почему) => {
    if (typeof имя === "string" && !итог.has(имя)) итог.set(имя, почему)
  }
  for (const guard of проверка.guards ?? []) {
    добавить(
      guard?.from,
      `доказательство держится на постоянном шаге по «${guard?.param ?? "?"}» в вызове «${guard?.to ?? "?"}», ` +
        "а при большом значении шаг не меняет числа: числа IEEE-754",
    )
  }
  for (const descent of проверка.descents ?? []) {
    добавить(
      descent?.from,
      `доказательство держится на объявленной мере «убывает» в вызове «${descent?.to ?? "?"}», ` +
        "а мера обязана убыть, остаться неотрицательной и остаться целой на КАЖДОМ витке",
    )
  }
  return итог
}

function объявленныеЯщики(процессы) {
  const сЯщиком = new Map()
  for (const узел of процессы) {
    if (typeof узел?.name === "string" && Number.isInteger(узел.mailbox) && узел.mailbox > 0) {
      сЯщиком.set(узел.name, узел.mailbox)
    }
  }
  return сЯщиком
}

/**
 * Достижимые отказы каждого процесса программы.
 *
 * @param {object} program AST с `processes` и `functions`
 * @returns {Map<string, Array<{вид: string, почему: string, где: object|null, функция: string|null}>>}
 *   Ключ — имя процесса, значение — виды отказа в порядке видов, по одной записи
 *   на вид: первое найденное место каждого вида. Одной записи хватает, потому
 *   что решение надзора одно на вид, а не на место; остальные места нашлись бы
 *   тем же анализом, но диагностику они бы только удлинили.
 */
export function достижимыеОтказы(program) {
  const процессы = Array.isArray(program?.processes) ? program.processes : []
  const итог = new Map()
  if (процессы.length === 0) return итог

  const функции = program?.functions ?? []
  const тотальные = new Set(функции.filter((фн) => фн?.total === true).map((фн) => фн.name))
  /* Оценки витков считаются один раз на программу: они свойство функций, а не
     процессов, и три процесса с общим обработчиком (escalate.flang) обязаны
     получить одну и ту же оценку, а не три одинаковые. */
  const оценки = оценитьВитки(program)
  /* Тело каждой функции обходится РОВНО ОДИН РАЗ на всю программу, а не по разу
     на каждый процесс, который до неё дотягивается. Разница не косметическая:
     пятьсот процессов над общей цепочкой из ста функций — это пятьдесят тысяч
     обходов AST против шестисот. Замерено на такой программе: 38,0 мс до
     разделения, 5,6 мс после, при 9,2 мс на всю остальную проверку типов.

     Что осталось и почему это не чинится здесь: замыкание всё ещё считается по
     разу на обработчик, то есть O(процессов × достижимых функций) переходов по
     готовой таблице. На той же синтетике это те самые 5,6 мс; на живых
     программах, где процессов десятки, а не сотни, это десятые доли
     миллисекунды. Убрать множитель можно только сложением замыканий снизу вверх
     по конденсации графа вызовов, а это отдельная работа с циклами, и делать её
     ради синтетики значило бы усложнять по догадке. */
  const сЯщиком = объявленныеЯщики(процессы)
  /* Шестой вид спрашивается у анализа завершаемости, а не у текста: сторожа
     ставит понижение по его же спискам (см. `стережённыеМерой`). */
  const стережённые = стережённыеМерой(program)
  const собственные = new Map()
  for (const фн of функции) {
    if (typeof фн?.name === "string" && !собственные.has(фн.name)) {
      собственные.set(фн.name, своиОтказы(фн, сЯщиком, стережённые))
    }
  }
  /* Замыкание считается один раз на ОБРАБОТЧИК: в `escalate.flang` три процесса
     делят один обработчик, и считать его трижды значило бы платить втрое за один
     и тот же ответ. */
  const разобранные = new Map()

  for (const узел of процессы) {
    if (typeof узел?.name !== "string") continue
    const отказы = []

    /* 1. Запас витков. Тотальность снимает ЕГО — не «делает маловероятным», а
       именно снимает: планировщик не считает витки тому, про кого доказано, что
       он вернётся (conc.mjs). Но снимает она только объявленный запас, а не
       предел планировщика: его разбирает пункт 2 сразу ниже. */
    if (!тотальные.has(узел.handler) && узел.budget !== null && узел.budget !== undefined) {
      отказы.push({
        вид: ВИДЫ_ОТКАЗА.ЗАПАС,
        почему: `обработчик «${узел.handler}» не тотален и работает по запасу в ${узел.budget} витков`,
        где: узел.span ?? null,
        функция: узел.handler ?? null,
      })
    }

    /* 2. Предел витков планировщика — тот самый вид, которого здесь не было.
       Проверяется только у тотального обработчика: у нетотального витки уже
       посчитаны запасом, и второго предела он не увидит. */
    if (тотальные.has(узел.handler)) {
      const почему = чемПлохаОценка(оценки.get(узел.handler))
      if (почему !== null) {
        отказы.push({
          вид: ВИДЫ_ОТКАЗА.ПРЕДЕЛ,
          почему: `обработчик «${узел.handler}» тотален, но ${почему}, ` +
            `а планировщик снимает пробег на ${TOTAL_HANDLER_STEPS} витках ` +
            `и на ${TOTAL_HANDLER_DEPTH} кадрах глубины`,
          где: узел.span ?? null,
          функция: узел.handler ?? null,
        })
      }
    }

    for (const запись of замыканиеОтказов(узел.handler, собственные, разобранные)) отказы.push(запись)
    итог.set(узел.name, отказы)
  }
  return итог
}

/**
 * Чем оценка витков не годится в доказательство того, что предел не достижим.
 *
 * `null` — годится: отказа этого вида у процесса нет. Строка — не годится, и она
 * же становится половиной текста диагностики, потому что «надзора нет» без «а
 * почему он нужен» читателю ничего не говорит.
 */
function чемПлохаОценка(запись) {
  if (запись === undefined || запись.оценка === null) {
    return `оценки витков у него нет: ${запись?.причина ?? "функция не найдена"}`
  }
  if (степень(запись.оценка) > 0) {
    return `витков у него ${текстОценки(запись.оценка)} — оценка растёт с размером входа`
  }
  const сколько = значение(запись.оценка, 0)
  if (сколько >= ПРЕДЕЛ_ПРОБЕГА) {
    return `витков у него ${сколько}, и это не меньше предела`
  }
  return null
}

/**
 * Отказы, достижимые из функции `начинает с` каждого процесса.
 *
 * Отдельно от `достижимыеОтказы`, потому что это отказы РАЗНОГО рода, и смешать
 * их значило бы соврать в диагностике. Отказ обработчика случается у живого
 * процесса, его видит надзор, и ответ на него — надзор. Отказ начального
 * состояния случается ДО того, как процесс появился: планировщик зовёт
 * `начинает с` при заводе (`conc.mjs`), надзирать в этот момент не над кем, а
 * перезапуск по контракту возвращает то же самое вычисленное значение — то
 * есть надзор не помог бы и потом.
 *
 * До этой функции `начинает с` не входил в анализ ВОВСЕ: считалось замыкание
 * только от `узел.handler`. Дыру предъявил прогон — программа с
 * `начинает с «нуль»`, где «нуль» берёт девятый элемент трёхэлементного списка,
 * проходила все проверки с нулём диагностик и валила ВСЮ программу на заводе
 * первого процесса.
 *
 * Считается тем же замыканием и по тем же правилам: вид «частичная форма» и вид
 * «остановлен» ловятся как у обработчика; вид «предел витков» ловится только
 * отсутствием доказательства завершения, потому что запаса витков у начального
 * состояния нет и назвать его негде.
 *
 * @param {object} program AST с `processes` и `functions`
 * @returns {Map<string, Array<{вид: string, почему: string, где: object|null, функция: string|null}>>}
 */
export function отказыНачального(program) {
  const процессы = Array.isArray(program?.processes) ? program.processes : []
  const итог = new Map()
  if (процессы.length === 0) return итог

  const функции = program?.functions ?? []
  const тотальные = new Set(функции.filter((фн) => фн?.total === true).map((фн) => фн.name))
  const оценки = оценитьВитки(program)
  /* Та же таблица ящиков, что и у обработчика, и это не «на всякий случай»:
     `своиОтказы` — одна функция на оба анализа, и звать её здесь с пустой
     таблицей значило бы считать начальное состояние по другим правилам, чем
     обработчик. Оценка тут сверху, как и везде в этом файле: `отправить`,
     построенный в `начинает с`, планировщик действием не выполнит (он берёт из
     отклика, а не из начального значения), но и `остановить` он оттуда не
     выполнит — а его этот анализ считает отказом с самого начала. Правило одно
     на все виды: построил в достижимом коде — назван. */
  const сЯщиком = объявленныеЯщики(процессы)
  /* Шестой вид спрашивается у анализа завершаемости, а не у текста: сторожа
     ставит понижение по его же спискам (см. `стережённыеМерой`). */
  const стережённые = стережённыеМерой(program)
  const собственные = new Map()
  for (const фн of функции) {
    if (typeof фн?.name === "string" && !собственные.has(фн.name)) {
      собственные.set(фн.name, своиОтказы(фн, сЯщиком, стережённые))
    }
  }
  const разобранные = new Map()

  for (const узел of процессы) {
    if (typeof узел?.name !== "string" || typeof узел.initial !== "string") continue
    const отказы = []

    /* Тотальность у начального состояния не роскошь: планировщик зовёт его без
       запаса витков, и нетотальная функция здесь — это программа, которая может
       не запуститься вовсе. Тот же спрос, что с обработчика без запаса, только
       ответить на него нечем, кроме доказательства. */
    if (!тотальные.has(узел.initial)) {
      отказы.push({
        вид: ВИДЫ_ОТКАЗА.ПРЕДЕЛ,
        почему: `начальное состояние «${узел.initial}» не помечено тотальным, а запаса витков у него ` +
          `нет и назвать его негде: планировщик зовёт его при заводе процесса`,
        где: узел.span ?? null,
        функция: узел.initial,
      })
    } else {
      const почему = чемПлохаОценка(оценки.get(узел.initial))
      if (почему !== null) {
        отказы.push({
          вид: ВИДЫ_ОТКАЗА.ПРЕДЕЛ,
          почему: `начальное состояние «${узел.initial}» тотально, но ${почему}, ` +
            `а планировщик снимает пробег на ${TOTAL_HANDLER_STEPS} витках ` +
            `и на ${TOTAL_HANDLER_DEPTH} кадрах глубины`,
          где: узел.span ?? null,
          функция: узел.initial,
        })
      }
    }

    for (const запись of замыканиеОтказов(узел.initial, собственные, разобранные)) отказы.push(запись)
    итог.set(узел.name, отказы)
  }
  return итог
}

/**
 * Отказы ПРЕДСТАВИТЕЛЕЙ: седьмой вид, и считается он не по тексту программы.
 *
 * ── Улика, ради которой функция написана ────────────────────────────────────
 *
 * Программа из двух безотказных по тексту процессов — оба тотальны, оценка витков
 * постоянная, частичных форм нет, `остановить` нет, ящик не объявлен — проходила
 * `flang check` С НУЛЁМ ДИАГНОСТИК. Размещение разводило их по двум узлам, узлы
 * поднимались, связь рвалась, и журнал говорил
 * `{"в":"отказ","процесс":"Слушатель","код":"FLANG_LINK_DOWN"}` при НУЛЕ решений
 * надзора: процесс оставался мёртвым, и сказать об этом было некому. То есть
 * обещание Г1 (`flang/conc/RESILIENCE.md`) — «отказ, который процесс может
 * выдать, а надзор не разбирает, — ошибка проверки» — через границу узла было
 * ложью, и ложью молчаливой.
 *
 * ── Откуда анализ узнаёт размещение, и почему именно оттуда ─────────────────
 *
 * Размещение — ДАННЫЕ УЗЛА, а не текст программы (`DISTRIBUTED.md`, «Размещение
 * — данные узла»): тот же исходник идёт на один узел и на два, и переписывать
 * его ради смены хоста значило бы пересобирать программу ради смены хоста.
 * Значит размещение анализ получает ДОВОДОМ — `flang check --размещение …` — и
 * тем же доводом, каким его получает узел при подъёме (`conc/bin/node.mjs`
 * отдаёт сюда свой файл размещения). Программу без размещения это не трогает ни
 * на диагностику: границы узла нет — представителей нет — и седьмого вида нет.
 *
 * ── Правило, и оно короче, чем кажется ─────────────────────────────────────
 *
 * У процесса есть представитель на КАЖДОМ узле, кроме своего (`distributed.mjs`,
 * таблица процессов: всё, что размещено не здесь, заводится представителем). Узел
 * без единого своего процесса не поднимается вовсе («узлу нечего нести»,
 * испытание 7), поэтому в счёт идут только несущие узлы. Отсюда: процесс
 * достижимо отказывает `FLANG_LINK_DOWN` тогда и только тогда, когда в размещении
 * есть ещё хотя бы один несущий узел, кроме его собственного.
 *
 * Своего узла в списке нет намеренно: там процесс — обычный процесс, и его отказы
 * считает `достижимыеОтказы`. Представитель — это ВТОРОЕ имя того же процесса на
 * чужом узле, и надзор в программе один на оба, потому что программа одна на все
 * узлы.
 *
 * @param {object} program AST с `processes`
 * @param {{узлы?: Record<string, {процессы?: string[]}>}} размещение файл размещения
 * @returns {Map<string, Array<{вид: string, почему: string, где: object|null, функция: string|null}>>}
 */
export function отказыСвязи(program, размещение) {
  const процессы = Array.isArray(program?.processes) ? program.processes : []
  const итог = new Map()
  if (процессы.length === 0) return итог
  const узлы = размещение?.узлы
  if (узлы === null || typeof узлы !== "object") return итог

  /* Несущие узлы и место каждого процесса — один проход. Процесс, названный в
     размещении дважды, здесь не диагностика: его ловит подъём узла
     (`размещениеУзла`), и ловит отказом, а не сообщением. Берётся первое место —
     чужим для остальных узлов процесс остаётся при любом выборе. */
  const несущие = []
  const дом = new Map()
  for (const [имяУзла, описание] of Object.entries(узлы)) {
    const свои = Array.isArray(описание?.процессы) ? описание.процессы : []
    if (свои.length === 0) continue
    несущие.push(имяУзла)
    for (const процесс of свои) if (!дом.has(процесс)) дом.set(процесс, имяУзла)
  }

  for (const узел of процессы) {
    if (typeof узел?.name !== "string") continue
    const мой = дом.get(узел.name)
    /* Размещение молчит про процесс — это отдельная беда, и говорит о ней подъём
       узла («имя обязано быть адресом», испытание 9). Сказать здесь «может
       отказать связью» значило бы отвечать не на тот вопрос. */
    if (мой === undefined) continue
    const чужие = несущие.filter((имя) => имя !== мой)
    if (чужие.length === 0) continue
    итог.set(узел.name, [{
      вид: ВИДЫ_ОТКАЗА.СВЯЗЬ,
      почему: `процесс размещён на узле «${мой}», а на ${перечислить(чужие)} у него ` +
        `представитель, и представитель умеет ровно одно — отказать ${LINK_DOWN_CODE}, ` +
        "когда связь потеряна",
      где: узел.span ?? null,
      функция: null,
    }])
  }
  return итог
}

/** «а», «б» и «в» — перечисление узлов в диагностике, без хвостовой запятой. */
function перечислить(имена) {
  const кавычки = имена.map((имя) => `«${имя}»`)
  if (кавычки.length === 1) return `узле ${кавычки[0]}`
  return `узлах ${кавычки.slice(0, -1).join(", ")} и ${кавычки[кавычки.length - 1]}`
}

/**
 * Что функция может сама по себе: кого зовёт и чем падает.
 *
 * Считается один раз на функцию, потому что это её свойство, а не свойство
 * процесса. Порядок обхода — порядок узлов в теле, и он же становится порядком
 * записей в диагностике: на одном исходнике она обязана быть одной и той же,
 * иначе её нельзя сверить.
 */
function своиОтказы(фн, сЯщиком, стережённые) {
  const вызовы = []
  const частичные = new Map()
  const ящики = new Map()
  let остановка = null
  /* Мера — свойство самой функции, а не узла её тела: сторожа ставит понижение
     на рекурсивный вызов, чьё доказательство держится на числе, и найден такой
     вызов анализом завершаемости, а не обходом ниже. Поэтому запись ставится до
     обхода и без него. */
  const мера = стережённые?.has(фн.name) === true
    ? {
      вид: ВИДЫ_ОТКАЗА.МЕРА,
      почему: `«${фн.name}»: ${стережённые.get(фн.name)}`,
      где: фн.span ?? null,
      функция: фн.name,
    }
    : null

  обойти(фн.body, (узел) => {
    if (узел.kind === "construct" && (узел.variant === "отправить" || узел.variant === "через")) {
      const кому = узел.fields?.["кому"]
      const потолок = кому?.kind === "literal" ? сЯщиком.get(кому.value) : undefined
      if (потолок !== undefined && !ящики.has(кому.value)) {
        ящики.set(кому.value, {
          вид: ВИДЫ_ОТКАЗА.ЯЩИК,
          почему: `«${узел.variant}» процессу «${кому.value}»: его ящик объявлен на ${потолок} сообщений, ` +
            "и переполнить его может отправитель",
          где: узел.span ?? фн.span ?? null,
          функция: фн.name,
        })
      }
    }
    /* `fnref` наравне с `call`: функция, отданная значением в «отобразить»,
       будет вызвана, и её отказы — отказы того, кто её отдал. */
    if ((узел.kind === "call" || узел.kind === "fnref") && typeof узел.name === "string") {
      вызовы.push(узел.name)
    }
    /* Доказанное место отказом не является: его сторожа в напечатанном коде
       нет вовсе (`местЧастичныхФорм` выше — там же сказано, кто ставит
       отметку). Множество отказов процесса — оценка СВЕРХУ, и класть в неё
       отказ, которого не бывает, значит требовать надзора за небывшим. */
    if (узел.kind === "builtin" && ЧАСТИЧНЫЕ.has(узел.name) && узел.доказана !== true && !частичные.has(узел.name)) {
      частичные.set(узел.name, {
        вид: ВИДЫ_ОТКАЗА.ЧАСТИЧНАЯ,
        почему: `«${узел.name}»: ${ЧАСТИЧНЫЕ.get(узел.name)}`,
        где: узел.span ?? фн.span ?? null,
        функция: фн.name,
      })
    }
    if (узел.kind === "construct" && узел.variant === "остановить" && остановка === null) {
      const причина = причинаОстановки(узел)
      if (причина.отказ) {
        остановка = {
          вид: ВИДЫ_ОТКАЗА.ОСТАНОВЛЕН,
          почему: причина.почему,
          где: узел.span ?? фн.span ?? null,
          функция: фн.name,
        }
      }
    }
  })

  return { вызовы, частичные, ящики, остановка, мера }
}

/**
 * Отказы, достижимые из функции: она сама и всё, до чего дотягивается.
 *
 * Обход в ширину по уже посчитанным таблицам, без единого захода в AST. Круг в
 * вызовах ему не страшен: `пройденные` обрывает повтор, а взаимная рекурсия для
 * этого анализа ничем не отличается от обычного вызова — множество отказов у
 * цикла то же самое, что у его звеньев вместе.
 */
function замыканиеОтказов(имя, собственные, кэш) {
  if (typeof имя !== "string") return []
  const готовое = кэш.get(имя)
  if (готовое !== undefined) return готовое

  const пройденные = new Set()
  const очередь = [имя]
  const частичные = new Map()
  const ящики = new Map()
  let остановка = null
  let мера = null

  while (очередь.length > 0) {
    const текущее = очередь.shift()
    if (пройденные.has(текущее)) continue
    пройденные.add(текущее)
    const своё = собственные.get(текущее)
    if (своё === undefined) continue
    for (const дальше of своё.вызовы) очередь.push(дальше)
    for (const [форма, запись] of своё.частичные) {
      if (!частичные.has(форма)) частичные.set(форма, запись)
    }
    for (const [адресат, запись] of своё.ящики) {
      if (!ящики.has(адресат)) ящики.set(адресат, запись)
    }
    if (остановка === null && своё.остановка !== null) остановка = своё.остановка
    if (мера === null && (своё.мера ?? null) !== null) мера = своё.мера
  }

  /* Порядок видов постоянен: сначала частичные формы в порядке обнаружения,
     потом полные ящики, потом остановка, потом мера. «Запас витков» дописывается
     снаружи, потому что он свойство процесса, а не функции: один и тот же
     обработчик у двух процессов может стоять с запасом и без. */
  const ответ = [...частичные.values(), ...ящики.values()]
  if (остановка !== null) ответ.push(остановка)
  if (мера !== null) ответ.push(мера)
  кэш.set(имя, ответ)
  return ответ
}

/**
 * Отказ ли это `остановить`.
 *
 * Литеральная «норма» — не отказ, и это решается здесь, а не в прогоне. Любой
 * другой литерал — отказ с названной причиной. Вычисляемая причина — отказ, и
 * это единственное честное решение: значение строки заранее неизвестно, а
 * молчать про «может быть отказ» анализ не имеет права.
 */
function причинаОстановки(узел) {
  const поле = узел.fields?.["почему"]
  if (поле?.kind === "literal") {
    if (поле.value === НОРМА) return { отказ: false, почему: "" }
    return { отказ: true, почему: `«остановить» с причиной «${String(поле.value)}»` }
  }
  return {
    отказ: true,
    почему: "«остановить» с вычисляемой причиной: она может оказаться не «нормой»",
  }
}

/**
 * Обход выражений. Тот же приём, что в `tags.mjs`: узлы AST — обычные объекты,
 * и обходить их вглубь дешевле, чем держать список видов узлов, который
 * разойдётся с парсером на первом же новом виде.
 */
function обойти(узел, посетить) {
  if (Array.isArray(узел)) {
    for (const элемент of узел) обойти(элемент, посетить)
    return
  }
  if (узел === null || typeof узел !== "object") return
  if (typeof узел.kind === "string") посетить(узел)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span" || ключ === "meta") continue
    if (значение !== null && typeof значение === "object") обойти(значение, посетить)
  }
}
