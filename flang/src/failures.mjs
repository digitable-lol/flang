/**
 * failures.mjs — множество отказов процесса как ВЫЧИСЛИМОЕ множество.
 *
 * Ради чего этот файл вообще есть. В Erlang множество отказов процесса открыто:
 * `badmatch`, `badarg`, `function_clause`, `undef`, что угодно из NIF. Перечислить,
 * чем именно может упасть данный процесс, там нельзя в принципе — и отсюда «let it
 * crash»: супервизор обязан быть механизмом общего назначения, потому что он не
 * знает, от чего спасает.
 *
 * В flang это множество замкнуто и перечислимо, и его можно посчитать до запуска.
 * Тогда надзор перестаёт быть только механизмом времени выполнения и становится
 * ещё и АНАЛИЗОМ: процесс, который может упасть, а надзора над ним нет, — ошибка
 * проверки, а не сюрприз в бою (`flang/conc/RESILIENCE.md`, шаг Г1). У OTP такого
 * не может быть никогда: сводить не с чем.
 *
 * ── ПРИ КАКИХ УСЛОВИЯХ замкнуто, и почему условия названы здесь ─────────────
 *
 * «Замкнуто» стояло здесь без единой оговорки, и прогон показал, что без них это
 * неправда: нашлись три места, где отказ был, а в множестве его не было. Все три
 * закрыты (ниже поимённо), но закрытость держится на условиях, и условия — часть
 * утверждения, а не сноска к нему:
 *
 *   1. ПРОГРАММА ПРОШЛА ПРОВЕРКИ. Множество считается по проверенному AST:
 *      неполный разбор, чужой тип аргумента встроенной формы, отклик не той
 *      формы — всё это снято проверкой типов, и потому в множестве их нет. На
 *      непроверенной программе вычислитель бросит что угодно, и это не отказ
 *      процесса, а запуск того, что не собиралось;
 *   2. ВЫЧИСЛИТЕЛЬ ИСПРАВЕН. `conc.mjs` кладёт в отказы код, который бросил
 *      вычислитель, а запасным берёт `FLANG_INTERNAL` — для того, что брошено не
 *      диагностикой вовсе. Ни `FLANG_INTERNAL`, ни «этого не должно случиться»
 *      коды вроде `FLANG_TYPE` из `stepField` видами отказа не считаются и в
 *      `КОДЫ_ОТКАЗА` не входят: они означают дефект реализации. Сторож на это
 *      настоящий, а не словесный — `flang/test/failures.test.mjs` гоняет все
 *      примеры с процессами по сетке семян и требует, чтобы каждый выданный код
 *      лежал в `КОДЫ_ОТКАЗА`.
 *
 * Третьего условия нет, и в этом смысл: «замкнуто при исправном компиляторе и
 * исправном рантайме» — это ровно то, что обещает любое доказательство о языке,
 * и ровно то, чего нет у Erlang, где множество открыто и при исправном рантайме.
 *
 * ── Множество отказов: первые три вида, и все три проверены прогоном ───────
 *
 * Видов сегодня СЕМЬ: три ниже, остальные — своими разделами дальше, потому что
 * каждый приехал отдельным шагом карты и с отдельным доводом. Число семь не
 * окончательное и окончательным быть не может: оно ровно такое, сколько способов
 * отказать язык успел завести.
 *
 * Не переписаны из контракта, а предъявлены: на каждый вид есть программа,
 * которая им падает, и она лежит в `flang/test/failures.test.mjs`. Контракт в
 * двух местах говорил не то, что делает планировщик, и оба места названы ниже.
 *
 *   1. «запас витков» — `FLANG_BUDGET_EXHAUSTED`. Обработчик без признака
 *      `тотальная` обязан назвать запас (types.mjs), и запас может кончиться.
 *      У тотального обработчика этого вида нет: завершение доказано.
 *
 *   2. «частичная форма» — `FLANG_BUILTIN_ARGS`. Встроенная форма, определённая
 *      не на всех значениях своего типа: `элемент` за концом списка, `голова`
 *      пустого, `к числу` от строки, которая числом не является. Список этих
 *      форм закрыт (`ЧАСТИЧНЫЕ` ниже) и сверяется с `builtins.mjs` прогоном:
 *      их восемь, появится девятая — тест назовёт её.
 *
 *   3. «остановлен» — `FLANG_STOPPED`. Явное `остановить` с причиной, отличной
 *      от «норма». Причина-литерал «норма» отказом не является, и это видно на
 *      этапе проверки: значит `остановить` с нормой множество отказов НЕ
 *      расширяет, а `остановить` с любой другой причиной — расширяет.
 *
 * Чего в множестве НЕТ, хотя контракт это называет:
 *
 *   • «деление на ноль». Его не бывает: деление в flang — IEEE-754, и `1 делить
 *     на 0` даёт бесконечность, а не отказ (builtins.mjs, `remainderOf` и
 *     соседи). Контракт (`flang/conc/SPEC.md`, «Отказ, надзор, перезапуск») и
 *     карта (`RESILIENCE.md`) называют его отказом — это неверно, и проверено
 *     прогоном.
 *
 *   • «деление структуры не того варианта» и неполный разбор. Их исключает
 *     проверка типов: `FLANG_MATCH_NOT_EXHAUSTIVE` — ошибка компиляции
 *     (types.mjs), а поля варианта достаются только через `разбор`. До прогона
 *     такой отказ не доживает.
 *
 * ── Вид четвёртый: дыра, которая была здесь названа, и чем она закрыта ──────
 *
 *   4. «предел витков планировщика» — `FLANG_RECURSION_LIMIT`. Тотальный
 *      обработчик витков не считает: считает их планировщик, и его пределы
 *      (`conc.mjs`, `TOTAL_HANDLER_STEPS` и `TOTAL_HANDLER_DEPTH`) в исходнике
 *      программы не названы нигде.
 *
 * Здесь стояло, что этот вид НЕПЕРЕЧИСЛИМ и закрыть его нечем. Обе половины
 * перестали быть правдой: перечислим он ровно настолько, насколько известна
 * ОГРАНИЧЕННОСТЬ обработчика — оценка сверху на витки от размера входа
 * (`bounded.mjs`, шаг В3 карты). Правило вышло точное:
 *
 *   • оценка ПОСТОЯННАЯ и меньше предела — отказ недостижим, и это доказано, а
 *     не понадеяно: сколько бы сообщение ни весило, витков будет столько же;
 *   • оценка есть, но зависит от размера входа — отказ ДОСТИЖИМ: сообщение
 *     достаточной длины исчерпает любой предел, а длину сообщения не
 *     ограничивает ничто. Шаг А3 этого не изменил и изменить не мог: он
 *     ограничивает ЧИСЛО сообщений в ящике, а не размер каждого;
 *   • оценки нет вовсе — отказ достижим, и это тот случай, ради которого всё
 *     затевалось: тотальная `фиб` от 34 доказанно завершается и упирается в
 *     миллион, потому что тотальность даёт «завершится», а не «завершится
 *     скоро».
 *
 * Ошибка здесь по-прежнему односторонняя: анализ требует надзора там, где отказа
 * может и не быть (оценка сверху грубее правды), и не молчит там, где он есть.
 *
 * ── Три дыры, найденные прогоном уже ПОСЛЕ того, как всё выше было написано ──
 *
 * Каждая — место, где отказ был, а в множестве его не было. Названы прогонами,
 * не чтением, и каждая закрыта здесь же.
 *
 *   а. ПРЕДЕЛОВ У ПРОБЕГА ДВА, а сводился один. Кроме миллиона витков
 *      планировщик держит десять тысяч кадров глубины — этот предел жил
 *      умолчанием `interpret.mjs` и не был назван нигде. Обработчик с ПОСТОЯННОЙ
 *      оценкой в 260 036 витков (сумма литерального списка из 20 000 чисел) шёл
 *      «отказ недостижим», а прогон ронял процесс `FLANG_RECURSION_LIMIT` на
 *      глубине 10 001 с пустым списком решений. Закрыто: `ПРЕДЕЛ_ПРОБЕГА` —
 *      меньшее из двух, и оба предела теперь имена (`conc.mjs`);
 *   б. `начинает с` В АНАЛИЗ НЕ ВХОДИЛ ВОВСЕ. Считалось замыкание от
 *      `узел.handler` и только от него, а функцию начального состояния
 *      планировщик тоже зовёт — при заводе процесса. Программа с
 *      `начинает с «нуль»`, где «нуль» берёт девятый элемент трёхэлементного
 *      списка, проходила проверки с нулём диагностик и валила ВСЮ программу.
 *      Закрыто: `отказыНачального` ниже, и отдельным кодом `FLANG_INITIAL_FAILURE`
 *      (`types.mjs`) — надзор такому процессу не помогает, и говорить «допишите
 *      надзор» было бы враньём;
 *   в. `FLANG_PROCESS` БЫЛ ЖИВЫМ КОДОМ ОТКАЗА мимо этого списка. Программа могла
 *      объявить СВОЙ тип «Действие», проверка типов её принимала, а планировщик
 *      отвергал незнакомое действие в отклике и валил процесс кодом, которого
 *      здесь нет. Закрыто в `types.mjs`: словарь действий — слово языка, и
 *      переобъявить его нельзя.
 *
 * ── Вид пятый: его добавил шаг А3, и добавить было обязано ──────────────
 *
 *   5. «ящик адресата полон» — `FLANG_MAILBOX_FULL`. Пока ящик был неограничен,
 *      отправка отказать не могла ничем, и этого вида не существовало. С А3
 *      размер ящика объявляется (`принимает «T» с ящиком N`), и отправитель,
 *      которому некуда положить сообщение, падает. Достижим вид тогда и только
 *      тогда, когда в достижимом коде есть `отправить` или `через` процессу с
 *      ОБЪЯВЛЕННЫМ ящиком: адресат там обязан быть литералом (types.mjs,
 *      `addresseeOf`), поэтому вопрос решается по тексту, а не гаданием.
 *
 * Урок здесь общий и стоит того, чтобы его записать: шаг, который добавляет в
 * язык новый способ отказать, обязан добавить его И СЮДА. Иначе обещание Г1 —
 * «отказ, который процесс может выдать, а надзор не разбирает, — ошибка
 * проверки» — перестаёт быть правдой ровно в тот день, когда способ появился, и
 * молча: проверка не краснеет, она просто не знает.
 *
 * ── Вид седьмой: он приехал не шагом языка, а границей узла ────────────────
 *
 *   7. «связь с узлом потеряна» — `FLANG_LINK_DOWN`. Процесс, размещённый на
 *      другом узле, стоит здесь ПРЕДСТАВИТЕЛЕМ (`flang/conc/DISTRIBUTED.md`), и
 *      единственное его умение — отказать, когда связь потеряна.
 *
 * Ровно этим видом урок выше и подтвердился, только дорогой ценой: способ
 * отказать появился (распределённость), а сюда не приехал, и почти год обещание
 * Г1 кончалось на границе узла. Причина названа в самом контракте: множество
 * считается по достижимому КОДУ, а связь в коде не упоминается вовсе — её
 * называет размещение. Значит анализу нужен второй вход, и он у него теперь есть
 * (`отказыСвязи` ниже): не текст программы, а данные узла, доводом. Пока довода
 * нет, седьмой вид не считается — и это не дыра, а отсутствие границы: программа
 * без размещения живёт на одном узле, где представителей не бывает.
 *
 * ── Почему достижимость считается по графу вызовов, а не по телу обработчика ─
 *
 * Отказ случается там, где стоит частичная форма, а стоять она может в функции,
 * которую обработчик зовёт через три перехода. Значит считать надо транзитивное
 * замыкание — то самое, которым уже пользуются дефункционализация и проверка
 * тотальности. Замыкание берёт и `fnref`: функция, отданная как значение в
 * `отобразить`, будет вызвана, и её отказы — отказы этого процесса.
 *
 * Оценка СВЕРХУ, и это сказано прямо: «может упасть» здесь значит «в достижимом
 * коде есть место, где отказ этого вида возможен», а не «есть вход, на котором
 * он случится». Второе неразрешимо. Ошибаться в эту сторону безопасно: анализ
 * требует надзора там, где отказа может и не быть, но никогда не молчит там,
 * где он может быть.
 */

