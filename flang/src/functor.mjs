/**
 * КВАДРАТ СВЯЗИ: согласована ли связь двух модулей с их собственными стрелками.
 *
 * ── Что здесь называется как ────────────────────────────────────────────────
 * Интерфейс модуля — это его КАТЕГОРИЯ: какие у него объекты (записи) и что он
 * с ними умеет (стрелки). Связь двух модулей — это ФУНКТОР между их
 * категориями: он говорит, какому объекту одного соответствует объект другого и
 * какой стрелке — какая стрелка.
 *
 * До этого файла связь проверялась ТОЛЬКО СЛИЧЕНИЕМ ИМЁН (`checkFunctors` в
 * `types.mjs`): концы сходятся, композиция и единицы сохраняются, полнота на
 * категории домена считается. Всё это — про объявления. Про ДАННЫЕ не
 * проверялось ничего, потому что перевода данных в языке не было: сказать
 * «объекту «Заказ» соответствует объект «Отгрузка»» можно было, а сказать, ЧЕМ
 * именно, — нечем.
 *
 * `объект «Заказ» отображается в «Отгрузка» даёт «Отгрузка по заказу»` — это то
 * самое «чем». И с ним появляется утверждение, которое можно проверить:
 *
 *     перевести и сделать   ==   сделать и перевести
 *
 * Формально: для каждой стрелки `ф: А → Б` домена и её образа `Ф(ф)` квадрат
 *
 *       А ──── ф ────▶ Б
 *       │              │
 *      tА             tБ            обязан коммутировать:
 *       ▼              ▼            tБ(ф(x)) == Ф(ф)(tА(x))
 *      Ф(А) ─ Ф(ф) ──▶ Ф(Б)
 *
 * Это закон естественности самого перевода: `t` есть естественное
 * преобразование из вложения категории домена в композицию «функтор, потом
 * вложение категории кодомена». Оба вложения — в одну и ту же большую категорию
 * типов и тотальных функций flang, поэтому вертикальные стрелки квадрата
 * законны, хотя ни одной из двух категорий они не принадлежат.
 *
 * ── Ради чего это написано ──────────────────────────────────────────────────
 * Ради одной ошибки, которую человек правда делает: ПЕРЕВОД ТЕРЯЕТ ПОЛЕ.
 * Модуль заказов знает про отмену, модуль отгрузки — про свою отмену, а функция,
 * которая строит отгрузку по заказу, признак отмены не переносит. Каждая из трёх
 * функций по отдельности тотальна, типы сходятся, её собственные примеры
 * зелёные. Ни одна проверка дерева этого не видит — кроме этой.
 *
 * ── Почему сетка, а не доказательство ───────────────────────────────────────
 * Равенство двух путей — это равенство ВЫЧИСЛЕНИЙ на всех значениях объекта, и
 * оно неразрешимо. Значит здесь конечная сетка из значений, которые написал сам
 * автор, и отчёт обязан называть её размер: «сетка N значений» — не «доказано».
 * Ведомость (`proof.mjs`) печатает про такие проверки строку, оканчивающуюся
 * словами «Это не доказательство», и это не оговорка ради скромности: на сетке
 * ловится опровержение, а не подтверждается закон.
 *
 * Замыкание по композиции при этом достаётся даром, и это не случайность:
 * вычисление И ЕСТЬ композиция. Если квадраты образующих стрелок сошлись на
 * сетке, квадрат любой их композиции на той же сетке сходится сам — считать его
 * отдельно не нужно. (В теории схем это условия конгруэнтности отношения
 * эквивалентности путей у Спивака, `Functorial Data Migration`, опр. 3.2.4.)
 *
 * ── Что остаётся допущением автора ──────────────────────────────────────────
 * Связь, где хотя бы на одном конце квадрата нет `даёт`, проверить нечем, и
 * проверка молчит диагностикой, но НЕ молчит отчётом: такие связи уезжают в
 * `assumed` — как у `sets.mjs` и `iso.mjs`, и по той же причине. Объявление, о
 * котором не сказано ничего, читается как проверенное.
 *
 * ── Откуда берётся сетка ────────────────────────────────────────────────────
 * Оттуда же, откуда у изоморфизма: из значений, которые автор уже написал.
 * Для объекта «А» это входы примеров стрелок, из «А» выходящих; ожидаемые
 * значения примеров стрелок, в «А» входящих; и входы примеров самого перевода
 * «А» — их автор писал именно как значения «А». Примеры берутся и у функции, и
 * у законов при стрелке: и те и другие писал тот, кто знает краевые случаи, а
 * квадрат ломается именно на них.
 */
import { reifyValue, valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Больше этого числа значений на объект в сетку не берём: обход линеен, но
 *  вычисление стрелки — нет, и «проверено» обязано означать одно и то же в
 *  разных прогонах. Число то же, что у изоморфизма и моноида, намеренно: два
 *  разных предела рядом читались бы как утверждение о разной цене. */
export const ПРЕДЕЛ_СЕТКИ = 12

/** Глубже этого композиции не разворачиваем: `«в» после («б» после «а»)` — это
 *  дерево, и цикл в объявлениях (стрелка, собранная сама из себя) обязан
 *  кончиться отказом, а не переполнением стека. */
const ПРЕДЕЛ_ГЛУБИНЫ = 32

/**
 * Проверка квадратов всех связей программы.
 *
 * @param {object} программа AST flang (связанный, если файл с импортами)
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>,
 *   checked: Array<{ functor: string, values: number, squares: number, distinct: number }>,
 *   assumed: Array<{ functor: string, why: string }> }}
 */
export function checkFunctorSquares(программа, пределы = {}) {
  const функторы = (Array.isArray(программа?.legacy) ? программа.legacy : []).filter(
    (узел) => узел?.construct === "functorFile",
  )
  const diagnostics = []
  const checked = []
  const assumed = []
  if (функторы.length === 0) return { diagnostics, checked, assumed }

  const функции = Array.isArray(программа?.functions) ? программа.functions : []
  const стрелки = new Map()
  for (const узел of Array.isArray(программа?.morphisms) ? программа.morphisms : []) {
    if (typeof узел?.name === "string") стрелки.set(узел.name, узел)
  }

  let среда = null
  const звать = (имяФункции, значение) => {
    const функция = функции.find((кандидат) => кандидат.name === имяФункции)
    if (функция === undefined || (функция.params ?? []).length !== 1) {
      return { ошибка: `функции «${имяФункции}» нет или она не от одного входа` }
    }
    try {
      if (среда === null) среда = createRuntime(программа, пределы)
      return { значение: среда.call(имяФункции, { [функция.params[0].name]: значение }) }
    } catch (беда) {
      /* Отказ на значении сетки — не нарушение закона, а другое сообщение:
         квадрат здесь проверить не на чем, и сказать надо именно это. */
      return { ошибка: беда?.message ?? String(беда) }
    }
  }

  /**
   * Применить стрелку по имени.
   *
   * Три вида стрелок, и все три обязаны работать: единица возвращает вход,
   * композиция — правая, потом левая, обычная стрелка — свою функцию. Иначе
   * квадрат композиции пришлось бы объявлять непроверяемым, а он-то как раз и
   * есть то, ради чего категория собирается из стрелок.
   */
  const применить = (имя, значение, глубина = 0) => {
    if (глубина > ПРЕДЕЛ_ГЛУБИНЫ) return { ошибка: `стрелка «${имя}» разворачивается без конца` }
    const узел = стрелки.get(имя)
    if (узел === undefined) return { нет: `стрелки «${имя}» нет` }
    if (узел.identity === true) return { значение }
    if (узел.kind === "composition") {
      const правая = применить(узел.right, значение, глубина + 1)
      if (правая.значение === undefined) return правая
      return применить(узел.left, правая.значение, глубина + 1)
    }
    if (typeof узел.gives !== "string" || узел.gives === "") {
      return { нет: `у стрелки «${имя}» нет «даёт»` }
    }
    return звать(узел.gives, значение)
  }

  for (const { value: функтор, span } of функторы) {
    const узел = { span }
    /* Образ объекта и перевод к нему — одной картой: у квадрата нужны обе
       стороны сразу, а разводить их по двум таблицам значило бы дважды искать
       одно и то же. */
    const образОбъекта = new Map()
    for (const пара of функтор.objects ?? []) {
      if (образОбъекта.has(пара.from)) continue
      образОбъекта.set(пара.from, { to: пара.to, gives: пара.gives })
    }

    const переводов = [...образОбъекта.values()].filter((образ) => годная(образ.gives)).length
    if (переводов === 0) {
      /* Связь без единого перевода — то, чем функтор был всегда: сличение имён.
         Это законное объявление, о нём уже сказано в `checkFunctors`, и второй
         диагностики оно не заслуживает. Но и молчать о нём отчёт не вправе. */
      assumed.push({
        functor: функтор.name,
        why: "ни у одного объекта нет «даёт»: переводить нечем, сравнивать нечего",
      })
      continue
    }

    const доБед = diagnostics.length
    const сказать = (текст) => {
      diagnostics.push({
        code: "FLANG_FUNCTOR_SQUARE",
        message: `функтор «${функтор.name}»: ${текст}`,
        severity: "error",
        span,
      })
    }

    let значенийВсего = 0
    let квадратов = 0
    let пропущено = 0
    let оборвано = null
    const различные = []

    квадраты: for (const пара of функтор.morphisms ?? []) {
      const стрелка = стрелки.get(пара.from)
      const образ = стрелки.get(пара.to)
      /* Стрелки нет или концы не сошлись — об этом уже сказала проверка типов.
         Второе сообщение о том же было бы шумом, а не помощью. */
      if (стрелка === undefined || образ === undefined) continue
      const начало = концы(стрелка, стрелки)
      if (начало === null) continue

      const слева = образОбъекта.get(начало.domain)
      const справа = образОбъекта.get(начало.codomain)
      if (!годная(слева?.gives) || !годная(справа?.gives)) {
        пропущено += 1
        continue
      }

      const сетка = сеткаОбъекта(программа, начало.domain, стрелки, слева.gives, функции)
      /* Пустая сетка — не проверенный квадрат, а НЕпроверенный: считать его
         наравне с посчитанным значило бы сказать «квадратов 3» о двух. */
      if (сетка.length === 0) {
        пропущено += 1
        continue
      }
      значенийВсего += сетка.length
      квадратов += 1

      for (const значение of сетка) {
        /* Путь первый: сделать в своём модуле, потом перевести. */
        const сделал = применить(пара.from, значение)
        if (сделал.нет !== undefined || сделал.ошибка !== undefined) {
          оборвано = сделал.нет ?? сделал.ошибка
          пропущено += 1
          квадратов -= 1
          значенийВсего -= сетка.length
          continue квадраты
        }
        const первый = звать(справа.gives, сделал.значение)

        /* Путь второй: перевести, потом сделать в соседнем. */
        const перевёл = звать(слева.gives, значение)
        const второй = перевёл.ошибка !== undefined ? перевёл : применить(пара.to, перевёл.значение)

        if (первый.ошибка !== undefined || второй.ошибка !== undefined || второй.нет !== undefined) {
          оборвано = первый.ошибка ?? второй.ошибка ?? второй.нет
          пропущено += 1
          квадратов -= 1
          значенийВсего -= сетка.length
          continue квадраты
        }

        запомнить(различные, первый.значение)
        if (!valuesEqual(первый.значение, второй.значение)) {
          сказать(
            `квадрат не сходится на стрелке «${пара.from}»: на ${покажи(значение)} ` +
              `путь «${справа.gives}» после «${пара.from}» дал ${покажи(первый.значение)}, ` +
              `а «${пара.to}» после «${слева.gives}» — ${покажи(второй.значение)}`,
          )
          break квадраты
        }
      }
    }

    const нарушений = diagnostics.length - доБед
    if (квадратов > 0) {
      checked.push({
        functor: функтор.name,
        values: значенийВсего,
        squares: квадратов,
        /* Сколько РАЗНЫХ значений выдал первый путь. Сетка, на которой оба пути
           дают одно и то же значение всегда, закон не проверяет, а подтверждает
           сама себя: параллельные пути на постоянной сетке равны при любой
           реализации. Число это ничего не запрещает, но и спрятать его нельзя —
           проверка обязана называть, сколько она СРАВНИЛА, а не сколько
           посмотрела. */
        distinct: различные.length,
        ...(нарушений === 0 ? {} : { violations: нарушений }),
        ...(пропущено === 0 ? {} : { skipped: пропущено }),
        ...(оборвано === null ? {} : { aborted: оборвано }),
      })
    } else {
      assumed.push({
        functor: функтор.name,
        why:
          оборвано === null
            ? "сетка пуста или у стрелок квадрата нет «даёт»: считать не на чем"
            : `обход оборван: ${оборвано}`,
      })
    }
  }

  return { diagnostics, checked, assumed }
}

function годная(имя) {
  return typeof имя === "string" && имя !== ""
}

/**
 * Концы стрелки, включая композицию.
 *
 * У композиции своих концов в узле нет — они выводятся при проверке типов, — а
 * квадрату они нужны, чтобы знать, чью сетку брать. Домен композиции есть домен
 * правой (она применяется первой), кодомен — кодомен левой.
 */
function концы(узел, стрелки, глубина = 0) {
  if (глубина > ПРЕДЕЛ_ГЛУБИНЫ) return null
  if (узел?.kind !== "composition") {
    return typeof узел?.domain === "string" && typeof узел?.codomain === "string"
      ? { domain: узел.domain, codomain: узел.codomain }
      : null
  }
  const правая = стрелки.get(узел.right)
  const левая = стрелки.get(узел.left)
  if (правая === undefined || левая === undefined) return null
  const начало = концы(правая, стрелки, глубина + 1)
  const конец = концы(левая, стрелки, глубина + 1)
  return начало === null || конец === null ? null : { domain: начало.domain, codomain: конец.codomain }
}

/**
 * Значения объекта, на которых проверяется квадрат.
 *
 * Три источника, и все три — написанное автором: входы примеров стрелок, из
 * объекта выходящих; ожидаемые значения примеров стрелок, в него входящих;
 * входы примеров перевода этого объекта. Ничего не выдумывается: сетка — это
 * краевые случаи, которые автор уже назвал сам.
 */
function сеткаОбъекта(программа, объект, стрелки, перевод, функции) {
  const собрано = []
  const добавить = (значение) => {
    if (значение === undefined || собрано.length >= ПРЕДЕЛ_СЕТКИ) return
    const готовое = reifyValue(значение)
    if (собрано.some((уже) => valuesEqual(уже, готовое))) return
    собрано.push(готовое)
  }

  for (const пример of примерыФункции(функции, перевод)) {
    for (const значение of Object.values(пример.args ?? {})) добавить(значение)
  }
  for (const стрелка of стрелки.values()) {
    if (!годная(стрелка.gives)) continue
    const примеры = [...примерыФункции(функции, стрелка.gives), ...законные(стрелка)]
    if (стрелка.domain === объект) {
      for (const пример of примеры) for (const значение of Object.values(пример.args ?? {})) добавить(значение)
    }
    if (стрелка.codomain === объект) {
      for (const пример of примеры) добавить(пример.expected)
    }
  }

  return собрано
}

function примерыФункции(функции, имя) {
  const функция = функции.find((кандидат) => кандидат.name === имя)
  return Array.isArray(функция?.examples) ? функция.examples : []
}

function законные(стрелка) {
  return (стрелка.laws ?? []).flatMap((закон) => закон.examples ?? [])
}

function запомнить(список, значение) {
  const готовое = reifyValue(значение)
  if (список.some((уже) => valuesEqual(уже, готовое))) return
  список.push(готовое)
}

/** Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт. */
function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 40 ? `${текст.slice(0, 37)}…` : текст
}
