/**
 * grid.mjs — ПОИСК нарушений на сетке примеров, а не подсчёт примеров.
 *
 * ── Улика, из-за которой этот слой заведён ──────────────────────────────────
 * Ведомость печатала у недоказанного постусловия строку «сетка N значений
 * (примеры функции): нарушений не найдено», и число `N` брала из
 * `obligations.mjs` (`grid: примеры.length`). То есть СЧИТАЛА примеры и говорила
 * о них «нарушений не найдено», не посмотрев ни на один. Улика снималась одной
 * порчей: в `flang/examples/rosetta/roman-numerals.flang` постусловие «результат
 * не меньше 0» переписывалось на «не меньше 1», и тогда
 *
 *   flang check --proof … → сетка 3 значения (примеры функции): нарушений не найдено
 *   flang test        … → {"example":"Не римская цифра — ноль","code":"FLANG_PROPERTY"}
 *
 * в ту же секунду. Нарушение есть, прогон его находит, а ведомость — главный
 * измеритель проекта — говорит, что нарушений нет. Тест, который не умеет
 * краснеть, хуже отсутствующего: он выдаёт спокойствие, которого нет, и здесь
 * это спокойствие стояло в документе, которому верят больше всего.
 *
 * ── Что делает этот слой ────────────────────────────────────────────────────
 * Прогоняет примеры функции ТЕМ ЖЕ вычислителем, каким их прогоняет `flang
 * test`, и отвечает на один вопрос про каждое постусловие: искали ли нарушение
 * и нашли ли. Три ответа, и они разные:
 *
 *   НАШЛИ      — на примере автора утверждение ложно. Ведомость обязана сказать
 *                «НАРУШЕНО» и назвать пример.
 *   НЕ НАШЛИ   — прогон дошёл до конца на всех примерах и ни одного нарушения не
 *                дал. Только теперь слова «нарушений не найдено» — правда.
 *   НЕ ИСКАЛИ  — прогон отказал по ДРУГОЙ причине (отказ в теле, предел шагов,
 *                форма, которую вычислитель не берёт). Тогда так и сказано: «не
 *                искали», с причиной. Молчаливое «считаем, что всё хорошо»
 *                здесь и было бы тем самым дефектом.
 *
 * ── Почему прогон, а не разбор выражения ────────────────────────────────────
 * Постусловие проверяется вычислителем после КАЖДОГО возврата функции, включая
 * возвраты рекурсивные. Вычислить его самому на одном лишь итоговом значении
 * значило бы искать в меньшем числе точек, чем ищет рантайм, — и `flang test`
 * снова находил бы то, чего ведомость не нашла. Прогон через `interpret.mjs`
 * даёт ровно те же точки, что и рантайм, потому что это он и есть.
 *
 * ── Как нарушение приписывается СВОЕМУ постусловию ──────────────────────────
 * Вычислитель бросает на первом нарушенном постусловии, и по коду ошибки нельзя
 * сказать, чьё оно: у функции постусловий бывает несколько, а нарушить может и
 * вложенный вызов. Поэтому прогон идёт по программе-тени, где оставлено РОВНО
 * ОДНО постусловие — то, о котором спрашивают, — а все прочие сняты. Тогда
 * ошибка с кодом постусловия принадлежит ему и никому больше.
 *
 * Снятие чужих постусловий не прячет нарушений и не выдумывает их: постусловие
 * ничего не вычисляет, кроме признака, и его снятие может только УБРАТЬ отказ, а
 * не изменить значение. Значит найденное здесь нарушение найдёт и `flang test`
 * (если раньше не упрётся в чужое), а пропустить то, что нашёл он, этот поиск не
 * может.
 *
 * ── Чего этот слой не делает ────────────────────────────────────────────────
 * Не даёт диагностик. Нарушенное постусловие на примере автора — это красный
 * `flang test`, и место у примеров одно: команда, которая примеры прогоняет
 * (тот же довод, по которому закон при стрелке проверяется в `flang test`, а не
 * в `flang check` — `compat.mjs`, `runExamples`). Работа этого слоя — не завести
 * второе место отказа, а не дать ведомости сказать «не найдено» там, где не
 * искали.
 */
import { createRuntime } from "./interpret.mjs"

/** Версия формата поиска: его читает ведомость, значит она названа. */
export const СЕТКА = 1

/** Код, которым вычислитель отказывает на нарушенном постусловии по умолчанию. */
const КОД_ПО_УМОЛЧАНИЮ = "FLANG_PROPERTY"

/**
 * Поиск нарушений на сетке примеров — по одному ответу на каждое постусловие.
 *
 * @param {object} программа AST модуля (связанного, если файл с импортами)
 * @param {object[]} обязательства список из `obligations()`
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы] пределы вычислителя;
 *   по умолчанию те же, что у `flang test`, — иначе «нашёл прогон» и «нашла
 *   ведомость» стали бы разными утверждениями
 * @returns {{ version: number, checked: object[] }}
 */
export function checkGrid(программа, обязательства, пределы = {}) {
  const функции = new Map()
  for (const fn of Array.isArray(программа?.functions) ? программа.functions : []) {
    if (typeof fn?.name === "string" && !функции.has(fn.name)) функции.set(fn.name, fn)
  }

  /* НОМЕР ПОСТУСЛОВИЯ ВНУТРИ ФУНКЦИИ, и он здесь не для порядка вывода.
     Обязательства собираются обходом `fn.postconditions` подряд, по одному на
     каждое и без пропусков (`obligations.mjs`), поэтому k-е обязательство
     функции — это k-е её постусловие. Тот же счёт по месту ведёт и ведомость,
     когда сводит ответы поиска с обязательствами. */
  const checked = []
  const номера = new Map()
  for (const обязательство of обязательства ?? []) {
    if (обязательство?.kind !== "postcondition") continue
    const номер = номера.get(обязательство.of) ?? 0
    номера.set(обязательство.of, номер + 1)
    checked.push(поискПоОбязательству(программа, функции, обязательство, номер, пределы))
  }
  return { version: СЕТКА, checked }
}

function поискПоОбязательству(программа, функции, обязательство, номер, пределы) {
  const функция = функции.get(обязательство.of)
  const примеры = Array.isArray(функция?.examples) ? функция.examples : []
  const отчёт = {
    id: обязательство.id,
    of: обязательство.of ?? null,
    name: обязательство.name ?? null,
    examples: примеры.length,
    searched: 0,
    violations: [],
    unsearched: [],
  }

  /* Постусловие ищется ПО МЕСТУ В СПИСКЕ, а не по имени и не по ссылке.
     Не по имени — потому что имя уникально внутри функции по договорённости, а
     не по проверке, и два одноимённых постусловия развели бы поиск не туда.

     НЕ ПО ССЫЛКЕ — и вот это стоило отдельного разбора. Раньше здесь стояло
     `узел?.expr === обязательство.goal`: свидетель на JavaScript кладёт в
     обязательство ТОТ ЖЕ САМЫЙ объект выражения, что стоит в узле, и сравнение
     по ссылке было точным. Точным — и невоспроизводимым ничем, кроме этого
     самого свидетеля: слой, который считает обязательства и отдаёт их ДАННЫМИ
     (а именно так отдаёт их эталон на flang и так же отдал бы любой другой
     язык), несёт выражение, равное узлу знак в знак и не равное ему по ссылке.
     Поиск отвечал «не искали» на КАЖДОМ постусловии, ведомость послушно
     печатала это вместо «нарушений не найдено», и ни одна проверка не краснела:
     сверка обязательств была побайтовой и совпадала, а зависимость от
     тождества объектов в неё не попадала вовсе.

     Счёт по месту точен по той же причине, по какой был точен счёт по ссылке:
     обязательства собираются обходом `fn.postconditions` подряд, по одному на
     каждое и без пропусков. */
  const постусловие = (функция?.postconditions ?? [])[номер] ?? null
  if (постусловие === null || примеры.length === 0) {
    /* Искать нечего, и это не «не нашли»: у утверждения без примеров сетка
       пуста, и ведомость говорит о нём «объявлено, не доказано». */
    return отчёт
  }

  const код = typeof постусловие.code === "string" ? постусловие.code : КОД_ПО_УМОЛЧАНИЮ
  let среда
  try {
    среда = createRuntime(тень(программа, функция, постусловие), пределы)
  } catch (беда) {
    for (const пример of примеры) {
      отчёт.unsearched.push({ example: имяПримера(пример), why: причина(беда) })
    }
    return отчёт
  }

  for (const пример of примеры) {
    try {
      среда.call(функция.name, пример?.args ?? {})
      отчёт.searched += 1
    } catch (беда) {
      if (кодОшибки(беда) === код) {
        отчёт.searched += 1
        отчёт.violations.push({ example: имяПримера(пример), why: причина(беда) })
        continue
      }
      /* Отказ по другой причине — это не «нарушений нет» и не «нарушение есть».
         Про этот пример утверждение не проверено ничем, и сказать надо ровно
         это. */
      отчёт.unsearched.push({ example: имяПримера(пример), why: причина(беда) })
    }
  }
  return отчёт
}

/**
 * Программа-тень: то же самое, но постусловие в ней ровно одно.
 *
 * Копируются только те функции, у которых постусловия есть; остальные едут той
 * же ссылкой — программа корпуса бывает в тысячи функций, и переписывать их все
 * ради одного узла значило бы платить за поиск больше, чем он стоит.
 */
function тень(программа, функция, постусловие) {
  const функции = (программа?.functions ?? []).map((другая) => {
    if (другая === функция) return { ...другая, postconditions: [постусловие] }
    const свои = другая?.postconditions
    return Array.isArray(свои) && свои.length > 0 ? { ...другая, postconditions: [] } : другая
  })
  return { ...программа, functions: функции }
}

function имяПримера(пример) {
  return typeof пример?.name === "string" ? пример.name : null
}

function кодОшибки(беда) {
  if (typeof беда?.code === "string") return беда.code
  const первая = Array.isArray(беда?.diagnostics) ? беда.diagnostics[0] : undefined
  return typeof первая?.code === "string" ? первая.code : undefined
}

function причина(беда) {
  return беда instanceof Error ? беда.message : String(беда)
}
