/**
 * browser.mjs — хозяин вкладки для программы, которую крутит ИНТЕРПРЕТАТОР.
 *
 * Самого хозяина здесь больше нет, и это главное, что стоит про файл знать. Он
 * лежит целиком в `../emit/js/flang_host_browser.js`, у которого НОЛЬ ввозов, а
 * здесь осталась переходная строка: подставить интерпретаторскую фабрику
 * варианта и интерпретаторские кости.
 *
 * ── Почему хозяин переехал ──────────────────────────────────────────────────
 *
 * Он ввозил `variant`, `сбой` и `makeRandom`, и вместе с тремя именами во
 * вкладку приезжала вся вторая реализация языка: замерено в браузере — 16
 * файлов, 1 692 153 байта из 1 752 748, которые везла страница приложения.
 * Напечатанный тем же деревом модуль того же приложения весит 53 877 байт.
 * Пока хозяин ввозил компилятор, печать плана не дала бы ничего: вкладка всё
 * равно тащила бы вычислитель.
 *
 * ── Почему хозяин ОДИН, а не два ────────────────────────────────────────────
 *
 * Соблазн был написать вкладке отдельного хозяина и оставить этот как есть.
 * Тогда в дереве было бы два ответа на вопрос «что делает поручение
 * «Показать»» — и разошлись бы они молча, потому что сверять их нечем: у одного
 * на входе значения интерпретатора, у другого значения напечатанного модуля.
 * Поэтому реализация одна, а различие представлений вынесено в ОДИН параметр —
 * фабрику варианта.
 *
 * Договор наружу не изменился: `browserHost({ документ, seed, … })` принимает
 * то же, что принимал, и возвращает ту же функцию «поручение → отклик».
 */

import { variant } from "../builtins.mjs"
import { makeRandom } from "../conc.mjs"
import { хозяинВкладки } from "../emit/js/flang_host_browser.js"

/**
 * Хозяин для браузера поверх значений интерпретатора.
 *
 * @param {{
 *   документ?: object, разрешено?: object, seed?: number,
 *   таймаут?: number, fetch?: Function, часы?: Function,
 *   отложить?: Function, снять?: Function, очередь?: number
 * }} options
 *   `документ` подменяем — иначе проверить хозяина можно было бы только в
 *   браузере, а прогон, для которого нужны руки, прогоном не считается.
 *   `очередь` — сколько событий копить, пока план занят; свыше самое старое
 *   выбрасывается.
 * @returns {(поручение: object) => Promise<object>}
 */
export function browserHost(options = {}) {
  return хозяинВкладки({
    ...options,
    вариант: variant,
    /* Семя переводится в бросок ЗДЕСЬ, а не там: повторимые кости — это знание
       второй реализации (`makeRandom`), и держать его копию в файле, который
       едет во вкладку, значило бы завести третий генератор рядом с двумя
       существующими. Молча разошёлся бы любой из трёх. */
    бросить: options.seed === undefined ? undefined : makeRandom(options.seed),
  })
}
