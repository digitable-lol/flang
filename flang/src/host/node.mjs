/**
 * host/node.mjs — хозяин ввода-вывода для Node.
 *
 * Это ВТОРАЯ половина решения из `flang/cat/SPEC.md`: язык строит описание
 * действия, а исполняет его хозяин — среда, в которую напечатан модуль. Здесь
 * такая среда одна, Node, и все настоящие эффекты языка живут ровно в этом
 * файле: по одной ветке на поручение, ни одной больше.
 *
 * Граница честности проведена там же, где в контракте: **сам HTTP написан не на
 * flang**. Здесь `fetch` и `net.createServer`, там — то, что запрос описывает и
 * что делать с ответом.
 *
 * ── Что здесь появилось вместе с сокетом и чего здесь НЕТ ───────────────────
 *
 * Появилось: слушающий сокет, очередь принятых соединений, сокет, открытый
 * наружу, и буфер пришедших байтов. Всё это — вещи хозяина, и живут они в
 * замыкании `nodeHost`, а наружу выходят ЧИСЛОМ: `«Соединение открыто» с
 * соединение равным 3`. Программа этим числом не может сделать ничего, кроме
 * как вернуть его в следующем поручении, — и это ровно та мера власти, которая
 * ей нужна.
 *
 * Не появилось НИ ОДНОЙ строки, знающей про HTTP. Хозяин не ищет `\r\n\r\n`, не
 * читает `Content-Length` и не решает, полон ли запрос: он отдаёт то, что
 * пришло, а «пришло не всё» — это ответ ПРОГРАММЫ (`«Запрос неполон»`,
 * `stdlib/http.flang`), после которого она просит `«Прочитать из соединения»` ещё
 * раз. Накопление байтов из нескольких пакетов оказалось не долгом хозяина, как
 * ожидалось, а обычным витком плана: буфер держит тот, кто умеет сказать, чего
 * ему не хватает.
 *
 * Чего нет и названо: ПРИНЯТОЕ соединение живёт ОДИН обмен. `«Ответить в
 * соединение»` пишет ответ и закрывает сокет — keep-alive не поддержан, и
 * поручения «Закрыть соединение» нет именно поэтому. Пустой ответ закрывает
 * соединение, не написав ни байта: так выглядит молчание на обрезанный запрос.
 *
 * ── Кто закрывает соединение: правило идёт за тем, кто его завёл ────────────
 *
 * ОТКРЫТОЕ программой соединение ответом НЕ закрывается, и это не исключение из
 * правила, а само правило: закрывает тот, кто завёл. Хозяин принял соединение — он и
 * кладёт трубку, ответив. Программа открыла соединение — значит она в середине
 * разговора, и закрой её первая же запись, поручение `«Открыть соединение»`
 * было бы бесполезно ровно для того случая, ради которого заведено: написать
 * запрос, прочитать ответ, написать следующий.
 *
 * Закрыть открытое соединение всё-таки можно, и нового слова для этого не
 * понадобилось: `«Ответить в соединение»` с ПУСТЫМ содержимым закрывает его, не
 * написав ни байта, — та же семантика пустого ответа, что у принятого.
 *
 * Долг, который отсюда следует, назван честно: открытое и не закрытое
 * программой соединение живёт до `закрыть()`. Течёт оно так же, как течёт
 * файловый дескриптор в любой другой программе.
 *
 * ── Почему хозяин может отказать ────────────────────────────────────────────
 *
 * Полномочия принадлежат хозяину, а не программе, и это видно в коде: у хозяина
 * есть набор разрешений, и запрещённое поручение возвращается откликом `«Сбой»`
 * с кодом `FLANG_IO_DENIED`. Не исключением — откликом: программа обязана уметь
 * встретить неудачу поручения, а «сеть выключили» ничем не отличается от «сеть
 * не ответила». Один путь на оба случая — один и проверенный.
 *
 * Это не теоретическая тонкость. Именно так чистота языка окупается: описание
 * действия можно прочитать ДО того, как оно случилось, и решить, случится ли
 * оно вообще. Программа, которую пропустили через факт-чекинг, не могла тайком
 * сходить в сеть — сходить в сеть может только хозяин.
 *
 * ── Почему у запуска процесса СВОЁ право ────────────────────────────────────
 *
 * Прав было пять, и ни одно из них не подошло. Пустить запуск под `чтение`
 * значило бы соврать про полномочия сразу дважды: `--no-read` перестал бы
 * запрещать чтение (запущенная программа читает что хочет), а разрешённое
 * чтение молча включало бы исполнение. Запуск процесса — это выход из
 * песочницы по определению: у порождённого процесса свои права, своя сеть и
 * свой доступ к диску, и хозяин не может их сузить ничем из того, что здесь
 * написано.
 *
 * По той же причине `внутриКорня` на запуск НЕ распространяется и не может: имя
 * программы — это не путь поручения, оно ищется по `PATH`. Ключ `--in-dir`
 * ограничивает пути ПОРУЧЕНИЙ, а не полномочия запущенного процесса, и обещать
 * второе значило бы обещать песочницу, которой здесь нет. Настоящий запрет
 * здесь один — `--no-spawn`.
 *
 * ── Почему случайность приходит семенем ─────────────────────────────────────
 *
 * `Math.random` не воспроизводится, а прогон, который нельзя повторить, нельзя
 * и проверить. Поэтому у хозяина есть `seed`, и генератор взят тот же самый,
 * что у планировщика конкурентности (`makeRandom`, mulberry32, шесть строк
 * целочисленной арифметики): его обязан повторить один в один хозяин в любой из
 * восьми целей печати. Без семени берётся `Math.random` — но тогда прогон и не
 * обещает повторимости.
 */

import { spawn } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { readdir, readFile, writeFile } from "node:fs/promises"
import { createConnection, createServer } from "node:net"
import { isAbsolute, relative, resolve } from "node:path"
/* Тот самый механизм, что стоял за `setEncoding("utf8")`: он один умеет
   придержать незавершённую многобайтовую последовательность до следующего
   пакета. Здесь он зовётся руками и ТОЛЬКО из текстового чтения — октетное
   его не касается. */
import { StringDecoder } from "node:string_decoder"

import { isList, variant, элементыСписка } from "../builtins.mjs"
import { makeRandom } from "../conc.mjs"
import { сбой } from "../io.mjs"

/**
 * Срок хозяина по умолчанию, в миллисекундах.
 *
 * Тридцать секунд стояли здесь числом в двух местах и НАРУЖУ не выходили
 * никак: ключа, поднимающего срок, не было ни у `flang io`, ни в этом файле.
 * Цена этого измерена: одна сборка релизного C идёт 128 000 мс — четыре с
 * лишним срока, — и значит планом на flang сборкой управлять было нельзя.
 * Две работы независимо оставили сборку на JavaScript.
 *
 * Число осталось прежним намеренно: умолчание обязано ловить программу, которая
 * ждёт ввода и не дождётся, — довод к сроку не изменился ни на строку. Изменилось
 * то, что теперь его можно НАЗВАТЬ: `flang io --timeout 600000`.
 */
export const СРОК_ПО_УМОЛЧАНИЮ = 30_000

/** Что хозяину позволено. Всё включено — CLI сужает это ключами. */
const ПОЛНЫЕ_ПРАВА = Object.freeze({
  чтение: true,
  запись: true,
  сеть: true,
  время: true,
  случайность: true,
  запуск: true,
})

/**
 * Хозяин для Node: функция «поручение → отклик».
 *
 * @param {{
 *   base?: string, разрешено?: object, seed?: number,
 *   внутриКорня?: boolean, таймаут?: number, fetch?: Function
 * }} options
 *   `base` — каталог, относительно которого разрешаются пути (по умолчанию
 *   текущий). `внутриКорня` запрещает выход за него: путь `../../etc/passwd`
 *   становится отказом, а не чтением. `fetch` подменяем — иначе проверить
 *   сетевое поручение можно было бы только в сети.
 */
export function nodeHost(options = {}) {
  const корень = resolve(options.base ?? process.cwd())
  const можно = { ...ПОЛНЫЕ_ПРАВА, ...(options.разрешено ?? {}) }
  const внутриКорня = options.внутриКорня === true
  const таймаут = options.таймаут ?? СРОК_ПО_УМОЛЧАНИЮ
  const сходить = options.fetch ?? globalThis.fetch
  const бросить = options.seed === undefined ? Math.random : makeRandom(options.seed)

  /* ── мирская половина соединения ──────────────────────────────────────────
     Три таблицы, и ни одна из них не видна программе: слушающие сокеты по
     портам, соединения по номерам и счётчик номеров. Номер выдаётся подряд с
     единицы и не переиспользуется — закрытое соединение исчезает из таблицы, и
     поручение с его номером получает `«Сбой»`, а не чужой сокет.

     Таблица соединений ОДНА на принятые и на открытые: с точки зрения чтения и
     записи они неразличимы, и разница между ними живёт ровно в одном поле —
     `своё`, «это соединение открыла программа». Читает его только запись, и
     только затем, чтобы решить, класть ли трубку. */
  const слушают = new Map()
  const соединения = new Map()
  let следующийНомер = 1
  let закрыт = false

  /** Открыть порт (один раз на порт) и дождаться, пока он действительно слушает. */
  const слушать = (порт) => {
    const готовое = слушают.get(порт)
    if (готовое !== undefined) return готовое
    const место = { сервер: null, очередь: [], ждут: [] }
    слушают.set(порт, место)
    место.готов = new Promise((решить, отказать) => {
      /* `allowHalfOpen: true` — НЕ настройка вкуса, а условие того, чтобы
         служба имела право ПОДУМАТЬ между запросом и ответом.

         Без него node закрывает свою половину соединения, как только клиент
         прислал FIN («я всё сказал»), — и ответ, написанный после этого, уходит
         в никуда. Пока служба отвечала в том же витке, в котором прочитала, это
         не было видно: `serve-network.mjs` проходил все шестнадцать соединений.
         Улика появилась, когда между чтением и ответом встал журнал
         упреждающей записи (`serve-durable.mjs`): из восьми запросов пять
         меняющих получили НОЛЬ байт вместо ответа, при том что поручений
         «Ответить в соединение» хозяин исполнил все восемь, и журнал на диске
         был правильный. Проиграна была гонка, а не логика.

         Закрывать соединение это не мешает: `«Ответить в соединение»` на
         принятом соединении всегда сам зовёт `сокет.end(...)` (или `destroy()`
         на молчании), то есть половину хозяина закрывает хозяин, а не таймер
         сети. */
      const сервер = createServer({ allowHalfOpen: true }, (сокет) => выдать(место, принять(сокет, false)))
      сервер.on("error", отказать)
      сервер.listen(порт, () => решить(сервер))
      место.сервер = сервер
    })
    return место
  }

  /**
   * Записать сокет в таблицу и подписаться на его байты — общее для обеих
   * сторон, и общее не ради краткости: принятое и открытое соединение обязаны
   * читаться ОДИНАКОВО, иначе программа, которой «всё равно, кто принёс байты»,
   * это утверждение перестала бы подтверждать.
   */
  const принять = (сокет, своё) => {
    const номер = следующийНомер++
    /* ОКТЕТЫ, а не знаки, и это перемена по существу.
    
       Прежде здесь стоял `сокет.setEncoding("utf8")`, и довод к нему был
       верный ровно наполовину: `setEncoding` действительно держит незавершённую
       многобайтовую последовательность до следующего пакета, и без этого
       кириллица, разрезанная границей TCP, приезжала бы половинками знака.
       Неверна была вторая половина: он же ЗАМЕНЯЕТ всякий не-UTF-8 октет на
       U+FFFD, а замена необратима. Двоичный протокол после неё не читается
       вовсе — 557 октетов сеанса PostgreSQL превращаются в 626 знаков.

       Теперь хозяин копит СЫРЫЕ буферы и ничего не решает за программу. Оба
       свойства сохранены и разведены по разным поручениям:

         «Прочитать из соединения» отдаёт ТЕКСТ и держит незавершённый хвост
            (`StringDecoder` ниже) — ровно то, что делал `setEncoding`;
         «Прочитать октеты из соединения» отдаёт ВСЁ накопленное числами, и
            хвоста у него нет: у октета не бывает половинки.

       `раскодировщик` заводится лениво: соединению, которое читают только
       октетами, он не нужен вовсе. */
    const соединение = {
      сокет,
      пришло: [],
      конец: false,
      ждут: [],
      своё,
      раскодировщик: null,
    }
    соединения.set(номер, соединение)
    сокет.on("data", (кусок) => {
      соединение.пришло.push(кусок)
      разбудить(соединение)
    })
    сокет.on("end", () => { соединение.конец = true; разбудить(соединение) })
    сокет.on("close", () => { соединение.конец = true; разбудить(соединение) })
    сокет.on("error", () => { соединение.конец = true; разбудить(соединение) })
    return номер
  }

  /**
   * Пойти наружу. `allowHalfOpen: true` здесь по той же причине, что у
   * слушающего сокета, но с другой стороны: программа вправе дописать запрос,
   * сказать «я всё» и ЖДАТЬ ответа — без этого флага node закрыл бы соединение
   * на своей половине и ответ сервера потерялся бы.
   *
   * Срок здесь свой, а не системный: `connect(2)` к молчащему адресу висит
   * минутами, а хозяину положено ОТВЕТИТЬ. Поэтому тот же `таймаут`, что у
   * `«Запросить»`, и тот же код отказа.
   */
  const открыть = (адрес, порт) =>
    new Promise((решить, отказать) => {
      const сокет = createConnection({ host: адрес, port: порт, allowHalfOpen: true })
      let решено = false
      const срок = setTimeout(() => {
        if (решено) return
        решено = true
        сокет.destroy()
        отказать(new Error(`соединение с ${адрес}:${порт} не установилось за ${таймаут} мс`))
      }, таймаут)
      сокет.once("error", (ошибка) => {
        if (решено) return
        решено = true
        clearTimeout(срок)
        отказать(ошибка)
      })
      сокет.once("connect", () => {
        if (решено) return
        решено = true
        clearTimeout(срок)
        /* Подписки на `error` ставит `принять`, и своя, ранняя, к этому мигу
           уже сделала всё, ради чего стояла: до соединения ошибка означает «не
           дошли», после — «оборвалось», и это разные ответы. */
        решить(принять(сокет, true))
      })
    })

  /** Пришли байты или соединение кончилось — тот, кто ждал чтения, продолжает. */
  const разбудить = (соединение) => {
    const ждут = соединение.ждут
    соединение.ждут = []
    for (const продолжить of ждут) продолжить()
  }

  /** Новое соединение: либо отдать ждущему `«Принять соединение»`, либо в очередь. */
  const выдать = (место, номер) => {
    const ждущий = место.ждут.shift()
    if (ждущий === undefined) место.очередь.push(номер)
    else ждущий(номер)
  }

  /** Путь поручения → путь файловой системы, либо отказ. */
  const путь = (значение) => {
    if (typeof значение !== "string" || значение === "") {
      return { беда: сбой("FLANG_IO_PATH", "поручению нужен непустой путь") }
    }
    const полный = resolve(корень, значение)
    if (внутриКорня) {
      const внутрь = relative(корень, полный)
      if (внутрь.startsWith("..") || isAbsolute(внутрь)) {
        return { беда: сбой("FLANG_IO_DENIED", `путь «${значение}» ведёт за пределы каталога работы`) }
      }
    }
    return { полный }
  }

  const исполнить = async function исполнить(поручение) {
    const поля = поручение.fields ?? {}
    switch (поручение.variant) {
      case "Прочитать файл": {
        if (!можно.чтение) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать файлы")
        const { полный, беда } = путь(поля["путь"])
        if (беда !== undefined) return беда
        try {
          return variant("Прочитано", { содержимое: await readFile(полный, "utf8") })
        } catch (ошибка) {
          return сбой("FLANG_IO_READ", текст(ошибка))
        }
      }

      case "Записать файл": {
        if (!можно.запись) return сбой("FLANG_IO_DENIED", "хозяину запрещено писать файлы")
        const { полный, беда } = путь(поля["путь"])
        if (беда !== undefined) return беда
        const содержимое = String(поля["содержимое"] ?? "")
        try {
          await writeFile(полный, содержимое, "utf8")
          /* Считаем кодовые точки, а не единицы UTF-16: длина строки в языке
             считается именно так (SPEC, раздел 5), и «записано» обязано
             совпадать с «длина» на том же тексте. Иначе кириллица и эмодзи
             давали бы два разных числа об одном и том же файле. */
          return variant("Записано", { сколько: [...содержимое].length })
        } catch (ошибка) {
          return сбой("FLANG_IO_WRITE", текст(ошибка))
        }
      }

      /**
       * Перечислить каталог — под тем же правом `чтение`, что и «Прочитать
       * файл»: и то и другое узнаёт содержимое диска, а два права на одно
       * полномочие означали бы, что `--no-read` не запрещает читать.
       *
       * `.sort()` здесь — НЕ причёсывание вывода, а условие сравнимости. Смысл
       * словаря в том, что журнал поручений настоящего хозяина сверяется с
       * журналом поддельного (`хозяинПоСписку` в `io.mjs`), а `readdir` порядка
       * не обещает: он отдаёт то, что вернула файловая система. Прогон, который
       * нельзя повторить, нельзя и проверить — тот же довод, по которому у
       * случайности здесь семя, а не `Math.random`.
       *
       * Сортируется по кодовым точкам (`Array.prototype.sort` без сравнителя),
       * а не по правилам языка: `localeCompare` зависит от локали среды, то
       * есть от того, чего хозяин не выбирает. Кириллица от этого едет после
       * латиницы — и это предсказуемо, а предсказуемость здесь и требуется.
       */
      case "Перечислить каталог": {
        if (!можно.чтение) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать файлы")
        const { полный, беда } = путь(поля["путь"])
        if (беда !== undefined) return беда
        try {
          return variant("Перечислено", { имена: (await readdir(полный)).sort() })
        } catch (ошибка) {
          return сбой("FLANG_IO_LIST", текст(ошибка))
        }
      }

      /**
       * Запустить процесс — единственная ветка, где хозяин отдаёт управление
       * ЧУЖОЙ программе, и потому единственная, где есть чему пойти не так
       * тремя разными способами: не запустилось, кончилось само, кончилось не
       * само.
       *
       * `execFile` через `promisify` сюда НЕ ГОДИТСЯ, и это не вкус: он
       * режектится на ненулевом коде возврата. «Программа отработала и вернула
       * 3» приехала бы в `catch` как ошибка — ровно та подмена, против которой
       * неудача сделана ОТКЛИКОМ, а не исключением. Ненулевой код — это
       * РЕЗУЛЬТАТ работы (сторож спек ради него поручение и заводит), а не
       * сбой; сбой здесь — только «программы нет» и «не уложилась в срок».
       */
      case "Запустить процесс": {
        if (!можно.запуск) return сбой("FLANG_IO_DENIED", "хозяину запрещено запускать процессы")
        const программа = поля["программа"]
        if (typeof программа !== "string" || программа === "") {
          return сбой("FLANG_IO_SPAWN", "поручению нужно непустое имя программы")
        }
        /* `isList`, а не `Array.isArray`: срез списка (`хвост`, `подсписок`) —
           такой же список, и прежняя проверка молча превращала его в пустой
           набор аргументов. */
        const аргументы = isList(поля["аргументы"]) ? элементыСписка(поля["аргументы"]).map(String) : []
        return await запуститьПроцесс(программа, аргументы, корень, таймаут, null)
      }

      /**
       * То же самое, плюс написать потомку в стандартный ввод.
       *
       * Отличие от соседа сверху ровно одно и живёт оно в последнем доводе
       * `запуститьПроцесс`: `null` значит «ввода нет» (потомку дают пустоту),
       * строка значит «вот твой ввод» — написать и ЗАКРЫТЬ. Закрыть
       * обязательно: программа, читающая свой ввод до конца, без этого ждёт
       * вечно, и ждёт она именно нас.
       */
      case "Запустить процесс с вводом": {
        if (!можно.запуск) return сбой("FLANG_IO_DENIED", "хозяину запрещено запускать процессы")
        const программа = поля["программа"]
        if (typeof программа !== "string" || программа === "") {
          return сбой("FLANG_IO_SPAWN", "поручению нужно непустое имя программы")
        }
        const аргументы = isList(поля["аргументы"]) ? элементыСписка(поля["аргументы"]).map(String) : []
        return await запуститьПроцесс(программа, аргументы, корень, таймаут, String(поля["ввод"] ?? ""))
      }

      case "Запросить": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        if (typeof сходить !== "function") {
          return сбой("FLANG_IO_NET", "у хозяина нет способа сходить в сеть")
        }
        const способ = String(поля["способ"] ?? "GET").toUpperCase()
        const адрес = String(поля["адрес"] ?? "")
        const тело = String(поля["тело"] ?? "")
        try {
          const запрос = { method: способ, signal: AbortSignal.timeout(таймаут) }
          /* Тело у GET и HEAD запрещено спецификацией fetch, и пустая строка —
             это «тела нет», а не «тело нулевой длины»: иначе всякое чтение
             страницы падало бы на ровном месте. */
          if (тело !== "" && способ !== "GET" && способ !== "HEAD") запрос.body = тело
          const ответ = await сходить(адрес, запрос)
          return variant("Ответ сети", { код: ответ.status, тело: await ответ.text() })
        } catch (ошибка) {
          return сбой("FLANG_IO_NET", текст(ошибка))
        }
      }

      case "Открыть соединение": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        const адрес = поля["адрес"]
        if (typeof адрес !== "string" || адрес === "") {
          return сбой("FLANG_IO_NET", "поручению «Открыть соединение» нужен непустой адрес")
        }
        const порт = Number(поля["порт"])
        /* Ноль здесь НЕ годится, в отличие от приёма: «порт 0» на слушающем
           сокете значит «дай любой свободный», а на исходящем не значит ничего
           — идти по такому адресу некуда. */
        if (!Number.isInteger(порт) || порт < 1 || порт > 65535) {
          return сбой("FLANG_IO_NET", `порт «${поля["порт"]}» не годится: нужно целое от 1 до 65535`)
        }
        if (закрыт) return сбой("FLANG_IO_NET", "хозяин закрыл соединения: открывать больше нечего")
        try {
          return variant("Соединение открыто", { соединение: await открыть(адрес, порт) })
        } catch (ошибка) {
          /* Тот же код, что у `«Запросить»`, и это не лень: для программы «не
             дозвонились» и «сеть не ответила» — один путь, и он один и
             проверен. */
          return сбой("FLANG_IO_NET", текст(ошибка))
        }
      }

      case "Принять соединение": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        const порт = Number(поля["порт"])
        if (!Number.isInteger(порт) || порт < 0 || порт > 65535) {
          return сбой("FLANG_IO_NET", `порт «${поля["порт"]}» не годится: нужно целое от 0 до 65535`)
        }
        if (закрыт) return сбой("FLANG_IO_NET", "хозяин закрыл слушающие сокеты: принимать больше нечего")
        const место = слушать(порт)
        try {
          await место.готов
        } catch (ошибка) {
          слушают.delete(порт)
          return сбой("FLANG_IO_NET", текст(ошибка))
        }
        const готовый = место.очередь.shift()
        if (готовый !== undefined) return variant("Соединение открыто", { соединение: готовый })
        /* Ждём НЕ ВЕЧНО и не по таймеру: ждущий записывается в место, и его
           будит либо новое соединение, либо `закрыть()` — тем же `«Сбой»`, каким
           отвечает выключенная сеть. Сервер, у которого отняли порт, обязан
           узнать об этом откликом, а не зависнуть. */
        const номер = await new Promise((решить) => место.ждут.push(решить))
        if (номер === null) return сбой("FLANG_IO_NET", "слушающий сокет закрыт хозяином")
        return variant("Соединение открыто", { соединение: номер })
      }

      case "Прочитать из соединения": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        const соединение = соединения.get(Number(поля["соединение"]))
        if (соединение === undefined) {
          return сбой(
            "FLANG_IO_READ",
            `соединения «${поля["соединение"]}» у хозяина нет: оно закрыто, не принималось и не открывалось`,
          )
        }
        /* Отдаётся ВСЁ накопленное разом, а не по пакету: пакеты — забота
           TCP, а не языка, и программа, читающая тело в мегабайт, не обязана
           платить за это шестнадцатью витками вместо одного. */
        /* Раскодировщик — на соединение, а не на чтение, и это условие того,
           чтобы кириллица, разрезанная границей TCP, доехала целой: хвост
           незавершённой последовательности он держит между вызовами. Ровно то,
           что делал `setEncoding`, только теперь это решение ТЕКСТОВОГО
           поручения, а не хозяина. */
        if (соединение.раскодировщик === null) соединение.раскодировщик = new StringDecoder("utf8")
        let кусок = ""
        /* ЖДЁМ, ПОКА СЛОЖИТСЯ ХОТЯ БЫ ОДИН ЗНАК, и цикл этот не про
           эффективность.

           Пустая строка у `«Прочитано»` значит КОНЕЦ — по ней программа
           отличает обрезанный запрос от недочитанного. А раскодировщик отдаёт
           пустую строку и в другом случае: пришёл кусок, целиком состоящий из
           начала многобайтовой последовательности. Вернуть её тогда значило бы
           соврать «связь кончилась» на первой же кириллической букве, порезанной
           границей пакета.

           Прежний `setEncoding` этой беды не знал даром: поток сам не выдаёт
           события с пустой строкой, то есть ждал за нас. Теперь ждём здесь, и
           выход из цикла один — либо знак сложился, либо связь кончилась. */
        for (;;) {
          if (соединение.пришло.length === 0 && !соединение.конец) {
            await new Promise((решить) => соединение.ждут.push(решить))
          }
          const октеты = Buffer.concat(соединение.пришло)
          соединение.пришло = []
          кусок += соединение.раскодировщик.write(октеты)
          if (кусок !== "") break
          if (соединение.конец) {
            /* Связь кончилась — придержанный хвост уже никогда не дополнится, и
               молчать о нём нельзя: `end()` отдаёт его знаками замены, тем же
               числом, каким их отдавал `setEncoding` на закрытии сокета. */
            кусок += соединение.раскодировщик.end()
            break
          }
        }
        return variant("Прочитано", { содержимое: кусок })
      }

      /**
       * Октеты из соединения — то же самое чтение, но БЕЗ единого решения
       * хозяина о том, что эти байты значат.
       *
       * Отличий от текстового чтения ровно два, и оба вынуждены:
       *
       *   хвоста нет. Текст держит незавершённую многобайтовую
       *      последовательность до следующего пакета, потому что половина знака
       *      — не знак. У октета половинки не бывает, и придерживать нечего:
       *      отдаётся ВСЁ накопленное;
       *   отклик свой. `«Прочитано»` несёт строку, а здесь список чисел из
       *      [0, 255] — тот же способ назвать байт, каким его называют
       *      `stdlib/utf8.flang` и `stdlib/base64.flang`.
       *
       * Смешивать два чтения на одном соединении можно, и смысл у смеси
       * определён: текстовое читает столько, сколько складывается в знаки, и
       * придерживает хвост; октетное после него заберёт этот хвост первым. Ни
       * один октет при этом не теряется и не удваивается — придержанное живёт в
       * раскодировщике, а не в очереди буферов.
       */
      case "Прочитать октеты из соединения": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        const соединение = соединения.get(Number(поля["соединение"]))
        if (соединение === undefined) {
          return сбой(
            "FLANG_IO_READ",
            `соединения «${поля["соединение"]}» у хозяина нет: оно закрыто, не принималось и не открывалось`,
          )
        }
        if (соединение.пришло.length === 0 && !соединение.конец) {
          await new Promise((решить) => соединение.ждут.push(решить))
        }
        const октеты = Buffer.concat(соединение.пришло)
        соединение.пришло = []
        /* Пустой список — это КОНЕЦ, ровно как пустая строка у «Прочитано». */
        return variant("Октеты", { октеты: Array.from(октеты) })
      }

      case "Ответить в соединение": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        const номер = Number(поля["соединение"])
        const соединение = соединения.get(номер)
        if (соединение === undefined) {
          return сбой(
            "FLANG_IO_WRITE",
            `соединения «${поля["соединение"]}» у хозяина нет: оно закрыто, не принималось и не открывалось`,
          )
        }
        const содержимое = String(поля["содержимое"] ?? "")
        /* ЕДИНСТВЕННОЕ место, где принятое соединение отличается от открытого, и
           отличие названо правилом, а не случаем: закрывает тот, кто завёл.
           Принятое хозяин закрывает ответом (обмен кончился), открытое —
           оставляет программе (разговор продолжается). Пустое содержимое
           закрывает и то и другое: это и есть «положить трубку». */
        const закрываем = содержимое === "" || !соединение.своё
        if (закрываем) соединения.delete(номер)
        try {
          if (содержимое === "") {
            /* Молчание: соединение закрывается, не написав ни байта. Так служба
               отвечает на запрос, который не доехал. */
            соединение.сокет.destroy()
          } else if (закрываем) {
            await new Promise((решить, отказать) => {
              соединение.сокет.end(Buffer.from(содержимое, "utf8"), (ошибка) =>
                ошибка ? отказать(ошибка) : решить(),
              )
            })
          } else {
            await new Promise((решить, отказать) => {
              соединение.сокет.write(Buffer.from(содержимое, "utf8"), (ошибка) =>
                ошибка ? отказать(ошибка) : решить(),
              )
            })
          }
          /* Кодовые точки, а не октеты, — то же число, что у записи в файл, и
             тот же названный зазор: `Content-Length` служба считает знаками.
             У октетного близнеца ниже этого зазора нет: там считаются октеты,
             потому что там они и есть. */
          return variant("Записано", { сколько: [...содержимое].length })
        } catch (ошибка) {
          return сбой("FLANG_IO_WRITE", текст(ошибка))
        }
      }

      /**
       * Октеты в соединение. Всё, что отличает это поручение от текстового
       * близнеца сверху, — ОТСУТСТВИЕ перевода: там `Buffer.from(строка,
       * "utf8")`, здесь буфер собирается из чисел, и ни одно из них не меняется
       * по дороге.
       *
       * Правила закрытия те же самые и взяты у соседа буквально: закрывает тот,
       * кто завёл, а пустое содержимое кладёт трубку. Пустое здесь — пустой
       * СПИСОК, и это не натяжка: у обоих поручений «ничего не написать»
       * выражено значением нулевой длины, и разбирается оно одним вопросом.
       *
       * Октет проверяется на месте, а не молча приводится. Число 256 или 3.5 —
       * это ошибка ПРОГРАММЫ, и `«Сбой»` про неё честнее, чем `& 0xFF`: молчащее
       * приведение отправило бы в сеть не то, что программа сказала, и разница
       * всплыла бы у собеседника, а не здесь.
       */
      case "Ответить октетами в соединение": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        const номер = Number(поля["соединение"])
        const соединение = соединения.get(номер)
        if (соединение === undefined) {
          return сбой(
            "FLANG_IO_WRITE",
            `соединения «${поля["соединение"]}» у хозяина нет: оно закрыто, не принималось и не открывалось`,
          )
        }
        const собрано = вОктеты(поля["октеты"])
        if (собрано.беда !== undefined) return собрано.беда
        const буфер = собрано.буфер
        const закрываем = буфер.length === 0 || !соединение.своё
        if (закрываем) соединения.delete(номер)
        try {
          if (буфер.length === 0) {
            соединение.сокет.destroy()
          } else if (закрываем) {
            await new Promise((решить, отказать) => {
              соединение.сокет.end(буфер, (ошибка) => (ошибка ? отказать(ошибка) : решить()))
            })
          } else {
            await new Promise((решить, отказать) => {
              соединение.сокет.write(буфер, (ошибка) => (ошибка ? отказать(ошибка) : решить()))
            })
          }
          return variant("Записано", { сколько: буфер.length })
        } catch (ошибка) {
          return сбой("FLANG_IO_WRITE", текст(ошибка))
        }
      }

      case "Текущее время": {
        if (!можно.время) return сбой("FLANG_IO_DENIED", "хозяину запрещено смотреть на часы")
        return variant("Отметка времени", { миллисекунды: Date.now() })
      }

      case "Случайное число": {
        if (!можно.случайность) return сбой("FLANG_IO_DENIED", "хозяину запрещено бросать кости")
        return variant("Выпало", { значение: бросить() })
      }

      /* ── экран ─────────────────────────────────────────────────────────────
         Экрана у Node нет, и это сказано ОТКЛИКОМ, а не молчанием и не
         исключением. Разница между «не знаю такого поручения» и «знаю, но у
         меня этого нет» — не педантизм: первое означает, что хозяин отстал от
         словаря языка и его надо чинить, второе — что программа просит
         невозможного ЗДЕСЬ и может попросить другого. Программа, написанная для
         браузера, запущенная через `flang io`, получит `FLANG_IO_NO_SCREEN` и
         сдастся с ним же — вместо того чтобы врать, будто показала. */
      case "Показать":
      case "Ждать событие":
        return сбой(
          "FLANG_IO_NO_SCREEN",
          `у хозяина Node нет экрана: поручение «${поручение.variant}» исполнить нечем`,
        )

      default:
        /* Набор поручений закрыт, поэтому «неизвестное поручение» — это не
           «мы такого ещё не умеем», а расхождение хозяина со словарём языка.
           Отклик, а не исключение: программа увидит `«Сбой»` и решит сама. */
        return сбой("FLANG_IO_UNKNOWN", `хозяин не знает поручения «${поручение.variant}»`)
    }
  }

  /**
   * Отдать порты обратно системе. Это НЕ поручение и потому не в словаре:
   * закрывает слушающий сокет тот, кто его завёл, а завёл его тот, кто позвал
   * `nodeHost`. Программа порт не открывала — она попросила принять соединение.
   *
   * Ждущий `«Принять соединение»` получает `«Сбой»`, и это единственный способ
   * закончить план, который в остальном ждал бы вечно: сервер есть
   * бесконечная последовательность завершающихся программ, и кончается она
   * снаружи.
   */
  исполнить.закрыть = () => {
    закрыт = true
    for (const место of слушают.values()) {
      const ждут = место.ждут
      место.ждут = []
      for (const продолжить of ждут) продолжить(null)
      место.сервер?.close()
    }
    слушают.clear()
    for (const соединение of соединения.values()) соединение.сокет.destroy()
    соединения.clear()
  }

  return исполнить
}

/**
 * СИНХРОННЫЙ хозяин — тот, которого зовёт планировщик процессов.
 *
 * ── Почему синхронный, а не тот же ──────────────────────────────────────────
 *
 * Хозяин плана (`nodeHost` выше) асинхронен, и это законно: `runPlan` ждёт его
 * `await`-ом. Планировщик процессов (`conc.mjs`, `runConcurrent`) синхронен
 * ВЕСЬ, и синхронен не по недосмотру: его зовут из побайтовой сверки с
 * напечатанным C, из перебора сетки семян, из замера и из горячей замены —
 * полсотни мест. Сделать его асинхронным ради поручения значило бы переписать
 * их все и, главное, переписать сверку, которая и есть доказательство модели.
 *
 * Цена названа и не спрятана: **ни одно сетевое поручение синхронному хозяину
 * не даётся**. Node не умеет ждать `fetch` синхронно, и притворяться нечем —
 * поэтому `«Запросить»` отвечает `«Сбой»` с кодом `FLANG_IO_NET`, тем же самым,
 * которым асинхронный хозяин отвечает, когда сходить в сеть нечем. Это долг, и
 * он записан в `flang/conc/SPEC.md` строкой, а не забыт: снимет его либо
 * асинхронный планировщик, либо поручение, отвечающее не сразу.
 *
 * С приходом сокета барьер стал ВИДНЕЕ, а не выше, и назвать это надо точно:
 * `«Принять соединение»` — то самое поручение, которое ОБЯЗАНО ждать, и
 * синхронному хозяину оно не даётся тем более. Значит сервер, написанный
 * процессами (`server.flang`), упрётся ровно в тот же барьер, что и клиент:
 * служба на ПЛАНЕ по сети работает сегодня, служба на ПРОЦЕССАХ — нет, и
 * разделяет их не сеть, а то, что планировщик синхронен весь. Долг один, мест
 * два.
 *
 * `«Открыть соединение»` барьера не сдвинуло и не могло: `connect(2)` ждёт
 * ответа с той стороны так же, как `accept(2)` ждёт стучащегося. Поэтому оно
 * стоит в той же ветке — пятым, а не пятым сообщением.
 *
 * Остальные четыре поручения синхронны по природе: чтение, запись, часы и кости.
 * Отказы, полномочия и разрешение путей — те же самые, что у соседа сверху, и
 * взяты они у него буквально (`путь`, `ПОЛНЫЕ_ПРАВА`, `сбой`), чтобы у двух
 * хозяев одной среды не разошлись ни коды, ни правила.
 *
 * ── Чего этот хозяин НЕ ЗНАЕТ, и это названо числом ─────────────────────────
 *
 * Три поручения падают здесь в `default` и получают `FLANG_IO_UNKNOWN`:
 * «Перечислить каталог», «Запустить процесс» и «Запустить процесс с вводом».
 * По словарю (шапка `io.mjs`) это слово значит «хозяин ОТСТАЛ от языка», а не
 * «мне нечем», — и отставание настоящее: `readdirSync` и `spawnSync` синхронны
 * по природе, барьер планировщика их не касается.
 *
 * Почему не исправлено здесь: у службы ДВА хозяина, и второй — напечатанный C
 * (`emit/c/flang_conc.c`). Там те же три поручения тоже падают в «не знаю», и
 * закрыть дыру в одном значило бы РАЗВЕСТИ хозяев: журнал службы под Node
 * перестал бы совпадать с журналом той же службы, напечатанной в C, а на
 * побайтовом совпадении этих журналов стоит доказательство модели
 * конкурентности. Долг записан целиком: три поручения, два хозяина, одна
 * правка, и делать её надо в обоих местах сразу.
 */
export function nodeHostSync(options = {}) {
  const корень = resolve(options.base ?? process.cwd())
  const можно = { ...ПОЛНЫЕ_ПРАВА, ...(options.разрешено ?? {}) }
  const внутриКорня = options.внутриКорня === true
  const бросить = options.seed === undefined ? Math.random : makeRandom(options.seed)

  const путь = (значение) => {
    if (typeof значение !== "string" || значение === "") {
      return { беда: сбой("FLANG_IO_PATH", "поручению нужен непустой путь") }
    }
    const полный = resolve(корень, значение)
    if (внутриКорня) {
      const внутрь = relative(корень, полный)
      if (внутрь.startsWith("..") || isAbsolute(внутрь)) {
        return { беда: сбой("FLANG_IO_DENIED", `путь «${значение}» ведёт за пределы каталога работы`) }
      }
    }
    return { полный }
  }

  return function исполнить(поручение) {
    const поля = поручение.fields ?? {}
    switch (поручение.variant) {
      case "Прочитать файл": {
        if (!можно.чтение) return сбой("FLANG_IO_DENIED", "хозяину запрещено читать файлы")
        const { полный, беда } = путь(поля["путь"])
        if (беда !== undefined) return беда
        try {
          return variant("Прочитано", { содержимое: readFileSync(полный, "utf8") })
        } catch (ошибка) {
          return сбой("FLANG_IO_READ", текст(ошибка))
        }
      }

      case "Записать файл": {
        if (!можно.запись) return сбой("FLANG_IO_DENIED", "хозяину запрещено писать файлы")
        const { полный, беда } = путь(поля["путь"])
        if (беда !== undefined) return беда
        const содержимое = String(поля["содержимое"] ?? "")
        try {
          writeFileSync(полный, содержимое, "utf8")
          /* Кодовые точки, а не единицы UTF-16, — как у асинхронного хозяина, и
             по той же причине: «записано» обязано совпадать с «длина». */
          return variant("Записано", { сколько: [...содержимое].length })
        } catch (ошибка) {
          return сбой("FLANG_IO_WRITE", текст(ошибка))
        }
      }

      case "Запросить":
      case "Открыть соединение":
      case "Принять соединение":
      case "Прочитать из соединения":
      case "Ответить в соединение":
      /* Октетная пара платит тот же барьер и по той же причине: ждать сеть
         синхронно нечем. Кодировка тут ни при чём — от неё зависит, ЧТО придёт,
         а не то, можно ли дождаться. */
      case "Прочитать октеты из соединения":
      case "Ответить октетами в соединение": {
        if (!можно.сеть) return сбой("FLANG_IO_DENIED", "хозяину запрещено ходить в сеть")
        /* Названный долг, а не молчание: сходить в сеть и дождаться ответа, не
           отпуская поток, Node не умеет, а планировщик процессов синхронен. Код
           тот же, каким асинхронный хозяин отвечает на «нечем сходить»: для
           программы «сеть не дали» и «сеть не ответила» — один путь, и он один
           и проверен.

           Четыре поручения соединения стоят в одной ветке с `«Запросить»`
           намеренно: барьер у них ОДИН И ТОТ ЖЕ, и разводить его на пять
           сообщений значило бы делать вид, что причин пять. */
        return сбой(
          "FLANG_IO_NET",
          `у синхронного хозяина нет способа ждать сеть («${поручение.variant}»): ` +
            "планировщик процессов не ждёт",
        )
      }

      case "Текущее время": {
        if (!можно.время) return сбой("FLANG_IO_DENIED", "хозяину запрещено смотреть на часы")
        return variant("Отметка времени", { миллисекунды: Date.now() })
      }

      case "Случайное число": {
        if (!можно.случайность) return сбой("FLANG_IO_DENIED", "хозяину запрещено бросать кости")
        return variant("Выпало", { значение: бросить() })
      }

      default:
        return сбой("FLANG_IO_UNKNOWN", `хозяин не знает поручения «${поручение.variant}»`)
    }
  }
}

function текст(ошибка) {
  return ошибка instanceof Error ? ошибка.message : String(ошибка)
}

/**
 * Список чисел поручения → буфер октетов, либо `«Сбой»`.
 *
 * Одна функция на обоих хозяев и на все октетные поручения: разойдись у них
 * правило про то, что считается октетом, — и программа, проверенная под одним,
 * молча ехала бы не так под другим.
 *
 * Проверяется КАЖДОЕ число, и отказ называет номер. Довод тот же, по которому
 * неудача поручения — отклик: 256 и 3.5 в списке октетов — это ошибка
 * программы, и молчаливое `& 0xFF` отправило бы собеседнику не то, что она
 * сказала. Найти такую подмену потом можно только по чужому логу.
 *
 * `isList`, а не `Array.isArray`: список в языке бывает и срезом (`Список` в
 * `builtins.mjs`), и срез — обычный список для всякого, кто его читает. Хвост
 * списка, отданный октетным поручением, приезжает сюда именно срезом.
 */
function вОктеты(значение) {
  if (!isList(значение)) {
    return { беда: сбой("FLANG_IO_OCTETS", "поручению нужен список октетов, а дан не список") }
  }
  const числа = элементыСписка(значение)
  const буфер = Buffer.allocUnsafe(числа.length)
  for (let место = 0; место < числа.length; место += 1) {
    const октет = числа[место]
    if (typeof октет !== "number" || !Number.isInteger(октет) || октет < 0 || октет > 255) {
      return {
        беда: сбой(
          "FLANG_IO_OCTETS",
          `октет ${место + 1} равен «${октет}»: нужно целое от 0 до 255`,
        ),
      }
    }
    буфер[место] = октет
  }
  return { буфер }
}

/**
 * Сколько единиц UTF-16 двух потоков хозяин соглашается держать в памяти.
 *
 * Считается НЕ по правилам языка («длина» считает кодовые точки, SPEC, раздел
 * 5): здесь мерится не длина текста, а занятая память, а память занимают именно
 * единицы UTF-16. Число в сообщение уезжает то же самое, что проверяется.
 */
const ПРЕДЕЛ_ВЫВОДА = 1 << 20

/**
 * Запуск процесса и ожидание его конца — обещанием, собранным руками.
 *
 * Руками, потому что готовые обёртки Node лгут в трёх местах сразу, и каждое
 * названо здесь, чтобы их не вернули обратно «для краткости»:
 *
 *   • `promisify(execFile)` РЕЖЕКТИТСЯ на ненулевом коде — см. ветку выше;
 *   • `spawn` со своим ключом `timeout` убивает процесс сигналом, и тогда
 *     «истёк срок» неотличимо от «убит кем-то ещё»: `close` в обоих случаях
 *     приносит один и тот же `SIGTERM`. Здесь срок стережёт свой таймер, и
 *     ответом на него идёт `«Сбой»` с кодом `FLANG_IO_TIMEOUT` — беда хозяина,
 *     который срок и назначил, а не судьба процесса;
 *   • `shell: true` превратило бы имя программы в команду оболочки. Его тут
 *     нет и быть не должно.
 *
 * Таймаут здесь ОБЯЗАТЕЛЕН: без него `flang io` висит навсегда на первой же
 * программе, которая ждёт ввода, и `maxOrders` не спасает — предел считает
 * поручения, а висит одно.
 *
 * Предел вывода — из того же ряда. Программа, печатающая без конца, съела бы
 * память хозяина целиком, и никакой предел поручений этого тоже не увидит.
 * Усечь вывод молча нельзя: отклик тогда врал бы про то, что программа
 * сказала. Поэтому предел — это `«Сбой»`, а не тихое обрезание.
 */
function запуститьПроцесс(программа, аргументы, корень, таймаут, ввод) {
  return new Promise((готово) => {
    let дитя
    try {
      /* СТАНДАРТНЫЙ ВВОД НАЗВАН, а не оставлен умолчанию, и это правка, а не
         оформление. Умолчание `spawn` — труба, и труба эта открыта: никто в неё
         не пишет и никто её не закрывает. Для потомка, читающего свой ввод, это
         не «ввода нет», а «ввод будет позже», и он ждёт — до срока хозяина, то
         есть до `SIGKILL`. Замер: двоичный языковой сервер при открытой трубе
         отвечал НУЛЁМ байтов, при закрытой — 334 байтами.

         Поэтому без ввода потомку даётся пустота (`ignore` — это `/dev/null`,
         чтение из него сразу конец), а с вводом — труба, в которую пишут и
         которую тут же закрывают. */
      дитя = spawn(программа, аргументы, {
        cwd: корень,
        stdio: [ввод === null ? "ignore" : "pipe", "pipe", "pipe"],
      })
    } catch (ошибка) {
      /* `spawn` бросает синхронно на кривых аргументах (не на пропавшем файле —
         тот приезжает событием `error`). Обе дороги обязаны кончиться откликом. */
      готово(сбой("FLANG_IO_SPAWN", текст(ошибка)))
      return
    }

    let вывод = ""
    let ошибки = ""
    let отвечено = false
    /* Таймер объявлен ДО `ответить`, хотя заводится после: `ответить` его
       снимает, и порядок «объявить, потом присвоить» убирает всякий вопрос о
       том, что будет, если ответ придёт раньше, чем таймер заведён. */
    let часы = null
    /* Событий, кончающих ожидание, четыре (`error`, `close`, срок, предел), и
       любое может прийти после другого: убитый процесс всё равно закроет
       потоки. Отвечает ПЕРВОЕ, остальные молчат — иначе обещание пыталось бы
       разрешиться дважды, и второй ответ пропал бы незаметно. */
    const ответить = (отклик) => {
      if (отвечено) return
      отвечено = true
      clearTimeout(часы)
      готово(отклик)
    }

    часы = setTimeout(() => {
      дитя.kill("SIGKILL")
      ответить(сбой("FLANG_IO_TIMEOUT", `программа «${программа}» не уложилась в ${таймаут} мс`))
    }, таймаут)

    const копить = (куда) => (кусок) => {
      if (куда === "вывод") вывод += кусок
      else ошибки += кусок
      if (вывод.length + ошибки.length <= ПРЕДЕЛ_ВЫВОДА) return
      дитя.kill("SIGKILL")
      ответить(
        сбой("FLANG_IO_SPAWN", `программа «${программа}» напечатала больше ${ПРЕДЕЛ_ВЫВОДА} единиц UTF-16`),
      )
    }
    дитя.stdout.setEncoding("utf8")
    дитя.stderr.setEncoding("utf8")
    дитя.stdout.on("data", копить("вывод"))
    дитя.stderr.on("data", копить("ошибки"))

    /* Написать и закрыть. `error` на трубе ввода — обычное дело, а не поломка:
       потомок вправе кончиться, не дочитав («head -1»), и тогда запись бьётся
       об `EPIPE`. Это НЕ ответ: ответ придёт от `close`, с кодом и выводом,
       которые потомок успел дать. Молчание здесь — единственное честное
       поведение, а необработанный `error` уронил бы весь процесс хозяина. */
    if (ввод !== null) {
      дитя.stdin.on("error", () => {})
      дитя.stdin.end(ввод, "utf8")
    }

    /* «Не запустилось вовсе» — это `error`: программы нет, прав нет, имя не то.
       Только здесь `«Сбой»` честен, потому что процесса не было. */
    дитя.on("error", (ошибка) => ответить(сбой("FLANG_IO_SPAWN", текст(ошибка))))

    /* `close`, а не `exit`: `exit` приходит, когда кончился процесс, а потоки
       могут ещё дочитываться, и часть вывода уехала бы мимо отклика. */
    дитя.on("close", (код, сигнал) => {
      ответить(
        сигнал === null && код !== null
          ? variant("Процесс завершён", { код, вывод, ошибки })
          : variant("Процесс убит", { сигнал: сигнал ?? "неизвестен", вывод, ошибки }),
      )
    })
  })
}
