/** Код отказа загрузки. Отказ — определённый исход, а не молчаливое «не вышло». */
export const ОТКАЗ_ЗАМЕНЫ = "FLANG_HOTSWAP_REFUSED"

/**
 * Запрос на замену ПОД работающим планировщиком.
 *
 * Отдаётся в `runConcurrent(программа, прогон, { замены: [замена({…})] })` и
 * ложится на барьере между пробегами — после `после` пробегов, считая и снятые
 * по кванту. Планировщик зовёт `проверить` с текущей программой и НАКОПЛЕННЫМ
 * состоянием процесса; всё остальное решается здесь.
 *
 * Проверялка приезжает функцией, а не импортом на той стороне, и это вынужденно
 * и правильно разом: `parser.mjs` и `types.mjs` импортируют `conc.mjs`, а мы
 * импортируем их — обратный импорт замкнул бы круг. Планировщику про доказательства
 * знать и не надо: его дело — когда спросить и что сделать с ответом.
 *
 * @param {{после?: number, процесс: string, исходник: string, витков?: number,
 *          витковПереноса?: number, перенос?: string, файл?: string}} что
 */
export function замена(что) {
  return {
    после: что.после ?? 0,
    процесс: что.процесс,
    проверить: (программа, процесс, состояние) =>
      заменитьОбработчик(программа, процесс, что.исходник, {
        витков: что.витков,
        витковПереноса: что.витковПереноса,
        перенос: что.перенос,
        файл: что.файл,
        состояние,
      }),
  }
}

/**
 * Принять новый обработчик под работающим процессом.
 *
 * @param {object} программа AST работающей программы
 * @param {string} процесс имя процесса, чей обработчик меняется
 * @param {string} исходник текст модуля с новыми объявлениями
 * @param {{витков?: number, витковПереноса?: number, файл?: string,
 *          перенос?: string, состояние?: unknown}} условия
 *   `витков` — граница, в которую новый обработчик обязан уложиться при ЛЮБОМ
 *   размере входа. Названа — значит требуется ПОСТОЯННАЯ оценка не больше этого
 *   числа: оценка, растущая с размером сообщения, границы не даёт, потому что
 *   размер сообщения не ограничен ничем.
 *   `перенос` — имя функции, переводящей состояние из старого вида в новый.
 *   Требуется тогда и только тогда, когда замена меняет объявленный вид
 *   состояния процесса.
 *   `состояние` — то самое накопленное состояние, которое переносится. Дано —
 *   значит перенос ВЫПОЛНЯЕТСЯ здесь же, а его цена сверяется с границей числом,
 *   а не формой многочлена. Не дано (замена проверяется, а не применяется) —
 *   перенос обязан уложиться в границу при любом размере, как обработчик.
 * @returns {{
 *   принято: boolean, программа: object|null, диагностики: Array,
 *   оценка: number[]|null, узел: object|null, состояние: unknown,
 *   перенос: {функция: string, оценка: number[]|null, размер: number|null,
 *             витков: number|null, витки: number|null}|null
 * }}
 */
export function заменитьОбработчик(программа, процесс, исходник, условия = {}) {
  const узел = (программа?.processes ?? []).find((п) => п?.name === процесс)
  if (узел === undefined) {
    return отказ(`процесса «${процесс}» в программе нет: менять нечего`)
  }

  let новые
  try {
    новые = parse(исходник, условия.файл ?? "замена.flang")
  } catch (ошибка) {
    return отказ(`новый обработчик не разобран: ${ошибка?.message ?? String(ошибка)}`)
  }

  /* ── Что замене трогать нельзя, и почему это не осторожность ─────────────
     Надзор строится на прогон один раз и дальше только читается: дерево, по
     которому идёт отказ, обязано быть тем же деревом, с которым сведено
     множество достижимых отказов (Г1). Меняя его под работающим планировщиком,
     мы получили бы проверку полноты, описывающую не то, что работает. */
  if ((новые.supervisors ?? []).length > 0) {
    return отказ(
      `замена объявляет надзор «${новые.supervisors[0].name}»: надзор под работающим планировщиком не меняется — ` +
        `дерево надзора сведено с множеством достижимых отказов (шаг Г1) один раз на прогон`,
    )
  }

  /* Типы ДОБАВЛЯЮТСЯ, но не переобъявляются. Переобъявление стёрло бы старый вид
     состояния — ровно тот, который обязан принимать перенос, — и проверить
     перенос стало бы нечем. Встроенный словарь «Действие» здесь не в счёт: его
     приписывает сам разбор, а не автор замены. */
  const типы = [...(программа.types ?? [])]
  for (const тип of новые.types ?? []) {
    if (тип?.builtin === true) continue
    if (типы.some((старый) => старый?.name === тип.name)) {
      return отказ(
        `тип «${тип.name}» уже объявлен в работающей программе: замена типы добавляет, но не переобъявляет — ` +
          `иначе старый вид состояния перестал бы быть объявлен где бы то ни было, и переносить его было бы нечем`,
      )
    }
    типы.push(тип)
  }

  /* Объявление процесса заменяется целиком — вид состояния, начальное, запас,
     обработчик, — кроме одного поля. */
  let новыйУзел = узел
  for (const объявленный of новые.processes ?? []) {
    if (!(программа.processes ?? []).some((п) => п?.name === объявленный.name)) {
      return отказ(
        `процесса «${объявленный.name}» в работающей программе нет: новых процессов замена не заводит — ` +
          `порождение это шаг Б1, и порядок процессов задаёт чередование`,
      )
    }
    if (объявленный.name !== процесс) {
      return отказ(
        `замена объявляет процесс «${объявленный.name}», а меняется «${процесс}»: за один заход меняется один процесс`,
      )
    }
    /* Единственное поле, которое не меняется никогда. В ящике уже лежат
       сообщения объявленного вида, а перенос у нас один и на состояние; чтобы
       сменить вид сообщений, пришлось бы переводить каждое из уже пришедших, а
       это не то же самое, что перевести одно состояние. */
    if (объявленный.accepts !== узел.accepts) {
      return отказ(
        `тип сообщений процесса «${процесс}» объявлен как «${узел.accepts}», а замена называет «${объявленный.accepts}»: ` +
          `в ящике уже лежат сообщения объявленного вида, и переводить их нечем`,
      )
    }
    новыйУзел = объявленный
  }
  const процессы = (программа.processes ?? []).map((п) => (п?.name === процесс ? новыйУзел : п))

  /* Функции с теми же именами ЗАМЕНЯЮТСЯ, остальные добавляются. Порядок
     сохраняется — не для красоты: от порядка функций зависит порядок
     диагностик, а диагностика, которая переставляется от замены к замене, не
     сверяется ни с чем. */
  const поИмени = new Map((новые.functions ?? []).map((фн) => [фн.name, фн]))
  const функции = (программа.functions ?? []).map((фн) => поИмени.get(фн.name) ?? фн)
  for (const фн of новые.functions ?? []) {
    if (!функции.some((старая) => старая.name === фн.name)) функции.push(фн)
  }
  /* Прогоны из кандидата УБИРАЮТСЯ, и это правило, а не поблажка. `прогон` — это
     пример программы: семя, входящие сообщения и ожидаемое итоговое состояние.
     Ожидание описывает программу ДО замены и по-другому описывать не может: оно
     написано в исходнике, а замена приезжает после. Смена вида состояния делает
     такое ожидание не «неверным», а бессмысленным — оно про тип, которого у
     процесса больше нет. Проверять код по устаревшему примеру значило бы
     требовать переписать примеры в момент замены. Замена проверяет КОД. */
  const кандидат = { ...программа, types: типы, functions: функции, processes: процессы, runs: [] }

  /* Признак «тотальная» проверяется ПЕРВЫМ, до типов, и порядок здесь не
     вкусовщина. Проверка типов тоже отвергает нетотальный обработчик без
     запаса (`FLANG_HANDLER_NOT_TOTAL`), но говорит про программу: «объявите
     запас». Загрузке нужно сказать другое и про другое — «доказательства нет,
     поэтому не принято», — а два разных ответа на один вопрос обязан давать
     тот, кто ближе к делу. */
  const обязанБытьТотальным = новыйУзел.budget === null || новыйУзел.budget === undefined
  const новый = функции.find((фн) => фн.name === новыйУзел.handler)
  if (новый === undefined) {
    return отказ(`в замене нет обработчика «${новыйУзел.handler}»`)
  }
  if (обязанБытьТотальным && новый.total !== true) {
    return отказ(
      `обработчик «${новыйУзел.handler}» приехал без признака «тотальная», а процесс «${процесс}» ` +
        `запаса витков не объявлял: принять нечего — доказательства нет`,
    )
  }

  const типовые = checkTypes(кандидат)
  const диагностикиТипов = (типовые?.diagnostics ?? []).filter((д) => д.severity !== "warning")
  if (диагностикиТипов.length > 0) {
    return отказ(`новый обработчик не прошёл проверку типов`, диагностикиТипов)
  }

  /* Тотальность требуется тогда же, когда её требует компилятор: у процесса без
     объявленного запаса витков. С запасом обработчик имеет право не завершаться
     — исчерпание запаса определённый исход, и надзор про него знает. */
  if (обязанБытьТотальным) {
    const тотальность = checkTotality(кандидат)
    if (!тотальность.ok) {
      return отказ(
        `тотальность обработчика «${новыйУзел.handler}» не доказана`,
        тотальность.diagnostics,
      )
    }
  }

  const оценки = оценитьВитки(кандидат)
  const оценка = оценки.get(новыйУзел.handler)
  if (условия.витков !== undefined) {
    if (оценка === undefined || оценка.оценка === null) {
      return отказ(
        `оценки витков у обработчика «${новыйУзел.handler}» нет (${оценка?.причина ?? "функция не найдена"}), ` +
          `а названа граница в ${условия.витков} витков`,
        [],
        null,
      )
    }
    if (степень(оценка.оценка) > 0) {
      return отказ(
        `витков у обработчика «${новыйУзел.handler}» ${текстОценки(оценка.оценка)} — оценка растёт с размером ` +
          `сообщения, а размер сообщения не ограничен ничем: в ${условия.витков} витков это не укладывается`,
        [],
        оценка.оценка,
      )
    }
    const сколько = значение(оценка.оценка, 0)
    if (сколько > условия.витков) {
      return отказ(
        `витков у обработчика «${новыйУзел.handler}» ${сколько}, а названа граница в ${условия.витков}`,
        [],
        оценка.оценка,
      )
    }
  }

  const перенос = проверитьПеренос(кандидат, узел, новыйУзел, оценки, условия)
  if (перенос.отказ !== null) return перенос.отказ

  return {
    принято: true,
    программа: кандидат,
    диагностики: [],
    оценка: оценка?.оценка ?? null,
    узел: новыйУзел,
    состояние: перенос.состояние,
    перенос: перенос.отчёт,
  }
}

/**
 * Перенос состояния между видами: нужен ли, годится ли, во что обойдётся.
 *
 * Возвращает `{ отказ, состояние, отчёт }`. `состояние` — новое состояние, если
 * его было из чего сделать; `undefined` значит «переносить было нечего или
 * нечем, состояние остаётся прежним».
 */
function проверитьПеренос(кандидат, узел, новыйУзел, оценки, условия) {
  const сменаВида = новыйУзел.state !== узел.state
  const названо = условия.перенос !== undefined && условия.перенос !== null

  if (!сменаВида) {
    if (названо) {
      /* Перенос, названный впустую, — это работа, которая не будет сделана, и
         молчание о ней хуже отказа: автор считал бы состояние переделанным. */
      return {
        отказ: отказ(
          `перенос «${условия.перенос}» назван, а вид состояния не менялся (как был «${узел.state}», так и остался): ` +
            `перенос зовётся только при смене вида, и молча пропустить его нельзя`,
        ),
        состояние: undefined,
        отчёт: null,
      }
    }
    return { отказ: null, состояние: undefined, отчёт: null }
  }

  if (!названо) {
    return {
      отказ: отказ(
        `вид состояния меняется с «${узел.state}» на «${новыйУзел.state}», а переноса не названо: ` +
          `накопленное состояние принадлежит процессу, и превратить его в новый вид догадкой нельзя`,
      ),
      состояние: undefined,
      отчёт: null,
    }
  }

  const функция = (кандидат.functions ?? []).find((фн) => фн?.name === условия.перенос)
  if (функция === undefined) {
    return {
      отказ: отказ(`переноса «${условия.перенос}» в замене нет`),
      состояние: undefined,
      отчёт: null,
    }
  }
  if (функция.total !== true) {
    return {
      отказ: отказ(
        `перенос «${условия.перенос}» приехал без признака «тотальная»: незавершающийся перенос оставил бы процесс ` +
          `ни в старом виде, ни в новом, и надзору такое не разобрать`,
      ),
      состояние: undefined,
      отчёт: null,
    }
  }

  /* Тип переноса сверяется с ОБОИМИ объявлениями — тем и отличается от
     `code_change/3`, у которого тип `term() -> term()`. */
  const параметры = функция.params ?? []
  if (параметры.length !== 1) {
    return {
      отказ: отказ(
        `перенос «${условия.перенос}» принимает ${параметры.length} арг., а обязан принимать один: старое состояние`,
      ),
      состояние: undefined,
      отчёт: null,
    }
  }
  const принимает = имяТипа(параметры[0]?.type)
  if (принимает !== узел.state) {
    return {
      отказ: отказ(
        `перенос «${условия.перенос}» принимает «${принимает}», а состояние процесса «${узел.name}» объявлено как ` +
          `«${узел.state}»: переносить надо то, что накоплено, а не то, что хотелось бы`,
      ),
      состояние: undefined,
      отчёт: null,
    }
  }
  const возвращает = имяТипа(функция.returns)
  if (возвращает !== новыйУзел.state) {
    return {
      отказ: отказ(
        `перенос «${условия.перенос}» возвращает «${возвращает}», а новый вид состояния объявлен как «${новыйУзел.state}»`,
      ),
      состояние: undefined,
      отчёт: null,
    }
  }

  const своя = оценки.get(условия.перенос)
  const оценкаПереноса = своя?.оценка ?? null
  const естьСостояние = Object.hasOwn(условия, "состояние") && условия.состояние !== undefined
  const размер = естьСостояние ? размерЗначения(условия.состояние) : null
  let предел = null

  if (условия.витковПереноса !== undefined) {
    if (оценкаПереноса === null) {
      return {
        отказ: отказ(
          `оценки витков у переноса «${условия.перенос}» нет (${своя?.причина ?? "функция не найдена"}), ` +
            `а названа граница в ${условия.витковПереноса} витков`,
        ),
        состояние: undefined,
        отчёт: null,
      }
    }
    if (естьСостояние) {
      /* Вот оно, место, где строгость выходит дешевле. Перенос зовётся один раз
         и на состоянии, которое лежит перед нами: его размер — число, значит и
         цена переноса — число, а не многочлен. Растущая оценка тут не помеха. */
      предел = значение(оценкаПереноса, размер)
      if (предел > условия.витковПереноса) {
        return {
          отказ: отказ(
            `перенос «${условия.перенос}» на состоянии размера ${размер} стоит ${предел} витков, ` +
              `а названа граница в ${условия.витковПереноса}`,
          ),
          состояние: undefined,
          отчёт: null,
        }
      }
    } else if (степень(оценкаПереноса) > 0) {
      /* Состояния нам не дали — значит подставлять нечего, и спрос тот же, что с
         обработчика: уложись при любом размере. */
      return {
        отказ: отказ(
          `витков у переноса «${условия.перенос}» ${текстОценки(оценкаПереноса)}, а состояния, на котором это ` +
            `можно было бы посчитать числом, не дано: в ${условия.витковПереноса} витков это не укладывается`,
        ),
        состояние: undefined,
        отчёт: null,
      }
    } else {
      предел = значение(оценкаПереноса, 0)
      if (предел > условия.витковПереноса) {
        return {
          отказ: отказ(
            `витков у переноса «${условия.перенос}» ${предел}, а названа граница в ${условия.витковПереноса}`,
          ),
          состояние: undefined,
          отчёт: null,
        }
      }
    }
  }

  const отчёт = {
    функция: условия.перенос,
    оценка: оценкаПереноса,
    размер,
    витков: предел,
    витки: null,
  }
  if (!естьСостояние) return { отказ: null, состояние: undefined, отчёт }

  /* Перенос ВЫПОЛНЯЕТСЯ здесь, а не у зовущего, и ровно поэтому замена
     атомарна: не сошлось — не применено ничего. Предел витков берётся
     посчитанный: если перенос его перешагнёт, значит соврала оценка, и узнать
     об этом надо отказом замены, а не тихо. */
  const счёт = { витки: 0 }
  try {
    const рантайм = createRuntime(кандидат)
    const состояние = предел === null
      ? рантайм.call(условия.перенос, [условия.состояние], { отчёт: счёт })
      : рантайм.call(условия.перенос, [условия.состояние], { maxSteps: предел, отчёт: счёт })
    отчёт.витки = счёт.витки
    return { отказ: null, состояние, отчёт }
  } catch (ошибка) {
    return {
      отказ: отказ(
        `перенос «${условия.перенос}» не выполнился: ${ошибка?.message ?? String(ошибка)}`,
      ),
      состояние: undefined,
      отчёт: null,
    }
  }
}

/** Имя объявленного типа: перенос сверяется по именам, а не по строению. */
function имяТипа(тип) {
  return тип?.kind === "named" ? тип.name : (тип?.name ?? null)
}

function отказ(сообщение, диагностики = [], оценка = null) {
  return {
    принято: false,
    программа: null,
    диагностики: [
      { code: ОТКАЗ_ЗАМЕНЫ, message: сообщение, severity: "error", span: null },
      ...диагностики,
    ],
    оценка,
    узел: null,
    состояние: undefined,
    перенос: null,
  }
}
