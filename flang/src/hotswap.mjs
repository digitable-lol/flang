/**
 * hotswap.mjs — горячая замена обработчика ПОД ДОКАЗАТЕЛЬСТВО.
 *
 * Шаг Е1 карты (`flang/conc/RESILIENCE.md`), и он зависит от В3 не по формату
 * зависимостей, а по существу: без оценки витков доказывать было бы нечего,
 * кроме тотальности, а тотальности для этого мало.
 *
 * ── Чем это отличается от загрузки модуля в BEAM ───────────────────────────
 *
 * BEAM грузит что угодно. `code:load_binary/3` примет модуль, чей
 * `handle_call/3` уходит в вечный цикл, и процесс повиснет намертво — снимется
 * только `exit/2`. Это не недосмотр, а следствие: доказательства завершения у
 * BEAM нет ни для старого кода, ни для нового, значит и требовать его от нового
 * не с чем.
 *
 * Здесь наоборот. Дефункционализация, проверка тотальности и оценка витков —
 * ЦЕЛЬНОПРОГРАММНЫЕ: они смотрят на всю программу разом. Значит заменить
 * обработчик под работающим процессом — это переспросить доказательство, а не
 * подменить указатель. Дороже, чем в BEAM, и строже, чем в BEAM, и оба слова
 * здесь буквальны.
 *
 * ── Что именно требуется от нового обработчика ─────────────────────────────
 *
 * Четыре условия, и каждое отвергает своё:
 *
 *   1. РАЗБИРАЕТСЯ и СВЯЗЫВАЕТСЯ — иначе замены нет вовсе;
 *   2. ПРОХОДИТ ПРОВЕРКУ ТИПОВ вместе со всей остальной программой. Именно
 *      вместе: обработчик обязан принимать то же состояние и то же сообщение,
 *      что объявлены у процесса, и вернуть тот же отклик;
 *   3. ТОТАЛЕН — если процесс не объявил запаса витков. Тут проверка ровно та
 *      же, что на этапе компиляции, и другой быть не может: доказательство,
 *      которое в рантайме слабее, чем в компиляторе, — это не доказательство;
 *   4. ОГРАНИЧЕН, если названа граница (`витков`). Это и есть вклад В3, и без
 *      него пункт 3 оставлял бы дверь открытой: тотальная `фиб` тотальна,
 *      проверку тотальности проходит, и вешает процесс на миллион витков ничуть
 *      не хуже вечного цикла в BEAM. Разница только в том, что она когда-нибудь
 *      кончится, а для кванта это разница без различия.
 *
 * ── Чего здесь НЕТ, и это граница, а не заготовка ──────────────────────────
 *
 * Замена НЕ переносит состояние из одного вида в другой: состояние принадлежит
 * процессу, его тип объявлен, и новый обработчик обязан принимать тот же тип.
 * «Изменить представление состояния на лету» — это `code_change/3` из OTP, и
 * его здесь нет: он требует функции перевода, которую тоже надо проверять, а
 * проверять её сегодня нечем — тип старого состояния после замены уже не
 * объявлен нигде.
 *
 * Замена не умеет и второго, что умеет BEAM: держать две версии модуля
 * одновременно. Это устройство таблицы кода 1986 года, из которого «две версии»
 * и следуют; нам нужна замена, а не именно этот её механизм.
 */

import { оценитьВитки, степень, текстОценки, значение } from "./bounded.mjs"
import { parse } from "./parser.mjs"
import { checkTotality } from "./totality.mjs"
import { checkTypes } from "./types.mjs"

/** Код отказа загрузки. Отказ — определённый исход, а не молчаливое «не вышло». */
export const ОТКАЗ_ЗАМЕНЫ = "FLANG_HOTSWAP_REFUSED"

/**
 * Принять новый обработчик под работающим процессом.
 *
 * @param {object} программа AST работающей программы
 * @param {string} процесс имя процесса, чей обработчик меняется
 * @param {string} исходник текст модуля с новыми объявлениями функций
 * @param {{витков?: number, файл?: string}} условия
 *   `витков` — граница, в которую новый обработчик обязан уложиться при ЛЮБОМ
 *   размере входа. Названа — значит требуется ПОСТОЯННАЯ оценка не больше этого
 *   числа: оценка, растущая с размером сообщения, границы не даёт, потому что
 *   размер сообщения не ограничен ничем.
 * @returns {{принято: boolean, программа: object|null, диагностики: Array, оценка: number[]|null}}
 */
export function заменитьОбработчик(программа, процесс, исходник, условия = {}) {
  const узел = (программа?.processes ?? []).find((п) => п?.name === процесс)
  if (узел === undefined) {
    return отказ(`процесса «${процесс}» в программе нет: менять нечего`)
  }

  let новые
  try {
    новые = parse(исходник, условия.файл ?? "замена.flang")
  } catch (ошибка) {
    return отказ(`новый обработчик не разобран: ${ошибка?.message ?? String(ошибка)}`)
  }

  /* Функции с теми же именами ЗАМЕНЯЮТСЯ, остальные добавляются. Порядок
     сохраняется — не для красоты: от порядка функций зависит порядок
     диагностик, а диагностика, которая переставляется от замены к замене, не
     сверяется ни с чем. */
  const поИмени = new Map((новые.functions ?? []).map((фн) => [фн.name, фн]))
  const функции = (программа.functions ?? []).map((фн) => поИмени.get(фн.name) ?? фн)
  for (const фн of новые.functions ?? []) {
    if (!функции.some((старая) => старая.name === фн.name)) функции.push(фн)
  }
  const кандидат = { ...программа, functions: функции }

  /* Признак «тотальная» проверяется ПЕРВЫМ, до типов, и порядок здесь не
     вкусовщина. Проверка типов тоже отвергает нетотальный обработчик без
     запаса (`FLANG_HANDLER_NOT_TOTAL`), но говорит про программу: «объявите
     запас». Загрузке нужно сказать другое и про другое — «доказательства нет,
     поэтому не принято», — а два разных ответа на один вопрос обязан давать
     тот, кто ближе к делу. */
  const обязанБытьТотальным = узел.budget === null || узел.budget === undefined
  const новый = функции.find((фн) => фн.name === узел.handler)
  if (новый === undefined) {
    return отказ(`в замене нет обработчика «${узел.handler}»`)
  }
  if (обязанБытьТотальным && новый.total !== true) {
    return отказ(
      `обработчик «${узел.handler}» приехал без признака «тотальная», а процесс «${процесс}» ` +
        `запаса витков не объявлял: принять нечего — доказательства нет`,
    )
  }

  const типы = checkTypes(кандидат)
  const диагностикиТипов = (типы?.diagnostics ?? []).filter((д) => д.severity !== "warning")
  if (диагностикиТипов.length > 0) {
    return отказ(`новый обработчик не прошёл проверку типов`, диагностикиТипов)
  }

  /* Тотальность требуется тогда же, когда её требует компилятор: у процесса без
     объявленного запаса витков. С запасом обработчик имеет право не завершаться
     — исчерпание запаса определённый исход, и надзор про него знает. */
  if (обязанБытьТотальным) {
    const тотальность = checkTotality(кандидат)
    if (!тотальность.ok) {
      return отказ(
        `тотальность обработчика «${узел.handler}» не доказана`,
        тотальность.diagnostics,
      )
    }
  }

  const оценка = оценитьВитки(кандидат).get(узел.handler)
  if (условия.витков !== undefined) {
    if (оценка === undefined || оценка.оценка === null) {
      return отказ(
        `оценки витков у обработчика «${узел.handler}» нет (${оценка?.причина ?? "функция не найдена"}), ` +
          `а названа граница в ${условия.витков} витков`,
        [],
        null,
      )
    }
    if (степень(оценка.оценка) > 0) {
      return отказ(
        `витков у обработчика «${узел.handler}» ${текстОценки(оценка.оценка)} — оценка растёт с размером ` +
          `сообщения, а размер сообщения не ограничен ничем: в ${условия.витков} витков это не укладывается`,
        [],
        оценка.оценка,
      )
    }
    const сколько = значение(оценка.оценка, 0)
    if (сколько > условия.витков) {
      return отказ(
        `витков у обработчика «${узел.handler}» ${сколько}, а названа граница в ${условия.витков}`,
        [],
        оценка.оценка,
      )
    }
  }

  return {
    принято: true,
    программа: кандидат,
    диагностики: [],
    оценка: оценка?.оценка ?? null,
  }
}

function отказ(сообщение, диагностики = [], оценка = null) {
  return {
    принято: false,
    программа: null,
    диагностики: [
      { code: ОТКАЗ_ЗАМЕНЫ, message: сообщение, severity: "error", span: null },
      ...диагностики,
    ],
    оценка,
  }
}
