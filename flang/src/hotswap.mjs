/**
 * hotswap.mjs — горячая замена обработчика ПОД ДОКАЗАТЕЛЬСТВО.
 *
 * Шаг Е1 карты (`flang/conc/RESILIENCE.md`), и он зависит от В3 не по формату
 * зависимостей, а по существу: без оценки витков доказывать было бы нечего,
 * кроме тотальности, а тотальности для этого мало.
 *
 * ── Чем это отличается от загрузки модуля в BEAM ───────────────────────────
 *
 * BEAM грузит что угодно. `code:load_binary/3` примет модуль, чей
 * `handle_call/3` уходит в вечный цикл, и процесс повиснет намертво — снимется
 * только `exit/2`. Это не недосмотр, а следствие: доказательства завершения у
 * BEAM нет ни для старого кода, ни для нового, значит и требовать его от нового
 * не с чем.
 *
 * Здесь наоборот. Дефункционализация, проверка тотальности и оценка витков —
 * ЦЕЛЬНОПРОГРАММНЫЕ: они смотрят на всю программу разом. Значит заменить
 * обработчик под работающим процессом — это переспросить доказательство, а не
 * подменить указатель. Дороже, чем в BEAM, и строже, чем в BEAM, и оба слова
 * здесь буквальны.
 *
 * ── Что именно требуется от нового обработчика ─────────────────────────────
 *
 * Четыре условия, и каждое отвергает своё:
 *
 *   1. РАЗБИРАЕТСЯ и СВЯЗЫВАЕТСЯ — иначе замены нет вовсе;
 *   2. ПРОХОДИТ ПРОВЕРКУ ТИПОВ вместе со всей остальной программой. Именно
 *      вместе: обработчик обязан принимать то же состояние и то же сообщение,
 *      что объявлены у процесса, и вернуть тот же отклик;
 *   3. ТОТАЛЕН — если процесс не объявил запаса витков. Тут проверка ровно та
 *      же, что на этапе компиляции, и другой быть не может: доказательство,
 *      которое в рантайме слабее, чем в компиляторе, — это не доказательство;
 *   4. ОГРАНИЧЕН, если названа граница (`витков`). Это и есть вклад В3, и без
 *      него пункт 3 оставлял бы дверь открытой: тотальная `фиб` тотальна,
 *      проверку тотальности проходит, и вешает процесс на миллион витков ничуть
 *      не хуже вечного цикла в BEAM. Разница только в том, что она когда-нибудь
 *      кончится, а для кванта это разница без различия.
 *
 * ── ПЕРЕНОС СОСТОЯНИЯ, и чем он строже и дешевле `code_change/3` ───────────
 *
 * Старый вид состояния и новый — разные типы, и решать, что делать с уже
 * накопленным, догадкой нельзя. В OTP это `code_change(OldVsn, State, Extra)`:
 * функция в новом модуле, которую зовёт `sys:change_code` на ПРИОСТАНОВЛЕННОМ
 * процессе. Проверяет её не проверяет никто: тип у неё `term() -> term()`, то
 * есть типа нет вовсе; завершаться она не обязана, и если не завершится —
 * процесс останется висеть приостановленным, а надзор про это не узнает, потому
 * что процесс не умер; вернёт не тот вид — беда всплывёт позже и в чужом месте.
 *
 * Здесь тот же приём ложится на язык с объявленными типами, и от этого меняется
 * в четырёх местах:
 *
 *   1. У переноса ЕСТЬ ТИП, и он сверяется с обоими объявлениями сразу: принять
 *      обязан старый вид состояния, вернуть — новый. Оба объявления в кандидате
 *      есть, потому что замена НЕ переобъявляет существующие типы, а добавляет
 *      новые. Это и есть ответ на «тип старого состояния после замены уже не
 *      объявлен нигде»: объявлен, в работающей программе, и она никуда не делась;
 *   2. перенос обязан быть ТОТАЛЕН — той же проверкой, что обработчик;
 *   3. перенос идёт под СВОЮ границу (`витковПереноса`), и вот здесь строгость
 *      выходит ДЕШЕВЛЕ. Обработчику нужна ПОСТОЯННАЯ оценка, потому что размер
 *      сообщения не ограничен ничем. Перенос зовётся РОВНО ОДИН РАЗ и ровно на
 *      том состоянии, которое лежит перед нами, — а его структурный размер это
 *      число. Значит растущая оценка не помеха: в неё подставляется этот размер,
 *      и сверяется с границей не форма многочлена, а посчитанный виток.
 *      Границы две, а не одна, и это тоже не мелочь: `витков` — цена КАЖДОГО
 *      сообщения, её сводят с квантом; `витковПереноса` — разовая цена одного
 *      переезда. Одним числом их называть значило бы либо запретить дорогой
 *      разовый переезд, либо разрешить дорогой обработчик;
 *   4. замена АТОМАРНА. Не сошлось что-нибудь — не применено ничего, работает
 *      старый вид со старым состоянием. В OTP неудавшийся `code_change` оставляет
 *      процесс приостановленным, и разбирается с этим release handler, то есть
 *      слой выше и снаружи.
 *
 * ── Чего здесь НЕТ, и это граница, а не заготовка ──────────────────────────
 *
 * Замена не умеет того, что умеет BEAM: держать две версии модуля одновременно.
 * Это устройство таблицы кода 1986 года, из которого «две версии» и следуют; нам
 * нужна замена, а не именно этот её механизм.
 *
 * Здесь стояло, почему она не нужна: «сообщение у нас обрабатывается ровно одним
 * видом кода целиком». Это неправда, и опровергнута она счётом. Барьер стоит
 * между ПРОБЕГАМИ, и целым он держит пробег, а не сообщение: `продолжить` и
 * `отложить` возвращают сообщение в ящик УЖЕ ПОСЛЕ того, как состояние из
 * отклика зафиксировано, значит одно сообщение растягивается на несколько
 * пробегов, а замена ложится между ними. Одно сообщение, `продолжить`, замена
 * после двух пробегов: 1 + 1 + 100 = 102 — вклад обоих видов
 * (`flang/test/hotswap.test.mjs`).
 *
 * Довод, который остался, слабее прежнего и держится: две версии не нужны,
 * потому что ПРОБЕГ цел. Начавшийся пробег не обязан дочитываться в старом виде
 * — он ничего не менял, его можно бросить и повторить; в BEAM `handle_call`
 * обязан, потому что правит свою кучу по ходу дела. А вот начатое СООБЩЕНИЕ мы
 * делим между видами, и в этом месте BEAM умеет то, чего не умеем мы. Планировщик
 * такой случай называет: `наСередине` в отчёте о замене (`conc.mjs`).
 */

