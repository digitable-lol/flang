/**
 * Идемпотентность: `х∘х = х` и `ф(ф(х)) = ф(х)`.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Программа с функцией «Вычесть» и пятью нарушенными свойствами проходила
 * `flang check --proof` со строкой «законов на сетке: 0 (значений в сетках 0);
 * на веру: 0» и разделом «нет объявленных законов». Сказать «эта операция
 * повторяется безопасно» язык не умел вовсе — ни объявить, ни проверить.
 *
 * ── Ради чего это свойство, а не ради полноты списка ────────────────────────
 *
 * Идемпотентность — это РАЗРЕШЕНИЕ БЕЗОПАСНО ПОВТОРИТЬ, и в отказоустойчивости
 * оно решает конкретный, названный в этом дереве вопрос. `conc.mjs` держит
 * отметку `наСередине`: в ящике процесса лежало сообщение, которое старый вид
 * обработчика уже трогал, — и barrier горячей замены НЕ обещает, что доиграть
 * его новым видом безопасно. Обещать было нечем: язык не знал, идемпотентен ли
 * обработчик. Теперь знает, и отметка `повторБезопасен` стоит рядом.
 *
 * То же и у надзора: «упал — перезапустили» безопасно ровно тогда, когда
 * повторное применение ничего не меняет.
 *
 * ── Две формы, и обе настоящие ──────────────────────────────────────────────
 *
 *   два входа   `х ∘ х = х`        — операция, соединяющая значение с самим
 *                                    собой, возвращает его же. Так устроены
 *                                    объединение множеств, максимум, «или»;
 *   один вход   `ф(ф(х)) = ф(х)`   — второе применение ничего не меняет. Так
 *                                    устроены нормализация, обрезка, «применить
 *                                    оплату к заказу».
 *
 * Различает их ЧИСЛО ВХОДОВ объявленной функции, и ни одна не угадывается: обе
 * написаны автором, а `types.mjs` сверил, что вход у функции носителя и что
 * результат из носителя не выводит.
 *
 * ── Что здесь ПРОВЕРЯЕТСЯ, а не доказывается ────────────────────────────────
 *
 * Закон. Устройство доказано раньше и в другом месте (`types.mjs`, сличением
 * объявлений). Здесь — равенство вычислений на всех значениях носителя, а оно
 * неразрешимо: значит конечная сетка, и ведомость обязана называть её размер
 * строкой, оканчивающейся словами «Это не доказательство».
 */
import { valuesEqual } from "./builtins.mjs"
import { ПРЕДЕЛ_СЕТКИ, объявления, основа, покажи, пусто } from "./svoystva.mjs"

export { ПРЕДЕЛ_СЕТКИ }

/** Имя свойства — то самое, что автор пишет в ёлочках. */
export const ИМЯ = "идемпотентность"

/**
 * Проверка идемпотентности всех операций, её объявивших.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object>,
 *   assumed: Array<object>, permits: Array<object> }}
 */
export function checkIdempotence(программа, пределы = {}) {
  const узлы = объявления(программа, ИМЯ)
  const итог = пусто()
  if (узлы.length === 0) return итог

  const { найти, звать, сетка } = основа(программа, пределы)

  for (const узел of узлы) {
    const функция = найти(узел.operation)
    const входов = (функция?.params ?? []).length
    if (функция === undefined || (входов !== 1 && входов !== 2)) {
      /* Про негодное устройство уже сказала проверка типов; повторять её
         словами здесь значило бы дать автору чинить одну беду по двум
         сообщениям. Но и молчать нельзя: объявление, о котором отчёт молчит,
         читается как проверенное. */
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation ?? null,
        why: "устройство операции не сошлось: об этом сказала проверка типов",
      })
      continue
    }

    const значения = сетка([узел.operation])
    if (значения.length === 0) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation,
        why: `у «${узел.operation}» нет примеров: сетка пуста, повторять было не на чем`,
      })
      continue
    }

    const доБед = итог.diagnostics.length
    let оборвано = null
    let точек = 0
    for (const х of значения) {
      точек += 1
      /* Два входа — `х ∘ х`; один вход — `ф(ф(х))` против `ф(х)`. Во втором
         случае сравнивается НЕ с «х»: `ф` не обязана быть тождеством, она
         обязана не менять уже своего результата. */
      const первое = входов === 2 ? звать(узел.operation, х, х) : звать(узел.operation, х)
      if (первое.ошибка) {
        оборвано = `«${узел.operation}» отказала на значении сетки: ${первое.ошибка}`
        break
      }
      const ожидалось = входов === 2 ? х : первое.значение
      const второе = входов === 2 ? первое : звать(узел.operation, первое.значение)
      if (второе.ошибка) {
        оборвано = `«${узел.operation}» отказала на своём же результате: ${второе.ошибка}`
        break
      }
      if (valuesEqual(второе.значение, ожидалось)) continue
      итог.diagnostics.push({
        code: "FLANG_NOT_IDEMPOTENT",
        message: входов === 2
          ? `свойство «${ИМЯ}»: «${узел.operation}» не идемпотентна: на ${покажи(х)} и ${покажи(х)} ` +
            `вышло ${покажи(второе.значение)}, а обязано было выйти ${покажи(х)} — ` +
            `повторить такую операцию нельзя, второй раз она меняет результат`
          : `свойство «${ИМЯ}»: «${узел.operation}» не идемпотентна: на ${покажи(х)} она дала ` +
            `${покажи(первое.значение)}, а на своём же результате — ${покажи(второе.значение)} — ` +
            `повторить такую функцию нельзя, второй прогон меняет результат`,
        severity: "error",
        span: узел.span,
      })
      break
    }

    const нарушений = итог.diagnostics.length - доБед
    итог.checked.push({
      property: ИМЯ,
      subject: узел.operation,
      values: значения.length,
      points: точек,
      arity: входов,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
    if (нарушений > 0 || оборвано !== null) continue
    итог.permits.push({
      permit: "повторить",
      property: ИМЯ,
      subject: узел.operation,
      says: `повторить «${узел.operation}» безопасно: второе применение результата не меняет — ` +
        `сообщение можно переслать ещё раз, обработчик перезапустить`,
    })
  }

  return итог
}

/**
 * Разрешено ли повторить названную функцию — вопрос одной строкой.
 *
 * Ответ ЧЕСТНЫЙ в обе стороны: `false` означает «не разрешено», а не
 * «нарушено», — и не объявленное свойство, и нарушенное, и посчитанное на
 * пустой сетке дают одно и то же `false`. Разрешение выдаётся, а не
 * подразумевается.
 *
 * Своего словаря свойств здесь нет: ответ берётся из того же `permits`, который
 * печатает ведомость. Второй источник разошёлся бы с первым молча, и тогда
 * спрашивающий разрешал бы то, о чём отчёт говорит «нарушено».
 *
 * ── ЧЕГО ЭТА ФУНКЦИЯ СЕГОДНЯ НЕ ДЕЛАЕТ, и это граница, а не заготовка ───────
 *
 * Напрашивался ей один вызов — барьер горячей замены (`conc.mjs`, отметка
 * `наСередине`): сообщение, которое старый вид обработчика уже трогал, можно
 * переиграть новым видом целиком ровно тогда, когда обработчик идемпотентен.
 * Спросить не вышло, и причина не в связке модулей, а в типах: обработчик
 * процесса возвращает НЕ своё состояние, а «Отклик» — запись с состоянием и
 * списком действий. Значит `ф(ф(х))` у него не собирается вовсе: результат не
 * годится ему же на вход. Ни один обработчик не может объявить это свойство
 * честно, и вызов, всегда отвечающий `false`, был бы полем-обманкой в отчёте о
 * замене — хуже отсутствующего, потому что читался бы как измерение.
 *
 * Что для такого вызова нужно на самом деле — ТРЕТЬЯ форма закона,
 * `ф(ф(с, м), м) = ф(с, м)`, идемпотентность по второму входу. Она здесь не
 * сделана и не изображена; в `flang/cat/ZAKONY.md` она названа как недостача.
 *
 * @param {object} программа AST flang
 * @param {string} имя имя функции
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {boolean}
 */
export function повторБезопасен(программа, имя, пределы = {}) {
  if (typeof имя !== "string" || имя === "") return false
  if (!Array.isArray(программа?.properties)) return false
  if (!программа.properties.some((узел) => узел?.name === ИМЯ && узел?.operation === имя)) return false
  try {
    return checkIdempotence(программа, пределы).permits.some((запись) => запись.subject === имя)
  } catch {
    /* Отказ проверки — это не разрешение. Молчаливое `true` здесь стоило бы
       ровно того, ради чего свойство и заводилось. */
    return false
  }
}
