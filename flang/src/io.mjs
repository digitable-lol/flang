/**
 * План — объявление, а не значение: три строки, каждая называет уже объявленное.
 *
 * ```flang
 * план «Отчёт о ссылке»
 *   состояние «Ход»
 *   начинает с «Начать»
 *   обрабатывает «Дальше»
 * ```
 *
 * Ни одного нового слова, кроме `план`: `состояние`, `начинает с` и
 * `обрабатывает` уже ключевые — теми же тремя словами объявляется процесс. Это
 * не экономия ради экономии, а правило: каждое новое ключевое слово запрещает
 * одноимённую переменную во ВСЕХ файлах репозитория. Цену этому уже платили —
 * см. «символы» в `lexer.mjs`.
 *
 * Живёт проверка здесь, а не в `types.mjs`, ровно по одной причине: в
 * `types.mjs` одновременно работают несколько независимых правок, и добавлять
 * туда шестьдесят строк значило бы гарантировать конфликт. Наружу торчит
 * функция от `(program, ctx)`, и в `checkTypes` от неё остаётся одна строка.
 */
export function checkPlans(program, ctx) {
  const планы = Array.isArray(program?.plans) ? program.plans : []
  if (планы.length === 0) return

  const видели = new Set()
  for (const план of планы) {
    if (typeof план?.name !== "string" || план.name === "") {
      ctx.report("FLANG_PLAN", "план требует имени", план)
      continue
    }
    if (видели.has(план.name)) {
      ctx.report("FLANG_PLAN", `план «${план.name}» объявлен дважды`, план)
      continue
    }
    видели.add(план.name)

    /* Словарь обязан быть на месте. Парсер приписывает его всякой программе с
       планом, поэтому пропажа означает одно из двух: имя занято собственным
       объявлением программы либо AST собран не парсером. Сказать об этом прямо
       дешевле, чем оставить читателю каскад «неизвестный тип». */
    const пропало = IO_TYPES.filter((тип) => !ctx.sums.has(тип.name))
    if (пропало.length > 0) {
      ctx.report(
        "FLANG_PLAN",
        `план «${план.name}» не собран: в программе нет сумм ${пропало.map((т) => `«${т.name}»`).join(", ")} — ` +
          "это словарь ввода-вывода, и его имена заняты собственными объявлениями",
        план,
      )
      continue
    }

    const состояние = состояниеПлана(план, ctx)
    проверитьНачало(план, состояние, ctx)
    проверитьШаг(план, состояние, ctx)
  }
}

/** Тип состояния плана: объявленная запись, сумма или псевдоним. */
function состояниеПлана(план, ctx) {
  const имя = план.state
  if (typeof имя !== "string" || имя === "") {
    ctx.report("FLANG_PLAN", `план «${план.name}» не называет тип состояния`, план)
    return null
  }
  if (ctx.records.has(имя)) return { kind: "record", name: имя }
  if (ctx.sums.has(имя)) return { kind: "sum", name: имя }
  if (ctx.aliases.has(имя)) return { kind: "alias", name: имя }
  ctx.report("FLANG_PLAN", `состояние плана «${план.name}» — неизвестный тип «${имя}»`, план)
  return null
}

/**
 * Тип, которым обязано быть поле `потом` варианта «Сделать» — то есть тип
 * состояния плана.
 *
 * Зачем это отдельно от `состояниеПлана`. Поле `потом` объявлено джокером
 * (`любое`), потому что параметрической суммы у словаря ввода-вывода нет, и до
 * этой функции его не сверял НИКТО: `check` принимал программу, положившую в
 * `потом` значение чужого типа, а падала она у хозяина, на первом же обороте
 * цикла — `разбор не покрывает значение …`. Улика записана
 * `flang/test/io.test.mjs` двумя случаями: чужой вариант и голая строка.
 *
 * Проверять тут ЕСТЬ чем, и это главное: тип состояния назван самим автором в
 * строке `состояние «Ход»`, а `проверитьШаг` уже сверяет с ним первый параметр
 * функции шага. Значит `потом` и первый параметр обязаны быть одним типом —
 * иначе хозяин подаёт в шаг то, чего шаг не объявлял. Сверка делается ровно тем
 * же приёмом, каким `types.mjs` сверяет груз действия «отправить» с
 * объявленным `принимает` адресата: словарный джокер уступает место типу,
 * известному из объявления.
 *
 * Возвращает `null` — «сверять нечем», и тогда поведение прежнее:
 *
 *   • планов в программе нет вовсе. Тогда и цикла хозяина нет: `flang io`
 *     требует имя плана, и без плана `«Сделать»` никуда не едет;
 *   • планы называют РАЗНЫЕ состояния. Тогда одного ожидания у поля нет, а
 *     выбрать из двух было бы произволом; чинится это не здесь, а параметром
 *     у самого `«Продолжение»`;
 *   • состояние — неизвестный тип или псевдоним. Про неизвестный `checkPlans`
 *     уже сказал, второй раз незачем. Псевдоним же `состояниеПлана` намеренно
 *     сверяет ПО ИМЕНИ, а не по структуре (см. `сверитьИмяТипа`), и подсунуть
 *     это имя структурному `sameType` значило бы сравнить его с развёрнутым
 *     типом и получить ложный отказ.
 *
 * Печать не тронута: словарь остаётся тем же, что был, — джокер в поле никуда
 * не девается, добавилась только сверка. Поэтому восемь целей печатают ровно те
 * же байты, что до правки.
 */
/**
 * Один ли план в программе.
 *
 * Нужно второму джокеру — полю `значение` варианта «Конец работы». Тип
 * результата плана НЕ ОБЪЯВЛЕН нигде: у `план` есть `состояние`, `начинает с` и
 * `обрабатывает`, и строки `возвращает` у него нет. Значит сверить `значение` с
 * объявлением, как сверяется `потом`, нельзя — объявления не существует.
 *
 * Но одно утверждение проверить можно и без него: у плана ОДИН результат, а
 * значит все «Конец работы» одной программы обязаны нести значение одного типа.
 * Программа, отдающая число по одной ветке и строку по другой, сообщает хозяину
 * то, чего он не сможет разобрать, — и это ошибка независимо от того, объявлен
 * тип или нет. Проверка слабее объявления (первое встреченное значение
 * становится образцом вместо названного автором), но сильнее молчания.
 *
 * Требуется ровно один план: при двух планах у ветки нет одного правильного
 * ответа — «Конец работы» разных планов законно разного типа, а какой шаг чей,
 * связывание не знает (`план` берётся только у входного файла, шаги — общие).
 * Тогда сверка отключается целиком, и это записано уликой в тестах.
 */
export function planResultIsShared(program) {
  return (Array.isArray(program?.plans) ? program.plans : []).length === 1
}

export function planStateType(program, ctx) {
  const планы = Array.isArray(program?.plans) ? program.plans : []
  if (планы.length === 0) return null

  let общее = null
  for (const план of планы) {
    const имя = план?.state
    if (typeof имя !== "string" || имя === "") return null
    if (общее !== null && общее !== имя) return null
    общее = имя
  }
  if (общее === null) return null
  if (ctx.records.has(общее)) return { kind: "record", name: общее }
  if (ctx.sums.has(общее)) return { kind: "sum", name: общее }
  return null
}

function проверитьНачало(план, состояние, ctx) {
  const имя = план.initial
  if (typeof имя !== "string" || имя === "") {
    ctx.report("FLANG_PLAN", `план «${план.name}» не называет начальное состояние`, план)
    return
  }
  const signature = ctx.signatures.get(имя)
  if (signature === undefined) {
    ctx.report("FLANG_PLAN", `начальное состояние плана «${план.name}» — неизвестная функция «${имя}»`, план)
    return
  }
  if (signature.params.length !== 0) {
    ctx.report(
      "FLANG_PLAN",
      `начальное состояние плана «${план.name}» — функция «${имя}» с ${signature.params.length} аргум., ` +
        "а обязана быть без аргументов",
      план,
    )
  }
  сверитьИмяТипа(signature.returns, состояние, `функция «${имя}» плана «${план.name}» возвращает`, план, ctx)
}

/**
 * Шаг плана: `(состояние, «Отклик») → «Продолжение»`.
 *
 * Ровно та же форма, что у обработчика процесса, и это не совпадение: и там и
 * здесь чистая функция получает «где мы были» и «что случилось», а возвращает
 * «что делать». Одна форма на две модели значит, что и хозяин ввода-вывода, и
 * планировщик конкурентности — это один и тот же цикл с разным набором
 * действий.
 */
function проверитьШаг(план, состояние, ctx) {
  const имя = план.handler
  if (typeof имя !== "string" || имя === "") {
    ctx.report("FLANG_PLAN", `план «${план.name}» не называет функцию шага`, план)
    return
  }
  const signature = ctx.signatures.get(имя)
  if (signature === undefined) {
    ctx.report("FLANG_PLAN", `шаг плана «${план.name}» — неизвестная функция «${имя}»`, план)
    return
  }
  if (signature.params.length !== 2) {
    ctx.report(
      "FLANG_PLAN",
      `шаг плана «${план.name}» — функция «${имя}» с ${signature.params.length} аргум., ` +
        "а обязана принимать состояние и отклик",
      план,
    )
    return
  }
  сверитьИмяТипа(signature.params[0].type, состояние, `первый аргумент функции «${имя}»`, план, ctx)
  сверитьИмяТипа(
    signature.params[1].type,
    { kind: "sum", name: RESPONSE_TYPE_NAME },
    `второй аргумент функции «${имя}»`,
    план,
    ctx,
  )
  сверитьИмяТипа(
    signature.returns,
    { kind: "sum", name: CONTINUATION_TYPE_NAME },
    `функция «${имя}» плана «${план.name}» возвращает`,
    план,
    ctx,
  )
}

/**
 * Сверка по ИМЕНИ типа, а не по структуре.
 *
 * Структурное сравнение здесь было бы неверным: псевдоним разворачивается в
 * список или скаляр, и «состояние плана» перестало бы отличаться от любого
 * другого списка того же элемента. Плану нужно совпадение объявлений, а не
 * совпадение представлений.
 */
function сверитьИмяТипа(получено, ожидается, что, при, ctx) {
  if (ожидается === null) return
  if (получено?.kind === "unknown") return
  if (получено?.name === ожидается.name) return
  ctx.report(
    "FLANG_PLAN",
    `${что} «${получено?.name ?? типОдним(получено)}», а ожидался «${ожидается.name}»`,
    при,
  )
}

function типОдним(тип) {
  if (тип === null || тип === undefined) return "ничего"
  if (тип.kind === "list") return "список"
  return тип.kind
}

