/**
 * Признак «план сдался сам» на брошенной беде.
 *
 * Символ, а не строковое поле: беда уезжает в `errorResult` и печатается JSON-ом,
 * а символьный ключ туда не попадает — признак виден коду и не виден выводу.
 * Один на модуль, читается только через `сдалсяСам`, ставится только в
 * `runPlan`.
 */
const СДАЛСЯ_САМ = Symbol("план сдался сам")

/**
 * Беда — это вердикт программы, а не поломка исполнителя?
 *
 * Нужно ровно одному вызывающему — `commandIo`, — и ровно за тем, ради чего
 * сторожу спек нужен код выхода: «нашёл беду» обязано отличаться от «сам
 * сломался». Первое — обычная работа, на которой CI краснеет по делу; второе —
 * повод чинить инструмент, а не предмет.
 */
export function сдалсяСам(ошибка) {
  return ошибка !== null && typeof ошибка === "object" && ошибка[СДАЛСЯ_САМ] === true
}

/** Отклик «хозяин не смог»: код и текст, а не исключение. */
export function сбой(код, сообщение) {
  return variant(RESPONSE_FAILURE, { код: String(код), сообщение: String(сообщение) })
}

/**
 * Поддельный хозяин: список заготовленных откликов по порядку.
 *
 * Нужен и тестам, и примерам в документации, поэтому живёт здесь, а не в
 * `test/`. Отклика не хватило — это `«Сбой»`, а не исключение: программа
 * обязана уметь встретить неудачу поручения, и поддельный хозяин не должен
 * прятать этот путь от проверки.
 */
export function хозяинПоСписку(отклики) {
  const очередь = [...отклики]
  return () => {
    if (очередь.length === 0) return сбой("FLANG_IO_SCRIPT", "у поддельного хозяина кончились отклики")
    return reifyValue(очередь.shift())
  }
}
