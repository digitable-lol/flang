/** Сколько поручений исполнитель выдаёт, прежде чем сдаться. */
const DEFAULT_MAX_ORDERS = 10_000

/**
 * Прогнать план, отдавая поручения наружу.
 *
 * `исполнить` — функция хозяина: поручение (значение `«Поручение»`) → отклик
 * (значение `«Отклик»`); может быть асинхронной. Ни одного эффекта эта функция
 * не делает сама — в этом и смысл: подставив список заготовленных откликов,
 * тот же план прогоняется БЕЗ файлов и без сети, и сверять есть что —
 * `журнал` содержит все выданные поручения по порядку.
 *
 * @returns {Promise<{значение: unknown, журнал: {поручение: object, отклик: object}[], поручений: number}>}
 */
export async function runPlan(program, planName, исполнить, options = {}) {
  const план = findPlan(program, planName)
  if (typeof исполнить !== "function") {
    throw flangError("FLANG_IO", "исполнителю плана нужна функция «выполнить поручение»", план.span)
  }
  const предел = options.maxOrders ?? DEFAULT_MAX_ORDERS
  const runtime = createRuntime(program, {
    maxSteps: options.maxSteps,
    maxDepth: options.maxDepth,
  })
  const сверитьВход = входШага(program, план)

  let состояние = runtime.call(план.initial, [])
  let отклик = variant(RESPONSE_NOTHING, {})
  const журнал = []

  for (;;) {
    сверитьВход(состояние, отклик)
    const продолжение = runtime.call(план.handler, [состояние, отклик])
    if (!isVariant(продолжение) || IO_VARIANT_OWNER.get(продолжение.variant) !== CONTINUATION_TYPE_NAME) {
      throw flangError(
        "FLANG_IO",
        `шаг «${план.handler}» плана «${план.name}» вернул не «${CONTINUATION_TYPE_NAME}»`,
        план.span,
      )
    }

    if (продолжение.variant === CONTINUE_DONE) {
      return { значение: продолжение.fields["значение"] ?? null, журнал, поручений: журнал.length }
    }
    if (продолжение.variant === CONTINUE_GIVE_UP) {
      const код = продолжение.fields["код"]
      const сообщение = продолжение.fields["сообщение"]
      /* Код берётся у программы, а не назначается здесь: программа сдаётся
         сама, и она же лучше знает, чем именно. Пустой код заменяется общим —
         диагностика без кода не годится машине. */
      const беда = flangError(
        typeof код === "string" && код !== "" ? код : "FLANG_IO_FAILED",
        typeof сообщение === "string" ? сообщение : `план «${план.name}» отказался продолжать`,
        план.span,
      )
      /* Метка «сдался сам» — единственное, чем `«Провал»` отличается снаружи от
         поломки исполнителя, и ставится она ЗДЕСЬ, потому что только здесь
         известно, что решение приняла программа. Читает её `commandIo`
         (`flang/bin/flang.mjs`) и превращает в код выхода: 1 — программа нашла
         беду, 3 — сломался инструмент. Кодом отказа это не различить: у
         `«Провал»` он СВОЙ, программа пишет туда что хочет, и `FLANG_IO_DENIED`
         из чужого отклика приезжает сюда наравне с `МОЯ_СПЕКА_ПЛОХА`. */
      беда[СДАЛСЯ_САМ] = true
      throw беда
    }

    if (журнал.length >= предел) {
      throw flangError(
        "FLANG_IO_LIMIT",
        `план «${план.name}» исчерпал предел поручений (${предел})`,
        план.span,
      )
    }

    const поручение = продолжение.fields["поручение"]
    if (!isVariant(поручение) || !ORDER_VARIANTS.has(поручение.variant)) {
      throw flangError(
        "FLANG_IO",
        `план «${план.name}» просит выполнить не поручение`,
        план.span,
      )
    }
    состояние = продолжение.fields["потом"] ?? null
    отклик = проверитьОтклик(await исполнить(поручение), поручение, план)
    журнал.push({ поручение, отклик })
  }
}

/**
 * ГРАНИЦА ВХОДА цикла поручений: значения, которые приходят в функцию шага.
 *
 * Шаг плана — обычная функция с объявленными типами (`принимает ход: «Ход»,
 * отклик: «Отклик»`), и ОБА её аргумента цикл берёт не из программы:
 *
 *   `отклик` приносит ХОЗЯИН — среда, в которую напечатан модуль. Хозяев
 *      столько же, сколько целей печати, плюс всякий, кто встроит `runPlan` в
 *      свою программу; компилятор не видел ни одного из них.
 *   `состояние` приезжает полем `потом`, а тип этого поля — джокер `любое`:
 *      параметрической суммы у словаря нет. Объявленный тип у состояния всё же
 *      есть — строка `состояние «Ход»`, — и `types.mjs` сверяет с ней ВЫРАЖЕНИЕ
 *      в исходнике; значение на витке не сверял никто. Там, где сверять
 *      выражение нечем (планов в программе два и состояния у них разные),
 *      объявление остаётся единственной защитой, и она была пустой.
 *
 * До этой сверки хозяину верили на слово наполовину: `проверитьОтклик`
 * спрашивал «это вообще «Отклик»?» и на имени варианта останавливался. Цена
 * замерена: хозяин, вернувший `«Отметка времени» с миллисекунды равным
 * "вчера"`, доводил план ДО КОНЦА, и результатом плана было `"мс: вчера"` — ни
 * одной диагностики, ложь про тип в ответе. С `миллисекунды` равным `ничто`
 * выходило `"мс: ничто"`: `к строке` не спотыкается ни на том, ни на другом.
 *
 * Проверка — та же самая, что у `--args`, у фактов и у примеров в исходнике
 * (`checkArguments` в types.mjs), и зовётся она ДО вызова шага. Внутри она
 * поймала бы ложь на той операции, которой не повезло первой («к строке» у
 * одного плана, «длина» у другого), то есть говорила бы о симптоме и только на
 * тех витках, до которых дошло исполнение.
 *
 * Чего она НЕ делает: не сужает набор откликов. Правильно устроенный, но не
 * тот вариант («Записано» там, где ждали «Отметку времени») — это работа
 * программы, её ветка `случай любое`, и граница обязана его пропустить. Иначе
 * вместе с ложью исчез бы путь «поручение не удалось», ради которого отказ
 * хозяина и сделан ОТКЛИКОМ, а не исключением.
 *
 * Таблицы типов строятся один раз на `runPlan`, а не на виток: витков по
 * умолчанию до десяти тысяч.
 */
function входШага(program, план) {
  const шаг = (program?.functions ?? []).find((функция) => функция?.name === план.handler)
  const имена = (шаг?.params ?? []).map((параметр) => параметр?.name)
  const сверить = проверкаВхода(program)
  return (состояние, отклик) => {
    /* Шаг не той формы — забота `checkPlans`: он про это уже сказал, и сверять
       набор значений со списком параметров, которого нет, нечем. */
    if (имена.length !== 2 || имена.some((имя) => typeof имя !== "string")) return
    const вход = сверить(план.handler, { [имена[0]]: состояние, [имена[1]]: отклик })
    if (вход.ok) return
    const беда = flangError(
      вход.diagnostics[0].code,
      `план «${план.name}»: на вход шага «${план.handler}» пришло значение не того типа ` +
        `(состояние — из поля «потом», отклик — от хозяина): ${вход.diagnostics[0].message}`,
      план.span,
    )
    /* Диагностики уезжают КАК ЕСТЬ: врать может и не один аргумент, а текст у
       них тот же, каким `flang check` говорит о значении примера. */
    беда.diagnostics = вход.diagnostics
    throw беда
  }
}

/** Хозяин обязан вернуть `«Отклик»`, и ничто другое откликом не считается. */
function проверитьОтклик(значение, поручение, план) {
  const отклик = reifyValue(значение)
  if (!isVariant(отклик) || IO_VARIANT_OWNER.get(отклик.variant) !== RESPONSE_TYPE_NAME) {
    throw flangError(
      "FLANG_IO",
      `хозяин вернул не «${RESPONSE_TYPE_NAME}» на поручение «${поручение.variant}» плана «${план.name}»`,
      план.span,
    )
  }
  return отклик
}

/** План по имени; без имени — единственный объявленный. */
export function findPlan(program, planName) {
  const планы = Array.isArray(program?.plans) ? program.plans : []
  if (планы.length === 0) {
    throw flangError("FLANG_UNKNOWN_PLAN", "в программе нет ни одного плана: исполнять нечего")
  }
  if (planName === undefined || planName === null || planName === "") {
    if (планы.length === 1) return планы[0]
    throw flangError(
      "FLANG_UNKNOWN_PLAN",
      `планов несколько (${планы.map((п) => `«${п.name}»`).join(", ")}) — назовите нужный`,
    )
  }
  const найден = планы.find((план) => план.name === planName)
  if (найден === undefined) {
    throw flangError("FLANG_UNKNOWN_PLAN", `не найден план «${planName}»`)
  }
  return найден
}

