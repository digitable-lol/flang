/**
 * Приписать словарь к программе. Идемпотентно, как `withActionType`.
 *
 * Тип, чьё имя (или имя любого его варианта) уже занято в программе, НЕ
 * приписывается: чужое объявление важнее нашего, и молча его переопределять
 * нельзя. Программа при этом получит обычную диагностику «неизвестный тип» или
 * «неизвестный вариант» — честный отказ вместо тихой подмены смысла.
 */
export function withIoTypes(program) {
  const types = Array.isArray(program?.types) ? program.types : []
  const занято = new Set()
  for (const тип of types) {
    if (typeof тип?.name === "string") занято.add(тип.name)
    for (const в of тип?.variants ?? []) if (typeof в?.name === "string") занято.add(в.name)
  }
  const добавить = IO_TYPES.filter(
    (тип) => !занято.has(тип.name) && !тип.variants.some((в) => занято.has(в.name)),
  )
  if (добавить.length === 0) return program
  return { ...program, types: [...types, ...добавить.map((тип) => structuredClone(тип))] }
}

