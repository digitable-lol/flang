/**
 * io.mjs — ввод-вывод flang: словарь поручений, план и его исполнитель.
 *
 * Контракт — `flang/cat/SPEC.md`, раздел «Эффекты и HTTP». Решение оттуда взято
 * дословно: **язык остаётся чистым**. `вариант «Прочитать файл» с путь равным
 * "имя.txt"` не читает файл — оно строит ОПИСАНИЕ действия, обычное значение
 * обычной суммы типов. Читает файл хозяин: среда, в которую напечатан модуль.
 *
 * Отсюда всё устройство ниже, и каждое решение объясняется этим одним словом.
 *
 * ── Почему словарь поручений встроенный, а не объявляемый ───────────────────
 *
 * Та же причина, что у словаря действий конкурентности (`conc.mjs`): поручение
 * — это КОНТРАКТ между языком и хозяином, а не выбор автора программы. Объявляй
 * его каждая программа заново — две программы назвали бы чтение файла
 * по-разному, и хозяину пришлось бы угадывать, какой из вариантов читать. А
 * хозяев восемь (по числу целей печати), и все они обязаны понимать одно и то
 * же.
 *
 * Отсюда же размер набора: девять поручений, и набор ЗАКРЫТ. Полнота здесь
 * дороже, чем кажется: каждое новое поручение обязан уметь ОТВЕТИТЬ КАЖДЫЙ
 * хозяин, включая тот, что напечатан в C. Ответить — не то же самое, что
 * исполнить: `«Сбой»` с кодом — законный ответ, и хозяин Node отвечает им на
 * оба экранных поручения (`FLANG_IO_NO_SCREEN`), потому что экрана у него нет.
 * Различать эти два слова пришлось ровно здесь: пока набор был про файлы, часы
 * и сеть, всякий хозяин умел всё, и разница не стоила ни строки.
 *
 * ── Почему поручений экрана ДВА, а не четыре ────────────────────────────────
 *
 * Считали четыре: «Показать», «Ждать событие», «Прочитать поле», «Отложить».
 * Осталось два, и оба сокращения — следствие того, что здесь машина
 * продолжений, а не поток:
 *
 *   «Прочитать поле» не нужно, потому что читать поле НЕКОГДА. Программа
 *      просыпается один раз на одно событие; значение поля, каким оно было в
 *      миг события, приносит сам отклик (`«Случилось»` с `значение`). Отдельное
 *      чтение спрашивало бы про поле ПОСЛЕ события — то есть про другой миг.
 *   «Отложить» не нужно, потому что машина продолжений ждёт РОВНО ОДНО. Два
 *      поручения «спи» и «жди» были бы двумя ожиданиями сразу, а выбрать из них
 *      первое сработавшее нечем: `«Продолжение»` несёт одно поручение. Поэтому
 *      срок сложен внутрь ожидания: `«Ждать событие» с срок равным 400` значит
 *      «разбуди на действии человека или через 400 мс, что раньше». Ноль —
 *      «жди без предела».
 *
 * То есть цена браузера в словаре — не «четыре плюс три», а **два плюс три**, и
 * сократило её устройство языка, а не экономия.
 * ── Почему каталог и процесс — поручения, а не удобство ─────────────────────
 *
 * Набор растёт не по желанию автора программы, а правкой этого файла.
 *
 * Здесь стояло «пять поручений», и довод к ним был такой: шестое
 * пришлось бы писать восемь раз, по числу целей печати. Довод СНЯТ замером, а
 * не мнением: в `flang/src/host/` сегодня ровно ОДИН файл — `node.mjs`. Семи
 * остальным целям не хватает не шестого поручения, а цикла хозяина и всех пяти
 * существующих; шестое стоит одного исполнителя, а не восьми
 * (`fspec/README.md`, раздел «Во что обойдётся унести сторожа на flang целиком»).
 *
 * «Перечислить каталог» и «Запустить процесс» заведены не «для полноты», а под
 * названную работу: сторож спек (`fspec/guard.mjs`) обязан НАЙТИ спеки в
 * каталоге, позвать на каждой компилятор и покраснеть в CI. Работ было три —
 * «Перечислить каталог», «Запустить процесс» и код выхода, — и порядок был
 * жёсткий: ни одна из трёх в одиночку не даёт ничего. Здесь лежат первые две;
 * третья — не поручение вовсе, и живёт она в `flang/bin/flang.mjs`
 * (`commandIo`), потому что код выхода принадлежит не языку, а команде.
 *
 * ── Почему это НЕ монада ────────────────────────────────────────────────────
 *
 * Монада ввода-вывода требует типа `Действие А`, параметрического по результату:
 * без параметра `соединение` не выразить — оно обязано принимать `Действие
 * (Действие А)`. Параметрических типов в языке пока нет (PLAN.md, пункт 1), и
 * ждать их здесь незачем: без ввода-вывода язык не умеет прочитать файл СЕГОДНЯ.
 *
 * Поэтому здесь не монада, а **машина продолжений**, и разница названа честно:
 *
 *   монада прячет продолжение в замыкании — «что делать с ответом»;
 *   здесь продолжение — ЗНАЧЕНИЕ объявленного автором типа.
 *
 * Это дефункционализация монады, сделанная руками: ровно тот приём, которым
 * PLAN.md собирается печатать функции первого класса. Когда параметрический
 * полиморфизм появится, форма `в монаде «Ввод-вывод»` будет разворачиваться
 * компилятором в эту же машину, а тип состояния станет генерируемым вместо
 * написанного. Машина останется — сменится тот, кто её пишет.
 *
 * Что из-за этого недоступно, перечислено в `flang/cat/SPEC.md`, раздел
 * «Ввод-вывод: что сделано и чем это не монада». Коротко: связывание не
 * является выражением, тип результата поручения не отслеживается (`«Отклик»` —
 * одна закрытая сумма на все поручения), а поле продолжения имеет тип-джокер.
 *
 * ── Что здесь есть и чего здесь нет ─────────────────────────────────────────
 *
 * Здесь: словарь, проверка объявления `план` и исполнитель, которому ВНЕШНИЙ
 * код передаёт функцию «выполнить поручение». Самих файлов, сокетов и часов
 * здесь нет ни одного — модуль детерминирован и не импортирует ничего из Node.
 * Настоящий хозяин живёт в `src/host/node.mjs`, а поддельный (список заранее
 * заготовленных откликов) пишется в три строки и живёт в тестах.
 *
 * Граница проходит именно здесь, и она же — главное проверяемое свойство:
 * последовательность поручений программы можно получить и сверить, НЕ ВЫПОЛНИВ
 * ни одного из них.
 */

