/**
 * Обратимость изоморфизма — то, что ПРОВЕРЯЕТСЯ, а не доказывается.
 *
 * Устройство изоморфизма доказано раньше и в другом месте (`types.mjs`): концы
 * обеих стрелок сходятся крест-накрест, единицы обоих объектов объявлены. Само
 * же обещание — «обратный после прямого даёт единицу» — говорит о РАВЕНСТВЕ
 * ВЫЧИСЛЕНИЙ на всех значениях объекта, а такое равенство неразрешимо. Значит
 * здесь конечная сетка, и отчёт обязан называть её размер: «проверено на N
 * значениях» — не то же самое, что «доказано».
 *
 * ПОЧЕМУ ЭТОГО НЕ БЫЛО ДО СИХ ПОР. Контракт (`flang/cat/SPEC.md`, «Изоморфизм»)
 * говорил прямо: обратимость не проверяется вовсе, потому что у стрелки нет
 * тела — вычислять на сетке нечего, а два разных объявления стрелок «А» → «А»
 * равными не являются. Там же названо и условие, при котором это меняется:
 * «сетка появится здесь тогда же, когда у морфизма появится `даёт`». `даёт`
 * появился, и вот сетка.
 *
 * ЧТО ОСТАЛОСЬ ДОПУЩЕНИЕМ. Изоморфизм, у которого хотя бы одна стрелка без
 * `даёт`, проверить нечем, и он остаётся тем же допущением автора, каким был:
 * молча, без диагностики. Это не поблажка — объявление стрелки без реализации
 * законно и полезно (так написаны все морфизмы наследия FTS), и требовать
 * реализацию ради проверки значило бы запретить объявлять то, чего ещё нет.
 * Но и хвастаться проверкой в этом случае нельзя: `checked` перечисляет ровно
 * те изоморфизмы, где сетка была не пуста.
 *
 * МОЛЧАНИЕ ПРИ ЭТОМ НЕ БЕСПЛАТНО. Диагностики такому изоморфизму не нужно, а
 * отчёту нужно: объявление, о котором не сказано ничего, читается как
 * проверенное. Поэтому пропуски перечисляются в `assumed` — тем же полем и с
 * той же оговоркой, что у `sets.mjs`. Список отдельный, а не пустая строчка в
 * `checked`, чтобы слово «сетка» нельзя было прочитать про то, чего не считали.
 *
 * ── Откуда берётся сетка ────────────────────────────────────────────────────
 * Оттуда же, откуда у моноида: из значений, которые автор уже написал. Для
 * объекта «А» это входы примеров прямой стрелки (она принимает «А») и
 * ожидаемые значения примеров обратной (она «А» возвращает); для объекта «Б» —
 * наоборот. Примеры берутся и у самой функции, и у законов стрелки: и те и
 * другие писал тот, кто знает краевые случаи, а закон ломается именно на них.
 */
import { reifyValue, valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Больше этого числа значений в сетку не берём: кругооборот линеен, но
 *  вычисление стрелки — нет, и «проверено» обязано означать одно и то же в
 *  разных прогонах. */
export const ПРЕДЕЛ_СЕТКИ = 12

/**
 * Проверка обратимости всех изоморфизмов программы.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<{ isomorphism: string, values: number }>,
 *   assumed: Array<{ isomorphism: string, why: string }> }}
 */
export function checkIsoLaws(программа, пределы = {}) {
  const изоморфизмы = Array.isArray(программа?.isomorphisms) ? программа.isomorphisms : []
  const diagnostics = []
  const checked = []
  const assumed = []
  if (изоморфизмы.length === 0) return { diagnostics, checked, assumed }

  const стрелки = new Map()
  for (const узел of Array.isArray(программа?.morphisms) ? программа.morphisms : []) {
    if (узел?.kind === "morphism") стрелки.set(узел.name, узел)
  }

  const среда = createRuntime(программа, пределы)
  const звать = (имяФункции, значение) => {
    const функция = функцииПрограммы(программа).find((кандидат) => кандидат.name === имяФункции)
    if (!функция || (функция.params ?? []).length !== 1) return { ошибка: `функции «${имяФункции}» нет` }
    try {
      return { значение: среда.call(имяФункции, { [функция.params[0].name]: значение }) }
    } catch (беда) {
      /* Отказ стрелки на значении сетки — не нарушение закона, а другое
         сообщение: кругооборот проверить не на чем, и сказать надо именно это. */
      return { ошибка: беда?.message ?? String(беда) }
    }
  }

  for (const узел of изоморфизмы) {
    const прямая = стрелки.get(узел.forward)
    const обратная = стрелки.get(узел.backward)
    /* Стрелки нет или концы не сошлись — об этом уже сказала проверка типов.
       Второе сообщение о том же было бы шумом, а не помощью. */
    if (прямая === undefined || обратная === undefined) {
      assumed.push({ isomorphism: узел.name, why: "стрелка не объявлена: сверять нечего" })
      continue
    }
    if (!реализована(прямая) || !реализована(обратная)) {
      assumed.push({ isomorphism: узел.name, why: "у стрелки нет «даёт»: вычислять нечего" })
      continue
    }

    /* Нарушения считаются и уезжают в отчёт: без этого нарушенный изоморфизм
       попадал в `checked` ровно так же, как честный, и ведомость печатала о нём
       «сетка N значений: нарушений не найдено» — та же неправда, что стояла у
       сетки примеров. Обход при этом обрывается на первом же контрпримере,
       значит и число значений говорит не о пройденном. */
    const доБед = diagnostics.length
    const сказать = (текст) => {
      diagnostics.push({
        code: "FLANG_ISO_NOT_INVERSE",
        message: `изоморфизм «${узел.name}»: ${текст}`,
        severity: "error",
        span: узел.span,
      })
    }

    /* Два круга, по одному на объект. Множество имён не сворачивается: у
       изоморфизма объекта с самим собой оба круга — один и тот же, и проверить
       его дважды дешевле, чем завести особый случай ради одной итерации. */
    let значенийВсего = 0
    for (const [объект, туда, назад] of [
      [узел.from, прямая, обратная],
      [узел.to, обратная, прямая],
    ]) {
      const сетка = сеткаЗначений(программа, туда, назад)
      значенийВсего += сетка.length
      for (const значение of сетка) {
        const первый = звать(туда.gives, значение)
        if (первый.ошибка) {
          сказать(`«${туда.name}» отказала на значении сетки: ${первый.ошибка}`)
          break
        }
        const второй = звать(назад.gives, первый.значение)
        if (второй.ошибка) {
          сказать(`«${назад.name}» отказала на значении сетки: ${второй.ошибка}`)
          break
        }
        if (!valuesEqual(второй.значение, значение)) {
          сказать(
            `кругооборот через «${объект}» не даёт «единица ${объект}»: ` +
              `${покажи(значение)} после «${туда.name}» и «${назад.name}» стало ${покажи(второй.значение)}`,
          )
          break
        }
      }
    }

    /* Изоморфизм без единого значения в сетке проверкой не считается: сказать
       «проверено» о нуле значений — это ровно та подмена «доказано» на
       «посмотрели», от которой язык и отгораживается. */
    const нарушений = diagnostics.length - доБед
    if (значенийВсего > 0) {
      checked.push({
        isomorphism: узел.name,
        values: значенийВсего,
        ...(нарушений === 0 ? {} : { violations: нарушений }),
      })
    } else assumed.push({ isomorphism: узел.name, why: "у стрелок нет примеров: сетка пуста" })
  }

  return { diagnostics, checked, assumed }
}

function реализована(стрелка) {
  return typeof стрелка.gives === "string" && стрелка.gives !== ""
}

function функцииПрограммы(программа) {
  return Array.isArray(программа?.functions) ? программа.functions : []
}

/**
 * Значения объекта, на которых проверяется кругооборот.
 *
 * `туда` принимает объект — годятся входы её примеров; `назад` объект
 * возвращает — годятся ожидаемые значения её примеров. Примеры берутся у самой
 * функции и у всех законов стрелки: в AST это разные места, а по смыслу одно и
 * то же — значения, названные автором.
 */
function сеткаЗначений(программа, туда, назад) {
  const собрано = []
  const добавить = (значение) => {
    if (значение === undefined) return
    const готовое = reifyValue(значение)
    if (собрано.some((уже) => valuesEqual(уже, готовое))) return
    собрано.push(готовое)
  }

  for (const пример of примеры(программа, туда)) {
    for (const значение of Object.values(пример.args ?? {})) добавить(значение)
  }
  for (const пример of примеры(программа, назад)) добавить(пример.expected)

  return собрано.slice(0, ПРЕДЕЛ_СЕТКИ)
}

function примеры(программа, стрелка) {
  const функция = функцииПрограммы(программа).find((кандидат) => кандидат.name === стрелка.gives)
  const свои = функция?.examples ?? []
  const законные = (стрелка.laws ?? []).flatMap((закон) => закон.examples ?? [])
  return [...свои, ...законные]
}

/** Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт. */
function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 40 ? `${текст.slice(0, 37)}…` : текст
}
