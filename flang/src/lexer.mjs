/**
 * Порядок поверхностей. Он же порядок слов в `KEYWORDS`, и он значим: первая
 * победившая фраза остаётся за своим идентификатором.
 */
export const SURFACE_ORDER = ["ru", "en", "eo", "zh"]

/**
 * Плоская таблица — та, что была здесь всегда: идентификатор → все слова
 * подряд. Собирается из `SURFACE_TABLE`, а не пишется руками, поэтому
 * разъехаться они не могут. Слово, стоящее на двух поверхностях сразу
 * (эсперантское `plus` — оно же английское), в списке остаётся одно.
 */
export const KEYWORDS = Object.fromEntries(
  Object.entries(SURFACE_TABLE).map(([id, surfaces]) => [
    id,
    [...new Set(SURFACE_ORDER.flatMap((surface) => surfaces[surface] ?? []))],
  ]),
)

/** Фраза → поверхность, на которой она написана. Общее слово отдаётся первой. */
const PHRASE_SURFACE = new Map()
for (const [id, surfaces] of Object.entries(SURFACE_TABLE)) {
  for (const surface of SURFACE_ORDER) {
    for (const phrase of surfaces[surface] ?? []) {
      if (!PHRASE_SURFACE.has(phrase)) PHRASE_SURFACE.set(phrase, surface)
    }
  }
  void id
}

/**
 * Поверхность, на которой написана фраза, или `null`.
 *
 * `plus` и `minus` стоят и в английском столбце, и в эсперантском: слово одно
 * и то же. Поверхность у него называется английской — не потому, что оно
 * английское, а потому, что по одному такому слову поверхность файла не
 * определяется, и спорить тут не о чем. Определяется она большинством
 * (`surfaceOfTokens`), где общее слово голоса не меняет.
 */
export function surfaceOfPhrase(phrase) {
  return PHRASE_SURFACE.get(phrase.toLowerCase()) ?? null
}

/**
 * Слово понятия на заданной поверхности — то, которое показывают диагностики.
 * Берётся первое: у понятия слов бывает несколько (`равен`, `равна`, `равно`),
 * и первое в строке — то, которым понятие называют.
 */
export function wordOn(id, surface) {
  return SURFACE_TABLE[id]?.[surface]?.[0] ?? null
}

/**
 * Поверхность потока токенов — большинством голосов среди ключевых слов.
 *
 * Не «первое ключевое слово»: файл на эсперанто начинается с английского
 * `module`, потому что эсперантского слова у этого понятия нет, и по первому
 * слову вся диагностика файла говорила бы по-английски. Не «все слова одной
 * поверхности» тоже: смешение законно ровно там, где на поверхности слова нет.
 *
 * Ничья и пустой поток дают `null` — тогда диагностика остаётся на русской
 * поверхности, как и была.
 */
export function surfaceOfTokens(tokens) {
  const счёт = new Map()
  for (const token of tokens) {
    if (token.kind !== "keyword") continue
    const поверхность = surfaceOfPhrase(token.text ?? "")
    if (поверхность === null) continue
    счёт.set(поверхность, (счёт.get(поверхность) ?? 0) + 1)
  }
  let лучшая = null
  let сколько = 0
  let ничья = false
  for (const [поверхность, голоса] of счёт) {
    if (голоса > сколько) {
      лучшая = поверхность
      сколько = голоса
      ничья = false
    } else if (голоса === сколько) {
      ничья = true
    }
  }
  return ничья ? null : лучшая
}

const PHRASES = new Map()
let MAX_PHRASE_WORDS = 1
for (const [id, phrases] of Object.entries(KEYWORDS)) {
  for (const phrase of phrases) {
    const words = phrase.split(" ")
    if (words.length > MAX_PHRASE_WORDS) MAX_PHRASE_WORDS = words.length
    /* Первая победившая фраза остаётся за своим идентификатором: таблица выше
       читается сверху вниз, поэтому конфликт виден глазами при правке. */
    if (!PHRASES.has(phrase)) PHRASES.set(phrase, id)
  }
}

/** Ключевое слово по одной поверхности — нужно тестам и парсеру для сообщений. */
export function keywordId(text) {
  return PHRASES.get(text.toLowerCase()) ?? null
}

export function tokenize(source) {
  if (typeof source !== "string") {
    throw flangError("FLANG_LEX", "исходник должен быть строкой")
  }

  const text = source.replace(/^\uFEFF/u, "").replace(/\r\n?/gu, "\n")
  const tokens = []
  const indents = [0]
  let offset = 0
  let line = 1
  let column = 1
  let depth = 0
  let atLineStart = true
  let lineHasTokens = false

  const here = () => ({ line, column })

  const advance = () => {
    const character = text[offset]
    offset += 1
    if (character === "\n") {
      line += 1
      column = 1
    } else {
      column += 1
    }
    return character
  }

  const push = (token) => {
    tokens.push(token)
    if (token.kind !== "indent" && token.kind !== "dedent" && token.kind !== "newline") lineHasTokens = true
  }

  const skipBlockComment = () => {
    const start = here()
    advance()
    advance()
    while (offset < text.length && !(text[offset] === "*" && text[offset + 1] === "/")) advance()
    if (offset >= text.length) throw flangError("FLANG_LEX", "не закрыт блочный комментарий", start)
    advance()
    advance()
  }

  /**
   * Начало значащей строки: измеряем отступ, пропуская пустые строки и
   * комментарии. Возвращает false, если значащих строк больше нет.
   */
  const openLine = () => {
    let width = 0
    for (;;) {
      const character = text[offset]
      if (character === undefined) return false
      if (character === " ") {
        width += 1
        advance()
        continue
      }
      if (character === "\t") {
        width += TAB_WIDTH
        advance()
        continue
      }
      if (character === "\n") {
        width = 0
        advance()
        continue
      }
      if (character === "/" && text[offset + 1] === "/") {
        while (offset < text.length && text[offset] !== "\n") advance()
        continue
      }
      if (character === "/" && text[offset + 1] === "*") {
        const before = line
        skipBlockComment()
        /* Комментарий через несколько строк обнуляет измеренный отступ:
           значащим считается отступ той строки, где стоит первый токен. */
        if (line !== before) width = 0
        continue
      }
      break
    }

    const top = indents[indents.length - 1]
    if (width > top) {
      indents.push(width)
      push({ kind: "indent", value: "", span: here() })
      return true
    }
    while (width < indents[indents.length - 1]) {
      indents.pop()
      push({ kind: "dedent", value: "", span: here() })
    }
    if (width !== indents[indents.length - 1]) {
      throw flangError(
        "FLANG_LEX",
        `рваный отступ: ${width} не совпадает ни с одним открытым уровнем (${indents.join(", ")})`,
        here(),
      )
    }
    return true
  }

  const readQuoted = (open, close) => {
    const start = here()
    advance()
    let value = ""
    let closed = false
    while (offset < text.length) {
      const character = advance()
      if (character === close) {
        closed = true
        break
      }
      if (character === "\\" && offset < text.length) {
        const escaped = advance()
        const escapes = { n: "\n", r: "\r", t: "\t", '"': '"', "'": "'", "\\": "\\" }
        if (escaped === "u") {
          const hex = text.slice(offset, offset + 4)
          if (!/^[0-9A-Fa-f]{4}$/u.test(hex)) throw flangError("FLANG_LEX", "неверный Unicode-escape", start)
          for (let index = 0; index < 4; index += 1) advance()
          value += String.fromCharCode(Number.parseInt(hex, 16))
        } else {
          value += escapes[escaped] ?? escaped
        }
        continue
      }
      value += character
    }
    if (!closed) {
      throw flangError("FLANG_LEX", open === "«" ? "не закрыта кавычка-ёлочка" : "не закрыта кавычка", start)
    }
    return { value: value.normalize("NFC"), span: start }
  }

  while (offset < text.length) {
    if (atLineStart && depth === 0) {
      if (!openLine()) break
      atLineStart = false
      continue
    }
    atLineStart = false

    const character = text[offset]

    if (character === "\n") {
      const start = here()
      advance()
      if (lineHasTokens) {
        tokens.push({ kind: "newline", value: "\n", span: start })
        lineHasTokens = false
      }
      atLineStart = true
      continue
    }
    if (character === " " || character === "\t") {
      advance()
      continue
    }
    if (character === "/" && text[offset + 1] === "/") {
      while (offset < text.length && text[offset] !== "\n") advance()
      continue
    }
    if (character === "/" && text[offset + 1] === "*") {
      skipBlockComment()
      continue
    }
    if (character === "→") {
      const start = here()
      advance()
      push({ kind: "arrow", value: "→", span: start })
      continue
    }
    if ((character === "-" || character === "=") && text[offset + 1] === ">") {
      const start = here()
      advance()
      advance()
      push({ kind: "arrow", value: "→", span: start })
      continue
    }
    if (character === "«") {
      const { value, span } = readQuoted("«", "»")
      push({ kind: "name", value, quoted: true, span })
      continue
    }
    if (character === '"' || character === "'") {
      const { value, span } = readQuoted(character, character)
      push({ kind: "string", value, quoted: true, span })
      continue
    }
    if (/\d/u.test(character) || (character === "-" && /\d/u.test(text[offset + 1] ?? ""))) {
      const start = here()
      const match = NUMBER.exec(text.slice(offset))
      if (match === null) throw flangError("FLANG_LEX", "неверное число", start)
      for (let index = 0; index < match[0].length; index += 1) advance()
      push({ kind: "number", value: Number(match[0]), text: match[0], span: start })
      continue
    }
    if (NAME_START.test(character)) {
      const start = here()
      let value = advance()
      while (offset < text.length && NAME_PART.test(text[offset])) value += advance()
      push({ kind: "name", value: value.normalize("NFC"), quoted: false, span: start })
      continue
    }
    const narrow = PUNCT.includes(character) ? character : FULLWIDTH.get(character)
    if (narrow !== undefined) {
      const start = here()
      advance()
      push({ kind: "punct", value: narrow, span: start })
      if (narrow === "{" || narrow === "[" || narrow === "(") depth += 1
      if (narrow === "}" || narrow === "]" || narrow === ")") depth = Math.max(0, depth - 1)
      continue
    }

    throw flangError("FLANG_LEX", `недопустимый символ '${character}'`, here())
  }

  if (lineHasTokens) tokens.push({ kind: "newline", value: "\n", span: here() })
  while (indents.length > 1) {
    indents.pop()
    tokens.push({ kind: "dedent", value: "", span: here() })
  }
  tokens.push({ kind: "eof", value: "", span: here() })

  return foldKeywords(tokens)
}

/** Склейка соседних незакавыченных слов в ключевые слова и фразы (жадно, длинные вперёд). */
function foldKeywords(tokens) {
  const result = []
  let index = 0
  while (index < tokens.length) {
    const token = tokens[index]
    if (token.kind !== "name" || token.quoted) {
      result.push(token)
      index += 1
      continue
    }
    let size = Math.min(MAX_PHRASE_WORDS, tokens.length - index)
    let id = null
    for (; size >= 1; size -= 1) {
      const run = tokens.slice(index, index + size)
      if (run.some((item) => item.kind !== "name" || item.quoted)) continue
      const found = PHRASES.get(run.map((item) => item.value.toLowerCase()).join(" "))
      if (found !== undefined) {
        id = found
        break
      }
    }
    if (id === null) {
      result.push(token)
      index += 1
      continue
    }
    const run = tokens.slice(index, index + size)
    result.push({ kind: "keyword", value: id, text: run.map((item) => item.value).join(" "), span: token.span })
    index += size
  }
  return result
}
