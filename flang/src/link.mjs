/**
 * Связывание модулей flang: `использует «Модуль» из "путь"`.
 *
 * До этого файла импорт разбирался, но не действовал: parser.mjs складывал
 * `{ category, from }` в `legacy`, а имена из другого файла оставались
 * несвязанными — `FLANG_UNKNOWN_NAME` на первом же вызове. Из-за этого stdlib
 * нельзя было использовать из решений, а ядро FTS, разложенное по слоям
 * (лексер, парсер, вычислитель, печать), не собиралось в одну программу.
 *
 * Решение намеренно простое: импорт — это слияние объявлений, а не пространство
 * имён. Языку без экспоненциалов и с уникальными именами вариантов
 * пространства имён дали бы больше сложности, чем пользы: пришлось бы решать,
 * как выглядит квалифицированное имя по-русски («Списки.Сумма»? «Сумма из
 * Списки»?), и тащить это решение во все восемь бэкендов. Слияние же печатается
 * в любой целевой язык одинаково — как один набор функций.
 *
 * Цена решения — конфликт имён становится ошибкой, а не перекрытием. Это
 * осознанно: молчаливое перекрытие функции из другого файла — источник ошибок,
 * которые невозможно объяснить, глядя на один файл.
 */

import { readFile } from "node:fs/promises"
import { dirname, isAbsolute, resolve } from "node:path"

/** Ошибка связывания в том же формате, что остальные диагностики языка. */
function diagnostic(code, message, span) {
  return span === undefined || span === null
    ? { code, message, severity: "error" }
    : { code, message, severity: "error", span }
}

/**
 * Имя файла в местах разобранного модуля.
 *
 * ── Зачем ──────────────────────────────────────────────────────────────────
 * Диагностика flang несёт строку и столбец, но не файл: одному файлу оно и не
 * нужно. После связывания нужно: «строка 12» одинаково правдоподобно указывает
 * и во входной файл, и в импортированный, а различить их нечем. Для CLI это
 * неудобство — человек видит одно сообщение и догадывается. Для редактора это
 * ложь: подчёркивание уезжает в чужой буфер, на строку, к ошибке отношения не
 * имеющую.
 *
 * Чинится там, где ломается, — в языке, а не в языковом сервере: место
 * рождается в разборе, значит имя файла надо проставить сразу после разбора, и
 * тогда его унаследует всякий, кто строит диагностику по узлу (`spanOf` в
 * types.mjs и totality.mjs отдаёт ТОТ ЖЕ объект места). Сервер ничего не
 * восстанавливает и ничего не угадывает — он читает поле.
 *
 * ── Почему по просьбе, а не всегда ─────────────────────────────────────────
 * AST — не внутреннее дело этого файла. У языка две реализации связывания:
 * здесь и на самом flang (`flang/self`), и тест самораскрутки сверяет их
 * ПОБАЙТОВО, печатью в JSON. Всякое новое поле в AST — это работа, которую
 * обязаны сделать обе, иначе одна из них перестаёт быть реализацией того же
 * языка. Пока вторая про файлы не знает, поле проставляется только тому, кто
 * попросил (`attributeFiles`), и печать AST остаётся прежней: `flang ast` и
 * `flang check` не просят, языковой сервер просит.
 *
 * Это не «временный костыль до реализации в self»: имя файла и не должно
 * попадать в печать AST. AST описывает программу, а не то, из каких файлов её
 * собрали, — файлы нужны диагностике, а она и получает их через тот же объект
 * места, ни во что не печатаясь.
 *
 * Проставляет имя загрузчик, а не сам `parse`: разбор одного файла обязан
 * давать побайтово прежний AST (`flang ast` без импортов сверяется с ним в
 * тесте), да и парсер файлов не читает — это работа загрузчика. Отсюда и
 * экспорт: тот, кто загрузил текст, знает, как этот текст называется.
 *
 * Обход итеративный, а не рекурсивный: тело `core/parser.flang` глубже, чем
 * стек по умолчанию, и рекурсия здесь однажды упала бы не на своём файле.
 */
export function stampFile(root, file) {
  const seen = new WeakSet()
  const stack = [root]
  while (stack.length > 0) {
    const node = stack.pop()
    if (node === null || typeof node !== "object" || seen.has(node)) continue
    seen.add(node)
    if (Array.isArray(node)) {
      for (const item of node) stack.push(item)
      continue
    }
    /* Место уже названное чужим файлом не переписываем: узел мог приехать из
       импортированного модуля, и переклеить ему имя значило бы соврать. */
    if (node.span !== null && typeof node.span === "object" && node.span.file === undefined) {
      node.span.file = file
    }
    for (const value of Object.values(node)) stack.push(value)
  }
  return root
}

/** Импорты лежат в legacy — там же, куда их кладёт parseModuleHeader. */
export function importsOf(program) {
  const header = (program?.legacy ?? []).find((node) => node?.construct === "moduleHeader")
  return header?.value?.imports ?? []
}

/** `экспортирует` ограничивает видимое; без него виден весь модуль. */
function exportsOf(program) {
  const header = (program?.legacy ?? []).find((node) => node?.construct === "moduleHeader")
  const names = header?.value?.exports
  return Array.isArray(names) && names.length > 0 ? new Set(names) : null
}

/**
 * Категорные объявления, которые связывание переносит между модулями.
 *
 * Ключ — поле разобранной программы (`parse` кладёт их рядом с `types` и
 * `functions`), слово — как назвать находку в диагностике о столкновении имён.
 * Все четыре слова мужского рода, поэтому «объявлен» одно на всех.
 *
 * Функтора в таблице нет и быть не может: он единственный из пятерых лежит не
 * своим списком, а узлом наследия FTS в `legacy` (`construct: "functorFile"`),
 * и сливается отдельно — см. `functors` в `linkProgram`.
 */
const КАТЕГОРНЫЕ = [
  ["morphisms", "морфизм", "объявлен"],
  ["isomorphisms", "изоморфизм", "объявлен"],
  ["bifunctors", "бифунктор", "объявлен"],
  ["monoids", "моноид", "объявлен"],
  /* Вложение и общая часть — объявления того же рода: они принадлежат модулю, и
     общая часть вправе сослаться на вложение из соседнего файла. Не слей их —
     и доказательство, которое ловится в одном файле, через `использует`
     исчезало бы молча, ровно как это было бы у морфизма.

     Третье слово в строке — причастие в роде слова. До этих двух строк все
     четыре понятия были мужского рода, и «объявлен» стояло в сообщении прямо;
     «вложение объявлен» читается как опечатка компилятора, а компилятор,
     который путается в падежах, теряет доверие и там, где он прав. */
  ["embeddings", "вложение", "объявлено"],
  ["intersections", "общая часть", "объявлена"],
  /* Категория — интерфейс модуля, и без неё связывание теряло САМУ ПРОВЕРКУ, а
     не одно объявление. Улика снималась тремя файлами: модуль «Заказы» с
     категорией из одной стрелки, модуль «Отгрузка» со своей, и третий модуль с
     функтором между ними, который эту стрелку НЕ отображает. Одним файлом это
     отвергается кодом `FLANG_FUNCTOR_NOT_TOTAL`; теми же строками, разложенными
     по трём модулям через `использует`, — проходило молча с `valid: true` и
     нулём диагностик.

     Причина ровно та, что названа у соседей выше: полнота функтора считается по
     числу стрелок категории домена (`checkFunctors`, закон 4 в types.mjs), а в
     слитой программе категорий не оставалось вовсе — «сколько» опять
     становилось неизвестным числом. То же и с двумя аксиомами самой категории:
     замкнутость под композицией и наличие единиц переставали проверяться, стоило
     файлу обзавестись хоть одной строкой `использует`.

     Женский род — отсюда «объявлена». */
  ["categories", "категория", "объявлена"],
]

/**
 * Служебное звено цепочки: `цепочка «Оформление»` из трёх шагов разворачивается
 * в композиции «Оформление · шаг 1» и «Оформление», и первая — не имя, а
 * внутренность второй (`parseChain` в parser.mjs, там же и этот разделитель).
 *
 * Знать о нём приходится здесь по одной причине: `только «Оформление»`
 * перечисляет имена, а имени «Оформление · шаг 1» автор не писал и написать не
 * может. Фильтруй звенья наравне с именами — и выборочный импорт привозил бы
 * цепочку без середины, то есть ссылку на морфизм, которого нет.
 */
const ЗВЕНО_ЦЕПОЧКИ = " · шаг "

/**
 * Видно ли объявление снаружи модуля.
 *
 * Для всего, у чего есть имя, правило то же, что у типов и функций: `visible`
 * — это `экспортирует` ∩ `только`, а `null` значит «видно всё». Исключение
 * одно и объяснено у `ЗВЕНО_ЦЕПОЧКИ`: служебное звено видно вместе со своей
 * цепочкой, потому что своего имени у него нет.
 */
function видно(visible, узел) {
  if (visible === null) return true
  const имя = узел?.name
  if (typeof имя !== "string") return false
  if (узел?.internal !== true) return visible.has(имя)
  const край = имя.lastIndexOf(ЗВЕНО_ЦЕПОЧКИ)
  return край !== -1 && visible.has(имя.slice(0, край))
}

/**
 * Загружает файл и все его импорты, сливая объявления в одну программу.
 *
 * `parse` передаётся снаружи, а не импортируется здесь: bin/flang.mjs уже умеет
 * находить функцию разбора среди нескольких возможных имён, и дублировать этот
 * выбор значит однажды разойтись с ним.
 *
 * `options.attributeFiles` — проставить в места имя файла, из которого узел
 * приехал (см. `stampFile`). По умолчанию нет: печать AST от этого не меняется.
 */
export async function linkProgram(entryFile, source, parse, options = {}) {
  const readSource = options.readFile ?? ((file) => readFile(file, "utf8"))
  /* Без просьбы — тождество: ни одного лишнего поля в AST и ни одного лишнего
     обхода дерева на каждом связывании. */
  const mark = options.attributeFiles === true ? stampFile : (node) => node
  const diagnostics = []
  const types = []
  const functions = []
  /* Объявления теорката. Стрелка, изоморфизм, бифунктор и моноид — объявления
     того же рода, что типы и функции: они принадлежат модулю, а не программе
     целиком, и композиция вправе собрать стрелку одного модуля со стрелкой
     другого. Значит и сливаться они обязаны так же — иначе доказательство,
     которое ловится в одном файле, через `использует` исчезает молча. */
  const категории = Object.fromEntries(КАТЕГОРНЫЕ.map(([поле]) => [поле, []]))
  /* Функтор — того же рода объявление, но приезжает узлом `legacy`, а не своим
     списком, поэтому и список у него свой. */
  const functors = []
  /* Откуда пришло имя — нужно, чтобы конфликт назвал оба файла, а не только
     тот, который загрузился вторым. */
  const originOfType = new Map()
  const originOfFunction = new Map()
  /* У каждого вида — своя карта происхождения, потому что и пространство имён
     своё: `checkMorphisms`, `checkMonoids` и соседи в types.mjs держат по
     таблице на вид, и моноид «Сумма» рядом с морфизмом «Сумма» никому не
     мешает. Одна общая карта запретила бы то, что язык разрешает. */
  const originOfCategorical = new Map(КАТЕГОРНЫЕ.map(([поле]) => [поле, new Map()]))
  const originOfFunctor = new Map()
  const loaded = new Set()
  const loading = []
  /* Тексты файлов и признак «в файле есть импорты» — для второго прохода,
     который доразрешает вызовы функций без аргументов. */
  const sources = new Map()
  const withImports = new Set()

  /**
   * Пересечение «что модуль отдаёт» и «что у него просят».
   *
   * Просьба не расширяет видимое: `только «Внутри»` для неэкспортированного
   * имени ничего не даёт — иначе `экспортирует` перестал бы что-либо значить.
   */
  const narrow = (exported, requested) => {
    if (requested === undefined || requested === null) return exported
    if (exported === null) return requested
    return new Set([...requested].filter((name) => exported.has(name)))
  }

  /**
   * Повтор ВНУТРИ одного файла — не дело связывания, но и глотать его нельзя.
   *
   * `merge` зовётся ровно один раз на файл (`load` возвращает `null` для уже
   * загруженного, и `merge` стоит после `loaded.add`), поэтому `previous ===
   * file` означает единственное: одно имя объявлено в этом файле дважды. Про
   * два МОДУЛЯ здесь сказать нечего — модуль один, — и сообщение «объявлен в
   * двух модулях: A и A» было бы ложью.
   *
   * Раньше такой повтор молча пропускался (`continue`), и от этого проверка
   * пропадала целиком: `types.mjs` ловит «объявлена дважды» на СЛИТОЙ
   * программе, а в слитой оставалось одно объявление из двух. Итог измерен
   * уликой в `flang/test/link.test.mjs`: файл с двумя `функция «Ответ»` и одной
   * строкой `использует` проходил `check` с `valid: true` и нулём диагностик,
   * побеждало ВТОРОЕ тело, а пример первого не считался вовсе — `flang test`
   * показывал ноль примеров. Тот же файл без строки `использует` честно
   * отвергался: связывания не было, и `types.mjs` видел оба объявления.
   *
   * Значит достаточно НЕ ронять второе объявление. Тогда повтор внутри файла
   * ловится одним и тем же кодом и одним и тем же текстом независимо от того,
   * есть в файле импорты или нет, — а это ровно то свойство, которого не было.
   * Отдельной диагностики здесь не добавляется намеренно: два сообщения об
   * одной ошибке хуже одного.
   */
  const свой = (previous, file) => previous === file

  const merge = (program, file, visible) => {
    for (const type of program.types ?? []) {
      if (visible !== null && !visible.has(type.name)) continue
      const previous = originOfType.get(type.name)
      if (previous !== undefined) {
        /* Тип, который вводит сам язык (сумма «Действие» из conc.mjs),
           приписывается каждому файлу с процессами отдельно. Два таких файла
           дали бы «объявлен в двух модулях» — конфликт, которого нет: это одно
           и то же объявление, а не два разных. */
        if (type.builtin === true) continue
        if (!свой(previous, file)) {
          diagnostics.push(
            diagnostic(
              "FLANG_DUPLICATE_NAME",
              `тип «${type.name}» объявлен в двух модулях: ${previous} и ${file}`,
              type.span,
            ),
          )
          continue
        }
        types.push(type)
        continue
      }
      originOfType.set(type.name, file)
      types.push(type)
    }
    for (const fn of program.functions ?? []) {
      if (visible !== null && !visible.has(fn.name)) continue
      const previous = originOfFunction.get(fn.name)
      if (previous !== undefined) {
        if (!свой(previous, file)) {
          diagnostics.push(
            diagnostic(
              "FLANG_DUPLICATE_NAME",
              `функция «${fn.name}» объявлена в двух модулях: ${previous} и ${file}`,
              fn.span,
            ),
          )
          continue
        }
        functions.push(fn)
        continue
      }
      originOfFunction.set(fn.name, file)
      functions.push(fn)
    }
    /* Видимость считается по тому же набору имён, что у типов и функций: у
       объявления теорката тоже есть имя, и `экспортирует` обязано значить для
       стрелки ровно то же, что для типа. Стрелка, чей объект остался
       невидимым, честно упрётся в «домен морфизма … не объявлен» — так же,
       как сегодня упирается функция с неэкспортированным типом параметра.

       Столкновение имён — ошибка того же вида, что у типов и функций, и
       ловится здесь, а не в types.mjs, по измеренной причине. `checkMorphisms`
       про два модуля не знает и сказать может только «морфизм «х» объявлен
       дважды» — без единого имени файла и с местом второго объявления, которое
       в открытом файле показывает на постороннюю строку. Здесь же оба файла
       известны, поэтому второе объявление не кладётся вовсе: одно сообщение,
       называющее обе стороны, вместо одного, не называющего ни одной. */
    for (const [поле, слово, объявлено] of КАТЕГОРНЫЕ) {
      const откуда = originOfCategorical.get(поле)
      for (const узел of program[поле] ?? []) {
        if (!видно(visible, узел)) continue
        const previous = откуда.get(узел.name)
        if (previous !== undefined) {
          /* О столкновении цепочек скажет их последнее звено — то, у которого
             имя написал автор. Ругаться ещё и на служебные значило бы выдать
             три сообщения об одной ошибке. */
          if (previous !== file && узел.internal !== true) {
            diagnostics.push(
              diagnostic(
                "FLANG_DUPLICATE_NAME",
                `${слово} «${узел.name}» ${объявлено} в двух модулях: ${previous} и ${file}`,
                узел.span,
              ),
            )
          }
          continue
        }
        откуда.set(узел.name, file)
        категории[поле].push(узел)
      }
    }
    /* Функтор — пятый из этого рода, и без отдельного разбора он не переехал бы
       вовсе: его узел лежит в `legacy`, а `legacy` берётся у входного файла
       целиком, так что импортированный функтор терялся, а свой доезжал, но
       непроверенным — его объекты живут в другом модуле. */
    for (const узел of program.legacy ?? []) {
      if (узел?.construct !== "functorFile") continue
      const имя = узел.value?.name
      if (!видно(visible, узел.value)) continue
      const previous = originOfFunctor.get(имя)
      if (previous !== undefined) {
        if (previous !== file) {
          diagnostics.push(
            diagnostic(
              "FLANG_DUPLICATE_NAME",
              `функтор «${имя}» объявлен в двух модулях: ${previous} и ${file}`,
              узел.span,
            ),
          )
        }
        continue
      }
      originOfFunctor.set(имя, file)
      functors.push(узел)
    }
  }

  /* Что именно берём из каждого файла: `null` — всё видимое, иначе набор имён
     из `только`. Пересечение с `экспортирует` считается в merge. */
  const wanted = new Map()

  /**
   * Как называется модуль в каждом разобранном файле.
   *
   * Нужна ровно затем, чтобы сверка имени в `использует` не зависела от порядка
   * обхода. Раньше сверка стояла на результате `load`, а `load` отдаёт `null`
   * для уже загруженного файла — и потому ВТОРОЙ импорт того же файла не
   * сверялся вовсе. Улика (`flang/test/link.test.mjs`): один и тот же
   * `использует «Совсем не то имя» из "real.flang"` отвергался, если этот файл
   * ещё не грузили, и проходил молча, если его уже притащил сосед. Одна и та же
   * ложь про имя модуля — разный ответ компилятора, и разница только в порядке
   * строк. Имя же известно всегда: файл разобран, заголовок прочитан.
   */
  const moduleOf = new Map()

  /** Сверка имени в `использует` с заголовком файла. Одна на оба места вызова. */
  const сверитьИмяМодуля = (target, written, headerSpan) => {
    const настоящее = moduleOf.get(target)
    if (настоящее === undefined || настоящее === "" || настоящее === written) return
    diagnostics.push(
      diagnostic(
        "FLANG_IMPORT_NAME",
        `модуль в ${target} называется «${настоящее}», а импортируется как «${written}»`,
        headerSpan,
      ),
    )
  }

  const load = async (file, text, isEntry) => {
    if (loaded.has(file)) return null
    /* Цикл импортов — ошибка, а не молчаливая остановка: иначе часть объявлений
       окажется недоступной, и виноват будет порядок обхода. */
    if (loading.includes(file)) {
      diagnostics.push(
        diagnostic("FLANG_IMPORT_CYCLE", `циклический импорт: ${[...loading, file].join(" → ")}`),
      )
      return null
    }
    loading.push(file)

    sources.set(file, text)

    let program
    try {
      program = mark(parse(text, file), file)
    } catch (error) {
      /* У ошибки разбора уже есть код и место — заворачивать её своим текстом
         значит потерять строку, на которой всё сломалось. Не хватает ей ровно
         одного: файла, в котором эта строка находится. */
      const wrapped = error?.diagnostics ?? [
        diagnostic("FLANG_PARSE", error instanceof Error ? error.message : String(error)),
      ]
      diagnostics.push(...mark(wrapped, file))
      loading.pop()
      loaded.add(file)
      return null
    }

    if (importsOf(program).length > 0) withImports.add(file)
    /* Запоминается СРАЗУ после разбора, а не после слияния: сверять имя обязан и
       тот, кто придёт к этому файлу вторым, — а он придёт раньше, чем `merge`. */
    moduleOf.set(file, typeof program.module === "string" ? program.module : "")

    /* Заголовок модуля — место, куда указывают беды импорта: самих строк
       `использует` в AST нет (у записи импорта нет места), а заголовок стоит
       ровно над ними. Это не точное место, но честное: тот же файл, тот же
       блок. Выдумывать строку было бы хуже. */
    const headerSpan = (program.legacy ?? []).find((node) => node?.construct === "moduleHeader")?.span

    for (const entry of importsOf(program)) {
      const target = isAbsolute(entry.from) ? entry.from : resolve(dirname(file), entry.from)
      if (loaded.has(target) || loading.includes(target)) {
        if (loading.includes(target)) {
          diagnostics.push(
            diagnostic("FLANG_IMPORT_CYCLE", `циклический импорт: ${[...loading, target].join(" → ")}`, headerSpan),
          )
        } else {
          /* Файл уже привезён кем-то другим — но имя в ЭТОЙ строке `использует`
             никто не сверял. Про цикл уже сказано, второй жалобой на тот же
             импорт читателя грузить незачем, поэтому только в этой ветке. */
          сверитьИмяМодуля(target, entry.category, headerSpan)
        }
        continue
      }
      let imported
      try {
        imported = await readSource(target)
      } catch (error) {
        diagnostics.push(
          diagnostic(
            "FLANG_IMPORT_NOT_FOUND",
            `не найден модуль «${entry.category}»: ${target} (${error instanceof Error ? error.message : String(error)})`,
            headerSpan,
          ),
        )
        continue
      }
      if (Array.isArray(entry.only)) {
        const already = wanted.get(target)
        wanted.set(target, already === undefined ? new Set(entry.only) : new Set([...already, ...entry.only]))
      } else {
        wanted.set(target, null)
      }
      await load(target, imported, false)
      /* Имя модуля в `использует` обязано совпадать с его заголовком: иначе
         читатель видит одно имя, а получает объявления из другого файла.
         Сверяется по запомненному имени, а не по результату `load`: см.
         `moduleOf`. Файл, который не разобрался, имени не оставил — про него уже
         сказано кодом разбора, и молчать здесь правильно. */
      сверитьИмяМодуля(target, entry.category, headerSpan)
    }

    loading.pop()
    loaded.add(file)
    merge(program, file, isEntry ? null : narrow(exportsOf(program), wanted.get(file)))
    return program
  }

  const entry = await load(resolve(entryFile), source, true)

  /**
   * Второй проход: имя функции без аргументов становится вызовом только если
   * такая функция объявлена, а на первом проходе каждый файл знал лишь свои
   * объявления — вызов импортированной функции без аргументов оставался
   * несвязанным именем. Теперь полный набор имён известен, и файлы, у которых
   * есть импорты, разбираются заново уже с ним.
   *
   * Перебор ограничен файлами с импортами: у остальных внешних имён нет, и
   * повторный разбор дал бы тот же результат.
   */
  const names = new Set(functions.map((fn) => fn.name))
  const reparsed = new Map()
  for (const [file, text] of sources) {
    if (!withImports.has(file)) continue
    try {
      reparsed.set(file, mark(parse(text, file, names), file))
    } catch {
      /* Файл уже разобрался на первом проходе, значит второй провалиться не
         может; но если это случилось — оставляем результат первого прохода,
         а не роняем всё связывание. */
    }
  }
  if (reparsed.size > 0) {
    for (const [file, program] of reparsed) {
      const visible = file === resolve(entryFile) ? null : exportsOf(program)
      for (const fn of program.functions ?? []) {
        if (visible !== null && !visible.has(fn.name)) continue
        const at = functions.findIndex((item) => item.name === fn.name)
        /* Заменяем только своё: функция с тем же именем из другого файла — это
           конфликт, о котором уже сказано выше, и подменять её здесь значило
           бы решать конфликт молча. */
        if (at !== -1 && originOfFunction.get(fn.name) === file) functions[at] = fn
      }
      /* Категорные объявления переразбираются тем же правилом, и не ради
         симметрии: единица моноида — ВЫРАЖЕНИЕ, и `единица «Пусто»` с функцией
         «Пусто» из другого модуля на первом проходе осталась бы несвязанным
         именем. Функтора здесь нет намеренно: в его теле одни имена объектов и
         стрелок, разрешать в нём нечего. */
      for (const [поле] of КАТЕГОРНЫЕ) {
        const список = категории[поле]
        const откуда = originOfCategorical.get(поле)
        for (const узел of program[поле] ?? []) {
          if (!видно(visible, узел)) continue
          const at = список.findIndex((item) => item.name === узел.name)
          if (at !== -1 && откуда.get(узел.name) === file) список[at] = узел
        }
      }
    }
  }

  const linked = {
    flang: 1,
    module: entry?.module ?? "",
    types,
    functions,
    /* Функтор лежит в `legacy`, а `legacy` берётся у входного файла целиком —
       поэтому свои функторы отсюда вынимаются и кладутся обратно уже слитыми.
       Иначе функтор входного файла приехал бы дважды: своим узлом и слитым.
       Когда функторов нет, список остаётся тем же объектом, что и был. */
    legacy:
      functors.length > 0
        ? [...(entry?.legacy ?? []).filter((узел) => узел?.construct !== "functorFile"), ...functors]
        : (entry?.legacy ?? []),
    diagnostics,
  }
  /* Объявления теорката, наоборот, приходят из всех модулей сразу: они слиты в
     `merge`, здесь остаётся только выложить непустые списки. Ключ появляется
     ровно тогда, когда объявления есть, — программа без теорката обязана
     остаться побайтово прежней, иначе неподвижная точка самоприменения сошлась
     бы к другому AST. */
  for (const [поле, объявления] of Object.entries(категории)) {
    if (объявления.length > 0) linked[поле] = объявления
  }
  /* Процессы, надзор и прогоны берутся у входного файла и только у него.
     Причина не в лени: процесс — это объявление о программе целиком (у него
     ящик, планировщик и итоговое состояние), и слить процессы двух модулей в
     одну систему значило бы решить, чей прогон чей. Импортируемый модуль отдаёт
     типы и функции — из них процесс собирается во входном файле. */
  /* План — там же и по той же причине: он говорит о программе целиком (у него
     начальное состояние, шаг и исполнитель), и слить планы двух модулей значило
     бы решить, чей план исполнять. */
  /* Теорема — там же и по своей причине: она говорит о функциях СВОЕГО модуля и
     доказана была, когда проверяли его файл. Слить теоремы импортированных
     модулей значило бы перепроверять чужое доказательство в каждом, кто модуль
     использует, — та же работа столько раз, сколько импортов, и ни одного
     нового факта за неё. Ключ не выкладывается, когда теорем нет: программа без
     доказательств обязана остаться побайтово прежней. */
  for (const поле of ["processes", "supervisors", "runs", "plans", "theorems"]) {
    if (Array.isArray(entry?.[поле]) && entry[поле].length > 0) linked[поле] = entry[поле]
  }
  return linked
}
