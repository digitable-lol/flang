/**
 * ЗАМОК БЕЗ СКЛАДА — `flang.lock`, в котором лежат САМИ зависимости.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Требование владельца к пакетам записано дословно: «нужен уникальный и
 * качественный подход, простой, без необходимости постоянно что-то где-то
 * складировать и скачивать». Обычный замок (npm, cargo, nix) этого требования
 * НЕ выполняет: в нём лежат ссылки — имя, версия и хеш, — а по ссылке надо
 * идти на склад. Нет склада — нет сборки, и воспроизводимость держится на
 * чужой готовности хранить.
 *
 * Здесь замок держит не ссылку, а КОД:
 *
 *   человек пишет:  использует «Строки» из "../../stdlib/strings.flang"
 *   в замке лежит:  «Строки» → её исходник целиком плюс адрес по содержимому
 *   склада:         нет вообще
 *
 * Скачивать неоткуда, потому что всё уже приехало. Воспроизводимость при этом
 * не «хеш совпал, значит, наверное, тот же код», а «код в замке и лежит».
 *
 * ── СХЕМА 2: brotli из формата убран, и вот чем это оплачено ────────────────
 * Схема 1 хранила модуль так: разбор → JSON → brotli качества 11 → base64, и
 * ЭТО и называлось адресом модуля. Решение владельца: адрес модуля перестаёт
 * быть brotli. Довод не про трудоёмкость, а про цель: эталонный кодировщик
 * brotli — десятки тысяч строк, и байт в байт нужен именно он, иначе замок,
 * собранный двоичным компилятором, не совпадёт с замком свидетеля на том же
 * входе. Написать его на C99 значило бы не приблизить удаление JavaScript, а
 * внести в доверенное основание чужой алгоритм сжатия.
 *
 * Схема 2 устроена так:
 *
 *   АДРЕС  — sha256 исходника модуля (64 знака), то есть адрес ПО СОДЕРЖИМОМУ;
 *   ГРУЗ   — сам исходник модуля, строкой JSON, без сжатия и без base64.
 *
 * Четыре условия, которым замена обязана была отвечать, и чем отвечает:
 *
 * 1. ДЕТЕРМИНИРОВАННОСТЬ. sha256 — функция от байтов и только от них. Один
 *    исходник даёт один адрес всегда, на любой машине и в любой год.
 * 2. ВОСПРОИЗВОДИМОСТЬ НА ОБЕИХ СТОРОНАХ ПОБАЙТОВО. Двоичному нужны sha256
 *    (около 130 строк переносимого C99, и он всё равно нужен под печать замка)
 *    и экранирование строки JSON, которое на стороне flang уже написано
 *    («Экранировать», «Печать строки» в `flang/core/json.flang`). Ни канонизации
 *    разбора, ни печати чисел с точным обратным разбором, ни порядка ключей —
 *    ничего этого схема 2 у второй стороны не требует, потому что груз есть
 *    ТЕКСТ, а не дерево.
 * 3. НИЧЕГО ЧУЖОГО В ОСНОВАНИИ. Алгоритма сжатия в формате нет вовсе — это
 *    и есть «отсутствие алгоритма». sha256 — единственная вычислительная
 *    зависимость, и она уже была: печать замка считалась ею и в схеме 1.
 * 4. РАЗМЕР НАЗВАН ЧИСЛОМ. Замок вырос примерно вдесятеро — числа в
 *    `docs/lockfile-without-store.md` и в `scripts/lockfile-size.mjs`. Платим
 *    местом на диске, и оно самое дешёвое из того, чем можно было заплатить:
 *    git жмёт свои объекты zlib сам, то есть сжатие живёт у git, а не у нас в
 *    доверенном основании.
 *
 * ── Почему груз — ИСХОДНИК, а не разбор ─────────────────────────────────────
 * Схема 1 везла разбор со снятыми местами. Отказ от сжатия делает выбор между
 * разбором и исходником заново, и исходник выигрывает по трём измеренным
 * причинам:
 *
 * • ВТОРОЙ СТОРОНЕ НЕ НУЖЕН СЕРИАЛИЗАТОР РАЗБОРА. Чтобы пересчитать печать
 *   разбора, двоичному пришлось бы напечатать дерево в JSON БАЙТ В БАЙТ так
 *   же, как это делает `JSON.stringify`, — включая кратчайшую обратимую запись
 *   двойной точности. Исходник печатать не нужно: он и так текст.
 * • ИСЧЕЗАЕТ ЛОВУШКА ПОРЯДКА КЛЮЧЕЙ. Схема 1 обязана была сохранять порядок
 *   полей записи в разборе (канонизатор его сортирует, а печать в C несёт
 *   порядок полей) — улика снималась печатью и стоила отладки. У текста
 *   порядка ключей нет вовсе.
 * • ВОЗВРАЩАЮТСЯ МЕСТА. Схема 1 снимала `span` с доводом «места не
 *   содержимое», и на 93 постусловиях библиотеки это дало расхождение печати:
 *   `docs/zettel/zamok-snimaet-mesta-a-generator-ih-pechataet.md`, 337 байт из
 *   76 819 — генератор кода печатает `span` в диагностику нарушенного
 *   постусловия. Исходник в замке даёт при повторном разборе ТЕ ЖЕ места
 *   (`span` — это `{line, column}`, имени файла в нём нет), и расхождение
 *   исчезает не заплаткой, а устройством.
 *
 * Цена исходника против разбора — 15 % объёма (84 931 Б против 73 783 Б на трёх
 * модулях stdlib) и повторный разбор при сборке. Обе платы названы и приняты.
 *
 * ── Формат ──────────────────────────────────────────────────────────────────
 * JSON, как всё в этом дереве (`AGENTS.md`: «JSON is the sole interchange
 * form»), и раскладкой повторяет запись кеша вердиктов (`proofcache.mjs`):
 * номер схемы, содержимое, печать. Печать — не подпись и не доверенный корень,
 * а САМОПРОВЕРКА: адрес каждого модуля пересчитывается по грузу и обязан
 * совпасть. Разошлось — отказ, а не «ну наверное».
 *
 * ── Чего замок НЕ делает, и это названо прямо ───────────────────────────────
 * • Синтаксиса языка он не трогает. Человек пишет `использует «Строки» из
 *   "…"`; замок видит только инструмент.
 * • Обновление — ЦЕЛИКОМ. Вышла новая `strings.flang` — в замок переезжает вся
 *   она, а не строка с новым хешем. Иначе быть не может: в замке лежит код.
 * • Версий и реестра здесь нет. Замок отвечает на вопрос «из чего собрано», а
 *   не «что новее»; на второй вопрос отвечает шаг 3 из
 *   `docs/modularity-and-packages.md`, и до него далеко.
 */
import { createHash } from "node:crypto"
import { readFile } from "node:fs/promises"
import { dirname, isAbsolute, relative, resolve } from "node:path"

import { каноническийJSON } from "./digest.mjs"
import { importsOf } from "./link.mjs"

/**
 * Версия раскладки замка. Меняется — прежние замки перестают приниматься.
 *
 * 1 — груз brotli+base64 от разбора со снятыми местами (до 19 августа 2026);
 * 2 — груз ИСХОДНИКОМ, адрес sha256 по содержимому, сжатия нет вовсе.
 */
export const СХЕМА_ЗАМКА = 2

/** Имя файла замка рядом с входной программой. */
export const ИМЯ_ЗАМКА = "flang.lock"

/**
 * Печать текста — sha256 с приставкой, в которую входит номер схемы.
 *
 * Номер схемы внутри приставки — не украшение: он делает адреса двух схем
 * заведомо разными даже на одном и том же тексте, поэтому груз, переложенный
 * из замка прежней схемы, не может случайно пройти проверку новой.
 *
 * Своя приставка, а не общая с `digest.mjs`: печать замка и адрес определения
 * отвечают на разные вопросы, и путать их одним пространством было бы ошибкой,
 * которую заметят через год.
 */
export function печатьТекста(текст) {
  return createHash("sha256").update(`flang-lock-${СХЕМА_ЗАМКА} ${текст}`, "utf8").digest("hex")
}

/**
 * Печать значения — по каноническому JSON.
 *
 * Годится там, где порядок ключей не значит ничего: список «путь → адрес»
 * состоит из массивов, а у массива порядок и так свой.
 */
export function печать(значение) {
  return печатьТекста(каноническийJSON(значение))
}

/**
 * АДРЕС МОДУЛЯ — sha256 его исходника.
 *
 * Одна строка, и она делегирует `печатьТекста` намеренно: адрес обязан
 * проверяться ровно тем же действием, каким получен. Два разных способа
 * посчитать одно число — это два способа разойтись.
 *
 * Что в адрес входит: ВЕСЬ текст файла, байт в байт, вместе с примечаниями и
 * переводами строк. Переформатировали зависимость — адрес другой, и это верно:
 * замок отвечает на вопрос «из чего собрано», а собрано было из этих байтов.
 * Места из них печатаются в диагностику напечатанной программы, то есть
 * наблюдаемы, — значит они содержимое.
 */
export function адресМодуля(исходник) {
  return печатьТекста(исходник)
}

/* ──────────────────────────── сборка замка ──────────────────────────────── */

/**
 * Собрать замок для входной программы: обойти импорты по замыканию и положить
 * КОД каждого встреченного модуля.
 *
 * `parse` передаётся снаружи по той же причине, что и в `linkProgram`: выбор
 * функции разбора уже сделан в `bin/flang.mjs`, и второй такой выбор однажды
 * разойдётся с первым. Разбор здесь нужен ровно для двух вещей — обойти
 * импорты и назвать модуль; в замок едет исходник, а не разбор.
 */
export async function собратьЗамок(входнойФайл, parse, настройки = {}) {
  const читать = настройки.readFile ?? ((файл) => readFile(файл, "utf8"))
  const вход = resolve(входнойФайл)
  const корень = настройки.корень ?? dirname(вход)
  const модули = []
  const пройдено = new Set([вход])
  const очередь = []

  const поставить = (изФайла, запись) => {
    const цель = isAbsolute(запись.from) ? запись.from : resolve(dirname(изФайла), запись.from)
    if (пройдено.has(цель)) return
    пройдено.add(цель)
    очередь.push({ файл: цель, имя: запись.category })
  }

  const своё = parse(await читать(вход), вход)
  for (const запись of importsOf(своё)) поставить(вход, запись)

  while (очередь.length > 0) {
    const { файл, имя } = очередь.shift()
    const исходник = await читать(файл)
    const дерево = parse(исходник, файл)
    for (const запись of importsOf(дерево)) поставить(файл, запись)
    модули.push({
      имя: typeof дерево.module === "string" ? дерево.module : имя,
      путь: путёмЗамка(корень, файл),
      функций: (дерево.functions ?? []).length,
      адрес: адресМодуля(исходник),
      исходник,
    })
  }
  /* Порядок — по пути, а не по обходу: замок обязан быть одним и тем же файлом
     при одной и той же программе, иначе `git diff` шумит на пустом месте. */
  модули.sort((л, п) => (л.путь < п.путь ? -1 : л.путь > п.путь ? 1 : 0))
  return {
    схема: СХЕМА_ЗАМКА,
    вход: путёмЗамка(корень, вход),
    модули,
    печать: печать(модули.map((м) => [м.путь, м.адрес])),
  }
}

/** Путь внутри замка — от каталога самого замка и всегда через косую черту. */
function путёмЗамка(корень, файл) {
  const путь = relative(корень, файл).split("\\").join("/")
  return путь.startsWith(".") || путь.startsWith("/") ? путь : `./${путь}`
}

/* ──────────────────────────── чтение замка ──────────────────────────────── */

/**
 * ЗАМОК ПРЕЖНЕЙ СХЕМЫ ОТВЕРГАЕТСЯ ГРОМКО — и текст отказа говорит, что делать.
 *
 * Отдельной функцией, а не строкой на месте, потому что говорить это обязаны
 * оба читателя — и замок, и пакет, — а два текста одного отказа однажды
 * разойдутся. Молчаливое «прочтём как сумеем» здесь хуже всего: груз схемы 1
 * есть base64 от brotli, и попытка разобрать его как исходник дала бы не
 * отказ, а мусор под видом кода.
 */
export function прежняяСхема(что, было, надо, пересобрать) {
  if (было === undefined || было === null) {
    return `${что} без номера схемы: прежним форматом собран или испорчен, а нужна схема ${надо}. Пересоберите: ${пересобрать}`
  }
  return (
    `${что} собран прежним форматом: схема ${JSON.stringify(было)}, а нужна ${надо}. ` + `Пересоберите: ${пересобрать}`
  )
}

/**
 * Разложить замок в карту «полный путь файла → разбор».
 *
 * Всякое сомнение — ОТКАЗ, а не пропуск: у кеша вердиктов промах стоит вызова
 * ядра и потому дёшев, а здесь промах означал бы чтение исходника, которого
 * уже нет. Молчаливое «ну соберём из того, что нашлось» дало бы программу,
 * собранную не из замка, — то есть ровно ту невоспроизводимость, против
 * которой замок и заводился.
 *
 * `parse` передаётся снаружи, как и при сборке: в замке лежит текст, и дерево
 * из него делает та же функция разбора, что и для своих файлов. Второй разбор
 * здесь не плата за схему 2, а перенос той же работы: схема 1 звала
 * `JSON.parse` по распакованному грузу ровно столько же раз.
 */
export function модулиЗамка(замок, корень, parse) {
  if (замок?.схема !== СХЕМА_ЗАМКА) {
    throw new Error(прежняяСхема("замок", замок?.схема, СХЕМА_ЗАМКА, "flang lock <программа> > flang.lock"))
  }
  if (typeof parse !== "function") throw new Error("замку нужна функция разбора: в нём лежит исходник, а не дерево")
  if (!Array.isArray(замок.модули)) throw new Error("в замке нет списка модулей")
  if (замок.печать !== печать(замок.модули.map((м) => [м.путь, м.адрес]))) {
    throw new Error("печать замка не сходится: замок правлен или испорчен")
  }
  const карта = new Map()
  for (const модуль of замок.модули) {
    карта.set(resolve(корень, модуль.путь), разборМодуля(модуль, parse, "замке"))
  }
  return карта
}

/**
 * Одна запись груза → разбор, со всеми отказами.
 *
 * Общая у замка и пакета намеренно: проверок здесь три, и пакет, проверяющий
 * две из трёх, был бы дырой ровно в том месте, где её никто не ищет.
 */
export function разборМодуля(модуль, parse, где) {
  if (typeof модуль?.исходник !== "string") throw new Error(`в ${где} у модуля «${модуль?.имя}» нет исходника`)
  /* Адрес пересчитывается, а не читается: запись обязана сама сказать, что в
     ней лежит, и сказанное обязано совпасть с грузом до последнего байта. */
  if (адресМодуля(модуль.исходник) !== модуль.адрес) {
    throw new Error(`адрес модуля «${модуль.имя}» не сходится с его исходником: правлен или испорчен`)
  }
  let дерево = null
  try {
    дерево = parse(модуль.исходник, модуль.путь)
  } catch (беда) {
    throw new Error(
      `модуль «${модуль.имя}» из ${где} не разбирается: ${беда instanceof Error ? беда.message : String(беда)}`,
    )
  }
  const настоящее = typeof дерево.module === "string" ? дерево.module : null
  if (настоящее !== null && настоящее !== модуль.имя) {
    throw new Error(`в ${где} модуль назван «${модуль.имя}», а в исходнике он «${настоящее}»`)
  }
  return дерево
}
