/**
 * @param {object} options
 *   `send` — куда уходит готовое сообщение JSON-RPC (обязателен);
 *   `readFile` — чтение импортируемых модулей с диска (подменяется в тестах);
 *   `exit` — что делать на `exit` (по умолчанию завершить процесс).
 */
export function createServer(options = {}) {
  const с = {
    отправить: options.send ?? (() => {}),
    сДиска: options.readFile ?? ((путь) => прочитатьФайл(путь, "utf8")),
    завершить: options.exit ?? ((код) => process.exit(код)),
    /* Открытые буферы: адрес → { uri, путь, текст, версия, разбор }. */
    документы: new Map(),
    /* Путь → адрес: импортируемый модуль ищется по пути, а адрес нужен, чтобы
       диагностика уехала в тот же буфер, каким его открыл редактор. */
    поПути: new Map(),
    /* Что и от чьего имени опубликовано: два открытых файла могут ругаться на
       один и тот же импортируемый модуль, и снимая свою диагностику, нельзя
       снять заодно чужую. */
    опубликовано: new Map(),
    /* Номер разбора на документ: ответ устаревшего разбора публиковать нельзя,
       иначе редактор покажет ошибки позапрошлой версии текста. */
    поколения: new Map(),
    готов: false,
    закрывается: false,
  }

  return {
    receive: (сообщение) => принять(с, сообщение),
    /** Для тестов и отладки: что сервер считает содержимым буфера. */
    document: (uri) => с.документы.get(uri),
  }
}

/* ──────────────────────────────── JSON-RPC ──────────────────────────────── */

async function принять(с, сообщение) {
  if (сообщение === null || typeof сообщение !== "object" || typeof сообщение.method !== "string") return
  const запрос = сообщение.id !== undefined && сообщение.id !== null

  try {
    const результат = await вызвать(с, сообщение.method, сообщение.params ?? {}, запрос)
    if (запрос) отправить(с, { jsonrpc: "2.0", id: сообщение.id, result: результат === undefined ? null : результат })
  } catch (ошибка) {
    /* Сбой на одном запросе не имеет права уронить сервер: редактор останется
       без ответа на всё остальное, а человек — без объяснения. */
    if (запрос) {
      отправить(с, {
        jsonrpc: "2.0",
        id: сообщение.id,
        error: { code: ошибка?.rpc ?? -32603, message: ошибка instanceof Error ? ошибка.message : String(ошибка) },
      })
      return
    }
    сообщитьВЖурнал(с, `${сообщение.method}: ${ошибка instanceof Error ? ошибка.message : String(ошибка)}`)
  }
}

async function вызвать(с, метод, параметры, запрос) {
  /* До рукопожатия сервер не отвечает ни на что: он ещё не знает, с кем
     говорит. Молчать нельзя — редактор будет ждать вечно, — поэтому отказ с
     кодом «сервер не инициализирован» из спецификации. */
  if (!с.готов && метод !== "initialize" && метод !== "exit") {
    if (!запрос) return undefined
    throw Object.assign(new Error("сервер ещё не инициализирован"), { rpc: -32002 })
  }

  switch (метод) {
    case "initialize":
      с.готов = true
      return приветствие()
    case "initialized":
      return undefined
    case "shutdown":
      с.закрывается = true
      return null
    case "exit":
      с.завершить(с.закрывается ? 0 : 1)
      return undefined

    case "textDocument/didOpen":
      return открыть(с, параметры)
    case "textDocument/didChange":
      return изменить(с, параметры)
    case "textDocument/didSave":
      return сохранён(с, параметры)
    case "textDocument/didClose":
      return закрыть(с, параметры)

    case "textDocument/completion":
      return дополнение(с, параметры)
    case "textDocument/hover":
      return наведение(с, параметры)
    case "textDocument/definition":
      return переход(с, параметры)

    default:
      /* Неизвестное уведомление молча пропускается — так требует протокол;
         неизвестный запрос обязан получить отказ, иначе редактор будет ждать
         ответа вечно. */
      if (!запрос) return undefined
      throw Object.assign(new Error(`метод не поддержан: ${метод}`), { rpc: -32601 })
  }
}

function приветствие() {
  return {
    capabilities: {
      /* Позиции считаются в единицах UTF-16 — как и требует протокол по
         умолчанию, и как их уже считает лексер flang (столбец растёт на каждой
         единице строки JS). Второго пересчёта не нужно. */
      positionEncoding: "utf-16",
      /* Синхронизация целым текстом: разбор всё равно идёт от начала файла, а
         приращения дали бы вторую модель документа и вторую же возможность
         разойтись с редактором. */
      textDocumentSync: { openClose: true, change: 1, save: { includeText: false } },
      completionProvider: { triggerCharacters: ["«", "."] },
      hoverProvider: true,
      definitionProvider: true,
    },
    serverInfo: { name: SERVER_NAME, version: "0.1.0" },
  }
}

function отправить(с, сообщение) {
  с.отправить(сообщение)
}

function сообщитьВЖурнал(с, текст) {
  отправить(с, { jsonrpc: "2.0", method: "window/logMessage", params: { type: 1, message: текст } })
}

/* ─────────────────────────────── документы ──────────────────────────────── */

async function открыть(с, параметры) {
  const документ = параметры?.textDocument
  if (документ?.uri === undefined) return
  положить(с, документ.uri, документ.text ?? "", документ.version ?? 0)
  await проверить(с, документ.uri)
}

async function изменить(с, параметры) {
  const uri = параметры?.textDocument?.uri
  const текущий = с.документы.get(uri)
  if (текущий === undefined) return
  /* Синхронизация полная: последнее изменение и есть весь текст. Если редактор
     всё же прислал приращение, честнее ничего не менять, чем склеить текст
     наполовину и проверять выдуманный файл. */
  const целиком = (параметры.contentChanges ?? []).filter((к) => к?.range === undefined).pop()
  if (целиком === undefined) return
  положить(с, uri, целиком.text ?? "", параметры.textDocument.version ?? текущий.версия + 1)
  await проверить(с, uri)
}

async function сохранён(с, параметры) {
  const uri = параметры?.textDocument?.uri
  /* Сохранение соседнего файла меняет то, что видит импорт, а изменения в нём
     редактор нам не присылал: перепроверяем всё открытое. */
  if (с.документы.has(uri)) for (const открытый of [...с.документы.keys()]) await проверить(с, открытый)
}

async function закрыть(с, параметры) {
  const uri = параметры?.textDocument?.uri
  const документ = с.документы.get(uri)
  if (документ === undefined) return
  с.документы.delete(uri)
  с.поПути.delete(документ.путь)
  с.поколения.delete(uri)
  /* Закрытый файл больше ни за что не отвечает — снимаем всё, что он показал,
     включая диагностику импортированных модулей. */
  разнести(с, uri, new Map())
}

function положить(с, uri, текст, версия) {
  const путь = кПути(uri)
  const документ = с.документы.get(uri) ?? { uri, путь, разбор: null }
  документ.текст = текст
  документ.версия = версия
  с.документы.set(uri, документ)
  if (путь !== null) с.поПути.set(путь, uri)
}

/* ─────────────────────────────── диагностика ────────────────────────────── */

/**
 * Разбор и проверка одного открытого документа.
 *
 * Импортируемые модули читаются сначала из открытых буферов и только потом с
 * диска: иначе сервер показывал бы ошибки по сохранённой версии соседнего
 * файла, которую человек уже правит на экране.
 */
async function проверить(с, uri) {
  const документ = с.документы.get(uri)
  if (документ === undefined || документ.путь === null) return

  const поколение = (с.поколения.get(uri) ?? 0) + 1
  с.поколения.set(uri, поколение)

  /* Тексты прочитанных модулей нужны потом, чтобы у диагностики в чужом файле
     был не огрызок в один символ, а подчёркнутое слово. */
  const тексты = new Map([[документ.путь, документ.текст]])
  const чтение = async (путь) => {
    const полный = resolve(путь)
    const открытый = с.документы.get(с.поПути.get(полный) ?? "")
    const текст = открытый?.текст ?? (await с.сДиска(полный))
    тексты.set(полный, текст)
    return текст
  }

  let итог
  try {
    итог = await checkSource(документ.путь, документ.текст, { readFile: чтение })
  } catch (ошибка) {
    итог = {
      program: null,
      diagnostics: [{ code: "FLANG_INTERNAL", severity: "error", message: сообщение(ошибка) }],
      total: new Set(),
      signatures: new Map(),
    }
  }

  /* Пока шла проверка, текст мог измениться ещё раз: ответ устарел. */
  if (с.поколения.get(uri) !== поколение) return

  /* Программа последнего УДАЧНОГО разбора остаётся жить: пока человек дописывает
     строку, текст не разбирается почти никогда, а дополнение и наведение нужны
     именно в этот момент. Показывать при этом старую диагностику нельзя — она
     и не показывается, диагностика всегда от текущего текста. */
  if (итог.program !== null) {
    документ.разбор = { программа: итог.program, сигнатуры: итог.signatures, тотальные: итог.total }
  }

  разнести(с, uri, разложитьПоФайлам(с, документ, итог.diagnostics, тексты))
}

/**
 * Диагностика → «в каком буфере её показать».
 *
 * Правило одно: решает имя файла в месте. Диагностику, у которой места нет
 * вовсе, показать негде — и она уходит в журнал редактора текстом, а не
 * подчёркиванием в первой попавшейся строке. Такое сообщение всегда называет
 * файл словами («тип «X» объявлен в двух модулях: A и B»), и приписать ему
 * строку значило бы указать мимо.
 */
function разложитьПоФайлам(с, документ, диагностики, тексты) {
  const поФайлам = new Map()
  for (const диагностика of диагностики ?? []) {
    const файл = диагностика?.span?.file
    if (!уМестаЕстьСтрока(диагностика) || файл === undefined) {
      сообщитьВЖурнал(с, `${диагностика?.code ?? "FLANG"}: ${диагностика?.message ?? ""}`)
      continue
    }
    const адрес = с.поПути.get(файл) ?? кАдресу(файл)
    if (адрес === null) continue
    const список = поФайлам.get(адрес) ?? []
    список.push(вДиагностикуLSP(диагностика, тексты.get(файл)))
    поФайлам.set(адрес, список)
  }
  /* Открытый файл обязан получить ответ всегда, даже пустой: иначе прошлые
     подчёркивания останутся на экране после того, как ошибку починили. */
  if (!поФайлам.has(документ.uri)) поФайлам.set(документ.uri, [])
  return поФайлам
}

function уМестаЕстьСтрока(диагностика) {
  return typeof диагностика?.span?.line === "number"
}

function вДиагностикуLSP(диагностика, текст) {
  const результат = {
    range: диапазон(диагностика.span, текст),
    severity: УРОВЕНЬ[диагностика.severity] ?? 1,
    message: диагностика.message ?? "",
    source: "flang",
  }
  if (typeof диагностика.code === "string") результат.code = диагностика.code
  return результат
}

/**
 * Публикация с учётом того, что владельцев у одного файла может быть несколько.
 *
 * Два открытых файла, импортирующих один модуль, оба вправе сказать о нём своё.
 * Публикуется объединение, а снимает каждый только своё — иначе починка одного
 * файла стирала бы с экрана ошибки, найденные другим.
 */
function разнести(с, владелец, поФайлам) {
  const затронутые = new Set(поФайлам.keys())
  for (const [адрес, отВладельцев] of с.опубликовано) {
    if (отВладельцев.has(владелец)) затронутые.add(адрес)
  }

  for (const адрес of затронутые) {
    const отВладельцев = с.опубликовано.get(адрес) ?? new Map()
    const свои = поФайлам.get(адрес) ?? []
    if (свои.length === 0) отВладельцев.delete(владелец)
    else отВладельцев.set(владелец, свои)

    const всё = [...отВладельцев.values()].flat()
    if (отВладельцев.size === 0) с.опубликовано.delete(адрес)
    else с.опубликовано.set(адрес, отВладельцев)
    отправить(с, {
      jsonrpc: "2.0",
      method: "textDocument/publishDiagnostics",
      params: { uri: адрес, diagnostics: всё },
    })
  }
}

/* ─────────────────────────────── дополнение ─────────────────────────────── */

async function дополнение(с, параметры) {
  const документ = с.документы.get(параметры?.textDocument?.uri)
  if (документ === undefined) return { isIncomplete: false, items: [] }

  const строкиТекста = строки(документ.текст)
  const позиция = параметры.position ?? { line: 0, character: 0 }
  const строка = строкиТекста[позиция.line] ?? ""
  const символ = Math.min(позиция.character ?? 0, строка.length)
  const слово = началоСлова(строка.slice(0, символ))
  /* Уже набранное `«…»` заменяется целиком: иначе получилось бы `«Удвоить»»`. */
  const конец = строка[символ] === "»" ? символ + 1 : символ
  const область = {
    start: { line: позиция.line, character: слово.начало },
    end: { line: позиция.line, character: конец },
  }
  const вЁлочках = слово.текст.startsWith("«")

  const элементы = собратьДополнение(документ, строкиТекста, позиция, слово, вЁлочках)
  return {
    isIncomplete: false,
    items: элементы.map((элемент) => ({
      label: элемент.label,
      kind: элемент.kind,
      detail: элемент.detail,
      documentation: элемент.documentation,
      sortText: элемент.sortText,
      filterText: элемент.label,
      textEdit: { range: область, newText: элемент.insert ?? элемент.label },
    })),
  }
}

function собратьДополнение(документ, строкиТекста, позиция, слово, вЁлочках) {
  const программа = документ.разбор?.программа ?? null
  const строка = строкиТекста[позиция.line] ?? ""
  const до = строка.slice(0, Math.min(позиция.character ?? 0, строка.length))
  const передСловом = до.slice(0, слово.начало)

  /* Поле записи: слева от набираемого стоит точка. Чей это тип — решается по
     параметру функции, в теле которой стоит курсор; если решить не удалось,
     предлагаются поля всех записей, и каждое названо своим типом. Предложить
     лишнее — небольшая беда; не предложить ничего — беда ровно та, ради
     которой дополнение и делают. */
  if (передСловом.endsWith(".")) {
    const цель = имяВМесте(передСловом.slice(0, -1), передСловом.length - 1)
    return поляЗаписей(программа, типИмени(документ, программа, позиция.line, цель?.name), вЁлочках)
  }

  /* Вариант суммы: строка начинается со `случай`. Разбираемое значение ищется
     выше по тексту — у `разбор`, к которому этот `случай` относится. */
  if (/^\s*(?:случай|case)\s/u.test(до)) {
    const цель = целиРазбора(строкиТекста, позиция.line)
    return вариантыСумм(программа, типИмени(документ, программа, позиция.line, цель), вЁлочках)
  }

  return [...именаМодуля(документ, программа, вЁлочках), ...ключевыеСлова()]
}

/** Ключевые слова — прямо из таблицы лексера, всеми её поверхностями. */
function ключевыеСлова() {
  const элементы = []
  for (const [идентификатор, поверхности] of Object.entries(KEYWORDS)) {
    for (const поверхность of поверхности) {
      элементы.push({
        label: поверхность,
        kind: ВИД.слово,
        detail: `ключевое слово (${идентификатор})`,
        sortText: `3${поверхность}`,
      })
    }
  }
  return элементы
}

/** Имена объявлений: сначала свои, потом пришедшие по `использует`. */
function именаМодуля(документ, программа, вЁлочках) {
  return объявления(программа).map((объявление) => {
    const своё = объявление.узел?.span?.file === документ.путь
    return {
      label: оформитьИмя(объявление.имя, вЁлочках),
      kind: видОбъявления(объявление),
      detail: `${объявление.вид}${своё ? "" : ` из ${короткийПуть(объявление.узел?.span?.file)}`}`,
      documentation: описание(объявление, документ.разбор),
      sortText: `${своё ? "1" : "2"}${объявление.имя}`,
    }
  })
}

function поляЗаписей(программа, имяТипа, вЁлочках) {
  const записи = (программа?.types ?? []).filter((тип) => тип?.kind === "record")
  const нужные = имяТипа === null ? записи : записи.filter((запись) => запись.name === имяТипа)
  const источник = нужные.length > 0 ? нужные : записи
  const элементы = []
  const видели = new Set()
  for (const запись of источник) {
    for (const поле of запись.fields ?? []) {
      const ключ = `${запись.name}·${поле.name}`
      if (видели.has(ключ)) continue
      видели.add(ключ)
      элементы.push({
        label: оформитьИмя(поле.name, вЁлочках),
        kind: ВИД.поле,
        detail: `${описатьТип(поле.type)} — поле записи «${запись.name}»`,
        sortText: `0${поле.name}`,
      })
    }
  }
  return элементы
}

function вариантыСумм(программа, имяТипа, вЁлочках) {
  const суммы = (программа?.types ?? []).filter((тип) => тип?.kind === "sum")
  const нужные = имяТипа === null ? суммы : суммы.filter((сумма) => сумма.name === имяТипа)
  const источник = нужные.length > 0 ? нужные : суммы
  const элементы = []
  for (const сумма of источник) {
    for (const вариант of сумма.variants ?? []) {
      элементы.push({
        label: оформитьИмя(вариант.name, вЁлочках),
        kind: ВИД.вариант,
        detail: `вариант «${сумма.name}»${поляВарианта(вариант)}`,
        sortText: `0${вариант.name}`,
      })
    }
  }
  return элементы
}

function поляВарианта(вариант) {
  const поля = вариант.fields ?? []
  return поля.length === 0 ? "" : ` с ${поля.map((поле) => `${поле.name}: ${описатьТип(поле.type)}`).join(", ")}`
}

/**
 * Имя, к которому относится ближайший сверху `разбор`.
 *
 * Идём вверх по строкам с меньшим отступом — так же, как это видит человек:
 * `случай` принадлежит тому `разбор`, под которым он написан.
 */
function целиРазбора(строкиТекста, номер) {
  const свой = отступ(строкиТекста[номер] ?? "")
  for (let i = номер - 1; i >= 0; i -= 1) {
    const строка = строкиТекста[i]
    if (строка === undefined || строка.trim() === "") continue
    if (отступ(строка) >= свой) continue
    const совпадение = /(?:^|\s)(?:разбор|match)\s+(.+)$/u.exec(строка)
    if (совпадение === null) return null
    const хвост = совпадение[1].trim()
    const имя = /^«([^»]*)»/u.exec(хвост) ?? /^"([^"]*)"/u.exec(хвост) ?? /^([\p{L}\p{N}_-]+)/u.exec(хвост)
    return имя === null ? null : имя[1]
  }
  return null
}

function отступ(строка) {
  return /^[ \t]*/u.exec(строка)[0].length
}

/**
 * Тип имени в точке текста: параметр функции, в теле которой стоит курсор.
 *
 * Дальше параметров сервер не идёт намеренно. Вывести тип произвольного
 * выражения умеет types.mjs, но только по разобранной программе — а дополняют
 * как раз тогда, когда текст ещё не разбирается. Обещать вывод и молчать при
 * каждой недописанной строке было бы хуже, чем не обещать.
 */
function типИмени(документ, программа, номерСтроки, имя) {
  if (typeof имя !== "string" || имя === "") return null
  const функция = охватывающаяФункция(документ, программа, номерСтроки)
  const параметр = (функция?.params ?? []).find((п) => п.name === имя)
  if (параметр !== undefined) {
    /* `принимает Покупка` — форма утилиты FTS: имя параметра и есть имя записи,
       и парсер уже записал его типом, так что отдельной ветки ей не надо. У
       скаляра полей нет вовсе — тогда честнее сказать «не знаю» и показать всё,
       чем показать поля наугад выбранной записи. */
    return параметр.type?.kind === "named" ? параметр.type.name : null
  }
  /* Слово оказалось именем типа — например, курсор не в теле функции, а имя
     записи набрано прямо. Полей у неё ровно столько же. */
  return (программа?.types ?? []).some((тип) => тип.name === имя) ? имя : null
}

function охватывающаяФункция(документ, программа, номерСтроки) {
  let найдена = null
  for (const fn of программа?.functions ?? []) {
    const место = fn?.span
    if (место?.file !== документ.путь || typeof место.line !== "number") continue
    if (место.line - 1 > номерСтроки) continue
    if (найдена === null || место.line > найдена.span.line) найдена = fn
  }
  return найдена
}

/* ──────────────────────────────── наведение ─────────────────────────────── */

function наведение(с, параметры) {
  const найдено = объявлениеВТочке(с, параметры)
  if (найдено === null) return null
  const { документ, объявление, слово, строка } = найдено
  const текст = [
    "```flang",
    поверхность(объявление, документ.разбор),
    "```",
    ...дополнительно(объявление, документ),
  ]
  return {
    contents: { kind: "markdown", value: текст.join("\n") },
    range: {
      start: { line: строка, character: слово.начало },
      end: { line: строка, character: слово.конец },
    },
  }
}

/**
 * Объявление — поверхностью самого языка.
 *
 * Не «Function<number, number>» и не «(x: number) => number»: человек читает то
 * же, что пишет. Типы называются словами types.mjs (`typeName`), а не своими —
 * второго словаря у языка быть не должно.
 */
function поверхность(объявление, разбор) {
  const узел = объявление.узел
  switch (объявление.вид) {
    case "функция": {
      const сигнатура = разбор?.сигнатуры?.get(объявление.имя)
      const строки = [`${узел.total === true ? "тотальная функция" : "функция"} «${объявление.имя}»`]
      const параметры = сигнатура?.params ?? (узел.params ?? []).map((п) => ({ name: п.name, type: null, ast: п.type }))
      if (параметры.length > 0) {
        строки.push(
          `  принимает ${параметры
            .map((п) => `${п.name}: ${п.type === null ? описатьТип(п.ast) : typeName(п.type)}`)
            .join(", ")}`,
        )
      }
      const возврат = сигнатура === undefined ? описатьТип(узел.returns) : typeName(сигнатура.returns)
      строки.push(`  возвращает ${возврат}`)
      return строки.join("\n")
    }
    case "запись":
      return [`запись «${объявление.имя}»`, ...(узел.fields ?? []).map((п) => `  ${п.name}: ${описатьТип(п.type)}`)]
        .join("\n")
    case "тип":
      return узел.kind === "alias"
        ? `тип «${объявление.имя}» это ${описатьТип(узел.of)}`
        : [`тип «${объявление.имя}»`, ...(узел.variants ?? []).map((в) => `  вариант ${в.name}${поляВарианта(в)}`)]
          .join("\n")
    case "морфизм":
      return узел.kind === "composition"
        ? `морфизм «${объявление.имя}» это «${узел.left}» после «${узел.right}»`
        : `морфизм «${объявление.имя}» из «${узел.domain ?? узел.value?.domain}» в «${узел.codomain ?? узел.value?.codomain}»`
    case "процесс":
      return [
        `процесс «${объявление.имя}»`,
        `  состояние «${узел.state}»`,
        `  начинает с «${узел.initial}»`,
        `  принимает «${узел.accepts}»`,
        `  обрабатывает «${узел.handler}»${узел.budget === null ? "" : ` с запасом ${узел.budget}`}`,
      ].join("\n")
    case "надзор":
      return [
        `надзор «${объявление.имя}»`,
        ...(узел.watch ?? []).map((п) => `  процесс «${п.process}» стратегия «${п.strategy}»`),
        /* Вложенные надзоры показываются наравне с процессами: без них в
           подсказке не видно, куда ведёт «передать выше». */
        ...(узел.nested ?? []).map((н) => `  надзор «${н.supervisor}» стратегия «${н.strategy}»`),
        ...(узел.threshold === null || узел.threshold === undefined
          ? []
          : [`  порог отказов ${узел.threshold.failures} за ${узел.threshold.window} иначе «${узел.threshold.otherwise}»`]),
      ].join("\n")
    case "прогон":
      /* Сетка семян показывается сеткой, а не первым её семенем: подсказка,
         которая пишет «семя 1» там, где в исходнике «семя от 1 до 1000»,
         скрывает от читателя ровно то, чем этот прогон отличается от соседнего. */
      return [
        `прогон «${объявление.имя}»`,
        узел.seedTo === null || узел.seedTo === undefined
          ? `  семя ${узел.seed}`
          : `  семя от ${узел.seed} до ${узел.seedTo}`,
      ].join("\n")
    default:
      return `${объявление.вид} «${объявление.имя}»`
  }
}

/**
 * Про функцию говорится главное: доказано ли завершение.
 *
 * Ответов три, а не два, и это не педантизм. Слово «тотальная» в объявлении —
 * просьба доказать, а не доказательство: `checkTotality` может её отвергнуть, и
 * тогда рядом уже висит диагностика. Сказать в такой момент «завершение
 * доказано» значило бы соврать ровно там, где человек и смотрит, — поэтому
 * отдельная фраза для «объявлено, но не доказано». Пересказывать саму причину
 * отказа наведение не берётся: она уже сказана диагностикой, своими словами и
 * на своей строке.
 */
function дополнительно(объявление, документ) {
  const строки = []
  if (объявление.вид === "функция") {
    const тотальная = объявление.узел.total === true
    строки.push(
      тотальная && документ.разбор?.тотальные?.has(объявление.имя) === true
        ? "Завершение доказано."
        : тотальная
          ? "Завершение объявлено, но в последнем разобранном виде не доказано."
          : "Завершение не доказано: вычисление ограничено лимитом шагов.",
    )
  }
  const файл = объявление.узел?.span?.file
  if (файл !== undefined && файл !== документ.путь) строки.push(`Объявлено в \`${короткийПуть(файл)}\`.`)
  return строки
}

/* ───────────────────────────── переход к месту ──────────────────────────── */

function переход(с, параметры) {
  const найдено = объявлениеВТочке(с, параметры)
  if (найдено === null) return null
  const место = найдено.объявление.узел?.span
  if (место === undefined || место === null || typeof место.line !== "number") return null
  const файл = место.file ?? найдено.документ.путь
  const адрес = с.поПути.get(файл) ?? кАдресу(файл)
  if (адрес === null) return null
  const открытый = с.документы.get(адрес)
  return { uri: адрес, range: диапазон(место, открытый?.текст) }
}

/* ──────────────────────────── общее для обоих ───────────────────────────── */

function объявлениеВТочке(с, параметры) {
  const документ = с.документы.get(параметры?.textDocument?.uri)
  if (документ === undefined || документ.разбор === null) return null
  const позиция = параметры.position ?? { line: 0, character: 0 }
  const текстСтроки = строки(документ.текст)[позиция.line]
  if (текстСтроки === undefined) return null
  const слово = имяВМесте(текстСтроки, Math.min(позиция.character ?? 0, текстСтроки.length))
  if (слово === null) return null
  const объявление = объявления(документ.разбор.программа).find((о) => о.имя === слово.name)
  return объявление === undefined ? null : { документ, объявление, слово, строка: позиция.line }
}

/** Всё, что объявлено программой, одним списком: имя, вид и узел с местом. */
function объявления(программа) {
  const список = []
  for (const тип of программа?.types ?? []) {
    список.push({ вид: тип.kind === "record" ? "запись" : "тип", имя: тип.name, узел: тип })
  }
  for (const fn of программа?.functions ?? []) список.push({ вид: "функция", имя: fn.name, узел: fn })
  for (const узел of программа?.morphisms ?? []) {
    /* Служебные звенья цепочки (`… · шаг 1`) в пространстве имён не живут —
       предлагать и показывать их значило бы выдать сахар за объявление. */
    if (узел?.internal === true) continue
    список.push({ вид: "морфизм", имя: узел.name, узел })
  }
  for (const узел of программа?.processes ?? []) список.push({ вид: "процесс", имя: узел.name, узел })
  for (const узел of программа?.supervisors ?? []) список.push({ вид: "надзор", имя: узел.name, узел })
  for (const узел of программа?.runs ?? []) список.push({ вид: "прогон", имя: узел.name, узел })
  for (const узел of программа?.legacy ?? []) {
    if (узел?.construct === "moduleHeader") continue
    const имя = узел?.value?.name ?? узел?.value?.title
    if (typeof имя !== "string" || имя === "") continue
    список.push({ вид: НАСЛЕДИЕ[узел.construct] ?? узел.construct, имя, узел })
  }
  /* Одноимённых здесь быть не должно — связывание считает это ошибкой, — но
     если они есть, побеждает первое: показать оба места нечем, а показать
     произвольное значило бы увести человека наугад. */
  const видели = new Set()
  const один = []
  for (const объявление of список) {
    if (видели.has(объявление.имя)) continue
    видели.add(объявление.имя)
    один.push(объявление)
  }
  return один
}

function видОбъявления(объявление) {
  switch (объявление.вид) {
    case "функция": case "морфизм": case "утилита": return ВИД.функция
    case "запись": return ВИД.запись
    case "тип": return объявление.узел?.kind === "sum" ? ВИД.сумма : ВИД.запись
    default: return ВИД.переменная
  }
}

function описание(объявление, разбор) {
  if (объявление.вид !== "функция") return undefined
  const сигнатура = разбор?.сигнатуры?.get(объявление.имя)
  if (сигнатура === undefined) return undefined
  const принимает = сигнатура.params.map((п) => `${п.name}: ${typeName(п.type)}`).join(", ")
  return `${принимает === "" ? "без аргументов" : `принимает ${принимает}`} → ${typeName(сигнатура.returns)}`
}

/**
 * Тип из AST разбора — словами types.mjs.
 *
 * Своих слов здесь нет ни одного: узел разбора переводится в то представление,
 * которым types.mjs называет типы в диагностике, и печатает его `typeName`.
 * Запись и сумма печатаются одинаково («Имя» в ёлочках), поэтому различать их
 * в переводе не нужно.
 */
function описатьТип(тип) {
  if (тип === null || тип === undefined) return "не указан"
  return typeName(вНормальный(тип))
}

function вНормальный(тип) {
  if (тип === null || тип === undefined) return { kind: "unknown" }
  switch (тип.kind) {
    case "named": return { kind: "record", name: тип.name }
    case "list": return { kind: "list", of: вНормальный(тип.of) }
    /* Тип функции печатается теми же словами, что в исходнике, — этим занят
       `typeName`, и своих слов у редактора здесь по-прежнему ноль. Записей в
       AST две (словесная и стрелочная), и обе сводятся к одной так же, как в
       `types.mjs`. */
    case "fn": return {
      kind: "fn",
      params: (Array.isArray(тип.params) ? тип.params : тип.from === undefined ? [] : [тип.from]).map(вНормальный),
      returns: вНормальный(тип.returns === undefined ? тип.to : тип.returns),
    }
    case "flag": return { kind: "boolean" }
    case "nothing": return { kind: "null" }
    default: return { kind: тип.kind }
  }
}

/**
 * Имя в тексте: в ёлочках, если оно того требует.
 *
 * Требует оно тогда, когда одним словом не записывается: имя из нескольких
 * слов или имя, совпавшее с ключевым словом. Знание об этом — у лексера
 * (`keywordId`), и спрашиваем мы его, а не свой список.
 */
function оформитьИмя(имя, вЁлочках) {
  if (вЁлочках) return `«${имя}»`
  const однимСловом = /^[\p{L}\p{N}_-]+$/u.test(имя) && keywordId(имя) === null
  return однимСловом ? имя : `«${имя}»`
}

/* ──────────────────────────── текст и позиции ───────────────────────────── */

function строки(текст) {
  return (текст ?? "").split(/\r\n|\r|\n/u)
}

/**
 * Место flang (строка и столбец с единицы) → область LSP (с нуля).
 *
 * Область растягивается до конца слова: место у flang — точка, а точка в
 * редакторе не видна. Если текста файла нет под рукой, подчёркивается один
 * символ — врать шириной не станем.
 */
function диапазон(место, текст) {
  const начало = {
    line: Math.max(0, (место?.line ?? 1) - 1),
    character: Math.max(0, (место?.column ?? 1) - 1),
  }
  const строка = текст === undefined ? undefined : строки(текст)[начало.line]
  if (строка === undefined) {
    return { start: начало, end: { line: начало.line, character: начало.character + 1 } }
  }
  const слово = имяВМесте(строка, Math.min(начало.character, строка.length))
  const конец = слово !== null && слово.начало <= начало.character ? слово.конец : начало.character + 1
  return { start: начало, end: { line: начало.line, character: Math.max(конец, начало.character + 1) } }
}

/**
 * Имя, накрытое позицией.
 *
 * Сначала «…» и "…": в них имя может содержать пробелы («Рассчитать задержку»),
 * и разрезать его по словам значило бы не найти ни одного объявления.
 */
function имяВМесте(строка, символ) {
  for (const [открыть, закрыть] of [["«", "»"], ['"', '"']]) {
    let от = 0
    for (;;) {
      const начало = строка.indexOf(открыть, от)
      if (начало === -1) break
      const конец = строка.indexOf(закрыть, начало + 1)
      if (конец === -1) break
      if (символ >= начало && символ <= конец) {
        return { name: строка.slice(начало + 1, конец), начало, конец: конец + 1 }
      }
      от = конец + 1
    }
  }
  const ЧАСТЬ = /[\p{L}\p{N}_-]/u
  let начало = символ
  while (начало > 0 && ЧАСТЬ.test(строка[начало - 1])) начало -= 1
  let конец = символ
  while (конец < строка.length && ЧАСТЬ.test(строка[конец])) конец += 1
  return начало === конец ? null : { name: строка.slice(начало, конец), начало, конец }
}

/** Что именно заменяет дополнение: набранное слово вместе с открытой ёлочкой. */
function началоСлова(до) {
  const открыта = до.lastIndexOf("«")
  if (открыта > до.lastIndexOf("»")) return { начало: открыта, текст: до.slice(открыта) }
  const хвост = /[\p{L}\p{N}_-]*$/u.exec(до)[0]
  return { начало: до.length - хвост.length, текст: хвост }
}

