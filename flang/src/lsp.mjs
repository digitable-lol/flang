/**
 * lsp.mjs — языковой сервер flang: ядро без транспорта.
 *
 * ── Что он делает и чего не делает ─────────────────────────────────────────
 * Сервер отвечает на четыре вопроса редактора: «что здесь не так»
 * (диагностика), «что можно дописать» (дополнение), «что это принимает и
 * возвращает» (наведение), «где это объявлено» (переход). Больше он не делает
 * ничего: ни правок кода, ни переименования, ни форматирования — обещать их
 * значило бы обещать вторую реализацию языка.
 *
 * ── Почему проверка не своя ────────────────────────────────────────────────
 * Диагностика берётся не из отдельного «быстрого» разбора, а из `checkSource`
 * (repl.mjs) — той же дороги, какой проверяет `flang check` и каждый ввод
 * оболочки. Соблазн написать серверу свою проверку велик: он гоняет её на
 * каждое нажатие. Но разойдись дороги — и редактор начнёт молчать там, где
 * компилятор откажет. Молчащий редактор хуже медленного: он врёт.
 *
 * ── Почему дополнение берёт слова из таблицы ───────────────────────────────
 * Ключевые слова берутся из `KEYWORDS` (lexer.mjs) прямо во время работы, а не
 * переписываются сюда списком. Формы в языке прибавляются постоянно — за одни
 * сутки прибавились «разложить … на символы», «процесс», «надзор», «прогон», —
 * и список-копия разошёлся бы с языком на первой же из них, причём молча.
 *
 * ── Честность про место диагностики ────────────────────────────────────────
 * После связывания «строка 12» сама по себе не значит ничего: файлов много. У
 * места теперь есть имя файла — его проставляет связывание по просьбе того, кто
 * собирается показывать диагностику человеку (`attributeFiles` и `stampFile` в
 * link.mjs), — и сервер разносит диагностику по буферам ПО НЕМУ, а не по тому,
 * какой файл сейчас открыт.
 *
 * Диагностику, у которой места нет вовсе, сервер не рисует в открытом буфере
 * наугад: она уходит в журнал редактора текстом. Подчеркнуть не ту строку — это
 * сказать неправду о конкретном месте; ничего не подчеркнуть — всего лишь не
 * сказать, где именно. Второе честнее.
 *
 * Транспорта этот модуль не знает: он принимает разобранное сообщение JSON-RPC
 * и зовёт `send` с ответом. Поэтому его можно проверить, не запуская процесс —
 * а сам процесс проверяется тестом отдельно и по-настоящему.
 */

