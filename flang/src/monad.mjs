/** Тип-параметр в сыром AST парсера — это `named` без аргументов. */
function этоПараметр(тип, имя) {
  return тип?.kind === "named" && тип.name === имя && !Array.isArray(тип.args)
}

/**
 * Устройство монады из объявлений: тип, его варианты и роли полей.
 *
 * Возвращает `{ узел, тип, ветви }`, где ветвь — вариант суммы с разметкой
 * полей: `несёт` — имя поля типа «А» (или null), `прочие` — остальные поля.
 * Отказ возвращается текстом: у разворачивания и у проверки типов он один и
 * тот же, а вот способ показать его разный — исключение против диагностики.
 */
export function устройствоМонады(узел, types) {
  const тип = (types ?? []).find((кандидат) => кандидат?.name === узел.name)
  if (тип === undefined) return { беда: `типа «${узел.name}» нет` }
  if (тип.kind !== "sum") {
    return {
      беда:
        `«${узел.name}» — не сумма типов, а ${тип.kind === "record" ? "запись" : "псевдоним"}; ` +
        "монада разворачивается разбором по вариантам, а разбирать запись нечем",
    }
  }
  const параметры = Array.isArray(тип.typeParams) ? тип.typeParams : []
  if (!параметры.includes(узел.param)) {
    return {
      беда:
        `у типа «${узел.name}» нет параметра «${узел.param}»` +
        (параметры.length === 0 ? ": тип не параметрический" : `; объявлены ${параметры.map((и) => `«${и}»`).join(", ")}`),
    }
  }

  const ветви = []
  for (const вариант of тип.variants ?? []) {
    const несут = (вариант.fields ?? []).filter((поле) => этоПараметр(поле.type, узел.param))
    for (const поле of вариант.fields ?? []) {
      /* Параметр внутри списка, внутри применения или внутри типа функции —
         это отображение, которого на месте не написать: понадобился бы цикл, а
         значит и продолжение значением. Отказ называет поле поимённо. */
      if (!этоПараметр(поле.type, узел.param) && упоминает(поле.type, узел.param)) {
        return {
          беда:
            `в варианте «${вариант.name}» параметр «${узел.param}» стоит внутри поля «${поле.name}», а не целиком; ` +
            "отображение внутрь списка или внутрь применения на месте не разворачивается",
        }
      }
    }
    if (несут.length > 1) {
      return {
        беда:
          `в варианте «${вариант.name}» параметр «${узел.param}» стоит в ${несут.length} полях; ` +
          "форма `в монаде` разворачивает по одному полю на вариант",
      }
    }
    ветви.push({
      вариант: вариант.name,
      несёт: несут.length === 1 ? несут[0].name : null,
      прочие: (вариант.fields ?? []).filter((поле) => !этоПараметр(поле.type, узел.param)).map((поле) => поле.name),
    })
  }
  if (ветви.length === 0) return { беда: `у типа «${узел.name}» нет ни одного варианта` }
  if (!ветви.some((ветвь) => ветвь.несёт !== null)) {
    return { беда: `ни один вариант «${узел.name}» не содержит поля типа «${узел.param}» — связывать нечего` }
  }
  return { узел, тип, ветви }
}

/** Встречается ли имя параметра где-нибудь в типе — на любой глубине. */
function упоминает(тип, имя) {
  if (тип === null || typeof тип !== "object") return false
  if (тип.kind === "named" && тип.name === имя) return true
  const дети = [тип.of, тип.returns, тип.from, тип.to, ...(тип.args ?? []), ...(тип.params ?? [])]
  return дети.some((ребёнок) => упоминает(ребёнок, имя))
}

