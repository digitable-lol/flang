/**
 * Проверка законов всех монад программы.
 *
 * Законы записаны через СВЯЗЫВАНИЕ, а не через η и μ, и это не пересказ: форма
 * `в монаде` разворачивается именно в связывание, значит проверять надо то, чем
 * автор будет пользоваться. Само связывание собирается здесь ровно так же, как
 * его собирает разворачивание, — `соединение` автора поверх отображения,
 * выведенного из типа, — поэтому красный закон означает беду в объявленных
 * функциях, а не в проверке.
 *
 *   левая единица     связать(возврат(а), к) = к(а)
 *   правая единица    связать(м, возврат)    = м
 *   ассоциативность   связать(связать(м, к), г) = связать(м, х → связать(к(х), г))
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object> }}
 */
export function checkMonadLaws(программа, пределы = {}) {
  const монады = Array.isArray(программа?.monads) ? программа.monads : []
  const diagnostics = []
  const checked = []
  if (монады.length === 0) return { diagnostics, checked }

  const среда = createRuntime(программа, пределы)
  const функции = Array.isArray(программа?.functions) ? программа.functions : []
  /** Вызов по имени с позиционными аргументами; отказ возвращается значением. */
  const звать = (имя, ...аргументы) => {
    const функция = функции.find((кандидат) => кандидат.name === имя)
    if (!функция) return { ошибка: `функции «${имя}» нет` }
    const назван = {}
    функция.params.forEach((параметр, номер) => {
      назван[параметр.name] = аргументы[номер]
    })
    try {
      return { значение: среда.call(имя, назван) }
    } catch (беда) {
      /* Отказ на значении сетки — не нарушение закона, а другое сообщение:
         закон проверить не на чем, и сказать надо именно это. */
      return { ошибка: беда?.message ?? String(беда) }
    }
  }

  for (const узел of монады) {
    const устройство = устройствоМонады(узел, программа.types)
    /* Про негодное устройство уже сказал `checkTypes`; повторять его словами
       здесь значило бы показать автору одну беду дважды. */
    if (устройство.беда !== undefined) continue

    const сказать = (код, текст) => {
      diagnostics.push({ code: код, message: `монада «${узел.name}»: ${текст}`, severity: "error", span: узел.span })
    }
    const возврат = (значение) => звать(узел.unit, значение)
    /* Связывание собирается ровно так же, как его собирает разворачивание:
       отображение по устройству типа, затем объявленное автором соединение.
       Значит красный закон означает беду в объявленных функциях, а не здесь. */
    const связать = (м, к) => {
      const отображено = отобразитьЗначение(устройство, м, к)
      if (отображено.ошибка !== undefined) return отображено
      return звать(узел.join, отображено.значение)
    }

    const { значения, простые, стрелки } = сетка(узел, устройство, программа, звать)
    if (значения.length === 0 || простые.length === 0) {
      сказать(
        "FLANG_MONAD",
        `сетку строить не из чего: ни у «${узел.unit}», ни у «${узел.join}», ни у стрелок Клейсли ` +
          "нет примеров — законы проверить не на чем",
      )
      continue
    }

    /* Левая единица — первой: она линейна по сетке и ломается чаще прочих,
       потому что о «возврат» думают в последнюю очередь. */
    левая: for (const а of простые) {
      const обёрнуто = возврат(а)
      if (обёрнуто.ошибка) {
        сказать("FLANG_MONAD", `возврат отказал на ${покажи(а)}: ${обёрнуто.ошибка}`)
        break
      }
      for (const стрелка of стрелки) {
        const слева = связать(обёрнуто.значение, стрелка.звать)
        const справа = стрелка.звать(а)
        if (слева.ошибка || справа.ошибка) continue
        if (!valuesEqual(слева.значение, справа.значение)) {
          сказать(
            "FLANG_MONAD_LEFT_UNIT",
            `левая единица нарушена: связать(возврат(${покажи(а)}), «${стрелка.имя}») дало ` +
              `${покажи(слева.значение)}, а «${стрелка.имя}» от ${покажи(а)} даёт ${покажи(справа.значение)}`,
          )
          break левая
        }
      }
    }

    for (const м of значения) {
      const слева = связать(м, возврат)
      if (слева.ошибка) continue
      if (!valuesEqual(слева.значение, м)) {
        сказать(
          "FLANG_MONAD_RIGHT_UNIT",
          `правая единица нарушена: связать(${покажи(м)}, возврат) дало ${покажи(слева.значение)}, а обязано было ` +
            `вернуть само ${покажи(м)}`,
        )
        break
      }
    }

    let троек = 0
    авария: for (const м of значения) {
      for (const к of стрелки) {
        for (const г of стрелки) {
          троек += 1
          const первое = связать(м, к.звать)
          if (первое.ошибка) continue
          const слева = связать(первое.значение, г.звать)
          /* Правая часть — та самая стрелка Клейсли, которую в языке негде
             записать значением: здесь она обычное замыкание JavaScript, потому
             что проверка живёт в компиляторе, а не в проверяемой программе. */
          const справа = связать(м, (значение) => {
            const шаг = к.звать(значение)
            return шаг.ошибка !== undefined ? шаг : связать(шаг.значение, г.звать)
          })
          if (слева.ошибка || справа.ошибка) continue
          if (!valuesEqual(слева.значение, справа.значение)) {
            сказать(
              "FLANG_MONAD_ASSOC",
              `связывание не ассоциативно: на ${покажи(м)}, «${к.имя}», «${г.имя}» слева вышло ` +
                `${покажи(слева.значение)}, справа ${покажи(справа.значение)}`,
            )
            break авария
          }
        }
      }
    }

    checked.push({
      monad: узел.name,
      values: значения.length,
      plain: простые.length,
      arrows: стрелки.map((стрелка) => стрелка.имя),
      triples: троек,
    })
  }

  return { diagnostics, checked }
}

/**
 * Отображение эндофунктора над ЗНАЧЕНИЕМ — то же правило, что печатает
 * `отображение` выше, только применённое к вычисленному варианту.
 */
function отобразитьЗначение(устройство, значение, к) {
  if (!isVariant(значение)) return { ошибка: `${покажи(значение)} — не вариант «${устройство.тип.name}»` }
  const ветвь = устройство.ветви.find((кандидат) => кандидат.вариант === значение.variant)
  if (ветвь === undefined) return { ошибка: `варианта «${значение.variant}» у «${устройство.тип.name}» нет` }
  const поля = { ...(значение.fields ?? {}) }
  if (ветвь.несёт !== null) {
    const шаг = к(поля[ветвь.несёт])
    if (шаг.ошибка !== undefined) return шаг
    поля[ветвь.несёт] = шаг.значение
  }
  return { значение: variant(значение.variant, поля) }
}

/**
 * Сетка: значения монады, значения «внутри» и стрелки Клейсли.
 *
 * Берётся оттуда же, откуда её берёт моноид, — из примеров, написанных
 * автором. Довод тот же и он важнее удобства: примеры пишет тот, кто знает
 * краевые случаи, а на случайных значениях «Возможно» ассоциативно всегда,
 * потому что случайное значение почти никогда не «Нет».
 *
 * Стрелка Клейсли — объявленная функция ОДНОГО аргумента, у которой аргумент не
 * монада, а результат — применение того же типа. Условие про аргумент не
 * придирка: `«Умножить значение»` ведёт из «Возможно» в «Возможно», и подставь
 * её сюда — каждый вызов отказывал бы, а закон молча считался бы проверенным.
 *
 * Сам `возврат` стоит в списке последним и входит всегда: без него
 * ассоциативность не проверялась бы на тождественном шаге.
 */
function сетка(узел, устройство, программа, звать) {
  const функции = Array.isArray(программа?.functions) ? программа.functions : []
  const значения = []
  const простые = []
  const добавить = (куда, значение) => {
    if (значение === undefined) return
    if (куда.some((готовое) => valuesEqual(готовое, значение))) return
    куда.push(значение)
  }
  const этоВариантМонады = (значение) =>
    isVariant(значение) && устройство.ветви.some((ветвь) => ветвь.вариант === значение.variant)

  const разложить = (сырое) => {
    /* Значение примера лежит в AST обычным объектом `{variant, fields}`, а
       вычислитель отдаёт `FlangVariant`, и `valuesEqual` их РАЗЛИЧАЕТ. Без
       этого приведения правая единица падала бы на паре тождественных с виду
       значений — измерено, а не предположено. */
    const значение = reifyValue(сырое)
    if (!этоВариантМонады(значение)) {
      добавить(простые, значение)
      return
    }
    добавить(значения, значение)
    const ветвь = устройство.ветви.find((кандидат) => кандидат.вариант === значение.variant)
    /* Значение из-под варианта годится в «простые» только если само не монада:
       у вложенного M(M«А») внутри лежит монада, а не «А», и подставить её в
       `возврат` значило бы проверять закон не на том типе. */
    if (ветвь.несёт !== null) {
      const внутри = (значение.fields ?? {})[ветвь.несёт]
      if (!этоВариантМонады(внутри)) добавить(простые, внутри)
    }
  }

  const стрелки = []
  const датьСтрелку = (функция) => {
    if (стрелки.some((готовая) => готовая.имя === функция.name)) return
    стрелки.push({ имя: функция.name, звать: (значение) => звать(функция.name, значение) })
  }
  const этоСтрелка = (функция) =>
    функция.params.length === 1 &&
    ведётВМонаду(функция.returns, узел.name) &&
    !ведётВМонаду(функция.params[0].type, узел.name)

  for (const функция of функции) {
    const своя = функция.name === узел.unit || функция.name === узел.join
    const клейсли = этоСтрелка(функция)
    if (!своя && !клейсли) continue
    for (const пример of функция.examples ?? []) {
      for (const значение of Object.values(пример.args ?? {})) разложить(значение)
      разложить(пример.expected)
    }
    if (клейсли && функция.name !== узел.unit) датьСтрелку(функция)
  }
  const единица = функции.find((функция) => функция.name === узел.unit)
  if (единица !== undefined && единица.params.length === 1) датьСтрелку(единица)

  return {
    значения: значения.slice(0, ПРЕДЕЛ_СЕТКИ),
    простые: простые.slice(0, ПРЕДЕЛ_СЕТКИ),
    стрелки: стрелки.slice(0, ПРЕДЕЛ_СТРЕЛОК),
  }
}

/** Тип — применение объявленного типа монады: `«Возможно» от чего-нибудь`. */
function ведётВМонаду(тип, имя) {
  return тип?.kind === "named" && тип.name === имя
}

/**
 * Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт.
 *
 * Порог 72, а не 40, как у моноида, и это не разнобой: у моноида носитель
 * скалярный, а здесь всякое значение — вариант, и на сорока символах от
 * `{"variant":"Есть","fields":{"значение":7}}` остаётся одно многоточие.
 * Контрпример, который не видно, контрпримером не является.
 */
function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 72 ? `${текст.slice(0, 69)}…` : текст
}
