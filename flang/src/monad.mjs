/**
 * Заменить все узлы `inMonad` обычными вызовами.
 *
 * Обещание то же, что у прохода дефункционализации: программа без блоков
 * возвращается ТЕМ ЖЕ объектом, а не копией, и то же верно для каждой отдельной
 * функции. Парсер зовёт этот проход, только когда блок написан, но проверка
 * `естьБлок` стоит и здесь: экспорт вправе позвать кто угодно.
 */
export function expandMonads(program) {
  if (!Array.isArray(program?.functions) || !program.functions.some((fn) => естьБлок(fn?.body))) return program

  const монады = new Map()
  for (const узел of program.monads ?? []) {
    if (монады.has(узел.name)) {
      throw flangError("FLANG_MONAD", `монада «${узел.name}» объявлена дважды`, узел.span)
    }
    монады.set(узел.name, узел)
  }

  const развернуть = (узел) => {
    const объявление = монады.get(узел.monad)
    if (объявление === undefined) {
      throw flangError("FLANG_MONAD", `монады «${узел.monad}» нет: объявите 'монада «${узел.monad}» от «А»'`, узел.span)
    }
    const устройство = устройствоМонады(объявление, program.types)
    if (устройство.беда !== undefined) {
      throw flangError("FLANG_MONAD", `монада «${узел.monad}»: ${устройство.беда}`, объявление.span ?? узел.span)
    }
    /* Собирается справа налево: продолжение каждого `пусть` — это уже готовое
       выражение, поэтому последним считается `возврат`, а связывания
       наворачиваются от последнего к первому. */
    let итог = { kind: "call", name: объявление.unit, args: [узел.result], span: узел.span }
    for (let номер = узел.binds.length - 1; номер >= 0; номер -= 1) {
      const связывание = узел.binds[номер]
      итог = {
        kind: "call",
        name: объявление.join,
        args: [отображение(устройство, связывание.value, связывание.name, итог, связывание.span)],
        span: связывание.span,
      }
    }
    return итог
  }

  const функции = program.functions.map((fn) => {
    const тело = переписать(fn?.body, развернуть)
    /* Функция без блока возвращается ТЕМ ЖЕ объектом: обещание «не тронуть то,
       чего не касается» проверяется побайтовой сверкой AST всего репозитория, и
       лишняя копия сломала бы не её, а доверие к ней. */
    return тело === fn?.body ? fn : { ...fn, body: тело }
  })
  return { ...program, functions: функции }
}

/**
 * Отображение эндофунктора, напечатанное на месте.
 *
 * `разбор источник` по всем вариантам типа: вариант, несущий параметр,
 * связывает его под именем автора и пересобирается с ТЕЛОМ на месте этого поля;
 * прочие варианты пересобираются как были.
 *
 * ── Захват имени: дефект, найденный запуском ────────────────────────────────
 * Соседние поля несущего варианта копировались под своими же именами, и это
 * молча крало имена у автора. Мерено программой, а не рассуждением: у монады со
 * строковой меткой функция с параметром `метка` получала в теле блока НЕ свой
 * параметр, а метку из-под варианта — «ш7» вместо «снаружи7». Проверка типов
 * молчала: типы совпадали.
 *
 * Отвергать такую программу было бы неверно — автор не обязан знать, как
 * называются поля внутри монады. Поэтому копия берёт имя, которого в теле НЕТ:
 * `метка`, `метка 2`, `метка 3`. Множество занятых имён — все `var` тела плюс
 * имя связывания; шире нужного, зато не требует знать области видимости, а
 * лишний суффикс не стоит ничего. Ветви, не несущей параметра, переименование
 * не нужно вовсе: тела автора в ней нет.
 */
function отображение(устройство, источник, имя, тело, span) {
  const занято = именаВнутри(тело, new Set([имя]))
  const cases = устройство.ветви.map((ветвь) => {
    const несущая = ветвь.несёт !== null
    const bind = {}
    const fields = {}
    for (const поле of ветвь.прочие) {
      const местное = несущая ? свободноеИмя(поле, занято) : поле
      bind[поле] = местное
      fields[поле] = { kind: "var", name: местное, span }
    }
    if (несущая) {
      bind[ветвь.несёт] = имя
      fields[ветвь.несёт] = тело
    }
    return {
      pattern: { kind: "variant", name: ветвь.вариант, bind },
      body: { kind: "construct", variant: ветвь.вариант, fields, span },
    }
  })
  return { kind: "match", target: источник, cases, span }
}

/** Первое имя вида «поле», «поле 2», «поле 3», которого ещё не заняли. */
function свободноеИмя(поле, занято) {
  let имя = поле
  for (let номер = 2; занято.has(имя); номер += 1) имя = `${поле} ${номер}`
  занято.add(имя)
  return имя
}

/**
 * Все имена, которые тело читает из окружения.
 *
 * Собираются `var` — единственный вид узла, который смотрит в окружение. Имена,
 * связанные внутри самого тела (`пусть`, образцы, `отобразить`), сюда тоже
 * попадают, и это не ошибка: множество нужно ШИРЕ настоящего, а лишнее имя
 * стоит одного суффикса.
 */
function именаВнутри(узел, собрано) {
  if (узел === null || typeof узел !== "object") return собрано
  if (Array.isArray(узел)) {
    for (const элемент of узел) именаВнутри(элемент, собрано)
    return собрано
  }
  if (узел.kind === "var" && typeof узел.name === "string") собрано.add(узел.name)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span" || ключ === "name") continue
    /* Образец несёт связывания строками — они читаются телом ветви, значит
       занимают имя ровно так же, как `var`. */
    if (ключ === "pattern") {
      for (const местное of Object.values(значение?.bind ?? {})) собрано.add(местное)
      if (typeof значение?.head === "string") собрано.add(значение.head)
      if (typeof значение?.tail === "string") собрано.add(значение.tail)
      continue
    }
    именаВнутри(значение, собрано)
  }
  return собрано
}

/**
 * Есть ли блок `в монаде` где-нибудь внутри выражения.
 *
 * Отдельный обход, а не `переписать` с ловушкой, и это не дублирование:
 * `переписать` заводит объект на КАЖДЫЙ узел, а этот проход не заводит ни
 * одного. Разница платится на каждом разборе каждой программы репозитория —
 * у `self/parser.flang` это десятки тысяч узлов, — а блоков там нет ни одного.
 */
function естьБлок(узел) {
  if (узел === null || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some(естьБлок)
  if (узел.kind === "inMonad") return true
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span" || ключ === "pattern") continue
    if (естьБлок(значение)) return true
  }
  return false
}

/**
 * Обход выражения с заменой узлов `inMonad`.
 *
 * Своё, а не общее: общего обхода выражений в компиляторе нет, и заводить его
 * ради одного прохода значило бы держать список видов узла в третьем месте.
 * Здесь достаточно знать, у каких видов есть дети-выражения, — и незнакомый
 * вид просто возвращается как есть, потому что блока внутри него быть не может.
 */
function переписать(узел, развернуть) {
  if (узел === null || typeof узел !== "object") return узел
  if (Array.isArray(узел)) return узел.map((элемент) => переписать(элемент, развернуть))
  if (узел.kind === "inMonad") {
    const развёрнутый = развернуть({
      ...узел,
      binds: узел.binds.map((связь) => ({ ...связь, value: переписать(связь.value, развернуть) })),
      result: переписать(узел.result, развернуть),
    })
    return развёрнутый
  }
  const копия = {}
  let изменилось = false
  for (const [ключ, значение] of Object.entries(узел)) {
    const новое =
      ключ === "span" || ключ === "pattern" ? значение : переписать(значение, развернуть)
    копия[ключ] = новое
    if (новое !== значение) изменилось = true
  }
  return изменилось ? копия : узел
}

