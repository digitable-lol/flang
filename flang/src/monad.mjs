/**
 * Монада: разворачивание формы `в монаде` и проверка законов на сетке.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЗДЕСЬ ДВЕ РАЗНЫЕ ВЕЩИ, И ГРАНИЦА МЕЖДУ НИМИ — ГЛАВНОЕ
 *
 * `expandMonads` — разворачивание. Оно работает внутри парсера и обязано
 * оставить на выходе программу из раздела 5 SPEC, в которой никакой монады уже
 * нет: обычные вызовы, обычный `разбор`, обычные конструкторы вариантов.
 *
 * `checkMonadLaws` — проверка. Она вычисляет и предъявляет контрпример, ровно
 * как `monoid.mjs`, потому что законы монады — это равенства ВЫЧИСЛЕНИЙ, а их
 * на бесконечном множестве не решить.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ФОРМЕ НЕ НУЖНЫ ФУНКЦИИ ПЕРВОГО КЛАССА
 *
 * Связывание `bind(м, к) = соединение(отобразить(к, м))` требует, чтобы `к`
 * было значением. У продолжения есть свободные имена — то, что связали строки
 * выше, — значит тегом (`функция «Имя»`) оно не выражается: тег в flang полей
 * не захватывает (фаза 1 в `flang/cat/HOF.md`, частичного применения нет).
 *
 * Поэтому здесь `к` НЕ СТРОИТСЯ вовсе. Продолжение известно синтаксически, и
 * отображение эндофунктора печатается на месте — `разбор` по вариантам типа, в
 * котором тело продолжения стоит прямо в ветви:
 *
 *   в монаде «Возможно»            соединение от (разбор М
 *     пусть х равно М          →     случай вариант «Есть» с значение как х
 *     возврат Е                        то вариант «Есть» с значение равным («Обернуть» от Е)
 *                                    случай «Нет»
 *                                      то вариант «Нет»)
 *
 * Свободные имена работают потому, что это ВЫРАЖЕНИЕ, а не функция: замыкать
 * нечего. Так обещание из `flang/PLAN.md` («функций первого класса ей не нужно,
 * потому что тело известно синтаксически») оказывается не лозунгом, а
 * устройством.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ОТКУДА БЕРЁТСЯ ОТОБРАЖЕНИЕ, ЕСЛИ ЕГО НИКТО НЕ ОБЪЯВЛЯЛ
 *
 * Монада — это эндофунктор плюс η и μ, и объявлены здесь только η и μ. Значит
 * отображение обязано браться откуда-то ещё, и берётся оно из САМОГО ТИПА.
 *
 * У полиномиального функтора (сумма вариантов, у каждого — конечный список
 * полей) законное отображение ровно одно: пройти по полям, к полям типа «А»
 * применить, остальные скопировать. Это не выбор из нескольких — это
 * единственная функция нужного типа, сохраняющая единицы и композицию. Поэтому
 * функториальность здесь ДОКАЗАНА построением, а не проверена на сетке, и в
 * объявлении монады строки «эндофунктор» нет: она не сообщала бы ничего, чего
 * компилятор не знает из объявления типа.
 *
 * Цена названа: параметр обязан стоять в поле ЦЕЛИКОМ. `значение: «А»` —
 * разворачивается; `значения: список «А»` или `дальше: «Возможно» от «А»` — нет,
 * потому что отображение внутрь списка или внутрь рекурсии на месте не
 * печатается: там нужен цикл, то есть отдельная функция, то есть продолжение
 * значением, то есть захват. Это та же граница, что и у фазы 4 в `HOF.md`, и
 * отказ называет её словами, а не общим «не разобрано».
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ДОКАЗЫВАЕТСЯ, А ЧТО ПРОВЕРЯЕТСЯ (`flang/cat/SPEC.md`, «Граница честности»)
 *
 * Доказывается сличением объявлений — в `types.mjs`, рядом с моноидом:
 * тип объявлен и параметрический; параметр монады у него есть; `возврат` ведёт
 * из «А» в M«А»; `соединение` ведёт из M(M«А») в M«А»; параметр стоит в полях
 * целиком, значит отображение выводится и функториально.
 *
 * Проверяется на конечной сетке — здесь: левая единица, правая единица,
 * ассоциативность связывания. Сетка берётся оттуда же, откуда её берёт моноид,
 * — из примеров, написанных автором, — и её размер печатается в отчёте.
 */
