/**
 * Законы моноида — то, что ПРОВЕРЯЕТСЯ, а не доказывается.
 *
 * Разница с законами функтора существенная, и путать их нельзя. Функтор
 * доказывается сравнением объявлений: морфизм — объявление, домен и кодомен
 * известны до запуска, и «образ композиции есть композиция образов» решается
 * сличением имён. У моноида законы говорят о РАВЕНСТВЕ ВЫЧИСЛЕНИЙ на всех
 * значениях носителя:
 *
 *   ассоциативность   (а ⊕ б) ⊕ в = а ⊕ (б ⊕ в)
 *   нейтральность     е ⊕ а = а = а ⊕ е
 *   обратимость       а ⊕ обр(а) = е = обр(а) ⊕ а
 *
 * Равенство вычислений на бесконечном множестве неразрешимо. Поэтому здесь
 * конечная сетка, и отчёт обязан называть её размер: «проверено на N значениях»
 * — не то же самое, что «доказано», и документация языка на этом стоит.
 *
 * ── Откуда берётся сетка ────────────────────────────────────────────────────
 * Не из воздуха и не из генератора случайных значений. Значения берутся оттуда,
 * где автор их уже написал: аргументы и ожидаемые результаты примеров самой
 * операции, плюс объявленная единица. Довод простой — примеры операции пишет
 * тот, кто знает её краевые случаи, и именно на них закон и ломается. Случайные
 * значения дали бы больше точек и меньше смысла: моноид «склейка строк» на
 * случайных строках ассоциативен всегда, а на пустой строке и на строке с
 * суррогатной парой — вопрос.
 *
 * Сетка ограничена сверху: троек кубически много, и на двадцати значениях это
 * уже восемь тысяч вычислений. Предел назван явно и печатается в отчёте — иначе
 * «проверено» означало бы разное в разных прогонах.
 */
import { valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Больше этого числа значений в сетку не берём — см. шапку про кубический рост. */
export const ПРЕДЕЛ_СЕТКИ = 12

/**
 * Значения для сетки: из примеров операции и обращения, плюс единица.
 *
 * Порядок — сначала единица, потом примеры в порядке появления: закон чаще
 * всего ломается именно на единице, и увидеть это в отчёте первым полезнее.
 * Дубликаты убираются по значению, а не по ссылке.
 */
function сеткаЗначений(узел, программа, единица) {
  const собрано = [единица]
  const добавить = (значение) => {
    if (значение === undefined) return
    if (собрано.some((готовое) => valuesEqual(готовое, значение))) return
    собрано.push(значение)
  }
  for (const имя of [узел.operation, узел.inverse]) {
    if (имя === null || имя === undefined) continue
    const функция = программа.functions.find((кандидат) => кандидат.name === имя)
    for (const пример of функция?.examples ?? []) {
      for (const значение of Object.values(пример.args ?? {})) добавить(значение)
      добавить(пример.expected)
    }
  }
  return собрано.slice(0, ПРЕДЕЛ_СЕТКИ)
}

/**
 * Проверка законов всех моноидов программы.
 *
 * Возвращает диагностики того же вида, что остальные проверки языка: код,
 * сообщение, уровень, место. Нарушенный закон — это ОШИБКА, а не
 * предупреждение: объявление «моноид» обещает законы, и объявление, обещание
 * которого не выполняется, хуже отсутствующего.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<{ monoid: string, values: number, triples: number }> }}
 */
export function checkMonoidLaws(программа, пределы = {}) {
  const моноиды = Array.isArray(программа?.monoids) ? программа.monoids : []
  const diagnostics = []
  const checked = []
  if (моноиды.length === 0) return { diagnostics, checked }

  const среда = createRuntime(программа, пределы)
  const звать = (имя, ...аргументы) => {
    const функция = программа.functions.find((кандидат) => кандидат.name === имя)
    if (!функция) return { ошибка: `функции «${имя}» нет` }
    const назван = {}
    функция.params.forEach((параметр, номер) => {
      назван[параметр.name] = аргументы[номер]
    })
    try {
      return { значение: среда.call(имя, назван) }
    } catch (беда) {
      /* Отказ операции на значении сетки — не нарушение закона, а другое
         сообщение: закон проверить не на чем, и сказать надо именно это. */
      return { ошибка: беда?.message ?? String(беда) }
    }
  }

  for (const узел of моноиды) {
    const единица = вычислитьЕдиницу(узел, среда, программа)
    if (единица === undefined) {
      diagnostics.push({
        code: "FLANG_MONOID",
        message: `моноид «${узел.name}»: единицу не удалось вычислить, законы проверить не на чем`,
        severity: "error",
        span: узел.span,
      })
      continue
    }

    const значения = сеткаЗначений(узел, программа, единица)
    let троек = 0
    /* НАРУШЕНИЯ СЧИТАЮТСЯ, И СЧЁТ УЕЗЖАЕТ В ОТЧЁТ. Раньше `checked` заполнялся
       безусловно: моноид с нарушенной ассоциативностью попадал в него ровно так
       же, как честный, и ведомость печатала о нём «сетка N значений: нарушений
       не найдено» — та же неправда, что у сетки примеров, и в ту же сторону.
       Программа при этом отказная, и `flang check` ведомости не печатает, но
       `proofLedger` — вывозимая функция, и отчёт по ней собирают инструменты. */
    const доБед = diagnostics.length
    /* Место, на котором поиск ОБОРВАЛСЯ, не найдя нарушения. Отличать его от
       пройденной насквозь сетки обязательно: «не найдено на всей сетке» и «не
       найдено там, докуда дошли» — разные утверждения. */
    let оборвано = null
    const сказать = (код, текст) => {
      diagnostics.push({ code: код, message: `моноид «${узел.name}»: ${текст}`, severity: "error", span: узел.span })
    }

    /* Нейтральность — первой: она дешёвая (линейна по сетке) и ломается чаще
       ассоциативности, потому что про единицу забывают. */
    for (const значение of значения) {
      const слева = звать(узел.operation, единица, значение)
      const справа = звать(узел.operation, значение, единица)
      if (слева.ошибка || справа.ошибка) {
        сказать("FLANG_MONOID", `операция отказала на значении сетки: ${слева.ошибка ?? справа.ошибка}`)
        break
      }
      if (!valuesEqual(слева.значение, значение)) {
        сказать("FLANG_MONOID_IDENTITY", `единица не нейтральна слева: операция от единицы и ${покажи(значение)} дала ${покажи(слева.значение)}`)
        break
      }
      if (!valuesEqual(справа.значение, значение)) {
        сказать("FLANG_MONOID_IDENTITY", `единица не нейтральна справа: операция от ${покажи(значение)} и единицы дала ${покажи(справа.значение)}`)
        break
      }
    }

    /* Ассоциативность — по всем тройкам сетки. */
    авария: for (const а of значения) {
      for (const б of значения) {
        for (const в of значения) {
          троек += 1
          const слева = звать(узел.operation, звать(узел.operation, а, б).значение, в)
          const справа = звать(узел.operation, а, звать(узел.operation, б, в).значение)
          if (слева.ошибка || справа.ошибка) {
            /* ОБРЫВ, А НЕ ЧИСТАЯ СЕТКА. Здесь стоял голый `break авария`:
               операция отказала на тройке, обход прекращался, а отчёт уходил
               такой же, как у пройденной насквозь сетки, — и ведомость говорила
               «нарушений не найдено» о тройках, до которых не дошла. Отказ
               операции законом не нарушен, диагностики поэтому нет; но и молчать
               об оборванном поиске нельзя, поэтому обрыв назван и уезжает в
               отчёт. */
            оборвано = `операция отказала на тройке ${покажи(а)}, ${покажи(б)}, ${покажи(в)}:`
              + ` ${слева.ошибка ?? справа.ошибка}`
            break авария
          }
          if (!valuesEqual(слева.значение, справа.значение)) {
            сказать(
              "FLANG_MONOID_ASSOC",
              `операция не ассоциативна: на ${покажи(а)}, ${покажи(б)}, ${покажи(в)} слева вышло ` +
                `${покажи(слева.значение)}, справа ${покажи(справа.значение)}`,
            )
            break авария
          }
        }
      }
    }

    /* Обратимость — только если обращение объявлено; с ним моноид есть группа. */
    if (узел.inverse !== null && узел.inverse !== undefined) {
      for (const значение of значения) {
        const обратное = звать(узел.inverse, значение)
        if (обратное.ошибка) {
          сказать("FLANG_MONOID", `обращение отказало на значении сетки: ${обратное.ошибка}`)
          break
        }
        const слева = звать(узел.operation, обратное.значение, значение)
        const справа = звать(узел.operation, значение, обратное.значение)
        if (слева.ошибка || справа.ошибка) {
          оборвано = `операция отказала при обращении ${покажи(значение)}: ${слева.ошибка ?? справа.ошибка}`
          break
        }
        if (!valuesEqual(слева.значение, единица) || !valuesEqual(справа.значение, единица)) {
          сказать(
            "FLANG_GROUP_INVERSE",
            `обращение не даёт единицу: на ${покажи(значение)} вышло ${покажи(слева.значение)} слева и ` +
              `${покажи(справа.значение)} справа`,
          )
          break
        }
      }
    }

    /* Поля появляются только тогда, когда им есть что сказать: у честного
       моноида запись обязана остаться прежней — на её форму сослались тесты
       законов дословно, и «нарушений 0» в каждой записи приучило бы к этому
       полю за неделю. */
    const нарушений = diagnostics.length - доБед
    checked.push({
      monoid: узел.name,
      values: значения.length,
      triples: троек,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
  }

  return { diagnostics, checked }
}

function вычислитьЕдиницу(узел, среда, программа) {
  /* Единица — выражение, а не вызов, поэтому вычисляется обёрткой: заводить
     второй вычислитель ради одного literal значило бы держать две семантики. */
  const обёртка = {
    ...программа,
    functions: [
      ...programFunctions(программа),
      { name: `«единица ${узел.name}»`, params: [], returns: узел.carrier, body: узел.unit, examples: [] },
    ],
  }
  try {
    return createRuntime(обёртка).call(`«единица ${узел.name}»`, {})
  } catch {
    return undefined
  }
}

function programFunctions(программа) {
  return Array.isArray(программа?.functions) ? программа.functions : []
}

/** Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт. */
function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 40 ? `${текст.slice(0, 37)}…` : текст
}
