/**
 * Монотонность: `а ≤ б ⟹ ф(а) ≤ ф(б)`.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Функция «Сколько осталось до предела», объявленная над растущим состоянием,
 * проходила `flang check --proof` со строкой «нет объявленных законов».
 * Состояние росло, ответ УБЫВАЛ — и кеш, положенный рядом, отдавал бы старое
 * значение как «ещё верное». Сказать об этом языку было нечем.
 *
 * ── Ради чего это свойство ──────────────────────────────────────────────────
 *
 * Два разрешения разом, и второе — то, ради которого свойство просили.
 *
 * ПЕРВОЕ, вместе с частичным порядком: состояния, сходящиеся без блокировок.
 * Монотонная функция от растущего состояния не может «передумать»: реплика,
 * получившая обновление, никогда не отвечает меньше, чем отвечала.
 *
 * ВТОРОЕ, и оно самостоятельное: БЕЗОПАСНОСТЬ КЕШИРОВАНИЯ. Кеш хранит ответ,
 * посчитанный на СТАРОМ входе, и отдаёт его, пока «ничего не изменилось».
 * Вопрос, на который кеш обязан ответить и обычно не отвечает: что значит
 * «ничего»? Если вход только растёт, а функция монотонна, то сохранённый ответ
 * — это НИЖНЯЯ ГРАНИЦА нынешнего, и на ней можно строить: «уже не меньше
 * стольких», «уже разрешено», «уже набрано». Без монотонности сохранённый ответ
 * не значит ничего вовсе: он мог стать и больше, и меньше.
 *
 * ── ЗДЕСЬ ОДНО СВОЙСТВО ОПИРАЕТСЯ НА ДРУГОЕ, и это не удобство ──────────────
 *
 * Закон говорит «а ≤ б ⟹ ф(а) ≤ ф(б)», то есть требует ПОРЯДКА НА ОБОИХ КОНЦАХ
 * функции. Берутся они из объявленных `свойство «частичный порядок»`, и не из
 * объявлений, а из ПРОШЕДШИХ проверку (`partialorder.mjs`, `здоровыеПорядки`).
 * Порядок объявленный, но нарушенный, монотонности не годится: вердикт о
 * монотонности относительно того, что порядком не является, был бы утверждением
 * ни о чём — ровно тем «доказать можно что угодно», ради запрета которого
 * сломанное свойство и останавливает зависящие от него.
 *
 * Порядка нет ни на домене, ни на кодомене — запись уходит в `assumed` с
 * причиной, а не молчит: объявление, о котором отчёт молчит, читается как
 * проверенное.
 *
 * ── Что здесь ПРОВЕРЯЕТСЯ, а не доказывается ────────────────────────────────
 *
 * Закон. Устройство доказано раньше и в другом месте (`types.mjs`: функция
 * объявлена и берёт ровно один вход). Здесь — утверждение обо всех парах
 * значений домена, а оно неразрешимо: значит конечная сетка, квадратичная по
 * ней, и ведомость обязана называть её размер строкой, оканчивающейся словами
 * «Это не доказательство».
 *
 * ── Откуда берётся сетка, и почему она СВОДНАЯ ──────────────────────────────
 *
 * Из примеров самой функции И из значений, на которых считался порядок домена.
 * Вторая половина здесь не для полноты: закон говорит о ПАРАХ, связанных
 * порядком, а пары эти живут там, где автор писал порядок, — в примерах
 * отношения. Взять только примеры функции значило бы искать нарушение там, где
 * сравнимых пар может не оказаться вовсе.
 */
import { ключТипа, ПРЕДЕЛ_СЕТКИ, объявления, основа, покажи, пусто } from "./svoystva.mjs"
import { здоровыеПорядки } from "./partialorder.mjs"

export { ПРЕДЕЛ_СЕТКИ }

/** Имя свойства — то самое, что автор пишет в ёлочках. */
export const ИМЯ = "монотонность"

/**
 * Проверка монотонности всех функций, её объявивших.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object>,
 *   assumed: Array<object>, permits: Array<object> }}
 */
export function checkMonotonicity(программа, пределы = {}) {
  const узлы = объявления(программа, ИМЯ)
  const итог = пусто()
  if (узлы.length === 0) return итог

  const { найти, звать, сетка } = основа(программа, пределы)
  const порядки = здоровыеПорядки(программа, пределы)

  for (const узел of узлы) {
    const функция = найти(узел.function)
    if (функция === undefined || (функция.params ?? []).length !== 1) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.function ?? null,
        why: "устройство функции не сошлось: об этом сказала проверка типов",
      })
      continue
    }

    const домен = ключТипа(функция.params[0].type)
    const кодомен = ключТипа(функция.returns)
    const наДомене = порядки.get(домен)
    const наКодомене = порядки.get(кодомен)
    if (наДомене === undefined || наКодомене === undefined) {
      /* Ровно то место, где сломанное свойство останавливает зависящее от него:
         `здоровыеПорядки` отдаёт только ПРОШЕДШИЕ порядки, значит порядок
         объявленный и нарушенный приходит сюда как отсутствующий. Причина
         называется одной формулировкой на оба случая нарочно — «порядка нет» и
         «порядок есть, но он не порядок» для монотонности одно и то же: сказать
         ей нечем. */
      const чего = наДомене === undefined
        ? `на входе «${имяТипа(функция.params[0].type)}»`
        : `на результате «${имяТипа(функция.returns)}»`
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.function,
        why: `здорового частичного порядка ${чего} нет: сравнивать нечем, ` +
          `а порядок объявленный и нарушенный монотонности не годится`,
      })
      continue
    }

    /* Сетка сводная: примеры самой функции плюс значения, на которых считался
       порядок домена. Порядок здесь значим — свои значения впереди, потому что
       предел стоит на всю сетку, и терять при упоре в потолок надо чужое. */
    const свои = сетка([узел.function], { толькоВходы: true })
    const отПорядка = сетка([наДомене.операция], { толькоВходы: true })
    const значения = []
    for (const х of [...свои, ...отПорядка]) {
      if (значения.length >= ПРЕДЕЛ_СЕТКИ) break
      if (значения.some((уже) => JSON.stringify(уже) === JSON.stringify(х))) continue
      значения.push(х)
    }
    if (значения.length === 0) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.function,
        why: `ни у «${узел.function}», ни у порядка «${наДомене.операция}» нет примеров: сетка пуста`,
      })
      continue
    }

    const доБед = итог.diagnostics.length
    let оборвано = null
    let пар = 0
    let сравнимых = 0
    const меньше = (отношение, а, б) => {
      const ответ = звать(отношение, а, б)
      if (ответ.ошибка) return { нет: ответ.ошибка }
      if (typeof ответ.значение !== "boolean") return { нет: `«${отношение}» вернула не признак` }
      return { да: ответ.значение }
    }

    пары: for (const а of значения) {
      for (const б of значения) {
        пар += 1
        const вход = меньше(наДомене.операция, а, б)
        if (вход.нет !== undefined) {
          оборвано = `порядок «${наДомене.операция}» не посчитался: ${вход.нет}`
          break пары
        }
        /* Несравнимые пары закон не задевает вовсе: посылка `а ≤ б` ложна, и
           о таких парах он не утверждает ничего. Считать их проверенными
           значило бы завышать силу проверки ровно на них. */
        if (!вход.да) continue
        сравнимых += 1
        const образА = звать(узел.function, а)
        const образБ = звать(узел.function, б)
        if (образА.ошибка || образБ.ошибка) {
          оборвано = `«${узел.function}» отказала на значении сетки: ${образА.ошибка ?? образБ.ошибка}`
          break пары
        }
        const выход = меньше(наКодомене.операция, образА.значение, образБ.значение)
        if (выход.нет !== undefined) {
          оборвано = `порядок «${наКодомене.операция}» не посчитался: ${выход.нет}`
          break пары
        }
        if (выход.да) continue
        итог.diagnostics.push({
          code: "FLANG_NOT_MONOTONE",
          message: `свойство «${ИМЯ}»: «${узел.function}» не монотонна: ${покажи(а)} не больше ${покажи(б)} ` +
            `по «${наДомене.операция}», а образы — ${покажи(образА.значение)} и ${покажи(образБ.значение)} — ` +
            `по «${наКодомене.операция}» идут в обратную сторону. Кешировать ответ такой функции нельзя: ` +
            `сохранённое значение перестаёт быть нижней границей нынешнего`,
          severity: "error",
          span: узел.span,
        })
        break пары
      }
    }

    const нарушений = итог.diagnostics.length - доБед
    /* СРАВНИМЫХ ПАР НОЛЬ — это не «проверено», а «проверять было не на чем»:
       посылка закона не выполнилась ни разу, и вердикт «нарушений не найдено»
       был бы утверждением ни о чём. Такая же граница, по какой пустая сетка
       уходит в `assumed`. */
    if (нарушений === 0 && оборвано === null && сравнимых === 0) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.function,
        why: `на сетке из ${значения.length} значений сравнимых пар не нашлось: ` +
          `посылка «а ≤ б» не выполнилась ни разу, проверять было не на чем`,
      })
      continue
    }
    итог.checked.push({
      property: ИМЯ,
      subject: узел.function,
      values: значения.length,
      points: пар,
      comparable: сравнимых,
      /* Сеток здесь две — домена и кодомена, — и предел ведомости считается по
         этому числу: один предел рядом с суммой значений читался бы как упор в
         потолок там, где потолка ещё не видели. */
      grids: 2,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
    if (нарушений > 0 || оборвано !== null) continue
    итог.permits.push({
      permit: "кешировать",
      property: ИМЯ,
      subject: узел.function,
      says: `ответ «${узел.function}» можно кешировать: пока вход не убывает по ` +
        `«${наДомене.операция}», сохранённое значение остаётся нижней границей нынешнего`,
    })
  }

  return итог
}

/** Имя типа для сообщения — коротко и теми же словами, какими его писал автор. */
function имяТипа(тип) {
  if (тип === null || тип === undefined) return "неизвестно"
  if (тип.kind === "named") return тип.name
  return String(тип.kind)
}
