/**
 * obligations.mjs — обязательства: что именно надо доказать, в виде ДАННЫХ.
 *
 * ── Зачем отдельный слой между поверхностью и ядром ─────────────────────────
 * Автор написал `обеспечивает «высота неотрицательна» результат не меньше 0` и
 * рядом `теорема «высота неотрицательна»`. Это два разных места файла, и связаны
 * они только именем. Ядру нельзя дать ни то, ни другое по отдельности: терм
 * доказательства проверяется ОТНОСИТЕЛЬНО цели, а цель написана у функции, а не
 * у теоремы. Значит между ними обязан стоять слой, который сводит их в один
 * объект и говорит: вот утверждение, вот при каких допущениях, вот по чему
 * квантор, вот чем автор предлагает это закрыть.
 *
 * Этот объект и называется обязательством (verification condition). Он —
 * ДАННЫЕ, а не текст: у него нет ни одной строки, предназначенной человеку,
 * кроме `id`, и ядро читает его поля, а не разбирает сообщение. Обратное
 * (передавать ядру текст) означало бы третий разбор одного и того же — после
 * лексера и парсера, — и разошёлся бы он молча.
 *
 * ── Три источника, и все три уже есть в программе ───────────────────────────
 *   ПОСТУСЛОВИЕ  `обеспечивает «имя» <утверждение>` у функции. Цель —
 *                утверждение, квантор — параметры функции, `результат` связан.
 *   МЕРА         `убывает <мера>` у функции. Цель — «мера убывает на каждом
 *                витке и ограничена снизу». Её УЖЕ доказал анализ
 *                завершаемости, и обязательство не переспрашивает: оно записывает
 *                факт, чтобы ведомость могла назвать его тем же словом, каким
 *                называет остальные.
 *   ТЕОРЕМА      `теорема «имя»` с доказательством. Сама она обязательства не
 *                создаёт — она его ЗАКРЫВАЕТ. Теорема, которая ничего не
 *                закрывает, — отказ: доказано было бы неизвестно что.
 *
 * ── Чего этот слой не делает ────────────────────────────────────────────────
 * Не проверяет ни одного доказательства. Здесь нет ни переписки, ни индукции,
 * ни арифметики — только сведение целей с предложенными доказательствами и
 * отказ там, где свести не удалось. Проверка — работа ядра (`proofterm.mjs`), и
 * держать её отдельно нужно ровно затем, чтобы ядро было маленьким: то, что
 * ищет соответствия по именам, не может быть частью того, что ничего не ищет.
 *
 * Не решает, доказано или нет. Обязательство несёт `discharge: null` до тех пор,
 * пока ядро не сказало своё слово. Слой, который сам себе выставляет оценку, —
 * это тот же дефект, из-за которого `flang check` печатал один `valid: true` на
 * три разные вещи.
 */

/** Версия формата обязательств: их читает ядро и ведомость, значит она названа. */
export const ОБЯЗАТЕЛЬСТВА = 1

/**
 * Обязательства программы.
 *
 * @param {object} program AST модуля (уже связанный, если файл с импортами)
 * @param {{ totality?: object }} [итоги] результаты внешних проверок; нужен
 *   только `totality`, и только затем, чтобы не пересчитывать доказанное
 *   завершение вторым графом вызовов
 * @returns {{ obligations: object[], diagnostics: object[] }}
 */
export function obligations(program, итоги = undefined) {
  const функции = Array.isArray(program?.functions) ? program.functions : []
  const теоремы = Array.isArray(program?.theorems) ? program.theorems : []
  const diagnostics = []
  const список = []

  /* Носитель обещания завершения читается из анализа, а не считается заново:
     второй граф вызовов — это второй ответ на тот же вопрос. */
  const меры = new Map()
  for (const запись of итоги?.totality?.descents ?? []) {
    if (!меры.has(запись.from)) меры.set(запись.from, [])
    меры.get(запись.from).push(запись)
  }

  for (const fn of функции) {
    const имя = String(fn?.name ?? "")
    const параметры = (fn?.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
    const примеры = Array.isArray(fn?.examples) ? fn.examples : []

    for (const постусловие of fn?.postconditions ?? []) {
      /* Квантор: назвал автор — берём названный, не назвал — все параметры.
         Разница не косметическая: по названному параметру пойдёт индукция, а по
         безымянному обязательству идти некуда, и ядру придётся сказать об этом
         прямо, а не догадываться. */
      const по = типичное(постусловие.forall, параметры)
      список.push({
        id: `постусловие «${постусловие.name}» функции «${имя}»`,
        kind: "postcondition",
        name: String(постусловие.name ?? ""),
        of: имя,
        vars: параметры,
        forall: по,
        hypotheses: [],
        goal: постусловие.expr,
        bind: постусловие.bind ?? null,
        /* Сетка, на которой утверждение уже посчитано без всякого
           доказательства: примеры функции. Постусловие проверяется после
           КАЖДОГО возврата, значит каждый пример его и проверил. Число здесь —
           не оценка доказанности, а размер сетки, и ведомость обязана назвать
           его тем же словом, каким называет сетки законов. */
        grid: примеры.length,
        proof: null,
        discharge: null,
        span: постусловие.span ?? fn?.span ?? null,
      })
    }

    if (fn?.decreases !== undefined && fn?.decreases !== null) {
      const места = меры.get(имя) ?? []
      список.push({
        id: `мера функции «${имя}»`,
        kind: "measure",
        name: имя,
        of: имя,
        vars: параметры,
        forall: null,
        hypotheses: [],
        goal: fn.decreases,
        bind: null,
        grid: 0,
        proof: null,
        /* Единственное обязательство, которое приходит уже закрытым, и закрыл
           его не автор: анализ завершаемости доказал убывание обходом графа
           вызовов до всякого доказательства. Ядру здесь делать нечего, и
           притворяться, будто есть, значило бы поставить в цепочку доверия шаг,
           которого нет. Сторожа названы числом: `тотальная` означает
           «завершится или честно откажет», и где возможно второе — часть
           доказательства, а не оговорка к нему. */
        discharge: {
          by: "analysis",
          guardSites: места.length,
          says: "доказано объявленной мерой: убывание доказал анализ завершаемости",
        },
        span: fn?.span ?? null,
      })
    }
  }

  /* Теоремы привязываются к обязательствам по имени. Имя — единственный
     механизм связывания, который в языке уже есть везде: `по свойству «…»`,
     `по примеру «…»`, `даёт «…»`, `операция «…»` — все ссылаются по имени.
     Заводить для теоремы отдельную запись «о какой функции речь» значило бы
     дать одному и тому же две записи и разбирать, какая главнее. */
  const поИмени = new Map()
  for (const обязательство of список) {
    if (обязательство.kind !== "postcondition") continue
    if (!поИмени.has(обязательство.name)) поИмени.set(обязательство.name, [])
    поИмени.get(обязательство.name).push(обязательство)
  }

  for (const теорема of теоремы) {
    const имя = String(теорема?.name ?? "")
    const цели = поИмени.get(имя) ?? []
    if (цели.length === 0) {
      diagnostics.push({
        code: "FLANG_PROOF_NO_GOAL",
        severity: "error",
        message:
          `теорема «${имя}» ничего не закрывает: постусловия «${имя}» нет ни у одной функции модуля.`
          + " Теорема доказывает названное утверждение, а не утверждение вообще —"
          + ` назовите её так же, как постусловие, которое она закрывает`,
        span: теорема?.span,
      })
      continue
    }
    if (цели.length > 1) {
      /* Одно имя на два постусловия — не описка, а неразрешимая ссылка: `по
         свойству «X»` тоже не смогло бы сказать, о каком из двух речь. */
      diagnostics.push({
        code: "FLANG_PROOF_AMBIGUOUS",
        severity: "error",
        message:
          `теорема «${имя}» закрывала бы сразу ${цели.length} постусловия`
          + ` (${цели.map((ц) => `«${ц.of}»`).join(", ")}), и выбрать нельзя.`
          + " Дайте постусловиям разные имена",
        span: теорема?.span,
      })
      continue
    }
    const цель = цели[0]
    if (цель.proof !== null) {
      diagnostics.push({
        code: "FLANG_PROOF_DUPLICATE",
        severity: "error",
        message: `постусловие «${имя}» доказывается дважды: у него больше одной теоремы`,
        span: теорема?.span,
      })
      continue
    }
    /* Утверждение теоремы обязано быть ТЕМ ЖЕ, что обещает функция. Иначе
       доказали бы одно, а обещали другое, и ведомость сказала бы «доказано» о
       строке, к которой доказательство не относится. Сверка — синтаксическая: у
       ядра нет и не должно быть способа решить, что два разных утверждения
       «означают одно и то же». */
    if (!одинаковы(теорема?.claim?.expr, цель.goal)) {
      diagnostics.push({
        code: "FLANG_PROOF_CLAIM_MISMATCH",
        severity: "error",
        message:
          `теорема «${имя}» утверждает не то, что обещает функция «${цель.of}»:`
          + " утверждение теоремы и постусловие обязаны совпадать слово в слово."
          + " Ядро не решает, что два разных утверждения означают одно и то же",
        span: теорема?.claim?.span ?? теорема?.span,
      })
      continue
    }
    цель.proof = теорема
    цель.hypotheses = (теорема?.given ?? []).map((г) => г.expr)
    /* Переменные теоремы обязаны быть параметрами функции: доказывать о
       переменной, которой у функции нет, значит доказывать о чём-то другом. */
    for (const переменная of теорема?.vars ?? []) {
      if (!цель.vars.some((п) => п.name === переменная.name)) {
        diagnostics.push({
          code: "FLANG_PROOF_UNKNOWN_VAR",
          severity: "error",
          message:
            `теорема «${имя}» вводит «${переменная.name}», а у функции «${цель.of}» такого параметра нет`,
          span: переменная?.span ?? теорема?.span,
        })
      }
    }
    if (теорема?.qed !== true) {
      diagnostics.push({
        code: "FLANG_PROOF_UNFINISHED",
        severity: "error",
        message:
          `доказательство теоремы «${имя}» не закончено: нет строки «следовательно доказано».`
          + " Незакрытое доказательство — это набросок, и принять его за доказанное нельзя",
        span: теорема?.span,
      })
    }
  }

  return { version: ОБЯЗАТЕЛЬСТВА, obligations: список, diagnostics }
}

/** Квантор: названный параметр или все параметры функции. */
function типичное(forall, параметры) {
  if (typeof forall !== "string") return null
  return параметры.find((п) => п.name === forall) ?? { name: forall, type: null }
}

/**
 * Синтаксическое равенство двух выражений — без нормализации и без вычислений.
 *
 * ПОЧЕМУ БЕЗ НОРМАЛИЗАЦИИ. Сравнивать «с точностью до переименования» или «до
 * приведения» значило бы завести здесь второй упрощатель — тот самый, что
 * живёт в ядре, — и разошлись бы они молча. Здесь нужно ровно одно: сказать,
 * что автор написал в двух местах одно и то же. Он либо написал, либо нет.
 *
 * `span` не сравнивается: одно и то же утверждение в двух местах файла стоит на
 * разных строках, и требовать совпадения строк было бы требованием невозможного.
 */
export function одинаковы(левое, правое) {
  if (левое === правое) return true
  if (левое === null || правое === null) return false
  if (typeof левое !== "object" || typeof правое !== "object") return false
  if (Array.isArray(левое) !== Array.isArray(правое)) return false
  if (Array.isArray(левое)) {
    if (левое.length !== правое.length) return false
    return левое.every((элемент, и) => одинаковы(элемент, правое[и]))
  }
  const ключи = (узел) => Object.keys(узел).filter((ключ) => ключ !== "span").sort()
  const левые = ключи(левое)
  const правые = ключи(правое)
  if (левые.length !== правые.length) return false
  return левые.every((ключ, и) => правые[и] === ключ && одинаковы(левое[ключ], правое[ключ]))
}
