/**
 * ПАКЕТ — один файл, в котором лежит модуль вместе со всем, от чего он зависит.
 *
 * ── Что это решает ──────────────────────────────────────────────────────────
 * Сегодня чужой модуль подключается ПУТЁМ по файловой системе, и путь этот
 * измеряется (`docs/site/packages.ru.md`): семь шагов у того, кто подключает,
 * из них два — открыть чужой файл и прочесть первую строку, потому что имя
 * модуля обязано совпасть, а узнать его больше неоткуда. Программа при этом не
 * переносится: скопировал свой каталог — `FLANG_IMPORT_NOT_FOUND`.
 *
 * Пакет — это замок (`lockfile.mjs`), у которого появились три вещи, которых
 * замку не нужно, а пакету нужно:
 *
 *   ИМЯ и ВЕРСИЯ — потому что пакет подключают, а замок только собирают;
 *   ИСТОЧНИК     — откуда его взяли, чтобы взять снова;
 *   ВЕДОМОСТЬ    — что автор доказал про свои функции.
 *
 * ── Как подключается ────────────────────────────────────────────────────────
 * Одной строкой, и новых слов в языке для этого не заведено:
 *
 *   использует «Множество строк» из "sets.flang-package"
 *
 * Расширение видит инструмент, а не язык: `link.mjs` не тронут ни строкой, как
 * не был тронут ради замка. Подмена делается двумя обёртками переднего края —
 * `readFile` и `parse`, — и по той же причине: у языка две реализации
 * связывания, вторая на самом flang (`flang/self/link.flang`), и всякое новое
 * поле в разборе оплачивалось бы правкой обеих плюс побайтовой сверкой.
 *
 * ── Почему один файл, а не каталог и не склад ───────────────────────────────
 * Требование владельца записано дословно: «без необходимости постоянно что-то
 * где-то складировать и скачивать». Пакет — файл: положил в git, приложил к
 * письму, скопировал на флешку. Сборка у того, кто его подключил, идёт БЕЗ
 * СЕТИ и без каталога `~/.flang`, потому что качать неоткуда: код уже здесь.
 *
 * ── ВЕДОМОСТЬ — СПРАВКА, А НЕ ДОВЕРЕННЫЙ КОРЕНЬ, и это главное ──────────────
 * В пакете лежит то, что ядро сказало про функции автора: «доказано», «сетка
 * N», «объявлено». Лежит СПРАВКОЙ. Ни одна проверка у того, кто подключил
 * пакет, на неё не опирается: связанная программа содержит тела чужих функций
 * целиком, и ядро доказывает их заново, как доказывало бы исходники.
 *
 * Так сделано не из осторожности, а по замеру. Кеш вердиктов по адресу
 * содержимого в дереве есть (`proofcache.mjs`), и его собственный замер
 * говорит, что он стоит дороже, чем экономит. Перемерено на 98 файлах корпуса
 * с обязательствами, одним процессом:
 *
 *   ЯДРО ДОКАЗАТЕЛЬСТВА  112 мс   ← всё, что пакет мог бы сэкономить
 *   адреса определений   144 мс   ← всё, что пакет обязан потратить
 *
 * То есть ключ, которым доказательство кешируют, дороже самого доказательства,
 * и на всём корпусе разом. Пакет, который вёз бы вердикты вместо справки, был
 * бы медленнее и при этом обязан был бы им верить. Число названо здесь, чтобы
 * следующий начинал с него, а не с довода.
 *
 * ── Двух версий одной библиотеки нет, и пакет этого не меняет ───────────────
 * Импорт в flang сливает объявления в одно плоское пространство имён
 * (`link.mjs`), совпадение имён — `FLANG_DUPLICATE_NAME`. Отказ от
 * сосуществования версий записан в роадмапе и разобран в
 * `docs/modularity-and-packages.md`; здесь он НЕ снимается и снят быть не
 * может. Что здесь делается — только одно: два пакета, привезшие один и тот же
 * путь с разным содержимым, отвергаются НАЗВАННЫМ отказом `FLANG_PACKAGE`, а
 * не решаются молча в пользу того, кто приехал первым.
 */
import { readFile } from "node:fs/promises"
import { dirname, isAbsolute, relative, resolve } from "node:path"

import { адресМодуля, печать, прежняяСхема, разборМодуля } from "./lockfile.mjs"
import { importsOf } from "./link.mjs"

/**
 * Версия раскладки пакета. Меняется — прежние пакеты перестают приниматься.
 *
 * 1 — груз brotli+base64 от разбора со снятыми местами (до 19 августа 2026);
 * 2 — груз ИСХОДНИКОМ, адрес sha256 по содержимому, сжатия нет вовсе
 *     (см. «СХЕМА 2» в шапке `lockfile.mjs` — довод там целиком).
 *
 * Двигается ВМЕСТЕ с `СХЕМА_ЗАМКА`, а не отдельно: груз у них один и тот же
 * код, и пакет схемы 1 внутри пакета схемы 2 был бы ровно тем молчаливым
 * чтением, против которого номер схемы и заведён.
 */
export const СХЕМА_ПАКЕТА = 2

/** Расширение файла пакета. Латиницей — значит английскими словами. */
export const РАСШИРЕНИЕ = ".flang-package"

/** Объявление пакета рядом с его входным файлом. */
export const ИМЯ_ОБЪЯВЛЕНИЯ = "flang.package"

/** Файл пакета опознаётся по расширению — и только по нему. */
export const этоПакет = (путь) => typeof путь === "string" && путь.endsWith(РАСШИРЕНИЕ)

/**
 * ЧТО ЗАВЕРЯЕТ ПЕЧАТЬ ПАКЕТА — и почему больше, чем у замка.
 *
 * Замок заверяет только груз: пути и печати модулей. Для замка этого хватает —
 * он отвечает на вопрос «из чего собрано», и всё, что в нём есть сверх груза,
 * есть справка для человека.
 *
 * У пакета сверх груза лежит ЕГО ЛИЧНОСТЬ: имя, версия, источник. По ним на
 * него ссылаются и по ним его отличают от соседа. Незаверенная версия — это
 * версия, которую правят одним `sed` и не ловят ничем: тот же код приезжает под
 * другим номером, и подмену не видит никто. Поэтому здесь под печать уходит всё,
 * что пакет о себе говорит, включая число функций каждого модуля.
 *
 * Улика ДО, прогоном: до этой правки подмена `"версия"` с `0.1.0` на `9.9.9` и
 * подмена `"функций"` с 3 на 999 проходили `flang check` молча, ответом
 * `{"valid":true,…}`. Сейчас обе — `FLANG_PACKAGE`.
 */
export function печатьПакета(пакет) {
  return печать([
    пакет.имя,
    пакет.версия,
    пакет.источник ?? "",
    пакет.вход,
    (пакет.модули ?? []).map((м) => [м.путь, м.имя, м.функций, м.адрес]),
  ])
}

/* ─────────────────────────── объявление пакета ───────────────────────────── */

/**
 * Прочесть объявление `flang.package` — JSON рядом со входным файлом.
 *
 * Объявление обязательно: без него `flang package` откажет. Пакет без имени и
 * версии — это замок, и делать вид, что это пакет, значило бы обещать
 * подключение, которого не выйдет: подключают по имени модуля, а сверяют его с
 * тем, что записано в пакете.
 */
export function разобратьОбъявление(текст, откуда) {
  let о = null
  try {
    о = JSON.parse(текст)
  } catch (беда) {
    throw new Error(`${откуда} не разбирается как JSON: ${беда instanceof Error ? беда.message : String(беда)}`)
  }
  if (о === null || typeof о !== "object" || Array.isArray(о)) throw new Error(`${откуда}: ожидалась запись JSON`)
  const строкой = (ключ, обязательно) => {
    const значение = о[ключ]
    if (значение === undefined || значение === null) {
      if (обязательно) throw new Error(`${откуда}: нет поля «${ключ}»`)
      return null
    }
    if (typeof значение !== "string" || значение === "") throw new Error(`${откуда}: поле «${ключ}» — непустая строка`)
    return значение
  }
  return { имя: строкой("имя", true), версия: строкой("версия", true), источник: строкой("источник", false) }
}

/**
 * Найти и прочесть объявление рядом со входным файлом.
 *
 * `отказом` подаётся вызывающим, а не берётся отсюда: коды бед строит передний
 * край (`fail` в `bin/flang.mjs`), и второй способ их строить однажды разойдётся
 * с первым.
 */
export async function объявлениеРядом(входнойФайл, читать, отказом) {
  const путь = resolve(dirname(resolve(входнойФайл)), ИМЯ_ОБЪЯВЛЕНИЯ)
  let текст = null
  try {
    текст = await читать(путь)
  } catch {
    throw отказом(
      "FLANG_PACKAGE",
      `рядом с ${входнойФайл} нет объявления ${ИМЯ_ОБЪЯВЛЕНИЯ}: пакету нужны имя и версия, ` +
        "и берутся они оттуда, а не из вызова",
    )
  }
  try {
    return разобратьОбъявление(текст, путь)
  } catch (беда) {
    throw отказом("FLANG_PACKAGE", беда instanceof Error ? беда.message : String(беда))
  }
}

/* ───────────────────────────── сборка пакета ─────────────────────────────── */

/**
 * Собрать пакет: обойти замыкание импортов и положить КОД каждого модуля.
 *
 * Обход тот же, что у замка, и намеренно не вынесен в общую функцию: у замка
 * корень — каталог программы, у пакета — каталог его входного файла, и общая
 * функция с двумя корнями через полгода разойдётся с одним из вызывающих.
 */
export async function собратьПакет(входнойФайл, parse, объявление, настройки = {}) {
  const читать = настройки.readFile ?? ((файл) => readFile(файл, "utf8"))
  const вход = resolve(входнойФайл)
  const корень = dirname(вход)
  const модули = []
  const пройдено = new Set()
  const очередь = [{ файл: вход, имя: объявление.имя }]

  const поставить = (изФайла, запись) => {
    const цель = isAbsolute(запись.from) ? запись.from : resolve(dirname(изФайла), запись.from)
    if (пройдено.has(цель)) return
    пройдено.add(цель)
    очередь.push({ файл: цель, имя: запись.category })
  }
  пройдено.add(вход)

  const записью = (файл, исходник, дерево, имя) => ({
    имя: typeof дерево.module === "string" ? дерево.module : имя,
    путь: путёмПакета(корень, файл),
    функций: (дерево.functions ?? []).length,
    адрес: адресМодуля(исходник),
    исходник,
  })

  let свой = null
  while (очередь.length > 0) {
    const { файл, имя } = очередь.shift()
    /* ЗАВИСИМОСТЬ-ПАКЕТ РАСПАКОВЫВАЕТСЯ, а не пересобирается из исходников: у
       того, кто собирает пакет над чужим пакетом, исходников чужого нет и не
       будет — в этом весь смысл. Груз переезжает как есть, вместе с печатью
       каждого модуля, и потому остаётся тем же байт в байт.
       Ставится ЦЕЛИКОМ: у привезённого пакета замыкание уже полное, обходить
       его импорты второй раз нечем и незачем. */
    if (этоПакет(файл)) {
      let вложенный = null
      try {
        вложенный = JSON.parse(await читать(файл))
      } catch (беда) {
        throw new Error(`пакет ${файл} не прочитан: ${беда instanceof Error ? беда.message : String(беда)}`)
      }
      /* Проверяется ЦЕЛИКОМ (адреса, разбор, имена, входной модуль), и только
         потом груз переезжает как есть: испорченный вложенный пакет обязан
         отвергнуться здесь, а не всплыть у того, кому мы отдадим свой. */
      модулиПакета(вложенный, файл, parse)
      for (const { путь, модуль } of записиПакета(вложенный, файл)) {
        if (модули.some((м) => м.путь === путёмПакета(корень, путь))) continue
        модули.push({ ...модуль, путь: путёмПакета(корень, путь) })
      }
      continue
    }
    const исходник = await читать(файл)
    const дерево = parse(исходник, файл)
    if (файл === вход) свой = дерево
    for (const запись of importsOf(дерево)) поставить(файл, запись)
    модули.push(записью(файл, исходник, дерево, имя))
  }

  const своёИмя = typeof свой?.module === "string" ? свой.module : null
  if (своёИмя !== объявление.имя) {
    throw new Error(
      `в ${ИМЯ_ОБЪЯВЛЕНИЯ} пакет назван «${объявление.имя}», а модуль в ${входнойФайл} называется ${
        своёИмя === null ? "никак" : `«${своёИмя}»`
      }`,
    )
  }

  /* Порядок — по пути, а не по обходу: один и тот же модуль обязан давать один
     и тот же файл, иначе `git diff` шумит на пустом месте. */
  модули.sort((л, п) => (л.путь < п.путь ? -1 : л.путь > п.путь ? 1 : 0))
  const пакет = {
    схема: СХЕМА_ПАКЕТА,
    имя: объявление.имя,
    версия: объявление.версия,
    вход: путёмПакета(корень, вход),
    модули,
    ведомость: настройки.ведомость ?? [],
  }
  /* Источник — поле необязательное, и когда его нет, его нет в файле вовсе:
     пустая строка в JSON выглядит как «источник забыли», а не «его не было». */
  if (объявление.источник !== null) пакет.источник = объявление.источник
  пакет.печать = печатьПакета(пакет)
  return пакет
}

/** Путь внутри пакета — от каталога входного файла и всегда через косую черту. */
function путёмПакета(корень, файл) {
  const путь = relative(корень, файл).split("\\").join("/")
  return путь.startsWith(".") || путь.startsWith("/") ? путь : `./${путь}`
}

/* ──────────────────────────── чтение пакета ──────────────────────────────── */

/**
 * ЗАПИСИ пакета, разложенные по полным путям, — без единого разбора.
 *
 * Отдельно от `модулиПакета` потому, что у них два разных потребителя: тому,
 * кто СОБИРАЕТ пакет над чужим пакетом, нужен груз как есть (он переезжает
 * байт в байт), а тому, кто пакет ЧИТАЕТ, нужны деревья. Общая функция,
 * отдающая и то и другое, разбирала бы исходники ради того, кому они не нужны.
 *
 * Всё, что можно проверить не разбирая, проверяется здесь: схема, имя, версия,
 * список и печать.
 */
export function записиПакета(пакет, файлПакета) {
  const где = dirname(resolve(файлПакета))
  if (пакет?.схема !== СХЕМА_ПАКЕТА) {
    throw new Error(прежняяСхема("пакет", пакет?.схема, СХЕМА_ПАКЕТА, `flang package <входной файл> > <имя>${РАСШИРЕНИЕ}`))
  }
  if (typeof пакет.имя !== "string" || пакет.имя === "") throw new Error("у пакета нет имени")
  if (typeof пакет.версия !== "string" || пакет.версия === "") throw new Error(`у пакета «${пакет.имя}» нет версии`)
  if (!Array.isArray(пакет.модули)) throw new Error(`в пакете «${пакет.имя}» нет списка модулей`)
  if (пакет.печать !== печатьПакета(пакет)) {
    throw new Error(`печать пакета «${пакет.имя}» не сходится: пакет правлен или испорчен`)
  }
  /* Входной модуль лежит по пути САМОГО ФАЙЛА ПАКЕТА, а не по своему пути
     внутри него: на пакет ссылаются `использует «Имя» из "sets.flang-package"`,
     и разрешение импорта обязано попасть ровно в эту запись. */
  return пакет.модули.map((модуль) => ({
    путь: модуль.путь === пакет.вход ? resolve(файлПакета) : resolve(где, модуль.путь),
    модуль,
  }))
}

/**
 * Разложить пакет в карту «полный путь файла → разбор».
 *
 * Всякое сомнение — ОТКАЗ, а не пропуск, и по той же причине, что у замка:
 * промах здесь означал бы чтение исходника, которого у того, кто подключил
 * пакет, нет и не будет. Молчаливое «соберём из того, что нашлось» дало бы
 * программу, собранную не из пакета.
 *
 * Каталог, в котором лежит сам файл пакета, — то, относительно чего
 * раскладываются пути замыкания, и относительно него же `link.mjs` разрешит
 * `использует … из "…"` внутри привезённых модулей. Совпадение этих двух
 * разрешений — то, на чём всё держится, и оно проверяется прогоном, а не
 * рассуждением (`flang/test/package.test.mjs`).
 *
 * `parse` передаётся снаружи, как и замку: в пакете лежит исходник, а не
 * дерево, и разбирать его обязана та же функция, что разбирает свои файлы.
 */
export function модулиПакета(пакет, файлПакета, parse) {
  if (typeof parse !== "function") throw new Error("пакету нужна функция разбора: в нём лежит исходник, а не дерево")
  const карта = new Map()
  let вход = null
  for (const { путь, модуль } of записиПакета(пакет, файлПакета)) {
    const дерево = разборМодуля(модуль, parse, `пакете «${пакет.имя} ${пакет.версия}»`)
    if (модуль.путь === пакет.вход) вход = дерево
    карта.set(путь, дерево)
  }
  if (вход === null) throw new Error(`в пакете «${пакет.имя}» нет входного модуля ${пакет.вход}`)
  if ((typeof вход.module === "string" ? вход.module : null) !== пакет.имя) {
    throw new Error(`пакет назван «${пакет.имя}», а его входной модуль — «${вход.module}»`)
  }
  return карта
}

/**
 * Собрать карту разборов по ВСЕМ пакетам, на которые ссылается программа.
 *
 * Обход по рёбрам импорта, а не по именам: имя ищется только для того, чтобы
 * назвать беду в отказе. Ребро даёт путь, путь даёт файл, файл даёт разбор —
 * и то, что приехало, есть ровно то, на что сослались.
 *
 * Транзитивность настоящая: пакет, который сам подключает пакет, разворачивается
 * тем же обходом. Столкновение двух пакетов на одном пути с РАЗНЫМ содержимым —
 * названный отказ, а не «кто первый».
 */
export async function пакетамиПрограммы(деревоВхода, файлВхода, parse, настройки = {}) {
  const читать = настройки.readFile ?? ((файл) => readFile(файл, "utf8"))
  const карта = new Map()
  const источники = new Map()
  const пройдено = new Set()
  const очередь = []

  const пройденоПакетом = (путь) => пройдено.has(путь)
  const поставить = (изФайла, дерево) => {
    for (const запись of importsOf(дерево)) {
      if (!этоПакет(запись.from)) continue
      const цель = isAbsolute(запись.from) ? запись.from : resolve(dirname(изФайла), запись.from)
      /* Вложенный пакет, уже приехавший грузом внутри внешнего, второй раз не
         ищется: он есть в карте, и на диске его нет. */
      if (пройдено.has(цель) || карта.has(цель)) continue
      пройдено.add(цель)
      очередь.push(цель)
    }
  }
  поставить(resolve(файлВхода), деревоВхода)
  if (очередь.length === 0) return null

  while (очередь.length > 0) {
    const файл = очередь.shift()
    let пакет = null
    try {
      пакет = JSON.parse(await читать(файл))
    } catch (беда) {
      throw new Error(`пакет ${файл} не прочитан: ${беда instanceof Error ? беда.message : String(беда)}`)
    }
    const свои = модулиПакета(пакет, файл, parse)
    for (const [путь, дерево] of свои) {
      const прежний = карта.get(путь)
      if (прежний !== undefined) {
        /* Сверяется СОДЕРЖИМОЕ, а не имя: два пакета вправе везти одну и ту же
           `lists.flang` — это ромб, и он разрешается сам собой, когда обе
           стороны везут одно и то же. Разное содержимое на одном пути — это
           две версии одной библиотеки, а их в flang не бывает. */
        if (JSON.stringify(прежний) !== JSON.stringify(дерево)) {
          throw new Error(
            `путь ${путь} привезли два пакета с разным содержимым: «${источники.get(путь)}» и «${пакет.имя} ${пакет.версия}». ` +
              "Двух версий одной библиотеки в одной программе не бывает: поднимите обе стороны до одной версии",
          )
        }
        continue
      }
      карта.set(путь, дерево)
      источники.set(путь, `${пакет.имя} ${пакет.версия}`)
    }
    /* Импорты привезённых модулей обходятся ПОСЛЕ того, как весь пакет лёг в
       карту, а не по ходу. Порядок здесь решает: пакет над пакетом везёт и
       верхний модуль, и вложенный файл пакета, и первый ссылается на второй.
       Обход по ходу поставил бы вложенный файл в очередь раньше, чем он попал
       в карту, и хозяин пошёл бы искать его на диске — где его нет и не должно
       быть. */
    for (const [путь, дерево] of свои) {
      if (пройденоПакетом(путь)) continue
      поставить(путь, дерево)
    }
  }
  return карта
}

