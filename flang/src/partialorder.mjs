/**
 * Частичный порядок: рефлексивность, антисимметрия, транзитивность.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Функция «Не старше», объявленная СТРОГИМ сравнением (`меньше` вместо
 * `не больше`), проходила `flang check --proof` со строкой «нет объявленных
 * законов». Отношение, при котором значение не сравнимо само с собой,
 * порядком не является ни при каком прочтении, — а сказать это языку было
 * нечем: отношений в нём не было вовсе.
 *
 * ── Ради чего это свойство ──────────────────────────────────────────────────
 *
 * Разрешение СРАВНИВАТЬ СОСТОЯНИЯ, и оно — основание под состояниями, которые
 * сходятся без блокировок. Реплика, принявшая обновление, обязана уметь
 * ответить «моё состояние не старше пришедшего»; из трёх законов порядка
 * следует, что ответ не зависит от того, в каком порядке обновления приходили:
 *
 *   рефлексивность  — состояние сравнимо само с собой, значит повторная
 *                     доставка не двигает реплику назад;
 *   антисимметрия   — два состояния, каждое «не старше» другого, РАВНЫ, значит
 *                     расхождение реплик было бы видно, а не пряталось бы за
 *                     двумя «не старше»;
 *   транзитивность  — цепочка сравнений замыкается, значит согласие двух реплик
 *                     о промежуточном состоянии есть согласие о крайних.
 *
 * Без антисимметрии остаётся ПРЕДПОРЯДОК, и это не мелочь: на нём две разные
 * реплики объявляются взаимно «не старше», а расхождение между ними — законным.
 * Поэтому проверяются все три и порознь, а сообщение называет, какой закон.
 *
 * ── Что здесь ПРОВЕРЯЕТСЯ, а не доказывается ────────────────────────────────
 *
 * Законы. Устройство доказано раньше и в другом месте (`types.mjs`, сличением
 * объявлений: два входа носителя, возврат — признак). Здесь — утверждения обо
 * всех парах и тройках значений носителя, а они неразрешимы: значит конечная
 * сетка, и ведомость обязана называть её размер строкой, оканчивающейся
 * словами «Это не доказательство».
 *
 * ── Порядок проверок содержательный, а не удобный ───────────────────────────
 *
 * Рефлексивность, антисимметрия, транзитивность — по возрастанию цены (линия,
 * квадрат, куб) и по убыванию частоты поломки. Первое же нарушение
 * ОСТАНАВЛИВАЕТ остальные: отношение, оказавшееся не порядком, порядком не
 * является, и всё, что о нём сказали бы остальные законы, было бы утверждением
 * о том, что порядком не является. По той же причине сломанный порядок
 * останавливает МОНОТОННОСТЬ (`monotone.mjs`).
 */
import { valuesEqual } from "./builtins.mjs"
import { ключТипа, ПРЕДЕЛ_СЕТКИ, объявления, основа, покажи, пусто } from "./svoystva.mjs"

export { ПРЕДЕЛ_СЕТКИ }

/** Имя свойства — то самое, что автор пишет в ёлочках. */
export const ИМЯ = "частичный порядок"

/**
 * Проверка частичного порядка всех отношений, его объявивших.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object>,
 *   assumed: Array<object>, permits: Array<object> }}
 */
export function checkPartialOrder(программа, пределы = {}) {
  const узлы = объявления(программа, ИМЯ)
  const итог = пусто()
  if (узлы.length === 0) return итог

  const { найти, звать, сетка } = основа(программа, пределы)

  for (const узел of узлы) {
    const функция = найти(узел.operation)
    if (функция === undefined || (функция.params ?? []).length !== 2) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation ?? null,
        why: "устройство отношения не сошлось: об этом сказала проверка типов",
      })
      continue
    }

    /* ТОЛЬКО ВХОДЫ: результат у отношения — признак, и класть `да` в сетку
       значений носителя значило бы считать порядок на признаках. */
    const значения = сетка([узел.operation], { толькоВходы: true })
    if (значения.length === 0) {
      итог.assumed.push({
        property: ИМЯ,
        subject: узел.operation,
        why: `у «${узел.operation}» нет примеров: сетка пуста, сравнивать было нечего`,
      })
      continue
    }

    const доБед = итог.diagnostics.length
    let оборвано = null
    let точек = 0
    const сказать = (код, текст) => {
      итог.diagnostics.push({
        code: код,
        message: `свойство «${ИМЯ}»: «${узел.operation}» ${текст}`,
        severity: "error",
        span: узел.span,
      })
    }
    const сравнить = (а, б) => {
      const ответ = звать(узел.operation, а, б)
      if (ответ.ошибка) return { нет: ответ.ошибка }
      if (typeof ответ.значение !== "boolean") {
        return { нет: `вернула ${покажи(ответ.значение)}, а не признак` }
      }
      return { да: ответ.значение }
    }

    законы: {
      /* 1. Рефлексивность — линия по сетке. */
      for (const х of значения) {
        точек += 1
        const сам = сравнить(х, х)
        if (сам.нет !== undefined) {
          оборвано = `отношение не посчиталось: ${сам.нет}`
          break законы
        }
        if (сам.да) continue
        сказать(
          "FLANG_ORDER_NOT_REFLEXIVE",
          `не рефлексивно: ${покажи(х)} не сравнимо с самим собой. Отношение, при котором значение ` +
            `не «не старше» себя, порядком не является ни при каком прочтении — и повторная доставка ` +
            `того же состояния двигала бы реплику назад`,
        )
        break законы
      }

      /* 2. Антисимметрия — квадрат. Без неё это ПРЕДПОРЯДОК, и на нём две
            разные реплики объявляются взаимно «не старше». */
      for (const х of значения) {
        for (const у of значения) {
          точек += 1
          const туда = сравнить(х, у)
          const назад = сравнить(у, х)
          if (туда.нет !== undefined || назад.нет !== undefined) {
            оборвано = `отношение не посчиталось: ${туда.нет ?? назад.нет}`
            break законы
          }
          if (!туда.да || !назад.да || valuesEqual(х, у)) continue
          сказать(
            "FLANG_ORDER_NOT_ANTISYMMETRIC",
            `не антисимметрично: ${покажи(х)} и ${покажи(у)} сравнимы в обе стороны, но не равны. ` +
              `Это предпорядок, а не порядок: на нём две разошедшиеся реплики объявляются взаимно ` +
              `«не старше», и расхождение между ними становится законным`,
          )
          break законы
        }
      }

      /* 3. Транзитивность — куб. */
      for (const х of значения) {
        for (const у of значения) {
          const первое = сравнить(х, у)
          if (первое.нет !== undefined) {
            оборвано = `отношение не посчиталось: ${первое.нет}`
            break законы
          }
          if (!первое.да) continue
          for (const з of значения) {
            точек += 1
            const второе = сравнить(у, з)
            const итого = сравнить(х, з)
            if (второе.нет !== undefined || итого.нет !== undefined) {
              оборвано = `отношение не посчиталось: ${второе.нет ?? итого.нет}`
              break законы
            }
            if (!второе.да || итого.да) continue
            сказать(
              "FLANG_ORDER_NOT_TRANSITIVE",
              `не транзитивно: ${покажи(х)} не старше ${покажи(у)}, ${покажи(у)} не старше ${покажи(з)}, ` +
                `а ${покажи(х)} и ${покажи(з)} — нет. Цепочка сравнений не замыкается, и согласие двух ` +
                `реплик о промежуточном состоянии перестаёт быть согласием о крайних`,
            )
            break законы
          }
        }
      }
    }

    const нарушений = итог.diagnostics.length - доБед
    итог.checked.push({
      property: ИМЯ,
      subject: узел.operation,
      values: значения.length,
      points: точек,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
    if (нарушений > 0 || оборвано !== null) continue
    итог.permits.push({
      permit: "сравнить",
      property: ИМЯ,
      subject: узел.operation,
      says: `состояния можно сравнивать «${узел.operation}»: три закона порядка посчитаны, ` +
        `значит согласие реплик не зависит от порядка, в котором к ним приходили обновления`,
    })
  }

  return итог
}

/**
 * Порядки, ПРОШЕДШИЕ проверку, — по ключу типа носителя.
 *
 * Это и есть точка, в которой одно свойство опирается на другое: монотонность
 * говорит «а ≤ б ⟹ ф(а) ≤ ф(б)», и без порядка на обоих концах функции сказать
 * ей нечего. Берётся отсюда, а не из объявлений: порядок, объявленный и
 * НАРУШЕННЫЙ, монотонности не годится — вердикт о монотонности относительно
 * того, что порядком не является, был бы утверждением ни о чём.
 *
 * Ключ — тип ПЕРВОГО входа отношения. Он же тип второго и тип носителя: это
 * сверила проверка типов, и второй раз здесь не сверяется.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {Map<string, {операция: string, значения: number}>}
 */
export function здоровыеПорядки(программа, пределы = {}) {
  const карта = new Map()
  const узлы = объявления(программа, ИМЯ)
  if (узлы.length === 0) return карта
  const итог = checkPartialOrder(программа, пределы)
  const прошли = new Set(итог.permits.map((запись) => запись.subject))
  const функции = Array.isArray(программа?.functions) ? программа.functions : []
  for (const узел of узлы) {
    if (!прошли.has(узел.operation)) continue
    const функция = функции.find((кандидат) => кандидат.name === узел.operation)
    const ключ = ключТипа(функция?.params?.[0]?.type)
    if (ключ === null || карта.has(ключ)) continue
    const посчитано = итог.checked.find((запись) => запись.subject === узел.operation)
    карта.set(ключ, { операция: узел.operation, значения: посчитано?.values ?? 0 })
  }
  return карта
}
