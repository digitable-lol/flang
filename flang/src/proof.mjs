const СЛОВАРЬ = [
  "слова ведомости, и они не взаимозаменяемы:",
  "  «доказано» — утверждение обо ВСЕХ входах, выведенное из объявлений и структуры;",
  "  «доказано индукцией по «Т»» — то же обо всех входах типа «Т», а не о написанных.",
  "      Принцип читается с ОБЪЯВЛЕНИЯ, и носителей у него два: у объявленной суммы —",
  "      начальность (часть значения меньше значения, шаг идёт при допущении на частях);",
  "      у отрезка «нат» — конечность [0, 2⁵³−1] и СТРОГИЙ спуск на единицу, и спуск",
  "      этот ядро читает в теле функции, а не принимает на слово;",
  "  «сетка N» — посчитано на N значениях автора, нарушений не найдено; это НЕ доказательство;",
  "  «объявлено, не доказано» — утверждение высказано, доказательства при нём нет;",
  "  «на веру» — не посчитано ничем, допущение автора.",
]

/**
 * Ведомость словами.
 *
 * Та же ведомость, что в JSON, и ни одного числа сверх неё: человек и
 * инструмент обязаны читать одно и то же, иначе спорить о числах будут они, а
 * не люди.
 *
 * @param {object} ведомость итог `proofLedger`
 * @returns {string} текст, оканчивающийся переводом строки
 */
export function formatProofLedger(ведомость) {
  const строки = []
  const модуль = ведомость.module === null ? "" : ` модуля «${ведомость.module}»`
  строки.push(`── ведомость доказательства${модуль} ──`, ...СЛОВАРЬ, "")

  const ширина = Math.max(0, ...ведомость.functions.map((ф) => отображаемых(`«${ф.name}»`)))
  строки.push("чем несётся обещание «тотальная»:")
  /* Пустой раздел без строчки — та же беда, что молчание про допущение: заголовок
     есть, под ним ничего, и читается это как сбой печати. Модель FTS без функций
     (`examples/task-status.fts` — одни записи) сюда приходит законно. */
  if (ведомость.functions.length === 0) строки.push("  нет объявленных функций")
  for (const ф of ведомость.functions) {
    const имя = `«${ф.name}»`
    строки.push(`  ${имя}${" ".repeat(ширина - отображаемых(имя))}  ${ф.says}`)
  }

  строки.push("", "законы (сетка конечна, доказательством не является):")
  if (ведомость.laws.length === 0) строки.push("  нет объявленных законов")
  for (const закон of ведомость.laws) строки.push(`  ${закон.kind} «${закон.name}» — ${закон.says}`)

  /* Раздел печатается только там, где утверждение высказано. У программы без
     постусловий и теорем его нет вовсе — и это не то же самое, что «пустой
     раздел»: пустой заголовок сообщил бы, что утверждения искали и не нашли, а
     их не было чем высказать до этой работы, и большинство файлов дерева их не
     высказывает до сих пор. */
  if (Array.isArray(ведомость.claims) && ведомость.claims.length > 0) {
    строки.push("", "что высказано и чем это несётся:")
    for (const запись of ведомость.claims) {
      const чья = запись.of === null ? "" : ` функции «${запись.of}»`
      строки.push(`  ${запись.kind} «${запись.name}»${чья} — ${запись.says}`)
    }
  }

  строки.push("", "принято на веру:")
  if (ведомость.assumed.length === 0) строки.push("  ничего")
  for (const запись of ведомость.assumed) строки.push(`  ${запись.kind} «${запись.name}» — ${запись.says}`)

  const и = ведомость.totals
  строки.push(
    "",
    "итог:",
    `  функций ${и.functions}: тотальных ${и.total}, обычных ${и.ordinary}`,
    `  обещание несёт: композиция ${и.carriers.composition}, структура ${и.carriers.structure}, `
      + `точный шаг ${и.carriers.exact}, постоянный шаг ${и.carriers.step}, объявленная мера ${и.carriers.measure}`,
    `  сторожей в рантайме: ${и.guardSites} ${мест(и.guardSites)}`,
    /* Точки (тройки) есть только у законов, которые перебирают тройки, — у
       моноида и монады. Печатать «точек 0» там, где троек не бывает, значило бы
       сообщить о нуле сделанной работы вместо «этот закон так не проверяют». */
    `  законов на сетке: ${и.laws.grid} (значений в сетках ${и.laws.gridValues}`
      + `${и.laws.gridPoints > 0 ? `, троек ${и.laws.gridPoints}` : ""})`
      /* Как и у утверждений: печатается только когда есть. */
      + `${(и.laws.violated ?? 0) > 0 ? `; НАРУШЕНО: ${и.laws.violated}` : ""}`
      + `; на веру: ${и.laws.assumed}`,
  )
  /* Строка итога по утверждениям печатается только там, где они есть, — по тому
     же правилу, что и раздел выше. */
  if (и.claims !== undefined && и.claims.total > 0) {
    строки.push(
      `  утверждений ${и.claims.total}: доказано ${и.claims.proved}`
        + `${(и.claims.induction ?? 0) > 0 ? ` (из них индукцией ${и.claims.induction})` : ""}`
        + безТеоремы(и.claims)
        + `, сетка ${и.claims.grid}, `
        + `объявлено, не доказано ${и.claims.declared}`
        + `${и.claims.refused > 0 ? `, отвергнуто ядром ${и.claims.refused}` : ""}`
        /* Печатается только когда есть: «НАРУШЕНО 0» в каждой ведомости
           приучило бы к этой строке за неделю, а она обязана бросаться в
           глаза. */
        + `${(и.claims.violated ?? 0) > 0 ? `, НАРУШЕНО на примерах ${и.claims.violated}` : ""}`
        + `${и.claims.steps > 0 ? ` (шагов в термах ${и.claims.steps})` : ""}`,
    )
  }
  if (и.unaccounted > 0) {
    строки.push(`  РАСХОЖДЕНИЕ: у ${и.unaccounted} тотальных функций носитель не назван`)
  }
  return `${строки.join("\n")}\n`
}

/* Ширина имени в знаках, а не в кодовых единицах: имена функций бывают на
   любом языке поверхности, и «阶乘» занимает две кодовые единицы UTF-16 при
   двух знаках. Считать `length` значило бы кривые столбцы у половины корпуса. */
function отображаемых(текст) {
  return [...String(текст)].length
}

/* Три формы вместо двух: «сетка 2 значений» и «2 мест» — тот сорт вывода, из-за
   которого отчёту не верят целиком, включая числа. */
function склонить(сколько, одно, два, много) {
  const сотня = сколько % 100
  if (сотня >= 11 && сотня <= 14) return много
  const единица = сколько % 10
  if (единица === 1) return одно
  if (единица >= 2 && единица <= 4) return два
  return много
}

function значений(сколько) {
  return склонить(сколько, "значение", "значения", "значений")
}

function мест(сколько) {
  return склонить(сколько, "место", "места", "мест")
}

/**
 * Скобка итога про утверждения, доказанные БЕЗ теоремы, и про то, скольким из
 * них факт дал объявленный тип.
 *
 * Два числа в одной скобке, а не два раза по числу: они вложены — второе есть
 * часть первого, — и печатать их порознь значило бы дать читателю складывать
 * самому. Второе печатается только когда оно есть: «объявленным типом 0» сказало
 * бы о нуле сделанной работы там, где работа просто другая.
 */
function безТеоремы(утверждения) {
  const всего = утверждения.declaration ?? 0
  if (всего === 0) return ""
  const типом = утверждения.byType ?? 0
  return ` (из них без теоремы ${всего}${типом > 0 ? `, объявленным типом ${типом}` : ""})`
}

function шагов(сколько) {
  return склонить(сколько, "шаг", "шага", "шагов")
}

function случаях(сколько) {
  return склонить(сколько, "случае", "случаях", "случаях")
}

function случаев(сколько) {
  return склонить(сколько, "случай", "случая", "случаев")
}
