/**
 * Строки законов — из `checked` тех модулей, которые считали.
 *
 * Размер сетки идёт в отчёт всегда, вместе с пределом: «сетка 12 значений» без
 * «предел 12» не даёт понять, кончились значения автора или кончился предел, а
 * это разные вещи. Первое — автор написал мало примеров, второе — сетка
 * упёрлась в потолок и на дальние значения никто не смотрел.
 */
function* законыПрограммы(program, итоги) {
  /* Обращение объявлено или нет — читается из AST, а не добавляется в `checked`:
     на форму `checked` уже сослались тесты законов дословно, и менять её ради
     отчёта значило бы переписать их за компанию. */
  const обращение = new Map(
    (Array.isArray(program?.monoids) ? program.monoids : [])
      .map((узел) => [узел.name, узел.inverse !== null && узел.inverse !== undefined]),
  )
  for (const запись of итоги?.monoid?.checked ?? []) {
    yield закон("моноид", запись.monoid, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.моноид,
      points: запись.triples,
      pointsOf: "троек",
      laws: обращение.get(запись.monoid) === true
        ? "ассоциативность, нейтральность, обратимость"
        : "ассоциативность, нейтральность",
    })
  }
  for (const запись of итоги?.monad?.checked ?? []) {
    yield закон("монада", запись.monad, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.монада,
      points: запись.triples,
      pointsOf: "троек",
      arrows: запись.arrows ?? [],
      arrowLimit: ПРЕДЕЛЫ.стрелки,
      laws: "левая единица, правая единица, ассоциативность связывания",
    })
  }
  for (const запись of итоги?.iso?.checked ?? []) {
    /* Предел двойной: `values` у изоморфизма — сумма двух сеток, по одной на
       объект, и каждая упирается в свой предел отдельно. */
    yield закон("изоморфизм", запись.isomorphism, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.изоморфизм * 2,
      laws: "кругооборот в обе стороны",
    })
  }
  for (const запись of итоги?.sets?.checked ?? []) {
    if (запись.embedding !== undefined) {
      yield закон("вложение", запись.embedding, {
        values: запись.values,
        limit: ПРЕДЕЛЫ.вложение,
        laws: "инъективность: склейки не нашлось",
      })
      continue
    }
    /* И здесь двойной, по той же причине: сложены образы двух вложений. */
    yield закон("общая часть", запись.intersection, {
      values: запись.values,
      limit: ПРЕДЕЛЫ["общая часть"] * 2,
      laws: "непустота: свидетель предъявлен",
      witness: запись.witness,
    })
  }
}

function закон(вид, имя, сетка) {
  const части = [`сетка ${сетка.values} ${значений(сетка.values)} (предел ${сетка.limit})`]
  if (сетка.points !== undefined) части.push(`${сетка.points} ${сетка.pointsOf}`)
  if (сетка.arrows !== undefined) {
    части.push(`стрелок ${сетка.arrows.length} (предел ${сетка.arrowLimit})`)
  }
  return {
    kind: вид,
    name: имя ?? null,
    verdict: "grid",
    grid: {
      values: сетка.values,
      limit: сетка.limit,
      ...(сетка.points === undefined ? {} : { points: сетка.points }),
      ...(сетка.arrows === undefined ? {} : { arrows: сетка.arrows }),
    },
    laws: сетка.laws,
    ...(сетка.witness === undefined ? {} : { witness: сетка.witness }),
    says: `${части.join(", ")}: нарушений не найдено (${сетка.laws}). Это не доказательство`,
  }
}

/**
 * То, что принято на веру.
 *
 * `assumed` возвращает сегодня только `sets.mjs`, и это не значит, что верить
 * больше нечему: изоморфизм без `даёт` не попадает ни в `checked`, ни в
 * `assumed` — он молчит. Ведомость его достаёт сама, потому что объявление,
 * о котором не сказано ничего, читается как проверенное.
 */
function* наВеруПрограммы(итоги) {
  for (const запись of итоги?.sets?.assumed ?? []) {
    const вид = запись.embedding !== undefined ? "вложение" : "общая часть"
    yield {
      kind: вид,
      name: запись.embedding ?? запись.intersection ?? null,
      verdict: "assumed",
      why: запись.why,
      says: `на веру: ${запись.why}`,
    }
  }
  for (const запись of итоги?.iso?.assumed ?? []) {
    yield {
      kind: "изоморфизм",
      name: запись.isomorphism ?? null,
      verdict: "assumed",
      why: запись.why,
      says: `на веру: ${запись.why}`,
    }
  }
}

/* ------------------------------------------------------------------ */
/* Утверждения: постусловия и теоремы                                  */
/* ------------------------------------------------------------------ */

/**
 * Строки высказанных утверждений — по одной на постусловие и на теорему.
 *
 * Вердикт берётся у ядра, а не выставляется здесь: ведомость называет своими
 * словами то, что посчитали другие, и своего мнения о доказанности у неё нет.
 * Ровно поэтому `discharge` приезжает готовым — его положило ядро
 * (`proofterm.mjs`) или анализ завершаемости, а обязательства только свели цель
 * с предложенным доказательством.
 *
 * Порядок разделов внутри: сначала постусловия функций (о них есть что сказать
 * по-разному), потом старая форма теоремы — она всегда «объявлено, не доказано»,
 * и стоит последней затем, чтобы это бросалось в глаза как долг, а не тонуло.
 */
function* утвержденияПрограммы(program, итоги) {
  for (const запись of итоги?.obligations?.obligations ?? []) {
    if (запись.kind !== "postcondition") continue
    yield утверждение(запись)
  }

  /* Старая форма теоремы. Она разбирается с самого начала и не читается никем:
     узел уезжает в `legacy`, и следствий из него не выводит ни типизатор, ни
     печать. Промолчать о ней нельзя — молчание читается как «нормально», а
     теорема, о которой ведомость молчит, выглядит доказанной. */
  for (const узел of program?.legacy ?? []) {
    if (узел?.construct !== "theorem") continue
    const имя = узел?.value?.title ?? null
    yield {
      kind: "теорема наследия",
      name: имя,
      of: null,
      verdict: "declared",
      grid: 0,
      steps: 0,
      says:
        "объявлено, не доказано: старая форма теоремы (наследие FTS) разбирается,"
        + " но следствий из неё не выводит никто — доказательства при ней нет вовсе",
    }
  }
}

function утверждение(запись) {
  const общее = {
    kind: ВИД_ПОСТУСЛОВИЯ,
    name: запись.name ?? null,
    of: запись.of ?? null,
    forall: запись.forall?.name ?? null,
  }
  const сброс = запись.discharge

  if (сброс !== null && сброс !== undefined && сброс.verdict === "доказано") {
    return {
      ...общее,
      verdict: "proved",
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      says:
        `доказано: терм принят ядром, ${сброс.steps ?? 0} ${шагов(сброс.steps ?? 0)}`
        + `${(сброс.cases?.length ?? 0) === 0 ? "" : ` в ${сброс.cases.length} ${случаях(сброс.cases.length)} индукции`}`
        + " — утверждение обо ВСЕХ входах",
    }
  }

  if (сброс !== null && сброс !== undefined && сброс.verdict === "сетка") {
    return {
      ...общее,
      verdict: "grid",
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      says:
        `сетка: терм принят ядром, но опирается на закон, посчитанный на конечной сетке`
        + " — это не доказательство",
    }
  }

  if (сброс !== null && сброс !== undefined && сброс.verdict === "отвергнуто") {
    /* Отвергнутый терм — это отказ программы, и до ведомости она не доходит
       (ведомость не печатается у программы с отказом). Строка всё равно есть:
       ведомость читают и по JSON от инструмента, который отказ показал отдельно. */
    return {
      ...общее,
      verdict: "refused",
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      says: `отвергнуто ядром: ${(сброс.refusals?.length ?? 0)} ${мест(сброс.refusals?.length ?? 0)} не сведено к названным фактам`,
    }
  }

  /* Доказательства нет. Тогда всё, что есть, — сетка примеров: постусловие
     проверяется после КАЖДОГО возврата, значит каждый пример его и проверил.
     Предела у этой сетки нет — её пишет автор и ничто её не ограничивает, — и
     поэтому здесь не «предел P», а честное «примеров N». */
  const примеров = запись.grid ?? 0
  if (примеров > 0) {
    return {
      ...общее,
      verdict: "grid",
      grid: примеров,
      steps: 0,
      says:
        `сетка ${примеров} ${значений(примеров)} (примеры функции): нарушений не найдено.`
        + " Это не доказательство — теоремы при утверждении нет",
    }
  }
  return {
    ...общее,
    verdict: "declared",
    grid: 0,
    steps: 0,
    says:
      "объявлено, не доказано: ни теоремы, ни примеров."
      + " Утверждение проверяется в рантайме после каждого возврата — на тех входах, которые придут",
  }
}

const ВИД_ПОСТУСЛОВИЯ = "постусловие"

/* ------------------------------------------------------------------ */
/* Итоги                                                              */
/* ------------------------------------------------------------------ */

function итоги_(строки, законы, наВеру, утверждения = []) {
  const носителей = { composition: 0, structure: 0, step: 0, measure: 0 }
  let тотальных = 0
  let мест = 0
  let несведённых = 0
  for (const строка of строки) {
    if (строка.total !== true) continue
    тотальных += 1
    мест += строка.guardSites
    if (строка.carrier === null) несведённых += 1
    else носителей[строка.carrier] += 1
  }
  return {
    functions: строки.length,
    total: тотальных,
    ordinary: строки.length - тотальных,
    carriers: носителей,
    /* Функции, у которых ведомость носителя не назвала. Ноль — единственное
       значение, при котором ведомость сошлась с анализом; поле есть затем,
       чтобы это можно было проверить числом, а не глазами. */
    unaccounted: несведённых,
    guardSites: мест,
    laws: {
      grid: законы.length,
      assumed: наВеру.length,
      gridValues: законы.reduce((сумма, закон) => сумма + (закон.grid?.values ?? 0), 0),
      gridPoints: законы.reduce((сумма, закон) => сумма + (закон.grid?.points ?? 0), 0),
    },
    /* Утверждения по вердиктам. Ключ есть всегда — в отличие от раздела, — и это
       не противоречие: раздел печатается человеку и пустой читался бы как сбой,
       а поле итога читает инструмент, и ноль в нём говорит «утверждений нет»
       ровно то же, что отсутствие ключа, но без ветвления у читателя. */
    claims: {
      total: утверждения.length,
      proved: утверждения.filter((з) => з.verdict === "proved").length,
      grid: утверждения.filter((з) => з.verdict === "grid").length,
      declared: утверждения.filter((з) => з.verdict === "declared").length,
      refused: утверждения.filter((з) => з.verdict === "refused").length,
      steps: утверждения.reduce((сумма, з) => сумма + (з.steps ?? 0), 0),
    },
  }
}

/* ------------------------------------------------------------------ */
/* Печать для человека                                                 */
/* ------------------------------------------------------------------ */

const СЛОВАРЬ = [
  "слова ведомости, и они не взаимозаменяемы:",
  "  «доказано» — утверждение обо ВСЕХ входах, выведенное из объявлений и структуры;",
  "  «сетка N» — посчитано на N значениях автора, нарушений не найдено; это НЕ доказательство;",
  "  «объявлено, не доказано» — утверждение высказано, доказательства при нём нет;",
  "  «на веру» — не посчитано ничем, допущение автора.",
]

/**
 * Ведомость словами.
 *
 * Та же ведомость, что в JSON, и ни одного числа сверх неё: человек и
 * инструмент обязаны читать одно и то же, иначе спорить о числах будут они, а
 * не люди.
 *
 * @param {object} ведомость итог `proofLedger`
 * @returns {string} текст, оканчивающийся переводом строки
 */
export function formatProofLedger(ведомость) {
  const строки = []
  const модуль = ведомость.module === null ? "" : ` модуля «${ведомость.module}»`
  строки.push(`── ведомость доказательства${модуль} ──`, ...СЛОВАРЬ, "")

  const ширина = Math.max(0, ...ведомость.functions.map((ф) => отображаемых(`«${ф.name}»`)))
  строки.push("чем несётся обещание «тотальная»:")
  /* Пустой раздел без строчки — та же беда, что молчание про допущение: заголовок
     есть, под ним ничего, и читается это как сбой печати. Модель FTS без функций
     (`examples/task-status.fts` — одни записи) сюда приходит законно. */
  if (ведомость.functions.length === 0) строки.push("  нет объявленных функций")
  for (const ф of ведомость.functions) {
    const имя = `«${ф.name}»`
    строки.push(`  ${имя}${" ".repeat(ширина - отображаемых(имя))}  ${ф.says}`)
  }

  строки.push("", "законы (сетка конечна, доказательством не является):")
  if (ведомость.laws.length === 0) строки.push("  нет объявленных законов")
  for (const закон of ведомость.laws) строки.push(`  ${закон.kind} «${закон.name}» — ${закон.says}`)

  /* Раздел печатается только там, где утверждение высказано. У программы без
     постусловий и теорем его нет вовсе — и это не то же самое, что «пустой
     раздел»: пустой заголовок сообщил бы, что утверждения искали и не нашли, а
     их не было чем высказать до этой работы, и большинство файлов дерева их не
     высказывает до сих пор. */
  if (Array.isArray(ведомость.claims) && ведомость.claims.length > 0) {
    строки.push("", "что высказано и чем это несётся:")
    for (const запись of ведомость.claims) {
      const чья = запись.of === null ? "" : ` функции «${запись.of}»`
      строки.push(`  ${запись.kind} «${запись.name}»${чья} — ${запись.says}`)
    }
  }

  строки.push("", "принято на веру:")
  if (ведомость.assumed.length === 0) строки.push("  ничего")
  for (const запись of ведомость.assumed) строки.push(`  ${запись.kind} «${запись.name}» — ${запись.says}`)

  const и = ведомость.totals
  строки.push(
    "",
    "итог:",
    `  функций ${и.functions}: тотальных ${и.total}, обычных ${и.ordinary}`,
    `  обещание несёт: композиция ${и.carriers.composition}, структура ${и.carriers.structure}, `
      + `постоянный шаг ${и.carriers.step}, объявленная мера ${и.carriers.measure}`,
    `  сторожей в рантайме: ${и.guardSites} ${мест(и.guardSites)}`,
    /* Точки (тройки) есть только у законов, которые перебирают тройки, — у
       моноида и монады. Печатать «точек 0» там, где троек не бывает, значило бы
       сообщить о нуле сделанной работы вместо «этот закон так не проверяют». */
    `  законов на сетке: ${и.laws.grid} (значений в сетках ${и.laws.gridValues}`
      + `${и.laws.gridPoints > 0 ? `, троек ${и.laws.gridPoints}` : ""}); на веру: ${и.laws.assumed}`,
  )
  /* Строка итога по утверждениям печатается только там, где они есть, — по тому
     же правилу, что и раздел выше. */
  if (и.claims !== undefined && и.claims.total > 0) {
    строки.push(
      `  утверждений ${и.claims.total}: доказано ${и.claims.proved}, сетка ${и.claims.grid}, `
        + `объявлено, не доказано ${и.claims.declared}`
        + `${и.claims.refused > 0 ? `, отвергнуто ядром ${и.claims.refused}` : ""}`
        + `${и.claims.steps > 0 ? ` (шагов в термах ${и.claims.steps})` : ""}`,
    )
  }
  if (и.unaccounted > 0) {
    строки.push(`  РАСХОЖДЕНИЕ: у ${и.unaccounted} тотальных функций носитель не назван`)
  }
  return `${строки.join("\n")}\n`
}

/* Ширина имени в знаках, а не в кодовых единицах: имена функций бывают на
   любом языке поверхности, и «阶乘» занимает две кодовые единицы UTF-16 при
   двух знаках. Считать `length` значило бы кривые столбцы у половины корпуса. */
function отображаемых(текст) {
  return [...String(текст)].length
}

/* Три формы вместо двух: «сетка 2 значений» и «2 мест» — тот сорт вывода, из-за
   которого отчёту не верят целиком, включая числа. */
function склонить(сколько, одно, два, много) {
  const сотня = сколько % 100
  if (сотня >= 11 && сотня <= 14) return много
  const единица = сколько % 10
  if (единица === 1) return одно
  if (единица >= 2 && единица <= 4) return два
  return много
}

function значений(сколько) {
  return склонить(сколько, "значение", "значения", "значений")
}

function мест(сколько) {
  return склонить(сколько, "место", "места", "мест")
}

function шагов(сколько) {
  return склонить(сколько, "шаг", "шага", "шагов")
}

function случаях(сколько) {
  return склонить(сколько, "случае", "случаях", "случаях")
}
