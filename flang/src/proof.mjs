/**
 * proof.mjs — ведомость доказательства: чем несётся обещание каждой функции и
 * на какой сетке смотрели законы.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Язык различает доказанное и посчитанное (docs/overview.ru.md, «Пользовательские
 * свойства проверяются, а не доказываются»), но различал он это только в
 * документации. Инструмент говорил одно слово на всё: `flang check` печатал
 * `valid: true`, и за этим `true` стояли рядом три совершенно разных вещи —
 * завершение, доказанное обходом графа вызовов; ассоциативность, посчитанная на
 * двенадцати значениях автора; и обратимость изоморфизма, не посчитанная ничем.
 * Прочитать по выводу, какая из них чем является, было нельзя.
 *
 * Отсюда ведомость. Она не проверяет ничего нового: все её числа анализ уже
 * считал и выбрасывал — `checkTotality` возвращал `guards` и `descents`,
 * `monoid.mjs`, `monad.mjs`, `iso.mjs` и `sets.mjs` возвращали `checked` и
 * `assumed`, а оболочка брала из результата один `diagnostics`. Работа
 * ведомости — донести посчитанное до печати и назвать каждое своим словом.
 *
 * ── Пять слов, и путать их нельзя ───────────────────────────────────────────
 * Главное требование к ведомости — словарь. «Проверено на двенадцати значениях»
 * читается как «доказано», и пока читается — числа доказательности не значат
 * ничего. Поэтому слова не пересекаются, и ни одно не встречается там, где
 * годится другое:
 *
 *   ДОКАЗАНО   — утверждение обо ВСЕХ входах, выведенное из объявлений и
 *                структуры программы. Так говорится о завершении и о том, чей
 *                терм доказательства принял ядро (`proofterm.mjs`).
 *   ДОКАЗАНО ИНДУКЦИЕЙ ПО «Т» — то же самое и строго больше: носитель
 *                утверждения БЕСКОНЕЧЕН, и покрыт он не перечислением, а
 *                принципом, прочитанным с объявления суммы «Т». База закрыта
 *                вычислением, шаг выведен при допущении на частях значения.
 *                Слово пятое, а не оттенок четвёртого: «доказано» без индукции
 *                говорит «цель свелась к названным фактам», а это — «цель верна
 *                на носителе, который нельзя перебрать». Отличать его надо и от
 *                «доказано структурой» из раздела выше: там речь о ЗАВЕРШЕНИИ
 *                функции, здесь — об истинности утверждения о её результате, и
 *                одно без другого бывает сплошь и рядом.
 *   СЕТКА N    — посчитано на N значениях, написанных автором, и нарушений на
 *                них не нашлось. Это НЕ доказательство: равенство вычислений на
 *                всех значениях носителя неразрешимо, и сетка конечна.
 *   ОБЪЯВЛЕНО, НЕ ДОКАЗАНО — утверждение высказано, а доказательства при нём
 *                нет вовсе. Сюда попадают старая форма `теорема` (наследие FTS:
 *                она разбирается, но следствий из неё не выводит никто) и
 *                постусловие без теоремы, у которого и примеров нет. Слово
 *                четвёртое, а не оттенок «на веру», и разница между ними
 *                содержательная: «на веру» — это допущение, которое считать
 *                НЕЧЕМ; «объявлено, не доказано» — это утверждение, которое
 *                считать есть чем, а никто не считал. Первое требует новой
 *                проверки, второе — доказательства от автора.
 *   НА ВЕРУ    — не посчитано ничем: объявление есть, считать его нечем или не
 *                на чем. Допущение автора.
 *
 * Пятое слово, которого здесь нет и не будет: «ядро состоятельно». Про ядро
 * ведомость не говорит ничего, и это намеренно — перекрёстная сверка ловит
 * ошибки ядра, но состоятельности не доказывает, а утверждение обязано быть той
 * силы, какой оно есть. Что про ядро сказать можно, сказано там, где это
 * измерено: в его собственных проверках.
 *
 * Слова «проверено» в ведомости нет вовсе, и это нарочно: оно и есть то самое
 * слово, которое читается двумя способами. Вместо него — «сетка N значений:
 * нарушений не найдено». Формулировка длиннее и сказать её короче нельзя:
 * «не найдено» и «нет» — разные утверждения (flang/cat/SETS.md).
 *
 * ── «Не найдено» означает «искали и не нашли» ───────────────────────────────
 * И это стоило отдельной работы, потому что сначала не означало. Строка «сетка
 * N значений (примеры функции): нарушений не найдено» печаталась о числе
 * `примеры.length`: ведомость СЧИТАЛА примеры и объявляла их чистыми, не
 * посмотрев ни на один. На порченом файле она говорила «нарушений не найдено» в
 * ту же секунду, когда `flang test` печатал `FLANG_PROPERTY` на примере автора.
 * Отчёт, который не умеет краснеть, хуже отсутствующего: он выдаёт спокойствие,
 * которого нет, и здесь оно стояло в документе, которому верят больше всего.
 *
 * Ищет теперь `grid.mjs` — прогоном примеров через тот же вычислитель, каким
 * работает `flang test`, — и ведомость печатает то, что он нашёл. Ответов три,
 * и они не сливаются: «нарушений не найдено (искали прогоном на всех N)»,
 * «НАРУШЕНО на примере «…»» и «нарушений НЕ ИСКАЛИ». Третий — про непроделанную
 * работу, и сказать его прямо можно; нельзя молчаливо считать, что всё хорошо.
 *
 * ШЕСТОЕ СЛОВО, «НАРУШЕНО», в словарь вверху ведомости не вписано намеренно:
 * там перечислены степени уверенности («доказано», «сетка», «на веру»), а это
 * не степень, а факт — найденный контрпример. Он бьёт любой вердикт, включая
 * «доказано»: расходятся тогда не два мнения, а доказательство и факт.
 *
 * То же и у законов: `checked` моноида, монады и изоморфизма приезжает и тогда,
 * когда закон НАРУШЕН (диагностика при этом есть, и программа отказная), и
 * ведомость обязана прочесть у модуля число нарушений, а не печатать «не
 * найдено» о сетке, на которой поиск оборвался на первом же контрпримере.
 *
 * ── Пять носителей обещания ─────────────────────────────────────────────────
 * Обещание `тотальная` несёт ровно одно из пяти, и это видно по тому, что
 * возвращает анализ:
 *
 *   КОМПОЗИЦИЯ   функция не входит ни в один цикл. Доказывать нечего: обещание
 *                складывается из обещаний тех, кого она зовёт.
 *   СТРУКТУРА    цикл есть, и на общей позиции убывает ЧАСТЬ значения. Значения
 *                flang — конечные деревья, цепочка частей обрывается сама.
 *                Рантайм об этом доказательстве не знает ничего.
 *   ТОЧНЫЙ ШАГ   цикл есть, убывает объявленный `нат` на целый постоянный
 *                шаг. Дно и потолок даёт САМ ТИП, внутри потолка шаг точен, и
 *                доказательство полное: сторожа нет. Это единственный носитель,
 *                который читает объявленный тип.
 *   ПОСТОЯННЫЙ ШАГ   цикл есть, убывает число на постоянный шаг при дне. В
 *                вещественных числах это доказательство; числа flang — IEEE-754,
 *                где `x − 1` при большом |x| равен `x`, поэтому анализ ставит
 *                сторожа и говорит, где. Отказ вместо зацикливания.
 *   ОБЪЯВЛЕННАЯ МЕРА  то же, но порядок назвал автор словом `убывает`. Сторож
 *                там же и по той же причине.
 *
 * Разница между стережёнными и доказанными называется в ведомости прямо: у
 * композиции, структуры и точного шага в строке нет сторожа, у постоянного шага
 * и объявленной меры он есть и посчитан по местам. Сторож — это не оговорка к доказательству, это его часть: `тотальная`
 * означает «завершится или честно откажет», и ведомость обязана показывать, где
 * второе возможно.
 *
 * ── Чего ведомость не делает ────────────────────────────────────────────────
 * Не печатается у программы с отказом. Ведомость говорит, чем несётся обещание;
 * у программы, которая не прошла проверку, обещания нет, и «доказано» в такой
 * ведомости было бы неправдой о каждой строке. Отказ печатается как всегда.
 */

import { ПРЕДЕЛ_СЕТКИ as ПРЕДЕЛ_ИЗО } from "./iso.mjs"
import { ПРЕДЕЛ_СЕТКИ as ПРЕДЕЛ_МОНАДЫ, ПРЕДЕЛ_СТРЕЛОК } from "./monad.mjs"
import { ПРЕДЕЛ_СЕТКИ as ПРЕДЕЛ_МОНОИДА } from "./monoid.mjs"
import { ПРЕДЕЛ_СЕТКИ as ПРЕДЕЛ_МНОЖЕСТВ } from "./sets.mjs"
import { describeMeasure } from "./totality.mjs"

/** Версия формата ведомости: её читают инструменты, значит она названа. */
export const ВЕДОМОСТЬ = 1

/**
 * Носители обещания — код для машины и слово для человека.
 *
 * Код латиницей и не меняется: по нему считают этапы. Слово — то самое, вокруг
 * которого вся работа, и оно одно и то же в человеческом выводе и в JSON,
 * потому что две разные формулировки одного факта и есть способ их спутать.
 */
export const НОСИТЕЛИ = Object.freeze({
  composition: "композицией",
  structure: "структурой",
  exact: "точным шагом",
  step: "постоянным шагом",
  measure: "объявленной мерой",
})

/** Предел сетки каждого закона — оттуда, где он объявлен, а не списком здесь. */
export const ПРЕДЕЛЫ = Object.freeze({
  моноид: ПРЕДЕЛ_МОНОИДА,
  монада: ПРЕДЕЛ_МОНАДЫ,
  изоморфизм: ПРЕДЕЛ_ИЗО,
  вложение: ПРЕДЕЛ_МНОЖЕСТВ,
  "общая часть": ПРЕДЕЛ_МНОЖЕСТВ,
  стрелки: ПРЕДЕЛ_СТРЕЛОК,
})

/**
 * Ведомость по программе.
 *
 * Итоги считает не по своим представлениям о программе, а по тому, что вернул
 * анализ: `cycles` говорит, у кого доказывать было что, `structures`, `guards` и
 * `descents` — чем именно доказали. Своего графа вызовов здесь нет и быть не
 * должно: второй граф — это второй ответ на тот же вопрос, и разойдётся он
 * молча.
 *
 * @param {object} program AST модуля
 * @param {{ totality: object, monoid?: object, monad?: object, iso?: object, sets?: object }} итоги
 *   результаты, которые уже посчитаны вызывающим (оболочка считает их для
 *   диагностик, и считать второй раз значило бы платить за монаду дважды)
 * @returns {object} ведомость: та же и для человека, и для JSON
 */
export function proofLedger(program, итоги) {
  const тотальность = итоги?.totality
  if (тотальность === undefined || тотальность === null) {
    throw new Error("ведомость требует результат checkTotality: без него о завершении сказать нечего")
  }

  const функции = Array.isArray(program?.functions) ? program.functions : []
  const вЦикле = new Map()
  for (const компонента of тотальность.cycles ?? []) {
    for (const имя of компонента) вЦикле.set(имя, компонента)
  }
  const поИмени = (список) => {
    const карта = new Map()
    for (const запись of список ?? []) {
      if (!карта.has(запись.from)) карта.set(запись.from, [])
      карта.get(запись.from).push(запись)
    }
    return карта
  }
  const структуры = поИмени(тотальность.structures)
  const точные = поИмени(тотальность.exact)
  const сторожа = поИмени(тотальность.guards)
  const меры = поИмени(тотальность.descents)

  const строки = функции.map((fn) => строкаФункции(fn, { вЦикле, структуры, точные, сторожа, меры }))
  const законы = [...законыПрограммы(program, итоги)]
  const наВеру = [...наВеруПрограммы(итоги)]
  const утверждения = [...утвержденияПрограммы(program, итоги)]

  const ведомость = {
    ledger: ВЕДОМОСТЬ,
    module: program?.module ?? null,
    functions: строки,
    laws: законы,
    assumed: наВеру,
    totals: итоги_(строки, законы, наВеру, утверждения),
  }
  /* Раздел появляется только у программы, где утверждение высказано. Ведомость
     программы без постусловий и теорем обязана остаться той же, что была: на её
     форму уже сослались тесты дословно, и добавить всем пустой раздел значило бы
     переписать их за компанию — ровно тот довод, по которому `checked` законов
     не менялся ради отчёта. */
  if (утверждения.length > 0) ведомость.claims = утверждения
  return ведомость
}

/* ------------------------------------------------------------------ */
/* Строка функции                                                      */
/* ------------------------------------------------------------------ */

function строкаФункции(fn, { вЦикле, структуры, точные, сторожа, меры }) {
  const имя = String(fn?.name ?? "")
  /* Обычная функция обещания не давала, и ведомость не притворяется, будто
     дала: у неё завершение обеспечивает лимит шагов вычислителя, а это не
     свойство программы. */
  if (fn?.total !== true) {
    return {
      name: имя,
      total: false,
      carrier: null,
      says: "обещания нет: функция обычная, о завершении не сказано ничего",
      recursive: null,
      cycle: null,
      argument: null,
      measure: null,
      guardSites: 0,
    }
  }

  const компонента = вЦикле.get(имя) ?? null
  const цикл = компонента === null ? null : [...компонента].sort()
  const общее = { name: имя, total: true, recursive: компонента !== null, cycle: цикл }

  if (компонента === null) {
    return {
      ...общее,
      carrier: "composition",
      says: `доказано ${НОСИТЕЛИ.composition}: рекурсии нет, обещание сложено из обещаний тех, кого зовёт`,
      argument: null,
      measure: null,
      guardSites: 0,
    }
  }

  /* Порядок ветвей ТОТ ЖЕ, что у анализа: структура → постоянный шаг →
     объявленная мера (`checkComponent` в totality.mjs). У анализа он значит
     «дешёвое доказательство побеждает», и ведомость обязана читать его так же:
     иначе объявленная рядом мера превратила бы отчёт о бесплатном структурном
     убывании в отчёт о стороже, которого нет. Совпасть эти списки в одной
     функции не могут — компонента доказывается одним способом, — но порядок
     здесь не «на всякий случай», а единственное место, где эта договорённость
     записана дважды и потому проверяема. */
  const структура = структуры.get(имя)
  if (структура !== undefined && структура.length > 0) {
    const аргумент = аргументом(структура[0])
    return {
      ...общее,
      carrier: "structure",
      says: `доказано ${НОСИТЕЛИ.structure}: ${аргумент} на каждом витке становится частью себя`
        + `${через(цикл, имя)}; цепочка частей конечного дерева обрывается сама, сторожа нет`,
      argument: аргумент,
      measure: null,
      guardSites: 0,
    }
  }

  /* Точный шаг стоит ПЕРЕД стережённым по тому же правилу, по которому
     структура стоит перед обоими: дешёвое доказательство побеждает, а
     доказательство без сторожа дешевле доказательства со сторожем. Совпасть
     эти два списка в одной функции не могут — компонента уходит либо в один,
     либо в другой, — но порядок записан здесь дважды и потому проверяем. */
  const точный = точные?.get(имя)
  if (точный !== undefined && точный.length > 0) {
    const аргумент = аргументом(точный[0])
    return {
      ...общее,
      carrier: "exact",
      says: `доказано ${НОСИТЕЛИ.exact}: ${аргумент} объявлен натуральным и убывает на ${точный[0].step}`
        + `${через(цикл, имя)}; дно и потолок даёт тип, внутри потолка шаг точен — сторожа нет`,
      argument: аргумент,
      measure: null,
      guardSites: 0,
    }
  }

  const сторож = сторожа.get(имя)
  if (сторож !== undefined && сторож.length > 0) {
    const аргумент = аргументом(сторож[0])
    return {
      ...общее,
      carrier: "step",
      says: `доказано ${НОСИТЕЛИ.step}: ${аргумент} убывает на постоянный шаг и ограничен снизу`
        + `${через(цикл, имя)}; на IEEE-754 шаг не всегда меняет число, поэтому сторож, ${местами(сторож.length)}`,
      argument: аргумент,
      measure: null,
      guardSites: сторож.length,
    }
  }

  const мера = меры.get(имя)
  if (мера !== undefined && мера.length > 0) {
    const текст = describeMeasure(мера[0].current)
    return {
      ...общее,
      carrier: "measure",
      says: `доказано ${НОСИТЕЛИ.measure}: убывает ${текст}${через(цикл, имя)}; `
        + `мера объявлена автором, сторож считает её на каждом витке — ${местами(мера.length)}`,
      argument: null,
      measure: текст,
      guardSites: мера.length,
    }
  }

  /* Сюда попасть нельзя: цикл без доказательства уходит в `failed`, а `cycles`
     возвращает только доказанные компоненты целиком. Строка всё равно есть —
     промолчать о функции в ведомости хуже, чем признаться, что о ней сказать
     нечем: молчание читается как «нормально». */
  return {
    ...общее,
    carrier: null,
    says: "рекурсия есть, а чем доказана — анализ не назвал: это расхождение ведомости с анализом",
    argument: null,
    measure: null,
    guardSites: 0,
  }
}

/** «аргумент 2 («показатель»)» — позиция и имя, чтобы можно было пойти и прочесть. */
function аргументом(запись) {
  const имя = запись?.param
  const номер = Number(запись?.position ?? 0) + 1
  return имя === null || имя === undefined ? `аргумент ${номер}` : `аргумент ${номер} («${имя}»)`
}

/** Цикл из нескольких функций назван целиком: обещание у них общее. */
function через(цикл, имя) {
  const прочие = (цикл ?? []).filter((другое) => другое !== имя)
  return прочие.length === 0 ? "" : ` в цикле с ${прочие.map((другое) => `«${другое}»`).join(", ")}`
}

function местами(сколько) {
  return `${сколько} ${мест(сколько)}`
}

