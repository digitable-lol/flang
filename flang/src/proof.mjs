/**
 * Строки законов — из `checked` тех модулей, которые считали.
 *
 * Размер сетки идёт в отчёт всегда, вместе с пределом: «сетка 12 значений» без
 * «предел 12» не даёт понять, кончились значения автора или кончился предел, а
 * это разные вещи. Первое — автор написал мало примеров, второе — сетка
 * упёрлась в потолок и на дальние значения никто не смотрел.
 */
function* законыПрограммы(program, итоги) {
  /* Обращение объявлено или нет — читается из AST, а не добавляется в `checked`:
     на форму `checked` уже сослались тесты законов дословно, и менять её ради
     отчёта значило бы переписать их за компанию. */
  const обращение = new Map(
    (Array.isArray(program?.monoids) ? program.monoids : [])
      .map((узел) => [узел.name, узел.inverse !== null && узел.inverse !== undefined]),
  )
  /* ЧТО ИЗМЕНИЛОСЬ У МОНОИДА, и это первое место, где объявленное свойство
     меняет вердикт о ЧУЖОЙ конструкции.
     В объявлении моноида коммутативности не было, и это стояло записанным
     честно: `flang/cat/SPEC.md` называл множество «моноидом, коммутативным», а
     сказать этого языком было нечем. Теперь есть — отдельным объявлением, — и
     моноид, чья операция объявлена коммутативной и посчитана чистой, называет
     это в своей же строке законов. То же у идемпотентности: моноид с
     идемпотентной операцией есть полурешётка, и разрешение «сливать состояния
     без блокировок» относится к нему целиком, а не к одной функции.
     Слово берётся из `permits`, а не из `properties`: объявленное и НЕ
     посчитанное не есть закон моноида, и приписать его сюда значило бы выдать
     объявление за проверку. */
  const свойстваОперации = (операция) => {
    const слова = []
    for (const [ключ, слово] of [["commutative", "коммутативность"], ["idempotent", "идемпотентность"]]) {
      if ((итоги?.[ключ]?.permits ?? []).some((запись) => запись.subject === операция)) слова.push(слово)
    }
    return слова
  }
  const операции = new Map(
    (Array.isArray(program?.monoids) ? program.monoids : []).map((узел) => [узел.name, узел.operation]),
  )
  for (const запись of итоги?.monoid?.checked ?? []) {
    const свои = обращение.get(запись.monoid) === true
      ? ["ассоциативность", "нейтральность", "обратимость"]
      : ["ассоциативность", "нейтральность"]
    yield закон("моноид", запись.monoid, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.моноид,
      points: запись.triples,
      pointsOf: "троек",
      laws: [...свои, ...свойстваОперации(операции.get(запись.monoid))].join(", "),
    })
  }
  for (const запись of итоги?.monad?.checked ?? []) {
    yield закон("монада", запись.monad, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.монада,
      points: запись.triples,
      pointsOf: "троек",
      arrows: запись.arrows ?? [],
      arrowLimit: ПРЕДЕЛЫ.стрелки,
      laws: "левая единица, правая единица, ассоциативность связывания",
    })
  }
  for (const запись of итоги?.iso?.checked ?? []) {
    /* Предел двойной: `values` у изоморфизма — сумма двух сеток, по одной на
       объект, и каждая упирается в свой предел отдельно. */
    yield закон("изоморфизм", запись.isomorphism, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.изоморфизм * 2,
      laws: "кругооборот в обе стороны",
    })
  }
  for (const запись of итоги?.sets?.checked ?? []) {
    if (запись.embedding !== undefined) {
      yield закон("вложение", запись.embedding, {
        values: запись.values,
        limit: ПРЕДЕЛЫ.вложение,
        laws: "инъективность: склейки не нашлось",
      })
      continue
    }
    /* И здесь двойной, по той же причине: сложены образы двух вложений. */
    yield закон("общая часть", запись.intersection, {
      values: запись.values,
      limit: ПРЕДЕЛЫ["общая часть"] * 2,
      laws: "непустота: свидетель предъявлен",
      witness: запись.witness,
    })
  }
  /* Пять объявленных свойств. Каждое печатается СВОЕЙ строкой и своим именем —
     не «свойство «Х»», а «идемпотентность «Применить оплату»»: свойство, из
     которого следует своё разрешение, обязано и называться своим словом.
     Предел умножается на число сеток: у монотонности их две (домен и кодомен),
     и один предел рядом с суммой значений читался бы как упор в потолок там,
     где потолка ещё не видели. */
  for (const ключ of Object.keys(СВОЙСТВА_ВЕДОМОСТИ)) {
    for (const запись of итоги?.[ключ]?.checked ?? []) {
      yield закон(запись.property, запись.subject, {
        values: запись.values,
        limit: ПРЕДЕЛЫ.свойство * Math.max(запись.grids ?? 1, 1),
        points: запись.points,
        /* Слово называет свойство, а не ведомость: у идемпотентности точка —
           это повтор, у коммутативности — пара, у транзитивности — тройка.
           Одно слово на пятерых было бы ровно тем «примерно тем же», из-за
           которого отчёту перестают верить целиком, включая числа. */
        pointsOf: склонить(запись.points ?? 0, ...ФОРМЫ_ТОЧЕК[ключ]),
        violations: запись.violations,
        aborted: запись.aborted,
        laws: СВОЙСТВА_ВЕДОМОСТИ[ключ],
      })
    }
  }
}

function закон(вид, имя, сетка) {
  const части = [`сетка ${сетка.values} ${значений(сетка.values)} (предел ${сетка.limit})`]
  if (сетка.points !== undefined) части.push(`${сетка.points} ${сетка.pointsOf}`)
  if (сетка.arrows !== undefined) {
    части.push(`стрелок ${сетка.arrows.length} (предел ${сетка.arrowLimit})`)
  }
  /* «Нарушений не найдено» о законе, который НАРУШЕН, — это ровно та неправда,
     ради запрета которой ведомость и заведена. Поля появляются только там, где
     их передали, поэтому строка каждого закона, посчитанного вчера, остаётся
     побайтово прежней. */
  const нарушено = (сетка.violations ?? 0) > 0
  const оборвано = typeof сетка.aborted === "string" && сетка.aborted !== ""
  const вердикт = нарушено ? "broken" : оборвано ? "aborted" : "grid"
  const говорит = нарушено
    ? `${части.join(", ")}: НАРУШЕНО, ${сетка.violations} ${случаев(сетка.violations)} (${сетка.laws}). `
      + "Контрпример предъявлен диагностикой"
    : оборвано
      ? `${части.join(", ")}: посчитано не всё — ${сетка.aborted} (${сетка.laws}). Это не доказательство`
      : `${части.join(", ")}: нарушений не найдено (${сетка.laws}). Это не доказательство`
  return {
    kind: вид,
    name: имя ?? null,
    verdict: вердикт,
    grid: {
      values: сетка.values,
      limit: сетка.limit,
      ...(сетка.points === undefined ? {} : { points: сетка.points }),
      ...(сетка.arrows === undefined ? {} : { arrows: сетка.arrows }),
    },
    laws: сетка.laws,
    ...(сетка.witness === undefined ? {} : { witness: сетка.witness }),
    ...(нарушено ? { violations: сетка.violations } : {}),
    ...(оборвано ? { aborted: сетка.aborted } : {}),
    says: говорит,
  }
}

/**
 * То, что принято на веру.
 *
 * `assumed` возвращает сегодня только `sets.mjs`, и это не значит, что верить
 * больше нечему: изоморфизм без `даёт` не попадает ни в `checked`, ни в
 * `assumed` — он молчит. Ведомость его достаёт сама, потому что объявление,
 * о котором не сказано ничего, читается как проверенное.
 */
function* наВеруПрограммы(итоги) {
  for (const запись of итоги?.sets?.assumed ?? []) {
    const вид = запись.embedding !== undefined ? "вложение" : "общая часть"
    yield {
      kind: вид,
      name: запись.embedding ?? запись.intersection ?? null,
      verdict: "assumed",
      why: запись.why,
      says: `на веру: ${запись.why}`,
    }
  }
  for (const запись of итоги?.iso?.assumed ?? []) {
    yield {
      kind: "изоморфизм",
      name: запись.isomorphism ?? null,
      verdict: "assumed",
      why: запись.why,
      says: `на веру: ${запись.why}`,
    }
  }
  /* Объявленное свойство, которое не на чем было посчитать. Молчать о нём
     нельзя по той же причине, по какой нельзя молчать об изоморфизме без
     `даёт`: свойство объявлено, разрешение из него НЕ выдано, а объявление, о
     котором отчёт молчит, читается как проверенное. */
  for (const ключ of Object.keys(СВОЙСТВА_ВЕДОМОСТИ)) {
    for (const запись of итоги?.[ключ]?.assumed ?? []) {
      yield {
        kind: запись.property,
        name: запись.subject ?? null,
        verdict: "assumed",
        why: запись.why,
        says: `на веру: ${запись.why}`,
      }
    }
  }
}

/**
 * Разрешения — то, ЧТО ИЗ ПОСЧИТАННОГО СЛЕДУЕТ.
 *
 * Раздел отдельный от законов, и это не оформление. Закон говорит, что
 * посчитано; разрешение — что компилятору теперь позволено делать такого, чего
 * он не мог раньше. Свойство, из которого ничего не следует, языку не нужно, и
 * пустой раздел здесь — приговор проверке, а не отчёту.
 *
 * Разрешение выдаётся ровно за чистый счёт на НЕПУСТОЙ сетке. Нарушение —
 * разрешения нет; пустая сетка — разрешения нет, и запись стоит строкой «на
 * веру» выше. Слабее этого нельзя: разрешение, выданное за непосчитанное, и
 * есть та самая продажа перебора за доказательство.
 */
function* разрешенияПрограммы(итоги) {
  for (const ключ of Object.keys(СВОЙСТВА_ВЕДОМОСТИ)) {
    for (const запись of итоги?.[ключ]?.permits ?? []) {
      yield {
        permit: запись.permit,
        kind: запись.property,
        name: запись.subject ?? null,
        /* Сетка КОНЕЧНА, и разрешение получено на ней. Слово стоит в самой
           записи, а не в шапке раздела: запись уезжает в JSON поодиночке, и
           читатель одной записи обязан видеть её цену. */
        verdict: "grid",
        says: запись.says,
      }
    }
  }
}

