/**
 * Строки законов — из `checked` тех модулей, которые считали.
 *
 * Размер сетки идёт в отчёт всегда, вместе с пределом: «сетка 12 значений» без
 * «предел 12» не даёт понять, кончились значения автора или кончился предел, а
 * это разные вещи. Первое — автор написал мало примеров, второе — сетка
 * упёрлась в потолок и на дальние значения никто не смотрел.
 */
function* законыПрограммы(program, итоги) {
  /* Обращение объявлено или нет — читается из AST, а не добавляется в `checked`:
     на форму `checked` уже сослались тесты законов дословно, и менять её ради
     отчёта значило бы переписать их за компанию. */
  const обращение = new Map(
    (Array.isArray(program?.monoids) ? program.monoids : [])
      .map((узел) => [узел.name, узел.inverse !== null && узел.inverse !== undefined]),
  )
  for (const запись of итоги?.monoid?.checked ?? []) {
    yield закон("моноид", запись.monoid, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.моноид,
      points: запись.triples,
      pointsOf: "троек",
      violations: запись.violations,
      aborted: запись.aborted,
      laws: обращение.get(запись.monoid) === true
        ? "ассоциативность, нейтральность, обратимость"
        : "ассоциативность, нейтральность",
    })
  }
  for (const запись of итоги?.monad?.checked ?? []) {
    yield закон("монада", запись.monad, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.монада,
      points: запись.triples,
      pointsOf: "троек",
      arrows: запись.arrows ?? [],
      arrowLimit: ПРЕДЕЛЫ.стрелки,
      violations: запись.violations,
      skipped: запись.skipped,
      laws: "левая единица, правая единица, ассоциативность связывания",
    })
  }
  for (const запись of итоги?.iso?.checked ?? []) {
    /* Предел двойной: `values` у изоморфизма — сумма двух сеток, по одной на
       объект, и каждая упирается в свой предел отдельно. */
    yield закон("изоморфизм", запись.isomorphism, {
      values: запись.values,
      limit: ПРЕДЕЛЫ.изоморфизм * 2,
      violations: запись.violations,
      laws: "кругооборот в обе стороны",
    })
  }
  for (const запись of итоги?.sets?.checked ?? []) {
    if (запись.embedding !== undefined) {
      yield закон("вложение", запись.embedding, {
        values: запись.values,
        limit: ПРЕДЕЛЫ.вложение,
        laws: "инъективность: склейки не нашлось",
      })
      continue
    }
    /* И здесь двойной, по той же причине: сложены образы двух вложений. */
    yield закон("общая часть", запись.intersection, {
      values: запись.values,
      limit: ПРЕДЕЛЫ["общая часть"] * 2,
      laws: "непустота: свидетель предъявлен",
      witness: запись.witness,
    })
  }
}

/**
 * Строка одного закона.
 *
 * «Нарушений не найдено» здесь означает ровно то же, что у сетки примеров:
 * ИСКАЛИ И НЕ НАШЛИ. Ищут сами модули законов — они вычисляют сетку, — и
 * ведомость читает у них две вещи, о которых раньше не спрашивала: сколько
 * нарушений нашлось (`violations`) и не оборвался ли обход, не дойдя до конца
 * сетки (`aborted`, `skipped`). Без этого нарушенный моноид попадал в отчёт
 * такой же строкой, как честный, — модуль клал его в `checked` безусловно.
 */
function закон(вид, имя, сетка) {
  const части = [`сетка ${сетка.values} ${значений(сетка.values)} (предел ${сетка.limit})`]
  if (сетка.points !== undefined) части.push(`${сетка.points} ${сетка.pointsOf}`)
  if (сетка.arrows !== undefined) {
    части.push(`стрелок ${сетка.arrows.length} (предел ${сетка.arrowLimit})`)
  }
  const нарушений = сетка.violations ?? 0
  const оборвано = сетка.aborted ?? null
  const пропущено = сетка.skipped ?? 0
  return {
    kind: вид,
    name: имя ?? null,
    verdict: нарушений > 0 ? "violated" : "grid",
    grid: {
      values: сетка.values,
      limit: сетка.limit,
      ...(сетка.points === undefined ? {} : { points: сетка.points }),
      ...(сетка.arrows === undefined ? {} : { arrows: сетка.arrows }),
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(пропущено === 0 ? {} : { skipped: пропущено }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    },
    laws: сетка.laws,
    ...(сетка.witness === undefined ? {} : { witness: сетка.witness }),
    says: нарушений > 0
      ? `${части.join(", ")}: НАРУШЕНО, ${нарушений} ${мест(нарушений)} (${сетка.laws}).`
        + " Сетка конечна, но контрпримера хватило"
      : `${части.join(", ")}: ${сказатьПроСетку(пропущено, оборвано)} (${сетка.laws}). Это не доказательство`,
  }
}

/**
 * Что сказать о сетке, на которой нарушений не нашлось.
 *
 * Прошли её насквозь — «нарушений не найдено», и это правда. Оборвался обход или
 * часть точек сравнить было нечем — так и сказано: молчаливое «не найдено» о
 * непройденном и есть та самая неправда, ради которой всё это писалось.
 */
function сказатьПроСетку(пропущено, оборвано) {
  if (оборвано !== null) return `нарушений не найдено там, докуда дошли — обход оборван: ${оборвано}`
  if (пропущено > 0) return `нарушений не найдено, но ${пропущено} точек сравнить было нечем`
  return "нарушений не найдено"
}

/**
 * То, что принято на веру.
 *
 * `assumed` возвращает сегодня только `sets.mjs`, и это не значит, что верить
 * больше нечему: изоморфизм без `даёт` не попадает ни в `checked`, ни в
 * `assumed` — он молчит. Ведомость его достаёт сама, потому что объявление,
 * о котором не сказано ничего, читается как проверенное.
 */
function* наВеруПрограммы(итоги) {
  for (const запись of итоги?.sets?.assumed ?? []) {
    const вид = запись.embedding !== undefined ? "вложение" : "общая часть"
    yield {
      kind: вид,
      name: запись.embedding ?? запись.intersection ?? null,
      verdict: "assumed",
      why: запись.why,
      says: `на веру: ${запись.why}`,
    }
  }
  for (const запись of итоги?.iso?.assumed ?? []) {
    yield {
      kind: "изоморфизм",
      name: запись.isomorphism ?? null,
      verdict: "assumed",
      why: запись.why,
      says: `на веру: ${запись.why}`,
    }
  }
}

