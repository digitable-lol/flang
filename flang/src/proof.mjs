/** Законы, у которых контрпример НАЙДЕН, — их считают отдельно от посчитанных. */
function нарушенныхЗаконов(законы) {
  return законы.filter((закон) => закон.verdict === "violated").length
}

function итоги_(строки, законы, наВеру, утверждения = []) {
  const носителей = { composition: 0, structure: 0, exact: 0, step: 0, measure: 0 }
  let тотальных = 0
  let мест = 0
  let несведённых = 0
  for (const строка of строки) {
    if (строка.total !== true) continue
    тотальных += 1
    мест += строка.guardSites
    if (строка.carrier === null) несведённых += 1
    else носителей[строка.carrier] += 1
  }
  return {
    functions: строки.length,
    total: тотальных,
    ordinary: строки.length - тотальных,
    carriers: носителей,
    /* Функции, у которых ведомость носителя не назвала. Ноль — единственное
       значение, при котором ведомость сошлась с анализом; поле есть затем,
       чтобы это можно было проверить числом, а не глазами. */
    unaccounted: несведённых,
    guardSites: мест,
    /* «На сетке» считает законы, у которых поиск нарушений вернулся ни с чем, —
       и только их. Закон, у которого контрпример НАЙДЕН, стоит в строках со
       своим вердиктом и считается отдельно: сложить их значило бы отчитаться о
       нарушенном законе как о посчитанном. Ключ `violated` появляется только
       когда есть что считать — «нарушено 0» в каждой ведомости приучило бы к
       себе за неделю. */
    laws: {
      grid: законы.filter((закон) => закон.verdict === "grid").length,
      assumed: наВеру.length,
      ...(нарушенныхЗаконов(законы) === 0 ? {} : { violated: нарушенныхЗаконов(законы) }),
      gridValues: законы.reduce((сумма, закон) => сумма + (закон.verdict === "grid" ? закон.grid?.values ?? 0 : 0), 0),
      gridPoints: законы.reduce((сумма, закон) => сумма + (закон.verdict === "grid" ? закон.grid?.points ?? 0 : 0), 0),
    },
    /* Утверждения по вердиктам. Ключ есть всегда — в отличие от раздела, — и это
       не противоречие: раздел печатается человеку и пустой читался бы как сбой,
       а поле итога читает инструмент, и ноль в нём говорит «утверждений нет»
       ровно то же, что отсутствие ключа, но без ветвления у читателя. */
    claims: {
      total: утверждения.length,
      /* `proved` считает ВСЕ утверждения обо всех входах — и выведенные цепочкой,
         и выведенные индукцией: доказанность у них одна и та же. `induction` —
         не второй счёт того же, а ответ на другой вопрос: сколькими из них
         покрыт бесконечный носитель. Сложить их значило бы посчитать одно
         утверждение дважды, а не назвать — потерять пятое слово в итоге. */
      proved: утверждения.filter((з) => з.verdict === "proved" || з.verdict === "proved-induction").length,
      induction: утверждения.filter((з) => з.verdict === "proved-induction").length,
      /* Третий счёт того же рода, что `induction`, и заведён по той же причине:
         он отвечает на вопрос «сколько доказано без единого написанного терма —
         одним сведением цели с телом». Сложить его с `proved` нельзя, промолчать
         о нём тоже: тогда «доказано» перестало бы говорить, ЧЕМ. */
      declaration: утверждения.filter((з) => з.by === "declaration").length,
      /* И его подсчёт: у скольких из них факт дал ОБЪЯВЛЕННЫЙ ТИП, а не литерал
         с выбором. Свернуть эти два в одно значило бы сказать «по объявленным
         типам» о доказательстве, которое ни одного объявления не читало. */
      byType: утверждения.filter((з) => з.byType === true).length,
      grid: утверждения.filter((з) => з.verdict === "grid").length,
      declared: утверждения.filter((з) => з.verdict === "declared").length,
      refused: утверждения.filter((з) => з.verdict === "refused").length,
      /* Шестое число, и оно про факт, а не про доказательство: у скольких
         утверждений прогон примеров НАШЁЛ нарушение. Ноль здесь — единственное
         значение, при котором остальные числа этой строки что-то значат: при
         найденном контрпримере «доказано» рядом означало бы ошибку ядра, а
         «сетка» — что сетку считали, а не смотрели. */
      violated: утверждения.filter((з) => з.verdict === "violated").length,
      steps: утверждения.reduce((сумма, з) => сумма + (з.steps ?? 0), 0),
    },
  }
}

