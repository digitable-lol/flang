/**
 * Строки высказанных утверждений — по одной на постусловие и на теорему.
 *
 * Вердикт берётся у ядра, а не выставляется здесь: ведомость называет своими
 * словами то, что посчитали другие, и своего мнения о доказанности у неё нет.
 * Ровно поэтому `discharge` приезжает готовым — его положило ядро
 * (`proofterm.mjs`) или анализ завершаемости, а обязательства только свели цель
 * с предложенным доказательством.
 *
 * Порядок разделов внутри: сначала постусловия функций (о них есть что сказать
 * по-разному), потом старая форма теоремы — она всегда «объявлено, не доказано»,
 * и стоит последней затем, чтобы это бросалось в глаза как долг, а не тонуло.
 */
function* утвержденияПрограммы(program, итоги) {
  /* Поиск нарушений на сетке сводится с обязательством ПО МЕСТУ В СПИСКЕ, а не
     по имени и не по `id`: и то и другое уникально по договорённости (имя — в
     пределах функции), а два одноимённых постусловия у одной функции язык не
     запрещает, и тогда чужое нарушение приписалось бы соседу. Порядок же общий:
     `grid.mjs` обходит тот же список тем же отбором. Совпадение `id` сверяется —
     разошёлся порядок, значит записи не о том, и ведомость честно скажет «не
     искали» вместо чужого ответа.

     Записи может не быть вовсе (ведомость собирают и по итогам, посчитанным без
     прогона), и тогда ведомость обязана сказать «не искали», а не «не найдено». */
  const поиск = Array.isArray(итоги?.grid?.checked) ? итоги.grid.checked : []
  let номер = 0
  for (const запись of итоги?.obligations?.obligations ?? []) {
    if (запись.kind !== "postcondition") continue
    const найдено = поиск[номер]
    номер += 1
    yield утверждение(запись, найдено?.id === запись.id ? найдено : null)
  }

  /* Старая форма теоремы. Она разбирается с самого начала и не читается никем:
     узел уезжает в `legacy`, и следствий из него не выводит ни типизатор, ни
     печать. Промолчать о ней нельзя — молчание читается как «нормально», а
     теорема, о которой ведомость молчит, выглядит доказанной. */
  for (const узел of program?.legacy ?? []) {
    if (узел?.construct !== "theorem") continue
    const имя = узел?.value?.title ?? null
    yield {
      kind: "теорема наследия",
      name: имя,
      of: null,
      verdict: "declared",
      grid: 0,
      steps: 0,
      says:
        "объявлено, не доказано: старая форма теоремы (наследие FTS) разбирается,"
        + " но следствий из неё не выводит никто — доказательства при ней нет вовсе",
    }
  }
}

function утверждение(запись, найдено = null) {
  const общее = {
    kind: ВИД_ПОСТУСЛОВИЯ,
    name: запись.name ?? null,
    of: запись.of ?? null,
    forall: запись.forall?.name ?? null,
  }
  const сброс = запись.discharge

  /* НАРУШЕНИЕ БЬЁТ ЛЮБОЙ ВЕРДИКТ, И ЭТО НЕ ГРУБОСТЬ ОТЧЁТА. Прогон нашёл вход
     автора, на котором утверждение ложно. Если ядро при этом сказало
     «доказано» — расходятся не два мнения, а доказательство и факт, и молчать
     об этом нельзя ни секунды: ведомость для того и заведена, чтобы разница
     между доказанным и посчитанным была видна, а «доказано» при найденном
     контрпримере — это ошибка ЯДРА, самая дорогая из возможных. */
  const нарушения = найдено?.violations ?? []
  /* Одно исключение, и оно не смягчение: у ОТВЕРГНУТОГО ядром утверждения
     контрпример ничего не переворачивает — оба факта смотрят в одну сторону
     («верить нельзя»), а вердикт «отвергнуто» несёт сверх того причину, по
     которой программа не проходит `flang check`. Поэтому там контрпример
     ДОБАВЛЯЕТСЯ к строке, а не заменяет её. Заменяет он только те вердикты,
     которые говорят о хорошем: «доказано» и «сетка». */
  if (нарушения.length > 0 && вердиктЯдра(сброс) !== "отвергнуто") {
    const первое = нарушения[0]
    const судил = вердиктЯдра(сброс)
    return {
      ...общее,
      verdict: "violated",
      grid: запись.grid ?? 0,
      searched: найдено.searched ?? 0,
      violations: нарушения,
      steps: сброс?.steps ?? 0,
      says:
        `НАРУШЕНО на примере «${первое.example}»: ${первое.why}`
        + `${нарушения.length > 1 ? ` (и ещё ${нарушения.length - 1})` : ""}`
        + (судил === "доказано"
          ? " — а ядро сказало «доказано»: РАСХОЖДЕНИЕ доказательства с фактом, и верить надо факту"
          : " — утверждение ложно на входе, который автор написал сам"),
    }
  }

  /* ПЯТОЕ СЛОВО ВЕДОМОСТИ. Утверждение, доказанное индукцией, — не оттенок
     «доказано», а другое утверждение о том, ЧЕМ оно доказано, и путать их нельзя
     ровно по той же причине, по которой нельзя путать «доказано» и «сетка».
     «Доказано ядром» без индукции говорит: цель свелась к названным фактам
     цепочкой шагов. «Доказано индукцией по «Т»» говорит строго больше: принцип
     прочитан с объявления суммы «Т», случаи сошлись с конструкторами ТОЧНО,
     база закрыта вычислением, а шаг выведен ПРИ ДОПУЩЕНИИ на частях значения.
     Второе покрывает бесконечный носитель, первое — нет, и читатель ведомости
     обязан видеть разницу, не заглядывая в файл.

     Отличать его надо и от «доказано структурой» из соседнего раздела: там речь
     о ЗАВЕРШЕНИИ функции (обещание `тотальная`), здесь — об истинности
     УТВЕРЖДЕНИЯ о её результате. Слова разные потому, что вещи разные: функция
     может завершаться структурно и при этом не обещать ничего. */
  if (сброс !== null && сброс !== undefined && сброс.verdict === "доказано" && сброс.induction != null) {
    const и = сброс.induction
    return {
      ...общее,
      verdict: "proved-induction",
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      induction: {
        type: и.type ?? null,
        param: и.param ?? null,
        /* НОСИТЕЛЬ ПРИНЦИПА, и молчать о нём нельзя по той же причине, по какой
           нельзя молчать о разнице «доказано» и «сетка». Индукция по объявленной
           сумме держится на начальности: часть значения меньше значения, и
           цепочка частей конечного дерева обрывается сама. Индукция по отрезку
           `нат` держится на другом: отрезок [0, 2⁵³−1] КОНЕЧЕН, а спуск строг и
           дна не проскакивает. Утверждения одинаково сильные, но опираются на
           разное, и читатель ведомости обязан видеть, на что. */
        carrier: и.carrier ?? "algebra",
        base: и.base ?? 0,
        step: и.step ?? 0,
        rules: и.rules ?? [],
      },
      says:
        `доказано индукцией по «${и.type}»: база ${и.base} ${случаев(и.base)},`
        + (и.carrier === "segment"
          ? ` шаг при допущении на убывшем «${и.param}» (${и.step} ${случаев(и.step)})`
          : ` шаг при допущении на частях (${и.step} ${случаев(и.step)})`)
        + `${(и.rules ?? []).length === 0 ? "" : `, правила сведения: ${и.rules.join("; ")}`}`
        + (и.carrier === "segment"
          ? ` — утверждение обо ВСЕХ значениях отрезка «${и.type}» [0, ${и.segment?.верх ?? "2⁵³−1"}],`
            + " а не о написанных: отрезок конечен, спуск строг и дна не проскакивает"
          : ` — утверждение обо ВСЕХ входах типа «${и.type}», а не о написанных`),
    }
  }

  /* ДОКАЗАНО БЕЗ ТЕРМА — и ведомость обязана сказать именно это, а не «терм
     принят». Цель свелась к тому, что автор написал в подписи: `нат` — это
     отрезок [0, 2^53−1], то есть факт «не меньше 0», и ядро прочитало его там,
     где он написан. Слово то же самое, «доказано»: утверждение обо ВСЕХ входах и
     есть доказанное, чем бы оно ни было выведено. А вот ЧЕМ — разное, и молчать
     об этом нельзя: «терм принят» о доказательстве, которого автор не писал,
     было бы неправдой в ту же сторону, в какую неправдой было бы «доказано»
     вместо «сетки». */
  if (сброс !== null && сброс !== undefined && сброс.verdict === "доказано" && сброс.by === "declaration") {
    /* И ещё одно различие внутри этого же вердикта, и молчать о нём тоже нельзя.
       Цель могла свестись БЕЗ единого объявленного типа — восемью литералами
       под выбором, например, — и тогда «по объявленным типам аргументов» назвало
       бы источником факт, которым никто не пользовался. Понадобился он или нет,
       решает не эта строка, а ядро: `proofterm.mjs` спрашивает у `свести` тот же
       вопрос без объявлений и кладёт ответ в `byType`. */
    return {
      ...общее,
      verdict: "proved",
      by: "declaration",
      byType: сброс.byType === true,
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      says:
        (сброс.byType === true
          ? `доказано по объявленным типам аргументов: цель сведена правилом «${сброс.rule}»`
          : `доказано сведением цели с телом функции: правило «${сброс.rule}»,`
            + " объявленные типы аргументов не понадобились")
        + " — утверждение обо ВСЕХ входах, а не о написанных; теоремы при нём нет и не нужно",
    }
  }

  if (сброс !== null && сброс !== undefined && сброс.verdict === "доказано") {
    return {
      ...общее,
      verdict: "proved",
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      says:
        `доказано: терм принят ядром, ${сброс.steps ?? 0} ${шагов(сброс.steps ?? 0)}`
        + `${(сброс.cases?.length ?? 0) === 0 ? "" : ` в ${сброс.cases.length} ${случаях(сброс.cases.length)} индукции`}`
        + " — утверждение обо ВСЕХ входах",
    }
  }

  if (сброс !== null && сброс !== undefined && сброс.verdict === "сетка") {
    return {
      ...общее,
      verdict: "grid",
      grid: запись.grid ?? 0,
      steps: сброс.steps ?? 0,
      says:
        `сетка: терм принят ядром, но опирается на закон, посчитанный на конечной сетке`
        + " — это не доказательство",
    }
  }

  if (сброс !== null && сброс !== undefined && сброс.verdict === "отвергнуто") {
    /* Отвергнутый терм — это отказ программы, и до ведомости она не доходит
       (ведомость не печатается у программы с отказом). Строка всё равно есть:
       ведомость читают и по JSON от инструмента, который отказ показал отдельно. */
    return {
      ...общее,
      verdict: "refused",
      grid: запись.grid ?? 0,
      ...(нарушения.length === 0 ? {} : { violations: нарушения }),
      steps: сброс.steps ?? 0,
      says: `отвергнуто ядром: ${(сброс.refusals?.length ?? 0)} ${мест(сброс.refusals?.length ?? 0)} не сведено к названным фактам`
        /* И если прогон нашёл при этом контрпример — сказать о нём здесь же.
           «Не свелось» и «ложно на примере автора» — разные утверждения: первое
           про доказательство, второе про факт, и второе сильнее. */
        + `${нарушения.length === 0 ? "" : `; и прогон нашёл контрпример: пример «${нарушения[0].example}»`}`,
    }
  }

  /* Доказательства нет. Тогда всё, что есть, — сетка примеров: постусловие
     проверяется после КАЖДОГО возврата, значит каждый пример его и проверил.
     Предела у этой сетки нет — её пишет автор и ничто её не ограничивает, — и
     поэтому здесь не «предел P», а честное «примеров N».

     И ГЛАВНОЕ: «нарушений не найдено» говорится только тогда, когда их ИСКАЛИ.
     Первая редакция этой строки печатала эти слова о числе `примеры.length` —
     то есть считала примеры и объявляла их чистыми, не посмотрев ни на один.
     Ищет `grid.mjs` прогоном, тем же вычислителем, каким работает `flang test`;
     сюда приезжает ответ, и ответов три: нашли, не нашли, не искали. Третий
     сказан теми же словами — «не искали», — потому что честное «не смотрели»
     допустимо, а молчаливое «считаем, что всё хорошо» нет. */
  const примеров = запись.grid ?? 0
  if (примеров > 0) {
    const искали = найдено === null ? null : найдено.searched ?? 0
    const мимо = найдено?.unsearched ?? []
    return {
      ...общее,
      verdict: "grid",
      grid: примеров,
      searched: искали,
      ...(мимо.length === 0 ? {} : { unsearched: мимо }),
      steps: 0,
      says:
        `сетка ${примеров} ${значений(примеров)} (примеры функции): `
        + сказатьПроПоиск(примеров, искали, мимо)
        + " Это не доказательство — теоремы при утверждении нет",
    }
  }
  return {
    ...общее,
    verdict: "declared",
    grid: 0,
    steps: 0,
    says:
      "объявлено, не доказано: ни теоремы, ни примеров."
      /* Слова с корнем «провер» здесь стояло «утверждение ПРОВЕРЯЕТСЯ в
         рантайме» — и это была дыра в собственном запрете ведомости: запрет
         держался тестом, а тест смотрел только программы БЕЗ утверждений, и в
         разделе утверждений слово жило. Смысл строки не изменился ни на йоту,
         изменилось слово. */
      + " Его считает рантайм после каждого возврата — на тех входах, которые придут",
  }
}

const ВИД_ПОСТУСЛОВИЯ = "постусловие"

/** Вердикт ядра словом — или `null`, если ядро об этом утверждении не говорило. */
function вердиктЯдра(сброс) {
  return сброс === null || сброс === undefined ? null : сброс.verdict ?? null
}

/**
 * Три ответа поиска, и они разные.
 *
 * «Не найдено» говорится только про то число примеров, на котором прогон
 * ДОШЁЛ до вердикта. Всё остальное называется своими словами: «не искали» —
 * это честное сообщение о непроделанной работе, и оно строго лучше, чем
 * «не найдено» о том, на что не смотрели.
 */
function сказатьПроПоиск(примеров, искали, мимо) {
  if (искали === null) {
    return "нарушений НЕ ИСКАЛИ — прогона примеров не было, посчитано только их число."
  }
  if (искали === 0) {
    return `нарушений не искали ни на одном: ${первоеОтличие(мимо)}.`
  }
  if (мимо.length > 0) {
    return `нарушений не найдено на ${искали} из ${примеров};`
      + ` на остальных ${мимо.length} не искали: ${первоеОтличие(мимо)}.`
  }
  return `нарушений не найдено (искали прогоном на всех ${примеров}).`
}

/** Причина первого непройденного примера — с именем: по нему можно пойти и посмотреть. */
function первоеОтличие(мимо) {
  const первое = мимо[0]
  if (первое === undefined) return "причина не названа"
  return `«${первое.example}» — ${первое.why}`
}

