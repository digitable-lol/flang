/**
 * КЕШ ВЕРДИКТОВ ЯДРА по адресу содержимого — `~/.flang/cache`.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Доказательство стоит на порядки дороже теста, и до сих пор оно считалось
 * заново на каждом прогоне: кешировать его было не по чему. Появился адрес
 * определения (`flang/src/digest.mjs`) — появилось по чему.
 *
 * Нашёлся ключ — ядро не зовётся вовсе. Не нашёлся — зовётся, и вердикт
 * кладётся.
 *
 * ── ГЛАВНОЕ: КЕШУ НЕ ВЕРЯТ НА СЛОВО ─────────────────────────────────────────
 * Кеш, которому верят без проверки, — это аксиома с диском вместо бумаги.
 * Держится это тремя замками, и каждый закрывает свою дыру.
 *
 * ЗАМОК ПЕРВЫЙ — В КЛЮЧЕ СТОИТ САМО ЯДРО. Ключ есть ТРОЙКА: адрес определения,
 * адрес утверждения, адрес проверяющего. Третий считается от БАЙТОВ ядра
 * (`proofterm.mjs`, `obligations.mjs`, `flang/proof/`): правь ядро на один знак
 * — и все ключи станут другими, а вердикты, сделанные прежней его версией, не
 * всплывут никогда. Без этого замка кеш однажды сохранил бы доказательство,
 * сделанное сломанным ядром, и отдавал бы его годами.
 *
 * ЗАМОК ВТОРОЙ — ЗАПИСЬ САМОЗАВЕРЕНА И ОТКАЗ ЗАКРЫТЫЙ. В записи лежит ключ
 * ЦЕЛИКОМ и печать — хеш пары «ключ, вердикт». На чтении пересчитываются оба:
 * ключ обязан совпасть с запрошенным, печать — со своей. Разошлось хоть что-то,
 * не разобрался JSON, не тот номер схемы — это ПРОМАХ, то есть ядро зовётся,
 * а не «ну наверное можно верить». Сомнение стоит вызова ядра, и это дёшево:
 * промах — ровно та цена, что была до кеша.
 *
 * ЗАМОК ТРЕТИЙ — КЕШ НЕ РАСШИРЯЕТ ДОВЕРЕННОГО. `АКСИОМЫ` у ядра —
 * `Object.freeze([])`, и кеш не смеет объявить доказанным то, чего ядро не
 * доказывало: у него нет для этого слов. Принимается только вердикт, у которого
 * `kernel` равен нынешнему номеру ядра, а `verdict` — одно из трёх слов `СИЛА`.
 * Запись с четвёртым словом, с иным номером ядра или с непустым списком аксиом
 * отвергается. Кеш умеет ОТВЕТИТЬ то, что ядро уже говорило, и не умеет
 * СКАЗАТЬ ничего сверх этого.
 *
 * ── Чего эти замки НЕ держат, и это названо прямо ───────────────────────────
 * Печать — не подпись: у неё нет тайны. Тот, кто добрался до `~/.flang/cache` и
 * держит в руках этот файл, пересчитает и печать. Против такого противника
 * замок один и он не криптографический: каталог свой собственный, и `FLANG_CACHE=нет`
 * выключает кеш целиком, а `flang check --proof` без него считает ровно то же
 * самое. Печать держит ПОРЧУ И ПРАВКУ — то есть всё, что случается на самом
 * деле; от подделки с исходником в руках держит только отказ от кеша.
 *
 * ── ЗАМЕР, РАДИ КОТОРОГО ВСЁ И ЗАТЕВАЛОСЬ, И ОН НЕПРИЯТНЫЙ ──────────────────
 * Кеш заводился под довод «доказательство стоит на три порядка дороже теста».
 * Довод верен про ЦЕНУ ОДНОГО ШАГА и неверен про сегодняшний корпус. Замерено
 * на 48 файлах с постусловиями (`flang/proof/examples`, `flang/examples`,
 * `flang/stdlib`), одним процессом, чтобы старт node не смазывал числа:
 *
 *   разбор              90 мс
 *   обязательства        3 мс
 *   ЯДРО ДОКАЗАТЕЛЬСТВА 98 мс   ← всё, что кеш способен сэкономить
 *   адреса определений  62 мс   ← всё, что кеш обязан потратить
 *
 * А `flang check --proof` на тех же 48 файлах занимает 37 секунд, и уходят они
 * не в ядро: `check` без ключа — 0,74 с на файл, с ключом — 1,14 с, пустой node
 * — 0,04 с. То есть время съедают ввоз модулей (`types.mjs` — 465 КБ) и
 * ведомость на самом flang, а ядро — две миллисекунды на файл.
 *
 * Итог замера прямой: на горячем кеше пять файлов идут 4,73 с, на холодном
 * 4,71 с, а с `FLANG_CACHE=нет` — 4,42 с. КЕШ СЕГОДНЯ СТОИТ ДОРОЖЕ, ЧЕМ
 * ЭКОНОМИТ, примерно втрое. Он написан, проверен и верен, но выигрыш начнётся
 * не раньше, чем ядро подорожает — а подорожает оно, когда доказательства
 * перестанут быть в один-два шага. Число названо здесь, чтобы следующий, кто
 * возьмётся считать, начинал с него, а не с довода.
 *
 * ── Гранулярность, и почему пока такая ──────────────────────────────────────
 * Ключ — на КАЖДОЕ утверждение по отдельности, и это правильная гранулярность:
 * у функции бывает два постусловия, и вердикты у них разные. Но ядро зовётся
 * одним куском (`checkProofs` считает всю программу разом), поэтому промах хоть
 * одного утверждения зовёт ядро на всю программу. Складывается при этом всё
 * равно поштучно — и когда ядро научится считать одно утверждение, менять здесь
 * будет нечего.
 */
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { адресаОпределений, адресУтверждения, каноническийJSON, хеш } from "./digest.mjs"
import { АКСИОМЫ, СИЛА, ЯДРО, checkProofs } from "./proofterm.mjs"

/** Версия раскладки кеша. Меняется — прежние записи перестают находиться. */
export const СХЕМА_КЕША = 1

/**
 * Куда кладём. Кеш ВКЛЮЧАЕТСЯ переменной `FLANG_CACHE`, а не выключается ею:
 * по умолчанию его нет в рабочем пути вовсе (см. замер ниже и потолок в
 * `flang/test/rabochiy-put.test.mjs`).
 *
 *   `FLANG_CACHE=да`   — обычное место, `~/.flang/cache`;
 *   `FLANG_CACHE=<путь>` — своё место, чем и пользуются проверки;
 *   не задана или `нет`  — кеша нет, ядро зовётся всегда.
 */
export function корень() {
  const свой = process.env.FLANG_CACHE
  if (typeof свой !== "string" || свой === "" || свой === "нет" || свой === "0") return null
  if (свой === "да" || свой === "1") return join(homedir(), ".flang", "cache")
  return свой
}

/**
 * АДРЕС ПРОВЕРЯЮЩЕГО — хеш байтов ядра, а не номер версии.
 *
 * Номер пишет человек и забывает поднять; байты не забывают. Считается один раз
 * за прогон: файлов десяток, а `flang check` зовёт это на каждую программу.
 */
let адресЯдра = null
export function адресПроверяющего() {
  if (адресЯдра !== null) return адресЯдра
  const свой = dirname(fileURLToPath(import.meta.url))
  const части = []
  const собрать = (путь) => {
    let что = null
    try {
      что = statSync(путь)
    } catch {
      return
    }
    if (что.isDirectory()) {
      for (const имя of readdirSync(путь).sort()) собрать(join(путь, имя))
      return
    }
    if (!путь.endsWith(".mjs")) return
    части.push([путь.slice(путь.lastIndexOf("/") + 1), createHash("sha256").update(readFileSync(путь)).digest("hex")])
  }
  for (const путь of [
    join(свой, "proofterm.mjs"),
    join(свой, "obligations.mjs"),
    join(свой, "digest.mjs"),
    join(свой, "..", "proof"),
  ]) {
    собрать(путь)
  }
  адресЯдра = хеш({ "«ядро»": ЯДРО, "«схема»": СХЕМА_КЕША, "«байты»": части, "«аксиом»": АКСИОМЫ.length })
  return адресЯдра
}

const файлом = (где, ключ) => join(где, "sha256", ключ.slice(0, 2), `${ключ}.json`)

/** Ключ тройкой → одна строка, которой назван файл. */
function именем(тройка) {
  return хеш({ "«схема»": СХЕМА_КЕША, ...тройка })
}

/**
 * Взять вердикт. Любое сомнение — промах: `null` значит «зовите ядро».
 */
export function взять(где, тройка) {
  if (где === null) return null
  let запись = null
  try {
    запись = JSON.parse(readFileSync(файлом(где, именем(тройка)), "utf8"))
  } catch {
    return null
  }
  if (запись?.схема !== СХЕМА_КЕША) return null
  /* Ключ пересчитывается, а не читается: запись обязана сама сказать, о чём
     она, и сказанное обязано совпасть со спрошенным. */
  if (каноническийJSON(запись.ключ) !== каноническийJSON(тройка)) return null
  if (запись.печать !== хеш({ ключ: запись.ключ, вердикт: запись.вердикт })) return null
  const вердикт = запись.вердикт
  if (вердикт === null || typeof вердикт !== "object") return null
  /* Третий замок: у кеша нет слов сверх ядерных. */
  if (вердикт.kernel !== ЯДРО) return null
  if (!Object.values(СИЛА).includes(вердикт.verdict)) return null
  if (!Array.isArray(вердикт.refusals)) return null
  if (АКСИОМЫ.length !== 0) return null
  return вердикт
}

/** Положить вердикт. Неудача записи — не отказ: кеш ускоряет, а не решает. */
export function положить(где, тройка, вердикт) {
  if (где === null) return false
  const запись = {
    схема: СХЕМА_КЕША,
    ключ: тройка,
    вердикт,
    печать: хеш({ ключ: тройка, вердикт }),
  }
  const путь = файлом(где, именем(тройка))
  try {
    mkdirSync(dirname(путь), { recursive: true })
    writeFileSync(путь, `${JSON.stringify(запись)}\n`, "utf8")
    return true
  } catch {
    return false
  }
}

/**
 * Проверить доказательства программы, спросив сперва кеш.
 *
 * Отдаёт то же, что `checkProofs`, плюс поле `кеш` со счётом попаданий и
 * промахов — число, которым и меряется выигрыш.
 */
export function checkProofsCached(program, список, настройки = {}) {
  const где = корень()
  const адреса = адресаОпределений(program)
  const проверяющий = адресПроверяющего()
  const обязательства = (список ?? []).filter((о) => о?.kind === "postcondition")
  const тройки = обязательства.map((о) => ({
    определение: адреса.функции.get(о.of) ?? `имя:${о.of}`,
    утверждение: адресУтверждения(о, адреса.функции),
    проверяющий,
  }))
  /* Предусловия снимаются на ВСЮ программу разом, значит и ключ у них
     программный: адрес программы есть свод адресов её определений. */
  const тройкаПрограммы = {
    определение: хеш([...адреса.функции.values()].sort()),
    утверждение: "«предусловия и покрытие программы»",
    проверяющий,
  }
  const своды = обязательства.map((о, н) => взять(где, тройки[н]))
  const общее = взять(где, тройкаПрограммы)
  const промахов = своды.filter((в) => в === null).length + (общее === null ? 1 : 0)
  if (промахов === 0) {
    /* ЯДРО НЕ ЗВАЛОСЬ ВОВСЕ. Вердикты разложены обратно по обязательствам —
       ведомость печатается из них так же, как из свежих. */
    const checked = обязательства.map((о, н) => {
      о.discharge = своды[н]
      return { id: о.id, of: о.of, name: о.name, ...своды[н] }
    })
    /* Отказы снятия предусловий едут тем же порядком, каким их кладёт ядро:
       иначе горячий кеш промолчал бы о том, о чём холодный ругается. */
    const diagnostics = [...(общее.preconditions?.diagnostics ?? [])]
    for (const [н, о] of обязательства.entries()) {
      void о
      for (const беда of своды[н].refusals) {
        diagnostics.push({ code: беда.code, severity: "error", message: беда.message, span: беда.span })
      }
    }
    return { version: ЯДРО, checked, diagnostics, preconditions: общее.preconditions, кеш: { попаданий: обязательства.length + 1, промахов: 0 } }
  }
  const итог = checkProofs(program, список, настройки)
  for (const [н, о] of обязательства.entries()) {
    if (о.discharge !== null && о.discharge !== undefined) положить(где, тройки[н], о.discharge)
  }
  положить(где, тройкаПрограммы, {
    kernel: ЯДРО,
    verdict: СИЛА.proved,
    steps: 0,
    cases: [],
    refusals: [],
    preconditions: итог.preconditions,
  })
  return { ...итог, кеш: { попаданий: обязательства.length + 1 - промахов, промахов } }
}
