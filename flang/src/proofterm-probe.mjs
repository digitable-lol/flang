/**
 * Постусловия ВЫЗВАННЫХ функций, инстанцированные по месту вызова.
 *
 * ── Что это за ход и чем он отличается от седьмого ──────────────────────────
 * Седьмой ход — `по свойству` — делает то же самое, но ПО ССЫЛКЕ АВТОРА: автор
 * пишет `по свойству «имя»`, ядро находит постусловие с этим именем и
 * инстанцирует его по месту вызова. Восьмой ход — тот же самый факт БЕЗ ссылки:
 * там, где теоремы нет вовсе (`поОбъявленномуТипу`, `разборомПоСлучаям`),
 * называть правило некому, а факт на месте вызова тот же.
 *
 * Замер, ради которого ход заведён: из 94 незакрытых целей `flang/stdlib` у 44
 * после нормализации остаётся вызов, у 33 — вызов ЧУЖОЙ функции, и у 19 из этих
 * 33 у вызванного постусловие ЕСТЬ. Ядро его не читало ни на одном из них.
 *
 * ── ПОЧЕМУ ЭТО ФАКТ, А НЕ АКСИОМА, И ОПОРА НАЗВАНА ВСЛУХ ────────────────────
 * `обеспечивает` — не пожелание автора, а ПРОВЕРКА ПРИ КАЖДОМ ВОЗВРАТЕ. Она
 * стоит у вычислителя (`interpret.mjs`, `stepPost`: постусловие считается после
 * тела, и ложное валит вызов) и в напечатанном коде ВСЕХ ВОСЬМИ целей
 * (`emit/c.mjs` — `fl_post`, и по одному такому же месту у js, python, go,
 * rust, java, csharp, elixir; в C ради этой проверки отключается даже свёртка
 * хвостового вызова). Значит утверждение «вызов вернул значение ⇒ значение
 * удовлетворяет постусловию вызванного» — теорема о вычислении языка, а не
 * допущение: вход, на котором постусловие ложно, значения не даёт вовсе,
 * вызывающий его не увидит и до своего возврата не дойдёт.
 *
 * Это ровно тот же род факта, что `требует` у `по предположению`: не «автор
 * написал», а «кто-то за это заплатил». За `требует` платит вызывающий на
 * каждом месте вызова, за `обеспечивает` — вызываемый на каждом возврате.
 *
 * Сила вердикта поэтому НЕ ослабляется — в отличие от `по закону`, где закон
 * посчитан на конечной сетке и слабее доказательства. Здесь ослаблять нечего:
 * проверка при возврате не сетка, она стоит на каждом входе.
 *
 * ── ТРИ ОПАСНОСТИ, И КАЖДАЯ ЗАКРЫТА УСТРОЙСТВОМ, А НЕ ВНИМАНИЕМ ─────────────
 *
 *   КРУГ. Постусловие функции, применённое к доказательству её же
 *     постусловия, — это P из P. Прямой случай — рекурсивный вызов; случай
 *     через два шага — взаимная рекурсия («А» берёт у «Б», «Б» берёт у «А»), и
 *     он тот же круг, только не виден в одной функции; через три — тройка, и
 *     так далее. Закрыто НЕ проверкой, а ПОСТРОЕНИЕМ: фактом вправе стать
 *     только то постусловие, которое ядро УЖЕ ДОКАЗАЛО, — и доказало без него.
 *     Ход идёт неподвижной точкой: пока проходом закрывается хоть одно новое
 *     утверждение, делается следующий проход, и на каждом доступны факты только
 *     из закрытых РАНЬШЕ. Круга завестись негде: чтобы факт «А» стал доступен,
 *     «А» обязано быть закрыто, а закрыто оно было без «Б», которое сейчас на
 *     него опирается. Ни рекурсию, ни взаимную рекурсию отдельно ловить не
 *     надо — они не могут начаться: своё собственное постусловие в момент
 *     доказательства ещё не закрыто, значит его в списке доказанных нет.
 *     Индукцию это не отменяет: часть значения обосновывает `разборомПоСлучаям`
 *     допущением принципа, и рекурсивный вызов закрывается ИМ, а не этим ходом.
 *
 *     ЦЕНА НАЗВАНА: ход не берёт постусловие, которое АВТОР НАПИСАЛ, но ядро не
 *     доказало. «Сортировать» из `stdlib/lists.flang` закрылось бы шагом
 *     «Вставить по порядку», у которого «вставка удлиняет список ровно на один»
 *     написано и не доказано, — и не закрывается. Это сознательный размен:
 *     ненадёжное постусловие в библиотеке уже находили дважды («длина
 *     сохраняется при перевороте» ложна на одиноком суррогате), и ход, берущий
 *     ненадёжное, потащил бы ложь дальше молча. Седьмой ход (`по свойству`)
 *     недоказанное берёт — но там ЕСТЬ АВТОР, который на него сослался; здесь
 *     автора нет вовсе, и брать за него нельзя.
 *
 *   НЕОПЛАЧЕННОЕ ПРЕДУСЛОВИЕ. Постусловие вызываемого верно ТОЛЬКО при
 *     выполненном `требует`. Взять его на месте, где `требует` не снято, значит
 *     завести аксиому, которой не поймает ни один сторож пустоты `АКСИОМЫ`.
 *     Закрыто тем, что оплату решает не этот ход, а `снятьПредусловия`: она
 *     возвращает множество НЕСНЯТЫХ рёбер, и факт с такого ребра не берётся
 *     вовсе. Своего второго ответа на вопрос «оплачено ли» здесь нет ни одного.
 *
 *   НЕ ПО ИМЕНИ, А ПО РЕБРУ. Постусловие берётся у той функции, которая правда
 *     вызвана в этом узле: `среда.функции.get(вызов.name)` — то есть у
 *     объявления, к которому вызов разрешён в ЭТОЙ связанной программе, — и
 *     инстанцируется по ЕЁ параметрам. Поиска постусловия ПО ИМЕНИ
 *     УТВЕРЖДЕНИЯ здесь нет и быть не должно: `найтиПостусловие` обходит все
 *     функции модуля и на одноимённых постусловиях двух разных функций вернёт
 *     первую попавшуюся — то есть доказательство про чужое тело. Тот же довод
 *     записан у переноса теорем по ребру импорта (`src/link.mjs`).
 *
 * ── СПИСОК СЛУЧАЕВ, КОТОРЫЕ ХОД БЕРЁТ, — ЦЕЛИКОМ ────────────────────────────
 * Берётся факт, и только он, когда сошлись ВСЕ шесть:
 *   1. узел — `call` с именем (не `apply`, не `fnref`, не композиция: там
 *      вызванного по узлу не назвать, а гадать ядро не станет);
 *   2. имя разрешается в функцию ЭТОЙ программы;
 *   3. у неё есть хоть одно `обеспечивает`;
 *   4. это постусловие ядро УЖЕ ДОКАЗАЛО на одном из прошлых проходов
 *      неподвижной точки (закрывает круг построением);
 *   5. у вызванной не осталось НЕОПЛАЧЕННЫХ мест `требует` — по ответу
 *      `снятьПредусловия`, а не по своему;
 *   6. инстанция строится: число аргументов совпало с числом параметров и
 *      подстановка не захватила бы имени.
 * Всё, что под эти шесть не подошло, факта не даёт, и вердикта тогда нет —
 * ровно как было до этого хода.
 *
 * @returns {{claim: object, of: string, name: string}[]} факты, по одному на
 *   постусловие каждого годного вызова; порядок — обхода, а не случайный.
 */
function постусловияВызванных(заключение, обязательство, среда) {
  const факты = []
  собратьВызовы(заключение, (вызов) => {
    const вызванная = среда.функции?.get(вызов.name)
    if (вызванная === undefined || вызванная === null) return
    const постусловия = Array.isArray(вызванная.postconditions) ? вызванная.postconditions : []
    if (постусловия.length === 0) return
    /* НЕОПЛАЧЕННОЕ ПРЕДУСЛОВИЕ — ответом того, кто снимал, а не своим. Спрошено
       ПРО ВЫЗВАННОГО ЦЕЛИКОМ, а не про одно ребро: нормализация вправе принести
       сюда вызов из ЧУЖОГО тела (развёртка определения), и тогда ребра
       «доказываемая → вызванная» в исходнике не было вовсе, а неоплаченное
       место — было. Оценка сверху, как у множества отказов процесса. */
    if ((вызванная.preconditions ?? []).length > 0 && среда.неоплаченные instanceof Set
      && среда.неоплаченные.has(вызов.name)) return
    for (const постусловие of постусловия) {
      /* КРУГ — построением: берётся только УЖЕ ДОКАЗАННОЕ ядром. */
      if (!(среда.доказанные instanceof Set) || !среда.доказанные.has(ключФакта(вызов.name, постусловие.name))) continue
      const инстанция = инстанцияПостусловия({ of: вызов.name, fn: вызванная, постусловие }, вызов)
      if (инстанция === null) continue
      /* Один и тот же факт с двух одинаковых мест вызова — один факт: список
         допущений сличается знак в знак, и повтор в нём ничего не добавляет,
         кроме работы.

         СЛИЧАЮТСЯ ДЕРЕВЬЯ, А НЕ ПЕЧАТЬ. Здесь стоял ключ `какНаписан(инстанция)`,
         и это была НАСТОЯЩАЯ ОШИБКА, а не мелочь стиля: `какНаписан` печатает
         ТИП (`flang/src/as-written.mjs`), а инстанция — ВЫРАЖЕНИЕ, и на всяком
         выражении эта печать отвечала одной и той же строкой «тип без
         объявления». Значит ключ у всех фактов совпадал, и правило оставляло
         РОВНО ОДИН факт на всё заключение — первый по обходу. У функции, которая
         зовёт одну и ту же вызванную в двух ветвях с разными аргументами
         («Вставить по» в `docs/benchmark2`), второй факт пропадал молча, и
         доказательство не складывалось по причине, о которой отказ не говорил
         ни слова. Сличение деревьев (`одинаковы`) — то же самое, каким ядро
         сличает допущения с целью. */
      if (факты.some((был) => одинаковы(был.claim, инстанция))) continue
      факты.push({ claim: инстанция, of: вызов.name, name: постусловие.name })
    }
  })
  return факты
}

/**
 * Ключ доказанного постусловия — «чьё» и «какое», одной строкой.
 *
 * Разделитель — нулевой знак, и по той же причине, что у ребра вызова: имена
 * пишутся русскими словами, пробелы в них законны, и склейка через пробел дала
 * бы двум разным парам один ключ.
 */
const ключФакта = (кого, имя) => `${кого}\u0000${имя}`

/**
 * Свести цель, а не вышло — свести её ЖЕ при постусловиях вызванных.
 *
 * ПОРЯДОК ЗДЕСЬ — ИЗЪЯТИЕ, А НЕ ЭКОНОМИЯ. Сначала цель сводится БЕЗ единого
 * факта по вызову; факты подаются только тогда, когда без них не вышло. Значит
 * «закрыто постусловием вызванного» в ведомости означает ровно это, а не «ход
 * был позван». Ведомость, называющая способ по последнему позванному правилу, а
 * не по сработавшему, — это то самое слово, которое сильнее дела.
 *
 * @returns {{сведение: object, факты: object[]|null}} `факты` не `null` только
 *   тогда, когда без них цель не свелась, а с ними свелась.
 */
function свестиСВызовами(цель, допущения, объявления, обязательство, среда) {
  const без = свести(цель, допущения, объявления, среда.функции, среда.вычислить, ПРЕДЕЛ_ВЕТВЛЕНИЯ)
  if (без.ok) return { сведение: без, факты: null }
  const факты = постусловияВызванных(цель, обязательство, среда)
  if (process.env.PROBE2) console.error("ФАКТЫ ПО ВЫЗОВУ:", факты.length, факты.map((ф)=>JSON.stringify(ф.claim).slice(0,400)).join("\n   | "), "| доказанные:", [...(среда.доказанные??[])].join(" ; "))
  if (факты.length === 0) return { сведение: без, факты: null }
  const с = свести(
    цель,
    [...допущения, ...факты.map((факт) => ({ claim: факт.claim }))],
    объявления,
    среда.функции,
    среда.вычислить,
    ПРЕДЕЛ_ВЕТВЛЕНИЯ,
  )
  return с.ok ? { сведение: с, факты } : { сведение: без, факты: null }
}

/** Постусловия вызванных, названные поимённо, — для вердикта словами. */
const поВызовам = (факты) =>
  факты.map((факт) => `«${факт.name}» функции «${факт.of}»`).join(", ")

/**
 * Утверждение, выведенное из ОБЪЯВЛЕННЫХ ТИПОВ, — без теоремы и без термов.
 *
 * ── Зачем это отдельный путь, а не пятое правило шага ───────────────────────
 * Постусловие «результат не меньше 0» у функции `принимает первое: нат, второе:
 * нат`, чьё тело `первое плюс второе`, верно на всех входах и видно это из
 * ОДНОЙ строки подписи. Написать при нём теорему было бы не доказательством, а
 * пересказом: индукции не по чему (у `нат` нет объявленных вариантов, принцип
 * читать не с чего), а цепочка состояла бы из единственного шага «это следует
 * из объявления». Девятое слово поверхности ради такого шага пришлось бы
 * завести в таблице ключевых слов самоприменённого лексера — то есть увеличить
 * ровно тот долг, в который слой доказательства и упёрся (`proof/SPEC.md`).
 *
 * ── Почему это не «ядро начало искать» ──────────────────────────────────────
 * Поиска здесь ноль: одна подстановка (тело функции на место `результат` —
 * ровно та же, какой строится заключение посылки индукции) и один вызов
 * `свести`, который сам ничего не перебирает. Не свелось — вердикта НЕТ:
 * ни отказа, ни диагностики. Отказать здесь было бы неправдой — постусловие без
 * теоремы это не ошибка, а утверждение, посчитанное сеткой примеров, и ведомость
 * так о нём и скажет.
 *
 * ── Почему факт НАЗВАН, хотя автор не назвал его словом ─────────────────────
 * Правило «шаг без названного факта отвергается» не нарушено: факт назван
 * подписью. `принимает первое: нат` — это и есть написанное автором «первое не
 * меньше 0», и типизатор проверяет его на каждом вызове. Ядро читает написанное,
 * а не додумывает.
 *
 * @returns {object|null} вердикт или `null`, если из объявлений цель не выводится
 */
function поОбъявленномуТипу(обязательство, среда) {
  const функция = среда.функции.get(обязательство.of)
  const тело = функция?.body
  if (тело === null || тело === undefined) return null
  if (обязательство.goal === null || обязательство.goal === undefined) return null

  /* `результат` — это тело функции, и подстановка здесь та же самая, какой
     `initial.mjs` строит заключение посылки: постусловие считается после
     каждого возврата, значит утверждение о `результат` и есть утверждение о
     теле. Второй подстановки (переменной на конструктор) тут нет — нет и
     разбора: доказывается сразу вся функция. */
  const цель = подставить(обязательство.goal, { [обязательство.bind ?? "результат"]: тело })
  /* Подстановка отказалась: она захватила бы чужое имя (`initial.mjs`,
     `захватывает`). Вердикта тогда НЕТ — ровно как когда цель не свелась: это
     не ошибка автора, а место, где ядро не умеет, и молчание здесь честнее
     отказа. Проверять `null` обязательно и явно: `свести` от `null` тоже не
     проходит, но опираться на это значило бы держать состоятельность на том,
     как чужая функция ведёт себя на входе, которого не ждала. */
  if (цель === null) return null
  /* Определения модуля приезжают сюда ДАННЫМИ, наравне с объявлениями: ядро не
     ходит за телом чужой функции само, ему его дают, и разворачивает оно только
     то, что названо в `reduce.mjs` двумя правилами с названным пределом. */
  /* ПРЕДУСЛОВИЯ САМОЙ ФУНКЦИИ — допущения этого места, и они не новые: внутри
     тела `требует` ИСТИННО, потому что его снял КАЖДЫЙ вызывающий
     (`снятьПредусловия` выше). Соседние пути их уже читают (`поПредположению`,
     `поСвойству`); путь без теоремы не читал, и это была не граница, а пропуск:
     тот же факт, тот же источник, а ответ разный. */
  const свои = (обязательство.assumptions ?? []).map((выражение) => ({ claim: выражение }))
  const { сведение, факты } = свестиСВызовами(цель, свои, обязательство.vars, обязательство, среда)
  if (!сведение.ok) return null
  /* Факты по вызову едут и в ИЗЪЯТИЕ ниже: изъятие спрашивает, понадобился ли
     ОБЪЯВЛЕННЫЙ ТИП, и подать туда меньше фактов значило бы измерить не то. */
  const поВызову = (факты ?? []).map((факт) => ({ claim: факт.claim }))

  /* ПОНАДОБИЛСЯ ЛИ ОБЪЯВЛЕННЫЙ ТИП — вопрос отдельный, и ответ на него ведомость
     обязана давать правдой, а не по месту в коде.
     Утверждение «результат не меньше 0» у функции над `строка`, чьё тело —
     восемь ветвей выбора с литералами, сводится ЦЕЛИКОМ БЕЗ ЕДИНОГО ОБЪЯВЛЕНИЯ:
     работают литерал и выбор, а типов аргументов правило не касается вовсе.
     Сказать о таком «доказано по объявленным типам аргументов» значило бы
     назвать источником факт, которым никто не пользовался, — та же неправда в
     ту же сторону, что «доказано» вместо «сетки», только мельче.
     Проверяется ИЗЪЯТИЕМ, а не догадкой: тот же вызов без объявлений. Свелось и
     без них — значит объявленный тип не понадобился. Второй вызов `свести`
     ничего не перебирает, как и первый, и стоит ровно столько же.
     ЦЕЛЬ, ЗАКРЫТУЮ ВЫЧИСЛЕНИЕМ, ИЗЫМАТЬ НЕ НАДО, и это не экономия: вычисление
     не смотрит в объявления ВОВСЕ — у замкнутой цели имён нет, значит и типов
     этих имён нет, — поэтому ответ изъятия известен заранее, а второй прогон
     стоил бы ровно столько же, сколько первый, то есть вдвое дороже правила. */
  const безОбъявлений = сведение.rule === ВЫЧИСЛЕНИЕМ
    ? { ok: true }
    : свести(цель, [...свои, ...поВызову], [], среда.функции, null, ПРЕДЕЛ_ВЕТВЛЕНИЯ)

  return {
    kernel: ЯДРО,
    verdict: СИЛА.proved,
    /* Чем закрыто — полем, а не разбором строки: ведомость обязана назвать это
       СВОИМИ словами, и «терм принят» здесь было бы неправдой, потому что терма
       нет вовсе. */
    by: "declaration",
    /* А это — уточнение к нему: понадобился ли для сведения объявленный тип.
       Оба числа стоят в своде порознь, потому что отвечают на разные вопросы:
       сколько доказано без теоремы и сколько из них — фактом из подписи. */
    byType: !безОбъявлений.ok,
    rule: сведение.rule,
    /* Шагов ноль, и это честно: шаги считаются в ТЕРМАХ, а терма здесь нет.
       Приписать сюда единицу значило бы завысить «шагов в принятых термах» в
       своде на утверждения, у которых терма никто не писал. */
    steps: 0,
    cases: [],
    refusals: [],
    /* ЧЕМ ЗАКРЫТО НА САМОМ ДЕЛЕ — полем, а не только словами: ведомость читает
       данные. Поле стоит ТОЛЬКО когда факт по вызову понадобился, и понадобился
       он проверяется изъятием (`свестиСВызовами`), а не тем, что ход был позван. */
    ...((факты ?? []).length === 0 ? {} : { calls: факты.map((ф) => ({ of: ф.of, name: ф.name })) }),
    says:
      /* И третья формулировка того же вердикта, потому что закрыто оно ТРЕТЬИМ
         способом. Сказать «сведением цели с телом функции: правило „вычисление“»
         значило бы назвать вычисление правилом вывода, а оно им не является:
         правило выводит при живых именах, вычисление отвечает там, где имён не
         осталось. Разные ходы — разные слова, иначе читатель ведомости не
         отличит выведенное от посчитанного. */
      ((факты ?? []).length > 0
        ? `доказано по постусловию вызванного (${поВызовам(факты)}): правило «${сведение.rule}»`
          + " — постусловие проверяется у вызванного при КАЖДОМ возврате, поэтому на месте вызова"
          + " это факт, а не допущение"
        : сведение.rule === ВЫЧИСЛЕНИЕМ
        ? "доказано вычислением замкнутой цели: свободных имён в ней не осталось,"
          + " значит значение у неё одно, и вычисление отвечает про него целиком"
        : безОбъявлений.ok
          ? `доказано сведением цели с телом функции: правило «${сведение.rule}»,`
            + " объявленные типы аргументов не понадобились"
          : `доказано по объявленным типам аргументов: правило «${сведение.rule}»`)
      + " — утверждение обо ВСЕХ входах, теоремы при нём нет и не нужно",
  }
}

/**
 * Индукция по `разбор`у — БЕЗ теоремы, на том же пути, где снимается постусловие.
 *
 * ── Зачем она здесь, а не в теореме ─────────────────────────────────────────
 * Принцип индукции у ядра есть и доказан (`проверитьИндукцию` ниже), но звали
 * его только из НАПИСАННОЙ РУКОЙ теоремы. Написать теорему можно не везде:
 * восемь слов слоя доказательств не имеют продукции в `flang/self/parser.flang`,
 * и теорема в `flang/stdlib` роняет побайтовую сверку самоприменения. Мест, где
 * утверждение верно, доказательство есть, а вписать его некуда, оказалось
 * измеримое число. Это правило закрывает их — БЕЗ единого нового слова в языке.
 *
 * ── Почему это доказательство, а не допущение ───────────────────────────────
 * Принцип порождается ТЕМ ЖЕ `принципИндукции`, что и у теоремы: посылка на
 * каждый конструктор объявленной суммы (или встроенного списка), заключение —
 * ветвь `разбор` этого конструктора, допущение — ТА ЖЕ цель на части значения.
 * Разница с путём теоремы ровно одна и названа: там ядро закрывает посылку БЕЗ
 * допущений (посылка, закрытая допущением, — это шаг, и его обязан назвать
 * автор словом `по предположению`), здесь автора нет вовсе, поэтому ядро само
 * ведёт обе половины — и обязано свести ОБЕ, иначе вердикта нет.
 *
 * ── Пять условий, и ни одно не лишнее ───────────────────────────────────────
 *   НОСИТЕЛЬ   разбираемое имя объявлено суммой или встроенным списком. По
 *              `число` и `целое` принципа нет, и брать его неоткуда.
 *   ВЕРХНИЙ    `разбор` стоит на верхнем уровне тела (`ветвиРазбора`). Разбор
 *   УРОВЕНЬ    под условием отвечает не за все значения.
 *   ПОКРЫТИЕ   у КАЖДОЙ посылки принципа есть ветвь и заключение. Пропущенный
 *              конструктор значит, что о части значений не сказано ничего.
 *   БАЗА ЕСТЬ  посылок без допущений хотя бы одна. Индукция, у которой все
 *              посылки шаговые, не сказала бы ни о одном КОНЕЧНОМ значении:
 *              это круг, а не вывод, и молчаливо принять его нельзя.
 *   ВСЕ СВЕЛИСЬ одна несведённая посылка рвёт вывод целиком. Частичного успеха
 *              у принципа нет: заключать можно, только когда сошлись обе части.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 * Ни одного допущения СВЕРХ построенных: допущение строится `принципИндукции`
 * по полям-местам варианта, то есть по значению, УМЕНЬШИВШЕМУСЯ по построению.
 * Шаг, зовущий себя не на части (на другом параметре, на построенном заново
 * значении, с другими прочими аргументами), допущению не сличится — сличение
 * синтаксическое, — и вердикта не будет. Это не осторожность: допущение о
 * значении, которое не убыло, и есть та самая аксиома под другим именем.
 *
 * Поиска здесь по-прежнему ноль: одно `свести` на посылку, ничего не
 * перебирающее, и посылок столько, сколько у типа конструкторов.
 *
 * @returns {object|null} вердикт или `null`, если индукция не сложилась
 */
function разборомПоСлучаям(обязательство, среда) {
  const функция = среда.функции.get(обязательство.of)
  if (функция === undefined || функция === null) return null
  if (обязательство.goal === null || обязательство.goal === undefined) return null

  /* НОСИТЕЛЬ и ВЕРХНИЙ УРОВЕНЬ читаются здесь и оба — чтением, а не догадкой:
     по какому имени идёт разбор, написано в теле, а чем это имя объявлено —
     в подписи. Нормализация разворачивает `пусть` перед разбором и ничего не
     вычисляет, поэтому разбор остаётся тем же разбором. */
  const тело = нормализовать(функция.body ?? null)
  if (тело?.kind !== "match") { if (process.env.PROBE) console.error("НЕ РАЗБОР:", обязательство.of, обязательство.name, тело?.kind); return null }
  if (тело.target?.kind !== "var") return null
  const параметр = тело.target.name
  const переменная = (обязательство.vars ?? []).find((п) => п.name === параметр)
  if (переменная === undefined) return null
  const тип = переменная.type ?? null
  const имяТипа = имяИменованного(тип)
  const сумма = имяТипа !== null
    ? среда.суммы.get(имяТипа)
    : (тип?.kind === "list" ? объявлениеСписка(тип) : undefined)
  /* Отрезка `нат` здесь нет НАРОЧНО: по нему принцип держится на строгом спуске
     меры, а меру называет автор словом `убывает`. Тело, написанное `разбор`,
     о спуске не говорит ничего, и брать отрезок значило бы взять принцип,
     которого не с чего прочитать. */
  if (сумма === undefined) return null

  const принцип = принципИндукции({
    сумма,
    функция,
    обязательство,
    /* Случаев автора нет ни одного — теоремы нет вовсе. Порождение читает тогда
       имена частей с образцов САМОГО ТЕЛА (`связиВетви`), и это единственный
       источник имён, какой здесь есть. */
    индукция: { param: параметр, cases: [], span: обязательство.span ?? null },
  })
  if (принцип.unread !== null && принцип.unread !== undefined) return null
  if (принцип.matched !== true) return null
  if ((принцип.unmatched ?? []).length > 0) return null
  const посылки = принцип.premises ?? []
  if (посылки.length === 0) return null

  const база = []
  const шаг = []
  const cases = []
  const поВызову = []
  for (const посылка of посылки) {
    /* ПОКРЫТИЕ: ветвь на конструктор есть, и подстановка не отказалась. Нет —
       вердикта нет вовсе: доказывали бы утверждение о `результат`, не зная,
       что такое `результат` в этом случае. */
    if (посылка.conclusion === null || посылка.conclusion === undefined) return null
    const допущения = [
      ...(посылка.facts ?? []),
      /* Допущения индукции — ровно те, что построил принцип, и ни одним больше.
         У базы их ноль (полей-мест у варианта нет), и это не проверка, а
         следствие построения: список пуст сам. */
      ...(посылка.hypotheses ?? []).map((г) => г.claim),
    ]
    const { сведение, факты } = свестиСВызовами(
      посылка.conclusion,
      допущения,
      посылка.declarations,
      обязательство,
      среда,
    )
    /* ВСЕ СВЕЛИСЬ: одна несведённая рвёт вывод целиком. Ослабить вердикт до
       сетки нельзя — сетка говорит «прогнали по значениям», а здесь не прогоняли
       ничего. */
    if (!сведение.ok) { if (process.env.PROBE) console.error("ПОСЫЛКА", посылка.label ?? посылка.variant, "\n  ЦЕЛЬ:", JSON.stringify(посылка.conclusion), "\n  ДОПУЩЕНИЯ:", JSON.stringify(допущения), "\n  ОТКАЗ:", сведение.why); return null }
    for (const факт of факты ?? []) {
      /* Постусловия вызванных, понадобившиеся хоть одной посылке, собираются на
         весь вывод: ведомость называет ИСТОЧНИК факта, а он один и тот же во
         всех случаях, где вызван тот же вызванный. */
      if (!поВызову.some((был) => был.of === факт.of && был.name === факт.name)) {
        поВызову.push({ of: факт.of, name: факт.name })
      }
    }
    cases.push({
      variant: посылка.variant,
      label: посылка.label ?? посылка.variant,
      kind: посылка.kind,
      parts: посылка.parts,
      verdict: СИЛА.proved,
      by: "reduction",
      steps: 0,
      rule: сведение.rule,
    })
    ;(посылка.kind === "base" ? база : шаг).push(СИЛА.proved)
  }

  /* БАЗА ЕСТЬ. Проверяется отдельно от свёртки принципа, потому что свёртка
     считает пустой базу законной (у теоремы её вправе закрыть автор), а здесь
     закрывать некому: все посылки шаговые значило бы вывод, опирающийся только
     на самого себя. */
  if (база.length === 0) return null
  if (свернутьПринцип({ покрытие: true, база, шаг }) !== СИЛА.proved) return null

  return {
    kernel: ЯДРО,
    verdict: СИЛА.proved,
    /* Чем закрыто. Слово своё, а не `declaration`: там цель свелась с телом
       ЦЕЛИКОМ и допущений не было ни одного, здесь тело разобрано по случаям и
       у шаговых посылок допущение есть. Свести их в одно слово значило бы
       сказать «без индукции» о выводе, который весь на ней и держится. */
    by: "cases",
    byType: false,
    rule: cases[0].rule,
    /* Шагов ноль: шаги считаются в ТЕРМАХ, а терма здесь никто не писал. */
    steps: 0,
    cases,
    refusals: [],
    /* Свод индукции — той же формы, какой его отдаёт путь теоремы: ведомость
       читает одно поле и не различает, откуда индукция пришла. */
    induction: {
      type: принцип.type,
      param: принцип.param,
      carrier: принцип.carrier,
      base: база.length,
      step: шаг.length,
      functor: сигнатураФунктора(сумма),
      rules: [...new Set(cases.map((с) => с.rule).filter((п) => п !== undefined))],
    },
    ...(поВызову.length === 0 ? {} : { calls: поВызову }),
    says:
      `доказано индукцией по «${принцип.type}»: база ${база.length},`
      + ` шаг при допущении на частях (${шаг.length})`
      + (поВызову.length === 0
        ? ""
        : `, и при постусловии вызванного (${поВызовам(поВызову)})`)
      + " — теоремы при нём нет и не нужно",
  }
}
function проверитьТерм(обязательство, среда, настройки) {
  const теорема = обязательство.proof
  const refusals = []
  /* Сила начинается доказанной и может только ослабнуть: закон на сетке
     ослабляет её до сетки, невыведенный шаг — до отказа. Обратного хода нет, и
     это правило одно на весь вердикт. */
  let сила = СИЛА.proved
  const ослабить = (до) => {
    if (сила === СИЛА.refused) return
    if (до === СИЛА.refused) сила = СИЛА.refused
    else if (до === СИЛА.grid && сила === СИЛА.proved) сила = СИЛА.grid
  }

  let шагов = 0
  const cases = []
  let индукцией = null

  if (теорема.induction === undefined || теорема.induction === null) {
    /* Доказательство без индукции — цепочка шагов при цели. Годится там, где
       утверждение закрыто само (у функции без параметров) или выводится
       ссылкой; ни одного случая при этом нет, и разбирать нечего. */
    const итог = проверитьЦепочку(теорема.steps ?? [], {
      обязательство,
      среда,
      настройки,
      /* Посылки нет — значит нет ни допущений, ни заключения случая. Правила,
         которым посылка нужна (`по предположению`), скажут об этом словами, а не
         упрутся в пустоту: доказательство без индукции их и не должно звать. */
      посылка: null,
      место: `теорема «${теорема.name}»`,
    })
    шагов += итог.шагов
    refusals.push(...итог.refusals)
    ослабить(итог.сила)
  } else {
    const итог = проверитьИндукцию(теорема.induction, { обязательство, среда, настройки })
    refusals.push(...итог.refusals)
    ослабить(итог.сила)
    шагов += итог.шагов
    cases.push(...итог.cases)
    индукцией = итог.induction
  }

  if (теорема.qed !== true) {
    /* Обязательства это уже сказали диагностикой; ядро не повторяет её, но и
       доказанным незакрытое доказательство назвать не может. */
    ослабить(СИЛА.refused)
  }

  /* Индукция называется в вердикте отдельным полем, а не только словами: слово
     читает человек, а поле — ведомость, и пятое слово ведомости обязано браться
     из данных, а не из разбора строки. Поле стоит только там, где индукция
     ДОШЛА до свёртки принципа: у отвергнутого терма её нет, иначе ведомость
     сказала бы «доказано индукцией» о том, что не доказано. */
  const induction = сила === СИЛА.refused ? null : индукцией

  return {
    kernel: ЯДРО,
    verdict: сила,
    steps: шагов,
    cases,
    refusals,
    ...(induction === null ? {} : { induction }),
    says: словами(сила, шагов, cases.length, refusals.length, induction),
  }
}

/**
 * Свёртка ПРИНЦИПА — одно правило, и оно то же, что у всей остальной цепочки.
 *
 * Это то место, ради которого принцип порождается ТЕРМОМ, а не пишется правилом
 * на JavaScript: здесь он сворачивается, и свёртка читается целиком за один
 * взгляд. Эталон на flang («Вердикт индукции» в `flang/proof/kernel.flang`)
 * делает ровно это же, и вердикты сверяются перебором.
 *
 * Три условия, и ни одно не лишнее:
 *   ПОКРЫТИЕ  случаи сошлись с объявлением суммы ТОЧНО. Нет — принцип не тот,
 *             который читается с объявления, и сворачивать нечего.
 *   НЕПУСТОТА индукция без единой посылки не сказала ни о одном значении типа.
 *   СЛАБЕЙШЕЕ каждая посылка держит вывод целиком: одна невыведенная рвёт всё.
 *
 * База и шаг сворачиваются ОДИНАКОВО и порознь. Порознь — потому что ведомость
 * обязана назвать их числом раздельно; одинаково — потому что это одна и та же
 * посылка функтора, у которой мест `X` ноль или больше нуля, и разное правило
 * для них означало бы, что перечисление доказывается не тем же принципом, что
 * дерево.
 */
export function свернутьПринцип({ покрытие, база, шаг }) {
  if (покрытие !== true) return СИЛА.refused
  const все = [...(база ?? []), ...(шаг ?? [])]
  if (все.length === 0) return СИЛА.refused
  let итог = СИЛА.proved
  for (const сила of все) {
    if (сила === СИЛА.refused) return СИЛА.refused
    if (сила === СИЛА.grid) итог = СИЛА.grid
  }
  return итог
}

/**
 * Индукция: случаи обязаны ТОЧНО покрыть конструкторы объявленной суммы.
 *
 * Это и есть начальность, прочитанная с объявления, и проверяется она здесь
 * одним сличением множеств — без всякого вывода. Пропущенный конструктор значит,
 * что о части значений не сказано ничего; лишний — что сказано о значении,
 * которого у типа не бывает. Ни то, ни другое не индукция.
 *
 * ПОЧЕМУ ИМЕННО ТОЧНОЕ РАВЕНСТВО, А НЕ «ПОКРЫТИЕ». Исчерпывающность `разбор`
 * считает типизатор, и считает он её по тем же образцам. Разреши здесь лишний
 * случай — и два слоя стали бы отвечать на один вопрос по-разному.
 */
function проверитьИндукцию(индукция, { обязательство, среда, настройки }) {
  const refusals = []
  const cases = []
  let шагов = 0

  const переменная = обязательство.vars.find((п) => п.name === индукция.param)
  const тип = переменная === undefined ? null : (переменная.type ?? null)
  const имяТипа = имяИменованного(тип)

  /* ТРИ ИСТОЧНИКА ПРИНЦИПА, И ВСЕ ТРИ — ЧТЕНИЕ, А НЕ АКСИОМА.
     Объявленная сумма читается из программы: автор написал `тип … вариант …`.
     Встроенный список объявления в программе не имеет, но имеет его в самом
     языке: два образца исчерпывают его разбор, типы головы и хвоста называет
     типизатор, а хвост считает частью значения анализ завершаемости
     (`объявлениеСписка`). Отрезок `нат` читается из ДВУХ ГРАНИЦ типа
     (`отрезокНата`), и принцип по нему порождается той же формой.
     Дальше ядро не различает, откуда принцип пришёл: свёртка у всех трёх общая,
     и ветки «а если по числу» ниже нет ни одной. */
  const сумма = имяТипа !== null
    ? среда.суммы.get(имяТипа)
    : (тип?.kind === "list" ? объявлениеСписка(тип) : undefined)
  const отрезок = сумма === undefined && отрезокНата(имяТипа)

  if (сумма === undefined && !отрезок) {
    refusals.push({
      code: КОДЫ.type,
      message:
        `индукция теоремы «${обязательство.name}» идёт по «${индукция.param}»,`
        + ` а у этого типа (${какНаписан(тип)}) принципа индукции нет.`
        + " Принцип читается из трёх мест и ниоткуда больше: у объявленной суммы — из её вариантов,"
        + " у встроенного списка — из двух образцов, которыми язык исчерпывает его разбор,"
        + " у объявленного `нат` — из двух границ отрезка."
        + " По «число» и «целое» его брать НЕЛЬЗЯ, и это не осторожность:"
        + " у «число» в носителе живёт «+∞», у которого «х минус 1» равно самому «х»,"
        + " и спуска не происходит вовсе; а вне [0, 2⁵³−1] ложно и само «х минус 1 меньше х»"
        + " (при х = 2⁵³+4 округление к ближайшему возвращает то же х)",
      span: индукция.span,
    })
    return { сила: СИЛА.refused, refusals, cases, шагов, induction: null }
  }

  /* ПРИНЦИП ПОРОЖДАЕТСЯ, А НЕ ВПИСАН. Всё, что ядро знает об индукции по этому
     типу, приходит одним объектом из `flang/proof/initial.mjs` — по объявлению
     суммы (или по двум границам отрезка) и телу функции. Здесь принцип только
     СВОРАЧИВАЕТСЯ; правил индукции для списка, для дерева и для перечисления по
     отдельности здесь нет ни одного, и это проверяемое свойство: работает всё,
     что объявлено `тип … вариант …`, и ровно потому, что порождение не
     различает эти случаи.

     Порождений два, а свёртка одна, и это тоже решение: принципы приезжают сюда
     ОДНОЙ формой (посылки с заключением, допущениями, фактами и свободными
     именами), поэтому ниже нет ни одной ветки «а если по числу». Заведись такая
     ветка — и «доказано индукцией» означало бы у двух принципов разное. */
  const функция = среда.функции.get(обязательство.of)
  /* ТРЕТЬЕ ПОРОЖДЕНИЕ, и выбирается оно ЧТЕНИЕМ ТЕЛА, а не догадкой: тело,
     написанное `свёртка <переменная индукции> …`, читается принципом по свёртке
     (`initial.mjs`, `принципПоСвёртке`), потому что ветвей `разбор` у него нет
     ни одной и заключение посылки строить было бы не из чего. Порождений стало
     три, а свёртка принципа по-прежнему ОДНА: все три приезжают сюда одной
     формой, и ветки «а если по свёртке» ниже нет ни одной. */
  const свёртка = сумма === undefined ? null : свёрткаПоПеременной(функция, индукция.param)
  const принцип = отрезок
    ? принципПоЧислу({ тип: имяТипа, функция, обязательство, индукция })
    : свёртка !== null
      ? принципПоСвёртке({ свёртка, функция, обязательство, индукция })
      : принципИндукции({ сумма, функция, обязательство, индукция })

  /* Прочитать принцип могло и не выйти: у отрезка читаются мера, условие дна и
     спуск, и любое из трёх автор вправе написать так, что читать станет нечего.
     Порождение об этом ГОВОРИТ (`unread`), а отказывает ядро — и отказывает
     кодом, а не общим словом. */
  if (принцип.unread !== null && принцип.unread !== undefined) {
    refusals.push({
      code: КОД_НЕПРОЧИТАННОГО[принцип.unread.code] ?? КОДЫ.induction,
      message: `индукция теоремы «${обязательство.name}» по отрезку «${имяТипа}»: ${принцип.unread.why}`,
      span: индукция.span,
    })
    return { сила: СИЛА.refused, refusals, cases, шагов, induction: null }
  }

  /* ПОКРЫТИЕ, и здесь оно перестало означать «автор написал случай на каждую
     посылку». Означает оно теперь ровно то, чем было с самого начала: о КАЖДОЙ
     посылке принципа что-то сказано. Сказать может и автор — словом `случай`, —
     и ЯДРО: посылка, заключение которой `свести` закрывает само, закрыта и без
     обоснования шага. Это ровно тот же путь, каким закрывается постусловие без
     теоремы (`поОбъявленномуТипу` выше), и поиска в нём столько же — ноль: одно
     `свести` на посылку, ничего не перебирающее.

     Зачем это вообще понадобилось, стоит сказать прямо: базу вида `0 не меньше
     0` закрыть было НЕЧЕМ. `по предположению` там отвергается по делу (частей
     нет, предполагать не о чем), а `по примеру` требует примера, которого у
     функции может не быть ни одного — так и стояло у «Глубины» из leetcode 104,
     и ради строчки доказательства в файл дописывался пример, которого в корпусе
     нет. Дописанный ради доказательства пример — это уже не дословный перенос.

     И ГРАНИЦА У ЭТОГО ПРАВИЛА ОДНА, ЗАТО ЖЁСТКАЯ: ядро закрывает посылку БЕЗ
     ЕДИНОГО ДОПУЩЕНИЯ ИНДУКЦИИ. Допущения в вызов `свести` ниже не передаются
     вовсе — передаются только объявления подписи и факты самого разбора. Причина
     не в осторожности, а в том, ЧТО ТАКОЕ доказательство индукцией: посылка,
     сведённая без допущений, индукции не потребовала — она того же рода, что
     постусловие без теоремы, и сказать о ней «доказано» можно, ничего не
     спрашивая у автора. Посылка, сведённая ДОПУЩЕНИЕМ, — это шаг индукции, и то,
     что он опёрся на допущение, обязан сказать автор словом `по предположению`.
     Разреши здесь допущения — и теорема из одного случая доказывала бы всё
     подряд, а ведомость писала бы «шаг при допущении» о шаге, которого никто не
     писал. Это проверено изъятием, а не обещано. */
  const закрытоЯдром = new Map()
  const непокрытые = []
  for (const посылка of принцип.premises) {
    if (посылка.case !== null && посылка.case !== undefined) continue
    if (посылка.conclusion === null || посылка.conclusion === undefined) {
      непокрытые.push({ посылка, why: "ветви разбора у этого случая нет вовсе" })
      continue
    }
    /* И ЗДЕСЬ ЖЕ ЧЕТВЁРТЫЙ ХОД, и он тут по той же причине, по какой стоит выше:
       посылка, у которой свободного имени не осталось, — это ОДНО значение, и
       закрыть её вычислением ядро вправе без единого слова автора. Что это даёт
       — сказано числом: база вида «печать варианта начинается с кавычки» до сих
       пор требовала примера на КАЖДЫЙ конструктор, а примеров у функции корпуса
       может не быть ни одного. Допущения индукции в вычисление не едут (их сюда
       и не передают), значит вычислением закрывается ровно то, что индукции не
       потребовало. */
    const сведение = свести(
      посылка.conclusion,
      посылка.facts ?? [],
      посылка.declarations,
      среда.функции,
      среда.вычислить,
      ПРЕДЕЛ_ВЕТВЛЕНИЯ,
    )
    if (сведение.ok) закрытоЯдром.set(посылка, сведение)
    else непокрытые.push({ посылка, why: сведение.why })
  }

  const лишние = принцип.unmatched ?? []
  const покрытие = непокрытые.length === 0 && лишние.length === 0

  if (!покрытие) {
    const части = []
    if (непокрытые.length > 0) {
      части.push(
        `не разобраны и ядром не закрыты ${непокрытые
          .map(({ посылка, why }) => `«${меткаПосылки(посылка)}» (${why})`)
          .join("; ")}`,
      )
    }
    if (лишние.length > 0) {
      части.push(`лишних случаев ${лишние.length}: ${лишние.map(меткаСлучая).join(", ")}`)
    }
    refusals.push({
      code: КОДЫ.cases,
      message:
        /* Тип берётся у ПРИНЦИПА, а не у имени переменной: у встроенного списка
           имени нет вовсе (`имяТипа` там `null`), и сообщение говорило бы
           «не покрывает „null“». Принцип своё имя знает — им и назван. */
        `индукция теоремы «${обязательство.name}» не покрывает «${принцип.type ?? имяТипа}» точно:`
        + ` ${части.join("; ")}. О каждой посылке принципа обязано быть сказано —`
        + " случаем автора или сведением самого ядра; лишний случай говорит о том, чего у типа не бывает",
      span: индукция.span,
    })
  }

  /* Ветвь разбора — то, чем `результат` оказывается в этом случае. Нет разбора
     по переменной индукции — нет и заключения посылки, и говорить дальше не о
     чем: доказывали бы утверждение о `результат`, не зная, что такое `результат`
     в этом случае. */
  if (!принцип.matched) {
    refusals.push({
      code: КОДЫ.branch,
      message:
        `тело функции «${обязательство.of}» не разбирает «${индукция.param}» на верхнем уровне`
        + ` и не сворачивает «${индукция.param}» свёрткой,`
        + " поэтому заключение посылки индукции построить не из чего."
        + " Ядро читает «результат» случая из ДВУХ форм тела и ниоткуда больше:"
        + " с ветви `разбор` по той же переменной (тогда посылок столько, сколько конструкторов)"
        + " и с начала и шага `свёртка` по той же переменной (тогда посылок две — начало и виток)."
        + " Тело-вызов, тело-арифметика и тело-условие заключения посылки не дают:"
        + " угадывать «результат» ядро не станет",
      span: индукция.span,
    })
  }

  const база = []
  const шаг = []
  for (const посылка of принцип.premises) {
    const сведение = закрытоЯдром.get(посылка)
    if (посылка.case === null || посылка.case === undefined) {
      if (сведение === undefined) continue
      /* Посылка, закрытая САМИМ ЯДРОМ. Шагов у неё ноль, и это честно: шаги
         считаются в термах, а терма здесь никто не писал. Чем закрыта — стоит
         полем `by`, потому что ведомость обязана называть это своими словами, а
         не выдавать за написанное автором. */
      cases.push({
        variant: посылка.variant,
        label: меткаПосылки(посылка),
        kind: посылка.kind,
        parts: посылка.parts,
        verdict: СИЛА.proved,
        by: "reduction",
        steps: 0,
        rule: сведение.rule,
      })
      ;(посылка.kind === "base" ? база : шаг).push(СИЛА.proved)
      continue
    }
    const итог = проверитьПосылку(посылка, { обязательство, среда, настройки, принцип })
    refusals.push(...итог.refusals)
    шагов += итог.шагов
    cases.push({
      variant: посылка.variant,
      label: меткаПосылки(посылка),
      kind: посылка.kind,
      parts: посылка.parts,
      verdict: итог.сила,
      by: "term",
      steps: итог.шагов,
      ...(итог.rule === null || итог.rule === undefined ? {} : { rule: итог.rule }),
    })
    ;(посылка.kind === "base" ? база : шаг).push(итог.сила)
  }

  const сила = свернутьПринцип({ покрытие: покрытие && принцип.matched, база, шаг })

  return {
    сила,
    refusals,
    cases,
    шагов,
    /* Ведомости нужны три числа, имя типа и НОСИТЕЛЬ принципа — ничего сверх
       того, что напечатается. Носитель здесь не украшение: «доказано индукцией
       по «Дерево»» и «доказано индукцией по отрезку «нат»» держатся на разном —
       первое на начальности объявленной суммы, второе на конечности отрезка и
       строгом спуске, — и читатель ведомости обязан видеть, на чём. */
    induction: {
      type: принцип.type,
      param: принцип.param,
      carrier: принцип.carrier,
      base: база.length,
      step: шаг.length,
      ...(принцип.carrier === "segment"
        ? { segment: принцип.segment, floor: принцип.floor }
        : принцип.carrier === "fold"
          /* У свёртки функтора НЕТ, и подсовывать сюда функтор списка нельзя:
             принцип держится не на начальности списка, а на конечности числа
             витков. Назван вместо него сам виток — имена накопителя и элемента,
             — потому что читатель ведомости обязан видеть, на чём стоит
             допущение. */
          ? { fold: { acc: принцип.premises[1]?.parts?.[0] ?? null } }
          : { functor: сигнатураФунктора(сумма) }),
      rules: [...new Set(cases.map((с) => с.rule).filter((п) => п !== undefined))],
    },
  }
}

/** Чем посылка названа в отказе: именем конструктора или именем половины отрезка. */
function меткаПосылки(посылка) {
  return посылка.label ?? посылка.variant ?? посылка.kind
}

/**
 * Почему у посылки нет заключения — и причин ровно две, а не одна.
 *
 * Обе кончаются одним и тем же `conclusion === null`, и до этой строки ядро
 * называло только первую. Различает их поле `branch`: оно есть у той посылки,
 * чью ветвь разбора порождение НАШЛО. Нашло ветвь, а заключения всё равно нет —
 * значит заключение не построилось, и единственная причина этому одна:
 * подстановка отказалась, потому что захватила бы чужое имя (`initial.mjs`,
 * `захватывает`).
 *
 * Разница не косметическая: по первому сообщению автор пойдёт править ТЕЛО
 * функции, которое в порядке, и не найдёт ничего. Отказ, называющий не ту
 * причину, стоит дороже отказа молчаливого — молчаливый хотя бы не уводит.
 */
function почемуНетЗаключения(посылка, обязательство) {
  if (посылка.branch === null || посылка.branch === undefined) {
    return (
      `у случая «${меткаПосылки(посылка)}» нет ветви разбора в теле функции «${обязательство.of}»,`
      + " поэтому заключение посылки построить не из чего"
    )
  }
  return (
    `заключение случая «${меткаПосылки(посылка)}» не построено: подстановка в цель ЗАХВАТИЛА БЫ имя —`
    + " цель связывает своим `пусть`, `разбор`, `свёртка` или `отобразить`/`отфильтровать` то самое имя,"
    + " которое свободно в подставляемом теле ветви. Ядро не переименовывает: выдуманное имя"
    + " не сличить с допущением. Назовите элемент связывателя в утверждении иначе, чем параметр функции"
  )
}

/** Чем назван случай автора, не отвечающий ни одной посылке. */
function меткаСлучая(случай) {
  const образец = случай?.pattern
  if (образец?.kind === "variant") return `«${образец.name}»`
  if (образец?.kind === "literal") return `литерал ${JSON.stringify(образец.value)}`
  if (образец?.kind === "any") {
    return образец.bind === undefined || образец.bind === null ? "«любое»" : `«любое ${образец.bind}»`
  }
  return "образец не по варианту"
}

/**
 * Одна посылка принципа — то, что автор написал словом `случай`.
 *
 * Посылка приходит уже построенной: у неё есть заключение (цель, в которой
 * `результат` заменён телом ветви разбора) и допущения (по одному на поле типа
 * самой суммы). Ядру остаётся сверить с ней шаги автора — ни строить, ни искать
 * здесь больше нечего, и это и есть та работа, ради которой принцип порождён
 * термом заранее.
 */
function проверитьПосылку(посылка, { обязательство, среда, настройки, принцип }) {
  return проверитьЦепочку(посылка.case.steps ?? [], {
    обязательство,
    среда,
    настройки,
    посылка,
    принцип,
    место:
      `${посылка.kind === "base" ? "база" : "шаг"} «${меткаПосылки(посылка)}»`
      + ` теоремы «${обязательство.name}»`,
  })
}

/**
 * Цепочка шагов: каждый обязан быть выведен НАЗВАННЫМ правилом.
 *
 * Свёртка слева, состояние — множество известных утверждений. Ни ветвления, ни
 * возврата назад: шаг либо выведен, либо нет, и отказ не отменяет предыдущих
 * шагов, а только называет своё место. Печатать все отказы, а не первый, —
 * решение: автор правит доказательство целиком, и «первая ошибка» заставила бы
 * его прогонять проверку столько раз, сколько в цепочке дыр.
 */
function проверитьЦепочку(шаги, контекст) {
  const refusals = []
  let сила = СИЛА.proved
  let rule = null
  /* Известно к первому шагу ровно две вещи, и обе — чужая работа: гипотезы
     `дано` теоремы и предусловия функции, снятые вызывающими. Ни одну из них
     эта цепочка не доказывает; она с них начинается. */
  const известно = [
    ...(контекст.обязательство.hypotheses ?? []),
    ...(контекст.обязательство.assumptions ?? []).map((выражение) => ({
      kind: "precondition",
      of: контекст.обязательство.of,
      claim: выражение,
    })),
  ]

  шаги.forEach((шаг, и) => {
    const номер = и + 1
    const итог = проверитьШаг(шаг, номер, известно, контекст)
    if (итог.ok) {
      if (итог.claim !== null && итог.claim !== undefined) известно.push(итог.claim)
      if (итог.сила === СИЛА.grid && сила === СИЛА.proved) сила = СИЛА.grid
      if (итог.rule !== null && итог.rule !== undefined) rule = итог.rule
      return
    }
    сила = СИЛА.refused
    /* Отказ обязан назвать не только чего не хватило, но и ЧТО УЖЕ ИЗВЕСТНО:
       иначе автор не видит, дошло ли доказательство до этого места вообще, и
       правит наугад. Ровно это требование к диагностике ядра: «шаг N: не
       выведено X; известно Y — назовите факт или добавьте свойство». */
    refusals.push({
      code: итог.code ?? КОДЫ.step,
      message: `шаг ${номер}, ${контекст.место}: ${итог.why}. ${названо(известно)}`,
      span: шаг.span,
    })
  })

  if (шаги.length === 0) {
    сила = СИЛА.refused
    refusals.push({ code: КОДЫ.step, message: `${контекст.место}: ни одного шага`, span: undefined })
  }

  return { сила, refusals, шагов: шаги.length, rule }
}

/**
 * Что к этому месту уже известно — словами, коротко.
 *
 * Печатается по ВИДУ факта, а не его текстом: утверждение — это выражение, и
 * печатать выражение значило бы завести здесь вторую печать выражений к той,
 * что уже есть в восьми целях. Вида хватает, чтобы понять, дошло ли
 * доказательство до этого места: «предположение индукции» и «пример «X»» —
 * разные вещи, и автор по ним видит, где он.
 */
function названо(известно) {
  if (известно.length === 0) return "к этому месту не известно ничего, кроме гипотез «дано»"
  const виды = известно.map((факт) => {
    if (факт?.kind === "hypothesis") return `предположение индукции о части «${факт.part}»`
    if (факт?.kind === "example") return `пример «${факт.name}»`
    if (факт?.kind === "law") return `закон «${факт.name}» (на сетке)`
    if (факт?.kind === "property") return `постусловие «${факт.name}» функции «${факт.of}» на месте вызова`
    if (факт?.kind === "precondition") return `предусловие функции «${факт.of}»`
    return "гипотеза «дано»"
  })
  return `известно: ${виды.join("; ")}`
}

/** Один шаг: правило названо, ядро только сверяет. */
function проверитьШаг(шаг, номер, известно, контекст) {
  const { обязательство, среда, настройки, посылка } = контекст
  const правило = шаг?.by?.rule ?? null

  if (правило === "example") {
    return поПримеру(шаг, обязательство, среда, настройки, посылка)
  }
  if (правило === "hypothesis") {
    return поПредположению(шаг, посылка, обязательство, среда)
  }
  if (правило === "property") {
    return поСвойству(шаг, посылка, обязательство, среда)
  }
  if (правило === "law") {
    /* Закон обязан быть ОБЪЯВЛЕН. Принять ссылку на незаявленный закон значило
       бы разрешить сослаться на что угодно: строка `по закону «чего не бывает»`
       закрывала бы любой шаг, и ядро перестало бы проверять. */
    if (!среда.законы.has(шаг.by.name)) {
      return {
        ok: false,
        why:
          `закона «${шаг.by.name}» в модуле нет: ни моноида, ни монады, ни изоморфизма с таким именем`
          + " не объявлено — сослаться не на что",
      }
    }
    /* Закон принимается, но ослабляет вердикт до сетки: он сам посчитан на
       конечной сетке автора, и доказательство не может быть сильнее того, на что
       опирается. */
    return {
      ok: true,
      сила: СИЛА.grid,
      claim: { kind: "law", name: шаг.by.name },
    }
  }
  return { ok: false, why: `правило шага не названо (${правило ?? "нет"})` }
}

/**
 * `по свойству «имя»`: СЛИЧЕНИЕ ПО ВЫЗОВУ — и здесь оно наконец что-то доказывает.
 *
 * ── Что здесь стояло раньше ─────────────────────────────────────────────────
 * Отказ, и отказ честный: «свести „результат“ шага с результатом другой функции
 * ядру пока нечем… дождитесь сличения по вызову». Правило существовало на
 * поверхности (`по свойству` разбирается разборщиком с самого начала) и не
 * закрывало НИ ОДНОГО шага. Замер цены доказательства назвал этот пробел вторым
 * по отдаче после формы тела.
 *
 * ── Откуда берётся факт, и почему это ЧТЕНИЕ, а не вера ─────────────────────
 * Постусловие — обещание языка, а не пожелание автора: вычислитель проверяет его
 * ПОСЛЕ КАЖДОГО возврата (`interpret.mjs`, `stepPost`), и нарушенное постусловие
 * прекращает вычисление отказом `FLANG_PROPERTY`. Значит утверждение
 *
 *     у вызова «Г» от а₁ … аₙ, У КОТОРОГО ЕСТЬ ЗНАЧЕНИЕ,
 *     постусловие «Г» на этом значении истинно
 *
 * — не допущение, а свойство языка, ровно того же рода, что `тотальная`: ядро
 * читает написанное слово, а держит его другой слой. На этом же основании ядро
 * уже разворачивает вызовы (`reduce.mjs`, ОГРАНИЧИТЕЛЬ 1 читает `тотальная`).
 * `АКСИОМЫ` от этого не пополнились: аксиому не проверяет никто, а это —
 * проверяется на каждом возврате.
 *
 * Оговорка названа прямо, потому что она есть: у вызова, который НЕ ЗАВЕРШАЕТСЯ
 * или отказывает, значения нет вовсе, и утверждение о нём не истинно и не ложно
 * — оно не высказано. Та же оговорка стоит у правила неотрицательности
 * (`reduce.mjs`, `неотрицательнаяФорма`), и она одна на всё ядро.
 *
 * И ЗАВИСИМОСТЬ НАЗВАНА ЗАРАНЕЕ, чтобы её нельзя было сломать молча: правило
 * стоит на том, что постусловие ЛИБО доказано ядром, ЛИБО проверяется на
 * каждом возврате. Снять проверку с ДОКАЗАННОГО постусловия можно — оно
 * доказано; снять её с НЕДОКАЗАННОГО нельзя, не сломав это правило.
 *
 * ── Подстановка ЧИТАЕТСЯ, а не подбирается ──────────────────────────────────
 * Инстанция строится по МЕСТУ ВЫЗОВА: в заключении посылки (или в цели с
 * подставленным телом) ищутся узлы `вызов «Г» от …`, и на каждом из них
 * постусловие «Г» инстанцируется двумя подстановками — параметры на аргументы
 * этого вызова, `результат` на сам вызов. Кандидатов ровно столько, сколько
 * вызовов, перебирать нечего: подстановку называет сам узел. Ни одного вызова
 * «Г» в заключении нет — отказ говорит именно это, а не «не свелось».
 *
 * ── Круг остаётся запрещён ──────────────────────────────────────────────────
 * Ссылка на доказываемое сейчас постусловие отвергается, как и прежде: `по
 * предположению` существует именно затем, чтобы часть значения обосновывалась
 * убыванием, а не ссылкой на саму цель.
 */
function поСвойству(шаг, посылка, обязательство, среда) {
  if (шаг.by.name === обязательство.name) {
    return {
      ok: false,
      why:
        `«по свойству «${шаг.by.name}»» ссылается на то самое постусловие, которое сейчас доказывается —`
        + " это круг. Часть значения обосновывает «по предположению», а не ссылка на саму цель",
    }
  }
  const найдено = найтиПостусловие(среда, шаг.by.name)
  if (найдено === null) {
    return {
      ok: false,
      why: `постусловия «${шаг.by.name}» нет ни у одной функции модуля — сослаться не на что`,
    }
  }

  /* Заключение — то же самое, что сводит `по предположению`: внутри индукции это
     заключение посылки, вне её — цель с подставленным телом функции. Второго
     способа узнать, о чём идёт речь, здесь нет и быть не должно. */
  const функция = среда.функции.get(обязательство.of)
  const заключение = посылка === undefined || посылка === null
    ? подставить(обязательство.goal, { [обязательство.bind ?? "результат"]: функция?.body ?? null })
    : посылка.conclusion
  if (заключение === null || заключение === undefined) {
    return {
      ok: false,
      code: КОДЫ.branch,
      why: посылка === undefined || посылка === null
        ? `у функции «${обязательство.of}» нет тела, поэтому «результат» цели заменить нечем`
        : почемуНетЗаключения(посылка, обязательство),
    }
  }

  /* Выписанное автором утверждение шага обязано быть ТЕМ ЖЕ, что заключение, —
     тем же требованием и по той же причине, что у `по предположению`: шаг
     закрывает ПОСЫЛКУ, и если бы он закрывал написанную рядом строку, посылка
     считалась бы доказанной тем, что к ней не относится. Это не придирка к
     записи, а дыра: `проверитьЦепочку` объявляет посылку доказанной, когда
     выведены все её шаги, и шаг о постороннем утверждении закрыл бы её даром. */
  if (шаг?.claim !== undefined && шаг?.claim !== null) {
    if (!одинаковы(нормализовать(шаг.claim), нормализовать(заключение))) {
      return {
        ok: false,
        why:
          "выписанное утверждение шага — не заключение этого места."
          + " Заключение ядро СТРОИТ по объявлению и телу функции, и подменить его написанным нельзя;"
          + " уберите утверждение или напишите то же самое",
      }
    }
  }

  const вызовы = вызовыИмени(заключение, найдено.of)
  if (вызовы.length === 0) {
    return {
      ok: false,
      why:
        `постусловие «${шаг.by.name}» принадлежит функции «${найдено.of}», а в заключении этого места`
        + ` нет ни одного вызова «${найдено.of}» — сличать не с чем.`
        + " Ядро инстанцирует постусловие ПО МЕСТУ ВЫЗОВА и мест не выдумывает",
    }
  }

  const инстанции = []
  for (const вызов of вызовы) {
    const инстанция = инстанцияПостусловия(найдено, вызов)
    /* Подстановка отказалась захватом имени — инстанции нет, а не «инстанция
       пустая». Пустить `null` дальше значило бы свести цель к списку фактов, в
       котором одного не хватает, и отказ пришёл бы не оттуда, откуда беда. */
    if (инстанция !== null) инстанции.push({ claim: инстанция })
  }
  if (инстанции.length === 0) {
    return {
      ok: false,
      why:
        `постусловие «${шаг.by.name}» на месте вызова не инстанцируется: подстановка ЗАХВАТИЛА БЫ имя —`
        + " заключение связывает своим связывателем то самое имя, которое свободно в аргументе вызова."
        + " Ядро не переименовывает: выдуманное имя не сличить с заключением",
    }
  }

  /* ДОПУЩЕНИЙ ИНДУКЦИИ ЗДЕСЬ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Правило ядра записано
     прямо: посылка, сведённая допущением, — это ШАГ ИНДУКЦИИ, и то, что он
     опёрся на допущение, обязан сказать автор словом `по предположению`. Пусти
     допущения сюда — и ведомость писала бы «выведено из постусловия «Х»» о
     шаге, который на самом деле закрылся допущением индукции, то есть называла
     бы источником не то. Цена честности названа: шаг, которому нужны И
     допущение, И постусловие вызываемого, сегодня не пишется — цепочка требует,
     чтобы КАЖДЫЙ шаг закрывал заключение сам. */
  const допущения = [
    ...(обязательство.assumptions ?? []).map((выражение) => ({ claim: выражение })),
    ...(посылка?.facts ?? []),
    ...инстанции,
  ]
  const объявления = посылка?.declarations
    ?? (функция?.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
  const сведение = свести(заключение, допущения, объявления, среда?.функции ?? null, null, ПРЕДЕЛ_ВЕТВЛЕНИЯ)
  if (!сведение.ok) {
    return {
      ok: false,
      why:
        `не выведено заключение из постусловия «${шаг.by.name}» функции «${найдено.of}»,`
        + ` инстанцированного на ${вызовы.length} ${вызовы.length === 1 ? "вызове" : "вызовах"}: ${сведение.why}`,
    }
  }
  return {
    ok: true,
    сила: СИЛА.proved,
    rule: сведение.rule,
    claim: { kind: "property", name: шаг.by.name, of: найдено.of },
  }
}

/**
 * Инстанция постусловия на месте вызова — ДВЕ подстановки, и обе читаются с узла.
 *
 * Параметры функции становятся аргументами ЭТОГО вызова, `результат` — самим
 * вызовом. Двух подстановок здесь ровно столько же и по той же причине, что у
 * допущения индукции: постусловие вправе говорить и о `результат`, и о
 * параметрах, и забыть вторую значило бы получить факт о другом значении.
 *
 * Порядок значим и записан явно: сначала параметры (внутрь выражения
 * постусловия), потом `результат`, — иначе подставленный вызов обошёлся бы
 * вторично и его собственные аргументы переписались бы как параметры.
 */
function инстанцияПостусловия(найдено, вызов) {
  const параметры = найдено.fn?.params ?? []
  const аргументы = вызов.args ?? []
  if (параметры.length !== аргументы.length) return null
  const замены = {}
  параметры.forEach((параметр, и) => {
    замены[параметр.name] = аргументы[и]
  })
  const поПараметрам = подставить(найдено.постусловие.expr, замены)
  if (поПараметрам === null) return null
  return подставить(поПараметрам, { [найдено.постусловие.bind ?? "результат"]: вызов })
}

/** Все узлы `вызов <имя>` внутри выражения — обходом, без графа вызовов. */
function вызовыИмени(узел, имя) {
  const найдено = []
  собратьВызовы(узел, (вызов) => {
    if (вызов.name === имя) найдено.push(вызов)
  })
  return найдено
}

/**
 * `по предположению`: ШАГ ИНДУКЦИИ, и здесь он наконец что-то ДОКАЗЫВАЕТ.
 *
 * ── Что изменилось и почему это главное в работе ────────────────────────────
 * Раньше это правило только ОБЪЯВЛЯЛО допущение известным и шло дальше — то
 * есть шаг закрывался тем, что автор написал слово. Вывода при этом не
 * происходило никакого, и рекурсивный случай честно отвергался соседним
 * правилом. Теперь правило обязано СВЕСТИ заключение посылки к допущениям, и
 * пока сведение не прошло, шаг не выведен.
 *
 * ── Три вещи, которых ядро здесь по-прежнему не делает ──────────────────────
 * Не ищет подстановку: допущение построено заранее (`initial.mjs`) по полю
 * рекурсивного типа, и кандидатов ровно столько, сколько таких полей.
 * Не разворачивает вызов на НЕИЗВЕСТНОМ значении: `«Высота» от м` при
 * неизвестном `м` нормальной формы не имеет, и разворачивать его ядро не станет.
 * Развёртка есть, но она закрыта списком из двух видов — вызов на КОНСТРУКТОРЕ и
 * определение без вызовов — и стоит под названным пределом (`reduce.mjs`,
 * `ПРЕДЕЛ_РАЗВЁРТКИ`). Именно поэтому допущения индукции никуда не делись: они и
 * есть то, что известно о вызове, который разворачивать нельзя.
 * Не принимает ничего сверх двух названных правил (`reduce.mjs`): всё, что не
 * свелось, отвергается с указанием, какое правило не прошло и что было известно.
 *
 * ── Почему допущение на частях законно ──────────────────────────────────────
 * Потому что это посылка принципа, порождённого начальной алгеброй, а не
 * догадка: у поля типа самой суммы значение СТРОГО меньше целого (часть
 * конечного дерева), и цепочка частей обрывается сама — тот же довод, которым
 * держится носитель обещания «структурой» у 149 функций корпуса. Ядро не верит
 * допущению — оно требует, чтобы из него был выведен вывод.
 */
function поПредположению(шаг, посылка, обязательство, среда) {
  if (посылка === undefined || посылка === null) {
    return внеИндукции(шаг, обязательство, среда)
  }
  /* ДОПУЩЕНИЯ ЭТОГО МЕСТА — ДВУХ РОДОВ, и оба построены, а не названы автором.
     Первый — предположения индукции: по одному на поле типа самой суммы, их
     строит `initial.mjs` по объявлению. Второй — ПРЕДУСЛОВИЯ функции: внутри
     тела они истинны, потому что снял их каждый вызывающий (`снятьПредусловия`
     выше), и они те же самые во всех посылках — предусловие говорит о входе, а
     вход у всех случаев один.

     Слово «предположение» покрывает оба рода и покрывало всегда: `по
     предположению` — это `by assumption`, а предусловие и есть допущение. Ядро
     от этого не стало верить автору больше: допущение по-прежнему СТРОИТСЯ (из
     объявления суммы или из строки `требует`), а не объявляется словом, и из
     него по-прежнему надо СВЕСТИ заключение. */
  const предусловия = (обязательство.assumptions ?? []).map((выражение) => ({ claim: выражение }))
  const допущения = [...посылка.hypotheses, ...предусловия]
  if (допущения.length === 0) {
    return {
      ok: false,
      code: КОДЫ.induction,
      why:
        `«по предположению» стоит в базе «${меткаПосылки(посылка)}», где предположения индукции нет:`
        + (посылка.variant === null
          ? " это дно отрезка — то место, где спуск кончается, и значения ниже, о котором предполагать,"
            + " просто нет"
          : " у этого конструктора нет ни одного поля с типом самой суммы, значит части значения нет,"
            + " и предполагать не о чем")
        + ", а предусловий у функции не объявлено ни одного."
        + " База закрывается вычислением («по примеру»), предусловием «требует»"
        + " или сводится самим ядром — тогда случая при ней не нужно",
    }
  }
  if (посылка.conclusion === null) {
    return {
      ok: false,
      code: КОДЫ.branch,
      why: почемуНетЗаключения(посылка, обязательство),
    }
  }
  /* Допущение, которого нет, — не пустое допущение. Подстановка, строящая
     допущение, отказывается по той же причине, что и подстановка, строящая
     заключение (захват имени), и отказаться она может ПОРОЗНЬ с ней: значения
     подставляются разные (вызов на части против тела ветви). Пустить такую
     посылку дальше значило бы сводить заключение к списку допущений, в котором
     одного не хватает, — и отказ пришёл бы не оттуда, откуда беда. */
  if ((посылка.hypotheses ?? []).some((г) => г?.claim === null || г?.claim === undefined)) {
    return {
      ok: false,
      code: КОДЫ.induction,
      why:
        `допущение индукции для случая «${меткаПосылки(посылка)}» не построено:`
        + " подстановка в цель ЗАХВАТИЛА БЫ имя — цель связывает своим связывателем то самое имя,"
        + " которое свободно в вызове на части значения. Ядро не переименовывает:"
        + " выдуманное имя не сличить с заключением",
    }
  }

  /* Автор вправе выписать утверждение шага словами (`затем <утверждение> по
     предположению`). Тогда оно обязано быть ТЕМ ЖЕ, что заключение посылки, —
     иначе в файле стояла бы одна строка, а доказывалась другая, и читатель
     видел бы «доказано» рядом с утверждением, к которому это не относится.
     Сличаются нормальные формы, а не тексты: `пусть` и разбор известного
     конструктора — запись, а не содержание. */
  if (шаг?.claim !== undefined && шаг?.claim !== null) {
    if (!одинаковы(нормализовать(шаг.claim), нормализовать(посылка.conclusion))) {
      return {
        ok: false,
        code: КОДЫ.induction,
        why:
          "выписанное утверждение шага — не заключение посылки индукции."
          + " Заключение случая ядро СТРОИТ по объявлению суммы и телу ветви разбора,"
          + " и подменить его написанным нельзя; уберите утверждение или напишите то же самое",
      }
    }
  }

  /* Третий источник известного — ОБЪЯВЛЕНИЯ: типы параметров функции и полей
     образца этого случая. Допущение говорит о части значения, объявление — о
     знаке имени, и ядро не смешивает их: оба приезжают в `свести` порознь и
     закрытым списком. Предусловия едут в ПЕРВОМ списке наравне с
     предположениями индукции: и то и другое — допущение, из которого надо
     СВЕСТИ, а не поверить. */
  const сведение = свести(
    посылка.conclusion,
    [...допущения, ...(посылка.facts ?? [])],
    посылка.declarations,
    среда?.функции ?? null,
    null,
    ПРЕДЕЛ_ВЕТВЛЕНИЯ,
  )
  if (!сведение.ok) {
    return {
      ok: false,
      code: КОДЫ.induction,
      why:
        `шаг «${меткаПосылки(посылка)}» не сведён к допущениям`
        + `${посылка.hypotheses.length === 0 ? "" : ` на ${частями(посылка.parts)}`}`
        + `${предусловия.length === 0 ? "" : ` и ${предусловия.length} предусловию функции`}: ${сведение.why}`,
    }
  }
  return {
    ok: true,
    сила: СИЛА.proved,
    rule: сведение.rule,
    claim:
      посылка.hypotheses.length === 0
        ? { kind: "precondition", of: обязательство.of, count: предусловия.length }
        : {
            kind: "hypothesis",
            of: обязательство.name,
            param: посылка.hypotheses[0]?.param ?? null,
            part: посылка.parts.join(", "),
          },
  }
}

const частями = (части) =>
  части.length === 0 ? "частях" : `${части.length === 1 ? "части" : "частях"} ${части.map((ч) => `«${ч}»`).join(", ")}`

/**
 * `по предположению` ВНЕ индукции: цель при предусловиях функции.
 *
 * ── Почему это то же самое правило, а не второе ─────────────────────────────
 * Внутри индукции ядро сводит ЗАКЛЮЧЕНИЕ ПОСЫЛКИ — цель, в которой `результат`
 * заменён телом ВЕТВИ разбора. Вне индукции ветвей нет, и `результат` — это всё
 * тело функции целиком. Подстановка та же, сведение то же, правил по-прежнему
 * два: меняется только то, ЧЕМ оказывается `результат`, и берётся это с
 * объявления функции, а не угадывается.
 *
 * ── Почему без предусловий здесь нечего делать ──────────────────────────────
 * Свести цель не к чему: допущений нет ни одного. Раньше это место отвечало
 * «посылки, у которой брать допущение, здесь нет» и было право — до `требует` у
 * функции не бывало допущений вовсе. Теперь бывают, и ровно они, а не слово
 * автора, делают шаг возможным. Нет ни одного — отказ остаётся, и текст его
 * называет обе дороги: индукцию и предусловие.
 *
 * ── Граница, названная прямо ────────────────────────────────────────────────
 * Тело с ВЫЗОВОМ (в том числе рекурсивным) остаётся непрозрачным термом:
 * разворачивать вызов ядро не умеет и не будет (`reduce.mjs`, шапка). Значит
 * этой дорогой доказываются утверждения о функциях, чьё тело собрано из
 * известного, — и не доказываются о рекурсивных без объявленной суммы. Так
 * устроен и `flang/examples/rosetta/fibonacci.flang`: его лемма стала
 * ВЫСКАЗЫВАЕМОЙ, а доказанной не стала, и причина названа там же.
 */
function внеИндукции(шаг, обязательство, среда) {
  const предусловия = (обязательство.assumptions ?? []).map((выражение) => ({ claim: выражение }))
  if (предусловия.length === 0) {
    return {
      ok: false,
      code: КОДЫ.induction,
      why:
        "«по предположению» стоит вне индукции, а допущений у этой цели нет ни одного:"
        + " ни посылки индукции (её даёт `индукция по`), ни предусловия функции (его даёт `требует`)."
        + " Предполагать не о чем",
    }
  }

  const функция = среда.функции.get(обязательство.of)
  const тело = функция?.body ?? null
  if (тело === null) {
    return {
      ok: false,
      code: КОДЫ.step,
      why: `у функции «${обязательство.of}» нет тела, поэтому «результат» цели заменить нечем`,
    }
  }

  const заключение = подставить(обязательство.goal, { [обязательство.bind ?? "результат"]: тело })

  /* Выписанное автором утверждение шага обязано быть ТЕМ ЖЕ, что заключение, —
     тем же требованием и по той же причине, что внутри индукции: иначе в файле
     стояла бы одна строка, а доказывалась другая. */
  if (шаг?.claim !== undefined && шаг?.claim !== null) {
    if (!одинаковы(нормализовать(шаг.claim), нормализовать(заключение))) {
      return {
        ok: false,
        code: КОДЫ.step,
        why:
          "выписанное утверждение шага — не цель функции с подставленным телом."
          + " Заключение ядро СТРОИТ по объявлению и телу функции, и подменить его написанным нельзя",
      }
    }
  }

  const сведение = свести(заключение, предусловия, [], null, null, ПРЕДЕЛ_ВЕТВЛЕНИЯ)
  if (!сведение.ok) {
    return {
      ok: false,
      code: КОДЫ.step,
      why: `цель не сведена к ${предусловия.length} предусловию функции: ${сведение.why}`,
    }
  }
  return {
    ok: true,
    сила: СИЛА.proved,
    rule: сведение.rule,
    claim: { kind: "precondition", of: обязательство.of, count: предусловия.length },
  }
}

/**
 * `по примеру «имя»`: утверждение ЗАКРЫТО и вычисляется в `да`.
 *
 * Единственное правило, которое решается вычислением, а не выводом, и потому
 * единственное, которое сегодня закрывает случай целиком. Закрытый терм — это
 * значение: чтобы узнать, верно ли утверждение о нём, спорить не о чем, надо
 * посчитать. Считает тот же интерпретатор, которым язык считает всё остальное, —
 * второго вычислителя здесь нет и быть не должно.
 *
 * ПОЧЕМУ ПРИМЕР ОБЯЗАН БЫТЬ ОБРАЗЦОМ ЭТОГО СЛУЧАЯ. Пример про `«Звено»` ничего
 * не говорит о случае `«Пусто»`: это утверждение о другом значении. Проверяется
 * сличением: значение аргумента индукции в примере обязано быть тем же
 * вариантом, что образец случая.
 */
function поПримеру(шаг, обязательство, среда, настройки, посылка) {
  const fn = среда.функции.get(обязательство.of)
  const пример = (fn?.examples ?? []).find((п) => п.name === шаг.by.name)
  if (пример === undefined) {
    return { ok: false, why: `у функции «${обязательство.of}» нет примера «${шаг.by.name}»` }
  }

  const случайВарианта = посылка === undefined || посылка === null
    ? null
    : { param: посылка.param ?? null, variant: посылка.variant, bind: посылка.binds }

  /* ТА ЖЕ ПРОВЕРКА СОСТОЯТЕЛЬНОСТИ, НО ВНЕ ИНДУКЦИИ, и здесь её не было.
     Ниже, в ветви случая, стоит правило «примером закрывается только то, у чего
     значение одно». Доказательство БЕЗ индукции случая не имеет вовсе, и до этой
     строки правило к нему не применялось ни разу: `по примеру` закрывало цель
     одним прогоном. Это принимало ложь, и принимало её молча — измерено
     программой, а не рассуждением: постусловие «длина соединения равна трём» у
     «Соединить списки» (утверждение обо ВСЕХ парах списков, ложное почти на
     всех) получало вердикт «доказано ядром: терм принят, 1 шаг», потому что
     пример «Два непустых» и правда даёт три. Ведомость печатала слово
     «доказано» о заведомо ложном утверждении, то есть ядро в этом месте не
     проверяло ничего.

     Правило то же, что у случая, и другим быть не может: пример — ОДНО
     значение, и закрыть им можно ровно то утверждение, у которого значение одно.
     Вне индукции это функция без параметров: у неё вход один, и прогон отвечает
     обо всех входах, потому что вход один. У функции с параметрами значений
     столько же, сколько входов, и один пример говорит об одном из них.

     Граница ровно эта и была объявлена прозой с самого начала («целиком ядро
     доказывает утверждения, закрытые в каждом случае: конечные суммы, у которых
     все конструкторы без полей, И ФУНКЦИИ БЕЗ ПАРАМЕТРОВ» — `docs/overview.ru.md`),
     а в коде стояла только её половина. Здесь код догнал прозу. */
  if (случайВарианта === null && (обязательство.vars ?? []).length > 0) {
    const имена = (обязательство.vars ?? []).map((п) => `«${п.name}»`).join(", ")
    return {
      ok: false,
      why:
        `«по примеру «${шаг.by.name}»» стоит вне индукции, а у функции «${обязательство.of}»`
        + ` есть параметры (${имена}): значений у утверждения столько же, сколько входов,`
        + " а пример — одно из них. Примером закрывается только утверждение с ОДНИМ значением"
        + " (функция без параметров); обо всех значениях говорит «индукция по <параметр>»",
    }
  }

  if (случайВарианта !== null) {
    const параметр = случайВарианта.param

    /* ГЛАВНАЯ ПРОВЕРКА СОСТОЯТЕЛЬНОСТИ ЭТОГО ПРАВИЛА, и без неё ядро принимало
       бы ложь. Пример — ОДНО значение. Закрыть им случай можно ровно тогда,
       когда у ЗАКЛЮЧЕНИЯ ПОСЫЛКИ значение одно, то есть когда в нём не осталось
       ни одного свободного имени: закрытый терм — это значение, и вычисление
       отвечает про него обо всём случае. Осталось хоть одно свободное имя —
       значений столько же, сколько подстановок, и один прогон говорит об одной
       из них.

       ЗДЕСЬ СТОЯЛА ПОЛОВИНА ЭТОГО ПРАВИЛА, И ПОЛОВИНА ПРИНИМАЛА ЛОЖЬ. Проверялся
       образец: «случай связывает имена — отказать». Образец — не заключение, и
       расходятся они в обе стороны, обе измеримы:

         СЛИШКОМ СЛАБО. У функции ДВУХ параметров образец `случай пусто` не
         связывает ничего, а в заключении остаётся второй параметр. Тело
         `случай пусто то н` при цели «результат не меньше 0» давало заключение
         `н не меньше 0` — ЛОЖНОЕ при н = −1, — и закрывалось примером с н = 5.
         Со встроенными типами функции с двумя параметрами — правило, а не
         исключение (в `lists.flang` их 19 из 28), так что начальная алгебра
         списка открыла бы эту дыру настежь.

         СЛИШКОМ СИЛЬНО. Образец `случай вариант «Одиночка» с звено как одно`
         связывает имена, а заключение всё равно закрыто, если тело ветви их не
         употребляет (`то 1` при цели «результат не меньше 0» даёт `1 не меньше
         0`). Такой случай примером закрывается законно, и отказывать ему значило
         требовать доказательства у того, что уже вычислено.

       Проверять надо то, о чём правило и говорит, — само заключение. Свободные
       имена считаются по нормальной форме: `пусть` и разбор известного
       конструктора — запись, а не содержание, и имя, исчезающее при развёртке,
       свободным не является. */
    if (посылка.conclusion === null) {
      return {
        ok: false,
        code: КОДЫ.branch,
        why: `${почемуНетЗаключения(посылка, обязательство)}, и закрывать примером нечего`,
      }
    }

    /* ТА ЖЕ ПРОВЕРКА, НО ДОВЕДЁННАЯ ДО КОНЦА, И ДЫРА, КОТОРУЮ ОНА ЗАКРЫВАЕТ.
       Строка выше смотрит только на имена, связанные ОБРАЗЦОМ, — а свободным в
       заключении бывает и второй ПАРАМЕТР функции, до которого образец не
       касается вовсе. У функции с одним параметром это невидимо, у функции с
       двумя — принятая ложь: `случай вариант «Пусто»` при `принимает стопка:
       «Стопка», порог: число` замкнутым не является, и пример говорит о ОДНОМ
       пороге из бесконечности. Спрашивается это не здесь, а у порождения:
       свободные имена заключения оно считает той же подстановкой, какой строит
       само заключение. */
    const свободные = посылка.free ?? []
    if (свободные.length > 0) {
      return {
        ok: false,
        code: КОДЫ.induction,
        why:
          `в заключении случая «${меткаПосылки(посылка)}» свободны`
          + ` ${свободные.map((и) => `«${и}»`).join(", ")}, поэтому значений у него бесконечно много,`
          + " а пример — одно. Примером закрывается посылка, у которой свободного имени не осталось;"
          + " с живым именем её закрывает сведение или «по предположению»",
      }
    }

    const значение = пример.args?.[параметр]
    /* Посылка по отрезку варианта не имеет: у `нат` конструкторов нет вовсе.
       Отвечает ли пример этому случаю, решается тем же вопросом, что у суммы, —
       ТО ЛИ ЭТО ЗНАЧЕНИЕ, — только заданным числом: значение обязано попадать в
       дно, прочитанное с условия «если». Пример из спуска о дне не говорит. */
    if (посылка.variant === null) {
      const верх = посылка.bound
      const число = typeof значение === "number" ? значение : Number.NaN
      if (!Number.isFinite(число) || число < 0 || число > верх) {
        return {
          ok: false,
          why:
            `пример «${шаг.by.name}» задаёт «${параметр}» как ${JSON.stringify(значение) ?? "ничто"},`
            + ` а дно отрезка — это [0, ${верх}]:`
            + " это утверждение о другом значении, и случай им не закрывается",
        }
      }
    } else {
      const вариантЗначения = вариантОбразца(значение)
      if (вариантЗначения !== случайВарианта.variant) {
        return {
          ok: false,
          why:
            `пример «${шаг.by.name}» задаёт «${параметр}» как`
            + ` ${вариантЗначения === null ? "не вариант" : `«${вариантЗначения}»`},`
            + ` а случай разбирает «${случайВарианта.variant}»:`
            + " это утверждение о другом значении, и случай им не закрывается",
        }
      }
    }
  }

  /* Считаем ровно то, что обещает функция: постусловие уже проверяется после
     каждого возврата, значит прогон примера И ЕСТЬ проверка утверждения на этом
     значении. Отдельного вычислителя утверждения здесь нет — иначе их стало бы
     два, и разошлись бы они молча. */
  const шагов = настройки.maxSteps ?? 200000
  try {
    evaluate(среда.program, обязательство.of, пример.args ?? {}, шагов)
  } catch (ошибка) {
    return {
      ok: false,
      why:
        `пример «${шаг.by.name}» не проходит: ${ошибка?.message ?? "вычисление сорвалось"}.`
        + " Утверждение на этом значении неверно, значит случай им не закрывается",
    }
  }
  return { ok: true, сила: СИЛА.proved, claim: { kind: "example", name: шаг.by.name, args: пример.args ?? {} } }
}

