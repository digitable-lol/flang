/**
 * Всё, что ядру нужно знать о программе, — собранное один раз и только чтением.
 *
 * Своего графа вызовов и своего вывода типов здесь нет и быть не должно: у
 * программы уже есть и то, и другое, а второй ответ на тот же вопрос расходится
 * с первым молча.
 */
function средаПрограммы(program, настройки = {}) {
  const функции = new Map()
  for (const fn of program?.functions ?? []) функции.set(fn.name, fn)
  const суммы = new Map()
  for (const тип of program?.types ?? []) {
    if (тип?.kind !== "sum") continue
    суммы.set(тип.name, тип)
  }
  /* Имена объявленных законов — те, на которые вправе сослаться `по закону`.
     Собираются из объявлений, а не из результатов проверки законов: сослаться
     можно на объявленный закон, а посчитан он или остался допущением — это
     ослабление вердикта, а не запрет ссылки, и решается оно отдельно. */
  const законы = new Set()
  for (const поле of ["monoids", "monads", "isomorphisms", "embeddings", "intersections"]) {
    for (const узел of program?.[поле] ?? []) {
      if (typeof узел?.name === "string") законы.add(узел.name)
    }
  }
  /* ЧЕТВЁРТЫЙ ХОД `свести` — вычисление замкнутой цели, собранное здесь ОДИН
     раз на программу: имя обёртки выбирается по всем объявленным именам, и
     выбирать его заново на каждую цель значило бы отвечать на один вопрос
     столько раз, сколько у модуля утверждений. */
  const вычислить = вычислениемЗамкнутой(program, настройки)
  return { program, функции, суммы, законы, вычислить }
}

/**
 * Предел вычисления замкнутой цели — витков и глубины.
 *
 * ЧИСЛО НАЗВАНО, А НЕ СПРЯТАНО, и по той же причине, по какой назван
 * `ПРЕДЕЛ_РАЗВЁРТКИ` (`flang/proof/reduce.mjs`): предел, о котором нельзя
 * сказать, отличается от зависания только тем, что зависание видно. Достижение
 * предела здесь НЕ проходит молча — вычисление отказывает и говорит об этом
 * словами, потому что «не досчитали» и «неправда» — разные ответы автору.
 *
 * СОСТОЯТЕЛЬНОСТИ ЧИСЛО НЕ КАСАЕТСЯ: остановиться раньше — значит доказать
 * МЕНЬШЕ, а не доказать ложное. Поэтому взято столько же, сколько у вычислителя
 * языка по умолчанию (`DEFAULT_MAX_STEPS`): цель — это выражение из тела
 * функции, и считать её дольше, чем язык считает саму функцию, незачем.
 */
export const ПРЕДЕЛ_ВЫЧИСЛЕНИЯ = Object.freeze({ шагов: 1_000_000, глубина: 10_000 })

/** Имя обёртки, в которой цель отдаётся вычислителю. */
const ИМЯ_ОБЁРТКИ = "цель ядра доказательства"

/**
 * ВЫЧИСЛЕНИЕ ЗАМКНУТОЙ ЦЕЛИ — тот же ход, каким `по примеру` закрывает случай.
 *
 * ── Почему это не новое доверие ─────────────────────────────────────────────
 * Ядро уже решает вычислением, и решает им единственное правило, которое
 * закрывает случай целиком: `по примеру` (ниже) прогоняет пример тем же
 * интерпретатором, которым язык считает всё остальное, и принимает случай,
 * если утверждение на этом значении верно. Довод там записан прямо: «закрытый
 * терм — это значение, и спорить о нём не о чем, надо посчитать». Здесь тот же
 * довод и тот же интерпретатор — новое только место, откуда ход позван
 * (`свести`). Доверенных сущностей не прибавилось, `АКСИОМЫ` остались пусты.
 *
 * ── Три условия, и ни одно не украшение ─────────────────────────────────────
 *   ЗАМКНУТОСТЬ  У цели не осталось ни одного свободного имени. Считается она
 *                ТОЙ ЖЕ функцией (`свободныеИмена`), какой её считает посылка
 *                индукции для `по примеру`, — иначе на вопрос «какие имена
 *                здесь свободны» было бы два ответа, а расходятся такие ответы
 *                молча. Осталось хоть одно имя — значений у цели столько же,
 *                сколько подстановок, и один прогон говорит об одной из них.
 *                Это ровно тот класс, на котором ядро уже печатало «доказано»
 *                о неправде (`flang/test/proof-soundness.test.mjs`).
 *   ПРЕДЕЛ       Вычисление ограничено витками и глубиной и при исчерпании
 *                ОТКАЗЫВАЕТ, называя предел. Молчаливое «не вышло» здесь было
 *                бы худшим из ответов: неотличимым от «неправда».
 *   ЗНАЧЕНИЕ     Принимается ровно `да`. `нет` — это ЛОЖНОЕ утверждение, и
 *                отказ говорит именно это; не признак — цель не утверждение
 *                вовсе; отказ вычисления — цель не имеет значения, и говорить
 *                о нём нечего.
 *
 * ── Почему цель заворачивается в функцию ────────────────────────────────────
 * Вычислитель языка считает ФУНКЦИЮ, а не выражение, и второго входа у него
 * нет. Обёртка — функция без параметров с целью в теле; это та же самая форма,
 * какой цель считает автор, когда пишет `пример`. Имя обёртки выбирается так,
 * чтобы не совпасть ни с одним объявленным (тот же приём, что у сторожей меры в
 * `defunc.mjs`): подменить собой чужую функцию она не имеет права.
 *
 * ── Почему это ВЫПУЩЕНО НАРУЖУ ──────────────────────────────────────────────
 * Ход, который нельзя позвать порознь, нельзя и проверить порознь: негативная
 * проверка обязана уметь спросить у него ровно один вопрос — «что ты ответишь
 * на цель со свободным именем, на незавершающуюся и на отказавшую» — и сверить
 * ОТКАЗ ДОСЛОВНО. Через `checkProofs` этот отказ не виден вовсе: постусловие без
 * теоремы, которое не закрылось, вердикта не получает по решению соседней
 * функции. Поэтому вход сюда открыт, и открыт он ради изъятия, а не удобства.
 *
 * @param {object} program AST модуля
 * @param {{ maxSteps?: number, maxDepth?: number }} настройки
 * @returns {(цель: object) => {ok: boolean, why: string|null}}
 */
export function вычислениемЗамкнутой(program, настройки = {}) {
  const занято = new Set()
  for (const fn of program?.functions ?? []) {
    if (typeof fn?.name === "string") занято.add(fn.name)
  }
  let имя = ИМЯ_ОБЁРТКИ
  for (let суффикс = 2; занято.has(имя); суффикс += 1) имя = `${ИМЯ_ОБЁРТКИ} ${суффикс}`

  const пределы = {
    maxSteps: настройки.maxSteps ?? ПРЕДЕЛ_ВЫЧИСЛЕНИЯ.шагов,
    maxDepth: настройки.maxDepth ?? ПРЕДЕЛ_ВЫЧИСЛЕНИЯ.глубина,
  }

  return (цель) => {
    if (цель === null || цель === undefined) {
      return { ok: false, why: "вычислять нечего: цели нет" }
    }
    const свободные = [...свободныеИмена(цель)]
    if (свободные.length > 0) {
      return {
        ok: false,
        why:
          `Вычислить её тоже нельзя: в цели свободны ${свободные.map((и) => `«${и}»`).join(", ")},`
          + " то есть значений у неё столько же, сколько подстановок, а вычисление отвечает про одно."
          + " Вычислением закрывается цель, у которой свободного имени не осталось ни одного",
      }
    }

    /* Обёртка объявлена НЕ тотальной, и это не описка: завершение её тела никто
       не доказывал — ровно затем над вычислением и стоит предел. Сказать здесь
       `тотальная` значило бы приписать функции обещание, которого нет. */
    const обёртка = { name: имя, total: false, params: [], returns: null, body: цель }
    const обёрнутая = { ...program, functions: [...(program?.functions ?? []), обёртка] }

    let значение
    try {
      значение = evaluate(обёрнутая, имя, {}, пределы)
    } catch (ошибка) {
      return {
        ok: false,
        why:
          `Вычислить её тоже не вышло: ${ошибка?.message ?? "вычисление сорвалось"}`
          + ` (предел — ${пределы.maxSteps} витков и глубина ${пределы.maxDepth}).`
          + " Цель без значения не доказана и не опровергнута: отказ вычисления — это отказ,"
          + " а не «нет»",
      }
    }

    if (значение === true) return { ok: true, why: null }
    if (значение === false) {
      return {
        ok: false,
        why:
          "Вычисление же говорит о ней прямо: замкнутая цель посчитана и дала «нет»."
          + " Значение у неё одно, значит утверждение ЛОЖНО — доказывать нечего, надо чинить",
      }
    }
    return {
      ok: false,
      why:
        `Вычислить её тоже нельзя: замкнутая цель дала ${describeValue(значение)}, а не признак.`
        + " Утверждение обязано быть признаком: «да» или «нет», и вычисление не вправе"
        + " считать признаком что-то ещё",
    }
  }
}

