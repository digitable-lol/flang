/**
 * Снять предусловия у всех вызовов программы.
 *
 * ── Почему это работа вызывающего, а не вызываемого ─────────────────────────
 * Проверка на входе функции сказала бы о том входе, который пришёл; утверждение
 * нужно обо ВСЕХ. Обязательство на вызывающем даёт ровно обратное: если каждый
 * вызов снял условие, то внутри тела оно ИСТИННО — не «проверено», а известно, —
 * и на него вправе опираться правила сведения (`поПредположению` ниже). Это и
 * есть то, ради чего слово заведено; проверка в рантайме дала бы только
 * проверку. Так же устроено в Dafny, и по той же причине.
 *
 * Побочное следствие, ради которого возражение против слова и снялось: в восьми
 * целях печати не появляется ни одной новой строки. Проверять во время работы
 * то, что снято на проверке, значило бы платить за доказанное.
 *
 * ── Три правила снятия, и все три уже есть у ядра ───────────────────────────
 * Предусловие вызываемого — выражение о его ПАРАМЕТРАХ. Подставив на место
 * параметров аргументы вызова, получаем ИНСТАНЦИЮ — утверждение о том, чем
 * вызывающий зовёт. Дальше — ни одного нового правила:
 *
 *   СВЕДЕНИЕМ    `свести` (`flang/proof/reduce.mjs`) при фактах вызывающего.
 *                Факты — предусловия САМОЙ вызывающей функции: внутри её тела
 *                они истинны, потому что их сняли её собственные вызывающие.
 *                Правила те же два, список тот же закрытый.
 *   ВЫЧИСЛЕНИЕМ  инстанция ЗАМКНУТА (свободных имён не осталось) — тогда это
 *                значение, и спорить не о чем, надо посчитать. То же правило и
 *                тем же вычислителем, каким закрывается база индукции
 *                (`поПримеру`); третьего вычислителя здесь нет.
 *   НИЧЕМ        всё остальное ОТВЕРГАЕТСЯ поимённо — с указанием вызова,
 *                предусловия и того, какие факты были известны.
 *
 * ── Чего здесь нет и почему ─────────────────────────────────────────────────
 * Нет условия ветвления как факта. `если осталось не больше 0 то … иначе «Ф» от
 * (осталось минус 1)` — вызов стоит под условием, и условие о нём кое-что
 * говорит; собирать эти факты значило бы завести здесь путевые условия, то есть
 * анализ, которого у языка нет ни одного. Названо прямо, потому что это
 * ближайшая граница слова: предусловие, которое держится ветвлением вызывающего,
 * сегодня не снимается, и отказ обязан сказать это, а не промолчать.
 *
 * @param {object} program AST модуля
 * @param {{ maxSteps?: number }} [настройки]
 * @returns {{ sites: number, discharged: number, diagnostics: object[] }}
 */
export function снятьПредусловия(program, настройки = {}) {
  const требования = new Map()
  for (const fn of program?.functions ?? []) {
    const список = Array.isArray(fn?.preconditions) ? fn.preconditions : []
    if (список.length > 0) требования.set(fn.name, { fn, список })
  }
  if (требования.size === 0) return { sites: 0, discharged: 0, diagnostics: [], неоплаченные: new Set() }

  /* Места вызова собираются одним обходом и только чтением: своего графа
     вызовов здесь не заводится — он уже есть у анализа завершаемости, а второй
     ответ на тот же вопрос расходится с первым молча. Здесь нужен не граф, а
     сами узлы вызова с их аргументами, и берутся они с дерева. */
  const места = []
  for (const fn of program?.functions ?? []) {
    const факты = (Array.isArray(fn?.preconditions) ? fn.preconditions : []).map((п) => п.expr)
    собратьВызовы(fn?.body, (вызов) => {
      const цель = требования.get(вызов.name)
      if (цель === undefined) return
      const аргументы = Array.isArray(вызов.args) ? вызов.args : []
      const параметры = цель.fn.params ?? []
      if (аргументы.length !== параметры.length) return /* об арности говорит типизатор */
      const замены = {}
      параметры.forEach((параметр, и) => {
        замены[параметр.name] = аргументы[и]
      })
      for (const предусловие of цель.список) {
        места.push({
          из: fn.name,
          кого: вызов.name,
          предусловие,
          инстанция: нормализовать(подставить(предусловие.expr, замены)),
          факты,
          span: вызов.span ?? предусловие.span ?? null,
        })
      }
    })
  }

  /* Сведение — первым: оно ничего не считает и потому не может не завершиться. */
  const осталось = []
  let снято = 0
  for (const место of места) {
    const сведение = свести(место.инстанция, место.факты, [], null, null, ПРЕДЕЛ_ВЕТВЛЕНИЯ)
    if (сведение.ok) {
      снято += 1
      место.rule = сведение.rule
      continue
    }
    место.why = сведение.why
    осталось.push(место)
  }

  /* Вычислением — вторым и только для замкнутых. Вычислитель создаётся ОДИН на
     всю программу: инстанции складываются в неё отдельными функциями без
     параметров, потому что вычислитель умеет звать функцию, а не выражение.
     Собирать его на каждое место значило бы готовить программу столько раз,
     сколько в ней вызовов. */
  const замкнутые = осталось.filter((место) => свободныеИмена(место.инстанция).size === 0)
  if (замкнутые.length > 0) {
    const занято = new Set((program?.functions ?? []).map((fn) => fn.name))
    const добавленные = замкнутые.map((место, и) => {
      let имя = `снятие предусловия ${и + 1}`
      while (занято.has(имя)) имя = `${имя} `
      занято.add(имя)
      место.синтетическая = имя
      return { name: имя, total: true, params: [], returns: { kind: "flag" }, body: место.инстанция, examples: [] }
    })
    const производная = { ...program, functions: [...(program.functions ?? []), ...добавленные] }
    let вычислитель = null
    try {
      вычислитель = createRuntime(производная, { maxSteps: настройки.maxSteps ?? 200000 })
    } catch {
      вычислитель = null /* программа не готовится — об этом скажет тот, кто её готовит */
    }
    if (вычислитель !== null) {
      for (const место of замкнутые) {
        try {
          место.значение = вычислитель.call(место.синтетическая, {})
        } catch (ошибка) {
          место.сорвалось = ошибка?.message ?? "вычисление сорвалось"
        }
      }
    }
  }

  const diagnostics = []
  /* НЕОПЛАЧЕННЫЕ ВЫЗВАННЫЕ — по имени того, КОГО зовут, и список этот нужен не
     диагностике, а ПРАВИЛУ ПОСТУСЛОВИЯ ВЫЗВАННОГО (`постусловияВызванных`
     ниже). Постусловие вызываемого верно только при выполненном `требует`;
     значит брать его там, где `требует` где-нибудь не снято, нельзя — это была
     бы аксиома под другим именем, и её не поймал бы ни один сторож пустоты
     `АКСИОМЫ`. Ответ на вопрос «оплачено ли» даёт ровно эта функция и никто
     больше: второй ответ на тот же вопрос разошёлся бы с первым молча.

     ИМЯ ВЫЗВАННОГО, А НЕ РЕБРО, и это оценка СВЕРХУ нарочно: нормализация цели
     вправе принести вызов из ЧУЖОГО тела (развёртка определения), и тогда ребра
     «доказываемая → вызванная» в исходнике не было вовсе, а неоплаченное место
     — было. Назвать неоплаченным того, у кого не оплачено хоть одно место,
     безопасно; пропустить неоплаченного — нет. */
  const неоплаченные = new Set()
  for (const место of осталось) {
    if (место.значение === true) {
      снято += 1
      continue
    }
    неоплаченные.add(место.кого)
    const почему =
      место.значение === false
        ? "инстанция замкнута и вычисляется в «нет»: этот вызов условию не удовлетворяет"
        : место.сорвалось !== undefined
          ? `инстанция замкнута, но не вычислилась: ${место.сорвалось}`
          : место.why
    diagnostics.push({
      code: КОДЫ.precondition,
      severity: "error",
      message:
        `вызов «${место.кого}» в функции «${место.из}» не снимает предусловие`
        + ` «${место.предусловие.name}»: ${почему}.`
        + ` ${названоФактами(место.факты)}`,
      span: место.span,
    })
  }

  return { sites: места.length, discharged: снято, diagnostics, неоплаченные }
}

/** Что вызывающему известно в этом месте — по именам, коротко. */
function названоФактами(факты) {
  if ((факты ?? []).length === 0) {
    return "вызывающему здесь не известно ничего: у него самого предусловий нет,"
      + " а условие ветвления фактом ядру не является (граница названа в шапке файла)"
  }
  return `известно: ${факты.length} собственное предусловие вызывающего`
}

/** Все узлы `call` дерева — обходом, без графа вызовов. */
function собратьВызовы(узел, взять) {
  if (узел === null || узел === undefined || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) собратьВызовы(элемент, взять)
    return
  }
  if (узел.kind === "call" && typeof узел.name === "string") взять(узел)
  for (const [ключ, значение] of Object.entries(узел)) {
    if (ключ === "span") continue
    собратьВызовы(значение, взять)
  }
}

