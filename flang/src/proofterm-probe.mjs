/**
 * Аксиомы арифметики — место оставлено, и оно ПО-ПРЕЖНЕМУ ПУСТО.
 *
 * Числа flang — IEEE-754. «х минус 1 меньше х» на них неправда при большом |х|
 * (ровно та причина, по которой анализ завершаемости ставит сторожа на
 * постоянный шаг), а «х плюс 1 не меньше х» неправда при переполнении. Аксиома,
 * которая иногда ложна, хуже отсутствующей: она делает ложным всё, что из неё
 * выведено.
 *
 * ЗДЕСЬ СТОЯЛО «список наполнится, когда у языка появится точный тип `нат` с
 * дном». Тип появился, и список НЕ наполнился — это стоит сказать прямо, потому
 * что вышло не по плану, а лучше плана. `нат` дал не аксиомы, а ФАКТЫ: отрезок
 * [0, 2^53−1] у объявленного имени читается ядром там, где автор его написал, —
 * и дно, и потолок (`reduce.mjs`, `известноеПоТипу` и `ограниченноеПоТипу`).
 * Факт из подписи и аксиома — разные вещи: подпись проверяет типизатор на каждом
 * вызове и граница входа на каждом запуске, а аксиому не проверяет никто.
 *
 * ЧЕМ ОТ АКСИОМЫ ОТЛИЧАЮТСЯ ПРАВИЛА СВЕДЕНИЯ (`flang/proof/reduce.mjs`), которые
 * этой работой появились. Аксиома — утверждение, принятое БЕЗ доказательства, и
 * ложная аксиома отравляет всё дерево вывода. Правило сведения — теорема о
 * IEEE-754, доказанная рассуждением о представлении: «сумма двух значений из
 * [0, +∞] лежит в [0, +∞]» верно на всех входах без исключения, включая
 * переполнение (+∞) и оба нуля, а на NaN посылка `не меньше 0` попросту ложна.
 * Разница не словесная: аксиому надо принять на веру, а правило — проверить, и
 * его проверяет отдельный тест на враждебной выборке (NaN, ±0, ±∞, крайние
 * значения). Всё, для чего такого рассуждения нет, в правила не попало —
 * вычитания там нет и не будет, потому что разность двух натуральных
 * отрицательна уже на `2 минус 3`.
 *
 * Умножение в правилах ЕСТЬ, но с условием, и условие — то самое рассуждение о
 * представлении: сомножители берутся, только когда о КАЖДОМ известны ОБЕ
 * границы, то есть он лежит в отрезке [0, конечное]. Одного дна мало: `0 × +∞`
 * в IEEE-754 даёт NaN, а на NaN посылка `не меньше 0` ложна, и правило,
 * бравшее бы одно дно, доказало бы ложь. Раньше здесь стояло «умножения там
 * нет» — это перестало быть правдой вместе с `work/kernel-mul-field`.
 *
 * И у каждого правила свой список случаев, а не общий: правило дна берёт сумму
 * (сумма неотрицательных неотрицательна), правило потолка сумму НЕ берёт (сумма
 * двух `нат` выходит за 2^53−1 законно). Перепиши кто-нибудь один список из
 * другого — ядро начало бы доказывать ложь, и это проверено изъятием.
 */
export const АКСИОМЫ = Object.freeze([])

/** Сила вердикта. Порядок значим: слабейшее побеждает в цепочке. */
export const СИЛА = Object.freeze({ proved: "доказано", grid: "сетка", refused: "отвергнуто" })

/**
 * Проверить доказательства всех обязательств программы.
 *
 * @param {object} program AST модуля
 * @param {object[]} список обязательства из `obligations.mjs`
 * @param {{ maxSteps?: number }} [настройки]
 * @returns {{ version: number, checked: object[], diagnostics: object[] }}
 */
export function checkProofs(program, список, настройки = {}) {
  const diagnostics = []
  const checked = []
  const среда = средаПрограммы(program, настройки)

  /* Предусловия снимаются ПЕРВЫМИ, и порядок здесь не косметический: допущение,
     на которое опираются термы ниже, обязано быть оплачено раньше, чем на него
     сошлются. Не сошлись — программа отвергнута, и «доказано» о её теоремах
     напечатано не будет: ведомость не печатается у программы с отказом. */
  const предусловия = снятьПредусловия(program, настройки)
  diagnostics.push(...предусловия.diagnostics)
  /* ОПЛАЧЕННОСТЬ ПРИЕЗЖАЕТ В СРЕДУ ДАННЫМИ, а не спрашивается заново: правило
     постусловия вызванного обязано знать, снято ли `требует` у вызванного, и
     знать это ОТ ТОГО, КТО СНИМАЛ. */
  среда.неоплаченные = предусловия.неоплаченные ?? new Set()
  /* СПИСОК ДОКАЗАННОГО — то, чем закрыт круг. Пуст на первом проходе, растёт от
     прохода к проходу и никогда не убывает: постусловие попадает сюда только
     после того, как ядро закрыло его САМО, без единого факта по вызову. */
  среда.доказанные = new Set()

  const постусловия = (список ?? []).filter((о) => о.kind === "postcondition")
  /* ЗАКРЫТЫЕ БЕЗ ТЕОРЕМЫ ИДУТ НЕПОДВИЖНОЙ ТОЧКОЙ, и это не оптимизация, а то,
     чем закрыт КРУГ. Проход даёт факт по вызову только из постусловий,
     закрытых на ПРОШЛЫХ проходах; первый проход идёт с пустым списком, то есть
     ровно так, как ядро работало до этого хода. Пока проход закрывает хоть одно
     новое утверждение, делается следующий; список доказанного не убывает и
     ограничен числом постусловий, значит проходов конечное число. Порядок
     объявлений на итог не влияет — это и значит «неподвижная точка», а не
     «один проход сверху вниз». */
  const без = постусловия.filter((о) => о.proof === null || о.proof === undefined)
  for (;;) {
    let прибыло = false
    for (const обязательство of без) {
      if (обязательство.discharge !== null && обязательство.discharge !== undefined) continue
      /* Теоремы при утверждении нет. Это не значит, что о нём нечего сказать:
         цель могла быть выведена из того, что автор УЖЕ написал, — из типов в
         подписи функции. Одна попытка одним правилом, без единого перебора; не
         вышло — вердикта нет, и утверждение остаётся сеткой примеров, как
         стояло. */
      const поТипу = поОбъявленномуТипу(обязательство, среда) ?? разборомПоСлучаям(обязательство, среда)
      if (поТипу === null) continue
      обязательство.discharge = поТипу
      среда.доказанные.add(ключФакта(обязательство.of, обязательство.name))
      прибыло = true
    }
    if (!прибыло) break
  }

  for (const обязательство of постусловия) {
    if (обязательство.proof === null || обязательство.proof === undefined) {
      if (обязательство.discharge === null || обязательство.discharge === undefined) continue
      checked.push({
        id: обязательство.id,
        of: обязательство.of,
        name: обязательство.name,
        ...обязательство.discharge,
      })
      continue
    }
    const вердикт = проверитьТерм(обязательство, среда, настройки)
    обязательство.discharge = вердикт
    checked.push({ id: обязательство.id, of: обязательство.of, name: обязательство.name, ...вердикт })
    for (const беда of вердикт.refusals) {
      /* Код называет НЕ «терм отвергнут», а место отказа: индукция, покрытие
         случаев, ветвь разбора или шаг вообще. Инструмент, который читает один
         код на всё, не может отличить «доказательство неверно» от
         «доказательства нет», а различить их обязан — это разные починки. */
      diagnostics.push({
        code: беда.code ?? КОДЫ.step,
        severity: "error",
        message: беда.message,
        span: беда.span,
      })
    }
  }

  /* НАРУЖУ УЕЗЖАЕТ ПРЕЖНЯЯ ТРОЙКА, БЕЗ СПИСКА НЕОПЛАЧЕННЫХ, и это не сокрытие.
     Ответ `checkProofs` сличается с эталоном на flang ПОБАЙТОВО, по всему
     корпусу (`flang/test/self-proofterm.test.mjs`), и новое поле в нём — это
     расхождение на КАЖДОЙ программе, включая те, где предусловий нет вовсе.
     Список неоплаченных — внутренняя связь двух частей ядра, а не часть его
     ответа: его читает правило постусловия вызванного и никто больше. */
  const { неоплаченные: _, ...наружу } = предусловия
  return { version: ЯДРО, checked, diagnostics, preconditions: наружу }
}

