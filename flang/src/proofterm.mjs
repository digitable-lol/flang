/* Среда: что ядро знает о программе                                   */
/* ------------------------------------------------------------------ */

/**
 * Всё, что ядру нужно знать о программе, — собранное один раз и только чтением.
 *
 * Своего графа вызовов и своего вывода типов здесь нет и быть не должно: у
 * программы уже есть и то, и другое, а второй ответ на тот же вопрос расходится
 * с первым молча.
 */
function средаПрограммы(program) {
  const функции = new Map()
  for (const fn of program?.functions ?? []) функции.set(fn.name, fn)
  const суммы = new Map()
  const вариантОт = new Map()
  for (const тип of program?.types ?? []) {
    if (тип?.kind !== "sum") continue
    суммы.set(тип.name, тип)
    for (const вариант of тип.variants ?? []) вариантОт.set(вариант.name, тип.name)
  }
  /* Имена объявленных законов — те, на которые вправе сослаться `по закону`.
     Собираются из объявлений, а не из результатов проверки законов: сослаться
     можно на объявленный закон, а посчитан он или остался допущением — это
     ослабление вердикта, а не запрет ссылки, и решается оно отдельно. */
  const законы = new Set()
  for (const поле of ["monoids", "monads", "isomorphisms", "embeddings", "intersections"]) {
    for (const узел of program?.[поле] ?? []) {
      if (typeof узел?.name === "string") законы.add(узел.name)
    }
  }
  return { program, функции, суммы, вариантОт, законы }
}

