function имяИменованного(тип) {
  if (тип === null || тип === undefined) return null
  if (тип.kind === "named") return тип.name
  return null
}

/** Вариант, которым записано значение примера, или `null`. */
function вариантОбразца(значение) {
  if (значение === null || значение === undefined) return null
  if (typeof значение !== "object") return null
  if (typeof значение.variant === "string") return значение.variant
  return null
}

function найтиПостусловие(среда, имя) {
  for (const fn of среда.функции.values()) {
    for (const постусловие of fn?.postconditions ?? []) {
      if (постусловие.name === имя) return { of: fn.name, постусловие }
    }
  }
  return null
}

/**
 * Вердикт словами — теми же, что в ведомости, и ни одним лишним.
 *
 * Слова «проверено» здесь нет и быть не может: оно и есть то, которое читается
 * двумя способами (`proof.mjs`, «Три слова»).
 */
function словами(сила, шагов, случаев, отказов, индукция = null) {
  const хвост = `${шагов} ${шагом(шагов)}${случаев === 0 ? "" : ` в ${случаев} ${случаем(случаев)}`}`
  if (сила === СИЛА.proved && индукция !== null && индукция !== undefined) {
    /* Пятое слово ведомости берётся отсюда, из данных, а не пересобирается там
       заново: две формулировки одного факта и есть способ их спутать. */
    return (
      `доказано индукцией по «${индукция.type}»: база ${индукция.base} ${случаем_(индукция.base)},`
      + ` шаг при допущении на частях (${индукция.step} ${случаем_(индукция.step)}), ${хвост}`
    )
  }
  if (сила === СИЛА.proved) {
    return `доказано ядром: терм принят, ${хвост}`
  }
  if (сила === СИЛА.grid) {
    return `сетка: терм принят, ${хвост}, но опирается на закон, посчитанный на конечной сетке — это не доказательство`
  }
  return `отвергнуто: ${отказов} ${местом(отказов)} не сведено к названным фактам, ${хвост}`
}

function склонить(сколько, одно, два, много) {
  const сотня = сколько % 100
  if (сотня >= 11 && сотня <= 14) return много
  const единица = сколько % 10
  if (единица === 1) return одно
  if (единица >= 2 && единица <= 4) return два
  return много
}

const шагом = (сколько) => склонить(сколько, "шаг", "шага", "шагов")
const случаем = (сколько) => склонить(сколько, "случае", "случаях", "случаях")
const случаем_ = (сколько) => склонить(сколько, "случай", "случая", "случаев")
const местом = (сколько) => склонить(сколько, "место", "места", "мест")
