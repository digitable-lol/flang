/**
 * proofterm.mjs — ядро: проверяльщик термов доказательства.
 *
 * ── Что здесь есть и чего здесь нет ─────────────────────────────────────────
 * Здесь есть ровно одно: свёртка по конечному дереву терма, которая на каждом
 * шаге спрашивает «выведено ли это из уже известного НАЗВАННЫМ правилом» и
 * отвечает да или нет. Здесь НЕТ поиска — ни перебора правил, ни подбора
 * подстановки, ни решателя. Это не экономия и не отсрочка: поиск и есть то,
 * из-за чего проверяльщику нельзя доверять, не прочитав его целиком, а прочитать
 * целиком можно только маленький.
 *
 * Отсюда главное свойство, ради которого ядро своё, а не чужое: проверяльщик —
 * структурная свёртка по конечному дереву, то есть идеальная тотальная программа
 * flang. Он обязан проходить наш собственный анализ завершаемости и печататься во
 * все восемь целей. Близнец на flang лежит в `flang/proof/kernel.flang`, и что он
 * тотален — показано прогоном `flang check`, а не рассуждением.
 *
 * ── Откуда взята конструкция ────────────────────────────────────────────────
 * Индукция — не новое понятие языка, а следствие уже объявленного: индуктивный
 * тип есть НАЧАЛЬНАЯ АЛГЕБРА, и её универсальное свойство даёт сразу и свёртку
 * (она в языке есть с самого начала), и принцип индукции (которого не было).
 * Поэтому принцип здесь не выдуман: он ЧИТАЕТСЯ с объявления суммы — случаев
 * ровно столько, сколько конструкторов, и в рекурсивном случае доступно
 * предположение о части значения. Механизм подсмотрен у `datatype`-пакета
 * Isabelle (BSD): там принцип индукции тоже порождается из универсального
 * свойства, а не постулируется. Подсмотрен МЕХАНИЗМ, не код: код там на ML и
 * завязан на контексты и пространства имён Isabelle, а наши программы — не термы
 * HOL, и переносить Pure значило бы вместо ядра получить задачу погружения
 * семантики flang в HOL.
 *
 * Поверхность — Isar, и по той же причине: она придумана ради читаемости и уже
 * себя доказала. Тактик нет и не будет (`parser.mjs`, `parseTheorem`).
 *
 * ── Четыре правила, и каждое решает вопрос БЕЗ поиска ────────────────────────
 *   ПО ПРИМЕРУ        Утверждение ЗАКРЫТО (свободных имён не осталось) и
 *                     вычисляется интерпретатором в `да`. Решается вычислением,
 *                     а не выводом: закрытый терм — это значение, и спорить о
 *                     нём не о чем. Пример при этом обязан быть образцом ЭТОГО
 *                     случая, иначе ссылка говорила бы о другом значении.
 *   ПО ПРЕДПОЛОЖЕНИЮ  ШАГ ИНДУКЦИИ. Допущение — это цель, в которой переменная
 *                     индукции заменена на ЧАСТЬ значения, связанную образцом
 *                     случая; подстановка не подбирается, часть названа образцом.
 *                     Правило не «объявляет допущение известным», а обязано
 *                     СВЕСТИ к нему заключение посылки двумя названными
 *                     правилами (`flang/proof/reduce.mjs`). Не свелось — шаг не
 *                     выведен, и отказ называет, какое правило не прошло.
 *   ПО СВОЙСТВУ       Утверждение — синтаксический образец названного
 *                     постусловия под подстановкой, которую ядро СЧИТЫВАЕТ
 *                     сличением, а не ищет. Ссылка на доказываемое сейчас
 *                     постусловие отвергается: это круг, и `по предположению`
 *                     существует именно затем, чтобы круга не было.
 *   ПО ЗАКОНУ         То же, но факт приходит от закона моноида, монады или
 *                     изоморфизма. И вот здесь ядро обязано сказать неприятное:
 *                     эти законы посчитаны на КОНЕЧНОЙ СЕТКЕ автора, а не
 *                     доказаны. Доказательство, опирающееся на закон, не может
 *                     быть сильнее того, на что оно опирается, поэтому такой
 *                     терм принимается, но помечается сеткой — и ведомость
 *                     обязана сказать «сетка», а не «доказано». Это не
 *                     придирка: ровно так теряется вся разница между
 *                     доказанным и посчитанным, если о ней промолчать один раз.
 *
 * ── Граница честности: что ядро НЕ умеет ────────────────────────────────────
 * Аксиом у ядра ноль, и список `АКСИОМЫ` по-прежнему пуст. Шаг «из «высота от х
 * не меньше 0» следует «высота от х плюс 1 не меньше 0»» выводится теперь не
 * аксиомой, а ПРАВИЛОМ СВЕДЕНИЯ — доказанной теоремой о IEEE-754 (см. `АКСИОМЫ`
 * ниже и `flang/proof/reduce.mjs`). Правил два, список закрыт, и всё, что под них
 * не подошло, ОТВЕРГАЕТСЯ с указанием, какое правило не прошло и что известно.
 * Отвергается, а не принимается молча, и это главное: ядро, которое в непонятном
 * месте говорит «ладно», не проверяет ничего.
 *
 * Ближайшая оставшаяся граница названа прямо: посылка, у которой связаны имена
 * НЕрекурсивных полей (`вариант «Есть» содержит значение: «А»`). Допущения там
 * нет — поле не типа самой суммы, — а примером случай не закрыть: имя связано,
 * значений бесконечно много. Закроет её упрощатель, а не индукция, и вместе с
 * ней — законы монады и изоморфизма, стоящие сегодня сеткой.
 */

