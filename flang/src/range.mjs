/**
 * range.mjs — интервальный анализ целых значений flang.
 *
 * ── Что это и зачем ────────────────────────────────────────────────────────
 *
 * У языка появилось уточнение числа: `нат` — целое в диапазоне [0, 2⁵³−1],
 * `целое` — целое в [−(2⁵³−1), 2⁵³−1]. Это НЕ новый вид значения: значения
 * остаются теми же IEEE-754 double (SPEC, раздел 2), поэтому ни один из восьми
 * эмиттеров, ни самоприменение, ни побайтовая сверка печати уточнения не видят
 * вовсе. Видит его один типизатор.
 *
 * Уточнение стоит ровно столько, сколько стоит вопрос «а точно ли значение,
 * которое сюда приехало, лежит в этом диапазоне». Ответить на него можно двумя
 * способами, и они не равноценны:
 *
 *   ПРОВЕРКОЙ В РАНТАЙМЕ. Каждое место, где `нат` производится, проверяет
 *   диапазон. В корпусе сложений 209 и умножений 33 — это 242 новых проверки
 *   против 14 сторожей, которые стоят там сегодня. Уточнение, введённое так,
 *   ухудшает картину, а не улучшает: обещание «завершится либо честно
 *   откажет» становится дороже ровно там, где его хотели сделать дешевле.
 *
 *   СТАТИЧЕСКИМ ВЫВОДОМ. Там, где границу значения видно из программы, её
 *   выводит анализ, и проверка не нужна вовсе: не потому, что её отменили, а
 *   потому, что доказано. Там, где не видно, уточнение просто НЕ ПОЛУЧАЕТСЯ —
 *   тип выражения остаётся `число`, и отказ приходит на этапе проверки типов,
 *   до всякого запуска.
 *
 * Взят второй, и отсюда главное свойство этого файла: он не добавляет ни одной
 * проверки в рантайм. Ни одной. Сумма двух `нат` — это `число`, а не «`нат` со
 * сторожем»: 2⁵³−1 плюс 2⁵³−1 из диапазона выходит, и молчать об этом нельзя,
 * а стеречь — незачем, когда можно сказать.
 *
 * ── Что такое интервал здесь ───────────────────────────────────────────────
 *
 * Интервал — это `{ min, max }` и ОДНОВРЕМЕННО обещание целости: значение есть
 * точное целое число и лежит в [min, max] ⊆ [−ТОЧНО, ТОЧНО]. Дробного
 * интервала в этом файле не существует, и это не упрощение, а точная граница
 * полезности: обе половины уточнения (`нат`, `целое`) говорят о целых, и
 * доказательство, которому интервал служит — «шаг постоянного размера
 * действительно меняет число», — верно ровно для целых внутри мантиссы.
 *
 * `null` означает «сказать нечего», и это тип `число`. Три состояния —
 * `нат`, `целое`, «нечего» — тем самым не три отдельных сущности, а три
 * положения одного интервала, и подтипизация `нат` ≤ `целое` ≤ `число`
 * получается вложением интервалов, а не таблицей отношений.
 *
 * ── Откуда берутся интервалы ───────────────────────────────────────────────
 *
 * Источников три, и все три — уже написанный корпус, а не будущий:
 *
 *   1. ОБЪЯВЛЕНИЕ. `принимает н: нат` — интервал параметра [0, ТОЧНО].
 *   2. ЛИТЕРАЛ. В корпусе 1140 целых литералов. `н минус 1` умеет убывать
 *      только потому, что про `1` известно всё.
 *   3. ГРАНИЦА В `если`. `если н не больше 0 … иначе` даёт в ветви `иначе`
 *      н ≥ 1 — и ровно это превращает `н минус 1` из `целого` в `нат`.
 *
 * Четвёртого источника нет намеренно: интервал НЕ выводится по циклу (fixpoint
 * по накопителю свёртки, по рекурсивному параметру). Незачем — параметр и так
 * объявлен, а объявленное точнее выведенного. Накопитель свёртки поэтому
 * уточнения не получает вовсе (`шире` в `types.mjs`): вывод по нему
 * потребовал бы второго прохода, а второй проход — это второй ответ на тот же
 * вопрос, который однажды разойдётся с первым.
 *
 * ── Почему граница ровно 2⁵³−1 ─────────────────────────────────────────────
 *
 * Она измерена, а не выбрана. `x минус 1` впервые не меняет x на 2⁵⁴; при
 * |x| ≤ 2⁵³ соседние целые различимы, и убывание на единицу — теорема, а не
 * надежда. 2⁵³−1 — последнее целое, для которого это верно вместе с
 * представимостью самого значения (`Number.MAX_SAFE_INTEGER`).
 *
 * ── Чего здесь нет ─────────────────────────────────────────────────────────
 *
 * Нет деления: `делить` целого не даёт (16 мест в корпусе, из них 6 уже
 * написаны как целочисленное деление руками — им нужен оператор, которого в
 * языке пока нет). Нет процента — `X процентов от Y` это `X · Y / 100`. Нет
 * вывода по нескольким витками цикла. Всё это оставляет тип `число`, то есть
 * отказывает в уточнении, а не выдумывает его.
 */

/**
 * Наибольшее целое, для которого IEEE-754 double различает соседей.
 *
 * Названо здесь и только здесь: `types.mjs` и `totality.mjs` берут его отсюда,
 * потому что число это одно и то же — граница уточнения и граница, на которой
 * держится доказательство убывания. Разойдись они хоть на единицу, тип обещал
 * бы одно, а анализ завершаемости доказывал другое.
 */
export const ТОЧНО = 9007199254740991

/** Уточнения, которые можно объявить. Порядок — от узкого к широкому. */
export const УТОЧНЕНИЯ = Object.freeze({
  natural: Object.freeze({ min: 0, max: ТОЧНО }),
  integer: Object.freeze({ min: -ТОЧНО, max: ТОЧНО }),
})

/** Слово языка для объявленного уточнения — для печати типа в диагностике. */
export const СЛОВО = Object.freeze({ natural: "нат", integer: "целое" })

/**
 * Интервал по объявленному уточнению или `null`.
 *
 * Читает то самое поле `refine`, которое кладёт парсер (`SCALAR_TYPES`), и
 * ничего больше: уточнение — это ОДНО слово в объявлении, а не вывод.
 */
export function уточнение(refine) {
  return УТОЧНЕНИЯ[refine] ?? null
}

/**
 * Интервал числового типа: `{min, max}` или `null`.
 *
 * Не число — `null`, и это не то же самое, что «число без границ»: у списка
 * границ нет и быть не может, а у `числа` их нет потому, что про него ничего
 * не обещано. Различать их здесь незачем — оба означают «уточнения нет».
 */
export function интервалТипа(type) {
  if (!type || type.kind !== "number") return null
  if (typeof type.min !== "number" || typeof type.max !== "number") return null
  return { min: type.min, max: type.max }
}

/**
 * Интервал целого литерала или `null`.
 *
 * Целость и конечность проверяются вместе: `Number.isInteger` ложен и для NaN,
 * и для ±∞, поэтому отдельной проверки на конечность не нужно. Граница
 * `ТОЧНО` обязательна: `1e300` — целое по `Number.isInteger`, но соседей у
 * него нет, и обещать про него нечего.
 */
export function интервалЛитерала(value) {
  if (typeof value !== "number" || !Number.isInteger(value)) return null
  if (value < -ТОЧНО || value > ТОЧНО) return null
  return { min: value, max: value }
}

/**
 * Интервал, приведённый к обещанию: пусто, если он вышел за точную область.
 *
 * Один вход и один выход у каждого сложения, вычитания и сужения: пока
 * приведение стоит в одном месте, «за границей мантиссы обещания нет» —
 * одно правило, а не семь похожих.
 */
export function свести(min, max) {
  if (typeof min !== "number" || typeof max !== "number") return null
  if (!Number.isInteger(min) || !Number.isInteger(max)) return null
  if (min > max) return null
  if (min < -ТОЧНО || max > ТОЧНО) return null
  return { min, max }
}

/**
 * Вложен ли интервал значения в интервал объявления.
 *
 * Это и есть подтипизация чисел, целиком: `нат` ≤ `целое` — потому что
 * [0, ТОЧНО] ⊆ [−ТОЧНО, ТОЧНО]; `целое` ≤ `число` — потому что у `числа`
 * интервала нет и требовать нечего. Отдельной таблицы отношений поэтому не
 * существует, и разойтись ей не с чем.
 *
 * @param {{min:number,max:number}|null} значение интервал пришедшего значения
 * @param {{min:number,max:number}|null} объявлено интервал объявленного типа
 */
export function вместимо(значение, объявлено) {
  if (объявлено === null) return true
  if (значение === null) return false
  return значение.min >= объявлено.min && значение.max <= объявлено.max
}

/** Объединение ветвей: самое слабое обещание из двух. Пусто у любой — пусто. */
export function объединить(левый, правый) {
  if (левый === null || правый === null) return null
  return свести(Math.min(левый.min, правый.min), Math.max(левый.max, правый.max))
}

/** Общая часть: обе границы сразу. Нужна сужению в ветви `если`. */
export function пересечь(левый, правый) {
  if (левый === null) return правый
  if (правый === null) return левый
  return свести(Math.max(левый.min, правый.min), Math.min(левый.max, правый.max))
}

/**
 * Интервал результата арифметики.
 *
 * Умножение перебирает четыре произведения границ, а не берёт `min·min` и
 * `max·max`: у отрицательных границ порядок переворачивается, и на
 * [−3, 2] · [−3, 2] «наивная» формула дала бы [9, 4] — интервал наизнанку.
 *
 * Деление отсутствует намеренно (шапка файла). Остаток есть, но только при
 * делителе, который заведомо не ноль: `x остаток от 0` даёт NaN, а NaN не
 * целое, и обещать про него нечего.
 */
export function арифметика(op, левый, правый) {
  if (левый === null || правый === null) return null
  switch (op) {
    case "add": return свести(левый.min + правый.min, левый.max + правый.max)
    case "sub": return свести(левый.min - правый.max, левый.max - правый.min)
    case "mul": {
      const углы = [
        левый.min * правый.min, левый.min * правый.max,
        левый.max * правый.min, левый.max * правый.max,
      ]
      return свести(Math.min(...углы), Math.max(...углы))
    }
    case "mod": {
      /* Остаток в flang — знака ДЕЛИМОГО (`%` в JavaScript, и так же во всех
         восьми целях), поэтому диапазон считается от делимого, а не по модулю. */
      if (правый.min <= 0 && правый.max >= 0) return null
      const модуль = Math.max(Math.abs(правый.min), Math.abs(правый.max)) - 1
      const низ = левый.min >= 0 ? 0 : -модуль
      const верх = левый.max <= 0 ? 0 : модуль
      return свести(низ, верх)
    }
    default: return null
  }
}

/** Обратное сравнение: чем становится условие в ветви `иначе`. */
const ОБРАТНО = Object.freeze({ gt: "lte", gte: "lt", lt: "gte", lte: "gt", eq: null, neq: "eq" })

/**
 * Что условие `если` говорит о значении в одной из ветвей.
 *
 * Возвращает список правок `{ имя, интервал }`: имя видимой переменной и
 * интервал, до которого её можно сузить внутри ветви. Пустой список — условие
 * ничего не сказало, и это обычное дело.
 *
 * ── Почему именно так, а не решателем ──────────────────────────────────────
 *
 * Сужается ТОЛЬКО имя, сравнённое с тем, чей интервал уже известен. Не
 * `н минус 1 больше 0` — хотя оно и означает `н > 1`: перенос через сдвиг верен
 * для вещественных чисел, а сравнивает программа double, и у большого сдвига
 * между `fl(н + сдвиг) > K` и `н > K − сдвиг` помещается половина ulp. Ровно то
 * же решение и по той же причине принято в `totality.mjs` (`lowerBoundGuard`):
 * строгость границы берётся там, где округлять нечего.
 *
 * Логика `и притом`/`или`/`не` разворачивается парсером в `если`, поэтому
 * сужение по ней возможно и стоит две ветки: конъюнкция — это `если А то Б
 * иначе нет`, и в ветви `то` верны ОБА условия. Дизъюнкция (`если А то да
 * иначе Б`) в ветви `иначе` тоже даёт оба отрицания. Больше ничего: вложенная
 * логика произвольной формы — это решатель, а его у языка нет.
 *
 * @param {object} cond узел условия
 * @param {"then"|"else"} ветвь
 * @param {(node:object)=>({min:number,max:number}|null)} интервалУзла
 *   интервал произвольного выражения — считает вызывающий, он один знает
 *   область видимости
 * @param {(node:object)=>(string|null)} имяУзла имя, если узел — просто имя
 * @returns {{имя: string, интервал: {min:number,max:number}, устанавливает: boolean}[]}
 *   `устанавливает` — сравнение доказало целость само, без прежнего интервала
 */
export function сужение(cond, ветвь, интервалУзла, имяУзла) {
  if (!cond || typeof cond !== "object") return []
  if (cond.kind === "binary") return сравнением(cond, ветвь, интервалУзла, имяУзла)
  if (cond.kind !== "if") return []
  /* Конъюнкция и дизъюнкция, как их развернул парсер. Отрицание (`если А то нет
     иначе да`) сюда попадает тем же путём: ветви у него постоянные, и правку
     даёт та из них, которая осталась. */
  const тоЛитерал = литерал(cond.then)
  const иначеЛитерал = литерал(cond.else)
  if (иначеЛитерал === false && ветвь === "then") {
    return [
      ...сужение(cond.cond, "then", интервалУзла, имяУзла),
      ...сужение(cond.then, "then", интервалУзла, имяУзла),
    ]
  }
  if (тоЛитерал === true && ветвь === "else") {
    return [
      ...сужение(cond.cond, "else", интервалУзла, имяУзла),
      ...сужение(cond.else, "else", интервалУзла, имяУзла),
    ]
  }
  if (тоЛитерал === false && иначеЛитерал === true) {
    return сужение(cond.cond, ветвь === "then" ? "else" : "then", интервалУзла, имяУзла)
  }
  return []
}

function литерал(node) {
  return node && typeof node === "object" && node.kind === "literal" ? node.value : undefined
}

function сравнением(cond, ветвь, интервалУзла, имяУзла) {
  const op = ветвь === "then" ? cond.op : ОБРАТНО[cond.op]
  if (op === null || op === undefined) return []
  const правки = []
  /* Обе стороны, потому что обе законны: `если н больше 0` и `если 0 меньше н`
     — одно и то же условие, и уточнение не вправе зависеть от порядка слов. */
  добавить(правки, имяУзла(cond.left), op, интервалУзла(cond.right))
  добавить(правки, имяУзла(cond.right), ЗЕРКАЛО[op], интервалУзла(cond.left))
  return правки
}

/** Тот же оператор, прочитанный с другой стороны: `а < б` это `б > а`. */
const ЗЕРКАЛО = Object.freeze({ gt: "lt", gte: "lte", lt: "gt", lte: "gte", eq: "eq", neq: "neq" })

function добавить(правки, имя, op, граница) {
  if (имя === null || граница === null) return
  const интервал = отСравнения(op, граница)
  /* `равно` не сужает интервал, а СОЗДАЁТ его: `если х равно 7` доказывает, что
     х есть ровно 7, то есть целое, даже если до этого места про х не было
     известно ничего. Все прочие сравнения так не умеют — `х не больше 7`
     оставляет 4.5 законным значением, — поэтому различие названо полем, а не
     выведено из формы: вызывающему надо знать, вправе ли он поверить в целость
     там, где её раньше не было. */
  if (интервал !== null) правки.push({ имя, интервал, устанавливает: op === "eq" })
}

/**
 * Интервал, следующий из «имя op граница».
 *
 * Строгое сравнение сдвигает границу на единицу, и это законно ровно потому,
 * что интервал здесь — обещание ЦЕЛОСТИ: между целыми `н > 3` и `н ≥ 4` нет
 * разницы. Для дробных значений интервала не существует вовсе (шапка файла),
 * поэтому и случая, в котором этот сдвиг был бы неверен, не существует.
 */
function отСравнения(op, граница) {
  switch (op) {
    case "gt": return свести(граница.min + 1, ТОЧНО)
    case "gte": return свести(граница.min, ТОЧНО)
    case "lt": return свести(-ТОЧНО, граница.max - 1)
    case "lte": return свести(-ТОЧНО, граница.max)
    case "eq": return свести(граница.min, граница.max)
    default: return null
  }
}

/**
 * Держит ли объявленный тип значение в точной области.
 *
 * Спрашивает `totality.mjs`, и спрашивает про ОБЪЯВЛЕННЫЙ тип из AST, а не про
 * выведенный: анализ завершаемости типов не читает и читать не должен (там нет
 * ни таблицы сигнатур, ни развёртки псевдонимов). Одно поле `refine` на узле
 * параметра — это ровно то, что парсер написал по слову автора, и большего
 * доказательству не нужно: `нат` и `целое` оба держат значение внутри
 * [−ТОЧНО, ТОЧНО], а внутри неё постоянный целый шаг меняет число НАВЕРНОЕ.
 *
 * Псевдоним (`тип «Счётчик» это нат`) сюда не доходит, и это осознанный
 * консерватизм, а не дыра: не доказали — значит остался сторож, то есть
 * ровно то, что было до этой работы.
 */
export function точныйТип(node) {
  if (!node || typeof node !== "object") return false
  if (node.kind !== "number") return false
  return node.refine === "natural" || node.refine === "integer"
}
