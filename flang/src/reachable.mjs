/**
 * Достижимость от точки входа: что печатать, а что выбросить.
 *
 * ── Улика ───────────────────────────────────────────────────────────────────
 * `использует «Списки» из "…/lists.flang"` тянет ВЕСЬ модуль. Связывание так и
 * задумано — «импорт это слияние объявлений» (`link.mjs`), — но печать
 * принимала слияние за программу. Мерено на `flang/examples/import-check.flang`
 * (один вызов «Сумма» из модуля в 698 строк): после связывания 29 функций, из
 * них вызывается 2, а 27 не вызываются никогда. В C это 1670 строк и 74 394
 * байта модуля программы, из которых мёртвых 1496 строк и 65 951 байт — 88.7 %.
 * В JavaScript 1121 строка и 36 525 байт, мёртвых 961 строка и 30 557 байт —
 * 83.7 %. Мёртвое не просто занимает место: оно компилируется, попадает в
 * бинарник и в вызов по имени, то есть обещает пользователю функции, которых он
 * не писал.
 *
 * ── Почему это не дело бэкенда ──────────────────────────────────────────────
 * Бэкенду отличить своё от привезённого НЕЧЕМ: связывание кладёт функции всех
 * модулей в один плоский список и происхождения в AST не оставляет — намеренно,
 * см. «Имя файла в местах разобранного модуля» в `link.mjs`. Знает, какой файл
 * был входом, только загрузчик, поэтому проход стоит на переднем крае и зовётся
 * один раз на все восемь целей — ровно там же и по той же причине, по какой там
 * стоит отметка меры (`markMeasure` в `bin/flang.mjs`).
 *
 * ── Достижимость здесь не равна «упомянуто в тексте» ────────────────────────
 * Три места, где наивный обход вызовов ошибётся:
 *
 * 1. ФУНКЦИЯ-ЗНАЧЕНИЕ. `отобразить список как ф → …` и `функция «Удвоить»`
 *    приезжают узлом `fnref`, а не `call`. Пропусти его — и понижение
 *    (`defunc.mjs`) построило бы диспетчер на функцию, которой в программе уже
 *    нет, то есть несобираемый C.
 * 2. ОБРАБОТЧИК ПРОЦЕССА И ШАГ ПЛАНА. Процесс объявляется ДАННЫМИ, и имя
 *    функции стоит в нём строкой (`handler`), а не узлом вызова. Ищи только
 *    вызовы — и надзор остался бы без обработчика.
 * 3. МЕРА И ПОСТУСЛОВИЕ. `убывает …` и `обеспечивает …` — не тело, но именно из
 *    них анализ строит сторожа времени работы, и выражения меры уезжают в
 *    напечатанный код отметкой на узле вызова (`markGuards` в `totality.mjs`).
 *    Поэтому обход идёт по ВСЕМУ узлу функции, а не по её телу.
 *
 * 4. ПРИМЕР. Печать примеров не печатает ни в одной из восьми целей, и первой
 *    мыслью было их не обходить. Мысль неверная: понижение читает и примеры.
 *    `дано ф равно функция «Сложить»` — это `fnref`, а `fnref` понижение
 *    превращает в ТЕГ и требует, чтобы функция была объявлена, иначе бросает
 *    `FLANG_UNKNOWN_NAME` (`tagValue` в `defunc.mjs`). Выброси функцию, которую
 *    называет только пример, — и печать не просто обеднеет, она откажет.
 *    Ровно так устроен `stdlib/higher-order.flang`: все его функции-значения
 *    стоят в примерах. Цена обхода примеров мерена по всему корпусу и равна
 *    нулю: ни одной лишней функции ни в одном из десяти файлов, где вообще есть
 *    что отбрасывать.
 *
 * ── Что считается точкой входа ──────────────────────────────────────────────
 * Функции ВХОДНОГО файла — то, что человек написал и попросил напечатать, — и
 * всё, что программа называет вне списка функций: обработчики процессов, шаги
 * планов, вызовы из теорем, законов и объявлений теорката. Плюс имена из
 * `экспортирует` входного модуля: это объявленная поверхность программы, и она
 * даёт способ оставить перепечатанное чужое имя, не заводя ключа командной
 * строки.
 *
 * ── Тождество там, где отбрасывать нечего ───────────────────────────────────
 * Если живы все, возвращается ТОТ ЖЕ объект программы. Это не оптимизация:
 * программа без импортов обязана печататься побайтово прежней, иначе побайтовая
 * сверка близнецов и точка раскрутки `bootstrap/` разошлись бы на первом же
 * файле корпуса.
 */

/** Узлы, чьё поле `name` — имя функции. */
const ИМЕНУЕТ_ФУНКЦИЮ = new Set(["call", "fnref"])

/**
 * Поля, в которые обход не заходит.
 *
 * Ровно одно, и это `span`: место не называет ни одной функции, а лежит на
 * каждом узле дерева. Всё остальное обходится, включая примеры — см. пункт 4 в
 * шапке файла.
 */
const НЕ_ОБХОДИТЬ = new Set(["span"])

/**
 * Имена функций, названные внутри узла.
 *
 * Обход итеративный, а не рекурсивный, по той же причине, по какой итеративен
 * `stampFile` в `link.mjs`: AST `core/parser.flang` глубже, чем стек по
 * умолчанию, и рекурсия здесь однажды упала бы не на своём файле.
 */
function собрать(корень, куда) {
  const виден = new Set()
  const стек = [корень]
  while (стек.length > 0) {
    const узел = стек.pop()
    if (узел === null || typeof узел !== "object" || виден.has(узел)) continue
    виден.add(узел)
    if (Array.isArray(узел)) {
      for (const элемент of узел) стек.push(элемент)
      continue
    }
    if (ИМЕНУЕТ_ФУНКЦИЮ.has(узел.kind) && typeof узел.name === "string") куда.add(узел.name)
    /* Обработчик процесса и шаг плана: имя функции строкой. Поле называется
       одинаково у обоих (`parseProcess` и `parsePlan` в parser.mjs), поэтому
       правило одно на два объявления. */
    if (typeof узел.handler === "string") куда.add(узел.handler)
    for (const [поле, значение] of Object.entries(узел)) {
      if (НЕ_ОБХОДИТЬ.has(поле)) continue
      стек.push(значение)
    }
  }
  return куда
}

/** Имена из `экспортирует` входного модуля — объявленная поверхность программы. */
function объявленаПоверхность(программа) {
  const шапка = (программа?.legacy ?? []).find((узел) => узел?.construct === "moduleHeader")
  const имена = шапка?.value?.exports
  return Array.isArray(имена) ? имена : []
}

/**
 * Точки входа программы: функции входного файла плюс всё, что названо вне
 * списка функций.
 *
 * @param {object} программа связанная программа
 * @param {Iterable<string>} свои имена функций, объявленных во входном файле
 * @returns {Set<string>}
 */
export function entryPoints(программа, свои) {
  const корни = new Set(свои ?? [])
  for (const имя of объявленаПоверхность(программа)) корни.add(имя)
  /* Всё, кроме самих функций: процессы, надзор, прогоны, планы, теоремы,
     объявления теорката и наследие FTS. Имя, названное там, — вход: тела, из
     которого до него можно было бы дойти, у этих объявлений нет. Список полей
     не перечисляется: он растёт с языком, и забытое поле означало бы молча
     выброшенную функцию — а это ровно та беда, от которой файл написан. */
  for (const [поле, значение] of Object.entries(программа ?? {})) {
    if (поле === "functions") continue
    собрать(значение, корни)
  }
  return корни
}

/**
 * Замыкание точек входа по вызовам.
 *
 * @param {object} программа связанная программа
 * @param {Iterable<string>} свои имена функций входного файла
 * @returns {Set<string>} имена ОБЪЯВЛЕННЫХ функций, до которых можно дойти
 */
export function reachableFunctions(программа, свои) {
  const функции = new Map()
  for (const функция of программа?.functions ?? []) {
    if (функция !== null && typeof функция === "object" && typeof функция.name === "string") {
      функции.set(функция.name, функция)
    }
  }
  const живые = new Set()
  const очередь = [...entryPoints(программа, свои)]
  while (очередь.length > 0) {
    const имя = очередь.pop()
    /* Имени может не быть среди объявленных: встроенные формы (`длина`,
       `голова`) приходят теми же узлами вызова, и это не ошибка. */
    if (живые.has(имя) || !функции.has(имя)) continue
    живые.add(имя)
    for (const сосед of собрать(функции.get(имя), new Set())) {
      if (!живые.has(сосед)) очередь.push(сосед)
    }
  }
  return живые
}

/**
 * Программа без функций, до которых от точки входа не дойти.
 *
 * @param {object} программа связанная программа
 * @param {Iterable<string>|null} свои имена функций входного файла; `null` —
 *   входного файла нет (стандартный ввод, готовый AST, модель FTS) или связывания
 *   не было, и тогда отбрасывать нечего: программа возвращается как есть.
 * @returns {object} та же программа, если живы все; иначе копия с урезанным
 *   списком функций (порядок остальных сохраняется).
 */
export function dropUnreachable(программа, свои) {
  if (свои === null || свои === undefined) return программа
  if (программа === null || typeof программа !== "object") return программа
  if (!Array.isArray(программа.functions)) return программа
  const живые = reachableFunctions(программа, свои)
  const оставшиеся = программа.functions.filter((функция) => живые.has(функция?.name))
  if (оставшиеся.length === программа.functions.length) return программа
  return { ...программа, functions: оставшиеся }
}
