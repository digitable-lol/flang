/**
 * repl.mjs — интерактивная оболочка flang: ядро без терминала.
 *
 * ── Почему сессия хранит ИСХОДНИК, а не AST ────────────────────────────────
 * Оболочка накапливает объявления, и каждое следующее выражение обязано видеть
 * все предыдущие. Хранить накопленное как AST соблазнительно (уже разобрано),
 * но тогда сессия перестаёт быть программой: её нельзя ни показать, ни
 * сохранить, ни проверить тем же путём, каким проверяется файл. Поэтому сессия
 * — это текст на flang, а на каждом вводе он пересобирается и проходит ровно
 * ту же дорогу, что `flang check`: parse → checkTypes → checkTotality. Совпадение
 * дорог не оптимизация, а требование: иначе оболочка принимала бы программы,
 * которые компилятор отвергает, и наоборот.
 *
 * ── Как вычисляется выражение ──────────────────────────────────────────────
 * Верхнего уровня «просто выражение» в языке нет: программа — это объявления
 * (SPEC, раздел 5). Заводить для оболочки второй вход в парсер значило бы
 * завести вторую грамматику, которая однажды разойдётся с первой. Поэтому
 * выражение оборачивается в функцию
 *
 *     функция «⟨выражение⟩»
 *       <ввод, сдвинутый на два пробела>
 *
 * дописывается к исходнику сессии и вычисляется вызовом без аргументов.
 * Обёртка намеренно НЕ тотальная: она может вызывать обычные функции, и
 * объявлять её тотальной значило бы обещать завершение, которого никто не
 * доказывал.
 *
 * ── Честность про завершение ───────────────────────────────────────────────
 * Тотальность здесь не «пометка», а результат того же анализа (totality.mjs):
 * объявление с недоказанным убыванием отвергается так же, как в `flang check`.
 * Про обычную функцию оболочка говорит прямо: завершение не доказано, вычисление
 * держится на лимите шагов интерпретатора, и превышение лимита приходит тем же
 * FLANG_RECURSION_LIMIT, что и при обычном запуске, — без подмены текста.
 *
 * ── Команды через точку ────────────────────────────────────────────────────
 * `.помощь`, `.объявления`, `.сохранить` … Точка выбрана не по вкусу: ни одна
 * конструкция flang не может начинаться с точки — числа требуют цифры (лексер,
 * NUMBER), имена начинаются с ID_Start, ключевые слова — со слова. Значит
 * строка с точки заведомо не программа, и оболочке не приходится гадать.
 * Двоеточие такой гарантии не даёт: оно живёт в самой поверхности языка
 * («принимает х: число», «поле: значение»), и команда `:тип` читалась бы как
 * кусок объявления. Английские имена команд работают наравне с русскими —
 * ровно как две поверхности самого языка.
 *
 * Терминала этот модуль не знает: он принимает строку и возвращает результат.
 * Читает и пишет файлы только по команде и только через переданные `readFile`
 * и `writeFile` — иначе оболочку нельзя было бы проверить тестом.
 */

