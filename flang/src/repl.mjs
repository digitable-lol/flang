/**
 * @param {object} options
 *   `base` — каталог, относительно которого читаются пути (по умолчанию рабочий);
 *   `maxSteps`, `maxDepth` — пределы интерпретатора для вычисления выражений;
 *   `readFile`, `writeFile` — доступ к файлам (подменяются в тестах).
 */
export function createSession(options = {}) {
  const с = {
    база: options.base ?? process.cwd(),
    пределы: { maxSteps: options.maxSteps, maxDepth: options.maxDepth },
    чтение: options.readFile ?? ((путь) => прочитатьФайл(путь, "utf8")),
    запись: options.writeFile ?? ((путь, текст) => записатьФайл(путь, текст, "utf8")),
    /* Заголовок модуля хранится разобранным, а не строкой: `использует` пишется
       в разных местах ввода и в загружаемых файлах, а в исходнике сессии он
       обязан быть ровно один и ровно наверху. */
    заголовок: { имя: "", импорты: [], экспорт: [] },
    объявления: [],
    /* Имена функций последней принятой сессии: с ними разбирается ввод, иначе
       вызов функции без аргументов остался бы несвязанным именем. */
    известные: new Set(),
    тотальные: new Set(),
  }

  return {
    submit: (текст) => принять(с, текст),
    needsMore: (текст) => needsMoreInput(текст, с.известные),
    load: (файл) => загрузить(с, файл),
    source: () => собрать(с, null).текст,
    declarations: () => с.объявления.map((о) => ({ names: [...о.имена], label: о.метка, source: о.текст })),
  }
}

/**
 * Приём одного ввода. Возвращает результат одного из видов:
 *   { kind: "empty" }                        — вводить было нечего
 *   { kind: "value", value, text }           — выражение вычислено
 *   { kind: "declared", declared, replaced } — объявления приняты
 *   { kind: "message", text }                — ответ команды
 *   { kind: "diagnostics", diagnostics }     — отказ; сессия не изменилась
 *   { kind: "quit" }                         — конец работы
 */
async function принять(с, исходный) {
  const обрезанный = исходный.trim()
  if (обрезанный === "") return { kind: "empty" }

  try {
    if (обрезанный.startsWith(".")) return await команда(с, обрезанный)
    const ввод = снятьОбщийОтступ(исходный)
    const токены = токенизировать(ввод.текст)
    /* Ввод из одних комментариев — это ничто, а не программа без тела. Ошибку
       лексера (токены === null) сюда не пускаем: её обязан показать разбор. */
    if (токены !== null && !токены.some(значащий)) return { kind: "empty" }
    return вид(ввод.текст) === "объявление" ? await объявить(с, ввод) : await вычислить(с, ввод)
  } catch (ошибка) {
    /* Непредвиденный сбой не имеет права уронить оболочку: сессия остаётся
       прежней, а ошибка показывается как диагностика. */
    return отказ(диагностикиИз(ошибка))
  }
}

/* ────────────────────────────── вычисление ──────────────────────────────── */

async function вычислить(с, ввод) {
  const имя = имяВыражения(с)
  const собранное = await построить(с, с.заголовок, с.объявления, обёртка(ввод, имя))
  if (собранное.diagnostics.length > 0) return отказ(собранное.diagnostics, собранное.карта)

  const проверка = проверить(собранное.программа)
  if (проверка.diagnostics.length > 0) return отказ(проверка.diagnostics, собранное.карта)

  try {
    const значение = createRuntime(собранное.программа, с.пределы).call(имя, {})
    return { kind: "value", value: значение, text: formatValue(значение) }
  } catch (ошибка) {
    /* Лимит шагов приходит сюда обычным FLANG_RECURSION_LIMIT интерпретатора.
       Текст не подменяем: в нём названы функция, лимит и глубина. */
    return отказ(диагностикиИз(ошибка), собранное.карта)
  }
}

/** Имя обёртки, не занятое ничем в сессии: столкнуться можно только нарочно. */
function имяВыражения(с) {
  let имя = ИМЯ_ВЫРАЖЕНИЯ
  while (с.известные.has(имя)) имя += "′"
  return имя
}

/** Ввод как тело функции: каждая непустая строка сдвигается на два пробела. */
function обёртка(ввод, имя) {
  const тело = ввод.текст
    .split("\n")
    .map((строка) => (строка.trim() === "" ? "" : `  ${строка}`))
    .join("\n")
  return {
    вид: "ввод",
    имя: null,
    текст: `функция «${имя}»\n${тело}`,
    сдвигСтрок: 1,
    сдвигСтолбцов: 2 + ввод.отступ,
  }
}

/* ────────────────────────────── объявления ──────────────────────────────── */

async function объявить(с, ввод) {
  const разобрано = разобратьВвод(ввод.текст, с.известные)
  if (разобрано.diagnostics !== undefined) {
    return отказ(разобрано.diagnostics.map((д) => вМесте(д, "ввод", null, разобрано.сдвигСтрок, ввод.отступ)))
  }

  /* Ввод, в котором есть только заголовок модуля, меняет заголовок сессии, а не
     список объявлений: `использует` в исходнике обязан стоять ровно один раз и
     ровно наверху, иначе связывание увидит не тот набор импортов. */
  if (толькоЗаголовок(разобрано.программа)) {
    const прежние = new Set(с.известные)
    const заголовок = слитьЗаголовок(с, разобрано.программа, с.база)
    const принято = await применить(с, заголовок, с.объявления, [])
    if (принято.kind !== "declared") return принято
    /* Импорт сам по себе ничего не объявляет, поэтому докладываем не «объявлено»,
       а что именно стало видно: без этого числа непонятно, подключилось ли хоть
       что-нибудь. */
    const новые = [...с.известные].filter((имя) => !прежние.has(имя))
    const текст = текстЗаголовка(заголовок) ?? ""
    return { kind: "message", text: `${текст}\nстало видно функций: ${новые.length}` }
  }

  const фрагменты = разложить(ввод.текст, разобрано.программа)
  const слияние = заменить(с.объявления, фрагменты)
  if (слияние.ошибка !== undefined) return отказ([диагностика(слияние.ошибка)])
  const имена = фрагменты.flatMap((ф) => ф.имена)
  /* Только что набранное помечается как «ввод»: ошибка в нём обязана указывать
     строку ввода, а не строку объявления, о котором пользователь ещё не думает
     как об отдельной части сессии. */
  return применить(с, с.заголовок, слияние.объявления, имена, слияние.заменённые, new Set(фрагменты))
}

/**
 * Разбор одного ввода отдельно от сессии.
 *
 * Нужен ровно для двух вещей: узнать, ЧТО объявлено (иначе нечего заменять при
 * переобъявлении), и показать ошибку разбора на строке ввода, а не на строке
 * собранной сессии. `использует` и `экспортирует` без заголовка модуля —
 * синтаксическая ошибка, поэтому для них заголовок подставляется, а сдвиг строк
 * возвращается вызывающему.
 */
function разобратьВвод(текст, известные) {
  const первый = первыйЗначащий(текст)
  const нуженЗаголовок = первый?.kind === "keyword" && (первый.value === "uses" || первый.value === "exports")
  const источник = нуженЗаголовок ? `модуль «${ИМЯ_СЕССИИ}»\n${текст}` : текст
  try {
    return { программа: parse(источник, ФАЙЛ_СЕССИИ, известные), сдвигСтрок: нуженЗаголовок ? 1 : 0 }
  } catch (ошибка) {
    return { diagnostics: диагностикиИз(ошибка), сдвигСтрок: нуженЗаголовок ? 1 : 0 }
  }
}

function толькоЗаголовок(программа) {
  return (
    (программа.types ?? []).length === 0 &&
    (программа.functions ?? []).length === 0 &&
    (программа.morphisms ?? []).length === 0 &&
    (программа.legacy ?? []).every((узел) => узел.construct === "moduleHeader")
  )
}

/**
 * Слияние заголовка модуля из ввода или загруженного файла с заголовком сессии.
 *
 * Пути импортов пересчитываются относительно каталога сессии: файл, загруженный
 * из другого каталога, ссылается на соседей по-своему, и без пересчёта его
 * `использует` указывал бы в пустоту.
 */
function слитьЗаголовок(с, программа, откуда) {
  const заголовок = {
    имя: с.заголовок.имя,
    импорты: [...с.заголовок.импорты],
    экспорт: [...с.заголовок.экспорт],
  }
  for (const узел of программа.legacy ?? []) {
    if (узел.construct !== "moduleHeader") continue
    if (заголовок.имя === "" && typeof узел.value?.name === "string") заголовок.имя = узел.value.name
    for (const импорт of узел.value?.imports ?? []) {
      const путь = переписатьПуть(импорт.from, откуда, с.база)
      const прежний = заголовок.импорты.findIndex((item) => item.from === путь)
      const запись = { category: импорт.category, from: путь }
      if (Array.isArray(импорт.only)) запись.only = [...импорт.only]
      if (прежний === -1) заголовок.импорты.push(запись)
      else заголовок.импорты[прежний] = запись
    }
    for (const имя of узел.value?.exports ?? []) {
      if (!заголовок.экспорт.includes(имя)) заголовок.экспорт.push(имя)
    }
  }
  return заголовок
}

function переписатьПуть(путь, откуда, база) {
  const полный = resolve(откуда, путь)
  const относительный = relative(база, полный)
  return относительный === "" ? полный : относительный
}

/**
 * Замена прежних объявлений одноимёнными новыми.
 *
 * Переобъявление — не роскошь: в оболочке функцию правят по десять раз, и
 * «функция объявлена дважды» на каждую правку сделала бы её бесполезной. Замена
 * идёт НА МЕСТЕ, чтобы порядок объявлений (а значит, и сохранённый файл)
 * не переставлялся от правки к правке.
 *
 * Один случай отвергается: если прежний фрагмент объявлял несколько имён и
 * переобъявлено из них не всё, замена молча потеряла бы остальные.
 */
function заменить(объявления, новые) {
  const имена = new Set(новые.flatMap((ф) => ф.имена))
  const частичный = объявления.find(
    (о) => о.имена.some((и) => имена.has(и)) && !о.имена.every((и) => имена.has(и)),
  )
  if (частичный !== undefined) {
    return {
      ошибка:
        `${частичный.метка} объявлено вместе с ${частичный.имена.map((и) => `«${и}»`).join(", ")}: ` +
        "переобъявите их одним вводом или начните заново командой «.сбросить»",
    }
  }

  const итог = []
  const заменённые = []
  let вставлено = false
  for (const о of объявления) {
    if (о.имена.some((и) => имена.has(и))) {
      заменённые.push(о.метка)
      if (!вставлено) {
        итог.push(...новые)
        вставлено = true
      }
      continue
    }
    итог.push(о)
  }
  if (!вставлено) итог.push(...новые)
  return { объявления: итог, заменённые }
}

/** Сборка кандидата, проверка и — если чисто — принятие его как новой сессии. */
async function применить(с, заголовок, объявления, имена, заменённые = [], свежие = new Set()) {
  const собранное = await построить(с, заголовок, объявления, null, свежие)
  if (собранное.diagnostics.length > 0) return отказ(собранное.diagnostics, собранное.карта)

  const проверка = проверить(собранное.программа)
  if (проверка.diagnostics.length > 0) return отказ(проверка.diagnostics, собранное.карта)

  с.заголовок = заголовок
  с.объявления = объявления
  с.известные = new Set((собранное.программа.functions ?? []).map((fn) => fn.name))
  с.тотальные = проверка.тотальные

  return {
    kind: "declared",
    declared: описатьОбъявленное(собранное.программа, проверка.тотальные, new Set(имена)),
    replaced: заменённые,
  }
}

/**
 * Что сказать про принятые объявления. Про функцию говорится главное: доказано
 * ли её завершение. «Тотальная» без доказательства не бывает — такое объявление
 * сюда не доходит, его отвергает checkTotality.
 */
function описатьОбъявленное(программа, тотальные, имена) {
  const описания = []
  for (const тип of программа.types ?? []) {
    if (!имена.has(тип.name)) continue
    описания.push({ name: тип.name, label: меткаТипа(тип), total: null })
  }
  for (const fn of программа.functions ?? []) {
    if (!имена.has(fn.name)) continue
    описания.push({
      name: fn.name,
      label: `${fn.total === true ? "тотальная функция" : "функция"} «${fn.name}»`,
      total: fn.total === true && тотальные.has(fn.name),
    })
  }
  for (const узел of программа.morphisms ?? []) {
    if (!имена.has(узел.name)) continue
    описания.push({ name: узел.name, label: `морфизм «${узел.name}»`, total: null })
  }
  for (const узел of программа.legacy ?? []) {
    const имя = узел.value?.name
    if (typeof имя !== "string" || !имена.has(имя)) continue
    описания.push({ name: имя, label: `${НАСЛЕДИЕ.get(узел.construct) ?? узел.construct} «${имя}»`, total: null })
  }
  return описания
}

function меткаТипа(тип) {
  return тип.kind === "record" ? `запись «${тип.name}»` : `тип «${тип.name}»`
}

/* ───────────────────── разложение ввода на объявления ───────────────────── */

/**
 * Ввод режется на отдельные объявления по строкам, с которых они начинаются.
 *
 * Порознь они нужны, чтобы переобъявление меняло одну функцию, а не весь ввод
 * целиком, и чтобы `.объявления` показывал список, а не простыню. Комментарии
 * перед объявлением уходят вместе с ним: в файлах библиотеки они и есть его
 * описание, и терять их при загрузке нельзя.
 *
 * Если разрезать не получается — объявления вложены в `категория «…»`, у узла
 * нет места, кусок начинается с отступа, — ввод остаётся одним фрагментом. Это
 * не отказ: сессия остаётся правильной, просто переобъявлять придётся целиком.
 */
function разложить(текст, программа) {
  const узлы = [
    ...(программа.types ?? []).map((узел) => ({ имя: узел.name, строка: узел.span?.line, метка: меткаТипа(узел) })),
    ...(программа.functions ?? []).map((узел) => ({
      имя: узел.name,
      строка: узел.span?.line,
      метка: `${узел.total === true ? "тотальная функция" : "функция"} «${узел.name}»`,
    })),
    ...(программа.morphisms ?? []).map((узел) => ({
      имя: узел.name,
      строка: узел.span?.line,
      метка: `морфизм «${узел.name}»`,
    })),
    ...(программа.legacy ?? [])
      .filter((узел) => узел.construct !== "moduleHeader")
      .map((узел) => ({
        имя: узел.value?.name,
        строка: узел.span?.line,
        метка: `${НАСЛЕДИЕ.get(узел.construct) ?? узел.construct} «${узел.value?.name ?? "?"}»`,
      })),
  ]
  const всё = [{ имена: узлы.map((у) => у.имя).filter((и) => typeof и === "string"), метка: меткаВсего(узлы), текст }]
  if (узлы.length === 0) return всё
  if (узлы.some((у) => typeof у.строка !== "number" || typeof у.имя !== "string")) return всё

  const строки = текст.split("\n")
  const начала = [...new Set(узлы.map((у) => у.строка))].sort((а, б) => а - б)
  const куски = начала.map((первая, индекс) => ({
    первая,
    последняя: (начала[индекс + 1] ?? строки.length + 1) - 1,
  }))
  /* Хвост куска — комментарии и пустые строки — принадлежит следующему
     объявлению: читатель написал их про него, а не про предыдущее. */
  for (let индекс = 0; индекс + 1 < куски.length; индекс += 1) {
    while (куски[индекс].последняя >= куски[индекс].первая && служебная(строки[куски[индекс].последняя - 1])) {
      куски[индекс].последняя -= 1
      куски[индекс + 1].первая -= 1
    }
  }
  const последний = куски[куски.length - 1]
  while (последний.последняя >= последний.первая && (строки[последний.последняя - 1] ?? "").trim() === "") {
    последний.последняя -= 1
  }
  /* Комментарий перед ПЕРВЫМ объявлением тем же правом принадлежит ему. Назад
     идём только по служебным строкам, поэтому заголовок модуля (он не служебная
     строка) остаётся снаружи и в объявление не заезжает. */
  while (куски[0].первая > 1 && служебная(строки[куски[0].первая - 2])) куски[0].первая -= 1
  for (const кусок of куски) {
    /* Пустые строки в начале куска не несут ничего, кроме лишней пустой строки
       в сохранённом файле. */
    while (кусок.первая < кусок.последняя && (строки[кусок.первая - 1] ?? "").trim() === "") кусок.первая += 1
  }

  const фрагменты = []
  for (const кусок of куски) {
    const свои = узлы.filter((у) => у.строка >= кусок.первая && у.строка <= кусок.последняя)
    const тело = строки.slice(кусок.первая - 1, кусок.последняя).join("\n")
    /* Кусок с отступом в первой строке — часть чужого блока (`категория «…»`):
       отдельным объявлением он не соберётся. */
    if (тело.trim() === "" || /^[ \t]/u.test(тело)) return всё
    фрагменты.push({ имена: свои.map((у) => у.имя), метка: меткаВсего(свои), текст: тело })
  }
  return фрагменты
}

function меткаВсего(узлы) {
  if (узлы.length === 0) return "объявление"
  return узлы.length === 1 ? узлы[0].метка : узлы.map((у) => у.метка).join(", ")
}

function служебная(строка) {
  const обрезанная = (строка ?? "").trim()
  return обрезанная === "" || обрезанная.startsWith("//")
}

/* ──────────────────────── сборка и проверка сессии ──────────────────────── */

/**
 * Исходник сессии + карта строк.
 *
 * Карта нужна, чтобы диагностика показывала строку ВВОДА, а не строку
 * собранного текста: пользователь набрал три строки, и «ошибка в строке 47»
 * ему ничего не говорит.
 */
function собрать(с, хвост, свежие = new Set()) {
  const части = []
  const заголовок = текстЗаголовка(с.заголовок ?? { имя: "", импорты: [], экспорт: [] })
  if (заголовок !== null) части.push({ вид: "модуль", имя: null, текст: заголовок, сдвигСтрок: 0, сдвигСтолбцов: 0 })
  for (const о of с.объявления ?? []) {
    const вид = свежие.has(о) ? "ввод" : "объявление"
    части.push({ вид, имя: о.метка, текст: о.текст, сдвигСтрок: 0, сдвигСтолбцов: 0 })
  }
  if (хвост !== null && хвост !== undefined) части.push(хвост)

  const карта = []
  let строка = 1
  for (const часть of части) {
    const высота = часть.текст.split("\n").length
    карта.push({ ...часть, первая: строка, последняя: строка + высота - 1 })
    /* Между частями ровно одна пустая строка — она же разделитель в файле,
       который пишет «.сохранить». */
    строка += высота + 1
  }
  return { текст: части.length === 0 ? "" : `${части.map((часть) => часть.текст).join("\n\n")}\n`, карта }
}

function текстЗаголовка(заголовок) {
  if (заголовок.импорты.length === 0 && заголовок.экспорт.length === 0 && заголовок.имя === "") return null
  const строки = [`модуль «${заголовок.имя === "" ? ИМЯ_СЕССИИ : заголовок.имя}»`]
  for (const импорт of заголовок.импорты) {
    const выбор = Array.isArray(импорт.only) ? ` только ${импорт.only.map((и) => `«${и}»`).join(", ")}` : ""
    строки.push(`  использует «${импорт.category}» из ${JSON.stringify(импорт.from)}${выбор}`)
  }
  if (заголовок.экспорт.length > 0) {
    строки.push(`  экспортирует ${заголовок.экспорт.map((и) => `«${и}»`).join(", ")}`)
  }
  return строки.join("\n")
}

/** Разбор собранной сессии; со связыванием, если в заголовке есть импорты. */
async function построить(с, заголовок, объявления, хвост, свежие = new Set()) {
  const { текст, карта } = собрать({ заголовок, объявления }, хвост, свежие)
  const разобрано = await разобрать(resolve(с.база, ФАЙЛ_СЕССИИ), текст, с.чтение)
  return разобрано.программа === undefined
    ? { карта, diagnostics: разобрано.diagnostics }
    : { карта, программа: разобрано.программа, diagnostics: разобрано.diagnostics }
}

/**
 * Разбор исходника: сам по себе или со связыванием, если в нём есть импорты.
 *
 * Решает не вызывающий, а сам файл — по `использует` в заголовке. Иначе
 * пришлось бы держать это знание в трёх местах (CLI, оболочка, сервер), и
 * однажды одно из них научилось бы читать модули, а другое нет.
 */
async function разобрать(файл, текст, чтение) {
  let своё
  try {
    своё = parse(текст, файл)
  } catch (ошибка) {
    return { diagnostics: диагностикиИз(ошибка) }
  }
  if (importsOf(своё).length === 0) {
    /* Файл без импортов — единственный случай, где место диагностики очевидно
       и без имени файла. Имя всё равно проставляем: у вызывающего должно быть
       одно правило чтения места, а не два. */
    return { программа: stampFile(своё, файл), diagnostics: [] }
  }
  /* `attributeFiles` — просьба проставить в места имя файла. Просит её тот, кто
     показывает диагностику человеку: без имени файла после связывания «строка
     12» указывает в один из нескольких файлов, и в какой — неизвестно. Печать
     AST этого не просит и потому не меняется (см. `stampFile` в link.mjs). */
  const { diagnostics, ...программа } = await linkProgram(файл, текст, parse, {
    readFile: чтение,
    attributeFiles: true,
  })
  return { программа, diagnostics }
}

/** Та же пара проверок и в том же порядке, что у `flang check`. */
function проверить(программа) {
  const типы = checkTypes(программа)
  const тотальность = checkTotality(программа)
  return {
    diagnostics: [...типы.diagnostics, ...тотальность.diagnostics].filter((д) => д?.severity !== "warning"),
    тотальные: тотальность.total,
    сигнатуры: типы.types,
  }
}

/**
 * Полная дорога проверки одного исходника: разбор (со связыванием) → типы →
 * завершаемость.
 *
 * Ровно та же дорога, какой оболочка проверяет каждый ввод, и ровно та, что у
 * `flang check`. Вынесена сюда не ради красоты: у языкового сервера соблазн
 * завести «свою, побыстрее» дорогу особенно велик — он проверяет текст на
 * каждое нажатие. Разойдись эти дороги, и редактор начал бы подчёркивать
 * зелёным то, что компилятор отвергает; это хуже, чем не подчёркивать вовсе.
 *
 * `readFile` подменяется вызывающим: сервер читает импортируемые модули из
 * открытых буферов, а не с диска, — иначе показывал бы ошибки по сохранённой
 * версии соседнего файла.
 *
 * @returns {{program: object|null, diagnostics: object[], total: Set<string>,
 *            signatures: Map<string, object>}}
 *   `diagnostics` — уже без предупреждений, как в `flang check`; `total` —
 *   имена функций с доказанным завершением; `signatures` — типы параметров и
 *   результата, посчитанные проверкой типов, а не собранные по AST заново.
 */
export async function checkSource(файл, исходник, options = {}) {
  const чтение = options.readFile ?? ((путь) => прочитатьФайл(путь, "utf8"))
  const разобрано = await разобрать(resolve(файл), исходник, чтение)
  /* Не разобралось или не связалось — типы не считаем: по программе с
     недостающим модулем проверка типов выдала бы список несвязанных имён, из
     которого ни одна строка не относится к тому, что человек сейчас сломал. */
  if (разобрано.программа === undefined || разобрано.diagnostics.length > 0) {
    return {
      program: разобрано.программа ?? null,
      diagnostics: разобрано.diagnostics,
      total: new Set(),
      signatures: new Map(),
    }
  }
  const проверка = проверить(разобрано.программа)
  return {
    program: разобрано.программа,
    diagnostics: проверка.diagnostics,
    total: проверка.тотальные,
    signatures: проверка.сигнатуры,
  }
}

/* ──────────────────────────────── команды ───────────────────────────────── */

async function команда(с, строка) {
  const пробел = строка.search(/\s/u)
  const имя = (пробел === -1 ? строка : строка.slice(0, пробел)).toLowerCase()
  const довесок = пробел === -1 ? "" : строка.slice(пробел).trim()

  switch (имя) {
    case ".помощь":
    case ".help":
    case ".?":
      return { kind: "message", text: HELP }
    case ".объявления":
    case ".list":
      return { kind: "message", text: списокОбъявлений(с) }
    case ".исходник":
    case ".source": {
      const текст = собрать(с, null).текст.trimEnd()
      return { kind: "message", text: текст === "" ? "сессия пуста" : текст }
    }
    case ".сохранить":
    case ".save":
      return сохранить(с, довесок)
    case ".загрузить":
    case ".load":
      return загрузить(с, довесок)
    case ".сбросить":
    case ".reset":
      с.заголовок = { имя: "", импорты: [], экспорт: [] }
      с.объявления = []
      с.известные = new Set()
      с.тотальные = new Set()
      return { kind: "message", text: "сессия сброшена: объявлений нет" }
    case ".выход":
    case ".quit":
    case ".exit":
      return { kind: "quit" }
    default:
      return отказ([диагностика(`неизвестная команда «${имя}»; «.помощь» — список команд`)])
  }
}

function списокОбъявлений(с) {
  const строки = []
  const заголовок = текстЗаголовка(с.заголовок)
  if (заголовок !== null) строки.push(заголовок)
  if (с.объявления.length === 0) {
    строки.push("в сессии ничего не объявлено")
    return строки.join("\n")
  }
  с.объявления.forEach((о, индекс) => {
    /* Про завершение говорит не пометка в тексте, а множество доказанных имён:
       пометка «тотальная» без доказательства до сессии не доходит, но и
       полагаться на неё при печати незачем. */
    const про = о.имена.some((имя) => с.тотальные.has(имя))
      ? " — завершение доказано"
      : о.метка.includes("функция")
        ? " — обычная: завершение не доказано"
        : ""
    строки.push(`${индекс + 1}. ${о.метка}${про}`)
  })
  return строки.join("\n")
}

async function сохранить(с, путь) {
  if (путь === "") return отказ([диагностика("«.сохранить» требует путь к файлу")])
  const полный = resolve(с.база, путь)
  /* Пути импортов пересчитываются относительно места файла, а не сессии: иначе
     сохранённая в другой каталог сессия ссылалась бы на модули мимо них, и
     `flang check` на ней падал бы — то есть сохранение врало бы. */
  const каталог = dirname(полный)
  const заголовок = {
    ...с.заголовок,
    импорты: с.заголовок.импорты.map((импорт) => ({ ...импорт, from: переписатьПуть(импорт.from, с.база, каталог) })),
  }
  const текст = собрать({ заголовок, объявления: с.объявления }, null).текст
  if (текст === "") return отказ([диагностика("сохранять нечего: в сессии ничего не объявлено")])
  try {
    await с.запись(полный, текст)
  } catch (ошибка) {
    return отказ([диагностика(`не удалось записать ${полный}: ${сообщение(ошибка)}`)])
  }
  return { kind: "message", text: `сессия записана в ${полный} (объявлений: ${с.объявления.length})` }
}

/**
 * Загрузка файла в сессию.
 *
 * Файл не «подключается», а разбирается на объявления и вливается в сессию —
 * ровно как если бы его набрали руками. Поэтому загруженную функцию можно тут же
 * переобъявить, а `.сохранить` вернёт всё это одним файлом. Подключение без
 * копирования у языка уже есть, и это `использует «Модуль» из "…"`.
 */
async function загрузить(с, путь) {
  if (путь === "") return отказ([диагностика("«.загрузить» требует путь к файлу")])
  const полный = resolve(с.база, путь)
  if (полный.endsWith(".json") || полный.endsWith(".fts")) {
    return отказ([
      диагностика(
        `оболочка загружает исходники flang, а ${полный.endsWith(".json") ? "JSON с готовым AST" : "модель FTS"} — нет; ` +
          "для них есть «flang check» и «flang run»",
      ),
    ])
  }

  let текст
  try {
    текст = await с.чтение(полный)
  } catch (ошибка) {
    return отказ([диагностика(`не удалось прочитать ${полный}: ${сообщение(ошибка)}`)])
  }

  let программа
  try {
    программа = parse(текст, полный, с.известные)
  } catch (ошибка) {
    return отказ(диагностикиИз(ошибка).map((д) => вМесте(д, "файл", путь, 0, 0)))
  }

  const заголовок = слитьЗаголовок(с, программа, dirname(полный))
  const фрагменты = разложить(текст, программа)
  const слияние = заменить(с.объявления, фрагменты)
  if (слияние.ошибка !== undefined) return отказ([диагностика(слияние.ошибка)])

  const имена = фрагменты.flatMap((ф) => ф.имена)
  const результат = await применить(с, заголовок, слияние.объявления, имена, слияние.заменённые)
  if (результат.kind === "declared") результат.from = путь
  return результат
}

/* ──────────────────────────── печать значений ───────────────────────────── */

/**
 * Значение — поверхностью языка: `да`, `нет`, `ничто`, `[1, 2]`, `пустой список`.
 * Это не «украшение вывода»: то же самое пишут бэкенды (`к строке` в emit/js),
 * и печатать в оболочке иначе значило бы учить пользователя второму словарю.
 *
 * Рекурсия здесь — по данным, а не по программе: её глубина ограничена
 * вложенностью самого значения (тот же довод, что у valuesEqual).
 */
export function formatValue(значение) {
  if (значение === null || значение === undefined) return "ничто"
  if (значение === true) return "да"
  if (значение === false) return "нет"
  if (typeof значение === "number") return Object.is(значение, -0) ? "-0" : String(значение)
  if (typeof значение === "string") return JSON.stringify(значение)
  if (isList(значение)) {
    return значение.length === 0 ? "пустой список" : `[${значение.map(formatValue).join(", ")}]`
  }
  if (isVariant(значение)) {
    const поля = Object.entries(значение.fields ?? {})
    return поля.length === 0
      ? значение.variant
      : `${значение.variant}(${поля.map(([имя, поле]) => `${имя}: ${formatValue(поле)}`).join(", ")})`
  }
  if (isRecord(значение)) {
    const поля = Object.entries(значение)
    return поля.length === 0 ? "{}" : `{${поля.map(([имя, поле]) => `${имя}: ${formatValue(поле)}`).join(", ")}}`
  }
  return String(значение)
}

/* ───────────────────────────── печать ответа ────────────────────────────── */

/** Сколько объявлений печатать поимённо, прежде чем перейти к счёту. */
const ПОДРОБНО = 6

/** Результат приёма — текстом для терминала. Пустая строка означает «молчим». */
export function formatResult(результат) {
  switch (результат.kind) {
    case "value":
      return результат.text
    case "message":
      return результат.text
    case "declared": {
      const строки = результат.replaced.map((метка) => `заменено: ${метка}`)
      if (результат.declared.length > ПОДРОБНО) {
        /* Файл библиотеки — это два десятка объявлений; перечислять их построчно
           значит залить экран. Считаем то, ради чего их и читают. */
        const доказано = результат.declared.filter((о) => о.total === true).length
        const обычных = результат.declared.filter((о) => о.total === false).length
        const прочих = результат.declared.length - доказано - обычных
        строки.push(
          `объявлений: ${результат.declared.length} — с доказанным завершением ${доказано}, ` +
            `обычных функций ${обычных}, типов и прочего ${прочих}`,
        )
      } else {
        for (const описание of результат.declared) {
          const про = описание.total === true
            ? " — завершение доказано"
            : описание.total === false
              ? " — завершение не доказано: вычисление ограничено лимитом шагов"
              : ""
          строки.push(`объявлено: ${описание.label}${про}`)
        }
      }
      if (результат.from !== undefined) строки.push(`загружено из ${результат.from}`)
      return строки.join("\n")
    }
    case "diagnostics":
      return результат.diagnostics.map(formatDiagnostic).join("\n")
    default:
      return ""
  }
}

/** Диагностика — кодом и местом, как в `flang check`, только не в JSON. */
export function formatDiagnostic(диагностика) {
  const место = диагностика.at
  const где =
    место === undefined || место === null
      ? ""
      : место.where === "ввод"
        ? `, строка ${место.line}${место.column === undefined ? "" : `, столбец ${место.column}`}`
        : место.where === "файл"
          ? ` в файле ${место.name}, строка ${место.line}`
          : место.where === "модуль"
            ? `, заголовок модуля, строка ${место.line}`
            : ` в объявлении (${место.name}), строка ${место.line}`
  return `${диагностика.code}${где}: ${диагностика.message}`
}

/* ─────────────────────── продолжение многострочного ввода ───────────────── */

/**
 * Нужен ли ещё ввод.
 *
 * Правило простое и оттого предсказуемое: пустая строка заканчивает ввод всегда,
 * а всё, что заведомо не помещается в строку — заголовок объявления с блоком
 * ниже, незакрытая скобка, `если` без `иначе`, — продолжается до пустой строки.
 * Автоматически завершать блок «как только он разобрался» нельзя: после тела
 * функции законно идут `пример`ы, и оболочка обрубала бы их на полуслове.
 *
 * Ошибочная строка тоже уходит в продолжение — отличить «не дописано» от
 * «написано неверно» по одной строке невозможно. Цена ошибки мала: пустая
 * строка заканчивает ввод, и диагностика приходит целиком.
 */
export function needsMoreInput(текст, известные) {
  if (текст.trim() === "") return false
  if (текст.trimStart().startsWith(".")) return false
  const строки = текст.split("\n")
  if (строки[строки.length - 1].trim() === "") return false
  if (строки.length > 1) return true
  return !законченная(текст, известные)
}

function законченная(строка, известные) {
  if (вид(строка) === "объявление") {
    const разобрано = разобратьВвод(строка, известные)
    if (разобрано.diagnostics !== undefined) return false
    const первый = первыйЗначащий(строка)
    if (первый?.kind === "keyword" && БЛОЧНЫЕ.has(первый.value)) {
      /* Псевдоним (`тип «Метр» это число`) — единственное блочное слово, за
         которым блока не бывает: продолжать его нечем. */
      const узлы = разобрано.программа.types ?? []
      return узлы.length === 1 && узлы[0].kind === "alias"
    }
    return true
  }
  try {
    parse(обёртка({ текст: строка, отступ: 0 }, ИМЯ_ВЫРАЖЕНИЯ).текст, ФАЙЛ_СЕССИИ, известные)
    return true
  } catch {
    return false
  }
}

/* ───────────────────────────── разбор ввода ─────────────────────────────── */

/**
 * Объявление или выражение.
 *
 * Решает первое ключевое слово — то же самое, по которому выбирает
 * `parseDeclaration`. Спорное слово ровно одно: `запись` начинает и объявление
 * типа, и литерал записи (`запись «Точка» с «х» равно 1`). Различаем так же,
 * как парсер: за именем в литерале стоит `с`.
 */
function вид(текст) {
  const токены = токенизировать(текст)
  if (токены === null) return "выражение"
  const первый = токены.find((токен) => значащий(токен))
  if (первый === undefined || первый.kind !== "keyword" || !ОБЪЯВЛЕНИЯ.has(первый.value)) return "выражение"
  if (первый.value === "record" || первый.value === "object") {
    const хвост = токены.slice(токены.indexOf(первый) + 2).find((токен) => значащий(токен))
    if (хвост?.kind === "keyword" && (хвост.value === "with" || хвост.value === "contains")) return "выражение"
  }
  return "объявление"
}

function первыйЗначащий(текст) {
  const токены = токенизировать(текст)
  return токены === null ? null : (токены.find((токен) => значащий(токен)) ?? null)
}

function значащий(токен) {
  return токен.kind !== "indent" && токен.kind !== "dedent" && токен.kind !== "newline" && токен.kind !== "eof"
}

function токенизировать(текст) {
  try {
    return tokenize(текст)
  } catch {
    /* Ошибка лексера — не повод гадать о виде ввода: пусть её покажет разбор,
       у которого есть и место, и код. */
    return null
  }
}

/**
 * Общий отступ ввода снимается: вставленный из файла кусок начинается с
 * отступа, а лексер такому исходнику скажет только «рваный отступ». Столбцы
 * диагностики восстанавливаются по снятой ширине.
 */
function снятьОбщийОтступ(исходный) {
  const строки = исходный.replace(/\s+$/u, "").split("\n")
  const значащие = строки.filter((строка) => строка.trim() !== "")
  if (значащие.length === 0) return { текст: "", отступ: 0 }
  let общий = /^[ \t]*/u.exec(значащие[0])[0]
  for (const строка of значащие) {
    const свой = /^[ \t]*/u.exec(строка)[0]
    while (общий !== "" && !свой.startsWith(общий)) общий = общий.slice(0, -1)
  }
  if (общий === "") return { текст: строки.join("\n"), отступ: 0 }
  const снято = строки.map((строка) => (строка.startsWith(общий) ? строка.slice(общий.length) : строка.trimStart()))
  return { текст: снято.join("\n"), отступ: общий.length }
}

/* ────────────────────────────── диагностика ─────────────────────────────── */

function отказ(diagnostics, карта) {
  return {
    kind: "diagnostics",
    diagnostics: diagnostics.map((д) => (карта === undefined ? д : разместить(д, карта))),
  }
}

/**
 * Диагностики связывания, чьё место — в ЧУЖОМ файле.
 *
 * Диагностика flang несёт строку и столбец, но не файл, поэтому после
 * связывания «строка 12» может относиться и к сессии, и к импортированному
 * модулю; различить их нечем (тем же свойством страдает `flang check` на
 * программе с импортами). Там, где принадлежность точно чужая, место лучше не
 * показывать вовсе: неверное место хуже отсутствующего.
 */
const ЧУЖОЕ_МЕСТО = new Set(["FLANG_DUPLICATE_NAME", "FLANG_IMPORT_CYCLE", "FLANG_IMPORT_NOT_FOUND", "FLANG_IMPORT_NAME"])

/** Место диагностики в собранном исходнике → место во вводе пользователя. */
function разместить(диагностика, карта) {
  const строка = диагностика.span?.line
  if (typeof строка !== "number" || ЧУЖОЕ_МЕСТО.has(диагностика.code)) return диагностика
  const часть = карта.find((кусок) => строка >= кусок.первая && строка <= кусок.последняя)
  if (часть === undefined) return диагностика
  return {
    ...диагностика,
    at: {
      where: часть.вид,
      name: часть.имя,
      line: Math.max(1, строка - часть.первая + 1 - часть.сдвигСтрок),
      column:
        typeof диагностика.span.column === "number"
          ? Math.max(1, диагностика.span.column - часть.сдвигСтолбцов)
          : undefined,
    },
  }
}

/** То же самое, но место известно заранее: ввод разбирался отдельно от сессии. */
function вМесте(диагностика, где, имя, сдвигСтрок, сдвигСтолбцов) {
  const строка = диагностика.span?.line
  if (typeof строка !== "number") return диагностика
  return {
    ...диагностика,
    at: {
      where: где,
      name: имя,
      line: Math.max(1, строка - сдвигСтрок),
      column:
        typeof диагностика.span.column === "number"
          ? Math.max(1, диагностика.span.column - сдвигСтолбцов)
          : undefined,
    },
  }
}

/**
 * Ошибка оболочки — это ошибка вызова, а не ошибка программы, поэтому код тот
 * же, каким CLI помечает неверный вызов: заводить для оболочки собственный код
 * значило бы расширять список кодов там, где ничего нового не произошло.
 */
function диагностика(сообщениеОшибки) {
  return { code: "FLANG_CLI", message: сообщениеОшибки, severity: "error" }
}

function диагностикиИз(ошибка) {
  if (Array.isArray(ошибка?.diagnostics) && ошибка.diagnostics.length > 0) return ошибка.diagnostics
  const код = typeof ошибка?.code === "string" ? ошибка.code : "FLANG_INTERNAL"
  return [{ code: код, message: сообщение(ошибка), severity: "error" }]
}

function сообщение(ошибка) {
  return ошибка instanceof Error ? ошибка.message : String(ошибка)
}
