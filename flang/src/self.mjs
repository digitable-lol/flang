/**
 * Слои компилятора, написанные на самом flang, — в рабочем пути, а не в сверках.
 *
 * ── Зачем этот файл ─────────────────────────────────────────────────────────
 *
 * Близнецы на flang были написаны и сверены с эталоном побайтово, но звать их
 * умели только проверки. Команда `flang check` продолжала спрашивать эталон на
 * JavaScript, и «язык доказывает сам себя» означало «язык доказывает сам себя,
 * когда об этом просит тест». Этот файл ставит близнецов туда, где решение
 * принимается на самом деле.
 *
 * ── Что здесь есть ──────────────────────────────────────────────────────────
 *
 * Обязательства — сведение написанного у функции постусловия с написанной рядом
 * теоремой в один объект. Слой на flang: `flang/self/obligations.flang`.
 * Побайтовое совпадение с эталоном измерено на 243 программах дерева и 14
 * нарочно дурных: расхождений 0 (`flang/test/self-obligations.test.mjs`).
 *
 * ── Чего здесь НЕТ, и почему ────────────────────────────────────────────────
 *
 * ЯДРО ДОКАЗАТЕЛЬСТВ (`flang/src/proofterm.mjs`) не переключено. У близнеца
 * `flang/self/proofterm.flang` измеренный зазор — 12 программ из 249, и он
 * назван поимённо в `flang/test/self-proofterm.test.mjs`. Зазор не косметический:
 * близнецу не хватает четырёх правил самого ядра (начальная алгебра встроенного
 * списка, принцип по отрезку «нат», точные десятичные, вычисление замкнутой
 * цели). Переключить сейчас значило бы отвечать «отвергнуто» там, где эталон
 * отвечает «доказано», — то есть уронить ведомость десяти программ дерева.
 *
 * ВЕДОМОСТЬ (`flang/src/proof.mjs`) не переключена по той же причине и с другим
 * числом: у близнеца `flang/self/proof.flang` нет раздела утверждений вовсе, и
 * это семь красных проверок в `flang/test/self-proof.test.mjs`.
 *
 * Оба зазора названы числом, а не оговоркой, и закрываются переносом, а не
 * правкой этого файла.
 *
 * ── Запасного пути к эталону нет ────────────────────────────────────────────
 *
 * Если слой на flang сорвался, вызов сорвётся — эталон за него не досчитает.
 * Тихий запасной путь и есть тот дефект, ради которого сверка побайтовая: он
 * срабатывал бы молча, и никто бы не заметил, что близнеца в рабочем пути нет.
 */
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { вЗначение, изЗначения } from "./bridge.mjs"
import { createRuntime } from "./interpret.mjs"
import { linkProgram } from "./link.mjs"
import { parse } from "./parser.mjs"

/**
 * Бюджет САМОГО СЛОЯ, а не проверяемой программы.
 *
 * Один виток машины на flang стоит от полутора до трёх тысяч витков эталона
 * (`flang/self/SPEC.md`, «Цена прогона»), поэтому запас взят тот же, что у
 * сверок. Он стережёт не медленность, а зацикливание.
 */
const БЮДЖЕТ = { maxSteps: 40_000_000, maxDepth: 10_000 }

const файлОбязательств = fileURLToPath(new URL("../self/obligations.flang", import.meta.url))

/** Исходник слоя обязательств. Наружу — ради порчи: изъятие обязано краснеть. */
export const исходникОбязательств = readFileSync(файлОбязательств, "utf8")

/**
 * Слой обязательств, собранный из данного исходника.
 *
 * Параметром, а не постоянной: доказательство «рабочий путь считает
 * близнецом» держится на том, что ИСПОРЧЕННЫЙ близнец меняет ответ команды.
 * Собрать испорченный слой можно только здесь.
 */
export async function слойОбязательств(текст = исходникОбязательств) {
  const { diagnostics: _пропущено, ...программа } = await linkProgram(файлОбязательств, текст, parse)
  return createRuntime(программа, БЮДЖЕТ)
}

/**
 * Слой собирается ОДИН РАЗ на процесс и откладывается до первого спроса.
 *
 * Отложен нарочно: связывание близнеца стоит около полусекунды, а команда, у
 * которой обязательств никто не спросит (`flang emit`, `flang run`), платить за
 * это не должна.
 */
let готовыйСлой = null

/**
 * Обязательства программы — тем же ответом, что у `obligations` эталона.
 *
 * Порядок ключей и порядок записей повторяют эталон побайтово: их читает ядро,
 * ведомость и чужие скрипты, и разойтись в них значит сломать не своё.
 *
 * Второй довод — итоги остальных проверок. Слою нужен из них ровно один
 * список: спуски анализа завершаемости, по которым закрывается обязательство
 * объявленной меры. Спрашивать у него больше нечего, и передавать больше не
 * надо: лишнее поле в аргументе — это лишний способ разойтись.
 */
export async function обязательства(программа, итоги = undefined, слой = undefined) {
  const среда = слой ?? (готовыйСлой ??= await слойОбязательств())
  const спуски = итоги?.totality?.descents ?? []
  return изЗначения(среда.call("Обязательства", {
    программа: вЗначение(программа),
    спуски: спуски.map(вЗначение),
  }))
}
