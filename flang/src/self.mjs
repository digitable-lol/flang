/**
 * Слои компилятора, написанные на самом flang, — в рабочем пути, а не в сверках.
 *
 * ── Зачем этот файл ─────────────────────────────────────────────────────────
 *
 * Близнецы на flang были написаны и сверены с эталоном побайтово, но звать их
 * умели только проверки. Команда `flang check` продолжала спрашивать эталон на
 * JavaScript, и «язык доказывает сам себя» означало «язык доказывает сам себя,
 * когда об этом просит тест». Этот файл ставит близнецов туда, где решение
 * принимается на самом деле.
 *
 * ── Что здесь есть ──────────────────────────────────────────────────────────
 *
 * Обязательства — сведение написанного у функции постусловия с написанной рядом
 * теоремой в один объект. Слой на flang: `flang/self/obligations.flang`.
 * Побайтовое совпадение с эталоном измерено на 243 программах дерева и 14
 * нарочно дурных: расхождений 0 (`flang/test/self-obligations.test.mjs`).
 *
 * ── Чего здесь НЕТ, и почему ────────────────────────────────────────────────
 *
 * ЯДРО ДОКАЗАТЕЛЬСТВ (`flang/src/proofterm.mjs`) не переключено — но УЖЕ НЕ
 * ПОТОМУ, ЧТО ЗАЗОР. Зазор ЗАКРЫТ: `flang/self/proofterm.flang` сходится с
 * эталоном ПОБАЙТОВО на 301 программе из 301, названный зазор — пустой список
 * (`flang/test/self-proofterm.test.mjs`). Все четыре правила, которых близнецу
 * не хватало, перенесены: начальная алгебра встроенного списка, принцип по
 * отрезку «нат», точные десятичные и вычисление замкнутой цели.
 *
 * Здесь стояло «зазор — 12 программ из 249», и это было верно на своём замере, а
 * потом молча устарело вдвое. Число заменено на сегодняшнее, потому что устаревший
 * довод держал решение не хуже настоящего: читающий видел причину не переключать
 * и не имел способа узнать, что причины больше нет.
 *
 * Что держит переключение ТЕПЕРЬ — не зазор ядра, а проводка: ядру подаются
 * снаружи обязательства, спуски и исходы прогона примеров, и переключается оно
 * вместе с ними, а не отдельно.
 *
 * ── Что здесь ещё есть ──────────────────────────────────────────────────────
 *
 * ВЕДОМОСТЬ ДОКАЗАТЕЛЬСТВА — чем несётся обещание каждой функции, на какой сетке
 * смотрели каждый закон, что высказано утверждениями и что принято на веру. Слой
 * на flang: `flang/self/proof.flang`. Побайтовое совпадение с эталоном измерено
 * на ВСЕХ 226 программах дерева, в обоих видах сразу — машинный вид с порядком
 * ключей и текст человеку знак в знак: расхождений 0
 * (`flang/test/self-proof.test.mjs`).
 *
 * До 16 августа у близнеца не было раздела утверждений вовсе, и это было семь
 * красных проверок; вместе с ним не было ни категории, ни функтора, ни пяти
 * объявленных свойств, и про них сверка МОЛЧАЛА — не потому, что сошлось, а
 * потому, что в корпусе сверки не было ни одной программы, где они есть.
 *
 * ── Запасного пути к эталону нет ────────────────────────────────────────────
 *
 * Если слой на flang сорвался, вызов сорвётся — эталон за него не досчитает.
 * Тихий запасной путь и есть тот дефект, ради которого сверка побайтовая: он
 * срабатывал бы молча, и никто бы не заметил, что близнеца в рабочем пути нет.
 */
