/**
 * ЧТО ЗДЕСЬ ПЕРЕКЛЮЧЕНО И ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ОБЯЗАТЕЛЬСТВ.
 *
 * Идемпотентность, коммутативность, дистрибутивность, частичный порядок и
 * монотонность считают слои на самом flang, а не `flang/src/*.mjs`. У
 * обязательств переключение было сменой двери: слою хватало разобранной
 * программы. Здесь мало разобрать — надо ВЫПОЛНИТЬ, и до сих пор это держало
 * пятерых в рабочем пути.
 *
 * ── Что мешало, и чем это оказалось на самом деле ───────────────────────────
 *
 * Записано было так: «передать вычислитель функцией в flang нечем — функций
 * первого класса у языка нет». Прогон говорит другое. Вычислитель зовётся ПО
 * ИМЕНИ (`использует «Вычислитель flang» из "interpret.flang"`), и так его уже
 * зовёт `flang/self/proof-kernel.flang`. Упирался перенос в ТОТАЛЬНОСТЬ:
 * тотальная функция, зовущая «Вызвать», отвергается кодом FLANG_NOT_TOTAL —
 * «обычная функция может не завершиться»; та же функция без слова «тотальная»
 * проходит проверку с нулём диагностик.
 *
 * Отсюда `flang/self/oracle.flang`: 23 его функции из 42 обещания тотальности
 * не несут, и это честно — он выполняет ЧУЖУЮ программу, а обещать её
 * завершение значило бы обещать разрешимость остановки. У пяти законов рядом
 * обычных функций по-прежнему ноль: граница проходит ровно по вызову
 * вычислителя.
 *
 * ── Чем подтверждено ────────────────────────────────────────────────────────
 *
 * `flang/test/self-svoystva.test.mjs`: таблица оракула в дереве против таблицы
 * оракула в проверке побайтово — 274 программы корпуса (706 строк) и 48
 * нарочных (1169 строк), расхождений 0; вердикт на таблице из дерева тот же,
 * что у свидетеля, — 48 программ на пять законов. Три порчи в одно слово
 * краснеют на настоящих программах корпуса.
 *
 * ── Запасного пути к свидетелю нет ──────────────────────────────────────────
 *
 * Сорвётся слой — сорвётся команда. Тихий запасной путь и есть тот дефект, ради
 * которого сверка побайтовая.
 */
