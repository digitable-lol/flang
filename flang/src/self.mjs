/**
 * Бюджет САМОГО СЛОЯ, а не проверяемой программы.
 *
 * Один виток машины на flang стоит от полутора до трёх тысяч витков эталона
 * (`flang/self/SPEC.md`, «Цена прогона»), поэтому запас взят тот же, что у
 * сверок. Он стережёт не медленность, а зацикливание.
 */
const БЮДЖЕТ = { maxSteps: 40_000_000, maxDepth: 10_000 }

const файлОбязательств = fileURLToPath(new URL("../self/obligations.flang", import.meta.url))

/** Исходник слоя обязательств. Наружу — ради порчи: изъятие обязано краснеть. */
export const исходникОбязательств = readFileSync(файлОбязательств, "utf8")

/**
 * Слой обязательств, собранный из данного исходника.
 *
 * Параметром, а не постоянной: доказательство «рабочий путь считает
 * близнецом» держится на том, что ИСПОРЧЕННЫЙ близнец меняет ответ команды.
 * Собрать испорченный слой можно только здесь.
 */
export async function слойОбязательств(текст = исходникОбязательств) {
  const { diagnostics: _пропущено, ...программа } = await linkProgram(файлОбязательств, текст, parse)
  return createRuntime(программа, БЮДЖЕТ)
}

/**
 * Слой собирается ОДИН РАЗ на процесс и откладывается до первого спроса.
 *
 * Отложен нарочно: связывание близнеца стоит около полусекунды, а команда, у
 * которой обязательств никто не спросит (`flang emit`, `flang run`), платить за
 * это не должна.
 */
let готовыйСлой = null

/**
 * Обязательства программы — тем же ответом, что у `obligations` эталона.
 *
 * Порядок ключей и порядок записей повторяют эталон побайтово: их читает ядро,
 * ведомость и чужие скрипты, и разойтись в них значит сломать не своё.
 *
 * Второй довод — итоги остальных проверок. Слою нужен из них ровно один
 * список: спуски анализа завершаемости, по которым закрывается обязательство
 * объявленной меры. Спрашивать у него больше нечего, и передавать больше не
 * надо: лишнее поле в аргументе — это лишний способ разойтись.
 */
export async function обязательства(программа, итоги = undefined, слой = undefined) {
  const среда = слой ?? (готовыйСлой ??= await слойОбязательств())
  const спуски = итоги?.totality?.descents ?? []
  return изЗначения(среда.call("Обязательства", {
    программа: вЗначение(программа),
    спуски: спуски.map(вЗначение),
  }))
}

