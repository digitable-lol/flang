/**
 * Итоги проверок в той форме, которую читает слой на flang.
 *
 * ЗДЕСЬ НЕ РЕШАЕТСЯ НИЧЕГО, и это условие, а не оговорка: поля перекладываются
 * из того же `results`, из которого их берёт свидетель, а порядок разделов, слова
 * точек и вся арифметика итогов написаны на flang. Предел сетки едет рядом с её
 * размером и берётся ОТТУДА, ГДЕ ОБЪЯВЛЕН — из модуля закона: копия предела
 * внутри ведомости разошлась бы с настоящим молча.
 *
 * Место у него одно — здесь, — по той же причине, по какой мост живёт в дереве,
 * а не в девятнадцати проверках: две копии перевода расходятся молча, и тогда
 * сверка сравнивает не то, что печатает команда.
 */
export function итогиВедомости(результаты) {
  const тотальность = результаты?.totality ?? {}
  const множества = результаты.sets?.checked ?? []
  const множестваНаВеру = результаты.sets?.assumed ?? []
  return {
    "циклы": (тотальность.cycles ?? []).map((имена) => ({ "имена": имена })),
    "структуры": (тотальность.structures ?? []).map(убывание),
    /* Точное убывание едет своим полем и со своим шагом: у него нет сторожа, и
       свалить его в один список со стережённым значило бы попросить ведомость
       различать их по форме записи вместо того, чтобы назвать. */
    "точные": (тотальность.exact ?? []).map((запись) => ({ ...убывание(запись), "шаг": запись.step })),
    "сторожа": (тотальность.guards ?? []).map(убывание),
    "спуски": (тотальность.descents ?? []).map((запись) => ({
      "откуда": запись.from,
      "мера": вЗначение(запись.current),
    })),
    "моноиды": (результаты.monoid?.checked ?? []).map((запись) => ({
      "имя": запись.monoid, "значений": запись.values, "троек": запись.triples, "предел": ПРЕДЕЛ_МОНОИДА,
      "исход": исход(запись.violations, 0, запись.aborted),
    })),
    "монады": (результаты.monad?.checked ?? []).map((запись) => ({
      "имя": запись.monad, "значений": запись.values, "троек": запись.triples,
      "стрелки": запись.arrows ?? [], "предел": ПРЕДЕЛ_МОНАДЫ, "предел стрелок": ПРЕДЕЛ_СТРЕЛОК,
      "исход": исход(запись.violations, запись.skipped, null),
    })),
    "изоморфизмы": (результаты.iso?.checked ?? []).map((запись) => ({
      "имя": запись.isomorphism, "значений": запись.values, "предел": ПРЕДЕЛ_ИЗОМОРФИЗМА,
      "исход": исход(запись.violations, 0, null),
    })),
    /* Категория и естественное преобразование — ОДНИМ списком, в том порядке, в
       каком их сложила проверка: два списка пришлось бы сливать в отчёте, и
       слияние решало бы за неё. */
    "категории": (результаты.category?.checked ?? []).map((запись) => ({
      "преобразование": запись.transformation !== undefined,
      "имя": запись.transformation ?? запись.category,
      "значений": запись.values,
      "объектов": запись.objects ?? 1,
      "точек": запись.transformation !== undefined ? запись.squares : запись.triples,
      "предел": ПРЕДЕЛ_КАТЕГОРИИ,
      "исход": исход(запись.violations, запись.skipped, запись.aborted),
    })),
    /* Вложение и общая часть — тоже одним, и по той же причине. */
    "множества": множества.map((запись) => ({
      "общая часть": запись.embedding === undefined,
      "имя": запись.embedding ?? запись.intersection,
      "значений": запись.values,
      "предел": ПРЕДЕЛ_МНОЖЕСТВ,
      "свидетель": узелОпц(запись.embedding === undefined ? запись.witness : undefined),
      "исход": исход(0, 0, null),
    })),
    "идемпотентность": свойство(результаты.idempotent),
    "коммутативность": свойство(результаты.commutative),
    "дистрибутивность": свойство(результаты.distributive),
    "частичный порядок": свойство(результаты.order),
    "монотонность": свойство(результаты.monotone),
    "связи": (результаты.functor?.checked ?? []).map((запись) => ({
      "имя": запись.functor, "значений": запись.values, "квадратов": запись.squares,
      "различных": запись.distinct, "предел": ПРЕДЕЛ_КВАДРАТА,
      "исход": исход(запись.violations, запись.skipped, запись.aborted),
    })),
    "допущения множеств": множестваНаВеру.map((з) => ({
      "общая часть": з.embedding === undefined,
      "имя": з.embedding ?? з.intersection ?? "",
      "причина": з.why,
    })),
    "допущения изоморфизмов": (результаты.iso?.assumed ?? [])
      .map((з) => ({ "имя": з.isomorphism, "причина": з.why })),
    "допущения категорий": (результаты.category?.assumed ?? []).map((з) => ({
      "преобразование": з.transformation !== undefined,
      "имя": з.category ?? з.transformation ?? "",
      "причина": з.why,
    })),
    "допущения связей": (результаты.functor?.assumed ?? [])
      .map((з) => ({ "имя": з.functor ?? "", "причина": з.why })),
    /* Обязательство несёт вердикт ядра, поиск — факт с примера автора, и сводятся
       они ПО МЕСТУ В СПИСКЕ. Порознь — потому что порознь их считают. */
    "обязательства": (результаты.obligations?.obligations ?? []).map((з) => ({
      "идентификатор": з.id,
      "вид": з.kind,
      "имя": з.name ?? "",
      "чья": з.of ?? "",
      "для всех": текстОпц(з.forall?.name ?? null),
      "сетка": з.grid ?? 0,
      "сброс": сброс(з.discharge),
    })),
    "поиск": (результаты.grid?.checked ?? []).map((з) => ({
      "идентификатор": з.id,
      "искали": з.searched ?? 0,
      "нарушения": (з.violations ?? []).map(нарушение),
      "мимо": (з.unsearched ?? []).map(нарушение),
    })),
  }
}

/**
 * Ведомость доказательства — тем же ответом, что у `proofLedger` свидетеля.
 *
 * Три вида сразу, и все три считает слой: машинный (по нему считают этапы),
 * текст человеку (в нём живёт словарь) и JSON, напечатанный тем же принтером,
 * каким слой печатает дерево разбора. Порядок ключей повторяет свидетель побайтово:
 * это поверхность совместимости, и разойтись в ней значит сломать чужой скрипт,
 * не сломав ни одного своего теста.
 *
 * Совпадение измерено на ВСЕХ 226 программах дерева, в обоих видах
 * (`flang/test/self-proof.test.mjs`): расхождений 0.
 */
export async function ведомость(программа, результаты, слой = undefined) {
  const среда = слой ?? (готоваяВедомость ??= await слойВедомости())
  return ведомостьСлоем(среда, программа, результаты)
}

/**
 * То же самое, но СИНХРОННО и на готовом слое.
 *
 * Асинхронной ведомость была ровно из-за одного — связывания эталона, а оно
 * делается один раз на процесс. Вызывающему, который связал слой заранее, ждать
 * больше нечего, и заставлять его быть асинхронным значило бы красить в `await`
 * цепочку вызовов там, где никакого ожидания нет.
 *
 * Дверь эта появилась не для удобства. `flang/src/proof.mjs` — свидетель ведомости
 * на JavaScript — стёрт, и шестнадцать его потребителей (тринадцать проверок и
 * три скрипта) переведены сюда. У свидетеля подпись была синхронная; сделай здесь
 * только асинхронную — и перевод каждого потребителя стал бы переписыванием, а
 * не сменой двери. Переписанный потребитель сравнивать было бы уже не с чем.
 */
export function ведомостьСлоем(среда, программа, результаты) {
  const запись = среда.call("Ведомость", {
    программа: вЗначение(программа),
    итоги: итогиВедомости(результаты ?? {}),
  })
  return {
    значением: изЗначения(среда.call("Ведомость значением", { ведомость: запись })),
    словами: среда.call("Ведомость словами", { ведомость: запись }),
    json: среда.call("Ведомость в JSON", { ведомость: запись }),
  }
}
