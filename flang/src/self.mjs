/**
 * Одна проверенная запись — категория ЛИБО преобразование.
 *
 * Порядок ключей — поверхность: по нему берёт ответ замороженная запись
 * свидетеля, и переставленный ключ даёт красные там, где ничего не менялось.
 * Поля уезжают наружу ТОЛЬКО при ненулевом значении — тем же приёмом, каким
 * свидетель пишет `...(нарушений === 0 ? {} : …)`.
 */
function записьКатегории(запись) {
  const сетка = запись.fields["запись"]
  const хвост = {
    ...(сетка["нарушений"] === 0 ? {} : { violations: сетка["нарушений"] }),
    ...(сетка["пропущено"] === 0 ? {} : { skipped: сетка["пропущено"] }),
    ...(сетка["оборвано"] === "" ? {} : { aborted: сетка["оборвано"] }),
  }
  return запись.variant === "Проверена категория"
    ? {
        category: сетка["категория"],
        values: сетка["значений"],
        objects: сетка["объектов"],
        triples: сетка["троек"],
        arrows: сетка["стрелки"],
        ...хвост,
      }
    : {
        transformation: сетка["преобразование"],
        values: сетка["значений"],
        objects: сетка["объектов"],
        squares: сетка["квадратов"],
        ...хвост,
      }
}

