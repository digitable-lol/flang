/** Слой одного закона. Исходником — ради той же порчи. */
export async function слойЗакона(файл, текст = undefined) {
  const путь = fileURLToPath(new URL(`../self/${файл}`, import.meta.url))
  const исходник = текст ?? readFileSync(путь, "utf8")
  const { diagnostics: _пропущено, ...программа } = await linkProgram(путь, исходник, parse)
  return createRuntime(программа, БЮДЖЕТ)
}

const готовыеСвойства = new Map()

/**
 * Пустой итог закона — тот же, что отдаёт свидетель на программе без единого
 * объявления. Стоит рядом с законами, а не внутри: закон, которого в программе
 * не объявили, не считает НИЧЕГО, и связывать ради этого слой значило бы платить
 * полсекунды за четыре пустых списка.
 */
const БЕЗ_ЗАКОНА = () => ({ diagnostics: [], checked: [], assumed: [], permits: [] })

/**
 * Слой закона — по одному и ТОЛЬКО ТОТ, чьё свойство в программе объявлено.
 *
 * Замер, из-за которого так: пять слоёв разом стоят около двух секунд на
 * связывание, а объявлены в программе редко все пятеро. `crdt-merge.flang`
 * объявляет четыре свойства из пяти, `split-lines.flang` — два, `retry-safe.flang`
 * — одно. Платить за неспрошенное — это платить за молчание.
 */
async function слойПоТребованию(ключ, файл) {
  if (!готовыеСвойства.has(ключ)) готовыеСвойства.set(ключ, await слойЗакона(файл))
  return готовыеСвойства.get(ключ)
}

/**
 * Пять объявленных свойств одной программы — тем же ответом, что у пяти
 * `check*` свидетеля, ключ в ключ и порядок в порядок.
 *
 * ПЯТЬ КЛЮЧЕЙ ЕСТЬ ВСЕГДА, даже когда не объявлено ни одного свойства, и это
 * не педантизм: свидетель ставил все пять и в этом случае, а ведомость читает
 * их по имени. Отсутствующий ключ и ключ с четырьмя пустыми списками — два
 * разных входа для того, кто читает, и разойтись они могли бы молча.
 *
 * Ни один слой при этом не связывается. Цена честная: слой связывается около
 * полусекунды, а объявленные свойства есть у четырёх программ корпуса из 274.
 * Платить за неспрошенное — это платить за молчание.
 */
export async function свойства(программа, слои = undefined) {
  const объявлено = new Set((программа?.properties ?? []).map((узел) => узел?.name))
  const переведённая = объявлено.size === 0 ? null : вЗначение(программа)
  if (объявлено.size === 0) {
    const пустые = {}
    for (const [, ключ] of ЗАКОНЫ_СВОЙСТВ) пустые[ключ] = БЕЗ_ЗАКОНА()
    return пустые
  }
  const оракул = слои?.оракул ?? (готовыеСвойства.has("оракул") ? готовыеСвойства.get("оракул") : готовыеСвойства.set("оракул", await слойОракула()).get("оракул"))
  /* Таблица одна на пятерых, а не пять: ключ у вызова один, и пять таблиц
     разошлись бы там, где два свойства объявлены об одной операции. */
  const таблица = оракул.call("Таблица вызовов свойств", {
    "программа": переведённая,
    "предел витков": БЮДЖЕТ.maxSteps,
    "предел глубины": БЮДЖЕТ.maxDepth,
  })
  const итоги = {}
  for (const [имя, ключ, файл, точка, запись] of ЗАКОНЫ_СВОЙСТВ) {
    if (!объявлено.has(имя)) {
      итоги[ключ] = БЕЗ_ЗАКОНА()
      continue
    }
    const среда = слои?.[ключ] ?? (await слойПоТребованию(ключ, файл))
    const итог = среда.call(точка, { "программа": переведённая, "таблица": таблица })
    итоги[ключ] = {
      diagnostics: итог["диагностики"].map(диагностикаСвойства),
      checked: итог["проверено"].map(запись),
      assumed: итог["допущено"].map(допущениеСвойства),
      permits: итог["разрешено"].map(разрешениеСвойства),
    }
  }
  return итоги
}

