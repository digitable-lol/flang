/**
 * Устройство вложений и общих частей — утверждения обо ВСЕХ входах.
 *
 * ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ У ВЛОЖЕНИЯ:
 *
 *   1. оба множества объявлены — объект категории это тип, тем же правилом,
 *      каким объявлены концы морфизма и изоморфизма;
 *   2. имя вложения не занято другим вложением;
 *   3. если написано `даёт «Ф»` — «Ф» объявлена, принимает ровно один вход,
 *      вход этот есть вложенная часть, а результат — объемлющее множество. Это
 *      дословно правило `FLANG_MORPHISM_SHAPE` у стрелки, и оно здесь не
 *      скопировано ради красоты: вложение И ЕСТЬ стрелка, а второе понимание
 *      слова `даёт` было бы вторым языком.
 *
 * ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ У ОБЩЕЙ ЧАСТИ:
 *
 *   4. объемлющее множество объявлено;
 *   5. ОБЕ стороны вложены в это объемлющее — не «как-нибудь связаны», а
 *      именно объявленным `вложение … в «У»`. Без этого «общий элемент» не с
 *      чем сличать: значения разных типов в языке несравнимы, и утверждение
 *      теряет смысл, а не точность;
 *   6. имя общей части свободно — им не назван ни тип, ни другая общая часть;
 *   7. у одной пары сторон над одним объемлющим общая часть ОДНА. Расслоенное
 *      произведение единственно с точностью до изоморфизма, и два разных имени
 *      для него — не богатство записи, а противоречие: читатель вправе
 *      спросить, которое из них общая часть, и ответа в программе нет.
 *
 * ЧЕГО ЗДЕСЬ НЕ ДОКАЗЫВАЕТСЯ И ДОКАЗАНО БЫТЬ НЕ МОЖЕТ — см. `checkSetLaws`
 * ниже и раздел «Граница честности» в flang/cat/SETS.md.
 *
 * @param {object} program AST flang
 * @param {object} ctx контекст `checkTypes`: `report`, `records`, `sums`,
 *                     `aliases`, `signatures`
 */
export function checkSetShapes(program, ctx) {
  const вложения = списком(program?.embeddings)
  const пересечения = списком(program?.intersections)
  if (вложения.length === 0 && пересечения.length === 0) return

  const объявлен = (имя) => ctx.records.has(имя) || ctx.sums.has(имя) || ctx.aliases.has(имя)

  /* ── вложения ───────────────────────────────────────────────────────── */
  const виделиВложение = new Map()
  /* Пары «часть → объемлющее»: по ним общая часть узнаёт, вложены ли её
     стороны. Множество имён на пару, а не одно имя: вложений одной части в
     одно и то же множество бывает несколько (разные стрелки), и запрещать это
     нельзя — два разных моно «А» → «Б» законны. */
  const вложеноВ = new Map()
  for (const узел of вложения) {
    if (виделиВложение.has(узел.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `вложение «${узел.name}» объявлено дважды`, узел)
      continue
    }
    виделиВложение.set(узел.name, узел)

    /* Третье слово в паре — то же «не объявлено» в согласии с родом роли:
       «вложенная часть … не объявлено» читается как опечатка компилятора, а
       компилятор, который путается в падежах, теряет доверие и там, где он
       прав. Тот же довод стоит у таблицы КАТЕГОРНЫЕ в link.mjs. */
    for (const [роль, имя, объявлено] of [
      ["вложенная часть", узел.from, "не объявлена"],
      ["объемлющее множество", узел.to, "не объявлено"],
    ]) {
      if (!объявлен(имя)) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `${роль} вложения «${узел.name}» — «${имя}» — ${объявлено}: множество здесь это тип`,
          узел,
        )
      }
    }

    if (!вложеноВ.has(узел.from)) вложеноВ.set(узел.from, new Set())
    вложеноВ.get(узел.from).add(узел.to)

    сверитьРеализацию(узел, ctx, объявлен)
  }
  ctx.embeddings = виделиВложение

  /* ── общие части ────────────────────────────────────────────────────── */
  const виделиЧасть = new Map()
  /* Ключ пары — стороны в ОТСОРТИРОВАННОМ порядке вместе с объемлющим:
     «А и Б в У» и «Б и А в У» — одна и та же общая часть, и объявить её дважды
     разными именами нельзя ни в том порядке, ни в другом. */
  const пары = new Map()
  for (const узел of пересечения) {
    if (виделиЧасть.has(узел.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `общая часть «${узел.name}» объявлена дважды`, узел)
      continue
    }
    виделиЧасть.set(узел.name, узел)

    /* Имя общей части не спорит с типом намеренно: `пересечение` типа не
       заводит (см. parseIntersection), а тёзка типа заставил бы читателя
       гадать, что такое «Срочные оплаченные» — запись или общая часть. */
    if (объявлен(узел.name)) {
      ctx.report(
        "FLANG_MEET_NAME_TAKEN",
        `общая часть «${узел.name}»: этим именем уже назван тип, а `
          + `пересечение типа не объявляет — выберите общей части своё имя`,
        узел,
      )
    }

    if (!объявлен(узел.within)) {
      ctx.report(
        "FLANG_UNKNOWN_NAME",
        `объемлющее множество общей части «${узел.name}» — «${узел.within}» — не объявлено: множество здесь это тип`,
        узел,
      )
    }

    for (const [роль, сторона] of [["первая сторона", узел.left], ["вторая сторона", узел.right]]) {
      if (вложеноВ.get(сторона)?.has(узел.within) === true) continue
      ctx.report(
        "FLANG_MEET_NO_UNIVERSE",
        `общая часть «${узел.name}»: ${роль} «${сторона}» не вложена в «${узел.within}». `
          + `Пересечение считается ВНУТРИ объемлющего множества: без вложения общий элемент `
          + `не с чем сличать — объявите «вложение … из «${сторона}» в «${узел.within}»»`,
        узел,
      )
    }

    /* Сторона сама с собой — не пересечение, а само множество: утверждение,
       которое ничего не утверждает. Ловится здесь, а не сеткой: сетка на нём
       как раз зазеленела бы. */
    if (узел.left === узел.right) {
      ctx.report(
        "FLANG_MEET_SAME_SIDE",
        `общая часть «${узел.name}»: обе стороны — «${узел.left}». `
          + `Пересечение множества с самим собой есть оно само, и нового имени ему не нужно`,
        узел,
      )
    }

    const ключ = JSON.stringify([[узел.left, узел.right].sort(), узел.within])
    const прежняя = пары.get(ключ)
    if (прежняя !== undefined) {
      ctx.report(
        "FLANG_MEET_TWICE",
        `общая часть «${узел.left}» и «${узел.right}» в «${узел.within}» уже названа «${прежняя}»: `
          + `у пары множеств общая часть одна, и второе имя для неё — противоречие, а не синоним`,
        узел,
      )
      continue
    }
    пары.set(ключ, узел.name)
  }
  ctx.intersections = виделиЧасть
}

/**
 * `даёт «Ф»` у вложения — то же правило, что у стрелки, и те же слова.
 *
 * Код диагностики свой (`FLANG_EMBED_SHAPE`, а не `FLANG_MORPHISM_SHAPE`):
 * по коду машина понимает, что чинить, и «морфизм» в отчёте о вложении отправил
 * бы её искать объявление, которого автор не писал.
 */
function сверитьРеализацию(узел, ctx, объявлен) {
  if (typeof узел.gives !== "string" || узел.gives === "") return

  const сигнатура = ctx.signatures.get(узел.gives)
  if (сигнатура === undefined) {
    ctx.report("FLANG_UNKNOWN_NAME", `вложение «${узел.name}» даёт «${узел.gives}»: такой функции нет`, узел)
    return
  }

  const входы = Array.isArray(сигнатура.params) ? сигнатура.params : []
  if (входы.length !== 1) {
    ctx.report(
      "FLANG_EMBED_SHAPE",
      `вложение «${узел.name}» ведёт из одного множества в одно, а «${узел.gives}» `
        + `принимает ${входы.length}: вложению нужна функция ровно от одного входа`,
      узел,
    )
    return
  }

  /* Сличаются ИМЕНА типов, а не развёрнутые типы: разворачивать псевдонимы
     здесь значило бы утащить сюда половину `types.mjs` вместе с областью
     параметров типа. Имя достаточно — множество здесь это объявленный тип, а
     его имя и есть его тождество (равенство типов в языке номинальное). */
  const имяВхода = имяТипа(входы[0]?.type)
  const имяРезультата = имяТипа(сигнатура.returns)
  if (объявлен(узел.from) && имяВхода !== null && имяВхода !== узел.from) {
    ctx.report(
      "FLANG_EMBED_SHAPE",
      `вложение «${узел.name}» ведёт из «${узел.from}», а «${узел.gives}» принимает «${имяВхода}»`,
      узел,
    )
  }
  if (объявлен(узел.to) && имяРезультата !== null && имяРезультата !== узел.to) {
    ctx.report(
      "FLANG_EMBED_SHAPE",
      `вложение «${узел.name}» ведёт в «${узел.to}», а «${узел.gives}» возвращает «${имяРезультата}»`,
      узел,
    )
  }
}

/**
 * Имя объявленного типа или null, если тип безымянный (число, строка, список…).
 *
 * Вид узла (`record`, `sum`, `named`) здесь не перечисляется намеренно: важно
 * ровно одно — есть ли у типа ИМЯ, потому что равенство типов в языке
 * номинальное. Список видов пришлось бы дописывать при каждом новом виде, и
 * забытая строка молча пропускала бы несходящееся вложение — ровно так эта
 * проверка и промолчала при первом прогоне, когда здесь стоял один `named`.
 */
function имяТипа(тип) {
  if (тип === null || тип === undefined) return null
  return typeof тип.name === "string" && тип.name !== "" ? тип.name : null
}

const списком = (значение) => (Array.isArray(значение) ? значение : [])
