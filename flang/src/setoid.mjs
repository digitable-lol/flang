/**
 * Равенство морфизмов: категория, обогащённая сетоидами.
 *
 * ── Чего не было и почему это было дорого ───────────────────────────────────
 *
 * До сегодняшнего дня равенства морфизмов в языке не было вовсе, и `cat/SPEC.md`
 * называл цену прямо: ассоциативность композиции НЕ ПРОВЕРЯЛАСЬ, потому что
 * `«в» после («б» после «а»)` и `(«в» после «б») после «а»` — два разных ИМЕНИ,
 * а проверка, сравнивающая имена, продавала бы сличение строк за аксиому. Тем
 * же были заблокированы естественные преобразования: коммутирующий квадрат —
 * это равенство двух композиций, и сказать его было нечем.
 *
 * ── Выбранный ответ и два отвергнутых ───────────────────────────────────────
 *
 * Категория объявляет СВОЁ отношение равенства — по одному на объект, функцией
 * из двух значений в признак:
 *
 * ```flang
 * категория «Отгрузки»
 *   морфизм «отгрузить»
 *   объект «Заказ» даёт «Заказы равны»
 * ```
 *
 * Равенство СТРЕЛОК выводится из него поточечно: `ф` и `ф'` из «А» в «Б» равны,
 * когда на каждом значении «А» их образы равны по равенству «Б». Это стандартный
 * ответ теории категорий, записанной в языке с типами: так устроены
 * `agda-categories` и категорные библиотеки Coq вне UniMath.
 *
 * Отвергнуто два других пути. Равенство через типы тождества требует зависимых
 * типов, которых у flang нет и не будет (`cat/SPEC.md`, «чего нет и не будет без
 * отдельной большой работы»). Равенство по нормализации работает только для
 * очень конкретных категорий и молча лжёт про остальные.
 *
 * ── Что здесь ПРОВЕРЯЕТСЯ, а не доказывается ────────────────────────────────
 *
 * Всё. Устройство равенства (функция объявлена, два входа объекта, признак на
 * выходе) доказано раньше и в другом месте — `types.mjs`, сличением объявлений.
 * Здесь же — утверждения о РАВЕНСТВЕ ВЫЧИСЛЕНИЙ на всех значениях объекта, а
 * такие утверждения неразрешимы. Значит конечная сетка, и отчёт обязан называть
 * её размер: «проверено на N значениях» — не то же самое, что «доказано».
 *
 *   1. ОБЪЯВЛЕННОЕ РАВЕНСТВО ЕСТЬ ЭКВИВАЛЕНТНОСТЬ — рефлексивно, симметрично,
 *      транзитивно. Первое из двух обязательств, и оно не формальность: не
 *      проверив его, можно «доказать» что угодно. Отношение «не больше»
 *      транзитивно и рефлексивно, но НЕ симметрично, и на нём равными вышли бы
 *      стрелки, равными не являющиеся.
 *   2. КОМПОЗИЦИЯ УВАЖАЕТ РАВЕНСТВО — «если ф равно ф', то г после ф равно
 *      г после ф'». При поточечном равенстве стрелок это ровно требование,
 *      чтобы каждая стрелка категории переводила равные значения в равные;
 *      проверяется и корень (каждая стрелка), и само утверждение о композиции
 *      на тех парах стрелок, которые на сетке вышли равными.
 *   3. АССОЦИАТИВНОСТЬ КОМПОЗИЦИИ — `(в после б) после а` и
 *      `в после (б после а)` на каждом значении домена дают образы, равные по
 *      равенству кодомена.
 *
 * ── Сила третьей проверки названа честно, и это важнее самой проверки ───────
 *
 * Композиция в flang не пишется автором: `после` разворачивается в применение,
 * а применение ассоциативно по построению вычислителя. Значит у категории, где
 * все три стрелки реализованы, обе скобки дают ОДНО И ТО ЖЕ значение, и вся
 * проверка сводится к вопросу «рефлексивно ли объявленное равенство в той
 * точке, куда композиция пришла». Вопрос не пустой — точка эта в сетку
 * кодомена, вообще говоря, не входит, и рефлексивность там никем не считана, —
 * но и выдавать его за проверку аксиомы нельзя.
 *
 * Что изменилось по существу: раньше две скобки были ДВУМЯ ИМЕНАМИ и сравнить
 * их было нечем; теперь сравниваются ВЫЧИСЛЕНИЯ через объявленное автором
 * равенство. Чтобы проверка могла краснеть и на честной программе, композиции
 * нужен собственный `даёт` — тогда две скобки пойдут через две написанные
 * руками функции и разойдутся. Это отдельная работа, и она названа в
 * `flang/cat/SPEC.md`, а не сделана здесь молча.
 *
 * ── Откуда берётся сетка ────────────────────────────────────────────────────
 *
 * Оттуда же, откуда у моноида и изоморфизма: из значений, которые автор уже
 * написал. Для объекта «А» это входы примеров стрелок, ИЗ него выходящих,
 * ожидаемые значения примеров стрелок, В него входящих, и оба входа примеров
 * самой функции равенства. Примеры пишет тот, кто знает краевые случаи, а закон
 * ломается именно на них.
 */
import { reifyValue, valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Больше этого числа значений в сетку одного объекта не берём: транзитивность
 *  кубична по сетке, и на двадцати значениях это уже восемь тысяч сравнений. */
export const ПРЕДЕЛ_СЕТКИ = 12

/** Больше этого числа composable-троек стрелок не смотрим: троек кубически
 *  много по числу стрелок, а «проверено» обязано означать одно и то же в разных
 *  прогонах. */
export const ПРЕДЕЛ_ТРОЕК = 64

/**
 * Проверка законов всех категорий программы, объявивших своё равенство.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>,
 *   checked: Array<{ category: string, values: number, triples: number, arrows: Array<string> }>,
 *   assumed: Array<{ category: string, why: string }> }}
 */
export function checkCategoryLaws(программа, пределы = {}) {
  const категории = Array.isArray(программа?.categories) ? программа.categories : []
  const diagnostics = []
  const checked = []
  const assumed = []
  if (категории.length === 0) return { diagnostics, checked, assumed }

  const узлыСтрелок = new Map()
  for (const узел of Array.isArray(программа?.morphisms) ? программа.morphisms : []) {
    if (typeof узел?.name === "string") узлыСтрелок.set(узел.name, узел)
  }
  const концы = концыСтрелок(узлыСтрелок)
  const функции = Array.isArray(программа?.functions) ? программа.functions : []
  const среда = createRuntime(программа, пределы)

  const звать = (имя, ...аргументы) => {
    const функция = функции.find((кандидат) => кандидат.name === имя)
    if (функция === undefined) return { ошибка: `функции «${имя}» нет` }
    const назван = {}
    ;(функция.params ?? []).forEach((параметр, номер) => {
      назван[параметр.name] = аргументы[номер]
    })
    try {
      return { значение: среда.call(имя, назван) }
    } catch (беда) {
      /* Отказ на значении сетки — не нарушение закона, а другое сообщение:
         проверить закон здесь не на чем, и сказать надо именно это. */
      return { ошибка: беда?.message ?? String(беда) }
    }
  }

  /** Стрелка на значении: `даёт` считает, единица возвращает вход, композиция
   *  применяет правую и затем левую. Ничего сверх объявленного. */
  const применить = (имя, значение) => {
    const узел = узлыСтрелок.get(имя)
    if (узел === undefined) return { ошибка: `морфизма «${имя}» нет` }
    if (узел.kind === "composition") {
      const справа = применить(узел.right, значение)
      if (справа.ошибка) return справа
      return применить(узел.left, справа.значение)
    }
    if (узел.identity === true) return { значение }
    if (typeof узел.gives !== "string" || узел.gives === "") {
      return { ошибка: `у морфизма «${имя}» нет 'даёт'` }
    }
    return звать(узел.gives, значение)
  }

  const реализована = (имя, глубина = 0) => {
    const узел = узлыСтрелок.get(имя)
    if (узел === undefined || глубина > 32) return false
    if (узел.kind === "composition") {
      return реализована(узел.left, глубина + 1) && реализована(узел.right, глубина + 1)
    }
    return узел.identity === true || (typeof узел.gives === "string" && узел.gives !== "")
  }

  /* Посчитанное по каждой категории — сетки и равенства — нужно вторым разом,
     естественному преобразованию: квадрат живёт в категории КОДОМЕНА функторов,
     и сравнивает его её равенство. Считать сетку второй раз значило бы получить
     второй ответ на тот же вопрос, а расходятся такие ответы молча. */
  const посчитано = new Map()

  for (const узел of категории) {
    const равенства = объявленныеРавенства(узел, функции)
    if (равенства.size === 0) {
      /* Категория без объявленного равенства — та же граница, по которой
         изоморфизм без `даёт` уходит в `assumed`: сравнивать нечем, и молчать
         об этом нельзя. Объявление, о котором отчёт молчит, читается как
         проверенное. */
      assumed.push({
        category: узел.name,
        why: "своего равенства не объявлено: равенство стрелок не выразимо, ассоциативность не считана",
      })
      continue
    }

    const свои = (узел.morphisms ?? []).filter((имя) => концы.has(имя))
    const сетки = сеткиОбъектов(свои, концы, узлыСтрелок, равенства, функции)
    if (!посчитано.has(узел.name)) посчитано.set(узел.name, { равенства, сетки })

    const доБед = diagnostics.length
    let оборвано = null
    let троек = 0
    let пропущено = 0
    const сказать = (код, текст) => {
      diagnostics.push({
        code: код,
        message: `категория «${узел.name}»: ${текст}`,
        severity: "error",
        span: узел.span,
      })
    }

    /** Равны ли два значения объекта по объявленному равенству. */
    const равны = (объект, а, б) => {
      const имя = равенства.get(объект)
      if (имя === undefined) return { нет: `у «${объект}» равенство не объявлено` }
      const итог = звать(имя, а, б)
      if (итог.ошибка) return { нет: итог.ошибка }
      if (typeof итог.значение !== "boolean") {
        return { нет: `«${имя}» вернула ${покажи(итог.значение)}, а не признак` }
      }
      return { да: итог.значение }
    }

    /* ── Обязательство первое: это эквивалентность ─────────────────────────
       Порядок — рефлексивность, симметрия, транзитивность: по возрастанию
       цены (линия, квадрат, куб) и по убыванию частоты поломки. */
    эквивалентность: for (const [объект, значения] of сетки) {
      for (const х of значения) {
        const сам = равны(объект, х, х)
        if (сам.нет !== undefined) {
          оборвано = `равенство на «${объект}» не посчиталось: ${сам.нет}`
          break эквивалентность
        }
        if (!сам.да) {
          сказать(
            "FLANG_EQUALITY_NOT_REFLEXIVE",
            `равенство на «${объект}» не рефлексивно: ${покажи(х)} не равно самому себе. ` +
              `Отношение, при котором значение не равно себе, равенством не является ни при каком прочтении`,
          )
          break эквивалентность
        }
      }
      for (const х of значения) {
        for (const у of значения) {
          const туда = равны(объект, х, у)
          const назад = равны(объект, у, х)
          if (туда.нет !== undefined || назад.нет !== undefined) {
            оборвано = `равенство на «${объект}» не посчиталось: ${туда.нет ?? назад.нет}`
            break эквивалентность
          }
          if (туда.да !== назад.да) {
            сказать(
              "FLANG_EQUALITY_NOT_SYMMETRIC",
              `равенство на «${объект}» не симметрично: ${покажи(х)} и ${покажи(у)} — ` +
                `${туда.да ? "да" : "нет"}, а ${покажи(у)} и ${покажи(х)} — ${назад.да ? "да" : "нет"}`,
            )
            break эквивалентность
          }
        }
      }
      for (const х of значения) {
        for (const у of значения) {
          const первое = равны(объект, х, у)
          if (первое.нет !== undefined) {
            оборвано = `равенство на «${объект}» не посчиталось: ${первое.нет}`
            break эквивалентность
          }
          if (!первое.да) continue
          for (const з of значения) {
            const второе = равны(объект, у, з)
            const итог = равны(объект, х, з)
            if (второе.нет !== undefined || итог.нет !== undefined) {
              оборвано = `равенство на «${объект}» не посчиталось: ${второе.нет ?? итог.нет}`
              break эквивалентность
            }
            if (второе.да && !итог.да) {
              сказать(
                "FLANG_EQUALITY_NOT_TRANSITIVE",
                `равенство на «${объект}» не транзитивно: ${покажи(х)} равно ${покажи(у)}, ` +
                  `${покажи(у)} равно ${покажи(з)}, а ${покажи(х)} и ${покажи(з)} — нет`,
              )
              break эквивалентность
            }
          }
        }
      }
    }

    /* ПОРЯДОК ЗДЕСЬ СОДЕРЖАТЕЛЬНЫЙ, а не удобный. Отношение, оказавшееся не
       эквивалентностью, равенством не является; всё, что о нём сказали бы
       остальные законы, было бы утверждением о том, что равенством не
       является, — «не проверив первого, можно доказать что угодно». Поэтому
       здесь не «заодно посчитаем», а СТОП: остальные законы категории не
       считаны, и отчёт говорит об этом словами, а не молчит и не выдаёт
       непосчитанное за чистую сетку. */
    if (diagnostics.length > доБед) {
      checked.push({
        category: узел.name,
        values: [...сетки.values()].reduce((сумма, список) => сумма + список.length, 0),
        objects: сетки.size,
        triples: 0,
        arrows: свои,
        violations: diagnostics.length - доБед,
        aborted: "объявленное равенство не эквивалентность: согласованность с композицией"
          + " и ассоциативность не считаны — они говорили бы о том, что равенством не является",
      })
      continue
    }

    /* ── Обязательство второе: композиция уважает равенство ────────────────
       Корень утверждения «ф равно ф' влечёт г после ф равно г после ф'» — это
       требование к КАЖДОЙ стрелке: равные значения обязаны переходить в равные.
       Не выполнись оно — равенство перестаёт быть равенством морфизмов, потому
       что «равные» стрелки, продолженные одной и той же г, разойдутся. */
    конгруэнтность: for (const имя of свои) {
      const пара = концы.get(имя)
      const узелСтрелки = узлыСтрелок.get(имя)
      if (узелСтрелки?.identity === true) continue
      if (!реализована(имя)) {
        пропущено += 1
        continue
      }
      const сетка = сетки.get(пара.domain)
      if (сетка === undefined || !равенства.has(пара.codomain)) {
        пропущено += 1
        continue
      }
      for (const х of сетка) {
        for (const у of сетка) {
          const вход = равны(пара.domain, х, у)
          if (вход.нет !== undefined) {
            оборвано = `равенство на «${пара.domain}» не посчиталось: ${вход.нет}`
            break конгруэнтность
          }
          if (!вход.да) continue
          const образХ = применить(имя, х)
          const образУ = применить(имя, у)
          if (образХ.ошибка || образУ.ошибка) {
            оборвано = `стрелка «${имя}» отказала на значении сетки: ${образХ.ошибка ?? образУ.ошибка}`
            break конгруэнтность
          }
          const выход = равны(пара.codomain, образХ.значение, образУ.значение)
          if (выход.нет !== undefined) {
            оборвано = `равенство на «${пара.codomain}» не посчиталось: ${выход.нет}`
            break конгруэнтность
          }
          if (!выход.да) {
            сказать(
              "FLANG_EQUALITY_NOT_CONGRUENT",
              `композиция не уважает равенство: ${покажи(х)} и ${покажи(у)} равны по равенству ` +
                `«${пара.domain}», а «${имя}» перевела их в ${покажи(образХ.значение)} и ` +
                `${покажи(образУ.значение)}, которые по равенству «${пара.codomain}» не равны`,
            )
            break конгруэнтность
          }
        }
      }
    }

    /* То же утверждение в том виде, в каком оно записано в контракте: если две
       ОБЪЯВЛЕННЫЕ стрелки вышли на сетке равными, то и продолженные одной и той
       же стрелкой они обязаны остаться равными. Пар таких немного (у стрелок
       обязаны совпасть оба конца), а сказать это прямо стоит: закон говорит о
       стрелках, и отчёт обязан говорить о них же. */
    продолжение: for (const [ф, штрих] of равныеПары(свои, концы, сетки, равенства, применить, равны)) {
      const пара = концы.get(ф)
      for (const г of свои) {
        const дальше = концы.get(г)
        if (дальше.domain !== пара.codomain) continue
        if (!реализована(г) || !равенства.has(дальше.codomain)) continue
        for (const х of сетки.get(пара.domain) ?? []) {
          const слева = применить(ф, х)
          const справа = применить(штрих, х)
          if (слева.ошибка || справа.ошибка) break продолжение
          const через = применить(г, слева.значение)
          const мимо = применить(г, справа.значение)
          if (через.ошибка || мимо.ошибка) break продолжение
          const итог = равны(дальше.codomain, через.значение, мимо.значение)
          if (итог.нет !== undefined) break продолжение
          if (!итог.да) {
            сказать(
              "FLANG_EQUALITY_NOT_CONGRUENT",
              `«${ф}» и «${штрих}» равны на сетке, а «${г}» после них — нет: на ${покажи(х)} вышло ` +
                `${покажи(через.значение)} и ${покажи(мимо.значение)}`,
            )
            break продолжение
          }
        }
      }
    }

    /* ── Ассоциативность композиции ────────────────────────────────────────
       Обе скобки собираются из объявленных стрелок и сравниваются ОБЪЯВЛЕННЫМ
       равенством кодомена. Про силу этой проверки сказано в шапке файла прямо и
       без прикрас: композиция вычисляется применением, значит на реализованных
       стрелках обе скобки дают одно значение, и краснеет проверка ровно там,
       где объявленное равенство не рефлексивно в точке, до которой композиция
       дошла. Точка эта в сетку кодомена не входит, и никто её там не считал. */
    const тройки = []
    for (const а of свои) {
      for (const б of свои) {
        for (const в of свои) {
          if (тройки.length >= ПРЕДЕЛ_ТРОЕК) break
          if (концы.get(а).codomain !== концы.get(б).domain) continue
          if (концы.get(б).codomain !== концы.get(в).domain) continue
          тройки.push([а, б, в])
        }
      }
    }
    ассоциативность: for (const [а, б, в] of тройки) {
      const домен = концы.get(а).domain
      const кодомен = концы.get(в).codomain
      if (!реализована(а) || !реализована(б) || !реализована(в) || !равенства.has(кодомен)) {
        пропущено += 1
        continue
      }
      const сетка = сетки.get(домен) ?? []
      /* Две скобки собираются ПОРОЗНЬ, как два разных морфизма, и только потом
         применяются: «б после а» — стрелка из домена «а» в кодомен «б», «в
         после б» — из домена «б» в кодомен «в». Ровно это в языке и было двумя
         разными именами, которые нечем было сравнить. */
      const бПослеА = (значение) => {
        const шаг = применить(а, значение)
        return шаг.ошибка ? шаг : применить(б, шаг.значение)
      }
      const вПослеБ = (значение) => {
        const шаг = применить(б, значение)
        return шаг.ошибка ? шаг : применить(в, шаг.значение)
      }
      for (const х of сетка) {
        троек += 1
        const внутри = бПослеА(х)
        if (внутри.ошибка) {
          оборвано = `стрелка «${б}» после «${а}» отказала на значении сетки: ${внутри.ошибка}`
          break ассоциативность
        }
        const слева = применить(в, внутри.значение)
        const первая = применить(а, х)
        const справа = первая.ошибка ? первая : вПослеБ(первая.значение)
        if (слева.ошибка || справа.ошибка) {
          оборвано = `стрелка «${в}» отказала на значении сетки: ${слева.ошибка ?? справа.ошибка}`
          break ассоциативность
        }
        const итог = равны(кодомен, слева.значение, справа.значение)
        if (итог.нет !== undefined) {
          оборвано = `равенство на «${кодомен}» не посчиталось: ${итог.нет}`
          break ассоциативность
        }
        if (!итог.да) {
          сказать(
            "FLANG_CATEGORY_NOT_ASSOC",
            `композиция не ассоциативна: на ${покажи(х)} путь «${в}» после («${б}» после «${а}») дал ` +
              `${покажи(слева.значение)}, а («${в}» после «${б}») после «${а}» — ${покажи(справа.значение)}, ` +
              `и по равенству «${кодомен}» они не равны`,
          )
          break ассоциативность
        }
      }
    }

    const нарушений = diagnostics.length - доБед
    const значенийВсего = [...сетки.values()].reduce((сумма, список) => сумма + список.length, 0)
    if (значенийВсего === 0) {
      assumed.push({
        category: узел.name,
        why: "у стрелок и у равенства нет примеров: сетка пуста, считать не на чем",
      })
      continue
    }
    checked.push({
      category: узел.name,
      values: значенийВсего,
      /* Число объектов с равенством — не украшение отчёта: предел сетки стоит
         НА ОБЪЕКТ, и без этого числа «сетка 24 значения (предел 12)» читалось
         бы как упор в потолок там, где потолка ещё не видели. */
      objects: сетки.size,
      triples: троек,
      arrows: свои,
      ...(нарушений === 0 ? {} : { violations: нарушений }),
      ...(пропущено === 0 ? {} : { skipped: пропущено }),
      ...(оборвано === null ? {} : { aborted: оборвано }),
    })
  }

  /* ── Естественность преобразований ────────────────────────────────────────
     Отдельным проходом и после категорий: квадрат сравнивает две стрелки
     равенством категории кодомена, а она считается выше. */
  for (const узел of Array.isArray(программа?.transformations) ? программа.transformations : []) {
    проверитьЕстественность(узел, {
      функторы: функторыПрограммы(программа),
      концы,
      посчитано,
      применить,
      реализована,
      звать,
      diagnostics,
      checked,
      assumed,
    })
  }

  return { diagnostics, checked, assumed }
}

/**
 * Закон естественности: квадрат коммутирует.
 *
 * Для каждой стрелки `ф: Х → У` категории домена два пути из `Ф(Х)` в `Г(У)`
 * обязаны давать равные значения:
 *
 *   Г(ф) после альфа_Х      — сначала преобразовать, потом отобразить вторым;
 *   альфа_У после Ф(ф)      — сначала отобразить первым, потом преобразовать.
 *
 * ЭТО ПЕРВЫЙ ЗАКОН ЭТОГО ФАЙЛА, КОТОРЫЙ КРАСНЕЕТ НА ЧЕСТНОЙ ПРОГРАММЕ, и разница
 * с ассоциативностью здесь принципиальная. У ассоциативности обе скобки —
 * ОДНА И ТА ЖЕ цепочка применений, и разойтись им не на чем. Здесь же четыре
 * стрелки — `Ф(ф)`, `Г(ф)`, `альфа_Х`, `альфа_У` — написаны автором ПОРОЗНЬ, и
 * равенство путей есть настоящее утверждение о его коде: сдвинь любую из
 * четырёх на единицу, и квадрат перестанет коммутировать.
 *
 * ЧТО ОСТАЁТСЯ ДОПУЩЕНИЕМ. Категория кодомена без объявленного равенства —
 * сравнивать нечем; стрелка без `даёт` — вычислять нечем. И то и другое уходит
 * в `assumed` с причиной, а не молчит: объявление, о котором отчёт молчит,
 * читается как проверенное.
 */
function проверитьЕстественность(узел, среда) {
  const { функторы, концы, посчитано, применить, реализована, diagnostics, checked, assumed } = среда
  const слева = функторы.get(узел.from)
  const справа = функторы.get(узел.to)
  const отложить = (почему) => assumed.push({ transformation: узел.name, why: почему })
  if (слева === undefined || справа === undefined || слева.to !== справа.to) {
    /* Об этом уже сказала проверка типов; второе сообщение о том же было бы
       шумом, а не помощью. */
    отложить("функторы не сошлись: об этом сказала проверка устройства")
    return
  }

  const кодомен = посчитано.get(слева.to)
  if (кодомен === undefined) {
    отложить(`категория «${слева.to}» своего равенства не объявила: квадрат сравнить нечем`)
    return
  }

  const компоненты = new Map((узел.components ?? []).map((запись) => [запись.object, запись.morphism]))
  const образОбъекта = (функтор) => new Map((функтор.objects ?? []).map((пара) => [пара.from, пара.to]))
  const объектыСлева = образОбъекта(слева)
  const стрелкиСлева = new Map((слева.morphisms ?? []).map((пара) => [пара.from, пара.to]))
  const стрелкиСправа = new Map((справа.morphisms ?? []).map((пара) => [пара.from, пара.to]))

  let значений = 0
  let квадратов = 0
  let пропущено = 0
  let оборвано = null
  const доБед = diagnostics.length

  const равны = (объект, а, б) => {
    const имя = кодомен.равенства.get(объект)
    if (имя === undefined) return { нет: `у «${объект}» равенство не объявлено` }
    const итог = среда.звать(имя, а, б)
    if (итог.ошибка) return { нет: итог.ошибка }
    if (typeof итог.значение !== "boolean") return { нет: `«${имя}» вернула не признак` }
    return { да: итог.значение }
  }

  квадраты: for (const [стрелка, образСлева] of стрелкиСлева) {
    const образСправа = стрелкиСправа.get(стрелка)
    const пара = концы.get(стрелка)
    if (образСправа === undefined || пара === undefined) {
      пропущено += 1
      continue
    }
    const альфаХ = компоненты.get(пара.domain)
    const альфаУ = компоненты.get(пара.codomain)
    if (альфаХ === undefined || альфаУ === undefined) {
      пропущено += 1
      continue
    }
    const начало = объектыСлева.get(пара.domain)
    const конец = стрелкиСправаКонец(концы, образСправа)
    if (начало === undefined || конец === undefined || !кодомен.равенства.has(конец)) {
      пропущено += 1
      continue
    }
    for (const имя of [образСлева, образСправа, альфаХ, альфаУ]) {
      if (реализована(имя)) continue
      пропущено += 1
      continue квадраты
    }

    const сетка = кодомен.сетки.get(начало) ?? []
    /* Пустая сетка — не проверенный квадрат, а непроверенный: считать его в
       отчёте наравне с посчитанным значило бы сказать «квадратов 2» о единице. */
    if (сетка.length === 0) {
      пропущено += 1
      continue
    }
    for (const значение of сетка) {
      значений += 1
      /* Путь первый: преобразовать, потом отобразить вторым функтором. */
      const альфа = применить(альфаХ, значение)
      const первый = альфа.ошибка ? альфа : применить(образСправа, альфа.значение)
      /* Путь второй: отобразить первым функтором, потом преобразовать. */
      const образ = применить(образСлева, значение)
      const второй = образ.ошибка ? образ : применить(альфаУ, образ.значение)
      if (первый.ошибка || второй.ошибка) {
        оборвано = `стрелка квадрата «${стрелка}» отказала на значении сетки: `
          + `${первый.ошибка ?? второй.ошибка}`
        break квадраты
      }
      const итог = равны(конец, первый.значение, второй.значение)
      if (итог.нет !== undefined) {
        оборвано = `равенство на «${конец}» не посчиталось: ${итог.нет}`
        break квадраты
      }
      if (!итог.да) {
        diagnostics.push({
          code: "FLANG_TRANSFORM_NOT_NATURAL",
          message: `преобразование «${узел.name}»: квадрат не коммутирует на морфизме «${стрелка}»: `
            + `на ${покажи(значение)} путь «${образСправа}» после «${альфаХ}» дал ${покажи(первый.значение)}, `
            + `а «${альфаУ}» после «${образСлева}» — ${покажи(второй.значение)}`,
          severity: "error",
          span: узел.span,
        })
        break квадраты
      }
    }
    квадратов += 1
  }

  if (значений === 0) {
    отложить("сетка пуста или стрелки квадрата не реализованы: считать не на чем")
    return
  }
  const нарушений = diagnostics.length - доБед
  checked.push({
    transformation: узел.name,
    values: значений,
    objects: компоненты.size,
    squares: квадратов,
    ...(нарушений === 0 ? {} : { violations: нарушений }),
    ...(пропущено === 0 ? {} : { skipped: пропущено }),
    ...(оборвано === null ? {} : { aborted: оборвано }),
  })
}

/** Кодомен стрелки-образа: конец квадрата, в котором сравниваются оба пути. */
function стрелкиСправаКонец(концы, имя) {
  return концы.get(имя)?.codomain
}

/** Функторы программы: они приезжают узлом наследия, как их разбирает парсер. */
function функторыПрограммы(программа) {
  const карта = new Map()
  for (const узел of Array.isArray(программа?.legacy) ? программа.legacy : []) {
    if (узел?.construct !== "functorFile") continue
    if (!карта.has(узел.value?.name)) карта.set(узел.value.name, узел.value)
  }
  return карта
}

/**
 * Концы каждой стрелки, включая композиции.
 *
 * Своя таблица, а не `ctx.morphisms` из `types.mjs`: модуль законов зовут в
 * одном ряду с проверкой типов, а не после неё, и молча зависеть от чужого
 * состояния значило бы держать порядок вызовов правилом без сторожа. Ровно так
 * же поступает `iso.mjs`. Расхождения при этом быть не может: концы композиции
 * выводятся из концов сомножителей и ниоткуда больше.
 */
function концыСтрелок(узлы) {
  const концы = new Map()
  for (const [имя, узел] of узлы) {
    if (узел.kind === "morphism") концы.set(имя, { domain: узел.domain, codomain: узел.codomain })
  }
  let сдвинулись = true
  while (сдвинулись) {
    сдвинулись = false
    for (const [имя, узел] of узлы) {
      if (узел.kind !== "composition" || концы.has(имя)) continue
      const левая = концы.get(узел.left)
      const правая = концы.get(узел.right)
      if (левая === undefined || правая === undefined) continue
      концы.set(имя, { domain: правая.domain, codomain: левая.codomain })
      сдвинулись = true
    }
  }
  return концы
}

/** Равенства категории, у которых названная функция объявлена и берёт два входа. */
function объявленныеРавенства(узел, функции) {
  const равенства = new Map()
  for (const запись of узел.equalities ?? []) {
    const функция = функции.find((кандидат) => кандидат.name === запись?.gives)
    if (функция === undefined || (функция.params ?? []).length !== 2) continue
    if (равенства.has(запись.object)) continue
    равенства.set(запись.object, запись.gives)
  }
  return равенства
}

/**
 * Сетка значений по объектам категории.
 *
 * Для объекта берутся: входы примеров стрелок, из него выходящих (они принимают
 * его значения), ожидаемые значения примеров стрелок, в него входящих (они их
 * возвращают), и оба входа примеров самой функции равенства — их автор писал
 * именно как значения этого объекта.
 */
function сеткиОбъектов(свои, концы, узлыСтрелок, равенства, функции) {
  const сетки = new Map()
  const положить = (объект, значение) => {
    if (значение === undefined) return
    if (!сетки.has(объект)) сетки.set(объект, [])
    const список = сетки.get(объект)
    const готовое = reifyValue(значение)
    if (список.some((уже) => valuesEqual(уже, готовое))) return
    if (список.length >= ПРЕДЕЛ_СЕТКИ) return
    список.push(готовое)
  }

  for (const [объект, имяРавенства] of равенства) {
    сетки.set(объект, [])
    const функция = функции.find((кандидат) => кандидат.name === имяРавенства)
    for (const пример of функция?.examples ?? []) {
      for (const значение of Object.values(пример.args ?? {})) положить(объект, значение)
    }
  }

  for (const имя of свои) {
    const пара = концы.get(имя)
    const стрелка = узлыСтрелок.get(имя)
    for (const пример of примерыСтрелки(стрелка, функции)) {
      for (const значение of Object.values(пример.args ?? {})) положить(пара.domain, значение)
      положить(пара.codomain, пример.expected)
    }
  }

  /* Объекты, у которых равенства нет, в сетке не нужны: сравнивать их значения
     нечем, и держать их значило бы считать размер сетки по тому, чего не
     считали. */
  for (const объект of [...сетки.keys()]) {
    if (!равенства.has(объект)) сетки.delete(объект)
  }
  return сетки
}

function примерыСтрелки(стрелка, функции) {
  if (стрелка === undefined) return []
  const функция = функции.find((кандидат) => кандидат.name === стрелка.gives)
  const свои = функция?.examples ?? []
  const законные = (стрелка.laws ?? []).flatMap((закон) => закон.examples ?? [])
  return [...свои, ...законные]
}

/**
 * Пары РАЗНЫХ стрелок категории с общими концами, вышедшие на сетке равными.
 *
 * Их и продолжают: закон говорит «если ф равно ф', то г после ф равно г после
 * ф'», а посылка «ф равно ф'» проверяема ровно здесь и ровно так — поточечно,
 * объявленным равенством кодомена.
 */
function равныеПары(свои, концы, сетки, равенства, применить, равны) {
  const пары = []
  for (let i = 0; i < свои.length; i += 1) {
    for (let j = i + 1; j < свои.length; j += 1) {
      const ф = свои[i]
      const штрих = свои[j]
      const левые = концы.get(ф)
      const правые = концы.get(штрих)
      if (левые.domain !== правые.domain || левые.codomain !== правые.codomain) continue
      if (!равенства.has(левые.codomain)) continue
      const сетка = сетки.get(левые.domain) ?? []
      if (сетка.length === 0) continue
      let равно = true
      for (const х of сетка) {
        const слева = применить(ф, х)
        const справа = применить(штрих, х)
        if (слева.ошибка || справа.ошибка) {
          равно = false
          break
        }
        const итог = равны(левые.codomain, слева.значение, справа.значение)
        if (итог.нет !== undefined || !итог.да) {
          равно = false
          break
        }
      }
      if (равно) пары.push([ф, штрих])
    }
  }
  return пары
}

/** Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт. */
function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 40 ? `${текст.slice(0, 37)}…` : текст
}
