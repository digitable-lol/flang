/**
 * Законы отношений множеств — то, что ПРОВЕРЯЕТСЯ, а не доказывается.
 *
 * ВЛОЖЕНИЕ ОБЕЩАЕТ ИНЪЕКТИВНОСТЬ. «Часть» — это не любая стрелка: стрелка,
 * склеивающая два разных значения в одно, показывает не подмножество, а
 * фактор. Равенство «разные входы дают разные выходы» говорит обо всех парах
 * значений и потому неразрешимо — значит конечная сетка, и отчёт обязан
 * называть её размер. Нарушение — ОШИБКА: контрпример предъявлен, и он
 * настоящий, а не «не нашли».
 *
 * ОБЩАЯ ЧАСТЬ ОБЕЩАЕТ, ЧТО ОНА НЕ ПУСТА. Два круга рисуют внахлёст ровно
 * затем, чтобы сказать «есть общие элементы»; разведённые круги — чтобы
 * сказать обратное. Здесь проверка ищет СВИДЕТЕЛЯ: значение, которое приходит
 * в объемлющее множество и слева, и справа. Нашла — общая часть ПОДТВЕРЖДЕНА
 * этим значением, оно названо и попадает в `checked`.
 *
 * НЕ НАШЛА — и проверка МОЛЧИТ. Это решение, а не недоделка, и вот его довод.
 * Отсутствие свидетеля на конечной сетке не доказывает пустоты: значений,
 * которых автор не написал, бесконечно много. Диагностикой такое сказать
 * нельзя — в языке нет уровня «к сведению»: `flang check` считает недопустимой
 * любую диагностику (`valid: diagnostics.length === 0` в bin/flang.mjs), а
 * `warning` он выбрасывает молча (`normalizeDiagnostics`). Значит выбор был
 * между «уронить программу, которая ни в чём не виновата» и «промолчать»;
 * уронить нельзя — автор вправе написать примеры, среди которых общего значения
 * просто нет. Такая общая часть уходит в `assumed`: инструмент её видит, автор
 * не получает ложного отказа, а слово «проверено» не растягивается на то, что
 * не проверялось.
 *
 * ЧТО ОСТАЁТСЯ ДОПУЩЕНИЕМ АВТОРА ЦЕЛИКОМ — универсальность: что названная
 * общая часть САМАЯ БОЛЬШАЯ из общих. Это утверждение про все множества сразу,
 * включая те, которых в программе нет; проверить его не на чем ни
 * доказательством, ни сеткой, и компилятор о нём молчит. Он и следствий из него
 * не выводит — по той же причине, по которой не выводит их из изоморфизма
 * (flang/cat/SPEC.md, «Изоморфизм»).
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 * @returns {{ diagnostics: Array<object>, checked: Array<object>, assumed: Array<object> }}
 */
export function checkSetLaws(программа, пределы = {}) {
  const вложения = списком(программа?.embeddings)
  const пересечения = списком(программа?.intersections)
  const diagnostics = []
  const checked = []
  /* Отношения, о которых сетке сказать нечего: вложение без реализации и общая
     часть без свидетеля. Список отдельный, а не пустая строчка в `checked`, —
     чтобы «проверено» нельзя было прочитать про то, что не проверялось. */
  const assumed = []
  if (вложения.length === 0 && пересечения.length === 0) return { diagnostics, checked, assumed }

  const зов = вычислитель(программа, пределы)

  for (const узел of вложения) {
    /* Вложение без реализации проверить нечем, и проверка молчит: объявление
       без тела законно, а требовать тело ради проверки значило бы запретить
       объявлять то, чего ещё нет. */
    if (!реализовано(узел)) {
      assumed.push({ embedding: узел.name, why: "нет реализации: вычислять нечего" })
      continue
    }
    const сетка = сеткаВхода(программа, узел.gives)
    if (сетка.length === 0) {
      assumed.push({ embedding: узел.name, why: `у «${узел.gives}» нет примеров: сетка пуста` })
      continue
    }

    const образы = []
    let оборвалось = false
    for (const значение of сетка) {
      const итог = зов(узел.gives, значение)
      if (итог.ошибка !== undefined) {
        diagnostics.push(беда(
          "FLANG_EMBED_NOT_INJECTIVE",
          `вложение «${узел.name}»: «${узел.gives}» отказала на значении сетки: ${итог.ошибка}`,
          узел,
        ))
        оборвалось = true
        break
      }
      const близнец = образы.find((уже) => зов.равны(уже.образ, итог.значение))
      if (близнец !== undefined) {
        diagnostics.push(беда(
          "FLANG_EMBED_NOT_INJECTIVE",
          `вложение «${узел.name}» обещает, что «${узел.from}» есть ЧАСТЬ «${узел.to}», `
            + `а «${узел.gives}» склеивает два разных значения в одно: `
            + `${покажи(близнец.вход)} и ${покажи(значение)} дают ${покажи(итог.значение)}. `
            + `Склеивающая стрелка показывает не подмножество, а фактор`,
          узел,
        ))
        оборвалось = true
        break
      }
      образы.push({ вход: значение, образ: итог.значение })
    }
    if (!оборвалось) checked.push({ embedding: узел.name, values: сетка.length })
  }

  for (const узел of пересечения) {
    const слева = вложениеИз(вложения, узел.left, узел.within)
    const справа = вложениеИз(вложения, узел.right, узел.within)
    /* Нет вложения или нет реализации — об этом уже сказано доказательством
       устройства либо сказать нечего вовсе. Второе сообщение о том же было бы
       шумом, а не помощью. */
    if (слева === undefined || справа === undefined) {
      assumed.push({ intersection: узел.name, why: "хотя бы одно вложение без реализации" })
      continue
    }

    const образыСлева = образыСтороны(программа, зов, слева)
    const образыСправа = образыСтороны(программа, зов, справа)
    if (образыСлева.length === 0 || образыСправа.length === 0) {
      assumed.push({ intersection: узел.name, why: "у вложений нет примеров: сетка пуста" })
      continue
    }

    const свидетель = образыСлева.find((левый) => образыСправа.some((правый) => зов.равны(левый.образ, правый.образ)))
    if (свидетель !== undefined) {
      checked.push({
        intersection: узел.name,
        values: образыСлева.length + образыСправа.length,
        witness: свидетель.образ,
      })
      continue
    }
    assumed.push({
      intersection: узел.name,
      why:
        `среди ${образыСлева.length + образыСправа.length} написанных значений в «${узел.within}» `
        + `общего не нашлось: либо множества и правда не пересекаются, либо пример общего значения не написан`,
    })
  }

  return { diagnostics, checked, assumed }
}

