/**
 * Отношения множеств: вложение и общая часть — контракт flang/cat/SETS.md.
 *
 * Файл отвечает сразу за обе полки границы честности, и разложены они по двум
 * функциям, а не смешаны в одну:
 *
 *   checkSetShapes(программа, ctx) — ДОКАЗЫВАЕТСЯ сличением объявлений,
 *                                    зовётся из `checkTypes`;
 *   checkSetLaws(программа)        — ПРОВЕРЯЕТСЯ на сетке, зовётся из
 *                                    `flang check` рядом с моноидом, монадой
 *                                    и изоморфизмом.
 *
 * Разделение не косметическое. Первая функция ничего не вычисляет и потому
 * говорит обо ВСЕХ входах; вторая вычисляет и потому говорит о КОНЕЧНОМ их
 * числе. Смешать их в одну — значит выдать «посмотрели на дюжину значений» за
 * «доказано», а это ровно та подмена, от которой язык отгораживается
 * (flang/cat/SPEC.md, «Граница честности: доказано против проверено»).
 *
 * ── Почему слов два, а не три ───────────────────────────────────────────────
 *
 * Тикет называл три отношения — подмножество, пересечение, объединение — и три
 * стрелочных способа их выразить: моно, расслоенное произведение,
 * ко-произведение. Заведено ДВА слова, и вот почему третьего нет.
 *
 * ОБЪЕДИНЕНИЕ В ЯЗЫКЕ УЖЕ ЕСТЬ, и называется оно `тип … вариант …`. Ко-
 * произведение — это в точности тип с вариантами вместе со своими вложениями:
 * `вариант «Это А»` и `вариант «Это Б»` и есть две стрелки внутрь, а `разбор`
 * — это в точности его универсальное свойство («задай по функции с каждой
 * стороны — получишь функцию из объединения»). Новое слово об этом не доказало
 * бы ничего сверх того, что уже доказывает исчерпывающность разбора, зато
 * завело бы вторую проверку рядом с первой — и разъехались бы они молча. Довод
 * тот же, по которому в языке нет отдельной «группы» (моноид с обращением).
 *
 * ВТОРОЕ, и это важнее: объединение двух НАЛЕГАЮЩИХ множеств — не ко-
 * произведение, а ко-декартов квадрат. Ко-произведение складывает непересекающиеся
 * копии, и «А ∪ Б» через него выражается только когда общей части нет. Дать
 * слову «объединение» смысл ко-произведения значило бы соврать ровно в том
 * случае, ради которого его и просят, — в случае двух налегающих кругов.
 *
 * ТРЕТЬЕ: с холста объединение не читается. Большой круг с двумя малыми внутри
 * не отличим от «два подмножества одного множества» — «покрывают ли они его
 * целиком» рисунком не сказано. Слово, которому нечем стать со стороны, ради
 * которой оно заводилось, не заводится.
 */
import { reifyValue, valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Больше этого числа значений в сетку не берём — по той же причине, что в
 *  `iso.mjs`: перебор пар квадратичен, а «проверено» обязано означать одно и
 *  то же в разных прогонах. */
export const ПРЕДЕЛ_СЕТКИ = 12

