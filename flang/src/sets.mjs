const списком = (значение) => (Array.isArray(значение) ? значение : [])

const реализовано = (узел) => typeof узел?.gives === "string" && узел.gives !== ""

const беда = (code, message, узел) => ({ code, message, severity: "error", span: узел?.span })

/**
 * Вложение стороны в объемлющее — первое РЕАЛИЗОВАННОЕ, и только оно.
 *
 * Нереализованное сюда не годится намеренно: сетка ВЫЧИСЛЯЕТ образы, а у
 * вложения без `даёт` вычислять нечего. Вернуть его значило бы уронить проверку
 * на пустом месте или, что хуже, объявить общую часть подтверждённой, ничего не
 * посчитав. Нет реализации — общая часть уходит в `assumed`, и это честный
 * ответ, а не пропуск.
 */
function вложениеИз(вложения, часть, объемлющее) {
  return вложения.find((узел) => узел.from === часть && узел.to === объемлющее && реализовано(узел))
}

/**
 * Значения стороны, доведённые до объемлющего множества.
 *
 * Сличать входы двух вложений напрямую нельзя: они лежат в РАЗНЫХ множествах и
 * несравнимы по построению. Сравнивать надо образы — то, во что обе стороны
 * приходят внутри «У». Ровно это и делает расслоенное произведение.
 */
function образыСтороны(программа, зов, вложение) {
  const образы = []
  for (const значение of сеткаВхода(программа, вложение.gives)) {
    const итог = зов(вложение.gives, значение)
    if (итог.ошибка !== undefined) continue
    образы.push({ вход: значение, образ: итог.значение })
  }
  return образы
}

/**
 * Сетка входов функции — из значений, которые автор уже написал.
 *
 * Источник тот же, что у моноида и изоморфизма: примеры самой функции. Своих
 * примеров у вложения нет и заводить их не надо — функция, которой оно
 * реализовано, свои примеры уже несёт, и писать те же значения второй раз
 * значило бы развести две правды об одном.
 */
function сеткаВхода(программа, имяФункции) {
  const функция = функции(программа).find((кандидат) => кандидат.name === имяФункции)
  if (функция === undefined || (функция.params ?? []).length !== 1) return []
  const собрано = []
  for (const пример of функция.examples ?? []) {
    for (const сырое of Object.values(пример.args ?? {})) {
      if (сырое === undefined) continue
      const значение = reifyValue(сырое)
      if (собрано.some((уже) => valuesEqual(уже, значение))) continue
      собрано.push(значение)
    }
  }
  return собрано.slice(0, ПРЕДЕЛ_СЕТКИ)
}

const функции = (программа) => (Array.isArray(программа?.functions) ? программа.functions : [])

/**
 * Вычислитель: зовёт функцию по имени на одном значении.
 *
 * Отказ функции на значении сетки — не нарушение закона, а другое сообщение:
 * проверять не на чем, и сказать надо именно это. Приём и разбор те же, что в
 * `iso.mjs`; второго исполнителя здесь нет намеренно.
 */
function вычислитель(программа, пределы) {
  const среда = createRuntime(программа, пределы)
  const зов = (имяФункции, значение) => {
    const функция = функции(программа).find((кандидат) => кандидат.name === имяФункции)
    if (функция === undefined) return { ошибка: `функции «${имяФункции}» нет` }
    try {
      return { значение: среда.call(имяФункции, { [функция.params[0].name]: значение }) }
    } catch (что) {
      return { ошибка: что?.message ?? String(что) }
    }
  }
  зов.равны = valuesEqual
  return зов
}

/** Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт. */
function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 40 ? `${текст.slice(0, 37)}…` : текст
}
