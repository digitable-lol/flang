/**
 * Объявленные свойства — общая основа пяти законов.
 *
 * ── Что здесь лежит и чего здесь НЕТ ────────────────────────────────────────
 *
 * Здесь нет ни одного закона. Здесь — то, что у пяти проверок общее и обязано
 * совпадать до последнего числа: как берётся сетка, как зовётся функция, как
 * называется значение в тексте отказа и какой предел стоит на сетке. Сами
 * законы живут порознь, по модулю на свойство:
 *
 *   `idempotent.mjs`    х∘х = х            — разрешение ПОВТОРИТЬ
 *   `commutative.mjs`   а∘б = б∘а          — разрешение РАЗЛОЖИТЬ свёртку
 *   `distributive.mjs`  а×(б+в)=а×б+а×в    — разрешение ПЕРЕПИСАТЬ выражение
 *   `partialorder.mjs`  ≤ рефл./антисим./транз. — разрешение СРАВНИВАТЬ состояния
 *   `monotone.mjs`      а≤б ⟹ ф(а)≤ф(б)    — разрешение КЕШИРОВАТЬ
 *
 * Порознь — потому что этого попросил владелец языка, и довод у него тот же,
 * по которому порознь лежат `iso.mjs` и `sets.mjs`: свойство, из которого
 * ничего не следует, языку не нужно, а следствие у каждого своё. Один модуль на
 * пятерых прятал бы пять разных разрешений за одним вердиктом.
 *
 * ── Что ПРОВЕРЯЕТСЯ, а не доказывается ──────────────────────────────────────
 *
 * Всё, что здесь считается. Устройство свойства (функция объявлена, входов
 * столько, сколько нужно, типы сходятся с носителем) доказано раньше и в другом
 * месте — `types.mjs`, сличением объявлений, без единого вычисления. Здесь же —
 * утверждения о РАВЕНСТВЕ ВЫЧИСЛЕНИЙ на всех значениях носителя, а такие
 * утверждения неразрешимы. Значит конечная сетка, и ведомость обязана называть
 * её размер строкой, оканчивающейся словами «Это не доказательство».
 *
 * ── Откуда берётся сетка ────────────────────────────────────────────────────
 *
 * Оттуда же, откуда у моноида, изоморфизма и категории: из значений, которые
 * автор уже написал, — входы и ожидаемые значения примеров названных функций.
 * Довод тот же и он не про экономию: примеры пишет тот, кто знает краевые
 * случаи, а закон ломается именно на них. Случайные значения дали бы больше
 * точек и меньше смысла.
 *
 * ── Разрешение выдаётся, а не подразумевается ───────────────────────────────
 *
 * Проверка, которая ничего не разрешает, — украшение отчёта. Поэтому каждая из
 * пяти при чистом счёте на НЕПУСТОЙ сетке кладёт в `permits` именованное
 * разрешение: что именно компилятору теперь позволено делать такого, чего он не
 * мог раньше. Нарушение — разрешения нет. Пустая сетка — разрешения нет и запись
 * уходит в `assumed`: считать было не на чем, и молчать об этом нельзя, потому
 * что объявление, о котором отчёт молчит, читается как проверенное.
 */
import { reifyValue, valuesEqual } from "./builtins.mjs"
import { createRuntime } from "./interpret.mjs"

/** Больше этого числа значений в сетку не берём: тройки кубичны по сетке. */
export const ПРЕДЕЛ_СЕТКИ = 12

/* СЛОВАРЬ ПЯТИ ИМЁН УЕХАЛ В `types.mjs` 19 августа, и это не перестановка:
   единственным, кто его брал, был типизатор, и ради пяти пар он ввозил сюда
   весь модуль. Копия у типизатора сверяется с хозяином — слоем на flang
   (`self/svoystva.flang`, «Имена свойств»). Второй копии здесь нет намеренно:
   две копии одного словаря расходятся молча. */

/** Объявления одного вида — по имени свойства, а не по порядку в файле. */
export function объявления(программа, имя) {
  const список = Array.isArray(программа?.properties) ? программа.properties : []
  return список.filter((узел) => узел?.name === имя)
}

/**
 * Ключ типа для сличения концов.
 *
 * Нужен ровно одному месту — монотонности, которой надо найти объявленный
 * порядок на домене и на кодомене функции. Сличать типы здесь, в слое законов,
 * приходится своим ключом, а не `sameType` из `types.mjs`: слой законов зовут в
 * одном ряду с проверкой типов, а не после неё, и молча зависеть от чужого
 * состояния значило бы держать порядок вызовов правилом без сторожа. Ровно так
 * же поступают `iso.mjs` и `sets.mjs`.
 *
 * Расхождения при этом быть не может: оба конца читаются из одного и того же
 * места AST — `params[i].type` и `returns` объявленной функции.
 */
export function ключТипа(тип) {
  if (тип === null || тип === undefined) return null
  if (typeof тип !== "object") return String(тип)
  if (тип.kind === "named") return `named:${тип.name}`
  if (тип.kind === "list") return `list:${ключТипа(тип.item ?? тип.element)}`
  return String(тип.kind)
}

/**
 * Общая обвязка: вызов функции, сетка значений, показ значения.
 *
 * @param {object} программа AST flang
 * @param {{ maxSteps?: number, maxDepth?: number }} [пределы]
 */
export function основа(программа, пределы = {}) {
  const функции = Array.isArray(программа?.functions) ? программа.functions : []
  const среда = createRuntime(программа, пределы)

  const найти = (имя) => функции.find((кандидат) => кандидат.name === имя)

  const звать = (имя, ...аргументы) => {
    const функция = найти(имя)
    if (функция === undefined) return { ошибка: `функции «${имя}» нет` }
    const назван = {}
    ;(функция.params ?? []).forEach((параметр, номер) => {
      назван[параметр.name] = аргументы[номер]
    })
    try {
      return { значение: среда.call(имя, назван) }
    } catch (беда) {
      /* Отказ на значении сетки — не нарушение закона, а другое сообщение:
         проверить закон здесь не на чем, и сказать надо именно это. */
      return { ошибка: беда?.message ?? String(беда) }
    }
  }

  /**
   * Сетка по названным функциям: входы примеров и ожидаемые значения.
   *
   * `толькоВходы` — для тех функций, чей результат носителем НЕ является:
   * у отношения порядка результат признак, и складывать `да` в сетку значений
   * носителя значило бы считать порядок на признаках.
   */
  const сетка = (имена, { толькоВходы = false } = {}) => {
    const собрано = []
    const положить = (значение) => {
      if (значение === undefined) return
      const готовое = reifyValue(значение)
      if (собрано.some((уже) => valuesEqual(уже, готовое))) return
      if (собрано.length >= ПРЕДЕЛ_СЕТКИ) return
      собрано.push(готовое)
    }
    for (const имя of имена) {
      if (typeof имя !== "string" || имя === "") continue
      for (const пример of найти(имя)?.examples ?? []) {
        for (const значение of Object.values(пример.args ?? {})) положить(значение)
        if (!толькоВходы) положить(пример.expected)
      }
    }
    return собрано
  }

  return { функции, найти, звать, сетка }
}

/** Значение в сообщении — коротко и однозначно; JSON достаточен и не врёт. */
export function покажи(значение) {
  const текст = JSON.stringify(значение)
  return текст === undefined ? String(значение) : текст.length > 40 ? `${текст.slice(0, 37)}…` : текст
}

/**
 * Пустой итог — общая форма ответа всех пяти.
 *
 * `permits` стоит рядом с `checked`, а не внутри него: разрешение — это НЕ
 * строка отчёта о том, что посчитано, а то, что из посчитанного следует. Их
 * склейка была бы ровно тем смешением, из-за которого свойство и превращается в
 * украшение.
 */
export function пусто() {
  return { diagnostics: [], checked: [], assumed: [], permits: [] }
}
