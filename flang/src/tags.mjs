/**
 * tags.mjs — теги программы: конечный список случаев диспетчера `применить`.
 *
 * Функция первого класса в flang — это ТЕГ (дефункционализация, Reynolds 1972;
 * обоснование в `flang/cat/HOF.md`). Тег строится РОВНО одной формой,
 * `функция «Имя»`, поэтому множество тегов программы конечно и вычислимо
 * простым обходом — за это заплачено отсутствием раздельной компиляции.
 *
 * ── Почему это отдельный модуль, а не по копии в каждом слое ────────────────
 *
 * Список нужен ДВУМ слоям, и они обязаны понимать его одинаково:
 *
 *   • `totality.mjs` разворачивает по нему применение в рёбра графа вызовов и
 *     на этом доказывает завершение;
 *   • `interpret.mjs` по нему же отказывается применять тег, которого программа
 *     не строит.
 *
 * Разойдись они хоть на один тег — и доказанное перестало бы соответствовать
 * исполняемому: анализ рассуждал бы об одном множестве случаев, а вычислитель
 * допускал бы другое. Одно определение на оба слоя делает такое расхождение
 * невозможным, а не маловероятным.
 *
 * ── Зачем вычислителю отказываться ─────────────────────────────────────────
 *
 * Значение приходит и снаружи — `evaluate(программа, имя, аргументы)`, — и
 * снаружи можно подсунуть тег любой объявленной функции. Такой тег прошёл бы по
 * типам (`функция из числа в число` — законный тип и у обычной функции) и
 * обесценил бы доказанную тотальность. Причём не только через обычную функцию:
 * комбинатор Ω выражается и на одних тотальных —
 *
 *     объект «Ящик»
 *       ф: функция из «Ящик» в число
 *
 *     тотальная функция «Ω»
 *       принимает я: «Ящик»
 *       возвращает число
 *       я.ф от я
 *
 * — и если тег «Ω» подать снаружи, `я.ф от я` крутится вечно, хотя названа
 * тотальной. Программа же, которая строит этот тег сама, ловится анализом:
 * ребро «Ω» → «Ω» не убывает. Отказ снаружи закрывает ровно ту дыру, которую
 * анализ закрыть не может, потому что снаружи он не смотрит.
 *
 * В напечатанном коде отказа не потребуется: у диспетчера есть случай ровно на
 * тот тег, который где-то строится, и построить чужой нечем. Здесь то же самое
 * делается явно — потому что напечатанный код и интерпретатор обязаны вести
 * себя одинаково, а не «примерно одинаково».
 */

/**
 * Имена функций, взятых значением где-либо в программе.
 *
 * Обход общий, а не по видам узлов: тег законен всюду, где законно выражение —
 * в теле, в постусловии, в единице моноида, в обработчике процесса, — и
 * пропустить место значило бы потерять случай диспетчера.
 *
 * @param {object} program AST модуля (SPEC, раздел 5)
 * @param {(name: string) => boolean} declared называет ли имя объявленную функцию
 * @returns {Set<string>}
 */
export function programTags(program, declared) {
  const found = new Set()
  const note = (name) => {
    /* Имя, не называющее объявленную функцию, тегом не является: это обычный
       вариант суммы, случайно совпавший именем. Совпадение возможно —
       пространства имён у вариантов и функций разные. */
    if (typeof name === "string" && declared(name)) found.add(name)
  }
  walk(program, note)
  return found
}

function walk(node, note) {
  if (Array.isArray(node)) {
    for (const item of node) walk(item, note)
    return
  }
  if (!node || typeof node !== "object") return
  if (node.kind === "fnref") {
    note(node.name)
  } else if (node.kind === undefined && typeof node.variant === "string") {
    /* Значение примера: там тег уже свёрнут в вариант без полей
       («дано ф равно функция «Удвоить»» → `{ variant: "Удвоить", fields: {} }`).
       Узел-конструктор сюда не попадает — у него есть `kind`, — и это важно:
       вариант, названный как функция, тегом от этого не становится. */
    note(node.variant)
  }
  for (const value of Object.values(node)) walk(value, note)
}
