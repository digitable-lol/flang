/**
 * target-plan.mjs — граница печати по `план`у: цель либо печатает его, либо отказывает.
 *
 * ── Улика, ради которой это заведено ────────────────────────────────────────
 *
 * `flang emit web/shortener/klient.flang --target js` (приложение из 32
 * тотальных функций) кончался **кодом 0, без единой диагностики**, и печатал
 * все функции приложения, включая обе функции плана — начальное состояние и
 * шаг. Самого объявления
 *
 *   план «Стойка ссылок»
 *     состояние «Стойка»
 *     начинает с «Начать»
 *     обрабатывает «Дальше»
 *
 * в напечатанном модуле не было: НОЛЬ БАЙТ. Снаружи получался набор функций,
 * про который нельзя узнать, что это программа ввода-вывода, кто в ней начало и
 * кто шаг. Ровно тот же исход, что был у процессов до `требуетПланировщика`
 * (`src/conc.mjs`), и ровно так же он выглядел успехом.
 *
 * ── Почему файл лежит ЗДЕСЬ, а не в `conc.mjs` и не в `src/emit/` ──────────
 *
 * Напрашивался именно `conc.mjs`: там лежит таблица возможностей целей и оба
 * соседних сторожа — `требуетПланировщика` и `требуетХозяина`. Держать три
 * сторожа в двух местах — это одно знание в двух файлах, и разъезжается оно
 * молча.
 *
 * Перевесил замер, а не вкус. `conc.mjs` лежит в РАБОЧЕМ ПУТИ — в том наборе из
 * двадцати файлов JavaScript, который поднимается в процесс на обычном
 * `flang check` (`flang/test/rabochiy-put.test.mjs`). У этого набора есть
 * потолок, и правило у потолка одностороннее: число может только падать, потому
 * что каждый переключённый на flang слой его опускает. Сторож, положенный в
 * `conc.mjs`, поднял его со 29 722 строк до 29 822 — и покраснел ровно тем
 * тестом, который для этого и стоит.
 *
 * А печать в рабочий путь не входит вовсе: `flang/src/emit/` поднимается только
 * командой `emit`. Значит место границы печати — здесь, и это не обход правила,
 * а его применение: JavaScript, который язык из себя вытесняет, не должен
 * прирастать ради работы, которая к вычислению отношения не имеет.
 *
 * В `src/emit/` файл тоже лежать не может, и это не вкус: каталог — РЕЕСТР
 * бэкендов (`bin/flang.mjs`, `emitTargets`), всякий `.mjs` в нём считается ещё
 * одной целью печати, и общий файл стал бы там девятой «целью». Ровно по этой
 * причине здесь же, а не там, лежит сосед `target-occupied.mjs` — и он же
 * задаёт имя: это правило ЦЕЛИ, общее для всех восьми.
 *
 * Что за это заплачено, названо ниже — полем `план` в таблице возможностей
 * целей, которого теперь нет.
 */

import { flangError } from "./builtins.mjs"

/**
 * Код отказа печати, когда в программе объявлен `план`, а исполнить его в
 * напечатанном коде нечем.
 *
 * Третий код рядом с двумя, и третий он не для полноты. `FLANG_CONC_UNSUPPORTED`
 * — про процессы, `FLANG_IO_UNSUPPORTED` — про `поручить` внутри процесса, а
 * план — ни то ни другое: это ВХОДНАЯ ТОЧКА программы ввода-вывода. Слить его с
 * соседями значило бы сказать «у цели нет планировщика» там, где планировщик
 * как раз есть, — и отправить читателя чинить не то.
 */
export const PLAN_UNSUPPORTED_CODE = "FLANG_PLAN_UNSUPPORTED"

/**
 * Цели печати, которые умеют напечатать `план` — вход программы ввода-вывода.
 *
 * ── Почему список написан, а не выведен из таблицы возможностей ─────────────
 *
 * Два соседних списка в `conc.mjs` ВЫВОДЯТСЯ из таблицы, и довод там сильный:
 * список и таблица — одно знание, а двум спискам этого знания хватило бы, чтобы
 * разойтись молча. Здесь поля `план` в таблице нет, и вот почему: таблица лежит
 * в рабочем пути, у которого потолок ходит только вниз (см. шапку файла).
 *
 * Цена этого названа прямо: в выводе `flang emit` поля `возможности.план` нет,
 * то есть машиночитаемая граница языка про план молчит. Разъехаться списку с
 * поведением при этом негде, и держит это не таблица, а проверка:
 * `flang/test/emit-plan-refuse.test.mjs` берёт цели из КАТАЛОГА `src/emit`,
 * печатает каждой программу с планом и требует, чтобы напечатавшие совпали с
 * этим списком ровно, а остальные отказали названным кодом. Девятая цель
 * попадёт под проверку тем, что появится файл, а не тем, что кто-то вспомнит
 * про список.
 *
 * Поле вернётся в таблицу тогда же, когда рабочий путь опустится настолько,
 * что двенадцать строк в нём перестанут быть платой.
 */
export const ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА = Object.freeze(["js"])

/**
 * Отказ печати, если в программе объявлен `план`, а напечатать его нечем.
 *
 * Живёт в бэкенде, а не в команде, по той же причине, что два соседних сторожа:
 * бэкенды — библиотека, их зовут напрямую из Node, и отказ в `bin/flang.mjs`
 * закрыл бы только командную строку.
 *
 * @param {object} program AST flang
 * @param {string} цель идентификатор цели печати (имя модуля в `src/emit`)
 * @throws {Error} с кодом `FLANG_PLAN_UNSUPPORTED`, если печатать план нечем
 */
export function требуетИсполнителяПлана(program, цель) {
  if (ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА.includes(цель)) return
  const планы = Array.isArray(program?.plans) ? program.plans : []
  if (планы.length === 0) return
  const первый = планы[0]
  throw flangError(
    PLAN_UNSUPPORTED_CODE,
    `у цели «${цель}» нет исполнителя плана, а в программе объявлен план «${первый?.name ?? "?"}» ` +
      `(состояние «${первый?.state ?? "?"}», начинает с «${первый?.initial ?? "?"}», ` +
      `обрабатывает «${первый?.handler ?? "?"}»)` +
      (планы.length > 1 ? ` и ещё ${планы.length - 1}` : "") +
      `. Объявление плана в «${цель}» напечатать нечем: функции начала и шага стали бы обычными ` +
      `функциями, которых никто не зовёт, и напечатанный модуль умел бы считать, но не работать. ` +
      `Цели с исполнителем плана: ${ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА.join(", ")}`,
    первый?.span ?? null,
  )
}
