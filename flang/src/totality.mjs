/**
 * Имя результата в постусловии, когда автор не связал его сам.
 *
 * То же значение и по той же причине, что у вычислителя (`interpret.mjs`,
 * `DEFAULT_RESULT_BINDING`) и у типизатора: область видимости постусловия
 * обязана быть одна на все три слоя, иначе анализ обошёл бы не то выражение,
 * которое посчитает вычислитель.
 */
const RESULT_BINDING = "результат"

/** Имя постусловия для сообщения; безымянное бывает только в AST руками. */
function postLabel(post) {
  return typeof post.name === "string" && post.name.length > 0 ? post.name : "без имени"
}

/**
 * Анализ завершаемости программы.
 *
 * @param {object} program AST модуля (SPEC, раздел 5)
 * @returns {{ ok: boolean, diagnostics: object[], total: Set<string>,
 *   guards: object[], descents: object[], structures: object[], cycles: string[][] }}
 *   `total` — функции, помеченные `тотальная`, для которых завершение
 *   доказано. Непомеченные функции не анализируются (за них отвечает лимит
 *   шагов интерпретатора), поэтому их в множестве нет никогда.
 *   `cycles` — компоненты сильной связности, внутри которых есть цикл: ровно
 *   те функции, у которых доказывать было ЧТО. Возвращаются потому, что без
 *   них снаружи нельзя отличить «доказано композицией» (рекурсии нет, обещание
 *   складывается из тотальных вызовов) от «доказано структурой» (рекурсия есть,
 *   и убывает часть значения): и то и другое приходит сюда без единого сторожа
 *   и без единой диагностики. Считать это второй раз снаружи значило бы
 *   держать второй граф вызовов — и разойтись с этим на первом же `применить`.
 *   `structures` — рёбра, доказанные структурным убыванием, с позицией и именем
 *   аргумента, который убывает. По той же причине, что `cycles`: снаружи
 *   назвать этот аргумент нечем, а «доказано структурой» без имени аргумента —
 *   это отчёт, который нельзя перепроверить чтением программы.
 */
export function checkTotality(program) {
  const diagnostics = []
  const report = (code, message, node) => {
    diagnostics.push({ code, message, severity: "error", span: spanOf(node) })
  }

  const functions = new Map()
  for (const fn of Array.isArray(program?.functions) ? program.functions : []) {
    if (typeof fn?.name === "string" && fn.name.length > 0 && !functions.has(fn.name)) functions.set(fn.name, fn)
  }

  const totalNames = new Set()
  for (const [name, fn] of functions) if (fn.total === true) totalNames.add(name)

  /* Теги программы по арности — конечный список случаев диспетчера
     `применить`. Считается один раз на всю программу (место, где тег построен,
     к тому, где он применён, отношения не имеет) и ЛЕНИВО: сбор требует обхода
     всей программы, а спрашивают о нём только применения. Программа без
     функций-значений не платит за них ни миллисекунды — на связанном
     компиляторе из 1275 функций это разница между 40 мс и 140 мс. */
  let tagTable = null
  const tags = () => (tagTable ??= tagsByArity(program, functions))

  // Собираем вызовы только из тотальных функций: обычные не анализируются.
  const calls = []
  for (const name of totalNames) {
    const fn = functions.get(name)
    const params = paramNames(fn)
    const env = new Map()
    params.forEach((paramName, index) => env.set(paramName, parameterOrigin(index, paramName)))
    const state = { from: name, params, calls, tags, functions }
    collectCalls(fn.body, env, state)
    /* Мера — тоже код, и код этот ИСПОЛНЯЕТСЯ: сторож считает её на каждом
       витке. Не обойди её здесь — и `убывает «Медленно» от н`, где «Медленно»
       обычная, дало бы тотальную функцию, которая виснет в собственном
       доказательстве. Обходится тем же проходом и на тех же правах, поэтому и
       самовызов из меры (`убывает «НОД» от а и б`) становится обычным ребром
       цикла, каким он и является. */
    if (fn.decreases !== null && typeof fn.decreases === "object") {
      collectCalls(fn.decreases, env, { ...state, inMeasure: true })
    }
    /* Постусловие — тоже код, и код этот ИСПОЛНЯЕТСЯ: `stepPost` считает его
       ПОСЛЕ КАЖДОГО возврата (`interpret.mjs`), и пока оно не посчитано, вызов
       не состоялся. Значит завершение вызова — это завершение тела И завершение
       каждого постусловия, и обходить их разными правилами нельзя: обещание
       `тотальная` покрывает вызов целиком, а не его половину. Не обойди их
       здесь — и `обеспечивает «п» «Вечная» от результат`, где «Вечная» обычная,
       дало бы тотальную функцию, которая виснет в собственном обещании, и
       `flang check` не сказал бы об этом ни слова.

       Довод тот же, что у меры строкой выше, и он не про постусловия и не про
       меры, а про одно: обещание, которое ВЫЧИСЛЯЕТСЯ, отвечает за своё
       вычисление наравне с телом.

       ОБЛАСТЬ ВИДИМОСТИ ВЗЯТА У ВЫЧИСЛИТЕЛЯ, А НЕ ВЫДУМАНА. `stepPost` кладёт
       результат ПОВЕРХ окружения вызова (`env[property.bind] = frame.result` на
       `Object.create(frame.env)`), поэтому и здесь `bind` кладётся поверх
       параметров: сойдись имя параметра с именем результата — оба слоя поймут
       его одинаково, и параметр перестанет быть виден под своим именем в обоих.
       Происхождение у результата `null`: про значение, которое вызов только что
       построил, не известно ничего — та же запись, что у результата любого
       другого вызова (шапка, «теряется там, где значение строится»). */
    for (const post of Array.isArray(fn.postconditions) ? fn.postconditions : []) {
      if (post === null || typeof post !== "object") continue
      const inner = new Map(env)
      inner.set(typeof post.bind === "string" ? post.bind : RESULT_BINDING, null)
      collectCalls(post.expr, inner, { ...state, inPostcondition: postLabel(post) })
    }
  }

  const failed = new Set()
  const edges = []

  for (const call of calls) {
    const callee = functions.get(call.to)
    /* Место вызова названо В САМОМ СООБЩЕНИИ, а не оставлено на `span`, и это
       не многословие. Услышав «тотальная функция «Ф» вызывает обычную», автор
       пойдёт искать вызов в тело — а в теле его нет: `обеспечивает` стоит НАД
       телом и читается как объявление, а не как код. Ровно на этом обещание и
       протекало, поэтому сообщение обязано сказать, что вычисляемое обещание
       тоже код. На вызове из тела обе вставки пусты, и текст остаётся прежним
       знак в знак: старые сообщения ничего не потеряли. */
    const вПостусловии = call.inPostcondition === undefined ? "" : ` в постусловии «${call.inPostcondition}»`
    const частьВызова = call.inPostcondition === undefined
      ? ""
      : ". Постусловие считается после каждого возврата, значит вызов из него — часть вызова"
        + ` «${call.from}», а не заметка рядом с ним`
    if (!callee) {
      // Неизвестное имя — отдельная беда (её называет types.mjs), но для нас
      // важно другое: про завершение такой функции сказать нечего.
      report("FLANG_NOT_TOTAL", `тотальная функция «${call.from}» вызывает неизвестную функцию «${call.to}»${вПостусловии}: завершение доказать нельзя${частьВызова}`, call.node)
      failed.add(call.from)
      continue
    }
    if (!totalNames.has(call.to)) {
      /* Через применение беда та же, а починка другая: «пометьте вызываемую
         тотальной» верно и здесь, но человеку надо знать, что путь идёт через
         значение-функцию, — иначе он будет искать вызов и не найдёт его. */
      report(
        "FLANG_NOT_TOTAL",
        call.applied === true
          ? `тотальная функция «${call.from}» применяет значение-функцию «${call.to}»${вПостусловии}, а «${call.to}» обычная: она может не завершиться, и гарантия «${call.from}» становится пустой${частьВызова}. Пометьте «${call.to}» как тотальную или снимите «тотальная» с «${call.from}»`
          : `тотальная функция «${call.from}» вызывает обычную функцию «${call.to}»${вПостусловии}: обычная функция может не завершиться, и гарантия «${call.from}» становится пустой${частьВызова}. Пометьте «${call.to}» как тотальную или снимите «тотальная» с «${call.from}»`,
        call.node,
      )
      failed.add(call.from)
      continue
    }
    edges.push({ ...call, calleeParams: paramNames(callee) })
  }

  const guards = []
  const descents = []
  const structures = []
  const exact = []
  const cycles = []
  const точные = точныеИмена(program)
  for (const component of stronglyConnectedComponents([...totalNames], edges)) {
    checkComponent(component, edges, failed, report, guards, descents, functions, structures, exact, точные)
    /* Признак цикла — тот же самый, по которому `checkComponent` решает, есть
       ли здесь что доказывать: хотя бы одно ребро внутри компоненты. Считается
       он здесь заново, а не возвращается из `checkComponent`, чтобы порядок
       проверок в ней не зависел от учёта. */
    const members = new Set(component)
    if (edges.some((edge) => members.has(edge.from) && members.has(edge.to))) cycles.push(component)
  }

  // Недоказанность заразна: если «А» зовёт «Б», а «Б» не доказана, то и
  // «А» не доказана. Диагностику при этом не дублируем — причина названа
  // один раз, в месте, где её можно починить.
  let growing = true
  while (growing) {
    growing = false
    for (const edge of edges) {
      if (failed.has(edge.to) && !failed.has(edge.from)) {
        failed.add(edge.from)
        growing = true
      }
    }
  }

  const total = new Set([...totalNames].filter((name) => !failed.has(name)))
  /* Стеречь незачем то, что и так не доказано: у недоказанной функции гарантии
     нет, и завершение ей обеспечивает лимит шагов, а не мера. */
  return {
    ok: diagnostics.length === 0,
    diagnostics,
    total,
    guards: guards.filter((guard) => total.has(guard.from)),
    descents: descents.filter((descent) => total.has(descent.from)),
    structures: structures.filter((item) => total.has(item.from)),
    /* Рёбра, у которых постоянный шаг доказан СТАТИЧЕСКИ — на точном
       натуральном типе. Возвращаются по той же причине, что `structures`:
       снаружи их не отличить от стережённых иначе как вторым анализом. */
    exact: exact.filter((item) => total.has(item.from)),
    /* По той же причине, что и сторожа: у недоказанной компоненты обещания нет,
       и называть её рекурсию «доказанной структурой» было бы неправдой. Цикл
       берётся целиком или не берётся вовсе — половина компоненты не цикл. */
    cycles: cycles.filter((component) => component.every((name) => total.has(name))),
  }
}

