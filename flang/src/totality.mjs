/* Компоненты сильной связности и проверка цикла                       */
/* ------------------------------------------------------------------ */

function checkComponent(component, edges, failed, report, guards, descents, functions, structures = [], exact = [], точные = ТОЧНЫЕ_ИМЕНА) {
  const members = new Set(component)
  const inner = edges.filter((edge) => members.has(edge.from) && members.has(edge.to))
  // Компонента из одной функции без самовызова — не цикл: доказывать нечего.
  if (inner.length === 0) return

  const decreasing = inner.map((edge) => ({ edge, positions: decreasingPositions(edge) }))
  const silent = decreasing.filter((item) => item.positions.length === 0)

  /* Объявленная мера пробуется ПОСЛЕДНЕЙ, а не первой, и это важно: вывод
     анализа для всякой программы без `убывает` обязан остаться прежним
     байт в байт. Порядок «структура → постоянный шаг → объявленная мера»
     означает ещё и то, что объявить меру там, где доказывает структура, не
     значит начать платить за сторожа: дешёвое доказательство побеждает. */
  const объявлена = component.every((name) => measureOf(functions.get(name)) !== null)

  if (silent.length > 0) {
    if (объявлена) return declareDescent(component, inner, functions, failed, report, descents)
    for (const { edge } of silent) {
      report("FLANG_NOT_TOTAL", explainNoDescent(edge, component), edge.node)
      failed.add(edge.from)
    }
    /* Мера объявлена не у всех — назвать недостающих обязательно: без этого
       автор, написавший `убывает` у одной функции цикла, видит отказ и не
       видит, что чинить. */
    reportPartialMeasure(component, functions, report, inner[0].node)
    for (const name of component) failed.add(name)
    return
  }

  /* Общая позиция ищется отдельно среди структурных убываний и отдельно среди
     мер: смешать их значило бы склеить два несовместимых порядка (см. шапку). */
  const структурой = commonPositions(decreasing, false)
  if (структурой.length > 0) {
    /* Сторожить здесь нечего: цепочка частей конечного дерева обрывается сама,
       и рантайм об этом доказательстве не узнаёт ничего. Позиция называется
       наружу не для сторожа, а для отчёта: «доказано структурой» без имени
       убывающего аргумента нельзя перепроверить чтением программы. Позиция
       ПЕРВАЯ общая — по той же причине, что у меры ниже: доказательство держится
       на любой одной, и называть остальные значило бы обещать больше сделанного. */
    const position = структурой[0]
    for (const { edge } of decreasing) {
      structures.push({ position, from: edge.from, to: edge.to, param: edge.params[position] ?? null })
    }
    return
  }

  /* Доказано мерой — значит доказано на числах, а не на double. Разница между
     ними наблюдаема (шапка, «Где это доказательство упирается в IEEE-754»),
     поэтому позиция, на которой держится доказательство, называется наружу:
     понижение поставит на ней сторожа, и обещание станет проверяемым в самой
     программе, а не только на бумаге. Берётся ПЕРВАЯ общая позиция — их может
     быть несколько, но доказательство держится на любой одной, и сторожить
     остальные значило бы платить за то же обещание дважды. */
  const мерой = commonPositions(decreasing, true)
  if (мерой.length > 0) {
    /* ТОЧНЫЙ НАТУРАЛЬНЫЙ ТИП СНИМАЕТ СТОРОЖА, и это единственная причина, по
       которой он заведён.
     *
     * Сторож стоит здесь не от недоверия к доказательству, а от IEEE-754:
     * рассуждение «шаг постоянен, дно есть, значит цепочка обрывается» верно
     * для вещественных чисел, а на double `х минус 1` при большом |х| равно
     * самому х, и цепочка не двигается вовсе (шапка файла). Обе дыры этого
     * рассуждения закрывает объявление `принимает н: нат`:
     *
     *   ДНО даёт сам тип — 0, — и брать его из `если` больше не нужно;
     *   ПОТОЛОК даёт сам тип — 2^53−1, — и внутри него `н минус c` при целом
     *   c ≥ 1 ТОЧНО: соседние целые там различимы, шаг не теряется никогда.
     *
     * Цепочка н, н−c, н−2c, … обрывается не позже чем через ⌈н/c⌉ витков, и
     * это доказано о ВСЕХ входах, а не проверено на одном. Сторожить нечего:
     * вход, на котором шаг не сработал бы, типом уже отвергнут.
     *
     * ЧЕМ ЭТО ДЕРЖИТСЯ. Тем, что аргумент на этой позиции ПРОВЕРЕН типизатором
     * при каждом вызове: `нат` не принимает ни дробного, ни отрицательного, ни
     * вышедшего за 2^53−1. Здесь анализ завершаемости впервые опирается на
     * проверку типов — раньше он не читал типов вовсе (шапка, «Циклы»).
     * Опора названа вслух, потому что она настоящая: снимите проверку типов, и
     * это доказательство станет неверным.
     */
    const position = мерой[0]
    if (точнаяПозиция(position, decreasing, functions, точные)) {
      for (const { edge } of decreasing) {
        exact.push({
          position,
          from: edge.from,
          to: edge.to,
          param: edge.params[position] ?? null,
          step: шагРебра(edge, position),
        })
      }
      return
    }
    for (const { edge } of decreasing) {
      guards.push({
        node: edge.node,
        position,
        from: edge.from,
        to: edge.to,
        param: edge.params[position],
        arg: edge.args[position],
        applied: edge.applied === true,
      })
    }
    return
  }

  // Ни один из двух даровых порядков не сошёлся — остаётся объявленная мера.
  if (объявлена) return declareDescent(component, inner, functions, failed, report, descents)

  // Каждое ребро где-то убывает, но общей позиции нет — см. контрпример
  // в шапке файла: такой цикл может быть бесконечным.
  const detail = decreasing
    .map(({ edge, positions }) => `«${edge.from}» → «${edge.to}» убывает по ${positions.map((item) => argumentLabel(edge, item.position)).join(", ")}`)
    .join("; ")
  report(
    "FLANG_NOT_TOTAL",
    `в цикле ${component.map((name) => `«${name}»`).join(" → ")} нет аргумента, который убывает на каждом вызове: ${detail}. Нужен один и тот же убывающий аргумент на всех рёбрах цикла`,
    decreasing[0].edge.node,
  )
  reportPartialMeasure(component, functions, report, decreasing[0].edge.node)
  for (const name of component) failed.add(name)
}

