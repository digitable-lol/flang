/**
 * Имена типов, означающих точное натуральное, вместе с псевдонимами программы.
 *
 * Псевдоним — второе имя, а не новый тип (`тип «Счётчик» это нат`), и не
 * пройти по ним значило бы наказывать автора за то, что он назвал своё понятие
 * своим словом. Проход идёт до неподвижной точки: псевдоним псевдонима — тоже
 * псевдоним.
 */
function точныеИмена(program) {
  const имена = new Set(ТОЧНЫЕ_ИМЕНА)
  const объявления = Array.isArray(program?.types) ? program.types : []
  let растёт = true
  while (растёт) {
    растёт = false
    for (const объявление of объявления) {
      if (объявление?.kind !== "alias" || typeof объявление.name !== "string") continue
      if (имена.has(объявление.name)) continue
      if (!точноеИмя(объявление.of ?? объявление.type, имена)) continue
      имена.add(объявление.name)
      растёт = true
    }
  }
  return имена
}

/** Написан ли этот тип точным натуральным. */
function точноеИмя(тип, имена) {
  if (typeof тип === "string") return имена.has(тип)
  if (!тип || typeof тип !== "object") return false
  /* `нат или ничто` натуральным не является: `ничто` вычесть нельзя. Имя
     состояния (`state: true`) — маркер доказательства, а не тип значения.
     Применение (`args`) у скаляра невозможно, но проверить дешевле, чем
     доказывать, что невозможно. */
  if (тип.optional === true || тип.state === true || Array.isArray(тип.args)) return false
  return typeof тип.name === "string" && имена.has(тип.name)
}

/** Объявлен ли параметр функции на этой позиции точным натуральным. */
function натуральныйПараметр(fn, position, имена) {
  const params = Array.isArray(fn?.params) ? fn.params : []
  if (position < 0 || position >= params.length) return false
  return точноеИмя(params[position]?.type, имена)
}

/**
 * Доказывается ли убывание на этой позиции СТАТИЧЕСКИ, без сторожа.
 *
 * Три условия, и каждое обязательно на КАЖДОМ ребре компоненты.
 *
 *   1. Позиция объявлена `нат` и у вызывающей, и у вызываемой. Хватило бы и
 *      одной — типизатор всё равно сверит аргумент с объявлением вызываемой, —
 *      но проверять обе дешевле, чем рассуждать о том, какая из них важнее, а
 *      в цикле из нескольких функций каждая бывает обеими.
 *   2. Шаг ЦЕЛЫЙ и не меньше единицы по величине. Дробный шаг (`минус 0.5`) на
 *      натуральном не только не точен — он выводит значение из типа, и первый
 *      же виток дал бы не-натуральное. Он остаётся со сторожем, как и был.
 *   3. Шаг-параметр (`н минус ш`) обязан сам быть натуральным. Его
 *      положительность и неизменность вдоль цепочки уже доказаны выше
 *      (`invariantStep`), иначе позиция не попала бы в убывающие; здесь
 *      добавляется только целость, без которой ⌈н/ш⌉ не конечно.
 */
function точнаяПозиция(position, decreasing, functions, имена) {
  for (const { edge } of decreasing) {
    if (!натуральныйПараметр(functions.get(edge.from), position, имена)) return false
    if (!натуральныйПараметр(functions.get(edge.to), position, имена)) return false
    const origin = edge.origins[position]
    if (!origin) return false
    if (origin.stepParam === null) {
      if (!Number.isInteger(origin.step) || origin.step > -1) return false
      continue
    }
    if (origin.step !== 0) return false
    if (!натуральныйПараметр(functions.get(edge.from), origin.stepParam, имена)) return false
  }
  return true
}

/**
 * Шаг ребра словами — для ведомости.
 *
 * Отдаётся СТРОКОЙ, а не числом или именем: у литерального шага это «1», у
 * шага-параметра — «ш» в ёлочках, и решать, что из этого печатать, обязано
 * одно место. Иначе выбор пришлось бы повторять в ведомости, а её эталон на
 * самом языке повторил бы его третий раз — и тип «число или строка» пришлось бы
 * заводить ради одного поля.
 */
function шагРебра(edge, position) {
  const origin = edge.origins[position]
  if (!origin) return "?"
  if (origin.stepParam === null) return String(-origin.step)
  const имя = edge.params[origin.stepParam]
  return isName(имя) ? `«${имя}»` : "шаг"
}

function isName(значение) {
  return typeof значение === "string" && значение.length > 0
}

/** Позиции заданного способа, убывающие на КАЖДОМ ребре компоненты. */
function commonPositions(decreasing, measure) {
  return decreasing[0].positions
    .filter((item) => item.measure === measure)
    .map((item) => item.position)
    .filter((position) => decreasing.every(({ positions }) =>
      positions.some((item) => item.measure === measure && item.position === position)))
}

function argumentLabel(edge, position) {
  const caller = edge.params[position] ?? `#${position + 1}`
  return `аргументу ${position + 1} (параметр «${caller}»)`
}

function explainNoDescent(edge, component) {
  const reasons = edge.origins.map((origin, index) => {
    const shown = describeExpr(edge.args[index])
    const callerParam = edge.params[index]
    if (!origin) return `аргумент ${index + 1} (${shown}) не выведен ни из одного параметра`
    const выведено = origin.depth !== null ? "часть" : "мера"
    if (origin.param !== index) {
      return `аргумент ${index + 1} (${shown}) — ${выведено} параметра «${origin.name}», а сравнивается с параметром «${callerParam ?? "?"}» на своей позиции`
    }
    if (origin.depth !== null) {
      if (origin.depth === 0) return `аргумент ${index + 1} (${shown}) — это сам параметр «${origin.name}», а не его часть`
      return `аргумент ${index + 1} (${shown}) убывает`
    }
    return measureReason(origin, index, shown, edge)
  })
  const действие = edge.applied === true ? "применение значения-функции" : "вызов"
  const cycle = edge.from === edge.to
    ? (edge.applied === true ? `применение значения-функции «${edge.to}» к самой себе` : `рекурсивный вызов «${edge.to}»`)
    : `${действие} «${edge.to}» в цикле ${component.map((name) => `«${name}»`).join(" → ")}`
  const hint = "Передавайте часть аргумента: хвост списка из образца «голова и хвост», поле варианта из образца, поле записи или элемент коллекции"
  return `тотальная функция «${edge.from}»: ${cycle} не убывает — ${reasons.join("; ") || "у вызова нет аргументов"}. ${hint}`
}

/**
 * Почему числовая мера не доказывает завершение. Разбор идёт по шагу, а не по
 * границе, потому что чинить надо разное: нулевой и растущий шаг — это
 * переписать вызов, отсутствие границы — дописать проверку.
 */
function measureReason(origin, index, shown, edge) {
  if (origin.stepParam !== null) return parametricReason(origin, index, shown, edge)
  if (origin.step < 0) {
    if (origin.bounded) return `аргумент ${index + 1} (${shown}) убывает по мере`
    return `аргумент ${index + 1} (${shown}) уменьшает параметр «${origin.name}», но снизу «${origin.name}» ничем не ограничен: добавьте проверку вида «если ${origin.name} не больше 0»`
  }
  if (origin.step > 0) return `аргумент ${index + 1} (${shown}) увеличивает параметр «${origin.name}»`
  return `аргумент ${index + 1} (${shown}) не уменьшает параметр «${origin.name}»: шаг нулевой`
}

/**
 * То же самое для шага-параметра. Условий у него на одно больше, поэтому
 * названы оба недостающих сразу: чинятся они в разных местах программы —
 * дно приписывают к мере, а положительность и неизменность к шагу.
 */
function parametricReason(origin, index, shown, edge) {
  const step = edge.params[origin.stepParam] ?? `#${origin.stepParam + 1}`
  const head = `аргумент ${index + 1} (${shown}) уменьшает параметр «${origin.name}» на «${step}»`
  if (!origin.bounded) {
    return `${head}, но снизу «${origin.name}» ничем не ограничен: добавьте проверку вида «если ${origin.name} не больше 0»`
  }
  return `${head}, но про «${step}» не доказано, что он больше нуля и приходит в вызов неизменным: `
    + `добавьте проверку вида «если ${step} не больше 0» и передавайте «${step}» аргументом ${origin.stepParam + 1} как есть`
}

/**
 * Компоненты сильной связности. Замыкание достижимости, а не алгоритм
 * Тарьяна: функций в модуле десятки, зато код очевидно верен и читается
 * без разбора стека.
 */
function stronglyConnectedComponents(nodes, edges) {
  const reach = new Map(nodes.map((node) => [node, new Set()]))
  for (const edge of edges) reach.get(edge.from)?.add(edge.to)
  let growing = true
  while (growing) {
    growing = false
    for (const node of nodes) {
      for (const middle of [...reach.get(node)]) {
        for (const far of reach.get(middle) ?? []) {
          if (!reach.get(node).has(far)) {
            reach.get(node).add(far)
            growing = true
          }
        }
      }
    }
  }
  const seen = new Set()
  const components = []
  for (const node of nodes) {
    if (seen.has(node)) continue
    const component = nodes.filter((other) => other === node
      || (reach.get(node).has(other) && reach.get(other).has(node)))
    for (const member of component) seen.add(member)
    components.push(component)
  }
  return components
}

