/**
 * ── Подтипизация: `нат` ≤ `целое` ≤ `число` ─────────────────────────────────
 *
 * До этой работы отношения совместимости в языке было ровно одно — `sameType`,
 * то есть РАВЕНСТВО. Введение второго отношения — изменение доктрины, и цена ей
 * названа числом: из 35 мест, где стоял `sameType`, на `годится` переведены 10
 * — ровно те, где значение ВТЕКАЕТ в объявленную позицию (тело против
 * `возвращает`; мера; аргумент вызова; аргумент применения; операнд арифметики
 * и сцепления; поле варианта; тело свёртки против накопителя; образец-литерал
 * против разбираемого; аргумент встроенной формы; элемент в `добавить`).
 * Остальные 25 `sameType` остались равенством и обязаны им остаться: там
 * сверяются НОСИТЕЛИ
 * (моноид, монада, изоморфизм, состояние процесса), а носитель у `нат` и
 * `число` ОДИН И ТОТ ЖЕ — тот самый IEEE-754 double. Это не совпадение, а то,
 * ради чего уточнение сделано уточнением: восемь генераторов, самоприменение и
 * побайтовая сверка не заметили ни одного изменения.
 *
 * Направление у `годится` есть, и оно единственное: `годится(данный,
 * ожидаемый)`. Порядок аргументов у прежнего `sameType` в файле неоднороден
 * (он симметричен, и это было незаметно), поэтому каждое из десяти мест
 * выверено поимённо, а не заменой по образцу.
 */
function годится(actual, expected) {
  if (!actual || !expected) return true
  if (actual.kind === "unknown" || expected.kind === "unknown") return true
  if (числовой(actual) && числовой(expected)) return вложен(actual, expected)
  /* Список — единственный ковариантный конструктор языка, и он вправе им быть:
     значения flang неизменяемы (SPEC, раздел 2), `добавить` строит новый
     список, и записать в `список нат` число неоткуда. Запись, сумма и функция
     остаются инвариантными: у них есть места, где значение и читается, и
     кладётся. */
  if (actual.kind === "list" && expected.kind === "list") return годится(actual.of, expected.of)
  return sameType(actual, expected)
}

function sameType(a, b) {
  if (!a || !b) return true
  if (a.kind === "unknown" || b.kind === "unknown") return true
  if (a.kind !== b.kind) return false
  if (a.kind === "list") return sameType(a.of, b.of)
  /*
   * Функции сравниваются ИНВАРИАНТНО: и по аргументам, и по результату — на
   * совпадение, а не на пригодность. Подтипов в flang нет вообще, `sameType`
   * везде означает равенство, и заводить их ради одного вида типа значило бы
   * получить два разных отношения совместимости в одном языке.
   */
  if (a.kind === "fn") {
    const left = fnParams(a)
    const right = fnParams(b)
    if (left.length !== right.length) return false
    return left.every((item, index) => sameType(item, right[index])) && sameType(a.returns, b.returns)
  }
  /* Параметр равен только сам себе: внутри полиморфной функции «А» — это
     конкретный, но неизвестный тип, и подставить вместо неё число нельзя. */
  if (a.kind === "param") return a.name === b.name
  if (a.kind === "record" || a.kind === "sum") return a.name === b.name && sameArgs(a.args, b.args)
  return true
}

/** Аргументы применения. Отсутствие аргументов и пустой список — одно и то же:
 *  так обычный тип сравнивается с обычным ровно как раньше. */
function sameArgs(a, b) {
  const left = Array.isArray(a) ? a : []
  const right = Array.isArray(b) ? b : []
  if (left.length !== right.length) return false
  return left.every((item, index) => sameType(item, right[index]))
}

/* Экспортируется ради наведения в редакторе: сигнатуру функции там показывает
   языковой сервер, и называть типы он обязан теми же словами, какими называет
   их диагностика. Иначе у языка появился бы второй словарь — тот же довод, по
   которому оболочка печатает значения поверхностью языка. */
export function typeName(type) {
  if (!type) return "неизвестный тип"
  if (type.optional === true) return `${typeName({ ...type, optional: false })} или ничто`
  switch (type.kind) {
    case "number": return числовоеИмя(type)
    case "string": return "строка"
    case "boolean": return "признак"
    case "null": return "ничто"
    // «список числа», а не «список число»: так тип пишется в исходнике
    // (SPEC, раздел 3), и сообщение можно скопировать в объявление.
    case "list": return `список ${genitive(type.of)}`
    // Печатается тем же оборотом, каким пишется в исходнике: «Возможно» от
    // числа. Сообщение об ошибке можно скопировать в объявление.
    case "record": case "sum": return `«${type.name}»${appliedTo(type)}`
    case "param": return `«${type.name}»`
    // Печатается тем же оборотом, каким пишется в исходнике: «функция из числа
    // и строки в признак». Сообщение об ошибке можно скопировать в объявление.
    case "fn": return `функция${acceptedFrom(type)} в ${accusative(type.returns)}`
    default: return "неизвестный тип"
  }
}

/**
 * Как назвать числовой тип.
 *
 * Имён у чисел ТРИ, а не столько, сколько бывает отрезков: в объявлении можно
 * написать `нат`, `целое` и `число`, и диагностика обязана говорить теми же
 * словами, какими пишется объявление, — иначе сообщение нельзя скопировать в
 * программу. Посчитанный отрезок называется поэтому самым узким из трёх имён,
 * в которое он вкладывается: `[0, 10]` — это `нат`, `[−5, 5]` — это `целое`,
 * `[0.5, 1]` — это `число`.
 *
 * Что при этом теряется: точные границы посчитанного отрезка наружу не
 * выходят. Это сознательно. Сообщение «ожидался нат, получен целое» читается и
 * чинится; сообщение «ожидался [0, 9007199254740991], получен [−1,
 * 9007199254740990]» — нет, и чинить по нему пришлось бы, считая степени двойки
 * в уме.
 */
function числовоеИмя(type) {
  if (!целыйЛи(type)) return "число"
  if (низОт(type) >= 0 && верхОт(type) <= ТОЧНЫЙ_ПОТОЛОК) return "нат"
  if (низОт(type) >= ТОЧНОЕ_ДНО && верхОт(type) <= ТОЧНЫЙ_ПОТОЛОК) return "целое"
  return "число"
}

function appliedTo(type) {
  if (!Array.isArray(type.args) || type.args.length === 0) return ""
  return ` от ${type.args.map(genitive).join(" и ")}`
}

function acceptedFrom(type) {
  const params = fnParams(type)
  if (params.length === 0) return ""
  return ` из ${params.map(genitive).join(" и ")}`
}

const GENITIVE = new Map([["number", "числа"], ["string", "строки"], ["boolean", "признака"], ["null", "ничего"]])

/* Родительный падеж уточнённых имён. `нат` не склоняется — это сокращение, как
   «ℕ», и «список нат» читается ровно так же, как «список числа». `целое`
   склоняется обычным прилагательным. */
const GENITIVE_ЧИСЛА = new Map([["число", "числа"], ["нат", "нат"], ["целое", "целого"]])

function genitive(type) {
  if (!type) return "неизвестного"
  if (type.kind === "number") return GENITIVE_ЧИСЛА.get(числовоеИмя(type))
  if (GENITIVE.has(type.kind)) return GENITIVE.get(type.kind)
  if (type.kind === "list") return `списка ${genitive(type.of)}`
  if (type.kind === "record" || type.kind === "sum") return `«${type.name}»${appliedTo(type)}`
  if (type.kind === "param") return `«${type.name}»`
  /* Вложенный тип функции берётся в скобки и остаётся в именительном падеже —
     потому что в исходнике он и пишется так: `функция из (функция из числа в
     число) в число`. Скобки там обязательны (иначе внутреннее `в` съело бы
     внешнее), значит сообщение и исходник совпадают дословно. */
  if (type.kind === "fn") return `(${typeName(type)})`
  return "неизвестного"
}

/** Винительный падеж после `в`: среди скаляров отличается только строка. */
function accusative(type) {
  if (type?.kind === "string" && type.optional !== true) return "строку"
  if (type?.kind === "fn") return `(${typeName(type)})`
  return typeName(type)
}

/** Скаляр ли: только по скалярам разрешено сравнение на равенство. */
function isScalarType(type) {
  return type.kind === "number" || type.kind === "string" || type.kind === "boolean" || type.kind === "null"
}

