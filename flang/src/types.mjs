/* Морфизмы: стрелки категорий и их композиция                         */
/* ------------------------------------------------------------------ */

/**
 * Стыковка композиции — то немногое в теоркате, что компилятор ДОКАЗЫВАЕТ, а не
 * проверяет на примерах: `«в» это «б» после «а»` собирается тогда и только
 * тогда, когда кодомен «а» совпадает с доменом «б». Это утверждение обо всех
 * входах, и оно не требует ни сетки, ни решателя.
 *
 * Порядок математический: правая применяется первой. Отсюда домен композиции —
 * домен правой, кодомен — кодомен левой.
 *
 * Объекты категории — это типы, поэтому домен и кодомен обязаны быть
 * объявленной записью, суммой или псевдонимом: стрелка в несуществующий объект
 * бессмысленна, и молчать об этом нельзя.
 */
function checkMorphisms(program, ctx) {
  const морфизмы = Array.isArray(program?.morphisms) ? program.morphisms : []
  if (морфизмы.length === 0) return

  const стрелки = new Map()
  const объявлен = (имя) =>
    ctx.records.has(имя) || ctx.sums.has(имя) || ctx.aliases.has(имя)

  /* Первый проход — только стрелки: композиция вправе ссылаться на морфизм,
     объявленный ниже, ровно как функция вправе звать функцию ниже себя. */
  for (const узел of морфизмы) {
    if (узел?.kind !== "morphism") continue
    for (const [роль, имя] of [["домен", узел.domain], ["кодомен", узел.codomain]]) {
      if (!объявлен(имя)) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `${роль} морфизма «${узел.name}» — «${имя}» — не объявлен: объект категории это тип`,
          узел,
        )
      }
    }
    if (стрелки.has(узел.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `морфизм «${узел.name}» объявлен дважды`, узел)
      continue
    }
    проверитьРеализацию(узел, ctx)
    стрелки.set(узел.name, { domain: узел.domain, codomain: узел.codomain })
  }

  /* Второй проход — композиции. Разрешаются по мере готовности: композиция от
     композиции законна, а цикл в определениях — ошибка, а не зависание. */
  const ждут = морфизмы.filter((узел) => узел?.kind === "composition")
  let сдвинулись = true
  while (сдвинулись && ждут.length > 0) {
    сдвинулись = false
    for (let i = ждут.length - 1; i >= 0; i -= 1) {
      const узел = ждут[i]
      const левая = стрелки.get(узел.left)
      const правая = стрелки.get(узел.right)
      if (левая === undefined || правая === undefined) continue

      ждут.splice(i, 1)
      сдвинулись = true

      if (правая.codomain !== левая.domain) {
        ctx.report(
          "FLANG_COMPOSE_MISMATCH",
          `композиция «${узел.name}» не стыкуется: «${узел.right}» приводит в «${правая.codomain}», ` +
            `а «${узел.left}» ожидает «${левая.domain}»`,
          узел,
        )
        continue
      }
      if (стрелки.has(узел.name)) {
        ctx.report("FLANG_DUPLICATE_NAME", `морфизм «${узел.name}» объявлен дважды`, узел)
        continue
      }
      стрелки.set(узел.name, { domain: правая.domain, codomain: левая.codomain })
    }
  }

  for (const узел of ждут) {
    const неизвестно = стрелки.has(узел.right) ? узел.left : узел.right
    ctx.report(
      "FLANG_UNKNOWN_NAME",
      `композиция «${узел.name}» ссылается на «${неизвестно}»: такого морфизма нет ` +
        `(или определения ходят по кругу)`,
      узел,
    )
  }

  ctx.morphisms = стрелки
}

/**
 * Реализация стрелки: `даёт «Имя функции»`, и закон при ней.
 *
 * ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ — сличением объявлений, без сетки и без вычислений:
 *
 *   1. названная функция объявлена;
 *   2. она принимает РОВНО один вход. Стрелка ведёт из одного объекта в один,
 *      и функция двух аргументов ей не соответствует: произведение объектов
 *      в языке есть (запись), и морфизм из пары пишется записью-доменом;
 *   3. тип входа — домен, тип результата — кодомен. Это то самое место, ради
 *      которого стрелка вообще нужна: имя «морфизм» без совпадения концов с
 *      функцией было бы украшением.
 *
 * ЧЕГО ЗДЕСЬ НЕ ДОКАЗЫВАЕТСЯ: сам закон. Он говорит о равенстве вычислений и
 * проверяется примерами автора при `flang test` (`compat.mjs`), а «проверено
 * на N примерах» — не «доказано»; граница проходит там же, где у моноида.
 *
 * Имена законов сверяются на повтор: два закона под одним именем сделали бы
 * отчёт неоднозначным ровно в тот момент, когда он нужен, — при падении.
 */
function проверитьРеализацию(узел, ctx) {
  const законы = Array.isArray(узел.laws) ? узел.laws : []
  const виделиЗакон = new Set()
  for (const закон of законы) {
    if (виделиЗакон.has(закон?.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `у морфизма «${узел.name}» два закона с именем «${закон.name}»`, закон ?? узел)
      continue
    }
    виделиЗакон.add(закон?.name)
  }

  if (typeof узел.gives !== "string" || узел.gives === "") return

  const сигнатура = ctx.signatures.get(узел.gives)
  if (сигнатура === undefined) {
    ctx.report(
      "FLANG_UNKNOWN_NAME",
      `морфизм «${узел.name}» даёт «${узел.gives}»: такой функции нет`,
      узел,
    )
    return
  }

  const входы = Array.isArray(сигнатура.params) ? сигнатура.params : []
  if (входы.length !== 1) {
    ctx.report(
      "FLANG_MORPHISM_SHAPE",
      `морфизм «${узел.name}» ведёт из одного объекта в один, а «${узел.gives}» ` +
        `принимает ${входы.length}: стрелке нужна функция ровно от одного входа`,
      узел,
    )
    return
  }

  /* Необъявленный конец уже назван выше своей диагностикой; нормализовать его
     значило бы сказать о той же беде второй раз другими словами. */
  const объявлен = (имя) => ctx.records.has(имя) || ctx.sums.has(имя) || ctx.aliases.has(имя)
  if (объявлен(узел.domain) && !sameType(входы[0].type, normalizeType(узел.domain, ctx, узел))) {
    ctx.report(
      "FLANG_MORPHISM_SHAPE",
      `морфизм «${узел.name}» ведёт из «${узел.domain}», а «${узел.gives}» ` +
        `принимает ${typeName(входы[0].type)}`,
      узел,
    )
  }
  if (объявлен(узел.codomain) && !sameType(сигнатура.returns, normalizeType(узел.codomain, ctx, узел))) {
    ctx.report(
      "FLANG_MORPHISM_SHAPE",
      `морфизм «${узел.name}» ведёт в «${узел.codomain}», а «${узел.gives}» ` +
        `возвращает ${typeName(сигнатура.returns)}`,
      узел,
    )
  }

  /* Значения примеров закона — против той же сигнатуры и той же проверкой,
     какой проверяются примеры функции. Иначе опечатка в имени входа доживала
     бы до `flang test` и приходила бы туда невнятным отказом вычисления
     вместо внятной ошибки модели. */
  for (const закон of законы) {
    checkExamples(закон, сигнатура, ctx, `закона «${закон?.name}» морфизма «${узел.name}»`)
  }
}

/**
 * Функтор: отображение объектов и стрелок, обязанное сохранять устройство.
 *
 * Объявление функтора в языке было и раньше — `функтор «Ф» из «A» в «B»` с
 * блоком `объект … отображается в …` и `морфизм … отображается в морфизм …`.
 * Не было проверки: слово «функтор» стояло, а гарантии за ним не стояло
 * никакой. Здесь появляется гарантия.
 *
 * ЗАКОНЫ НЕ ВКЛЮЧАЮТСЯ ПО ЖЕЛАНИЮ. В контракте была строка `сохраняет
 * композицию` — отдельное разрешение на проверку. Она не сделана намеренно:
 * отображение, не сохраняющее композицию, функтором не является, и дать
 * написать это слово без закона значило бы продать имя вместо содержания.
 *
 * ЧТО ИМЕННО ДОКАЗЫВАЕТСЯ, а не проверяется на примерах. Всё нижеследующее —
 * утверждения обо всех входах, и берутся они из одних объявлений, без сетки и
 * без решателя. Это возможно ровно потому, что морфизм здесь объявление, а не
 * значение: у функций первого класса такой проверки не бывает.
 *
 *   1. согласование стрелки с объектами: если «ф» ведёт из «A» в «B», то её
 *      образ обязан вести из образа «A» в образ «B». Ровно та же стыковка, что
 *      у композиции, только через отображение;
 *   2. сохранение композиции: образ композиции обязан быть композицией образов
 *      в том же порядке;
 *   3. сохранение единиц: образ тождественного морфизма объекта обязан быть
 *      тождественным морфизмом его образа;
 *   4. отображение объектов однозначно — иначе это не функция.
 *
 * Чего проверка НЕ делает и делать не может: имена категорий («из «Продажи» в
 * «Биллинг»») остаются пометкой для читателя. Категория в языке не объявляется
 * отдельной сущностью, и утверждать, что объект принадлежит именно этой
 * категории, не на чем.
 */
/**
 * Моноид: то в нём, что ДОКАЗЫВАЕТСЯ.
 *
 * Здесь проверяется устройство, а не законы: операция обязана быть функцией
 * двух аргументов носителя, возвращающей носитель; единица обязана быть
 * значением носителя; обращение, если объявлено, — функцией носителя в
 * носитель. Это утверждения обо всех входах, и берутся они из объявлений.
 *
 * Сами законы — ассоциативность, нейтральность, обратимость — так проверить
 * НЕЛЬЗЯ: это утверждения о равенстве вычислений на всех значениях носителя, а
 * равенство вычислений неразрешимо. Они проверяются на конечной сетке
 * (`flang/src/monoid.mjs`), и путать одно с другим нельзя — ровно об этом
 * раздел «Граница честности» в контракте.
 *
 * Отдельного понятия «группа» нет: группа это моноид с обращением. Второе
 * слово развело бы две проверки, которые обязаны совпадать во всём, кроме
 * одного закона.
 */
function checkMonoids(program, ctx) {
  const моноиды = Array.isArray(program?.monoids) ? program.monoids : []
  if (моноиды.length === 0) return

  const видели = new Map()
  for (const узел of моноиды) {
    if (видели.has(узел.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `моноид «${узел.name}» объявлен дважды`, узел)
      continue
    }
    видели.set(узел.name, узел)

    const носитель = узел.carrier
    проверитьОперацию(узел, носитель, ctx)
    проверитьЕдиницу(узел, носитель, ctx)
    if (узел.inverse !== null) проверитьОбращение(узел, носитель, ctx)
  }
  ctx.monoids = видели
}

function проверитьОперацию(узел, носитель, ctx) {
  const signature = ctx.signatures.get(узел.operation)
  if (!signature) {
    ctx.report("FLANG_UNKNOWN_NAME", `моноид «${узел.name}»: операции «${String(узел.operation)}» нет`, узел)
    return
  }
  if (signature.params.length !== 2) {
    ctx.report(
      "FLANG_MONOID",
      `моноид «${узел.name}»: операция «${signature.name}» принимает ${signature.params.length} арг., а обязана два — ` +
        `операция моноида соединяет два значения носителя в одно`,
      узел,
    )
    return
  }
  for (const [номер, параметр] of signature.params.entries()) {
    if (!sameType(параметр.type, носитель)) {
      ctx.report(
        "FLANG_TYPE",
        `моноид «${узел.name}»: аргумент ${номер + 1} операции «${signature.name}» имеет тип ${typeName(параметр.type)}, ` +
          `а носитель объявлен как ${typeName(носитель)}`,
        узел,
      )
    }
  }
  if (!sameType(signature.returns, носитель)) {
    ctx.report(
      "FLANG_TYPE",
      `моноид «${узел.name}»: операция «${signature.name}» возвращает ${typeName(signature.returns)}, ` +
        `а носитель объявлен как ${typeName(носитель)} — операция обязана не выводить из носителя`,
      узел,
    )
  }
}

function проверитьЕдиницу(узел, носитель, ctx) {
  const тип = inferExpr(узел.unit, new Map(), null, ctx, `моноид «${узел.name}»`)
  if (тип.kind !== "unknown" && !sameType(тип, носитель)) {
    ctx.report(
      "FLANG_TYPE",
      /* Носитель называется НОСИТЕЛЕМ, а не уточнением: моноид объявляется над
         `число`, и сказать «единица имеет тип нат» значило бы ответить не на
         тот вопрос. Разговор здесь про носитель — им же и меряется, `sameType`
         выше. Ровно та же причина, по которой этот `sameType` не стал
         `годится`: у моноида нет направления, у него есть равенство. */
      `моноид «${узел.name}»: единица имеет тип ${typeName(расширить(тип))}, а носитель объявлен как ${typeName(носитель)}`,
      узел,
    )
  }
}

function проверитьОбращение(узел, носитель, ctx) {
  const signature = ctx.signatures.get(узел.inverse)
  if (!signature) {
    ctx.report("FLANG_UNKNOWN_NAME", `моноид «${узел.name}»: обращения «${String(узел.inverse)}» нет`, узел)
    return
  }
  if (signature.params.length !== 1) {
    ctx.report(
      "FLANG_MONOID",
      `моноид «${узел.name}»: обращение «${signature.name}» принимает ${signature.params.length} арг., а обязано один`,
      узел,
    )
    return
  }
  if (!sameType(signature.params[0].type, носитель) || !sameType(signature.returns, носитель)) {
    ctx.report(
      "FLANG_TYPE",
      `моноид «${узел.name}»: обращение «${signature.name}» обязано вести из ${typeName(носитель)} в ${typeName(носитель)}, ` +
        `а ведёт из ${typeName(signature.params[0].type)} в ${typeName(signature.returns)}`,
      узел,
    )
  }
}

/**
 * Монада: устройство ДОКАЗЫВАЕТСЯ, законы проверяются вычислением.
 *
 * Граница здесь проходит там же, где у моноида, и по той же причине. Из
 * объявлений решается всё, что говорит о ФОРМЕ: тип объявлен и параметричен;
 * названный параметр у него есть; `возврат` ведёт из «А» в M«А»; `соединение`
 * ведёт из M(M«А») в M«А» с одной и той же «А». Это утверждения обо всех
 * входах, и сетка им не нужна.
 *
 * Сюда же попадает то, чего у моноида нет вовсе: **выводимость отображения**.
 * Монада — эндофунктор плюс η и μ, а объявлены только η и μ; отображение
 * компилятор берёт из устройства типа, и оно существует ровно тогда, когда
 * параметр стоит в поле целиком. Поэтому «параметр внутри списка» — это отказ
 * ЗДЕСЬ, а не сюрприз при разворачивании первого же блока `в монаде`.
 *
 * Законы (левая единица, правая, ассоциативность связывания) — равенства
 * вычислений на всех значениях, и они проверяются на конечной сетке в
 * `flang/src/monad.mjs`, как ассоциативность моноида. Путать нельзя: об этом
 * раздел «Граница честности» в `flang/cat/SPEC.md`.
 */
function checkMonads(program, ctx) {
  const монады = Array.isArray(program?.monads) ? program.monads : []
  if (монады.length === 0) return

  const видели = new Map()
  for (const узел of монады) {
    if (видели.has(узел.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `монада «${узел.name}» объявлена дважды`, узел)
      continue
    }
    видели.set(узел.name, узел)

    const устройство = устройствоМонады(узел, program.types)
    if (устройство.беда !== undefined) {
      ctx.report("FLANG_MONAD", `монада «${узел.name}»: ${устройство.беда}`, узел)
      continue
    }
    const позиция = (устройство.тип.typeParams ?? []).indexOf(узел.param)
    проверитьВозврат(узел, позиция, ctx)
    проверитьСоединение(узел, позиция, ctx)
  }
  ctx.monads = видели
}

/** Применение объявленного типа монады с нужной арностью — и ничто другое. */
function применениеМонады(тип, узел, арность) {
  return тип?.kind === "sum" && тип.name === узел.name && (тип.args ?? []).length === арность
}

function проверитьВозврат(узел, позиция, ctx) {
  const signature = ctx.signatures.get(узел.unit)
  const арность = (ctx.typeParams.get(узел.name) ?? []).length
  if (!signature) {
    ctx.report("FLANG_UNKNOWN_NAME", `монада «${узел.name}»: возврата «${String(узел.unit)}» нет`, узел)
    return
  }
  if (signature.params.length !== 1) {
    ctx.report(
      "FLANG_MONAD",
      `монада «${узел.name}»: возврат «${signature.name}» принимает ${signature.params.length} арг., а обязан один — ` +
        `возврат заворачивает одно значение в «${узел.name}»`,
      узел,
    )
    return
  }
  if (!применениеМонады(signature.returns, узел, арность)) {
    ctx.report(
      "FLANG_MONAD",
      `монада «${узел.name}»: возврат «${signature.name}» возвращает ${typeName(signature.returns)}, ` +
        `а обязан вернуть «${узел.name}»`,
      узел,
    )
    return
  }
  const внутри = signature.returns.args[позиция]
  if (!sameType(внутри, signature.params[0].type)) {
    ctx.report(
      "FLANG_MONAD",
      `монада «${узел.name}»: возврат «${signature.name}» принимает ${typeName(signature.params[0].type)}, ` +
        `а кладёт на место «${узел.param}» тип ${typeName(внутри)} — это не «А» → «${узел.name}» от «А»`,
      узел,
    )
  }
}

function проверитьСоединение(узел, позиция, ctx) {
  const signature = ctx.signatures.get(узел.join)
  const арность = (ctx.typeParams.get(узел.name) ?? []).length
  if (!signature) {
    ctx.report("FLANG_UNKNOWN_NAME", `монада «${узел.name}»: соединения «${String(узел.join)}» нет`, узел)
    return
  }
  if (signature.params.length !== 1) {
    ctx.report(
      "FLANG_MONAD",
      `монада «${узел.name}»: соединение «${signature.name}» принимает ${signature.params.length} арг., а обязано один — ` +
        `соединение сплющивает одну двойную вложенность`,
      узел,
    )
    return
  }
  const принимает = signature.params[0].type
  if (!применениеМонады(принимает, узел, арность) || !применениеМонады(принимает.args[позиция], узел, арность)) {
    ctx.report(
      "FLANG_MONAD",
      `монада «${узел.name}»: соединение «${signature.name}» принимает ${typeName(принимает)}, ` +
        `а обязано принимать «${узел.name}» от («${узел.name}» от «${узел.param}»)`,
      узел,
    )
    return
  }
  if (!sameType(signature.returns, принимает.args[позиция])) {
    ctx.report(
      "FLANG_MONAD",
      `монада «${узел.name}»: соединение «${signature.name}» возвращает ${typeName(signature.returns)}, ` +
        `а сплющивает ${typeName(принимает)} — снявшись на один слой, тип обязан стать ` +
        `${typeName(принимает.args[позиция])}`,
      узел,
    )
  }
}

function checkFunctors(program, ctx) {
  const наследие = Array.isArray(program?.legacy) ? program.legacy : []
  const функторы = наследие.filter((узел) => узел?.construct === "functorFile")
  if (функторы.length === 0) return

  const стрелки = ctx.morphisms instanceof Map ? ctx.morphisms : new Map()
  const морфизмы = Array.isArray(program?.morphisms) ? program.morphisms : []
  /* Композиции берутся из исходных узлов, а не из `стрелки`: там от композиции
     остались только домен и кодомен, а закону нужны имена сомножителей. */
  const композиции = new Map()
  for (const узел of морфизмы) {
    if (узел?.kind === "composition") композиции.set(узел.name, узел)
  }
  const единицы = new Map()
  for (const узел of морфизмы) {
    if (узел?.kind === "morphism" && узел.identity === true) единицы.set(узел.name, узел.domain)
  }

  for (const { value: функтор, span } of функторы) {
    const узел = { span }
    const образОбъекта = new Map()
    for (const пара of функтор.objects ?? []) {
      if (образОбъекта.has(пара.from)) {
        ctx.report(
          "FLANG_FUNCTOR_OBJECT_TWICE",
          `функтор «${функтор.name}»: объект «${пара.from}» отображается дважды — ` +
            `в «${образОбъекта.get(пара.from)}» и в «${пара.to}»; отображение объектов обязано быть однозначным`,
          узел,
        )
        continue
      }
      образОбъекта.set(пара.from, пара.to)
    }

    const образМорфизма = new Map()
    for (const пара of функтор.morphisms ?? []) образМорфизма.set(пара.from, пара.to)

    /* Закон 1: стрелка согласована с объектами. */
    for (const пара of функтор.morphisms ?? []) {
      const исходная = стрелки.get(пара.from)
      const образ = стрелки.get(пара.to)
      if (исходная === undefined) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `функтор «${функтор.name}» отображает «${пара.from}», но такого морфизма нет`,
          узел,
        )
        continue
      }
      if (образ === undefined) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `функтор «${функтор.name}» отображает «${пара.from}» в «${пара.to}», но морфизма «${пара.to}» нет`,
          узел,
        )
        continue
      }
      for (const [роль, конец] of [["домен", "domain"], ["кодомен", "codomain"]]) {
        const объект = исходная[конец]
        if (!образОбъекта.has(объект)) {
          ctx.report(
            "FLANG_FUNCTOR_OBJECT_MISSING",
            `функтор «${функтор.name}» отображает морфизм «${пара.from}», но не отображает его ${роль} ` +
              `«${объект}»: без образа объекта образ стрелки не с чем согласовать`,
            узел,
          )
          continue
        }
        const ожидается = образОбъекта.get(объект)
        if (образ[конец] !== ожидается) {
          ctx.report(
            "FLANG_FUNCTOR_ARROW_MISMATCH",
            `функтор «${функтор.name}»: «${пара.from}» имеет ${роль} «${объект}», его образ — «${ожидается}», ` +
              `но «${пара.to}» имеет ${роль} «${образ[конец]}»`,
            узел,
          )
        }
      }
    }

    /* Закон 2: образ композиции — композиция образов, в том же порядке. */
    for (const [имя, композиция] of композиции) {
      if (!образМорфизма.has(имя)) continue
      const образЛевой = образМорфизма.get(композиция.left)
      const образПравой = образМорфизма.get(композиция.right)
      if (образЛевой === undefined || образПравой === undefined) {
        const без = образЛевой === undefined ? композиция.left : композиция.right
        ctx.report(
          "FLANG_FUNCTOR_COMPOSITION",
          `функтор «${функтор.name}» отображает композицию «${имя}», но не отображает «${без}», ` +
            `из которой она собрана: закон сохранения композиции проверить не на чем`,
          узел,
        )
        continue
      }
      const образКомпозиции = композиции.get(образМорфизма.get(имя))
      if (образКомпозиции === undefined) {
        ctx.report(
          "FLANG_FUNCTOR_COMPOSITION",
          `функтор «${функтор.name}»: образ композиции «${имя}» — «${образМорфизма.get(имя)}» — сам композицией не объявлен, ` +
            `а обязан быть «${образЛевой}» после «${образПравой}»`,
          узел,
        )
        continue
      }
      if (образКомпозиции.left !== образЛевой || образКомпозиции.right !== образПравой) {
        ctx.report(
          "FLANG_FUNCTOR_COMPOSITION",
          `функтор «${функтор.name}» не сохраняет композицию: образ «${имя}» обязан быть ` +
            `«${образЛевой}» после «${образПравой}», а объявлен как «${образКомпозиции.left}» после «${образКомпозиции.right}»`,
          узел,
        )
      }
    }

    /* Закон 3: образ единицы — единица образа. */
    for (const [имя, объект] of единицы) {
      if (!образМорфизма.has(имя)) continue
      if (!образОбъекта.has(объект)) continue
      const ожидается = `единица ${образОбъекта.get(объект)}`
      if (образМорфизма.get(имя) !== ожидается) {
        ctx.report(
          "FLANG_FUNCTOR_IDENTITY",
          `функтор «${функтор.name}» не сохраняет единицы: образ «${имя}» обязан быть «${ожидается}», ` +
            `а объявлен «${образМорфизма.get(имя)}»`,
          узел,
        )
      }
    }
  }
}

