/**
 * Двунаправленный вывод: `expected` — тип, которого ждёт контекст (или null).
 * Он нужен только там, где выражение само по себе неоднозначно (пустой
 * список), и как «якорь» для ветвей `если`/`разбор`, чтобы ошибка называла
 * объявленный тип, а не первую попавшуюся ветвь.
 */
function inferExpr(expr, env, expected, ctx, fnName) {
  if (!expr || typeof expr !== "object") {
    ctx.report("FLANG_TYPE", "ожидалось выражение", expr)
    return UNKNOWN
  }
  switch (expr.kind) {
    case "literal": return literalType(expr, ctx)
    case "var": return varType(expr, env, ctx)
    case "field": return fieldType(expr, env, ctx, fnName)
    case "let": {
      const valueType = inferExpr(expr.value, env, null, ctx, fnName)
      if (!isName(expr.name)) {
        ctx.report("FLANG_TYPE", "«пусть» требует имени", expr)
        return inferExpr(expr.in, env, expected, ctx, fnName)
      }
      const inner = new Map(env)
      inner.set(expr.name, valueType)
      return inferExpr(expr.in, inner, expected, ctx, fnName)
    }
    case "if": {
      const cond = inferExpr(expr.cond, env, BOOLEAN, ctx, fnName)
      if (!sameType(cond, BOOLEAN)) {
        ctx.report("FLANG_TYPE", `условие «если» должно быть признаком, а не ${typeName(cond)}`, expr.cond ?? expr)
      }
      /* Ветви видят РАЗНЫЕ среды: в `то` верно условие, в `иначе` — его
         отрицание, и оба утверждения о числах кладутся на имена границами. Это
         и есть вторая опора интервального анализа после литералов — та самая,
         на которой держится «граница видна статически». */
      const thenType = inferExpr(expr.then, сузить(expr.cond, env, true), expected, ctx, fnName)
      const elseType = inferExpr(expr.else, сузить(expr.cond, env, false), expected ?? thenType, ctx, fnName)
      /* Сверка ветвей осталась `sameType`, и это ровно то, что нужно: у ветвей
         нет направления, ни одна не «втекает» в другую, и требовать от них
         подтипизации значило бы отвергнуть `если … то 0 иначе н`. Носитель у
         них обязан быть один — а уточнения сводит объединение ниже. */
      if (!sameType(thenType, elseType)) {
        ctx.report("FLANG_TYPE", `ветви «если» разных типов: ${typeName(thenType)} и ${typeName(elseType)}`, expr)
        return expected ?? UNKNOWN
      }
      /* Тип `если` — ОБЪЕДИНЕНИЕ ветвей, а не первая из них. `если н не больше 0
         то 0 иначе н` при `н: нат` даёт `нат`, потому что обе ветви лежат в
         нём; взяв первую, анализ обещал бы `[0,0]` — то есть неправду. */
      if (thenType.kind === "unknown") return elseType
      if (elseType.kind === "unknown") return thenType
      return объединить(thenType, elseType)
    }
    case "call": return callType(expr, env, expected, ctx, fnName)
    case "fnref": return fnrefType(expr, ctx)
    case "apply": return applyType(expr, env, ctx, fnName)
    case "binary": return binaryType(expr, env, ctx, fnName)
    case "construct": return constructType(expr, env, expected, ctx, fnName)
    case "record": return recordType(expr, env, expected, ctx, fnName)
    case "list": return listType(expr, env, expected, ctx, fnName)
    case "match": return matchType(expr, env, expected, ctx, fnName)
    case "fold": return foldType(expr, env, ctx, fnName)
    case "map": return mapType(expr, env, expected, ctx, fnName)
    case "filter": return filterType(expr, env, ctx, fnName)
    case "builtin": return builtinType(expr, env, ctx, fnName)
    default:
      ctx.report("FLANG_TYPE", `неизвестный вид выражения «${String(expr.kind)}»`, expr)
      return UNKNOWN
  }
}

/**
 * Тип литерала.
 *
 * ЧИСЛОВОЙ ЛИТЕРАЛ ЗНАЕТ СЕБЯ ТОЧНО, и это главный источник границ во всём
 * анализе: целых литералов в корпусе 1140, и каждый из них — отрезок из одной
 * точки. Без этого правила `«Ф» от 5` не сказал бы про свой аргумент ничего, и
 * доказывать было бы не из чего.
 *
 * Расширение это, а не сужение: `5` по-прежнему годится всюду, где ждут
 * `число`, потому что `нат` в `число` вкладывается. Новым стало ровно
 * обратное — `5` годится и там, где ждут `нат`, а `5.5` и `−1` там не годятся.
 */
function literalType(expr, ctx) {
  const value = expr.value
  if (typeof value === "number" && Number.isFinite(value)) {
    return Number.isSafeInteger(value) ? отрезок(value, value, true) : NUMBER
  }
  if (typeof value === "string") return STRING
  if (typeof value === "boolean") return BOOLEAN
  if (value === null) return NOTHING
  ctx.report("FLANG_TYPE", `литерал ${JSON.stringify(value)} не является скаляром`, expr)
  return UNKNOWN
}

function varType(expr, env, ctx) {
  if (!isName(expr.name) || !env.has(expr.name)) {
    ctx.report("FLANG_UNKNOWN_NAME", `имя «${String(expr.name)}» не связано`, expr)
    return UNKNOWN
  }
  return env.get(expr.name)
}

function fieldType(expr, env, ctx, fnName) {
  const target = inferExpr(expr.target, env, null, ctx, fnName)
  if (target.kind === "unknown") return UNKNOWN
  if (target.kind !== "record") {
    ctx.report("FLANG_TYPE", `доступ к полю «${String(expr.field)}» требует записи, а не ${typeName(target)}`, expr)
    return UNKNOWN
  }
  const fields = ctx.records.get(target.name)
  if (!fields?.has(expr.field)) {
    ctx.report("FLANG_TYPE", `запись «${target.name}» не имеет поля «${String(expr.field)}»`, expr)
    return UNKNOWN
  }
  /* Поле параметрической записи объявлено в параметрах, а прочитано у
     конкретного применения: `«Пара» от числа и строки` даёт полю «первое»
     число, а не «А». Подстановка — здесь, потому что здесь известно и то и
     другое. */
  return substitute(fields.get(expr.field), bindingsOf(target, ctx))
}

function callType(expr, env, expected, ctx, fnName) {
  const signature = ctx.signatures.get(expr.name)
  const args = Array.isArray(expr.args) ? expr.args : []
  if (!signature) {
    ctx.report("FLANG_UNKNOWN_NAME", `неизвестная функция «${String(expr.name)}»`, expr)
    for (const arg of args) inferExpr(arg, env, null, ctx, fnName)
    return UNKNOWN
  }
  if (args.length !== signature.params.length) {
    ctx.report("FLANG_TYPE", `функция «${signature.name}» принимает ${signature.params.length} арг. (${signature.params.map((p) => `«${p.name}»`).join(", ") || "нет"}), а вызвана с ${args.length}`, expr)
  }
  const typeParams = signature.typeParams ?? []
  /* Аргументы типа не пишутся, а выводятся — и решается это слева направо, в
     порядке чтения. Уже связанное подставляется в ожидание следующего
     аргумента, поэтому пустой список во второй позиции получает тип, решённый
     первой: `«Приписать» от 7 и []` даёт список числа. */
  const bindings = new Map()
  /* Ожидание результата участвует и ДО аргументов, а не только после них — но
     ТОЛЬКО как подсказка вложенному выводу, в решение оно здесь не входит.

     Довод предъявлен программой, а не соображением. Форма `в монаде` над типом
     с ДВУМЯ параметрами разворачивается в `соединение от (вариант «Успех» с
     итог равным …)`, где у конструктора один параметр решается полем, а второй
     не решается ничем: по бокам от него в этом выражении ничего нет. Ожидание
     же его знает — оно приехало из `возвращает «Результат» от числа и строки`,
     — и раньше не доезжало, потому что параметрический тип аргумента гасил
     ожидание в null.

     Почему это безопасно: подсказка не участвует ни в `matchAgainst`, ни в
     `sameType` ниже — она лишь ДОБАВЛЯЕТ контекст, которого не было. Значит
     принять эта строка может больше прежнего, а отвергнуть — ровно столько же.
     Проверено сверкой с `self/types.flang` на всех программах репозитория и на
     сломанных программах из тестов: расхождений ноль. */
  const подсказка = new Map()
  if (typeParams.length > 0 && expected) matchAgainst(signature.returns, expected, подсказка)
  args.forEach((arg, index) => {
    const param = signature.params[index]
    const wanted = param ? substitute(param.type, bindings) : null
    const намёк = param && hasParams(wanted) ? substitute(param.type, new Map([...подсказка, ...bindings])) : wanted
    const actual = inferExpr(arg, env, hasParams(намёк) ? null : намёк, ctx, fnName)
    if (!param) return
    if (typeParams.length > 0) matchAgainst(param.type, actual, bindings)
    const settled = substitute(param.type, bindings)
    if (!годится(actual, settled)) {
      ctx.report("FLANG_TYPE", `аргумент «${param.name}» функции «${signature.name}»: ожидался ${typeName(settled)}, получен ${typeName(actual)}`, arg)
    }
  })
  if (typeParams.length === 0) return signature.returns
  /* Что не решилось аргументами, решает ожидание: у `функция «Ничего» от «А»
     возвращает «Возможно» от «А»` аргументов нет вовсе, и без этого шага она
     была бы невызываема. */
  if (typeParams.some((name) => !bindings.has(name)) && expected) {
    matchAgainst(signature.returns, expected, bindings)
  }
  reportUnsolved(typeParams, bindings, `вызов «${signature.name}»`, ctx, expr)
  return substitute(signature.returns, bindings)
}

