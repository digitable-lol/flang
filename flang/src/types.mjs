/** Сигнатура объявленной функции как тип значения. */
function signatureType(signature) {
  return { kind: "fn", params: signature.params.map((param) => param.type), returns: signature.returns }
}

/**
 * `функция «Удвоить»` — тег функции как значение.
 *
 * Полиморфная функция значением стать НЕ МОЖЕТ, и это отказ, а не пропуск.
 * `функция «Обернуть»` при `функция «Обернуть» от «А»` — это значение типа
 * `∀А. «А» → «Возможно» от «А»`, то есть ранг 2, а вывод в модуле —
 * одностороннее сопоставление первого порядка (шапка файла). Молчаливо взять
 * такое значение значило бы выпустить наружу тип с несвязанным параметром, а
 * он дальше сравнивался бы с чем попало.
 */
function fnrefType(expr, ctx) {
  const signature = ctx.signatures.get(expr.name)
  if (!signature) {
    ctx.report("FLANG_UNKNOWN_NAME", `неизвестная функция «${String(expr.name)}»`, expr)
    return UNKNOWN
  }
  const typeParams = signature.typeParams ?? []
  if (typeParams.length > 0) {
    ctx.report(
      "FLANG_TYPE_PARAM",
      `функция «${signature.name}» объявлена от ${countParams(typeParams.length)} и значением стать не может: ` +
        `у значения тип один, а у неё их столько, сколько подстановок`,
      expr,
    )
    return UNKNOWN
  }
  return signatureType(signature)
}

/**
 * Применение значения-функции: `ф от 5`.
 *
 * Отличается от вызова по имени ровно тем, что тип берётся не из таблицы
 * сигнатур, а из типа самого значения. Всё остальное — арность, типы
 * аргументов, тип результата — проверяется теми же словами, потому что беда
 * у пользователя та же самая.
 */
function applyType(expr, env, ctx, fnName) {
  const target = inferExpr(expr.fn, env, null, ctx, fnName)
  const args = Array.isArray(expr.args) ? expr.args : []
  const где = appliedName(expr.fn)
  if (target.kind !== "fn") {
    if (target.kind !== "unknown") {
      ctx.report("FLANG_APPLY", `применять можно только функцию, а ${где} имеет тип ${typeName(target)}`, expr)
    }
    for (const arg of args) inferExpr(arg, env, null, ctx, fnName)
    return UNKNOWN
  }
  const params = fnParams(target)
  if (args.length !== params.length) {
    ctx.report(
      "FLANG_APPLY",
      `${где} имеет тип ${typeName(target)}: применяется к ${countArgs(params.length)}, а применено к ${countArgs(args.length)}`,
      expr,
    )
  }
  args.forEach((arg, index) => {
    const wanted = params[index]
    const actual = inferExpr(arg, env, wanted && !hasParams(wanted) ? wanted : null, ctx, fnName)
    if (wanted === undefined) return
    if (!годится(actual, wanted)) {
      ctx.report("FLANG_TYPE", `аргумент ${index + 1} применения ${где}: ожидался ${typeName(wanted)}, получен ${typeName(actual)}`, arg)
    }
  })
  return target.returns ?? UNKNOWN
}

/** Как назвать применяемое в диагностике: у имени есть имя, у остального — вид. */
function appliedName(node) {
  if (node?.kind === "var" && isName(node.name)) return `«${node.name}»`
  if (node?.kind === "field" && isName(node.field)) return `поле «${node.field}»`
  if (node?.kind === "fnref" && isName(node.name)) return `«${node.name}»`
  if (node?.kind === "call" && isName(node.name)) return `результат «${node.name}»`
  return "применяемое"
}

function binaryType(expr, env, ctx, fnName) {
  const op = expr.op
  if (ARITHMETIC.has(op)) {
    const left = checkOperand(expr.left, env, NUMBER, ctx, fnName, op, "левый")
    const right = checkOperand(expr.right, env, NUMBER, ctx, fnName, op, "правый")
    /* Отрезок результата считается по отрезкам операндов. Ждут здесь по-прежнему
       `число` — самый широкий из трёх, — поэтому НИ ОДНА написанная программа не
       получает новой диагностики: арифметика принимает ровно столько же, сколько
       принимала. Изменилось только то, что она ОТДАЁТ. */
    return арифметика(op, left, right)
  }
  if (op === "concat") {
    checkOperand(expr.left, env, STRING, ctx, fnName, op, "левый")
    checkOperand(expr.right, env, STRING, ctx, fnName, op, "правый")
    return STRING
  }
  if (ORDERING.has(op)) {
    const left = inferExpr(expr.left, env, null, ctx, fnName)
    const right = inferExpr(expr.right, env, left, ctx, fnName)
    /*
     * Упорядочены ТОЛЬКО числа. Это не выбор проверки типов, а факт про язык:
     * порядок задан в одном месте — `compare` ядра FTS (`src/utility.ts`), и
     * оно бросает «сравнения порядка допустимы только для чисел» на всём
     * остальном. Ровно то же делают `interpret.mjs` (`order`) и печать в JS
     * (`$ord`). Пропуская сюда строки, проверка обещала бы то, чего ни один
     * исполнитель не умеет: программа проходила бы `check` и падала при
     * запуске. Лексикографический порядок строк пришлось бы сначала завести
     * в ядре — а до тех пор его здесь нет.
     */
    for (const [type, side, node] of [[left, "левый", expr.left], [right, "правый", expr.right]]) {
      if (type.kind !== "unknown" && type.kind !== "number") {
        ctx.report("FLANG_TYPE", `${side} операнд сравнения «${op}» имеет тип ${typeName(type)}: сравнения порядка допустимы только для чисел`, node ?? expr)
      }
    }
    if (!sameType(left, right)) {
      ctx.report("FLANG_TYPE", `сравнение «${op}» между ${typeName(left)} и ${typeName(right)}`, expr)
    }
    return BOOLEAN
  }
  if (EQUALITY.has(op)) {
    const left = inferExpr(expr.left, env, null, ctx, fnName)
    const right = inferExpr(expr.right, env, left, ctx, fnName)
    if (!sameType(left, right)) {
      ctx.report("FLANG_TYPE", `сравнение «${op}» между ${typeName(left)} и ${typeName(right)}`, expr)
    } else if (left.kind !== "unknown" && !isScalarType(left)) {
      ctx.report("FLANG_TYPE", `сравнивать на равенство можно только скаляры, а не ${typeName(left)}`, expr)
    }
    return BOOLEAN
  }
  ctx.report("FLANG_TYPE", `неизвестная операция «${String(op)}»`, expr)
  inferExpr(expr.left, env, null, ctx, fnName)
  inferExpr(expr.right, env, null, ctx, fnName)
  return UNKNOWN
}

function checkOperand(node, env, want, ctx, fnName, op, side) {
  const actual = inferExpr(node, env, want, ctx, fnName)
  if (!годится(actual, want)) {
    ctx.report("FLANG_TYPE", `${side} операнд «${op}»: ожидался ${typeName(want)}, получен ${typeName(actual)}`, node ?? undefined)
  }
  return actual
}

function constructType(expr, env, expected, ctx, fnName) {
  const owner = ctx.variantOwner.get(expr.variant)
  const given = expr.fields ?? {}
  /* Действие с адресатом: адресат сверяется с объявленными процессами, а тип
     груза берётся у адресата, а не из словаря действий — там он джокер, потому
     что полиморфизма в языке нет. */
  const адресат =
    owner === ACTION_TYPE_NAME && ACTION_PROCESS_FIELD[expr.variant] !== undefined && ctx.processes?.size > 0
      ? addresseeOf(expr, ctx)
      : null
  /* Продолжение плана: то же самое и по той же причине. Поле `потом` объявлено
     джокером, а тип у него есть — состояние, названное в объявлении `план`
     (`io.mjs`, `planStateType`). Без этой сверки `потом` не проверял никто, и
     программа с чужим типом в нём проходила `check`, а падала у хозяина. */
  const состояниеПлана =
    owner === CONTINUATION_TYPE_NAME && expr.variant === CONTINUE_DO ? ctx.planState ?? null : null
  if (!owner) {
    ctx.report("FLANG_UNKNOWN_NAME", `неизвестный конструктор варианта «${String(expr.variant)}»`, expr)
    for (const value of Object.values(given)) inferExpr(value, env, null, ctx, fnName)
    return UNKNOWN
  }
  const declared = ctx.sums.get(owner).get(expr.variant)
  const typeParams = ctx.typeParams.get(owner) ?? []
  const bindings = new Map()
  /* Ожидание — подсказка полю, а не решение за него; довод тот же, что в
     `callType`, и тот же тому счёт. `вариант «Успех» с итог равным («Удалось»
     от готово)` знает «Значение» по полю, а «Беда» не знает ниоткуда, кроме
     ожидания: в самом выражении её нет. */
  const подсказка = подсказкаИзОжидания({ kind: "sum", name: owner }, typeParams, expected)
  for (const [name, type] of declared) {
    if (!(name in given)) {
      ctx.report("FLANG_TYPE", `конструктор «${expr.variant}» требует поле «${name}» (${typeName(type)})`, expr)
      continue
    }
    /* Джокер словаря уступает место типу, известному из объявления: груз
       действия — объявленному `принимает` адресата, продолжение плана —
       объявленному `состояние`. Оба случая устроены одинаково, поэтому и
       записаны одним оборотом. */
    const изОбъявления =
      адресат !== null && name === "что" ? адресат.accepts
      : состояниеПлана !== null && name === "потом" ? состояниеПлана
      : null
    const wanted = изОбъявления ?? substitute(type, bindings)
    const намёк = hasParams(wanted) ? substitute(type, new Map([...подсказка, ...bindings])) : wanted
    const actual = inferExpr(given[name], env, hasParams(намёк) ? null : намёк, ctx, fnName)
    if (typeParams.length > 0) matchAgainst(type, actual, bindings)
    const settled = изОбъявления ?? substitute(type, bindings)
    if (!годится(actual, settled)) {
      ctx.report("FLANG_TYPE", `поле «${name}» варианта «${expr.variant}»: ожидался ${typeName(settled)}, получен ${typeName(actual)}`, given[name])
    }
    /* Результат плана: объявления нет, поэтому образцом становится первое
       встреченное значение, а сверяются с ним остальные (`io.mjs`,
       `planResultIsShared`). Утверждение — «у плана один результат», и оно
       проверяемо без нового слова в языке. */
    if (
      ctx.planResultShared === true &&
      owner === CONTINUATION_TYPE_NAME &&
      expr.variant === CONTINUE_DONE &&
      name === "значение" &&
      actual.kind !== "unknown"
    ) {
      if (ctx.planDone === null) {
        ctx.planDone = { type: actual, at: given[name] }
      } else if (!sameType(actual, ctx.planDone.type)) {
        ctx.report(
          "FLANG_TYPE",
          `у плана один результат, а «Конец работы» несёт то ${typeName(ctx.planDone.type)}, ` +
            `то ${typeName(actual)}: хозяин получит значение, которого не ждёт`,
          given[name],
        )
      }
    }
  }
  for (const name of Object.keys(given)) {
    if (!declared.has(name)) {
      ctx.report("FLANG_TYPE", `вариант «${expr.variant}» типа «${owner}» не имеет поля «${name}»`, expr)
      inferExpr(given[name], env, null, ctx, fnName)
    }
  }
  if (typeParams.length === 0) return { kind: "sum", name: owner }
  return solvedResult({ kind: "sum", name: owner }, typeParams, bindings, expected, `конструктор «${expr.variant}»`, ctx, expr)
}

function recordType(expr, env, expected, ctx, fnName) {
  const fields = ctx.records.get(expr.type)
  const given = expr.fields ?? {}
  if (!fields) {
    ctx.report("FLANG_UNKNOWN_NAME", `неизвестная запись «${String(expr.type)}»`, expr)
    for (const value of Object.values(given)) inferExpr(value, env, null, ctx, fnName)
    return UNKNOWN
  }
  const typeParams = ctx.typeParams.get(expr.type) ?? []
  const bindings = new Map()
  const подсказка = подсказкаИзОжидания({ kind: "record", name: expr.type }, typeParams, expected)
  for (const [name, type] of fields) {
    if (!(name in given)) {
      if (type.optional !== true) ctx.report("FLANG_TYPE", `запись «${expr.type}» требует поле «${name}» (${typeName(type)})`, expr)
      continue
    }
    const wanted = substitute(type, bindings)
    const намёк = hasParams(wanted) ? substitute(type, new Map([...подсказка, ...bindings])) : wanted
    const actual = inferExpr(given[name], env, hasParams(намёк) ? null : намёк, ctx, fnName)
    if (typeParams.length > 0) matchAgainst(type, actual, bindings)
    const settled = substitute(type, bindings)
    if (!sameType(actual, settled)) {
      ctx.report("FLANG_TYPE", `поле «${name}» записи «${expr.type}»: ожидался ${typeName(settled)}, получен ${typeName(actual)}`, given[name])
    }
  }
  for (const name of Object.keys(given)) {
    if (!fields.has(name)) {
      ctx.report("FLANG_TYPE", `запись «${expr.type}» не имеет поля «${name}»`, expr)
      inferExpr(given[name], env, null, ctx, fnName)
    }
  }
  if (typeParams.length === 0) return { kind: "record", name: expr.type }
  return solvedResult({ kind: "record", name: expr.type }, typeParams, bindings, expected, `запись «${expr.type}»`, ctx, expr)
}

/**
 * Что ожидание говорит о параметрах — до того, как поля скажут своё.
 *
 * Отдельно от `solvedResult`, потому что применяется РАНЬШЕ него и с другой
 * силой: `solvedResult` решает тип целиком и вправе жаловаться, а это —
 * односторонняя подсказка вложенному выводу, которая ни на что не жалуется и
 * ничего не решает. Пустая карта — законный ответ.
 */
function подсказкаИзОжидания(base, typeParams, expected) {
  const карта = new Map()
  if (typeParams.length === 0 || !expected) return карта
  matchAgainst({ ...base, args: typeParams.map((name) => ({ kind: "param", name })) }, expected, карта)
  return карта
}

/**
 * Тип построенного значения параметрического объявления: что не решили поля,
 * решает ожидание. Без второго шага `вариант «Ничего»` не имел бы типа вообще
 * — полей у него нет, а параметр есть. Это ровно тот случай, ради которого
 * проверка двунаправленная.
 */
function solvedResult(base, typeParams, bindings, expected, label, ctx, at) {
  if (typeParams.some((name) => !bindings.has(name)) && expected) {
    matchAgainst({ ...base, args: typeParams.map((name) => ({ kind: "param", name })) }, expected, bindings)
  }
  reportUnsolved(typeParams, bindings, label, ctx, at)
  return { ...base, args: typeParams.map((name) => bindings.get(name) ?? UNKNOWN) }
}

/**
 * Список однороден. Тип пустого списка берётся из контекста; если контекста
 * нет — `список неизвестного`, совместимый с любым списком. Это не «дырка»
 * в проверке: единственное, что можно сделать с пустым списком без контекста,
 * — вернуть его или передать дальше, и там контекст уже появится.
 */
function listType(expr, env, expected, ctx, fnName) {
  const items = Array.isArray(expr.items) ? expr.items : []
  const wanted = expected && expected.kind === "list" ? expected.of : null
  if (items.length === 0) return { kind: "list", of: wanted ?? UNKNOWN }

  let element = wanted
  items.forEach((item, index) => {
    const actual = inferExpr(item, env, element, ctx, fnName)
    if (!element || element.kind === "unknown") {
      element = actual
      return
    }
    if (!sameType(actual, element)) {
      ctx.report("FLANG_TYPE", `список неоднороден: элемент ${index + 1} имеет тип ${typeName(actual)}, а список — ${typeName(element)}`, item)
      return
    }
    /* Тип списка — ОБЪЕДИНЕНИЕ элементов, а не тип первого: `[0, 1, 2]` даёт
       `список нат`, `[0, −1]` — `список целого`, `[0, 0.5]` — `список числа`.
       Взяв первый, анализ обещал бы отрезок [0,0] на всём списке. */
    element = объединить(element, actual)
  })
  return { kind: "list", of: element ?? UNKNOWN }
}

