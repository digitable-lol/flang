/**
 * Процессы (flang/conc/SPEC.md, шаг 1).
 *
 * Проверяется то, ради чего процесс вообще объявлением, а не значением:
 * обработчик — обычная функция языка, и его сигнатуру можно сверить с
 * объявлением до запуска. Три утверждения проверяются здесь и все три —
 * утверждения обо всех входах, а не о примерах.
 *
 *   1. обработчик принимает ровно объявленный тип состояния и объявленный тип
 *      сообщения, в этом порядке;
 *   2. обработчик возвращает отклик — запись ровно из двух полей: «состояние»
 *      того же типа и «действия» — список «Действие»;
 *   3. обработчик без признака `тотальная` обязан назвать запас витков.
 *
 * Третье — ошибка, а не предупреждение, и это записано в контракте («Что
 * проверяется и чем», пункт 4). Причина не в строгости ради строгости:
 * обработчик, про который не известно ни что он завершается, ни сколько ему
 * отпущено, держит свой процесс неограниченно долго, и планировщику нечего
 * противопоставить. Предупреждение здесь означало бы «мы знаем, что программа
 * может встать, и разрешаем это молча».
 */
function checkProcesses(program, ctx) {
  const процессы = Array.isArray(program?.processes) ? program.processes : []
  ctx.processes = new Map()
  if (процессы.length === 0) return

  for (const узел of процессы) {
    if (!isName(узел?.name)) {
      ctx.report("FLANG_PROCESS", "объявление процесса требует имени", узел)
      continue
    }
    if (ctx.processes.has(узел.name)) {
      ctx.report("FLANG_PROCESS", `процесс «${узел.name}» объявлен дважды`, узел)
      continue
    }

    const состояние = namedOnly(узел.state, ctx, узел, `состояние процесса «${узел.name}»`)
    const сообщение = namedOnly(узел.accepts, ctx, узел, `тип сообщений процесса «${узел.name}»`)
    ctx.processes.set(узел.name, { node: узел, state: состояние, accepts: сообщение })

    /* Размер ящика (А3). Ноль отвергается наравне с дробью и минусом: ящик на
       ноль сообщений означал бы, что процессу нельзя отправить ничего, и такой
       процесс честнее не объявлять вовсе, чем объявить недостижимым. */
    if (узел.mailbox !== null && узел.mailbox !== undefined &&
        (!Number.isInteger(узел.mailbox) || узел.mailbox <= 0)) {
      ctx.report(
        "FLANG_PROCESS",
        `размер ящика процесса «${узел.name}» — ${узел.mailbox}: ожидалось целое положительное число`,
        узел,
      )
    }

    checkInitial(узел, состояние, ctx)
    checkHandler(узел, состояние, сообщение, ctx)
  }
}

/**
 * Начальное состояние — функция без параметров.
 *
 * Не литерал и не выражение: перезапуск обязан давать ровно то же значение, что
 * и первый запуск (контракт, «Отказ, надзор, перезапуск»), а функция без
 * параметров — самая короткая запись «одно и то же значение всякий раз»,
 * которая при этом проверяется по типу и печатается в C прямо.
 */
function checkInitial(узел, состояние, ctx) {
  const signature = ctx.signatures.get(узел.initial)
  if (!signature) {
    ctx.report(
      "FLANG_UNKNOWN_NAME",
      `процесс «${узел.name}» начинает с «${String(узел.initial)}», но такой функции нет`,
      узел,
    )
    return
  }
  if (signature.params.length !== 0) {
    ctx.report(
      "FLANG_PROCESS",
      `начальное состояние «${signature.name}» процесса «${узел.name}» принимает ${signature.params.length} арг.: ` +
        `начальное состояние — это значение, поэтому функция обязана быть без параметров`,
      узел,
    )
  }
  if (!sameType(signature.returns, состояние)) {
    ctx.report(
      "FLANG_TYPE",
      `начальное состояние «${signature.name}» процесса «${узел.name}» даёт ${typeName(signature.returns)}, ` +
        `а состояние объявлено как ${typeName(состояние)}`,
      узел,
    )
  }
}

function checkHandler(узел, состояние, сообщение, ctx) {
  const signature = ctx.signatures.get(узел.handler)
  if (!signature) {
    ctx.report(
      "FLANG_UNKNOWN_NAME",
      `процесс «${узел.name}» обрабатывает «${String(узел.handler)}», но такой функции нет`,
      узел,
    )
    return
  }

  if (signature.params.length !== 2) {
    ctx.report(
      "FLANG_TYPE",
      `обработчик «${signature.name}» процесса «${узел.name}» принимает ${signature.params.length} арг., ` +
        `а обязан принимать два: состояние и сообщение`,
      узел,
    )
  } else {
    const ожидается = [
      ["состояние", состояние],
      ["сообщение", сообщение],
    ]
    ожидается.forEach(([роль, тип], индекс) => {
      const параметр = signature.params[индекс]
      if (!sameType(параметр.type, тип)) {
        ctx.report(
          "FLANG_TYPE",
          `обработчик «${signature.name}» процесса «${узел.name}»: ${роль} объявлено как ${typeName(тип)}, ` +
            `а параметр «${параметр.name}» имеет тип ${typeName(параметр.type)}`,
          узел,
        )
      }
    })
  }

  checkResponse(узел, signature, состояние, ctx)

  /* Запас витков — единственный ответ на «обработчик может не завершиться»,
     который у планировщика есть. Нет доказательства и нет запаса — программа
     не собирается. */
  if (!signature.total && узел.budget === null) {
    ctx.report(
      "FLANG_HANDLER_NOT_TOTAL",
      `обработчик «${signature.name}» процесса «${узел.name}» не помечен тотальным, поэтому обязан назвать запас: ` +
        `«обрабатывает «${signature.name}» с запасом N витков». Без запаса и без доказательства завершения ` +
        `процесс может держать себя сколь угодно долго, и планировщику нечего этому противопоставить`,
      узел,
    )
  }
  if (узел.budget !== null && (!Number.isInteger(узел.budget) || узел.budget <= 0)) {
    ctx.report(
      "FLANG_PROCESS",
      `запас витков процесса «${узел.name}» — ${узел.budget}: ожидалось целое положительное число`,
      узел,
    )
  }
}

/** Отклик: запись ровно из «состояние» и «действия». */
function checkResponse(узел, signature, состояние, ctx) {
  const отклик = signature.returns
  if (!отклик || отклик.kind === "unknown") return
  if (отклик.kind !== "record") {
    ctx.report(
      "FLANG_TYPE",
      `обработчик «${signature.name}» процесса «${узел.name}» возвращает ${typeName(отклик)}, ` +
        `а обязан возвращать отклик — запись с полями «состояние» и «действия»`,
      узел,
    )
    return
  }
  const поля = ctx.records.get(отклик.name)
  if (!поля) return

  const состояниеОтклика = поля.get("состояние")
  if (состояниеОтклика === undefined) {
    ctx.report(
      "FLANG_TYPE",
      `отклик «${отклик.name}» обработчика «${signature.name}» не имеет поля «состояние»`,
      узел,
    )
  } else if (!sameType(состояниеОтклика, состояние)) {
    ctx.report(
      "FLANG_TYPE",
      `поле «состояние» отклика «${отклик.name}» имеет тип ${typeName(состояниеОтклика)}, ` +
        `а состояние процесса «${узел.name}» объявлено как ${typeName(состояние)}`,
      узел,
    )
  }

  const действия = поля.get("действия")
  if (действия === undefined) {
    ctx.report(
      "FLANG_TYPE",
      `отклик «${отклик.name}» обработчика «${signature.name}» не имеет поля «действия»`,
      узел,
    )
  } else if (действия.kind !== "list" || действия.of?.name !== ACTION_TYPE_NAME) {
    ctx.report(
      "FLANG_TYPE",
      `поле «действия» отклика «${отклик.name}» имеет тип ${typeName(действия)}, ` +
        `а обязано быть списком «${ACTION_TYPE_NAME}»`,
      узел,
    )
  }
}

/**
 * Имя типа и только имя: состояние и сообщение процесса обязаны быть
 * объявленной записью или суммой. Скаляр здесь запрещён намеренно — состояние
 * процесса, которое является числом, невозможно ни расширить, ни прочитать по
 * имени поля, а перезапуск такого процесса неотличим от его продолжения.
 */
function namedOnly(name, ctx, at, label) {
  if (!isName(name)) {
    ctx.report("FLANG_PROCESS", `${label} требует имени типа`, at)
    return UNKNOWN
  }
  if (ctx.records.has(name)) return { kind: "record", name }
  if (ctx.sums.has(name)) return { kind: "sum", name }
  if (ctx.aliases.has(name)) return expandAlias(name, ctx)
  ctx.report("FLANG_UNKNOWN_NAME", `${label}: неизвестный тип «${name}»`, at)
  return UNKNOWN
}

/**
 * Действие с адресатом: `отправить` и `через`.
 *
 * Здесь проверяется то, что делает объявление процесса не украшением, а
 * контрактом: адресат обязан быть объявленным процессом, а сообщение — того
 * типа, который этот процесс объявил в `принимает`. Тип поля «что» в словаре
 * действий — джокер (полиморфизма в языке нет), поэтому без этой сверки
 * отправка была бы нетипизированной вовсе.
 *
 * Адресат обязан быть литералом. Это ограничение шага 1, и оно записано в
 * контракте: имя процесса как значение (открытый вопрос «Именование процессов»)
 * ещё не решено, а проверять адресата, вычисленного в рантайме, нечем.
 *
 * Возвращает найденный процесс — его `принимает` становится ожидаемым типом
 * поля «что». Сверять груз здесь нельзя: `constructType` всё равно обойдёт поля
 * варианта, и второй проход по тому же выражению удвоил бы диагностики.
 */
function addresseeOf(expr, ctx) {
  const поле = ACTION_PROCESS_FIELD[expr.variant]
  /* У порождения тот же вопрос задаётся про ВИД, а не про адресата: `породить`
     заводит экземпляр объявленного вида, и `принимает` этого вида — тип первого
     сообщения. Слово в диагностике меняется вместе с полем, потому что «адресат
     обязан быть литералом» про `вид` читалось бы как ошибка компилятора. */
  const проИмя = поле === "вид" ? "вид порождаемого процесса" : "адресат"
  const адресат = (expr.fields ?? {})[поле]
  if (адресат === undefined) return null
  if (адресат.kind !== "literal" || typeof адресат.value !== "string") {
    ctx.report(
      "FLANG_PROCESS",
      `действие «${expr.variant}»: ${проИмя} обязан быть именем объявленного процесса, ` +
        `записанным прямо здесь — вычисленное имя проверить нечем`,
      адресат,
    )
    return null
  }
  const процесс = ctx.processes.get(адресат.value)
  if (процесс === undefined) {
    const известные = [...ctx.processes.keys()].map((имя) => `«${имя}»`).join(", ")
    ctx.report(
      "FLANG_UNKNOWN_PROCESS",
      `действие «${expr.variant}» ` +
        (поле === "вид" ? `порождает «${адресат.value}»` : `адресовано «${адресат.value}»`) +
        `, но такой процесс не объявлен` +
        (известные === "" ? "" : `; объявлены ${известные}`),
      expr,
    )
    return null
  }
  return процесс
}

/**
 * Надзор. Проверяется, что под надзором стоят объявленные процессы и надзоры и
 * что стратегия — одна из трёх названных контрактом.
 *
 * С шага 3 за объявлением стоит поведение (`flang/src/conc.mjs`), и от этого
 * проверок стало больше — ровно на те вопросы, на которые планировщик обязан
 * знать ответ ДО запуска, иначе решать пришлось бы произволом:
 *
 *   1. у процесса не больше одного надзора. Два надзора над одним процессом —
 *      два разных решения об одном отказе, и выбирать между ними было бы нечем;
 *   2. у надзора не больше одного надзора сверху — по той же причине, и это же
 *      делает «передать выше» однозначным;
 *   3. надзор не может оказаться выше самого себя. Иначе «передать выше» ходило
 *      бы по кругу, и отказ не доходил бы ни до какого исхода.
 *
 * Первые две проверяются по всей программе, а не внутри одного объявления:
 * `надзор «А»` и `надзор «Б»`, каждый из которых честно называет процесс один
 * раз, вместе дают ту же неоднозначность.
 */
function checkSupervisors(program, ctx) {
  const надзоры = Array.isArray(program?.supervisors) ? program.supervisors : []
  if (надзоры.length === 0) return
  const процессы = ctx.processes instanceof Map ? ctx.processes : new Map()

  const стратегия = (имя, узел, где) => {
    if (!STRATEGIES.includes(имя)) {
      ctx.report(
        "FLANG_PROCESS",
        `${где}: стратегия «${имя}» неизвестна; их три — ${STRATEGIES.map((s) => `«${s}»`).join(", ")}`,
        узел,
      )
    }
  }

  const объявленные = new Set(надзоры.map((узел) => узел.name))
  /* Кто над кем: имя подопечного → имя надзора. Обе таблицы нужны и после
     проверки — по ним планировщик находит, кому докладывать об отказе. */
  const надзорПроцесса = new Map()
  const надзорНадзора = new Map()

  const виденные = new Set()
  for (const узел of надзоры) {
    if (виденные.has(узел.name)) ctx.report("FLANG_PROCESS", `надзор «${узел.name}» объявлен дважды`, узел)
    виденные.add(узел.name)

    const подНадзором = new Set()
    for (const запись of узел.watch ?? []) {
      if (!процессы.has(запись.process)) {
        ctx.report(
          "FLANG_UNKNOWN_PROCESS",
          `надзор «${узел.name}» следит за «${запись.process}», но такой процесс не объявлен`,
          запись,
        )
      }
      if (подНадзором.has(запись.process)) {
        ctx.report(
          "FLANG_PROCESS",
          `надзор «${узел.name}» называет процесс «${запись.process}» дважды: стратегия обязана быть одна`,
          запись,
        )
      } else if (надзорПроцесса.has(запись.process)) {
        ctx.report(
          "FLANG_PROCESS",
          `процесс «${запись.process}» стоит под двумя надзорами — «${надзорПроцесса.get(запись.process)}» и ` +
            `«${узел.name}»: об одном отказе было бы два решения, и выбирать между ними нечем`,
          запись,
        )
      } else {
        надзорПроцесса.set(запись.process, узел.name)
      }
      подНадзором.add(запись.process)
      стратегия(запись.strategy, запись, `надзор «${узел.name}» за «${запись.process}»`)
    }

    for (const запись of узел.nested ?? []) {
      if (!объявленные.has(запись.supervisor)) {
        ctx.report(
          "FLANG_UNKNOWN_PROCESS",
          `надзор «${узел.name}» следит за надзором «${запись.supervisor}», но такой надзор не объявлен`,
          запись,
        )
      }
      if (запись.supervisor === узел.name) {
        ctx.report("FLANG_PROCESS", `надзор «${узел.name}» назван внутри самого себя`, запись)
      } else if (надзорНадзора.has(запись.supervisor)) {
        ctx.report(
          "FLANG_PROCESS",
          `надзор «${запись.supervisor}» стоит под двумя надзорами — «${надзорНадзора.get(запись.supervisor)}» и ` +
            `«${узел.name}»: «передать выше» вело бы сразу в две стороны`,
          запись,
        )
      } else {
        надзорНадзора.set(запись.supervisor, узел.name)
      }
      стратегия(запись.strategy, запись, `надзор «${узел.name}» за надзором «${запись.supervisor}»`)
    }

    const порог = узел.threshold
    if (порог === null || порог === undefined) continue
    стратегия(порог.otherwise, порог, `порог отказов надзора «${узел.name}»`)
    for (const [поле, подпись] of [["failures", "число отказов"], ["window", "окно в миллисекундах"]]) {
      if (!Number.isInteger(порог[поле]) || порог[поле] <= 0) {
        ctx.report(
          "FLANG_PROCESS",
          `порог отказов надзора «${узел.name}»: ${подпись} — ${порог[поле]}, ожидалось целое положительное число`,
          порог,
        )
      }
    }
  }

  /* Круг в надзоре: «А» под «Б», «Б» под «А». Отказ, дойдя до такого места,
     ходил бы по кольцу вместо того, чтобы кончиться исходом. */
  for (const узел of надзоры) {
    const пройденные = new Set([узел.name])
    let текущий = надзорНадзора.get(узел.name)
    while (текущий !== undefined) {
      if (пройденные.has(текущий)) {
        ctx.report(
          "FLANG_PROCESS",
          `надзор «${узел.name}» оказался выше самого себя: «передать выше» ходило бы по кругу`,
          узел,
        )
        break
      }
      пройденные.add(текущий)
      текущий = надзорНадзора.get(текущий)
    }
  }
  ctx.supervisedProcesses = надзорПроцесса
}

/**
 * Полнота надзора: непокрытый достижимый отказ — ошибка проверки
 * (`flang/conc/RESILIENCE.md`, шаг Г1).
 *
 * Это то, чего у OTP быть не может, и дело не в старании. В Erlang множество
 * отказов процесса открыто, сводить надзор не с чем, и «let it crash» — не
 * лихость, а единственный честный ответ на незнание. В flang это множество
 * замкнуто и вычислимо (`failures.mjs`), поэтому его можно свести с объявленной
 * политикой и потребовать покрытия ДО запуска.
 *
 * Что считается покрытием. Надзор объявляется на процесс целиком, а не на вид
 * отказа, значит покрыт процесс, который назван хоть в одном `надзор … процесс
 * «X» стратегия «…»`. Стратегия при этом любая, включая «передать выше», у
 * которого наверху никого: «отказ дошёл доверху» — определённый исход с именем,
 * а не молчание. Не покрыт — процесс, о чьём отказе решать НЕКОМУ: он остаётся
 * мёртвым до конца прогона, и узнать об этом можно только по итоговым
 * состояниям.
 *
 * Почему ошибка, а не предупреждение. Предупреждение здесь означало бы «мы
 * посчитали, чем этот процесс может упасть, увидели, что решать об этом некому,
 * и разрешаем это молча». Ровно та же причина, по какой ошибкой сделан
 * нетотальный обработчик без запаса витков.
 *
 * Процесс с ПУСТЫМ множеством отказов надзора не требует, и это вторая половина
 * той же мысли: у тотального обработчика с исчерпывающим разбором и без
 * частичных форм падать нечем, и требовать над ним надзора значило бы требовать
 * обряда. Надзор над ним не запрещён — он просто не обязателен.
 */
function checkFailureCoverage(program, ctx) {
  const процессы = Array.isArray(program?.processes) ? program.processes : []
  if (процессы.length === 0) return
  const подНадзором = ctx.supervisedProcesses instanceof Map ? ctx.supervisedProcesses : new Map()
  const отказы = достижимыеОтказы(program)

  /* Порядок объявления, а не порядок таблицы: диагностики одного исходника
     обязаны идти в одном и том же порядке, иначе их нельзя сверить. */
  for (const узел of процессы) {
    const найденные = отказы.get(узел?.name)
    if (найденные === undefined || найденные.length === 0) continue
    if (подНадзором.has(узел.name)) continue

    const перечень = найденные
      .map((отказ) => `${отказ.вид} (${отказ.почему})`)
      .join("; ")
    ctx.report(
      UNCOVERED_CODE,
      `процесс «${узел.name}» может отказать, а надзора над ним нет: ${перечень}. ` +
        `Решать об этом отказе некому — процесс останется мёртвым до конца прогона. ` +
        `Назовите его в надзоре: «надзор «…» процесс «${узел.name}» стратегия «…»»`,
      /* Место — точка отказа, а не объявление процесса: искать «элемент» в
         чужой функции по имени процесса было бы поиском вручную. `где` — это
         уже span, поэтому он заворачивается в узел, какого ждёт `spanOf`. */
      найденные[0]?.где ? { span: найденные[0].где } : узел,
    )
  }

  /* Начальное состояние — второй проход, и он НЕ смотрит на надзор. Отказ здесь
     случается на заводе процесса: процесса ещё нет, решать о нём некому, а
     перезапуск по контракту возвращает то же самое вычисленное значение,
     которого не получилось. Значит «допишите надзор» было бы неверным советом, и
     код у диагностики свой.

     Дыра, которую это закрывает, была предъявлена прогоном: `начинает с «нуль»`,
     где «нуль» берёт девятый элемент трёхэлементного списка, проходил проверки с
     нулём диагностик, а `runConcurrent` бросал `FLANG_BUILTIN_ARGS` НАРУЖУ — то
     есть отказ убивал всю программу, а не процесс, и множество отказов процесса
     было замкнуто только на вид. */
  const наЗаводе = отказыНачального(program)
  for (const узел of процессы) {
    const найденные = наЗаводе.get(узел?.name)
    if (найденные === undefined || найденные.length === 0) continue
    const перечень = найденные
      .map((отказ) => `${отказ.вид} (${отказ.почему})`)
      .join("; ")
    ctx.report(
      INITIAL_CODE,
      `начальное состояние «${узел.initial}» процесса «${узел.name}» может отказать: ${перечень}. ` +
        `Надзор здесь не поможет: на заводе процесса ещё нет, а перезапуск возвращает то же самое ` +
        `вычисленное значение. Начальное состояние обязано быть безотказным`,
      найденные[0]?.где ? { span: найденные[0].где } : узел,
    )
  }
}

/**
 * Прогон — пример конкурентной программы: семя, входные сообщения, итог.
 * Сообщение сверяется с `принимает` адресата, ожидаемое состояние — с
 * объявленным типом состояния. Ровно то же, что делает `checkExamples` для
 * обычной функции, и по той же причине.
 *
 * Второе ожидание — `стратегия «X» N раз` — сверяется с надзором: стратегия
 * обязана быть одной из трёх, а процесс — стоять под надзором. Второе не
 * придирка: ожидание «надзор перезапустил его дважды» от процесса, за которым
 * никто не следит, не может сбыться никогда, и лучше сказать это до прогона,
 * чем показать «ожидалось 2, вышло 0» и оставить гадать почему.
 *
 * Третье ожидание — `любое из [ … ]` — требует сетки семян (`семя от N до M`),
 * и это не формальность. Множество допустимых итогов проверяется В ОБЕ
 * СТОРОНЫ: ни одно семя не вышло за множество И каждое названное значение
 * где-то встретилось. На одном семени вторая половина не может сбыться ни при
 * каком множестве длиннее единицы, то есть ожидание было бы заведомо ложным, а
 * заведомо ложное ожидание лучше отвергнуть до прогона.
 */
function checkRuns(program, ctx) {
  const прогоны = Array.isArray(program?.runs) ? program.runs : []
  if (прогоны.length === 0) return
  const процессы = ctx.processes instanceof Map ? ctx.processes : new Map()

  for (const прогон of прогоны) {
    const label = `прогон «${прогон.name}»`
    if (!Number.isInteger(прогон.seed) || прогон.seed < 0) {
      ctx.report("FLANG_PROCESS", `${label}: семя ${прогон.seed} — ожидалось целое неотрицательное число`, прогон)
    }
    const сетка = прогон.seedTo !== null && прогон.seedTo !== undefined
    if (сетка) {
      if (!Number.isInteger(прогон.seedTo) || прогон.seedTo < 0) {
        ctx.report(
          "FLANG_PROCESS",
          `${label}: верхнее семя ${прогон.seedTo} — ожидалось целое неотрицательное число`,
          прогон,
        )
      } else if (прогон.seedTo < прогон.seed) {
        /* Пустая сетка не «ничего не проверяет» — она проверяет ВСЁ, потому что
           утверждение о всех элементах пустого множества истинно. Прогон,
           который зеленеет, не сделав ни одного пробега, — худший из возможных
           видов молчания, и лучше сказать об этом разбором. */
        ctx.report(
          "FLANG_PROCESS",
          `${label}: сетка семян от ${прогон.seed} до ${прогон.seedTo} пуста — такой прогон сбудется, ` +
            "не проверив ни одного чередования",
          прогон,
        )
      }
    }
    if (процессы.size === 0) {
      ctx.report("FLANG_PROCESS", `${label} записан, но в программе не объявлено ни одного процесса`, прогон)
      continue
    }

    /* «Дано» кладётся в ящики ДО первого выбора планировщика, значит проверить
       его на переполнение можно ДО прогона: сколько сообщений названо, столько
       и ляжет. Отправку из обработчика так проверить нельзя — она зависит от
       чередования, — и потому она отказывает в прогоне, а эта строка отвергает
       программу разбором. Без неё прогон, объявивший ящик на два и положивший в
       него три, падал бы отказом отправителя, которого в исходнике нет. */
    const сколькоДано = new Map()
    for (const запись of прогон.inbox ?? []) {
      const процесс = процессы.get(запись.process)
      if (процесс === undefined) {
        ctx.report("FLANG_UNKNOWN_PROCESS", `${label}: процесс «${запись.process}» не объявлен`, запись)
        continue
      }
      checkValue(запись.message, процесс.accepts, `${label}: сообщение процессу «${запись.process}»`, ctx, запись)
      const было = (сколькоДано.get(запись.process) ?? 0) + 1
      сколькоДано.set(запись.process, было)
      const потолок = процесс.node?.mailbox
      if (Number.isInteger(потолок) && потолок > 0 && было > потолок) {
        ctx.report(
          "FLANG_PROCESS",
          `${label}: процессу «${запись.process}» дано ${было} сообщений, а его ящик объявлен на ${потолок} — ` +
            "переполнение случилось бы до первого пробега",
          запись,
        )
      }
    }
    const подНадзором = ctx.supervisedProcesses instanceof Map ? ctx.supervisedProcesses : new Map()
    for (const ожидание of прогон.expected ?? []) {
      const процесс = процессы.get(ожидание.process)
      if (процесс === undefined) {
        ctx.report("FLANG_UNKNOWN_PROCESS", `${label}: процесс «${ожидание.process}» не объявлен`, ожидание)
        continue
      }
      if (ожидание.kind === "strategy") {
        if (!STRATEGIES.includes(ожидание.strategy)) {
          ctx.report(
            "FLANG_PROCESS",
            `${label}: стратегия «${ожидание.strategy}» неизвестна; их три — ` +
              STRATEGIES.map((s) => `«${s}»`).join(", "),
            ожидание,
          )
        }
        if (!Number.isInteger(ожидание.times) || ожидание.times < 0) {
          ctx.report(
            "FLANG_PROCESS",
            `${label}: «${ожидание.process}» стратегия «${ожидание.strategy}» ${ожидание.times} — ` +
              `ожидалось целое неотрицательное число`,
            ожидание,
          )
        }
        if (!подНадзором.has(ожидание.process)) {
          ctx.report(
            "FLANG_PROCESS",
            `${label}: ожидается стратегия для процесса «${ожидание.process}», но он не стоит ни под каким ` +
              `надзором — решения о нём не принимает никто`,
            ожидание,
          )
        }
        continue
      }
      if (ожидание.kind === "oneOf") {
        if (!Array.isArray(ожидание.states)) {
          ctx.report(
            "FLANG_PROCESS",
            `${label}: после 'любое из' ожидался список значений в квадратных скобках`,
            ожидание,
          )
          continue
        }
        if (!сетка) {
          ctx.report(
            "FLANG_PROCESS",
            `${label}: 'любое из' проверяется перебором семян, а у прогона одно семя — ` +
              "напишите 'семя от N до M'",
            ожидание,
          )
        } else if (прогон.seedTo === прогон.seed) {
          /* Сетка мерится ЧИСЛОМ СЕМЯН, а не наличием предлога. `семя от 5 до 5`
             записано сеткой и перебирает ОДНО чередование, то есть вторая
             половина проверки («каждое названное значение где-то встретилось»)
             не сбудется на нём ни при каком множестве длиннее единицы — ровно
             то же заведомо ложное ожидание, что и при `семя 5`. Проверка
             смотрела на форму записи, и эта запись проходила молча, краснея
             потом прогоном. */
          ctx.report(
            "FLANG_PROCESS",
            `${label}: сетка семян от ${прогон.seed} до ${прогон.seedTo} перебирает одно чередование — ` +
              "'любое из' на нём не сбудется ни при каком множестве длиннее единицы",
            ожидание,
          )
        }
        if (ожидание.states.length === 0) {
          ctx.report("FLANG_PROCESS", `${label}: множество итогов «${ожидание.process}» пусто`, ожидание)
        }
        /* Повтор в множестве — не ошибка исполнения, а ошибка чтения: читатель
           видит N значений и считает, что итогов N, а их меньше. */
        const виданные = new Set()
        ожидание.states.forEach((значение, номер) => {
          const ключ = JSON.stringify(значение)
          if (виданные.has(ключ)) {
            ctx.report(
              "FLANG_PROCESS",
              `${label}: в множестве итогов «${ожидание.process}» значение №${номер + 1} повторяется`,
              ожидание,
            )
          }
          виданные.add(ключ)
          checkValue(
            значение,
            процесс.state,
            `${label}: итог №${номер + 1} из множества «${ожидание.process}»`,
            ctx,
            ожидание,
          )
        })
        continue
      }
      checkValue(ожидание.state, процесс.state, `${label}: ожидаемое состояние «${ожидание.process}»`, ctx, ожидание)
    }
  }
}

