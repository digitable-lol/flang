/**
 * Проверка типов всей программы.
 *
 * @param {object} program AST модуля (SPEC, раздел 5)
 * @returns {{ ok: boolean, diagnostics: object[], types: Map<string, object> }}
 *   `types` — сигнатура каждой функции: `{ params, returns, total }` уже в
 *   нормализованных типах, чтобы вызывающему коду не пришлось разбирать AST
 *   типов второй раз.
 */
export function checkTypes(program) {
  const diagnostics = []
  const report = (code, message, node) => {
    diagnostics.push({ code, message, severity: "error", span: spanOf(node) })
  }

  const ctx = {
    report,
    records: new Map(),      // имя записи → Map<поле, Тип>
    sums: new Map(),         // имя суммы → Map<вариант, Map<поле, Тип>>
    variantOwner: new Map(), // имя варианта → имя суммы
    aliases: new Map(),      // имя псевдонима → объявление (узел `alias`)
    aliasTypes: new Map(),   // имя псевдонима → развёрнутый тип (мемоизация)
    aliasOpen: new Set(),    // псевдонимы в процессе развёртывания — ловушка цикла
    signatures: new Map(),
    /* Параметрический полиморфизм (flang/cat/POLY.md). `typeParams` — имена
       параметров каждого объявленного типа; пустой массив у обычного типа,
       поэтому проверка арности одна на всех. `paramScope` — параметры,
       связанные тем объявлением, которое нормализуется прямо сейчас: имя
       параметра важнее одноимённого типа, и только внутри своего объявления. */
    typeParams: new Map(), // имя типа → массив имён его параметров
    paramScope: null,      // Set<имя параметра> или null вне объявления
    /* Тип состояния плана — ожидание для поля `потом` варианта «Сделать»
       (`io.mjs`, `planStateType`). `null` значит «сверять нечем». */
    planState: null,
    /* Второй джокер словаря: `значение` варианта «Конец работы». Объявленного
       типа у результата плана нет вовсе, поэтому образцом становится первое
       встреченное значение — см. `planResultIsShared`. `planDone` хранит его тип
       и узел, чтобы сообщение назвало оба места. */
    planResultShared: false,
    planDone: null,
  }

  collectTypes(program, ctx)
  collectSignatures(program, ctx)
  /* Процессы собираются ДО проверки тел: адресат действия «отправить»
     сверяется с объявленными процессами прямо в теле обработчика, и знать о
     них к этому моменту уже надо. */
  checkProcesses(program, ctx)
  /* Состояние плана — по той же причине и тем же порядком: поле `потом`
     сверяется с ним прямо в теле функции шага, значит к обходу тел тип уже
     обязан быть известен. Само объявление `план` проверяется ниже
     (`checkPlans`), и диагностик здесь не выдаётся ни одной. */
  ctx.planState = planStateType(program, ctx)
  ctx.planResultShared = planResultIsShared(program)

  for (const fn of listFunctions(program)) {
    if (!isName(fn?.name)) continue
    checkFunction(fn, ctx)
  }

  checkMorphisms(program, ctx)
  checkFunctors(program, ctx)
  /* Изоморфизм и бифунктор — после морфизмов и по той же причине, по какой
     после них идёт функтор: обеим проверкам нужна готовая таблица стрелок
     (`ctx.morphisms`), включая выведенные концы композиций. */
  checkIsomorphisms(program, ctx)
  /* Отношения множеств — после изоморфизма и по той же причине, что он сам
     после морфизмов: общая часть сличается с ВЛОЖЕНИЯМИ, а те — с сигнатурами
     функций, и обе таблицы к этому месту уже готовы. */
  checkSetShapes(program, ctx)
  checkBifunctors(program, ctx)
  checkMonoids(program, ctx)
  checkMonads(program, ctx)
  checkSupervisors(program, ctx)
  /* Полнота надзора — ПОСЛЕ надзора и до прогонов: ей нужна готовая таблица
     «кто под кем» (`ctx.supervisedProcesses`), которую заполняет проверка выше. */
  checkFailureCoverage(program, ctx)
  checkRuns(program, ctx)
  checkPlans(program, ctx)

  return { ok: diagnostics.length === 0, diagnostics, types: ctx.signatures }
}

