/**
 * Имя результата внутри постусловия, когда постусловие его не назвало.
 *
 * Четвёртое повторение одного слова — и ни одного лишнего: так же его держат у
 * себя парсер (`parser.mjs`, `RESULT_BINDING`), мост из FTS (`compat.mjs`, там
 * же) и вычислитель (`interpret.mjs`, `DEFAULT_RESULT_BINDING`). Импортировать
 * его сюда неоткуда: единственный экспорт живёт в `compat.mjs`, а тот тянет за
 * собой вычислитель целиком — типизатор перестал бы быть отдельным проходом
 * ради одной строки. Важно не место константы, а то, что умолчание здесь и
 * умолчание в `interpret.mjs` СОВПАДАЮТ: разойдись они, проверка связывала бы
 * одно имя, а вычисление другое, и типизатор доказывал бы не то выражение,
 * которое исполнится.
 */
const DEFAULT_RESULT_BINDING = "результат"

/**
 * Объявленное постусловие `обеспечивает «имя» <утверждение>`.
 *
 * Проверяется ровно два свойства, и без обоих утверждение не является
 * утверждением.
 *
 * ТИПИЗИРУЕТСЯ ВООБЩЕ. Выражение постусловия — обычное выражение языка, и
 * читается оно по общим правилам, теми же `inferExpr`: `результат` связан
 * объявленным типом возврата, параметры — своими типами, остальное как везде.
 * До этой проверки поле `postconditions` не читала здесь ни одна строка, и
 * `результат плюс "строка"` проходил `flang check` с ответом `valid: true`.
 * Видно этого не было, потому что постусловия приходили только из `compat.mjs`,
 * а он строит их сам и строит правильными; слово `обеспечивает` отдало эту
 * запись автору, и вместе с ней — возможность написать в ней бессмыслицу.
 *
 * ПРИЗНАК. Постусловие обязано давать `да` или `нет`, и это отдельная проверка,
 * а не следствие первой: `результат плюс 1` типизируется прекрасно и не
 * является утверждением ни о чём. Требование не выдумано здесь — его уже
 * предъявляет вычислитель (`interpret.mjs`, `stepPost`: «постусловие должно
 * давать признак»), но предъявляет при ПЕРВОМ ВЫЗОВЕ, то есть у пользователя, а
 * не у автора. Здесь оно предъявляется на проверке — до того, как утверждение
 * попадёт в машинерию доказательств.
 *
 * ЗАЧЕМ ЭТО СРОЧНО. Ведомость (`proof.mjs`) печатает по каждому утверждению,
 * чем оно несётся: доказано ядром, сетка примеров, объявлено-не-доказано.
 * Утверждение, которое не типизируется, отравляет всю машинерию: ядру
 * предъявили бы термом бессмыслицу, а ведомость напечатала бы про неё «сетка»
 * или «объявлено» — то есть сказала бы, что утверждение есть, когда его нет.
 *
 * ОБЛАСТЬ ВИДИМОСТИ ВЗЯТА У ВЫЧИСЛИТЕЛЯ, А НЕ ВЫДУМАНА. `stepPost` кладёт
 * результат в окружение вызова поверх всего (`env[property.bind] = result` на
 * `Object.create(frame.env)`), поэтому и здесь `bind` кладётся поверх
 * параметров: сойдись имя параметра с именем результата, оба слоя поймут его
 * одинаково. Проверять то, чего не будет при вычислении, — худший вид проверки.
 */
function checkPostconditions(fn, signature, env, ctx, where) {
  const list = fn.postconditions
  /* Не список — не наше дело: о форме AST говорит тот, кто его читает целиком
     (`interpret.mjs`, `normalizePostconditions`, код `FLANG_PARSE`). Второе
     сообщение о том же изъяне ничего не добавило бы. */
  if (!Array.isArray(list)) return

  for (const post of list) {
    if (post === null || typeof post !== "object") continue
    const label = isName(post.name) ? `постусловие «${post.name}»` : "постусловие"

    /* Квантор `для всех имя` называет ТОТ параметр, по которому утверждение
       потом доказывают индукцией (`obligations.mjs`). Тип связанного им имени
       обязан приходить из параметра — и приходит: имя уже лежит в `env` со
       своим объявленным типом, второй раз связывать его здесь значило бы
       завести ему второй, ничем не подкреплённый тип. Проверяется поэтому
       единственное: что параметр с таким именем есть. Парсер это уже требует
       (`parseEnsures`), но AST приходит и мимо него — из моста, из понижения,
       из файла, — и обязательство по несуществующему имени нечем предъявить. */
    if (post.forall !== undefined && post.forall !== null) {
      if (!isName(post.forall) || !signature.params.some((param) => param.name === post.forall)) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `${where}: ${label} объявлено «для всех ${String(post.forall)}», а параметра с таким именем у функции нет`
            + " — индукция пошла бы по имени, которого не существует",
          post.expr ?? fn,
        )
      }
    }

    const bind = isName(post.bind) ? post.bind : DEFAULT_RESULT_BINDING
    const inner = new Map(env)
    inner.set(bind, signature.returns)

    const actual = inferExpr(post.expr, inner, BOOLEAN, ctx, fn.name)
    if (!sameType(actual, BOOLEAN)) {
      ctx.report(
        "FLANG_TYPE",
        `${where}: ${label} даёт ${typeName(actual)}, а постусловие обязано быть признаком`
          + " — оно проверяется после каждого возврата, и «да» или «нет» решает, состоялся ли вызов",
        post.expr ?? fn,
      )
    }
  }
}

/**
 * Примеры против сигнатуры.
 *
 * `чей` — родительный падеж владельца примера. У функции это она сама, у
 * закона при стрелке — закон и морфизм: примеры закона проверяются той же
 * функцией, что примеры функции, потому что это буквально одни и те же
 * примеры той же сигнатуры, а второе понимание слов «дано» и «ожидается»
 * означало бы два разных языка в одном.
 */
function checkExamples(fn, signature, ctx, чей = `функции «${fn.name}»`) {
  for (const example of fn.examples ?? []) {
    const label = isName(example?.name) ? `пример «${example.name}»` : "пример"
    const args = example?.args ?? {}
    const bindings = solveExample(signature, example, ctx)
    for (const param of signature.params) {
      if (!(param.name in args)) {
        // Необязательный аргумент можно не задавать: отсутствие — это `ничто`,
        // а не пропуск. Ядро FTS считает так же (`requiredFields`
        // в `src/validate.ts` исключает поля с `| undefined`).
        if (param.type.optional !== true) {
          ctx.report("FLANG_TYPE", `${label} ${чей} не задаёт аргумент «${param.name}»`, example)
        }
        continue
      }
      checkValue(args[param.name], substitute(param.type, bindings), `${label}: аргумент «${param.name}»`, ctx, example)
    }
    for (const given of Object.keys(args)) {
      if (!signature.params.some((param) => param.name === given)) {
        ctx.report("FLANG_UNKNOWN_NAME", `${label} ${чей} задаёт неизвестный аргумент «${given}»`, example)
      }
    }
    checkValue(example?.expected, substitute(signature.returns, bindings), `${label}: ожидаемое значение`, ctx, example)
  }
}

/**
 * Подстановка для ОДНОГО примера полиморфной функции — фаза 2 `cat/POLY.md`.
 *
 * Зачем отдельный источник вывода. У вызова типы аргументов уже известны из
 * выражений, и подстановку решает `callType`. У примера выражений нет вовсе:
 * `дано ф равно функция «Удвоить»` — это ЗНАЧЕНИЕ, обычный JSON. Пока
 * подстановку из значений никто не выводил, объявленный тип уходил в
 * `checkValue` как написан, и выходило одно из двух, оба неверных:
 *
 *   • `ф: функция из «А» в «Б»` сравнивалось с `функция из числа в число`
 *     буквально — пример полиморфной функции падал, хотя он верен;
 *   • `значение: «А»` не проверялось вовсе — в примере годилось что угодно.
 *
 * Решение то же самое, что на вызове, и намеренно тем же кодом: вывести тип
 * значения настолько, насколько он выводится, и сопоставить с объявленным
 * (`matchAgainst`). Заводить здесь второе понимание подстановки значило бы
 * получить два языка в одном — ровно тот довод, по которому примеры закона
 * проверяются той же функцией, что примеры функции.
 *
 * Порядок источников — аргументы, потом ожидаемое значение — взят у `callType`
 * и по той же причине: у `функция «Ничего» от «А» возвращает «Возможно» от «А»`
 * аргументов нет вовсе, и без второго источника её пример был бы непроверяем.
 * Обратный порядок был бы хуже: ожидаемое значение — то, что пример проверяет,
 * и выводить по нему раньше, чем по входу, значит подгонять проверку под ответ.
 *
 * Нерешённое связывается джокером МОЛЧА, без `FLANG_TYPE_PARAM`. Отказ здесь
 * означал бы «пример обязан определить каждый параметр», а это неправда:
 * `дано значение равно ничто` про «А» не говорит ничего и вправе не говорить.
 * Джокер `sameType` пропускает, значит непроверенным останется ровно то, про
 * что значение промолчало, а не пример целиком.
 */
function solveExample(signature, example, ctx) {
  const typeParams = signature.typeParams ?? []
  const bindings = new Map()
  if (typeParams.length === 0) return bindings
  const args = example?.args ?? {}
  for (const param of signature.params) {
    if (!(param.name in args) || !hasParams(param.type)) continue
    matchAgainst(param.type, exampleValueType(args[param.name], param.type, ctx), bindings)
  }
  if (typeParams.some((name) => !bindings.has(name)) && hasParams(signature.returns)) {
    matchAgainst(signature.returns, exampleValueType(example?.expected, signature.returns, ctx), bindings)
  }
  for (const name of typeParams) {
    if (!bindings.has(name)) bindings.set(name, UNKNOWN)
  }
  return bindings
}

/**
 * Тип значения примера — настолько, насколько он из самого значения выводится.
 * Джокер там, где не выводится, и это не лень, а единственный честный ответ:
 * `[]` не говорит про тип элемента, `ничто` не говорит вообще ни про что.
 *
 * `hint` — объявленный тип на этом же месте. Он не проверяется здесь (проверит
 * `checkValue`), а РАЗВОДИТ формы, которые в JSON записаны одинаково:
 * `{ вариант: "Удвоить" }` — это функция-значение, если ждут функцию, и вариант
 * суммы, если такой вариант объявлен. Без подсказки обе формы неразличимы, а
 * второй способ записывать значения SPEC не фиксирует.
 */
function exampleValueType(value, hint, ctx) {
  if (typeof value === "number" && Number.isFinite(value)) return NUMBER
  if (typeof value === "string") return STRING
  if (typeof value === "boolean") return BOOLEAN
  if (value === null || value === undefined) return UNKNOWN
  if (Array.isArray(value)) {
    const inner = hint?.kind === "list" ? hint.of : null
    /* Хватит первого элемента, который что-то сказал: разнотипный список — это
       беда самого примера, и назовёт её `checkValue` по подставленному типу. */
    for (const item of value) {
      const found = exampleValueType(item, inner, ctx)
      if (found.kind !== "unknown") return { kind: "list", of: found }
    }
    return { kind: "list", of: UNKNOWN }
  }
  if (!isPlainObject(value)) return UNKNOWN
  const tag = value["вариант"] ?? value.variant
  if (isName(tag)) {
    if (hint?.kind === "fn" || !ctx.variantOwner.has(tag)) return fnValueType(tag, ctx)
    return sumValueType(tag, value, hint, ctx)
  }
  if (hint?.kind === "record" && ctx.records.has(hint.name)) return recordValueType(value, hint, ctx)
  return UNKNOWN
}

/** Тег функции как значение. Полиморфную функцию значением брать нельзя
 *  (`fnrefType`), и здесь та же граница: у неё тип не один, а по подстановке. */
function fnValueType(tag, ctx) {
  const signature = ctx.signatures.get(tag)
  if (!signature || (signature.typeParams ?? []).length > 0) return UNKNOWN
  return signatureType(signature)
}

/** Аргументы применения суммы выводятся из полей варианта, а не из подсказки:
 *  подсказка могла бы сама состоять из параметров и ничего бы не решила. */
function sumValueType(tag, value, hint, ctx) {
  const owner = ctx.variantOwner.get(tag)
  const declared = ctx.sums.get(owner)?.get(tag)
  if (!declared) return UNKNOWN
  const names = ctx.typeParams.get(owner) ?? []
  if (names.length === 0) return { kind: "sum", name: owner }
  const payload = isPlainObject(value["поля"] ?? value.fields)
    ? (value["поля"] ?? value.fields)
    : omit(value, ["вариант", "variant"])
  return { kind: "sum", name: owner, args: solveArgs(names, declared, payload, hint, owner, ctx) }
}

function recordValueType(value, hint, ctx) {
  const names = ctx.typeParams.get(hint.name) ?? []
  if (names.length === 0) return { kind: "record", name: hint.name }
  return { kind: "record", name: hint.name, args: solveArgs(names, ctx.records.get(hint.name), value, hint, hint.name, ctx) }
}

/** Общее для суммы и записи: поля объявлены в ИМЕНАХ ПАРАМЕТРОВ владельца,
 *  значит по значениям полей решается подстановка владельца, а не вызывающей
 *  функции. Два пространства имён параметров смешивать нельзя: «А» функции и
 *  «А» типа — разные «А». */
function solveArgs(names, declared, payload, hint, owner, ctx) {
  const solved = new Map()
  const outer = hint?.name === owner ? bindingsOf(hint, ctx) : new Map()
  for (const [name, fieldType] of declared ?? []) {
    if (!isPlainObject(payload) || !(name in payload)) continue
    matchAgainst(fieldType, exampleValueType(payload[name], substitute(fieldType, outer), ctx), solved)
  }
  return names.map((name) => solved.get(name) ?? UNKNOWN)
}

/**
 * Значение (из примера) против типа. Значения — обычный JSON, поэтому вариант
 * суммы приходится узнавать по форме: `{ вариант: "Слово", … }` либо
 * `{ variant: "Слово", fields: { … } }`. Обе формы приняты сознательно —
 * SPEC фиксирует AST, но не сериализацию значений.
 */
function checkValue(value, type, label, ctx, at) {
  if (!type || type.kind === "unknown") return
  if (type.optional === true && (value === null || value === undefined)) return
  const bad = () => ctx.report("FLANG_TYPE", `${label} не соответствует типу ${typeName(type)}`, at)
  switch (type.kind) {
    /* Значение примера — единственное место, где уточнение проверяется не по
       типу, а по САМОМУ ЧИСЛУ, и потому проверяется точно: `пример … дано н
       равно −1` при `н: нат` ловится здесь, а не остаётся надеждой. */
    case "number":
      if (typeof value !== "number" || !Number.isFinite(value)) { bad(); return }
      if (целыйЛи(type) && !Number.isInteger(value)) {
        ctx.report("FLANG_TYPE", `${label}: ${value} не целое, а тип ${typeName(type)} — целый`, at)
        return
      }
      if (value < низОт(type) || value > верхОт(type)) {
        ctx.report("FLANG_TYPE", `${label}: ${value} вне ${typeName(type)}`, at)
      }
      return
    case "string":
      if (typeof value !== "string") bad()
      return
    case "boolean":
      if (typeof value !== "boolean") bad()
      return
    case "null":
      if (value !== null) bad()
      return
    case "list":
      if (!Array.isArray(value)) { bad(); return }
      value.forEach((item, index) => checkValue(item, type.of, `${label}[${index}]`, ctx, at))
      return
    case "record": {
      const fields = ctx.records.get(type.name)
      if (!isPlainObject(value) || !fields) { bad(); return }
      const bindings = bindingsOf(type, ctx)
      for (const [name, declaredType] of fields) {
        const fieldType = substitute(declaredType, bindings)
        if (!(name in value)) {
          if (fieldType.optional !== true) ctx.report("FLANG_TYPE", `${label}: не задано поле «${name}» записи «${type.name}»`, at)
          continue
        }
        checkValue(value[name], fieldType, `${label}.${name}`, ctx, at)
      }
      for (const name of Object.keys(value)) {
        if (!fields.has(name)) ctx.report("FLANG_TYPE", `${label}: запись «${type.name}» не имеет поля «${name}»`, at)
      }
      return
    }
    /*
     * Значение-функция в примере. Записывается тегом — тем же `{ вариант: … }`,
     * что и вариант без полей, потому что после дефункционализации это и ЕСТЬ
     * вариант: `функция «Удвоить»` — конструктор тега «Удвоить» без захваченных
     * полей. Проверяется здесь не форма, а тип: тег обязан называть объявленную
     * функцию, и её сигнатура обязана совпасть с ожидаемой.
     */
    case "fn": {
      const tag = isPlainObject(value) ? (value["вариант"] ?? value.variant) : null
      if (!isName(tag)) { bad(); return }
      const signature = ctx.signatures.get(tag)
      if (!signature) {
        ctx.report("FLANG_UNKNOWN_NAME", `${label}: функции «${tag}» нет`, at)
        return
      }
      const actual = signatureType(signature)
      if (!sameType(actual, type)) {
        ctx.report("FLANG_TYPE", `${label}: «${tag}» имеет тип ${typeName(actual)}, а ожидался ${typeName(type)}`, at)
      }
      return
    }
    case "sum": {
      if (!isPlainObject(value)) { bad(); return }
      const variantName = value["вариант"] ?? value.variant
      const variants = ctx.sums.get(type.name)
      if (!isName(variantName) || !variants || !variants.has(variantName)) {
        ctx.report("FLANG_TYPE", `${label}: ожидался вариант типа «${type.name}»`, at)
        return
      }
      const declared = variants.get(variantName)
      const bindings = bindingsOf(type, ctx)
      const payload = isPlainObject(value["поля"] ?? value.fields)
        ? (value["поля"] ?? value.fields)
        : omit(value, ["вариант", "variant"])
      for (const [name, declaredType] of declared) {
        if (!(name in payload)) {
          ctx.report("FLANG_TYPE", `${label}: вариант «${variantName}» требует поле «${name}»`, at)
          continue
        }
        checkValue(payload[name], substitute(declaredType, bindings), `${label}.${name}`, ctx, at)
      }
      return
    }
    default:
      return
  }
}

