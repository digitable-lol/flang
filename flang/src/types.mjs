/**
 * Тождественные морфизмы программы: имя стрелки → объект, чью единицу она даёт.
 *
 * Отдельной функцией, а не полем `ctx`, чтобы проверки не зависели от порядка
 * вызова друг друга сильнее, чем уже зависят от `ctx.morphisms`.
 */
function единицыОбъектов(program) {
  const единицы = new Map()
  for (const узел of Array.isArray(program?.morphisms) ? program.morphisms : []) {
    if (узел?.kind === "morphism" && узел.identity === true) единицы.set(узел.name, узел.domain)
  }
  return единицы
}

/**
 * Изоморфизм: пара стрелок туда и обратно.
 *
 * ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ. Всё нижеследующее — утверждения обо всех входах,
 * полученные сличением объявлений, без сетки и без вычислений. Возможно это
 * ровно потому же, почему возможны законы функтора: морфизм в языке —
 * ОБЪЯВЛЕНИЕ, его домен и кодомен известны до запуска.
 *
 *   1. объекты изоморфизма объявлены (объект категории — это тип);
 *   2. обе стрелки объявлены;
 *   3. концы сходятся: прямая ведёт из первого объекта во второй, обратная —
 *      из второго в первый. Это и делает обе композиции замкнутыми на себя:
 *      «обратный после прямого» ведёт из «А» в «А», «прямой после обратного» —
 *      из «Б» в «Б». Без этого закон обратимости даже сформулировать нельзя;
 *   4. единицы обоих объектов объявлены. Закон говорит «композиция даёт
 *      единицу», и если единицы в программе нет, он говорит о том, чего нет.
 *
 * ЧЕГО ЗДЕСЬ НЕ ДОКАЗЫВАЕТСЯ, и это главное. Само равенство «обратный после
 * прямого = единица» не проверяется никак — ни доказательством, ни сеткой. И
 * не потому, что руки не дошли: у стрелки категории сегодня НЕТ тела. `морфизм
 * «ф» из «А» в «Б»` — это объявление без вычисления, вычислять на сетке
 * попросту нечего, а два разных объявления стрелок «А» → «А» равными не
 * являются. Значит объявление изоморфизма — это ДОПУЩЕНИЕ автора, а проверка
 * здесь отвечает на единственный вопрос, на который может ответить: допущение
 * сформулировано осмысленно и согласовано со всем остальным объявленным.
 *
 * Отсюда же — почему компилятор не пользуется этим допущением как правилом
 * переписывания. Соблазн есть: зная «обратный после прямого = единица А»,
 * можно было бы считать объявленную композицию с такими сомножителями
 * единицей. Делать так нельзя — тогда у функтора столкнулись бы два его
 * собственных закона: сохранение композиции требует, чтобы образом был
 * «образ после образа», а сохранение единиц — чтобы образом была «единица …»,
 * и оба сразу не выполнимы ни при каком объявлении. Языку с равенствами
 * морфизмов нужна отдельная работа; в контракте это записано, а здесь честно
 * не сделано.
 */
function checkIsomorphisms(program, ctx) {
  const изоморфизмы = Array.isArray(program?.isomorphisms) ? program.isomorphisms : []
  if (изоморфизмы.length === 0) return

  const стрелки = ctx.morphisms instanceof Map ? ctx.morphisms : new Map()
  const единицы = единицыОбъектов(program)
  const объявлен = (имя) => ctx.records.has(имя) || ctx.sums.has(имя) || ctx.aliases.has(имя)

  const видели = new Map()
  for (const узел of изоморфизмы) {
    if (видели.has(узел.name)) {
      ctx.report("FLANG_DUPLICATE_NAME", `изоморфизм «${узел.name}» объявлен дважды`, узел)
      continue
    }
    видели.set(узел.name, узел)

    for (const [роль, имя] of [["первый объект", узел.from], ["второй объект", узел.to]]) {
      if (!объявлен(имя)) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `${роль} изоморфизма «${узел.name}» — «${имя}» — не объявлен: объект категории это тип`,
          узел,
        )
      }
    }

    /* Концы. Сообщение называет ОБЕ стороны — и требуемую, и объявленную:
       «не сходится» без имён заставляет искать вторую половину глазами. */
    const сверить = (роль, имяСтрелки, домен, кодомен) => {
      const стрелка = стрелки.get(имяСтрелки)
      if (стрелка === undefined) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `изоморфизм «${узел.name}»: ${роль} «${имяСтрелки}» — такого морфизма нет`,
          узел,
        )
        return
      }
      if (стрелка.domain !== домен || стрелка.codomain !== кодомен) {
        ctx.report(
          "FLANG_ISO_MISMATCH",
          `изоморфизм «${узел.name}»: ${роль} «${имяСтрелки}» обязан вести из «${домен}» в «${кодомен}», ` +
            `а ведёт из «${стрелка.domain}» в «${стрелка.codomain}»`,
          узел,
        )
      }
    }
    сверить("прямой морфизм", узел.forward, узел.from, узел.to)
    сверить("обратный морфизм", узел.backward, узел.to, узел.from)

    /* Единицы обоих объектов. Множество, а не пара: изоморфизм объекта с самим
       собой законен (тождественная стрелка — изоморфизм), и требовать в этом
       случае две единицы одного объекта было бы придиркой. */
    for (const объект of new Set([узел.from, узел.to])) {
      if (единицы.has(`единица ${объект}`)) continue
      ctx.report(
        "FLANG_ISO_IDENTITY_MISSING",
        `изоморфизм «${узел.name}» обещает, что кругооборот через «${объект}» даёт «единица ${объект}», ` +
          `а единица объекта «${объект}» не объявлена: закон говорит о том, чего в программе нет`,
        узел,
      )
    }
  }
  ctx.isomorphisms = видели
}

/**
 * Бифунктор: функтор от двух входов сразу.
 *
 * ЛОЖИТСЯ ЛИ ОН НА УСТРОЙСТВО ФУНКТОРА — вопрос, с которого начиналась работа.
 * Ответ: законы ложатся полностью, поверхность из контракта — наполовину.
 *
 * Законы ложатся потому, что вся проверка функтора построена на сличении
 * объявленных имён, а ключ отображения — деталь: там имя объекта, здесь пара
 * имён. Все три закона переписываются заменой ключа и ничем больше.
 *
 * Не ложится общий вид из контракта: `бифунктор «Пара» из «Значения» и
 * «Значения» в «Значения»` с образом `«Пара А Б»`. Здесь «А» и «Б» —
 * переменные типа, а параметрических типов в языке нет: «Пара А Б» будет
 * именем одной записи, а не семейством записей. Поэтому пары объектов и
 * морфизмов здесь КОНКРЕТНЫЕ — ровно так же, как конкретны объекты у функтора,
 * у которого «Заказ отображается в Счёт» пишется для этих двух записей, а не
 * для семейства. Ограничение общее для обеих конструкций, снимется вместе с
 * параметрическим полиморфизмом и законов не касается.
 *
 * ЧТО ДОКАЗЫВАЕТСЯ (всё — сличением объявлений, без сетки):
 *
 *   1. отображение пар объектов однозначно;
 *   2. согласование стрелок с объектами: если «ф» ведёт из «А1» в «А2», а «г» —
 *      из «Б1» в «Б2», то образ пары обязан вести из образа пары «А1», «Б1» в
 *      образ пары «А2», «Б2»;
 *   3. сохранение композиции по обоим входам: образ пары композиций обязан
 *      быть композицией образов пар в том же порядке;
 *   4. сохранение единиц: образ пары единиц обязан быть единицей образа пары.
 *
 * ГРАНИЦА ТРЕТЬЕГО ЗАКОНА названа отдельно, потому что она не очевидна. Он
 * проверяется там, где ОБЕ стороны пары объявлены композициями. Смешанный
 * случай — композиция по одному входу и произвольная стрелка по другому —
 * раскладывается только через образы пар с единицей, а их автор не объявлял.
 * Требовать их значило бы заставлять писать то, о чём не просили; молча
 * пропускать разлад — обманывать. Поэтому случай назван здесь и в контракте.
 */
function checkBifunctors(program, ctx) {
  const бифункторы = Array.isArray(program?.bifunctors) ? program.bifunctors : []
  if (бифункторы.length === 0) return

  const стрелки = ctx.morphisms instanceof Map ? ctx.morphisms : new Map()
  /* Композиции берутся из исходных узлов: в `стрелки` от композиции остались
     только концы, а закону нужны имена сомножителей. */
  const композиции = new Map()
  for (const узел of Array.isArray(program?.morphisms) ? program.morphisms : []) {
    if (узел?.kind === "composition") композиции.set(узел.name, узел)
  }
  const единицы = единицыОбъектов(program)

  for (const бифунктор of бифункторы) {
    const образОбъектов = new Map()
    for (const пара of бифунктор.objects ?? []) {
      const ключ = ключПары(пара.from)
      if (образОбъектов.has(ключ)) {
        ctx.report(
          "FLANG_BIFUNCTOR_OBJECT_TWICE",
          `бифунктор «${бифунктор.name}»: пара объектов ${имяПары(пара.from)} отображается дважды — ` +
            `в «${образОбъектов.get(ключ)}» и в «${пара.to}»; отображение пар обязано быть однозначным`,
          бифунктор,
        )
        continue
      }
      образОбъектов.set(ключ, пара.to)
    }

    const образМорфизмов = new Map()
    for (const пара of бифунктор.morphisms ?? []) образМорфизмов.set(ключПары(пара.from), пара.to)

    /* Закон 1: стрелки согласованы с объектами по обоим входам. */
    for (const пара of бифунктор.morphisms ?? []) {
      const [левый, правый] = пара.from
      const исходные = [стрелки.get(левый), стрелки.get(правый)]
      let целы = true
      for (const [номер, имя] of [левый, правый].entries()) {
        if (исходные[номер] !== undefined) continue
        целы = false
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `бифунктор «${бифунктор.name}» отображает пару ${имяПары(пара.from)}, но морфизма «${имя}» нет`,
          бифунктор,
        )
      }
      if (!целы) continue
      const образ = стрелки.get(пара.to)
      if (образ === undefined) {
        ctx.report(
          "FLANG_UNKNOWN_NAME",
          `бифунктор «${бифунктор.name}» отображает пару ${имяПары(пара.from)} в «${пара.to}», ` +
            `но морфизма «${пара.to}» нет`,
          бифунктор,
        )
        continue
      }
      for (const [роль, конец] of [["домен", "domain"], ["кодомен", "codomain"]]) {
        const параОбъектов = [исходные[0][конец], исходные[1][конец]]
        const ключ = ключПары(параОбъектов)
        if (!образОбъектов.has(ключ)) {
          ctx.report(
            "FLANG_BIFUNCTOR_OBJECT_MISSING",
            `бифунктор «${бифунктор.name}» отображает пару морфизмов ${имяПары(пара.from)}, ` +
              `но не отображает её ${роль} — пару объектов ${имяПары(параОбъектов)}: ` +
              `без образа пары объектов образ стрелки не с чем согласовать`,
            бифунктор,
          )
          continue
        }
        const ожидается = образОбъектов.get(ключ)
        if (образ[конец] !== ожидается) {
          ctx.report(
            "FLANG_BIFUNCTOR_ARROW_MISMATCH",
            `бифунктор «${бифунктор.name}»: пара ${имяПары(пара.from)} имеет ${роль} ${имяПары(параОбъектов)}, ` +
              `его образ — «${ожидается}», но «${пара.to}» имеет ${роль} «${образ[конец]}»`,
            бифунктор,
          )
        }
      }
    }

    /* Закон 2: образ пары композиций — композиция образов, в том же порядке. */
    for (const пара of бифунктор.morphisms ?? []) {
      const [левый, правый] = пара.from
      const слева = композиции.get(левый)
      const справа = композиции.get(правый)
      if (слева === undefined || справа === undefined) continue

      const параВерхняя = [слева.left, справа.left]
      const параНижняя = [слева.right, справа.right]
      const образВерхней = образМорфизмов.get(ключПары(параВерхняя))
      const образНижней = образМорфизмов.get(ключПары(параНижняя))
      if (образВерхней === undefined || образНижней === undefined) {
        const без = образВерхней === undefined ? параВерхняя : параНижняя
        ctx.report(
          "FLANG_BIFUNCTOR_COMPOSITION",
          `бифунктор «${бифунктор.name}» отображает пару композиций ${имяПары(пара.from)}, ` +
            `но не отображает пару ${имяПары(без)}, из которой она собрана: ` +
            `закон сохранения композиции проверить не на чем`,
          бифунктор,
        )
        continue
      }
      const образКомпозиции = композиции.get(пара.to)
      if (образКомпозиции === undefined) {
        ctx.report(
          "FLANG_BIFUNCTOR_COMPOSITION",
          `бифунктор «${бифунктор.name}»: образ пары ${имяПары(пара.from)} — «${пара.to}» — ` +
            `сам композицией не объявлен, а обязан быть «${образВерхней}» после «${образНижней}»`,
          бифунктор,
        )
        continue
      }
      if (образКомпозиции.left !== образВерхней || образКомпозиции.right !== образНижней) {
        ctx.report(
          "FLANG_BIFUNCTOR_COMPOSITION",
          `бифунктор «${бифунктор.name}» не сохраняет композицию: образ пары ${имяПары(пара.from)} обязан быть ` +
            `«${образВерхней}» после «${образНижней}», а объявлен как ` +
            `«${образКомпозиции.left}» после «${образКомпозиции.right}»`,
          бифунктор,
        )
      }
    }

    /* Закон 3: образ пары единиц — единица образа пары. */
    for (const пара of бифунктор.morphisms ?? []) {
      const первый = единицы.get(пара.from[0])
      const второй = единицы.get(пара.from[1])
      if (первый === undefined || второй === undefined) continue
      const ключ = ключПары([первый, второй])
      /* Пара объектов без образа — не нарушение: бифунктор вправе быть объявлен
         не на всём, и об отсутствии образа уже сказано законом 1 там, где это
         действительно мешает. */
      if (!образОбъектов.has(ключ)) continue
      const ожидается = `единица ${образОбъектов.get(ключ)}`
      if (пара.to !== ожидается) {
        ctx.report(
          "FLANG_BIFUNCTOR_IDENTITY",
          `бифунктор «${бифунктор.name}» не сохраняет единицы: образ пары ${имяПары(пара.from)} ` +
            `обязан быть «${ожидается}», а объявлен «${пара.to}»`,
          бифунктор,
        )
      }
    }
  }
}

/* Ключ пары для таблиц. Разделитель — нулевой символ, и не для красоты:
   имена в ёлочках сплошь с пробелами («по накладной», «оформить бумажно»),
   и на пробеле пара «а» с «б в» слиплась бы с парой «а б» с «в» в один ключ.
   Записан escape-последовательностью: сырой нулевой байт в исходнике делает
   файл двоичным для grep и половины редакторов. */
function ключПары([левый, правый]) {
  return `${левый}\u0000${правый}`
}

/** Пара в сообщении — оба имени и союз, как она написана в исходнике. */
function имяПары([левый, правый]) {
  return `«${левый}» и «${правый}»`
}

