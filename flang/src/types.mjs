/**
 * Нижняя и верхняя границы числового типа. У `число` их нет вовсе, и это
 * читается как «вся прямая»: `число` — самый широкий числовой тип, и всякое
 * уточнение в него вкладывается.
 */
function низОт(тип) {
  return typeof тип?.низ === "number" ? тип.низ : -Infinity
}

function верхОт(тип) {
  return typeof тип?.верх === "number" ? тип.верх : Infinity
}

function целыйЛи(тип) {
  return тип?.целое === true
}

function числовой(тип) {
  return тип?.kind === "number"
}

/**
 * Числовой тип по посчитанным границам.
 *
 * ЗДЕСЬ И ЖИВЁТ ПРОВЕРКА ПЕРЕПОЛНЕНИЯ, и она статическая. Отрезок, вышедший за
 * точную сетку double, ПЕРЕСТАЁТ быть целым: за 2^53−1 соседние целые
 * неразличимы, и обещать там точность значило бы обещать неправду. Отсюда
 * главное свойство этой работы: место, где `нат` производится (сложение,
 * умножение), не требует НИ ОДНОГО нового сторожа в рантайме — переполнение
 * ловится РАСШИРЕНИЕМ типа. `нат плюс нат`, чья сумма доказуемо помещается,
 * остаётся `нат`; та, про которую этого не видно, становится `число`. Расширение
 * — не ошибка: программа, писавшая на `число`, продолжает проверяться ровно как
 * раньше.
 *
 * Ненадёжные концы (NaN, ±∞ — они получаются из деления и из умножения на
 * бесконечную границу) стирают уточнение целиком: про такой отрезок сказать
 * нечего, и он становится обычным `число`.
 */
function отрезок(низ, верх, целое) {
  if (!Number.isFinite(низ) || !Number.isFinite(верх) || низ > верх) return NUMBER
  if (целое !== true) return NUMBER
  if (низ < ТОЧНОЕ_ДНО || верх > ТОЧНЫЙ_ПОТОЛОК) return NUMBER
  if (низ === 0 && верх === ТОЧНЫЙ_ПОТОЛОК) return NAT
  if (низ === ТОЧНОЕ_ДНО && верх === ТОЧНЫЙ_ПОТОЛОК) return INTEGER
  return { kind: "number", целое: true, низ, верх }
}

/**
 * Вкладывается ли один числовой отрезок в другой.
 *
 * Целость проверяется в одну сторону: целое годится там, где ждут любое число,
 * а любое число там, где ждут целое, — нет. Это и есть подтипизация, записанная
 * в одну строку.
 */
function вложен(узкий, широкий) {
  if (целыйЛи(широкий) && !целыйЛи(узкий)) return false
  return низОт(узкий) >= низОт(широкий) && верхОт(узкий) <= верхОт(широкий)
}

/**
 * Объединение двух типов: самый узкий тип, в который вкладываются оба.
 *
 * Нужно ровно там, где сходятся ВЕТВИ: `если`, `разбор`, литерал списка. Ветвь
 * `то 0` и ветвь `иначе «Ф» от …` дают два разных отрезка, и тип целого
 * выражения — их объединение, а не первый попавшийся. Без объединения `если`
 * над числами пришлось бы отвергать, и уточнение не пережило бы ни одной
 * развилки.
 *
 * Для всего, что не число, объединение — это прежнее равенство: подтипов у
 * записей, сумм и функций в языке нет и не заводится.
 */
function объединить(a, b) {
  if (!a) return b
  if (!b) return a
  if (a.kind === "unknown") return b
  if (b.kind === "unknown") return a
  if (числовой(a) && числовой(b)) {
    if (a.optional === true || b.optional === true) return NUMBER
    return отрезок(Math.min(низОт(a), низОт(b)), Math.max(верхОт(a), верхОт(b)), целыйЛи(a) && целыйЛи(b))
  }
  if (a.kind === "list" && b.kind === "list") {
    const of = объединить(a.of, b.of)
    return { kind: "list", of }
  }
  return a
}

/**
 * Пересечение двух числовых типов: то, что известно про значение, когда верны
 * оба утверждения сразу. Нужно сужению по условию `если`.
 */
function пересечь(a, b) {
  if (!числовой(a) || !числовой(b)) return a
  const низ = Math.max(низОт(a), низОт(b))
  const верх = Math.min(верхОт(a), верхОт(b))
  const целое = целыйЛи(a) || целыйЛи(b)
  const узкий = отрезок(низ, верх, целое)
  /* Пустой отрезок (`н больше 5` в ветви, где уже известно `н меньше 3`)
     `отрезок` вернул бы как `число` — то есть РАСШИРИЛ бы. Ветвь недостижима, и
     честнее оставить то, что знали до сужения, чем сообщить о значении больше
     правды. */
  return низ > верх ? a : узкий
}

/**
 * ── Сужение по условию `если` ───────────────────────────────────────────────
 *
 * Вторая опора анализа после объявлений — границы, написанные в условиях.
 * `если место меньше длина строки` в ветви `то` говорит про `место` ровно то,
 * что нужно вывести: верхняя граница у него есть. Ровно так уточнение
 * добирается до кода, где `нат` нигде не написан.
 *
 * Что читается: сравнение имени с ЧИСЛОВЫМ ЛИТЕРАЛОМ, с любой стороны, и
 * соединение таких сравнений через `и`. Всё прочее не сужает ничего — это
 * консервативно и потому безопасно: не сузив, анализ теряет доказательство, а
 * не приобретает ложное.
 *
 * ПОЧЕМУ ТОЛЬКО ЛИТЕРАЛ. Сузить по `н меньше м` можно было бы верхом `м`, но
 * `м` — имя, и его собственный отрезок мог быть посчитан в другой ветви. Цена
 * ошибки здесь несимметрична: лишнее сужение делает доказуемым то, что неверно.
 * Литерал же в программе стоит ровно один и не зависит ни от чего.
 *
 * ЦЕЛОСТЬ ГРАНИЦЫ. `н меньше 10` при целом `н` даёт верх 9, а не 10 — но только
 * при ЦЕЛОМ: для `число` строгая граница отрезком не выражается, и там берётся
 * нестрогая. Это единственное место, где уточнение усиливает само себя.
 */
function сузить(cond, env, ветвь) {
  const границы = new Map()
  собратьГраницы(cond, ветвь, границы)
  if (границы.size === 0) return env
  let inner = null
  for (const [имя, список] of границы) {
    const прежний = env.get(имя)
    /* «Может отсутствовать» сужением не трогается: `ничто` в отрезок не
       укладывается, и потерять эту пометку значило бы пообещать значение там,
       где его может не быть. */
    if (!числовой(прежний) || прежний.optional === true) continue
    let узкий = прежний
    for (const { op, предел } of список) узкий = пересечь(узкий, поСравнению(op, предел, целыйЛи(узкий)))
    if (узкий === прежний) continue
    if (inner === null) inner = new Map(env)
    inner.set(имя, узкий)
  }
  return inner ?? env
}

/**
 * Границы, которые условие кладёт на имена в данной ветви.
 *
 * `и притом`, `или` и `не` собственных узлов в AST НЕ ИМЕЮТ: парсер
 * разворачивает их в `если` (`parseDisjunction`, `parseConjunction`,
 * `parseNegation`), и это не деталь разбора, а подарок анализу. Три логических
 * слова читаются здесь одной формой:
 *
 *   `а и притом б`  →  `если а то б иначе нет`      — в ветви `то` верны ОБА;
 *   `а или б`       →  `если а то да иначе б`       — в ветви `иначе` ложны оба;
 *   `не а`          →  `если а то нет иначе да`     — ветви меняются местами.
 *
 * Отличаются они ровно тем, какая ветвь — литерал `да`, а какая — `нет`.
 */
function собратьГраницы(cond, ветвь, наружу) {
  if (!cond || typeof cond !== "object") return
  if (cond.kind === "if") {
    const тоЛи = булевЛитерал(cond.then)
    const иначеЛи = булевЛитерал(cond.else)
    /* `а и притом б`: в ветви `то` верны обе половины. В ветви `иначе` неизвестно,
       какая из них сорвалась, — и потому не сужается ничего. */
    if (иначеЛи === false && ветвь) {
      собратьГраницы(cond.cond, true, наружу)
      собратьГраницы(cond.then, true, наружу)
      return
    }
    /* `а или б`: в ветви `иначе` ложны обе половины. */
    if (тоЛи === true && !ветвь) {
      собратьГраницы(cond.cond, false, наружу)
      собратьГраницы(cond.else, false, наружу)
      return
    }
    /* `не а`: ветви поменялись местами, и вместе с ними — сторона условия. */
    if (тоЛи === false && иначеЛи === true) {
      собратьГраницы(cond.cond, !ветвь, наружу)
    }
    return
  }
  if (cond.kind !== "binary" || !ORDERING.has(cond.op)) return

  const op = ветвь ? cond.op : отрицание(cond.op)
  if (op === null) return
  const слева = cond.left?.kind === "var" && isName(cond.left.name) ? cond.left.name : null
  const справа = cond.right?.kind === "var" && isName(cond.right.name) ? cond.right.name : null
  const левыйЛитерал = числовойЛитерал(cond.left)
  const правыйЛитерал = числовойЛитерал(cond.right)

  /* `имя ОП литерал` и `литерал ОП имя` — одно утверждение, записанное с разных
     сторон. Второе приводится к первому переворотом знака. */
  if (слева !== null && правыйЛитерал !== null) добавить(наружу, слева, op, правыйЛитерал)
  else if (справа !== null && левыйЛитерал !== null) добавить(наружу, справа, перевернуть(op), левыйЛитерал)
}

function добавить(наружу, имя, op, предел) {
  if (op === null) return
  const список = наружу.get(имя)
  if (список === undefined) наружу.set(имя, [{ op, предел }])
  else список.push({ op, предел })
}

function числовойЛитерал(узел) {
  if (узел?.kind !== "literal") return null
  return typeof узел.value === "number" && Number.isFinite(узел.value) ? узел.value : null
}

function булевЛитерал(узел) {
  return узел?.kind === "literal" && typeof узел.value === "boolean" ? узел.value : null
}

const ОТРИЦАНИЕ = new Map([["gt", "lte"], ["lte", "gt"], ["lt", "gte"], ["gte", "lt"]])
const ПЕРЕВОРОТ = new Map([["gt", "lt"], ["lt", "gt"], ["gte", "lte"], ["lte", "gte"]])

function отрицание(op) {
  return ОТРИЦАНИЕ.get(op) ?? null
}

function перевернуть(op) {
  return ПЕРЕВОРОТ.get(op) ?? null
}

/**
 * Ограничение, которое сравнение с литералом кладёт на имя.
 *
 * СТРОГОСТЬ РАБОТАЕТ ТОЛЬКО НА ЦЕЛОМ, и это не упущение, а разница между двумя
 * порядками. `н больше 3` у целого значит `н ≥ 4` — потому что между 3 и 4
 * целых нет. У дробного между ними их сколько угодно, «строго больше 3»
 * отрезком не выражается вовсе, и берётся нестрогая граница: она верна всегда и
 * просто слабее. Ровно поэтому уточнение усиливает само себя: чем точнее тип,
 * тем больше говорит то же самое условие.
 */
function поСравнению(op, предел, целое) {
  const шаг = целое === true ? 1 : 0
  switch (op) {
    case "gte": return { kind: "number", целое, низ: предел, верх: Infinity }
    case "gt": return { kind: "number", целое, низ: предел + шаг, верх: Infinity }
    case "lte": return { kind: "number", целое, низ: -Infinity, верх: предел }
    case "lt": return { kind: "number", целое, низ: -Infinity, верх: предел - шаг }
    default: return null
  }
}

/**
 * Расширение до носителя: посчитанный отрезок забывается, вид типа остаётся.
 *
 * НУЖНО РОВНО ТАМ, ГДЕ ЗНАЧЕНИЕ НЕСЁТСЯ ЧЕРЕЗ ЦИКЛ. Тип накопителя свёртки
 * обязан быть НЕПОДВИЖНОЙ ТОЧКОЙ: он приходит из начального значения, а тело
 * обязано вернуть его же. Начальное значение `0` — это отрезок [0, 0], и тело
 * `акк плюс 1` в него не укладывается никогда, сколько бы витков ни было. Взять
 * объединение тоже нельзя: `акк плюс 1` при `акк: нат` даёт [1, 2^53], то есть
 * выходит за точную сетку и перестаёт быть натуральным — и так на каждом шаге.
 *
 * Языку негде записать тип накопителя (аннотации у `свёртка` в AST нет), а
 * искать неподвижную точку перебором значило бы выводить тело по нескольку раз
 * и печатать его диагностики по нескольку раз. Поэтому здесь стоит честное
 * ограничение, названное вслух: НАКОПИТЕЛЬ СВЁРТКИ НЕ УТОЧНЯЕТСЯ. Цена —
 * `свёртка`, считающая натуральное, даёт `число`; выгода — ни одна написанная
 * программа не получила ни одной новой диагностики, а тип, который нельзя
 * объявить, не выводится наугад.
 */
function расширить(тип) {
  if (числовой(тип) && тип.optional !== true) return NUMBER
  /* Список расширяется ВГЛУБЬ: накопитель `[0]`, к которому тело дописывает
     длины, — это `список числа`, а не `список` отрезка [0, 0]. Растущий список
     несётся через цикл ровно так же, как растущее число. */
  if (тип?.kind === "list" && тип.optional !== true) return { kind: "list", of: расширить(тип.of) }
  return тип
}

/**
 * Числовой тип выражения по интервальной арифметике.
 *
 * Складывать и умножать отрезки можно ровно потому, что обе операции
 * монотонны по каждому аргументу: крайние значения результата достигаются на
 * концах. Деление сюда не попадает НАМЕРЕННО — `делить` в flang даёт IEEE-деление
 * (`3 делить на 2` это 1.5), и отрезок у него был бы целым только по недосмотру.
 * Функция, которой нужно целочисленное деление, пишет его сама, и таких в
 * корпусе уже шесть.
 */
function арифметика(op, left, right) {
  if (!числовой(left) || !числовой(right)) return NUMBER
  const целое = целыйЛи(left) && целыйЛи(right)
  const [a1, a2] = [низОт(left), верхОт(left)]
  const [b1, b2] = [низОт(right), верхОт(right)]
  switch (op) {
    case "add": return отрезок(a1 + b1, a2 + b2, целое)
    case "sub": return отрезок(a1 - b2, a2 - b1, целое)
    case "mul": {
      const углы = [a1 * b1, a1 * b2, a2 * b1, a2 * b2].filter((x) => !Number.isNaN(x))
      if (углы.length < 4) return NUMBER
      return отрезок(Math.min(...углы), Math.max(...углы), целое)
    }
    /* Остаток от неотрицательного делителя: результат лежит в [0, делитель−1] и
       целый, если целы оба. Знак левого операнда важен — в JavaScript `-7 % 3`
       это −1, и то же самое обещают все девять исполнителей, — поэтому дно 0
       берётся только при неотрицательном левом. */
    case "mod": {
      if (!целое || b1 <= 0 || a1 < 0) return NUMBER
      return отрезок(0, Math.max(0, b2 - 1), true)
    }
    default: return NUMBER
  }
}

