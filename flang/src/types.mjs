/**
 * ── Точный натуральный тип ──────────────────────────────────────────────────
 *
 * `нат` — НЕ новый вид значения, а УТОЧНЕНИЕ существующего. Значение остаётся
 * тем же IEEE-754 double, что и у `число`; отличается только обещание, которое
 * про него доказано: это целое из отрезка [0, 2^53−1].
 *
 * ПОЧЕМУ ИМЕННО ТАК, А НЕ НОВЫМ ВИДОМ ЗНАЧЕНИЯ. Восемь исполнителей сверяются
 * побайтово, самоприменение печатает само себя, а `flang/core/*` — триста
 * функций — обязаны остаться на IEEE. Новый вид значения (bignum, список битов,
 * числа Чёрча) означал бы восемь новых рантаймов и новую сверку. Уточнение
 * означает ровно одно: `kind` остаётся `"number"`, и все семь мест языка,
 * решающих по `kind === "number"`, продолжают работать НЕ ИЗМЕНИВШИСЬ. Тип
 * ДОБАВЛЯЕТСЯ, ничего не отнимая.
 *
 * ОТКУДА ПОТОЛОК. Мерено, а не выведено: `х минус 1` впервые не меняет `х` на
 * 2^54. Внутри [−(2^53−1), 2^53−1] целое представимо точно, соседние целые
 * различимы, и `х ± c` при целом c не теряет ни единицы. Ровно это и делает
 * `нат` пригодным дном для доказательства убывания: на нём постоянный шаг
 * доказывается СТАТИЧЕСКИ, и сторож в рантайме не нужен (см. totality.mjs).
 *
 * ПОЧЕМУ ОТРЕЗОК, А НЕ ОДИН ПРИЗНАК. Уточнение записано отрезком [`низ`,
 * `верх`] и признаком `целое` — не потому, что языку нужны произвольные
 * отрезки в объявлениях (их нет и не будет), а потому, что ВЫВОДИТЬ приходится
 * именно отрезки: `н минус 1` при `н: нат` — это [−1, 2^53−1], и назвать этот
 * тип можно только посчитав границы. Написать в объявлении можно два имени —
 * `нат` и `целое`; всё остальное отрезком живёт внутри вывода и наружу
 * выходит теми же двумя именами (`typeName`).
 */
