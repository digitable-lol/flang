/**
 * types.mjs — проверка и вывод типов flang.
 *
 * Вход — AST из SPEC.md, раздел 5 (формат менять нельзя). Выход — диагностики
 * в формате ядра FTS (`{ code, message, severity, span }`, см. src/validate.ts)
 * и таблица сигнатур функций.
 *
 * Почему здесь нет Хиндли — Милнера. Единственные места, где тип действительно
 * неизвестен, — это локальное `пусть`, элемент списка, накопитель свёртки и
 * пустой список. Всё остальное задано объявленной сигнатурой, и функции первого
 * класса этого не изменили: значение-функция строится формой `функция «Имя»`,
 * то есть по объявленной сигнатуре, а не выводится из тела. Унификация с
 * переменными типов дала бы ту же силу вывода, но сообщения об ошибках стали
 * бы говорить о «t7 против t12» вместо «ветви «если» разных типов» — для
 * языка, где типы объявляются, это чистый проигрыш.
 * Поэтому проверка двунаправленная (bidirectional): `inferExpr(узел, среда,
 * ожидаемый)`. Ожидаемый тип течёт сверху вниз и решает единственный
 * по-настоящему неоднозначный случай — пустой список: `[]` в контексте
 * `список строки` получает тип `список строки`, а без контекста —
 * `список неизвестного`, который совместим с чем угодно и потому не даёт
 * каскада ложных ошибок.
 *
 * ── Что здесь появилось вместе с точным натуральным типом ──────────────────
 *
 * Отношений совместимости в языке было ОДНО — `sameType`, то есть равенство.
 * Стало два: `sameType` для НОСИТЕЛЯ (равенство, им сверяются моноид, монада,
 * изоморфизм, состояние процесса) и `годится` для ВТЕКАНИЯ значения в
 * объявленную позицию (подтипизация `нат` ≤ `целое` ≤ `число`). Разделение
 * возможно ровно потому, что `нат` — уточнение, а не новый вид значения:
 * носитель у всех трёх один и тот же IEEE-754 double, и все семь мест языка,
 * решающих по `kind === "number"`, не изменились ни на знак.
 *
 * Вместе с подтипизацией появился интервальный анализ: числовой тип носит
 * отрезок [`низ`, `верх`] и признак `целое`, отрезки складываются и умножаются
 * по правилам интервальной арифметики, а условия `если` кладут на имена
 * границы. Написать в объявлении можно три имени (`нат`, `целое`, `число`);
 * отрезок — внутренняя запись, и наружу он выходит теми же тремя именами.
 *
 * Переполнение при этом ловится РАСШИРЕНИЕМ типа, а не сторожем в рантайме:
 * сумма, про которую не видно, что она помещается в точную сетку double,
 * перестаёт быть целой и становится обычным `число`. Поэтому этап не добавил
 * ни одной проверки в напечатанный код — ни на одно из 209 сложений и 33
 * умножений корпуса.
 */

