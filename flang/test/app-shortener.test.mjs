/**
 * app-shortener.test.mjs — приложение в браузере, прогнанное БЕЗ браузера и БЕЗ
 * сети, но с настоящей службой.
 *
 * Проверяется ПРИЛОЖЕНИЕ, а не его сборка. Разница существенная: сборка отвечает
 * на вопрос «собралось ли», а здесь спрашивается «а что человек увидит, если
 * наберёт адрес и нажмёт кнопку». Ответ сверяется побайтово с текстом экрана.
 *
 * Подмен здесь ровно два, и оба — про мир, а не про поведение:
 *
 *   ДОКУМЕНТ — объект с `querySelector`, `querySelectorAll` и
 *      `addEventListener`. Тот же приём, что у соседа
 *      (`flang/test/host-browser.test.mjs`): хозяин браузера работает с ним так
 *      же, как с окном вкладки.
 *   СЕТЬ — `fetch`, за которым стоит НАСТОЯЩАЯ служба-сокращатель на flang
 *      (`flang/examples/web/shortener/service.flang`), позванная в памяти. Ни
 *      сокета, ни порта: «Обслужить» — чистая функция «состояние и байты
 *      запроса → новое состояние и байты ответа», ровно как в `serve.mjs` рядом
 *      со службой. Значит проверка гоняет два приложения на flang сразу,
 *      клиента и службу, и сверяет то, что вышло у обоих.
 *
 * Чего здесь НЕ проверяется и проверено быть не может: что настоящий браузер
 * съест программу, что настоящий `addEventListener` разбудит план и что
 * настоящий `fetch` донесёт запрос. Это `web/shortener/probe.mjs`.
 */

import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { loadProgram } from "../bin/flang.mjs"
import { evaluateFlang } from "../src/compat.mjs"
import { browserHost } from "../src/host/browser.mjs"
import { runPlan } from "../src/io.mjs"
import { parse } from "../src/parser.mjs"

const КЛИЕНТ = fileURLToPath(new URL("../../web/shortener/klient.flang", import.meta.url))
const СЛУЖБА = fileURLToPath(new URL("../examples/web/shortener/service.flang", import.meta.url))

/** Разобранный клиент — один на все проверки файла. */
async function клиент() {
  return parse(await readFile(КЛИЕНТ, "utf8"), { file: КЛИЕНТ })
}

/**
 * Подставная страница: места, кнопки и ПОЛЯ ВВОДА.
 *
 * Поля — то, чего не было у соседа, и они здесь не для полноты. Кнопка приносит
 * объявленное страницей `данные-значение`, а поле — своё содержимое, и порядок
 * этих двух источников однажды уже стоил упавшего прогона в настоящем браузере.
 * Поэтому у кнопок ниже `value` пустой строкой, как в настоящем HTML.
 */
function страница({ места = [], кнопки = [], поля = [] } = {}) {
  const узлы = new Map()
  for (const имя of места) {
    узлы.set(`[данные-место="${имя}"]`, { textContent: "", getAttribute: () => имя })
  }
  const источники = []
  const слушателей = (узел) => (узел.слушатели ??= [])
  for (const значение of кнопки) {
    источники.push({
      вид: "кнопка",
      значение,
      value: "",
      getAttribute: (что) =>
        что === "данные-событие" ? "кнопка" : что === "данные-значение" ? значение : null,
      addEventListener(что, кто) {
        слушателей(this).push({ что, кто })
      },
      textContent: значение,
    })
  }
  for (const имя of поля) {
    источники.push({
      вид: "поле",
      значение: имя,
      value: "",
      /* У поля ввода объявленного значения НЕТ — хозяин обязан спросить
         содержимое. Ровно так устроен настоящий `<input>`. */
      getAttribute: (что) => (что === "данные-событие" ? имя : null),
      addEventListener(что, кто) {
        слушателей(this).push({ что, кто })
      },
      textContent: "",
    })
  }
  const найти = (значение) => {
    const узел = источники.find((к) => к.значение === значение)
    assert.ok(узел !== undefined, `нет источника «${значение}»`)
    return узел
  }
  const позвать = (узел, вид) => {
    for (const { что, кто } of узел.слушатели ?? []) if (что === вид) кто()
  }
  return {
    querySelector: (селектор) => узлы.get(селектор) ?? null,
    querySelectorAll: () => источники,
    нажать: (значение) => позвать(найти(значение), "click"),
    набрать(имя, текст) {
      const узел = найти(имя)
      узел.value = текст
      позвать(узел, "input")
    },
    экран: () => узлы.get('[данные-место="экран"]')?.textContent ?? null,
  }
}

/**
 * Настоящая служба-сокращатель, позванная в памяти вместо сети.
 *
 * `Content-Length` считается ЗНАКАМИ, а не октетами, и это не небрежность: так
 * его считает сама служба (`длина` в языке считает знаки). Хозяин, говорящий с
 * настоящей сетью, обязан был бы считать октеты — там это делает
 * `web/shortener/stend.mjs`, и там же названо, почему.
 */
async function службаВПамяти() {
  const программа = await loadProgram(СЛУЖБА)
  let хранилище = { записи: [], выдано: 0 }
  const журнал = []
  const сходить = async (адрес, запрос = {}) => {
    const способ = String(запрос.method ?? "GET")
    const тело = String(запрос.body ?? "")
    журнал.push(`${способ} ${адрес}`)
    const голова = `${способ} ${адрес} HTTP/1.1\r\nHost: проба\r\n`
    const текст =
      тело === "" ? `${голова}\r\n` : `${голова}Content-Length: ${[...тело].length}\r\n\r\n${тело}`
    const о = evaluateFlang(программа, "Обслужить", { хранилище, текст }, { maxSteps: 40_000_000 })
    хранилище = о["состояние"]
    const сырой = о["ответ"] ?? ""
    const рубеж = сырой.indexOf("\r\n\r\n")
    return { status: о["код"], text: async () => (рубеж < 0 ? "" : сырой.slice(рубеж + 4)) }
  }
  сходить.журнал = журнал
  сходить.хранилище = () => хранилище
  return сходить
}

/** Хозяин пробы: настоящий `browserHost`, но с мгновенными часами. */
function хозяинПробы(окно, сходить) {
  const исполнить = browserHost({
    документ: окно,
    fetch: сходить,
    отложить: (что) => setTimeout(что, 0),
    снять: (метка) => clearTimeout(метка),
  })
  /* «Ждать событие» со сроком 0 значит «жду человека без предела». Рук, которые
     нажмут, здесь нет, поэтому предел приходится назначить — единственное
     послабление, и оно названо вслух, как у соседа. */
  return async (поручение) =>
    поручение.variant === "Ждать событие" && Number(поручение.fields?.["срок"] ?? 0) === 0
      ? await исполнить({ ...поручение, fields: { срок: 1 } })
      : await исполнить(поручение)
}

/**
 * Прогон приложения до заданного числа поручений.
 *
 * Конца у плана нет ни одной веткой — приложение кончается тогда, когда
 * закрывают вкладку. Значит останов приходит СНАРУЖИ, и `FLANG_IO_LIMIT` здесь
 * успешный конец прогона, а не беда.
 */
async function прогнать(программа, хозяин, поручений) {
  try {
    await runPlan(программа, "Стойка ссылок", хозяин, { maxOrders: поручений })
    assert.fail("приложение обязано было упереться в предел: конца у него нет")
  } catch (беда) {
    assert.equal(беда.code, "FLANG_IO_LIMIT", `ждали предел, а получили: ${беда.message}`)
  }
}

const ПОЛНАЯ = {
  места: ["экран", "итог"],
  кнопки: ["сократить", "обновить", "перейти", "очистить"],
  поля: ["адрес", "код"],
}

test("приложение само спрашивает у службы список, не дожидаясь человека", async () => {
  const программа = await клиент()
  const окно = страница(ПОЛНАЯ)
  const сходить = await службаВПамяти()
  await прогнать(программа, хозяинПробы(окно, сходить), 6)

  assert.deepEqual(сходить.журнал, ["GET /ссылки"])
  assert.equal(
    окно.экран(),
    "адрес:  \nкод:    \nссылок: 0\n\n  (ссылок пока нет)\n\nсписок свежий: ссылок 0",
  )
})

test("набранный адрес доезжает до программы целиком, а не по букве", async () => {
  const программа = await клиент()
  const окно = страница(ПОЛНАЯ)
  const сходить = await службаВПамяти()

  setTimeout(() => окно.набрать("адрес", "https://пример.рф/док"), 0)
  await прогнать(программа, хозяинПробы(окно, сходить), 8)

  assert.match(окно.экран(), /^адрес: {2}https:\/\/пример\.рф\/док$/mu)
})

test("«сократить» доходит до службы, и список обновляется тем же ходом", async () => {
  const программа = await клиент()
  const окно = страница(ПОЛНАЯ)
  const сходить = await службаВПамяти()

  setTimeout(() => {
    окно.набрать("адрес", "https://пример.рф/док")
    окно.нажать("сократить")
  }, 0)
  await прогнать(программа, хозяинПробы(окно, сходить), 14)

  /* Три запроса, и третий — не лишний: «Создано» задумывает список, потому что
     после создания на экране обязан быть СВЕЖИЙ список, а не прежний. */
  assert.deepEqual(сходить.журнал, ["GET /ссылки", "POST /ссылки", "GET /ссылки"])
  assert.equal(
    окно.экран(),
    "адрес:  \nкод:    к1\nссылок: 1\n\n  к1   →  https://пример.рф/док   (переходов 0)" +
      "\n\nсписок свежий: ссылок 1",
  )
})

test("переход по короткой ссылке двигает счётчик службы", async () => {
  const программа = await клиент()
  const окно = страница(ПОЛНАЯ)
  const сходить = await службаВПамяти()

  setTimeout(() => {
    окно.набрать("адрес", "https://пример.рф/док")
    окно.нажать("сократить")
  }, 0)
  setTimeout(() => {
    окно.набрать("код", "к1")
    окно.нажать("перейти")
  }, 20)
  await прогнать(программа, хозяинПробы(окно, сходить), 26)

  assert.deepEqual(сходить.журнал, [
    "GET /ссылки",
    "POST /ссылки",
    "GET /ссылки",
    "GET /с/к1",
    "GET /ссылки",
  ])
  assert.equal(сходить.хранилище().записи[0].переходов, 1)
  assert.match(окно.экран(), /\(переходов 1\)/u)
})

test("отказ службы — ответ, а не поломка: приложение показывает его и живёт", async () => {
  const программа = await клиент()
  const окно = страница(ПОЛНАЯ)
  const сходить = await службаВПамяти()

  /* `javascript:` служба отвергает кодом 422 — её решение, не наше. Клиент
     обязан показать сказанное и остаться живым, а не сдаться. */
  setTimeout(() => {
    окно.набрать("адрес", "javascript:alert(1)")
    окно.нажать("сократить")
  }, 0)
  await прогнать(программа, хозяинПробы(окно, сходить), 14)

  assert.match(окно.экран(), /служба отказала \(422\): адрес принимается только по http и https/u)
})

test("сеть отвалилась — хозяин сказал кодом, приложение осталось живым", async () => {
  const программа = await клиент()
  const окно = страница(ПОЛНАЯ)
  const сходить = async () => {
    throw new Error("fetch failed")
  }
  await прогнать(программа, хозяинПробы(окно, сходить), 6)

  assert.match(окно.экран(), /хозяин не смог \(FLANG_IO_NET\): fetch failed/u)
})

test("места на странице нет — план сдаётся кодом хозяина, а не крутится вечно", async () => {
  const программа = await клиент()
  /* Ни одного места: показывать некуда. Это единственный случай, когда
     приложение сдаётся, и сдаётся оно КОДОМ ХОЗЯИНА, а не своим. */
  const окно = страница({ места: [], кнопки: ["обновить"], поля: ["адрес"] })
  const сходить = await службаВПамяти()

  await assert.rejects(
    runPlan(программа, "Стойка ссылок", хозяинПробы(окно, сходить), { maxOrders: 50 }),
    (беда) => {
      assert.equal(беда.code, "FLANG_IO_PLACE")
      assert.match(беда.message, /на странице нет места «экран»/u)
      return true
    },
  )
})

test("напечатанный в JavaScript модуль считает то же, что вычислитель", async () => {
  /* Приложение печатается в JavaScript тем же генератором, что и всё остальное,
     и напечатанное обязано СЧИТАТЬ то же самое. Проверяется на обработчике —
     самой сложной функции приложения, через которую проходит каждый виток.
     Чего проверить нельзя, названо в README рядом: план (`план «Стойка
     ссылок»`) генератор не печатает вовсе, поэтому напечатанный модуль умеет
     считать, но не умеет работать. */
  const { mkdtemp, rm } = await import("node:fs/promises")
  const { tmpdir } = await import("node:os")
  const { join } = await import("node:path")
  const { emitJs } = await import("../src/emit/js.mjs")

  const программа = await loadProgram(КЛИЕНТ)
  const напечатано = emitJs(программа, { cli: false })
  const куда = await mkdtemp(join(tmpdir(), "flang-stoyka-"))
  try {
    const { writeFile } = await import("node:fs/promises")
    const файл = join(куда, напечатано.files[0].path)
    await writeFile(файл, напечатано.files[0].content, "utf8")
    const модуль = await import(`file://${файл}`)

    const начальное = модуль.nachat()
    assert.deepEqual(начальное, {
      набрано: "",
      выбран: "",
      ссылки: [],
      дело: "список",
      сообщение: "спрашиваем список…",
    })

    const продолжение = модуль.dalshe(начальное, модуль.Pokazano({}))
    assert.equal(продолжение.variant, "Сделать")
    assert.equal(продолжение.fields["поручение"].variant, "Запросить")
    assert.equal(продолжение.fields["поручение"].fields["адрес"], "/ссылки")

    /* То же самое у вычислителя — и результаты обязаны совпасть, иначе
       напечатанное и написанное разошлись бы молча. */
    const уВычислителя = evaluateFlang(
      программа,
      "Спросить службу",
      { стойка: начальное },
      { maxSteps: 1_000_000 },
    )
    assert.equal(уВычислителя.fields["поручение"].fields["адрес"], "/ссылки")
  } finally {
    await rm(куда, { recursive: true, force: true })
  }
})
