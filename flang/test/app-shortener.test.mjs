test("напечатанный в JavaScript модуль считает то же, что вычислитель", async () => {
  /* Приложение печатается в JavaScript тем же генератором, что и всё остальное,
     и напечатанное обязано СЧИТАТЬ то же самое. Проверяется на обработчике —
     самой сложной функции приложения, через которую проходит каждый виток.
     Здесь проверяется только СЧЁТ. Что напечатанный модуль умеет и работать —
     то есть что план в нём есть и крутится, — проверяет соседний тест. */
  const { mkdtemp, rm } = await import("node:fs/promises")
  const { tmpdir } = await import("node:os")
  const { join } = await import("node:path")
  const { emitJs } = await import("../src/emit/js.mjs")

  const программа = await loadProgram(КЛИЕНТ)
  const напечатано = emitJs(программа, { cli: false })
  const куда = await mkdtemp(join(tmpdir(), "flang-stoyka-"))
  try {
    const { writeFile } = await import("node:fs/promises")
    const файл = join(куда, напечатано.files[0].path)
    await writeFile(файл, напечатано.files[0].content, "utf8")
    const модуль = await import(`file://${файл}`)

    const начальное = модуль.nachat()
    assert.deepEqual(начальное, {
      набрано: "",
      выбран: "",
      ссылки: [],
      дело: "список",
      сообщение: "спрашиваем список…",
    })

    const продолжение = модуль.dalshe(начальное, модуль.Pokazano({}))
    assert.equal(продолжение.variant, "Сделать")
    assert.equal(продолжение.fields["поручение"].variant, "Запросить")
    assert.equal(продолжение.fields["поручение"].fields["адрес"], "/ссылки")

    /* То же самое у вычислителя — и результаты обязаны совпасть, иначе
       напечатанное и написанное разошлись бы молча. */
    const уВычислителя = evaluateFlang(
      программа,
      "Спросить службу",
      { стойка: начальное },
      { maxSteps: 1_000_000 },
    )
    assert.equal(уВычислителя.fields["поручение"].fields["адрес"], "/ссылки")
  } finally {
    await rm(куда, { recursive: true, force: true })
  }
})

test("предел поручений: умолчание держит, ключ двигает, ноль снимает", async (t) => {
  /*
   * ПОДДЕЛКА, ради которой этот тест написан, и она нашлась снятием правки:
   * из напечатанного исполнителя убрали ВЕСЬ предел поручений — и весь набор
   * проверок остался ЗЕЛЁНЫМ. Предел при этом не украшение: умолчание в
   * 10 000 — мера пакетной программы, которая кончается, а страница приложения
   * снимает его нулём именно потому, что вкладка не кончается. То есть
   * проверялось «приложение работает», а не «ключ, которым оно работает,
   * что-нибудь значит».
   *
   * План здесь ИМЕННО ЭТОТ, а не соседний: у «Стойки ссылок» нет ни одной
   * ветки «Конец работы» — кончает её человек. Значит без предела она крутится
   * ровно столько, сколько отвечает хозяин, и все три случая различимы.
   */
  const { mkdtemp, rm } = await import("node:fs/promises")
  const { tmpdir } = await import("node:os")
  const { join } = await import("node:path")
  const { emitJs } = await import("../src/emit/js.mjs")

  const напечатано = emitJs(await loadProgram(КЛИЕНТ), { cli: false })
  const куда = await mkdtemp(join(tmpdir(), "flang-stoyka-predel-"))
  try {
    const { writeFile } = await import("node:fs/promises")
    const файл = join(куда, напечатано.files[0].path)
    await writeFile(файл, напечатано.files[0].content, "utf8")
    const модуль = await import(`file://${файл}`)
    const описатель = модуль.ioPlan()

    /* Хозяин, который не кончается сам: показ — «Показано», ожидание —
       нажатие, сеть — пустой список. Считает выданные поручения и по
       достижении `хватит` останавливает план своим кодом. */
    const крутить = async (настройки, хватит) => {
      let выдано = 0
      const хозяин = (поручение) => {
        выдано += 1
        if (выдано >= хватит) return описатель.вариант("Сбой", { код: "FLANG_IO_PLACE", сообщение: "хватит" })
        if (поручение.variant === "Показать") return описатель.вариант("Показано", {})
        if (поручение.variant === "Ждать событие") {
          return описатель.вариант("Случилось", { откуда: "кнопка", значение: "обновить" })
        }
        if (поручение.variant === "Запросить") return описатель.вариант("Ответ сети", { код: 200, тело: "" })
        return описатель.вариант("Сбой", { код: "FLANG_IO_UNKNOWN", сообщение: поручение.variant })
      }
      try {
        await модуль.ioRun("Стойка ссылок", хозяин, настройки)
        return { код: null, выдано }
      } catch (беда) {
        return { код: беда.code, выдано }
      }
    }

    /* 1. Ключом. Предел в семь поручений обязан сработать раньше хозяина,
          который остановился бы на сотом. */
    const семь = await крутить({ поручений: 7 }, 100)
    t.diagnostic(`предел 7: код ${семь.код}, выдано ${семь.выдано}`)
    assert.equal(семь.код, "FLANG_IO_LIMIT", "предел поручений не сработал")
    assert.equal(семь.выдано, 7, `выдано ${семь.выдано} поручений вместо семи`)

    /* 2. Умолчанием. Ключа нет — работает то же число, что у свидетеля. */
    const умолчание = await крутить({}, 100_000)
    t.diagnostic(`умолчание: код ${умолчание.код}, выдано ${умолчание.выдано}`)
    assert.equal(умолчание.код, "FLANG_IO_LIMIT", "без ключа предела не оказалось вовсе")
    assert.equal(умолчание.выдано, 10_000, `умолчание оказалось ${умолчание.выдано}, а не 10 000`)

    /* 3. Нулём. Предел снят — план идёт ЗА умолчание, и останавливает его
          хозяин, а не исполнитель. Это ровно тот случай, которым живёт
          страница приложения. */
    const без = await крутить({ поручений: 0 }, 12_345)
    t.diagnostic(`без предела: код ${без.код}, выдано ${без.выдано}`)
    assert.equal(без.код, "FLANG_IO_PLACE", "ноль не снял предел — план остановил исполнитель, а не хозяин")
    assert.equal(без.выдано, 12_345, `выдано ${без.выдано} вместо 12 345`)
    assert.ok(без.выдано > умолчание.выдано, "«без предела» не ушло дальше умолчания — различить нечем")
  } finally {
    await rm(куда, { recursive: true, force: true })
  }
})

test("напечатанный модуль УМЕЕТ РАБОТАТЬ: план в нём есть и крутится хозяином", async (t) => {
  /*
   * Улика, ради которой этот тест написан: раньше генератор печатал 67
   * экспортов приложения — всё, включая обе функции плана, — и терял само
   * объявление `план` (0 байт, 0 диагностик, код возврата 0). Снаружи получался
   * набор функций, про который нельзя узнать, что это программа ввода-вывода.
   *
   * Проверяется именно ЭТО: не «в тексте есть слово план», а что по описателю
   * из напечатанного модуля хозяин, ничего не знающий об этом приложении,
   * доводит его до настоящего экрана. Хозяин здесь поддельный — список
   * заготовленных откликов, — и потому ни браузера, ни сети тут нет.
   */
  const { mkdtemp, rm } = await import("node:fs/promises")
  const { tmpdir } = await import("node:os")
  const { join } = await import("node:path")
  const { emitJs } = await import("../src/emit/js.mjs")

  const напечатано = emitJs(await loadProgram(КЛИЕНТ), { cli: false })
  const куда = await mkdtemp(join(tmpdir(), "flang-stoyka-plan-"))
  try {
    const { writeFile } = await import("node:fs/promises")
    const файл = join(куда, напечатано.files[0].path)
    await writeFile(файл, напечатано.files[0].content, "utf8")
    const модуль = await import(`file://${файл}`)

    const описатель = модуль.ioPlan()
    assert.equal(описатель.планы.length, 1, "планов в описателе не один")
    assert.equal(описатель.планы[0].имя, "Стойка ссылок")
    assert.equal(описатель.планы[0].состояние, "Стойка")
    assert.equal(описатель.планы[0].начало, модуль.nachat, "начало плана — не та функция")
    assert.equal(описатель.планы[0].шаг, модуль.dalshe, "шаг плана — не та функция")

    /* Поддельный хозяин: показывает в никуда, отвечает за службу списком из
       одной ссылки и на третьем показе останавливает план кодом. Останавливает
       СВОИМ кодом, а не пределом: предел проверял бы исполнителя, а нам нужно,
       чтобы проверялось приложение. */
    const экраны = []
    let показов = 0
    const ответ = "к1 http://пример.рф 7"
    const хозяин = (поручение) => {
      const поля = поручение.fields
      if (поручение.variant === "Показать") {
        экраны.push(String(поля["текст"]))
        показов += 1
        if (показов >= 3) {
          return описатель.вариант("Сбой", { код: "FLANG_IO_PLACE", сообщение: "хватит" })
        }
        return описатель.вариант("Показано", {})
      }
      if (поручение.variant === "Запросить") {
        return описатель.вариант("Ответ сети", { код: 200, тело: ответ })
      }
      if (поручение.variant === "Ждать событие") {
        return описатель.вариант("Случилось", { откуда: "кнопка", значение: "обновить" })
      }
      return описатель.вариант("Сбой", { код: "FLANG_IO_UNKNOWN", сообщение: поручение.variant })
    }

    let отказ = null
    try {
      await модуль.ioRun("Стойка ссылок", хозяин, { поручений: 0 })
    } catch (беда) {
      отказ = беда
    }
    t.diagnostic(`показов экрана: ${экраны.length}`)
    assert.equal(отказ?.code, "FLANG_IO_PLACE", "план остановил не хозяин")
    assert.equal(отказ?.сдался, true, "не отмечено, что сдалась программа, а не сломался исполнитель")
    assert.ok(экраны.length >= 3, `экран собрался ${экраны.length} раз вместо трёх`)
    assert.match(экраны[0], /спрашиваем список…/u, "первый экран — не тот, с которого приложение начинает")
    assert.match(экраны[1], /к1 http:\/\/пример\.рф/u, "ответ службы не доехал до экрана")
    assert.match(экраны[1], /ссылок: 1/u, "список не разобран")
  } finally {
    await rm(куда, { recursive: true, force: true })
  }
})
