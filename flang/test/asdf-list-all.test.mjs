/**
 * Список версий плагина asdf обязан состоять из версий, которые МОЖНО ПОСТАВИТЬ.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * 18 августа 2026 `asdf list-all flang` предлагал 0.4.8, а `asdf install flang
 * 0.4.8` падал:
 *
 *     flang 0.4.8: скачиваю flang-0.4.8-c.tar.gz
 *     curl: (22) The requested URL returned error: 404
 *     не удалось скачать .../download/v0.4.8/flang-0.4.8-c.tar.gz
 *     версии, которые можно поставить, показывает 'asdf list-all flang'
 *
 * Последняя строка — совет, замкнутый в кольцо: он отсылает к списку, который
 * 0.4.8 и предложил. Человек честно делает, что сказано, и получает тот же ответ.
 *
 * Причина: v0.4.8 — настоящий релиз (аннотированный тег владельца, 129 коммитов
 * после v0.4.7, прямой предок v0.5.0), у которого просто НЕТ вложений. Скрипт
 * отбирал релизы вместо тегов — и написал об этом в комментарии прямым текстом,
 * «список, из которого нельзя поставить, хуже короткого», — но релиз без архива
 * его отбор не отсеивал. Намерение было записано верно, а код проверял не то.
 *
 * Отсюда предмет этого файла: не «релиз существует», а «архив отдаётся». Ровно
 * от этого зависит установка, и ровно это должно определять список.
 *
 * ── Почему две проверки, а не одна ──────────────────────────────────────────
 * Первая идёт без сети на заготовленном ответе: она обязана краснеть всегда, на
 * любой машине, и именно она стережёт сам отбор. Вторая ходит на GitHub и
 * сверяет список с тем, что там лежит сегодня: только она заметит релиз без
 * архива, выпущенный завтра. Без первой проверка выключается вместе с сетью;
 * без второй она не знает о настоящих релизах ничего.
 *
 * Обе гоняют НАСТОЯЩИЙ bin/list-all, а не его пересказ на JavaScript. Проверять
 * пересказ бессмысленно: поедет пользователю оболочка.
 *
 * Запуск:  node --test flang/test/asdf-list-all.test.mjs
 * Заглушить сетевую половину:  FLANG_SKIP_RELEASE_CHECK=1
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const СКРИПТ = join(корень, "packaging/asdf/bin/list-all")
const РЕПО = "digitable-lol/flang"
const ЖДАТЬ = 15000

/** Имя архива, которое bin/download соберёт из версии. Одно место на весь файл:
 *  если оно разойдётся со скриптом скачивания, разойдётся и проверка. */
export const имяАрхива = (версия) => `flang-${версия}-c.tar.gz`

/** Версии, которые ДОЛЖНЫ быть в списке: у релиза есть вложение с тем самым
 *  именем. Всё остальное поставить нельзя, сколько бы релиз ни существовал. */
export function версииСАрхивом(релизы) {
  const годные = []
  for (const релиз of релизы ?? []) {
    const версия = /^v(\d+\.\d+\.\d+)$/u.exec(релиз.tag_name ?? "")?.[1]
    if (!версия) continue
    if ((релиз.assets ?? []).some((в) => в.name === имяАрхива(версия))) годные.push(версия)
  }
  return годные
}

/** Версии релизов БЕЗ архива — те самые, из-за которых заведён файл. */
export function версииБезАрхива(релизы) {
  const пустые = []
  for (const релиз of релизы ?? []) {
    const версия = /^v(\d+\.\d+\.\d+)$/u.exec(релиз.tag_name ?? "")?.[1]
    if (!версия) continue
    if (!(релиз.assets ?? []).some((в) => в.name === имяАрхива(версия))) пустые.push(версия)
  }
  return пустые
}

const посортировать = (версии) =>
  [...версии].sort((а, б) => {
    const [а1, а2, а3] = а.split(".").map(Number)
    const [б1, б2, б3] = б.split(".").map(Number)
    return а1 - б1 || а2 - б2 || а3 - б3
  })

/** Прогон настоящего скрипта. Возвращает список версий, как его увидит asdf. */
function прогнать(окружение = {}) {
  const вывод = execFileSync("bash", [СКРИПТ], {
    encoding: "utf8",
    timeout: 60000,
    env: { ...process.env, ...окружение },
  })
  return вывод.trim().split(/\s+/u).filter(Boolean)
}

/** Список именами — чтобы красный называл виновных, а не только их число. */
const списком = (версии) => (версии.length === 0 ? "(пусто)" : версии.join(" "))

/* ------------------------------------------------- отбор, без сети и без GitHub */

test("релиз без архива в список не попадает", () => {
  /*
   * Заготовленный ответ вместо GitHub. Четыре случая, и три из них — беда:
   *   9.9.9 — архив есть, имя сходится        → обязан быть в списке;
   *   9.9.8 — вложений НЕТ вовсе              → это ровно случай v0.4.8;
   *   9.9.7 — вложение есть, но не архив      → релиз не пуст, а поставить нечего;
   *   9.9.6 — архив есть, но от другой версии → bin/download запросит своё имя и
   *                                             получит 404, как и в первом случае.
   * Последний случай стоит здесь не для полноты: имя архива и тег — разные поля,
   * и разойтись они могут молча.
   */
  const каталог = mkdtempSync(join(tmpdir(), "flang-asdf-list-"))
  try {
    const ответ = join(каталог, "releases.json")
    const адрес = (тег, файл) => `https://github.com/${РЕПО}/releases/download/${тег}/${файл}`
    writeFileSync(
      ответ,
      JSON.stringify([
        { tag_name: "v9.9.9", assets: [{ name: "flang-9.9.9-c.tar.gz", browser_download_url: адрес("v9.9.9", "flang-9.9.9-c.tar.gz") }] },
        { tag_name: "v9.9.8", assets: [] },
        { tag_name: "v9.9.7", assets: [{ name: "notes.txt", browser_download_url: адрес("v9.9.7", "notes.txt") }] },
        { tag_name: "v9.9.6", assets: [{ name: "flang-9.9.5-c.tar.gz", browser_download_url: адрес("v9.9.6", "flang-9.9.5-c.tar.gz") }] },
      ]),
      "utf8",
    )

    const названы = прогнать({ FLANG_RELEASES_URL: `file://${ответ}` })
    const ожидаем = ["9.9.9"]
    const лишние = названы.filter((в) => !ожидаем.includes(в))
    const пропали = ожидаем.filter((в) => !названы.includes(в))

    assert.deepEqual(
      названы,
      ожидаем,
      `bin/list-all назвал: ${списком(названы)}; ожидали: ${списком(ожидаем)}. ` +
        `Лишние (поставить нельзя, а предложены): ${списком(лишние)}. ` +
        `Пропавшие (поставить можно, а не предложены): ${списком(пропали)}. ` +
        `Названо ${названы.length}, ожидалось ${ожидаем.length}.`,
    )
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
})

/* -------------------------------------------------------- сверка с живым GitHub */

async function githubДоступен() {
  try {
    const заголовки = { accept: "application/vnd.github+json", "user-agent": "flang-asdf-list-check" }
    const токен = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN ?? process.env.GITHUB_API_TOKEN
    if (токен) заголовки.authorization = `Bearer ${токен}`
    const ответ = await fetch(`https://api.github.com/repos/${РЕПО}/releases?per_page=100`, {
      headers: заголовки,
      signal: AbortSignal.timeout(ЖДАТЬ),
    })
    if (ответ.status === 403 || ответ.status === 429) {
      return { да: false, почему: `API GitHub ответил ${ответ.status} (лимит запросов)` }
    }
    if (!ответ.ok) return { да: false, почему: `API GitHub ответил ${ответ.status}` }
    return { да: true, релизы: await ответ.json() }
  } catch (беда) {
    return { да: false, почему: `до api.github.com не достучались: ${беда.message}` }
  }
}

test("список плагина совпадает с тем, что на GitHub можно скачать", async (t) => {
  if (process.env.FLANG_SKIP_RELEASE_CHECK) {
    t.skip("проверка выключена намеренно: FLANG_SKIP_RELEASE_CHECK")
    return
  }
  const доступ = await githubДоступен()
  if (!доступ.да) {
    /* Пропуск обязан называть причину: «не смог проверить» и «проверил, всё
       хорошо» — разные исходы, и смешение их однажды уже пропустило ложь. */
    t.skip(`GitHub недоступен, список плагина НЕ ПРОВЕРЕН — ${доступ.почему}`)
    return
  }

  const ставятся = посортировать(версииСАрхивом(доступ.релизы))
  const пустые = посортировать(версииБезАрхива(доступ.релизы))
  const названы = прогнать()

  /* Главное утверждение файла, и сформулировано оно ровно как беда: релиз без
     архива, попавший в выдачу, — красное. */
  const предложеныЗря = названы.filter((в) => пустые.includes(в))
  assert.deepEqual(
    предложеныЗря,
    [],
    `bin/list-all предлагает версии, у которых на GitHub НЕТ архива: ${списком(предложеныЗря)}. ` +
      `«asdf install flang ${предложеныЗря[0] ?? "…"}» упадёт на скачивании с 404, ` +
      `а сообщение об ошибке отошлёт человека обратно к этому же списку. ` +
      `Релизов без архива всего ${пустые.length}: ${списком(пустые)}. ` +
      `Названо ${названы.length}: ${списком(названы)}.`,
  )

  /* И обратное: отбор не должен выкинуть годную версию. Короткий список — тоже
     беда, просто тихая: человек не узнает, что версия есть. */
  const потеряны = ставятся.filter((в) => !названы.includes(в))
  assert.deepEqual(
    потеряны,
    [],
    `на GitHub есть архив, а bin/list-all эти версии не назвал: ${списком(потеряны)}. ` +
      `Можно поставить ${ставятся.length}: ${списком(ставятся)}. ` +
      `Названо ${названы.length}: ${списком(названы)}.`,
  )

  assert.deepEqual(
    названы,
    ставятся,
    `список плагина разошёлся со скачиваемым. ` +
      `Названо ${названы.length}: ${списком(названы)}. ` +
      `Скачивается ${ставятся.length}: ${списком(ставятся)}.`,
  )
})
