/**
 * Сторож состава правил — сам под проверкой.
 *
 * Сторож, который не умеет краснеть, выглядит ровно как сторож, у которого всё
 * хорошо. Поэтому здесь четыре ИЗЪЯТИЯ: у дерева по очереди отнимается ровно то,
 * что сторож держит, и каждое обязано дать своё нарушение своего рода. Изъятия
 * делаются на КОПИИ дерева во временном каталоге — само дерево не трогается.
 *
 * Пятая проверка — «на живом дереве нарушений нет»: без неё четыре изъятия
 * доказывали бы только, что сторож умеет ругаться.
 */
import assert from "node:assert/strict"
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { test } from "node:test"
import { fileURLToPath } from "node:url"

import {
  РАЗНИЦА,
  СПРАВКА,
  СУДЬИ_СВИДЕТЕЛЯ,
  ТОЛЬКО_У_БИНАРНИКА,
  ВХОД_БИНАРНИКА,
  кодыФайла,
  проверить,
  числа,
} from "../scripts/binary-rules-guard.mjs"
import { рабочийКаталог } from "./tempdir.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const работа = рабочийКаталог("binary-rules")

/** Копия дерева ровно в том объёме, какой читает сторож. */
function копия(метка) {
  const куда = join(работа, метка)
  for (const кусок of ["flang/src", "flang/self", "flang/stdlib", "flang/core"]) {
    cpSync(join(корень, кусок), join(куда, кусок), { recursive: true })
  }
  return куда
}

/** Правка одного файла в копии: место обязано найтись, иначе изъятие не о том. */
function подменить(куда, отн, было, стало) {
  const путь = join(куда, отн)
  const текст = readFileSync(путь, "utf8")
  const новый = текст.replace(было, стало)
  assert.notEqual(новый, текст, `${отн}: место изъятия не найдено — изъятие проверяет не то`)
  mkdirSync(dirname(путь), { recursive: true })
  writeFileSync(путь, новый, "utf8")
  return куда
}

test("на живом дереве нарушений нет, и число расхождений названо", () => {
  const итог = числа(корень)
  assert.deepEqual(проверить(корень), [])
  assert.ok(итог.расходится > 0, "расхождений ноль — сторожу нечего стеречь, и это подозрительно")
  assert.equal(итог.поверхностей, РАЗНИЦА.length)
})

test("ИЗЪЯТИЕ: правило свидетеля, не названное в РАЗНИЦА, — красно", () => {
  /* Свидетелю дописывается код, которого нет ни у бинарника, ни в списке. */
  const куда = подменить(
    копия("новое-правило"),
    "flang/src/types.mjs",
    '"FLANG_MORPHISM_SHAPE"',
    '"FLANG_ARROW_NONSENSE"',
  )
  const роды = проверить(куда).map((н) => н.род)
  assert.ok(роды.includes("не названо"), `вышло ${JSON.stringify(проверить(куда))}`)
})

test("ИЗЪЯТИЕ: правило, ПЕРЕЕХАВШЕЕ в бинарник, красит запись о долге", () => {
  const куда = подменить(
    копия("долг-закрыт"),
    "flang/self/types.flang",
    '"FLANG_TYPE_ARGS"',
    '"FLANG_MONOID_ASSOC"',
  )
  const нарушения = проверить(куда)
  assert.ok(
    нарушения.some((н) => н.род === "запись протухла" && н.что === "FLANG_MONOID_ASSOC"),
    `вышло ${JSON.stringify(нарушения)}`,
  )
})

test("ИЗЪЯТИЕ: справка, замолчавшая о поверхности, — красно", () => {
  const куда = копия("справка-молчит")
  const путь = join(куда, СПРАВКА)
  writeFileSync(путь, readFileSync(путь, "utf8").replaceAll("изоморфизм", "нечто"), "utf8")
  const нарушения = проверить(куда)
  assert.ok(
    нарушения.some((н) => н.род === "справка молчит"),
    `вышло ${JSON.stringify(нарушения)}`,
  )
})

test("ИЗЪЯТИЕ: ключ, убранный из списка поверхностей эталона, — красно", () => {
  const куда = подменить(копия("эталон-молчит"), ВХОД_БИНАРНИКА, '"monoids", ', "")
  const нарушения = проверить(куда)
  assert.ok(
    нарушения.some((н) => н.род === "эталон молчит" && н.что.endsWith("/monoids")),
    `вышло ${JSON.stringify(нарушения)}`,
  )
})

/* ── форма самого списка ── */

test("ни один код не назван дважды, и у каждой поверхности есть слово и коды", () => {
  const все = new Set()
  for (const запись of РАЗНИЦА) {
    assert.ok(запись.слово.length > 0, `${запись.поверхность}: нет слова для справки`)
    assert.ok(запись.коды.length > 0, `${запись.поверхность}: нет ни одного кода`)
    for (const код of запись.коды) {
      assert.ok(!все.has(код), `${код} назван дважды`)
      все.add(код)
    }
  }
  assert.equal(
    все.size,
    числа(корень).расходится,
    "сумма кодов РАЗНИЦА разошлась с измеренным расхождением",
  )
})

test("судящие файлы свидетеля существуют и правда судят", () => {
  for (const отн of СУДЬИ_СВИДЕТЕЛЯ) {
    const текст = readFileSync(join(корень, отн), "utf8")
    assert.ok(кодыФайла(отн, текст).size > 0, `${отн}: ни одного кода отказа — файл не судящий`)
  }
})

test("список ТОЛЬКО_У_БИНАРНИКА не свалка: у каждой записи назван довод", () => {
  for (const { код, почему } of ТОЛЬКО_У_БИНАРНИКА) {
    assert.ok(почему.length > 20, `${код}: довод короче фразы «так исторически»`)
  }
})
