/* ────────────────────── размер входа считается по значению ──────────────── */

test("размер входа — структурный: скаляр единица, список единица плюс части", () => {
  assert.equal(размерЗначения(7), 1)
  assert.equal(размерЗначения("строка"), 1)
  assert.equal(размерЗначения([]), 1)
  assert.equal(размерЗначения([1, 2, 3]), 4)
  assert.equal(размерЗначения([[1, 2], [3]]), 6)
  assert.equal(размерЗначения({ variant: "тик", fields: {} }), 1)
  assert.equal(размерЗначения({ variant: "с", fields: { чем: [1, 2] } }), 4)
})
