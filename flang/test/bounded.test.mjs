test("ВЕТВЯЩАЯСЯ рекурсия оценки не получает даже со спуском по данным", () => {
  /*
   * Спуск здесь настоящий — оба вызова идут по хвосту, — и тотальность на этом
   * доказывается. А витков всё равно показательно много: на списке длины 20 их
   * уже за миллион. Ровно это и отличает ограниченность от тотальности, и ровно
   * поэтому проверка стоит на счёте вызовов на пути, а не на спуске.
   */
  const текст = `${шапка}тотальная функция «двоить»
  принимает элементы: список числа
  возвращает число
  разбор элементы
    случай пусто
      то 1
    случай голова и хвост
      то («двоить» от хвост) плюс («двоить» от хвост)
`
  const программа = parse(текст, "оценка.flang")
  const оценка = оценитьВитки(программа).get("двоить")
  assert.equal(оценка.оценка, null)
  assert.equal(оценка.причина, ПРИЧИНЫ.ВЕТВЯЩАЯСЯ)

  /* И это не перестраховка: витки правда растут вдвое с каждым элементом. */
  const мало = витков(программа, "двоить", [Array.from({ length: 8 }, () => 1)])
  const больше = витков(программа, "двоить", [Array.from({ length: 9 }, () => 1)])
  assert.ok(больше > мало * 1.8, `${мало} → ${больше}: рост обязан быть примерно вдвое`)
})

