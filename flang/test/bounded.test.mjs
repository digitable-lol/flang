/**
 * Ограниченность: оценка сверху на витки от размера входа (`src/bounded.mjs`,
 * шаг В3 карты `flang/conc/RESILIENCE.md`).
 *
 * ── Чем эта проверка отличается от проверки тотальности ────────────────────
 *
 * Тотальность проверяется утверждением «отвергнуто» или «принято». Оценку так
 * проверить нельзя: она НЕ бывает верной сама по себе, она бывает верной по
 * отношению к прогону. Поэтому здесь два сторожа, и оба нужны:
 *
 *   1. ОЦЕНКА СВЕРХУ НЕ ЗАНИЖЕНА. Витки считаются двоичным поиском по запасу —
 *      тем же прибором, которым их считает `flang/conc/bench.mjs`: наименьший
 *      запас, на котором функция ещё не падает с FLANG_RECURSION_LIMIT, и есть
 *      точное число витков. Это счёт, а не измерение: он не зависит ни от
 *      машины, ни от нагрузки, и повторяется до единицы. Факт обязан не
 *      превышать оценку на КАЖДОМ из размеров входа, а не на одном удобном.
 *
 *   2. ОЦЕНКА НЕ БЕССМЫСЛЕННО ГРУБА. Оценка «витков не больше 10^9» тоже верна
 *      и тоже бесполезна: с квантом её не свести. Поэтому рядом стоит потолок
 *      на ЗАПАС: оценка не имеет права быть больше факта втрое. Если анализ
 *      когда-нибудь начнут «страховать» множителями, проверка покраснеет.
 *
 * Без первого сторожа файл разрешал бы врать в опасную сторону, без второго —
 * в бесполезную.
 */

import assert from "node:assert/strict"
import test from "node:test"

import {
  ПРИЧИНЫ,
  оценитьВитки,
  размерЗначения,
  степень,
  текстОценки,
  значение,
} from "../src/bounded.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"

/**
 * Точное число витков вызова — двоичным поиском по запасу.
 *
 * Прибор тот же, что у мерки, и по той же причине: часы мерили бы соседа по
 * машине, а запас меряет работу.
 */
function витков(программа, имя, аргументы) {
  const рантайм = createRuntime(программа, { maxSteps: 20_000_000 })
  const проходит = (запас) => {
    try {
      рантайм.call(имя, аргументы, { maxSteps: запас })
      return true
    } catch (ошибка) {
      if (ошибка?.code === "FLANG_RECURSION_LIMIT") return false
      throw ошибка
    }
  }
  let низ = 0
  let верх = 1
  while (!проходит(верх)) {
    низ = верх
    верх *= 2
    assert.ok(верх <= 20_000_000, `«${имя}» не уложилась в двадцать миллионов витков`)
  }
  while (верх - низ > 1) {
    const середина = Math.floor((низ + верх) / 2)
    if (проходит(середина)) верх = середина
    else низ = середина
  }
  return верх
}

const шапка = "модуль «Оценка»\n\n"

const списочные = `${шапка}тотальная функция «сумма»
  принимает элементы: список числа
  возвращает число
  разбор элементы
    случай пусто
      то 0
    случай голова и хвост
      то голова плюс «сумма» от хвост

тотальная функция «длина свёрткой»
  принимает элементы: список числа
  возвращает число
  свёртка элементы начиная с 0 как акк и эл → акк плюс 1

тотальная функция «удвоить»
  принимает элементы: список числа
  возвращает список числа
  отобразить элементы как эл → эл умножить на 2

тотальная функция «сумма удвоенных»
  принимает элементы: список числа
  возвращает число
  «сумма» от («удвоить» от элементы)
`

/* ─────────────── сторож 1: оценка не занижена ни на одном входе ─────────── */

test("оценка не занижена: факт не больше оценки на всех длинах входа", () => {
  const программа = parse(списочные, "оценка.flang")
  const оценки = оценитьВитки(программа)
  for (const имя of ["сумма", "длина свёрткой", "удвоить"]) {
    const оценка = оценки.get(имя)
    assert.notEqual(оценка.оценка, null, `«${имя}» осталась без оценки: ${оценка.причина}`)
    for (const длина of [0, 1, 2, 5, 17, 60, 250]) {
      const список = Array.from({ length: длина }, (_, номер) => номер)
      const н = размерЗначения(список)
      const факт = витков(программа, имя, [список])
      const сверху = значение(оценка.оценка, н)
      assert.ok(
        факт <= сверху,
        `«${имя}» на длине ${длина}: факт ${факт} витков, а оценка обещала не больше ${сверху} ` +
          `(${текстОценки(оценка.оценка)} при н=${н})`,
      )
    }
  }
})

/* ─────────────── сторож 2: оценка не бессмысленно груба ─────────────────── */

test("оценка не грубее факта втрое: иначе её не с чем свести", () => {
  const программа = parse(списочные, "оценка.flang")
  const оценки = оценитьВитки(программа)
  for (const имя of ["сумма", "длина свёрткой", "удвоить"]) {
    const оценка = оценки.get(имя).оценка
    const список = Array.from({ length: 250 }, (_, номер) => номер)
    const н = размерЗначения(список)
    const факт = витков(программа, имя, [список])
    const сверху = значение(оценка, н)
    assert.ok(
      сверху <= факт * 3,
      `«${имя}»: оценка ${сверху} против факта ${факт} — запас больше трёхкратного, ` +
        `такую оценку с квантом не сведёшь`,
    )
  }
})

/* ──────────────── что именно оценивается: числа, а не «линейна» ─────────── */

test("оценка называется числами и коэффициенты не плавают от прогона к прогону", () => {
  const программа = parse(списочные, "оценка.flang")
  const оценки = оценитьВитки(программа)
  assert.equal(текстОценки(оценки.get("сумма").оценка), "11·н + 11")
  assert.equal(текстОценки(оценки.get("длина свёрткой").оценка), "6·н + 6")
  assert.equal(степень(оценки.get("сумма").оценка), 1)
})

/* ─────────── дыра, из-за которой оценка была бы ложной, и её сторож ───────── */

test("цикл по РАЗДУТОМУ списку оценки не получает: длина цикла — не размер входа", () => {
  /*
   * Программа ниже свёрткой строит список из н² элементов и потом идёт по нему.
   * Крутится она н² раз, а не н, и первая редакция этого файла считала иначе:
   * множителем цикла у неё был размер входа, а не длина того, по чему цикл идёт.
   * Оценка выходила `6·н² + 13·н + 14`, а факт на четырёх длинах — 235, 839,
   * 3199, 7095 против обещанных 229, 617, 1969, 4089. Оценка сверху, которая
   * меньше факта, — не оценка, а ошибка в опасную сторону.
   *
   * Чинится это не множителем «на всякий случай», а отказом: длина цикла берётся
   * из размера того, по чему он идёт, а если этот размер не выведен из входа —
   * оценки нет. Проверка стоит здесь, чтобы дыру нельзя было открыть обратно.
   */
  const текст = `${шапка}тотальная функция «раздуть»
  принимает элементы: список числа
  возвращает число
  пусть большой равно (свёртка элементы начиная с пустой список как акк и эл → (свёртка элементы начиная с акк как акк2 и эл2 → добавить эл2 к акк2))
  свёртка большой начиная с 0 как акк3 и эл3 → акк3 плюс эл3
`
  const оценка = оценитьВитки(parse(текст, "оценка.flang")).get("раздуть")
  assert.equal(оценка.оценка, null)
  assert.equal(оценка.причина, ПРИЧИНЫ.РАЗМЕР)
})

test("РАСТУЩИЙ аргумент рекурсии оценки не получает: спуск ограничивает глубину, не цену", () => {
  /*
   * Вторая дыра того же рода, и найдена она тем же сторожем. Спуск здесь
   * настоящий — первый аргумент убывает по хвосту, глубина не больше н, — а
   * ВТОРОЙ аргумент на каждом шаге удваивается, и тело, идущее по нему, стоит
   * н² вместо н. Оценка выходила `6·н² + 20·н + 14`, факт на четырёх длинах —
   * 229, 831, 3161, 12403 против обещанных 448, 680, 960, 1288: со второй точки
   * оценка отстаёт, и дальше отставание растёт вдвое за шаг.
   *
   * Отсюда правило: каждый аргумент рекурсивного вызова обязан быть частью входа
   * либо постоянного размера. Тогда размеры по ходу рекурсии не растут, и `н`
   * остаётся верхней границей для всех — а не только для того, по которому идёт
   * спуск.
   */
  const текст = `${шапка}тотальная функция «раздуть по кругу»
  принимает вход: список числа, акк: список числа
  возвращает число
  разбор вход
    случай пусто
      то (свёртка акк начиная с 0 как а и э → а плюс э)
    случай голова и хвост
      то «раздуть по кругу» от хвост и (свёртка акк начиная с акк как а2 и э2 → добавить э2 к а2)
`
  const оценка = оценитьВитки(parse(текст, "оценка.flang")).get("раздуть по кругу")
  assert.equal(оценка.оценка, null)
  assert.equal(оценка.причина, ПРИЧИНЫ.РАСТУЩИЙ)
})

test("составная функция оценки не получает, и это названная потеря, а не молчание", () => {
  /*
   * `«сумма» от («удвоить» от элементы)` оценивается насквозь: `удвоить` длины
   * списка не меняет, значит `сумма` над её выводом стоит столько же, сколько над
   * входом. Здесь этого не видно, и не видно намеренно: чтобы это увидеть, нужна
   * оценка сверху на РАЗМЕР РЕЗУЛЬТАТА функции, а это отдельный неподвижный счёт
   * по графу вызовов. Без него единственный сохранный ответ — «размер не выведен».
   *
   * Проверка стоит не для того, чтобы закрепить потерю, а чтобы она была видна и
   * названа: в тот день, когда размер результата начнут считать, этот тест
   * покраснеет и его перепишут — а не в тот день, когда кто-то обнаружит, что
   * половина библиотеки без оценки, и не поймёт почему.
   */
  const оценка = оценитьВитки(parse(списочные, "оценка.flang")).get("сумма удвоенных")
  assert.equal(оценка.оценка, null)
  assert.equal(оценка.причина, ПРИЧИНЫ.РАЗМЕР)
})

