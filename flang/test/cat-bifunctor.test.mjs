/**
 * Бифунктор — функтор от двух входов сразу.
 *
 * ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ, а не проверяется на примерах: всё. Причина та же, по
 * которой доказываются законы функтора (`cat-functor.test.mjs`): морфизм в
 * языке ОБЪЯВЛЕНИЕ, домен и кодомен известны до запуска, и «образ пары
 * композиций есть композиция образов пар» решается сличением имён — без сетки,
 * без вычислений, без решателя. Отличие от функтора ровно одно: ключ
 * отображения не имя, а ПАРА имён.
 *
 * ЧЕГО НЕТ И ПОЧЕМУ. В контракте (flang/cat/SPEC.md) бифунктор записан в общем
 * виде — `из «Значения» и «Значения» в «Значения»`, образ `«Пара А Б»`, где «А»
 * и «Б» переменные типа. Так записать нельзя: параметрических типов в языке
 * нет, «Пара А Б» будет именем одной записи, а не семейством. Поэтому пары
 * здесь КОНКРЕТНЫЕ — ровно как конкретны объекты у функтора. Ограничение общее
 * для обеих конструкций и законов не касается ни одним словом.
 *
 * ГРАНИЦА ЗАКОНА КОМПОЗИЦИИ названа отдельным тестом: он проверяется там, где
 * обе стороны пары объявлены композициями. Смешанный случай раскладывается
 * только через образы пар с единицей, а их автор не объявлял — требовать их
 * значило бы заставлять писать то, о чём не просили.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

function проверить(исходник) {
  const итог = checkTypes(parse(исходник, "проба.flang"))
  return {
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

/* Основа: продажи по двум независимым путям и «пары» — записи, в которых оба
   пути идут рядом. У обеих сторон есть объявленная композиция, иначе закон
   сохранения композиции проверять не на чем. Кортежей в языке нет, поэтому
   «пара» — обычная запись с двумя номерами, как «Пара чисел» в stdlib. */
const ОСНОВА = `модуль «Продажи»

запись «Заказ»
  номер: строка
запись «Отгрузка»
  номер: строка
запись «Счёт»
  номер: строка

запись «Пара заказов»
  первый: строка
  второй: строка
запись «Пара отгрузок»
  первый: строка
  второй: строка
запись «Пара счетов»
  первый: строка
  второй: строка

морфизм «отгрузить» из «Заказ» в «Отгрузка»
морфизм «выставить» из «Отгрузка» в «Счёт»
морфизм «оформить» это «выставить» после «отгрузить»

морфизм «отгрузить обе» из «Пара заказов» в «Пара отгрузок»
морфизм «выставить обе» из «Пара отгрузок» в «Пара счетов»
морфизм «оформить обе» это «выставить обе» после «отгрузить обе»
`

const ЗАКОННЫЙ = `${ОСНОВА}
бифунктор «Пара» из «Продажи» и «Продажи» в «Продажи»
  объекты «Заказ» и «Заказ» отображаются в «Пара заказов»
  объекты «Отгрузка» и «Отгрузка» отображаются в «Пара отгрузок»
  объекты «Счёт» и «Счёт» отображаются в «Пара счетов»
  морфизмы «отгрузить» и «отгрузить» отображаются в морфизм «отгрузить обе»
  морфизмы «выставить» и «выставить» отображаются в морфизм «выставить обе»
  морфизмы «оформить» и «оформить» отображаются в морфизм «оформить обе»
`

test("бифунктор, сохраняющий устройство по обоим входам, проходит проверку", () => {
  const итог = проверить(ЗАКОННЫЙ)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("образ пары стрелок обязан вести из образа пары доменов в образ пары кодоменов", () => {
  /* Пара отгрузок отображается не в «Пара отгрузок», а в «Пара счетов» — и
     «отгрузить обе», ведущая в пару отгрузок, образом быть перестаёт. */
  const итог = проверить(ЗАКОННЫЙ.replace(
    "объекты «Отгрузка» и «Отгрузка» отображаются в «Пара отгрузок»",
    "объекты «Отгрузка» и «Отгрузка» отображаются в «Пара счетов»",
  ))
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_ARROW_MISMATCH"), итог.коды.join(", "))
  /* Сообщение обязано назвать обе стороны: чего ждали и что объявлено. */
  const текст = итог.тексты.find((строка) => строка.includes("«отгрузить» и «отгрузить»"))
  assert.match(текст, /кодомен «Отгрузка» и «Отгрузка»/u)
  assert.match(текст, /«Пара счетов»/u)
  assert.match(текст, /«Пара отгрузок»/u)
})

test("пара объектов без образа ловится там, где её не с чем согласовать", () => {
  const итог = проверить(ЗАКОННЫЙ.replace("  объекты «Отгрузка» и «Отгрузка» отображаются в «Пара отгрузок»\n", ""))
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_OBJECT_MISSING"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /не отображает её кодомен — пару объектов «Отгрузка» и «Отгрузка»/u)
})

test("отображение пар однозначно: второй образ одной пары — ошибка", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "  объекты «Счёт» и «Счёт» отображаются в «Пара счетов»",
    "  объекты «Счёт» и «Счёт» отображаются в «Пара счетов»\n  объекты «Счёт» и «Счёт» отображаются в «Пара заказов»",
  ))
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_OBJECT_TWICE"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /пара объектов «Счёт» и «Счёт» отображается дважды/u)
})

test("порядок пары значим: «А» и «Б» — не то же самое, что «Б» и «А»", () => {
  /* Ключом отображения служит УПОРЯДОЧЕННАЯ пара, и это не формальность: у
     бифунктора два входа, и путать их местами — менять смысл. Здесь домен пары
     стрелок — «Заказ» и «Отгрузка», а отображена пара «Отгрузка» и «Заказ»:
     если бы ключ был множеством, подмена прошла бы молча. */
  const итог = проверить(`${ОСНОВА}
запись «Пара заказа и отгрузки»
  первый: строка
  второй: строка
запись «Пара отгрузки и счёта»
  первый: строка
  второй: строка

морфизм «наискось» из «Пара заказа и отгрузки» в «Пара отгрузки и счёта»

бифунктор «Пара» из «Продажи» и «Продажи» в «Продажи»
  объекты «Отгрузка» и «Заказ» отображаются в «Пара заказа и отгрузки»
  объекты «Отгрузка» и «Счёт» отображаются в «Пара отгрузки и счёта»
  морфизмы «отгрузить» и «выставить» отображаются в морфизм «наискось»
`)
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_OBJECT_MISSING"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /не отображает её домен — пару объектов «Заказ» и «Отгрузка»/u)
  /* А кодомен той же стрелки отображён и в счёт ошибок не идёт. */
  assert.equal(итог.коды.filter((код) => код === "FLANG_BIFUNCTOR_OBJECT_MISSING").length, 1, итог.тексты.join("\n"))
})

test("образ пары композиций обязан быть композицией образов в том же порядке", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "морфизм «оформить обе» это «выставить обе» после «отгрузить обе»",
    "морфизм «оформить обе» это «отгрузить обе» после «выставить обе»",
  ))
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_COMPOSITION"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /обязан быть «выставить обе» после «отгрузить обе»/u)
})

test("образ пары композиций, объявленный простой стрелкой, композицией не считается", () => {
  /* Концы при этом сходятся, и первый закон молчит. Второй обязан заговорить:
     бифунктор сохраняет не концы, а устройство. */
  const итог = проверить(ЗАКОННЫЙ.replace(
    "морфизм «оформить обе» это «выставить обе» после «отгрузить обе»",
    "морфизм «оформить обе» из «Пара заказов» в «Пара счетов»",
  ))
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_COMPOSITION"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /сам композицией не объявлен/u)
})

test("пара, из которой собрана композиция, обязана быть отображена — иначе закон проверять не на чем", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "  морфизмы «выставить» и «выставить» отображаются в морфизм «выставить обе»\n",
    "",
  ))
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_COMPOSITION"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /не отображает пару «выставить» и «выставить», из которой она собрана/u)
})

test("образ пары единиц обязан быть единицей образа пары", () => {
  const исходник = `модуль «Единицы»

запись «Заказ»
  номер: строка
запись «Пара заказов»
  первый: строка
  второй: строка
запись «Пара счетов»
  первый: строка
  второй: строка

единица «Заказ»
единица «Пара заказов»
единица «Пара счетов»

бифунктор «Пара наизнанку» из «Дела» и «Дела» в «Дела»
  объекты «Заказ» и «Заказ» отображаются в «Пара заказов»
  морфизмы «единица Заказ» и «единица Заказ» отображаются в морфизм «единица Пара счетов»
`
  const итог = проверить(исходник)
  assert.ok(итог.коды.includes("FLANG_BIFUNCTOR_IDENTITY"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /обязан быть «единица Пара заказов», а объявлен «единица Пара счетов»/u)
})

test("пара единиц, которую бифунктор не отображает, законом не считается нарушенной", () => {
  /* Бифунктор вправе быть объявлен не на всём: отсутствие образа противоречия
     не создаёт, а ругаться значило бы заставлять выписывать очевидное. */
  const итог = проверить(`${ОСНОВА}
единица «Заказ»

бифунктор «Пара» из «Продажи» и «Продажи» в «Продажи»
  объекты «Заказ» и «Заказ» отображаются в «Пара заказов»
  объекты «Отгрузка» и «Отгрузка» отображаются в «Пара отгрузок»
  морфизмы «отгрузить» и «отгрузить» отображаются в морфизм «отгрузить обе»
`)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("смешанный случай закон композиции не трогает — и это сказано вслух", () => {
  /* Композиция по левому входу и простая стрелка по правому. Разложить такую
     пару можно только через образы пар с единицей, которых автор не объявлял,
     — поэтому проверка молчит НАМЕРЕННО. Тест держит границу: если однажды
     закон расширят, он упадёт и заставит переписать обещание в SPEC. */
  const итог = проверить(`${ОСНОВА}
запись «Пара заказа и отгрузки»
  первый: строка
  второй: строка
запись «Пара счёта и счёта»
  первый: строка
  второй: строка

морфизм «смешанная» из «Пара заказа и отгрузки» в «Пара счёта и счёта»

бифунктор «Пара» из «Продажи» и «Продажи» в «Продажи»
  объекты «Заказ» и «Отгрузка» отображаются в «Пара заказа и отгрузки»
  объекты «Счёт» и «Счёт» отображаются в «Пара счёта и счёта»
  морфизмы «оформить» и «выставить» отображаются в морфизм «смешанная»
`)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("несуществующий морфизм в паре назван по имени", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "морфизмы «выставить» и «выставить» отображаются в морфизм «выставить обе»",
    "морфизмы «выставить» и «которого нет» отображаются в морфизм «выставить обе»",
  ))
  assert.ok(итог.коды.includes("FLANG_UNKNOWN_NAME"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /но морфизма «которого нет» нет/u)
})

test("имена категорий у бифунктора остаются пометкой, как и у функтора", () => {
  /* Та же граница честности, что закреплена для функтора: категория отдельной
     сущностью в языке не объявляется, и утверждать принадлежность объекта ей
     не на чем. Тест упадёт, если это когда-нибудь изменится. */
  const итог = проверить(ЗАКОННЫЙ.replace('из «Продажи» и «Продажи» в «Продажи»', 'из «Ниоткуда» и «Нипочём» в «Никуда»'))
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("английская поверхность даёт тот же разбор", () => {
  const программа = parse(`${ОСНОВА}
bifunctor «Пара» from «Продажи» and «Продажи» to «Продажи»
  objects «Заказ» and «Заказ» map to «Пара заказов»
  morphisms «отгрузить» and «отгрузить» map to morphism «отгрузить обе»
`, "проба.flang")
  const узел = программа.bifunctors[0]
  assert.deepEqual(узел.from, ["Продажи", "Продажи"])
  assert.deepEqual(узел.objects, [{ from: ["Заказ", "Заказ"], to: "Пара заказов" }])
  assert.deepEqual(узел.morphisms, [{ from: ["отгрузить", "отгрузить"], to: "отгрузить обе" }])
})
