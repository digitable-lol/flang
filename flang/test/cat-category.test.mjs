/**
 * Категория, назвавшая свои стрелки: две аксиомы, которые ДОКАЗЫВАЮТСЯ.
 *
 * ── Что было до ─────────────────────────────────────────────────────────────
 * `категория «Х»` в языке была именем и ничем больше: разбор запоминал его в
 * узле наследия FTS, а всё, что стояло под ним, укладывал плоско. Отсюда две
 * дыры, и вторая дорогая.
 *
 * Первая: имена категорий у функтора (`из «Продажи» в «Биллинг»`) оставались
 * пометкой для читателя — так и записано в шапке `cat-functor.test.mjs`.
 *
 * Вторая: `flang/cat/SPEC.md` обещал «полноту отображений функтора — каждому
 * объекту и морфизму ДОМЕНА сопоставлено что-то в кодомене», а проверить это
 * было нечем. Функтор, отобразивший две стрелки из пяти, проходил проверку
 * молча, потому что «пять» было неизвестным числом. Обещание в документации
 * стояло, содержания за ним не было.
 *
 * ── Граница честности ───────────────────────────────────────────────────────
 * Всё, что проверяется здесь, — ДОКАЗАТЕЛЬСТВА, а не сетка. Возможны они ровно
 * потому же, почему возможны законы функтора: морфизм в языке ОБЪЯВЛЕНИЕ, а не
 * значение, и его концы известны до запуска. Ни одна проверка этого файла не
 * вычисляет ничего.
 *
 * Чего здесь нет и не будет без отдельной работы — АССОЦИАТИВНОСТЬ композиции.
 * `«в» после («б» после «а»)` и `(«в» после «б») после «а»` — два разных имени,
 * а равенства морфизмов в языке нет вовсе. Сравнение имён вместо аксиомы было
 * бы ровно той подменой, от которой язык отгораживается.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

function проверить(исходник) {
  const программа = parse(исходник, "проба.flang")
  const итог = checkTypes(программа)
  return {
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

/* Две стрелки и их композиция — меньше нельзя: без композиции замкнутость
   проверять не на чем, а она здесь главная. */
const ОСНОВА = `модуль «Продажи»

объект «Заказ»
  номер: строка

объект «Отгрузка»
  номер: строка

объект «Счёт»
  номер: строка

морфизм «отгрузить» из «Заказ» в «Отгрузка»
морфизм «выставить» из «Отгрузка» в «Счёт»
морфизм «оформить» это «выставить» после «отгрузить»
единица «Заказ»
единица «Отгрузка»
единица «Счёт»
`

const ПОЛНАЯ = `${ОСНОВА}
категория «Продажи»
  морфизм «отгрузить»
  морфизм «выставить»
  морфизм «оформить»
`

/* ─────────────────────────────── форма ───────────────────────────────────── */

test("категория со списком стрелок попадает в AST своим узлом", () => {
  const программа = parse(ПОЛНАЯ, "проба.flang")
  assert.deepEqual(программа.categories, [
    {
      kind: "category",
      name: "Продажи",
      morphisms: ["отгрузить", "выставить", "оформить"],
      span: программа.categories[0].span,
    },
  ])
})

test("ЗАГОЛОВОК ДОКУМЕНТА FTS НЕ ЗАДЕТ: категории без списка в AST не появляется", () => {
  /* Это не мелочь и не вкусовщина. `категория «Х»` с объектами и утилитами под
     ней — заголовок сорока моделей `.fts` репозитория, и их AST сверяет
     побайтово неподвижная точка самоприменения. Появись у них новый ключ —
     разошлись бы все сорок сразу. */
  const программа = parse(
    `категория «Продажи»\n\n  объект Покупка\n    сумма является числом\n`,
    "проба.fts",
  )
  assert.equal(программа.categories, undefined)
  assert.equal(программа.legacy.some((узел) => узел.construct === "category"), true)
})

test("членство и объявление различаются тем, что стоит ЗА именем", () => {
  /* Морфизм-утверждение FTS: за именем перевод строки, а следом отступ. Первый
     заход принял его за членство, съел заголовок и споткнулся о собственный
     блок. Здесь это закреплено: блок под именем — объявление, и только. */
  const программа = parse(
    `категория «Продажи»\n  морфизм «скидка полагается»\n    если Покупка\n    то Покупка\n`,
    "проба.fts",
  )
  assert.equal(программа.categories, undefined)
  assert.equal(программа.legacy.some((узел) => узел.construct === "morphism"), true)
})

test("законная категория проверку проходит", () => {
  assert.deepEqual(проверить(ПОЛНАЯ).коды, [])
})

/* ───────────────────────────── членство ──────────────────────────────────── */

test("категория из несуществующих стрелок — это список слов", () => {
  const итог = проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «улететь»\n`)
  assert.deepEqual(итог.коды, ["FLANG_CATEGORY_UNKNOWN_ARROW"])
  assert.match(итог.тексты.join("\n"), /морфизм «улететь», но такого морфизма нет/u)
})

test("одна стрелка, названная дважды, сделала бы полноту функтора неправдой", () => {
  const итог = проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «отгрузить»\n  морфизм «отгрузить»\n`)
  assert.deepEqual(итог.коды, ["FLANG_CATEGORY_ARROW_TWICE"])
})

test("два списка под одним именем — два разных обещания", () => {
  const итог = проверить(
    `${ОСНОВА}\nкатегория «Продажи»\n  морфизм «отгрузить»\n\nкатегория «Продажи»\n  морфизм «выставить»\n`,
  )
  assert.deepEqual(итог.коды, ["FLANG_DUPLICATE_NAME"])
})

/* ───────────────────── аксиома первая: замкнутость ───────────────────────── */

test("АКСИОМА: категория замкнута под композицией", () => {
  const итог = проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «отгрузить»\n  морфизм «оформить»\n`)
  assert.deepEqual(итог.коды, ["FLANG_CATEGORY_NOT_CLOSED"])
  assert.match(итог.тексты.join("\n"), /композиция «оформить» собрана из «выставить»/u)
})

test("сообщение о незамкнутости называет ОБА недостающих сомножителя", () => {
  const итог = проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «оформить»\n`)
  assert.deepEqual(итог.коды, ["FLANG_CATEGORY_NOT_CLOSED", "FLANG_CATEGORY_NOT_CLOSED"])
  assert.match(итог.тексты.join("\n"), /«выставить»/u)
  assert.match(итог.тексты.join("\n"), /«отгрузить»/u)
})

/* ────────────────────── аксиома вторая: единицы ──────────────────────────── */

test("АКСИОМА: у каждого объекта категории есть единица", () => {
  const безЕдиницы = ОСНОВА.replace("единица «Отгрузка»\n", "")
  const итог = проверить(`${безЕдиницы}\nкатегория «Продажи»\n  морфизм «отгрузить»\n`)
  assert.deepEqual(итог.коды, ["FLANG_CATEGORY_NO_IDENTITY"])
  assert.match(итог.тексты.join("\n"), /у объекта «Отгрузка» нет единицы/u)
})

test("единицы в списке не пишутся: они входят по своим объектам", () => {
  /* Иначе автор писал бы их дважды — объявлением и членством, — и второе место
     могло бы разойтись с первым молча. */
  assert.deepEqual(проверить(ПОЛНАЯ).коды, [])
  const явно = проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «отгрузить»\n  морфизм «единица Заказ»\n`)
  assert.deepEqual(явно.коды, [])
})

/* ──────────────────── что это дало функтору ──────────────────────────────── */

const ТОЖДЕСТВЕННЫЙ = `${ПОЛНАЯ}
функтор «Тождественный» из «Продажи» в «Продажи»
  объект «Заказ» отображается в «Заказ»
  объект «Отгрузка» отображается в «Отгрузка»
  объект «Счёт» отображается в «Счёт»
  морфизм «отгрузить» отображается в морфизм «отгрузить»
  морфизм «выставить» отображается в морфизм «выставить»
  морфизм «оформить» отображается в морфизм «оформить»
`

test("функтор над объявленной категорией отображает её целиком", () => {
  assert.deepEqual(проверить(ТОЖДЕСТВЕННЫЙ).коды, [])
})

test("ГЛАВНОЕ: функтор, отобразивший часть категории, больше не проходит молча", () => {
  const частичный = ТОЖДЕСТВЕННЫЙ.replace(
    "  морфизм «выставить» отображается в морфизм «выставить»\n",
    "",
  ).replace("  морфизм «оформить» отображается в морфизм «оформить»\n", "")
  const итог = проверить(частичный)
  assert.deepEqual(итог.коды, ["FLANG_FUNCTOR_NOT_TOTAL", "FLANG_FUNCTOR_NOT_TOTAL"])
  assert.match(итог.тексты.join("\n"), /не отображает морфизм «выставить» категории «Продажи»/u)
  assert.match(итог.тексты.join("\n"), /определён на всей категории домена/u)
})

test("образ обязан лежать в категории кодомена", () => {
  const исходник = `${ОСНОВА}
морфизм «печатать» из «Заказ» в «Счёт»
морфизм «мимо» из «Отгрузка» в «Счёт»

категория «Продажи»
  морфизм «отгрузить»

категория «Биллинг»
  морфизм «мимо»

функтор «Мимо» из «Продажи» в «Биллинг»
  объект «Заказ» отображается в «Отгрузка»
  объект «Отгрузка» отображается в «Счёт»
  морфизм «отгрузить» отображается в морфизм «мимо»
`
  assert.deepEqual(проверить(исходник).коды, [])

  const наружу = исходник.replace("морфизм «отгрузить» отображается в морфизм «мимо»", "морфизм «отгрузить» отображается в морфизм «печатать»")
  const итог = проверить(наружу)
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_IMAGE_OUTSIDE"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /не входит в категорию «Биллинг»/u)
})

test("НЕОБЪЯВЛЕННАЯ категория остаётся допущением автора, а не ошибкой", () => {
  /* Та же граница, по которой изоморфизм без «даёт» уходит в `assumed`, а не в
     диагностику: объявлять то, чего ещё нет, законно и полезно. Полнота
     проверяется там и только там, где сказано, из чего категория состоит. */
  const итог = проверить(ТОЖДЕСТВЕННЫЙ.replace('из «Продажи» в «Продажи»', 'из «Ниоткуда» в «Никуда»'))
  assert.deepEqual(итог.коды, [])
})

/* ───────────────────────── целая программа ───────────────────────────────── */

const ПРИМЕР = "flang/examples/cat/order-shipment.flang"

test(`целая программа ${ПРИМЕР} принимается вместе с категорией`, () => {
  const исходник = readFileSync(new URL("../examples/cat/order-shipment.flang", import.meta.url), "utf8")
  const программа = parse(исходник, ПРИМЕР)
  assert.deepEqual(программа.categories?.map((узел) => узел.name), ["Отгрузки"])
  assert.deepEqual(checkTypes(программа).diagnostics, [])

  /* Изъятие внутри примера: снять единицу «Заказ» — файл обязан покраснеть.
     Комментарий в самом файле обещает ровно это, и обещание проверяется, а не
     стоит словами. */
  const безЕдиницы = checkTypes(parse(исходник.replace("единица «Заказ»\n", ""), ПРИМЕР))
  assert.deepEqual(безЕдиницы.diagnostics.map((беда) => беда.code), ["FLANG_CATEGORY_NO_IDENTITY"])

  /* И второе: снять «выписать» из списка — композиция «оформить» остаётся без
     сомножителя, категория перестаёт быть замкнутой. */
  const безСтрелки = checkTypes(parse(исходник.replace("  морфизм «выписать»\n", ""), ПРИМЕР))
  assert.deepEqual(безСтрелки.diagnostics.map((беда) => беда.code), ["FLANG_CATEGORY_NOT_CLOSED"])
})

test("коды диагностик свои: по коду машина понимает, что чинить", () => {
  const коды = new Set([
    ...проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «улететь»\n`).коды,
    ...проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «отгрузить»\n  морфизм «отгрузить»\n`).коды,
    ...проверить(`${ОСНОВА}\nкатегория «Продажи»\n  морфизм «оформить»\n`).коды,
    ...проверить(`${ОСНОВА.replace("единица «Отгрузка»\n", "")}\nкатегория «Продажи»\n  морфизм «отгрузить»\n`).коды,
  ])
  assert.deepEqual([...коды].sort(), [
    "FLANG_CATEGORY_ARROW_TWICE",
    "FLANG_CATEGORY_NOT_CLOSED",
    "FLANG_CATEGORY_NO_IDENTITY",
    "FLANG_CATEGORY_UNKNOWN_ARROW",
  ])
  assert.equal([...коды].includes("FLANG_TYPE"), false)
})
