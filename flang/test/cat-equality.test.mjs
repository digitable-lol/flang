/* ─────────────────── настоящая программа репозитория ─────────────────────── */

/* Тестом на строках проверяется, что конструкция РАБОТАЕТ; настоящим файлом —
   что ею можно ПОЛЬЗОВАТЬСЯ. Это разные утверждения, и второе за одну сессию
   уже находило то, чего не находило первое (`flang/cat/POLY.md`). */
const ПРИМЕР = "flang/examples/cat/order-shipment.flang"
const исходникПримера = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

test("пример репозитория: категория объявила своё равенство, и три её закона посчитаны", () => {
  const программа = разобрать(исходникПримера)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = checkCategoryLaws(программа)
  assert.deepEqual(итог.diagnostics, [], итог.diagnostics.map((беда) => беда.message).join("\n"))
  assert.equal(итог.checked.length, 1)
  assert.equal(итог.checked[0].category, "Отгрузки")
  assert.ok(итог.checked[0].values > 0, "категория с пустой сеткой проверенной не считается")
  assert.ok(итог.checked[0].triples > 0, "ассоциативность на настоящем файле не считана ни разу")
  assert.deepEqual(итог.assumed, [])
})

test("пример репозитория: изъятие внутри файла — подделка равенства роняет его поимённо", () => {
  /* Комментарий в самом файле обещает ровно это, и обещание проверяется, а не
     стоит словами: «не больше» рефлексивно и транзитивно, а равенством не
     является — и категория отказывает. */
  const подделка = исходникПримера.replace(
    "  первый.сумма равен второй.сумма",
    "  первый.сумма не больше второй.сумма",
  )
  assert.notEqual(подделка, исходникПримера, "место подделки в файле не найдено")
  const итог = checkCategoryLaws(разобрать(подделка))
  assert.deepEqual(итог.diagnostics.map((беда) => беда.code), ["FLANG_EQUALITY_NOT_SYMMETRIC"])
})

test("пример репозитория: снять равенство — три закона уходят из «сетки» в «на веру»", () => {
  /* Вторая половина того же изъятия, и она важнее первой: без объявленного
     равенства проверка не краснеет, а МОЛЧИТ — и молчание обязано быть видно
     отдельной строкой, иначе оно читается как «проверено». */
  const без = исходникПримера.replace(/\n {2}объект «[^»]+» даёт «[^»]+»/gu, "")
  assert.notEqual(без, исходникПримера, "строк равенства в файле не найдено")
  const итог = checkCategoryLaws(разобрать(без))
  assert.deepEqual(итог.diagnostics, [])
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.match(итог.assumed[0].why, /своего равенства не объявлено/u)
})
