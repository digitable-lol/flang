test("АССОЦИАТИВНОСТЬ УМЕЕТ КРАСНЕТЬ — и вот единственное место, где она это делает", () => {
  /* Здесь названа честная граница силы проверки. Композиция вычисляется
     применением, значит обе скобки дают одно значение; краснеет сравнение
     ровно тогда, когда объявленное равенство не рефлексивно В ТОЧКЕ, КУДА
     КОМПОЗИЦИЯ ПРИШЛА. Точка эта в сетку кодомена не входит: сетка «Г»
     собирается из примеров «в» и держит только единицу, а композиция от 7
     доходит до семёрки, которой там никто не считал.

     Категория взята без композиций — только три атомарные стрелки, — чтобы
     краснела ИМЕННО ассоциативность: будь в ней «в после ба», семёрку поймала
     бы конгруэнтность, и тест перестал бы говорить о том, о чём назван. */
  const усечённое = `
тотальная функция «Г равны до пяти»
  принимает первое: «Г», второе: «Г»
  возвращает признак
  (первое.н равен второе.н) и притом (первое.н не больше 5)
`
  const семёрка = `
тотальная функция «А равны 7»
  принимает первое: «А», второе: «А»
  возвращает признак
  пример «семь и семь»
    дано первое равно запись «А» с н равным 7
    дано второе равно запись «А» с н равным 7
    ожидается да
  первое.н равен второе.н
`
  const исходник = `${ОБЪЕКТЫ}${СТРОГОЕ}${усечённое}${семёрка}${СТРЕЛКИ}
категория «Проба»
  морфизм «а»
  морфизм «б»
  морфизм «в»
  объект «А» даёт «А равны 7»
  объект «Б» даёт «Б равны»
  объект «В» даёт «В равны»
  объект «Г» даёт «Г равны до пяти»
`
  const итог = законы(исходник)
  assert.deepEqual(итог.коды, ["FLANG_CATEGORY_NOT_ASSOC"])
  assert.match(итог.тексты.join("\n"), /композиция не ассоциативна/u)
  assert.match(итог.тексты.join("\n"), /«в» после \(«б» после «а»\)/u)
})

