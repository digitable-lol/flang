/**
 * Равенство морфизмов: категория, обогащённая сетоидами.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 * Программа с четырьмя объектами, тремя стрелками и ДВУМЯ ИМЕНАМИ одного пути —
 * `«в» после («б» после «а»)` и `(«в» после «б») после «а»` — проходила
 * `flang check --proof` со строкой «законов на сетке: 0» и разделом «нет
 * объявленных законов». Про равенство этих двух стрелок отчёт не говорил
 * ничего, и сказать ему было нечем: равенства морфизмов в языке не было вовсе.
 * `cat/SPEC.md` называл это прямо: «проверка, сравнивающая имена, продавала бы
 * сличение строк за аксиому».
 *
 * ── Что здесь ДОКАЗЫВАЕТСЯ, а что ПРОВЕРЯЕТСЯ ───────────────────────────────
 * Устройство равенства — доказывается сличением объявлений, без единого
 * вычисления: объект принадлежит категории, равенство у него одно, названная
 * функция берёт два входа этого объекта и возвращает признак (`types.mjs`).
 *
 * Сами свойства — проверяются на конечной сетке значений автора и называются
 * ровно так (`setoid.mjs`): равенство есть эквивалентность; композиция его
 * уважает; композиция ассоциативна. Ведомость печатает их одной строкой,
 * оканчивающейся словами «Это не доказательство», и это не оговорка ради
 * скромности: равенство вычислений на всех значениях неразрешимо.
 *
 * ── Про силу проверки ассоциативности сказано отдельно и без прикрас ────────
 * Композиция в flang не пишется автором — `после` разворачивается в применение,
 * а применение ассоциативно по построению вычислителя. Значит на реализованных
 * стрелках обе скобки дают одно значение, и покраснеть проверка может ровно
 * там, где объявленное равенство не рефлексивно в точке, до которой композиция
 * дошла. Такая точка в сетку кодомена не входит, и никто её там не считал —
 * поэтому проверка не пуста; но и аксиомой она не становится. Тест
 * «ассоциативность краснеет» построен именно на этом случае и говорит о нём.
 */
import assert from "node:assert/strict"
