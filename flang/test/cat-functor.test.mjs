/**
 * Законы функтора — то, что компилятор ДОКАЗЫВАЕТ, а не проверяет на примерах.
 *
 * Объявление функтора в языке было и раньше: `функтор «Ф» из «A» в «B»` с
 * блоком отображений разбирался и укладывался в дерево. Гарантии за ним не
 * стояло никакой — слово было, содержания не было. Эти тесты и есть содержание.
 *
 * Ключевое здесь — почему доказательство вообще возможно. Морфизм в языке
 * ОБЪЯВЛЕНИЕ, а не значение: у него есть имя, домен и кодомен, известные до
 * запуска. Поэтому «образ композиции обязан быть композицией образов» —
 * утверждение обо всех входах, проверяемое сравнением имён, без сетки и без
 * решателя. С функциями первого класса такой проверки не бывает: там композиция
 * — вычисление, и равенство двух вычислений неразрешимо.
 *
 * Отсюда же проходила граница: имена категорий («из «Продажи» в «Биллинг»»)
 * оставались пометкой для читателя, потому что категория отдельной сущностью не
 * объявлялась. 2026-08-14 граница сдвинулась, но не исчезла: категория, которая
 * НАЗВАЛА свои стрелки, стала проверяемой (`cat-category.test.mjs`), а та, что
 * не объявлена, осталась ровно пометкой — и здесь это по-прежнему закреплено
 * тестом, чтобы никто не принял одно за другое.
 *
 * Полнота отображения живёт там же, где категория, и по той же причине: пока
 * неизвестно, из скольких стрелок состоит домен, «функтор отобразил всё»
 * проверить не на чем. Тесты этого файла — про согласованность образов; тесты
 * соседнего — про то, что образов ровно столько, сколько стрелок.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

/** Коды диагностик проверки типов — по ним и сверяемся. */
function проверить(исходник) {
  const программа = parse(исходник, "проба.flang")
  const итог = checkTypes(программа)
  return {
    ok: itogOk(итог),
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

function itogOk(итог) {
  return (итог.diagnostics ?? []).length === 0
}

/* Основа для проб: две цепочки одной длины между одними и теми же концами.
   Электронный путь идёт через отгрузку, бумажный — через накладную, и функтор
   переводит один в другой. Пример намеренно не игрушечный: у обеих цепочек есть
   объявленная композиция, иначе закон сохранения композиции нечем проверять. */
const ОСНОВА = `модуль «Продажи»

запись «Заказ»
  номер: строка

запись «Отгрузка»
  номер: строка

запись «Счёт»
  номер: строка

запись «Накладная»
  номер: строка

морфизм «отгрузить» из «Заказ» в «Отгрузка»
морфизм «выставить» из «Отгрузка» в «Счёт»
морфизм «оформить» это «выставить» после «отгрузить»

морфизм «печатать» из «Заказ» в «Накладная»
морфизм «подписать» из «Накладная» в «Счёт»
морфизм «оформить бумажно» это «подписать» после «печатать»
`

const ЗАКОННЫЙ = `${ОСНОВА}
функтор «Электронное в бумажное» из «Продажи» в «Продажи»
  объект «Заказ» отображается в «Заказ»
  объект «Отгрузка» отображается в «Накладная»
  объект «Счёт» отображается в «Счёт»
  морфизм «отгрузить» отображается в морфизм «печатать»
  морфизм «выставить» отображается в морфизм «подписать»
  морфизм «оформить» отображается в морфизм «оформить бумажно»
`

test("функтор, сохраняющий устройство, проходит проверку", () => {
  const итог = проверить(ЗАКОННЫЙ)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("образ стрелки обязан вести из образа домена в образ кодомена", () => {
  /* Отгрузка отображается не в накладную, а в счёт — и теперь «печатать»,
     ведущая в накладную, образом «отгрузить» быть не может. */
  const итог = проверить(ЗАКОННЫЙ.replace("объект «Отгрузка» отображается в «Накладная»", "объект «Отгрузка» отображается в «Счёт»"))
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_ARROW_MISMATCH"), итог.коды.join(", "))
  /* Диагностика обязана назвать ОБА конца, а не сказать «не сходится»: без имён
     искать придётся глазами по всему блоку отображений. */
  const текст = итог.тексты.find((строка) => строка.includes("отгрузить"))
  assert.match(текст, /кодомен «Отгрузка»/u)
  assert.match(текст, /«Счёт»/u)
  assert.match(текст, /«Накладная»/u)
})

test("объект без образа ловится там, где его не с чем согласовать", () => {
  const итог = проверить(ЗАКОННЫЙ.replace("  объект «Отгрузка» отображается в «Накладная»\n", ""))
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_OBJECT_MISSING"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /не отображает его кодомен «Отгрузка»/u)
})

test("отображение объектов однозначно: второй образ — ошибка, а не победа последнего", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "  объект «Счёт» отображается в «Счёт»",
    "  объект «Счёт» отображается в «Счёт»\n  объект «Счёт» отображается в «Накладная»",
  ))
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_OBJECT_TWICE"), итог.коды.join(", "))
})

test("образ композиции обязан быть композицией образов в том же порядке", () => {
  /* Бумажная цепочка собрана в обратном порядке. Композиция при этом сама по
     себе не стыкуется, и первой сработает FLANG_COMPOSE_MISMATCH, — но закон
     функтора обязан сказать своё отдельно: без него ошибка выглядела бы бедой
     одной цепочки, а не разладом отображения. */
  const итог = проверить(ЗАКОННЫЙ.replace(
    "морфизм «оформить бумажно» это «подписать» после «печатать»",
    "морфизм «оформить бумажно» это «печатать» после «подписать»",
  ))
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_COMPOSITION"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /обязан быть «подписать» после «печатать»/u)
})

test("образ композиции, объявленный простой стрелкой, композицией не считается", () => {
  /* «оформить бумажно» перестаёт быть композицией и становится обычной
     стрелкой с теми же концами. Концы сходятся, и первый закон молчит — а
     второй обязан заговорить: функтор сохраняет не концы, а устройство. */
  const итог = проверить(ЗАКОННЫЙ.replace(
    "морфизм «оформить бумажно» это «подписать» после «печатать»",
    "морфизм «оформить бумажно» из «Заказ» в «Счёт»",
  ))
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_COMPOSITION"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /сам композицией не объявлен/u)
})

test("образ единицы обязан быть единицей образа", () => {
  const исходник = `модуль «Единицы»

запись «Заказ»
  номер: строка

запись «Счёт»
  номер: строка

морфизм «выставить» из «Заказ» в «Счёт»
единица «Заказ»
единица «Счёт»

функтор «Тождество наизнанку» из «Дела» в «Дела»
  объект «Заказ» отображается в «Счёт»
  объект «Счёт» отображается в «Счёт»
  морфизм «единица Заказ» отображается в морфизм «единица Счёт»
  морфизм «единица Счёт» отображается в морфизм «единица Заказ»
`
  const итог = проверить(исходник)
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_IDENTITY"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /образ «единица Счёт» обязан быть «единица Счёт»/u)
})

test("единица, которую функтор не отображает, законом не считается нарушенной", () => {
  /* Функтор вправе быть объявлен не на всём: образ единицы определён
     однозначно, и его отсутствие противоречия не создаёт. Ругаться здесь
     значило бы заставлять выписывать очевидное. */
  const исходник = `модуль «Единицы»

запись «Заказ»
  номер: строка

запись «Счёт»
  номер: строка

морфизм «выставить» из «Заказ» в «Счёт»
единица «Заказ»

функтор «Частичный» из «Дела» в «Дела»
  объект «Заказ» отображается в «Заказ»
  объект «Счёт» отображается в «Счёт»
  морфизм «выставить» отображается в морфизм «выставить»
`
  assert.deepEqual(проверить(исходник).коды, [])
})

test("несуществующий морфизм в отображении назван по имени", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "морфизм «выставить» отображается в морфизм «подписать»",
    "морфизм «выставить» отображается в морфизм «которого нет»",
  ))
  assert.ok(итог.коды.includes("FLANG_UNKNOWN_NAME"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /морфизма «которого нет» нет/u)
})

test("имена НЕОБЪЯВЛЕННЫХ категорий остаются пометкой: выдуманная проверку не роняет", () => {
  /* Закрепляем границу честности. Категория, назвавшая свои стрелки, теперь
     проверяется (`cat-category.test.mjs`); та, о которой не сказано ничего,
     остаётся допущением автора — ровно как изоморфизм без `даёт`. Если
     когда-нибудь и она начнёт быть ошибкой, этот тест упадёт и заставит
     переписать обещание в документации, а не тихо разойтись с ней. */
  const итог = проверить(ЗАКОННЫЙ.replace('из «Продажи» в «Продажи»', 'из «Ниоткуда» в «Никуда»'))
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})
