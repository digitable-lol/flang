/**
 * Изоморфизм — пара стрелок туда и обратно.
 *
 * ГРАНИЦА ЧЕСТНОСТИ ЗДЕСЬ ПРОХОДИТ ВНУТРИ ОДНОЙ КОНСТРУКЦИИ, и назвать её надо
 * до первого теста, иначе зелёный прогон прочитается как «обратимость
 * доказана», а это неправда.
 *
 * ДОКАЗЫВАЕТСЯ — сличением объявлений, без сетки и без вычислений, потому что
 * морфизм в языке ОБЪЯВЛЕНИЕ, и концы его известны до запуска:
 *
 *   — объекты изоморфизма объявлены (объект категории — это тип);
 *   — обе стрелки объявлены;
 *   — концы сходятся крест-накрест: прямая из «А» в «Б», обратная из «Б» в «А».
 *     Именно это делает обе композиции замкнутыми на себя — без него закон
 *     обратимости нельзя даже сформулировать;
 *   — единицы обоих объектов объявлены: закон говорит «композиция даёт
 *     единицу», и если единицы нет, он говорит о том, чего в программе нет.
 *
 * ПРОВЕРЯЕТСЯ НА СЕТКЕ — само равенство «обратный после прямого = единица», и
 * ровно там, где обе стрелки РЕАЛИЗОВАНЫ (`даёт «Ф»`). Раньше не проверялось
 * вовсе, и причина была не в недосмотре: у стрелки не было тела, вычислять на
 * сетке было нечего. Условие названо в контракте прямо — «сетка появится здесь
 * тогда же, когда у морфизма появится `даёт`»; `даёт` появился, и она здесь
 * (`iso.mjs`). «Проверено на N значениях» при этом не «доказано», и тесты ниже
 * называют эти два утверждения по-разному.
 *
 * ОСТАЁТСЯ ДОПУЩЕНИЕМ — пара, где хотя бы одна стрелка без `даёт`. Проверять
 * нечем, и проверка молчит: объявление стрелки без реализации законно и полезно
 * (так написаны все морфизмы наследия FTS), а требовать реализацию ради проверки
 * значило бы запретить объявлять то, чего ещё нет. Тест «допущение так и
 * остаётся допущением» ниже закрепляет это прямо, чтобы граница не размылась.
 *
 * Разница с моноидом теперь только в источнике сетки: там значения берутся из
 * примеров операции, здесь — из примеров обеих стрелок и их законов.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { checkIsoLaws } from "../src/iso.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

function проверить(исходник) {
  const итог = checkTypes(parse(исходник, "проба.flang"))
  return {
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

/** Сетка обратимости — отдельной дорогой, как у моноида: она ВЫЧИСЛЯЕТ. */
function обратимость(исходник) {
  const итог = checkIsoLaws(parse(исходник, "проба.flang"))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    проверено: итог.checked,
  }
}

/* Основа: заказ и накладная — две записи об одном и том же, и переход между
   ними обратим. Пример не игрушечный намеренно: обратимая пара в предметной
   области — это ровно «две формы одних данных», и других изоморфизмов в
   прикладном коде почти не бывает. */
const ОСНОВА = `модуль «Продажи»

запись «Заказ»
  номер: строка

запись «Накладная»
  номер: строка

морфизм «выписать» из «Заказ» в «Накладная»
морфизм «по накладной» из «Накладная» в «Заказ»
единица «Заказ»
единица «Накладная»
`

const ЗАКОННЫЙ = `${ОСНОВА}
изоморфизм «Заказ и накладная» из «Заказ» в «Накладная»
  прямой морфизм «выписать»
  обратный морфизм «по накладной»
`

test("пара, сходящаяся концами крест-накрест, проходит проверку", () => {
  const итог = проверить(ЗАКОННЫЙ)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("перепутанные местами стрелки ловятся обеими сторонами", () => {
  const итог = проверить(ЗАКОННЫЙ.replace(
    "  прямой морфизм «выписать»\n  обратный морфизм «по накладной»",
    "  прямой морфизм «по накладной»\n  обратный морфизм «выписать»",
  ))
  assert.ok(итог.коды.includes("FLANG_ISO_MISMATCH"), итог.коды.join(", "))
  /* Сообщение обязано назвать и требуемые концы, и объявленные: «не сходится»
     без имён заставляет искать вторую половину глазами по всему файлу. */
  const текст = итог.тексты.find((строка) => строка.includes("прямой морфизм"))
  assert.match(текст, /обязан вести из «Заказ» в «Накладная»/u)
  assert.match(текст, /а ведёт из «Накладная» в «Заказ»/u)
  /* И вторая стрелка тоже: молчать о ней значило бы отправить автора чинить
     по одной ошибке за прогон. */
  assert.ok(итог.тексты.some((строка) => строка.includes("обратный морфизм «выписать»")), итог.тексты.join("\n"))
})

test("стрелка мимо объекта изоморфизма ловится, даже когда сама по себе законна", () => {
  /* «оплатить» — совершенно правильный морфизм, просто ведёт не туда. Проверка
     сличает концы с объявленными объектами, а не «есть ли вообще стрелка». */
  const итог = проверить(`${ОСНОВА}
запись «Платёж»
  сумма: число

морфизм «оплатить» из «Заказ» в «Платёж»

изоморфизм «Заказ и накладная» из «Заказ» в «Накладная»
  прямой морфизм «оплатить»
  обратный морфизм «по накладной»
`)
  assert.ok(итог.коды.includes("FLANG_ISO_MISMATCH"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /«оплатить» обязан вести из «Заказ» в «Накладная», а ведёт из «Заказ» в «Платёж»/u)
})

test("композиция годится в стрелку изоморфизма: концы у неё выведены, а не объявлены", () => {
  /* Обратный путь идёт в два шага. Изоморфизм об этом знать не обязан — ему
     нужны концы, а концы композиции компилятор уже вывел при её проверке. */
  const итог = проверить(`модуль «Продажи»

запись «Заказ»
  номер: строка
запись «Накладная»
  номер: строка
запись «Черновик»
  номер: строка

морфизм «выписать» из «Заказ» в «Накладная»
морфизм «в черновик» из «Накладная» в «Черновик»
морфизм «из черновика» из «Черновик» в «Заказ»
морфизм «по накладной» это «из черновика» после «в черновик»
единица «Заказ»
единица «Накладная»

изоморфизм «Заказ и накладная» из «Заказ» в «Накладная»
  прямой морфизм «выписать»
  обратный морфизм «по накладной»
`)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("несуществующая стрелка названа по имени, а не «что-то не объявлено»", () => {
  const итог = проверить(ЗАКОННЫЙ.replace("обратный морфизм «по накладной»", "обратный морфизм «которого нет»"))
  assert.ok(итог.коды.includes("FLANG_UNKNOWN_NAME"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /обратный морфизм «которого нет» — такого морфизма нет/u)
})

test("объект изоморфизма обязан быть объявленным типом", () => {
  const итог = проверить(ЗАКОННЫЙ.replace('изоморфизм «Заказ и накладная» из «Заказ» в «Накладная»', 'изоморфизм «Заказ и накладная» из «Заказ» в «Выдумка»'))
  assert.ok(итог.коды.includes("FLANG_UNKNOWN_NAME"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /второй объект изоморфизма .*«Выдумка».*не объявлен/u)
})

test("единица объекта обязана быть объявлена: закон говорит именно о ней", () => {
  /* Без «единица «Накладная»» обещание «кругооборот даёт единицу» ссылается на
     то, чего в программе нет. Это не придирка: единица — конструкция языка, и
     закон изоморфизма — единственное место, где её отсутствие меняет смысл
     объявления с проверяемого на пустое. */
  const итог = проверить(ЗАКОННЫЙ.replace("единица «Накладная»\n", ""))
  assert.ok(итог.коды.includes("FLANG_ISO_IDENTITY_MISSING"), итог.коды.join(", "))
  const текст = итог.тексты.find((строка) => строка.includes("FLANG") || строка.includes("кругооборот"))
  assert.match(текст, /кругооборот через «Накладная» даёт «единица Накладная»/u)
  assert.match(текст, /не объявлена/u)
})

test("изоморфизм объекта с самим собой законен и второй единицы не требует", () => {
  /* Тождественная стрелка — изоморфизм, и это не крайний случай ради полноты:
     на нём проверяется, что требование единиц берётся по МНОЖЕСТВУ объектов, а
     не по паре. Иначе автору пришлось бы объявлять «единица Заказ» дважды. */
  const итог = проверить(`модуль «Продажи»

запись «Заказ»
  номер: строка

единица «Заказ»

изоморфизм «Заказ сам себе» из «Заказ» в «Заказ»
  прямой морфизм «единица Заказ»
  обратный морфизм «единица Заказ»
`)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
})

test("изоморфизм с одним именем дважды — ошибка, а не победа последнего", () => {
  const итог = проверить(`${ЗАКОННЫЙ}
изоморфизм «Заказ и накладная» из «Накладная» в «Заказ»
  прямой морфизм «по накладной»
  обратный морфизм «выписать»
`)
  assert.ok(итог.коды.includes("FLANG_DUPLICATE_NAME"), итог.коды.join(", "))
})

test("объявление с одной половиной парой не является", () => {
  assert.throws(
    () => parse(`${ОСНОВА}
изоморфизм «Заказ и накладная» из «Заказ» в «Накладная»
  прямой морфизм «выписать»
`, "проба.flang"),
    /не указан обратный морфизм/u,
  )
})

test("допущение так и остаётся допущением: без 'даёт' кругооборот не проверяется", () => {
  /* Закрепляем ГРАНИЦУ. «в никуда» и «обратно ниоткуда» — стрелки без `даёт`,
     вычислять в них нечего, и утверждение «их кругооборот есть единица» здесь
     ничем не подкреплено. Проверка молчит — и молчит осознанно: сказать
     «проверено» о нуле значений значило бы подменить «доказано» на
     «посмотрели». Отсюда и второе утверждение теста — такой изоморфизм не
     попадает в список проверенных, а не попадает туда с нулём. */
  const исходник = `модуль «Пустое»

запись «А»
  поле: число
запись «Б»
  поле: число

морфизм «в никуда» из «А» в «Б»
морфизм «обратно ниоткуда» из «Б» в «А»
единица «А»
единица «Б»

изоморфизм «Ничем не подкреплённый» из «А» в «Б»
  прямой морфизм «в никуда»
  обратный морфизм «обратно ниоткуда»
`
  const итог = проверить(исходник)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
  const сетка = обратимость(исходник)
  assert.deepEqual(сетка.коды, [], сетка.тексты.join("\n"))
  assert.deepEqual(сетка.проверено, [])
})

/* ───────────────── обратимость на сетке: у реализованных стрелок ─────────── */

/* Две формы одних данных, и обе стрелки СЧИТАЮТ. Пример тот же, что в шапке
   контракта, — с телом он перестал быть игрушечным: кругооборот действительно
   выполняется, и сломать его можно арифметикой, а не подтасовкой. */
const РЕАЛИЗОВАННЫЙ = `модуль «Продажи»

объект «Заказ»
  сумма является числом

объект «Накладная»
  итог является числом

тотальная функция «Выписать»
  принимает заказ: «Заказ»
  возвращает «Накладная»
  запись «Накладная» с итог равным заказ.сумма

тотальная функция «По накладной»
  принимает накладная: «Накладная»
  возвращает «Заказ»
  запись «Заказ» с сумма равным накладная.итог

морфизм «выписать» из «Заказ» в «Накладная»
  даёт «Выписать»
  закон «итог равен сумме»
    пример «обычный»
      дано заказ равно запись «Заказ» с сумма равным 5
      ожидается запись «Накладная» с итог равным 5

морфизм «по накладной» из «Накладная» в «Заказ»
  даёт «По накладной»
  закон «сумма равна итогу»
    пример «обычный»
      дано накладная равно запись «Накладная» с итог равным 7
      ожидается запись «Заказ» с сумма равным 7

единица «Заказ»
единица «Накладная»

изоморфизм «Заказ и накладная» из «Заказ» в «Накладная»
  прямой морфизм «выписать»
  обратный морфизм «по накладной»
`

test("обратимая пара проходит сетку и объявляет её размер", () => {
  const итог = обратимость(РЕАЛИЗОВАННЫЙ)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
  /* Размер сетки — часть отчёта, а не подробность: «проверено на N значениях»
     без N означало бы разное в разных прогонах. */
  assert.deepEqual(итог.проверено, [{ isomorphism: "Заказ и накладная", values: 4 }])
})

test("сетка берётся из значений, названных автором, — и с обеих сторон", () => {
  /* Убираем закон обратной стрелки: значений для круга через «Накладная»
     станет меньше, но не ноль — ожидаемое значение примера прямой стрелки тоже
     значение «Накладной», и оно в сетку идёт. Это и есть довод, по которому
     сетка собирается из ДВУХ источников, а не из одного. */
  const итог = обратимость(РЕАЛИЗОВАННЫЙ.replace(
    "  закон «сумма равна итогу»\n    пример «обычный»\n      дано накладная равно запись «Накладная» с итог равным 7\n      ожидается запись «Заказ» с сумма равным 7\n",
    "",
  ))
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
  assert.deepEqual(итог.проверено, [{ isomorphism: "Заказ и накладная", values: 2 }])
})

test("необратимая пара называет значение, на котором круг не сошёлся", () => {
  /* Обратная стрелка прибавляет единицу — пара перестаёт быть изоморфизмом.
     Сообщение обязано предъявить контрпример: «не обратимо» без значения
     заставляет искать его руками, а именно значение и есть вся находка. */
  const итог = обратимость(РЕАЛИЗОВАННЫЙ
    .replace("запись «Заказ» с сумма равным накладная.итог", "запись «Заказ» с сумма равным (накладная.итог плюс 1)")
    .replace("ожидается запись «Заказ» с сумма равным 7", "ожидается запись «Заказ» с сумма равным 8"))
  assert.ok(итог.коды.includes("FLANG_ISO_NOT_INVERSE"), итог.коды.join(", "))
  const текст = итог.тексты.find((строка) => строка.includes("через «Заказ»"))
  assert.match(текст, /кругооборот через «Заказ» не даёт «единица Заказ»/u)
  assert.match(текст, /\{"сумма":5\} после «выписать» и «по накладной» стало \{"сумма":6\}/u)
})

test("круг проверяется в обе стороны, а не только из первого объекта", () => {
  /* Пара может быть обратима слева и не обратима справа — это разные
     утверждения. Ломаем прямую стрелку: круг через «Заказ» уцелеет только
     если проверять его от «Накладной» тоже. */
  const итог = обратимость(РЕАЛИЗОВАННЫЙ
    .replace("запись «Накладная» с итог равным заказ.сумма", "запись «Накладная» с итог равным 0")
    .replace("ожидается запись «Накладная» с итог равным 5", "ожидается запись «Накладная» с итог равным 0"))
  assert.ok(итог.тексты.some((строка) => строка.includes("через «Накладная»")), итог.тексты.join("\n"))
})

test("одна реализованная стрелка из двух проверки не даёт: круг замкнуть нечем", () => {
  const итог = обратимость(РЕАЛИЗОВАННЫЙ.replace("  даёт «По накладной»\n", "").replace(
    "  закон «сумма равна итогу»\n    пример «обычный»\n      дано накладная равно запись «Накладная» с итог равным 7\n      ожидается запись «Заказ» с сумма равным 7\n",
    "",
  ))
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
  assert.deepEqual(итог.проверено, [])
})

test("английская поверхность даёт тот же разбор", () => {
  const программа = parse(`${ОСНОВА}
isomorphism «Заказ и накладная» from «Заказ» to «Накладная»
  forward morphism «выписать»
  inverse morphism «по накладной»
`, "проба.flang")
  assert.deepEqual(программа.isomorphisms.map((узел) => [узел.from, узел.to, узел.forward, узел.backward]), [
    ["Заказ", "Накладная", "выписать", "по накладной"],
  ])
})
