/** Разложить набор файлов во временный каталог и связать от входного. */
async function связать(файлы, входной) {
  const каталог = mkdtempSync(join(tmpdir(), "flang-svyaz-"))
  try {
    for (const [имя, текст] of Object.entries(файлы)) writeFileSync(join(каталог, имя), текст, "utf8")
    const путь = join(каталог, входной)
    const { diagnostics: бедыСвязывания, ...программа } = await linkProgram(путь, файлы[входной], parse)
    return { программа, бедыСвязывания }
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Полный вердикт: связывание + типы + квадраты. Ровно то, что делает `check`. */
async function проверить(файлы, входной) {
  const { программа, бедыСвязывания } = await связать(файлы, входной)
  const типы = checkTypes(программа)
  const квадраты = await checkFunctorSquares(программа)
  return {
    программа,
    коды: [...бедыСвязывания, ...(типы.diagnostics ?? []), ...квадраты.diagnostics].map((б) => б.code),
    сообщения: [...бедыСвязывания, ...(типы.diagnostics ?? []), ...квадраты.diagnostics].map((б) => б.message),
    квадраты,
  }
}

