test("подделка: перевод, потерявший поле, отвергается — и отказ несёт контрпример", async () => {
  const итог = await проверить(
    { "orders.flang": ЗАКАЗЫ, "shipping.flang": ОТГРУЗКА, "svyaz.flang": ПОТЕРЯННОЕ_ПОЛЕ },
    "svyaz.flang",
  )
  assert.ok(итог.коды.includes("FLANG_FUNCTOR_SQUARE"), `вышло ${JSON.stringify(итог.коды)}`)

  const текст = итог.сообщения.find((строка) => строка.includes("квадрат не сходится"))
  assert.ok(текст !== undefined, "отказ обязан назвать себя словами «квадрат не сходится»")

  /* КОНТРПРИМЕР В ТЕКСТЕ ОТКАЗА — это и есть вся находка. «Связь не согласована»
     без значения заставляет искать его руками; здесь названы и вход, и оба
     исхода, и стрелка, на которой пути разошлись. */
  assert.match(текст, /«отменить заказ»/u, "названа стрелка")
  assert.match(текст, /\{"сумма":500,"отменён":0\}/u, "названо значение, на котором разошлись")
  assert.match(текст, /\{"сумма":500,"отменена":0\}/u, "назван исход первого пути")
  assert.match(текст, /\{"сумма":500,"отменена":1\}/u, "назван исход второго пути")
})

