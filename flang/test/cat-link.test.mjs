test("пример flang/examples/cat/modules: три модуля согласованы, и это посчитано", async () => {
  const { readFileSync } = await import("node:fs")
  const входной = join(примерКаталог, "reconciliation.flang")
  const исходник = readFileSync(входной, "utf8")
  const { diagnostics: бедыСвязывания, ...программа } = await linkProgram(входной, исходник, parse)
  assert.deepEqual(бедыСвязывания, [])
  assert.deepEqual((checkTypes(программа).diagnostics ?? []).map((б) => б.code), [])

  const квадраты = await checkFunctorSquares(программа)
  assert.deepEqual(квадраты.diagnostics, [])
  assert.deepEqual(квадраты.checked.map((з) => з.functor).sort(), ["Заказ в отгрузку", "Заказ в платёж"])
  for (const запись of квадраты.checked) {
    assert.equal(запись.squares, 3, `у связи «${запись.functor}» обязаны считаться три квадрата`)
    assert.ok(запись.values > 0, `у связи «${запись.functor}» сетка обязана быть непустой`)
    /* Вырожденная сетка — та, где оба пути дают одно и то же значение всегда;
       на ней квадрат сходится при любой реализации. Число различных исходов
       печатается в ведомости именно затем, чтобы такую сетку нельзя было выдать
       за проверку, и здесь оно обязано быть больше единицы. */
    assert.ok(запись.distinct > 1, `сетка связи «${запись.functor}» вырождена: исходов ${запись.distinct}`)
  }
})

test("пример: композиция стрелок тоже входит в квадрат, а не пропускается молча", async () => {
  const { readFileSync } = await import("node:fs")
  const входной = join(примерКаталог, "reconciliation.flang")
  const { diagnostics: _, ...программа } = await linkProgram(входной, readFileSync(входной, "utf8"), parse)
  const итог = await checkFunctorSquares(программа)
  /* Три квадрата на связь — это две образующие стрелки и их композиция. Считать
     композицию не обязательно (вычисление и есть композиция, поэтому её квадрат
     сходится сам), но УМЕТЬ её взять проверка обязана: иначе категория,
     собранная из стрелок, была бы наполовину непроверяемой. */
  assert.ok(итог.checked.every((з) => з.squares === 3))
})

