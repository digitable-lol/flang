test("связь без переводов остаётся допущением автора: ни диагностики, ни строки «проверено»", async () => {
  /* Функтор без `даёт` — то, чем он был всегда: сличение имён. Это законное
     объявление (так написаны все четыре функтора наследия FTS), и второй
     диагностики оно не заслуживает. Но и в `checked` ему не место: сказать
     «проверено» о нуле сравнений — это подмена «доказано» на «посмотрели». */
  const безПеревода = ЧЕСТНАЯ.replace(" даёт «Отгрузка по заказу»", "")
  const итог = await проверить(
    { "orders.flang": ЗАКАЗЫ, "shipping.flang": ОТГРУЗКА, "svyaz.flang": безПеревода },
    "svyaz.flang",
  )
  assert.deepEqual(итог.коды, [])
  assert.deepEqual(итог.квадраты.checked, [])
  assert.equal(итог.квадраты.assumed.length, 1)
  assert.match(итог.квадраты.assumed[0].why, /переводить нечем/u)
})

