/**
 * СВЯЗЬ МОДУЛЕЙ: интерфейс модуля объектом, связь между модулями морфизмом.
 *
 * ── Что здесь проверяется и зачем ───────────────────────────────────────────
 * Интерфейс модуля — это его КАТЕГОРИЯ: `категория «Заказы»` со списком стрелок
 * говорит, какие у модуля виды вещей и что он с ними умеет. Связь двух модулей
 * — ФУНКТОР между такими категориями; в категории категорий он и есть морфизм,
 * так что «связь морфизмом» — не метафора, а то, чем эта запись является.
 *
 * До этой работы связь проверялась только сличением ИМЁН. Здесь появляются две
 * вещи, которых не было:
 *
 *   1. категории ПЕРЕЕЗЖАЮТ через `использует`. Без этого связь между модулями
 *      не проверялась вовсе — а именно между модулями она и нужна;
 *   2. перевод ДАННЫХ (`объект «А» отображается в «Б» даёт «Ф»`) и КВАДРАТ,
 *      который он обязан замыкать: «перевести и сделать» = «сделать и
 *      перевести».
 *
 * ── Четыре обязательных раздела, и ни один не украшение ─────────────────────
 * УЛИКА — прогоном показано, что до правки рассогласование модулей проходило
 * молча: те же строки одним файлом отвергались, тремя модулями — нет.
 * ПОДДЕЛКА — нарушение обязано быть отвергнуто, и в тексте отказа обязан стоять
 * КОНТРПРИМЕР: значение, на котором пути разошлись, и оба исхода.
 * ИЗЪЯТИЕ — снятие проверки обязано красить поимённо названные проверки.
 * АКСИОМ НОЛЬ — список `АКСИОМЫ` ядра доказательств обязан остаться пуст: слой
 * связи модулей не имеет права ничего в него добавить.
 */
