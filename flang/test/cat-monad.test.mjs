const разобрать = (исходник) => parse(исходник, "проба.flang")
/**
 * Тот же исходник без блока `в монаде`.
 *
 * Нужен там, где порча — в самом объявлении монады: с блоком до `checkTypes`
 * дело не дойдёт, потому что развернуть негодную монаду нечем, и разбор
 * откажет раньше. Это не обход проверки, а её устройство: форма разворачивается
 * внутри парсера, значит и спрос с неё там же.
 */
const безБлока = (исходник) => исходник.slice(0, исходник.indexOf("тотальная функция «Дважды убавить»"))
const коды = (итог) => (итог.diagnostics ?? []).map((беда) => беда.code)
const тексты = (итог) => (итог.diagnostics ?? []).map((беда) => беда.message).join("\n")
const устройство = (исходник) => checkTypes(разобрать(исходник))
const законы = (исходник) => checkMonadLaws(разобрать(исходник))

/** Отказ разбора приходит исключением; здесь он нужен значением. */
function отказ(исходник) {
  try {
    parse(исходник, "проба.flang")
    return null
  } catch (беда) {
    return беда?.diagnostics?.[0] ?? { code: "?", message: беда?.message ?? String(беда) }
  }
}

