test("формы блока: без связываний, с четырьмя, внутри `пусть`, с `если` в возврате", () => {
  /* Четыре края разом, и все четыре — про то, что блок остаётся ОБЫЧНЫМ
     выражением: он вправе не связывать ничего, связывать сколько угодно, стоять
     значением `пусть` и держать в `возврат` что угодно, вплоть до `если`. */
  const исходник = `${безБлока(ВОЗМОЖНО)}
тотальная функция «Без связываний»
  принимает начало: число
  возвращает «Возможно» от числа
  в монаде «Возможно»
    возврат начало плюс 1

тотальная функция «Возврат с если»
  принимает начало: число
  возвращает «Возможно» от числа
  в монаде «Возможно»
    пусть первое равно «Убавить» от начало
    возврат если первое больше 2 то первое умножить на 10 иначе первое

тотальная функция «Блок значением пусть»
  принимает начало: число
  возвращает «Возможно» от числа
  пусть готово равно в монаде «Возможно»
    пусть первое равно «Убавить» от начало
    возврат первое плюс 100
  готово

тотальная функция «Четыре шага»
  принимает начало: число
  возвращает «Возможно» от числа
  в монаде «Возможно»
    пусть один равно «Убавить» от начало
    пусть два равно «Убавить» от один
    пусть три равно «Убавить» от два
    пусть четыре равно «Убавить» от три
    возврат один плюс два плюс три плюс четыре
`
  const программа = разобрать(исходник)
  assert.deepEqual(коды(checkTypes(программа)), [], тексты(checkTypes(программа)))
  const тотальность = checkTotality(программа)
  assert.deepEqual(тотальность.diagnostics, [])

  const дай = (имя, начало) => JSON.parse(JSON.stringify(evaluate(программа, имя, { начало })))
  assert.deepEqual(дай("Без связываний", 3), { variant: "Есть", fields: { значение: 4 } })
  assert.deepEqual(дай("Возврат с если", 5), { variant: "Есть", fields: { значение: 40 } })
  assert.deepEqual(дай("Возврат с если", 0), { variant: "Нет", fields: {} })
  assert.deepEqual(дай("Блок значением пусть", 3), { variant: "Есть", fields: { значение: 102 } })
  /* 5 → 4+3+2+1; на 3 цепочка обрывается третьим шагом. */
  assert.deepEqual(дай("Четыре шага", 5), { variant: "Есть", fields: { значение: 10 } })
  assert.deepEqual(дай("Четыре шага", 3), { variant: "Нет", fields: {} })
})

