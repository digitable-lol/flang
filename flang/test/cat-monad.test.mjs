/**
 * Монада и форма `в монаде`: что доказано, что проверено, а что развёрнуто.
 *
 * Три границы, и каждую этот файл проверяет отдельно.
 *
 * РАЗВОРАЧИВАЕТСЯ. `в монаде` живёт от парсера до парсера: на выходе `parse`
 * узла `inMonad` не существует, а стоит обычный вызов `соединение` поверх
 * обычного `разбор`. Отсюда всё остальное бесплатно — типы, завершаемость,
 * восемь бэкендов и обе реализации самоприменения о форме не знают ни строчки.
 * Проверяется это не словами: тест ищет `inMonad` в напечатанном JSON и требует
 * ноль, а потом печатает программу во все восемь целей.
 *
 * ДОКАЗЫВАЕТСЯ устройство: тип объявлен и параметричен; названный параметр у
 * него есть; `возврат` ведёт из «А» в M«А»; `соединение` — из M(M«А») в M«А»;
 * параметр стоит в полях целиком, значит отображение эндофунктора выводится
 * однозначно. Утверждения обо всех входах, живут в `checkTypes`.
 *
 * ПРОВЕРЯЕТСЯ на конечной сетке — три закона связывания. Это равенства
 * ВЫЧИСЛЕНИЙ, и решить их нельзя, можно только предъявить контрпример. Форма
 * сообщения поэтому та же, что у моноида: не «закон нарушен», а «на этом
 * значении и этих стрелках слева вышло одно, справа другое».
 *
 * Ассоциативность проверяется на монаде-писателе, а не на «Возможно», и это не
 * прихоть: у «Возможно» ассоциативность ломается только вместе с единицами, то
 * есть отдельного контрпримера на неё не построить. У писателя — строится: если
 * `соединение` склеит метки задом наперёд, обе единицы уцелеют (пустая метка
 * коммутирует со всем), а ассоциативность рухнет. Тест без контрпримера ничего
 * не проверяет, и на такой ловушке этот файл уже стоял бы.
 */
