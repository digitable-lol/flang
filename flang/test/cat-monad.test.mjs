function который(имя) {
  try {
    execFileSync("which", [имя], { stdio: "pipe" })
    return имя
  } catch {
    return null
  }
}

/*
 * Напечатанное уходит во временный каталог системы, а не в `output/` дерева, —
 * как у `emit-c.test.mjs`. Причина не в чистоте: `output/` не убирается за
 * прогоном, и каждый запуск оставлял бы там ещё один каталог с рантаймом на
 * 160 КБ. Здесь всё уходит одним `rm` по концу файла.
 */
const времянкаНабора = mkdtempSync(join(tmpdir(), "flang-cat-monad-"))
process.on("exit", () => rmSync(времянкаНабора, { recursive: true, force: true }))

/** Пустой каталог под напечатанное. */
function времянка(метка) {
  const путь = join(времянкаНабора, метка)
  rmSync(путь, { recursive: true, force: true })
  mkdirSync(путь, { recursive: true })
  return путь
}

function записать(каталог, напечатанное) {
  for (const файл of напечатанное.files) writeFileSync(`${каталог}/${файл.path}`, файл.content, "utf8")
}

/** Значение из прогонщика на C — в то же представление, что у интерпретатора. */
function изС(значение) {
  if (значение === null || typeof значение !== "object") return значение
  if ("v" in значение) {
    const поля = {}
    for (const [имя, вложенное] of значение.f) поля[имя] = изС(вложенное)
    return { variant: значение.v, fields: поля }
  }
  if ("n" in значение) return Number(значение.n)
  if ("s" in значение) return значение.s
  if ("b" in значение) return значение.b
  if ("l" in значение) return значение.l.map(изС)
  return значение
}
