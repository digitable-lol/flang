test("пример репозитория: напечатанный JS считает то же, что интерпретатор", async () => {
  const программа = parse(исходникПримера, ПРИМЕР)
  const каталог = времянка("monad-js")
  записать(каталог, emitJs(программа))
  const модуль = await import(`file://${каталог}/itog_zakaza.js`)
  const пары = [
    ["Итог со скидкой", "itogSoSkidkoy"],
    ["Итог со скидкой вручную", "itogSoSkidkoyVruchnuyu"],
    ["Сколько сэкономили на паре", "skolkoSekonomiliNaPare"],
    ["Отгрузка по позиции", "otgruzkaPoPozicii"],
  ]
  let точек = 0
  for (const [русское, латиница] of пары) {
    assert.equal(typeof модуль[латиница], "function", `в напечатанном нет «${латиница}»`)
    for (const номер of [0, 1, 2, 3, 9, -1]) {
      точек += 1
      const ждём = JSON.stringify(evaluate(программа, русское, { номер }))
      assert.equal(JSON.stringify(модуль[латиница](номер)), ждём, `${русское} на ${номер}`)
    }
  }
  assert.ok(точек >= 24, `точек сверки ${точек}`)
})

