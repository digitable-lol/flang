/**
 * Моноид и группа: что здесь доказано, а что проверено.
 *
 * Эти тесты стоят на границе, которую язык обязан держать явной, и сами её
 * проверяют с обеих сторон.
 *
 * ДОКАЗЫВАЕТСЯ устройство: операция — функция двух аргументов носителя,
 * возвращающая носитель; единица — значение носителя; обращение — функция
 * носителя в носитель. Это утверждения обо всех входах, берутся из объявлений,
 * и живут в `checkTypes` рядом с законами функтора.
 *
 * ПРОВЕРЯЕТСЯ на конечной сетке всё остальное: ассоциативность, нейтральность,
 * обратимость. Это равенства вычислений на всех значениях носителя, и решить их
 * нельзя — можно только предъявить контрпример. Отсюда и форма сообщений: не
 * «закон нарушен», а «на 0, 0, 5 слева вышло −5, справа 5».
 *
 * Группы отдельной конструкцией нет: группа — моноид с обращением. Тест это
 * закрепляет, потому что соблазн завести второе слово будет возвращаться.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { checkMonoidLaws } from "../src/monoid.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

/** Склейка строк — моноид без обращения: обратной строки не бывает. */
const СКЛЕЙКА = `модуль «Моноиды»

тотальная функция «Склеить»
  принимает первая: строка, вторая: строка
  возвращает строка
  пример «Две части»
    дано первая равно "аб"
    дано вторая равно "вг"
    ожидается "абвг"
  пример «С пустой»
    дано первая равно ""
    дано вторая равно "х"
    ожидается "х"
  соединить первая с вторая

моноид «Склейка строк»
  носитель строка
  операция «Склеить»
  единица ""
`

/** Сложение чисел — уже группа: обращение объявлено. */
const СЛОЖЕНИЕ = `модуль «Группа»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  пример «Сумма»
    дано первое равно 2
    дано второе равно 3
    ожидается 5
  пример «С нулём»
    дано первое равно 7
    дано второе равно 0
    ожидается 7
  первое плюс второе

тотальная функция «Противоположное»
  принимает значение: число
  возвращает число
  пример «Меняет знак»
    дано значение равно 4
    ожидается -4
  0 минус значение

моноид «Сложение чисел»
  носитель число
  операция «Сложить»
  единица 0
  обратный элемент «Противоположное»
`

const коды = (итог) => (итог.diagnostics ?? []).map((беда) => беда.code)
const тексты = (итог) => (итог.diagnostics ?? []).map((беда) => беда.message).join("\n")

const устройство = (исходник) => checkTypes(parse(исходник, "проба.flang"))
const законы = (исходник) => checkMonoidLaws(parse(исходник, "проба.flang"))

/* ─────────────────────── доказуемая часть ─────────────────────── */

test("моноид со сходящимся устройством проходит проверку", () => {
  assert.deepEqual(коды(устройство(СКЛЕЙКА)), [], тексты(устройство(СКЛЕЙКА)))
})

test("единица чужого типа названа вместе с носителем", () => {
  const итог = устройство(СКЛЕЙКА.replace('единица ""', "единица 0"))
  assert.ok(коды(итог).includes("FLANG_TYPE"), коды(итог).join(", "))
  assert.match(тексты(итог), /единица имеет тип число, а носитель объявлен как строка/u)
})

test("операция, выводящая из носителя, — ошибка, а не мелочь", () => {
  /* Носитель числовой, операция и единица строковые: все ЧЕТЫРЕ несовпадения
     обязаны быть названы по отдельности — два аргумента, возврат и единица.
     Иначе автор чинит по одному и гадает, что вылезет дальше. */
  const итог = устройство(СКЛЕЙКА.replace("носитель строка", "носитель число"))
  assert.equal(коды(итог).filter((код) => код === "FLANG_TYPE").length, 4)
  assert.match(тексты(итог), /операция «Склеить» возвращает строка/u)
})

test("операция не той арности: сказано, сколько берёт и сколько надо", () => {
  const исходник = `модуль «Арность»

тотальная функция «Одна»
  принимает первая: строка
  возвращает строка
  первая

моноид «Склейка строк»
  носитель строка
  операция «Одна»
  единица ""
`
  const итог = устройство(исходник)
  assert.ok(коды(итог).includes("FLANG_MONOID"), коды(итог).join(", "))
  assert.match(тексты(итог), /принимает 1 арг\., а обязана два/u)
})

test("несуществующая операция названа по имени", () => {
  const итог = устройство(СКЛЕЙКА.replace("операция «Склеить»", "операция «Которой нет»"))
  assert.ok(коды(итог).includes("FLANG_UNKNOWN_NAME"), коды(итог).join(", "))
  assert.match(тексты(итог), /операции «Которой нет» нет/u)
})

/* ─────────────────────── проверяемая часть ─────────────────────── */

test("законы склейки строк держатся на сетке из примеров", () => {
  const итог = законы(СКЛЕЙКА)
  assert.deepEqual(коды(итог), [], тексты(итог))
  /* Отчёт обязан называть размер сетки: «проверено» без числа — не проверено. */
  assert.equal(итог.checked.length, 1)
  assert.ok(итог.checked[0].values >= 3, `значений в сетке всего ${итог.checked[0].values}`)
  assert.equal(итог.checked[0].triples, итог.checked[0].values ** 3)
})

test("вычитание не моноид: названы и нейтральность, и ассоциативность", () => {
  const вычитание = СКЛЕЙКА
    .replace("носитель строка", "носитель число")
    .replace('единица ""', "единица 0")
    .replace("соединить первая с вторая", "первая минус вторая")
    .replace('дано первая равно "аб"', "дано первая равно 5")
    .replace('дано вторая равно "вг"', "дано вторая равно 3")
    .replace('ожидается "абвг"', "ожидается 2")
    .replace('дано первая равно ""', "дано первая равно 7")
    .replace('дано вторая равно "х"', "дано вторая равно 0")
    .replace('ожидается "х"', "ожидается 7")
  const итог = законы(вычитание)
  assert.ok(коды(итог).includes("FLANG_MONOID_IDENTITY"), коды(итог).join(", "))
  assert.ok(коды(итог).includes("FLANG_MONOID_ASSOC"), коды(итог).join(", "))
  /* Контрпример, а не вердикт: без значений автор не поймёт, что чинить. */
  assert.match(тексты(итог), /на 0, 0, 5 слева вышло -5, справа 5/u)
})

test("группа — это моноид с обращением, отдельного слова не нужно", () => {
  const итог = законы(СЛОЖЕНИЕ)
  assert.deepEqual(коды(итог), [], тексты(итог))
  assert.deepEqual(коды(устройство(СЛОЖЕНИЕ)), [])
})

test("обращение, не дающее единицу, ловится с контрпримером", () => {
  const итог = законы(СЛОЖЕНИЕ.replace("  0 минус значение", "  значение плюс 1"))
  assert.ok(коды(итог).includes("FLANG_GROUP_INVERSE"), коды(итог).join(", "))
  assert.match(тексты(итог), /обращение не даёт единицу/u)
})

test("обращение не той формы ловится до вычисления законов", () => {
  const итог = устройство(СЛОЖЕНИЕ.replace(
    "тотальная функция «Противоположное»\n  принимает значение: число\n  возвращает число",
    "тотальная функция «Противоположное»\n  принимает значение: число\n  возвращает строка",
  ).replace("  0 минус значение", '  к строке значение'))
  assert.ok(коды(итог).includes("FLANG_TYPE"), коды(итог).join(", "))
  assert.match(тексты(итог), /обращение «Противоположное» обязано вести из число в число/u)
})

test("программа без моноидов проверку законов не запускает", () => {
  const итог = законы("модуль «Пусто»\n\nтотальная функция «Два»\n  возвращает число\n  2\n")
  assert.deepEqual(итог.diagnostics, [])
  assert.deepEqual(итог.checked, [])
})
