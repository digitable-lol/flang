/* ─────────────────────── закон при стрелке ───────────────────────────────── */

/* Отдельная категория со СЧИТАЕМОЙ стрелкой: у «Отгрузка» здесь номер число, а
   не строка, — иначе закон нечем было бы нарушить арифметикой, и падение
   пришлось бы подстраивать вручную. */
const СЧИТАЕМАЯ = `модуль «Продажи»

объект «Заказ»
  сумма является числом

объект «Отгрузка»
  номер является числом

тотальная функция «Отгрузить заказ»
  принимает заказ: «Заказ»
  возвращает «Отгрузка»
  запись «Отгрузка» с номер равным заказ.сумма
`

const СО_ЗАКОНОМ = `${СЧИТАЕМАЯ}
морфизм «отгрузить» из «Заказ» в «Отгрузка»
  даёт «Отгрузить заказ»
  закон «номер берётся из суммы»
    пример «обычный»
      дано заказ равно запись «Заказ» с сумма равным 5
      ожидается запись «Отгрузка» с номер равным 5
`

test("стрелка без блока осталась ровно тем, чем была: ни gives, ни laws в узле", () => {
  /* Ключи появляются только когда написаны. Иначе AST каждой существующей
     стрелки поменялся бы на два поля, а его сверяет побайтово неподвижная
     точка самоприменения — расхождение там дороже любого удобства. */
  const стрелка = (разобрать(КАТЕГОРИЯ).morphisms ?? [])[0]
  assert.equal("gives" in стрелка, false)
  assert.equal("laws" in стрелка, false)
})

test("закон разбирается в примеры той же формы, что примеры функции", () => {
  const стрелка = (разобрать(СО_ЗАКОНОМ).morphisms ?? [])[0]
  assert.equal(стрелка.gives, "Отгрузить заказ")
  assert.equal(стрелка.laws.length, 1)
  assert.equal(стрелка.laws[0].name, "номер берётся из суммы")
  assert.deepEqual(стрелка.laws[0].examples.map((пример) => пример.name), ["обычный"])
  assert.deepEqual(стрелка.laws[0].examples[0].args, { заказ: { сумма: 5 } })
})

test("реализация, сходящаяся концами с объявленной стрелкой, проходит проверку", () => {
  assert.deepEqual(проверить(СО_ЗАКОНОМ).diagnostics, [])
})

test("нарушенный собственным примером закон валит flang test и называет себя", () => {
  /* КРИТЕРИЙ ГОТОВНОСТИ всей конструкции. Закон, который не может провалиться,
     — украшение; закон, который проваливается молча или безымянно, — хуже
     украшения, потому что читается как гарантия. */
  const сломано = СО_ЗАКОНОМ.replace("ожидается запись «Отгрузка» с номер равным 5", "ожидается запись «Отгрузка» с номер равным 6")
  const итог = runExamples(разобрать(сломано))
  assert.equal(итог.valid, false)
  assert.equal(итог.failed, 1)
  const строка = итог.results[0]
  assert.equal(строка.function, "морфизм «отгрузить», закон «номер берётся из суммы»")
  assert.equal(строка.example, "обычный")
  assert.deepEqual(строка.actual, { номер: 5 })
})

test("выполняющийся закон идёт в тот же отчёт, что примеры функции", () => {
  /* Не в отдельный: иначе часть примеров языка проверяла бы одна команда, а
     часть — другая, и автор обязан был бы помнить, какая именно. */
  const итог = runExamples(разобрать(СО_ЗАКОНОМ))
  assert.equal(итог.valid, true)
  assert.equal(итог.total, 1)
})

test("даёт на несуществующую функцию названо по имени", () => {
  const итог = проверить(СО_ЗАКОНОМ.replace('даёт «Отгрузить заказ»', 'даёт «Которой нет»'))
  assert.deepEqual(коды(итог), ["FLANG_UNKNOWN_NAME"])
  assert.match(итог.diagnostics[0].message, /морфизм «отгрузить» даёт «Которой нет»: такой функции нет/u)
})

test("реализация с чужим кодоменом отвергается: имя «морфизм» без совпадения концов — украшение", () => {
  const итог = проверить(
    `${СЧИТАЕМАЯ}\nморфизм «отгрузить» из «Заказ» в «Заказ»\n  даёт «Отгрузить заказ»\n`,
  )
  assert.deepEqual(коды(итог), ["FLANG_MORPHISM_SHAPE"])
  assert.match(итог.diagnostics[0].message, /ведёт в «Заказ», а «Отгрузить заказ» возвращает «Отгрузка»/u)
})

test("реализация от двух входов стрелкой не является", () => {
  /* Стрелка ведёт из ОДНОГО объекта в один. Произведение объектов в языке есть
     (запись), и морфизм из пары пишется записью-доменом, а не двумя входами. */
  const итог = проверить(
    `${СЧИТАЕМАЯ}\nтотальная функция «Отгрузить двумя»\n  принимает заказ: «Заказ», ещё: число\n  возвращает «Отгрузка»\n  запись «Отгрузка» с номер равным ещё\n\n` +
      `морфизм «отгрузить» из «Заказ» в «Отгрузка»\n  даёт «Отгрузить двумя»\n`,
  )
  assert.deepEqual(коды(итог), ["FLANG_MORPHISM_SHAPE"])
  assert.match(итог.diagnostics[0].message, /принимает 2: стрелке нужна функция ровно от одного входа/u)
})

test("пример закона проверяется по типам там же, где примеры функции", () => {
  /* Опечатка в имени входа обязана быть ошибкой модели, а не невнятным отказом
     вычисления при `flang test`. Сообщение называет и закон, и морфизм. */
  const итог = проверить(СО_ЗАКОНОМ.replace("дано заказ равно", "дано зкааз равно"))
  assert.deepEqual(коды(итог).sort(), ["FLANG_TYPE", "FLANG_UNKNOWN_NAME"])
  assert.match(итог.diagnostics.map((д) => д.message).join("\n"), /закона «номер берётся из суммы» морфизма «отгрузить»/u)
})

