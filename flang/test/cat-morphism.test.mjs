/**
 * Теоркат-поверхность, шаг 1: категория, стрелка, композиция, цепочка, единица.
 *
 * Стыковка композиции — то немногое в теоркате, что компилятор ДОКАЗЫВАЕТ, а не
 * проверяет на сетке входов: `«в» это «б» после «а»` собирается тогда и только
 * тогда, когда кодомен «а» равен домену «б». Утверждение обо всех входах, без
 * решателя и без примеров, — поэтому тесты ниже проверяют не «работает на
 * случае», а что несостыковка отвергается всегда.
 *
 * Контракт: flang/cat/SPEC.md.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

const КАТЕГОРИЯ = `модуль «Продажи»

объект «Заказ»
  сумма является числом

объект «Отгрузка»
  номер является строкой

объект «Счёт»
  итог является числом

морфизм «отгрузить» из «Заказ» в «Отгрузка»
морфизм «выставить» из «Отгрузка» в «Счёт»
`

const разобрать = (текст) => parse(текст, "проба.flang")
const проверить = (текст) => checkTypes(разобрать(текст))
const коды = (итог) => itogКоды(итог)
const itogКоды = (итог) => итог.diagnostics.map((d) => d.code)

test("стрелка получает домен и кодомен, а не уезжает в legacy", () => {
  const программа = разобрать(КАТЕГОРИЯ)
  const стрелки = программа.morphisms ?? []
  assert.equal(стрелки.length, 2)
  assert.deepEqual(
    стрелки.map((м) => [м.name, м.domain, м.codomain]),
    [
      ["отгрузить", "Заказ", "Отгрузка"],
      ["выставить", "Отгрузка", "Счёт"],
    ],
  )
})

test("композиция стыкуется — кодомен правой равен домену левой", () => {
  const итог = проверить(`${КАТЕГОРИЯ}морфизм «оформить» это «выставить» после «отгрузить»\n`)
  assert.deepEqual(итог.diagnostics, [], "правильная композиция обязана собираться молча")
})

test("переставленная композиция отвергается с указанием, что с чем не сошлось", () => {
  const итог = проверить(`${КАТЕГОРИЯ}морфизм «оформить» это «отгрузить» после «выставить»\n`)
  assert.deepEqual(коды(итог), ["FLANG_COMPOSE_MISMATCH"])
  const текст = итог.diagnostics[0].message
  assert.match(текст, /«выставить» приводит в «Счёт»/u)
  assert.match(текст, /«отгрузить» ожидает «Заказ»/u)
})

test("композиция от композиции законна: разрешается по мере готовности", () => {
  const итог = проверить(
    `${КАТЕГОРИЯ}морфизм «оформить» это «выставить» после «отгрузить»\n` +
      `морфизм «оформить дважды» это «оформить» после «отгрузить»\n`,
  )
  /* «оформить» ведёт из «Заказ» в «Счёт», «отгрузить» — из «Заказ» в «Отгрузка»:
     стыковки нет, и это должно быть замечено, а не пропущено из-за порядка. */
  assert.deepEqual(коды(итог), ["FLANG_COMPOSE_MISMATCH"])
})

test("композиция вправе ссылаться на морфизм, объявленный ниже", () => {
  const итог = проверить(
    `модуль «Проба»\n\nобъект «А»\n  поле является числом\n\nобъект «Б»\n  поле является числом\n\n` +
      `морфизм «оба» это «второй» после «первый»\n` +
      `морфизм «первый» из «А» в «Б»\n` +
      `морфизм «второй» из «Б» в «А»\n`,
  )
  assert.deepEqual(итог.diagnostics, [], "порядок объявлений не должен решать")
})

test("морфизм в необъявленный объект — ошибка: объект категории это тип", () => {
  const итог = проверить(`${КАТЕГОРИЯ}морфизм «в никуда» из «Заказ» в «Пустота»\n`)
  assert.deepEqual(коды(итог), ["FLANG_UNKNOWN_NAME"])
  assert.match(итог.diagnostics[0].message, /«Пустота»/u)
})

test("хождение по кругу — диагностика, а не зависание", () => {
  const итог = проверить(`${КАТЕГОРИЯ}морфизм «а» это «б» после «отгрузить»\nморфизм «б» это «а» после «отгрузить»\n`)
  assert.ok(коды(итог).includes("FLANG_UNKNOWN_NAME"), `получено ${JSON.stringify(коды(итог))}`)
})

test("цепочка разворачивается в композиции и стыкуется по всей длине", () => {
  const текст = `${КАТЕГОРИЯ}цепочка «провести»\n  сначала «отгрузить»\n  затем «выставить»\n`
  assert.deepEqual(проверить(текст).diagnostics, [])
  const шаги = (разобрать(текст).morphisms ?? []).filter((м) => м.kind === "composition")
  assert.equal(шаги.length, 1)
  assert.equal(шаги[0].name, "провести")
})

test("промежуточные звенья цепочки служебные и не занимают имён", () => {
  const текст =
    `${КАТЕГОРИЯ}объект «Оплата»\n  принята является признаком\n\n` +
    `морфизм «оплатить» из «Счёт» в «Оплата»\n` +
    `цепочка «провести»\n  сначала «отгрузить»\n  затем «выставить»\n  затем «оплатить»\n`
  assert.deepEqual(проверить(текст).diagnostics, [])
  const композиции = (разобрать(текст).morphisms ?? []).filter((м) => м.kind === "composition")
  assert.equal(композиции.length, 2)
  assert.equal(композиции.filter((м) => м.internal === true).length, 1)
  assert.equal(композиции.at(-1).name, "провести")
})

test("разрыв в середине цепочки называет, где именно порвалось", () => {
  const текст =
    `${КАТЕГОРИЯ}объект «Оплата»\n  принята является признаком\n\n` +
    `морфизм «оплатить» из «Счёт» в «Оплата»\n` +
    `цепочка «провести»\n  сначала «отгрузить»\n  затем «оплатить»\n`
  const итог = проверить(текст)
  assert.deepEqual(коды(итог), ["FLANG_COMPOSE_MISMATCH"])
  assert.match(итог.diagnostics[0].message, /«отгрузить» приводит в «Отгрузка»/u)
  assert.match(итог.diagnostics[0].message, /«оплатить» ожидает «Счёт»/u)
})

test("единица объекта — стрелка из него в него самого", () => {
  const программа = разобрать(`${КАТЕГОРИЯ}единица «Заказ»\n`)
  const единица = (программа.morphisms ?? []).find((м) => м.identity === true)
  assert.notEqual(единица, undefined)
  assert.equal(единица.domain, "Заказ")
  assert.equal(единица.codomain, "Заказ")
})

test("единица композируется с любой стрелкой из своего объекта", () => {
  const итог = проверить(`${КАТЕГОРИЯ}единица «Заказ»\nморфизм «тот же» это «отгрузить» после «единица Заказ»\n`)
  assert.deepEqual(итог.diagnostics, [], "композиция с единицей обязана стыковаться")
})

test("старая форма морфизма FTS продолжает работать: она утверждение, а не стрелка", () => {
  /* 24 морфизма в моделях репозитория написаны так, и они обязаны остаться
     валидными: морфизм это «и то и другое», а не «одно вместо другого». */
  const программа = разобрать(
    `модуль «Проба»\n\nморфизм «Готовый заказ можно отгрузить»\n  если «Готов к отгрузке»\n  то «Отгрузить разрешено»\n`,
  )
  assert.equal((программа.morphisms ?? []).length, 0, "утверждение не должно попадать в стрелки")
  const legacy = (программа.legacy ?? []).filter((узел) => узел.construct === "morphism")
  assert.equal(legacy.length, 1)
})

test("два морфизма с одним именем — ошибка", () => {
  const итог = проверить(`${КАТЕГОРИЯ}морфизм «отгрузить» из «Заказ» в «Счёт»\n`)
  assert.deepEqual(коды(итог), ["FLANG_DUPLICATE_NAME"])
})

test("цепочка короче двух шагов не собирается: композировать нечего", () => {
  assert.throws(() => разобрать(`${КАТЕГОРИЯ}цепочка «одна»\n  сначала «отгрузить»\n`), /двух шагов/u)
})
