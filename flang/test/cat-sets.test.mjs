test("склеивающая стрелка — не вложение, и сообщение предъявляет контрпример", async () => {
  const склейка = РИСУНОК.replace(
    "  запись «Заказ» с номер равным срочный.номер",
    "  запись «Заказ» с номер равным 0",
  )
    .replace("    ожидается запись «Заказ» с номер равным 1", "    ожидается запись «Заказ» с номер равным 0")
    .replace("    ожидается запись «Заказ» с номер равным 2\n  запись", "    ожидается запись «Заказ» с номер равным 0\n  запись")
  const { коды, тексты } = await насетке(склейка)
  assert.deepEqual(коды, ["FLANG_EMBED_NOT_INJECTIVE"])
  /* Без значений в тексте «не инъективно» заставляет искать контрпример
     руками, а именно он и есть вся находка. */
  assert.match(тексты[0], /\{"номер":1\} и \{"номер":2\} дают \{"номер":0\}/u)
  assert.match(тексты[0], /показывает не подмножество, а фактор/u)
})

test("непустота общей части подтверждается СВИДЕТЕЛЕМ, и он назван", async () => {
  const { коды, проверено } = await насетке(РИСУНОК)
  assert.deepEqual(коды, [])
  const общая = проверено.find((запись) => запись.intersection === "Срочные оплаченные")
  assert.deepEqual(общая, { intersection: "Срочные оплаченные", values: 4, witness: { номер: 2 } })
})

