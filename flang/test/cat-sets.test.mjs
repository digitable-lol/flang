test("слов два, и оба свои: вложение и пересечение", () => {
  assert.equal(keywordId("вложение"), "embedding")
  assert.equal(keywordId("embedding"), "embedding")
  assert.equal(keywordId("пересечение"), "intersection")
  assert.equal(keywordId("intersection"), "intersection")
})

test("«объединение» словом НЕ стало: ко-произведение в языке уже есть", () => {
  /* Это не забывчивость, а решение, и держать его обязан тест. Ко-произведение
     — это `тип … вариант …` вместе с `разбор`: два вложения внутрь и
     универсальное свойство. Третье слово об этом не доказало бы ничего сверх
     исчерпывающности разбора, зато завело бы вторую проверку рядом с первой.
     Заведи его завтра — этот тест покраснеет и потребует объяснить, что нового
     оно доказывает. */
  assert.equal(keywordId("объединение"), null)
  assert.equal(keywordId("union"), null)

  /* А сам копроизведение-тип разбирается и проверяется как всегда. */
  const { коды } = проверить([
    "модуль «М»",
    "",
    "тип «Заказ или отказ»",
    "  вариант «Есть заказ» содержит номер: число",
    "  вариант «Отказано»",
    "",
  ].join("\n"))
  assert.deepEqual(коды, [])
})

