/** Разбор + доказательство устройства: то, что делает `checkTypes`. */
function проверить(исходник) {
  const итог = checkTypes(parse(исходник, "проба.flang"))
  return {
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

/** Сетка — отдельной дорогой, как у изоморфизма и моноида: она ВЫЧИСЛЯЕТ. */
async function насетке(исходник) {
  const итог = await множестваЗаконом(parse(исходник, "проба.flang"))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    проверено: итог.checked,
    допущено: итог.assumed,
  }
}

