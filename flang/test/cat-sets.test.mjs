test("целая программа с кругами Эйлера принимается — и это тот самый рисунок", async () => {
  /* Не фрагмент, а файл целиком: `flang/examples/cat/euler-orders.flang` — три
     круга, два вложения и одна общая часть. Проверяется он тем же путём, каким
     его проверяет `flang check`: устройство доказывается, сетка считается, и ни
     та ни другая дорога не даёт ни одной диагностики. */
  const исходник = readFileSync(new URL("../examples/cat/euler-orders.flang", import.meta.url), "utf8")
  assert.deepEqual(проверить(исходник).коды, [])
  const сетка = await насетке(исходник)
  assert.deepEqual(сетка.коды, [])
  /* Зелёное здесь означает не «посмотрели», а названное число значений и
     названного свидетеля. */
  assert.deepEqual(
    сетка.проверено.find((запись) => запись.intersection === "Срочные оплаченные"),
    { intersection: "Срочные оплаченные", values: 4, witness: { номер: 2, срочность: 1 } },
  )
})

test("ЦЕЛАЯ ПРОГРАММА, КОТОРАЯ ОБЯЗАНА БЫТЬ ОТВЕРГНУТА: вложения, которого нет", () => {
  /* Зеркало теста выше, и написано оно до кода. Рисунок тот же — два круга
     внутри третьего, — но одно вложение НЕ ОБЪЯВЛЕНО, а общая часть объявлена.
     Принять такое значило бы согласиться, что «общий элемент» есть у множеств,
     которые не с чем сличать: значения «Оплаченного» и «Заказа» — разных типов.

     Отвергается это ДОКАЗАТЕЛЬСТВОМ, а не сеткой, поэтому отказ не зависит ни от
     примеров, ни от их числа. И отвергается своим кодом: `FLANG_MEET_NO_UNIVERSE`
     говорит машине, что чинить, а сообщение — какую строку дописать. */
  const отвергаемая = [
    "модуль «Круги, которых нет»",
    "",
    "объект «Заказ»",
    "  номер является числом",
    "",
    "объект «Срочный»",
    "  номер является числом",
    "",
    "объект «Оплаченный»",
    "  номер является числом",
    "",
    "тотальная функция «Срочный заказ»",
    "  принимает срочный: «Срочный»",
    "  возвращает «Заказ»",
    "  пример «первый»",
    "    дано срочный равно запись «Срочный» с номер равным 1",
    "    ожидается запись «Заказ» с номер равным 1",
    "  запись «Заказ» с номер равным срочный.номер",
    "",
    "вложение «Срочные среди заказов» из «Срочный» в «Заказ» даёт «Срочный заказ»",
    "",
    "пересечение «Срочные оплаченные» из «Срочный» и «Оплаченный» в «Заказ»",
    "",
  ].join("\n")

  const { коды, тексты } = проверить(отвергаемая)
  assert.deepEqual(коды, ["FLANG_MEET_NO_UNIVERSE"])
  assert.match(тексты[0], /вторая сторона «Оплаченный» не вложена в «Заказ»/u)
  assert.match(тексты[0], /объявите «вложение … из «Оплаченный» в «Заказ»»/u)

  /* И главное: отказ здесь не от того, что сетка чего-то не нашла. Убери
     примеры вовсе — программа останется отвергнутой тем же кодом. */
  const безПримеров = отвергаемая
    .split("\n")
    .filter((строка) => !строка.startsWith("  пример") && !строка.startsWith("    "))
    .join("\n")
  assert.deepEqual(проверить(безПримеров).коды, ["FLANG_MEET_NO_UNIVERSE"])
})

