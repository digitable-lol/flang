/**
 * Отношения множеств: вложение и общая часть — контракт flang/cat/SETS.md.
 *
 * ГРАНИЦА ЧЕСТНОСТИ ЗДЕСЬ ПРОХОДИТ ВНУТРИ КАЖДОГО ИЗ ДВУХ СЛОВ, и назвать её
 * надо до первого теста, иначе зелёный прогон прочитается как «подмножество
 * доказано», а это неправда.
 *
 * ДОКАЗЫВАЕТСЯ — сличением объявлений, без сетки и без вычислений:
 *
 *   вложение    — оба множества объявлены; имя не занято другим вложением;
 *                 написанное `даёт «Ф»` принимает ровно один вход, вход этот
 *                 есть вложенная часть, а результат — объемлющее множество;
 *   пересечение — объемлющее множество объявлено; ОБЕ стороны в него вложены
 *                 объявленным `вложение`; имя общей части свободно; стороны
 *                 различны; у одной пары над одним объемлющим общая часть одна.
 *
 * ПРОВЕРЯЕТСЯ НА СЕТКЕ — на значениях, написанных автором, и только на них:
 *
 *   вложение    — инъективность: два разных значения не приходят в одно.
 *                 Нарушение — ОШИБКА, потому что контрпример предъявлен;
 *   пересечение — непустота: ищется свидетель, значение, приходящее в
 *                 объемлющее и слева, и справа. Найден — общая часть попадает
 *                 в `checked` вместе со свидетелем.
 *
 * ОСТАЁТСЯ ДОПУЩЕНИЕМ — и это главное, ради чего написан последний раздел
 * тестов:
 *
 *   • вложение без `даёт` — вычислять нечего, проверка молчит;
 *   • общая часть БЕЗ СВИДЕТЕЛЯ. Сетка не нашла общего значения — и это НЕ
 *     ошибка: значений, которых автор не написал, бесконечно много. Такая
 *     общая часть уходит в `assumed`, а `flang check` о ней молчит;
 *   • универсальность общей части — что она САМАЯ БОЛЬШАЯ из общих. Утверждение
 *     про все множества сразу; проверить его нечем, и компилятор не выводит из
 *     него следствий.
 *
 * ПОЧЕМУ СЛОВ ДВА, А НЕ ТРИ, — тоже закреплено тестом: объединения нет, потому
 * что ко-произведение в языке уже есть и называется `тип … вариант …`.
 */
