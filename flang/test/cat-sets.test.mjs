test("общая часть без свидетеля — НЕ ошибка: «не нашли» это не «нет»", async () => {
  /* Самый важный тест файла. Убираем общее значение: у «Срочного» остаётся 1, у
     «Оплаченного» — 3. Сетка общего не находит — и молчит.

     Ошибкой это сделать нельзя: значений, которых автор не написал, бесконечно
     много, и «среди двух написанных общего нет» пустоты не доказывает. Уронить
     здесь программу значило бы выдать «не нашли» за «нет» — ровно та подмена,
     от которой язык отгораживается. */
  const безСвидетеля = РИСУНОК.split("\n")
    .filter((строка, номер, все) => {
      const шапка = все.slice(0, номер).reverse().find((кандидат) => кандидат.startsWith("  пример"))
      return !(шапка === "  пример «второй»" && строка.startsWith("    "))
    })
    .filter((строка) => строка !== "  пример «второй»")
    .join("\n")

  const { коды, проверено, допущено } = await насетке(безСвидетеля)
  assert.deepEqual(коды, [])
  assert.equal(проверено.some((запись) => запись.intersection !== undefined), false)
  const запись = допущено.find((кандидат) => кандидат.intersection === "Срочные оплаченные")
  assert.notEqual(запись, undefined)
  assert.match(запись.why, /либо множества и правда не пересекаются, либо пример общего значения не написан/u)
})

test("`flang check` о допущении молчит: программа без свидетеля остаётся годной", async () => {
  /* Устройство проверено раньше, а сетка сказать ничего не может — значит и
     диагностики нет ни одной. */
  const безТела = ЗАКАЗЫ
    + "вложение «Срочные среди заказов» из «Срочный» в «Заказ»\n"
    + "вложение «Оплаченные среди заказов» из «Оплаченный» в «Заказ»\n"
    + ПЕРЕСЕЧЕНИЕ
  assert.deepEqual(проверить(безТела).коды, [])
  assert.deepEqual((await насетке(безТела)).коды, [])
})

/* ────────────────────────── слияние модулей ──────────────────────────────── */

const каталоги = []
after(async () => {
  for (const каталог of каталоги) await rm(каталог, { recursive: true, force: true })
})

async function песочница(файлы) {
  const каталог = await mkdtemp(join(tmpdir(), "flang-sets-"))
  каталоги.push(каталог)
  for (const [имя, текст] of Object.entries(файлы)) await writeFile(join(каталог, имя), текст, "utf8")
  return каталог
}

test("общая часть видит вложение из соседнего модуля — но только вывезенное", async () => {
  /* Вложение — объявление того же рода, что морфизм, и через `использует` оно
     переезжает так же: по имени и только если модуль его вывозит. Не слей их —
     и доказательство, которое ловится в одном файле, через импорт исчезало бы
     молча. Вывезти по имени при этом ОБЯЗАТЕЛЬНО, ровно как морфизм: список
     `экспортирует` — это и есть граница видимости, и особого правила у
     отношений множеств нет. */
  const основа = (вывоз) => `модуль «Основа»
экспортирует ${вывоз}

объект «Заказ»
  номер является числом

объект «Срочный»
  номер является числом

объект «Оплаченный»
  номер является числом

вложение «Срочный в Заказ» из «Срочный» в «Заказ»
вложение «Оплаченный в Заказ» из «Оплаченный» в «Заказ»
`
  const главный = `модуль «Круги»
использует «Основа» из "основа.flang"

пересечение «Срочные оплаченные» из «Срочный» и «Оплаченный» в «Заказ»
`
  const проверитьПару = async (вывоз) => {
    const каталог = await песочница({ "основа.flang": основа(вывоз), "главный.flang": главный })
    const путь = join(каталог, "главный.flang")
    const { diagnostics: связывание, ...программа } = await linkProgram(путь, главный, parse)
    assert.deepEqual(связывание, [])
    return (checkTypes(программа).diagnostics ?? []).map((беда) => беда.code)
  }

  assert.deepEqual(
    await проверитьПару('«Заказ», «Срочный», «Оплаченный», «Срочный в Заказ», «Оплаченный в Заказ»'),
    [],
  )
  /* Не вывезли — обе стороны остались без вложения, и отказ говорит именно об
     этом, а не о пропавшем имени. */
  assert.deepEqual(
    await проверитьПару('«Заказ», «Срочный», «Оплаченный»'),
    ["FLANG_MEET_NO_UNIVERSE", "FLANG_MEET_NO_UNIVERSE"],
  )
})

test("столкновение имён при слиянии говорит о вложении в его роде", async () => {
  /* «вложение объявлен в двух модулях» читается как опечатка компилятора, а
     компилятор, который путается в падежах, теряет доверие и там, где он прав.
     До этих двух слов все категорные понятия были мужского рода, и причастие
     стояло в сообщении прямо. */
  const общий = `объект «Заказ»
  номер является числом

объект «Срочный»
  номер является числом

вложение «Срочный в Заказ» из «Срочный» в «Заказ»
`
  const каталог = await песочница({
    "левый.flang": `модуль «Левый»\nэкспортирует «Заказ», «Срочный», «Срочный в Заказ»\n\n${общий}`,
    "правый.flang": `модуль «Правый»\nэкспортирует «Срочный в Заказ»\n\n${общий}`,
    "главный.flang": `модуль «Главный»\nиспользует «Левый» из "левый.flang"\nиспользует «Правый» из "правый.flang"\n`,
  })
  const источник = readFileSync(join(каталог, "главный.flang"), "utf8")
  const { diagnostics } = await linkProgram(join(каталог, "главный.flang"), источник, parse)
  const про = diagnostics.filter((беда) => беда.message.includes("Срочный в Заказ"))
  assert.ok(про.length > 0, `диагностик о вложении нет: ${JSON.stringify(diagnostics)}`)
  assert.match(про[0].message, /вложение «Срочный в Заказ» объявлено в двух модулях/u)
})

