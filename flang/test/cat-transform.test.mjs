/**
 * Естественное преобразование: коммутирующий квадрат.
 *
 * ── Почему это не могло быть сделано раньше ─────────────────────────────────
 * Закон естественности — это РАВЕНСТВО ДВУХ КОМПОЗИЦИЙ: `Г(ф) после альфа_Х` и
 * `альфа_У после Ф(ф)` — две разные стрелки с общими концами. Пока равенства
 * морфизмов в языке не было, сказать «они равны» было нечем, и контракт
 * (`flang/cat/SPEC.md`) держал преобразование в задуманном, а не в сделанном.
 * Равенство появилось (`flang/src/setoid.mjs`), и вместе с ним появился квадрат.
 *
 * ── Чем этот закон отличается от ассоциативности, и это главное ─────────────
 * Ассоциативность на реализованных стрелках сходится ВСЕГДА: композиция
 * вычисляется применением, а применение ассоциативно по построению вычислителя,
 * и обе скобки — одна и та же цепочка вызовов. Квадрат же собран из ЧЕТЫРЁХ
 * написанных автором функций — `Ф(ф)`, `Г(ф)`, `альфа_Х`, `альфа_У`, — и
 * равенство путей есть настоящее утверждение о его коде. Сдвинь любую из
 * четырёх на единицу, и квадрат перестанет коммутировать; тест «единицы забыты
 * ровно один раз» ловит именно такую правку в настоящем файле репозитория.
 *
 * ── Ни одного нового слова ──────────────────────────────────────────────────
 * `морфизм «η» из функтора «Ф» в функтор «Г»` — естественное преобразование ЕСТЬ
 * морфизм в категории функторов, и других прочтений у записи нет. Из таблицы
 * лексера прибавилась одна форма — родительный падеж `функтора` рядом с
 * `функтор`, как `поля` рядом с `поле`; занятость мерена
 * `flang/scripts/word-occupancy.mjs`: голым именем ноль.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { parse } from "../src/parser.mjs"
import { formatProofLedger, proofLedger } from "./vedomost.mjs"
import { checkCategoryLaws } from "../src/setoid.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const ПРИМЕР = "flang/examples/cat/natural-square.flang"
const исходник = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

function разобрать(текст) {
  return parse(текст, ПРИМЕР)
}

function типы(текст) {
  const итог = checkTypes(разобрать(текст))
  return {
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

function законы(текст) {
  const итог = checkCategoryLaws(разобрать(текст))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    checked: итог.checked,
    assumed: итог.assumed,
  }
}

/** Замена в исходнике примера, которая обязана найтись: иначе тест не о том. */
function правка(было, стало) {
  const текст = исходник.replace(было, стало)
  assert.notEqual(текст, исходник, `место правки не найдено: ${было}`)
  return текст
}

/* ─────────────────────────────── форма ───────────────────────────────────── */

test("преобразование попадает в AST своим ключом", () => {
  const программа = разобрать(исходник)
  assert.deepEqual(программа.transformations, [
    {
      kind: "transformation",
      name: "в копейки",
      from: "В рублях",
      to: "В копейках",
      components: [
        { object: "Заявка", morphism: "заявку в копейки" },
        { object: "Счёт", morphism: "счёт в копейки" },
      ],
      span: программа.transformations[0].span,
    },
  ])
})

test("ОБЫЧНАЯ СТРЕЛКА НЕ ЗАДЕТА: ключа `transformations` у неё не появляется", () => {
  /* То же обещание, каким `categories` не появился у заголовка документа FTS:
     программа, написанная вчера, обязана дать побайтово прежний AST. */
  const программа = разобрать(правка(
    `морфизм «в копейки» из функтора «В рублях» в функтор «В копейках»
  объект «Заявка» отображается в морфизм «заявку в копейки»
  объект «Счёт» отображается в морфизм «счёт в копейки»
`,
    "",
  ))
  assert.equal(программа.transformations, undefined)
  assert.ok(программа.morphisms.length > 0, "стрелки при этом на месте")
})

test("преобразование без единой компоненты отвергается разбором", () => {
  /* Тот же довод, по которому отвергается закон без примеров: объявление,
     которое ничего не обещает, читается как гарантия. */
  assert.throws(
    () => разобрать(правка(
      `  объект «Заявка» отображается в морфизм «заявку в копейки»
  объект «Счёт» отображается в морфизм «счёт в копейки»
`,
      "",
    )),
    /требует хотя бы одной компоненты/u,
  )
})

/* ─────────────── устройство: ДОКАЗЫВАЕТСЯ сличением объявлений ───────────── */

test("настоящий файл репозитория проверку типов проходит", () => {
  assert.deepEqual(типы(исходник).коды, [])
})

test("преобразование между необъявленными функторами отвергается", () => {
  const итог = типы(правка("из функтора «В рублях» в функтор «В копейках»", "из функтора «Нет» в функтор «Тоже нет»"))
  assert.deepEqual(итог.коды, ["FLANG_UNKNOWN_NAME", "FLANG_UNKNOWN_NAME"])
  assert.match(итог.тексты.join("\n"), /исходный функтор «Нет» не объявлен/u)
  assert.match(итог.тексты.join("\n"), /целевой функтор «Тоже нет» не объявлен/u)
})

test("функторы обязаны быть параллельны: разные концы — не преобразование", () => {
  /* Второй функтор ведёт в «Схему», а не в «Учёт»: компонента `альфа_Х` тогда
     ведёт из объекта одной категории в объект другой, и концов у неё нет. */
  const косой = `
функтор «Обратно» из «Схема» в «Схема»
  объект «Заявка» отображается в «Заявка»
  объект «Счёт» отображается в «Счёт»
  морфизм «выставить» отображается в морфизм «выставить»
`
  const итог = типы(правка(
    "морфизм «в копейки» из функтора «В рублях» в функтор «В копейках»",
    `${косой}\nморфизм «в копейки» из функтора «В рублях» в функтор «Обратно»`,
  ))
  assert.deepEqual(итог.коды, ["FLANG_TRANSFORM_SHAPE"])
  assert.match(итог.тексты.join("\n"), /только между функторами с одними и теми же концами/u)
})

test("компонента обязана вести из образа первого функтора в образ второго", () => {
  const итог = типы(правка(
    "объект «Заявка» отображается в морфизм «заявку в копейки»",
    "объект «Заявка» отображается в морфизм «счёт в копейки»",
  ))
  assert.deepEqual(итог.коды, ["FLANG_TRANSFORM_COMPONENT"])
  assert.match(
    итог.тексты.join("\n"),
    /обязана вести из «Заявка в рублях» в «Заявка в копейках», а «счёт в копейки» ведёт из «Счёт в рублях»/u,
  )
})

test("компонента есть у КАЖДОГО отображённого объекта", () => {
  const итог = типы(правка("  объект «Счёт» отображается в морфизм «счёт в копейки»\n", ""))
  assert.deepEqual(итог.коды, ["FLANG_TRANSFORM_NOT_TOTAL"])
  assert.match(итог.тексты.join("\n"), /не действует на объекте «Счёт»/u)
})

test("две компоненты на одном объекте — две стрелки в одной точке квадрата", () => {
  const итог = типы(правка(
    "  объект «Счёт» отображается в морфизм «счёт в копейки»\n",
    "  объект «Счёт» отображается в морфизм «счёт в копейки»\n  объект «Счёт» отображается в морфизм «счёт в копейки»\n",
  ))
  assert.deepEqual(итог.коды, ["FLANG_TRANSFORM_COMPONENT"])
  assert.match(итог.тексты.join("\n"), /две компоненты/u)
})

test("компонента, названная несуществующим морфизмом, отвергается", () => {
  /* И ровно одна диагностика: отвергнутая компонента не даёт второй — «а у
     этого объекта компоненты нет», — иначе автор чинил бы одну беду по двум
     сообщениям. */
  const итог = типы(правка("отображается в морфизм «заявку в копейки»", "отображается в морфизм «нет такого»"))
  assert.deepEqual(итог.коды, ["FLANG_UNKNOWN_NAME"])
  assert.match(итог.тексты.join("\n"), /но такого морфизма нет/u)
})

/* ───────────────── закон естественности: ПРОВЕРЯЕТСЯ на сетке ─────────────── */

test("квадрат настоящего файла коммутирует, и число квадратов уезжает в отчёт", () => {
  const итог = законы(исходник)
  assert.deepEqual(итог.коды, [], итог.тексты.join("\n"))
  const строка = итог.checked.find((запись) => запись.transformation === "в копейки")
  assert.ok(строка !== undefined, "преобразование в отчёт не попало вовсе")
  assert.ok(строка.values > 0, "сетка пуста — проверять было не на чем")
  assert.equal(строка.squares, 1)
  assert.deepEqual(итог.assumed, [])
})

test("ЗАКОН КРАСНЕЕТ НА ЧЕСТНОЙ ПРОГРАММЕ: единицы забыты ровно один раз", () => {
  /* Вот ради чего всё и делалось. «Наценка в копейках» прибавляет 100 вместо
     1000 — то есть рубль вместо десяти, — и ни один другой закон дерева этого
     не видит: функция тотальна, типы сходятся, её собственный пример можно
     подогнать. Ловит это только квадрат, и ловит контрпримером. */
  const сломано = правка(
    "запись «Счёт в копейках» с копейки равным (заявка.копейки плюс 1000)",
    "запись «Счёт в копейках» с копейки равным (заявка.копейки плюс 100)",
  ).replace("ожидается запись «Счёт в копейках» с копейки равным 11000",
    "ожидается запись «Счёт в копейках» с копейки равным 10100")
  const итог = законы(сломано)
  assert.deepEqual(итог.коды, ["FLANG_TRANSFORM_NOT_NATURAL"])
  assert.match(итог.тексты.join("\n"), /квадрат не коммутирует на морфизме «выставить»/u)
  /* Контрпример предъявлен, а не спрятан за вердиктом: без значений искать его
     пришлось бы руками, а именно значения и есть вся находка. */
  assert.match(итог.тексты.join("\n"), /\{"копейки":\d+\}/u)
})

test("категория кодомена без своего равенства — квадрат сравнить нечем", () => {
  const без = правка(
    `  объект «Заявка в рублях» даёт «Заявки в рублях равны»
  объект «Счёт в рублях» даёт «Счета в рублях равны»
  объект «Заявка в копейках» даёт «Заявки в копейках равны»
  объект «Счёт в копейках» даёт «Счета в копейках равны»
`,
    "",
  )
  const итог = законы(без)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked.some((запись) => запись.transformation !== undefined), false)
  const строка = итог.assumed.find((запись) => запись.transformation === "в копейки")
  assert.ok(строка !== undefined, "молчание о непроверенном читается как проверенное")
  assert.match(строка.why, /своего равенства не объявила/u)
})

test("нереализованная стрелка квадрата уводит преобразование в «на веру», а не в отказ", () => {
  /* Та же граница, по которой изоморфизм без `даёт` уходит в допущение:
     объявлять то, чего ещё нет, законно и полезно. */
  const без = правка("морфизм «счёт в копейки» из «Счёт в рублях» в «Счёт в копейках»\n  даёт «Счёт в копейки»",
    "морфизм «счёт в копейки» из «Счёт в рублях» в «Счёт в копейках»")
  const итог = законы(без)
  assert.deepEqual(итог.коды.filter((код) => код.startsWith("FLANG_TRANSFORM")), [])
  assert.ok(итог.assumed.some((запись) => запись.transformation === "в копейки"))
})

/* ──────────────────────────────── ведомость ──────────────────────────────── */

test("ведомость называет квадрат сеткой и словами «Это не доказательство»", () => {
  const программа = разобрать(исходник)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    category: checkCategoryLaws(программа),
  })
  const строка = ведомость.laws.find((закон) => закон.kind === "преобразование")
  assert.ok(строка !== undefined, "квадрата в ведомости нет вовсе")
  assert.equal(строка.name, "в копейки")
  assert.equal(строка.verdict, "grid")
  assert.match(строка.says, /квадрат коммутирует/u)
  assert.match(строка.says, /Это не доказательство/u)
  assert.match(formatProofLedger(ведомость), /преобразование «в копейки» — сетка/u)
})
