/**
 * Страница сайта «Что изменилось» обязана совпадать с историей репозитория.
 *
 * `docs/site/changelog.md` и `docs/site/changelog.json` печатаются из git
 * (`scripts/build-changelog-page.mjs`), и этот тест — вся причина, по которой печать
 * имеет смысл. Приём тот же, что у `flang/test/changelog.test.mjs` для
 * `CHANGELOG.md` и у `flang/test/stdlib-index.test.mjs` для указателя
 * библиотеки: напечатанное сверяется с тем, из чего печаталось.
 *
 * ── ПОЧЕМУ ПРОВЕРОК ВОСЕМЬ, А НЕ ОДНА ───────────────────────────────────────
 *
 * Полная сверка требует всей истории, а `actions/checkout` без `fetch-depth`
 * кладёт одну ревизию. В таком клоне сверять не с чем — но это не повод стать
 * зелёным ни о чём: шесть проверок из восьми git не требуют вовсе.
 *
 *   1. ПОЛНАЯ СВЕРКА (нужен git). Печатаем страницу заново от той же головы,
 *      что записана в снимке, и сверяем побайтово. Ловит подделку любого поля:
 *      заголовка вливания, хеша, даты, числа.
 *   2. СТАРЕНИЕ (нужен git). В ствол приехало слияние, которого страница не
 *      знает, — красный. Это НЕ придирка: страница заведена ровно затем, чтобы
 *      показывать движение, и страница про движение, молчащая про движение,
 *      хуже, чем её отсутствие. Прямой коммит в ствол страницу не старит —
 *      сам коммит с перепечаткой был бы таким, и проверка вечно требовала бы
 *      печатать журнал коммитом, который в него не попал.
 *   3. MARKDOWN ИЗ ТОГО ЖЕ СНИМКА (без git). Два файла обязаны быть двумя
 *      видами одной структуры. Краснеет на правке страницы руками — в любом
 *      клоне.
 *   4. РАЗБИЕНИЕ БЕЗ ОСТАТКА (без git). Сумма приехавших по всем шагам ствола
 *      обязана совпасть с числом коммитов в истории. Раскладка, теряющая
 *      работу, теряла бы её МОЛЧА: страница выглядела бы так же.
 *   5. ШАПКА ЖУРНАЛА (без git). Комментарий `<!-- … -->` из `CHANGELOG.md` не
 *      обязан доезжать до читателя экранированным текстом.
 *   6. ДВОЕТОЧИЕ И СПИСОК (без git). Обещание списка без списка. Случая на
 *      сегодняшней истории нет, поэтому снимок для него собран в самой
 *      проверке.
 *   7. ЧИСЛО В ЭТОЙ ШАПКЕ (без git). Оно сверяется с числом `test(` в файле:
 *      «ПРОВЕРОК ПЯТЬ» над шестью, а потом «ШЕСТЬ» над семью — это писалось
 *      здесь дважды за один день. Файл, заведённый стеречь чужие числа, своё
 *      обязан стеречь тем более.
 *   8. СТРАНИЦА ВПИСАНА В САЙТ (без git). Заведённая, но не вписанная в карту
 *      страница до читателя не доедет, а сборка о ней не узнает: она собирает
 *      то, что в карте.
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { РАЗДЕЛЫ } from "../../docs/site/sitemap.mjs"
import { разобрать } from "../../docs/site/markdown.mjs"
import {
  ИЗМЕРИТЕЛИ,
  ПУТЬ_JSON,
  ПУТЬ_MD,
  печатьMarkdown,
  историяПолна as полнаЛиИстория,
  собратьСводку,
  сериализовать,
} from "../../scripts/build-changelog-page.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))
const записанныйMd = readFileSync(ПУТЬ_MD, "utf8")
const записанныйJson = readFileSync(ПУТЬ_JSON, "utf8")
const снимок = JSON.parse(записанныйJson)

const гит = (доводы) =>
  execFileSync("git", доводы, { cwd: КОРЕНЬ, encoding: "utf8", maxBuffer: 1 << 30 }).trim()

/*
 * Вся ли история под рукой. Вопрос задаётся ТЕМ ЖЕ кодом, которым его задаёт
 * сверка `node scripts/build-changelog-page.mjs --check`: два ответа на один вопрос
 * разошлись бы, и тогда сторож и сверка спорили бы о том, что считать бедой.
 * Неполный клон — не отставшая страница: обвинять файл в том, что до него не
 * доехала история, значило бы красить тест за чужую беду. Та же оговорка и по
 * той же причине стоит в `changelog.test.mjs`.
 */
const историяПолна = () => полнаЛиИстория(снимок)

test("страница «Что изменилось» совпадает с историей репозитория", (t) => {
  const история = историяПолна()
  if (!история.полна) {
    t.diagnostic(`полная сверка пропущена: ${история.причина}`)
    t.diagnostic("в CI это чинится fetch-depth: 0 у actions/checkout")
    return
  }

  const свежая = собратьСводку(снимок.голова)
  assert.equal(
    записанныйJson,
    сериализовать(свежая),
    "docs/site/changelog.json разошёлся с историей — перепечатайте: node scripts/build-changelog-page.mjs",
  )
  assert.equal(
    записанныйMd,
    печатьMarkdown(свежая),
    "docs/site/changelog.md разошёлся с историей — перепечатайте: node scripts/build-changelog-page.mjs",
  )
})

test("страница знает про каждое вливание, доехавшее до ствола", (t) => {
  const история = историяПолна()
  if (!история.полна) {
    t.diagnostic(`сверка старения пропущена: ${история.причина}`)
    return
  }

  /* Список слияний берётся ВЫБОРКОЙ ПО ДЕРЕВУ, а не перечнем в теле проверки:
     перечень, набранный руками, зеленел бы после того, как дерево ушло вперёд
     (docs/zettel/spisok-rukami-perezhivaet-derevo.md). */
  const пропущенные = гит([
    "log",
    "--first-parent",
    "--merges",
    "--format=%h %s",
    `${снимок.голова}..HEAD`,
  ])
  assert.equal(
    пропущенные,
    "",
    "в ствол приехали вливания, о которых страница молчит:\n" +
      пропущенные +
      "\nПерепечатайте: node scripts/build-changelog-page.mjs",
  )
})

test("markdown страницы напечатан из того же снимка, что json", () => {
  /* Без git: два файла обязаны быть двумя видами одной структуры. Краснеет на
     правке страницы руками — и краснеет в любом клоне. */
  assert.equal(
    записанныйMd,
    печатьMarkdown(снимок),
    "docs/site/changelog.md не совпадает с печатью из changelog.json — страницу правили руками",
  )
})

test("раскладка коммитов по стволу не теряет ни одного коммита", () => {
  /* Цепь первого родителя разбивает историю БЕЗ ОСТАТКА: каждый достижимый
     коммит приехал ровно одним шагом ствола. Проверяется суммой, а не на глаз:
     потерянная ветка выглядела бы на странице ровно так же, как её отсутствие
     в истории, — то есть никак. */
  const приехало = снимок.вливания.reduce((н, в) => н + в.приехало, 0)
  const прямых = снимок.прямые.reduce((н, п) => н + п.записи.length + п.скрыто, 0)
  assert.equal(
    приехало + прямых,
    снимок.всегоКоммитов,
    `по шагам ствола разложено ${приехало + прямых} коммитов, а в истории ${снимок.всегоКоммитов}`,
  )

  assert.equal(
    снимок.вливания.length + прямых,
    снимок.шаговСтвола,
    "шагов ствола не столько, сколько вливаний и прямых коммитов вместе",
  )

  assert.ok(снимок.вливания.length > 0, "в снимке нет ни одного вливания — так не бывает")
  for (const в of снимок.вливания) {
    assert.match(в.дата, /^\d{4}-\d{2}-\d{2}$/u, `дата вливания не разобрана: ${в.дата}`)
    assert.match(в.коммит, /^[0-9a-f]{7,}$/u, `хеш вливания не разобран: ${в.коммит}`)
    assert.ok(в.заголовок.length > 0, `у вливания ${в.коммит} нет заголовка`)
    assert.ok(в.приехало >= 1, `вливание ${в.коммит} не принесло ни одного коммита — так не бывает`)
    for (const и of ИЗМЕРИТЕЛИ) {
      assert.equal(
        typeof в.числа[и.ключ],
        "number",
        `у вливания ${в.коммит} нет числа «${и.имя}» — измеритель завели, а снимок не перепечатали`,
      )
    }
  }
})

test("шапка журнала не доезжает до читателя комментарием", () => {
  /* `CHANGELOG.md` начинается с комментария `<!-- … -->` — «файл печатается,
     править руками бессмысленно». Это записка тому, кто правит дерево, а не
     читателю сайта. HTML внутри markdown здесь намеренно не поддержан, и без
     уборки комментарий доезжал бы до страницы экранированным текстом первым же
     абзацем. Проверяется не отсутствие строки в исходнике, а РАЗБОР: в
     исходнике комментарий обязан остаться. */
  const исходник = readFileSync(new URL("../../CHANGELOG.md", import.meta.url), "utf8")
  assert.match(исходник, /<!--/u, "в шапке CHANGELOG.md больше нет комментария — проверять нечего")

  const { html } = разобрать(исходник)
  assert.ok(!html.includes("&lt;!--"), "комментарий шапки доехал до страницы экранированным текстом")
  assert.ok(
    !html.includes("Править его руками бессмысленно"),
    "текст комментария виден на странице журнала",
  )
  assert.match(html, /Журнал изменений flang/u, "страница журнала разобралась пустой")
})

test("двоеточие ставится только там, где за ним идёт список", () => {
  /* День, у которого ВСЕ прямые коммиты скрыты правилом видимости, печатал
     «Приехало прямо в ствол, мимо ветки:» и не давал за двоеточием ничего:
     обещание списка без списка. На сегодняшней истории такого дня уже нет —
     значит проверять его на ней нечем, и снимок для этого случая собирается
     здесь, а не выискивается в дереве. Иначе правка держалась бы на том, что
     история случайно перестала её задевать. */
  const снимокСоСкрытыми = {
    ...снимок,
    дни: ["2026-08-17"],
    вливания: [],
    прямые: [{ дата: "2026-08-17", записи: [], скрыто: 1 }],
  }
  const текст = печатьMarkdown(снимокСоСкрытыми)
  assert.ok(
    !текст.includes("мимо ветки:"),
    "двоеточие обещало список, а за ним ничего: все прямые коммиты дня скрыты",
  )
  assert.match(
    текст,
    /Прямо в ствол, мимо ветки, приехала 1 правка, языка снаружи не меняющая\./u,
    "скрытые прямые коммиты дня не названы вовсе — день выглядит пустым",
  )

  /* Обратный случай: когда список есть, двоеточие обязано стоять. Проверка без
     него зеленела бы на печати, которая вообще перестала печатать прямые
     коммиты. */
  const снимокСоСписком = {
    ...снимок,
    дни: ["2026-08-17"],
    вливания: [],
    прямые: [{ дата: "2026-08-17", записи: [{ текст: "Проба", коммит: "abc1234" }], скрыто: 0 }],
  }
  assert.match(печатьMarkdown(снимокСоСписком), /мимо ветки:\n\n- Проба \(`abc1234`\)/u)
})

test("число проверок в шапке этого файла сверено с самим файлом", () => {
  /* За один день здесь дважды написали устаревшее число: «ПРОВЕРОК ПЯТЬ» над
     шестью, потом «ШЕСТЬ» над семью. Проза не исполняется и потому не ломается
     — ровно тот довод, ради которого в этом дереве заведён сторож чисел
     (flang/scripts/count-guard.mjs). Он .md-файлы читает, а .mjs — нет, и
     число в шапке проверки жило вне всякого измерителя. Теперь измеритель у
     него есть, и это сам файл. */
  const свой = readFileSync(new URL("./changelog-page.test.mjs", import.meta.url), "utf8")
  const СЛОВА = new Map([
    ["ОДНА", 1], ["ДВЕ", 2], ["ТРИ", 3], ["ЧЕТЫРЕ", 4], ["ПЯТЬ", 5],
    ["ШЕСТЬ", 6], ["СЕМЬ", 7], ["ВОСЕМЬ", 8], ["ДЕВЯТЬ", 9], ["ДЕСЯТЬ", 10],
  ])
  const шапка = /ПОЧЕМУ ПРОВЕРОК ([А-ЯЁ]+), А НЕ ОДНА/u.exec(свой)
  assert.ok(шапка, "в шапке файла больше нет строки «ПОЧЕМУ ПРОВЕРОК …» — сверять нечего")
  const сказано = СЛОВА.get(шапка[1])
  assert.ok(сказано, `слово «${шапка[1]}» не из словаря счёта`)

  /* Считаются вызовы `test(` в начале строки: так их пишет весь этот файл, и
     так их не спутать со словом «test» внутри прозы. */
  const измерено = (свой.match(/^test\(/gmu) ?? []).length
  assert.equal(
    сказано,
    измерено,
    `шапка обещает ${сказано} проверок, а в файле их ${измерено}: правьте шапку, а не сторожа`,
  )

  const пункты = (свой.match(/^ \*   \d+\. /gmu) ?? []).length
  assert.equal(пункты, измерено, `в шапке перечислено ${пункты} проверок из ${измерено}`)
})

test("страница вписана в карту сайта", () => {
  /* Карта берётся из того же места, откуда её берёт сборка. Заметить, что
     страница напечатана и никуда не вписана, иначе нечем: сборка собирает
     только то, что в карте, и о лишнем файле не узнает. */
  const адреса = РАЗДЕЛЫ.flatMap((р) => р.страницы.map((с) => с.из))
  assert.ok(
    адреса.includes("docs/site/changelog.md"),
    "docs/site/changelog.md не вписан в docs/site/sitemap.mjs — страница напечатана, а на сайт не попадёт",
  )
  assert.ok(
    адреса.includes("CHANGELOG.md"),
    "CHANGELOG.md не вписан в docs/site/sitemap.mjs — журнал печатается, а на сайте его нет",
  )
})
