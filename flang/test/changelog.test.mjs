/**
 * Журнал изменений обязан совпадать с историей репозитория.
 *
 * CHANGELOG.md и changelog.json печатаются из тегов и коммитов
 * (scripts/build-changelog.mjs), и этот тест — вся причина, по которой печать
 * имеет смысл. Написанный руками журнал разошёлся бы с языком при первом же
 * релизе, и разошёлся бы молча: текст не исполняется, значит не ломается. За
 * один день в этом репозитории такое случилось шесть раз — с каталогом
 * недостач, с шапками модулей, с комментариями про бэкенды. Тот же приём, что
 * у указателя библиотеки (flang/test/stdlib-index.test.mjs).
 *
 * ПОЧЕМУ ПРОВЕРОК ТРИ, А НЕ ОДНА. Полная сверка с git требует всей истории и
 * всех тегов, а `actions/checkout` без `fetch-depth` кладёт одну ревизию и ни
 * одного тега. В таком клоне сверять журнал не с чем — но это не повод стать
 * зелёным ни о чём: две проверки из трёх git не требуют вовсе и работают
 * всегда. Полная сверка ловит «вышел релиз, журнал не перепечатан»; сверка
 * Markdown с JSON ловит правку журнала руками; сверка с package.json ловит
 * поднятую версию, о которой журнал не знает.
 *
 * fetch-depth: 0 в .github/workflows/ci.yml поставлен ровно затем, чтобы в CI
 * работала и первая.
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import {
  ПУТЬ_JSON,
  ПУТЬ_MD,
  печатьMarkdown,
  собратьЖурнал,
  сериализовать,
  читатьРепозиторий,
  читатьТеги,
} from "../../scripts/build-changelog.mjs"

const записанныйMd = readFileSync(ПУТЬ_MD, "utf8")
const записанныйJson = readFileSync(ПУТЬ_JSON, "utf8")
const журналИзФайла = JSON.parse(записанныйJson)
const пакет = JSON.parse(
  readFileSync(fileURLToPath(new URL("../../package.json", import.meta.url)), "utf8"),
)

/**
 * Вся ли история под рукой. Тегов МЕНЬШЕ, чем релизов в записанном журнале, —
 * это неполный клон, а не отставший журнал: обвинять файл в том, что до него
 * не доехали теги, значило бы красить тест в красный за чужую беду. Тегов
 * столько же или больше — сверять есть с чем, и расхождение уже настоящее.
 */
function историяПолна() {
  try {
    const теги = читатьТеги()
    if (теги.length < журналИзФайла.releases.length) {
      return { полна: false, причина: `тегов видно ${теги.length}, а релизов в журнале ${журналИзФайла.releases.length}` }
    }
    return { полна: true, причина: null }
  } catch (беда) {
    return { полна: false, причина: `git не отвечает: ${беда.message}` }
  }
}

test("журнал изменений совпадает с историей репозитория", (t) => {
  const история = историяПолна()
  if (!история.полна) {
    t.diagnostic(`полная сверка пропущена: ${история.причина}`)
    t.diagnostic("в CI это чинится fetch-depth: 0 у actions/checkout")
    return
  }

  const свежий = собратьЖурнал(читатьРепозиторий())
  assert.deepEqual(
    свежий.unclassified,
    [],
    "правило видимости не знает этих путей — допишите их в ВИДИМОСТЬ (scripts/build-changelog.mjs), " +
      "иначе правка, меняющая язык, молча не доедет до журнала",
  )
  assert.equal(
    записанныйJson,
    сериализовать(свежий),
    "changelog.json разошёлся с историей — перепечатайте: node scripts/build-changelog.mjs",
  )
  assert.equal(
    записанныйMd,
    печатьMarkdown(свежий),
    "CHANGELOG.md разошёлся с историей — перепечатайте: node scripts/build-changelog.mjs",
  )
})

test("CHANGELOG.md напечатан из того же снимка, что changelog.json", () => {
  /* Проверка без git: два файла обязаны быть двумя видами одной структуры.
     Она краснеет на правке журнала руками — и краснеет в любом клоне. */
  assert.equal(
    записанныйMd,
    печатьMarkdown(журналИзФайла),
    "CHANGELOG.md не совпадает с печатью из changelog.json — журнал правили руками",
  )
})

test("журнал знает версию, объявленную в package.json", () => {
  /* Тоже без git. Релиз, о котором журнал не знает, — это и есть «журнал
     отстал», и это единственное, что видно в клоне глубиной в одну ревизию. */
  assert.equal(
    журналИзФайла.latest,
    пакет.version,
    `package.json объявляет ${пакет.version}, а последний релиз журнала — ${журналИзФайла.latest}: ` +
      "поставьте тег и перепечатайте журнал (node scripts/build-changelog.mjs)",
  )
  assert.equal(журналИзФайла.declared, пакет.version, "поле declared в журнале отстало от package.json")
})

test("правила разбора проверены на выдуманной истории", () => {
  /* Самопроверка сборщика гоняется отдельным процессом, а не импортом: она
     заканчивается process.exit(1) на первом же расхождении, и импорт уронил бы
     весь прогон тестов без имени виноватого. Проверяются на ней те правила,
     которые на настоящей истории не встречаются: пометка «Пользователю: …»,
     легковесный тег, порядок 0.4.10 после 0.4.2, русский счёт правок. */
  const вывод = execFileSync(
    process.execPath,
    [fileURLToPath(new URL("../../scripts/build-changelog.mjs", import.meta.url)), "--self-test"],
    { encoding: "utf8" },
  )
  assert.match(вывод, /self-test ок/u)
})

test("в журнале каждый релиз назван версией, датой и хотя бы одной записью", () => {
  assert.ok(журналИзФайла.releases.length > 0, "в журнале нет ни одного релиза")
  for (const релиз of журналИзФайла.releases) {
    assert.match(релиз.version, /^\d+\.\d+\.\d+/u, `версия релиза не разобрана: ${релиз.version}`)
    assert.match(релиз.date, /^\d{4}-\d{2}-\d{2}$/u, `дата релиза ${релиз.version} не разобрана: ${релиз.date}`)
    assert.ok(релиз.human, `у релиза ${релиз.version} нет человеческой даты`)
    assert.ok(
      релиз.entries.length + релиз.hidden > 0,
      `релиз ${релиз.version} не содержит ни одного коммита — так не бывает`,
    )
  }
})
