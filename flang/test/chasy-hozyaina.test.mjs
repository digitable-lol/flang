/**
 * Часы хозяина обязаны идти в миллисекундах, а не в секундах.
 *
 * ── Улика, с которой начата правка ──────────────────────────────────────────
 *
 * У хозяина на C поручение «Текущее время» отвечало `time(NULL) * 1000.0`. Пять
 * замеров подряд дали 1787191329000 все пять, при настоящем времени
 * 1787191329259: точность — СЕКУНДА, а последние три цифры всегда нули.
 *
 * Молчаливость этой беды и делает её опасной. Отклик приходит, тип верный,
 * программа работает — и меряет время с шагом в тысячу миллисекунд. Узел
 * распределённой системы шлёт признак жизни раз в 200 мс и рвёт связь после
 * 1000 мс молчания: на таких часах «прошло 200 мс» неотличимо от «не прошло
 * нисколько», а срок перестаёт быть числом.
 *
 * ── Почему проверка меряет, а не читает исходник ────────────────────────────
 *
 * Прочитать в `flang_conc.c` слово `clock_gettime` было бы дешевле и не значило
 * бы ничего: вызов может стоять и отвечать секундами (так и было — `time`
 * тоже «часы»). Поэтому здесь напечатанная программа СПРАШИВАЕТ время дважды и
 * сверяется с часами этой машины.
 *
 * Запуск: node --test flang/test/chasy-hozyaina.test.mjs
 */
import assert from "node:assert/strict"
import { execFileSync, spawnSync } from "node:child_process"
import { rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { findExecutable } from "../src/toolchain.mjs"
import { missingToolchain } from "./toolchain-guard.mjs"
import { рабочийКаталог, средаСборки } from "./tempdir.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const cc = findExecutable("cc") ?? findExecutable("gcc")

/* Служба, которая спрашивает время и складывает отметку в состояние. Пишется
   здесь, а не берётся из дерева: программа существует ради одного замера, и
   держать её в примерах языка не за что. */
const ПРОГРАММА = `модуль «Который час»

объект «Часы»
  «когда»: число

объект «Пусто»
  «сколько»: число

тип «Просьба»
  вариант «спроси»

объект «Отклик службы»
  «состояние»: «Часы»
  «действия»: список «Действие»

объект «Отклик почты»
  «состояние»: «Пусто»
  «действия»: список «Действие»

процесс «Служба»
  состояние «Часы»
  начинает с «ноль»
  принимает «Просьба»
  обрабатывает «шаг службы»

процесс «Почта»
  состояние «Пусто»
  начинает с «пусто»
  принимает «Отклик»
  обрабатывает «шаг почты»

тотальная функция «ноль»
  возвращает «Часы»
  запись «Часы» с «когда» равным 0

тотальная функция «пусто»
  возвращает «Пусто»
  запись «Пусто» с «сколько» равным 0

тотальная функция «шаг службы»
  принимает текущее: «Часы», просьба: «Просьба»
  возвращает «Отклик службы»
  разбор просьба
    случай вариант «спроси»
      то (запись «Отклик службы» с «состояние» равным текущее и «действия» равным [(вариант «поручить» с «кому» равным "Почта" и «поручение» равным (вариант «Текущее время»))])

тотальная функция «шаг почты»
  принимает принесено: «Пусто», отклик: «Отклик»
  возвращает «Отклик почты»
  запись «Отклик почты» с «состояние» равным (запись «Пусто» с «сколько» равным ((принесено.«сколько») плюс 1)) и «действия» равным []

прогон «спросить время»
  семя от 1 до 1
  дано «Служба» принимает (вариант «спроси»)
  ожидается «Почта» равен (запись «Пусто» с «сколько» равным 1)
`

test("часы хозяина на C идут в миллисекундах и сходятся с часами машины", async (t) => {
  if (cc === null) return missingToolchain(t, "c", "компилятора C нет — пропуск")
  const каталог = рабочийКаталог("chasy")
  try {
    const исходник = join(каталог, "chasy.flang")
    writeFileSync(исходник, ПРОГРАММА, "utf8")
    const печать = spawnSync(process.execPath, [join(корень, "flang/bin/flang.mjs"), "emit", исходник, "--target", "c", "--out", каталог], {
      cwd: корень, encoding: "utf8", env: { ...process.env, LC_ALL: "C.UTF-8" }, maxBuffer: 256 * 1024 * 1024,
    })
    assert.equal(печать.status, 0, `печать отказала:\n${печать.stdout}\n${печать.stderr}`)
    /* Имена файлов берутся из вывода печати, а не переписываются сюда: имя
       модуля переводится в латиницу правилом, живущим в печати. */
    const напечатано = JSON.parse(печать.stdout).files.map((это) => это.path).filter((это) => это.endsWith(".c"))
    assert.ok(напечатано.length >= 2, `печать отдала ${напечатано.length} файлов .c`)
    execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", ...напечатано, "-o", "cli", "-lm", "-lpthread"], {
      cwd: каталог, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"],
    })

    const спросить = () => {
      const ответ = JSON.parse(execFileSync(join(каталог, "cli"), {
        cwd: каталог, input: `${JSON.stringify({ run: "спросить время", seed: "1", host: "1" })}\n`,
        encoding: "utf8", maxBuffer: 64 * 1024 * 1024,
      }).trim())
      assert.equal(ответ.ok, true, `прогон отказал: ${JSON.stringify(ответ)}`)
      const письмо = ответ.журнал.find((з) => з.сообщение?.v === "Отметка времени")
      assert.notEqual(письмо, undefined, "хозяин не принёс «Отметку времени»")
      return Number(письмо.сообщение.f.find(([поле]) => поле === "миллисекунды")[1].n)
    }

    const до = Date.now()
    const первый = спросить()
    const второй = спросить()
    const после = Date.now()

    /* ПЕРВОЕ: отметка попадает в промежуток по часам этой машины. Ловит и
       эпоху не ту, и единицы не те. */
    assert.ok(первый >= до - 1000 && первый <= после + 1000,
      `отметка ${первый} вне промежутка [${до}, ${после}] — это не миллисекунды текущей эпохи`)

    /* ВТОРОЕ, и ради него всё писалось: два замера подряд НЕ обязаны различаться
       (могут попасть в одну миллисекунду), но обязаны не быть кратными тысяче
       оба сразу. Секундные часы дают ...000 всегда; шанс, что две настоящие
       отметки подряд обе лягут ровно на миллисекунду, кратную 1000, — один на
       миллион. */
    assert.ok(первый % 1000 !== 0 || второй % 1000 !== 0,
      `обе отметки кратны тысяче (${первый}, ${второй}) — часы идут с шагом в секунду, а не в миллисекунду`)

    /* ТРЕТЬЕ: отметка — целое. Хозяин на Node отдаёт `Date.now()`, а два хозяина
       одного языка обязаны отвечать на одно поручение значением одного вида. */
    assert.ok(Number.isInteger(первый) && Number.isInteger(второй),
      `отметка не целая (${первый}, ${второй}) — у хозяина на Node она целая`)

    console.log(`часы хозяина на C: ${первый}, ${второй}; часы машины ${до}…${после}`)
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
})
