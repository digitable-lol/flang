/**
 * Сторож утверждений о недостаче в комментариях и прозе — и проверка САМОГО
 * сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/claim-guard.mjs`. Здесь три
 * разных обязательства, и путать их нельзя:
 *
 *   1. на дереве сторож ЧИСТ — ни одна проза не отрицает формы, которую язык
 *      знает;
 *   2. сторож ЛОВИТ — на подложенных случаях, по одному на каждый вид;
 *   3. сторож МОЛЧИТ там, где обязан молчать — на надгробиях снятых утверждений
 *      и на фразах не о языке.
 *
 * Второе и третье написаны потому, что проверка, которая не может упасть,
 * выглядит ровно как проверка, у которой всё хорошо. Ровно этим дефектом
 * страдали гейты `digitwm` и `blender-mcp`, где цитата строки SPDX в шапке
 * удовлетворяла проверку на наличие SPDX.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { mkdtemp, rm, writeFile, mkdir } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"
import {
  КОРЕНЬ,
  УЗКИЕ,
  кускиПрозы,
  лексерЗнает,
  отсеятьУзкие,
  проверить,
  собратьУтверждения,
} from "../scripts/claim-guard.mjs"

/** Разбор с проверкой типов — то, чем `УЗКИЕ` подтверждают свою узкую правду. */
function пр(тело, парам = "н: число", возвр = "число") {
  const исходник = `модуль «Проба»\n\nтотальная функция «Проба»\n  принимает ${парам}\n  возвращает ${возвр}\n  ${тело}\n`
  try {
    const программа = parse(исходник, "проба.flang")
    return { программа, беды: (checkTypes(программа).diagnostics ?? []).map((б) => б.code) }
  } catch (беда) {
    return { программа: null, беды: [беда?.code ?? "FLANG_PARSE"] }
  }
}

/** Прогон сторожа по временному дереву. */
async function наДереве(файлы) {
  const каталог = await mkdtemp(join(tmpdir(), "claim-guard-"))
  try {
    for (const [имя, текст] of Object.entries(файлы)) {
      const путь = join(каталог, имя)
      await mkdir(join(путь, ".."), { recursive: true })
      await writeFile(путь, текст, "utf8")
    }
    return проверить(каталог)
  } finally {
    await rm(каталог, { recursive: true, force: true })
  }
}

/* Обход всего дерева стоит секунд, а нужен двум проверкам. Считается один раз. */
const ВСЕ = собратьУтверждения(КОРЕНЬ)

test("на дереве репозитория сторож чист", () => {
  const нарушения = отсеятьУзкие(ВСЕ)
  assert.deepEqual(
    нарушения.map((н) => `${н.файл}:${н.строка} — ${н.известные.join(", ")}`),
    [],
    "проза отрицает форму, которую язык знает: правьте прозу, а не сторожа",
  )
})

test("лексер отвечает про форму прогоном, а не таблицей", () => {
  /* Составное слово — одна форма. */
  assert.equal(лексерЗнает("код символа"), true)
  assert.equal(лексерЗнает("и притом"), true)
  assert.equal(лексерЗнает("или"), true)
  /* Не слово языка. */
  assert.equal(лексерЗнает("замыкание"), false)
  assert.equal(лексерЗнает("макрос"), false)
  /* Три ключевых слова подряд формой не являются — иначе сторож краснел бы
     на верном утверждении «формы `элемент или беда` нет». */
  assert.equal(лексерЗнает("элемент или беда"), false)
})

test("сторож ЛОВИТ утверждение о форме, которая в языке есть", async () => {
  for (const [имя, файл, текст] of [
    ["комментарий .flang", "п.flang", "модуль «П»\n\n// Формы «код символа» в языке нет, поэтому таблица.\n"],
    ["комментарий .mjs", "п.mjs", "/* Здесь формы «код символа» в языке нет, поэтому иначе. */\n"],
    ["проза .md", "п.md", "Обойти это нечем: формы «код символа» в языке нет.\n"],
    ["поле .json", "п.json", '{ "причина": "инфиксного «или» в языке нет" }\n'],
  ]) {
    const нарушения = await наДереве({ [файл]: текст })
    assert.equal(нарушения.length, 1, `${имя}: сторож не поймал подложенное утверждение`)
  }
})

test("сторож МОЛЧИТ на надгробии снятого утверждения", async () => {
  const нарушения = await наДереве({
    "п.flang": "модуль «П»\n\n// Здесь стояло, что формы «код символа» в языке нет. Форма появилась.\n",
  })
  assert.deepEqual(нарушения, [], "надгробие — это память о правке, а не утверждение; краснеть на нём значит требовать стирать историю")
})

test("сторож МОЛЧИТ на цитате чужого утверждения", async () => {
  const нарушения = await наДереве({
    "п.mjs": '/* Прежняя оговорка звучала так: «потому что формы «код символа» в языке нет вовсе». Больше не так. */\n',
  })
  assert.deepEqual(нарушения, [])
})

test("сторож МОЛЧИТ, когда речь не о языке, а о файле или о программе", async () => {
  const нарушения = await наДереве({
    "а.mjs": "/* Слова «шаг» здесь нет ни разу — проверено грепом. */\n",
    "б.mjs": "/* Программа, в которой формы `к числу или беда` нет, обязана дать прежний AST. */\n",
  })
  assert.deepEqual(нарушения, [])
})

test("сторож МОЛЧИТ на утверждении о форме, которой в языке правда нет", async () => {
  const нарушения = await наДереве({
    "п.flang": "модуль «П»\n\n// Формы «замыкание» в языке нет и не будет.\n",
  })
  assert.deepEqual(нарушения, [], "форму, которой нет, сторож проверить не может и не должен — на неё пишут улику в claims.test.mjs")
})

test("сторож не путает кавычки, стоящие в предложении по другому поводу", async () => {
  /* Настоящий случай из flang/SPEC.md: названа форма «элемент или беда»,
     которой нет, а рядом стоит `длина`, которая есть. Краснеть здесь не на чем. */
  const нарушения = await наДереве({
    "п.md": "Проверить его заранее стоит одного сравнения с `длина`, и потому формы «элемент или беда» нет.\n",
  })
  assert.deepEqual(нарушения, [])
})

test("каждое узкое исключение подтверждается программой", () => {
  assert.ok(УЗКИЕ.length > 0, "список узких мест пуст — тогда и проверять нечего")
  for (const узкое of УЗКИЕ) {
    assert.ok(
      узкое.проверка(пр),
      `узкое исключение для ${узкое.где} («${узкое.форма}») БОЛЬШЕ НЕ ВЕРНО: программа, которая ` +
        `подтверждала узкую правду, теперь работает. Довод, записанный в исключении: ${узкое.почему}. ` +
        `Уберите исключение и поправьте прозу.`,
    )
  }
})

test("узкое исключение снимает ровно своё место, а не все подряд", async () => {
  /* То же утверждение в ЧУЖОМ файле обязано ловиться: исключение поимённое. */
  const нарушения = await наДереве({ "чужой.mjs": "/* инфиксного `и` в языке нет, поэтому вложенные если */\n" })
  assert.equal(нарушения.length, 1, "исключение для defunc.mjs не должно прикрывать другие файлы")
})

test("сторож смотрит только на прозу, а не на код", async () => {
  /* Строковый литерал в коде — не утверждение автора о языке. */
  const нарушения = await наДереве({
    "п.mjs": 'const весть = "формы «код символа» в языке нет"\n',
  })
  assert.deepEqual(нарушения, [], "сторож обязан читать комментарии, а не строки кода")
})

test("обход доходит до глубоких каталогов, а не молчит по недосмотру", () => {
  /* Зелёный сторож обязан быть зелёным ОТ ЧИСТОТЫ, а не оттого, что обход
     однажды сузили и он перестал видеть полдерева. Проверяется на надгробии,
     которое в дереве заведомо лежит: `flang/stdlib/sets.flang` помнит, что
     «код символа» появился 9 августа 2026. Видит его сторож — значит доходит
     и до `flang/stdlib`, и до прочей глубины. */
  const текст = readFileSync(new URL("../stdlib/sets.flang", import.meta.url), "utf8")
  const куски = кускиПрозы("flang/stdlib/sets.flang", текст)
  assert.ok(куски.length > 0, "комментарии stdlib/sets.flang не читаются вовсе")
  assert.ok(
    куски.some((к) => /БОЛЬШЕ НЕ ПРАВДА/u.test(к.текст)),
    "надгробие из stdlib/sets.flang не попало в разбор — обход или разбор комментариев сузился",
  )
})
