test("каждое утверждение о невозможном стоит в документе дословно", () => {
  for (const запись of УТВЕРЖДЕНИЯ) {
    if (запись.пропустить) continue
    const текст = прочитать(запись.где)
    assert.ok(
      текст.includes(запись.цитата),
      `в ${запись.где} больше нет фразы «${запись.цитата}». Документ переписали — ` +
        `пересмотрите запись в claims.test.mjs, а не подгоняйте текст обратно.`,
    )
  }
})

test("каждое утверждение о невозможном подтверждается программой", () => {
  for (const запись of УТВЕРЖДЕНИЯ) {
    if (запись.пропустить) continue
    assert.ok(
      запись.держит(),
      `${запись.где}: утверждение «${запись.цитата}» БОЛЬШЕ НЕ ВЕРНО — программа, которая ` +
        `его подтверждала, теперь работает. Причина, записанная в документе: ${запись.почему}. ` +
        `Правьте документ, а не тест.`,
    )
  }
})
