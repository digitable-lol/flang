/**
 * Утверждения о невозможном, записанные в прозе, — и программы, которые их держат.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * За одни сутки ШЕСТЬ раз выяснилось, что объяснение недостачи пережило саму
 * недостачу:
 *
 *   1. восемь записей из пятнадцати в каталоге «чего не хватает языку»;
 *   2. тринадцать функций stdlib без примеров — «вариант в примере записать
 *      нельзя»;
 *   3. шапка «Строк» — «разложение на символы обрезке не помогает», при том что
 *      ровно такая обрезка уже была тотальной в соседнем файле;
 *   4. «восемь бэкендов не печатают функции» — устарело через час после того,
 *      как это написали;
 *   5. «полиморфизм печатается мономорфизацией» — бэкенды и так стирали типы;
 *   6. «печатается — значит можно писать библиотеку» — печать и разбор
 *      самоприменением оказались разными контрактами.
 *
 * Причина у всех одна и она устроена коварно: **утверждение о недостаче —
 * единственное утверждение о языке, которое не ломается, когда становится
 * ложным**. Тест, проверяющий, что чего-то НЕТ, никто не пишет; тест,
 * проверяющий, что что-то ЕСТЬ, на такую фразу не посмотрит. Код при этом
 * зелёный, а документ врёт.
 *
 * ── Почему не проверка всех комментариев ────────────────────────────────────
 * Слов «нельзя», «невозможно», «не помогает» в исходниках 211 штук. Требовать
 * улику от каждого — это шум, который перестанут читать через неделю, и он же
 * запретит объяснять устройство языка обычными словами.
 *
 * Проверяются те документы, которые УЖЕ подвели, и ровно те фразы, что несут
 * утверждение. Каждая запись — тройка: файл, дословная цитата и программа.
 * Цитата обязана присутствовать; программа обязана подтверждать её.
 *
 * Отсюда два разных отказа, и они означают разное:
 *
 *   • цитаты нет — документ переписали. Значит утверждение либо изменилось,
 *     либо исчезло, и запись здесь надо пересмотреть, а не «починить текст»;
 *   • программа больше не подтверждает — недостача ЗАКРЫТА. Значит документ
 *     теперь врёт, и править надо его.
 *
 * Второй случай и есть тот, ради которого файл написан.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

const корень = new URL("../../", import.meta.url)

const прочитать = (путь) => readFileSync(new URL(путь, корень), "utf8")

/** Разбор с проверкой; `null` в программе — не разобралось вовсе. */
function проверить(исходник) {
  try {
    const программа = parse(исходник, "проба.flang")
    return { программа, беды: (checkTypes(программа).diagnostics ?? []).map((б) => б.code) }
  } catch (беда) {
    return { программа: null, беды: [беда?.code ?? "FLANG_PARSE"] }
  }
}

/* Парсер, написанный на самом языке, связывается один раз: он состоит из
   нескольких модулей, и связывание на каждом обращении стоило бы секунд.
   Способ взят из flang/test/missing.test.mjs — там та же нужда решена так же,
   и разводить два способа спрашивать вторую реализацию незачем. */
const ПУТЬ_ПАРСЕРА = fileURLToPath(new URL("../self/parser.flang", import.meta.url))
const { diagnostics: бедыПарсера, ...парсерНаFlang } = await linkProgram(
  ПУТЬ_ПАРСЕРА,
  readFileSync(ПУТЬ_ПАРСЕРА, "utf8"),
  parse,
)
const средаПарсера = createRuntime(парсерНаFlang, { maxSteps: 150_000_000, maxDepth: 20_000 })

/** Отвергает ли исходник ВТОРАЯ реализация — та, что написана на самом языке. */
function отвергаетСвой(исходник) {
  assert.deepEqual(бедыПарсера, [], "self/parser.flang не связался — проверять нечем")
  const итог = средаПарсера.call("Разбор исходника", { исходник, внешние: [] })
  return (итог["диагностики"] ?? []).length > 0
}

/**
 * Реестр утверждений.
 *
 * `держит` возвращает true, ПОКА утверждение верно. Стало false — недостача
 * закрыта, и документ пора править.
 */
const УТВЕРЖДЕНИЯ = [
  {
    где: "flang/stdlib/logic.flang",
    цитата: "Записать его здесь нельзя",
    почему:
      "конъюнкция и дизъюнкция — моноиды, но stdlib входит в корпус сверки самоприменения, " +
      "а self/parser.flang слова «моноид» не разбирает: лексер на языке его уже знает, парсер ещё нет",
    держит: () =>
      отвергаетСвой(
        'модуль «Проба»\n\nтотальная функция «Оба»\n  принимает первый: признак, второй: признак\n' +
          "  возвращает признак\n  если первый\n    то второй\n    иначе нет\n\n" +
          'моноид «Конъюнкция»\n  носитель признак\n  операция «Оба»\n  единица да\n',
      ),
  },
  {
    где: "flang/src/totality.mjs",
    цитата: "Измерено: 18014398509481988 − 1 = 18014398509481988",
    почему:
      "убывание по мере доказано для вещественных чисел, а числа flang — IEEE-754 double; " +
      "выше 2⁵⁴ шаг «минус один» перестаёт что-либо менять, и «До нуля» от такого входа не завершается. " +
      "Пока это утверждение верно, шапка totality.mjs обязана называть границу вслух",
    держит: () => {
      /* Считает сам язык, а не JavaScript: утверждение — про арифметику flang,
         и проверять его надо там, где она живёт. Если double однажды сменится
         на что-то точное, эта проба перестанет держать, и границу из шапки
         придётся убрать — что и будет правдой. */
      const итог = проверить(
        "модуль «Точность»\n\nтотальная функция «Убавить»\n  принимает н: число\n  возвращает число\n  н минус 1\n",
      )
      if (итог.программа === null || итог.беды.length > 0) return false
      const среда = createRuntime(итог.программа, { maxSteps: 1_000 })
      const огромное = 18014398509481988
      return среда.call("Убавить", { н: огромное }) === огромное
    },
  },
  {
    где: "flang/stdlib/optional.flang",
    цитата: "«равен» над параметром типа отвергается",
    почему:
      "у параметра типа нет операций, и равенство не исключение: сравнивать разрешено только " +
      "скаляры (types.mjs). Пока это так, sets.flang и dictionary.flang параметрическими не " +
      "станут — «Есть в множестве» и поиск по ключу написаны через `равен`, — и то же держит " +
      "числовыми «Индекс», «Считать вхождения» и «Без значения» в lists.flang",
    держит: () => {
      const итог = проверить(
        'модуль «Равенство»\n\nтотальная функция «Совпало» от «А»\n' +
          "  принимает первое: «А», второе: «А»\n  возвращает признак\n  первое равен второе\n",
      )
      return итог.беды.length > 0
    },
  },
  {
    где: "flang/stdlib/optional.flang",
    цитата: "начальное значение свёртки типизируется БЕЗ ожидаемого типа",
    почему:
      "foldType в types.mjs передаёт в вывод начального значения null, поэтому конструктор " +
      "полиморфного варианта без полей в этой позиции подстановку не выводит. Ровно из-за этого " +
      "«Найти не меньше» переписана со свёртки на разбор списка",
    держит: () => {
      const итог = проверить(
        'модуль «Начало свёртки»\n\nтип «Возможно» от «А»\n  вариант «Есть» содержит значение: «А»\n' +
          '  вариант «Нет»\n\nтотальная функция «Проба»\n  принимает элементы: список числа\n' +
          '  возвращает «Возможно» от числа\n  свёртка элементы начиная с вариант «Нет» как акк и эл\n' +
          "    вариант «Есть» с значение равным эл\n",
      )
      return итог.беды.includes("FLANG_TYPE_PARAM")
    },
  },
  {
    где: "flang/stdlib/higher-order.flang",
    цитата: "сверяется с ожидаемым типом БЕЗ подстановки",
    почему:
      "значение примера проверяется checkValue по объявленному типу, а подстановку из самих " +
      "значений примера никто не выводит — это фаза 2 в flang/cat/POLY.md, она не сделана. " +
      "Пока так, «Отобразить» и «Отобразить строки» в одну функцию не сводятся: объявление " +
      "проходит, а примеры падают, и stdlib.test.mjs требует пример у каждой такой функции",
    держит: () => {
      const итог = проверить(
        'модуль «Пример функции»\n\nтотальная функция «Удвоить»\n  принимает х: число\n' +
          "  возвращает число\n  х плюс х\n\n" +
          'тотальная функция «Отобразить» от «А» и «Б»\n' +
          "  принимает ф: функция из «А» в «Б», элементы: список «А»\n  возвращает список «Б»\n" +
          '  пример «Удвоение»\n    дано ф равно функция «Удвоить»\n' +
          "    дано элементы равно [1, 2]\n    ожидается [2, 4]\n" +
          "  отобразить элементы как эл → ф от эл\n",
      )
      return итог.беды.length > 0
    },
  },
  {
    где: "flang/examples/leetcode/020-valid-parentheses.flang",
    цитата: "Прерывать свёртку нельзя",
    почему: "выйти из свёртки досрочно нечем: у неё нет формы раннего возврата",
    держит: () => {
      /* Если бы прерывание появилось, у свёртки был бы синтаксис выхода.
         Проверяем прямо: попытка выйти из свёртки не разбирается. */
      const итог = проверить(
        "модуль «Прерывание»\n\nтотальная функция «Проба»\n  принимает элементы: список числа\n" +
          "  возвращает число\n  свёртка элементы начиная с 0 как акк и эл → прервать акк\n",
      )
      return итог.программа === null || итог.беды.length > 0
    },
  },
]

test("каждое утверждение о невозможном стоит в документе дословно", () => {
  for (const запись of УТВЕРЖДЕНИЯ) {
    if (запись.пропустить) continue
    const текст = прочитать(запись.где)
    assert.ok(
      текст.includes(запись.цитата),
      `в ${запись.где} больше нет фразы «${запись.цитата}». Документ переписали — ` +
        `пересмотрите запись в claims.test.mjs, а не подгоняйте текст обратно.`,
    )
  }
})

test("каждое утверждение о невозможном подтверждается программой", () => {
  for (const запись of УТВЕРЖДЕНИЯ) {
    if (запись.пропустить) continue
    assert.ok(
      запись.держит(),
      `${запись.где}: утверждение «${запись.цитата}» БОЛЬШЕ НЕ ВЕРНО — программа, которая ` +
        `его подтверждала, теперь работает. Причина, записанная в документе: ${запись.почему}. ` +
        `Правьте документ, а не тест.`,
    )
  }
})
