/**
 * Утверждения о невозможном, записанные в прозе, — и программы, которые их держат.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * За одни сутки ШЕСТЬ раз выяснилось, что объяснение недостачи пережило саму
 * недостачу:
 *
 *   1. восемь записей из пятнадцати в каталоге «чего не хватает языку»;
 *   2. тринадцать функций stdlib без примеров — «вариант в примере записать
 *      нельзя»;
 *   3. шапка «Строк» — «разложение на символы обрезке не помогает», при том что
 *      ровно такая обрезка уже была тотальной в соседнем файле;
 *   4. «восемь бэкендов не печатают функции» — устарело через час после того,
 *      как это написали;
 *   5. «полиморфизм печатается мономорфизацией» — бэкенды и так стирали типы;
 *   6. «печатается — значит можно писать библиотеку» — печать и разбор
 *      самоприменением оказались разными контрактами.
 *
 * Причина у всех одна и она устроена коварно: **утверждение о недостаче —
 * единственное утверждение о языке, которое не ломается, когда становится
 * ложным**. Тест, проверяющий, что чего-то НЕТ, никто не пишет; тест,
 * проверяющий, что что-то ЕСТЬ, на такую фразу не посмотрит. Код при этом
 * зелёный, а документ врёт.
 *
 * ── Почему не проверка всех комментариев ────────────────────────────────────
 * Здесь стояло «слов «нельзя», «невозможно», «не помогает» в исходниках 211
 * штук». Число не воспроизводится ни при каком прочтении и 9 августа 2026
 * пересчитано: этих трёх слов 492 по всему дереву и 378 в `.mjs` и `.flang`, а
 * вместе с оборотами «не выразить», «в языке нет», «нечем» и прочими — 904
 * фразы в 219 файлах. Вывод от пересчёта только окреп: требовать улику от
 * каждого — это шум, который перестанут читать через неделю, и он же запретит
 * объяснять устройство языка обычными словами.
 *
 * ── Что из этих 904 всё-таки проверяется машиной ────────────────────────────
 * Подкласс, которому улика не нужна, потому что она уже есть и зовётся
 * лексером: «формы «X» в языке нет», где `X` назван кавычками. Такое решается
 * прогоном `tokenize`, и сторожит его `flang/scripts/claim-guard.mjs` вместе с
 * `flang/test/claim-guard.test.mjs` — без реестра и без ручного заведения
 * записей. В день, когда он был написан, он нашёл девять таких мест, и семь из
 * них были ложью; шесть — про одну и ту же форму `код символа`.
 *
 * Здешний реестр остаётся для всего остального: утверждение о том, чего в языке
 * НЕТ, машина проверить не может, потому что спросить ей не у кого. Такому
 * утверждению по-прежнему нужна программа, написанная человеком, — и она ниже.
 *
 * Проверяются те документы, которые УЖЕ подвели, и ровно те фразы, что несут
 * утверждение. Каждая запись — тройка: файл, дословная цитата и программа.
 * Цитата обязана присутствовать; программа обязана подтверждать её.
 *
 * Отсюда два разных отказа, и они означают разное:
 *
 *   • цитаты нет — документ переписали. Значит утверждение либо изменилось,
 *     либо исчезло, и запись здесь надо пересмотреть, а не «починить текст»;
 *   • программа больше не подтверждает — недостача ЗАКРЫТА. Значит документ
 *     теперь врёт, и править надо его.
 *
 * Второй случай и есть тот, ради которого файл написан.
 */
