/**
 * Граница входа: `flang run --args` против объявленных типов.
 *
 * ── Что здесь ловится ───────────────────────────────────────────────────────
 *
 * До этой правки значения из `--args` не сверялись с объявленным типом ничем.
 * На живом файле дерева (`flang/examples/measure/natural.flang`, «Факториал»
 * принимает `н: нат`) это выглядело так:
 *
 *   --args '{"н": -3}'      → {"result":1}      посчиталось
 *   --args '{"н": 2.5}'     → {"result":3.75}   посчиталось
 *   --args '{"н": "строка"}'→ FLANG_TYPE «сравнения порядка допустимы только
 *                              для чисел» — про операцию в теле, не про вход
 *   --args '{"н": 1e300}'   → FLANG_RECURSION_LIMIT на глубине 10001
 *
 * Последняя строка — не косметика. `нат` это [0, 2^53−1], и доказательство
 * завершения `тотальной` стоит НА ЭТОМ: ниже потолка `н минус 1` точно меньше
 * `н`, поэтому сторож убывания в такую функцию не печатается ВОВСЕ (SPEC,
 * «Точное натуральное»). Значение вне типа выносит вместе с типом и
 * доказательство: 1e300 минус 1 равно 1e300, цепочка вечна, ловить её нечем.
 * То есть ТОТАЛЬНАЯ функция отказывала кодом, который SPEC отводит ОБЫЧНОЙ
 * функции, исчерпавшей лимит, — и отказывала после десяти тысяч кадров работы.
 *
 * ── Чего этот тест требует ──────────────────────────────────────────────────
 *
 * Не «сообщение стало понятнее», а «значение не дошло до вычисления»: отказ
 * обязан прийти кодом FLANG_TYPE и НЕ иметь права быть FLANG_RECURSION_LIMIT.
 * Снимут проверку на границе — на 1e300 вернётся предел глубины, и тест
 * покраснеет.
 *
 * ── Почему на файле репозитория ─────────────────────────────────────────────
 *
 * Выдуманная программа доказывала бы, что дыра бывает; `natural.flang` лежит в
 * дереве и служит образцом точного натурального типа — на нём дыра БЫЛА. Вторая
 * половина изъятия проверяется рядом: годный вход обязан считаться, иначе тест
 * зеленел бы от того, что не проходит ничего.
 */

import assert from "node:assert/strict"
import { execFile } from "node:child_process"
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { after, test } from "node:test"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

const выполнить = promisify(execFile)
const cli = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))
const натуральное = fileURLToPath(new URL("../examples/measure/natural.flang", import.meta.url))

const workdir = await mkdtemp(join(tmpdir(), "flang-cli-args-"))
after(async () => {
  await rm(workdir, { recursive: true, force: true })
})

let счётчик = 0
async function песочница(имя, текст) {
  const каталог = join(workdir, `s${(счётчик += 1)}`)
  await mkdir(каталог, { recursive: true })
  const путь = join(каталог, имя)
  await writeFile(путь, текст, "utf8")
  return путь
}

/** Успешный прогон: JSON из stdout, ничего в stderr. */
async function успех(аргументы) {
  const { stdout, stderr } = await выполнить("node", [cli, ...аргументы], { maxBuffer: 64 * 1024 * 1024 })
  assert.equal(stderr, "", "успешный прогон не пишет в stderr")
  return JSON.parse(stdout)
}

/** Отказ: код возврата, stdout и разобранный отчёт из stderr. */
async function отказ(аргументы) {
  try {
    await выполнить("node", [cli, ...аргументы], { maxBuffer: 64 * 1024 * 1024 })
  } catch (error) {
    return { code: error.code, stdout: error.stdout, report: JSON.parse(error.stderr) }
  }
  assert.fail(`вызов ${аргументы.join(" ")} обязан был отказать`)
}

const запуск = (функция, аргументы, ...хвост) =>
  ["run", натуральное, "--function", функция, "--args", JSON.stringify(аргументы), ...хвост]

/* ─────────── половина изъятия, без которой вторая ничего не значит ────────── */

test("годный вход считается: проверка границы не мешает работе", async () => {
  assert.equal((await успех(запуск("Факториал", { н: 5 }))).result, 120)
  assert.equal((await успех(запуск("Числа от одного до", { н: 3 }))).result.length, 3)
  assert.equal((await успех(запуск("Сумма списка", { элементы: [1, 2, 3] }))).result, 6)
  assert.equal((await успех(запуск("Сумма пары", { первое: 2, второе: 3 }))).result, 5)
})

/* ───────────────────────── вход, лгущий про тип ──────────────────────────── */

test("строка вместо «нат» отвергается на границе, а не операцией в теле", async () => {
  const { code, stdout, report } = await отказ(запуск("Факториал", { н: "строка" }))
  assert.equal(code, 1, "ошибка входа, а не вызова — код 1")
  assert.equal(stdout, "", "отвергнутый вход не имеет права оставить результат в stdout")
  assert.equal(report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(report.diagnostics[0].message, /аргумент «н» не соответствует типу нат/u)
  /* Про ВХОД, а не про операцию: до правки здесь стояло «сравнения порядка
     допустимы только для чисел» — правда о `не больше`, и ни слова о том, что
     значение не того типа, который объявлен. */
  assert.doesNotMatch(report.diagnostics[0].message, /сравнени/u)
})

test("отрицательное в «нат» отвергается, а не считается", async () => {
  const { code, stdout, report } = await отказ(запуск("Факториал", { н: -3 }))
  assert.equal(code, 1)
  assert.equal(stdout, "", "до правки здесь печаталось {\"result\":1}")
  assert.equal(report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(report.diagnostics[0].message, /-3 вне нат/u)
})

test("дробное в «нат» отвергается, а не считается", async () => {
  const { code, stdout, report } = await отказ(запуск("Факториал", { н: 2.5 }))
  assert.equal(code, 1)
  assert.equal(stdout, "", "до правки здесь печаталось {\"result\":3.75}")
  assert.equal(report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(report.diagnostics[0].message, /2\.5 не целое, а тип нат — целый/u)
})

test("за потолком «нат» — отказ по ТИПУ, а не по глубине", async () => {
  /* Главная проверка файла. 1e300 лежит вне [0, 2^53−1], а сторожа убывания у
     этой функции нет — его сняло доказательство по типу. Поэтому без границы
     входа тотальная функция уходила в вечную рекурсию и падала пределом
     глубины: FLANG_RECURSION_LIMIT, десять тысяч кадров, код обычной функции у
     тотальной. Снимут границу — вернётся ровно это, и обе проверки ниже
     покраснеют. */
  const { code, stdout, report } = await отказ(запуск("Факториал", { н: 1e300 }))
  assert.equal(code, 1)
  assert.equal(stdout, "")
  const коды = report.diagnostics.map((беда) => беда.code)
  assert.ok(!коды.includes("FLANG_RECURSION_LIMIT"), `вход дошёл до вычисления: ${коды.join(", ")}`)
  assert.equal(коды[0], "FLANG_TYPE")
  assert.match(report.diagnostics[0].message, /1e\+300 вне нат/u)
})

test("значение не доходит до вычислителя: отказ есть и при одном разрешённом шаге", async () => {
  /* Второй способ сказать «до вычисления не дошло», и он не про текст: с
     `--max-steps 1` вычислитель не успевает ничего, и если бы вход проверялся
     ИМ, отказ был бы про предел шагов. Он про тип. */
  const { report } = await отказ(запуск("Факториал", { н: -3 }, "--max-steps", "1"))
  assert.equal(report.diagnostics[0].code, "FLANG_TYPE")
})

test("врут оба аргумента — приезжают обе диагностики", async () => {
  const { report } = await отказ(запуск("Сумма пары", { первое: -1, второе: 0.5 }))
  assert.deepEqual(report.diagnostics.map((беда) => беда.code), ["FLANG_TYPE", "FLANG_TYPE"])
  assert.match(report.diagnostics[0].message, /аргумент «первое»: -1 вне нат/u)
  assert.match(report.diagnostics[1].message, /аргумент «второе»: 0\.5 не целое/u)
})

test("ложь внутри значения называется путём: элемент списка и поле записи", async () => {
  const список = await отказ(запуск("Сумма списка", { элементы: [1, 2, "три"] }))
  assert.equal(список.report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(список.report.diagnostics[0].message, /«элементы»\[2\] не соответствует типу число/u)

  const файл = await песочница(
    "запись.flang",
    `модуль «Запись»

объект «Покупка»
  сумма является числом
  скидка является нат

тотальная функция «Итог»
  принимает вход: «Покупка»
  возвращает число
  вход.сумма минус вход.скидка
`,
  )
  assert.equal(
    (await успех(["run", файл, "--function", "Итог", "--args", JSON.stringify({ вход: { сумма: 200, скидка: 20 } })])).result,
    180,
  )
  const запись = await отказ(
    ["run", файл, "--function", "Итог", "--args", JSON.stringify({ вход: { сумма: 200, скидка: -1 } })],
  )
  assert.equal(запись.report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(запись.report.diagnostics[0].message, /«вход»\.скидка: -1 вне нат/u)
})

test("«иногда является» пропускается дверью, а лишнее и обязательное — нет", async () => {
  /* Дыра была НАРУЖНАЯ, а не внутренняя: `fieldMap` в types.mjs нормализовал
     `field.type`, а пометку `иногда является` парсер кладёт на САМО ПОЛЕ, — и
     `checkValue` требовал необязательное поле как обязательное. Улика до
     правки, снятая ровно этой командой:

       --args '{"а": {"сумма": 10}}'
         → FLANG_TYPE «вызов функции «Сумма анкеты»: аргумент «а»: не задано
           поле «комментарий» записи «Анкета»»

     То есть дверь отвергала значение, которое объявлению не противоречит ничем.
     Три проверки ниже держат обе стороны разом: пропустить необязательное —
     обязана; пропустить лишнее или недостачу обязательного — не имеет права. */
  const файл = await песочница(
    "анкета.flang",
    `модуль «Анкета»

объект «Анкета»
  сумма является числом
  комментарий иногда является строкой

тотальная функция «Сумма анкеты»
  принимает а: «Анкета»
  возвращает число
  а.сумма
`,
  )
  const вызов = (значение) =>
    ["run", файл, "--function", "Сумма анкеты", "--args", JSON.stringify({ а: значение })]

  assert.equal((await успех(вызов({ сумма: 10 }))).result, 10, "необязательное поле можно не задавать")
  assert.equal((await успех(вызов({ сумма: 10, комментарий: null }))).result, 10, "«ничто» — законное значение")
  assert.equal((await успех(вызов({ сумма: 10, комментарий: "ок" }))).result, 10, "и заданное — тоже")

  /* «Можно не задавать» не значит «можно соврать про тип». */
  const ложь = await отказ(вызов({ сумма: 10, комментарий: 5 }))
  assert.equal(ложь.report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(ложь.report.diagnostics[0].message, /«а»\.комментарий не соответствует типу строка или ничто/u)

  /* Лишнее поле отвергается по-прежнему: необязательность одного поля не
     открывает запись для полей, которых в ней нет. */
  const лишнее = await отказ(вызов({ сумма: 10, привет: 1 }))
  assert.equal(лишнее.report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(лишнее.report.diagnostics[0].message, /запись «Анкета» не имеет поля «привет»/u)

  /* И обязательное поле без значения — тоже по-прежнему. */
  const недостача = await отказ(вызов({ комментарий: "ок" }))
  assert.equal(недостача.report.diagnostics[0].code, "FLANG_TYPE")
  assert.match(недостача.report.diagnostics[0].message, /не задано поле «сумма» записи «Анкета»/u)
})

/* ────────────────── одно утверждение, а не два разных языка ───────────────── */

test("граница входа судит тем же приговором, что и пример в исходнике", async () => {
  /* `дано н равно −1` при `н: нат` отвергается `flang check` — значит и
     `--args '{"н": -1}'` обязано отвергаться ТЕМ ЖЕ кодом и теми же словами о
     значении. Разойдись эти двое, «значение подходит типу» значило бы в языке
     две разные вещи, смотря откуда значение приехало. */
  const исходник = await readFile(натуральное, "utf8")
  const порченый = await песочница(
    "натуральное.flang",
    исходник.replace("    дано н равно 3\n    ожидается [1, 2, 3]", "    дано н равно -1\n    ожидается пустой список"),
  )
  assert.notEqual(порченый, исходник, "изъятию нечего портить: пример «До трёх» не найден")

  const проверка = await отказ(["check", порченый])
  const беда = проверка.report.diagnostics.find((item) => item.message.includes("вне нат"))
  assert.ok(беда, `check не поймал −1 в «нат»: ${JSON.stringify(проверка.report.diagnostics)}`)

  const вход = await отказ(запуск("Числа от одного до", { н: -1 }))
  assert.equal(вход.report.diagnostics[0].code, беда.code)
  /* Общий хвост: у примера впереди стоит его имя, у вызова — имя функции, а
     говорят они об одном и том же значении одними и теми же словами. */
  const хвост = "аргумент «н»: -1 вне нат"
  assert.ok(беда.message.endsWith(хвост), беда.message)
  assert.ok(вход.report.diagnostics[0].message.endsWith(хвост), вход.report.diagnostics[0].message)
})
