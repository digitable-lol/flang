/**
 * `flang check --размещение` — сборка распределённой программы.
 *
 * ── Что здесь ловится ───────────────────────────────────────────────────────
 *
 * Обещание языка: набор отказов замкнут, и отказ, который процесс может выдать,
 * а надзор не разбирает, — ошибка СБОРКИ, а не сюрприз в бою. Через границу узла
 * это обещание было ложью: процесс, размещённый на другом узле, стоит здесь
 * представителем и умеет ровно одно — отказать `FLANG_LINK_DOWN`
 * (`flang/conc/DISTRIBUTED.md`), а анализ отказов о нём не знал, потому что
 * связи в тексте программы нет вовсе: её называет размещение.
 *
 * Улика была снята двумя узлами: программа ниже проходила `flang check` с нулём
 * диагностик, узлы поднимались, соседа убивали — и журнал говорил
 * `{"в":"отказ","процесс":"Слушатель","код":"FLANG_LINK_DOWN"}` при НОЛЕ решений
 * надзора.
 *
 * ── Почему отдельный файл, а не строка в failures.test.mjs ──────────────────
 *
 * Там проверен АНАЛИЗ — прямым вызовом `checkTypes(программа, { размещение })`,
 * без процессов и файлов. Здесь проверена ДОРОГА к нему: ключ командной строки,
 * чтение файла размещения и код выхода. Дорога ломается отдельно от анализа —
 * ключ, который принят и не действует, оставил бы проверку зелёной, а обещание
 * пустым, и по прогону анализа этого было бы не видно.
 *
 * Вторая дорога — подъём узла (`flang/conc/distributed.test.mjs`, испытание 10):
 * `flang check --размещение` автор может и забыть, а поднять узел мимо проверки
 * нельзя.
 */

import assert from "node:assert/strict"
import { execFile } from "node:child_process"
import { mkdtemp, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { after, test } from "node:test"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

const выполнить = promisify(execFile)
const cli = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))

const каталог = await mkdtemp(join(tmpdir(), "flang-placement-"))
after(async () => { await rm(каталог, { recursive: true, force: true }) })

/**
 * Оба процесса безотказны ПО ТЕКСТУ: тотальны, оценка витков постоянная,
 * частичных форм нет, `остановить` нет, ящик не объявлен. Значит без размещения
 * проверка обязана молчать — и молчит законно.
 */
const программа = [
  "объект «Счёт»",
  "  «сколько»: число",
  "",
  "тип «Весть»",
  "  вариант «звонок» содержит «раз»: число",
  "",
  "объект «Отклик»",
  "  «состояние»: «Счёт»",
  "  «действия»: список «Действие»",
  "",
  "процесс «Звонарь»",
  "  состояние «Счёт»",
  "  начинает с «нуль»",
  "  принимает «Весть»",
  "  обрабатывает «шаг»",
  "",
  "процесс «Слушатель»",
  "  состояние «Счёт»",
  "  начинает с «нуль»",
  "  принимает «Весть»",
  "  обрабатывает «шаг»",
  "",
  "НАДЗОР",
  "тотальная функция «нуль»",
  "  возвращает «Счёт»",
  "  запись «Счёт» с «сколько» равным 0",
  "",
  "тотальная функция «шаг»",
  "  принимает текущее: «Счёт», сообщение: «Весть»",
  "  возвращает «Отклик»",
  "  разбор сообщение",
  "    случай вариант «звонок» с «раз» как раз",
  "      пусть новое равно (запись «Счёт» с «сколько» равным (текущее.«сколько» плюс раз))",
  "      запись «Отклик» с «состояние» равным новое и «действия» равным []",
  "",
].join("\n")

const надзор = [
  "надзор «Цех»",
  "  процесс «Звонарь» стратегия «перезапустить»",
  "  процесс «Слушатель» стратегия «перезапустить»",
  "  порог отказов 2 за 5000 миллисекунд иначе «передать выше»",
  "",
].join("\n")

const безНадзора = join(каталог, "без-надзора.flang")
const сНадзором = join(каталог, "с-надзором.flang")
const размещение = join(каталог, "место.json")
const одинУзел = join(каталог, "один-узел.json")

await writeFile(безНадзора, программа.replace("НАДЗОР\n", ""), "utf8")
await writeFile(сНадзором, программа.replace("НАДЗОР\n", надзор), "utf8")
await writeFile(
  размещение,
  JSON.stringify({
    узлы: {
      "здесь": { слушать: "127.0.0.1:0", процессы: ["Звонарь"] },
      "там": { слушать: "127.0.0.1:0", процессы: ["Слушатель"] },
    },
  }),
  "utf8",
)
await writeFile(
  одинУзел,
  JSON.stringify({ узлы: { "всё": { слушать: "127.0.0.1:0", процессы: ["Звонарь", "Слушатель"] } } }),
  "utf8",
)

/**
 * Запустить `flang` и вернуть код выхода вместе с разобранным ответом.
 *
 * Ответ читается из stdout при согласии и из stderr при отказе — так устроен
 * передний край: диагностика уходит в stderr, а ненулевой код выхода и есть
 * «ошибка сборки». Проверять здесь надо ИМЕННО код, а не текст: `emit`
 * отказывался печатать непроверенное ровно потому, что код был ненулевым.
 */
async function запустить(...доводы) {
  try {
    const { stdout } = await выполнить(process.execPath, [cli, ...доводы])
    return { код: 0, ответ: JSON.parse(stdout) }
  } catch (беда) {
    const текст = String(беда.stderr ?? "").trim()
    return { код: беда.code ?? 1, ответ: текст === "" ? null : JSON.parse(текст) }
  }
}

const проверить = (...доводы) => запустить("check", ...доводы)

test("без ключа проверка молчит: границы узла нет — представителей нет", async () => {
  const { код, ответ } = await проверить(безНадзора)
  assert.equal(код, 0, JSON.stringify(ответ))
  assert.equal(ответ.valid, true)
  assert.deepEqual(ответ.diagnostics, [])
})

test("с размещением та же программа отвергается: забытый надзор над представителем", async () => {
  const { код, ответ } = await проверить(безНадзора, "--размещение", размещение)
  assert.equal(код, 1, "непокрытый представитель обязан быть ошибкой сборки, а не предупреждением")
  assert.equal(ответ.valid, false)
  assert.deepEqual(ответ.diagnostics.map((б) => б.code), ["FLANG_UNCOVERED_FAILURE", "FLANG_UNCOVERED_FAILURE"])
  assert.match(ответ.diagnostics[0].message, /связь с узлом потеряна/u)
  assert.match(ответ.diagnostics[0].message, /FLANG_LINK_DOWN/u)
})

test("дописанный надзор принимает её обратно, и проверка снова зелёная", async () => {
  const { код, ответ } = await проверить(сНадзором, "--размещение", размещение)
  assert.equal(код, 0, JSON.stringify(ответ))
  assert.deepEqual(ответ.diagnostics, [])
})

test("размещение на одном узле ошибкой не становится: требовать надзора не за что", async () => {
  const { код, ответ } = await проверить(безНадзора, "--размещение", одинУзел)
  assert.equal(код, 0, JSON.stringify(ответ))
  assert.deepEqual(ответ.diagnostics, [])
})

test("ключ у чужой команды — отказ вызова, а не молча проглоченный довод", async () => {
  /* Ключ, который принят и не действует, обещает проверку и молчит — ровно та
     беда, ради которой всё это делалось. Поэтому у `emit` он отказ (код 2), а не
     украшение. */
  const { код, ответ } = await запустить("emit", безНадзора, "--target", "js", "--размещение", размещение)
  assert.equal(код, 2)
  assert.match(ответ.error, /ключ команды check/u)
})

test("файл, который не размещение, называется этим, а не считается пустым", async () => {
  const чужой = join(каталог, "чужой.json")
  await writeFile(чужой, JSON.stringify({ узлы: 7 }), "utf8")
  const { код, ответ } = await проверить(безНадзора, "--размещение", чужой)
  assert.equal(код, 2)
  assert.match(ответ.error, /нет поля «узлы»/u)
})
