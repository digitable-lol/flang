/**
 * Сторож кодов отказа, названных прозой, — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/code-guard.mjs`. Обязательств
 * четыре, и они разные:
 *
 *   1. на дереве сторож ЧИСТ — каждый `FLANG_*` из любого `.md` либо есть в
 *      исходниках, либо помечен «объявлено, не сделано» с доводом;
 *   2. сторож ЛОВИТ выдуманный код — расхождение в одну букву имени;
 *   3. сторож ЛОВИТ ЗАКРЫТЫЙ ДОЛГ: код, помеченный «не сделано», появился в
 *      исходниках, и пометка стала неправдой;
 *   4. сторож не засчитывает за существование СВОЙ СОБСТВЕННЫЙ список
 *      исключений и не засчитывает тесты.
 *
 * Четвёртое — не выдумка на будущее, а починенный дефект: первый прогон дал
 * «не существует: 0», потому что сторож нашёл `FLANG_LAW_LIMIT` и
 * `FLANG_NODE_DEAD` в собственном исходнике и остался доволен собой.
 *
 * Запуск: node --test flang/test/code-guard.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { КОРЕНЬ, ОБЪЯВЛЕНО_НЕ_СДЕЛАНО, проверить, собрать } from "../scripts/code-guard.mjs"

/** Прогон сторожа по временному дереву. */
async function наДереве(файлы) {
  const каталог = await mkdtemp(join(tmpdir(), "code-guard-"))
  try {
    for (const [имя, текст] of Object.entries(файлы)) {
      const путь = join(каталог, имя)
      await mkdir(join(путь, ".."), { recursive: true })
      await writeFile(путь, текст, "utf8")
    }
    return проверить(каталог)
  } finally {
    await rm(каталог, { recursive: true, force: true })
  }
}

const ДЕРЕВО = собрать(КОРЕНЬ)

test("на дереве репозитория сторож чист", () => {
  const нарушения = проверить(КОРЕНЬ)
  assert.deepEqual(
    нарушения.map((н) => `${н.род}: ${н.код} — ${н.места.map((м) => м.файл).join(", ")}`),
    [],
    "проза называет код, которого нет: правьте прозу, а не сторожа",
  )
})

test("обход доходит до всей прозы, а не молчит по недосмотру", () => {
  /* Зелёный сторож обязан быть зелёным ОТ ЧИСТОТЫ, а не оттого, что обход
     однажды сузили и он перестал видеть полдерева. Улики — коды из трёх разных
     углов дерева: контракт распределённости, контракт категорной поверхности и
     контракт процессов. */
  assert.ok(ДЕРЕВО.вПрозе.size > 60, `имён FLANG_* в прозе всего ${ДЕРЕВО.вПрозе.size} — обход сузился`)
  for (const [код, файл] of [
    ["FLANG_LINK_DOWN", "flang/conc/DISTRIBUTED.md"],
    ["FLANG_MONOID_ASSOC", "flang/cat/SPEC.md"],
    ["FLANG_NO_SCHEDULER", "flang/conc/SPEC.md"],
  ]) {
    const места = ДЕРЕВО.вПрозе.get(код) ?? []
    assert.ok(места.some((м) => м.файл === файл), `код ${код} не найден в ${файл} — обход не дошёл`)
  }
})

test("сторож ЛОВИТ выдуманный код — расхождение в одну букву имени", async () => {
  const нарушения = await наДереве({
    "рантайм.c": 'fl_fail(ctx, error, FLANG_LINK_DOWN, "связь");\n',
    "проза.md": "Обрыв связи даёт `FLANG_LINK_DOWNN`.\n",
  })
  assert.deepEqual(
    нарушения.map((н) => [н.род, н.код]),
    [["выдуман", "FLANG_LINK_DOWNN"]],
    "одна лишняя буква в имени кода — это код, по которому ищут и не находят",
  )
  assert.equal(нарушения[0].места[0].файл, "проза.md")
  assert.equal(нарушения[0].места[0].строка, 1, "сторож обязан назвать строку, а не только файл")
})

test("сторож МОЛЧИТ, когда код в исходниках есть", async () => {
  const нарушения = await наДереве({
    "рантайм.c": 'fl_fail(ctx, error, FLANG_LINK_DOWN, "связь");\n',
    "проза.md": "Обрыв связи даёт `FLANG_LINK_DOWN`.\n",
  })
  assert.deepEqual(нарушения, [])
})

test("сторож НЕ засчитывает за существование тест", async () => {
  /* Тест, называющий код в комментарии, — такая же проза. Засчитать её значит
     разрешить прозе подтверждать саму себя. */
  const нарушения = await наДереве({
    "flang/test/п.test.mjs": "/* Когда-нибудь тут будет FLANG_MADE_UP. */\n",
    "проза.md": "Отказ называется `FLANG_MADE_UP`.\n",
  })
  assert.deepEqual(
    нарушения.map((н) => н.код),
    ["FLANG_MADE_UP"],
    "код, живущий только в тесте, существованием не является",
  )
})

test("сторож НЕ засчитывает за существование собственный список исключений", () => {
  /* Починенный дефект: сторож искал коды во всех не-`.md` файлах, включая себя,
     и находил их в `ОБЪЯВЛЕНО_НЕ_СДЕЛАНО`. Проверяется прямо: ни один код из
     списка не должен числиться существующим — а он назван в исходнике сторожа
     буква в букву. */
  for (const запись of ОБЪЯВЛЕНО_НЕ_СДЕЛАНО) {
    assert.equal(
      ДЕРЕВО.вИсходниках.has(запись.код),
      false,
      `${запись.код} числится существующим — сторож принял за реализацию собственный список либо тест`,
    )
  }
})

test("сторож ЛОВИТ закрытый долг: помеченный код появился в исходниках", async () => {
  /* Список исключений обязан краснеть в ОБЕ стороны. Иначе он превращается в
     свалку, куда сваливают всё покрасневшее, — то есть в выключатель сторожа.
     Улика подкладывается настоящим кодом из настоящего списка. */
  const код = ОБЪЯВЛЕНО_НЕ_СДЕЛАНО[0].код
  const нарушения = await наДереве({
    "рантайм.c": `fl_fail(ctx, error, ${код}, "предел");\n`,
    "проза.md": `Упор в предел даёт \`${код}\`.\n`,
  })
  assert.deepEqual(
    нарушения.map((н) => [н.род, н.код]),
    [["долг закрыт", код]],
    "долг закрыли, а пометка «объявлено, не сделано» осталась — и стала неправдой",
  )
})

test("каждая запись списка называет место и довод, а не «так исторически»", () => {
  assert.ok(ОБЪЯВЛЕНО_НЕ_СДЕЛАНО.length > 0, "список пуст — тогда и проверять нечего")
  for (const запись of ОБЪЯВЛЕНО_НЕ_СДЕЛАНО) {
    assert.match(запись.код, /^FLANG_[A-Z0-9_]+$/u)
    assert.ok(запись.где.endsWith(".md"), `${запись.код}: место обязано быть файлом прозы`)
    assert.ok(
      (ДЕРЕВО.вПрозе.get(запись.код) ?? []).some((м) => м.файл === запись.где),
      `${запись.код}: список называет ${запись.где}, а кода там нет — запись протухла`,
    )
    assert.ok(
      запись.почему.length > 80,
      `${запись.код}: довод короче фразы «так исторически» — такой довод не довод`,
    )
  }
})

