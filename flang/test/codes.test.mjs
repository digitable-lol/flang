/**
 * Коды бед, названные ПРОЗОЙ, — и то, что за каждым что-то стоит.
 *
 * ── Откуда взялся ───────────────────────────────────────────────────────────
 *
 * `flang/test/manpage.test.mjs` уже требует этого от ОДНОГО файла: «каждый
 * FLANG_*, названный в разделе ДИАГНОСТИКА страницы руководства, обязан
 * встречаться в исходниках». Довод там записан коротко и полностью: выдуманный
 * код в документации хуже отсутствующего — по нему ищут и не находят.
 *
 * Довод этот ничем не связан со страницей руководства, а проверка стояла только
 * на ней. Замер по дереву на 15 августа 2026: в 53 файлах `.md` названо 69
 * различных имён `FLANG_*`, и ДВА из них не существовали нигде, кроме прозы, —
 * `FLANG_NODE_DEAD` (`flang/conc/DISTRIBUTED.md`) и `FLANG_LAW_LIMIT`
 * (`flang/cat/SPEC.md`). Оба назывались так, будто работают. Смотрит сторож на
 * 52 из этих 53: `CHANGELOG.md` печатается из истории и руками не правится
 * (см. `этоПроза`).
 *
 * ── Две честные судьбы у такого имени, и третьей нет ────────────────────────
 *
 * Либо код СУЩЕСТВУЕТ — его кто-то печатает, и по нему можно искать. Либо он
 * стоит в ЯВНОМ СПИСКЕ необещанного — таблице в том же документе, где имя
 * названо, с вердиктом и доводом. Вердиктов ровно два, и они разные:
 *
 *   • `объявлено, не сделано` — обещано на будущее, сегодня не работает. Та же
 *     пометка, какой размечена ведомость `flang/conc/DISTRIBUTED.md`: из 44 её
 *     утверждений 20 помечены ею (счёт по дереву, 15 августа 2026), и документ
 *     от этого не стал хуже — он стал проверяемым;
 *   • `отвергнуто` — кода не будет НИКОГДА, и назван он затем, чтобы объяснить,
 *     почему выбран другой. Так назван `FLANG_NODE_DEAD`: утверждать смерть
 *     узла нечем, поэтому отказ объявляется о СВЯЗИ. Пометить такое имя как
 *     «объявлено, не сделано» значило бы соврать вторым способом.
 *
 * Третий путь — стереть упоминание и промолчать — запрещён именно потому, что
 * выглядит чище всех: обещание, тихо убранное из документа, остаётся ложью, но
 * теперь незаметной.
 *
 * ── Что считается исходником, и почему не всё подряд ────────────────────────
 *
 * Опасность у широкого набора одна, зато крупная: ЛОЖНАЯ ЗЕЛЁНАЯ. Код, названный
 * в `.md`, не должен считаться существующим потому, что его же называет другая
 * проза. Поэтому из набора исходников вычтены:
 *
 *   • сама проза — все `.md`;
 *   • `packaging/` — страница руководства и формула Homebrew: это тоже рассказ
 *     о языке, а не язык. Страницу стережёт `manpage.test.mjs` тем же способом;
 *   • тесты — каталоги `test/` и файлы вида `имя.test.mjs`: тест ПРО код не есть
 *     код, а комментарий в тесте — такая же проза;
 *   • `changelog.json` и `CHANGELOG.md` — печатаются из истории, а не пишутся.
 *
 * Всё остальное дерево считается исходником целиком: компилятор на JS и на
 * flang, рантайм на C, восемь бэкендов, инструменты, скрипты, примеры,
 * библиотека. Проверено при заведении сторожа: сужение набора (без тестов, без
 * журнала, без упаковки) не меняет ответа — ненайденных имён как было два, так и
 * осталось. Значит строгость здесь ничего не стоит, а покупает многое.
 *
 * ── Чего сторож не делает ───────────────────────────────────────────────────
 *
 * Он не проверяет, что код ДОСТИЖИМ: строка в исходнике может лежать в ветке,
 * куда не попасть. Это другая работа, и её делают анализ непокрытых отказов
 * (`src/failures.mjs`) и сетка семян в `failures.test.mjs` — там «замкнуто» и
 * доказывается прогоном. Здесь проверяется вещь более скромная и потому
 * бесспорная: по имени, названному читателю, есть что найти.
 *
 * Он не отличает код в исходнике от кода, названного в КОММЕНТАРИИ исходника:
 * комментарий — тоже проза, и имя, живущее только в нём, сторож считал бы
 * существующим. Мерено при заведении: таких имён СЕГОДНЯ ноль — все 69
 * встречаются в коде со снятыми комментариями. Значит дыра пока пустая, и
 * закрывать её разбором комментариев (со строковыми литералами, регулярными
 * выражениями и восемью языками печати) дороже, чем она стоит.
 *
 * Запуск: node --test flang/test/codes.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync, readdirSync, statSync } from "node:fs"
import { join, relative } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))

/** Каталоги, которых в дереве исходников нет: чужое, собранное, временное. */
const ПРОПУСК = new Set(["node_modules", "dist", ".git", ".claude", "output", "coverage"])

/** Имя `FLANG_*` как его пишут везде — в прозе, в коде и на проводе. */
const ИМЯ = /\bFLANG_[A-Z0-9_]+\b/gu

/** Заголовок списка необещанного. Одна строка на документ, дословно. */
export const ЗАГОЛОВОК_СПИСКА = "Коды, названные здесь и не существующие"

/** Два вердикта, и оба обязаны быть выбраны, а не написаны как придётся. */
export const ВЕРДИКТЫ = new Set(["объявлено, не сделано", "отвергнуто"])

/**
 * Довод короче этого — не довод. Число взято не с потолка: «нет», «пока»,
 * «см. выше» короче, а любая настоящая причина длиннее.
 */
const ДОВОД_ОТ = 20

/* ─────────────────────────────── обход дерева ────────────────────────────── */

function файлыДерева(каталог, собранное = []) {
  /* Порядок имён — свой, а не тот, в котором их отдала файловая система: список
     нарушений сравнивается целиком, и он обязан быть одинаков на двух машинах. */
  for (const имя of readdirSync(каталог).sort()) {
    if (ПРОПУСК.has(имя)) continue
    const путь = join(каталог, имя)
    if (statSync(путь).isDirectory()) файлыДерева(путь, собранное)
    else собранное.push(путь)
  }
  return собранное
}

/**
 * Проза — это `.md`: там документ говорит с человеком.
 *
 * Кроме `CHANGELOG.md`, и вот почему. Он ПЕЧАТАЕТСЯ из тегов и тем коммитов
 * (`npm run changelog`), править его руками запрещено, и тема коммита, назвавшая
 * код, живёт в истории навсегда. Красный сторож, который чинится только
 * переписыванием истории, — это сторож, которого через неделю выключат. Дыра
 * названа честно: тема коммита здесь не проверяется ничем, и код, названный
 * только в ней, сторож пропустит.
 */
export function этоПроза(отн) {
  return отн.endsWith(".md") && отн !== "CHANGELOG.md"
}

/** Исходник — всё, кроме прозы, упаковки, тестов и печатаемого журнала. */
export function этоИсходник(отн) {
  if (отн.endsWith(".md")) return false
  if (отн.startsWith("packaging/")) return false
  if (отн === "changelog.json") return false
  if (/(?:^|\/)tests?\//u.test(отн)) return false
  if (/\.test\.[a-z]+$/u.test(отн)) return false
  return true
}

function прочитать(путь) {
  try {
    return readFileSync(путь, "utf8")
  } catch {
    return ""
  }
}

/** Имена, названные текстом, без повторов. */
export function именаТекста(текст) {
  return new Set(текст.match(ИМЯ) ?? [])
}

/* ──────────────────────────── список необещанного ────────────────────────── */

/**
 * Строки списка необещанного из текста документа.
 *
 * Читается ТОЛЬКО под своим заголовком, и это не придирка к оформлению: иначе
 * любая таблица, где имя кода попало в первую клетку, молча стала бы
 * разрешением. Разрешение обязано быть написано намеренно.
 */
export function списокНеобещанного(текст) {
  const строки = текст.split("\n")
  const начало = строки.findIndex((с) => новыйЗаголовок(с) && с.includes(ЗАГОЛОВОК_СПИСКА))
  if (начало < 0) return []
  const записи = []
  for (let i = начало + 1; i < строки.length; i++) {
    const строка = строки[i]
    if (новыйЗаголовок(строка)) break
    const тело = строка.trim()
    if (!тело.startsWith("|")) continue
    const ячейки = тело.replace(/^\|/u, "").replace(/\|$/u, "").split("|").map((я) => я.trim())
    if (ячейки.length < 3) continue
    const код = ячейки[0].match(/FLANG_[A-Z0-9_]+/u)?.[0]
    /* Шапка таблицы и разделитель кода не называют — они и не записи. */
    if (код === undefined) continue
    записи.push({ код, вердикт: ячейки[1].replace(/\*/gu, "").trim(), довод: ячейки[2].trim() })
  }
  return записи
}

function новыйЗаголовок(строка) {
  return /^#{1,6}\s/u.test(строка)
}

/* ─────────────────────────────────── сверка ──────────────────────────────── */

/**
 * Сверка прозы с исходниками. Чистая функция от двух отображений — ровно затем,
 * чтобы её саму можно было проверить подложенными случаями, а не только на
 * настоящем дереве: сторож, который не умеет краснеть, выглядит точно так же,
 * как сторож, у которого всё хорошо.
 *
 * @param {Map<string, string>} проза путь → текст документа
 * @param {Set<string>} вИсходниках имена, встречающиеся в коде
 * @returns {Array<{вид: string, код: string, файл: string, почему: string}>}
 */
export function сверить(проза, вИсходниках) {
  const нарушения = []
  for (const [путь, текст] of проза) {
    const записи = списокНеобещанного(текст)
    const вСписке = new Map(записи.map((з) => [з.код, з]))

    for (const запись of записи) {
      if (вИсходниках.has(запись.код)) {
        нарушения.push({
          вид: "список устарел",
          код: запись.код,
          файл: путь,
          почему: `«${запись.код}» стоит в списке необещанного, а в исходниках он есть: ` +
            "список врёт в другую сторону — снимите строку",
        })
      } else if (!ВЕРДИКТЫ.has(запись.вердикт)) {
        нарушения.push({
          вид: "чужой вердикт",
          код: запись.код,
          файл: путь,
          почему: `вердикт «${запись.вердикт}» не из двух разрешённых: ` +
            [...ВЕРДИКТЫ].map((в) => `«${в}»`).join(" или "),
        })
      } else if (запись.довод.length < ДОВОД_ОТ) {
        нарушения.push({
          вид: "вердикт без довода",
          код: запись.код,
          файл: путь,
          почему: "вердикт без причины — то же молчание, только в таблице",
        })
      }
    }

    for (const имя of именаТекста(текст)) {
      if (вИсходниках.has(имя)) continue
      if (вСписке.has(имя)) continue
      нарушения.push({
        вид: "нет в исходниках",
        код: имя,
        файл: путь,
        почему: `проза называет «${имя}», а в исходниках его нет: либо заведите код, ` +
          `либо поставьте его в список «${ЗАГОЛОВОК_СПИСКА}» этого файла с вердиктом`,
      })
    }
  }
  return нарушения
}

/** Дерево как два отображения: проза и имена исходников. */
export function снятьСДерева(корень = КОРЕНЬ) {
  const проза = new Map()
  const вИсходниках = new Set()
  let исходников = 0
  for (const путь of файлыДерева(корень)) {
    const отн = relative(корень, путь).split("\\").join("/")
    if (этоПроза(отн)) {
      проза.set(отн, прочитать(путь))
    } else if (этоИсходник(отн)) {
      исходников++
      for (const имя of именаТекста(прочитать(путь))) вИсходниках.add(имя)
    }
  }
  return { проза, вИсходниках, исходников }
}

const дерево = снятьСДерева()

const словами = (нарушения) =>
  нарушения.map((н) => `  ${н.файл}: ${н.почему}`).join("\n")

/* ───────────────────────────── настоящее дерево ──────────────────────────── */

test("сторож смотрит на всё дерево, а не в пустоту", () => {
  /* Первая проверка — про сам сторож. Обход, который перестал что-то находить
     (переехал каталог, сменилось расширение), зелен ровно так же, как обход, у
     которого всё сошлось. Числа взяты с замера 15 августа 2026 и держатся снизу:
     расти дереву не запрещено, а вот схлопнуться незаметно — да. */
  assert.ok(дерево.проза.size >= 50, `документов .md найдено ${дерево.проза.size} — обход прозы обмелел`)
  assert.ok(дерево.исходников >= 400, `исходников найдено ${дерево.исходников} — обход кода обмелел`)
  assert.ok(дерево.вИсходниках.size >= 80, `имён в исходниках ${дерево.вИсходниках.size} — обход кода обмелел`)
  const названные = new Set()
  for (const текст of дерево.проза.values()) for (const имя of именаТекста(текст)) названные.add(имя)
  assert.ok(названные.size >= 60, `имён в прозе ${названные.size} — обход прозы обмелел`)
})

test("каждый код, названный прозой дерева, существует или стоит в списке необещанного", () => {
  const нарушения = сверить(дерево.проза, дерево.вИсходниках)
  assert.deepEqual(нарушения, [], `коды без исходника и без вердикта:\n${словами(нарушения)}`)
})

test("необещанного сегодня ровно одно имя, и вердикт у него «отвергнуто»", () => {
  /* Ведомость, а не украшение: пока список короткий, его читают. Каждая новая
     строка обязана быть замечена здесь — то есть человеком, а не сборкой. */
  const необещанное = []
  for (const [путь, текст] of дерево.проза) {
    for (const запись of списокНеобещанного(текст)) необещанное.push([запись.код, путь, запись.вердикт])
  }
  assert.deepEqual(необещанное, [
    ["FLANG_NODE_DEAD", "flang/conc/DISTRIBUTED.md", "отвергнуто"],
  ])
})

/* ──────────────────────── подложенные случаи: изъятие ────────────────────── */

const списком = (текст) => new Map([["проба.md", текст]])
const исходники = new Set(["FLANG_TYPE", "FLANG_LINK_DOWN"])

test("выдуманный код в прозе — отказ, и сторож называет файл", () => {
  const нарушения = сверить(списком("Ошибка `FLANG_NEVER_WAS` приезжает сюда.\n"), исходники)
  assert.equal(нарушения.length, 1)
  assert.equal(нарушения[0].вид, "нет в исходниках")
  assert.equal(нарушения[0].код, "FLANG_NEVER_WAS")
  assert.equal(нарушения[0].файл, "проба.md")
})

test("существующий код прозе разрешён без всякого списка", () => {
  assert.deepEqual(сверить(списком("Не сошлось — `FLANG_TYPE`.\n"), исходники), [])
})

const сСписком = (строки) =>
  списком([
    "# Проба",
    "",
    `## ${ЗАГОЛОВОК_СПИСКА}`,
    "",
    "| код | вердикт | почему |",
    "|---|---|---|",
    ...строки,
    "",
  ].join("\n"))

test("код с вердиктом «объявлено, не сделано» сторожа устраивает", () => {
  const текст = сСписком(["| `FLANG_LATER` | **объявлено, не сделано** | форма есть, печати нет — работа впереди |"])
  assert.deepEqual(сверить(текст, исходники), [])
})

test("код с вердиктом «отвергнуто» сторожа устраивает", () => {
  const текст = сСписком(["| `FLANG_NEVER` | **отвергнуто** | утверждать это нечем, поэтому выбран другой код |"])
  assert.deepEqual(сверить(текст, исходники), [])
})

test("вердикт не из двух разрешённых — отказ: «когда-нибудь» не вердикт", () => {
  const текст = сСписком(["| `FLANG_LATER` | **когда-нибудь** | форма есть, печати нет — работа впереди |"])
  const нарушения = сверить(текст, исходники)
  assert.equal(нарушения.length, 1)
  assert.equal(нарушения[0].вид, "чужой вердикт")
})

test("вердикт без довода — отказ: причина обязана быть написана", () => {
  const текст = сСписком(["| `FLANG_LATER` | **объявлено, не сделано** | пока нет |"])
  const нарушения = сверить(текст, исходники)
  assert.equal(нарушения.length, 1)
  assert.equal(нарушения[0].вид, "вердикт без довода")
})

test("строка про существующий код — отказ: список врёт в другую сторону", () => {
  const текст = сСписком(["| `FLANG_TYPE` | **объявлено, не сделано** | это неправда: код существует и печатается |"])
  const нарушения = сверить(текст, исходники)
  assert.equal(нарушения.length, 1)
  assert.equal(нарушения[0].вид, "список устарел")
})

test("таблица вне своего заголовка разрешением не становится", () => {
  /* Иначе сторожа обходили бы случайно: таблица кодов в другом разделе молча
     превратилась бы в белый список. */
  const текст = списком([
    "# Проба",
    "",
    "## Просто таблица",
    "",
    "| код | вердикт | почему |",
    "|---|---|---|",
    "| `FLANG_NEVER_WAS` | **отвергнуто** | причина, написанная не в том разделе |",
    "",
  ].join("\n"))
  const нарушения = сверить(текст, исходники)
  assert.equal(нарушения.length, 1)
  assert.equal(нарушения[0].вид, "нет в исходниках")
})
