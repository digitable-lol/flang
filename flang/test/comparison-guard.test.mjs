/**
 * Сторож предобработки свидетеля — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/comparison-guard.mjs`.
 * Обязательств пять, и они разные:
 *
 *   1. на дереве сторож ЧИСТ — всякая предобработка свидетеля названа в своём
 *      файле и вписана в поимённый список;
 *   2. сторож ЛОВИТ УЗОР, ради которого написан: `emitC(markMeasureGuards(…))`
 *      без второй отметки переднего края;
 *   3. сторож ЛОВИТ ПРЯТКИ: предобработка есть, а блока с доводом нет;
 *   4. сторож ЛОВИТ ДОВОД, не отвечающий на единственный вопрос — что
 *      покраснеет, если предобработку убрать;
 *   5. поимённый список краснеет В ОБЕ СТОРОНЫ: новый файл без записи — красно,
 *      запись без файла — тоже.
 *
 * Пятое — не выдумка на будущее, а то, чем список отличается от свалки. Список,
 * краснеющий в одну сторону, — это выключатель сторожа, и однажды в этом дереве
 * он им и стал (`docs/zettel/checks-that-stopped-comparing.md`, четвёртый
 * случай: изъятие зазеленело, перестав проверять).
 *
 * Запуск: node --test flang/test/comparison-guard.test.mjs
 */
import assert from "node:assert/strict"
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { КОРЕНЬ, МАРКЕР, ПРЕДОБРАБОТКА, ПРЕОБРАЗОВАТЕЛИ, проверить, собрать } from "../scripts/comparison-guard.mjs"

/**
 * Прогон сторожа по временному дереву.
 *
 * Список ПРЕДОБРАБОТКА в подложенном дереве не действует ни на одно имя (в нём
 * нет ни одного из тамошних файлов), поэтому подложенный файл всегда даёт заодно
 * «нет в списке». Пробы ниже спрашивают про РОД нарушения, а не про их число.
 */
async function наДереве(файлы) {
  const каталог = await mkdtemp(join(tmpdir(), "comparison-guard-"))
  try {
    for (const [имя, текст] of Object.entries(файлы)) {
      const путь = join(каталог, имя)
      await mkdir(join(путь, ".."), { recursive: true })
      await writeFile(путь, текст, "utf8")
    }
    return проверить(каталог)
  } finally {
    await rm(каталог, { recursive: true, force: true })
  }
}

/** Довод, который сторож обязан принять: длинный и с ответом на вопрос. */
const ДОВОД =
  `/*\n * ${МАРКЕР} markMeasureGuards, markProven — обе отметки переднего края\n` +
  " * свидетеля, и печатает он только программу с обеими. Без них сверка сличала бы\n" +
  " * эталона с печатью, которой у свидетеля не бывает, и молчала бы обо всех\n" +
  " * местах, где свидетель печатает выражение, а эталон — вызов помощника.\n */\n"

test("на дереве репозитория сторож чист", () => {
  const нарушения = проверить(КОРЕНЬ)
  assert.deepEqual(
    нарушения.map((н) => `${н.род}: ${н.файл}:${н.строка} — ${н.чего}`),
    [],
    "предобработка свидетеля спрятана в выражении либо разошлась с поимённым списком",
  )
})

test("обход доходит до всех сверок эталона, а не молчит по недосмотру", () => {
  /* Зелёный сторож обязан быть зелёным ОТ ЧИСТОТЫ, а не оттого, что обход
     однажды сузили и он перестал видеть половину дерева. Улики — три сверки из
     разных углов: печать в C, отметка меры, связывание. */
  const дерево = собрать(КОРЕНЬ)
  assert.ok(дерево.size >= 30, `сверок эталона найдено всего ${дерево.size} — обход сузился`)
  for (const файл of [
    "flang/test/self-bootstrap.test.mjs",
    "flang/test/self-totality.test.mjs",
    "flang/test/self-link.test.mjs",
  ]) {
    assert.ok(дерево.has(файл), `${файл} не попал в обход`)
  }
  const мест = [...дерево.values()].reduce((сумма, { зовёт }) => сумма + зовёт.length, 0)
  assert.ok(мест >= 20, `мест предобработки найдено всего ${мест} — образец перестал ловить`)
})

test("сторож ЛОВИТ узор, ради которого написан: одна отметка переднего края из двух", async () => {
  /* Ровно то выражение, которым сверка молчала: печать программы, которой
     свидетель не отдаёт никому. */
  const нарушения = await наДереве({
    "flang/test/self-выдумка.test.mjs":
      'import { emitC } from "../src/emit/c.mjs"\n' +
      'import { markMeasureGuards } from "../src/totality.mjs"\n' +
      ДОВОД +
      "const свидетель = emitC(markMeasureGuards(программа), ПРЕДЕЛЫ)\n",
  })
  const узор = нарушения.filter((н) => н.род === "половина отметки")
  assert.deepEqual(
    узор.map((н) => [н.файл, н.чего]),
    [["flang/test/self-выдумка.test.mjs", "markProven"]],
    "сверка кормит печатник свидетеля программой с одной отметкой из двух, а сторож молчит",
  )
})

test("сторож МОЛЧИТ, когда обе отметки переднего края на месте", async () => {
  const нарушения = await наДереве({
    "flang/test/self-выдумка.test.mjs":
      'import { emitC } from "../src/emit/c.mjs"\n' +
      ДОВОД +
      "const свидетель = emitC(markProven(markMeasureGuards(программа)), ПРЕДЕЛЫ)\n",
  })
  assert.deepEqual(
    нарушения.filter((н) => н.род === "половина отметки"),
    [],
    "обе отметки стоят, а сторож жалуется — он требует не того, что обещал",
  )
})

test("правило пары спрашивается только там, где программу получает ПЕЧАТНИК", () => {
  /* Сверка САМОГО преобразования печатника не зовёт, и второй отметки от неё
     требовать не за что: её предмет — одна функция, а не программа, уезжающая
     в печать. Улика живая: `self-totality.test.mjs` сличает «Отметить меры» с
     `markMeasureGuards` и `markProven` не зовёт — и это законно. */
  const дерево = собрать(КОРЕНЬ)
  const отметки = дерево.get("flang/test/self-totality.test.mjs")
  assert.deepEqual(отметки.зовёт, ["markMeasureGuards"])
  assert.equal(отметки.печатает, false, "сверка отметки зовёт печатник — довод правила исчез")
  const печать = дерево.get("flang/test/self-emit-c.test.mjs")
  assert.equal(печать.печатает, true, "сверка печати печатника не зовёт — образец перестал ловить")
})

test("сторож ЛОВИТ прятки: предобработка есть, а довода нет", async () => {
  const нарушения = await наДереве({
    "flang/test/self-выдумка.test.mjs": "const свидетель = emitC(markProven(markMeasureGuards(программа)))\n",
  })
  assert.deepEqual(
    нарушения.filter((н) => н.род === "не названа").map((н) => н.файл),
    ["flang/test/self-выдумка.test.mjs"],
    "предобработка спрятана в выражении, а сторож её не увидел",
  )
})

test("сторож ЛОВИТ довод, не отвечающий на единственный вопрос", async () => {
  /* Довод длинный, все имена названы — и всё равно красно: он не говорит, что
     покраснеет, если предобработку убрать. Ровно этим вопросом законная
     предобработка отличается от незаконной, и ответ на него нельзя пропустить
     молча. */
  const безОтвета =
    `/*\n * ${МАРКЕР} markMeasureGuards, markProven — так делает передний край\n` +
    " * свидетеля, и здесь сделано так же, потому что иначе печать получила бы не ту\n" +
    " * программу, а это исторически сложившийся порядок, менять который незачем.\n */\n"
  const нарушения = await наДереве({
    "flang/test/self-выдумка.test.mjs": безОтвета + "const свидетель = emitC(markProven(markMeasureGuards(п)))\n",
  })
  assert.deepEqual(
    нарушения.filter((н) => н.род === "нет ответа").map((н) => н.файл),
    ["flang/test/self-выдумка.test.mjs"],
    "довод молчит о том, что покраснеет без предобработки, а сторож этого не заметил",
  )
})

test("сторож ЛОВИТ короткий довод — «так исторически» доводом не считается", async () => {
  const нарушения = await наДереве({
    "flang/test/self-выдумка.test.mjs":
      `/* ${МАРКЕР} markMeasureGuards, markProven — так надо, без них не работает */\n` +
      "const свидетель = emitC(markProven(markMeasureGuards(п)))\n",
  })
  assert.deepEqual(
    нарушения.filter((н) => н.род === "довод не довод").map((н) => н.файл),
    ["flang/test/self-выдумка.test.mjs"],
  )
})

test("поимённый список краснеет В ОБЕ СТОРОНЫ", async () => {
  /* Сторона первая: файл предобрабатывает свидетеля и в списке его нет. */
  const новый = await наДереве({
    "flang/test/self-выдумка.test.mjs": ДОВОД + "const э = emitC(markProven(markMeasureGuards(п)))\n",
  })
  assert.deepEqual(
    новый.filter((н) => н.род === "нет в списке").map((н) => н.файл),
    ["flang/test/self-выдумка.test.mjs"],
    "новая предобработка просочилась мимо списка",
  )

  /* Сторона вторая: запись в списке есть, а предобработки в дереве нет. */
  const пусто = await наДереве({ "flang/test/self-пусто.test.mjs": "const э = 1\n" })
  assert.deepEqual(
    пусто.filter((н) => н.род === "список протух").map((н) => н.файл).sort(),
    ПРЕДОБРАБОТКА.map((з) => з.файл).sort(),
    "протухшая запись списка не краснеет — список превратился в свалку",
  )
})

test("каждая запись списка называет файл и набор преобразователей, а не «прочее»", () => {
  assert.ok(ПРЕДОБРАБОТКА.length > 0, "список пуст — тогда и проверять нечего")
  const дерево = собрать(КОРЕНЬ)
  for (const запись of ПРЕДОБРАБОТКА) {
    assert.match(запись.файл, /^flang\/test\/self-[a-z-]+\.test\.mjs$/u, `${запись.файл}: не путь сверки эталона`)
    assert.ok(запись.зовёт.length > 0, `${запись.файл}: запись без единого имени ничего не называет`)
    for (const имя of запись.зовёт) {
      assert.ok(ПРЕОБРАЗОВАТЕЛИ.includes(имя), `${запись.файл}: ${имя} не преобразователь программы`)
    }
    assert.ok(дерево.has(запись.файл), `${запись.файл}: запись есть, а файла в дереве нет`)
  }
})
