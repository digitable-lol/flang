/**
 * СЛОВАРЬ МЕЖДУ ДВУМЯ СПЕКАМИ — и то, что он перестал быть немым.
 *
 * ── Зачем эта конструкция вообще существует ─────────────────────────────────
 *
 * Замысел языка: спеки бизнес-требований пишутся на flang, легаси-система
 * закрыта одной спекой, новое требование приходит другой, и машина обязана
 * уметь сказать, что второе противоречит первому. Сравнить две спеки можно
 * только зная, ЧТО ЧЕМУ соответствует: в одной «Покупка», в другой «Счёт», и
 * без словаря сравнивать нечего. Функтор и есть этот словарь — конструкция,
 * которой нет ни в одном другом формате требований.
 *
 * ── Что было замерено ДО этих тестов ────────────────────────────────────────
 *
 * Разбор строил из функтора ПОЛНЫЙ узел: `imports` (пары «категория → путь»),
 * `objects` с `fields` внутри, `morphisms`. Не терялось ничего. Читать этот
 * узел было некому:
 *
 *   • `imports` не встречается в `flang/src/types.mjs` ни разу — пути на спеки
 *     не открывал никто. `link.mjs` их тоже не трогает: строка `использует`
 *     ВНУТРИ функтора уезжает в `value.imports`, а не в импорты модуля;
 *   • `fields` не встречается в `checkFunctors` (`types.mjs`, 2186–2400) ни
 *     разу. Так это и записано в контракте (`flang/cat/SPEC.md`): «Полей
 *     перевода компилятор не видит… не проверяется ничем».
 *
 * Улика была одна и предъявлялась прогоном: `flang check` на образце
 * `fixtures/fts-naslediye/скидки-в-подписки.fts` отвечал
 * `{"valid":true,"module":"Скидка в подписку","functions":[],"types":[],
 * "diagnostics":[]}` и кодом 0 — при том, что оба пути `использует` в этом файле
 * ведут в каталог `specs/`, которого в дереве нет, а объекты «Заказ» и
 * «Подписка» не объявлены нигде. Словарь, который можно написать на
 * несуществующие слова, — не словарь.
 *
 * ── Что стережёт этот файл ──────────────────────────────────────────────────
 *
 * Изъятием, а не рассуждением: три испорченных словаря лежат в фикстурах рядом
 * с целым, отличаются от него одной строкой, и каждый обязан покраснеть СВОИМ
 * кодом. Красное и зелёное берутся из одного и того же прогона, иначе
 * «проверка работает» было бы утверждением о коде, который никто не запускал.
 *
 * Чего эти тесты НЕ утверждают: что требования двух спек не противоречат друг
 * другу. Это следующий слой и другая работа. Здесь доказано ровно то, что
 * словарь, которым тот слой будет пользоваться, состоит из существующих слов.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { checkFunctorDictionary } from "../src/compat.mjs"
import { parse } from "../src/parser.mjs"

const ФИКСТУРЫ = resolve(dirname(fileURLToPath(import.meta.url)), "fixtures")
const СЛОВАРИ = `${ФИКСТУРЫ}/fts-slovar`

/** Прогон проверки на файле: чтение и разбор подаются извне, как их и ждут. */
function проверить(файл) {
  const программа = parse(readFileSync(файл, "utf8"), файл)
  const итог = checkFunctorDictionary(программа, {
    file: файл,
    read: (путь) => readFileSync(путь, "utf8"),
    parse,
  })
  return {
    ...итог,
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
  }
}

test("целый словарь проверен, и число проверенного названо", () => {
  const итог = проверить(`${СЛОВАРИ}/slovar.fts`)
  assert.deepEqual(итог.diagnostics, [])
  assert.equal(итог.valid, true)
  /* Числа здесь не украшение: `valid: true` при нуле сравнений — ровно та
     ложная зелёная, от которой заведена вся проверка. Один функтор, один
     объект, два поля — и ни одного поля источника, оставшегося без образа. */
  assert.deepEqual(итог.checked, { functors: 1, objects: 1, fields: 2, unmapped: 0 })
})

test("поле, которого нет ни с одной стороны, названо с обеих", () => {
  const итог = проверить(`${СЛОВАРИ}/slovar-net-polya.fts`)
  assert.equal(итог.valid, false)
  assert.deepEqual(итог.коды, ["FLANG_FUNCTOR_DICTIONARY", "FLANG_FUNCTOR_DICTIONARY"])
  assert.match(итог.тексты[0], /у объекта «Покупка» нет поля «скидка»/u)
  assert.match(итог.тексты[1], /у объекта «Счёт» такого поля нет/u)
  /* Что БЫЛО в спеке — половина находки: без списка имён автор идёт открывать
     чужой файл и читать его глазами, а с ним видит опечатку сразу. */
  assert.match(итог.тексты[0], /есть «сумма», «постоянный клиент»/u)
  assert.match(итог.тексты[1], /есть «сумма без НДС», «лояльный»/u)
  /* Объект СОШЁЛСЯ, поля — нет: и то и другое обязано быть видно числом. */
  assert.deepEqual(итог.checked, { functors: 1, objects: 1, fields: 0, unmapped: 2 })
})

test("перевод числа в признак — отдельная беда со своим кодом", () => {
  const итог = проверить(`${СЛОВАРИ}/slovar-chuzhoy-tip.fts`)
  assert.equal(итог.valid, false)
  assert.deepEqual(итог.коды, ["FLANG_FUNCTOR_FIELD_TYPE"])
  assert.match(итог.тексты[0], /«Покупка\.сумма» — number/u)
  assert.match(итог.тексты[0], /«Счёт\.лояльный» — flag/u)
  /* Оба имени существуют — беда именно в типах, и код обязан отличаться от
     кода «такого поля нет»: по коду ищут, и два разных изъяна под одним именем
     значили бы, что искать нечем. */
  assert.equal(итог.checked.objects, 1)
  assert.equal(итог.checked.fields, 0)
})

test("объект, которого нет ни в одной спеке, — беда с обеих сторон", () => {
  const итог = проверить(`${СЛОВАРИ}/slovar-net-obyekta.fts`)
  assert.equal(итог.valid, false)
  assert.deepEqual(итог.коды, ["FLANG_FUNCTOR_DICTIONARY", "FLANG_FUNCTOR_DICTIONARY"])
  assert.match(итог.тексты[0], /в спеке «Продажи» такого объекта нет; есть «Покупка»/u)
  assert.match(итог.тексты[1], /в спеке «Биллинг» такого объекта нет; есть «Счёт»/u)
  /* Полей не сверялось ни одного, и `checked` это признаёт: объект не сошёлся,
     значит про его поля не известно НИЧЕГО. Записать их в проверенные значило
     бы посчитать за проверку то, чего не было. */
  assert.deepEqual(итог.checked, { functors: 1, objects: 0, fields: 0, unmapped: 0 })
})

test("образец наследия краснеет: обе спеки ведут в никуда", () => {
  /* Тот самый файл, на котором `flang check` отвечал `valid: true` и кодом 0.
     Здесь он отвечает двумя отказами — по одному на каждую половину словаря. */
  const итог = проверить(`${ФИКСТУРЫ}/fts-naslediye/скидки-в-подписки.fts`)
  assert.equal(итог.valid, false)
  assert.deepEqual(итог.коды, ["FLANG_FUNCTOR_SPEC_MISSING", "FLANG_FUNCTOR_SPEC_MISSING"])
  assert.match(итог.тексты[0], /исходная спека «Скидки» не прочитана/u)
  assert.match(итог.тексты[1], /целевая спека «Подписки» не прочитана/u)
  /* Каскада нет намеренно: спека не прочитана — значит про объекты «Заказ» и
     «Подписка» сказать нечего, и говорить о них второй бедой запрещено. */
  assert.equal(итог.checked.objects, 0)
})

test("категория без строки «использует» названа своей бедой, а не молчанием", () => {
  const исходник = `функтор «Заказ в счёт» из «Продажи» в «Биллинг»
  использует «Продажи» из «./prodazhi.fts»

  объект Покупка отображается в «Счёт»
    поле сумма отображается в поле «сумма без НДС»
`
  const программа = parse(исходник, `${СЛОВАРИ}/проба.fts`)
  const итог = checkFunctorDictionary(программа, {
    file: `${СЛОВАРИ}/проба.fts`,
    read: (путь) => readFileSync(путь, "utf8"),
    parse,
  })
  assert.equal(итог.valid, false)
  assert.deepEqual(итог.diagnostics.map((беда) => беда.code), ["FLANG_FUNCTOR_SPEC_MISSING"])
  assert.match(итог.diagnostics[0].message, /целевая спека «Биллинг» не привезена/u)
})

test("файл, объявляющий не ту категорию, отвергнут: сверялись бы с чужой спекой", () => {
  const исходник = `функтор «Заказ в счёт» из «Продажи» в «Биллинг»
  использует «Продажи» из «./prodazhi.fts»
  использует «Биллинг» из «./prodazhi.fts»

  объект Покупка отображается в «Покупка»
`
  const программа = parse(исходник, `${СЛОВАРИ}/проба.fts`)
  const итог = checkFunctorDictionary(программа, {
    file: `${СЛОВАРИ}/проба.fts`,
    read: (путь) => readFileSync(путь, "utf8"),
    parse,
  })
  assert.equal(итог.valid, false)
  assert.deepEqual(итог.diagnostics.map((беда) => беда.code), ["FLANG_FUNCTOR_SPEC_NAME"])
  assert.match(итог.diagnostics[0].message, /привезена под именем «Биллинг», а файл .* объявляет «Продажи»/u)
})

test("программа без функтора не проверяется и не притворяется проверенной", () => {
  /* Ни одного узла — ни одного чтения файла: `read` и `parse` тут даже не
     нужны, и требовать их значило бы заставить всякого звать проверку с
     платформой в руках. */
  const итог = checkFunctorDictionary({ flang: 1, module: "Пусто", legacy: [] })
  assert.equal(итог.valid, true)
  assert.deepEqual(итог.checked, { functors: 0, objects: 0, fields: 0, unmapped: 0 })
})

test("без чтения и разбора проверка отказывается, а не молчит зелёным", () => {
  const программа = parse(readFileSync(`${СЛОВАРИ}/slovar.fts`, "utf8"), `${СЛОВАРИ}/slovar.fts`)
  /* Молчаливое `valid: true` здесь было бы худшим из возможных ответов: он
     неотличим от «словарь проверен». */
  assert.throws(() => checkFunctorDictionary(программа), /сверять не с чем/u)
})
