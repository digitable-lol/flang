test("семь целей из восьми ОТКАЗЫВАЮТ печатать поручение, и каждая — названным кодом", async () => {
  /* Молчаливая потеря — худший исход, потому что выглядит успехом: Elixir и
     JavaScript печатают процессы честно, а `поручить` в их планировщиках не
     значится вовсе, и напечатанная программа упала бы на «неизвестном действии»
     уже в бою. Отказ говорит об этом там, где это ещё можно изменить. */
  const { emitTargets, loadEmitter } = await import("../bin/flang.mjs")
  const программа = служба()
  const отказали = new Map()
  const напечатали = []
  for (const цель of await emitTargets()) {
    const { emit } = await loadEmitter(цель)
    try {
      emit(программа, {})
      напечатали.push(цель)
    } catch (ошибка) {
      отказали.set(цель, ошибка.diagnostics?.[0]?.code ?? null)
    }
  }
  assert.deepEqual(напечатали, ["c"], `поручение напечатали: ${напечатали.join(", ")}`)
  assert.equal(отказали.size, 7, `отказали ${отказали.size} целей вместо семи`)
  assert.equal(отказали.get("elixir"), IO_UNSUPPORTED_CODE)
  assert.equal(отказали.get("js"), IO_UNSUPPORTED_CODE)
  for (const цель of ["go", "python", "rust", "java", "csharp"]) {
    assert.equal(отказали.get(цель), "FLANG_CONC_UNSUPPORTED", `цель «${цель}» отказала не тем кодом`)
  }
  console.log(`печатают поручение: ${напечатали.join(", ")}; отказывают: ${[...отказали.keys()].join(", ")}`)
})

