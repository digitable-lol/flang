/**
 * Шов между двумя слоями языка: процесс выдаёт ПОРУЧЕНИЕ и получает отклик
 * сообщением (седьмое действие `поручить`).
 *
 * ── Улика, с которой начата работа ──────────────────────────────────────────
 *
 * Слоёв было два, и сделаны они одинаково. Ввод-вывод (`src/io.mjs`): поручение
 * ОПИСЫВАЕТСЯ значением закрытой суммы «Поручение», исполняет его хозяин.
 * Конкурентность (`src/conc.mjs`): действие ОПИСЫВАЕТСЯ значением закрытой суммы
 * «Действие», исполняет его планировщик. Автор ввода-вывода сходство заметил и
 * записал («Ровно та же форма, что у обработчика процесса, и это не
 * совпадение»), а связывать не стал.
 *
 * Цена мерилась двумя отказами на одной программе-службе, и оба сняты прогоном:
 *
 *   вариант «поручить» …             → FLANG_UNKNOWN_NAME
 *   «действия» равным [поручение]    → FLANG_TYPE, «список неоднороден: элемент
 *                                      1 имеет тип «Поручение», а список —
 *                                      «Действие»»
 *
 * Второй — точный диагноз: язык умел ОПИСАТЬ поручение и не умел его ВЫДАТЬ.
 * Сервис — это процессы, которые говорят с миром; писать сервисы было нельзя.
 *
 * ── Что здесь стерегут, по разделам ─────────────────────────────────────────
 *
 *   1. форма седьмого действия и то, что джокеров у него НОЛЬ;
 *   2. проверка типов: адресат обязан принимать «Отклик»;
 *   3. ЗАМКНУТОСТЬ множества отказов — самое дорогое здесь. Отказ поручения
 *      покрыт не надзором, а полнотой разбора по закрытой сумме; полный ящик
 *      остаётся пятым видом, и без него подделка проходит проверку;
 *   4. граница хозяина: что приходит извне, обязано подходить объявленному типу;
 *   5. сетка семян — шесть прогонов «от 1 до 1000», как принято у слоя;
 *   6. настоящий хозяин: служба читает НАСТОЯЩИЙ файл — и на Node, и в
 *      напечатанном C;
 *   7. изъятие: снимаем правку — краснеет названное место, а не что попало;
 *   8. AST девяти примеров конкурентности не изменился ни на байт.
 *
 * Запуск: node --test flang/test/conc-io.test.mjs
 */
