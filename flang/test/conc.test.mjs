/**
 * Модель конкурентности flang — шаги 1, 3 и 5: поверхность, проверки,
 * планировщик эталона, надзор в действии и перебор семян
 * (`flang/conc/SPEC.md`, `flang/src/conc.mjs`).
 *
 * Про надзор (шаг 3) проверяется пять утверждений, и все пять — про поведение,
 * а не про разбор: перезапуск возвращает состояние к НАЧАЛЬНОМУ ЗНАЧЕНИЮ; порог
 * срабатывает ровно на N+1 отказе в окне и не срабатывает, когда окно уехало;
 * «остановить» не перезапускает; «передать выше» доходит до надзора ступенью
 * выше, а если выше никого — до остановки всей программы с названным исходом;
 * и чередование остаётся воспроизводимым по семени даже там, где процессы
 * падают и поднимаются.
 *
 * Четыре вещи проверяются здесь и никем больше.
 *
 * 1. Новое ключевое слово не затеняет существующее имя. Это не абстрактная
 *    осторожность: слово «символы» однажды уже сломало два файла репозитория, и
 *    поверхность пришлось переделывать. Поэтому здесь есть прямая проверка на
 *    «начальное» и «порог» — два слова из контракта конкурентности, которые в
 *    репозитории заняты именами, — и сверка таблицы ключевых слов с корпусом.
 *
 * 2. Проверка типов отвергает то, что контракт велит отвергать: обработчик не
 *    той формы, необъявленный процесс в «отправить», нетотальный обработчик без
 *    запаса витков. Последнее — ошибка, а не предупреждение, и тест смотрит
 *    именно на severity.
 *
 * 3. Одно семя — одно чередование, побайтово. Проверяется не «похоже», а
 *    равенство JSON журнала доставок, полученного двумя независимыми прогонами
 *    после двух независимых разборов исходника. Разные семена дают разные
 *    чередования — иначе семя было бы украшением.
 *
 * 4. Исчерпание запаса витков и бесконечное откладывание дают ОПРЕДЕЛЁННЫЙ
 *    исход, а не зависание. Зависание в тесте выглядело бы как «тест идёт
 *    долго», и его нельзя было бы отличить от медленной машины.
 *
 * 5. Сетка семян перебирается ВСЯ, расхождение называет семя, а множество
 *    итогов проверяется в обе стороны. Одно семя проверяет одно чередование, и
 *    утверждение «состояние не рассыпается ни при каком порядке» им не
 *    проверяется вовсе — см. раздел «сетка семян» ниже.
 */
