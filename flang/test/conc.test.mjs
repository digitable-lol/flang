/** Программа-шаблон: меняем один кусок и смотрим, что скажет проверка. */
function программа({ обработчик, процесс }) {
  return [
    "объект «Счёт»",
    "  «всего»: число",
    "",
    "тип «Команда»",
    "  вариант «прибавить» содержит «сколько»: число",
    "",
    "объект «Отклик»",
    "  «состояние»: «Счёт»",
    "  «действия»: список «Действие»",
    "",
    процесс ?? [
      "процесс «Счётчик»",
      "  состояние «Счёт»",
      "  начинает с «пусто»",
      "  принимает «Команда»",
      "  обрабатывает «шаг»",
    ].join("\n"),
    "",
    "тотальная функция «пусто»",
    "  возвращает «Счёт»",
    "  запись «Счёт» с «всего» равным 0",
    "",
    обработчик ?? [
      "тотальная функция «шаг»",
      "  принимает счёт: «Счёт», сообщение: «Команда»",
      "  возвращает «Отклик»",
      "  разбор сообщение",
      "    случай вариант «прибавить» с «сколько» как сколько",
      "      пусть новое равно (запись «Счёт» с «всего» равным (счёт.«всего» плюс сколько))",
      "      запись «Отклик» с «состояние» равным новое и «действия» равным []",
    ].join("\n"),
    "",
  ].join("\n")
}

test("образцовая программа с процессом проходит проверку без диагностик", () => {
  assert.deepEqual(диагностики(программа({})), [])
})

test("обработчик обязан принимать объявленные состояние и сообщение", () => {
  const чужоеСостояние = программа({
    обработчик: [
      "тотальная функция «шаг»",
      "  принимает счёт: число, сообщение: «Команда»",
      "  возвращает «Отклик»",
      "  запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным счёт) и «действия» равным []",
    ].join("\n"),
  })
  assert.ok(
    диагностики(чужоеСостояние).some((д) => д.code === "FLANG_TYPE" && д.message.includes("состояние объявлено как «Счёт»")),
    JSON.stringify(диагностики(чужоеСостояние)),
  )

  const чужоеСообщение = программа({
    обработчик: [
      "тотальная функция «шаг»",
      "  принимает счёт: «Счёт», сообщение: строка",
      "  возвращает «Отклик»",
      "  запись «Отклик» с «состояние» равным счёт и «действия» равным []",
    ].join("\n"),
  })
  assert.ok(
    диагностики(чужоеСообщение).some((д) => д.code === "FLANG_TYPE" && д.message.includes("сообщение объявлено как «Команда»")),
  )
})

test("обработчик обязан возвращать отклик — запись из состояния и действий", () => {
  /* Не запись вовсе — сказано одной фразой, потому что искать в скаляре поля
     «состояние» и «действия» бессмысленно. */
  const скаляр = программа({
    обработчик: [
      "тотальная функция «шаг»",
      "  принимает счёт: «Счёт», сообщение: «Команда»",
      "  возвращает число",
      "  счёт.«всего»",
    ].join("\n"),
  })
  assert.ok(
    диагностики(скаляр).some((д) => д.code === "FLANG_TYPE" && д.message.includes("обязан возвращать отклик")),
    JSON.stringify(диагностики(скаляр)),
  )

  /* Запись, но не та: называются оба недостающих поля, а не только первое —
     иначе починка шла бы по одной ошибке за прогон. */
  const чужаяЗапись = программа({
    обработчик: [
      "тотальная функция «шаг»",
      "  принимает счёт: «Счёт», сообщение: «Команда»",
      "  возвращает «Счёт»",
      "  счёт",
    ].join("\n"),
  })
  const беды = диагностики(чужаяЗапись).map((д) => д.message)
  assert.ok(беды.some((м) => м.includes("не имеет поля «состояние»")), JSON.stringify(беды))
  assert.ok(беды.some((м) => м.includes("не имеет поля «действия»")), JSON.stringify(беды))
})

