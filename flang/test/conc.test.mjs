/** Диагностики проверки типов: только они решают, принята программа или нет. */
const диагностики = (текст) => checkTypes(parse(текст, "проба.flang")).diagnostics
const коды = (текст) => диагностики(текст).map((д) => д.code)

/* ────────────────────────── затенение имён ──────────────────────────────── */

test("«начальное» и «порог» остались именами: ключевыми словами они не стали", () => {
  /* Оба слова стоят в контракте конкурентности, и оба заняты в репозитории:
     «начальное» — переменная в flang/core/lexer.flang (четыре места), «порог» —
     параметр в flang/stdlib/optional.flang. Ключевое слово запрещает имя,
     значит заводить их было нельзя. */
  assert.equal(keywordId("начальное"), null)
  assert.equal(keywordId("порог"), null)
  assert.equal(keywordId("витков"), null)
  assert.equal(keywordId("миллисекунд"), null)
  assert.equal(keywordId("за"), null)

  const исходник = [
    "тотальная функция «Сумма с порогом»",
    "  принимает элементы: список числа, порог: число",
    "  возвращает число",
    "  пусть начальное равно 0",
    "  свёртка элементы начиная с начальное как акк и эл",
    "    если эл не меньше порог",
    "      то акк плюс эл",
    "      иначе акк",
    "",
  ].join("\n")
  assert.deepEqual(checkTypes(parse(исходник, "проба.flang")).diagnostics, [])
})

test("фраза из двух частей: «порог» отдельно — имя, «порог отказов» — ключевое слово", () => {
  assert.equal(keywordId("порог отказов"), "failureThreshold")
  assert.equal(keywordId("с запасом"), "budget")
  /* Одиночное «с» остаётся предлогом, иначе «соединить a с b» перестало бы
     разбираться. */
  assert.equal(keywordId("с"), "with")

  const токены = tokenize("порог отказов 3 за 5000 миллисекунд\n")
  assert.deepEqual(
    токены.slice(0, 6).map((т) => [т.kind, т.value]),
    [["keyword", "failureThreshold"], ["number", 3], ["name", "за"], ["number", 5000], ["name", "миллисекунд"], ["newline", "\n"]],
  )
})

test("новые слова не встречаются именами ни в одном .flang репозитория", () => {
  /* Прямая проверка того же, что защищает предыдущий тест, но не на пробе, а на
     корпусе: если завтра кто-то заведёт переменную «прогон», тест назовёт файл
     и слово, а не оставит разбираться с «не разобрана конструкция». */
  const новые = ["процесс", "обрабатывает", "надзор", "стратегия", "прогон", "семя"]
  const файлы = [
    "flang/stdlib/lists.flang", "flang/stdlib/numbers.flang", "flang/stdlib/optional.flang",
    "flang/stdlib/result.flang", "flang/stdlib/strings.flang",
    "flang/core/lexer.flang", "flang/core/parser.flang", "flang/core/evaluate.flang", "flang/core/json.flang",
    "flang/self/lexer.flang", "flang/self/parser.flang", "flang/self/types.flang", "flang/self/totality.flang",
  ]
  for (const путь of файлы) {
    const токены = tokenize(readFileSync(`${корень}${путь}`, "utf8"))
    for (const токен of токены) {
      assert.ok(
        !(токен.kind === "keyword" && новые.includes(токен.text)),
        `${путь}: слово «${токен.text}» стало ключевым в файле, который к конкурентности отношения не имеет`,
      )
    }
  }
})

