test("А3: «отложить» и «продолжить» не переполняют собственный ящик", () => {
  /* Сообщение, которое кладут обратно, только что из этого ящика вышло, значит
     места в нём заведомо хватает — и проверять его там нельзя, иначе процесс с
     ящиком на единицу не смог бы отложить ни одного сообщения, то есть
     объявленный потолок в единицу запрещал бы «отложить» вовсе. */
  const текст = [
    "модуль «Упрямец»", "",
    "объект «Пусто»", "  «сколько»: число", "",
    "тип «Что-нибудь»", "  вариант «нечто»", "",
    "объект «Отклик»", "  «состояние»: «Пусто»", "  «действия»: список «Действие»", "",
    "процесс «Упрямец»", "  состояние «Пусто»", "  начинает с «ничего»",
    "  принимает «Что-нибудь» с ящиком 1 сообщений", "  обрабатывает «всегда откладывать»", "",
    "тотальная функция «ничего»", "  возвращает «Пусто»",
    "  запись «Пусто» с «сколько» равным 0", "",
    "тотальная функция «всегда откладывать»",
    "  принимает своё: «Пусто», сообщение: «Что-нибудь»", "  возвращает «Отклик»",
    "  запись «Отклик» с «состояние» равным своё и «действия» равным [(вариант «отложить»)]", "",
  ].join("\n")
  const программа = parse(текст, "упрямец.flang")
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = runConcurrent(программа, {
    kind: "run", name: "упрямство", seed: 1,
    inbox: [{ process: "Упрямец", message: { variant: "нечто", fields: {} } }],
    expected: [],
  }, { maxTurns: 50 })
  assert.equal(итог.исход, "предел пробегов")
  assert.deepEqual(итог.отказы, [])
  assert.ok(итог.журнал.every((з) => з.исход === "отложено"))
})

