test("исчерпание запаса витков — определённый исход, а не зависание", () => {
  const программа = разобрать("budget")
  const итог = runConcurrent(программа, программа.runs[0])

  assert.equal(итог.исход, "покой", "прогон обязан закончиться сам")
  const последняя = итог.журнал[итог.журнал.length - 1]
  assert.equal(последняя.исход, "запас исчерпан")
  assert.equal(последняя.код, "FLANG_BUDGET_EXHAUSTED")
  /* Состояние — то, каким было до непосильного сообщения: обработчик чист,
     поэтому половины изменения не бывает. */
  assert.deepEqual(итог.состояния["Разборщик"], { "сделано": 1 })
  assert.deepEqual(итог.живые, [], "упавший процесс остаётся остановленным: надзора в шаге 1 нет")
  assert.equal(итог.отказы.length, 1)
})

test("бесконечное откладывание упирается в предел пробегов, а не висит", () => {
  /* Процесс, который откладывает всё подряд, готов всегда — планировщику
     никогда не бывает нечего делать. Без предела это был бы вечный цикл, и в
     выводе теста он выглядел бы как «тест идёт долго». */
  const текст = [
    "объект «Пусто»",
    "  «сколько»: число",
    "",
    "тип «Что-нибудь»",
    "  вариант «нечто»",
    "",
    "объект «Отклик»",
    "  «состояние»: «Пусто»",
    "  «действия»: список «Действие»",
    "",
    "процесс «Упрямец»",
    "  состояние «Пусто»",
    "  начинает с «ничего»",
    "  принимает «Что-нибудь»",
    "  обрабатывает «всегда откладывать»",
    "",
    "тотальная функция «ничего»",
    "  возвращает «Пусто»",
    "  запись «Пусто» с «сколько» равным 0",
    "",
    "тотальная функция «всегда откладывать»",
    "  принимает своё: «Пусто», сообщение: «Что-нибудь»",
    "  возвращает «Отклик»",
    "  запись «Отклик» с «состояние» равным своё и «действия» равным [(вариант «отложить»)]",
    "",
  ].join("\n")
  const программа = parse(текст, "упрямец.flang")
  assert.deepEqual(checkTypes(программа).diagnostics, [])

  const прогон = {
    kind: "run",
    name: "упрямство",
    seed: 1,
    inbox: [{ process: "Упрямец", message: { variant: "нечто", fields: {} } }],
    expected: [],
  }
  const итог = runConcurrent(программа, прогон, { maxTurns: 50 })
  assert.equal(итог.исход, "предел пробегов")
  assert.equal(итог.пробегов, 50)
  assert.ok(итог.журнал.every((з) => з.исход === "отложено"))
})

test("взаимная блокировка обнаруживается покоем, а не зависанием", () => {
  /* Два процесса ждут друг друга: сообщений нет, таймеров нет, работы нет.
     Модель такую пару не запрещает (контракт, «Что проверяется и чем»), но
     обнаруживать её обязана — и обнаруживает: прогон заканчивается покоем,
     а состояния остаются начальными. */
  const программа = разобрать("counter")
  const итог = runConcurrent(программа, { ...программа.runs[0], inbox: [] })
  assert.equal(итог.исход, "покой")
  assert.equal(итог.журнал.length, 0)
  assert.deepEqual(итог.состояния["Счётчик"], { "всего": 0 })
})

