test("проверка типов отвергает сетку, которая ничего не проверяет", () => {
  const беды = (прогоны) => checkTypes(parse(гонка(прогоны), "сетка.flang")).diagnostics

  /* «любое из» на одном семени: половина «каждое значение где-то встретилось»
     не может сбыться ни при каком множестве длиннее единицы. */
  const одноСемя = беды([
    "прогон «п»",
    "  семя 1",
    ...дваТика,
    "  ожидается «Сборщик» любое из [(запись «Метки» с «строки» равным [\"Л\", \"П\"])]",
  ])
  assert.ok(одноСемя.some((д) => д.message.includes("одно семя")), JSON.stringify(одноСемя))

  /* И `семя от 5 до 5` — тоже одно семя, как бы сеточно оно ни выглядело.
     Проверка смотрела на ПРЕДЛОГ, а не на длину отрезка, поэтому такой прогон
     проходил проверку молча и краснел уже прогоном, перечисляя «не
     встретилось» для всех значений, кроме доставшегося. */
  const сеткаИзОдного = беды([
    "прогон «п»",
    "  семя от 5 до 5",
    ...дваТика,
    "  ожидается «Сборщик» любое из [",
    "    (запись «Метки» с «строки» равным [\"Л\", \"П\"]),",
    "    (запись «Метки» с «строки» равным [\"П\", \"Л\"])]",
  ])
  assert.ok(
    сеткаИзОдного.some((д) => д.code === "FLANG_PROCESS" && д.message.includes("одно чередование")),
    JSON.stringify(сеткаИзОдного),
  )

  /* Зубы у этой строки двое, и оба нужны: отвергается ОДНО семя, а не сетка
     вообще (отрезок из двух семян проходит), и отвергается `любое из`, а не
     запись `от N до N` (тот же отрезок с `равен` проходит — это законная запись
     одного чередования). */
  const дваСемени = беды([
    "прогон «п»",
    "  семя от 5 до 6",
    ...дваТика,
    "  ожидается «Сборщик» любое из [",
    "    (запись «Метки» с «строки» равным [\"Л\", \"П\"]),",
    "    (запись «Метки» с «строки» равным [\"П\", \"Л\"])]",
  ])
  assert.deepEqual(дваСемени, [], JSON.stringify(дваСемени))

  const отрезокСРавен = беды([
    "прогон «п»",
    "  семя от 5 до 5",
    ...дваТика,
    "  ожидается «Левый» равен (запись «Метки» с «строки» равным [\"Л\"])",
  ])
  assert.deepEqual(отрезокСРавен, [], JSON.stringify(отрезокСРавен))

  /* Пустая сетка сбылась бы, не проверив ничего: утверждение обо всех элементах
     пустого множества истинно. */
  const пустая = беды([
    "прогон «п»",
    "  семя от 9 до 4",
    ...дваТика,
    "  ожидается «Левый» равен (запись «Метки» с «строки» равным [\"Л\"])",
  ])
  assert.ok(пустая.some((д) => д.message.includes("пуста")), JSON.stringify(пустая))

  /* Повтор в множестве обманывает читателя, а не планировщик: значений видно
     три, а итогов два. */
  const повтор = беды([
    "прогон «п»",
    "  семя от 1 до 200",
    ...дваТика,
    "  ожидается «Сборщик» любое из [",
    "    (запись «Метки» с «строки» равным [\"Л\", \"П\"]),",
    "    (запись «Метки» с «строки» равным [\"Л\", \"П\"])]",
  ])
  assert.ok(повтор.some((д) => д.message.includes("повторяется")), JSON.stringify(повтор))

  /* Значение не того типа ловится в каждом элементе множества, а не только в
     первом: чинить по одной ошибке за прогон — плохая сделка. */
  const чужойТип = беды([
    "прогон «п»",
    "  семя от 1 до 200",
    ...дваТика,
    "  ожидается «Сборщик» любое из [",
    "    (запись «Метки» с «строки» равным [\"Л\", \"П\"]),",
    "    (запись «Счёт» с «всего» равным 1)]",
  ])
  assert.ok(
    чужойТип.some((д) => д.code === "FLANG_TYPE" && д.message.includes("итог №2")),
    JSON.stringify(чужойТип),
  )
})

