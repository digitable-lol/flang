test("нетотальный обработчик без запаса витков — ошибка, а не предупреждение", () => {
  const безЗапаса = программа({
    обработчик: [
      "функция «шаг»",
      "  принимает счёт: «Счёт», сообщение: «Команда»",
      "  возвращает «Отклик»",
      "  запись «Отклик» с «состояние» равным счёт и «действия» равным []",
    ].join("\n"),
  })
  const беды = диагностики(безЗапаса)
  const беда = беды.find((д) => д.code === "FLANG_HANDLER_NOT_TOTAL")
  assert.ok(беда, JSON.stringify(беды))
  assert.equal(беда.severity, "error")
  assert.ok(беда.message.includes("с запасом"))

  /* С запасом та же программа принимается — но запас теперь ответ только
     наполовину. Названный запас может кончиться, значит у процесса появился
     достижимый отказ, и надзор над ним стал обязателен (шаг Г1): без строки
     «надзор» та же программа отвергается с `FLANG_UNCOVERED_FAILURE`, и это
     проверено ниже. */
  const сЗапасом = программа({
    процесс: [
      "процесс «Счётчик»",
      "  состояние «Счёт»",
      "  начинает с «пусто»",
      "  принимает «Команда»",
      "  обрабатывает «шаг» с запасом 1000 витков",
      "",
      "надзор «Учёт»",
      "  процесс «Счётчик» стратегия «перезапустить»",
    ].join("\n"),
    обработчик: [
      "функция «шаг»",
      "  принимает счёт: «Счёт», сообщение: «Команда»",
      "  возвращает «Отклик»",
      "  запись «Отклик» с «состояние» равным счёт и «действия» равным []",
    ].join("\n"),
  })
  assert.deepEqual(диагностики(сЗапасом), [])
})

