/* Соответствие поверхности FTS вариантам «Сравнение» из контракта. */
const СРАВНЕНИЯ = { eq: "Равно", neq: "Не равно", gte: "Не меньше", lte: "Не больше", gt: "Больше", lt: "Меньше" }

const вариант = (имя, поля = {}) => ({ variant: имя, fields: поля })

/**
 * `FtsScalar` в значение «Скаляр». Перевод взаимно однозначный: `Object.is`
 * различает 0 и −0, и сумма типов сохраняет это различие — в отличие от
 * текстовой записи, где `String(-0)` даёт «0». Обратный перевод — `скалярВJS`.
 */
function скаляр(значениеJS) {
  if (typeof значениеJS === "string") return вариант("Скаляр строка", { значение: значениеJS })
  if (typeof значениеJS === "number") return вариант("Скаляр число", { значение: значениеJS })
  if (typeof значениеJS === "boolean") return вариант("Скаляр признак", { значение: значениеJS })
  return вариант("Скаляр ничто")
}

const значение = (скалярJS) => вариант("Значение операнда", { скаляр: скаляр(скалярJS) })
const поле = (имя) => вариант("Поле операнда", { поле: имя })
const процент = (доля, имя) => вариант("Процент операнда", { процент: доля, поле: имя })
const результат = () => вариант("Результат операнда")
const присвоить = (операнд) => вариант("Присвоить", { операнд })
const добавить = (операнд) => вариант("Добавить", { операнд })
const условие = (имя, сравнение, операнд) => ({ поле: имя, сравнение: вариант(СРАВНЕНИЯ[сравнение] ?? сравнение), операнд })
const правило = (имя, условия, действие) => ({ имя, условия, действие })
const свойство = (имя, сравнение, операнд) => ({ имя, сравнение: вариант(СРАВНЕНИЯ[сравнение] ?? сравнение), операнд })
const пример = (имя, вход, ожидается) => ({ имя, вход: привязки(вход), ожидается: скаляр(ожидается) })
const привязки = (вход) => Object.entries(вход).map(([имя, зн]) => ({ имя, значение: скаляр(зн) }))

function утилитаИз({ имя, принимает = "Вход", возвращает = "Деньги", начальное = 0, правила = [], свойства = [], примеры = [] }) {
  return { имя, принимает, возвращает, начальное: скаляр(начальное), правила, свойства, примеры }
}

/* Перевод `FtsUtility` ядра в значение «Утилита» — только перекладывание. */
function операнд(item) {
  if (item.kind === "value") return значение(item.value)
  if (item.kind === "field") return поле(item.field)
  if (item.kind === "percent") return процент(item.percent, item.field)
  return результат()
}

function утилита(u) {
  return {
    имя: u.name,
    принимает: u.input,
    возвращает: u.output,
    начальное: скаляр(u.initial),
    правила: u.rules.map((r) => ({
      имя: r.name,
      условия: r.when.map((c) => условие(c.field, c.operator, операнд(c.value))),
      действие: r.action.kind === "set" ? присвоить(операнд(r.action.value)) : добавить(операнд(r.action.value)),
    })),
    свойства: u.properties.map((p) => свойство(p.name, p.operator, операнд(p.value))),
    примеры: u.examples.map((e) => пример(e.name, e.input, e.expected)),
  }
}

/* ─────────────────────────── вызов вычислителя ──────────────────────────── */

/** Итог вычисления в удобном для проверок виде: `{ значение }` либо `{ код, сообщение }`. */
function вычислить(утилитаЗначение, вход) {
  const итог = evaluate(программа, "Вычислить утилиту", { "утилита": утилитаЗначение, вход: привязки(вход) })
  if (итог.variant === "Отказ") return { код: итог.fields.код, сообщение: итог.fields.сообщение }
  return { значение: скалярВJS(итог.fields.значение) }
}

/** Значение «Скаляр» обратно в скаляр JS — для сверки по `Object.is`. */
function скалярВJS(значениеСкаляра) {
  if (значениеСкаляра.variant === "Скаляр ничто") return null
  return значениеСкаляра.fields.значение
}

