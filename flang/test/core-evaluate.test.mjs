/* ──────────────── дифференциальная сверка со всем репозиторием ──────────── */

/**
 * Сетка входов выводится из самой модели: значения из примеров, все константы
 * условий и действий, границы вокруг них (c−1, c, c+1). Расхождения `>` против
 * `>=` прячутся именно там.
 */
function константы(u) {
  const числа = new Set()
  const строки = new Set()
  const взять = (v) => {
    if (typeof v === "number") числа.add(v)
    if (typeof v === "string") строки.add(v)
  }
  const оп = (o) => {
    if (o.kind === "value") взять(o.value)
    if (o.kind === "percent") числа.add(o.percent)
  }
  взять(u.initial)
  for (const r of u.rules) {
    for (const c of r.when) оп(c.value)
    оп(r.action.value)
  }
  for (const p of u.properties) оп(p.value)
  for (const e of u.examples) for (const v of Object.values(e.input)) взять(v)
  return { числа, строки }
}

function сетка(structure, u) {
  const конст = константы(u)
  const кандидаты = new Map()
  for (const field of structure.fields) {
    const значения = new Set()
    for (const e of u.examples) if (field.name in e.input) значения.add(e.input[field.name])
    const тип = field.type.replace(/\s*\|\s*undefined/gu, "").trim()
    if (тип === "Число" || тип === "Деньги" || тип === "number") {
      for (const v of конст.числа) {
        значения.add(v - 1)
        значения.add(v)
        значения.add(v + 1)
      }
      значения.add(0)
      значения.add(-1)
      значения.add(1)
    } else if (тип === "Признак" || тип === "boolean") {
      значения.add(true)
      значения.add(false)
    } else if (тип === "Строка" || тип === "Дата" || тип === "string") {
      for (const v of конст.строки) значения.add(v)
      значения.add("")
    } else if (значения.size === 0) {
      значения.add(true)
    }
    кандидаты.set(field.name, [...значения].slice(0, 10))
  }
  const входы = u.examples.map((e) => ({ ...e.input }))
  const обязательные = structure.fields.filter((field) => !field.type.includes("undefined"))
  let сочетания = [[]]
  for (const field of обязательные) {
    const следующие = []
    for (const сочетание of сочетания) {
      for (const v of кандидаты.get(field.name) ?? [null]) {
        if (следующие.length >= 2000) break
        следующие.push([...сочетание, v])
      }
      if (следующие.length >= 2000) break
    }
    сочетания = следующие
  }
  for (const сочетание of сочетания) {
    const вход = {}
    обязательные.forEach((field, индекс) => {
      вход[field.name] = сочетание[индекс]
    })
    входы.push(вход)
  }
  return входы
}

function модели() {
  const файлы = [
    ...globSync("examples/**/*.fts", { cwd: root }),
    ...globSync("web/demo/models/*.fts", { cwd: root }),
    ...globSync("tools/ftsc/stdlib/**/*.fts", { cwd: root }),
  ].sort()
  const документы = []
  for (const файлМодели of файлы) {
    const разобранный = parseModuleFile(readFileSync(root + файлМодели, "utf8"), файлМодели)
    /* Файлы-функторы документами FTS не являются — у них нет категории. */
    if (разобранный.kind !== "module") continue
    let документ
    try {
      документ = ядро.compile(разобранный.body)
    } catch {
      continue
    }
    документы.push({ файл: файлМодели, документ })
  }
  return документы
}

const документы = модели()

test("дифференциальная сверка: репозиторий даёт модели с утилитами", () => {
  assert.ok(документы.length >= 10, `документов: ${документы.length}`)
  const утилит = документы.reduce((сумма, { документ }) => сумма + (документ.utilities ?? []).length, 0)
  assert.ok(утилит >= 10, `утилит: ${утилит}`)
})

test("дифференциальная сверка: значения и коды совпадают с ядром на TS", () => {
  let входов = 0
  let утилит = 0
  for (const { файл: имяФайла, документ } of документы) {
    for (const u of документ.utilities ?? []) {
      const structure = документ.structures.find((s) => s.name === u.input)
      if (!structure) continue
      утилит += 1
      const значениеУтилиты = утилита(u)
      for (const вход of сетка(structure, u)) {
        входов += 1
        let ожидаемое
        let ожидаемыйКод
        try {
          ожидаемое = ядро.evaluateUtility(u, вход)
        } catch (ошибка) {
          ожидаемыйКод = кодОшибки(ошибка)
        }
        const итог = вычислить(значениеУтилиты, вход)
        const место = `${имяФайла} / «${u.name}» / ${JSON.stringify(вход)}`
        if (ожидаемыйКод !== undefined) {
          assert.equal(итог.код, ожидаемыйКод, `${место}: ядро дало ${ожидаемыйКод}, flang — ${итог.код ?? итог.значение}`)
        } else {
          assert.equal(итог.код, undefined, `${место}: ядро посчитало ${ожидаемое}, flang отказался с ${итог.код}`)
          assert.ok(
            Object.is(итог.значение, ожидаемое),
            `${место}: ядро дало ${ожидаемое}, flang — ${итог.значение}`,
          )
        }
      }
    }
  }
  assert.ok(утилит >= 10, `утилит в сверке: ${утилит}`)
  assert.ok(входов >= 5000, `входов в сверке: ${входов}`)
})

test("дифференциальная сверка: перевод скаляров обратим", () => {
  /* Сверка выше сравнивает движки на переведённых данных. Если перевод
     `FtsScalar` → «Скаляр» что-то теряет, она доказывала бы совпадение на
     подменённом входе, поэтому обратимость проверяется отдельно и на всех
     скалярах, которые встречаются в моделях репозитория. */
  const скаляры = new Set()
  const взять = (v) => {
    if (v !== undefined) скаляры.add(v)
  }
  for (const { документ } of документы) {
    for (const u of документ.utilities ?? []) {
      взять(u.initial)
      for (const r of u.rules) {
        for (const c of r.when) if (c.value.kind === "value") взять(c.value.value)
        if (r.action.value.kind === "value") взять(r.action.value.value)
      }
      for (const p of u.properties) if (p.value.kind === "value") взять(p.value.value)
      for (const e of u.examples) {
        взять(e.expected)
        for (const v of Object.values(e.input)) взять(v)
      }
    }
  }
  assert.ok(скаляры.size > 0)
  for (const исходный of скаляры) {
    const обратно = скалярВJS(скаляр(исходный))
    assert.ok(Object.is(обратно, исходный), `${JSON.stringify(исходный)} → ${JSON.stringify(обратно)}`)
  }
})

