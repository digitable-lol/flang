/**
 * Тесты лексера ядра FTS (`flang/core/lexer.flang`).
 *
 * Лексер написан на самом flang, поэтому проверяется тем же конвейером, что и
 * стандартная библиотека: разбор → типы → тотальность → примеры, а сверх того —
 * поведение на настоящих моделях репозитория.
 *
 * Читаемость потока токенов держится на функции «Разметка»: она печатает список
 * «Токен» строками (`>` отступ больше, `<` отступ меньше, `/` конец строки,
 * `.` конец файла, `имя …`, `строка …`, `число …`, `знак …`). Иначе сверять
 * пришлось бы объекты FlangVariant, и падение теста читалось бы как дамп, а не
 * как утверждение. Там, где важен именно вариант, а не его печать, проверяется
 * список «Токены».
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import test from "node:test"

import { isVariant, valuesEqual } from "../src/builtins.mjs"
import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"
import { текстМодели, файлыКорпуса } from "./corpus.mjs"

/* Заголовок `модуль …` знают файлы tools/**, а ядро — нет: тело модуля
   вынимается тем же разборщиком, что в core-parser. */
const { parseModuleFile } = await import(new URL("../../tools/ftsc/src/parse-module.mjs", import.meta.url).href)

const источник = readFileSync(fileURLToPath(new URL("../core/lexer.flang", import.meta.url)), "utf8")
const программа = parse(источник, "core/lexer.flang")
const типы = checkTypes(программа)
const тотальность = checkTotality(программа)

const модель = (имя) => readFileSync(fileURLToPath(new URL(`../../${имя}`, import.meta.url)), "utf8")

const вызвать = (имя, аргументы) => evaluate(программа, имя, аргументы)
const разметка = (текст) => вызвать("Разметка", { исходник: текст })
const токены = (текст) => вызвать("Токены", { исходник: текст })
const коды = (текст) => вызвать("Коды диагностик", { исходник: текст })
const диагностики = (текст) => вызвать("Диагностики", { исходник: текст })

