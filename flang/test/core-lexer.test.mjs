test("order-discount.fts: отступы сходятся — каждому ОтступБольше свой ОтступМеньше", () => {
  const поток = токены(модель("web/demo/models/order-discount.fts"))
  const имена = поток.map((токен) => (isVariant(токен) ? токен.variant : "?"))
  assert.equal(имена.filter((имя) => имя === "ОтступБольше").length, имена.filter((имя) => имя === "ОтступМеньше").length)
  assert.equal(имена.at(-1), "Конец")
  assert.equal(имена.filter((имя) => имя === "Конец").length, 1)
  /* Глубина никогда не уходит в минус и возвращается в ноль ровно на «Конец». */
  let глубина = 0
  for (const имя of имена) {
    if (имя === "ОтступБольше") глубина += 1
    if (имя === "ОтступМеньше") глубина -= 1
    assert.ok(глубина >= 0, "закрыто больше уровней, чем открыто")
  }
  assert.equal(глубина, 0)
})

