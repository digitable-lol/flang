test("lexer.flang: разбор даёт контракт SPEC, раздел 5", () => {
  assert.equal(программа.flang, 1)
  assert.equal(программа.module, "Лексер FTS")
  assert.ok(Array.isArray(программа.functions))
  assert.ok(программа.functions.length > 0)
  /* Детерминированность: повторный разбор даёт побайтово тот же AST. */
  assert.equal(JSON.stringify(parse(источник, "core/lexer.flang")), JSON.stringify(программа))
})

test("lexer.flang: типы без диагностик", () => {
  assert.deepEqual(типы.diagnostics, [])
})

test("lexer.flang: тотальность без диагностик", () => {
  assert.deepEqual(тотальность.diagnostics, [])
})

test("lexer.flang: все функции объявлены тотальными и доказаны", () => {
  for (const функция of программа.functions) {
    assert.equal(функция.total, true, `«${функция.name}» не помечена тотальной`)
    assert.ok(тотальность.total.has(функция.name), `«${функция.name}» не доказана тотальной`)
  }
})

test("lexer.flang: объявлен ровно тот тип «Токен», что в core/SPEC.md, раздел 1", () => {
  const токен = (программа.types ?? []).find((тип) => тип.name === "Токен")
  assert.ok(токен, "тип «Токен» не объявлен")
  assert.equal(токен.kind, "sum")
  assert.deepEqual(
    токен.variants.map((вариант) => вариант.name),
    ["ОтступБольше", "ОтступМеньше", "КонецСтроки", "Имя", "Строка", "Число", "Знак", "Конец"],
  )
  const поля = Object.fromEntries(
    токен.variants.map((вариант) => [вариант.name, (вариант.fields ?? []).map((поле) => [поле.name, поле.type.kind])]),
  )
  assert.deepEqual(поля["Имя"], [["текст", "string"]])
  assert.deepEqual(поля["Строка"], [["текст", "string"]])
  assert.deepEqual(поля["Число"], [["значение", "number"]])
  assert.deepEqual(поля["Знак"], [["текст", "string"]])
  assert.deepEqual(поля["ОтступБольше"], [])
  assert.deepEqual(поля["Конец"], [])
})

test("lexer.flang: примеры всех функций сходятся", () => {
  let счёт = 0
  for (const функция of программа.functions) {
    for (const пример of функция.examples ?? []) {
      счёт += 1
      const получено = evaluate(программа, функция.name, пример.args)
      assert.ok(
        valuesEqual(получено, пример.expected),
        `«${функция.name}» / «${пример.name}»: ожидалось ${JSON.stringify(пример.expected)}, получено ${JSON.stringify(получено)}`,
      )
    }
  }
  assert.ok(счёт >= 40, `примеров всего ${счёт}`)
})

