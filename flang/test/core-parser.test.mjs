  const src =
    "категория «А»\n  утилита У\n    принимает Б\n    возвращает число\n    начинает с 0\n" +
    "    пример П\n      дано х равно 1\n      дано у равно 2\n      дано х равно 3\n      ожидается результат равен 0\n"
  assert.equal(скомпилировать(src), JSON.stringify(ядро.compile(src)))
  assert.deepEqual(JSON.parse(скомпилировать(src)).utilities[0].examples[0].input, { х: 3, у: 2 })
