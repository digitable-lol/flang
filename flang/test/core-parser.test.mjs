/**
 * Парсер ядра FTS на flang — `flang/core/parser.flang`.
 *
 * Главная проверка здесь одна и она сквозная: для каждой модели `.fts`
 * репозитория (и внешнего каталога моделей, если он есть) строится вся цепочка
 * ядра на flang — текст → лексер (`core/lexer.flang`) → парсер
 * (`core/parser.flang`) → печать JSON (`core/json.flang`) — и результат обязан
 * совпасть с `JSON.stringify(compile(текст))` настоящего ядра на TypeScript
 * **побайтово**. Критерий готовности из `flang/core/SPEC.md`, раздел 5: ядро
 * верно не тогда, когда проходят его собственные тесты.
 *
 * Второй по важности блок — диагностики. Для трёх десятков намеренно сломанных
 * моделей сверяются и код, и текст сообщения: перевод обязан давать ровно ту же
 * ошибку, что ядро, иначе совместимость сломается на первом же отказе
 * (flang/SPEC.md, раздел 5). Два случая расходятся сознательно и закреплены
 * отдельными тестами, чтобы закрытие долга не прошло молча.
 *
 * Остальные проверки закрывают то, чего в моделях репозитория не встречается:
 * скаляры всех четырёх видов, операнды всех четырёх видов, повтор ключа во
 * входе примера, английская поверхность, имена в обычных кавычках.
 */
import assert from "node:assert/strict"
import { existsSync, globSync, readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { valuesEqual } from "../src/builtins.mjs"
import { evaluate } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const root = fileURLToPath(new URL("../..", import.meta.url))
const файл = fileURLToPath(new URL("../core/parser.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")

/* Свой разбор — чтобы знать, какие функции объявлены именно здесь, а какие
   приехали из лексера и печати. Проверки тотальности и типов идут по связанной
   программе: без импортов имена соседних слоёв остались бы несвязанными. */
const свой = parse(исходник, "core/parser.flang")
const связано = await linkProgram(файл, исходник, parse)
const { diagnostics: диагностикиСвязывания, ...программа } = связано
const типы = checkTypes(программа)
const тотальность = checkTotality(программа)

const ядро = await import(new URL("../../dist/src/index.js", import.meta.url).href)
const { parseModuleFile } = await import(new URL("../../tools/ftsc/src/parse-module.mjs", import.meta.url).href)

/**
 * Лимит шагов поднят с миллиона до четырёх: разбор — работа на порядок тяжелее
 * печати, и самая большая модель репозитория (`tools/gacascade/models/
 * assignment.fts`) укладывается между одним и двумя миллионами шагов. Запас
 * взят двукратный и не больше: лимит здесь — не формальность, а проверка того,
 * что разбор остался линейным по числу строк, а не превратился в перебор.
 */
const ШАГИ = { maxSteps: 4_000_000 }
const вызвать = (name, args) => evaluate(программа, name, args, ШАГИ)

const скомпилировать = (исходник) => вызвать("Скомпилировать", { исходник })
const диагностики = (исходник) => вызвать("Диагностики исходника", { исходник })
const коды = (исходник) => вызвать("Коды разбора", { исходник })

/* ────────────────────────────── слои модуля ─────────────────────────────── */

test("parser.flang: связывание модулей без диагностик", () => {
  assert.deepEqual(диагностикиСвязывания, [])
  assert.equal(программа.module, "Парсер FTS")
})

test("parser.flang: разбор даёт контракт SPEC, раздел 5", () => {
  assert.equal(свой.flang, 1)
  assert.ok(Array.isArray(свой.functions))
  assert.ok(свой.functions.length >= 60, `функций: ${свой.functions.length}`)
  assert.ok(Array.isArray(свой.types))
  /* Детерминированность: повторный разбор даёт побайтово тот же AST. */
  assert.equal(JSON.stringify(parse(исходник, "core/parser.flang")), JSON.stringify(свой))
})

test("parser.flang: типы без диагностик", () => {
  assert.deepEqual(типы.diagnostics, [])
})

test("parser.flang: тотальность без диагностик", () => {
  assert.deepEqual(тотальность.diagnostics, [])
})

test("parser.flang: каждая функция помечена «тотальная» и доказана", () => {
  for (const fn of свой.functions) {
    assert.equal(fn.total, true, `«${fn.name}» не помечена тотальной`)
    assert.ok(тотальность.total.has(fn.name), `«${fn.name}» помечена тотальной, но не доказана`)
  }
})

test("parser.flang: вся связанная программа тотальна", () => {
  for (const fn of программа.functions) {
    assert.equal(fn.total, true, `«${fn.name}» не помечена тотальной`)
    assert.ok(тотальность.total.has(fn.name), `«${fn.name}» помечена тотальной, но не доказана`)
  }
})

test("parser.flang: примеры сходятся", () => {
  let count = 0
  for (const fn of свой.functions) {
    for (const example of fn.examples ?? []) {
      count += 1
      const actual = evaluate(программа, fn.name, example.args, ШАГИ)
      assert.ok(
        valuesEqual(actual, example.expected),
        `«${fn.name}» / «${example.name}»: ожидалось ${JSON.stringify(example.expected)}, получено ${JSON.stringify(actual)}`,
      )
    }
  }
  assert.ok(count >= 5, `примеров: ${count}`)
})

