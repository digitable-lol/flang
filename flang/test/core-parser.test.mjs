test("утверждение-применение и композиция: один и два морфизма", () => {
  const шапка =
    "категория «А»\n  объект «Заказ»\n    статус является состоянием «Собран»\n" +
    "  морфизм «Собранный отгружается»\n    если «Собран»\n    то «Отгружен»\n" +
    "  морфизм «Отгруженный доставляется»\n    если «Отгружен»\n    то «Доставлен»\n"
  const один = шапка + "  теорема «Т»\n    дано «Заказ» имеет статус равное да\n    в данных заказы найти где номер равен 1\n    по морфизму «Собранный отгружается»\n"
  const два = один + "    затем по морфизму «Отгруженный доставляется»\n    следовательно «Доставлен»\n"
  assert.equal(скомпилировать(один), JSON.stringify(ядро.compile(один)))
  assert.equal(JSON.parse(скомпилировать(один)).proposition.kind, "apply")
  assert.equal(скомпилировать(два), JSON.stringify(ядро.compile(два)))
  assert.equal(JSON.parse(скомпилировать(два)).proposition.kind, "compose")
})
