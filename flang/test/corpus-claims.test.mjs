test("а с теоремой то же самое ложное утверждение ядро ОТВЕРГАЕТ, и называет чем", async () => {
  /* ГРАНИЦА МОЛЧАНИЯ — здесь, и её надо было измерить, а не описать.
     Выше ядро на ложь промолчало, и промолчало по делу: теоремы при утверждении
     не было, а недоказанное утверждение — не ошибка. Отсюда законный вопрос:
     умеет ли ядро вообще отказывать на ЭТОЙ цели, или «не меньше 0» у него
     всегда проходит мимо?

     Умеет, и вот проверка. Берётся то же самое утверждение той же формы
     («результат не меньше 0»), но при нём стоит ТЕОРЕМА — доказательство, которое
     автор написал и предъявил. Портится оно так же, на один знак: `0` → `1`.
     Теперь молчать нельзя, потому что предъявлено доказательство ложного, и ядро
     отказывает двумя названными кодами.

     Файл взят готовый (`corpus-numtree.flang`, «Высота» из
     `flang/stdlib/numtree.flang`): своей теоремы у римских цифр нет и быть не
     может — индукции не по чему, `строка` не объявленная сумма. Это и есть та
     причина, по которой при них теоремы не написано. */
  const путь = "flang/proof/examples/corpus-numtree.flang"
  const исходник = текст(путь)
  const порча = исходник
    .replace("обеспечивает «высота неотрицательна» результат не меньше 0", "обеспечивает «высота неотрицательна» результат не меньше 1")
    .replace("утверждаем результат не меньше 0", "утверждаем результат не меньше 1")
  assert.notEqual(порча, исходник, "порча не наложилась — проверка ничего не проверяет")

  const программа = await loadProgramFromSource(порча, путь)
  const внешнее = await externalChecks(программа)
  const коды = внешнее.diagnostics.filter((б) => String(б?.code ?? "").startsWith("FLANG_PROOF")).map((б) => б.code)
  assert.deepEqual(
    [...new Set(коды)].sort(),
    ["FLANG_PROOF_INDUCTION_STEP", "FLANG_PROOF_STEP"],
    "ядро приняло ЛОЖНОЕ доказательство или отказало молча",
  )

  /* И вердикт в ведомости — «отвергнуто», а не «сетка» и не «доказано». */
  const итог = proofLedger(программа, внешнее.results)
  const з = утверждение(итог, "высота неотрицательна")
  assert.equal(з?.verdict, "refused", `ведомость сказала «${з?.says}»`)

  /* А непорченый файл при этом доказан — иначе красным было бы всё подряд, и
     отказ выше ничего бы не означал. */
  const целый = await loadProgramFromSource(исходник, путь)
  const цело = await externalChecks(целый)
  assert.deepEqual(цело.diagnostics.filter((б) => б?.severity !== "warning"), [])
  assert.equal(утверждение(proofLedger(целый, цело.results), "высота неотрицательна")?.verdict, "proved-induction")
})

