/**
 * Список функций корпуса, у которых цель «результат не меньше 0» сводится
 * сегодня, — поимённо и целиком.
 *
 * Число здесь — главный ответ этой работы, и он неприятный: десять функций на
 * 2800. Стоять оно обязано в исполняемом виде, потому что «почти нигде» —
 * это настроение, а «10 из 2800» — измерение, и вырасти оно может только от
 * работы над ядром или над корпусом, а не от пересказа.
 *
 * ЗВЁЗДОЧКА У СЕМИ СТРОК: они лежат в каталогах побайтовой неподвижной точки
 * самоприменения (`flang/self`, `flang/stdlib`, `flang/core`,
 * `flang/examples/leetcode`, `flang/examples/measure`), где слова
 * `обеспечивает` нет продукции у парсера на flang. Написать утверждение там
 * нельзя — не по осторожности, а потому что сверка разборщика перестанет
 * сходиться. Это не граница ядра, это долг самоприменения, и назван он в
 * `flang/proof/SPEC.md` и `flang/self/SPEC.md`.
 */
const ОХВАТ = [
  "flang/examples/leetcode/013-roman-to-integer.flang «Значение цифры»",
  "flang/examples/measure/natural.flang «Сумма пары»",
  "flang/examples/rosetta/roman-numerals-english.flang «Value of a symbol»",
  "flang/examples/rosetta/roman-numerals.flang «Значение цифры»",
  "flang/proof/examples/corpus-natural.flang «Сумма пары»",
  "flang/self/emit-c.flang «Байтов у символа»",
  "flang/self/parser.flang «Наименьшая основа»",
  "flang/self/parser.flang «Размер пачки»",
  "flang/self/proof.flang «Версия ведомости»",
  "flang/self/types.flang «Потолок точных»",
]

test("охват: ядро берёт «результат не меньше 0» ровно у этих функций корпуса", () => {
  const найдено = []
  let всего = 0
  for (const путь of ФАЙЛЫ) {
    let программа
    try {
      программа = parse(текст(путь), путь)
    } catch {
      continue
    }
    for (const функция of программа.functions ?? []) {
      всего += 1
      if (берётЛиЯдро(функция).ok) найдено.push(`${путь} «${функция.name}»`)
    }
  }
  assert.ok(всего > 2500, `корпус ужался до ${всего} функций — обход смотрит не туда`)
  assert.deepEqual(
    найдено.sort(),
    [...ОХВАТ].sort(),
    "охват ядра изменился: впишите новые функции сюда и напишите им утверждения там, где это разрешено",
  )
})

test("охват: семь из десяти писать нельзя — они в корпусе неподвижной точки", () => {
  /* Каталоги — не список из головы: он снят с `исходникиFlang`
     (`flang/test/self-parser.test.mjs`), где и стоит корпус побайтовой сверки. */
  const закрытые = ["flang/stdlib/", "flang/core/", "flang/examples/leetcode/", "flang/examples/measure/", "flang/self/"]
  const нельзя = ОХВАТ.filter((строка) => закрытые.some((каталог) => строка.startsWith(каталог)))
  assert.equal(нельзя.length, 7, `закрытых стало ${нельзя.length}: ${нельзя.join("; ")}`)
  /* И проверка, что запрет настоящий, а не поверье: ни у одной функции этих
     каталогов постусловия нет. Смотрится РАЗБОРОМ, а не поиском слова в тексте:
     `flang/self/lexer.flang` слово `обеспечивает` содержит — в таблице ключевых
     слов, которую он сверяет с эталоном, — и поиск по тексту спутал бы таблицу
     лексера с формой языка. */
  for (const путь of ФАЙЛЫ) {
    if (!закрытые.some((каталог) => путь.startsWith(каталог))) continue
    let программа
    try {
      программа = parse(текст(путь), путь)
    } catch {
      continue
    }
    for (const функция of программа.functions ?? []) {
      assert.equal(
        (функция.postconditions ?? []).length,
        0,
        `${путь}, «${функция.name}»: постусловие в корпусе неподвижной точки —`
          + " сверка разборщика перестанет сходиться (self-parser.test.mjs)",
      )
    }
  }
})
