/**
 * Причина строки «Фибоначчи» — ИЗМЕРЕНА, а не вспомнена.
 *
 * Строка эта переписывалась дважды, и оба раза потому, что причина при ней
 * протухала молча: сначала «развёртки определений нет», потом «принципа по числу
 * нет». Обе половины стали ложью, а строка осталась. Значит проверять надо не
 * ОТКАЗ ядра (он один на все строки заказа и ни о чём не говорит), а ровно те
 * два факта, из которых причина сегодня состоит.
 *
 * ФАКТ ПЕРВЫЙ: у самой «Фибоначчи» принцип по отрезку не читается вовсе — тело
 * есть ВЫЗОВ, а не `если`, и дна отрезка в нём не видно. Это не про индукцию: по
 * такому телу нечего разбирать ни одному принципу.
 *
 * ФАКТ ВТОРОЙ, и он важнее: лемма, которая закрыла бы «Фибоначчи», ЗАПИСАНА, но
 * теоремы при ней нет. «Результат не меньше 0» о «Фибоначчи шагом» ложно без
 * условия: накопитель объявлен `число`, и на входе автора же вида `осталось = 0`
 * при отрицательном `предыдущее` функция возвращает отрицательное. Верна там
 * условная форма — «ЕСЛИ накопители неотрицательны», — и записать её стало чем:
 * слово `требует` приехало 16 августа 2026. Строка заказа поэтому адресована НЕ
 * ядру индукции: ядру нечего сводить, пока при лемме не написана теорема,
 * и написать это надо прямо — иначе следующий работник будет чинить индукцию,
 * которая тут ни при чём.
 */
test("заказ «Фибоначчи»: причина измерена — тело не «если», а теоремы при лемме нет", async () => {
  const путь = "flang/examples/rosetta/fibonacci.flang"
  const программа = await loadProgramFromSource(текст(путь), путь)

  /* Факт первый — спрашивается у самого порождения принципа, а не пересказом. */
  const фибоначчи = функцияИз(программа, "Фибоначчи")
  const принцип = принципПоЧислу({
    тип: "нат",
    функция: фибоначчи,
    обязательство: {
      of: "Фибоначчи",
      name: "проба",
      goal: ЦЕЛЬ,
      bind: "результат",
      vars: (фибоначчи.params ?? []).map((п) => ({ name: п.name, type: п.type })),
    },
    индукция: { param: "н", measure: { kind: "var", name: "н" }, cases: [] },
  })
  assert.equal(принцип.unread?.code, "branch", JSON.stringify(принцип.unread))
  assert.match(принцип.unread.why, /не «если»/u)

  /* ФАКТ ВТОРОЙ ПЕРЕПИСАН СБОРКОЙ, потому что причина под ним изменилась. Здесь
     стояло «лемма НЕПРЕДСТАВИМА: слова `требует` в языке нет», и это было
     правдой до 16 августа 2026. Слово приехало (`work/trebuet`), лемма
     записана — два `требует` и `обеспечивает` у «Фибоначчи шагом», — и
     непредставимой она больше не является.

     Ложной без предусловий она быть не перестала, и это по-прежнему считается
     ВЫЧИСЛЕНИЕМ, а не рассуждением: вход `0 / −7 / 9` того же вида, что пример
     автора, и снаружи программы он теперь отвергается по имени требования. Не
     отвергнись он — предусловие ничего не значило бы. */
  let отказ = null
  try {
    evaluate(программа, "Фибоначчи шагом", { осталось: 0, предыдущее: -7, текущее: 9 })
  } catch (беда) {
    отказ = беда
  }
  assert.ok(отказ !== null, "вход с отрицательным накопителем прошёл — предусловие перестало что-либо значить")
  assert.match(
    отказ.message,
    /не выполнено требование «предыдущее неотрицательно»/u,
    `отказ назвал не то требование: ${отказ.message}`,
  )
  /* И то же самое с другой стороны: при неотрицательных накопителях функция
     возвращает накопитель, и лемма о ней ИСТИННА. */
  assert.equal(evaluate(программа, "Фибоначчи шагом", { осталось: 0, предыдущее: 7, текущее: 9 }), 7)

  /* И третье, без чего два первых читались бы как придирка: принцип по отрезку у
     «Фибоначчи шагом» ЧИТАЕТСЯ целиком — спуск строгий, дно на месте. Ядро
     упирается не в чтение принципа, а в то, что доказывать там нечего: посылка
     дна — это `предыдущее не меньше 0`, и она ложна. */
  const шагом = функцияИз(программа, "Фибоначчи шагом")
  const принципШагом = принципПоЧислу({
    тип: "нат",
    функция: шагом,
    обязательство: {
      of: "Фибоначчи шагом",
      name: "проба",
      goal: ЦЕЛЬ,
      bind: "результат",
      vars: (шагом.params ?? []).map((п) => ({ name: п.name, type: п.type })),
    },
    индукция: { param: "осталось", measure: { kind: "var", name: "осталось" }, cases: [] },
  })
  assert.equal(принципШагом.unread, null, "принцип по отрезку перестал читаться у «Фибоначчи шагом»")
  const [дно, спуск] = принципШагом.premises
  assert.equal(
    свести(дно.conclusion, дно.facts, дно.declarations, определенияМодуля(программа)).ok,
    false,
    "дно «Фибоначчи шагом» свелось — а оно ЛОЖНО: ядро доказывает неправду",
  )
  assert.equal(
    свести(спуск.conclusion, [...спуск.hypotheses, ...спуск.facts], спуск.declarations, определенияМодуля(программа)).ok,
    true,
    "спуск «Фибоначчи шагом» перестал сводиться допущением — причина строки изменилась",
  )
})

