/**
 * Утверждения о поведении, написанные в КОРПУСЕ, — и граница того, что ядро
 * берёт.
 *
 * ── Зачем этот файл, если есть `proof-kernel.test.mjs` ──────────────────────
 *
 * Тот проверяет ЯДРО на фикстурах: правило, подделку, изъятие слова. Этот
 * проверяет КОРПУС: что написанное в настоящих файлах языка — правда, что ядро
 * это берёт, и — главное — чего оно НЕ берёт, хотя правда.
 *
 * Повод такой. Ядро научилось судить постусловие без теоремы (`proofterm.mjs`,
 * `поОбъявленномуТипу`), и первым вопросом стало: сколько корпуса от этого
 * стало доказуемым? Отвечать на такой вопрос памятью нельзя, поэтому здесь он
 * ИСПОЛНЯЕТСЯ — обходом всех 2802 функций корпуса с одним и тем же вопросом к
 * `свести`. Ответ невелик и стоит числом («охват»), и когда ядро вырастет,
 * число обязано вырасти вместе с ним, а не остаться пересказом вчерашнего дня.
 *
 * ── Что здесь проверяется, и почему именно это ──────────────────────────────
 *
 *   1. ДОКАЗАНО. Оба написанных утверждения ядро берёт целиком — «доказано»,
 *      а не «сетка». Без этого остальное не о чем.
 *   2. ИЗЪЯТИЕ. Снимите строку `обеспечивает` — и утверждения не станет вовсе.
 *      Зелёный цвет первого пункта обязан быть следствием строки, а не общего
 *      благополучия файла.
 *   3. ЛОЖЬ. То же утверждение, испорченное до `не меньше 1`, ложно на примере
 *      автора («Не римская цифра — ноль»), и три слоя обязаны сказать об этом
 *      РАЗНОЕ, но ни один — не «доказано»: ядро снимает доказанность, прогон
 *      примеров краснеет кодом `FLANG_PROPERTY`, рантайм отказывает тем же
 *      кодом. Здесь же названо прямо, чего ядро НЕ делает и почему — и здесь же
 *      измерена ГРАНИЦА этого молчания: то же ложное утверждение той же формы,
 *      но с ТЕОРЕМОЙ при нём, ядро ОТВЕРГАЕТ двумя названными кодами. Молчит оно
 *      ровно там, где доказательства ему не предъявляли.
 *   3-бис. ДВЕ ПОВЕРХНОСТИ. Постусловие впервые встало на паре листингов, и
 *      сверка пар о нём не знала — она падала на производном поле `message`.
 *      Слот заведён (`surface-pair.mjs`), и вместе с ним проверка, что сверка
 *      умеет на новом слоте КРАСНЕТЬ, а не только пропускать.
 *   4. ЗАКАЗ. Утверждения, которые ПРАВДА и которых ядро сегодня не берёт, —
 *      таблицей, с причиной у каждого и с доказательством правды на примерах
 *      автора. Список исполняемый: научится ядро — тест покраснеет и потребует
 *      вычеркнуть строку. Список обещаний, который нельзя вычеркнуть проверкой,
 *      превращается в кладбище.
 *   5. ОХВАТ. Сколько функций корпуса ядро берёт на цель «результат не меньше
 *      0» и где они лежат — числом и поимённо.
 *
 * Запуск: node --test flang/test/corpus-claims.test.mjs
 */
