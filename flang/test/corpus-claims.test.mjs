/** Цель, о которой весь этот файл: «результат не меньше 0». */
const ЦЕЛЬ = {
  kind: "binary",
  op: "gte",
  left: { kind: "var", name: "результат" },
  right: { kind: "literal", value: 0 },
}

/**
 * Берёт ли ядро цель `результат не меньше 0` у этой функции — тем же вопросом и
 * теми же двумя вызовами, какими его задаёт `proofterm.mjs`: одна подстановка
 * (тело на место `результат`) и одно `свести` с объявлениями подписи.
 *
 * Своей логики здесь нет ни строки — иначе тест отвечал бы на свой вопрос, а не
 * на вопрос ядра.
 */
function берётЛиЯдро(функция, определения = null) {
  if (функция?.body === null || функция?.body === undefined) return { ok: false, why: "тела нет" }
  const объявления = (функция.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
  /* Определения модуля — четвёртый аргумент `свести`, и он тут не для полноты:
     `proofterm.mjs` передаёт их (`среда.функции`), а значит и обход обязан. Не
     передай он их — обход мерил бы ядро, которого нет, и «охват» разошёлся бы с
     тем, что ведомость печатает на тех же файлах. */
  return свести(подставить(ЦЕЛЬ, { результат: функция.body }), [], объявления, определения)
}

/** Функции модуля картой — ровно тем же, чем их собирает `средаПрограммы` ядра. */
const определенияМодуля = (программа) => new Map((программа?.functions ?? []).map((ф) => [ф.name, ф]))

const функцияИз = (программа, имя) => (программа.functions ?? []).find((ф) => ф.name === имя)

/**
 * Есть ли в дереве узел, у которого совпали все названные поля.
 *
 * Обход, а не разбор строки: причина «не берёт из-за умножения» обязана стоять
 * рядом с телом, где умножение и правда есть.
 */
function естьВТеле(узел, образец) {
  if (узел === null || узел === undefined || typeof узел !== "object") return false
  if (Array.isArray(узел)) return узел.some((элемент) => естьВТеле(элемент, образец))
  if (Object.entries(образец).every(([ключ, значение]) => узел[ключ] === значение)) return true
  return Object.entries(узел).some(([ключ, значение]) => ключ !== "span" && естьВТеле(значение, образец))
}

/** Ведомость программы из текста — тем же путём, каким её строит оболочка. */
async function ведомость(исходник, имя) {
  const программа = await loadProgramFromSource(исходник, имя)
  const внешнее = await externalChecks(программа)
  assert.deepEqual(
    внешнее.diagnostics.filter((б) => б?.severity !== "warning"),
    [],
    `${имя}: программа обязана проходить проверки, иначе ведомости у неё нет`,
  )
  return proofLedger(программа, внешнее.results)
}

const утверждение = (итог, имя) => (итог.claims ?? []).find((з) => з.name === имя)

