/**
 * Корпус на самом flang, сетка входов к нему и пределы — в ОДНОМ месте на все
 * шесть сверок напечатанного кода с интерпретатором (`emit-go`, `emit-rust`,
 * `emit-java`, `emit-csharp`, `emit-python`, `emit-elixir`).
 *
 * Раньше эти сто с лишним строк были скопированы в шесть файлов побайтово, и
 * различались в них ровно два слова — имя цели в комментарии. Правило, которое
 * приходится писать шесть раз, шесть раз и расходится; здесь оно написано один
 * раз, а цена этому — один импорт.
 *
 * ── Что за корпус ───────────────────────────────────────────────────────────
 *
 * Набор программ для главной сверки — не выдуманные фикстуры, а всё, что в
 * репозитории написано на самом flang: `flang/stdlib/*.flang` и
 * `flang/examples/leetcode/*.flang`. Сетка входов строится из примеров функций
 * и из порчи их аргументов заведомо неподходящими значениями — там, где
 * проверяются коды и тексты диагностик.
 *
 * Функции, работающие с суммами типов, примеров пока не имеют (см.
 * stdlib.test.mjs) — им остаётся только порча, то есть проверка кодов и
 * текстов диагностик. Это меньше, чем хотелось бы, но это не ноль, и без этого
 * два десятка функций не проверялись бы собранным кодом вовсе.
 */
import assert from "node:assert/strict"
import { readdirSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { variant } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"

const stdlibDirectory = fileURLToPath(new URL("../stdlib/", import.meta.url))
const leetcodeDirectory = fileURLToPath(new URL("../examples/leetcode/", import.meta.url))

/** Программы корпуса в порядке загрузки: `stdlib/`, затем `examples/leetcode/`. */
export function loadPrograms() {
  const found = []
  for (const directory of [stdlibDirectory, leetcodeDirectory]) {
    for (const name of readdirSync(directory).filter((item) => item.endsWith(".flang")).sort()) {
      found.push({ file: name, program: parse(readFileSync(directory + name, "utf8"), name) })
    }
  }
  return found
}

/* Значения, которых функция заведомо не ждёт. Ими портятся аргументы примеров:
   так проверяются не значения, а коды и тексты диагностик — вторая половина
   наблюдаемого поведения, и та, в которой кодогенератор ошибается чаще. */
export const ЧУЖИЕ = [null, "не то", 42, true, [], [1, "два"], { "поле": 1 }, variant("Нет такого", {})]

/** Объявлен ли параметр типом «функция»: `функция из числа в число`. */
function fnTypedParam(fn, index) {
  const param = fn.params?.[index]
  return param !== null && typeof param === "object" && param.type?.kind === "fn"
}

/**
 * Сетка одной функции: аргументы её примеров плюс их порча по одному
 * аргументу. Выдуманная сетка проверяла бы фантазию автора теста, а сетка из
 * примеров — то, ради чего функция написана.
 */
export function functionGrid(fn) {
  const params = fn.params.map((param) => (typeof param === "string" ? param : param.name))
  const examples = (fn.examples ?? []).filter((example) =>
    example.args !== null && typeof example.args === "object" &&
    params.every((name) => Object.hasOwn(example.args, name)))
  const points = examples.map((example) => params.map((name) => example.args[name]))
  if (params.length === 0) return points

  const seed = points.length > 0 ? points[0] : params.map(() => null)
  for (let index = 0; index < params.length; index += 1) {
    /* Параметр типа «функция» порче не подвергается, и это не дырка, а
       названное расхождение (`flang/cat/HOF.md`, «Одно расхождение, и оно
       названо»): чужое значение на месте тега отвергают ОБЕ стороны, но
       разными словами — интерпретатор `FLANG_APPLY`, напечатанный диспетчер
       `FLANG_MATCH_NOT_EXHAUSTIVE`, — потому что «отказать вот с этим текстом»
       в языке невыразимо. Проверяется оно дословно и отдельно, в
       `flang/test/stdlib-hof.test.mjs` и `flang/test/hof-emit.test.mjs`;
       здесь же сверяются тексты, и сверять их тут значило бы записать
       расхождение в восьми местах вместо одного. Значения из примеров на этой
       позиции остаются: тег там настоящий. */
    if (fnTypedParam(fn, index)) continue
    for (const alien of ЧУЖИЕ) {
      const spoiled = [...seed]
      spoiled[index] = alien
      points.push(spoiled)
    }
  }
  return points
}

/**
 * Пределы главной сверки.
 *
 * Шаг напечатанного кода — вход в функцию, виток хвостового цикла и отскок
 * батута; шаг интерпретатора — итерация его машины, а их на одно применение
 * функции приходится много. Значит при одном и том же пределе счётчик
 * напечатанного кода всегда меньше, и упереться в лимит первым может только
 * интерпретатор. Такие точки сверяются по коду ошибки, а не по тексту: текст
 * содержит число шагов, а оно у двух счётчиков разное по построению.
 */
export const ПРЕДЕЛЫ = { maxSteps: 5_000_000, maxDepth: 10_000 }

/**
 * Насколько разное — измерено, а не на глаз, и это ЦЕНА одинакового предела.
 *
 * Наименьший бюджет шагов, при котором «Правильные скобки» от 9 ещё отвечают
 * значением: у интерпретатора 1 153 082, у напечатанного кода 23 713 — и это
 * 23 713 у ВСЕХ восьми целей знак в знак. Отношение 48,6 держится от н=1 до
 * н=9 с точностью до третьего знака. Читается это так: **один и тот же
 * `maxSteps` покупает напечатанному коду в 48,6 раза больше ПРИМЕНЕНИЙ
 * ФУНКЦИЙ**, чем интерпретатору.
 *
 * Пока цена одного применения ограничена, расхождение и правда одностороннее и
 * безопасное. Но она не ограничена: `добавить` копирует весь список, а стоит
 * один шаг — в семи движках из девяти (кроме бэкенда C, где список растёт в
 * запас ёмкости, и кроме… никого больше). У программы, копящей ответ в списке,
 * работа квадратична по числу применений, и разница во времени выходит не 48,6,
 * а 48,6² ≈ 2400. Цифры по всем восьми целям — `flang/SPEC.md`, раздел
 * «Стоимость встроенных форм».
 *
 * Отсюда `УБЕГАЮЩИЕ` — см. ниже.
 */
export const РАЗМАХ_СЧЁТЧИКОВ = 40

/**
 * Бюджет шагов для убегающей точки.
 *
 * На точке, где интерпретатор исчерпал 5 000 000 СВОИХ шагов, сверять по
 * значению нечего: значения нет ни у кого. Сверяется только то, что и
 * напечатанный движок отказывает по пределу — а для этого ему не нужен бюджет,
 * которого хватит на 48,6 раза больше работы. Десять тысяч своих шагов он
 * исчерпывает на тех же точках за миллисекунды, и требование от этого не
 * слабеет, а УЖЕСТОЧАЕТСЯ: раньше было «если он тоже остановился, то тем же
 * кодом», стало «он обязан остановиться».
 */
export const ПРЕДЕЛ_УБЕГАЮЩЕЙ = 10_000

/**
 * Точки сетки, на которых ЭТАЛОН упирается в предел шагов, — поимённо.
 *
 * Их три на 8799 точек корпуса, и все три устроены одинаково: «порча»
 * подставила значение, которое параметр ПРИНИМАЕТ. Диагностики от такой порчи
 * не будет — будет другое вычисление, о цене которого никто ничего не обещал.
 *
 *   1–2. `н` объявлено `число`, и 42 для него не чужое. «Правильные скобки» от
 *        42 — это Каталан(42) ≈ 6·10²² слов; ответа не существует ни у кого.
 *   3.   `буквы` объявлено `список строки`, и пустой список для него не чужой.
 *        При пустом наборе букв «Покрывает» истинно всегда, левый край едет
 *        вправо без остановки, а объявленная мера уходит в минус — то есть
 *        рекурсия не кончается вовсе.
 *
 * Список не «чтобы пропустить», а чтобы ЧИТАТЬ: он говорит, где корпус просит
 * ответа, которого нет. Зубы у списка в `corpus-runaway.test.mjs`: каждое имя
 * обязано и правда упираться в предел у интерпретатора, и ни одна неназванная
 * точка корпуса упираться не смеет. Обе стороны — падение, а не заметка.
 */
export const УБЕГАЮЩИЕ = [
  {
    файл: "022-generate-parentheses.flang",
    функция: "Строить скобки",
    аргументы: [42, 0, 0, "", []],
    почему: "н = 42 при пустом начале: Каталан(42) ≈ 6·10²² слов",
  },
  {
    файл: "022-generate-parentheses.flang",
    функция: "Правильные скобки",
    аргументы: [42],
    почему: "н = 42: Каталан(42) ≈ 6·10²² слов",
  },
  {
    файл: "076-minimum-window-substring.flang",
    функция: "Окно покрытия",
    аргументы: [["а"], [], 1, 1, { "начало": 0, "ширина": 0 }],
    почему: "пустой набор букв: «Покрывает» истинно всегда, левый край едет вправо без конца",
  },
]

/** Ключ точки: файл, функция и аргументы — по значению, не по ссылке. */
export const ключТочки = (файл, функция, аргументы) =>
  `${файл} / «${функция}» ${JSON.stringify(аргументы)}`

const названные = new Set(УБЕГАЮЩИЕ.map((т) => ключТочки(т.файл, т.функция, т.аргументы)))

/** Названа ли точка убегающей. */
export const убегающая = (файл, функция, аргументы) =>
  названные.has(ключТочки(файл, функция, аргументы))

/**
 * Сверка наблюдённого с названным — знак в знак, в обе стороны.
 *
 * Вызывается из каждой из шести сверок и из `corpus-runaway.test.mjs`: список
 * убегающих точек — общее утверждение о корпусе, и молча разойтись с ним ни
 * одна сверка не имеет права.
 *
 * @param {string[]} наблюдаемые ключи точек, на которых эталон упёрся в предел
 * @returns {string} строка для отчёта
 */
export function сверьУбегающих(наблюдаемые) {
  const названныеСписком = УБЕГАЮЩИЕ.map((т) => ключТочки(т.файл, т.функция, т.аргументы)).sort()
  const лишние = наблюдаемые.filter((к) => !названные.has(к)).sort()
  assert.deepEqual(
    лишние,
    [],
    "на этих точках эталон упёрся в предел шагов, а в списке УБЕГАЮЩИЕ (flang/test/corpus-grid.mjs) их нет — " +
      `назовите их там вместе с причиной либо почините программу:\n  ${лишние.join("\n  ")}`,
  )
  assert.deepEqual(
    [...new Set(наблюдаемые)].sort(),
    названныеСписком,
    "список УБЕГАЮЩИЕ обязан совпадать с наблюдаемым знак в знак: имя, которое перестало упираться в предел, " +
      "больше не исключение и обязано уйти из списка",
  )
  return `убегающих точек ${наблюдаемые.length}, все названы поимённо в УБЕГАЮЩИЕ`
}
