/**
 * Корпус сломанных объявлений `план` — по случаю на каждую ветку `ctx.report`
 * проверки `checkPlans` (`flang/src/io.mjs`).
 *
 * ── Зачем корпус заведён РАНЬШЕ близнеца ────────────────────────────────────
 *
 * Счёт, ради которого это стоило делать первым (мерено `grep`-ом, не
 * предположено):
 *
 *   • программ со словом `план` во всём дереве — ОДНА
 *     (`flang/examples/io/link-report.flang`), и она ЦЕЛАЯ: диагностик у неё
 *     ноль;
 *   • планов в `flang/test/io.test.mjs` — десять, а случаев с `FLANG_PLAN`
 *     среди них — ТРИ;
 *   • веток `ctx.report` в эталоне — ДВЕНАДЦАТЬ.
 *
 * То есть до этого файла дифференциальная сверка близнеца имела бы на входе
 * одну зелёную программу и три сломанных: близнец, у которого выпало бы девять
 * веток из двенадцати, остался бы зелёным. Сверка, которая зеленеет, ничего не
 * проверяя, — не сверка, и заводить её без корпуса нельзя.
 *
 * ── Почему корпус двухэтажный ───────────────────────────────────────────────
 *
 * Четыре ветки эталона ИЗ ИСХОДНИКА НЕДОСТИЖИМЫ, и это свойство парсера, а не
 * недосмотр: `parsePlan` (`flang/src/parser.mjs`) требует имя плана и все три
 * строки — `состояние`, `начинает с`, `обрабатывает`, — а без любой из них
 * падает своей диагностикой, до проверки типов не доехав. Значит `план требует
 * имени`, `не называет тип состояния`, `не называет начальное состояние` и `не
 * называет функцию шага` достижимы только у AST, собранного не парсером, — и
 * именно так их и достаёт второй этаж корпуса. Ветки эти не мёртвые: `checkTypes`
 * принимает AST от кого угодно, включая мост из FTS и построители внутри
 * компилятора.
 *
 * Первый этаж — обычные программы на flang в `fixtures/plany/`, потому что
 * ошибка посреди настоящего исходника и есть то, что видит человек.
 *
 * Ожидания здесь НЕ ЗАПИСАНЫ. Эталон — единственный источник правды о тексте
 * диагностики, и вторая его копия разошлась бы с ним молча; корпус отвечает за
 * то, ЧТО подать на вход, а `plans-corpus.test.mjs` — за то, что каждый вход
 * даёт свою, отличную от прочих, диагностику.
 */
import { readdirSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { parse } from "../src/parser.mjs"

const каталог = fileURLToPath(new URL("./fixtures/plany/", import.meta.url))

/** Программы корпуса, как они написаны на flang. Сортировка — по имени файла. */
export const ФАЙЛЫ_ПЛАНОВ = readdirSync(каталог)
  .filter((имя) => имя.endsWith(".flang"))
  .sort()
  .map((имя) => ({
    имя: `fixtures/plany/${имя}`,
    путь: `${каталог}${имя}`,
    текст: readFileSync(`${каталог}${имя}`, "utf8"),
  }))

/** Разбор без связывания: импортов у корпуса нет, и повторное имя внутри файла
    связывание сняло бы молча (см. `self-types.test.mjs`). */
const разобрать = (файл) => parse(файл.текст, файл.имя)

/**
 * Порчи AST — те четыре ветки, до которых из исходника не добраться.
 *
 * Основой взята целая программа корпуса: порча снимает у её плана ровно одно
 * поле, и всё остальное остаётся тем, чем было. Так диагностика оказывается
 * посреди настоящей программы, а не в трёх строках, — и место у неё то же, что
 * было бы у живого плана.
 */
const ПОЛЯ_ПЛАНА = [
  ["name", "без-имени", ""],
  ["state", "без-состояния", null],
  ["initial", "без-начала", null],
  ["handler", "без-шага", null],
]

function испортитьПлан(целое, поле, значение) {
  const планы = целое.plans.map((план, индекс) =>
    индекс === 0 ? { ...план, [поле]: значение } : план,
  )
  return { ...целое, plans: планы }
}

/**
 * Весь корпус одним списком: `{ имя, ast }`. Первый этаж — файлы, второй —
 * порчи AST поверх целой программы.
 */
export function корпусПланов() {
  const целое = ФАЙЛЫ_ПЛАНОВ.find((файл) => файл.имя.endsWith("00-tselyj.flang"))
  if (целое === undefined) throw new Error("в корпусе нет целой программы 00-tselyj.flang")
  const основа = разобрать(целое)

  const случаи = ФАЙЛЫ_ПЛАНОВ.map((файл) => ({ имя: файл.имя, ast: разобрать(файл) }))
  for (const [поле, метка, значение] of ПОЛЯ_ПЛАНА) {
    случаи.push({ имя: `AST/${метка}`, ast: испортитьПлан(основа, поле, значение) })
  }
  return случаи
}

/**
 * Ветки `ctx.report` эталона, поимённо. Список — не текст диагностики, а её
 * ОПОЗНАВАТЕЛЬ: пара «имя ветки → как узнать её в сообщении». Нужен затем, что
 * покрытие корпуса измеряется по веткам, а не по числу случаев: два случая на
 * одну ветку — это не двенадцать веток.
 */
export const ВЕТКИ_ЭТАЛОНА = [
  ["план требует имени", (текст) => текст === "план требует имени"],
  ["план объявлен дважды", (текст) => /^план «.+» объявлен дважды$/.test(текст)],
  ["словарь не собран", (текст) => /^план «.+» не собран: в программе нет сумм /.test(текст)],
  ["нет типа состояния", (текст) => /^план «.+» не называет тип состояния$/.test(текст)],
  ["состояние — неизвестный тип", (текст) => /^состояние плана «.+» — неизвестный тип «.+»$/.test(текст)],
  ["нет начального состояния", (текст) => /^план «.+» не называет начальное состояние$/.test(текст)],
  ["начало — неизвестная функция", (текст) => /^начальное состояние плана «.+» — неизвестная функция «.+»$/.test(текст)],
  ["начало с аргументами", (текст) => /^начальное состояние плана «.+» — функция «.+» с \d+ аргум\., а обязана быть без аргументов$/.test(текст)],
  ["нет функции шага", (текст) => /^план «.+» не называет функцию шага$/.test(текст)],
  ["шаг — неизвестная функция", (текст) => /^шаг плана «.+» — неизвестная функция «.+»$/.test(текст)],
  ["шаг не той арности", (текст) => /^шаг плана «.+» — функция «.+» с \d+ аргум\., а обязана принимать состояние и отклик$/.test(текст)],
  ["тип не сошёлся", (текст) => /, а ожидался «.+»$/.test(текст)],
]

/**
 * Четыре применения `сверитьИмяТипа` — они все двенадцатой веткой, и порознь их
 * не различает ничто, кроме начала сообщения. Считаются отдельно: выпади из
 * близнеца одно из четырёх, число веток не поехало бы.
 */
export const ПРИМЕНЕНИЯ_СВЕРКИ = [
  ["возврат начала", (текст) => /^функция «.+» плана «.+» возвращает «.+», а ожидался «(?!Продолжение)/.test(текст)],
  ["первый аргумент шага", (текст) => /^первый аргумент функции «.+» «.+», а ожидался «.+»$/.test(текст)],
  ["второй аргумент шага", (текст) => /^второй аргумент функции «.+» «.+», а ожидался «Отклик»$/.test(текст)],
  ["возврат шага", (текст) => /^функция «.+» плана «.+» возвращает «.+», а ожидался «Продолжение»$/.test(текст)],
]

/** Ветви `типОдним`: у типа без имени в сообщение уезжает слово вместо имени. */
export const СЛОВА_БЕЗ_ИМЕНИ = ["«список»", "«number»"]
