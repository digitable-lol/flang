test("каждая названная убегающая точка и правда упирается в предел у свидетеля", () => {
  assert.ok(УБЕГАЮЩИЕ.length > 0, "список УБЕГАЮЩИЕ пуст — тогда он не нужен вовсе")
  for (const точка of УБЕГАЮЩИЕ) {
    const итог = исход(() => interpret(найти(точка.файл), точка.функция, точка.аргументы, ПРЕДЕЛЫ))
    assert.ok(
      !итог.ok && итог.код === "FLANG_RECURSION_LIMIT",
      `${ключТочки(точка.файл, точка.функция, точка.аргументы)} названа убегающей («${точка.почему}»), ` +
        `а свидетель при ${ПРЕДЕЛЫ.maxSteps} шагах дал ${итог.ok ? "значение" : итог.код}: ` +
        "исключение больше не заслужено и обязано уйти из списка",
    )
  }
})

test("ни одна неназванная точка корпуса в предел шагов не упирается", (t) => {
  const убежали = []
  let точек = 0
  const начало = Date.now()
  for (const { file, program } of программы) {
    for (const fn of program.functions) {
      for (const args of functionGrid(fn)) {
        точек += 1
        const итог = исход(() => interpret(program, fn.name, args, ПРЕДЕЛЫ))
        if (!итог.ok && итог.код === "FLANG_RECURSION_LIMIT") убежали.push(ключТочки(file, fn.name, args))
      }
    }
  }
  const отчёт = сверьУбегающих(убежали)
  assert.ok(точек > 2000, `сетка слишком редкая: ${точек}`)
  t.diagnostic(
    `программ: ${программы.length}, точек сетки: ${точек}, ${отчёт}, за ${Math.round((Date.now() - начало) / 1000)} с`,
  )
})

test("на каждой названной точке напечатанный движок исчерпывает ПРЕДЕЛ_УБЕГАЮЩЕЙ", async (t) => {
  for (const точка of УБЕГАЮЩИЕ) {
    const модуль = await напечатать(точка.файл)
    const итог = зовиНапечатанное(модуль, точка.функция, точка.аргументы, {
      maxSteps: ПРЕДЕЛ_УБЕГАЮЩЕЙ,
      maxDepth: ПРЕДЕЛЫ.maxDepth,
    })
    assert.ok(
      !итог.ok && итог.код === "FLANG_RECURSION_LIMIT",
      `${ключТочки(точка.файл, точка.функция, точка.аргументы)}: напечатанный движок при ` +
        `${ПРЕДЕЛ_УБЕГАЮЩЕЙ} шагах дал ${итог.ok ? "значение" : итог.код} — тогда утверждение шести сверок пусто`,
    )
  }
  t.diagnostic(`точек названо ${УБЕГАЮЩИЕ.length}, на каждой отказ по пределу при ${ПРЕДЕЛ_УБЕГАЮЩЕЙ} шагах`)
})

test("цена одинакового предела: шаг напечатанного движка крупнее шага свидетеля", async (t) => {
  const файл = "022-generate-parentheses.flang"
  const программа = найти(файл)
  const модуль = await напечатать(файл)
  const н = 7

  const бюджетСвидетеля = наименьшийБюджет((шаги) =>
    исход(() => interpret(программа, "Правильные скобки", [н], { maxSteps: шаги, maxDepth: ПРЕДЕЛЫ.maxDepth })).ok)
  const бюджетЦели = наименьшийБюджет((шаги) =>
    зовиНапечатанное(модуль, "Правильные скобки", [н], { maxSteps: шаги, maxDepth: ПРЕДЕЛЫ.maxDepth }).ok)

  const размах = бюджетСвидетеля / бюджетЦели
  t.diagnostic(
    `«Правильные скобки» от ${н}: свидетелю нужно ${бюджетСвидетеля} шагов, напечатанному коду ${бюджетЦели} — ` +
      `размах ${размах.toFixed(1)}`,
  )
  assert.ok(
    размах >= РАЗМАХ_СЧЁТЧИКОВ,
    `размах счётчиков ${размах.toFixed(1)} — меньше объявленного ${РАЗМАХ_СЧЁТЧИКОВ}. ` +
      "Если счётчики сблизили, это хорошая новость: перепроверьте, нужны ли ещё исключения УБЕГАЮЩИЕ, " +
      "и поправьте число в corpus-grid.mjs.",
  )
})
