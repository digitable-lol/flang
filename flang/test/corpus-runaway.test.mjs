/**
 * Убегающие точки корпуса: список с зубами.
 *
 * ── Что случилось и чего это стоило ─────────────────────────────────────────
 *
 * Сетка корпусных сверок портит аргументы примеров значениями из `ЧУЖИЕ`. На
 * двух точках из 8799 испорченный аргумент оказывается таким, что ответа нет
 * ни у кого: «Правильные скобки» от 42 — это Каталан(42) ≈ 6·10²² слов.
 * Интерпретатор отвечает на них отказом по пределу шагов за ~1,5 с, и это
 * правильный ответ.
 *
 * Напечатанный код отвечал на ту же точку ЧАСАМИ. Причина не в стороже —
 * сторож исправен, — а в том, что предел шагов у двух движков считает разные
 * единицы:
 *
 *   наименьший бюджет шагов, при котором «Правильные скобки» от н ещё
 *   отвечают ЗНАЧЕНИЕМ (измерено двоичным поиском, число детерминированное):
 *
 *     н              1       3        5         7           9
 *     свидетель       313    2795   25 512   268 289   3 097 466
 *     восемь целей   3      22      196     2 055      23 713
 *
 * Отношение 130,6 держится от н=5 до н=9. Читается это так: один и тот же
 * `maxSteps` покупает напечатанному коду в 130,6 раза больше ПРИМЕНЕНИЙ
 * ФУНКЦИЙ. Пока цена применения ограничена, расхождение одностороннее и
 * безопасное — так и было записано в шести сверках. Но она не ограничена:
 * `добавить` копирует весь список, а стоит один шаг. У программы, копящей
 * ответ в списке, работа квадратична по числу применений, и 130,6 превращается
 * в её квадрат. Отсюда полторы секунды у свидетеля и час у напечатанного кода на
 * одной и той же точке.
 *
 * ── Что теперь делают сверки ────────────────────────────────────────────────
 *
 * На убегающей точке сверять по значению нечего: значения нет ни у кого.
 * Поэтому напечатанный код спрашивается там бюджетом `ПРЕДЕЛ_УБЕГАЮЩЕЙ` — тем,
 * который он исчерпывает за миллисекунды, — и требование от этого не слабеет,
 * а УЖЕСТОЧАЕТСЯ: было «если он тоже остановился, то тем же кодом», стало
 * «обязан остановиться».
 *
 * ── Зубы ────────────────────────────────────────────────────────────────────
 *
 * Молчаливый пропуск недопустим, поэтому список `УБЕГАЮЩИЕ` проверяется в обе
 * стороны и на цене:
 *
 *   1. каждое имя списка обязано И ПРАВДА упираться в предел у свидетеля —
 *      иначе исключение не заслужено и обязано уйти из списка;
 *   2. ни одна НЕназванная точка корпуса упираться в предел не смеет —
 *      появится такая, тест назовёт её и покраснеет;
 *   3. на каждой названной точке напечатанный движок обязан исчерпать
 *      `ПРЕДЕЛ_УБЕГАЮЩЕЙ` — иначе утверждение шести сверок было бы пустым;
 *   4. размах счётчиков — не рассказ, а измерение: он считается здесь заново
 *      двоичным поиском и обязан быть не меньше `РАЗМАХ_СЧЁТЧИКОВ`. Сблизят
 *      счётчики — тест покраснеет, и исключения надо будет пересмотреть.
 *
 * Тулчейна этому файлу не нужно: цель JS печатается и грузится модулем, а
 * счётчик шагов у неё тот же, что у остальных семи (см. таблицу).
 */
import assert from "node:assert/strict"
import { writeFile } from "node:fs/promises"
import { join } from "node:path"
import { test } from "node:test"
import { pathToFileURL } from "node:url"

import { evaluate as interpret } from "../src/interpret.mjs"
import { emitJs } from "../src/emit/js.mjs"
import { camel } from "../src/naming.mjs"
import {
  functionGrid,
  loadPrograms,
  ключТочки,
  сверьУбегающих,
  ПРЕДЕЛ_УБЕГАЮЩЕЙ,
  ПРЕДЕЛЫ,
  РАЗМАХ_СЧЁТЧИКОВ,
  УБЕГАЮЩИЕ,
} from "./corpus-grid.mjs"
import { рабочийКаталог, средаСборки } from "./tempdir.mjs"

const программы = loadPrograms()
const рабочий = рабочийКаталог("corpus-runaway")

const найти = (файл) => {
  const запись = программы.find((п) => п.file === файл)
  assert.ok(запись, `в корпусе нет программы «${файл}» — список УБЕГАЮЩИЕ ссылается в пустоту`)
  return запись.program
}

/** Исход вызова: значение или код отказа. */
function исход(вызов) {
  try {
    return { ok: true, значение: вызов() }
  } catch (беда) {
    return { ok: false, код: беда?.code ?? "?", текст: String(беда?.message ?? беда) }
  }
}

/* ─────────── цель JS: печатается и грузится модулем, тулчейна не надо ─────────── */

let счёт = 0
const модули = new Map()
async function напечатать(файл) {
  if (модули.has(файл)) return модули.get(файл)
  const печать = emitJs(найти(файл))
  счёт += 1
  const путь = join(рабочий, `m${счёт}-${печать.files[0].path}`)
  await writeFile(путь, печать.files[0].content, "utf8")
  const модуль = await import(pathToFileURL(путь).href)
  модули.set(файл, модуль)
  return модуль
}

const имяЭкспорта = (имя) => {
  const идент = camel(имя)
  return /^[A-Za-z_$]/u.test(идент) ? идент : `_${идент}`
}

function зовиНапечатанное(модуль, имя, аргументы, пределы) {
  модуль.$newContext(пределы)
  const функция = модуль[имяЭкспорта(имя)]
  assert.equal(typeof функция, "function", `в напечатанном JS нет «${имя}»`)
  return исход(() => функция(...аргументы))
}

/**
 * Наименьший бюджет шагов, при котором вызов ещё отвечает значением.
 *
 * Мерится не время, а детерминированное целое: от загрузки машины оно не
 * зависит, а разницу между движками показывает точнее любого секундомера.
 */
function наименьшийБюджет(ок, потолок = 100_000_000) {
  let верх = 1
  while (!ок(верх)) {
    верх *= 2
    assert.ok(верх <= потолок, `бюджет перевалил за ${потолок}, а ответа всё нет`)
  }
  let низ = Math.floor(верх / 2)
  while (низ + 1 < верх) {
    const середина = Math.floor((низ + верх) / 2)
    if (ок(середина)) верх = середина
    else низ = середина
  }
  return верх
}

