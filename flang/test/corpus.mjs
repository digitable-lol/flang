/**
 * Корпус моделей `.fts` для сверок ядра, написанного на flang, — общий для
 * `core-lexer`, `core-parser` (сквозная цепочка), `core-json` (печать документа)
 * и `core-evaluate` (вычисление утилит).
 *
 * ── Откуда он теперь берётся ────────────────────────────────────────────────
 * Раньше корпус собирался по всему дереву: модели лежали в `examples/`,
 * `tools/ftsc/stdlib/`, `web/demo/models/` — то есть в старом проекте FTS.
 * Проект вынесен из репозитория (тег `fts-pered-udaleniem`), и модели переехали
 * сюда, в фикстуры языка: `flang/test/fixtures/fts/`. Это не копия — оригинал
 * ушёл вместе с проектом.
 *
 * Тела моделей лежат УЖЕ БЕЗ заголовка `модуль …`: его снимал разборщик
 * старого компилятора (`tools/ftsc/src/parse-module.mjs`), и снят он один раз,
 * при переносе. Поэтому языку разборщик чужого заголовка больше не нужен, а
 * пустые строки в начале некоторых фикстур — это ровно те строки, которые он
 * заменял пустыми, чтобы номера строк в диагностиках не разъезжались.
 *
 * ── Чего здесь больше нет и почему ──────────────────────────────────────────
 * Внешний корпус по переменной `FTS_MODEL_PATH` убран. Он существовал затем,
 * чтобы пользователь старого проекта мог подключить к сверке СВОИ модели;
 * пользователей у проекта, которого нет, не бывает. Довод, ради которого
 * переменная заводилась, при этом остаётся в силе и здесь: фактический охват
 * печатается в выводе (`строкиОхвата`), потому что проверка, чей охват может
 * тихо схлопнуться, зелена ровно так же, как исправная.
 */
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

/* Выборка своя, не из `node:fs`: тамошний `globSync` появился только в Node 22,
   а пакет обещает Node ≥ 20 — импорт из `node:fs` ронял бы файл целиком, до
   первой проверки. */
import { globSync } from "./glob.mjs"

/**
 * Два источника, и оба обязательны.
 *
 * `фикстуры` — модели, приехавшие вместе со старым проектом. `замер` — три
 * задания замера авторства (`benchmarks/model-authoring/reference/d*.fts`): они
 * из репозитория никуда не уезжали и в корпусе стояли всегда, потому что старая
 * выборка шла по всему дереву. Забыть их значило бы тихо ужать сверку на три
 * модели — ровно та потеря охвата, ради которой этот файл и написан.
 */
const ИСТОЧНИКИ = [
  { имя: "фикстуры", каталог: fileURLToPath(new URL("./fixtures/fts/", import.meta.url)), образец: "**/*.fts" },
  { имя: "замер", каталог: fileURLToPath(new URL("../../benchmarks/model-authoring/reference/", import.meta.url)), образец: "*.fts" },
]

/** Имя основного источника — под ним идут модели фикстур. */
export const РЕПОЗИТОРИЙ = ИСТОЧНИКИ[0].имя

/**
 * Все файлы корпуса.
 *
 * Возвращаются именно файлы, а не документы: какие из них документы ядра, а
 * какие — намеренно сломанные модели, решает вызывающий тест, у каждого свой
 * отбор.
 *
 * @returns {{имя: string, путь: string, источник: string}[]}
 */
export function файлыКорпуса() {
  return ИСТОЧНИКИ.flatMap(({ имя: источник, каталог, образец }) =>
    globSync(образец, { cwd: каталог })
      .sort()
      .map((путь) => ({ имя: путь, путь: каталог + путь, источник })),
  )
}

/** Текст файла корпуса — отдельной функцией, чтобы тесты не знали про пути. */
export const текстМодели = ({ путь }) => readFileSync(путь, "utf8")

/**
 * Строки об охвате для вывода теста: сколько моделей проверено и откуда взяты.
 *
 * Первая строка — итог (она же годится для имени теста), дальше по строке на
 * каждый источник: сколько файлов найдено и сколько из них попало в сверку.
 * Разница между этими числами — не ошибка (в корпусе есть намеренно сломанные
 * модели), но видеть её надо.
 *
 * @param {{источник: string}[]} корпус модели, реально попавшие в сверку
 * @param {{источник: string}[]} файлы все файлы, из которых корпус отбирался
 */
export function строкиОхвата(корпус, файлы) {
  const считать = (список, источник) => список.filter((запись) => запись.источник === источник).length
  const источники = [...new Set(файлы.map(({ источник }) => источник))]
  const итог = `${корпус.length} моделей из ${файлы.length} файлов .fts`
  const подробно = источники.map((источник) => {
    const откуда = ИСТОЧНИКИ.find((и) => и.имя === источник)?.каталог ?? "?"
    return `  ${источник} (${откуда}): моделей ${считать(корпус, источник)} из ${считать(файлы, источник)} файлов .fts`
  })
  return [итог, ...подробно]
}
