/**
 * Корпус моделей `.fts` для дифференциальных сверок ядра — общий для
 * `core-json.test.mjs` (печать документа) и `core-parser.test.mjs` (сквозная
 * цепочка «текст → лексер → парсер → JSON»).
 *
 * Корпус состоит из двух частей. Первая — модели самого репозитория: она есть
 * всегда и у всех одна и та же. Вторая — внешние каталоги моделей; они
 * подключаются ТОЛЬКО переменной окружения `FTS_MODEL_PATH` (список каталогов
 * через тот же разделитель, что и в `PATH`, — как `FTS_TOOLCHAIN_PATH`), и
 * никак иначе.
 *
 * Почему так строго. Раньше внешний каталог подхватывался по факту
 * существования пути в чужой домашней папке. Охват от этого менялся молча: на
 * машине автора корпус был 56 моделей, на чистом клоне — 47, а в выводе теста
 * ни то, ни другое число не появлялось. Утверждение «побайтовое совпадение на
 * 56 моделях из 56» у читателя не воспроизводилось, и заметить это было
 * неоткуда. Проверка, чей охват зависит от постороннего каталога и которая об
 * этом молчит, даёт ложную уверенность — это дефект проверки, а не документации.
 *
 * Отсюда два правила, и оба обязательны:
 *
 *   1. внешние модели подключает только явно заданная переменная окружения;
 *   2. фактический охват печатается в выводе теста — числа и источники
 *      (`строкиОхвата`), чтобы прогон на чистом клоне отличался от прогона с
 *      подключённым внешним корпусом по одному взгляду на вывод.
 *
 * Ошибка в `FTS_MODEL_PATH` — несуществующий каталог, файл вместо каталога,
 * каталог без единой модели — это падение с внятным текстом, а не молчаливый
 * пропуск. Иначе опечатка в переменной вернула бы ровно ту же беду с другой
 * стороны: охват тихо схлопнулся бы к репозиторному, а тест продолжил бы
 * зеленеть.
 */
import { readFileSync, statSync } from "node:fs"
import { delimiter, resolve } from "node:path"
import { fileURLToPath } from "node:url"

/* Выборка своя, не из `node:fs`: тамошний `globSync` появился только в Node 22,
   а пакет обещает Node ≥ 20 — импорт из `node:fs` ронял бы файл целиком, до
   первой проверки. */
import { globSync } from "./glob.mjs"

/** Единственный способ подключить к сверке модели вне репозитория. */
export const ПЕРЕМЕННАЯ = "FTS_MODEL_PATH"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/** Имя источника, под которым в корпусе идут модели самого репозитория. */
export const РЕПОЗИТОРИЙ = "репозиторий"

const модели = (каталог) =>
  globSync("**/*.fts", { cwd: каталог, exclude: (путь) => путь.includes("node_modules") }).sort()

/**
 * Каталоги из `FTS_MODEL_PATH`, проверенные на пригодность.
 *
 * Пустые записи (хвостовой разделитель) пропускаются — это опечаткой не
 * является. Всё остальное, что не даёт моделей, — ошибка с указанием, какая
 * именно запись переменной виновата.
 *
 * Вызывается на верхнем уровне модуля, а не из `файлыКорпуса()`, намеренно:
 * тогда битая переменная роняет загрузку файла теста целиком, до объявления
 * первого `test`. Отложенная проверка давала бы «прошло 38, упало 1» —
 * половина сверки успевала бы отчитаться об успехе на урезанном корпусе, и
 * ошибку опять было бы легко проглядеть.
 */
function внешниеКаталоги() {
  const записи = String(process.env[ПЕРЕМЕННАЯ] ?? "")
    .split(delimiter)
    .map((запись) => запись.trim())
    .filter((запись) => запись.length > 0)

  return записи.map((запись) => {
    const каталог = resolve(запись)
    let сведения
    try {
      сведения = statSync(каталог)
    } catch {
      throw new Error(
        `${ПЕРЕМЕННАЯ}: каталога «${запись}» нет (искали ${каталог}). ` +
          `Внешний корпус подключается только этой переменной, поэтому промолчать о битом пути нельзя: ` +
          `поправьте путь или уберите запись из ${ПЕРЕМЕННАЯ} — тогда сверка пойдёт по одним моделям репозитория.`,
      )
    }
    if (!сведения.isDirectory()) {
      throw new Error(
        `${ПЕРЕМЕННАЯ}: «${запись}» — не каталог (${каталог}). ` +
          `В переменной перечисляются каталоги с моделями, а не отдельные файлы.`,
      )
    }
    const файлы = модели(каталог)
    if (файлы.length === 0) {
      throw new Error(
        `${ПЕРЕМЕННАЯ}: в каталоге «${запись}» нет ни одного файла .fts (искали ${каталог}/**/*.fts). ` +
          `Пустой внешний корпус молча уменьшил бы охват сверки — уберите запись из ${ПЕРЕМЕННАЯ} или укажите каталог с моделями.`,
      )
    }
    return { источник: каталог, каталог, файлы }
  })
}

/* Проверка переменной — при загрузке модуля: см. комментарий выше. */
const внешние = внешниеКаталоги()

/**
 * Все файлы корпуса: сначала модели репозитория, затем внешние — в порядке
 * записей `FTS_MODEL_PATH`.
 *
 * Возвращаются именно файлы, а не документы: какие из них документы ядра, а
 * какие — файлы-функторы, заголовки модулей и намеренно сломанные модели,
 * решает вызывающий тест, у каждого свой отбор.
 *
 * @returns {{имя: string, путь: string, источник: string}[]}
 */
export function файлыКорпуса() {
  const части = [{ источник: РЕПОЗИТОРИЙ, каталог: корень, файлы: модели(корень) }, ...внешние]
  return части.flatMap(({ источник, каталог, файлы }) =>
    файлы.map((путь) => ({
      /* Имя внешней модели — полный путь: под «courses/…» уже нельзя было
         понять, чей это каталог и подключён ли он вообще. */
      имя: источник === РЕПОЗИТОРИЙ ? путь : `${каталог}/${путь}`,
      путь: (каталог.endsWith("/") ? каталог : `${каталог}/`) + путь,
      источник,
    })),
  )
}

/** Текст файла корпуса — отдельной функцией, чтобы тесты не знали про пути. */
export const текстМодели = ({ путь }) => readFileSync(путь, "utf8")

/**
 * Строки об охвате для вывода теста: сколько моделей проверено и откуда взяты.
 *
 * Первая строка — итог (она же годится для имени теста), дальше по строке на
 * каждый источник: сколько файлов найдено и сколько из них попало в сверку.
 * Разница между этими числами — не ошибка (в репозитории есть файлы-функторы и
 * намеренно сломанные модели), но видеть её надо: если внешний каталог даёт
 * девять файлов и ноль моделей, это должно бросаться в глаза.
 *
 * @param {{источник: string}[]} корпус модели, реально попавшие в сверку
 * @param {{источник: string}[]} файлы все файлы, из которых корпус отбирался
 */
export function строкиОхвата(корпус, файлы) {
  const считать = (список, источник) => список.filter((запись) => запись.источник === источник).length
  const источники = [...new Set(файлы.map(({ источник }) => источник))]
  const внешниеИсточники = источники.filter((источник) => источник !== РЕПОЗИТОРИЙ)

  const итог =
    внешниеИсточники.length === 0
      ? `${корпус.length} моделей: только репозиторий, внешний корпус не подключён (${ПЕРЕМЕННАЯ} не задана)`
      : `${корпус.length} моделей: репозиторий ${считать(корпус, РЕПОЗИТОРИЙ)} + внешние ${корпус.length - считать(корпус, РЕПОЗИТОРИЙ)} (${ПЕРЕМЕННАЯ})`

  const подробно = источники.map((источник) => {
    const откуда = источник === РЕПОЗИТОРИЙ ? `${РЕПОЗИТОРИЙ} ${корень}` : `${ПЕРЕМЕННАЯ} ${источник}`
    return `  ${откуда}: моделей ${считать(корпус, источник)} из ${считать(файлы, источник)} файлов .fts`
  })

  return [итог, ...подробно]
}
