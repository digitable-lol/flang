/**
 * Сторож чисел в прозе — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/count-guard.mjs`. Здесь три
 * разных обязательства, и путать их нельзя:
 *
 *   1. на дереве сторож ЧИСТ — ни одно проверяемое число прозы не разошлось с
 *      измерителем;
 *   2. сторож ЛОВИТ — на подложенных случаях, по одному на каждый вид записи, и
 *      ловит расхождение в ОДНУ цифру;
 *   3. сторож МОЛЧИТ там, где обязан молчать: на приближениях, на надгробиях, на
 *      числе, которое говорит не о размере файла, и на пути, которого нет.
 *
 * Второе и третье написаны потому, что проверка, которая не может упасть,
 * выглядит ровно как проверка, у которой всё хорошо. Тем же доводом открывается
 * шапка `flang/test/claim-guard.test.mjs`, и он в этом дереве самый дорогой из
 * выученных: тест, который не умеет краснеть, хуже отсутствующего — он выдаёт
 * спокойствие, которого нет.
 *
 * Запуск: node --test flang/test/count-guard.test.mjs
 */
import assert from "node:assert/strict"
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises"
import { readFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { сводКорпуса } from "../scripts/proof-ledger.mjs"
import {
  КОРЕНЬ,
  основыДля,
  проверить,
  строкПод,
  строкиТаблиц,
  ВЕДОМОСТЬ,
} from "../scripts/count-guard.mjs"

/** Прогон сторожа по временному дереву. */
async function наДереве(файлы, свод = null) {
  const каталог = await mkdtemp(join(tmpdir(), "count-guard-"))
  try {
    for (const [имя, текст] of Object.entries(файлы)) {
      const путь = join(каталог, имя)
      await mkdir(join(путь, ".."), { recursive: true })
      await writeFile(путь, текст, "utf8")
    }
    return проверить(каталог, свод)
  } finally {
    await rm(каталог, { recursive: true, force: true })
  }
}

/* Свод корпуса считается один раз: он обходит все `.flang` дерева. */
const СВОД = (await сводКорпуса()).итог

test("на дереве репозитория сторож чист", () => {
  const расхождения = проверить(КОРЕНЬ, СВОД)
  assert.deepEqual(
    расхождения.map((р) => `${р.файл}:${р.строка} — ${р.род} про ${р.про}: сказано ${р.сказано}, измерено ${р.измерено}`),
    [],
    "число в прозе разошлось с измерителем: правьте прозу, а не сторожа",
  )
})

test("измеритель строк считает ровно то же, что wc -l", () => {
  /* Улика — файл, который здесь же и читается: строк в нём столько, сколько
     переводов строки. Совпадение с `wc -l` проверяется тем же определением, а
     не вторым счётчиком: второй счётчик — это второе место, где можно ошибиться. */
  const текст = readFileSync(new URL("../scripts/count-guard.mjs", import.meta.url), "utf8")
  const переводов = [...текст].filter((с) => с === "\n").length
  assert.equal(строкПод("flang/scripts/count-guard.mjs"), переводов)
})

test("измеритель понимает файл, каталог и образец со звёздочкой", () => {
  const файл = строкПод("flang/scripts/count-guard.mjs")
  const образец = строкПод("flang/scripts/count-*.mjs")
  assert.equal(образец, файл, "образец, накрывающий один файл, обязан дать его размер")
  const каталог = строкПод("flang/core/")
  const звёздочкой = строкПод("flang/core/*.flang")
  assert.equal(каталог, звёздочкой, "каталог меряется по своим исходникам, спецификация рядом в счёт не идёт")
  assert.equal(строкПод("flang/такого-каталога-нет/*.mjs"), null, "измерителя у несуществующего пути нет, и выдумывать ноль нельзя")
})

test("путь читается и от корня, и от каталога документа", () => {
  /* Настоящий случай: `src/lexer.mjs` в `flang/cat/POLY.md` — это
     `flang/src/lexer.mjs`, а `src/*.ts` в `flang/core/SPEC.md` — корневое ядро
     на TypeScript. Обе записи живут в дереве, и решает место документа. */
  assert.deepEqual(основыДля("flang/cat/POLY.md"), ["", "flang", "flang/cat"])
  assert.deepEqual(основыДля("README.md"), [""])
  assert.equal(
    строкПод("src/lexer.mjs", КОРЕНЬ, основыДля("flang/cat/POLY.md")),
    строкПод("flang/src/lexer.mjs"),
  )
  assert.equal(строкПод("src/lexer.mjs", КОРЕНЬ, [""]), null, "в корне репозитория `src/lexer.mjs` нет — там TypeScript")
})

test("сторож ЛОВИТ расхождение в ОДНУ единицу, во всех трёх записях", async () => {
  /* Тот самый порог: сторож, который ловит только грубое расхождение, пропустит
     ровно тот случай, из-за которого он заведён, — цифру, поправленную не там.
     Файл-улика ровно в три строки, а проза называет четыре. */
  for (const [имя, проза] of [
    ["путь слева", "Слой `код.mjs` — 4 строк, и на этом весь слой."],
    ["число слева", "Всего 4 строк в `код.mjs`."],
    ["без предлога", "Перенос 4 строк `код.mjs` на другую цель."],
  ]) {
    const расхождения = await наДереве({ "код.mjs": "один\nдва\nтри\n", "проза.md": `${проза}\n` })
    assert.equal(расхождения.length, 1, `${имя}: сторож не поймал подложенный размер`)
    assert.equal(расхождения[0].сказано, 4, имя)
    assert.equal(расхождения[0].измерено, 3, имя)
  }
})

test("сторож читает и английскую прозу: половина дерева написана по-английски", async () => {
  /* Сторож, знающий одно слово из двух, был бы зелёным на половине дерева от
     незнания, а не от чистоты. Проверяются обе записи, таблица и приближение. */
  const расхождения = await наДереве({
    "код.mjs": "один\nдва\nтри\n",
    "проза.md":
      "The layer `код.mjs` is 4 lines.\n\n" +
      "Another way: 4 lines in `код.mjs`.\n\n" +
      "| Layer | Lines |\n|---|---|\n| `код.mjs` | 7 |\n\n" +
      "Approximate, and left alone: `код.mjs` is about 40 lines.\n",
  })
  assert.deepEqual(
    расхождения.map((р) => [р.род, р.сказано, р.измерено]),
    [
      ["строк", 4, 3],
      ["строк", 4, 3],
      ["строк (таблица)", 7, 3],
    ],
  )
})

test("сторож ЛОВИТ строку таблицы со столбцом «Строк»", async () => {
  const расхождения = await наДереве({
    "код.mjs": "один\nдва\nтри\n",
    "проза.md": "| Слой | Строк | Что делает |\n|---|---|---|\n| `код.mjs` | 99 | считает |\n",
  })
  assert.equal(расхождения.length, 1, "сторож не поймал строку таблицы")
  assert.equal(расхождения[0].род, "строк (таблица)")
  assert.equal(расхождения[0].строка, 3, "названа не та строка таблицы")
})

test("сторож ЛОВИТ разошедшееся число ведомости", async () => {
  const расхождения = await наДереве(
    { "проза.md": "Числом: высказано 4 утверждения, из них 2 доказаны ядром.\n" },
    { claims: { total: 9, proved: 6, grid: 2, declared: 1 } },
  )
  assert.deepEqual(
    расхождения.map((р) => [р.про, р.сказано, р.измерено]),
    [
      ["claims.total", 4, 9],
      ["claims.proved", 2, 6],
    ],
  )
})

test("сторож МОЛЧИТ на приближении: «~70 строк» обещает приблизительность и держит её", async () => {
  const расхождения = await наДереве({
    "код.mjs": "один\nдва\nтри\n",
    "проза.md": "Слой `код.mjs` — ~70 строк.\n",
  })
  assert.deepEqual(расхождения, [], "приближение честно называет себя приближением")
})

test("сторож МОЛЧИТ на надгробии снятого числа", async () => {
  const расхождения = await наДереве({
    "код.mjs": "один\nдва\nтри\n",
    "проза.md": "Здесь стояло, что в `код.mjs` 999 строк. Файл с тех пор переписан.\n",
  })
  assert.deepEqual(расхождения, [], "память о правке — не утверждение; краснеть на ней значит требовать стирать историю")
})

test("сторож МОЛЧИТ, когда число говорит не о размере файла, а о куске внутри него", async () => {
  /* Настоящая фраза из `flang/conc/SPEC.md`: «плюс 269 строк склейки в
     `js.mjs`». 269 — размер вставки, а не файла, и приписать их файлу значило бы
     краснеть на верном предложении. */
  const расхождения = await наДереве({
    "js.mjs": Array.from({ length: 900 }, () => "x").join("\n") + "\n",
    "проза.md": "Планировщик печатается отдельно, плюс 269 строк склейки в `js.mjs` — столько файл теряет без него.\n",
  })
  assert.deepEqual(расхождения, [])
})

test("сторож МОЛЧИТ на пути, которого в дереве нет", async () => {
  /* Несуществующий путь — отдельная беда и отдельный сторож. Здесь краснеть
     нечем: измерителя нет, а выдумывать «ноль строк» значит врать числом. */
  const расхождения = await наДереве({ "проза.md": "Слой `нет-такого.mjs` — 12 строк.\n" })
  assert.deepEqual(расхождения, [])
})

test("сторож не читает числа из блоков кода", async () => {
  /* В блоке кода стоит образец вывода, а не утверждение автора о дереве. */
  const расхождения = await наДереве({
    "код.mjs": "один\nдва\nтри\n",
    "проза.md": "Вывод команды:\n\n```\n`код.mjs` — 4 строк\n```\n",
  })
  assert.deepEqual(расхождения, [], "сторож обязан читать прозу, а не образцы вывода")
})

test("обход доходит до глубоких каталогов, а не молчит по недосмотру", () => {
  /* Зелёный сторож обязан быть зелёным ОТ ЧИСТОТЫ, а не оттого, что обход
     однажды сузили. Улика — таблица размеров слоёв в `flang/cat/POLY.md`: она
     лежит на третьем уровне и содержит одиннадцать проверяемых строк. */
  const текст = readFileSync(new URL("../cat/POLY.md", import.meta.url), "utf8")
  const строки = строкиТаблиц(текст)
  assert.ok(строки.length >= 11, `таблица слоёв в flang/cat/POLY.md не разобрана: найдено ${строки.length} строк`)
  for (const с of строки) {
    assert.equal(
      строкПод(с.путь, КОРЕНЬ, основыДля("flang/cat/POLY.md")),
      с.сказано,
      `flang/cat/POLY.md:${с.строка} — ${с.путь}`,
    )
  }
})

test("каждое правило ведомости называет живое поле свода", () => {
  assert.ok(ВЕДОМОСТЬ.length > 0, "список правил пуст — тогда и проверять нечего")
  for (const правило of ВЕДОМОСТЬ) {
    const значение = правило.поле.split(".").reduce((о, к) => о?.[к], СВОД)
    assert.equal(
      typeof значение,
      "number",
      `правило «${правило.что}» смотрит в поле ${правило.поле}, которого в своде больше нет`,
    )
  }
})

test("каждое правило ведомости находит фразу в дереве, а не стережёт пустоту", () => {
  /* Правило, чья фраза из прозы исчезла, остаётся зелёным и не стережёт ничего —
     тот же дефект, что у сторожа печати, когда обещание вычёркивают из README.
     Улика — `docs/overview.ru.md`, где стоят все четыре числа ведомости. */
  const обзор = readFileSync(new URL("../../docs/overview.ru.md", import.meta.url), "utf8")
  for (const правило of ВЕДОМОСТЬ) {
    assert.match(
      обзор,
      правило.образец,
      `фразы под правилом «${правило.что}» в docs/overview.ru.md больше нет: ` +
        `перепишите правило вместе с прозой, а не молчком`,
    )
  }
})
