/**
 * `flang/stdlib/datetime.flang` против календаря, который считает не он.
 *
 * Примеры внутри модуля проверяют написанные точки. Здесь проверяется КЛАСС:
 * каждый день подряд на промежутке в семнадцать лет сверяется с `Date` из
 * JavaScript — независимой реализацией того же григорианского календаря.
 * Календарные формулы ошибаются не «немного», а ровно на день, и такая
 * ошибка на написанных точках прячется, а на промежутке — нет.
 *
 * Сверяются три вещи: перевод даты в дни, обратный перевод и день недели.
 * Плюс круговое тождество разбора и печати ISO-8601 на тех же днях.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import test from "node:test"

import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"

const программа = parse(readFileSync(fileURLToPath(new URL("../stdlib/datetime.flang", import.meta.url)), "utf8"), "datetime.flang")
const настройки = { maxSteps: 200_000_000, maxDepth: 10_000 }
const зовём = (имя, ...аргументы) => evaluate(программа, имя, аргументы, настройки)
const дата = (год, месяц, сутки) => ({ variant: "Календарный день", fields: { год, месяц, сутки } })

/* Промежуток: 2015-01-01 .. 2031-12-31, каждый день подряд. */
const ОТ = Date.UTC(2015, 0, 1) / 86400000
const ДО = Date.UTC(2031, 11, 31) / 86400000

test("дни от эпохи и обратно совпадают с календарём JS на каждом дне 2015…2031", () => {
  for (let д = ОТ; д <= ДО; д += 1) {
    const свидетель = new Date(д * 86400000)
    const г = свидетель.getUTCFullYear()
    const м = свидетель.getUTCMonth() + 1
    const с = свидетель.getUTCDate()

    assert.equal(зовём("Дней от эпохи", дата(г, м, с)), д, `Дней от эпохи для ${г}-${м}-${с}`)

    const обратно = зовём("Дата из дней", д)
    assert.deepEqual(обратно.fields, { год: г, месяц: м, сутки: с }, `Дата из дней для ${д}`)

    assert.equal(зовём("День недели", дата(г, м, с)), свидетель.getUTCDay(), `День недели для ${г}-${м}-${с}`)
  }
})

test("разбор и печать ISO-8601 — круговое тождество на каждом дне 2015…2031", () => {
  for (let д = ОТ; д <= ДО; д += 1) {
    const текст = new Date(д * 86400000).toISOString().slice(0, 10)
    const итог = зовём("Разобрать отметку", текст)
    assert.equal(итог.variant, "Дата разобрана", `${текст}: ${итог.fields?.причина}`)
    assert.equal(зовём("Напечатать дату", итог.fields.отметка.fields.день), текст)
  }
})

test("високосность совпадает с календарём JS на годах 1600…2400", () => {
  for (let г = 1600; г <= 2400; г += 1) {
    const свидетель = new Date(Date.UTC(г, 1, 29)).getUTCMonth() === 1
    assert.equal(зовём("Високосный год", г), свидетель, `високосность ${г}`)
  }
})

test("день года считается тем же числом, что и разность с первым января", () => {
  for (const [г, м, с, ожидание] of [
    [2026, 1, 1, 1],
    [2026, 3, 1, 60],
    [2024, 3, 1, 61],
    [2026, 12, 31, 365],
    [2024, 12, 31, 366],
  ]) {
    assert.equal(зовём("День года", дата(г, м, с)), ожидание, `${г}-${м}-${с}`)
  }
})

test("отметка с поясом даёт то же мгновение, что и та же отметка по Гринвичу", () => {
  const сПоясом = зовём("Разобрать отметку", "2026-08-18T13:00:00+03:00")
  const поГринвичу = зовём("Разобрать отметку", "2026-08-18T10:00:00Z")
  assert.equal(сПоясом.variant, "Дата разобрана")
  assert.equal(поГринвичу.variant, "Дата разобрана")
  assert.equal(зовём("Одно мгновение", сПоясом.fields.отметка, поГринвичу.fields.отметка), true)
  assert.equal(
    зовём("Секунд от эпохи", сПоясом.fields.отметка),
    Date.parse("2026-08-18T13:00:00+03:00") / 1000,
    "секунды от эпохи совпадают с Date.parse",
  )
})

test("на мусоре разбор отметки молчит, а не выдумывает дату", () => {
  for (const мусор of [
    "",
    "2026",
    "2026-08",
    "20260818",
    "2026/08/18",
    "2026-13-01",
    "2026-00-10",
    "2026-02-30",
    "2026-08-18T25:00:00",
    "2026-08-18T12:60:00",
    "2026-08-18T12:00:00МСК",
    "2026-08-18T12:00:00+3:00",
    "аааа-аа-аа",
    "2026-08-18T12:00",
  ]) {
    const итог = зовём("Разобрать отметку", мусор)
    assert.equal(итог.variant, "Дата не разобрана", `на входе ${JSON.stringify(мусор)} разбор выдал значение`)
    assert.ok(итог.fields.причина.length > 0)
  }
})
