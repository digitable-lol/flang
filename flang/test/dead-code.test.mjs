const workdir = await mkdtemp(join(tmpdir(), "flang-dead-code-"))
after(async () => {
  await rm(workdir, { recursive: true, force: true })
})

let счётчик = 0
async function песочница(файлы = {}) {
  const каталог = join(workdir, `s${(счётчик += 1)}`)
  await mkdir(каталог, { recursive: true })
  for (const [имя, текст] of Object.entries(файлы)) await writeFile(join(каталог, имя), текст, "utf8")
  return каталог
}

/** Имена функций входного файла — то же, что знает загрузчик про свой вход. */
async function свои(путь) {
  return parse(await readFile(путь, "utf8"), путь).functions.map((функция) => функция.name)
}

async function напечатать(аргументы) {
  const { stdout, stderr } = await run("node", [cli, "emit", ...аргументы], { maxBuffer: 256 * 1024 * 1024 })
  assert.equal(stderr, "", "успешная печать не пишет в stderr")
  return JSON.parse(stdout)
}

const байт = (файлы) => файлы.reduce((сумма, файл) => сумма + Buffer.byteLength(файл.content, "utf8"), 0)
const строк = (файлы) => файлы.reduce((сумма, файл) => сумма + файл.content.split("\n").length, 0)

/* ─────────────────────────────── улика ──────────────────────────────────── */

test("улика: импорт тянет 29 функций, а от точки входа достижимы 2", async (t) => {
  const программа = await loadProgram(проба)
  const имена = await свои(проба)
  assert.deepEqual(имена, ["Сумма пробы"], "во входном файле одна функция")
  assert.ok(программа.functions.length >= 25, `после связывания функций ${программа.functions.length}`)

  const живые = reachableFunctions(программа, имена)
  assert.deepEqual([...живые].sort(), ["Сумма", "Сумма пробы"], "живых обязано быть ровно две")
  const мёртвые = программа.functions.filter((функция) => !живые.has(функция.name)).map((функция) => функция.name)
  for (const имя of ["Двоичный поиск", "Сортировать", "Сжать в пары"]) {
    assert.ok(мёртвые.includes(имя), `«${имя}» обязана быть мёртвой`)
  }
  t.diagnostic(`связано ${программа.functions.length}, живых ${живые.size}, мёртвых ${мёртвые.length}`)
})

test("числа улики: сколько строк и байт занимало недостижимое в C и в JS", async (t) => {
  const программа = await loadProgram(проба)
  const урезанная = dropUnreachable(программа, await свои(проба))
  for (const [цель, печать] of [["c", emitC], ["js", emitJs]]) {
    const было = печать(программа, {}).files
    const стало = печать(урезанная, {}).files
    /* Рантайм и его шапка нужны ВСЕГДА и потому из счёта вынесены: считаем то,
       что печатается по программе, а не по языку. */
    const свой = (файлы) => файлы.filter((файл) => !файл.path.startsWith("flang_") && файл.path !== "Makefile")
    const дельтаБайт = байт(свой(было)) - байт(свой(стало))
    const дельтаСтрок = строк(свой(было)) - строк(свой(стало))
    assert.ok(дельтаБайт > 0, `${цель}: печать не уменьшилась ни на байт`)
    /* Мёртвого было больше половины модуля программы — на этом файле это не
       «немного лишнего», а основной объём вывода. */
    assert.ok(
      дельтаБайт * 2 > байт(свой(было)),
      `${цель}: мёртвого ${дельтаБайт} байт из ${байт(свой(было))} — меньше половины, улика не воспроизвелась`,
    )
    t.diagnostic(
      `${цель}: модуль программы ${строк(свой(было))} строк / ${байт(свой(было))} байт, ` +
        `мёртвого ${дельтаСтрок} строк / ${дельтаБайт} байт`,
    )
  }
})

