test("ведомость не урезается: проверка по-прежнему видит все функции", async () => {
  const { stdout } = await run("node", [cli, "check", проба, "--proof", "--json"], { maxBuffer: 64 * 1024 * 1024 })
  const отчёт = JSON.parse(stdout)
  const программа = await loadProgram(проба)
  assert.equal(отчёт.valid, true)
  assert.equal(отчёт.functions.length, программа.functions.length, "check стал проверять меньше функций")
  assert.equal(отчёт.proof.totals.functions, программа.functions.length, "ведомость похудела вместе с печатью")
  /* Сторож времени работы у «Числа до» — в ведомости он есть и обязан
     остаться: отбрасывание живёт в печати, а не в доказательстве. */
  assert.ok(отчёт.proof.totals.guardSites >= 1, "места сторожей пропали из ведомости")
})

test("урезанное собирается компилятором C и отвечает на свою точку входа", async (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет (ни cc, ни gcc в PATH и в FTS_TOOLCHAIN_PATH) — пропуск")
    return
  }
  const каталог = join(await песочница(), "c")
  const напечатано = await напечатать([проба, "--target", "c", "--out", каталог])
  const исходники = напечатано.files.map((файл) => файл.path).filter((путь) => путь.endsWith(".c"))
  execFileSync(cc, ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", ...исходники, "-o", "проба", "-lm"], {
    cwd: каталог,
    stdio: "pipe",
  })
  const ответ = execFileSync(join(каталог, "проба"), {
    input: `${JSON.stringify({ fn: "Сумма пробы", args: [[1, 2, 3, 40]] })}\n`,
    encoding: "utf8",
  })
  assert.deepEqual(JSON.parse(ответ.trim()), { ok: true, value: { n: "46" } })

  /* И то, ради чего всё: выброшенного в бинарнике нет. Прогонщик отвечает по
     имени, и раньше он отвечал на функции, которых автор не писал. */
  const мёртвый = JSON.parse(execFileSync(join(каталог, "проба"), {
    input: `${JSON.stringify({ fn: "Двоичный поиск", args: [[1, 2], 1] })}\n`,
    encoding: "utf8",
  }).trim())
  assert.equal(мёртвый.ok, false, "прогонщик всё ещё зовёт функцию, которой в программе нет")
  assert.equal(мёртвый.code, "FLANG_UNKNOWN_NAME")
})
