/**
 * Мёртвый код в печати: `использует «Списки»` тянул ВЕСЬ модуль.
 *
 * ── Улика, мерено до правки ─────────────────────────────────────────────────
 * `flang/examples/import-check.flang` — восемь строк, один вызов «Сумма» из
 * модуля «Списки» (698 строк). После связывания в программе 29 функций, из них
 * от точки входа достижимы 2, а 27 не вызываются никогда. В C это давало 1670
 * строк и 74 394 байта модуля программы, из которых 1535 строк и 68 110 байт
 * (91.6 %) — мёртвые; в JavaScript 1121 строку и 36 525 байт, из них 996 строк
 * и 32 148 байт (88.0 %) — мёртвые. По всему корпусу таких файлов десять, счёт
 * мёртвых там от 6 до 118 функций, а в байтах это 1 418 700 C и 455 311
 * JavaScript.
 *
 * Цена — не только место. Мёртвое компилируется, попадает в бинарник и в вызов
 * по имени: напечатанный прогонщик отвечал на `«Двоичный поиск»` у программы,
 * автор которой двоичного поиска не писал.
 *
 * ── Что здесь проверяется ───────────────────────────────────────────────────
 * 1. Улика числами: сколько связано, сколько живо, сколько выброшено.
 * 2. Печать через CLI совпадает с печатью УРЕЗАННОЙ программы байт в байт, и в
 *    ней нет ни одного мёртвого имени.
 * 3. Тождество: программе без импортов печать обязана остаться прежней — от
 *    этого зависят побайтовые сверки близнецов и точка раскрутки `bootstrap/`.
 * 4. Три ловушки, на которых наивный обход вызовов выбросил бы живое:
 *    функция-значение (`fnref`), обработчик и начальное состояние процесса
 *    (имя функции СТРОКОЙ, а не узлом вызова), постусловие и мера.
 * 5. Ведомость доказательства НЕ урезается: `check --proof` считает все 29
 *    функций, потому что отбрасывание живёт в печати, а не в проверке.
 * 6. Урезанное собирается: `cc -std=c99 -Werror -pedantic` и ответ на запрос.
 */
