test("flang emit печатает урезанную программу — и ни одного мёртвого имени", async () => {
  const программа = await loadProgram(проба)
  const урезанная = dropUnreachable(программа, await свои(проба))
  assert.notEqual(урезанная, программа, "отбрасывать было чему")

  for (const [цель, печать] of [["c", emitC], ["js", emitJs]]) {
    const напечатано = await напечатать([проба, "--target", цель])
    assert.deepEqual(напечатано.files, печать(урезанная, {}).files, `цель ${цель}: печать не совпала с урезанной`)
    const текст = напечатано.files.filter((файл) => !файл.path.startsWith("flang_")).map((файл) => файл.content).join("")
    for (const мёртвое of ["Двоичный поиск", "Сортировать", "Сжать в пары"]) {
      assert.ok(!текст.includes(мёртвое), `цель ${цель}: в печати осталось мёртвое имя «${мёртвое}»`)
    }
    assert.ok(текст.includes("Сумма пробы"), `цель ${цель}: точка входа пропала из печати`)
    assert.ok(текст.includes("«Сумма»"), `цель ${цель}: достижимая «Сумма» пропала из печати`)
  }
})

