test("ловушка: функция-значение — не вызов, а её выбрасывать нельзя", async () => {
  const вход = join(await песочница({
    "главный.flang": `модуль «Главный»
  использует «Высший порядок» из ${JSON.stringify(высшийПорядок)}

тотальная функция «Итог»
  принимает элементы: список числа
  возвращает число
  «Свернуть» от функция «Сложить» и 0 и элементы
`,
  }), "главный.flang")

  const программа = await loadProgram(вход)
  const живые = reachableFunctions(программа, await свои(вход))
  /* «Сложить» не вызывается ниоткуда: она стоит ЗНАЧЕНИЕМ. Выброси её — и
     понижение бросит FLANG_UNKNOWN_NAME на теге, то есть печать откажет. */
  assert.ok(живые.has("Сложить"), "функция-значение потерялась")
  assert.ok(живые.has("Свернуть"), "вызванная функция потерялась")
  assert.ok(!живые.has("Умножить"), "«Умножить» не нужна этой программе")

  const урезанная = dropUnreachable(программа, await свои(вход))
  assert.doesNotThrow(() => emitC(урезанная, {}), "печать урезанной отказала")
  assert.ok(урезанная.functions.length < программа.functions.length, "не выброшено ничего")
})

