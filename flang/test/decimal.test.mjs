test("программа корпуса проверяется всеми слоями без единой диагностики", () => {
  /* Сторож всего файла разом, и без него любая его часть могла бы отвалиться
     молча: остальные проверки здесь смотрят на ОТДЕЛЬНЫЕ функции и на значения,
     а типы всей программы не смотрит никто. Каталог `flang/examples` в отличие
     от `flang/stdlib` своего построчного теста не имеет. */
  assert.deepEqual(checkTypes(деньги).diagnostics, [])
  assert.deepEqual(checkTotality(деньги).diagnostics, [])
  for (const фн of деньги.functions) {
    if (фн.total !== true) continue
    assert.ok(checkTotality(деньги).total.has(фн.name), `«${фн.name}» помечена тотальной, но не доказана`)
  }
})

