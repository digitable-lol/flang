/** Одна и та же программа на трёх типах — сложение, умножение, остаток. */
const замерный = (тип) =>
  `модуль «З»\n\nтотальная функция «Сложить»\n  принимает ряд: список ${тип}\n  возвращает число\n`
  + "  свёртка ряд начиная с 0 как итог и ч\n    итог плюс ч\n\n"
  + `тотальная функция «Умножить»\n  принимает первое: ${тип}, второе: ${тип}\n  возвращает число\n`
  + "  первое умножить на второе\n\n"
  + `тотальная функция «Остаток»\n  принимает сумма: ${тип}\n  возвращает число\n`
  + "  сумма остаток от 100\n"

const напечатать = (emit, тип) => {
  const итог = emit(parse(замерный(тип)))
  const файлы = Array.isArray(итог) ? итог : (итог.files ?? [])
  return файлы.map((ф) => `=== ${ф.path} ===\n${ф.content}`).join("\n")
}

test("ЦЕНА: тела функций печатаются ПОБАЙТОВО так же, как у `число`", () => {
  /* Это и есть ответ на «во сколько раз медленнее»: НИ ВО СКОЛЬКО. Точное
     десятичное — уточнение, а не новый вид значения, поэтому во время работы
     его нет вовсе: масштаб и отрезок живут в типизаторе и до печати не
     доезжают. Мерить это секундомером было бы неправдой в обе стороны — на
     загруженной машине он врёт на десятки процентов, — а тождество текста
     врать не умеет.

     Расходиться разрешено РОВНО ДВУМ местам, и оба вне тела: комментарий
     `@param` (он называет тип словами автора) и таблица ГРАНИЦЫ ВХОДА, где
     значение, приехавшее снаружи, сверяется с объявленным типом. */
  for (const [имя, emit] of [["C", emitC], ["JS", emitJs]]) {
    const точный = напечатать(emit, "сотых").split("\n")
    const обычный = напечатать(emit, "число").split("\n")
    assert.equal(точный.length, обычный.length, `${имя}: число строк разошлось`)
    const разошлись = []
    for (let i = 0; i < точный.length; i += 1) if (точный[i] !== обычный[i]) разошлись.push(точный[i].trim())
    for (const строка of разошлись) {
      assert.ok(
        строка.startsWith("* @param") || строка.startsWith("{ kind:") || строка.startsWith("{ FL_TYPE_"),
        `${имя}: разошлась строка ТЕЛА, а не комментария и не границы входа: ${строка}`,
      )
    }
    assert.ok(разошлись.length > 0, `${имя}: не разошлось вообще ничего — проверка смотрит не туда`)
  }
})

test("ЦЕНА: печать точного десятичного отличается от `нат` ровно ИМЕНЕМ типа", () => {
  /* Самое сильное, что здесь можно сказать: `сотых` печатается ровно как `нат`
     — тот же отрезок [0, 2^53−1], та же отметка «целое», та же проверка на
     границе входа. Отличается ОДНА строка таблицы, и в ней отличается только
     имя. Значит стоимость точного десятичного во время работы равна стоимости
     `нат`, а она известна и равна нулю операций в теле. */
  const точный = напечатать(emitJs, "сотых").split("\n")
  const натуральный = напечатать(emitJs, "нат").split("\n")
  const разошлись = []
  for (let i = 0; i < точный.length; i += 1) if (точный[i] !== натуральный[i]) разошлись.push(i)
  assert.equal(разошлись.length, 2, "разошлось не две строки таблицы типов, а что-то ещё")
  for (const i of разошлись) {
    assert.equal(
      точный[i].replaceAll("сотых", "нат"),
      натуральный[i],
      "различие не сводится к имени типа — печать узнала о масштабе, а не должна была",
    )
  }
})

