/**
 * Точный десятичный тип: `сотых` и `тысячных`.
 *
 * ── Зачем он вообще ─────────────────────────────────────────────────────────
 *
 * Файл начинается с УЛИКИ, а не с проверки нового: первые тесты считают на
 * `число` то, что считает корпус, и требуют, чтобы ответ оказался НЕВЕРНЫМ.
 * Это не насмешка над IEEE-754, а условие честности: пока не показано, что
 * старое ломается, новое нечем оправдать. Улики три, и все три — вычисление:
 *
 *   `0.1 плюс 0.2` не равно 0.3;
 *   `(0.1 плюс 0.2) плюс 0.3` не равно `0.1 плюс (0.2 плюс 0.3)` — сложение
 *      НЕ АССОЦИАТИВНО, и одно выражение в разном порядке даёт два ответа;
 *   `«Скидка по цене»` из `flang/examples/monad/order-total.flang` на цене
 *      555.55 отдаёт 55.55499999999999 — ни 55.55, ни 55.56.
 *
 * ── Что проверяется дальше, и почему именно это ─────────────────────────────
 *
 *   ТОЧНОСТЬ    сложение сотен значений в РАЗНОМ ПОРЯДКЕ даёт ОДИН результат.
 *               На `число` тот же тест краснеет — это отдельная проверка рядом,
 *               иначе «точно» осталось бы словом.
 *   МАСШТАБ     копейки не складываются с тысячными и с безразмерным счётчиком.
 *   ПЕРЕПОЛНЕНИЕ ловится расширением типа, а не молчаливой порчей значения.
 *   ДОКАЗУЕМОСТЬ ядро берёт из подписи ТРИ факта — дно, потолок и целость, — и
 *               третий несёт вес: без него правило остатка ложно прямым числом.
 *   ИЗЪЯТИЕ     та же функция над `число` теряет слово «доказано».
 *
 * Запуск: node --test flang/test/decimal.test.mjs
 */
