test("ТРЕТИЙ ФАКТ НЕСЁТ ВЕС: без целости правило остатка ЛОЖНО прямым числом", () => {
  /* 5.5 остаток от 2 равно 1.5, а 1.5 больше единицы. Значит правило
     «остаток по 2 не больше 1» верно только для ЦЕЛОГО делимого, и целость
     обязана приезжать фактом, а не подразумеваться. Здесь это проверено на
     самом правиле, без обхода программы. */
  assert.equal(5.5 % 2, 1.5)
  assert.ok(1.5 > 1, "если это когда-нибудь станет ложью, правило можно ослабить")

  const выражение = {
    kind: "binary",
    op: "mod",
    left: { kind: "var", name: "х" },
    right: { kind: "literal", value: 2 },
  }
  const снизу = [{ kind: "var", name: "х" }]
  assert.equal(ограничено(выражение, 1, [], снизу, []), false, "без факта целости правило прошло — это ложь")
  assert.equal(ограничено(выражение, 1, [], снизу, снизу), true, "с фактом целости правило обязано пройти")
})

