/** Сумма списка в заданном порядке, посчитанная самим языком. */
function сложитьЯзыком(значения, тип) {
  const программа = parse(
    "модуль «С»\n\nтотальная функция «Сложить»\n"
      + `  принимает ряд: список ${тип}\n`
      + "  возвращает число\n"
      + "  свёртка ряд начиная с 0 как итог и ч\n    итог плюс ч\n",
  )
  return evaluate(программа, "Сложить", { ряд: значения })
}

/** Тот же список в 200 разных порядках — детерминированной перетасовкой. */
function порядки(значения, сколько) {
  const списки = []
  for (let seed = 1; seed <= сколько; seed += 1) {
    const копия = [...значения]
    /* Перетасовка Фишера—Йейтса на линейном конгруэнтном генераторе: порядок
       нужен РАЗНЫЙ и ВОСПРОИЗВОДИМЫЙ, а `Math.random` не даёт второго. */
    let x = seed * 2654435761 % 2147483647
    for (let i = копия.length - 1; i > 0; i -= 1) {
      x = (x * 48271) % 2147483647
      const j = x % (i + 1)
      const t = копия[i]
      копия[i] = копия[j]
      копия[j] = t
    }
    списки.push(копия)
  }
  return списки
}

test("ТОЧНОСТЬ: 300 копеечных значений в 200 порядках дают ОДИН результат", () => {
  /* Значения нарочно «денежные» — цены с копейками, записанные в копейках.
     Тот же список в дробном виде даст в IEEE разные суммы (проверка ниже). */
  const копейки = []
  for (let i = 1; i <= 300; i += 1) копейки.push(i * 7 % 1000 + 1)
  const ожидание = копейки.reduce((a, b) => a + b, 0)

  const ответы = new Set()
  for (const порядок of порядки(копейки, 200)) ответы.add(сложитьЯзыком(порядок, "сотых"))
  assert.equal(ответы.size, 1, `порядок изменил сумму: ${[...ответы].join(", ")}`)
  assert.equal([...ответы][0], ожидание)
})

test("ТА ЖЕ ПРОВЕРКА НА `число` КРАСНЕЕТ: порядок даёт РАЗНЫЕ суммы", () => {
  /* Без этого теста «точно» осталось бы словом: проверка, которая зелена на
     обоих типах, ничего про точность не утверждает. */
  const доли = []
  for (let i = 1; i <= 300; i += 1) доли.push((i * 7 % 1000 + 1) / 100)

  const ответы = new Set()
  for (const порядок of порядки(доли, 200)) ответы.add(сложитьЯзыком(порядок, "число"))
  assert.ok(ответы.size > 1, "IEEE вдруг стало ассоциативным — проверьте перетасовку")
})

test("ТОЧНОСТЬ: десятая доля плюс две десятых равны трём десятым — в сотых долях", () => {
  /* 0.1 = 10 сотых, 0.2 = 20 сотых, 0.3 = 30 сотых. Равенство ТОЧНОЕ, и оно
     остаётся точным при любой расстановке скобок. */
  const программа = parse(
    "модуль «Т»\n\nтотальная функция «Слева»\n  принимает цена: сотых\n  возвращает число\n"
      + "  ((10 плюс 20) плюс 30) плюс цена\n\n"
      + "тотальная функция «Справа»\n  принимает цена: сотых\n  возвращает число\n"
      + "  (10 плюс (20 плюс 30)) плюс цена\n",
  )
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.equal(evaluate(программа, "Слева", { цена: 0 }), 60)
  assert.equal(evaluate(программа, "Справа", { цена: 0 }), 60)
  assert.equal(
    evaluate(программа, "Слева", { цена: 0 }),
    evaluate(программа, "Справа", { цена: 0 }),
    "скобки изменили ответ — точности нет",
  )
})

test("ТОЧНОСТЬ: деление с остатком не теряет ни одной копейки", () => {
  /* Утверждение: доля, умноженная на число частей, плюс неделимый остаток
     снова даёт исходную сумму. Считается НАСТОЯЩИМИ функциями библиотеки, а не
     повторением их на JavaScript. */
  let проверено = 0
  for (let сумма = 0; сумма <= 500; сумма += 1) {
    for (const частей of [1, 2, 3, 7, 11, 100]) {
      const доля = evaluate(деньги, "Доля при дележе", { сумма, частей })
      const остаток = evaluate(деньги, "Копеек в неделимом остатке", { сумма, частей })
      assert.equal(доля * частей + остаток, сумма, `дележ ${сумма} на ${частей} потерял копейки`)
      проверено += 1
    }
  }
  assert.equal(проверено, 501 * 6)
})

test("ТОЧНОСТЬ: печать и разбор суммы сходятся на всей сетке копеек", () => {
  /* «Сумма записью» обязана печатать ровно две цифры после точки, и число,
     прочитанное обратно, обязано совпасть с исходными копейками. */
  for (let сумма = 0; сумма <= 1000; сумма += 1) {
    const запись = evaluate(деньги, "Сумма записью", { сумма })
    assert.match(запись, /^\d+\.\d\d$/u, `сумма ${сумма} напечатана как «${запись}»`)
    assert.equal(Math.round(Number(запись) * 100), сумма)
  }
})

