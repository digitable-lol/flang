test("ЯДРО: сложение и умножение в список конечных целых НЕ ВХОДЯТ", () => {
  /* В IEEE-754 `1e308 плюс 1e308` — это +∞, а `+∞ остаток от 100` — NaN.
     Возьми ядро сумму в посылку конечности, и правило доказывало бы ложь ровно
     на переполнении. Проверяется отказом, а не обещанием. */
  const цель = (op) => ({
    kind: "binary",
    op: "lte",
    left: {
      kind: "binary",
      op: "mod",
      left: { kind: "binary", op, left: { kind: "var", name: "а" }, right: { kind: "var", name: "б" } },
      right: { kind: "literal", value: 100 },
    },
    right: { kind: "literal", value: 99 },
  })
  const сотых = { kind: "named", name: "сотых" }
  const объявлены = [{ name: "а", type: сотых }, { name: "б", type: сотых }]
  for (const op of ["add", "mul", "sub", "div"]) {
    assert.equal(свести(цель(op), [], объявлены).ok, false, `операция «${op}» принята за конечное целое`)
  }
})

