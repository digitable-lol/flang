test("УЛИКА: сложение на `число` НЕ АССОЦИАТИВНО — порядок меняет ответ", () => {
  /* Это и есть довод, по которому про плавающую точку доказывать нельзя:
     теорема о сумме обязана не зависеть от расстановки скобок, а здесь
     зависит. */
  const программа = parse(
    "модуль «У»\n\ntотальная функция «Слева»\n  принимает ничего: число\n  возвращает число\n"
      .replace("tотальная", "тотальная")
      + "  ((0.1 плюс 0.2) плюс 0.3) плюс ничего\n\n"
      + "тотальная функция «Справа»\n  принимает ничего: число\n  возвращает число\n"
      + "  (0.1 плюс (0.2 плюс 0.3)) плюс ничего\n",
  )
  const слева = evaluate(программа, "Слева", { ничего: 0 })
  const справа = evaluate(программа, "Справа", { ничего: 0 })
  assert.notEqual(слева, справа, "порядок перестал влиять — улика устарела, перепишите её")
  assert.equal(слева, 0.6000000000000001)
  assert.equal(справа, 0.6)
})

