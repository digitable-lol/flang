test("УЛИКА: на `число` десятая доля плюс две десятых не равны трём десятым", () => {
  const программа = parse(
    "модуль «У»\n\nтотальная функция «Три десятых»\n  принимает ничего: число\n  возвращает число\n"
      + "  (0.1 плюс 0.2) плюс ничего\n",
  )
  const ответ = evaluate(программа, "Три десятых", { ничего: 0 })
  assert.notEqual(ответ, 0.3, "если это когда-нибудь станет 0.3, весь файл теряет смысл")
  assert.equal(ответ, 0.30000000000000004)
})

test("УЛИКА: сложение на `число` НЕ АССОЦИАТИВНО — порядок меняет ответ", () => {
  /* Это и есть довод, по которому про плавающую точку доказывать нельзя:
     теорема о сумме обязана не зависеть от расстановки скобок, а здесь
     зависит. */
  const программа = parse(
    "модуль «У»\n\ntотальная функция «Слева»\n  принимает ничего: число\n  возвращает число\n"
      .replace("tотальная", "тотальная")
      + "  ((0.1 плюс 0.2) плюс 0.3) плюс ничего\n\n"
      + "тотальная функция «Справа»\n  принимает ничего: число\n  возвращает число\n"
      + "  (0.1 плюс (0.2 плюс 0.3)) плюс ничего\n",
  )
  const слева = evaluate(программа, "Слева", { ничего: 0 })
  const справа = evaluate(программа, "Справа", { ничего: 0 })
  assert.notEqual(слева, справа, "порядок перестал влиять — улика устарела, перепишите её")
  assert.equal(слева, 0.6000000000000001)
  assert.equal(справа, 0.6)
})

test("УЛИКА: настоящая «Скидка по цене» корпуса теряет копейку", () => {
  const исходник = readFileSync(`${корень}flang/examples/monad/order-total.flang`, "utf8")
  const программа = parse(исходник, "order-total.flang")
  const ответ = evaluate(программа, "Скидка по цене", { цена: 555.55 })
  /* Функция отдаёт «Возможно», значение лежит в поле. Копейки в нём нет:
     55.55499999999999 не округляется ни к 55.55, ни к 55.56 без потери. */
  const значение = ответ?.fields?.значение ?? ответ?.значение
  assert.equal(значение, 55.55499999999999)
  assert.notEqual(значение, 55.55)
})

