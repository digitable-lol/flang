/**
 * Сообщение обязано называть ЛЕКАРСТВО, а не только болезнь.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Замер авторства (`benchmarks/model-authoring` в ветке
 * `bench/model-authoring`) показал, на чём умирают программы, написанные по
 * выжимке синтаксиса: 78% отказов условия «б» — ОДНА причина (отступ под
 * `модуль`), а в условии «в» 27% — слово языка, поставленное именем, и 17% —
 * инфиксное действие, написанное префиксом. Во всех случаях отказ был верен, а
 * сообщение молчало о том, чем беду лечат. На словах `цепочка` и `в` на этом же
 * умерли и два решения из двадцати четырёх, написанных человеком.
 *
 * ЧЕМ ЗДЕСЬ СТЕРЕЖЁТСЯ КАЖДОЕ СООБЩЕНИЕ. Проверка не сверяет текст побуквенно —
 * так стерегут опечатку, а не смысл. Проверяется пара:
 *
 *   1) больная программа отказывает с ОЖИДАЕМЫМ кодом, и в тексте отказа стоит
 *      лекарство — то самое слово или та самая форма, которой беда лечится;
 *   2) программа, в которой сделано РОВНО ТО, что велит текст, разбирается.
 *
 * Второе — главное. Без него сообщение могло бы советовать несуществующее
 * лечение, и проверка бы этого не заметила. Изъятие любой из подсказок валит
 * первую половину, изъятие лечения — вторую.
 *
 * Коды диагностик здесь не меняются и не заводятся: имена в этом языке решает
 * владелец. Проверки написаны на те коды, что были.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { FlangError, parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

/** Первая диагностика отказавшего разбора. */
function отказ(исходник) {
  try {
    parse(исходник)
  } catch (ошибка) {
    assert.ok(ошибка instanceof FlangError, `ожидалась FlangError, получено ${ошибка}`)
    return ошибка.diagnostics[0]
  }
  return assert.fail(`ожидался отказ разбора для:\n${исходник}`)
}

/** Разбор обязан пройти: так проверяется, что названное лечение и правда лечит. */
function разбирается(исходник) {
  try {
    parse(исходник)
  } catch (ошибка) {
    assert.fail(`эта программа обязана разбираться, а отказ: ${ошибка.message}\n${исходник}`)
  }
}

/** Все куски лекарства обязаны стоять в тексте. */
function лечение(диагностика, код, куски) {
  assert.equal(диагностика.code, код)
  for (const кусок of куски) {
    assert.ok(
      диагностика.message.includes(кусок),
      `в сообщении нет лекарства «${кусок}»:\n${диагностика.message}`,
    )
  }
}

/* ── 1. отступ под «модуль» — 78% отказов условия «б» ─────────────────────── */

test("сдвинутое под «модуль» объявление: сообщение называет отступ и левый край", () => {
  const сдвинуто = "модуль «М»\n  тотальная функция «Двойка»\n    возвращает число\n    2\n"
  лечение(отказ(сдвинуто), "FLANG_PARSE", ["отступ", "у левого края", "заголовок модуля блока объявлений не открывает"])

  /* Лекарство: снять отступ. Больше в программе не меняется ничего. */
  разбирается(сдвинуто.replaceAll("\n  ", "\n").replaceAll("\n    ", "\n  "))
})

/* ── 2. слово языка, поставленное именем — 27% отказов условия «в» ─────────── */

for (const слово of ["состояние", "цепочка", "в"]) {
  test(`имя «${слово}» совпало со словом языка: сообщение называет и занятость, и ёлочки`, () => {
    const больная = `функция «Ф»\n  принимает ${слово}: число\n  возвращает число\n  ${слово} плюс 1\n`
    const беда = отказ(больная)
    лечение(беда, "FLANG_PARSE", ["занято языком", "в ёлочках", `«${слово}»`, "переименуйте"])

    /* Лекарство первое — ёлочки, ровно как советует текст. */
    разбирается(`функция «Ф»\n  принимает «${слово}»: число\n  возвращает число\n  «${слово}» плюс 1\n`)
    /* Лекарство второе — переименовать. */
    разбирается("функция «Ф»\n  принимает своё: число\n  возвращает число\n  своё плюс 1\n")
  })
}

test("лишнее слово в форме: то же сообщение велит его убрать", () => {
  const лишнее =
    "функция «Ф»\n  принимает элементы: список числа\n  возвращает число\n"
    + "  свёртка от элементы начиная с 0 как акк и эл → акк плюс эл\n"
  лечение(отказ(лишнее), "FLANG_PARSE", ["'от'", "попало в форму лишним", "уберите его"])

  /* Лекарство: убрать слово. */
  разбирается(лишнее.replace("свёртка от элементы", "свёртка элементы"))
})

test("слово языка у левого края: сообщение перечисляет объявления и напоминает про отступ", () => {
  лечение(отказ("модуль «М»\n\nсостояние «С»\n"), "FLANG_PARSE", [
    "этим словом объявление не начинается",
    "'функция'",
    "с отступом",
  ])
})

/* ── 3. инфиксное действие, написанное префиксом — 17% отказов условия «в» ── */

test("«умножить 3.14 на р»: сообщение называет инфиксный порядок", () => {
  const префиксом = "функция «Площадь»\n  принимает р: число\n  возвращает число\n  умножить 3.14 на (р умножить на р)\n"
  const беда = отказ(префиксом)
  лечение(беда, "FLANG_UNKNOWN_NAME", ["«умножить»", "МЕЖДУ", "«3.14 умножить на р»", "'принимает'"])

  /* Лекарство: тот же порядок, что показан в сообщении. */
  разбирается("функция «Площадь»\n  принимает р: число\n  возвращает число\n  3.14 умножить на (р умножить на р)\n")
})

test("проверка типов говорит о несвязанном имени тем же текстом, что разбор", () => {
  const итог = checkTypes(parse("функция «Ф»\n  возвращает число\n  Неизвестное\n"))
  лечение(итог.diagnostics[0], "FLANG_UNKNOWN_NAME", ["«Неизвестное»", "МЕЖДУ", "«3.14 умножить на р»"])
})

/* ── 4. литерал примера — 12% отказов условия «в» ─────────────────────────── */

test("имя в ёлочках как значение примера: сообщение требует слово 'вариант'", () => {
  const больной =
    "тип «Свет»\n  вариант «Красный»\n  вариант «Зелёный»\n\n"
    + "функция «Можно»\n  принимает свет: «Свет»\n  возвращает признак\n"
    + "  пример «Красный»\n    дано свет равно «Красный»\n    ожидается нет\n  нет\n"
  лечение(отказ(больной), "FLANG_PARSE", ["примеры не вычисляются", "'вариант'", "'запись'", "в ёлочках"])

  /* Лекарство: слово «вариант» впереди имени. */
  разбирается(больной.replace("дано свет равно «Красный»", "дано свет равно вариант «Красный»"))
})

/* ── 5. образец случая ────────────────────────────────────────────────────── */

test("условие в «случай»: сообщение перечисляет образцы и отсылает к 'если'", () => {
  const больной =
    "функция «Ф»\n  принимает н: число\n  возвращает признак\n  разбор н\n"
    + "    случай если н больше 0\n      то да\n    случай другое\n      то нет\n"
  лечение(отказ(больной), "FLANG_PARSE", ["ожидался образец", "'пусто'", "'если'", "имя со "])

  /* Лекарство: условие — через «если», а не образцом. */
  разбирается("функция «Ф»\n  принимает н: число\n  возвращает признак\n  если н больше 0 то да иначе нет\n")
  /* И число образцом БЫВАЕТ — сообщение не должно этого запрещать. */
  разбирается(
    "функция «Ф»\n  принимает н: число\n  возвращает признак\n  разбор н\n"
    + "    случай 0\n      то да\n    случай другое\n      то нет\n",
  )
})
