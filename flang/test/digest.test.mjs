const корень = fileURLToPath(new URL("../..", import.meta.url))
const прочесть = (путь) => readFileSync(`${корень}${путь}`, "utf8")
const адреса = (путь) => {
  const программа = parse(прочесть(путь), путь)
  return [...адресаОпределений(программа).функции.values()].sort().join(" ")
}
const адресаТекста = (текст) => {
  const программа = parse(текст, "проба.flang")
  return [...адресаОпределений(программа).функции.values()].sort().join(" ")
}

/* ─────────────────────── подделка 1: четыре поверхности ─────────────────── */

test("четыре поверхности одной программы дают один адрес", () => {
  const образец = адреса("/flang/examples/rosetta/factorial.flang")
  for (const путь of [
    "/flang/examples/rosetta/factorial-english.flang",
    "/flang/examples/surfaces/factorial.eo.flang",
    "/flang/examples/surfaces/factorial.zh.flang",
  ]) {
    assert.equal(адреса(путь), образец, `${путь}: адреса разошлись с русской поверхностью`)
  }
  /* Не пустая сверка: адресов пять, и они разные — иначе «совпали» ничего бы
     не значило. */
  assert.equal(new Set(образец.split(" ")).size, 5)
})

test("все пары «русская — английская» из Rosetta Code дают одни адреса", () => {
  const каталог = `${корень}/flang/examples/rosetta`
  let пар = 0
  for (const файл of readdirSync(каталог).sort()) {
    if (!файл.endsWith("-english.flang")) continue
    пар += 1
    const русский = файл.replace("-english.flang", ".flang")
    assert.equal(
      адреса(`/flang/examples/rosetta/${русский}`),
      адреса(`/flang/examples/rosetta/${файл}`),
      `${русский}: адреса разошлись с английским близнецом`,
    )
  }
  assert.equal(пар, 14, "пар в наборе стало другое число — сверьте таблицу")
})

