/**
 * АДРЕС ОПРЕДЕЛЕНИЯ — устойчивость, чувствительность и кеш.
 *
 * Здесь стоят подделки, без которых шаг 1 бесполезен, и каждая проверяет ровно
 * одно утверждение:
 *
 *   ПОВЕРХНОСТИ. Один алгоритм, набранный русскими и китайскими словами, — одна
 *   функция, и адрес обязан быть один. Иначе экосистема расколется на четыре
 *   несовместимые.
 *
 *   ТОЛЬКО ИМЕНА АВТОРА. Вычеркнуты ровно те слоты, что объявлены именами, и ни
 *   одного сверх. Проверяется механически: КАЖДЫЙ строковый слот дерева портится
 *   на один знак, и адрес обязан сдвинуться везде, кроме объявленных имён.
 *   Без этой проверки канонизатор, вычеркнувший заодно `kind` и `op`, выглядел
 *   бы исправным: деревья совпадали бы, а «плюс» и «минус» получили бы один
 *   адрес.
 *
 *   КЕШ НЕ ВЕРИТ НА СЛОВО. Подменённый вердикт не принимается: любое сомнение —
 *   промах, то есть вызов ядра.
 */
