test("переставлены объявления в файле — адреса те же", () => {
  /* Порядок объявлений — раскладка автора, а не содержимое. Две тотальные
     функции без связи между собой меняются местами целиком. */
  const первая = источник.slice(источник.indexOf("тотальная функция «Приписать в начало»"), источник.indexOf("тотальная функция «Произведение»"))
  const вторая = источник.slice(источник.indexOf("тотальная функция «Произведение»"), источник.indexOf("функция «Числа от и до»"))
  const переставлено = источник.replace(первая + вторая, вторая + первая)
  assert.notEqual(переставлено, источник, "перестановка не удалась — сверьте образец")
  assert.equal(адресаТекста(переставлено), адресаТекста(источник))
})

/* ───────────── подделка 4: вычеркнуты ТОЛЬКО имена автора ──────────────── */

/**
 * Перебрать каждый строковый слот дерева тем же путём, каким его видит
 * нормализация, и сказать, какой у него разряд.
 */
function слоты(программа) {
  const найдено = []
  const идти = (узел, путь) => {
    if (узел === null || typeof узел !== "object") return
    if (Array.isArray(узел)) {
      узел.forEach((э, н) => идти(э, `${путь}[${н}]`))
      return
    }
    for (const ключ of Object.keys(узел)) {
      if (ключ === "span") continue
      const значение = узел[ключ]
      if (typeof значение === "string") найдено.push({ путь, ключ, разряд: разрядСлота(путь, ключ, узел) })
      else идти(значение, `${путь}.${ключ}`)
    }
  }
  идти(программа, "")
  /* Только определения: адресуются функции, типы и теоремы, а `legacy` — узлы
     наследия FTS, которые в адрес не входят вовсе и входить не должны. */
  return найдено.filter(({ путь }) => /^\.(functions|types|theorems)\[/u.test(путь))
}

test("портится каждый строковый слот: незаметных слотов сверх имён автора нет", () => {
  const текст = прочесть("/flang/examples/rosetta/run-length-encoding.flang")
  const целое = parse(текст, "проба.flang")
  const было = [...адресаОпределений(целое).функции.values()].sort().join(" ")
  const список = слоты(целое)
  assert.ok(список.length > 100, `слотов всего ${список.length} — корпус подозрительно мал`)
  let именных = 0
  let значимых = 0
  for (const { путь, ключ, разряд } of список) {
    const копия = JSON.parse(JSON.stringify(целое))
    const узел = путь === "" ? копия : путь
      .slice(1)
      .split(/\.|(?=\[)/u)
      .filter((ш) => ш !== "")
      .reduce((где, шаг) => (шаг.startsWith("[") ? где[Number(шаг.slice(1, -1))] : где[шаг]), копия)
    узел[ключ] = `${узел[ключ]}\u0301`
    const стало = [...адресаОпределений(копия).функции.values()].sort().join(" ")
    if (разряд === null) {
      /* ВОТ ГЛАВНОЕ УТВЕРЖДЕНИЕ ЭТОГО ФАЙЛА. Слот, которого нет в таблице имён,
         обязан быть значимым. Канонизатор, вычеркнувший заодно `kind` и `op`,
         покраснел бы ровно здесь — и только здесь: деревья у него совпадали. */
      assert.notEqual(стало, было, `${путь}.${ключ}: слот не именной, а адрес не сдвинулся`)
      значимых += 1
      continue
    }
    именных += 1
  }
  /* Числа печатаются нарочно: «вычеркнуты только имена автора» — утверждение о
     ДВУХ числах, и одно без другого ничего не значит. */
  assert.ok(значимых > 0 && именных > 0, `значимых ${значимых}, именных ${именных}`)
})

test("имена, выбранные автором и никем не помянутые, адрес не двигают", () => {
  /* Проверка с другой стороны: слот именной — значит правка ОДНОГО его места
     ничего не двигает, если на это имя никто не ссылается. Имя модуля, имя
     примера и имя утверждения ссылок не имеют по построению. */
  const путь = "/flang/examples/rosetta/fibonacci.flang"
  const целое = parse(прочесть(путь), путь)
  const было = [...адресаОпределений(целое).функции.values()].sort().join(" ")
  const порча = (правка) => {
    const копия = JSON.parse(JSON.stringify(целое))
    правка(копия)
    return [...адресаОпределений(копия).функции.values()].sort().join(" ")
  }
  assert.equal(порча((к) => { к.module = "Совсем другое" }), было, "имя модуля сдвинуло адрес")
  const сПримером = (целое.functions ?? []).find((ф) => (ф.examples ?? []).length > 0)
  assert.ok(сПримером !== undefined, "в образце нет ни одного примера")
  assert.equal(
    порча((к) => { к.functions.find((ф) => ф.name === сПримером.name).examples[0].name = "Другое имя примера" }),
    было,
    "имя примера сдвинуло адрес",
  )
})

test("таблица именных слотов знает про род узла, а не только про ключ", () => {
  /* Улика ошибки, которую поймал автор первой редакции: у узла вызова рядом с
     `name` стоят `args` и `op`, и вычеркнуть их заодно значило бы дать «плюсу»
     и «минусу» один адрес. */
  assert.equal(разрядСлота(".functions[0].body", "name", { kind: "call", name: "Ф" }), "функция")
  assert.equal(разрядСлота(".functions[0].body", "op", { kind: "binary", op: "add" }), null)
  assert.equal(разрядСлота(".functions[0].body", "kind", { kind: "call" }), null)
  assert.equal(разрядСлота(".functions[0].body", "name", { kind: "builtin", name: "добавить" }), null)
  /* Путевое правило не смеет доставать до узла с родом. */
  assert.equal(разрядСлота(".functions[0]", "name", { kind: "call", name: "Ф" }), "функция")
  assert.equal(разрядСлота(".functions[0]", "name", { name: "Ф" }), "стереть")
  void ИМЕННЫЕ_СЛОТЫ
})

/* ──────────────────── подделка 5: кешу не верят на слово ────────────────── */

const тройка = (что) => ({ определение: хеш(что), утверждение: хеш(["утв", что]), проверяющий: адресПроверяющего() })
const вердикт = () => ({ kernel: ЯДРО, verdict: СИЛА.proved, steps: 3, cases: [], refusals: [], says: "доказано" })

test("подменённый вердикт в кеше не принимается на веру", () => {
  const где = mkdtempSync(join(tmpdir(), "flang-kesh-"))
  const ключ = тройка("проба")
  assert.equal(положить(где, ключ, вердикт()), true)
  assert.deepEqual(взять(где, ключ), вердикт(), "своя же запись обязана находиться")

  const путь = join(где, "sha256", ...(() => {
    const [первый] = readdirSync(join(где, "sha256"))
    return [первый, readdirSync(join(где, "sha256", первый))[0]]
  })())

  const порча = (правка, зачем) => {
    const целое = JSON.parse(readFileSync(путь, "utf8"))
    writeFileSync(путь, JSON.stringify(правка(целое)), "utf8")
    assert.equal(взять(где, ключ), null, зачем)
    writeFileSync(путь, `${JSON.stringify(целое)}\n`, "utf8")
    assert.deepEqual(взять(где, ключ), вердикт(), "починенная запись обязана снова находиться")
  }

  порча((з) => ({ ...з, вердикт: { ...з.вердикт, verdict: СИЛА.refused } }), "подменённое слово вердикта принято на веру")
  порча((з) => ({ ...з, вердикт: { ...з.вердикт, steps: 999 } }), "подменённое число шагов принято на веру")
  порча((з) => ({ ...з, печать: хеш("не та печать") }), "запись с чужой печатью принята на веру")
  порча((з) => ({ ...з, ключ: { ...з.ключ, проверяющий: хеж() } }), "запись о другом проверяющем принята на веру")
  порча((з) => ({ ...з, схема: з.схема + 1 }), "запись другой схемы принята на веру")
})

test("правка ядра на один знак обесценивает весь кеш", () => {
  /* Адрес проверяющего считается от БАЙТОВ ядра, а не от номера версии: номер
     пишет человек и забывает поднять, байты не забывают. */
  const байты = readFileSync(new URL("../src/proofterm.mjs", import.meta.url))
  assert.ok(адресПроверяющего().length === 64)
  assert.notEqual(адресПроверяющего(), хеж(байты))
})

test("аксиом у ядра ноль, и кеш их не заводит", () => {
  assert.deepEqual(АКСИОМЫ, [])
  assert.ok(Object.isFrozen(АКСИОМЫ))
})

test("обязательства и адреса считаются об одной и той же программе", () => {
  const путь = "/flang/proof/examples/corpus-lists.flang"
  const программа = parse(прочесть(путь), путь)
  const и = адресаОпределений(программа)
  for (const о of obligations(программа).obligations ?? []) {
    if (о.kind !== "postcondition") continue
    assert.ok(и.функции.has(о.of), `у обязательства «${о.name}» нет адреса функции «${о.of}»`)
  }
})

/** Заведомо чужой хеш — им проверяется, что сверка не сравнивает пустое с пустым. */
function хеж(что = "чужое") {
  return хеш({ "«чужое»": String(что).slice(0, 32) })
}
