/**
 * Двунаправленные управляющие символы — общая проверка ВСЕХ целей печати.
 *
 * Правило одно на все бэкенды: двунаправленные управляющие символы Unicode
 * (U+061C, U+200E, U+200F, U+202A…U+202E, U+2066…U+2069) нельзя печатать в
 * целевой код сырыми. Места они не занимают, а раскладку текста меняют, поэтому
 * файл читается не так, как исполняется, — это «Trojan Source»
 * (CVE-2021-42574). Практических следствий четыре, и все четыре наблюдаемы на
 * этой машине:
 *
 *   • rustc 1.96 отвергает их и в литерале, и в КОММЕНТАРИИ:
 *     `text_direction_codepoint_in_literal` и `…_in_comment` — deny-by-default.
 *     До общего фильтра напечатанный крейт с таким именем не собирался вовсе;
 *   • elixirc 1.20.2 отказывается разбирать файл — «invalid bidirectional
 *     formatting character in comment/string», — и тоже в обоих местах;
 *   • gcc 13 под `-Werror` не собирает файл с непарным управляющим —
 *     `-Wbidi-chars=unpaired` включён по умолчанию и смотрит в том числе
 *     комментарии. Парную пару RLO…PDF он пропускает молча, поэтому его
 *     молчание ничего не доказывает;
 *   • javac собирает молча даже под `-Xlint:all -Werror`, CPython и node — тоже.
 *     Это не смягчающее обстоятельство, а отягчающее: ровно ради этого молчания
 *     атаку и придумали. Как ведёт себя Roslyn, здесь не проверено — тулчейна
 *     .NET на машине нет, — и полагаться на него всё равно нельзя.
 *
 * В программу эти символы попадают законно, без всякой атаки: таблица блоков
 * лексера (flang/self/lexer.flang) перечисляет весь блок U+2000…U+207F подряд,
 * и одиннадцать из двенадцати — как раз оттуда.
 *
 * ── Почему тест общий, а не по бэкенду ──────────────────────────────────────
 * Проверка была ровно одна, у бэкенда C (flang/test/emit-c.test.mjs), — и
 * поэтому три цели, добавленные позже (java, csharp, elixir), правило не
 * унаследовали: печатали сырыми, и никто не падал. Тест на бэкенд ловит только
 * те бэкенды, о которых кто-то вспомнил.
 *
 * Поэтому здесь перебор идёт ПО РЕЕСТРУ ЦЕЛЕЙ, а реестр — сам каталог
 * `flang/src/emit` (`emitTargets()` из bin/flang.mjs), тот же, по которому
 * работает `flang emit --target`. Девятая цель попадает под проверку тем, что
 * её модуль положили в каталог: списка целей, который можно забыть пополнить, в
 * этом файле нет. Файл подхватывается прогоном `npm test`
 * (`node --test flang/test/*.test.mjs`) — списка тестов, который тоже можно
 * забыть пополнить, там нет тоже.
 *
 * ── Два пути, по которым символ доезжает до файла ───────────────────────────
 * Их именно два, и первый когда-то закрыли, а второй остался открытым:
 *
 *   1. СТРОКОВЫЙ ЛИТЕРАЛ — значение из разбираемого текста. Его экранирует
 *      функция литерала каждого бэкенда;
 *   2. ИМЯ FTS В КОММЕНТАРИИ — «Функция flang «…»», шапка файла, подпись
 *      параметра, javadoc, `///`, @moduledoc. Комментарий не исполняется, и
 *      ровно поэтому он опасен: его читают первым, а проверить исполнением не
 *      могут. Здесь имя уезжает ещё и в литерал — прогонщик сравнивает с ним
 *      запрошенное имя функции, — так что оба пути проверяются одной программой.
 *
 * Поэтому программа ниже несёт управляющие ТРИЖДЫ: в имени модуля, в имени
 * функции и в строковом литерале, а проверяется ВЕСЬ напечатанный файл целиком,
 * а не найденный в нём литерал.
 *
 * ── Что именно проверяется ──────────────────────────────────────────────────
 *   1. НИ ОДНОГО СЫРОГО СИМВОЛА ни в одном напечатанном файле — ни в коде, ни в
 *      комментарии, ни в имени файла. Это то, из-за чего отказывают компиляторы
 *      и из-за чего врёт ревью.
 *   2. ЗНАЧЕНИЕ НЕ ИЗМЕНИЛОСЬ. Экранирование, потерявшее символ или подменившее
 *      кодовую точку, «чинит» предупреждение ценой чужой программы. Поэтому
 *      напечатанное разбирается обратно — в БАЙТЫ, а не в символы (у C
 *      экранирован каждый байт UTF-8 отдельно) — и сверяется: литерал с тем, что
 *      на этой же программе даёт интерпретатор, имя — с именем, по которому
 *      интерпретатор эту функцию вызывает.
 *
 * Формы экранирования у целей разные и общими быть не могут: `\NNN` побайтно в
 * C (в узкой строке C99 нет `\u`), `\uXXXX` в Java, C#, Go, Python и JS,
 * `\u{X…}` в Rust и Elixir. Общее — результат, и сверяется здесь именно он.
 *
 * Сам инструмент проверки — общий с тестом второго компилятора репозитория
 * (flang/test/bidi-guard.mjs): правило одно на оба, и способ его проверить
 * тоже обязан быть один. Свои у этого теста — программа и источник истины.
 *
 * Сам этот файл сырых двунаправленных не содержит: и в исходнике flang, и в
 * ожидаемом значении они заданы кодами, а не символами, — иначе тест
 * воспроизводил бы ровно ту беду, от которой стережёт.
 */
import assert from "node:assert/strict"
import { test } from "node:test"

import { emitTargets, loadEmitter } from "../bin/flang.mjs"
import { evaluate as interpret } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import {
  BIDI_CONTROLS,
  bodiesBetween,
  decodeEscapes,
  emittedFiles,
  rawControls,
  УПРАВЛЯЮЩИЕ,
} from "./bidi-guard.mjs"

/* Цели, существовавшие в день написания теста. Перебор идёт НЕ по этому списку,
   а по реестру: список держится только как нижняя граница. `emitTargets()`
   возвращает пустой список, если каталога нет (переехал, переименован), и без
   этой проверки перебор по пустому реестру выглядел бы успехом. */
const ИЗВЕСТНЫЕ = ["c", "csharp", "elixir", "go", "java", "js", "python", "rust"]

/* Якоря чисто из ASCII-букв: их не экранирует ни одна цель, поэтому тело
   между ними находится в напечатанном файле без знания языка.
   Закрывающий начинается с «Z» намеренно: это не шестнадцатеричная и не
   восьмеричная цифра, и к экранированию перед ним ничего не приклеится — иначе
   тест ловил бы собственный якорь вместо ошибки бэкенда. */
const НАЧАЛО = "bidiA"
const КОНЕЦ = "Zbidi"

/* Якоря для ИМЕНИ — отдельные, и в них есть пробел. Причина в том, что имя FTS
   попадает не только в текст, но и в идентификаторы целевого языка: «Метка
   nameA … Zname» превращается в MetkaNameAZname, и якорь без пробела нашёлся бы
   внутри идентификатора — с пустым телом между половинками, то есть тест ловил
   бы транслитерацию вместо экранирования. Пробел в идентификатор не проходит
   ни у одной цели. */
const ИМЯ_НАЧАЛО = "nameA "
const ИМЯ_КОНЕЦ = " Zname"

/* Имена собираются из кодов, а не пишутся символами: escape-последовательности
   flang разбирает в строковом литерале, а имя в «…» берёт дословно, поэтому
   иначе в этом файле оказались бы сырые управляющие. */
const ИМЯ_МОДУЛЯ = `Двунаправленные ${ИМЯ_НАЧАЛО}${УПРАВЛЯЮЩИЕ}${ИМЯ_КОНЕЦ}`
const ИМЯ_ФУНКЦИИ = `Метка ${ИМЯ_НАЧАЛО}${УПРАВЛЯЮЩИЕ}${ИМЯ_КОНЕЦ}`

const source = [
  `модуль «${ИМЯ_МОДУЛЯ}»`,
  "",
  `тотальная функция «${ИМЯ_ФУНКЦИИ}»`,
  "  возвращает строка",
  `  "${НАЧАЛО}${BIDI_CONTROLS.map((code) => `\\u${code.toString(16).padStart(4, "0")}`).join("")}${КОНЕЦ}"`,
].join("\n")

const program = parse(source)

/* Источник истины — интерпретатор, а не константа в тесте: сверять печать с
   переписанным от руки ожиданием значило бы проверять, что автор теста и автор
   бэкенда одинаково поняли исходник. Вызов идёт по ИМЕНИ с управляющими — тем
   самым, которое бэкенды печатают в комментарий и в литерал прогонщика: если
   интерпретатор функцию под ним находит, то и напечатанный код обязан находить
   её под ним же, а значит экранирование обязано давать ровно эти кодовые точки. */
const ожидаемое = interpret(program, ИМЯ_ФУНКЦИИ, [])

test("ни одна цель печати не выводит двунаправленные управляющие сырыми", async (t) => {
  /* Программа обязана содержать весь набор — и в литерале, и в имени: иначе
     цель, экранировавшая только часть, прошла бы проверку на остальных. */
  const вЛитерале = [...ожидаемое].filter((c) => BIDI_CONTROLS.includes(c.codePointAt(0)))
  assert.equal(вЛитерале.length, BIDI_CONTROLS.length, "в литерале обязаны быть все двенадцать управляющих")
  const вИмени = [...(program.functions[0]?.name ?? "")].filter((c) => BIDI_CONTROLS.includes(c.codePointAt(0)))
  assert.equal(вИмени.length, BIDI_CONTROLS.length, "в имени функции обязаны быть все двенадцать управляющих")
  assert.equal(program.module, ИМЯ_МОДУЛЯ, "имя модуля обязано дойти до печати дословно")

  const targets = await emitTargets()
  for (const known of ИЗВЕСТНЫЕ) {
    assert.ok(targets.includes(known), `реестр целей потерял «${known}»: перебирать нечего, проверка не состоялась`)
  }

  for (const target of targets) {
    await t.test(`цель «${target}»`, async () => {
      const backend = await loadEmitter(target, targets)
      const files = emittedFiles(backend.emit(program, {}), target)

      const raw = rawControls(files)
      assert.deepEqual(
        raw,
        [],
        `цель «${target}» печатает двунаправленные управляющие сырыми:\n  ${raw.join("\n  ")}\n` +
          "Экранировать их обязан и строковый литерал бэкенда, и весь остальной вывод — имя FTS уезжает ещё и в " +
          "комментарии (шапка файла, документация функции). Форма своя у каждого языка " +
          "(\\NNN побайтно в C, \\uXXXX в Java, C#, Go, Python и JS, \\u{X…} в Rust и Elixir); " +
          "общий фильтр на выходе emit() — escapeBidiInFiles из flang/src/bidi.mjs",
      )

      /* Отсутствие сырых символов само по себе ещё не победа: цель, потерявшая
         их при печати, тоже «чиста». Поэтому и литерал, и имя ищутся по якорям
         и разбираются обратно. */
      const литералы = bodiesBetween(files, НАЧАЛО, КОНЕЦ)
      assert.ok(литералы.length > 0, `цель «${target}» не напечатала литерал вовсе: якорь «${НАЧАЛО}» не найден`)
      for (const { path, body } of литералы) {
        assert.equal(
          `${НАЧАЛО}${decodeEscapes(body)}${КОНЕЦ}`,
          ожидаемое,
          `цель «${target}», файл ${path}: экранирование изменило значение литерала — ` +
            "байты и кодовые точки обязаны остаться теми же, что у интерпретатора",
        )
      }

      const имена = bodiesBetween(files, ИМЯ_НАЧАЛО, ИМЯ_КОНЕЦ)
      assert.ok(
        имена.length > 0,
        `цель «${target}» нигде не напечатала имя FTS: якорь «${ИМЯ_НАЧАЛО}» не найден. Имя стоит и в шапке ` +
          "файла, и в документации функции — если его не стало, потерялась не проверка, а документация",
      )
      for (const { path, body } of имена) {
        assert.equal(
          decodeEscapes(body),
          УПРАВЛЯЮЩИЕ,
          `цель «${target}», файл ${path}: имя FTS напечатано не дословно — экранирование обязано ` +
            "восстанавливаться в те же кодовые точки, иначе комментарий врёт о том, как функция называется",
        )
      }
    })
  }
})
