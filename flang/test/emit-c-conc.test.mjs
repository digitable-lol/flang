/**
 * Б1 + вторая стена замера: во что порождённый процесс обходится по памяти.
 *
 * Прибор — адресное пространство (`ulimit -v`), потому что мерить надо именно
 * его: замер планировщика назвал 146 КиБ на работающий процесс, и это были
 * два куска арены по 64 КиБ, из которых трогалась пара страниц. Резерв не
 * стоил бы ничего, если бы его хватало; он и был стеной.
 *
 * Порог взят с запасом в оба конца: десять тысяч процессов обязаны уложиться в
 * 128 МиБ (при старом куске им нужно было бы 1,3 ГиБ), а сто тысяч — не
 * уложиться, иначе проверка ничего не измеряет и зеленела бы при любой цене.
 */
test("Б1: порождённый процесс стоит килобайты адресного пространства, а не сто двадцать восемь", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  const собрано = собрать("рой", parse(плодовитый(), "рой.flang"))
  const подПределом = (пробегов, кибибайт) => {
    const запрос = JSON.stringify({
      run: "рой", seed: "1", turns: String(пробегов), journal: "0", processes: "1000000",
    })
    const прогон = spawnSync("/bin/sh", ["-c", `ulimit -v ${кибибайт} || exit 97; exec "$0"`, собрано.cli],
      { input: `${запрос}\n`, encoding: "utf8", timeout: 300_000, maxBuffer: 1 << 28 })
    if (прогон.status === 97) return "предел не ставится"
    const ответ = JSON.parse((прогон.stdout ?? "").split("\n")[0] || "{}")
    return ответ.ok === true ? "прошёл" : (ответ.code ?? "не ответил")
  }

  const десять = подПределом(20_000, 131_072)
  if (десять === "предел не ставится") {
    t.diagnostic("ulimit -v в этой оболочке не ставится — проверка пропущена")
    return
  }
  assert.equal(
    десять, "прошёл",
    "десять тысяч порождённых процессов обязаны уложиться в 128 МиБ: при куске в 64 КиБ им нужно 1,3 ГиБ",
  )
  /* Зубы: тот же предел и вдесятеро больше процессов — обязан не пройти.
     Без этой половины проверка зеленела бы и при куче в мегабайт на процесс. */
  assert.equal(
    подПределом(200_000, 131_072), "FLANG_MEMORY",
    "сто тысяч процессов в те же 128 МиБ влезать не должны — иначе прибор ничего не меряет",
  )
  t.diagnostic("10 000 порождённых процессов держатся под 128 МиБ адресного пространства, 100 000 — нет")
})

