/**
 * Стенд ПАР: каждая пара — свой пинг-понг, пар сколько угодно.
 *
 * Заведён ради одного: ящика, в который пишет ОДИН поток, а читает ДРУГОЙ. У
 * стенда «себе» такого нет вовсе (процесс пишет сам себе, ящик трогает только
 * его поток), у пинг-понга из двух процессов есть, но разъезжаться по ядрам там
 * нечему. Здесь и то и другое сразу, и потому именно этот стенд ловит снятый
 * замок процесса.
 */
function стендПары(пар) {
  const части = [`модуль «Пары»

объект «Сч»
  «всего»: число
  «кому»: строка

тип «Кмд»
  вариант «тик» содержит «шаг»: число

объект «Отклик»
  «состояние»: «Сч»
  «действия»: список «Действие»

тотальная функция «отбить»
  принимает текущее: «Сч», сообщение: «Кмд»
  возвращает «Отклик»
  разбор сообщение
    случай вариант «тик» с «шаг» как ш
      пусть новое равно (запись «Сч» с «всего» равным (текущее.«всего» плюс 1) и «кому» равным текущее.«кому»)
      пусть письмо равно (вариант «отправить» с «кому» равным текущее.«кому» и «что» равным (вариант «тик» с «шаг» равным ш))
      запись «Отклик» с «состояние» равным новое и «действия» равным [письмо]
`]
  const прогон = ["прогон «стенд»", "  семя 1"]
  for (let п = 1; п <= пар; п += 1) {
    const а = `А${п}`
    const б = `Б${п}`
    части.push(`тотальная функция «н${а}»\n  возвращает «Сч»\n  запись «Сч» с «всего» равным 0 и «кому» равным "${б}"\n`)
    части.push(`тотальная функция «н${б}»\n  возвращает «Сч»\n  запись «Сч» с «всего» равным 0 и «кому» равным "${а}"\n`)
    части.push(`процесс «${а}»\n  состояние «Сч»\n  начинает с «н${а}»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
    части.push(`процесс «${б}»\n  состояние «Сч»\n  начинает с «н${б}»\n  принимает «Кмд»\n  обрабатывает «отбить»\n`)
    прогон.push(`  дано «${а}» принимает (вариант «тик» с «шаг» равным 1)`)
  }
  прогон.push(`  ожидается «А1» равен (запись «Сч» с «всего» равным 0 и «кому» равным "Б1")`)
  части.push(прогон.join("\n") + "\n")
  return разобратьТекст(части.join("\n"), "пары.flang")
}

test("Р6: письмо, пересекающее границу между потоками, доходит целым и ровно один раз", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  /* Улика на месте: без этой проверки замок процесса в рабочем режиме не держал
     бы НИЧЕГО из проверяемого набором. Изъятие показало прямо: сняв взятие и
     снятие замка, стенды «себе», `race` и `server` остаются зелёными все пять,
     а этот стенд роняет прогонщик насмерть — пустой вывод вместо JSON.

     Почему так: у «себе» ящик процесса трогает только его собственный поток, у
     `race` и `server` пробегов десяток. Пара же на КАЖДОМ пробеге переносит
     сообщение из кучи одного процесса в кучу другого, и процессы эти в рабочем
     режиме почти всегда на разных ядрах. */
  const ПАР = 128
  const собрано = собрать("пары-128", стендПары(ПАР))
  let проверено = 0
  for (const потоков of [2, 4, 8, 16]) {
    for (const предел of [5000, 50000]) {
      const [ответ] = спросить(собрано, [{
        run: "стенд", seed: "1", turns: String(предел), journal: "0", workers: String(потоков),
      }])
      assert.ok(ответ.ok, `${потоков} потоков, предел ${предел}: отказ ${JSON.stringify(ответ).slice(0, 200)}`)
      assert.equal(Number(ответ["пробегов"]), предел, `${потоков} потоков, предел ${предел}: пробегов не столько`)
      /* Каждый пробег прибавляет единицу ровно одному счётчику. Сумма меньше —
         письмо потерялось; больше — доставилось дважды; не число — ящик порван
         посередине. Все три — то, от чего стоит замок. */
      const сумма = ответ["состояния"]
        .reduce((с, [, значение]) => с + раскодировать(значение)["всего"], 0)
      assert.equal(сумма, предел,
        `${потоков} потоков, предел ${предел}: счётчики дают ${сумма} — письма потерялись или задвоились`)
      /* Жив обязан остаться каждый: падение процесса здесь означало бы, что
         доставка сорвалась, а сорваться ей нечем — ящики не объявлены
         ограниченными, памяти вдоволь. */
      assert.equal(ответ["живые"].length, ПАР * 2,
        `${потоков} потоков, предел ${предел}: живых ${ответ["живые"].length} из ${ПАР * 2}`)
      проверено += 1
    }
  }
  t.diagnostic(`${ПАР} пар, ${проверено} сочетаний «потоков × предел»: письма целы и счётчики сходятся`)
})
