/**
 * Пинг-понг: два процесса перебрасывают друг другу один «тик», в ящике всё
 * время не больше одного сообщения, число пробегов задаёт запрос.
 *
 * Форма та же, что у `flang/conc/bench.mjs` («Сколько живёт процесс»), и это
 * важно: числа из карты и числа отсюда обязаны говорить об одной программе.
 * Весь рост арены здесь — рост ОТ ПРОБЕГОВ, потому что входное сообщение ровно
 * одно, а состояние — счётчик постоянного размера.
 */
function пингПонг() {
  const шаг = (имя, кому) => [
    `тотальная функция «${имя}»`,
    "  принимает счёт: «Счёт», сообщение: «Тик»", "  возвращает «Отклик»",
    "  пусть новое равно (запись «Счёт» с «всего» равным (счёт.«всего» плюс 1))",
    `  пусть письмо равно (вариант «отправить» с «кому» равным "${кому}" и «что» равным (вариант «тик»))`,
    "  запись «Отклик» с «состояние» равным новое и «действия» равным [письмо]", "",
  ]
  return [
    "модуль «Мерка»", "",
    "объект «Счёт»", "  «всего»: число", "",
    "тип «Тик»", "  вариант «тик»", "",
    "объект «Отклик»", "  «состояние»: «Счёт»", "  «действия»: список «Действие»", "",
    "процесс «Пинг»", "  состояние «Счёт»", "  начинает с «нуль»",
    "  принимает «Тик»", "  обрабатывает «шаг к понгу»", "",
    "процесс «Понг»", "  состояние «Счёт»", "  начинает с «нуль»",
    "  принимает «Тик»", "  обрабатывает «шаг к пингу»", "",
    "тотальная функция «нуль»", "  возвращает «Счёт»",
    "  запись «Счёт» с «всего» равным 0", "",
    ...шаг("шаг к понгу", "Понг"),
    ...шаг("шаг к пингу", "Пинг"),
    "прогон «мерка»", "  семя 1",
    "  дано «Пинг» принимает (вариант «тик»)",
    "  ожидается «Пинг» равен (запись «Счёт» с «всего» равным 0)", "",
  ].join("\n")
}

/**
 * Шаг А2: своя куча у процесса, и потому процесс живёт неограниченно.
 *
 * ── Что здесь проверяется и почему именно так ───────────────────────────────
 * До А2 арена только росла: `valgrind` называл 510,6 байта на пробег с журналом
 * и 338,8 без него, и ни один из них не возвращался. Утверждение А2 — не «стало
 * меньше», а «наклон РАВЕН нулю»: сколько бы пробегов ни было, байт выдано
 * malloc столько же. Поэтому здесь сравнение на РАВЕНСТВО, а не на «меньше чем»:
 * порог пропустил бы медленную течь, а равенство — нет.
 *
 * Прибор — счётчик malloc из `valgrind`, а не память процесса: он не зависит ни
 * от нагрузки, ни от машины, ни от компилятора, поэтому равенство здесь можно
 * требовать буквально, до байта.
 *
 * ── Зубы ────────────────────────────────────────────────────────────────────
 * Проверка, которая молчит на настоящей поломке, хуже отсутствующей: за сутки в
 * этом репозитории таких нашлось две. Поэтому тот же прибор на той же программе
 * обязан УВИДЕТЬ рост там, где он есть, — с журналом. Журнал пишет запись на
 * каждый пробег, он наблюдение, и расти ему положено (шаг А1); если и с ним
 * счётчик покажет равенство, значит сломался прибор, а не программа кончилась.
 */
test("шаг А2: без журнала наклон «байт на пробег» равен нулю, с журналом — нет", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  const проба = spawnSync("valgrind", ["--version"], { encoding: "utf8" })
  if (проба.status !== 0) {
    t.diagnostic("valgrind в системе нет — точного прибора нет, проверка пропущена")
    return
  }
  const собрано = собрать("пинг-понг", parse(пингПонг(), "жизнь.flang"))
  const байт = (пробегов, журнал) => {
    const запрос = JSON.stringify({ run: "мерка", seed: "1", turns: String(пробегов), journal: журнал })
    const прогон = spawnSync("valgrind", ["--tool=memcheck", собрано.cli],
      { input: `${запрос}\n`, encoding: "utf8", maxBuffer: 1 << 28 })
    const строка = (прогон.stderr ?? "").split("\n").find((с) => с.includes("total heap usage"))
    const разбор = /([\d,]+) allocs, ([\d,]+) frees, ([\d,]+) bytes allocated/u.exec(строка ?? "")
    assert.ok(разбор !== null, `valgrind не назвал числа:\n${прогон.stderr}`)
    return {
      выделений: Number(разбор[1].replace(/,/gu, "")),
      освобождений: Number(разбор[2].replace(/,/gu, "")),
      байт: Number(разбор[3].replace(/,/gu, "")),
    }
  }

  const мало = байт(1000, "0")
  const много = байт(8000, "0")
  assert.equal(
    много.байт, мало.байт,
    `наклон обязан быть нулевым: ${мало.байт} байт на 1000 пробегов против ${много.байт} на 8000 — ` +
      "процесс снова течёт, и это ровно та стена, которую снял А2",
  )
  assert.equal(много.освобождений, много.выделений, "куча обязана вернуть системе всё, что купила")

  /* Зубы: тот же прибор, та же программа, отличие одно — журнал. */
  const сЖурналом = { мало: байт(1000, "1"), много: байт(8000, "1") }
  assert.ok(
    сЖурналом.много.байт > сЖурналом.мало.байт,
    "с журналом рост обязан быть виден — иначе прибор ослеп и первая половина проверки ничего не значит",
  )
  t.diagnostic(
    `без журнала ${мало.байт} = ${много.байт} байт (${много.выделений} выделений, ` +
      `${много.освобождений} освобождений); с журналом ${сЖурналом.мало.байт} → ${сЖурналом.много.байт}, ` +
      `то есть ${((сЖурналом.много.байт - сЖурналом.мало.байт) / 7000).toFixed(1)} байта на пробег наблюдения`,
  )
})

/**
 * То же утверждение вторым прибором и на настоящем плече: миллион пробегов под
 * пределом памяти. До А2 такой прогон просил около 470 МиБ и кончался
 * `FLANG_MEMORY`; после — держит постоянную кучу.
 *
 * Предел ставится втрое выше нужного, а не впритык: проверка обязана ловить
 * возвращение течи, а не разницу в libc между машинами. Зубы те же — с
 * журналом тот же прогон под тем же пределом обязан не пройти.
 */
test("шаг А2: миллион пробегов укладывается в 128 МиБ", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  const собрано = собрать("пинг-понг", parse(пингПонг(), "жизнь.flang"))
  const подПределом = (журнал) => {
    const запрос = JSON.stringify({ run: "мерка", seed: "1", turns: "1000000", journal: журнал })
    const прогон = spawnSync("/bin/sh", ["-c", 'ulimit -v 131072 || exit 97; exec "$0"', собрано.cli],
      { input: `${запрос}\n`, encoding: "utf8", maxBuffer: 1 << 28 })
    if (прогон.status === 97) return null
    const строка = (прогон.stdout ?? "").split("\n").find((с) => с.length > 0)
    assert.ok(строка !== undefined, `прогонщик не ответил ничего:\n${прогон.stderr}`)
    return JSON.parse(строка)
  }

  const рабочий = подПределом("0")
  if (рабочий === null) {
    t.diagnostic("оболочка не даёт поставить ulimit -v — проверка пропущена")
    return
  }
  assert.ok(рабочий.ok, `миллион пробегов не уложился в 128 МиБ: ${JSON.stringify(рабочий)}`)
  assert.equal(рабочий.пробегов, "1000000", "прогон обязан дойти до конца, а не остановиться раньше")

  /* Зубы: предел настоящий и на этой платформе работает — с журналом тот же
     миллион пробегов в него не влезает. Заодно это честная граница шага: течь
     перестало РАБОЧЕЕ состояние, а наблюдение как росло, так и растёт. */
  const сЖурналом = подПределом("1")
  assert.equal(
    сЖурналом.ok, false,
    "с журналом миллион пробегов обязан не влезть в 128 МиБ — иначе предел не работает и проверка слепа",
  )
  assert.equal(сЖурналом.code, "FLANG_MEMORY")
})

test("планировщик печатается байт в байт из файла рядом", () => {
  /* Рантайм лежит настоящими .c/.h в репозитории, а не строкой в бэкенде: так
     его проверяет компилятор прямо здесь. Печать обязана его не трогать — кроме
     шапки, которую бэкенд ставит перед файлом. */
  const исходник = readFileSync(new URL("../src/emit/c/flang_conc.c", import.meta.url), "utf8")
  const заголовок = readFileSync(new URL("../src/emit/c/flang_conc.h", import.meta.url), "utf8")
  const напечатано = emitC(разобрать("counter")).files
  assert.ok(напечатано.find((файл) => файл.path === "flang_conc.c").content.endsWith(исходник))
  assert.ok(напечатано.find((файл) => файл.path === "flang_conc.h").content.endsWith(заголовок))
})
