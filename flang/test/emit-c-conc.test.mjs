/**
 * Печать конкурентности flang → C: планировщик в рантайме (`flang/conc/SPEC.md`,
 * шаг 6).
 *
 * ── Чем эта сверка отличается от сверки с BEAM ──────────────────────────────
 *
 * У Elixir (`emit-elixir-conc.test.mjs`) сверять побайтово нечем: семени у BEAM
 * нет, чередование выбирает её планировщик, и всё, что там можно потребовать, —
 * «исход с машины лежит в множестве исходов эталона». Контракт пришлось из-за
 * этого переписать, и в разделе «Что проверяется и чем» это записано прямо.
 *
 * Здесь возвращается ИСХОДНОЕ требование пункта 2, и целиком: планировщик в C
 * принимает семя, и на одном и том же семени он обязан выдать ПОБАЙТОВО тот же
 * журнал доставок, что и эталон на JS. Не «исход из набора», не «похожее
 * чередование» — ту же строку. Сравнивается на каждом семени сетки:
 *
 *   время | процесс | исход пробега | код отказа | доставленное сообщение
 *
 * Сообщение в журнале — не украшение: без него совпали бы и два планировщика,
 * которые по-разному переставляют ящик, но одинаково выбирают процесс. Ровно
 * это и ловит «отложить» в `mailbox.flang`.
 *
 * Сверх журнала сверяется итог: исход программы, состояния всех процессов, кто
 * жив, какие были отказы, виртуальное время и число пробегов.
 *
 * ── Почему у сверки есть зубы ───────────────────────────────────────────────
 *
 * Побайтовое равенство слабо ровно в одном месте: оно сбывается и тогда, когда
 * обе стороны ничего не делают. Поэтому проверяется и обратное — что на сетке
 * семян чередований МНОГО (иначе сверка доказывала бы одно чередование из
 * восьмидесяти четырёх законных) и что подделанный журнал из совпадения
 * выпадает.
 *
 * ── Если компилятора C нет ──────────────────────────────────────────────────
 * Тесты, которым нужен `cc`, честно пропускаются через `missingToolchain`;
 * `FTS_REQUIRE_TOOLCHAINS=c` превращает пропуск в падение. Статические тесты
 * (что напечатано, что не напечатано, детерминированность) идут всегда.
 */
import assert from "node:assert/strict"
import { execFileSync, spawnSync } from "node:child_process"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { mkdtemp, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { after, test } from "node:test"
import { fileURLToPath } from "node:url"

import { runConcurrent } from "../src/conc.mjs"
import { parse } from "../src/parser.mjs"
import { emitC } from "../src/emit/c.mjs"
import { findExecutable } from "../../tools/ftsc/src/toolchain.mjs"
import { missingToolchain } from "../../tools/ftsc/test/toolchain-guard.mjs"

const cc = findExecutable("cc") ?? findExecutable("gcc")

/* Флаги — часть контракта бэкенда, а не строгость теста: ослабить их значило бы
   скрыть от себя, что печать испортилась. */
const CFLAGS = ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic"]

const примеры = fileURLToPath(new URL("../conc/examples/", import.meta.url))
const stdlib = fileURLToPath(new URL("../stdlib/", import.meta.url))

const ПРОГРАММЫ = ["counter", "race", "mailbox", "supervision", "escalate", "budget"]

/**
 * Сколько семян сверяется на каждый прогон.
 *
 * Двести, а не тысяча: сверка здесь ТОЧНАЯ, поэтому каждое семя приносит
 * утверждение, а не голос в множество. Двести семян на каждый из одиннадцати
 * прогонов дают больше двух тысяч побайтовых совпадений и укладываются в
 * секунды — тысяча дала бы то же самое вчетверо дольше. Насыщение множества
 * чередований проверяется отдельно и на той же сетке.
 */
const СЕМЯН = 200

const рабочий = await mkdtemp(join(tmpdir(), "flang-conc-c-"))
after(async () => {
  await rm(рабочий, { recursive: true, force: true })
})

function разобрать(имя) {
  return parse(readFileSync(`${примеры}${имя}.flang`, "utf8"), `${имя}.flang`)
}

/* ───────────────────── печать, сборка, запуск ───────────────────── */

let счёт = 0
const собранные = new Map()

/** Печатает программу в ПУСТОЙ каталог и собирает ровно то, что напечатано. */
function собрать(имя, программа) {
  const готовое = собранные.get(имя)
  if (готовое !== undefined) return готовое

  счёт += 1
  const каталог = join(рабочий, `p${счёт}`)
  mkdirSync(каталог, { recursive: true })
  const напечатано = emitC(программа)
  for (const файл of напечатано.files) writeFileSync(join(каталог, файл.path), файл.content, "utf8")

  const исходники = напечатано.files.filter((файл) => файл.path.endsWith(".c")).map((файл) => файл.path)
  try {
    execFileSync(cc, [...CFLAGS, ...исходники, "-o", "flang_cli", "-lm"], {
      cwd: каталог,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    })
  } catch (беда) {
    assert.fail(`${cc} не принял напечатанное (${CFLAGS.join(" ")}):\n${беда.stderr ?? беда.message}`)
  }

  const результат = { каталог, cli: join(каталог, "flang_cli"), файлы: напечатано.files }
  собранные.set(имя, результат)
  return результат
}

/** Один процесс на сколько угодно прогонов: сборка дорога, прогон дёшев. */
function спросить(собрано, запросы) {
  const вход = `${запросы.map((запрос) => JSON.stringify(запрос)).join("\n")}\n`
  const вывод = execFileSync(собрано.cli, {
    input: вход,
    encoding: "utf8",
    maxBuffer: 512 * 1024 * 1024,
  })
  const строки = вывод.split("\n").filter((строка) => строка.length > 0)
  assert.equal(строки.length, запросы.length, "прогонщик обязан ответить на каждый запрос ровно один раз")
  return строки.map((строка) => JSON.parse(строка))
}

/* ───────────────────── канон значений ─────────────────────
   Итог эталона — значения flang в записи интерпретатора, итог из C — тот же
   размеченный JSON, что у остальных бэкендов. Сравнивать их можно только приведя
   к одному виду, и вид этот обязан различать ровно то, что различает язык. */

function каноническое(значение) {
  if (значение === null || значение === undefined) return "ничто"
  if (typeof значение === "boolean") return значение ? "да" : "нет"
  if (typeof значение === "number") return `#${Object.is(значение, -0) ? "-0" : String(значение)}`
  if (typeof значение === "string") return `"${значение}"`
  if (Array.isArray(значение)) return `[${значение.map(каноническое).join(",")}]`
  if (typeof значение === "object") {
    if (typeof значение.variant === "string" && значение.fields !== undefined) {
      return `«${значение.variant}»${поля(значение.fields)}`
    }
    return поля(значение)
  }
  throw new Error(`нечего канонизировать: ${typeof значение}`)
}

function поля(запись) {
  return `{${Object.keys(запись).sort().map((имя) => `${имя}:${каноническое(запись[имя])}`).join(",")}}`
}

/** Значение из размеченного JSON прогонщика. */
function раскодировать(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(раскодировать)
  if (Object.hasOwn(узел, "r")) {
    const запись = {}
    for (const [имя, значение] of узел.r) запись[имя] = раскодировать(значение)
    return запись
  }
  if (Object.hasOwn(узел, "v")) {
    const поля = {}
    for (const [имя, значение] of узел.f ?? []) поля[имя] = раскодировать(значение)
    return { variant: узел.v, fields: поля }
  }
  throw new Error(`нечего раскодировать: ${JSON.stringify(узел)}`)
}

/* ───────────────────── журнал и итог одной строкой ───────────────────── */

function журналЭталона(итог) {
  return итог.журнал
    .map((з) => `${з.время}|${з.процесс}|${з.исход}|${з.код ?? ""}|${каноническое(з.сообщение)}`)
    .join("\n")
}

function журналC(ответ) {
  return ответ["журнал"]
    .map((з) =>
      `${Number(з["время"])}|${з["процесс"]}|${з["исход"]}|${з["код"]}|` +
      каноническое(раскодировать(з["сообщение"])))
    .join("\n")
}

function итогЭталона(итог) {
  const состояния = Object.entries(итог.состояния)
    .map(([имя, значение]) => `${имя}=${каноническое(значение)}`)
    .join("; ")
  const отказы = итог.отказы.map((о) => `${о.процесс}:${о.код}`).join(",")
  const решения = итог.решения.map((р) => `${р.процесс}/${р.надзор}/${р.стратегия}`).join(",")
  return `${итог.исход} | ${состояния} | живые: ${итог.живые.join(",")} | отказы: ${отказы} | ` +
    `решения: ${решения} | время ${итог.время} | пробегов ${итог.пробегов}`
}

function итогC(ответ) {
  const состояния = ответ["состояния"]
    .map(([имя, значение]) => `${имя}=${каноническое(раскодировать(значение))}`)
    .join("; ")
  const отказы = ответ["отказы"].map(([имя, код]) => `${имя}:${код}`).join(",")
  const решения = ответ["решения"].map(([п, н, с]) => `${п}/${н}/${с}`).join(",")
  return `${ответ["исход"]} | ${состояния} | живые: ${ответ["живые"].join(",")} | отказы: ${отказы} | ` +
    `решения: ${решения} | время ${Number(ответ["время"])} | пробегов ${Number(ответ["пробегов"])}`
}

/* ══════════ 1. главная сверка: то же семя — тот же журнал, побайтово ══════════ */

test("на одном семени напечатанный C даёт побайтово тот же журнал доставок, что эталон", async (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет (ни в PATH, ни в FTS_TOOLCHAIN_PATH) — пропуск")
    return
  }

  let прогонов = 0
  let сверок = 0
  const чередования = new Set()
  const начало = Date.now()

  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    const собрано = собрать(имя, программа)
    assert.ok(программа.runs?.length > 0, `${имя}: в программе нет ни одного прогона`)

    const запросы = []
    const план = []
    for (const прогон of программа.runs) {
      for (let семя = 0; семя < СЕМЯН; семя += 1) {
        запросы.push({ run: прогон.name, seed: String(семя) })
        план.push({ прогон, семя })
      }
    }
    const ответы = спросить(собрано, запросы)

    план.forEach(({ прогон, семя }, индекс) => {
      const ответ = ответы[индекс]
      assert.ok(ответ.ok, `${имя} / «${прогон.name}» / семя ${семя}: прогонщик ответил отказом ${JSON.stringify(ответ)}`)
      const итог = runConcurrent(программа, { ...прогон, seed: семя })
      const слева = журналЭталона(итог)
      const справа = журналC(ответ)
      assert.equal(
        справа,
        слева,
        `${имя} / «${прогон.name}» / семя ${семя}: журналы доставок разошлись.\n` +
          `  эталон:\n${слева}\n  C:\n${справа}`,
      )
      assert.equal(
        итогC(ответ),
        итогЭталона(итог),
        `${имя} / «${прогон.name}» / семя ${семя}: итоги разошлись при совпавшем журнале`,
      )
      чередования.add(`${имя}|${слева}`)
      сверок += 1
    })
    прогонов += программа.runs.length
  }

  t.diagnostic(
    `программ: ${ПРОГРАММЫ.length}, прогонов: ${прогонов}, семян на прогон: ${СЕМЯН}, ` +
      `побайтовых совпадений журнала: ${сверок}, различных чередований: ${чередования.size}, ` +
      `за ${Math.round((Date.now() - начало) / 1000)} с`,
  )
  assert.ok(сверок >= 2000, `сверок слишком мало: ${сверок}`)
  /* Побайтовое равенство сбывается и у двух планировщиков, которые ничего не
     делают. Здесь проверяется обратное: чередований на сетке МНОГО, значит
     совпало не «одно и то же всегда», а сотня разных порядков. */
  assert.ok(чередования.size >= 50, `различных чередований слишком мало: ${чередования.size}`)
})

/* ══════════ 2. у сверки есть зубы ══════════ */

test("сверка имеет зубы: подделанный журнал из совпадения выпадает", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  /* Утверждение «журналы совпали побайтово» ничего не значило бы, если бы под
     него подходило что угодно. Здесь проверяется, что не подходит: достаточно
     переставить два соседних пробега в журнале эталона — и равенство ломается.
     Перестановка выбрана нарочно: она не меняет ни длины журнала, ни множества
     доставленных сообщений, а меняет ровно ЧЕРЕДОВАНИЕ, ради которого всё и
     затевалось. */
  let проверено = 0
  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    const собрано = собрать(имя, программа)
    for (const прогон of программа.runs) {
      const [ответ] = спросить(собрано, [{ run: прогон.name, seed: "0" }])
      const строки = журналC(ответ).split("\n")
      if (строки.length < 2) continue
      const переставлено = [строки[1], строки[0], ...строки.slice(2)].join("\n")
      assert.notEqual(
        переставлено,
        журналЭталона(runConcurrent(программа, { ...прогон, seed: 0 })),
        `${имя} / «${прогон.name}»: журнал с переставленными пробегами остался равен эталонному — ` +
          "значит сверка не различает порядок, ради которого она и написана",
      )
      проверено += 1
    }
  }
  assert.ok(проверено >= 5, `прогонов с журналом длиннее одного пробега слишком мало: ${проверено}`)
})

test("семя решает всё: два разных семени дают разные журналы хотя бы где-то", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  /* Если бы планировщик в C игнорировал семя и всегда брал первый готовый
     процесс, главная сверка всё равно прошла бы на программах с одним готовым
     процессом. Здесь проверяется, что семя доехало: на `race.flang` разные
     семена дают разные чередования, и их не два. */
  const программа = разобрать("race")
  const собрано = собрать("race", программа)
  const прогон = программа.runs[0]
  const журналы = new Set()
  for (const ответ of спросить(собрано, Array.from({ length: 200 }, (_, семя) => ({ run: прогон.name, seed: String(семя) })))) {
    журналы.add(журналC(ответ))
  }
  assert.ok(журналы.size >= 6, `на 200 семенах C дал всего ${журналы.size} чередований — семя не работает`)
})

/* ══════════ 2½. единственное измеренное расхождение: единица запаса ══════════ */

test("запас витков считается в СВОИХ единицах, и расхождение одностороннее", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  /* Побайтовое совпадение журналов держится везде, кроме одного места, и место
     это надо не прятать, а прибить проверкой. Виток интерпретатора — итерация
     его машины; виток C (`fl_tick`) — вход в функцию, оборот хвостового цикла и
     отскок батута. Витков C всегда МЕНЬШЕ, значит эталон упирается в предел
     первым, и расхождение одностороннее: напечатанный код не объявит
     исчерпанным то, что эталон досчитал.

     Измерено двоичным поиском по входу при `с запасом 2000 витков`: эталон
     успевает на длине 140, C — на 1998. Здесь берётся точка между ними: эталон
     обязан упасть, C обязан досчитать. Если единицы когда-нибудь сойдутся,
     проверка покраснеет — и это правильно: расхождение придётся измерить
     заново, а не переписать про него абзац. */
  const источник = readFileSync(`${примеры}budget.flang`, "utf8")
    .replace(/дано «Разборщик» принимает \(вариант «короткий» с «длина» равным 5\)/u,
             "дано «Разборщик» принимает (вариант «короткий» с «длина» равным 400)")
    .replace(/\n {2}дано «Разборщик» принимает \(вариант «бесконечный»\)/u, "")
    .replace(/ожидается «Разборщик» равен \(запись «Разбор» с «сделано» равным 1\)/u,
             "ожидается «Разборщик» равен (запись «Разбор» с «сделано» равным 401)")
  const программа = parse(источник, "budget-400.flang")
  const собрано = собрать("budget-400", программа)
  const [ответ] = спросить(собрано, [{ run: программа.runs[0].name, seed: "1" }])
  const итог = runConcurrent(программа, { ...программа.runs[0], seed: 1 })

  assert.equal(итог.журнал[0].исход, "запас исчерпан", "эталон обязан упереться в запас первым")
  assert.equal(ответ["журнал"][0]["исход"], "обработано", "у C витки крупнее, и на этой длине он обязан досчитать")
  t.diagnostic("расхождение одностороннее и измерено: при запасе 2000 эталон успевает на длине 140, C — на 1998")
})

/* ══════════ 2¾. журнал необязателен, и его отсутствие видно ══════════ */

test("«journal»:«0» убирает журнал и не трогает ничего больше", (t) => {
  if (cc === null) {
    missingToolchain(t, "c", "компилятора C нет — пропуск")
    return
  }
  /*
   * Шаг А1. Журнал доставок — НАБЛЮДЕНИЕ, и в рабочем режиме оно не нужно, а
   * платится за него памятью на каждом пробеге: арена рантайма не возвращает
   * ничего, поэтому долгоживущий процесс с журналом течёт тем быстрее, чем
   * дольше живёт (`flang/conc/RESILIENCE.md`, «Сколько живёт процесс»).
   *
   * Проверяются обе половины, и вторая важнее первой.
   *
   *   1. Журнала нет: поля «журнал» в ответе НЕТ ВОВСЕ. Пустой список означал бы
   *      «пробегов не было» — и сверка из теста 1, сравнив пустоту с пустотой,
   *      промолчала бы вместо того, чтобы покраснеть. Здесь это проверено прямо.
   *   2. Всё остальное побитово то же самое: исход, состояния, живые, отказы,
   *      решения, время, пробегов. Признак, который меняет наблюдаемое, был бы
   *      не выключателем наблюдения, а вторым планировщиком.
   *
   * Гоняется по всем шести программам и по всем их прогонам: журнал трогает
   * каждый пробег, значит различие, если оно есть, вылезет где угодно, а не
   * только там, где падают процессы.
   */
  let пар = 0
  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    const собрано = собрать(имя, программа)
    for (const прогон of программа.runs) {
      for (const семя of ["0", "1", "17"]) {
        const [сЖурналом, безЖурнала] = спросить(собрано, [
          { run: прогон.name, seed: семя, journal: "1" },
          { run: прогон.name, seed: семя, journal: "0" },
        ])
        assert.ok(Array.isArray(сЖурналом["журнал"]), `${имя}/${прогон.name}/${семя}: журнал обязан быть по умолчанию`)
        assert.equal(
          Object.hasOwn(безЖурнала, "журнал"),
          false,
          `${имя}/${прогон.name}/${семя}: без журнала поля быть не должно, а не пустой список`,
        )
        assert.equal(
          итогC(безЖурнала),
          итогC(сЖурналом),
          `${имя}/${прогон.name}/${семя}: выключение журнала изменило наблюдаемое`,
        )
        пар += 1
      }
    }
  }

  /* И умолчание: запрос без поля «journal» обязан вести журнал, иначе сверка
     теста 1 однажды замолчала бы, ничего никому не сказав. */
  const программа = разобрать("counter")
  const [поУмолчанию] = спросить(собрать("counter", программа), [{ run: программа.runs[0].name, seed: "0" }])
  assert.ok(Array.isArray(поУмолчанию["журнал"]), "по умолчанию журнал ведётся")
  t.diagnostic(`пар «с журналом / без журнала»: ${пар}`)
})

