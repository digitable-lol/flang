/**
 * БИБЛИОТЕЧНАЯ ДВЕРЬ НАПЕЧАТАННОГО C: чужая программа, вызывающая по имени.
 *
 * ── Дыра, с которой это начиналось ─────────────────────────────────────────
 *
 * Граница входа у напечатанной программы стояла ровно в одном месте — в
 * прогонщике (`flang_cli.c` зовёт `fl_check_entry` до `FL_PROGRAM_CALL`).
 * Прогонщик — не единственный вход и не главный: главный сценарий этой печати
 * — встроить напечатанный flang в программу на другом языке, а такая программа
 * линкует `libМОДУЛЬ.a` и зовёт `МОДУЛЬ_call` напрямую. Улика, снятая
 * прогоном собранного C на `examples/measure/natural.flang`:
 *
 *   МОДУЛЬ_call("Факториал", −3)    → FL_OK, значение 1
 *   МОДУЛЬ_call("Факториал", 2.5)   → FL_OK, значение 3.75
 *   МОДУЛЬ_call("Факториал", 1e300) → FLANG_RECURSION_LIMIT на глубине 10001
 *
 * Третья строка — худшая, и она та же, что в шапке `emit-entry-types`:
 * доказательство завершения `тотальной` стоит НА ТИПЕ (у `нат` есть потолок
 * 2^53−1, ниже которого `н минус 1` точно меньше `н`), сторож убывания в такую
 * функцию не печатается ВОВСЕ, и значение вне типа выносит вместе с типом
 * доказательство. Тотальная функция отказывала кодом, отведённым обычной.
 *
 * ── Что здесь требуется ────────────────────────────────────────────────────
 *
 * У напечатанной программы ДВЕ двери, и обе обязаны быть на месте:
 *
 *   `МОДУЛЬ_call`  — вычислитель. Обязан отвечать значение в значение так же,
 *                    как `interpret` у свидетеля, а тот объявленных типов не
 *                    сверяет: сверяет их `flang run`.
 *   `МОДУЛЬ_enter` — дверь. Сверяет объявленные типы (`fl_check_entry`) и
 *                    только потом зовёт вычислитель; код и текст отказа —
 *                    дословно те же, что у `checkArguments` свидетеля.
 *
 * Проверяется это ПРОГОНОМ СОБРАННОГО C, а не разглядыванием напечатанного
 * текста: чужая программа компилируется, линкуется с библиотекой и зовёт обе
 * двери по одной и той же сетке значений. Пропадёт дверь — чужая программа не
 * соберётся; перестанет она сверять — ответы разойдутся со свидетелем;
 * начнёт сверять `_call` — разойдутся ответы вычислителя с `interpret`.
 * Совпадение текста не проверяется нигде, поэтому переписать комментарий в
 * эмиттере эта проверка не мешает, а вынуть границу — мешает.
 *
 * Половина изъятия, без которой вторая ничего не значит: в сетке есть годные
 * входы, и они обязаны считаться обеими дверями. Иначе зелень означала бы, что
 * дверь просто заперта.
 */
