const источник = fileURLToPath(new URL("../examples/measure/natural.flang", import.meta.url))
const программа = parse(readFileSync(источник, "utf8"), "examples/measure/natural.flang")

/**
 * Сетка. Значения тут только тех видов, которые чужая программа строит руками
 * (`fl_number`, `fl_text`, `fl_list`), а возвращают все четыре функции число —
 * иначе ответ пришлось бы печатать, а не сравнивать.
 *
 * `имя C` — как значения собираются в чужой программе; сами значения по именам
 * параметров идут свидетелю, и ожидание берётся у него, а не выписывается
 * руками.
 */
const СЕТКА = [
  { метка: "факториал-минус", имя: "Факториал", args: { "н": -3 }, строит: ["fl_number(-3.0)"] },
  { метка: "факториал-дробь", имя: "Факториал", args: { "н": 2.5 }, строит: ["fl_number(2.5)"] },
  { метка: "факториал-строка", имя: "Факториал", args: { "н": "строка" }, строит: ["stroka"] },
  { метка: "факториал-потолок", имя: "Факториал", args: { "н": 1e300 }, строит: ["fl_number(1e300)"] },
  { метка: "факториал-годный", имя: "Факториал", args: { "н": 5 }, строит: ["fl_number(5.0)"] },
  { метка: "пара-минус", имя: "Сумма пары", args: { "первое": 1, "второе": -1 }, строит: ["fl_number(1.0)", "fl_number(-1.0)"] },
  { метка: "пара-годная", имя: "Сумма пары", args: { "первое": 2, "второе": 3 }, строит: ["fl_number(2.0)", "fl_number(3.0)"] },
  { метка: "список-не-список", имя: "Сумма списка", args: { "элементы": 5 }, строит: ["fl_number(5.0)"] },
  { метка: "список-кривой", имя: "Сумма списка", args: { "элементы": [1, "строка", 3] }, строит: ["krivoy"] },
  { метка: "список-годный", имя: "Сумма списка", args: { "элементы": [1, 2, 3] }, строит: ["spisok"] },
  { метка: "место-минус", имя: "Сумма до места", args: { "элементы": [1, 2, 3], "место": -1 }, строит: ["spisok", "fl_number(-1.0)"] },
  { метка: "место-годное", имя: "Сумма до места", args: { "элементы": [1, 2, 3], "место": 3 }, строит: ["spisok", "fl_number(3.0)"] },
]

/** Ожидание ДВЕРИ: `checkArguments` — тот же свидетель, что у `flang run --args`. */
function ждётДверь(точка) {
  const итог = checkArguments(программа, точка.имя, точка.args)
  if (итог.ok) return { ok: true, значение: evaluate(программа, точка.имя, точка.args) }
  return { ok: false, code: итог.diagnostics[0].code, message: итог.diagnostics[0].message }
}

/**
 * Ожидание ВЫЧИСЛИТЕЛЯ: `interpret`, и он объявленных типов не сверяет.
 *
 * Отказы вычислителя сюда не берутся: у −3 и 2.5 вычислитель ОТВЕЧАЕТ, и
 * именно это отличает вычислитель от двери. Точки, где он отказывает (строка,
 * потолок), проверяются только тем, что дверь на них отказала РАНЬШЕ и ДРУГИМ
 * текстом — то есть до вычисления вообще не дошло.
 */
function ждётВычислитель(точка) {
  try {
    return { ok: true, значение: evaluate(программа, точка.имя, точка.args) }
  } catch {
    return null
  }
}

const ДВЕРЬ = СЕТКА.map(ждётДверь)
const ВЫЧИСЛИТЕЛЬ = СЕТКА.map(ждётВычислитель)

/* Свидетель обязан на чём-то отказать и на чём-то посчитать: сетка, где всё
   годно, доказала бы только то, что дверь открыта. */
assert.ok(ДВЕРЬ.some((ждём) => !ждём.ok), "сетка обязана содержать входы вне объявленных типов")
assert.ok(ДВЕРЬ.some((ждём) => ждём.ok), "сетка обязана содержать годные входы")

/** Чужая программа на C: строит значения руками и зовёт обе двери по имени. */
function чужаяПрограмма(префикс, заголовок) {
  const вызовы = СЕТКА.map((точка, индекс) => {
    const присвоения = точка.строит.map((как, место) => `  args[${место}] = ${как};`)
    return [
      ...присвоения,
      `  ask(${JSON.stringify(точка.метка)}, ${JSON.stringify(точка.имя)}, args, ${точка.строит.length}); /* ${индекс} */`,
    ].join("\n")
  })
  return `/*
 * Чужая программа: она НЕ напечатана flang, а линкована с напечатанной
 * библиотекой и зовёт её по имени — ровно так, как это делает всякий, кто
 * встраивает flang в программу на другом языке.
 */
#include <stdio.h>
#include <string.h>

#include "${заголовок}"

typedef fl_status (*door_fn)(fl_ctx *, const char *, const fl_value *, size_t, fl_value *, fl_error *);

static fl_arena arena;
static fl_ctx ctx;
static door_fn door;

static void ask(const char *label, const char *fn, const fl_value *args, size_t count) {
  fl_error error;
  fl_value result;
  fl_status status;
  error.code = NULL;
  error.message = NULL;
  result = fl_nothing();
  status = door(&ctx, fn, args, count, &result, &error);
  if (status == FL_OK) {
    if (result.tag == FL_NUMBER) {
      printf("%s\\tOK\\t%.17g\\n", label, result.as.number);
    } else {
      printf("%s\\tOK\\t?\\n", label);
    }
    return;
  }
  printf("%s\\tFAIL\\t%s\\t%s\\n", label, error.code == NULL ? "?" : error.code,
         error.message == NULL ? "?" : error.message);
}

int main(int argc, char **argv) {
  fl_error error;
  fl_value stroka;
  fl_value spisok;
  fl_value krivoy;
  fl_value *items;
  fl_value args[2];

  fl_arena_init(&arena);
  fl_ctx_init(&ctx, &arena);
  error.code = NULL;
  error.message = NULL;

  door = ${префикс}_enter;
  if (argc > 1 && strcmp(argv[1], "call") == 0) door = ${префикс}_call;

  if (fl_text(&ctx, "строка", strlen("строка"), &stroka, &error) != FL_OK) return 2;
  if (fl_list_alloc(&ctx, 3, &items, &error) != FL_OK) return 2;
  items[0] = fl_number(1.0);
  items[1] = fl_number(2.0);
  items[2] = fl_number(3.0);
  spisok = fl_list(items, 3);
  if (fl_list_alloc(&ctx, 3, &items, &error) != FL_OK) return 2;
  items[0] = fl_number(1.0);
  items[1] = stroka;
  items[2] = fl_number(3.0);
  krivoy = fl_list(items, 3);

${вызовы.join("\n")}

  fl_arena_release(&arena);
  return 0;
}
`
}

/** Ответы чужой программы, по одному на точку сетки, разобранные по табуляции. */
function разобрать(вывод) {
  const строки = вывод.split("\n").filter((строка) => строка.length > 0)
  assert.equal(строки.length, СЕТКА.length, `чужая программа обязана ответить на каждую точку:\n${вывод}`)
  return строки.map((строка, индекс) => {
    const части = строка.split("\t")
    assert.equal(части[0], СЕТКА[индекс].метка, `ответы приехали не по порядку: ${строка}`)
    if (части[1] === "OK") return { ok: true, значение: Number(части[2]) }
    return { ok: false, code: части[2], message: части.slice(3).join("\t") }
  })
}

const ccBin = findExecutable("cc") ?? findExecutable("gcc")

test("C: чужая программа через дверь входа сверяется с объявленными типами", (t) => {
  if (!ccBin) {
    missingToolchain(t, "c", "компилятор C не найден — пропуск")
    return
  }

  const каталог = рабочийКаталог("emit-c-library-door")
  mkdirSync(каталог, { recursive: true })
  const напечатано = emitC(программа, {})
  for (const файл of напечатано.files) writeFileSync(join(каталог, файл.path), файл.content, "utf8")

  /* Имя двери берётся из напечатанного заголовка, а не выписывается: префикс
     считает сам эмиттер из имени модуля. */
  const заголовок = напечатано.files.find((файл) => файл.path.endsWith(".h") && !файл.path.startsWith("flang_"))
  assert.ok(заголовок !== undefined, "у напечатанной программы обязан быть заголовок модуля")
  const найден = /fl_status ([a-z0-9_]+)_call\(fl_ctx/u.exec(заголовок.content)
  assert.ok(найден !== null, "в заголовке обязан быть вызов по имени")
  const префикс = найден[1]

  writeFileSync(join(каталог, "chuzhaya.c"), чужаяПрограмма(префикс, заголовок.path), "utf8")

  /* Прогонщик (`flang_cli.c`) НЕ собирается нарочно: он свою границу зовёт сам,
     и с ним проверка ничего не сказала бы про библиотечную дверь. */
  const исходники = напечатано.files
    .filter((файл) => файл.path.endsWith(".c") && файл.path !== "flang_cli.c")
    .map((файл) => файл.path)
  const среда = средаСборки(каталог)
  const сборка = spawnSync(
    ccBin,
    ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "chuzhaya.c", ...исходники, "-o", "chuzhaya", "-lm"],
    { cwd: каталог, encoding: "utf8", env: среда },
  )
  assert.equal(
    сборка.status,
    0,
    `чужая программа не собралась — дверь входа у напечатанной библиотеки пропала:\n${сборка.stdout}\n${сборка.stderr}`,
  )

  const прогон = (дверь) =>
    разобрать(execFileSync(join(каталог, "chuzhaya"), дверь === "call" ? ["call"] : [], {
      cwd: каталог,
      encoding: "utf8",
      env: среда,
    }))

  /* ── дверь: объявленные типы сверяются ДО вычисления ── */
  const черезДверь = прогон("enter")
  ДВЕРЬ.forEach((ждём, индекс) => {
    const точка = СЕТКА[индекс]
    const ответ = черезДверь[индекс]
    const кто = `дверь «${точка.имя}» на ${JSON.stringify(точка.args)}`
    if (ждём.ok) {
      assert.equal(ответ.ok, true, `${кто}: годный вход обязан считаться, а пришло ${JSON.stringify(ответ)}`)
      assert.equal(ответ.значение, ждём.значение, `${кто}: значение разошлось с вычислителем`)
      return
    }
    assert.equal(ответ.ok, false, `${кто}: значение вне типа обязано быть отвергнуто, а пришло ${JSON.stringify(ответ)}`)
    assert.equal(ответ.code, ждём.code, `${кто}: код отказа разошёлся со свидетелем`)
    assert.equal(ответ.message, ждём.message, `${кто}: текст отказа разошёлся со свидетелем`)
  })

  /* ── вычислитель: остался вычислителем, а не второй дверью ── */
  const черезВычислитель = прогон("call")
  ВЫЧИСЛИТЕЛЬ.forEach((ждём, индекс) => {
    if (ждём === null) return
    const точка = СЕТКА[индекс]
    const ответ = черезВычислитель[индекс]
    const кто = `вычислитель «${точка.имя}» на ${JSON.stringify(точка.args)}`
    assert.equal(ответ.ok, true, `${кто}: interpret отвечает, обязан ответить и напечатанный C, а пришло ${JSON.stringify(ответ)}`)
    assert.equal(ответ.значение, ждём.значение, `${кто}: значение разошлось с interpret`)
  })

  /* Изъятие: хотя бы одна точка обязана расходиться между дверями — иначе обе
     проверки выше прошли бы и на программе, где двери одна и та же. */
  const разошлись = СЕТКА.filter(
    (_, индекс) => !ДВЕРЬ[индекс].ok && ВЫЧИСЛИТЕЛЬ[индекс] !== null && черезВычислитель[индекс].ok,
  )
  assert.ok(
    разошлись.length > 0,
    "сетка обязана содержать значение, которое дверь отвергает, а вычислитель считает",
  )
})
