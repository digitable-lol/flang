/**
 * Печать конкурентной программы в цель, у которой планировщика нет.
 *
 * ── Что здесь стерегут ──────────────────────────────────────────────────────
 *
 * Шесть целей из восьми ТЕРЯЛИ процессы молча, и это был худший из возможных
 * исходов, потому что он выглядел успехом. Замер на
 * `flang/conc/examples/supervision.flang` (12 августа 2026):
 *
 *   | цель    | код возврата | «Работник» в выводе | `processes|supervisors` в бэкенде |
 *   |---------|--------------|---------------------|----------------------------------|
 *   | go      | 0            | 0 раз               | 0                                |
 *   | js      | 0            | 0 раз               | 0                                |
 *   | python  | 0            | 0 раз               | 0                                |
 *   | rust    | 0            | 0 раз               | 0                                |
 *   | java    | 0            | 0 раз               | 0                                |
 *   | csharp  | 0            | 0 раз               | 0                                |
 *   | c       | 0            | 9 раз               | 15                               |
 *   | elixir  | 0            | 9 раз               | 10                               |
 *
 * Имя второго процесса, «Учётчик», встречалось у всех шести РОВНО ОДИН раз — и
 * только строковым литералом адреса внутри тела обработчика
 * (`Value: rt.Text("Учётчик")`). То есть в напечатанном не было ни процесса, ни
 * состояния, ни ящика, ни надзора: обработчики стали обычными функциями,
 * которых никто не зовёт. Программа собиралась целевым компилятором,
 * запускалась и делала не то, что написано.
 *
 * ── Почему проверка идёт по КАТАЛОГУ целей, а не по списку ──────────────────
 *
 * Знание «у этой цели планировщик есть» живёт в двух местах по существу: в
 * `ЦЕЛИ_С_ПЛАНИРОВЩИКОМ` (оттуда берётся текст отказа) и в том, какие бэкенды
 * зовут `требуетПланировщика`. Разъехаться они могут молча — новый бэкенд
 * просто не позовёт сторожа и снова начнёт терять процессы. Поэтому цели
 * берутся из `emitTargets()`, то есть из каталога `src/emit`, и каждая обязана
 * либо напечатать процессы, либо отказать. Девятая цель попадёт под проверку
 * тем, что появится файл, а не тем, что кто-то вспомнит про этот тест.
 *
 * Запуск: node --test flang/test/emit-conc-refuse.test.mjs
 */
import assert from "node:assert/strict"
import { execFile } from "node:child_process"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

import { emitTargets, loadEmitter } from "../bin/flang.mjs"
import { NO_SCHEDULER_CODE, ЦЕЛИ_С_ПЛАНИРОВЩИКОМ } from "../src/conc.mjs"
import { parse } from "../src/parser.mjs"

const run = promisify(execFile)
const cli = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))
const примеры = fileURLToPath(new URL("../conc/examples/", import.meta.url))
const stdlib = fileURLToPath(new URL("../stdlib/", import.meta.url))

const разобрать = (путь, имя) => parse(readFileSync(путь + имя, "utf8"), имя)

/** Улика — живой пример репозитория, а не выдумка: два процесса и надзор. */
const СПроцессами = разобрать(примеры, "supervision.flang")
/** И вторая половина, без которой первая ничего не значит: та же печать без процессов. */
const БезПроцессов = разобрать(stdlib, "optional.flang")

test("улика на месте: в программе-улике действительно объявлены процессы и надзор", () => {
  /* Иначе тест зеленел бы на программе, у которой процессов нет вовсе, и
     «отказала» читалось бы как «работает». */
  assert.equal(СПроцессами.processes.length, 2)
  assert.equal(СПроцессами.supervisors.length, 1)
  assert.equal(СПроцессами.runs.length, 3)
  assert.deepEqual(БезПроцессов.processes ?? [], [])
})

test("каждая цель из каталога либо печатает процессы, либо отказывает — молча не теряет", async () => {
  const цели = await emitTargets()
  assert.ok(цели.length >= 8, `целей в каталоге всего ${цели.length}`)
  const отказали = []
  const напечатали = []

  for (const цель of цели) {
    const { emit } = await loadEmitter(цель)
    let напечатано = null
    let беда = null
    try {
      напечатано = emit(СПроцессами, {})
    } catch (ошибка) {
      беда = ошибка
    }

    if (ЦЕЛИ_С_ПЛАНИРОВЩИКОМ.includes(цель)) {
      assert.equal(беда, null, `цель «${цель}» обещана с планировщиком, а печать отказала: ${беда?.message}`)
      /* «Напечатала» — это не «не упала»: имя процесса обязано встретиться в
         напечатанном больше одного раза. Один раз оно встречалось и у шести
         потерявших — литералом адреса в теле обработчика. */
      const весь = напечатано.files.map((файл) => файл.content).join("")
      const сколько = весь.split("Работник").length - 1
      assert.ok(сколько > 1, `цель «${цель}»: имя процесса встречается ${сколько} раз — процессов в выводе нет`)
      напечатали.push(цель)
      continue
    }

    assert.notEqual(беда, null, `цель «${цель}» напечатала конкурентную программу, не имея планировщика`)
    assert.equal(беда.diagnostics?.[0]?.code, NO_SCHEDULER_CODE, `цель «${цель}»: ${беда.message}`)
    assert.match(беда.message, new RegExp(`«${цель}»`, "u"), "отказ обязан называть цель")
    assert.match(беда.message, /Работник/u, "отказ обязан называть первый непечатаемый процесс")
    for (const с of ЦЕЛИ_С_ПЛАНИРОВЩИКОМ) {
      assert.ok(беда.message.includes(с), `отказ не называет цель «${с}», в которую печатать МОЖНО`)
    }
    отказали.push(цель)
  }

  /* Охват печатается: проверка, молча схлопнувшаяся к одной цели, зеленела бы
     точно так же. */
  console.log(`печатают процессы: ${напечатали.join(", ")}; отказывают: ${отказали.join(", ")}`)
  assert.deepEqual(напечатали, [...ЦЕЛИ_С_ПЛАНИРОВЩИКОМ].sort())
  assert.ok(отказали.length >= 6, `отказавших целей всего ${отказали.length}`)
})

test("отказ — про процессы, а не про цель: без процессов та же цель печатает всё", async () => {
  /* Изъятие наоборот. Отказ, который срабатывал бы на любой программе, был бы
     не проверкой, а поломкой шести бэкендов, и тест выше её бы не отличил. */
  for (const цель of await emitTargets()) {
    const { emit } = await loadEmitter(цель)
    const напечатано = emit(БезПроцессов, {})
    assert.ok(напечатано.files.length > 0, `цель «${цель}» не напечатала программу без процессов`)
  }
})

test("одного объявления процесса достаточно: надзор и прогон не нужны", async () => {
  /* Правило отказа — «объявлена конкурентность», а не «объявлен надзор».
     Программа с одним процессом и без надзора до `check` не доходит, но печать
     обязана отказать и на ней: бэкенд зовут напрямую, и проверок перед ним
     может не быть вовсе. */
  const только = { ...БезПроцессов, processes: [{ name: "Один", handler: "нет такого", span: { line: 1, column: 1 } }] }
  const { emit } = await loadEmitter("go")
  assert.throws(
    () => emit(только, {}),
    (ошибка) => {
      assert.equal(ошибка.diagnostics?.[0]?.code, NO_SCHEDULER_CODE)
      assert.match(ошибка.message, /процесс «Один»/u)
      return true
    },
  )
})

test("через CLI отказ тот же и ничего не остаётся в stdout", async () => {
  /* Последнее звено: код возврата и то, что диагностика уехала в stderr. До
     правки эта же команда давала код 0 и 80 155 байт Go. */
  try {
    await run("node", [cli, "emit", `${примеры}supervision.flang`, "--target", "go"], { maxBuffer: 64 * 1024 * 1024 })
    assert.fail("emit --target go на конкурентной программе обязан отказать")
  } catch (ошибка) {
    assert.equal(ошибка.code, 1, "ошибка модели, а не вызова")
    assert.equal(ошибка.stdout, "", "в stdout не должно остаться ни байта кода")
    const отчёт = JSON.parse(ошибка.stderr)
    assert.equal(отчёт.diagnostics[0].code, NO_SCHEDULER_CODE)
  }
})
