/**
 * Печатает ту же программу в JS и загружает НАСТОЯЩИЙ артефакт — тот самый
 * модуль, который получит пользователь, а не его пересказ.
 */
let счётМодулей = 0
async function загрузитьJs(исходная = программа) {
  const каталог = join(рабочий, "js")
  mkdirSync(каталог, { recursive: true })
  const напечатано = emitJs(исходная)
  счётМодулей += 1
  const путь = join(каталог, `м${счётМодулей}-${напечатано.files[0].path}`)
  writeFileSync(путь, напечатано.files[0].content, "utf8")
  return { модуль: await import(pathToFileURL(путь).href), текст: напечатано.files[0].content }
}

/** Что вышло: значение или отказ. Отличать обязательно — в этом весь тест. */
async function исход(работа) {
  try {
    return { вид: "значение", значение: await работа() }
  } catch (беда) {
    return { вид: "отказ", code: беда.code, message: беда.message }
  }
}

test("JS: объявленный предел глубины достижим — стек отводится под него потоком", async (t) => {
  const { модуль } = await загрузитьJs()

  /* Так печатается и так зовут: расчёт уезжает в поток с заданным стеком. */
  const через_рычаг = await исход(() =>
    модуль.$callDeep(модуль.spusk, [ПРЕДЕЛ * 4], { maxDepth: ПРЕДЕЛ, maxSteps: 0 }),
  )
  assert.equal(через_рычаг.вид, "отказ", `JS обязан ОТКАЗАТЬ, а не ${JSON.stringify(через_рычаг)}`)
  assert.equal(через_рычаг.code, эталонныйОтказ.code)
  assert.equal(через_рычаг.message, эталонныйОтказ.message, "текст отказа обязан совпасть с эталоном дословно")

  /* И считает он то же самое, что прямой вызов: рычаг меняет стек, а не смысл.
     Без этой строки тест зеленел бы и на «$callDeep, который всегда отказывает». */
  const значение = await исход(() => модуль.$callDeep(модуль.spusk, [3], { maxDepth: ПРЕДЕЛ, maxSteps: 0 }))
  модуль.$newContext({ maxDepth: ПРЕДЕЛ, maxSteps: 0 })
  assert.deepEqual(значение, { вид: "значение", значение: модуль.spusk(3) })

  t.diagnostic(`при ${СВЯЗЫВАНИЙ} связываниях JS дошёл до объявленного предела ${ПРЕДЕЛ} и отказал текстом эталона`)
})

test("JS: изъятие рычага красит тест — на своём стеке до предела не доходит НИКТО", async (t) => {
  const { модуль } = await загрузитьJs()

  /* Долг, каким он был: прямой вызов считает на стеке того, кто позвал. Отказ
     объявленный — сторож на месте, — но текст называет хозяина, а не предел, и
     глубина много меньше обещанной. Это и есть доказательство изъятием: уберут
     поток из `$callDeep` — верхний тест сравняется с этим и покраснеет. */
  const свой_стек = await исход(() => {
    модуль.$newContext({ maxDepth: ПРЕДЕЛ, maxSteps: 0 })
    return модуль.spusk(ПРЕДЕЛ * 4)
  })
  assert.equal(свой_стек.вид, "отказ", `на своём стеке программа обязана отказать: ${JSON.stringify(свой_стек)}`)
  assert.equal(свой_стек.code, "FLANG_RECURSION_LIMIT", "код из закрытого набора видов отказа")
  const кадры = Number(/на глубине (\d+)/u.exec(свой_стек.message)?.[1])
  assert.match(
    свой_стек.message,
    /^функция «Спуск» исчерпала стек хозяина на глубине \d+, не дойдя до предела глубины вызовов \(10000\)$/u,
    "текст обязан называть хозяина, а не предел",
  )
  assert.ok(
    кадры > 0 && кадры < ПРЕДЕЛ,
    `без рычага объявленный предел обязан оставаться недостижимым, иначе тест беззуб: ${кадры}`,
  )

  /* И самая тонкая рекурсия тоже не доходит — до починки объявленных 10 000 не
     существовало НИ ДЛЯ ОДНОЙ программы, а не только для толстой. */
  const тонкая = parse(
    [
      "модуль «Тонкий кадр»",
      "",
      "функция «Спуск»",
      "  принимает н: число",
      "  возвращает число",
      "  если н не больше 0",
      "    то 0",
      "    иначе 1 плюс («Спуск» от (н минус 1))",
      "",
    ].join("\n"),
    "тонкий-кадр.flang",
  )
  const { модуль: тонкий } = await загрузитьJs(тонкая)
  const тонкий_свой = await исход(() => {
    тонкий.$newContext({ maxDepth: ПРЕДЕЛ, maxSteps: 0 })
    return тонкий.spusk(ПРЕДЕЛ * 4)
  })
  const тонкие_кадры = Number(/на глубине (\d+)/u.exec(тонкий_свой.message)?.[1])
  assert.ok(
    тонкие_кадры > 0 && тонкие_кадры < ПРЕДЕЛ,
    `даже тонкий кадр не доходил до предела на своём стеке: ${JSON.stringify(тонкий_свой)}`,
  )
  const тонкий_рычаг = await исход(() =>
    тонкий.$callDeep(тонкий.spusk, [ПРЕДЕЛ * 4], { maxDepth: ПРЕДЕЛ, maxSteps: 0 }),
  )
  /* Функция здесь тоже «Спуск», поэтому текст обязан совпасть с эталоном слово
     в слово — тем же, что списан с интерпретатора выше. */
  assert.equal(тонкий_рычаг.message, эталонныйОтказ.message)

  t.diagnostic(
    `изъятие: свой стек несёт ${кадры} кадров у толстого и ${тонкие_кадры} у тонкого при обещанных ${ПРЕДЕЛ}; с потоком оба доходят до ${ПРЕДЕЛ + 1}`,
  )
})

test("JS: выше потолка стека обещание не выдумывается, а передаётся сторожу", async (t) => {
  /* Стек берётся под объявленный предел, но не бесконечный: потолок 1 ГиБ. Выше
     него честно ровно то же, что в Rust на поднятом пределе, — отказ остаётся
     объявленным, а текст называет хозяина. Проверяется не число кадров (оно
     зависит от машины), а то, что отказ НЕ выдуман и не смерть. */
  const { модуль } = await загрузитьJs()
  const поднятый = await исход(() =>
    модуль.$callDeep(модуль.spusk, [12_000_000], { maxDepth: 3_000_000, maxSteps: 0 }),
  )
  assert.equal(поднятый.вид, "отказ", `JS обязан отказать, а не оборваться: ${JSON.stringify(поднятый)}`)
  assert.equal(поднятый.code, "FLANG_RECURSION_LIMIT")
  assert.match(
    поднятый.message,
    /^функция «Спуск» исчерпала стек хозяина на глубине \d+, не дойдя до предела глубины вызовов \(3000000\)$/u,
  )
  const кадры = Number(/на глубине (\d+)/u.exec(поднятый.message)?.[1])
  assert.ok(кадры > ПРЕДЕЛ, `потолок обязан быть выше объявленного предела по умолчанию, а не ниже: ${кадры}`)
  t.diagnostic(`JS: под потолком 1 ГиБ уложилось ${кадры} кадров — «${поднятый.message}»`)
})
