/* ───────────────────── программа с толстым кадром ───────────────────── */

/**
 * Сорок локальных связываний, и все живы на момент рекурсивного вызова.
 *
 * «Живы» здесь обязательное слово: связывание, чей результат никому не нужен,
 * оптимизатор выбрасывает, и кадр остаётся тонким — то есть тест мерил бы не то,
 * что называется. Поэтому все сорок складываются в результат, а рекурсивный
 * вызов стоит ПОСЛЕ суммы: значит все сорок обязаны пережить его в кадре.
 */
const СВЯЗЫВАНИЙ = 40

function толстаяПрограмма() {
  const имена = Array.from({ length: СВЯЗЫВАНИЙ }, (_, номер) => `а${String(номер + 1).padStart(2, "0")}`)
  const строки = [
    "модуль «Толстый кадр»",
    "",
    "функция «Спуск»",
    "  принимает н: число",
    "  возвращает число",
    ...имена.map((имя, номер) => `  пусть ${имя} равно н плюс ${номер + 1}`),
    "  если н не больше 0",
    "    то 0",
    `    иначе (${имена.join(" плюс ")}) плюс («Спуск» от (н минус 1))`,
    "",
  ]
  return parse(строки.join("\n"), "толстый-кадр.flang")
}

const программа = толстаяПрограмма()

/** Предел глубины по умолчанию — тот, который язык обещает всем и каждому. */
const ПРЕДЕЛ = 10_000

/**
 * Отказ эталона на том же входе. С него списывается ТЕКСТ, а не только код:
 * совпадение текста — часть контракта печати, и списывать его руками значило бы
 * позволить двум движкам разъехаться на редакции сообщения.
 */
const эталонныйОтказ = (() => {
  try {
    /* Лимит шагов поднят намеренно: проверяется предел ГЛУБИНЫ, а шаг у
       интерпретатора мельче, и при умолчании он упёрся бы первым — на глубине
       2 208, то есть в другой предел и с другим текстом. */
    interpret(программа, "Спуск", [ПРЕДЕЛ * 4], { maxDepth: ПРЕДЕЛ, maxSteps: 1_000_000_000 })
  } catch (беда) {
    return { code: беда.code, message: беда.message }
  }
  return assert.fail("эталон обязан упереться в предел глубины на этом входе")
})()

test("эталон на этом входе отказывает объявленно", () => {
  assert.equal(эталонныйОтказ.code, "FLANG_RECURSION_LIMIT")
  assert.equal(
    эталонныйОтказ.message,
    `функция «Спуск» превысила предел глубины вызовов (${ПРЕДЕЛ}) на глубине ${ПРЕДЕЛ + 1}`,
  )
})

/* ───────────────────── общий разбор ответа ───────────────────── */

/**
 * Запускает прогонщик и говорит, ЧЕМ кончилось: ответом, объявленным отказом
 * или смертью. Различать смерть от отказа обязательно — в ней весь долг.
 */
function спросить(бинарник, запрос, окружение = undefined) {
  const прогон = spawnSync(бинарник, [], {
    input: `${JSON.stringify(запрос)}\n`,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    env: окружение,
  })
  if (прогон.signal !== null) return { вид: "смерть", сигнал: прогон.signal }
  if (прогон.status !== 0) return { вид: "смерть", код: прогон.status, шум: (прогон.stderr ?? "").slice(0, 200) }
  const строка = (прогон.stdout ?? "").split("\n").find((с) => с.length > 0)
  if (строка === undefined) return { вид: "смерть", молча: true, шум: (прогон.stderr ?? "").slice(0, 200) }
  const ответ = JSON.parse(строка)
  return ответ.ok ? { вид: "значение", значение: ответ.value } : { вид: "отказ", code: ответ.code, message: ответ.message }
}

/** Спуск заведомо глубже предела: он обязан УПЕРЕТЬСЯ, а не досчитать. */
const ЗАПРОС = { fn: "Спуск", args: [{ n: String(ПРЕДЕЛ * 4) }], steps: "0" }

/* ══════════════════════════════ C ══════════════════════════════ */

function напечататьC() {
  const каталог = join(рабочий, "c")
  mkdirSync(каталог, { recursive: true })
  const напечатано = emitC(программа)
  for (const файл of напечатано.files) writeFileSync(join(каталог, файл.path), файл.content, "utf8")
  return { каталог, файлы: напечатано.files.filter((файл) => файл.path.endsWith(".c")).map((файл) => файл.path) }
}

function собратьC(печать, имя, лишние) {
  execFileSync(cc, [...CFLAGS, ...лишние, ...печать.файлы, "-o", имя, "-lm"], {
    cwd: печать.каталог,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  })
  return join(печать.каталог, имя)
}

test("C: объявленный предел глубины достижим и у функции с толстым кадром", (t) => {
  if (cc === null) return missingToolchain(t, "c", "компилятора C нет — пропуск")
  const печать = напечататьC()
  const как_печатается = собратьC(печать, "cli", [])

  const итог = спросить(как_печатается, ЗАПРОС)
  assert.equal(итог.вид, "отказ", `напечатанный C обязан ОТКАЗАТЬ, а не ${JSON.stringify(итог)}`)
  assert.equal(итог.code, эталонныйОтказ.code)
  assert.equal(итог.message, эталонныйОтказ.message, "текст отказа обязан совпасть с эталоном дословно")

  t.diagnostic(`при ${СВЯЗЫВАНИЙ} связываниях C дошёл до объявленного предела ${ПРЕДЕЛ} и отказал текстом эталона`)
})

test("C: изъятие починки красит тест — без стека и сторожа это SIGSEGV", (t) => {
  if (cc === null) return missingToolchain(t, "c", "компилятора C нет — пропуск")
  const печать = напечататьC()

  /* (в) Долг, каким он был: ни потока с заданным стеком, ни сторожа. Смерть по
     сигналу — не «ошибка теста», а ровно то, что обязано случиться, если
     починку выломают. */
  const голый = собратьC(печать, "cli-naked", ["-DFL_NO_POSIX_STACK", "-DFL_STACK_ROOM_FALLBACK=0"])
  const мёртвый = спросить(голый, ЗАПРОС)
  assert.equal(мёртвый.вид, "смерть", `без потока и без сторожа программа обязана умереть, иначе тест беззуб: ${JSON.stringify(мёртвый)}`)
  assert.equal(мёртвый.сигнал, "SIGSEGV", "и умереть именно по стеку")

  /* (б) Половина починки: потока нет, сторож есть. Отказ объявленный, но текст
     честно называет хозяина, а не предел, до которого не добрались. */
  const сторожевой = собратьC(печать, "cli-guard", ["-DFL_NO_POSIX_STACK"])
  const честный = спросить(сторожевой, ЗАПРОС)
  assert.equal(честный.вид, "отказ", `со сторожем программа обязана отказать: ${JSON.stringify(честный)}`)
  assert.equal(честный.code, "FLANG_RECURSION_LIMIT", "код из закрытого набора видов отказа")
  assert.match(
    честный.message,
    /^функция «Спуск» исчерпала стек хозяина на глубине \d+, не дойдя до предела глубины вызовов \(10000\)$/u,
    "текст обязан называть хозяина, а не предел",
  )

  t.diagnostic(`изъятие: без потока и сторожа — ${мёртвый.сигнал}; со сторожем — «${честный.message}»`)
})

test("C: обещание держится и под пределом адресного пространства", (t) => {
  if (cc === null) return missingToolchain(t, "c", "компилятора C нет — пропуск")
  /* Стек берётся отображением, значит под `ulimit -v` он отнимает адресное
     пространство у арены. Проверяется не то, что глубина остаётся прежней (она
     не остаётся), а то, что ОТКАЗ ОСТАЁТСЯ ОБЪЯВЛЕННЫМ на всей лестнице. */
  const печать = напечататьC()
  const бинарник = собратьC(печать, "cli-limited", [])
  const ступени = [524_288, 65_536, 16_384]
  const глубины = []
  for (const предел of ступени) {
    const прогон = spawnSync("/bin/sh", ["-c", `ulimit -v ${предел} || exit 97; exec "$0"`, бинарник], {
      input: `${JSON.stringify(ЗАПРОС)}\n`,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    })
    if (прогон.status === 97) {
      t.diagnostic("оболочка не даёт поставить ulimit -v — проверка пропущена")
      return
    }
    assert.equal(прогон.signal, null, `под ulimit -v ${предел} программа умерла по сигналу ${прогон.signal}`)
    const строка = (прогон.stdout ?? "").split("\n").find((с) => с.length > 0)
    assert.ok(строка !== undefined, `под ulimit -v ${предел} программа не сказала ничего:\n${прогон.stderr}`)
    const ответ = JSON.parse(строка)
    assert.equal(ответ.ok, false)
    assert.equal(ответ.code, "FLANG_RECURSION_LIMIT", `под ulimit -v ${предел}: ${ответ.message}`)
    глубины.push(`${предел} КиБ → ${ответ.message.replace(/^.*?глубине (\d+).*$/u, "$1")}`)
  }
  t.diagnostic(`отказ объявленный на всей лестнице: ${глубины.join("; ")}`)
})

