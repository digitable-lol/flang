test("Go: объявленный предел ПО УМОЛЧАНИЮ достижим и у функции с толстым кадром", (t) => {
  if (goBin === null) return missingToolchain(t, "go", "компилятора Go нет — пропуск")
  /*
   * Go — единственная из трёх целей, где приём не применён, и это записано
   * замером, а не мнением. У горутины нет явного размера стека: он растёт сам,
   * ПЕРЕЕЗЖАЯ на новое место, и отметка стека, снятая на входе в расчёт, после
   * первого же переезда не значит ничего — сторож по адресам там невозможен.
   * Зато растущий стек и снимает вопрос по умолчанию: на этой же программе Go
   * доходит до объявленного предела и отказывает объявленно. Дальше предела по
   * умолчанию обещание Go не держит, и это записано в SPEC отдельной строкой, а
   * не спрятано под общим «отказ всегда объявленный».
   */
  const каталог = join(рабочий, "go")
  mkdirSync(каталог, { recursive: true })
  const напечатано = emitGo(программа)
  for (const файл of напечатано.files) {
    const путь = join(каталог, файл.path)
    mkdirSync(join(путь, ".."), { recursive: true })
    writeFileSync(путь, файл.content, "utf8")
  }
  const сборка = spawnSync(goBin, ["build", "-o", "flang_cli", "./cli"], {
    cwd: каталог,
    encoding: "utf8",
    env: GO_ENV,
  })
  assert.equal(сборка.status, 0, `go build не собрал напечатанное:\n${сборка.stdout}\n${сборка.stderr}`)

  const итог = спросить(join(каталог, "flang_cli"), ЗАПРОС, GO_ENV)
  assert.equal(итог.вид, "отказ", `Go обязан отказать: ${JSON.stringify(итог)}`)
  assert.equal(итог.code, эталонныйОтказ.code)
  assert.equal(итог.message, эталонныйОтказ.message, "текст отказа обязан совпасть с эталоном дословно")
  t.diagnostic("Go: растущий стек горутины несёт предел по умолчанию; сторожа по адресам там завести нельзя — стек переезжает")
})

