  assert.equal(итог.code, эталонныйОтказ.code)
  assert.equal(итог.message, эталонныйОтказ.message, "текст отказа обязан совпасть с эталоном дословно")
  t.diagnostic("Go: растущий стек горутины несёт предел по умолчанию; сторожа по адресам там завести нельзя — стек переезжает")
