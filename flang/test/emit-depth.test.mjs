/**
 * Предел глубины несётся СТЕКОМ, и это проверяется, а не обещается.
 *
 * ── Что здесь чинится ───────────────────────────────────────────────────────
 *
 * Счётчик глубины считает КАДРЫ, а несёт их стек, и сколько их влезет, зависит
 * от программы: у нехвостовой функции с одним параметром кадр толщиной 352
 * байта, у функции с сорока локальными связываниями — 5 526. При объявленном
 * пределе 10 000 первая проходила его вдвое (23 807 кадров при стеке 8 МиБ), а
 * вторая умирала на 1 518 кадрах по SIGSEGV — без кода, без текста, без
 * возможности перехвата. То есть
 * объявленный предел глубины В ЭТИХ ЦЕЛЯХ ПРЕДЕЛОМ НЕ БЫЛ, а обещание языка
 * «тотальная функция завершится ИЛИ ОТКАЖЕТ ЧЕСТНО» не держалось ни тем, ни
 * другим концом.
 *
 * Проверять это на средней программе бессмысленно: средняя программа проходила
 * и до починки. Поэтому здесь стоит ХУДШАЯ форма — сорок связываний, живых
 * через рекурсивный вызов, чтобы компилятор не выбросил ни одного.
 *
 * ── Почему тест отдельным файлом, а не в emit-c.test.mjs ────────────────────
 *
 * Долг общий для четырёх целей — C, Go, Rust и JavaScript, — и лечится он в
 * трёх из них одним и тем же приёмом: расчёт уезжает в поток с ЯВНО ЗАДАННЫМ
 * стеком. Разложенный по четырём файлам печати, он читался бы как четыре
 * несвязанные мелочи; здесь видно, что это одно свойство языка и одна его
 * граница.
 *
 * ── Чем JavaScript отличался от остальных трёх ──────────────────────────────
 *
 * В C, Go и Rust объявленный предел был достижим ХОТЬ ДЛЯ КАКОЙ-ТО программы —
 * тонкий кадр проходил его вдвое. В JavaScript не проходила НИ ОДНА: самая
 * тонкая рекурсивная функция укладывалась в стек V8 7 386 раз при обещанных
 * 10 000, а эта, с сорока связываниями, — 1 379 раз. То есть объявленное число
 * не было пределом ни при каких условиях, а отказ приходил не тот, которым на
 * том же входе отвечает интерпретатор.
 *
 * ── Зубы: изъятие ───────────────────────────────────────────────────────────
 *
 * Тест, который просто видит объявленный отказ, зеленел бы и на программе, где
 * отказ приходит по любой другой причине. Поэтому здесь собираются ТРИ варианта
 * одного и того же напечатанного C, и проверяется, что они дают три РАЗНЫХ
 * исхода:
 *
 *   а) как печатается            → объявленный предел достигнут (глубина 10001);
 *   б) без потока, сторож на месте → объявленный отказ про стек хозяина;
 *   в) без потока и без сторожа    → SIGSEGV, то есть долг, каким он был.
 *
 * Вариант (в) — это и есть доказательство изъятием: если завтра починку
 * выломают, (а) сравняется с (в), и тест покраснеет, а не промолчит.
 */
