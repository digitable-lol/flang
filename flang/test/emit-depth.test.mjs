test("Rust: поднятый предел глубины даёт объявленный отказ, а не аварийный останов", (t) => {
  if (rustcBin === null) return missingToolchain(t, "rust", "rustc не найден — пропуск")
  const каталог = join(рабочий, "rust")
  mkdirSync(join(каталог, "src"), { recursive: true })
  const напечатано = emitRust(программа)
  for (const файл of напечатано.files) {
    const путь = join(каталог, файл.path)
    mkdirSync(join(путь, ".."), { recursive: true })
    writeFileSync(путь, файл.content, "utf8")
  }
  /* Сборка ровно та же, что в emit-rust.test.mjs: сперва библиотека, потом
     прогонщик с нею наружу. `-D warnings` не смягчается — напечатанный Rust
     обязан собираться без единого замечания, и сторож стека тоже. */
  const RUSTC = ["--edition", "2021", "-D", "warnings", "-C", "debuginfo=0", "-C", "opt-level=2"]
  const RUST_ENV = средаСборки(рабочий, { CARGO_NET_OFFLINE: "true" })
  const библиотека = join(каталог, "libflangprogram.rlib")
  const lib = spawnSync(
    rustcBin,
    [...RUSTC, "--crate-type", "lib", "--crate-name", "flangprogram", "-o", библиотека, "src/lib.rs"],
    { cwd: каталог, encoding: "utf8", env: RUST_ENV },
  )
  assert.equal(lib.status, 0, `rustc не собрал библиотеку:\n${lib.stdout}\n${lib.stderr}`)
  assert.equal(lib.stderr.trim(), "", `rustc нашёл, к чему придраться:\n${lib.stderr}`)
  const сборка = spawnSync(
    rustcBin,
    [...RUSTC, "--extern", `flangprogram=${библиотека}`, "-o", join(каталог, "flang_cli"), "src/main.rs"],
    { cwd: каталог, encoding: "utf8", env: RUST_ENV },
  )
  assert.equal(сборка.status, 0, `rustc не собрал прогонщик:\n${сборка.stdout}\n${сборка.stderr}`)
  assert.equal(сборка.stderr.trim(), "", `rustc нашёл, к чему придраться:\n${сборка.stderr}`)

  /* Под объявленный предел стек отводится, значит он достижим. */
  const обычный = спросить(join(каталог, "flang_cli"), ЗАПРОС)
  assert.equal(обычный.вид, "отказ", `Rust обязан отказать: ${JSON.stringify(обычный)}`)
  assert.equal(обычный.message, эталонныйОтказ.message, "и текстом эталона")

  /*
   * Предел, поднятый ЗАПРОСОМ, стек уже не несёт: он заведён один раз на
   * процесс, под предел, объявленный при печати. Раньше это был `fatal runtime
   * error: stack overflow, aborting` — то есть смерть без кода и текста; теперь
   * сторож переводит его в объявленный отказ, честно называющий хозяина.
   */
  const поднятый = спросить(join(каталог, "flang_cli"), {
    fn: "Спуск",
    args: [{ n: "2000000" }],
    depth: "500000",
    steps: "0",
  })
  assert.equal(поднятый.вид, "отказ", `Rust обязан отказать, а не оборваться: ${JSON.stringify(поднятый)}`)
  assert.equal(поднятый.code, "FLANG_RECURSION_LIMIT")
  assert.match(
    поднятый.message,
    /^функция «Спуск» исчерпала стек хозяина на глубине \d+, не дойдя до предела глубины вызовов \(500000\)$/u,
  )
  t.diagnostic(`Rust: «${поднятый.message}»`)
})

