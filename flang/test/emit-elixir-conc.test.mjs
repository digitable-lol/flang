/**
 * Печать конкурентности flang → Elixir: процесс в GenServer, надзор в дерево
 * супервизоров OTP (`flang/conc/SPEC.md`, шаг 4).
 *
 * ── Чем сверяться, если ответа не один ──────────────────────────────────────
 *
 * У остальных бэкендов сверка простая: на одном входе напечатанный код обязан
 * дать то же значение и ту же ошибку, что интерпретатор. Здесь так нельзя.
 * Семантика модели — ЛЮБОЕ чередование атомарных пробегов (контракт,
 * «Семантика»), и «то же самое» для конкурентной программы значит не одно
 * значение, а НАБОР возможных исходов. Планировщик BEAM выбирает чередование
 * сам, семени у него нет, и требовать от него исхода с семени 4172 было бы
 * требованием, которого модель не предъявляет.
 *
 * Поэтому сверка устроена так:
 *
 *   1. Эталон (`conc.mjs`) прогоняется на СЕТКЕ СЕМЁН — тысяча семян на каждый
 *      прогон, — и из итогов собирается множество: состояния всех процессов,
 *      кто остался жив, исход программы и список отказов.
 *   2. Напечатанная программа собирается настоящим `elixirc` и запускается на
 *      настоящей BEAM много раз подряд.
 *   3. КАЖДЫЙ исход с BEAM обязан лежать в множестве эталона. Не «похож» —
 *      лежать: сравниваются канонические записи значений.
 *
 * У такой сверки два известных слабых места, и оба закрыты отдельными тестами.
 *
 * **Множество может оказаться ненасыщенным** — тогда исход с BEAM выпадет из
 * него не потому, что печать неверна, а потому, что семян не хватило. Проверка:
 * набор с половины сетки обязан совпасть с набором со всей сетки. Совпал —
 * значит сетка своё уже показала.
 *
 * **Множество может оказаться слишком широким** — тогда в него попадёт что
 * угодно, и сверка ничего не проверяет. Проверок на зубы две: у любого исхода
 * из набора достаточно изменить ОДНО число, и он из набора выпадает; и наборы
 * двух прогонов одной программы с разными входными сообщениями не пересекаются
 * ни в одной точке.
 *
 * (Третья проверка на зубы напрашивалась и не подошла: «добавить программе
 * лишнее входное сообщение — исход обязан выпасть из набора». На
 * `supervision.flang` она не сбывается, и правильно делает: четвёртое ядовитое
 * сообщение приходит процессу, который после третьего отказа уже остановлен
 * надзором, — то есть возмущение ненаблюдаемо по существу, а не по слабости
 * сверки.)
 *
 * ── Журнал доставок: сверка сильнее исходов ─────────────────────────────────
 *
 * Контракт (пункт 2 «Что проверяется и чем») требует сверять не итог, а журнал
 * доставок: расхождение в планировщике проявится задолго до расхождения в
 * итоге. Побайтового совпадения журналов здесь быть не может — семени у BEAM
 * нет, — но множество журналов эталона на сетке семян насыщается тоже, и тогда
 * «журнал с BEAM лежит в множестве журналов эталона» проверяется буквально. У
 * `race.flang` в этом множестве 84 журнала — это все чередования, которые
 * допускает причинность, и попасть в них случайно нельзя.
 *
 * Программы с таймером из этой сверки исключены, и причина названа в отчёте
 * шага 4: единица времени у эталона — пробег обработчика, у BEAM —
 * миллисекунда настоящих часов. Журналы поэтому расходятся по ДЛИНЕ (у эталона
 * одиннадцать пробегов, у BEAM — около двух тысяч), хотя набор ИСХОДОВ у них
 * один и тот же, и он сверяется.
 *
 * Обе сверки идут в одном тесте намеренно: каждый запуск на BEAM стоит дороже
 * всего остального вместе взятого, и спрашивать машину дважды об одном и том же
 * значило бы удвоить цену проверки ради разделения на два имени.
 *
 * ── Если тулчейна Elixir нет ────────────────────────────────────────────────
 * Тесты, которым нужен компилятор, честно пропускаются через `missingToolchain`;
 * `FTS_REQUIRE_TOOLCHAINS=elixir` превращает пропуск в падение. Статические
 * тесты (что напечатано, что не напечатано, детерминированность) идут всегда.
 */
