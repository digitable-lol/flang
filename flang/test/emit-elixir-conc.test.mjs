test("сверка имеет зубы: одно изменённое число выводит исход из набора", () => {
  /* Набор, в который попадает что угодно, ничего не проверяет. Здесь проверяется
     обратное: у любого исхода из набора хватает изменить ОДНО число — и он из
     набора выпадает. Значит «исход с BEAM лежит в наборе» — утверждение, а не
     тавтология. */
  let проверено = 0
  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    for (const прогон of программа.runs ?? []) {
      const набор = наборЭталона(программа, прогон, 200)
      for (const исход of набор.keys()) {
        const подделка = исход.replace(/#(-?\d+)/u, (_целиком, число) => `#${Number(число) + 1}`)
        assert.notEqual(подделка, исход, `${имя} / «${прогон.name}»: в исходе нет ни одного числа`)
        assert.ok(
          !набор.has(подделка),
          `${имя} / «${прогон.name}»: исход с изменённым числом остался в наборе — ` +
            "набор слишком широк, и сверка по нему ничего не доказывает",
        )
        проверено += 1
      }
    }
  }
  assert.ok(проверено >= 20, `исходов проверено слишком мало: ${проверено}`)
})

test("наборы разных прогонов не пересекаются: набор — свойство прогона, а не программы", () => {
  /* Вторая половина зубов. Если бы набор был широк, наборы двух прогонов одной
     программы с РАЗНЫМИ входными сообщениями перекрылись бы, и «исход лежит в
     наборе» перестало бы отличать один прогон от другого. */
  let пар = 0
  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    const прогоны = программа.runs ?? []
    for (let левый = 0; левый < прогоны.length; левый += 1) {
      for (let правый = левый + 1; правый < прогоны.length; правый += 1) {
        /* Только процесс и сообщение: у двух прогонов с одинаковыми входными
           сообщениями (и разными семенами) наборы обязаны СОВПАДАТЬ, а не
           разойтись, — сравнивать их бессмысленно. Место в исходнике из ключа
           убрано, иначе одинаковые ящики выглядели бы разными. */
        const ящик = (прогон) => JSON.stringify((прогон.inbox ?? []).map((з) => [з.process, з.message]))
        if (ящик(прогоны[левый]) === ящик(прогоны[правый])) continue
        const первый = наборЭталона(программа, прогоны[левый], 200)
        const второй = наборЭталона(программа, прогоны[правый], 200)
        for (const исход of первый.keys()) {
          assert.ok(
            !второй.has(исход),
            `${имя}: наборы прогонов «${прогоны[левый].name}» и «${прогоны[правый].name}» пересеклись`,
          )
        }
        пар += 1
      }
    }
  }
  assert.ok(пар >= 4, `пар прогонов с разными ящиками слишком мало: ${пар}`)
})

