test("ограниченный ящик (А3) в Elixir не печатается, и печать отказывает названным кодом", () => {
  /* Честная граница шага А3, и записана она отказом, а не молчанием.
     Ящик процесса BEAM неограничен устройством машины, а `send/2` там не может
     сообщить, что адресат не справляется: он всегда возвращает сообщение.
     Подделать потолок можно было бы одним способом — опросить
     `Process.info(pid, :message_queue_len)` из ОТПРАВИТЕЛЯ, — но это чтение
     чужого ящика в другой момент времени, то есть не объявленный потолок, а
     гонка вместо него. Напечатать похожее и назвать это ограниченным ящиком
     было бы ровно тем враньём, которого в этом репозитории быть не должно.

     Проверка стоит здесь, а не в разделе с BEAM, потому что тулчейн ей не
     нужен: отказывает ПЕЧАТЬ, а не сборка. */
  const программа = разобрать("backpressure")
  assert.throws(
    () => emitElixir(программа),
    (беда) => {
      assert.equal(беда.diagnostics?.[0]?.code, "FLANG_EMIT", JSON.stringify(беда.diagnostics))
      assert.match(беда.message, /ящик на 4 сообщений/u)
      assert.match(беда.message, /у процесса BEAM\s+ящик неограничен/u)
      return true
    },
  )

  /* Зубы: тот же самый файл без одной строки печатается без единой жалобы —
     значит отказ пришёл именно от объявленного ящика, а не от чего-то ещё в
     этой программе. */
  const безЯщика = разобратьТекст(
    readFileSync(`${примеры}backpressure.flang`, "utf8").replace(" с ящиком 4 сообщений", ""),
    "backpressure.flang",
  )
  assert.ok(emitElixir(безЯщика).files.length > 0)
})
