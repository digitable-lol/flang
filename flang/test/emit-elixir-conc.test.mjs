/* ───────────────────── печать, сборка, запуск ───────────────────── */

let счёт = 0
const собранные = new Map()

/** Печатает программу в пустой каталог и собирает ровно то, что напечатано. */
function собрать(имя, программа) {
  const готовое = собранные.get(имя)
  if (готовое !== undefined) return готовое

  счёт += 1
  const каталог = join(рабочий, `p${счёт}`)
  mkdirSync(каталог, { recursive: true })
  const напечатано = emitElixir(программа)
  for (const файл of напечатано.files) {
    mkdirSync(dirname(join(каталог, файл.path)), { recursive: true })
    writeFileSync(join(каталог, файл.path), файл.content, "utf8")
  }

  const исходники = напечатано.files.filter((файл) => файл.path.endsWith(".ex")).map((файл) => файл.path)
  const модульФайл = исходники.find((путь) => !путь.startsWith("flang_"))
  const текст = напечатано.files.find((файл) => файл.path === модульФайл).content
  const модуль = текст.match(/^defmodule ([A-Za-z0-9_.]+) do$/mu)[1]

  mkdirSync(join(каталог, "_build"), { recursive: true })
  const сборка = spawnSync(elixircBin, ["--warnings-as-errors", "-o", "_build", ...исходники], {
    cwd: каталог,
    encoding: "utf8",
    env: СРЕДА,
  })
  assert.equal(
    сборка.status,
    0,
    `elixirc не принял напечатанное (--warnings-as-errors):\n${сборка.stdout}\n${сборка.stderr}`,
  )

  const результат = { каталог, модуль, файлы: напечатано.files.map((файл) => файл.path), текст }
  собранные.set(имя, результат)
  return результат
}

/** Один запуск BEAM на сколько угодно прогонов: старт машины дорог, прогон дёшев. */
function спросить(собрано, запросы) {
  const вход = `${запросы.map((запрос) => JSON.stringify(запрос)).join("\n")}\n`
  const вывод = execFileSync(elixirBin, ["-pa", "_build", "-e", `Flang.Cli.main(["${собрано.модуль}"])`], {
    cwd: собрано.каталог,
    input: вход,
    encoding: "utf8",
    env: СРЕДА,
    maxBuffer: 512 * 1024 * 1024,
    timeout: ПРЕДЕЛ_РАЗГОВОРА,
    killSignal: "SIGKILL",
  })
  const строки = вывод.split("\n").filter((строка) => строка.length > 0)
  assert.equal(строки.length, запросы.length, "прогонщик обязан ответить на каждый запрос ровно один раз")
  return строки.map((строка) => JSON.parse(строка))
}

/* ───────────────────── канон значений ─────────────────────
   Итог эталона — значения flang в записи интерпретатора, итог с BEAM — тот же
   размеченный JSON, что у остальных бэкендов. Сравнивать их можно только приведя
   к одному виду, и вид этот обязан различать ровно то, что различает язык:
   порядок полей записи не значим (fields_equal рантайма сравнивает по именам),
   порядок элементов списка значим, NaN равен NaN. */

function каноническое(значение) {
  if (значение === null || значение === undefined) return "ничто"
  if (typeof значение === "boolean") return значение ? "да" : "нет"
  if (typeof значение === "number") return `#${Object.is(значение, -0) ? "-0" : String(значение)}`
  if (typeof значение === "string") return `"${значение}"`
  if (Array.isArray(значение)) return `[${значение.map(каноническое).join(",")}]`
  if (typeof значение === "object") {
    if (typeof значение.variant === "string" && значение.fields !== undefined) {
      return `«${значение.variant}»${поля(значение.fields)}`
    }
    return поля(значение)
  }
  throw new Error(`нечего канонизировать: ${typeof значение}`)
}

function поля(запись) {
  return `{${Object.keys(запись).sort().map((имя) => `${имя}:${каноническое(запись[имя])}`).join(",")}}`
}

/** Значение из размеченного JSON прогонщика. */
function раскодировать(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(раскодировать)
  if (Object.hasOwn(узел, "r")) {
    const запись = {}
    for (const [имя, значение] of узел.r) запись[имя] = раскодировать(значение)
    return запись
  }
  if (Object.hasOwn(узел, "v")) {
    const поля = {}
    for (const [имя, значение] of узел.f ?? []) поля[имя] = раскодировать(значение)
    return { variant: узел.v, fields: поля }
  }
  throw new Error(`нечего раскодировать: ${JSON.stringify(узел)}`)
}

/**
 * Канон ИСХОДА — того, что вообще наблюдаемо снаружи: состояния процессов, кто
 * жив, чем кончилась программа и какие были отказы. Ни времени, ни номеров
 * пробегов здесь нет намеренно: у эталона время виртуальное, у BEAM настоящее,
 * и сравнивать их значило бы сравнивать не то.
 */
function исходЭталона(итог) {
  const состояния = Object.entries(итог.состояния)
    .map(([имя, значение]) => `${имя}=${каноническое(значение)}`)
    .join("; ")
  const отказы = итог.отказы.map((отказ) => `${отказ.процесс}:${отказ.код}`).join(",")
  return `${итог.исход} | ${состояния} | живые: ${итог.живые.join(",")} | отказы: ${отказы}`
}

function исходBEAM(ответ) {
  const состояния = ответ["состояния"]
    .map(([имя, значение]) => `${имя}=${каноническое(раскодировать(значение))}`)
    .join("; ")
  const отказы = ответ["отказы"].map(([имя, код]) => `${имя}:${код}`).join(",")
  return `${ответ["исход"]} | ${состояния} | живые: ${ответ["живые"].join(",")} | отказы: ${отказы}`
}

/** Набор исходов эталона на сетке семян. */
function наборЭталона(программа, прогон, семян) {
  const набор = new Map()
  for (let семя = 0; семя < семян; семя += 1) {
    const итог = runConcurrent(программа, { ...прогон, seed: семя })
    const ключ = исходЭталона(итог)
    if (!набор.has(ключ)) набор.set(ключ, семя)
  }
  return набор
}

/** Набор журналов доставки эталона на той же сетке. */
function журналыЭталона(программа, прогон, семян) {
  const набор = new Set()
  for (let семя = 0; семя < семян; семя += 1) {
    набор.add(runConcurrent(программа, { ...прогон, seed: семя }).журнал.map((з) => з.процесс).join(","))
  }
  return набор
}

/* ══════════════════ 1. главная сверка: исход и чередование ══════════════════ */

test("напечатанное на BEAM не выходит за набор эталона: ни исходом, ни чередованием", async (t) => {
  if (!тулчейн) {
    missingToolchain(t, "elixir", "тулчейн Elixir не найден (ни в PATH, ни в FTS_TOOLCHAIN_PATH) — пропуск")
    return
  }

  let прогонов = 0
  let запусков = 0
  let сверок = 0
  let чередований = 0
  const начало = Date.now()
  const видано = []
  const виды = new Set()

  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    const собрано = собрать(имя, программа)
    assert.ok(программа.runs?.length > 0, `${имя}: в программе нет ни одного прогона`)

    const запросы = []
    const план = []
    for (const прогон of программа.runs) {
      for (let раз = 0; раз < ПОВТОРОВ; раз += 1) {
        запросы.push({ run: прогон.name })
        план.push(прогон)
      }
    }
    const ответы = спросить(собрано, запросы)

    const наборы = new Map()
    const журналы = new Map()
    const своё = new Map()
    план.forEach((прогон, индекс) => {
      const ответ = ответы[индекс]
      assert.ok(ответ.ok, `${имя} / «${прогон.name}»: прогонщик ответил отказом ${JSON.stringify(ответ)}`)
      for (const [, код] of ответ["отказы"]) if (код) виды.add(код)
      if (!наборы.has(прогон.name)) наборы.set(прогон.name, наборЭталона(программа, прогон, СЕМЯН))
      const набор = наборы.get(прогон.name)
      const исход = исходBEAM(ответ)
      if (!своё.has(прогон.name)) своё.set(прогон.name, new Set())
      своё.get(прогон.name).add(исход)
      assert.ok(
        набор.has(исход),
        `${имя} / «${прогон.name}»: BEAM дала исход, которого эталон не даёт ни на одном из ${СЕМЯН} семян.\n` +
          `  BEAM:   ${исход}\n` +
          `  эталон: ${[...набор.keys()].join("\n          ")}`,
      )
      запусков += 1

      /* Журнал — сверка сильнее исходов, но у программы с таймером её нет:
         единица времени у эталона пробег, у BEAM миллисекунда, и журналы
         расходятся по длине, а не по существу (см. шапку). */
      if (С_ТАЙМЕРОМ.has(имя)) return
      if (!журналы.has(прогон.name)) журналы.set(прогон.name, журналыЭталона(программа, прогон, СЕМЯН))
      const чередования = журналы.get(прогон.name)
      const журнал = ответ["журнал"].join(",")
      assert.ok(
        чередования.has(журнал),
        `${имя} / «${прогон.name}»: BEAM выдала чередование, которого эталон не даёт ни на одном семени.\n` +
          `  BEAM: ${журнал}\n  журналов у эталона: ${чередования.size}`,
      )
      сверок += 1
    })
    прогонов += программа.runs.length
    for (const [прогон, набор] of своё) {
      видано.push(`${имя}/«${прогон}»: ${набор.size} из ${наборы.get(прогон).size}`)
    }
    for (const набор of журналы.values()) чередований += набор.size
  }

  t.diagnostic(
    `программ: ${ПРОГРАММЫ.length}, прогонов: ${прогонов}, запусков на BEAM: ${запусков}, ` +
      `сверенных журналов: ${сверок} (различных чередований у эталона: ${чередований}), ` +
      `семян у эталона на прогон: ${СЕМЯН}, за ${Math.round((Date.now() - начало) / 1000)} с`,
  )
  /* Сколько исходов из набора эталона BEAM показала на самом деле. Требовать
     тут ничего нельзя — планировщик машины вправе ходить одной дорогой, — но
     видеть это надо: если BEAM всегда даёт один и тот же исход, сверка
     доказывает меньше, чем кажется. */
  t.diagnostic(`исходов показала BEAM (из набора эталона): ${видано.join(", ")}`)
  assert.ok(запусков >= 250, `запусков на BEAM слишком мало: ${запусков}`)
  assert.ok(сверок >= 200, `журналов сверено слишком мало: ${сверок}`)

  /* И вторая половина, ради которой в сверку добавлен `measure.flang`. Сверка
     по НАБОРУ слаба тем же, чем побайтовая у C: набор считает эталон, и сними
     отметку меры — её потеряют обе стороны разом. Обе досчитают одну и ту же
     бессмыслицу (`делитель` = 1.7763568394002505e-15), исход с BEAM окажется в
     наборе, и сверка промолчит зелёным. Здесь это требуется прямо: код
     `FLANG_MEASURE` обязан ПРИЙТИ С МАШИНЫ. Набор отказов объявлен замкнутым
     (`flang/src/failures.mjs`: «шаг, добавляющий способ отказать, обязан
     добавить его И СЮДА»), и замкнутость, проверенная у одного эталона, о
     напечатанном не говорит ничего. */
  const мера = КОДЫ_ОТКАЗА[ВИДЫ_ОТКАЗА.МЕРА]
  assert.ok(
    виды.has(мера),
    `шестой вид отказа («${ВИДЫ_ОТКАЗА.МЕРА}», ${мера}) с BEAM не пришёл ни разу — ` +
      `сверка стережёт программу без сторожей меры. Пришли: ${[...виды].sort().join(", ") || "никакие"}`,
  )
  t.diagnostic(`видов отказа пришло с BEAM: ${[...виды].sort().join(", ")}`)
})

