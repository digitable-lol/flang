/**
 * Сторож обещаний о печати и о стоимости форм — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/emit-guard.mjs`. Обязательств
 * четыре:
 *
 *   1. на дереве сторож ЧИСТ — «семь бэкендов и один самодостаточный файл»
 *      сходится с прогоном восьми эмиттеров, а таблица стоимостей — с рантаймами;
 *   2. сторож ЛОВИТ разошедшуюся скобку таблицы стоимостей — на цель;
 *   3. сторож ЛОВИТ ПРОПАВШЕЕ обещание: фраза, стёртая из README, — такое же
 *      расхождение, как неверная. Обещание, которое переписали, обязано быть
 *      перепроверено, а не потеряно;
 *   4. улики стоимости — настоящие куски настоящих рантаймов, и каждая на месте.
 *
 * Третье написано потому, что сторож, стерегущий фразу, тише всего умирает от
 * того, что фразу переписали: он остаётся зелёным и не стережёт ничего.
 *
 * Запуск: node --test flang/test/emit-guard.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import {
  КОРЕНЬ,
  МАНИФЕСТЫ,
  ОБЕЩАНИЯ,
  СТОИМОСТЬ_ХВОСТА,
  печатьВсех,
  проверить,
  строкаХвоста,
  целиИсключения,
} from "../scripts/emit-guard.mjs"

const прочитать = (отн) => readFileSync(new URL(отн, new URL("../../", import.meta.url)), "utf8")

test("на дереве репозитория сторож чист", async () => {
  const нарушения = await проверить(КОРЕНЬ)
  assert.deepEqual(
    нарушения.map((н) => `${н.файл} — ${н.что} [${н.род}]: ${н.весть ?? `сказано ${н.сказано}, напечатано ${н.измерено}`}`),
    [],
    "обещание прозы разошлось с печатью: правьте прозу, а не сторожа",
  )
})

test("печать меряется прогоном восьми эмиттеров, а не таблицей", async () => {
  const печать = await печатьВсех(КОРЕНЬ)
  assert.equal(печать.size, 8, "целей обязано быть восемь")
  /* Здесь стояло «бэкенд JS печатает один файл», и это перестало быть правдой
     вместе с границей входа у восьмой цели (`work/js-entry-types`): рядом с
     модулем печатается прогонщик `flang_cli.js`, которым и держится
     объявленный предел глубины вызовов. Обещание не ослаблено, а разделено на
     два — сколько файлов у цели и сколько из них МОДУЛЬ. */
  assert.deepEqual(печать.get("js").файлы, ["mesto_vstavki.js", "flang_cli.js"], "у JS модуль и прогонщик рядом")
  assert.equal(
    печать.get("js").файлы.filter((п) => !п.endsWith("flang_cli.js")).length,
    1,
    "сам модуль JS обязан оставаться одним самодостаточным файлом",
  )
  assert.equal(
    [...печать.values()].filter((п) => п.сборка.length > 0).length,
    7,
    "файл сборки печатают семь целей — та самая семёрка, о которой говорит README",
  )
  assert.equal(печать.get("js").сборка.length, 0, "у JS файла сборки нет: он и не обещан")
  /* Манифест — файл, который не Makefile и не исходник цели. Их ровно три, и
     README называет их поимённо. */
  assert.deepEqual(
    [...печать.values()].flatMap((п) => п.манифесты).sort(),
    ["Cargo.toml", "flang.csproj", "go.mod"],
  )
})

test("сторож ЛОВИТ разошедшуюся скобку таблицы стоимостей — на одну цель", () => {
  /* Настоящее расхождение, из-за которого сторож и заведён: скобка называла C и
     Rust, а срезом берёт ещё и Go. */
  const срезом = СТОИМОСТЬ_ХВОСТА.filter((з) => з.класс === "срез").map((з) => з.цель).sort()
  assert.deepEqual(срезом, ["C", "Go", "Rust"])
  assert.deepEqual(целиИсключения("копия суффикса (срез без копии в C и Rust)").sort(), ["C", "Rust"])
  assert.notDeepEqual(целиИсключения("копия суффикса (срез без копии в C и Rust)").sort(), срезом)
  /* И она же, верная, сходится. */
  assert.deepEqual(целиИсключения("копия суффикса (срез без копии в C, Go и Rust)").sort(), срезом)
})

test("разбор скобки не путает `C` внутри `C#`", () => {
  /* Голый поиск подстроки нашёл бы `C` в `C#` и назвал бы цель, которой в
     скобке нет. Улика — скобка, где стоит только `C#`. */
  assert.deepEqual(целиИсключения("копия суффикса (срез без копии в C#)"), ["C#"])
  assert.deepEqual(целиИсключения("копия суффикса (срез без копии в C# и Go)").sort(), ["C#", "Go"])
})

test("строка таблицы про `хвост` читается из настоящей спецификации", () => {
  const строка = строкаХвоста(прочитать("flang/SPEC.md"))
  assert.notEqual(строка, null, "строки про `хвост` в таблице стоимостей нет")
  assert.match(строка.elixir, /даром/u, "колонка Elixir перестала обещать бесплатный хвост")
  assert.deepEqual(
    целиИсключения(строка.общая).sort(),
    СТОИМОСТЬ_ХВОСТА.filter((з) => з.класс === "срез").map((з) => з.цель).sort(),
  )
})

test("каждая улика стоимости — настоящий кусок настоящего рантайма", () => {
  assert.equal(СТОИМОСТЬ_ХВОСТА.length, 8, "целей и вычислитель — восемь записей")
  for (const запись of СТОИМОСТЬ_ХВОСТА) {
    const исходник = прочитать(запись.файл)
    assert.ok(
      исходник.includes(запись.улика),
      `${запись.цель}: в ${запись.файл} больше нет «${запись.улика}» — реализация сменилась, таблицу стоимостей надо пересмотреть`,
    )
    assert.ok(["срез", "копия"].includes(запись.класс))
  }
})

test("сторож ЛОВИТ ПРОПАВШЕЕ обещание, а не молчит на нём", () => {
  /* Сторож, стерегущий фразу, тише всего умирает от того, что фразу переписали.
     Проверяется прямо: каждый образец обязан находиться в своём файле СЕЙЧАС, а
     нарочно испорченный — не находиться. */
  for (const обещание of ОБЕЩАНИЯ) {
    const текст = прочитать(обещание.файл)
    assert.ok(обещание.образец.test(текст), `${обещание.файл}: образец «${обещание.что}» больше не находится`)
    assert.equal(
      обещание.образец.test(текст.replace(обещание.образец, "— обещание отсюда убрали —")),
      false,
      `${обещание.файл}: образец «${обещание.что}» находится даже в тексте, из которого фразу вырезали`,
    )
  }
  for (const запись of МАНИФЕСТЫ) {
    const текст = прочитать(запись.файл)
    assert.ok(запись.образец.test(текст), `${запись.файл}: скобка с манифестами больше не находится`)
  }
})

test("обещания стоят в ОБОИХ README, а не в одном", () => {
  /* Русский и английский README расходились уже не раз, и расходились молча:
     правку вносили в один. Здесь обязаны быть покрыты оба. */
  const файлы = new Set(ОБЕЩАНИЯ.map((о) => о.файл))
  assert.deepEqual([...файлы].sort(), ["README.md", "README.ru.md"])
  const русских = ОБЕЩАНИЯ.filter((о) => о.файл === "README.ru.md").length
  const английских = ОБЕЩАНИЯ.filter((о) => о.файл === "README.md").length
  assert.equal(русских, английских, "обещаний в двух README поровну — иначе одно перевели, а другое нет")
})
