test("«журнал: false» убирает журнал и не трогает ничего больше", async () => {
  /*
   * Журнал доставок — НАБЛЮДЕНИЕ, и в рабочем режиме оно не нужно, а платится за
   * него памятью на каждом пробеге. Проверяются обе половины, и вторая важнее
   * первой.
   *
   *   1. Журнала нет: поля «журнал» в итоге НЕТ ВОВСЕ. Пустой список означал бы
   *      «пробегов не было» — и сверка из теста 1, сравнив пустоту с пустотой,
   *      промолчала бы вместо того, чтобы покраснеть.
   *   2. Всё остальное побитово то же самое: исход, состояния, живые, отказы,
   *      решения, время, пробегов. Признак, который меняет наблюдаемое, был бы не
   *      выключателем наблюдения, а вторым планировщиком.
   */
  let пар = 0
  for (const имя of ПРОГРАММЫ) {
    const программа = разобрать(имя)
    const { модуль } = await загрузить(имя, программа)
    for (const прогон of программа.runs) {
      for (const семя of [0, 1, 17]) {
        const сЖурналом = модуль.concRun(прогон.name, { семя })
        const безЖурнала = модуль.concRun(прогон.name, { семя, журнал: false })
        assert.ok(Array.isArray(сЖурналом.журнал), `${имя}/${прогон.name}/${семя}: журнал обязан быть по умолчанию`)
        assert.equal(
          Object.hasOwn(безЖурнала, "журнал"),
          false,
          `${имя}/${прогон.name}/${семя}: с «журнал: false» поля «журнал» быть не должно вовсе`,
        )
        assert.equal(итогом({ ...безЖурнала, журнал: [] }), итогом({ ...сЖурналом, журнал: [] }))
        пар += 1
      }
    }
  }
  assert.ok(пар >= 30, `пар слишком мало: ${пар}`)
})

