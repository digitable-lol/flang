  assert.match(текст, /имя: "два прибавления и доклад"/u)
  assert.match(текст, /export function concRun\(имя, настройки = \{\}\) \{/u)
  /* Тотальному обработчику запас витков не ставится: завершение доказано. */
  assert.match(текст, /тотальный: true,\n\s+запас: 0,/u)

  const безПроцессов = emitJs(parse(readFileSync(`${stdlib}optional.flang`, "utf8"), "optional.flang"))
  const один = безПроцессов.files.map((файл) => файл.content).join("")
  for (const примета of ["$conc", "$concПрогон", "concRun", "$КОНК_"]) {
    assert.ok(
      !один.includes(примета),
      `программе без процессов планировщик не нужен, а в напечатанном есть «${примета}»: ` +
        "планировщик обязан стоить ноль байт там, где процессов нет",
    )
  }

  /* А вот счётчик витков ноль байт не стоит нигде, и это не оговорка, а вторая
     половина обещания: без него незавершающаяся функция в ОБЫЧНОЙ программе
     вращалась бы вечно, а не отказывала (`emit-js.test.mjs`, «нехвостовая
     рекурсия глубже предела…»). Цена его измерена и объявлена отдельно от
     планировщика.

     Проверяется здесь то, что легко потерять при слиянии двух работ: счётчик
     ОДИН — тот же и в обычной программе, и в конкурентной. Два прибора означали
     бы два разных числа предела в одном модуле: тот же обработчик отказал бы по
     одному, досчитав по другому. Считается место, где виток ПРИБАВЛЯЕТСЯ: оно
     обязано быть ровно одно. */
  const счётчиков = (напечатанное) => (напечатанное.match(/\$steps \+= 1/gu) ?? []).length
