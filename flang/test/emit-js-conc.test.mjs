/**
 * Печать конкурентности flang → JavaScript: планировщик внутри напечатанного
 * модуля (`flang/src/emit/js/flang_conc.js`).
 *
 * ── Чем эта сверка отличается от сверки с BEAM ──────────────────────────────
 *
 * У Elixir (`emit-elixir-conc.test.mjs`) сверять побайтово нечем: семени у BEAM
 * нет, чередование выбирает её планировщик, и всё, что там можно потребовать, —
 * «исход с машины лежит в множестве исходов эталона». Здесь возвращается
 * ИСХОДНОЕ требование контракта (`flang/conc/SPEC.md`, «Что проверяется и чем»,
 * пункт 2), и целиком, ровно как у C: планировщик принимает семя, и на одном и
 * том же семени он обязан выдать ПОБАЙТОВО тот же журнал доставок, что эталон.
 * Сравнивается на каждом семени сетки:
 *
 *   время | процесс | исход пробега | код отказа | доставленное сообщение
 *
 * Сообщение в журнале — не украшение: без него совпали бы и два планировщика,
 * которые по-разному переставляют ящик, но одинаково выбирают процесс. Ровно это
 * и ловит «отложить» в `mailbox.flang`.
 *
 * Сверх журнала сверяется итог: исход программы, состояния всех процессов, кто
 * жив, какие были отказы, какие решения принял надзор, виртуальное время и число
 * пробегов.
 *
 * ── Какие программы сверяются и почему помеченные ───────────────────────────
 *
 * ВСЕ примеры каталога, и берутся они из каталога, а не из списка. Список стоял
 * руками, `measure.flang` в него не попал, и шестой вид отказа (`FLANG_MEASURE`)
 * не сверялся с эталоном ни у одной цели печати.
 *
 * Разбираются они ПОМЕЧЕННЫМИ отметкой меры — той же, какую кладёт передний край
 * на каждую команду, включая `emit` (`bin/flang.mjs`, `markMeasure`). Сторожа по
 * этой отметке ставит понижение (`defunc.mjs`, `guardDescent`) до того, как
 * бэкенд напечатает хоть байт, поэтому печать от голого разбора — это печать
 * программы БЕЗ сторожей вовсе. Измерено: в `emitJs(parse(measure.flang))` слово
 * `FLANG_MEASURE` встречается ноль раз, в помеченной — три.
 *
 * ── Почему эта цель дешевле остальных, и чем за это платится ────────────────
 *
 * Эталон УЖЕ на JavaScript, поэтому планировщик здесь — перенос эталона на
 * представление значений напечатанного модуля, а не второе проектирование.
 * Платится за это одним: витки считаются не тем же прибором, что у эталона.
 * Виток эталона — итерация его машины, виток напечатанного модуля — вход в
 * функцию, способную к рекурсии, оборот хвостового цикла и шаг батута, то есть
 * в точности то же, что в C (`fl_tick`). Витков поэтому МЕНЬШЕ, эталон упирается
 * в запас первым, и расхождение одностороннее: напечатанное не объявит
 * исчерпанным то, что эталон досчитал. Измерено и прибито отдельным тестом ниже.
 *
 * Прибор при этом ОДИН на весь модуль: планировщик не приносит своего счётчика,
 * а ставит предел общему счётчику витков (`$step`, `emit/js.mjs`) на время
 * пробега и читает его показание. Два счётчика в одном модуле означали бы два
 * разных числа предела — обработчик отказал бы по одному прибору, досчитав по
 * другому, — и ниже это прибито проверкой: место, где виток прибавляется, ровно
 * одно, и в обычной программе, и в конкурентной.
 *
 * ── Почему тулчейн не нужен и почему модуль загружается из data: ────────────
 *
 * Цель — JavaScript, а проверка идёт на нём же: напечатанный модуль
 * импортируется прямо в этот прогон. Загружается он из `data:`-URL, а не из
 * файла в каталоге, и это не экономия на уборке: так проверяется заодно и
 * обещание шапки модуля — «самодостаточен, ни одной зависимости». Модуль,
 * которому нужен сосед по каталогу, из `data:` не загрузится вовсе.
 *
 * Запуск: node --test flang/test/emit-js-conc.test.mjs
 */
