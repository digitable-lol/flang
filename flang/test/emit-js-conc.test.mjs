/* ══════════ 4. единственное измеренное расхождение: единица запаса ══════════ */

test("запас витков считается в СВОИХ единицах, и расхождение одностороннее", async (t) => {
  /* Побайтовое совпадение журналов держится везде, кроме одного места, и место
     это надо не прятать, а прибить проверкой. Виток эталона — итерация его
     машины; виток напечатанного (`$step`) — вход в функцию, способную к
     рекурсии, оборот хвостового цикла и шаг батута, то есть та же единица, что у
     C. Витков всегда МЕНЬШЕ, значит эталон упирается в предел первым, и
     расхождение одностороннее: напечатанное не объявит исчерпанным то, что
     эталон досчитал.

     Измерено при `с запасом 2000 витков`: эталон успевает на длине 140,
     напечатанный JavaScript — на 1999 (виток на вход в «крутить» плюс оборот
     цикла на каждый шаг: 1 + 1999 витков = 2000). Здесь берутся ТРИ точки: до границы эталона
     (оба досчитали), между границами (эталон отказал, напечатанное досчитало) и
     за границей напечатанного (отказали оба). Если единицы когда-нибудь
     сойдутся, средняя точка покраснеет — и это правильно: расхождение придётся
     измерить заново, а не переписать про него абзац. */
  const источник = readFileSync(`${примеры}budget.flang`, "utf8")
    .replace(/\n {2}дано «Разборщик» принимает \(вариант «бесконечный»\)/u, "")
  const наДлине = async (длина) => {
    const текст = источник
      .replace(/дано «Разборщик» принимает \(вариант «короткий» с «длина» равным 5\)/u,
               `дано «Разборщик» принимает (вариант «короткий» с «длина» равным ${длина})`)
      .replace(/ожидается «Разборщик» равен \(запись «Разбор» с «сделано» равным 1\)/u,
               `ожидается «Разборщик» равен (запись «Разбор» с «сделано» равным ${длина + 1})`)
    const программа = разобратьТекст(текст, `budget-${длина}.flang`)
    const { модуль } = await загрузить(`budget-${длина}`, программа)
    const эталон = runConcurrent(программа, { ...программа.runs[0], seed: 1 })
    const напечатанное = модуль.concRun(программа.runs[0].name, { семя: 1 })
    return {
      эталон: эталон.журнал[0].исход,
      витковЭталона: эталон.витки[0],
      напечатанное: напечатанное.журнал[0].исход,
      витковНапечатанного: напечатанное.витки[0],
    }
  }

  const до = await наДлине(100)
  assert.equal(до.эталон, "обработано", "на длине 100 эталон обязан досчитать")
  assert.equal(до.напечатанное, "обработано", "на длине 100 напечатанное обязано досчитать")

  const между = await наДлине(400)
  assert.equal(между.эталон, "запас исчерпан", "на длине 400 эталон обязан упереться в запас")
  assert.equal(между.напечатанное, "обработано", "у напечатанного витки крупнее: на длине 400 он обязан досчитать")

  const за = await наДлине(2500)
  assert.equal(за.эталон, "запас исчерпан", "на длине 2500 эталон обязан упереться в запас")
  assert.equal(за.напечатанное, "запас исчерпан", "запас обязан работать и в напечатанном — иначе он бы ЗАВИС")

  /* И то, из чего односторонность следует: на всех трёх точках витков у
     напечатанного меньше, чем у эталона, а не «примерно столько же». */
  for (const точка of [до, между, за]) {
    assert.ok(
      точка.витковНапечатанного <= точка.витковЭталона,
      `витков у напечатанного (${точка.витковНапечатанного}) больше, чем у эталона ` +
        `(${точка.витковЭталона}) — расхождение перестало быть односторонним`,
    )
  }
  t.diagnostic(
    `витков на пробег: длина 100 — эталон ${до.витковЭталона}, JS ${до.витковНапечатанного}; ` +
      `длина 400 — эталон ${между.витковЭталона}, JS ${между.витковНапечатанного}; ` +
      `длина 2500 — эталон ${за.витковЭталона}, JS ${за.витковНапечатанного}`,
  )
})

