/*
 * Лицензионное уведомление в НАПЕЧАТАННОМ коде — по всем восьми целям.
 *
 * ── Зачем этот тест отдельно от `scripts/check-licensing.mjs` ──────────────
 *
 * Гейт смотрит на файлы в дереве. Он отвечает на вопрос «несёт ли наш исходник
 * шапку» и ничего не знает о том, доезжает ли эта шапка до чужой программы.
 * А доехать она обязана: рантаймы бэкендов печатаются в чужой каталог БАЙТ В
 * БАЙТ, получатель распространяет их дальше уже как часть своего исходника, и
 * пункт 1 BSD-2-Clause требует сохранять уведомление именно при таком
 * распространении. Между «шапка есть в репозитории» и «шапка есть у
 * получателя» стоит печать, и сломать её может любая правка бэкенда:
 * достаточно научиться срезать ведущий комментарий или собирать рантайм из
 * кусков.
 *
 * ── Где проходит граница ──────────────────────────────────────────────────
 *
 * Уведомление стоит на НАШЕМ коде и только на нём. Файл, в который переведена
 * программа пользователя, — его файл, а не наш, и нашего копирайта на нём быть
 * не должно. Так же поступают bison, flex и tree-sitter. Граница проверяется в
 * обе стороны: рантайм обязан нести шапку, перевод программы обязан её не
 * нести. Иначе «поставить везде» выглядело бы починкой ровно до первого юриста.
 *
 * ── Как отличается наше от пользовательского ──────────────────────────────
 *
 * Не списком имён, а признаком: напечатанный файл считается нашим, если внутри
 * него лежит содержимое файла из `flang/src/emit/<цель>/`. Это ровно то
 * определение, из которого следует требование: наш он потому, что скопирован
 * из нашего дерева. Список имён пришлось бы править при каждом переименовании,
 * и первое же забытое имя превратило бы проверку в тишину.
 */

import assert from "node:assert/strict"
import { readdirSync, readFileSync } from "node:fs"
import { test } from "node:test"
import { fileURLToPath } from "node:url"

import { parse } from "../src/parser.mjs"
import { emitC } from "../src/emit/c.mjs"
import { emitRust } from "../src/emit/rust.mjs"
import { emitGo } from "../src/emit/go.mjs"
import { emitJava } from "../src/emit/java.mjs"
import { emitCsharp } from "../src/emit/csharp.mjs"
import { emitElixir } from "../src/emit/elixir.mjs"
import { emitPython } from "../src/emit/python.mjs"
import { emitJs } from "../src/emit/js.mjs"

const манифест = JSON.parse(readFileSync(fileURLToPath(new URL("../../package.json", import.meta.url)), "utf8"))
const ЛИЦЕНЗИЯ = манифест.license

const копирайт = /SPDX-FileCopyrightText:\s*\d{4}\s+Digitable/u
const идентификатор = /SPDX-License-Identifier:\s*(\S+)/u

function несётУведомление(текст, чей) {
  assert.match(текст, копирайт, `${чей}: нет строки SPDX-FileCopyrightText`)
  const найден = текст.match(идентификатор)
  assert.ok(найден, `${чей}: нет строки SPDX-License-Identifier`)
  assert.equal(
    найден[1],
    ЛИЦЕНЗИЯ,
    `${чей}: идентификатор ${найден[1]}, а package.json объявляет ${ЛИЦЕНЗИЯ}`,
  )
}

const исходникиЦели = (каталог, суффиксы) => {
  const путь = fileURLToPath(new URL(`../src/emit/${каталог}/`, import.meta.url))
  return readdirSync(путь)
    .filter((имя) => суффиксы.some((суффикс) => имя.endsWith(суффикс)))
    .map((имя) => ({ имя, текст: readFileSync(путь + имя, "utf8") }))
}

const программа = (путь) =>
  parse(readFileSync(fileURLToPath(new URL(путь, import.meta.url)), "utf8"), путь)

const факториал = программа("../examples/rosetta/factorial.flang")
const счётчик = программа("../conc/examples/counter.flang")

/*
 * Восемь целей. `печать` берёт ту программу, при которой цель печатает НАИБОЛЬШЕЕ
 * число наших файлов: у C это программа с процессами и с оболочкой — иначе из
 * шести файлов проверялись бы два.
 *
 * `сборочные` — файлы, которые не код, а инструкция сборщику (Makefile, go.mod,
 * манифест). Границу «наше/пользовательское» на них ставить нечего.
 */
const ЦЕЛИ = [
  { имя: "C", каталог: "c", суффиксы: [".c", ".h"], печать: () => emitC(счётчик, { repl: true }), наших: 6 },
  { имя: "Rust", каталог: "rust", суффиксы: [".rs"], печать: () => emitRust(факториал), наших: 2 },
  { имя: "Go", каталог: "go", суффиксы: [".go"], печать: () => emitGo(факториал), наших: 2 },
  { имя: "Java", каталог: "java", суффиксы: [".java"], печать: () => emitJava(факториал), наших: 6 },
  { имя: "C#", каталог: "csharp", суффиксы: [".cs"], печать: () => emitCsharp(факториал), наших: 6 },
  { имя: "Elixir", каталог: "elixir", суффиксы: [".ex"], печать: () => emitElixir(счётчик), наших: 3 },
  { имя: "Python", каталог: "python", суффиксы: [".py"], печать: () => emitPython(факториал), наших: 2 },
]

const СБОРОЧНЫЕ = /^(Makefile|go\.mod|Cargo\.toml|flang\.csproj|mix\.exs)$/u

test("рантаймы всех восьми целей несут уведомление в дереве", () => {
  let просмотрено = 0
  for (const цель of ЦЕЛИ) {
    const файлы = исходникиЦели(цель.каталог, цель.суффиксы)
    assert.ok(файлы.length > 0, `${цель.имя}: в каталоге рантайма не нашлось ни одного файла`)
    for (const файл of файлы) {
      несётУведомление(файл.текст, `${цель.каталог}/${файл.имя}`)
      просмотрено += 1
    }
  }
  /* JS печатает рантайм не файлом, а куском внутри модуля, поэтому он проверен
     отдельным случаем ниже; здесь его каталог тоже просматривается. */
  for (const файл of исходникиЦели("js", [".js"])) {
    несётУведомление(файл.текст, `js/${файл.имя}`)
    просмотрено += 1
  }
  /* Двадцать восемь — это шесть файлов C, два Rust, два Go, шесть Java, шесть
     C#, три Elixir, два Python и один JS на день правки. Число сторожит не
     количество, а обход: если каталоги перестанут читаться и списки окажутся
     пустыми, проверка выше пройдёт вхолостую и промолчит. */
  assert.ok(просмотрено >= 28, `рантаймов просмотрено ${просмотрено}, а их не меньше двадцати восьми`)
})

for (const цель of ЦЕЛИ) {
  test(`напечатанный ${цель.имя}: уведомление на рантайме и НЕ на переводе программы`, () => {
    const исходники = исходникиЦели(цель.каталог, цель.суффиксы)
    const напечатано = цель.печать()

    let наших = 0
    let пользовательских = 0
    for (const файл of напечатано.files) {
      const имя = файл.path.split("/").pop()
      const наш = исходники.some((исходник) => файл.content.includes(исходник.текст.trimEnd()))
      if (наш) {
        несётУведомление(файл.content, `печать ${цель.имя}: ${файл.path}`)
        наших += 1
        continue
      }
      if (СБОРОЧНЫЕ.test(имя)) continue
      assert.doesNotMatch(
        файл.content,
        копирайт,
        `печать ${цель.имя}: ${файл.path} — это перевод программы пользователя, `
        + "нашего копирайта на нём быть не должно",
      )
      пользовательских += 1
    }

    assert.equal(
      наших,
      цель.наших,
      `печать ${цель.имя}: наших файлов напечатано ${наших}, а ожидалось ${цель.наших} — `
      + "либо рантайм перестал печататься как есть, либо признак «наш» перестал срабатывать",
    )
    assert.ok(
      пользовательских > 0,
      `печать ${цель.имя}: перевода программы в выводе не нашлось — граница проверена вхолостую`,
    )
  })
}

test("напечатанный JavaScript: планировщик приезжает вместе со своим уведомлением", () => {
  /* У JS граница «наше/пользовательское» проходит НЕ ТАК, как у семи остальных,
     и проходит она двумя разными способами сразу.

     Файлом наш код уезжает один — прогонщик (`flang/src/emit/js/flang_cli.js`),
     и с ним всё как у прочих целей: он копируется как есть и обязан нести
     уведомление. А рантайм и планировщик конкурентности отдельным файлом не
     печатаются вовсе — они попадают ВНУТРЬ модуля программы, и уведомление на
     них проверяется внутри него.

     Отсюда и проверка «а на переводе программы копирайта нет» смотрит на МОДУЛЬ,
     а не на весь вывод: прогонщик рядом с ним — наш файл, и требовать от него
     молчания значило бы требовать нарушения. */
  const модуль = (программа) => {
    const файлы = emitJs(программа).files.filter((файл) => файл.path !== "flang_cli.js")
    assert.equal(файлы.length, 1, `перевода программы ожидался один файл, а их ${файлы.length}`)
    return файлы[0].content
  }

  /* Прогонщик — наш файл, и он обязан нести уведомление у обеих программ. */
  for (const [имя, программа] of [["с процессами", счётчик], ["без процессов", факториал]]) {
    const прогонщик = emitJs(программа).files.find((файл) => файл.path === "flang_cli.js")
    assert.ok(прогонщик !== undefined, `печать JavaScript (${имя}): прогонщик не напечатан`)
    несётУведомление(прогонщик.content, `печать JavaScript (${имя}): flang_cli.js`)
  }

  несётУведомление(модуль(счётчик), "печать JavaScript: модуль с процессами")

  assert.doesNotMatch(
    модуль(факториал),
    копирайт,
    "печать JavaScript: у программы без процессов нашего кода в модуле нет, значит нет и повода ставить копирайт",
  )
})
