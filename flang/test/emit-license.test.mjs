/*
 * Лицензионное уведомление в НАПЕЧАТАННОМ коде.
 *
 * ── Зачем этот тест отдельно от `scripts/check-licensing.mjs` ──────────────
 *
 * Гейт смотрит на файлы в дереве. Он отвечает на вопрос «несёт ли наш исходник
 * шапку» и ничего не знает о том, доезжает ли эта шапка до чужой программы.
 * А доехать она обязана: рантаймы бэкендов печатаются в чужой каталог БАЙТ В
 * БАЙТ, получатель распространяет их дальше уже как часть своего исходника, и
 * пункт 1 BSD-2-Clause требует сохранять уведомление именно при таком
 * распространении. Между «шапка есть в репозитории» и «шапка есть у
 * получателя» стоит печать, и сломать её может любая правка бэкенда: достаточно
 * научиться срезать ведущий комментарий или собирать рантайм из кусков.
 *
 * ── Где проходит граница ──────────────────────────────────────────────────
 *
 * Уведомление стоит на НАШЕМ коде и только на нём. Файл, в который переведена
 * программа пользователя, — его файл, а не наш, и нашего копирайта на нём быть
 * не должно. Так же поступают bison, flex и tree-sitter. Граница проверяется в
 * обе стороны: рантайм обязан нести шапку, перевод программы обязан её не
 * нести. Иначе «поставить везде» выглядело бы починкой ровно до первого
 * юриста.
 *
 * ── Набор проверяемых файлов ──────────────────────────────────────────────
 *
 * Печатаемые рантаймы берутся ОБХОДОМ каталогов `flang/src/emit/{c,rust,js}`,
 * а не списком имён. Новый файл рантайма, положенный рядом без шапки, падает
 * здесь, а не становится первым непомеченным — так же, как в гейте.
 */

import assert from "node:assert/strict"
import { readdirSync, readFileSync } from "node:fs"
import { test } from "node:test"
import { fileURLToPath } from "node:url"

import { parse } from "../src/parser.mjs"
import { emitC } from "../src/emit/c.mjs"
import { emitRust } from "../src/emit/rust.mjs"
import { emitJs } from "../src/emit/js.mjs"

const манифест = JSON.parse(readFileSync(fileURLToPath(new URL("../../package.json", import.meta.url)), "utf8"))
const ЛИЦЕНЗИЯ = манифест.license

const копирайт = /SPDX-FileCopyrightText:\s*\d{4}\s+Digitable/u
const идентификатор = /SPDX-License-Identifier:\s*(\S+)/u

function несётУведомление(текст, чей) {
  assert.match(текст, копирайт, `${чей}: нет строки SPDX-FileCopyrightText`)
  const найден = текст.match(идентификатор)
  assert.ok(найден, `${чей}: нет строки SPDX-License-Identifier`)
  assert.equal(
    найден[1],
    ЛИЦЕНЗИЯ,
    `${чей}: идентификатор ${найден[1]}, а package.json объявляет ${ЛИЦЕНЗИЯ}`,
  )
}

/* ────────────────── 1. рантаймы в дереве ────────────────── */

const РАНТАЙМЫ = { c: [".c", ".h"], rust: [".rs"], js: [".js"] }

test("печатаемые рантаймы всех трёх бэкендов несут уведомление в дереве", () => {
  let просмотрено = 0
  for (const [цель, суффиксы] of Object.entries(РАНТАЙМЫ)) {
    const каталог = fileURLToPath(new URL(`../src/emit/${цель}/`, import.meta.url))
    const файлы = readdirSync(каталог).filter((имя) => суффиксы.some((суффикс) => имя.endsWith(суффикс)))
    assert.ok(файлы.length > 0, `${цель}: в каталоге рантайма не нашлось ни одного файла`)
    for (const имя of файлы) {
      несётУведомление(readFileSync(каталог + имя, "utf8"), `${цель}/${имя}`)
      просмотрено += 1
    }
  }
  /* Девять — это шесть файлов C, два Rust и один JS на день правки. Число
     сторожит не количество, а обход: если каталог перестанет читаться и список
     окажется пустым, проверка выше пройдёт вхолостую. */
  assert.ok(просмотрено >= 9, `рантаймов просмотрено ${просмотрено}, а их не меньше девяти`)
})

/* ────────────────── 2. уведомление доезжает до печати ────────────────── */

const скобки = parse(
  readFileSync(fileURLToPath(new URL("../examples/rosetta/factorial.flang", import.meta.url)), "utf8"),
  "factorial.flang",
)
const счётчик = parse(
  readFileSync(fileURLToPath(new URL("../conc/examples/counter.flang", import.meta.url)), "utf8"),
  "counter.flang",
)

/** Файлы печати, которые являются НАШИМ кодом, скопированным как есть. */
const НАШИ_C = new Set([
  "flang_runtime.c", "flang_runtime.h",
  "flang_conc.c", "flang_conc.h",
  "flang_cli.c", "flang_repl.c",
])
const НАШИ_RUST = new Set(["src/runtime.rs", "src/cli.rs"])

test("напечатанный C: уведомление стоит на рантайме и не стоит на переводе программы", () => {
  /* Программа с процессами и с оболочкой — так печатаются ВСЕ шесть наших
     файлов сразу, а не два из шести. */
  const напечатано = emitC(счётчик, { repl: true })
  const пути = напечатано.files.map((файл) => файл.path)
  for (const имя of НАШИ_C) {
    assert.ok(пути.includes(имя), `${имя} не напечатался — сетка проверки перестала быть полной`)
  }

  for (const файл of напечатано.files) {
    if (НАШИ_C.has(файл.path)) {
      несётУведомление(файл.content, `печать C: ${файл.path}`)
      continue
    }
    if (файл.path === "Makefile") continue
    assert.doesNotMatch(
      файл.content,
      копирайт,
      `печать C: ${файл.path} — это перевод программы пользователя, нашего копирайта на нём быть не должно`,
    )
  }
})

test("напечатанный Rust: уведомление стоит на рантайме и не стоит на переводе программы", () => {
  const напечатано = emitRust(скобки)
  const пути = напечатано.files.map((файл) => файл.path)
  for (const имя of НАШИ_RUST) {
    assert.ok(пути.includes(имя), `${имя} не напечатался — сетка проверки перестала быть полной`)
  }

  for (const файл of напечатано.files) {
    if (НАШИ_RUST.has(файл.path)) {
      несётУведомление(файл.content, `печать Rust: ${файл.path}`)
      continue
    }
    if (файл.path === "Makefile" || файл.path === "Cargo.toml") continue
    assert.doesNotMatch(
      файл.content,
      копирайт,
      `печать Rust: ${файл.path} — это перевод программы пользователя, нашего копирайта на нём быть не должно`,
    )
  }
})

test("напечатанный JavaScript: планировщик приезжает вместе со своим уведомлением", () => {
  /* У JS рантайм отдельным файлом не печатается: единственный кусок нашего
     кода, уезжающий как есть, — планировщик конкурентности, и он попадает
     ВНУТРЬ модуля программы. Значит и уведомление проверяется внутри него. */
  const сПроцессами = emitJs(счётчик)
  const модуль = сПроцессами.files.map((файл) => файл.content).join("\n")
  несётУведомление(модуль, "печать JavaScript: модуль с процессами")

  const безПроцессов = emitJs(скобки).files.map((файл) => файл.content).join("\n")
  assert.doesNotMatch(
    безПроцессов,
    копирайт,
    "печать JavaScript: у программы без процессов нашего кода в выводе нет, значит нет и повода ставить копирайт",
  )
})
