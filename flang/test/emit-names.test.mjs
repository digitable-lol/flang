/**
 * Два объявления с одним именем — общая проверка ВСЕХ целей печати.
 *
 * 7 августа 2026 года main покраснел на `go vet`:
 *
 *     flang/vysshiy_poryadok.go:125:6: Udvoit redeclared in this block
 *         flang/vysshiy_poryadok.go:31:6: other declaration of Udvoit
 *
 * — и так тринадцать раз на пятьдесят три функции. Печатался
 * `flang/stdlib/higher-order.flang`: первая программа репозитория, которую
 * переписывает дефункционализация (`src/defunc.mjs`). Тег функции она объявляет
 * ВАРИАНТОМ ТОГО ЖЕ ИМЕНИ — «Удвоить» становится и функцией, и вариантом, — а
 * бэкенд Go давал обоим один идентификатор `Udvoit`.
 *
 * ── Почему этого никто не заметил раньше ────────────────────────────────────
 *
 * Заметить было нечем на машине без тулчейна. Печать шла молча и выглядела
 * правильной; отказывал только настоящий компилятор Go — то есть ТОЛЬКО в той
 * джобе CI, где Go установлен. Проверка, которая срабатывает лишь там, где есть
 * тулчейн, — это не проверка, а лотерея: разработчик без Go получает зелёный
 * набор на коде, который не собирается.
 *
 * Поэтому проверка здесь НЕ СОБИРАЕТ НИЧЕГО. Она читает напечатанное и требует
 * от него свойства, которое видно на любой машине: два разных объекта модели не
 * имеют права получить один идентификатор.
 *
 * ── Почему проверка общая, а не в бэкенде Go ───────────────────────────────
 *
 * Совпадение имени функции и имени варианта в модели ЗАКОННО — пространства
 * имён у них разные (`flang/cat/HOF.md`, решение 2), — и дефункционализация
 * строит такие программы сама, на каждую функцию, взятую значением. Значит это
 * не особенность Go, а требование ко всем восьми целям сразу, и семь из них его
 * выполняли по-разному: C печатает `…_variant_chyotnoe` против `…_chyotnoe`,
 * Rust — `variant_chyotnoe` против `funkciya_chyotnoe`, C#, Java, Python и
 * Elixir — приставки роли (`V`/`Fn`, `v_`/`fn_`), JS — регистр (`Chyotnoe`
 * против `chyotnoe`). Go не делал ничего.
 *
 * Проверка на одну цель ловит только те цели, о которых кто-то вспомнил.
 * Поэтому перебор идёт ПО РЕЕСТРУ ЦЕЛЕЙ — по самому каталогу `flang/src/emit`
 * (`emitTargets()`), тому же, по которому работает `flang emit --target`, — и
 * девятая цель попадает под проверку тем, что её модуль положили в каталог.
 * Образца объявлений у новой цели не будет, и тест об этом СКАЖЕТ, а не
 * промолчит: списка, который можно забыть пополнить, здесь нет.
 *
 * ── Как отличить объявление от всего остального, не разбирая целевой язык ───
 *
 * Никак — и не надо. Считаются строки, которые вводят имя (`func X(`, `def x(`,
 * `pub fn x(`, `public static Value x(`, …), а от грубости этого приёма
 * страхуют две вещи.
 *
 * Первая: НИЖНЯЯ ГРАНИЦА. Объявлений, пришедших из модели, обязано найтись не
 * меньше, чем в модели функций. Образец, переставший совпадать после правки
 * бэкенда, обрушит эту границу — то есть тест покраснеет, а не станет тихо
 * проверять пустоту. Тест, который ничего не нашёл и потому доволен, — это
 * ровно та беда, из-за которой красный main и случился.
 *
 * Вторая: СВОИ ИМЕНА БЭКЕНДА исключаются не списком, а измерением. Та же цель
 * печатает модуль БЕЗ ЕДИНОГО объявления модели, и всё, что нашлось там, —
 * рантайм, прогонщик, диспетчер `Call`, — вычитается. Так из-под проверки
 * уходят и многотельные функции Elixir (`def call(…)` на каждое имя — это одна
 * функция с восемью телами, а не восемь объявлений), и прототип рядом с
 * определением в C, и никакого перечня исключений вести не приходится.
 *
 * ── Три программы, и третья отвечает не так, как первые две ────────────────
 *
 *   1. `flang/stdlib/higher-order.flang` — тот самый модуль, на котором CI и
 *      покраснел. Печатается всеми восемью, повторов быть не должно.
 *   2. вариант и функция одного имени БЕЗ высшего порядка — чтобы было видно,
 *      что беда не в дефункционализации: она лишь первой на неё наступила.
 *      Такая модель законна, печататься обязана, повторов быть не должно.
 *   3. запись «Точка» и функция, которую в модели ТАК И НАЗВАЛИ, «Создать
 *      Точка». Здесь имена совпадают уже после транслитерации, и требовать
 *      печати нельзя: C и JS такую модель ОТВЕРГАЮТ, называя оба имени, и это
 *      правильный ответ. Неправильный ровно один — напечатать два объявления и
 *      промолчать. Так до этой правки делал только Go.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { test } from "node:test"

import { emitTargets, loadEmitter } from "../bin/flang.mjs"
import { parse } from "../src/parser.mjs"

/**
 * Строка, вводящая имя в пространство имён файла, — по одному образцу на цель.
 *
 * Образцы нарочно грубые: точный разбор восьми целевых языков стоил бы дороже
 * самой проверки и сам стал бы источником ошибок. Точности здесь и не нужно —
 * нужна полнота, и её стережёт нижняя граница (см. шапку).
 */
const ОБЪЯВЛЕНИЕ = {
  c: /^(?:static\s+)?[A-Za-z_][A-Za-z0-9_]*(?:\s+\*?|\s*\*\s*)([A-Za-z_][A-Za-z0-9_]*)\s*\(/u,
  csharp:
    /^\s*(?:public|private|internal|protected)\s+(?:static\s+)?[A-Za-z_][A-Za-z0-9_.<>[\]]*\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/u,
  elixir: /^\s*defp?\s+([a-z_][A-Za-z0-9_?!]*)\s*\(/u,
  go: /^func\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/u,
  java: /^\s*(?:public|private|protected)\s+(?:static\s+)?(?:final\s+)?[A-Za-z_][A-Za-z0-9_.<>[\]]*\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/u,
  js: /^export\s+function\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*\(/u,
  python: /^def\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/u,
  rust: /^(?:pub\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/u,
}

/** Модуль без единого объявления модели: всё найденное в нём — своё у бэкенда. */
const ПУСТО = "модуль «Столкновение имён»\n"

/* Вариант и функция одного имени — без единой функции-значения. Показывает, что
   беда не в дефункционализации: она только первой на неё наступила. */
const ОДНО_ИМЯ = `модуль «Столкновение имён»

тип «Цвет»
  вариант «Красный»
  вариант «Синий»

тотальная функция «Красный»
  принимает х: число
  возвращает число
  х плюс 1

тотальная функция «Оттенок»
  принимает х: число
  возвращает «Цвет»
  вариант «Красный»
`

/* Имя функции, совпадающее с именем фабрики записи ПОСЛЕ транслитерации: у
   записи «Точка» фабрика называется «создать Точка», и модель вправе назвать
   функцию «Создать Точка». Различить их нечем — отказ здесь законен. */
const ИМЯ_ФАБРИКИ = `модуль «Столкновение имён»

объект «Точка»
  сдвиг: число

тотальная функция «Создать Точка»
  принимает х: число
  возвращает число
  х плюс 2
`

/**
 * Объявления напечатанного: имя → сколько раз объявлено, по файлам.
 *
 * Считается по файлам, а не по всей выдаче: у C прототип лежит в заголовке, а
 * определение в теле, и это одно объявление, а не два.
 */
function объявления(цель, напечатанное) {
  const образец = ОБЪЯВЛЕНИЕ[цель]
  assert.ok(
    образец !== undefined,
    `у цели «${цель}» нет образца объявления в flang/test/emit-names.test.mjs — ` +
      "добавьте его: без образца проверка на повтор имён этой цели не смотрит вовсе",
  )
  const по_файлам = new Map()
  const все = new Set()
  for (const файл of напечатанное.files) {
    const счёт = new Map()
    for (const [номер, строка] of файл.content.split("\n").entries()) {
      const совпадение = образец.exec(строка)
      if (совпадение === null) continue
      все.add(совпадение[1])
      if (!счёт.has(совпадение[1])) счёт.set(совпадение[1], [])
      счёт.get(совпадение[1]).push(номер + 1)
    }
    по_файлам.set(файл.path, счёт)
  }
  return { по_файлам, все }
}

/** Повторы среди имён, пришедших ИЗ МОДЕЛИ: свои имена бэкенда вычтены. */
function повторы(печать, свои) {
  const найдено = []
  for (const [путь, счёт] of печать.по_файлам) {
    for (const [имя, строки] of счёт) {
      if (строки.length > 1 && !свои.has(имя)) найдено.push(`${путь}:${строки.join(",")} — «${имя}»`)
    }
  }
  return найдено
}

const ВЫСШИЙ_ПОРЯДОК = readFileSync(new URL("../stdlib/higher-order.flang", import.meta.url), "utf8")

const цели = await emitTargets()

test("цели печати вообще нашлись", () => {
  /* Реестр пуст — значит перебор ниже прошёл вхолостую и «все восемь целей
     чисты» означало бы «ни одной цели не проверено». */
  assert.ok(цели.length >= 8, `целей печати найдено ${цели.length}, ожидалось не меньше восьми`)
})

for (const цель of цели) {
  const модели = [
    { имя: "stdlib «Высший порядок» (тег и функция одного имени)", исходник: ВЫСШИЙ_ПОРЯДОК },
    { имя: "вариант и функция одного имени, без высшего порядка", исходник: ОДНО_ИМЯ },
  ]

  for (const модель of модели) {
    test(`${цель}: ${модель.имя} — ни одного повторного объявления`, async () => {
      const { emit } = await loadEmitter(цель)
      const программа = parse(модель.исходник)
      const свои = объявления(цель, emit(parse(ПУСТО))).все
      const печать = объявления(цель, emit(программа))

      /* Нижняя граница: образец обязан видеть объявления модели. Перестал
         совпадать — тест краснеет здесь, а не молча проверяет пустоту. */
      const из_модели = [...печать.все].filter((имя) => !свои.has(имя))
      assert.ok(
        из_модели.length >= программа.functions.length,
        `в напечатанном для «${цель}» нашлось ${из_модели.length} имён из модели, ` +
          `а функций в модели ${программа.functions.length} — образец объявления перестал совпадать`,
      )

      const повторные = повторы(печать, свои)
      assert.deepEqual(
        повторные,
        [],
        `бэкенд «${цель}» объявил одно имя дважды — в Go это «redeclared in this block», ` +
          `в Python и JS второе определение молча съедает первое:\n${повторные.join("\n")}`,
      )
    })
  }

  test(`${цель}: имя функции совпало с именем фабрики записи — отказ или разные имена, но не молчание`, async () => {
    const { emit } = await loadEmitter(цель)
    let печать
    try {
      печать = объявления(цель, emit(parse(ИМЯ_ФАБРИКИ)))
    } catch (беда) {
      /* Отказ законен — но обязан назвать оба имени, иначе по нему нечего
         чинить в модели. */
      const текст = String(беда?.message ?? беда)
      assert.match(текст, /Точка/u, `отказ цели «${цель}» не называет столкнувшиеся имена: ${текст}`)
      return
    }
    const свои = объявления(цель, emit(parse(ПУСТО))).все
    const повторные = повторы(печать, свои)
    assert.deepEqual(
      повторные,
      [],
      `бэкенд «${цель}» напечатал два объявления с одним именем и промолчал — ` +
        `отказать было можно, промолчать нельзя:\n${повторные.join("\n")}`,
    )
  })
}
