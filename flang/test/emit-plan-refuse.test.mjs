/**
 * Печать программы с объявлением `план` — либо целиком, либо отказом.
 *
 * ── Что здесь стерегут ──────────────────────────────────────────────────────
 *
 * ВОСЕМЬ целей из восьми ТЕРЯЛИ план молча, и это худший из возможных исходов,
 * потому что он выглядит успехом. Замер на `web/shortener/klient.flang`
 * (приложение из 32 тотальных функций, 20 августа 2026):
 *
 *   emit --target js  →  код 0, диагностик 0
 *                     →  67 экспортов напечатано, включая ОБЕ функции плана
 *                     →  объявление «план «Стойка ссылок»»: 0 байт
 *
 * То есть напечатанный модуль умел считать и не умел работать: снаружи это
 * набор функций, про который нельзя узнать, что это программа ввода-вывода,
 * какая функция в ней начальная и какая — шаг.
 *
 * Ровно та же беда была у процессов, и против неё стоит соседний сторож
 * (`emit-conc-refuse.test.mjs`). Этот — его третий брат, и устроен он так же:
 *
 *   • цели берутся из КАТАЛОГА `src/emit`, а не из списка. Девятая цель попадёт
 *     под проверку тем, что появится файл, а не тем, что кто-то вспомнит про
 *     этот тест;
 *   • каждая цель обязана либо напечатать план, либо отказать НАЗВАННЫМ кодом.
 *     Третьего — «напечатать программу без плана» — не бывает;
 *   • строка возможностей (`ВОЗМОЖНОСТИ_ЦЕЛЕЙ[цель].план`) сверяется с
 *     ПОВЕДЕНИЕМ, а не читается как комментарий: обещавшая план обязана его
 *     напечатать, не обещавшая — отказать.
 *
 * ── Почему сверка идёт до ЖУРНАЛА, а не до наличия слова ────────────────────
 *
 * «В выводе есть слово ioPlan» — слабый критерий: он не отличает напечатанный
 * план от напечатанного комментария про план. Поэтому цель, обещавшая план,
 * проверяется прогоном: тот же план, тот же поддельный хозяин, тот же порядок
 * откликов — и журнал поручений напечатанного модуля обязан совпасть с
 * журналом свидетеля (`runPlan` из `src/io.mjs`) ПОБАЙТОВО, вместе с
 * результатом.
 *
 * Запуск: node --test flang/test/emit-plan-refuse.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath, pathToFileURL } from "node:url"

import { emitTargets, loadEmitter } from "../bin/flang.mjs"
import { PLAN_UNSUPPORTED_CODE, ВОЗМОЖНОСТИ_ЦЕЛЕЙ, ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА } from "../src/conc.mjs"
import { runPlan, хозяинПоСписку } from "../src/io.mjs"
import { parse } from "../src/parser.mjs"
import { рабочийКаталог } from "./tempdir.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const читать = (путь) => readFileSync(путь, "utf8")

/** Программа с планом — настоящая, из дерева, а не сочинённая ради теста. */
const ПЛАНОВАЯ = "flang/examples/io/link-report.flang"
const плановая = () => parse(читать(корень + ПЛАНОВАЯ), "link-report.flang")

/** Та же программа без объявления `план`: остаются те же функции, план исчезает. */
const безПлана = () => {
  const программа = плановая()
  return { ...программа, plans: [] }
}

/**
 * Отклики поддельного хозяина по порядку — одни и те же для обеих сторон.
 *
 * Три отклика проводят план по всем трём его поручениям и доводят до ветки
 * «Конец работы»: сверяется и журнал, и результат. Четвёртого отклика нет
 * намеренно — если исполнитель попросит лишнее, обе стороны получат «кончились
 * отклики», и разойтись им будет негде.
 */
const ОТКЛИКИ = [
  { variant: "Прочитано", fields: { содержимое: "http://127.0.0.1:8080/привет\n" } },
  { variant: "Ответ сети", fields: { код: 200, тело: "привет" } },
  { variant: "Записано", fields: { сколько: 42 } },
]

test("у каждой цели каталога есть строка возможностей, и в ней сказано про план", async () => {
  const цели = await emitTargets()
  assert.ok(цели.length >= 8, `целей нашлось ${цели.length} — каталог схлопнулся`)
  for (const цель of цели) {
    const строка = ВОЗМОЖНОСТИ_ЦЕЛЕЙ[цель]
    assert.ok(строка !== undefined, `у цели «${цель}» нет строки возможностей`)
    assert.ok(
      строка.план === "есть" || строка.план === "нет",
      `цель «${цель}» не отвечает про план: ${JSON.stringify(строка.план)}`,
    )
    assert.equal(
      строка.план === "есть",
      ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА.includes(цель),
      `строка возможностей цели «${цель}» разошлась со списком целей с исполнителем плана`,
    )
  }
})

test("каждая цель либо печатает план, либо отказывает — третьего нет", async (t) => {
  const программа = плановая()
  const напечатали = []
  const отказали = new Map()
  for (const цель of await emitTargets()) {
    const { emit } = await loadEmitter(цель)
    try {
      emit(программа, {})
      напечатали.push(цель)
    } catch (ошибка) {
      отказали.set(цель, ошибка.diagnostics?.[0]?.code ?? null)
    }
  }
  t.diagnostic(`план печатают: ${напечатали.join(", ") || "никто"}; отказывают: ${[...отказали.keys()].join(", ")}`)
  assert.deepEqual(напечатали, [...ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА], "напечатали не те цели, что обещали")
  for (const [цель, код] of отказали) {
    assert.equal(код, PLAN_UNSUPPORTED_CODE, `цель «${цель}» отказала кодом «${код}», а не названным`)
  }
  assert.ok(отказали.size > 0, "не отказала ни одна цель — сторож ничего не держит")
})

test("отказ — ПРО ПЛАН, а не про ввод-вывод вообще: без объявления те же цели печатают", async () => {
  /* Снять правку и посмотреть, что покраснеет, — наоборот. Отказ,
     срабатывающий на всякой программе со словарём ввода-вывода, был бы не
     проверкой, а поломкой семи бэкендов: словарь приписывается программе
     разборщиком, а объявление `план` пишет автор. */
  const программа = безПлана()
  for (const цель of await emitTargets()) {
    const { emit } = await loadEmitter(цель)
    const напечатано = emit(программа, {})
    assert.ok(напечатано.files.length > 0, `цель «${цель}» не напечатала программу без плана`)
  }
})

test("цель, обещавшая план, печатает описатель и исполнителя, а не слово про них", async () => {
  const программа = плановая()
  for (const цель of ЦЕЛИ_С_ИСПОЛНИТЕЛЕМ_ПЛАНА) {
    const { emit } = await loadEmitter(цель)
    const текст = emit(программа, {}).files[0].content
    /* Куски взяты ОБЪЯВЛЕНИЯМИ, а не словами, и это стоило одного зелёного
       теста, который ничего не держал: слова «ioPlan» и «ioRun» есть в
       пояснении к самому исполнителю, а он печатается отдельно от описателя.
       Убери описатель — и проверка на слово осталась бы зелёной. Проверка на
       строку `export function ioPlan() {` краснеет. */
    for (const кусок of [
      "const $io = {",
      `      имя: "Сходить по ссылке",`,
      `      состояние: "Ход",`,
      "export function ioPlan() {",
      "export function ioRun(имя, исполнить, настройки = {}) {",
      "async function $ioПрогон($io, имя, исполнить, настройки = {}) {",
    ]) {
      assert.ok(текст.includes(кусок), `цель «${цель}»: в напечатанном нет «${кусок}»`)
    }
    /* Программа без плана те же две двери получать НЕ должна: иначе признак
       «план напечатан» стал бы признаком «модуль напечатан». */
    const без = emit(безПлана(), {}).files[0].content
    for (const кусок of ["const $io = {", "export function ioRun(", "$ioПрогон"]) {
      assert.ok(!без.includes(кусок), `цель «${цель}»: «${кусок}» напечатан программе без плана`)
    }
  }
})

test("журнал поручений напечатанного модуля совпадает со свидетельским побайтово", async (t) => {
  const программа = плановая()
  const { emit } = await loadEmitter("js")

  /* Свидетель: тот же план на интерпретаторе, тот же список откликов. */
  const свидетельский = []
  const свидетельХозяин = хозяинПоСписку(ОТКЛИКИ)
  let свидетельИтог = null
  let свидетельОтказ = null
  try {
    свидетельИтог = await runPlan(программа, "Сходить по ссылке", async (поручение) => {
      свидетельский.push(JSON.stringify({ имя: поручение.variant, поля: поручение.fields }))
      return свидетельХозяин()
    })
  } catch (беда) {
    свидетельОтказ = `${беда.code}: ${беда.message}`
  }
  assert.ok(свидетельский.length > 0, "свидетель не выдал ни одного поручения — сверять нечего")

  const каталог = рабочийКаталог("emit-plan-refuse")
  try {
    const { writeFileSync } = await import("node:fs")
    const { join } = await import("node:path")
    const путь = join(каталог, "modul.js")
    writeFileSync(путь, emit(программа, { cli: false }).files[0].content, "utf8")
    const модуль = await import(pathToFileURL(путь).href)

    const наш = []
    let следующий = 0
    let нашИтог = null
    let нашОтказ = null
    try {
      нашИтог = await модуль.ioRun("Сходить по ссылке", (поручение) => {
        наш.push(JSON.stringify({ имя: поручение.variant, поля: поручение.fields }))
        const отклик = ОТКЛИКИ[следующий]
        следующий += 1
        if (отклик === undefined) return модуль.ioPlan().вариант("Сбой", { код: "FLANG_IO_SCRIPT", сообщение: "у поддельного хозяина кончились отклики" })
        return модуль.ioPlan().вариант(отклик.variant, отклик.fields)
      })
    } catch (беда) {
      нашОтказ = `${беда.code}: ${беда.message}`
    }

    t.diagnostic(`поручений: свидетель ${свидетельский.length}, напечатанный ${наш.length}`)
    assert.deepEqual(наш, свидетельский, "журналы поручений разошлись")
    assert.equal(нашОтказ, свидетельОтказ, "отказ разошёлся со свидетельским")
    assert.deepEqual(
      нашИтог?.значение ?? null,
      свидетельИтог?.значение ?? null,
      "результат плана разошёлся со свидетельским",
    )
  } finally {
    const { rmSync } = await import("node:fs")
    rmSync(каталог, { recursive: true, force: true })
  }
})
