/**
 * ЗАКОН ПЕЧАТИ: `flang emit` не печатает того, что `flang check` того же
 * двоичного отвергает.
 *
 * ── Что было до правки, числом ──────────────────────────────────────────────
 * `emit_file` в `flang/src/emit/c/flang_repl.c` не звал НИ ОДНОЙ проверки: он
 * смотрел диагностики СВЯЗЫВАНИЯ и печатал всё, что связалось. Ни типов, ни
 * завершаемости, ни ядра доказательств. `flang check` того же двоичного те же
 * программы отвергал — то есть два входа одного бинарника выносили разные
 * вердикты об одном файле, и опасен именно этот разрыв: неумение видно,
 * расхождение — нет.
 *
 * Замер 20 августа 2026 по программам дерева, все команды настоящие и
 * процессом: свидетель на Node отказался печатать 59 программ, и ВСЕ 59
 * двоичный печатал — кодом 0 и шестью файлами C на каждую. Почти половина —
 * ложные ДОКАЗАТЕЛЬСТВА: 26 отказов `FLANG_PROOF_INDUCTION_*`. Это и есть
 * довод, по которому ядро стоит в подмножестве печати, а не отброшено вместе
 * с примерами: печать без ядра теряет байты, а не только строгость.
 *
 * ── Почему проверка живёт ЗДЕСЬ, а не в self-bootstrap.test.mjs ─────────────
 * Потому что ей не нужна вторая реализация. Весь `self-bootstrap.test.mjs`
 * построен на свидетеле (`emitC`, `linkProgram`, `checkTypes`) — уедет
 * свидетель, уедет и он, а этот закон обязан пережить его: он сверяет ДВА ВХОДА
 * ОДНОГО двоичного между собой. Двоичный для него собирается из `bootstrap/`
 * командой `make`, то есть ровно тем способом, каким компилятор пересобирается
 * без Node.
 *
 * ── Почему закон сформулирован так, а не списком ────────────────────────────
 * Список того, чего у двоичного нет, набранный руками, протухает в первую же
 * чужую правку. Признак класса записан в
 * `docs/zettel/sverka-dvuh-realizaciy-slepnet-na-tom-chto-vychli-do-sravneniya.md`:
 * если ожидаемое собирается ВНУТРИ сверки из кусков, сверка меряет пересечение,
 * а не разницу. Здесь ожидаемое не собирается ниоткуда — оно БЕРЁТСЯ У
 * НАСТОЯЩЕЙ КОМАНДЫ ЦЕЛИКОМ: `flang check` зовётся процессом, и его вердикт и
 * есть ожидаемое.
 *
 * Закон: **вердикт `emit` равен вердикту `check`, и единственное расхождение,
 * которое печати позволено, — `FLANG_EXAMPLE`.** Названо ОДНО СЛОВО — имя
 * единственного пробела, — а не список программ и не список кодов.
 *
 * ── Почему пробел именно примеры, и это измерено ────────────────────────────
 * Прогон примеров считает вычислитель, написанный на самом языке. На самых
 * больших программах дерева он в собственный предел двоичного не укладывается:
 * `flang check flang/self/bootstrap/compiler.flang` доходит до ПЯТОГО шага
 * (успев напечатать «функций 4206, из них с доказанным завершением 3084; типов
 * 389; файлов вместе с импортами 21») и падает только на нём —
 * `FLANG_RECURSION_LIMIT: функция «Описания программы» исчерпала лимит шагов
 * (40000000)», «прогон примеров прекращён», код 1, 10 мин 35 с.
 *
 * А `flang emit flang/self/bootstrap/compiler.flang` — это и есть РАСКРУТКА:
 * им компилятор печатает сам себя без Node. Свяжи печать с примерами, и
 * пересобрать компилятор стало бы нельзя. Ядро при этом укладывается — тот же
 * прогон это и показал, — и остаётся в подмножестве печати.
 */
