/**
 * ЖУРНАЛ УПРЕЖДАЮЩЕЙ ЗАПИСИ, НАПЕЧАТАННЫЙ ВО ВСЕ ВОСЕМЬ ЦЕЛЕЙ, ПРОТИВ КОРПУСА.
 *
 * ── Зачем это отдельным файлом ──────────────────────────────────────────────
 *
 * Главная сверка напечатанного кода (`corpus-grid.mjs`) собирает корпус по
 * маске каталогов — `flang/stdlib/` и `flang/examples/leetcode/`, — и модуль
 * журнала в неё не попадает. То есть без этого файла утверждение «журнал
 * восстанавливается после обрыва» проверялось бы только вычислителем на
 * JavaScript, а про семь остальных целей не было бы сказано ничего.
 *
 * Здесь оно проверяется у ВСЕХ ВОСЬМИ, и проверяется настоящей сборкой:
 * исходник печатается в цель, собирается её собственным компилятором и
 * запускается прогонщиком (`flang_cli`), а ответы сверяются с корпусом —
 * с теми самыми числами, что посчитаны рукой в `wal-corpus.mjs`.
 *
 * ── Что подаётся ────────────────────────────────────────────────────────────
 *
 * Все 61 именованный вход корпуса И все 27 обрывов эталонного журнала подряд.
 * Восемь целей на 88 входов — 704 ответа, и ни одному из них не разрешено
 * отличаться от посчитанного заранее.
 *
 * ── Чего этот файл НЕ проверяет ─────────────────────────────────────────────
 *
 * Долговечности. Ни одна из восьми программ ниже не касается диска: журнал
 * приезжает СТРОКОЙ в аргументе и уезжает значением. Что останется на пластине
 * после отключения питания, здесь не проверяется и проверено быть не может.
 *
 * ── Если тулчейна нет ───────────────────────────────────────────────────────
 *
 * Цель честно пропускается через `missingToolchain`, и пропуск виден в отчёте.
 * `FTS_REQUIRE_TOOLCHAINS=go` превращает пропуск Go в падение — молчаливый
 * пропуск, выглядящий как успех, недопустим.
 */
import assert from "node:assert/strict"
import { execFileSync, spawnSync } from "node:child_process"
import { globSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { findExecutable } from "../src/toolchain.mjs"
import { рабочийКаталог, средаСборки } from "./tempdir.mjs"
import { missingToolchain } from "./toolchain-guard.mjs"
import { КОРПУС, обрывы } from "./wal-corpus.mjs"

const исходник = fileURLToPath(new URL("../examples/wal/write-ahead-log.flang", import.meta.url))
const бинарьFlang = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))
const рабочий = рабочийКаталог("emit-wal")

/** Имя файла модуля у всех восьми целей — транслитерация имени модуля flang. */
const МОДУЛЬ = "zhurnal_uprezhdayuschey_zapisi"
/** Имя класса у целей, где модуль — класс. */
const КЛАСС = "ZhurnalUprezhdayuscheyZapisi"

/**
 * Восемь целей: чем проверяется наличие тулчейна и чем запускается прогонщик.
 *
 * `пуск` возвращает `[команда, доводы]` относительно каталога цели. Там, где
 * напечатанный `Makefile` даёт правило `run`, зовётся оно — печатник знает про
 * свою цель больше, чем этот файл. Два исключения названы поимённо:
 *
 *   • у C и Go правила `run` в `Makefile` нет вовсе — собирается `flang_cli`,
 *     и запускать его надо самому;
 *   • у C# правило есть, но зовёт `dotnet run -v quiet --nologo -- Класс`, и
 *     ключи уезжают ПРОГРАММЕ: она принимает `--nologo` за имя класса и падает
 *     `TypeLoadException`. Это свойство напечатанного Makefile, а не журнала,
 *     поэтому здесь зовётся уже собранная сборка напрямую.
 */
const ЦЕЛИ = [
  { id: "c", проба: "cc", собирать: true, пуск: () => ["./flang_cli", []] },
  { id: "go", проба: "go", собирать: true, пуск: () => ["./flang_cli", []] },
  { id: "rust", проба: "cargo", собирать: true, пуск: null },
  { id: "python", проба: "python3", собирать: true, пуск: null },
  { id: "java", проба: "javac", собирать: true, пуск: null },
  {
    id: "csharp",
    проба: "dotnet",
    собирать: true,
    пуск: (каталог) => ["dotnet", [globSync(join(каталог, "bin", "Debug", "*", "flang.dll"))[0] ?? "flang.dll", КЛАСС]],
  },
  { id: "elixir", проба: "elixir", собирать: true, пуск: null },
  { id: "js", проба: "node", собирать: false, пуск: () => ["node", ["flang_cli.js", `${МОДУЛЬ}.js`]] },
]

/**
 * Значения протокола прогонщика размечены тегами: JSON беднее flang, и без
 * разметки потерялись бы NaN, −0 и разница между записью и вариантом.
 */
const раскодировать = (значение) => {
  if (значение === null || typeof значение !== "object") return значение
  if ("n" in значение) return Number(значение.n)
  if ("s" in значение) return значение.s
  if ("l" in значение) return значение.l.map(раскодировать)
  if ("r" in значение) return Object.fromEntries(значение.r.map(([имя, поле]) => [имя, раскодировать(поле)]))
  if ("v" in значение) {
    return { вариант: значение.v, поля: Object.fromEntries((значение.f ?? []).map(([имя, поле]) => [имя, раскодировать(поле)])) }
  }
  return значение
}

/** Корпус целиком: именованные входы плюс все обрывы эталона. */
const ВХОДЫ = [
  ...КОРПУС.map((в) => ({ имя: в.имя, текст: в.текст, записи: в.записи, съедено: в.съедено })),
  ...обрывы().map((о) => ({ имя: `обрыв на ${о.к}`, текст: о.текст, записи: о.записи, съедено: о.съедено })),
]

const ЗАПРОСЫ =
  ВХОДЫ.map((в) => JSON.stringify({ fn: "Прочитать журнал", args: [{ s: в.текст }], depth: "10000", steps: "20000000" })).join("\n") + "\n"

test("корпус для восьми целей собран целиком", () => {
  assert.equal(ВХОДЫ.length, КОРПУС.length + обрывы().length)
  assert.ok(ВХОДЫ.length >= 80, `входов: ${ВХОДЫ.length}`)
})

for (const цель of ЦЕЛИ) {
  test(`${цель.id}: напечатанный журнал читает корпус так же, как вычислитель`, async (t) => {
    if (!findExecutable(цель.проба)) {
      missingToolchain(t, цель.id, `не найден «${цель.проба}» (ни в PATH, ни в FTS_TOOLCHAIN_PATH) — пропуск`)
      return
    }
    const каталог = join(рабочий, цель.id)
    /* Печать идёт в СВЕЖИЙ каталог: `make` отвечает «nothing to be done» по
       времени файлов и отдал бы старый артефакт. */
    execFileSync("node", [бинарьFlang, "emit", исходник, "--target", цель.id, "--cli", "--out", каталог], {
      stdio: ["ignore", "ignore", "pipe"],
    })
    const среда = средаСборки(рабочий, { DOTNET_CLI_HOME: рабочий, DOTNET_CLI_TELEMETRY_OPTOUT: "1", DOTNET_NOLOGO: "1", CARGO_HOME: join(рабочий, "cargo") })
    if (цель.собирать) {
      const сборка = spawnSync("make", ["-C", каталог], { encoding: "utf8", env: среда })
      assert.equal(сборка.status, 0, `сборка ${цель.id} отказала:\n${(сборка.stderr || сборка.stdout || "").slice(0, 2000)}`)
    }
    const пуск = цель.пуск === null ? ["make", ["-C", каталог, "run"]] : цель.пуск(каталог)
    const прогон = spawnSync(пуск[0], пуск[1], {
      input: ЗАПРОСЫ,
      encoding: "utf8",
      maxBuffer: 1 << 28,
      env: среда,
      cwd: каталог,
    })
    assert.equal(прогон.status, 0, `прогон ${цель.id} отказал:\n${(прогон.stderr || "").slice(0, 2000)}`)

    const строки = прогон.stdout.split("\n").filter((с) => с.trim().startsWith("{"))
    assert.equal(строки.length, ВХОДЫ.length, `ответов ${строки.length} на ${ВХОДЫ.length} запросов`)

    const беды = []
    for (let место = 0; место < ВХОДЫ.length; место += 1) {
      const вход = ВХОДЫ[место]
      const ответ = JSON.parse(строки[место])
      if (ответ.ok !== true) {
        беды.push(`${вход.имя}: отказ ${ответ.code} — ${ответ.message}`)
        continue
      }
      const значение = раскодировать(ответ.value)
      const записи = (значение["записи"] ?? []).map((з) => ({ номер: з["номер"], тело: з["тело"] }))
      if (JSON.stringify(записи) !== JSON.stringify(вход.записи)) {
        беды.push(`${вход.имя}: записи ${JSON.stringify(записи)} вместо ${JSON.stringify(вход.записи)}`)
      }
      if (значение["съедено"] !== вход.съедено) {
        беды.push(`${вход.имя}: съедено ${значение["съедено"]} вместо ${вход.съедено}`)
      }
      /* Съеденное и остаток обязаны дать вход знак в знак и у напечатанного
         кода тоже: это то же утверждение, что стоит постусловием при функции. */
      const начало = [...вход.текст].slice(0, вход.съедено).join("")
      if (начало + значение["остаток"] !== вход.текст) {
        беды.push(`${вход.имя}: съеденное плюс остаток не дают вход`)
      }
    }
    assert.deepEqual(беды, [], `расхождений у цели ${цель.id}: ${беды.length} из ${ВХОДЫ.length}`)
  })
}
