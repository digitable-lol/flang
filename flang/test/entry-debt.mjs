/**
 * ДОЛГ ЭТАЛОНОВ ПЕЧАТИ, НАЗВАННЫЙ И ВЫЧТЕННЫЙ — в одном месте на четыре цели.
 *
 * ДОЛГ ЗАКРЫВАЕТСЯ ПО ЦЕЛЯМ, И ФАЙЛ ПУСТЕЕТ. Elixir закрыл его пятым, Python —
 * шестым: оба печатают границу входа сами, вычитание из их сверок снято
 * целиком, и метки для них отсюда убраны. Так и задумано этим файлом: он держит
 * долг названным, а не вечным.
 *
 * Один эталон печати (`emit-csharp`) писался от точки, где свидетель ещё не
 * печатал
 * ГРАНИЦУ ВХОДА: таблицу объявленных типов параметров, по которой прогонщик
 * сверяет пришедшее снаружи значение ДО вызова (`work/emit-entry-types`,
 * `renderEntry` в каждом `flang/src/emit/*.mjs`). У эталонов её нет — слово
 * «Граница входа» встречается только в `self/emit-c.flang`, и это измеримо:
 * `grep -c 'Граница входа' flang/self/emit-*.flang`.
 *
 * Расхождение от этого ОДНО и всегда одно и то же: у свидетеля есть ровно один
 * лишний блок, а всё остальное совпадает байт в байт. Поэтому сверка не
 * отменена и не ослаблена до «похоже»: из вывода свидетеля ВЫЧИТАЕТСЯ названный
 * блок вместе с тем разделителем, который печать поставила перед ним, и остаток
 * обязан совпасть с эталоном ПОБАЙТОВО. Внутри текста не нормализуется ничего.
 *
 * Зубы у проверки с двух сторон, и это главное:
 *
 *   • блок вырезается по ДВУМ меткам — первой и последней строке, — и обе
 *     обязаны найтись; не найдётся вторая — `безГраницы` отдаёт беду, а не
 *     молча возвращает текст целиком;
 *   • пропавший блок красит сверку отдельным утверждением (`долгБылНайден`):
 *     снимет кто-то долг — тест потребует убрать вычитание, а не промолчит.
 *
 * У GO, RUST, JAVA, JS, ELIXIR и PYTHON долга больше НЕТ: границу входа печатают
 * сами эталоны, таблица приезжает настройками, и все шесть сверок идут ПОЛНЫМИ
 * файлами, без единого среза. Метки js и java ниже оставлены: по ним считается,
 * сколько блоков границы у свидетеля, в замерах долга у оставшейся цели. У неё
 * после блока идёт закрывающая скобка класса, поэтому вырезать приходится
 * середину.
 */

/**
 * Метки блока границы входа по целям: первая строка блока, последняя строка
 * блока и длина разделителя, который печать ставит ПЕРЕД блоком.
 *
 * Все три ИЗМЕРЕНЫ на выдаче свидетеля, а не угаданы: разделитель — два перевода
 * строки там, где блок печатается отдельным телом (`bodies.push(renderEntry(…))`,
 * тела склеиваются пустой строкой), три у Python (тело перед ним само кончается
 * переводом строки) и один у JavaScript, где блок — поле объекта в общем списке
 * строк. Ошибись здесь на один символ — сверка покраснеет на первой же
 * программе, а не промолчит: вырезанное сравнивается побайтово.
 */
export const МЕТКИ_ГРАНИЦЫ = Object.freeze({
  js: {
    начало: "  /* Граница входа: объявленные типы параметров данными. Прогонщик сверяет",
    конец: "  },",
    разделитель: 1,
  },
  java: {
    начало: "  /* Граница входа: объявленные типы параметров данными. Прогонщик сверяет по",
    конец: "  }",
    разделитель: 2,
  },
  csharp: {
    начало: "    // Граница входа: объявленные типы параметров данными. Прогонщик сверяет",
    конец: "    }",
    разделитель: 2,
  },
})

/**
 * Вывод свидетеля без блока границы входа.
 *
 * @param {string} текст содержимое одного напечатанного файла
 * @param {string} цель ключ из `МЕТКИ_ГРАНИЦЫ`
 * @returns {{текст: string, былаГраница: boolean, беда: string|null}}
 */
export function безГраницы(текст, цель) {
  const метки = МЕТКИ_ГРАНИЦЫ[цель]
  if (метки === undefined) throw new Error(`неизвестная цель «${цель}»`)
  const место = текст.indexOf(метки.начало)
  if (место === -1) return { текст, былаГраница: false, беда: null }
  /* Конец ищется как ЦЕЛАЯ строка и только после начала: подстрокой «  }»
     нашлось бы что угодно. */
  const хвост = текст.indexOf(`\n${метки.конец}\n`, место + метки.начало.length)
  if (хвост === -1) {
    return { текст, былаГраница: true, беда: `блок границы входа начался, но не кончился меткой ${JSON.stringify(метки.конец)}` }
  }
  const конец = хвост + 1 + метки.конец.length
  return {
    текст: текст.slice(0, место - метки.разделитель) + текст.slice(конец),
    былаГраница: true,
    беда: null,
  }
}

/**
 * Долг обязан БЫТЬ: вычитание блока, которого нет, — молчаливое ослабление
 * сверки. Программа без параметров таблицы не печатает вовсе, поэтому
 * требование стоит на НАБОРЕ файлов программы, а не на каждом файле.
 */
export function долгБылНайден(блоков, файлы) {
  if (блоков > 0) return null
  const крупные = файлы.some((файл) => файл.content.length > 400)
  return крупные
    ? "свидетель не напечатал границы входа ни в одном файле — вычитание блока стало прикрытием, снимите его"
    : null
}
