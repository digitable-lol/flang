/**
 * Двери входа: значения, приехавшие снаружи, против объявленных типов.
 *
 * ── Одна дыра в трёх местах ─────────────────────────────────────────────────
 *
 * `flang run --args` сверять вход научился (`cli-args.test.mjs`). Тем же
 * способом значения снаружи принимают ещё три места, и проверки у них не было:
 *
 *   `flang facts --facts`  факты из файла становятся аргументами вызова;
 *   `flang io`             отклик хозяина приходит в функцию шага плана;
 *   `flang repl`           значение, набранное человеком.
 *
 * Улики, снятые до правки на живых файлах дерева:
 *
 *   facts, `{"н": -3}`     → {"ok":true,…"status":"verified"} и КОД 0.
 *                            Факт-чекинг сказал «подтверждено» про вычисление
 *                            на значении, которого в типе «нат» нет.
 *   facts, `{"н": 2.5}`    → "status":"refuted" — приговор «ложно», вынесенный
 *                            по вычислению на значении вне типа.
 *   facts, `{"н": 1e300}`  → FLANG_RECURSION_LIMIT после шага «тотальность:
 *                            ok»: модуль сам объявил функцию завершающейся и
 *                            сам же не дождался ответа.
 *   io, отклик хозяина
 *     «Отметка времени» с
 *     `миллисекунды: "вчера"` → план дошёл до конца и вернул "мс: вчера". Ни
 *                            одной диагностики: ложь про тип в РЕЗУЛЬТАТЕ.
 *
 * ── Чего эти проверки требуют ───────────────────────────────────────────────
 *
 * Не «сообщение стало понятнее», а «значение не дошло до вычисления»: отказ
 * обязан прийти кодом FLANG_TYPE и не имеет права быть ни FLANG_RECURSION_LIMIT,
 * ни отказом встроенной формы в глубине тела. Снимут сверку на границе — в
 * `facts` вернётся предел глубины, в `io` вернётся "мс: вчера", и это здесь
 * покраснеет.
 *
 * ── Половина изъятия, без которой вторая ничего не значит ───────────────────
 *
 * В каждой двери есть проверка «годный вход проходит»: годный факт считается,
 * утверждение без вызова функции границей не задето, годный отклик доводит план
 * до конца, а ЧУЖОЙ (но правильно устроенный) вариант отклика доходит до
 * программы и обрабатывается её же веткой. Иначе зелень означала бы, что не
 * проходит ничего.
 */

import assert from "node:assert/strict"
import { execFile } from "node:child_process"
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { after, test } from "node:test"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

import { variant } from "../src/builtins.mjs"
import { checkFacts } from "../src/factcheck.mjs"
import { runPlan, хозяинПоСписку } from "../src/io.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

const выполнить = promisify(execFile)
const cli = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))
const путьНатурального = fileURLToPath(new URL("../examples/measure/natural.flang", import.meta.url))

/* Файл дерева, а не выдуманная программа: `natural.flang` служит образцом
   точного натурального типа, и дыра была НА НЁМ. */
const натуральное = parse(await readFile(путьНатурального, "utf8"), путьНатурального)

const workdir = await mkdtemp(join(tmpdir(), "flang-entry-doors-"))
after(async () => {
  await rm(workdir, { recursive: true, force: true })
})

let счётчик = 0
async function песочница(имя, текст) {
  const путь = join(workdir, `${(счётчик += 1)}-${имя}`)
  await writeFile(путь, текст, "utf8")
  return путь
}

/* ══════════════════════ дверь первая: flang facts ═══════════════════════════ */

const УТВЕРЖДЕНИЕ = "«Факториал» от «н» равно 120"

const вердикт = (факты, утверждение = УТВЕРЖДЕНИЕ) =>
  checkFacts(натуральное, { facts: факты, claims: [утверждение] }).results[0]

test("facts: годный факт считается, и утверждение подтверждается", () => {
  const итог = вердикт({ н: 5 })
  assert.equal(итог.holds, true)
  assert.equal(итог.status, "verified")
  /* След вычисления обязан остаться прежним: граница входа не добавляет шага,
     когда врать нечему, — иначе всякий, кто читает `steps`, читал бы другое. */
  assert.deepEqual(итог.steps.map((шаг) => шаг.kind), ["разбор", "тотальность", "факт", "вычисление", "сравнение"])
})

test("facts: отрицательное вместо «нат» — отказ, а не «подтверждено»", () => {
  /* До правки здесь было holds: true, status: "verified", код возврата 0:
     «Факториал» от −3 равен 1… и утверждение про 120 опровергалось бы, а про 1
     подтверждалось. Ответ выдавался на значении, которого в типе нет. */
  const итог = вердикт({ н: -3 }, "«Факториал» от «н» равно 1")
  assert.equal(итог.holds, false)
  assert.equal(итог.status, "refused")
  assert.match(итог.why, /FLANG_TYPE/u)
  assert.match(итог.why, /-3 вне нат/u)
  assert.ok(
    !итог.steps.some((шаг) => шаг.kind === "вычисление"),
    `вход дошёл до вычисления: ${JSON.stringify(итог.steps)}`,
  )
})

test("facts: дробное вместо «нат» — отказ, а не приговор «опровергнуто»", () => {
  /* «Опровергнуто» — это утверждение о мире, и выносить его по вычислению на
     значении вне типа хуже, чем не отвечать вовсе: до правки здесь стояло
     status: "refuted" и «Факториал» от 2.5 = 3.75. */
  const итог = вердикт({ н: 2.5 })
  assert.equal(итог.status, "refused")
  assert.match(итог.why, /2\.5 не целое/u)
})

test("facts: за потолком «нат» — отказ по ТИПУ, а не предел глубины", () => {
  /* Главная проверка двери. 1e300 лежит вне [0, 2^53−1], сторожа убывания у
     доказанной функции нет — его сняло доказательство ПО ТИПУ. До правки
     факт-чекинг успевал сказать «тотальность: ok» и следом упирался в
     FLANG_RECURSION_LIMIT: гарантия №1 самого модуля («только тотальные
     функции — иначе ответ может не наступить») не срабатывала, потому что
     функция ТОТАЛЬНА, а ответ всё равно не наступал. */
  const итог = вердикт({ н: 1e300 })
  assert.equal(итог.status, "refused")
  assert.ok(!/FLANG_RECURSION_LIMIT/u.test(итог.why), `вход дошёл до вычисления: ${итог.why}`)
  assert.match(итог.why, /FLANG_TYPE/u)
  assert.match(итог.why, /1e\+300 вне нат/u)
})

test("facts: строка вместо «нат» — отказ про ВХОД, а не про операцию в теле", () => {
  const итог = вердикт({ н: "строка" })
  assert.equal(итог.status, "refused")
  assert.match(итог.why, /аргумент «н» не соответствует типу нат/u)
  /* До правки: «сравнения порядка допустимы только для чисел» — правда о
     `не больше` и ни слова о том, что значение не того типа, который объявлен. */
  assert.doesNotMatch(итог.why, /сравнени/u)
})

test("facts: имя факта названо рядом с именем аргумента", () => {
  /* Имя аргумента — авторское («н»), имя факта — вызывающей стороны
     («сколько»). Сообщение обязано назвать оба: иначе непонятно, какую строку
     файла фактов править. */
  const итог = checkFacts(натуральное, {
    facts: { сколько: -3 },
    claims: ["«Факториал» от «сколько» равно 1"],
  }).results[0]
  assert.equal(итог.status, "refused")
  assert.match(итог.why, /«н» ← факт «сколько»/u)
})

test("facts: утверждение без вызова функции границей не задето", () => {
  /* Граница судит АРГУМЕНТЫ. Факт, который никуда не подставляется, никакому
     объявленному типу не обязан: «факт «н» больше 0» — утверждение о самом
     факте, и оно обязано отвечать как отвечало. */
  const итог = checkFacts(натуральное, { facts: { н: 5 } , claims: ["факт «н» больше 0"] }).results[0]
  assert.equal(итог.holds, true)
  assert.deepEqual(итог.steps.map((шаг) => шаг.kind), ["разбор", "факт", "сравнение"])
})

test("flang facts: ложь в файле фактов — код 1 и FLANG_TYPE в stdout", async () => {
  const факты = await песочница("факты.json", JSON.stringify({ н: 1e300 }))
  const годные = await песочница("годные.json", JSON.stringify({ н: 5 }))
  const запуск = (файл) => [ "facts", путьНатурального, "--facts", файл, "--claims", JSON.stringify([УТВЕРЖДЕНИЕ]) ]

  const { stdout } = await выполнить("node", [cli, ...запуск(годные)], { maxBuffer: 64 * 1024 * 1024 })
  assert.equal(JSON.parse(stdout).ok, true, "годный файл фактов обязан считаться")

  const отказ = await выполнить("node", [cli, ...запуск(факты)], { maxBuffer: 64 * 1024 * 1024 }).then(
    () => assert.fail("вход, лгущий про тип, обязан был отказать"),
    (беда) => беда,
  )
  assert.equal(отказ.code, 1)
  /* Вердикт — результат работы, а не сбой инструмента: JSON остаётся в stdout. */
  const разбор = JSON.parse(отказ.stdout)
  assert.equal(разбор.ok, false)
  assert.equal(разбор.results[0].status, "refused")
  assert.match(разбор.results[0].why, /FLANG_TYPE/u)
  assert.ok(!/FLANG_RECURSION_LIMIT/u.test(разбор.results[0].why), разбор.results[0].why)
})

/* ══════════════════════ дверь вторая: flang io ══════════════════════════════ */

/**
 * План, который спрашивает у хозяина время и печатает его.
 *
 * `миллисекунды` объявлены числом в словаре ввода-вывода (`io.mjs`), то есть
 * тип у отклика ЕСТЬ — его просто никто не сверял со значением.
 */
const ЧАСЫ = `модуль «Часы»

тип «Ход»
  вариант «Спросим»
  вариант «Скажем»

тотальная функция «Начать»
  возвращает «Ход»
  вариант «Спросим»

тотальная функция «Дальше»
  принимает ход: «Ход», отклик: «Отклик»
  возвращает «Продолжение»
  разбор ход
    случай вариант «Спросим»
      то вариант «Сделать» с поручение равным (вариант «Текущее время») и потом равным (вариант «Скажем»)
    случай вариант «Скажем»
      то разбор отклик
           случай вариант «Отметка времени» с миллисекунды как мс
             то вариант «Конец работы» с значение равным (соединить "мс: " с (к строке мс))
           случай вариант «Сбой» с код как код и сообщение как сообщение
             то вариант «Провал» с код равным код и сообщение равным сообщение
           случай любое
             то вариант «Провал» с код равным "FLANG_IO_ORDER" и сообщение равным "ждали часы"

план «Который час»
  состояние «Ход»
  начинает с «Начать»
  обрабатывает «Дальше»
`

const часы = parse(ЧАСЫ, "часы.flang")

test("io: программа плана проходит проверку — сверять будем ВХОД, а не её", () => {
  assert.deepEqual(checkTypes(часы).diagnostics, [])
})

test("io: годный отклик хозяина доводит план до конца", async () => {
  const итог = await runPlan(часы, "Который час", хозяинПоСписку([variant("Отметка времени", { миллисекунды: 1755000000000 })]))
  assert.equal(итог.значение, "мс: 1755000000000")
  assert.equal(итог.поручений, 1)
})

test("io: ЧУЖОЙ вариант отклика — не ошибка типа, а работа программы", async () => {
  /* Вторая половина изъятия, и она важнее первой. «Записано» вместо «Отметки
     времени» — правильно устроенный «Отклик», просто не тот, которого ждали:
     его обязана встретить ветка `случай любое` программы, а не граница входа.
     Закройся дверь слишком широко — этот путь исчез бы, и вместе с ним
     обещание «программа обязана уметь встретить неудачу поручения». */
  await assert.rejects(
    runPlan(часы, "Который час", хозяинПоСписку([variant("Записано", { сколько: 3 })])),
    (беда) => беда.diagnostics[0].code === "FLANG_IO_ORDER" && беда.message === "ждали часы",
  )
})

test("io: «Сбой» хозяина по-прежнему доходит до программы", async () => {
  await assert.rejects(
    runPlan(часы, "Который час", хозяинПоСписку([variant("Сбой", { код: "FLANG_IO_DENIED", сообщение: "часы запрещены" })])),
    (беда) => беда.diagnostics[0].code === "FLANG_IO_DENIED" && беда.message === "часы запрещены",
  )
})

test("io: ложь хозяина про тип поля не доезжает до программы", async () => {
  /* До правки этот прогон КОНЧАЛСЯ УСПЕХОМ и возвращал "мс: вчера": словарь
     объявляет `миллисекунды` числом, `проверитьОтклик` смотрел только на имя
     варианта, и строка проходила внутрь молча. */
  await assert.rejects(
    runPlan(часы, "Который час", хозяинПоСписку([variant("Отметка времени", { миллисекунды: "вчера" })])),
    (беда) => {
      assert.equal(беда.diagnostics[0].code, "FLANG_TYPE")
      assert.match(беда.message, /план «Который час»/u)
      assert.match(беда.diagnostics[0].message, /аргумент «отклик»\.миллисекунды не соответствует типу число/u)
      return true
    },
  )
})

test("io: ничто вместо числа — тоже отказ на границе", async () => {
  /* «ничто» опаснее строки: `к строке ничто` не спотыкается, и до правки план
     возвращал "мс: ничто" — ответ, неотличимый от настоящего для того, кто
     читает только результат. */
  await assert.rejects(
    runPlan(часы, "Который час", хозяинПоСписку([variant("Отметка времени", { миллисекунды: null })])),
    (беда) => беда.diagnostics[0].code === "FLANG_TYPE",
  )
})

test("io: поля вовсе нет — отказ на границе, а не в глубине вычисления", async () => {
  await assert.rejects(
    runPlan(часы, "Который час", хозяинПоСписку([variant("Отметка времени", {})])),
    (беда) => {
      assert.equal(беда.diagnostics[0].code, "FLANG_TYPE")
      assert.match(беда.diagnostics[0].message, /требует поле «миллисекунды»/u)
      return true
    },
  )
})

test("io: хозяин, вернувший не отклик, отвергается как и прежде", async () => {
  /* Прежняя половина проверки хозяина («это вообще «Отклик»?») остаётся на
     месте и остаётся FLANG_IO: граница входа её не заменяет, а продолжает. */
  await assert.rejects(
    runPlan(часы, "Который час", () => 42),
    (беда) => беда.diagnostics[0].code === "FLANG_IO",
  )
})

test("flang io: настоящий хозяин проходит границу насквозь", async () => {
  /* Вторая половина изъятия для этой двери, и снята она с НАСТОЯЩЕГО хозяина.
     `src/host/node.mjs` сегодня не врёт — он сам собирает отклики и типы в них
     не путает, — поэтому улику про ложь пришлось снимать хозяином из тестов.
     Но проверка стоит в цикле плана, через который ходит и настоящий хозяин:
     сломай её — и `flang io` перестанет работать вовсе. Здесь это и
     проверяется, командой целиком. */
  const файл = await песочница("часы.flang", ЧАСЫ)
  const { stdout } = await выполнить("node", [cli, "io", файл], { maxBuffer: 64 * 1024 * 1024 })
  const итог = JSON.parse(stdout)
  assert.equal(итог.plan, "Который час")
  assert.equal(итог.orders, 1)
  assert.match(итог.result, /^мс: \d+$/u, "часы хозяина обязаны прийти числом")
})

