test("процесс, которому падать нечем, надзора не требует", () => {
  /* Вторая половина анализа, и она важнее первой: если бы надзора требовали от
     всех, проверка ничего не считала бы и ничего бы не значила. «Счётчик» и
     «Журнал» из counter.flang тотальны, разбор у них исчерпывающий, частичных
     форм нет — множество отказов пусто, и надзор над ними стоит по желанию
     автора, а не по требованию проверки. */
  const исходник = readFileSync(`${корень}flang/conc/examples/counter.flang`, "utf8")
  const программа = parse(исходник, "counter.flang")
  for (const [процесс, отказы] of достижимыеОтказы(программа)) {
    assert.deepEqual(отказы, [], `у «${процесс}» отказов быть не должно`)
  }
  /* Уберём надзор целиком — программа обязана остаться принятой. */
  const безНадзора = исходник.replace(/надзор «Учёт»\n(?:  .*\n)+/, "")
  assert.ok(!безНадзора.includes("надзор «Учёт»"), "надзор из текста не удалён — тест ничего не проверяет")
  assert.deepEqual(checkTypes(parse(безНадзора, "counter.flang")).diagnostics, [])
})
