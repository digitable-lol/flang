test("ДЫРА: тотальный обработчик тоже отказывает, и этого вида нет в перечислении", () => {
  /*
   * Контракт говорит: запас витков — «только у обработчика БЕЗ признака
   * тотальная». Планировщик говорит иначе. Тотальному обработчику он тоже
   * ставит предел — миллион витков (`conc.mjs`, TOTAL_HANDLER_STEPS), — и предел
   * этот в исходнике программы не назван нигде. Значит отказ, который из него
   * следует, НЕПЕРЕЧИСЛИМ из текста: чтобы его предсказать, надо знать не
   * программу, а константу рантайма.
   *
   * Причина глубже константы. Тотальность даёт «завершится», а не «завершится
   * скоро»: «фиб» ниже доказанно завершается и при этом упирается в миллион на
   * входе 34. Закрыть дыру можно только ОГРАНИЧЕННОСТЬЮ — оценкой сверху на
   * витки от размера входа (RESILIENCE.md, шаг В3). До неё анализ честно
   * считает три вида, а не все, и вот программа, на которой это видно.
   */
  const текст = [
    шапка,
    "тип «Весть»",
    "  вариант «считать» содержит «сколько»: число",
    "",
    "процесс «П»",
    "  состояние «Состояние»",
    "  начинает с «пусто»",
    "  принимает «Весть»",
    "  обрабатывает «шаг»",
    "",
    "тотальная функция «фиб»",
    "  принимает н: число",
    "  возвращает число",
    "  если н меньше 2",
    "    то н",
    "    иначе («фиб» от (н минус 1)) плюс («фиб» от (н минус 2))",
    "",
    "тотальная функция «шаг»",
    "  принимает сост: «Состояние», весть: «Весть»",
    "  возвращает «Отклик»",
    "  разбор весть",
    "    случай вариант «считать» с «сколько» как сколько",
    "      пусть х равно «фиб» от сколько",
    "      запись «Отклик» с «состояние» равным (запись «Состояние» с «счёт» равным х) и «действия» равным []",
    "",
    "прогон «тотальный, но долгий»",
    "  семя 1",
    "  дано «П» принимает (вариант «считать» с «сколько» равным 34)",
    "  ожидается «П» равен (запись «Состояние» с «счёт» равным 0)",
    "",
  ].join("\n")

  const программа = parse(текст, "проба.flang")
  /* Анализ молчит: по перечислению у этого процесса отказов нет. */
  assert.deepEqual(достижимыеОтказы(программа).get("П"), [])
  assert.deepEqual(диагностики(текст), [], "надзора Г1 не требует — и в этом дыра")

  /* А прогон отказывает, и код отказа не принадлежит ни одному виду. */
  const итог = runConcurrent(программа, программа.runs[0], {})
  assert.deepEqual(итог.отказы.map((о) => о.код), ["FLANG_RECURSION_LIMIT"])
  assert.deepEqual(итог.живые, [], "решать некому: надзора проверка не потребовала")
})

/* ───────────── список частичных форм сверен с builtins.mjs ──────────────── */

test("список частичных форм сверен с builtins.mjs, а не переписан из головы", () => {
  /*
   * Партиальность встроенной формы видна по одному признаку: внутри её
   * реализации стоит собственный `throw flangError`, а не только общие
   * `expect…`, которые снимает проверка типов. Считаем такие формы прямо по
   * исходнику: анализ, разошедшийся с `builtins.mjs`, молча перестал бы видеть
   * целый вид отказа, и заметить это было бы нечем.
   */
  const исходник = readFileSync(`${корень}flang/src/builtins.mjs`, "utf8")
  const сБросками = new Set()
  let текущая = null
  for (const строка of исходник.split("\n")) {
    const начало = строка.match(/^ {2}"([^"]+)": \(args/)
    if (начало) текущая = начало[1]
    if (текущая !== null && /throw flangError\(/.test(строка)) сБросками.add(текущая)
  }

  /* Формы, которые бросают только на чужом ТИПЕ аргумента: такой вход проверка
     типов не пропускает, значит отказом выполнения это не становится. Каждая
     названа поимённо — списком «всё остальное» здесь отделаться нельзя. */
  const снимаетПроверкаТипов = new Set(["длина", "пусто", "к строке", "соединить", "процентов от"])

  const ожидаемые = [...сБросками].filter((имя) => !снимаетПроверкаТипов.has(имя)).sort()
  assert.deepEqual(
    [...ЧАСТИЧНЫЕ.keys()].sort(),
    ожидаемые,
    "в builtins.mjs появилась форма, которая может отказать, а анализ про неё не знает",
  )
})

