const диагностики = (текст) => checkTypes(parse(текст, "проба.flang")).diagnostics
const коды = (текст) => диагностики(текст).map((д) => д.code)

/** Прогнать первый прогон программы и вернуть его итог. */
function прогнать(текст) {
  const программа = parse(текст, "проба.flang")
  const беды = [
    ...checkTypes(программа).diagnostics,
    ...(checkTotality(программа)?.diagnostics ?? []),
  ].filter((д) => д.severity !== "warning")
  assert.deepEqual(беды, [], "программа обязана пройти проверки, иначе прогон ничего не показывает")
  return runConcurrent(программа, программа.runs[0], {})
}

