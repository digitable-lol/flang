test("отметку меры кладёт САМ передний край, а не только тесты этого файла", () => {
  /*
   * Последнее звено той же цепи, и без него весь файл стережёт СВОЮ программу, а
   * не пользовательскую. Прогоны выше метят программу сами (`запустить`), сетка
   * примеров — тоже. Это верно ровно до тех пор, пока её так же метит передний
   * край: `bin/flang.mjs`, `markMeasure`, один раз на все команды. А стоит
   * отметка там внутри `try/catch`, который ЛЮБУЮ беду глотает и молча
   * возвращает непомеченную программу.
   *
   * Что будет, если она оттуда пропадёт, измерено изъятием, а не додумано: 105
   * тестов (`failures`, `conc`, `measure`, `cli-test-checks`) остаются
   * ЗЕЛЁНЫМИ — они метят сами, — а `flang test` на `measure.flang` начинает
   * считать без сторожа: «дробь роняет процесс мерой» досчитывает делитель
   * 1.7763568394002505e-15 вместо отказа, надзор не принимает ни одного решения
   * из ожидаемого одного. То есть единственным, кто это заметил бы, был сам
   * пример — и только если его кто-нибудь прогонит НАСТОЯЩИМ CLI.
   *
   * Поэтому тест зовёт не библиотеку, а команду: `node flang/bin/flang.mjs test
   * flang/conc/examples/measure.flang`. Это единственное место, где сверяется
   * передний край целиком; всё остальное в файле — про множество отказов.
   */
  /* Провалившийся `flang test` выходит ненулевым кодом и печатает отчёт в
     stderr, а `execFileSync` на ненулевом коде бросает. Ловим и берём отчёт из
     беды: иначе красный сказал бы «команда упала», а не ЧЕМ она упала. */
  let итог
  try {
    итог = execFileSync(
      process.execPath,
      [`${корень}flang/bin/flang.mjs`, "test", `${корень}flang/conc/examples/measure.flang`],
      { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    )
  } catch (беда) {
    итог = `${беда.stdout ?? ""}${беда.stderr ?? ""}`
  }
  const отчёт = JSON.parse(итог)
  assert.equal(отчёт.valid, true, итог)
  assert.equal(отчёт.failed, 0, итог)
  /* Прогон, который без отметки врёт, назван поимённо: он и есть предмет. */
  const дробь = отчёт.results.find((р) => String(р.run ?? "").startsWith("дробь роняет процесс мерой"))
  assert.ok(дробь, `прогон про меру пропал из примера — тест перестал что-либо стеречь: ${итог}`)
  assert.equal(дробь.passed, true, итог)
  assert.equal(дробь.решений, 1, "надзор обязан принять ровно одно решение — перезапуск после FLANG_MEASURE")
})

