/**
 * Прогон ТОЙ ЖЕ программы, какую запускает пользователь.
 *
 * Отметку меры кладёт передний край — `bin/flang.mjs`, `markMeasure`, один раз
 * на все команды (`run`, `test`, `emit`, `repl`), — а сторожа по ней ставит
 * вычислитель (`interpret.mjs`, `guardDescent`). Значит прогон от ГОЛОГО
 * разбора — это прогон программы без сторожей вовсе, то есть не той, что видит
 * CLI. Ровно этим сторож замкнутости в конце файла был слеп по построению; его
 * прозрели 12 августа, а прогоны выше остались сырыми, и правило стало
 * действовать в одном месте файла из двух.
 *
 * Поэтому правило теперь одно на файл: любой прогон идёт через эту функцию.
 * Программе без числовой меры отметка не добавляет ничего — `markMeasureGuards`
 * возвращает ТОТ ЖЕ объект (`totality.mjs`), — значит уравнивание бесплатно там,
 * где меры нет, и обязательно там, где она есть: «фиб» ниже стережётся
 * постоянным шагом, и её прогон гонял программу, которой не бывает у
 * пользователя.
 *
 * Исключений два, и оба намеренные: «слепой» прогон в тесте шестого вида — там
 * непомеченная программа сама предмет сверки, — и сетка примеров в конце файла,
 * где отметка кладётся один раз на файл, снаружи цикла по семенам, ради времени.
 */
const запустить = (программа, прогон, настройки = {}) =>
  runConcurrent(markMeasureGuards(программа), прогон, настройки)

/** Прогнать первый прогон программы и вернуть его итог. */
function прогнать(текст) {
  const программа = parse(текст, "проба.flang")
  const беды = [
    ...checkTypes(программа).diagnostics,
    ...(checkTotality(программа)?.diagnostics ?? []),
  ].filter((д) => д.severity !== "warning")
  assert.deepEqual(беды, [], "программа обязана пройти проверки, иначе прогон ничего не показывает")
  return запустить(программа, программа.runs[0])
}

