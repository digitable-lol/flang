/**
 * Множество отказов процесса и полнота надзора — шаг Г1
 * (`flang/conc/RESILIENCE.md`, `flang/src/failures.mjs`).
 *
 * Это то место модели, где flang делает не то же, что OTP, а то, чего у OTP
 * быть не может. В Erlang множество отказов процесса открыто, поэтому супервизор
 * обязан быть механизмом общего назначения. Здесь оно замкнуто и вычислимо,
 * значит его можно свести с объявленной политикой ДО запуска и потребовать
 * покрытия.
 *
 * Проверяется здесь ровно то, без чего эта проверка была бы украшением.
 *
 * 1. Она КРАСНЕЕТ на поломке. Программа, чей процесс может упасть, а надзора над
 *    ним нет, отвергается — и та же программа с дописанной строкой надзора
 *    проходит. Обе половины обязательны: проверка, которая не падала на
 *    поломке, ничего не стережёт, а проверка, которая падает всегда, стережёт
 *    от работы.
 *
 * 2. Перечисление видов отказа — не список из документа, а три прогона.
 *    На каждый вид есть программа, которая им падает, и код отказа сверяется с
 *    тем, что выдал планировщик. Список, переписанный из контракта и никем не
 *    предъявленный, разошёлся бы с планировщиком молча — и разошёлся: контракт
 *    называет отказом деление на ноль, которого не бывает (ниже).
 *
 * 3. Список частичных встроенных форм сверяется с `builtins.mjs`, а не с
 *    памятью автора. Восьмая партиальная форма, добавленная завтра, обязана
 *    быть названа тестом, а не тихо выпасть из анализа.
 *
 * 4. Названа ДЫРА: тотальный обработчик тоже может отказать, и этого вида нет
 *    ни в контракте, ни в анализе. Тест на неё зелёный не потому, что дыры нет,
 *    а потому, что он её предъявляет: закрыть её нечем до шага В3.
 */
