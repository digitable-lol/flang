test("вид шестой — «мера не убыла»: обработчик, доказанный числовой мерой", () => {
  /*
   * Шестой вид, и он приехал так же, как пятый: не рассуждением, а прогоном.
   * Доказательство по числовой мере верно для ЧИСЕЛ, а числа языка IEEE-754:
   * остатки пары (φ, 1) убывают строго, ограничены снизу и не кончаются никогда,
   * а `x минус 1` при большом |x| равен x. Поэтому понижение ставит на такой
   * вызов сторожа, и `FLANG_MEASURE` — настоящий отказ настоящего процесса.
   *
   * Вид назван ВТОРЫМ, а не единственным, и это не недоделка: у обработчика,
   * стережённого мерой, оценка витков отсутствует (`bounded.mjs` рекурсию по
   * числу не умеет), поэтому достижим ещё и предел витков планировщика. Ровно на
   * этом совпадении непокрытость шестого вида и не бросалась в глаза: надзор
   * требовался всё равно. Совпадение исчезнет в день, когда оценка научится
   * числовой рекурсии, и тогда этот вид останется единственным.
   */
  const программа = parse(мерой, "проба.flang")
  assert.deepEqual(
    достижимыеОтказы(программа).get("П").map((о) => о.вид),
    [ВИДЫ_ОТКАЗА.ПРЕДЕЛ, ВИДЫ_ОТКАЗА.МЕРА],
  )
  const запись = достижимыеОтказы(программа).get("П")[1]
  assert.equal(запись.функция, "НОД", "вид обязан назвать функцию, а не процесс: чинить придётся её")
  assert.match(запись.почему, /объявленной мере «убывает» в вызове «НОД»/u)

  /* И прогон её роняет — тем самым кодом, который приписан виду. Программа
     гоняется ПОМЕЧЕННОЙ, потому что сторожа ставит отметка меры: непомеченная
     программа — это программа без сторожей, и на ней шестого вида не бывает
     вовсе (ровно этим сторож множества и был слеп). */
  const итог = запустить(программа, программа.runs[0])
  assert.deepEqual(итог.отказы.map((о) => о.код), [КОДЫ_ОТКАЗА[ВИДЫ_ОТКАЗА.МЕРА]])
  assert.match(итог.отказы[0].сообщение, /перестала быть целой/u)

  /* Непомеченная — тот же прогон не роняет ничего и досчитывает бессмыслицу:
     цепочка остатков сходится по IEEE-754 к нулю, и «наибольшим общим делителем»
     объявляется 1.7763568394002505e-15. Вот это и есть цена молчания.

     Единственное место файла, где `runConcurrent` зовётся напрямую и намеренно:
     здесь непомеченная программа — сам предмет сверки, а не способ запуска. */
  const слепой = runConcurrent(программа, программа.runs[0], {})
  assert.deepEqual(слепой.отказы, [])
  assert.equal(слепой.состояния["П"]["счёт"], 1.7763568394002505e-15)
})

