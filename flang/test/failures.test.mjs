    "  принимает «Весть»",
    "  обрабатывает «шаг»",
    "",
    "тотальная функция «шаг»",
    "  принимает сост: «Состояние», весть: «Весть»",
    "  возвращает «Отклик»",
    "  разбор весть",
    "    случай вариант «делить» с «на» как на",
    "      пусть х равно (1 делить на на)",
    "      запись «Отклик» с «состояние» равным (запись «Состояние» с «счёт» равным х) и «действия» равным []",
