test("«замкнуто» — не слово, а сетка: коды отказов всех примеров лежат в КОДАХ_ОТКАЗА", () => {
  /*
   * Сторож на само утверждение, ради которого написан весь файл. Виды отказа
   * названы словами, а планировщик кладёт в `отказы` КОДЫ, и до `КОДЫ_ОТКАЗА`
   * свести одно с другим было нечем: списки жили в разных файлах и разошлись бы
   * молча — ровно так и разошёлся `FLANG_PROCESS`.
   *
   * Гоняются все примеры конкурентности по сетке семян: чередование выбирает
   * семя, и отказ, который случается только на одном из них, обязан быть найден
   * не удачей. `FLANG_INTERNAL` в таблицу не входит намеренно — он не вид
   * отказа, а запасной код для того, что вычислитель бросил не диагностикой,
   * то есть признак дефекта реализации. Появится он здесь — тест покраснеет, и
   * это будет правильный красный.
   *
   * ── Почему `markMeasureGuards`, а не голый `parse` ──────────────────────────
   *
   * Здесь стоял голый `parse`, и сторож был СЛЕП ПО ПОСТРОЕНИЮ: передний край
   * (`bin/flang.mjs`, `markMeasure`) кладёт на программу отметки меры до всякого
   * прогона, вычислитель ставит по ним сторожа (`interpret.mjs` зовёт
   * `guardDescent`), и `FLANG_MEASURE` бывает только у ПОМЕЧЕННОЙ программы. То
   * есть сторож множества гонял не ту программу, которую запускает пользователь,
   * а меньшую — и один вид отказа не мог показаться ему ни на каком семени.
   * Разница не теоретическая: на `flang/examples/measure/binary-search.flang`
   * отметка растит программу с 6701 знака до 11218, на `euclid.flang` — с 2763
   * до 4663.
   *
   * И вторая половина того же дефекта: даже став зрячим, сторож ничего бы не
   * увидел, потому что числовой меры не было ни в одном примере каталога. Она
   * появилась — `measure.flang`, — и `FLANG_MEASURE` стал шестым видом отказа.
   */
  /* Каталогов ДВА, и второй заведён вместе с седьмым действием (`поручить`,
     `src/conc.mjs`). Урок этого файла — «шаг, который добавляет в язык новый
     способ отказать, обязан добавить его И СЮДА» — проверяется не абзацем, а
     тем, что программы со СЛУЖБАМИ гоняются этим самым сторожем: начни
     поручение ронять процесс кодом, которого нет в `КОДЫ_ОТКАЗА`, покраснеет
     здесь.
     Лежат службы отдельным каталогом, а не среди примеров, и причина названа в
     `flang/conc/sluzhby/chtenie.flang`: `conc/examples` целиком входит в
     побайтовый корпус самоприменения, а эталон парсера на flang выписывает
     словарь действий данными и знает шесть действий, а не семь. */
  const каталоги = [`${корень}flang/conc/examples`, `${корень}flang/conc/sluzhby`]
  const допустимые = new Set(Object.values(КОДЫ_ОТКАЗА))
  let встреченных = 0
  let программ = 0

  for (const каталог of каталоги) {
    for (const имя of readdirSync(каталог).filter((и) => и.endsWith(".flang"))) {
      const программа = markMeasureGuards(parse(readFileSync(`${каталог}/${имя}`, "utf8"), имя))
      программ += 1
      for (const прогон of программа.runs ?? []) {
        for (let семя = 1; семя <= 12; семя += 1) {
          const итог = runConcurrent(программа, { ...прогон, seed: семя }, {})
          for (const отказ of итог.отказы) {
            встреченных += 1
            assert.ok(
              допустимые.has(отказ.код),
              `${имя}, семя ${семя}: процесс «${отказ.процесс}» отказал кодом ${отказ.код}, ` +
                `которого нет ни в одном виде отказа. Либо вид не назван, либо это дефект рантайма`,
            )
          }
        }
      }
    }
  }
  assert.ok(встреченных > 0, "ни одного отказа не встретилось — сторож стерёг бы пустоту")
  /* Охват печатается: сторож, молча схлопнувшийся к одному каталогу, зеленел бы
     точно так же. */
  console.log(`программ с процессами: ${программ}, отказов сверено: ${встреченных}`)
})

