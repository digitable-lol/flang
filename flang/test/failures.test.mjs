test("непокрытый достижимый отказ — ошибка проверки, а покрытый молчит", () => {
  const беды = диагностики(непокрытая)
  const беда = беды.find((д) => д.code === UNCOVERED_CODE)
  assert.ok(беда, `ожидался ${UNCOVERED_CODE}, получено ${JSON.stringify(беды)}`)
  assert.equal(беда.severity, "error", "предупреждение здесь означало бы «знаем и разрешаем молча»")
  assert.ok(беда.message.includes("«Распорядитель»"), беда.message)
  assert.ok(беда.message.includes("элемент"), "диагностика обязана назвать, ЧЕМ процесс упадёт")

  /* Вторая половина обязательна ровно так же, как первая: проверка, которая
     краснеет и на исправном, стережёт от работы, а не от ошибки. */
  assert.deepEqual(диагностики(покрытая), [])
})

test("отвергнутая программа и правда падала: проверка предъявляет не догадку", () => {
  /* Без этого теста Г1 был бы утверждением о коде, а не о поведении: анализ
     сказал «может упасть», и надо показать, что процесс действительно падает
     тем самым кодом и остаётся мёртвым, когда решать о нём некому. */
  const программа = parse(непокрытая, "проба.flang")
  const итог = runConcurrent(программа, программа.runs[0], {})
  assert.deepEqual(итог.отказы.map((о) => [о.процесс, о.код]), [["Распорядитель", "FLANG_BUILTIN_ARGS"]])
  assert.deepEqual(итог.живые, [], "решать некому — процесс остаётся мёртвым")
  assert.deepEqual(итог.решения, [])

  /* А с надзором тот же отказ кончается решением, и процесс поднимается. */
  const сНадзором = parse(покрытая, "проба.flang")
  const второй = runConcurrent(сНадзором, сНадзором.runs[0], {})
  assert.deepEqual(второй.живые, ["Распорядитель"])
  assert.deepEqual(
    второй.решения.map((р) => [р.процесс, р.надзор, р.стратегия]),
    [["Распорядитель", "Зал", "перезапустить"]],
  )
})

