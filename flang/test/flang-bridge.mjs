/**
 * МОСТ JS → FLANG для обвязки тестов (пакет Ч385, задача 9960).
 *
 * Каждый `<имя>.flang` этого пакета устроен одним из двух способов:
 *
 *   • чистая функция без мира — зовётся `flang run <файл> --function «Имя»
 *     --args '{…}'`, доводы ПЛОСКИЙ объект скаляров (это ограничение самого
 *     `flang run`, не наше — списки и вложенные объекты он не принимает);
 *   • план ввода-вывода — зовётся `flang io <файл> --plan «Имя»`. Вход
 *     плана — файл «вход.json» РЯДОМ со скриптом: поля-поручения «Прочитать
 *     доводы» и «Прочитать переменную среды» в словаре языка ОБЪЯВЛЕНЫ (22
 *     поручения, `flang/cat/SPEC.md`), но нынешний `bootstrap/flang`
 *     (собран сегодня) не отвечает на них ничем, кроме «Сбой» кодом
 *     FLANG_IO_UNKNOWN — проверено прогоном на этом же дереве, зафиксировано
 *     в шапках самих `.flang`-файлов. Поэтому вход идёт файлом, а не
 *     доводами командной строки.
 *
 * Для плана путь поручений разрешается ОТ КАТАЛОГА САМОГО ФАЙЛА (SPEC,
 * «Ввод-вывод»: «пути поручений плана разрешаются относительно каталога
 * входного файла»), а не от текущего каталога хозяина, — значит вход.json
 * обязан лежать РЯДОМ со скриптом. Параллельным прогонам нельзя делить один
 * такой каталог, поэтому каждый вызов заводит свой временный каталог, копирует
 * туда файл `.flang` и вход.json, и убирает каталог за собой в конце — той же
 * заботой, какой посвящён `tempdir.mjs` этого же пакета (но не через него:
 * средство, использующее себя же для собственной проверки, ничего не
 * проверяет).
 */
import { spawnSync } from "node:child_process"
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

import { путьДвоичного } from "../scripts/binary.mjs"

const ЗДЕСЬ = fileURLToPath(new URL(".", import.meta.url))

/** Ошибка отказа плана — несёт код и сырое сообщение, как «Сбой»/«Провал». */
export class ОтказПлана extends Error {
  constructor(код, сообщение) {
    super(`${код}: ${сообщение}`)
    this.name = "ОтказПлана"
    this.код = код
  }
}

/**
 * Прогнать план `имяПлана` из `<ЗДЕСЬ>/имяФайла` со входом `вход`
 * (сериализуется в вход.json). Возвращает разобранное значение
 * `«Конец работы»` — обычный JS-объект `{вариант, ...поля}` для варианта суммы,
 * или голое значение (число/строка/признак), если план вернул скаляр.
 *
 * Бросает `ОтказПлана` на «Провал» плана, и `Error` — на кривой вызов (код 2)
 * или сломанный инструмент (код 3): это те же три исхода, что в контракте
 * `flang io --help` («КОДЫ ВОЗВРАТА»), только различённые типом ошибки.
 */
export function прогнатьПлан(имяФайла, имяПлана, вход, настройки = {}) {
  const рабочий = mkdtempSync(join(tmpdir(), "flang-bridge-"))
  try {
    /* Скрипт копируется в «рабочий/test», а не прямо в «рабочий»: у каждого
       .flang этого пакета есть «использует … из "../stdlib/…"», и путь этот
       считается ОТ КАТАЛОГА САМОГО ФАЙЛА — скопируй файл без стойки, и
       «../stdlib» глядело бы мимо настоящей библиотеки. Симлинк, а не копия
       stdlib: файлы того же дерева, дублировать незачем, а обновление
       stdlib другим прогоном не должно требовать новой копии здесь. */
    const тестКаталог = join(рабочий, "test")
    mkdirSync(тестКаталог)
    symlinkSync(join(ЗДЕСЬ, "../stdlib"), join(рабочий, "stdlib"), "dir")
    copyFileSync(join(ЗДЕСЬ, имяФайла), join(тестКаталог, имяФайла))
    writeFileSync(join(тестКаталог, "вход.json"), JSON.stringify(вход ?? {}), "utf8")
    const итог = spawnSync(
      путьДвоичного(),
      ["io", join(тестКаталог, имяФайла), "--plan", имяПлана],
      { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, timeout: настройки.срок ?? 180_000 },
    )
    if (итог.error) throw итог.error
    if (итог.status === 0) {
      const отчёт = JSON.parse(итог.stdout)
      return распаковатьЗначение(отчёт.result)
    }
    let разобрано = null
    try {
      разобрано = JSON.parse(итог.stdout)
    } catch {
      /* вывод не json — беда до печати результата (кривой вызов, код 2) */
    }
    const сообщение = разобрано?.diagnostics?.[0]?.message ?? разобрано?.error ?? (итог.stderr || итог.stdout).trim()
    const код = разобрано?.diagnostics?.[0]?.code ?? "FLANG_IO"
    if (итог.status === 1) throw new ОтказПлана(код, сообщение)
    if (итог.status === null) {
      throw new Error(`flang io ${имяФайла} --plan "${имяПлана}" убит сигналом ${итог.signal} (истёк срок? снят снаружи?): ${сообщение}`)
    }
    throw new Error(`flang io ${имяФайла} --plan "${имяПлана}" — код ${итог.status}: ${сообщение}`)
  } finally {
    rmSync(рабочий, { recursive: true, force: true })
  }
}

/**
 * Прогнать чистую функцию `flang run` над `<ЗДЕСЬ>/имяФайла`. `доводы` —
 * ПЛОСКИЙ объект скаляров (строка/число/признак), как того требует сам
 * `flang run --args`.
 */
export function прогнатьФункцию(имяФайла, имяФункции, доводы = {}) {
  const итог = spawnSync(
    путьДвоичного(),
    ["run", join(ЗДЕСЬ, имяФайла), "--function", имяФункции, "--args", JSON.stringify(доводы)],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, timeout: 90_000 },
  )
  if (итог.error) throw итог.error
  if (итог.status !== 0) {
    throw new Error(`flang run ${имяФайла} --function "${имяФункции}" — код ${итог.status}: ${(итог.stderr || итог.stdout).trim()}`)
  }
  return распаковатьЗначение(JSON.parse(итог.stdout))
}

/**
 * `{"variant":"Имя","fields":{...}}` (форма `flang io`) и `{"вариант":"Имя",
 * ...плоские поля}` (форма `flang run`) — оба сводятся к одному плоскому
 * JS-объекту `{вариант, ...поля}`. Голый скаляр (число/строка/признак/список)
 * возвращается как есть — вариантов у него нет.
 */
function распаковатьЗначение(значение) {
  if (значение && typeof значение === "object" && !Array.isArray(значение)) {
    if (typeof значение.variant === "string") return { вариант: значение.variant, ...(значение.fields ?? {}) }
    if (typeof значение.вариант === "string") return значение
  }
  return значение
}
