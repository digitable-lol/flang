/**
 * Выборка файлов по образцу — на том, что есть в Node 20.
 *
 * `globSync` появился в `node:fs` только в Node 22. Пакет обещает Node ≥ 20
 * (`engines` в package.json), CI гоняет набор на 20, 22 и 24, и сам flang на
 * Node 20 работает целиком. А семь тестов импортировали `globSync` прямо из
 * `node:fs` — и на Node 20 не загружались вовсе: падал не отдельный случай, а
 * весь файл, до первой проверки. Обещание держит рантайм, ломала его оснастка.
 *
 * Здесь та же выборка на `readdirSync`, ровно в тех рамках, которые нужны
 * тестам:
 *
 *   `*`   — сколько угодно символов внутри одного сегмента пути;
 *   `?`   — один символ внутри сегмента;
 *   `**`  — сколько угодно сегментов, в том числе ни одного.
 *
 * Имена с точки не попадают ни в результат, ни в обход, если только сегмент
 * образца сам не начинается с точки, — иначе `**` полез бы в `.git`. Так же
 * ведёт себя `node:fs`.
 */
import { readdirSync } from "node:fs"
import { join } from "node:path"

/** Сегмент образца → проверка одного имени; `**` остаётся собой. */
function разобратьСегмент(сегмент) {
  if (сегмент === "**") return "**"
  const тело = сегмент.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, "[^/]*").replace(/\?/g, "[^/]")
  return { проверка: new RegExp(`^${тело}$`), сТочки: сегмент.startsWith(".") }
}

function подходит(сегмент, имя) {
  if (имя.startsWith(".") && !сегмент.сТочки) return false
  return сегмент.проверка.test(имя)
}

/** Чужой каталог может оказаться нечитаемым: это не повод ронять выборку. */
function содержимое(каталог) {
  try {
    return readdirSync(каталог, { withFileTypes: true })
  } catch {
    return []
  }
}

function обойти(сегменты, каталог, префикс, исключить, найденное) {
  const [первый, ...остальные] = сегменты
  if (первый === "**") {
    /* «Ни одного сегмента»: остаток образца сопоставляется прямо здесь. */
    if (остальные.length > 0) обойти(остальные, каталог, префикс, исключить, найденное)
    for (const запись of содержимое(каталог)) {
      if (!запись.isDirectory() || запись.name.startsWith(".")) continue
      const путь = префикс + запись.name
      if (исключить?.(путь)) continue
      обойти(сегменты, join(каталог, запись.name), путь + "/", исключить, найденное)
    }
    return
  }
  for (const запись of содержимое(каталог)) {
    if (!подходит(первый, запись.name)) continue
    const путь = префикс + запись.name
    if (исключить?.(путь)) continue
    if (остальные.length === 0) найденное.add(путь)
    else if (запись.isDirectory()) обойти(остальные, join(каталог, запись.name), путь + "/", исключить, найденное)
  }
}

/**
 * Пути, подходящие под образец, — относительно `cwd`, как у `node:fs`.
 *
 * `exclude` вызывается на каждом имени по пути обхода, включая каталоги: вернув
 * `true` на каталоге, отсекаешь всё поддерево — на этом держится отсечение
 * `node_modules`.
 */
export function globSync(образец, { cwd = process.cwd(), exclude } = {}) {
  const найденное = new Set()
  обойти(образец.split("/").map(разобратьСегмент), cwd, "", exclude, найденное)
  return [...найденное]
}
