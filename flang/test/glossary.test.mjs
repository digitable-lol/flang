/**
 * Сторож словаря обязан УМЕТЬ КРАСНЕТЬ.
 *
 * Сторож, который не краснеет, выглядит ровно как сторож, у которого всё
 * хорошо, — и это худший из возможных сторожей, потому что на него ссылаются.
 * Поэтому здесь не «словарь сходится» (это одна строка), а три проверки:
 *
 *   1. сегодня чисто — `--check` доволен записанным `docs/glossary.md`;
 *   2. слово добавили в таблицу, словарь не пересобрали → ОТКАЗ;
 *   3. понятие в таблице есть, пояснения в словаре нет → ОТКАЗ с именем.
 *
 * Случаи 2 и 3 подкладываются НАСТОЯЩИЕ: словарь перепечатывается в память с
 * подменённой таблицей, файл на диске не трогается.
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { KEYWORDS } from "../src/lexer.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))
const СТОРОЖ = "docs/site/glossary.mjs"
const СТРАНИЦА = "docs/glossary.md"

/** Запуск сторожа. Возвращает `{ код, вывод }`, не бросая при отказе. */
function запустить(...ключи) {
  try {
    const вывод = execFileSync(process.execPath, [СТОРОЖ, ...ключи], {
      cwd: КОРЕНЬ,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    })
    return { код: 0, вывод }
  } catch (беда) {
    return { код: беда.status ?? 1, вывод: `${беда.stdout ?? ""}${беда.stderr ?? ""}` }
  }
}

test("словарь сегодня сходится с таблицей поверхностей", () => {
  const { код, вывод } = запустить("--check")
  assert.equal(код, 0, `сторож словаря красный:\n${вывод}`)
  assert.match(вывод, /чисто/u)
})

test("словарь покрывает таблицу целиком — понятий столько же, сколько в KEYWORDS", async () => {
  const { разобратьТаблицу, проверитьПолноту } = await import("../../docs/site/glossary.mjs")
  assert.deepEqual(проверитьПолноту(), [], "у понятия таблицы нет пояснения в словаре")
  assert.equal(разобратьТаблицу().length, Object.keys(KEYWORDS).length)
})

test("КРАСНЕЕТ: слово в таблице есть, в записанном словаре нет", () => {
  const путь = КОРЕНЬ + СТРАНИЦА
  const было = readFileSync(путь, "utf8")
  try {
    // Стираем одну строку словаря — ровно то, что случится, если слово в
    // таблицу добавили, а `node docs/site/glossary.mjs` не прогнали.
    const порченый = было.replace(/^\| `модуль` \|.*$/mu, "")
    assert.notEqual(порченый, было, "образец для порчи не найден — проверку надо чинить, а не отключать")
    writeFileSync(путь, порченый)
    const { код, вывод } = запустить("--check")
    assert.equal(код, 1, "сторож НЕ покраснел на разошедшемся словаре")
    assert.match(вывод, /разошёлся с таблицей/u)
  } finally {
    writeFileSync(путь, было)
  }
  // И убеждаемся, что вернули как было.
  assert.equal(запустить("--check").код, 0, "после отката сторож обязан снова быть зелёным")
})

test("КРАСНЕЕТ: у понятия таблицы нет пояснения — и отказ называет понятие", async () => {
  const { проверитьПолноту } = await import("../../docs/site/glossary.mjs")
  // Подкладываем в таблицу понятие, которого в словаре заведомо нет.
  const выдуманное = "выдуманноеПонятиеДляПроверкиСторожа"
  KEYWORDS[выдуманное] = ["выдуманное слово"]
  try {
    const беды = проверитьПолноту()
    assert.ok(беды.length > 0, "сторож полноты НЕ покраснел на понятии без пояснения")
    assert.ok(
      беды.some((б) => б.includes(выдуманное)),
      `отказ обязан назвать понятие поимённо, а сказал: ${беды.join(" / ")}`,
    )
  } finally {
    delete KEYWORDS[выдуманное]
  }
  assert.deepEqual(проверитьПолноту(), [], "после отката сторож полноты обязан снова молчать")
})
