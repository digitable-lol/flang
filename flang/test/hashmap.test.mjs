/**
 * `flang/stdlib/hashmap.flang` — словарь хешем.
 *
 * Модуль обещает три вещи, и примерами внутри функций проверяется только
 * первая. Остальные две обещания ПРО ВСЕ ВХОДЫ, и примером их не поймать:
 *
 *   1. ЗНАЧЕНИЯ — что найдено то, что положено. Примеры это и делают.
 *   2. СЛОЖНОСТЬ — что цена от размера не зависит. Пример скажет, что ответ
 *      верен, и промолчит о том, что он обошёлся в обход всего словаря.
 *   3. НЕИЗМЕНЯЕМОСТЬ С РАЗДЕЛЕНИЕМ — что вставка не копирует дерево. Это
 *      вообще не про значение: два значения могут быть равны и при этом быть
 *      разными объектами, а разница между ними — вся память программы.
 *
 * Поэтому здесь меряется. Чем — тем же, чем в `stdlib.test.mjs`: не временем
 * (оно шумит вдвое от прогона к прогону), а ШАГАМИ ВЫЧИСЛИТЕЛЯ, которые
 * считаются двоичным поиском по `maxSteps` и воспроизводимы побайтово.
 *
 * Отдельно проверяется то, ради чего хеш написан на языке целиком: углы
 * IEEE-754. −0, ±∞, NaN и |x| за 2⁵³ приходят сюда АРГУМЕНТАМИ, а не из
 * исходника, — литерала для ∞ и NaN у языка нет, а типизация примера отвергает
 * нечисло. Та же оговорка и по той же причине стоит у суррогатных пар в
 * `tree.flang`.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { evaluate, valuesEqual } from "../src/interpret.mjs"
import { reifyValue } from "../src/builtins.mjs"
import { parse } from "../src/parser.mjs"
import { markMeasureGuards } from "../src/totality.mjs"
import { checkTotality } from "../src/totality.mjs"

const корень = fileURLToPath(new URL("..", import.meta.url))
const разобрать = (файл) =>
  markMeasureGuards(parse(readFileSync(`${корень}/stdlib/${файл}`, "utf8"), `stdlib/${файл}`))

const ХЕШЕМ = разобрать("hashmap.flang")
const ДЕРЕВОМ = разобрать("tree.flang")
const СПИСКОМ = разобрать("dictionary.flang")

const БОЛЬШОЕ = { maxSteps: 400_000_000, maxDepth: 200_000 }
const зови = (программа, имя, аргументы) => evaluate(программа, имя, аргументы, БОЛЬШОЕ)

const ключНомер = (номер) => `ключ-${String(номер).padStart(6, "0")}`
const набор = (сколько) => Array.from({ length: сколько }, (_, к) => ключНомер(к + 1))
const словарьИз = (ключи) => зови(ХЕШЕМ, "Словарь из ключей", { ключи })

/** Цена вычисления в шагах: наименьший `maxSteps`, при котором оно проходит. */
function шаговНа(программа, имя, аргументы) {
  const проходит = (предел) => {
    try {
      evaluate(программа, имя, аргументы, { ...БОЛЬШОЕ, maxSteps: предел })
      return true
    } catch (беда) {
      if (беда?.code === "FLANG_RECURSION_LIMIT") return false
      throw беда
    }
  }
  let низ = 1
  let верх = 1
  while (!проходит(верх)) {
    низ = верх + 1
    верх *= 2
  }
  while (низ < верх) {
    const середина = Math.floor((низ + верх) / 2)
    if (проходит(середина)) верх = середина
    else низ = середина + 1
  }
  return низ
}

/* ───────────────── тотальность: структурой и без сторожей ───────────────── */

test("hashmap.flang: тотальность доказана структурой, сторожей в рантайме ноль", () => {
  /*
   * Это ГЛАВНОЕ обещание модуля, и оно проверяется не глазами, а тем же
   * анализом, который печатает `flang check --proof`. Сторож — это проверка
   * убывания на каждом витке рекурсии; он появляется там, где завершение
   * доказано числовой мерой, а не структурой. Спуск по хешу — это деление
   * числа, и написанный в лоб он потребовал бы меры; поэтому обещание здесь
   * несут ПОЛЕ ВАРИАНТА и ХВОСТ СПИСКА, а число едет рядом как значение.
   */
  const итог = checkTotality(ХЕШЕМ)
  assert.ok(итог.ok, `анализ завершаемости не прошёл: ${JSON.stringify(итог.diagnostics)}`)
  assert.equal(итог.guards.length, 0, `сторожей быть не должно, а их ${итог.guards.length}`)
  assert.equal(
    ХЕШЕМ.functions.filter((ф) => ф.total).length,
    ХЕШЕМ.functions.length,
    "все функции модуля обязаны быть тотальными",
  )
  const структурой = new Set(итог.structures.map((р) => р.from))
  for (const имя of ["Развести", "Вложить", "Искать", "Искать признак", "Звенья словаря", "Глубина словаря"]) {
    assert.ok(структурой.has(имя), `«${имя}» обязана нестись структурой, а не чем-то ещё`)
  }
})

/* ───────────────── углы IEEE-754: хеш определён на всём носителе ───────── */

test("hashmap.flang: «В кольцо» определена на всём носителе числа", () => {
  /*
   * Требование к хешу — быть определённым НА ВСЁМ носителе, а носитель у числа
   * flang это IEEE-754 целиком. Ответ обязан быть целым вычетом из [0, модуль):
   * дробная цифра пути не совпала бы ни с одной из четырёх ветвей спуска, и
   * ключ потерялся бы молча, а −0 не совпало бы даже с нулём (`равен` — это
   * Object.is).
   */
  const углы = [
    0, -0, 1, -1, 2, -2, 0.5, -0.5, 3.9999, -3.9999,
    4, 4 ** 13, 4 ** 14, 100000006, 100000007, 100000008,
    -100000006, -100000007, -100000008, 2 ** 31, 2 ** 52, 2 ** 53, 2 ** 53 + 2, -(2 ** 53),
    1e15, 1e16, 1e21, 1e100, 1e308, -1e308, 5e-324, -5e-324, Number.MAX_VALUE, Number.EPSILON,
    Infinity, -Infinity, NaN,
  ]
  for (const значение of углы) {
    const название = Object.is(значение, -0) ? "-0" : String(значение)
    const вычет = зови(ХЕШЕМ, "В кольцо", { значение })
    assert.ok(Number.isInteger(вычет), `«В кольцо» от ${название} дала не целое: ${вычет}`)
    assert.ok(вычет >= 0 && вычет < 100000007, `«В кольцо» от ${название} вышла из кольца: ${вычет}`)
    assert.ok(!Object.is(вычет, -0), `«В кольцо» от ${название} дала −0`)

    const хеш = зови(ХЕШЕМ, "Хеш числа", { значение })
    assert.ok(Number.isInteger(хеш) && хеш >= 0 && хеш < 100000007, `«Хеш числа» от ${название}: ${хеш}`)

    /* Путь обязан быть четырнадцатью цифрами по основанию 4 И восстанавливать
       вычет: иначе он не путь, а набор чисел. */
    const путь = зови(ХЕШЕМ, "Путь хеша", { хеш: значение })
    assert.equal(путь.length, 14, `«Путь хеша» от ${название}: цифр ${путь.length}`)
    for (const цифра of путь) {
      assert.ok(Number.isInteger(цифра) && цифра >= 0 && цифра <= 3, `цифра вне [0,3] у ${название}: ${путь}`)
    }
    assert.equal(путь.reduce((с, ц, к) => с + ц * 4 ** к, 0), вычет, `путь не восстанавливает вычет у ${название}`)
  }
})

test("hashmap.flang: −0 и 0 — один вычет, ±∞ и NaN — три разных", () => {
  /* Ноль со знаком обязан слиться с нулём: иначе ключ, чей спуск оказался −0,
     не совпал бы ни с одной ветвью. А ±∞ и NaN обязаны РАЗОЙТИСЬ между собой:
     три разных значения носителя, слитые в одно, — это три ключа в одной
     грозди на ровном месте. */
  assert.equal(зови(ХЕШЕМ, "В кольцо", { значение: -0 }), зови(ХЕШЕМ, "В кольцо", { значение: 0 }))
  const особые = [Infinity, -Infinity, NaN].map((значение) => зови(ХЕШЕМ, "В кольцо", { значение }))
  assert.deepEqual(особые, [1, 2, 3])
  assert.equal(new Set(особые).size, 3)
})

test("hashmap.flang: хеш строки совпадает с «Хеш строки» из tree.flang", () => {
  /* Два словаря библиотеки считают хеш одной и той же формулой, и если они
     разойдутся, то разойдутся МОЛЧА: каждый останется верным сам себе, а
     программа, переехавшая с одного на другой, получит другое дерево и другие
     примеры. Формула записана дважды по причине, названной в шапке tree.flang
     (модули проверяются поодиночке), — значит и сверять их надо тестом. */
  const строки = [
    "", "a", "b", "ab", "ba", "я", "Я", "имя", "город", "страна", "ключ-000001",
    "Content-Type", "😀", "😀😀", "中文", "a😀b", " ", "\n", "ОЧЕНЬ-длинный-".repeat(9),
    ...набор(200),
  ]
  let расхождений = 0
  for (const текст of строки) {
    const хешем = зови(ХЕШЕМ, "Хеш ключа", { ключ: текст })
    const деревом = зови(ДЕРЕВОМ, "Хеш строки", { текст })
    if (!Object.is(хешем, деревом)) расхождений += 1
  }
  assert.equal(расхождений, 0, `на ${строки.length} строках разошлись ${расхождений} раз`)
})

