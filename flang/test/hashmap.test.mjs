test("hashmap.flang: словарь хешем и словарь списком отвечают одно и то же", () => {
  /* Быстрый словарь, отвечающий не то же самое, что медленный, — не ускорение,
     а замена смысла. Сверяются оба на одном наборе, включая отсутствующий
     ключ, пустой ключ и ключ, вытесненный повторной укладкой. */
  const пары = [
    ["имя", "Марат"], ["город", "Казань"], ["страна", "Россия"], ["имя", "Пётр"],
    ["", "пусто"], ["😀", "смайл"], ["Content-Type", "application/json"],
  ]
  let хешем = { variant: "Пустое место", fields: {} }
  let списком = []
  for (const [ключ, значение] of пары) {
    хешем = зови(ХЕШЕМ, "Положить в словарь", { словарь: хешем, ключ, значение })
    списком = зови(СПИСКОМ, "Положить", { словарь: списком, ключ, значение })
  }
  for (const искомый of ["имя", "город", "страна", "", "😀", "Content-Type", "нет такого", "ИМЯ"]) {
    assert.equal(
      зови(ХЕШЕМ, "Найти в словаре", { словарь: хешем, искомый, запасное: "—" }),
      зови(СПИСКОМ, "Взять или запасное", { словарь: списком, искомый, запасное: "—" }),
      `по ключу «${искомый}» словари разошлись`,
    )
    assert.equal(
      зови(ХЕШЕМ, "Есть ключ в словаре", { словарь: хешем, искомый }),
      зови(СПИСКОМ, "Есть ключ", { словарь: списком, искомый }),
      `о наличии ключа «${искомый}» словари разошлись`,
    )
  }
  assert.equal(зови(ХЕШЕМ, "Размер словаря", { словарь: хешем }), зови(СПИСКОМ, "Размер", { словарь: списком }))
  assert.deepEqual(
    [...зови(ХЕШЕМ, "Ключи словаря", { словарь: хешем })].sort(),
    [...зови(СПИСКОМ, "Ключи", { словарь: списком })].sort(),
  )
})

test("hashmap.flang: ни один ключ не теряется на сетке размеров", () => {
  for (const n of [0, 1, 2, 3, 5, 17, 64, 257, 1000]) {
    const ключи = набор(n)
    const словарь = словарьИз(ключи)
    assert.equal(зови(ХЕШЕМ, "Размер словаря", { словарь }), n, `n=${n}: потерялись ключи`)
    assert.deepEqual([...зови(ХЕШЕМ, "Ключи словаря", { словарь })].sort(), [...ключи].sort(), `n=${n}: не те ключи`)
    for (const ключ of ключи) {
      assert.equal(зови(ХЕШЕМ, "Найти в словаре", { словарь, искомый: ключ, запасное: "—" }), ключ)
    }
    for (const чужой of ["нет такого", "", "ключ-999999"]) {
      assert.equal(зови(ХЕШЕМ, "Есть ключ в словаре", { словарь, искомый: чужой }), false, `n=${n}: «${чужой}»`)
    }
  }
})

test("hashmap.flang: форма словаря зависит от набора ключей, а не от порядка вставки", () => {
  /* Путь ключа определяется его хешом, а не соседями, значит один и тот же
     набор обязан давать ПОБАЙТОВО то же значение. Для языка, где две программы
     сверяются побайтово, это не украшение, а свойство. */
  const ключи = набор(200)
  const прямо = словарьИз(ключи)
  const наоборот = словарьИз([...ключи].reverse())
  const вперемешку = словарьИз([...ключи].sort((а, б) => (а > б ? -1 : 1)))
  assert.deepEqual(JSON.parse(JSON.stringify(наоборот)), JSON.parse(JSON.stringify(прямо)))
  assert.deepEqual(JSON.parse(JSON.stringify(вперемешку)), JSON.parse(JSON.stringify(прямо)))
})

test("hashmap.flang: столкновение хеша не теряет ключей", () => {
  /* Гроздь заводится только на настоящем столкновении, и найти его случайным
     перебором дорого — поэтому оно СТРОИТСЯ: две строки, чей хеш совпал,
     ищутся по таблице хешей коротких ключей. Если такой пары не нашлось,
     проверять нечего, и тест об этом молчит вслух, а не притворяется зелёным. */
  const хеш = (текст) => зови(ХЕШЕМ, "Хеш ключа", { ключ: текст })
  const по = new Map()
  let пара = null
  let семя = 7
  for (let и = 0; и < 200000 && пара === null; и += 1) {
    семя = (семя * 48271) % 2147483647
    const текст = `с${семя.toString(36)}`
    const х = хеш(текст)
    if (по.has(х) && по.get(х) !== текст) пара = [по.get(х), текст]
    else по.set(х, текст)
  }
  assert.ok(пара !== null, "столкновения хеша не нашлось — гроздь осталась непроверенной")
  assert.equal(хеш(пара[0]), хеш(пара[1]))

  const ключи = [пара[0], пара[1], "имя", "город"]
  const словарь = словарьИз(ключи)
  assert.equal(зови(ХЕШЕМ, "Размер словаря", { словарь }), 4, "гроздь потеряла ключ")
  for (const ключ of ключи) {
    assert.equal(зови(ХЕШЕМ, "Найти в словаре", { словарь, искомый: ключ, запасное: "—" }), ключ, `«${ключ}»`)
  }
  /* Повторная укладка в гроздь обязана ВЫТЕСНЯТЬ, а не заводить второе звено. */
  const переписанный = зови(ХЕШЕМ, "Положить в словарь", { словарь, ключ: пара[0], значение: "новое" })
  assert.equal(зови(ХЕШЕМ, "Размер словаря", { словарь: переписанный }), 4)
  assert.equal(зови(ХЕШЕМ, "Найти в словаре", { словарь: переписанный, искомый: пара[0], запасное: "—" }), "новое")
  assert.equal(зови(ХЕШЕМ, "Найти в словаре", { словарь: переписанный, искомый: пара[1], запасное: "—" }), пара[1])
})

/* ───────────────── сложность: цена не зависит от размера ───────────────── */

test("hashmap.flang: глубина ограничена длиной хеша, а не числом ключей", () => {
  /* Четырнадцать цифр по основанию 4 покрывают всё кольцо (4¹⁴ > модуль),
     значит глубже четырнадцати спуск не уходит ни при каком n. Проверяется
     именно граница, а не логарифм: логарифм — это то, что получается, а
     константа — то, что обещано. */
  for (const n of [10, 100, 1000, 10000]) {
    const глубина = зови(ХЕШЕМ, "Глубина словаря", { словарь: словарьИз(набор(n)) })
    assert.ok(глубина <= 14, `n=${n}: глубина ${глубина}, а больше 14 быть не может`)
    assert.ok(глубина < n, `n=${n}: глубина ${глубина} — дерево выродилось в список`)
  }
})

test("hashmap.flang: поиск не дорожает с размером, а список дорожает как n", () => {
  /*
   * Замер, ради которого модуль написан. Числа на 13 августа 2026 (шаги
   * вычислителя, «Есть ключ» на ключ, который в словаре ЕСТЬ; у списка связей
   * цена одна на любой ключ — свёртка обходит все связи):
   *
   *      n | список | хешем | глубина
   *     10 |    167 |   434 |  6
   *    100 |   1607 |   441 |  6
   *   1000 |  16007 |   518 |  8
   *  10000 | 160007 |   623 | 10
   *
   * На десяти ключах список ВЫИГРЫВАЕТ, и это не дефект: равенство строк —
   * встроенная форма и один шаг, а здесь сначала считается хеш ключа. Перелом
   * около тридцати ключей.
   *
   * Точные числа не закрепляются — они поедут от любой правки вычислителя.
   * Закрепляется класс: при удесятерении размера список обязан подорожать
   * почти вдесятеро, а этот словарь — меньше чем вдвое.
   */
  const цена = (n) => {
    const ключи = набор(n)
    const словарь = словарьИз(ключи)
    const связи = ключи.map((к) => ({ variant: "Связь", fields: { ключ: к, значение: к } }))
    return {
      хешем: шаговНа(ХЕШЕМ, "Есть ключ в словаре", { словарь, искомый: ключНомер(n) }),
      списком: шаговНа(СПИСКОМ, "Есть ключ", { словарь: связи, искомый: ключНомер(n) }),
    }
  }
  const малое = цена(1000)
  const большое = цена(10000)

  assert.ok(
    большое.списком >= малое.списком * 8,
    `список обязан расти как n: ${малое.списком} → ${большое.списком} при удесятерении размера`,
  )
  assert.ok(
    большое.хешем < малое.хешем * 2,
    `словарь хешем обязан почти не расти: ${малое.хешем} → ${большое.хешем} при удесятерении размера`,
  )
  assert.ok(
    большое.хешем * 50 < большое.списком,
    `на 10000 ключах хеш обязан быть кратно дешевле: ${большое.хешем} против ${большое.списком}`,
  )
})

test("hashmap.flang: вставка не дорожает с размером", () => {
  const цена = (n) => шаговНа(ХЕШЕМ, "Положить в словарь", { словарь: словарьИз(набор(n)), ключ: "новичок", значение: "1" })
  const малая = цена(1000)
  const большая = цена(10000)
  assert.ok(большая < малая * 2, `вставка обязана почти не расти: ${малая} → ${большая}`)
})

/* ───────────────── неизменяемость с разделением ───────────────── */

/** Все узлы значения по ТОЖДЕСТВУ ссылок. */
function узлы(значение, собрано = new Set()) {
  if (значение === null || typeof значение !== "object" || собрано.has(значение)) return собрано
  собрано.add(значение)
  if (Array.isArray(значение)) for (const э of значение) узлы(э, собрано)
  else if (typeof значение.variant === "string") for (const п of Object.values(значение.fields)) узлы(п, собрано)
  else for (const п of Object.values(значение)) узлы(п, собрано)
  return собрано
}

/** Сколько ссылок физически записано при постройке узла. */
const ячеек = (узел) =>
  Array.isArray(узел)
    ? узел.length
    : Object.keys(typeof узел?.variant === "string" ? узел.fields : (узел ?? {})).length

test("hashmap.flang: вставка разделяет с прежним словарём почти всё", () => {
  /*
   * Неизменяемость в языке даром: значения и так не меняются. Обещание модуля
   * сильнее — что новый словарь НЕ КОПИРУЕТ старый, а делит с ним неизменённые
   * ветви. Проверяется тождеством ссылок: копия отличается от разделения
   * только этим, и другого способа их различить нет.
   *
   * Меряется в ЯЧЕЙКАХ, а не в объектах, и это существенно: список связей по
   * числу объектов разделяет не хуже (все связи остаются теми же, свежих
   * объектов ровно два), но в свежий список записывается n + 1 ссылка. Растёт
   * как n именно это число.
   */
  for (const n of [100, 1000, 10000]) {
    const прежний = словарьИз(набор(n))
    const новый = зови(ХЕШЕМ, "Положить в словарь", { словарь: прежний, ключ: "новичок", значение: "1" })

    const были = узлы(прежний)
    const стали = узлы(новый)
    const общих = [...стали].filter((у) => были.has(у)).length
    const свежие = [...стали].filter((у) => !были.has(у))
    const ячеекСвежих = свежие.reduce((с, у) => с + ячеек(у), 0)

    assert.ok(общих / были.size > 0.95, `n=${n}: разделено ${общих} из ${были.size} — слишком мало`)
    assert.ok(
      ячеекСвежих < 4 * 15 + 8,
      `n=${n}: вставка написала ${ячеекСвежих} ячеек, а обязана уложиться в глубину дерева`,
    )

    /* Прежний словарь обязан остаться прежним — иначе «неизменяемый» пустое
       слово. Сверяется значением, а не ссылкой: ссылка тут та же по построению. */
    assert.equal(зови(ХЕШЕМ, "Размер словаря", { словарь: прежний }), n)
    assert.equal(зови(ХЕШЕМ, "Есть ключ в словаре", { словарь: прежний, искомый: "новичок" }), false)
    assert.equal(зови(ХЕШЕМ, "Размер словаря", { словарь: новый }), n + 1)

    /* А теперь то же самое списку связей — ради числа, с которым сравнивать. */
    const связи = reifyValue(набор(n).map((к) => ({ variant: "Связь", fields: { ключ: к, значение: к } })))
    const списокНовый = зови(СПИСКОМ, "Положить", { словарь: связи, ключ: "новичок", значение: "1" })
    const былиС = узлы(связи)
    const ячеекС = [...узлы(списокНовый)].filter((у) => !былиС.has(у)).reduce((с, у) => с + ячеек(у), 0)
    /* У списка это число растёт КАК n — вот утверждение, которое закрепляется;
       у словаря хешем оно ограничено глубиной и уже проверено выше константой.
       Отношение сравнивается только там, где оно перестаёт быть вопросом
       констант, — на десяти тысячах ключей. */
    assert.ok(ячеекС >= n, `n=${n}: список обязан писать не меньше n ячеек, а написал ${ячеекС}`)
    if (n >= 10000) {
      assert.ok(
        ячеекС > ячеекСвежих * 100,
        `n=${n}: список обязан писать кратно больше ячеек: ${ячеекС} против ${ячеекСвежих}`,
      )
    }
  }
})

test("hashmap.flang: значения словаря — обычные значения, и равенство у них структурное", () => {
  /* Два словаря, собранные по-разному из одного набора, обязаны быть РАВНЫ по
     `valuesEqual` — тому же равенству, каким язык сравнивает всё остальное. */
  const ключи = набор(50)
  assert.ok(valuesEqual(словарьИз(ключи), словарьИз([...ключи].reverse())))
  assert.ok(!valuesEqual(словарьИз(ключи), словарьИз(ключи.slice(1))))
})
