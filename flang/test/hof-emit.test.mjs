test("на программах без функций-значений проход возвращает ТОТ ЖЕ объект", () => {
  /* Это и есть доказательство «печать не изменилась ни на байт»: бэкенду
     достаётся тот же объект, что и до правки, значит и выдача та же. Слабее
     формулировать нельзя — «структурно равный» пришлось бы сверять печатью
     всех программ во все восемь целей, а это часы на каждом прогоне.

     Корпус — все `.flang` репозитория, включая семь слоёв самоприменения:
     печать в C у них часть неподвижной точки. Модели `.fts` не берутся
     намеренно: у формы FTS поверхности для функции-значения нет вовсе
     (`compat.mjs` переводит закрытый список конструкций), значит и появиться
     новому узлу неоткуда.

     Исключений ДВА, и оба — файлы на функциях-значениях, которые проход
     ПЕРЕПИСЫВАЕТ по существу: `flang/stdlib/higher-order.flang` (сама
     библиотека) и `flang/proof/examples/corpus-hof.flang` (утверждения о её
     функциях при дословно перенесённых телах — `stdlib-claims.test.mjs`).
     Второе исключение — не ослабление утверждения, а его следствие: тело,
     перенесённое дословно, обязано вести себя дословно так же, в том числе под
     проходом. Раньше исключений не было вовсе, потому что и высшего порядка в
     репозитории быть не могло; теперь `self/` его понимает, библиотека лежит
     на своём месте. Что проход делает с ней — проверяет `stdlib-hof.test.mjs`. */
  const свои = ["flang/stdlib/higher-order.flang", "flang/proof/examples/corpus-hof.flang"]
  const файлы = globSync("flang/**/*.flang", { cwd: корень }).sort().filter((путь) => !свои.includes(путь))
  for (const путь of свои) {
    assert.ok(existsSync(join(корень, путь)), `${путь}: файла нет — исключение стало ложью`)
  }
  let проверено = 0
  for (const путь of файлы) {
    let ast
    try {
      ast = parse(readFileSync(join(корень, путь), "utf8"), путь)
    } catch {
      /* Файл, который сам по себе не разбирается (кусок с импортами), сюда не
         относится: у прохода на вход попадает уже разобранная программа. */
      continue
    }
    assert.equal(defunctionalize(ast), ast, `${путь}: проход подменил программу, а высшего порядка в ней нет`)
    проверено += 1
  }
  assert.ok(проверено >= 50, `корпус подозрительно мал: ${проверено} файлов`)
  console.log(`тождественность прохода: ${проверено} исходников репозитория`)
})

test("тег стал вариантом, применение — вызовом диспетчера, узлов высшего порядка не осталось", () => {
  const после = defunctionalize(программа)
  const найдено = { fnref: 0, apply: 0 }
  const обход = (узел) => {
    if (Array.isArray(узел)) return узел.forEach(обход)
    if (узел === null || typeof узел !== "object") return
    if (узел.kind === "fnref") найдено.fnref += 1
    if (узел.kind === "apply" && Object.hasOwn(узел, "fn")) найдено.apply += 1
    Object.values(узел).forEach(обход)
  }
  обход(после)
  assert.deepEqual(найдено, { fnref: 0, apply: 0 }, "после прохода программа обязана быть первопорядковой")

  const выбрать = после.functions.find((фн) => фн.name === "Выбрать")
  assert.deepEqual(выбрать.body.then, { kind: "construct", variant: "Удвоить", fields: {}, span: выбрать.body.then.span })
  const применить = после.functions.find((фн) => фн.name === "Применить")
  assert.equal(применить.body.kind, "call")
  assert.equal(применить.body.name, "применить 1")
  assert.deepEqual(применить.body.args.map((узел) => узел.name), ["ф", "х"])
})

test("диспетчер печатается на каждую арность свой, а случаи у него — теги из tags.mjs", () => {
  const после = defunctionalize(программа)
  const диспетчеры = после.functions.filter((фн) => фн.name.startsWith("применить "))
  assert.deepEqual(диспетчеры.map((фн) => фн.name), ["применить 1", "применить 2"])
  assert.deepEqual(диспетчеры.map((фн) => фн.params.length), [2, 3])
  /* Тег арности 1 в диспетчер арности 2 не попадает и наоборот: у функции
     столько аргументов, сколько объявлено, каррирования в языке нет. */
  assert.deepEqual(диспетчеры[0].body.cases.map((в) => в.pattern.name), ["Удвоить", "Утроить"])
  assert.deepEqual(диспетчеры[1].body.cases.map((в) => в.pattern.name), ["Сложить", "Умножить"])

  /* Списки случаев обязаны совпасть с тем, что видят анализ завершаемости и
     вычислитель: разойдись они — и напечатанное считало бы не то, что
     доказано. Источник у всех трёх один (`tags.mjs`), и вот это проверка, что
     он действительно один. */
  /* Спрашивается `tags.mjs` тем же способом, каким его спрашивает печать: не
     «объявлено ли имя», а «какие у функции параметры». С фазы 4 тег — это имя
     ВМЕСТЕ с набором захваченного, и предиката «объявлено ли» списку случаев
     уже не хватает: у одной функции тегов может быть несколько. */
  const параметры = new Map(программа.functions.map((фн) => [фн.name, (фн.params ?? []).map((п) => п.name ?? п)]))
  const теги = [...programTags(программа, (имя) => параметры.get(имя) ?? null).values()]
    .map((тег) => tagVariant(тег.name, тег.captured))
    .sort()
  const случаи = диспетчеры.flatMap((фн) => фн.body.cases.map((ветвь) => ветвь.pattern.name)).sort()
  assert.deepEqual(случаи, теги)
  assert.deepEqual(теги, ["Сложить", "Удвоить", "Умножить", "Утроить"])

  /* «Умножить» попадает в теги только из тела «Пробы»? Нет — из примера
     «Свести» приходит «Сложить», и это важный случай: тег из значения примера
     тоже обязан получить случай, потому что вычислитель такой тег принимает. */
  assert.ok(теги.includes("Сложить"))
})

