/**
 * Печать функций первого класса: дефункционализация одним проходом
 * (`flang/src/defunc.mjs`, обоснование — `flang/cat/HOF.md`, фаза 3).
 *
 * До этой фазы восемь бэкендов отказывались громко: `FLANG_PARSE: неизвестный
 * вид выражения «apply»`. Теперь высшего порядка не видит ни один из них —
 * перед печатью тег превращается в вариант, применение в вызов одного
 * диспетчера, и на вход бэкенду приходит программа тех же узлов, какие он
 * печатает с первого дня.
 *
 * Проверяется здесь ровно три вещи, и порядок их важности такой:
 *
 *   1. **Ничего не сломано.** Проход обязан быть ТОЖДЕСТВЕННЫМ на программах
 *      без функций-значений — не «давать такой же результат», а возвращать ТОТ
 *      ЖЕ объект. Тогда печать не может измениться ни на байт по построению, а
 *      не по счастливому совпадению, и неподвижная точка
 *      (`self-bootstrap.test.mjs`) остаётся сошедшейся. Проверяется на всём
 *      корпусе `.flang` репозитория.
 *
 *   2. **Печатают все восемь.** Модуль с функциями-значениями уходит во все
 *      восемь целей. Бэкенд, в котором забыли одну строку вызова прохода,
 *      падает здесь тем самым «неизвестный вид выражения «apply»» — это и есть
 *      защита от того, чтобы проход остался общим только на словах.
 *
 *   3. **Считают то же, что интерпретатор.** Напечатанное собирается настоящим
 *      тулчейном и гоняется на сетке входов: значения, коды и тексты ошибок
 *      обязаны совпасть с `interpret.mjs`. Это правило языка, и высший порядок
 *      его не отменяет.
 *
 * ── Одно расхождение, и оно названо ────────────────────────────────────────
 *
 * Тег, которого программа не строит, можно подать снаружи — и вычислителю, и
 * напечатанному прогонщику. Отказывают оба, но разными словами: вычислитель
 * говорит `FLANG_APPLY` с объяснением, что случая диспетчера нет, а
 * напечатанный `разбор` — `FLANG_MATCH_NOT_EXHAUSTIVE`. Совпасть они не могут:
 * «отказать вот с этим текстом» в языке невыразимо, а заводить ради этого
 * встроенную форму значило бы править восемь рантаймов — ровно то, чего проход
 * избегает. Расхождение проверяется дословно (тест «чужой тег отвергают обе
 * стороны»), случается только на входе, который проверка типов не пропустила
 * бы, и на значениях, которые программа способна построить сама, его нет.
 *
 * ── Почему исходник лежит здесь, а не в `flang/examples/` ──────────────────
 *
 * Раньше причина была запретительной: ни одна программа репозитория не вправе
 * использовать функции-значения, пока `self/` их не понимает (POLY.md, HOF.md).
 * Запрет снят — самоприменение понимает, и библиотека переехала в
 * `flang/stdlib/higher-order.flang`.
 *
 * Причина осталась другая, и она про сам тест: модуль ниже написан НЕ для
 * пользы, а для полноты — в нём все способы взять функцию значением и ровно
 * две арности, потому что диспетчер печатается на каждую арность свой. Такой
 * программе место рядом с проверкой, а не в каталоге примеров, который читают
 * как образец для подражания.
 *
 * ── Тулчейны ───────────────────────────────────────────────────────────────
 *
 * Сборка идёт там, где компилятор есть: C (gcc и clang), Java, Elixir, Rust,
 * Python. Печать в JavaScript проверяется всегда — модуль импортируется прямо в
 * этот процесс. Отсутствующий тулчейн — честный пропуск через
 * `missingToolchain`, а `FTS_REQUIRE_TOOLCHAINS` превращает пропуск в падение.
 * Go и .NET печатаются, но не собираются: сверка их печати идёт в
 * `emit-go.test.mjs` и `emit-csharp.test.mjs` там, где тулчейн есть.
 *
 * Запуск: node --test flang/test/hof-emit.test.mjs
 */
