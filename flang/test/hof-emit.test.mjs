test("чужой тег отвергают обе стороны — разными словами, и это записано", (t) => {
  const бинарь = findExecutable("gcc") ?? findExecutable("clang")
  if (бинарь === null) return missingToolchain(t, "c", "нет gcc/clang")

  const { каталог, файлы } = напечатать(emitC)
  const сборка = spawnSync(
    бинарь,
    [...ФЛАГИ_C, ...файлы.filter((ф) => ф.path.endsWith(".c")).map((ф) => ф.path), "-o", "flang_cli", "-lm"],
    { cwd: каталог, encoding: "utf8" },
  )
  assert.equal(сборка.status, 0, `компилятор не собрал напечатанное:\n${сборка.stderr}`)

  const запросы = [
    { fn: "Применить", args: [закодировать(тег("Выбрать")), закодировать(7)] },
    { fn: "Применить", args: [закодировать(7), закодировать(7)] },
  ]
  const ответы = построчно(
    execFileSync(join(каталог, "flang_cli"), {
      input: `${запросы.map((з) => JSON.stringify(з)).join("\n")}\n`,
      encoding: "utf8",
    }),
    запросы.length,
  )

  /* Вычислитель объясняет, почему случая нет; напечатанный `разбор` говорит,
     что значение не покрыто. Отказывают оба, и это главное: доказанная
     тотальность не обходится ни там, ни там. */
  const первый = исход(() => interpret(программа, "Применить", [тег("Выбрать"), 7]))
  assert.equal(первый.ok, false)
  assert.equal(первый.code, "FLANG_APPLY")
  assert.match(первый.message, /ни одно место программы не берёт эту функцию значением/u)
  assert.equal(ответы[0].ok, false)
  assert.equal(ответы[0].code, "FLANG_MATCH_NOT_EXHAUSTIVE")
  assert.match(ответы[0].message, /Выбрать/u)

  const второй = исход(() => interpret(программа, "Применить", [7, 7]))
  assert.equal(второй.ok, false)
  assert.equal(второй.code, "FLANG_APPLY")
  assert.match(второй.message, /применять можно только функцию/u)
  assert.equal(ответы[1].ok, false)
  assert.equal(ответы[1].code, "FLANG_MATCH_NOT_EXHAUSTIVE")
})
