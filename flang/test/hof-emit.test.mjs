/* Имя экспорта — тот же `camel`, каким его считает бэкенд. */
const экспорт = (имя) => {
  const ident = camel(имя)
  return /^[A-Za-z_$]/u.test(ident) ? ident : `_${ident}`
}

/**
 * Переносит значение интерпретатора в представление напечатанного модуля.
 *
 * У модуля свой класс варианта (`$FlangVariant`), и `instanceof` чужой объект
 * не признаёт — это устройство бэкенда JS, а не следствие высшего порядка
 * (`emit-js.test.mjs` переносит значения тем же способом). Для тега это
 * означает ровно то, что обещала дефункционализация: тег строится ЭКСПОРТОМ
 * КОНСТРУКТОРА ВАРИАНТА, как любой другой вариант.
 */
function перенести(модуль) {
  const обход = (значение) => {
    if (Array.isArray(значение)) return значение.map(обход)
    if (значение !== null && typeof значение === "object") {
      if (вариантПохож(значение)) {
        const конструктор = модуль[pascal(значение.variant)]
        assert.equal(typeof конструктор, "function", `модуль не экспортирует конструктор «${значение.variant}»`)
        const поля = {}
        for (const [к, з] of Object.entries(значение.fields)) поля[к] = обход(з)
        return конструктор(поля)
      }
      const запись = {}
      for (const [к, з] of Object.entries(значение)) запись[к] = обход(з)
      return запись
    }
    return значение
  }
  return обход
}

test("напечатанное в JavaScript считает то же, что интерпретатор", async () => {
  const { файлы } = напечатать(emitJs)
  const путь = join(рабочий, `js-${счётчик}.mjs`)
  writeFileSync(путь, файлы[0].content, "utf8")
  const модуль = await import(pathToFileURL(путь).href)
  const перенос = перенести(модуль)

  let сверено = 0
  ;[...СЕТКА, ЧУЖОЙ].forEach(([имя, аргументы], и) => {
    const функция = модуль[экспорт(имя)]
    assert.equal(typeof функция, "function", `модуль не экспортирует «${имя}»`)
    if (и === СЕТКА.length) {
      /* Чужой тег в JS не построить вовсе: конструктора «Выбрать» модуль не
         экспортирует, потому что тегом эта функция нигде не берётся. Это и
         есть обещанное «построить чужой нечем» — здесь оно видно прямо.
         Поэтому подаётся обычный объект той же формы, и модуль отвергает его
         как значение не того вида. */
      assert.equal(модуль[pascal("Выбрать")], undefined)
      const чужое = исход(() => функция({ variant: "Выбрать", fields: {} }, 7))
      assert.equal(чужое.ok, false, "JS: чужой тег обязан быть отвергнут")
      return
    }
    const напечатанное = исход(() => функция(...аргументы.map(перенос)))
    assert.ok(
      тотЖеИсход(СВИДЕТЕЛЬ_БИБЛИОТЕКИ[и], напечатанное),
      `JS: «${имя}» на входе ${JSON.stringify(аргументы.map(закодировать))}: ` +
        `интерпретатор дал ${описать(СВИДЕТЕЛЬ_БИБЛИОТЕКИ[и])}, напечатанное дало ${описать(напечатанное)}`,
    )
    сверено += 1
  })
  assert.ok(сверено >= 90, `сетка слишком редкая: ${сверено}`)
  console.log(`JavaScript: сверено ${сверено} точек`)
})

