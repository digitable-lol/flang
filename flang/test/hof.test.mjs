/* ────────── тег снаружи: единственная дыра, которую анализ закрыть не мог ── */

/**
 * Комбинатор Ω на одних тотальных функциях — то, ради чего вычислитель проверяет
 * тег, а не только его арность.
 *
 * `я.ф от я` применяет функцию из поля записи к самой записи. Если тег «Ω»
 * строится в программе, анализ видит ребро «Ω» → «Ω» и отказывает: аргумент не
 * убывает. Если не строится — программа честно тотальна, но снаружи можно
 * подать `{ ф: тег («Ω») }`, и это ЗАКОННОЕ по типам значение обесценило бы
 * доказанное. Оба конца проверяются здесь.
 */
const ОМЕГА = `модуль «Т»

объект «Ящик»
  ф: функция из «Ящик» в число

тотальная функция «Ω»
  принимает я: «Ящик»
  возвращает число
  я.ф от я
`

test("Ω, построенная в программе, отвергается анализом", () => {
  const программа = parse(`${ОМЕГА}
тотальная функция «Пуск»
  принимает х: число
  возвращает число
  «Ω» от (запись «Ящик» с ф равным функция «Ω»)
`)
  assert.deepEqual(коды(checkTypes(программа)), [])
  assert.match(беды(программа).join("\n"), /не убывает/u)
  assert.equal(checkTotality(программа).total.has("Ω"), false)
})

test("Ω, поданная снаружи тегом, не применяется: такого случая у диспетчера нет", () => {
  /* Тега «Ω» программа не строит, значит доказательство её тотальности верно —
     и обязано остаться верным. Вычислитель отказывает ровно там, где отказал бы
     напечатанный код: в `switch` нет случая, которого не построила программа. */
  const программа = parse(ОМЕГА)
  assert.deepEqual(коды(checkTypes(программа)), [])
  assert.deepEqual(беды(программа), [])
  assert.ok(checkTotality(программа).total.has("Ω"))

  assert.throws(
    () => evaluate(программа, "Ω", { я: { ф: { variant: "Ω", fields: {} } } }),
    (беда) => беда.code === "FLANG_APPLY" && /ни одно место программы не берёт/u.test(беда.message),
  )
})

