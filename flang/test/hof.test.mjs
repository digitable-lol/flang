test("тип функции читается словами и попадает в AST одним узлом", () => {
  const ast = parse(`${УДВОИТЬ}
тотальная функция «Применить»
  принимает ф: функция из числа в число, х: число
  возвращает число
  ф от х
`)
  assert.deepEqual(ast.functions[1].params[0].type, {
    kind: "fn",
    params: [{ kind: "number" }],
    returns: { kind: "number" },
  })
})

test("аргументов у типа функции может быть сколько угодно, включая ноль", () => {
  const ast = parse(`${УДВОИТЬ}
тотальная функция «Ф»
  принимает а: функция из числа и строки в признак, б: функция в число
  возвращает число
  0
`)
  const [а, б] = ast.functions[1].params
  assert.deepEqual(а.type.params, [{ kind: "number" }, { kind: "string" }])
  assert.deepEqual(а.type.returns, { kind: "flag" })
  assert.deepEqual(б.type, { kind: "fn", params: [], returns: { kind: "number" } })
})

test("стрелочная запись даёт тот же ТИП, что словесная, хотя узел у неё свой", () => {
  const тело = (запись) => `${УДВОИТЬ}
тотальная функция «Ф»
  принимает ф: ${запись}
  возвращает строка
  ф от 1
`
  /* В AST записи две, и это долг, а не замысел: стрелочный узел `{from, to}`
     сверяется побайтово с тем, что строит `self/parser.flang`, а тот новой
     формы не знает. Сводится долг в `normalizeType`, и наружу выходит один
     тип — проверяется тем, что обе записи дают одну и ту же диагностику с
     одним и тем же названием типа. */
  assert.deepEqual(parse(тело("функция из числа в строку")).functions[1].params[0].type, {
    kind: "fn",
    params: [{ kind: "number" }],
    returns: { kind: "string" },
  })
  assert.deepEqual(parse(тело("число → строка")).functions[1].params[0].type, {
    kind: "fn",
    from: { kind: "number" },
    to: { kind: "string" },
  })

  const словами = проверить(тело("функция из числа в строку"))
  const стрелкой = проверить(тело("число → строка"))
  assert.deepEqual(коды(словами), [])
  assert.deepEqual(коды(стрелкой), [])

  /* И то, что тип один: обе записи одинаково не пускают неверный аргумент. */
  const мимо = (запись) => проверить(`${УДВОИТЬ}
тотальная функция «Ф»
  принимает ф: ${запись}
  возвращает строка
  ф от "текст"
`)
  assert.deepEqual(тексты(мимо("функция из числа в строку")), тексты(мимо("число → строка")))
  assert.match(тексты(мимо("число → строка"))[0], /ожидался число, получен строка/u)
})

