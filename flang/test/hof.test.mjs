test("применение значения-функции не мешает доказать завершение", () => {
  const программа = parse(`${УДВОИТЬ}
тотальная функция «Отобразить всё»
  принимает элементы: список числа, ф: функция из числа в число
  возвращает список числа
  разбор элементов
    случай пусто
      то пустой список
    случай голова и хвост
      то добавить (ф от голова) к («Отобразить всё» от хвост и ф)
`)
  assert.deepEqual(коды(checkTypes(программа)), [])
  assert.deepEqual(беды(программа), [])
  /* Именно это и обещает дефункционализация: рекурсия по списку доказывается
     ровно как прежде, а применение внутри неё — обычное ребро в «Удвоить». */
  assert.ok(checkTotality(программа).total.has("Отобразить всё"))
})

test("тотальная функция, применяющая обычную, не доказывается — и причина названа", () => {
  const программа = parse(`модуль «Т»

функция «Крутить»
  принимает х: число
  возвращает число
  «Крутить» от х

тотальная функция «Применить»
  принимает ф: функция из числа в число, х: число
  возвращает число
  ф от х

функция «Пуск»
  возвращает число
  «Применить» от функция «Крутить» и 1
`)
  /* Без дефункционализации это неуловимо: «Применить» не называет «Крутить»
     нигде в своём теле. Ловится оно потому, что тег строится в программе, а
     программа видна целиком. */
  assert.match(беды(программа).join("\n"), /применяет значение-функцию «Крутить», а «Крутить» обычная/u)
  assert.equal(checkTotality(программа).total.has("Применить"), false)
})

test("вечный цикл через высший порядок отвергается", () => {
  const программа = parse(`модуль «Т»

тотальная функция «А»
  принимает ф: функция из числа в число, н: число
  возвращает число
  ф от н

тотальная функция «Б»
  принимает н: число
  возвращает число
  «А» от функция «Б» и н
`)
  /* «Б» зовёт «А», «А» применяет тег «Б» — цикл, в котором ничего не убывает.
     Программа действительно не завершается ни на одном входе. */
  assert.deepEqual(коды(checkTypes(программа)), [])
  const текст = беды(программа).join("\n")
  assert.match(текст, /в цикле «А» → «Б» не убывает/u)
  assert.equal(checkTotality(программа).total.size, 0)
})

