const проверить = (исходник) => checkTypes(parse(исходник))
const коды = (результат) => результат.diagnostics.map((d) => d.code)
const тексты = (результат) => результат.diagnostics.map((d) => d.message)
const беды = (программа) => checkTotality(программа).diagnostics.map((d) => d.message)

/** Заготовка: одна тотальная функция, которую есть за что взять значением. */
const УДВОИТЬ = `модуль «Т»

тотальная функция «Удвоить»
  принимает х: число
  возвращает число
  х плюс х
`

