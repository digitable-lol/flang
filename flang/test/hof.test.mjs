test("значение-функция и вызов по имени различаются позицией, а не словом", () => {
  const ast = parse(`${УДВОИТЬ}
тотальная функция «Применить»
  принимает ф: функция из числа в число, х: число
  возвращает число
  ф от х

тотальная функция «Проба»
  возвращает число
  «Применить» от функция «Удвоить» и 21
`)
  /* `ф от х` — применение значения: «ф» связано параметром.
     `«Применить» от …` — вызов: имя функции локальным связыванием не бывает. */
  assert.equal(ast.functions[1].body.kind, "apply")
  assert.equal(ast.functions[1].body.fn.name, "ф")
  assert.equal(ast.functions[2].body.kind, "call")
  assert.equal(ast.functions[2].body.args[0].kind, "fnref")
  assert.equal(ast.functions[2].body.args[0].name, "Удвоить")
})

