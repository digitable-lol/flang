test("подделка захватом отвергнута завершаемостью: типы её пропускают, FLANG_NOT_TOTAL — нет", () => {
  /* Подделка — программа, пытающаяся получить незавершающийся вызов через
     ЗАХВАТ. `«Крутить»` не завершается и честно объявлена обычной; тег её
     берётся не целиком, а с прижатым `шаг`, и подаётся туда, где ждут
     `функция из числа в число`. Удайся это — обещание тотальности осталось бы
     ложным, а счёт бы не кончился.

     Ценность подделки именно в том, что ТИПЫ ЕЁ ПРОПУСКАЮТ. До фазы 4 её
     отвергал `FLANG_APPLY` — частичного применения не было вовсе, — и проверка
     держалась на отказе по ФОРМЕ. Теперь форма законна, захват типизируется, и
     единственное, что стоит между этой программой и вечным счётом, — анализ
     завершаемости. Отсюда и утверждение: диагностик типов быть НЕ ДОЛЖНО, а
     `FLANG_NOT_TOTAL` — должен.

     Откуда берётся ребро. Тег «Крутить» с одним захваченным попадает в
     диспетчер ОСТАВШЕЙСЯ арности 1 — туда же, куда смотрит `ф от х` внутри
     «Применить», — и ребро «Применить» → «Крутить» проводит именно он. Это
     другая дорога, чем была до фазы 4 (тогда недоприменение считалось прямым
     вызовом), и проверка спрашивает ВЕРДИКТ, а не дорогу к нему. */
  const подделка = `модуль «Т»

функция «Крутить»
  принимает шаг: число, х: число
  возвращает число
  «Крутить» от шаг и х

тотальная функция «Применить»
  принимает ф: функция из числа в число, х: число
  возвращает число
  ф от х

тотальная функция «Проба»
  возвращает число
  «Применить» от (функция «Крутить» с шаг равным 1) и 5
`
  /* Типы молчат: захват законен и типизирован. Не молчали бы — подделка
     стерегла бы отказ по форме, а не доказуемость завершения. */
  assert.deepEqual(коды(проверить(подделка)), [], "захват обязан типизироваться — иначе подделка ничего не стережёт")

  const вердикт = checkTotality(parse(подделка))
  assert.ok(
    вердикт.diagnostics.some((д) => д.code === "FLANG_NOT_TOTAL"),
    "подделка обязана быть отвергнута завершаемостью: через захват в язык не должно быть входа для вечного счёта",
  )
  assert.equal(вердикт.total.has("Применить"), false, "«Применить» НЕ доказана тотальной — иначе подделка удалась")

  /* Тот же захват, но вокруг ТОТАЛЬНОЙ функции, доказывается. Строка стоит
     здесь затем, чтобы отказ выше нельзя было получить огрублением «объявить
     недоказанным всё, что применяет захваченный тег». */
  const честная = подделка
    .replace("функция «Крутить»\n", "тотальная функция «Крутить»\n")
    .replace("  «Крутить» от шаг и х", "  шаг плюс х")
  const добрый = checkTotality(parse(честная))
  assert.deepEqual(добрый.diagnostics, [])
  assert.equal(добрый.total.has("Применить"), true)
})

