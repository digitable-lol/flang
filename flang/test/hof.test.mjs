test("одна функция обоими тегами сразу: целиком и с захватом — это РАЗНЫЕ теги", () => {
  /* Случай, ради которого тег перестал быть одним лишь именем. «Сложить» взята
     и целиком (арность 2), и с прижатым «первое» (оставшаяся арность 1). Считай
     их одним тегом — и один из двух диспетчеров позвал бы функцию не с тем
     числом аргументов; объяви их одним вариантом — и напечатанная сумма имела бы
     два поля там, где у одного из тегов полей нет вовсе. */
  const программа = parse(`модуль «Т»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

тотальная функция «Свернуть»
  принимает элементы: список числа, ф: функция из числа и числа в число, начало: число
  возвращает число
  свёртка элементы начиная с начало как акк и эл → ф от акк и эл

тотальная функция «Применить»
  принимает ф: функция из числа в число, х: число
  возвращает число
  ф от х

тотальная функция «Проба»
  возвращает число
  («Свернуть» от [1, 2, 3] и функция «Сложить» и 0) плюс («Применить» от (функция «Сложить» с первое равным 10) и 0)
`)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.deepEqual(беды(программа), [])
  assert.equal(evaluate(программа, "Проба", {}), 16, "6 от свёртки и 10 от захвата")

  /* Понижение обязано развести их по РАЗНЫМ диспетчерам и объявить двумя
     вариантами: у одного поле «первое», у другого полей нет. */
  const после = defunctionalize(программа)
  const диспетчеры = после.functions.filter((фн) => фн.name.startsWith("применить "))
  assert.deepEqual(диспетчеры.map((фн) => фн.name), ["применить 1", "применить 2"])
  assert.deepEqual(диспетчеры[0].body.cases.map((в) => в.pattern.name), ["Сложить с первое"])
  assert.deepEqual(диспетчеры[1].body.cases.map((в) => в.pattern.name), ["Сложить"])

  const сумма = после.types.find((тип) => тип.kind === "sum")
  assert.deepEqual(
    сумма.variants.map((в) => [в.name, в.fields.map((поле) => поле.name)]),
    [["Сложить", []], ["Сложить с первое", ["первое"]]],
    "два варианта на одну функцию, и поля у них разные",
  )
})

test("захват берёт ЗНАЧЕНИЕ локального имени, а не замыкается над ним", () => {
  /* Здесь видно, чем захват отличается от замыкания, и почему он не возвращает
     в язык неразрешимость, ради ухода от которой сделана дефункционализация.

     `функция «Сложить» с второе равным («Удвоить» от н)` выглядит как замыкание
     над `н`. Замыканием оно не является: выражение считается ОДИН РАЗ, в момент
     постройки тега, и в тег едет ПОСЧИТАННОЕ ЧИСЛО — обычное поле обычного
     варианта. Ни окружения, ни отложенного вычисления в теге нет, поэтому
     множество тегов программы осталось конечным, а граф вызовов — известным
     целиком.

     Отсюда же и порядок вычисления: «Удвоить» зовётся один раз на постройку, а
     не на каждое применение тега. Напечатанный код считает так же, потому что
     там захват стоит полем конструктора. */
  const программа = parse(`${УДВОИТЬ}
тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

тотальная функция «Применить»
  принимает ф: функция из числа в число, х: число
  возвращает число
  ф от х

тотальная функция «Проба»
  принимает н: число
  возвращает число
  «Применить» от (функция «Сложить» с второе равным («Удвоить» от н)) и 5
`)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.deepEqual(беды(программа), [])
  assert.equal(evaluate(программа, "Проба", { н: 3 }), 11, "второе = удвоенное 3, дальше 5 плюс 6")
  assert.equal(evaluate(программа, "Проба", { н: 0 }), 5)

  /* Понижение обязано положить в поле ВЫРАЖЕНИЕ, переписанное как всякое
     другое, а не оставить его невычисленным где-то сбоку. */
  const после = defunctionalize(программа)
  const проба = после.functions.find((фн) => фн.name === "Проба")
  const тег = проба.body.args[0]
  assert.equal(тег.kind, "construct")
  assert.equal(тег.variant, "Сложить с второе")
  assert.equal(тег.fields["второе"].kind, "call", "захваченное осталось вызовом, а не свернулось в литерал")
})
