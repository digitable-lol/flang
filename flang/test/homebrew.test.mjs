/**
 * Формула Homebrew обязана указывать на СУЩЕСТВУЮЩИЙ архив со СВОИМ хешем.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * У формулы три числа про один и тот же релиз: версия, ссылка на архив и его
 * sha256. Разойтись они могут молча и разошлись: в v0.4.8 подняли версию и
 * ссылку, а `sha256` оставили от v0.4.7 — тот же
 * `3287ecb7ea1d789c1e6c4a5ca2e958656410825ec3e79ee475854681d96e6645`, что стоял
 * в формуле релизом раньше. Ни один тест этого не заметил, потому что слова
 * `sha256` во всём наборе не было вовсе: `grep -arln sha256` по flang/test и тестам инструментов
 * не давал ни одного попадания. Поймать это могли только `brew` на настоящей
 * установке или человек, сверивший две строки глазами, — то есть никто.
 *
 * Проверка тут нарочно НЕ ходит в сеть. Скачивание архива нельзя выполнить ни в
 * CI без выхода наружу, ни на машине без интернета, а проверка, которую нельзя
 * выполнить, не проверка (тот же довод, что у scripts/build-changelog.mjs про
 * примечания к релизам на GitHub). Поэтому улики берутся из репозитория:
 *
 *   1. ОДНА ВЕРСИЯ НА ТРИ МЕСТА. Тег в ссылке, имя архива в ссылке и `version`
 *      формулы обязаны совпасть с `package.json`. Это ловит «подняли версию, а
 *      ссылку забыли» и наоборот.
 *
 *   2. ХЕШ НЕ ЧУЖОЙ. История самой формулы помнит, какой sha256 объявлялся для
 *      какого релиза. Хеш, уже объявленный для ДРУГОЙ версии, — доказательство,
 *      что его не пересчитали: два разных архива побайтово равны не бывают.
 *      Улика лежит в git, подделать её задним числом нельзя.
 *
 *   3. ХЕШ СВЕРЕН С АРХИВОМ, КОГДА АРХИВ ЕСТЬ. Если рядом лежит
 *      `flang-<версия>-c.tar.gz`, его хеш обязан совпасть с объявленным. Если
 *      архива нет — проверка КРАСНЕЕТ, а не молчит: хеш, который никто не может
 *      сверить, — это хеш, который никто и не сверял. Ровно так эта беда и
 *      проехала.
 *
 * ── Что делать, когда проверка 3 красная ────────────────────────────────────
 * Она красная всё время, пока релиза нет. Это не придирка теста: пока архива
 * `flang-<версия>-c.tar.gz` не существует, правильного sha256 ВЗЯТЬ НЕГДЕ, и
 * любое число в формуле ничем не подтверждено. Лечится одним из двух:
 *
 *   • собрать архив (`node scripts/build-release-c.mjs`, затем упаковка тем
 *     самым `tar`, что записан в формуле над строкой `sha256`) и положить его в
 *     `output/` или рядом с репозиторием — тогда хеш считается из него. Команда
 *     упаковки записана в формуле целиком и не сокращается до `tar -czf`:
 *     простой `tar -czf` кладёт в архив время правки, права и владельца, то есть
 *     даёт разные байты при одном и том же содержимом, — а хеш, который нельзя
 *     повторить, нельзя и проверить;
 *   • указать готовый архив прямо:
 *     `FLANG_RELEASE_TARBALL=/путь/flang-0.4.8-c.tar.gz`.
 *
 * Сильнее было бы печатать sha256 в репозиторий тем же скриптом, что собирает
 * архив, и сверять формулу с напечатанным — как печатается журнал изменений и
 * указатель библиотеки. Тогда проверка стала бы зелёной и без архива под рукой.
 * Здесь этого нет умышленно: запись хеша — часть выпуска релиза, а релиза
 * v0.4.8 не существует, и придумывать за него нечего.
 *
 * Запуск: node --test flang/test/homebrew.test.mjs
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { existsSync, readFileSync, readdirSync } from "node:fs"
import { basename, join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const прочитать = (путь) => readFileSync(join(корень, путь), "utf8")

const ФОРМУЛА = "packaging/homebrew/flang.rb"
const формула = прочитать(ФОРМУЛА)
const пакет = JSON.parse(прочитать("package.json"))

/* ------------------------------------------------------------------- разбор */

/**
 * Три числа формулы. Каждое ищется построчно и обязано быть единственным: слово
 * `sha256` встречается и в прозе комментария над ним, а нам нужна объявленная
 * строка, а не рассказ о ней.
 */
export function разобратьФормулу(текст) {
  const одно = (образец, имя) => {
    const все = [...текст.matchAll(образец)]
    assert.equal(все.length, 1, `в формуле ${все.length} строк «${имя}», а нужна ровно одна`)
    return все[0][1]
  }
  const ссылка = одно(/^\s*url\s+"([^"]+)"/gmu, "url")
  return {
    ссылка,
    sha256: одно(/^\s*sha256\s+"([0-9a-f]{64})"/gmu, "sha256"),
    version: одно(/^\s*version\s+"([^"]+)"/gmu, "version"),
    тег: /\/download\/v([^/]+)\//u.exec(ссылка)?.[1] ?? null,
    архив: ссылка.split("/").at(-1),
  }
}

const объявлено = разобратьФормулу(формула)

const хешФайла = (путь) => createHash("sha256").update(readFileSync(путь)).digest("hex")

/**
 * Где искать архив релиза. В репозитории его нет и быть не должно: он весит
 * полмегабайта и собирается заново. Поэтому смотрим туда, куда его кладут, — и
 * даём указать путь прямо, чтобы проверку можно было выполнить и на машине, где
 * архив уже скачан.
 */
function архивыРядом() {
  const прямо = process.env.FLANG_RELEASE_TARBALL
  const найдено = new Map()
  if (прямо && existsSync(прямо)) найдено.set(basename(прямо), прямо)
  for (const каталог of [join(корень, "output/release-c"), join(корень, "output"), корень, join(корень, "..")]) {
    let имена
    try {
      имена = readdirSync(каталог)
    } catch {
      continue /* каталога нет — это не улика, а обычное дело */
    }
    for (const имя of имена) {
      if (/^flang-\d+\.\d+\.\d+-c\.tar\.gz$/u.test(имя) && !найдено.has(имя)) {
        найдено.set(имя, join(каталог, имя))
      }
    }
  }
  return найдено
}

/**
 * История формулы: какой sha256 объявлялся под какой версией. Читается из git,
 * потому что другого честного списка прошлых хешей в репозитории нет, а
 * рукописный список был бы второй копией той же правды.
 */
function прошлыеОбъявления() {
  const коммиты = execFileSync("git", ["-C", корень, "log", "--format=%H", "--", ФОРМУЛА], {
    encoding: "utf8",
  })
    .split("\n")
    .filter(Boolean)
  const было = new Map()
  for (const коммит of коммиты) {
    let текст
    try {
      текст = execFileSync("git", ["-C", корень, "show", `${коммит}:${ФОРМУЛА}`], {
        encoding: "utf8",
        maxBuffer: 8 * 1024 * 1024,
      })
    } catch {
      continue /* в том коммите формулы ещё не было */
    }
    const хеш = /^\s*sha256\s+"([0-9a-f]{64})"/mu.exec(текст)?.[1]
    const версия = /\/download\/v([^/]+)\//u.exec(текст)?.[1]
    /* У v0.4.0 стояло `sha256 :no_check` — сверять там нечего. */
    if (!хеш || !версия) continue
    /* Копятся ВСЕ объявления хеша, а не первое встреченное. Один хеш законно
       стоит под одной версией много коммитов подряд (v0.4.5 объявлялся дважды),
       и, оставив только новейшее, проверка не увидела бы, что тот же хеш стоял
       релизом раньше под другим номером, — то есть пропустила бы ровно ту беду,
       ради которой написана. */
    if (!было.has(хеш)) было.set(хеш, [])
    было.get(хеш).push({ версия, коммит })
  }
  return было
}

/* ----------------------------------------------------------------- проверки */

test("формула, ссылка и package.json говорят об одном релизе", () => {
  assert.match(пакет.version, /^\d+\.\d+\.\d+$/u)
  assert.equal(
    объявлено.version,
    пакет.version,
    `${ФОРМУЛА}: version «${объявлено.version}», а package.json объявляет ${пакет.version}`,
  )
  assert.equal(
    объявлено.тег,
    пакет.version,
    `${ФОРМУЛА}: ссылка ведёт на тег v${объявлено.тег}, а версия пакета ${пакет.version}`,
  )
  assert.equal(
    объявлено.архив,
    `flang-${пакет.version}-c.tar.gz`,
    `${ФОРМУЛА}: в ссылке архив «${объявлено.архив}», а версия пакета ${пакет.version}`,
  )
})

test("объявленный sha256 не повторяет хеш другого релиза", (t) => {
  let было
  try {
    было = прошлыеОбъявления()
  } catch (беда) {
    /* Неполный клон или отсутствующий git — не повод красить тест за чужую беду.
       Так же поступает с полной сверкой flang/test/changelog.test.mjs. */
    t.skip(`историю формулы прочитать нечем: ${беда.message}`)
    return
  }
  if (было.size === 0) {
    t.skip("в доступной истории нет ни одного прошлого объявления sha256 — клон неполный")
    return
  }

  /* git log идёт от новых к старым, поэтому самое раннее объявление — последнее
     в списке. Именно оно называет релиз, у которого хеш и был взят. */
  const чужие = (было.get(объявлено.sha256) ?? []).filter((где) => где.версия !== пакет.version)
  const самоеРаннее = чужие.at(-1)
  assert.ok(
    самоеРаннее === undefined,
    самоеРаннее
      ? `${ФОРМУЛА}: sha256 ${объявлено.sha256} уже объявлялся для релиза ` +
        `v${самоеРаннее.версия} (коммит ${самоеРаннее.коммит.slice(0, 7)}), а теперь стоит ` +
        `под v${пакет.version}. Два разных архива побайтово равны не бывают: хеш перенесли, ` +
        `а не пересчитали. Пересчитайте его по архиву flang-${пакет.version}-c.tar.gz.`
      : "",
  )
})

test("объявленный sha256 сверен с настоящим архивом", () => {
  const архивы = архивыРядом()
  const свой = архивы.get(`flang-${пакет.version}-c.tar.gz`)

  if (свой) {
    const посчитан = хешФайла(свой)
    assert.equal(
      посчитан,
      объявлено.sha256,
      `${ФОРМУЛА}: объявлен sha256 ${объявлено.sha256}, а у ${свой} он ${посчитан}`,
    )
    return
  }

  /* Архива своей версии нет. Прежде чем сказать «сверить нечем», посмотрим, не
     принадлежит ли объявленный хеш какому-нибудь другому архиву, лежащему
     рядом: тогда это не «нечем сверить», а прямая улика. */
  const чужой = [...архивы.entries()].find(([, путь]) => хешФайла(путь) === объявлено.sha256)
  const как =
    `Соберите архив: node scripts/build-release-c.mjs, затем упакуйте той командой tar, ` +
    `что записана в ${ФОРМУЛА} над строкой sha256 (простой tar -czf не годится: он кладёт в ` +
    `архив время правки и права, и хеш выйдет другим при том же содержимом). Положите архив в ` +
    `output/ или укажите готовый: FLANG_RELEASE_TARBALL=/путь/flang-${пакет.version}-c.tar.gz. ` +
    `Пока архива нет, правильный sha256 взять негде, и число в формуле ничем не подтверждено.`

  assert.fail(
    чужой
      ? `${ФОРМУЛА}: объявленный sha256 ${объявлено.sha256} — это хеш файла ${чужой[1]}, ` +
        `а не архива flang-${пакет.version}-c.tar.gz, которого нет нигде рядом. ${как}`
      : `${ФОРМУЛА}: sha256 ${объявлено.sha256} сверить нечем — архива ` +
        `flang-${пакет.version}-c.tar.gz нет ни в output/, ни рядом с репозиторием. ${как}`,
  )
})
