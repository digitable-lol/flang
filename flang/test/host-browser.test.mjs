/**
 * host-browser.test.mjs — приложение в браузере, прогнанное БЕЗ браузера.
 *
 * Страница, открытая руками, доказательством не является: её нельзя повторить,
 * нельзя запустить в CI и нельзя сравнить с прошлым разом. Поэтому здесь
 * подставной документ — объект с `querySelector`, `querySelectorAll` и
 * `addEventListener`, тридцать строк, — и настоящий хозяин браузера
 * (`src/host/browser.mjs`) работает с ним ровно так же, как с окном вкладки.
 *
 * Это тот же приём, каким `nodeHost` проверяется без сети (`fetch` подменяем):
 * граница честности проходит по одной функции, и если её можно подменить, то
 * прогон без рук возможен.
 *
 * ГЛАВНОЕ, что здесь проверено, — переворот цикла. `runPlan` тянущий: он сам
 * просит следующее поручение. Браузер толкающий: события зовут программу. Ниже
 * события ПРИХОДЯТ ИЗВНЕ, из `setTimeout` подставного окна, посреди работы
 * плана, и план их получает — потому что `runPlan` ждёт хозяина на `await`, а
 * `await` и есть инверсия управления. Ни одной строки исполнителя не тронуто.
 */

import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { browserHost } from "../src/host/browser.mjs"
import { runPlan } from "../src/io.mjs"
import { parse } from "../src/parser.mjs"

const ПРИЛОЖЕНИЕ = fileURLToPath(new URL("../../web/app/hailstone.flang", import.meta.url))

/**
 * Подставная страница: места и кнопки, и ничего больше.
 *
 * Не эмулятор браузера — ровно те четыре метода, которыми пользуется хозяин.
 * Больше и не нужно: если хозяину понадобится пятый, он появится здесь же, и
 * это будет видно в diff, а не спрятано за библиотекой в сорок мегабайт.
 */
function страница({ места = [], кнопки = [] } = {}) {
  const узлы = new Map()
  for (const имя of места) {
    узлы.set(`[данные-место="${имя}"]`, { textContent: "", getAttribute: () => имя })
  }
  const источники = кнопки.map((значение) => {
    const слушатели = []
    return {
      значение,
      слушатели,
      getAttribute: (что) => (что === "данные-событие" ? "кнопка" : что === "данные-значение" ? значение : null),
      addEventListener: (вид, что) => слушателиПополнить(слушатели, вид, что),
      textContent: значение,
      /* Пустое `value` — не выдумка ради полноты, а улика. У кнопки в HTML это
         свойство ЕСТЬ и оно пустая строка; хозяин сначала спрашивал его и
         потому получал от всякого нажатия пустоту. Подставная страница без
         `value` беду не ловила, и нашлась она в настоящем браузере
         (`web/app/probe.mjs`). Проверка, пропустившая беду, чинится вместе с
         бедой — иначе она пропустит её второй раз. */
      value: "",
    }
  })
  return {
    querySelector: (селектор) => узлы.get(селектор) ?? null,
    querySelectorAll: () => источники,
    нажать(значение) {
      const узел = источники.find((к) => к.значение === значение)
      assert.ok(узел !== undefined, `нет кнопки «${значение}»`)
      for (const { вид, что } of узел.слушатели) if (вид === "click") что()
    },
    экран: () => узлы.get('[данные-место="экран"]')?.textContent ?? null,
  }
}

function слушателиПополнить(куда, вид, что) {
  куда.push({ вид, что })
}

/**
 * Хозяин пробы: тот же `browserHost`, но с часами, идущими мгновенно.
 *
 * Две подмены, и обе про ВРЕМЯ, а не про поведение:
 *
 *   `отложить` срабатывает сразу. Настоящие 350 мс на такт сделали бы проверку
 *      медленной, а медленную проверку не гоняют. Срок при этом остаётся
 *      проверяемым: он приходит сюда числом от программы.
 *   срок 0 («жду человека без предела») превращается в 1 мс. Иначе прогон без
 *      рук встал бы навсегда: рук, которые нажмут, нет. Это не послабление
 *      хозяину — это единственное место, где «без предела» приходится
 *      ограничить, и оно названо вслух.
 */
function хозяинПробы(окно, ещё = {}) {
  const сроки = []
  const исполнить = browserHost({
    документ: окно,
    отложить: (что, через) => {
      сроки.push(через)
      return setTimeout(что, 0)
    },
    снять: (метка) => clearTimeout(метка),
    ...ещё,
  })
  const обёртка = async (поручение) => {
    if (поручение.variant === "Ждать событие" && Number(поручение.fields?.["срок"] ?? 0) === 0) {
      return await исполнить({ ...поручение, fields: { срок: 1 } })
    }
    return await исполнить(поручение)
  }
  обёртка.сроки = сроки
  return обёртка
}

/** Разобранная программа приложения — одна на все проверки файла. */
async function приложение() {
  return parse(await readFile(ПРИЛОЖЕНИЕ, "utf8"), { file: ПРИЛОЖЕНИЕ })
}

/**
 * Прогон приложения до заданного числа поручений.
 *
 * Плана без конца остановить нечем изнутри — у «Градин» нет ни одной ветки
 * `«Конец работы»`, и это не упущение, а честность: приложение кончается тогда,
 * когда закрывают вкладку. Поэтому останов приходит СНАРУЖИ, пределом
 * поручений, и `FLANG_IO_LIMIT` здесь — успешный конец прогона, а не беда.
 */
async function прогнать(программа, хозяин, поручений) {
  try {
    await runPlan(программа, "Градины", хозяин, { maxOrders: поручений })
    assert.fail("приложение обязано было упереться в предел: конца у него нет")
  } catch (беда) {
    assert.equal(беда.code, "FLANG_IO_LIMIT", `ждали предел, а получили: ${беда.message}`)
  }
}

test("приложение показывает начальное состояние, не дожидаясь человека", async () => {
  const программа = await приложение()
  const окно = страница({ места: ["экран"], кнопки: ["7"] })
  const хозяин = хозяинПробы(окно)
  await прогнать(программа, хозяин, 3)
  assert.equal(
    окно.экран(),
    "набор: 0\nчисло: 0\nшагов: 0\nвершина: 0\nбег: нет\nнаберите число и нажмите «пуск»",
  )
})

test("нажатие человека доходит до программы и меняет то, что на экране", async () => {
  const программа = await приложение()
  const окно = страница({ места: ["экран"], кнопки: ["2", "7", "пуск", "шаг", "сброс"] })
  const хозяин = хозяинПробы(окно)

  /* События толкаются ИЗВНЕ, из очереди макрозадач, пока план ждёт. Именно это
     и есть переворот: не программа спрашивает «что нажали», а нажатие будит
     программу. Задержки между нажатиями нет намеренно — хозяин обязан не
     потерять их, даже если человек быстрее плана. */
  setTimeout(() => {
    окно.нажать("2")
    окно.нажать("7")
    окно.нажать("пуск")
    окно.нажать("шаг")
  }, 0)

  await прогнать(программа, хозяин, 10)
  /* 27 → 82: нечётное взлетает втрое с единицей. Один шаг, вершина 82, и бег
     не включён — «шаг» двигает ровно на такт, ровно как обещано. */
  assert.equal(окно.экран(), "набор: 27\nчисло: 82\nшагов: 1\nвершина: 82\nбег: нет\nлетим")
})

test("часы будят план сами: «бег» считает без единого нажатия", async () => {
  const программа = await приложение()
  const окно = страница({ места: ["экран"], кнопки: ["6", "пуск", "бег"] })
  const хозяин = хозяинПробы(окно)

  setTimeout(() => {
    окно.нажать("6")
    окно.нажать("пуск")
    окно.нажать("бег")
  }, 0)

  await прогнать(программа, хозяин, 40)
  /* 6 → 3 → 10 → 5 → 16 → 8 → 4 → 2 → 1: восемь шагов, вершина 16, и бег
     остановился САМ, придя к единице. Это и есть «незавершаемость живёт в
     планировщике»: программа не крутила цикл, она каждый раз возвращала одно
     продолжение, а крутили её часы. */
  assert.equal(окно.экран(), "набор: 6\nчисло: 1\nшагов: 8\nвершина: 16\nбег: нет\nпришли к единице")
  assert.ok(
    хозяин.сроки.includes(350),
    `программа обязана была попросить срок 350 мс, а просила ${хозяин.сроки}`,
  )
})

test("нажатия, случившиеся пока план считал, не теряются", async () => {
  const программа = await приложение()
  const окно = страница({ места: ["экран"], кнопки: ["1", "2", "3"] })
  const хозяин = хозяинПробы(окно)

  /* Все три нажатия приходят ОДНИМ тактом, до того как план успел попросить
     хоть одно событие: подписка происходит на первом же «Ждать событие», а
     нажимают до неё и между витками. Копилка хозяина обязана их сберечь —
     иначе страница выглядела бы залипшей. */
  setTimeout(() => {
    окно.нажать("1")
    окно.нажать("2")
    окно.нажать("3")
  }, 0)

  await прогнать(программа, хозяин, 12)
  assert.equal(окно.экран(), "набор: 123\nчисло: 0\nшагов: 0\nвершина: 0\nбег: нет\nнабрано 123")
})

test("места на странице нет — отклик «Сбой», а не падение вкладки", async () => {
  const программа = await приложение()
  const окно = страница({ места: [], кнопки: ["1"] })
  const хозяин = хозяинПробы(окно)
  await assert.rejects(
    () => runPlan(программа, "Градины", хозяин, { maxOrders: 5 }),
    (беда) => {
      assert.equal(беда.code, "FLANG_IO_PLACE")
      assert.match(беда.message, /нет места «экран»/u)
      return true
    },
  )
})

test("хозяин браузера отвечает на КАЖДОЕ поручение словаря, и ни одно не остаётся без ответа", async () => {
  const { IO_TYPES } = await import("../src/io.mjs")
  const { variant } = await import("../src/builtins.mjs")
  const [поручение] = IO_TYPES
  const окно = страница({ места: ["экран"], кнопки: [] })
  const хозяин = browserHost({ документ: окно, seed: 7 })

  const поля = {
    "Прочитать файл": { путь: "нет.txt" },
    "Записать файл": { путь: "нет.txt", содержимое: "" },
    Запросить: { способ: "GET", адрес: "http://127.0.0.1:1/", тело: "" },
    "Текущее время": {},
    "Случайное число": {},
    Показать: { место: "экран", текст: "проба" },
    "Ждать событие": { срок: 1 },
    "Перечислить каталог": { путь: "." },
    "Запустить процесс": { программа: "echo", аргументы: [] },
    "Запустить процесс с вводом": { программа: "cat", аргументы: [], ввод: "" },
    "Открыть соединение": { адрес: "127.0.0.1", порт: 1 },
    "Принять соединение": { порт: 1 },
    "Прочитать из соединения": { соединение: 1 },
    "Ответить в соединение": { соединение: 1, содержимое: "" },
    "Прочитать октеты из соединения": { соединение: 1 },
    "Ответить октетами в соединение": { соединение: 1, октеты: [] },
  }
  /* Список полей ведётся руками, и сторож этого не прощает: словарь вырос —
     заполни. Иначе «хозяин ответил на всё» проверялось бы на подмножестве. */
  assert.deepEqual(
    поручение.variants.map((в) => в.name).filter((имя) => поля[имя] === undefined),
    [],
    "в словаре есть поручение, которого нет в таблице полей этой проверки",
  )
  const ответы = []
  const коды = {}
  for (const в of поручение.variants) {
    const отклик = await хозяин(variant(в.name, поля[в.name]))
    /* «Не знаю такого поручения» — расхождение хозяина со словарём, и оно
       обязано быть невозможным: набор закрыт, значит хозяин знает всё. */
    assert.notEqual(отклик.fields?.["код"], "FLANG_IO_UNKNOWN", `хозяин не знает «${в.name}»`)
    ответы.push(отклик.variant)
    коды[в.name] = отклик.fields?.["код"]
  }
  assert.equal(ответы.length, поручение.variants.length)
  /* Каждая нехватка вкладки названа СВОИМ кодом, а не общим отказом: программа
     вправе различать «нет файлов», «нет процессов» и «нет сырых сокетов» —
     упёршись в первое, она может попробовать другое. */
  assert.equal(коды["Прочитать файл"], "FLANG_IO_NO_FILES")
  assert.equal(коды["Перечислить каталог"], "FLANG_IO_NO_FILES")
  assert.equal(коды["Запустить процесс"], "FLANG_IO_NO_SPAWN")
  assert.equal(коды["Запустить процесс с вводом"], "FLANG_IO_NO_SPAWN")
  /* Сырых сокетов у вкладки нет, и подменить их `fetch`-ом или `WebSocket`-ом
     значило бы соврать в контракте: поручение просит байты, а не HTTP. */
  assert.equal(коды["Открыть соединение"], "FLANG_IO_NO_SOCKETS")
  assert.equal(коды["Принять соединение"], "FLANG_IO_NO_SOCKETS")
  assert.equal(коды["Прочитать из соединения"], "FLANG_IO_NO_SOCKETS")
  assert.equal(коды["Ответить в соединение"], "FLANG_IO_NO_SOCKETS")
  assert.equal(коды["Прочитать октеты из соединения"], "FLANG_IO_NO_SOCKETS")
  assert.equal(коды["Ответить октетами в соединение"], "FLANG_IO_NO_SOCKETS")
  /* А вот экран у вкладки есть, и это единственное, что она исполняет по-настоящему. */
  assert.equal(ответы[поручение.variants.findIndex((в) => в.name === "Показать")], "Показано")
  assert.equal(ответы[поручение.variants.findIndex((в) => в.name === "Ждать событие")], "Срок вышел")
})
