/**
 * Горячая замена под доказательство — шаг Е1 карты (`flang/conc/RESILIENCE.md`).
 *
 * Проверка карты сформулирована так: «нетотальный обработчик получает отказ на
 * загрузке; тотальный принимается, и процесс продолжает с того же состояния».
 * Здесь она сделана целиком, и к ней добавлен третий случай, которого в карте
 * не было, потому что до В3 его нельзя было и назвать: обработчик ТОТАЛЬНЫЙ, но
 * без оценки витков. BEAM повесит процесс вечным циклом, а такой обработчик
 * повесит его на миллион витков — разница есть, различия нет.
 *
 * Каждый отказ здесь предъявляется, а не описывается: рядом с отвергнутой
 * заменой стоит прогон, который показывает, ЧЕМ именно она плоха.
 */

import assert from "node:assert/strict"
import test from "node:test"

import { ОТКАЗ_ЗАМЕНЫ, заменитьОбработчик } from "../src/hotswap.mjs"
import { runConcurrent } from "../src/conc.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { текстОценки } from "../src/bounded.mjs"

const исходник = `модуль «Служба»

объект «Счёт»
  «всего»: число

тип «Весть»
  вариант «прибавить» содержит «сколько»: число
  вариант «сложить» содержит «числа»: список числа

объект «Отклик»
  «состояние»: «Счёт»
  «действия»: список «Действие»

процесс «Служба»
  состояние «Счёт»
  начинает с «нуль»
  принимает «Весть»
  обрабатывает «шаг»

надзор «Сверху»
  процесс «Служба» стратегия «перезапустить»

тотальная функция «нуль»
  возвращает «Счёт»
  запись «Счёт» с «всего» равным 0

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным (счёт.«всего» плюс сколько)) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []

прогон «работа»
  семя 1
  дано «Служба» принимает (вариант «прибавить» с «сколько» равным 5)
  дано «Служба» принимает (вариант «прибавить» с «сколько» равным 7)
  ожидается «Служба» равен (запись «Счёт» с «всего» равным 12)
`

const программа = parse(исходник, "служба.flang")

/** Состояние, до которого процесс дожил к моменту замены. */
function состояниеПослеРаботы() {
  const итог = runConcurrent(программа, программа.runs[0], {})
  assert.equal(итог.исход, "покой")
  return итог.состояния["Служба"]
}

/* ─────────────── отказ первый: доказательства нет вовсе ────────────────── */

test("нетотальный обработчик получает отказ на загрузке", () => {
  const замена = `модуль «Замена»

функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным сколько) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []
`
  const итог = заменитьОбработчик(программа, "Служба", замена)
  assert.equal(итог.принято, false)
  assert.equal(итог.диагностики[0].code, ОТКАЗ_ЗАМЕНЫ)
  assert.match(итог.диагностики[0].message, /без признака «тотальная»/u)
})

test("обработчик с признаком «тотальная», но недоказанный, тоже отвергается", () => {
  /*
   * Признак — это заявка, а не доказательство. Здесь заявка есть, а рекурсия
   * идёт по числу вниз без нижней границы, и проверка завершаемости её не
   * принимает — та же самая проверка, что на этапе компиляции. Слово
   * «тотальная» само по себе не грузит ничего, и это ровно та строгость, ради
   * которой Е1 и затевался.
   */
  const замена = `модуль «Замена»

тотальная функция «крутить»
  принимает сколько: число
  возвращает число
  «крутить» от (сколько минус 1)

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным («крутить» от сколько)) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []
`
  const итог = заменитьОбработчик(программа, "Служба", замена)
  assert.equal(итог.принято, false)
  assert.equal(итог.диагностики[0].code, ОТКАЗ_ЗАМЕНЫ)
  assert.match(итог.диагностики[0].message, /тотальность обработчика .* не доказана/u)
  assert.ok(итог.диагностики.slice(1).some((д) => д.code === "FLANG_NOT_TOTAL"))
})

/* ─────── отказ второй: доказательство есть, но не то — вклад В3 ────────── */

test("ТОТАЛЬНЫЙ обработчик без оценки витков отвергается, когда названа граница", () => {
  /*
   * Здесь всё по правилам старого мира: «фиб» тотальна, завершение её доказано
   * (убывающая мера с нижней границей), компилятор её принимает. И она же
   * съедает столько витков, сколько ей дадут: на входе 34 их больше миллиона.
   *
   * До В3 отказать здесь было НЕЧЕМ: доказывать было нечего сверх тотальности,
   * и загрузка прошла бы. Это и есть та самая дверь, которую тотальность
   * оставляла открытой, и разница с вечным циклом BEAM тут есть, а различия нет.
   */
  const замена = `модуль «Замена»

тотальная функция «фиб»
  принимает н: число
  возвращает число
  если н меньше 2
    то н
    иначе («фиб» от (н минус 1)) плюс («фиб» от (н минус 2))

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным («фиб» от сколько)) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []
`
  /* Без названной границы замена проходит: тотальность доказана, и требовать
     больше не с чего — это поведение до Е1. */
  assert.equal(заменитьОбработчик(программа, "Служба", замена).принято, true)

  /* А с границей — нет, и причина названа поимённо. */
  const итог = заменитьОбработчик(программа, "Служба", замена, { витков: 1000 })
  assert.equal(итог.принято, false)
  assert.match(итог.диагностики[0].message, /оценки витков у обработчика .* нет/u)
})

test("оценка, растущая с размером сообщения, границей не считается", () => {
  /*
   * Обработчик ниже безупречен: тотален, ограничен, оценка у него есть и она
   * линейна. И принять его под названную границу всё равно нельзя — потому что
   * размер сообщения не ограничен ничем, а значит и витки не ограничены. Отказ
   * тут не придирка, а единственный честный ответ: граница, которая держится
   * «обычно», границей не является.
   */
  const замена = `модуль «Замена»

тотальная функция «сумма»
  принимает элементы: список числа
  возвращает число
  разбор элементы
    случай пусто
      то 0
    случай голова и хвост
      то голова плюс «сумма» от хвост

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным сколько) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным («сумма» от набор)) и «действия» равным []
`
  const итог = заменитьОбработчик(программа, "Служба", замена, { витков: 1_000_000 })
  assert.equal(итог.принято, false)
  assert.match(итог.диагностики[0].message, /оценка растёт с размером сообщения/u)

  /* Без границы та же замена проходит: требовать ограниченности всегда значило
     бы запретить обработчики, которые ходят по сообщению, а это половина всего
     полезного. */
  assert.equal(заменитьОбработчик(программа, "Служба", замена).принято, true)
})

/* ─────────────── замена принята: состояние то же, счёт новый ───────────── */

test("тотальный и ограниченный обработчик принимается, и процесс продолжает с того же состояния", () => {
  const было = состояниеПослеРаботы()
  assert.deepEqual(было, { "всего": 12 })

  const замена = `модуль «Замена»

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным (счёт.«всего» плюс (сколько умножить на 2))) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []
`
  const итог = заменитьОбработчик(программа, "Служба", замена, { витков: 1000 })
  assert.equal(итог.принято, true, JSON.stringify(итог.диагностики))
  assert.equal(текстОценки(итог.оценка), "20", "оценка обязана быть постоянной и названной числом")

  /* Состояние принадлежит процессу, а не коду: новый обработчик получает ровно
     то, что оставил старый, и считает от него — 12 плюс дважды по 3. */
  const рантайм = createRuntime(итог.программа, { maxSteps: 100_000 })
  const отклик = рантайм.call("шаг", [было, { variant: "прибавить", fields: { "сколько": 3 } }])
  assert.deepEqual(отклик["состояние"], { "всего": 18 })
})

test("замена, не проходящая проверку типов, отвергается вместе с её диагностикой", () => {
  const замена = `модуль «Замена»

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным "не число") и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []
`
  const итог = заменитьОбработчик(программа, "Служба", замена)
  assert.equal(итог.принято, false)
  assert.match(итог.диагностики[0].message, /не прошёл проверку типов/u)
  assert.ok(итог.диагностики.length > 1, "диагностика проверки типов обязана приехать целиком")
})
