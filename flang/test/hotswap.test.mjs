/** Процесс, у которого состояние — список: на нём видно, что перенос не постоянен. */
function журнал(сколько) {
  return parse([
    "модуль «Журнал»", "",
    "объект «Лог»", "  «строки»: список числа", "",
    "тип «Весть»", "  вариант «записать» содержит «что»: число", "",
    "объект «Отклик»", "  «состояние»: «Лог»", "  «действия»: список «Действие»", "",
    "процесс «Журнал»", "  состояние «Лог»", "  начинает с «пустой»",
    "  принимает «Весть»", "  обрабатывает «шаг»", "",
    "надзор «Сверху»", "  процесс «Журнал» стратегия «перезапустить»", "",
    "тотальная функция «пустой»", "  возвращает «Лог»",
    "  запись «Лог» с «строки» равным []", "",
    "тотальная функция «шаг»",
    "  принимает лог: «Лог», весть: «Весть»", "  возвращает «Отклик»",
    "  разбор весть",
    "    случай вариант «записать» с «что» как что",
    "      запись «Отклик» с «состояние» равным (запись «Лог» с «строки» равным (добавить что к лог.«строки»)) и «действия» равным []", "",
    "прогон «работа»", "  семя 1",
    ...Array.from({ length: сколько }, (_, i) => `  дано «Журнал» принимает (вариант «записать» с «что» равным ${i + 1})`),
    `  ожидается «Журнал» равен (запись «Лог» с «строки» равным [${Array.from({ length: сколько }, (_, i) => i + 1).join(", ")}])`,
    "",
  ].join("\n"), "журнал.flang")
}

/** Свести список в число: перенос, чья оценка РАСТЁТ с размером состояния. */
const сведение = `модуль «Замена»

объект «Итог»
  «сумма»: число

объект «Отклик итога»
  «состояние»: «Итог»
  «действия»: список «Действие»

процесс «Журнал»
  состояние «Итог»
  начинает с «ноль итога»
  принимает «Весть»
  обрабатывает «шаг итога»

тотальная функция «ноль итога»
  возвращает «Итог»
  запись «Итог» с «сумма» равным 0

тотальная функция «сумма»
  принимает элементы: список числа
  возвращает число
  разбор элементы
    случай пусто
      то 0
    случай голова и хвост
      то голова плюс «сумма» от хвост

тотальная функция «свести»
  принимает старое: «Лог»
  возвращает «Итог»
  запись «Итог» с «сумма» равным («сумма» от старое.«строки»)

тотальная функция «шаг итога»
  принимает итог: «Итог», весть: «Весть»
  возвращает «Отклик итога»
  разбор весть
    случай вариант «записать» с «что» как что
      запись «Отклик итога» с «состояние» равным (запись «Итог» с «сумма» равным (итог.«сумма» плюс что)) и «действия» равным []
`

test("растущая оценка переноса — не помеха, а посчитанная цена: подставляется РАЗМЕР ТОГО САМОГО состояния", () => {
  /*
   * Обработчику растущая оценка границей не считается (тест выше): размер
   * сообщения не ограничен ничем, поэтому «уложится» про него сказать нельзя.
   * С переносом всё иначе — он зовётся один раз и на состоянии, которое лежит
   * перед нами, а его структурный размер это число. Значит границу можно не
   * требовать постоянной, а ПОСЧИТАТЬ. Строже (проверено настоящее число, а не
   * форма многочлена) и дешевле (принято то, что обработчику запрещено).
   */
  const программаЖивая = журнал(6)
  const итог = runConcurrent(программаЖивая, программаЖивая.runs[0], {
    замены: [запросЗамены({ после: 4, процесс: "Журнал", исходник: сведение, перенос: "свести", витков: 1000, витковПереноса: 1000, витковПереноса: 1000 })],
  })

  assert.equal(итог.замены[0].принято, true, JSON.stringify(итог.замены[0].диагностики))
  const сведения = итог.замены[0].перенос
  assert.ok(степень(сведения.оценка) > 0, `оценка переноса ${текстОценки(сведения.оценка)} обязана быть растущей — иначе тест проверяет не то`)
  assert.equal(сведения.размер, 6, "структурный размер «Лог» из четырёх чисел: узел плюс список плюс четыре")
  assert.equal(сведения.витков, значение(сведения.оценка, сведения.размер))
  assert.ok(сведения.витки > 0 && сведения.витки <= сведения.витков, `перенос стоил ${сведения.витки} витков при обещанных не больше ${сведения.витков}`)

  /* 1+2+3+4 переехало числом, потом два оставшихся сообщения легли новым видом. */
  assert.deepEqual(итог.состояния["Журнал"], { "сумма": 21 })
})

