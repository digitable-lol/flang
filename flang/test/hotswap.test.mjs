test("ТОТАЛЬНЫЙ обработчик без оценки витков отвергается, когда названа граница", () => {
  /*
   * Здесь всё по правилам старого мира: «фиб» тотальна, завершение её доказано
   * (убывающая мера с нижней границей), компилятор её принимает. И она же
   * съедает столько витков, сколько ей дадут: на входе 34 их больше миллиона.
   *
   * До В3 отказать здесь было НЕЧЕМ: доказывать было нечего сверх тотальности,
   * и загрузка прошла бы. Это и есть та самая дверь, которую тотальность
   * оставляла открытой, и разница с вечным циклом BEAM тут есть, а различия нет.
   */
  const замена = `модуль «Замена»

тотальная функция «фиб»
  принимает н: число
  возвращает число
  если н меньше 2
    то н
    иначе («фиб» от (н минус 1)) плюс («фиб» от (н минус 2))

тотальная функция «шаг»
  принимает счёт: «Счёт», весть: «Весть»
  возвращает «Отклик»
  разбор весть
    случай вариант «прибавить» с «сколько» как сколько
      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным («фиб» от сколько)) и «действия» равным []
    случай вариант «сложить» с «числа» как набор
      запись «Отклик» с «состояние» равным счёт и «действия» равным []
`
  /* Без названной границы замена проходит: тотальность доказана, и требовать
     больше не с чего — это поведение до Е1. */
  assert.equal(заменитьОбработчик(программа, "Служба", замена).принято, true)

  /* А с границей — нет, и причина названа поимённо. */
  const итог = заменитьОбработчик(программа, "Служба", замена, { витков: 1000 })
  assert.equal(итог.принято, false)
  assert.match(итог.диагностики[0].message, /оценки витков у обработчика .* нет/u)
})

