/* ── перенос БЕЗ состояния на руках: спрос тот же, что с обработчика ─────── */

test("замена проверяется и без состояния — тогда перенос обязан быть постоянным", () => {
  /*
   * `заменитьОбработчик` зовут и не из планировщика: чтобы узнать, приняли бы
   * такую замену вообще. Состояния тогда нет, подставлять в оценку нечего, и
   * спрос с переноса становится тем же, что с обработчика — уложись при ЛЮБОМ
   * размере. Дешевле получается только там, где состояние на руках, и это
   * ровно та цена, которую платит проверка «вообще».
   */
  const журнальная = журнал(4)
  const безСостояния = заменитьОбработчик(журнальная, "Журнал", сведение, {
    перенос: "свести",
    витковПереноса: 1_000_000,
  })
  assert.equal(безСостояния.принято, false)
  assert.match(безСостояния.диагностики[0].message, /состояния, на котором это можно было бы посчитать числом, не дано/u)

  /* А то же самое с состоянием на руках — принимается, и цена названа числом. */
  const сСостоянием = заменитьОбработчик(журнальная, "Журнал", сведение, {
    перенос: "свести",
    витковПереноса: 1_000_000,
    состояние: { "строки": [1, 2, 3, 4] },
  })
  assert.equal(сСостоянием.принято, true, JSON.stringify(сСостоянием.диагностики))
  assert.deepEqual(сСостоянием.состояние, { "сумма": 10 })
  assert.equal(сСостоянием.перенос.размер, 6)
})
