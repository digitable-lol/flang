/* ══════════════════════════════════════════════════════════════════════════
   ПЕРЕНОС СОСТОЯНИЯ МЕЖДУ ВИДАМИ — и чем он строже и дешевле `code_change/3`

   В OTP это `code_change(OldVsn, State, Extra) -> {ok, NewState}`: функция в
   новом модуле, которую зовёт `sys:change_code` на приостановленном процессе.
   Не проверяет её никто и ничем. Её тип — `term() -> term()`, то есть типа у
   неё нет вовсе; она имеет право не завершиться, и тогда процесс висит
   ПРИОСТАНОВЛЕННЫМ, а надзор про такое не знает — процесс не умер; а если она
   вернёт не тот вид, беда всплывёт позже, в чужом `badmatch`, и связать её с
   заменой будет уже нечем.

   Здесь наоборот, и наоборот в четырёх местах:

   1. У переноса ЕСТЬ ТИП, и он сверяется с обоими объявлениями сразу: принять
      обязан старый вид состояния, вернуть — новый. Оба вида в кандидате
      объявлены, потому что замена НЕ переобъявляет существующие типы, а
      добавляет новые (тест выше). Это и есть ответ на «тип старого состояния
      после замены уже не объявлен нигде» — он объявлен, в работающей программе.
   2. Перенос обязан быть ТОТАЛЕН — той же проверкой, что и обработчик.
      Приостановленного процесса, из которого нет выхода, у нас не бывает.
   3. Перенос идёт ПОД границу: если названа `витков`, оценка обязана в неё
      уложиться. И вот здесь получается ДЕШЕВЛЕ, чем у обработчика: обработчику
      нужна ПОСТОЯННАЯ оценка, потому что размер сообщения не ограничен ничем, а
      перенос зовётся РОВНО ОДИН РАЗ и ровно на том состоянии, которое лежит
      перед нами. Его размер известен числом, значит в оценку можно подставить
      это число и получить не многочлен, а виток. Растущая оценка для переноса —
      не помеха, а посчитанная цена.
   4. Замена АТОМАРНА: не сошлось что-нибудь — работает старый вид со старым
      состоянием, и прогон этого даже не замечает. В OTP неудавшийся
      `code_change` оставляет процесс приостановленным, а разбирается с этим
      release handler, то есть слой выше и снаружи.
   ══════════════════════════════════════════════════════════════════════════ */

