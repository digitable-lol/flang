/**
 * ХОЗЯЕВА СОГЛАСНЫ: каждое поручение словаря названо в КАЖДОМ исполнителе.
 *
 * Проверка заведена на беду, которая уже случилась. Словарь ввода-вывода закрыт,
 * и это значит: на всякое поручение обязан ОТВЕТИТЬ всякий исполнитель — Node,
 * браузер, напечатанный C и синхронный планировщик. Ответить — не то же самое,
 * что исполнить: «у меня нет сокетов» и «мне запрещено» суть законные ответы, а
 * вот «не знаю такого поручения» значит, что исполнитель ОТСТАЛ от языка.
 *
 * До этой проверки отставание находилось только прогоном, а прогон под
 * напечатанным C стоит полутора минут сборки и потому в наборе тестов не стоит
 * вовсе. Значит поручение можно было завести, забыть про один из исполнителей и
 * не покраснеть. Здесь это красное: имя поручения ищется в исходнике каждого
 * исполнителя буквально.
 *
 * ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ, и сказать это надо прямо: она не проверяет, что
 * исполнители отвечают ОДИНАКОВО. Совпадение ответов байт в байт мерится
 * прогоном обоих на одной программе, и такой прогон здесь есть — но только
 * когда собранный двоичный назван переменной среды FLANG_C_BINARY. Без него
 * проверка говорит об этом словами, а не молчит.
 *
 * Запуск: node --test flang/test/hozyaeva-soglasny.test.mjs
 *   с прогоном обоих: FLANG_C_BINARY=/путь/к/flang node --test flang/test/hozyaeva-soglasny.test.mjs
 */
import assert from "node:assert/strict"
import { execFile } from "node:child_process"
import { createServer } from "node:net"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"
import test from "node:test"

import { IO_TYPES } from "../src/io.mjs"

const запустить = promisify(execFile)
const корень = fileURLToPath(new URL("../..", import.meta.url))
const прочитать = (путь) => readFileSync(new URL(`../../${путь}`, import.meta.url), "utf8")

const [ПОРУЧЕНИЕ] = IO_TYPES

/**
 * Четыре исполнителя, и все четыре обязаны знать все поручения.
 *
 * `flang/src/host/node.mjs` держит сразу двух — асинхронного и синхронного, — и
 * потому назван один раз: разделять их пришлось бы разбором файла, а разбор
 * файла в проверке сам стал бы предметом, который надо стеречь.
 */
const ИСПОЛНИТЕЛИ = Object.freeze([
  "flang/src/host/node.mjs",
  "flang/src/host/browser.mjs",
  "flang/src/emit/c/flang_repl.c",
  "flang/src/emit/c/flang_conc.c",
])

/**
 * ОБЪЯВЛЕННЫЙ ДОЛГ, а не список исключений.
 *
 * Один исполнитель отстаёт от словаря сегодня, и отставание это настоящее:
 * `flang/src/emit/c/flang_conc.c` — хозяин ПЛАНИРОВЩИКА ПРОЦЕССОВ, и пяти
 * поручений он не знает вовсе, то есть отвечает на них «не знаю такого
 * поручения». Ровно те же пять не знает и его свидетель, синхронный хозяин на
 * Node (`nodeHostSync`), — и это единственное, что спасает: службу под ними
 * можно сверять байт в байт, потому что оба не знают ОДНО И ТО ЖЕ.
 *
 * Список объявлен здесь именно затем, чтобы долг было видно и чтобы он не мог
 * ни вырасти, ни уменьшиться молча. Уменьшится — проверка тоже покраснеет, и
 * это не придирка: закрыть дыру у одного из двух и есть тот самый способ их
 * развести.
 *
 * Экранные два в этом списке по другой причине, чем три остальных: экрана нет
 * ни у одного хозяина вне браузера, и отвечать на них можно только отказом.
 * Каталог и процессы — настоящий долг: `readdirSync` и `fork` синхронны по
 * природе, и барьер планировщика их не касается. Закрывать надо ОБА места
 * сразу, одной правкой.
 */
const ДОЛГ = Object.freeze({
  "flang/src/emit/c/flang_conc.c": [
    "Показать",
    "Ждать событие",
    "Перечислить каталог",
    "Запустить процесс",
    "Запустить процесс с вводом",
  ],
})

test("каждое поручение словаря названо в каждом исполнителе, кроме объявленного долга", () => {
  const пропуски = []
  for (const путь of ИСПОЛНИТЕЛИ) {
    const исходник = прочитать(путь)
    for (const в of ПОРУЧЕНИЕ.variants) {
      if (!исходник.includes(`"${в.name}"`)) пропуски.push(`${путь}: «${в.name}»`)
    }
  }
  const ожидаемые = Object.entries(ДОЛГ).flatMap(([путь, имена]) => имена.map((имя) => `${путь}: «${имя}»`))
  /* Полные списки, а не первое несовпадение: заведи поручение и забудь про двух
     исполнителей — надо увидеть обоих сразу, а не чинить по одному. И сравнение
     РОВНОЕ: лишнего пропуска нет, объявленный долг не уменьшился незамеченным. */
  assert.deepEqual(пропуски.sort(), ожидаемые.sort(), "исполнители разошлись со словарём")
})

test("словарь на flang знает ровно те же имена, что словарь-образец", () => {
  /* Словарь отражён на flang (`flang/self/parser.flang`), и отражение это
     обязано быть двусторонним: разойдись имена хоть одним ключом — и побайтовая
     сверка разбора любой программы со словарём покажет расхождение, а не
     промолчит. Ловится оно здесь раньше и дешевле. */
  const эталон = прочитать("flang/self/parser.flang")
  const пропуски = []
  for (const тип of IO_TYPES) {
    for (const в of тип.variants) {
      if (!эталон.includes(`"${в.name}"`)) пропуски.push(`${тип.name}: «${в.name}»`)
    }
  }
  assert.deepEqual(пропуски, [], `словарь на flang отстал:\n${пропуски.join("\n")}`)
})

test("ПРОВЕРКА ИМЕЕТ ЗУБЫ: выдуманное поручение не находится ни у кого", () => {
  /* Изъятие рычага: если бы поиск по исходнику находил что угодно, две проверки
     выше зеленели бы навсегда. */
  const выдуманное = "Проглотить луну"
  for (const путь of [...ИСПОЛНИТЕЛИ, "flang/self/parser.flang"]) {
    assert.equal(
      прочитать(путь).includes(`"${выдуманное}"`),
      false,
      `${путь} нашёл поручение, которого нет в словаре — значит поиск ничего не значит`,
    )
  }
})

test("ПРОГОН ОБОИХ: одна программа, два исполнителя, вывод байт в байт", async (t) => {
  const двоичный = process.env.FLANG_C_BINARY
  if (двоичный === undefined || двоичный === "") {
    /* Пропуск СЛОВАМИ: собранного двоичного здесь нет, и делать вид, что
       совпадение проверено, нельзя. Собрать его — полторы минуты:
       `node scripts/bootstrap-c.mjs && make -C bootstrap`. */
    t.skip(
      "не задан FLANG_C_BINARY — совпадение исполнителей байт в байт не проверялось; " +
        "имена поручений сверены выше",
    )
    return
  }
  const план = "flang/examples/io/oktety-po-provodu.flang"
  const все = Buffer.from(Array.from({ length: 256 }, (_, октет) => октет))
  const прогнать = async (команда, ключи) => {
    /* Сервер поднимается заново на каждый прогон: соединение живёт один обмен,
       и держать его между исполнителями значило бы сравнивать разные потоки. */
    const сервер = createServer((сокет) => сокет.end(все))
    await new Promise((готово) => сервер.listen(51999, "127.0.0.1", готово))
    try {
      const { stdout } = await запустить(команда, ключи, { cwd: корень, maxBuffer: 1 << 24 })
      return stdout
    } finally {
      await new Promise((готово) => сервер.close(готово))
    }
  }
  const наNode = await прогнать(process.execPath, ["flang/bin/flang.mjs", "io", план])
  const вC = await прогнать(двоичный, ["io", план])
  t.diagnostic(`вывод: ${Buffer.byteLength(наNode)} октетов у одного, ${Buffer.byteLength(вC)} у другого`)
  /* Не «оба сказали 256», а ВЕСЬ вывод целиком: журнал поручений и откликов
     входит в него, и разойдись исполнители хоть номером соединения — видно
     будет здесь. */
  assert.equal(вC, наNode)
  assert.match(наNode, /октетов 256, сумма 32640/)
})
