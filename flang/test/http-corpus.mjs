/**
 * Корпус входов для `flang/stdlib/http.flang` — данные, а не прогон.
 *
 * ── Почему корпус написан РАНЬШЕ модуля ─────────────────────────────────────
 *
 * Разбор HTTP пишется в две страницы и выглядит правильным на всяком входе,
 * который автор придумал сам, потому что автор придумывает те входы, которые
 * его разбор уже умеет. Корпус, написанный до кода, ломает этот круг: сначала
 * названо, ЧТО обязано случиться, потом написано то, что это делает.
 *
 * ── Три исхода, и главное здесь — второй ────────────────────────────────────
 *
 * У разбора запроса ровно три исхода, и они РАЗНЫЕ:
 *
 *   «разобран»  — запрос целый, вот он;
 *   «неполон»   — байтов пока мало, ЖДАТЬ ЕЩЁ. Правильный ответ — молчание;
 *   «испорчен»  — так починить нельзя, отвечать кодом и закрывать связь.
 *
 * Второй исход и есть та дыра, ради которой корпус строится первым. Разбор,
 * который сливает «неполон» с «испорчен», проходит любую наивную проверку:
 * на целом запросе он даёт тот же ответ, что правильный. Разойдутся они только
 * на обрезанном входе — а обрезанный вход приходит всегда, потому что TCP не
 * обещает, что запрос придёт одним куском.
 *
 * Слить их можно в обе стороны, и обе беды дорогие:
 *
 *   «неполон» назвать «испорченным» — служба рвёт живое соединение всякий раз,
 *   когда запрос разделился на два пакета. Ловится это только под нагрузкой;
 *
 *   «испорчен» назвать «неполным» — служба ждёт продолжения, которого не будет,
 *   и держит связь до таймаута. Это уже не ошибка, а способ её положить.
 *
 * Поэтому в корпусе есть входы, где ЕДИНСТВЕННЫЙ правильный ответ — «неполон»
 * (обрезанное на середине заголовка, тело короче обещанного, обрезанный чанк),
 * и входы, где единственный правильный — «испорчен» на том же месте.
 *
 * ── Злонамеренные ───────────────────────────────────────────────────────────
 *
 * Помечены `злой: true`. Это не «кривые» входы — кривой приходит от старого
 * клиента, злой приходит от того, кто читал ту же спецификацию, что и автор
 * разбора, и ищет расхождение между ними. Отсюда два `Content-Length`,
 * голый перевод строки в блоке заголовков и заголовок в мегабайт.
 */

