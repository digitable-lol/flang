/**
 * Прогон корпуса http по `flang/stdlib/http.flang`.
 *
 * Модуль проверяет себя примерами — их сходимость стережёт `stdlib.test.mjs`
 * вместе со всей библиотекой. Здесь проверяется то, чего примеры показать не
 * могут, и ровно оно решает, годится ли разбор для настоящей службы.
 *
 * 1. **Корпус целиком.** Входы лежат отдельно (`http-corpus.mjs`) и написаны
 *    ДО модуля. Разбор обязан дать на каждом ровно тот исход, который назван
 *    в корпусе, — включая злонамеренные, где правильный ответ неочевиден.
 *
 * 2. **Завершаемость на злом входе — прогоном, а не пометкой.** Компилятор
 *    доказывает, что разбор завершается; вычислитель здесь ограничен счётчиком
 *    шагов, и заголовок в мегабайт обязан уложиться в него, а не только
 *    «когда-нибудь кончиться».
 *
 * 3. **Разбор и печать сходятся.** Напечатанный запрос разбирается обратно в
 *    тот же запрос. Это то свойство, которое ловит расхождение между двумя
 *    половинами модуля раньше, чем его поймает чужой клиент.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { reifyValue } from "../src/builtins.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"
import { АДРЕСА, КОРПУС, СЧЁТ } from "./http-corpus.mjs"

const ПУТЬ = fileURLToPath(new URL("../stdlib/http.flang", import.meta.url))
const модуль = parse(readFileSync(ПУТЬ, "utf8"), "http.flang")
/* Счётчик шагов здесь не формальность: он и есть та проверка, что разбор
   укладывается в предел на мегабайтном входе, а не просто «когда-нибудь». */
const среда = createRuntime(модуль, { maxSteps: 20_000_000, maxDepth: 100_000 })

/** Исход разбора одним словом — то же деление, что в корпусе. */
function разобрать(текст) {
  const исход = reifyValue(среда.call("Разобрать запрос", { текст }))
  if (исход.variant === "Запрос разобран") {
    const запрос = reifyValue(исход.fields["запрос"])
    return {
      ждём: "разобран",
      метод: запрос.fields["метод"],
      цель: запрос.fields["цель"],
      версия: запрос.fields["версия"],
      тело: запрос.fields["тело"],
      заголовки: reifyValue(запрос.fields["заголовки"]).map((з) => {
        const пара = reifyValue(з)
        return [пара.fields["имя"], пара.fields["значение"]]
      }),
    }
  }
  if (исход.variant === "Запрос неполон") return { ждём: "неполон" }
  return { ждём: "испорчен", код: исход.fields["код"], причина: исход.fields["причина"] }
}

test("модуль проходит типы и тотальность, и каждая функция доказана", () => {
  assert.deepEqual(checkTypes(модуль).diagnostics, [])
  const тотальность = checkTotality(модуль)
  assert.deepEqual(тотальность.diagnostics, [])
  for (const функция of модуль.functions) {
    assert.equal(функция.total, true, `«${функция.name}» не помечена тотальной`)
    assert.ok(тотальность.total.has(функция.name), `«${функция.name}» помечена тотальной, но не доказана`)
  }
})

test("корпус назван числом", () => {
  /* Число входов — часть отчёта о работе, и оно обязано считаться, а не
     помниться: приписка «около полусотни» протухает при первом же дополнении. */
  assert.equal(СЧЁТ.всего, КОРПУС.length + АДРЕСА.length)
  assert.ok(СЧЁТ.злых >= 20, `злонамеренных всего ${СЧЁТ.злых}`)
  assert.ok(СЧЁТ.неполных >= 5, `неполных всего ${СЧЁТ.неполных}`)
})

for (const случай of КОРПУС) {
  test(`запрос: ${случай.имя}`, () => {
    const исход = разобрать(случай.вход)
    assert.equal(исход.ждём, случай.ждём, `на «${случай.имя}» вышло «${исход.ждём}» (${исход.причина ?? ""})`)
    if (случай.код !== undefined) assert.equal(исход.код, случай.код)
    if (случай.метод !== undefined) assert.equal(исход.метод, случай.метод)
    if (случай.цель !== undefined) assert.equal(исход.цель, случай.цель)
    if (случай.тело !== undefined) assert.equal(исход.тело, случай.тело)
    if (случай.заголовок !== undefined) {
      assert.deepEqual(исход.заголовки, [случай.заголовок])
    }
  })
}

test("«неполон» и «испорчен» не сливаются", () => {
  /* Главная дыра, ради которой корпус строился первым. Разбор, который отвечает
     одинаково на обрезанный и на кривой вход, проходит любую проверку на целом
     запросе — и расходится с правильным ровно там, где это дорого стоит.

     Здесь пара входов, различающихся ОДНИМ решением: оба обрываются на теле, но
     первый обещал длину и не дослал, а второй назвал длину дважды. Первый —
     ждать, второй — отвергать. */
  assert.equal(разобрать("POST / HTTP/1.1\r\nContent-Length: 9\r\n\r\nаб").ждём, "неполон")
  assert.equal(разобрать("POST / HTTP/1.1\r\nContent-Length: 9\r\nContent-Length: 9\r\n\r\nаб").ждём, "испорчен")
  /* И зеркально на чанках: обрезанный чанк — ждать, кривой размер — отвергать. */
  assert.equal(разобрать("POST / HTTP/1.1\r\nTransfer-Encoding: chunked\r\n\r\n5\r\nаб").ждём, "неполон")
  assert.equal(разобрать("POST / HTTP/1.1\r\nTransfer-Encoding: chunked\r\n\r\nзз\r\nаб").ждём, "испорчен")
})

test("запрос по одному байту: каждый обрезок — «неполон», и только целое — «разобран»", () => {
  /* Так запрос и приходит из сети. Ни один обрезок не смеет быть «испорчен»:
     служба, отвечающая 400 на половину правильного запроса, рвёт связь тем
     чаще, чем хуже сеть. */
  const целое = "POST /заказы?номер=77 HTTP/1.1\r\nHost: узел\r\nContent-Length: 11\r\n\r\nтовар=книга"
  const знаки = [...целое]
  for (let сколько = 0; сколько < знаки.length; сколько += 1) {
    const исход = разобрать(знаки.slice(0, сколько).join(""))
    assert.equal(исход.ждём, "неполон", `обрезок длиной ${сколько} дал «${исход.ждём}»`)
  }
  assert.equal(разобрать(целое).ждём, "разобран")
})

for (const случай of АДРЕСА) {
  test(`адрес: ${случай.имя}`, () => {
    const пары = reifyValue(среда.call("Разобрать параметры", { строказапроса: случай.вход })).map((з) => {
      const пара = reifyValue(з)
      return [пара.fields["имя"], пара.fields["значение"]]
    })
    assert.deepEqual(пары, случай.ждём)
  })
}

test("печать и разбор сходятся", () => {
  const напечатанный = среда.call("Напечатать запрос", {
    запрос: {
      variant: "Запрос",
      fields: {
        "метод": "POST",
        "цель": "/заказы",
        "версия": "HTTP/1.1",
        "заголовки": [{ variant: "Заголовок", fields: { "имя": "Host", "значение": "узел" } }],
        "тело": "товар=книга",
      },
    },
  })
  const обратно = разобрать(напечатанный)
  assert.equal(обратно.ждём, "разобран")
  assert.equal(обратно.метод, "POST")
  assert.equal(обратно.цель, "/заказы")
  assert.equal(обратно.тело, "товар=книга")
})

test("кодирование и раскодирование сходятся на печатных ASCII", () => {
  /* Только на них, и это названный предел: переправы из кодовой точки обратно в
     символ язык не даёт, поэтому многобайтовое раскодирование оставляет запись
     как есть.
     Проверяется именно то, что обещано, — обещание шире прогона было бы ложью. */
  for (const текст of ["", "a b", "а=б&в", "/путь?ключ=значение", "~-._"]) {
    const печатные = [...текст].every((знак) => знак.codePointAt(0) < 128)
    const закодировано = среда.call("Закодировать проценты", { текст })
    const обратно = среда.call("Раскодировать проценты", { текст: закодировано })
    if (печатные) assert.equal(обратно, текст, `на «${текст}» круг не сошёлся`)
  }
})

test("заголовок в мегабайт отвергается кодом, а не отказом вычисления", () => {
  const исход = разобрать(`GET / HTTP/1.1\r\nX-Много: ${"х".repeat(1024 * 1024)}\r\n\r\n`)
  assert.equal(исход.ждём, "испорчен")
  assert.equal(исход.код, 431)
})
