test("ПОДДЕЛКА ТРЕТЬЕЙ БАЗОЙ: `элемент начиная с 2` отвергнуто названным кодом", () => {
  /* `at = номер − база` осмысленно ровно при двух числах. Всякое другое молча
     сдвинуло бы каждый доступ по списку, а молчание здесь — это и есть беда,
     ради которой заказана проверка. */
  const беда = отказ("модуль «М»\n\nэлемент начиная с 2\n")
  assert.equal(беда?.code, "FLANG_PARSE")
  assert.match(беда.message, /третьей базы у языка нет/u)
})

test("ПОДДЕЛКА НЕ ЧИСЛОМ: `элемент начиная с \"ноль\"` отвергнуто там же", () => {
  const беда = отказ('модуль «М»\n\nэлемент начиная с "ноль"\n')
  assert.equal(беда?.code, "FLANG_PARSE")
  assert.match(беда.message, /база номера объявляется числом 0 или 1/u)
})

test("ПОДДЕЛКА ДВУМЯ ОБЪЯВЛЕНИЯМИ: порядок строк не вправе решать", () => {
  /* Второе объявление молча победило бы первое — и смысл программы решала бы
     не запись, а то, какая строка ниже. */
  const беда = отказ("модуль «М»\n\nэлемент начиная с 0\nэлемент начиная с 1\n")
  assert.equal(беда?.code, "FLANG_PARSE")
  assert.match(беда.message, /база номера объявлена дважды/u)

  /* И то же самое ДВАЖДЫ ОДНИМ числом: «оба раза ноль» — тоже два объявления. */
  assert.match(отказ("модуль «М»\n\nэлемент начиная с 0\nэлемент начиная с 0\n").message, /дважды/u)
})

test("ПОДДЕЛКА ПОЛОВИНОЙ ФРАЗЫ: `элемент 0` у левого края отвергнуто", () => {
  const беда = отказ("модуль «М»\n\nэлемент 0\n")
  assert.equal(беда?.code, "FLANG_PARSE")
  assert.match(беда.message, /ожидалось 'начиная с'/u)
})

test("ИЗЪЯТИЕ: `элемент` внутри тела остался выражением, а не объявлением", () => {
  /* Слово взято из таблицы, а не заведено, и потому опасность у него своя:
     присвоив `элемент` левому краю, легко отнять его у выражений. Улика — та
     же программа, где `элемент` стоит с отступом и обязана работать. */
  const п = parse(ВЗЯТЬ(""), "п.flang")
  assert.equal(evaluate(п, "Ф", [[10, 20, 30]]), 10)
})

