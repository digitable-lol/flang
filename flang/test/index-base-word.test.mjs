/**
 * `элемент начиная с 0` — СЛОВО, которым автор объявляет базу номера в файле.
 *
 * ── Чем это отличается от вчерашнего ────────────────────────────────────────
 * База номера уже была свойством ПРОГРАММЫ (`базаНомера`), и её уже читали все
 * одиннадцать мест — рантайм, интерпретатор, восемь печатей и типизатор. Ставил
 * её при этом ключ запуска `--index-base`, то есть автор программы её не писал
 * НИГДЕ. Здесь появляется объявление, и оно кладётся у левого края — рядом со
 * `свойство` и `требует`, тем же укладом.
 *
 * ── Чего здесь НЕ проверяется, и это нарочно ────────────────────────────────
 * Не проверяется, что слово «есть». Проверяется, что оно ЧИТАЕТСЯ ТРЕМЯ
 * разными потребителями и что каждый из трёх при другом числе отвечает ДРУГОЕ:
 *
 *   ВЫЧИСЛЕНИЕ  `элемент 1 в [10,20,30]` даёт 20 при базе 0 и 10 при базе 1.
 *   ДОКАЗАТЕЛЬСТВО  нестрогая граница `н не больше (длина эл)` доказывает место
 *               при базе 1 и НЕ доказывает при базе 0; строгая — наоборот.
 *               Это и было целью всей работы: типизатор доказывал условие,
 *               верное при ОБЕИХ базах, то есть более слабое, чем нужно.
 *   ПЕЧАТЬ      во все восемь целей, и мера здесь ПОБАЙТОВАЯ.
 *
 * ── Умолчание — ЕДИНИЦА, и это мерится, а не обещается ──────────────────────
 * Весь сегодняшний корпус написан при базе 1, поэтому программа БЕЗ объявления
 * обязана считаться и печататься ровно как прежде. Проверяется двумя мерами
 * сразу: ключа `базаНомера` в её AST нет вовсе (байты канонического JSON те же)
 * и печать её совпадает знак в знак с печатью той же программы, объявившей
 * единицу явно.
 *
 * ── Четыре поверхности ──────────────────────────────────────────────────────
 * Слова не заведено ни одного: `элемент` (`item`) и `начиная с` (`startingWith`)
 * стоят в таблице лексера с самого начала и открыты на всех четырёх. Проверка
 * ниже читает одну и ту же программу по-русски, по-английски, на эсперанто и
 * по-китайски и требует ОДНОГО числа.
 *
 * Запуск: node --test flang/test/index-base-word.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"

import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"
import { emitTargets, loadEmitter } from "../bin/flang.mjs"

/** Объявление базы отдельной строкой; пустая строка значит «не объявлено». */
const объявив = (строка) => (строка === "" ? "" : `${строка}\n\n`)

/** Программа, чей ответ ЗАВИСИТ от базы: берёт элемент номер один. */
const ВЗЯТЬ = (объявление) => `модуль «М»

${объявив(объявление)}тотальная функция «Ф»
  принимает эл: список числа
  возвращает число
  элемент 1 в эл
`

/** Программа, чьё ДОКАЗАТЕЛЬСТВО зависит от базы: сторож у `элемент`. */
const ПОД_СТОРОЖЕМ = (объявление, сторож) => `модуль «М»

${объявив(объявление)}тотальная функция «Взять»
  принимает эл: список числа, н: нат
  возвращает число
  если ${сторож} то элемент н в эл иначе 0
`

const НЕСТРОГИЙ_ВЕРХ = "н больше 0 и притом н не больше (длина эл)"
const СТРОГИЙ_ВЕРХ = "н не меньше 0 и притом н меньше (длина эл)"

/** Сколько мест частичных форм закрыл АНАЛИЗ — то, что видит доказательство. */
const доказано = (исходник) => checkTypes(parse(исходник, "проба.flang")).доказаныАнализом.size

/** Код отказа разбора и его текст; `null`, если программа разобралась. */
function отказ(исходник) {
  try {
    parse(исходник, "проба.flang")
    return null
  } catch (error) {
    /* Код у отказа разбора едет в `diagnostics`, а не полем на ошибке: так его
       читают и остальные проверки репозитория. */
    return { code: error.diagnostics?.[0]?.code, message: error.message }
  }
}

/* ================================================================== */
/* ТО, РАДИ ЧЕГО СЛОВО ЗАВЕДЕНО                                        */
/* ================================================================== */

test("две базы — ДВА разных ответа, и обе программы валидны", () => {
  /* Главная проверка файла. Если бы объявление никуда не доезжало, оба числа
     были бы одним, и всё остальное здесь стало бы прозой. */
  const сНулём = parse(ВЗЯТЬ("элемент начиная с 0"), "п.flang")
  const сЕдиницей = parse(ВЗЯТЬ("элемент начиная с 1"), "п.flang")

  assert.deepEqual(checkTypes(сНулём).diagnostics, [], "программа с базой 0 обязана быть валидной")
  assert.deepEqual(checkTypes(сЕдиницей).diagnostics, [], "программа с базой 1 обязана быть валидной")

  assert.equal(evaluate(сНулём, "Ф", [[10, 20, 30]]), 20, "при базе 0 номер 1 — это второй элемент")
  assert.equal(evaluate(сЕдиницей, "Ф", [[10, 20, 30]]), 10, "при базе 1 номер 1 — это первый элемент")
})

test("объявление доезжает до ДОКАЗАТЕЛЬСТВА, и в обе стороны", () => {
  /* Ради этого вся работа и делалась: до неё типизатор базы не знал и потому
     доказывал условие, верное при ОБЕИХ базах, — то есть более слабое, чем
     нужно. Проверка стоит парой, потому что одна половина не ловит подмену
     «всегда доказано» или «никогда не доказано»: при базе 1 верна нестрогая
     граница и ложна строгая, при базе 0 — ровно наоборот. */
  assert.equal(доказано(ПОД_СТОРОЖЕМ("элемент начиная с 1", НЕСТРОГИЙ_ВЕРХ)), 1, "при базе 1 `н ≤ длина` — это граница")
  assert.equal(доказано(ПОД_СТОРОЖЕМ("элемент начиная с 0", НЕСТРОГИЙ_ВЕРХ)), 0, "при базе 0 `н ≤ длина` пускает за край")
  assert.equal(доказано(ПОД_СТОРОЖЕМ("элемент начиная с 0", СТРОГИЙ_ВЕРХ)), 1, "при базе 0 граница строгая")
  assert.equal(доказано(ПОД_СТОРОЖЕМ("элемент начиная с 1", СТРОГИЙ_ВЕРХ)), 0, "при базе 1 `н ≥ 0` не даёт низа")
})

/* ================================================================== */
/* УМОЛЧАНИЕ — ЕДИНИЦА, и старая программа не сдвинулась ни на байт    */
/* ================================================================== */

test("молчание значит единицу — и в вычислении, и в доказательстве", () => {
  assert.equal(evaluate(parse(ВЗЯТЬ(""), "п.flang"), "Ф", [[10, 20, 30]]), 10)
  assert.equal(доказано(ПОД_СТОРОЖЕМ("", НЕСТРОГИЙ_ВЕРХ)), 1)
  assert.equal(доказано(ПОД_СТОРОЖЕМ("", СТРОГИЙ_ВЕРХ)), 0)
})

test("у программы без объявления ключа `базаНомера` в AST НЕТ вовсе", () => {
  /* Единица, выложенная в AST явно, переписала бы байты канонического JSON
     каждой программы репозитория ради числа, которое и так известно. */
  const молча = parse(ВЗЯТЬ(""), "п.flang")
  assert.equal(Object.hasOwn(молча, "базаНомера"), false, "молчание завело ключ, которого вчера не было")

  /* А у объявившей — есть, и стоит он ПОСЛЕДНИМ: порядок ключей и есть байты. */
  const явно = parse(ВЗЯТЬ("элемент начиная с 1"), "п.flang")
  assert.equal(явно.базаНомера, 1)
  assert.equal(Object.keys(явно).at(-1), "базаНомера", "ключ вставлен в середину — это байты чужого AST")
  assert.deepEqual(
    Object.keys(молча),
    Object.keys(явно).filter((ключ) => ключ !== "базаНомера"),
    "объявление сдвинуло не только свой ключ",
  )
})

test("ПОБАЙТОВО: объявленная единица печатается как молчание — во все восемь целей", async () => {
  /* Мера умолчания, и она сильнее равенства AST: печать могла бы разойтись и
     при одинаковом дереве — например, приписав в заголовок «база объявлена».
     Цели берутся РЕЕСТРОМ каталога, а не списком здесь: появись девятая — она
     попадёт под ту же проверку сама. */
  const молча = parse(ВЗЯТЬ(""), "п.flang")
  const явно = parse(ВЗЯТЬ("элемент начиная с 1"), "п.flang")
  const сНулём = parse(ВЗЯТЬ("элемент начиная с 0"), "п.flang")

  const цели = await emitTargets()
  assert.ok(цели.length >= 8, `целей печати найдено ${цели.length}`)
  for (const цель of цели) {
    const { emit } = await loadEmitter(цель, цели)
    const байты = (программа) => (emit(программа, {}).files ?? []).map((ф) => ({ path: ф.path, content: ф.content }))
    assert.deepEqual(байты(молча), байты(явно), `цель «${цель}»: умолчание разошлось с объявленной единицей`)
    /* И тут же — улика к тесту выше: сверка обязана УМЕТЬ краснеть. */
    assert.notDeepEqual(байты(молча), байты(сНулём), `цель «${цель}»: база 0 напечаталась как база 1`)
  }
})

