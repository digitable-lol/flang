test("одно объявление на всех четырёх поверхностях — и число одно", () => {
  /* Слова не заведено ни одного: `элемент`/`item`/`ero`/`元素` и
     `начиная с`/`starting with`/`komencante per`/`起始于` стоят в таблице с
     самого начала. Дыры в ней сегодня все до одной в словаре доказательства,
     и восемнадцатой здесь не появилось. */
  const поверхности = {
    ru: "модуль «М»\n\nэлемент начиная с 0\n",
    en: "module «M»\n\nitem starting with 0\n",
    eo: "module «M»\n\nero komencante per 0\n",
    zh: "模块 «M»\n\n元素 起始于 0\n",
  }
  for (const [имя, исходник] of Object.entries(поверхности)) {
    assert.equal(parse(исходник, "п.flang").базаНомера, 0, `поверхность «${имя}» базу не объявила`)
  }
})

