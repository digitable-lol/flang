test("объявление ПОБЕЖДАЕТ ключ `--index-base`, а не уступает ему молча", async () => {
  /* Заказ давал выбор: отказать или посчитать по объявленному. Выбрано второе,
     и довод один. База — свойство ПРОГРАММЫ, как имя модуля; ключ, способный
     его переиграть, вернул бы ровно то, что эта работа убрала, — два источника
     одного числа. Тихого расхождения при этом не возникает: программа считает
     то, что в ней написано, при любом ключе.
     Молчащая программа ключу по-прежнему подчиняется — переходный уклад для
     файлов, где объявления ещё нет. */
  const сНулём = parse(ВЗЯТЬ("элемент начиная с 0"), "п.flang")
  assert.equal(evaluate(сНулём, "Ф", [[10, 20, 30]], { indexBase: 1 }), 20, "ключ переиграл объявление автора")

  const молча = parse(ВЗЯТЬ(""), "п.flang")
  assert.equal(evaluate(молча, "Ф", [[10, 20, 30]], { indexBase: 0 }), 20, "молчащая программа ключ не услышала")

  const цели = await emitTargets()
  for (const цель of цели) {
    const { emit } = await loadEmitter(цель, цели)
    const байты = (программа, опции) => (emit(программа, опции).files ?? []).map((ф) => ф.content).join("")
    assert.equal(
      байты(сНулём, { indexBase: 1 }),
      байты(сНулём, { indexBase: 0 }),
      `цель «${цель}»: печать объявившей программы зависит от ключа`,
    )
  }
})
