/**
 * Третья форма класса номера, и единственная, где номеров ДВА. Договор рантайма
 * (`builtins.mjs`, `подстрока`) при длине L и базе b — четыре факта:
 * `начало ≥ b`, `начало ≤ L + b`, `конец ≤ L` (базой НЕ сдвигается),
 * `конец ≥ начало − b`. Каждый из четырёх проверяется здесь и своим тестом, и
 * своей подделкой: правило, у которого нет отвергаемой подделки, доказывает не
 * то, что написано в его шапке.
 */
const поСтроке = (тело, типы = "т: строка, н: нат") => `тотальная функция «Кусок»
  принимает ${типы}
  возвращает строка
  ${тело}
`

test("`подстрока т с 1 по (длина т)` доказана БЕЗ непустоты — и это верно", () => {
  /* Начало 1 при базе 1 даёт `start = 0`, а `0 ≤ L` верно и у пустой строки;
     конец помнит имя. Пустая строка здесь — законный вход, а не край. */
  const исходник = поСтроке("подстрока т с 1 по (длина т)")
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 1, "первый факт даёт литерал, третий — имя, четвёртый — числа")
})

test("та же запись при базе 0 НЕ доказана: четвёртый факт теряет базу", () => {
  /* `конец ≥ начало − b`: при b = 1 это `длина т ≥ 0` и верно всегда, при b = 0
     это `длина т ≥ 1` и требует непустоты. База — свойство программы, и отказ
     достаётся ровно той, которой причитается. */
  const дерево = parse(МОДУЛЬ + поСтроке("подстрока т с 1 по (длина т)"))
  assert.equal(checkTypes({ ...дерево, базаНомера: 1 }).доказаныАнализом.size, 1)
  assert.equal(checkTypes({ ...дерево, базаНомера: 0 }).доказаныАнализом.size, 0)
})

