/**
 * Тесты границ НОМЕРА — верха, выраженного именем.
 *
 * Класс отказов здесь другой, чем у непустоты, и другим он остаётся до конца.
 * Непустота — утверждение об ОДНОМ значении, и укладывается она в число
 * (`длинаНиз`). «Номер внутри списка» — утверждение о ДВУХ именах сразу
 * («н меньше длины эл»), и ни при каком выборе числа в отрезок оно не ложится:
 * длина `эл` в момент проверки типов есть имя, а не число. Отсюда `подДлиной`
 * — набор имён, чьей длины число заведомо меньше.
 *
 * Проверяется пять разных утверждений, и они не заменяют друг друга:
 *
 *   ДВЕ ПОЛОВИНЫ  доказывают ОБЕ границы разом и ни одна поодиночке: низ даёт
 *                 отрезок (число против числа), верх — имя.
 *   ОБЕ БАЗЫ      условие `1 ≤ н < длина` верно и при базе номера 1, и при 0,
 *                 а базы проверка типов не видит вовсе.
 *   ПОТЕРЯ        уточнение обязано ТЕРЯТЬСЯ на арифметике и на перевязке
 *                 имени. Каждая потеря — свой тест: снятая по ошибке проверка
 *                 это отказ, которого больше никто не поймает.
 *   ПОДДЕЛКИ      условие про ДРУГОЕ имя, про ДРУГОЕ сравнение и про ДРУГОЕ
 *                 выражение обязано оставить место отвергнутым.
 *   ЗАСЛОН        доказанное анализом НЕ становится отметкой `доказана`, пока
 *                 у формы нет доказанного пути печати: свод считает по отметке,
 *                 и отметка без печати сделала бы его число неправдой.
 *
 * Запуск: node --test flang/test/index-bounds.test.mjs
 */
import assert from "node:assert/strict"
import { test } from "node:test"

import { СНИМАЮТСЯ_НЕПУСТОТОЙ } from "../src/builtins.mjs"
import { ЧАСТИЧНЫЕ } from "../src/failures.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"

const МОДУЛЬ = "модуль «М»\n\n"
const проверить = (исходник) => checkTypes(parse(МОДУЛЬ + исходник))

/** Сколько мест частичных форм доказал АНАЛИЗ (до заслона печати). */
const доказано = (исходник) => проверить(исходник).доказаныАнализом.size

/** Сколько мест доказано ДЛЯ ПЕЧАТИ — то есть что увидит свод. */
const дляПечати = (исходник) => проверить(исходник).доказаны.size

const коды = (исходник) => проверить(исходник).diagnostics.map((d) => d.code)

/** Тело функции с двумя параметрами: список и номер. */
const поСписку = (тело, номер = "нат") => `тотальная функция «Взять»
  принимает эл: список числа, н: ${номер}
  возвращает число
  ${тело}
`

/* ================================================================== */
/* Две половины: низ отрезком, верх именем                             */
/* ================================================================== */

test("номер доказан обеими границами: `н больше 0 и притом н меньше (длина эл)`", () => {
  const исходник = поСписку("если н больше 0 и притом н меньше (длина эл) то элемент н в эл иначе 0")
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 1, "низ дал отрезок, верх — имя")
})

test("одной верхней границы НЕ хватает: `н меньше (длина эл)` без низа", () => {
  /* Улика к тесту выше. При базе номера 1 значение 0 выходит за начало списка,
     и знание «меньше длины» об этом не говорит ничего. */
  const исходник = поСписку("если н меньше (длина эл) то элемент н в эл иначе 0")
  assert.equal(доказано(исходник), 0)
})

test("одной нижней границы НЕ хватает: `н больше 0` без верха", () => {
  const исходник = поСписку("если н больше 0 то элемент н в эл иначе 0")
  assert.equal(доказано(исходник), 0)
})

test("верх, посчитанный числом, годится так же: `элемент 1 в эл` при длине не меньше двух", () => {
  /* Вторая дорога у той же верхней границы: длина известна снизу, номер —
     сверху, и утверждение `н < длина` доказывается двумя числами. */
  const исходник = `тотальная функция «Второй»
  возвращает число
  элемент 1 в [10, 20, 30]
`
  assert.equal(доказано(исходник), 1)
})

test("`элемент 3 в [10, 20]` НЕ доказан: номер за концом", () => {
  const исходник = `тотальная функция «Третий»
  возвращает число
  элемент 3 в [10, 20]
`
  assert.equal(доказано(исходник), 0)
})

test("`элемент 1 в [10]` доказан при базе 1 и НЕ доказан при базе 0", () => {
  /* Цена прежнего решения «одно условие на обе базы», названная числом: это
     место безопасно при базе 1 и опасно при базе 0. Пока база была ключом
     запуска, приходилось отказывать обеим; теперь она свойство программы, и
     отказ достаётся ровно той, которой он причитается. */
  const исходник = `тотальная функция «Один»
  возвращает число
  элемент 1 в [10]
`
  const дерево = parse(МОДУЛЬ + исходник)
  assert.equal(checkTypes({ ...дерево, базаНомера: 1 }).доказаныАнализом.size, 1)
  assert.equal(checkTypes({ ...дерево, базаНомера: 0 }).доказаныАнализом.size, 0)
})

/* ================================================================== */
/* Строка: та же граница у «символ»                                    */
/* ================================================================== */

test("«символ» доказан тем же условием, что и «элемент»", () => {
  const исходник = `тотальная функция «Знак»
  принимает т: строка, н: нат
  возвращает строка
  если н больше 0 и притом н меньше (длина т) то символ н в т иначе ""
`
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 1)
})

/* ================================================================== */
/* Потеря: где уточнение перестаёт быть верным                         */
/* ================================================================== */

test("ГРАНИЦА ТЕРЯЕТСЯ НА АРИФМЕТИКЕ: про `н плюс 1` не известно ничего", () => {
  /* Главная ловушка этого хода. `н` меньше длины `эл` — а `н плюс 1` не меньше
     ничего, и «сохранить границу через сложение» здесь не отклонено вежливо:
     арифметика строит числовой тип заново (`отрезок`), а `отрезок` про
     `подДлиной` не знает вовсе. */
  const исходник = поСписку("если н больше 0 и притом н меньше (длина эл) то элемент (н плюс 1) в эл иначе 0")
  assert.equal(доказано(исходник), 0)
})

test("ГРАНИЦА ТЕРЯЕТСЯ НА ПЕРЕВЯЗКЕ ИМЕНИ: `пусть эл = []`", () => {
  /* Знание записано ИМЕНЕМ, а имя перевязывается. Не отмени знание при
     связывании — и уточнение стало бы ложным ровно там, где этого удобнее
     всего не заметить. */
  const исходник = `тотальная функция «Взять»
  принимает эл: список числа, н: нат
  возвращает число
  если н больше 0 и притом н меньше (длина эл)
    то
      пусть эл равно []
      элемент н в эл
    иначе 0
`
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 0)
})

test("вложенное числовое сужение НЕ отнимает именной верх", () => {
  /* Сужение только ДОБАВЛЯЕТ знание, а `пересечь` строит отрезок заново и про
     `подДлиной` не знает. Не перенеси именной верх через числовое сужение — и
     `если н меньше 100` внутри уже доказанной ветви отнимал бы доказанное. */
  const исходник = `тотальная функция «Взять»
  принимает эл: список числа, н: нат
  возвращает число
  если н больше 0 и притом н меньше (длина эл)
    то (если н меньше 100 то элемент н в эл иначе 0)
    иначе 0
`
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 1)
})

test("номер, объявленный `число`, НЕ доказан: рантайм требует целого", () => {
  /* `н больше 0` у дробного даёт `н ≥ 0`, а не `н ≥ 1`: между 0 и 1 дробных
     сколько угодно. И даже дай оно единицу — `элемент 1.5 в эл` отказывает
     раньше всякой границы (`builtins.mjs`, `expectInteger`). */
  const исходник = поСписку("если н больше 0 и притом н меньше (длина эл) то элемент н в эл иначе 0", "число")
  assert.equal(доказано(исходник), 0)
})

test("граница НЕ живёт в ветви `иначе`: там условие ложно", () => {
  const исходник = поСписку("если н больше 0 и притом н меньше (длина эл) то 0 иначе элемент н в эл")
  assert.equal(доказано(исходник), 0)
})

