test("ПОДДЕЛКА Ф4 «через отрицание»: ветвь `иначе` от `н больше м` знания НЕ даёт", () => {
  /* `Е не больше Е` в IEEE-754 не теорема: на `не число` ложны ОБА сравнения
     сразу, и ветвь `иначе` от `н больше м` достаётся в том числе значению, про
     которое `н ≤ м` ложно. У границы через ДЛИНУ этой беды нет — длина
     натуральна по построению, — а здесь оба конца произвольны. */
  const исходник = `тотальная функция «Кусок»
  принимает «т»: строка, «н»: нат, «м»: нат
  возвращает строка
  если «н» больше 0 и притом «н» не больше (длина «т») и притом «м» не больше (длина «т»)
    то (если «н» больше «м» то "" иначе подстрока «т» с «н» по «м»)
    иначе ""
`
  assert.equal(доказано(исходник), 0)
})

