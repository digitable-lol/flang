/* Подделки: каждая метит в свою посылку                               */
/* ================================================================== */

test("ПОДДЕЛКА «чужое имя»: условие про `другой`, а номер берётся у `эл`", () => {
  const исходник = `тотальная функция «Взять»
  принимает эл: список числа, другой: список числа, н: нат
  возвращает число
  если н больше 0 и притом н меньше (длина другой) то элемент н в эл иначе 0
`
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 0, "длина чужого списка о своём не говорит ничего")
})

test("ПОДДЕЛКА «другое сравнение»: верх вместо низа", () => {
  const исходник = поСписку("если н больше 0 и притом н больше (длина эл) то элемент н в эл иначе 0")
  assert.equal(доказано(исходник), 0)
})

test("нестрогое `не больше` доказывает ПРИ БАЗЕ 1 — той, что у программы по умолчанию", () => {
  /* Это перестало быть подделкой ровно тогда, когда база стала свойством
     ПРОГРАММЫ. `at = н − 1` при `1 ≤ н ≤ длина` лежит в [0, длина−1] — сторож
     верен, и написан он в корпусе именно так (14 мест). Раньше правило базы не
     знало и отказывалось от нестрогой границы у обеих. */
  const исходник = поСписку("если н больше 0 и притом н не больше (длина эл) то элемент н в эл иначе 0")
  assert.deepEqual(коды(исходник), [])
  assert.equal(доказано(исходник), 1)
})

test("ПОДДЕЛКА «чужая база»: та же программа при базе 0 НЕ доказана", () => {
  /* Главная подделка этого хода, и она про смысл, а не про синтаксис. Тот же
     текст, та же граница, другая база — и `н = длина эл` указывает на один за
     концом. Программа обязана ОТКАЗАТЬ на этом месте (сторож остаётся), а не
     посчитать тихо. */
  const тело = "если н больше 0 и притом н не больше (длина эл) то элемент н в эл иначе 0"
  const дерево = parse(МОДУЛЬ + поСписку(тело))
  assert.equal(checkTypes({ ...дерево, базаНомера: 1 }).доказаныАнализом.size, 1, "база 1 — доказано")
  assert.equal(checkTypes({ ...дерево, базаНомера: 0 }).доказаныАнализом.size, 0, "база 0 — сторож остаётся")
})

test("СТРОГОЕ `меньше` доказывает при ОБЕИХ базах: оно сильнее нужного", () => {
  /* Улика к подделке выше: с базой спорит только нестрогая граница. Строгая
     верна и там и там, и потому от базы не зависит вовсе. */
  const тело = "если н больше 0 и притом н меньше (длина эл) то элемент н в эл иначе 0"
  const дерево = parse(МОДУЛЬ + поСписку(тело))
  assert.equal(checkTypes({ ...дерево, базаНомера: 1 }).доказаныАнализом.size, 1)
  assert.equal(checkTypes({ ...дерево, базаНомера: 0 }).доказаныАнализом.size, 1)
})

test("база — свойство ПРОГРАММЫ, и её отсутствие значит единицу", () => {
  /* Переходный уклад назван числом: у программы без объявления база равна
     единице — то самое умолчание, при котором написан весь корпус. Ни одна
     написанная программа не меняет смысла ни на одно значение. */
  const тело = "если н больше 0 и притом н не больше (длина эл) то элемент н в эл иначе 0"
  const дерево = parse(МОДУЛЬ + поСписку(тело))
  assert.equal(дерево.базаНомера, undefined, "объявления в программе нет")
  assert.equal(checkTypes(дерево).доказаныАнализом.size, 1, "и это ровно база 1")
})

test("ПОДДЕЛКА «другое выражение»: `длина (хвост эл)` вместо `длина эл`", () => {
  /* Условие истинное и даже более сильное, и всё равно не в счёт: сужение
     читает ИМЯ, а не выражение. Та же названная граница, что у нижней границы
     длины, и по тому же доводу. */
  const исходник = поСписку("если н больше 0 и притом н меньше (длина (хвост эл)) то элемент н в эл иначе 0")
  assert.equal(доказано(исходник), 0)
})

test("ПОДДЕЛКА «другой номер»: условие про `н`, а берётся `м`", () => {
  const исходник = `тотальная функция «Взять»
  принимает эл: список числа, н: нат, м: нат
  возвращает число
  если н больше 0 и притом н меньше (длина эл) то элемент м в эл иначе 0
`
  assert.equal(доказано(исходник), 0)
})

