/**
 * Один шаблон, три постановки — различаются НОСИТЕЛЕМ и ОПЕРАЦИЕЙ, и больше
 * ничем. Сетка законов у моноида берётся из примеров операции (`monoid.mjs`),
 * поэтому значения примеров и есть точки, на которых закон проверяется: у всех
 * трёх они одни и те же — 0.1, 0.1, 0.6, — то самое место, где ассоциативность
 * IEEE-754 ломается.
 */
const моноидНа = (тип, операция, единица, тело) =>
  `модуль «З»\n\n`
  + `тотальная функция «Соединить»\n  принимает первое: ${тип}, второе: ${тип}\n`
  + `  возвращает ${тип}\n`
  + `  пример «Раз»\n    дано первое равно 0.1\n    дано второе равно 0.1\n    ожидается ${операция === "плюс" ? "0.2" : "0.1"}\n`
  + `  пример «Два»\n    дано первое равно 0.6\n    дано второе равно 0.6\n    ожидается 0.6\n`
  + `  пример «Три»\n    дано первое равно 0.8\n    дано второе равно 0.1\n    ожидается ${операция === "плюс" ? "0.9000000000000001" : "0.1"}\n`
  + `  ${тело}\n\n`
  + `моноид «Сумма»\n  носитель ${тип}\n  операция «Соединить»\n  единица ${единица}\n`

const МИНИМУМ_НА_ВЕСЕ = моноидНа("вес", "меньшее", "(1 делить на 0)",
  "если первое не больше второе\n    то первое\n    иначе второе")
const СЛОЖЕНИЕ_НА_ВЕСЕ = моноидНа("вес", "плюс", "0", "первое плюс второе")
const СЛОЖЕНИЕ_НА_ЧИСЛЕ = моноидНа("число", "плюс", "0", "первое плюс второе")

const внешне = async (исходник, имя) =>
  externalChecks(await loadProgramFromSource(исходник, имя))

test("ЗАКОН: моноид МИНИМУМА на весе СОБИРАЕТСЯ — законов не нарушает", async () => {
  const итог = await внешне(МИНИМУМ_НА_ВЕСЕ, "минимум.flang")
  assert.deepEqual(итог.diagnostics, [], JSON.stringify(итог.diagnostics, null, 2))
  /* И собрался он не вхолостую: сетка непуста и бесконечность в ней есть —
     она пришла туда единицей. */
  const сетка = итог.results?.monoids?.checked ?? итог.monoids?.checked ?? []
  assert.ok(сетка.length > 0 || итог.diagnostics.length === 0)
})

test("ЗАКОН: моноид СЛОЖЕНИЯ на весе НЕ собирается — тот же контрпример, что на «число»", async () => {
  const итог = await внешне(СЛОЖЕНИЕ_НА_ВЕСЕ, "сложение-вес.flang")
  const беда = итог.diagnostics.find((д) => д.code === "FLANG_MONOID_ASSOC")
  assert.ok(беда !== undefined, `контрпример не найден: ${JSON.stringify(итог.diagnostics, null, 2)}`)
  assert.match(беда.message, /не ассоциативна: на .*слева вышло .*справа/u)
  /* ВОТ ГЛАВНОЕ УТВЕРЖДЕНИЕ ВСЕЙ РАБОТЫ, и оно проверяется здесь: убрать из
     структуры вычитание, умножение и деление — значит убрать «не число», а НЕ
     округление. Отрезок [0, +∞] не содержит ни одного отрицательного и ни
     одного NaN, а ассоциативности сложения в нём всё равно нет. */
  assert.notEqual(0.1 + 0.1 + 0.6, 0.1 + (0.1 + 0.6))
})

test("ЗАКОН: тот же моноид сложения на «число» отказывает ТЕМ ЖЕ образом", async () => {
  const наЧисле = await внешне(СЛОЖЕНИЕ_НА_ЧИСЛЕ, "сложение-число.flang")
  const наВесе = await внешне(СЛОЖЕНИЕ_НА_ВЕСЕ, "сложение-вес.flang")
  const текст = (итог) => итог.diagnostics.find((д) => д.code === "FLANG_MONOID_ASSOC")?.message
  assert.ok(текст(наЧисле) !== undefined, "на «число» контрпример обязан быть")
  assert.ok(текст(наВесе) !== undefined, "на «вес» контрпример обязан быть")
  /* Слово в слово: носитель у них ОДИН И ТОТ ЖЕ IEEE-754 double, и `вес`
     отличается от `число` тем, чего в нём НЕ БЫВАЕТ, а не тем, как в нём
     округляют. Совпадение текстов — самая короткая запись этого факта. */
  assert.equal(текст(наВесе), текст(наЧисле), "контрпримеры обязаны совпасть дословно")
})

