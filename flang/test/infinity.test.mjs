test("объявленный тип — источник ФАКТА, а не аксиома: список закрыт двумя именами", () => {
  const имя = { kind: "var", name: "х" }
  const параметр = (тип) => [{ name: "х", type: { kind: "named", name: тип } }]
  /* Дно есть ровно у двух типов языка, и ровно они факт дают. */
  for (const тип of ["вес", "стоимость", "weight", "нат", "нат"]) {
    assert.ok(неотрицательно(имя, известноеПоТипу(параметр(тип))), `«${тип}» обязан давать факт`)
  }
  /* А у этих дна нет, и молчаливо принять их значило бы принять ложь:
     у `целое` дно −(2^53−1), у `число` его нет вовсе. */
  for (const тип of ["целое", "число", "строка", "Ромашка"]) {
    assert.ok(!неотрицательно(имя, известноеПоТипу(параметр(тип))), `«${тип}» не смеет давать факт`)
  }
  /* Умножения в правиле нет и не будет — по той самой паре, ради которой
     умножение не впущено и в сам тип. */
  const произведение = { kind: "binary", op: "mul", left: имя, right: имя }
  assert.ok(!неотрицательно(произведение, известноеПоТипу(параметр("вес"))), "0 × ∞ = не число")
  const разность = { kind: "binary", op: "sub", left: имя, right: имя }
  assert.ok(!неотрицательно(разность, известноеПоТипу(параметр("вес"))), "∞ − ∞ = не число")
  /* А сумма и выбор — есть, и это и есть замкнутость отрезка. */
  const сумма = { kind: "binary", op: "add", left: имя, right: имя }
  assert.ok(неотрицательно(сумма, известноеПоТипу(параметр("вес"))))
})

