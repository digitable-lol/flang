/* ПОДДЕЛКА: NaN в языке сегодня проходит молча                        */
/* ------------------------------------------------------------------ */

const НЕ_ЧИСЛО = `модуль «Подделка»

тотальная функция «Ноль на ноль»
  принимает н: число
  возвращает число
  0 делить на 0
`

test("ПОДДЕЛКА: `0 делить на 0` проходит типизацию без единой диагностики", () => {
  const итог = проверить(НЕ_ЧИСЛО)
  assert.deepEqual(коды(итог), [], тексты(итог))
  /* И это не придирка: значение, которое отсюда выходит, в JSON не
     представимо вовсе — оно уезжает к пользователю как `null`. */
  assert.ok(Number.isNaN(0 / 0))
  assert.equal(JSON.stringify(0 / 0), "null")
})
