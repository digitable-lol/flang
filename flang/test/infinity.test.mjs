/**
 * Отрезок [0, +∞] — тип `вес`, и всё, что о нём ПРОВЕРЕНО ВЫЧИСЛЕНИЕМ.
 *
 * ── С чего начато: заказанное утверждение оказалось наполовину ложным ────────
 * Заказ звучал так: «неотрицательные числа с бесконечностью, отрезок [0, +∞], по
 * сложению образуют настоящий коммутативный моноид; беда только в трёх операциях
 * — `∞ − ∞`, `0 × ∞`, `∞ / ∞`; уберите их, и законы вернутся».
 *
 * Половина этого — правда, и она проверена ниже: сложение на [0, +∞] ЗАМКНУТО,
 * коммутативно, ноль нейтрален, бесконечность поглощает, NaN недостижим.
 *
 * Вторая половина — НЕПРАВДА, и контрпример вычислен, а не рассказан:
 *
 *   (0.1 + 0.1) + 0.6 = 0.8
 *    0.1 + (0.1 + 0.6) = 0.7999999999999999
 *
 * Оба слагаемых из [0, +∞], NaN нигде нет, вычитания нет — а ассоциативности
 * тоже нет. Потому что ассоциативность ломает НЕ NaN, а ОКРУГЛЕНИЕ, и убрать
 * вычитание значит убрать NaN, а не округление. Это тот же контрпример, каким
 * ветка точного десятичного отвергла моноид над `число`, и он тот же самый не
 * случайно: `число` и `вес` — один и тот же IEEE-754 double, и `вес` отличается
 * от `число` тем, чего в нём НЕ БЫВАЕТ (отрицательных и NaN), а не тем, как в
 * нём округляют.
 *
 * Отсюда вывод, на котором стоит весь файл: КОММУТАТИВНЫЙ МОНОИД НА [0, +∞] ЕСТЬ,
 * НО ЕГО ОПЕРАЦИЯ — НЕ СЛОЖЕНИЕ, А МИНИМУМ (и максимум). `минимум` и `максимум`
 * не округляют вовсе — они ВЫБИРАЮТ один из операндов, — поэтому ассоциативны
 * точно, а не почти. Единица минимума — `+∞`, единица максимума — `0`, и обе
 * лежат внутри типа. Сложение остаётся в типе как замкнутая монотонная операция
 * и как то, над чем минимум дистрибутивен (тропическое полукольцо: ровно оно и
 * есть кратчайший путь), но моноидом объявляется НЕ ОНО.
 *
 * Ниже это доказано трижды: числами JavaScript, программой на flang и отказом
 * сборки моноида — на всех трёх уровнях один и тот же контрпример.
 */
