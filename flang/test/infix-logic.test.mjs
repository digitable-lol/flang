/* ─────────── главный сторож: корпус не сдвинулся ни на один токен ────────── */

const исключить = (путь) => путь.includes("node_modules") || путь.startsWith("dist")
const корпус = [
  ...globSync("**/*.flang", { cwd: корень, exclude: исключить }),
  ...globSync("**/*.fts", { cwd: корень, exclude: исключить }),
].sort()

/**
 * Поток токенов не сдвинулся — и это ПЕРЕСЧИТАНО, а не унаследовано.
 *
 * ── Что здесь было и почему перестало работать ──────────────────────────────
 *
 * Прежняя редакция требовала, чтобы новых слов в корпусе не было НИ ОДНОГО, и на
 * этом строила дешёвое доказательство: таблица ключевых слов только пополнилась,
 * склейка идёт от длинной фразы к короткой, значит поток мог поехать ровно в той
 * позиции, где победила НОВАЯ фраза; таких позиций нет — значит не поехало
 * нигде. Довод верный, и в нём же было сказано прямо: напиши `или` в любом файле
 * — проверка покраснеет и ПОТРЕБУЕТ ПЕРЕСЧИТАТЬ ПОТОК ЗАНОВО, а не поверить на
 * слово.
 *
 * Ровно это и случилось. Корпус вырос: решения LeetCode и `self/totality.flang`
 * пишут `или`, `не` и `и притом` сорок с лишним раз. Посылка «ни одного» умерла
 * не от ошибки, а от успеха — слова вошли в обиход.
 *
 * ── Чем она заменена ────────────────────────────────────────────────────────
 *
 * Довод сохранён целиком, но применён к тому, к чему применим. Файлы делятся
 * ровно на два вида, и каждому — своё утверждение:
 *
 *   НЕ ИСПОЛЬЗУЮТ новых слов. Прежний довод действует без изменений: победить
 *   новой фразе негде, поток тот же, каким был. Проверяется, что таких файлов
 *   по-прежнему большинство корпуса.
 *
 *   ИСПОЛЬЗУЮТ. У них «прежнего потока» не существовало вовсе — они написаны
 *   после того, как слова появились. Про них надо утверждать другое: что слово
 *   стало ключевым ТАМ, ГДЕ АВТОР ЭТОГО ХОТЕЛ, и не разрезало ничего соседнего.
 *   Это проверяется разбором: файл обязан разобраться, и в его дереве обязано
 *   стоять то самое логическое выражение, а не два обломка.
 *
 * ── Чего этот тест не утверждает ────────────────────────────────────────────
 *
 * Он не заменяет побайтовую сверку лексера с близнецом на flang
 * (`self-lexer.test.mjs`) — та проверяет ДРУГОЕ: что два лексера читают корпус
 * одинаково. Здесь речь об одном лексере до и после пополнения таблицы.
 */
test("поток токенов пересчитан: где новых слов нет — он тот же, где есть — они разобраны как задумано", () => {
  assert.ok(корпус.length >= 140, `файлов корпуса всего ${корпус.length}`)
  const новые = new Set(["andAlso", "or", "not"])
  const сНовыми = []
  const безНовых = []
  for (const путь of корпус) {
    const исходник = readFileSync(корень + путь, "utf8")
    let есть = false
    try {
      for (const токен of tokenize(исходник)) {
        if (токен.kind === "keyword" && новые.has(токен.value)) {
          есть = true
          break
        }
      }
    } catch {
      /* Файл, который не лексится, — забота соседних проверок, не этой. */
      continue
    }
    ;(есть ? сНовыми : безНовых).push(путь)
  }

  /* Половина первая: у большинства корпуса новых слов нет, и для них прежний
     довод остаётся полным доказательством неизменности потока. */
  assert.ok(
    безНовых.length > сНовыми.length,
    `файлов без новых слов ${безНовых.length}, с новыми ${сНовыми.length} — довод о неизменности потерял основание`,
  )

  /* Половина вторая, и она новая: там, где слова написаны, они обязаны быть
     разобраны как логические операции. Не «файл не упал», а именно узел на
     месте: слово, съевшее соседний токен, дало бы либо отказ разбора, либо
     дерево без логического узла. */
  const беды = []
  for (const путь of сНовыми) {
    if (!путь.endsWith(".flang")) continue /* модели FTS разбираются своим ядром */
    let дерево
    try {
      дерево = parse(readFileSync(корень + путь, "utf8"), путь)
    } catch (беда) {
      беды.push(`${путь}: не разобрался — ${беда?.message ?? String(беда)}`)
      continue
    }
    /* Своего узла у этих слов НЕТ — парсер разворачивает их в `если`
       (`а и притом б` → `если а то б иначе нет`, и так все три). Поэтому
       проверяется СООТНОШЕНИЕ: каждое слово даёт ровно одно `если`, значит
       ветвлений в дереве не может быть меньше, чем слов в потоке. Съешь слово
       соседний токен — разбор либо откажет, либо не построит своё ветвление, и
       неравенство сломается. Больше — сколько угодно: авторские `если` никто не
       считал. */
    const слов = [...tokenize(readFileSync(корень + путь, "utf8"))]
      .filter((токен) => токен.kind === "keyword" && новые.has(токен.value)).length
    const ветвлений = [...JSON.stringify(дерево).matchAll(/"kind":"if"/gu)].length
    if (ветвлений < слов) {
      беды.push(`${путь}: слов ${слов}, а ветвлений в дереве ${ветвлений} — слово съело соседний токен`)
    }
  }
  assert.deepEqual(беды, [], `разбор новых слов разошёлся с замыслом на ${беды.length} файлах`)
  assert.ok(сНовыми.length > 0, "новые слова в корпусе не встречаются — тогда действует прежняя, дешёвая редакция")
})

/* ─────────── четыре поверхности ─────────────────────────────────────────── */

test("новые слова стоят на всех поверхностях, где для них есть устоявшееся слово", () => {
  assert.deepEqual(KEYWORDS.andAlso, ["и притом", "and also", "kaj ankaŭ", "并且"])
  assert.deepEqual(KEYWORDS.or, ["или", "or", "aŭ", "或者"])
  /* Эсперанто молчит намеренно: `ne` таблица уже отдала `нет` (litFalse), а
     одна фраза не вправе означать две конструкции. Шестое такое место. */
  assert.deepEqual(KEYWORDS.not, ["не", "not", "非"])
  assert.equal(keywordId("ne"), "litFalse", "`ne` остаётся эсперантским `нет`")
})

test("длинная фраза по-прежнему бьёт короткую — новые слова ничего не отняли", () => {
  const слова = (текст) => tokenize(`${текст}\n`).map((т) => (т.kind === "keyword" ? т.value : т.kind))
  assert.deepEqual(слова("голова и хвост"), ["headTail", "newline", "eof"])
  assert.deepEqual(слова("не равен"), ["cmpNeq", "newline", "eof"])
  assert.deepEqual(слова("не больше"), ["cmpLte", "newline", "eof"])
  assert.deepEqual(слова("не меньше"), ["cmpGte", "newline", "eof"])
  assert.deepEqual(слова("is not equal to"), ["cmpNeq", "newline", "eof"])
  assert.deepEqual(слова("al nombro aŭ fiasko"), ["toNumberOrFail", "newline", "eof"])
  assert.deepEqual(слова("к числу или беда"), ["toNumberOrFail", "newline", "eof"])
  /* И наоборот: одинокие слова остаются собой. */
  assert.deepEqual(слова("и притом"), ["andAlso", "newline", "eof"])
  assert.deepEqual(слова("и"), ["and", "newline", "eof"])
  assert.deepEqual(слова("не"), ["not", "newline", "eof"])
  assert.deepEqual(слова("или"), ["or", "newline", "eof"])
})

test("на каждой поверхности выражение читается одинаково", () => {
  const формы = {
    ru: "функция «Ф»\n  принимает а: признак, б: признак\n  возвращает признак\n  не а и притом б\n",
    en: "function «Ф»\n  accepts а: flag, б: flag\n  returns flag\n  not а and also б\n",
    eo: "funkcio «Ф»\n  akceptas а: bulea, б: bulea\n  redonas bulea\n  а kaj ankaŭ б\n",
    zh: "函数 «Ф»\n  接受 а: 布尔, б: 布尔\n  返回 布尔\n  а 并且 б\n",
  }
  const русский = голый(parse(формы.ru)).functions[0].body
  const английский = голый(parse(формы.en)).functions[0].body
  assert.deepEqual(английский, русский, "английская поверхность даёт другое дерево")

  /* У эсперанто и китайского отрицания в таблице нет — сравниваем конъюнкцию. */
  const конъюнкция = голый(parse(формы.ru.replace("не а и притом б", "а и притом б"))).functions[0].body
  for (const поверхность of ["eo", "zh"]) {
    assert.deepEqual(
      голый(parse(формы[поверхность])).functions[0].body,
      конъюнкция,
      `поверхность ${поверхность} даёт другое дерево`,
    )
  }
  assert.deepEqual(SURFACE_ORDER, ["ru", "en", "eo", "zh"])
})
