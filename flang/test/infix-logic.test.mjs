/**
 * Инфиксные логические операции: `не`, `и притом`, `или`.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Правка трогает три слоя разом — таблицу лексера (обе
 * копии), уровень приоритета в разборщике (обе копии) и текст
 * `flang/stdlib/logic.flang`, — а держится вся она на ОДНОМ утверждении:
 *
 *   запись `«Ф» от а и притом б` читается однозначно, потому что `и притом` —
 *   не два слова, а одно составное, и склейка ключевых слов жадная и
 *   длиннейшая-первой; при этом `«Ф» от а и б` продолжает означать ДВА
 *   аргумента, как означало всегда.
 *
 * Первые два теста этого файла — ровно эта пара: программа, которая обязана
 * разобраться по-новому, и программа, которая обязана разобраться ПО-СТАРОМУ.
 * Они написаны раньше кода намеренно: без второго теста «улучшение» инфиксной
 * записи молча меняет смысл каждого вызова с двумя аргументами в репозитории, и
 * заметить это было бы негде — вызовов таких сотни, и все они зелёные.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import test from "node:test"

import { evaluate } from "../src/interpret.mjs"
import { KEYWORDS, keywordId, SURFACE_ORDER, tokenize } from "../src/lexer.mjs"
import { parse } from "../src/parser.mjs"
import { checkTypes } from "../src/types.mjs"
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))

/** Спаны в сравнении форм узлов только мешают. */
function голый(значение) {
  if (Array.isArray(значение)) return значение.map(голый)
  if (значение === null || typeof значение !== "object") return значение
  const итог = {}
  for (const [ключ, поле] of Object.entries(значение)) {
    if (ключ === "span") continue
    итог[ключ] = голый(поле)
  }
  return итог
}

/** Тело единственной функции: параметры объявлены заранее — имена обязаны быть связаны. */
const тело = (выражение, параметры = "а: признак, б: признак, ц: признак", возвращает = "признак") =>
  голый(parse(`функция «Ф»\n  принимает ${параметры}\n  возвращает ${возвращает}\n  ${выражение}\n`)).functions[0]
    .body

/* ─────────── пара, ради которой всё и затевалось ─────────────────────────── */

test("«Ф» от а и притом б — ОДИН аргумент, и вся запись конъюнкция", () => {
  const узел = тело("«Оба» от а и притом б", "а: признак, б: признак")
  /* Конъюнкция — верхний узел: `и притом` уровнем ниже применения. */
  assert.equal(узел.kind, "if", `верхним узлом вышло ${узел.kind}`)
  /* Слева от `и притом` — вызов, и аргумент у него РОВНО ОДИН. */
  assert.deepEqual(узел.cond, { kind: "call", name: "Оба", args: [{ kind: "var", name: "а" }] })
  assert.deepEqual(узел.then, { kind: "var", name: "б" })
  assert.deepEqual(узел.else, { kind: "literal", value: false })
})

test("«Ф» от а и б — по-прежнему ДВА аргумента, ни один вызов репозитория не поехал", () => {
  const узел = тело("«Оба» от а и б", "а: признак, б: признак")
  assert.deepEqual(узел, {
    kind: "call",
    name: "Оба",
    args: [
      { kind: "var", name: "а" },
      { kind: "var", name: "б" },
    ],
  })
})

/* ─────────── приоритеты ──────────────────────────────────────────────────── */

test("приоритеты: `не` крепче `и притом`, `и притом` крепче `или`", () => {
  /* Выражение, где все три спорят между собой: `не а и притом б или ц`.
     Единственное правильное чтение — `((не а) и притом б) или ц`. */
  const узел = тело("не а и притом б или ц")

  /* Верхний уровень — `или`: `если ЛЕВОЕ то да иначе ц`. */
  assert.equal(узел.kind, "if")
  assert.deepEqual(узел.then, { kind: "literal", value: true }, "у `или` ветка `то` — это `да`")
  assert.deepEqual(узел.else, { kind: "var", name: "ц" }, "правый операнд `или` — `ц`")

  /* Под ним — `и притом`: `если (не а) то б иначе нет`. */
  const конъюнкция = узел.cond
  assert.equal(конъюнкция.kind, "if")
  assert.deepEqual(конъюнкция.then, { kind: "var", name: "б" })
  assert.deepEqual(конъюнкция.else, { kind: "literal", value: false })

  /* И в самом низу — `не`: `если а то нет иначе да`. */
  assert.deepEqual(конъюнкция.cond, {
    kind: "if",
    cond: { kind: "var", name: "а" },
    then: { kind: "literal", value: false },
    else: { kind: "literal", value: true },
  })
})

test("приоритеты левоассоциативны: `а или б или ц` — `(а или б) или ц`", () => {
  const узел = тело("а или б или ц")
  assert.deepEqual(узел.cond, {
    kind: "if",
    cond: { kind: "var", name: "а" },
    then: { kind: "literal", value: true },
    else: { kind: "var", name: "б" },
  })
  assert.deepEqual(узел.else, { kind: "var", name: "ц" })
})

test("сравнение крепче логики: `х больше 1 и притом х меньше 9`", () => {
  const узел = тело("х больше 1 и притом х меньше 9", "х: число")
  assert.equal(узел.kind, "if")
  assert.deepEqual(узел.cond, {
    kind: "binary",
    op: "gt",
    left: { kind: "var", name: "х" },
    right: { kind: "literal", value: 1 },
  })
  assert.deepEqual(узел.then, {
    kind: "binary",
    op: "lt",
    left: { kind: "var", name: "х" },
    right: { kind: "literal", value: 9 },
  })
})

test("`не` перед сравнением берёт всё сравнение, а не левый операнд", () => {
  const узел = тело("не х равен 1", "х: число")
  assert.deepEqual(узел, {
    kind: "if",
    cond: { kind: "binary", op: "eq", left: { kind: "var", name: "х" }, right: { kind: "literal", value: 1 } },
    then: { kind: "literal", value: false },
    else: { kind: "literal", value: true },
  })
})

test("скобки перебивают приоритет: `а и притом (б или ц)`", () => {
  const узел = тело("а и притом (б или ц)")
  assert.deepEqual(узел.cond, { kind: "var", name: "а" })
  assert.deepEqual(узел.then, {
    kind: "if",
    cond: { kind: "var", name: "б" },
    then: { kind: "literal", value: true },
    else: { kind: "var", name: "ц" },
  })
})

test("логика доходит до условия `если` и до тела встроенных форм", () => {
  const условие = тело("если а и притом б\n    то да\n    иначе нет")
  assert.equal(условие.cond.kind, "if", "условие `если` разбирается на том же уровне, что и выражение")
  assert.deepEqual(условие.cond.else, { kind: "literal", value: false })

  const отбор = тело(
    "отфильтровать элементы где э → э больше 1 и притом э меньше 9",
    "элементы: список числа",
    "список числа",
  )
  assert.equal(отбор.kind, "filter")
  assert.equal(отбор.body.kind, "if")
})

/* ─────────── значения: таблицы истинности ────────────────────────────────── */

const вычислить = (выражение, параметры, аргументы) => {
  const исходник = `функция «Ф»\n  принимает ${параметры}\n  возвращает признак\n  ${выражение}\n`
  return evaluate(parse(исходник), "Ф", аргументы)
}

test("таблицы истинности сходятся с `stdlib/logic.flang`", () => {
  const пары = [
    [false, false],
    [false, true],
    [true, false],
    [true, true],
  ]
  for (const [п, в] of пары) {
    assert.equal(вычислить("а и притом б", "а: признак, б: признак", [п, в]), п && в, `и притом: ${п}, ${в}`)
    assert.equal(вычислить("а или б", "а: признак, б: признак", [п, в]), п || в, `или: ${п}, ${в}`)
  }
  assert.equal(вычислить("не а", "а: признак", [true]), false)
  assert.equal(вычислить("не а", "а: признак", [false]), true)
})

test("закон де Моргана проверяется перебором на самой записи, а не на функциях", () => {
  for (const п of [false, true]) {
    for (const в of [false, true]) {
      assert.equal(
        вычислить("не (а и притом б)", "а: признак, б: признак", [п, в]),
        вычислить("не а или не б", "а: признак, б: признак", [п, в]),
        `де Морган: ${п}, ${в}`,
      )
      assert.equal(
        вычислить("не (а или б)", "а: признак, б: признак", [п, в]),
        вычислить("не а и притом не б", "а: признак, б: признак", [п, в]),
        `де Морган (двойственный): ${п}, ${в}`,
      )
    }
  }
})

test("вычисление ленивое: правый операнд не считается, когда левый всё решил", () => {
  /* `нет и притом (1 делить на 0)` — если бы правый операнд считался, вышло бы
     деление на ноль. Ленивость здесь не украшение: она и есть причина, по
     которой запись разворачивается в `если`, а не в вызов функции. */
  const исходник =
    "функция «Ф»\n  принимает а: признак\n  возвращает признак\n  а и притом ((1 делить на 0) равен 0)\n"
  assert.equal(evaluate(parse(исходник), "Ф", [false]), false)
})

