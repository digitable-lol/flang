/**
 * Строки метода `install` формулы. Проверка повторяет их своими руками, и
 * СПИСОК обязан совпасть: появится в формуле восьмая строка — здесь покраснеет.
 * Иначе «воспроизведение раскладки» тихо перестало бы воспроизводить формулу, а
 * узнать об этом можно было бы только от человека с Маком.
 */
const РАСКЛАДКА_ФОРМУЛЫ = [
  'system "make", "CFLAGS=-std=c99 -Wall -Wextra -Werror -pedantic -O2"',
  'собрано = File.exist?("flang") ? "flang" : "flang_cli"',
  'bin.install собрано => "flang"',
  'lib.install Dir["lib*.a"]',
  'include.install Dir["*.h"]',
  'man1.install "flang.1"',
  '(share/"flang").install Dir["share/flang/*"]',
]

function строкиУстановкиФормулы() {
  const формула = readFileSync(join(корень, "packaging/homebrew/flang.rb"), "utf8")
  const начало = формула.indexOf("  def install\n")
  assert.notEqual(начало, -1, "в формуле нет метода install")
  const конец = формула.indexOf("\n  end\n", начало)
  return формула
    .slice(начало + "  def install\n".length, конец)
    .split("\n")
    .map((строка) => строка.trim())
    .filter((строка) => строка !== "" && !строка.startsWith("#"))
}

test("формула ставит ровно то, что проверка умеет повторить", () => {
  assert.deepEqual(
    строкиУстановкиФормулы(),
    РАСКЛАДКА_ФОРМУЛЫ,
    "метод install формулы разошёлся с тем, что повторяет эта проверка. Пока brew на машине " +
      "нет, раскладку воспроизводит она — и обязана воспроизводить ВСЮ. Поправьте РАСКЛАДКА_ФОРМУЛЫ " +
      "и код раскладки вместе.",
  )
})

/* ------------------------------------------------------- сборка архива один раз */

/**
 * GNU tar, а не «какой найдётся».
 *
 * У bsdtar (он же `tar` на macOS) НЕТ ни `--sort`, ни `--mtime`, и байты выйдут
 * другими — то есть хеш архива, собранного на Маке обычным `tar`, не совпал бы
 * с хешем того же дерева, собранного на Linux. Формула это оговаривает словами
 * «на macOS это `gtar` из пакета `gnu-tar`»; здесь оговорка превращается в
 * выбор, потому что проверка обязана идти на обеих платформах. Это вторая из
 * двух бед, которые видны только вне Linux.
 */
function gnuTar() {
  for (const имя of ["tar", "gtar", "gnutar"]) {
    const итог = бег(имя, ["--version"])
    if (итог.код === 0 && итог.вывод.includes("GNU tar")) return имя
  }
  return null
}

/**
 * Команда упаковки и список имён БЕРУТСЯ ИЗ ФОРМУЛЫ, а не пишутся здесь второй
 * копией.
 *
 * Довод не про красоту. Знание «чем именно упакован архив» уже жило двумя
 * копиями — в формуле и в скрипте выпуска, — и разошлось молча: список имён в
 * формуле не содержал LICENSE, который скрипт кладёт. Третья копия здесь
 * разошлась бы точно так же, и разошлась бы именно та, которую зовут реже.
 * Поэтому формула — источник, а проверка её читает.
 *
 * Заодно это делает проверку чувствительной к правке формулы: поменяли режим
 * прав или порядок имён — архив пересобирается по-новому, а не по памяти.
 */
function упаковкаИзФормулы() {
  const формула = readFileSync(join(корень, "packaging/homebrew/flang.rb"), "utf8")
  const кусок = формула
    .split("\n")
    .filter((строка) => строка.startsWith("  #"))
    .map((строка) => строка.slice(3).trim())
    .join("\n")
  const команда = (кусок.match(/^(tar [\s\S]*?)\n\s*\| gzip/mu) ?? [])[1]
  assert.ok(
    команда !== undefined,
    "в комментарии формулы над строкой sha256 не нашлась команда tar. Она там источник, а не пересказ: " +
      "проверка собирает архив ровно ею.",
  )
  const слова = команда.replace(/\\\n/gu, " ").split(/\s+/u)
  const ключи = слова.filter((слово) => слово.startsWith("--") && слово !== "--")
  const после = слова.indexOf("-cf")
  assert.ok(после !== -1, `команда tar в формуле без «-cf»: ${команда}`)
  /* После «-cf -» идут имена; «-C каталог» проверка подставляет своё. */
  const имена = слова
    .slice(после + 2)
    /* Хвостовая косая последней строки продолжения остаётся в захвате: её
       перевод строки в выражение не попал. Имя файла косой не бывает. */
    .filter((слово) => слово !== "" && слово !== "\\" && !слово.startsWith("-"))
  assert.ok(имена.length > 0, `в команде tar формулы не перечислено ни одного имени: ${команда}`)
  return { ключи, имена }
}

let архивПамять = null

/**
 * Собрать релизный архив — ОДИН раз на весь прогон.
 *
 * Сети не требует и не ждёт: архив печатается на месте тем же скриптом, что
 * готовит релиз (`scripts/build-release-c.mjs`), и упаковывается той же
 * командой `tar`, что записана в формуле. Так проверка заодно накрывает
 * ЧЕТВЁРТУЮ поломку: скрипт выпуска отказывал всегда, и узнать об этом можно
 * было только выпуская.
 *
 * Готовый архив можно подать снаружи — `FLANG_RELEASE_TARBALL=/путь/…`; тогда
 * проверяется он, а не собранный. Это дорога для проверки НАСТОЯЩЕГО релиза.
 */
function архив() {
  if (архивПамять !== null) return архивПамять
  mkdirSync(РАБОТА, { recursive: true })

  const снаружи = process.env.FLANG_RELEASE_TARBALL
  if (снаружи !== undefined && существует(снаружи)) {
    const каталог = join(РАБОТА, "raspakovano")
    rmSync(каталог, { recursive: true, force: true })
    mkdirSync(каталог, { recursive: true })
    const распаковка = бег("tar", ["-xzf", снаружи, "-C", каталог])
    assert.equal(распаковка.код, 0, `архив ${снаружи} не распаковался: ${сказано(распаковка)}`)
    архивПамять = { тарбол: снаружи, дерево: каталог, откуда: `подан снаружи: ${снаружи}` }
    return архивПамять
  }

  const дерево = join(РАБОТА, "release-c")
  const тарбол = join(РАБОТА, `flang-${ВЕРСИЯ}-c.tar.gz`)
  /* Переиспользование в пределах прогона и между прогонами: печать идёт около
     трёх минут, а меняется она только вместе с деревом. Признак свежести —
     bootstrap/compiler_flang.c: он печатается из того же источника. */
  const свежий =
    существует(тарбол) &&
    [
      "bootstrap/compiler_flang.c",
      "scripts/build-release-c.mjs",
      /* И формула: команда `tar` записана в ней, и её правка меняет байты
         архива. Пропусти её — и проверка гоняла бы архив, собранный прежней
         командой, то есть ровно то, против чего она заведена. */
      "packaging/homebrew/flang.rb",
    ].every((путь) => статус(тарбол).mtimeMs > статус(join(корень, путь)).mtimeMs)
  if (!свежий) {
    const начало = Date.now()
    const сборка = бег("node", [join(корень, "scripts/build-release-c.mjs"), дерево], { срок: 30 * 60 * 1000 })
    assert.equal(
      сборка.код,
      0,
      "scripts/build-release-c.mjs не собрал релиз — выпустить релиз НЕЛЬЗЯ. Это четвёртая поломка " +
        `19 августа, и вот она снова:\n${сказано(сборка).slice(-3000)}`,
    )
    console.log(`архив напечатан и собран за ${((Date.now() - начало) / 1000).toFixed(0)} с`)
    /* Скрипт собирает прямо в этом каталоге, поэтому в архив кладутся ИМЕНА, а
       не всё подряд: иначе туда уедут flang, *.o и libcompiler_flang.a. */
    const tar = gnuTar()
    assert.ok(
      tar !== null,
      "GNU tar не найден. Обычный `tar` на macOS — это bsdtar, у него нет ни --sort, ни --mtime, " +
        "и архив вышел бы с другими байтами и другим sha256. Ставится пакетом gnu-tar.",
    )
    const { ключи, имена } = упаковкаИзФормулы()
    const упаковка = бег("sh", [
      "-c",
      `${tar} ${ключи.join(" ")} -C ${JSON.stringify(дерево)} -cf - ${имена.join(" ")} | gzip -9n > ${JSON.stringify(тарбол)}`,
    ])
    assert.equal(упаковка.код, 0, `упаковка не удалась: ${сказано(упаковка)}`)
  }

  const каталог = join(РАБОТА, "raspakovano")
  rmSync(каталог, { recursive: true, force: true })
  mkdirSync(каталог, { recursive: true })
  const распаковка = бег("tar", ["-xzf", тарбол, "-C", каталог])
  assert.equal(распаковка.код, 0, `собранный архив не распаковался: ${сказано(распаковка)}`)
  архивПамять = { тарбол, дерево: каталог, откуда: свежий ? "взят готовым из output/" : "собран на месте" }
  return архивПамять
}

