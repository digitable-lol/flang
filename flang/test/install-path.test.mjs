/**
 * Проверить ПОСТАВЛЕННЫЙ flang планом на самом flang.
 *
 * Семь команд, их порядок и то, что считать бедой, объявлены в
 * `packaging/install-check.flang` и проверены там тридцатью примерами БЕЗ
 * единого запуска. Здесь остаётся подать настройку и прочитать ответ.
 *
 * Поверхность ответов приезжает отсюда, а не зашита в план, и вот почему:
 * установок четыре, а программ за ними ДВЕ. Три пути ставят бинарник, четвёртый
 * — инструментарий на Node, и на одни и те же команды они отвечают по-разному.
 * Расхождение названо таблицей ниже, а не спрятано.
 */
const ПОВЕРХНОСТЬ = {
  двоичный: { версия: `flang ${ВЕРСИЯ}`, справка: "flang check", проверка: "проверено", ложь: "не прошёл" },
  node: { версия: ВЕРСИЯ, справка: "flang check", проверка: '"valid":true', ложь: '"passed":false' },
}

/**
 * Расхождение двух поверхностей — ИМЕНОВАННОЕ. Разойдись они ещё в одном месте,
 * список изменится, и это станет видно, а не растворится в «ну они же разные».
 *
 * ЭТОТ СПИСОК СКОРО ОБЯЗАН СТАТЬ ПУСТЫМ, и это не пожелание, а соседняя работа:
 * на ветке `vypusk/npm-dvoichnyy` npm начинает ставить ТОТ ЖЕ двоичный, что и
 * brew (там измерено: расхождений было 54 из 59, стало 7). Когда она вольётся,
 * путь npm станет отвечать как двоичный, эта проверка покраснеет и потребует
 * снять записи — ровно так, как и задумано: молча разъехаться она не даст, и
 * молча сойтись тоже.
 */
const РАСХОЖДЕНИЕ = ["версия", "проверка", "ложь"]

function проверитьУстановку(имя, путьКFlang, вид) {
  const место = join(РАБОТА, "proverka", имя)
  rmSync(место, { recursive: true, force: true })
  mkdirSync(место, { recursive: true })
  copyFileSync(join(корень, "packaging/install-check.flang"), join(место, "install-check.flang"))

  const поверхность = ПОВЕРХНОСТЬ[вид]
  writeFileSync(
    join(место, "settings.txt"),
    [
      путьКFlang,
      поверхность.версия,
      поверхность.справка,
      join(корень, "flang/stdlib/lists.flang"),
      поверхность.проверка,
      join(корень, "flang/test/fixtures/install-path/false-example.flang"),
      поверхность.ложь,
      join(место, "pechat"),
    ].join("\n") + "\n",
    "utf8",
  )

  const итог = бег("node", [join(корень, "flang/bin/flang.mjs"), "io", join(место, "install-check.flang")], {
    срок: 15 * 60 * 1000,
  })
  let ответ = {}
  try {
    ответ = JSON.parse(итог.вывод)
  } catch {
    ответ = { error: `план не ответил JSON-ом: ${сказано(итог).slice(0, 800)}` }
  }
  return { код: итог.код, ...ответ }
}

