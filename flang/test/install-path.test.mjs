/**
 * Инструкция — тоже предмет проверки, и это вторая поломка целиком.
 *
 * Человек честно набирал три строки из нашей инструкции и на третьей получал
 * ошибку, потому что команду `asdf global` удалили в чужом инструменте. Читать
 * инструкцию глазами бесполезно: строка выглядит правильной ровно до того дня,
 * когда её удаляют у соседа. Поэтому команды ОТСЮДА ВЫНИМАЮТСЯ И РАЗБИРАЮТСЯ,
 * а те, что можно выполнить, — выполняются.
 */
const ИНСТРУКЦИИ = ["packaging/asdf/README.md", "docs/site/install.ru.md", "docs/site/install.md"]

/**
 * Команды чужих инструментов, которых БОЛЬШЕ НЕТ. Таблица маленькая нарочно:
 * она не про «как правильно», она про «это уже убили, и мы это знаем».
 */
const УДАЛЁННЫЕ = [
  { команда: "asdf global", когда: "asdf 0.16.0", вместо: "asdf set -u" },
  { команда: "asdf local", когда: "asdf 0.16.0", вместо: "asdf set" },
]

/**
 * Чего на этой машине выполнить нельзя — с причиной у каждой строки. Список
 * закрытый: команда, которой нет ни здесь, ни среди выполнимых, красит проверку
 * и требует решения, а не молчаливого пропуска.
 */
const НЕ_ВЫПОЛНЯЕМ = {
  brew: "Homebrew на машине нет; раскладку файлов проверка повторяет сама",
  asdf: "asdf на машине нет; то, что делает плагин, проверка запускает напрямую",
  mise: "mise на машине нет; плагин у него тот же самый",
  git: "клонирование по сети — не предмет этой проверки",
  npm: "путь npm проверяется отдельно, настоящими npm pack и npm install",
  sudo: "установка в системные каталоги под другим пользователем",
  cd: "смена каталога — не команда инструмента",
  cc: "прямой вызов компилятора проверяется сборкой из исходников",
  cp: "перенос копии плагина в соседний репозиторий — работа сопровождающего, не установка",
  make: "сборка проверяется путём «из исходников»",
}

/** Строки кода из блоков ```bash — без строк вывода и без комментариев. */
function командыИнструкции(файл) {
  const текст = readFileSync(join(корень, файл), "utf8")
  const блоки = [...текст.matchAll(/```(?:bash|sh|console)\n([\s\S]*?)```/gu)].map((м) => м[1])
  const строки = []
  for (const блок of блоки) {
    /* Перенос строки обратной косой — одна команда, а не две. */
    const склеено = блок.replace(/\\\n\s*/gu, " ")
    for (const сырая of склеено.split("\n")) {
      const строка = сырая.replace(/\s+#.*$/u, "").trim()
      if (строка === "" || строка.startsWith("#")) continue
      строки.push(строка)
    }
  }
  return строки
}

test("команды из инструкции ВЫПОЛНЯЮТСЯ, а не читаются глазами", () => {
  const всё = []
  for (const файл of ИНСТРУКЦИИ) всё.push(...командыИнструкции(файл).map((строка) => ({ файл, строка })))
  assert.ok(всё.length > 0, "в инструкциях не нашлось ни одной команды — разбор блоков сломан")

  /* 1. Удалённых команд чужих инструментов быть не должно. Это вторая поломка,
        и краснеть она обязана словами про КОМАНДУ, а не «что-то не так». */
  const мёртвые = []
  for (const { файл, строка } of всё) {
    for (const { команда, когда, вместо } of УДАЛЁННЫЕ) {
      /* Слова «asdf global» в ПРОЗЕ разрешены — там объясняют, почему её нет.
         Красит только КОМАНДА, то есть начало строки кода. */
      if (строка === команда || строка.startsWith(`${команда} `)) {
        мёртвые.push(`${файл}: «${строка}» — ${команда} удалена в ${когда}, вместо неё ${вместо}`)
      }
    }
  }
  assert.deepEqual(
    мёртвые,
    [],
    `инструкция советует команду, которой НЕТ в сегодняшнем инструменте:\n${мёртвые.join("\n")}\n` +
      "Ровно так человек набирал три строки и на третьей получал ошибку.",
  )

  /* 2. Каждая команда либо выполняется здесь, либо названа в списке невыполнимых
        с причиной. Третьего не дано: молчаливый пропуск неотличим от проверки. */
  const бездомные = []
  const выполнено = []
  for (const { файл, строка } of всё) {
    const первое = строка.split(/\s+/u)[0]
    if (первое === "flang") {
      выполнено.push({ файл, строка })
      continue
    }
    if (!(первое in НЕ_ВЫПОЛНЯЕМ)) бездомные.push(`${файл}: «${строка}» — первое слово «${первое}»`)
  }
  assert.deepEqual(
    бездомные,
    [],
    "в инструкции появилась команда, которую проверка не умеет ни выполнить, ни объяснить:\n" +
      `${бездомные.join("\n")}\n` +
      "Добавьте её в НЕ_ВЫПОЛНЯЕМ с причиной или научите проверку её выполнять.",
  )

  /* 3. Команды самого flang выполняются — тем flang, который есть под рукой.
        Это не полная установка (её проверяет другой тест ниже), но инструкция,
        советующая несуществующий ключ, покраснеет уже здесь и за секунды. */
  const свой = ["node", [join(корень, "flang/bin/flang.mjs")]]
  const беды = []
  for (const { файл, строка } of выполнено) {
    const доводы = строка.split(/\s+/u).slice(1)
    /* Команды, которым нужен файл или терминал, спрашиваются справкой: нам
       важно, что КЛЮЧ существует, а не что он что-то посчитал. */
    const спрос = доводы.includes("--help") ? доводы : [...доводы, "--help"]
    const итог = бег(свой[0], [...свой[1], ...спрос])
    if (итог.код !== 0) беды.push(`${файл}: «${строка}» → код ${итог.код}: ${сказано(итог).slice(0, 200)}`)
  }
  assert.deepEqual(беды, [], `команда из инструкции не выполнилась:\n${беды.join("\n")}`)

  /* 4. Чего выполнить нельзя — то СВЕРЯЕТСЯ С ДЕРЕВОМ. Инструкция называет
        каталоги, цели make, имя пакета и адрес репозитория, и каждое из них
        может устареть молча. Стоит это ноль секунд и ловит ровно тот класс
        расхождений, из-за которого третья строка перестала работать. */
  const makefile = readFileSync(join(корень, "bootstrap/Makefile"), "utf8")
  const свёрка = []
  for (const { файл, строка } of всё) {
    const слова = строка.split(/\s+/u)
    if (слова[0] === "make" && слова[1] === "-C") {
      const каталог = слова[2]
      if (!существует(join(корень, каталог))) свёрка.push(`${файл}: «${строка}» — каталога ${каталог} нет`)
      for (const цель of слова.slice(3).filter((с) => /^[a-z]+$/u.test(с))) {
        if (!new RegExp(`^${цель}:`, "mu").test(makefile)) {
          свёрка.push(`${файл}: «${строка}» — цели «${цель}» в ${каталог}/Makefile нет`)
        }
      }
    }
    for (const слово of слова) {
      if (слово.startsWith("@digitable-lol/") && слово !== пакет.name) {
        свёрка.push(`${файл}: «${строка}» — пакет «${слово}», а package.json зовётся «${пакет.name}»`)
      }
      if (слово.includes("github.com/digitable-lol/flang") && !пакет.repository.url.includes("digitable-lol/flang")) {
        свёрка.push(`${файл}: «${строка}» — адрес репозитория разошёлся с package.json`)
      }
    }
  }
  assert.deepEqual(свёрка, [], `инструкция называет то, чего в дереве нет:\n${свёрка.join("\n")}`)

  console.log(
    `команды инструкции: всего ${всё.length}, выполнено flang-ом ${выполнено.length}, ` +
      `сверено с деревом ${всё.filter((к) => к.строка.startsWith("make -C") || к.строка.includes("digitable-lol")).length}, ` +
      `названо невыполнимыми ${всё.length - выполнено.length}, удалённых чужих команд 0`,
  )
})

