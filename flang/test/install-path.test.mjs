/**
 * Запустить программу и вернуть код, вывод и ошибки — БЕЗ оболочки.
 *
 * `execFileSync` сюда не годится: он бросает на ненулевом коде, а ненулевой код
 * здесь сплошь и рядом РЕЗУЛЬТАТ (`flang test` на ложном примере обязан вернуть
 * не ноль). Подмена «результата» на «исключение» — ровно та беда, из-за которой
 * формула, смотревшая на код возврата, пропускала молчащий `--help`.
 */
function бег(программа, доводы, опции = {}) {
  const итог = spawnSync(программа, доводы, {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    timeout: опции.срок ?? 20 * 60 * 1000,
    cwd: опции.где ?? корень,
    input: опции.вход,
    env: { ...process.env, LC_ALL: "C.UTF-8", ...(опции.среда ?? {}) },
  })
  return {
    код: итог.status,
    вывод: итог.stdout ?? "",
    ошибки: итог.stderr ?? "",
    беда: итог.error,
  }
}

