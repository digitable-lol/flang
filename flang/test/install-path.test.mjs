/* ------------------------------------------------------------------- долги */

/**
 * ДОЛГ, а не «известная особенность»: то, что путь установки сегодня НЕ даёт, с
 * точным указанием, где это чинится. Список закрытый в обе стороны — стало
 * больше или стало меньше, проверка краснеет и требует правки записи. Так долг
 * не рассасывается молчанием и не растёт незаметно.
 */
const ДОЛГИ = [
  {
    путь: "из исходников",
    шаг: "flang emit --target c печатает, а не упирается в ненайденный рантайм",
    почему:
      "`make install` не кладёт share/flang/<цель>: правило install печатается генератором, " +
      "и знание о нём лежит ДВУМЯ копиями — flang/src/emit/c.mjs:996 и flang/self/emit-c.flang:3801. " +
      "Нужна одна строка в обеих: `test ! -d share || cp -R share $(DESTDIR)$(PREFIX)/`. " +
      "Второй половиной долга bootstrap/ не несёт каталога share вовсе — его туда " +
      "кладёт scripts/bootstrap-c.mjs, а bootstrap/ сверяется побайтово. Обе правки — вне " +
      "этой ветки (flang/src/**, flang/self/**, bootstrap/** правят другие).",
  },
]

function сверитьСДолгом(путь, ответ) {
  const долг = ДОЛГИ.find((з) => з.путь === путь)
  if (долг === undefined) {
    assert.equal(ответ.код, 0, `${путь}: поставленный flang не работает — ${ответ.error ?? "план не ответил"}`)
    return
  }
  if (ответ.код === 0) {
    assert.fail(
      `${путь}: ДОЛГ ЗАКРЫТ — шаг «${долг.шаг}» теперь проходит. Уберите запись из ДОЛГИ, ` +
        "иначе проверка перестанет держать то, что уже работает.",
    )
  }
  const названо = String(ответ.error ?? "")
  assert.ok(
    названо.includes(долг.шаг),
    `${путь}: сдалось не на том шаге, что записан долгом.\n  ждали: ${долг.шаг}\n  вышло: ${названо}`,
  )
  console.log(`ДОЛГ (${путь}): ${долг.шаг}\n  где чинить: ${долг.почему}`)
}

/* ------------------------------------------------------ хеш того, что скачают */

/**
 * Отдельным тестом верхнего уровня, а не шагом пути: компилятора он не требует,
 * идёт четверть секунды и потому выполняется всегда — в том числе там, где
 * сборку прогнать нечем.
 */
test("sha256 формулы описывает тот файл, который она велит скачать", () => {
    const формула = readFileSync(join(корень, "packaging/homebrew/flang.rb"), "utf8")
    const объявлен = (формула.match(/^\s*sha256 "([0-9a-f]{64})"$/mu) ?? [])[1]
    const ссылка = (формула.match(/^\s*url "([^"]+)"$/mu) ?? [])[1]
    assert.ok(объявлен !== undefined && ссылка !== undefined, "в формуле нет url или sha256")

    /* Сверяется НЕ с архивом, собранным здесь, и это не поблажка.
       Формула ставит ВЫПУЩЕННЫЙ архив по своей ссылке, а дерево ушло вперёд
       с последнего тега: собранный на месте архив законно другой, и требовать
       от него хеша релиза значило бы держать проверку вечно красной. Предмет
       здесь другой и он ровно тот, что видит человек: brew скачает файл по
       этой ссылке и сверит хеш сам, — значит и мы скачиваем и сверяем.

       Свой архив можно подать ключом FLANG_RELEASE_TARBALL — так проверяется
       кандидат в релиз до публикации. */
    const снаружи = process.env.FLANG_RELEASE_TARBALL
    let файл = снаружи
    if (файл === undefined) {
      файл = join(РАБОТА, "po-ssylke.tar.gz")
      const скачивание = бег("curl", ["-fsSL", "--max-time", "120", "-o", файл, ссылка])
      if (скачивание.код !== 0) {
        console.log(`архив по ссылке формулы не скачался (сети нет?) — sha256 сверить не с чем: ${ссылка}`)
        return
      }
    }
    const наш = хеш(файл)
    assert.equal(
      объявлен,
      наш,
      `sha256 формулы не описывает файл, который она велит скачать.\n  в формуле: ${объявлен}\n` +
        `  у файла:   ${наш}\n  ссылка:    ${ссылка}\n` +
        "brew сверяет хеш сам и остановит установку до распаковки: с таким числом не ставится никто.",
    )
    console.log(`sha256 формулы сверен с файлом по ссылке: ${объявлен.slice(0, 12)}… совпал`)
  })

/* ------------------------------------------------- то, что видно только на Маке */

/**
 * Вызовы, которые есть в POSIX, но НЕ в ISO C. Ровно они зависят от того, какой
 * уровень видимости открыт заголовками, и ровно на них ломается сборка на
 * Darwin. Список из разбора
 * docs/zettel/a-feature-macro-that-opens-on-glibc-closes-on-darwin.md.
 */
const POSIX_НЕ_ISO = ["mkdtemp", "access", "getcwd", "isatty", "sigaction"]

test("сборка на Darwin: макрос на месте, и список вызовов, зависящих от него, не вырос", () => {
  const файл = "bootstrap/flang_repl.c"
  const текст = readFileSync(join(корень, файл), "utf8")

  /* Первая из пяти поломок 19 августа. `_POSIX_C_SOURCE 200809L` ОТКРЫВАЕТ
     mkdtemp на glibc и ЗАКРЫВАЕТ на Darwin: заголовки Apple считают видимость
     по __DARWIN_C_LEVEL, а -std=c99 добавляет __STRICT_ANSI__ и роняет уровень
     ещё ниже. Лечится вторым макросом, а не снятием первого. */
  assert.ok(текст.includes("#define _POSIX_C_SOURCE"), `${файл}: пропал _POSIX_C_SOURCE`)
  assert.ok(
    /#if defined\(__APPLE__\)[\s\S]{0,120}#define _DARWIN_C_SOURCE/u.test(текст),
    `${файл}: пропал блок _DARWIN_C_SOURCE. Без него -std=c99 на Darwin закрывает mkdtemp, ` +
      "и `brew install` не доходит до конца НИ У КОГО на Mac — при зелёном ubuntu.",
  )

  /* Список вызовов, зависящих от уровня видимости, закрытый в обе стороны.
     Шестой такой вызов — новая версия той же поломки, и узнать о нём надо
     здесь, за миллисекунды, а не из сборки на чужой машине. */
  const кандидаты = [
    ...new Set(
      [...текст.matchAll(/\b([a-z_][a-z0-9_]*)\s*\(/gu)]
        .map((м) => м[1])
        .filter((имя) => POSIX_НЕ_ISO.includes(имя)),
    ),
  ].sort()
  assert.deepEqual(
    кандидаты,
    [...POSIX_НЕ_ISO].sort(),
    "список вызовов, зависящих от уровня видимости заголовков, изменился. Каждый такой вызов " +
      "на Darwin виден только при поднятом __DARWIN_C_LEVEL: сверьте, что новый закрыт тем же " +
      "макросом, и поправьте POSIX_НЕ_ISO.",
  )

  /* ЧЕСТНО О ГРАНИЦЕ ЭТОЙ ПРОВЕРКИ. Она статическая. Строка
     `#if defined(__APPLE__)` на Linux не выполняется вовсе, и зелёный прогон
     здесь про Darwin не говорит НИЧЕГО — он говорит лишь, что макрос и список
     вызовов на месте. Единственная улика — сборка на Маке, и она вынесена
     в .github/workflows/put-ustanovki.yml (матрица ubuntu + macos). */
  console.log(
    `Darwin: макрос _DARWIN_C_SOURCE на месте, вызовов, зависящих от уровня видимости, ` +
      `${кандидаты.length} (${кандидаты.join(", ")}); ПРОВЕРЕНО ЧТЕНИЕМ, не сборкой`,
  )
})

