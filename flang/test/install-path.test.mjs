/**
 * Собрать распакованный архив теми же флагами, что у формулы и у плагина.
 *
 * Флаги — часть контракта бэкенда: напечатанный код обязан собираться без
 * единого предупреждения. Ослабить их здесь значило бы скрыть от себя же, что
 * печать испортилась.
 */
const ФЛАГИ = "CFLAGS=-std=c99 -Wall -Wextra -Werror -pedantic -O2"

function собрать(где) {
  const начало = Date.now()
  const итог = бег("make", ["-C", где, ФЛАГИ], { срок: 30 * 60 * 1000 })
  assert.equal(итог.код, 0, `сборка в ${где} не прошла:\n${сказано(итог).slice(-3000)}`)
  const секунд = ((Date.now() - начало) / 1000).toFixed(0)
  /* Имя выхода спрашивается у КАТАЛОГА, а не пишется: у самого компилятора это
     `flang`, у обычной напечатанной программы — `flang_cli`, и на этой развилке
     сломались подряд формула, плагин и скрипт выпуска. */
  const лежит = readdirSync(где)
  const бинарник = ["flang", "flang_cli"].find((имя) => лежит.includes(имя))
  assert.ok(бинарник !== undefined, `сборка прошла, но бинарника нет: в ${где} лежит ${лежит.join(", ")}`)
  if (ПОРЧА === "имя-выхода" && бинарник === "flang") {
    /* ПОРЧА: вернуть прежнее имя выхода. Установка обязана упасть, назвав себя. */
    бег("mv", [join(где, "flang"), join(где, "flang_cli")])
    return { бинарник: "flang_cli", секунд }
  }
  return { бинарник, секунд }
}

