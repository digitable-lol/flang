/**
 * ПУТЬ УСТАНОВКИ ЦЕЛИКОМ: собрать архив → поставить из него в чистое место →
 * выполнить команды из инструкции → получить ответ.
 *
 * ── Зачем эта проверка появилась ────────────────────────────────────────────
 * 19 августа 2026 путь установки сломался ПЯТЬ раз за один вечер. Все пять
 * нашёл владелец руками; ни одну не поймал ни один прогон:
 *
 *   1  `mkdtemp` на macOS — `brew install` не доходил до конца ни у кого на
 *      Mac, а три работы CI из трёх шли на ubuntu;
 *   2  `asdf global` — команду удалили в asdf 0.16.0, а инструкция её советует;
 *   3  имя выхода сборки — `make` стал класть `flang` вместо `flang_cli`;
 *   4  скрипт выпуска искал `flang_cli` и отказывал ВСЕГДА;
 *   5  исходники рантайма — `flang emit --target c` не работает ни у одного
 *      установленного пользователя.
 *
 * У всех пяти ОДНА причина: **проверки в дереве гоняют то, что лежит в дереве,
 * а человек получает архив, в котором лежит другое.** Целиком путь установки не
 * проходил никто. Отсюда устройство этого файла: он не чинит пять поломок по
 * одной, он проходит путь.
 *
 * ── Что здесь проверено настоящим инструментом, а что воспроизведением ──────
 * Честно, поимённо, потому что раньше в этих файлах всё выглядело рабочим и не
 * работало ничего.
 *
 * НАСТОЯЩИМ инструментом:
 *   • `make` и `cc` — да, обе сборки настоящие, теми же флагами, что у формулы;
 *   • `packaging/asdf/bin/install` — да, запускается как есть, с теми
 *     переменными окружения, какие подаёт asdf;
 *   • `npm pack` и установка тарбола — да, настоящими `npm`;
 *   • сам поставленный `flang` — да, все семь команд выполняются.
 *
 * ВОСПРОИЗВЕДЕНИЕМ:
 *   • `brew` — на машине его нет (`command -v brew` пуст). Раскладка файлов
 *     повторяется по строкам метода `install` формулы, и совпадение СПИСКА
 *     строк с тем, что проверка умеет повторить, стоит отдельной проверкой:
 *     появится в формуле восьмая строка — эта проверка покраснеет и назовёт её.
 *     Непроверенным остаётся то, что умеет только brew: разбор файла как Ruby,
 *     песочница сборки, `brew audit`.
 *   • `asdf` — его на машине тоже нет, и `bin/download` без сети не сходит за
 *     архивом. Скачивание заменяется распаковкой того архива, который проверка
 *     собрала сама; всё, что делает `bin/install`, — настоящее.
 *
 * ── Сколько это стоит по времени ────────────────────────────────────────────
 * Замерено на этом дереве, не прикинуто:
 *   • одна сборка релизного C флагами формулы — 128 с (`-j4` не помогает:
 *     `compiler_flang.c` — одна единица трансляции на 11 МБ);
 *   • `node scripts/build-release-c.mjs` — 173 с (печать плюс своя сборка
 *     с `-flto`).
 * Путей четыре, но сборок три: npm ставит инструментарий на Node и `cc` ему не
 * нужен.
 *
 * ПОЛНЫЙ ПРОГОН ЗАМЕРЕН ЦЕЛИКОМ, а не сложен из частей: 391 с на свободной
 * машине и 518 с на занятой (соседние работы шли параллельно). С готовым
 * архивом в `output/` — 260—267 с. Разбивка одного прогона: печать релиза
 * 129—179 с, Homebrew 87—125 с, asdf 81 с, из исходников 83—100 с, npm 3,9 с.
 *
 * Отсюда решение: архив собирается ОДИН раз и переиспользуется всеми путями
 * (иначе к каждому пути добавилось бы ещё по 129 с печати), а полный прогон
 * живёт отдельной работой CI (`.github/workflows/put-ustanovki.yml`), которая
 * ходит на правки упаковки, на тег и раз в сутки, а не на каждый коммит. В
 * `npm test` он тоже попадает — тот идёт только на тег и около двух часов, и
 * +8,6 минуты к нему это +7 %.
 *
 * Быстрая половина файла (команды из инструкции, разбор формулы) компилятора не
 * требует и идёт за секунды — она выполняется всегда и везде.
 *
 * ── Как проверить саму проверку ─────────────────────────────────────────────
 * Порчей, и она встроена. `FLANG_PORCHA=<имя>` ломает один шаг нарочно:
 *
 *   FLANG_PORCHA=рантайм      убрать share/flang/c из поставленного
 *   FLANG_PORCHA=имя-выхода   переименовать выход сборки обратно в flang_cli
 *
 * Две другие порчи задуманного задания — подменить sha256 в формуле и вернуть
 * `asdf global` в инструкцию — делаются правкой самих файлов, и ключа для них
 * здесь НЕТ намеренно: чёрный ход в проверке, которым можно подменить её же
 * улику, стоит дороже, чем удобство порчи. Порча этих двух — обычный sed по
 * `packaging/homebrew/flang.rb` и `packaging/asdf/README.md`.
 *
 * Проверка, которая не краснеет на порче, ничего не держит.
 *
 * Запуск:
 *   node --test --test-timeout=1800000 flang/test/install-path.test.mjs
 */
