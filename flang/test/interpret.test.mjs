// ───────────────────────────── цена «добавить» ─────────────────────────────

/*
 * Виток — это оборот машины, а не единица работы, и на этом стояла дыра.
 *
 * УЛИКА. «добавить … к …» строило новый список ЦЕЛИКОМ, значит накопление н
 * элементов стоило O(н²), а счётчик витков этого НЕ ВИДЕЛ: на 50 000 / 100 000 /
 * 200 000 «добавить» витков ровно 1 000 009 / 2 000 009 / 4 000 009 — линия, —
 * а времени 14 375 / 48 668 / 229 634 мс, показатель роста при удвоении 1,76 и
 * 2,24, то есть квадрат. Предел шагов при такой цене шага перестаёт быть
 * СРОКОМ: у целей печати те же 5 000 000 шагов брались двадцать минут вместо
 * секунды, и от вечного цикла это неотличимо.
 *
 * Отсюда здесь ДВА теста, и они проверяют разное:
 *
 *   • цену — накопление обязано быть линейным, и витки при этом обязаны
 *     остаться теми же ДО ЕДИНИЦЫ (иначе починили не цену, а семантику);
 *   • правильность — список продлевается ЗАПИСЬЮ в общий массив, и если
 *     инвариант «ячейку за концом занимает единственный» сломан, ветвление двух
 *     «добавить» от одного списка испортит оба.
 *
 * Без второго первый зеленел бы и на «добавить», которое просто портит данные.
 */

/** «Накопить н» — н раз «добавить», хвостовым самовызовом. AST руками. */
const накопление = {
  flang: 1,
  module: "Накопление",
  functions: [{
    name: "Накопить",
    total: true,
    params: [{ name: "н" }, { name: "итог" }],
    body: {
      kind: "if",
      cond: бин("lte", пер("н"), лит(0)),
      then: пер("итог"),
      else: зов("Накопить", бин("sub", пер("н"), лит(1)), форма("добавить", пер("н"), пер("итог"))),
    },
  }],
}

test("накопление списка линейно, а витки при этом не двигаются ни на единицу", (t) => {
  /* Предел шагов поднят намеренно: здесь меряется цена ОДНОГО шага, и упор в
     счётчик в измерение входить не должен. Самовызов хвостовой, поэтому глубина
     остаётся единицей при любом н. */
  const рантайм = createRuntime(накопление, { maxSteps: 50_000_000 })
  const времена = []
  for (const н of [50_000, 100_000, 200_000]) {
    const отчёт = {}
    const начало = Date.now()
    const список = рантайм.call("Накопить", [н, []], { отчёт })
    времена.push(Date.now() - начало)

    assert.ok(Array.isArray(список), "наружу обязан выходить обычный массив, а не вид вычислителя")
    assert.equal(список.length, н, "накоплено не то число элементов")
    assert.equal(список[0], н, "первым обязан лежать первый добавленный")
    assert.equal(список[н - 1], 1, "последним — последний добавленный")
    /* Тот самый сторож. Число снято ДО починки и обязано пережить её без
       изменения: витки считают обороты машины, а не копии, поэтому правильная
       починка цены их не трогает. Поехали витки — переехала семантика. */
    assert.equal(отчёт.витки, 20 * н + 9, "счётчик витков сдвинулся — это уже не та же программа")
  }

  /* Порог с запасом в два порядка, а не «на глаз»: до починки те же три точки
     давали 14 375, 48 668 и 229 634 мс, после — 80, 130 и 272 мс. Между 272 и
     30 000 нет ни машины помедленнее, ни отобранного процессора: там разница
     классов сложности, а не нагрузки. */
  assert.ok(
    времена[2] < 30_000,
    `200 000 «добавить» заняли ${времена[2]} мс — это снова квадрат, а не линия`,
  )
  /* И отдельно форма роста: удвоение длины обязано удваивать время, а не
     учетверять. Множитель 3 (а не 2) и запас в 500 мс оставлены под шум машины;
     квадрат давал здесь 4,7. */
  assert.ok(
    времена[2] < времена[1] * 3 + 500,
    `удвоение числа «добавить» подняло время с ${времена[1]} до ${времена[2]} мс — это квадратичный рост`,
  )
  t.diagnostic(
    `накопление: 50 000 за ${времена[0]} мс, 100 000 за ${времена[1]} мс, 200 000 за ${времена[2]} мс`,
  )
})

test("«добавить» за постоянное время не портит исходный список: ветвление и хвост", () => {
  /* Ветвление — то самое место, где приём «занять ячейку за концом» ломается,
     если инвариант неверен: «три» обязано кончаться тройкой, «четыре» —
     четвёркой, а «основа» обязана остаться прежней. Ослабление условия
     «занято == конец» до «занято >= конец» даёт здесь [[],[1],[2],[1,4],[1,4]]
     вместо [[],[1],[2],[1,3],[1,4]] — то есть «три» переписывается задним
     числом. «Хвост» стоит рядом не для полноты: он отдаёт суффикс ЧУЖОГО
     списка, и продление такого суффикса не имеет права дописать в чужие
     ячейки. */
  const ветвление = {
    flang: 1,
    module: "Ветвление добавления",
    functions: [
      {
        name: "Ветвление",
        params: [{ name: "основа" }],
        body: {
          kind: "let",
          name: "один",
          value: форма("добавить", лит(1), пер("основа")),
          in: {
            kind: "let",
            name: "два",
            value: форма("добавить", лит(2), пер("основа")),
            in: {
              kind: "let",
              name: "три",
              value: форма("добавить", лит(3), пер("один")),
              in: {
                kind: "let",
                name: "четыре",
                value: форма("добавить", лит(4), пер("один")),
                in: {
                  kind: "list",
                  items: [пер("основа"), пер("один"), пер("два"), пер("три"), пер("четыре")],
                },
              },
            },
          },
        },
      },
      {
        name: "Ветвление хвоста",
        params: [{ name: "основа" }],
        body: {
          kind: "let",
          name: "срез",
          value: форма("хвост", пер("основа")),
          in: {
            kind: "let",
            name: "один",
            value: форма("добавить", лит(1), пер("срез")),
            in: {
              kind: "let",
              name: "два",
              value: форма("добавить", лит(2), пер("срез")),
              in: { kind: "list", items: [пер("основа"), пер("срез"), пер("один"), пер("два")] },
            },
          },
        },
      },
    ],
  }
  const рантайм = createRuntime(ветвление)

  assert.deepEqual(рантайм.call("Ветвление", [[]]), [[], [1], [2], [1, 3], [1, 4]])
  assert.deepEqual(
    рантайм.call("Ветвление", [[7, 8]]),
    [[7, 8], [7, 8, 1], [7, 8, 2], [7, 8, 1, 3], [7, 8, 1, 4]],
  )
  for (const основа of [[7], [7, 8, 9], [1, 2, 3, 4, 5]]) {
    const [сама, один, два, три, четыре] = рантайм.call("Ветвление", [основа])
    assert.deepEqual(сама, основа, "исходный список обязан остаться прежним")
    assert.deepEqual(один, [...основа, 1])
    assert.deepEqual(два, [...основа, 2])
    assert.deepEqual(три, [...основа, 1, 3])
    assert.deepEqual(четыре, [...основа, 1, 4])
  }

  assert.deepEqual(рантайм.call("Ветвление хвоста", [[7, 8]]), [[7, 8], [8], [8, 1], [8, 2]])
  for (const основа of [[7], [7, 8, 9], [1, 2, 3, 4, 5]]) {
    const срез = основа.slice(1)
    assert.deepEqual(
      рантайм.call("Ветвление хвоста", [основа]),
      [основа, срез, [...срез, 1], [...срез, 2]],
    )
  }

  /* Продление списка, по которому ИДЁТ обход: тело свёртки занимает ячейки за
     концом того самого общего массива, и обход обязан их не увидеть — иначе
     свёртка по списку из трёх элементов не кончится никогда. */
  const свёрткаПоРастущему = {
    flang: 1,
    module: "Свёртка по растущему",
    functions: [{
      name: "Удвоить обходом",
      params: [{ name: "элементы" }],
      body: {
        kind: "let",
        name: "начало",
        value: форма("добавить", лит(0), пер("элементы")),
        in: {
          kind: "fold",
          over: пер("начало"),
          init: пер("начало"),
          acc: "накоплено",
          item: "элемент",
          body: форма("добавить", пер("элемент"), пер("накоплено")),
        },
      },
    }],
  }
  assert.deepEqual(
    createRuntime(свёрткаПоРастущему).call("Удвоить обходом", [[1, 2, 3]]),
    [1, 2, 3, 0, 1, 2, 3, 0],
  )
})

/*
 * ── То же самое для «приписать … к …», и проверять отдельно ОБЯЗАТЕЛЬНО ─────
 *
 * У приписывания в начало свой конец буфера и свой водораздел. `буфер.length`
 * ему не годится ничем: массив JS растёт только вправо. Занятое слева считает
 * `буфер.низ` — первая занятая кем-то ячейка, — и он только УБЫВАЕТ; занять
 * ячейку `низ − 1` вправе тот единственный список, чьё `начало` совпало с `низ`
 * (`builtins.mjs`, «Список с запасом»).
 *
 * Значит инвариант здесь ВТОРОЙ, а не тот же самый, и зелёные тесты «добавить»
 * о нём не говорят ничего. Ослабление условия `начало === низ` до `начало >= низ`
 * даёт на ветвлении [[],[1],[2],[4,1],[4,1]] вместо [[],[1],[2],[3,1],[4,1]] —
 * «три» переписывается задним числом ровно так же, как у соседа.
 */

/** «Приписать н» — н раз «приписать», хвостовым самовызовом. AST руками. */
const приписывание = {
  flang: 1,
  module: "Приписывание",
  functions: [{
    name: "Приписать",
    total: true,
    params: [{ name: "н" }, { name: "итог" }],
    body: {
      kind: "if",
      cond: бин("lte", пер("н"), лит(0)),
      then: пер("итог"),
      else: зов("Приписать", бин("sub", пер("н"), лит(1)), форма("приписать", пер("н"), пер("итог"))),
    },
  }],
}

test("приписывание в начало линейно, а витки при этом те же, что у дописывания", (t) => {
  const рантайм = createRuntime(приписывание, { maxSteps: 50_000_000 })
  const времена = []
  for (const н of [50_000, 100_000, 200_000]) {
    const отчёт = {}
    const начало = Date.now()
    const список = рантайм.call("Приписать", [н, []], { отчёт })
    времена.push(Date.now() - начало)

    assert.ok(Array.isArray(список), "наружу обязан выходить обычный массив, а не вид вычислителя")
    assert.equal(список.length, н, "приписано не то число элементов")
    assert.equal(список[0], 1, "первым обязан лежать последний приписанный")
    assert.equal(список[н - 1], н, "последним — первый приписанный")
    /* Витков ровно столько же, сколько у «добавить» на той же программе: формы
       различаются концом списка, а не числом оборотов машины. Поехали витки —
       переехала семантика, а не цена. */
    assert.equal(отчёт.витки, 20 * н + 9, "счётчик витков сдвинулся — это уже не та же программа")
  }

  /* Пороги те же, что у соседа, и по той же причине: между линией и квадратом
     здесь два порядка, а не шум машины. Свёртка, которой приписывание писали до
     появления формы, даёт на этих трёх точках часы (tmp/bench/pripisat.mjs). */
  assert.ok(
    времена[2] < 30_000,
    `200 000 «приписать» заняли ${времена[2]} мс — это квадрат, а не линия`,
  )
  assert.ok(
    времена[2] < времена[1] * 3 + 500,
    `удвоение числа «приписать» подняло время с ${времена[1]} до ${времена[2]} мс — это квадратичный рост`,
  )
  t.diagnostic(
    `приписывание: 50 000 за ${времена[0]} мс, 100 000 за ${времена[1]} мс, 200 000 за ${времена[2]} мс`,
  )
})

