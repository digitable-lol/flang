test("хозяин ходит в сеть: настоящий сервер, настоящий запрос", async () => {
  const сервер = createServer((запрос, ответ) => {
    const путь = decodeURIComponent(запрос.url)
    ответ.writeHead(путь === "/нет" ? 404 : 200, { "content-type": "text/plain; charset=utf-8" })
    ответ.end(`${запрос.method} ${путь}`)
  })
  await new Promise((готово) => слушать(сервер, готово))
  const порт = сервер.address().port
  try {
    const исполнить = nodeHost({})
    const ответ = await исполнить(
      variant("Запросить", { способ: "GET", адрес: `http://127.0.0.1:${порт}/привет`, тело: "" }),
    )
    assert.equal(ответ.variant, "Ответ сети")
    assert.equal(ответ.fields["код"], 200)
    assert.equal(ответ.fields["тело"], "GET /привет")

    const нет = await исполнить(
      variant("Запросить", { способ: "GET", адрес: `http://127.0.0.1:${порт}/нет`, тело: "" }),
    )
    /* 404 — это ОТВЕТ, а не сбой: сеть сработала. Смешивать «не дошло» и
       «дошло и сказало нет» нельзя, иначе программа не сможет их различить. */
    assert.equal(нет.variant, "Ответ сети")
    assert.equal(нет.fields["код"], 404)
  } finally {
    await new Promise((готово) => сервер.close(готово))
  }
})

