test("словарь ввода-вывода — три суммы, и все поручения объявлены полями", () => {
  const [поручение, отклик, продолжение] = IO_TYPES
  assert.deepEqual(поручение.variants.map((в) => в.name), [
    "Прочитать файл",
    "Записать файл",
    "Запросить",
    "Текущее время",
    "Случайное число",
    "Показать",
    "Ждать событие",
    "Перечислить каталог",
    "Запустить процесс",
    "Открыть соединение",
    "Принять соединение",
    "Прочитать из соединения",
    "Ответить в соединение",
  ])
  /* Набор закрыт — но закрыт он объявлением в `io.mjs`, а не числом. Здесь
     стояло «пять, и шестое стоило бы восьми реализаций»; довод снят замером:
     исполнитель в дереве ОДИН (`src/host/node.mjs`), и шестое поручение стоило
     одного. Число осталось сторожем — оно краснеет, когда словарь растёт мимо
     этого списка, и это его единственная работа. Экранные два хозяин Node не
     исполняет, а отказывает `FLANG_IO_NO_SCREEN` — отказ тоже ответ, и он
     проверен ниже; последние четыре — соединение, и синхронный хозяин платит за
     них «Сбоем», как и за «Запросить». Из этих четырёх первое, «Открыть
     соединение», — единственное во всём словаре, которым программа ХОДИТ по
     сырому сокету сама: без него на языке не пишется клиент ни к одной службе
     с двоичным протоколом. */
  assert.equal(поручение.variants.length, 13)
  /* Отклики на запуск процесса ДВА, и это часть контракта, а не подробность
     хозяина: у процесса, остановленного сигналом, кода возврата нет вовсе, и
     единственный вариант потребовал бы часового числа в поле `код`. А на четыре
     поручения соединения отклик ОДИН: «Соединение открыто» отвечает и на
     открытие, и на приём — ответить им нечем, кроме номера, — а чтение из
     соединения отвечает «Прочитано», ответ в соединение — «Записано», теми же
     вариантами, что файл. */
  assert.deepEqual(отклик.variants.map((в) => в.name), [
    "Пока ничего",
    "Прочитано",
    "Записано",
    "Ответ сети",
    "Отметка времени",
    "Выпало",
    "Показано",
    "Случилось",
    "Срок вышел",
    "Перечислено",
    "Процесс завершён",
    "Процесс убит",
    "Соединение открыто",
    "Сбой",
  ])
  assert.ok(отклик.variants.some((в) => в.name === "Сбой"), "у хозяина обязан быть способ сказать «не смог»")
  assert.deepEqual(продолжение.variants.map((в) => в.name), ["Сделать", "Конец работы", "Провал"])
  for (const тип of IO_TYPES) assert.equal(тип.builtin, true, `${тип.name}: словарь вводит язык, а не автор`)
})

