/**
 * Результат плана один — значит все «Конец работы» одного типа.
 *
 * Второй джокер словаря, и чинится он иначе, чем `потом`: объявленного типа у
 * результата плана нет НИГДЕ (`план` не имеет строки `возвращает`), поэтому
 * сверять с объявлением нечего. Проверяется поэтому более слабое, но всё же
 * проверяемое утверждение: у плана ОДИН результат, и ветка, отдающая строку там,
 * где соседняя отдала число, сообщает хозяину то, чего он разобрать не сможет.
 * Образцом становится первое встреченное значение.
 *
 * Улика: программа ниже проходила `check` с `valid: true`.
 */
test("«Конец работы» разного типа в одном плане — отказ проверки", () => {
  const { типы } = собрать(`модуль «М»

тип «Ход»
  вариант «Начало»
  вариант «Конец»

тотальная функция «Начать»
  возвращает «Ход»
  вариант «Начало»

тотальная функция «Дальше»
  принимает ход: «Ход», отклик: «Отклик»
  возвращает «Продолжение»
  разбор ход
    случай вариант «Начало»
      то вариант «Конец работы» с значение равным 42
    случай вариант «Конец»
      то вариант «Конец работы» с значение равным "сорок два"

план «Сходить»
  состояние «Ход»
  начинает с «Начать»
  обрабатывает «Дальше»
`)
  const беда = типы.find((д) => /у плана один результат/u.test(д.message))
  assert.ok(беда !== undefined, `ожидался отказ, получено ${JSON.stringify(типы)}`)
  /* Тип образца называется ТОЧНЫМ именем, а не общим: литерал 42 после
     появления `нат` выводится уточнением, и сообщение говорит «то нат, то
     строка». Прежде здесь стояло `/число/`, и это было верно ровно до того дня.
     Проверяется поэтому «названо одно из числовых имён», а не одно конкретное:
     сузится уточнение ещё раз — сообщение станет точнее, а проверка не
     покраснеет впустую. Что имя ИМЕННО числовое, держит вторая половина: рядом
     обязана стоять `строка`, иначе расхождение не названо. */
  /* Границы слова `\b` здесь не годятся: в JavaScript они определены на
     ASCII-словах, и с кириллицей не срабатывают никогда. */
  assert.match(беда.message, /то (нат|целое|число), то/u, "сообщение обязано назвать тип образца")
  assert.match(беда.message, /строка/u, "и тип расхождения")
})

