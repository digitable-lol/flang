/* ─────────────────── коды выхода: нашёл беду ≠ сам сломался ─────────────── */

/**
 * Программа, которая сдаётся первым же шагом, не тронув мира.
 *
 * Нужна именно такая: единица от `«Провал»` обязана быть видна БЕЗ поручения,
 * иначе её не отличить от единицы, которую даёт неудавшийся эффект.
 */
const СДАТЬСЯ = `модуль «Сдаться»

тип «Ход»
  вариант «Сразу»

тотальная функция «Начать»
  возвращает «Ход»
  вариант «Сразу»

тотальная функция «Дальше»
  принимает ход: «Ход», отклик: «Отклик»
  возвращает «Продолжение»
  разбор ход
    случай вариант «Сразу»
      то вариант «Провал» с код равным "СПЕКИ_НЕ_СОГЛАСНЫ" и сообщение равным "наследница обещает обратное"

план «Вердикт»
  состояние «Ход»
  начинает с «Начать»
  обрабатывает «Дальше»
`

/**
 * Требование, ради которого код выхода вообще правился, — дословно: сторож
 * обязан отличать «нашёл беду» от «сам сломался». До этой правки оба случая
 * давали 1, потому что оба приезжали исключением, и CI не мог сказать, чинить
 * ему спеки или сторожа.
 *
 * Числа берутся не из значения `«Провал»` (его поле `код` — СТРОКА, и номера
 * там нет), а из природы беды: `runPlan` метит ту единственную, которую подняла
 * сама программа.
 */
test("код выхода flang io: 0 — дошли, 1 — программа сдалась сама, 3 — сломался инструмент", async () => {
  const каталог = join(песочница, "cli-коды")
  await mkdirp(каталог)
  await writeFile(join(каталог, "вход.txt"), "текст", "utf8")
  await writeFile(join(каталог, "эхо.flang"), ПЕРЕПИСАТЬ, "utf8")
  await writeFile(join(каталог, "вердикт.flang"), СДАТЬСЯ, "utf8")

  const прогон = async (аргументы) => {
    const итог = await запустить("node", [cli, ...аргументы]).catch((о) => о)
    return { код: итог.code ?? 0, stderr: итог.stderr ?? "" }
  }

  const дошли = await прогон(["io", join(каталог, "эхо.flang")])
  assert.equal(дошли.код, 0)

  const сдались = await прогон(["io", join(каталог, "вердикт.flang")])
  assert.equal(сдались.код, 1, "«Провал» — это вердикт программы: 1, и CI обязан на нём падать")
  assert.equal(JSON.parse(сдались.stderr).diagnostics[0].code, "СПЕКИ_НЕ_СОГЛАСНЫ")

  /* Предел поручений — поломка ОСНАСТКИ: программа ни от чего не отказывалась,
     ей не дали доработать. Такое обязано отличаться от вердикта. */
  const предел = await прогон(["io", join(каталог, "эхо.flang"), "--max-orders", "1"])
  assert.equal(предел.код, 3, "предел поручений — это сломался инструмент, а не нашлась беда")
  assert.equal(JSON.parse(предел.stderr).diagnostics[0].code, "FLANG_IO_LIMIT")

  /* Неизвестный план — туда же: назвали не то, программа не при чём. */
  const нетПлана = await прогон(["io", join(каталог, "эхо.flang"), "--plan", "Нет такого"])
  assert.equal(нетПлана.код, 3)
  assert.equal(JSON.parse(нетПлана.stderr).diagnostics[0].code, "FLANG_UNKNOWN_PLAN")

  /* Двойка осталась двойкой: кривой вызов — не вердикт и не поломка. */
  const кривой = await прогон(["io", join(каталог, "эхо.flang"), "--небывалый-ключ"])
  assert.equal(кривой.код, 2)
})

