/**
 * Поле `потом` сверяется с состоянием плана — то, чего не делал НИКТО.
 *
 * Улика, с которой правка началась: обе программы ниже проходили `check`
 * целиком (`valid: true`, ноль диагностик), а падали у хозяина на первом же
 * обороте цикла — `FLANG_MATCH_NOT_EXHAUSTIVE`, «разбор не покрывает значение
 * Не состояние плана». То есть ошибка, которую статическая проверка обязана
 * поймать, доставалась рантайму.
 *
 * Причина была не в недосмотре, а в том, что поле объявлено джокером (`любое`,
 * `{ kind: "any" }` в словаре): параметрической суммы у `«Продолжение»` нет.
 * Но сверять было ЧЕМ — тип состояния назван автором в строке `состояние «Ход»`,
 * и с ним уже сверялся первый параметр функции шага. Теперь с ним же сверяется
 * и `потом`: хозяин подаёт в шаг ровно то, что шаг объявил.
 *
 * Оба случая нарочно разной природы: чужой ОБЪЯВЛЕННЫЙ тип и голый скаляр —
 * второй проверяет, что сверка не сводится к «лишь бы это был какой-нибудь
 * вариант».
 */
