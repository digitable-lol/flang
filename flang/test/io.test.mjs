test("словарь ввода-вывода — три суммы, и все поручения объявлены полями", () => {
  const [поручение, отклик, продолжение] = IO_TYPES
  assert.deepEqual(поручение.variants.map((в) => в.name), [
    "Прочитать файл",
    "Записать файл",
    "Запросить",
    "Текущее время",
    "Случайное число",
    "Принять связь",
    "Прочитать из связи",
    "Ответить в связь",
  ])
  /* Набор закрыт, и это утверждение, а не описание: каждое поручение обязан
     уметь исполнить каждый хозяин. Последние три — сеть, которой ЖДУТ, и цену
     «в некоторых целях не работает» они платят ОТКЛИКОМ: синхронный хозяин
     отвечает на них «Сбой», как и на «Запросить». */
  assert.equal(поручение.variants.length, 8)
  /* Откликов на три поручения прибавился ОДИН. Чтение из связи отвечает
     «Прочитано», ответ в связь — «Записано»: программе всё равно, кто принёс
     байты, и здесь это утверждение, а не совпадение имён. */
  assert.deepEqual(отклик.variants.map((в) => в.name), [
    "Пока ничего",
    "Прочитано",
    "Записано",
    "Ответ сети",
    "Отметка времени",
    "Выпало",
    "Связь принята",
    "Сбой",
  ])
  assert.ok(отклик.variants.some((в) => в.name === "Сбой"), "у хозяина обязан быть способ сказать «не смог»")
  assert.deepEqual(продолжение.variants.map((в) => в.name), ["Сделать", "Конец работы", "Провал"])
  for (const тип of IO_TYPES) assert.equal(тип.builtin, true, `${тип.name}: словарь вводит язык, а не автор`)
})

