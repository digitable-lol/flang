/**
 * ГЛАВНАЯ ПРОВЕРКА НОВОГО ПОРУЧЕНИЯ, и она нарочно сделана прогоном, а не типами.
 *
 * Сервер здесь НЕ HTTP: `net.createServer` и свой протокол в две строки —
 * «пришла строка, ответил строкой». Взят он такой именно потому, что `«Открыть
 * соединение»` заводится ради протоколов, которых хозяин не знает: сойди эта
 * проверка на HTTP-сервере, она проверяла бы `«Запросить»` другими словами.
 *
 * Дальше идёт весь круг, ради которого поручение и добавлено: открыть — сходить
 * НАРУЖУ (этого в языке не было вовсе), написать запрос, ПРОЧИТАТЬ ответ на том
 * же соединении, написать второй запрос и прочитать второй ответ. Второй обмен
 * здесь не для полноты: он и есть проверка правила «открытое программой
 * соединение ответом не закрывается» — закрывай его первая запись, второй
 * запрос получил бы `«Сбой»`.
 */
test("НАСТОЯЩИЙ ПРОГОН: «Открыть соединение» ходит наружу по сырому сокету и разговаривает дважды", async () => {
  const сервер = createTcpServer((сокет) => {
    сокет.setEncoding("utf8")
    сокет.on("data", (кусок) => сокет.write(`эхо:${кусок.trim()}\n`))
  })
  await new Promise((готово) => сервер.listen(0, "127.0.0.1", готово))
  const порт = сервер.address().port
  const исполнить = nodeHost({})
  try {
    const открыто = await исполнить(variant("Открыть соединение", { адрес: "127.0.0.1", порт }))
    assert.equal(открыто.variant, "Соединение открыто", JSON.stringify(открыто))
    const соединение = открыто.fields["соединение"]
    assert.equal(typeof соединение, "number")

    const записано = await исполнить(
      variant("Ответить в соединение", { соединение, содержимое: "привет\n" }),
    )
    assert.equal(записано.variant, "Записано")
    assert.equal(записано.fields["сколько"], 7)

    const пришло = await исполнить(variant("Прочитать из соединения", { соединение }))
    assert.equal(пришло.variant, "Прочитано")
    assert.equal(пришло.fields["содержимое"], "эхо:привет\n")

    /* ВТОРОЙ обмен по ТОМУ ЖЕ номеру: если бы ответ закрывал открытое
       соединение, здесь стоял бы «Сбой» с FLANG_IO_WRITE. */
    await исполнить(variant("Ответить в соединение", { соединение, содержимое: "ещё\n" }))
    const второе = await исполнить(variant("Прочитать из соединения", { соединение }))
    assert.equal(второе.fields["содержимое"], "эхо:ещё\n")

    /* Пустое содержимое — «положить трубку»: другого слова для этого в словаре
       нет, и после него номер перестаёт быть номером. */
    const закрыто = await исполнить(variant("Ответить в соединение", { соединение, содержимое: "" }))
    assert.equal(закрыто.variant, "Записано")
    assert.equal(закрыто.fields["сколько"], 0)
    const после = await исполнить(variant("Прочитать из соединения", { соединение }))
    assert.equal(после.variant, "Сбой")
    assert.equal(после.fields["код"], "FLANG_IO_READ")
  } finally {
    исполнить.закрыть()
    await new Promise((готово) => сервер.close(готово))
  }
})

