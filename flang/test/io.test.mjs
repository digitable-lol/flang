/** Разбор + типы + тотальность одной строкой: три слоя обязаны быть согласны. */
function собрать(исходник) {
  const программа = parse(исходник, "проба.flang")
  return {
    программа,
    типы: checkTypes(программа).diagnostics,
    тотальность: checkTotality(программа).diagnostics,
  }
}

