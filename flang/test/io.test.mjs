/**
 * Ввод-вывод flang: словарь поручений, план и хозяин.
 *
 * Контракт — `flang/cat/SPEC.md`, раздел «Эффекты и HTTP». Проверяется ровно
 * то, что он обещает, и в том же порядке.
 *
 * 1. **Чистота не потеряна.** Функция, строящая поручение, — обычная тотальная
 *    функция, и её примеры сходятся БЕЗ файлов, сети и часов. Это главное
 *    свойство всей затеи: описание действия сравнивается с ожидаемым описанием,
 *    а не выполняется.
 * 2. **Словарь приписывается только при использовании.** Программа без
 *    ввода-вывода обязана дать побайтово тот же AST, что и раньше, — иначе
 *    неподвижная точка самоприменения сошлась бы к другому компилятору.
 * 3. **Слово `план` никого не выселило.** Слово «шаг» ключевым не стало, и
 *    файл, где `шаг` — переменная и поле записи, по-прежнему разбирается.
 * 4. **Хозяин исполняет, и он же может отказать.** Настоящий хозяин на Node
 *    читает файл, ходит в сеть (по настоящему сокету к настоящему серверу) и
 *    пишет файл; хозяин с урезанными правами отвечает отказом, а не молчанием.
 * 5. **Прогон повторим.** Одно семя — одно случайное число.
 */
