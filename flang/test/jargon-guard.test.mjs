/**
 * Сторож жаргона обязан УМЕТЬ КРАСНЕТЬ — и краснеть на настоящем файле.
 *
 * ── Зачем этот тест длиннее самого сторожа ──────────────────────────────────
 * Проверка, переставшая сравнивать, выглядит ровно как проверка, у которой всё
 * хорошо. В этом дереве такое находили тринадцать раз за трое суток, и
 * последний случай был в тот же день, что и этот сторож: сверка печати
 * вычитала блок ПЕРЕД сравнением, и напечатанный код собирался без единого
 * предупреждения, а падал при первом запросе.
 *
 * Поэтому здесь не «сторож зелёный» (это одна строка), а пять разных способов
 * его уронить:
 *
 *   1. сегодня чисто — новых слов нет, долг сходится с записанным;
 *   2. каждый образец ЛОВИТ то, что обязан ловить, и НЕ ловит то, что не
 *      должен. Ослабленный образец («эталон» → «этало-о-он») роняет тест, а не
 *      тихо перестаёт находить;
 *   3. ПОРЧА: слово вписывается в настоящую страницу — сторож обязан
 *      покраснеть и назвать файл со строкой. И на чистой странице, и на той, у
 *      которой записан долг: долг не имеет права расти;
 *   4. исключение нельзя выдумать: цитата объяснения, которой в файле нет, —
 *      отказ; объяснение ПОСЛЕ первого употребления — тоже отказ;
 *   5. новая страница сайта не может проскользнуть мимо сторожа: каждый
 *      источник из карты сайта либо под маской поверхности, либо назван в
 *      списке «вне запрета» с доводом.
 *
 * Запуск: node --test flang/test/jargon-guard.test.mjs
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { РАЗДЕЛЫ, БАЗА_ЗНАНИЙ } from "../../docs/site/sitemap.mjs"
import {
  маскаВОбразец,
  найти,
  образецСлова,
  прочитатьНастройку,
  читаемое,
} from "../../scripts/jargon-guard.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url))
const СТОРОЖ = "scripts/jargon-guard.mjs"

/** Запуск сторожа отдельным процессом. Возвращает `{ код, вывод }`, не бросая. */
function запустить(...ключи) {
  try {
    const вывод = execFileSync(process.execPath, [СТОРОЖ, ...ключи], {
      cwd: КОРЕНЬ,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      env: { ...process.env, LC_ALL: "C.UTF-8" },
    })
    return { код: 0, вывод }
  } catch (беда) {
    return { код: беда.status ?? 1, вывод: `${беда.stdout ?? ""}${беда.stderr ?? ""}` }
  }
}

/** Вписать порчу в файл, прогнать сторожа, вернуть файл как был. */
function приПорче(файл, испортить, что) {
  const путь = КОРЕНЬ + файл
  const было = readFileSync(путь, "utf8")
  try {
    const стало = испортить(было)
    assert.notEqual(стало, было, `порча ${файл} ничего не изменила — проверку надо чинить, а не отключать`)
    writeFileSync(путь, стало)
    что(запустить())
  } finally {
    writeFileSync(путь, было)
  }
  assert.equal(запустить().код, 0, `после отката сторож обязан снова быть зелёным (${файл})`)
}

/* ─────────────────────────── 1. сегодня чисто ─────────────────────────────── */

test("сторож жаргона сегодня зелёный: новых внутренних слов нет", () => {
  const { код, вывод } = запустить()
  assert.equal(код, 0, `сторож жаргона красный:\n${вывод}`)
  assert.match(вывод, /новых 0/u)
})

test("долг записан и не пуст: сторож стережёт живое, а не пустой список", () => {
  const настройка = прочитатьНастройку(КОРЕНЬ)
  const файлов = Object.keys(настройка.долг ?? {}).length
  assert.ok(файлов > 0, "долг пуст — либо всё уже чисто (проверьте руками), либо сторож ничего не читает")
  assert.ok(настройка.поверхности.length > 0, "список поверхностей пуст: стеречь нечего")
})

/* ────────────────── 2. образцы ловят то, что обязаны ловить ────────────────── */

test("каждый образец ловит свои примеры и не ловит чужие", () => {
  const { слова } = прочитатьНастройку(КОРЕНЬ)
  for (const слово of слова) {
    assert.ok(Array.isArray(слово.ловит) && слово.ловит.length > 0, `у слова «${слово.имя}» нет ни одного примера «ловит»`)
    for (const пример of слово.ловит) {
      assert.ok(
        образецСлова(слово).test(пример),
        `образец слова «${слово.имя}» ПЕРЕСТАЛ ловить «${пример}» — он больше не находит того, ради чего заведён`,
      )
    }
    for (const пример of слово["не ловит"] ?? []) {
      assert.ok(
        !образецСлова(слово).test(пример),
        `образец слова «${слово.имя}» ловит «${пример}», а не должен: это обычное слово, и краснеть на нём значит заставлять писать неправду`,
      )
    }
  }
})

test("имена слов не повторяются: два образца с одним именем прячут друг друга в отчёте", () => {
  const { слова } = прочитатьНастройку(КОРЕНЬ)
  const имена = слова.map((с) => с.имя)
  assert.deepEqual([...new Set(имена)].sort(), [...имена].sort())
})

/* ─────────────────────────────── 3. ПОРЧА ─────────────────────────────────── */

test("КРАСНЕЕТ: жаргон вписан в чистую страницу — отказ называет файл и строку", () => {
  const файл = "docs/guide/single-source.ru.md"
  assert.equal(прочитатьНастройку(КОРЕНЬ).долг?.[файл] ?? 0, 0, `у ${файл} появился долг — возьмите для порчи другую чистую страницу`)
  приПорче(
    файл,
    (текст) => текст + "\nКорпус сверяется с эталоном побайтово, и это держит сторож.\n",
    ({ код, вывод }) => {
      assert.equal(код, 1, "сторож НЕ покраснел на странице с вписанным жаргоном")
      assert.match(вывод, new RegExp(файл.replace(/[.]/gu, "\\."), "u"), "отказ не назвал файл")
      assert.match(вывод, /строка \d+/u, "отказ не назвал строку")
      assert.match(вывод, /эталон/iu, "отказ не назвал само слово")
    },
  )
})

test("КРАСНЕЕТ: долг не имеет права расти — одно лишнее слово на странице с долгом", () => {
  const файл = "README.ru.md"
  const записанный = прочитатьНастройку(КОРЕНЬ).долг?.[файл] ?? 0
  assert.ok(записанный > 0, `у ${файл} нет записанного долга — возьмите для этой проверки другой файл`)
  приПорче(
    файл,
    (текст) => текст + "\nВедомость печатается по всему корпусу.\n",
    ({ код, вывод }) => {
      assert.equal(код, 1, "сторож НЕ покраснел на выросшем долге")
      assert.match(вывод, /README\.ru\.md: внутренних слов \d+, дозволено \d+/u, "отказ не назвал ни числа найденного, ни дозволенного")
    },
  )
})

test("КРАСНЕЕТ: долг упал, а число не поправили", () => {
  // Долг падает при чистке страницы. Сторож обязан требовать нового числа, иначе
  // потолок остаётся высоким и пропускает свежий жаргон обратно.
  const файл = "docs/jargon.json"
  приПорче(
    файл,
    (текст) => {
      const н = JSON.parse(текст)
      const первый = Object.keys(н.долг)[0]
      н.долг[первый] += 5
      return JSON.stringify(н, null, 2) + "\n"
    },
    ({ код, вывод }) => {
      assert.equal(код, 1, "сторож НЕ покраснел на завышенном долге")
      assert.match(вывод, /Долг упал/u, "отказ не сказал, что делать с упавшим долгом")
    },
  )
})

test("жаргон в блоке кода и в имени файла НЕ считается: это название вещи, а не проза", () => {
  const { слова } = прочитатьНастройку(КОРЕНЬ)
  const страница = [
    "# Проба",
    "",
    "Смотрите [отчёт](../scripts/proof-ledger.mjs) и команду `flang check --proof`.",
    "",
    "```",
    "node flang/scripts/proof-ledger.mjs   # ведомость по всему корпусу",
    "```",
    "",
  ].join("\n")
  assert.deepEqual(найти(читаемое(страница, "проза"), слова), [])
})

test("в исходнике читаются ТОЛЬКО строки, и адрес со слэшами их не съедает", () => {
  /* Ровно то место, где сторож начал бы зеленеть впустую: приняв две косые
     внутри адреса за начало комментария, он проглотил бы конец строки вместе с
     жаргоном в ней. */
  const { слова } = прочитатьНастройку(КОРЕНЬ)
  const исходник = [
    '/* ведомость в комментарии законна: это разговор разработчиков */',
    '// и здесь тоже: корпус, эталон, свидетель',
    'puts("см. https://flang.dev/proofs — ведомость печатается ключом --proof");',
  ].join("\n")
  const находки = найти(читаемое(исходник, "строки"), слова)
  assert.equal(находки.length, 1, `в исходнике найдено ${находки.length} вместо одного: ${находки.map((н) => н.текст).join(", ")}`)
  assert.equal(находки[0].строка, 3)
})

test("литерал-образец с кавычкой внутри не сбивает разбор — иначе сторож читал бы КОД как прозу", () => {
  /* Настоящий случай: разборщик на JavaScript содержал
     `message.replace(/'([^']{1,40})'/gu, …)`. Разборщик проверки, не знающий
     про образцы, принимал первую кавычку за начало строки и с этого места читал
     весь файл как текст для читателя: 54 «находки» в комментариях одного
     парсера и молчание о настоящих строках.

     Живым файлом здесь был `flang/src/parser.mjs`. Его в дереве нет с
     20 августа 2026 — реализация на JavaScript удалена коммитом `fe8e8a37`, — и
     проба с того дня падала на чтении: ENOENT, а не проваленное утверждение.
     Живой файл ей нужен любой, лишь бы с образцами, внутри которых стоит
     кавычка; такой есть — исходник самого сторожа. */
  const { слова } = прочитатьНастройку(КОРЕНЬ)
  const исходник = [
    "const цитата = сообщение.replace(/'([^']{1,40})'/gu, (целиком) => целиком)",
    "/* корпус, эталон, сторож — это комментарий, и он законен */",
    'const подсказка = "здесь ведомость — настоящая утечка"',
  ].join("\n")
  const находки = найти(читаемое(исходник, "строки"), слова)
  assert.deepEqual(
    находки.map((н) => н.строка),
    [3],
    `разбор сбился на литерале-образце: ${находки.map((н) => `строка ${н.строка} «${н.текст}»`).join(", ")}`,
  )

  // И то же самое на живом файле: деление после значения образцом не считается.
  const сторож = читаемое(readFileSync(КОРЕНЬ + "scripts/jargon-guard.mjs", "utf8"), "строки")
  assert.ok(
    !/new RegExp\(/u.test(сторож),
    "разбор исходника выпустил наружу код сторожа — значит, где-то он снова принял код за строку",
  )
})

/* ──────────────────────── 4. исключение нельзя выдумать ────────────────────── */

test("КРАСНЕЕТ: исключение цитирует объяснение, которого в файле нет", () => {
  приПорче(
    "docs/jargon.json",
    (текст) => {
      const н = JSON.parse(текст)
      н.исключения.push({
        файл: "README.ru.md",
        слово: "эталон",
        объяснено: "этой фразы в README нет и никогда не было, она выдумана целиком",
        почему: "проба сторожа",
      })
      return JSON.stringify(н, null, 2) + "\n"
    },
    ({ код, вывод }) => {
      assert.equal(код, 1, "сторож ПРИНЯЛ исключение с выдуманной цитатой")
      assert.match(вывод, /цитирует объяснение, которого в файле нет/u)
    },
  )
})

test("КРАСНЕЕТ: объяснение стоит ПОЗЖЕ первого употребления — читатель уже споткнулся", () => {
  const файл = "docs/guide/single-source.ru.md"
  const путь = КОРЕНЬ + файл
  const былаСтраница = readFileSync(путь, "utf8")
  const былаНастройка = readFileSync(КОРЕНЬ + "docs/jargon.json", "utf8")
  try {
    // Слово стоит в начале, объяснение — в конце. Так и выглядит утечка,
    // которую исключение прикрывать не имеет права.
    writeFileSync(путь, "Сверка идёт с эталоном.\n\n" + былаСтраница + "\nЭталон — это реализация языка на JavaScript, с которой всё сверяется.\n")
    const н = JSON.parse(былаНастройка)
    н.исключения.push({
      файл,
      слово: "эталон",
      объяснено: "Эталон — это реализация языка на JavaScript, с которой всё сверяется.",
      почему: "проба сторожа",
    })
    writeFileSync(КОРЕНЬ + "docs/jargon.json", JSON.stringify(н, null, 2) + "\n")
    const { код, вывод } = запустить()
    assert.equal(код, 1, "сторож ПРИНЯЛ объяснение, стоящее после первого употребления")
    assert.match(вывод, /РАНЬШЕ объяснения/u)
  } finally {
    writeFileSync(путь, былаСтраница)
    writeFileSync(КОРЕНЬ + "docs/jargon.json", былаНастройка)
  }
  assert.equal(запустить().код, 0, "после отката сторож обязан снова быть зелёным")
})

/* ─────────── 5. новая страница сайта не проскользнёт мимо сторожа ──────────── */

test("каждый источник страницы сайта либо под запретом, либо назван в «вне запрета»", () => {
  const настройка = прочитатьНастройку(КОРЕНЬ)
  const поверхности = настройка.поверхности.map((п) => маскаВОбразец(п.маска))
  const освобождения = настройка["вне запрета"].map((о) => маскаВОбразец(о.маска))

  const источники = new Set()
  for (const раздел of РАЗДЕЛЫ) {
    for (const страница of раздел.страницы) {
      if (!страница.из) continue
      источники.add(страница.из)
      // Английская пара объявлена именем файла рядом, а не строкой карты.
      if (страница.из.endsWith(".ru.md")) источники.add(страница.из.slice(0, -".ru.md".length) + ".md")
    }
  }
  источники.add(БАЗА_ЗНАНИЙ.указатель)

  const мимо = [...источники].filter(
    // Английская пара выводится из имени, а не объявляется картой: у части
    // страниц её просто нет, и требовать сторожа на несуществующий файл незачем.
    (файл) => existsSync(КОРЕНЬ + файл) && !поверхности.some((о) => о.test(файл)) && !освобождения.some((о) => о.test(файл)),
  )
  assert.deepEqual(
    мимо,
    [],
    "эти страницы сайта не стережёт никто и никто не сказал почему — впишите их в docs/jargon.json: " +
      "в «поверхности», если их читает пришедший за языком, или в «вне запрета» с доводом",
  )
})

test("«вне запрета» несёт довод на каждую маску, а не голый список", () => {
  const настройка = прочитатьНастройку(КОРЕНЬ)
  for (const о of настройка["вне запрета"]) {
    assert.ok(
      typeof о.почему === "string" && о.почему.length >= 20,
      `у освобождения «${о.маска}» нет довода: молчаливое освобождение — это дыра, а не решение`,
    )
  }
})
