/**
 * Сторож столкновений имён — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/link-collision-guard.mjs`.
 * Обязательств здесь шесть, и второе важнее первого:
 *
 *   1. ПОДДЕЛКА КРАСНИТ, ЧИСТОЕ — НЕТ. Дерево с нарочно внесённым столкновением
 *      названо поимённо; такое же дерево без него молчит. Сторож, который не
 *      умеет краснеть, не стережёт ничего, а сторож, который краснеет всегда,
 *      будет снят.
 *
 *   2. ОБХОД СОВПАДАЕТ СО СВЯЗЫВАНИЕМ. На том же поддельном дереве спрашивается
 *      двоичный (`flang ast`), и его FLANG_DUPLICATE_NAME сверяются со списком
 *      сторожа СЛОВО В СЛОВО. Это единственная проверка, ради которой сторож
 *      вообще имеет право существовать: обход текста — это утверждение о
 *      поведении связывания, и оно обязано проверяться связыванием, а не
 *      рассуждением. Без двоичного проба пропускается; `FTS_REQUIRE_BINARY=1`
 *      превращает пропуск в отказ.
 *
 *   3. МЕСТО НАЗЫВАЕТСЯ. Имя, ОБА файла и ОБЕ строки. Связывание называет одну
 *      строку и без файла вовсе («диагностика компилятора имени файла не
 *      несёт»), и без второго места искать пришлось бы руками.
 *
 *   4. `ТОЛЬКО` УЧТЕНО. Имя, не ввезённое выборочным импортом, столкновением не
 *      считается; и выключи этот учёт — на стволе прибавится ЛОЖНЫХ имён.
 *      Число названо здесь, а не описано словами.
 *
 *   5. СЛОВА ЯЗЫКА НЕ РАЗЪЕХАЛИСЬ. Списки ключевых слов сторожа сверяются с
 *      таблицей лексера (`flang/self/lexer.flang`): у языка четыре письма, и
 *      забытое слово — это молча пропущенное объявление.
 *
 *   6. СТВОЛ СВЕРЕН С ДОЛГОМ. Столкновения ствола записаны поимённо; сторож
 *      краснеет на НОВОМ, а не на записанном.
 *
 * Запуск: node --test flang/test/link-collision-guard.test.mjs
 */
import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"

import {
  КОРЕНЬ,
  РОДЫ,
  СЛОВА,
  ВХОД_ПО_УМОЛЧАНИЮ,
  замыкание,
  объявления,
  прочитатьДолг,
  сверитьСДолгом,
  сообщение,
  столкновения,
} from "../scripts/link-collision-guard.mjs"
import { рабочийКаталог } from "./tempdir.mjs"

const работа = рабочийКаталог("link-collision")
const двоичный = join(КОРЕНЬ, "bootstrap/flang")

/** Завести дерево из именованных файлов и вернуть путь входного. */
function дерево(имя, файлы) {
  const где = join(работа, имя)
  mkdirSync(где, { recursive: true })
  for (const [файл, текст] of Object.entries(файлы)) writeFileSync(join(где, файл), текст)
  return join(где, "вход.flang")
}

const А = `модуль «А»

тотальная функция «Из А»
  возвращает число
  1
`

const Б_ЧИСТЫЙ = `модуль «Б»

тотальная функция «Из Б»
  возвращает число
  2
`

const Б_СО_СТОЛКНОВЕНИЕМ = `модуль «Б»

тотальная функция «Из Б»
  возвращает число
  2

тотальная функция «Из А»
  возвращает число
  3
`

const ВХОД = `модуль «Вход»
  использует «А» из "a.flang"
  использует «Б» из "b.flang"

тотальная функция «Итог»
  возвращает число
  («Из А») плюс («Из Б»)
`

const ВХОД_ВЫБОРОЧНО = `модуль «Вход»
  использует «А» из "a.flang"
  использует «Б» из "b.flang" только «Из Б»

тотальная функция «Итог»
  возвращает число
  («Из А») плюс («Из Б»)
`

/** FLANG_DUPLICATE_NAME двоичного, приведённые к тексту сообщения. */
function связываниеГоворит(вход) {
  const итог = spawnSync(двоичный, ["ast", вход], { encoding: "utf8", maxBuffer: 1024 * 1024 * 256 })
  const текст = `${итог.stderr ?? ""}${итог.stdout ?? ""}`
  return текст
    .split("\n")
    .filter((строка) => строка.includes("FLANG_DUPLICATE_NAME"))
    .map((строка) => строка.replace(/^.*?FLANG_DUPLICATE_NAME[^:]*:\s*/u, "").trim())
    .sort()
}

/* ── 1. подделка краснит, чистое — нет ─────────────────────────────────────── */

test("дерево с внесённым столкновением названо поимённо, с обоими файлами и обеими строками", () => {
  const вход = дерево("подделка", { "a.flang": А, "b.flang": Б_СО_СТОЛКНОВЕНИЕМ, "вход.flang": ВХОД })
  const итог = столкновения(вход, { корень: "/" })
  assert.equal(итог.столкновения.length, 1, "внесённое столкновение обязано найтись")
  const с = итог.столкновения[0]
  assert.equal(с.имя, "Из А")
  assert.equal(с.поле, "functions")
  assert.ok(с.первый.файл.endsWith("a.flang"), `первый файл: ${с.первый.файл}`)
  assert.ok(с.второй.файл.endsWith("b.flang"), `второй файл: ${с.второй.файл}`)
  assert.equal(с.первый.строка, 3, "строка объявления в a.flang")
  assert.equal(с.второй.строка, 7, "строка объявления в b.flang")
})

test("то же дерево без столкновения молчит", () => {
  const вход = дерево("чистое", { "a.flang": А, "b.flang": Б_ЧИСТЫЙ, "вход.flang": ВХОД })
  assert.deepEqual(столкновения(вход, { корень: "/" }).столкновения, [])
})

test("столкновение типов ловится наравне с функциями, а тип и функция одного имени — нет", () => {
  const общийТип = `модуль «Б»

объект «Общий»
  «поле»: число

тотальная функция «Из Б»
  возвращает число
  2
`
  const сТипом = дерево("типы", {
    "a.flang": `модуль «А»

объект «Общий»
  «поле»: число

тотальная функция «Из А»
  возвращает число
  1
`,
    "b.flang": общийТип,
    "вход.flang": ВХОД,
  })
  const итогТипов = столкновения(сТипом, { корень: "/" })
  assert.equal(итогТипов.столкновения.length, 1)
  assert.equal(итогТипов.столкновения[0].поле, "types")

  /* Пространства разные: тип «Общий» и функция «Общий» друг другу не мешают. */
  const разныеРода = дерево("рода", {
    "a.flang": `модуль «А»

объект «Общий»
  «поле»: число
`,
    "b.flang": `модуль «Б»

тотальная функция «Общий»
  возвращает число
  2
`,
    "вход.flang": `модуль «Вход»
  использует «А» из "a.flang"
  использует «Б» из "b.flang"

тотальная функция «Итог»
  возвращает число
  «Общий»
`,
  })
  assert.deepEqual(столкновения(разныеРода, { корень: "/" }).столкновения, [])
})

/* ── 2. обход совпадает со связыванием ─────────────────────────────────────── */

test("на поддельном дереве обход называет то же, что связывание, слово в слово", (t) => {
  if (!existsSync(двоичный)) {
    if (process.env.FTS_REQUIRE_BINARY === "1") assert.fail(`нет двоичного ${двоичный}`)
    t.skip(`нет двоичного ${двоичный} — сверку со связыванием пропускаем`)
    return
  }
  const вход = дерево("сверка", { "a.flang": А, "b.flang": Б_СО_СТОЛКНОВЕНИЕМ, "вход.flang": ВХОД })
  const наше = столкновения(вход, { корень: "/" }).столкновения.map(сообщение).sort()
  assert.deepEqual(наше, связываниеГоворит(вход), "обход и связывание обязаны называть одно и то же")
})

test("выборочный ввоз: чего не ввезли, то не сталкивается — и связывание согласно", (t) => {
  const вход = дерево("выборочно", {
    "a.flang": А,
    "b.flang": Б_СО_СТОЛКНОВЕНИЕМ,
    "вход.flang": ВХОД_ВЫБОРОЧНО,
  })
  assert.deepEqual(
    столкновения(вход, { корень: "/" }).столкновения,
    [],
    "«Из А» из b.flang не ввезена выборочным импортом — столкновения нет",
  )
  if (!existsSync(двоичный)) {
    if (process.env.FTS_REQUIRE_BINARY === "1") assert.fail(`нет двоичного ${двоичный}`)
    t.skip(`нет двоичного ${двоичный}`)
    return
  }
  assert.deepEqual(связываниеГоворит(вход), [], "связывание тоже молчит")
})

/* ── 3. и 4. ствол: `только` меняет картину числом ─────────────────────────── */

test("замыкание ствола — не каталог: файлов заметно меньше, чем .flang в дереве", () => {
  const { порядок, пропали, циклы } = замыкание(ВХОД_ПО_УМОЛЧАНИЮ)
  assert.deepEqual(пропали, [], "в замыкании ствола не должно быть ненайденных модулей")
  assert.deepEqual(циклы, [], "в замыкании ствола не должно быть циклов импорта")
  assert.ok(порядок.length > 20 && порядок.length < 60, `файлов в замыкании: ${порядок.length}`)
  assert.equal(порядок.at(-1).путь, ВХОД_ПО_УМОЛЧАНИЮ, "входной файл сливается последним")
  assert.equal(порядок.at(-1).видимость, null, "входной файл виден целиком")
})

test("выключи учёт `только` — и сторож соврёт: на стволе прибавятся ложные имена", () => {
  const счётом = столкновения(ВХОД_ПО_УМОЛЧАНИЮ).столкновения
  const слепо = столкновения(ВХОД_ПО_УМОЛЧАНИЮ, { безВидимости: true }).столкновения
  assert.ok(
    слепо.length > счётом.length,
    `учёт «только» обязан менять картину: с ним ${счётом.length}, без него ${слепо.length}`,
  )
  const лишние = слепо
    .filter((с) => !счётом.some((н) => н.поле === с.поле && н.имя === с.имя))
    .map((с) => `${с.слово} «${с.имя}»`)
  assert.ok(лишние.length > 0, `ложных имён без учёта «только»: ${лишние.join(", ")}`)
})

/* ── 5. слова языка ────────────────────────────────────────────────────────── */

test("ключевые слова сторожа — те же, что в таблице лексера", () => {
  const текст = readFileSync(join(КОРЕНЬ, "flang/self/lexer.flang"), "utf8")
  const начало = текст.indexOf("тотальная функция «Куски таблицы»")
  assert.ok(начало > 0, "в лексере не нашлась «Куски таблицы» — сверять не с чем")
  const конец = текст.indexOf("\nтотальная функция", начало + 10)
  const тело = текст.slice(начало, конец)
  const поЖетонам = new Map()
  for (const кусок of тело.matchAll(/"((?:[^"\\]|\\.)*)"/gu)) {
    for (const пара of кусок[1].split("|")) {
      const где = пара.indexOf(":")
      if (где <= 0) continue
      const слово = пара.slice(0, где)
      const жетон = пара.slice(где + 1)
      if (!поЖетонам.has(жетон)) поЖетонам.set(жетон, [])
      поЖетонам.get(жетон).push(слово)
    }
  }
  for (const [жетон, слова] of Object.entries(СЛОВА)) {
    assert.deepEqual(
      [...слова].sort(),
      [...(поЖетонам.get(жетон) ?? [])].sort(),
      `слова жетона «${жетон}» разъехались с таблицей лексера`,
    )
  }
  /* Каждый род опирается на жетоны, которые в списке слов есть. */
  for (const род of РОДЫ) {
    for (const жетон of род.жетоны) {
      assert.ok(СЛОВА[жетон] !== undefined, `род ${род.поле} просит неизвестный жетон ${жетон}`)
    }
  }
})

test("объявление читается только с первой колонки: `запись «Х» с …` — не объявление", () => {
  const найдено = объявления(`модуль «М»

объект «Точка»
  «х»: число

тотальная функция «Собрать»
  возвращает «Точка»
  запись «Точка» с «х» равным 1

// тотальная функция «Из комментария»
`)
  assert.deepEqual(
    найдено.map((о) => `${о.поле}:${о.имя}`),
    ["types:Точка", "functions:Собрать"],
  )
})

