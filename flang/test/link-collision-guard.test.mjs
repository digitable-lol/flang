/* ── 7. три формы, найденные СВЕРКОЙ, а не вычиткой ────────────────────────── */

test("цепочка, тождественная стрелка и естественное преобразование — три ловушки теорката", () => {
  /* Все три поймала сверка со связыванием на поддельных деревьях, и каждая
     до неё была ошибкой: цепочку и единицу сторож не видел вовсе, а
     преобразование называл лишним именем. */
  const найдено = объявления(`модуль «М»

морфизм «отгрузить» из «Заказ» в «Отгрузка»

единица «Заказ»

цепочка «Оформление»
  сначала «отгрузить»
  затем «выписать»

морфизм «в копейки» из функтора «В рублях» в функтор «В копейках»
`)
  assert.deepEqual(
    найдено.map((о) => `${о.поле}:${о.имя}`),
    ["morphisms:отгрузить", "morphisms:единица Заказ", "morphisms:Оформление"],
    "цепочка и единица — стрелки; естественное преобразование стрелкой не становится",
  )
})

test("цепочка сталкивается с одноимённым морфизмом соседнего модуля", (t) => {
  const шаги = `модуль «А»

объект «Заказ»
  «н»: число

объект «Отгрузка»
  «н»: число

объект «Счёт»
  «н»: число

морфизм «отгрузить» из «Заказ» в «Отгрузка»
морфизм «выставить» из «Отгрузка» в «Счёт»

цепочка «Оформление»
  сначала «отгрузить»
  затем «выставить»
`
  const сосед = `модуль «Б»

объект «Заявка»
  «н»: число

объект «Расчёт»
  «н»: число

морфизм «Оформление» из «Заявка» в «Расчёт»
`
  const вход = дерево("цепочка", { "a.flang": шаги, "b.flang": сосед, "вход.flang": ВХОД })
  const наше = столкновения(вход, { корень: "/" }).столкновения
  assert.equal(наше.length, 1)
  assert.equal(наше[0].имя, "Оформление")
  assert.equal(наше[0].поле, "morphisms")
  if (!existsSync(двоичный)) {
    if (process.env.FTS_REQUIRE_BINARY === "1") assert.fail(`нет двоичного ${двоичный}`)
    t.skip(`нет двоичного ${двоичный}`)
    return
  }
  assert.deepEqual(наше.map(сообщение).sort(), связываниеГоворит(вход))
})
