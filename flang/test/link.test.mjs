/** Проверка типов поверх связанной программы: связывание отдаёт лишний ключ. */
function проверитьСвязанное(связано) {
  const { diagnostics: _беды, ...программа } = связано
  return checkTypes(программа)
}

/**
 * Полная дорога проверки: связать файл из песочницы и проверить типы связанного.
 *
 * `options` передаётся насквозь, потому что просьбы у зовущих разные:
 * `bin/flang.mjs` связывает без них, а `repl.mjs` — с `attributeFiles`, и
 * проверять надо ровно то, что просят они, а не удобную середину.
 */
async function проверить(dir, имя, options = {}) {
  const связано = await linkProgram(join(dir, имя), await readEntry(dir, имя), parse, options)
  return { связывание: связано.diagnostics, типы: проверитьСвязанное(связано).diagnostics, программа: связано }
}

const коды = (список) => список.map((беда) => беда.code)

