/**
 * Повтор ВНУТРИ одного файла ловится одинаково — есть в файле импорты или нет.
 *
 * Улика, с которой правка началась. Файл с двумя `тотальная функция «Ответ»` и
 * одной строкой `использует`, которая к повтору отношения не имеет:
 *
 *   • `check` отвечал `valid: true` и НОЛЬ диагностик;
 *   • побеждало второе тело (`999`), первое исчезало;
 *   • вместе с первым исчезал его `пример` — `flang test` показывал ноль
 *     примеров, то есть проверка, написанная автором, не считалась вовсе.
 *
 * Тот же файл без строки `использует` честно отвергался «функция «Ответ»
 * объявлена дважды». То есть присутствие постороннего импорта ВЫКЛЮЧАЛО
 * проверку: `types.mjs` ловит повтор на слитой программе, а связывание роняло
 * второе объявление молча (`previous !== file` в `merge`).
 *
 * Проверяется поэтому не «есть диагностика», а РАВЕНСТВО двух наборов: один и
 * тот же текст с импортом и без обязан давать те же коды и те же сообщения.
 * Утверждение сильнее и не даёт починить это половинчато — например, выдав с
 * импортом другой код или лишнее второе сообщение.
 */
test("повтор имени в одном файле ловится и при импорте: наборы диагностик равны", async () => {
  const тело = (шапка) => `${шапка}
тотальная функция «Ответ»
  возвращает число
  пример «Первое тело даёт единицу»
    ожидается 1
  1

тотальная функция «Ответ»
  возвращает число
  999
`
  const dir = await sandbox({
    "помощник.flang": `модуль «Помощник»

тотальная функция «Удвоить»
  принимает н: число
  возвращает число
  н умножить на 2
`,
    "сИмпортом.flang": тело('модуль «Проба»\n  использует «Помощник» из "помощник.flang"\n'),
    "безИмпорта.flang": тело("модуль «Проба»\n"),
  })

  /* `linkProgram` возвращает саму слитую программу, а диагностики связывания
     лежат на ней полем. Имя файла из сообщений убирается: пути двух проб
     разные по построению, а сравниваются наборы. */
  const снять = async (файл) => {
    const слитая = await link(join(dir, файл), await readEntry(dir, файл))
    return [...слитая.diagnostics, ...checkTypes(слитая).diagnostics]
      .map((д) => `${д.code}: ${д.message}`)
      .sort()
  }

  const сИмпортом = await снять("сИмпортом.flang")
  const безИмпорта = await снять("безИмпорта.flang")

  assert.ok(
    безИмпорта.some((с) => /объявлена дважды/u.test(с)),
    `без импорта повтор обязан ловиться, получено ${JSON.stringify(безИмпорта)}`,
  )
  assert.deepEqual(
    сИмпортом,
    безИмпорта,
    "импорт не вправе менять то, ловится ли повтор имени в самом файле",
  )
})

