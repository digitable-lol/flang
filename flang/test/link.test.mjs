test("функтор проверяется, когда его объекты объявлены в другом модуле", async () => {
  /* Функтор — единственный из пяти, кто лежит не своим списком, а узлом
     наследия FTS в `legacy`. `legacy` берётся у входного файла целиком, поэтому
     импортированный функтор терялся, а свой доезжал непроверенным: его объекты
     живут в другом модуле, и без них закону не на чем сойтись. */
  const счета = `модуль «Счета»

объект «Счёт»
  итог является числом

объект «Акт»
  номер является строкой

морфизм «выставить» из «Счёт» в «Акт»
`
  const функтор = (образЗаказа, образОтгрузки) => `модуль «Главный»
  использует «Продажи» из "продажи.flang"
  использует «Счета» из "счета.flang"

функтор «Учёт» из «Продажи» в «Счета»
  объект «Заказ» отображается в «${образЗаказа}»
  объект «Отгрузка» отображается в «${образОтгрузки}»
  морфизм «отгрузить» отображается в морфизм «выставить»
`
  const законный = await sandbox({
    "продажи.flang": ПРОДАЖИ,
    "счета.flang": счета,
    "главный.flang": функтор("Счёт", "Акт"),
  })
  const целое = await проверить(законный, "главный.flang")
  assert.deepEqual(целое.связывание, [])
  assert.deepEqual(целое.типы, [], "законный функтор над двумя модулями обязан проходить молча")

  const кривой = await sandbox({
    "продажи.flang": ПРОДАЖИ,
    "счета.flang": счета,
    "главный.flang": функтор("Акт", "Счёт"),
  })
  const сломано = await проверить(кривой, "главный.flang")
  assert.deepEqual(коды(сломано.типы), ["FLANG_FUNCTOR_ARROW_MISMATCH", "FLANG_FUNCTOR_ARROW_MISMATCH"])
  assert.match(сломано.типы[0].message, /«отгрузить» имеет домен «Заказ»/u)
  assert.match(сломано.типы[0].message, /«выставить» имеет домен «Счёт»/u)
  /* Свой функтор обязан доехать РОВНО один раз: `legacy` входного файла берётся
     целиком, и слить функторы, не вынув их оттуда, значило бы удвоить и
     объявление, и каждое сообщение о нарушенном законе. */
  assert.equal(целое.программа.legacy.filter((узел) => узел?.construct === "functorFile").length, 1)
})

