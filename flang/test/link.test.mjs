test("два морфизма с одним именем из разных модулей — FLANG_DUPLICATE_NAME с обоими файлами", async () => {
  /* Столкновение имён — ошибка того же вида, что у типов и функций, и ловится
     связыванием, а не types.mjs, по измеренной причине: `checkMorphisms` про
     два модуля не знает и говорит «морфизм «х» объявлен дважды», не называя ни
     одного файла и указывая местом на строку, которой в открытом файле нет. */
  const dir = await sandbox({
    "первый.flang": `модуль «Первый»

объект «А»
  поле является числом

морфизм «общий» из «А» в «А»
`,
    "второй.flang": `модуль «Второй»

объект «Б»
  поле является числом

морфизм «общий» из «Б» в «Б»
`,
    "главный.flang": `модуль «Главный»
  использует «Первый» из "первый.flang"
  использует «Второй» из "второй.flang"

функция «Ответ»
  возвращает число
  1
`,
  })
  const итог = await проверить(dir, "главный.flang", { attributeFiles: true })
  assert.deepEqual(коды(итог.связывание), ["FLANG_DUPLICATE_NAME"])
  const беда = итог.связывание[0]
  assert.match(беда.message, /морфизм «общий»/u)
  assert.match(беда.message, /первый\.flang/u)
  assert.match(беда.message, /второй\.flang/u)
  /* Место — там, где стоит второе объявление: первое законно, ошибка в том,
     что его повторили. */
  assert.equal(беда.span.file, join(dir, "второй.flang"))
  /* Одно сообщение, а не два: второе объявление не кладётся в программу, и
     `checkMorphisms` своего «объявлен дважды» уже не добавляет. */
  assert.deepEqual(коды(итог.типы), [])
})

test("столкновение имён ловится у каждого вида объявления, не только у морфизма", async () => {
  /* Виды перечислены поимённо, а не «как-нибудь»: пропусти один — и его имена
     начнут молча перекрываться, а заметить это будет негде. */
  const виды = [
    ["изоморфизм", "изоморфизм «Общее» из «А» в «А»\n  прямой морфизм «сам»\n  обратный морфизм «сам»\n"],
    ["бифунктор", "бифунктор «Общее» из «К» и «К» в «К»\n  объекты «А» и «А» отображаются в «А»\n"],
    ["моноид", "моноид «Общее»\n  носитель число\n  операция «Сложить»\n  единица 0\n"],
    ["функтор", "функтор «Общее» из «К» в «К»\n  объект «А» отображается в «А»\n"],
  ]
  for (const [вид, объявление] of виды) {
    const модуль = (имя) => `модуль «${имя}»

объект «А»
  поле является числом

морфизм «сам» из «А» в «А»

тотальная функция «Сложить ${имя}»
  принимает «а»: число, «б»: число
  возвращает число
  «а» плюс «б»

${объявление.replace("«Сложить»", `«Сложить ${имя}»`)}`
    const dir = await sandbox({
      "первый.flang": модуль("Первый"),
      "второй.flang": модуль("Второй"),
      "главный.flang": `модуль «Главный»
  использует «Первый» из "первый.flang" только «Общее»
  использует «Второй» из "второй.flang" только «Общее»

функция «Ответ»
  возвращает число
  1
`,
    })
    const { связывание } = await проверить(dir, "главный.flang")
    const беда = связывание.find((д) => д.code === "FLANG_DUPLICATE_NAME" && д.message.startsWith(вид))
    assert.notEqual(беда, undefined, `${вид}: ожидалось столкновение, получено ${JSON.stringify(связывание)}`)
    assert.match(беда.message, /первый\.flang/u, `${вид}: не назван первый файл`)
    assert.match(беда.message, /второй\.flang/u, `${вид}: не назван второй файл`)
  }
})

