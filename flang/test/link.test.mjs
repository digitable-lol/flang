/**
 * Та же сверка имени — когда файл уже привезён соседом.
 *
 * Улика: сверка стояла на результате `load`, а `load` отдаёт `null` для уже
 * загруженного файла. Поэтому ОДНА И ТА ЖЕ ложь про имя модуля отвергалась или
 * проходила молча в зависимости от того, притащил ли этот файл кто-то раньше, —
 * то есть от порядка строк `использует`, к самой лжи отношения не имеющего.
 *
 * Проверяются оба порядка одним утверждением: сверка обязана срабатывать и
 * тогда, когда файл видят впервые, и тогда, когда второй раз.
 */
test("имя модуля сверяется и у повторного импорта, а не только у первого", async () => {
  const dir = await sandbox({
    "числа.flang": `модуль «Числа»

тотальная функция «Один»
  возвращает число
  1
`,
    "сосед.flang": `модуль «Сосед»
  использует «Числа» из "числа.flang"

тотальная функция «Два»
  возвращает число
  «Один» плюс 1
`,
    /* Сначала сосед — он и загрузит «числа.flang». К моменту второй строки файл
       уже загружен, и именно здесь сверка пропадала. */
    "главный.flang": `модуль «Главный»
  использует «Сосед» из "сосед.flang"
  использует «Цифры» из "числа.flang"

тотальная функция «Позвать»
  возвращает число
  «Два»
`,
  })
  const result = await link(join(dir, "главный.flang"), await readEntry(dir, "главный.flang"))
  const mismatch = result.diagnostics.find((item) => item.code === "FLANG_IMPORT_NAME")
  assert.notEqual(
    mismatch,
    undefined,
    `повторный импорт под чужим именем обязан ловиться, получено ${JSON.stringify(result.diagnostics)}`,
  )
  assert.match(mismatch.message, /«Числа»/u, "сообщение обязано называть настоящее имя модуля")
  assert.match(mismatch.message, /«Цифры»/u, "и то, под которым его импортируют")
  assert.equal(
    result.diagnostics.filter((item) => item.code === "FLANG_IMPORT_NAME").length,
    1,
    "одна ложь — одно сообщение",
  )
})

