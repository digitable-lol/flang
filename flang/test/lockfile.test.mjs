/**
 * ЗАМОК БЕЗ СКЛАДА — проверки того единственного утверждения, ради которого он
 * заводился: **программа собирается из замка, когда исходников зависимостей на
 * диске нет вовсе.**
 *
 * Проверка устроена подделкой, а не осмотром: настоящая программа с тремя
 * импортами копируется в пустой каталог ВМЕСТЕ С ЗАМКОМ И БЕЗ ЗАВИСИМОСТЕЙ, и
 * `flang check` обязан отдать то же самое, байт в байт. Контрольный опыт
 * рядом: тот же каталог без замка обязан отказать `FLANG_IMPORT_NOT_FOUND` —
 * иначе проверка доказывала бы не работу замка, а то, что зависимости где-то
 * нашлись.
 *
 * Остальное — отказы. Замок, которому верят на слово, ничем не лучше
 * отсутствия замка: испорченный груз, правленый список и замок ПРЕЖНЕЙ СХЕМЫ
 * обязаны отвергаться, а не собираться «из того, что прочиталось».
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { СХЕМА_ЗАМКА, адресМодуля, модулиЗамка, печать, собратьЗамок } from "../src/lockfile.mjs"
import { parse } from "../src/parser.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const CLI = join(корень, "flang", "bin", "flang.mjs")
/* Настоящая программа, а не заготовка: три импорта из stdlib, 78 КБ
   исходников зависимостей, и она проверяется целиком. */
const ПРОГРАММА = join(корень, "flang", "examples", "web", "orders-api.flang")
const КОРНЕВОЙ = join(корень, "flang", "examples", "web")

const позвать = (аргументы, { ждатьОтказ = false } = {}) => {
  try {
    return execFileSync(process.execPath, [CLI, ...аргументы], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  } catch (ошибка) {
    if (!ждатьОтказ) throw ошибка
    return `${ошибка.stdout ?? ""}${ошибка.stderr ?? ""}`
  }
}

const вовремя = () => mkdtempSync(join(tmpdir(), "flang-zamok-"))

/**
 * ПОДМЕНА, КОТОРАЯ ОТЧИТЫВАЕТСЯ, ЧТО ОНА СЛУЧИЛАСЬ.
 *
 * Заведено потому, что порча, попавшая не туда, где считают, даёт ложный ноль:
 * проверка «отказ был» проходит, а отказ был не на подмену. Здесь подмена
 * обязана изменить значение — иначе падает сама подделка, а не проверяемое.
 */
const подменив = (замок, номер, поле, значение) => {
  const копия = JSON.parse(JSON.stringify(замок))
  assert.notEqual(копия.модули[номер][поле], значение, `подмена «${поле}» ничего не поменяла: подделка мимо цели`)
  копия.модули[номер][поле] = значение
  assert.notEqual(
    JSON.stringify(копия.модули[номер]),
    JSON.stringify(замок.модули[номер]),
    `подмена «${поле}» не легла в запись`,
  )
  return копия
}

test("адрес модуля — sha256 его исходника, и ничего больше", () => {
  const исходник = readFileSync(join(корень, "flang", "stdlib", "sets.flang"), "utf8")
  const адрес = адресМодуля(исходник)
  /* Шестьдесят четыре знака шестнадцатеричных — и никакого base64 от сжатия:
     brotli из формата убран, и проверка обязана это видеть, а не подразумевать. */
  assert.match(адрес, /^[0-9a-f]{64}$/)
  /* Детерминированность: тот же вход — тот же адрес. */
  assert.equal(адрес, адресМодуля(исходник))
  /* И один добавленный пробел даёт другой адрес. */
  assert.notEqual(адрес, адресМодуля(`${исходник} `))
})

test("в замке лежат сами зависимости ИСХОДНИКОМ, а не ссылки и не сжатый груз", async () => {
  const замок = await собратьЗамок(ПРОГРАММА, parse)
  assert.equal(замок.схема, СХЕМА_ЗАМКА)
  assert.equal(замок.модули.length, 3)
  assert.deepEqual(замок.модули.map((м) => м.имя).sort(), ["Множество строк", "Словарь", "Строки"])
  for (const модуль of замок.модули) {
    /* Груз — ТЕКСТ ФАЙЛА байт в байт, а не его пересказ. */
    const наДиске = readFileSync(join(КОРНЕВОЙ, модуль.путь), "utf8")
    assert.equal(модуль.исходник, наДиске, `груз «${модуль.имя}» разошёлся с файлом`)
    assert.equal(модуль.адрес, адресМодуля(наДиске))
    assert.ok(модуль.функций > 0)
    /* Ссылка на склад была бы короткой; здесь лежит КОД, и он длинный. Это
       цена подхода, и её надо видеть в проверке, а не только в отчёте. */
    assert.ok(модуль.исходник.length > 200, `груз «${модуль.имя}» подозрительно короток`)
  }
  const модули = модулиЗамка(замок, КОРНЕВОЙ, parse)
  assert.equal(модули.size, 3)
})

test("испорченный груз и правленый список замка отвергаются", async () => {
  const замок = await собратьЗамок(ПРОГРАММА, parse)

  /* Груз подменён чужим: адрес пересчитывается ПО ГРУЗУ, а не читается. */
  const сГрузом = подменив(замок, 0, "исходник", замок.модули[1].исходник)
  assert.throws(() => модулиЗамка(сГрузом, КОРНЕВОЙ, parse), /адрес модуля/)

  /* Груз подменён В ОДНО СЛОВО: имя модуля в первой строке. Адрес обязан
     разойтись — иначе адрес не про содержимое. */
  const одноСлово = замок.модули[0].исходник.replace("модуль «Словарь»", "модуль «Словарик»")
  assert.notEqual(одноСлово, замок.модули[0].исходник, "подмена слова не сработала: слова в файле нет")
  assert.throws(() => модулиЗамка(подменив(замок, 0, "исходник", одноСлово), КОРНЕВОЙ, parse), /адрес модуля/)

  /* Адрес подменён под груз: тогда не сходится печать всего списка. */
  const сАдресом = подменив(замок, 0, "адрес", "0".repeat(64))
  assert.throws(() => модулиЗамка(сАдресом, КОРНЕВОЙ, parse), /печать замка/)

  /* Груз и адрес подменены СОГЛАСОВАННО, а печать списка пересчитана — так
     подделывает тот, кто прочёл этот файл. Ловит проверка имени модуля. */
  const согласованно = подменив(замок, 0, "исходник", одноСлово)
  согласованно.модули[0].адрес = адресМодуля(одноСлово)
  согласованно.печать = печать(согласованно.модули.map((м) => [м.путь, м.адрес]))
  assert.throws(() => модулиЗамка(согласованно, КОРНЕВОЙ, parse), /в замке модуль назван/)

  /* Груз, который вовсе не разбирается, — свой отказ, а не голая беда разбора. */
  const мусор = подменив(замок, 0, "исходник", "это не программа на flang")
  мусор.модули[0].адрес = адресМодуля(мусор.модули[0].исходник)
  мусор.печать = печать(мусор.модули.map((м) => [м.путь, м.адрес]))
  assert.throws(() => модулиЗамка(мусор, КОРНЕВОЙ, parse), /не разбирается|модуль назван/)
})

test("ЗАМОК ПРЕЖНЕЙ СХЕМЫ отвергается громко, а не читается неверно молча", async () => {
  const замок = await собратьЗамок(ПРОГРАММА, parse)

  /* Замок схемы 1 — тот, что собирался до 19 августа 2026: груз в нём был
     base64 от brotli, поле называлось `адрес`, а печать модуля лежала
     отдельным полем. Здесь он воссоздан полем в поле; заглядывать в груз
     новому читателю нельзя и не нужно — отказать он обязан ПО НОМЕРУ СХЕМЫ,
     раньше всякого разбора груза. */
  const прежний = {
    схема: 1,
    вход: замок.вход,
    модули: замок.модули.map((м) => ({
      имя: м.имя,
      путь: м.путь,
      функций: м.функций,
      адрес: Buffer.from(м.исходник, "utf8").toString("base64"),
      печать: "0".repeat(64),
    })),
    печать: "0".repeat(64),
  }
  assert.notEqual(прежний.схема, СХЕМА_ЗАМКА, "подделка мимо цели: схемы совпали")
  let сказано = null
  assert.throws(
    () => модулиЗамка(прежний, КОРНЕВОЙ, parse),
    (беда) => {
      сказано = беда.message
      return true
    },
  )
  /* Отказ обязан НАЗЫВАТЬ беду и говорить, что делать: «замок собран прежним
     форматом, пересоберите». Молчаливое «схема не та» человек не поймёт. */
  assert.match(сказано, /прежним форматом/)
  assert.match(сказано, /схема 1/)
  assert.match(сказано, /Пересоберите: flang lock/)

  /* И вторая застава: прежний замок, которому номер схемы подправили руками,
     обязан упереться в печать — груз-то в нём всё равно прежний. */
  const переклеенный = { ...прежний, схема: СХЕМА_ЗАМКА }
  assert.throws(() => модулиЗамка(переклеенный, КОРНЕВОЙ, parse), /печать замка не сходится/)

  /* Замок вовсе без номера схемы — тоже громкий отказ, а не «ну ладно». */
  const безНомера = { ...замок }
  delete безНомера.схема
  assert.throws(() => модулиЗамка(безНомера, КОРНЕВОЙ, parse), /без номера схемы/)
})

test("прежний замок отвергается и через CLI, кодом FLANG_LOCK", () => {
  const где = вовремя()
  try {
    const замок = JSON.parse(позвать(["lock", ПРОГРАММА]))
    cpSync(ПРОГРАММА, join(где, "orders-api.flang"))
    assert.notEqual(замок.схема, 1, "подделка мимо цели: замок и так схемы 1")
    замок.схема = 1
    writeFileSync(join(где, "flang.lock"), `${JSON.stringify(замок)}\n`, "utf8")
    const вывод = позвать(["check", join(где, "orders-api.flang")], { ждатьОтказ: true })
    assert.match(вывод, /FLANG_LOCK/)
    assert.match(вывод, /прежним форматом/)
    assert.match(вывод, /Пересоберите/)
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
})

test("программа собирается из замка, когда исходников зависимостей нет", () => {
  const где = вовремя()
  try {
    const свидетель = позвать(["check", ПРОГРАММА])
    const замок = позвать(["lock", ПРОГРАММА])
    cpSync(ПРОГРАММА, join(где, "orders-api.flang"))

    /* Контрольный опыт ПЕРВЫМ и без замка: тот же каталог обязан отказать.
       Без него проверка ниже доказывала бы не работу замка, а то, что
       зависимости где-то нашлись. */
    const безЗамка = позвать(["check", join(где, "orders-api.flang")], { ждатьОтказ: true })
    assert.match(безЗамка, /FLANG_IMPORT_NOT_FOUND/)

    writeFileSync(join(где, "flang.lock"), замок, "utf8")
    const изЗамка = позвать(["check", join(где, "orders-api.flang")])
    /* Сверять было ЧТО: пустой вывод сравнялся бы с пустым и дал ложный ноль. */
    assert.ok(свидетель.length > 100, "свидетелю нечего сказать — сверка была бы ни о чём")
    /* Побайтово: замок обязан давать ТО ЖЕ дерево, а не похожее. */
    assert.equal(изЗамка, свидетель)
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
})

test("печать программы из замка совпадает с печатью из исходников побайтово", () => {
  const где = вовремя()
  try {
    const замок = позвать(["lock", ПРОГРАММА])
    cpSync(ПРОГРАММА, join(где, "orders-api.flang"))
    writeFileSync(join(где, "flang.lock"), замок, "utf8")
    /* Улика снималась здесь, а не в `check`: на схеме 1 замок снимал `span`, а
       генератор кода печатает место нарушенного постусловия — расходилось 337
       байт из 76 819 (`docs/zettel/zamok-snimaet-mesta-a-generator-ih-
       pechataet.md`). Схема 2 везёт исходник, места возвращаются вместе с ним,
       и расхождение снимается устройством, а не заплаткой. */
    for (const цель of ["c", "js"]) {
      const изИсходников = позвать(["emit", ПРОГРАММА, "--target", цель])
      const изЗамка = позвать(["emit", join(где, "orders-api.flang"), "--target", цель])
      assert.ok(изИсходников.length > 1000, `печать в ${цель} пуста — сверка была бы ни о чём`)
      assert.equal(изЗамка, изИсходников, `печать в ${цель} разошлась`)
    }
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
})

test("испорченный замок — отказ, а не тихая сборка из чего попало", () => {
  const где = вовремя()
  try {
    const замок = JSON.parse(позвать(["lock", ПРОГРАММА]))
    cpSync(ПРОГРАММА, join(где, "orders-api.flang"))
    assert.match(замок.модули[0].адрес, /^[0-9a-f]{64}$/, "подделка мимо цели: адрес не тот, что портим")
    замок.модули[0].адрес = "0".repeat(64)
    writeFileSync(join(где, "flang.lock"), `${JSON.stringify(замок)}\n`, "utf8")
    const вывод = позвать(["check", join(где, "orders-api.flang")], { ждатьОтказ: true })
    assert.match(вывод, /FLANG_LOCK/)
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
})
