test("сервер не печатает в stdout ничего, кроме рамок протокола", async () => {
  /* Один лишний байт в stdout — и редактор теряет связь навсегда. Проверяется
     тем, что клиент выше разобрал весь поток без остатка: если бы там был
     мусор, разбор рамок упал бы ещё в ходе теста. */
  const исходник = `модуль «Тихо»

тотальная функция «Ответ»
  возвращает число
  42
`
  const каталог = await песочница({ "тихо.flang": исходник })
  const { к, адрес } = await сессия(каталог, "тихо.flang", исходник)
  await к.дождаться(диагностикаДля(адрес))
  await к.закрыть()
  assert.equal(к.процесс.exitCode, 0, `сервер вышел с кодом ${к.процесс.exitCode}; stderr: ${к.журнал()}`)
})

async function прочитать(каталог, имя) {
  const { readFile } = await import("node:fs/promises")
  return readFile(join(каталог, имя), "utf8")
}
