test("чистый файл: диагностика приходит и она пуста", async () => {
  const каталог = await песочница({
    "чисто.flang": `модуль «Чисто»

тотальная функция «Удвоить»
  принимает х: число
  возвращает число
  х умножить на 2
`,
  })
  const { к, адрес } = await сессия(каталог, "чисто.flang", await прочитать(каталог, "чисто.flang"))
  const сообщение = await к.дождаться(диагностикаДля(адрес))
  assert.deepEqual(сообщение.params.diagnostics, [])
  await к.закрыть()
})

test("ошибка типов приходит кодом, уровнем и местом", async () => {
  const исходник = `модуль «Косо»

тотальная функция «Удвоить»
  принимает х: число
  возвращает число
  х умножить на "два"
`
  const каталог = await песочница({ "косо.flang": исходник })
  const { к, адрес } = await сессия(каталог, "косо.flang", исходник)
  const сообщение = await к.дождаться(диагностикаДля(адрес))

  assert.equal(сообщение.params.diagnostics.length > 0, true)
  const первая = сообщение.params.diagnostics[0]
  assert.equal(первая.source, "flang")
  assert.equal(первая.severity, 1)
  assert.match(первая.code, /^FLANG_/u)
  /* Строка с «умножить на» — шестая в файле, то есть пятая с нуля. */
  assert.equal(первая.range.start.line, 5)
  assert.equal(первая.range.end.character > первая.range.start.character, true)
  await к.закрыть()
})

test("правка текста меняет диагностику: ошибка появляется и уходит", async () => {
  const целый = `модуль «Правка»

тотальная функция «Ответ»
  возвращает число
  42
`
  const каталог = await песочница({ "правка.flang": целый })
  const { к, адрес } = await сессия(каталог, "правка.flang", целый)
  assert.deepEqual((await к.дождаться(диагностикаДля(адрес))).params.diagnostics, [])

  к.уведомить("textDocument/didChange", {
    textDocument: { uri: адрес, version: 2 },
    contentChanges: [{ text: целый.replace("  42", "  «Нет такой» от 1") }],
  })
  const сломано = await к.дождаться(диагностикаДля(адрес))
  assert.equal(сломано.params.diagnostics.length > 0, true)

  к.уведомить("textDocument/didChange", {
    textDocument: { uri: адрес, version: 3 },
    contentChanges: [{ text: целый }],
  })
  const починено = await к.дождаться(диагностикаДля(адрес))
  assert.deepEqual(починено.params.diagnostics, [])
  await к.закрыть()
})

test("диагностика процессов доезжает до редактора наравне с типами", async () => {
  /* Проверки процессов появились в языке последними (conc.mjs), и попасть в
     редактор они обязаны тем же путём, что и всё остальное, — иначе у сервера
     завёлся бы собственный, отстающий, список проверок. */
  const исходник = `${ПРОЦЕСС}
надзор «Присмотр»
  процесс «Которого нет» стратегия «перезапустить»
`
  const каталог = await песочница({ "надзор.flang": исходник })
  const { к, адрес } = await сессия(каталог, "надзор.flang", исходник)
  const сообщение = await к.дождаться(диагностикаДля(адрес))
  assert.equal(
    сообщение.params.diagnostics.some((д) => д.message.includes("Которого нет")),
    true,
    `диагностика надзора не пришла: ${JSON.stringify(сообщение.params.diagnostics)}`,
  )
  await к.закрыть()
})

/* ───────────────── честность про место: чужой файл — чужой буфер ────────── */

test("ошибка импортированного модуля уезжает в его буфер, а не в открытый", async () => {
  /* Ради этого в языке и появилось имя файла в месте диагностики. Без него
     «строка 4» из соседнего модуля подчеркнулась бы в открытом файле — на
     строке, которая к ошибке отношения не имеет. */
  const каталог = await песочница({
    "чужой.flang": `модуль «Чужой»

тотальная функция «Кривая»
  принимает х: число
  возвращает число
  х плюс "текст"
`,
    "главный.flang": `модуль «Главный»
  использует «Чужой» из "чужой.flang"

тотальная функция «Позвать»
  принимает х: число
  возвращает число
  «Кривая» от х
`,
  })
  const { к, адрес } = await сессия(каталог, "главный.flang", await прочитать(каталог, "главный.flang"))
  const чужойАдрес = pathToFileURL(join(каталог, "чужой.flang")).href

  const свой = await к.дождаться(диагностикаДля(адрес))
  const чужой = await к.дождаться(диагностикаДля(чужойАдрес))
  assert.deepEqual(свой.params.diagnostics, [], "в открытом файле ошибок нет — и подчёркивать нечего")
  assert.equal(чужой.params.diagnostics.length > 0, true)
  /* Шестая строка чужого файла — та самая, где «плюс "текст"». */
  assert.equal(чужой.params.diagnostics[0].range.start.line, 5)
  await к.закрыть()
})

test("пропавший модуль показан в том файле, который его просит", async () => {
  const исходник = `модуль «Главный»
  использует «Нет такого» из "нет-такого.flang"

тотальная функция «Ответ»
  возвращает число
  42
`
  const каталог = await песочница({ "главный.flang": исходник })
  const { к, адрес } = await сессия(каталог, "главный.flang", исходник)
  const сообщение = await к.дождаться(диагностикаДля(адрес))
  const беда = сообщение.params.diagnostics.find((д) => д.code === "FLANG_IMPORT_NOT_FOUND")
  assert.notEqual(беда, undefined, JSON.stringify(сообщение.params.diagnostics))
  /* Места у записи импорта в AST нет, поэтому указываем на заголовок модуля:
     тот же файл, тот же блок. Первая строка — «модуль «Главный»». */
  assert.equal(беда.range.start.line, 0)
  await к.закрыть()
})

/* ────────────────────────────── автодополнение ──────────────────────────── */

test("ключевые слова берутся из таблицы лексера, включая вчерашние формы", async () => {
  const исходник = `модуль «Слова»

тотальная функция «Ответ»
  возвращает число
  42
`
  const каталог = await песочница({ "слова.flang": исходник })
  const { к, адрес } = await сессия(каталог, "слова.flang", `${исходник}\nраз`)
  await к.дождаться(диагностикаДля(адрес))

  const ответ = await к.запрос("textDocument/completion", {
    textDocument: { uri: адрес },
    position: { line: 6, character: 3 },
  })
  const слова = new Set(ответ.items.map((э) => э.label))
  /* Формы, прибавившиеся в язык последними. Список здесь не «полный набор
     языка», а именно свежие слова: разойтись с таблицей сервер может только
     на них, и именно на них тест обязан краснеть. */
  for (const слово of ["разложить", "на символы", "процесс", "надзор", "прогон", "стратегия", "семя"]) {
    assert.equal(слова.has(слово), true, `в дополнении нет ключевого слова «${слово}»`)
  }
  /* Английская поверхность языка равноправна — значит, и в дополнении тоже. */
  assert.equal(слова.has("process"), true)
  await к.закрыть()
})

test("дополнение знает имена модуля и имена импортированного модуля", async () => {
  const каталог = await песочница({
    "числа.flang": `модуль «Числа»

тотальная функция «Удвоить»
  принимает значение: число
  возвращает число
  значение умножить на 2
`,
    "главный.flang": `модуль «Главный»
  использует «Числа» из "числа.flang"

запись «Точка»
  х: число

тотальная функция «Учетверить»
  принимает значение: число
  возвращает число
  «Удвоить» от («Удвоить» от значение)
`,
  })
  const текст = await прочитать(каталог, "главный.flang")
  const { к, адрес } = await сессия(каталог, "главный.flang", текст)
  await к.дождаться(диагностикаДля(адрес))
  await дописать(к, адрес, 2, `${текст}\n«`)

  /* Открытая ёлочка на последней строке: так имя и набирают. */
  const ответ = await к.запрос("textDocument/completion", {
    textDocument: { uri: адрес },
    position: { line: 11, character: 1 },
  })
  const поМетке = new Map(ответ.items.map((э) => [э.label, э]))
  assert.equal(поМетке.has("«Учетверить»"), true, "нет своей функции")
  assert.equal(поМетке.has("«Точка»"), true, "нет своей записи")
  assert.equal(поМетке.has("«Удвоить»"), true, "нет функции из импортированного модуля")
  /* Своё и чужое различаются в подписи: иначе непонятно, откуда имя взялось. */
  assert.equal(поМетке.get("«Учетверить»").detail, "функция")
  assert.match(поМетке.get("«Удвоить»").detail, /числа\.flang/u)
  assert.match(поМетке.get("«Учетверить»").documentation, /принимает значение: число → число/u)
  /* Своё предлагается раньше чужого, чужое — раньше ключевых слов. */
  assert.equal(поМетке.get("«Учетверить»").sortText < поМетке.get("«Удвоить»").sortText, true)
  await к.закрыть()
})

test("после точки предлагаются поля записи, и именно той, что у параметра", async () => {
  const исходник = `модуль «Поля»

запись «Точка»
  х: число
  у: число

запись «Отрезок»
  длина: число

тотальная функция «Первая координата»
  принимает точка: «Точка»
  возвращает число
  точка.
`
  const каталог = await песочница({ "поля.flang": исходник })
  /* Открываем заведомо целый файл, чтобы у сервера был разбор, а дополняем уже
     по недописанной строке: именно так это и происходит у человека. */
  const целый = исходник.replace("  точка.\n", "  точка.х\n")
  const { к, адрес } = await сессия(каталог, "поля.flang", целый)
  await к.дождаться(диагностикаДля(адрес))
  await дописать(к, адрес, 2, исходник)

  const ответ = await к.запрос("textDocument/completion", {
    textDocument: { uri: адрес },
    position: { line: 12, character: 8 },
  })
  const метки = ответ.items.map((э) => э.label)
  /* «у» приезжает в ёлочках, а «х» — нет, и это не прихоть: «у» есть в таблице
     ключевых слов (`at`), а голое ключевое слово в позиции имени разберётся не
     как имя. Спрашивает об этом сервер сам лексер, а не свой список. */
  assert.deepEqual(метки.sort(), ["«у»", "х"], `предложено не то: ${JSON.stringify(метки)}`)
  assert.match(ответ.items[0].detail, /поле записи «Точка»/u)
  await к.закрыть()
})

