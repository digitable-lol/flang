/**
 * Страница руководства `man flang` — и то, что она описывает существующее.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Человек, поставивший язык из brew, набирает `man flang` раньше, чем идёт
 * читать README в интернете. Страницы не было вовсе; теперь она есть, и у неё
 * ровно та беда, что у всякого документа: она может пережить то, о чём
 * рассказывает, и остаться зелёной. Тест на «файл на месте» этого не заметит.
 *
 * Поэтому проверяется не наличие, а три соответствия, каждое из которых
 * способно тихо разойтись:
 *
 *   1. СТРАНИЦА НАБИРАЕТСЯ. Битый troff `man` показывает молча, мусором. Если
 *      groff в системе есть, страница обязана набраться без предупреждений.
 *
 *   2. КОМАНДЫ ТЕ ЖЕ, ЧТО У БИНАРНИКА. Синопсис сверяется со справкой, которую
 *      печатает сам бинарник (`FLANG_HELP` в flang_repl.c). Разойдись они —
 *      страница обещала бы команду, которой нет, или молчала бы о нужной.
 *
 *   3. КОДЫ БЕД СУЩЕСТВУЮТ. Каждый FLANG_*, названный в разделе «ДИАГНОСТИКА»,
 *      обязан встречаться в исходниках компилятора или рантайма. Выдуманный код
 *      в документации хуже отсутствующего: по нему ищут и не находят.
 *
 * И версия: она живёт в четырёх местах сразу — package.json, формула Homebrew,
 * `FLANG_VERSION` в flang_repl.c, заголовок страницы, — потому что бинарник
 * собирается без Node и без brew и прочитать чужой файл ему неоткуда. Все
 * четыре сверяются здесь.
 *
 * То, что команды РАБОТАЮТ, проверяется не тут, а на настоящем flang₁ в
 * flang/test/self-bootstrap.test.mjs: здесь нет бинарника, а сверять документ с
 * документом — половина дела.
 *
 * Запуск: node --test flang/test/manpage.test.mjs
 */
import assert from "node:assert/strict"
import { execFileSync, spawnSync } from "node:child_process"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const прочитать = (путь) => readFileSync(new URL(путь, new URL("../../", import.meta.url)), "utf8")

const страница = прочитать("packaging/flang.1")
const оболочка = прочитать("flang/src/emit/c/flang_repl.c")
const формула = прочитать("packaging/homebrew/flang.rb")
const пакет = JSON.parse(прочитать("package.json"))

test("страница руководства набирается troff без предупреждений", (t) => {
  const troff = ["groff", "nroff"].find(
    (имя) => spawnSync("which", [имя], { stdio: "ignore" }).status === 0,
  )
  if (troff === undefined) {
    t.skip("ни groff, ни nroff в PATH — набрать страницу нечем")
    return
  }
  const путь = new URL("../../packaging/flang.1", import.meta.url)
  /* `-z` набирает и НЕ печатает: нужен только поток предупреждений. `-ww` —
     самый подробный уровень, потому что молчание groff по умолчанию скрывает
     ровно то, из-за чего страница выглядит мусором. */
  const тихо = spawnSync(troff, ["-K", "utf8", "-man", "-Tutf8", "-ww", "-z", fileURLToPath(путь)], {
    encoding: "utf8",
  })
  assert.equal(тихо.status, 0, `troff отказался: ${тихо.stderr}`)
  assert.equal(тихо.stderr.trim(), "", `troff ругается на страницу:\n${тихо.stderr}`)

  /* groff размечает жирное и подчёркнутое управляющими последовательностями
     терминала — их снимает `man`, а нам они мешают искать слова. */
  const набрано = execFileSync(troff, ["-K", "utf8", "-man", "-Tutf8", fileURLToPath(путь)], {
    encoding: "utf8",
  }).replace(/\[[0-9;]*m/gu, "")
  assert.match(набрано, /FLANG\(1\)/u, "в набранной странице нет заголовка FLANG(1)")
  /* Разделы, без которых страница не страница, — и в том числе те, что просил
     заказчик этой работы: диагностика, файлы, примеры, см. также. */
  for (const раздел of ["ИМЯ", "СИНОПСИС", "ОПИСАНИЕ", "КОМАНДЫ", "ДИАГНОСТИКА", "ОКРУЖЕНИЕ", "ФАЙЛЫ", "ПРИМЕРЫ", "СМ. ТАКЖЕ"]) {
    assert.ok(набрано.includes(раздел), `в странице нет раздела «${раздел}»`)
  }
})

test("синопсис страницы и справка бинарника называют одни и те же команды", () => {
  /* Ищутся сами слова команд, а не «flang <слово>»: в troff между ними стоят
     макросы разметки, и требовать соседства значило бы сверять оформление, а
     не список. В синопсисе и в справке других таких слов нет. */
  /* Список слов расширен до ВСЕХ команд бинарника. Прежде сверялись пять
     (`--json`, `--version`, `--help`, `check`, `repl`), и три остальные —
     `test`, `run`, `emit` — могли разойтись со страницей молча: справка
     называла бы команду, о которой страница не знает, и наоборот. */
  const команды = (текст) =>
    new Set([...текст.replace(/\\-/gu, "-").matchAll(/(?<![\w-])(--json|--version|--help|check|repl|test|run|emit)(?![\w-])/gu)].map((н) => н[1]))
  const синопсис = страница.slice(страница.indexOf(".SH СИНОПСИС"), страница.indexOf(".SH ОПИСАНИЕ"))
  assert.ok(синопсис.length > 0, "в странице нет раздела «СИНОПСИС»")
  /* Справка бинарника лежит строковым литералом: берём её от объявления до
     последней строки, чтобы не поймать соседний текст файла. */
  const справка = оболочка.slice(местоОт("static const char FLANG_HELP[] ="), местоДо("Подробности: man flang"))
  const вСправке = команды(справка)
  assert.ok(вСправке.size > 0, "справка бинарника не найдена в flang_repl.c")
  assert.deepEqual([...команды(синопсис)].sort(), [...вСправке].sort(), "страница и справка расходятся в списке команд")
})

function местоОт(маркер) {
  const место = оболочка.indexOf(маркер)
  assert.notEqual(место, -1, `в flang_repl.c нет «${маркер}»`)
  return место
}

function местоДо(маркер) {
  const место = оболочка.indexOf(маркер)
  assert.notEqual(место, -1, `в flang_repl.c нет «${маркер}»`)
  return место + маркер.length
}

test("каждый код беды со страницы существует в исходниках", () => {
  const названные = [...new Set([...страница.matchAll(/\bFLANG_[A-Z_]+\b/gu)].map((найдено) => найдено[0]))]
  /* Служебные имена страницы — переменные окружения, а не коды бед. */
  const коды = названные.filter((имя) => !["FLANG_CC", "FLANG_INCLUDE_DIR", "FLANG_LIB_DIR"].includes(имя))
  assert.ok(коды.length > 10, `на странице всего ${коды.length} кодов — раздел «ДИАГНОСТИКА» опустел`)

  /* Улика — сами исходники: компилятор на flang, рантайм на C и человеческий
     вход. Код, которого там нет, никто и никогда не напечатает. */
  const где = [
    ...globSync("flang/self/**/*.flang", { cwd: корень }),
    "flang/src/emit/c/flang_runtime.c",
    "flang/src/emit/c/flang_runtime.h",
    "flang/src/emit/c/flang_repl.c",
    "flang/src/emit/c/flang_cli.c",
  ]
  const исходники = где.map((путь) => readFileSync(new URL(путь, new URL("../../", import.meta.url)), "utf8")).join("\n")
  for (const код of коды) {
    assert.ok(исходники.includes(код), `страница обещает код «${код}», которого нет ни в одном исходнике`)
  }
})

test("версия одна на все четыре места, где она записана", () => {
  const версия = пакет.version
  assert.match(версия, /^\d+\.\d+\.\d+$/u)
  /* Бинарник собирается без Node и без brew: прочитать package.json ему
     неоткуда, поэтому версия у него своя строкой — и обязана совпадать. */
  assert.ok(
    оболочка.includes(`#define FLANG_VERSION "${версия}"`),
    `flang_repl.c называет не ту версию: package.json обещает ${версия}`,
  )
  assert.ok(формула.includes(`version "${версия}"`), "формула Homebrew обещает другую версию")
  assert.ok(
    страница.includes(`"flang ${версия}"`),
    `в заголовке .TH страницы не ${версия}: человек прочтёт версию в подвале man`,
  )
})

test("страница попадает в релиз и ставится формулой под тем же именем", () => {
  /* Формула ставит страницу из корня распакованного архива; кладёт её туда
     скрипт сборки релиза. Имя одно на две упаковки, и разойтись оно может
     молча: brew упадёт только на настоящем релизе, а его собирают редко. */
  const сборка = прочитать("scripts/build-release-c.mjs")
  assert.ok(сборка.includes('join(каталог, "flang.1")'), "скрипт релиза перестал класть flang.1 в архив")
  assert.ok(сборка.includes('join(корень, "packaging/flang.1")'), "скрипт релиза берёт страницу не из packaging/")
  assert.ok(формула.includes('man1.install "flang.1"'), "формула Homebrew перестала ставить страницу")
})
