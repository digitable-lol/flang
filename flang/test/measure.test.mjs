test("структурное убывание доказывается без меры и БЕЗ сторожа", () => {
  /* Порядок «структура → постоянный шаг → объявленная мера» существует ради
     этого: объявить меру там, где доказывает структура, не значит начать
     платить за сторожа на каждом витке. */
  const длина =
    "модуль «М»\n\nтотальная функция «Длина»\n  принимает сп: список числа\n  возвращает число\n" +
    "  убывает длина сп\n  разбор сп\n    случай пусто\n      то 0\n" +
    "    случай голова и хвост\n      то 1 плюс «Длина» от хвост\n"
  const { тотальность } = проверить(длина)
  assert.equal(тотальность.total.has("Длина"), true)
  assert.equal(тотальность.descents.length, 0, "структура доказала — сторожить нечего")

  const { понижено, среда } = собрать(длина)
  assert.deepEqual(понижено.functions.map((узел) => узел.name), ["Длина"])
  assert.equal(среда.call("Длина", { сп: [1, 2, 3] }), 3)
})

test("постоянный шаг доказывается прежним числовым сторожем", () => {
  const счёт =
    "модуль «М»\n\nтотальная функция «До нуля»\n  принимает н: число\n  возвращает число\n" +
    "  если н не больше 0\n    то 0\n    иначе «До нуля» от (н минус 1)\n"
  const { тотальность } = проверить(счёт)
  assert.equal(тотальность.guards.length, 1, "прежний сторож на месте")
  assert.equal(тотальность.descents.length, 0, "новый сторож не вмешивается")
  const { понижено } = собрать(счёт)
  assert.ok(понижено.functions.some((узел) => узел.name === "мера убывает"))
  assert.ok(!понижено.functions.some((узел) => узел.name.startsWith("объявленная мера")))
})

test("программа без меры даёт побайтово прежние AST и понижение", () => {
  /* Самое важное утверждение файла. Новая форма не имеет права сдвинуть ни
     байта там, где ею не пользуются: на побайтовом совпадении стоит всё
     самоприменение. */
  const обычная =
    "модуль «М»\n\nтотальная функция «Длина»\n  принимает сп: список числа\n  возвращает число\n" +
    "  разбор сп\n    случай пусто\n      то 0\n" +
    "    случай голова и хвост\n      то 1 плюс «Длина» от хвост\n"
  const разобрано = parse(обычная, "м.flang")
  assert.equal(Object.hasOwn(разобрано.functions[0], "decreases"), false, "поля меры быть не должно")

  const отмечено = markMeasureGuards(разобрано)
  assert.equal(отмечено, разобрано, "отметка обязана вернуть ТОТ ЖЕ объект")
  assert.equal(Object.hasOwn(отмечено, "descents"), false)
  assert.equal(Object.hasOwn(отмечено, "measures"), false)
})

