/** Код и текст отказа при запуске — или `null`, если отказа не было. */
function отказ(среда, имя, аргументы) {
  try {
    среда.call(имя, аргументы)
    return null
  } catch (беда) {
    return { code: беда.code, message: String(беда.message) }
  }
}

test("дробная мера отвергается на запуске: цепочка (φ, 1) не кончается", () => {
  /* Ровно тот вход, из-за которого Евклид и был отвергнут раньше: остатки
     пары (φ, 1) — 0.618, 0.382, 0.236 … — убывают строго, ограничены снизу и
     не кончаются никогда. Целость меры это ловит на первом же витке. */
  const { среда } = собрать(ЕВКЛИД)
  const беда = отказ(среда, "НОД", { а: 1.618033988749895, б: 1 })
  assert.notEqual(беда, null, "ожидался отказ")
  assert.equal(беда.code, "FLANG_MEASURE")
  assert.match(беда.message, /перестала быть целой/)
})

test("мера, ушедшая ниже нуля, отвергается и подсказывает «плюс 1»", () => {
  const безЕдиницы =
    "модуль «Поиск»\n\nтотальная функция «Сужать»\n  принимает низ: число, верх: число\n" +
    "  возвращает число\n  убывает верх минус низ\n" +
    "  если низ больше верх\n    то 0\n    иначе «Сужать» от (низ плюс 2) и верх\n"
  const { среда } = собрать(безЕдиницы)
  const беда = отказ(среда, "Сужать", { низ: 1, верх: 2 })
  assert.notEqual(беда, null, "ожидался отказ")
  assert.equal(беда.code, "FLANG_MEASURE")
  assert.match(беда.message, /ушла ниже нуля/)
  assert.match(беда.message, /плюс 1/)
})

test("мера, которая не убыла, отвергается", () => {
  const стоит =
    "модуль «Стоит»\n\nтотальная функция «Топтаться»\n  принимает н: число\n" +
    "  возвращает число\n  убывает н\n" +
    "  если н не больше 0\n    то 0\n    иначе «Топтаться» от н\n"
  const { среда } = собрать(стоит)
  const беда = отказ(среда, "Топтаться", { н: 3 })
  assert.notEqual(беда, null, "ожидался отказ")
  assert.equal(беда.code, "FLANG_MEASURE")
  assert.match(беда.message, /не убыла/)
})

test("на исправном витке сторож не зовётся", () => {
  /* Быстрая ветвь — не украшение: сторож стоит в ветви, куда попадают только
     тогда, когда мера не убыла. Считаем вызовы сторожа по имени: их ноль. */
  const { понижено, среда } = собрать(ЕВКЛИД)
  const сторож = понижено.functions.find((узел) => узел.name.startsWith("объявленная мера убывает"))
  assert.notEqual(сторож, undefined, "сторож обязан быть напечатан")
  assert.equal(сторож.total, true)
  assert.equal(среда.call("НОД", { а: 1071, б: 462 }), 21)
})

