/**
 * Объявленная мера: `убывает <выражение>`.
 *
 * Проверяется здесь ровно то, ради чего мера заведена, и обе стороны каждого
 * утверждения. Доказуемое обязано доказываться — иначе форма бесполезна.
 * Недоказуемое обязано отвергаться — иначе гарантия `тотальная` сломана.
 *
 * Отдельная забота — НЕИЗМЕННОСТЬ ПРЕЖНЕГО. Программа без `убывает` обязана
 * пройти анализ и понижение ровно так же, как до появления формы: тот же
 * вердикт, те же сторожа, тот же AST. Без этой проверки новая форма могла бы
 * молча сдвинуть байты у всего корпуса, а побайтовое совпадение
 * самоприменения — единственное, чем оно вообще держится.
 *
 * Запуск: node --test flang/test/measure.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { test } from "node:test"
import { fileURLToPath } from "node:url"

import { defunctionalize } from "../src/defunc.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality, markMeasureGuards } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/** Разбор, типы и завершаемость одним вызовом — как их видит оболочка. */
function проверить(исходник) {
  const программа = parse(исходник, "мера.flang")
  return { программа, типы: checkTypes(программа), тотальность: checkTotality(программа) }
}

/** Готовая к запуску программа: с отметками меры и понижённая. */
function собрать(исходник) {
  const { программа } = проверить(исходник)
  const понижено = defunctionalize(markMeasureGuards(программа))
  return { понижено, среда: createRuntime(понижено, { maxSteps: 5_000_000 }) }
}

const ЕВКЛИД =
  "модуль «Евклид»\n\nтотальная функция «НОД»\n  принимает а: число, б: число\n" +
  "  возвращает число\n  убывает б\n" +
  "  если б равен 0\n    то а\n    иначе «НОД» от б и (а остаток от б)\n"

