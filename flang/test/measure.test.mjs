test("примеры flang/examples/measure сходятся все до одного", () => {
  let всего = 0
  for (const файл of ["euclid", "binary-search"]) {
    const путь = `${корень}flang/examples/measure/${файл}.flang`
    const исходник = readFileSync(путь, "utf8")
    const { типы, тотальность } = проверить(исходник)
    assert.deepEqual(типы.diagnostics, [], `${файл}: типы`)
    assert.deepEqual(тотальность.diagnostics, [], `${файл}: завершаемость`)
    const { среда } = собрать(исходник)
    for (const функция of parse(исходник, путь).functions) {
      for (const пример of функция.examples ?? []) {
        всего += 1
        assert.deepEqual(
          среда.call(функция.name, пример.args),
          пример.expected,
          `${файл}: «${функция.name}», пример «${пример.name}»`,
        )
      }
    }
  }
  assert.ok(всего >= 10, `примеров всего ${всего}`)
})
