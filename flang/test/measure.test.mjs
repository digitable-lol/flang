test("Евклид доказывается объявленной мерой", () => {
  const { типы, тотальность } = проверить(ЕВКЛИД)
  assert.deepEqual(типы.diagnostics, [])
  assert.deepEqual(тотальность.diagnostics, [])
  assert.equal(тотальность.ok, true)
  assert.deepEqual([...тотальность.total], ["НОД"])
  assert.equal(тотальность.descents.length, 1)
})

test("Евклид считает наибольший общий делитель", () => {
  const { среда } = собрать(ЕВКЛИД)
  for (const [а, б, ждём] of [[1071, 462, 21], [48, 18, 6], [97, 89, 1], [7, 0, 7], [18, 48, 6], [270, 192, 6]]) {
    assert.equal(среда.call("НОД", { а, б }), ждём, `НОД(${а}, ${б})`)
  }
})

test("Евклид без меры по-прежнему отвергается", () => {
  /* Мера — это то, что говорит АВТОР. Без неё анализ видит ровно то же, что
     видел всегда: «а остаток от б» не часть «б» и не постоянный шаг. */
  const { тотальность } = проверить(ЕВКЛИД.replace("  убывает б\n", ""))
  assert.equal(тотальность.ok, false)
  assert.deepEqual([...new Set(тотальность.diagnostics.map((беда) => беда.code))], ["FLANG_NOT_TOTAL"])
  assert.equal(тотальность.total.has("НОД"), false)
})

test("двоичный поиск доказывается без списка-топлива", () => {
  const исходник = readFileSync(`${корень}flang/examples/measure/binary-search.flang`, "utf8")
  const { типы, тотальность } = проверить(исходник)
  assert.deepEqual(типы.diagnostics, [])
  assert.deepEqual(тотальность.diagnostics, [])
  /* «Элемент по номеру» из этого списка ИСЧЕЗ, и это не потеря функции, а
     снятие обхода: середина берётся встроенной формой `элемент N в СПИСОК` за
     постоянное время, и помощник, обходивший список звено за звеном, стал не
     нужен. Список закреплён целиком именно затем, чтобы такой помощник не
     завёлся обратно молча. */
  assert.deepEqual([...тотальность.total].sort(), ["Двоичный поиск", "Поиск в диапазоне"])

  /* Топлива в подписи нет — это и есть то, что изменилось. Раньше «Поиск в
     диапазоне» возил список только ради доказательства. */
  const поиск = тотальность.total.has("Поиск в диапазоне")
  assert.equal(поиск, true)
  const функция = parse(исходник, "b.flang").functions.find((узел) => узел.name === "Поиск в диапазоне")
  assert.deepEqual(функция.params.map((параметр) => параметр.name), ["элементы", "цель", "низ", "верх"])
})

test("двоичный поиск по мере стоит логарифм, а не линию", (t) => {
  /*
   * УЛИКА. Середину брал свой помощник «Элемент по номеру», обходивший список
   * звено за звеном: log₂n взятий по цене n каждое дают линию — дороже, чем
   * просто пройти список подряд, то есть от «двоичного» не остаётся ничего.
   *
   * Мерятся ВИТКИ, а не секунды: цена вычисления — наименьший бюджет шагов,
   * при котором оно доходит. Число целое, от загрузки машины не зависит; по
   * секундам на одной точке класс сложности не отличить вообще никак.
   *
   * Витки на 14 августа 2026:
   *      n |  обходом |  формой
   *    500 |   77 119 |   1068
   *   8000 | 1 825 595 |  1572
   * Показатель k = log(цена₂/цена₁)/log(16): был 1,141 — линия, стал 0,139 —
   * логарифм. Порог 0,5 лежит между ними и не близок ни к одному.
   */
  const исходник = readFileSync(`${корень}flang/examples/measure/binary-search.flang`, "utf8")
  const { понижено } = собрать(исходник)
  const цена = (n) => {
    const элементы = Array.from({ length: n }, (_, к) => к + 1)
    const доходит = (предел) => {
      try {
        return createRuntime(понижено, { maxSteps: предел, maxDepth: 100_000 })
          .call("Двоичный поиск", { элементы, цель: n }) === n - 1
      } catch {
        return false
      }
    }
    let низ = 1
    let верх = 1
    while (!доходит(верх)) {
      низ = верх + 1
      верх *= 2
      assert.ok(верх < 1e9, `поиск не доходит ни при каком бюджете шагов на n=${n}`)
    }
    while (низ < верх) {
      const середина = Math.floor((низ + верх) / 2)
      if (доходит(середина)) верх = середина
      else низ = середина + 1
    }
    return низ
  }
  const малое = цена(500)
  const большое = цена(8000)
  const k = Math.log(большое / малое) / Math.log(16)
  t.diagnostic(`двоичный поиск по мере: ${малое} витков на 500, ${большое} на 8000 — показатель ${k.toFixed(3)}`)
  assert.ok(
    k < 0.5,
    `поиск подорожал с ${малое} до ${большое} при росте списка в 16 раз (показатель ${k.toFixed(3)}): ` +
      "середина снова берётся обходом, и двоичный поиск перестал быть двоичным",
  )
})

test("двоичный поиск находит и не находит там, где должен", () => {
  const { среда } = собрать(readFileSync(`${корень}flang/examples/measure/binary-search.flang`, "utf8"))
  const элементы = [-1, 0, 3, 5, 9, 12]
  for (const [цель, ждём] of [[9, 4], [-1, 0], [12, 5], [3, 2], [2, -1], [100, -1]]) {
    assert.equal(среда.call("Двоичный поиск", { элементы, цель }), ждём, `поиск ${цель}`)
  }
  assert.equal(среда.call("Двоичный поиск", { элементы: [], цель: 5 }), -1)
  assert.equal(среда.call("Двоичный поиск", { элементы: [5], цель: 5 }), 0)
})

test("счёт ВВЕРХ доказывается мерой, а без неё нет", () => {
  /* «Счёт вверх» стоял в списке недостач рядом с Евклидом: `н плюс 1` растёт,
     верхней границы у меры нет. Объявленная мера снимает и это — убывает не
     сам счётчик, а расстояние до предела. */
  const вверх =
    "модуль «Счёт»\n\nтотальная функция «Вверх»\n  принимает н: число, предел: число\n" +
    "  возвращает число\n  убывает предел минус н\n" +
    "  если н не меньше предел\n    то н\n    иначе «Вверх» от (н плюс 1) и предел\n"
  const { тотальность } = проверить(вверх)
  assert.deepEqual(тотальность.diagnostics, [])
  assert.equal(тотальность.total.has("Вверх"), true)

  const без = проверить(вверх.replace("  убывает предел минус н\n", ""))
  assert.equal(без.тотальность.ok, false)

  const { среда } = собрать(вверх)
  assert.equal(среда.call("Вверх", { н: 0, предел: 10 }), 10)
})

