/**
 * Список недостач языка обязан быть правдой.
 *
 * В `flang/examples/leetcode/index.json` есть раздел «чего не хватает языку» —
 * список того, что язык не умеет, с объяснением каждого пункта. Он написан
 * честно и ради честности: по нему судят, на что язык годится.
 *
 * 6 августа 2026 года выяснилось, что ВОСЕМЬ ЗАПИСЕЙ ИЗ ПЯТНАДЦАТИ — неправда.
 * Модульность работает, структурное сравнение в примерах работает, сравнение
 * строк давно сведено между слоями, встроенные формы «символ» и «пусто»
 * работают, списочная форма «соединить» работает, вызов функции без аргументов
 * работает, псевдоним типа работает. Часть была правдой когда-то и осталась в
 * списке после починки; часть описывала расхождение слоёв, которое свели.
 *
 * Заметить это было нечем: недостача — единственное утверждение о языке,
 * которое НЕ ЛОМАЕТСЯ, когда становится ложным. Тест, проверяющий, что чего-то
 * нет, никто не пишет; тест, проверяющий, что что-то есть, на такую запись не
 * посмотрит. Список наполовину из выдуманного хуже отсутствующего: он и есть то
 * самое «проверено на словах», против чего написан весь проект.
 *
 * Отсюда этот файл. У каждой оставшейся недостачи здесь стоит ПРОГРАММА,
 * которая её показывает, и тест требует, чтобы программа по-прежнему не
 * работала. Починили недостачу — тест краснеет и заставляет убрать запись из
 * списка. Это единственный известный способ не дать честному списку стать
 * враньём.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const КАТАЛОГ = JSON.parse(readFileSync(new URL("../examples/leetcode/index.json", import.meta.url), "utf8"))
const НЕДОСТАЧИ = new Set((КАТАЛОГ["чего не хватает языку"] ?? []).map((запись) => запись["чего"]))

/** Разбор и проверка: `null`, если программа не разобралась вовсе. */
function проверить(исходник) {
  try {
    const программа = parse(исходник, "проба.flang")
    return { программа, беды: (checkTypes(программа).diagnostics ?? []).map((б) => б.code) }
  } catch (беда) {
    return { программа: null, беды: [беда?.code ?? "FLANG_PARSE"] }
  }
}

/**
 * Недостачи, каждая со своей программой-уликой.
 *
 * `показ` обязан вернуть true, ПОКА недостача есть. Как только язык научится —
 * тест покраснеет на этой строке, и это правильное поведение: список надо
 * поправить, а не тест.
 */
const УЛИКИ = [
  {
    чего: "логические операции инфиксной записью",
    показ: () => {
      /* Речь именно об ИНФИКСНОЙ записи: как функции эти операции есть в
         flang/stdlib/logic.flang и там же объяснено, почему слово «и» занять
         нельзя. Улика проверяет синтаксис, а не наличие операций. */
      for (const выражение of ["первый и второй", "первый или второй", "не первый"]) {
        const итог = проверить(
          `модуль «Логика»\n\nтотальная функция «Проба»\n  принимает первый: признак, второй: признак\n` +
            `  возвращает признак\n  ${выражение}\n`,
        )
        if (итог.программа !== null && итог.беды.length === 0) return false
      }
      return true
    },
  },
  {
    чего: "вывод убывания по мере с непостоянным шагом",
    показ: () => {
      /*
       * Запись переписана 9 августа 2026: прежняя стала неправдой. Евклид и
       * двоичный поиск ПИШУТСЯ — мерой, которую называет автор. Осталось не
       * «нельзя написать», а «нельзя вывести»: убывание непостоянного шага
       * язык не выводит сам, его объявляют строкой `убывает <выражение>`.
       *
       * Отсюда улика тройная, и все три части нужны.
       *
       * Первая: постоянный шаг по-прежнему выводится сам, обоих видов —
       * литералом (`н минус 1`) и параметром (`н минус ш`). Это то, что
       * недостачей НЕ является, и не проверять его значило бы хранить
       * недостачу шире, чем она есть.
       *
       * Вторая — сама недостача: БЕЗ объявленной меры остаток (Евклид),
       * половина отрезка (двоичный поиск) и тающий шаг Зенона отвергаются.
       * Появится вывод — эта половина станет ложной, тест покраснеет и
       * потребует переписать запись снова.
       *
       * Третья: С объявленной мерой первые два доказываются и считают. Без
       * неё запись пережила бы собственную починку и снова стала бы враньём —
       * ровно тем, против чего написан весь этот файл.
       */
      const доказуемо = (исходник, имя) => {
        const { программа } = проверить(исходник)
        return программа !== null && checkTotality(программа).total.has(имя)
      }
      const счёт =
        `модуль «Счёт»\n\nтотальная функция «До нуля»\n  принимает н: число\n  возвращает число\n` +
        `  если н не больше 0\n    то 0\n    иначе «До нуля» от (н минус 1)\n`
      const шагом =
        `модуль «Счёт»\n\nтотальная функция «Шагами»\n  принимает н: число, ш: число\n  возвращает число\n` +
        `  если ш не больше 0\n    то 0\n    иначе\n      если н не больше 0\n        то 0\n` +
        `        иначе «Шагами» от (н минус ш) и ш\n`
      if (!доказуемо(счёт, "До нуля") || !доказуемо(шагом, "Шагами")) return false

      const евклид =
        `модуль «Евклид»\n\nтотальная функция «НОД»\n  принимает а: число, б: число\n  возвращает число\n` +
        `  если б не больше 0\n    то а\n    иначе «НОД» от б и (а остаток от б)\n`
      const пополам =
        `модуль «Поиск»\n\nтотальная функция «Половинить»\n  принимает низ: число, верх: число\n  возвращает число\n` +
        `  если верх не больше низ\n    то низ\n    иначе «Половинить» от ((низ плюс верх) делить на 2) и верх\n`
      const зенон =
        `модуль «Зенон»\n\nтотальная функция «Шагами»\n  принимает н: число, ш: число\n  возвращает число\n` +
        `  если ш не больше 0\n    то 0\n    иначе\n      если н не больше 0\n        то 0\n` +
        `        иначе «Шагами» от (н минус ш) и (ш делить на 2)\n`
      for (const исходник of [евклид, пополам, зенон]) {
        const { программа } = проверить(исходник)
        if (программа === null) continue
        if (checkTotality(программа).diagnostics.length === 0) return false
      }

      /* Третья часть: с объявленной мерой то же самое доказывается и считает.
         Мера у Евклида — «б», у деления пополам — ширина отрезка; «плюс 1»
         там не украшение, а условие неотрицательности меры. */
      const сМерой =
        `модуль «Евклид»\n\nтотальная функция «НОД»\n  принимает а: число, б: число\n  возвращает число\n` +
        `  убывает б\n  если б равен 0\n    то а\n    иначе «НОД» от б и (а остаток от б)\n`
      if (!доказуемо(сМерой, "НОД")) return false
      const { программа: сНОД } = проверить(сМерой)
      if (evaluate(сНОД, "НОД", { а: 1071, б: 462 }) !== 21) return false

      const поискМерой =
        `модуль «Поиск»\n\nтотальная функция «Сузить»\n  принимает низ: число, верх: число\n  возвращает число\n` +
        `  убывает верх минус низ плюс 1\n  если низ больше верх\n    то низ\n` +
        `    иначе «Сузить» от (((низ плюс верх) минус ((низ плюс верх) остаток от 2)) делить на 2 плюс 1) и верх\n`
      if (!доказуемо(поискМерой, "Сузить")) return false
      return true
    },
  },
  {
    чего: "замена элемента массива по номеру",
    показ: () => {
      /*
       * Улика тройная, и первые две половины проверяют СДЕЛАННОЕ, а не
       * оставшееся: иначе запись пережила бы починку молча.
       *
       * Первая: чтение по номеру работает — форма `элемент N в СПИСОК`.
       * Вторая: доказательство завершения от неё не ослабло — проход по номеру
       * вниз доказывается числовой мерой, а элемент считается частью списка,
       * поэтому рекурсия вглубь по нему доказывается тоже.
       * Третья: ЗАПИСИ по номеру нет ни в каком написании — и вот это и есть
       * оставшаяся недостача.
       *
       * Четвёртая появилась 9 августа 2026, когда закрылась соседняя запись
       * «ассоциативный массив с быстрым доступом». Быстрый словарь построен
       * ДЕРЕВОМ (`flang/stdlib/tree.flang`), а не хеш-таблицей, и причина
       * ровно эта: вставка в корзинный массив без замены по номеру стоила бы
       * копии всего массива. Значит доступ за ПОСТОЯННОЕ время висит на этой
       * записи, и проверять надо обе стороны — что логарифмический словарь
       * есть и что постоянного по-прежнему нет.
       */
      const чтение = проверить(
        "модуль «Индекс»\n\nтотальная функция «Проба»\n  принимает элементы: список числа, н: число\n" +
          "  возвращает число\n  элемент н в элементы\n",
      )
      if (чтение.программа === null || чтение.беды.length > 0) return false
      if (evaluate(чтение.программа, "Проба", { элементы: [10, 20, 30], н: 2 }) !== 20) return false

      const вниз = проверить(
        "модуль «Сумма»\n\nтотальная функция «Сумма до»\n  принимает элементы: список числа, н: число\n" +
          "  возвращает число\n  если н не больше 0\n    то 0\n" +
          "    иначе (элемент н в элементы) плюс «Сумма до» от элементы и (н минус 1)\n",
      )
      if (вниз.программа === null || вниз.беды.length > 0) return false
      if (!checkTotality(вниз.программа).total.has("Сумма до")) return false

      for (const тело of [
        "заменить элемент 1 в элементы на 5",
        "элемент 1 в элементы равно 5",
        "положить 5 в элементы по 1",
      ]) {
        const итог = проверить(
          "модуль «Замена»\n\nтотальная функция «Проба»\n  принимает элементы: список числа\n" +
            `  возвращает список числа\n  ${тело}\n`,
        )
        if (итог.программа !== null && итог.беды.length === 0) return false
      }

      /* Логарифмический словарь есть — и это часть недостачи, а не её
         опровержение: он потому и дерево, что замены по номеру нет. */
      const дерево = проверить(readFileSync(new URL("../stdlib/tree.flang", import.meta.url), "utf8"))
      if (дерево.программа === null || дерево.беды.length > 0) return false
      if (!checkTotality(дерево.программа).total.has("Найти в дереве")) return false
      return true
    },
  },
  {
    чего: "обработка ошибок",
    показ: () => {
      /*
       * Улика тройная, и все три половины нужны — иначе она подтверждала бы
       * недостачу и в том случае, если бы отказ не обрабатывался НИКАК, и в
       * том, если бы обрабатывался уже везде.
       *
       * Первая: у «к числу» отказ СТАЛ значением — форма `к числу или беда`
       * возвращает «Не разобрано» вместо конца вычисления. Не проверять это
       * значило бы снова хранить недостачу, которой нет.
       *
       * Вторая: сама «к числу» по-прежнему прекращает вычисление. Перехвата в
       * языке нет и не будет: он был бы прыжком по стеку, а в C, куда язык
       * печатается, прыгать нечем.
       *
       * Третья: у ОСТАЛЬНЫХ встроенных форм отказ так и остался концом
       * вычисления — «голова» от пустого списка ничего не возвращает. Их
       * пригодность выразима заранее, и это ровно то, что осталось недостачей:
       * проверять обязан автор, а не язык.
       */
      const разбор =
        "модуль «Отказ»\n\nтотальная функция «Проба»\n  принимает текст: строка\n  возвращает строка\n" +
        "  разбор (к числу или беда текст)\n" +
        "    случай вариант «Разобрано» с значение как н\n      то \"\"\n" +
        "    случай вариант «Не разобрано» с код как к и сообщение как весть\n      то весть\n"
      const значением = проверить(разбор)
      if (значением.программа === null || значением.беды.length > 0) return false
      const весть = evaluate(значением.программа, "Проба", { текст: "не число" })
      if (весть !== '«к числу»: строка "не число" не является числом') return false

      const прекращает = (исходник, аргументы) => {
        const { программа } = проверить(исходник)
        if (программа === null) return true
        try {
          evaluate(программа, "Проба", аргументы)
          return false
        } catch {
          return true
        }
      }
      const прежняя =
        "модуль «Отказ»\n\nтотальная функция «Проба»\n  принимает текст: строка\n  возвращает число\n  к числу текст\n"
      const пустойСписок =
        "модуль «Отказ»\n\nтотальная функция «Проба»\n  принимает элементы: список числа\n  возвращает число\n  голова элементы\n"
      return прекращает(прежняя, { текст: "не число" }) && прекращает(пустойСписок, { элементы: [] })
    },
  },
]

test("каждая недостача из каталога подтверждается программой", () => {
  for (const улика of УЛИКИ) {
    assert.ok(
      НЕДОСТАЧИ.has(улика.чего),
      `в каталоге нет недостачи «${улика.чего}», а улика на неё есть — уберите улику или верните запись`,
    )
    assert.ok(
      улика.показ(),
      `недостача «${улика.чего}» БОЛЬШЕ НЕ СУЩЕСТВУЕТ: программа-улика работает. ` +
        `Уберите запись из «чего не хватает языку» в flang/examples/leetcode/index.json`,
    )
  }
})

test("у каждой недостачи каталога есть улика, кроме назначенных без неё", () => {
  /* Одна запись улики иметь не может: она про сам список. Остальные обязаны —
     иначе недостачу снова будет нечем проверить, и всё повторится. */
  const безУлики = new Set(["проверка самого этого списка"])
  const сУликой = new Set(УЛИКИ.map((улика) => улика.чего))
  const беспризорные = [...НЕДОСТАЧИ].filter((чего) => !сУликой.has(чего) && !безУлики.has(чего))
  assert.deepEqual(
    беспризорные,
    [],
    `эти недостачи никем не проверяются и могут тихо стать неправдой: ${беспризорные.join(", ")}`,
  )
})
