/** Разбор и проверка: `null`, если программа не разобралась вовсе. */
function проверить(исходник) {
  try {
    const программа = parse(исходник, "проба.flang")
    return { программа, беды: (checkTypes(программа).diagnostics ?? []).map((б) => б.code) }
  } catch (беда) {
    return { программа: null, беды: [беда?.code ?? "FLANG_PARSE"] }
  }
}

