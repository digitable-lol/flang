/**
 * Список недостач языка обязан быть правдой.
 *
 * В `flang/examples/leetcode/index.json` есть раздел «чего не хватает языку» —
 * список того, что язык не умеет, с объяснением каждого пункта. Он написан
 * честно и ради честности: по нему судят, на что язык годится.
 *
 * 6 августа 2026 года выяснилось, что ВОСЕМЬ ЗАПИСЕЙ ИЗ ПЯТНАДЦАТИ — неправда.
 * Модульность работает, структурное сравнение в примерах работает, сравнение
 * строк давно сведено между слоями, встроенные формы «символ» и «пусто»
 * работают, списочная форма «соединить» работает, вызов функции без аргументов
 * работает, псевдоним типа работает. Часть была правдой когда-то и осталась в
 * списке после починки; часть описывала расхождение слоёв, которое свели.
 *
 * Заметить это было нечем: недостача — единственное утверждение о языке,
 * которое НЕ ЛОМАЕТСЯ, когда становится ложным. Тест, проверяющий, что чего-то
 * нет, никто не пишет; тест, проверяющий, что что-то есть, на такую запись не
 * посмотрит. Список наполовину из выдуманного хуже отсутствующего: он и есть то
 * самое «проверено на словах», против чего написан весь проект.
 *
 * Отсюда этот файл. У каждой оставшейся недостачи здесь стоит ПРОГРАММА,
 * которая её показывает, и тест требует, чтобы программа по-прежнему не
 * работала. Починили недостачу — тест краснеет и заставляет убрать запись из
 * списка. Это единственный известный способ не дать честному списку стать
 * враньём.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { createRuntime, evaluate } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const КАТАЛОГ = JSON.parse(readFileSync(new URL("../examples/leetcode/index.json", import.meta.url), "utf8"))
const НЕДОСТАЧИ = new Set((КАТАЛОГ["чего не хватает языку"] ?? []).map((запись) => запись["чего"]))

/** Разбор и проверка: `null`, если программа не разобралась вовсе. */
function проверить(исходник) {
  try {
    const программа = parse(исходник, "проба.flang")
    return { программа, беды: (checkTypes(программа).diagnostics ?? []).map((б) => б.code) }
  } catch (беда) {
    return { программа: null, беды: [беда?.code ?? "FLANG_PARSE"] }
  }
}

/*
 * Парсер на flang — для одной-единственной улики: той, где язык уже умеет, а
 * репозиторий ещё не вправе. `linkProgram` асинхронна, а улики синхронны,
 * поэтому связывание идёт здесь, на верхнем уровне, один раз.
 */
const ПУТЬ_ПАРСЕРА = fileURLToPath(new URL("../self/parser.flang", import.meta.url))
const { diagnostics: бедыПарсера, ...парсерНаFlang } = await linkProgram(
  ПУТЬ_ПАРСЕРА,
  readFileSync(ПУТЬ_ПАРСЕРА, "utf8"),
  parse,
)
const средаПарсера = createRuntime(парсерНаFlang, { maxSteps: 150_000_000, maxDepth: 20_000 })

/** Разбирает ли исходник ПАРСЕР НА FLANG (`self/parser.flang`), а не эталон. */
function разбираетНаFlang(исходник) {
  assert.deepEqual(бедыПарсера, [], "self/parser.flang не связался — проверять нечем")
  const итог = средаПарсера.call("Разбор исходника", { исходник, внешние: [] })
  return (итог["диагностики"] ?? []).length === 0
}

/**
 * Недостачи, каждая со своей программой-уликой.
 *
 * `показ` обязан вернуть true, ПОКА недостача есть. Как только язык научится —
 * тест покраснеет на этой строке, и это правильное поведение: список надо
 * поправить, а не тест.
 */
const УЛИКИ = [
  {
    чего: "логические операции инфиксной записью",
    показ: () => {
      /* Речь именно об ИНФИКСНОЙ записи: как функции эти операции есть в
         flang/stdlib/logic.flang и там же объяснено, почему слово «и» занять
         нельзя. Улика проверяет синтаксис, а не наличие операций. */
      for (const выражение of ["первый и второй", "первый или второй", "не первый"]) {
        const итог = проверить(
          `модуль «Логика»\n\nтотальная функция «Проба»\n  принимает первый: признак, второй: признак\n` +
            `  возвращает признак\n  ${выражение}\n`,
        )
        if (итог.программа !== null && итог.беды.length === 0) return false
      }
      return true
    },
  },
  {
    чего: "параметрический полиморфизм",
    показ: () => {
      /* Имена вариантов уникальны на всю программу, поэтому «то же самое, но с
         другим типом внутри» требует второго типа с другими именами. Это и
         делает монаду невыразимой: M(M) — отдельный руками написанный тип. */
      const итог = проверить(
        `модуль «Полиморфизм»\n\n` +
          `тип «Возможно»\n  вариант «Есть» с «значение»: число\n  вариант «Нет»\n\n` +
          `тип «Двойное»\n  вариант «Есть» с «значение»: «Возможно»\n  вариант «Нет»\n`,
      )
      return итог.беды.length > 0
    },
  },
  {
    чего: "убывание по мере",
    показ: () => {
      /* Счёт до N завершается очевидно человеку, но убывает ЧИСЛО, а часть
         значения для анализа — хвост списка, голова, поле записи или варианта. */
      const исходник =
        `модуль «Счёт»\n\nтотальная функция «До нуля»\n  принимает н: число\n  возвращает число\n` +
        `  если н не больше 0\n    то 0\n    иначе «До нуля» от (н минус 1)\n`
      const { программа } = проверить(исходник)
      if (программа === null) return true
      return !checkTotality(программа).total.has("До нуля")
    },
  },
  {
    чего: "функции первого класса в программах репозитория",
    показ: () => {
      /*
       * Недостача особого рода: у ЯЗЫКА функции первого класса есть, и первая
       * половина улики это подтверждает — иначе запись означала бы не то, что
       * написано. Нет их у РЕПОЗИТОРИЯ: `self/parser.flang` новой формы не
       * разбирает, а корпус сверки собирается по маске каталога, значит первый
       * же файл stdlib или examples с `функция из числа в число` роняет
       * неподвижную точку.
       *
       * Поэтому улика двойная: эталон обязан ПРИНЯТЬ программу, а парсер на
       * flang — ОТКАЗАТЬ. Совпадут они — недостачи больше нет, и тест скажет,
       * что запись пора убрать, а библиотеку из `stdlib-hof.test.mjs`
       * перенести в `flang/stdlib/`.
       */
      /* Тег строит САМА программа: вычислитель отказывается применять тег,
         которого ни одно место программы не берёт значением (HOF.md, «Дыра,
         которую анализ закрыть не может»). Поэтому «Проба», а не «Применить»
         с тегом снаружи. */
      const исходник =
        `модуль «Высший»\n\nтотальная функция «Удвоить»\n  принимает х: число\n  возвращает число\n  х плюс х\n\n` +
        `тотальная функция «Применить»\n  принимает ф: функция из числа в число, х: число\n  возвращает число\n  ф от х\n\n` +
        `тотальная функция «Проба»\n  принимает х: число\n  возвращает число\n  «Применить» от функция «Удвоить» и х\n`
      const итог = проверить(исходник)
      if (итог.программа === null || итог.беды.length > 0) return false
      if (checkTotality(итог.программа).diagnostics.length > 0) return false
      if (evaluate(итог.программа, "Проба", { х: 21 }) !== 42) return false
      return !разбираетНаFlang(исходник)
    },
  },
  {
    чего: "ассоциативный массив",
    показ: () => {
      const итог = проверить(
        `модуль «Словарь»\n\nтотальная функция «Проба»\n  принимает д: словарь строки\n  возвращает число\n  1\n`,
      )
      return итог.программа === null || итог.беды.length > 0
    },
  },
  {
    чего: "массив с индексным доступом",
    показ: () => {
      /* Взять элемент по номеру можно только обходом: встроенной формы нет. */
      const итог = проверить(
        `модуль «Индекс»\n\nтотальная функция «Проба»\n  принимает элементы: список числа\n` +
          `  возвращает число\n  элемент 1 в элементы\n`,
      )
      return итог.программа === null || итог.беды.length > 0
    },
  },
  {
    чего: "образцы для строк",
    показ: () => {
      /* «пусто» и «голова и хвост» работают только со списком; строку надо
         сперва разложить формой «разложить … на символы». */
      const итог = проверить(
        `модуль «Образцы»\n\nтотальная функция «Проба»\n  принимает текст: строка\n  возвращает число\n` +
          `  разбор текст\n    случай пусто\n      то 0\n    случай голова и хвост\n      то 1\n`,
      )
      return итог.программа === null || итог.беды.length > 0
    },
  },
  {
    чего: "обработка ошибок",
    показ: () => {
      /* Отказ встроенной формы прекращает вычисление целиком: перехватить его
         нечем, поэтому проверять надо ДО опасного места. */
      const исходник =
        `модуль «Отказ»\n\nтотальная функция «Проба»\n  принимает текст: строка\n  возвращает число\n  к числу текст\n`
      const { программа } = проверить(исходник)
      if (программа === null) return true
      try {
        evaluate(программа, "Проба", { текст: "не число" })
        return false
      } catch {
        return true
      }
    },
  },
]

test("каждая недостача из каталога подтверждается программой", () => {
  for (const улика of УЛИКИ) {
    assert.ok(
      НЕДОСТАЧИ.has(улика.чего),
      `в каталоге нет недостачи «${улика.чего}», а улика на неё есть — уберите улику или верните запись`,
    )
    assert.ok(
      улика.показ(),
      `недостача «${улика.чего}» БОЛЬШЕ НЕ СУЩЕСТВУЕТ: программа-улика работает. ` +
        `Уберите запись из «чего не хватает языку» в flang/examples/leetcode/index.json`,
    )
  }
})

test("у каждой недостачи каталога есть улика, кроме назначенных без неё", () => {
  /* Одна запись улики иметь не может: она про сам список. Остальные обязаны —
     иначе недостачу снова будет нечем проверить, и всё повторится. */
  const безУлики = new Set(["проверка самого этого списка"])
  const сУликой = new Set(УЛИКИ.map((улика) => улика.чего))
  const беспризорные = [...НЕДОСТАЧИ].filter((чего) => !сУликой.has(чего) && !безУлики.has(чего))
  assert.deepEqual(
    беспризорные,
    [],
    `эти недостачи никем не проверяются и могут тихо стать неправдой: ${беспризорные.join(", ")}`,
  )
})
