/**
 * НАДЗОР НА ЖИВОМ УЗЛЕ: процесс упал — надзор поднял его, и он снова работает
 * через провод.
 *
 * ── Что здесь считается доказательством ─────────────────────────────────────
 *
 * Не «форма заведена» и не «в журнале появилось слово», а три исхода, которые
 * различаются наблюдаемо:
 *
 *   1. НАДЗОР ОБЪЯВЛЕН, стратегия «перезапустить». Процесс падает на письме,
 *      которого его разбор не покрывает; надзор поднимает его; ТРЕТЬЕ письмо,
 *      лежавшее в ящике всё время, пока процесс был мёртв, обрабатывается — и
 *      его доклад доезжает до процесса НА ДРУГОМ УЗЛЕ. Состояние при этом
 *      начинается заново (2 + 3 дало бы 5, а вышло 3), а ящик перезапуск не
 *      тронул — оба решения записаны на flang и здесь предъявлены числом.
 *   2. НАДЗОР НЕ ОБЪЯВЛЕН — тот же отказ оставляет процесс лежать: третье
 *      письмо не обрабатывается никогда, и на другой узел не доезжает. Это
 *      УЛИКА ДО: без надзора узел ведёт себя ровно так, как вёл до этой работы.
 *   3. ПОРОГ ОТКАЗОВ ИСЧЕРПАН (0 отказов за 5000 мс). Первый же отказ уходит на
 *      запасную стратегию «передать выше», над «Цехом» надзора нет — и узел
 *      останавливается целиком, не дождавшись своего срока.
 *
 * ── Где живут решения ───────────────────────────────────────────────────────
 *
 * Все три исхода считает `flang/conc/supervisor.flang` — напечатанный модуль, тот
 * же во всех девяти целях. Хозяин не решает ничего: он передаёт отказ надзору и
 * исполняет его веления («Поднять», «Уложить», «Решено», «Некому надзирать»).
 *
 * ── Мера ────────────────────────────────────────────────────────────────────
 *
 * Прогон печатает её сам: «надзор работает на N целях из 9». Число это ДРУГОЕ,
 * чем у `flang/scripts/node-across-targets.flang`: узел целиком там считается
 * отдельно, а надзор — на
 * тех, чей хозяин уже умеет передавать отказ надзору.
 *
 * Запуск: node --test flang/test/nadzor-uzla.test.mjs
 */
import assert from "node:assert/strict"
import { rmSync } from "node:fs"
import test from "node:test"

import { findExecutable, missingToolchain } from "./toolchain-guard.mjs"
import { рабочийКаталог } from "./tempdir.mjs"
import {
  ОПОРА,
  ЦЕЛИ,
  журнал,
  корень,
  напечатаннаяПрограмма,
  новаяЗапись,
  поднятьУзел,
  собратьУзел,
} from "./uzel-osnastka.mjs"

/* Цели, чей хозяин уже передаёт отказ надзору. Список короткий нарочно: он и
   есть мера, и растёт он не «формой», а правкой хозяина. */
const С_НАДЗОРОМ = ["python", "js", "go", "elixir", "csharp", "java", "rust", "c", "cpp"]

const ПРОЦЕССЫ = [
  { имя: "Счётчик", начальное: "Начальный счёт", обработчик: "Обработчик счёта", ящик: null },
  { имя: "Учётчик", начальное: "Начальные записи", обработчик: "Обработчик учёта", ящик: null },
]

/** Дерево надзора — ДАННЫЕ узла, ровно как размещение и план процессов. */
const ЦЕХ = (порог) => ({
  имя: "Цех",
  порог,
  окно: 5000,
  иначе: "передать выше",
  процессы: [{ кто: "Счётчик", стратегия: "перезапустить" }],
  надзоры: [],
})

const ПЛАНЫ = {
  "plan.json": { процессы: ПРОЦЕССЫ, надзоры: [ЦЕХ(1)] },
  "plan-bez.json": { процессы: ПРОЦЕССЫ },
  "plan-porog.json": { процессы: ПРОЦЕССЫ, надзоры: [ЦЕХ(0)] },
}

/* Три письма подряд. Второе — «записать», команда УЧЁТА, посланная СЧЁТЧИКУ:
   разбор его обработчика такого варианта не покрывает, и он отказывает с
   FLANG_MATCH_NOT_EXHAUSTIVE. Отказ приезжает с провода, а не выдумывается
   хозяином, и программу ради него править не пришлось.

   Вариант взят ОБЪЯВЛЕННЫЙ, а не выдуманный, и это не мелочь: у цели js
   напечатанный модуль требует собирать вариант своим конструктором, и
   несуществующее имя хозяин отвергает раньше, чем оно доедет до обработчика.
   Проверять надо отказ ОБРАБОТЧИКА, а не отказ разбора провода. */
const ВБРОС = JSON.stringify([
  { кому: "Счётчик", что: ["в", "замерить", { сколько: ["ч", 2] }] },
  { кому: "Счётчик", что: ["в", "записать", { текст: ["с", "не тому"] }] },
  { кому: "Счётчик", что: ["в", "замерить", { сколько: ["ч", 3] }] },
])

const целейРаботает = []

/** Поднять пару «опора слушает — цель звонит» и дождаться обоих «концов». */
async function пара(цель, чем, чемОпора, каталог, каталогОпоры, планФайл, узлы) {
  const хэш = (await import("node:crypto")).createHash("sha256")
    .update(напечатаннаяПрограмма(каталог), "utf8").digest("hex")

  const опора = поднятьУзел(ОПОРА, чемОпора, каталогОпоры, [
    "--я", "учёт", "--слушать", "127.0.0.1:0", "--хэш", хэш,
    "--план-файл", планФайл,
    "--размещение", JSON.stringify({ "Счётчик": "счёт", "Учётчик": "учёт" }),
    "--срок", "2000", "--пульс", "200", "--жить", "9",
  ], узлы)
  const поднят = await новаяЗапись(опора.записи, (з) => з.в === "поднят", 20_000)
    .catch((беда) => { throw new Error(`${беда.message}\nstderr опоры:\n${опора.ошибки.текст}`) })

  const начало = Date.now()
  const новый = поднятьУзел(цель, чем, каталог, [
    "--я", "счёт", "--слушать", "127.0.0.1:0", "--хэш", хэш,
    "--план-файл", планФайл,
    "--размещение", JSON.stringify({
      "Счётчик": "счёт", "Учётчик": "учёт", звонить: { "учёт": `127.0.0.1:${поднят.порт}` },
    }),
    "--вбросить", ВБРОС,
    "--срок", "2000", "--пульс", "200", "--жить", "6",
  ], узлы)

  await новаяЗапись(новый.записи, (з) => з.в === "связь" && з.что === "заведена", 20_000)
    .catch((беда) => { throw new Error(`${беда.message}\nstderr ${цель.имя}:\n${новый.ошибки.текст}`) })
  const конецЦели = await новаяЗапись(новый.записи, (з) => з.в === "конец", 20_000)
    .catch((беда) => { throw new Error(`${беда.message}\nstderr ${цель.имя}:\n${новый.ошибки.текст}`) })
  /* Сколько прожил ИМЕННО узел цели: опора живёт девять секунд и ждать её
     нельзя — иначе остановка узла утонет в чужом сроке. */
  const прожил = Date.now() - начало
  const конецОпоры = await новаяЗапись(опора.записи, (з) => з.в === "конец", 20_000)
  return { новый, опора, конецЦели, конецОпоры, прожил }
}

for (const имяЦели of С_НАДЗОРОМ) {
 const цель = ЦЕЛИ.find((это) => это.имя === имяЦели) ?? ОПОРА
 test(`надзор на ${цель.имя}: упавший процесс поднят, и он снова работает через провод`, async (t) => {
  const чем = цель.ищем.map((это) => findExecutable(это)).find((это) => это !== null)
  if (чем === undefined || чем === null) {
    return missingToolchain(t, цель.тулчейн, `тулчейн «${цель.тулчейн}» не найден — пропуск`)
  }
  const чемОпора = ОПОРА.ищем.map((это) => findExecutable(это)).find((это) => это !== null)
  if (чемОпора === undefined || чемОпора === null) {
    return missingToolchain(t, ОПОРА.тулчейн, `тулчейн опоры «${ОПОРА.тулчейн}» не найден`)
  }

  const каталог = рабочийКаталог(`nadzor-${цель.имя}`)
  const каталогОпоры = рабочийКаталог(`nadzor-opora-${цель.имя}`)
  const узлы = []
  try {
    собратьУзел(каталог, цель, ПЛАНЫ)
    собратьУзел(каталогОпоры, ОПОРА, ПЛАНЫ)

    /* ── 1. надзор объявлен: поднял, и письмо после подъёма доехало ──────── */
    const с = await пара(цель, чем, чемОпора, каталог, каталогОпоры, "plan.json", узлы)
    const решено = await новаяЗапись(с.новый.записи, (з) => з.в === "надзор" && з.что === "решено", 5_000)
    assert.equal(решено.надзор, "Цех")
    assert.equal(решено.стратегия, "перезапустить")
    await новаяЗапись(с.новый.записи, (з) => з.в === "надзор" && з.что === "поднят" && з.кто === "Счётчик", 5_000)
    /* Всего 3, а не 5: перезапуск вернул состояние к начальному. Подтверждено 2:
       ответ на доклад после подъёма тоже дошёл. */
    assert.deepEqual(
      с.конецЦели.состояния["Счётчик"],
      ["з", { "всего": ["ч", 3], "подтверждено": ["ч", 2] }],
      `надзор не поднял «Счётчика»: ${JSON.stringify(с.конецЦели.состояния)}`,
    )
    /* Письмо, лежавшее в ящике мёртвого процесса, доехало до ДРУГОГО узла. */
    assert.deepEqual(
      с.конецОпоры.состояния["Учётчик"],
      ["з", { "строки": ["л", [["с", "2"], ["с", "3"]]] } ],
      `доклад после подъёма не доехал: ${JSON.stringify(с.конецОпоры.состояния)}`,
    )
    for (const п of узлы.splice(0)) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }

    /* ── 2. надзора нет: тот же отказ оставляет процесс лежать (улика ДО) ── */
    const без = await пара(цель, чем, чемОпора, каталог, каталогОпоры, "plan-bez.json", узлы)
    assert.equal(
      без.новый.записи.find((з) => з.в === "надзор"), undefined,
      "без объявленного надзора не должно быть ни одной записи надзора",
    )
    /* Подтверждено НОЛЬ, а не один: все три письма лежат в ящике с самого
       начала и разбираются подряд, поэтому процесс умирает на втором раньше,
       чем вернётся ответ на первый, — а мёртвому ответ уже не кладут. */
    assert.deepEqual(
      без.конецЦели.состояния["Счётчик"],
      ["з", { "всего": ["ч", 2], "подтверждено": ["ч", 0] }],
      `без надзора «Счётчик» не должен был подняться: ${JSON.stringify(без.конецЦели.состояния)}`,
    )
    assert.deepEqual(
      без.конецОпоры.состояния["Учётчик"],
      ["з", { "строки": ["л", [["с", "2"]]] } ],
      `без надзора третье письмо не должно было доехать: ${JSON.stringify(без.конецОпоры.состояния)}`,
    )
    for (const п of узлы.splice(0)) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }

    /* ── 3. порог исчерпан: передать выше, и над «Цехом» никого ──────────── */
    const порог = await пара(цель, чем, чемОпора, каталог, каталогОпоры, "plan-porog.json", узлы)
    const выше = порог.новый.записи.find((з) => з.в === "надзор" && з.стратегия === "передать выше")
    assert.notEqual(выше, undefined, "порог 0 обязан был уйти на запасную стратегию")
    const некому = порог.новый.записи.find((з) => з.в === "надзор" && з.что === "некому")
    assert.notEqual(некому, undefined, "над «Цехом» надзора нет — обязано быть «некому»")
    /* Узел остановился целиком, не дождавшись своих шести секунд. */
    assert.ok(порог.прожил < 5_000, `узел не остановился: прожил ${порог.прожил} мс`)

    целейРаботает.push(цель.имя)
    console.log(`надзор: ${цель.имя} ↔ ${ОПОРА.имя}, процесс упал, надзор поднял, письмо после подъёма доехало`)
    console.log("  без объявленного надзора тот же отказ оставляет процесс лежать")
    console.log(`  порог исчерпан → «передать выше» → «некому» → узел остановлен за ${порог.прожил} мс из 6000`)
  } finally {
    for (const п of узлы) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }
    rmSync(каталог, { recursive: true, force: true })
    rmSync(каталогОпоры, { recursive: true, force: true })
  }
 })
}

test.after(() => {
  if (целейРаботает.length === 0) {
    console.log("НАДЗОР: НЕ ИЗМЕРЕНО — ни одна цель не прошла")
    return
  }
  const сколько = целейРаботает.length
  console.log(`НАДЗОР РАБОТАЕТ НА ${сколько} ${сколько === 1 ? "ЦЕЛИ" : "ЦЕЛЯХ"} ИЗ 9: ${целейРаботает.join(", ")}`)
  console.log("решения надзора при этом печатаются во все девять — это другое число и другой прогон")
})
