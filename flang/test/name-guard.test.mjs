test("краснеет на подделке, подложенной ФАЙЛОМ, а не записью в дереве", async (t) => {
  const каталог = await mkdtemp(join(tmpdir(), "flang-name-guard-"))
  t.after(() => rm(каталог, { recursive: true, force: true }))
  await mkdir(join(каталог, "корпус"), { recursive: true })
  await writeFile(
    join(каталог, "корпус", "fake.flang"),
    [
      "модуль «Подделка»",
      "",
      "тотальная функция «Сложить всё»",
      "  принимает н: список число",
      "  возвращает число",
      "  пример «Три числа»",
      "    дано н равно [1, 2, 3]",
      "    ожидается 6",
      "  свёртка н начиная с 0 как акк и эл → акк плюс эл",
      "",
    ].join("\n"),
    "utf8",
  )
  const { найдено, долг } = долгКорпуса(каталог, ["корпус"])
  const имена = new Set(найдено.map((м) => м.name))
  assert.ok(имена.has("н"), "однобуквенный параметр не пойман")
  assert.ok(имена.has("акк"), "обрубок «акк» не пойман")
  assert.ok(имена.has("эл"), "обрубок «эл» не пойман")
  assert.deepEqual(долг["корпус/fake.flang"], ["акк", "н", "эл"])
})

