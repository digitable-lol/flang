test("охват сторожа назван числом: чего он не смотрит — видно, а не молчит", () => {
  /* `КАТАЛОГИ` — четыре каталога, а `.flang` в дереве много больше. Каталог,
     не попавший в список, НЕ КРАСНЕЕТ: он просто не проверяется, и сторож
     зеленеет ровно потому, что смотреть перестал — тот самый класс, о котором
     заметка `docs/zettel/renaming-a-file-silently-disables-the-guard.md`.
     Числа здесь затем и прибиты: сдвинутся — придётся принять решение, а не
     забыть о нём. 85 рукописных файлов вне охвата — названный долг охвата, и
     расширять его надо вместе с новым замером цены, а не молча. */
  const о = охват()
  /* 220 → 222 и 809 → 811: прибавились `flang/stdlib/postgres.flang` и
     `flang/examples/db/postgres-plan.flang` (драйвер PostgreSQL). Оба под
     правилами, долга не принесли. */
  /* 222 → 227 и 811 → 826 при своде границы входа, слоя ввода-вывода и ветки
     `svod/zav`. Пятнадцать файлов названы поимённо, и три четверти из них
     приехали СТВОЛОМ, а не сводом: на стволе охват уже был 225 из 824, и
     ведомость за ним не переписали.

     Под правила встало пять (+5):
       flang/self/obyazatelstva-i-yadro.flang    ствол
       flang/self/otkazy-tipov.flang             ствол
       flang/self/otkazy-totalnosti.flang        ствол
       flang/examples/io/oktety-po-provodu.flang свод (слой ввода-вывода)
       flang/examples/io/potomok.flang           свод (слой ввода-вывода)
     Долга не принёс ни один: поимённая сверка после них молчит.

     Вне охвата прибавилось десять, все на стволе, и все — рукописные (75 → 85):
     `docs/kurs/proverka.flang`, `editors/vim/proverka/proba-beda.flang`,
     `editors/vim/proverka/proba-perehoda.flang`, `flang/conc/svyaz.flang`,
     `scripts/podsvetka-vim.flang`, `scripts/pravila-vim.flang`,
     `scripts/proverka-lsp.flang`, `scripts/proverka-vim.flang`,
     `scripts/slova-yazyka.flang`, `web/shortener/klient.flang`. Долг охвата
     этим и вырос: 75 → 85. Расширять охват здесь нельзя — цену по этим
     каталогам не мерили, а правило без замера цены и есть то, что потом
     отключают. Печать замеров (500) и образцы тестов (14) не двинулись.

     Арифметика прогоном, а не в уме: 227 + 599 = 826 и 500 + 85 + 14 = 599. */
  assert.equal(о.смотрим, 227, "файлов под правилами")
  assert.equal(о.всего, 826, "файлов .flang в дереве")
  assert.deepEqual(о.поРодам, {
    "печать замеров": 500,
    "рукописное вне четырёх каталогов": 85,
    "образцы тестов": 14,
  })
})

