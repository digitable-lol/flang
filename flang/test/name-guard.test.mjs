/**
 * Сторож имён — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/name-guard.mjs`. Здесь четыре
 * разных обязательства, и путать их нельзя:
 *
 *   1. на дереве сторож ЧИСТ — новых нарушений нет, долг совпал поимённо;
 *   2. сторож ЛОВИТ — на подделках, по одной на каждое правило;
 *   3. сторож МОЛЧИТ на здоровом коде — и это проверено не общими словами, а
 *      здоровыми именами всех четырёх поверхностей: русской, английской,
 *      эсперантской, китайской. Порог «не меньше трёх» на них значит разное, и
 *      правило, написанное в кодовых точках, запретило бы `列表` и `阶乘`;
 *   4. дыра в разборе НАЗВАНА числом: `flang/self/interpret.flang` целиком не
 *      берётся, и сторож обязан сказать это вслух, а не молча недосчитать.
 *
 * Четвёртое написано потому, что файл, упавший целиком, уносит свои проверки
 * молча: сторож остаётся зелёным ровно потому, что проверять стало нечего. То
 * же самое, только в другую сторону, говорит шапка
 * `flang/test/count-guard.test.mjs`: проверка, которая не может упасть,
 * выглядит ровно как проверка, у которой всё хорошо.
 *
 * Запуск: node --test flang/test/name-guard.test.mjs
 */
