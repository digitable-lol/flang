test("на корпусе новых нарушений нет: долг совпадает поимённо", () => {
  const { долг } = долгКорпуса()
  const записанный = JSON.parse(readFileSync(ФАЙЛ_ДОЛГА, "utf8")).files
  const новые = []
  const снятые = []
  for (const файл of new Set([...Object.keys(долг), ...Object.keys(записанный)])) {
    const сейчас = new Set(долг[файл] ?? [])
    const было = new Set(записанный[файл] ?? [])
    for (const имя of сейчас) if (!было.has(имя)) новые.push(`${файл}: «${имя}»`)
    for (const имя of было) if (!сейчас.has(имя)) снятые.push(`${файл}: «${имя}»`)
  }
  assert.deepEqual(новые, [], "новые имена в долге — либо поправьте код, либо перепишите долг")
  assert.deepEqual(снятые, [], "имена сняты — перепишите долг: node flang/scripts/name-guard.mjs --debt")
})

test("цена приведения корпуса названа числом, а не словом", () => {
  const { найдено, помиловано } = долгКорпуса()
  const поКодам = {}
  for (const место of найдено) for (const код of место.коды) поКодам[код] = (поКодам[код] ?? 0) + 1
  /* Числа перемерены деревом 19 августа на стволе 24d7681d (было 1539/513/1345/3250
     на 2bfcb7d0, а до того 1434/502/1341/3131 при вливании 718f9169). Прибавили
     101 новое имя в семи файлах, и две трети из них — ОДИН файл: `stdlib/sha256.flang`
     несёт 67 (`а0`…`а7`, `б0`…`б7`, `н0`…`н7`, `п0`…`п15`, `р0`…`р7`, `с0`…`с15`).
     Это рабочие переменные, расписание сообщения и таблица констант FIPS 180-4:
     имена заданы стандартом, а нумерация — его же индексами. Остальные 34 — конкурентность
     («а», «б», «в», «г», «д», «з», «зн», «и», «н», «о», «п», «р», «т», «т1», «т2»,
     «у», «ф», «х», «э», «акк» в `self/conc.flang`), два оракула, `utf8`, «то» в ядре
     доказательств и «хр» в плане с журналом. Долг ПРИНЯТ, а не оплачен:
     это математические имена в новых файлах, и переписывать их — работа над теми
     файлами, а не над сторожем. Разойдутся — значит корпус
     двинулся, и двинулся он либо в сторону правил, либо от них; молча этого
     знать нельзя. Первый замер (17 августа, 186 файлов) давал 1181/436/1150/228
     — за сутки корпус вырос на четыре файла и на 135 мест долга. Р4 после этого
     приведён нацело: 228 → 0, и ноль здесь измерен, а не назначен. */
  /* 1821/524/1378/3575 → 1829/524/1383/3588 при своде границы входа, слоя
     ввода-вывода и ветки `svod/zav`. Числа сняты прогоном по каждому файлу
     отдельно и сложены прогоном, а не в уме; разложение полное, и на ствол
     здесь приходится больше, чем на свод:

       Р1 1821 → 1836 на СТВОЛЕ: `self/bootstrap/compiler.flang` 16 → 31, все
          пятнадцать приехали с ответом двоичного редактору (6516ea71, `flang
          lsp`). Ведомость за ними не переписали, и ствол приехал сюда красным.
       Р1 1836 → 1829 здесь: те же пятнадцать мест несли четыре однобуквенных
          имени, и все четыре переименованы по образцу, который уже стоит в
          этом же файле: «б» → «беда» (эталон — `self/parser.flang:5366`),
          «ф» → «файл» (строка 1243 этого файла), «э» → «элемент» (строка 870
          этого файла), «р» → «разобранное» (по имени типа «Разобранное»).
          Семь мест связывания, отсюда ровно −7.
       Р2 524 не шелохнулся ни на стволе, ни здесь.
       Р3 1378 → 1381 на СТВОЛЕ: `self/bootstrap/compiler.flang` 4 → 6 и
          `self/emit-js.flang` 61 → 62.
       Р3 1381 → 1383 здесь: `self/types.flang` 2 → 4 — два новых `акк` в
          свёртках (строки 6935 и 6945), пришедшие с границей входа. Имя `акк`
          за этим файлом в долге УЖЕ ЧИСЛИТСЯ, поэтому поимённая сверка молчит,
          а счёт растёт: ключ долга нарочно без счётчика вхождений, см. шапку
          сторожа. Долг принят, не оплачен — переписывать свёртки границы входа
          значит работать над ней, а не над сторожем.

     Сумма мест сходится прогоном: было 1821 + 524 + 1378 = 3723 кода на 3575
     мест, стало 1829 + 524 + 1383 = 3736 кодов на 3588 мест. Разница «кодов
     минус мест» и там и там 148 — это места, на которые легло по два правила
     сразу; она не поехала, и это отдельная улика, что двинулся корпус, а не
     разбор. */
  assert.equal(поКодам["Р1-одна-буква"], 1829)
  assert.equal(поКодам["Р2-короче-трёх"], 524)
  assert.equal(поКодам["Р3-обрубок"], 1383)
  assert.equal(поКодам["Р4-две-письменности"], undefined, "две письменности внутри слова: приведено нацело")
  assert.equal(поКодам["Р5-длинное-имя"], undefined, "верхняя граница имени сегодня не пробита")
  assert.equal(поКодам["Р6-длинный-пример"], undefined, "верхняя граница имени примера сегодня не пробита")
  assert.equal(найдено.length, 3588, "всего мест долга")
  assert.equal(помиловано, 29, "мест, где неверно ПРАВИЛО, а не код")
})

