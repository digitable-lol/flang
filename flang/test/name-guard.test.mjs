test("эсперантская диакритика считается за одну букву: NFD не должен менять итог", () => {
  const nfc = { role: "параметр", name: "ĉu".normalize("NFC") }
  const nfd = { role: "параметр", name: "ĉu".normalize("NFD") }
  assert.deepEqual(нарушения(nfc), нарушения(nfd))
  assert.deepEqual(нарушения(nfc), ["Р2-короче-трёх"], "две буквы — коротко на любой латинской поверхности")
  assert.deepEqual(нарушения({ role: "параметр", name: "ĉio".normalize("NFD") }), [])
})

test("одиночный иероглиф ловится, два — нет: порог хань в иероглифах, не в буквах", () => {
  assert.deepEqual(нарушения({ role: "параметр", name: "数" }), ["Р2-короче-трёх"])
  assert.deepEqual(нарушения({ role: "параметр", name: "数字" }), [])
})

test("хань с латиницей не считается двумя письменностями: двойников там нет", () => {
  assert.deepEqual(нарушения({ role: "пример", name: "二十的阶乘在double中仍然精确" }), [])
  assert.ok(нарушения({ role: "пример", name: "Печать сode" }).includes("Р4-две-письменности"))
})

/* ─────────────── 4. дыра в разборе названа, а не проглочена ─────────────── */

test("список потерь сверяется в обе стороны: и новая потеря, и надгробие снятой", () => {
  const { потери } = связывания()
  assert.deepEqual(
    потери.map((п) => `${п.file}:${п.line}`).sort(),
    [...ПОТЕРИ].sort(),
    "неразобранные функции — те же самые, что записаны; надгробие врёт так же, как пропуск",
  )
  assert.deepEqual(ПОТЕРИ, [], "сегодня корпус разбирается целиком")
})

test("дыра в разборе закрыта стволом: 280 функций из 280, отступление не понадобилось", () => {
  const { связывания: все, потери } = связывания()
  const свои = все.filter((м) => м.file === "flang/self/interpret.flang" && м.role === "функция")
  /* 17 августа файл не брался целиком и отступление спасало 277 из 279. Ствол
     дыру закрыл (57a193bb, 7f95df5d); отступление осталось страховкой. */
  assert.equal(свои.length, 280, "разобрано функций у flang/self/interpret.flang")
  assert.deepEqual(потери, [], "потерь больше нет")
})

test("охват сторожа назван числом: чего он не смотрит — видно, а не молчит", () => {
  /* `КАТАЛОГИ` — четыре каталога, а `.flang` в дереве много больше. Каталог,
     не попавший в список, НЕ КРАСНЕЕТ: он просто не проверяется, и сторож
     зеленеет ровно потому, что смотреть перестал — тот самый класс, о котором
     заметка `docs/zettel/renaming-a-file-silently-disables-the-guard.md`.
     Числа здесь затем и прибиты: сдвинутся — придётся принять решение, а не
     забыть о нём. 70 рукописных файлов вне охвата — названный долг охвата, и
     расширять его надо вместе с новым замером цены, а не молча. */
  const о = охват()
  assert.equal(о.смотрим, 209, "файлов под правилами")
  assert.equal(о.всего, 796, "файлов .flang в дереве")
  assert.deepEqual(о.поРодам, {
    "печать замеров": 500,
    "рукописное вне четырёх каталогов": 73,
    "образцы тестов": 14,
  })
})

test("исключения — это не долг: список назван и объяснён", () => {
  const мест = [...ИСКЛЮЧЕНИЯ.values()].reduce((сумма, имена) => сумма + имена.size, 0)
  assert.equal(ИСКЛЮЧЕНИЯ.size, 10, "файлов с исключением")
  assert.equal(мест, 11, "различных имён под исключением")
  const записанный = JSON.parse(readFileSync(ФАЙЛ_ДОЛГА, "utf8")).files
  for (const [файл, имена] of ИСКЛЮЧЕНИЯ) {
    for (const имя of имена) {
      assert.ok(!(записанный[файл] ?? []).includes(имя), `«${имя}» не может быть и долгом, и исключением (${файл})`)
    }
  }
})
