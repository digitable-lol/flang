const счёт = (исходник) => {
  const программа = parse(исходник)
  const итог = checkTotality(программа)
  return { сторожей: итог.guards.length, точных: итог.exact.length, тотальных: итог.total.size, беды: итог.diagnostics }
}

test("объявленный `нат` снимает сторожа с постоянного шага", () => {
  const с_натом = счёт(
    "модуль «М»\n\nтотальная функция «Вниз»\n  принимает н: нат\n  возвращает число\n"
      + "  если н не больше 0\n    то 0\n    иначе «Вниз» от (н минус 1)\n",
  )
  assert.deepEqual(с_натом.беды, [])
  assert.equal(с_натом.тотальных, 1)
  assert.equal(с_натом.сторожей, 0, "сторожа быть не должно: дно и потолок даёт тип")
  assert.equal(с_натом.точных, 1)

  const без_ната = счёт(
    "модуль «М»\n\nтотальная функция «Вниз»\n  принимает н: число\n  возвращает число\n"
      + "  если н не больше 0\n    то 0\n    иначе «Вниз» от (н минус 1)\n",
  )
  assert.deepEqual(без_ната.беды, [])
  assert.equal(без_ната.сторожей, 1, "на `число` сторож остаётся: IEEE-754 не даёт потолка")
  assert.equal(без_ната.точных, 0)
})

test("дробный шаг на натуральном сторожа не снимает", () => {
  /* Половинка не целая, и точность отрезка ей не помогает: доказательство
     держится на том, что шаг ЦЕЛЫЙ, а не на том, что он мал. */
  const итог = счёт(
    "модуль «М»\n\nтотальная функция «Вниз»\n  принимает н: нат\n  возвращает число\n"
      + "  если н не больше 0\n    то 0\n    иначе «Вниз» от (н минус 0.5)\n",
  )
  assert.equal(итог.точных, 0)
  assert.equal(итог.сторожей, 1)
})

test("псевдоним натурального работает как натуральное", () => {
  const итог = счёт(
    "модуль «М»\n\nтип «Счётчик» это нат\n\nтотальная функция «Вниз»\n  принимает н: «Счётчик»\n  возвращает число\n"
      + "  если н не больше 0\n    то 0\n    иначе «Вниз» от (н минус 1)\n",
  )
  assert.deepEqual(итог.беды, [])
  assert.equal(итог.точных, 1)
  assert.equal(итог.сторожей, 0)
})

test("структурное убывание сильнее и побеждает: натуральное его не перебивает", () => {
  const итог = счёт(
    "модуль «М»\n\nтотальная функция «Длина»\n  принимает ряд: список числа, н: нат\n  возвращает число\n"
      + "  разбор ряд\n    случай пусто\n      то н\n"
      + "    случай голова и хвост\n      «Длина» от хвост и н\n",
  )
  assert.deepEqual(итог.беды, [])
  assert.equal(итог.точных, 0, "доказано структурой — она дешевле и идёт первой")
  assert.equal(итог.сторожей, 0)
})

