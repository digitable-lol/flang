test("натуральное втекает в число: `нат` годится там, где объявлено `число`", () => {
  const итог = проверить(
    "модуль «М»\n\n"
      + "функция «Берёт число»\n  принимает х: число\n  возвращает число\n  х\n\n"
      + "функция «Даёт»\n  принимает н: нат\n  возвращает число\n  «Берёт число» от н\n",
  )
  assert.deepEqual(итог.diagnostics, [])
})

test("число в натуральное НЕ втекает: обратного вложения нет", () => {
  const итог = проверить(
    "модуль «М»\n\n"
      + "функция «Берёт нат»\n  принимает н: нат\n  возвращает число\n  н\n\n"
      + "функция «Даёт»\n  принимает х: число\n  возвращает число\n  «Берёт нат» от х\n",
  )
  assert.deepEqual(коды(итог), ["FLANG_TYPE"])
  assert.match(тексты(итог)[0], /ожидался нат, получен число/u)
})

test("целое между ними: нат ≤ целое ≤ число, и ни одно вложение не обратимо", () => {
  const годится = проверить(
    "модуль «М»\n\n"
      + "функция «Берёт целое»\n  принимает ц: целое\n  возвращает число\n  ц\n\n"
      + "функция «Даёт»\n  принимает н: нат\n  возвращает число\n  «Берёт целое» от н\n",
  )
  assert.deepEqual(годится.diagnostics, [])

  const негодится = проверить(
    "модуль «М»\n\n"
      + "функция «Берёт нат»\n  принимает н: нат\n  возвращает число\n  н\n\n"
      + "функция «Даёт»\n  принимает ц: целое\n  возвращает число\n  «Берёт нат» от ц\n",
  )
  assert.deepEqual(коды(негодится), ["FLANG_TYPE"])
})

test("список ковариантен: `список нат` годится там, где ждут `список числа`", () => {
  const итог = проверить(
    "модуль «М»\n\n"
      + "функция «Берёт»\n  принимает ряд: список числа\n  возвращает число\n  длина ряд\n\n"
      + "функция «Даёт»\n  принимает ряд: список нат\n  возвращает число\n  «Берёт» от ряд\n",
  )
  assert.deepEqual(итог.diagnostics, [])
})

