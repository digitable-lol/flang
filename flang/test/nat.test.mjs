/**
 * Тесты точного натурального типа `нат`.
 *
 * Проверяется четыре разных утверждения, и они не заменяют друг друга:
 *
 *   ПОДТИПИЗАЦИЯ  `нат` втекает в `число`, `число` в `нат` — нет. Это то самое
 *                 второе отношение совместимости, которого у языка не было.
 *   ОТРЕЗКИ       арифметика считает границы, а переполнение расширяет тип, а
 *                 не отказывает и не ставит сторожа.
 *   СТОРОЖ        объявленный `нат` снимает сторожа с постоянного шага, и снятие
 *                 меряется числом, а не наблюдается глазами.
 *   СОГЛАСИЕ      два списка имён (`types.mjs` и `totality.mjs`) совпадают.
 *                 Разойтись они могут молча — и тогда `нат` перестанет работать,
 *                 не сказав об этом.
 *
 * Запуск: node --test flang/test/nat.test.mjs
 */
import assert from "node:assert/strict"
import { test } from "node:test"

import { parse } from "../src/parser.mjs"
import { checkTotality, ТОЧНЫЕ_ИМЕНА } from "../src/totality.mjs"
import { checkTypes, ИМЕНА_НАТ, ИМЕНА_ЦЕЛОГО, ТОЧНАЯ_СЕТКА, typeName } from "../src/types.mjs"
import { занятость } from "../scripts/word-occupancy.mjs"

const проверить = (исходник) => checkTypes(parse(исходник))
const коды = (итог) => итог.diagnostics.map((d) => d.code)
const тексты = (итог) => итог.diagnostics.map((d) => d.message)

/* ================================================================== */
/* Слово                                                               */
/* ================================================================== */

test("ни одно имя уточнения не стало ключевым словом", () => {
  /* Занятость слов мерена ДО заведения (`flang/scripts/word-occupancy.mjs`):
     голым именем в корпусе было НОЛЬ у каждого — «нат», «натуральное»,
     «целое», «nat», «naturo», «自然数», «integer», «entjero». Повторить тот
     замер здесь уже нельзя: теперь эти слова стоят в корпусе голыми законно,
     именами типов, и их там десятки.
     Проверяемым осталось то, на чём держится всё остальное: ключевыми они не
     стали. Стань — и поток токенов каждой написанной программы изменился бы, а
     `self/lexer.flang` разошёлся бы с эталоном побайтово. */
  for (const слово of [...ИМЕНА_НАТ, ...ИМЕНА_ЦЕЛОГО]) {
    assert.equal(занятость(слово, []).ключевое, null, `«${слово}» стало ключевым словом`)
  }
})

test("имена типа не стали ключевыми словами: лексер и парсер не изменились", () => {
  /* Уточнение входит в язык через `namedOrScalar`, а не через таблицу лексера.
     Проверяется это тем, что разбор даёт ОБЫЧНЫЙ именной тип — тот же узел,
     каким разбирается «Возможно». Стань `нат` ключевым — узел стал бы другим,
     и `self/parser.flang` разошёлся бы с эталоном побайтово. */
  const программа = parse("модуль «М»\n\nфункция «Ф»\n  принимает н: нат\n  возвращает число\n  н\n")
  assert.deepEqual(программа.functions[0].params[0].type, { kind: "named", name: "нат" })
})

