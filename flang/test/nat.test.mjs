test("списки имён натурального в типизаторе и в анализе завершаемости совпадают", () => {
  /* Круг импортов не даёт анализу позвать типизатор, поэтому список имён
     записан дважды. Разойтись он может молча: объявленный `нат` просто
     перестанет снимать сторожа, и ни одна проверка об этом не скажет. Этот
     тест — то единственное место, где расхождение становится отказом. */
  assert.deepEqual([...ТОЧНЫЕ_ИМЕНА].sort(), [...ИМЕНА_НАТ].sort())
})

test("границы точной сетки — те самые, что мерены на double", () => {
  /* `х минус 1` впервые не меняет `х` на 2^54; ниже 2^53 соседние целые
     различимы. Проверка считает это на самих числах, а не повторяет число
     словами. */
  assert.equal(ТОЧНАЯ_СЕТКА.верх, 2 ** 53 - 1)
  assert.equal(ТОЧНАЯ_СЕТКА.низ, -(2 ** 53 - 1))
  assert.notEqual(ТОЧНАЯ_СЕТКА.верх - 1, ТОЧНАЯ_СЕТКА.верх)
  assert.equal(2 ** 54 - 1, 2 ** 54)
})

test("имена целого не пусты и не пересекаются с именами натурального", () => {
  assert.ok(ИМЕНА_ЦЕЛОГО.includes("целое"))
  for (const имя of ИМЕНА_ЦЕЛОГО) assert.ok(!ИМЕНА_НАТ.includes(имя), `имя «${имя}» означает два типа сразу`)
})

test("оба уточнения печатаются теми же словами, какими пишутся в объявлении", () => {
  /* Сообщение об ошибке обязано быть таким, чтобы его можно было скопировать в
     программу. Посчитанный отрезок называется поэтому самым узким из трёх имён. */
  assert.equal(typeName({ kind: "number" }), "число")
  assert.equal(typeName({ kind: "number", целое: true, низ: 0, верх: 10 }), "нат")
  assert.equal(typeName({ kind: "number", целое: true, низ: -5, верх: 5 }), "целое")
  assert.equal(typeName({ kind: "list", of: { kind: "number", целое: true, низ: 0, верх: 3 } }), "список нат")
})
