/**
 * Тесты непустоты — нижней границы длины у списка и у строки.
 *
 * Форма та же, что у точного типа `нат`, и по той же причине: `нат` — не новый
 * вид значения, а уточнение `число` отрезком; непустота — не новый вид
 * значения, а уточнение списка и строки одним числом. Значение остаётся тем же
 * массивом и той же строкой, и все места языка, решающие по `kind`, работают
 * не изменившись.
 *
 * Проверяется пять разных утверждений, и они не заменяют друг друга:
 *
 *   ПОСТРОЕНИЕ  длина известна из того, ЧЕМ значение построено: литерал,
 *               `добавить`, `соединить`, `символы`, `разделить`, `хвост`.
 *   СУЖЕНИЕ     `если пусто л то … иначе <здесь л непуст>` кладёт границу так
 *               же, как её кладут числовые сравнения.
 *   ПЕЧАТЬ      где доказано, напечатанный код зовёт помощника БЕЗ сторожа, и
 *               это видно числом, а не глазами.
 *   БЕЗОПАСНОСТЬ уточнение обязано ТЕРЯТЬСЯ там, где перестаёт быть верным:
 *               в ветвях `если`, в накопителе свёртки, за границей функции.
 *               Каждая потеря — свой тест: снятая по ошибке проверка это отказ,
 *               которого больше никто не поймает.
 *   ОХВАТ       снимается ровно четыре формы из восьми, и остальные четыре
 *               названы вместе с тем, чем доказывались бы они.
 *
 * Запуск: node --test flang/test/nonempty.test.mjs
 */
import assert from "node:assert/strict"
import { test } from "node:test"

import { emitJs } from "../src/emit/js.mjs"
import { ЧАСТИЧНЫЕ } from "../src/failures.mjs"
import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { СНИМАЮТСЯ_НЕПУСТОТОЙ } from "../src/builtins.mjs"
import { checkTypes, markProven } from "../src/types.mjs"

const МОДУЛЬ = "модуль «М»\n\n"
const проверить = (исходник) => checkTypes(parse(МОДУЛЬ + исходник))
const коды = (итог) => итог.diagnostics.map((d) => d.code)

/** Сколько мест частичных форм доказано в этой программе. */
const доказано = (исходник) => проверить(исходник).доказаны.size

/** Сколько мест частичных форм в ней всего. */
function мест(исходник) {
  let счёт = 0
  const обойти = (узел) => {
    if (Array.isArray(узел)) { for (const э of узел) обойти(э); return }
    if (узел === null || typeof узел !== "object") return
    if (узел.kind === "builtin" && ЧАСТИЧНЫЕ.has(узел.name)) счёт += 1
    for (const [к, з] of Object.entries(узел)) {
      if (к === "span" || к === "meta") continue
      if (з !== null && typeof з === "object") обойти(з)
    }
  }
  обойти(parse(МОДУЛЬ + исходник).functions)
  return счёт
}

