/** Сколько раз имя помощника вызвано в напечатанном JavaScript. */
function вызовов(исходник, помощник) {
  const программа = markProven(parse(МОДУЛЬ + исходник))
  const код = emitJs(программа).files.map((файл) => файл.content).join("\n")
  return код.split(`${помощник}(`).length - 1
}

test("доказанное место печатается помощником БЕЗ сторожа, недоказанное — со сторожем", () => {
  const доказан = "тотальная функция «Ф»\n  принимает л: список числа\n  возвращает число\n  голова (добавить 7 к л)\n"
  const нет = "тотальная функция «Ф»\n  принимает л: список числа\n  возвращает число\n  голова л\n"
  /* Первый вызов — само место; помощник объявлен в рантайме, и его объявление
     в счёт не идёт: считаются вызовы «имя(», а объявление печатается как
     `function имя(`. Поэтому у доказанного места вызовов сторожа НОЛЬ. */
  assert.equal(вызовов(доказан, "$b_golova"), 0, "у доказанного места сторожа нет")
  assert.ok(вызовов(доказан, "$b_golova_dokazano") > 0, "и есть путь без сторожа")
  assert.ok(вызовов(нет, "$b_golova") > 0, "у недоказанного сторож остался")
  assert.equal(вызовов(нет, "$b_golova_dokazano"), 0, "и пути без сторожа нет")
})

test("помощник без сторожа отказа частичности не содержит вовсе", () => {
  /* Изъятие для теста выше: без этой проверки «снято» значило бы «переименовано»
     — тест был бы зелен и на помощнике, где сторож остался под другим именем. */
  const исходник = "тотальная функция «Ф»\n  принимает л: список числа\n  возвращает число\n  голова (добавить 7 к л)\n"
  const код = emitJs(markProven(parse(МОДУЛЬ + исходник))).files.map((файл) => файл.content).join("\n")
  const начало = код.indexOf("function $b_golova_dokazano(")
  assert.ok(начало >= 0, "помощник без сторожа обязан быть напечатан")
  const тело = код.slice(начало, код.indexOf("\n}", начало))
  assert.ok(!тело.includes("список пуст"), "сторож частичности обязан быть снят, а не переименован")
})

test("отметка невидима там, где доказывать нечего: тот же объект программы", () => {
  /* Программа без доказанных мест обязана проходить насквозь ТЕМ ЖЕ объектом:
     иначе печать разошлась бы там, где ничего не менялось.

     Пример подобран так, чтобы доказывать было нечего ОБЕИМ отметкам разом.
     Раньше здесь стояло `н плюс 1` — оно годилось, пока отметка была одна;
     теперь у арифметики доказан тип обоих операндов, и такая программа честно
     помечается. Значит и пример обязан обойтись без чисел вовсе. */
  const без = parse(МОДУЛЬ + "тотальная функция «Ф»\n  принимает т: строка\n  возвращает строка\n  соединить т с \"!\"\n")
  assert.equal(markProven(без), без, "программы без доказуемых мест не трогаются вовсе")
  const недоказанная = parse(МОДУЛЬ + "тотальная функция «Ф»\n  принимает л: список строки\n  возвращает строка\n  голова л\n")
  assert.equal(markProven(недоказанная), недоказанная, "и программы, где ни одно место не снято")
})

test("доказанное место даёт ТОТ ЖЕ ответ, что интерпретатор", () => {
  /* Главная сверка непустоты: снятая проверка обязана быть снята потому, что
     ей нечего ловить, а не потому, что ответ стал другим. */
  const исходник =
    "тотальная функция «Ф»\n  принимает л: список числа\n  возвращает число\n  голова (добавить 7 к л)\n"
  const программа = markProven(parse(МОДУЛЬ + исходник))
  assert.equal(evaluate(программа, "Ф", { "л": [] }), 7, "пустой список — тот самый случай, где сторож стоял")
  assert.equal(evaluate(программа, "Ф", { "л": [1, 2] }), 1)
})

