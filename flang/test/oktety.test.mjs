/** Где лежит `initdb`, если он вообще есть. */
function путьКPostgres() {
  const свои = ["/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/16/bin", "/usr/local/pgsql/bin"]
  for (const каталог of свои) {
    if (existsSync(join(каталог, "initdb"))) return каталог
  }
  try {
    const где = execFileSync("sh", ["-c", "command -v initdb"], { encoding: "utf8" }).trim()
    if (где !== "") return где.replace(/\/initdb$/, "")
  } catch {
    /* нет — значит нет */
  }
  return null
}

/** Стартовое сообщение протокола 3.0: длина, версия, пары «ключ, значение». */
function стартовое(пользователь, база) {
  const пары = Buffer.from(`user\0${пользователь}\0database\0${база}\0\0`, "utf8")
  const голова = Buffer.alloc(8)
  голова.writeInt32BE(8 + пары.length, 0)
  голова.writeInt32BE(196608, 4)
  return Buffer.concat([голова, пары])
}

/** Простой запрос: 'Q', длина, текст, нуль. */
function запрос(текст) {
  const тело = Buffer.from(`${текст}\0`, "utf8")
  const голова = Buffer.alloc(5)
  голова.write("Q", 0, "latin1")
  голова.writeInt32BE(4 + тело.length, 1)
  return Buffer.concat([голова, тело])
}

/** Конец очереди: 'Z' с длиной 5 — ReadyForQuery. */
const готовК = (буфер) =>
  буфер.length >= 6 && буфер[буфер.length - 6] === 0x5a && буфер.readInt32BE(буфер.length - 5) === 5

/** Разложить поток на сообщения протокола: тег и длина у каждого. */
function сообщения(буфер) {
  const итог = []
  let место = 0
  while (место + 5 <= буфер.length) {
    const длина = буфер.readInt32BE(место + 1)
    if (длина < 4 || место + 1 + длина > буфер.length) break
    итог.push({ тег: String.fromCharCode(буфер[место]), длина, от: место, до: место + 1 + длина })
    место += 1 + длина
  }
  return { разобрано: итог, хвост: буфер.length - место }
}

test("НАСТОЯЩИЙ POSTGRESQL: полный сеанс через октетные поручения, ни одного знака замены", async (t) => {
  const каталогPg = путьКPostgres()
  if (каталогPg === null) {
    /* Пропуск СЛОВАМИ, а не молчанием: проверка, которой не дали предмета,
       обязана сказать об этом, иначе зелёное поле врёт про охват. */
    t.skip("нет initdb — настоящий PostgreSQL не поднять; октеты проверены на всех 256 значениях выше")
    return
  }
  const дом = mkdtempSync(join(tmpdir(), "flang-pg-"))
  const данные = join(дом, "данные")
  /* Каталог сокета — КОРОТКИЙ: путь к домену UNIX у PostgreSQL ограничен 107
     октетами, а временный каталог теста легко длиннее. */
  const сокеты = mkdtempSync(join(tmpdir(), "fpg-"))
  const порт = 55000 + (process.pid % 4000)
  let сервер = null
  const исполнить = nodeHost({})
  try {
    execFileSync(join(каталогPg, "initdb"), ["-D", данные, "-A", "trust", "-U", "flang", "--encoding=UTF8", "--locale=C"], {
      stdio: "pipe",
    })
    сервер = spawn(
      join(каталогPg, "postgres"),
      ["-D", данные, "-p", String(порт), "-k", сокеты, "-c", "listen_addresses=127.0.0.1"],
      { stdio: "pipe" },
    )
    /* Ждём, пока порт заговорит. Не таймером «на глазок»: стучимся до успеха. */
    const дождаться = async () => {
      for (let попытка = 0; попытка < 200; попытка += 1) {
        const открылось = await new Promise((готово) => {
          const проба = createConnection({ host: "127.0.0.1", port: порт })
          проба.once("connect", () => {
            проба.destroy()
            готово(true)
          })
          проба.once("error", () => готово(false))
        })
        if (открылось) return true
        await new Promise((готово) => setTimeout(готово, 100))
      }
      return false
    }
    assert.ok(await дождаться(), "PostgreSQL не поднялся на своём порту")

    const пуск = стартовое("flang", "postgres")
    const текстЗапроса = "select 1 as один, 'здравствуй' as слово"

    /* ── эталон: голый сокет, октеты как есть ─────────────────────────────── */
    const эталон = await new Promise((решить, отказать) => {
      const куски = []
      const сокет = createConnection({ host: "127.0.0.1", port: порт })
      let шаг = 0
      сокет.on("connect", () => сокет.write(пуск))
      сокет.on("data", (кусок) => {
        куски.push(кусок)
        if (!готовК(Buffer.concat(куски))) return
        if (шаг === 0) {
          шаг = 1
          сокет.write(запрос(текстЗапроса))
        } else {
          сокет.end()
        }
      })
      сокет.on("close", () => решить(Buffer.concat(куски)))
      сокет.on("error", отказать)
    })

    /* ── подопытный: тот же сеанс, но через хозяина языка ─────────────────── */
    const открыто = await исполнить(variant("Открыть соединение", { адрес: "127.0.0.1", порт }))
    assert.equal(открыто.variant, "Соединение открыто", JSON.stringify(открыто))
    const соединение = открыто.fields["соединение"]

    const писать = async (буфер) => {
      const отклик = await исполнить(
        variant("Ответить октетами в соединение", { соединение, октеты: [...буфер] }),
      )
      assert.equal(отклик.variant, "Записано", JSON.stringify(отклик))
      assert.equal(отклик.fields["сколько"], буфер.length)
    }
    const читатьДоГотовности = async () => {
      const куски = []
      for (;;) {
        const отклик = await исполнить(variant("Прочитать октеты из соединения", { соединение }))
        assert.equal(отклик.variant, "Октеты", JSON.stringify(отклик))
        const кусок = отклик.fields["октеты"]
        if (кусок.length === 0) break
        куски.push(...кусок)
        if (готовК(Buffer.from(куски))) break
      }
      return Buffer.from(куски)
    }

    await писать(пуск)
    const первый = await читатьДоГотовности()
    await писать(запрос(текстЗапроса))
    const второй = await читатьДоГотовности()
    const принято = Buffer.concat([первый, второй])

    /* ── сверка ───────────────────────────────────────────────────────────── */
    const разборЭталона = сообщения(эталон)
    const разборПринятого = сообщения(принято)
    t.diagnostic(
      `эталон: ${эталон.length} октетов, ${разборЭталона.разобрано.length} сообщений; ` +
        `через хозяина: ${принято.length} октетов, ${разборПринятого.разобрано.length} сообщений`,
    )

    /* Число октетов и разбивка на сообщения ОБЯЗАНЫ совпасть. Сеансы разные
       (у каждого свой ключ отмены и своя метка времени), поэтому байт в байт
       весь поток не сходится — сходятся ДЛИНЫ и ТЕГИ, а это ровно то, что
       ломала кодировка: она меняла и длину, и границы сообщений. */
    assert.equal(принято.length, эталон.length, "через хозяина обязано прийти столько же октетов")
    assert.deepEqual(
      разборПринятого.разобрано.map((с) => `${с.тег}${с.длина}`),
      разборЭталона.разобрано.map((с) => `${с.тег}${с.длина}`),
      "разбивка на сообщения обязана совпасть с эталонной",
    )
    assert.equal(разборПринятого.хвост, 0, "поток обязан разобраться нацело")

    /* ЗНАКОВ ЗАМЕНЫ НОЛЬ — и это не «их не видно», а «их негде взять»: октеты
       никто не раскодировал. Проверяется прямо: последовательности EF BF BD,
       какой знак замены становится в UTF-8, в потоке нет. */
    assert.equal(принято.includes(Buffer.from([0xef, 0xbf, 0xbd])), false, "знак замены в потоке")

    /* ОТВЕТ РАЗОБРАН, а не «что-то приехало»: у сеанса обязаны быть
       AuthenticationOk (R), описание строки (T), сама строка (D) и
       CommandComplete (C) — иначе сверка длин прошла бы и на мусоре. */
    const теги = разборПринятого.разобрано.map((с) => с.тег).join("")
    assert.ok(теги.startsWith("R"), `первое сообщение обязано быть R, а очередь такая: ${теги}`)
    for (const тег of ["T", "D", "C", "Z"]) {
      assert.ok(теги.includes(тег), `в сеансе нет сообщения «${тег}»: ${теги}`)
    }

    /* И САМОЕ ГЛАВНОЕ: строка ответа читается. «здравствуй» приехало из базы
       кириллицей — значит октеты не только сохранились, но и складываются
       обратно в текст, когда программа этого просит. */
    const строкаОтвета = разборПринятого.разобрано.find((с) => с.тег === "D")
    assert.ok(строкаОтвета !== undefined, "в ответе нет строки данных")
    const тело = принято.subarray(строкаОтвета.от + 7, строкаОтвета.до)
    assert.ok(тело.includes(Buffer.from("здравствуй", "utf8")), "в строке ответа нет присланного слова")
    assert.ok(тело.includes(Buffer.from("1", "utf8")), "в строке ответа нет числа")
  } finally {
    исполнить.закрыть()
    if (сервер !== null) {
      сервер.kill("SIGQUIT")
      await new Promise((готово) => сервер.on("close", готово))
    }
    rmSync(дом, { recursive: true, force: true })
    rmSync(сокеты, { recursive: true, force: true })
  }
})

test("УЛИКА НА НАСТОЯЩИХ БАЙТАХ POSTGRESQL: текстовая пара портит их и сегодня", async () => {
  /* Кластер тут не нужен: беда не в сервере, а в трубе. Берётся ТОЧНЫЙ кадр
     протокола — тот, что портится всегда: модификатор типа −1 это FF FF FF FF,
     и длина поля NULL −1 тоже. Проверка держит предмет починки на месте: сними
     октетные поручения — и двоичному протоколу опять нечем ездить. */
  const описаниеСтроки = Buffer.concat([
    /* тег и длина: 35 — это весь кадр без тега, ровно как считает протокол */
    Buffer.from("T", "latin1"),
    Buffer.from([0, 0, 0, 35]),
    /* полей одно, имя поля кириллицей — чтобы в кадре был и законный UTF-8 */
    Buffer.from([0, 1]),
    Buffer.from("слово\0", "utf8"),
    /* таблица, номер столбца, тип «текст» (25) */
    Buffer.from([0, 0, 64, 1, 0, 1, 0, 0, 0, 25]),
    /* длина типа −1 — переменная: FF FF, и это ВСЕГДА */
    Buffer.from([0xff, 0xff]),
    /* модификатор типа −1: FF FF FF FF, и это тоже всегда */
    Buffer.from([0xff, 0xff, 0xff, 0xff]),
    Buffer.from([0, 0]),
  ])
  assert.equal(описаниеСтроки.length, 36)
  const сервер = await отдающий(описаниеСтроки)
  const порт = сервер.address().port
  const исполнить = nodeHost({})
  try {
    const первое = await исполнить(variant("Открыть соединение", { адрес: "127.0.0.1", порт }))
    const текстом = await прочитатьВсё(исполнить, первое.fields["соединение"], false)
    const замен = [...текстом].filter((з) => з.codePointAt(0) === ЗНАК_ЗАМЕНЫ).length
    assert.ok(замен > 0, "кадр PostgreSQL обязан портиться текстовым чтением — иначе предмет починки исчез")
    assert.equal(замен, 6, "шесть октетов 0xFF кадра обязаны стать шестью знаками замены")
  } finally {
    исполнить.закрыть()
    await new Promise((готово) => сервер.close(готово))
  }

  const второйСервер = await отдающий(описаниеСтроки)
  const второйПорт = второйСервер.address().port
  const второйХозяин = nodeHost({})
  try {
    const второе = await второйХозяин(
      variant("Открыть соединение", { адрес: "127.0.0.1", порт: второйПорт }),
    )
    const октетами = await прочитатьВсё(второйХозяин, второе.fields["соединение"], true)
    assert.ok(октетами.equals(описаниеСтроки), "октетное чтение обязано вернуть кадр байт в байт")
    /* Длина, записанная в самом кадре, обязана совпасть с тем, что программа
       сможет посчитать: это и есть та работа, ради которой октеты нужны. */
    assert.equal(октетами.readInt32BE(1) + 1, октетами.length)
    assert.equal(октетами.readInt32BE(октетами.length - 6), -1, "модификатор типа −1 обязан доехать числом")
  } finally {
    второйХозяин.закрыть()
    await new Promise((готово) => второйСервер.close(готово))
  }
})
