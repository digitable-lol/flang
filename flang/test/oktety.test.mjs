const ЗНАК_ЗАМЕНЫ = 0xfffd

/** Поднять сервер, который отдаёт заданные октеты и закрывает связь. */
function отдающий(октеты, покусочно = false) {
  return new Promise((готово) => {
    const сервер = createServer((сокет) => {
      if (!покусочно) {
        сокет.end(октеты)
        return
      }
      /* По одному октету за раз и с паузой: так проверяется, что хозяин
         накапливает, а не теряет границы пакетов. */
      let место = 0
      const дальше = () => {
        if (место >= октеты.length) {
          сокет.end()
          return
        }
        сокет.write(октеты.subarray(место, место + 1))
        место += 1
        setTimeout(дальше, 1)
      }
      дальше()
    })
    сервер.listen(0, "127.0.0.1", () => готово(сервер))
  })
}

/** Прочитать всё до конца связи одним из двух способов. */
async function прочитатьВсё(исполнить, соединение, октетами) {
  const куски = []
  for (;;) {
    const отклик = await исполнить(
      variant(
        октетами ? "Прочитать октеты из соединения" : "Прочитать из соединения",
        { соединение },
      ),
    )
    if (отклик.variant === "Сбой") throw new Error(JSON.stringify(отклик))
    const кусок = октетами ? отклик.fields["октеты"] : отклик.fields["содержимое"]
    if (кусок.length === 0) break
    куски.push(кусок)
  }
  return октетами ? Buffer.from(куски.flat()) : куски.join("")
}

