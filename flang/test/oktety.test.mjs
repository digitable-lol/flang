test("ТЕКСТ ЦЕЛ: кириллица, разрезанная границей пакета, приезжает целой", async () => {
  /* Это ровно то свойство, ради которого в хозяине стоял `setEncoding("utf8")`,
     и снять его было нельзя. Здесь оно проверяется НА РАЗРЕЗЕ: знак «в»
     занимает два октета, и они уезжают разными пакетами. Сломай раскодировщик —
     и вместо «Здравствуй, мир» приедет знак замены. */
  const слово = "Здравствуй, мир — и ещё эмодзи 🙂"
  const октеты = Buffer.from(слово, "utf8")
  const сервер = createServer((сокет) => {
    /* Режем ПОСЕРЕДИНЕ многобайтовой последовательности: третий октет — вторая
       половина буквы «д». */
    сокет.write(октеты.subarray(0, 3))
    setTimeout(() => сокет.end(октеты.subarray(3)), 20)
  })
  await new Promise((готово) => сервер.listen(0, "127.0.0.1", готово))
  const порт = сервер.address().port
  const исполнить = nodeHost({})
  try {
    const открыто = await исполнить(variant("Открыть соединение", { адрес: "127.0.0.1", порт }))
    const текст = await прочитатьВсё(исполнить, открыто.fields["соединение"], false)
    assert.equal(текст, слово)
    assert.equal([...текст].filter((з) => з.codePointAt(0) === ЗНАК_ЗАМЕНЫ).length, 0)
  } finally {
    исполнить.закрыть()
    await new Promise((готово) => сервер.close(готово))
  }
})

