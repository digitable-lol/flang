/**
 * ОКТЕТЫ В ТРУБЕ СОЕДИНЕНИЯ: что теряла пара текстовых поручений и что не
 * теряет пара октетных.
 *
 * Проверка заведена под названную беду, а не «на всякий случай». Беда такая:
 * поручения `«Прочитать из соединения»` и `«Ответить в соединение»` объявлены
 * со `строка`, и хозяин Node раскодировал сокет как UTF-8. Всё, что UTF-8 не
 * является, он заменял знаком U+FFFD, а замена НЕОБРАТИМА. Значит ни один
 * двоичный протокол — PostgreSQL, Redis, gRPC, TLS — на языке не писался.
 *
 * ── Чем эта проверка отличается от «прогнали и зелено» ─────────────────────
 *
 * Она сравнивает то, что обещает, и сравнивает в ОБЕ стороны:
 *
 *   ЧТО СЛОМАНО — на тех же самых байтах текстовая пара обязана ПОТЕРЯТЬ, и
 *      потеря считается числом. Не потеряла — значит проверка меряет не то, о
 *      чём говорит, и красное здесь честнее зелёного;
 *   ЧТО ПОЧИНЕНО — октетная пара обязана вернуть байты РОВНО те же, что ушли,
 *      побайтово, включая нулевые и включая 0xFF.
 *
 * Первое из двух — не украшение. Проверка, у которой нет предмета, зеленеет
 * навсегда: сними починку — и она этого не заметит.
 *
 * ── Три предмета ───────────────────────────────────────────────────────────
 *
 * 1. ВСЕ 256 ОКТЕТОВ. Самый широкий вход, какой бывает: если проезжает каждое
 *    значение байта, то проезжает всякий протокол.
 * 2. НАСТОЯЩИЙ PostgreSQL 17. Кластер поднимается прямо здесь (`initdb` с
 *    доверием), и через хозяина идёт ПОЛНЫЙ сеанс: стартовое сообщение, ответ
 *    сервера, запрос, строки ответа. Сверяется с эталоном — тем же сеансом,
 *    снятым голым сокетом. Нет `initdb` — проверка говорит об этом словами и
 *    пропускается, а не молчит.
 * 3. ТЕКСТ НЕ СЛОМАН. Кириллица, разрезанная границей пакета TCP, обязана
 *    приехать целой — это то самое свойство, ради которого стоял
 *    `setEncoding("utf8")`, и оно сохранено раскодировщиком на соединение.
 *
 * Запуск: node --test flang/test/oktety.test.mjs
 */
import assert from "node:assert/strict"
