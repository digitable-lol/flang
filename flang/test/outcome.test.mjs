const ПРИМЕР = fileURLToPath(new URL("../examples/errors/column-total.flang", import.meta.url))
const исходник = readFileSync(ПРИМЕР, "utf8")
const программа = parse(исходник, "flang/examples/errors/column-total.flang")

const песочница = await mkdtemp(join(tmpdir(), "flang-outcome-"))
after(async () => {
  await rm(песочница, { recursive: true, force: true })
})

/** Разбор с проверкой типов; `null` в программе — не разобралось вовсе. */
function проверить(текст) {
  try {
    const разобрано = parse(текст, "проба.flang")
    return { программа: разобрано, беды: (checkTypes(разобрано).diagnostics ?? []).map((б) => б.code) }
  } catch (беда) {
    return { программа: null, беды: [беда?.code ?? "FLANG_PARSE"] }
  }
}

/* ─────────────────────── 1. чистота: форма не бросает ────────────────────── */

/**
 * Сетка входов. Здесь собрано ровно то, ради чего форма и заводилась:
 * пригодные записи числа, все виды непригодных и тот случай, где заранее
 * написанная проверка неизбежно ошиблась бы, — «1e999» разбирается по правилам
 * записи, но конечным числом не является.
 */
const ВХОДЫ = [
  "0",
  "42",
  "-3",
  "2.5",
  ".5",
  "+7",
  "1e3",
  " 7 ",
  "\t8\n",
  " 9 ",
  "",
  " ",
  "abc",
  "1.",
  "1e",
  "0x10",
  "Infinity",
  "NaN",
  "1e999",
  "-1e999",
  "١٢٣",
  "1 2",
]

test("форма не бросает ни на одном входе, а возвращает вариант", () => {
  for (const вход of ВХОДЫ) {
    const итог = callBuiltin("к числу или беда", [вход])
    assert.ok(
      итог.variant === "Разобрано" || итог.variant === "Не разобрано",
      `${JSON.stringify(вход)} дал ${JSON.stringify(итог)}`,
    )
  }
})

test("текст отказа — дословно тот, которым отказала бы «к числу»", () => {
  let отказов = 0
  for (const вход of ВХОДЫ) {
    const итог = callBuiltin("к числу или беда", [вход])
    if (итог.variant === "Разобрано") {
      assert.equal(итог.fields["значение"], callBuiltin("к числу", [вход]), JSON.stringify(вход))
      continue
    }
    отказов += 1
    assert.throws(
      () => callBuiltin("к числу", [вход]),
      (беда) => {
        assert.equal(итог.fields["код"], беда.code, `код на ${JSON.stringify(вход)}`)
        assert.equal(итог.fields["сообщение"], беда.message, `текст на ${JSON.stringify(вход)}`)
        return true
      },
      JSON.stringify(вход),
    )
  }
  assert.ok(отказов >= 10, `отказов в сетке всего ${отказов} — сетка перестала проверять путь отказа`)
})

test("отказать форма не может даже на аргументе не той формы", () => {
  /* Проверка типов такую программу не пропустит, но `evaluate` со стороны
     подать её может. «Почти не может отказать» здесь ничем не лучше прежнего:
     программа снова не знала бы, надо ли проверять заранее. */
  for (const вход of [5, true, null, [], { поле: 1 }]) {
    const итог = callBuiltin("к числу или беда", [вход])
    assert.equal(итог.variant, "Не разобрано", `${JSON.stringify(вход)}`)
    assert.equal(итог.fields["код"], "FLANG_BUILTIN_ARGS")
  }
})

test("пример разбирается, типизируется и весь тотален", () => {
  const типы = checkTypes(программа)
  assert.deepEqual(типы.diagnostics, [])
  const тотальность = checkTotality(программа)
  assert.deepEqual(тотальность.diagnostics, [])
  for (const функция of программа.functions) {
    assert.ok(тотальность.total.has(функция.name), `«${функция.name}» объявлена тотальной, но не доказана`)
  }
})

test("все примеры примера сходятся — включая путь отказа", () => {
  let счёт = 0
  for (const функция of программа.functions) {
    for (const пример of функция.examples ?? []) {
      счёт += 1
      assert.deepEqual(
        evaluate(программа, функция.name, пример.args),
        пример.expected,
        `«${функция.name}» / «${пример.name}»`,
      )
    }
  }
  assert.equal(счёт, 13, `примеров ${счёт}`)
})

/* ───────────────── 2. тотальность: новой лазейки не появилось ────────────── */

test("рекурсия по полю исхода тотальной не считается", () => {
  /* Значение, вынутое из варианта, который построила ВСТРОЕННАЯ форма, частью
     аргумента не является: «к числу или беда» в число destructors анализа не
     входит и не должна входить. Иначе незавершающаяся программа объявила бы
     себя тотальной. */
  const итог = проверить(
    "модуль «Лазейка»\n\nтотальная функция «Ц»\n  принимает текст: строка\n  возвращает число\n" +
      "  разбор (к числу или беда текст)\n" +
      "    случай вариант «Разобрано» с значение как н\n      то «Ц» от (к строке н)\n" +
      "    случай вариант «Не разобрано» с код как к и сообщение как весть\n      то 0\n",
  )
  assert.notEqual(итог.программа, null, "программа обязана разобраться — отвергает её анализ, а не парсер")
  assert.deepEqual(итог.беды, [])
  const коды = checkTotality(итог.программа).diagnostics.map((б) => б.code)
  assert.deepEqual(коды, ["FLANG_NOT_TOTAL"])
})

/* ─────────────────── 3. те же значения и тексты у печати ─────────────────── */

/** Значение на проводе прогонщика C: число едет строкой, чтобы доехали ±0 и NaN. */
function закодировать(значение) {
  if (значение === null || значение === undefined) return null
  if (typeof значение === "boolean") return значение
  if (typeof значение === "number") return { n: Object.is(значение, -0) ? "-0" : String(значение) }
  if (typeof значение === "string") return { s: значение }
  if (Array.isArray(значение)) return { l: значение.map(закодировать) }
  throw new Error(`нечего кодировать: ${typeof значение}`)
}

function раскодировать(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(раскодировать)
  throw new Error(`нечего декодировать: ${JSON.stringify(узел)}`)
}

/**
 * Сетка вызовов: имя функции и столбец. Одна и та же для всех трёх движков —
 * иначе сверка сверяла бы разное.
 */
const ВЫЗОВЫ = [
  ["Сумма столбца", ["1", "2.5", "-3"]],
  ["Сумма столбца", ["10", "abc", "5"]],
  ["Сумма столбца", [" 7 ", "3"]],
  ["Сумма столбца", []],
  ["Пропущено ячеек", ["1", "abc", "2", ""]],
  ["Первая беда", ["1", "abc", "2"]],
  ["Первая беда", ["1e999"]],
  ["Первая беда", [" 1 ", "0x10"]],
  ["Первая беда", ["1", "2"]],
  ["Код первой беды", ["1", "щ"]],
  ["Код первой беды", ["1"]],
  ["Отчёт", ["10", "abc", "5"]],
  ["Отчёт", ["10", "5"]],
  ["Отчёт", ["", " ", "NaN"]],
]

test("напечатанный C даёт те же значения и те же тексты, что интерпретатор", async (t) => {
  const каталог = join(песочница, "c")
  await mkdir(каталог, { recursive: true })
  const напечатано = emitC(программа, {})
  for (const файл of напечатано.files) await writeFile(join(каталог, файл.path), файл.content, "utf8")
  try {
    execFileSync(
      "cc",
      [
        "-std=c99",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-pedantic",
        ...напечатано.files.filter((файл) => файл.path.endsWith(".c")).map((файл) => файл.path),
        "-o",
        "flang_cli",
        "-lm",
      ],
      { cwd: каталог, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    )
  } catch (беда) {
    if (беда.code === "ENOENT") return t.skip("компилятора C нет")
    assert.fail(`cc не собрал напечатанное:\n${беда.stderr ?? беда.message}`)
  }

  const запросы = ВЫЗОВЫ.map(([имя, столбец]) => JSON.stringify({ fn: имя, args: [закодировать(столбец)] }))
  const вывод = execFileSync(join(каталог, "flang_cli"), { input: `${запросы.join("\n")}\n`, encoding: "utf8" })
  const строки = вывод.split("\n").filter((строка) => строка.length > 0)
  assert.equal(строки.length, ВЫЗОВЫ.length, "прогонщик обязан ответить на каждый запрос ровно один раз")

  ВЫЗОВЫ.forEach(([имя, столбец], номер) => {
    const ответ = JSON.parse(строки[номер])
    assert.ok(ответ.ok, `«${имя}» на ${JSON.stringify(столбец)} отказала: ${ответ.code} ${ответ.message}`)
    assert.deepEqual(
      раскодировать(ответ.value),
      evaluate(программа, имя, { части: столбец }),
      `«${имя}» на ${JSON.stringify(столбец)}`,
    )
  })
})

test("напечатанный JS даёт те же значения и те же тексты, что интерпретатор", async () => {
  /* Модуль — первый файл; второй у цели JS — прогонщик (`flang_cli.js`), и
     здесь он не нужен: функции зовутся прямо из модуля. */
  const напечатано = emitJs(программа, {})
  assert.deepEqual(напечатано.files.map((файл) => файл.path).slice(1), ["flang_cli.js"])
  const путь = join(песочница, `outcome-${напечатано.files[0].path}`)
  await writeFile(путь, напечатано.files[0].content, "utf8")
  const модуль = await import(pathToFileURL(путь).href)

  /* Имя экспорта не угадывается: берётся то единственное, что подходит по
     смыслу. Список экспортов у напечатанного модуля закрыт, и сверять имена —
     работа emit-js.test.mjs, а не эта. */
  const экспорты = Object.entries(модуль).filter(([, значение]) => typeof значение === "function")
  assert.ok(экспорты.length >= ВЫЗОВЫ.length / 2, `экспортов всего ${экспорты.length}`)

  for (const [имя, столбец] of ВЫЗОВЫ) {
    const ожидается = evaluate(программа, имя, { части: столбец })
    const функция = модуль[имяЭкспорта(имя)]
    assert.equal(typeof функция, "function", `в напечатанном модуле нет «${имя}» (${имяЭкспорта(имя)})`)
    assert.deepEqual(функция(столбец), ожидается, `«${имя}» на ${JSON.stringify(столбец)}`)
  }
})

/* Имена экспортов напечатанного JS — camelCase транслитерации; здесь они
   выписаны, а не выведены, ровно чтобы тест падал при переименовании, а не
   молча проверял пустоту. */
const ЭКСПОРТЫ = new Map([
  ["Сумма столбца", "summaStolbca"],
  ["Пропущено ячеек", "propuschenoYacheek"],
  ["Первая беда", "pervayaBeda"],
  ["Код первой беды", "kodPervoyBedy"],
  ["Отчёт", "otchyot"],
])

function имяЭкспорта(имя) {
  const найдено = ЭКСПОРТЫ.get(имя)
  assert.ok(найдено !== undefined, `имя экспорта для «${имя}» не выписано`)
  return найдено
}

/* ──────────────── 4. новых занятых слов не появилось ─────────────────────── */

test("«беда» осталась обычным именем, а «или» стало словом языка", () => {
  /* Здесь стояло «„или“ и „беда“ остались обычными именами», и половина этого
     перестала быть правдой 9 августа 2026: `или` заведено инфиксной операцией
     (`flang/stdlib/logic.flang`). Тест покраснел на этой строке первым — и это
     ровно то, ради чего он написан: цену слова видно там, где её платят.

     Цена измерена и невелика: голых, незакавыченных `или` в позиции имени во
     всех 150 файлах `.flang` и `.fts` репозитория — ноль. Но она НЕ НУЛЕВАЯ, и
     называется здесь прямо: `принимает или: число` больше не разбирается. */
  const итог = проверить(
    "модуль «Имена»\n\nтотальная функция «Проба»\n  принимает беда: число\n" +
      "  возвращает число\n  пусть числу равно беда плюс 1\n  числу\n",
  )
  assert.notEqual(итог.программа, null)
  assert.deepEqual(итог.беды, [])
  assert.equal(evaluate(итог.программа, "Проба", { беда: 3 }), 4)

  const сИли = проверить(
    "модуль «Имена»\n\nтотальная функция «Проба»\n  принимает или: число\n  возвращает число\n  или\n",
  )
  assert.equal(сИли.программа, null, "«или» — слово языка, именем оно больше не бывает")
})

test("фраза из четырёх слов сильнее нового слова «или»", () => {
  /* Главное, чего новое слово НЕ отняло. Склейка идёт от длинной фразы к
     короткой, поэтому `к числу или беда` осталась одним токеном, а не тремя;
     разъедься это — отказ-значение перестал бы разбираться молча. */
  const итог = проверить(
    "модуль «Отказ»\n\nфункция «Проба»\n  принимает текст: строка\n  возвращает число\n" +
      "  разбор (к числу или беда текст)\n" +
      "    случай вариант «Разобрано» с значение как н\n      то н\n" +
      "    случай вариант «Не разобрано» с код как к и сообщение как весть\n      то 0\n",
  )
  assert.notEqual(итог.программа, null, "`к числу или беда` разъехалась на `к числу` + `или` + `беда`")
  assert.deepEqual(итог.беды, [])
})

test("одинокая фраза без аргумента — отказ, а не имя", () => {
  /* У одноместных форм «нет аргумента» значит «это имя переменной» (образец
     `голова и хвост` на том и держится). Фразой из четырёх слов переменную не
     назвать, поэтому здесь молчать нельзя. */
  const итог = проверить(
    "модуль «Пусто»\n\nтотальная функция «Проба»\n  возвращает число\n  к числу или беда\n",
  )
  assert.equal(итог.программа, null)
  assert.deepEqual(итог.беды, ["FLANG_PARSE"])
})

/* ─────── 5. словарь приписывается только тому, кто формой пользуется ─────── */

test("программа без формы даёт побайтово прежний AST", () => {
  const без = parse(
    "модуль «Без исхода»\n\nтотальная функция «Проба»\n  принимает текст: строка\n  возвращает число\n  к числу текст\n",
    "проба.flang",
  )
  assert.deepEqual(без.types, [], "тип исхода приписан программе, которая им не пользуется")
})

test("программа с формой получает тип исхода — и ровно один раз", () => {
  const имена = программа.types.map((тип) => тип.name)
  assert.deepEqual(имена, ["Итог", OUTCOME_TYPE_NAME])
  const исход = программа.types.find((тип) => тип.name === OUTCOME_TYPE_NAME)
  assert.equal(исход.builtin, true, "тип словаря обязан быть помечен встроенным — иначе связывание сочтёт его чужим")
  assert.deepEqual(
    исход.variants.map((в) => в.name),
    ["Разобрано", "Не разобрано"],
  )
})

test("своё объявление важнее словаря: тихой подмены нет", () => {
  /* Та же уступка, что у словаря ввода-вывода: имя, занятое автором, не
     переопределяется молча. Программа получает честную диагностику, а не
     чужой тип под своим именем. */
  const итог = проверить(
    "модуль «Занято»\n\nтип «Исход числа»\n  вариант «Своё» содержит значение: число\n\n" +
      "тотальная функция «Проба»\n  принимает текст: строка\n  возвращает число\n" +
      "  разбор (к числу или беда текст)\n    случай любое\n      то 0\n",
  )
  assert.notEqual(итог.программа, null)
  const свои = итог.программа.types.filter((тип) => тип.name === OUTCOME_TYPE_NAME)
  assert.equal(свои.length, 1, "словарь приписан поверх собственного объявления")
  assert.deepEqual(
    свои[0].variants.map((в) => в.name),
    ["Своё"],
  )
})
