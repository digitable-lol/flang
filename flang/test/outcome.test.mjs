/**
 * Отказ встроенной формы, ставший значением: форма `к числу или беда`.
 *
 * Обоснование самой формы — в `flang/src/builtins.mjs`, раздел «отказ, ставший
 * значением». Здесь проверяется то, что там обещано, и ровно в том же порядке.
 *
 * 1. **Чистота не потеряна.** Форма ничего не бросает и ничего не выполняет —
 *    она СТРОИТ значение обычной суммы. Поэтому путь отказа проверяется обычным
 *    примером, тем же способом, что путь успеха; ровно как `«Сбой»` хозяина
 *    ввода-вывода в `flang/examples/io/link-report.flang`.
 * 2. **Тотальность не ослабла.** Отказ, ставший значением, не даёт нового
 *    способа убывать: поле варианта, полученного из встроенной формы, частью
 *    аргумента не является, и рекурсия по нему тотальной не признаётся.
 * 3. **Тексты совпадают у всех.** Значение и текст отказа обязаны совпасть у
 *    интерпретатора и у печати. Проверяется на C (собирается и запускается
 *    настоящим компилятором) и на JS (напечатанный модуль загружается
 *    настоящим `import`), остальные шесть целей — общими сверками
 *    `emit-*.test.mjs`, куда программа попадает вместе со всеми.
 * 4. **Никого не выселили.** Форма — фраза из четырёх слов, поэтому ни «или»,
 *    ни «беда» ключевыми не стали: файл, где это имена, обязан разбираться.
 * 5. **Словарь приписывается только при использовании.** Программа без этой
 *    формы обязана дать побайтово прежний AST — иначе неподвижная точка
 *    самоприменения сошлась бы к другому компилятору.
 */
