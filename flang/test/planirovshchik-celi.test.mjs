/**
 * Таблица процессов и планировщик узла у ВОСЬМИ целей печати.
 *
 * ── Против какого утверждения написан этот прогон ───────────────────────────
 *
 * В базе знаний стояло прямо: «вторая половина узла — таблица процессов с
 * планировщиком, 219 строк кода — этим приёмом не берётся: она не решает о
 * мире, она ЕСТЬ планировщик». Слой связи переехал на flang и напечатался в
 * восемь целей, а этот кусок был назван непереносимым.
 *
 * Утверждение проверено счётом и оказалось неверным. Тот же блок на конец
 * работы — `flang/conc/distributed.mjs`, строки 380–683 — это 224 строки кода,
 * из которых МИРА пять: `setImmediate` (558), `setTimeout` (493, 494, 623) и
 * два чтения часов (507, 583). Остальные 219 — решения: кто готов бежать,
 * влезет ли письмо в ящик, куда вернуть отложенное, кому уходит отказ.
 *
 * Разница между «решает о мире» и «есть планировщик» настоящая, но проходит она
 * не там, где её провели. Планировщик — это не код, это ТОТ, КТО ДЕРЖИТ
 * УПРАВЛЕНИЕ. Убери из него чтение часов и вызов обработчика по имени (первое —
 * мир, второе — граница языка: передать функцию туда, где она приезжает
 * данными, flang не умеет) — и останутся решения, которые печатаются.
 *
 * Здесь это считается, а не утверждается: `flang/conc/scheduler.flang`
 * печатается в каждую из восьми целей, собирается настоящим тулчейном,
 * запускается — и обязан на каждое событие ответить тем же новым состоянием
 * узла и тем же списком велений.
 *
 * ── Кто здесь свидетель ─────────────────────────────────────────────────────
 *
 * `flang/conc/scheduler.js` — напечатанный модуль цели JavaScript, тот
 * самый, который зовёт настоящий узел. Оговорка та же, что у соседа: сверка
 * «напечатанное с напечатанным» доказывает ПЕРЕНОСИМОСТЬ, а не правильность.
 * Правильность держат прогоны по настоящим сокетам.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 *
 * Ни одного сокета, ни одних часов, ни одного вызова обработчика. Обработчик
 * планировщик не зовёт, а ВЕЛИТ позвать, и его ответ приезжает следующим
 * событием — поэтому спрашивать цель о нём нечего.
 *
 * Запуск: node --test flang/test/planirovshchik-celi.test.mjs
 */
