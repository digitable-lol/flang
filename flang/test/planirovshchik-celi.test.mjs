/* ─────────────────── значения прогонщика ───────────────────
   Протокол ровно тот же, что у соседа (`svyaz-celi.test.mjs`), и это не
   копирование ради удобства: два разных протокола на одну и ту же пару
   «свидетель — напечатанная цель» разошлись бы на первом же числе. Число едет
   строкой, потому что JSON не знает ни NaN, ни бесконечностей, ни знака нуля. */
function вТег(значение) {
  if (значение === null || значение === undefined) return null
  if (typeof значение === "boolean") return значение
  if (typeof значение === "number") return { n: Object.is(значение, -0) ? "-0" : String(значение) }
  if (typeof значение === "string") return { s: значение }
  if (Array.isArray(значение)) return { l: значение.map(вТег) }
  if (typeof значение === "object" && typeof значение.variant === "string") {
    return { v: значение.variant, f: Object.entries(значение.fields).map(([к, з]) => [к, вТег(з)]) }
  }
  return { r: Object.entries(значение).map(([к, з]) => [к, вТег(з)]) }
}

function изТега(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return узел.n === "-0" ? -0 : Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(изТега)
  if (Object.hasOwn(узел, "r")) { const з = {}; for (const [к, э] of узел.r) з[к] = изТега(э); return з }
  if (Object.hasOwn(узел, "v")) { const п = {}; for (const [к, э] of узел.f ?? []) п[к] = изТега(э); return { variant: узел.v, fields: п } }
  throw new Error(`нечего раскодировать: ${JSON.stringify(узел)}`)
}

