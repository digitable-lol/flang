/**
 * Корпус объявлений `план` — проверка САМОГО КОРПУСА, а не эталона.
 *
 * Порядок захода такой: сперва доказать, что корпус РАЗЛИЧАЕТ случаи, и только
 * потом ставить на него дифференциальную сверку эталона. Иначе сверка была бы
 * зелёной от того, что вход у неё пустой, — а таких в этом дереве уже находили.
 *
 * Что здесь утверждается:
 *
 *   • ПОКРЫТИЕ. Каждая из двенадцати веток `ctx.report` свидетеля хотя бы одним
 *     случаем достигнута, и каждое из четырёх применений `сверитьИмяТипа` —
 *     тоже. Первое — про ветки, второе — про то, что двенадцатая ветка не
 *     сходится в один случай.
 *   • РАЗЛИЧИМОСТЬ. Сломанные случаи дают ПОПАРНО РАЗНЫЕ сообщения. Корпус, где
 *     два случая неотличимы, считает себя больше, чем он есть.
 *   • РОВНО ОДНА. У каждого сломанного случая ровно одна диагностика
 *     `FLANG_PLAN`, а у целой программы — ноль. Случай с двумя жалобами сразу
 *     не сказал бы, которая из них его.
 *   • ЧИСТОТА. Кроме `FLANG_PLAN`, корпус не поднимает НИЧЕГО: диагностика о
 *     плане обязана быть единственной причиной, по которой файл красен.
 */
import assert from "node:assert/strict"
import test from "node:test"

import { checkTypes } from "../src/types.mjs"
import {
  ВЕТКИ_СВИДЕТЕЛЯ,
  ПРИМЕНЕНИЯ_СВЕРКИ,
  СЛОВА_БЕЗ_ИМЕНИ,
  корпусПланов,
} from "./corpus-plans.mjs"

const случаи = корпусПланов()
const итоги = случаи.map((случай) => ({
  ...случай,
  все: checkTypes(случай.ast).diagnostics,
}))
const планы = (итог) => итог.все.filter((д) => д.code === "FLANG_PLAN")

const целые = итоги.filter((итог) => планы(итог).length === 0)
const сломанные = итоги.filter((итог) => планы(итог).length > 0)

/**
 * Целых программ ДВЕ, и вторая — не запас, а измеренная нужда.
 *
 * `13-shag-dzhoker.flang` заведена изъятием: эталон, у которого снята ветка
 * «джокер молчит», оставался зелёным на всех шестнадцати сломанных случаях И на
 * единственной настоящей программе дерева. Правильный ответ там — молчание, и
 * поймать пропажу молчания можно только программой, где молчать НАДО.
 */
const ЦЕЛЫЕ = ["fixtures/plany/00-tselyj.flang", "fixtures/plany/13-shag-dzhoker.flang"]

test("корпус: программ в нём столько, сколько заявлено, и целых среди них две", () => {
  assert.ok(случаи.length >= 18, `случаев всего ${случаи.length}`)
  assert.deepEqual(целые.map((итог) => итог.имя), ЦЕЛЫЕ, "целых обязано быть ровно две")
  assert.equal(сломанные.length, случаи.length - ЦЕЛЫЕ.length)
})

test("корпус: у каждого сломанного случая ровно одна диагностика FLANG_PLAN", () => {
  for (const итог of сломанные) {
    assert.equal(планы(итог).length, 1, `${итог.имя}: диагностик плана ${планы(итог).length}`)
  }
})

/**
 * Единственное исключение — джокерный случай: джокер в позиции типа добывается
 * только НЕИЗВЕСТНЫМ ИМЕНЕМ (слово `любое` парсер в этой позиции не принимает),
 * и неизвестное имя свидетель называет своей диагностикой. Она названа здесь
 * поимённо, чтобы «кроме плана ничего» не превратилось молча в «что угодно».
 */
const ПРОЧЕЕ_ПОЗВОЛЕНО = new Map([
  ["fixtures/plany/13-shag-dzhoker.flang", ["FLANG_UNKNOWN_NAME: неизвестный тип «Небывалое»"]],
])

test("корпус: кроме FLANG_PLAN не поднимается ничего, кроме названного поимённо", () => {
  for (const итог of итоги) {
    const прочее = итог.все.filter((д) => д.code !== "FLANG_PLAN")
    assert.deepEqual(
      прочее.map((д) => `${д.code}: ${д.message}`),
      ПРОЧЕЕ_ПОЗВОЛЕНО.get(итог.имя) ?? [],
      `${итог.имя}: лишние диагностики`,
    )
  }
})

test("корпус: все двенадцать веток ctx.report свидетеля достигнуты", () => {
  const тексты = сломанные.map((итог) => планы(итог)[0].message)
  const не_достигнуты = ВЕТКИ_СВИДЕТЕЛЯ.filter(([, узнать]) => !тексты.some((текст) => узнать(текст))).map(
    ([имя]) => имя,
  )
  assert.deepEqual(не_достигнуты, [], "ветки свидетеля без единого случая в корпусе")
  assert.equal(ВЕТКИ_СВИДЕТЕЛЯ.length, 12, "веток ctx.report в io.mjs двенадцать")
})

test("корпус: все четыре применения сверитьИмяТипа достигнуты порознь", () => {
  const тексты = сломанные.map((итог) => планы(итог)[0].message)
  const не_достигнуты = ПРИМЕНЕНИЯ_СВЕРКИ.filter(
    ([, узнать]) => !тексты.some((текст) => узнать(текст)),
  ).map(([имя]) => имя)
  assert.deepEqual(не_достигнуты, [], "применения сверки без случая в корпусе")
})

test("корпус: обе ветви типОдним достигнуты — у типа без имени в сообщение уезжает слово", () => {
  const тексты = сломанные.map((итог) => планы(итог)[0].message)
  for (const слово of СЛОВА_БЕЗ_ИМЕНИ) {
    assert.ok(
      тексты.some((текст) => текст.includes(слово)),
      `ни один случай не даёт ${слово}`,
    )
  }
})

test("корпус: сообщения сломанных случаев попарно различны", () => {
  const видели = new Map()
  for (const итог of сломанные) {
    const текст = планы(итог)[0].message
    const прежний = видели.get(текст)
    assert.equal(прежний, undefined, `${итог.имя} и ${прежний} неотличимы: «${текст}»`)
    видели.set(текст, итог.имя)
  }
  assert.equal(видели.size, сломанные.length)
})

/**
 * Улика, ради которой корпус и заведён, — числом и в одном месте.
 *
 * До него ветки покрывались тремя случаями `io.test.mjs` и одной ЦЕЛОЙ
 * программой дерева. Здесь считается, сколько веток корпус достаёт сам; если
 * счёт поедет вниз, значит корпус сузили, и сверка эталона стала слабее молча.
 */
test("корпус: улика числом — веток достигнуто столько, сколько их в свидетеле", () => {
  const тексты = сломанные.map((итог) => планы(итог)[0].message)
  const достигнуто = ВЕТКИ_СВИДЕТЕЛЯ.filter(([, узнать]) => тексты.some((текст) => узнать(текст))).length
  assert.equal(достигнуто, 12, `веток достигнуто ${достигнуто} из 12`)
  assert.ok(сломанные.length >= 16, `сломанных случаев ${сломанные.length}`)
})
