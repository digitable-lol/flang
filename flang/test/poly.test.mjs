const проверить = (исходник) => checkTypes(parse(исходник))
const коды = (результат) => результат.diagnostics.map((d) => d.code)
const тексты = (результат) => результат.diagnostics.map((d) => d.message)

/** Модуль-заготовка: параметрическая сумма и параметрическая запись. */
const ВОЗМОЖНО = `модуль «Т»

тип «Возможно» от «А»
  вариант «Есть» содержит значение: «А»
  вариант «Ничего»

объект «Пара» от «Первый» и «Второй»
  первое: «Первый»
  второе: «Второй»
`

/* ─────────────────────────────── разбор ──────────────────────────────────── */

test("параметры типа попадают в AST только когда написаны", () => {
  const ast = parse(`${ВОЗМОЖНО}
тип «Токен»
  вариант «Слово» содержит текст: строка
`)
  const возможно = ast.types.find((t) => t.name === "Возможно")
  const пара = ast.types.find((t) => t.name === "Пара")
  const токен = ast.types.find((t) => t.name === "Токен")
  assert.deepEqual(возможно.typeParams, ["А"])
  assert.deepEqual(пара.typeParams, ["Первый", "Второй"])
  /* Главное обещание фазы: у непараметрического объявления поля нет вовсе,
     значит JSON старых программ не меняется ни на байт. */
  assert.equal(Object.hasOwn(токен, "typeParams"), false)
})

test("аргументы типа попадают в AST только когда написаны", () => {
  const ast = parse(`${ВОЗМОЖНО}
тотальная функция «Ф»
  принимает а: «Возможно» от число, б: «Токен или»
  возвращает число
  0

тип «Токен или» это список числа
`)
  const [а, б] = ast.functions[0].params
  assert.deepEqual(а.type, { kind: "named", name: "Возможно", args: [{ kind: "number" }] })
  assert.equal(Object.hasOwn(б.type, "args"), false)
})

test("применение правоассоциативно и совпадает со скобочной записью", () => {
  const без = parse(`${ВОЗМОЖНО}
тотальная функция «Ф»
  принимает а: «Возможно» от «Возможно» от число
  возвращает число
  0
`)
  const со = parse(`${ВОЗМОЖНО}
тотальная функция «Ф»
  принимает а: («Возможно» от («Возможно» от число))
  возвращает число
  0
`)
  assert.deepEqual(без.functions[0].params[0].type, со.functions[0].params[0].type)
})

test("«и» в поле варианта не съедается списком аргументов типа", () => {
  const ast = parse(`${ВОЗМОЖНО}
тип «Обёртка»
  вариант «Внутри» содержит п: «Пара» от число и строка и метка: строка
`)
  const вариант = ast.types.find((t) => t.name === "Обёртка").variants[0]
  /* Два поля, а не одно: `и метка:` — это новое поле, `и строка` — второй
     аргумент типа. Различаются заглядыванием на двоеточие. */
  assert.deepEqual(вариант.fields.map((f) => f.name), ["п", "метка"])
  assert.equal(вариант.fields[0].type.args.length, 2)
})

test("параметры типа функции читаются тем же словом «от»", () => {
  const ast = parse(`${ВОЗМОЖНО}
тотальная функция «Обернуть» от «А»
  принимает значение: «А»
  возвращает «Возможно» от «А»
  вариант «Есть» с значение равным значение
`)
  assert.deepEqual(ast.functions[0].typeParams, ["А"])
})

