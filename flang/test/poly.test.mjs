/**
 * Параметрический полиморфизм: разбор и проверка типов (flang/cat/POLY.md).
 *
 * Тесты идут через настоящий исходник, а не через собранный руками AST: главное
 * обещание первой фазы — что новая форма ЧИТАЕТСЯ и при этом старая читается
 * ровно как раньше, а проверить это можно только поверхностью языка.
 *
 * Запуск: node --test flang/test/poly.test.mjs
 */
import assert from "node:assert/strict"
