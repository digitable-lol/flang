/* ─────────────────────────── печать: стирание ────────────────────────────── */

/**
 * Решение «стирание, а не мономорфизация» держится на одном факте: печать
 * типов не видит. Проверяется прямо, а не рассуждением, — иначе это была бы
 * догадка. Если однажды какой-то бэкенд начнёт печатать объявленный тип в
 * сигнатуру, упадёт этот тест, а не пользователь.
 */
const ДВЕ_ПОДСТАНОВКИ = parse(`${ПОЛНЫЙ}
тотальная функция «Число или ноль»
  принимает опция: «Возможно» от число
  возвращает число
  «Значение или запас» от опция и 0

тотальная функция «Строка или пусто»
  принимает опция: «Возможно» от строка
  возвращает строка
  «Значение или запас» от опция и ""
`)

const напечатать = (печать) =>
  печать(ДВЕ_ПОДСТАНОВКИ, { module: "Т" }).files.map((файл) => файл.content).join("\n")

test("восемь целей печатают полиморфный модуль, не зная о параметрах", () => {
  const цели = [
    ["c", emitC], ["go", emitGo], ["rust", emitRust], ["python", emitPython],
    ["java", emitJava], ["csharp", emitCsharp], ["elixir", emitElixir], ["js", emitJs],
  ]
  for (const [имя, печать] of цели) {
    const файлы = печать(ДВЕ_ПОДСТАНОВКИ, { module: "Т" }).files
    assert.ok(файлы.length > 0, `${имя}: не напечатано ни одного файла`)
    /* Печать не выдаёт диагностик и не бросает: параметры типа до неё просто
       не доходят — их нет в том, что она читает (имена и поля). */
    assert.ok(файлы.every((файл) => типичныйФайл(файл)), `${имя}: файл без имени или без текста`)
  }
})

const типичныйФайл = (файл) => typeof файл?.path === "string" && typeof файл?.content === "string"

test("две подстановки дают одну фабрику варианта, а не две", () => {
  /* Мономорфизация породила бы «Есть» для числа и «Есть» для строки
     раздельно. Стирание даёт одну функцию, потому что значение носит тег, а
     не тип. Это и есть измерение, на котором стоит решение из POLY.md. */
  const счёт = (код, образец) => (код.match(образец) ?? []).length
  assert.equal(счёт(напечатать(emitJs), /\bfunction Est\(/gu), 1)
  assert.equal(счёт(напечатать(emitC), /fl_status t_variant_est\(/gu), 2) // объявление и определение
  /* `VariantEst`, а не `Est`: роль входит в имя, как и в C рядом. Считается
     здесь по-прежнему ОДНА фабрика на две подстановки — приставка про
     стирание ничего не меняет, она про то, что у пакета Go одно пространство
     имён и функция с именем варианта в нём законна. */
  assert.equal(счёт(напечатать(emitGo), /\bVariantEst\(/gu), 1)
})

/* ──────────────────────── старое читается как раньше ─────────────────────── */

test("«от» после имени типа не ломает вызов функции в теле", () => {
  /* `от` — то же слово, что и в применении функции. Разводит их позиция:
     в типе применяется тип, в выражении — функция. */
  const результат = проверить(`модуль «Т»

тотальная функция «Удвоить»
  принимает х: число
  возвращает число
  х плюс х

тотальная функция «Ф»
  принимает х: число
  возвращает число
  «Удвоить» от х
`)
  assert.deepEqual(коды(результат), [])
})
