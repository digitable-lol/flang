/**
 * ПОТОМОК ИЗ ПЛАНА: ввод и срок.
 *
 * Две дыры одного слоя, найденные разными работами, и обе проверяются здесь
 * ПРОГОНОМ настоящего `flang io` над настоящим планом на flang — а не вызовом
 * хозяина мимо языка. Довод простой: обе дыры мерились тем, что работа НЕ
 * ПЕРЕЕХАЛА на flang, значит и починка обязана меряться тем, что переехала.
 *
 * ── Первая: писать в ввод потомка было нечем ────────────────────────────────
 *
 * Поручение «Запустить процесс» отдавало имя и аргументы, приносило код и
 * вывод — а поля под ввод в словаре не было вовсе. Проверка потоковости
 * языкового сервера из-за этого ушла на оболочку.
 *
 * У дыры была вторая половина, которую никто не называл: хозяин заводил потомку
 * ОТКРЫТУЮ трубу ввода и не писал в неё ни байта. Для потомка, читающего свой
 * ввод, это не «ввода нет», а «ввод будет позже», и он ждал — до срока хозяина.
 * Обе половины проверяются здесь по отдельности, потому что чинятся они разным.
 *
 * ── Вторая: срок хозяина не назывался ───────────────────────────────────────
 *
 * Тридцать секунд стояли числом в трёх хозяевах, наружу не выходили никак, а
 * одна сборка релизного C идёт 128 секунд. Ключ проверяется В ОБЕ СТОРОНЫ:
 * мало́ — потомок не успел и пришёл СБОЕМ; поднято — успел. Проверка, которая
 * смотрит только на вторую сторону, зеленела бы и при выброшенном ключе.
 *
 * Запуск: node --test flang/test/potomok.test.mjs
 */
import assert from "node:assert/strict"
import { execFile, spawn } from "node:child_process"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"
import test from "node:test"

const запустить = promisify(execFile)
const корень = fileURLToPath(new URL("../..", import.meta.url))
const команда = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))
const план = fileURLToPath(new URL("../examples/io/potomok.flang", import.meta.url))

/** Прогнать `flang io` и вернуть разобранный вывод вместе с кодом выхода и сроком работы. */
async function прогон(ключи) {
  const начало = Date.now()
  try {
    const { stdout } = await запустить(process.execPath, [команда, "io", план, ...ключи], {
      cwd: корень,
      maxBuffer: 1 << 24,
    })
    return { код: 0, итог: JSON.parse(stdout), мс: Date.now() - начало }
  } catch (ошибка) {
    const текст = ошибка.stdout === "" ? ошибка.stderr : ошибка.stdout
    return { код: ошибка.code ?? 1, итог: JSON.parse(текст), мс: Date.now() - начало }
  }
}

test("ПЛАН НА FLANG ПИШЕТ ПОТОМКУ В ВВОД, и потомок отдаёт написанное обратно", async () => {
  const { код, итог } = await прогон(["--plan", "Эхо через ввод"])
  assert.equal(код, 0, JSON.stringify(итог))
  /* Кириллица тут не для красоты: ввод едет строкой, хозяин пишет её UTF-8,
     потомок отдаёт октеты назад, хозяин читает их UTF-8 — и знак в знак
     совпасть обязано всё. Один потерянный октет здесь виден сразу. */
  assert.equal(итог.result, "здравствуй, мир")
  assert.equal(итог.orders, 1)
  const поручение = итог.log[0]["поручение"]
  assert.equal(поручение.variant, "Запустить процесс с вводом")
  assert.equal(поручение.fields["ввод"], "здравствуй, мир")
  const отклик = итог.log[0]["отклик"]
  assert.equal(отклик.variant, "Процесс завершён")
  assert.equal(отклик.fields["код"], 0)
})

test("УЛИКА: потомок, читающий ввод, кончается сразу — а не ждёт до срока хозяина", async () => {
  /* Тот же `cat`, но БЕЗ ввода. Прежде хозяин давал ему открытую трубу, в
     которую никто не пишет, и `cat` ждал её закрытия — то есть тридцать секунд
     и «Сбой» по сроку. Теперь ввода нет — значит пустота, и конец наступает
     сразу.

     Срок здесь урезан до полутора секунд НАРОЧНО: с ним проверка краснеет за
     полторы секунды вместо тридцати, и краснеет она именно на той беде, о
     которой говорит. Сними правку про `/dev/null` — здесь будет
     FLANG_IO_TIMEOUT. */
  const { код, итог, мс } = await прогон(["--plan", "Чтение без ввода", "--timeout", "1500"])
  assert.equal(код, 0, `потомок без ввода обязан кончиться сам: ${JSON.stringify(итог)}`)
  assert.equal(итог.result, "")
  assert.equal(итог.log[0]["отклик"].variant, "Процесс завершён")
  assert.ok(мс < 1500, `потомок без ввода занял ${мс} мс — он ждал трубы, а не кончился сразу`)
})

test("СРОК НАЗЫВАЕТСЯ КЛЮЧОМ, и проверяется он В ОБЕ СТОРОНЫ", async () => {
  /* Сторона первая: срок мал — потомок не успел, и приходит это ОТКЛИКОМ
     «Сбой» с названным кодом, а не молчанием и не зависанием. */
  const мало = await прогон(["--plan", "Быстрая работа", "--timeout", "400"])
  assert.equal(мало.код, 1, `план обязан сдаться сам: ${JSON.stringify(мало.итог)}`)
  assert.equal(мало.итог.diagnostics?.[0]?.code, "FLANG_IO_TIMEOUT", JSON.stringify(мало.итог))
  assert.match(мало.итог.error, /не уложилась в 400 мс/)
  assert.ok(мало.мс < 3000, `отказ по сроку 400 мс занял ${мало.мс} мс — срок не дошёл до хозяина`)

  /* Сторона вторая: срок поднят — тот же потомок успел. Без неё проверка
     зеленела бы и на ключе, который просто всё роняет. */
  const хватит = await прогон(["--plan", "Быстрая работа", "--timeout", "8000"])
  assert.equal(хватит.код, 0, JSON.stringify(хватит.итог))
  assert.equal(хватит.итог.log[0]["отклик"].variant, "Процесс завершён")
  assert.ok(хватит.мс >= 2000, `потомок на две секунды занял ${хватит.мс} мс — он не работал`)
})

test("ГЛАВНАЯ МЕРА: потомок живёт ДОЛЬШЕ тридцати секунд, когда срок поднят", async (t) => {
  /* Ровно тот случай, из-за которого сборка осталась на JavaScript: работа
     честно длиннее умолчания. Тридцать одна секунда взята потому, что она
     БОЛЬШЕ тридцати — на меньшем числе проверка ничего бы не сказала.

     Умолчание при этом остаётся тем же и проверено выше по коду: срок обязан
     быть, иначе `flang io` висит навсегда на программе, которая ждёт ввода. */
  const { код, итог, мс } = await прогон(["--plan", "Долгая работа", "--timeout", "90000"])
  t.diagnostic(`потомок на 31 с при сроке 90 000 мс: ${мс} мс, код выхода ${код}`)
  assert.equal(код, 0, JSON.stringify(итог))
  assert.equal(итог.log[0]["отклик"].variant, "Процесс завершён")
  assert.equal(итог.log[0]["отклик"].fields["код"], 0)
  assert.ok(мс > 30_000, `работа заняла ${мс} мс — она не перешагнула прежнее умолчание`)
})

test("ПРОВЕРКА ИМЕЕТ ЗУБЫ: без ключа тот же потомок умирает на умолчании в 30 с", async (t) => {
  /* Изъятие рычага. Тот же план без `--timeout` обязан упереться в 30 000 мс —
     иначе всё выше зеленело бы и при выброшенном умолчании, то есть проверяло
     бы не срок, а способность `sleep` кончиться. */
  const { код, итог, мс } = await прогон(["--plan", "Долгая работа"])
  t.diagnostic(`тот же потомок без ключа: ${мс} мс, код выхода ${код}`)
  assert.equal(код, 1, JSON.stringify(итог))
  assert.equal(итог.diagnostics?.[0]?.code, "FLANG_IO_TIMEOUT")
  assert.match(итог.error, /не уложилась в 30000 мс/)
})

test("кривой срок — кривой вызов, а не тихое умолчание", async () => {
  for (const плохой of ["0", "-5", "много", "1.5"]) {
    const итог = await new Promise((готово) => {
      const дитя = spawn(process.execPath, [команда, "io", план, "--timeout", плохой], { cwd: корень })
      let ошибки = ""
      дитя.stderr.on("data", (кусок) => {
        ошибки += кусок
      })
      дитя.on("close", (код) => готово({ код, ошибки }))
    })
    /* Код 2 — «кривой вызов», тот же, каким отвечает всякий негодный ключ.
       Молча взять умолчание значило бы исполнить не то, о чём попросили. */
    assert.equal(итог.код, 2, `--timeout ${плохой} обязан быть кривым вызовом`)
    assert.match(итог.ошибки, /--timeout/)
  }
})
