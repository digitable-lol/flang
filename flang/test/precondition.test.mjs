/**
 * Предусловие `требует` — слово, которым в языке ОГРАНИЧИВАЮТ вход.
 *
 * ── Что здесь проверяется ───────────────────────────────────────────────────
 * Четыре вещи, и ни одна не про то, что слово «есть»:
 *
 *   СНИМАЕТ ВЫЗЫВАЮЩИЙ  вызов, который условия не снимает, ОТВЕРГНУТ поимённо.
 *                       Это половина смысла слова: без обязательства на
 *                       вызывающем предусловие было бы обещанием, за которым
 *                       ничего не стоит.
 *   ДОПУЩЕНИЕ В ЯДРЕ    внутри тела предусловие — известный факт, и на нём ядро
 *                       доказывает то, чего без него доказать нельзя. Вторая
 *                       половина, и проверяется она ИЗЪЯТИЕМ: снимите строку —
 *                       и доказательство краснеет.
 *   ГРАНИЦА             вход, пришедший снаружи (`--args`, пример), проверяется
 *                       вычислением: там доказывать нечего.
 *   ЦЕНА В ПЕЧАТИ РАВНА НУЛЮ  та же программа с `требует` и без него печатается
 *                       ПОБАЙТОВО одинаково во все восемь целей. Это и было
 *                       возражение, из-за которого слова не заводили; здесь оно
 *                       измерено, а не обещано.
 *
 * ── Почему у каждой проверки есть близнец-изъятие ───────────────────────────
 * Проверка, которая не умеет краснеть, — строка в отчёте. Поэтому у всякого
 * «так работает» ниже стоит пара «изымем то, что стережём».
 */
import assert from "node:assert/strict"
import test from "node:test"

import { obligations } from "../src/obligations.mjs"
import { parse } from "../src/parser.mjs"
import { АКСИОМЫ, checkProofs, снятьПредусловия } from "../src/proofterm.mjs"
import { checkTypes } from "../src/types.mjs"
import { evaluate } from "../src/interpret.mjs"
import { emitTargets, loadEmitter } from "../bin/flang.mjs"

/** Диагностики типизатора без предупреждений. */
function типы(исходник) {
  const беды = (checkTypes(parse(исходник, "проба.flang")).diagnostics ?? []).filter((б) => б.severity !== "warning")
  return { коды: беды.map((б) => б.code), тексты: беды.map((б) => б.message) }
}

/** Полная цепочка: разбор → обязательства → ядро. Возвращает диагностики ядра. */
function ядро(исходник) {
  const программа = parse(исходник, "проба.flang")
  const итог = obligations(программа)
  const вердикты = checkProofs(программа, итог.obligations)
  return { программа, обязательства: итог.obligations, вердикты }
}

/* ── Стопка с предусловием: база разбора возвращает ПАРАМЕТР ────────────────
   Тот самый случай, который до `требует` не закрывался ничем: примером нельзя
   (имя связано, значений бесконечно много), предположением индукции нельзя (у
   «Пусто» нет полей типа самой суммы). */
const СТОПКА = `модуль «М»

тип «Стопка»
  вариант «Пусто»
  вариант «Звено» содержит голова: число, хвост: «Стопка»

тотальная функция «Высота от дна»
  принимает стопка: «Стопка», дно: число
  возвращает число
  требует «дно неотрицательно» дно не меньше 0
  для всех стопка обеспечивает «высота от дна неотрицательна» результат не меньше 0
  пример «пустая от нуля»
    дано стопка равно вариант «Пусто»
    дано дно равно 0
    ожидается 0
  разбор стопка
    случай вариант «Пусто»
      то дно
    случай вариант «Звено» с голова как г и хвост как х
      то («Высота от дна» от х и дно) плюс 1

теорема «высота от дна неотрицательна»
  дано стопка: «Стопка»
  дано дно: число
  утверждаем результат не меньше 0
  индукция по стопка
    случай вариант «Пусто»
      то по предположению
    случай вариант «Звено» с голова как г и хвост как х
      то по предположению
  следовательно доказано
`

// ── поверхность и AST ──────────────────────────────────────────────────────

test("предусловие едет в AST своим полем, и `результат` в нём не связан", () => {
  const программа = parse(СТОПКА, "стопка.flang")
  const [предусловие] = программа.functions[0].preconditions
  assert.equal(предусловие.name, "дно неотрицательно")
  assert.equal(предусловие.code, "FLANG_PRECONDITION")
  assert.equal(предусловие.expr.kind, "binary")
  assert.equal(предусловие.expr.op, "gte")
  /* `bind` у постусловия есть, у предусловия его нет и быть не может:
     результата до вызова не существует. Разница между двумя словами ровно в
     этом, и она обязана быть видна в дереве. */
  assert.ok(!("bind" in предусловие), "предусловие связало «результат», которого до вызова нет")
})

test("предусловия у функции нет — и поля в AST нет тоже", () => {
  /* Изъятие того, что стережёт побайтовую неподвижную точку самоприменения:
     программа без `требует` обязана давать РОВНО прежний AST. */
  const без = parse(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n  н плюс 1\n",
    "без.flang",
  )
  assert.ok(!("preconditions" in без.functions[0]), "поле появилось у функции без предусловия")
})

test("`результат` внутри предусловия — несвязанное имя, а не молчаливо принятое", () => {
  const { коды, тексты } = типы(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + "  требует «п» результат не меньше 0\n  н\n",
  )
  assert.deepEqual(коды, ["FLANG_UNKNOWN_NAME"], тексты.join(" | "))
})

test("предусловие обязано быть признаком", () => {
  const { коды, тексты } = типы(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + "  требует «п» н плюс 1\n  н\n",
  )
  assert.deepEqual(коды, ["FLANG_TYPE"], тексты.join(" | "))
  assert.match(тексты[0], /предусловие «п» даёт число, а предусловие обязано быть признаком/u)
})

// ── ПОДДЕЛКА 1: предусловие, которое не выполняется у вызывающего ──────────

test("подделка: вызов, который предусловия не снимает, отвергнут и назван", () => {
  const { вердикты } = ядро(
    "модуль «М»\n\nтотальная функция «Взять»\n  принимает н: число\n  возвращает число\n"
      + "  требует «вход неотрицателен» н не меньше 0\n  н плюс н\n\n"
      + "тотальная функция «Зовёт мимо»\n  принимает м: число\n  возвращает число\n  «Взять» от м\n",
  )
  const беды = вердикты.diagnostics.filter((д) => д.code === "FLANG_PRECONDITION_CALL")
  assert.equal(беды.length, 1, JSON.stringify(вердикты.diagnostics))
  assert.match(беды[0].message, /вызов «Взять» в функции «Зовёт мимо» не снимает предусловие «вход неотрицателен»/u)
  /* Отказ обязан назвать ПРАВИЛО, которое не прошло, — иначе автор правит
     наугад. Правил снятия по-прежнему столько же, сколько правил сведения. */
  assert.match(беды[0].message, /неотрицательность по построению/u)
})

test("подделка: вызов с замкнутым, но ЛОЖНЫМ аргументом — отвергнут вычислением", () => {
  const { вердикты } = ядро(
    "модуль «М»\n\nтотальная функция «Взять»\n  принимает н: число\n  возвращает число\n"
      + "  требует «вход неотрицателен» н не меньше 0\n  н плюс н\n\n"
      + "тотальная функция «Зовёт минусом»\n  возвращает число\n  «Взять» от (0 минус 7)\n",
  )
  const беды = вердикты.diagnostics.filter((д) => д.code === "FLANG_PRECONDITION_CALL")
  assert.equal(беды.length, 1, JSON.stringify(вердикты.diagnostics))
  assert.match(беды[0].message, /инстанция замкнута и вычисляется в «нет»/u)
})

test("годный вызов снимается — обоими правилами, и это не одно и то же", () => {
  /* Обратная сторона двух изъятий выше: проверка, которая краснеет на верной
     программе, ничего не стоит. Здесь стоят обе дороги снятия сразу:
     ВЫЧИСЛЕНИЕМ (замкнутый литерал) и СВЕДЕНИЕМ (собственное предусловие
     вызывающего). */
  const программа = parse(
    "модуль «М»\n\nтотальная функция «Взять»\n  принимает н: число\n  возвращает число\n"
      + "  требует «вход неотрицателен» н не меньше 0\n  н плюс н\n\n"
      + "тотальная функция «Литералом»\n  возвращает число\n  «Взять» от 7\n\n"
      + "тотальная функция «Своим условием»\n  принимает м: число\n  возвращает число\n"
      + "  требует «м неотрицательно» м не меньше 0\n  «Взять» от м\n",
    "годный.flang",
  )
  const итог = снятьПредусловия(программа)
  assert.equal(итог.sites, 2, "мест вызова с предусловием")
  assert.equal(итог.discharged, 2, JSON.stringify(итог.diagnostics))
  assert.deepEqual(итог.diagnostics, [])
})

// ── ПОДДЕЛКА 2: предусловие, объявленное, но не доехавшее допущением ───────

test("ИЗЪЯТИЕ: снимите `требует` — и доказательство базы краснеет", () => {
  /* Главная проверка файла. Она показывает, что предусловие не украшение: без
     него ядро эту теорему НЕ принимает, и код отказа тот, который надо. */
  const { вердикты } = ядро(СТОПКА)
  assert.deepEqual(вердикты.diagnostics, [], "годная программа обязана быть чистой")
  assert.equal(вердикты.checked[0].verdict, "доказано")

  const без = СТОПКА.replace("  требует «дно неотрицательно» дно не меньше 0\n", "")
  assert.notEqual(без, СТОПКА, "улика не собралась: строки `требует` в образце нет")
  const снято = ядро(без)
  const беды = снято.вердикты.diagnostics.filter((д) => д.code === "FLANG_PROOF_INDUCTION_STEP")
  assert.equal(беды.length, 1, JSON.stringify(снято.вердикты.diagnostics))
  assert.match(беды[0].message, /предусловий у функции не объявлено ни одного/u)
})

test("ИЗЪЯТИЕ: предусловие, не доехавшее до обязательства, теорему не спасает", () => {
  /* Изъятие не строки исходника, а ПРОВОДА: поле `assumptions` — то самое
     место, где предусловие становится допущением ядра. Оборвите его — и
     теорема, которая только что была доказана, отвергается. Проверка ловит
     разрыв между «слово написано» и «слово доехало». */
  const программа = parse(СТОПКА, "стопка.flang")
  const итог = obligations(программа)
  const цель = итог.obligations.find((о) => о.kind === "postcondition")
  assert.deepEqual(цель.assumptions.length, 1, "предусловие не доехало до обязательства")

  цель.assumptions = []
  const вердикты = checkProofs(программа, итог.obligations)
  assert.equal(вердикты.checked[0].verdict, "отвергнуто")
})

// ── ПОДДЕЛКА 3: ложь через невыполнимое предусловие ────────────────────────

test("подделка: замкнутое предусловие отвергнуто — из лжи следует что угодно", () => {
  /* `требует «ложь» 1 не меньше 2` невыполнимо ни на одном входе, и телу
     досталась бы допущением ложь: любая цель «доказалась» бы ею. Замкнутое
     предусловие отвергается ЦЕЛИКОМ — и истинное тоже, потому что ни то, ни
     другое не является условием на ВХОД, а разбирать какое из двух перед нами,
     типизатору нечем и не нужно: отказ у них один. */
  for (const условие of ["1 не меньше 2", "1 не меньше 0"]) {
    const { коды, тексты } = типы(
      "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
        + `  требует «замкнуто» ${условие}\n  н\n`,
    )
    assert.deepEqual(коды, ["FLANG_PRECONDITION"], `${условие}: ${тексты.join(" | ")}`)
    assert.match(тексты[0], /не упоминает ни одного параметра/u)
  }
})

test("невыполнимое предусловие ПРИ параметре запирает функцию, а не выпускает ложь", () => {
  /* Граница проверки выше названа прямо: `н больше н` упоминает параметр и всё
     равно невыполнимо, а решить это значило бы завести решатель. Ложь при этом
     не выходит наружу, и вот чем это измеряется: ядро «докажет» ею любую цель,
     НО ни один вызов такой функции снять условие не сможет, и `flang check`
     покраснеет на каждом. Функция, которую нельзя позвать, ничего не отравляет.

     Проверяются ОБА конца: доказано внутри — и отвергнут вызов снаружи. */
  const исходник = "модуль «М»\n\nтотальная функция «Ложь»\n  принимает н: число\n  возвращает число\n"
    + "  требует «невыполнимо» н больше н\n"
    + "  обеспечивает «ложь» результат не меньше 0\n  0 минус 1\n\n"
    + "теорема «ложь»\n  дано н: число\n  утверждаем результат не меньше 0\n"
    + "  по предположению\n  следовательно доказано\n\n"
    + "тотальная функция «Зовёт»\n  принимает м: число\n  возвращает число\n  «Ложь» от м\n"
  const { вердикты } = ядро(исходник)
  const вызов = вердикты.diagnostics.filter((д) => д.code === "FLANG_PRECONDITION_CALL")
  assert.equal(вызов.length, 1, JSON.stringify(вердикты.diagnostics))
  assert.match(вызов[0].message, /вызов «Ложь» в функции «Зовёт» не снимает предусловие «невыполнимо»/u)

  /* И граница программы её тоже не пускает: доказать снаружи нечего, значит
     считается. Ни одного входа, на котором `н больше н` истинно, не бывает,
     поэтому отказ здесь неизбежен, а не случаен. */
  assert.throws(
    () => evaluate(parse(исходник, "ложь.flang"), "Ложь", { н: 5 }),
    (ошибка) => ошибка.code === "FLANG_PRECONDITION",
  )
})

// ── допущение работает и ВНЕ индукции ──────────────────────────────────────

test("вне индукции: цель с телом сводится к предусловию, а вычитание — не сводится", () => {
  /* Две программы отличаются одним знаком, и вердикты у них разные. Это и есть
     проверка того, что правило работает, а не пропускает: `н плюс н` при
     `н не меньше 0` неотрицательно (правило сведения, доказанная теорема о
     IEEE-754), а `н минус 3` — нет, и вычитания в правилах нет и не будет
     (разность двух неотрицательных отрицательна уже на 2 минус 3).

     ЗДЕСЬ СТОЯЛО УМНОЖЕНИЕ, и строка была верна ровно до того дня, когда
     правило умножения приехало в ядро (`work/kernel-mul-field`,
     `work/kernel-factorial`). `н умножить на 3` при `н не меньше 0` СВОДИТСЯ —
     тройка есть конечный литерал больше нуля, и второму сомножителю хватает
     дна. Оставить прежнюю строку значило бы держать проверку, которая ждёт от
     ядра слабости; поэтому она переписана, а умножение проверено ниже с
     противоположным ожиданием. */
  const шаблон = (тело) =>
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
    + "  требует «вход неотрицателен» н не меньше 0\n"
    + `  обеспечивает «п» результат не меньше 0\n  ${тело}\n\n`
    + "теорема «п»\n  дано н: число\n  утверждаем результат не меньше 0\n"
    + "  по предположению\n  следовательно доказано\n"

  const сложение = ядро(шаблон("н плюс н"))
  assert.deepEqual(сложение.вердикты.diagnostics, [])
  assert.equal(сложение.вердикты.checked[0].verdict, "доказано")

  const вычитание = ядро(шаблон("н минус 3"))
  assert.equal(вычитание.вердикты.checked[0].verdict, "отвергнуто")
  assert.match(
    вычитание.вердикты.diagnostics[0].message,
    /цель не сведена к 1 предусловию функции: неотрицательность по построению не проходит/u,
  )

  /* И третья программа — та самая, что была здесь отрицательной: умножение на
     конечный положительный литерал СВОДИТСЯ, и предусловие в этом выводе
     работает наравне с допущением индукции. */
  const умножение = ядро(шаблон("н умножить на 3"))
  assert.deepEqual(умножение.вердикты.diagnostics, [])
  assert.equal(умножение.вердикты.checked[0].verdict, "доказано")
})

test("«по предположению» без индукции и без предусловий — по-прежнему отказ", () => {
  /* Изъятие: слово не стало закрывать шаг само по себе. Нет ни посылки, ни
     предусловия — предполагать не о чем, и ядро говорит это обоими словами. */
  const { вердикты } = ядро(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + "  обеспечивает «п» результат не меньше 0\n  0\n\n"
      + "теорема «п»\n  дано н: число\n  утверждаем результат не меньше 0\n"
      + "  по предположению\n  следовательно доказано\n",
  )
  assert.equal(вердикты.checked[0].verdict, "отвергнуто")
  assert.match(вердикты.diagnostics[0].message, /ни посылки индукции.*ни предусловия функции/su)
})

// ── граница программы ──────────────────────────────────────────────────────

test("граница: вход снаружи проверяется вычислением, и отказ называет требование", () => {
  const программа = parse(СТОПКА, "стопка.flang")
  const пусто = { variant: "Пусто", fields: {} }
  assert.equal(evaluate(программа, "Высота от дна", { стопка: пусто, дно: 3 }), 3)
  assert.throws(
    () => evaluate(программа, "Высота от дна", { стопка: пусто, дно: -3 }),
    (ошибка) => {
      assert.equal(ошибка.code, "FLANG_PRECONDITION")
      assert.match(ошибка.message, /не выполнено требование «дно неотрицательно» функции «Высота от дна»/u)
      return true
    },
  )
})

test("граница ровно одна: рекурсивный вызов внутри программы её не проходит", () => {
  /* Изъятие наоборот: если бы проверка стояла у КАЖДОГО вызова, а не на
     границе, она сработала бы и внутри. Здесь внутренний вызов заведомо
     нарушил бы своё же предусловие, а функция всё равно считается: внутренние
     вызовы идут через `applyFunction` и до границы не доходят.

     Это не поблажка, а следствие того, кто снимает условие: у внутреннего
     вызова обязательство снял `flang check` (и здесь бы не снял — программа
     краснеет), а рантайм проверяет только то, за что никто не отвечал. */
  const исходник = "модуль «М»\n\nтотальная функция «Вниз»\n  принимает н: нат\n  возвращает число\n"
    + "  требует «н не ноль» н больше 0\n"
    + "  если н не больше 1\n    то 0\n    иначе («Вниз» от (н минус 1)) плюс 1\n"
  const программа = parse(исходник, "вниз.flang")
  /* Внутренний вызов условия не снимает — и `flang check` это говорит. */
  const беды = снятьПредусловия(программа).diagnostics
  assert.equal(беды.length, 1, JSON.stringify(беды))
  assert.match(беды[0].message, /вызов «Вниз» в функции «Вниз» не снимает предусловие «н не ноль»/u)
  /* А рантайм на границе проверяет только внешний вход. */
  assert.equal(evaluate(программа, "Вниз", { н: 3 }), 2)
  assert.throws(
    () => evaluate(программа, "Вниз", { н: 0 }),
    (ошибка) => ошибка.code === "FLANG_PRECONDITION",
  )
})

// ── цена в печати ──────────────────────────────────────────────────────────

test("цена предусловия в восьми целях печати равна нулю байт", async () => {
  /* Возражение, из-за которого слово не заводили, звучало так: «предусловие —
     это НОВЫЙ рантайм в интерпретаторе и во всех восьми целях печати». Здесь
     оно ИЗМЕРЕНО: та же программа с `требует` и без него печатается побайтово
     одинаково всеми восемью бэкендами. Возражение снялось не рассуждением, а
     выбором того, кто снимает условие.

     Проверка умеет краснеть: напечатай какой-нибудь бэкенд хоть одну строку
     проверки входа — сравнение разойдётся на первом же файле. */
  const сИм = "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
    + "  требует «вход неотрицателен» н не меньше 0\n"
    + "  обеспечивает «п» результат не меньше 0\n  н плюс н\n"
  /* Строка не УДАЛЯЕТСЯ, а заменяется комментарием, и это не хитрость: удали
     её — и все следующие строки сдвинутся на одну, а места (`span`) едут в
     печать вместе с отказами постусловия. Тогда сравнение разошлось бы на
     номере строки, то есть проверка ловила бы сдвиг файла вместо предусловия. */
  const безНего = сИм.replace(
    "  требует «вход неотрицателен» н не меньше 0\n",
    "  // строка снята: номера строк не сдвигаются\n",
  )
  assert.notEqual(сИм, безНего)
  assert.equal(сИм.split("\n").length, безНего.split("\n").length, "строк стало не столько же")

  /* Цели берутся РЕЕСТРОМ каталога, а не списком в тесте: появись девятая
     цель — она попадёт под ту же проверку сама, а не когда о ней вспомнят. */
  const цели = await emitTargets()
  assert.ok(цели.length >= 8, `целей печати найдено ${цели.length}`)
  for (const цель of цели) {
    const { emit } = await loadEmitter(цель, цели)
    const первое = emit(parse(сИм, "п.flang"), {})
    const второе = emit(parse(безНего, "п.flang"), {})
    assert.deepEqual(
      (первое.files ?? []).map((ф) => ({ path: ф.path, content: ф.content })),
      (второе.files ?? []).map((ф) => ({ path: ф.path, content: ф.content })),
      `цель «${цель}»: предусловие доехало до печати, а не должно было`,
    )
  }
})

