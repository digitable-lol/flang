/* ПРАВИЛО «ЦЕЛЬ ЕСТЬ ДОПУЩЕНИЕ»: что снимает и на чём обязано встать  */
/* ================================================================== */

/**
 * ТО, РАДИ ЧЕГО ПРАВИЛО ЗАВЕДЕНО, и рядом — ДВЕ ПОДДЕЛКИ на него же.
 *
 * До правила `требует` в корпусе был неприменим: у ядра не было хода «цель
 * дословно совпала с допущением», поэтому предусловие ломало КАЖДОЕ место
 * вызова, включая то, где вызывающий допускает ровно то же самое. Вторая
 * функция ниже — этот случай, и он обязан сниматься.
 *
 * Две другие — программы, пытающиеся тем же правилом доказать ЛОЖЬ, и ложь у
 * обеих настоящая: `«Голова» от пустой список` падает всегда, а
 * `«Голова» от другой` падает всякий раз, когда `другой` пуст при непустом
 * `эл`. Обе метят РОВНО в новое правило: предикат у вызывающего и у
 * вызываемого один и тот же (`не пусто …`), и разойдись правило с «дословно»
 * хоть на шаг — читай оно «про ту же проверку» вместо «то же выражение», — оба
 * вызова снялись бы. Это и есть посылка, на которой правило стоит теоремой:
 * совпасть обязано ВЫРАЖЕНИЕ в ТОМ ЖЕ окружении, а не форма утверждения.
 */
const ДОПУЩЕНИЕМ = `модуль «Допущением»

тотальная функция «Голова»
  принимает эл: список числа
  возвращает число
  требует «непуст» не пусто эл
  голова эл

тотальная функция «Своё же допущение»
  принимает эл: список числа
  возвращает число
  требует «непуст» не пусто эл
  «Голова» от эл

тотальная функция «Ложь пустотой»
  принимает эл: список числа
  возвращает число
  требует «непуст» не пусто эл
  «Голова» от пустой список

тотальная функция «Ложь чужим именем»
  принимает эл: список числа, другой: список числа
  возвращает число
  требует «непуст» не пусто эл
  «Голова» от другой
`

test("«цель есть допущение» снимает вызов у того, кто допускает ТО ЖЕ САМОЕ", () => {
  const итог = снятьПредусловия(parse(ДОПУЩЕНИЕМ, "проба.flang"))
  assert.equal(итог.sites, 3, "мест вызова с предусловием стало не три")
  assert.equal(итог.discharged, 1, "снялось не ровно одно место — то, где допущение дословно то же")
  assert.ok(
    итог.diagnostics.every((д) => !/«Своё же допущение»/u.test(д.message)),
    "вызов из «Своё же допущение» отвергнут, хотя допущение у него дословно то же",
  )
})

test("ПОДДЕЛКА допущением: ложь тем же предикатом отвергнута кодом FLANG_PRECONDITION_CALL", () => {
  const итог = снятьПредусловия(parse(ДОПУЩЕНИЕМ, "проба.flang"))
  const отказы = итог.diagnostics.filter((д) => д.code === "FLANG_PRECONDITION_CALL")
  assert.equal(отказы.length, 2, "подделок отвергнуто не две")

  /* ПЕРВАЯ: инстанция замкнута и ЛОЖНА. Правило до неё не доходит вовсе —
     отвергает вычисление, и отказ говорит именно это, а не «правила нет». */
  const пустотой = отказы.find((д) => /«Ложь пустотой»/u.test(д.message))
  assert.ok(пустотой !== undefined, "вызов с пустым списком не отвергнут поимённо")
  assert.match(пустотой.message, /вычисляется в «нет»/u, "отказ не назвал, что инстанция ЛОЖНА")

  /* ВТОРАЯ: инстанция про ДРУГОЕ ИМЯ, и отвергнуть её обязано само правило.
     Отказ называет четвёртое правило поимённо: правило, о котором отказ
     промолчал, ничем не отличается от «ядро решило». */
  const именем = отказы.find((д) => /«Ложь чужим именем»/u.test(д.message))
  assert.ok(именем !== undefined, "вызов с чужим списком не отвергнут поимённо")
  assert.match(именем.message, /«цель есть допущение», и оно тоже не прошло/u, "отказ не назвал правила")
  assert.match(именем.message, /ни одно допущение не совпало с целью знак в знак/u)
})

