test("В4: доигрывание НЕ ломает тотальности — предел пробегов остаётся пределом", () => {
  /*
   * Пробег на паузе делает процесс готовым при ПУСТОМ ящике, и это то место, где
   * легко было бы завести зависание: планировщик, который считает такой процесс
   * неготовым, объявит «покой» посреди недосчитанного пробега, а тот, кто
   * забудет считать дольки пробегами, не упрётся в предел никогда.
   *
   * Отсюда две проверки в одной. Предел ставится заведомо ниже, чем нужно
   * долгому пробегу, — исход обязан быть «предел пробегов», и пробегов обязано
   * быть ровно столько, сколько объявлено.
   */
  const программаТест = программа(ДЛИНА)
  for (const предел of [3, 5, 9]) {
    const итог = runConcurrent(программаТест, программаТест.runs[0],
      { квант: 64, доигрывать: true, maxTurns: предел })
    assert.equal(итог.исход, "предел пробегов", `предел ${предел}: прогон обязан упереться, а не кончиться покоем`)
    assert.equal(итог.пробегов, предел, `предел ${предел}: пробегов ${итог.пробегов}, а объявлено ${предел}`)
    assert.equal(итог.журнал.length, предел, `предел ${предел}: записей журнала не столько же, сколько пробегов`)
  }
})

