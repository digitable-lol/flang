/**
 * Вытеснение по витку — шаг В2 карты (`flang/conc/RESILIENCE.md`).
 *
 * ── Что именно проверяется, и почему числами ───────────────────────────────
 *
 * Карта требует: «программа из одного долгого и одного короткого обработчика —
 * короткий получает свои пробеги (сегодня не получает)». Формулировка эта
 * неточна, и неточность надо назвать, а не унаследовать: пробеги короткий
 * получает и сегодня — планировщик выбирает из готовых по семени, а не по
 * очереди. Не получает он другого: ЗАДЕРЖКИ, которая от долгого соседа не
 * зависит. Пока долгий пробег идёт, короткий ждёт его целиком.
 *
 * Поэтому проверка меряет не «получил ли пробег», а НАИБОЛЬШЕЕ ЧИСЛО ВИТКОВ В
 * ОДНОМ ПРОБЕГЕ — ровно ту величину, на которую короткий ждёт. Витки — счёт, а
 * не измерение: они не зависят ни от машины, ни от нагрузки и повторяются до
 * единицы.
 *
 * ── Чего вытеснение НЕ даёт, и это сказано здесь, а не в примечании ────────
 *
 * Пробег снимается и начинается ЗАНОВО, а не продолжается с середины: обработчик
 * чист, состояние он возвращает значением, и брошенный на середине пробег не
 * оставляет половины изменения. Это не приближение к настоящему вытеснению, а
 * другая сделка, и цена обеих измерена в В1 (`flang/conc/bench.mjs`): настоящее
 * стоит стека на процесс и переключения, это — переделанной работы.
 *
 * Отсюда честная граница, и она проверена отдельным тестом, чтобы её нельзя
 * было забыть: ПОТОЛКА ЗАДЕРЖКИ такое вытеснение не даёт вовсе. Квант растёт
 * удвоением, пока пробег не влезет целиком, значит последняя попытка идёт от
 * начала до конца и стоит ровно столько же, сколько стоил бы пробег без всякого
 * вытеснения. Наибольшее число витков в одном пробеге не уменьшается ни на
 * виток.
 *
 * Что оно даёт: ЧЕРЕДОВАНИЕ — короткий обработчик получает свои пробеги, пока
 * долгий ещё не досчитал, — и стоит это меньше трёх цен пробега (считано, а не
 * прикинуто: см. тест про переплату) и нуля байт памяти.
 *
 * А потолок задержки даёт не вытеснение, а ограниченность (шаг В3): обработчику
 * с постоянной оценкой витков он известен до запуска, и снимать такой обработчик
 * незачем. Либо настоящее вытеснение со стеком на процесс — его цена измерена в
 * В1 и в язык пока не внесена.
 */

import assert from "node:assert/strict"
import test from "node:test"

import { runConcurrent } from "../src/conc.mjs"
import { parse } from "../src/parser.mjs"

/**
 * Долгий и короткий обработчики в одной программе.
 *
 * Долгий считает список НЕ хвостовой рекурсией, поэтому цена его пробега прямо
 * задаётся длиной списка в сообщении. Короткий кладёт число в состояние и всё.
 */
function программа(длина) {
  const числа = Array.from({ length: длина }, () => 1).join(", ")
  return parse([
    "модуль «Вытеснение»", "",
    "объект «Счёт»", "  «всего»: число", "",
    "тип «Весть»",
    "  вариант «сложить» содержит «числа»: список числа",
    "  вариант «отметить» содержит «сколько»: число", "",
    "объект «Отклик»", "  «состояние»: «Счёт»", "  «действия»: список «Действие»", "",
    "процесс «Долгий»", "  состояние «Счёт»", "  начинает с «нуль»",
    "  принимает «Весть»", "  обрабатывает «шаг долгого»", "",
    "процесс «Короткий»", "  состояние «Счёт»", "  начинает с «нуль»",
    "  принимает «Весть»", "  обрабатывает «шаг короткого»", "",
    "надзор «Сверху»",
    "  процесс «Долгий» стратегия «остановить»",
    "  процесс «Короткий» стратегия «остановить»", "",
    "тотальная функция «нуль»", "  возвращает «Счёт»",
    "  запись «Счёт» с «всего» равным 0", "",
    "тотальная функция «сумма»", "  принимает элементы: список числа", "  возвращает число",
    "  разбор элементы",
    "    случай пусто", "      то 0",
    "    случай голова и хвост", "      то голова плюс «сумма» от хвост", "",
    "тотальная функция «шаг долгого»",
    "  принимает счёт: «Счёт», весть: «Весть»", "  возвращает «Отклик»",
    "  разбор весть",
    "    случай вариант «сложить» с «числа» как набор",
    "      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным («сумма» от набор)) и «действия» равным []",
    "    случай вариант «отметить» с «сколько» как сколько",
    "      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным сколько) и «действия» равным []", "",
    "тотальная функция «шаг короткого»",
    "  принимает счёт: «Счёт», весть: «Весть»", "  возвращает «Отклик»",
    "  разбор весть",
    "    случай вариант «сложить» с «числа» как набор",
    "      запись «Отклик» с «состояние» равным счёт и «действия» равным []",
    "    случай вариант «отметить» с «сколько» как сколько",
    "      запись «Отклик» с «состояние» равным (запись «Счёт» с «всего» равным сколько) и «действия» равным []", "",
    "прогон «оба сразу»", "  семя 1",
    `  дано «Долгий» принимает (вариант «сложить» с «числа» равным [${числа}])`,
    "  дано «Короткий» принимает (вариант «отметить» с «сколько» равным 1)",
    "  дано «Короткий» принимает (вариант «отметить» с «сколько» равным 2)",
    "  дано «Короткий» принимает (вариант «отметить» с «сколько» равным 3)",
    "  ожидается «Короткий» равен (запись «Счёт» с «всего» равным 3)", "",
  ].join("\n"), "вытеснение.flang")
}

const ДЛИНА = 400

/* ─────────── сторож: сегодня короткий ждёт долгого целиком ──────────────── */

test("без кванта задержка равна цене САМОГО долгого пробега", () => {
  const программаТест = программа(ДЛИНА)
  const итог = runConcurrent(программаТест, программаТест.runs[0], {})

  assert.equal(итог.исход, "покой")
  assert.equal(итог.вытеснений, 0, "без кванта снимать некому")
  const самыйДолгий = Math.max(...итог.витки)
  /* Число это не круглое и не должно быть круглым: оно ровно столько, сколько
     стоит «сумма» на списке из ДЛИНА элементов, и меняться оно имеет право
     только вместе с вычислителем. */
  assert.ok(самыйДолгий > 4000, `самый долгий пробег ${самыйДолгий} витков — мало для проверки`)
  /* И вот она, задержка: пока идёт этот пробег, короткий не делает ничего. */
  assert.ok(
    итог.витки.filter((в) => в > 1000).length === 1,
    `дорогих пробегов ${итог.витки.filter((в) => в > 1000).length}, а долгий обработчик один`,
  )
})

/* ─────────── что даёт квант: потолок на пробег вместо суммы ─────────────── */

test("квант даёт ЧЕРЕДОВАНИЕ: короткий успевает всё, пока долгий ещё считает", () => {
  const программаТест = программа(ДЛИНА)
  const безКванта = runConcurrent(программаТест, программаТест.runs[0], {})
  const самыйДолгий = Math.max(...безКванта.витки)

  /* Квант берётся заведомо меньше цены долгого пробега — иначе снимать было бы
     нечего, и проверка ничего бы не проверяла. */
  const квант = 512
  assert.ok(квант < самыйДолгий / 4, "квант обязан быть заметно меньше долгого пробега")

  const итог = runConcurrent(программаТест, программаТест.runs[0], { квант, maxTurns: 100_000 })
  assert.equal(итог.исход, "покой", "вытеснение обязано доводить программу до конца, а не ронять")
  assert.ok(итог.вытеснений > 0, "долгий пробег обязан быть снят хоть раз")

  /* ГЛАВНОЕ ЧИСЛО. Короткий получает свои пробеги, ПОКА долгий ещё не досчитал:
     это и есть чередование, которого без вытеснения нет. Считаются короткие
     пробеги, стоящие в журнале раньше того, на котором долгий дошёл до конца. */
  const доКонцаДолгого = []
  for (const запись of итог.журнал) {
    if (запись.процесс === "Долгий" && запись.исход === "обработано") break
    доКонцаДолгого.push(запись)
  }
  assert.equal(
    доКонцаДолгого.filter((з) => з.процесс === "Короткий").length, 3,
    "все три коротких пробега обязаны успеть до конца долгого",
  )

  /* И то же самое без кванта — там долгий доходит первым же пробегом, и ждать
     его приходится целиком. */
  const безВытеснения = []
  for (const запись of безКванта.журнал) {
    if (запись.процесс === "Долгий") break
    безВытеснения.push(запись)
  }
  assert.ok(
    безВытеснения.filter((з) => з.процесс === "Короткий").length < 3,
    "без кванта короткий не успевает всё до конца долгого — иначе сравнивать нечего",
  )
})

test("ЧЕГО КВАНТ НЕ ДАЁТ: самый дорогой пробег остаётся ровно таким же", () => {
  /*
   * Проверка, которая стережёт не поведение, а честность рассказа о нём, и
   * покраснеет она в тот день, когда кто-нибудь запишет вытеснение в «потолок
   * задержки». Потолка оно не даёт.
   *
   * Почему. Пробег снимается и НАЧИНАЕТСЯ ЗАНОВО, а квант растёт удвоением,
   * пока не вместит пробег целиком. Последняя попытка поэтому идёт от начала до
   * конца, ни разу не снявшись, и стоит ровно столько, сколько стоил бы пробег
   * без всякого вытеснения. Наибольшее число витков в одном пробеге не
   * уменьшается ни на виток — оно и не может уменьшиться, пока обработчик не
   * умеет продолжаться с середины.
   *
   * Отсюда развилка, и обе её ветви названы в карте:
   *   • жёсткий потолок задержки даёт НАСТОЯЩЕЕ вытеснение — со стеком на
   *     процесс и переключением; цена измерена в В1;
   *   • или ОГРАНИЧЕННОСТЬ (В3): обработчику с постоянной оценкой витков
   *     потолок известен до запуска, и снимать его незачем.
   */
  const программаТест = программа(ДЛИНА)
  const безКванта = runConcurrent(программаТест, программаТест.runs[0], {})
  const сКвантом = runConcurrent(программаТест, программаТест.runs[0], { квант: 512, maxTurns: 100_000 })
  assert.equal(
    Math.max(...сКвантом.витки), Math.max(...безКванта.витки),
    "последняя попытка обязана стоить ровно столько же: вытеснение не режет пробег, а повторяет его",
  )
})

test("переплата за переделанную работу не больше троекратной, и это считается", () => {
  /*
   * Счёт, а не надежда. Попытки идут с квантами q, 2q, 4q … 2^k·q, и снимаются
   * все, кроме последней. Если C — истинная цена пробега, то 2^(k−1)·q < C (иначе
   * предпоследняя попытка уже дошла бы), значит брошено q·(2^k − 1) < 2^k·q < 2C,
   * а всего сделано меньше 3C. Ровно это и проверяется — на четырёх квантах, а
   * не на одном удобном.
   */
  const программаТест = программа(ДЛИНА)
  const безКванта = runConcurrent(программаТест, программаТест.runs[0], {})
  const честно = безКванта.витки.reduce((сумма, в) => сумма + в, 0)

  for (const квант of [64, 128, 512, 2048]) {
    const итог = runConcurrent(программаТест, программаТест.runs[0], { квант, maxTurns: 100_000 })
    const сВытеснением = итог.витки.reduce((сумма, в) => сумма + в, 0)
    assert.ok(
      сВытеснением < честно * 3,
      `квант ${квант}: витков ${сВытеснением} против ${честно} — удвоение обязано держать переплату втрое`,
    )
  }
})

/* ─────────── вытеснение не меняет того, ЧТО программа считает ──────────── */

test("исход, состояния и число доставок не зависят от кванта", () => {
  const программаТест = программа(ДЛИНА)
  const эталон = runConcurrent(программаТест, программаТест.runs[0], {})
  for (const квант of [64, 512, 4096]) {
    const итог = runConcurrent(программаТест, программаТест.runs[0], { квант, maxTurns: 100_000 })
    assert.equal(итог.исход, эталон.исход, `квант ${квант}: исход разошёлся`)
    assert.deepEqual(итог.состояния, эталон.состояния, `квант ${квант}: состояния разошлись`)
    assert.deepEqual(итог.живые, эталон.живые, `квант ${квант}: живые разошлись`)
    assert.deepEqual(итог.отказы, эталон.отказы, `квант ${квант}: отказы разошлись`)
    /* Доставок столько же: снятые пробеги — не доставки, они не съедают
       сообщение. Это и есть проверка того, что вытеснение прозрачно. */
    const доставок = (журнал) => журнал.filter((з) => з.исход !== "снято по кванту").length
    assert.equal(доставок(итог.журнал), доставок(эталон.журнал), `квант ${квант}: доставок разное число`)
  }
})

test("на одном кванте и одном семени журнал повторяется побайтово", () => {
  const программаТест = программа(120)
  const первый = runConcurrent(программаТест, программаТест.runs[0], { квант: 256, maxTurns: 100_000 })
  const второй = runConcurrent(программаТест, программаТест.runs[0], { квант: 256, maxTurns: 100_000 })
  assert.deepEqual(JSON.stringify(первый.журнал), JSON.stringify(второй.журнал))
  assert.deepEqual(первый.витки, второй.витки)
})
