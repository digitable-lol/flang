/**
 * Проверка, которая обязана краснеть от снятия правила, а не от чего попало.
 *
 * Изъятие делается руками: в `flang/src/proofterm.mjs` из строки
 * `поОбъявленномуТипу(…) ?? разборомПоСлучаям(…)` убирается второе слагаемое.
 * После этого краснеют ОБА теста раздела «БЕРЁТ» — и только они: подделки
 * остаются зелёными, потому что они и без правила не доказываются. Именно этим
 * изъятие и полезно: правило, от снятия которого не краснеет ничего, ничего и
 * не держит, а правило, от снятия которого краснеют подделки, держало не то.
 */
test("ИЗЪЯТИЕ названо: до правила обязательство приезжает ОТКРЫТЫМ", async () => {
  const программа = await loadProgramFromSource(ДЕРЕВО, "изъятие.flang")
  const внешнее = await externalChecks(программа)
  /* Обязательство приезжает в ядро БЕЗ вердикта — это и есть то состояние, в
     котором цель жила до правила, и мерить изъятие есть чем: снятое правило
     оставит её в нём навсегда. Проверяется на свежем разборе, где `checkProofs`
     не звали вовсе: позови его — и поле уже заполнено, мерить нечего. */
  const свежие = obligations(программа, внешнее.results)
  const о = свежие.obligations.find((з) => з.name === "размер неотрицателен")
  assert.notEqual(о, undefined, "обязательства нет вовсе — проверять нечего")
  assert.equal(о.discharge ?? null, null, "обязательство пришло уже снятым — изъятие ничего не измерит")
  /* А после ядра оно снято, и снято ИМЕННО правилом случаев. */
  const ядро = checkProofs(программа, свежие.obligations)
  assert.equal(вердикт(ядро, "размер неотрицателен")?.by, "cases")
})
