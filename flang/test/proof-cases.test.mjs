/* ПОДДЕЛКИ — четыре, и каждая про своё                                */
/* ================================================================== */

/**
 * ПОДДЕЛКА ПЕРВАЯ — индукция по значению, которое НЕ УМЕНЬШИЛОСЬ.
 *
 * Шаг зовёт себя не на части `х`, а на значении, ПОСТРОЕННОМ ЗАНОВО из неё:
 * `Звено(х)` не меньше `Звено(х)`, спуска нет вовсе. Допущение принцип строит
 * про `Ф(х)` — про убывшее, — и с вызовом `Ф(Звено(х))` оно не сличается:
 * сличение синтаксическое. Прими ядро такое, и «доказано» держалось бы на
 * допущении о значении, которое не убыло, — то есть на аксиоме под другим именем.
 */
const НЕ_УБЫВАЕТ = `модуль «Не убывает»

тип «Ящик»
  вариант «Пусто»
  вариант «Звено» содержит хвост: «Ящик»

функция «Ф»
  принимает я: «Ящик»
  возвращает число
  для всех я обеспечивает «неотрицательно» результат не меньше 0
  разбор я
    случай «Пусто»
      то 0
    случай вариант «Звено» с хвост как х
      то 0 минус («Ф» от (вариант «Звено» с хвост равным х)) минус 1
`

test("ПОДДЕЛКА: шаг зовёт себя на ПОСТРОЕННОМ заново значении — не доказано", async () => {
  const { ядро } = await разобрать(НЕ_УБЫВАЕТ)
  const з = вердикт(ядро, "неотрицательно")
  assert.equal(з, null, `ядро объявило доказанным то, что не убывает: «${з?.says}»`)
})

/**
 * ПОДДЕЛКА ВТОРАЯ — шаг, ссылающийся на ДРУГОЙ случай.
 *
 * Разбирается `я`, а зовёт себя тело на `д` — на втором параметре того же типа,
 * до которого образец не касается вовсе. Допущение принцип строит про `Ф(х, д)`
 * (переменная индукции стала частью, прочие аргументы остались собой), и вызов
 * `Ф(д, д)` ему не отвечает. Прими ядро такое — и «доказано» говорилось бы о
 * значении, про которое допущения никто не строил.
 */
const ЧУЖОЙ_СЛУЧАЙ = `модуль «Чужой случай»

тип «Ящик»
  вариант «Пусто»
  вариант «Звено» содержит хвост: «Ящик»

функция «Ф»
  принимает я: «Ящик», д: «Ящик»
  возвращает число
  для всех я обеспечивает «неотрицательно» результат не меньше 0
  разбор я
    случай «Пусто»
      то 0
    случай вариант «Звено» с хвост как х
      то 0 минус («Ф» от д и д) минус 1
`

test("ПОДДЕЛКА: шаг зовёт себя на ЧУЖОМ параметре — не доказано", async () => {
  const { ядро } = await разобрать(ЧУЖОЙ_СЛУЧАЙ)
  const з = вердикт(ядро, "неотрицательно")
  assert.equal(з, null, `ядро сослалось на допущение, которого не строило: «${з?.says}»`)
})

/**
 * ПОДДЕЛКА ТРЕТЬЯ — БАЗЫ НЕТ ни одной.
 *
 * У суммы оба варианта несут поле своего же типа, значит обе посылки принципа
 * шаговые. Каждая сводится допущением знак в знак — и вывод опирается ровно на
 * самого себя: о конечном значении не сказано ничего. Это не индукция, а круг,
 * и молчаливо принять его нельзя. Свёртка принципа пустую базу считает законной
 * (у теоремы её вправе закрыть автор), поэтому условие «база есть» стоит в
 * правиле ОТДЕЛЬНО.
 */
const БАЗЫ_НЕТ = `модуль «Базы нет»

тип «Виток»
  вариант «Левый» содержит внутри: «Виток»
  вариант «Правый» содержит внутри: «Виток»

функция «Ф»
  принимает виток: «Виток»
  возвращает число
  для всех виток обеспечивает «неотрицательно» результат не меньше 0
  разбор виток
    случай вариант «Левый» с внутри как нутро
      то «Ф» от нутро
    случай вариант «Правый» с внутри как нутро
      то «Ф» от нутро
`

test("ПОДДЕЛКА: базы нет ни одной — вывод опёрся бы только на себя, не доказано", async () => {
  const { ядро } = await разобрать(БАЗЫ_НЕТ)
  const з = вердикт(ядро, "неотрицательно")
  assert.equal(з, null, `ядро приняло круг за индукцию: «${з?.says}»`)
})

/**
 * ПОДДЕЛКА ЧЕТВЁРТАЯ — цель на НЕ-ЧИСЛЕ.
 *
 * `0 делить на 0` — это NaN, и он достижим изнутри языка без единой
 * диагностики. «NaN не больше NaN» ЛОЖНО: порядок на NaN не выполняется ни в
 * какую сторону. Цель замкнута, база и шаг сводились бы тождеством — и ровно
 * поэтому она здесь: правило обязано остаться при вычислении, а вычисление
 * обязано сказать «нет».
 *
 * Тождеству посылка «не NaN» не нужна (`равен` языка есть `Object.is`, и
 * `не число равно не число` даёт ДА), а порядку — нужна. Спутай их — и ядро
 * начало бы доказывать ложь на каждой функции корпуса.
 */
const ЦЕЛЬ_НЕ_ЧИСЛО = `модуль «Не число»

тип «Ящик»
  вариант «Пусто»
  вариант «Звено» содержит хвост: «Ящик»

функция «Ф»
  принимает я: «Ящик»
  возвращает число
  для всех я обеспечивает «порядок на не-числе» (0 делить на 0) не больше (0 делить на 0)
  разбор я
    случай «Пусто»
      то 0
    случай вариант «Звено» с хвост как х
      то «Ф» от х
`

test("ПОДДЕЛКА: цель на не-числе — «NaN не больше NaN» осталась отвергнутой", async () => {
  const { ядро } = await разобрать(ЦЕЛЬ_НЕ_ЧИСЛО)
  const з = вердикт(ядро, "порядок на не-числе")
  assert.equal(з, null, `ядро доказало ложь о NaN: «${з?.says}»`)
})

/**
 * И то же самое ТОЖДЕСТВОМ — чтобы разница была видна числом, а не на слово.
 * `не число равно не число` даёт ДА, значит эта цель истинна и берётся. Стой
 * рядом одна проверка про порядок — читатель решил бы, что правило просто не
 * работает на NaN; их две, и они расходятся ровно там, где расходится язык.
 */
test("РАЗЛИЧАЕТ: тождество на не-числе берётся, порядок — нет", async () => {
  const { ядро } = await разобрать(ЦЕЛЬ_НЕ_ЧИСЛО.replace(
    "(0 делить на 0) не больше (0 делить на 0)",
    "(0 делить на 0) равно (0 делить на 0)",
  ))
  const з = вердикт(ядро, "порядок на не-числе")
  assert.notEqual(з, null, "тождество на NaN истинно, а ядро о нём промолчало")
  assert.equal(з.verdict, "доказано", `ведомость сказала «${з.says}»`)
})

