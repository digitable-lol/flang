/**
 * Индукция по `разбор`у БЕЗ теоремы — что она берёт и чего не берёт.
 *
 * ── Почему правило вообще завелось ──────────────────────────────────────────
 * Принцип индукции у ядра был и был доказан, но звали его только из НАПИСАННОЙ
 * РУКОЙ теоремы. В `flang/stdlib` теорему писать нельзя: восемь слов слоя
 * доказательств не имеют продукции в `flang/self/parser.flang`, и теорема
 * роняет побайтовую сверку самоприменения. Правило `разборомПоСлучаям`
 * (`flang/src/proofterm.mjs`) зовёт ТОТ ЖЕ принцип с пути постусловия — без
 * единого нового слова в языке.
 *
 * ── Два обязательства, и оба здесь ──────────────────────────────────────────
 *   СПИСОК СЛУЧАЕВ  что правило берёт, названо целиком и поимённо, а не числом:
 *                   число молчит о том, какие случаи оно считало.
 *   ПОДДЕЛКИ        четыре программы, пытающиеся получить «доказано» даром.
 *                   Каждая обязана остаться НЕдоказанной, и рядом с каждой
 *                   сказано, чем именно она подделка.
 *
 * ── Почему подделка отвергается МОЛЧАНИЕМ, а не диагностикой ────────────────
 * Это путь постусловия БЕЗ теоремы, и отказ здесь был бы неправдой: автор не
 * писал доказательства, значит и ломаться нечему. Правильный ответ ядра —
 * вердикта НЕТ, а ведомость печатает «объявлено, не доказано» либо считает
 * утверждение сеткой примеров. Поэтому проверяется не «отвергнуто», а
 * «НЕ доказано»: слово «доказано» о подделке и есть та дыра, ради которой
 * файл написан.
 *
 * Там, где подделка утверждает ЛОЖЬ, отказ всё-таки называется — но называет его
 * прогон, а не ядро: `flang check` гоняет примеры, и ложный пример отвергается
 * кодом `FLANG_EXAMPLE`. Это и есть «отказ, называющий подделку».
 *
 * Запуск: node --test flang/test/proof-cases.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"

import { externalChecks, loadProgramFromSource } from "../bin/flang.mjs"
import { obligations } from "../src/obligations.mjs"
import { checkProofs } from "../src/proofterm.mjs"

/** Обязательства и вердикты ядра для текста — тем же путём, каким их считает оболочка. */
async function разобрать(исходник, имя = "случаи.flang") {
  const программа = await loadProgramFromSource(исходник, имя)
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, внешнее, об, ядро, первый: ядро.checked[0] ?? null }
}

/** Вердикт по имени утверждения — или `null`, если ядро о нём ничего не сказало. */
const вердикт = (ядро, имя) => ядро.checked.find((з) => з.name === имя) ?? null

/* ================================================================== */
/* ЧТО ПРАВИЛО БЕРЁТ — список случаев, называемый целиком               */
/* ================================================================== */

/**
 * Дерево: база «Лист» без единого допущения, шаг «Узел» — двумя допущениями,
 * по одному на каждое поле-место. Ровно та форма, ради которой правило и есть.
 */
const ДЕРЕВО = `модуль «Дерево»

тип «Дерево»
  вариант «Лист»
  вариант «Узел» содержит левое: «Дерево», правое: «Дерево»

тотальная функция «Размер»
  принимает д: «Дерево»
  возвращает число
  для всех д обеспечивает «размер неотрицателен» результат не меньше 0
  разбор д
    случай вариант «Лист»
      то 0
    случай вариант «Узел» с левое как л и правое как п
      то (1 плюс («Размер» от л)) плюс («Размер» от п)
`

test("БЕРЁТ: база и шаг сведены ядром — список случаев назван целиком", async () => {
  const { ядро } = await разобрать(ДЕРЕВО)
  const з = вердикт(ядро, "размер неотрицателен")
  assert.notEqual(з, null, "ядро о цели не сказало ничего")
  assert.equal(з.verdict, "доказано", `ведомость сказала «${з.says}»`)
  /* Чем закрыто — своим словом, а не `declaration`: там цель сводится с телом
     ЦЕЛИКОМ и допущений нет ни одного, здесь тело разобрано и у шага допущение
     есть. Одно слово на два разных вывода скрыло бы, на чём держится второй. */
  assert.equal(з.by, "cases")
  assert.equal(з.induction?.carrier, "algebra")
  assert.equal(з.induction?.type, "Дерево")
  assert.equal(з.induction?.param, "д")
  /* СПИСОК ЦЕЛИКОМ И ПОИМЁННО. Числа «база 1, шаг 1» здесь мало: оно молчит о
     том, КАКИЕ случаи посчитаны, и подмена одного другим прошла бы незаметно. */
  assert.deepEqual(
    з.cases.map((с) => [с.variant, с.kind]),
    [["Лист", "base"], ["Узел", "step"]],
  )
  assert.equal(з.induction.base, 1)
  assert.equal(з.induction.step, 1)
  /* Терма никто не писал, значит шагов ноль — иначе свод завысил бы «шагов в
     принятых термах» на утверждения, у которых терма нет. */
  assert.equal(з.steps, 0)
})

test("БЕРЁТ: встроенный список — тот же принцип, два образца вместо вариантов", async () => {
  const { ядро } = await разобрать(`модуль «Список»

тотальная функция «Длина хвостом»
  принимает сп: список числа
  возвращает число
  для всех сп обеспечивает «длина неотрицательна» результат не меньше 0
  разбор сп
    случай пусто
      то 0
    случай голова г и хвост х
      то 1 плюс («Длина хвостом» от х)
`)
  const з = вердикт(ядро, "длина неотрицательна")
  assert.notEqual(з, null, "ядро о цели не сказало ничего")
  assert.equal(з.verdict, "доказано", `ведомость сказала «${з.says}»`)
  assert.equal(з.by, "cases")
  assert.equal(з.cases.map((с) => с.kind).join(","), "base,step")
})

