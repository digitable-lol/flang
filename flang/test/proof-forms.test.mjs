/**
 * ПОДДЕЛКА. Шаг выписывает ПОСТОРОННЕЕ утверждение — истинное, выводимое из
 * названного постусловия, — и им закрывает посылку, заключение которой ложно.
 * Без этой проверки `проверитьЦепочку` объявила бы посылку доказанной по тому,
 * что к ней не относится.
 */
const ПОДДЕЛКА_ЧУЖИМ_УТВЕРЖДЕНИЕМ = `модуль «Подделка чужим утверждением»

${СТОПКА}
тотальная функция «Ниже нуля»
  принимает стопка: «Стопка»
  возвращает число
  для всех стопка обеспечивает «ниже нуля» результат не меньше 0
  0 минус (1 плюс («Высота» от стопка))

теорема «ниже нуля»
  дано стопка: «Стопка»
  утверждаем результат не меньше 0
  затем («Высота» от стопка) не меньше 0 по свойству «высота неотрицательна»
  следовательно доказано
`

test("сличение по вызову: постусловие инстанцируется по месту вызова и закрывает цель", async () => {
  const { об, ядро } = await разобрать(ПО_ВЫЗОВУ)
  const вывод = вердикт(об, "и это неотрицательно")
  assert.equal(вывод?.verdict, "доказано", `не взято: ${отказы(ядро)}`)
  /* И постусловие самой «Высоты» обязано остаться доказанным индукцией:
     сличение по вызову не заменяет собой доказательства того, на что ссылается. */
  assert.equal(вердикт(об, "высота неотрицательна")?.verdict, "доказано")
})

test("ПОДДЕЛКА БЕЗ ВЫЗОВА: сослаться на постусловие функции, которую не зовут, нельзя", async () => {
  const { об, ядро } = await разобрать(ПОДДЕЛКА_БЕЗ_ВЫЗОВА)
  const вывод = вердикт(об, "минус один неотрицателен")
  assert.equal(вывод?.verdict, "отвергнуто", `ядро доказало ложь: ${вывод?.says}`)
  assert.match(отказы(ядро), /нет ни одного вызова «Высота»/u, отказы(ядро))
})

test("ПОДДЕЛКА РАЗНОСТЬЮ: ссылка не разрешение — из факта обязано быть сведено заключение", async () => {
  const { об, ядро } = await разобрать(ПОДДЕЛКА_РАЗНОСТЬЮ)
  const вывод = вердикт(об, "разность неотрицательна")
  assert.equal(вывод?.verdict, "отвергнуто", `ядро доказало ложь: ${вывод?.says}`)
  assert.match(отказы(ядро), /вычитания в этом списке нет/u, отказы(ядро))
})

test("ПОДДЕЛКА ЧУЖИМ УТВЕРЖДЕНИЕМ: шаг обязан закрывать заключение, а не соседнюю правду", async () => {
  const { об, ядро } = await разобрать(ПОДДЕЛКА_ЧУЖИМ_УТВЕРЖДЕНИЕМ)
  const вывод = вердикт(об, "ниже нуля")
  assert.equal(вывод?.verdict, "отвергнуто", `ядро доказало ложь: ${вывод?.says}`)
  assert.match(отказы(ядро), /не заключение этого места/u, отказы(ядро))
})

test("круг остаётся кругом: ссылка на доказываемое сейчас постусловие отвергнута", async () => {
  const { об, ядро } = await разобрать(`модуль «Круг»

${СТОПКА}
тотальная функция «Ещё выше»
  принимает стопка: «Стопка»
  возвращает число
  для всех стопка обеспечивает «ещё выше неотрицательно» результат не меньше 0
  0 минус («Ещё выше» от стопка)

теорема «ещё выше неотрицательно»
  дано стопка: «Стопка»
  утверждаем результат не меньше 0
  по свойству «ещё выше неотрицательно»
  следовательно доказано
`)
  assert.equal(вердикт(об, "ещё выше неотрицательно")?.verdict, "отвергнуто")
  assert.match(отказы(ядро), /это круг/u, отказы(ядро))
})

