/**
 * ФОРМЫ ТЕЛА: чем написан настоящий код и за что ядро умеет зацепиться.
 *
 * ── Улика ДО, числом ────────────────────────────────────────────────────────
 * Замер цены доказательства (`docs/benchmark-proof-cost-2.md`) назвал узкое место со
 * знаменателем: ядро строило заключение посылки индукции ТОЛЬКО с ветвей
 * `разбор` по переменной индукции, а таких тел в `flang/stdlib` **58 из 208**.
 * Остальные 150 написаны свёрткой (45), условием (37), арифметикой (21),
 * вызовом (18) и прочим. На двадцати функциях замера это давало 7 отказов из 18
 * с кодом `FLANG_PROOF_INDUCTION_BRANCH`.
 *
 * Здесь стоят три хода, которыми ядро научилось цепляться за эти формы, и у
 * каждого — своя подделка и своё изъятие:
 *
 *   РАЗБОР ЦЕЛИ ПО УСЛОВИЮ (`reduce.mjs`, `поУсловию`). Цель, у которой на
 *     верхнем уровне стоит `если`, делится надвое подстановкой ЗНАЧЕНИЯ
 *     условия, и обе половины сводятся теми же тремя правилами. Ни один факт из
 *     условия при этом не выводится — ровно поэтому ход не повторяет измеренный
 *     ноль ветки `work/kernel-conditions`
 *     (`docs/zettel/usloviya-esli-dali-nol.md`).
 *
 *   ИНДУКЦИЯ ПО СВЁРТКЕ (`initial.mjs`, `принципПоСвёртке`). Тело, написанное
 *     `свёртка <переменная индукции> …`, даёт две посылки — начало и виток, — и
 *     допущение говорит о НАКОПИТЕЛЕ, а не о части списка.
 *
 *   СЛИЧЕНИЕ ПО ВЫЗОВУ (`proofterm.mjs`, `поСвойству`). `по свойству «имя»`
 *     инстанцирует названное постусловие ПО МЕСТУ ВЫЗОВА в заключении. До этой
 *     работы правило существовало на поверхности и отказывало всегда.
 *
 * Запуск: node --test flang/test/proof-forms.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"

import { externalChecks, loadProgramFromSource } from "../bin/flang.mjs"
import { obligations } from "../src/obligations.mjs"
import { АКСИОМЫ, checkProofs } from "../src/proofterm.mjs"
import { ВЕТВЛЕНИЕМ, ПРЕДЕЛ_ВЕТВЛЕНИЯ, свести } from "../proof/reduce.mjs"

/** Обязательства и вердикты ядра для текста — тем же путём, каким их считает оболочка. */
async function разобрать(исходник, имя = "формы.flang") {
  const программа = await loadProgramFromSource(исходник, имя)
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, об, ядро, первый: ядро.checked[0] ?? null }
}

const вердикт = (об, имя) =>
  об.obligations.find((о) => о.kind === "postcondition" && о.name === имя)?.discharge ?? null

const отказы = (ядро) => ядро.diagnostics.map((д) => д.message).join("\n")

/* ================================================================== */
/* 1. РАЗБОР ЦЕЛИ ПО УСЛОВИЮ                                           */
/* ================================================================== */

/**
 * Тело-условие: «Следует» из `stdlib/logic.flang`, перенесённое дословно.
 *
 * Утверждение полное — оно исчерпывает смысл функции, — и до этой работы ядро
 * его не брало ничем: тело не `разбор`, индукции не по чему (у `признак`
 * принципа нет), а цель — равенство двух разных деревьев.
 */
const УСЛОВИЕ_В_ТЕЛЕ = `модуль «Условие в теле»

тотальная функция «Следует»
  принимает посылка: признак, следствие: признак
  возвращает признак
  для всех посылка обеспечивает «это классическая импликация» результат равен ((не посылка) или следствие)
  если посылка то следствие иначе да
`

/**
 * ПОДДЕЛКА. Половина «условие ложно» неправда, а половина «условие истинно» —
 * правда. Ход обязан требовать ОБЕ: иначе он доказывал бы утверждение, верное
 * только на части входов, и печатал бы при этом «обо ВСЕХ входах».
 *
 * `если х больше 0 то х иначе (0 минус х)` — это модуль, и он неотрицателен; а
 * подделка утверждает `результат не меньше х`, что правда только в ветви `то`
 * (при х = −5 модуль равен 5, и `5 не меньше −5` — тоже правда… поэтому взято
 * другое: `результат равен х`, ложное ровно в ветви `иначе` при х < 0).
 */
const ПОДДЕЛКА_ПОЛОВИНОЙ = `модуль «Подделка половиной»

тотальная функция «Модуль»
  принимает х: число
  возвращает число
  для всех х обеспечивает «это и есть вход» результат равен х
  если х больше 0 то х иначе (0 минус х)
`

/** ИЗЪЯТИЕ: та же функция с честным утверждением — ход обязан его взять. */
const ЧЕСТНОЕ_ПОЛОВИНОЙ = ПОДДЕЛКА_ПОЛОВИНОЙ
  .replace("«это и есть вход» результат равен х", "«вход или его отрицание» результат равен (если х больше 0 то х иначе (0 минус х))")

test("тело-условие: цель делится по условию и закрывается БЕЗ теоремы", async () => {
  const { об } = await разобрать(УСЛОВИЕ_В_ТЕЛЕ)
  const вывод = вердикт(об, "это классическая импликация")
  assert.equal(вывод?.verdict, "доказано", `не взято: ${JSON.stringify(вывод)}`)
  assert.equal(вывод.rule, ВЕТВЛЕНИЕМ, `закрыто не тем ходом: ${вывод.rule}`)
  /* Ведомость обязана назвать ход своим словом: «разбор цели по условию» и
     «вычисление замкнутой цели» держатся на разном, и читатель обязан видеть,
     на чём. */
  assert.match(вывод.says, /разбор цели по условию/u, вывод.says)
})

test("ПОДДЕЛКА ПОЛОВИНОЙ: правда только в ветви «то» — ядро не берёт", async () => {
  const { об } = await разобрать(ПОДДЕЛКА_ПОЛОВИНОЙ)
  const вывод = вердикт(об, "это и есть вход")
  assert.notEqual(вывод?.verdict, "доказано", `ядро доказало ложь: ${вывод?.says}`)
})

test("ИЗЪЯТИЕ подделки: честное утверждение о той же функции ядро берёт", async () => {
  const { об } = await разобрать(ЧЕСТНОЕ_ПОЛОВИНОЙ)
  const вывод = вердикт(об, "вход или его отрицание")
  assert.equal(вывод?.verdict, "доказано", "запрет съел само правило, а не подделку")
})

test("условие ПОД СВЯЗЫВАТЕЛЕМ не берётся: под свёрткой у него нет одного значения", () => {
  /* Свёртка связывает `эл`, и `эл равно "х"` означает своё на каждом элементе.
     Заменить его одним значением значило бы говорить о списке из одинаковых
     элементов. Ход обязан за такое условие не браться ВОВСЕ — и отказ тогда о
     ветвлении не говорит ни слова. */
  const цель = {
    kind: "binary",
    op: "eq",
    left: {
      kind: "fold",
      over: { kind: "var", name: "список" },
      init: { kind: "literal", value: true },
      acc: "акк",
      item: "эл",
      body: {
        kind: "if",
        cond: { kind: "binary", op: "eq", left: { kind: "var", name: "эл" }, right: { kind: "literal", value: "х" } },
        then: { kind: "var", name: "акк" },
        else: { kind: "literal", value: false },
      },
    },
    right: { kind: "literal", value: true },
  }
  const итог = свести(цель, [], [], null, null, ПРЕДЕЛ_ВЕТВЛЕНИЯ)
  assert.equal(итог.ok, false, "ядро взяло условие из-под связывателя")
  assert.equal(/разбор цели по условию/u.test(итог.why), false, итог.why)
})

test("предел ветвления назван числом и говорит о себе в отказе", () => {
  /* Пять вложенных условий подряд при пределе четыре: ход обязан остановиться
     и СКАЗАТЬ об этом. Молчаливое «не вышло» здесь было бы худшим ответом —
     неотличимым от «неправда». */
  const имя = (н) => ({ kind: "var", name: `у${н}` })
  let терм = { kind: "literal", value: 1 }
  for (let н = ПРЕДЕЛ_ВЕТВЛЕНИЯ + 1; н >= 1; н -= 1) {
    терм = { kind: "if", cond: имя(н), then: терм, else: { kind: "var", name: `н${н}` } }
  }
  const цель = { kind: "binary", op: "gte", left: терм, right: { kind: "literal", value: 0 } }
  const итог = свести(цель, [], [], null, null, ПРЕДЕЛ_ВЕТВЛЕНИЯ)
  assert.equal(итог.ok, false)
  assert.match(итог.why, new RegExp(`предел ветвления \\(${ПРЕДЕЛ_ВЕТВЛЕНИЯ}\\)`, "u"), итог.why)
})

