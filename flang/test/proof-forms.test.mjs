/**
 * Тело-свёртка и утверждение О НАКОПИТЕЛЕ: длина растёт, а знак — нет.
 *
 * Начало свёртки — литерал 0, виток — `акк плюс 1`. Утверждение «результат не
 * меньше 0» истинно о начале и переживает виток, а витков ровно столько,
 * сколько ячеек в списке.
 */
const СВЁРТКА_ИНВАРИАНТ = `модуль «Свёртка инвариант»

тотальная функция «Сколько всего»
  принимает элементы: список числа
  возвращает число
  для всех элементы обеспечивает «счёт неотрицателен» результат не меньше 0
  свёртка элементы начиная с 0 как акк и эл → акк плюс 1

теорема «счёт неотрицателен»
  дано элементы: список числа
  утверждаем результат не меньше 0
  индукция по элементы
    случай голова и хвост
      то по предположению
  следовательно доказано
`

/**
 * ПОДДЕЛКА. То же тело, но утверждение связывает результат со СПИСКОМ:
 * «результат равен длине». Оно ИСТИННО (счётчик и есть длина), но инвариантом
 * накопителя не доказывается: при пустом списке начало 0 равно длине пустого,
 * а виток `акк плюс 1` из «акк равен длине» никакого «акк плюс 1 равен длине»
 * не даёт. Ход обязан отказать, а не принять.
 *
 * Это и есть ГРАНИЦА принципа, названная числом: из шести функций замера,
 * написанных свёрткой, пять утверждают именно такую форму.
 */
const СВЁРТКА_ПРО_СПИСОК = `модуль «Свёртка про список»

тотальная функция «Сколько всего»
  принимает элементы: список числа
  возвращает число
  для всех элементы обеспечивает «счёт есть длина» результат равен (длина элементы)
  свёртка элементы начиная с 0 как акк и эл → акк плюс 1

теорема «счёт есть длина»
  дано элементы: список числа
  утверждаем результат равен (длина элементы)
  индукция по элементы
    случай голова и хвост
      то по предположению
  следовательно доказано
`

/**
 * ПОДДЕЛКА. Накопитель свёртки назван ИМЕНЕМ ПАРАМЕТРА, и параметр стоит в
 * цели. Снаружи `порог` — число из подписи, внутри витка — накопитель, и
 * посылка говорила бы не о том, о чём её написали.
 */
const СВЁРТКА_ЗАХВАТ = `модуль «Свёртка захват»

тотальная функция «Не ниже порога»
  принимает элементы: список числа, порог: нат
  возвращает число
  для всех элементы обеспечивает «не ниже порога» результат не меньше 0
  свёртка элементы начиная с порог как порог и эл → (0 минус 1)

теорема «не ниже порога»
  дано элементы: список числа
  дано порог: нат
  утверждаем результат не меньше 0
  индукция по элементы
    случай голова и хвост
      то по предположению
  следовательно доказано
`

test("тело-свёртка: посылки читаются с начала и витка, и вердикт называет свёртку", async () => {
  const { об, ядро } = await разобрать(СВЁРТКА_ИНВАРИАНТ)
  const вывод = вердикт(об, "счёт неотрицателен")
  assert.equal(вывод?.verdict, "доказано", `не взято: ${отказы(ядро)}`)
  assert.equal(вывод.induction?.carrier, "fold", `носитель принципа назван неверно: ${вывод.induction?.carrier}`)
  assert.equal(вывод.induction?.base, 1)
  assert.equal(вывод.induction?.step, 1)
  /* Носитель обязан быть назван СВОИМ словом: свёртка в flang левая, и это НЕ
     индукция по списку. Сказать «по «список»» значило бы назвать носителем
     начальность, на которой этот принцип не стоит. */
  assert.equal(вывод.induction?.fold?.acc, "акк")
})

test("ПОДДЕЛКА СВЁРТКОЙ: утверждение про СПИСОК инвариантом накопителя не доказывается", async () => {
  const { об, ядро } = await разобрать(СВЁРТКА_ПРО_СПИСОК)
  const вывод = вердикт(об, "счёт есть длина")
  assert.equal(вывод?.verdict, "отвергнуто", `ядро приняло то, чего не доказывало: ${вывод?.says}`)
  /* Отказ обязан назвать посылку свёртки поимённо: автор чинит не «что-то в
     теореме», а начало или виток. Здесь не сходится и то, и другое — при
     свободном списке «0 равен длине элементы» ложно так же, как и шаг. */
  assert.match(отказы(ядро), /начало свёртки|шаг свёртки/u, отказы(ядро))
})

test("ПОДДЕЛКА ЗАХВАТОМ СВЁРТКИ: накопитель, названный именем параметра, — отказ по имени", async () => {
  const { об, ядро } = await разобрать(СВЁРТКА_ЗАХВАТ)
  const вывод = вердикт(об, "не ниже порога")
  assert.notEqual(вывод?.verdict, "доказано", `ядро доказало ложь: ${вывод?.says}`)
  assert.match(отказы(ядро), /«порог»/u, отказы(ядро))
})

test("ИЗЪЯТИЕ: тело-вызов посылок по-прежнему не даёт, и отказ называет ОБЕ читаемые формы", async () => {
  const { ядро } = await разобрать(`модуль «Тело вызов»

тотальная функция «Длина списка»
  принимает элементы: список числа
  возвращает число
  длина элементы

тотальная функция «Через вызов»
  принимает элементы: список числа
  возвращает число
  для всех элементы обеспечивает «через вызов неотрицательно» результат не меньше 0
  0 минус («Длина списка» от элементы)

теорема «через вызов неотрицательно»
  дано элементы: список числа
  утверждаем результат не меньше 0
  индукция по элементы
    случай голова и хвост
      то по предположению
  следовательно доказано
`)
  const текст = отказы(ядро)
  assert.match(текст, /не разбирает/u, текст)
  assert.match(текст, /не сворачивает/u, текст)
})

