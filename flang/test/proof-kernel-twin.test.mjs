/**
 * Близнец ядра на flang: тотален, печатается всюду и отвечает то же, что эталон.
 *
 * ── Что здесь доказывается прогоном, а не рассуждением ──────────────────────
 * Свойство, ради которого ядро своё, а не чужое: проверяльщик термов —
 * структурная свёртка по КОНЕЧНОМУ дереву, то есть идеальная тотальная программа
 * flang. Пока это утверждение стоит в комментарии, оно ничем не подтверждено.
 * Здесь оно подтверждается тремя измерениями:
 *
 *   1. `flang check` объявляет каждую функцию ядра тотальной, и у рекурсивных
 *      носитель обещания — СТРУКТУРА, то есть убывание доказано статически.
 *      Сторожей в рантайме ноль. Это сильнее, чем «тотальна»: с мерой или
 *      постоянным шагом тотальность тоже бывает, но со сторожем, а сторож —
 *      место, где программа честно откажет вместо ответа.
 *   2. Ядро печатается во все восемь целей. Проверяльщик, который живёт только
 *      в Node, не годится: язык обещает работать всюду, и ядро — часть языка.
 *   3. Вердикты близнеца совпадают с вердиктами эталона на одних и тех же
 *      термах. Это тот же приём, которым в этом дереве сверяются девять
 *      исполнителей и которым держится побайтовая неподвижная точка
 *      самоприменения: два независимых ответа на один вопрос обязаны сойтись.
 *
 * ── Чего эта сверка НЕ доказывает, и это надо сказать вслух ─────────────────
 * Она не доказывает состоятельности ядра. Совпадение двух реализаций ловит
 * ошибку в одной из них, но общая ошибка проекта останется общей. Поэтому
 * говорить о результате следует ровно с той силой, какая у него есть:
 * «перекрёстно сверено на N термах», а не «ядро состоятельно». Это та же
 * дисциплина, по которой в ведомости запрещено слово «проверено» вместо
 * «доказано»: утверждение обязано быть той силы, какой оно есть.
 */
import assert from "node:assert/strict"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { emitJs } from "../src/emit/js.mjs"
import { evaluate } from "../src/interpret.mjs"
import { checkTotality } from "../src/totality.mjs"
import { loadProgram } from "../bin/flang.mjs"
import { СИЛА } from "../src/proofterm.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const ПУТЬ = "flang/proof/kernel.flang"
const ШАГИ = 200000

const ядро = await loadProgram(join(корень, ПУТЬ))

/* Свои конструкторы значений вместо литералов в каждом тесте: терм ниже
   строится трижды разными способами, и три записи одного и того же — способ
   их спутать. */
const шаг = (пометка) => ({ variant: "Шаг", fields: { пометка: { variant: пометка, fields: {} } } })
const конец = { variant: "Конец цепочки", fields: {} }
const цепочка = (пометки) =>
  пометки.reduceRight(
    (дальше, пометка) => ({ variant: "Звено цепочки", fields: { шаг: шаг(пометка), дальше } }),
    конец,
  )
const нетСлучаев = { variant: "Нет случаев", fields: {} }
const случаи = (список) =>
  список.reduceRight(
    (прочие, пометки) => ({ variant: "Случай", fields: { шаги: цепочка(пометки), прочие } }),
    нетСлучаев,
  )

const вызвать = (имя, args) => evaluate(ядро, имя, args, ШАГИ)

/* ================================================================== */
/* 1. Ядро на flang тотально, и носитель обещания — структура          */
/* ================================================================== */

test("каждая функция ядра объявлена тотальной и доказана анализом", () => {
  const итог = checkTotality(ядро)
  assert.deepEqual(итог.diagnostics, [], "анализ завершаемости отказал")
  assert.equal(итог.ok, true)
  assert.equal(ядро.functions.length, 5, "функций в ядре")
  for (const fn of ядро.functions) {
    assert.equal(fn.total, true, `«${fn.name}» не объявлена тотальной`)
    assert.ok(итог.total.has(fn.name), `«${fn.name}» объявлена тотальной, но не доказана`)
  }
})

test("рекурсия ядра несётся СТРУКТУРОЙ: сторожей в рантайме ноль", () => {
  /* Это и есть проверяемое свойство. Тотальность бывает и со сторожем — на
     постоянном шаге и на объявленной мере, — но сторож это место, где программа
     честно откажет вместо ответа. У свёртки по конечному дереву такого места нет
     и быть не должно: часть значения меньше значения, и цепочка частей
     обрывается сама. Изымите структурное убывание — и здесь появится сторож. */
  const итог = checkTotality(ядро)
  assert.deepEqual(итог.guards ?? [], [], "у ядра появился сторож на постоянном шаге")
  assert.deepEqual(итог.descents ?? [], [], "у ядра появился сторож на объявленной мере")
  const структурой = new Set((итог.structures ?? []).map((з) => з.from))
  assert.deepEqual(
    [...структурой].sort(),
    ["Вердикт случаев", "Вердикт цепочки"],
    "структурное убывание доказано не у тех функций",
  )
  /* Компонент цикла ровно столько, сколько рекурсивных функций: взаимной
     рекурсии в ядре нет, и это тоже свойство — свёртка идёт по одному дереву. */
  assert.equal((итог.cycles ?? []).length, 2, "циклов в графе вызовов ядра")
})

test("все примеры ядра сходятся: близнец считает то, что обещает", () => {
  let примеров = 0
  for (const fn of ядро.functions) {
    for (const пример of fn.examples ?? []) {
      примеров += 1
      const получено = вызвать(fn.name, пример.args ?? {})
      /* Сравниваются ЗНАЧЕНИЯ, а не прототипы: интерпретатор отдаёт вариант
         экземпляром своего класса, а разбор примера — обычным объектом, и
         `deepEqual` из `assert/strict` считает это разницей. Разницы здесь нет:
         вариант — это имя и поля, и оба сравниваются. */
      assert.deepEqual(
        JSON.parse(JSON.stringify(получено)),
        JSON.parse(JSON.stringify(пример.expected)),
        `«${fn.name}» / «${пример.name}»`,
      )
    }
  }
  assert.ok(примеров >= 17, `примеров в ядре всего ${примеров}`)
})

test("ядро печатается в JavaScript — значит живёт не только в интерпретаторе", () => {
  /* Полная сверка по восьми целям стоит в `cli-emit.test.mjs` для всего корпуса;
     здесь проверяется, что ядро в этот корпус входит и печать его не отвергает.
     Проверяльщик, который живёт только в Node, не годится: язык обещает работать
     всюду, и ядро — часть языка. */
  const напечатано = emitJs(ядро)
  const файлы = напечатано.files ?? напечатано
  assert.ok(Array.isArray(файлы) && файлы.length > 0, "печать не дала ни одного файла")
  const текст = файлы.map((ф) => ф.content).join("\n")
  for (const имя of ["Вердикт цепочки", "Вердикт случаев", "Вердикт доказательства"]) {
    assert.ok(текст.includes(имя), `в напечатанном коде нет «${имя}»`)
  }
})

/* ================================================================== */
/* 2. Правило «слабейшее побеждает» — на всех девяти парах             */
/* ================================================================== */

test("слабейшее побеждает: проверено на всех девяти парах вердиктов", () => {
  /* Не на выборке, а на ПОЛНОЙ таблице: вердиктов три, пар девять, и перебрать
     их целиком дешевле, чем спорить, какие важнее. Порядок задан здесь заново, а
     не взят у ядра, — иначе сверялось бы ядро с самим собой. */
  const порядок = ["Доказано", "Сетка", "Отвергнуто"]
  let пар = 0
  for (const левый of порядок) {
    for (const правый of порядок) {
      пар += 1
      const ожидается = порядок[Math.max(порядок.indexOf(левый), порядок.indexOf(правый))]
      const получено = вызвать("Слабее", {
        левый: { variant: левый, fields: {} },
        правый: { variant: правый, fields: {} },
      })
      assert.equal(получено.variant, ожидается, `«${левый}» и «${правый}»`)
    }
  }
  assert.equal(пар, 9, "таблица обязана быть полной")
})

/* ================================================================== */
/* 3. Перекрёстная сверка: близнец и эталон отвечают одно             */
/* ================================================================== */

/**
 * Тот же свод, что делает эталон, — записанный здесь заново и независимо.
 *
 * Записан ЗАНОВО намеренно: взять его у эталона значило бы сверять эталон с
 * самим собой. Правило одно и то же — слабейшее побеждает, пустое отвергается, —
 * и если два независимых прочтения этого правила расходятся, значит правило
 * сформулировано плохо, и это тоже находка.
 */
function эталонныйВердикт(случаиТерма, закрыто) {
  if (!закрыто) return СИЛА.refused
  if (случаиТерма.length === 0) return СИЛА.refused
  let итог = СИЛА.proved
  const ослабить = (до) => {
    if (итог === СИЛА.refused) return
    if (до === СИЛА.refused) итог = СИЛА.refused
    else if (до === СИЛА.grid && итог === СИЛА.proved) итог = СИЛА.grid
  }
  for (const пометки of случаиТерма) {
    if (пометки.length === 0) {
      ослабить(СИЛА.refused)
      continue
    }
    for (const пометка of пометки) {
      if (пометка === "Не выведен") ослабить(СИЛА.refused)
      else if (пометка === "Выведен сеткой") ослабить(СИЛА.grid)
    }
  }
  return итог
}

const СЛОВО = { Доказано: СИЛА.proved, Сетка: СИЛА.grid, Отвергнуто: СИЛА.refused }

test("вердикты близнеца и эталона совпали на всех порождённых термах", () => {
  /* Термы порождаются перебором, а не подбираются руками: пометок три, длина
     цепочки до трёх, случаев до трёх, плюс признак «закрыто». Число входов
     печатается — сверка, чей охват нельзя перепроверить, даёт ложную
     уверенность (тот же довод, по которому корпус моделей ядра печатает свой
     охват).

     Слово о силе результата: это ПЕРЕКРЁСТНАЯ СВЕРКА, а не доказательство
     состоятельности. Она ловит ошибку в одной из двух реализаций; общая ошибка
     останется общей. */
  const пометки = ["Выведен", "Выведен сеткой", "Не выведен"]
  const цепочки = [[]]
  for (const а of пометки) {
    цепочки.push([а])
    for (const б of пометки) {
      цепочки.push([а, б])
      for (const в of пометки) цепочки.push([а, б, в])
    }
  }

  let входов = 0
  const расхождения = []
  for (const закрыто of [true, false]) {
    /* Наборы случаев: ни одного, один, два — из полного перечня цепочек.
       Три случая по 40 цепочек дали бы 64 000 входов и ничего нового: правило
       свода ассоциативно, и третий случай проверяется тем же, чем второй. */
    const наборы = [[], ...цепочки.map((ц) => [ц])]
    for (const первая of цепочки) {
      for (const вторая of цепочки) наборы.push([первая, вторая])
    }
    for (const набор of наборы) {
      входов += 1
      const близнец = вызвать("Вердикт доказательства", { случаи: случаи(набор), закрыто })
      const эталон = эталонныйВердикт(набор, закрыто)
      if (СЛОВО[близнец.variant] !== эталон) {
        расхождения.push(
          `закрыто=${закрыто} набор=${JSON.stringify(набор)}:`
            + ` близнец «${близнец.variant}» → ${СЛОВО[близнец.variant]}, эталон ${эталон}`,
        )
      }
    }
  }
  assert.deepEqual(расхождения, [], `расхождений ${расхождения.length} из ${входов}`)
  assert.ok(входов >= 3000, `входов всего ${входов} — охват сверки ужался`)
  console.log(`  перекрёстная сверка: ${входов} термов, расхождений 0`)
})

test("сверка умеет краснеть: подменённое правило свода ловится", () => {
  /* Проверка, которая не умеет находить расхождение, ничего не сверяет. Здесь
     ломается ЭТАЛОННОЕ правило — «сильнейшее побеждает» вместо слабейшего, — и
     сверка обязана это увидеть. Ломать близнеца нельзя: он лежит файлом в
     дереве, и правка файла ради теста осталась бы в дереве. */
  const наизнанку = (случаиТерма) => {
    if (случаиТерма.some((п) => п.includes("Выведен"))) return СИЛА.proved
    return СИЛА.refused
  }
  let нашлось = false
  for (const набор of [[["Не выведен"]], [["Выведен", "Не выведен"]], [["Выведен сеткой"]]]) {
    const близнец = вызвать("Вердикт доказательства", { случаи: случаи(набор), закрыто: true })
    if (СЛОВО[близнец.variant] !== наизнанку(набор)) нашлось = true
  }
  assert.ok(нашлось, "подменённое правило прошло сверку — значит сверка ничего не проверяет")
})
