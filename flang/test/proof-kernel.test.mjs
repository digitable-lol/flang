test("ядро принимает терм: случаи покрывают конечную сумму точно", async () => {
  const { первый, внешнее } = await разобратьФайл(СВЕТОФОР)
  assert.equal(внешнее.diagnostics.length, 0, JSON.stringify(внешнее.diagnostics))
  assert.equal(первый.verdict, СИЛА.proved)
  assert.equal(первый.steps, 3)
  assert.deepEqual(
    первый.cases.map((с) => с.variant),
    ["Красный", "Жёлтый", "Зелёный"],
    "случаев ровно столько, сколько конструкторов",
  )
  assert.equal(первый.refusals.length, 0)
  assert.match(первый.says, /^доказано ядром/u)
  /* Слово «проверено» под запретом и здесь: вердикт ядра едет в ведомость как
     есть, и одно неосторожное слово вернуло бы всю путаницу. */
  assert.ok(!/провер/iu.test(первый.says), первый.says)
})

test("список аксиом арифметики пуст, и это утверждение о ядре", () => {
  /* Пуст намеренно: числа flang — IEEE-754, где «х плюс 1 не меньше х» неправда
     при большом |х|. Аксиома, которая иногда ложна, делает ложным всё, что из
     неё выведено. Проверка стоит затем, чтобы аксиому нельзя было добавить
     молча — вместе с ней обязано появиться обоснование и правка этой строки. */
  assert.deepEqual(АКСИОМЫ, [], "аксиомы ждут точного типа «нат» с дном")
})

