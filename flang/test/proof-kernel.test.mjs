test("ловушка 2⁵³ — не рассуждение, а число: и потому список форм спуска закрыт", () => {
  /* Та же мерка, что у правил сведения: правило, у которого нет доказательства о
     IEEE-754, в ядро не попадает. Здесь показано ОБРАТНОЕ — почему спуск обязан
     жить внутри [0, 2⁵³−1], а не «по числам вообще».

     Внутри отрезка соседние целые представимы точно, поэтому `х минус 1`
     вычисляется точно и строго меньше `х`. За 2⁵³ это ложь, и ложь буквальная. */
  assert.equal(2 ** 53 + 4 - 1, 2 ** 53 + 4, "«х минус 1 меньше х» ложно при х = 2⁵³+4 — на этом и стоит запрет")
  assert.ok(Number.MAX_SAFE_INTEGER - 1 < Number.MAX_SAFE_INTEGER, "внутри отрезка спуск строг — иначе принципа нет")
  /* А у `число` спуска нет вовсе: `+∞ минус 1` равно `+∞`, цепочка не кончается. */
  assert.equal(Number.POSITIVE_INFINITY - 1, Number.POSITIVE_INFINITY, "по «число» индукция была бы бесконечным спуском")
  /* И потолок ядро берёт у типизатора, а не переписывает: разойдись два числа —
     ядро сочло бы точным то, что типизатор точным не считает. */
  assert.equal(ТОЧНАЯ_СЕТКА.верх, Number.MAX_SAFE_INTEGER)
})

