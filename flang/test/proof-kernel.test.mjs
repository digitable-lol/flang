/* Факт посылки ШАГА: условие дна в ветви спуска ЛОЖНО                 */
/* ------------------------------------------------------------------ */

/**
 * Вторая половина прочитанной формы — и до этой работы она пропадала.
 *
 * Дно ядро читает с условия `если` и кладёт в посылку базы факт «п не больше
 * верх». В ветвь СПУСКА вычисление попадает ровно тогда, когда то же условие
 * ЛОЖНО, — а поле `facts` у посылки шага стояло пустым, то есть написанное
 * автором в шаге не читалось вовсе.
 *
 * Проверяется здесь три вещи, и все три нужны:
 *   1. факт есть, и он один и тот же по форме у всех пяти записей условия;
 *   2. факт ИСТИНЕН — вычислением, а не рассуждением: значения, попадающие в
 *      ветвь спуска, все до одного больше `верх`;
 *   3. факт стоит только у шага: у базы свой, и он противоположный.
 */
const ФОРМЫ_ДНА = [
  { условие: "н не больше 1", верх: 1, спуск: "иначе" },
  { условие: "н меньше 2", верх: 1, спуск: "иначе" },
  { условие: "н равно 0", верх: 0, спуск: "иначе" },
  { условие: "н больше 1", верх: 1, спуск: "то" },
  { условие: "н не меньше 2", верх: 1, спуск: "то" },
]

test("посылка ШАГА несёт факт «п больше верх» — вторую половину той же прочитанной формы", async () => {
  for (const форма of ФОРМЫ_ДНА) {
    /* База и спуск ставятся по ветвям так, как велит форма: у «больше» и «не
       меньше» база — это `иначе`. Тело при этом одно и то же по существу. */
    const дно = "1"
    const шаг = "н умножить на («Ф» от (н минус 1))"
    const то = форма.спуск === "то" ? шаг : дно
    const иначе = форма.спуск === "то" ? дно : шаг
    const исходник = `модуль «Формы»

// Условие вынесено СЛОВО В СЛОВО, чтобы «в какую ветвь попало вычисление» можно
// было спросить у языка, а не пересказать здесь второй раз.
функция «Условие»
  принимает н: нат
  возвращает признак
  ${форма.условие}

тотальная функция «Ф»
  принимает н: нат
  возвращает число
  для всех н обеспечивает «ф неотрицательна» результат не меньше 0
  если ${форма.условие}
    то ${то}
    иначе ${иначе}

теорема «ф неотрицательна»
  дано н: нат
  утверждаем результат не меньше 0
  индукция по н убывает н
    случай любое
      то по предположению
  следовательно доказано
`
    const { программа, об } = await разобрать(исходник)
    const функция = программа.functions.find((ф) => ф.name === "Ф")
    const обязательство = об.obligations.find((о) => о.kind === "postcondition")
    const принцип = принципПоЧислу({
      тип: "нат",
      функция,
      обязательство,
      индукция: { param: "н", measure: { kind: "var", name: "н" }, cases: [] },
    })
    assert.equal(принцип.unread, null, `${форма.условие}: ${JSON.stringify(принцип.unread)}`)
    const [база, спуск] = принцип.premises

    /* 1. Факт есть, он один, и он ровно «п больше верх». */
    assert.equal(спуск.facts.length, 1, `${форма.условие}: фактов у шага ${спуск.facts.length}`)
    assert.deepEqual(
      спуск.facts[0].claim,
      { kind: "binary", op: "gt", left: { kind: "var", name: "н" }, right: { kind: "literal", value: форма.верх } },
      форма.условие,
    )

    /* 3. А у базы факт свой и противоположный — списки не перепутаны. */
    assert.deepEqual(
      база.facts[0].claim,
      { kind: "binary", op: "lte", left: { kind: "var", name: "н" }, right: { kind: "literal", value: форма.верх } },
      форма.условие,
    )

    /* 2. И факт ИСТИНЕН — не рассуждением, а прогоном. Условие считает сам язык
       (функция «Условие» — то же выражение слово в слово), ветвь читается по его
       значению, и на КАЖДОМ значении, попавшем в спуск, факт обязан быть правдой.
       Проверка это не половинчатая: она же ловит и обратное — значение, которое
       больше `верх`, но ушло в базу; такое означало бы, что `верх` прочитан не с
       той стороны, и факт БАЗЫ стал бы ложью. */
    let вСпуске = 0
    for (let н = 0; н <= 8; н += 1) {
      const условие = evaluate(программа, "Условие", { н })
      const спускВзят = форма.спуск === "то" ? условие === true : условие === false
      if (спускВзят) {
        вСпуске += 1
        assert.ok(н > форма.верх, `${форма.условие}: н=${н} ушло в спуск, а факт «н больше ${форма.верх}» на нём ЛОЖЬ`)
      } else {
        assert.ok(н <= форма.верх, `${форма.условие}: н=${н} ушло в базу, а факт «н не больше ${форма.верх}» на нём ЛОЖЬ`)
      }
    }
    assert.ok(вСпуске > 0, `${форма.условие}: в спуск не попало ни одного значения — проверка пустая`)
  }
})

/**
 * ПОДДЕЛКА С ДРОБНЫМ ДНОМ — и это не выдуманная опасность, а найденная.
 *
 * До этой работы ядро печатало об утверждении ниже «доказано индукцией», а
 * рантайм отвергал его `FLANG_PROPERTY` на первом же входе `н = 2`. Причина
 * стояла в таблице `ДНО` (`flang/proof/initial.mjs`): у формы `если п меньше К`
 * верх дна считается как `К минус 1`, и при ДРОБНОМ `К` этот верх врёт. `если н
 * меньше 2.5` отправляет в базу значения 0, 1 и 2 — а посылка базы получала ФАКТ
 * «н не больше 1.5», ложный ровно на `н = 2`. Отсюда и «доказано» о неправде.
 *
 * Улика здесь исполняемая с ОБЕИХ сторон: ядро обязано отвергнуть, и рантайм
 * обязан на том же входе показать, что отвергать было за что. Проверка, у которой
 * есть только первая половина, не отличает «ядро осторожно» от «ядро право».
 */
test("ПОДДЕЛКА: дробное дно `если н меньше 2.5` — ОТВЕРГНУТО, и ложь видна рантаймом", async () => {
  const дробное = `модуль «Дробное дно»

тотальная функция «Мал»
  принимает н: нат
  возвращает число
  для всех н обеспечивает «мал» результат не больше 1.5
  пример «ноль»
    дано н равно 0
    ожидается 0
  если н меньше 2.5
    то н
    иначе «Мал» от (н минус 1)

теорема «мал»
  дано н: нат
  утверждаем результат не больше 1.5
  индукция по н убывает н
    случай любое
      то по предположению
  следовательно доказано
`
  const { первый, внешнее, программа } = await разобрать(дробное)
  assert.equal(первый.verdict, СИЛА.refused, "ядро доказало ЛОЖЬ: дробное дно принято")
  const беда = внешнее.diagnostics.find((д) => д.code === "FLANG_PROOF_INDUCTION_BRANCH")
  assert.ok(беда !== undefined, JSON.stringify(внешнее.diagnostics.map((д) => д.code)))
  assert.match(беда.message, /К обязан быть ещё и ЦЕЛЫМ/u, беда.message)

  /* И утверждение ДЕЙСТВИТЕЛЬНО ложно: на `н = 2` вычисление уходит в базу и
     возвращает 2, а обещано «не больше 1.5». Без этой половины отказ выше читался
     бы как придирка. */
  assert.throws(
    () => evaluate(программа, "Мал", { н: 2 }),
    (беда) => беда.code === "FLANG_PROPERTY",
    "утверждение оказалось правдой — тогда отказ ядра выше ничего не значит",
  )

  /* ИЗЪЯТИЕ: та же запись с ЦЕЛЫМ дном читается и доказывается. Отказ обязан быть
     от дробности, а не от того, что форма `меньше` перестала читаться вовсе. */
  const целое = дробное.replaceAll("2.5", "2").replaceAll("1.5", "1")
  const { первый: сЦелым } = await разобрать(целое)
  assert.equal(сЦелым.verdict, СИЛА.proved, JSON.stringify(сЦелым.refusals))
})

