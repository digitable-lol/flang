/* ── Закон: ссылка законна, но ослабляет вердикт до сетки ───────────────── */

const С_ЗАКОНОМ = `модуль «Сложение»

тип «Знак»
  вариант «Плюс»

моноид «Сумма»
  носитель число
  операция «Сложить»
  единица 0

тотальная функция «Сложить»
  принимает левое: число, правое: число
  возвращает число
  пример «нули»
    дано левое равно 0
    дано правое равно 0
    ожидается 0
  левое плюс правое

тотальная функция «Ноль»
  принимает знак: «Знак»
  возвращает число
  для всех знак обеспечивает «ноль неотрицателен» результат не меньше 0
  пример «плюс»
    дано знак равно вариант «Плюс»
    ожидается 0
  разбор знак
    случай вариант «Плюс»
      то 0

теорема «ноль неотрицателен»
  дано знак: «Знак»
  утверждаем результат не меньше 0
  индукция по знак
    случай вариант «Плюс»
      то по закону «Сумма»
  следовательно доказано
`

test("шаг по закону принят, но вердикт ослаблен до сетки, а не «доказано»", async () => {
  /* Законы моноида посчитаны на конечной сетке автора, а не доказаны.
     Доказательство не может быть сильнее того, на что опирается — и ведомость
     обязана сказать «сетка». Промолчи об этом один раз, и вся разница между
     доказанным и посчитанным потеряна. */
  const { первый } = await разобрать(С_ЗАКОНОМ)
  assert.equal(первый.verdict, СИЛА.grid, JSON.stringify(первый.refusals))
  assert.match(первый.says, /^сетка/u)
  assert.match(первый.says, /это не доказательство/u)
  assert.ok(!первый.says.includes("доказано ядром"), первый.says)
})

test("ссылка на необъявленный закон — отвергнуто", async () => {
  /* Изъятие того, что стережёт эта проверка: без неё строка `по закону «чего не
     бывает»` закрывала бы любой шаг, и ядро перестало бы проверять. */
  const испорченный = С_ЗАКОНОМ.replace('по закону «Сумма»', 'по закону «Чего не бывает»')
  assert.notEqual(испорченный, С_ЗАКОНОМ)
  const { первый } = await разобрать(испорченный)
  assert.equal(первый.verdict, СИЛА.refused)
  assert.ok(
    первый.refusals.some((о) => /закона «Чего не бывает» в модуле нет/u.test(о.message)),
    JSON.stringify(первый.refusals),
  )
})

