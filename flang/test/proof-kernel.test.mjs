/**
 * Обязательства и ядро: что надо доказать и что доказано.
 *
 * ── Как читать этот файл ────────────────────────────────────────────────────
 * У каждой проверки ядра здесь есть близнец-изъятие: сначала «терм принят»,
 * потом «изымем то, что стережёт эта проверка, — и обязано быть отвергнуто».
 * Проверяльщик, который умеет только принимать, не проверяет ничего, и убедиться
 * в этом можно единственным способом: показать, что он краснеет там, где должен.
 *
 * ── Почему отказы проверяются на фикстурах, а не на файлах дерева ───────────
 * Файл с отвергнутым термом не проходит `flang check`, значит в дереве его быть
 * не может — свод по корпусу требует нуля отвергнутых прямо
 * (`proof.test.mjs`). Поэтому принятые доказательства лежат файлами в
 * `flang/proof/examples/`, а отвергаемые — здесь, шаблонными строками. Это то же
 * разделение, по которому намеренно сломанные модели FTS лежат в фикстурах, а не
 * в корпусе.
 */
import assert from "node:assert/strict"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgram, loadProgramFromSource } from "../bin/flang.mjs"
import { obligations, одинаковы } from "../src/obligations.mjs"
import { АКСИОМЫ, checkProofs, СИЛА } from "../src/proofterm.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/** Обязательства и вердикты ядра для текста — тем же путём, каким их считает оболочка. */
async function разобрать(исходник) {
  const программа = await loadProgramFromSource(исходник, "ядро.flang")
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, внешнее, об, ядро, первый: ядро.checked[0] ?? null }
}

/** Тот же путь для файла дерева. */
async function разобратьФайл(путь) {
  const программа = await loadProgram(join(корень, путь))
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, внешнее, об, ядро, первый: ядро.checked[0] ?? null }
}

