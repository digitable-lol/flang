/**
 * ПОЧЕМУ ЯДРО НЕ ЧИТАЕТ УСЛОВИЯ `если`, И ПОЧЕМУ ЭТО НЕ УПУЩЕНИЕ.
 *
 * Оба правила границ спускаются в `если` и требуют своего от ОБЕИХ ветвей, а
 * само условие не читают. Выглядит это упущением, и заказ на него стоял
 * исполняемой строкой: «Абсолютное значение» из `flang/stdlib/numbers.flang`
 * написана как `если число меньше 0 то 0 минус число иначе число`, и «модуль
 * числа неотрицателен» человеку очевидно.
 *
 * Приём, которым это делается, в дереве есть и работает: `сузить` в
 * `flang/src/types.mjs` (числовые отрезки) и там же сужение по `пусто`
 * (непустота списка). Отдать его ядру — правка в двадцать строк.
 *
 * ЭТОГО НЕ СДЕЛАНО, и здесь стоят ТРИ ЗАМЕРА, из-за которых:
 *
 *   1. ВЕТВЬ `ИНАЧЕ` ЧИТАТЬ НЕЛЬЗЯ — вывод был бы ЛОЖНЫМ. В IEEE-754 сравнение
 *      с NaN ложно всегда, поэтому «`число меньше 0` не выполнилось» не значит
 *      «`число` не меньше 0»: на NaN ложны ОБЕ стороны. А «Абсолютному значению»
 *      нужна ровно ветвь `иначе`.
 *   2. ВЕТВЬ `ТО` ЧИТАТЬ МОЖНО (сравнение, давшее `да`, исключает NaN само), и
 *      это закрывает НОЛЬ целей на весь корпус. Сужение, которым никто не
 *      пользуется, — доверие, за которое некому отвечать; тем же доводом дерево
 *      откладывало потолок `нат`, пока у него не появился проверяющий.
 *   3. ЗАКАЗАННОЕ ЦЕЛИКОМ (сужение ОБЕИХ ветвей плюс вычитание в правиле дна,
 *      без которого ветвь `то` «Абсолютного значения» всё равно не сводится)
 *      закрывает РОВНО ОДНУ цель корпуса — вот эту, — и она ЛОЖЬ.
 *
 * То есть цена всего заказа: одно «доказано», и оно неверно. Замер ниже
 * исполняемый в обе стороны: научись ядро сужать ветвь `то` с пользой — числа
 * разойдутся, и строку придётся переписать вместе с правилом.
 */

const нольУзла = (у) => у?.kind === "literal" && у.value === 0
const конечныйУзла = (у) => у?.kind === "literal" && typeof у.value === "number" && Number.isFinite(у.value)

/**
 * Факты, которые условие кладёт, когда оно ВЕРНО, — четыре формы, список закрыт.
 *
 * Написано здесь ЗАНОВО, а не взято у ядра: у ядра этого нет вовсе, и весь
 * смысл замера в том, чтобы посчитать, что было бы, если бы было. Тем же
 * приёмом в `self-proof-kernel.test.mjs` заново записано правило третьего
 * источника фактов.
 */
function фактыУсловияЗаново(условие, наружу = []) {
  if (условие === null || условие === undefined || typeof условие !== "object") return наружу
  /* `а и притом б` парсер разворачивает в `если а то б иначе нет`: в ветви `то`
     верны обе половины. `или` и `не` не читаются — у первого неизвестно, какая
     половина верна, у второго верна ЛОЖНОСТЬ, а из неё в IEEE-754 не следует
     ничего (замер 1 ниже про это). */
  if (условие.kind === "if" && условие.else?.kind === "literal" && условие.else.value === false) {
    фактыУсловияЗаново(условие.cond, наружу)
    фактыУсловияЗаново(условие.then, наружу)
    return наружу
  }
  if (условие.kind !== "binary") return наружу
  const { op, left, right } = условие
  if ((op === "gte" || op === "gt") && нольУзла(right)) наружу.push({ вид: "снизу", терм: left })
  else if ((op === "lte" || op === "lt") && нольУзла(left)) наружу.push({ вид: "снизу", терм: right })
  if ((op === "lte" || op === "lt") && конечныйУзла(right)) наружу.push({ вид: "сверху", терм: left, граница: right.value })
  else if ((op === "gte" || op === "gt") && конечныйУзла(left)) наружу.push({ вид: "сверху", терм: right, граница: left.value })
  return наружу
}

const ОТРИЦАНИЕ_ЗАНОВО = new Map([["gt", "lte"], ["lte", "gt"], ["lt", "gte"], ["gte", "lt"]])

function отрицатьУсловие(условие) {
  if (условие?.kind !== "binary") return null
  const op = ОТРИЦАНИЕ_ЗАНОВО.get(условие.op)
  return op === undefined ? null : { ...условие, op }
}

/**
 * Правило дна, написанное заново и с двумя тумблерами: сужать ли ветвь `иначе`
 * и брать ли вычитание. Всё остальное — тот же список случаев, что у ядра.
 */
function днуЗаново(выражение, снизу, неположительные, тумблеры) {
  if (выражение === null || выражение === undefined) return false
  if (выражение.kind === "literal") {
    return typeof выражение.value === "number" && !Number.isNaN(выражение.value) && выражение.value >= 0
  }
  if (снизу.some((терм) => одинаковы(терм, выражение))) return true
  if (выражение.kind === "binary" && выражение.op === "add") {
    return днуЗаново(выражение.left, снизу, неположительные, тумблеры)
      && днуЗаново(выражение.right, снизу, неположительные, тумблеры)
  }
  /* Заказанное вычитание: `а минус б` неотрицательно при `а ≥ 0` и `б ≤ 0`. В
     IEEE-754 это ИСТИННО (точная разность при таких посылках не меньше нуля,
     округление к ближайшему знака не меняет, а NaN появиться негде: `а ≥ 0`
     исключает NaN и −∞ у `а`, `б ≤ 0` — NaN и +∞ у `б`). Правила всё равно нет,
     и замер 3 показывает, почему. */
  if (тумблеры.вычитание && выражение.kind === "binary" && выражение.op === "sub") {
    const вычитаемое = выражение.right
    const неположительно = (вычитаемое.kind === "literal"
      && typeof вычитаемое.value === "number"
      && !Number.isNaN(вычитаемое.value)
      && вычитаемое.value <= 0)
      || неположительные.some((терм) => одинаковы(терм, вычитаемое))
    if (днуЗаново(выражение.left, снизу, неположительные, тумблеры) && неположительно) return true
  }
  if (выражение.kind === "if") {
    const положить = (факты) => {
      const свои = снизу.slice()
      const нули = неположительные.slice()
      for (const факт of факты) {
        if (факт.вид === "снизу") свои.push(факт.терм)
        else if (факт.граница <= 0) нули.push(факт.терм)
      }
      return [свои, нули]
    }
    const [снизуТо, нуляТо] = положить(фактыУсловияЗаново(выражение.cond))
    const [снизуИначе, нуляИначе] = положить(
      тумблеры.иначеТоже ? фактыУсловияЗаново(отрицатьУсловие(выражение.cond) ?? {}) : [],
    )
    return днуЗаново(выражение.then, снизуТо, нуляТо, тумблеры)
      && днуЗаново(выражение.else, снизуИначе, нуляИначе, тумблеры)
  }
  return false
}

const ЦЕЛЬ_ДНА_ЗАМЕРА = {
  kind: "binary",
  op: "gte",
  left: { kind: "var", name: "результат" },
  right: { kind: "literal", value: 0 },
}

/** Тот же вопрос к переписанному правилу: цель — тело функции, факты — из подписи. */
function берётЛиЗаново(функция, определения, тумблеры) {
  const объявления = (функция.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
  const снизу = известноеПоТипу(объявления)
  const цель = нормализовать(подставить(ЦЕЛЬ_ДНА_ЗАМЕРА, { результат: функция.body }), определения)
  if (!(цель?.kind === "binary" && цель.op === "gte" && нольУзла(цель.right))) return false
  return днуЗаново(цель.left, снизу, [], тумблеры)
}

