/* ────────────── та же цель, но у посылки индукции ────────────── */

const БАЗА_БЕЗ_ПРИМЕРА = `модуль «База индукции»

тип «Сравнение»
  вариант «Меньше»
  вариант «Больше»
  вариант «Равно»

тотальная функция «Печать сравнения»
  принимает знак: «Сравнение»
  возвращает строка
  для всех знак обеспечивает «печать открыта оградой» результат начинается с "|"
  пример «меньше»
    дано знак равно вариант «Меньше»
    ожидается "|меньше"
  разбор знак
    случай вариант «Меньше»
      то "|меньше"
    случай вариант «Больше»
      то "|больше"
    случай вариант «Равно»
      то "|равно"

теорема «печать открыта оградой»
  дано знак: «Сравнение»
  утверждаем результат начинается с "|"
  индукция по знак
    случай вариант «Меньше»
      то по примеру «меньше»
  следовательно доказано
`

test("база индукции закрывается вычислением: один пример на три варианта, а не три", async () => {
  /* До четвёртого хода закрыть базу вида «печать начинается с ограды» было
     НЕЧЕМ, кроме примера на КАЖДЫЙ вариант, а примеров у функции корпуса может
     не быть ни одного: их дописывание и составляло половину объёма файлов в
     `flang/proof/examples/`. Теперь пример нужен ровно там, где автор его
     написал, а остальные посылки ядро закрывает само — и говорит, чем. */
  const { первый, внешнее } = await разобрать(БАЗА_БЕЗ_ПРИМЕРА)
  assert.equal(первый.verdict, СИЛА.proved, JSON.stringify(внешнее.diagnostics))
  assert.equal(первый.cases.length, 3)
  assert.equal(первый.cases.filter((с) => с.by === "term").length, 1, "случай автора один — тот, где стоит пример")
  const ядром = первый.cases.filter((с) => с.by === "reduction")
  assert.equal(ядром.length, 2, "две посылки обязано было закрыть само ядро")
  for (const случай of ядром) assert.equal(случай.rule, ВЫЧИСЛЕНИЕМ)
  assert.equal(первый.steps, 1, "шагов ровно столько, сколько написал автор: закрытое ядром терма не имеет")
})

test("ИЗЪЯТИЕ: у посылки со свободным именем вычисление не спрашивают", async () => {
  /* Граница хода у посылки та же, что у постусловия, и стоит она на том же
     месте: свободное имя в заключении — и значений столько же, сколько
     подстановок. Изымается ЗАМКНУТОСТЬ: у варианта появляется поле, а ветвь
     начинает возвращать его, и закрыть такую посылку вычислением нельзя —
     утверждение о ней ложно на первой же строке без ограды. */
  const сИменем = БАЗА_БЕЗ_ПРИМЕРА
    .replace("  вариант «Больше»", "  вариант «Больше» содержит текст: строка")
    .replace("    случай вариант «Больше»\n      то \"|больше\"", "    случай вариант «Больше» с текст как т\n      то т")
  assert.notEqual(сИменем, БАЗА_БЕЗ_ПРИМЕРА, "правка не применилась — тест ничего не проверяет")
  const { первый } = await разобрать(сИменем)
  assert.equal(первый?.verdict, СИЛА.refused, "посылка со свободным именем закрыта вычислением одного значения")
  assert.ok(
    первый.refusals.some((о) => /в цели свободны «т»/u.test(о.message)),
    JSON.stringify(первый.refusals),
  )
})
