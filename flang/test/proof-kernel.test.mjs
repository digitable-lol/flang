/*
 * Что здесь стережётся, и почему это самый дорогой заказ ядра.
 *
 * Свёртка — скрытая рекурсия по списку, и правила у неё не было вовсе: терм
 * непрозрачен, а принцип индукции читает заключение посылки с ВЕТВЕЙ `разбор`,
 * которых у тела-свёртки ноль. Половина `lists.flang` написана свёрткой, и
 * оттуда же восемь сеточных утверждений заказа.
 *
 * Правило выведено, а не постулировано: у свёртки есть НАЧАЛО и ШАГ, то есть
 * ровно две посылки индукции по списку, и доказательство целиком записано в
 * шапке `flang/proof/reduce.mjs`. Способов получить из него ложь три, и у
 * каждого ниже стоит своя проверка с контрпримером:
 *
 *   1. шаг, прибавляющий ЭЛЕМЕНТ (об элементе не известно ничего);
 *   2. отрицательное НАЧАЛО (на пустом списке результат есть само начало);
 *   3. факт о внешнем имени, которое свёртка ПЕРЕСВЯЗАЛА.
 */

const СВЁРТКОЙ = `модуль «Свёртка»

тотальная функция «Считать шаги»
  принимает элементы: список числа
  возвращает число
  обеспечивает «счёт шагов неотрицателен» результат не меньше 0
  пример «Три»
    дано элементы равно [1, 2, 3]
    ожидается 3
  свёртка элементы начиная с 0 как акк и эл → акк плюс 1
`

/* ПОДДЕЛКА 1: шаг прибавляет ЭЛЕМЕНТ. Утверждение ложно на списке из одного
   отрицательного числа, а пример автора остаётся верным. */
const ПОДДЕЛКА_ЭЛЕМЕНТ = СВЁРТКОЙ
  .replace("акк плюс 1", "акк плюс эл")
  .replace("ожидается 3", "ожидается 6")

/* ПОДДЕЛКА 2: начало отрицательно. Шаг тот же самый и знак сохраняет, но на
   ПУСТОМ списке результат есть само начало, то есть −1. */
const ПОДДЕЛКА_НАЧАЛО = СВЁРТКОЙ
  .replace("начиная с 0", "начиная с -1")
  .replace("ожидается 3", "ожидается 2")

test("свёртка доказана: неотрицательное начало и шаг, сохраняющий знак", async () => {
  const { первый, внешнее, ядро } = await разобрать(СВЁРТКОЙ)
  assert.deepEqual(внешнее.diagnostics, [], JSON.stringify(внешнее.diagnostics))
  assert.equal(ядро.checked.length, 1, "утверждение без теоремы дошло до ядра")
  assert.equal(первый.verdict, СИЛА.proved, JSON.stringify(первый))
  assert.equal(первый.rule, "неотрицательность по построению")
  assert.deepEqual(АКСИОМЫ, [], "у свёртки появилась индукция, а аксиом у ядра по-прежнему ноль")
})

