test("правило потолка истинно в IEEE-754, а не только в математике", () => {
  /* Близнец проверки правила 1, и делает он то же самое: перебирает враждебную
     выборку и смотрит, вправе ли правило так считать. Правило говорит: из
     «а не больше П» и «б не меньше 0» следует «а минус б не больше П» при
     КОНЕЧНОМ П. Ровно рядом стоит утверждение того же вида, которое ЛОЖНО:
     «а плюс б не больше П», и оно тоже проверяется — иначе список случаев
     выглядел бы закрытым по лени, а не по доказательству. */
  const выборка = [
    0, -0, 1, -1, 0.5, -0.5,
    ТОЧНАЯ_СЕТКА.верх, ТОЧНАЯ_СЕТКА.низ, ТОЧНАЯ_СЕТКА.верх - 1,
    Number.MAX_VALUE, -Number.MAX_VALUE, Number.MIN_VALUE, -Number.MIN_VALUE,
    Number.EPSILON, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY, Number.NaN,
  ]
  const границы = [ТОЧНАЯ_СЕТКА.верх, 0, 1, Number.MAX_VALUE]
  let посылок = 0
  const нарушения = []
  const ложь = []
  for (const П of границы) {
    for (const а of выборка) {
      for (const б of выборка) {
        /* Посылки правила — ИМЕННО сравнения языка. На NaN они ложны, и правило
           о нём ничего не утверждает; это не оговорка, а то, почему NaN не
           ломает вывод. */
        if (!(а <= П) || !(б >= 0)) continue
        посылок += 1
        if (!(а - б <= П)) нарушения.push(`${а} минус ${б} = ${а - б} при границе ${П}`)
        /* Выбор из двух ограниченных — тоже часть правила, и для него нужна
           вторая посылка про `б`, а не про её знак. */
        if (б <= П && !((а <= б ? а : б) <= П)) нарушения.push(`выбор из ${а} и ${б} при границе ${П}`)
        /* А вот СЛОЖЕНИЕ — то, чего в правиле нет; собираем свидетельства, что
           его отсутствие не перестраховка. */
        if (!(а + б <= П)) ложь.push(`${а} плюс ${б} при границе ${П}`)
      }
    }
  }
  assert.deepEqual(нарушения, [], "правило потолка нарушено — из ядра его надо изымать")
  assert.ok(посылок >= 100, `посылок в выборке всего ${посылок}`)
  assert.ok(ложь.length > 0, "«сумма ограниченных ограничена» не нашлось ложным — выборка бессильна")
  assert.equal(ТОЧНАЯ_СЕТКА.верх + ТОЧНАЯ_СЕТКА.верх <= ТОЧНАЯ_СЕТКА.верх, false, "и главный контрпример — на самом потолке")
  /* И граница обязана быть конечной: с `+∞` посылка не исключает `∞` у
     уменьшаемого, и правило ломается на NaN. */
  assert.equal(
    Number.POSITIVE_INFINITY - Number.POSITIVE_INFINITY <= Number.POSITIVE_INFINITY,
    false,
    "с бесконечной границей правило разности ложно",
  )
})

