/* ── Настоящие функции корпуса: доказано о них, а не о похожих ───────────── */

/**
 * Три утверждения о функциях, которые в дереве стояли задолго до индукции.
 *
 * ── Почему доказательства лежат в `flang/proof/examples/`, а не у функций ───
 * У восьми слов слоя доказательства НЕТ ПРОДУКЦИИ в самоприменённом парсере
 * (`flang/self/parser.flang`), а `flang/stdlib`, `flang/core`,
 * `flang/examples/leetcode`, `flang/examples/measure` и `flang/self` входят в
 * корпус побайтовой неподвижной точки САМОПРИМЕНЕНИЯ целиком
 * (`flang/test/self-parser.test.mjs`). Напиши `обеспечивает` в
 * `flang/stdlib/numtree.flang` — и парсер на flang перестанет давать тот же AST,
 * что эталон. Правило записано в дереве прямым текстом и не мною: «Пока слова
 * стоят в этом списке, `flang/stdlib/*.flang` не имеет права ими пользоваться».
 *
 * ── Что тогда вообще доказано ───────────────────────────────────────────────
 * Функции перенесены ДОСЛОВНО, и дословность здесь — не обещание в шапке, а
 * проверка ниже: дерево разбора тела в файле доказательства обязано совпасть с
 * деревом разбора тела в файле корпуса. Совпало — значит доказано о той самой
 * функции; разошлось — значит доказано о похожей, и тест краснеет. Без этой
 * проверки «утверждение корпуса» было бы словом, а не фактом.
 */
const ПЕРЕНЕСЕНО = [
  {
    доказательство: "flang/proof/examples/corpus-numtree.flang",
    корпус: "flang/stdlib/numtree.flang",
    функция: "Высота",
    тип: "Дерево чисел",
  },
  {
    доказательство: "flang/proof/examples/corpus-tree.flang",
    корпус: "flang/stdlib/tree.flang",
    функция: "Размер дерева",
    тип: "Дерево",
  },
  {
    доказательство: "flang/proof/examples/corpus-depth.flang",
    корпус: "flang/examples/leetcode/104-maximum-depth-of-binary-tree.flang",
    функция: "Глубина",
    тип: "Дерево",
  },
]

test("доказано о НАСТОЯЩИХ функциях корпуса: тела совпадают деревом разбора", async () => {
  for (const запись of ПЕРЕНЕСЕНО) {
    const свой = await loadProgram(join(корень, запись.доказательство))
    const чужой = await loadProgram(join(корень, запись.корпус))
    const здесь = свой.functions.find((ф) => ф.name === запись.функция)
    const там = чужой.functions.find((ф) => ф.name === запись.функция)
    assert.ok(здесь !== undefined, `${запись.доказательство}: нет «${запись.функция}»`)
    assert.ok(там !== undefined, `${запись.корпус}: нет «${запись.функция}»`)

    /* Тело — то, о чём утверждение. Сличается деревом разбора, а не текстом:
       `span` у двух файлов разный по определению, и требовать совпадения строк
       было бы требованием невозможного. */
    assert.ok(
      одинаковы(здесь.body, там.body),
      `тело «${запись.функция}» разошлось с ${запись.корпус} — доказано о похожей функции, а не о той же`,
    )
    assert.ok(одинаковы(здесь.params, там.params), `подпись «${запись.функция}» разошлась с корпусом`)

    /* И объявление типа: принцип индукции читается с НЕГО, значит расхождение
       здесь означало бы, что доказан другой принцип. */
    const типЗдесь = свой.types.find((т) => т.name === запись.тип)
    const типТам = чужой.types.find((т) => т.name === запись.тип)
    assert.ok(одинаковы(типЗдесь, типТам), `объявление «${запись.тип}» разошлось с ${запись.корпус}`)
  }
})

