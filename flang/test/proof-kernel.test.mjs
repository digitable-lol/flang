test("факт о внешнем имени НЕ переживает пересвязки свёрткой — вот контрпример", () => {
  /* Вторая половина инварианта «правило не спускается под связыватель», и
     держится она уже не запретом, а вычёркиванием. Проверяется тремя случаями
     сразу, и средний из них — та самая принятая ложь, ради которой всё это. */
  const нат = { kind: "named", name: "нат" }
  const известные = известноеПоТипу([{ name: "н", type: нат }])
  const свёртка = (поля) => ({
    kind: "fold",
    over: { kind: "var", name: "с" },
    init: { kind: "literal", value: 0 },
    acc: "акк",
    item: "эл",
    ...поля,
  })

  /* 1. ВНЕШНЕЕ ИМЯ, КОТОРОГО СВЁРТКА НЕ ТРОГАЛА, — факт остаётся фактом. */
  assert.equal(
    неотрицательно(свёртка({ body: { kind: "binary", op: "add", left: { kind: "var", name: "акк" }, right: { kind: "var", name: "н" } } }), известные),
    true,
    "факт о свободном имени пропал внутри свёртки — правило стало слабее, чем доказано",
  )

  /* 2. ТО ЖЕ ИМЯ, СВЯЗАННОЕ ЭЛЕМЕНТОМ. Тело возвращает последний элемент
     списка, и знак его неизвестен: `свёртка [−1] начиная с 0 как акк и н → н`
     даёт −1. Прими ядро этот случай — оно доказало бы ложь. */
  assert.equal(
    неотрицательно(свёртка({ item: "н", body: { kind: "var", name: "н" } }), известные),
    false,
    "факт о параметре лёг на элемент списка — это принятая ложь",
  )

  /* 3. ТО ЖЕ ИМЯ, СВЯЗАННОЕ НАКОПИТЕЛЕМ, при отрицательном начале. Знак
     накопителя обязан приезжать из НАЧАЛА, а не из объявления одноимённого
     параметра. */
  assert.equal(
    неотрицательно(свёртка({ acc: "н", init: { kind: "literal", value: -1 }, body: { kind: "var", name: "н" } }), известные),
    false,
    "факт о параметре закрыл накопитель, начало которого отрицательно",
  )

  /* 4. ОДНО ИМЯ НА ОБОИХ. Вычислитель связывает элемент ПОСЛЕ накопителя, и
     тело говорит об элементе; разбирать такое ядро не станет — оно откажет. */
  assert.equal(
    неотрицательно(свёртка({ acc: "оба", item: "оба", body: { kind: "var", name: "оба" } }), []),
    false,
    "накопитель и элемент под одним именем — ядро обязано отказать, а не гадать",
  )
})

