test("мера даёт обязательство, и оно приходит закрытым анализом, а не ядром", async () => {
  /* Единственное обязательство, которое закрывает не автор: убывание доказал
     анализ завершаемости обходом графа вызовов до всякого доказательства.
     Ядру здесь делать нечего, и притворяться, будто есть, значило бы поставить
     в цепочку доверия шаг, которого нет. */
  const { об, ядро, внешнее } = await разобрать(
    "модуль «М»\n\nтотальная функция «Вниз»\n  принимает н: число\n  возвращает число\n"
      + "  убывает н\n  если н не больше 0 то 0 иначе «Вниз» от (н минус 1)\n",
  )
  const мера = об.obligations.find((о) => о.kind === "measure")
  assert.ok(мера !== undefined, "обязательство меры не появилось")
  assert.equal(мера.discharge.by, "analysis")
  assert.match(мера.discharge.says, /^доказано объявленной мерой/u)
  /* Число сторожей сверяется с АНАЛИЗОМ, а не с догадкой теста. Здесь анализ
     закрыл функцию более дешёвым носителем — постоянным шагом, — и мест по
     объявленной мере у неё ноль: порядок ветвей «структура → постоянный шаг →
     объявленная мера» значит «дешёвое доказательство побеждает» (`totality.mjs`,
     и то же читает ведомость). Обязательство обязано говорить ровно то, что
     сказал анализ, поэтому число берётся у него. */
  const мест = (внешнее.results.totality?.descents ?? []).filter((з) => з.from === "Вниз").length
  assert.equal(мера.discharge.guardSites, мест, "сторожа посчитаны по анализу, а не по догадке")
  assert.equal(ядро.checked.length, 0, "ядро мер не трогает: их закрыл анализ")
})

