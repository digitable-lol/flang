test("правило умножения истинно в IEEE-754, а не только в математике", () => {
  /* Близнец проверок правил 1 и 3, и делает он то же самое: перебирает
     враждебную выборку и смотрит, вправе ли правило так считать.

     Правило говорит: из «а в [0, конечное]» и «б в [0, конечное]» следует
     «а умножить на б не меньше 0». Проверяется не реализация, а сама посылка. */
  const выборка = [
    0, -0, 1, -1, 0.5, -0.5, 2, ТОЧНАЯ_СЕТКА.верх, -ТОЧНАЯ_СЕТКА.верх,
    Number.MAX_VALUE, -Number.MAX_VALUE, Number.MIN_VALUE, -Number.MIN_VALUE,
    Number.EPSILON, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY, Number.NaN,
  ]
  let посылок = 0
  const нарушения = []
  for (const а of выборка) {
    for (const б of выборка) {
      /* Посылка правила — ИМЕННО те два сравнения, которые ядро умеет вывести:
         дно `не меньше 0` и КОНЕЧНЫЙ потолок. На NaN и на `+∞` она ложна, и
         правило о них ничего не утверждает; это не оговорка, а то, почему они не
         ломают вывод. */
      if (!(а >= 0) || !Number.isFinite(а)) continue
      if (!(б >= 0) || !Number.isFinite(б)) continue
      посылок += 1
      if (!(а * б >= 0)) нарушения.push(`${а} умножить на ${б} = ${а * б}`)
    }
  }
  assert.deepEqual(нарушения, [], "правило умножения нарушено — из ядра его надо изымать")
  assert.ok(посылок >= 60, `посылок в выборке всего ${посылок}`)

  /* И обратная половина: изъятая посылка действительно делает правило ложным.
     Без неё проверка говорила бы «выбранное правило работает», а не «посылка
     выбрана не по лени». */
  assert.equal(0 * Number.POSITIVE_INFINITY >= 0, false, "без КОНЕЧНОГО потолка: 0 × ∞ = NaN")
  assert.equal(-1 * 2 >= 0, false, "без ДНА: (−1) × 2 = −2")
  /* И почему `вОтрезке` не берёт сложения: сумма двух конечных бывает
     бесконечной, а бесконечный сомножитель — это NaN на следующем умножении. */
  assert.equal(Number.isFinite(Number.MAX_VALUE + Number.MAX_VALUE), false, "сумма конечных выпадает из отрезка")
  assert.equal(0 * (Number.MAX_VALUE + Number.MAX_VALUE) >= 0, false, "и тогда произведение — NaN")
})

test("сомножителем годится ОТРЕЗОК, а не одно дно: допущение индукции его не даёт", () => {
  /* Самое тонкое место правила, и оно проверяется у самой функции сведения.
     Допущение индукции `Т не меньше 0` — законный факт, и правило сложения им
     пользуется. Умножению его МАЛО: `Т` вправе быть `+∞`, и `0 умножить на Т`
     даст NaN. Ядро обязано различить два источника дна не по тому, откуда они
     приехали, а по тому, есть ли при них ВТОРАЯ граница. */
  const т = { kind: "var", name: "т" }
  const дно = { kind: "binary", op: "gte", left: т, right: { kind: "literal", value: 0 } }
  const потолок = (гр) => ({ kind: "binary", op: "lte", left: т, right: { kind: "literal", value: гр } })
  const цель = {
    kind: "binary",
    op: "gte",
    left: { kind: "binary", op: "mul", left: { kind: "literal", value: 0 }, right: т },
    right: { kind: "literal", value: 0 },
  }

  assert.equal(свести(цель, [дно]).ok, false, "одно дно принято за посылку умножения — правило стало ложным")
  assert.equal(свести(цель, [дно, потолок(100)]).ok, true, "две границы есть, а правило не сработало")
  assert.equal(свести(цель, [потолок(100)]).ok, false, "один потолок — тоже не посылка")
  /* Потолок, записанный БЕСКОНЕЧНОСТЬЮ, границей не является: он не исключает
     ровно того значения, ради которого посылку и завели. */
  assert.equal(свести(цель, [дно, потолок(Number.POSITIVE_INFINITY)]).ok, false, "«не больше +∞» принято за конечную границу")

  /* И сумма из отрезка выпадает — переполнением. Это не придирка: `(а плюс б)`
     при двух `нат` бывает `+∞` не бывает, а вот при двух `MAX_VALUE` бывает, и
     правило обязано быть закрыто по операции, а не по типу входов. */
  const черезСумму = {
    ...цель,
    left: {
      kind: "binary",
      op: "mul",
      left: { kind: "literal", value: 0 },
      right: { kind: "binary", op: "add", left: т, right: т },
    },
  }
  assert.equal(свести(черезСумму, [дно, потолок(100)]).ok, false, "сумма принята за величину из отрезка")
})

