    const свой = await loadProgram(join(корень, запись.доказательство))
    const чужой = await loadProgram(join(корень, запись.корпус))
    const здесь = свой.functions.find((ф) => ф.name === запись.функция)
    const там = чужой.functions.find((ф) => ф.name === запись.функция)
    assert.ok(здесь !== undefined, `${запись.доказательство}: нет «${запись.функция}»`)
    assert.ok(там !== undefined, `${запись.корпус}: нет «${запись.функция}»`)

