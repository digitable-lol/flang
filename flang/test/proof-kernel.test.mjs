/**
 * Обязательства и ядро: что надо доказать и что доказано.
 *
 * ── Как читать этот файл ────────────────────────────────────────────────────
 * У каждой проверки ядра здесь есть близнец-изъятие: сначала «терм принят»,
 * потом «изымем то, что стережёт эта проверка, — и обязано быть отвергнуто».
 * Проверяльщик, который умеет только принимать, не проверяет ничего, и убедиться
 * в этом можно единственным способом: показать, что он краснеет там, где должен.
 *
 * ── Почему отказы проверяются на фикстурах, а не на файлах дерева ───────────
 * Файл с отвергнутым термом не проходит `flang check`, значит в дереве его быть
 * не может — свод по корпусу требует нуля отвергнутых прямо
 * (`proof.test.mjs`). Поэтому принятые доказательства лежат файлами в
 * `flang/proof/examples/`, а отвергаемые — здесь, шаблонными строками. Это то же
 * разделение, по которому намеренно сломанные модели FTS лежат в фикстурах, а не
 * в корпусе.
 */
