test("«дано» теоремы сверяется по ТИПУ, а не только по имени", async () => {
  /* ДЫРА, КОТОРУЮ ЭТОТ ТЕСТ ДЕРЖИТ ЗАКРЫТОЙ. Сверка переменных теоремы
     останавливалась на имени, и `дано свет: «Несуществующий»` проходило молча:
     `flang check` отвечал `valid: true` о теореме, говорящей про значения типа,
     которого в модуле нет. Ведомость печатала бы про неё «доказано».

     Три программы ниже — одна проверка, разложенная на изъятия, и порознь ни
     одна из них ничего не доказывала бы:
       НЕТ ТИПА     — тип, которого в модуле нет вовсе;
       ЧУЖОЙ ТИП    — тип, который в модуле ЕСТЬ, но параметру не принадлежит.
                      Без этой строки проверка могла бы искать имя типа среди
                      объявлений модуля и всё равно пропускать доказательство не
                      о той функции;
       СВОЙ ТИП     — то же доказательство с ПРАВИЛЬНЫМ типом обязано быть
                      чистым, иначе проверка ловила бы не тип, а наличие `дано`. */
  const программа = (тип) =>
    "модуль «М»\n\nтип «Светофор»\n  вариант «Красный»\n\nтип «Ступень»\n  вариант «Низкая»\n\n"
      + "тотальная функция «Штраф»\n  принимает свет: «Светофор»\n  возвращает число\n"
      + "  для всех свет обеспечивает «штраф неотрицателен» результат не меньше 0\n"
      + "  пример «красный»\n    дано свет равно вариант «Красный»\n    ожидается 500\n"
      + "  разбор свет\n    случай вариант «Красный»\n      то 500\n\n"
      + `теорема «штраф неотрицателен»\n  дано свет: ${тип}\n`
      + "  утверждаем результат не меньше 0\n  индукция по свет\n"
      + "    случай вариант «Красный»\n      то по примеру «красный»\n  следовательно доказано\n"

  const нетТипа = (await разобрать(программа("«Несуществующий»"))).об
  const беда = нетТипа.diagnostics.find((д) => д.code === "FLANG_PROOF_VAR_TYPE")
  assert.ok(беда !== undefined, JSON.stringify(нетТипа.diagnostics))
  assert.match(беда.message, /вводит «свет» как «Несуществующий»/u)
  assert.match(беда.message, /объявлен как «Светофор»/u)

  const чужойТип = (await разобрать(программа("«Ступень»"))).об
  assert.ok(
    чужойТип.diagnostics.some((д) => д.code === "FLANG_PROOF_VAR_TYPE"),
    JSON.stringify(чужойТип.diagnostics),
  )

  const свойТип = (await разобрать(программа("«Светофор»"))).об
  assert.deepEqual(свойТип.diagnostics, [], JSON.stringify(свойТип.diagnostics))
})

