test("список аксиом арифметики пуст, и это утверждение о ядре", () => {
  /* Пуст намеренно: числа flang — IEEE-754, где «х плюс 1 не меньше х» неправда
     при большом |х|. Аксиома, которая иногда ложна, делает ложным всё, что из
     неё выведено. Проверка стоит затем, чтобы аксиому нельзя было добавить
     молча — вместе с ней обязано появиться обоснование и правка этой строки.

     Правила сведения (`flang/proof/reduce.mjs`) аксиомами не являются и этот
     список не наполняют: аксиому принимают без доказательства, а правило ниже
     проверяется на враждебной выборке. Разница проверяется тестом, а не
     обещается словами.

     Точный тип `нат` у языка ПОЯВИЛСЯ, и список всё равно пуст — вопреки тому,
     что здесь когда-то обещалось. `нат` дал не аксиомы, а факты: отрезок
     [0, 2^53−1] у объявленного имени ядро читает там, где автор его написал, и
     обе границы приезжают данными, а не доверием. */
  assert.deepEqual(АКСИОМЫ, [], "точный «нат» дал факты из подписи, а не аксиомы")
})

test("правило неотрицательности истинно в IEEE-754, а не только в математике", () => {
  /* Это то место, где работа могла стать «машинкой, штампующей доказано».
     Правило говорит: из «а не меньше 0» и «б не меньше 0» следует «а плюс б не
     меньше 0». В вещественных числах это очевидно; в числах flang очевидного
     нет ничего, и рядом стоит целый список утверждений того же вида, которые
     ЛОЖНЫ («а умножить на б», «а минус б», «а плюс 1 больше а»).

     Поэтому правило проверяется перебором по враждебной выборке: оба нуля, NaN,
     обе бесконечности, крайние конечные значения и субнормаль. Проверяется не
     реализация правила, а сама посылка — то, что правило вправе так считать. */
  const выборка = [
    0, -0, 1, -1, 0.5, -0.5,
    Number.MAX_VALUE, -Number.MAX_VALUE, Number.MIN_VALUE, -Number.MIN_VALUE,
    Number.EPSILON, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY, Number.NaN,
  ]
  let посылок = 0
  const нарушения = []
  for (const а of выборка) {
    for (const б of выборка) {
      /* Посылка правила — ИМЕННО сравнение языка `не меньше 0`. На NaN оно
         ложно, и правило о нём ничего не утверждает; это не оговорка, а то,
         почему NaN не ломает вывод. */
      if (!(а >= 0) || !(б >= 0)) continue
      посылок += 1
      if (!(а + б >= 0)) нарушения.push(`${а} плюс ${б} = ${а + б}`)
      /* Выбор из двух неотрицательных — тоже часть правила. */
      if (!((а >= 0 ? а : б) >= 0)) нарушения.push(`выбор из ${а} и ${б}`)
    }
  }
  assert.deepEqual(нарушения, [], "правило неотрицательности нарушено — из ядра его надо изымать")
  assert.ok(посылок >= 40, `посылок в выборке всего ${посылок}`)

  /* И обратное: то, чего в правилах НЕТ, действительно ложно. Без этой половины
     проверка говорила бы только «выбранное правило работает», а не «список
     правил закрыт не по лени». */
  assert.equal(0 * Number.POSITIVE_INFINITY >= 0, false, "произведение неотрицательных: 0 × ∞ = NaN")
  assert.equal(Number.MAX_VALUE + 1 > Number.MAX_VALUE, false, "«х плюс 1 больше х» ложно при большом х")
})

