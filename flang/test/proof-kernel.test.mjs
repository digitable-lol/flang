/* ── А ПОЛЕ ЗАПИСИ ФАКТОМ НЕ СТАНОВИТСЯ, и причина измерена, а не выбрана ──── */

/**
 * Отмывание: `целое` втекает в поле, объявленное `нат`, и вытекает оттуда `нат`.
 *
 * Программа обязана быть ВЕРНОЙ на вид: `объект «Ящик»` объявляет `вес: нат`,
 * `«Прямо»` принимает `нат` и обещает неотрицательность, а `«Отмыть»` кладёт в
 * поле `0 минус 1` и отдаёт это в `«Прямо»`. Ни одного нарушения глазами не
 * видно — и типизатор его тоже не видит.
 */
const ОТМЫВАНИЕ = `модуль «Отмывание»

объект «Ящик»
  вес: нат

тотальная функция «Прямо»
  принимает н: нат
  возвращает число
  обеспечивает «прямо неотрицательно» результат не меньше 0
  пример «ноль»
    дано н равно 0
    ожидается 0
  н

тотальная функция «Отмыть»
  принимает ц: число
  возвращает число
  «Прямо» от ((запись «Ящик» с вес равным (0 минус 1)).вес)
`

test("ДЫРА ЗАКРЫТА: поле записи больше не отмывает значение", async () => {
  /* ЧТО ЗДЕСЬ БЫЛО. Эта проверка стояла отрицательной и называлась «ЗАКАЗ: поле
     записи фактом НЕ становится». Она измеряла дыру: `recordType` в
     `flang/src/types.mjs` сверял тип поля через `sameType` — симметричное
     РАВЕНСТВО ФОРМЫ, для которого `нат`, `целое` и `число` суть один и тот же
     IEEE-754 double, — тогда как соседнее место, поле ВАРИАНТА, давно сверялось
     через `годится`. Из-за этого `запись «Ящик» с вес равным (0 минус 1)` при
     `вес: нат` не давало НИ ОДНОЙ диагностики, и поле ОТМЫВАЛО значение: −1
     выходило из записи с типом `нат` и попадало в аргумент, объявленный `нат`,
     про который у ядра факт «не меньше 0» уже есть. То есть дыра позволяла
     ядру доказать ложь — и доказывала: постусловие «Прямо» доказано обо ВСЕХ
     входах и тут же нарушалось на входе, пришедшем через поле.

     ЧТО СТАЛО. Одно слово в `recordType`: `sameType(actual, settled)` →
     `годится(actual, settled)`. Цена измерена, а не угадана: на всём дереве
     (183 файла `.flang` — stdlib, examples, core, self, proof, conc) диагностик
     от этой правки ровно ОДНА, в `flang/self/monoid.flang`, и она по делу —
     `«номер»: нат` принимал `(«сбор».«номер») плюс 1`, а сумма двух `нат`
     натуральным быть не обязана. Починено объявлением поля, а не ядром.

     ЧЕГО ЗДЕСЬ ПО-ПРЕЖНЕМУ НЕТ. Ядро тип поля записи фактом всё ещё не читает —
     но теперь это ВЫБОР, а не запрет: отвечающий за `нат` в поле появился, и
     завести факт можно источником по образцу `известноеПоТипу`. Третья половина
     ниже стережёт, чтобы это не случилось молча. */
  const { внешнее, ядро, первый } = await разобрать(ОТМЫВАНИЕ)

  /* Половина первая: дыры НЕТ. Программа, кладущая `−1` в поле, объявленное
     `нат`, получает диагностику, и диагностика называет и поле, и оба типа. */
  assert.equal(внешнее.diagnostics.length, 1, JSON.stringify(внешнее.diagnostics))
  assert.equal(внешнее.diagnostics[0].code, "FLANG_TYPE")
  assert.match(внешнее.diagnostics[0].message, /поле «вес» записи «Ящик»/u)
  assert.match(внешнее.diagnostics[0].message, /ожидался нат, получен целое/u)

  /* Половина вторая: почему это важно, а не косметика. Постусловие «Прямо»
     доказано ОБЪЯВЛЕННЫМ ТИПОМ аргумента, то есть обо всех входах, — и рантайм
     всё ещё ловит нарушение на том самом входе. Разница в том, что теперь до
     рантайма дело не доходит: ложь отвергается проверкой типов. */
  assert.equal(ядро.checked.length, 1)
  assert.equal(первый.verdict, СИЛА.proved)
  assert.equal(первый.byType, true, "весь факт здесь — объявленный `нат` аргумента")
  const { программа } = await разобрать(ОТМЫВАНИЕ)
  assert.throws(
    () => evaluate(программа, "Отмыть", { ц: 0 }),
    (беда) => беда.code === "FLANG_PROPERTY",
    "рантайм перестал ловить нарушение — значит сломан сторож постусловия, а не поле",
  )

  /* Половина третья: `свести` на обращении к полю по-прежнему МОЛЧИТ. Своего
     случая у поля нет ни в одном из трёх правил. Покраснеет эта строка — значит
     факт завели; заводить его надо источником (`известноеПоТипу` для
     `имя.поле`), а не новым решающим правилом, и вписывать сюда положительную
     проверку, а не снимать эту. */
  const цель = {
    kind: "binary",
    op: "gte",
    left: { kind: "field", target: { kind: "var", name: "я" }, field: "вес" },
    right: { kind: "literal", value: 0 },
  }
  const объявлено = [{ name: "я", type: { kind: "named", name: "Ящик" } }]
  assert.equal(свести(цель, [], объявлено).ok, false, "ядро прочитало тип поля записи фактом")
  assert.match(свести(цель, [], объявлено).why, /неотрицательность по построению не проходит/u)
})

