/**
 * Восьмой ход ядра: ПОСТУСЛОВИЕ ВЫЗВАННОГО как факт на месте вызова.
 *
 * ── Что за ход и зачем ──────────────────────────────────────────────────────
 * Замер до правки (`flang/stdlib`, 94 незакрытых утверждения): у 44 после
 * нормализации остаётся вызов, у 33 — вызов ЧУЖОЙ функции, и у 19 из этих 33 у
 * вызванного постусловие ЕСТЬ. Ядро его не читало ни на одном. Ход читает — и
 * читает НЕ ВСЁ, что написано: список случаев закрыт и назван в шапке
 * `постусловияВызванных` (`flang/src/proofterm.mjs`).
 *
 * ── Три опасности этого хода, и каждая закрыта устройством ──────────────────
 * Каждая опасность здесь стоит ПОДДЕЛКОЙ — программой, которая доказала бы
 * ложь, будь устройство снято. Подделок шесть, и ни одна не зеленеет:
 *
 *   КРУГ (подделки 1 и 2). Прямой — рекурсивный вызов; через два шага —
 *     взаимная рекурсия. Закрыт ПОСТРОЕНИЕМ: фактом становится только то
 *     постусловие, которое ядро уже доказало БЕЗ него, и ход идёт неподвижной
 *     точкой. Своё постусловие в момент доказательства не закрыто, значит его в
 *     списке доказанных нет; постусловие взаимного соседа — тоже.
 *   НЕОПЛАЧЕННОЕ ПРЕДУСЛОВИЕ (подделка 3). Постусловие верно только при
 *     выполненном `требует`. Закрыто ответом `снятьПредусловия`: у вызванного,
 *     где хоть одно место `требует` не снято, факт не берётся вовсе, а само
 *     место отвергается кодом `FLANG_PRECONDITION_CALL`.
 *   НЕ ПО ИМЕНИ, А ПО РЕБРУ (подделка 4). Постусловие берётся у той функции,
 *     которая правда вызвана в узле, а не у одноимённой. Тот же довод, что у
 *     переноса теорем по ребру импорта (`src/link.mjs`).
 *
 * И ещё две подделки на то, ЧТО ход берёт («проверяй, что берёшь»):
 *   ЛОЖНОЕ ПОСТУСЛОВИЕ НА НЕ-ЧИСЛЕ (подделка 5) и ЛОЖНОЕ НА ПУСТОМ ВХОДЕ
 *     (подделка 6). Обе — постусловия, которые АВТОР НАПИСАЛ, а ядро не
 *     доказало; взяв их, ход потащил бы ложь дальше. Обе отвергнуты тем же
 *     устройством, что круг: непроверенного ход не берёт.
 *
 * ── Что здесь НЕ проверяется, и это сказано вслух ───────────────────────────
 * Отказ этого хода МОЛЧАЛИВ по построению: путь «постусловие без теоремы» не
 * отвергает, а не даёт вердикта вовсе (`поОбъявленномуТипу`: «Отказать здесь
 * было бы неправдой»). Поэтому у подделок 1, 2, 4, 5, 6 кода отказа НЕТ и быть
 * не может — их улика другая и она сильнее: у каждой ложь НАЗЫВАЕТСЯ ПРОГОНОМ,
 * кодом `FLANG_PROPERTY` на конкретном входе, и вход этот выписан. Код отказа
 * есть ровно там, где ему место, — у подделки 3 (`FLANG_PRECONDITION_CALL`).
 *
 * Запуск: node --test flang/test/proof-po-vyzovu.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"

import { loadProgramFromSource } from "../bin/flang.mjs"
import { evaluate } from "../src/interpret.mjs"
import { obligations } from "../src/obligations.mjs"
import { checkProofs, КОДЫ, СИЛА } from "../src/proofterm.mjs"

/** Вердикты ядра по программе-исходнику: имя утверждения — вердикт. */
async function вердикты(исходник) {
  const программа = await loadProgramFromSource(исходник, "подделка.flang")
  const { obligations: список } = obligations(программа)
  const итог = checkProofs(программа, список)
  const карта = new Map()
  for (const з of итог.checked) карта.set(`${з.of} ${з.name}`, з)
  return { карта, коды: итог.diagnostics.map((б) => б.code), итог, программа }
}

const вердикт = (карта, функция, имя) => карта.get(`${функция} ${имя}`)?.verdict ?? null

/** Прогон функции — и код отказа, если он был. Улика лжи, а не рассуждение. */
function прогон(программа, имя, аргументы) {
  try {
    return { значение: evaluate(программа, имя, аргументы), code: null }
  } catch (беда) {
    return { значение: undefined, code: беда?.code ?? null, message: беда?.message ?? "" }
  }
}

/* ================================================================== */
/* ПОДДЕЛКА 1 — КРУГ ПРЯМОЙ: рекурсивный вызов                         */
/* ================================================================== */

/* Цель «(«Само себя» от н) равен 1» совпадает ЗНАК В ЗНАК с инстанцией
   собственного постусловия на рекурсивном вызове. Возьми ход его — и правило
   «цель есть допущение» закрыло бы утверждение о функции, которая не возвращает
   ничего: P из P в чистом виде. Функция объявлена ОБЫЧНОЙ нарочно — с
   «тотальная» анализ завершаемости её и не пропустит, а круг ловить обязано
   ядро, а не сосед. */
const КРУГ_ПРЯМОЙ = `модуль «Круг прямой»

функция «Само себя»
  принимает н: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Само себя» от н
`

test("ПОДДЕЛКА 1 (круг прямой): постусловие функции не доказывает само себя", async () => {
  const { карта } = await вердикты(КРУГ_ПРЯМОЙ)
  assert.notEqual(
    вердикт(карта, "Само себя", "единица"),
    СИЛА.proved,
    "рекурсивный вызов отдал ядру собственное постусловие — это P из P",
  )
})

/* ================================================================== */
/* ПОДДЕЛКА 2 — КРУГ ВЗАИМНЫЙ: тот же круг через два шага               */
/* ================================================================== */

const КРУГ_ВЗАИМНЫЙ = `модуль «Круг взаимный»

функция «Первая»
  принимает н: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Вторая» от н

функция «Вторая»
  принимает н: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Первая» от н
`

test("ПОДДЕЛКА 2 (круг взаимный): два шага — тот же круг, и он тоже закрыт", async () => {
  const { карта } = await вердикты(КРУГ_ВЗАИМНЫЙ)
  assert.notEqual(вердикт(карта, "Первая", "единица"), СИЛА.proved, "«Первая» закрыта постусловием «Второй»")
  assert.notEqual(вердикт(карта, "Вторая", "единица"), СИЛА.proved, "«Вторая» закрыта постусловием «Первой»")
})

/* ЧТО ХОД БЕРЁТ, КОГДА КРУГА НЕТ, — тот же вход без цикла. Без этой пары запрет
   нельзя отличить от «ход не работает вовсе»: подделка, отвергнутая заодно с
   правилом, ничего не показывает. */
const БЕЗ_КРУГА = `модуль «Без круга»

тотальная функция «Единица»
  принимает н: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  1

тотальная функция «Через единицу»
  принимает н: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Единица» от н
`

test("ход РАБОТАЕТ, когда круга нет: та же форма без цикла закрывается", async () => {
  const { карта } = await вердикты(БЕЗ_КРУГА)
  assert.equal(вердикт(карта, "Единица", "единица"), СИЛА.proved, "лемма не доказана — сверять нечего")
  assert.equal(
    вердикт(карта, "Через единицу", "единица"),
    СИЛА.proved,
    "запрет бьёт не по кругу, а по ходу вообще",
  )
})

/* ================================================================== */
/* ПОДДЕЛКА 3 — НЕОПЛАЧЕННОЕ «требует»                                 */
/* ================================================================== */

/* «Точно единица» обещает «результат равен 1» ТОЛЬКО при «н равен 1» — на любом
   другом входе она вернёт этот вход, и постусловие ложно. Её собственное
   утверждение ядро ДОКАЗЫВАЕТ: внутри тела предусловие истинно (за него платят
   вызывающие), и правило «цель есть допущение» закрывает цель им. То есть
   устройство «берётся только доказанное» подделку НЕ ловит — ловить её обязано
   именно устройство оплаты, и здесь оно проверяется в одиночку.

   «Через неё» зовёт её на «м: нат», где живёт и ноль, — и не платит. Возьми ход
   постусловие здесь, и ложь про ноль уехала бы к вызывающему под словом
   «доказано». */
const НЕОПЛАТА = `модуль «Неоплата»

тотальная функция «Точно единица»
  принимает н: нат
  возвращает число
  требует «вход единица» н равен 1
  обеспечивает «единица» результат равен 1
  н

тотальная функция «Через неё»
  принимает м: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Точно единица» от м
`

test("ПОДДЕЛКА 3 (неоплаченное «требует»): факт не берётся, и место названо кодом", async () => {
  const { карта, коды, программа } = await вердикты(НЕОПЛАТА)
  assert.equal(
    вердикт(карта, "Точно единица", "единица"),
    СИЛА.proved,
    "лемма не доказана — тогда подделку ловит другое устройство, и это место не проверено",
  )
  assert.ok(
    коды.includes(КОДЫ.precondition),
    `место вызова не отвергнуто: коды ${JSON.stringify(коды)}`,
  )
  assert.notEqual(
    вердикт(карта, "Через неё", "единица"),
    СИЛА.proved,
    "постусловие взято на месте, где «требует» не снято, — это аксиома под другим именем",
  )
  /* УЛИКА: ложь называет прогон, а не рассуждение. */
  const беда = прогон(программа, "Через неё", { м: 0 })
  assert.notEqual(беда.code, null, `на нуле подделка обязана отказать, а не вернуть значение: ${JSON.stringify(беда)}`)
})

/* ОПЛАЧЕННОЕ «требует» — тот же вход, где вызывающий за условие платит. */
const ОПЛАТА = `модуль «Оплата»

тотальная функция «Точно единица»
  принимает н: нат
  возвращает число
  требует «вход единица» н равен 1
  обеспечивает «единица» результат равен 1
  н

тотальная функция «Через неё»
  принимает м: нат
  возвращает число
  требует «и здесь единица» м равен 1
  обеспечивает «единица» результат равен 1
  «Точно единица» от м
`

test("оплаченное «требует»: тот же вызов, за который заплатили, факт даёт", async () => {
  const { карта, коды } = await вердикты(ОПЛАТА)
  assert.ok(!коды.includes(КОДЫ.precondition), `место обязано сниматься: ${JSON.stringify(коды)}`)
  assert.equal(вердикт(карта, "Точно единица", "единица"), СИЛА.proved, "лемма не доказана — сверять нечего")
  assert.equal(
    вердикт(карта, "Через неё", "единица"),
    СИЛА.proved,
    "запрет бьёт по предусловию вообще, а не по НЕОПЛАЧЕННОМУ",
  )
})

/* ================================================================== */
/* ПОДДЕЛКА 4 — ОДНОИМЁННОЕ ПОСТУСЛОВИЕ ЧУЖОЙ ФУНКЦИИ                   */
/* ================================================================== */

/* Два постусловия НАЗВАНЫ ОДИНАКОВО и говорят разное: у «Как было» — что длина
   сохраняется (правда), у «Ничего» — что она неотрицательна (правда, и
   бесполезно). «Через ничего» зовёт «Ничего». Сличи ядро постусловие ПО ИМЕНИ —
   и приедет утверждение ПРО ЧУЖОЕ ТЕЛО, которым ложная цель закроется. */
const ОДНОИМЁННОЕ = `модуль «Одноимённые»

тотальная функция «Как было»
  принимает элементы: список числа
  возвращает список числа
  обеспечивает «мера» (длина результат) равен (длина элементы)
  элементы

тотальная функция «Ничего»
  принимает элементы: список числа
  возвращает список числа
  обеспечивает «мера» (длина результат) не меньше 0
  пустой список

тотальная функция «Через ничего»
  принимает элементы: список числа
  возвращает список числа
  обеспечивает «длина сохраняется» (длина результат) равен (длина элементы)
  «Ничего» от элементы
`

test("ПОДДЕЛКА 4 (не по имени, а по ребру): одноимённое постусловие чужой функции не берётся", async () => {
  const { карта, программа } = await вердикты(ОДНОИМЁННОЕ)
  assert.equal(вердикт(карта, "Как было", "мера"), СИЛА.proved, "лемма-двойник не доказана — сверять нечего")
  assert.notEqual(
    вердикт(карта, "Через ничего", "длина сохраняется"),
    СИЛА.proved,
    "постусловие приехало по ИМЕНИ утверждения, а не по ребру вызова — это доказательство про чужое тело",
  )
  const беда = прогон(программа, "Через ничего", { элементы: [1] })
  assert.equal(
    беда.code,
    "FLANG_PROPERTY",
    `на списке из одного подделка обязана нарушить постусловие: ${JSON.stringify(беда)}`,
  )
})

/* ================================================================== */
/* ПОДДЕЛКА 5 — ПОСТУСЛОВИЕ, ЛОЖНОЕ НА НЕ-ЧИСЛЕ                        */
/* ================================================================== */

/* «0 делить на 0» проходит типизацию без единой диагностики и даёт НЕ ЧИСЛО, а
   «не число не меньше 0» ложно. Постусловие «Ноль на ноль» АВТОР НАПИСАЛ, и оно
   ЛОЖЬ. Возьми ход написанное — и ложь уехала бы к вызывающему целиком. */
const НЕ_ЧИСЛО = `модуль «Не число»

тотальная функция «Ноль на ноль»
  принимает н: число
  возвращает число
  обеспечивает «неотрицательно» результат не меньше 0
  0 делить на 0

тотальная функция «Через него»
  принимает н: число
  возвращает число
  обеспечивает «неотрицательно» результат не меньше 0
  «Ноль на ноль» от н
`

test("ПОДДЕЛКА 5 (цель на НЕ-ЧИСЛЕ): непроверенное постусловие ход не берёт", async () => {
  const { карта, программа } = await вердикты(НЕ_ЧИСЛО)
  assert.notEqual(вердикт(карта, "Ноль на ноль", "неотрицательно"), СИЛА.proved, "ложь доказана у самого вызванного")
  assert.notEqual(
    вердикт(карта, "Через него", "неотрицательно"),
    СИЛА.proved,
    "ход взял постусловие, которого ядро не доказывало, — и потащил ложь дальше",
  )
  const беда = прогон(программа, "Через него", { н: 1 })
  assert.equal(беда.code, "FLANG_PROPERTY", `не число обязано нарушить постусловие: ${JSON.stringify(беда)}`)
})

/* ================================================================== */
/* ПОДДЕЛКА 6 — ПОСТУСЛОВИЕ, ВЕРНОЕ ЛИШЬ НА НЕПУСТОМ ВХОДЕ              */
/* ================================================================== */

const НЕПУСТОЙ_ВХОД = `модуль «Непустой вход»

тотальная функция «Длина непуста»
  принимает элементы: список числа
  возвращает число
  обеспечивает «не меньше одного» результат не меньше 1
  длина элементы

тотальная функция «Через длину»
  принимает элементы: список числа
  возвращает число
  обеспечивает «не меньше одного» результат не меньше 1
  «Длина непуста» от элементы
`

test("ПОДДЕЛКА 6 (верно лишь на непустом): постусловие без «требует» ход не берёт", async () => {
  const { карта, программа } = await вердикты(НЕПУСТОЙ_ВХОД)
  assert.notEqual(вердикт(карта, "Длина непуста", "не меньше одного"), СИЛА.proved, "ложь доказана у самого вызванного")
  assert.notEqual(
    вердикт(карта, "Через длину", "не меньше одного"),
    СИЛА.proved,
    "постусловие, верное лишь на непустом входе, уехало к вызывающему без единой посылки",
  )
  const беда = прогон(программа, "Через длину", { элементы: [] })
  assert.equal(беда.code, "FLANG_PROPERTY", `пустой список обязан нарушить постусловие: ${JSON.stringify(беда)}`)
})

/* ================================================================== */
/* ИЗЪЯТИЕ: ход ничего не отбирает                                     */
/* ================================================================== */

/* Ход держит РОВНО те утверждения, которые без факта по вызову не сводятся.
   Цель, закрытая без него, обязана закрываться и с ним — иначе ход не
   прибавляет, а подменяет. */
test("ход НИЧЕГО не отбирает: цель, закрытая без него, закрыта и с ним", async () => {
  const { карта } = await вердикты(`модуль «Без вызова»

тотальная функция «Сумма»
  принимает первое: нат, второе: нат
  возвращает число
  обеспечивает «сумма неотрицательна» результат не меньше 0
  первое плюс второе
`)
  assert.equal(вердикт(карта, "Сумма", "сумма неотрицательна"), СИЛА.proved)
})
