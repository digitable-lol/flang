/* ПОДДЕЛКА 5: шаг свёртки прибавляет ДВА, а цель говорит про длину    */
/* ================================================================== */

const ШАГ_НА_ДВА = `модуль «Подделка шагом на два»

тотальная функция «Удвоить список» от «А»
  принимает элементы: список «А»
  возвращает список «А»
  обеспечивает «длина не меняется» (длина результат) равен (длина элементы)
  пример «два»
    дано элементы равно [1]
    ожидается [1, 1]
  свёртка элементы начиная с пустой список как акк и эл → добавить эл к (добавить эл к акк)
`

test("ПОДДЕЛКА шагом на два: близнец берёт только шаг РОВНО на один", async () => {
  const итог = await сведение(ШАГ_НА_ДВА, "Удвоить список", "длина не меняется")
  assert.equal(итог.ok, false, "правило приняло свёртку, растущую вдвое быстрее списка")
})

/* ================================================================== */
/* ПОДДЕЛКА 6: начало свёртки НЕ совпало с основанием правой стороны    */
/* ================================================================== */

const ЧУЖОЕ_НАЧАЛО = `модуль «Подделка началом»

тотальная функция «Слить не туда» от «А»
  принимает первые: список «А», вторые: список «А»
  возвращает список «А»
  обеспечивает «длина слияния есть длина вторых» (длина результат) равен (длина вторые)
  пример «пусто и пусто»
    дано первые равно пустой список
    дано вторые равно пустой список
    ожидается пустой список
  свёртка вторые начиная с первые как акк и эл → добавить эл к акк
`

test("ПОДДЕЛКА началом: начало свёртки не ноль, а справа его нет — не выведено", async () => {
  const итог = await сведение(ЧУЖОЕ_НАЧАЛО, "Слить не туда", "длина слияния есть длина вторых")
  assert.equal(итог.ok, false, "правило забыло основание правой стороны")
})

/* ================================================================== */
/* ТАВТОЛОГИЯ: закрывается даром — и обязана быть НАЗВАНА, а не сочтена */
/* ================================================================== */

const ТАВТОЛОГИЯ = `модуль «Тавтология»

тотальная функция «Отрицание»
  принимает х: число
  возвращает число
  обеспечивает «результат есть ноль минус х» результат равен (0 минус х)
  пример «пятёрка»
    дано х равно 5
    ожидается -5
  0 минус х
`

test("ТАВТОЛОГИЯ закрывается даром, и это НЕ прирост доказанности", async () => {
  /* Цель пересказывает тело слово в слово. Ядро закроет её сличением, и
     закрытие это верно — но не значит ничего: доказано, что тело равно себе.
     Тест стоит здесь затем, чтобы число таких целей считалось ОТДЕЛЬНО и не
     попадало в «закрыто правилом». */
  const итог = await сведение(ТАВТОЛОГИЯ, "Отрицание", "результат есть ноль минус х")
  assert.equal(итог.ok, true, "тавтология вдруг не закрылась — сличение сломано")
})

/* ================================================================== */
/* ИЗЪЯТИЕ: правило держит ровно то, что закрыло                       */
/* ================================================================== */

const РОВНО_НА_ОДИН = `модуль «Свёртка на один»

тотальная функция «Копия» от «А»
  принимает элементы: список «А»
  возвращает список «А»
  обеспечивает «длина копии равна длине входа» (длина результат) равен (длина элементы)
  пример «два»
    дано элементы равно [1, 2]
    ожидается [1, 2]
  свёртка элементы начиная с пустой список как акк и эл → добавить эл к акк

тотальная функция «В начало» от «А»
  принимает первый: «А», элементы: список «А»
  возвращает список «А»
  обеспечивает «удлиняет ровно на один» (длина результат) равен ((длина элементы) плюс 1)
  пример «в пустой»
    дано первый равно 1
    дано элементы равно пустой список
    ожидается [1]
  приписать первый к элементы
`

test("ЧЕСТНОЕ закрывается: свёртка ровно на один и перестановка соседей", async () => {
  const свёрткой = await сведение(РОВНО_НА_ОДИН, "Копия", "длина копии равна длине входа")
  assert.equal(свёрткой.ok, true, `свёртка ровно на один не сошлась: ${свёрткой.why}`)
  const соседями = await сведение(РОВНО_НА_ОДИН, "В начало", "удлиняет ровно на один")
  assert.equal(соседями.ok, true, `перестановка соседей не сошлась: ${соседями.why}`)
})
