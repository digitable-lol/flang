/**
 * Зубы двух правил тождества: перестановки соседей и «свёртка растёт ровно на один».
 *
 * ── Почему подделки лежат ЗДЕСЬ, а не в общем сторожа состоятельности ───────
 * Сторож `proof-soundness.test.mjs` спрашивает про КЛАСС: «сказала ведомость
 * „обо ВСЕХ входах“ — значит сетка контрпримера не находит». Он поймает ложь,
 * но только ту, которую сетка опровергнет прогоном. Половина ловушек этих двух
 * правил прогоном не опровергается вовсе: `(а плюс б) плюс в` против
 * `а плюс (б плюс в)` расходится на 0.1/0.1/0.6, а не на сетке из целых, и
 * `0 плюс х` против `х` расходится ровно на одном значении — на минус нуле.
 * Поэтому здесь подделки названы поимённо и проверяются у САМОГО правила.
 *
 * Запуск: node --test flang/test/proof-ravno.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"

import { loadProgramFromSource } from "../bin/flang.mjs"
import { подставить } from "../proof/initial.mjs"
import { ПРЕДЕЛ_ВЕТВЛЕНИЯ, свести } from "../proof/reduce.mjs"
import { obligations } from "../src/obligations.mjs"
import { вычислениемЗамкнутой } from "../src/proofterm.mjs"

/**
 * Тем же ходом, каким ядро снимает постусловие без теоремы: одна подстановка
 * тела на место `результат` и один `свести`. Второго пути сюда нет нарочно —
 * иначе тест проверял бы не то, чем закрывается цель в работе.
 */
async function сведение(исходник, имяФункции, имяУтверждения) {
  const программа = await loadProgramFromSource(исходник, "подделка.flang")
  const функции = new Map((программа.functions ?? []).map((ф) => [ф.name, ф]))
  const об = (obligations(программа).obligations ?? [])
    .find((о) => о.kind === "postcondition" && о.of === имяФункции && о.name === имяУтверждения)
  assert.ok(об !== undefined, `обязательства «${имяУтверждения}» у «${имяФункции}» нет`)
  const цель = подставить(об.goal, { [об.bind ?? "результат"]: функции.get(имяФункции)?.body })
  assert.ok(цель !== null, "подстановка захватила имя — подделка не о том")
  return свести(цель, [], об.vars, функции, вычислениемЗамкнутой(программа), ПРЕДЕЛ_ВЕТВЛЕНИЯ)
}

/* ================================================================== */
/* ПОДДЕЛКА 1: равенство с ЧУЖИМ ИМЕНЕМ                                */
/* ================================================================== */

const ЧУЖОЕ_ИМЯ = `модуль «Подделка чужим именем»

тотальная функция «Копия» от «А»
  принимает элементы: список «А», другие: список «А»
  возвращает список «А»
  обеспечивает «длина копии равна длине ЧУЖОГО списка» (длина результат) равен (длина другие)
  пример «пусто»
    дано элементы равно пустой список
    дано другие равно пустой список
    ожидается пустой список
  свёртка элементы начиная с пустой список как акк и эл → добавить эл к акк
`

test("ПОДДЕЛКА чужим именем: свёртка идёт по «элементы», а справа длина «другие» — не выведено", async () => {
  const итог = await сведение(ЧУЖОЕ_ИМЯ, "Копия", "длина копии равна длине ЧУЖОГО списка")
  assert.equal(итог.ok, false, "правило взяло свёртку по ДРУГОМУ списку — счёт витков не связан с границей")
})

/* ================================================================== */
/* ПОДДЕЛКА 2: равенство, верное только на НЕПУСТОМ входе               */
/* ================================================================== */

const ТОЛЬКО_НЕПУСТОЙ = `модуль «Подделка непустотой»

тотальная функция «Голова списком» от «А»
  принимает элементы: список «А»
  возвращает список «А»
  обеспечивает «в результате ровно один элемент» (длина результат) равен 1
  пример «непустой»
    дано элементы равно [1, 2]
    ожидается [1]
  разбор элементы
    случай пусто
      то пустой список
    случай голова и хвост
      то [голова]
`

test("ПОДДЕЛКА непустотой: на пустом входе длина 0, а не 1 — не выведено", async () => {
  const итог = await сведение(ТОЛЬКО_НЕПУСТОЙ, "Голова списком", "в результате ровно один элемент")
  assert.equal(итог.ok, false, "правило взяло утверждение, ложное на пустом списке")
})

/* ================================================================== */
/* ПОДДЕЛКА 3: равенство, ломающееся на МИНУС НУЛЕ                     */
/* ================================================================== */

const МИНУС_НОЛЬ = `модуль «Подделка минус нулём»

тотальная функция «Сам себе» 
  принимает х: число
  возвращает число
  обеспечивает «прибавление нуля ничего не меняет» результат равен (0 плюс х)
  пример «пятёрка»
    дано х равно 5
    ожидается 5
  х
`

test("ПОДДЕЛКА минус нулём: «0 плюс х» против «х» — расходятся ровно на минус нуле", async () => {
  /* Улика числом, а не опасением: `равен` языка есть `Object.is`. */
  assert.equal(Object.is(0 + -0, -0), false, "минус ноль перестал быть ловушкой — подделка не о том")
  const итог = await сведение(МИНУС_НОЛЬ, "Сам себе", "прибавление нуля ничего не меняет")
  assert.equal(итог.ok, false, "правило съело нейтральность нуля — она ложна на минус нуле")
})

/* ================================================================== */
/* ПОДДЕЛКА 4: АССОЦИАТИВНОСТЬ под видом перестановки соседей          */
/* ================================================================== */

const АССОЦИАТИВНОСТЬ = `модуль «Подделка ассоциативностью»

тотальная функция «Сумма трёх»
  принимает а: число, б: число, третье: число
  возвращает число
  обеспечивает «скобки не важны» результат равен ((а плюс б) плюс третье)
  пример «единицы»
    дано а равно 1
    дано б равно 1
    дано третье равно 1
    ожидается 3
  а плюс (б плюс третье)
`

test("ПОДДЕЛКА ассоциативностью: переставлять ЧЕРЕЗ СКОБКИ нельзя — в IEEE-754 это ложь", async () => {
  assert.notEqual((0.1 + 0.1) + 0.6, 0.1 + (0.1 + 0.6), "ассоциативность держится — подделка не о том")
  const итог = await сведение(АССОЦИАТИВНОСТЬ, "Сумма трёх", "скобки не важны")
  assert.equal(итог.ok, false, "перестановка соседей выродилась в ассоциативность")
})

