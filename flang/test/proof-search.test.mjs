/**
 * Три настоящих доказательства корпуса, написанных рукой: перечисление (база из
 * трёх случаев, шага нет), объявленная сумма (база и шаг) и ВСТРОЕННЫЙ список.
 * Взяты разные не для полноты: у перечисления все случаи закрываются примером, у
 * дерева — примером и допущением, а у списка образцы пишутся третьей формой
 * (`пусто`, `голова и хвост`), и печать находки обязана уметь все три.
 */
const НАСТОЯЩИЕ = [
  { путь: "flang/proof/examples/traffic-light.flang", имя: "штраф неотрицателен", тип: "Светофор" },
  { путь: "flang/proof/examples/corpus-numtree.flang", имя: "высота неотрицательна", тип: "Дерево чисел" },
  { путь: "flang/proof/examples/corpus-lists.flang", имя: "длина неотрицательна", тип: "список" },
  { путь: "flang/proof/examples/stack.flang", имя: "копия равна оригиналу", тип: "Стопка" },
]

for (const запись of НАСТОЯЩИЕ) {
  test(`${запись.путь}: снимите теорему — оракул находит её заново, и её принимает ведомость`, async () => {
    const { без, программа, обязательство } = await безДоказательства(запись.путь, запись.имя)

    const найдено = искатьДоказательство(обязательство, программа, без)
    assert.equal(найдено.ok, true, `оракул не нашёл: ${найдено.why}`)
    assert.ok(найдено.шагов > 0, "кандидатов перебрано ноль — значит перебора не было")

    /* Найденное написано СЛОВАМИ ЯЗЫКА, а не выдано деревом: восемь слов слоя
       доказательства стоят в тексте, и человек вправе вписать его в файл. */
    assert.match(найдено.текст, /^теорема «/u)
    assert.match(найдено.текст, /\n {2}утверждаем /u)
    assert.match(найдено.текст, /\n {2}индукция по /u)
    assert.match(найдено.текст, /\n {2}следовательно доказано\n$/u)

    /* И принимает его не оракул. Обычный путь целиком: разборщик, обязательства,
       ядро, ведомость. */
    const { итог, диагностики, заявка } = await ведомостьС(без, найдено.текст, запись.путь, запись.имя)
    assert.deepEqual(диагностики, [], "найденное доказательство не прошло обычных проверок")
    assert.equal(заявка?.verdict, "proved-induction", `ведомость сказала «${заявка?.says}»`)
    assert.match(заявка.says, new RegExp(`доказано индукцией по «${запись.тип}»`, "u"))
    assert.equal(итог.totals?.claims?.refused ?? 0, 0)
  })
}

test("найденное, вписанное в файл, даёт ту же ведомость, что написанное рукой", async () => {
  /* «ПОПАДАЕТ В ДЕРЕВО КАК ОБЫЧНОЕ ДОКАЗАТЕЛЬСТВО» — здесь это измеряется, а не
     обещается. Берётся настоящий файл корпуса, у него снимается написанная рукой
     теорема, оракул пишет свою, и ведомость ОБЕИХ версий сравнивается целиком:
     вердикт, слова, число шагов, свод по файлу. Разойдись хоть что-нибудь — и
     «найдено» означало бы доказательство другой силы, чем написанное человеком.

     Это же и есть проверка пути `--write`: инструмент дописывает в файл ровно ту
     строку, которая здесь сравнивается. */
  const запись = НАСТОЯЩИЕ[1]
  const исходник = текст(запись.путь)
  const рукой = await loadProgramFromSource(исходник, запись.путь)
  const рукойВнешнее = await externalChecks(рукой)
  const рукойИтог = proofLedger(рукой, рукойВнешнее.results)
  const рукойЗаявка = (рукойИтог.claims ?? []).find((к) => к.name === запись.имя)

  const { без, программа, обязательство } = await безДоказательства(запись.путь, запись.имя)
  const найдено = искатьДоказательство(обязательство, программа, без)
  assert.equal(найдено.ok, true, `оракул не нашёл: ${найдено.why}`)

  const { заявка, диагностики } = await ведомостьС(без, найдено.текст, запись.путь, запись.имя)
  assert.deepEqual(диагностики, [])
  assert.equal(заявка.verdict, рукойЗаявка.verdict)
  assert.equal(заявка.says, рукойЗаявка.says, "ведомость о найденном и о написанном рукой обязана говорить одно и то же")
  assert.equal(заявка.steps, рукойЗаявка.steps, "шагов в найденном терме столько же, сколько в написанном рукой")
})

test("доказательство БЕЗ индукции: у функции без параметров оракул находит цепочку из одного шага", async () => {
  /* Второй скелет оракула. Без этой проверки ветка `скелетБезИндукции` не
     исполнялась бы ни разу — то есть её бы не было.

     ЗДЕСЬ СТОЯЛО УСЛОВИЕ «программа, у которой тело НЕ сводится», и оно ломалось
     дважды по одной причине — ядро росло. Сначала `work/kernel-mul-field` взяло
     умножение, и `2 умножить на 3` стало сводиться; вместо него было взято
     вычитание, которого в правилах нет и не будет. Теперь у `свести` появился
     четвёртый ход — ЗАМКНУТАЯ ЦЕЛЬ ВЫЧИСЛЯЕТСЯ, — и такой программы не
     существует ВОВСЕ: у функции без параметров цель замкнута всегда, значит
     ядро закрывает её само, каким бы ни было тело.

     Поэтому условие снято, а не подновлено: скелет проверяется ПРЯМО — оракул
     зовётся руками, и вопрос к нему тот же самый («находит ли он цепочку из
     одного шага и принимает ли ядро найденное»), только он больше не опирается
     на молчание ядра. Молчания больше нет, и это не поломка проверки, а то,
     ради чего четвёртый ход и сделан. */
  const путь = "flang/proof/examples/проба-без-индукции.flang"
  const исходник = [
    "тотальная функция «Шестёрка»",
    "  возвращает число",
    "  обеспечивает «шестёрка неотрицательна» результат не меньше 0",
    "  пример «единственное значение»",
    "    ожидается 6",
    "  8 минус 2",
    "",
  ].join("\n")

  const программа = await loadProgramFromSource(исходник, путь)
  const внешнее = await externalChecks(программа)
  assert.deepEqual(внешнее.diagnostics.filter((б) => б?.severity !== "warning"), [])
  const обязательство = (внешнее.results?.obligations?.obligations ?? [])
    .find((о) => о.name === "шестёрка неотрицательна")
  assert.equal(
    обязательство.discharge?.rule,
    ВЫЧИСЛЕНИЕМ,
    "цель у функции без параметров замкнута, и ядро обязано закрывать её САМО — четвёртым ходом",
  )

  const найдено = искатьДоказательство(обязательство, программа, исходник)
  assert.equal(найдено.ok, true, `оракул не нашёл: ${найдено.why}`)
  assert.match(найдено.текст, /^теорема «шестёрка неотрицательна»\n/u)
  assert.match(найдено.текст, /\n {2}по примеру «единственное значение»\n/u)
  assert.ok(!/индукция по/u.test(найдено.текст), "индукции тут быть не должно: индуцировать не по чему")

  const { заявка, диагностики } = await ведомостьС(исходник, найдено.текст, путь, "шестёрка неотрицательна")
  assert.deepEqual(диагностики, [])
  assert.equal(заявка?.verdict, "proved", `ведомость сказала «${заявка?.says}»`)
  assert.match(заявка.says, /доказано: терм принят ядром, 1 шаг/u)
})

