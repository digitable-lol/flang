test("поиск не обязателен: ни ядро, ни ведомость, ни проверка его не зовут", () => {
  /* «Если он ничего не нашёл, программа обязана вести себя ровно как сегодня» —
     это свойство держится не обещанием, а тем, что зовущих нет вовсе. Смотрится
     чтением исходников: появись `import … search.mjs` в рабочем пути языка —
     проверка покраснеет и потребует объяснить, зачем поиск попал в контур. */
  const разрешено = new Set([
    "flang/proof/search.mjs",
    "flang/scripts/proof-search.mjs",
    "flang/test/proof-search.test.mjs",
    /* Замер охвата по заданной цели (`work/lemmy`) — тот же род инструмента, что
       оракул: он отвечает на вопрос «а какие утверждения вообще стоит писать»,
       и зовёт поиск ровно затем же, зачем его зовёт `proof-search.mjs`. В
       рабочий путь языка он не входит: `flang check` его не загружает, и ни
       ядро, ни ведомость о нём не знают. */
    "flang/scripts/claim-scan.mjs",
  ])
  const зовущие = []
  for (const путь of globSync("flang/**/*.mjs", { cwd: корень })) {
    if (разрешено.has(путь)) continue
    if (/(?:proof\/search|proof-search)\.mjs/u.test(текст(путь))) зовущие.push(путь)
  }
  assert.deepEqual(
    зовущие,
    [],
    "поиск попал в рабочий путь языка: ведомость обязана считать доказанным только написанное в файле",
  )
})
