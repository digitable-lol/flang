test("замер: сегодня поиск не находит по корпусу НИ ОДНОГО нового доказательства", async () => {
  /* ЭТО УЛИКА, А НЕ ПОХВАЛА. Число решает, стоит ли работа своей цены, и оно
     снято прогоном ДО всякой правки: из 49 утверждений корпуса не доказано 20, и
     ни одно из них не ждёт ненаписанной цепочки — все двадцать упираются в
     ПРАВИЛА ЯДРА (вид цели, тело-свёртка, обращение к полю), а не в автора.
     Значит поиск сегодня снимает не недоказанность, а ручную работу: он
     ВЫВОДИТ ЗАНОВО все одиннадцать доказательств индукцией, написанных рукой.

     Ноль здесь обязан вырасти вместе с ядром: научится ядро новому виду цели —
     эта проверка покраснеет и потребует вписать находки в корпус. Ровно так же
     стоит заказ в `corpus-claims.test.mjs`.

     ДВАДЦАТЬ ПЕРВОЕ ПРИШЛО ОТ РАБОТЫ НАД ЛЕММАМИ, и оно не «ещё одно
     недоказанное», а запись о недостаче с названным правилом. Это «найденная
     скобка — решённый исход» у «Есть скобка» (`flang/proof/examples/
     corpus-brackets.flang`): обе функции разбирают «итог» образцом
     `случай любое`, ветви с именем «Скобки нет» в теле нет, и заключение
     посылки построить не из чего — притом что у случая нет связанных имён,
     значение в нём одно, и пример о нём отвечает целиком. Поиск его тоже не
     берёт, и правильно делает: закрыло бы этот случай не доказательство, а одно
     чтение — ветвь `случай любое` служит ветвью каждому варианту, у которого
     своей нет. Пока чтения нет, утверждение стоит сеткой на всех трёх значениях
     типа. */
  const { ФАЙЛЫ } = await import("../scripts/proof-ledger.mjs")
  let открыто = 0
  const найдено = []
  for (const путь of ФАЙЛЫ) {
    const исходник = текст(путь)
    let программа
    try {
      программа = await loadProgramFromSource(исходник, путь)
    } catch {
      continue
    }
    const свои = new Set(parse(исходник, путь).functions?.map((ф) => ф.name) ?? [])
    const внешнее = await externalChecks(программа)
    if (внешнее.diagnostics.some((б) => б?.severity !== "warning")) continue
    for (const о of внешнее.results?.obligations?.obligations ?? []) {
      if (о.kind !== "postcondition" || !свои.has(о.of)) continue
      if (о.discharge !== null && о.discharge !== undefined) continue
      открыто += 1
      const ответ = искатьДоказательство(о, программа, исходник)
      if (ответ.ok) найдено.push(`${путь} «${о.name}»`)
    }
  }
  /* Число пересчитано на СОБРАННОМ дереве: `work/lemmy` завела шесть новых
     файлов корпуса с утверждениями, и недоказанных стало больше — не потому,
     что ядро ослабло, а потому, что корпус вырос. Ноль ниже при этом не сдвинулся
     ни на единицу, и это и есть ответ замера. */
  /* 27 → 29: сеть в словаре поручений привела в корпус план службы по сокету
     (`plan-network.flang`), и с ним два постусловия, которых ядро не закрывает.
     Ноль ниже опять не сдвинулся: корпус вырос, а поиск не нашёл. */
  assert.equal(открыто, 29, `недоказанных утверждений стало ${открыто} — замер сдвинулся, перепишите объяснение выше`)
  assert.deepEqual(
    найдено,
    [],
    "поиск нашёл новое доказательство: впишите его в корпус и поднимите число здесь —"
      + " именно за этим ноль и стоит исполняемым",
  )
})

