/**
 * ГЛАВНАЯ ПРОВЕРКА ЭТОГО ФАЙЛА.
 *
 * Оракул заставляют соврать подменой ОДНОГО шага: обоснования первого и
 * последнего случая меняются местами. Цепочка от этого остаётся синтаксически
 * безупречной — те же слова, тот же вид, — и ложной становится по существу: в
 * базе стоит `по предположению`, где предполагать не о чем, а в шаге — `по
 * примеру`, которым незамкнутое заключение не закрывается.
 *
 * Ядро обязано отвергнуть. Если бы оно принимало кандидата на слово, вся затея
 * с поиском была бы машинкой, штампующей слово «доказано»: поиск не проверяется
 * никем и проверяться не должен — за это отвечает ядро.
 */
for (const запись of НАСТОЯЩИЕ.filter((з) => з.путь !== "flang/proof/examples/traffic-light.flang")) {
  test(`${запись.путь}: ИЗЪЯТИЕ — ложный кандидат оракула ядро ОТВЕРГАЕТ`, async () => {
    const { без, программа, обязательство, доказаноБез } = await безДоказательства(запись.путь, запись.имя)

    const честно = искатьДоказательство(обязательство, программа, без)
    assert.equal(честно.ok, true, "честной находки нет — портить нечего")

    const ложь = искатьДоказательство(обязательство, программа, без, { лгать: ЛГАТЬ.перестановкой })
    assert.equal(ложь.ok, true, "оракул обязан ВЫДАТЬ кандидата, иначе изъятие проверяет не то")
    assert.notEqual(ложь.текст, честно.текст, "порча не наложилась — проверка ничего не проверяет")

    const { итог, диагностики, заявка } = await ведомостьС(без, ложь.текст, запись.путь, запись.имя)

    /* Ни одного «доказано» — ни в вердикте, ни в итогах, ни в словах. */
    assert.notEqual(заявка?.verdict, "proved", `ядро объявило ЛОЖЬ доказанной: «${заявка?.says}»`)
    assert.notEqual(заявка?.verdict, "proved-induction", `ядро объявило ЛОЖЬ доказанной: «${заявка?.says}»`)
    assert.equal(заявка?.verdict, "refused", `ведомость сказала «${заявка?.says}»`)
    assert.ok(!/доказано/u.test(заявка.says), `в вердикте лжи стоит слово «доказано»: «${заявка.says}»`)
    /* И ни одного «доказано» СВЕРХ того, что в файле было без всякой теоремы:
       ложный кандидат не прибавил доказанности ни на единицу. */
    assert.equal(
      итог.totals?.claims?.proved ?? 0,
      доказаноБез,
      "ложный кандидат прибавил доказанных утверждений — значит ядро ему поверило",
    )
    assert.equal(итог.totals?.claims?.refused ?? 0, 1, "отказ обязан быть посчитан, а не потерян")

    /* И отказ НАЗВАН кодом, а не молчанием: инструмент обязан отличать
       «доказательство неверно» от «доказательства нет». */
    const коды = [...new Set(диагностики.map((б) => String(б?.code ?? "")).filter((к) => к.startsWith("FLANG_PROOF")))]
    assert.ok(коды.length > 0, "ядро отвергло молча — тогда отказ не отличить от отсутствия")
    assert.ok(
      коды.includes("FLANG_PROOF_INDUCTION_STEP"),
      `отказ ядра назвал ${коды.join(", ")}, а ждали FLANG_PROOF_INDUCTION_STEP`,
    )
  })

  test(`${запись.путь}: ИЗЪЯТИЕ — ссылка на несуществующий пример тоже отвергается`, async () => {
    const { без, программа, обязательство, доказаноБез } = await безДоказательства(запись.путь, запись.имя)
    const ложь = искатьДоказательство(обязательство, программа, без, { лгать: ЛГАТЬ.примером })
    assert.equal(ложь.ok, true, "оракул обязан выдать кандидата")
    assert.match(ложь.текст, /по примеру «примера с таким именем нет»/u)

    const { итог, заявка } = await ведомостьС(без, ложь.текст, запись.путь, запись.имя)
    assert.equal(заявка?.verdict, "refused", `ведомость сказала «${заявка?.says}»`)
    assert.equal(итог.totals?.claims?.proved ?? 0, доказаноБез)
  })
}

