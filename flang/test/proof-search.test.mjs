/**
 * Поиск доказательства — и ГЛАВНОЕ: что ядро ему не верит ни на грамм.
 *
 * ── Что здесь проверяется, и почему именно это ──────────────────────────────
 *
 *   1. НАХОДИТ. Снимите написанную рукой теорему — оракул находит её заново, и
 *      найденное принимает не он, а ОБЫЧНЫЙ путь: разборщик, слой обязательств,
 *      ведомость. Без этого пункта остальное не о чем.
 *   2. ИЗЪЯТИЕ, ради которого всё и затевалось. Оракул заставляют выдать
 *      ЛОЖНОГО кандидата — подменой одного шага, — и ядро обязано ОТВЕРГНУТЬ:
 *      ни одного «доказано» в ведомости, отказ с названным кодом. Это важнее
 *      любого числа найденного: пока не показано, что ложь отвергается, «нашёл»
 *      не значит ничего.
 *   3. ВТОРАЯ ПОЛОВИНА НЕДОВЕРИЯ. Соврать можно не только в шаге, но и в самой
 *      ЦЕЛИ, и туда ядро даже не доедет — отвергнет слой обязательств, сличая
 *      утверждение теоремы с постусловием слово в слово.
 *   4. ПРЕДЕЛ НАЗВАН. Упёршись в предел, оракул говорит о нём в отказе, а не
 *      молчит: «не нашёл» и «не искал дальше» — разные ответы.
 *   5. ЗАМЕР ПО КОРПУСУ, исполняемый. Сегодня поиск не находит НИ ОДНОГО нового
 *      доказательства: все двадцать недоказанных утверждений упираются в правила
 *      ядра, а не в ненаписанную цепочку. Число стоит здесь, чтобы вырасти вместе
 *      с ядром, а не остаться пересказом вчерашнего дня.
 *   6. ПОИСК НЕ ОБЯЗАТЕЛЕН. Ни одна строка языка его не зовёт: ведомость,
 *      проверка и печать о нём не знают. Проверяется чтением исходников, а не
 *      обещанием.
 *
 * Запуск: node --test flang/test/proof-search.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { test } from "node:test"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgramFromSource } from "../bin/flang.mjs"
/* Имя четвёртого хода читается у ядра, а не переписывается здесь строкой: две
   копии одного слова расходятся молча, и проверка зеленела бы на чужом ходе. */
import { ВЫЧИСЛЕНИЕМ } from "../proof/reduce.mjs"
import { ЛГАТЬ, ПРЕДЕЛ_ГЛУБИНЫ, ПРЕДЕЛ_ШАГОВ, безТеоремы, искатьДоказательство } from "../proof/search.mjs"
import { globSync } from "../test/glob.mjs"
import { parse } from "../src/parser.mjs"
import { proofLedger } from "../src/proof.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const текст = (путь) => readFileSync(`${корень}${путь}`, "utf8")

/**
 * Исходник без написанной автором теоремы — и обязательство, которое от этого
 * осталось незакрытым.
 *
 * Снимать теорему обязательно: пока она в файле, постусловие закрыто, и оракулу
 * нечего искать. Это и есть способ спросить «нашёл бы он сам?» на НАСТОЯЩЕМ
 * доказательстве, а не на выдуманном.
 */
async function безДоказательства(путь, имя) {
  const исходник = текст(путь)
  const теорема = (parse(исходник, путь).theorems ?? []).find((т) => т.name === имя)
  assert.ok(теорема !== undefined, `теоремы «${имя}» в ${путь} нет — список протух`)
  const без = безТеоремы(исходник, теорема.span?.line ?? -1)
  assert.ok(без !== null && без !== исходник, "теорема не снялась — проверка ничего не проверяет")

  const программа = await loadProgramFromSource(без, путь)
  const внешнее = await externalChecks(программа)
  assert.deepEqual(
    внешнее.diagnostics.filter((б) => б?.severity !== "warning"),
    [],
    "файл без теоремы обязан проходить проверки",
  )
  const обязательство = (внешнее.results?.obligations?.obligations ?? [])
    .find((о) => о.kind === "postcondition" && о.name === имя)
  assert.ok(обязательство !== undefined, `постусловия «${имя}» без теоремы не осталось`)
  assert.ok(
    обязательство.discharge === null || обязательство.discharge === undefined,
    "постусловие закрылось и без теоремы — тогда оракулу тут нечего искать",
  )
  /* Сколько «доказано» в файле БЕЗ всякой теоремы при этом утверждении. Мерка
     для изъятия: у файла бывают и другие утверждения, и считать их за находку
     ложного кандидата значило бы мерить не то. Прирост обязан быть ровно один и
     ровно от нашей строки. */
  const доказаноБез = proofLedger(программа, внешнее.results).totals?.claims?.proved ?? 0
  return { исходник, без, программа, обязательство, доказаноБез }
}

/** Ведомость исходника с дописанным текстом — ОБЫЧНЫМ путём, без единой скидки. */
async function ведомостьС(без, текстТеоремы, путь, имя) {
  const собрано = `${без.replace(/\s*$/u, "")}\n\n${текстТеоремы}`
  const программа = await loadProgramFromSource(собрано, путь)
  const внешнее = await externalChecks(программа)
  const итог = proofLedger(программа, внешнее.results)
  return {
    итог,
    диагностики: внешнее.diagnostics.filter((б) => б?.severity !== "warning"),
    заявка: (итог.claims ?? []).find((к) => к.name === имя),
  }
}

