test("ИЗЪЯТИЕ: соври оракул в ЦЕЛИ — до ядра кандидат не доедет вовсе", async () => {
  /* Здесь ловит не ядро, и это стоит сказать прямо: ядро проверяет
     доказательство ОТНОСИТЕЛЬНО цели, значит подменённую цель оно проверило бы
     честно и честно приняло. Ловит слой обязательств — он сличает утверждение
     теоремы с постусловием функции слово в слово. Ровно поэтому находка выдаётся
     ТЕКСТОМ и проезжает обычный разбор: отдай оракул готовое дерево, эта проверка
     осталась бы у него внутри, то есть её не было бы. */
  const запись = НАСТОЯЩИЕ[1]
  const { без, программа, обязательство } = await безДоказательства(запись.путь, запись.имя)
  const ложь = искатьДоказательство(обязательство, программа, без, { лгать: ЛГАТЬ.целью })
  assert.equal(ложь.ok, true)
  assert.match(ложь.текст, /утверждаем результат не меньше 1/u)

  const собрано = `${без.replace(/\s*$/u, "")}\n\n${ложь.текст}`
  const программаСЛожью = await loadProgramFromSource(собрано, запись.путь)
  const внешнее = await externalChecks(программаСЛожью)
  const коды = внешнее.diagnostics.filter((б) => б?.severity !== "warning").map((б) => б.code)
  assert.ok(
    коды.includes("FLANG_PROOF_CLAIM_MISMATCH"),
    `подменённую цель пропустили: коды ${коды.join(", ") || "нет"}`,
  )
  const итог = proofLedger(программаСЛожью, внешнее.results)
  assert.equal(итог.totals?.claims?.proved ?? 0, 0)
  assert.equal(итог.totals?.claims?.induction ?? 0, 0)
})

