/**
 * Состоятельность ведомости: «доказано обо ВСЕХ входах» против прогона.
 *
 * ── Зачем отдельный файл, если негативных тестов ядра уже под сотню ─────────
 * Точечный тест ловит ТУ дыру, которую видел его автор. За сутки ядро трижды
 * напечатало «доказано» о неправде — дробное дно отрезка, незамкнутая цель под
 * прямым `по примеру`, свободный ВТОРОЙ параметр в базе индукции, — и каждый раз
 * дыра была новая. Каждая закрыта своим тестом, и каждый такой тест смотрит
 * ровно туда, куда смотрел его автор. Значит проверять надо не место, а
 * СВОЙСТВО, и формулируется оно одной строкой:
 *
 *   если ведомость говорит об утверждении «обо ВСЕХ входах»,
 *   то прогон не находит контрпримера ни на одном значении враждебной сетки.
 *
 * В этом условии нет ни слова про `по примеру`, про индукцию, про правила
 * сведения и про чтение объявленного типа. Новое правило ядра попадёт под него
 * само, без единой правки здесь, — а точечный тест не попадёт: он про место.
 *
 * ── Почему это НЕ доказательство, и почему так и надо ────────────────────────
 * Сетка конечна, и молчание сторожа доказательством не является — ровно по той
 * же причине, по какой им не является «сетка N» в самой ведомости. Сторож
 * несимметричен нарочно: найденный контрпример есть ОПРОВЕРЖЕНИЕ, и оно
 * окончательно; ненайденный не говорит ничего. Опровержение здесь и нужно: слово
 * «доказано» обязано быть неопровержимым, и один контрпример его снимает.
 *
 * ── Что сторож покрывает и чего не покрывает ────────────────────────────────
 * Файл с ОТВЕРГНУТЫМ термом в корпус попасть не может: `flang check` его не
 * пропустит, и свод требует нуля отвергнутых (`proof.test.mjs`). А файл с
 * ошибочно ПРИНЯТЫМ термом пропустится и в корпусе окажется — это ровно тот
 * случай, ради которого сторож и написан. Поэтому подделки здесь лежат
 * строками, а не файлами, и на них показаны ЗУБЫ: сетка обязана уметь
 * опровергнуть то, что опровержимо.
 *
 * Запуск: node --test flang/test/proof-soundness.test.mjs
 */
