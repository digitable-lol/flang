/**
 * ПОЧЕМУ ЭТОТ СТОРОЖ ГОНЯЕТ ОБОЛОЧКУ, А НЕ ЗОВЁТ `checkProofs`.
 *
 * Вердикт в рабочем пути считает СЛОЙ НА FLANG (`flang/src/self.mjs` →
 * `flang/self/proofterm.flang` → `flang/self/proof-kernel.flang`), а
 * `checkProofs` — свидетель на JavaScript. Сторож, спросивший свидетеля, зеленел
 * бы и при правиле, которого в решающем слое нет вовсе, — и наоборот, не заметил
 * бы дыры, заведённой в слое. Поэтому вердикт берётся ОТТУДА ЖЕ, откуда его
 * берёт `flang check`.
 */
test("ПОДДЕЛКИ ВХОЖДЕНИЯ: правило не берёт ни чужой элемент, ни функцию-значение", async () => {
  const { execFileSync } = await import("node:child_process")
  const файл = new URL("../proof/examples/poddelka-vhozhdenie.flang", import.meta.url)
  const вывод = execFileSync(
    process.execPath,
    [fileURLToPath(new URL("../bin/flang.mjs", import.meta.url)), "check", fileURLToPath(файл), "--proof", "--pretty"],
    { encoding: "utf8", env: { ...process.env, LC_ALL: "C.UTF-8" }, maxBuffer: 1 << 26 },
  )
  /* ПОДДЕЛКА 1 — приписали одно, утверждают про другое. */
  assert.match(
    вывод,
    /постусловие «в списке есть д»[^\n]*объявлено, не доказано/u,
    `ядро приняло подделку про чужой элемент:\n${вывод}`,
  )
  /* ПОДДЕЛКА 2 — искомое есть ФУНКЦИЯ-значение, и равенство значений на ней
     ложно даже с самой собой. Список при этом собран ровно тем приписыванием,
     которое правило берёт: краснеет здесь ровно проверка формы искомого
     («Сличимо с собой» в `flang/self/proof-kernel.flang`). Снимите её — и этот
     assert падёт первым. */
  assert.match(
    вывод,
    /постусловие «в списке есть ф»[^\n]*объявлено, не доказано/u,
    `ядро приняло подделку про функцию-значение:\n${вывод}`,
  )
})
