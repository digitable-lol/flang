/**
 * Скалярные сетки — враждебные нарочно.
 *
 * Ноль и МИНУС ноль стоят порознь: равенство считает `Object.is`, и на этом
 * различии уже поймано три ошибки библиотеки. NaN и обе бесконечности — потому
 * что «число» flang есть IEEE-754, и почти всякое «не меньше 0» на NaN ложно.
 * Дробное — потому что «число» не `нат`. Пустая строка — потому что встроенные
 * формы на ней отказывают.
 *
 * У `нат` сетка ДРУГАЯ, и это не послабление: `нат` есть отрезок [0, 2^53−1], и
 * рантайм проверяет его на входе (`вне нат` — отказ FLANG_TYPE). Значение вне
 * отрезка контрпримером не является: утверждение о нём и не высказывалось.
 */
const СЕТКА_ЧИСЛА = [0, -0, 1, -1, 2, -2, 0.5, -0.5, 3, -3, Number.NaN, Infinity, -Infinity]
const СЕТКА_НАТ = [0, 1, 2, 3, Number.MAX_SAFE_INTEGER]
const СЕТКА_ЦЕЛОГО = [0, 1, -1, 2, -2]
const СЕТКА_СТРОКИ = ["", "а", "А", "аб", "0", " ", "I", "V", "MMM"]
const СЕТКА_ПРИЗНАКА = [true, false]
/** Значения параметра типа: он параметрический, значит годится что угодно. */
const СЕТКА_ПАРАМЕТРА = [0, -1, "а"]

/** Сколько значений берётся от вложенного типа: без потолка сетка дерева взрывается. */
const ВЕТВЛЕНИЕ = 4
/** Глубина построения значений объявленной суммы. */
const ГЛУБИНА = 3
/** Потолок на произведение по параметрам: сторож обязан заканчиваться. */
const ПОТОЛОК = 3000

/**
 * Значения типа — читаются с объявления, а не угадываются.
 *
 * Тип, для которого сетки нет, возвращает `null`, и это не «пропустим»: охват
 * считается числом ниже, и утверждение с непокрытым параметром называется
 * поимённо. Молча пропущенный параметр — это сторож, который зеленеет оттого,
 * что ничего не проверил.
 */
function сеткаТипа(тип, объявления, параметрыТипа, глубина = ГЛУБИНА) {
  if (тип === null || тип === undefined) return null
  switch (тип.kind) {
    case "number": return СЕТКА_ЧИСЛА
    case "string": return СЕТКА_СТРОКИ
    case "flag": return СЕТКА_ПРИЗНАКА
    case "nothing": return [null]
    case "list": {
      const внутри = сеткаТипа(тип.of, объявления, параметрыТипа, глубина)
      if (внутри === null) return null
      const первые = внутри.slice(0, ВЕТВЛЕНИЕ)
      const наборы = [[], ...первые.map((з) => [з])]
      if (первые.length >= 2) наборы.push([первые[0], первые[1]])
      if (первые.length >= 3) наборы.push([первые[0], первые[1], первые[2]])
      return наборы
    }
    case "named": {
      /* `нат` и `целое` — уточнения числа, а не объявления модуля: их отрезки
         читает типизатор, и сетка обязана лежать ВНУТРИ отрезка. */
      if (тип.name === "нат") return СЕТКА_НАТ
      if (тип.name === "целое") return СЕТКА_ЦЕЛОГО
      if (параметрыТипа.has(тип.name)) return СЕТКА_ПАРАМЕТРА
      const объявление = объявления.get(тип.name)
      if (объявление === undefined) return null
      if (объявление.kind === "alias") return сеткаТипа(объявление.of, объявления, параметрыТипа, глубина)
      if (объявление.kind === "record") {
        const поля = {}
        for (const поле of объявление.fields ?? []) {
          const внутри = сеткаТипа(поле.type, объявления, параметрыТипа, 0)
          if (внутри === null) return null
          поля[поле.name] = внутри[0]
        }
        return [поля]
      }
      if (объявление.kind !== "sum") return null
      return значенияСуммы(объявление, объявления, параметрыТипа, глубина)
    }
    default: return null
  }
}

/**
 * Значения объявленной суммы до заданной глубины.
 *
 * Глубина 0 даёт только конструкторы БЕЗ рекурсивных полей — то есть базу
 * принципа. Каждая следующая ступень строит шаг на значениях предыдущей. Это то
 * же чтение объявления, каким порождается сам принцип
 * (`flang/proof/initial.mjs`), и другого источника у сторожа быть не должно:
 * второй ответ на вопрос «какие бывают значения этого типа» разошёлся бы с
 * первым молча.
 */
function значенияСуммы(сумма, объявления, параметрыТипа, глубина) {
  let собрано = []
  for (let ступень = 0; ступень <= глубина; ступень += 1) {
    const следующие = []
    for (const вариант of сумма.variants ?? []) {
      const поля = вариант.fields ?? []
      const рекурсивные = поля.filter((п) => п.type?.kind === "named" && п.type.name === сумма.name)
      if (рекурсивные.length > 0 && собрано.length === 0) continue
      const части = собрано.slice(0, ВЕТВЛЕНИЕ)
      const сколько = рекурсивные.length === 0 ? 1 : Math.max(части.length, 1)
      for (let и = 0; и < сколько; и += 1) {
        const значения = {}
        let годен = true
        for (const поле of поля) {
          if (поле.type?.kind === "named" && поле.type.name === сумма.name) {
            значения[поле.name] = части[и % части.length]
            continue
          }
          const внутри = сеткаТипа(поле.type, объявления, параметрыТипа, 0)
          if (внутри === null) {
            годен = false
            break
          }
          значения[поле.name] = внутри[и % внутри.length]
        }
        if (годен) следующие.push(variant(вариант.name, значения))
      }
    }
    собрано = [...собрано, ...следующие]
  }
  return собрано.length === 0 ? null : собрано
}

/**
 * Запасная сетка: значения, которые автор написал в примерах.
 *
 * Нужна там, где значение построить неоткуда, — у параметра типа `функция из
 * числа в признак`: функция-значение это ТЕГ, и годятся только те теги, которые
 * программа где-то берёт значением. Сочинять их здесь значило бы завести второй
 * ответ на вопрос, кого можно передать; автор уже ответил примером.
 *
 * Сетка при этом остаётся враждебной там, где может: у «Позиции где» условие
 * приезжает из примера, а список — из сетки, и произведение берётся полное.
 */
function изПримеров(fn, имя) {
  const собрано = []
  const виденные = new Set()
  for (const пример of fn?.examples ?? []) {
    const значение = пример?.args?.[имя]
    if (значение === undefined) continue
    const ключ = JSON.stringify(значение)
    if (виденные.has(ключ)) continue
    виденные.add(ключ)
    собрано.push(значение)
  }
  return собрано.length === 0 ? null : собрано
}

/** Произведение сеток по параметрам, с потолком: сторож обязан заканчиваться. */
function наборыАргументов(fn, объявления, параметрыТипа) {
  let наборы = [{}]
  for (const параметр of fn?.params ?? []) {
    const сетка = сеткаТипа(параметр.type, объявления, параметрыТипа, ГЛУБИНА) ?? изПримеров(fn, параметр.name)
    if (сетка === null) return null
    const следующие = []
    for (const набор of наборы) {
      for (const значение of сетка) {
        следующие.push({ ...набор, [параметр.name]: значение })
        if (следующие.length >= ПОТОЛОК) break
      }
      if (следующие.length >= ПОТОЛОК) break
    }
    наборы = следующие
  }
  return наборы
}

/**
 * Контрпримеры к утверждению: входы враждебной сетки, на которых рантайм
 * отвергает ИМЕННО это постусловие.
 *
 * Контрпример отличается от прочих отказов по СООБЩЕНИЮ, а не по коду.
 * `FLANG_PROPERTY` носит всякое нарушенное постусловие, включая чужое, всплывшее
 * из вложенного вызова; сообщение постусловие называет («нарушено свойство «имя»
 * функции «имя»») и кладёт его в AST сам разборщик. Отказ другой природы —
 * предел шагов, `вне нат`, встроенная форма на пустой строке — контрпримером НЕ
 * считается: он говорит, что вычисление не дошло или что вход вне объявленного
 * типа, а не что утверждение ложно.
 */
function контрпримеры(программа, обязательство, объявления, предел = 3) {
  const fn = (программа.functions ?? []).find((f) => f.name === обязательство.of)
  if (fn === undefined) return { поддержано: false, найдено: [], значений: 0 }
  const постусловие = (fn.postconditions ?? []).find((п) => п.name === обязательство.name)
  if (постусловие === undefined || typeof постусловие.message !== "string") {
    return { поддержано: false, найдено: [], значений: 0 }
  }
  const параметрыТипа = new Set((fn.typeParams ?? []).map((п) => (typeof п === "string" ? п : п?.name)))
  const наборы = наборыАргументов(fn, объявления, параметрыТипа)
  if (наборы === null) return { поддержано: false, найдено: [], значений: 0 }

  const найдено = []
  for (const набор of наборы) {
    try {
      evaluate(программа, fn.name, набор, { maxSteps: 200000 })
    } catch (ошибка) {
      if (ошибка?.message === постусловие.message) {
        найдено.push(набор)
        if (найдено.length >= предел) break
      }
    }
  }
  return { поддержано: true, найдено, значений: наборы.length }
}

/** Объявления типов программы — картой по имени. */
function объявленияТипов(программа) {
  const карта = new Map()
  for (const тип of программа?.types ?? []) {
    if (typeof тип?.name === "string") карта.set(тип.name, тип)
  }
  return карта
}

