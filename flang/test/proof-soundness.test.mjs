test("КЛАСС: ни одно утверждение корпуса не опровергается прогоном на враждебной сетке", async () => {
  /* Условие сторожа целиком: ведомость сказала «обо ВСЕХ входах» — значит
     враждебная сетка не находит контрпримера. Ни слова про `по примеру`, про
     индукцию, про правила сведения и про чтение объявленного типа: новое
     правило ядра попадёт под это условие само.

     ── ПОЧЕМУ ПРОВЕРЯЮТСЯ ВСЕ УТВЕРЖДЕНИЯ, А НЕ ТОЛЬКО ДОКАЗАННЫЕ ────────────
     Сперва здесь стояло `verdict === "доказано"` и довод к нему: «сетка» и
     «объявлено, не доказано» об ВСЕХ входах ничего не обещают, значит и спроса
     с них нет. Довод верен про ВЕРДИКТ и неверен про УТВЕРЖДЕНИЕ, и разницу
     показал корпус: в `four-words.flang` — файле, который учит читать слова
     ведомости, — два утверждения были попросту ЛОЖНЫ («результат не меньше 0» о
     функции, принимающей обычное `число`, при контрпримере −1), а ведомость
     печатала о них «сетка 3 значения: нарушений не найдено» и «объявлено, не
     доказано». Обе строки — правда о себе: примеры автора стояли на 0, 1 и 10.
     Читается это как заверение.

     Ложное утверждение в дереве — дефект при ЛЮБОМ вердикте. Доказанное ложное
     — дыра в ядре; сеточное ложное — неправда, которую ядро не обязано было
     поймать, но которую поймать МОЖНО, и молчать о ней, имея сетку в руках,
     значило бы держать сторожа с закрытым глазом. Поэтому вердикт здесь только
     ПЕЧАТАЕТСЯ рядом с находкой (чтобы было видно, дыра это в ядре или неправда
     в прозе), а порог у обоих один: контрпримеров ноль.

     Найдены те два независимо двумя ветками — `work/trebuet` чтением и этим
     сторожем прогоном, — и это лучшая проверка сторожа, какая бывает: он нашёл
     то, что нашёл человек, не зная о нём. */
  const проверено = []
  const непокрытые = []
  const опровергнутые = []
  let значений = 0

  for (const путь of ФАЙЛЫ) {
    let программа
    try {
      программа = await loadProgram(join(корень, путь))
    } catch {
      /* Файл, который не грузится, — забота свода по корпусу: он называет такие
         поимённо (`proof-ledger.mjs`), и второй счёт того же здесь не нужен. */
      continue
    }
    const внешнее = await externalChecks(программа)
    if (внешнее.diagnostics.some((б) => б?.severity !== "warning")) continue
    const об = obligations(программа, внешнее.results)
    checkProofs(программа, об.obligations)
    const объявления = объявленияТипов(программа)

    for (const обязательство of об.obligations) {
      if (обязательство.kind !== "postcondition") continue
      /* Вердикт не отбирает, а НАЗЫВАЕТСЯ: по нему читается, дыра это в ядре
         («доказано» о лжи) или неправда в прозе («сетка» о лжи). Отбор по нему
         оставил бы сторожа с закрытым глазом ровно там, где и жили две находки. */
      const вердикт = обязательство.discharge?.verdict
        ?? ((обязательство.grid ?? 0) > 0 ? "сетка" : "объявлено, не доказано")
      const метка = `[${вердикт}] ${путь}: «${обязательство.name}» функции «${обязательство.of}»`
      const итог = контрпримеры(программа, обязательство, объявления)
      if (!итог.поддержано) {
        непокрытые.push(метка)
        continue
      }
      значений += итог.значений
      проверено.push(метка)
      if (итог.найдено.length > 0) {
        опровергнутые.push(`${метка} — контрпример ${JSON.stringify(итог.найдено[0])}`)
      }
    }
  }

  assert.deepEqual(
    опровергнутые,
    [],
    "утверждение корпуса опровергнуто прогоном на враждебной сетке.\n"
      + "Вердикт в скобках говорит, что чинить: «доказано» — дыра в ядре,\n"
      + "«сетка»/«объявлено, не доказано» — неправда в самом утверждении.\n"
      + опровергнутые.join("\n"),
  )
  /* ОХВАТ ЧИСЛОМ, иначе сторож зеленеет от того, что не проверил ничего.
     Непокрытые названы поимённо: сторож обязан говорить, чего он НЕ проверил, —
     число «проверено» без этого читается как охват, а является половиной его.
     Порог стоит «не меньше», а не «равно»: расти корпусу можно, и ронять эту
     строку от роста было бы наказанием за работу. Равенство живёт в своде
     (`proof.test.mjs`), и второго счёта того же здесь нет. */
  assert.deepEqual(непокрытые, [], `у этих утверждений сетка по параметрам не построена:\n${непокрытые.join("\n")}`)
  assert.ok(проверено.length >= 60, `утверждений проверено ${проверено.length}, а их было 60`)
  assert.ok(значений >= 2000, `сетка из ${значений} значений — это меньше, чем было (2121)`)
})

