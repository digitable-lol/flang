/**
 * УЛИКА ПЕРВАЯ — прямой шаг `по примеру`, вне всякой индукции.
 *
 * Ведомость печатала «доказано: терм принят ядром, 1 шаг — утверждение обо ВСЕХ
 * входах», а `flang run` на том же файле отвечал FLANG_PROPERTY на `х = -5`.
 * Проверка «примером закрывается только то, у чего значение одно» жила в ветке
 * случая, а прямой шаг в неё не заходил вовсе: `посылка` у него `undefined`.
 */
const ПОДДЕЛКА_ПРЯМАЯ = `модуль «Подделка»

тотальная функция «Противоположное»
  принимает х: число
  возвращает число
  для всех х обеспечивает «результат не больше нуля» результат не больше 0
  пример «Пять»
    дано х равно 5
    ожидается -5
  0 минус х

теорема «результат не больше нуля»
  дано х: число
  утверждаем результат не больше 0
  по примеру «Пять»
  следовательно доказано
`

/**
 * УЛИКА ВТОРАЯ — тот же класс ВНУТРИ индукции, и её видно только на функции
 * ДВУХ параметров.
 *
 * Проверка внутри индукции была, но смотрела на имена ОБРАЗЦА случая. Второй
 * параметр функции образец не связывает вовсе: база `случай вариант «Пусто»` при
 * теле `0 минус н` закрывалась примером с `н = 0`, и ведомость печатала
 * «доказано индукцией по «Ящик» … обо ВСЕХ входах типа «Ящик»» — при
 * контрпримере `н = 5` на том же файле.
 */
const ПОДДЕЛКА_ИНДУКЦИЕЙ = `модуль «Подделка два»

тип «Ящик»
  вариант «Пусто»
  вариант «Звено» содержит хвост: «Ящик»

тотальная функция «Мера»
  принимает я: «Ящик», н: число
  возвращает число
  для всех я обеспечивает «мера неотрицательна» результат не меньше 0
  пример «Пустой при нуле»
    дано я равно вариант «Пусто»
    дано н равно 0
    ожидается 0
  разбор я
    случай вариант «Пусто»
      то 0 минус н
    случай вариант «Звено» с хвост как х
      то «Мера» от х и н

теорема «мера неотрицательна»
  дано я: «Ящик»
  дано н: число
  утверждаем результат не меньше 0
  индукция по я
    случай вариант «Пусто»
      то по примеру «Пустой при нуле»
    случай вариант «Звено» с хвост как х
      то по предположению
  следовательно доказано
`

/** Обязательства и вердикты ядра для текста — тем же путём, каким их считает оболочка. */
async function разобрать(исходник, имя = "состоятельность.flang") {
  const программа = await loadProgramFromSource(исходник, имя)
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, об, ядро, первый: ядро.checked[0] ?? null }
}

test("ПОДДЕЛКА ПРЯМАЯ: примером закрыта цель с параметром — отвергнуто, и отказ называет параметр", async () => {
  const { ядро } = await разобрать(ПОДДЕЛКА_ПРЯМАЯ)
  const вердикт = ядро.checked[0]
  assert.equal(вердикт.verdict, "отвергнуто", `ядро приняло подделку: ${вердикт.says}`)
  assert.equal(ядро.diagnostics.length > 0, true, "отвергнуто молча — автор не узнает, что не так")
  const текст = ядро.diagnostics.map((д) => д.message).join("\n")
  /* Отказ обязан назвать ПРИЧИНУ, а не только факт: имя параметра, из-за
     которого значений больше одного, и то, что пример — одно из них. */
  assert.match(текст, /«х»/u, текст)
  assert.match(текст, /пример/u, текст)
})

test("ПОДДЕЛКА ИНДУКЦИЕЙ: свободен ВТОРОЙ параметр — отвергнута база, а не шаг", async () => {
  const { ядро } = await разобрать(ПОДДЕЛКА_ИНДУКЦИЕЙ)
  const вердикт = ядро.checked[0]
  assert.equal(вердикт.verdict, "отвергнуто", `ядро приняло подделку: ${вердикт.says}`)
  assert.equal(вердикт.induction, undefined, "у отвергнутого терма поля индукции быть не может")
  const текст = ядро.diagnostics.map((д) => д.message).join("\n")
  /* Место названо: отказ в БАЗЕ «Пусто», и свободно именно «н» — второй
     параметр, а не имя образца. Шаг «Звено» сводится и претензий не вызывает;
     переехать отказу на него нельзя, иначе автор чинил бы не то. */
  assert.match(текст, /база «Пусто»/u, текст)
  assert.match(текст, /«н»/u, текст)
})

test("замкнутая цель примером закрывается по-прежнему: запрет не съел правило", async () => {
  /* Граница с другой стороны. У функции БЕЗ параметров вход один, и вычисление
     отвечает обо всех входах, потому что вход один. Запрети здесь — и правило
     `по примеру` перестало бы закрывать вне индукции хоть что-нибудь. */
  const { ядро } = await разобрать(`модуль «Замкнутая»

тотальная функция «Ноль»
  возвращает число
  обеспечивает «ноль не больше нуля» результат не больше 0
  пример «он»
    ожидается 0
  0

теорема «ноль не больше нуля»
  утверждаем результат не больше 0
  по примеру «он»
  следовательно доказано
`)
  assert.equal(ядро.checked[0].verdict, "доказано", JSON.stringify(ядро.diagnostics))
})

test("ВСЕ ЧЕТЫРЕ ОБОСНОВАНИЯ вне индукции: ни одно не доводит цель с параметром до «доказано»", async () => {
  /* Обход СОСЕДЕЙ дыры, а не только её самой. Дыра была в том, что один вид шага
     не спросил про замкнутость; значит спросить надо у каждого, и спрошено
     исполняемо, а не в отчёте.

     `по закону` при этом принимается — и это не поблажка: его вердикт «сетка», а
     «сетка» ведомость печатает словами «это не доказательство». Класс сторожат
     СЛОВА ведомости, а не факт принятия терма, и разница здесь и работает. */
  const тело = (обоснование, законы) => `модуль «Соседи»
${законы}
тотальная функция «Половина»
  принимает н: число
  возвращает число
  для всех н обеспечивает «половина неотрицательна» результат не меньше 0
  пример «ноль»
    дано н равно 0
    ожидается 0
  н делить на 2

теорема «половина неотрицательна»
  дано н: число
  утверждаем результат не меньше 0
  ${обоснование}
  следовательно доказано
`
  const МОНОИД = `
моноид «Сложение чисел»
  носитель число
  операция «Плюс»
  единица 0

тотальная функция «Плюс»
  принимает левое: число, правое: число
  возвращает число
  левое плюс правое
`
  const случаи = [
    ["по примеру «ноль»", "", "отвергнуто"],
    ["по предположению", "", "отвергнуто"],
    ["по свойству «половина неотрицательна»", "", "отвергнуто"],
    ["по закону «Сложение чисел»", МОНОИД, "сетка"],
  ]
  for (const [обоснование, законы, ожидается] of случаи) {
    const { ядро } = await разобрать(тело(обоснование, законы))
    assert.equal(ядро.checked[0].verdict, ожидается, `${обоснование}: ${ядро.checked[0].says}`)
    assert.notEqual(ядро.checked[0].verdict, "доказано", `${обоснование} довело ложную цель до «доказано»`)
  }
})

