test("постусловия у функции нет — и поля в AST нет тоже", () => {
  /* Изъятие того, что стережёт побайтовую неподвижную точку самоприменения:
     программа без `обеспечивает` обязана давать РОВНО прежний AST. Появись
     `postconditions: []` у каждой функции — и первый же файл корпуса разошёлся
     бы с самоприменённым парсером. */
  const без = parse(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n  н плюс 1\n",
    "без.flang",
  )
  assert.ok(!("postconditions" in без.functions[0]), "поле появилось у функции без постусловия")
  /* `модуль` сам заводит узел заголовка в `legacy`, поэтому ключей пять, а не
     четыре; важно, что среди них нет ни `postconditions`, ни `theorems`. */
  assert.deepEqual(Object.keys(без), ["flang", "module", "types", "functions", "legacy"])
  assert.ok(!("theorems" in без))
})

