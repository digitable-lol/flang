import test from "node:test"

import { KEYWORDS, keywordId, tokenize, wordOn } from "../src/lexer.mjs"
import { parse } from "../src/parser.mjs"
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/** Слова доказательства — те восемь, что заведены ради этого слоя. */
const СЛОВА_ДОКАЗАТЕЛЬСТВА = [
  "ensures",
  "forall",
  "claim",
  "induction",
  "byProperty",
  "byExample",
  "byHypothesis",
  "qed",
]

const СТОПКА = `модуль «Стопка»

тип «Стопка»
  вариант «Пусто»
  вариант «Звено» содержит голова: число, хвост: «Стопка»

тотальная функция «Высота»
  принимает стопка: «Стопка»
  возвращает число
  для всех стопка обеспечивает «высота неотрицательна» результат не меньше 0
  пример «пустая стопка нулевой высоты»
    дано стопка равно вариант «Пусто»
    ожидается 0
  разбор стопка
    случай вариант «Пусто»
      то 0
    случай вариант «Звено» с голова как г и хвост как х
      то («Высота» от х) плюс 1

теорема «высота неотрицательна»
  дано стопка: «Стопка»
  утверждаем результат не меньше 0
  индукция по стопка
    случай вариант «Пусто»
      то по примеру «пустая стопка нулевой высоты»
    случай вариант «Звено» с голова как г и хвост как х
      то по предположению
      затем результат не меньше 0 по свойству «высота неотрицательна»
  следовательно доказано
`

/* Та же теорема наследия FTS, что стоит в дереве: её разбор обязан не
   измениться ни на байт, иначе полнота подмножества FTS перестала бы быть
   правдой. */
const НАСЛЕДИЕ = `категория «Исполнение заказа»

  объект Заказ
    номер является строкой
    оплачен является признаком

  морфизм «Оплаченный заказ можно отгрузить»
    если «Оплачен»
    то «Отгрузить заказ разрешено»

  теорема «Заказ ЗК-7781 можно отгрузить»
    дано Заказ имеет оплачен равное да
    в данных заказы найти где номер равен «ЗК-7781»
    по морфизму «Оплаченный заказ можно отгрузить»
    следовательно «Отгрузить заказ разрешено»
`

// ── постусловие обычной функции ────────────────────────────────────────────

test("обычная функция теперь может высказать утверждение о результате", () => {
  const программа = parse(СТОПКА, "стопка.flang")
  const [постусловие] = программа.functions[0].postconditions
  assert.equal(постусловие.name, "высота неотрицательна")
  assert.equal(постусловие.bind, "результат")
  assert.equal(постусловие.code, "FLANG_PROPERTY")
  assert.equal(постусловие.forall, "стопка", "квантор назвал параметр, по которому пойдёт индукция")
  assert.equal(постусловие.expr.kind, "binary")
  assert.equal(постусловие.expr.op, "gte")
})

test("постусловия у функции нет — и поля в AST нет тоже", () => {
  /* Изъятие того, что стережёт побайтовую неподвижную точку самоприменения:
     программа без `обеспечивает` обязана давать РОВНО прежний AST. Появись
     `postconditions: []` у каждой функции — и первый же файл корпуса разошёлся
     бы с самоприменённым парсером. */
  const без = parse(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n  н плюс 1\n",
    "без.flang",
  )
  assert.ok(!("postconditions" in без.functions[0]), "поле появилось у функции без постусловия")
  /* `модуль` сам заводит узел заголовка в `legacy`, поэтому ключей пять, а не
     четыре; важно, что среди них нет ни `postconditions`, ни `theorems`. */
  assert.deepEqual(Object.keys(без), ["flang", "module", "types", "functions", "legacy"])
  assert.ok(!("theorems" in без))
})

test("квантор по чужому имени — отказ, а не молчаливо принятая программа", () => {
  /* Обязательство по параметру, которого нет, нечем предъявить ядру: индукция
     пошла бы по имени, которого у функции не бывает. Молчать нельзя. */
  assert.throws(
    () =>
      parse(
        "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
          + "  для всех м обеспечивает «п» результат не меньше 0\n  н плюс 1\n",
        "чужое.flang",
      ),
    /нет параметра «м»/u,
  )
})

// ── теорема: две формы под одним словом ────────────────────────────────────

test("теорема новой формы едет своим ключом, а не в наследие", () => {
  const программа = parse(СТОПКА, "стопка.flang")
  assert.equal(программа.theorems.length, 1)
  assert.equal(
    (программа.legacy ?? []).filter((з) => з?.construct === "theorem").length,
    0,
    "теорема новой формы не должна попадать в legacy",
  )
  const теорема = программа.theorems[0]
  assert.equal(теорема.kind, "theorem")
  assert.equal(теорема.name, "высота неотрицательна")
  assert.equal(теорема.qed, true)
  assert.deepEqual(теорема.vars.map((п) => п.name), ["стопка"])
  assert.equal(теорема.induction.param, "стопка")
  assert.deepEqual(
    теорема.induction.cases.map((с) => с.pattern.name),
    ["Пусто", "Звено"],
    "случаев столько же, сколько конструкторов объявленной суммы",
  )
  assert.deepEqual(
    теорема.induction.cases.flatMap((с) => с.steps.map((ш) => ш.by.rule)),
    ["example", "hypothesis", "property"],
  )
})

test("старая форма теоремы разбирается ровно как разбиралась", () => {
  const программа = parse(НАСЛЕДИЕ, "наследие.flang")
  assert.ok(!("theorems" in программа), "теорема наследия не должна уезжать в новый ключ")
  const узел = программа.legacy.find((з) => з.construct === "theorem")
  assert.equal(узел.kind, "ftsLegacy")
  assert.deepEqual(Object.keys(узел.value), [
    "title",
    "structure",
    "field",
    "expected",
    "collection",
    "selectorField",
    "selectorValue",
    "morphisms",
    "conclusion",
  ])
  assert.equal(узел.value.structure, "Заказ")
  assert.equal(узел.value.field, "оплачен")
  assert.equal(узел.value.expected, true)
  assert.equal(узел.value.collection, "заказы")
  assert.equal(узел.value.conclusion, "Отгрузить заказ разрешено")
  assert.deepEqual(узел.value.morphisms, ["Оплаченный заказ можно отгрузить"])
})

test("все теоремы наследия в дереве разбираются в тот же узел, что и раньше", () => {
  /* Не выдуманный пример, а сами файлы репозитория: пять теорем FTS, которые
     стояли до этой работы. Числа названы, чтобы потеря файла была видна. */
  const файлы = globSync("**/*.fts", { cwd: корень, exclude: (путь) => путь.includes("node_modules") })
  let теорем = 0
  let файлов = 0
  for (const путь of файлы) {
    let программа
    try {
      программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    } catch {
      continue /* в корпусе есть намеренно сломанные модели */
    }
    const свои = (программа.legacy ?? []).filter((з) => з?.construct === "theorem")
    if (свои.length === 0) continue
    файлов += 1
    теорем += свои.length
    assert.ok(!("theorems" in программа), `${путь}: теорема наследия уехала в новый ключ`)
    for (const узел of свои) {
      assert.equal(узел.kind, "ftsLegacy", `${путь}: вид узла изменился`)
      assert.ok("conclusion" in узел.value, `${путь}: поле conclusion пропало`)
    }
  }
  assert.ok(теорем >= 5, `теорем наследия найдено ${теорем} в ${файлов} файлах, ожидалось не меньше пяти`)
})

