/**
 * Поверхность доказательства: чем в языке ВЫСКАЗЫВАЮТ утверждение.
 *
 * ── Что здесь проверяется, а что нет ────────────────────────────────────────
 * Здесь проверяется только СЛОЙ СЛОВ: что утверждение можно записать, что
 * записанное попадает в AST, что старая форма теоремы не заметила нововведения
 * и что новые слова не отняли ни одного имени у корпуса. Проверять ли
 * утверждение — работа обязательств (`obligations.mjs`) и ядра
 * (`proofterm.mjs`), и их проверки лежат в своих файлах.
 *
 * ── Почему у каждой проверки есть близнец-изъятие ───────────────────────────
 * Проверка, которая не умеет краснеть, — это не проверка, а строка в отчёте.
 * Поэтому у каждого утверждения ниже есть пара: сначала «так работает», потом
 * «изымем то, что стережём, — и обязано упасть». Тот же приём, которым в
 * `proof.test.mjs` сверка ведомости доказывает, что умеет ловить изъятую
 * строку сторожа.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
