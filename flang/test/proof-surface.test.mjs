test("ни одно новое слово не отняло имени у корпуса", () => {
  /* Тот самый замер, ради которого написан `flang/scripts/word-occupancy.mjs`,
     — но здесь он не в комментарии, а исполняется. Слово, ставшее ключевым,
     запрещает одноимённую переменную во всех файлах репозитория; если бы
     какое-то из восьми стояло в корпусе голым, файл, к доказательствам
     отношения не имеющий, перестал бы разбираться. */
  const фразы = СЛОВА_ДОКАЗАТЕЛЬСТВА.flatMap((id) => KEYWORDS[id])
  assert.equal(фразы.length, 16, "восемь понятий на двух поверхностях")
  const файлы = [
    ...globSync("**/*.flang", { cwd: корень, exclude: (путь) => путь.includes("node_modules") }),
    ...globSync("**/*.fts", { cwd: корень, exclude: (путь) => путь.includes("node_modules") }),
  ]
  assert.ok(файлы.length >= 150, `корпус ужался до ${файлы.length} файлов`)

  const наши = new Set(["flang/test/proof-surface.test.mjs"])
  let голых = 0
  const места = []
  for (const путь of файлы) {
    if (наши.has(путь.replace(/^\//u, ""))) continue
    let токены
    try {
      токены = tokenize(readFileSync(`${корень}${путь}`, "utf8"))
    } catch {
      continue
    }
    /* Голым считается токен `name` с `quoted: false`: закавыченное имя
       ключевым словом стать не может никогда, поэтому «ёлочки», строки и
       комментарии здесь не считаются — этим счёт и отличается от `grep`. */
    for (const токен of токены) {
      if (токен.kind !== "name" || токен.quoted === true) continue
      const слово = String(токен.value ?? "").toLowerCase()
      if (фразы.includes(слово)) {
        голых += 1
        места.push(`${путь}:${токен.span?.line ?? "?"} — «${слово}»`)
      }
    }
  }
  assert.equal(голых, 0, `слово доказательства стоит в корпусе голым:\n${места.join("\n")}`)
})

test("слова доказательства есть на русской и английской поверхности и молчат на двух других", () => {
  /* Молчание здесь — решение, а не пропуск, и оно ИЗМЕРЕНО, а не обещано в
     комментарии. Пока владелец не назвал эсперантское и китайское слово,
     доказательство пишется на двух поверхностях из четырёх, и это обязано быть
     видно числом: иначе завтра кто-нибудь допишет столбец, решив за владельца.
     Тот же довод держит `decreases` («убывает») на двух поверхностях. */
  for (const id of СЛОВА_ДОКАЗАТЕЛЬСТВА) {
    assert.ok(wordOn(id, "ru") !== null, `${id}: нет русского слова`)
    assert.ok(wordOn(id, "en") !== null, `${id}: нет английского слова`)
    assert.equal(wordOn(id, "eo"), null, `${id}: эсперантское слово завелось — это решение владельца`)
    assert.equal(wordOn(id, "zh"), null, `${id}: китайское слово завелось — это решение владельца`)
  }
})

test("длинная фраза побеждает короткую: 'следовательно доказано' — один токен", () => {
  /* Иначе новая форма отняла бы у старой её `следовательно «вывод»`. Склейка
     жадная и длиннейшая-первой, и здесь это проверено, а не предположено. */
  assert.equal(keywordId("следовательно доказано"), "qed")
  assert.equal(keywordId("следовательно"), "therefore")
  const токены = tokenize("следовательно доказано\n").filter((т) => т.kind === "keyword")
  assert.deepEqual(токены.map((т) => т.value), ["qed"])
  const старая = tokenize("следовательно «вывод»\n").filter((т) => т.kind === "keyword")
  assert.deepEqual(старая.map((т) => т.value), ["therefore"])
})

test("'по свойству' и 'по примеру' — свои токены, а не 'по' рядом со 'свойство'", () => {
  for (const [фраза, id] of [
    ["по свойству", "byProperty"],
    ["по примеру", "byExample"],
    ["по предположению", "byHypothesis"],
    ["индукция по", "induction"],
    ["для всех", "forall"],
  ]) {
    assert.equal(keywordId(фраза), id, `«${фраза}»`)
  }
  /* А одиночные слова остались за своими прежними понятиями — ни одно не
     отнято. */
  assert.equal(keywordId("свойство"), "property")
  assert.equal(keywordId("пример"), "example")
  assert.equal(keywordId("по"), "by")
  assert.equal(keywordId("затем"), "nextStep")
})
