// ── утверждение типизируется: бывшая недостача и то, что от неё осталось ────

/** Диагностики типизатора без предупреждений: `[код, …]`. */
function типы(исходник, имяФайла = "проба.flang") {
  const беды = (checkTypes(parse(исходник, имяФайла)).diagnostics ?? []).filter((б) => б.severity !== "warning")
  return { коды: беды.map((б) => б.code), тексты: беды.map((б) => б.message) }
}

test("выражение постусловия типизируется: число плюс строка больше не проходит", () => {
  /* Здесь стояла названная недостача, написанная приёмом
     `flang/test/missing.test.mjs`: у неё была эта самая программа, и тест
     требовал, чтобы типизатор о ней МОЛЧАЛ. Недостачи не стало — тест
     покраснел, как и обещано во вступлении того файла, и вместе с ним ушла
     запись из `flang/proof/SPEC.md`. Программа осталась та же, перевернулось
     требование: теперь красное значит, что дыра вернулась.

     Дыра была не в слое доказательства, а под ним: `types.mjs` не читал поле
     `postconditions` ни одной строкой. Видно её не было, потому что постусловия
     приходили только из `compat.mjs`, а он строит их сам и строит правильными;
     слово `обеспечивает` отдало эту запись автору. */
  const { коды, тексты } = типы(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + '  обеспечивает «бессмыслица» результат плюс "строка"\n  н\n',
  )
  /* Изъянов ДВА, и второй не следует из первого: выражение и складывает число
     со строкой, и не даёт признака. Названы обязаны быть оба. */
  assert.deepEqual(коды, ["FLANG_TYPE", "FLANG_TYPE"], тексты.join(" | "))
  assert.match(тексты[0], /правый операнд «add»/u)
  assert.match(тексты[1], /постусловие «бессмыслица» даёт число, а постусловие обязано быть признаком/u)
})

test("постусловие обязано быть признаком — само по себе, а не через сложение", () => {
  /* Изъятие первой проверки из второй: выражение типизируется безупречно и
     утверждением всё равно не является. Молчи типизатор здесь — «постусловие
     даёт признак» держалось бы на случайности разбора. */
  const { коды, тексты } = типы(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + "  обеспечивает «не утверждение» результат плюс 1\n  н\n",
  )
  assert.deepEqual(коды, ["FLANG_TYPE"], тексты.join(" | "))
  assert.match(тексты[0], /даёт число, а постусловие обязано быть признаком/u)
})

test("«результат» внутри постусловия имеет объявленный тип возврата", () => {
  /* Изъятие: возврат объявлен строкой, и сравнение порядка по нему незаконно.
     Приди `результат` джокером — типизатор промолчал бы, и проверка выше
     ловила бы только грубую бессмыслицу. */
  const { коды, тексты } = типы(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает строка\n"
      + "  обеспечивает «п» результат не меньше 0\n  \"а\"\n",
  )
  assert.ok(коды.length > 0, "типизатор не заметил, что результат — строка")
  assert.match(тексты.join(" | "), /левый операнд сравнения «gte» имеет тип строка/u)
})

test("«для всех» связывает имя, и тип ему даёт параметр", () => {
  /* Квантор называет параметр (`parseEnsures` этого требует), поэтому тип
     связанного имени обязан приходить оттуда же, откуда пришёл бы в теле.
     Изъятие: параметр — сумма, а постусловие сравнивает его по порядку. */
  const { коды, тексты } = типы(
    "модуль «М»\n\nтип «Светофор»\n  вариант «Красный»\n  вариант «Зелёный»\n\n"
      + "тотальная функция «Штраф»\n  принимает свет: «Светофор»\n  возвращает число\n"
      + "  для всех свет обеспечивает «п» свет больше 0\n  0\n",
  )
  assert.ok(коды.length > 0, "имя, связанное квантором, осталось без типа")
  assert.match(тексты.join(" | "), /операнд сравнения «gt» имеет тип «Светофор»/u)
})

test("годное постусловие остаётся годным — обе формы, с квантором и без", () => {
  /* Обратная сторона всех изъятий: проверка, которая краснеет на правильной
     программе, ничего не стоит. Здесь стоят обе поверхности сразу. */
  const { коды, тексты } = типы(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + "  для всех н обеспечивает «неотрицателен» результат не меньше 0\n"
      + "  обеспечивает «не меньше входа» результат не меньше н\n  н\n",
  )
  assert.deepEqual(коды, [], тексты.join(" | "))
})

test("квантор по чужому имени ловится и в AST, пришедшем мимо парсера", () => {
  /* Поверхность это уже запрещает (`parseEnsures` отказывает), но AST приходит
     в типизатор и другими дорогами — из моста `compat.mjs`, из понижения
     `defunc.mjs`, из файла через `flang check --ast`. Обязательство по имени,
     которого у функции нет, нечем предъявить ядру, и молчать о нём нельзя.
     Изъятие: то же самое дерево с ПРАВИЛЬНЫМ квантором обязано быть чистым —
     иначе проверка ловила бы не квантор, а что-то ещё. */
  const программа = parse(
    "модуль «М»\n\nтотальная функция «Ф»\n  принимает н: число\n  возвращает число\n"
      + "  для всех н обеспечивает «п» результат не меньше 0\n  н\n",
    "квантор.flang",
  )
  const постусловие = программа.functions[0].postconditions[0]
  assert.equal(постусловие.forall, "н", "улика не собралась: квантора в дереве нет")

  постусловие.forall = "чужое"
  const беды = (checkTypes(программа).diagnostics ?? []).filter((б) => б.severity !== "warning")
  assert.deepEqual(беды.map((б) => б.code), ["FLANG_UNKNOWN_NAME"], беды.map((б) => б.message).join(" | "))
  assert.match(беды[0].message, /«для всех чужое», а параметра с таким именем у функции нет/u)

  постусловие.forall = "н"
  assert.deepEqual((checkTypes(программа).diagnostics ?? []).map((б) => б.code), [])
})

test("НЕДОСТАЧА: предположение теоремы не типизируется", () => {
  /* Приём `flang/test/missing.test.mjs` — тот же, что стоял здесь у постусловия,
     и по той же причине: недостача записана в `flang/proof/SPEC.md`, и список
     недостач обязан быть правдой. `дано` объявляет имя с типом, и тип этот не
     сверяется ни с чем: `«Несуществующий»` проходит молча.

     Цель теоремы (`утверждаем`) сюда не входит и недостачей не является: она
     обязана совпадать с постусловием слово в слово, иначе `FLANG_PROOF_CLAIM_
     MISMATCH`, а без постусловия вовсе — `FLANG_PROOF_NO_GOAL`. Типизируется
     она, значит, вместе с постусловием — чужой проверкой, но полностью.

     Починят `дано` — тест покраснеет и заставит убрать запись из SPEC. */
  const { коды, тексты } = типы(
    "модуль «М»\n\nтип «Светофор»\n  вариант «Красный»\n\n"
      + "тотальная функция «Штраф»\n  принимает свет: «Светофор»\n  возвращает число\n"
      + "  для всех свет обеспечивает «штраф неотрицателен» результат не меньше 0\n"
      + "  пример «красный»\n    дано свет равно вариант «Красный»\n    ожидается 500\n"
      + "  разбор свет\n    случай вариант «Красный»\n      то 500\n\n"
      + "теорема «штраф неотрицателен»\n  дано свет: «Несуществующий»\n"
      + "  утверждаем результат не меньше 0\n  индукция по свет\n"
      + "    случай вариант «Красный»\n      то по примеру «красный»\n  следовательно доказано\n",
  )
  assert.deepEqual(
    коды,
    [],
    `типизатор заговорил о «дано» теоремы — недостача починена, уберите запись из flang/proof/SPEC.md: ${тексты.join(" | ")}`,
  )
})

