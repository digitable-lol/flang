test("теорема новой формы едет своим ключом, а не в наследие", () => {
  const программа = parse(СТОПКА, "стопка.flang")
  assert.equal(программа.theorems.length, 1)
  assert.equal(
    (программа.legacy ?? []).filter((з) => з?.construct === "theorem").length,
    0,
    "теорема новой формы не должна попадать в legacy",
  )
  const теорема = программа.theorems[0]
  assert.equal(теорема.kind, "theorem")
  assert.equal(теорема.name, "высота неотрицательна")
  assert.equal(теорема.qed, true)
  assert.deepEqual(теорема.vars.map((п) => п.name), ["стопка"])
  assert.equal(теорема.induction.param, "стопка")
  assert.deepEqual(
    теорема.induction.cases.map((с) => с.pattern.name),
    ["Пусто", "Звено"],
    "случаев столько же, сколько конструкторов объявленной суммы",
  )
  assert.deepEqual(
    теорема.induction.cases.flatMap((с) => с.steps.map((ш) => ш.by.rule)),
    ["example", "hypothesis", "property"],
  )
})

