/** Ведомость программы из текста — тем же путём, каким её строит оболочка. */
async function ведомость(исходник) {
  const программа = await loadProgramFromSource(исходник, "ведомость.flang")
  const внешнее = await externalChecks(программа)
  return { программа, внешнее, итог: proofLedger(программа, внешнее.results) }
}

