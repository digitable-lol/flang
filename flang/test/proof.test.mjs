/**
 * Расхождения ведомости с тем, что вернули проверки.
 *
 * Возвращает список претензий, а не бросает: список нужен и корпусной сверке (она
 * обязана назвать ВСЕ расхождения, а не первое), и проверке самой сверки на
 * порченой ведомости.
 *
 * Считается здесь всё заново и по-другому: из `guards` берутся имена через
 * `Set`, из `cycles` — плоский список, из `checked` — длины. Совпасть с
 * ведомостью это обязано числом, а не тем, что обе стороны позвали одну функцию.
 */
export function расхождения(итог, результаты) {
  const жалобы = []
  const тотальность = результаты.totality
  const имена = (список) => new Set((список ?? []).map((запись) => запись.from))
  const вЦикле = new Set((тотальность.cycles ?? []).flat())
  const сторожимые = new Set([...имена(тотальность.guards), ...имена(тотальность.descents)])
  const структурные = new Set([...имена(тотальность.structures)].filter((имя) => !сторожимые.has(имя)))
  const мест = (тотальность.guards ?? []).length + (тотальность.descents ?? []).length

  const тотальных = итог.functions.filter((запись) => запись.total === true)
  const под = (носитель) => тотальных.filter((запись) => запись.carrier === носитель).length

  /* Носитель у каждой тотальной функции ровно один и он назван. Ноль
     неназванных — единственное значение, при котором ведомость полна. */
  const безНосителя = тотальных.filter((запись) => запись.carrier === null)
  if (безНосителя.length > 0) {
    жалобы.push(`носитель не назван у ${безНосителя.length}: ${безНосителя.map((з) => з.name).join(", ")}`)
  }
  if (итог.totals.unaccounted !== безНосителя.length) {
    жалобы.push(`итог насчитал ${итог.totals.unaccounted} без носителя, а строк таких ${безНосителя.length}`)
  }

  /* Композиция — это ровно «нет в цикле». Не «нет сторожа» и не «нет
     структуры»: функция без рекурсии не могла попасть ни в один из трёх
     остальных списков, и подменять признак значило бы прятать расхождение. */
  const ожидаемо = {
    composition: тотальных.filter((запись) => !вЦикле.has(запись.name)).length,
    structure: тотальных.filter((запись) => структурные.has(запись.name)).length,
    /* Точный шаг — свой список анализа, а не подвид стережённого: у него нет
       сторожа, и посчитать его вместе со сторожимыми значило бы потерять ровно
       ту разницу, ради которой заведён точный натуральный тип. */
    exact: тотальных.filter((запись) => имена(тотальность.exact).has(запись.name)).length,
    step: тотальных.filter((запись) => имена(тотальность.guards).has(запись.name)).length,
    measure: тотальных.filter((запись) => имена(тотальность.descents).has(запись.name)).length,
  }
  for (const носитель of Object.keys(ожидаемо)) {
    if (под(носитель) !== ожидаемо[носитель]) {
      жалобы.push(`носитель «${носитель}»: в ведомости ${под(носитель)}, у анализа ${ожидаемо[носитель]}`)
    }
    if (итог.totals.carriers[носитель] !== под(носитель)) {
      жалобы.push(`итог по «${носитель}» ${итог.totals.carriers[носитель]} не равен числу строк ${под(носитель)}`)
    }
  }
  if (под("composition") + под("structure") + под("exact") + под("step") + под("measure") + безНосителя.length !== тотальных.length) {
    жалобы.push(`носители не покрывают тотальные: ${тотальных.length} строк`)
  }

  /* Сторож считается МЕСТАМИ, а не функциями: «Поиск в диапазоне» стережётся в
     двух вызовах, и число функций про цену обещания не говорит. */
  if (итог.totals.guardSites !== мест) {
    жалобы.push(`сторожей в ведомости ${итог.totals.guardSites} мест, у анализа ${мест}`)
  }
  const сСторожем = тотальных.filter((запись) => запись.guardSites > 0).length
  if (сСторожем !== сторожимые.size) {
    жалобы.push(`со сторожем в ведомости ${сСторожем} функций, у анализа ${сторожимые.size}`)
  }

  /* Законы: сетка — это `checked`, вера — `assumed`, и ни одна запись не имеет
     права исчезнуть по дороге или удвоиться. */
  const посчитано = ["monoid", "monad", "iso", "sets"]
    .reduce((сумма, ключ) => сумма + (результаты[ключ]?.checked?.length ?? 0), 0)
  const наВеру = ["monoid", "monad", "iso", "sets"]
    .reduce((сумма, ключ) => сумма + (результаты[ключ]?.assumed?.length ?? 0), 0)
  if (итог.laws.length !== посчитано) жалобы.push(`законов на сетке ${итог.laws.length}, у модулей ${посчитано}`)
  if (итог.assumed.length !== наВеру) жалобы.push(`на веру ${итог.assumed.length}, у модулей ${наВеру}`)
  if (итог.totals.laws.grid !== итог.laws.length) жалобы.push("итог по законам не равен числу строк")
  if (итог.totals.laws.assumed !== итог.assumed.length) жалобы.push("итог по вере не равен числу строк")

  /* Размер сетки обязан быть назван и быть положительным: «сетка» без числа —
     это ровно то «проверено», от которого ведомость и заводилась. */
  for (const закон of итог.laws) {
    if (!Number.isInteger(закон.grid?.values) || закон.grid.values <= 0) {
      жалобы.push(`у закона «${закон.name}» не назван размер сетки`)
    }
    if (!Number.isInteger(закон.grid?.limit) || закон.grid.limit < закон.grid.values) {
      жалобы.push(`у закона «${закон.name}» предел сетки меньше самой сетки`)
    }
  }
  return жалобы
}

test("ведомость сходится с анализом на всём корпусе .flang", async (t) => {
  let сведено = 0
  let безВедомости = 0
  for (const путь of ФАЙЛЫ) {
    const программа = await loadProgram(join(корень, путь))
    const внешнее = await externalChecks(программа)
    if (внешнее.diagnostics.some((беда) => беда?.severity !== "warning")) {
      безВедомости += 1
      continue
    }
    const итог = proofLedger(программа, внешнее.results)
    assert.deepEqual(расхождения(итог, внешнее.results), [], `${путь}: ведомость разошлась с анализом`)
    сведено += 1
  }
  /* Охват печатается: сверка, которая молча схлопнулась к трём файлам, зеленела
     бы ровно так же (тот же приём, что в flang/test/corpus.mjs). */
  t.diagnostic(`ведомостей сведено: ${сведено}, файлов без ведомости: ${безВедомости}, всего ${ФАЙЛЫ.length}`)
  assert.equal(сведено, ФАЙЛЫ.length, "корпус обязан сводиться целиком")
})

test("сверка умеет краснеть: изъятая строка сторожа ловится", async () => {
  const { внешнее, итог } = await ведомость(ФАКТОРИАЛ)
  assert.deepEqual(расхождения(итог, внешнее.results), [], "исходная ведомость обязана быть сведена")

  /* Изъятие: у функции пропал сторож — ровно то, что случится, если ведомость
     перестанет читать `guards`. Число мест сходится, а носитель — нет. */
  const порченая = {
    ...итог,
    functions: итог.functions.map((строка) => строка.name === "Факториал"
      ? { ...строка, carrier: "composition", guardSites: 0 }
      : строка),
    totals: { ...итог.totals, carriers: { ...итог.totals.carriers, step: 0, composition: итог.totals.carriers.composition + 1 }, guardSites: 0 },
  }
  const жалобы = расхождения(порченая, внешнее.results)
  assert.ok(жалобы.length > 0, "сверка не заметила изъятого сторожа — значит она не смотрит")
  assert.ok(жалобы.some((жалоба) => жалоба.includes("step")), жалобы.join("; "))
  assert.ok(жалобы.some((жалоба) => жалоба.includes("сторожей")), жалобы.join("; "))
})

test("сверка умеет краснеть: изъятый закон ловится", async () => {
  const { внешнее, итог } = await ведомость(ИЗОМОРФИЗМ_С_ТЕЛОМ)
  assert.deepEqual(расхождения(итог, внешнее.results), [])
  assert.equal(итог.laws.length, 1)

  const порченая = { ...итог, laws: [], totals: { ...итог.totals, laws: { ...итог.totals.laws, grid: 0 } } }
  assert.ok(расхождения(порченая, внешнее.results).length > 0, "исчезнувший закон обязан быть замечен")
})

