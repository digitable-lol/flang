async function файл(имя, исходник) {
  const путь = join(песочница, имя)
  await writeFile(путь, исходник, "utf8")
  return путь
}

test("check без ключа печатает то же, что печатал: --proof ничего не заменил", async () => {
  const путь = await файл("шаг.flang", ФАКТОРИАЛ)
  const без = await run(process.execPath, [cli, "check", путь])
  const машиной = await run(process.execPath, [cli, "check", путь, "--proof", "--json"])
  const { proof, ...остальное } = JSON.parse(машиной.stdout)
  assert.ok(proof !== undefined, "--json обязан отдать ведомость полем «proof»")
  /* Побайтово: поля, порядок полей и перевод строки — всё, на что мог опереться
     чужой скрипт. */
  assert.equal(`${JSON.stringify(остальное)}\n`, без.stdout)
  assert.ok(!без.stdout.includes("proof"), "без ключа о ведомости не должно быть и слова")
})

test("check --proof печатает ведомость человеку, а с --json — машине", async () => {
  const путь = await файл("мера.flang", МЕРА)
  const человеку = await run(process.execPath, [cli, "check", путь, "--proof"])
  assert.match(человеку.stdout, /── ведомость доказательства модуля «Мера» ──/u)
  assert.match(человеку.stdout, /доказано объявленной мерой: убывает «б»/u)
  assert.ok(!человеку.stdout.trimStart().startsWith("{"), "человеку — словами, а не JSON")

  const машине = await run(process.execPath, [cli, "check", путь, "--proof", "--json"])
  const итог = JSON.parse(машине.stdout)
  assert.equal(итог.proof.ledger, 1)
  assert.equal(итог.proof.totals.carriers.measure, 1)
})

