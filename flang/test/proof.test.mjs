  assert.equal(и.total, 2199, "тотальных")
  assert.equal(и.ordinary, 603, "обычных")
  assert.equal(и.carriers.composition, 1910, "несёт композиция: рекурсии нет")
  assert.equal(и.carriers.structure, 205, "несёт структура")
