/**
 * Ведомость доказательства: `flang check --proof`.
 *
 * Ведомость — это отчёт, а отчёт врёт молча. Своих чисел у неё нет ни одного:
 * всё, что она печатает, посчитал анализ (`checkTotality`) и модули законов
 * (`monoid.mjs`, `monad.mjs`, `iso.mjs`, `sets.mjs`). Значит и проверять надо не
 * «напечаталось что-то», а РОВНО ДВЕ ВЕЩИ, каждая из которых способна разойтись
 * тихо:
 *
 *   1. ВЕДОМОСТЬ СХОДИТСЯ С АНАЛИЗОМ. Каждая тотальная функция названа ровно
 *      одним носителем, и число функций под каждым носителем равно тому, что
 *      анализ вернул в `cycles`, `structures`, `guards` и `descents`; сторожа
 *      сосчитаны по местам, а не по функциям; законы на сетке — это в точности
 *      `checked`, а «на веру» — в точности `assumed`. Проверяется на всём
 *      корпусе, файл за файлом (`расхождения`), и она же проверяется на
 *      НАРОЧНО ПОРЧЕННОЙ ведомости — иначе про зелёный цвет нельзя сказать, от
 *      чего он: от сходимости или от того, что сверка ничего не смотрит.
 *
 *   2. СЛОВА НЕ ПУТАЮТСЯ. «Доказано» стоит только там, где утверждение про ВСЕ
 *      входы; про сетку не сказано ни «доказано», ни «проверено» — сказано
 *      «сетка N значений: нарушений не найдено». Слова «проверено» в ведомости
 *      нет вовсе, и это проверяется буквально: оно и есть то самое слово,
 *      которое читается двумя способами (docs/overview.ru.md).
 *
 * И третье, без чего ведомость нельзя было бы добавлять: `flang check` БЕЗ
 * ключа печатает то же, что печатал. Сверяется побайтово с выводом
 * `--proof --json` без поля `proof`.
 *
 * Запуск: node --test flang/test/proof.test.mjs
 */
