/**
 * Тесты доказанного типа числа — второй отметки `markProven`.
 *
 * ЧТО ЭТО. `fl_add` в рантайме — межмодульный вызов: два значения по 32 байта
 * туда, результат через указатель обратно, ветвь отказа посреди горячего кода.
 * Там, где вывод типов доказал тип обоих операндов, узел помечается `числовая`,
 * и печать считает выражение прямо на месте.
 *
 * ЧТО ПРИ ЭТОМ НЕ СНИМАЕТСЯ — сама сверка тегов. Она печатается одним `if` в
 * теле вызывающего, и это не перестраховка: граница входа сверяет НЕ ВСЁ. Вид
 * `неизвестно` — параметр полиморфизма и значение-функцию — она пропускает,
 * потому что сверять их не с чем, и через эту дверь чужое значение доезжает до
 * доказанного места. Пока сверка была снята совсем, корпус отвечал
 * `1.32e-309` там, где обязан был отвечать FLANG_TYPE.
 *
 * Отсюда правило для всякой такой правки: снятая проверка тега даёт не отказ, а
 * НЕВЕРНЫЙ ОТВЕТ — `.as.number` на значении со строковым тегом читает соседнее
 * поле объединения. Значит каждая дыра в доказательстве — своя проверка:
 *
 *   ДОКАЗАНО     оба операнда объявлены числом — выражение вместо вызова.
 *   НЕ ДОКАЗАНО  тип может нести «ничто» (`иногда является`) или неизвестен —
 *                отметки нет, вызов помощника остаётся целиком.
 *   ОТВЕТ ТОТ ЖЕ NaN, минус ноль, бесконечность, остаток и процент считаются
 *                ровно теми же выражениями, что стоят в теле помощника.
 *   ГРАНИЦА      чужое значение снаружи отказывает тем же кодом и текстом:
 *                через дверь входа — где она сверяет, и сверкой самой печати —
 *                где не сверяет (параметр полиморфизма).
 *
 * Запуск: node --test flang/test/proven-number.test.mjs
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { after, test } from "node:test"

import { emitC } from "../src/emit/c.mjs"
import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkArguments, checkTypes, markProven } from "../src/types.mjs"

const МОДУЛЬ = "модуль «М»\n\n"
const разобрать = (исходник) => parse(МОДУЛЬ + исходник)
const отмечено = (исходник) => checkTypes(разобрать(исходник)).числа.size

/** Весь напечатанный C программы одной строкой. */
const напечатать = (исходник) =>
  emitC(markProven(разобрать(исходник))).files.map((файл) => файл.content).join("\n")

/** Сколько мест двуместной операции в программе всего. */
function мест(исходник) {
  let счёт = 0
  const обойти = (узел) => {
    if (Array.isArray(узел)) { for (const э of узел) обойти(э); return }
    if (узел === null || typeof узел !== "object") return
    if (узел.kind === "binary" && узел.op !== "eq" && узел.op !== "neq" && узел.op !== "concat") счёт += 1
    for (const [к, з] of Object.entries(узел)) {
      if (к === "span" || к === "meta") continue
      if (з !== null && typeof з === "object") обойти(з)
    }
  }
  обойти(разобрать(исходник).functions)
  return счёт
}

/* ─────────────────── доказано ─────────────────── */

test("объявленные числом операнды: отметка стоит на всех местах", () => {
  const исходник = `функция «Ф»
  принимает а: число, б: число
  возвращает число
  (а плюс б) умножить на (а минус б)
`
  assert.equal(мест(исходник), 3, "мест двуместной операции стало другое число")
  assert.equal(отмечено(исходник), 3, "доказаны не все три места")
})

test("доказанное место печатается выражением, а вызова помощника не остаётся", () => {
  const код = напечатать(`функция «Ф»
  принимает а: число, б: число
  возвращает число
  а плюс б
`)
  assert.match(код, /fl_number\(a\.as\.number \+ b\.as\.number\)/u, "выражение не напечатано")
  assert.ok(!/fl_add\(ctx/u.test(код), "вызов fl_add остался там, где тип доказан")
})

test("вложенная арифметика складывается в одно выражение, а не в две упаковки", () => {
  const код = напечатать(`функция «Ф»
  принимает а: число, б: число, ц: число
  возвращает число
  (а плюс б) умножить на ц
`)
  assert.match(код, /fl_number\(\(a\.as\.number \+ b\.as\.number\) \* c\.as\.number\)/u, "скобки или вложение разошлись")
})

test("числовой литерал печатается числом, а не упаковкой с распаковкой", () => {
  const код = напечатать(`функция «Ф»
  принимает а: число
  возвращает число
  а плюс 2
`)
  assert.match(код, /fl_number\(a\.as\.number \+ 2\.0\)/u, "литерал завернули в fl_number зря")
})

test("сравнение порядка печатается знаком C, а не вызовом fl_lte", () => {
  const код = напечатать(`функция «Ф»
  принимает а: число, б: число
  возвращает признак
  а не больше б
`)
  assert.match(код, /fl_flag\(a\.as\.number <= b\.as\.number\)/u, "знак сравнения не напечатан")
  assert.ok(!/fl_lte\(ctx/u.test(код), "вызов fl_lte остался там, где тип доказан")
})

test("остаток зовёт fmod и тянет math.h, а процент сохраняет порядок множителей", () => {
  const остаток = напечатать(`функция «Ф»
  принимает а: число, б: число
  возвращает число
  а остаток от б
`)
  assert.match(остаток, /fl_number\(fmod\(a\.as\.number, b\.as\.number\)\)/u, "остаток напечатан не fmod")
  assert.match(остаток, /#include <math\.h>/u, "fmod напечатан, а math.h не подключён")
  const процент = напечатать(`функция «Ф»
  принимает а: число, б: число
  возвращает число
  а процентов от б
`)
  /* Порядок ядра: (процент / 100) * значение. Переставить множители нельзя —
     меняется последний бит мантиссы. */
  assert.match(процент, /fl_number\(\(a\.as\.number \/ 100\.0\) \* b\.as\.number\)/u, "порядок множителей переставлен")
})

/* ─────────────────── НЕ доказано: здесь проверка обязана остаться ─────────────────── */

test("«иногда является число» не доказано: значение может быть «ничто»", () => {
  /* Тип носит число И «ничто», а `.as.number` на теге FL_NOTHING прочитал бы
     чужое поле объединения. Проверка обязана остаться, и это единственное
     место, где доказательство отличается от «тип назван числом». */
  const исходник = `объект «Мера»
  «сколько» иногда является число

функция «Ф»
  принимает м: «Мера»
  возвращает число
  (м.«сколько») плюс 1
`
  assert.equal(мест(исходник), 1, "место двуместной операции пропало")
  assert.equal(отмечено(исходник), 0, "необязательное число посчитали доказанным")
  assert.match(напечатать(исходник), /fl_add\(ctx/u, "вызов fl_add сняли там, где значение может быть «ничто»")
})

test("операнд неизвестного типа не доказан", () => {
  const исходник = `функция «Ф»
  принимает а: число
  возвращает число
  а плюс («Нет такой» от а)
`
  assert.equal(отмечено(исходник), 0, "неизвестный тип посчитали доказанным")
})

/* ─────────────────── ответ тот же ─────────────────── */

test("выражения совпадают с телами помощников рантайма дословно", () => {
  /* Сверяется не «похоже», а буква в букву: побайтовое совпадение ответов
     держится на том, что порядок действий и округление те же. */
  const тела = {
    add: "left.as.number + right.as.number",
    sub: "left.as.number - right.as.number",
    mul: "left.as.number * right.as.number",
    div: "left.as.number / right.as.number",
  }
  const записи = { add: "плюс", sub: "минус", mul: "умножить на", div: "делить на" }
  for (const [операция, тело] of Object.entries(тела)) {
    const код = напечатать(`функция «Ф»
  принимает left: число, right: число
  возвращает число
  left ${записи[операция]} right
`)
    assert.ok(код.includes(`fl_number(${тело})`), `«${записи[операция]}»: выражение разошлось с рантаймом`)
  }
})

test("вычислитель и печать отвечают одинаково на NaN, минус нуле и бесконечности", () => {
  /* Отметка меняет ТЕКСТ печати, а не смысл программы. Вычислитель отметку не
     читает вовсе, поэтому его ответы — независимая мера того, что смысл цел. */
  const программа = разобрать(`функция «Ноль на ноль»
  возвращает число
  0 делить на 0

функция «Минус ноль остаток»
  возвращает число
  (0 минус 0.0) остаток от 1

функция «Один на ноль»
  возвращает число
  1 делить на 0
`)
  const отмеченная = markProven(программа)
  for (const имя of ["Ноль на ноль", "Минус ноль остаток", "Один на ноль"]) {
    assert.deepEqual(
      evaluate(отмеченная, имя, {}),
      evaluate(программа, имя, {}),
      `«${имя}»: отметка изменила ответ вычислителя`,
    )
  }
})

/* ─────────────────── граница входа ─────────────────── */

test("чужой тип снаружи ловится дверью входа, а не арифметикой", () => {
  /* Вот на чём стоит вся правка: значения, пришедшие снаружи, сверяются с
     объявленными типами ДО вызова (`fl_check_entry` в рантайме, `checkArguments`
     здесь). Если бы не сверялись, снятие проверки в `fl_add` меняло бы отказ на
     неверный ответ. */
  const программа = разобрать(`функция «Ф»
  принимает а: число
  возвращает число
  а плюс 1
`)
  const итог = checkArguments(программа, "Ф", { а: "строка" })
  assert.equal(итог.ok, false, "дверь входа пропустила строку в параметр числа")
  assert.equal(итог.diagnostics[0].code, "FLANG_TYPE", "код отказа двери входа сменился")
})

/* ─────────────────── то же самое собранным C ─────────────────── */

const рабочий = mkdtempSync(join(tmpdir(), "flang-proven-"))
after(() => rmSync(рабочий, { recursive: true, force: true }))

/** Собрать напечатанное тем же строгим набором, каким его собирает бэкенд. */
function собрать(исходник, имя) {
  const каталог = join(рабочий, имя)
  const напечатанное = emitC(markProven(разобрать(исходник)))
  execFileSync("mkdir", ["-p", каталог])
  for (const файл of напечатанное.files) writeFileSync(join(каталог, файл.path), файл.content, "utf8")
  assert.ok(readdirSync(каталог).length > 0, "печать не дала ни одного файла")
  const исходники = напечатанное.files.filter((ф) => ф.path.endsWith(".c")).map((ф) => ф.path)
  execFileSync("cc", ["-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O2",
    ...исходники, "-o", "flang_cli", "-lm", "-lpthread"], { cwd: каталог, encoding: "utf8" })
  return join(каталог, "flang_cli")
}

/** Один процесс на все запросы: сборка дорога, запрос дёшев. */
const спросить = (прогонщик, запросы) =>
  execFileSync(прогонщик, {
    input: `${запросы.map((з) => JSON.stringify(з)).join("\n")}\n`,
    encoding: "utf8",
  }).split("\n").filter((с) => с.length > 0).map((с) => JSON.parse(с))

test("собранный C: чужой тип отказывает дверью входа, а не даёт мусор", () => {
  /* Вот ради чего всё остальное. Если бы значение чужого типа доехало до
     доказанного места, `.as.number` прочитал бы чужое поле объединения и выдал
     ЧИСЛО — не отказ. Здесь это проверено прогоном, а не рассуждением: во всех
     четырёх случаях ответ обязан быть FLANG_TYPE от двери входа. */
  const прогонщик = собрать(`функция «Прибавить»
  принимает а: число
  возвращает число
  а плюс 1
`, "dver")
  const чужие = [{ s: "не число" }, null, { l: [] }, { r: [] }]
  const ответы = спросить(прогонщик, [
    { fn: "Прибавить", args: [{ n: "41" }] },
    ...чужие.map((значение) => ({ fn: "Прибавить", args: [значение] })),
  ])
  assert.deepEqual(ответы[0], { ok: true, value: { n: "42" } }, "число посчиталось неверно")
  for (const [номер, ответ] of ответы.slice(1).entries()) {
    assert.equal(ответ.ok, false, `${JSON.stringify(чужие[номер])}: чужой тип посчитался как число`)
    assert.equal(ответ.code, "FLANG_TYPE", `${JSON.stringify(чужие[номер])}: код отказа сменился`)
    assert.match(ответ.message, /не соответствует типу число/u, "отказал не тот, кто должен")
  }
})

test("собранный C: чужое значение сквозь параметр полиморфизма ловит сама печать", () => {
  /* ЗДЕСЬ ПРАВКА ЧУТЬ НЕ ОБМЕНЯЛА ОТКАЗ НА МУСОР, и нашлось это прогоном
     корпуса, а не рассуждением. Граница входа сверяет НЕ ВСЁ: вид `неизвестно`
     — параметр полиморфизма и значение-функцию — она пропускает, потому что
     сверять их не с чем. Через эту дверь строка доезжает до места, где тип
     «доказан»: `«Отобразить»` объявлена от «А», список [1, "два"] дверь
     пропускает, а внутри `«Удвоить»` параметр объявлен числом.

     Улика в цифрах: пока сверка тегов была снята совсем, ответом было
     `[2, 1.32e-309]` — прочитанные как double биты указателя на строку. Стало —
     тот же FLANG_TYPE, что и был до всей правки, слово в слово. */
  const прогонщик = собрать(`тотальная функция «Удвоить»
  принимает х: число
  возвращает число
  х плюс х

тотальная функция «Отобразить» от «А» и «Б»
  принимает ф: функция из «А» в «Б», элементы: список «А»
  возвращает список «Б»
  отобразить элементы как эл → ф от эл

тотальная функция «Удвоить всё»
  принимает элементы: список числа
  возвращает список числа
  «Отобразить» от (функция «Удвоить») и элементы
`, "poly")
  const ответы = спросить(прогонщик, [
    { fn: "Отобразить", args: [{ v: "Удвоить", f: [] }, { l: [{ n: "1" }, { n: "2" }] }] },
    { fn: "Отобразить", args: [{ v: "Удвоить", f: [] }, { l: [{ n: "1" }, { s: "два" }] }] },
  ])
  assert.deepEqual(ответы[0], { ok: true, value: { l: [{ n: "2" }, { n: "4" }] } }, "числа отобразились неверно")
  assert.equal(ответы[1].ok, false, "строка сквозь параметр полиморфизма посчиталась как число")
  assert.equal(ответы[1].code, "FLANG_TYPE", "код отказа сменился")
  assert.equal(
    ответы[1].message,
    "операция «add» допустима только для чисел, получено строка и строка",
    "текст отказа обязан быть тем же, что печатает сам помощник",
  )
})

test("собранный C: «ничто» в необязательном поле ловит сам помощник", () => {
  /* Дверь входа тут молчит законно: поле объявлено необязательным, и «ничто» в
     нём — законное значение типа. Поймать обязана арифметика, и она ловит,
     потому что это место НЕ доказано и вызов `fl_add` остался. */
  const прогонщик = собрать(`объект «Мера»
  «сколько» иногда является число

функция «Мерой»
  принимает м: «Мера»
  возвращает число
  (м.«сколько») плюс 1
`, "mera")
  const ответы = спросить(прогонщик, [
    { fn: "Мерой", args: [{ r: [["сколько", { n: "7" }]] }] },
    { fn: "Мерой", args: [{ r: [["сколько", null]] }] },
  ])
  assert.deepEqual(ответы[0], { ok: true, value: { n: "8" } }, "число в поле посчиталось неверно")
  assert.equal(ответы[1].ok, false, "«ничто» в поле посчиталось как число")
  assert.equal(ответы[1].code, "FLANG_TYPE", "код отказа помощника сменился")
  assert.match(ответы[1].message, /допустима только для чисел, получено ничто/u, "текст отказа помощника сменился")
})

test("напечатанный C сверяет границу входа тем же местом", () => {
  const код = напечатать(`функция «Ф»
  принимает а: число
  возвращает число
  а плюс 1
`)
  assert.match(код, /_entry_params\[\]/u, "таблицы границы входа в напечатанном коде нет")
  assert.match(код, /FL_TYPE_NUMBER/u, "объявленный тип параметра в таблицу не попал")
})
