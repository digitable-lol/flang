/**
 * ПЕРЕПИСЬ РАБОЧЕГО ПУТИ: сколько JavaScript ввозит `flang check` НА САМОМ ДЕЛЕ.
 *
 * ── Зачем этот файл ─────────────────────────────────────────────────────────
 *
 * Про изъятие эталона из рабочего пути в дереве сказано трижды — в шапке
 * `flang/src/self.mjs`, в объяснении у таблицы законов в `flang/bin/flang.mjs`
 * и утверждениями «ЭТАЛОНА В ПУТИ НЕТ» в `flang/test/self-cli.test.mjs`. Все
 * три меряют ТЕКСТ: ищут строку `import` в одном файле. Текстом же меряется и
 * обратное — «слой на flang ввозится». Но ни одно из них не отвечает на
 * вопрос, который задаёт владелец: СКОЛЬКО ЕГО ОСТАЛОСЬ.
 *
 * Ответ текстом получить нельзя. Ввоз бывает отложенным (`await import` внутри
 * ветки), бывает через третий файл, и бывает мёртвым — записанным в тексте, но
 * не исполняемым. Поэтому здесь мерится ПРОГОНОМ: команда `flang check`
 * запускается настоящим процессом под перехватчиком загрузки модулей, и в
 * список попадает ровно то, что node действительно загрузил.
 *
 * ── Что именно утверждается ─────────────────────────────────────────────────
 *
 *   1. ПРОБА РАБОТАЕТ. В списке обязан быть сам `flang/bin/flang.mjs` и обязан
 *      быть хоть один модуль из `flang/src`. Перехватчик, который ничего не
 *      поймал, дал бы пустой список — и все утверждения ниже прошли бы молча.
 *      Это то самое «отсутствие в красных значит „не спрашивали“».
 *   2. ЭТАЛОН ВЕДОМОСТИ НЕ ЗАГРУЖАЕТСЯ ВОВСЕ. `flang/src/proof.mjs` не попадает
 *      в процесс ни одной строкой — ни прямым ввозом, ни через третий файл.
 *      Утверждение сильнее того, что стоит в `self-cli.test.mjs`: там сказано,
 *      что его не ввозит ОДИН файл, здесь — что его не ввозит НИКТО.
 *   3. СЛОЙ НА FLANG ЗАГРУЖАЕТСЯ. `flang/src/self.mjs` и мост
 *      `flang/src/bridge.mjs` в списке есть. Без этого утверждение 2 зеленело
 *      бы и у команды, которая ведомости не считает вовсе.
 *   4. ПОТОЛОК НЕ ПОДНЯЛСЯ. Файлов и строк JavaScript в рабочем пути не больше,
 *      чем записано здесь числом. Число может только падать: каждый
 *      переключённый слой опускает его, и поднять его обратно молча нельзя.
 *
 * ── Чего здесь НЕ утверждается, и почему ────────────────────────────────────
 *
 * Не утверждается, что оставшийся JavaScript «лишний». `flang/src/interpret.mjs`,
 * `parser.mjs`, `link.mjs` и `lexer.mjs` — это то, ЧЕМ исполняется слой на
 * flang; выкинуть их значит выкинуть машину, на которой едет близнец. Их место
 * в списке — не долг, а основание. Долг здесь — те слои, у которых близнец
 * сверен побайтово и всё-таки не зовётся.
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, relative } from "node:path"
import test from "node:test"
import { fileURLToPath, pathToFileURL } from "node:url"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/**
 * Программа, на которой мерится путь.
 *
 * Взята с ОБЪЯВЛЕННОЙ МЕРОЙ и постусловиями: такая проходит анализ
 * завершаемости, обязательства, ядро доказательств и поиск на сетке, то есть
 * поднимает в процесс всё, что рабочий путь умеет поднимать. Программа без
 * утверждений не позвала бы ни ядро, ни ведомость, и перепись вышла бы короче
 * настоящей — то есть польстила бы.
 */
const ПРОГРАММА = "flang/examples/measure/euclid.flang"

/**
 * Перепись: что node загрузил за один настоящий прогон `flang check --proof`.
 *
 * Перехватчик ставится через `register()` из `node:module` — тем же способом,
 * каким это делает любой сторонний загрузчик. Он пишет URL каждого загруженного
 * модуля в файл; путь к файлу вшивается в текст перехватчика, а не едет
 * переменной среды: поток загрузчика среды родителя не наследует.
 */
function перепись() {
  const каталог = mkdtempSync(join(tmpdir(), "flang-perepis-"))
  const списокФайл = join(каталог, "spisok.txt")
  const перехватчик = join(каталог, "perehvatchik.mjs")
  writeFileSync(
    перехватчик,
    [
      'import { appendFileSync } from "node:fs"',
      `const КУДА = ${JSON.stringify(списокФайл)}`,
      "export async function load(url, context, nextLoad) {",
      '  if (url.startsWith("file:") && (url.endsWith(".mjs") || url.endsWith(".js"))) appendFileSync(КУДА, url + "\\n")',
      "  return nextLoad(url, context)",
      "}",
      "",
    ].join("\n"),
  )
  writeFileSync(списокФайл, "")

  /* Адрес перехватчика едет полным `file:`-URL: ставится он из `data:`-модуля,
     а у того нет каталога, относительно которого разрешать путь. */
  const ставит =
    "import { register } from 'node:module';" +
    `register(${JSON.stringify(pathToFileURL(перехватчик).href)});`
  execFileSync(
    process.execPath,
    ["--import", `data:text/javascript,${encodeURIComponent(ставит)}`, "flang/bin/flang.mjs", "check", "--proof", ПРОГРАММА],
    { cwd: корень, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  )

  const свои = new Set()
  for (const строка of readFileSync(списокФайл, "utf8").split("\n")) {
    if (строка === "") continue
    const путь = fileURLToPath(строка)
    if (!путь.startsWith(корень) || путь.includes("node_modules")) continue
    свои.add(relative(корень, путь))
  }
  return [...свои].sort()
}

const загружено = перепись()
const строк = (имя) => readFileSync(join(корень, имя), "utf8").split("\n").length
const всегоСтрок = загружено.reduce((сумма, имя) => сумма + строк(имя), 0)

/* ─────────────────────────────── утверждения ─────────────────────────────── */

test("ПРОБА РАБОТАЕТ: перехватчик поймал сам вход и слои компилятора", () => {
  assert.ok(
    загружено.includes("flang/bin/flang.mjs"),
    `перепись не поймала даже вход команды — поймано ${загружено.length} файлов, и все утверждения ниже пусты`,
  )
  const слои = загружено.filter((имя) => имя.startsWith("flang/src/"))
  assert.ok(слои.length >= 20, `модулей из flang/src поймано ${слои.length} — проба меряет не тот процесс`)
})

test("ЭТАЛОН ВЕДОМОСТИ НЕ ЗАГРУЖАЕТСЯ: proof.mjs не попадает в процесс ни через кого", () => {
  assert.ok(
    !загружено.includes("flang/src/proof.mjs"),
    "`flang/src/proof.mjs` снова оказался в рабочем пути — ведомость считает JavaScript",
  )
})

test("СЛОЙ НА FLANG ЗАГРУЖАЕТСЯ: близнец и мост в процессе есть", () => {
  assert.ok(загружено.includes("flang/src/self.mjs"), "слоя на flang в рабочем пути нет — считать ведомость некому")
  assert.ok(загружено.includes("flang/src/bridge.mjs"), "моста в рабочем пути нет — слою нечем принять данные")
})

/**
 * ПОТОЛОК. Числа записаны прогоном на 18 августа 2026 года.
 *
 * Они не «нормальные» и не «хорошие» — они ДОЛГ. Каждый переключённый слой
 * обязан их опустить, и опустить их здесь руками — часть переключения. Расти им
 * нечем: новый модуль в рабочем пути краснеет тут же.
 */
const ПОТОЛОК_ФАЙЛОВ = 36
const ПОТОЛОК_СТРОК = 34_995

test("ПОТОЛОК НЕ ПОДНЯЛСЯ: JavaScript в рабочем пути не прибавилось", (t) => {
  t.diagnostic(`рабочий путь: файлов JavaScript ${загружено.length}, строк ${всегоСтрок}`)
  t.diagnostic(загружено.join(" "))
  assert.ok(
    загружено.length <= ПОТОЛОК_ФАЙЛОВ,
    `файлов в рабочем пути ${загружено.length} против потолка ${ПОТОЛОК_ФАЙЛОВ}: ` +
      `прибавилось ${загружено.filter((имя) => !имя.startsWith("flang/")).join(", ") || "внутри flang/"}`,
  )
  assert.ok(
    всегоСтрок <= ПОТОЛОК_СТРОК,
    `строк JavaScript в рабочем пути ${всегоСтрок} против потолка ${ПОТОЛОК_СТРОК}`,
  )
})
