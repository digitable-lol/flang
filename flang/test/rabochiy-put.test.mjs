/**
 * ПЕРЕПИСЬ РАБОЧЕГО ПУТИ: сколько JavaScript ввозит `flang check` НА САМОМ ДЕЛЕ.
 *
 * ── Зачем этот файл ─────────────────────────────────────────────────────────
 *
 * Про изъятие эталона из рабочего пути в дереве сказано трижды — в шапке
 * `flang/src/self.mjs`, в объяснении у таблицы законов в `flang/bin/flang.mjs`
 * и утверждениями «ЭТАЛОНА В ПУТИ НЕТ» в `flang/test/self-cli.test.mjs`. Все
 * три меряют ТЕКСТ: ищут строку `import` в одном файле. Текстом же меряется и
 * обратное — «слой на flang ввозится». Но ни одно из них не отвечает на
 * вопрос, который задаёт владелец: СКОЛЬКО ЕГО ОСТАЛОСЬ.
 *
 * Ответ текстом получить нельзя. Ввоз бывает отложенным (`await import` внутри
 * ветки), бывает через третий файл, и бывает мёртвым — записанным в тексте, но
 * не исполняемым. Поэтому здесь мерится ПРОГОНОМ: команда `flang check`
 * запускается настоящим процессом под перехватчиком загрузки модулей, и в
 * список попадает ровно то, что node действительно загрузил.
 *
 * ── Что именно утверждается ─────────────────────────────────────────────────
 *
 *   1. ПРОБА РАБОТАЕТ. В списке обязан быть сам `flang/bin/flang.mjs` и обязан
 *      быть хоть один модуль из `flang/src`. Перехватчик, который ничего не
 *      поймал, дал бы пустой список — и все утверждения ниже прошли бы молча.
 *      Это то самое «отсутствие в красных значит „не спрашивали“».
 *   2. ЭТАЛОН ВЕДОМОСТИ НЕ ЗАГРУЖАЕТСЯ ВОВСЕ. `flang/src/proof.mjs` не попадает
 *      в процесс ни одной строкой — ни прямым ввозом, ни через третий файл.
 *      Утверждение сильнее того, что стоит в `self-cli.test.mjs`: там сказано,
 *      что его не ввозит ОДИН файл, здесь — что его не ввозит НИКТО.
 *   3. СЛОЙ НА FLANG ЗАГРУЖАЕТСЯ. `flang/src/self.mjs` и мост
 *      `flang/src/bridge.mjs` в списке есть. Без этого утверждение 2 зеленело
 *      бы и у команды, которая ведомости не считает вовсе.
 *   4. ПОТОЛОК НЕ ПОДНЯЛСЯ. Файлов и строк JavaScript в рабочем пути не больше,
 *      чем записано здесь числом. Число может только падать: каждый
 *      переключённый слой опускает его, и поднять его обратно молча нельзя.
 *
 * ── Чего здесь НЕ утверждается, и почему ────────────────────────────────────
 *
 * Не утверждается, что оставшийся JavaScript «лишний». `flang/src/interpret.mjs`,
 * `parser.mjs`, `link.mjs` и `lexer.mjs` — это то, ЧЕМ исполняется слой на
 * flang; выкинуть их значит выкинуть машину, на которой едет близнец. Их место
 * в списке — не долг, а основание. Долг здесь — те слои, у которых близнец
 * сверен побайтово и всё-таки не зовётся.
 */
