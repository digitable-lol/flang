/**
 * Программа, на которой мерится путь.
 *
 * Взята с ОБЪЯВЛЕННОЙ МЕРОЙ и постусловиями: такая проходит анализ
 * завершаемости, обязательства, ядро доказательств и поиск на сетке, то есть
 * поднимает в процесс всё, что рабочий путь умеет поднимать. Программа без
 * утверждений не позвала бы ни ядро, ни ведомость, и перепись вышла бы короче
 * настоящей — то есть польстила бы.
 */
const ПРОГРАММА = "flang/examples/measure/euclid.flang"

/**
 * Перепись: что node загрузил за один настоящий прогон `flang check --proof`.
 *
 * Перехватчик ставится через `register()` из `node:module` — тем же способом,
 * каким это делает любой сторонний загрузчик. Он пишет URL каждого загруженного
 * модуля в файл; путь к файлу вшивается в текст перехватчика, а не едет
 * переменной среды: поток загрузчика среды родителя не наследует.
 */
function перепись() {
  const каталог = mkdtempSync(join(tmpdir(), "flang-perepis-"))
  const списокФайл = join(каталог, "spisok.txt")
  const перехватчик = join(каталог, "perehvatchik.mjs")
  writeFileSync(
    перехватчик,
    [
      'import { appendFileSync } from "node:fs"',
      `const КУДА = ${JSON.stringify(списокФайл)}`,
      "export async function load(url, context, nextLoad) {",
      '  if (url.startsWith("file:") && (url.endsWith(".mjs") || url.endsWith(".js"))) appendFileSync(КУДА, url + "\\n")',
      "  return nextLoad(url, context)",
      "}",
      "",
    ].join("\n"),
  )
  writeFileSync(списокФайл, "")

  /* Адрес перехватчика едет полным `file:`-URL: ставится он из `data:`-модуля,
     а у того нет каталога, относительно которого разрешать путь. */
  const ставит =
    "import { register } from 'node:module';" +
    `register(${JSON.stringify(pathToFileURL(перехватчик).href)});`
  execFileSync(
    process.execPath,
    ["--import", `data:text/javascript,${encodeURIComponent(ставит)}`, "flang/bin/flang.mjs", "check", "--proof", ПРОГРАММА],
    { cwd: корень, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  )

  const свои = new Set()
  for (const строка of readFileSync(списокФайл, "utf8").split("\n")) {
    if (строка === "") continue
    const путь = fileURLToPath(строка)
    if (!путь.startsWith(корень) || путь.includes("node_modules")) continue
    свои.add(relative(корень, путь))
  }
  return [...свои].sort()
}

const загружено = перепись()
const строк = (имя) => readFileSync(join(корень, имя), "utf8").split("\n").length
const всегоСтрок = загружено.reduce((сумма, имя) => сумма + строк(имя), 0)

