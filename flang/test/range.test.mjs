/**
 * Уточнение числа (`нат`, `целое`) и интервальный анализ, на котором оно
 * держится.
 *
 * ── Что здесь проверяется и почему именно это ──────────────────────────────
 *
 * Уточнение числа не добавляет языку ни одного нового вида значения: значения
 * остаются IEEE-754 double, а тип говорит про диапазон. Значит и проверять надо
 * не «тип появился», а ровно те четыре утверждения, каждое из которых способно
 * оказаться неправдой молча:
 *
 *   1. УТОЧНЕНИЕ ЧТО-ТО ЗНАЧИТ. Значение вне диапазона в объявленный `нат` не
 *      проходит. Проверка тут — половина дела; вторая половина в том, что
 *      проверка эта СРАБАТЫВАЕТ, а не пропускает всё подряд, поэтому у каждого
 *      случая есть изъятие: та же программа, из которой убрано ровно то, чем
 *      она проходила, обязана покраснеть.
 *
 *   2. УТОЧНЕНИЕ НАПРАВЛЕННОЕ. `нат` годится там, где ждут `число`; `число` там,
 *      где ждут `нат`, — нет. Симметричное отношение здесь означало бы, что
 *      уточнение не значит ничего, а несимметричное не туда — что оно значит
 *      обратное.
 *
 *   3. ГРАНИЦА ВЫВОДИТСЯ, А НЕ ПРОВЕРЯЕТСЯ В РАНТАЙМЕ. `н минус 1` под
 *      проверкой `если н не больше 0` — это снова `нат`, и ни одной проверки в
 *      напечатанном коде от этого не появляется. Сумма же двух `нат` — это
 *      `число`, и отказ приходит на проверке типов. Это главное свойство всего
 *      этапа: 242 места, где `нат` производится, стоили бы 242 проверок в
 *      рантайме, а стоят нуля.
 *
 *   4. НА ПРОГРАММАХ БЕЗ УТОЧНЕНИЙ НЕ МЕНЯЕТСЯ НИЧЕГО. Проверяется отдельно и
 *      строго: диагностики корпуса сверяются с самоприменением (`self-*.test.mjs`),
 *      а здесь — что тип выражения без уточнений остался ровно `число`.
 *
 * Запуск: node --test flang/test/range.test.mjs
 */
import assert from "node:assert/strict"
import { test } from "node:test"

import { parse } from "../src/parser.mjs"
import {
  ТОЧНО,
  арифметика,
  вместимо,
  интервалЛитерала,
  объединить,
  пересечь,
  сужение,
  точныйТип,
  уточнение,
} from "../src/range.mjs"
import { checkTypes } from "../src/types.mjs"

const беды = (исходник) => checkTypes(parse(исходник, "уточнение.flang")).diagnostics
const тексты = (исходник) => беды(исходник).map((беда) => беда.message)
const чисто = (исходник) => assert.deepEqual(тексты(исходник), [], исходник)
const краснеет = (исходник, чем) => {
  const список = тексты(исходник)
  assert.ok(список.length > 0, `программа обязана быть отвергнута:\n${исходник}`)
  assert.ok(список.some((текст) => чем.test(текст)), список.join("; "))
}

