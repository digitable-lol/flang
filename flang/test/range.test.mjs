test("умножение перебирает четыре угла, а не два: иначе интервал выйдет наизнанку", () => {
  assert.deepEqual(арифметика("mul", { min: -3, max: 2 }, { min: -3, max: 2 }), { min: -6, max: 9 })
  assert.deepEqual(арифметика("mul", { min: 2, max: 3 }, { min: 4, max: 5 }), { min: 8, max: 15 })
  assert.deepEqual(арифметика("add", { min: 1, max: 2 }, { min: 10, max: 20 }), { min: 11, max: 22 })
  assert.deepEqual(арифметика("sub", { min: 1, max: 2 }, { min: 10, max: 20 }), { min: -19, max: -8 })
  assert.equal(арифметика("add", { min: ТОЧНО, max: ТОЧНО }, { min: 1, max: 1 }), null, "переполнение")
  assert.equal(арифметика("div", { min: 4, max: 4 }, { min: 2, max: 2 }), null, "деления здесь нет")
  assert.equal(арифметика("percent", { min: 4, max: 4 }, { min: 2, max: 2 }), null)
})

test("остаток берётся от делимого и требует делителя, который не ноль", () => {
  assert.deepEqual(арифметика("mod", { min: 0, max: 100 }, { min: 3, max: 3 }), { min: 0, max: 2 })
  assert.deepEqual(арифметика("mod", { min: -5, max: 5 }, { min: 3, max: 3 }), { min: -2, max: 2 })
  assert.equal(арифметика("mod", { min: 0, max: 5 }, { min: 0, max: 3 }), null, "делитель может быть нулём")
  assert.equal(арифметика("mod", { min: 0, max: 5 }, { min: -1, max: 1 }), null)
})

test("объединение и пересечение: слабейшее и сильнейшее из двух", () => {
  assert.deepEqual(объединить({ min: 1, max: 2 }, { min: 10, max: 20 }), { min: 1, max: 20 })
  assert.equal(объединить({ min: 1, max: 2 }, null), null, "пусто у одной — пусто у обоих")
  assert.deepEqual(пересечь({ min: 0, max: 20 }, { min: 10, max: 30 }), { min: 10, max: 20 })
  assert.equal(пересечь({ min: 0, max: 5 }, { min: 10, max: 30 }), null, "пустого пересечения не бывает")
  assert.deepEqual(пересечь(null, { min: 1, max: 2 }), { min: 1, max: 2 })
})

test("сужение читает узлы условия, а не выражения: два случая и ни одного больше", () => {
  const инт = (node) => (node?.kind === "literal" ? интервалЛитерала(node.value) : node?.интервал ?? null)
  const имя = (node) => (node?.kind === "var" ? node.name : null)
  const н = { kind: "var", name: "н", интервал: { min: 0, max: ТОЧНО } }
  const нуль = { kind: "literal", value: 0 }
  const условие = { kind: "binary", op: "lte", left: н, right: нуль }
  assert.deepEqual(сужение(условие, "else", инт, имя), [{ имя: "н", интервал: { min: 1, max: ТОЧНО }, устанавливает: false }])
  assert.deepEqual(сужение(условие, "then", инт, имя), [{ имя: "н", интервал: { min: -ТОЧНО, max: 0 }, устанавливает: false }])
  /* Изъятие: сдвинутое выражение границы не даёт — перенос через сдвиг верен
     для вещественных чисел, а сравнивает программа double. */
  const сдвиг = { kind: "binary", op: "sub", left: н, right: { kind: "literal", value: 1 } }
  assert.deepEqual(сужение({ kind: "binary", op: "gt", left: сдвиг, right: нуль }, "then", инт, имя), [])
})

