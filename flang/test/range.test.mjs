test("2⁵³−1 — последнее целое, у которого шаг на единицу что-то меняет", () => {
  /* Обоснование всей работы: при |x| ≤ 2⁵³ убывание на единицу — теорема, а не
     надежда, и именно поэтому сторож на `нат` не нужен. Число здесь не
     процитировано из документации, а посчитано на тех же double, на которых
     считает язык. */
  assert.equal(ТОЧНО, Number.MAX_SAFE_INTEGER)
  assert.equal(ТОЧНО - 1, 9007199254740990)
  assert.notEqual(ТОЧНО - 1, ТОЧНО)
  /* И изъятие: за границей шаг перестаёт менять число — ровно то, из-за чего
     сторож вообще появился. 2⁵⁴ первое такое целое. */
  assert.equal(2 ** 54 - 1, 2 ** 54)
  assert.equal(уточнение("natural").min, 0)
  assert.equal(уточнение("natural").max, ТОЧНО)
  assert.equal(уточнение("integer").min, -ТОЧНО)
  assert.equal(уточнение("unknown"), null)
})

test("литерал за границей мантиссы интервала не даёт: обещать про него нечего", () => {
  assert.deepEqual(интервалЛитерала(5), { min: 5, max: 5 })
  assert.deepEqual(интервалЛитерала(ТОЧНО), { min: ТОЧНО, max: ТОЧНО })
  assert.equal(интервалЛитерала(ТОЧНО + 2), null, "за границей соседей нет")
  assert.equal(интервалЛитерала(0.5), null, "дробное уточнением не бывает")
  assert.equal(интервалЛитерала(Number.NaN), null)
  assert.equal(интервалЛитерала(Number.POSITIVE_INFINITY), null)
})

