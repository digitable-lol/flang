test("нат ≤ целое ≤ число, и ни одно из трёх не наоборот", () => {
  const нат = уточнение("natural")
  const целое = уточнение("integer")
  assert.equal(вместимо(нат, целое), true, "нат ≤ целое")
  assert.equal(вместимо(нат, null), true, "нат ≤ число")
  assert.equal(вместимо(целое, null), true, "целое ≤ число")
  /* Изъятие: обратные три обязаны быть ложны. Верни хоть одна из них `true` —
     и уточнение перестало бы что-либо обещать. */
  assert.equal(вместимо(целое, нат), false, "целое ≰ нат")
  assert.equal(вместимо(null, нат), false, "число ≰ нат")
  assert.equal(вместимо(null, целое), false, "число ≰ целое")
})

test("нат годится там, где ждут число, а число там, где ждут нат, — нет", () => {
  const пара = (типГ, типФ) => `модуль «М»

функция «Г»
  принимает н: ${типГ}
  возвращает число
  0

функция «Ф»
  принимает х: ${типФ}
  возвращает число
  «Г» от х
`
  чисто(пара("число", "нат"))
  чисто(пара("целое", "нат"))
  чисто(пара("число", "целое"))
  краснеет(пара("нат", "число"), /ожидался нат, получен число/u)
  краснеет(пара("нат", "целое"), /ожидался нат, получен целое/u)
  краснеет(пара("целое", "число"), /ожидался целое, получен число/u)
})

test("список ковариантен: неизменяемый список нат годится списком числа", () => {
  const пара = (типГ, типФ) => `модуль «М»

функция «Г»
  принимает сп: список ${типГ}
  возвращает число
  0

функция «Ф»
  принимает сп: список ${типФ}
  возвращает число
  «Г» от сп
`
  чисто(пара("числа", "нат"))
  краснеет(пара("нат", "числа"), /ожидался список нат, получен список числа/u)
})

test("значение-функция контравариантна по аргументу: иначе подстановка неверна", () => {
  /* `функция из числа в число` вправе получить любое число. Функция,
     принимающая только `нат`, на её место не годится — и наоборот годится. */
  const пара = (ждём, даём) => `модуль «М»

функция «Удвоить»
  принимает х: ${даём}
  возвращает число
  х умножить на 2

функция «Дважды»
  принимает ф: функция из ${ждём} в число
  возвращает число
  ф от 1

функция «Ф»
  возвращает число
  «Дважды» от (функция «Удвоить»)
`
  чисто(пара("нат", "число"))
  краснеет(пара("число", "нат"), /ожидался/u)
})

