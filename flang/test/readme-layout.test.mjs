/* ═════════════ скрипты, которые документация велит запустить ═════════════ */

/**
 * Документация не называет скрипта, которого нет в дереве.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Это не гипотеза, а разобранный случай. Комментарий в `flang/self/SPEC.md`
 * объяснял, что четыре числа самораскрутки сняты прогоном `docs/ifl/facts.mjs`,
 * — и это была правда на ветке `docs/ifl-submission`, где скрипт лежал, и
 * неправда на main, где его не было. Читатель на main получал указание,
 * которое не выполняется: единственный способ проверить числа был назван
 * файлом, которого у читателя нет. Числа при этом верные — тем хуже, потому
 * что предъявить их было нечем.
 *
 * ── Что именно проверяется ──────────────────────────────────────────────────
 * Ровно одно: если страница пишет `node путь/до/скрипта.mjs` (или `bash …`,
 * `sh …`) внутри обратных кавычек, такой файл обязан лежать в дереве. Путь
 * засчитывается и от корня репозитория, и от каталога самой страницы: обе
 * записи в ходу — README инструмента пишет `node bin/имя.mjs` от
 * себя, README корня пишет `node flang/bin/flang.mjs` от корня.
 *
 * ── Чего он не проверяет, и почему это сказано вслух ────────────────────────
 * Продукты сборки (`dist/`, `node_modules/` и прочее из `ВНЕ_ДЕРЕВА`) не
 * сверяются: их наличие зависит от того, собирали ли дерево, и сторож, который
 * краснеет до `npm run build`, выключат в первый же день. Это не значит, что
 * туда можно ссылаться на что угодно, — это значит, что здесь такая ссылка не
 * поймана, и ловить её надо не отсюда.
 */
const ЗАПУСК = /`(?:node|bash|sh)\s+([A-Za-z0-9_./-]+\.(?:mjs|js|sh))/g

test("документация не называет скрипта, которого нет в дереве", () => {
  const страницы = globSync("**/*.md", {
    cwd: корень,
    exclude: (путь) => ВНЕ_ДЕРЕВА.includes(путь.split("/")[0]),
  }).sort()

  assert.ok(страницы.length > 0, "не найдено ни одной страницы .md — сломана сама выборка")

  const названо = []
  for (const страница of страницы) {
    const текст = readFileSync(корень + страница, "utf8")
    for (const [, путь] of текст.matchAll(ЗАПУСК)) {
      /* Продукт сборки пропускается по имени первого сегмента — тем же
         списком, которым карта репозитория исключает несобранные каталоги. */
      if (ВНЕ_ДЕРЕВА.includes(путь.split("/")[0])) continue
      названо.push([страница, путь])
    }
  }

  /* Число не сверяется с ожидаемым: ссылки прибавляются и убывают вместе с
     прозой, и требовать от неё постоянства значило бы держать текст за руки.
     Проверяется, что выборка вообще что-то нашла, — иначе тест зеленел бы на
     сломанном разборе. */
  assert.ok(
    названо.length > 0,
    "ни одна страница не называет скрипта к запуску — либо проза изменилась, либо сломан разбор",
  )

  for (const [страница, путь] of названо) {
    const отКорня = existsSync(корень + путь)
    const отСтраницы = existsSync(корень + dirname(страница) + "/" + путь)
    assert.ok(
      отКорня || отСтраницы,
      `${страница} велит запустить ${путь}, а такого файла в дереве нет: `
        + "либо скрипт не доехал до этой ветки, либо путь пережил переименование. "
        + "Указание, которое не выполняется, хуже отсутствующего — оно обещает проверку",
    )
  }
})
