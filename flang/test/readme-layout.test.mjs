test("числа README сходятся с деревом: каталоги верхнего уровня и инструменты", () => {
  /* Два счёта, которые называет сам раздел «Что где лежит». Без этой проверки
     они устарели бы первыми: карта каталогов ниже сверяется по именам, а «у
     корня 13 каталогов» — обычная фраза, которую ничто не держит. */
  const каталогов = каталогиДерева().length
  const инструментов = readdirSync(корень + "tools", { withFileTypes: true })
    .filter((запись) => запись.isDirectory()).length
  for (const [файл, фразы] of [
    ["README.ru.md", [`${каталогов} каталогов`, `${инструментов} инструментов`]],
    ["README.md", [`${каталогов} directories`, `${инструментов} tools`]],
  ]) {
    for (const фраза of фразы) {
      assert.ok(плоско(файл).includes(фраза), `${файл}: дерево изменилось — впишите «${фраза}»`)
    }
  }
})

test("числа flang/self/SPEC.md сходятся с деревом", () => {
  /* Не README, но соседняя беда, и найдена она ровно так же — глазами, а не
     проверкой. Шапка SPEC называет размер компилятора на JavaScript: там стояло
     «6166 строк», а их 16166. Число разошлось с деревом почти втрое и отличается
     от настоящего одной цифрой, так что прочитать его как опечатку было нельзя —
     только пересчитать. Обоснование всей работы («компилятор на JS большой,
     поэтому от Node уходим») опиралось на это число.

     Строки считаются буквально `wc -l` по `flang/src/*.mjs` без подкаталогов:
     эмиттеры лежат в `flang/src/emit/`, и SPEC называет их отдельно — «плюс
     эмиттеры». */
  const строк = (каталог, образец) =>
    readdirSync(корень + каталог)
      .filter((имя) => образец.test(имя))
      .reduce((сумма, имя) => сумма + readFileSync(корень + каталог + имя, "utf8").split("\n").length - 1, 0)

  for (const [фраза, сколько] of [
    ["строк в", строк("flang/src/", /\.mjs$/u)],
    ["строки, 300 функций", строк("flang/core/", /\.flang$/u)],
  ]) {
    const ожидается = `${сколько} ${фраза}`
    assert.ok(
      плоско("flang/self/SPEC.md").includes(ожидается),
      `flang/self/SPEC.md: дерево изменилось — впишите «${ожидается}»`,
    )
  }
})

test("процитированный вывод прогона в README сходится с деревом", () => {
  /* Соседний абзац говорит: «Прогон сам отчитывается об охвате, поэтому
     утверждение проверяемо, а не процитировано» — и следом идёт цитата вывода.
     Цитата отстала: «программ: 31, функций: 154 … сверенных примеров: 259» при
     35, 214 и 415, причём проза строкой выше уже называла верные числа. Два
     соседних абзаца противоречили друг другу, и убедительнее выглядел неверный:
     у него вид машинного вывода.

     Число сверенных ВХОДОВ сюда не берётся: сетку строит сам прогон из примеров
     и порчи аргументов, дёшево её здесь не пересчитать. Значит, из четырёх
     чисел цитаты одно остаётся неприкрытым и однажды отстанет так же. Дыра
     названа здесь нарочно: закрыть её можно, дав прогону печатать охват в файл,
     а этой проверке — читать его. Пока не сделано. */
  const корпус = измерить(["flang/stdlib/", "flang/examples/leetcode/"])
  for (const файл of ["README.ru.md", "README.md"]) {
    const текст = плоско(файл)
    const охват = текст.match(/программ: (\d+), функций: (\d+), сверенных входов: (\d+)/u)
    assert.ok(охват, `${файл}: пропала процитированная строка охвата`)
    assert.deepEqual(
      охват.slice(1, 3).map(Number),
      [корпус.файлов, корпус.функций],
      `${файл}: процитированный вывод отстал — прогон печатает «программ: ${корпус.файлов}, функций: ${корпус.функций}»`,
    )
    assert.ok(
      текст.includes(`сверенных примеров: ${корпус.примеров}`),
      `${файл}: процитированный вывод отстал — прогон печатает «сверенных примеров: ${корпус.примеров}»`,
    )
  }
})

test("«Состояние» каждого раздела долгов сходится с самим файлом", () => {
  /* В разделе «Долги» у каждого файла самоприменения стоит строка вида
     «Состояние: 84 функции, 84 тотальные, 0 обычных». Все семь сегодня верны —
     я пересчитал, прежде чем править, и хорошо, что пересчитал дважды: первый
     счёт шёл через `flang check`, а он считает функции СВЯЗАННОЙ программы,
     вместе с импортами, и дал 88 вместо 84 и 1574 вместо 68. Числа SPEC — про
     собственные объявления файла, и по ним всё сходится.
     Держать их, однако, нечем, а рядом в этом же файле число уже разошлось
     втрое.

     Сверяются числа, а не слова: форма («84 тотальные» против «194 тотальных»)
     зависит от числа, и диктовать её тесту значило бы требовать неграмотное
     согласование при каждой правке. «Тотальная» здесь — то, как функция
     ОБЪЯВЛЕНА, а не то, что доказано; в SPEC это счёт объявлений, поэтому и
     считается флаг разбора. */
  const разделы = readFileSync(корень + "flang/self/SPEC.md", "utf8").split(/^### /mu).slice(1)
  let сверено = 0
  for (const раздел of разделы) {
    const файл = раздел.match(/^`(self\/[^`]+\.flang)`/u)?.[1]
    if (!файл) continue
    const состояние = раздел.match(/Состояние: (\d+) функци\S* (\d+) тотальн\S* (\d+) обычн\S*/u)
    assert.ok(состояние, `${файл}: у раздела нет строки «Состояние: N функций, M тотальных, K обычных»`)
    const программа = parse(readFileSync(`${корень}flang/${файл}`, "utf8"), файл)
    const всего = (программа.functions ?? []).length
    const тотальных = (программа.functions ?? []).filter((ф) => ф.total).length
    assert.deepEqual(
      состояние.slice(1, 4).map(Number),
      [всего, тотальных, всего - тотальных],
      `flang/self/SPEC.md, раздел ${файл}: «Состояние» отстало от файла — там ${всего} функций, ${тотальных} тотальных, ${всего - тотальных} обычных`,
    )
    сверено += 1
  }
  assert.ok(сверено >= 7, `сверено ${сверено} разделов из семи — раздел исчез или заголовок перестал называть файл`)
})

