/**
 * README о репозитории обязан совпадать с репозиторием.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Раздел «Что где лежит» — проза о коде, а проза о коде в этом репозитории
 * либо проверяется, либо не существует. Причина известна поимённо: за одни
 * сутки шесть раз выяснялось, что объяснение пережило то, что объясняло, —
 * каталог недостач наполовину состоял из починенного, шапка модуля описывала
 * ограничение, которого нет, «восемь бэкендов не печатают функции» устарело
 * через час. Карта каталогов ломается так же и по той же причине: переименовал
 * каталог — карта соврала, и соврала молча, потому что текст не исполняется.
 *
 * Это не гипотеза. Когда раздел заводили, в обеих редакциях README уже стояло
 * четыре неверных числа: корпус бэкендов назван «31 программа со 154
 * функциями» при 35 и 214, библиотека — шестью модулями и 112 функциями при
 * девяти и 135, набор Rosetta Code — семью задачами при пятнадцати, а решения
 * LeetCode — «20 тотальны целиком» при всех 26. Ни одно из этих чисел не было
 * ничем связано с деревом, поэтому все четыре и разошлись.
 *
 * Здесь молча не выйдет, и проверок ровно столько, сколько разных способов
 * разойтись:
 *
 *   1. каталог назван, а его нет  — переименование или удаление;
 *   2. каталог есть, а не назван  — новый каталог верхнего уровня, о котором
 *      README промолчал: ровно та беда, с которой раздел и заводился;
 *   3. редакции разошлись         — правку внесли в одну README и забыли вторую;
 *   4. число в прозе устарело     — набор вырос, а страница осталась прежней.
 *
 * ── Почему граница раздела размечена комментарием ───────────────────────────
 * Искать раздел по заголовку значит запретить его переименовывать, а тест не
 * должен держать текст за руки. Пара `КАРТА-НАЧАЛО` / `КАРТА-КОНЕЦ` переживает
 * и переименование заголовка, и перенос раздела в другое место страницы: она
 * размечает то единственное, что здесь проверяется, — сам список каталогов.
 * Тот же приём стоит в `flang/stdlib/README.md`, где комментарий объясняет,
 * почему файл не правят руками.
 *
 * ── Почему числа сверяются цитатой, а не разбором прозы ─────────────────────
 * Вытаскивать числа из текста регулярным выражением значит завести второй
 * парсер русского языка и чинить его при каждой правке фразы. Здесь наоборот:
 * фраза СОБИРАЕТСЯ из измеренных чисел и обязана найтись в странице дословно.
 * Тот же приём, что в `flang/test/claims.test.mjs`. Отсюда и текст отказа —
 * готовая строка, которой чинится страница.
 */
import assert from "node:assert/strict"
import { existsSync, readFileSync, readdirSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))

const НАЧАЛО = "<!-- КАРТА-НАЧАЛО"
const КОНЕЦ = "<!-- КАРТА-КОНЕЦ -->"

const РЕДАКЦИИ = ["README.ru.md", "README.md"]

/**
 * Каталоги, которых нет в дереве исходников: их создают сборка, установка
 * зависимостей и печать релиза. Список не выдуман — каждое имя обязано стоять
 * в `.gitignore`, и это проверяется ниже отдельным тестом, иначе исключение
 * стало бы дырой, через которую новый каталог тихо пролез бы мимо карты.
 */
const ВНЕ_ДЕРЕВА = ["node_modules", "dist", "output", "generated", "coverage", "tmp", "research"]

const экранировать = (имя) => имя.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

/** Размеченный кусок README — только он и проверяется. */
function карта(файл) {
  const текст = readFileSync(корень + файл, "utf8")
  const от = текст.indexOf(НАЧАЛО)
  const до = текст.indexOf(КОНЕЦ)
  assert.ok(
    от !== -1 && до > от,
    `${файл}: карта репозитория не размечена — нужны «${НАЧАЛО} …» и «${КОНЕЦ}»`,
  )
  return текст.slice(от, до)
}

/**
 * Пути из карты: первое слово строки, если в нём есть косая черта. Так берётся
 * ровно левый столбец списка каталогов и не берутся ни пояснения справа, ни
 * текст комментария-разметки.
 */
function путиИзКарты(текст) {
  const пути = new Set()
  for (const строка of текст.split("\n")) {
    const первое = строка.trim().split(/\s+/)[0] ?? ""
    if (первое.includes("/") && !первое.includes("*")) пути.add(первое.replace(/\/+$/, ""))
  }
  return [...пути].sort()
}

/** Каталоги верхнего уровня, составляющие дерево исходников. */
function каталогиДерева() {
  return readdirSync(корень, { withFileTypes: true })
    .filter((запись) => запись.isDirectory() || запись.isSymbolicLink())
    .map((запись) => запись.name)
    .filter((имя) => имя !== ".git" && !ВНЕ_ДЕРЕВА.includes(имя))
    .sort()
}

for (const файл of РЕДАКЦИИ) {
  test(`${файл}: карта называет каждый каталог верхнего уровня`, () => {
    const текст = карта(файл)
    for (const имя of каталогиДерева()) {
      /* Имя обязано стоять в начале строки или после пробела, скобки, кавычки:
         иначе «src/» засчиталось бы вхождением внутрь «flang/src/», и удаление
         каталога верхнего уровня осталось бы незамеченным. */
      const назван = new RegExp(`(^|[\\s\`\\[(])${экранировать(имя)}/`, "m").test(текст)
      assert.ok(
        назван,
        `в карте ${файл} нет каталога ${имя}/ — репозиторий вырос, а README об этом молчит`,
      )
    }
  })

  test(`${файл}: каждый путь из карты существует`, () => {
    for (const путь of путиИзКарты(карта(файл))) {
      assert.ok(
        existsSync(корень + путь),
        `в карте ${файл} назван путь ${путь}, которого в дереве нет — карта пережила каталог`,
      )
    }
  })
}

test("русская и английская карты называют одни и те же каталоги", () => {
  /* Раздел есть в обеих редакциях, и разойтись они могут только правкой одной
     из них. Сверяются пути, а не пояснения: пояснения на разных языках. */
  assert.deepEqual(
    путиИзКарты(карта("README.md")),
    путиИзКарты(карта("README.ru.md")),
    "карты репозитория в README.md и README.ru.md называют разные каталоги",
  )
})

test("исключённые каталоги перечислены в .gitignore", () => {
  const игнор = readFileSync(корень + ".gitignore", "utf8")
  for (const имя of ВНЕ_ДЕРЕВА) {
    assert.ok(
      new RegExp(`^${экранировать(имя)}/?$`, "m").test(игнор),
      `${имя} исключён из сверки с картой, но в .gitignore его нет: либо каталог стал частью дерева и обязан попасть в README, либо исключение здесь лишнее`,
    )
  }
})

/* ═══════════════ числа, которыми README описывает наборы файлов ═══════════════ */

/** Страница целиком, со схлопнутыми пробелами: цитата не должна зависеть от переносов. */
const плоско = (файл) => readFileSync(корень + файл, "utf8").replace(/\s+/g, " ")

const модули = (каталог) =>
  readdirSync(корень + каталог)
    .filter((имя) => имя.endsWith(".flang"))
    .sort()

/**
 * Измерение набора: файлы, функции, доказанная тотальность, примеры.
 *
 * `задач` отдельно от `файлов`, потому что с тех пор, как каждая задача Rosetta
 * Code записана на обеих поверхностях, файл перестал быть задачей: их 28 при
 * 14 задачах. Пока это совпадало, разницы никто не видел, и README называл
 * файлы задачами — а сторож повторял за ним и требовал вписать «28 задач»,
 * то есть предлагал заменить верное число на неверное. Считаем то, что
 * названо: задача — это файл без `-english`.
 */
function измерить(каталоги) {
  const итог = { файлов: 0, задач: 0, функций: 0, тотальных: 0, примеров: 0 }
  for (const каталог of каталоги) {
    for (const имя of модули(каталог)) {
      const программа = parse(readFileSync(корень + каталог + имя, "utf8"), имя)
      const тотальность = checkTotality(программа)
      итог.файлов += 1
      if (!имя.endsWith("-english.flang")) итог.задач += 1
      for (const функция of программа.functions ?? []) {
        итог.функций += 1
        итог.примеров += (функция.examples ?? []).length
        if (тотальность.total.has(функция.name)) итог.тотальных += 1
      }
    }
  }
  return итог
}

