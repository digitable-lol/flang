test("числа README сходятся с деревом: каталоги верхнего уровня", () => {
  /* Счёт, который называет сам раздел «Что где лежит». Без этой проверки он
     устарел бы первым: карта каталогов ниже сверяется по именам, а «у корня
     десять каталогов» — обычная фраза, которую ничто не держит.

     Второй счёт — «9 инструментов» — снят вместе с каталогом `tools/`: девять
     инструментов старого проекта FTS вынесены из репозитория (тег
     `fts-pered-udaleniem`). Пустой список считать бессмысленно, а `readdirSync`
     по исчезнувшему пути ронял файл целиком, до первой проверки. */
  const каталогов = каталогиДерева().length
  for (const [файл, фразы] of [
    ["README.ru.md", [`${каталогов} каталогов`]],
    ["README.md", [`${каталогов} directories`]],
  ]) {
    for (const фраза of фразы) {
      assert.ok(плоско(файл).includes(фраза), `${файл}: дерево изменилось — впишите «${фраза}»`)
    }
  }
})

test("числа flang/self/SPEC.md сходятся с деревом", () => {
  /* Не README, но соседняя беда, и найдена она ровно так же — глазами, а не
     проверкой. Шапка SPEC называет размер компилятора на JavaScript: там стояло
     «6166 строк», а их 16166. Число разошлось с деревом почти втрое и отличается
     от настоящего одной цифрой, так что прочитать его как опечатку было нельзя —
     только пересчитать. Обоснование всей работы («компилятор на JS большой,
     поэтому от Node уходим») опиралось на это число.

     Строки считаются буквально `wc -l` по `flang/src/*.mjs` без подкаталогов:
     эмиттеры лежат в `flang/src/emit/`, и SPEC называет их отдельно — «плюс
     эмиттеры». */
  const строк = (каталог, образец) =>
    readdirSync(корень + каталог)
      .filter((имя) => образец.test(имя))
      .reduce((сумма, имя) => сумма + readFileSync(корень + каталог + имя, "utf8").split("\n").length - 1, 0)

  /* Слово при числе склоняется, и проверка обязана требовать ту форму, которая
     по-русски верна. Проверка требовала «строк» при любом числе — совпадало
     это случайно: 16166 и правда «строк». Первая же правка исходника сделала
     их 16184, то есть «строки», и проверка стала требовать вписать в SPEC
     безграмотное «16184 строк». Требование неверной формы хуже отсутствия
     проверки: оно её и портит. */
  const строкой = (сколько) => {
    const сотня = сколько % 100
    if (сотня >= 11 && сотня <= 14) return "строк"
    const единица = сколько % 10
    if (единица === 1) return "строка"
    if (единица >= 2 && единица <= 4) return "строки"
    return "строк"
  }

  for (const [хвост, сколько] of [
    [" в", строк("flang/src/", /\.mjs$/u)],
    [", 300 функций", строк("flang/core/", /\.flang$/u)],
  ]) {
    const ожидается = `${сколько} ${строкой(сколько)}${хвост}`
    assert.ok(
      плоско("flang/self/SPEC.md").includes(ожидается),
      `flang/self/SPEC.md: дерево изменилось — впишите «${ожидается}»`,
    )
  }
})

