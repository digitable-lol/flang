test("«Состояние» каждого раздела долгов сходится с самим файлом", () => {
  /* В разделе «Долги» у каждого файла самоприменения стоит строка вида
     «Состояние: 84 функции, 84 тотальные, 0 обычных». Все семь сегодня верны —
     я пересчитал, прежде чем править, и хорошо, что пересчитал дважды: первый
     счёт шёл через `flang check`, а он считает функции СВЯЗАННОЙ программы,
     вместе с импортами, и дал 88 вместо 84 и 1574 вместо 68. Числа SPEC — про
     собственные объявления файла, и по ним всё сходится.
     Держать их, однако, нечем, а рядом в этом же файле число уже разошлось
     втрое.

     Сверяются числа, а не слова: форма («84 тотальные» против «194 тотальных»)
     зависит от числа, и диктовать её тесту значило бы требовать неграмотное
     согласование при каждой правке. «Тотальная» здесь — то, как функция
     ОБЪЯВЛЕНА, а не то, что доказано; в SPEC это счёт объявлений, поэтому и
     считается флаг разбора. */
  const разделы = readFileSync(корень + "flang/self/SPEC.md", "utf8").split(/^### /mu).slice(1)
  let сверено = 0
  for (const раздел of разделы) {
    const файл = раздел.match(/^`(self\/[^`]+\.flang)`/u)?.[1]
    if (!файл) continue
    const состояние = раздел.match(/Состояние: (\d+) функци\S* (\d+) тотальн\S* (\d+) обычн\S*/u)
    assert.ok(состояние, `${файл}: у раздела нет строки «Состояние: N функций, M тотальных, K обычных»`)
    const программа = parse(readFileSync(`${корень}flang/${файл}`, "utf8"), файл)
    const всего = (программа.functions ?? []).length
    const тотальных = (программа.functions ?? []).filter((ф) => ф.total).length
    assert.deepEqual(
      состояние.slice(1, 4).map(Number),
      [всего, тотальных, всего - тотальных],
      `flang/self/SPEC.md, раздел ${файл}: «Состояние» отстало от файла — там ${всего} функций, ${тотальных} тотальных, ${всего - тотальных} обычных`,
    )
    сверено += 1
  }
  assert.ok(сверено >= 7, `сверено ${сверено} разделов из семи — раздел исчез или заголовок перестал называть файл`)
})

