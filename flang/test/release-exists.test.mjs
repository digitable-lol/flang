/**
 * Версия, обещанная документацией и формулой, обязана СУЩЕСТВОВАТЬ на GitHub —
 * вместе с архивом, который можно скачать.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * 18 августа 2026 сайт обещал два способа установки, и не работал ни один.
 * Формула Homebrew вела на
 * `https://github.com/digitable-lol/flang/releases/download/v0.5.0/flang-0.5.0-c.tar.gz`,
 * а сервер отвечал `404 Not Found` — девять байт вместо архива. Последним
 * существовавшим релизом был v0.4.8, и у него не было НИ ОДНОГО вложения: даже
 * откатившись на версию назад, поставить было нечего. При этом `package.json`,
 * `changelog.json`, `CHANGELOG.md` и формула дружно объявляли 0.5.0 — то есть
 * между собой они были согласованы идеально, и никто не покраснел.
 *
 * Почему этого не поймал flang/test/homebrew.test.mjs. Тот сторож сверяет
 * ВНУТРЕННЮЮ согласованность: версия в трёх местах формулы против package.json,
 * плюс что хеш не перенесён от прошлого релиза. Все три его проверки были
 * ЗЕЛЁНЫМИ, пока ссылка отдавала 404, — потому что он нарочно не ходит в сеть и
 * ни разу не спрашивает, есть ли по ссылке хоть что-нибудь. Согласованность лжи
 * — это тоже согласованность: четыре файла хором называли версию, которой не
 * существовало, и хор звучал стройно.
 *
 * Отсюда разделение обязанностей:
 *   • homebrew.test.mjs — «три числа формулы говорят об одном релизе» (без сети);
 *   • этот файл         — «такой релиз есть, и архив по ссылке отдаётся» (с сетью).
 *
 * ── Про сеть ────────────────────────────────────────────────────────────────
 * scripts/build-changelog.mjs отвергает GitHub как ИСТОЧНИК содержимого: за ним
 * надо ходить в сеть, а проверку, которую нельзя выполнить, проверкой не
 * назовёшь. Довод верный, но здесь он не запрещает сеть, а определяет поведение:
 * существование релиза — факт по своей природе сетевой, из репозитория его не
 * вычитать никак. Поэтому:
 *
 *   • GitHub недоступен (нет сети, нет DNS, лимит API) → тест ПРОПУСКАЕТСЯ, и
 *     пропуск громкий: он называет причину. Красить сборку за отключённый
 *     интернет нечестно;
 *   • GitHub ответил, а релиза или вложения нет → тест КРАСНЕЕТ. Это ровно та
 *     беда, ради которой файл написан, и молчать о ней нельзя.
 *
 * Разница принципиальная: «не смог проверить» и «проверил, всё плохо» — разные
 * исходы, и путать их нельзя. Именно смешение этих двух состояний и позволило
 * лжи проехать: непроверенное считалось рабочим.
 *
 * Запуск:  node --test flang/test/release-exists.test.mjs
 * Заглушить намеренно (без сети в CI):  FLANG_SKIP_RELEASE_CHECK=1
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const прочитать = (путь) => readFileSync(join(корень, путь), "utf8")

const РЕПО = "digitable-lol/flang"
const ФОРМУЛА = "packaging/homebrew/flang.rb"

/* ------------------------------------------------------------------- обещания */

/**
 * Что и где обещано. Каждое обещание — это пара «версия» и «кто её назвал»:
 * без имени места красный тест заставляет искать виноватого руками.
 */
export function обещанныеВерсии({ пакет, формула, журнал }) {
  const обещания = []
  const добавить = (версия, место) => {
    if (типВерсии(версия)) обещания.push({ версия, место })
  }
  добавить(пакет.version, "package.json → version")
  добавить(/^\s*version\s+"([^"]+)"/mu.exec(формула)?.[1], `${ФОРМУЛА} → version`)
  добавить(/\/download\/v([^/]+)\//u.exec(формула)?.[1], `${ФОРМУЛА} → url (тег)`)
  добавить(журнал?.declared, "changelog.json → declared")
  добавить(журнал?.latest, "changelog.json → latest")
  return обещания
}

const типВерсии = (значение) => typeof значение === "string" && /^\d+\.\d+\.\d+$/u.test(значение)

const пакет = JSON.parse(прочитать("package.json"))
const формула = прочитать(ФОРМУЛА)
let журнал = null
try {
  журнал = JSON.parse(прочитать("changelog.json"))
} catch {
  /* журнала может не быть — это не улика */
}

const обещания = обещанныеВерсии({ пакет, формула, журнал })

/* ---------------------------------------------------------------------- сеть */

const ЖДАТЬ = 15000

/** Один поход в API GitHub. Возвращает `{есть, код, тело}` либо бросает — если
 *  до GitHub вообще не достучались. Разница между «404» и «сети нет» здесь и
 *  проводится: первое — улика, второе — повод пропустить. */
async function спросить(путь) {
  const заголовки = { accept: "application/vnd.github+json", "user-agent": "flang-release-check" }
  /* Токен берётся, если он есть: без него лимит 60 запросов в час на адрес, и на
     общей машине его можно исчерпать чужими запросами. Прав токену не нужно
     никаких — репозиторий открытый. */
  const токен = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN
  if (токен) заголовки.authorization = `Bearer ${токен}`
  const ответ = await fetch(`https://api.github.com${путь}`, {
    headers: заголовки,
    signal: AbortSignal.timeout(ЖДАТЬ),
  })
  return { код: ответ.status, тело: ответ.status === 200 ? await ответ.json() : null }
}

/** Доступен ли GitHub вообще. Спрашиваем сам репозиторий: он открытый, ответ
 *  дешёвый, и 200 на нём означает «сеть есть, лимит не исчерпан». */
async function githubДоступен() {
  try {
    const { код } = await спросить(`/repos/${РЕПО}`)
    /* 403 и 429 — это исчерпанный лимит, а не отсутствие релиза: проверять
       нечем, надо пропускать, а не красить. */
    if (код === 403 || код === 429) return { да: false, почему: `API GitHub ответил ${код} (лимит запросов)` }
    if (код !== 200) return { да: false, почему: `API GitHub ответил ${код} на сам репозиторий` }
    return { да: true }
  } catch (беда) {
    return { да: false, почему: `до api.github.com не достучались: ${беда.message}` }
  }
}

/* ------------------------------------------------------------------ проверки */

test("обещанные версии вообще названы", () => {
  assert.ok(
    обещания.length > 0,
    "ни package.json, ни формула, ни changelog.json не назвали версию вида N.N.N — проверять нечего",
  )
  /* Все обещания обязаны быть про одну версию: иначе непонятно, существование
     чего проверять, и это само по себе беда. Внутреннюю сверку формулы с
     package.json делает homebrew.test.mjs; здесь она нужна, чтобы сетевая
     проверка знала свой предмет. */
  const разные = [...new Set(обещания.map((о) => о.версия))]
  assert.equal(
    разные.length,
    1,
    `обещаны разные версии: ${обещания.map((о) => `${о.версия} (${о.место})`).join(", ")}`,
  )
})

test("обещанный релиз существует на GitHub и несёт архив", async (t) => {
  if (process.env.FLANG_SKIP_RELEASE_CHECK) {
    t.skip("проверка выключена намеренно: FLANG_SKIP_RELEASE_CHECK")
    return
  }
  const доступ = await githubДоступен()
  if (!доступ.да) {
    /* Громко: пропуск обязан называть причину, иначе он неотличим от успеха, а
       именно это и позволило лжи проехать. */
    t.skip(`GitHub недоступен, существование релиза НЕ ПРОВЕРЕНО — ${доступ.почему}`)
    return
  }

  const версия = обещания[0].версия
  const кто = обещания.map((о) => о.место).join(", ")

  const { код, тело } = await спросить(`/repos/${РЕПО}/releases/tags/v${версия}`)
  assert.notEqual(
    код,
    404,
    `версию ${версия} обещают ${кто}, но релиза v${версия} на GitHub НЕТ ` +
      `(API ответил 404). Обещание установки, за которым нет релиза, — ложь: ` +
      `человек идёт по ссылке и получает 404. Выпустите релиз или уберите обещание.`,
  )
  assert.equal(код, 200, `API GitHub ответил ${код} на релиз v${версия}`)

  /* Релиз без вложений — отдельная беда, и она уже случалась: у v0.4.8 не было
     ни одного архива, то есть релиз существовал, а поставить было нечего. */
  const имя = `flang-${версия}-c.tar.gz`
  const вложения = (тело.assets ?? []).map((в) => в.name)
  assert.ok(
    вложения.includes(имя),
    `релиз v${версия} существует, но архива «${имя}» в нём нет. ` +
      `Вложения: ${вложения.length === 0 ? "НИ ОДНОГО" : вложения.join(", ")}. ` +
      `Ровно так и вышло с v0.4.8: релиз есть, ставить нечего.`,
  )

  const архив = тело.assets.find((в) => в.name === имя)
  assert.ok(архив.size > 0, `архив «${имя}» в релизе v${версия} пуст (0 байт)`)
})

test("ссылка формулы отдаёт архив, а не 404", async (t) => {
  if (process.env.FLANG_SKIP_RELEASE_CHECK) {
    t.skip("проверка выключена намеренно: FLANG_SKIP_RELEASE_CHECK")
    return
  }
  const доступ = await githubДоступен()
  if (!доступ.да) {
    t.skip(`GitHub недоступен, ссылка формулы НЕ ПРОВЕРЕНА — ${доступ.почему}`)
    return
  }

  const ссылка = /^\s*url\s+"([^"]+)"/mu.exec(формула)?.[1]
  assert.ok(ссылка, `${ФОРМУЛА}: строки url нет вовсе`)

  /* Именно HEAD по той самой ссылке из формулы, а не сборка адреса из версии:
     проверять надо то, что прочтёт brew, а не то, что мы думаем, будто там
     написано. Redirect идёт до конца — GitHub уводит вложения на свой CDN. */
  let ответ
  try {
    ответ = await fetch(ссылка, { method: "HEAD", redirect: "follow", signal: AbortSignal.timeout(ЖДАТЬ) })
  } catch (беда) {
    t.skip(`по ссылке формулы не сходили, НЕ ПРОВЕРЕНО — ${беда.message}`)
    return
  }

  assert.ok(
    ответ.ok,
    `${ФОРМУЛА}: url ведёт на ${ссылка}, а сервер отвечает ${ответ.status}. ` +
      `Это и есть «сайт обещает установку, которой нет»: brew скачает ${ответ.status} вместо архива.`,
  )
})
