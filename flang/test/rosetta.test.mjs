const файлы = globSync("*.flang", { cwd: корень }).sort()

test("набор Rosetta не растерялся и не пополнился молча", () => {
  /* Новый файл в каталоге обязан попасть в таблицу выше — иначе он не будет
     проверен на границу, и первое же расхождение уедет к читателю. */
  assert.deepEqual(файлы, [...ОЖИДАЕТСЯ.keys()].sort())
})

for (const имя of файлы) {
  test(`${имя}: разбирается, проходит проверки и держит границу`, () => {
    const исходник = readFileSync(new URL(имя, `file://${корень}`), "utf8")
    const программа = parse(исходник, имя)

    const типы = checkTypes(программа)
    assert.deepEqual(
      (типы.diagnostics ?? []).map((беда) => `${беда.code}: ${беда.message}`),
      [],
    )

    const завершаемость = checkTotality(программа)
    const тотальные = new Set(завершаемость.total ?? [])
    const ожидание = ОЖИДАЕТСЯ.get(имя)
    assert.equal(программа.functions.length, ожидание.функций, "изменилось число функций")
    assert.equal(
      тотальные.size,
      ожидание.тотальных,
      `граница сдвинулась: тотальных ${тотальные.size}, ожидалось ${ожидание.тотальных} — ` +
        `объяснение в шапке файла надо переписать`,
    )
  })

  test(`${имя}: все примеры сходятся`, () => {
    const исходник = readFileSync(new URL(имя, `file://${корень}`), "utf8")
    const программа = parse(исходник, имя)
    let сошлось = 0
    for (const функция of программа.functions) {
      for (const пример of функция.examples ?? []) {
        const получилось = evaluate(программа, функция.name, пример.args)
        assert.deepEqual(
          получилось,
          пример.expected,
          `${функция.name} / ${пример.name}`,
        )
        сошлось += 1
      }
    }
    /* Файл без единого примера в набор не годится: показывать решение, которое
       ничем не подтверждено, — ровно то, чем плохи витрины. */
    assert.ok(сошлось >= 5, `${имя}: примеров всего ${сошлось}`)
  })
}

/* ─────────────────────── две поверхности одной задачи ─────────────────────── */

test("у каждого английского листинга есть пара в таблице", () => {
  /* Файл `*-english.flang`, не попавший в ПАРЫ, не сверялся бы с русским вовсе:
     он прошёл бы проверки выше сам по себе и разошёлся бы с оригиналом молча. */
  const английские = файлы.filter((имя) => имя.endsWith("-english.flang")).sort()
  assert.deepEqual(английские, ПАРЫ.map(([, английский]) => английский).sort())
  for (const [русский, английский] of ПАРЫ) {
    assert.ok(ОЖИДАЕТСЯ.has(русский), `${русский} нет в таблице границ`)
    assert.ok(ОЖИДАЕТСЯ.has(английский), `${английский} нет в таблице границ`)
  }
})

for (const [русский, английский] of ПАРЫ) {
  test(`${русский} и ${английский} — одна программа, а не два похожих текста`, () => {
    const первый = parse(readFileSync(new URL(русский, `file://${корень}`), "utf8"), русский)
    const второй = parse(readFileSync(new URL(английский, `file://${корень}`), "utf8"), английский)

    /* Главное: деревья совпадают с точностью до взаимно однозначного
       переименования. Разбор поверхности не знает, и потому один и тот же
       алгоритм на двух языках обязан дать одно и то же дерево. */
    const словари = сверитьПоверхности(первый, второй)
    assert.ok(связаноИмён(словари) > 0, "сверка не связала ни одного имени — она пустая")

    /* И граница тотальности та же. Это следствие предыдущего, а не отдельный
       факт, — но именно оно попадёт на вики словом `total`, поэтому пусть
       ломается отдельным сообщением. */
    const границаПервого = new Set(checkTotality(первый).total ?? [])
    const границаВторого = new Set(checkTotality(второй).total ?? [])
    assert.equal(первый.functions.length, второй.functions.length, "разное число функций")
    assert.equal(
      границаПервого.size,
      границаВторого.size,
      `доказанность разошлась: ${границаПервого.size} против ${границаВторого.size}`,
    )
  })
}

test("сверка поверхностей ловит расхождение, а не только совпадение", () => {
  /* Проверка на проверку. Сверка, которая всё принимает, хуже отсутствующей:
     она даёт уверенность, ничего не проверив. Поэтому здесь берётся настоящая
     пара и в английский листинг вносится одна правка — та самая, какой
     разъезжаются файлы при доработке одного из них. */
  const русский = readFileSync(new URL("factorial.flang", `file://${корень}`), "utf8")
  const английский = readFileSync(new URL("factorial-english.flang", `file://${корень}`), "utf8")
  const испорченный = английский.replace("else n times («Factorial» of (n minus 1))", "else n times («Factorial» of (n minus 2))")
  assert.notEqual(испорченный, английский, "правка не применилась — тест ничего не проверяет")
  assert.throws(
    () => сверитьПоверхности(parse(русский, "factorial.flang"), parse(испорченный, "порча")),
    /1 ≠ 2/u,
  )
})

/**
 * ПОДДЕЛКИ НА СВЯЗКИ ТЕОРЕМЫ, и стоят они по той же причине, что подделка выше.
 *
 * Слоты `theorems[N].vars[M].name` и `theorems[N].induction.param` переведены из
 * побуквенных в именные (`surface-pair.mjs`): «осталось» и «remaining» — одно имя
 * на двух поверхностях, и требовать их буквального совпадения было неправотой.
 * Но послабление обязано снять ВЫБОР ИМЕНИ и не тронуть СВЕРКУ СВЯЗИ, а разница
 * эта из зелёного цвета не видна: область имён, принимающая что угодно, зеленела
 * бы и на подделке. Поэтому подделки бьют не в написание, а в связь.
 *
 * ПЕРВУЮ ловит сама сверка, и ловит взаимной однозначностью: «осталось» уже
 * ответило «remaining», и вторым ответом «total» ему быть нельзя. То есть
 * послабление сняло выбор имени и связь не тронуло — что и требовалось.
 *
 * ВТОРОЙ нужна теорема с ДВУМЯ связками: там ссылка, уведённая с одной на
 * другую, законна для РАЗБОРА — оба имени связаны, — и незаконна по СВЯЗИ.
 * Такой пары в корпусе нет, поэтому она собрана здесь: минимальная программа
 * на двух поверхностях. Без неё первая подделка оставляла бы открытым вопрос,
 * держит ли сверка связь или всего лишь ловит незнакомое слово.
 */
const ПАРА_СВЯЗОК_RU = `модуль «Проба»

тотальная функция «Ф»
  принимает а: нат, б: нат
  возвращает число
  а

теорема «проба связок»
  дано а: нат
  дано б: нат
  утверждаем результат не меньше 0
  индукция по а убывает а
    случай 0
      то по предположению
    случай любое
      то по предположению
  следовательно доказано
`

const наАнглийском = (текст) =>
  текст
    .replace("модуль «Проба»", "module «Probe»")
    .replace("тотальная функция «Ф»", "total function «F»")
    .replace("  принимает а: нат, б: нат", "  accepts a: nat, b: nat")
    .replace("  возвращает число", "  returns number")
    .replace("\n  а\n", "\n  a\n")
    .replace("теорема «проба связок»", "theorem «binder probe»")
    .replace("  дано а: нат", "  given a: nat")
    .replace("  дано б: нат", "  given b: nat")
    .replace("  утверждаем результат не меньше 0", "  claim result is at least 0")
    .replace("  индукция по а убывает а", "  induction on a decreases a")
    .replaceAll("    случай 0", "    case 0")
    .replaceAll("      то по предположению", "      then by hypothesis")
    .replaceAll("    случай любое", "    case any")
    .replace("  следовательно доказано", "  therefore proved")

test("ПОДДЕЛКА: связка теоремы сверяется по СВЯЗИ, а не по написанию", () => {
  const русский = readFileSync(new URL("fibonacci.flang", `file://${корень}`), "utf8")
  const английский = readFileSync(new URL("fibonacci-english.flang", `file://${корень}`), "utf8")

  /* Сперва — что подлинная пара ЗЕЛЕНА. Без этого подделки ниже краснели бы от
     чего угодно, и проверка не значила бы ничего. */
  сверитьПоверхности(parse(русский, "fibonacci.flang"), parse(английский, "fibonacci-english.flang"))

  /* ПОДДЕЛКА 1: ссылка уведена на имя, которого `given` не связывал. Ловит
     биекция: «осталось» уже ответило «remaining». */
  const мимоСвязки = английский.replace(
    "induction on remaining decreases remaining",
    "induction on total decreases remaining",
  )
  assert.notEqual(мимоСвязки, английский, "подмена 1 не применилась — подделка ничего не проверяет")
  assert.throws(
    () => сверитьПоверхности(parse(русский, "fibonacci.flang"), parse(мимоСвязки, "подделка 1")),
    /theorems\[0\]\.induction\.param/u,
    "ссылка мимо связки принята — область имён сняла сверку связи, а не выбор имени",
  )

  /* ПОДДЕЛКА 2: обе связки законны, но ссылка уведена с первой на вторую.
     Разбор такое пропускает; ловит взаимная однозначность имён: «а» уже
     ответило «a», вторым ответом «b» ему быть нельзя. */
  const парой = (английскийТекст) =>
    сверитьПоверхности(parse(ПАРА_СВЯЗОК_RU, "проба.flang"), parse(английскийТекст, "проба-english.flang"))
  парой(наАнглийском(ПАРА_СВЯЗОК_RU))
  const ссылкаНаДругую = наАнглийском(ПАРА_СВЯЗОК_RU)
    .replace("  induction on a decreases a", "  induction on b decreases b")
  assert.notEqual(ссылкаНаДругую, наАнглийском(ПАРА_СВЯЗОК_RU), "подмена 2 не применилась")
  assert.throws(
    () => парой(ссылкаНаДругую),
    /theorems\[0\]/u,
    "ссылка, уведённая на другую связку, принята — область имён сняла сверку связи",
  )

  /* И ОБРАТНОЕ: честное переименование связки ВМЕСТЕ со ссылками — зелено.
     Без этого две подделки выше доказывали бы лишь то, что сверка краснеет на
     любой правке, а требуется, чтобы она краснела на разъехавшейся связи и
     молчала на выборе имени. */
  const честное = наАнглийском(ПАРА_СВЯЗОК_RU)
    .replace("  given a: nat", "  given leftover: nat")
    .replace("  induction on a decreases a", "  induction on leftover decreases leftover")
  assert.notEqual(честное, наАнглийском(ПАРА_СВЯЗОК_RU), "подмена 3 не применилась")
  парой(честное)
})
