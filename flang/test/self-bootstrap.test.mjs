/**
 * Приглашение оболочки печатается ТОЛЬКО человеку за терминалом, поэтому и
 * проверить его можно только за терминалом. Псевдотерминал даёт `script` из
 * util-linux; его наличие и пригодность проверяются пробой, а не предполагаются
 * — иначе тест «проходил» бы молчанием там, где `script` зовётся иначе (BSD).
 */
function подТерминалом(команда, ввод) {
  const проба = spawnSync("script", ["-qec", "echo проба", "/dev/null"], { encoding: "utf8" })
  if (проба.status !== 0 || !проба.stdout.includes("проба")) {
    return null
  }
  return spawnSync("script", ["-qec", команда, "/dev/null"], { input: ввод, encoding: "utf8" })
}

