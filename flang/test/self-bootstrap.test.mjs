/**
 * Сколько теорем эталон обязан положить в связанную программу — спрашивается ДО
 * всякого сличения байтов.
 *
 * Сверка двух сторон зеленеет и тогда, когда сверять нечего: набор, у которого
 * эталон теорем не построил вовсе, сравнивал бы пустоту с пустотой и молчал —
 * ровно тот род проверки, которая перестала сравнивать и продолжает зеленеть.
 * Здесь у каждого теоремного набора записано, чего ждать от САМОГО ЭТАЛОНА:
 * ключ обязан быть там, где ему положено, и обязан отсутствовать там, где не
 * положено. Испортится сам набор (опечатка в теореме, съеденная строка) — тест
 * скажет об этом прямо, а не проглотит.
 */
const ЖДЁМ_ТЕОРЕМ = new Map([
  ["теорема входного файла едет в связанную программу", 1],
  ["без теоремы ключа `theorems` в программе нет", 0],
  ["теорема импортированного модуля едет за своей функцией", 1],
])

/* Перевод JSON → «Значение» из `flang/core/json.flang`: механический, как в
   соседних тестах слоёв, и ровно поэтому надёжный — он ничего не решает. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })
function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

const исходникиДля = (файлы) => Object.entries(файлы).map(([путь, текст]) => ({ путь, текст }))

test("связывание на flang повторяет src/link.mjs: программа и диагностики", async () => {
  for (const [имя, вход, файлы] of НАБОРЫ) {
    const { diagnostics: беды, ...программа } = await linkProgram(вход, файлы[вход], parse, {
      readFile: async (файл) => {
        if (!Object.hasOwn(файлы, файл)) throw new Error(`ENOENT: ${файл}`)
        return файлы[файл]
      },
    })

    const ждём = ЖДЁМ_ТЕОРЕМ.get(имя)
    if (ждём !== undefined) {
      assert.equal(программа.theorems?.length ?? 0, ждём, `${имя}: у ЭТАЛОНА теорем не столько — сверять нечего`)
    }
    /* И у чужого модуля теорема обязана БЫТЬ: иначе третий набор проверял бы,
       что близнец не потащил того, чего нет. */
    if (имя === "теорема импортированного модуля едет за своей функцией") {
      assert.equal(parse(файлы["/в/опора.flang"], "/в/опора.flang").theorems?.length, 1, `${имя}: в чужом модуле теоремы нет`)
    }

    const наш = evaluate(
      компилятор,
      "Печать связанного AST",
      { файлы: исходникиДля(файлы), вход },
      { maxSteps: 40_000_000, maxDepth: 20_000 },
    )
    assert.equal(наш, JSON.stringify(программа), `${имя}: связанная программа разошлась`)

    const проверка = evaluate(
      компилятор,
      "Связать исходники",
      { файлы: исходникиДля(файлы), вход },
      { maxSteps: 40_000_000, maxDepth: 20_000 },
    )
    assert.deepEqual(
      проверка["диагностики"].map((беда) => [беда["код"], беда["сообщение"]]),
      беды.map((беда) => [беда.code, беда.message]),
      `${имя}: диагностики связывания разошлись`,
    )
  }
})

