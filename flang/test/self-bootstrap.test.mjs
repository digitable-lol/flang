/**
 * Спуск по числовой мере: `н минус 1` при базе `н не больше 0`. Программа
 * доказуемо тотальна, и доказательство держится на мере — значит эталон ставит
 * на этом вызове сторож `FLANG_MEASURE`, потому что на double спуск идёт не
 * всегда: при |н| ≥ 2⁵³ шаг не меняет значения вовсе.
 */
const МЕРА = `модуль «Счёт»

тотальная функция «До нуля»
  принимает «н»: число
  возвращает число
  если «н» не больше 0
    то 0
    иначе «До нуля» от («н» минус 1)
`

/**
 * Сверка печатей на программе с мерой — без компилятора C.
 *
 * Побайтовая сверка flang₁ с эталоном ниже сильнее этой во всём, кроме одного:
 * она ПРОПУСКАЕТСЯ, когда `cc` не найден. А расхождение, которое здесь
 * стережётся, — единственное, которым два компилятора расходились на настоящих
 * программах репозитория, и цена ему не «другой байт», а зацикливание вместо
 * отказа. Поэтому оно проверяется и на вычислителе, где никакого `cc` не надо:
 * печать на flang идёт через тот же `Печать в C от исходников`, только
 * интерпретируемый.
 */
test("печать на flang ставит сторож меры там же, где эталон", async () => {
  const { diagnostics: беды, ...программа } = await linkProgram("счёт.flang", МЕРА, parse, {
    readFile: async (файл) => {
      throw new Error(`импортов тут нет: ${файл}`)
    },
  })
  assert.deepEqual(беды, [])
  /* Если сторожа нет у эталона, сверять нечего, и тест сторожит пустоту. */
  const сторожа = checkTotality(программа).guards
  assert.equal(сторожа.length, 1, "эталон не нашёл меры — программа перестала быть тем, ради чего стоит тут")
  assert.equal(сторожа[0].param, "н")

  /* Обе отметки, и по той же причине, что в сверке ниже: печатает эталон
     ОТМЕЧЕННУЮ программу, и близнец с той же минуты кладёт обе сам
     («Напечатать связанное» в `self/bootstrap/compiler.flang»). Сверять его
     с печатью полуотмеченной значило бы сверять с тем, чего нет. */
  const эталон = emitC(markProven(markMeasureGuards(программа)), ПРЕДЕЛЫ_ОБЫЧНЫЕ)
  assert.ok(
    эталон.files.some((файл) => файл.content.includes("FLANG_MEASURE")),
    "эталон напечатал программу с мерой без сторожа",
  )

  const наш = evaluate(
    компилятор,
    "Печать в C от исходников",
    { файлы: исходникиДля({ "счёт.flang": МЕРА }), вход: "счёт.flang", настройки: настройкиОбычные(программа) },
    { maxSteps: 40_000_000, maxDepth: 20_000 },
  )
  assert.deepEqual(наш["диагностики"], [], "связывание на flang дало диагностики")
  assert.equal(наш["ошибка"], "", "печать на flang отказала")
  assert.deepEqual(
    наш["файлы"].map((файл) => файл["путь"]),
    эталон.files.map((файл) => файл.path),
    "разошёлся набор напечатанных файлов",
  )
  for (const [индекс, файл] of эталон.files.entries()) {
    const мой = наш["файлы"][индекс]["содержимое"]
    if (мой === файл.content) continue
    const слева = файл.content.split("\n")
    const справа = мой.split("\n")
    const номер = слева.findIndex((текст, i) => текст !== справа[i])
    assert.fail(
      `${файл.path} разошёлся на строке ${номер + 1}\n` +
        `  эталон: ${JSON.stringify(слева[номер])}\n` +
        `  flang:  ${JSON.stringify(справа[номер])}`,
    )
  }
})

