/*
 * ПУТЬ УСТАНОВКИ — ТО, ЧЕГО НЕ ПРОХОДИЛ НИКТО, И ПОТОМУ ОН ЛОМАЛСЯ ЧЕТЫРЕЖДЫ
 * ЗА ОДИН ДЕНЬ.
 *
 * Всё, что выше, гоняет flang₁ ТАМ, ГДЕ ОН СОБРАН, — то есть рядом с его
 * собственными исходниками. Поставивший язык из brew или asdf оказывается в
 * другом месте: у него есть `bin/flang`, `lib/*.a`, `include/*.h` — и больше
 * ничего. Разница в этом «больше ничего» стоила команде `flang emit --target c`
 * работоспособности у ВСЕХ установленных пользователей: печать кладёт в вывод
 * четыре файла рантайма дословно, читает их с диска и не находит.
 *
 * Здесь путь пройден целиком: префикс раскладывается ровно так, как это делают
 * формула и плагин, и печать зовётся из него. Три вещи проверяются отдельно,
 * потому что ломались они порознь:
 *
 *   1. С `share/flang/c` печать РАБОТАЕТ и кладёт файлы;
 *   2. без него — отказывает, и отказ называет, чего не хватило (иначе первая
 *      проверка проходила бы и на бинарнике, который нашёл рантайм где-то ещё,
 *      и ничего бы не сторожила);
 *   3. каталог вывода заводится САМ — как у версии для Node. Прежде не
 *      заводился, и отказ винил первый файл рантайма, а не отсутствующий
 *      каталог; человек читал это как поломку рантайма и был прав для такого
 *      текста.
 *
 * Имена берутся из `scripts/release-layout.mjs` — оттуда же, откуда их берёт
 * скрипт релиза, — а совпадение с двумя упаковками сверяется отдельно ниже.
 */
test("установленный flang печатает в C: префикс как у формулы, каталог вывода заводится сам", (t) => {
  if (flang1 === null) {
    missingToolchain(t, "c", "компилятора C нет — flang₁ не собран, пропуск")
    return
  }
  const собрано = join(workdir, "flang1")
  const префикс = join(workdir, "префикс")
  for (const часть of ["bin", "lib", "include", РАНТАЙМ_ПРИ_УСТАНОВКЕ]) {
    mkdirSync(join(префикс, часть), { recursive: true })
  }
  writeFileSync(join(префикс, "bin/flang"), readFileSync(flang1))
  execFileSync("chmod", ["0755", join(префикс, "bin/flang")])
  for (const имя of readdirSync(собрано).filter((имя) => имя.endsWith(".a") || имя.endsWith(".h"))) {
    writeFileSync(join(префикс, имя.endsWith(".a") ? "lib" : "include", имя), readFileSync(join(собрано, имя)))
  }

  const проба = join(префикс, "проба.flang")
  writeFileSync(проба, "модуль «Проба»\n\nтотальная функция «Два»\n  возвращает число\n  2\n", "utf8")
  /* FLANG_RUNTIME_DIR снимается нарочно: с ним печать нашла бы рантайм в обход
     префикса, и проверка молчала бы ровно о том, ради чего написана. */
  const печатать = (куда) =>
    spawnSync(join(префикс, "bin/flang"), ["emit", проба, "--target", "c", "--out", куда], {
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      env: { ...process.env, FLANG_RUNTIME_DIR: "" },
    })

  /* 2. Сначала БЕЗ рантайма: отказ обязан быть и обязан быть понятным. */
  const без = печатать(join(префикс, "без-рантайма/вывод"))
  assert.equal(без.status, 2, `без ${РАНТАЙМ_ПРИ_УСТАНОВКЕ} печать обязана отказать: ${без.stderr}`)
  assert.match(без.stderr, /не найдены исходники рантайма C/u, `отказ не назвал причину: ${без.stderr}`)
  assert.match(без.stderr, /--runtime/u, "отказ не сказал, что делать")

  /* 1. Теперь как ставят формула и плагин — каталог `runtime-c` из архива
     целиком в `share/flang/c`. В дереве репозитория его источник тот же, что у
     скрипта релиза. */
  for (const имя of РАНТАЙМ_ФАЙЛЫ) {
    const текст = readFileSync(join(корень, РАНТАЙМ_В_ДЕРЕВЕ, имя), "utf8")
    /* Смотрится ШАПКА, а не весь файл: `flang_repl.c` сам эту строку и ищет
       (`emit_runtime_here`), и по всему тексту он отвергал бы сам себя. */
    assert.ok(
      !текст.slice(0, 400).includes("Сгенерировано flang"),
      `${имя} в ${РАНТАЙМ_В_ДЕРЕВЕ} — напечатанная копия, а не исходник: печать такую отвергает`,
    )
    writeFileSync(join(префикс, РАНТАЙМ_ПРИ_УСТАНОВКЕ, имя), текст, "utf8")
  }

  /* 3. Каталог вывода назван несуществующий, и притом в два уровня. */
  const куда = join(префикс, "нет-такого/каталога")
  const с = печатать(куда)
  assert.equal(с.status, 0, `установленный flang не напечатал: ${с.stderr}`)
  const файлы = readdirSync(куда).sort()
  assert.ok(файлы.includes("flang_runtime.c"), `рантайм не приехал: ${файлы.join(", ")}`)
  assert.ok(файлы.includes("flang_runtime.h"), `заголовок не приехал: ${файлы.join(", ")}`)
  assert.ok(файлы.includes("Makefile"), `Makefile не приехал: ${файлы.join(", ")}`)

  /* И ни одной строки внутреннего жаргона в том, что человек прочитал. */
  for (const слово of ["свидетел", "таблицаВхода", "замыкание", "слой типов"]) {
    assert.ok(!с.stderr.includes(слово), `печать сказала человеку «${слово}»: ${с.stderr}`)
  }
})

