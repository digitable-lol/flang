/**
 * ТРЕТИЙ КЛЮЧ, И ОН НЕ ЗАКРЫВАЕТСЯ В СВЯЗЫВАНИИ.
 *
 * `requirements` — договор о функции, которая ЕЩЁ НЕ НАПИСАНА, — берётся у
 * входного файла и только у него, ровно как процессы и планы. В `src/link.mjs`
 * он есть; в `«Ключи входного файла»` эталона его 18 августа не было, и это
 * поправлено здесь же, в том же заходе.
 *
 * НО ПРОВЕРИТЬ ЭТОТ КЛЮЧ НАБОРОМ НЕЛЬЗЯ, и вот почему — измерено, а не
 * предположено: `self/parser.flang` не знает слова `требует` У ЛЕВОГО КРАЯ
 * вовсе. На программе с договором эталон отдаёт ПУСТУЮ программу
 * (`module: ""`, ни одной функции), а свидетель — полную, с ключом `requirements`.
 * То есть зазор здесь не в связывании, а СЛОЕМ ВЫШЕ, в разборе.
 *
 * ПОЧЕМУ ЭТО СТОИТ ОТДЕЛЬНЫМ ТЕСТОМ, А НЕ НАБОРОМ. Набор с `требует` красил бы
 * связывание за чужую беду и указывал бы не на тот слой. Убрать его совсем —
 * значит вернуть ключ в сон: он и спал ровно потому, что НИ ОДНА программа
 * дерева не пишет `требует` у левого края (проверено: ноль файлов `.flang`).
 * Поэтому зазор назван ИСПОЛНЯЕМЫМ: пока эталон не умеет — тест зелен и
 * держит факт; научится — покраснеет и потребует перенести набор в `НАБОРЫ`.
 */
test("НАЗВАННЫЙ ЗАЗОР: `требует` у левого края разбирает свидетель, но не эталон", async () => {
  const исходник =
    "модуль «М»\n\nтребует «Ещё не написана»\n  принимает «н»: число\n  возвращает число\n"
    + "  обеспечивает «удвоенное неотрицательно» результат не меньше 0\n"
  const свидетель = parse(исходник)
  assert.equal(свидетель.requirements?.length, 1, "свидетель перестал разбирать `требует` — сверять нечего")

  const файлы = { "/в/м.flang": исходник }
  const наш = evaluate(
    компилятор,
    "Печать связанного AST",
    { файлы: исходникиДля(файлы), вход: "/в/м.flang" },
    { maxSteps: 40_000_000, maxDepth: 20_000 },
  )
  assert.equal(
    JSON.parse(наш).module,
    "",
    "эталон разбора НАУЧИЛСЯ `требует` — зазор закрыт: перенесите набор с договором в НАБОРЫ и снимите этот тест",
  )
  assert.ok(
    !Object.hasOwn(JSON.parse(наш), "requirements"),
    "у эталона появился ключ `requirements` — зазор закрыт, снимайте этот тест",
  )
})
