/**
 * Сторож замороженной точки раскрутки.
 *
 * `bootstrap/` — это печать компилятора в C99, лежащая в дереве, и она нужна
 * ровно для одного: собрать компилятор, имея только `cc` и `make`, без Node.
 * Артефакт в дереве ценен, пока он правда та печать, которую дают исходники
 * рядом. Разойдись он на байт — и «сборка без Node» соберёт ПРОШЛЫЙ компилятор,
 * молча, потому что 4.5 МБ сгенерированного C никто глазами не читает. Точка
 * раскрутки, которая врёт, хуже отсутствующей: отсутствующую видно.
 *
 * Сверяется тем же, чем шаги 2 и 3, — побайтово, и той же печатью: отмеченная
 * программа (`markMeasureGuards`) с теми же `ПРЕДЕЛЫ`. Сравнение и разбор
 * расхождений — `расхождения` из `scripts/bootstrap-c.mjs`, то есть ровно то, что
 * зовёт `node scripts/bootstrap-c.mjs --check`: сторож в наборе и сторож в
 * командной строке обязаны отвечать одно и то же, а для этого им положено быть
 * одним кодом.
 *
 * Компилятор C здесь не нужен, и это главное свойство теста. Всё остальное в
 * этом файле, что доказывает неподвижную точку, пропускается без `cc` — а эта
 * проверка идёт всегда, на любой машине, и стоит секунды: она сверяет байты, а
 * не собирает.
 *
 * Что отсюда следует для сборки без Node. Если байты `bootstrap/` совпали с
 * печатью эталона, то компилятор, собранный из `bootstrap/` тем же `cc` с теми
 * же флагами, — это flang₁ и есть, тот же самый бинарник. Значит «шаги 2 и 3»
 * ниже доказывают заодно и годность точки раскрутки: собранный из неё компилятор
 * печатает те же исходники побайтово. Отдельной третьей сборки для этого не
 * нужно — нужно тождество байтов, и стережёт его этот тест.
 */
test("точка раскрутки bootstrap/ совпадает с печатью текущих исходников, побайтово", () => {
  /* Отметок ДВЕ, и обе обязаны стоять, потому что печатает `bootstrap/` не этот
     тест, а `scripts/bootstrap-c.mjs` через `loadProgram` — а он ставит обе.
     Забудь здесь вторую, и тест краснел бы на верной точке раскрутки, требуя
     перепечатать то, что и так перепечатано. */
  const напечатано = emitC(markProven(markMeasureGuards(компилятор)), ПРЕДЕЛЫ)
  const беды = расхождения(напечатано.files)
  assert.deepEqual(
    беды,
    [],
    `точка раскрутки ${КАТАЛОГ}/ разошлась с flang/self/*.flang. Перепечатайте её в том же ` +
      `коммите, что и правку компилятора: node scripts/bootstrap-c.mjs`,
  )
  const всего = напечатано.files.reduce((сумма, файл) => сумма + Buffer.byteLength(файл.content, "utf8"), 0)
  assert.ok(всего > 3_000_000, `в точке раскрутки всего ${всего} байт — это не компилятор целиком`)
})

/** Собирает напечатанные файлы в пустом каталоге и отдаёт путь к прогонщику. */
function собрать(файлы, куда) {
  mkdirSync(куда, { recursive: true })
  for (const файл of файлы) writeFileSync(join(куда, файл.path), файл.content, "utf8")
  const исходники = файлы.filter((файл) => файл.path.endsWith(".c")).map((файл) => файл.path)
  try {
    execFileSync(cc, [...CFLAGS, ...БЕЗ_BIDI, ...исходники, "-o", "flang", "-lm"], {
      cwd: куда,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    })
  } catch (ошибка) {
    assert.fail(`${cc} не собрал напечатанный компилятор:\n${ошибка.stderr ?? ошибка.message}`)
  }
  return join(куда, "flang")
}

/** Один запрос — один процесс: прогонщик держит всё в арене до конца запроса. */
function спросить(бинарь, имя, аргументы, предел = null) {
  const запрос = `${JSON.stringify({ fn: имя, args: аргументы, depth: "200000" })}\n`
  const итог =
    предел === null
      ? spawnSync(бинарь, { input: запрос, encoding: "utf8", maxBuffer: 1024 * 1024 * 1024 })
      : spawnSync("/bin/sh", ["-c", `ulimit -v ${предел}; exec "$0"`, бинарь], {
          input: запрос,
          encoding: "utf8",
          maxBuffer: 1024 * 1024 * 1024,
        })
  assert.equal(итог.status, 0, `прогонщик не ответил: ${итог.stderr}`)
  return JSON.parse(итог.stdout.trim())
}

function раскодировать(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(раскодировать)
  if (Object.hasOwn(узел, "r")) return Object.fromEntries(узел.r.map(([ключ, вложенное]) => [ключ, раскодировать(вложенное)]))
  if (Object.hasOwn(узел, "v")) {
    return { variant: узел.v, fields: Object.fromEntries(узел.f.map(([ключ, з]) => [ключ, раскодировать(з)])) }
  }
  throw new Error(`нечего раскодировать: ${JSON.stringify(узел).slice(0, 80)}`)
}

/** Файл и всё, до чего дотягиваются его импорты: то же замыкание, что у линкера. */
function замыкание(путь, найдено = new Map()) {
  if (найдено.has(путь)) return найдено
  const текст = readFileSync(join(корень, путь), "utf8")
  найдено.set(путь, текст)
  let программа
  try {
    программа = parse(текст, путь)
  } catch {
    return найдено
  }
  const шапка = (программа.legacy ?? []).find((узел) => узел?.construct === "moduleHeader")
  for (const импорт of шапка?.value?.imports ?? []) {
    const части = путь.split("/").slice(0, -1)
    for (const кусок of импорт.from.split("/")) {
      if (кусок === ".") continue
      else if (кусок === "..") части.pop()
      else части.push(кусок)
    }
    замыкание(части.join("/"), найдено)
  }
  return найдено
}

