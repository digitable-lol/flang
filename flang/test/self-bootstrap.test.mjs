/* ─────────────────── шаг 2: память, которой хватает ─────────────────── */

/**
 * Здесь два года стояла стена, и она была не про язык, а про рантайм.
 *
 * `добавить` — единственный способ удлинить список, и он копировал: рантайм на
 * C выделял новый массив из n+1 `fl_value` и делал `memcpy`. Арена же не отдаёт
 * ничего до конца запроса — это её договор, записанный в шапке
 * `flang_runtime.h`. Значит список из n элементов, собранный n вызовами
 * `добавить`, оставлял после себя ~16·n² байт мусора, который никто не соберёт.
 * Под сборщиком мусора (JS, интерпретатор) этого не видно: живой памяти всё
 * время O(n), и разница между реализациями была не в алгоритме, а в том, что
 * одна отдаёт память, а другая нет.
 *
 * Лексер собирает поток токенов ровно так, и цена была измерена:
 *
 *   файл                     токенов   было      стало
 *   flang/core/json.flang       3 485   0.20 ГБ   0.01 ГБ
 *   flang/self/lexer.flang      8 610   1.20 ГБ   0.04 ГБ
 *   flang/core/parser.flang    23 184   8.29 ГБ   0.06 ГБ
 *   flang/self/parser.flang    35 276  18.90 ГБ   0.09 ГБ
 *
 * Левый столбец — это 16·n² с точностью до пяти процентов; сумма по восьми
 * файлам компилятора (119 тысяч токенов, шесть из них разбираются дважды —
 * второй проход `src/link.mjs`) давала порядка 90 ГБ, то есть шаг 2 не
 * проходил ни на этой машине, ни на разумной другой.
 *
 * Правый столбец — после того как `добавить` перестал копировать: массив
 * выделяется с запасом, элемент дописывается в запас на месте, а неизменяемость
 * держит счётчик занятых ячеек (`fl_b_dobavit`, `flang/src/emit/c/flang_runtime.c`;
 * само свойство проверяется в `flang/test/emit-c.test.mjs`). Расход стал
 * линейным.
 *
 * Тест ниже держит это измеренным и от машины не зависит: предел ставит он сам.
 * Граница проходит там, где прежняя реализация промахивалась на ПОРЯДКИ, а не
 * на проценты, — поэтому её не сдвинут ни аллокатор, ни разрядность указателя.
 *
 * ── Почему предел на связывание поднят с 4 ГБ до 8 ─────────────────────────
 *
 * Не потому, что что-то стало хуже, а потому, что компилятора стало больше.
 * Точный натуральный тип добавил в два самых крупных файла самоприменения около
 * тысячи строк: `self/types.flang` — отрезки, подтипизацию и сужение по
 * условию, `self/totality.flang` — точный шаг. Расход остался ЛИНЕЙНЫМ, вырос
 * ровно исходник, а прежний предел стоял к нужде вплотную.
 *
 * Числа мерены прогоном, а не выведены. Прежний замер: 4 ГБ не хватает, 8 ГБ
 * хватает. ЗАМЕР ПОСЛЕ ВТАСКИВАНИЯ ЯДРА ДОКАЗАТЕЛЬСТВА: 8 ГБ уже не хватает,
 * 12 ГБ хватает. Взято меньшее ПРОВЕРЕННОЕ; ещё точнее границу искать
 * незачем — она сдвинется от следующей же тысячи строк, а тест ловит не её.
 *
 * Почему сдвинулась: замыкание компилятора выросло с 2 560 функций до 3 431 —
 * в него въехали вычислитель и пять файлов ядра доказательства, — а исходников
 * в замыкании стало 18 файлов и 3 873 543 байта.
 *
 * Что тест ловит — ровно то же, ради чего написан. Копирующему `добавить` на те
 * же 119 тысяч токенов нужно было бы порядка 90 ГБ: в одиннадцать раз больше
 * нового предела. Граница по-прежнему проходит между ЛИНЕЙНЫМ и КВАДРАТИЧНЫМ, а
 * не между «влезло» и «не влезло», и ни аллокатор, ни разрядность указателя её
 * не сдвинут.
 *
 * 12 ГБ -> 20 ГБ ПРИ ВЛИВАНИИ ПАРЫ БИНАРНИКА (work/binary-emit и
 * work/binary-test-proof). Замыкание выросло снова: в него въехали печать в C и
 * дорога проверки с ядром четвёртым шагом — `self/bootstrap/compiler.flang`
 * поднялся с 211 строк до 591. Предел поднят по ЗАМЕРУ, а не на глаз: на 12 ГБ
 * связывание отвечает FLANG_MEMORY, на 20 ГБ проходит, и 29 проверок из 29
 * зелены.
 *
 * ДОВОД ТОТ ЖЕ И ОН НЕ ОСЛАБ. Граница проходит между ЛИНЕЙНЫМ и КВАДРАТИЧНЫМ:
 * копирующему `добавить` на этот же поток нужно было бы порядка 90 ГБ — вчетверо
 * с лишним больше нового предела. Двадцать гигабайт ловят квадратичность так же
 * надёжно, как ловили двенадцать; что они перестали бы ловить — так это рост
 * замыкания ещё вдвое, и тогда предел придётся двигать снова, снова замером.
 */
test("печать компилятора укладывается в память: поток токенов не копируется", (t) => {
  if (flang1 === null) {
    missingToolchain(t, "c", "компилятора C нет — flang₁ не собран, пропуск")
    return
  }
  const предел = 1024 * 1024 /* КБ, то есть 1 ГБ */

  /* Самый крупный файл репозитория: 35 276 токенов. Копирующему «добавить»
     нужно было бы на него 19 ГБ — в предел он промахнулся бы двадцатикратно. */
  const крупный = спросить(
    flang1,
    "Коды диагностик",
    [строка(readFileSync(join(корень, "flang/self/parser.flang"), "utf8"))],
    предел,
  )
  assert.equal(крупный.ok, true, `35 276 токенов обязаны укладываться в 1 ГБ: ${JSON.stringify(крупный)}`)
  assert.deepEqual(крупный.value.l, [], "лексика self/parser.flang чиста")

  /* И весь компилятор целиком — 119 тысяч токенов, шесть файлов дважды. */
  const все = спросить(flang1, "Печать связанного AST", [списокИсходников(замыкание(ВХОД)), строка(ВХОД)], 20 * 1024 * 1024)
  assert.equal(все.ok, true, `связывание всего компилятора не уложилось в 20 ГБ: ${JSON.stringify(все).slice(0, 200)}`)
  assert.equal(все.value.s, JSON.stringify(компилятор), "связанный AST компилятора разошёлся с эталоном")
})

/**
 * Шаги 2 и 3 — то, ради чего написано всё остальное.
 *
 * Сверяются не два, а три источника, и все побайтово:
 *   • C от flang₁ против C от эталона на JS — компилятор, напечатанный самим
 *     собой, обязан быть тем же файлом, что напечатал эталон. Это сильнее
 *     критерия SPEC и ловит расхождение сразу, до второй сборки;
 *   • C от flang₂ против C от flang₁ — собственно неподвижная точка;
 *   • и то, что flang₂ вообще собирается тем же `cc` с теми же флагами.
 *
 * Первое сравнение не заменяет второе: совпадение с эталоном говорит, что
 * flang₁ печатает правильно, а совпадение flang₂ с flang₁ — что правильно
 * печатает и программа, собранная из этой печати. Разойтись они могут порознь.
 */
test("шаги 2 и 3: flang₁ печатает сам себя, flang₂ печатает то же самое", (t) => {
  if (flang1 === null) {
    missingToolchain(t, "c", "компилятора C нет — flang₁ не собран, пропуск")
    return
  }
  const файлы = замыкание(ВХОД)
  const ответ = спросить(flang1, "Печать в C от исходников", [списокИсходников(файлы), строка(ВХОД), настройки(компилятор)])
  assert.equal(ответ.ok, true, `flang₁ не напечатал сам себя: ${JSON.stringify(ответ).slice(0, 300)}`)
  const итог = раскодировать(ответ.value)
  assert.deepEqual(итог["диагностики"], [])
  assert.equal(итог["ошибка"], "")

  /* Шаг 2: то же, что напечатал эталон, — иначе flang₁ понимает язык иначе.
     Отмеченная программа, а не связанная, и ОБЕИМИ отметками — по той же
     причине, что и в сверке корпуса выше: печатает эталон отмеченную. Третье
     из трёх мест, где сверка сравнивала flang₁ с печатью, которой эталон не
     даёт никому: здесь недостача пряталась под `#include <math.h>` — `fmod`
     печатается на доказанном месте, а через помощника не печатается вовсе. */
  const эталон = emitC(markProven(markMeasureGuards(компилятор)), ПРЕДЕЛЫ)
  assert.deepEqual(
    итог["файлы"].map((файл) => файл["путь"]),
    эталон.files.map((файл) => файл.path),
    "flang₁ напечатал не тот набор файлов",
  )
  for (const [индекс, файл] of эталон.files.entries()) {
    const мой = итог["файлы"][индекс]["содержимое"]
    if (мой === файл.content) continue
    const слева = файл.content.split("\n")
    const справа = мой.split("\n")
    const строкаРасхождения = слева.findIndex((текст, номер) => текст !== справа[номер])
    assert.fail(
      `компилятор, напечатанный самим собой, разошёлся с эталоном: ${файл.path}, строка ${строкаРасхождения + 1}\n` +
        `  эталон: ${JSON.stringify(слева[строкаРасхождения])}\n` +
        `  flang₁: ${JSON.stringify(справа[строкаРасхождения])}`,
    )
  }

  /* Шаг 3: C от flang₁ и C от flang₂ обязаны совпасть побайтово. */
  const flang2 = собрать(
    итог["файлы"].map((файл) => ({ path: файл["путь"], content: файл["содержимое"] })),
    join(workdir, "flang2"),
  )
  const второй = спросить(flang2, "Печать в C от исходников", [списокИсходников(файлы), строка(ВХОД), настройки(компилятор)])
  assert.equal(второй.ok, true, `flang₂ не напечатал компилятор: ${JSON.stringify(второй).slice(0, 300)}`)
  const итог2 = раскодировать(второй.value)
  assert.deepEqual(
    итог2["файлы"].map((файл) => [файл["путь"], файл["содержимое"]]),
    итог["файлы"].map((файл) => [файл["путь"], файл["содержимое"]]),
    "неподвижная точка не сошлась: C от flang₁ и C от flang₂ разошлись",
  )
  t.diagnostic(`неподвижная точка сошлась: ${итог["файлы"].length} файлов совпали побайтово у эталона, flang₁ и flang₂`)
})

