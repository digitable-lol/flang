function принимает(ключи) {
  const пробник = join(workdir, "probe.c")
  writeFileSync(пробник, "int main(void) { return 0; }\n", "utf8")
  return spawnSync(cc, [...ключи, пробник, "-o", join(workdir, "probe")], { encoding: "utf8" }).status === 0
}

/* ─────────────────── связанная программа компилятора ─────────────────── */

const исходникВхода = readFileSync(join(корень, ВХОД), "utf8")
const связано = await linkProgram(join(корень, ВХОД), исходникВхода, parse)
const { diagnostics: бедыСвязывания, ...компилятор } = связано
const свой = parse(исходникВхода, ВХОД)
/* Седьмой слой — связывание. Он уехал из обёртки в свой файл
   (`flang/self/link.flang`), и вместе с ним уехали его исполняемые примеры;
   поэтому «примеры обёртки» ниже судит оба файла точки раскрутки, а не один. */
const СЛОЙ_СВЯЗЫВАНИЯ = "flang/self/link.flang"
const свойСвязывания = parse(readFileSync(join(корень, СЛОЙ_СВЯЗЫВАНИЯ), "utf8"), СЛОЙ_СВЯЗЫВАНИЯ)

test("семь слоёв связываются в одну программу без столкновения имён", () => {
  /* Столкновений было 52: слои писались порознь, и у каждого нашлись свои
     «Узел ничто», «Диагностика», «Как в JS». Это первая проверка, потому что
     без неё нет и программы: `src/link.mjs` сливает объявления в одно плоское
     пространство имён, и повтор имени там — ошибка, а не перекрытие. */
  assert.deepEqual(бедыСвязывания, [], "связывание семи слоёв дало диагностики")
  assert.equal(компилятор.module, "Compiler flang")
  assert.ok(компилятор.functions.length > 1200, `функций после связывания ${компилятор.functions.length}`)
  const имена = компилятор.functions.map((функция) => функция.name)
  assert.equal(new Set(имена).size, имена.length, "одно имя досталось двум функциям")
  const типы = компилятор.types.map((тип) => тип.name)
  assert.equal(new Set(типы).size, типы.length, "одно имя досталось двум типам")
  /* Все семь слоёв на месте, а не «связалось что-то одно». Понижение приезжает
     не само по себе, а через печать, и забыть его нельзя молча
     (`stdlib/higher-order.flang` тогда не напечатается); связывание — наоборот,
     названо в обёртке прямо, и его точка входа тоже обязана быть здесь. */
  for (const имя of [
    "Токены",
    "Разбор исходника",
    "Проверить типы",
    "Проверить тотальность",
    "Печать программы",
    "Дефункционализировать",
    "Связать исходники",
  ]) {
    assert.ok(имена.includes(имя), `точки входа слоя «${имя}» нет в связанной программе`)
  }
})

test("связанный компилятор проходит проверку типов и анализ завершаемости", () => {
  assert.deepEqual(checkTypes(компилятор).diagnostics, [], "проверка типов дала диагностики")
  assert.deepEqual(checkTotality(компилятор).diagnostics, [], "анализ завершаемости дал диагностики")
})

test("примеры обёртки и слоя связывания сходятся", () => {
  let счёт = 0
  for (const функция of [...свой.functions, ...свойСвязывания.functions]) {
    for (const пример of функция.examples ?? []) {
      счёт += 1
      assert.deepEqual(
        evaluate(компилятор, функция.name, пример.args, { maxSteps: 10_000_000 }),
        пример.expected,
        `«${функция.name}» / «${пример.name}»`,
      )
    }
  }
  assert.ok(счёт >= 2, `примеров всего ${счёт}`)
})

