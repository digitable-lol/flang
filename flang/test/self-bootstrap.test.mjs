/* ─────────────────── шаг 2: стена, а не расхождение ─────────────────── */

/**
 * Почему неподвижная точка не сошлась — и почему это не про язык.
 *
 * `добавить` — единственный способ удлинить список, и он копирует: рантайм на C
 * выделяет новый массив из n+1 `fl_value` и делает `memcpy` (`fl_b_dobavit`,
 * `flang_runtime.c`). Арена же не отдаёт ничего до конца запроса — это её
 * договор, записанный в шапке `flang_runtime.h`. Значит список из n элементов,
 * собранный n вызовами `добавить`, оставляет после себя ~16·n² байт мусора,
 * который никто не соберёт. Под сборщиком мусора (JS, интерпретатор) это
 * незаметно: живой памяти всё время O(n).
 *
 * Лексер собирает поток токенов ровно так. Отсюда измеренное:
 *
 *   файл                     токенов   пик памяти
 *   flang/core/json.flang       3 485      0.20 ГБ
 *   flang/self/lexer.flang      8 610      1.20 ГБ
 *   flang/core/parser.flang    23 184      8.29 ГБ
 *   flang/self/parser.flang    35 276     18.90 ГБ
 *
 * — то есть 16·n² с точностью до пяти процентов. Собственные исходники
 * компилятора — это 119 тысяч токенов на восемь файлов, и каждый файл с
 * импортами разбирается дважды (второй проход `src/link.mjs`); сумма 16·n² по
 * файлам даёт порядка 90 ГБ. Ни на этой машине, ни на разумной другой шаг 2 не
 * проходит, и никакое дробление на запросы не помогает: одного `self/parser.flang`
 * хватает, чтобы упереться.
 *
 * Тест ниже это и закрепляет — без привязки к машине: предел ставится самим
 * тестом, и граница проходит между двумя настоящими файлами репозитория.
 */
test("шаг 2 упирается в память: поток токенов строится копированием", (t) => {
  if (flang1 === null) {
    missingToolchain(t, "c", "компилятора C нет — flang₁ не собран, пропуск")
    return
  }
  const предел = 4 * 1024 * 1024 /* КБ, то есть 4 ГБ */

  const мелкий = спросить(flang1, "Коды диагностик", [строка(readFileSync(join(корень, "flang/core/json.flang"), "utf8"))], предел)
  assert.equal(мелкий.ok, true, "3 485 токенов обязаны укладываться в 4 ГБ")
  assert.deepEqual(мелкий.value.l, [], "лексика core/json.flang чиста")

  const крупный = спросить(
    flang1,
    "Коды диагностик",
    [строка(readFileSync(join(корень, "flang/self/parser.flang"), "utf8"))],
    предел,
  )
  assert.equal(крупный.ok, false, "35 276 токенов в 4 ГБ уложиться не могут — стена исчезла?")
  assert.equal(крупный.code, "FLANG_MEMORY", `ожидалась нехватка памяти, получено ${крупный.code}: ${крупный.message}`)
})

