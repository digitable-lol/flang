/**
 * Неподвижная точка самоприменения: компилятор flang, собранный сам собой.
 *
 * Критерий — `flang/self/SPEC.md`, раздел «Критерий готовности — неподвижная
 * точка», и он ровно один:
 *
 *   1. компилятор на JS печатает `self/*.flang` → C → собирается → flang₁
 *   2. flang₁ печатает те же `self/*.flang`     → C → собирается → flang₂
 *   3. C от flang₁ и C от flang₂ совпадают побайтово
 *
 * Здесь этот путь пройден до конца: неподвижная точка сходится, и все три
 * печати — эталона на JS, flang₁ и flang₂ — совпадают побайтово.
 *
 * Долго не сходился шаг 2, и упирался он не в различие в понимании языка, а в
 * память: `добавить` копировал список целиком, арена не отдаёт ничего до конца
 * запроса, и поток токенов стоил ~16·n². На собственных исходниках компилятора
 * это давало порядка 90 ГБ. Стена снята в рантайме — «добавить» дописывает в
 * хвостовой запас массива (`fl_b_dobavit`, `flang/src/emit/c/flang_runtime.c`),
 * — и те же 119 тысяч токенов теперь стоят 2.4 ГБ. Мера осталась в наборе, см.
 * «печать компилятора укладывается в память» ниже.
 *
 * ── Что проверяется без компилятора C ───────────────────────────────────────
 * Что шесть слоёв вообще СВЯЗЫВАЮТСЯ в одну программу: до этой работы они жили
 * порознь, и 52 имени у них общие. Что связанная программа проходит типы и
 * анализ завершаемости. И что связывание, написанное на flang
 * (`self/bootstrap/compiler.flang`), повторяет `src/link.mjs` — слияние
 * объявлений, `только`, `экспортирует`, повтор имени, цикл импортов, второй
 * проход по вызовам без аргументов — на синтетических наборах файлов, где
 * сверяется и связанная программа целиком, и её диагностики.
 *
 * ── Что проверяется с компилятором C ────────────────────────────────────────
 * Шаг 1 целиком: C печатается, собирается `cc -std=c99 -Wall -Wextra -Werror
 * -pedantic`, получается flang₁. Дальше flang₁ гоняется как настоящий
 * компилятор — на 38 программах репозитория, вплоть до самых крупных, — и обязан:
 *   • напечатать тот же C, что эталон, ПОБАЙТОВО;
 *   • построить тот же связанный AST, побайтово после сериализации;
 *   • выдать те же диагностики и тот же вердикт — на чистых программах и на
 *     сломанных, где ошибка есть в каждой из шести категорий.
 * Это и есть требование SPEC «flang₁ обязан давать те же вердикты и
 * диагностики, что версия на JS».
 *
 * Шаги 2 и 3: flang₁ печатает свои собственные 760 КБ исходников, из этого
 * собирается flang₂, и он печатает их снова. Сверяется всё, что можно сверить:
 * печать flang₁ — с печатью эталона, печать flang₂ — с печатью flang₁. Совпасть
 * обязаны байты, а не «примерно то же самое».
 *
 * ── Точка раскрутки: единственная проверка здесь, которой не нужен cc ───────
 * `bootstrap/` — печать компилятора в C99, лежащая в дереве: ради неё сборка
 * компилятора обходится без Node вовсе (`make -C bootstrap`). Артефакт в дереве
 * ценен, пока он правда та печать, которую дают исходники рядом, — и тест «точка
 * раскрутки bootstrap/ совпадает с печатью текущих исходников, побайтово»
 * сторожит ровно это. Сверяет он байты, а не сборку, поэтому идёт ВСЕГДА, в
 * отличие от всего остального ниже.
 *
 * Отсюда следует то, что избавляет набор от третьей сборки: если байты
 * `bootstrap/` совпали с печатью эталона, то собранный из `bootstrap/` компилятор
 * — это flang₁ и есть, тот же бинарник. Значит шаги 2 и 3 доказывают заодно
 * годность точки раскрутки.
 *
 * ── Если компилятора C нет ──────────────────────────────────────────────────
 * Тесты, которым он нужен, честно пропускаются через `missingToolchain`
 * (flang/test/toolchain-guard.mjs) — тем же способом, что в
 * `cli-emit.test.mjs`. `FTS_REQUIRE_TOOLCHAINS=c` превращает пропуск в падение —
 * и с 13 августа 2026 CI это и требует. Прежде не мог: узкий гейт при любом
 * заданном значении требовал ВСЕ восемь тулчейнов, поэтому `c` в CI красил прогон
 * на отсутствии Go, Rust и Java, и самая сильная проверка репозитория
 * пропускалась молча.
 *
 * ── ПРЕДОБРАБОТКА ЭТАЛОНА: markMeasureGuards, markProven, dropUnreachable ──
 *
 * Эталону здесь дают не текст, а готовый AST, — и что именно на него положено
 * перед печатью, обязано совпадать с работой, а не с близнецом. Передний край
 * (`flang/bin/flang.mjs`, `loadProgramFromSource`) кладёт ОБЕ отметки, всегда:
 * `markProven(markMeasure(program))`. Печать читает обе. Значит и здесь стоят
 * обе; программу с одной отметкой из двух эталон не отдаёт никому, и сверка с
 * ней сравнивала бы близнеца с печатью, которой не бывает. Без них сверка
 * молчала бы обо всех местах, где эталон печатает доказанное выражение, а
 * близнец — вызов помощника: `markProven` пары на flang не имеет вовсе.
 *
 * `dropUnreachable` — третье, и оно НЕ отметка, а условие прохода: передний
 * край отбрасывает недостижимое для `emit --target c` и не отбрасывает для
 * сборки компилятора (`оболочка: true` зовёт «Токены» по имени). Обе половины
 * и сверяются — по одной на каждый случай, — а не одна за обе. Без него
 * покраснела бы верная печать: эталон урезает, близнец урезает, и требовать от
 * обоих неурезанного значило бы требовать того, чего ни один не делает.
 *
 * Шаги 2 и 3 стоят двух сборок компилятора вместо одной — это самая долгая
 * проверка в наборе (минуты, не секунды). Она всё равно идёт всегда: ради неё
 * написано всё остальное, и «неподвижная точка сходится» — не то утверждение,
 * которое имеет смысл проверять по праздникам.
 */
