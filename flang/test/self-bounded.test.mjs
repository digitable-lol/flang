/**
 * Бюджет разбора. ЧИСЛА СНЯТЫ ПРОГОНОМ, А НЕ ПОДОБРАНЫ.
 *
 * Меряет их сам вычислитель: `среда.call(…, { отчёт })` кладёт в отчёт число
 * сделанных витков, и двоичный поиск по пределу для этого не нужен вовсе. Самые
 * дорогие СВЯЗАННЫЕ программы корпуса:
 *
 *     flang/self/repl/repl.flang           287 096 888 витков   2428 функций
 *     flang/self/bootstrap/compiler.flang  211 597 878          2028
 *     flang/self/monad.flang                86 728 753          1201
 *     flang/self/sets.flang                 71 299 405          1074
 *
 * Весь корпус связкой стоит 1 049 972 388 витков и 148 секунд; разбором —
 * вчетверо меньше. Предел взят ДВУКРАТНЫМ запасом над самой дорогой, тем же
 * правилом, каким его берёт сосед по анализу (`self-totality.test.mjs`), а не
 * «чтобы прошло»: 280 миллионов, которых хватает соседу, здесь уже не хватало —
 * это случилось и было названо числом, а не обойдено молча.
 *
 * Цена НА ФУНКЦИЮ при этом ровная: 118 тыс. витков у `repl.flang`, 104 тыс. у
 * `compiler.flang`, 72 тыс. у `monad.flang`, 65 тыс. у `parser.flang`. Обход
 * остался линейным по числу узлов; поиск в памяти и в таблице описаний —
 * линейным по числу функций, и именно это даёт лёгкий рост цены на функцию у
 * самых больших программ. Станет он квадратичным — упрётся в предел и будет
 * назван, ровно за этим предел и стоит.
 *
 * Глубина поднята и поднята по делу: рекурсия здесь идёт не только по
 * вложенности выражения, но и ПО ГРАФУ ВЫЗОВОВ разбираемой программы — у
 * эталона её держит только стек JavaScript, и обещать тут нечего ни ему, ни
 * близнецу. Упрётся — будет назван отказом, а не молчанием.
 */
const ШАГИ = { maxSteps: 580_000_000, maxDepth: 200_000 }
const среда = createRuntime(программаСлоя, ШАГИ)

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Своя копия здесь нужна, иначе
   тест проверял бы себя переводом, который сам же и сверяет. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/**
 * Оценки витков на flang, приведённые к форме эталона.
 *
 * Отсутствие оценки у эталона — `null`, у близнеца — признак «есть оценка»:
 * необязательных полей записи в языке нет. Отсутствие спуска помечено минус
 * единицей, потому что позиция параметра отрицательной не бывает.
 */
function наши(ast) {
  return среда.call("Оценить витки", { "программа": значение(ast) }).map((запись) => [
    запись["имя"],
    {
      оценка: запись["итог"]["есть оценка"] ? запись["итог"]["многочлен"] : null,
      причина: запись["итог"]["есть оценка"] ? null : запись["итог"]["причина"],
      спуск: запись["итог"]["спуск"] < 0 ? null : запись["итог"]["спуск"],
    },
  ])
}

/**
 * Побайтовое расхождение двух итогов — вместе с ПОРЯДКОМ КЛЮЧЕЙ.
 *
 * Номер знака в ответе обязателен: «не совпало» на записи в сто тысяч знаков
 * заставляет искать разницу глазами, а найти её надо за один взгляд.
 */
function расхождение(эталон, наш) {
  const слева = JSON.stringify(эталон)
  const справа = JSON.stringify(наш)
  if (слева === справа) return null
  const знаки = [...слева]
  const место = знаки.findIndex((знак, номер) => знак !== справа[номер])
  const окно = (текст) => текст.slice(Math.max(0, место - 40), место + 120)
  return `разошлось на знаке ${место === -1 ? слева.length : место}:\n    эталон …${окно(слева)}…\n    наш    …${окно(справа)}…`
}

const расхождениеОценок = (программа) => расхождение([...оценитьВитки(программа)], наши(программа))

