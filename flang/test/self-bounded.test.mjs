/**
 * НАЙДЕНО ПЕРЕНОСОМ: `ПРИЧИНЫ.ВЗАИМНАЯ` в отчёт не попадает НИКОГДА.
 *
 * Эталон возвращает её из `оценить` в единственном месте — когда имя уже лежит
 * в `вРаботе`, то есть при взаимной рекурсии, — и возвращает МИМО `итог.set`.
 * Единственный её читатель, случай `call` в `считать`, смотрит только на
 * `чужая.оценка === null` и называет свою беду по-своему: «зовёт функцию без
 * оценки «X»». Верхний цикл `оценитьВитки` ответ `оценить` отбрасывает вовсе.
 * Значит текста «взаимная рекурсия…» в возвращаемой карте не бывает ни при
 * какой программе — константа объявлена, экспортирована и мертва.
 *
 * Это НЕ означает, что ветку можно выбросить: пока она возвращает «оценки
 * нет», вызывающий получает свою беду; верни она оценку — вердикт поедет. Но
 * назвать находку надо, и проверяется она числом, а не словом: ноль вхождений
 * на всём корпусе и на всех нарочных программах, включая ту, что взаимную
 * рекурсию как раз и содержит.
 */
test("причина «взаимная рекурсия» до отчёта не доезжает ни разу — ни на корпусе, ни на пробах", (t) => {
  const текст = ПРИЧИНЫ.ВЗАИМНАЯ
  assert.ok(!причиныПрограмм().has(текст.split(" «")[0]), "проба с взаимной рекурсией назвала её прямо")
  const взаимных = итоги.reduce((сумма, итог) => сумма + итог.взаимных, 0)
  t.diagnostic(`«${текст}» на ${файлыКорпуса.length} программах корпуса: ${взаимных} вхождений`)
  assert.equal(взаимных, 0, "причина оказалась достижимой — находка устарела, правьте прозу")
  /* И обратная половина: программа со взаимной рекурсией в списке ЕСТЬ, и обе
     её функции остаются без оценки — иначе проверка выше была бы утверждением
     о корпусе, в котором взаимной рекурсии нет вовсе. */
  const пара = [...оценитьВитки(parse(ВЗАИМНАЯ, "проба.flang"))]
  assert.equal(пара.length, 2)
  for (const [, запись] of пара) {
    assert.equal(запись.оценка, null)
    assert.match(запись.причина, /зовёт функцию без оценки/u)
  }
})

