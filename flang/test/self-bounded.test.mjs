/**
 * Ограниченность функции, написанная на самом flang — `flang/self/bounded.flang`.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы оценка
 * витков на flang обязана совпасть с оценкой эталона `flang/src/bounded.mjs` —
 * те же многочлены, коэффициент в коэффициент, те же причины отказа, те же
 * позиции спуска И ТОТ ЖЕ ПОРЯДОК ПАМЯТИ. Сверка побайтовая; расхождение
 * печатается с номером знака.
 *
 * ── Улика, снятая прогоном ДО этой работы ───────────────────────────────────
 * Близнеца не было вовсе, а закон этот задевает ВЕСЬ корпус, а не пять файлов
 * с категориями: оценку получает КАЖДАЯ функция каждой программы. Числом —
 * 233 программы, 6 760 функций разбором и 18 588 после связывания; оценка есть
 * у 8 654 из них, у 9 934 её нет с названной причиной. До сегодняшнего дня всё
 * это считал только эталон на JavaScript.
 *
 * Это делает сверку самой широкой в слое законов: у моноида и изоморфизма
 * сравнивать было нечего почти везде, здесь — везде есть.
 *
 * ── Чего здесь нет: вычислителя ─────────────────────────────────────────────
 * Ограниченность — единственный закон слоя, которому НЕ НАДО программу
 * выполнять. Ни оракула, ни таблицы вызовов, ни `self-evaluator.mjs`: обе
 * стороны читают один и тот же разобранный AST и ничего не вычисляют. Поэтому
 * и проверки «сломай вычислитель» здесь нет — ломать нечего; её место занимает
 * изъятие в самом близнеце.
 *
 * ── Что сверяется сверх оценки витков ───────────────────────────────────────
 * Вся арифметика многочленов: сложение, умножение, почленный максимум,
 * подстановка (схема Горнера над многочленами), значение при данном размере,
 * степень и печать словами. Она уезжает в диагностики и в отчёт мерки, значит
 * разойтись в ней — напечатать другое утверждение о том же коде.
 *
 * ── Порядок памяти — часть ответа, а не деталь ──────────────────────────────
 * Эталон возвращает `Map`, и порядок вставки в нём осмысленный: имя неизвестной
 * функции попадает туда В ТОТ МОМЕНТ, когда его встретили в теле, а имя
 * посчитанной — когда обход её тела закончился. Порядок этот виден снаружи
 * (`[...итог]`), поэтому близнец отдаёт список, а не отображение, и список
 * сверяется целиком.
 */
