/**
 * Многочлены для сверки арифметики.
 *
 * Взяты не наугад: пустой и нулевой (краевые для длины), постоянный, линейный,
 * квадратичный и кубический, многочлен с ДЫРОЙ посередине (нулевой средний
 * коэффициент — на нём ломается печать словами) и многочлен с нулём в старшем
 * разряде (на нём ломается степень).
 */
const МНОГОЧЛЕНЫ = [
  [],
  [0],
  [7],
  [0, 1],
  [7, 12],
  [1, 0, 3],
  [0, 0, 0, 5],
  [2, 3, 4, 5],
  [5, 0, 0],
  [1, 1],
  [12],
  [0, 0, 1],
]

test("сложение, максимум и умножение многочленов совпадают с эталоном на всех парах", () => {
  let пар = 0
  for (const первый of МНОГОЧЛЕНЫ) {
    for (const второй of МНОГОЧЛЕНЫ) {
      пар += 1
      assert.deepEqual(
        среда.call("Сложить многочлены", { "первый": первый, "второй": второй }),
        сложить(первый, второй),
        `сложение ${JSON.stringify(первый)} и ${JSON.stringify(второй)}`,
      )
      assert.deepEqual(
        среда.call("Максимум многочленов", { "первый": первый, "второй": второй }),
        максимум(первый, второй),
        `максимум ${JSON.stringify(первый)} и ${JSON.stringify(второй)}`,
      )
      /* `умножить` эталона на пустом первом множителе строит массив
         отрицательной длины и падает; такой пары у него не бывает — все
         многочлены счёта непусты, — поэтому и здесь она не сверяется. */
      if (первый.length === 0 || второй.length === 0) continue
      assert.deepEqual(
        среда.call("Умножить многочлены", { "первый": первый, "второй": второй }),
        умножить(первый, второй),
        `умножение ${JSON.stringify(первый)} и ${JSON.stringify(второй)}`,
      )
    }
  }
  assert.ok(пар >= 144, `пар всего ${пар}`)
})

test("подстановка, значение, степень и печать словами совпадают с эталоном", () => {
  for (const многочлен of МНОГОЧЛЕНЫ) {
    assert.equal(среда.call("Степень", { "многочлен": многочлен }), степень(многочлен), `степень ${JSON.stringify(многочлен)}`)
    assert.equal(
      среда.call("Текст оценки", { "многочлен": многочлен }),
      текстОценки(многочлен),
      `текст ${JSON.stringify(многочлен)}`,
    )
    for (const н of [0, 1, 2, 5, 100]) {
      assert.equal(
        среда.call("Значение многочлена", { "многочлен": многочлен, "н": н }),
        значениеМногочлена(многочлен, н),
        `значение ${JSON.stringify(многочлен)} при ${н}`,
      )
    }
    for (const аргумент of МНОГОЧЛЕНЫ) {
      if (аргумент.length === 0) continue
      assert.deepEqual(
        среда.call("Подставить", { "многочлен": многочлен, "аргумент": аргумент }),
        подставить(многочлен, аргумент),
        `подстановка ${JSON.stringify(многочлен)} в ${JSON.stringify(аргумент)}`,
      )
    }
  }
})

