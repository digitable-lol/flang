/*
 * ЕДИНСТВЕННОЕ ИЗМЕРЕННОЕ РАСХОЖДЕНИЕ ПРЕДСТАВЛЕНИЯ, и оно найдено прогоном, а
 * не предположено. Свидетель отличает вариант от записи КЛАССОМ
 * (`value instanceof FlangVariant`), а документ `«Значение»` класса не знает и
 * узнаёт вариант по форме: запись с непустой строкой в `variant` и полем
 * `fields`. Значит запись программы РОВНО с такими двумя полями от варианта
 * неотличима — здесь равна, у свидетеля нет.
 *
 * Это не огрех эталона: свидетель завёл варианту отдельный класс именно потому,
 * что служебная метка внутри записи столкнулась бы с полем пользователя, а
 * документ метку внутрь класть обязан — иначе он перестанет быть JSON. Разница
 * записана здесь проверкой, а не прозой: разойдись любая сторона — покраснеет.
 */
const самозванец = { variant: "Узел", fields: { л: 1 } }
const настоящий = variant("Узел", { л: 1 })
сверить("свидетель отличает вариант от записи-самозванца классом", false, valuesEqual(настоящий, самозванец))
сверить("эталон их не отличает: у документа класса нет", true, среда.call("Значения равны", { левое: вЗначение(настоящий), правое: вЗначение(самозванец) }))

/* ══════════ 8. ПОРЯДОК АРИФМЕТИКИ: (процент / 100) * значение ══════════ */

/* Сетка из 212 чисел — все целые до 200 и двенадцать дробей. Сверяется не
   только совпадение с `percentOf`, но и ЧИСЛО ПАР, на которых обратный порядок
   даёт другое значение: без этого числа довод «переписывать нельзя» был бы
   мнением. Считается на сетке пореже, чтобы не платить обходом 45 000 пар в
   вычислителе: полная сетка спрашивается у свидетеля, а у эталона — её край. */
const СЕТКА = [0, -0, 1, 2, 7, 35, 41, 57, 70, 99, 100, 200, 0.1, 0.3, 2.5, 7.3, 99.99, 1e-7, 1e7, NaN, Infinity, -Infinity]
let процентов = 0
let разошлисьПорядки = 0
for (const процент of СЕТКА) {
  for (const значение of СЕТКА) {
    процентов += 1
    сверить(`процентов от ${процент} и ${значение}`, percentOf(процент, значение), среда.call("Процентов от порядком", { процент, значение }))
    const обратный = среда.call("Процентов от обратным порядком", { процент, значение })
    if (!Object.is(обратный, percentOf(процент, значение))) разошлисьПорядки += 1
  }
}
if (разошлисьПорядки === 0) {
  расхождений += 1
  console.log("РАСХОЖДЕНИЕ: обратный порядок не разошёлся НИ РАЗУ — довод «переписывать нельзя» стал пустым")
}

