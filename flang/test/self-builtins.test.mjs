/** Годится ли значение этому роду — теми же вопросами, какими спрашивает свидетель. */
function годится(род, значение) {
  if (род === "строка") return typeof значение === "string"
  if (род === "число") return typeof значение === "number"
  if (род === "целое") return Number.isInteger(значение)
  return Array.isArray(значение)
}

function родМеста(места, позиция) {
  const место = места.find(([п]) => п === позиция)
  return место === undefined ? "строка" : место[2]
}

/**
 * Текст отказа глазами эталона. Целое — единственный род, у которого текстов
 * ДВА: `expectInteger` свидетеля сперва зовёт `expectNumber`, поэтому не-число
 * называется видом, а дробь — сама собой.
 */
function нашТекст(форма, роль, род, значение) {
  if (род === "целое") {
    if (typeof значение !== "number") {
      return среда.call("Отказ не число", { имя: форма, роль, значение: вЗначение(значение) })
    }
    return среда.call("Отказ не целое", { имя: форма, роль, число: значение })
  }
  return среда.call(ИМЯ_ОТКАЗА[род], { имя: форма, роль, значение: вЗначение(значение) })
}

