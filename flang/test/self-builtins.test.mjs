/**
 * Сверка эталона встроенных форм на flang со свидетелем на JavaScript —
 * побайтовая.
 *
 * ── Кто здесь эталон и кто свидетель ────────────────────────────────────────
 * Эталон — `flang/self/builtins.flang`. Свидетель — `flang/src/builtins.mjs`,
 * 956 строк, второе мнение, которое эта сверка спрашивает и которое уйдёт из
 * рабочего пути, когда сверка станет достаточной.
 *
 * ── Что сверяется и на чём ──────────────────────────────────────────────────
 *   1. СЛОВАРЬ. Каноническое имя и «форма ли это» — на каждом имени двадцати
 *      форм, каждом из десяти синонимов и на КАЖДОМ имени функции корпуса
 *      (это тысячи чужих имён, и ни одно из них формой быть не должно);
 *   2. АРНОСТИ. Для каждой из двадцати форм — вызов с 0…4 аргументами. Верной
 *      арности отвечает не отказ, всякой другой — отказ, чей текст сверяется
 *      побайтово. Тем же заодно проверено русское склонение: `plural`
 *      свидетеля наружу не выходит, а в текст отказа выходит;
 *   3. ТЕКСТЫ ОТКАЗОВ. Каждый отказ каждой формы, на матрице из 15 значений:
 *      `ничто`, строки, числа (включая минус ноль, «не число» и обе
 *      бесконечности), признаки, пустой и непустой список, запись, вариант с
 *      полями и без. Сверяется и код, и текст;
 *   4. ЧАСТИЧНОСТЬ. Список форм, снимаемых непустотой, и правило имени
 *      помощника — на настоящих таблицах имён всех ВОСЬМИ целей печати, на
 *      каждой из двадцати форм, доказанной и недоказанной;
 *   5. ИСХОД ЧИСЛА. Приписывание типа — на КАЖДОЙ разобранной программе
 *      корпуса, целиком через `JSON.stringify`, вместе с порядком ключей;
 *   6. ОСНОВАНИЕ ИНДЕКСАЦИИ — на трёх значениях ключа и на границах.
 *
 * Ни одного значения здесь не выдумано сверх названного: имена берутся из
 * корпуса, программы — из корпуса, таблицы помощников — из самих печатников.
 *
 * ── Чего эта сверка НЕ спрашивает, и почему ─────────────────────────────────
 * Тел двадцати форм здесь нет: они посчитаны на flang в
 * `flang/self/interpret.flang`, раздел «тела встроенных форм», и сверены на
 * корпусе в `self-interpret.test.mjs` — 127 программ, 2816 примеров. Спрашивать
 * их дважды значило бы завести второе место правды ровно там, где этот файл
 * заводится, чтобы его убрать.
 *
 * Нет здесь и списка с запасом (`Список`, `продлить`, `приписать`,
 * `материализовать`): это представление списка ВНУТРИ вычислителя на
 * JavaScript, наружу оно не выходит вовсе, и эталона на языке у него быть не
 * может. То же у `FlangError`: отказ, прекращающий вычисление, — исключение
 * JavaScript, а исключений в языке нет.
 *
 * ── Изъятие ─────────────────────────────────────────────────────────────────
 * Сверка обязана уметь краснеть. Порча подаётся переменной `PORCHA` — имя
 * ЛАТИНСКОЕ нарочно: переменная с кириллическим именем в zsh не экспортируется,
 * и порча тихо не доезжает, давая ложный ноль расхождений. Порча, не нашедшая
 * своего места, роняет прогон кодом 2.
 *
 * Каждая порча задевает ПОСЧИТАННОЕ, а не украшение, и это проверено прогоном,
 * а не рассуждением. Числа расхождений: синоним — 2, непустота — 9,
 * склонение — 36, исход — 212. Ноль здесь означал бы, что порча уехала туда,
 * где сверка не считает, — а это уже случалось у соседей.
 */
