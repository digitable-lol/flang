/**
 * Лимит витков. Число измерено, а не взято с запасом на глаз.
 *
 * ЗАМЕР ПОСЛЕ ВТАСКИВАНИЯ ЯДРА ДОКАЗАТЕЛЬСТВА. Самый дорогой вызов корпуса
 * переехал: им стал «Носители программы» на связанном
 * `flang/self/bootstrap/compiler.flang` (3 431 функция) — 2 162 811 736 витков;
 * «Проверить тотальность» на нём же 927 329 065. Прежний рекордсмен,
 * `flang/self/repl/repl.flang` (2 614 функций), стоит 1 159 429 174 и 500 565 341.
 * Предел взят вдвое больше измеренного максимума и не больше.
 *
 * ── Рост КВАДРАТИЧНЫЙ, и это не новость, а объявленное устройство ───────────
 * Замер сделан на ОДНОЙ программе до и после, чтобы разница была в размере, а
 * не в форме: `compiler.flang` без ядра — 2 560 функций, с ядром — 3 431.
 *
 *   функций            2 560 ->     3 431   x1.34
 *   «Носители»     1 133 701 585 -> 2 162 811 736   x1.91   то есть n^2.21
 *   «Тотальность»    488 963 719 ->   927 329 065   x1.90   то есть n^2.19
 *
 * Функций стало больше на 34 %, витков — на 91 %. Это ровно то, что записано в
 * соседнем стороже (`self-bounded.test.mjs`): обход линеен по числу узлов, а
 * поиск в памяти и в таблице описаний линеен по числу функций, и произведение
 * даёт квадрат. Сторож стоит НЕ против квадрата — против КУБА, и запас до него
 * не тронут: n^2.2 от куба так же далеко, как был.
 *
 * Поднимать предел без такого замера было бы снятием сторожа: он стережёт
 * сложность, а не формальность.
 *
 * Для сравнения: у соседней сверки вердикта (`self-totality.test.mjs`) предел
 * 280 000 000, и его хватает потому, что её корпус — четыре каталога, а самых
 * больших связанных программ дерева (`repl`, `bootstrap/compiler`) в нём нет.
 */
