/**
 * Две ветви эталона на одном дереве не сверяются вовсе — и это измерено, а не
 * оговорено.
 *
 * Обе правки («Цикл доказан» всегда истинна и отсев структур снят) проходят
 * сверку по НАСТОЯЩИМ программам незамеченными: в зелёном дереве каждая
 * функция, объявленная тотальной, доказана, поэтому обе ветви там всегда
 * истинны. Краснеют они только на дурных программах — тех самых трёх.
 *
 * Без этого теста дурные программы можно было бы выкинуть из корпуса, не
 * покраснев ни одной проверкой, и обе ветви ушли бы из сверки молча.
 */
test("две ветви отсева доказанного краснеют ТОЛЬКО на дурных программах", async () => {
  const настоящие = ПОДОПЫТНЫЕ.filter((имя) => !имя.startsWith("дурная — "))
  const дурные = ПОДОПЫТНЫЕ.filter((имя) => имя.startsWith("дурная — "))
  assert.equal(настоящие.length, 8)
  assert.equal(дурные.length, 3)

  /* Красный список сличается ЦЕЛИКОМ, а не по числу: покраснеет четвёртая —
     красно, перестанет краснеть одна из названных — тоже красно. Списки разные,
     и разница осмысленна: цикл недоказанной компоненты есть у всех трёх дурных,
     а структурное убывание — только там, где оно вообще считается. */
  const ЖДЁМ = new Map([
    ["недоказанная компонента поехала в отчёт доказанным циклом", дурные],
    ["структуры недоказанных функций перестали отсеиваться", [
      "дурная — структура убывает у доказанной и у заражённой недоказанностью",
      "дурная — взаимная рекурсия: заражена одна из двух, цикл не берётся вовсе",
    ]],
  ])

  for (const [имя, что, чем] of ИЗЪЯТИЯ_ОТЧЁТА.filter(([метка]) => ЖДЁМ.has(метка))) {
    const сломанный = await испорченный(файлНосителей, что, чем)
    const наНастоящих = await сверить(сломанный, среда, настоящие)
    assert.deepEqual(
      наНастоящих.расхождения.map(именем),
      [],
      `изъятие «${имя}» покраснело на настоящей программе — довод про дурные устарел, перепишите его`,
    )
    const наДурных = await сверить(сломанный, среда, дурные)
    assert.deepEqual(
      наДурных.расхождения.map(именем).sort(),
      [...ЖДЁМ.get(имя)].sort(),
      `изъятие «${имя}»: покрасневшие дурные разошлись с названными`,
    )
  }
  assert.equal(ЖДЁМ.size, 2, "названо не два изъятия — список ждущих разошёлся со списком проверяемых")
})
