/**
 * Носители обещания на самом flang: `flang/self/carriers.flang` вместе с теми
 * полями `«Итога тотальности»`, из которых ведомость называет носителя, —
 * против второго мнения на JavaScript (`flang/src/totality.mjs`), на ВСЁМ
 * корпусе дерева.
 *
 * ── Что такое носитель и почему вердикта мало ───────────────────────────────
 * `self/totality.flang` отдаёт ВЕРДИКТ: доказано или нет, диагностики и
 * множество доказанных функций. Он сверен побайтово и на корпусе
 * (`self-totality.test.mjs`). Но `flang check --proof` печатает не вердикт, а
 * ЧЕМ он вынесен: «доказано структурой, убывает «элементы»», «доказано точным
 * шагом на 1», «доказано объявленной мерой». Носителей пять — циклы,
 * структурные убывания, сторожа, точные шаги, спуски, — и ни один из них в
 * вердикт не входит.
 *
 * Отсюда критерий. Разойдись носитель — вердикт останется тем же: обе стороны
 * скажут «доказано», ведомость напечатает про ту же функцию ДРУГОЕ основание, и
 * не покраснеет ничего. Молчаливое расхождение отчёта о доказательстве — ровно
 * тот случай, ради которого сверка и заводится.
 *
 * ── Улика, ради которой файл заведён, числом ────────────────────────────────
 * До него носители сверялись в `self-proof.test.mjs` на ВОСЬМИ программах: пять
 * рукописных (композиция, структура, постоянный шаг, взаимная рекурсия,
 * объявленная мера) и три настоящих — `flang/core/json.flang`,
 * `flang/stdlib/lists.flang`, `flang/stdlib/tree.flang`. Программ в дереве 231.
 *
 * На тех трёх настоящих сверялись 20 циклов, 26 структур, 2 точных шага, 1
 * сторож и НОЛЬ спусков: объявленной меры в них нет ни одной, и единственным
 * входом объявленной меры была рукописная программа про «НОД». В дереве спусков
 * 98 — в 44 программах, ни одна из которых в сверку не входила. Носитель,
 * разошедшийся на четвёртой настоящей программе, уехал бы в ведомость молча.
 *
 * ── Из чего корпус ──────────────────────────────────────────────────────────
 *   1. ВСЕ программы дерева, какие грузятся: `flang/**` и `examples/**`. Корпус
 *      и приём те же, что у соседних сверок (`self-obligations.test.mjs`,
 *      `self-proofterm.test.mjs`), — не свой, чтобы охват одного слоя нельзя
 *      было спутать с охватом другого.
 *   2. ТРИ НАРОЧНО ДУРНЫХ. Дерево зелёное, и в нём НЕТ ни одной программы, где
 *      функция объявлена тотальной, а завершение не доказано. Значит две ветви
 *      эталона — «цикл берётся целиком или не берётся вовсе» («Цикл доказан»)
 *      и отсев структур недоказанных функций («Структуры компонент») — на одном
 *      дереве не сверялись бы ВОВСЕ: у них не было бы ни одного входа. Изъятие
 *      ниже это показывает числом: без дурных программ обе правки проходят
 *      сверку незамеченными.
 *
 * ── Критерий ────────────────────────────────────────────────────────────────
 * Побайтовый: `JSON.stringify` обоих ответов до знака, до ключа и до порядка
 * ключей. Сверяется всё, что есть у обеих сторон: имена компонент цикла в их
 * порядке; ребро, позиция и имя убывающего аргумента у структуры; шаг словами у
 * точного; стережённый аргумент у сторожа; обе меры, имена параметров
 * вызываемого и ТРИ ТЕКСТА отказа у спуска.
 *
 * Тексты сверяются наравне с числами и не в последнюю очередь: они уезжают в
 * напечатанный код тремя постусловиями сторожа меры (`defunc.mjs`), и
 * разошедшийся текст — это разошедшийся отказ у автора на руках.
 *
 * ── Изъятие: сверка обязана уметь краснеть ──────────────────────────────────
 * Ломается КУСОК В САМОМ ЭТАЛОНЕ — исходник читается с диска, один кусок
 * подменяется текстом, подменённый эталон связывается заново. Ломается копия в
 * памяти, не файл.
 *
 * И краснеть изъятие обязано на программах, которых в прежних восьми НЕ БЫЛО:
 * иначе расширение корпуса ничего не дало бы, а зелёный цвет говорил бы о
 * старой сверке.
 *
 * Запуск: node --test flang/test/self-carriers.test.mjs
 */
