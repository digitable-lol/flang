/**
 * Чистая половина командной строки flang, написанная на самом flang —
 * `flang/self/cli.flang`.
 *
 * ── Что здесь сверяется и почему именно это ────────────────────────────────
 *
 * Командная строка — это эффекты, и эталон её половины «быть командной
 * строкой» не может. Он решает: что означают доводы вызова, какую команду
 * звать, какими словами отказать и с каким кодом. Значит сверять надо ровно то,
 * что он решает, — И СВЕРЯТЬ ПОБАЙТОВО, потому что байты отказа читает человек,
 * а код возврата читает CI.
 *
 * Приём тот же, каким сверена оболочка (`self-repl.test.mjs`): один и тот же
 * вызов подаётся СВИДЕТЕЛЮ и ЭТАЛОНУ, и сходятся:
 *
 *   1. КОД ВОЗВРАТА — 0, 1 или 2. Расходится раньше текста.
 *   2. ПОТОК — stdout или stderr. Инструмент вокруг языка читает результат из
 *      одного и диагностику из другого, и перепутать их значит сломать оба.
 *   3. БАЙТЫ — знак в знак. Сюда входят справка целиком (2 217 байт), тексты
 *      всех двадцати пяти требований ключей, все негодные значения, JSON
 *      отказа со всем экранированием и `--pretty` в обоих видах.
 *
 * ── Корпус — настоящий, а не три рукописных вызова ─────────────────────────
 *
 * Корпус СТРОИТСЯ: каждый ключ, требующий значение, подаётся последним (нет
 * значения); каждый числовой ключ — с шестью значениями; каждый ключ ведомости
 * — с каждой чужой командой; каждая цель печати каталога — своим вызовом. Плюс
 * справка, версия, неизвестные команды и ключи. Итог печатается числом.
 *
 * ── Чего сверка НЕ делает молча ────────────────────────────────────────────
 *
 * Разбор JSON и список целей — эффекты (сообщение о кривом JSON пишет V8,
 * список целей читается каталогом), и эталон их не изображает: они приезжают
 * ему доводами. Вызовы, ответ на которые эталон решать не берётся, он помечает
 * «решено» равным «нет» — и тест ТРЕБУЕТ, чтобы свидетель на таком вызове до
 * чистого отказа не дошёл: молчаливое «не берусь» на вызове, у которого ответ
 * был, сверка засчитала бы сошедшимся.
 *
 * И проверка самой проверки: последний блок портит эталон по одной ветке и
 * требует, чтобы сверка покраснела.
 *
 * Запуск: node --test flang/test/self-cli-args.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { emitTargets, main } from "../bin/flang.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"

const файл = fileURLToPath(new URL("../self/cli.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")
const ВЕРСИЯ = JSON.parse(readFileSync(new URL("../../package.json", import.meta.url), "utf8")).version
const ЦЕЛИ = await emitTargets()

async function собрать(текст = исходник) {
  const связано = await linkProgram(файл, текст, parse)
  assert.equal(связано.diagnostics.length, 0, JSON.stringify(связано.diagnostics.slice(0, 2)))
  const { diagnostics: _, ...программа } = связано
  return createRuntime(программа, { maxSteps: 400_000_000, maxDepth: 20_000 })
}

const среда = await собрать()

/* ─────────────────────────── поручение хозяину ─────────────────────────── */

/**
 * Разбор JSON — эффект в том смысле, в каком он здесь важен: текст отказа пишет
 * движок, а не язык. Хозяин разбирает и привозит эталону ИТОГ — удался ли,
 * какого вида вышло значение и что сказал разборщик. Решение, что с этим
 * делать, остаётся у эталона, и именно оно сверяется.
 */
function разборыJSON(доводы) {
  const итоги = []
  for (let i = 0; i < доводы.length; i += 1) {
    if (доводы[i] !== "--args" && доводы[i] !== "--claims") continue
    const текст = доводы[i + 1]
    if (текст === undefined || итоги.some((р) => р["текст"] === текст)) continue
    let значение
    try {
      значение = JSON.parse(текст)
    } catch (беда) {
      итоги.push({ текст, удался: false, беда: беда.message, вид: "иное", "есть узлы": false })
      continue
    }
    const массив = Array.isArray(значение)
    const объект = значение !== null && typeof значение === "object" && !массив
    const вид = массив
      ? (значение.every((э) => typeof э === "string") ? "массив строк" : "массив")
      : (объект ? "объект" : "иное")
    итоги.push({
      текст,
      удался: true,
      беда: "",
      вид,
      "есть узлы": объект && значение["узлы"] !== null && typeof значение["узлы"] === "object" && !Array.isArray(значение["узлы"]),
    })
  }
  return итоги
}

/* ──────────────────────────── свидетель под колпаком ───────────────────────── */

/**
 * Один вызов свидетеля: код возврата и БАЙТЫ каждого потока по отдельности.
 *
 * Ловятся только СТРОКИ. Прогонщик `node --test` пишет в тот же stdout свои
 * сообщения буферами, и они попадали в улов, пока команда чего-то ждала: сверка
 * краснела на `emit --target --pretty` не расхождением эталона, а служебным
 * потоком прогонщика. Буфер пропускается насквозь — свидетель строками и только
 * строками (`stream.write(\`…\`)` в `writeJson`).
 */
async function свидетелем(доводы) {
  const было = [process.stdout.write, process.stderr.write]
  let вОдин = ""
  let вДругой = ""
  process.stdout.write = function (кусок, ...прочее) {
    if (typeof кусок !== "string") return было[0].call(process.stdout, кусок, ...прочее)
    вОдин += кусок
    return true
  }
  process.stderr.write = function (кусок, ...прочее) {
    if (typeof кусок !== "string") return было[1].call(process.stderr, кусок, ...прочее)
    вДругой += кусок
    return true
  }
  try {
    const код = await main(доводы)
    return { код, stdout: вОдин, stderr: вДругой }
  } finally {
    process.stdout.write = было[0]
    process.stderr.write = было[1]
  }
}

const эталоном = (доводы, среда_ = среда) =>
  среда_.call("Ответ на вызов", {
    доводы,
    разборы: разборыJSON(доводы),
    версия: ВЕРСИЯ,
    цели: ЦЕЛИ,
  })

/* ───────────────────────────────── корпус ───────────────────────────────── */

const КЛЮЧИ_СО_ЗНАЧЕНИЕМ = [
  "--function", "--utility", "--facts", "--target", "--out", "--plan",
  "--размещение", "--placement", "--steps", "--index-base", "--max-depth",
  "--max-steps", "--seed", "--max-orders", "--args", "--claims",
]
const ЧИСЛОВЫЕ = ["--steps", "--index-base", "--max-depth", "--max-steps", "--seed", "--max-orders"]
const ЗНАЧЕНИЯ_ЧИСЕЛ = ["0", "1", "-1", "2.5", "abc", "", " 7 ", "1e3", "+4"]
const ЧУЖИЕ_КОМАНДЫ = ["run", "test", "emit", "ast", "io", "repl", "facts", "lock"]
/* Список читается У ЭТАЛОНА, а не выписывается здесь: выписанный, он отстанет
   от свидетеля тем же молчанием, каким отстал сам эталон. */
const ИЗВЕСТНЫЕ = /"\|([a-z|]+)\|"/u
  .exec(исходник.slice(исходник.indexOf("тотальная функция «Известные команды»")))[1]
  .split("|")
  .filter((имя) => имя !== "")

/**
 * Корпус строится, а не выписывается: перечисление руками пропустило бы ровно
 * тот ключ, о котором не подумали, — а именно на нём разбор и расходится.
 */
function корпус() {
  const вызовы = []
  const дать = (...доводы) => вызовы.push(доводы)

  /* Файл в вызове стоит ВСЕГДА, где команда известна: без него свидетель читает
     стандартный ввод (`readInput("-")`), и сверка повисла бы на пустом вводе —
     не расхождением, а молчанием. Это не послабление: чтение файла и так за
     границей эталона, а всё, что решается до чтения, файлом не пахнет. */
  /* справка и версия — три имени каждой.

     ГОЛОГО ВЫЗОВА В КОРПУСЕ НЕТ, и это не пропуск: с этой правки `flang` без
     доводов открывает оболочку, а оболочка читает стандартный ввод. Позови
     здесь свидетель с пустым списком — и он забрал бы себе stdin прогонщика
     тестов. Что голый вызов означает, сверяется отдельным тестом ниже, по
     РЕШЕНИЮ эталона, а не по прогону свидетеля. */
  for (const имя of ["help", "--help", "-h"]) дать(имя)
  for (const имя of ["version", "--version", "-v"]) дать(имя)
  /* `flang --pretty` тоже голый вызов: позиционных доводов нет, значит это
     оболочка с ключом. В корпусе его нет по той же причине, по какой нет
     пустого списка, — свидетель ушёл бы читать stdin прогонщика. */

  /* второй этаж справки: раздел команды двумя дорогами, и обе обязаны совпасть */
  for (const команда of ["check", "run", "test", "emit", "io", "repl", "ast", "facts", "lock"]) {
    дать(команда, "--help")
    дать("help", команда)
  }
  дать("check", "а.flang", "--help")
  дать("help", "нет-такой-команды")
  дать("--help", "--version")
  дать("--version", "--help")

  /* неизвестные команды: справка целиком уезжает в stderr */
  for (const имя of ["чек", "CHECK", "check2", "-x", "и"]) дать(имя)

  /* КАЖДАЯ ИЗВЕСТНАЯ КОМАНДА — ГОЛЫМ ВЫЗОВОМ, без единого ключа.

     Дыра, из-за которой сторож заводится: все прочие вызовы корпуса идут С
     КЛЮЧОМ, а на чужом ключе свидетель отказывает РАНЬШЕ, чем доходит до имени
     команды. Поэтому эталон, не знавший команды `lock` вовсе, проходил сверку
     молча: до места, где имя сверяется, ни один вызов не добирался.

     Файл в вызове стоит: без него команда пошла бы читать стандартный ввод.
     `repl` не в списке, и это не пропуск: оболочка читает стандартный ввод ПО
     СУТИ, а не по недосмотру, и свидетель забрал бы себе stdin прогонщика тестов.
     Имя `repl` эталон при этом сверяет — через `дать("repl", "--help")` и
     через ключи ведомости у чужих команд. */
  for (const команда of ИЗВЕСТНЫЕ) if (команда !== "repl") дать(команда, "а.flang")

  /* каждый ключ со значением — последним, то есть без значения */
  for (const ключ of КЛЮЧИ_СО_ЗНАЧЕНИЕМ) {
    дать("check", "а.flang", ключ)
    дать(ключ)
  }

  /* каждый числовой ключ — со всеми значениями корпуса */
  for (const ключ of ЧИСЛОВЫЕ) {
    for (const значение of ЗНАЧЕНИЯ_ЧИСЕЛ) дать("run", "а.flang", ключ, значение)
  }

  /* значением ключа свидетель берёт ЛЮБОЙ следующий довод, включая похожий на ключ */
  дать("emit", "а.flang", "--target", "--pretty")
  дать("run", "а.flang", "--function", "--args")
  дать("check", "а.flang", "--размещение", "--pretty")

  /* JSON: годный объект, годный массив строк, негодная форма, кривой текст */
  for (const текст of ['{"н":1}', "[]", "[1]", '["а"]', "null", "5", "{", '{"а":}', '"с"']) {
    дать("run", "а.flang", "--function", "Ф", "--args", текст)
    дать("facts", "а.flang", "--claims", текст)
  }

  /* неизвестные ключи */
  for (const ключ of ["--нет", "--Pretty", "--no-checks", "--json2", "--"]) дать("check", "а.flang", ключ)

  /* ключи ведомости у чужих команд — каждый с каждой */
  for (const ключ of ["--proof", "--json", "--словарь", "--legend"]) {
    дать("check", "а.flang", ключ)
    for (const команда of ЧУЖИЕ_КОМАНДЫ) дать(команда, "а.flang", ключ)
  }
  for (const команда of ["check", "run", "ast", "io", "repl", "facts", "lock", "package"]) дать(команда, "а.flang", "--no-check")
  for (const команда of ЧУЖИЕ_КОМАНДЫ) дать(команда, "а.flang", "--размещение", "у.json")

  /* отказы, известные до чтения файла */
  дать("run", "а.flang")
  дать("run", "а.flang", "--pretty")
  дать("run", "а.flang", "--args", '{"н":1}')
  дать("facts", "а.flang")
  дать("facts", "а.flang", "--facts", "ф.json")
  дать("facts", "а.flang", "--pretty")
  дать("emit", "а.flang")
  дать("emit", "а.flang", "--pretty")
  for (const цель of [...ЦЕЛИ, "нет-такой", "C", "../x"]) дать("emit", "а.flang", "--target", цель)

  /* порядок ключей и накопление: последний побеждает, полномочия копятся */
  дать("io", "а.flang", "--no-read", "--no-write", "--no-net", "--no-clock", "--no-random", "--no-spawn", "--in-dir")
  дать("io", "а.flang", "--no-spawn")
  дать("emit", "а.flang", "--target", "c", "--target", "нет-такой")
  дать("emit", "а.flang", "--cli", "--no-cli", "--target", "нет-такой")
  дать("check", "а.flang", "--proof", "--json", "--pretty")
  дать("check", "а.flang", "--proof", "--словарь")
  дать("check", "а.flang", "--proof", "--legend", "--json")

  return вызовы
}

const ВЫЗОВЫ = корпус()

const uniq = (список) => [...new Set(список)]

/* ─────────────────────────────── сверка ─────────────────────────────── */

async function расхождение(доводы, среда_ = среда) {
  const ждём = await свидетелем(доводы)
  const наш = эталоном(доводы, среда_)
  const где = JSON.stringify(доводы)

  if (наш["решено"] !== true) {
    /* Эталон не берётся отвечать. Это законно ровно тогда, когда свидетель и сам
       не ответил чисто, а пошёл работать: чистый отказ, отданный молчанием, —
       это дыра, а не граница. Работа без файла кончается кодом 1 (ошибка
       модели: файла нет), а чистый отказ — кодом 2. */
    if (ждём.код === 2 && ждём.stderr !== "") return `${где}: эталон не взялся, а свидетель отказал чисто: ${ждём.stderr}`
    return null
  }
  if (наш["код"] !== ждём.код) return `${где}: код ${наш["код"]} ≠ ${ждём.код}`

  const ждали = наш["поток"] === "stdout" ? ждём.stdout : ждём.stderr
  const тихо = наш["поток"] === "stdout" ? ждём.stderr : ждём.stdout
  if (наш["текст"] !== ждали) {
    return `${где}: байты ${JSON.stringify(наш["текст"]).slice(0, 400)} ≠ ${JSON.stringify(ждали).slice(0, 400)}`
  }
  if (тихо !== "") return `${где}: во второй поток ушло ${JSON.stringify(тихо).slice(0, 200)}`
  return null
}

test("корпус вызовов собран и не пуст", () => {
  console.log(`вызовов в корпусе: ${ВЫЗОВЫ.length}, известных команд: ${ИЗВЕСТНЫЕ.length}`)
  assert.ok(ВЫЗОВЫ.length >= 150, `вызовов ${ВЫЗОВЫ.length}`)
  /* Перечень команд свидетеля: `main` разбирает их `switch`-ем, и разойтись со
     списком эталона он может молча. Сверяются САМИ ИМЕНА, а не их число. */
  const свидетель = readFileSync(fileURLToPath(new URL("../bin/flang.mjs", import.meta.url)), "utf8")
  const свитч = свидетель.slice(свидетель.indexOf("switch (options.command)"), свидетель.indexOf("default:"))
  const уСвидетеля = [...свитч.matchAll(/case "([a-z]+)":/gu)].map((н) => н[1])
  assert.deepEqual([...ИЗВЕСТНЫЕ].sort(), [...uniq(уСвидетеля)].sort(), "перечень команд у эталона и у свидетеля разошёлся")
  assert.ok(ЦЕЛИ.length > 0, "целей печати не нашлось — сверка emit проверяла бы пустоту")
})

test("побайтовая сверка эталона со свидетелем на корпусе вызовов", async () => {
  const беды = []
  let решено = 0
  for (const доводы of ВЫЗОВЫ) {
    const беда = await расхождение(доводы)
    if (беда !== null) беды.push(беда)
    if (эталоном(доводы)["решено"] === true) решено += 1
  }
  console.log(`сверено вызовов: ${ВЫЗОВЫ.length}, расхождений: ${беды.length}, решил эталон: ${решено}`)
  assert.deepEqual(беды, [], `расхождений ${беды.length} из ${ВЫЗОВЫ.length}`)
  /* Молчаливое «не берусь» на всём корпусе прошло бы сверку выше пустым
     списком. Порог требует, чтобы эталон РЕШАЛ большинство вызовов сам. */
  assert.ok(решено >= Math.floor(ВЫЗОВЫ.length * 0.8), `эталон решил ${решено} из ${ВЫЗОВЫ.length}`)
})

test("справка совпадает знак в знак и она короткая", async () => {
  const ждём = await свидетелем(["--help"])
  const наш = эталоном(["--help"])
  assert.equal(наш["текст"], ждём.stdout)
  /* Первый этаж справки — короткий, и это ПРОВЕРЯЕМОЕ обещание, а не намерение:
     прежняя справка занимала 7 406 байт и вываливала восемь команд с двумя
     десятками ключей на человека, который ещё не знает ни одной. */
  assert.ok(наш["текст"].length < 1200, `краткая справка ${наш["текст"].length} байт — это уже не краткая`)
  assert.ok(наш["текст"].length > 400, `краткая справка ${наш["текст"].length} байт — это уже не справка`)
})

test("второй этаж справки есть у каждой команды и он длиннее первого", async () => {
  const краткая = эталоном(["--help"])["текст"]
  for (const команда of ["check", "run", "test", "emit", "io", "repl", "ast", "facts", "lock"]) {
    const раздел = эталоном([команда, "--help"])["текст"]
    assert.notEqual(раздел, краткая, `у команды «${команда}» нет своего раздела справки`)
    assert.ok(раздел.startsWith(`flang ${команда} `), `раздел «${команда}» начинается не с вызова: ${раздел.slice(0, 60)}`)
  }
})

test("голая команда — это оболочка, а не справка", async () => {
  /* Свидетель здесь НЕ зовётся: голый вызов открывает оболочку и читает stdin.
     Сверяется решение — какую команду означает пустой список доводов, — и оно
     у эталона и у свидетеля записано одним словом в одном месте. */
  const наш = эталоном([])
  assert.equal(наш["решено"], false, "оболочку эталон решать не берётся — она эффект")
  assert.equal(наш["команда"], "repl", "голая команда обязана означать оболочку")
  const свидетель = readFileSync(fileURLToPath(new URL("../bin/flang.mjs", import.meta.url)), "utf8")
  assert.ok(
    свидетель.includes('options.command = positional[0] ?? "repl"'),
    "свидетель перестал открывать оболочку голой командой",
  )
})

/* ──────────────────────── изъятие: сверка обязана краснеть ──────────────── */

/**
 * Проверка самой проверки. Каждая порча — одна ветка эталона, и каждая обязана
 * дать хотя бы одно расхождение на корпусе. Сверка, которая не умеет краснеть,
 * хуже отсутствующей: она печатает зелёное и ничего не проверяет.
 */
const ПОРЧИ = [
  ["текст требования ключа", '"--target требует имя целевого языка"', '"--target требует язык"'],
  ["код возврата отказа", "«Ответом байтами» от 2 и \"stderr\"", "«Ответом байтами» от 1 и \"stderr\""],
  ["поток отказа", 'от 2 и "stderr" и («Отказом JSON»', 'от 2 и "stdout" и («Отказом JSON»'],
  ["строка краткой справки", '"  flang --version                    версия\\n",', '"  flang --versions                   версия\\n",'],
  ["строка раздела команды", '"flang check <файл> [--proof [--json] [--словарь]] [--размещение узлы.json] [--pretty]\\n",', '"flang check <файл> [--proof [--json]] [--pretty]\\n",'],
  ["проверка чужого --словарь", '(«к».«словарь») и притом (не ((«к».«команда») равен "check"))', '(«к».«словарь») и притом нет'],
  ["--словарь без --proof", '(«к».«словарь») и притом (не («к».«ведомость»))', '(«к».«словарь») и притом нет'],
  ["выбор раздела по команде", 'если «команда» равен "check"\n    то «Справка проверки»', 'если «команда» равен "check"\n    то «Справка прогона»'],
  ["тема справки у «help <команда>»", 'если («ключи».«команда») равен "help"\n    то «ключи».«файл»', 'если («ключи».«команда») равен "help"\n    то ""'],
  ["проверка чужого ключа", '(«к».«ведомость») и притом (не ((«к».«команда») равен "check"))', '(«к».«ведомость») и притом нет'],
  ["негодное число", '" должен быть целым положительным числом"', '" должен быть целым числом"'],
  ["экранирование кавычки", 'то "\\\\\\""', 'то "\\""'],
  ["разбор числа: пустое — ноль", 'то запись «Число довода» с «годно» равным да и «значение» равным 0\n    иначе «Число довода без знака» от «текст»', 'то запись «Число довода» с «годно» равным нет и «значение» равным 0\n    иначе «Число довода без знака» от «текст»'],
  ["показатель в записи числа", '(«Знак степени» от «з») то («Скан в состоянии» от «с» и 3)', '(«Знак степени» от «з») то («Негодный скан» от «с»)'],
]

test("испорченный эталон красит сверку", async () => {
  for (const [имя, было, стало] of ПОРЧИ) {
    assert.ok(исходник.includes(было), `порча «${имя}»: в эталоне нет ${JSON.stringify(было)}`)
    const испорченная = await собрать(исходник.replace(было, стало))
    let нашлось = null
    for (const доводы of ВЫЗОВЫ) {
      нашлось = await расхождение(доводы, испорченная)
      if (нашлось !== null) break
    }
    assert.notEqual(нашлось, null, `порча «${имя}» прошла сверку незамеченной`)
  }
})
