/**
 * СЕТКА СЕМЯН: двенадцать на каждый прогон, считая от объявленного семени.
 *
 * Двенадцать, а не одно, потому что одно семя предъявляет одно чередование;
 * и двенадцать у КАЖДОГО прогона, а не только у объявленных сеткой, потому что
 * прогон с одним семенем — это утверждение об одном чередовании, а планировщик
 * обязан совпадать на любом. 22 прогона × 12 = 264 исполнения.
 */
const СЕМЯН = 12

const исполнения = () => {
  const список = []
  for (const { имя, программа: п } of КОРПУС) {
    for (const прогон of п.runs ?? []) {
      for (let семя = прогон.seed; семя < прогон.seed + СЕМЯН; семя += 1) {
        список.push({ имя, программа: п, прогон, семя })
      }
    }
  }
  return список
}

const ИСПОЛНЕНИЯ = исполнения()

/* ─────────────────── сверка ─────────────────── */

const эталоном = ({ программа: п, прогон, семя }) => JSON.stringify(runConcurrent(п, { ...прогон, seed: семя }))

const близнецом = ({ программа: п, прогон, семя }, чем) =>
  JSON.stringify(изЗначения(чем.call("Прогнать", {
    "программа": вЗначение(п), "прогон": вЗначение(прогон), "семя": семя,
  })))

function расхождение(эталон, наш) {
  if (эталон === наш) return null
  let знак = 0
  while (знак < эталон.length && знак < наш.length && эталон[знак] === наш[знак]) знак += 1
  const кусок = (текст) => текст.slice(Math.max(0, знак - 70), знак + 180)
  return `разошлось на знаке ${знак}:\n      эталон:  ${кусок(эталон)}\n      близнец: ${кусок(наш)}`
}

/** Сверить всю сетку. Возвращает числа: сверка без охвата даёт ложную уверенность. */
function сверить(чем = среда, доПервой = false) {
  const беды = []
  let доставок = 0
  let решений = 0
  for (const исполнение of ИСПОЛНЕНИЯ) {
    const итог = runConcurrent(исполнение.программа, { ...исполнение.прогон, seed: исполнение.семя })
    доставок += итог.журнал.length
    решений += итог.решения.length
    let наш
    try { наш = близнецом(исполнение, чем) } catch (ошибка) { наш = `СОРВАЛОСЬ: ${ошибка?.message}` }
    const беда = расхождение(JSON.stringify(итог), наш)
    if (беда !== null) {
      беды.push(`${исполнение.имя} «${исполнение.прогон.name}» семя ${исполнение.семя}: ${беда}`)
      /* Изъятию хватает первого расхождения: вопрос там «ловит ли сверка
         вообще», а не «на скольких чередованиях». */
      if (доПервой) return { беды, доставок, решений }
    }
  }
  return { беды, доставок, решений }
}

