test("побитовые операции эталона отвечают то же, что операции JavaScript", () => {
  /* Улика к тесту выше: генератор мог бы совпасть на выбранных семенах и
     разойтись на разряде, до которого они не добрались. */
  const пары = [[0, 0], [1, 2], [255, 3855], [0xffffffff, 1], [0x9e3779b9, 61], [123456789, 987654321]]
  for (const [а, б] of пары) {
    assert.equal(среда.call("Исключающее или", { "а": а, "б": б }), (а ^ б) >>> 0, `xor ${а} ${б}`)
    assert.equal(среда.call("Побитовое или", { "а": а, "б": б }), (а | б) >>> 0, `or ${а} ${б}`)
    assert.equal(среда.call("Умножение по модулю", { "а": а, "б": б }), Math.imul(а, б) >>> 0, `imul ${а} ${б}`)
  }
  for (const х of [0, 1, 65535, 0xffffffff, 0x9e3779b9]) {
    for (const к of [0, 7, 14, 15, 31]) {
      assert.equal(среда.call("Сдвиг вправо", { "х": х, "сколько": к }), х >>> к, `${х} >>> ${к}`)
    }
  }
})

