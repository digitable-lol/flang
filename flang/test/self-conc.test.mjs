/**
 * Планировщик конкурентности: слой на flang против свидетеля на JavaScript.
 *
 * ── Зачем этот эталон существует ───────────────────────────────────────────
 * `flang/src/types.mjs` ввозит `conc.mjs` строкой 49, безусловно. Значит
 * JavaScript про процессы лежал в рабочем пути КАЖДОГО `flang check`, а не
 * только конкурентной программы: прогон на программе с нулём процессов грузит
 * 39 модулей, из них 33 из `flang/src`, и `conc.mjs` среди них. Пока эталона
 * нет, типизатор без JavaScript не соберётся, и слой процессов оказывается не
 * хвостом плана выброса свидетеля, а узлом.
 *
 * ── Почему сверка идёт НА СЕТКЕ СЕМЯН, а не на одном прогоне ────────────────
 * У слоя это принятая дисциплина, а не пожелание. Единственный источник
 * недетерминизма — выбор процесса из очереди готовых, и он берётся из
 * генератора, заведённого семенем; всё остальное строго определено. Отсюда
 * обещание: одно семя — один журнал доставок, ПОБАЙТОВО. Проверять его на одном
 * семени значит проверять одно чередование из тысячи.
 *
 * Поэтому здесь сверяется ЖУРНАЛ, а не итог, и не на одном семени, а на
 * двенадцати у каждого из 28 прогонов одиннадцати программ: 336 исполнений — та
 * же по устройству сетка, на какой слой сверяет напечатанный C со свидетелем
 * (`flang/test/emit-c-conc.test.mjs`).
 *
 * Сверяется при этом ВЕСЬ итог, а не журнал отдельно: `JSON.stringify` обоих
 * знак в знак, вместе с порядком ключей. Порядок ключей записи журнала — часть
 * формата: четыре поля ставятся при заводе записи, три дописываются, когда
 * пробег кончился отказом, и разъехавшийся порядок это разъехавшийся формат.
 *
 * ── Генератор сверяется ОТДЕЛЬНО, и это не дубль ────────────────────────────
 * Битовых операций в языке нет вовсе, а mulberry32 весь из них: эталон считает
 * их арифметикой по 32 весам разрядов. Свойство «тот же журнал на том же семени»
 * держится ровно на том, что генератор совпал ЧИСЛО В ЧИСЛО, и если он разойдётся
 * на далёком семени, сверка журналов покраснеет непонятно где. Поэтому генератор
 * сверяется прямо: 11 семян по 200 вызовов.
 *
 * ── Изъятие: сверка обязана уметь краснеть ──────────────────────────────────
 * Ломается кусок в самом эталоне — копия в памяти, файл на диске не трогается.
 */
