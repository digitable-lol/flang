/**
 * Сверка словаря действий, посчитанного САМИМ flang, со свидетелем на JavaScript.
 *
 * ── Улика, ради которой это делается ────────────────────────────────────────
 * `flang/src/conc.mjs` — 1768 строк без эталона, и лежат они в рабочем пути
 * КАЖДОГО `flang check`. Замыкание статических импортов от `flang/bin/flang.mjs`
 * — 17 модулей, 20 038 строк JavaScript, и `conc.mjs` в нём есть: его тянут
 * трое — сам вход, `src/compat.mjs` и `src/types.mjs`. Проверено на
 * `flang/examples/hello.flang`, где процессов нет вовсе: `conc.mjs` всё равно
 * загружается, потому что импорт статический.
 *
 * Из этих 1768 строк типизатору нужны ТРИ имени (`ACTION_PROCESS_FIELD`,
 * `ACTION_TYPE_NAME`, `STRATEGIES`), а разборщику четвёртое (`ACTION_TYPE`).
 * Все четыре — СЛОВАРЬ, и здесь сверяется ровно он.
 *
 * ── Чего эта сверка НЕ проверяет, и почему так сказано вслух ────────────────
 * Планировщика здесь нет: ни очереди, ни ящиков, ни надзора, ни генератора
 * чередований. Значит НЕТ И СЕТКИ СЕМЯН. Чередования свидетеля проверяются
 * перебором — 22 прогона, семь по сетке `от 1 до 1000` (`flang/test/conc.test.mjs`),
 * — и эталон планировщика обязан идти по той же сетке. Но словарь действий
 * статический: семени в нём нет ни одного разряда, и заявить сетку значило бы
 * соврать о том, чего здесь не считается. Корпус здесь вместо сетки, и корпус
 * настоящий: все программы дерева, до которых дотягивается связывание.
 *
 * ── Что сверяется побайтово ─────────────────────────────────────────────────
 *   1. `withActionType` на КАЖДОЙ программе корпуса, целиком: не «тот же набор
 *      полей», а `JSON.stringify` всей программы, вместе с порядком ключей.
 *      Обе ветки свидетеля попадают под сверку сами собой: у программы с
 *      процессами разборщик словарь уже приписал (идемпотентная ветка), у
 *      программы без процессов — ещё нет (ветка дописывания);
 *   2. `ACTION_PROCESS_FIELD` на каждом имени варианта, встреченном В КОРПУСЕ:
 *      узлы обходятся, значения ключа `variant` собираются, и обе стороны
 *      отвечают на одни и те же имена. `undefined` свидетеля равен здесь пустой
 *      строке эталона — у действий языка поля с пустым именем нет;
 *   3. `STRATEGIES` на каждой стратегии, встреченной в корпусе (ключ `strategy`),
 *      и на самом списке.
 *
 * ── Изъятие ─────────────────────────────────────────────────────────────────
 * Сверка обязана уметь краснеть. Проверено порчей эталона через переменную
 * `PORCHA` — имя ЛАТИНСКОЕ нарочно: переменная с кириллическим именем в zsh не
 * экспортируется, и порча тихо не доезжает, давая ложный ноль расхождений.
 * Здесь она доезжает: порча, не нашедшая своего места, роняет прогон кодом 2,
 * поэтому «ноль расхождений» и «порча не доехала» больше не выглядят одинаково.
 *
 * Три порчи, три числа:
 *   • `вид` — поле процесса у порождения становится «кому»: 1 расхождение;
 *   • `builtin` — из суммы пропадает пометка `builtin`: 150 расхождений, из них
 *     149 на настоящих программах корпуса (все, у кого словаря ещё не было) и
 *     одно на самой сумме;
 *   • `стратегия` — третья стратегия надзора выброшена: 2 расхождения, и одно
 *     из них приходит С КОРПУСА — «передать выше» в дереве правда встречается.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { ACTION_PROCESS_FIELD, ACTION_TYPE, ACTION_TYPE_NAME, STRATEGIES, withActionType } from "../src/conc.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { вЗначение } from "./self-evaluator.mjs"
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const исходник = readFileSync(корень + "flang/self/conc.flang", "utf8")
const порча = process.env.PORCHA ?? ""

/* Каждая порча выбрана так, чтобы задеть ПОСЧИТАННОЕ число, а не украшение:
   первая — поле процесса у порождения, второе из трёх имён словаря; вторая —
   пометку `builtin`, без которой связывание объявило бы словарь дважды; третья
   — третью стратегию надзора. Порча, которую корпус не видит, ничего не
   доказывает. */
let текст = исходник
if (порча === "вид") текст = текст.replace('если «действие» равен "породить" то "вид" иначе ""', 'если «действие» равен "породить" то "кому" иначе ""')
if (порча === "builtin") текст = текст.replace('    «Поле документа» от "builtin" и («Признак как узел» от да),\n', "")
if (порча === "стратегия") текст = текст.replace('["перезапустить", "остановить", "передать выше"]', '["перезапустить", "остановить"]')
if (порча !== "" && текст === исходник) {
  console.error(`порча «${порча}» не нашла своего места`)
  process.exit(2)
}

const { diagnostics: беды, ...слой } = await linkProgram(корень + "flang/self/conc.flang", текст, parse)
if (беды.length > 0) {
  console.error("не связался:", беды.map((б) => `${б.code}: ${б.message}`).join("\n"))
  process.exit(1)
}
const среда = createRuntime(слой, { maxSteps: 300_000_000, maxDepth: 20_000 })

/* Обратный перевод «Значение» → JSON. Механический и порядок ключей хранит:
   иначе побайтовая сверка сравнивала бы кодировку, а не ответ. */
function изЗначения(зн) {
  const вид = зн?.variant
  if (вид === "Значение списка") return зн.fields["элементы"].map(изЗначения)
  if (вид === "Значение записи") {
    const запись = {}
    for (const поле of зн.fields["поля"]) запись[поле["ключ"]] = изЗначения(поле["значение"])
    return запись
  }
  if (вид === "Значение скаляра") {
    const с = зн.fields["скаляр"]
    if (с.variant === "Скаляр ничто") return null
    return с.fields["значение"]
  }
  throw new Error(`неизвестный вид «Значение»: ${вид}`)
}

const каталоги = ["flang/conc/examples", "flang/examples", "flang/stdlib", "flang/core"]
const пути = каталоги.flatMap((к) => globSync("**/*.flang", { cwd: корень + к + "/" }).sort().map((и) => к + "/" + и))

/* Имена, которые встречаются в корпусе под ключами `variant` и `strategy`.
   Собирает их корпус, а не список в этом файле: сверка обязана спрашивать обе
   стороны об одном и том же, и спрашивать о том, что в дереве правда есть. */
function собрать(узел, ключ, куда) {
  if (Array.isArray(узел)) { for (const э of узел) собрать(э, ключ, куда); return }
  if (узел === null || typeof узел !== "object") return
  for (const [к, знач] of Object.entries(узел)) {
    if (к === ключ && typeof знач === "string") куда.add(знач)
    собрать(знач, ключ, куда)
  }
}

let программ = 0, сПроцессами = 0, байтСловаря = 0, расхождений = 0
const вариантыКорпуса = new Set()
const стратегииКорпуса = new Set()

for (const путь of пути) {
  let программа
  try {
    const { diagnostics: _, ...собрана } = await linkProgram(корень + путь, readFileSync(корень + путь, "utf8"), parse)
    программа = собрана
  } catch { continue }
  программ += 1
  if ((программа.processes ?? []).length > 0) сПроцессами += 1

  собрать(программа, "variant", вариантыКорпуса)
  собрать(программа, "strategy", стратегииКорпуса)

  const ожидание = JSON.stringify(withActionType(программа))
  const получено = JSON.stringify(изЗначения(среда.call("Приписать словарь действий", { программа: вЗначение(программа) })))
  байтСловаря += ожидание.length
  if (ожидание !== получено) {
    расхождений += 1
    const где = [...ожидание].findIndex((з, и) => з !== получено[и])
    console.log(`РАСХОЖДЕНИЕ словаря: ${путь}, первый разошедшийся байт ${где}:\n  свидетель:  …${ожидание.slice(Math.max(0, где - 60), где + 60)}…\n  эталон: …${получено.slice(Math.max(0, где - 60), где + 60)}…`)
  }
}

/* Поле процесса — на каждом имени варианта, какое в корпусе нашлось. */
const вариантыСписком = [...вариантыКорпуса].sort()
for (const имя of вариантыСписком) {
  const ожидание = ACTION_PROCESS_FIELD[имя] ?? ""
  const получено = среда.call("Поле процесса у действия", { "действие": имя })
  if (ожидание !== получено) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ поля процесса: «${имя}»: свидетель «${ожидание}», эталон «${получено}»`)
  }
}

/* Стратегии — на каждой, какая в корпусе нашлась. */
const стратегииСписком = [...стратегииКорпуса].sort()
for (const имя of стратегииСписком) {
  const ожидание = STRATEGIES.includes(имя)
  const получено = среда.call("Стратегия известна", { имя })
  if (ожидание !== получено) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ стратегии: «${имя}»: свидетель ${ожидание}, эталон ${получено}`)
  }
}

/* Сами постоянные: три имени, ради которых типизатор ввозит `conc.mjs`, плюс
   сумма «Действие», ради которой её ввозит разборщик. */
const постоянные = [
  ["имя типа действия", JSON.stringify(ACTION_TYPE_NAME), JSON.stringify(среда.call("Имя типа действия", {}))],
  ["стратегии надзора", JSON.stringify(STRATEGIES), JSON.stringify(среда.call("Стратегии надзора", {}))],
  ["имена действий", JSON.stringify(ACTION_TYPE.variants.map((в) => в.name)), JSON.stringify(среда.call("Имена действий", {}))],
  ["сумма «Действие»", JSON.stringify(ACTION_TYPE), JSON.stringify(изЗначения(среда.call("Тип действия", {})))],
]
for (const [имя, ожидание, получено] of постоянные) {
  if (ожидание !== получено) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ постоянной ${имя}:\n  свидетель:  ${ожидание}\n  эталон: ${получено}`)
  }
}

test("словарь действий: эталон на flang сходится со свидетелем побайтово", () => {
  assert.equal(расхождений, 0)
})

/* Охват печатается числами: сверка, чей корпус может тихо схлопнуться, зелена
   ровно так же, как исправная. */
console.log(`программ ${программ} (с процессами ${сПроцессами}), байт сверенного словаря ${байтСловаря}`)
console.log(`имён вариантов из корпуса ${вариантыСписком.length}, из них действий ${вариантыСписком.filter((и) => ACTION_PROCESS_FIELD[и] !== undefined).length}`)
console.log(`стратегий из корпуса ${стратегииСписком.length}: ${стратегииСписком.map((с) => `«${с}»`).join(", ")}`)
console.log(`постоянных ${постоянные.length}, расхождений ${расхождений}`)
