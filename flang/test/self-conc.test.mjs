test("охват сетки: все исходы прогона и все исходы записи журнала СРАБОТАЛИ", (t) => {
  const исходы = new Set()
  const исходыЗаписей = new Set()
  const коды = new Set()
  const стратегии = new Set()
  let порождений = 0
  let поручений = 0
  for (const исполнение of ИСПОЛНЕНИЯ) {
    const итог = runConcurrent(исполнение.программа, { ...исполнение.прогон, seed: исполнение.семя })
    поручений += итог.поручения.length
    исходы.add(итог.исход)
    for (const запись of итог.журнал) { исходыЗаписей.add(запись.исход); if (запись.код) коды.add(запись.код) }
    for (const решение of итог.решения) стратегии.add(решение.стратегия)
    порождений += итог.живые.length
  }
  t.diagnostic(`исходы прогона: ${[...исходы].sort().join(", ")}`)
  t.diagnostic(`исходы записей: ${[...исходыЗаписей].sort().join(", ")}`)
  t.diagnostic(`коды отказов: ${[...коды].sort().join(", ")}; стратегии: ${[...стратегии].sort().join(", ")}`)
  /* Без этого счёта побайтовая сверка выше могла бы быть зелёной на сетке, где
     ни один процесс не падает и ни один надзор не решает: «обе стороны молчат»
     — тоже совпадение. */
  assert.ok(исходы.has("покой"), "исход «покой» не встретился")
  assert.ok(исходы.has("отказ дошёл доверху"), "исход «отказ дошёл доверху» не встретился")
  assert.ok(исходыЗаписей.has("обработано"), "«обработано» не встретилось")
  assert.ok(исходыЗаписей.has("отказ"), "«отказ» не встретился")
  assert.ok(исходыЗаписей.has("остановлено"), "«остановлено» не встретилось")
  assert.ok(коды.size >= 4, `кодов отказа сработало ${коды.size}`)
  assert.ok(стратегии.size >= 2, `стратегий надзора сработало ${стратегии.size}`)
  assert.ok(порождений > 0, "живых процессов ноль — порождение не сверяется")
  /* Седьмое действие обязано СРАБОТАТЬ на сетке, а не просто быть написанным:
     ветка поручения у обеих сторон исполняется только здесь. */
  t.diagnostic(`поручений исполнено ${поручений}`)
  assert.ok(поручений >= 84, `поручений всего ${поручений} — ветка поручения почти не сверяется`)
})

