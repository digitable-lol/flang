/**
 * Понижение высшего порядка, написанное на самом flang —
 * `flang/self/defunc.flang`.
 *
 * ── Зачем этот файл появился ────────────────────────────────────────────────
 *
 * Близнец на 929 строк лежал в дереве и НЕ СВЕРЯЛСЯ НИ С ЧЕМ. Побайтовую сверку
 * с эталоном имели шесть слоёв — лексер, разборщик, типы, тотальность, печать в
 * C, ведомость, — а понижение не имело: его правильность подтверждалась только
 * косвенно, через тройную печать, где расхождение вылезло бы уже собранным C.
 *
 * Косвенное подтверждение здесь слабее, чем кажется. Тройная печать сходится,
 * пока понижение ОБА РАЗА неверно одинаково: неподвижная точка сверяет
 * компилятор сам с собой, а не с образцом. Расхождение с эталоном она поймает
 * только там, где оно доедет до байтов напечатанного C, — а понижение решает и
 * то, что до печати не доходит: какие теги вошли в диспетчер, какая у них
 * арность, каким объявлен отказ сторожа.
 *
 * ── Что сверяется ───────────────────────────────────────────────────────────
 *
 * Обе точки входа эталона (`flang/src/defunc.mjs`), каждая на всём корпусе:
 *
 *   `defunctionalize` ← «Дефункционализировать»   тег → случай диспетчера
 *   `guardDescent`    ← «Поставить сторожей»      сторож объявленной меры
 *
 * Критерий один и он побайтовый: `JSON.stringify` понижённой программы обязан
 * совпасть знак в знак, вместе с ПОРЯДКОМ КЛЮЧЕЙ. Слабее нельзя — понижение
 * отдаёт программу печати, и разошедшийся порядок полей даёт другой C при
 * одинаковом смысле, то есть ломает ту самую неподвижную точку, ради которой
 * самоприменение и делается.
 *
 * ── Половина, без которой вторая ничего не значит ───────────────────────────
 *
 * Программа БЕЗ высшего порядка обязана пройти понижение НЕИЗМЕННОЙ — байт в
 * байт той же. Это записано в шапке самого близнеца как его главное свойство:
 * он смотрит, есть ли в программе `fnref` или `apply`, и если нет, отдаёт её
 * как есть, не обходя вовсе. Без этой проверки тест зеленел бы на корпусе, где
 * высшего порядка почти нет, ничего при этом не проверяя.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { defunctionalize, guardDescent } from "../src/defunc.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { markMeasureGuards } from "../src/totality.mjs"
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const файл = fileURLToPath(new URL("../self/defunc.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")

const связано = await linkProgram(файл, исходник, parse)
const { diagnostics: _, ...программа } = связано

/* Лимит поднят по той же причине и той же меркой, что у соседних сверок:
   понижение — работа с целым AST сразу. Запас взят двукратный к самой дорогой
   программе корпуса; упрись обход в него — значит он перестал быть линейным по
   числу узлов, и тест обязан это назвать, а не молча замедлиться. */
const среда = createRuntime(программа, { maxSteps: 40_000_000 })
const вызвать = (имя, аргументы) => среда.call(имя, аргументы)

/* ─────────────── перевод AST в значения flang и обратно ─────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в соседних
   сверках, и по той же причине: иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и эталон их различает. */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

function изЗначения(узел) {
  if (узел.variant === "Значение списка") return узел.fields["элементы"].map(изЗначения)
  if (узел.variant === "Значение записи") {
    return Object.fromEntries(узел.fields["поля"].map((поле) => [поле["ключ"], изЗначения(поле["значение"])]))
  }
  const скалярное = узел.fields["скаляр"]
  return скалярное.variant === "Скаляр ничто" ? null : скалярное.fields["значение"]
}

/** Расхождение с указанием НОМЕРА ЗНАКА: «не совпало» без места нечинимо. */
function расхождение(эталон, наш) {
  if (эталон === наш) return null
  const слева = [...эталон]
  const справа = [...наш]
  let знак = 0
  while (знак < слева.length && знак < справа.length && слева[знак] === справа[знак]) знак += 1
  const кусок = (текст, от) => текст.slice(Math.max(0, от - 60), от + 60)
  return `разошлось на знаке ${знак}:\n  эталон: ${кусок(эталон, знак)}\n  наш:    ${кусок(наш, знак)}`
}

/* ───────────────────────────── корпус ───────────────────────────── */

/* Склеенный самоприменением компилятор исключён по той же причине, по какой его
   исключает свод ведомости: это не отдельная программа, а сборка всех
   остальных. */
const КОРПУС = globSync("flang/**/*.flang", { cwd: корень })
  .filter((путь) => путь !== "flang/self/bootstrap/compiler.flang")
  .sort()

/** Разобранные программы корпуса: те, что разбираются. Неразбираемое — не сюда. */
const ПРОГРАММЫ = КОРПУС.map((путь) => {
  try {
    return { путь, ast: parse(readFileSync(`${корень}${путь}`, "utf8"), путь) }
  } catch {
    return null
  }
}).filter(Boolean)

test("корпус не пуст и высший порядок в нём есть — иначе сверять нечего", () => {
  assert.ok(ПРОГРАММЫ.length > 50, `программ разобралось всего ${ПРОГРАММЫ.length}`)
  const сВысшим = ПРОГРАММЫ.filter(({ ast }) => JSON.stringify(ast).includes('"fnref"'))
  assert.ok(сВысшим.length > 0, "в корпусе не стало ни одной программы с тегом — сверка стала бы пустой")
})

test("«Дефункционализировать» на flang совпадает с эталоном побайтово на всём корпусе", () => {
  const беды = []
  for (const { путь, ast } of ПРОГРАММЫ) {
    const эталон = JSON.stringify(defunctionalize(structuredClone(ast)))
    const наш = JSON.stringify(изЗначения(вызвать("Дефункционализировать", { "программа": значение(ast) })))
    const беда = расхождение(эталон, наш)
    if (беда !== null) беды.push(`${путь}: ${беда}`)
  }
  assert.deepEqual(беды, [], `понижение разошлось с эталоном на ${беды.length} программах`)
})

test("«Поставить сторожей» на flang совпадает с эталоном побайтово на всём корпусе", () => {
  const беды = []
  for (const { путь, ast } of ПРОГРАММЫ) {
    const эталон = JSON.stringify(guardDescent(structuredClone(ast)))
    const наш = JSON.stringify(изЗначения(вызвать("Поставить сторожей", { "программа": значение(ast) })))
    const беда = расхождение(эталон, наш)
    if (беда !== null) беды.push(`${путь}: ${беда}`)
  }
  assert.deepEqual(беды, [], `сторожа разошлись с эталоном на ${беды.length} программах`)
})

/**
 * То же самое, но на ПОМЕЧЕННЫХ программах — и вот почему это отдельная
 * проверка, а не та же самая.
 *
 * Сторож ставится по отметке, а отметку кладёт анализ завершаемости
 * (`totality.mjs`, `markMeasureGuards`); `parse` её не кладёт никогда. Значит
 * проверка выше сравнивала два ТОЖДЕСТВЕННЫХ преобразования: программа без
 * отметок проходит обе стороны неизменной, и совпасть они не могли не суметь.
 * Ошибиться в том, КАК ставится сторож, она не мешала ничем.
 *
 * Улика измерена: из 172 разобранных программ корпуса отметки получают 46, и
 * ровно на них обе стороны впервые делают работу, а не пропускают её.
 */
const ПОМЕЧЕННЫЕ = ПРОГРАММЫ
  .map(({ путь, ast }) => ({ путь, ast: markMeasureGuards(ast) }))
  .filter(({ ast }) => Array.isArray(ast.measures) || Array.isArray(ast.descents))

test("помеченных программ в корпусе достаточно, иначе сверка сторожей пуста", () => {
  assert.ok(ПОМЕЧЕННЫЕ.length >= 40, `помеченных программ всего ${ПОМЕЧЕННЫЕ.length}`)
  for (const { путь, ast } of ПОМЕЧЕННЫЕ) {
    assert.notEqual(guardDescent(ast), ast, `${путь}: понижение не тронуло помеченную программу`)
  }
})

test("«Поставить сторожей» совпадает с эталоном на помеченных программах", (t) => {
  const беды = []
  for (const { путь, ast } of ПОМЕЧЕННЫЕ) {
    const эталон = JSON.stringify(guardDescent(structuredClone(ast)))
    const наш = JSON.stringify(изЗначения(вызвать("Поставить сторожей", { "программа": значение(ast) })))
    const беда = расхождение(эталон, наш)
    if (беда !== null) беды.push(`${путь}: ${беда}`)
  }
  t.diagnostic(`помеченных программ ${ПОМЕЧЕННЫЕ.length}`)
  assert.deepEqual(беды.slice(0, 5), [], `сторожа разошлись с эталоном на ${беды.length} программах`)
})

test("программа без высшего порядка проходит понижение НЕИЗМЕННОЙ", () => {
  /* Главное свойство близнеца, записанное в его же шапке: нет `fnref` и
     `apply` — нет и обхода. Байт не меняется не «по построению обхода», а
     потому, что обхода не было. Проверяется на настоящих программах корпуса, а
     не на выдуманной: выдуманная доказывала бы, что так бывает. */
  const без = ПРОГРАММЫ.filter(({ ast }) => {
    const текст = JSON.stringify(ast)
    return !текст.includes('"fnref"') && !текст.includes('"apply"')
  })
  assert.ok(без.length > 10, `программ без высшего порядка нашлось ${без.length} — мало для проверки`)
  const беды = []
  for (const { путь, ast } of без) {
    const было = JSON.stringify(ast)
    const стало = JSON.stringify(изЗначения(вызвать("Дефункционализировать", { "программа": значение(ast) })))
    if (было !== стало) беды.push(`${путь}: ${расхождение(было, стало)}`)
  }
  assert.deepEqual(беды, [], `понижение тронуло ${беды.length} программ, в которых трогать нечего`)
})
