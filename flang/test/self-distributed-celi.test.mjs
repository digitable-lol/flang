/* ─────────────────── значения на проводе прогонщика ─────────────────── */

/* Протокол прогонщика один на все восемь целей (`flang_cli`): число едет
   строкой, потому что JSON не знает ни NaN, ни бесконечностей, ни знака нуля. */
const вариантли = (это) =>
  это !== null && typeof это === "object" && typeof это.variant === "string" && typeof это.fields === "object" && это.fields !== null

function вТег(значение) {
  if (значение === null || значение === undefined) return null
  if (typeof значение === "boolean") return значение
  if (typeof значение === "number") return { n: Object.is(значение, -0) ? "-0" : String(значение) }
  if (typeof значение === "string") return { s: значение }
  if (Array.isArray(значение)) return { l: значение.map(вТег) }
  if (вариантли(значение)) return { v: значение.variant, f: Object.entries(значение.fields).map(([к, з]) => [к, вТег(з)]) }
  if (typeof значение === "object") return { r: Object.entries(значение).map(([к, з]) => [к, вТег(з)]) }
  throw new Error(`нечего кодировать: ${typeof значение}`)
}

function изТега(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return узел.n === "-0" ? -0 : Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(изТега)
  if (Object.hasOwn(узел, "r")) { const з = {}; for (const [к, э] of узел.r) з[к] = изТега(э); return з }
  if (Object.hasOwn(узел, "v")) { const п = {}; for (const [к, э] of узел.f ?? []) п[к] = изТега(э); return { variant: узел.v, fields: п } }
  throw new Error(`нечего раскодировать: ${JSON.stringify(узел)}`)
}

/* ─────────────────── перевод JSON ↔ «Значение» ─────────────────── */

/* Механический перевод, повторяющий форму и порядок ключей: решать он ничего не
   должен, иначе прогон проверял бы сам себя. Тот же, что в
   `self-distributed.test.mjs`, и по той же причине. */
const скаляр = (это) => {
  if (это === null) return { variant: "Скаляр ничто", fields: {} }
  if (typeof это === "string") return { variant: "Скаляр строка", fields: { значение: это } }
  if (typeof это === "number") return { variant: "Скаляр число", fields: { значение: это } }
  if (typeof это === "boolean") return { variant: "Скаляр признак", fields: { значение: это } }
  throw new Error(`не скаляр: ${String(это)}`)
}

function вЗначение(узел) {
  if (узел === undefined) return { variant: "Значение скаляра", fields: { скаляр: скаляр(null) } }
  if (Array.isArray(узел)) return { variant: "Значение списка", fields: { элементы: узел.map(вЗначение) } }
  if (узел !== null && typeof узел === "object") {
    return {
      variant: "Значение записи",
      fields: {
        поля: Object.entries(узел)
          .filter(([, з]) => з !== undefined)
          .map(([ключ, з]) => ({ ключ, значение: вЗначение(з) })),
      },
    }
  }
  return { variant: "Значение скаляра", fields: { скаляр: скаляр(узел) } }
}

function изЗначения(зн) {
  const вид = зн?.variant
  if (вид === "Значение списка") return зн.fields["элементы"].map(изЗначения)
  if (вид === "Значение записи") {
    const запись = {}
    for (const поле of зн.fields["поля"]) запись[поле["ключ"]] = изЗначения(поле["значение"])
    return запись
  }
  if (вид === "Значение скаляра") {
    const с = зн.fields["скаляр"]
    if (с.variant === "Скаляр ничто") return null
    return с.fields["значение"]
  }
  throw new Error(`неизвестный вид «Значение»: ${вид}`)
}

