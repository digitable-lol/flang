/* ─────────────────── цели печати ─────────────────── */

/* Имя модуля или класса берётся из САМОГО напечатанного Makefile, а не
   переписывается сюда: правило перевода имени в латиницу живёт в печати, и
   второй его экземпляр разошёлся бы с первым на первом же переименовании. */
function изMakefile(каталог, ключ) {
  const текст = readFileSync(join(каталог, "Makefile"), "utf8")
  const строка = текст.split("\n").find((это) => это.startsWith(`${ключ} ?=`))
  assert.ok(строка !== undefined, `в Makefile нет «${ключ} ?=»`)
  return строка.slice(`${ключ} ?=`.length).trim()
}

const ЦЕЛИ = [
  {
    имя: "js", тулчейн: "node", ищем: ["node"], собрать: null,
    прогон: (каталог) => ["node", ["flang_cli.js", globSync("*.js", { cwd: каталог }).find((ф) => ф !== "flang_cli.js")]],
  },
  {
    имя: "python", тулчейн: "python", ищем: ["python3", "python"], собрать: ["check"],
    прогон: (каталог, чем) => [чем, ["-B", "flang_cli.py", изMakefile(каталог, "MODULE")]],
  },
  { имя: "go", тулчейн: "go", ищем: ["go"], собрать: [], прогон: () => ["./flang_cli", []] },
  { имя: "c", тулчейн: "c", ищем: ["cc", "gcc"], собрать: [], прогон: () => ["./flang_cli", []] },
  { имя: "rust", тулчейн: "rust", ищем: ["cargo"], собрать: ["build"], прогон: () => ["./target/debug/flang_cli", []] },
  {
    имя: "java", тулчейн: "java", ищем: ["javac"], собрать: ["build"],
    прогон: (каталог) => ["java", ["-cp", ".", "FlangCli", изMakefile(каталог, "CLASS")]],
  },
  {
    имя: "csharp", тулчейн: "dotnet", ищем: ["dotnet"], собрать: ["build"],
    /* `dotnet run -- <довод>` в dotnet 10 отдаёт программе и свои ключи тоже,
       поэтому собранная библиотека зовётся напрямую. */
    прогон: (каталог) => ["dotnet", [globSync("bin/**/flang.dll", { cwd: каталог })[0], изMakefile(каталог, "CLASS")]],
  },
  {
    имя: "elixir", тулчейн: "elixir", ищем: ["elixir"], собрать: ["build"],
    прогон: (каталог) => ["elixir", ["-pa", "_build", "-e", `Flang.Cli.main(["${изMakefile(каталог, "MODULE")}"])`]],
  },
]

let целейпрошло = 0
let целейпропущено = 0
let сверокВсего = 0
let байтСверено = 0

for (const цель of ЦЕЛИ) {
  test(`распределённость: доказуемая половина печатается в цель ${цель.имя} и отвечает как свидетель`, (t) => {
    const чем = цель.ищем.map((это) => findExecutable(это)).find((это) => это !== null)
    if (чем === undefined || чем === null) {
      целейпропущено += 1
      return missingToolchain(t, цель.тулчейн, `тулчейн «${цель.тулчейн}» не найден (ни в PATH, ни в FTS_TOOLCHAIN_PATH) — пропуск`)
    }
    const каталог = join(рабочий, цель.имя)
    const среда = средаСборки(рабочий, { LC_ALL: "C.UTF-8" })

    const печать = spawnSync(process.execPath, [join(корень, "flang/bin/flang.mjs"), "emit", эталон, "--target", цель.имя, "--out", каталог], {
      cwd: корень, encoding: "utf8", env: среда, maxBuffer: 256 * 1024 * 1024,
    })
    assert.equal(печать.status, 0, `печать в ${цель.имя} отказала:\n${печать.stdout}\n${печать.stderr}`)

    if (цель.собрать !== null) {
      const сборка = spawnSync("make", цель.собрать, { cwd: каталог, encoding: "utf8", env: среда, maxBuffer: 256 * 1024 * 1024, timeout: 900_000 })
      assert.equal(сборка.status, 0, `тулчейн ${цель.имя} не принял напечатанное:\n${сборка.stdout}\n${сборка.stderr}`)
    }

    /* Один процесс на все вопросы: запуск дорог, вопрос дёшев. */
    const [чемЗвать, доводы] = цель.прогон(каталог, чем)
    const вход = `${вопросы.map((в) => JSON.stringify(в.запрос)).join("\n")}\n`
    const вывод = execFileSync(чемЗвать, доводы, {
      cwd: каталог, input: вход, encoding: "utf8", env: среда, maxBuffer: 1024 * 1024 * 1024, timeout: 900_000,
    })
    const строки = вывод.split("\n").filter((это) => это.trim() !== "")
    assert.equal(строки.length, вопросы.length, `цель ${цель.имя} ответила ${строки.length} раз на ${вопросы.length} вопросов`)

    const развалы = []
    for (const [номер, вопрос] of вопросы.entries()) {
      const ответ = JSON.parse(строки[номер])
      if (ответ.ok !== true) { развалы.push(`${вопрос.что}: отказ ${ответ.code} — ${ответ.message}`); continue }
      const получено = вопрос.привести(изТега(ответ.value))
      сверокВсего += 1
      байтСверено += вопрос.ждём.length
      if (получено !== вопрос.ждём) {
        const где = [...вопрос.ждём].findIndex((з, и) => з !== получено[и])
        развалы.push(
          `${вопрос.что}, первый разошедшийся байт ${где}:\n` +
            `  свидетель: …${вопрос.ждём.slice(Math.max(0, где - 60), где + 60)}…\n` +
            `  цель ${цель.имя}: …${получено.slice(Math.max(0, где - 60), где + 60)}…`,
        )
      }
      if (развалы.length > 5) break
    }
    assert.deepEqual(развалы, [], `цель ${цель.имя} разошлась со свидетелем:\n${развалы.join("\n")}`)
    целейпрошло += 1
  })
}

test.after(() => {
  console.log(`целей печати ${ЦЕЛИ.length}: прошло ${целейпрошло}, пропущено ${целейпропущено}`)
  console.log(`программ конкурентности ${программ}, прогонов ${прогонов}, значений на проводе ${значения.length + внеJSON.length} (вне корпуса ${внеКорпуса.length + 1}, вне JSON ${внеJSON.length} — только обратной стороной)`)
  console.log(`меток, встреченных в корпусе, ${метки.size}: ${[...метки].sort().map((м) => `«${м}»`).join(", ")}`)
  console.log(`вопросов к каждой цели ${вопросы.length}, сверок всего ${сверокВсего}, байт сверенного ответа ${байтСверено}`)
})
