/**
 * Распределённость у ВОСЬМИ целей печати — та её половина, которую можно
 * доказать.
 *
 * ── Что здесь проверяется и зачем ───────────────────────────────────────────
 * До этого прогона распределённость была у одной цели: узел
 * `flang/conc/distributed.mjs` написан на JavaScript и работает с тем, что
 * печатает цель JavaScript. Написать такой же узел ещё в семи языках — это семь
 * раз по 459 строк чужого кода, и каждая из семи копий разошлась бы с
 * остальными на первой же правке.
 *
 * Поэтому вопрос поставлен иначе: НЕ «напишем ли мы узел на седьмом языке», а
 * «сколько узла умеет напечатать сам компилятор». Ответ считается здесь, а не
 * оценивается: эталон `flang/self/distributed.flang` печатается в каждую из
 * восьми целей, собирается настоящим тулчейном этой цели, запускается и
 * отвечает на те же вопросы, что свидетель на JavaScript. Расхождение хоть в
 * одном байте — красный прогон.
 *
 * Что при этом доказано и что нет, сказано прямо:
 *
 *   • ДОКАЗАНО: значения на проводе (кодирование и раскодирование), сроки,
 *     закрытые списки (три состояния связи, четыре вида кадра, семь меток
 *     значений), размещение, адреса, «кого роняет разрыв». Это ровно та часть
 *     узла, у которой нет ни сокета, ни часов, ни изменяемого состояния;
 *   • НЕ ДОКАЗАНО и здесь не проверяется: сокеты, таймеры, таблица процессов,
 *     планировщик. Мир в язык не втаскивают, и напечатать его компилятор не
 *     может. Цена названа числом в `flang/conc/DISTRIBUTED.md`.
 *
 * То есть «распределённость у восьми целей» здесь значит: **два узла на разных
 * целях печати поймут провод друг друга байт в байт**, а не «узел на Rust
 * готов». Первое проверено, второе не обещано.
 *
 * ── Почему сверка идёт со свидетелем, а не с самим собой ────────────────────
 * Ожидания считает `flang/conc/distributed.mjs` — тот самый узел, который
 * работает сегодня. Сравнивать напечатанное с напечатанным значило бы проверять,
 * что восемь целей одинаково ошибаются.
 *
 * ── Если тулчейна нет ───────────────────────────────────────────────────────
 * Цель честно пропускается через `missingToolchain`. `FTS_REQUIRE_TOOLCHAINS`
 * превращает пропуск в падение. Молчаливый пропуск, выглядящий как успех,
 * недопустим — поэтому в конце печатается, сколько целей прошло и сколько
 * пропущено.
 */
