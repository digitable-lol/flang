/**
 * Сверка эталона распределённости со свидетелем на JavaScript — побайтовая.
 *
 * ── Что сверяется и на чём ──────────────────────────────────────────────────
 * `flang/conc/distributed.mjs` — 940 строк, и большинство из них МИР: `node:net`,
 * `setInterval`, `setTimeout`, `Date.now`. Мир в язык не втаскивают, поэтому
 * эталон `flang/self/distributed.flang` берёт ровно ту часть свидетеля, у которой
 * нет ни сокета, ни часов, ни изменяемого состояния, и сверяется здесь:
 *
 *   1. `закодировать` — на КАЖДОМ узле КАЖДОЙ программы корпуса, на КАЖДОМ
 *      состоянии и КАЖДОМ сообщении КАЖДОГО прогона корпуса. Не «то же множество полей», а
 *      `JSON.stringify` целиком, вместе с порядком ключей;
 *   2. `размещениеУзла().процессы` — на настоящем файле размещения
 *      (`flang/conc/examples/distributed.json`), обеими его сторонами;
 *   3. `разделитьАдрес` — на каждом адресе, какой в этом файле есть;
 *   4. `СРОКИ`, `СВЯЗЬ`, `КАДР` — постоянные, ради которых узел вообще
 *      настраивается;
 *   5. представители узла — не из формулы в этом файле, а из `создатьУзел`:
 *      узел строит таблицу процессов ДО всякого сокета, и `связи()` её
 *      показывает. Сверяется с «Кого роняет разрыв» эталона.
 *
 * ── Корпус прогонов, а не список в этом файле ───────────────────────────────
 * Значения на проводе берутся из ДВУХ мест, и оба настоящие: узлы всех
 * связанных программ дерева (это даёт записи, списки, строки, числа, признаки и
 * `ничто` десятками тысяч) и состояния всех прогонов конкурентных примеров
 * (это даёт ВАРИАНТЫ — сообщения, которые правда ходят между процессами).
 * Ни одно значение здесь не выдумано.
 *
 * Четыре значения, которых в корпусе нет и быть не может, потому что их нет в
 * JSON, — `NaN`, обе бесконечности и минус ноль — стоят отдельным списком, и
 * это названо вслух: ради них метка «ч» и заведена, а корпус их не даёт.
 *
 * ── Изъятие ─────────────────────────────────────────────────────────────────
 * Сверка обязана уметь краснеть. Порча подаётся переменной `PORCHA` — имя
 * ЛАТИНСКОЕ нарочно: переменная с кириллическим именем в zsh не экспортируется,
 * и порча тихо не доезжает, давая ложный ноль расхождений. Порча, не нашедшая
 * своего места, роняет прогон кодом 2.
 *
 * Четыре порчи, четыре числа (см. `PORCHI` ниже).
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { СВЯЗЬ, СРОКИ, КАДР, закодировать, размещениеУзла, разделитьАдрес } from "../conc/distributed.mjs"
import { runConcurrent } from "../src/conc.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { вЗначение } from "./self-evaluator.mjs"
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const исходник = readFileSync(корень + "flang/self/distributed.flang", "utf8")
const порча = process.env.PORCHA ?? ""

/* Каждая порча задевает ПОСЧИТАННОЕ, а не украшение: метку минус нуля (без неё
   −0 уехал бы нулём и вернулся нулём), метку варианта (без неё вариант уехал бы
   записью и обработчик его не разобрал бы), четвёртый вид кадра и пятую часть
   срока сторожа. */
const ПОРЧИ = {
  "минус ноль": ['«Строка как узел» от "-0"', '«Строка как узел» от "0"'],
  "вариант": ['      иначе «Есть поле у узла» от «узел» и "fields"', '      иначе нет'],
  "кадр": ['["привет", "письмо", "пульс", "отбой"]', '["привет", "письмо", "пульс"]'],
  "сторож": ['((«срок» минус («срок» остаток от 5)) делить на 5)', '((«срок» минус («срок» остаток от 4)) делить на 4)'],
}
let текст = исходник
if (порча !== "") {
  const пара = ПОРЧИ[порча]
  if (пара === undefined) { console.error(`порча «${порча}» не объявлена`); process.exit(2) }
  текст = исходник.replace(пара[0], пара[1])
  if (текст === исходник) { console.error(`порча «${порча}» не нашла своего места`); process.exit(2) }
}

const { diagnostics: беды, ...слой } = await linkProgram(корень + "flang/self/distributed.flang", текст, parse)
if (беды.length > 0) {
  console.error("не связался:", беды.map((б) => `${б.code}: ${б.message}`).join("\n"))
  process.exit(1)
}
const среда = createRuntime(слой, { maxSteps: 300_000_000, maxDepth: 20_000 })

/* Обратный перевод «Значение» → JSON. Механический и порядок ключей хранит:
   иначе побайтовая сверка сравнивала бы кодировку, а не ответ. */
function изЗначения(зн) {
  const вид = зн?.variant
  if (вид === "Значение списка") return зн.fields["элементы"].map(изЗначения)
  if (вид === "Значение записи") {
    const запись = {}
    for (const поле of зн.fields["поля"]) запись[поле["ключ"]] = изЗначения(поле["значение"])
    return запись
  }
  if (вид === "Значение скаляра") {
    const с = зн.fields["скаляр"]
    if (с.variant === "Скаляр ничто") return null
    return с.fields["значение"]
  }
  throw new Error(`неизвестный вид «Значение»: ${вид}`)
}

let расхождений = 0
const развал = (что, ожидание, получено) => {
  расхождений += 1
  const где = [...ожидание].findIndex((з, и) => з !== получено[и])
  console.log(`РАСХОЖДЕНИЕ ${что}, первый разошедшийся байт ${где}:\n  свидетель:  …${ожидание.slice(Math.max(0, где - 60), где + 60)}…\n  эталон: …${получено.slice(Math.max(0, где - 60), где + 60)}…`)
}
const сверить = (что, ожидание, получено) => {
  const о = JSON.stringify(ожидание)
  const п = JSON.stringify(получено)
  if (о !== п) развал(что, о, п)
}

/* ══════════ корпус значений: программы дерева и прогоны примеров ══════════ */

const каталоги = ["flang/conc/examples", "flang/examples", "flang/stdlib", "flang/core"]
const пути = каталоги.flatMap((к) => globSync("**/*.flang", { cwd: корень + к + "/" }).sort().map((и) => к + "/" + и))

const значения = []
let программ = 0, прогонов = 0, состояний = 0, сообщений = 0

/* Узлы всех связанных программ: записи, списки, строки, числа, признаки, ничто. */
for (const путь of пути) {
  let программа
  try {
    const { diagnostics: _, ...собрана } = await linkProgram(корень + путь, readFileSync(корень + путь, "utf8"), parse)
    программа = собрана
  } catch { continue }
  программ += 1
  значения.push(программа)
  /* Состояния настоящих прогонов — единственное место, откуда в корпус попадают
     ВАРИАНТЫ: сообщения, которые правда ходят между процессами. */
  for (const прогон of программа.runs ?? []) {
    const семена = Array.isArray(прогон.seeds) && прогон.seeds.length > 0 ? прогон.seeds.slice(0, 3) : [прогон.seed ?? 0]
    for (const семя of семена) {
      let итог
      try { итог = runConcurrent(программа, { ...прогон, seed: семя }) } catch { continue }
      прогонов += 1
      for (const состояние of Object.values(итог.состояния ?? {})) { значения.push(состояние); состояний += 1 }
      /* Сообщения журнала — это буквально то, что уехало бы по проводу: тот же
         вариант, те же поля, тот же порядок. Ради них метка «в» и заведена. */
      for (const строка of итог.журнал ?? []) {
        if (строка.сообщение === undefined) continue
        значения.push(строка.сообщение)
        сообщений += 1
      }
    }
  }
}

/* Четыре значения, которых в корпусе нет и быть не может: JSON их не умеет, а
   метка «ч» заведена ровно ради них. Названо вслух, а не подмешано в корпус. */
const внеJSON = [NaN, Infinity, -Infinity, -0]
for (const это of внеJSON) значения.push(это)

let байтПровода = 0
const меток = new Set()
for (const значение of значения) {
  const кодСвидетеля = закодировать(значение)
  const ожидание = JSON.stringify(кодСвидетеля)
  const получено = JSON.stringify(изЗначения(среда.call("Закодировать", { узел: вЗначение(значение) })))
  байтПровода += ожидание.length
  if (ожидание !== получено) развал("значения на проводе", ожидание, получено)
  /* Метка — первый элемент кадра у свидетеля, и эталон обязан звать её тем же
     именем сам по себе, а не только внутри кодирования. */
  const метка = среда.call("Метка значения", { узел: вЗначение(значение) })
  меток.add(метка)
  if (кодСвидетеля[0] !== метка) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ метки: свидетель «${кодСвидетеля[0]}», эталон «${метка}»`)
  }
}

/* ══════════ размещение: настоящий файл, обе его стороны ══════════ */

const файлРазмещения = JSON.parse(readFileSync(корень + "flang/conc/examples/distributed.json", "utf8"))
const узлыФайла = Object.keys(файлРазмещения.узлы)
for (const имяУзла of узлыФайла) {
  сверить(
    `размещение процессов на узле «${имяУзла}»`,
    размещениеУзла(файлРазмещения, имяУзла).процессы,
    изЗначения(среда.call("Размещение процессов", { файл: вЗначение(файлРазмещения) })),
  )
}
/* Однозначность: настоящий файл однозначен, а испорченный — нет, и эталон
   обязан НАЗВАТЬ процесс, как называет его свидетель отказом. */
const вдвойне = JSON.parse(JSON.stringify(файлРазмещения))
вдвойне.узлы[узлыФайла[1]].процессы.push(файлРазмещения.узлы[узлыФайла[0]].процессы[0])
for (const [что, файл, ждём] of [["целый", файлРазмещения, ""], ["с двойным размещением", вдвойне, файлРазмещения.узлы[узлыФайла[0]].процессы[0]]]) {
  let сказалСвидетель = ""
  try { размещениеУзла(файл, узлыФайла[0]) } catch (беда) { сказалСвидетель = беда.message }
  const сказалЭталон = среда.call("Размещён дважды", { файл: вЗначение(файл) })
  if (сказалЭталон !== ждём) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ размещения (${что}): эталон назвал «${сказалЭталон}», ждали «${ждём}»`)
  }
  if ((сказалСвидетель !== "") !== (сказалЭталон !== "")) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ размещения (${что}): свидетель «${сказалСвидетель}», эталон «${сказалЭталон}»`)
  }
}

/* ══════════ адреса: каждый, какой в файле есть ══════════ */

const адреса = []
for (const описание of Object.values(файлРазмещения.узлы)) {
  if (typeof описание.слушать === "string") адреса.push(описание.слушать)
  for (const адрес of Object.values(описание.звонить ?? {})) адреса.push(адрес)
}
адреса.push("::1:9001", "localhost:0")
for (const адрес of адреса) {
  const [хозяин, порт] = разделитьАдрес(адрес)
  сверить(`хозяин адреса «${адрес}»`, хозяин, среда.call("Хозяин адреса", { адрес }))
  сверить(`порт адреса «${адрес}»`, порт, среда.call("Порт адреса", { адрес }))
}

/* ══════════ постоянные ══════════ */

const постоянные = [
  ["пульс по умолчанию", СРОКИ.пульс, среда.call("Пульс по умолчанию", {})],
  ["срок по умолчанию", СРОКИ.срок, среда.call("Срок по умолчанию", {})],
  ["пауза по умолчанию", СРОКИ.пауза, среда.call("Пауза по умолчанию", {})],
  /* Формула сторожа стоит в `distributed.mjs` выражением внутри `сторожить`, а
     не постоянной: сверяется само выражение, слово в слово с ним. */
  ["период сторожа при сроке по умолчанию", Math.max(20, Math.floor(СРОКИ.срок / 5)), среда.call("Период сторожа", { срок: СРОКИ.срок })],
  ["состояния связи", Object.values(СВЯЗЬ), среда.call("Состояния связи", {})],
  ["виды кадров", Object.values(КАДР), среда.call("Виды кадров", {})],
]
for (const [имя, ожидание, получено] of постоянные) сверить(`постоянной ${имя}`, ожидание, получено)

/* ══════════ представители: таблица процессов настоящего узла ══════════ */

/* `создатьУзел` строит таблицу процессов ДО всякого сокета, и `связи()` её
   показывает. Значит «кого уронит разрыв» можно спросить у СВИДЕТЕЛЯ, а не у
   формулы, переписанной в этот файл. */
const { emitJs } = await import("../src/emit/js.mjs")
const { создатьУзел } = await import("../conc/distributed.mjs")
const путьПрограммы = "flang/conc/examples/distributed.flang"
const напечатано = emitJs(parse(readFileSync(корень + путьПрограммы, "utf8"), путьПрограммы)).files[0].content
const модуль = await import(`data:text/javascript;charset=utf-8;base64,${Buffer.from(напечатано, "utf8").toString("base64")}`)
let представителей = 0
for (const имяУзла of узлыФайла) {
  const узел = создатьУзел({
    имя: имяУзла,
    модуль,
    хэш: "0".repeat(64),
    размещение: размещениеУзла(файлРазмещения, имяУзла),
    сказать: () => {},
  })
  for (const сосед of узлыФайла) {
    const ожидание = Object.entries(узел.связи())
      .filter(([ключ, что]) => ключ.startsWith("представитель:") && что.узел === сосед)
      .map(([ключ]) => ключ.slice("представитель:".length))
    представителей += ожидание.length
    сверить(
      `кого роняет разрыв «${имяУзла}» ↔ «${сосед}»`,
      ожидание,
      среда.call("Кого роняет разрыв", { файл: вЗначение(файлРазмещения), я: имяУзла, сосед }),
    )
  }
  узел.остановиться()
}

test("распределённость: эталон на flang сходится со свидетелем побайтово", () => {
  assert.equal(расхождений, 0)
})

/* Охват печатается числами: сверка, чей корпус может тихо схлопнуться, зелена
   ровно так же, как исправная. */
console.log(`программ ${программ}, прогонов ${прогонов}, состояний из прогонов ${состояний}, сообщений из журналов ${сообщений}`)
console.log(`значений на проводе ${значения.length} (из них вне JSON ${внеJSON.length}), байт сверенного провода ${байтПровода}`)
console.log(`меток, встреченных в корпусе, ${меток.size}: ${[...меток].sort().map((м) => `«${м}»`).join(", ")}`)
console.log(`узлов размещения ${узлыФайла.length}, адресов ${адреса.length}, представителей ${представителей}, постоянных ${постоянные.length}`)
console.log(`расхождений ${расхождений}`)
