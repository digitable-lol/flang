/**
 * Лимит шагов поднят с миллиона до двухсот: печать в C# — работа с целым AST сразу,
 * и самая большая программа репозитория укладывается между шестьюдесятью и ста
 * миллионами шагов. Лимит здесь не формальность: он ловит превращение печати в
 * перебор. Глубина — по вложенности AST, поэтому её хватает штатной.
 *
 * ПОДНЯТ СО СТА ДО ДВУХСОТ МИЛЛИОНОВ, и число измерено, а не прикинуто. Печать
 * `flang/self/emit-c.flang` — самая дорогая из ста с лишним программ
 * репозитория — стоит 131 257 648 витков после того, как в этот файл прибавилось
 * двадцать функций (`work/skorost`: доказанная арифметика печатается выражением,
 * а сверку тега печать ставит сама). До прибавки она укладывалась в сто
 * миллионов, и запаса там было около 20 % — любое следующее пополнение выбило бы
 * лимит независимо от того, чем именно. Двести миллионов — это 1,5 запаса над
 * замером; сторожем лимит при этом быть не перестаёт: превращение печати в
 * перебор он поймает так же.
 */
const ШАГИ = { maxSteps: 200_000_000, maxDepth: 10_000 }
const вызвать = (имя, аргументы) => evaluate(программа, имя, аргументы, ШАГИ)

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и свидетель их различает. */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/* Рантайм печатается дословно и приходит параметром: читать файлы язык не
   умеет и не должен. Берём те же самые файлы, что берёт свидетель. */
const рантайм = (имя) => readFileSync(new URL(`../src/emit/csharp/${имя}`, import.meta.url), "utf8")
const РАНТАЙМ = {
  "рантайм значение": рантайм("Value.cs"),
  "рантайм поле": рантайм("Field.cs"),
  "рантайм ошибка": рантайм("FlangError.cs"),
  "рантайм контекст": рантайм("Ctx.cs"),
  "рантайм операции": рантайм("Flang.cs"),
  "исходник прогонщика": рантайм("FlangCli.cs"),
}

/*
 * Граница входа — объявленные типы параметров таблицей. Приходит она параметром
 * по той же причине, что и текст рантайма: решить, какой у параметра
 * объявленный тип, — работа слоя типов (`таблицаВхода` в `src/types.mjs`), а не
 * печати. Печать отвечает за то, что эти данные лягут в C# правильными байтами,
 * и вот это здесь и сверяется — побайтово, без всякого вычитания.
 *
 * Таблица считается на ТОЙ ЖЕ программе, что приходит сюда, и ДО понижения:
 * `emitCsharp` зовёт `таблицаВхода` раньше `defunctionalize`. Позови её на
 * понижённой — параметры диспетчера приехали бы в таблицу лишними строками.
 */
function границаВхода(программа) {
  const таблица = таблицаВхода(программа)
  return {
    "типы входа": таблица.типы.map((тип) => ({
      "вид": тип.вид,
      "имя": тип.имя,
      "владелец": тип.владелец,
      "ничто": тип.ничто,
      "целое": тип.целое,
      "отрезок": тип.отрезок,
      "низ": тип.низ,
      "верх": тип.верх,
      "элемент": тип.элемент,
      "поле с": тип.полеС,
      "полей": тип.полей,
      "вариант с": тип.вариантС,
      "вариантов": тип.вариантов,
    })),
    "поля входа": таблица.поля.map((поле) => ({ "имя": поле.имя, "тип": поле.тип })),
    "варианты входа": таблица.варианты.map((вариант) => ({
      "имя": вариант.имя,
      "поле с": вариант.полеС,
      "полей": вариант.полей,
    })),
    "параметры входа": таблица.параметры.map((параметр) => ({
      "функция": параметр.функция,
      "параметр": параметр.параметр,
      "тип": параметр.тип,
    })),
  }
}

function настройки(ast, опции = {}) {
  return {
    "путь": опции.path ?? "",
    "есть путь": опции.path !== undefined,
    "база": опции.indexBase === 0 ? 0 : 1,
    "предел глубины": опции.maxDepth ?? 10_000,
    "предел шагов": опции.maxSteps ?? 1_000_000,
    "прогонщик": опции.cli !== false,
    ...РАНТАЙМ,
    ...границаВхода(ast),
  }
}

/** Печать на flang: список файлов в той же форме, что у свидетеля. */
function напечатать(ast, опции = {}) {
  const итог = вызвать("Печать программы шарп", { "программа": значение(ast), "настройки": настройки(ast, опции) })
  return { files: итог.файлы.map((файл) => ({ path: файл.путь, content: файл.содержимое })), error: итог.ошибка }
}

/** Файл реализации модуля: единственный .cs, который не принадлежит рантайму. */
const РАНТАЙМНЫЕ = new Set(["Value.cs", "Field.cs", "FlangError.cs", "Ctx.cs", "Flang.cs", "FlangCli.cs"])
function исходникМодуля(файлы) {
  return файлы.find((файл) => файл.path.endsWith(".cs") && !РАНТАЙМНЫЕ.has(файл.path)).content
}

/**
 * Побайтовая сверка со свидетелем. Возвращает `null` при совпадении и текст
 * первого расхождения иначе — краснеть решает вызывающий, потому что на
 * недописанном эталоне важнее СЧЁТ совпавших, чем первый же отказ.
 */
function расхождение(имя, ast, опции = {}) {
  let свидетель
  try {
    свидетель = emitCsharp(ast, опции)
  } catch (ошибка) {
    return `${имя}: свидетель отказал (${ошибка.message}) — программа не годится для сверки`
  }
  let мой
  try {
    мой = напечатать(ast, опции)
  } catch (ошибка) {
    return `${имя}: печать на flang упала: ${ошибка.message}`
  }
  if (мой.error !== "") return `${имя}: печать на flang отказала: ${мой.error}`
  const пути = мой.files.map((файл) => файл.path)
  const ожидаемые = свидетель.files.map((файл) => файл.path)
  if (пути.join("|") !== ожидаемые.join("|")) {
    return `${имя}: набор файлов не совпал\n  свидетель: ${ожидаемые.join(", ")}\n  flang:  ${пути.join(", ")}`
  }
  /* ДОЛГ ЭТАЛОНА СНЯТ, И ВЫЧИТАНИЕ УБРАНО.
     Здесь стояло вычитание: печати ГРАНИЦЫ ВХОДА у эталона не было вовсе, и
     названный блок ВЫРЕЗАЛСЯ из вывода свидетеля перед сравнением. Долг закрыт
     — «Печать границы входа шарп» есть в эталоне, таблица приезжает
     настройками, — и сверяются полные файлы, байт в байт, без единого среза.
     Требование «блок обязан быть» стоит теперь на ОБЕИХ сторонах и красит
     сверку само, без утверждения-подпорки. */
  for (const [индекс, файл] of свидетель.files.entries()) {
    const наш = мой.files[индекс].content
    const ожидаемое = файл.content
    if (наш === ожидаемое) continue
    const слева = ожидаемое.split("\n")
    const справа = наш.split("\n")
    let строка = 0
    while (строка < слева.length && строка < справа.length && слева[строка] === справа[строка]) строка += 1
    return (
      `${имя}: ${файл.path} разошёлся на строке ${строка + 1}\n` +
      `  свидетель: ${JSON.stringify(слева[строка])}\n` +
      `  flang:  ${JSON.stringify(справа[строка])}`
    )
  }
  return null
}

/** Побайтовая сверка, которая обязана пройти. */
function сверить(имя, ast, опции = {}) {
  const беда = расхождение(имя, ast, опции)
  if (беда !== null) assert.fail(беда)
}

/** Отказ печати: код и текст обязаны совпасть с тем, что бросает свидетель. */
function сверитьОтказ(имя, ast) {
  let ожидаемое = null
  try {
    emitCsharp(ast)
  } catch (ошибка) {
    ожидаемое = ошибка.message
  }
  assert.notEqual(ожидаемое, null, `${имя}: свидетель не отказал, сверять нечего`)
  assert.equal(напечатать(ast).error, ожидаемое, `${имя}: текст отказа разошёлся`)
}

/**
 * Прогон по набору программ со счётом. Печатает «совпало N из M», называет
 * первое расхождение и краснеет ровно тогда, когда совпали не все.
 */
function прогнать(t, заголовок, набор) {
  let совпало = 0
  const расхождения = []
  for (const [имя, ast, опции] of набор) {
    const беда = расхождение(имя, ast, опции ?? {})
    if (беда === null) совпало += 1
    else расхождения.push(беда)
  }
  t.diagnostic(`${заголовок}: побайтово совпало ${совпало} из ${набор.length}, разошлось ${расхождения.length}`)
  if (расхождения.length > 0) {
    assert.fail(
      `${заголовок}: совпало ${совпало} из ${набор.length}, разошлось ${расхождения.length}.\n` +
        `Первое расхождение:\n${расхождения[0]}\n` +
        (расхождения.length > 1 ? `…и ещё ${расхождения.length - 1}` : ""),
    )
  }
}

