test("программы репозитория: JavaScript совпадает со свидетелем побайтово", async (t) => {
  assert.ok(программыРепозитория.length >= 30, "программ стало подозрительно мало")
  const расхождения = []
  let совпало = 0
  for (const относительный of программыРепозитория) {
    const беда = сверить(относительный, await разобрать(относительный))
    if (беда === null) совпало += 1
    else расхождения.push(беда)
  }
  const всего = программыРепозитория.length
  t.diagnostic(`побайтово совпало ${совпало} из ${всего}, разошлось ${расхождения.length}`)
  if (расхождения.length > 0) {
    const первое = расхождения[0]
    t.diagnostic(`первое расхождение — ${первое.имя}: ${первое.вид}`)
    t.diagnostic(первое.текст)
    /* Раскладка по глубине совпавшего префикса: она растёт раньше, чем число
       совпавших целиком программ, и потому мерит работу честнее. */
    const байтовые = расхождения.filter((беда) => беда.вид === "байты").map((беда) => беда.строка)
    if (байтовые.length > 0) {
      const среднее = Math.round(байтовые.reduce((сумма, номер) => сумма + номер, 0) / байтовые.length)
      t.diagnostic(
        `из ${байтовые.length} байтовых расхождений первое приходится в среднем на строку ${среднее}, ` +
          `самое раннее — на ${Math.min(...байтовые)}, самое позднее — на ${Math.max(...байтовые)}`,
      )
    }
  }
  assert.ok(
    совпало >= ПОРОГ,
    `побайтово совпало ${совпало} из ${всего} при пороге ${ПОРОГ} — доля упала`,
  )
  assert.equal(совпало, всего, `не совпало ${расхождения.length} программ из ${всего}`)
})

/**
 * Сколько программ с числовой мерой расходится ИЗ-ЗА понижения, а не из-за
 * печати. Число — храповик: вниз оно ходить может (это улучшение), вверх нет.
 *
 * Причина измерена прямо: на `003-longest-substring…` свидетельское понижение
 * (`src/defunc.mjs`) ставит сторож двум функциям — по три постусловия
 * `FLANG_MEASURE` каждой, — а понижение на flang (`self/defunc.flang`) не
 * ставит ни одного. Это тот же долг, из-за которого на `main` красен
 * `self-emit-c.test.mjs` («сторож меры»), и закрывает его ветка
 * `work/self-measure-check`, а не этот слой: печатник читает готовое.
 *
 * Число 41 — не совпадение: ровно столько расхождений насчитала на корпусе
 * та ветка («было 41 из 41, стало 0 из 41»). Две независимые сверки сошлись
 * на одном числе, и это лучшая проверка, какая тут возможна.
 */
const СТОРОЖ_МЕРЫ_ОТ_ПОНИЖЕНИЯ = 41

test("сторож меры: расходится только понижение, и ровно на измеренном числе программ", async (t) => {
  /* Программы выше приходят в сверку БЕЗ отметок: отметку кладёт анализ
     завершаемости (`markMeasureGuards`), а его та сверка не звала, — значит
     сторожа там не было ни у одной стороны, и расхождения она поймать не
     могла бы. Здесь отметка ставится явно, и расходиться есть чему: имена
     сторожей, форма постусловия, место связки шага и порядок временных имён —
     всё это наблюдаемо в напечатанном JavaScript. */
  const отПонижения = []
  const прочие = []
  let отмеченных = 0
  let совпало = 0
  for (const относительный of программыРепозитория) {
    const ast = await разобрать(относительный)
    /*
     * ПРЕДОБРАБОТКА СВИДЕТЕЛЯ: markMeasureGuards, markProven — обе отметки переднего
     * края (`flang/bin/flang.mjs`, `loadProgramFromSource`: `markProven(markMeasure(…))`).
     * Свидетель печатает ТОЛЬКО отмеченную программу: ни `emit`, ни `run`, ни `test`,
     * ни `repl` непомеченной не видят, а печатник читает обе отметки — `доказана`
     * и `числовая`. Снимается ими не разница между реализациями, а разница между
     * тестом и работой: без них сверка сличала бы эталон с печатью, которой у
     * свидетеля не бывает, и молчала бы обо всех 2634 местах, где свидетель печатает
     * выражение вместо вызова помощника, а эталон — вызов.
     */
    /* Отметки кладутся ПО ОЧЕРЕДИ, а не одним выражением, потому что «есть ли у
       программы числовая мера» спрашивается у ПЕРВОЙ: `markMeasureGuards`
       возвращает ТОТ ЖЕ объект там, где мерить нечего, а `markProven` меняет
       почти всякую программу — арифметика есть везде. Слей их в одно, и признак
       «мера есть» стал бы признаком «арифметика есть», а отбор — холостым. */
    const сМерой = markMeasureGuards(ast)
    const помеченная = markProven(сМерой)
    /* Проход тождествен там, где числовой меры нет вовсе: он возвращает ТОТ ЖЕ
       объект. Такие программы уже сверены выше без отметок, второй раз незачем. */
    if (сМерой === ast) continue
    отмеченных += 1
    const свидетельский = emitJs(помеченная).files[0].content
    assert.match(свидетельский, /FLANG_MEASURE/u, `${относительный}: сторожа нет даже у свидетеля`)
    const беда = сверить(относительный, помеченная)
    if (беда === null) {
      совпало += 1
      continue
    }
    /* Разделяем две беды. Сторож меры, которого нет у эталона, — долг
       понижения (`self/defunc.flang`). Всё остальное — долг ЭТОГО слоя, и
       спрятать его за чужим долгом нельзя. */
    const наш = напечатать(помеченная).files[0].content
    if (наш.includes("FLANG_MEASURE")) прочие.push(беда)
    else отПонижения.push(беда)
  }
  assert.ok(отмеченных >= 40, `программ с числовой мерой нашлось ${отмеченных} — корпус подменили?`)
  t.diagnostic(
    `программ с числовой мерой ${отмеченных}: совпало побайтово ${совпало}, ` +
      `разошлось из-за понижения ${отПонижения.length}, из-за печати ${прочие.length}`,
  )
  if (прочие.length > 0) t.diagnostic(`первое расхождение печати — ${прочие[0].имя}: ${прочие[0].текст}`)
  assert.equal(прочие.length, 0, `печать разошлась на ${прочие.length} программах со сторожем меры`)
  assert.ok(
    отПонижения.length <= СТОРОЖ_МЕРЫ_ОТ_ПОНИЖЕНИЯ,
    `из-за понижения расходится ${отПонижения.length} программ против измеренных ` +
      `${СТОРОЖ_МЕРЫ_ОТ_ПОНИЖЕНИЯ} — долг растёт, а не закрывается`,
  )
})

