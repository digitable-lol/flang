test("сторож меры: программа с ним печатается побайтово так же", async (t) => {
  /* Программы выше приходят БЕЗ отметок: отметку кладёт анализ завершаемости
     (`markMeasureGuards`), а его в той сверке никто не звал, — значит сторожа
     там не было ни у одной стороны, и расхождения такая сверка поймать не
     могла бы.

     Здесь отметка ставится явно, и берутся ВСЕ программы дерева, у которых
     числовая мера есть, — список не выписан руками, потому что мера у функции
     появляется и пропадает вместе с её переписыванием, и жёсткий список
     краснел бы не о печати. Расходиться есть чему: сторож меры снимает у
     функции хвостовые вызовы (у неё появляются постусловия), и вместо `loop`
     печатается обычный возврат, а связки `довод N` уезжают в имена и
     комментарии.

     Понижение делается ЗАРАНЕЕ и эталонное (`defunctionalize`), и обеим
     сторонам отдаётся уже понижённая программа. Причина названа числом:
     `self/defunc.flang` ставит сторожа меры не так, как `src/defunc.mjs` — на
     `leetcode/003` понижения расходятся на 144-й строке JSON, эталон даёт
     `пусть «довод 1»`, близнец — голый вызов. Это долг понижения, он уже
     красный у `self-emit-c.test.mjs`, и тащить его сюда значило бы мерить
     чужую работу вместо своей. Повторное понижение — тождество: отметка меры
     снимается первым проходом, и второй ей уже нечего оборачивать. */
  const отмеченные = []
  for (const относительный of программыРепозитория) {
    const ast = await разобрать(относительный)
    const помеченная = markMeasureGuards(ast)
    if (помеченная === ast) continue
    отмеченные.push({ относительный, помеченная: defunctionalize(помеченная), сторожей: checkTotality(ast).guards.length })
  }
  assert.ok(отмеченные.length >= 10, `программ с числовой мерой ${отмеченные.length} — слишком мало`)
  const беды = []
  let сторожей = 0
  for (const { относительный, помеченная, сторожей: сколько } of отмеченные) {
    assert.match(emitRust(помеченная).files.map((файл) => файл.content).join(""), /FLANG_MEASURE/u, относительный)
    const беда = расхождение(относительный, помеченная)
    if (беда !== null) беды.push(беда)
    сторожей += сколько
  }
  t.diagnostic(`программ с числовой мерой: ${отмеченные.length}, сторожей в них: ${сторожей}`)
  свод(t, "программы со сторожами меры", беды, отмеченные.length)
})

