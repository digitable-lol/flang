/**
 * Вычислитель flang, написанный на flang, как источник ответов вычислений для
 * сверок законов и факт-чекинга.
 *
 * ── Зачем этот файл есть ────────────────────────────────────────────────────
 *
 * Законам моноида и изоморфизма, отношениям множеств, законам монады и
 * факт-чекингу мало РАЗОБРАТЬ программу — им надо её ВЫПОЛНИТЬ. Вычислителя
 * flang на flang в дереве не было, поэтому ответы вычислений приезжали в
 * эталонов ДАННЫМИ: таблицу считал свидетель `flang/src/interpret.mjs`, то есть
 * JavaScript. Круг «язык доказывает сам себя» на этом размыкался: вердикт о
 * ПОВЕДЕНИИ программы держался на чужом языке.
 *
 * Вычислитель появился — `flang/self/interpret.flang`, — и этот файл ставит его
 * на то самое место. Отсюда следует главное свойство, которого не было ни у
 * одной сверки: СЛОМАЙ ВЫЧИСЛИТЕЛЬ, И СВЕРКА ЗАКОНОВ ИЛИ ФАКТОВ ПОКРАСНЕЕТ.
 * Раньше она бы этого не заметила — ответы приходили готовыми.
 *
 * ── Запасного пути к свидетелю НЕТ ────────────────────────────────────────────
 *
 * Он был, пока срез вычислителя был неполон: вызов, упёршийся в `к числу`,
 * `к числу или беда`, постусловие или функцию первого класса, досчитывал свидетель
 * — 393 таких вызова у законов и 73 у факт-чекинга. Срез закончен, все четыре
 * формы вошли в него, и путь убран из кода: все 4480 ответов считает сам flang.
 *
 * Форма вне среза (`FLANG_SELF_EVAL_UNSUPPORTED`) теперь не уступка, а ОТКАЗ:
 * вызов записывается, вердикт от него расходится со свидетелем, и сверка краснеет
 * с кодом в тексте. Проверено изъятием — подмени ответ на «вне среза», и у
 * законов краснеют три проверки разом. Тихо досчитать за язык больше нечему.
 *
 * ── Что здесь НЕ решается ───────────────────────────────────────────────────
 *
 * Ни одного решения сверки этот файл не принимает: он не выбирает, кого звать,
 * на каких значениях, в каком порядке и что считать повтором. Он отвечает ровно
 * на один вопрос — «чему равен вызов такой-то функции на таких-то аргументах», —
 * и отвечает на него программой на flang.
 */
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { isVariant, variant } from "../src/builtins.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"

/** Код, которым слой на flang отвечает на форму, не вошедшую в срез. */
export const ВНЕ_СРЕЗА = "FLANG_SELF_EVAL_UNSUPPORTED"

/**
 * УСТУПОК СВИДЕТЕЛЮ БОЛЬШЕ НЕТ, и это не оборот речи.
 *
 * Пока срез вычислителя был неполон, вызов, упёршийся в его границу, считал за
 * него свидетель на JavaScript: 393 таких вызова у законов и 73 у факт-чекинга.
 * Срез закончен — функции первого класса, постусловия, `к числу` и
 * `к числу или беда` вошли в него, — и запасного пути не осталось ни одного:
 * все 4480 ответов считает сам flang.
 *
 * Поэтому форма вне среза здесь больше НЕ переводит вызов к свидетелю, а
 * становится обычным отказом. Вердикт от такого отказа разойдётся со свидетелем, и
 * сверка покраснеет с кодом в тексте. Тихо досчитать за язык больше нечему.
 */

const файлСлоя = fileURLToPath(new URL("../self/interpret.flang", import.meta.url))

/** Исходник слоя. Наружу — ради порчи: сверка обязана уметь краснеть. */
export const исходникСлоя = readFileSync(файлСлоя, "utf8")

/**
 * Бюджет САМОГО ВЫЧИСЛИТЕЛЯ, а не вычисляемой программы.
 *
 * Один виток машины на flang стоит от полутора до трёх тысяч витков свидетеля
 * (`flang/self/SPEC.md`, «Цена прогона»), поэтому запас взят тот же, что у
 * `self-interpret.test.mjs`. Он стережёт не медленность, а зацикливание: слой,
 * переставший снимать кадры, упрётся в него и будет назван.
 */
const БЮДЖЕТ_СЛОЯ = { maxSteps: 300_000_000, maxDepth: 20_000 }

/**
 * Слой, собранный из данного исходника.
 *
 * Параметром, а не постоянной: доказательство «круг замкнулся» держится на том,
 * что ИСПОРЧЕННЫЙ вычислитель заставляет сверку законов и фактов покраснеть.
 * Собрать испорченный слой можно только здесь.
 */
export async function слойИз(текст = исходникСлоя) {
  const { diagnostics: бедыСвязывания, ...программа } = await linkProgram(файлСлоя, текст, parse)
  /*
   * Отказ связывания — НАХОДКА С ИМЕНЕМ, а не пустой слой.
   *
   * Здесь стояло `diagnostics: _`, и беды связывания уходили в пустоту. Слой от
   * этого не пропадал: `createRuntime` получал программу без функций и молча
   * отдавал вычислитель, который ничего не умеет. Сверка же видела не отказ, а
   * «вызовов вычислителем 0» — и оставалась зелёной на несобранном языке. Тот
   * же разряд ошибки, что и сторож, переставший сторожить: проверка, которая
   * молча не проверяет.
   *
   * Порчи, которыми сверка проверяет себя на покраснение, СМЫСЛОВЫЕ — вычитание
   * становится сложением, число сдвигается на единицу, — и связыванию не мешают.
   * Значит сюда попадёт только настоящая поломка: разъехавшийся `использует`,
   * пропавшее имя, несобранный модуль. Их и надо назвать вслух.
   */
  if (бедыСвязывания.length > 0) {
    const список = бедыСвязывания.map((б) => `${б.code ?? "?"}: ${б.message ?? String(б)}`).join("\n  ")
    throw new Error(`self/interpret.flang не связался — вычислять нечем:\n  ${список}`)
  }
  return createRuntime(программа, БЮДЖЕТ_СЛОЯ)
}

/** Целый слой — тот, на котором идут все сверки, кроме проверок на покраснение. */
export const средаСлоя = await слойИз()

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/*
 * Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
 * форму и порядок ключей и ничего не решает сам.
 *
 * Строится он сразу значениями времени выполнения (`variant` из builtins), а не
 * записями `{ variant, fields }`: `reifyValue` свидетеля возвращает готовый
 * вариант КАК ЕСТЬ, не спускаясь внутрь, — значит программа переводится один
 * раз, а не заново на каждый её вызов.
 */
function скаляр(значение) {
  if (значение === null) return variant("Скаляр ничто", {})
  if (typeof значение === "string") return variant("Скаляр строка", { значение })
  if (typeof значение === "number") return variant("Скаляр число", { значение })
  if (typeof значение === "boolean") return variant("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/** `undefined` пропускается там же, где его пропустил бы `JSON.stringify`. */
export function вЗначение(узел) {
  if (узел === undefined) return variant("Значение скаляра", { скаляр: скаляр(null) })
  if (isVariant(узел)) return вЗначение({ variant: узел.variant, fields: узел.fields })
  if (Array.isArray(узел)) return variant("Значение списка", { элементы: узел.map(вЗначение) })
  if (узел !== null && typeof узел === "object") {
    return variant("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: вЗначение(вложенное) })),
    })
  }
  return variant("Значение скаляра", { скаляр: скаляр(узел) })
}

/**
 * Аргументы вызова — НЕ то же самое, что узел AST, и разница здесь не мелочь.
 *
 * У AST «ключа нет» означает `undefined` свидетеля, поэтому перевод узла ключи с
 * `undefined` выбрасывает. У аргументов правило свидетеля другое: он спрашивает
 * `Object.hasOwn`, и ключ, выставленный в `undefined` руками, для него ЕСТЬ —
 * `reifyValue(undefined)` даёт `ничто`, и функция получает `ничто`, а не отказ
 * «не задан аргумент». Оракул законов выставляет такие ключи нарочно (недостающий
 * аргумент — «пустое место»), поэтому здесь ключи сохраняются все до единого.
 */
export function аргументыВЗначение(аргументы) {
  return variant("Значение записи", {
    поля: Object.keys(аргументы ?? {}).map((ключ) => ({ ключ, значение: вЗначение(аргументы[ключ]) })),
  })
}

/** «Знач» слоя на flang → значение времени выполнения свидетеля. */
export function изЗнач(зн) {
  const вид = зн.variant
  if (вид === "Знач число") return зн.fields["число"]
  if (вид === "Знач строка") return зн.fields["текст"]
  if (вид === "Знач признак") return зн.fields["признак"]
  if (вид === "Знач ничто") return null
  if (вид === "Знач список") return зн.fields["элементы"].map(изЗнач)
  if (вид === "Знач запись") {
    const запись = {}
    for (const поле of зн.fields["поля"]) запись[поле["ключ"]] = изЗнач(поле["значение"])
    return запись
  }
  if (вид === "Знач вариант") {
    const поля = {}
    for (const поле of зн.fields["поля"]) поля[поле["ключ"]] = изЗнач(поле["значение"])
    return variant(зн.fields["имя"], поля)
  }
  throw new Error(`неизвестный вид «Знач»: ${вид}`)
}

/* ─────────────────────────── сам вычислитель ─────────────────────────── */

/**
 * Программа, готовая к прогону вычислителем на flang.
 *
 * Подготовка отложена до первого вызова НАРОЧНО: таблица описаний строится
 * обходом всех объявлений, и на программе, у которой никто ничего не спросит,
 * она стоила бы дороже всей сверки. Сверки законов и монады перебирают весь
 * корпус, а звать кого-то приходится на единицах программ.
 */
export function вычислитель(ast, пределы = {}, среда = средаСлоя) {
  const предел = {
    витков: пределы.maxSteps ?? пределы.steps ?? 1_000_000,
    глубины: пределы.maxDepth ?? пределы.depth ?? 10_000,
  }
  let готовая = null
  return {
    /**
     * Ответ на один вызов. Аргументы приходят записью «имя параметра →
     * значение» — той же, какую получает `среда.call` свидетеля, и ключи
     * сохраняются ВСЕ, включая выставленные в `undefined` (см.
     * `аргументыВЗначение`: у аргументов правило `Object.hasOwn`, а не
     * правило AST).
     *
     * Возврат: `{ значение }`, `{ отказ, код }` либо `{ вне }` — последнее
     * означает форму за границей среза, и только оно даёт право на прежний путь.
     */
    звать(имя, аргументы) {
      if (готовая === null) {
        готовая = среда.call("Подготовить программу", {
          программа: вЗначение(ast),
          "предел витков": предел.витков,
          "предел глубины": предел.глубины,
        })
      }
      const итог = среда.call("Вызвать готовое", {
        готовая,
        имя,
        аргументы: аргументыВЗначение(аргументы),
      })
      if (итог["удалось"]) return { значение: изЗнач(итог["значение"]), витки: итог["витки"] }
      if (итог["код"] === ВНЕ_СРЕЗА) return { вне: итог["сообщение"] }
      return { отказ: итог["сообщение"], код: итог["код"], витки: итог["витки"] }
    },
  }
}
