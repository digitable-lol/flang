/**
 * Факт-чекинг, написанный на самом flang — `flang/self/factcheck.flang`.
 *
 * ── Зачем этот файл появился ────────────────────────────────────────────────
 *
 * Побайтовую сверку со свидетелем имели СЕМЬ слоёв компилятора — лексер,
 * разборщик, типы, тотальность, понижение, печать в C, ведомость. Факт-чекинг
 * не имел никакой, потому что его на flang не было вовсе. А ведь он —
 * ИСХОДНОЕ назначение всей системы (flang/SPEC.md, раздел 1): дать ответ
 * «подтверждено или нет» и не зависнуть, ради чего в языке и заведена
 * доказанная тотальность. Самоприменённый компилятор не умел делать то, ради
 * чего язык создан.
 *
 * ── Что сверяется ───────────────────────────────────────────────────────────
 *
 * Точка входа свидетеля (`flang/src/factcheck.mjs`):
 *
 *   `checkFacts` ← «Проверить факты»
 *
 * Критерий один и он побайтовый: `JSON.stringify` вердикта обязан совпасть знак
 * в знак, вместе с ПОРЯДКОМ КЛЮЧЕЙ. Слабее нельзя: вердикт факт-чекинга уходит
 * в stdout командой `flang facts` и разбирается вызывающей стороной, а `steps`
 * внутри него — след вычисления, по которому читатель судит, ЧТО считалось.
 * Ключ, пропущенный свидетелем (`reason` при удачной тотальности, `code` при
 * отказе без кода), обязан быть пропущен и здесь.
 *
 * ── Единственное, что эталон получает извне, и ЧЕМ ЭТО ПОСЧИТАНО ───────────
 *
 * У свидетеля одна внешняя зависимость — `options.evaluate`, вычислитель, и она у
 * него ПАРАМЕТР, а не спрятанный вызов. У эталона он остаётся параметром по
 * причине, которая сама лежит за границей среза: в flang нет функций первого
 * класса, передать вычислитель функцией нечем. Поэтому у эталона он — список
 * «Ответ вычислителя», таблица.
 *
 * СЧИТАЕТ ЖЕ ЭТУ ТАБЛИЦУ ВЫЧИСЛИТЕЛЬ, НАПИСАННЫЙ НА FLANG, — `self/interpret.flang`
 * через `self-evaluator.mjs`. Раньше её считал свидетель на JavaScript, и
 * факт-чекинг — то, ради чего язык создан, — отвечал «подтверждено или нет»
 * чужим языком. Отсюда проверка в конце файла, которой раньше не могло быть
 * вовсе: сломай вычислитель в одном месте — вердикт обязан разойтись со свидетелем.
 *
 * На свидетеля уходит ровно одно и оно названо числом в улике: вызов функции,
 * которая упирается в ГРАНИЦУ СРЕЗА вычислителя (постусловия, `к числу`,
 * `к числу или беда`). Такой вызов отвечает кодом `FLANG_SELF_EVAL_UNSUPPORTED`,
 * считается свидетелем и записывается — «половина, названная числом» лучше целого,
 * которое молча врёт.
 *
 * Какие вызовы делать, корпус знает сам: он складывает запись аргументов тем же
 * правилом, что и свидетель (`args[параметр] = факт`). Ключом стоит
 * `JSON.stringify` этой записи — значит эталон обязан собрать её с теми же
 * ключами, в том же порядке и с теми же значениями, иначе ответа он не найдёт.
 * Промах не молчит: ненайденный ответ даёт код «FLANG_FACTCHECK_НЕТ_ОТВЕТА»,
 * которого у свидетеля нет, и отдельная проверка требует, чтобы его не было ни в
 * одном вердикте. Код этот и таблица остаются вместе — убрать их можно только
 * вместе с параметром, то есть заведя в языке функции первого класса.
 *
 * Всё остальное эталон решает сам: разбирать ли утверждение, тотальна ли
 * функция, звать ли вычислитель вообще, что написать в «why».
 *
 * ── Корпус: настоящие утверждения, а не выдуманные ──────────────────────────
 *
 * Утверждения собраны из ПРИМЕРОВ, которые авторы написали своим программам и
 * моделям: имя функции — настоящее, факты — настоящий вход примера, число
 * справа — настоящее ожидание автора. Выдуманный набор доказывал бы, что оно
 * работает; этот доказывает, что оно ВОСПРОИЗВОДИТ ОБРАЗЕЦ.
 *
 * Одних подтверждаемых утверждений мало, и это не придирка: согласие только на
 * подтверждённых — согласие ни о чём. Поэтому корпус нарочно содержит все пять
 * исходов свидетеля, и на каждый есть проверка снизу:
 *
 *   verified  подтверждено вычислением;
 *   refuted   ОПРОВЕРГНУТО — тот же оператор при чужом ожидании автора;
 *   refused   отказ: нетотальная функция, непереданный факт, неразобранный
 *             текст, ПРЕДЕЛ ШАГОВ («не досчитали» — это ответ, а не сбой);
 *   error     сравнение порядка на нечисле.
 */
