/* Половина, без которой первая ничего не значит: согласие на подтверждённых —
   согласие ни о чём. Опровергнутое эталоном обязано быть опровергнуто и
   близнецом, и ТЕМ ЖЕ ТЕКСТОМ. */
test("опровергнутое эталоном опровергнуто и близнецом, с тем же текстом", () => {
  const беды = []
  let опровергнутых = 0
  for (const [номер, { случай, вердикт }] of ЭТАЛОН.entries()) {
    const наши = БЛИЗНЕЦ[номер].results
    for (const [место, итог] of вердикт.results.entries()) {
      if (итог.status !== "refuted") continue
      опровергнутых += 1
      const наш = наши[место]
      if (наш === undefined) {
        беды.push(`${случай.имя}: близнец не дал ответа на «${итог.claim}»`)
        continue
      }
      if (наш.holds !== false || наш.status !== "refuted") {
        беды.push(`${случай.имя}: «${итог.claim}» опровергнуто эталоном, а близнец сказал «${наш.status}»`)
        continue
      }
      const беда = расхождение(итог.why, наш.why)
      if (беда !== null) беды.push(`${случай.имя}: объяснение опровержения «${итог.claim}» ${беда}`)
    }
  }
  assert.ok(опровергнутых > 50, `опровергнутых утверждений всего ${опровергнутых}`)
  assert.deepEqual(беды, [], `опровержения разошлись на ${беды.length} утверждениях из ${опровергнутых}`)
})

