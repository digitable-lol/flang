test("сверка фактов краснеет, когда ломается вычислитель на flang", async (t) => {
  /* Шесть случаев, а не все шестьдесят семь: порченый вычислитель пересчитывает
     таблицу целиком, и полный прогон стоил бы полминуты, ничего не добавляя к
     доказательству. Шесть даёт расхождения на всех шести. */
  const пробы = СЛУЧАИ.filter((случай) =>
    ((случай.программа?.functions) ?? []).some((фн) => JSON.stringify(фн.body ?? null).includes('"sub"'))).slice(0, 6)
  assert.equal(пробы.length, 6, "в корпусе не набралось шести программ с вычитанием — порче нечего ломать")

  const целые = пробы.map((случай) => JSON.stringify(вердиктНаш(случай)))
  for (const [номер, случай] of пробы.entries()) {
    const свидетель = JSON.stringify(вердиктСвидетеля(случай))
    assert.equal(расхождение(свидетель, целые[номер]), null, `${случай.имя}: не сходится и на целом вычислителе`)
  }

  const испорчено = исходникСлоя.replace(
    'случай "sub"\n      то «левое» минус «правое»',
    'случай "sub"\n      то «левое» плюс «правое»',
  )
  assert.notEqual(испорчено, исходникСлоя, "порча ничего не заменила — сама порча устарела")

  const целый = слой
  слой = await слойИз(испорчено)
  try {
    const поймано = пробы.filter((случай, номер) => {
      const ответы = посчитатьОтветы(случай)
      return JSON.stringify(вердиктНаш(случай, ответы)) !== целые[номер]
    })
    assert.ok(поймано.length > 0, "испорченный вычислитель прошёл незамеченным на всём корпусе с вычитанием")
    t.diagnostic(`порча «вычитание стало сложением» поймана на ${поймано.length} случаях из ${пробы.length}`)
  } finally {
    слой = целый
  }
})

