/**
 * Сверка множества отказов, посчитанного САМИМ flang, со свидетелем на JavaScript.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Слой конкурентности — единственная подсистема без эталона, которая ввезена в
 * типизатор: `flang/src/types.mjs` берёт имена из `failures.mjs` и `conc.mjs`
 * напрямую, и потому JavaScript про процессы лежит в рабочем пути КАЖДОГО
 * `flang check`, а не только конкурентной программы. Пока эталона нет, свидетель
 * нельзя выбросить в принципе.
 *
 * ── Что сверяется, и что НЕТ ────────────────────────────────────────────────
 * Сверяется ядро: обход тела, места частичных форм, имена вызовов, собственные
 * отказы функции, транзитивное замыкание по графу вызовов и седьмой вид —
 * отказ представителя. Сверка побайтовая: сравниваются не «похоже», а строки
 * записей целиком, вместе с ПОРЯДКОМ — он часть ответа, потому что становится
 * порядком строк диагностики.
 *
 * Из сверки замыкания изъяты РОВНО ДВА вида — «запас витков» и «предел витков
 * планировщика». Оба считаются оценкой витков из `bounded.mjs`, у которого
 * эталона в этом дереве нет вовсе (716 строк свидетеля). Изъятие названо здесь
 * и держится списком `ВНЕ_СРЕЗА`, а не молчанием: расширять его нельзя, сужать
 * можно и нужно — в тот день, когда появится `self/bounded.flang`.
 *
 * ── Изъятие ─────────────────────────────────────────────────────────────────
 * Сверка обязана уметь краснеть, и это проверено порчей эталона, а не
 * обещанием: выброшенная из закрытого списка форма `элемент` даёт 67
 * расхождений, укороченный текст отказа порождения — 1.
 *
 * Третья порча — заставить обход спускаться в `span` — не даёт НИ ОДНОГО
 * расхождения, и это записано как есть: у узлов `span` нет поля `kind`, поэтому
 * пропуск `span` и `meta` у свидетеля стережёт скорость, а не ответ. На этом
 * корпусе. Порча, которую корпус не видит, ничего не доказывает, и называть её
 * доказательством было бы враньём.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { ВИДЫ_ОТКАЗА, достижимыеОтказы, именаВызовов, местЧастичныхФорм, отказыСвязи } from "../src/failures.mjs"
import { checkTotality } from "../src/totality.mjs"
import { вЗначение } from "./self-evaluator.mjs"
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const исходник = readFileSync(корень + "flang/self/failures.flang", "utf8")
const порча = process.env.PORCHA ?? ""

let текст = исходник
/* Порчи выбраны так, чтобы КАЖДАЯ задевала посчитанное число: первая — 238 мест
   частичных форм, вторая — порядок обхода, от которого зависят 1852 имени,
   третья — 11 записей замыкания. Порча, которую корпус не видит, ничего не
   доказывает, и три первые попытки были именно такими. */
if (порча === "форма") текст = текст.replace('(запись «Частичная форма» с «имя» равным "элемент" и «почему» равным "номер может выйти за список"),\n    ', "")
if (порча === "обход") текст = текст.replace('  если «ключ» равен "span"\n    то нет', '  если «ключ» равен "span"\n    то да')
if (порча === "порождение") текст = текст.replace('": имя даёт родитель, и оно может оказаться занятым"', '": имя даёт родитель"')
if (порча !== "" && текст === исходник) {
  console.error(`порча «${порча}» не нашла своего места`)
  process.exit(2)
}

const { diagnostics: беды, ...слой } = await linkProgram(корень + "flang/self/failures.flang", текст, parse)
if (беды.length > 0) {
  console.error("не связался:", беды.map((б) => `${б.code}: ${б.message}`).join("\n"))
  process.exit(1)
}
const среда = createRuntime(слой, { maxSteps: 300_000_000, maxDepth: 20_000 })

/* Корпус: весь, до которого дотягивается разбор. Программы с процессами в нём
   пересчитаны отдельно — на них идёт сверка замыкания. */
const каталоги = ["flang/conc/examples", "flang/examples", "flang/stdlib", "flang/core"]
const пути = каталоги.flatMap((к) => globSync("**/*.flang", { cwd: корень + к + "/" }).sort().map((и) => к + "/" + и))

/* Стережённые мерой: у эталона тотальности нет наружного `guards`, поэтому
   таблица приезжает параметром, и здесь она строится по тем же двум спискам
   анализа завершаемости, по каким её строит свидетель. */
function стережённыеМерой(программа) {
  const итог = []
  const виден = new Set()
  const проверка = checkTotality(программа)
  const добавить = (имя, почему) => {
    if (typeof имя === "string" && !виден.has(имя)) { виден.add(имя); итог.push({ имя, почему }) }
  }
  for (const guard of проверка.guards ?? []) {
    добавить(guard?.from, `доказательство держится на постоянном шаге по «${guard?.param ?? "?"}» в вызове «${guard?.to ?? "?"}», ` +
      "а при большом значении шаг не меняет числа: числа IEEE-754")
  }
  for (const descent of проверка.descents ?? []) {
    добавить(descent?.from, `доказательство держится на объявленной мере «убывает» в вызове «${descent?.to ?? "?"}», ` +
      "а мера обязана убыть, остаться неотрицательной и остаться целой на КАЖДОМ витке")
  }
  return итог
}

/* Виды, которые считает `bounded.mjs`, а эталона у него в этом дереве нет.
   Из сверки замыкания они изъяты — и это единственное изъятие. */
const ВНЕ_СРЕЗА = new Set([ВИДЫ_ОТКАЗА.ЗАПАС, ВИДЫ_ОТКАЗА.ПРЕДЕЛ])
const вСтроку = (отказ) => JSON.stringify({
  вид: отказ.вид,
  почему: отказ.почему,
  где: отказ.где ?? null,
  функция: отказ.функция ?? "",
})
/* Эталон отдаёт `где` документом «Значение» (core/json.flang) — тем же, каким
   ему приезжает AST. Обратный перевод механический и порядок ключей хранит:
   иначе побайтовая сверка сравнивала бы кодировку, а не ответ. */
function изЗначения(зн) {
  const вид = зн?.variant
  if (вид === "Значение списка") return зн.fields["элементы"].map(изЗначения)
  if (вид === "Значение записи") {
    const запись = {}
    for (const поле of зн.fields["поля"]) запись[поле["ключ"]] = изЗначения(поле["значение"])
    return запись
  }
  if (вид === "Значение скаляра") {
    const с = зн.fields["скаляр"]
    if (с.variant === "Скаляр ничто") return null
    return с.fields["значение"]
  }
  throw new Error(`неизвестный вид «Значение»: ${вид}`)
}
const слоемВСтроку = (отказ) => вСтроку({ ...отказ, где: изЗначения(отказ["где"]) })

let программ = 0, сПроцессами = 0, функций = 0, мест = 0, имён = 0, процессов = 0, записей = 0, расхождений = 0
let связей = 0

for (const путь of пути) {
  let программа
  try {
    const { diagnostics: _, ...собрана } = await linkProgram(корень + путь, readFileSync(корень + путь, "utf8"), parse)
    программа = собрана
  } catch { continue }
  программ += 1

  for (const фн of программа.functions ?? []) {
    функций += 1
    const узел = вЗначение(фн)
    const свидетельМест = местЧастичныхФорм(фн)
    мест += свидетельМест
    const слойМест = среда.call("Мест частичных форм", { функция: узел })
    if (свидетельМест !== слойМест) { расхождений += 1; console.log(`РАСХОЖДЕНИЕ мест: ${путь} «${фн.name}»: свидетель ${свидетельМест}, эталон ${слойМест}`) }

    const свидетельИмён = [...именаВызовов(фн)]
    имён += свидетельИмён.length
    const слойИмён = среда.call("Имена вызовов", { функция: узел })
    if (JSON.stringify(свидетельИмён) !== JSON.stringify(слойИмён)) {
      расхождений += 1
      console.log(`РАСХОЖДЕНИЕ имён: ${путь} «${фн.name}»:\n  свидетель ${JSON.stringify(свидетельИмён)}\n  эталон ${JSON.stringify(слойИмён)}`)
    }
  }

  const процессыУзлы = Array.isArray(программа.processes) ? программа.processes : []
  if (процессыУзлы.length === 0) continue
  сПроцессами += 1

  const ящики = среда.call("Объявленные ящики", { процессы: процессыУзлы.map(вЗначение) })
  const стережённые = стережённыеМерой(программа)
  const собственные = среда.call("Собственные отказы", {
    функции: (программа.functions ?? []).map(вЗначение),
    ящики,
    стережённые,
  })

  const свидетельВсе = достижимыеОтказы(программа)
  for (const узел of процессыУзлы) {
    if (typeof узел?.name !== "string") continue
    процессов += 1
    const ожидание = (свидетельВсе.get(узел.name) ?? []).filter((о) => !ВНЕ_СРЕЗА.has(о.вид))
    записей += ожидание.length
    const получено = среда.call("Замыкание отказов", { имя: узел.handler ?? "", собственные })
    const слева = ожидание.map(вСтроку).join("\n")
    const справа = получено.map(слоемВСтроку).join("\n")
    if (слева !== справа) {
      расхождений += 1
      console.log(`РАСХОЖДЕНИЕ замыкания: ${путь}, процесс «${узел.name}»:\n  свидетель:\n${слева}\n  эталон:\n${справа}`)
    }
  }

  /* Седьмой вид: размещение приезжает доводом, и корпус его знает один. */
  const рядом = корень + путь.replace(/\.flang$/, ".json")
  let размещение = null
  try { размещение = JSON.parse(readFileSync(рядом, "utf8")) } catch { размещение = null }
  if (размещение?.узлы === undefined) continue
  const узлыСписок = Object.entries(размещение.узлы).map(([имя, о]) => ({ имя, процессы: Array.isArray(о?.процессы) ? о.процессы : [] }))
  const свидетельСвязь = отказыСвязи(программа, размещение)
  const слойСвязь = среда.call("Отказы связи", { процессы: процессыУзлы.map(вЗначение), узлы: узлыСписок })
  const левоСвязь = [...свидетельСвязь.entries()].map(([п, о]) => `${п}\n${о.map(вСтроку).join("\n")}`).join("\n")
  const правоСвязь = слойСвязь.map((з) => `${з["процесс"]}\n${з["отказы"].map(слоемВСтроку).join("\n")}`).join("\n")
  связей += свидетельСвязь.size
  if (левоСвязь !== правоСвязь) {
    расхождений += 1
    console.log(`РАСХОЖДЕНИЕ связи: ${путь}:\n  свидетель:\n${левоСвязь}\n  эталон:\n${правоСвязь}`)
  }
}

test("множество отказов: эталон на flang сходится со свидетелем побайтово", () => {
  assert.equal(расхождений, 0)
})

console.log(`программ ${программ} (с процессами ${сПроцессами}), функций ${функций}, мест частичных форм ${мест}, имён вызовов ${имён}`)
console.log(`процессов ${процессов}, записей замыкания ${записей}, процессов с представителем ${связей}, расхождений ${расхождений}`)
