const близнецом = (имя, аргументы, чем) => JSON.stringify(изЗначения(чем.call(имя, аргументы)))

function расхождение(эталон, наш) {
  if (эталон === наш) return null
  let знак = 0
  while (знак < эталон.length && знак < наш.length && эталон[знак] === наш[знак]) знак += 1
  const кусок = (текст) => текст.slice(Math.max(0, знак - 60), знак + 160)
  return `разошлось на знаке ${знак}:\n      эталон:  ${кусок(эталон)}\n      близнец: ${кусок(наш)}`
}

/** Сверить весь корпус по обеим таблицам плюс все размещения. */
function сверить(чем = среда, доПервой = false) {
  const беды = []
  const назвать = (что, беда) => {
    беды.push(`${что}: ${беда}`)
    return доПервой
  }
  for (const вход of КОРПУС) {
    const аргументы = доводы(вход)
    for (const [имяТаблицы, эталонной, нашей] of [
      ["достижимые отказы", достижимыеОтказы, "Достижимые отказы"],
      ["отказы начального", отказыНачального, "Отказы начального"],
    ]) {
      const эталон = JSON.stringify(Object.fromEntries(эталонной(вход.ast)))
      let наш
      try { наш = близнецом(нашей, аргументы, чем) } catch (ошибка) { наш = `СОРВАЛОСЬ: ${ошибка?.message}` }
      const беда = расхождение(эталон, наш)
      if (беда !== null && назвать(`${вход.имя} / ${имяТаблицы}`, беда)) return беды
    }
  }
  for (const [имя, размещение] of Object.entries(РАЗМЕЩЕНИЯ)) {
    const эталон = JSON.stringify(Object.fromEntries(отказыСвязи(ДЛЯ_СВЯЗИ, размещение)))
    let наш
    try {
      наш = близнецом("Отказы связи",
        { "программа": вЗначение(ДЛЯ_СВЯЗИ), "размещение": вЗначение(размещение) }, чем)
    } catch (ошибка) { наш = `СОРВАЛОСЬ: ${ошибка?.message}` }
    const беда = расхождение(эталон, наш)
    if (беда !== null && назвать(`размещение — ${имя}`, беда)) return беды
  }
  return беды
}

