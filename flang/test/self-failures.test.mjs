test("три чтения многочлена совпадают с эталоном на всех оценках корпуса", (t) => {
  /* Оценка приезжает доводом, но РЕШЕНИЕ по ней принимается близнецом, и
     зависит оно от трёх чтений: степени, значения при нуле и печати словами.
     Сверяются они на настоящих оценках корпуса, а не на выдуманных. */
  const беды = []
  let оценок = 0
  const виданные = new Set()
  for (const вход of КОРПУС) {
    for (const [, запись] of оценитьВитки(вход.ast)) {
      if (запись.оценка === null) continue
      const ключ = JSON.stringify(запись.оценка)
      if (виданные.has(ключ)) continue
      виданные.add(ключ)
      оценок += 1
      const степень = запись.оценка.reduce((старшая, к, i) => (к !== 0 ? i : старшая), 0)
      const наша = среда.call("Степень многочлена отказа", { "многочлен": запись.оценка })
      if (наша !== степень) беды.push(`степень ${JSON.stringify(запись.оценка)}: ${наша} ≠ ${степень}`)
      const значение = запись.оценка.reduceRight((итог, к) => итог * 0 + к, 0)
      const наше = среда.call("Значение многочлена отказа", { "многочлен": запись.оценка, "н": 0 })
      if (наше !== значение) беды.push(`значение ${JSON.stringify(запись.оценка)}: ${наше} ≠ ${значение}`)
      const текст = текстОценкиЭталона(запись.оценка)
      const наш = среда.call("Текст многочлена отказа", { "многочлен": запись.оценка })
      if (наш !== текст) беды.push(`печать ${JSON.stringify(запись.оценка)}: «${наш}» ≠ «${текст}»`)
    }
  }
  t.diagnostic(`различных оценок ${оценок}, расхождений ${беды.length}`)
  assert.deepEqual(беды.slice(0, 3), [], `расхождений ${беды.length}`)
  assert.ok(оценок >= 100, `различных оценок всего ${оценок} — чтения многочлена почти не сверяются`)
})

/** Печать эталона, повторённая здесь ради сверки самой печати. */
function текстОценкиЭталона(многочлен) {
  const СТЕПЕНИ = ["", "н", "н²", "н³", "н⁴", "н⁵"]
  const части = []
  for (let i = многочлен.length - 1; i >= 0; i -= 1) {
    const коэффициент = многочлен[i]
    if (коэффициент === 0 && i !== 0) continue
    if (i === 0) {
      if (коэффициент !== 0 || части.length === 0) части.push(String(коэффициент))
      continue
    }
    const имя = СТЕПЕНИ[i] ?? `н^${i}`
    части.push(коэффициент === 1 ? имя : `${коэффициент}·${имя}`)
  }
  return части.join(" + ")
}

