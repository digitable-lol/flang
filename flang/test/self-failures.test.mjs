/**
 * Множество отказов процесса: слой на flang против эталона на JavaScript.
 *
 * ── Зачем этот близнец существует ───────────────────────────────────────────
 * `flang/src/failures.mjs` — тот файл, который делает надзор АНАЛИЗОМ, а не
 * только механизмом времени выполнения: множество отказов процесса здесь
 * замкнуто, перечислимо и считается до запуска. Это главное преимущество слоя
 * над OTP, где множество открыто и сводить не с чем. Близнеца у него не было
 * вовсе, а `flang/src/types.mjs` ввозит его строкой 50 — то есть JavaScript про
 * отказы процессов лежит в рабочем пути КАЖДОГО `flang check`, а не только
 * конкурентной программы.
 *
 * ── Что здесь сверяется и почему критерий именно такой ──────────────────────
 * Проверка дифференциальная и побайтовая: на каждой программе корпуса три
 * таблицы близнеца — достижимые отказы, отказы начального состояния и отказы
 * связи — обязаны совпасть с таблицами эталона знак в знак после
 * `JSON.stringify`, вместе с порядком ключей и порядком записей.
 *
 * Слабее нельзя, и довод про этот самый слой. Запись отказа несёт `вид`,
 * `почему`, `где` и `функция`, и каждое из четырёх уезжает в диагностику
 * `FLANG_UNCOVERED_FAILURE`, которую читает автор программы. Одна запись на
 * ВИД, а не на место, и порядок видов постоянен: частичные формы в порядке
 * обнаружения, потом полные ящики, потом три вида порождения, потом остановка,
 * потом мера. Сверка «столько же отказов» не увидела бы ни переставленных
 * записей, ни разошедшегося текста.
 *
 * ── Из чего корпус ──────────────────────────────────────────────────────────
 *   1. ВСЕ программы дерева, какие разбираются. Из них с процессами — десять
 *      (`flang/conc/examples`), и на них девять видов отказа из десяти
 *      встречаются по-настоящему.
 *   2. НАРОЧНО НАПИСАННЫЕ конкурентные программы под каждый вид и под каждую
 *      ветвь анализа. Без них не сверялись бы вовсе: «частичная форма» (в
 *      каталоге примеров её нет ни разу), отказы НАЧАЛЬНОГО состояния (в
 *      каталоге их ноль), замыкание через три перехода, функция, отданная
 *      значением, взаимная рекурсия в достижимом коде и литеральная «норма».
 *   3. ПЯТЬ РАЗМЕЩЕНИЙ для седьмого вида: он считается не по тексту программы,
 *      а по данным узла, и одной программы для него мало.
 *
 * ── Изъятие: сверка обязана уметь краснеть ──────────────────────────────────
 * Ломается кусок в самом близнеце — копия в памяти, файл на диске не трогается.
 */
