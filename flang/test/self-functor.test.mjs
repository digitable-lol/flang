/**
 * Квадрат связи модулей, написанный на самом flang — `flang/self/functor.flang`.
 *
 * СВИДЕТЕЛЬ `flang/src/functor.mjs` СТЁРТ (363 строки), и вместе с ним снято
 * ДЕСЯТЬ проверок этого файла: одна побайтовая сверка на нарочных связях, две
 * на корпусе (разобранном и связанном) и семь порч, которые красили ту сверку.
 * Сравнивать стало не с чем: подставить на место стёртого тот же слой значило
 * бы сравнивать слой сам с собой и зеленеть вечно. Каждая снятая проверка
 * названа в этом файле однострочной записью на своём месте.
 *
 * ЧЕМ ЗАМЕЩЕНО их покрытие, поимённо: побайтовый ответ яруса на всём корпусе
 * держит теперь ЗАПИСЬ ОТВЕТОВ (`flang/test/fixtures/zapis-oracula.json` и
 * `zapis-oracula.test.mjs`) — числа в ней заморожены СВИДЕТЕЛЕМ до удаления, а
 * отвечает на них слой на flang через `src/self.mjs`. Запись слабее свидетеля:
 * она знает только корпус дня съёмки и её можно переснять.
 *
 * Что осталось здесь и чей предмет никуда не делся: сам эталон (разбор, типы,
 * завершаемость, тотальность, примеры), оракул функтора в дереве против оракула
 * в этой проверке — и порчи оракула, потому что второй оракул написан прямо
 * здесь, на JavaScript, и стиранию не подлежал.
 *
 * ── Улика, снятая прогоном ДО этой работы ───────────────────────────────────
 * Эталона не было вовсе. Корпус (231 программа: всё `flang/**` и `examples/**`)
 * задевает этот закон в ДВУХ файлах — `flang/examples/cat/modules/reconciliation.flang`
 * и `flang/examples/cat/natural-square.flang`, — и до сегодняшнего дня на них
 * отвечал только свидетель на JavaScript: 2 проверенных связи (18 и 21 значение,
 * по 3 квадрата, по 10 различных образов) и 2 допущенных. На остальных 229
 * программах ответ пуст, и пустота эта — тоже утверждение: программа без
 * объявленной связи обязана давать три пустых списка, иначе сверка зеленела бы
 * на корпусе, где связей почти нет, не проверяя ничего.
 *
 * ── Почему числа важнее всего остального ────────────────────────────────────
 * Квадрат связи — проверка, которая НЕ ДОКАЗЫВАЕТСЯ: равенство двух путей на
 * всех значениях объекта неразрешимо. Поэтому ведомость (`proof.mjs`) печатает
 * про него «сетка N значений», а не «доказано», и числа N приезжают отсюда — из
 * `checked`/`«проверено»`. Эталон, дающий другое N, не «слегка расходится»: он
 * печатает в ведомости другое утверждение о том же коде. Поэтому сверяется не
 * «нашлось ли нарушение», а вся запись целиком: значения, квадраты, различные
 * образы, пропуски и место обрыва.
 *
 * ── Связывание, а не только разбор ──────────────────────────────────────────
 * И это отличие от `self-laws.test.mjs`, у которого корпус берётся разбором.
 * Связь модулей на то и связь, что живёт МЕЖДУ файлами: `reconciliation.flang`
 * называет стрелки трёх соседних модулей, и без связывания их нет ни у свидетеля,
 * ни у эталона — обе стороны молчали бы одинаково, и сверка была бы зелёной,
 * ничего не сверив. Поэтому здесь два прохода:
 *   • весь корпус РАЗБОРОМ — 231 программа, побайтово;
 *   • программы с объявленной связью СВЯЗЫВАНИЕМ — и список их считается
 *     прогоном, а не пишется руками. Отдельная проверка требует, чтобы
 *     связывание не рождало связей там, где разбор их не видел: иначе список
 *     обмелел бы молча.
 *
 * ── Откуда берётся таблица вызовов, и ЧЕМ она посчитана ─────────────────────
 * Квадрату мало РАЗОБРАТЬ программу — ему надо её ВЫПОЛНИТЬ. Языку flang нечем
 * передать функцию функцией (первого класса у него нет), поэтому вызовы
 * приезжают в эталон данными, и строит эту таблицу здешний оракул.
 *
 * СЧИТАЕТ ЖЕ ЕЁ ВЫЧИСЛИТЕЛЬ, НАПИСАННЫЙ НА FLANG, — `self/interpret.flang` через
 * `self-evaluator.mjs`. Отсюда проверка в конце файла: сломай вычислитель в
 * одном месте — вердикт квадратов обязан разойтись со свидетелем.
 *
 * Оракул НЕ РЕШАЕТ ничего из того, что решает эталон. Он берёт значения,
 * которые автор написал в примерах, БЕЗ ОТБОРА и с заведомо большим пределом,
 * чем предел эталона, — отбор, порядок и предел сетки остаются за эталоном, —
 * и вычисляет замыкание тех вызовов, которые свидетель может сделать: стрелку
 * домена на значении, перевод кодомена на её образе, перевод домена на значении
 * и стрелку кодомена на переводе. Ошибиться так можно ровно в одну сторону:
 * недостающий вызов эталон назовёт вслух («вызова нет в таблице»), и сверка от
 * этого покраснеет, а не позеленеет. Отдельный тест ниже стережёт, что этих слов
 * не появилось ни разу.
 */
