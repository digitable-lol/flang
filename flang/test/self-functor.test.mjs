/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-laws.test.mjs`, и по той же причине: своя копия здесь нужна, иначе тест
   проверял бы себя переводом, который сам же и сверяет. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и эталон их различает. */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/** Диагностика на flang, приведённая к форме эталона (`{code, message, severity, span}`). */
const образцовая = (беда) => ({
  code: беда["код"],
  message: беда["сообщение"],
  severity: беда["важность"],
  span: беда["есть место"] ? { line: беда["строка"], column: беда["столбец"] } : null,
})

/* ─────────────────────────── оракул вызовов ─────────────────────────── */

/**
 * СЧЁТ ОТВЕТОВ: чем посчитан каждый, и не осталось ли уступок.
 *
 * Это улика, а не украшение отчёта: вердикт квадрата держится на ответах
 * вычислений, и «эталоном 0» обязано быть напечатано — иначе «круг замкнут»
 * нечем ни подтвердить, ни опровергнуть.
 */
const счёт = { эталоном: 0, вычислителем: 0, вне: [] }

/**
 * Слой, которым сейчас считаются ответы.
 *
 * Переменная, а не постоянная, ровно ради доказательства изъятием: проверка в
 * конце файла подменяет её ИСПОРЧЕННЫМ вычислителем и требует, чтобы вердикт
 * квадратов разошёлся с эталоном.
 */
let слой = средаСлоя

/**
 * Вызов вычислителя: имя функции и один позиционный аргумент.
 *
 * Тот же путь, каким зовёт `звать` из `src/functor.mjs`: имя первого параметра
 * берётся из `params`, отказ вычисления — не исключение теста, а ответ.
 * ПРЕЖНЕГО ПУТИ К ЭТАЛОНУ НЕТ: форма вне среза записывается и становится
 * отказом, от которого вердикт разойдётся с эталоном.
 */
function позвать(программа, наш, имя, значениеВхода) {
  const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
  if (функция === undefined || (функция.params ?? []).length !== 1) return { нет: true }
  const ответ = наш.звать(имя, { [функция.params[0].name]: значениеВхода })
  if (ответ.вне !== undefined) {
    счёт.вне.push(`${имя}: ${ответ.вне}`)
    return { ошибка: ответ.вне }
  }
  счёт.вычислителем += 1
  return ответ.отказ === undefined ? { значение: ответ.значение } : { ошибка: ответ.отказ }
}

/** Аргумент в форме близнеца. */
const аргументом = (з) => вариантЗначения("Есть аргумент", { значение: значение(з) })

/**
 * Таблица вызовов одной программы.
 *
 * Ключ строит САМ БЛИЗНЕЦ («Ключ вызова»): формат ключа — его дело, и вторая
 * его копия здесь разошлась бы с первой молча.
 */
function таблицаВызовов(программа) {
  const наш = вычислитель(программа, ШАГИ, слой)
  const строки = new Map()
  const записать = (имя, значениеВхода) => {
    const ключ = средаФунктора.call("Ключ вызова", { "имя": имя, "аргументы": [аргументом(значениеВхода)] })
    if (строки.has(ключ)) return строки.get(ключ)
    const итог = позвать(программа, наш, имя, значениеВхода)
    строки.set(ключ, итог)
    return итог
  }
  return { записать, строки }
}

/* Строка таблицы: имени, которого в программе нет, в таблице не место — про
   такое близнец отвечает сам, не заглядывая в неё. */
const строкиТаблицы = (строки) =>
  [...строки]
    .filter(([, итог]) => итог.нет !== true)
    .map(([ключ, итог]) => ({
      "ключ": ключ,
      "ответ":
        итог.ошибка === undefined
          ? вариантЗначения("Вызов дал", { "значение": значение(итог.значение) })
          : вариантЗначения("Вызов отказал", { "сообщение": итог.ошибка }),
    }))

/**
 * Предел числа значений, на которых оракул строит замыкание.
 *
 * Заведомо больше предела сетки близнеца: сетка близнеца — начало этого списка,
 * а таблица обязана быть шире сетки, иначе недостающий вызов был бы виден только
 * как отсутствие.
 */
const ПРЕДЕЛ_ОРАКУЛА = ПРЕДЕЛ_СЕТКИ + 4

/* Повторы отсеиваются по печати значения — механически, а не по правилу
   близнеца: близнец считает повтором большее (запись с теми же ключами в
   другом порядке), поэтому его сетка — подмножество этого списка. */
function безПовторов(значения) {
  const видели = new Set()
  const итог = []
  for (const з of значения) {
    if (з === undefined) continue
    const ключ = JSON.stringify(з)
    if (видели.has(ключ)) continue
    видели.add(ключ)
    итог.push(з)
  }
  return итог.slice(0, ПРЕДЕЛ_ОРАКУЛА)
}

const примерыФункции = (функции, имя) => {
  const функция = функции.find((кандидат) => кандидат.name === имя)
  return Array.isArray(функция?.examples) ? функция.examples : []
}

const законные = (стрелка) => (стрелка?.laws ?? []).flatMap((закон) => закон.examples ?? [])

const годная = (имя) => typeof имя === "string" && имя !== ""

/**
 * Оракул квадратов: замыкание вызовов всех связей программы.
 *
 * Он повторяет ФОРМУ обхода эталона — иначе промежуточные значения композиции
 * взять неоткуда, — но ни одного его решения не принимает: сетка здесь шире
 * (предел на четыре больше), обрыв на нарушении не делается вовсе, а что из
 * набранного считать сеткой и где остановиться, решает близнец.
 */
function оракулФунктора(программа) {
  const узлы = (Array.isArray(программа.legacy) ? программа.legacy : []).filter(
    (узел) => узел?.construct === "functorFile",
  )
  if (узлы.length === 0) return []

  const функции = Array.isArray(программа.functions) ? программа.functions : []
  const стрелки = new Map()
  for (const узел of Array.isArray(программа.morphisms) ? программа.morphisms : []) {
    if (typeof узел?.name === "string") стрелки.set(узел.name, узел)
  }

  const { записать, строки } = таблицаВызовов(программа)

  const применить = (имя, значениеВхода, глубина = 0) => {
    if (глубина > 32) return { ошибка: true }
    const узел = стрелки.get(имя)
    if (узел === undefined) return { нет: true }
    if (узел.identity === true) return { значение: значениеВхода }
    if (узел.kind === "composition") {
      const правая = применить(узел.right, значениеВхода, глубина + 1)
      if (правая.значение === undefined) return правая
      return применить(узел.left, правая.значение, глубина + 1)
    }
    if (!годная(узел.gives)) return { нет: true }
    const итог = записать(узел.gives, значениеВхода)
    return итог.значение === undefined ? { ошибка: true } : { значение: итог.значение }
  }

  const концы = (узел, глубина = 0) => {
    if (глубина > 32) return null
    if (узел?.kind !== "composition") {
      return typeof узел?.domain === "string" && typeof узел?.codomain === "string"
        ? { domain: узел.domain, codomain: узел.codomain }
        : null
    }
    const правая = стрелки.get(узел.right)
    const левая = стрелки.get(узел.left)
    if (правая === undefined || левая === undefined) return null
    const начало = концы(правая, глубина + 1)
    const конец = концы(левая, глубина + 1)
    return начало === null || конец === null ? null : { domain: начало.domain, codomain: конец.codomain }
  }

  const сеткаОбъекта = (объект, перевод) => {
    const собрано = []
    for (const пример of примерыФункции(функции, перевод)) {
      for (const з of Object.values(пример.args ?? {})) собрано.push(з)
    }
    for (const стрелка of стрелки.values()) {
      if (!годная(стрелка.gives)) continue
      const примеры = [...примерыФункции(функции, стрелка.gives), ...законные(стрелка)]
      if (стрелка.domain === объект) {
        for (const пример of примеры) for (const з of Object.values(пример.args ?? {})) собрано.push(з)
      }
      if (стрелка.codomain === объект) for (const пример of примеры) собрано.push(пример.expected)
    }
    return безПовторов(собрано)
  }

  for (const { value: функтор } of узлы) {
    const образОбъекта = new Map()
    for (const пара of функтор.objects ?? []) {
      if (образОбъекта.has(пара.from)) continue
      образОбъекта.set(пара.from, { to: пара.to, gives: пара.gives })
    }
    for (const пара of функтор.morphisms ?? []) {
      const стрелка = стрелки.get(пара.from)
      const образ = стрелки.get(пара.to)
      if (стрелка === undefined || образ === undefined) continue
      const начало = концы(стрелка)
      if (начало === null) continue
      const слева = образОбъекта.get(начало.domain)
      const справа = образОбъекта.get(начало.codomain)
      if (!годная(слева?.gives) || !годная(справа?.gives)) continue
      for (const з of сеткаОбъекта(начало.domain, слева.gives)) {
        const сделал = применить(пара.from, з)
        if (сделал.значение !== undefined) записать(справа.gives, сделал.значение)
        const перевёл = записать(слева.gives, з)
        if (перевёл.значение !== undefined) применить(пара.to, перевёл.значение)
      }
    }
  }
  return строкиТаблицы(строки)
}

/* ─────────────────────────── сверка ─────────────────────────── */

/** Квадраты связей на flang, приведённые к форме эталона. */
function нашиФункторы(программа, переведённая = значение(программа)) {
  const итог = средаФунктора.call("Проверить законы функтора", {
    "программа": переведённая,
    "таблица": оракулФунктора(программа),
  })
  return {
    diagnostics: итог["диагностики"].map(образцовая),
    checked: итог["проверено"].map((сетка) => ({
      functor: сетка["функтор"],
      values: сетка["значений"],
      squares: сетка["квадратов"],
      distinct: сетка["различных"],
      /* Поля уезжают наружу ТОЛЬКО при ненулевом значении — тем же приёмом,
         каким эталон пишет `...(нарушений === 0 ? {} : { violations })`. */
      ...(сетка["нарушений"] === 0 ? {} : { violations: сетка["нарушений"] }),
      ...(сетка["пропущено"] === 0 ? {} : { skipped: сетка["пропущено"] }),
      ...(сетка["оборвано"] === "" ? {} : { aborted: сетка["оборвано"] }),
    })),
    assumed: итог["допущено"].map((пропуск) => ({ functor: пропуск["функтор"], why: пропуск["почему"] })),
  }
}

/**
 * Побайтовое расхождение двух итогов — вместе с ПОРЯДКОМ КЛЮЧЕЙ.
 *
 * Номер знака в ответе обязателен: «не совпало» на записи в две тысячи знаков
 * заставляет искать разницу глазами, а найти её надо за один взгляд.
 */
function расхождение(эталон, наш) {
  const слева = JSON.stringify(эталон)
  const справа = JSON.stringify(наш)
  if (слева === справа) return null
  const знаки = [...слева]
  const место = знаки.findIndex((знак, номер) => знак !== справа[номер])
  const окно = (текст) => текст.slice(Math.max(0, место - 30), место + 70)
  return `разошлось на знаке ${место === -1 ? слева.length : место}:\n    эталон …${окно(слева)}…\n    наш    …${окно(справа)}…`
}

