/* Проверка сверху на саму сверку: список нарочных программ обязан доводить
   эталон до каждого исхода, который он умеет выдавать. Список, из которого
   выпал исход, зеленел бы молча. */
test("нарочные связи покрывают все исходы закона", () => {
  const коды = new Set()
  const причины = new Set()
  const поля = new Set()
  for (const [, исходник] of СВЯЗИ) {
    const итог = checkFunctorSquares(parse(исходник, "проба.flang"))
    for (const беда of итог.diagnostics) коды.add(беда.code)
    for (const пропуск of итог.assumed) причины.add(пропуск.why.split(":")[0])
    for (const сетка of итог.checked) for (const ключ of Object.keys(сетка)) поля.add(ключ)
  }
  assert.deepEqual([...коды], ["FLANG_FUNCTOR_SQUARE"])
  assert.deepEqual([...причины].sort(), [
    "ни у одного объекта нет «даёт»",
    "обход оборван",
    "сетка пуста или у стрелок квадрата нет «даёт»",
  ])
  assert.deepEqual([...поля].sort(), ["aborted", "distinct", "functor", "skipped", "squares", "values", "violations"])
})

/* ────────────────── дифференциальная сверка на корпусе ────────────────── */

/**
 * Весь корпус `.flang` репозитория — и `flang/**`, и `examples/**`. Каждая
 * программа разбирается и судится квадратами; итоги маленькие, а сами программы
 * — нет, поэтому каждая забывается сразу после сверки.
 */
const файлыКорпуса = [
  ...globSync("**/*.flang", { cwd: `${корень}flang`, exclude: (путь) => путь.includes("node_modules") }).map(
    (путь) => `flang/${путь}`,
  ),
  ...globSync("**/*.flang", { cwd: `${корень}examples`, exclude: (путь) => путь.includes("node_modules") }).map(
    (путь) => `examples/${путь}`,
  ),
].sort()

const ПУСТО = JSON.stringify({ diagnostics: [], checked: [], assumed: [] })

const итоги = []
for (const путь of файлыКорпуса) {
  try {
    const программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    const переведённая = значение(программа)
    const эталон = checkFunctorSquares(программа)
    const наш = нашиФункторы(программа, переведённая)
    итоги.push({
      путь,
      квадраты: расхождение(эталон, наш),
      объявлено: (Array.isArray(программа.legacy) ? программа.legacy : []).filter(
        (узел) => узел?.construct === "functorFile",
      ).length,
      записей: эталон.checked.length + эталон.assumed.length + эталон.diagnostics.length,
      пустоуэталона: JSON.stringify(эталон) === ПУСТО,
      пустоунас: JSON.stringify(наш) === ПУСТО,
      тексты: наш.diagnostics.map((беда) => беда.message),
      наших: наш.checked.length + наш.assumed.length + наш.diagnostics.length,
    })
  } catch (ошибка) {
    итоги.push({ путь, отказ: ошибка?.message ?? String(ошибка) })
  }
}

test("каждая программа корпуса разбирается", () => {
  assert.ok(файлыКорпуса.length >= 200, `файлов всего ${файлыКорпуса.length}`)
  for (const итог of итоги) assert.equal(итог.отказ, undefined, `${итог.путь}: ${итог.отказ}`)
})

test("на каждой программе корпуса квадраты у близнеца те же, что у эталона", () => {
  for (const итог of итоги) assert.equal(итог.квадраты, null, `${итог.путь}: ${итог.квадраты}`)
})

/**
 * ПРОВЕРКА, БЕЗ КОТОРОЙ ПРЕДЫДУЩАЯ НИЧЕГО НЕ ЗНАЧИТ.
 *
 * Программа без объявленной связи обязана давать ПУСТОЙ результат у обоих — и
 * это проверено на настоящих программах репозитория, а не на выдуманной
 * пустышке. Без неё сверка зеленела бы на корпусе, где связей почти нет, не
 * проверяя ничего: близнец, всегда возвращающий три пустых списка, прошёл бы
 * проверку выше на всех программах, кроме двух.
 */
test("программа без объявленной связи даёт пустой результат у обоих", () => {
  let безСвязей = 0
  for (const итог of итоги) {
    if (итог.объявлено !== 0) continue
    безСвязей += 1
    assert.ok(итог.пустоуэталона, `${итог.путь}: у эталона результат не пуст`)
    assert.ok(итог.пустоунас, `${итог.путь}: у близнеца результат не пуст`)
  }
  assert.ok(безСвязей >= 200, `программ без связей в корпусе всего ${безСвязей}`)
})

/* И обратная половина той же проверки: программа со связью в корпусе ЕСТЬ, и
   сверка на ней не пустая. */
test("в корпусе есть настоящие программы со связью, и сверка на них не пустая", () => {
  const связные = итоги.filter((итог) => итог.объявлено > 0)
  assert.ok(связные.length >= 2, `программ со связью в корпусе ${связные.length}`)
  for (const итог of связные) {
    assert.ok(итог.записей > 0, `${итог.путь}: эталон не отчитался ни об одной связи`)
    assert.ok(итог.наших > 0, `${итог.путь}: близнец не отчитался ни об одной связи`)
  }
})

/* ───────────── сверка на СВЯЗАННЫХ программах корпуса ───────────── */

/**
 * Связь модулей живёт МЕЖДУ файлами, и без связывания её не видно ни одной из
 * двух сторон: `reconciliation.flang` называет стрелки трёх соседей, а разбор
 * одного файла их не знает. Поэтому программы со связью сверяются ещё раз —
 * связанными, ровно так, как их видит `flang check`.
 *
 * Список считается ПРОГОНОМ: связывается весь корпус, и связи считаются в
 * связанном виде. Если связывание когда-нибудь принесёт связь туда, где разбор
 * её не видел, список вырастет сам, а не останется рукописным.
 */
const связанные = []
for (const путь of файлыКорпуса) {
  const текст = readFileSync(`${корень}${путь}`, "utf8")
  const { diagnostics: _, ...программа } = await linkProgram(`${корень}${путь}`, текст, parse)
  const связей = (Array.isArray(программа.legacy) ? программа.legacy : []).filter(
    (узел) => узел?.construct === "functorFile",
  ).length
  if (связей === 0) continue
  связанные.push({ путь, программа, связей })
}

test("связывание не рождает связей там, где разбор их не видел", () => {
  const поРазбору = итоги.filter((итог) => итог.объявлено > 0).map((итог) => итог.путь)
  assert.deepEqual(
    связанные.map((вход) => вход.путь),
    поРазбору,
  )
})

test("на связанных программах корпуса квадраты у близнеца те же, что у эталона", (t) => {
  assert.ok(связанные.length >= 2, `связанных программ со связью ${связанные.length}`)
  let проверено = 0
  let допущено = 0
  for (const вход of связанные) {
    const эталон = checkFunctorSquares(вход.программа)
    const беда = расхождение(эталон, нашиФункторы(вход.программа))
    assert.equal(беда, null, `${вход.путь}: ${беда}`)
    проверено += эталон.checked.length
    допущено += эталон.assumed.length
  }
  t.diagnostic(`связанных программ со связью ${связанные.length}: проверено ${проверено}, допущено ${допущено}`)
  /* Сторож непустоты: связывание обязано ДАВАТЬ проверенные квадраты, а не
     только допущения. Обмелей оно — здесь станет ноль, и сверка выше зеленела бы
     на пустоте. */
  assert.ok(проверено >= 2, `проверенных связей после связывания ${проверено} — связывание обмелело`)
})

/**
 * Вызова, которого нет в таблице, не случилось ни разу.
 *
 * Это стережёт оракул, а не близнеца: пропусти оракул нужный вызов — и близнец
 * назовёт его вслух, а не промолчит.
 */
test("ни одна сверка не упёрлась в отсутствующий вызов", () => {
  const тексты = итоги.flatMap((итог) => итог.тексты ?? [])
  for (const [, исходник] of СВЯЗИ) {
    тексты.push(...нашиФункторы(parse(исходник, "проба.flang")).diagnostics.map((беда) => беда.message))
  }
  for (const вход of связанные) {
    const наш = нашиФункторы(вход.программа)
    тексты.push(...наш.diagnostics.map((беда) => беда.message))
    тексты.push(...наш.assumed.map((пропуск) => пропуск.why))
    тексты.push(...наш.checked.map((сетка) => сетка.aborted ?? ""))
  }
  assert.deepEqual(тексты.filter((текст) => текст.includes("вызова нет в таблице")), [])
})

/**
 * УЛИКА: чем считаются ответы вычислений, на которых держится вердикт.
 *
 * Цифра слева — сколько ответов посчитал вычислитель flang на flang, цифра
 * справа — сколько досчитал за него эталон на JavaScript. Справа обязан быть
 * ноль, и это утверждение прогона, а не обещание прозы.
 */
test("улика: чем посчитаны ответы вычислений, на которых держится вердикт", (t) => {
  t.diagnostic(`вызовов: вычислителем на flang ${счёт.вычислителем}, эталоном на JavaScript ${счёт.эталоном}`)
  const поВызову = new Map()
  for (const строка of счёт.вне) поВызову.set(строка, (поВызову.get(строка) ?? 0) + 1)
  for (const [строка, сколько] of [...поВызову].sort()) t.diagnostic(`вне среза, ${сколько}: ${строка}`)
  /* СТОРОЖ НЕПУСТОТЫ. Без него «эталоном 0» значило бы и «круг замкнут», и
     «сверка перестала звать кого-либо вовсе» — два противоположных состояния
     одной цифрой. */
  assert.ok(счёт.вычислителем > 40, `вычислитель посчитал ${счёт.вычислителем} вызовов — сверка перестала звать вовсе`)
  assert.deepEqual([...поВызову.keys()], [], "вызов упёрся в границу среза вычислителя")
  assert.equal(счёт.эталоном, 0, "эталон посчитал вызов, хотя запасного пути больше нет")
})

