const теньБлизнецом = (вход, имя, номер, свой = близнец) =>
  изЗначения(evaluate(свой, "Тень программы", { программа: вход.значение, имя, номер }, ШАГИ))

/* ─────────────────── оракул прогонов ─────────────────── */

const счёт = { прогонов: 0, теней: 0, отказовПодготовки: 0, поКоду: 0, поДругому: 0 }

/** Код отказа так, как его достаёт эталон: у ошибки либо у первой диагностики. */
function кодОшибки(беда) {
  if (typeof беда?.code === "string") return беда.code
  const первая = Array.isArray(беда?.diagnostics) ? беда.diagnostics[0] : undefined
  return typeof первая?.code === "string" ? первая.code : ""
}

const причина = (беда) => (беда instanceof Error ? беда.message : String(беда))

const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

/**
 * Таблица прогонов одной программы.
 *
 * Ключи строит САМ БЛИЗНЕЦ («Ключ прогона», «Ключ подготовки»): формат ключа —
 * его дело, и вторая его копия здесь разошлась бы с первой молча.
 *
 * ПРОГОН ИДЁТ ПО ТЕНИ, ПОСТРОЕННОЙ БЛИЗНЕЦОМ. Это не удобство: тень —
 * единственное, что слой делает с программой, и, считай её оракул сам, ошибка
 * близнеца в ней не сказалась бы на сверке с нетронутым эталоном ничем.
 */
function таблицаПрогонов(вход, свой = близнец) {
  const строки = []
  for (const { имя, номер, примеры } of местаПрогонов(вход.программа)) {
    const ключПодготовки = evaluate(свой, "Ключ подготовки", { имя, номер }, ШАГИ)
    let среда
    try {
      среда = createRuntime(теньБлизнецом(вход, имя, номер, свой), {})
      счёт.теней += 1
      строки.push({ "ключ": ключПодготовки, "ответ": вариантЗначения("Прогон дошёл") })
    } catch (беда) {
      счёт.отказовПодготовки += 1
      строки.push({
        "ключ": ключПодготовки,
        "ответ": вариантЗначения("Прогон отказал", { "код": кодОшибки(беда), "почему": причина(беда) }),
      })
      continue
    }
    примеры.forEach((пример, место) => {
      const ключ = evaluate(свой, "Ключ прогона", { имя, номер, пример: место }, ШАГИ)
      счёт.прогонов += 1
      try {
        среда.call(имя, пример?.args ?? {})
        строки.push({ "ключ": ключ, "ответ": вариантЗначения("Прогон дошёл") })
      } catch (беда) {
        const код = кодОшибки(беда)
        if (код === "FLANG_PROPERTY") счёт.поКоду += 1
        else счёт.поДругому += 1
        строки.push({
          "ключ": ключ,
          "ответ": вариантЗначения("Прогон отказал", { "код": код, "почему": причина(беда) }),
        })
      }
    })
  }
  return строки
}

/* ─────────────────── сверка ─────────────────── */

const эталоном = (вход) => checkGrid(вход.программа, вход.обязательства)

const близнецом = (вход, свой = близнец) =>
  изЗначения(evaluate(свой, "Поиск на сетке", {
    программа: вход.значение,
    обязательства: вход.обязательства.map(вЗначение),
    таблица: таблицаПрогонов(вход, свой),
  }, ШАГИ))

/** Полная сверка. Возвращает числа, а не «да/нет»: охват обязан быть перепроверяем. */
function сверить(свой = близнец, входы = корпус) {
  const расхождения = []
  let постусловий = 0
  let нарушений = 0
  let неискали = 0
  for (const вход of входы) {
    const эталон = эталоном(вход)
    постусловий += эталон.checked.length
    for (const з of эталон.checked) { нарушений += з.violations.length; неискали += з.unsearched.length }
    const слева = JSON.stringify(эталон)
    let справа
    try { справа = JSON.stringify(близнецом(вход, свой)) } catch (беда) { справа = `СОРВАЛОСЬ: ${беда?.message}` }
    if (слева !== справа) {
      let и = 0
      while (и < слева.length && и < справа.length && слева[и] === справа[и]) и += 1
      расхождения.push(
        `${вход.имя}: на знаке ${и}\n      эталон:  ${слева.slice(и, и + 130)}\n      близнец: ${справа.slice(и, и + 130)}`,
      )
    }
  }
  return { всего: входы.length, расхождения, постусловий, нарушений, неискали }
}

/**
 * Подкорпус изъятий: НАСТОЯЩИЕ программы дерева, где есть хоть одно
 * обязательство, плюс нарочные.
 *
 * Из него убраны программы самоприменённого слоя в две с половиной тысячи
 * функций — по цене, и цена названа: тень такой программы строится дольше, чем
 * стоит всё изъятие, а сказать об изъятии она может ровно то же, что говорит
 * пятидесятистрочный пример. Побайтовые сверки выше идут по ПОЛНОМУ корпусу, и
 * ослабляет подкорпус не их, а только время десяти порч.
 *
 * ОТБОР ИДЁТ ПО «ХОТЬ ОДНО ОБЯЗАТЕЛЬСТВО», А НЕ ПО «ХОТЬ ОДНО ПОСТУСЛОВИЕ», и
 * это правка по следам красного: пока в подкорпус попадали только программы с
 * постусловиями, изъятие «постусловия перестали отличаться от прочих
 * обязательств» проходило сверку НЕЗАМЕЧЕННЫМ — отличать было не от чего, мер в
 * подкорпусе не оказалось ни одной. Подкорпус, из которого выпал целый вид
 * входа, — это и есть тот самый зеленее-целого обрубок.
 *
 * Настоящие программы в подкорпусе есть, и это условие, а не пожелание: изъятие,
 * краснеющее лишь на рукописной программе, доказывает про перенос меньше, чем
 * обещает. Условие проверяется числом ниже.
 */
const ПОДКОРПУС = корпус.filter(
  (в) => в.обязательства.length > 0 && (в.программа.functions ?? []).length <= 300,
)
const НАСТОЯЩИХ_В_ПОДКОРПУСЕ = ПОДКОРПУС.filter((в) => !в.имя.startsWith("нарочная — ")).length
const МЕР_В_ПОДКОРПУСЕ = ПОДКОРПУС.reduce(
  (сумма, в) => сумма + в.обязательства.filter((о) => о.kind !== "postcondition").length, 0,
)

/**
 * Что видит изъятие: ОБЕ сверки разом, теней и поиска.
 *
 * Порознь их брать нельзя, и это находка, а не удобство. НА НАСТОЯЩЕМ КОРПУСЕ
 * НАРУШЕНИЙ НЕТ НИ ОДНОГО — все 161 непустых сеток отвечают «не нашли», — и
 * потому порча ТЕНИ поиском на настоящей программе не ловится вовсе: постусловия
 * там выполняются, и снятое чужое постусловие ничего не меняет в ответе. Ловится
 * она побайтовой сверкой самих теней, где настоящая программа расходится сразу.
 * Ровно за этим тень и проверяется отдельно, БЕЗ ОРАКУЛА.
 */
function порча(свой) {
  return [...сверитьТени(свой, ПОДКОРПУС).расхождения, ...сверить(свой, ПОДКОРПУС).расхождения]
}

/** Сверка ТЕНЕЙ — без единого прогона. */
function сверитьТени(свой = близнец, входы = корпус) {
  const расхождения = []
  let теней = 0
  let байт = 0
  for (const вход of входы) {
    const первая = new Map()
    for (const функция of вход.программа?.functions ?? []) {
      if (typeof функция?.name === "string" && !первая.has(функция.name)) первая.set(функция.name, функция)
    }
    for (const { имя, номер } of местаПрогонов(вход.программа)) {
      теней += 1
      const функция = первая.get(имя)
      const слева = JSON.stringify(теньВторымМнением(вход.программа, функция, функция.postconditions[номер]))
      байт += слева.length
      let справа
      try { справа = JSON.stringify(теньБлизнецом(вход, имя, номер, свой)) } catch (б) { справа = `СОРВАЛОСЬ: ${б?.message}` }
      if (слева !== справа) {
        let и = 0
        while (и < слева.length && и < справа.length && слева[и] === справа[и]) и += 1
        расхождения.push(
          `${вход.имя} → «${имя}» №${номер}: на знаке ${и}\n      второе мнение: ${слева.slice(и, и + 120)}\n      близнец:       ${справа.slice(и, и + 120)}`,
        )
      }
    }
  }
  return { теней, байт, расхождения }
}

test("ТЕНЬ ПРОГРАММЫ сходится побайтово на всём корпусе — без единого прогона", () => {
  const { теней, байт, расхождения } = сверитьТени()
  console.log(`  тень: программ ${корпус.length}, теней ${теней}, байт ${байт}, расхождений ${расхождения.length}`)
  assert.deepEqual(расхождения.slice(0, 2), [], `расхождений ${расхождения.length} из ${теней}`)
  assert.ok(теней >= 150, `теней всего ${теней} — корпус усох`)
  assert.ok(байт >= 10_000_000, `байт всего ${байт} — тени измельчали, сверять почти нечего`)
})

