/**
 * Механический перебор: каждая функция ПО ПЕРВОМУ ВХОЖДЕНИЮ ИМЕНИ, каждое её
 * постусловие по месту, каждый пример по месту. Отбора здесь нет — какие из этих
 * прогонов ему нужны, решает близнец.
 */
function местаПрогонов(программа) {
  const места = []
  const виденные = new Set()
  for (const функция of программа?.functions ?? []) {
    if (typeof функция?.name !== "string" || виденные.has(функция.name)) continue
    виденные.add(функция.name)
    const постусловия = Array.isArray(функция.postconditions) ? функция.postconditions : []
    const примеры = Array.isArray(функция.examples) ? функция.examples : []
    for (let номер = 0; номер < постусловия.length; номер += 1) места.push({ имя: функция.name, номер, примеры })
  }
  return места
}

/* ─────────────────── тень: второе мнение ─────────────────── */

/**
 * ВТОРОЕ МНЕНИЕ О ТЕНИ — дословная транскрипция `тень()` из `flang/src/grid.mjs`.
 * Эталон её не экспортирует, а трогать эталон ради теста нельзя.
 */
function теньВторымМнением(программа, функция, постусловие) {
  const функции = (программа?.functions ?? []).map((другая) => {
    if (другая === функция) return { ...другая, postconditions: [постусловие] }
    const свои = другая?.postconditions
    return Array.isArray(свои) && свои.length > 0 ? { ...другая, postconditions: [] } : другая
  })
  return { ...программа, functions: функции }
}

