/** Текст одного объявления: от его строки до строки следующего. */
function объявления(текстПрограммы, дерево) {
  const строки = текстПрограммы.split("\n")
  const начала = [...(дерево.types ?? []), ...(дерево.functions ?? []), ...(дерево.processes ?? []), ...(дерево.supervisors ?? []), ...(дерево.runs ?? [])]
    .map((о) => о?.span?.line).filter((л) => typeof л === "number").sort((а, б) => а - б)
  return (строка) => {
    const конец = начала.find((л) => л > строка) ?? строки.length + 1
    return строки.slice(строка - 1, конец - 1).join("\n").replace(/\n+$/u, "") + "\n"
  }
}

/** Объявление процесса, собранное из узла: замена меняет его целиком. */
function объявлениеПроцесса({ имя, состояние, начальное, принимает, обработчик }) {
  return [`процесс «${имя}»`, `  состояние «${состояние}»`, `  начинает с «${начальное}»`, `  принимает «${принимает}»`, `  обрабатывает «${обработчик}»`, ""].join("\n")
}

