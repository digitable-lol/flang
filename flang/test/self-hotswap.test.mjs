/**
 * Горячая замена: слой на flang против эталона на JavaScript.
 *
 * ── Улика ДО, числом ────────────────────────────────────────────────────────
 * В дереве 234 файла `.flang`, процесс объявляют 10. Программ-исходников внутри
 * `flang/test/hotswap.test.mjs` — 19, проверок в нём 24, и на все 19 сегодня
 * отвечает ровно одна сторона: близнецов в `flang/self` 32, и `hotswap.flang`
 * среди них не было. Ввозит `src/hotswap.mjs` ровно один файл — тот самый тест.
 *
 * ── Корпус НАСТОЯЩИЙ, а не нарочный ─────────────────────────────────────────
 * Программы берутся не из этого файла, а ВЫНИМАЮТСЯ из `hotswap.test.mjs`
 * разбором его текста: каждый шаблонный литерал, начинающийся с `модуль «`, —
 * это программа, на которой эталон проверяется сегодня. Написать корпус здесь
 * заново значило бы сверять близнеца с собственным представлением о слое.
 *
 * Сверка идёт СЕТКОЙ: каждый кандидат против каждой работающей программы, а не
 * только против своей. Кандидат, поданный чужой программе, — не выдумка: ровно
 * так получаются отказы «процесса в программе нет», «тип уже объявлен» и «тип
 * сообщений сменить нельзя», которых на своей программе не бывает ни разу.
 * Сетка та же по смыслу, что сетка семян у планировщика (`self-conc.test.mjs`):
 * один вход предъявляет одно решение, а слой обязан совпадать на любом.
 *
 * ── Что сверяется, и двумя утверждениями, а не одним ────────────────────────
 *
 *   • РЕШЕНИЕ СЛОЯ — на всей сетке. Принято или нет, код отказа, текст отказа
 *     знак в знак, имя нового узла. Это то, что решает ИМЕННО этот слой.
 *   • СКВОЗНЫЕ ДИАГНОСТИКИ — весь список целиком, вместе с диагностиками
 *     проверки типов и проверки тотальности, — на паре «кандидат против своей
 *     программы», то есть на той самой паре, на которой кандидат проверяется у
 *     эталона.
 *
 * Второе утверждение вынесено отдельно не для послабления, а потому, что оно
 * ловит ЧУЖОЙ долг, и долг этот здесь измерен (см. проверку «сквозные
 * диагностики упираются в долг соседа»): `self/types.flang` не делает проверок
 * ПРОЦЕССА, которые делает `src/types.mjs`. Все расхождения сетки — до одного
 * недостающие диагностики соседа, а не разошедшееся решение замены. Заметить
 * это раньше было негде: корпус `self-types.test.mjs` — это файлы репозитория,
 * а они годные, и на годной программе проверка процесса молчит у обеих сторон.
 *
 * ── Чего сверка НЕ спрашивает, и это названо числом ─────────────────────────
 * Четвёртое условие замены — оценка витков. `bounded.flang` не ввозится в один
 * модуль с разбором, типами и тотальностью: замыкания их точек входа дают 12
 * столкновений имён, все 12 — с `bounded.flang`, и 11 из 12 — разные
 * определения под одним именем. Близнец, дойдя до витков, ГОВОРИТ об этом
 * признаком «дошло до витков», а сверка такие случаи считает и называет числом.
 * Ловушка тут ровно та, про которую сказано в `flang/conc/SPEC.md`: отсутствие
 * проверки в красном списке значит «не спрашивали», а не «ответил да», —
 * поэтому ниже стоит утверждение о ЧИСЛЕ сверенных, а не только о нуле
 * расхождений.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { ОТКАЗ_ЗАМЕНЫ, заменитьОбработчик } from "../src/hotswap.mjs"
import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const файл = fileURLToPath(new URL("../self/hotswap.flang", import.meta.url))
const исходникБлизнеца = readFileSync(файл, "utf8")

const связано = await linkProgram(файл, исходникБлизнеца, parse)
const { diagnostics: диагностикиСвязывания, ...программаБлизнеца } = связано
const типы = checkTypes(программаБлизнеца)
const тотальность = checkTotality(программаБлизнеца)

/**
 * Предел витков поднят по замеру, а не «чтобы прошло»: близнец замены гоняет
 * внутри себя близнеца разбора, близнеца проверки типов и близнеца анализа
 * завершаемости — три цельнопрограммных прохода на каждую замену.
 */
const ШАГИ = { maxSteps: 400_000_000, maxDepth: 20_000 }
const среда = createRuntime(программаБлизнеца, ШАГИ)
const вызвать = (имя, аргументы) => среда.call(имя, аргументы)

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-totality.test.mjs`, и по той же причине: иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/* ─────────────────── корпус: вынут из теста эталона ─────────────────── */

const тестЭталона = readFileSync(fileURLToPath(new URL("./hotswap.test.mjs", import.meta.url)), "utf8")
const ИСХОДНИКИ = [...тестЭталона.matchAll(/`(модуль «[\s\S]*?)`/gu)].map((м) => м[1])

/* Работающая программа — та, что ОБЪЯВЛЯЕТ процесс; кандидат на замену — та,
   что не объявляет. Разделение сделано разбором, а не номером и не поиском по
   тексту: номер поехал бы от любой правки теста эталона, а «процесс «Имя»»
   пишется и внутри объявления надзора, где это не объявление процесса. */
const разобран = (исходник, номер) => {
  try {
    return parse(исходник, `корпус-${номер}.flang`)
  } catch {
    return null
  }
}
const РАЗОБРАННЫЕ = ИСХОДНИКИ.map(разобран)
const БАЗОВЫЕ = ИСХОДНИКИ.filter((_, н) => (РАЗОБРАННЫЕ[н]?.processes ?? []).length > 0)
const КАНДИДАТЫ = ИСХОДНИКИ.filter((_, н) => (РАЗОБРАННЫЕ[н]?.processes ?? []).length === 0)

const БАЗЫ = БАЗОВЫЕ.map((исходник, номер) => {
  const ast = parse(исходник, `база-${номер}.flang`)
  return { ast, процесс: ast.processes[0].name }
})

/* ─────────────────── сверка ─────────────────── */

/** Решение эталона: то, что решает ИМЕННО этот слой, плюс весь список. */
const эталоном = (база, кандидат) => {
  const итог = заменитьОбработчик(база.ast, база.процесс, кандидат, {})
  const первая = итог.диагностики[0] ?? null
  return {
    решение: {
      принято: итог.принято,
      отказ: первая && { код: первая.code, сообщение: первая.message },
      узел: итог.узел?.name ?? "",
    },
    список: итог.диагностики.map((д) => ({ код: д.code, сообщение: д.message })),
  }
}

/** Решение близнеца, приведённое к тому же виду. */
const близнецом = (зов, база, кандидат) => {
  const итог = зов("Заменить обработчик", {
    "программа": значение(база.ast),
    "процесс": база.процесс,
    "исходник": кандидат,
    "условия": зов("Условия по умолчанию", {}),
  })
  const первая = итог["диагностики"][0] ?? null
  return {
    дошлоДоВитков: итог["дошло до витков"],
    решение: {
      принято: итог["принято"],
      отказ: первая && { код: первая["код"], сообщение: первая["сообщение"] },
      узел: итог["узел"],
    },
    список: итог["диагностики"].map((д) => ({ код: д["код"], сообщение: д["сообщение"] })),
  }
}

const ИСПОЛНЕНИЯ = []
for (const база of БАЗЫ) {
  for (const кандидат of КАНДИДАТЫ) ИСПОЛНЕНИЯ.push({ база, кандидат })
}

const РЕШЕНИЯ = ИСПОЛНЕНИЯ.map(({ база, кандидат }) => ({
  база,
  кандидат,
  эталон: эталоном(база, кандидат),
  наше: близнецом(вызвать, база, кандидат),
}))

const СВЕРЕННЫЕ = РЕШЕНИЯ.filter((р) => !р.наше.дошлоДоВитков)
const ОТЛОЖЕННЫЕ = РЕШЕНИЯ.filter((р) => р.наше.дошлоДоВитков)

/** Своя программа кандидата — первая работающая: с ней он написан в паре. */
const СВОИ = СВЕРЕННЫЕ.filter((р) => р.база === БАЗЫ[0])

const место = ({ база, кандидат }) =>
  `процесс «${база.процесс}», замена «${(кандидат.split("\n")[2] ?? кандидат.split("\n")[0]).trim()}»`

