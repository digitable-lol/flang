/**
 * Отметка меры — тот же шаг, который делает передний край перед КАЖДОЙ командой
 * (`flang/bin/flang.mjs`, `markMeasure`): `run`, `test`, `emit` и `repl`
 * получают помеченную программу, и вычислитель видит именно её. Без этого шага
 * сверка шла по программам, где сторожа меры нет вовсе, — то есть эту часть
 * языка не проверяла совсем.
 *
 * Обёртка с перехватом — дословно как у переднего края: анализ не обязан
 * справляться с любым AST (списки сломанных программ ниже нарочно кривые), а
 * молчаливо ронять сверку он не должен.
 */
const помеченный = (ast) => {
  try {
    return markMeasureGuards(ast)
  } catch {
    return ast
  }
}

const корпус = []
for (const путь of исходники) {
  const { diagnostics: _, ...ast } = await linkProgram(`${корень}${путь}`, readFileSync(`${корень}${путь}`, "utf8"), parse)
  корпус.push({ путь, ast: помеченный(ast) })
}

/** Код, которым слой на flang отвечает на форму, не вошедшую в срез. */
const ВНЕ_СРЕЗА = "FLANG_SELF_EVAL_UNSUPPORTED"

/** Подготовленная программа слоя на flang — аналог `createRuntime` эталона. */
const готовая = (ast, вычислитель = среда, пределы = ПРЕДЕЛЫ) =>
  вычислитель.call("Подготовить программу", {
    программа: значение(ast),
    "предел витков": пределы.maxSteps,
    "предел глубины": пределы.maxDepth,
  })

/**
 * Прогон корпуса. Вынесен функцией, потому что его же зовёт проверка на
 * покраснение — на испорченном вычислителе, но тем же кодом.
 */
function прогнатьКорпус(вычислитель, файлы = корпус, пределы = ПРЕДЕЛЫ) {
  const итог = { сверено: 0, вне: 0, вСрезе: 0, беды: [], пропущеноВСрезе: [] }
  for (const { путь, ast } of файлы) {
    const функции = new Map(ast.functions.map((функция) => [функция.name, функция]))
    /* Подготовка — один раз на программу, по обе стороны: `createRuntime`
       эталона и «Подготовить программу» слоя на flang. */
    const значениеПрограммы = готовая(ast, вычислитель, пределы)
    const эталонная = createRuntime(ast, пределы)
    for (const функция of ast.functions) {
      for (const пример of функция.examples ?? []) {
        const свойства = замыкание(функции, функция.name)
        const годен = вСрезе(свойства)
        if (годен) итог.вСрезе += 1
        const метка = `${путь} :: ${функция.name} / ${пример.name}`
        let ответ
        try {
          ответ = сверитьВСреде(вычислитель, () => эталонная, значениеПрограммы, функция.name, пример.args, пределы)
        } catch (ошибка) {
          итог.беды.push(`${метка}: слой на flang упал — ${ошибка.message}`)
          continue
        }
        if (ответ.вне !== undefined) {
          итог.вне += 1
          if (годен) итог.пропущеноВСрезе.push(`${метка}: ${ответ.вне}`)
          continue
        }
        итог.сверено += 1
        if (ответ.беда !== undefined) итог.беды.push(`${метка}: ${ответ.беда}`)
      }
    }
  }
  return итог
}

/*
 * Эталон приходит ФАБРИКОЙ, а не готовой средой: `createRuntime` сам отвергает
 * программу без тела функции и с именем, объявленным дважды, — то есть часть
 * отказов случается ещё до вызова. Готовая среда такие отказы просто не дала бы
 * поймать: исключение вылетело бы мимо сверки, и она бы упала, а не сверила.
 */
function сверитьВСреде(вычислитель, эталонФабрика, значениеПрограммы, имя, аргументы, пределы = ПРЕДЕЛЫ) {
  const отчёт = {}
  let ждём = null
  let отказЭталона = null
  try {
    ждём = эталонФабрика().call(имя, аргументы, { отчёт, ...пределы })
  } catch (ошибка) {
    отказЭталона = [ошибка.code ?? "?", String(ошибка.message)]
  }
  const виткиЭталона = отчёт.витки ?? 0

  const наш = вычислитель.call("Вызвать готовое", {
    готовая: значениеПрограммы,
    имя,
    аргументы: значение(аргументы ?? {}),
  })
  if (!наш["удалось"] && наш["код"] === ВНЕ_СРЕЗА) return { вне: наш["сообщение"] }

  if (отказЭталона !== null) {
    if (наш["удалось"]) {
      return { беда: `эталон отказал (${отказЭталона[0]}: ${отказЭталона[1]}), слой на flang дал значение` }
    }
    const есть = [наш["код"], наш["сообщение"]]
    if (JSON.stringify(есть) !== JSON.stringify(отказЭталона)) {
      return { беда: `отказ ${JSON.stringify(есть)} ≠ ${JSON.stringify(отказЭталона)}` }
    }
    return виткиЭталона === наш["витки"] ? {} : { беда: `витки ${наш["витки"]} ≠ ${виткиЭталона} (на отказе)` }
  }
  if (!наш["удалось"]) {
    return { беда: `слой на flang отказал там, где эталон посчитал: ${наш["код"]}: ${наш["сообщение"]}` }
  }
  const получено = изЗнач(наш["значение"])
  if (печать(получено) !== печать(ждём)) return { беда: `значение ${печать(получено)} ≠ ${печать(ждём)}` }
  if (!valuesEqual(получено, ждём)) {
    return { беда: `значения печатаются одинаково, но не равны по «Object.is»: ${печать(получено)}` }
  }
  if (виткиЭталона !== наш["витки"]) return { беда: `витки ${наш["витки"]} ≠ ${виткиЭталона}` }
  return {}
}

