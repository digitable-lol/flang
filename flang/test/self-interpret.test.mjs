/* ───────────────────────── сверка умеет краснеть ───────────────────────── */

/**
 * Проверка проверки. Каждая порча снимает или подменяет ОДНУ операцию
 * вычислителя, и сверка обязана поймать каждую.
 *
 * У порчи две мишени, и обе нужны. ПРОБА — крошечная программа, написанная
 * ровно под эту операцию: она называет, что именно сломано, и краснеет за
 * миллисекунды. КОРОТКИЙ КОРПУС — настоящие программы репозитория: он
 * показывает, что порча видна не только на нарочно подобранном входе.
 *
 * По корпусу гоняется одна порча, а не все пять, и это решение по стоимости:
 * испорченное вычитание превращает всякий счётчик, идущий вниз, в счётчик,
 * идущий вверх, — и каждый такой пример добирает до предела витков вместо того,
 * чтобы кончиться. Пять таких прогонов стоили две с половиной минуты и не
 * добавляли к доказательству ничего сверх первого.
 */
const порчи = [
  {
    имя: "вычитание стало сложением",
    испортить: (текст) => текст.replace('случай "sub"\n      то «левое» минус «правое»', 'случай "sub"\n      то «левое» плюс «правое»'),
    проба: [`модуль «М»
тотальная функция «Ф»
  принимает «а»: число, «б»: число
  возвращает число
  «а» минус «б»`, "Ф", { а: 5, б: 3 }],
    покорпусу: true,
  },
  {
    имя: "хвостовой вызов перестал переиспользовать кадр",
    испортить: (текст) => текст.replace("      то «Кадр возврата без постусловий» от «кадр»", "      то нет"),
    /* Значение то же, витки другие: кадр возврата, который хвостовой вызов
       обязан был забрать себе, остаётся на стеке и снимается лишним витком.
       Эту порчу ловит ТОЛЬКО счётчик витков — и ради этого он и заведён. */
    проба: [`модуль «М»
тотальная функция «Считать»
  принимает «н»: число, «акк»: число
  возвращает число
  если «н» не больше 0
    то «акк»
    иначе «Считать» от («н» минус 1) и («акк» плюс «н»)`, "Считать", { н: 20, акк: 0 }],
  },
  {
    имя: "виток перестал считаться",
    испортить: (текст) => текст.replace(
      "«Дальше после шага» от «п» и («Шаг» от «п» и («С работой» от «м» и «дальше» и ((«м».«витки») плюс 1)) и «кадр»)",
      "«Дальше после шага» от «п» и («Шаг» от «п» и («С работой» от «м» и «дальше» и («м».«витки»)) и «кадр»)",
    ),
    проба: [`модуль «М»
тотальная функция «Ф»
  принимает «а»: число
  возвращает число
  «а» плюс 1`, "Ф", { а: 1 }],
  },
  {
    имя: "равенство перестало различать минус ноль",
    испортить: (текст) => текст.replace(
      "      то «число» равен «другое»",
      "      то («число» плюс 0) равен («другое» плюс 0)",
    ),
    проба: [`модуль «М»
тотальная функция «Ф»
  принимает «а»: число, «б»: число
  возвращает признак
  «а» равен «б»`, "Ф", { а: -0, б: 0 }],
  },
  {
    имя: "порядок ключей записи перевернулся",
    испортить: (текст) => текст.replace(
      "  «Сложить поля в конец» от «ключи» и «значения» и пустой список",
      "  «Сложить поля наоборот» от «ключи» и «значения»",
    ) + `

тотальная функция «Сложить поля наоборот»
  принимает «ключи»: список строки, «значения»: список «Знач»
  возвращает список «Поле знач»
  разбор «ключи»
    случай пусто
      то пустой список
    случай голова «первый» и хвост «прочие»
      то добавить (запись «Поле знач» с «ключ» равным «первый» и «значение» равным («Первое значение» от «значения»)) к («Сложить поля наоборот» от «прочие» и («Прочие значения» от «значения»))
`,
    проба: [`модуль «М»
объект «Р»
  «а»: число
  «б»: число
тотальная функция «Ф»
  возвращает «Р»
  запись «Р» с «а» равным 1 и «б» равным 2`, "Ф", {}],
  },
]

/* Три модуля библиотеки, а не все одиннадцать: испорченное вычитание уводит
   всякий счётчик, идущий вниз, в предел витков, и каждый такой пример стоит
   секунд. Трёх хватает — расхождений они дают десятки. */
const короткийКорпус = корпус.filter(({ путь }) =>
  ["flang/stdlib/lists.flang", "flang/stdlib/numbers.flang", "flang/stdlib/optional.flang"].includes(путь))

test("сверка умеет краснеть: каждая порча вычислителя ловится на пробе", async (t) => {
  for (const { имя, испортить, проба } of порчи) {
    const испорчено = испортить(исходник)
    assert.notEqual(испорчено, исходник, `порча «${имя}» ничего не заменила — сама порча устарела`)
    const { diagnostics: _, ...порченая } = await linkProgram(файл, испорчено, parse)
    const порченаяСреда = createRuntime(порченая, ШАГИ)

    const [текст, функция, аргументы] = проба
    const ast = parse(текст, "проба.flang")
    const фабрика = () => createRuntime(ast, ПРЕДЕЛЫ)
    /* Сначала — что на ЦЕЛОМ вычислителе проба сходится. Без этого «поймано»
       ничего не значило бы: проба могла бы краснеть сама по себе. */
    const целая = сверитьВСреде(среда, фабрика, готовая(ast), функция, аргументы)
    assert.equal(целая.беда, undefined, `«${имя}»: проба не сходится и на целом вычислителе — ${целая.беда}`)
    assert.equal(целая.вне, undefined, `«${имя}»: проба вне среза`)

    const порченый = сверитьВСреде(порченаяСреда, фабрика, готовая(ast, порченаяСреда), функция, аргументы)
    assert.ok(порченый.беда !== undefined, `порча «${имя}» прошла незамеченной на своей пробе`)
    t.diagnostic(`«${имя}»: ${порченый.беда}`)
  }
})

/*
 * Предел витков вычисляемой программы здесь свой и маленький — пять тысяч
 * вместо миллиона, — и просят его ОБЕ стороны, поэтому сверка остаётся сверкой.
 * Причина в том, что порча делает: испорченное вычитание уводит счётчик, идущий
 * вниз, в бесконечность, и каждый такой пример добирает до предела вместо того,
 * чтобы кончиться. С миллионом это две минуты, с пятью тысячами — секунды, а
 * ловится ровно то же самое: примеры, укладывающиеся в пять тысяч витков (а их
 * подавляющее большинство), сверяются как обычно; вышедшие за предел упираются
 * в него у обеих сторон одинаково и расхождения не дают.
 */
const ПРЕДЕЛЫ_ПОРЧИ = { maxSteps: 5_000, maxDepth: 500 }

test("сверка умеет краснеть: порча видна и на настоящих программах репозитория", async (t) => {
  const { имя, испортить } = порчи.find((порча) => порча.покорпусу === true)
  const { diagnostics: _, ...порченая } = await linkProgram(файл, испортить(исходник), parse)
  const целый = прогнатьКорпус(среда, короткийКорпус, ПРЕДЕЛЫ_ПОРЧИ)
  assert.deepEqual(целый.беды.slice(0, 5), [], "на целом вычислителе с этими же пределами расхождений быть не должно")
  const итог = прогнатьКорпус(createRuntime(порченая, ШАГИ), короткийКорпус, ПРЕДЕЛЫ_ПОРЧИ)
  assert.ok(итог.беды.length > 0, `порча «${имя}» прошла незамеченной: сверено ${итог.сверено}, расхождений 0`)
  t.diagnostic(`«${имя}»: поймано на ${итог.беды.length} примерах из ${итог.сверено + итог.беды.length}`)
})

test("на целом вычислителе тот же короткий корпус расхождений не даёт", () => {
  const итог = прогнатьКорпус(среда, короткийКорпус)
  assert.deepEqual(итог.беды.slice(0, 5), [])
  assert.ok(итог.сверено > 0, "короткий корпус пуст — порчи не на чем ловить")
})
