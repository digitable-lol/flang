/**
 * Вычислитель flang, написанный на самом flang — `flang/self/interpret.flang`.
 *
 * Проверка здесь одна и она дифференциальная, но у неё ДВА измерителя, и это
 * главное отличие от прочих слоёв самоприменения.
 *
 * ПЕРВЫЙ — значение. Для каждого примера корпуса значение, посчитанное слоем на
 * flang, обязано совпасть со значением эталонного `flang/src/interpret.mjs`.
 * Совпадение проверяется дважды разными мерками: печатью в JSON (она ловит
 * порядок ключей записи и форму варианта) и `valuesEqual` эталона (она ловит
 * минус ноль, который печать теряет: `JSON.stringify(-0)` даёт «0»).
 *
 * ВТОРОЙ — витки. Число витков машины обязано совпасть ЧИСЛО В ЧИСЛО. Это не
 * добавка к первому измерителю, а более чувствительный измеритель: программа с
 * переставленным порядком вычисления аргументов, с невыполненным хвостовым
 * вызовом или с лишним кадром даёт ТО ЖЕ значение и ДРУГОЕ число витков.
 * Первая же ошибка, которую поймала эта сверка, была именно такой: запись из
 * двух полей собиралась в обратном порядке ключей, а число витков совпадало.
 *
 * ЧЕГО СВЕРКА НЕ ДЕЛАЕТ МОЛЧА. Срез вычислителя покрывает не весь язык:
 * функций первого класса, постусловий и «к числу» в нём нет. Пропустить такой
 * пример молча значило бы посчитать пропущенное сошедшимся, поэтому слой на
 * flang отвечает на них особым кодом, а тест считает такие ответы отдельно и
 * требует, чтобы КАЖДЫЙ пример, который по статическому разбору укладывается в
 * срез, был именно СВЕРЕН, а не пропущен.
 *
 * И проверка самой проверки: последний блок портит одну операцию вычислителя и
 * требует, чтобы сверка покраснела. Сверка, которая не умеет краснеть, хуже
 * отсутствующей.
 */
