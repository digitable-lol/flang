/* ─────────────────── перевод AST в значения flang ─────────────────── */

/*
 * Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
 * форму и порядок ключей и ничего не решает сам.
 *
 * Строится он сразу значениями времени выполнения (`variant` из builtins), а не
 * записями `{ variant, fields }`, и это не украшение: `reifyValue` эталона
 * возвращает готовый вариант КАК ЕСТЬ, не спускаясь внутрь, — значит программа
 * переводится один раз на файл, а не заново на каждый её пример. С записями
 * перевод AST `self/parser.flang` пересобирался бы сотню раз.
 */
function скаляр(значение) {
  if (значение === null) return variant("Скаляр ничто", {})
  if (typeof значение === "string") return variant("Скаляр строка", { значение })
  if (typeof значение === "number") return variant("Скаляр число", { значение })
  if (typeof значение === "boolean") return variant("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и эталон их различает. */
function значение(узел) {
  if (узел === undefined) return variant("Значение скаляра", { скаляр: скаляр(null) })
  if (isVariant(узел)) {
    return значение({ variant: узел.variant, fields: узел.fields })
  }
  if (Array.isArray(узел)) return variant("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return variant("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return variant("Значение скаляра", { скаляр: скаляр(узел) })
}

/** «Знач» слоя на flang → значение времени выполнения эталона. */
function изЗнач(зн) {
  const вид = зн.variant
  if (вид === "Знач число") return зн.fields["число"]
  if (вид === "Знач строка") return зн.fields["текст"]
  if (вид === "Знач признак") return зн.fields["признак"]
  if (вид === "Знач ничто") return null
  if (вид === "Знач список") return зн.fields["элементы"].map(изЗнач)
  if (вид === "Знач запись") {
    const запись = {}
    for (const поле of зн.fields["поля"]) запись[поле["ключ"]] = изЗнач(поле["значение"])
    return запись
  }
  if (вид === "Знач вариант") {
    const поля = {}
    for (const поле of зн.fields["поля"]) поля[поле["ключ"]] = изЗнач(поле["значение"])
    return variant(зн.fields["имя"], поля)
  }
  throw new Error(`неизвестный вид «Знач»: ${вид}`)
}

/** Печать значения, различающая вариант и запись с теми же полями. */
const печать = (что) =>
  JSON.stringify(что, (ключ, значение) =>
    isVariant(значение) ? { "«вариант»": значение.variant, поля: значение.fields } : значение)

/* ──────────────── что укладывается в срез: статический разбор ──────────── */

const ВИДЫ_СРЕЗА = new Set([
  "literal", "var", "field", "let", "if", "match", "call", "binary",
  "list", "record", "construct", "builtin", "fold", "map", "filter",
  "fnref", "apply",
])
const ФОРМЫ_ВНЕ_СРЕЗА = new Set(["к числу", "к числу или беда", "к_числу", "к_числу_или_беда"])

function обход(узел, посетить) {
  if (узел === null || typeof узел !== "object") return
  if (Array.isArray(узел)) {
    for (const элемент of узел) обход(элемент, посетить)
    return
  }
  посетить(узел)
  for (const ключ of Object.keys(узел)) обход(узел[ключ], посетить)
}

/**
 * Виды выражений, формы и постусловия, достижимые из функции по графу вызовов.
 * Оценка ВЕРХНЯЯ: она считает достижимым всё, до чего ведёт вызов, даже если
 * на конкретном входе туда не заходят. Это ровно то, что нужно: пример,
 * попавший в срез по такой оценке, обязан быть сверен, а не пропущен.
 */
function замыкание(функции, имя) {
  const виды = new Set()
  const формы = new Set()
  let постусловия = false
  const видели = new Set()
  const очередь = [имя]
  while (очередь.length > 0) {
    const текущее = очередь.pop()
    if (видели.has(текущее)) continue
    видели.add(текущее)
    const функция = функции.get(текущее)
    if (функция === undefined) continue
    if ((функция.postconditions ?? []).length > 0) постусловия = true
    обход(функция.body, (узел) => {
      if (typeof узел.kind === "string") виды.add(узел.kind)
      if ((узел.kind === "call" || узел.kind === "fnref") && typeof узел.name === "string") очередь.push(узел.name)
      if (узел.kind === "builtin" && typeof узел.name === "string") формы.add(узел.name)
    })
  }
  return { виды, формы, постусловия }
}

const вСрезе = (свойства) =>
  !свойства.постусловия
  && [...свойства.виды].every((вид) => ВИДЫ_СРЕЗА.has(вид))
  && [...свойства.формы].every((форма) => !ФОРМЫ_ВНЕ_СРЕЗА.has(форма))

