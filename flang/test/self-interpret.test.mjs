/*
 * Предел витков вычисляемой программы здесь свой и маленький — пять тысяч
 * вместо миллиона, — и просят его ОБЕ стороны, поэтому сверка остаётся сверкой.
 * Причина в том, что порча делает: испорченное вычитание уводит счётчик, идущий
 * вниз, в бесконечность, и каждый такой пример добирает до предела вместо того,
 * чтобы кончиться. С миллионом это две минуты, с пятью тысячами — секунды, а
 * ловится ровно то же самое: примеры, укладывающиеся в пять тысяч витков (а их
 * подавляющее большинство), сверяются как обычно; вышедшие за предел упираются
 * в него у обеих сторон одинаково и расхождения не дают.
 */
const ПРЕДЕЛЫ_ПОРЧИ = { maxSteps: 5_000, maxDepth: 500 }

test("сверка умеет краснеть: порча видна и на настоящих программах репозитория", async (t) => {
  const { имя, испортить } = порчи.find((порча) => порча.покорпусу === true)
  const { diagnostics: _, ...порченая } = await linkProgram(файл, испортить(исходник), parse)
  const целый = прогнатьКорпус(среда, короткийКорпус, ПРЕДЕЛЫ_ПОРЧИ)
  assert.deepEqual(целый.беды.slice(0, 5), [], "на целом вычислителе с этими же пределами расхождений быть не должно")
  const итог = прогнатьКорпус(createRuntime(порченая, ШАГИ), короткийКорпус, ПРЕДЕЛЫ_ПОРЧИ)
  assert.ok(итог.беды.length > 0, `порча «${имя}» прошла незамеченной: сверено ${итог.сверено}, расхождений 0`)
  t.diagnostic(`«${имя}»: поймано на ${итог.беды.length} примерах из ${итог.сверено + итог.беды.length}`)
})

test("на целом вычислителе тот же короткий корпус расхождений не даёт", () => {
  const итог = прогнатьКорпус(среда, короткийКорпус)
  assert.deepEqual(итог.беды.slice(0, 5), [])
  assert.ok(итог.сверено > 0, "короткий корпус пуст — порчи не на чем ловить")
})
