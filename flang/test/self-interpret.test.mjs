test("корпус разбирается без отметок меры: обе стороны считают ОДНУ программу", () => {
  /* Сторож меры (`defunc.mjs`) переписывает тела функций с объявленной мерой.
     Эталон зовёт его в `prepareProgram`, а слой на flang — нет: понижение
     живёт отдельным слоем (`self/defunc.flang`). Пока анализ завершаемости не
     позван, отметок в AST нет и переписывать нечего, — но проверить это надо
     здесь, а не поверить: разойдись программы, и сверка сравнивала бы разное. */
  for (const { путь, ast } of корпус) {
    assert.equal(guardDescent(ast), ast, `${путь}: понижение изменило программу — сверка сравнивала бы разное`)
  }
})

