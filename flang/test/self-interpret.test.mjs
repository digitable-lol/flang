test("interpret.flang: нетотальность объявлена ровно там, где вычисление вправе не кончиться", (t) => {
  const обычные = свой.functions.filter((функция) => функция.total !== true).map((функция) => функция.name)
  /* Цикл машины — то самое место, где незавершение законно. Он ОБЯЗАН быть
     обычным: объяви его тотальным — и обещание языка стало бы неправдой на
     первой же зациклившейся программе. */
  assert.ok(обычные.includes("Прогон"), "«Прогон» обязан быть обычной функцией: чужая программа может не кончиться")
  assert.ok(обычные.includes("Овеществить"), "спуск по AST вглубь обычен — тот же долг, что у types.flang")
  const тотальных = свой.functions.filter((функция) => функция.total === true).length
  t.diagnostic(`своих функций ${свой.functions.length}: тотальных ${тотальных}, обычных ${обычные.length}`)
  assert.ok(тотальных > обычные.length * 2, `тотальных ${тотальных} против обычных ${обычные.length} — доля упала`)
})

