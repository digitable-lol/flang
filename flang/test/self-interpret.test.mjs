test("interpret.flang: нетотальность объявлена ровно там, где вычисление вправе не кончиться", (t) => {
  const обычные = свой.functions.filter((функция) => функция.total !== true).map((функция) => функция.name)
  /* Цикл машины — то самое место, где незавершение законно. Он ОБЯЗАН быть
     обычным: объяви его тотальным — и обещание языка стало бы неправдой на
     первой же зациклившейся программе. */
  assert.ok(обычные.includes("Прогон"), "«Прогон» обязан быть обычной функцией: чужая программа может не кончиться")
  assert.ok(обычные.includes("Овеществить"), "спуск по AST вглубь обычен — тот же долг, что у types.flang")
  const тотальных = свой.functions.filter((функция) => функция.total === true).length
  t.diagnostic(`своих функций ${свой.functions.length}: тотальных ${тотальных}, обычных ${обычные.length}`)
  assert.ok(тотальных > обычные.length * 2, `тотальных ${тотальных} против обычных ${обычные.length} — доля упала`)
})

test("interpret.flang: навигация по AST приезжает связыванием, а не копированием", () => {
  const свои = new Set(свой.functions.map((функция) => функция.name))
  for (const имя of ["Взять поле", "Элементы узла", "Вид узла", "Печать значения"]) {
    assert.ok(!свои.has(имя), `«${имя}» объявлена здесь, а должна приходить импортом`)
    assert.ok(программа.functions.some((функция) => функция.name === имя), `«${имя}» не приехала связыванием`)
  }
})

test("interpret.flang: примеры всех функций сходятся", (t) => {
  let счёт = 0
  for (const функция of программа.functions) {
    for (const пример of функция.examples ?? []) {
      счёт += 1
      const получено = evaluate(программа, функция.name, пример.args, ШАГИ)
      /* `deepEqual` здесь не годится: ожидание примера приезжает из AST записью
         `{ variant, fields }`, а вычислитель отдаёт класс варианта. Сравнивает
         `valuesEqual` эталона — та же мерка, которой сверяются значения ниже. */
      assert.ok(
        valuesEqual(получено, reifyValue(пример.expected)),
        `«${функция.name}» / «${пример.name}»: ${печать(получено)} ≠ ${печать(reifyValue(пример.expected))}`,
      )
    }
  }
  t.diagnostic(`примеров ${счёт}`)
  assert.ok(счёт >= 30, `примеров всего ${счёт}`)
})

