    const фабрика = () => createRuntime(ast, пределы)
    let упало = false
    try {
      фабрика().call(функция, аргументы, пределы)
    } catch {
      упало = true
    }
    assert.ok(упало, `«${имя}»: эталон не отказал — программа не сломана`)
