/**
 * «к числу»: последний бит, а не «примерно то же число».
 *
 * Форма отдана рантайму — слой на flang зовёт `к числу или беда` самого flang
 * (обоснование в шапке `self/interpret.flang`). Значит проверять надо не то,
 * что разбор написан, а то, что он ТОТ ЖЕ: строки ниже подобраны так, что
 * всякая самодельная копия на них разошлась бы.
 *
 *   " 42 "               — обрезка пробелов (у эталона `trim`);
 *   "-0"                 — минус ноль, который печать теряет, а `Object.is` нет;
 *   "0.1"                — округление десятичной дроби в binary64;
 *   "9007199254740993"   — нечётное целое за 2⁵³: правильный ответ
 *                          9007199254740992, а не то, что дала бы наивная
 *                          свёртка цифр умножением на десять;
 *   "1e-7", "1E+3"       — показатель обоими регистрами.
 */
test("«к числу» разбирает те же строки в те же биты", () => {
  const текст = `модуль «М»
функция «Число из строки»
  принимает «т»: строка
  возвращает число
  к числу «т»
функция «Исход строки»
  принимает «т»: строка
  возвращает «Исход числа»
  к числу или беда «т»`
  const ast = помеченный(parse(текст, "кчислу.flang"))
  const значениеПрограммы = готовая(ast)
  for (const текстЧисла of [" 42 ", "-0", "0.1", "9007199254740993", "1e-7", "1E+3", "+5", ".5", "1.5e300"]) {
    const ответ = сверитьВСреде(среда, () => createRuntime(ast, ПРЕДЕЛЫ), значениеПрограммы, "Число из строки", { т: текстЧисла })
    assert.equal(ответ.вне, undefined, `«${текстЧисла}»: слой на flang назвал это вне среза`)
    assert.equal(ответ.беда, undefined, `«${текстЧисла}»: ${ответ.беда}`)
  }
  /* Отказ, ставший значением: и код, и текст едут внутри варианта, значит
     сверяются как обычное значение — печатью и `valuesEqual`. */
  for (const текстЧисла of ["42", "мусор", "1e999", "", "0x1f", "Infinity"]) {
    const ответ = сверитьВСреде(среда, () => createRuntime(ast, ПРЕДЕЛЫ), значениеПрограммы, "Исход строки", { т: текстЧисла })
    assert.equal(ответ.вне, undefined, `«${текстЧисла}»: слой на flang назвал это вне среза`)
    assert.equal(ответ.беда, undefined, `«${текстЧисла}»: ${ответ.беда}`)
  }
  /* И проверка самой пробы: строки выше действительно РАЗНЫЕ по исходу —
     иначе цикл сверял бы девять раз одно и то же. */
  assert.equal(evaluate(ast, "Число из строки", { т: "9007199254740993" }, ПРЕДЕЛЫ), 9007199254740992)
  assert.ok(Object.is(evaluate(ast, "Число из строки", { т: "-0" }, ПРЕДЕЛЫ), -0))
})

