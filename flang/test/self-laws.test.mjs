/**
 * УЛИКА: чем считаются ответы вычислений, на которых держится вердикт.
 *
 * Цифра слева — сколько ответов посчитал вычислитель flang на flang, цифра
 * справа — сколько досчитал за него свидетель на JavaScript. Пока правая была
 * равна целому, круг самоприменения не замыкался: законы говорили о поведении
 * программы, поверив чужому языку на слово. Пока срез вычислителя был неполон,
 * за свидетелем оставалось 393 вызова. СЕГОДНЯ СПРАВА НОЛЬ, и это утверждение
 * прогона, а не обещание прозы.
 */
test("улика: чем посчитаны ответы вычислений, на которых держится вердикт", (t) => {
  t.diagnostic(
    `вызовов: вычислителем на flang ${счёт.вычислителем}, свидетелем на JavaScript ${счёт.свидетелем}; ` +
      `единиц: вычислителем ${счёт.единицВычислителем}, свидетелем ${счёт.единицСвидетелем}`,
  )
  const поВызову = new Map()
  for (const строка of счёт.вне) поВызову.set(строка, (поВызову.get(строка) ?? 0) + 1)
  for (const [строка, сколько] of [...поВызову].sort()) t.diagnostic(`вне среза, ${сколько}: ${строка}`)
  /* СТОРОЖ НЕПУСТОТЫ. Без него «свидетелем 0» значило бы и «круг замкнут», и
     «сверка перестала звать кого-либо вовсе» — два противоположных состояния
     одной цифрой. */
  assert.ok(счёт.вычислителем > 3000, `вычислитель посчитал ${счёт.вычислителем} вызовов — сверка перестала звать вовсе`)
  assert.ok(счёт.единицВычислителем > 20, `единиц посчитано ${счёт.единицВычислителем} — сетка обмелела`)

  /* УСТУПОК НОЛЬ, и проверка эта умеет краснеть: запасного пути к свидетелю в
     коде не осталось вовсе, а форма вне среза записывается сюда и становится
     отказом. Сузься срез вычислителя — здесь появится строка, а вердикт
     разойдётся со свидетелем. */
  assert.deepEqual([...поВызову.keys()], [], "вызов упёрся в границу среза вычислителя")
  assert.equal(счёт.свидетелем + счёт.единицСвидетелем, 0, "свидетель посчитал вызов, хотя запасного пути больше нет")
})

