test("ИЗЪЯТИЕ: испорченный оракул законов краснеет на настоящей программе корпуса", async (t) => {
  const целый = средаОракулаЗаконов
  for (const [имя, путь, было, стало] of ИЗЪЯТИЯ_ОРАКУЛА) {
    const программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    const переведённая = значение(программа)
    const свидетельМ = оракулМоноида(программа)
    const свидетельИ = оракулИзоморфизма(программа)
    const сверить = () => {
      const вДереве = таблицаМоноидаВДереве(программа, переведённая)
      return (
        расхождение(свидетельМ, { единицы: вДереве["единицы"], таблица: вДереве["таблица"] }) ??
        расхождение(свидетельИ, таблицаИзоморфизмаВДереве(программа, переведённая))
      )
    }
    assert.equal(сверить(), null, `${имя}: на целом оракуле ${путь} обязана сходиться`)

    const испорчено = исходникОракулаЗаконов.replace(было, стало)
    assert.notEqual(испорчено, исходникОракулаЗаконов, `${имя}: порча ничего не заменила — сама порча устарела`)
    const { diagnostics: _беды, ...порченая } = await linkProgram(файлОракулаЗаконов, испорчено, parse)
    средаОракулаЗаконов = createRuntime(порченая, { maxSteps: 400_000_000, maxDepth: 20_000 })
    try {
      const беда = сверить()
      assert.match(беда ?? "", /разошлось на знаке \d+/u, `${имя}: испорченный оракул прошёл незамеченным`)
      t.diagnostic(`${имя} на ${путь}: ${беда.split("\n")[0]}`)
    } finally {
      средаОракулаЗаконов = целый
    }
  }
})

