/* ────────────────── дифференциальная сверка на корпусе ────────────────── */

/**
 * Весь корпус `.flang` репозитория. Каждая программа разбирается и судится
 * обоими законами; итоги маленькие, а сами программы — нет, поэтому каждая
 * забывается сразу после сверки.
 *
 * Разбор, а не связывание, и обе стороны сверки читают одно и то же: моноид и
 * изоморфизм — объявления верхнего уровня, ни одно из них связывание не меняет,
 * а единственная программа корпуса с объявленным законом
 * (`flang/examples/cat/order-shipment.flang`) ничего не ввозит и вычисляется
 * целиком из себя. Появится ввозящая — связывание придётся завести обеим
 * сторонам сразу, иначе сверка перестанет быть сверкой одного и того же.
 */
const файлыКорпуса = globSync("**/*.flang", {
  cwd: `${корень}flang`,
  exclude: (путь) => путь.includes("node_modules"),
})
  .map((путь) => `flang/${путь}`)
  .sort()

const ПУСТО_МОНОИДА = JSON.stringify({ diagnostics: [], checked: [] })
const ПУСТО_ИЗОМОРФИЗМА = JSON.stringify({ diagnostics: [], checked: [], assumed: [] })

const итоги = []
for (const путь of файлыКорпуса) {
  try {
    const программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    const переведённая = значение(программа)
    const свидетельМоноидов = checkMonoidLaws(программа)
    const свидетельИзоморфизмов = checkIsoLaws(программа)
    const нашиМ = нашиМоноиды(программа, переведённая)
    const нашиИ = нашиИзоморфизмы(программа, переведённая)
    /* Таблицы оракула в дереве против таблиц оракула в этом файле — побайтово,
       вместе с порядком строк. Судит это отдельный тест ниже: расхождение
       таблиц значит, что вердикт посчитан на ДРУГИХ ответах, а по вердикту
       такое не видно — от лишней строки таблицы он не меняется. */
    const таблицаМ = оракулМоноида(программа)
    const таблицаИ = оракулИзоморфизма(программа)
    const вДеревеМ = таблицаМоноидаВДереве(программа, переведённая)
    итоги.push({
      путь,
      моноиды: расхождение(свидетельМоноидов, нашиМ),
      изоморфизмы: расхождение(свидетельИзоморфизмов, нашиИ),
      таблицаМоноида: расхождение(таблицаМ, { единицы: вДеревеМ["единицы"], таблица: вДеревеМ["таблица"] }),
      таблицаИзоморфизма: расхождение(таблицаИ, таблицаИзоморфизмаВДереве(программа, переведённая)),
      строкТаблиц: таблицаМ.таблица.length + таблицаИ.length,
      законов:
        свидетельМоноидов.checked.length +
        свидетельМоноидов.diagnostics.length +
        свидетельИзоморфизмов.checked.length +
        свидетельИзоморфизмов.assumed.length +
        свидетельИзоморфизмов.diagnostics.length,
      объявлено: (программа.monoids ?? []).length + (программа.isomorphisms ?? []).length,
      пустоусвидетеля: JSON.stringify(свидетельМоноидов) === ПУСТО_МОНОИДА && JSON.stringify(свидетельИзоморфизмов) === ПУСТО_ИЗОМОРФИЗМА,
      пустоунас: JSON.stringify(нашиМ) === ПУСТО_МОНОИДА && JSON.stringify(нашиИ) === ПУСТО_ИЗОМОРФИЗМА,
      тексты: [...нашиМ.diagnostics, ...нашиИ.diagnostics].map((беда) => беда.message),
      сеток: нашиМ.checked.length + нашиИ.checked.length + нашиИ.assumed.length,
    })
  } catch (ошибка) {
    итоги.push({ путь, отказ: ошибка?.message ?? String(ошибка) })
  }
}

