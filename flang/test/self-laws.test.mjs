/**
 * Законы категорий, написанные на самом flang — `flang/self/monoid.flang` и
 * `flang/self/iso.flang`.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы вердикт
 * законов на flang обязан совпасть с вердиктом свидетелей `flang/src/monoid.mjs`
 * и `flang/src/iso.mjs` — те же диагностики, код в код, текст в текст, место в
 * место, и ТЕ ЖЕ ЧИСЛА СЕТКИ. Сверка побайтовая, вместе с порядком ключей;
 * расхождение печатается с номером знака.
 *
 * ── Почему числа сетки важнее всего остального ──────────────────────────────
 * Законы моноида и изоморфизма — единственные проверки языка, которые НЕ
 * ДОКАЗЫВАЮТСЯ. Равенство вычислений на всех значениях носителя неразрешимо,
 * поэтому у каждого закона есть предел сетки, и ведомость доказательства
 * (`flang/src/proof.mjs`, `flang/self/proof.flang`) печатает про них «сетка N
 * значений», а не «доказано». Слово «доказано» рядом с ними было бы ложью.
 *
 * Числа N приезжают в ведомость отсюда — из `checked`/`«проверено»`. Значит
 * эталон, дающий другое N, не «слегка расходится»: он печатает в ведомости
 * другое утверждение о том же коде. Поэтому сверяется не «нашлось ли
 * нарушение», а вся запись целиком, вместе с числом значений и числом троек.
 *
 * ── Что покрывается сверх программ репозитория ──────────────────────────────
 *   • нарочные программы, собранные руками по `flang/cat/SPEC.md`: моноид без
 *     обращения и группа с ним; вычитание, у которого рвутся сразу три закона;
 *     обращение, не дающее единицу; несуществующая операция; операция,
 *     отказывающая на значении сетки — и в нейтральности, и внутри тройки (там
 *     свидетель подставляет наружному вызову ПУСТОЕ МЕСТО вместо значения, и
 *     таблица вызовов обязана это различать); единица, которую не удалось
 *     вычислить; значение длиннее сорока знаков, которое в тексте отсекается;
 *   • изоморфизмы: обратимая пара, необратимая в обе стороны, пара без `даёт`,
 *     пара с пустой сеткой, несуществующая стрелка, стрелка, зовущая
 *     несуществующую функцию, и стрелка, зовущая функцию чужой арности;
 *   • ЧЕТВЁРТАЯ ПРОВЕРКА, без которой первые три ничего не значат: программа
 *     БЕЗ объявленных законов обязана давать пустой результат у обоих — и это
 *     проверяется на настоящих программах корпуса, всех до единой. Иначе тест
 *     зеленел бы на корпусе, где законов почти нет, не проверяя ничего.
 *
 * ── Умеет ли сверка краснеть ────────────────────────────────────────────────
 * Отдельный раздел в конце: сверка запускается на нарочно испорченном итоге
 * эталона — в числе сетки, в числе троек и в тексте диагностики, — и обязана
 * назвать знак расхождения. Сверка, не умеющая краснеть, — не сверка.
 *
 * ── Откуда берётся таблица вызовов, и ЧЕМ она посчитана ─────────────────────
 * Законам мало РАЗОБРАТЬ программу — им надо её ВЫПОЛНИТЬ. Языку flang нечем
 * передать функцию функцией (первого класса у него нет), поэтому вызовы
 * приезжают в эталон данными, и строит эту таблицу здешний оракул.
 *
 * СЧИТАЕТ ЖЕ ЕЁ ТЕПЕРЬ ВЫЧИСЛИТЕЛЬ, НАПИСАННЫЙ НА FLANG, — `self/interpret.flang`
 * через `self-evaluator.mjs`. Раньше её считал свидетель на JavaScript, и круг
 * «язык доказывает сам себя» на этом размыкался: вердикт о ПОВЕДЕНИИ программы
 * держался на чужом языке. Отсюда проверка в конце файла, которой раньше не
 * могло быть вовсе: сломай вычислитель в одном месте — вердикт законов обязан
 * разойтись со свидетелем.
 *
 * НА СВИДЕТЕЛЬ НЕ УХОДИТ НИЧЕГО, и это утверждение прогона: улика печатает
 * «свидетелем на JavaScript 0». Пока срез вычислителя был неполон, за свидетелем
 * оставалось 393 вызова с `к числу`; срез закончен, и запасного пути в коде не
 * осталось вовсе — форма вне среза стала бы обычным отказом, от которого вердикт
 * разошёлся бы со свидетелем.
 *
 * Оракул НЕ РЕШАЕТ ничего из того, что решает эталон. Он берёт все значения,
 * которые автор написал в примерах названных функций, без отбора и без предела
 * — отбор, порядок и предел сетки остаются за эталоном, — и вычисляет на них
 * замыкание тех вызовов, которые свидетель может сделать: операцию на парах, потом
 * операцию на результатах, потом обращение. Ошибиться так можно ровно в одну
 * сторону: недостающий вызов эталон назовёт вслух («вызова нет в таблице»), и
 * сверка от этого покраснеет, а не позеленеет. Отдельный тест ниже стережёт,
 * что этих слов не появилось ни разу.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { reifyValue, valuesEqual } from "../src/builtins.mjs"
import { createRuntime, evaluate } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

import { ПРЕДЕЛ_ИЗОМОРФИЗМА as ПРЕДЕЛ_ИЗО_ПУТИ, ПРЕДЕЛ_МОНОИДА as ПРЕДЕЛ_МОНОИДА_ПУТИ } from "../src/self.mjs"

import { globSync } from "./glob.mjs"
import { вычислитель, исходникСлоя, слойИз, средаСлоя } from "./self-evaluator.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

const файлМоноида = fileURLToPath(new URL("../self/monoid.flang", import.meta.url))
const файлИзоморфизма = fileURLToPath(new URL("../self/iso.flang", import.meta.url))
const исходникМоноида = readFileSync(файлМоноида, "utf8")
const исходникИзоморфизма = readFileSync(файлИзоморфизма, "utf8")

/* Свой разбор — чтобы знать, какие функции объявлены именно здесь, а какие
   приехали из «Печати JSON», «Печати в C» и соседнего модуля законов. */
const свойМоноид = parse(исходникМоноида, "self/monoid.flang")
const свойИзоморфизм = parse(исходникИзоморфизма, "self/iso.flang")

const { diagnostics: связкаМоноида, ...программаМоноида } = await linkProgram(файлМоноида, исходникМоноида, parse)
const { diagnostics: связкаИзоморфизма, ...программаИзоморфизма } = await linkProgram(файлИзоморфизма, исходникИзоморфизма, parse)

const типыМоноида = checkTypes(программаМоноида)
const типыИзоморфизма = checkTypes(программаИзоморфизма)
const тотальностьМоноида = checkTotality(программаМоноида)
const тотальностьИзоморфизма = checkTotality(программаИзоморфизма)

/**
 * Лимит шагов поднят с миллиона до сорока миллионов, и не про запас: сетка в
 * двенадцать значений даёт 1728 троек, каждая тройка — четыре поиска в таблице,
 * а поиск линеен по её длине. На корпусе и на нарочных программах расход втрое
 * меньше, но лимит стережёт именно рост: поиск, ставший квадратичным по сетке,
 * упрётся в него и будет назван.
 */
const ШАГИ = { maxSteps: 40_000_000 }
const средаМоноида = createRuntime(программаМоноида, ШАГИ)
const средаИзоморфизма = createRuntime(программаИзоморфизма, ШАГИ)


/* ─────────────────────── слой: программы на flang ─────────────────────── */

test("monoid.flang: разбор даёт контракт cat/SPEC, «Моноид и группа»", () => {
  assert.equal(свойМоноид.flang, 1)
  assert.equal(свойМоноид.module, "Законы моноида")
  assert.ok(свойМоноид.functions.length > 0)
  /* Детерминированность: повторный разбор даёт побайтово тот же AST. */
  assert.equal(JSON.stringify(parse(исходникМоноида, "self/monoid.flang")), JSON.stringify(свойМоноид))
})

test("iso.flang: разбор даёт контракт cat/SPEC, «Изоморфизм»", () => {
  assert.equal(свойИзоморфизм.flang, 1)
  assert.equal(свойИзоморфизм.module, "Законы изоморфизма")
  assert.ok(свойИзоморфизм.functions.length > 0)
  assert.equal(JSON.stringify(parse(исходникИзоморфизма, "self/iso.flang")), JSON.stringify(свойИзоморфизм))
})

test("оба эталона связываются без диагностик", () => {
  assert.deepEqual(связкаМоноида, [])
  assert.deepEqual(связкаИзоморфизма, [])
})

test("оба эталона проходят проверку типов без диагностик", () => {
  assert.deepEqual(типыМоноида.diagnostics, [])
  assert.deepEqual(типыИзоморфизма.diagnostics, [])
})

test("оба эталона проходят анализ завершаемости без диагностик", () => {
  assert.deepEqual(тотальностьМоноида.diagnostics, [])
  assert.deepEqual(тотальностьИзоморфизма.diagnostics, [])
})

/**
 * Ни одной обычной функции и ни одного сторожа.
 *
 * Это не украшение отчёта. Ведомость доказательства печатает про законы «сетка
 * N», а не «доказано», — и печатать это вправе только программа, сама
 * проходящая тот анализ, чьими выводами она отчитывается. Обычная функция здесь
 * означала бы, что проверка законов может не завершиться, и тогда «сетка N»
 * стало бы обещанием без покрытия.
 */
test("у обоих эталонов нет ни одной обычной функции и ни одного сторожа", () => {
  for (const [имя, свой] of [
    ["monoid.flang", свойМоноид],
    ["iso.flang", свойИзоморфизм],
  ]) {
    const обычные = свой.functions.filter((функция) => функция.total !== true).map((функция) => функция.name)
    assert.deepEqual(обычные, [], `${имя}: обычные функции ${обычные.join(", ")}`)
  }
  for (const [имя, тотальность] of [
    ["monoid.flang", тотальностьМоноида],
    ["iso.flang", тотальностьИзоморфизма],
  ]) {
    assert.deepEqual(тотальность.guards, [], `${имя}: сторожа`)
  }
})

test("каждая объявленная тотальной функция эталонов доказана тотальной", () => {
  for (const [тотальность, свой] of [
    [тотальностьМоноида, свойМоноид],
    [тотальностьИзоморфизма, свойИзоморфизм],
  ]) {
    for (const функция of свой.functions) {
      assert.ok(тотальность.total.has(функция.name), `«${функция.name}» объявлена тотальной, но не доказана`)
    }
  }
})

test("примеры обоих эталонов сходятся", () => {
  let счёт = 0
  for (const [программа, свой] of [
    [программаМоноида, свойМоноид],
    [программаИзоморфизма, свойИзоморфизм],
  ]) {
    for (const функция of свой.functions) {
      for (const пример of функция.examples ?? []) {
        счёт += 1
        /* Сравнение то же, каким сверяет примеры `flang test`
           (`runExamples` из `src/compat.mjs`): ожидаемое значение овеществляется,
           потому что вариант в примере записан кодировкой, а вычислитель отдаёт
           настоящий вариант. */
        assert.ok(
          valuesEqual(evaluate(программа, функция.name, пример.args, ШАГИ), reifyValue(пример.expected)),
          `«${функция.name}» / «${пример.name}»`,
        )
      }
    }
  }
  assert.ok(счёт >= 8, `примеров всего ${счёт}`)
})

/**
 * Предел сетки объявлен в одном месте на каждый закон, и эталон обязан
 * называть то же число, что свидетель: предел уезжает в ведомость рядом с
 * размером сетки, и разойтись в нём значит напечатать другое утверждение.
 */
test("пределы сеток у эталонов те же, что у копии в рабочем пути", () => {
  assert.equal(средаМоноида.call("Предел сетки моноида", {}), ПРЕДЕЛ_МОНОИДА_ПУТИ)
  assert.equal(средаИзоморфизма.call("Предел сетки изоморфизма", {}), ПРЕДЕЛ_ИЗО_ПУТИ)
})

/**
 * КОПИЯ ПРЕДЕЛА В РАБОЧЕМ ПУТИ СВЕРЕНА С ОБЪЯВЛЕНИЕМ СЛОЯ.
 *
 * После переключения `src/monoid.mjs` и `src/iso.mjs` ушли из рабочего пути
 * целиком, и ведомость больше не берёт у них `ПРЕДЕЛ_СЕТКИ`. Число ей всё равно
 * нужно — она печатает «сетка N из предела M» и печатает синхронно, на
 * программах, где моноида нет вовсе, — поэтому копия стоит в `src/self.mjs`.
 *
 * Хозяин числа при этом СЛОЙ. Утверждение ниже держит копию честной: разъедется
 * — покраснеет здесь, а не в отчёте о чужой программе. Без него два числа могли
 * бы разойтись молча, и ведомость печатала бы про сетку неправду.
 */
test("предел сетки в рабочем пути тот же, что объявляет слой", () => {
  assert.equal(ПРЕДЕЛ_МОНОИДА_ПУТИ, средаМоноида.call("Предел сетки моноида", {}))
  assert.equal(ПРЕДЕЛ_ИЗО_ПУТИ, средаИзоморфизма.call("Предел сетки изоморфизма", {}))
})
