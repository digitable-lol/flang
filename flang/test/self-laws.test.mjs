/** Законы моноида на flang, приведённые к форме свидетеля. */
function нашиМоноиды(программа, переведённая = значение(программа)) {
  const { единицы, таблица } = оракулМоноида(программа)
  const итог = средаМоноида.call("Проверить законы моноида", {
    "программа": переведённая,
    "единицы": единицы,
    "таблица": таблица,
  })
  return {
    diagnostics: итог["диагностики"].map(образцовая),
    /* Поле `violations` уезжает наружу ТОЛЬКО при ненулевом значении — так же,
       как у свидетеля (`...(нарушений === 0 ? {} : { violations })`). Причина у
       обеих сторон одна: на форму записи честного моноида сослались тесты
       дословно, и «violations: 0» в каждой записи приучило бы к этому полю за
       неделю. Ноль на стороне flang — это отсутствие поля здесь, а не отдельный
       вариант в языке: у языка нет необязательных полей записи, и заводить их
       ради отчёта значило бы менять язык под сериализацию. */
    checked: итог["проверено"].map((сетка) => ({
      monoid: сетка["моноид"],
      values: сетка["значений"],
      triples: сетка["троек"],
      ...(сетка["нарушений"] === 0 ? {} : { violations: сетка["нарушений"] }),
      ...(сетка["оборвано"] === "" ? {} : { aborted: сетка["оборвано"] }),
    })),
  }
}

/** Обратимость изоморфизмов на flang, приведённая к форме свидетеля. */
function нашиИзоморфизмы(программа, переведённая = значение(программа)) {
  const итог = средаИзоморфизма.call("Проверить законы изоморфизма", {
    "программа": переведённая,
    "таблица": оракулИзоморфизма(программа),
  })
  return {
    diagnostics: итог["диагностики"].map(образцовая),
    checked: итог["проверено"].map((сетка) => ({
      isomorphism: сетка["изоморфизм"],
      values: сетка["значений"],
      ...(сетка["нарушений"] === 0 ? {} : { violations: сетка["нарушений"] }),
    })),
    assumed: итог["допущено"].map((пропуск) => ({ isomorphism: пропуск["изоморфизм"], why: пропуск["почему"] })),
  }
}

/**
 * Побайтовое расхождение двух итогов — вместе с ПОРЯДКОМ КЛЮЧЕЙ.
 *
 * Номер знака в ответе обязателен: «не совпало» на записи в две тысячи знаков
 * заставляет искать разницу глазами, а найти её надо за один взгляд.
 */
function расхождение(свидетель, наш) {
  const слева = JSON.stringify(свидетель)
  const справа = JSON.stringify(наш)
  if (слева === справа) return null
  const знаки = [...слева]
  const место = знаки.findIndex((знак, номер) => знак !== справа[номер])
  const окно = (текст) => текст.slice(Math.max(0, место - 30), место + 70)
  return `разошлось на знаке ${место === -1 ? слева.length : место}:\n    свидетель …${окно(слева)}…\n    наш    …${окно(справа)}…`
}

