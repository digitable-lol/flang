/* ─────────────────────────── оракул вызовов ─────────────────────────── */

/**
 * СЧЁТ ОТВЕТОВ, ПОСЧИТАННЫХ ЧУЖИМ ЯЗЫКОМ.
 *
 * Это улика, а не украшение отчёта. Пока вычислителя flang на flang не было,
 * КАЖДЫЙ ответ вычисления, на котором держится вердикт законов, считал эталон
 * на JavaScript. Число таких ответов и есть размер дыры в круге
 * самоприменения — и оно обязано быть напечатано, иначе «круг замкнут» нечем
 * ни подтвердить, ни опровергнуть.
 */
const счёт = { эталоном: 0, вычислителем: 0, единицЭталоном: 0, единицВычислителем: 0 }

/**
 * Вызов эталонного вычислителя: имя функции и позиционные аргументы.
 *
 * Тот же путь, каким зовёт `звать` из `src/monoid.mjs`: имена берутся из
 * `params` по порядку, лишние аргументы отбрасываются, недостающие приходят
 * пустым местом. Отказ вычисления — не исключение теста, а ответ: закон
 * проверить не на чем, и близнец обязан сказать об этом тем же текстом.
 */
function позвать(программа, среда, имя, аргументы) {
  const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
  if (!функция) return { нет: true }
  const назван = {}
  ;(функция.params ?? []).forEach((параметр, номер) => {
    назван[параметр.name] = аргументы[номер]
  })
  счёт.эталоном += 1
  try {
    return { значение: среда.call(имя, назван) }
  } catch (беда) {
    return { ошибка: беда?.message ?? String(беда) }
  }
}

/** Аргумент в форме близнеца: пустое место и `ничто` — разные аргументы. */
const аргументом = (з) =>
  з === undefined ? вариантЗначения("Нет аргумента") : вариантЗначения("Есть аргумент", { значение: значение(з) })

/**
 * Таблица вызовов одной программы.
 *
 * Ключ строит САМ БЛИЗНЕЦ («Ключ вызова»): формат ключа — его дело, и вторая
 * его копия здесь разошлась бы с первой молча.
 */
function таблицаВызовов(программа) {
  const среда = createRuntime(программа, ШАГИ)
  const строки = new Map()
  const записать = (имя, аргументы) => {
    const ключ = средаМоноида.call("Ключ вызова", { "имя": имя, "аргументы": аргументы.map(аргументом) })
    if (строки.has(ключ)) return строки.get(ключ)
    const итог = позвать(программа, среда, имя, аргументы)
    строки.set(ключ, итог)
    return итог
  }
  return { записать, строки }
}

/* Строка таблицы: имени, которого в программе нет, в таблице не место — про
   такое близнец отвечает сам, не заглядывая в неё. */
const строкиТаблицы = (строки) =>
  [...строки]
    .filter(([, итог]) => итог.нет !== true)
    .map(([ключ, итог]) => ({
      "ключ": ключ,
      "ответ":
        итог.ошибка === undefined
          ? вариантЗначения("Вызов дал", { "значение": значение(итог.значение) })
          : вариантЗначения("Вызов отказал", { "сообщение": итог.ошибка }),
    }))

/**
 * Предел числа значений, на которых оракул строит замыкание.
 *
 * Заведомо больше предела сетки обоих законов: сетка близнеца — начало этого
 * списка, а таблица обязана быть шире сетки, иначе недостающий вызов был бы
 * виден только как отсутствие.
 */
const ПРЕДЕЛ_ОРАКУЛА = Math.max(ПРЕДЕЛ_МОНОИДА, ПРЕДЕЛ_ИЗОМОРФИЗМА) + 4

/* Повторы отсеиваются по печати значения — механически, а не по правилу
   близнеца: близнец считает повтором большее (запись с теми же ключами в
   другом порядке), поэтому его сетка — подмножество этого списка. */
function безПовторов(значения) {
  const видели = new Set()
  const итог = []
  for (const з of значения) {
    if (з === undefined) continue
    const ключ = JSON.stringify(з)
    if (видели.has(ключ)) continue
    видели.add(ключ)
    итог.push(з)
  }
  return итог.slice(0, ПРЕДЕЛ_ОРАКУЛА)
}

/** Все значения, написанные автором в примерах названных функций. Отбора нет. */
function значенияПримеров(программа, имена) {
  const собрано = []
  for (const имя of имена) {
    if (имя === null || имя === undefined) continue
    const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
    for (const пример of функция?.examples ?? []) {
      for (const з of Object.values(пример.args ?? {})) собрано.push(з)
      собрано.push(пример.expected)
    }
  }
  return собрано
}

/**
 * Единица моноида: то же самое, что делает `вычислитьЕдиницу` эталона —
 * выражение оборачивается функцией без аргументов и вычисляется. Второго
 * вычислителя ради одного литерала здесь нет, как нет его и у эталона.
 */
function единицаМоноида(программа, узел) {
  const обёртка = {
    ...программа,
    functions: [
      ...(Array.isArray(программа.functions) ? программа.functions : []),
      { name: `«единица ${узел.name}»`, params: [], returns: узел.carrier, body: узел.unit, examples: [] },
    ],
  }
  счёт.единицЭталоном += 1
  try {
    return { есть: true, значение: createRuntime(обёртка).call(`«единица ${узел.name}»`, {}) }
  } catch {
    return { есть: false }
  }
}

/**
 * Оракул моноидов: единицы по порядку объявления и замыкание вызовов.
 *
 * Замыкание — ровно те вызовы, которые эталон может сделать: операция от
 * единицы и значения в обе стороны, операция на всех парах, операция на
 * результатах пар (это и есть `(а⊕б)⊕в` и `а⊕(б⊕в)`), обращение и операция на
 * обратном. Результат неудавшегося вызова тоже идёт дальше аргументом — пустым
 * местом, как у эталона.
 */
function оракулМоноида(программа) {
  const узлы = Array.isArray(программа.monoids) ? программа.monoids : []
  const единицы = узлы.map((узел) => единицаМоноида(программа, узел))
  const наружу = единицы.map((единица) =>
    единица.есть ? вариантЗначения("Единица есть", { "значение": значение(единица.значение) }) : вариантЗначения("Единицы нет"),
  )
  if (узлы.length === 0) return { единицы: наружу, таблица: [] }

  const { записать, строки } = таблицаВызовов(программа)
  узлы.forEach((узел, номер) => {
    const единица = единицы[номер]
    const операция = узел.operation
    const значения = безПовторов([
      ...(единица.есть ? [единица.значение] : []),
      ...значенияПримеров(программа, [операция, узел.inverse]),
    ])
    if (единица.есть) {
      for (const з of значения) {
        записать(операция, [единица.значение, з])
        записать(операция, [з, единица.значение])
      }
    }
    const промежуточные = []
    for (const а of значения) for (const б of значения) промежуточные.push(записать(операция, [а, б]).значение)
    for (const р of промежуточные) for (const в of значения) записать(операция, [р, в])
    for (const а of значения) for (const р of промежуточные) записать(операция, [а, р])
    if (узел.inverse !== null && узел.inverse !== undefined) {
      for (const з of значения) {
        const обратное = записать(узел.inverse, [з]).значение
        записать(операция, [обратное, з])
        записать(операция, [з, обратное])
      }
    }
  })
  return { единицы: наружу, таблица: строкиТаблицы(строки) }
}

/** Значения, написанные автором у стрелки: у её реализации и у её законов. */
function значенияСтрелки(программа, стрелка) {
  const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === стрелка.gives)
  const примеры = [...(функция?.examples ?? []), ...(стрелка.laws ?? []).flatMap((закон) => закон.examples ?? [])]
  const собрано = []
  for (const пример of примеры) {
    for (const з of Object.values(пример.args ?? {})) собрано.push(з)
    собрано.push(пример.expected)
  }
  return собрано
}

/** Оракул изоморфизмов: два шага круга на каждое значение обеих стрелок. */
function оракулИзоморфизма(программа) {
  const узлы = Array.isArray(программа.isomorphisms) ? программа.isomorphisms : []
  if (узлы.length === 0) return []

  const стрелки = new Map()
  for (const узел of Array.isArray(программа.morphisms) ? программа.morphisms : []) {
    if (узел?.kind === "morphism") стрелки.set(узел.name, узел)
  }

  const { записать, строки } = таблицаВызовов(программа)
  for (const узел of узлы) {
    const прямая = стрелки.get(узел.forward)
    const обратная = стрелки.get(узел.backward)
    if (прямая === undefined || обратная === undefined) continue
    if (typeof прямая.gives !== "string" || typeof обратная.gives !== "string") continue
    const значения = безПовторов([...значенияСтрелки(программа, прямая), ...значенияСтрелки(программа, обратная)])
    for (const [туда, назад] of [
      [прямая, обратная],
      [обратная, прямая],
    ]) {
      for (const з of значения) записать(назад.gives, [записать(туда.gives, [з]).значение])
    }
  }
  return строкиТаблицы(строки)
}

