/* ─────────────────────── дифференциальная сверка с образцом ──────────────── */

/** Токен образца и токен на flang, приведённые к одной форме. */
const образцовый = (токен) => [
  токен.kind,
  токен.kind === "number" ? токен.value : токен.value,
  токен.text ?? "",
  токен.quoted === true,
  токен.span?.line ?? 0,
  токен.span?.column ?? 0,
]

const наш = (токен) => [
  токен["вид"],
  токен["вид"] === "number" ? токен["число"] : токен["значение"],
  токен["текст"],
  токен["в ёлочках"],
  токен["строка"],
  токен["столбец"],
]

/**
 * Сверка одного текста. Возвращает описание первого расхождения или null.
 * Отказ образца — тоже поведение: сверяются код, сообщение и место.
 */
function расхождение(текст) {
  let эталон = null
  let отказ = null
  try {
    эталон = tokenize(текст)
  } catch (ошибка) {
    отказ = ошибка.diagnostics?.[0] ?? { code: "?", message: String(ошибка?.message) }
  }
  const итог = разобрать(текст)
  if (отказ !== null) {
    const беда = итог["диагностики"][0]
    if (беда === undefined) return `образец отказал (${отказ.code}: ${отказ.message}), лексер на flang — нет`
    const ждём = [отказ.code, отказ.message, отказ.span?.line ?? 0, отказ.span?.column ?? 0]
    const есть = [беда["код"], беда["сообщение"], беда["строка"], беда["столбец"]]
    return JSON.stringify(ждём) === JSON.stringify(есть)
      ? null
      : `диагностика ${JSON.stringify(есть)} ≠ ${JSON.stringify(ждём)}`
  }
  if (итог["диагностики"].length > 0) {
    return `лексер на flang отказал там, где образец разобрал: ${JSON.stringify(итог["диагностики"][0])}`
  }
  const свои = итог["токены"]
  for (let индекс = 0; индекс < Math.max(эталон.length, свои.length); индекс += 1) {
    if (эталон[индекс] === undefined) return `лишний токен ${индекс}: ${JSON.stringify(наш(свои[индекс]))}`
    if (свои[индекс] === undefined) return `нет токена ${индекс}: ${JSON.stringify(образцовый(эталон[индекс]))}`
    const ждём = JSON.stringify(образцовый(эталон[индекс]))
    const есть = JSON.stringify(наш(свои[индекс]))
    if (ждём !== есть) return `токен ${индекс}: ${есть} ≠ ${ждём}`
  }
  return null
}

const каталоги = ["flang/stdlib", "flang/core", "flang/examples/leetcode", "flang/self"]
const исходники = каталоги.flatMap((каталог) =>
  readdirSync(`${корень}${каталог}`)
    .filter((имя) => имя.endsWith(".flang"))
    .map((имя) => `${каталог}/${имя}`)
    .sort(),
)

test("каждый .flang репозитория лексируется в тот же поток, что у образца", () => {
  assert.ok(исходники.length >= 30, `файлов всего ${исходники.length}`)
  for (const путь of исходники) {
    const беда = расхождение(readFileSync(`${корень}${путь}`, "utf8"))
    assert.equal(беда, null, `${путь}: ${беда}`)
  }
})

test("сверка идёт по всем видам токенов, а не по паре имён", () => {
  const виды = new Set()
  for (const путь of исходники) {
    for (const токен of tokenize(readFileSync(`${корень}${путь}`, "utf8"))) виды.add(токен.kind)
  }
  assert.deepEqual(
    [...виды].sort(),
    ["arrow", "dedent", "eof", "indent", "keyword", "name", "newline", "number", "punct", "string"],
  )
})

