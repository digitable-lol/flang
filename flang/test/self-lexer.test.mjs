test("недопустимый символ называет сам символ", () => {
  assert.equal(беда("имя @ хвост\n")["сообщение"], "недопустимый символ '@'")
  assert.equal(беда("имя @ хвост\n")["столбец"], 5)
  /* Одинокий минус в набор знаков образца не входит, а началом имени не является. */
  assert.equal(беда("а - б\n")["сообщение"], "недопустимый символ '-'")
  /* Одинокая косая черта — тоже: комментарий начинают только `//` и `/*`. */
  assert.equal(беда("а / б\n")["сообщение"], "недопустимый символ '/'")
})

test("незакрытые кавычки и комментарий: место — начало, а не конец", () => {
  assert.equal(беда("объект «Покупка\n")["сообщение"], "не закрыта кавычка-ёлочка")
  assert.equal(беда("объект «Покупка\n")["столбец"], 8)
  assert.equal(беда('дано "строка\n')["сообщение"], "не закрыта кавычка")
  assert.equal(беда("а /* хвост\nещё\n")["сообщение"], "не закрыт блочный комментарий")
  assert.equal(беда("а /* хвост\nещё\n")["строка"], 1)
  assert.equal(беда("а /* хвост\nещё\n")["столбец"], 3)
  assert.equal(беда('"\\uZZZZ"\n')["сообщение"], "неверный Unicode-escape")
})

