/**
 * Лексер языка flang, написанный на самом flang — `flang/self/lexer.flang`.
 *
 * Главная проверка здесь одна и она сквозная: для каждого `.flang` репозитория
 * поток токенов, полученный лексером на flang, обязан совпасть с потоком от
 * эталонного `flang/src/lexer.mjs` — вид в вид, значение в значение, вместе с
 * `text`, признаком закавыченности и местом (строка и столбец). Это
 * единственная проверка, которая что-то доказывает: собственные тесты «на пару
 * примеров» её не заменяют, потому что лексер обязан не «работать», а
 * воспроизводить образец.
 *
 * Второй блок — отказы. Образец бросает исключение и теряет собранные токены;
 * лексер на flang возвращает беду значением. Сверяются код, текст сообщения и
 * место: расхождение в диагностике — такое же расхождение, как расхождение в
 * токенах.
 *
 * Третий блок — фаззинг: случайные склейки из кусков, на которых лексер обычно
 * и ломается (кавычки, экранирование, комментарии, стрелки, отступы). Сид
 * зафиксирован, поэтому падение воспроизводится.
 */
import assert from "node:assert/strict"
import { readdirSync, readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { evaluate, createRuntime } from "../src/interpret.mjs"
import { KEYWORDS, keywordId, tokenize } from "../src/lexer.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const файл = fileURLToPath(new URL("../self/lexer.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")

/* Свой разбор — чтобы знать, какие функции объявлены именно здесь, а какие
   приехали из «Строк». Типы и тотальность считаются по связанной программе:
   без импорта имена стандартной библиотеки остались бы несвязанными. */
const свой = parse(исходник, "self/lexer.flang")
const связано = await linkProgram(файл, исходник, parse)
const { diagnostics: диагностикиСвязывания, ...программа } = связано
const типы = checkTypes(программа)
const тотальность = checkTotality(программа)

/**
 * Лимит шагов поднят с миллиона до шестидесяти. Посимвольный проход по файлу в
 * 150 000 символов (`flang/core/parser.flang`, самый большой исходник
 * репозитория) укладывается между двадцатью и тридцатью миллионами шагов;
 * запас взят двукратный и не больше. Лимит здесь не формальность: он проверяет,
 * что разбор остался линейным по числу символов, а не свалился в квадрат.
 * Глубина вызовов оставлена стандартной — рекурсия прохода хвостовая, и
 * нехвостовой остаётся только склейка ключевых слов, а она живёт в пределах
 * одной строки.
 */
const ШАГИ = { maxSteps: 60_000_000 }
const среда = createRuntime(программа, ШАГИ)
const вызвать = (имя, аргументы) => среда.call(имя, аргументы)
const разобрать = (текст) => вызвать("Разобрать", { исходник: текст })
const разметка = (текст) => вызвать("Разметка", { исходник: текст })

