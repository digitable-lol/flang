test("«Символ по коду» даёт то же, что даёт образец на \\uXXXX", () => {
  let счёт = 0
  for (const [начало, конец] of [[0, 0x7ff], [0x2000, 0x21ff]]) {
    for (let код = начало; код <= конец; код += 1) {
      счёт += 1
      const ждём = String.fromCharCode(код).normalize("NFC")
      const есть = вызвать("Символ по коду", { код })
      assert.equal(есть, ждём, `код ${код.toString(16)}`)
    }
  }
  assert.equal(счёт, 2560)
  /* За выписанными блоками — пусто, и это отказ, а не молчаливая подмена. */
  assert.equal(вызвать("Символ по коду", { код: 0x3042 }), "")
  assert.equal(беда('"\\u3042"\n')["сообщение"], "неверный Unicode-escape")
})

