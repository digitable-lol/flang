const МЕСТО = (span) =>
  span === undefined || span === null
    ? { "есть": false, "строка": 0, "столбец": 0 }
    : { "есть": true, "строка": span.line, "столбец": span.column }

/* ─────────────────── корпус ─────────────────── */

function файлыКорпуса(каталог, найдено = []) {
  for (const имя of readdirSync(каталог)) {
    if (имя === "node_modules" || имя === ".git" || имя === ".claude" || имя === "dist") continue
    const путь = join(каталог, имя)
    if (statSync(путь).isDirectory()) файлыКорпуса(путь, найдено)
    else if (имя.endsWith(".flang")) найдено.push(путь)
  }
  return найдено
}

/** Тексты и первые разборы читаются один раз: изъятий ниже больше десятка. */
const тексты = new Map()
const тексту = (путь) => {
  if (!тексты.has(путь)) тексты.set(путь, readFileSync(путь, "utf8"))
  return тексты.get(путь)
}
const первыеРазборы = new Map()
function первыйРазбор(путь, текст) {
  if (!первыеРазборы.has(путь)) {
    try {
      первыеРазборы.set(путь, { программа: parse(текст, путь), диагностики: [] })
    } catch (беда) {
      первыеРазборы.set(путь, {
        программа: null,
        диагностики: (беда?.diagnostics ?? [{ code: "FLANG_PARSE", message: String(беда?.message ?? беда) }]).map((д) => ({
          "код": д.code,
          "сообщение": д.message,
          "место": МЕСТО(д.span),
        })),
      })
    }
  }
  return первыеРазборы.get(путь)
}

/** Файл и всё, до чего дотягиваются его импорты: то же замыкание, что у линкера. */
function замыкание(путь, тексту_, найдено = new Set()) {
  if (найдено.has(путь)) return найдено
  let текст
  try { текст = тексту_(путь) } catch { return найдено }
  найдено.add(путь)
  const разбор = первыйРазбор(путь, текст)
  if (разбор.программа === null) return найдено
  for (const импорт of importsOf(разбор.программа)) {
    const части = путь.split("/").slice(0, -1)
    for (const кусок of импорт.from.split("/")) {
      if (кусок === ".") continue
      else if (кусок === "..") части.pop()
      else части.push(кусок)
    }
    замыкание(части.join("/"), тексту_, найдено)
  }
  return найдено
}

