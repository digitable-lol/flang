test("восемь родов теорката и пять объявлений входного файла есть в корпусе, а не только в правиле", async () => {
  /* Раскладка по ключам стоит здесь не для красоты: пропади из слияния один род —
     скажем, монада, — общее число поехало бы, а какой именно род пропал, сказала
     бы только раскладка. Числа мерены на этом дереве. */
  const счёт = new Map()
  for (const вход of КОРПУС) {
    const { программа } = await вторымМнением(вход)
    for (const ключ of Object.keys(программа)) {
      if (["flang", "module", "types", "functions", "legacy"].includes(ключ)) continue
      счёт.set(ключ, (счёт.get(ключ) ?? 0) + 1)
    }
  }
  const ждём = [
    ["categories", 9], ["embeddings", 1], ["intersections", 1], ["isomorphisms", 1],
    ["monads", 2], ["monoids", 5], ["morphisms", 9],
    ["plans", 1], ["processes", 10], ["runs", 10], ["supervisors", 9], ["theorems", 36],
  ]
  assert.deepEqual([...счёт].sort((а, б) => а[0].localeCompare(б[0])), ждём, "раскладка объявлений по корпусу поехала")
})

