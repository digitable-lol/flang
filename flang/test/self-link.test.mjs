/** ВТОРОЕ МНЕНИЕ — реализация на JavaScript. */
async function вторымМнением(вход) {
  const опции = вход.дурной ? { readFile: читалка(вход.файлы) } : { readFile: async (путь) => readFileSync(путь, "utf8") }
  const { diagnostics: беды, ...программа } = await linkProgram(вход.вход, вход.тексту(вход.вход), parse, опции)
  return { программа, беды }
}

/**
 * РАБОЧИЙ СЛОЙ — тот самый, из которого печатается компилятор.
 *
 * Двумя вызовами, и это не обход: связывание у эталона тоже идёт двумя
 * проходами, и между ними стоит ПЕРЕРАЗБОР с полным набором имён. Набор имён
 * даёт близнец («Имена после первого прохода»); тест только разбирает по нему.
 */
function рабочимСлоем(вход, свой = близнец) {
  const файлы = [...замыкание(вход.вход, вход.тексту)]
  const разборы = файлы.map((путь) => ({ путь, разбор: первыйРазбор(путь, вход.тексту(путь)) }))
  const кОтдаче = (переразборы) =>
    разборы.map(({ путь, разбор }) => ({
      "путь": путь,
      "текст": "",
      "программа": значение(разбор.программа),
      "диагностики": разбор.диагностики,
      "переразбор": значение(переразборы?.get(путь) ?? null),
    }))

  const имена = evaluate(свой, "Имена после первого прохода", { "разборы": кОтдаче(), "вход": вход.вход }, ШАГИ)
  const набор = new Set(имена)
  const переразборы = new Map()
  for (const { путь, разбор } of разборы) {
    if (разбор.программа === null || importsOf(разбор.программа).length === 0) continue
    try { переразборы.set(путь, parse(вход.тексту(путь), путь, набор)) } catch { /* остаётся первый проход */ }
  }
  return evaluate(свой, "Связать разобранное", { "разборы": кОтдаче(переразборы), "вход": вход.вход }, ШАГИ)
}

const ключБеды = (код, текст, место) => JSON.stringify([код, текст, место])
const бедыЭталона = (беды) => беды.map((б) => ключБеды(б.code, б.message, б.span ? `${б.span.line}:${б.span.column}` : "-"))
const бедыСлоя = (итог) =>
  itogБеды(итог).map((б) => ключБеды(б["код"], б["сообщение"], б["место"]["есть"] ? `${б["место"]["строка"]}:${б["место"]["столбец"]}` : "-"))
const itogБеды = (итог) => итог["диагностики"] ?? []

/**
 * Сверить корпус. Возвращает числа, а не «да/нет»: сверка, чей охват нельзя
 * перепроверить, даёт ложную уверенность.
 */
async function сверить(свой = близнец, корпус = КОРПУС) {
  const расхождения = []
  let диагностик = 0
  let объявлений = 0
  for (const вход of корпус) {
    const { программа, беды } = await вторымМнением(вход)
    диагностик += беды.length
    объявлений += (программа.functions?.length ?? 0) + (программа.types?.length ?? 0)
    const ждём = JSON.stringify(программа)
    let наша
    let нашиБеды
    try {
      const итог = рабочимСлоем(вход, свой)
      наша = JSON.stringify(изЗначения(итог["программа"]))
      нашиБеды = бедыСлоя(итог)
    } catch (беда) {
      наша = `СОРВАЛОСЬ: ${беда?.message}`
      нашиБеды = ["СОРВАЛОСЬ"]
    }
    if (наша !== ждём) {
      let и = 0
      while (и < наша.length && и < ждём.length && наша[и] === ждём[и]) и += 1
      расхождения.push(
        `${вход.имя}: связанная программа на знаке ${и}\n      рабочий слой: ${наша.slice(и, и + 110)}\n      второе мнение: ${ждём.slice(и, и + 110)}`,
      )
      continue
    }
    const ждёмБеды = бедыЭталона(беды)
    if (JSON.stringify(нашиБеды) !== JSON.stringify(ждёмБеды)) {
      расхождения.push(
        `${вход.имя}: диагностики\n      рабочий слой: ${JSON.stringify(нашиБеды).slice(0, 220)}\n      второе мнение: ${JSON.stringify(ждёмБеды).slice(0, 220)}`,
      )
    }
  }
  return { всего: корпус.length, расхождения, диагностик, объявлений }
}

test("второе мнение на JavaScript сходится со слоем связывания ПОБАЙТОВО на всём корпусе", async () => {
  const { всего, расхождения, диагностик, объявлений } = await сверить()
  console.log(`  связывание: программ ${всего}, объявлений ${объявлений}, диагностик ${диагностик}, расхождений ${расхождения.length}`)
  assert.deepEqual(расхождения.slice(0, 3), [], `расхождений ${расхождения.length} из ${всего}`)
  assert.ok(всего >= 230, `программ всего ${всего} — корпус усох`)
  assert.ok(объявлений >= 20_000, `объявлений всего ${объявлений} — сверять почти нечего`)
  assert.ok(диагностик >= 10, `диагностик всего ${диагностик} — половина слоя не сверяется`)
})

