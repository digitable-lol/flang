/** Близнец с подменённым текстом — копия в памяти, файл на диске не трогается. */
async function испорченныйБлизнец(что, чем) {
  const исходник = readFileSync(файл, "utf8")
  const испорчено = исходник.replace(что, чем)
  assert.notEqual(испорчено, исходник, `подмена «${что}» не применилась — изъятие ничего не проверяет`)
  const { diagnostics: _д, ...связано } = await linkProgram(файл, испорчено, parse)
  return связано
}

