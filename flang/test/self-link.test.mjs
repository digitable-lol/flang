/** Читалка текстов для дурного набора: чего нет в наборе, того нет и на диске. */
const читалка = (файлы) => async (путь) => (Object.hasOwn(файлы, путь) ? файлы[путь] : readFile(путь, "utf8"))

/**
 * Один вход корпуса: имя, входной файл и читалка текстов.
 *
 * Дурные наборы читаются из памяти, программы дерева — с диска. Читалка одна и
 * та же у обеих сторон: разойдись они, сверка сравнивала бы разные программы.
 */
const КОРПУС = []
for (const путь of [...файлыКорпуса(join(корень, "flang")), ...файлыКорпуса(join(корень, "examples"))].sort()) {
  КОРПУС.push({ имя: путь.slice(корень.length + 1), вход: путь, тексту, дурной: false })
}
/* Каждому набору — свой каталог, и это не украшение. Пути здесь ключи: по ним
   разбор кладётся в кэш, по ним связывание отличает файлы друг от друга. Дай
   двум наборам один `/в/опора.flang` — и второй получил бы разбор первого, а
   сверка сравнивала бы две разные программы и краснела бы на ровном месте.
   Импорты внутри наборов относительные, поэтому переезд каталога их не трогает. */
for (const [номер, [имя, файлы]] of Object.entries(ДУРНЫЕ).entries()) {
  const свои = Object.fromEntries(Object.entries(файлы).map(([путь, текст]) => [путь.replace("/в/", `/в/${номер}/`), текст]))
  КОРПУС.push({
    имя: `дурной набор — ${имя}`,
    вход: ГЛАВНЫЙ.replace("/в/", `/в/${номер}/`),
    тексту: (путь) => {
      if (!Object.hasOwn(свои, путь)) throw new Error(`ENOENT: ${путь}`)
      return свои[путь]
    },
    файлы: свои,
    дурной: true,
  })
}

