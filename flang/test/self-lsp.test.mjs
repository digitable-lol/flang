/* ─────────────────── побайтовая сверка с эталоном ─────────────────── */

async function прогнать(случаи) {
  const итог = { сверено: 0, сообщений: 0, поручений: 0, беды: [] }
  for (const { имя, файлы, сообщения } of случаи) {
    const состояние = пара(файлы ?? {})
    for (const сообщение of сообщения) {
      let ответ
      try {
        ответ = await подать(состояние, сообщение)
      } catch (ошибка) {
        итог.беды.push(`${имя} :: ${сообщение.method}: слой на flang упал — ${ошибка.message}`)
        break
      }
      итог.сверено += 1
      итог.сообщений += ответ.сверено ?? 0
      if (ответ.беда !== undefined) итог.беды.push(`${имя} :: ${сообщение.method}: ${ответ.беда}`)
    }
    итог.поручений += состояние.поручений
  }
  return итог
}

test("сервер на flang отвечает эталону знак в знак: весь корпус обещаний", async (t) => {
  const итог = await прогнать(КОРПУС)
  assert.deepEqual(итог.беды.slice(0, 6), [])
  assert.ok(итог.сверено >= 40, `сверено всего ${итог.сверено} сообщений`)
  assert.ok(итог.поручений > 0, "ни одной проверки не поручено — сверка сравнивает не то")
  t.diagnostic(`сверено сообщений: ${итог.сверено}, исходящих: ${итог.сообщений}, поручений проверки: ${итог.поручений}`)
})

