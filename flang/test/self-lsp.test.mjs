/**
 * Языковой сервер flang, написанный на самом flang — `flang/self/lsp.flang`.
 *
 * Проверка здесь ровно та же, какой проверены все близнецы до него, и другой
 * быть не может: ПОБАЙТОВАЯ СВЕРКА С ЭТАЛОНОМ. Одна и та же последовательность
 * сообщений JSON-RPC подаётся в `flang/src/lsp.mjs` и в слой на flang, и после
 * каждого сообщения сверяется ВЕСЬ поток исходящего — сообщение за сообщением,
 * знак в знак.
 *
 * Сверяется НАПЕЧАТАННЫЙ вид, а не «эквивалентный JSON». Порядок ключей в
 * ответе LSP — часть договора с редактором: `JSON.stringify` эталона его
 * сохраняет, и близнец обязан сохранить тот же. Поэтому левая сторона сверки —
 * `JSON.stringify(отправленное)`, правая — строка, которую близнец построил
 * «Печатью значения». Совпасть они должны байтом.
 *
 * ЧТО СВЕРЯЕТСЯ ВМЕСТЕ С ТЕКСТОМ:
 *
 *   1. ПОРЯДОК сообщений. Диагностика, ушедшая в журнал, стоит ПЕРЕД
 *      публикацией, а ответ на запрос — ПОСЛЕ всех публикаций, потому что у
 *      эталона `await вызвать(...)` заканчивается раньше, чем уходит ответ.
 *      Список сравнивается целиком, а не по вхождению.
 *   2. ЧИСЛО сообщений. Лишняя публикация — расхождение; пропавшая — тоже.
 *   3. ВЫХОД. `exit` у эталона зовёт `process.exit(код)`; у близнеца это поле
 *      итога. Код сверяется отдельно: 0 после `shutdown`, 1 без него.
 *
 * ЧЕГО СВЕРКА НЕ ДЕЛАЕТ МОЛЧА. Разбор со связыванием (`checkSource`), имя
 * посчитанного типа (`typeName`) и перевод адреса в путь отданы ХОЗЯИНУ —
 * почему именно они, разобрано в шапке `flang/self/lsp.flang`. Хозяин здесь —
 * этот тест, и он ОДИН И ТОТ ЖЕ для обеих сторон: эталон зовёт `checkSource`
 * сам, близнец — через поручение, и получают они ответ одной и той же функции.
 * Разойтись на этом нельзя, а вот пропустить работу — можно, поэтому отдельная
 * проверка требует, чтобы поручений было ровно столько, сколько документов
 * проверено.
 *
 * И проверка самой проверки: последний блок портит по одной ветке слоя на flang
 * и требует, чтобы сверка покраснела на НАСТОЯЩЕМ запросе корпуса. Сверка,
 * которая не умеет краснеть, хуже отсутствующей.
 *
 * Запуск: node --test flang/test/self-lsp.test.mjs
 */
