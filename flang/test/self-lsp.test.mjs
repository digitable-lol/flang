const КАТАЛОГ = "/tmp/flang-lsp-сверка"
const адресом = (имя) => кАдресу(join(КАТАЛОГ, имя))
const путём = (имя) => resolve(join(КАТАЛОГ, имя))

/**
 * Два сервера, идущие в ногу, и один общий «диск».
 *
 * Диск общий нарочно: сервер ничего не записывает, а читает обе стороны через
 * одну и ту же функцию — иначе сверка ловила бы разницу дисков, а не разницу
 * серверов.
 */
function пара(файлы = {}) {
  const диск = new Map(Object.entries(файлы).map(([имя, текст]) => [путём(имя), текст]))
  const отправленные = []
  const выходы = []
  const состояние = {
    диск,
    отправленные,
    выходы,
    поручений: 0,
    эталон: createServer({
      send: (сообщение) => отправленные.push(сообщение),
      readFile: async (путь) => {
        if (!диск.has(путь)) throw new Error(`ENOENT: no such file or directory, open '${путь}'`)
        return диск.get(путь)
      },
      exit: (код) => выходы.push(код),
    }),
    близнец: зов("Новый сервер", {}),
  }
  return состояние
}

/** Поручение хозяину: та же `checkSource`, какой пользуется эталон. */
async function исполнить(состояние, путь, текст, сервер) {
  состояние.поручений += 1
  const открытые = зов("Открытые тексты", { "с": сервер })
  const тексты = new Map([[путь, текст]])
  const чтение = async (кого) => {
    const полный = resolve(кого)
    const открытый = открытые.find((о) => о["путь"] === полный)
    const найдено = открытый !== undefined ? открытый["текст"] : состояние.диск.get(полный)
    if (найдено === undefined) throw new Error(`ENOENT: no such file or directory, open '${полный}'`)
    тексты.set(полный, найдено)
    return найдено
  }

  let итог = null
  let сорвалось = false
  let беда = ""
  try {
    итог = await checkSource(путь, текст, { readFile: чтение })
  } catch (ошибка) {
    сорвалось = true
    беда = ошибка instanceof Error ? ошибка.message : String(ошибка)
  }

  const диагностики = сорвалось ? [] : (итог.diagnostics ?? [])
  const пути = new Set([...тексты.keys()])
  for (const д of диагностики) if (typeof д?.span?.file === "string") пути.add(д.span.file)

  return {
    "сорвалось": сорвалось,
    "беда": беда,
    "есть программа": !сорвалось && итог.program !== null,
    "программа": значение(сорвалось || итог.program === null ? undefined : итог.program),
    "диагностики": диагностики.map(вДиагностику),
    "тотальные": сорвалось ? [] : [...(итог.total ?? new Set())],
    "подписи": сорвалось ? [] : вПодписи(итог.signatures),
    "тексты": [...тексты.entries()].map(([путь, текст]) => ({ "путь": путь, "текст": текст })),
    "адреса": [...пути].map((путь) => ({ "путь": путь, "адрес": кАдресу(путь) })),
  }
}

/**
 * Одно сообщение в оба сервера. Возвращает описание первого расхождения или
 * пустой объект.
 */
async function подать(состояние, сообщение) {
  состояние.отправленные.length = 0
  состояние.выходы.length = 0
  await состояние.эталон.receive(сообщение)
  const ждём = состояние.отправленные.map((м) => JSON.stringify(м))

  let итог = зов("Принять", { "с": состояние.близнец, "м": вСообщение(сообщение) })
  let витков = 0
  while (итог["ждёт"] === true) {
    витков += 1
    if (витков > 64) return { беда: "поручения проверки не кончаются" }
    const проверка = await исполнить(состояние, итог["путь"], итог["текст"], итог["сервер"])
    итог = зов("Принять проверенное", { "и": итог, "п": проверка })
  }
  состояние.близнец = итог["сервер"]
  const наши = итог["исходящие"]

  if (наши.length !== ждём.length) {
    return { беда: `исходящих ${наши.length} ≠ ${ждём.length}: ${JSON.stringify(наши)} ≠ ${JSON.stringify(ждём)}` }
  }
  for (let индекс = 0; индекс < ждём.length; индекс += 1) {
    if (наши[индекс] !== ждём[индекс]) {
      return { беда: `сообщение ${индекс}: ${наши[индекс]} ≠ ${ждём[индекс]}` }
    }
  }
  const нашВыход = итог["выход"] === true ? [итог["код выхода"]] : []
  if (JSON.stringify(нашВыход) !== JSON.stringify(состояние.выходы)) {
    return { беда: `выход ${JSON.stringify(нашВыход)} ≠ ${JSON.stringify(состояние.выходы)}` }
  }
  return { сверено: ждём.length }
}

