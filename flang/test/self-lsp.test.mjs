/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-types.test.mjs`, — иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/* ─────────────────── адреса и пути: то, что отдано хозяину ─────────────── */

const кПути = (uri) => {
  try {
    return typeof uri === "string" && uri.startsWith("file:") ? resolve(fileURLToPath(uri)) : null
  } catch {
    return null
  }
}
const кАдресу = (путь) => pathToFileURL(путь).href

/** Разобранное сообщение JSON-RPC в том виде, в каком его читает слой на flang. */
function вСообщение(сообщение) {
  const параметры = сообщение.params ?? {}
  const документ = параметры.textDocument ?? {}
  const адрес = документ.uri
  const путь = адрес === undefined ? null : кПути(адрес)
  const позиция = параметры.position
  return {
    "метод": typeof сообщение.method === "string" ? сообщение.method : "",
    "есть номер": сообщение.id !== undefined && сообщение.id !== null,
    "номер": typeof сообщение.id === "number" ? сообщение.id : 0,
    "адрес": адрес ?? "",
    "есть адрес": адрес !== undefined,
    "путь": путь ?? "",
    "есть путь": путь !== null,
    "текст": документ.text ?? "",
    "есть текст": документ.text !== undefined,
    "версия": документ.version ?? 0,
    "есть версия": документ.version !== undefined,
    "правки": (параметры.contentChanges ?? []).map((к) => ({
      "есть область": к?.range !== undefined,
      "текст": к?.text ?? "",
      "есть текст": к?.text !== undefined,
    })),
    "строка": позиция?.line ?? 0,
    "столбец": позиция?.character ?? 0,
    "есть место": позиция !== undefined && позиция !== null,
  }
}

/** Диагностика ядра в том виде, в каком её читает слой на flang. */
const вДиагностику = (д) => ({
  "код": typeof д?.code === "string" ? д.code : "",
  "есть код": typeof д?.code === "string",
  "уровень": typeof д?.severity === "string" ? д.severity : "",
  "сообщение": д?.message ?? "",
  "есть строка": typeof д?.span?.line === "number",
  "строка": typeof д?.span?.line === "number" ? д.span.line : 0,
  "столбец": typeof д?.span?.column === "number" ? д.span.column : 0,
  "есть столбец": typeof д?.span?.column === "number",
  "файл": д?.span?.file ?? "",
  "есть файл": д?.span?.file !== undefined,
})

/** Подпись: имена типов печатает `typeName` эталона — так же, как у эталона. */
const вПодписи = (сигнатуры) =>
  [...(сигнатуры ?? new Map()).entries()].map(([имя, сигнатура]) => ({
    "имя": имя,
    "параметры": (сигнатура.params ?? []).map((п) => ({ "имя": п.name, "тип": typeName(п.type) })),
    "возвращает": typeName(сигнатура.returns),
  }))

