/**
 * Обязательства: рабочий слой на flang против второго мнения на JavaScript.
 *
 * ── Кто здесь кому эталон ───────────────────────────────────────────────────
 * Отношение перевёрнуто, и это не редактура. Обязательства в рабочем пути
 * считает `flang/self/obligations.flang` — его зовёт `flang check` через
 * `flang/src/self.mjs`. Реализация на JavaScript (`flang/src/obligations.mjs`)
 * в рабочем пути больше не считает ничего и живёт ТОЛЬКО здесь, в проверках,
 * как вторая независимая реализация.
 *
 * Зачем она нужна после переключения: неподвижная точка доказывает
 * СОГЛАСОВАННОСТЬ, а не правильность. Компилятор с устойчивой ошибкой
 * воспроизведёт её сам с собой идеально и не заметит. Ловит такое ровно одно —
 * вторая реализация, написанная порознь по той же спецификации. Пока она
 * сходится с рабочим слоем побайтово, у каждого ответа есть независимый
 * свидетель.
 *
 * ── Что здесь сверяется и почему критерий именно такой ──────────────────────
 * Проверка одна и она дифференциальная: на КАЖДОЙ программе дерева ответ
 * рабочего слоя обязан совпасть с ответом второго мнения ПОБАЙТОВО —
 * `JSON.stringify` обоих до знака, до ключа и до порядка ключей.
 *
 * Слабее критерий делать нельзя, и довод не общий, а про этот самый слой.
 * Обязательство — ДАННЫЕ, которые читает ядро: `goal`, `bind`, `vars`,
 * `hypotheses`, `forall`. Ошибись близнец в одном поле — и ядро получило бы
 * другую цель, честно свело бы её и честно сказало «доказано» о том, чего автор
 * не обещал. Сверка «столько же обязательств» этого не увидела бы вовсе.
 *
 * Порядок ключей сверяется наравне с содержимым по той же причине, по которой
 * он сверяется у принципа индукции (`self-proof-initial.test.mjs`): ответ уходит
 * в JSON, JSON читают инструменты, и разошедшийся порядок — это разошедшийся
 * формат.
 *
 * ── Из чего корпус ──────────────────────────────────────────────────────────
 *   1. ВСЕ программы дерева, какие грузятся: `flang/**` и `examples/**`. Здесь
 *      лежат настоящие постусловия, настоящие теоремы и настоящие меры.
 *   2. ДУРНЫЕ программы под каждый из семи кодов отказа. Без них половина слоя
 *      сверялась бы вхолостую: в дереве нет ни одной программы, где теорема
 *      доказывает не то, что обещает функция, — и не должно быть.
 *
 * ── Подделка ────────────────────────────────────────────────────────────────
 * Программа, пытающаяся протащить через связку ложь, обязана быть отвергнута
 * рабочим слоем ТЕМ ЖЕ КОДОМ и С ТЕМ ЖЕ ТЕКСТОМ, что и вторым мнением.
 * Отвергнуть по другой причине — это расхождение, а не успех: код уезжает в
 * инструмент, а текст к автору доказательства.
 *
 * ── Изъятие: сверка обязана уметь краснеть ──────────────────────────────────
 * Ломается КУСОК В САМОМ РАБОЧЕМ СЛОЕ — исходник читается с диска, один кусок
 * подменяется текстом, подменённый близнец связывается заново. Сверка обязана
 * назвать расхождение. Ломается копия в памяти, не файл: правка ради теста,
 * оставшаяся в дереве, — это тот самый тест, который не умеет краснеть.
 */
