/**
 * Парсер языка flang, написанный на самом flang — `flang/self/parser.flang`.
 *
 * Главная проверка здесь одна и она побайтовая: для каждого исходника
 * репозитория AST, построенный парсером на flang и напечатанный `«Печать
 * значения»` из `flang/core/json.flang`, обязан совпасть со строкой, которую
 * даёт `JSON.stringify(parse(исходник))` эталонного `flang/src/parser.mjs`.
 * Не «эквивалентный AST», а тот же байт: только это доказывает, что из него
 * соберётся ровно та же программа — включая порядок ключей, отсутствие
 * необязательных полей и места узлов.
 *
 * Корпус — три набора:
 *
 *   • все `.flang` репозитория (`flang/stdlib`, `flang/core`,
 *     `flang/examples/leetcode`, `flang/self`), то есть поверхность языка;
 *   • все `.fts` репозитория — они разбираются тем же парсером и покрывают
 *     наследие FTS: утилиты, морфизмы, теоремы, файлы-функторы и старую
 *     скобочную поверхность, которой в `.flang` нет ни одной;
 *   • краевые случаи и фаззинг с зафиксированным сидом.
 *
 * Отказы сверяются так же, как AST: эталон бросает исключение, парсер на flang
 * возвращает беду значением, и сравниваются код, текст сообщения и место
 * (строка и столбец). Расхождение в диагностике — такое же расхождение, как
 * расхождение в AST.
 */
import assert from "node:assert/strict"
import { readdirSync, readFileSync, statSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { createRuntime, evaluate } from "../src/interpret.mjs"
import { tokenize } from "../src/lexer.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const файл = fileURLToPath(new URL("../self/parser.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")

/* Свой разбор — чтобы знать, какие функции объявлены именно здесь, а какие
   приехали из лексера и печати JSON. Типы и тотальность считаются по связанной
   программе: без импорта имена соседних модулей остались бы несвязанными. */
const свой = parse(исходник, "self/parser.flang")
const связано = await linkProgram(файл, исходник, parse)
const { diagnostics: диагностикиСвязывания, ...программа } = связано
const типы = checkTypes(программа)
const тотальность = checkTotality(программа)

/**
 * Лимит шагов поднят до ста пятидесяти миллионов. Самый большой исходник
 * репозитория (`flang/self/parser.flang`, около 28 000 токенов) вместе с
 * лексером укладывается между пятьюдесятью и ста миллионами; запас взят
 * полуторакратный. Лимит здесь не формальность: он проверяет, что разбор
 * остался линейным по числу токенов, а не свалился в квадрат — поток разложен
 * пачками именно ради этого.
 *
 * Глубина поднята вдвое против стандартной: рекурсивный спуск вкладывается на
 * каждое `пусть` и на каждую ветку, а хвостовые вызовы глубины не занимают.
 */
const ШАГИ = { maxSteps: 150_000_000, maxDepth: 20_000 }
const среда = createRuntime(программа, ШАГИ)
const вызвать = (имя, аргументы) => среда.call(имя, аргументы)
const разобрать = (текст, внешние = []) => вызвать("Разбор исходника", { исходник: текст, внешние })
const напечатать = (узел) => вызвать("Печать значения", { значение: узел })

/* ─────────────────────────── слой: программа на flang ───────────────────── */

test("parser.flang: разбор даёт контракт SPEC, раздел 5", () => {
  assert.equal(свой.flang, 1)
  assert.equal(свой.module, "Парсер flang")
  assert.ok(Array.isArray(свой.functions))
  assert.ok(свой.functions.length > 300, `функций всего ${свой.functions.length}`)
  /* Детерминированность: повторный разбор даёт побайтово тот же AST. */
  assert.equal(JSON.stringify(parse(исходник, "self/parser.flang")), JSON.stringify(свой))
})

test("parser.flang: связывание с лексером и печатью JSON без диагностик", () => {
  assert.deepEqual(диагностикиСвязывания, [])
})

test("parser.flang: типы без диагностик", () => {
  assert.deepEqual(типы.diagnostics, [])
})

test("parser.flang: тотальность без диагностик", () => {
  assert.deepEqual(тотальность.diagnostics, [])
})

test("parser.flang: каждая объявленная тотальной функция доказана тотальной", () => {
  for (const функция of свой.functions) {
    if (функция.total !== true) continue
    assert.ok(тотальность.total.has(функция.name), `«${функция.name}» объявлена тотальной, но не доказана`)
  }
})

test("parser.flang: примеры всех функций сходятся", () => {
  let счёт = 0
  for (const функция of программа.functions) {
    for (const пример of функция.examples ?? []) {
      счёт += 1
      const получено = evaluate(программа, функция.name, пример.args, ШАГИ)
      assert.deepEqual(получено, пример.expected, `«${функция.name}» / «${пример.name}»`)
    }
  }
  assert.ok(счёт >= 100, `примеров всего ${счёт}`)
})

/* ─────────────────────── дифференциальная сверка с образцом ──────────────── */

/**
 * Сверка одного текста. Возвращает описание первого расхождения или null.
 * Отказ образца — тоже поведение: сверяются код, сообщение и место.
 */
function расхождение(текст) {
  let эталон = null
  let отказ = null
  try {
    эталон = JSON.stringify(parse(текст, "проверка.flang"))
  } catch (ошибка) {
    отказ = ошибка.diagnostics?.[0] ?? { code: "?", message: String(ошибка?.message) }
  }
  const итог = разобрать(текст)
  const беды = итог["диагностики"]
  if (отказ !== null) {
    if (беды.length === 0) return `образец отказал (${отказ.code}: ${отказ.message}), парсер на flang — нет`
    const ждём = [отказ.code, отказ.message, отказ.span?.line ?? 0, отказ.span?.column ?? 0]
    const есть = [беды[0]["код"], беды[0]["сообщение"], беды[0]["строка"], беды[0]["столбец"]]
    return JSON.stringify(ждём) === JSON.stringify(есть)
      ? null
      : `диагностика ${JSON.stringify(есть)} ≠ ${JSON.stringify(ждём)}`
  }
  if (беды.length > 0) return `парсер на flang отказал там, где образец разобрал: ${JSON.stringify(беды[0])}`
  const наше = напечатать(итог["программа"])
  if (наше === эталон) return null
  let место = 0
  while (место < Math.min(наше.length, эталон.length) && наше[место] === эталон[место]) место += 1
  return `AST разошёлся на байте ${место}:\n  есть: ${наше.slice(Math.max(0, место - 60), место + 90)}\n  ждём: ${эталон.slice(Math.max(0, место - 60), место + 90)}`
}

/** Файлы с нужным расширением: каталог целиком, вместе с подкаталогами. */
function файлы(каталог, расширение) {
  const найдено = []
  for (const запись of readdirSync(`${корень}${каталог}`)) {
    const путь = `${каталог}/${запись}`
    if (statSync(`${корень}${путь}`).isDirectory()) найдено.push(...файлы(путь, расширение))
    else if (запись.endsWith(расширение)) найдено.push(путь)
  }
  return найдено.sort()
}

const исходникиFlang = ["flang/stdlib", "flang/core", "flang/examples/leetcode", "flang/self"].flatMap((каталог) =>
  файлы(каталог, ".flang"),
)

test("каждый .flang репозитория даёт побайтово тот же AST, что и образец", () => {
  assert.ok(исходникиFlang.length >= 30, `файлов всего ${исходникиFlang.length}`)
  for (const путь of исходникиFlang) {
    const беда = расхождение(readFileSync(`${корень}${путь}`, "utf8"))
    assert.equal(беда, null, `${путь}: ${беда}`)
  }
})

test("собственный исходник парсера разбирается им же — побайтово", () => {
  assert.ok(исходникиFlang.includes("flang/self/parser.flang"))
  assert.equal(расхождение(исходник), null)
})

/**
 * Наследие FTS: `.flang` его не содержит ни в одном файле, поэтому утилиты,
 * морфизмы, теоремы, файлы-функторы и скобочная поверхность проверяются на
 * моделях `.fts` — их разбирает тот же `parser.mjs`.
 */
const исходникиFts = ["examples", "tools", "web", "editors"].flatMap((каталог) => файлы(каталог, ".fts"))

test("каждая модель .fts репозитория даёт побайтово тот же AST, что и образец", () => {
  assert.ok(исходникиFts.length >= 40, `моделей всего ${исходникиFts.length}`)
  for (const путь of исходникиFts) {
    const беда = расхождение(readFileSync(`${корень}${путь}`, "utf8"))
    assert.equal(беда, null, `${путь}: ${беда}`)
  }
})

test("корпус .fts действительно покрывает все конструкции наследия", () => {
  const виды = new Set()
  for (const путь of исходникиFts) {
    let программа
    try {
      программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    } catch {
      continue
    }
    for (const узел of программа.legacy ?? []) виды.add(узел.construct)
  }
  for (const вид of ["utility", "morphism", "theorem", "functorFile", "bracedDocument", "moduleHeader", "category"]) {
    assert.ok(виды.has(вид), `конструкция «${вид}» в корпусе не встретилась`)
  }
})

