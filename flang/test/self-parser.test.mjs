  const обойти = (узел) => {
    if (Array.isArray(узел)) return узел.forEach(обойти)
    if (узел === null || typeof узел !== "object") return
    if (typeof узел.kind === "string") виды.add(узел.kind)
    for (const значение of Object.values(узел)) обойти(значение)
  }
  for (const путь of [...исходникиFlang, ...исходникиFts]) обойти(parse(readFileSync(`${корень}${путь}`, "utf8"), путь))
