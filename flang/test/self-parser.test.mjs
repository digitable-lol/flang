/**
 * Парсер языка flang, написанный на самом flang — `flang/self/parser.flang`.
 *
 * Главная проверка здесь одна и она побайтовая: для каждого исходника
 * репозитория AST, построенный парсером на flang и напечатанный `«Печать
 * значения»` из `flang/core/json.flang`, обязан совпасть со строкой, которую
 * даёт `JSON.stringify(parse(исходник))` эталонного `flang/src/parser.mjs`.
 * Не «эквивалентный AST», а тот же байт: только это доказывает, что из него
 * соберётся ровно та же программа — включая порядок ключей, отсутствие
 * необязательных полей и места узлов.
 *
 * Корпус — три набора:
 *
 *   • все `.flang` репозитория (`flang/stdlib`, `flang/core`,
 *     `flang/examples/leetcode`, `flang/self`), то есть поверхность языка;
 *   • все `.fts` репозитория — они разбираются тем же парсером и покрывают
 *     наследие FTS: утилиты, морфизмы, теоремы, файлы-функторы и старую
 *     скобочную поверхность, которой в `.flang` нет ни одной;
 *   • краевые случаи и фаззинг с зафиксированным сидом.
 *
 * Отказы сверяются так же, как AST: эталон бросает исключение, парсер на flang
 * возвращает беду значением, и сравниваются код, текст сообщения и место
 * (строка и столбец). Расхождение в диагностике — такое же расхождение, как
 * расхождение в AST.
 */
import assert from "node:assert/strict"
