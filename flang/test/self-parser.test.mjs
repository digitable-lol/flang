test("имя не связано и имя неоднозначно — коды FLANG_UNKNOWN_NAME и FLANG_AMBIGUOUS_NAME", () => {
  const нет = беда("функция «Ф»\n  возвращает число\n  х\n")
  assert.equal(нет["код"], "FLANG_UNKNOWN_NAME")
  /* Текст ЛЕЧАЩИЙ, а не только называющий болезнь (`work/types-diagnostics`):
     он говорит, чем имя вводят, и отдельно — что действия языка пишутся МЕЖДУ
     значениями. Ошибка «умножить 3.14 на р» приходит именно сюда, и без второй
     половины автор чинил бы имя вместо порядка слов. */
  assert.equal(
    нет["сообщение"],
    "имя «х» не связано: имя вводят 'принимает', 'пусть' или образец 'случай';"
      + " а действия языка ('плюс', 'минус', 'умножить на', 'делить на', 'остаток от')"
      + " пишутся МЕЖДУ значениями — «3.14 умножить на р», а не «умножить 3.14 на р»",
  )
  assert.equal(нет["строка"], 3)
  assert.equal(нет["столбец"], 3)

  const много = беда("функция «Ф»\n  принимает элемент: число, элементы: число\n  возвращает число\n  элементами\n")
  assert.equal(много["код"], "FLANG_AMBIGUOUS_NAME")
  assert.equal(много["сообщение"], "имя «элементами» подходит сразу нескольким связанным: «элемент», «элементы»")
})

