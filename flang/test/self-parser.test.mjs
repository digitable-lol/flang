  "функция ", "возвращает ", "число", "модуль ",
  /* Три слова функтора добавлены вместе с переводом данных на его объекте:
     `даёт` в списке стоял и раньше, а вот `функтор`, `объект` и `отображается в`
     — нет, и склейки, где `даёт` попадает ВНУТРЬ функтора, до сих пор не
     рождались ни разу. Ровно там теперь и проходит новая развилка разбора. */
  "функтор ", "объект ", "отображается в ", "поле ", "отображается в поле ",
