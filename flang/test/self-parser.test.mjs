/* ─────────────────────── дифференциальная сверка с образцом ──────────────── */

/**
 * Сверка одного текста. Возвращает описание первого расхождения или null.
 * Отказ образца — тоже поведение: сверяются код, сообщение и место.
 */
function расхождение(текст) {
  let свидетель = null
  let отказ = null
  try {
    свидетель = JSON.stringify(parse(текст, "проверка.flang"))
  } catch (ошибка) {
    отказ = ошибка.diagnostics?.[0] ?? { code: "?", message: String(ошибка?.message) }
  }
  const итог = разобрать(текст)
  const беды = итог["диагностики"]
  if (отказ !== null) {
    if (беды.length === 0) return `образец отказал (${отказ.code}: ${отказ.message}), парсер на flang — нет`
    const ждём = [отказ.code, отказ.message, отказ.span?.line ?? 0, отказ.span?.column ?? 0]
    const есть = [беды[0]["код"], беды[0]["сообщение"], беды[0]["строка"], беды[0]["столбец"]]
    return JSON.stringify(ждём) === JSON.stringify(есть)
      ? null
      : `диагностика ${JSON.stringify(есть)} ≠ ${JSON.stringify(ждём)}`
  }
  if (беды.length > 0) return `парсер на flang отказал там, где образец разобрал: ${JSON.stringify(беды[0])}`
  const наше = напечатать(итог["программа"])
  if (наше === свидетель) return null
  let место = 0
  while (место < Math.min(наше.length, свидетель.length) && наше[место] === свидетель[место]) место += 1
  return `AST разошёлся на байте ${место}:\n  есть: ${наше.slice(Math.max(0, место - 60), место + 90)}\n  ждём: ${свидетель.slice(Math.max(0, место - 60), место + 90)}`
}

/** Файлы с нужным расширением: каталог целиком, вместе с подкаталогами. */
function файлы(каталог, расширение) {
  const найдено = []
  for (const запись of readdirSync(`${корень}${каталог}`)) {
    const путь = `${каталог}/${запись}`
    if (statSync(`${корень}${путь}`).isDirectory()) найдено.push(...файлы(путь, расширение))
    else if (запись.endsWith(расширение)) найдено.push(путь)
  }
  return найдено.sort()
}

