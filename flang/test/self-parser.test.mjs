/** Первая беда: код, текст и место — или null, если разобралось. */
function бедаОбразца(текст) {
  try {
    parse(текст, "поверхность.flang")
  } catch (ошибка) {
    const беда = ошибка.diagnostics?.[0]
    return беда === undefined ? null : [беда.code, беда.message, беда.span?.line ?? 0, беда.span?.column ?? 0]
  }
  return null
}

function бедаЭталона(текст) {
  const беда = разобрать(текст)["диагностики"][0]
  return беда === undefined ? null : [беда["код"], беда["сообщение"], беда["строка"], беда["столбец"]]
}

test("диагностика эталона цитирует слова ТОЙ поверхности, на которой написан файл", () => {
  let нерусских = 0
  for (const [что, исходник] of ПОВЕРХНОСТИ_ДИАГНОСТИК) {
    const ждём = бедаОбразца(исходник)
    assert.notEqual(ждём, null, `${что}: образец не отказал — проверять нечего`)
    assert.deepEqual(бедаЭталона(исходник), ждём, что)
    /* Улика непустоты: запись, где цитировать нечего, ничего не стережёт.
       Считаются те, где сообщение образца отличается от русского, — то есть
       где слой и правда сработал. */
    if (что.startsWith("русская") === false) нерусских += 1
  }
  assert.ok(нерусских >= 15, `нерусских случаев всего ${нерусских}`)
})

test("обрезка настоящих нерусских файлов даёт те же отказы, что у образца", () => {
  const файлы = файлы_поверхностей()
  assert.ok(файлы.length >= 2, `файлов поверхностей всего ${файлы.length}`)
  let обрезок = 0
  let отказов = 0
  const красные = []
  for (const путь of файлы) {
    const строки = readFileSync(`${корень}${путь}`, "utf8").split("\n")
    for (let край = 1; край < строки.length; край += 1) {
      const текст = `${строки.slice(0, край).join("\n")}\n`
      обрезок += 1
      const ждём = бедаОбразца(текст)
      if (ждём !== null) отказов += 1
      const есть = бедаЭталона(текст)
      if (JSON.stringify(ждём) !== JSON.stringify(есть)) {
        красные.push(`${путь}:${край} ${JSON.stringify(есть)} ≠ ${JSON.stringify(ждём)}`)
      }
    }
  }
  assert.deepEqual(красные, [], `обрезок разошлось ${красные.length}`)
  /* Обрезка, которая ни разу не отказала, проверяла бы разбор, а не отказ. */
  assert.ok(отказов >= 80, `отказов всего ${отказов} из ${обрезок} обрезок`)
})

