import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const файл = fileURLToPath(new URL("../self/parser.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")

/* Свой разбор — чтобы знать, какие функции объявлены именно здесь, а какие
   приехали из лексера и печати JSON. Типы и тотальность считаются по связанной
   программе: без импорта имена соседних модулей остались бы несвязанными. */
const свой = parse(исходник, "self/parser.flang")
const связано = await linkProgram(файл, исходник, parse)
const { diagnostics: диагностикиСвязывания, ...программа } = связано
const типы = checkTypes(программа)
const тотальность = checkTotality(программа)

/**
 * Лимит шагов поднят до ста пятидесяти миллионов. Самый большой исходник
 * репозитория (`flang/self/parser.flang`, около 28 000 токенов) вместе с
 * лексером укладывается между пятьюдесятью и ста миллионами; запас взят
 * полуторакратный. Лимит здесь не формальность: он проверяет, что разбор
 * остался линейным по числу токенов, а не свалился в квадрат — поток разложен
 * пачками именно ради этого.
 *
 * Глубина поднята вдвое против стандартной: рекурсивный спуск вкладывается на
 * каждое `пусть` и на каждую ветку, а хвостовые вызовы глубины не занимают.
 */
const ШАГИ = { maxSteps: 150_000_000, maxDepth: 20_000 }
const среда = createRuntime(программа, ШАГИ)
const вызвать = (имя, аргументы) => среда.call(имя, аргументы)
const разобрать = (текст, внешние = []) => вызвать("Разбор исходника", { исходник: текст, внешние })
const напечатать = (узел) => вызвать("Печать значения", { значение: узел })

