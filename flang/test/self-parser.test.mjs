test("сверка идёт по всем видам узлов, а не по паре выражений", () => {
  const виды = new Set()
  const обойти = (узел) => {
    if (Array.isArray(узел)) return узел.forEach(обойти)
    if (узел === null || typeof узел !== "object") return
    if (typeof узел.kind === "string") виды.add(узел.kind)
    for (const значение of Object.values(узел)) обойти(значение)
  }
  for (const путь of [...исходникиFlang, ...исходникиFts]) обойти(parse(readFileSync(`${корень}${путь}`, "utf8"), путь))
  for (const текст of краевые) {
    try {
      обойти(parse(текст, "краевой.flang"))
    } catch {
      /* Отказ образца видов узлов не добавляет — он их и не строит. */
    }
  }
  for (const вид of [
    "record", "sum", "alias", "literal", "var", "field", "let", "if", "call", "binary",
    "construct", "list", "match", "fold", "map", "filter", "builtin", "empty", "cons", "variant", "any",
    "number", "string", "flag", "named", "nothing", "ftsLegacy",
  ]) {
    assert.ok(виды.has(вид), `узел «${вид}» в корпусе не встретился`)
  }
})
