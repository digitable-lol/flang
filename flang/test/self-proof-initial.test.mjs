test("сигнатура функтора совпала с эталоном ПОБАЙТОВО на всех суммах", () => {
  /* Читается с объявления буквально: сумма по вариантам, произведение по полям,
     `X` на месте каждого поля, чей тип — сам объявляемый тип. Выбирать не из
     чего, значит и расходиться негде — а если разойдётся, то в том самом месте,
     где решается, что считать допущением индукции. */
  let входов = 0
  for (const [название, сумма] of СУММЫ) {
    входов += 1
    const эталон = сигнатураФунктора(сумма)
    const свой = изЗначения(вызвать("Сигнатура функтора", { сумма: значение(сумма) }))
    assert.equal(JSON.stringify(свой), побайтово(эталон), `сигнатура «${название}» разошлась`)
  }
  /* Граница поля `X` названа прямо, и здесь она проверена: `дети: список «Куст»`
     местом `X` НЕ является, потому что за списком стоит другой функтор. */
  const куст = сигнатураФунктора(СУММЫ[3][1])
  assert.deepEqual(куст.variants[1].recursive, [], "поле под списком стало местом X — это уже другой функтор")
  assert.equal(куст.base, 2, "у «Куста» обе посылки обязаны быть базой")
  console.log(`  сигнатура функтора: ${входов} сумм, расхождений 0`)
})

