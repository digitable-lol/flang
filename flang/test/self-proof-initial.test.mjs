/**
 * Начальная алгебра на самом flang: близнец `flang/proof/initial.mjs`.
 *
 * ── Критерий и почему он побайтовый ─────────────────────────────────────────
 * Всё, что строит этот слой, — ДАННЫЕ: сигнатура функтора, конструктор образца,
 * аргументы вызова на части, подстановка. Значит сверять их можно так же, как
 * сверяется разобранное дерево (`self-parser.test.mjs`) и напечатанный C
 * (`self-emit-c.test.mjs`) — ПОБАЙТОВО, через `JSON.stringify`, а не «на
 * эквивалентность».
 *
 * Слабее критерий делать нельзя, и здесь довод даже жёстче, чем у печати.
 * Заключение посылки и допущение индукции — это то, ЧТО ядру предстоит выводить.
 * Ошибись близнец в порядке двух подстановок, и он получил бы допущение о
 * другом значении: сведение честно отвергло бы правду или честно вывело бы
 * ложь, и оба раза — «по правилам». Поэтому сверяется вся запись целиком, до
 * ключа и до порядка ключей.
 *
 * ── Чего эта сверка не доказывает ───────────────────────────────────────────
 * Состоятельности ядра она не доказывает. Совпадение двух реализаций ловит
 * ошибку в одной из них; общая ошибка проекта останется общей. Поэтому о
 * результате говорится ровно с той силой, какая у него есть: «перекрёстно
 * сверено на N входах», а не «принцип верен».
 */
