/**
 * Ветви разбора по эталону — записаны здесь заново, потому что наружу эталон их
 * не выводит. Правило читается прямо с его шапки, а не пересказывается по коду.
 */
function ветвиЭталона(функция, параметр) {
  const { нормализовать } = эталонныйReduce
  const тело = нормализовать(функция?.body ?? null)
  if (тело?.kind !== "match") return []
  if (тело.target?.kind !== "var" || тело.target.name !== параметр) return []
  return (тело.cases ?? [])
    .filter((случай) => случай?.pattern?.kind === "variant")
    .map((случай) => случай.pattern.name)
}

