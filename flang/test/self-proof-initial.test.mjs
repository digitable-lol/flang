/**
 * Все входы `принципИндукции`, какие есть в корпусе: сумма, функция,
 * обязательство и узел `индукция по …`.
 *
 * Берутся они у тех же `obligations`, у которых их берёт ядро. Второго сбора
 * здесь нет и быть не должно: он был бы вторым ответом на тот же вопрос.
 */
function входыИзПрограммы(программа) {
  const итог = obligations(программа)
  const суммы = new Map((программа.types ?? []).filter((т) => т?.kind === "sum").map((т) => [т.name, т]))
  const функции = new Map((программа.functions ?? []).map((ф) => [ф.name, ф]))

  const собрано = []
  for (const обязательство of итог.obligations ?? []) {
    const индукция = обязательство.proof?.induction
    if (индукция === undefined || индукция === null) continue
    const переменная = (обязательство.vars ?? []).find((п) => п.name === индукция.param)
    const имяТипа = переменная?.type?.kind === "named" ? переменная.type.name : null
    const сумма = имяТипа === null ? undefined : суммы.get(имяТипа)
    if (сумма === undefined) continue
    собрано.push({
      имя: `${обязательство.of} / ${обязательство.name}`,
      сумма,
      функция: функции.get(обязательство.of),
      обязательство,
      индукция,
    })
  }
  return собрано
}

async function входыПринципа(путь, исходник = null) {
  const связано = await linkProgram(путь, исходник ?? readFileSync(путь, "utf8"), parse)
  const { diagnostics: _д, ...программа } = связано
  return входыИзПрограммы(программа)
}

/** Принцип близнеца для одного входа — «Значение» обратно в обычный JSON. */
