test("конструктор образца собран так же, как у эталона", () => {
  /* Уравнение образца, записанное значением: переменная индукции РАВНА
     конструктору с полями, названными образцом. Поле, которое образец не
     назвал, получает имя самого поля — иначе конструктор был бы дыркой. */
  let входов = 0
  for (const [название, сумма] of СУММЫ) {
    const функтор = сигнатураФунктора(сумма)
    for (const вариантФунктора of функтор.variants) {
      for (const связи of [{}, { хвост: "х" }, { меньшие: "л", большие: "п" }, { голова: "г", хвост: "х" }]) {
        входов += 1
        /* Эталон строит конструктор внутренней функцией; здесь он собран той же
           формулой, что и в нём, чтобы сверялось построение, а не обёртка. */
        const поля = {}
        for (const п of [...вариантФунктора.recursive, ...вариантФунктора.carried.map((к) => к.name)]) {
          поля[п] = { kind: "var", name: связи[п] ?? п }
        }
        const эталон = { kind: "construct", variant: вариантФунктора.name, fields: поля }
        const свой = изЗначения(
          вызвать("Конструктор", { вариант: значение(вариантФунктора), связи: значение(связи) }),
        )
        assert.equal(JSON.stringify(свой), побайтово(эталон), `конструктор «${название}»/«${вариантФунктора.name}»`)
      }
    }
  }
  console.log(`  конструктор образца: ${входов} входов, расхождений 0`)
})

test("аргументы вызова на части собраны так же, как у эталона", () => {
  /* Переменная индукции заменяется частью, остальные параметры остаются собой:
     допущение говорит о том же вызове с теми же прочими аргументами, иначе оно
     было бы допущением о другой функции. */
  const функции = [
    ["один параметр", { params: [{ name: "стопка" }] }],
    ["два параметра", { params: [{ name: "стопка" }, { name: "порог" }] }],
    ["параметра индукции нет", { params: [{ name: "иной" }] }],
    ["параметров нет вовсе", { params: [] }],
  ]
  let входов = 0
  for (const [название, функция] of функции) {
    for (const параметр of ["стопка", "иной"]) {
      входов += 1
      const эталон = (функция.params ?? []).map((п) =>
        п.name === параметр ? { kind: "var", name: "х" } : { kind: "var", name: п.name },
      )
      const свой = изЗначения(
        вызвать("Аргументы на части", { функция: значение(функция), имя: параметр, часть: "х" }),
      )
      assert.equal(JSON.stringify(свой), побайтово(эталон), `аргументы «${название}» по «${параметр}»`)
    }
  }
  console.log(`  аргументы на части: ${входов} входов, расхождений 0`)
})

