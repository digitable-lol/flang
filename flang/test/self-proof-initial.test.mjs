/* ─────────────────── перевод AST в значения flang и обратно ─────────────────── */

const вариант = (имя, поля = {}) => ({ variant: имя, fields: поля })
const ничто = вариант("Значение скаляра", { скаляр: вариант("Скаляр ничто") })

function значение(узел) {
  if (узел === null || узел === undefined) return ничто
  if (typeof узел === "string") return вариант("Значение скаляра", { скаляр: вариант("Скаляр строка", { значение: узел }) })
  if (typeof узел === "number") return вариант("Значение скаляра", { скаляр: вариант("Скаляр число", { значение: узел }) })
  if (typeof узел === "boolean") return вариант("Значение скаляра", { скаляр: вариант("Скаляр признак", { значение: узел }) })
  if (Array.isArray(узел)) return вариант("Значение списка", { элементы: узел.map(значение) })
  if (typeof узел === "object") {
    return вариант("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  throw new Error(`нечего переводить: ${String(узел)}`)
}

/**
 * «Значение» обратно в обычный JSON — чтобы сравнивать с эталоном одной строкой.
 *
 * Перевод механический и ничего не решает: вариант читается по имени, поля — по
 * порядку, в каком они лежат. Порядок здесь и есть предмет сверки, поэтому он
 * сохраняется, а не сортируется.
 */
function изЗначения(узел) {
  /* Функция языка вправе вернуть `список «Значение»`, а не одно «Значение»:
     тогда наружу приходит обычный массив, и разбирать в нём нечего, кроме
     элементов. */
  if (Array.isArray(узел)) return узел.map(изЗначения)
  const имяВарианта = узел?.variant ?? узел?.constructor?.name
  const поля = узел?.fields ?? узел
  if (имяВарианта === "Значение скаляра") {
    const скаляр = поля.скаляр
    const вид = скаляр?.variant ?? скаляр?.constructor?.name
    if (вид === "Скаляр ничто") return null
    return (скаляр.fields ?? скаляр).значение
  }
  if (имяВарианта === "Значение списка") return (поля.элементы ?? []).map(изЗначения)
  if (имяВарианта === "Значение записи") {
    const собрано = {}
    for (const поле of поля.поля ?? []) собрано[поле.ключ] = изЗначения(поле.значение)
    return собрано
  }
  throw new Error(`не «Значение»: ${JSON.stringify(узел)?.slice(0, 120)}`)
}

/**
 * Побайтовое сличение: `JSON.stringify` обоих ответов обязан совпасть.
 *
 * `undefined` эталона приводится к `null` тем же `JSON.parse(JSON.stringify(…))`,
 * каким его приводит всякая передача данных наружу: ключа со значением
 * `undefined` в JSON не бывает, и требовать от близнеца воспроизвести то, чего
 * в обмене нет, значило бы сверять не обмен, а внутренности JavaScript.
 */
const побайтово = (эталон) => JSON.stringify(JSON.parse(JSON.stringify(эталон)))

