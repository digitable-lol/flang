const ЗАМЕНЫ = [
  ["пусто", {}],
  ["х на литерал", { х: лит(7) }],
  ["х на вызов", { х: вызов("Высота", [имя("м")]) }],
  ["х и у сразу", { х: лит(1), у: лит(2) }],
  ["на имя себя же", { х: имя("х") }],
  ["имя, которого нет", { "нет такого": лит(0) }],
]

/** Замены в форму близнеца: список записей вместо словаря. */
const заменыБлизнеца = (замены, переименовать) =>
  Object.entries(замены).map(([ключ, узел]) => ({
    имя: ключ,
    узел: значение(переименовать ? узел : узел),
    переименовать,
  }))

test("подстановка выражений совпала с эталоном ПОБАЙТОВО, захвата нет", () => {
  let входов = 0
  const расхождения = []
  for (const [названиеВыражения, выражение] of ВЫРАЖЕНИЯ) {
    for (const [названиеЗамен, замены] of ЗАМЕНЫ) {
      входов += 1
      const эталон = подставить(выражение, замены)
      const свой = изЗначения(
        вызвать("Подставить", { выражение: значение(выражение), замены: заменыБлизнеца(замены, false) }),
      )
      if (JSON.stringify(свой) !== побайтово(эталон)) {
        расхождения.push(`«${названиеВыражения}» при «${названиеЗамен}»`)
      }
    }
  }
  console.log(`  подстановка выражений: ${входов} входов, совпало ${входов - расхождения.length}`)
  assert.deepEqual(расхождения, [], `расхождений ${расхождения.length} из ${входов}`)

  /* Изъятие смысла проверки: если бы связыватели не вычёркивали имя, вот эти
     два входа дали бы ДРУГОЙ ответ. Проверяется, что они и вправду разные. */
  const затеняющее = ВЫРАЖЕНИЯ.find(([н]) => н === "пусть, ЗАТЕНЯЮЩЕЕ х")[1]
  const незатеняющее = ВЫРАЖЕНИЯ.find(([н]) => н === "пусть, НЕ затеняющее")[1]
  const подЗатенением = подставить(затеняющее, { х: лит(7) })
  assert.equal(подЗатенением.in.left.kind, "var", "подстановка вошла под связыватель — это захват имени")
  assert.equal(подставить(незатеняющее, { х: лит(7) }).in.right.kind, "literal", "подстановка не дошла до свободного имени")
})

test("переименование имён совпало с эталоном ПОБАЙТОВО и сохраняет прочие ключи", () => {
  /* `подставитьИмена` меняет у узла ОДНО поле `name` и оставляет прочие ключи,
     в том числе место в исходнике. Здесь это и проверяется: узел с `span`
     обязан вернуться со своим `span`. */
  const карты = [
    ["пусто", new Map()],
    ["х в левое", new Map([["х", "левое"]])],
    ["х и у сразу", new Map([["х", "левое"], ["у", "правое"]])],
    ["имя, которого нет", new Map([["нет такого", "неважно"]])],
  ]
  let входов = 0
  const расхождения = []
  for (const [названиеВыражения, выражение] of ВЫРАЖЕНИЯ) {
    for (const [названиеКарты, карта] of карты) {
      входов += 1
      const эталон = подставитьИмена(выражение, карта)
      const замены = [...карта.entries()].map(([ключ, новое]) => ({
        имя: ключ,
        узел: значение(новое),
        переименовать: true,
      }))
      const свой = изЗначения(вызвать("Подставить имена", { выражение: значение(выражение), замены }))
      if (JSON.stringify(свой) !== побайтово(эталон)) {
        расхождения.push(`«${названиеВыражения}» при «${названиеКарты}»`)
      }
    }
  }
  console.log(`  переименование имён: ${входов} входов, совпало ${входов - расхождения.length}`)
  assert.deepEqual(расхождения, [], `расхождений ${расхождения.length} из ${входов}`)

  /* Место в исходнике переживает переименование — иначе отказ ядра показывал бы
     автору не ту строку. */
  const сМестом = подставитьИмена({ kind: "var", name: "х", span: МЕСТО }, new Map([["х", "левое"]]))
  assert.deepEqual(сМестом, { kind: "var", name: "левое", span: МЕСТО })
})

