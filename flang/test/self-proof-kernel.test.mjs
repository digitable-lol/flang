/**
 * Посылки принципа индукции для программы — те самые заключения и допущения,
 * которые ядро сводит, когда автор пишет `по предположению`.
 *
 * Строятся ТЕМ ЖЕ `принципИндукции`, каким их строит ядро: второе построение
 * здесь было бы вторым ответом на тот же вопрос, и разошлись бы они молча.
 */
async function посылкиПрограммы(путь, исходник) {
  const связано = await linkProgram(путь, исходник, parse)
  const { diagnostics: _д, ...программа } = связано
  const итог = obligations(программа)
  const суммы = new Map((программа.types ?? []).filter((т) => т?.kind === "sum").map((т) => [т.name, т]))
  const функции = new Map((программа.functions ?? []).map((ф) => [ф.name, ф]))

  const собрано = []
  for (const обязательство of итог.obligations ?? []) {
    const индукция = обязательство.proof?.induction
    if (индукция === undefined || индукция === null) continue
    const переменная = (обязательство.vars ?? []).find((п) => п.name === индукция.param)
    const имяТипа = переменная?.type?.kind === "named" ? переменная.type.name : null
    const сумма = имяТипа === null ? undefined : суммы.get(имяТипа)
    if (сумма === undefined) continue
    const принцип = принципИндукции({
      сумма,
      функция: функции.get(обязательство.of),
      обязательство,
      индукция,
    })
    for (const посылка of принцип.premises) {
      if (посылка.conclusion === null) continue
      собрано.push(
        утверждение(
          `${обязательство.name} / ${посылка.kind === "base" ? "база" : "шаг"} «${посылка.variant}»`,
          посылка.conclusion,
          посылка.hypotheses,
        ),
      )
    }
  }
  return собрано
}

