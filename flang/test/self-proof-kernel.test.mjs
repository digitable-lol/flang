  /* 1. ТОЛЬКО ТОТАЛЬНОЕ. Отличается одно поле — `total`. */
  const тотальная = вердиктСОпределениями(конструктор, допущенияВысоты, [], new Map([["Высота", ВЫСОТА]]))
  const обычная = вердиктСОпределениями(конструктор, допущенияВысоты, [], new Map([["Высота", { ...ВЫСОТА, total: false }]]))
  assert.deepEqual(тотальная, вердиктЭталона(конструктор, допущенияВысоты, [], new Map([["Высота", ВЫСОТА]])))
  assert.equal(тотальная.ok, true, "тотальная не развернулась — проба сломана")
  assert.deepEqual(тотальная.unfolded, [`Высота: ${РАЗВЁРТКА.constructor}`])
  assert.equal(обычная.ok, false, "обычная функция развёрнута — обещания завершения при ней нет")
  assert.deepEqual(обычная.unfolded, [])

  /* 2. ДВА ВИДА РАЗВЁРТКИ, СПИСОК ЗАКРЫТ. Плоское определение против того же с
     одним дописанным вызовом. */
  const плоская = цель("gte", вызов("Глубже", [глубина("л"), глубина("п")]), лит(0))
  const допущенияГлубины = [допущение(цель("gte", глубина("л"), лит(0))), допущение(цель("gte", глубина("п"), лит(0)))]
  const сПлоским = вердиктСОпределениями(плоская, допущенияГлубины, [], new Map([["Глубже", ГЛУБЖЕ]]))
  assert.equal(сПлоским.ok, true, `плоское определение не развернулось: ${сПлоским.why}`)
  assert.equal(сПлоским.rule, ПРАВИЛО.nonneg, "правило старое: выбор из неотрицательных")
  assert.deepEqual(сПлоским.unfolded, [`Глубже: ${РАЗВЁРТКА.flat}`])
  const сВызовом = вердиктСОпределениями(плоская, допущенияГлубины, [], new Map([["Глубже", { ...ГЛУБЖЕ, body: { ...ГЛУБЖЕ.body, then: вызов("Ещё", []) } }]]))
  assert.equal(сВызовом.ok, false, "определение с вызовом развернулось — второй ограничитель снят")

  /* 3. НАЗВАННЫЙ ПРЕДЕЛ. Снимите его — и эта проверка не покраснеет, а ЗАВИСНЕТ;
     поэтому проверяется, что предел достигнут, назван числом и НАПЕЧАТАН. */
  const растущая = цель("gte", вызов("Растущая", [звено({ хвост: имя("к") })]), лит(0))
  const сПределом = вердиктСОпределениями(растущая, [], [], new Map([["Растущая", РАСТУЩАЯ]]))
  assert.deepEqual(сПределом, вердиктЭталона(растущая, [], [], new Map([["Растущая", РАСТУЩАЯ]])))
  assert.equal(сПределом.ok, false, "ядро приняло то, чего не досчитало")
  assert.equal(сПределом.unfolded.length, ПРЕДЕЛ_РАЗВЁРТКИ, "развёрток не ровно столько, сколько позволено")
  assert.match(сПределом.why, /Предел развёртки \(32\) достигнут/u, `отказ молчит о пределе: ${сПределом.why}`)

  /* 4. ЗАХВАТ ИМЕНИ. Та же функция, тот же вызов, отличается одно имя аргумента. */
  const определенияВзять = new Map([["Взять", ВЗЯТЬ]])
