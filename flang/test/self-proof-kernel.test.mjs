test("вердикты близнеца и эталона совпали на порождённом корпусе утверждений", () => {
  /* Перебор, а не подбор руками: каждое выражение словаря становится левой
     частью обеих целей («не меньше 0» и «равно»), и каждая цель проверяется при
     каждом наборе допущений. Число входов печатается — сверка, чей охват нельзя
     перепроверить, даёт ложную уверенность. */
  const корпус = []
  for (const [имяВыражения, выражение] of ВЫРАЖЕНИЯ) {
    for (const [имяДопущений, допущения] of НАБОРЫ_ДОПУЩЕНИЙ) {
      корпус.push(
        утверждение(`«${имяВыражения}» не меньше 0 при «${имяДопущений}»`, цель("gte", выражение, лит(0)), допущения),
      )
      корпус.push(
        утверждение(`«${имяВыражения}» не меньше -0 при «${имяДопущений}»`, цель("gte", выражение, лит(-0)), допущения),
      )
      корпус.push(
        утверждение(`«${имяВыражения}» не меньше 1 при «${имяДопущений}»`, цель("gte", выражение, лит(1)), допущения),
      )
      for (const [имяПравого, правое] of ВЫРАЖЕНИЯ) {
        корпус.push(
          утверждение(
            `«${имяВыражения}» равно «${имяПравого}» при «${имяДопущений}»`,
            цель("eq", выражение, правое),
            допущения,
          ),
        )
      }
      корпус.push(утверждение(`«${имяВыражения}» больше 0 при «${имяДопущений}»`, цель("gt", выражение, лит(0)), допущения))
      корпус.push(утверждение(`само «${имяВыражения}» при «${имяДопущений}»`, выражение, допущения))
    }
  }

  const { всего, расхождения, принято } = сверить(корпус)
  console.log(
    `  сверка сведения: утверждений ${всего}, вердикты совпали ${всего - расхождения.length},`
      + ` разошлись ${расхождения.length}; принято эталоном ${принято}`,
  )
  assert.deepEqual(расхождения.slice(0, 5), [], `расхождений ${расхождения.length} из ${всего}`)
  assert.ok(всего >= 7888, `утверждений в корпусе всего ${всего} — охват сверки ужался`)
  /* Корпус обязан содержать и принятые, и отвергнутые. Сверка, в которой всё
     отвергается, сошлась бы и у ядра, отвергающего вообще всё. */
  assert.ok(принято > 0, "эталон не принял ни одного утверждения — корпус ничего не проверяет")
  assert.ok(принято < всего, "эталон принял всё — корпус не содержит ни одной лжи")
})

