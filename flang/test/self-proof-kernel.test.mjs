  const структурой = new Set((итог.structures ?? []).map((з) => з.from))
  for (const имяФункции of ["Одинаковы", "Списки одинаковы", "Поля сходятся", "Поле сходится", "Есть известное"]) {
    assert.ok(структурой.has(имяФункции), `«${имяФункции}» больше не убывает структурно`)
  }
