/** «Значение» обратно в обычный JSON — обратная сторона `значение`. */
function изЗначения(узел) {
  if (Array.isArray(узел)) return узел.map(изЗначения)
  const имяВарианта = узел?.variant ?? узел?.constructor?.name
  const поля = узел?.fields ?? узел
  if (имяВарианта === "Значение скаляра") {
    const скаляр = поля.скаляр
    const вид = скаляр?.variant ?? скаляр?.constructor?.name
    if (вид === "Скаляр ничто") return null
    return (скаляр.fields ?? скаляр).значение
  }
  if (имяВарианта === "Значение списка") return (поля.элементы ?? []).map(изЗначения)
  if (имяВарианта === "Значение записи") {
    const собрано = {}
    for (const поле of поля.поля ?? []) собрано[поле.ключ] = изЗначения(поле.значение)
    return собрано
  }
  throw new Error(`не «Значение»: ${JSON.stringify(узел)?.slice(0, 120)}`)
}

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод узла AST в «Значение» из `flang/core/json.flang`: он
   повторяет форму и ничего не решает сам, иначе тест проверял бы себя. Ключ со
   значением `undefined` пропускается ровно там, где его пропустил бы
   `JSON.stringify`: ключа нет — это не «ключ со значением ничто». */
const вариант = (имя, поля = {}) => ({ variant: имя, fields: поля })
const ничто = вариант("Значение скаляра", { скаляр: вариант("Скаляр ничто") })

function значение(узел) {
  if (узел === null || узел === undefined) return ничто
  if (typeof узел === "string") return вариант("Значение скаляра", { скаляр: вариант("Скаляр строка", { значение: узел }) })
  if (typeof узел === "number") return вариант("Значение скаляра", { скаляр: вариант("Скаляр число", { значение: узел }) })
  if (typeof узел === "boolean") return вариант("Значение скаляра", { скаляр: вариант("Скаляр признак", { значение: узел }) })
  if (Array.isArray(узел)) return вариант("Значение списка", { элементы: узел.map(значение) })
  if (typeof узел === "object") {
    return вариант("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  throw new Error(`нечего переводить: ${String(узел)}`)
}

/* Вердикт близнеца — в ту же форму, в какой его отдаёт эталон. Строки вместо
   `null` у близнеца потому, что `null` в flang нет; сведение к одной форме
   стоит здесь, а не в близнеце, чтобы близнец повторял эталон, а не тест. */
const вердиктом = (итог) => ({
  ok: итог.принято === true,
  rule: итог.правило === "" ? null : итог.правило,
  why: итог.причина === "" ? null : итог.причина,
  unfolded: итог.развёрнуто ?? [],
})

function вердиктБлизнеца(заключение, допущения) {
  return вердиктом(вызвать("Свести", {
    заключение: значение(заключение),
    допущения: (допущения ?? []).map(значение),
  }))
}

const вердиктЭталона = (заключение, допущения, объявления = [], определения = null) => {
  const итог = свести(заключение, допущения, объявления ?? [], определения)
  return { ok: итог.ok, rule: итог.rule ?? null, why: итог.why ?? null, unfolded: итог.unfolded ?? [] }
}

/** Одно утверждение корпуса: цель, допущения при ней и имя для отказа.
 *
 * Объявления и определения приезжают тем же способом, каким они приезжают в
 * ядро, — данными, а не догадкой: пустой список объявлений и `null` определений
 * означают «ядру их не дали», и это ровно те умолчания, что у эталона.
 */
const утверждение = (имя, заключение, допущения = [], объявления = [], определения = null) =>
  ({ имя, заключение, допущения, объявления, определения })

/**
 * Сверить корпус утверждений. Возвращает числа, а не «да/нет»: сверка, чей
 * охват нельзя перепроверить, даёт ложную уверенность.
 */
function сверить(корпус, { близнец: свестиБлизнецом = вердиктБлизнеца } = {}) {
  const расхождения = []
  let принято = 0
  let развёрнуто = 0
  for (const { имя, заключение, допущения, объявления, определения } of корпус) {
    const эталон = вердиктЭталона(заключение, допущения, объявления, определения)
    const свой = свестиБлизнецом(заключение, допущения, объявления, определения)
    if (эталон.ok) принято += 1
    развёрнуто += эталон.unfolded.length
    /* Отчёт о развёртке сверяется наравне с вердиктом. Без него близнец, который
       развернул ЧУЖОЕ тело и получил тот же ответ по другой причине, прошёл бы
       молча — а автору доказательства сказано было бы неправду о том, что ядро
       прочитало. */
    const разошлось = свой.ok !== эталон.ok || свой.rule !== эталон.rule || свой.why !== эталон.why
      || свой.unfolded.join("|") !== эталон.unfolded.join("|")
    if (разошлось) {
      расхождения.push(
        `${имя}: эталон {ok:${эталон.ok}, rule:${эталон.rule}, unfolded:[${эталон.unfolded}],`
          + ` why:${(эталон.why ?? "").slice(0, 60)}}`
          + ` ↔ близнец {ok:${свой.ok}, rule:${свой.rule}, unfolded:[${свой.unfolded}],`
          + ` why:${(свой.why ?? "").slice(0, 60)}}`,
      )
    }
  }
  return { всего: корпус.length, расхождения, принято, развёрнуто }
}

