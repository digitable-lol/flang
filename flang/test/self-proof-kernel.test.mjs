/**
 * Ядро доказательства на самом flang: близнец `flang/proof/reduce.mjs`.
 *
 * ── Что здесь сверяется и почему критерий именно такой ──────────────────────
 * Проверка одна и она дифференциальная: на КАЖДОМ утверждении корпуса вердикт
 * близнеца обязан совпасть с вердиктом эталона — принято или отвергнуто, ТЕМ ЖЕ
 * ПРАВИЛОМ и с ТЕМ ЖЕ ТЕКСТОМ причины, знак в знак.
 *
 * Слабее критерий делать нельзя, и довод тот же, каким держится побайтовая
 * сверка печати (`self-emit-c.test.mjs`): совпадения одних только
 * «принято/отвергнуто» мало. Два ядра могут принять одно и то же РАЗНЫМИ
 * правилами — например, тождество там, где эталон вывел неотрицательность, — и
 * разойтись на первом же утверждении, которого в корпусе не было. Имя правила и
 * текст причины уезжают в отказ ядра к автору доказательства; разойдись они, и
 * автор чинил бы не то, что сломано.
 *
 * ── Из чего корпус ──────────────────────────────────────────────────────────
 *   1. ПОРОЖДЁННЫЕ утверждения. Перебор целей над словарём выражений, в котором
 *      нарочно стоит всё, на чём ядро могло бы соврать: оба нуля, не-число, обе
 *      бесконечности, вычитание и умножение (правила для них НЕТ и не будет),
 *      `пусть`, `если`, разбор известного конструктора, вызов функции.
 *   2. НАСТОЯЩИЕ посылки корпуса. Заключения и допущения, порождённые
 *      `flang/proof/initial.mjs` по объявлениям сумм и телам функций из
 *      `flang/proof/examples/*.flang`. Это те самые термы, на которых сегодня
 *      стоит слово «доказано» в ведомости.
 *   3. ПОДДЕЛКИ. Те же доказательства при испорченном теле функции.
 *
 * ── Обратная проверка Карри–Ховарда ─────────────────────────────────────────
 * Подделка обязана быть отвергнута близнецом ТАК ЖЕ, как эталоном. Без этой
 * половины сверка говорила бы только «два ядра согласны», а согласиться они
 * могут и на лжи. Проверок две: тело шага, вычитающее вместо сложения
 * (правило 1), и функция, объявленная тождественной и таковой не являющаяся
 * (правило 2).
 *
 * ── Изъятие: сверка обязана уметь краснеть ──────────────────────────────────
 * Проверка, которая не умеет находить расхождение, ничего не сверяет. Здесь
 * ломается ПРАВИЛО В САМОМ БЛИЗНЕЦЕ — исходник читается с диска, одно правило
 * подменяется текстом, и подменённый близнец разбирается заново. Сверка обязана
 * назвать расхождение поимённо, а подделка — перестать отвергаться. Ломается
 * копия в памяти, не файл: правка ради теста, оставшаяся в дереве, — это тот
 * самый тест, который не умеет краснеть.
 */
