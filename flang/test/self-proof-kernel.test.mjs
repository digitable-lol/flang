test("аксиом у близнеца ноль — их неоткуда взять", () => {
  /* Список аксиом эталона пуст намеренно: числа flang — IEEE-754, где «х плюс 1
     не меньше х» неправда при |х| от 2⁵³. У близнеца аксиом нет и быть не может
     по построению: он не объявляет ни одного факта, а только читает данные ему.
     Проверка держит это тем, что в исходнике нет слова «аксиома» вовсе —
     появится, и вместе с ним обязано появиться обоснование. */
  const исходник = readFileSync(файл, "utf8")
  assert.ok(!/аксиом/iu.test(исходник.replace(/^.*Аксиом ноль.*$/gmu, "")), "в близнеце завелась аксиома")
})

