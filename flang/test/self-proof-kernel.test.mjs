/**
 * Тот же третий источник, записанный здесь ЗАНОВО и независимо.
 *
 * Записан заново намеренно — тем же приёмом, каким в `proof-kernel-twin.test.mjs`
 * заново записан свод вердиктов: взять правило у близнеца значило бы сверять
 * близнеца с самим собой. Правило читается прямо с довода, а не по коду:
 * объявление `нат` — это факт «имя не меньше 0», и кладётся он только на ИМЯ.
 *
 * Эталона с тремя источниками в дереве пока НЕТ: он лежит на ветках
 * `work/proof-types`, `work/proof-ceiling` и `work/kernel-unfold`, ни одна из
 * которых не влита. Поэтому здесь сверяется не «близнец против эталона», а
 * «близнец против правила», и сила у этого результата меньше — ровно настолько,
 * насколько «два прочтения правила сошлись» слабее, чем «две реализации
 * сошлись». Как только ветка приедет в `main`, сверка выше накроет и её.
 */
const ИМЕНА_НАТ_ЗАНОВО = ["нат", "натуральное", "nat", "naturo", "自然数"]

function известноеПоТипуЗаново(объявления) {
  return (объявления ?? [])
    .filter((о) => typeof о?.name === "string" && о?.type?.kind === "named" && ИМЕНА_НАТ_ЗАНОВО.includes(о.type.name))
    .map((о) => имя(о.name))
}

/**
 * Вердикт правила 1 при ТРЁХ источниках — собранный здесь из частей эталона.
 *
 * Заново написано ровно то, что этой работой и добавилось: сборка списка
 * известного из объявлений. Нормализация и сама неотрицательность берутся у
 * эталона в дереве — они на всех трёх ветках одни и те же, и переписывать их
 * здесь значило бы завести третье прочтение того, что уже сверено выше.
 */
function вердиктПравилаЗаново(заключение, допущения, объявления) {
  const цельФормы = нормализовать(заключение)
  const факты = (допущения ?? []).map((д) => нормализовать(д?.claim ?? д))
  const ноль = (узел) => узел?.kind === "literal" && узел.value === 0
  if (!(цельФормы?.kind === "binary" && цельФормы.op === "gte" && ноль(цельФормы.right))) {
    /* Не цель правила 1 — за неё отвечает сверка с эталоном выше. */
    return null
  }
  const известные = [
    ...факты.filter((ф) => ф?.kind === "binary" && ф.op === "gte" && ноль(ф.right)).map((ф) => ф.left),
    ...известноеПоТипуЗаново(объявления),
  ]
  return неотрицательно(цельФормы.left, известные)
    ? { ok: true, rule: "неотрицательность по построению" }
    : { ok: false, rule: null }
}

/* Текст отказа с тремя источниками — процитирован с ветки знак в знак. Стоит
   здесь затем, чтобы правка близнеца не могла его тихо переписать. */
const ОТКАЗ_ПРИ_ТИПАХ =
  "неотрицательность по построению не проходит: выражение случая собрано не только из неотрицательного."
  + " Неотрицательны литерал не меньше нуля, терм с допущением «не меньше 0»,"
  + " имя, объявленное типом «нат», их сумма и выбор из них;"
  + " умножения и вычитания в этом списке нет и не будет"
  + " (в IEEE-754 «ноль умножить на бесконечность» даёт не число,"
  + " а разность двух натуральных отрицательна уже на 2 минус 3)"

function вердиктСОбъявлениями(заключение, допущения, объявления) {
  const итог = вызвать("Свести с объявлениями", {
    заключение: значение(заключение),
    допущения: (допущения ?? []).map(значение),
    объявления: (объявления ?? []).map(значение),
  })
  return {
    ok: итог.принято === true,
    rule: итог.правило === "" ? null : итог.правило,
    why: итог.причина === "" ? null : итог.причина,
  }
}

