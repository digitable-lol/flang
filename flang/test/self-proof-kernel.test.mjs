/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод узла AST в «Значение» из `flang/core/json.flang`: он
   повторяет форму и ничего не решает сам, иначе тест проверял бы себя. Ключ со
   значением `undefined` пропускается ровно там, где его пропустил бы
   `JSON.stringify`: ключа нет — это не «ключ со значением ничто». */
const вариант = (имя, поля = {}) => ({ variant: имя, fields: поля })
const ничто = вариант("Значение скаляра", { скаляр: вариант("Скаляр ничто") })

function значение(узел) {
  if (узел === null || узел === undefined) return ничто
  if (typeof узел === "string") return вариант("Значение скаляра", { скаляр: вариант("Скаляр строка", { значение: узел }) })
  if (typeof узел === "number") return вариант("Значение скаляра", { скаляр: вариант("Скаляр число", { значение: узел }) })
  if (typeof узел === "boolean") return вариант("Значение скаляра", { скаляр: вариант("Скаляр признак", { значение: узел }) })
  if (Array.isArray(узел)) return вариант("Значение списка", { элементы: узел.map(значение) })
  if (typeof узел === "object") {
    return вариант("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  throw new Error(`нечего переводить: ${String(узел)}`)
}

/* Вердикт близнеца — в ту же форму, в какой его отдаёт эталон. Строки вместо
   `null` у близнеца потому, что `null` в flang нет; сведение к одной форме
   стоит здесь, а не в близнеце, чтобы близнец повторял эталон, а не тест. */
function вердиктБлизнеца(заключение, допущения) {
  const итог = вызвать("Свести", {
    заключение: значение(заключение),
    допущения: (допущения ?? []).map(значение),
  })
  return {
    ok: итог.принято === true,
    rule: итог.правило === "" ? null : итог.правило,
    why: итог.причина === "" ? null : итог.причина,
  }
}

const вердиктЭталона = (заключение, допущения) => {
  const итог = свести(заключение, допущения)
  return { ok: итог.ok, rule: итог.rule ?? null, why: итог.why ?? null }
}

/** Одно утверждение корпуса: цель, допущения при ней и имя для отказа. */
const утверждение = (имя, заключение, допущения = []) => ({ имя, заключение, допущения })

/**
 * Сверить корпус утверждений. Возвращает числа, а не «да/нет»: сверка, чей
 * охват нельзя перепроверить, даёт ложную уверенность.
 */
function сверить(корпус, { близнец: свестиБлизнецом = вердиктБлизнеца } = {}) {
  const расхождения = []
  let принято = 0
  for (const { имя, заключение, допущения } of корпус) {
    const эталон = вердиктЭталона(заключение, допущения)
    const свой = свестиБлизнецом(заключение, допущения)
    if (эталон.ok) принято += 1
    if (свой.ok !== эталон.ok || свой.rule !== эталон.rule || свой.why !== эталон.why) {
      расхождения.push(
        `${имя}: эталон {ok:${эталон.ok}, rule:${эталон.rule}, why:${(эталон.why ?? "").slice(0, 60)}}`
          + ` ↔ близнец {ok:${свой.ok}, rule:${свой.rule}, why:${(свой.why ?? "").slice(0, 60)}}`,
      )
    }
  }
  return { всего: корпус.length, расхождения, принято }
}

/* ─────────────────── словарь выражений для перебора ─────────────────── */

