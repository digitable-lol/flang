/**
 * Посылки, порождённые БЛИЗНЕЦОМ начальной алгебры (`self/proof-initial.flang`),
 * а не эталоном.
 *
 * Зачем отдельно от сверки выше. Там посылки строит `принципИндукции` эталона, и
 * это правильно: сверять надо ОДНИ И ТЕ ЖЕ термы, иначе расхождение вердиктов
 * ничего не скажет о ядре. Но у такой сверки есть слепое пятно: она молчит о
 * том, работает ли цепочка ЦЕЛИКОМ НА FLANG. Здесь принцип строит близнец,
 * сводит его близнец, и ответ обязан совпасть с ответом двух эталонов на том же
 * входе. Это и есть «ядро проверяет доказательства само» — на том куске пути,
 * который уже перенесён.
 *
 * Пятно, которое эта проверка закрывает, не выдумано: поле `declarations` в
 * посылке близнец не строил вовсе, и сверка вердиктов его отсутствия НЕ ВИДЕЛА —
 * потому что термы ей давал эталон.
 */
async function посылкиОбоихЯдер(путь) {
  const связано = await linkProgram(путь, readFileSync(путь, "utf8"), parse)
  const { diagnostics: _д, ...программа } = связано
  const итог = obligations(программа)
  const суммы = new Map((программа.types ?? []).filter((т) => т?.kind === "sum").map((т) => [т.name, т]))
  const функции = new Map((программа.functions ?? []).map((ф) => [ф.name, ф]))
  const определения = new Map((программа.functions ?? []).map((ф) => [ф.name, ф]))

  const собрано = []
  for (const обязательство of итог.obligations ?? []) {
    const индукция = обязательство.proof?.induction
    if (индукция === undefined || индукция === null) continue
    const переменная = (обязательство.vars ?? []).find((п) => п.name === индукция.param)
    const имяТипа = переменная?.type?.kind === "named" ? переменная.type.name : null
    const сумма = имяТипа === null ? undefined : суммы.get(имяТипа)
    if (сумма === undefined) continue
    const вход = { сумма, функция: функции.get(обязательство.of), обязательство, индукция }
    const эталонныйПринцип = принципИндукции(вход)
    const принципБлизнеца = изЗначения(вызватьНачальную("Принцип индукции", {
      сумма: значение(вход.сумма),
      функция: значение(вход.функция),
      обязательство: значение(вход.обязательство),
      индукция: значение(вход.индукция),
    }))
    собрано.push({
      имя: `${обязательство.of} / ${обязательство.name}`,
      эталон: эталонныйПринцип,
      свой: принципБлизнеца,
      определения,
    })
  }
  return собрано
}

test("КРУГ ЗАМКНУТ: принцип от близнеца сводится близнецом и совпадает с двумя эталонами", async () => {
  /* Цепочка целиком на flang: объявление суммы → принцип индукции (близнец) →
     сведение заключения к допущениям (близнец). Рядом та же цепочка на
     JavaScript. Сверяется каждый вердикт каждой посылки — вместе с правилом,
     текстом отказа и отчётом о развёрнутом. */
  let посылок = 0
  let принято = 0
  const расхождения = []
  for (const имяФайла of ФАЙЛЫ_КОРПУСА) {
    for (const { имя: имяЦели, эталон, свой, определения } of await посылкиОбоихЯдер(примеры + имяФайла)) {
      const парами = Math.max(эталон.premises.length, свой.premises?.length ?? 0)
      assert.equal(эталон.premises.length, свой.premises?.length, `${имяЦели}: посылок разное число`)
      for (let и = 0; и < парами; и += 1) {
        const пЭ = эталон.premises[и]
        const пБ = свой.premises[и]
        if (пЭ.conclusion === null) continue
        посылок += 1
        const вЭ = вердиктЭталона(пЭ.conclusion, пЭ.hypotheses, пЭ.declarations, определения)
        const вБ = вердиктом(вызвать("Свести с определениями", {
          заключение: значение(пБ.conclusion),
          допущения: (пБ.hypotheses ?? []).map(значение),
          объявления: (пБ.declarations ?? []).map(значение),
          определения: [...определения.values()].map(значение),
        }))
        if (вЭ.ok) принято += 1
        const разошлось = вБ.ok !== вЭ.ok || вБ.rule !== вЭ.rule || вБ.why !== вЭ.why
          || вБ.unfolded.join("|") !== вЭ.unfolded.join("|")
        if (разошлось) {
          расхождения.push(
            `${имяЦели} / ${пЭ.kind} «${пЭ.variant}»: эталон {ok:${вЭ.ok}, rule:${вЭ.rule}}`
              + ` ↔ близнец {ok:${вБ.ok}, rule:${вБ.rule}}`,
          )
        }
      }
    }
  }
  console.log(`  круг на flang: посылок ${посылок}, совпало ${посылок - расхождения.length}, принято ${принято}`)
  assert.deepEqual(расхождения, [], `расхождений ${расхождения.length} из ${посылок}`)
  assert.ok(посылок >= 10, `посылок всего ${посылок} — корпус потерян`)
  assert.ok(принято > 0, "ни одна посылка не сводится — круг замкнут вхолостую")
})

