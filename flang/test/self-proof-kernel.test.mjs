/** Близнец с подменённым текстом — копия в памяти, файл на диске не трогается. */
function испорченныйБлизнец(что, чем) {
  const исходник = readFileSync(файл, "utf8")
  const испорчено = исходник.replace(что, чем)
  assert.notEqual(испорчено, исходник, `подмена «${что}» не применилась — изъятие ничего не проверяет`)
  const программа = parse(испорчено, "self/proof-kernel.flang")
  /* Импорты близнеца разрешает связывание; здесь берётся уже связанная
     программа, у которой подменено только тело одной функции. */
  return { исходник: испорчено, программа }
}

async function свестиИспорченным(испорчено, заключение, допущения) {
  const программа = await linkProgram(файл, испорчено, parse)
  const { diagnostics: _д, ...связано } = программа
  const итог = evaluate(
    связано,
    "Свести",
    { заключение: значение(заключение), допущения: (допущения ?? []).map(значение) },
    ШАГИ,
  )
  return {
    ok: итог.принято === true,
    rule: итог.правило === "" ? null : итог.правило,
    why: итог.причина === "" ? null : итог.причина,
  }
}

test("изъятие: сломанное правило неотрицательности ловится сверкой поимённо", async () => {
  /* Ломается ПРАВИЛО 1 в близнеце: вычитание объявляется таким же безопасным,
     как сложение. Это ровно та ложь, против которой список правил закрыт —
     «а минус б» при неотрицательных `а` и `б` ОТРИЦАТЕЛЕН. Сверка обязана
     назвать расхождение, а подделка — перестать отвергаться. */
  const { исходник } = испорченныйБлизнец(
    'если «Это двоичное» от «выражение» и "add"',
    'если (если «Это двоичное» от «выражение» и "add" то да иначе «Это двоичное» от «выражение» и "sub")',
  )

  /* Половина первая: подделка ПЕРЕСТАЁТ отвергаться. */
  const подделка = СТОПКА.replace("то («Высота» от х) плюс 1", "то («Высота» от х) минус 1")
  const шаг = await шагЗвена(подделка, примеры + "проба-изъятие.flang")
  const эталон = вердиктЭталона(шаг.заключение, шаг.допущения)
  const сломанный = await свестиИспорченным(исходник, шаг.заключение, шаг.допущения)
  assert.equal(эталон.ok, false, "эталон принял подделку — изъятие ничего не показывает")
  assert.equal(сломанный.ok, true, "сломанное правило не приняло подделку — подмена не сработала")

  /* Половина вторая: сверка НАЗЫВАЕТ расхождение, а не просто краснеет. */
  const корпус = [утверждение("подделка «Высота» минус 1", шаг.заключение, шаг.допущения)]
  const итог = сверить(корпус, {
    близнец: (заключение, допущения) => ({
      /* Синхронный обход невозможен внутри `сверить`, поэтому вердикт уже
         посчитан выше и подставляется здесь: сверяется тот же самый ответ. */
      ...сломанный,
      ...(заключение === шаг.заключение && допущения === шаг.допущения ? {} : {}),
    }),
  })
  assert.equal(итог.расхождения.length, 1, "сверка не увидела расхождения — значит она ничего не сверяет")
  assert.match(итог.расхождения[0], /подделка «Высота» минус 1/u)
  assert.match(итог.расхождения[0], /эталон \{ok:false/u)
  assert.match(итог.расхождения[0], /близнец \{ok:true/u)
})

test("изъятие: сломанное сличение минус нуля ловится сверкой", async () => {
  /* Второе изъятие — под ту ловушку, на которой в этом дереве за день попались
     трое. Числа сличает «Числа тождественны» через двойное «не меньше»; замени
     его на `равен` языка (то есть на `Object.is`), и `-0` перестанет быть нулём:
     цель «Е не меньше -0» уедет из правила 1 в «правила нет». Эталон при этом
     отвечает по-прежнему, потому что `-0 === 0`. */
  const { исходник } = испорченныйБлизнец(
    "  если «левое» не меньше «правое»\n    то «правое» не меньше «левое»\n    иначе нет",
    "  «левое» равен «правое»",
  )
  const заключение = цель("gte", вызов("Высота", [имя("х")]), лит(-0))
  const допущения = [допущение(цель("gte", вызов("Высота", [имя("х")]), лит(0)))]

  const эталон = вердиктЭталона(заключение, допущения)
  const целый = вердиктБлизнеца(заключение, допущения)
  const сломанный = await свестиИспорченным(исходник, заключение, допущения)
  assert.equal(эталон.ok, true, "эталон не вывел цель с минус нулём — проба сломана")
  assert.deepEqual(целый, эталон, "целый близнец разошёлся с эталоном на минус нуле")
  assert.notDeepEqual(сломанный, эталон, "подменённое сличение прошло бы сверку — сверка ничего не проверяет")
  assert.equal(сломанный.ok, false, "сломанное сличение всё равно вывело цель")
})
