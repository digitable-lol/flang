  const захват = цель("gte", вызов("Взять", [имя("с"), имя("г")]), лит(0))
  const сЧистым = вердиктСОпределениями(чистое, [допущение(цель("gte", имя("д"), лит(0)))], [], определенияВзять)
  const сЗахватом = вердиктСОпределениями(захват, [допущение(цель("gte", имя("г"), лит(0)))], [], определенияВзять)
  assert.deepEqual(сЧистым.unfolded, [`Взять: ${РАЗВЁРТКА.flat}`], "чистое имя не развернулось")
  assert.deepEqual(сЗахватом.unfolded, [], "имя захвачено образцом — а развёртка всё равно прошла")
  assert.deepEqual(сЗахватом, вердиктЭталона(захват, [допущение(цель("gte", имя("г"), лит(0)))], [], определенияВзять))
