/**
 * ВОСЬМОЙ ХОД У ЭТАЛОНА НА flang: подделки те же, что у свидетеля.
 *
 * ── Зачем отдельный файл, если подделки уже есть ────────────────────────────
 * `flang/test/proof-po-vyzovu.test.mjs` бьёт по СВИДЕТЕЛЮ `flang/src/proofterm.mjs`.
 * Здесь те же шесть программ едут в ЭТАЛОН `flang/self/proofterm.flang` — тот,
 * который останется, когда JavaScript выбросят. Перенос, у которого подделок нет,
 * — это перенос на бумаге: наполовину перенесённый ход отвечал бы «доказано» там,
 * где свидетель молчит, и заметить это было бы нечем.
 *
 * ── Что проверяется на каждой программе, и все три вопроса разные ───────────
 *   1. ОТВЕТ СОВПАЛ ПОБАЙТОВО. `JSON.stringify` обоих ядер — до знака, до ключа
 *      и до порядка ключей. Отвергнуть по ДРУГОЙ причине — это расхождение, а не
 *      успех: код отказа уезжает в инструмент, текст к человеку.
 *   2. ЛОЖЬ НЕ ДОКАЗАНА ЭТАЛОНОМ. Проверяется по его собственному ответу, а не
 *      по ответу свидетеля: сойдись оба на «доказано», пункт 1 был бы зелен, а
 *      ядро печатало бы ложь.
 *   3. ЛОЖЬ НАЗВАНА. Отказ этого хода МОЛЧАЛИВ по построению — путь «постусловие
 *      без теоремы» не отвергает, а не даёт вердикта вовсе, — поэтому у подделок
 *      1, 2, 4, 5, 6 кода отказа нет и быть не может. Улика у них другая и
 *      сильнее: ложь называет ПРОГОН, код `FLANG_PROPERTY` на выписанном входе.
 *      Код отказа есть ровно там, где ему место, — у подделки 3
 *      (`FLANG_PRECONDITION_CALL`), и его печатают оба ядра.
 *
 * ── И ПАРА К КАЖДОМУ ЗАПРЕТУ ────────────────────────────────────────────────
 * «Ход не берёт X» и «ход не работает вовсе» — разные утверждения, и без пары их
 * не различить. Поэтому при круге стоит «то же без круга», при неоплате — «та же
 * оплата снята», и обе пары эталон обязан ЗАКРЫТЬ. Снимите восьмой ход — и
 * покраснеют именно они, а не подделки.
 *
 * Запуск: node --test flang/test/self-proof-po-vyzovu.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { loadProgram, loadProgramFromSource } from "../bin/flang.mjs"
import { evaluate } from "../src/interpret.mjs"
import { obligations } from "../src/obligations.mjs"
import { checkProofs } from "../src/proofterm.mjs"

const эталон = await loadProgram(fileURLToPath(new URL("../self/proofterm.flang", import.meta.url)))
const ШАГИ = { maxSteps: 40_000_000, maxDepth: 10_000 }

/* ─── перевод дерева в «Значение» эталона и обратно ─── */

const вариант = (имя, поля = {}) => ({ variant: имя, fields: поля })
const ничто = вариант("Значение скаляра", { скаляр: вариант("Скаляр ничто") })

function значение(узел) {
  if (узел === null || узел === undefined) return ничто
  if (typeof узел === "string") return вариант("Значение скаляра", { скаляр: вариант("Скаляр строка", { значение: узел }) })
  if (typeof узел === "number") return вариант("Значение скаляра", { скаляр: вариант("Скаляр число", { значение: узел }) })
  if (typeof узел === "boolean") return вариант("Значение скаляра", { скаляр: вариант("Скаляр признак", { значение: узел }) })
  if (Array.isArray(узел)) return вариант("Значение списка", { элементы: узел.map(значение) })
  return вариант("Значение записи", {
    поля: Object.entries(узел)
      .filter(([, вложенное]) => вложенное !== undefined)
      .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
  })
}

function изЗначения(узел) {
  if (Array.isArray(узел)) return узел.map(изЗначения)
  const имяВарианта = узел?.variant ?? узел?.constructor?.name
  const поля = узел?.fields ?? узел
  if (имяВарианта === "Значение скаляра") {
    const скаляр = поля.скаляр
    const вид = скаляр?.variant ?? скаляр?.constructor?.name
    if (вид === "Скаляр ничто") return null
    return (скаляр.fields ?? скаляр).значение
  }
  if (имяВарианта === "Значение списка") return (поля.элементы ?? []).map(изЗначения)
  const собрано = {}
  for (const поле of поля.поля ?? []) собрано[поле.ключ] = изЗначения(поле.значение)
  return собрано
}

/**
 * Ответы ОБОИХ ядер на одной программе.
 *
 * Свидетелю уезжает КОПИЯ обязательств: он правит их на месте
 * (`обязательство.discharge = вердикт`), и эталон увидел бы чужой вердикт.
 * Примеров с `по примеру` в подделках нет ни одного, поэтому `прогоны` пусты — и
 * пусты у обоих одинаково.
 */
async function оба(исходник) {
  const программа = await loadProgramFromSource(исходник, "подделка.flang")
  const { obligations: список } = obligations(программа)
  const свидетель = checkProofs(программа, список.map((о) => ({ ...о })))
  const наш = изЗначения(evaluate(эталон, "Проверить доказательства", {
    программа: значение(программа),
    обязательства: список.map(значение),
    прогоны: [],
  }, ШАГИ))
  return { программа, свидетель, наш }
}

/** Вердикт эталона по имени функции и имени утверждения. */
const вердикт = (ответ, функция, имя) =>
  (ответ.checked ?? []).find((з) => з.of === функция && з.name === имя)?.verdict ?? null

/** Чем закрыто — по данным ответа, а не по разбору слов. */
const источники = (ответ, функция, имя) =>
  (ответ.checked ?? []).find((з) => з.of === функция && з.name === имя)?.calls ?? []

/** Прогон функции — и код отказа, если он был. Улика лжи, а не рассуждение. */
function прогон(программа, имя, аргументы) {
  try {
    return { значение: evaluate(программа, имя, аргументы), code: null }
  } catch (беда) {
    return { значение: undefined, code: беда?.code ?? null, message: беда?.message ?? "" }
  }
}

/** Два текста знак в знак, с местом расхождения в сообщении. */
function знакВЗнак(имя, левый, правый) {
  if (левый === правый) return
  let и = 0
  while (и < левый.length && и < правый.length && левый[и] === правый[и]) и += 1
  assert.fail(
    `${имя}: ответы разошлись на знаке ${и}\n  свидетель: ${левый.slice(и, и + 160)}\n  эталон:    ${правый.slice(и, и + 160)}`,
  )
}

/** Пункт 1 на каждой программе: ответы двух ядер знак в знак, целиком. */
function побайтово(имя, { свидетель, наш }) {
  знакВЗнак(имя, JSON.stringify(свидетель), JSON.stringify(наш))
}

/**
 * ВЕДОМОСТЬ знак в знак — то, что решает ЭТОТ слой.
 *
 * Нужно ровно в одном месте — у подделки 3, — и причина названа, а не замята:
 * отказ снятия предусловия несёт в себе ПРИЧИНУ СВЕДЕНИЯ, а её сочиняет слой
 * `Свести` (`self/proof-kernel.flang` против `proof/reduce.mjs`), и на правиле
 * «тождество после переписки допущением» тексты этих двух слоёв сегодня
 * расходятся — тот же зазор, которым красны восемь программ корпуса в
 * `self-proofterm.test.mjs`. Сверять его здесь значило бы держать подделку
 * восьмого хода красной за чужой долг.
 *
 * Что при этом НЕ ослаблено: вердикты сверяются целиком и побайтово, код отказа
 * и его место — тоже. Разойдись эталон в том, ЧТО он доказал, или в том, ГДЕ
 * отказал, — красно.
 */
function ведомостьПобайтово(имя, { свидетель, наш }) {
  знакВЗнак(`${имя} (ведомость)`, JSON.stringify(свидетель.checked), JSON.stringify(наш.checked))
  знакВЗнак(
    `${имя} (коды и места отказов)`,
    JSON.stringify((свидетель.diagnostics ?? []).map((б) => ({ code: б.code, severity: б.severity, span: б.span }))),
    JSON.stringify((наш.diagnostics ?? []).map((б) => ({ code: б.code, severity: б.severity, span: б.span }))),
  )
  знакВЗнак(
    `${имя} (счёт мест «требует»)`,
    JSON.stringify({ sites: свидетель.preconditions?.sites, discharged: свидетель.preconditions?.discharged }),
    JSON.stringify({ sites: наш.preconditions?.sites, discharged: наш.preconditions?.discharged }),
  )
}

