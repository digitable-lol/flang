/* ПОДДЕЛКА 3 — НЕОПЛАЧЕННОЕ «требует»                                 */
/* ================================================================== */

/* «Точно единица» обещает «результат равен 1» ТОЛЬКО при «н равен 1» — на любом
   другом входе она вернёт этот вход, и постусловие ложно. Её собственное
   утверждение эталон ДОКАЗЫВАЕТ: внутри тела предусловие истинно (за него платят
   вызывающие), и правило «цель есть допущение» закрывает цель им. То есть
   устройство «берётся только доказанное» подделку НЕ ловит — ловить её обязано
   именно устройство оплаты, и здесь оно проверяется в одиночку.

   «Через неё» зовёт её на «м: нат», где живёт и ноль, — и не платит. Возьми ход
   постусловие здесь, и ложь про ноль уехала бы к вызывающему под словом
   «доказано». */
const НЕОПЛАТА = `модуль «Неоплата»

тотальная функция «Точно единица»
  принимает н: нат
  возвращает число
  требует «вход единица» н равен 1
  обеспечивает «единица» результат равен 1
  н

тотальная функция «Через неё»
  принимает м: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Точно единица» от м
`

test("ПОДДЕЛКА 3 (неоплаченное «требует»): факт не берётся, и место названо кодом", async () => {
  const ответы = await оба(НЕОПЛАТА)
  ведомостьПобайтово("неоплата", ответы)
  assert.equal(
    вердикт(ответы.наш, "Точно единица", "единица"),
    "доказано",
    "лемма не доказана — тогда подделку ловит другое устройство, и это место не проверено",
  )
  const коды = (ответы.наш.preconditions?.diagnostics ?? []).map((б) => б.code)
  assert.ok(
    коды.includes("FLANG_PRECONDITION_CALL"),
    `место вызова не отвергнуто эталоном: коды ${JSON.stringify(коды)}`,
  )
  assert.notEqual(
    вердикт(ответы.наш, "Через неё", "единица"),
    "доказано",
    "постусловие взято на месте, где «требует» не снято, — это аксиома под другим именем",
  )
  /* УЛИКА: ложь называет прогон, а не рассуждение. */
  const беда = прогон(ответы.программа, "Через неё", { м: 0 })
  assert.notEqual(беда.code, null, `на нуле подделка обязана отказать, а не вернуть значение: ${JSON.stringify(беда)}`)
})

/* ОПЛАЧЕННОЕ «требует» — тот же вход, где вызывающий за условие платит. */
const ОПЛАТА = `модуль «Оплата»

тотальная функция «Точно единица»
  принимает н: нат
  возвращает число
  требует «вход единица» н равен 1
  обеспечивает «единица» результат равен 1
  н

тотальная функция «Через неё»
  принимает м: нат
  возвращает число
  требует «и здесь единица» м равен 1
  обеспечивает «единица» результат равен 1
  «Точно единица» от м
`

test("оплаченное «требует» у эталона: тот же вызов, за который заплатили, факт даёт", async () => {
  const ответы = await оба(ОПЛАТА)
  побайтово("оплата", ответы)
  const коды = (ответы.наш.preconditions?.diagnostics ?? []).map((б) => б.code)
  assert.deepEqual(коды, [], `место обязано сниматься: ${JSON.stringify(коды)}`)
  assert.equal(вердикт(ответы.наш, "Точно единица", "единица"), "доказано", "лемма не доказана — сверять нечего")
  assert.equal(
    вердикт(ответы.наш, "Через неё", "единица"),
    "доказано",
    "запрет бьёт по предусловию вообще, а не по НЕОПЛАЧЕННОМУ",
  )
})

