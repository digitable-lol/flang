/* Два постусловия НАЗВАНЫ ОДИНАКОВО и говорят разное: у «Как было» — что длина
   сохраняется (правда), у «Ничего» — что она неотрицательна (правда, и
   бесполезно). «Через ничего» зовёт «Ничего». Сличи ядро постусловие ПО ИМЕНИ —
   и приедет утверждение ПРО ЧУЖОЕ ТЕЛО, которым ложная цель закроется. */
const ОДНОИМЁННОЕ = `модуль «Одноимённые»

тотальная функция «Как было»
  принимает элементы: список числа
  возвращает список числа
  обеспечивает «мера» (длина результат) равен (длина элементы)
  элементы

тотальная функция «Ничего»
  принимает элементы: список числа
  возвращает список числа
  обеспечивает «мера» (длина результат) не меньше 0
  пустой список

тотальная функция «Через ничего»
  принимает элементы: список числа
  возвращает список числа
  обеспечивает «длина сохраняется» (длина результат) равен (длина элементы)
  «Ничего» от элементы
`

test("ПОДДЕЛКА 4 (не по имени, а по ребру): одноимённое постусловие чужой функции не берётся", async () => {
  const ответы = await оба(ОДНОИМЁННОЕ)
  побайтово("одноимённое", ответы)
  assert.equal(вердикт(ответы.наш, "Как было", "мера"), "доказано", "лемма-двойник не доказана — сверять нечего")
  assert.notEqual(
    вердикт(ответы.наш, "Через ничего", "длина сохраняется"),
    "доказано",
    "постусловие приехало по ИМЕНИ утверждения, а не по ребру вызова — это доказательство про чужое тело",
  )
  const беда = прогон(ответы.программа, "Через ничего", { элементы: [1] })
  assert.equal(
    беда.code,
    "FLANG_PROPERTY",
    `на списке из одного подделка обязана нарушить постусловие: ${JSON.stringify(беда)}`,
  )
})

/* ================================================================== */
/* ПОДДЕЛКА 5 — ПОСТУСЛОВИЕ, ЛОЖНОЕ НА НЕ-ЧИСЛЕ                        */
/* ================================================================== */

/* «0 делить на 0» проходит типизацию без единой диагностики и даёт НЕ ЧИСЛО, а
   «не число не меньше 0» ложно. Постусловие «Ноль на ноль» АВТОР НАПИСАЛ, и оно
   ЛОЖЬ. Возьми ход написанное — и ложь уехала бы к вызывающему целиком. Это и
   есть та самая цена, названная у хода: НЕДОКАЗАННОЕ постусловие фактом не
   становится, даже когда автор его написал. */
const НЕ_ЧИСЛО = `модуль «Не число»

тотальная функция «Ноль на ноль»
  принимает н: число
  возвращает число
  обеспечивает «неотрицательно» результат не меньше 0
  0 делить на 0

тотальная функция «Через него»
  принимает н: число
  возвращает число
  обеспечивает «неотрицательно» результат не меньше 0
  «Ноль на ноль» от н
`

test("ПОДДЕЛКА 5 (цель на НЕ-ЧИСЛЕ): НЕДОКАЗАННОЕ постусловие эталон не берёт", async () => {
  const ответы = await оба(НЕ_ЧИСЛО)
  побайтово("не число", ответы)
  assert.notEqual(вердикт(ответы.наш, "Ноль на ноль", "неотрицательно"), "доказано", "ложь доказана у самого вызванного")
  assert.notEqual(
    вердикт(ответы.наш, "Через него", "неотрицательно"),
    "доказано",
    "ход взял постусловие, которого ядро не доказывало, — и потащил ложь дальше",
  )
  const беда = прогон(ответы.программа, "Через него", { н: 1 })
  assert.equal(беда.code, "FLANG_PROPERTY", `не число обязано нарушить постусловие: ${JSON.stringify(беда)}`)
})

/* ================================================================== */
/* ПОДДЕЛКА 6 — ПОСТУСЛОВИЕ, ВЕРНОЕ ЛИШЬ НА НЕПУСТОМ ВХОДЕ              */
/* ================================================================== */

const НЕПУСТОЙ_ВХОД = `модуль «Непустой вход»

тотальная функция «Длина непуста»
  принимает элементы: список числа
  возвращает число
  обеспечивает «не меньше одного» результат не меньше 1
  длина элементы

тотальная функция «Через длину»
  принимает элементы: список числа
  возвращает число
  обеспечивает «не меньше одного» результат не меньше 1
  «Длина непуста» от элементы
`

test("ПОДДЕЛКА 6 (верно лишь на непустом): постусловие без «требует» эталон не берёт", async () => {
  const ответы = await оба(НЕПУСТОЙ_ВХОД)
  побайтово("непустой вход", ответы)
  assert.notEqual(вердикт(ответы.наш, "Длина непуста", "не меньше одного"), "доказано", "ложь доказана у самого вызванного")
  assert.notEqual(
    вердикт(ответы.наш, "Через длину", "не меньше одного"),
    "доказано",
    "постусловие, верное лишь на непустом входе, уехало к вызывающему без единой посылки",
  )
  const беда = прогон(ответы.программа, "Через длину", { элементы: [] })
  assert.equal(беда.code, "FLANG_PROPERTY", `пустой список обязан нарушить постусловие: ${JSON.stringify(беда)}`)
})

/* ================================================================== */
/* ИЗЪЯТИЕ: ход ничего не отбирает                                     */
/* ================================================================== */

/* Ход держит РОВНО те утверждения, которые без факта по вызову не сводятся.
   Цель, закрытая без него, обязана закрываться и с ним — и закрываться БЕЗ поля
   `calls`, иначе ведомость называла бы источником факт, которым не пользовалась. */
test("ход НИЧЕГО не отбирает у эталона: цель, закрытая без него, закрыта и с ним", async () => {
  const ответы = await оба(`модуль «Без вызова»

тотальная функция «Сумма»
  принимает первое: нат, второе: нат
  возвращает число
  обеспечивает «сумма неотрицательна» результат не меньше 0
  первое плюс второе
`)
  побайтово("без вызова", ответы)
  assert.equal(вердикт(ответы.наш, "Сумма", "сумма неотрицательна"), "доказано")
  assert.deepEqual(источники(ответы.наш, "Сумма", "сумма неотрицательна"), [])
})

/* ================================================================== */
/* НЕПОДВИЖНАЯ ТОЧКА: порядок объявлений на итог не влияет              */
/* ================================================================== */

/* Ход идёт неподвижной точкой, а не одним проходом сверху вниз. Тот же вход, где
   лемма стоит ПОСЛЕ пользователя, обязан дать тот же ответ; дай эталон здесь
   «не доказано» — и «доказано» зависело бы от порядка строк в файле. */
test("неподвижная точка: лемма ПОСЛЕ пользователя закрывает его так же", async () => {
  const ответы = await оба(`модуль «Порядок»

тотальная функция «Через длину»
  принимает элементы: список числа
  возвращает число
  обеспечивает «длина неотрицательна» результат не меньше 0
  «Длина списка» от элементы

тотальная функция «Длина списка»
  принимает элементы: список числа
  возвращает число
  обеспечивает «длина неотрицательна» результат не меньше 0
  разбор элементов
    случай пусто
      то 0
    случай голова и хвост
      то 1 плюс («Длина списка» от хвоста)
`)
  побайтово("порядок", ответы)
  assert.equal(
    вердикт(ответы.наш, "Через длину", "длина неотрицательна"),
    "доказано",
    "ход прошёл один раз сверху вниз — тогда это не неподвижная точка",
  )
  assert.deepEqual(
    источники(ответы.наш, "Через длину", "длина неотрицательна"),
    [{ of: "Длина списка", name: "длина неотрицательна" }],
    "закрылось не постусловием вызванного — тогда порядок здесь ничего не мерит",
  )
})
