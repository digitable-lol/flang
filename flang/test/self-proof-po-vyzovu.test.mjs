/* ПОДДЕЛКА 1 — КРУГ ПРЯМОЙ: рекурсивный вызов                         */
/* ================================================================== */

/* Цель «(«Само себя» от н) равен 1» совпадает ЗНАК В ЗНАК с инстанцией
   собственного постусловия на рекурсивном вызове. Возьми ход его — и правило
   «цель есть допущение» закрыло бы утверждение о функции, которая не возвращает
   ничего: P из P в чистом виде. Функция объявлена ОБЫЧНОЙ нарочно — с
   `тотальная` анализ завершаемости её и не пропустит, а круг ловить обязано
   ядро, а не сосед. */
const КРУГ_ПРЯМОЙ = `модуль «Круг прямой»

функция «Само себя»
  принимает н: нат
  возвращает число
  обеспечивает «единица» результат равен 1
  «Само себя» от н
`

test("ПОДДЕЛКА 1 (круг прямой): эталон не доказывает постусловие им же самим", async () => {
  const ответы = await оба(КРУГ_ПРЯМОЙ)
  побайтово("круг прямой", ответы)
  assert.notEqual(
    вердикт(ответы.наш, "Само себя", "единица"),
    "доказано",
    "рекурсивный вызов отдал эталону собственное постусловие — это P из P",
  )
})

