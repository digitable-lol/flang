/**
 * Ведомость обязана быть тотальной ЦЕЛИКОМ, а не «в основном».
 *
 * Причина не в аккуратности. Ведомость печатает про чужие функции «доказано» —
 * утверждение обо всех входах. Программа, которая сама не проходит тот анализ,
 * чьими выводами она отчитывается, печатала бы доказательства из недоказуемого:
 * первый же зависший отчёт означал бы, что «доказано» напечатать не удалось, а
 * узнать об этом можно только по молчанию. Поэтому здесь не «долгов нет», а
 * «долгов быть не может»: ни одной обычной функции.
 */
test("proof.flang: тотальность без диагностик, и обычных функций нет ни одной", () => {
  assert.deepEqual(тотальность.diagnostics, [])
  const обычные = свой.functions.filter((функция) => функция.total !== true).map((функция) => функция.name)
  assert.deepEqual(обычные, [], "у ведомости не может быть обычных функций: она отчитывается о завершении")
  const недоказанные = свой.functions
    .filter((функция) => !тотальность.total.has(функция.name))
    .map((функция) => функция.name)
  assert.deepEqual(недоказанные, [], "объявлено тотальной, а завершение не доказано")
})

test("proof.flang: анализ на flang судит ведомость так же, как эталон", () => {
  const наш = средаАнализа.call("Проверить тотальность", { "программа": значение(программа) })
  assert.deepEqual(наш["диагностики"], [], "анализ на flang нашёл в ведомости незавершаемость")
  assert.deepEqual(наш["тотальные"], [...тотальность.total], "множество доказанных разошлось с эталоном")
})

test("proof.flang: примеры всех функций сходятся", () => {
  let счёт = 0
  for (const функция of свой.functions) {
    for (const пример of функция.examples ?? []) {
      счёт += 1
      const получено = evaluate(программа, функция.name, пример.args, ШАГИ)
      assert.deepEqual(получено, пример.expected, `«${функция.name}» / «${пример.name}»`)
    }
  }
  assert.ok(счёт >= 12, `примеров всего ${счёт}`)
})

