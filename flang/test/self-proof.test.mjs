/* ─────────────────── слова: «провер…» в ведомости нет ─────────────────── */

/**
 * Слова ведомости — те, что ведомость СКАЗАЛА, а не те, что она процитировала.
 *
 * Имена объявлений приезжают из чужой программы и печатаются в ёлочках; функция
 * по имени «Проверка сторожа» — не словарь ведомости, а цитата. Поэтому запрет
 * ищется по тексту, из которого ёлочки вынуты.
 *
 * Различие не теоретическое, и найдено оно падением: ведомость о собственном
 * исходнике содержит «провер» ШЕСТЬ раз — все шесть в именах функций соседних
 * слоёв («Проверка сторожа», «Проверка образца», «Проверить тотальность» и
 * прочие). Дословный запрет `!/провер/` покраснел бы на первой же настоящей
 * программе; в эталоне он держится только потому, что там его спрашивают о пяти
 * крошечных исходниках, где таких имён нет.
 */
const своимиСловами = (текст) => текст.replace(/«[^»]*»/gu, "«»")

test("слова с корнем «провер» в ведомости на flang нет вовсе", () => {
  /* Оно и есть то самое слово, которое читается двумя способами: «проверено на
     двенадцати значениях» человек дочитывает как «доказано». Вместо него —
     «сетка N значений: нарушений не найдено». Ищется в НАПЕЧАТАННОМ тексте: в
     исходнике корень встречается в комментариях, и стеречь надо вывод. */
  let текстов = 0
  for (const [имя, { прог, результаты }] of разобранные) {
    const наш = наFlang(прог, итогиПроверок(результаты))
    текстов += 1
    assert.ok(!/провер/iu.test(своимиСловами(наш.словами)), `${имя}: ведомость сказала «провер…»:\n${наш.словами}`)
    assert.ok(!/провер/iu.test(своимиСловами(наш.json)), `${имя}: машинный вид сказал «провер…»`)
    /* У этих девяти имён с корнем нет вовсе, поэтому здесь запрет обязан
       держаться и дословно — иначе вынимание ёлочек прятало бы находку. */
    assert.ok(!/провер/iu.test(наш.словами), `${имя}: корень встретился и вне ёлочек`)
  }
  assert.equal(текстов, 9, "запрет проверен не на всех видах ведомости")
})

