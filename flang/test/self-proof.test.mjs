/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-totality.test.mjs`, и по той же причине: иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/** Обратный перевод «Значение» → JSON: тот же механический разбор. */
function изЗначения(узел) {
  if (узел.variant === "Значение списка") return узел.fields["элементы"].map(изЗначения)
  if (узел.variant === "Значение записи") {
    return Object.fromEntries(узел.fields["поля"].map((поле) => [поле["ключ"], изЗначения(поле["значение"])]))
  }
  const внутри = узел.fields["скаляр"]
  return внутри.variant === "Скаляр ничто" ? null : внутри.fields["значение"]
}

/* ─────────────── итоги проверок: то же, что берёт эталон ─────────────── */

/**
 * `«Убывание»` из результата анализа.
 *
 * Имя параметра приезжает суммой «есть/нет», а не строкой: у эталона
 * `edge.params[position]` бывает `undefined`, и «аргумент 2» без имени — не то
 * же самое, что «аргумент 2 («»)».
 */
const убывание = (запись) => ({
  "откуда": запись.from,
  "куда": запись.to,
  "позиция": запись.position,
  "параметр": {
    "есть": запись.param !== undefined && запись.param !== null,
    "имя": запись.param ?? "",
  },
})

/**
 * Итоги проверок для ведомости на flang — из тех же `results`, из которых их
 * берёт ведомость-эталон (`externalChecks`, `flang/bin/flang.mjs`).
 *
 * Предел сетки едет рядом с её размером и берётся ОТТУДА, ГДЕ ОБЪЯВЛЕН — из
 * модуля закона. Копия предела внутри ведомости разошлась бы с настоящим молча,
 * а «сетка 12 значений» без «предел 12» не даёт понять, кончились значения
 * автора или кончился предел.
 */
function итогиПроверок(результаты) {
  const тотальность = результаты.totality
  const множества = результаты.sets?.checked ?? []
  const множестваНаВеру = результаты.sets?.assumed ?? []
  return {
    "циклы": (тотальность.cycles ?? []).map((имена) => ({ "имена": имена })),
    "структуры": (тотальность.structures ?? []).map(убывание),
    "сторожа": (тотальность.guards ?? []).map(убывание),
    "спуски": (тотальность.descents ?? []).map((запись) => ({
      "откуда": запись.from,
      "мера": значение(запись.current),
    })),
    "моноиды": (результаты.monoid?.checked ?? []).map((запись) => ({
      "имя": запись.monoid, "значений": запись.values, "троек": запись.triples, "предел": ПРЕДЕЛ_МОНОИДА,
    })),
    "монады": (результаты.monad?.checked ?? []).map((запись) => ({
      "имя": запись.monad, "значений": запись.values, "троек": запись.triples,
      "стрелки": запись.arrows ?? [], "предел": ПРЕДЕЛ_МОНАДЫ, "предел стрелок": ПРЕДЕЛ_СТРЕЛОК,
    })),
    "изоморфизмы": (результаты.iso?.checked ?? []).map((запись) => ({
      "имя": запись.isomorphism, "значений": запись.values, "предел": ПРЕДЕЛ_ИЗО,
    })),
    "вложения": множества.filter((запись) => запись.embedding !== undefined).map((запись) => ({
      "имя": запись.embedding, "значений": запись.values, "предел": ПРЕДЕЛ_МНОЖЕСТВ,
    })),
    "общие части": множества.filter((запись) => запись.embedding === undefined).map((запись) => ({
      "имя": запись.intersection, "значений": запись.values, "предел": ПРЕДЕЛ_МНОЖЕСТВ,
      "свидетель": значение(запись.witness),
    })),
    "допущения вложений": множестваНаВеру.filter((з) => з.embedding !== undefined)
      .map((з) => ({ "имя": з.embedding, "причина": з.why })),
    "допущения общих частей": множестваНаВеру.filter((з) => з.embedding === undefined)
      .map((з) => ({ "имя": з.intersection, "причина": з.why })),
    "допущения изоморфизмов": (результаты.iso?.assumed ?? [])
      .map((з) => ({ "имя": з.isomorphism, "причина": з.why })),
  }
}

/** Ведомость на flang: машинный вид, текст человеку и JSON. */
function наFlang(ast, итоги) {
  const ведомость = вызвать("Ведомость", { "программа": значение(ast), "итоги": итоги })
  return {
    ведомость,
    машиной: изЗначения(вызвать("Ведомость значением", { "ведомость": ведомость })),
    словами: вызвать("Ведомость словами", { "ведомость": ведомость }),
    json: вызвать("Ведомость в JSON", { "ведомость": ведомость }),
  }
}

/**
 * Расхождение ведомости на flang с эталоном. `null` — совпало всё.
 *
 * Сверяются три вида, и все три обязательны. Машинный — потому что по нему
 * считают этапы; текст — потому что его читает человек и в нём живёт словарь;
 * JSON — потому что порядок ключей это поверхность совместимости, и разойтись в
 * ней значит сломать чужой скрипт, не сломав ни одного своего теста.
 */
function расхождение(ast, результаты) {
  const эталон = proofLedger(ast, результаты)
  const наш = наFlang(ast, итогиПроверок(результаты))

  const ждём = JSON.stringify(эталон)
  if (наш.json !== ждём) {
    const слева = [...ждём]
    const место = слева.findIndex((знак, номер) => знак !== наш.json[номер])
    return `JSON разошёлся на знаке ${место}:\n  эталон: ${ждём.slice(Math.max(0, место - 80), место + 160)}`
      + `\n  наш:    ${наш.json.slice(Math.max(0, место - 80), место + 160)}`
  }
  const текст = formatProofLedger(эталон)
  if (наш.словами !== текст) {
    const место = [...текст].findIndex((знак, номер) => знак !== наш.словами[номер])
    return `текст разошёлся на знаке ${место}:\n  эталон: ${текст.slice(Math.max(0, место - 80), место + 160)}`
      + `\n  наш:    ${наш.словами.slice(Math.max(0, место - 80), место + 160)}`
  }
  try {
    assert.deepEqual(наш.машиной, JSON.parse(ждём))
  } catch (беда) {
    return `машинный вид разошёлся: ${беда.message.slice(0, 400)}`
  }
  return null
}

