/**
 * Ведомость доказательства, написанная на самом flang — `flang/self/proof.flang`.
 *
 * Проверка здесь одна и она дифференциальная: на одной и той же программе с
 * одними и теми же итогами анализа ведомость на flang обязана дать то же, что
 * ведомость-эталон `flang/src/proof.mjs`, — ПОБАЙТОВО и в обоих видах:
 * человеческий текст знак в знак и машинный JSON байт в байт, вместе с порядком
 * ключей.
 *
 * Слабее критерий делать нельзя, и не из перфекционизма. Ведомость — это отчёт
 * о доказуемости, и врёт он молча: «доказано композицией» вместо «доказано
 * постоянным шагом» не падает, не краснеет и читается так же гладко. Своих
 * чисел у ведомости нет ни одного, поэтому и проверять надо не «напечаталось
 * что-то», а совпадение с образцом на каждом знаке.
 *
 * Что проверяется сверх совпадения:
 *
 *   1. САМА ВЕДОМОСТЬ — ТОТАЛЬНАЯ ПРОГРАММА. Все её функции объявлены
 *      тотальными, и все доказаны — и эталоном, и анализом на flang. Это не
 *      украшение: программа, печатающая доказательства, но не проходящая наш
 *      же анализ завершаемости, печатала бы их из недоказуемого.
 *
 *   2. СЛОВА НЕ ПУТАЮТСЯ. Корня «провер» в готовом тексте нет ни одного — того
 *      самого слова, которое читается двумя способами («проверено на двенадцати
 *      значениях» человек дочитывает как «доказано»). Проверяется на тексте,
 *      напечатанном flang, а не на исходнике.
 *
 *   3. ЦЕПОЧКА БЕЗ NODE. Итоги анализа для ведомости считает не JavaScript, а
 *      `self/totality.flang`: «циклы» и «структурные» из «Итога тотальности»
 *      кладутся в «Итоги проверок», и носители обязаны получиться те же.
 *      Это и есть смысл переноса — «доказуемость» перестаёт зависеть от Node.
 *
 *   4. ПРОВЕРКИ УМЕЮТ КРАСНЕТЬ. Каждая сверка выше показана на ИЗЪЯТИИ: у
 *      ведомости отбирают сторожа, слово, порядок ключей, — и сверка обязана это
 *      назвать. Иначе про зелёный цвет нельзя сказать, от чего он.
 *
 * Запуск: node --test flang/test/self-proof.test.mjs
 */
