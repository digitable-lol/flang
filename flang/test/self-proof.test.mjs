/**
 * Дифференциальная сверка на настоящих программах репозитория.
 *
 * Не весь корпус: перевод связанной программы в «Значение» и обход её ведомостью
 * в интерпретаторе стоит секунды на файл, а корпус — 93 файла, из которых
 * половина — слои самоприменения по три-четыре тысячи строк. Взяты те, что
 * покрывают все ветви ведомости: композиция без рекурсии, структура, постоянный
 * шаг со сторожем, объявленная мера, взаимная рекурсия, все четыре вида законов
 * и программа без функций вовсе.
 *
 * Полный корпус сводится сводом на эталоне (`flang/scripts/proof-ledger.mjs`), и
 * числа его сверяются в `flang/test/proof.test.mjs`; здесь проверяется, что
 * ведомость на flang даёт то же, что эталон, а не то, что корпус не изменился.
 */
const КОРПУС = [
  "flang/core/json.flang",
  "flang/stdlib/lists.flang",
  "flang/stdlib/strings.flang",
  "flang/stdlib/numbers.flang",
  "flang/stdlib/tree.flang",
  "flang/examples/measure/euclid.flang",
  "flang/examples/measure/binary-search.flang",
  "flang/examples/cat/euler-orders.flang",
  "flang/examples/cat/order-shipment.flang",
  "flang/examples/monad/order-total.flang",
  "flang/self/proof.flang",
]

test("ведомость на flang совпадает с эталоном на программах репозитория", async (t) => {
  let сверено = 0
  for (const путь of КОРПУС) {
    const прог = await loadProgram(join(корень, путь))
    const внешнее = await externalChecks(прог)
    assert.deepEqual(внешнее.diagnostics.filter((б) => б?.severity !== "warning"), [], `${путь}: программа с отказом`)
    const беда = расхождение(прог, внешнее.results)
    assert.equal(беда, null, `${путь}: ${беда}`)
    сверено += 1
  }
  t.diagnostic(`сверено программ: ${сверено}`)
  assert.equal(сверено, КОРПУС.length, "корпус сверки схлопнулся")
})

test("ведомость на flang судит собственный исходник так же, как эталон", async () => {
  /* Неподвижная точка отчёта: ведомость печатает ведомость о себе самой, и это
     не игра — свой исходник это единственная программа, про которую ведомость
     обязана быть верна по построению. */
  const внешнее = await externalChecks(программа)
  const эталон = proofLedger(программа, внешнее.results)
  const наш = наFlang(программа, итогиПроверок(внешнее.results))
  assert.equal(наш.json, JSON.stringify(эталон))
  assert.equal(наш.словами, formatProofLedger(эталон))
  assert.equal(наш.машиной.totals.unaccounted, 0, "у ведомости о себе носитель обязан быть назван у каждой")
  assert.ok(!/провер/iu.test(своимиСловами(наш.словами)), "ведомость о себе сказала «провер…» своими словами")
  /* И находка, из-за которой запрет считается своими словами: в цитатах корень
     есть, и это законно — так называются функции соседних слоёв. */
  assert.ok(/провер/iu.test(наш.словами), "имён с корнем не стало — вынимание ёлочек больше ничего не проверяет")
})

