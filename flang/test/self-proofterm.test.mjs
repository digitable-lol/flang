const списком = ({ программа, спуски }) => obligations(программа, { totality: { descents: спуски } }).obligations

/* Обязательства свидетель ПРАВИТ НА МЕСТЕ (`обязательство.discharge = вердикт`),
   поэтому ему уезжает копия: иначе второй прогон того же входа увидел бы чужой
   вердикт, и изъятие ниже сравнивало бы испорченный эталон с испорченным
   свидетелем. */
const свидетелем = (вход) => checkProofs(вход.программа, списком(вход).map((о) => ({ ...о })))

const эталоном = (вход, свой = эталон) => {
  const список = списком(вход)
  return изЗначения(evaluate(свой, "Проверить доказательства", {
    программа: значение(вход.программа),
    обязательства: список.map(значение),
    прогоны: прогоны(вход.программа, список).map(значение),
  }, ШАГИ))
}

function сверить(свой = эталон) {
  const расхождения = []
  let строк = 0
  let диагностик = 0
  const вердикты = { "доказано": 0, "сетка": 0, "отвергнуто": 0 }
  for (const вход of корпус) {
    const свидетельОбъект = свидетелем(вход)
    строк += свидетельОбъект.checked.length
    диагностик += свидетельОбъект.diagnostics.length
    for (const с of свидетельОбъект.checked) вердикты[с.verdict] += 1
    const свидетель = JSON.stringify(свидетельОбъект)
    let наш
    try { наш = JSON.stringify(эталоном(вход, свой)) } catch (беда) { наш = `СОРВАЛОСЬ: ${беда?.message}` }
    if (свидетель !== наш) {
      let и = 0
      while (и < свидетель.length && и < наш.length && свидетель[и] === наш[и]) и += 1
      расхождения.push(
        `${вход.имя}: на знаке ${и}\n      свидетель:  ${свидетель.slice(и, и + 110)}\n      эталон: ${наш.slice(и, и + 110)}`,
      )
    }
  }
  return { всего: корпус.length, расхождения, строк, диагностик, вердикты }
}

