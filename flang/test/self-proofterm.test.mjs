test("ПОДДЕЛКА: доказательство ЛЖИ отвергается тем же кодом и тем же текстом", () => {
  /* Обратная сторона Карри–Ховарда: согласие двух ядер на «принято» ничего не
     стоило бы, если бы они не расходились и на «отвергнуто». Здесь тело шага
     ВЫЧИТАЕТ вместо сложения — то есть «Размер» ложно объявлен неотрицательным,
     — и близнец обязан не пустить это к ведомости той же причиной. */
  for (const имя of [
    "FLANG_PROOF_INDUCTION_STEP: шаг не сведён к допущению",
    "FLANG_PROOF_INDUCTION_CASES: конструктор не разобран",
    "FLANG_PROOF_STEP: пример про другой вариант",
    "FLANG_PROOF_STEP: закон не объявлен",
    "ОТВЕРГНУТО: нет строки «следовательно доказано»",
  ]) {
    const вход = корпус.find((в) => в.имя === `дурная — ${имя}`)
    const эталон = эталоном(вход)
    const наш = близнецом(вход)
    assert.ok(
      эталон.checked.every((с) => с.verdict === "отвергнуто"),
      `${имя}: ЭТАЛОН подделку принял — проверять нечего`,
    )
    assert.deepEqual(наш.checked.map((с) => с.verdict), эталон.checked.map((с) => с.verdict), `${имя}: вердикт разошёлся`)
    assert.deepEqual(наш.diagnostics.map((б) => б.code), эталон.diagnostics.map((б) => б.code), `${имя}: код отказа разошёлся`)
    /* ТЕКСТ сличается ДОСЛОВНО, и ровно одна приписка снимается с эталонного —
       та, что говорит о ЧЕТВЁРТОМ ХОДЕ (`Вычислить её тоже нельзя: …`). Ход этот
       у близнеца не написан вовсе, и долг назван там же, где ход
       (`flang/proof/SPEC.md`): дать близнецу вычисление значит переписать на
       flang интерпретатор, а не правило. Снимается приписка НАЗВАННЫМ куском, а
       не вольным сравнением: разойдись хоть буква в остальном отказе — красно; и
       красно же, если приписка вдруг перестанет находиться там, где эталон её
       ставит, потому что тогда сравниваются два разных текста. */
    const безВычисления = (текст) => текст.replace(/\. Вычислить её тоже нельзя: [^)]*?ни одного/u, "")
    assert.deepEqual(
      наш.diagnostics.map((б) => б.message),
      эталон.diagnostics.map((б) => безВычисления(б.message)),
      `${имя}: ТЕКСТ отказа разошёлся`,
    )
    assert.deepEqual(наш.checked.map((с) => с.says), эталон.checked.map((с) => с.says), `${имя}: вердикт СЛОВАМИ разошёлся`)
  }
})

