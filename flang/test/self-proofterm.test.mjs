/* ЦЕПОЧКА БЕЗ ЕДИНОГО ШАГА — вход, которого парсер не построит: `случай … то`
   требует обоснования, и написать пустой случай в файле нельзя. Ядро его тем не
   менее разбирает и обязано отвергнуть, а близнец — отвергнуть тем же текстом.
   Дерево собирается здесь руками, и это единственный такой вход: без него ветка
   «ни одного шага» не сверялась бы вовсе, и изъятие её не поймало бы.
   Заодно это единственный отказ БЕЗ места в исходнике — то самое `span:
   undefined`, которого у `JSON.stringify` нет как ключа, а не как `null`. */
{
  const программа = parse(шапка + теоремаДерева("по примеру «лист»", "по предположению"))
  программа.theorems[0].induction.cases[0].steps = []
  корпус.push({ имя: "собранная руками — цепочка без единого шага", программа, спуски: [] })
}

/* ШАГ БЕЗ НАЗВАННОГО ПРАВИЛА — второй вход, которого парсер не построит:
   обоснование у шага обязательно, и форма «затем <утверждение>» без `по …` в
   грамматике отсутствует. Последняя ветка `проверитьШаг` («правило шага не
   названо») от этого не имела в корпусе ни одного входа — то есть не сверялась
   вовсе. Дерево собирается руками по той же причине и тем же способом. */
{
  const программа = parse(шапка + теоремаДерева("по примеру «лист»", "по предположению"))
  программа.theorems[0].induction.cases[0].steps[0].by = { rule: null, name: null }
  корпус.push({ имя: "собранная руками — шаг без названного правила", программа, спуски: [] })
}

/* ─────────────────── сверка ─────────────────── */

const списком = ({ программа, спуски }) => obligations(программа, { totality: { descents: спуски } }).obligations

/* Обязательства эталон ПРАВИТ НА МЕСТЕ (`обязательство.discharge = вердикт`),
   поэтому ему уезжает копия: иначе второй прогон того же входа увидел бы чужой
   вердикт, и изъятие ниже сравнивало бы испорченного близнеца с испорченным
   эталоном. */
const эталоном = (вход) => checkProofs(вход.программа, списком(вход).map((о) => ({ ...о })))

const близнецом = (вход, свой = близнец) => {
  const список = списком(вход)
  return изЗначения(evaluate(свой, "Проверить доказательства", {
    программа: значение(вход.программа),
    обязательства: список.map(значение),
    прогоны: прогоны(вход.программа, список).map(значение),
  }, ШАГИ))
}

function сверить(свой = близнец) {
  const расхождения = []
  let строк = 0
  let диагностик = 0
  const вердикты = { "доказано": 0, "сетка": 0, "отвергнуто": 0 }
  for (const вход of корпус) {
    const эталонОбъект = эталоном(вход)
    строк += эталонОбъект.checked.length
    диагностик += эталонОбъект.diagnostics.length
    for (const с of эталонОбъект.checked) вердикты[с.verdict] += 1
    const эталон = JSON.stringify(эталонОбъект)
    let наш
    try { наш = JSON.stringify(близнецом(вход, свой)) } catch (беда) { наш = `СОРВАЛОСЬ: ${беда?.message}` }
    if (эталон !== наш) {
      let и = 0
      while (и < эталон.length && и < наш.length && эталон[и] === наш[и]) и += 1
      расхождения.push(
        `${вход.имя}: на знаке ${и}\n      эталон:  ${эталон.slice(и, и + 110)}\n      близнец: ${наш.slice(и, и + 110)}`,
      )
    }
  }
  return { всего: корпус.length, расхождения, строк, диагностик, вердикты }
}

