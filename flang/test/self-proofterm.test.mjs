/* ─────────────────── сверка ─────────────────── */

const списком = ({ программа, спуски }) => obligations(программа, { totality: { descents: спуски } }).obligations

/* Обязательства эталон ПРАВИТ НА МЕСТЕ (`обязательство.discharge = вердикт`),
   поэтому ему уезжает копия: иначе второй прогон того же входа увидел бы чужой
   вердикт, и изъятие ниже сравнивало бы испорченного близнеца с испорченным
   эталоном. */
const эталоном = (вход) => checkProofs(вход.программа, списком(вход).map((о) => ({ ...о })))

const близнецом = (вход, свой = близнец) => {
  const список = списком(вход)
  return изЗначения(evaluate(свой, "Проверить доказательства", {
    программа: значение(вход.программа),
    обязательства: список.map(значение),
    прогоны: прогоны(вход.программа, список).map(значение),
  }, ШАГИ))
}

function сверить(свой = близнец) {
  const расхождения = []
  let строк = 0
  let диагностик = 0
  const вердикты = { "доказано": 0, "сетка": 0, "отвергнуто": 0 }
  for (const вход of корпус) {
    const эталонОбъект = эталоном(вход)
    строк += эталонОбъект.checked.length
    диагностик += эталонОбъект.diagnostics.length
    for (const с of эталонОбъект.checked) вердикты[с.verdict] += 1
    const эталон = JSON.stringify(эталонОбъект)
    let наш
    try { наш = JSON.stringify(близнецом(вход, свой)) } catch (беда) { наш = `СОРВАЛОСЬ: ${беда?.message}` }
    if (эталон !== наш) {
      let и = 0
      while (и < эталон.length && и < наш.length && эталон[и] === наш[и]) и += 1
      расхождения.push(
        `${вход.имя}: на знаке ${и}\n      эталон:  ${эталон.slice(и, и + 110)}\n      близнец: ${наш.slice(и, и + 110)}`,
      )
    }
  }
  return { всего: корпус.length, расхождения, строк, диагностик, вердикты }
}

