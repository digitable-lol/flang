/*
 * ПОДДЕЛКИ СЕДЬМОГО ХОДА проверяются ОТДЕЛЬНО от списка выше, и причина в
 * устройстве самих программ, а не в снисхождении. Сличение по вызову опирается
 * на ЛЕММУ — постусловие чужой функции, у которой доказательство своё, — значит
 * в каждой такой программе стоят ДВА утверждения: доказанная лемма и подделка
 * при ней. Проверка выше требует, чтобы отвергнуто было КАЖДОЕ утверждение
 * программы, и на лемме она сломалась бы по делу.
 *
 * Поэтому здесь утверждение называется ПОИМЁННО, а требование то же и не слабее:
 * эталон обязан отвергнуть названное, близнец — отвергнуть его тем же КОДОМ и
 * тем же ТЕКСТОМ, и текст обязан назвать причину, а не сказать «ядро не смогло».
 * Лемма при этом обязана остаться ДОКАЗАННОЙ у обоих: подделка, отвергнутая
 * заодно с леммой, ничего не показывает.
 */
test("ПОДДЕЛКА седьмого хода: ссылка «по свойству» не разрешение, и отказ называет причину", () => {
  for (const [имя, утверждение, кусок] of [
    /* Вызов есть, инстанция строится — а вывода из неё нет: вычитания в списке
       правила неотрицательности нет и не будет. */
    ["ПОДДЕЛКА: ссылка «по свойству» не разрешение — заключение обязано быть сведено",
      "разность неотрицательна", "вычитания в этом списке нет"],
    /* Шаг закрывает посылку ПОСТОРОННЕЙ правдой. */
    ["ПОДДЕЛКА: «по свойству» закрывает шаг ПОСТОРОННИМ утверждением",
      "ниже нуля", "не заключение этого места"],
    /* Постусловие названо, а вызова той функции в заключении нет ни одного:
       инстанцировать не на чем. Эта подделка жила в корпусе и до седьмого хода —
       ею измерялся зазор, — и теперь обязана отвергаться по МЕСТУ ВЫЗОВА. */
    ["FLANG_PROOF_STEP: «по свойству» чужой функции, которую заключение не зовёт",
      "размер неотрицателен", "нет ни одного вызова"],
  ]) {
    const вход = корпус.find((в) => в.имя === `дурная — ${имя}`)
    assert.ok(вход !== undefined, `${имя}: программы нет в корпусе`)
    const эталон = эталоном(вход)
    const наш = близнецом(вход)
    const уЭталона = эталон.checked.find((с) => с.of !== undefined && с.name === утверждение)
      ?? эталон.checked.find((с) => с.name === утверждение)
    assert.ok(уЭталона !== undefined, `${имя}: утверждения «${утверждение}» у эталона нет — проба сломана`)
    assert.equal(уЭталона.verdict, "отвергнуто", `${имя}: ЭТАЛОН подделку принял — проверять нечего`)
    assert.ok(
      эталон.diagnostics.some((б) => б.message.includes(кусок)),
      `${имя}: отказ эталона не называет причину «${кусок}»: ${эталон.diagnostics.map((б) => б.message).join(" | ")}`,
    )
    assert.deepEqual(наш.checked.map((с) => с.verdict), эталон.checked.map((с) => с.verdict), `${имя}: вердикт разошёлся`)
    assert.deepEqual(наш.diagnostics.map((б) => б.code), эталон.diagnostics.map((б) => б.code), `${имя}: код отказа разошёлся`)
    assert.deepEqual(наш.diagnostics.map((б) => б.message), эталон.diagnostics.map((б) => б.message), `${имя}: ТЕКСТ отказа разошёлся`)
    assert.deepEqual(наш.checked.map((с) => с.says), эталон.checked.map((с) => с.says), `${имя}: вердикт СЛОВАМИ разошёлся`)
  }
})

