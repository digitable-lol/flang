/**
 * Интерактивная оболочка flang, написанная на самом flang —
 * `flang/self/repl/repl.flang`.
 *
 * Проверка здесь ровно та же, какой проверены девять слоёв самоприменения до
 * неё, и другой быть не может: ПОБАЙТОВАЯ СВЕРКА С ЭТАЛОНОМ. Одна и та же
 * последовательность ввода подаётся в `flang/src/repl.mjs` и в слой на flang, и
 * после каждого ввода сверяется:
 *
 *   1. ВИД ИТОГА — «вычислено», «объявлено», «сообщение», «отказ», «пусто»,
 *      «конец». Вид расходится раньше текста и потому проверяется первым.
 *   2. НАПЕЧАТАННЫЙ ОТВЕТ — `formatResult` эталона против «Печать итога»
 *      близнеца, знак в знак. Сюда входят и тексты отказов: код, место, строка,
 *      столбец и сообщение. Оболочка, отказывающая другими словами, — это не
 *      мелочь оформления: пользователь читает ровно эту строку.
 *   3. ИСХОДНИК СЕССИИ — то, что сессия накопила. Он сверяется отдельно от
 *      ответа, потому что расхождение в накоплении ответа не меняет: сессия
 *      разъезжается молча и вылезает через три ввода.
 *   4. ЗАПИСАННЫЙ ФАЙЛ — у `.сохранить` сверяются байты обоих дисков.
 *
 * ЧЕГО СВЕРКА НЕ ДЕЛАЕТ МОЛЧА. Связывания модулей на flang нет — слоя `link` в
 * самоприменении не написано, — и ввод с `использует` близнец не «пропускает», а
 * отвечает кодом FLANG_SELF_REPL_UNSUPPORTED. Тест считает такие ответы
 * отдельно и требует, чтобы их множество совпало с ОБЪЯВЛЕННЫМ списком: ни
 * одного лишнего отказа и ни одного молчаливого пропуска. Тот же довод, каким
 * `self/interpret.flang` отвечает на формы вне своего среза: пропущенное молча
 * сверка засчитала бы сошедшимся.
 *
 * И проверка самой проверки: последний блок портит по одной ветке оболочки на
 * flang и требует, чтобы сверка покраснела. Сверка, которая не умеет краснеть,
 * хуже отсутствующей.
 *
 * Запуск: node --test flang/test/self-repl.test.mjs
 */
