/**
 * Две оболочки, идущие в ногу, и два ОТДЕЛЬНЫХ диска.
 *
 * Диски отдельные нарочно: `.сохранить` пишет в свой каждый, и сверка байтов
 * между ними — самостоятельная проверка. Общий диск её бы съел, потому что
 * второй писавший затирал бы первого.
 */
function пара(файлы = {}, пределы = ПРЕДЕЛЫ) {
  const дискЭталона = new Map(Object.entries(файлы).map(([имя, текст]) => [join(каталог, имя), текст]))
  const дискБлизнеца = new Map(дискЭталона)
  const читать = (диск) => async (путь) => {
    if (!диск.has(путь)) throw new Error(`ENOENT: no such file or directory, open '${путь}'`)
    return диск.get(путь)
  }
  const эталон = createSession({
    base: каталог,
    maxSteps: пределы.maxSteps,
    maxDepth: пределы.maxDepth,
    readFile: читать(дискЭталона),
    writeFile: async (путь, текст) => {
      дискЭталона.set(путь, текст)
    },
  })
  return {
    эталон,
    дискЭталона,
    дискБлизнеца,
    читатьБлизнецу: читать(дискБлизнеца),
    сессия: зов("Новая сессия", {
      "предел витков": пределы.maxSteps,
      "предел глубины": пределы.maxDepth,
    }),
  }
}

/**
 * Поручения хозяину. Чтение и запись — эффекты, и в чистом языке их быть не
 * может; близнец говорит, ЧТО сделать, а делает хозяин — здесь это тест, в
 * терминале это будет `bin/flang.mjs`. Путь превращается в полный ровно тем же
 * `resolve` от того же каталога, каким это делает эталон: иначе разошлись бы
 * тексты отказов, в которых полный путь и назван.
 */
async function исполнить(состояние, итог) {
  if (итог["вид"] === "чтение") {
    const путь = итог["откуда"]
    const полный = resolve(каталог, путь)
    let текст = ""
    let удалось = true
    let ошибка = ""
    try {
      текст = await состояние.читатьБлизнецу(полный)
    } catch (беда) {
      удалось = false
      ошибка = беда.message
    }
    return зов("Принять прочитанное", {
      "с": итог["сессия"], "путь": путь, "полный": полный,
      "удалось": удалось, "ошибка": ошибка, "текст": текст,
    })
  }
  if (итог["вид"] === "запись") {
    const путь = итог["откуда"]
    const полный = resolve(каталог, путь)
    состояние.дискБлизнеца.set(полный, итог["текст"])
    return зов("Принять записанное", {
      "с": итог["сессия"], "полный": полный, "удалось": true, "ошибка": "",
    })
  }
  return итог
}

/** Один ввод в обе оболочки. Возвращает описание расхождения или null. */
async function подать(состояние, ввод) {
  const ждём = await состояние.эталон.submit(ввод)
  let итог = зов("Принять", { "с": состояние.сессия, "исходный": ввод })
  итог = await исполнить(состояние, итог)
  состояние.сессия = итог["сессия"]

  if (вне(итог)) return { вне: итог["отказы"][0]["сообщение"] }

  if (итог["вид"] !== ждём.kind) {
    return { беда: `вид «${итог["вид"]}» ≠ «${ждём.kind}»` }
  }
  const наш = зов("Печать итога", { "и": итог })
  const образец = formatResult(ждём)
  if (наш !== образец) {
    const безМеста = отказБезМеста(итог, ждём)
    if (безМеста === null) return { беда: `ответ ${JSON.stringify(наш)} ≠ ${JSON.stringify(образец)}` }
    return { безМеста }
  }

  const исходникБлизнеца = зов("Исходник сессии", { "с": состояние.сессия })
  const исходникЭталона = состояние.эталон.source()
  if (исходникБлизнеца !== исходникЭталона) {
    return { беда: `исходник сессии ${JSON.stringify(исходникБлизнеца)} ≠ ${JSON.stringify(исходникЭталона)}` }
  }
  return {}
}

const вне = (итог) =>
  итог["вид"] === "diagnostics"
  && итог["отказы"].length > 0
  && итог["отказы"][0]["код"] === ВНЕ_СРЕЗА

/**
 * Единственное НАЗВАННОЕ расхождение, и оно ровно в одном: отказ, пришедший из
 * вычислителя, эталон печатает с местом, а близнец — без.
 *
 * Причина не в оболочке: `self/interpret.flang` мест не хранит ВОВСЕ — ни одного
 * `span` во всём слое, — и взять их оболочке неоткуда. Расхождение записано в
 * «Долгах» `flang/self/SPEC.md`.
 *
 * Прощается оно узко и считается поштучно, иначе сверка перестала бы быть
 * сверкой. Условия все сразу: обе стороны отказали, отказов поровну, КАЖДЫЙ
 * отказ близнеца помечен пришедшим из вычислителя, у каждого нет места, и код с
 * сообщением совпадают знак в знак. Расходится только место — и только там, где
 * его физически нет.
 */
function отказБезМеста(итог, ждём) {
  if (итог["вид"] !== "diagnostics" || ждём.kind !== "diagnostics") return null
  const наши = итог["отказы"]
  if (наши.length !== ждём.diagnostics.length || наши.length === 0) return null
  const пары = наши.map((наш, индекс) => [наш, ждём.diagnostics[индекс]])
  if (!пары.every(([наш]) => наш["от вычисления"] === true && наш["точка"]["есть"] === false)) return null
  if (!пары.every(([наш, ждали]) => наш["код"] === ждали.code && наш["сообщение"] === ждали.message)) return null
  if (!пары.some(([, ждали]) => ждали.at !== undefined && ждали.at !== null)) return null
  return пары.map(([наш]) => наш["код"]).join(", ")
}

