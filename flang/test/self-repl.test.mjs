/**
 * Предел витков слоя поднят до четырёх миллиардов, потому что оболочка на flang
 * — это ШЕСТЬ слоёв в одной программе: на каждый ввод она гоняет лексер,
 * разборщик, проверку типов, анализ завершаемости и вычислитель, и каждый из
 * них сам написан на flang. Самый дорогой ввод корпуса — объявление функции с
 * разбором — обходится примерно в двести миллионов шагов эталонного движка.
 * Глубина поднята вдвое: рекурсивный спуск разборщика вкладывается на каждую
 * ветку.
 */
