/** «Знач» близнеца из значения времени выполнения эталона — для печати значений. */
function знач(значение) {
  if (значение === null || значение === undefined) return { variant: "Знач ничто", fields: {} }
  if (значение === true || значение === false) return { variant: "Знач признак", fields: { "признак": значение } }
  if (typeof значение === "number") return { variant: "Знач число", fields: { "число": значение } }
  if (typeof значение === "string") return { variant: "Знач строка", fields: { "текст": значение } }
  if (Array.isArray(значение)) return { variant: "Знач список", fields: { "элементы": значение.map(знач) } }
  return {
    variant: "Знач запись",
    fields: { "поля": Object.entries(значение).map(([ключ, поле]) => ({ "ключ": ключ, "значение": знач(поле) })) },
  }
}

test("значения печатаются поверхностью языка — тем же байтом, что у эталона", () => {
  const значения = [3, -0, 0, 1.5, 1e300, "текст", 'с "кавычкой"', true, false, null, [], [1, [2], "а"], { х: 1, у: 2 }, {}]
  for (const значение of значения) {
    assert.equal(
      зов("Печать значения оболочки", { "зн": знач(значение) }),
      formatValue(значение),
      `печать ${JSON.stringify(значение)}`,
    )
  }
})

