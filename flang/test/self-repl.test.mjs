/* ────────────────────────── сверка умеет краснеть ──────────────────────── */

/**
 * Порчи по одной ветке. Каждая — правдоподобная ошибка перевода, а не выдумка:
 * забытый знак в тексте, перепутанный порядок, снятая проверка. Требование одно
 * и оно жёсткое: на целом слое корпус зелёный, на порченом — красный.
 */
const ПОРЧИ = [
  {
    имя: "«пустой список» стал печататься как «[]»",
    испортить: (текст) => текст.replace('то "пустой список"', 'то "[]"'),
  },
  {
    имя: "минус ноль потерял знак",
    испортить: (текст) => текст.replace('    то "-0"\n    иначе к строке «ч»', "    то к строке «ч»\n    иначе к строке «ч»"),
  },
  {
    имя: "столбец перестал сдвигаться на ширину обёртки",
    испортить: (текст) => текст.replace(
      "и «сдвиг столбцов» равным (2 плюс («ввод».«отступ»))",
      "и «сдвиг столбцов» равным 0",
    ),
  },
  {
    имя: "переобъявление перестало заменять прежнее",
    испортить: (текст) => текст.replace(
      "  если «Есть общее имя» от («о».«имена») и «имена»\n    то запись «Ход слияния»",
      "  если нет\n    то запись «Ход слияния»",
    ),
  },
  {
    имя: "про недоказанное завершение перестали говорить",
    испортить: (текст) => текст.replace(
      '      то " — завершение не доказано: вычисление ограничено лимитом шагов"',
      '      то ""',
    ),
  },
  {
    имя: "между объявлениями сессии пропала пустая строка",
    испортить: (текст) => текст.replace('по "\\n\\n"), "\\n"]', 'по "\\n"), "\\n"]'),
  },
]

test("сверка умеет краснеть: каждая порча оболочки ловится корпусом", async (t) => {
  const целый = await прогнать(КОРПУС)
  assert.deepEqual(целый.беды.slice(0, 3), [], "на целом слое корпус обязан быть зелёным")

  for (const { имя, испортить } of ПОРЧИ) {
    const испорчено = испортить(исходник)
    assert.notEqual(испорчено, исходник, `порча «${имя}» ничего не заменила — сама порча устарела`)
    const { diagnostics: _, ...порченая } = await linkProgram(файл, испорчено, parse)
    const порченаяСреда = createRuntime(порченая, ШАГИ)
    const прежний = среда.call
    /* Подмена на время прогона: корпус и сверка те же, слой другой. Иначе
       пришлось бы завести вторую копию прогона, и краснела бы она, а не та,
       что стоит на страже. */
    среда.call = (fn, args) => порченаяСреда.call(fn, args)
    let итог
    try {
      итог = await прогнать(КОРПУС)
    } finally {
      среда.call = прежний
    }
    assert.ok(итог.беды.length > 0, `порча «${имя}» прошла незамеченной: сверено ${итог.сверено}, расхождений 0`)
    t.diagnostic(`«${имя}»: поймано на ${итог.беды.length} вводах из ${итог.сверено}`)
  }
})
