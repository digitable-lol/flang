/**
 * Равенство морфизмов и естественность преобразований, написанные на самом
 * flang — `flang/self/setoid.flang`.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы вердикт
 * законов категории на flang обязан совпасть с вердиктом эталона
 * `flang/src/setoid.mjs` — те же диагностики, код в код, текст в текст, место в
 * место, И ТЕ ЖЕ ЧИСЛА СЕТКИ. Сверка побайтовая, вместе с порядком ключей;
 * расхождение печатается с номером знака.
 *
 * ── Улика, снятая прогоном ДО этой работы ───────────────────────────────────
 * Близнеца не было вовсе. Корпус (231 программа: всё `flang/**` и `examples/**`)
 * задевает этот закон в ШЕСТИ файлах — пяти по разбору
 * (`examples/cat/moduli/{zakazy,platezhi,otgruzka}.flang`,
 * `examples/cat/natural-square.flang`, `examples/cat/order-shipment.flang`) и
 * шестом после связывания (`examples/cat/moduli/soglasovanie.flang`, три
 * категории приезжают к нему через `использует`). До сегодняшнего дня на них
 * отвечал только эталон на JavaScript: 3 проверенных категории, 6 допущенных.
 * На остальных 225 программах ответ пуст, и пустота эта — тоже утверждение.
 *
 * ── Почему числа важнее всего остального ────────────────────────────────────
 * Ни один из четырёх законов файла НЕ ДОКАЗЫВАЕТСЯ: равенство вычислений на
 * всех значениях объекта неразрешимо. Ведомость (`proof.mjs`) печатает про них
 * «сетка N значений», а не «доказано», и числа N приезжают отсюда — из
 * `checked`/`«проверено»`. Близнец, дающий другое N, не «слегка расходится»: он
 * печатает в ведомости другое утверждение о том же коде. Поэтому сверяется вся
 * запись целиком: значения, объекты, тройки, СПИСОК СТРЕЛОК, нарушения,
 * пропуски и место обрыва.
 *
 * ── Откуда берётся таблица вызовов, и ЧЕМ она посчитана ─────────────────────
 * Законам категории мало РАЗОБРАТЬ программу — им надо её ВЫПОЛНИТЬ: равенство
 * объявляется функцией, и спросить его можно только вычислением. Языку flang
 * нечем передать функцию функцией, поэтому вызовы приезжают в близнеца данными,
 * и строит эту таблицу здешний оракул.
 *
 * СЧИТАЕТ ЖЕ ЕЁ ВЫЧИСЛИТЕЛЬ, НАПИСАННЫЙ НА FLANG, — `self/interpret.flang` через
 * `self-evaluator.mjs`. Отсюда проверка в конце файла: сломай вычислитель в
 * одном месте — вердикт законов обязан разойтись с эталоном.
 *
 * Оракул НЕ РЕШАЕТ ничего из того, что решает близнец. Он строит ЗАМЫКАНИЕ
 * значений — сетка объекта плюс всё, во что её переводят стрелки категории за
 * четыре круга (длиннее цепочки у эталона нет: ассоциативность применяет три
 * стрелки, продолжение две, квадрат две), — и спрашивает равенство на ВСЕХ парах
 * замыкания. Предел его сетки заведомо шире предела близнеца, обрывов он не
 * делает вовсе, а что считать сеткой, в каком порядке смотреть законы и где
 * остановиться, решает близнец. Ошибиться так можно ровно в одну сторону:
 * недостающий вызов близнец назовёт вслух («вызова нет в таблице»), и сверка от
 * этого покраснеет, а не позеленеет. Отдельный тест ниже стережёт, что этих слов
 * не появилось ни разу.
 */
