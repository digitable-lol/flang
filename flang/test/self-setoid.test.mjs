/** Законы категории на flang, приведённые к форме эталона. */
function нашиКатегории(программа, переведённая = значение(программа)) {
  const итог = средаСетоида.call("Проверить законы категории", {
    "программа": переведённая,
    "таблица": оракулКатегорий(программа),
  })
  return {
    diagnostics: итог["диагностики"].map(образцовая),
    checked: итог["проверено"].map((запись) =>
      запись.variant === "Проверена категория"
        ? (() => {
            const сетка = запись.fields["запись"]
            return {
              category: сетка["категория"],
              values: сетка["значений"],
              objects: сетка["объектов"],
              triples: сетка["троек"],
              arrows: сетка["стрелки"],
              /* Поля уезжают наружу ТОЛЬКО при ненулевом значении — тем же
                 приёмом, каким эталон пишет `...(нарушений === 0 ? {} : …)`. */
              ...(сетка["нарушений"] === 0 ? {} : { violations: сетка["нарушений"] }),
              ...(сетка["пропущено"] === 0 ? {} : { skipped: сетка["пропущено"] }),
              ...(сетка["оборвано"] === "" ? {} : { aborted: сетка["оборвано"] }),
            }
          })()
        : (() => {
            const сетка = запись.fields["запись"]
            return {
              transformation: сетка["преобразование"],
              values: сетка["значений"],
              objects: сетка["объектов"],
              squares: сетка["квадратов"],
              ...(сетка["нарушений"] === 0 ? {} : { violations: сетка["нарушений"] }),
              ...(сетка["пропущено"] === 0 ? {} : { skipped: сетка["пропущено"] }),
              ...(сетка["оборвано"] === "" ? {} : { aborted: сетка["оборвано"] }),
            }
          })(),
    ),
    assumed: итог["допущено"].map((пропуск) =>
      пропуск.variant === "Допущена категория"
        ? { category: пропуск.fields["имя"], why: пропуск.fields["почему"] }
        : { transformation: пропуск.fields["имя"], why: пропуск.fields["почему"] },
    ),
  }
}

/**
 * Побайтовое расхождение двух итогов — вместе с ПОРЯДКОМ КЛЮЧЕЙ.
 *
 * Номер знака в ответе обязателен: «не совпало» на записи в две тысячи знаков
 * заставляет искать разницу глазами, а найти её надо за один взгляд.
 */
function расхождение(эталон, наш) {
  const слева = JSON.stringify(эталон)
  const справа = JSON.stringify(наш)
  if (слева === справа) return null
  const знаки = [...слева]
  const место = знаки.findIndex((знак, номер) => знак !== справа[номер])
  const окно = (текст) => текст.slice(Math.max(0, место - 30), место + 90)
  return `разошлось на знаке ${место === -1 ? слева.length : место}:\n    эталон …${окно(слева)}…\n    наш    …${окно(справа)}…`
}

