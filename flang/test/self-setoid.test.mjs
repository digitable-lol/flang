/** Чем посчитан каждый ответ: справа обязан остаться ноль. */
const счёт = { эталоном: 0, вычислителем: 0, вне: [] }

/** Слой, которым считаются ответы. Переменная — ради доказательства изъятием. */
let слой = средаСлоя

function позвать(программа, наш, имя, аргументы) {
  const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
  if (функция === undefined) return { нет: true }
  const назван = {}
  ;(функция.params ?? []).forEach((параметр, номер) => {
    назван[параметр.name] = аргументы[номер]
  })
  const ответ = наш.звать(имя, назван)
  if (ответ.вне !== undefined) {
    счёт.вне.push(`${имя}: ${ответ.вне}`)
    return { ошибка: ответ.вне }
  }
  счёт.вычислителем += 1
  return ответ.отказ === undefined ? { значение: ответ.значение } : { ошибка: ответ.отказ }
}

const аргументом = (з) => вариантЗначения("Есть аргумент", { значение: значение(з) })

/**
 * Таблица вызовов одной программы.
 *
 * Ключ строит САМ БЛИЗНЕЦ («Ключ вызова»): формат ключа — его дело, и вторая
 * его копия здесь разошлась бы с первой молча.
 */
function таблицаВызовов(программа) {
  const наш = вычислитель(программа, ШАГИ, слой)
  const строки = new Map()
  const записать = (имя, аргументы) => {
    const ключ = средаСетоида.call("Ключ вызова", { "имя": имя, "аргументы": аргументы.map(аргументом) })
    if (строки.has(ключ)) return строки.get(ключ)
    const итог = позвать(программа, наш, имя, аргументы)
    строки.set(ключ, итог)
    return итог
  }
  return { записать, строки }
}

const строкиТаблицы = (строки) =>
  [...строки]
    .filter(([, итог]) => итог.нет !== true)
    .map(([ключ, итог]) => ({
      "ключ": ключ,
      "ответ":
        итог.ошибка === undefined
          ? вариантЗначения("Вызов дал", { "значение": значение(итог.значение) })
          : вариантЗначения("Вызов отказал", { "сообщение": итог.ошибка }),
    }))

/** Предел сетки оракула: заведомо шире предела близнеца. */
const ПРЕДЕЛ_ОРАКУЛА = ПРЕДЕЛ_СЕТКИ + 4

/** Предел замыкания: сколько РАЗНЫХ значений держим на объекте. */
const ПРЕДЕЛ_ЗАМЫКАНИЯ = 48

/** Кругов распространения: у эталона длиннее цепочки нет — три стрелки подряд. */
const КРУГОВ = 4

const годная = (имя) => typeof имя === "string" && имя !== ""

const примерыФункции = (функции, имя) => {
  const функция = функции.find((кандидат) => кандидат.name === имя)
  return Array.isArray(функция?.examples) ? функция.examples : []
}

/** Концы каждой стрелки, включая композиции: замыкание повторами, как у эталона. */
function концыСтрелок(узлы) {
  const концы = new Map()
  for (const [имя, узел] of узлы) {
    if (узел.kind === "morphism") концы.set(имя, { domain: узел.domain, codomain: узел.codomain })
  }
  let сдвинулись = true
  while (сдвинулись) {
    сдвинулись = false
    for (const [имя, узел] of узлы) {
      if (узел.kind !== "composition" || концы.has(имя)) continue
      const левая = концы.get(узел.left)
      const правая = концы.get(узел.right)
      if (левая === undefined || правая === undefined) continue
      концы.set(имя, { domain: правая.domain, codomain: левая.codomain })
      сдвинулись = true
    }
  }
  return концы
}

/** Равенства категории, у которых названная функция объявлена и берёт два входа. */
function объявленныеРавенства(узел, функции) {
  const равенства = new Map()
  for (const запись of узел.equalities ?? []) {
    const функция = функции.find((кандидат) => кандидат.name === запись?.gives)
    if (функция === undefined || (функция.params ?? []).length !== 2) continue
    if (равенства.has(запись.object)) continue
    равенства.set(запись.object, запись.gives)
  }
  return равенства
}

/**
 * Оракул законов категории: замыкание вызовов всех категорий и преобразований.
 *
 * Он повторяет ФОРМУ обхода эталона там, где иначе неоткуда взять промежуточные
 * значения композиции, но ни одного его решения не принимает: сетка здесь шире,
 * обрывов нет вовсе, а равенство спрашивается на ВСЕХ парах замыкания, а не
 * только на тех, до которых близнец дойдёт.
 */
function оракулКатегорий(программа) {
  const категории = Array.isArray(программа.categories) ? программа.categories : []
  if (категории.length === 0) return []

  const функции = Array.isArray(программа.functions) ? программа.functions : []
  const узлыСтрелок = new Map()
  for (const узел of Array.isArray(программа.morphisms) ? программа.morphisms : []) {
    if (typeof узел?.name === "string") узлыСтрелок.set(узел.name, узел)
  }
  const концы = концыСтрелок(узлыСтрелок)
  const { записать, строки } = таблицаВызовов(программа)

  const применить = (имя, входное, глубина = 0) => {
    if (глубина > 64) return { ошибка: true }
    const узел = узлыСтрелок.get(имя)
    if (узел === undefined) return { ошибка: true }
    if (узел.kind === "composition") {
      const справа = применить(узел.right, входное, глубина + 1)
      if (справа.ошибка) return справа
      return применить(узел.left, справа.значение, глубина + 1)
    }
    if (узел.identity === true) return { значение: входное }
    if (!годная(узел.gives)) return { ошибка: true }
    const итог = записать(узел.gives, [входное])
    return итог.значение === undefined ? { ошибка: true } : { значение: итог.значение }
  }

  /** Сетка объекта эталона, но с пределом оракула. */
  const сеткиОбъектов = (свои, равенства) => {
    const сетки = new Map()
    const положить = (объект, з) => {
      if (з === undefined) return
      if (!сетки.has(объект)) сетки.set(объект, [])
      const список = сетки.get(объект)
      const готовое = reifyValue(з)
      if (список.some((уже) => valuesEqual(уже, готовое))) return
      if (список.length >= ПРЕДЕЛ_ОРАКУЛА) return
      список.push(готовое)
    }
    for (const [объект, имяРавенства] of равенства) {
      сетки.set(объект, [])
      for (const пример of примерыФункции(функции, имяРавенства)) {
        for (const з of Object.values(пример.args ?? {})) положить(объект, з)
      }
    }
    for (const имя of свои) {
      const пара = концы.get(имя)
      const стрелка = узлыСтрелок.get(имя)
      const примеры = [
        ...примерыФункции(функции, стрелка?.gives),
        ...((стрелка?.laws ?? []).flatMap((закон) => закон.examples ?? [])),
      ]
      for (const пример of примеры) {
        for (const з of Object.values(пример.args ?? {})) положить(пара.domain, з)
        положить(пара.codomain, пример.expected)
      }
    }
    return сетки
  }

  const посчитано = new Map()

  for (const узел of категории) {
    const равенства = объявленныеРавенства(узел, функции)
    if (равенства.size === 0) continue
    const свои = (узел.morphisms ?? []).filter((имя) => концы.has(имя))
    const сетки = сеткиОбъектов(свои, равенства)

    /* Замыкание: сетка плюс всё, во что её переводят стрелки за четыре круга. */
    const известно = new Map()
    const добавить = (объект, з) => {
      if (объект === undefined || з === undefined) return
      if (!известно.has(объект)) известно.set(объект, [])
      const список = известно.get(объект)
      if (список.length >= ПРЕДЕЛ_ЗАМЫКАНИЯ) return
      const готовое = reifyValue(з)
      if (список.some((уже) => valuesEqual(уже, готовое))) return
      список.push(готовое)
    }
    for (const [объект, значения] of сетки) for (const з of значения) добавить(объект, з)
    for (let круг = 0; круг < КРУГОВ; круг += 1) {
      for (const имя of свои) {
        const пара = концы.get(имя)
        for (const з of [...(известно.get(пара.domain) ?? [])]) {
          const итог = применить(имя, з)
          if (!итог.ошибка) добавить(пара.codomain, итог.значение)
        }
      }
    }
    /* Равенство спрашивается на ВСЕХ парах замыкания: близнец спросит его на
       подмножестве, каким бы порядком он ни шёл. */
    for (const [объект, имяРавенства] of равенства) {
      const значения = известно.get(объект) ?? []
      for (const а of значения) for (const б of значения) записать(имяРавенства, [а, б])
    }
    if (!посчитано.has(узел.name)) посчитано.set(узел.name, { равенства, известно })
  }

  /* Естественность: стрелки квадрата приходят из функторов и в `свои` категории
     могут не входить вовсе, поэтому их вызовы собираются отдельно. */
  const функторы = new Map()
  for (const узел of Array.isArray(программа.legacy) ? программа.legacy : []) {
    if (узел?.construct !== "functorFile") continue
    if (!функторы.has(узел.value?.name)) функторы.set(узел.value.name, узел.value)
  }
  for (const узел of Array.isArray(программа.transformations) ? программа.transformations : []) {
    const слева = функторы.get(узел.from)
    const справа = функторы.get(узел.to)
    if (слева === undefined || справа === undefined || слева.to !== справа.to) continue
    const кодомен = посчитано.get(слева.to)
    if (кодомен === undefined) continue
    const компоненты = new Map((узел.components ?? []).map((запись) => [запись.object, запись.morphism]))
    const объектыСлева = new Map((слева.objects ?? []).map((пара) => [пара.from, пара.to]))
    const стрелкиСлева = new Map((слева.morphisms ?? []).map((пара) => [пара.from, пара.to]))
    const стрелкиСправа = new Map((справа.morphisms ?? []).map((пара) => [пара.from, пара.to]))
    for (const [стрелка, образСлева] of стрелкиСлева) {
      const образСправа = стрелкиСправа.get(стрелка)
      const пара = концы.get(стрелка)
      if (образСправа === undefined || пара === undefined) continue
      const альфаХ = компоненты.get(пара.domain)
      const альфаУ = компоненты.get(пара.codomain)
      const начало = объектыСлева.get(пара.domain)
      if (альфаХ === undefined || альфаУ === undefined || начало === undefined) continue
      const конец = концы.get(образСправа)?.codomain
      const имяРавенства = конец === undefined ? undefined : кодомен.равенства.get(конец)
      for (const з of кодомен.известно.get(начало) ?? []) {
        const альфа = применить(альфаХ, з)
        const первый = альфа.ошибка ? альфа : применить(образСправа, альфа.значение)
        const образ = применить(образСлева, з)
        const второй = образ.ошибка ? образ : применить(альфаУ, образ.значение)
        if (имяРавенства === undefined || первый.ошибка || второй.ошибка) continue
        записать(имяРавенства, [первый.значение, второй.значение])
      }
    }
  }

  return строкиТаблицы(строки)
}

