const ШАГИ = { maxSteps: 400_000_000, maxDepth: 20_000 }

async function слой(имя) {
  const файл = fileURLToPath(new URL(`../self/${имя}.flang`, import.meta.url))
  const { diagnostics: _, ...программа } = await linkProgram(файл, readFileSync(файл, "utf8"), parse)
  const среда = createRuntime(программа, ШАГИ)
  return (функция, аргументы) => среда.call(функция, аргументы)
}

