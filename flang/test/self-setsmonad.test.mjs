test("законы множеств на таблице оракула из дерева: недостача пуста, а таблица не пуста", (t) => {
  const беды = []
  let строк = 0
  let непустых = 0
  for (const { имя, ast } of сверкаОракулаМножеств) {
    const таблица = таблицаМножеств(ast)
    строк += таблица.length
    if (таблица.length > 0) непустых += 1
    const { нехватка } = множестваОракулом(ast)
    if (нехватка.length > 0) беды.push(`${имя}: недостача не пуста — оракул не посчитал ${нехватка.length} вызов(ов)`)
  }
  t.diagnostic(`программ ${сверкаОракулаМножеств.length}, из них с непустой таблицей ${непустых}, строк таблиц ${строк}`)
  assert.deepEqual(беды, [], `оракул не закрыл спрос на ${беды.length} программах`)
  assert.ok(строк > 0, "таблицы пусты на всём корпусе — сверять было нечего")
  assert.ok(непустых >= 5, `программ с непустой таблицей всего ${непустых}`)
})

