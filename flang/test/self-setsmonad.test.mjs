/**
 * Отношения множеств и законы монады, написанные на самом flang —
 * `flang/self/sets.flang` и `flang/self/monad.flang`.
 *
 * ── Зачем этот файл появился ────────────────────────────────────────────────
 *
 * Побайтовую сверку с эталоном имели СЕМЬ слоёв — лексер, разборщик, типы,
 * тотальность, печать в C, ведомость, понижение. Отношения множеств и монада не
 * были перенесены вовсе: два слоя, которые решают, ЧТО КОМПИЛЯТОР ГОВОРИТ
 * ЧЕЛОВЕКУ О ЕГО МОДЕЛИ, целиком оставались на JavaScript, и «эталоном языка
 * является flang» про них было неправдой.
 *
 * ── ЧТО ЗДЕСЬ ГЛАВНОЕ: «не нашли» — это не «нет» ────────────────────────────
 *
 * Обе проверки НЕ ДОКАЗЫВАЮТ, а СЧИТАЮТ НА КОНЕЧНОЙ СЕТКЕ, и у каждой свой
 * ПРЕДЕЛ СЕТКИ. Из этого следует различие, на котором держится честность обоих
 * слов (`flang/cat/SETS.md`, «Граница честности»):
 *
 *   • инъективность вложения нарушается ПРЕДЪЯВЛЕННЫМ контрпримером — два
 *     разных входа и один общий образ. Это находка, и она ОТКАЗ;
 *   • непустота общей части подтверждается ПРЕДЪЯВЛЕННЫМ свидетелем. Свидетеля
 *     не нашлось — и это НЕ отказ, а «на веру»: значений, которых автор не
 *     написал, бесконечно много, и «среди написанных общего нет» пустоты не
 *     доказывает.
 *
 * Спутать эти две судьбы — значит научить язык врать словом. Поэтому здесь
 * сверяются не только диагностики, но и ОБА СПИСКА результата (`checked` и
 * `assumed`) целиком и побайтово: перепутанный список — это ровно та подмена,
 * которую диагностиками не поймать, потому что диагностик в обоих случаях ноль.
 *
 * ── Что сверяется ───────────────────────────────────────────────────────────
 *
 * Все четыре точки входа обоих эталонов:
 *
 *   `checkSetShapes`   ← «Проверить устройство множеств»  доказательство устройства
 *   `checkSetLaws`     ← «Проверить законы множеств»      сетка: отказ и вера
 *   `expandMonads`     ← «Развернуть монады»              форма `в монаде`
 *   `checkMonadLaws`   ← «Проверить законы монад»         сетка: три закона
 *
 * Критерий один и он побайтовый: `JSON.stringify` итога обязан совпасть знак в
 * знак, ВМЕСТЕ С ПОРЯДКОМ КЛЮЧЕЙ. Слабее нельзя: `checked` монады уезжает в
 * ведомость доказательства, а разошедшийся порядок полей дал бы другую
 * ведомость при том же смысле.
 *
 * ── Половина, без которой вторая ничего не значит ───────────────────────────
 *
 * Программа БЕЗ объявленных монад и отношений обязана давать ПУСТОЙ результат и
 * не считать ничего. Проверяется на настоящих программах корпуса, а не на
 * выдуманной: выдуманная доказывала бы, что так бывает. Без этой проверки
 * сверка зеленела бы на корпусе, где ни монад, ни вложений почти нет, ничего
 * при этом не проверяя.
 *
 * ── Как слой зовёт вычислитель, и ЧЕМ ТОТ СЧИТАЕТ ───────────────────────────
 *
 * Сетка ВЫЧИСЛЯЕТ, а передать вычислитель функцией в flang нечем: функций
 * первого класса у языка нет. Поэтому близнец устроен как СПРОС: он решает, кого
 * и на чём звать, и возвращает недостачу — вызовы, ответа на которые у него нет.
 * Здесь недостача считается и подаётся обратно, пока не опустеет. Решения
 * принимает близнец, снаружи приходит ровно «что даёт эта функция на этом
 * значении».
 *
 * СЧИТАЕТ ЭТО ТЕПЕРЬ ВЫЧИСЛИТЕЛЬ, НАПИСАННЫЙ НА FLANG, — `self/interpret.flang`
 * через `self-evaluator.mjs`, и на эталон здесь не уходит НИ ОДНОГО вызова: все
 * 224 укладываются в срез. Отсюда проверка в конце файла, которой раньше не
 * могло быть вовсе: сломай вычислитель в одном месте — вердикт законов монады
 * обязан разойтись с эталоном.
 */
