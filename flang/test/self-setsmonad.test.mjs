/**
 * Ответ на один вызов проверяемой программы.
 *
 * Аргументы раскладываются в точности как у свидетеля: значение уходит в ПЕРВЫЙ
 * параметр, остальные остаются `undefined`. Свидетель делает то же самое
 * (`функция.params.forEach`), и функция не той арности обязана отказать
 * одинаково с обеих сторон.
 */
/**
 * СЧЁТ ОТВЕТОВ, ПОСЧИТАННЫХ ЧУЖИМ ЯЗЫКОМ.
 *
 * Улика, а не украшение отчёта: пока вычислителя flang на flang не было, каждый
 * ответ, которым закрывается недостача спроса, считал свидетель на JavaScript, и
 * круг самоприменения на этом размыкался.
 */
const счёт = { свидетелем: 0, вычислителем: 0, вне: [], имена: new Set() }

/**
 * Слой, которым сейчас считаются ответы.
 *
 * Переменная, а не постоянная, ради доказательства изъятием: проверка в конце
 * файла подменяет её ИСПОРЧЕННЫМ вычислителем и требует, чтобы вердикт законов
 * монады разошёлся со свидетелем. Пока недостачу закрывал JavaScript, такая
 * подмена не меняла бы ровно ничего.
 */
let слойСейчас = средаСлоя

function посчитать(ast, наш, имя, вход) {
  const функция = (ast.functions ?? []).find((кандидат) => кандидат.name === имя)
  const назван = {}
  for (const [номер, параметр] of (функция?.params ?? []).entries()) {
    назван[параметр.name] = номер === 0 ? вход : undefined
  }
  const ответ = наш.звать(имя, назван)
  счёт.имена.add(имя)
  /* Запасного пути к свидетелю нет: форма вне среза записывается и становится
     отказом, от которого вердикт разойдётся со свидетелем. */
  if (ответ.вне !== undefined) {
    счёт.вне.push(`${имя}: ${ответ.вне}`)
    return { вышло: false, значение: значение(null), беда: ответ.вне }
  }
  счёт.вычислителем += 1
  return ответ.отказ === undefined
    ? { вышло: true, значение: значение(ответ.значение), беда: "" }
    : { вышло: false, значение: значение(null), беда: ответ.отказ }
}

/**
 * Круги спроса: эталон считает, называет недостачу, получает её и считает
 * снова — пока недостача не опустеет. Круг, на котором её нет, и есть ответ:
 * ни один вызов на нём не остался без настоящего значения.
 *
 * Кругов не бывает больше, чем звеньев в самой длинной цепочке вызовов, — у
 * монады это `возврат → отображение → соединение → стрелка`. Предел стоит вдвое
 * выше замеренного и ловит не медленность, а зацикливание.
 */
const посчитанное = new Map()

function спросить(ast, слойФункция, имяФункции) {
  /* Один и тот же вопрос об одной и той же программе задаётся в разных
     утверждениях; считать его дважды незачем — ответ у него один. */
  const ключ = `${имяФункции}\u0000${JSON.stringify(ast)}`
  const готовое = посчитанное.get(ключ)
  if (готовое !== undefined) return готовое
  const ответ = посчитать_кругами(ast, слойФункция, имяФункции)
  посчитанное.set(ключ, ответ)
  return ответ
}

function посчитать_кругами(ast, слойФункция, имяФункции) {
  const наш = вычислитель(ast, {}, слойСейчас)
  let ответы = []
  for (let круг = 0; круг < 40; круг += 1) {
    const итог = слойФункция(имяФункции, { программа: значение(ast), ответы })
    if (итог["нехватка"].length === 0) return { итог: изЗначения(итог["итог"]), кругов: круг + 1 }
    ответы = ответы.concat(итог["нехватка"].map((вызов) => ({
      функция: вызов["функция"],
      вход: вызов["вход"],
      ...посчитать(ast, наш, вызов["функция"], reifyValue(изЗначения(вызов["вход"]))),
    })))
  }
  throw new Error("спрос не сошёлся за сорок кругов")
}

/**
 * Контекст `checkTypes` для `checkSetShapes` — ТРАНСПОРТ, а не работа.
 *
 * Свидетель принимает контекст извне (его собирает `checkTypes` до вызова), и
 * собрать его здесь — то же самое, что перевести AST в «Значение»: ни одного
 * решения этот код не принимает. Сигнатуры при этом берутся у НАСТОЯЩЕЙ
 * проверки типов (`checkTypes(ast).types` — это и есть `ctx.signatures`), а не
 * пересчитываются: имя типа у параметра приезжает нормализованным, и
 * пересчитать его здесь значило бы завести третий ответ рядом с двумя.
 *
 * Что этот транспорт мог бы соврать, проверяется отдельно — тестом «коды
 * отношений множеств те же, что у полной проверки типов».
 */
function контекст(ast) {
  const диагностики = []
  const имена = new Map()
  for (const объявление of ast.types ?? []) {
    if (typeof объявление?.name === "string" && объявление.name !== "") имена.set(объявление.name, объявление)
  }
  return {
    диагностики,
    ctx: {
      report: (code, message, node) => диагностики.push({ code, message, severity: "error", span: node?.span ?? null }),
      records: имена,
      sums: new Map(),
      aliases: new Map(),
      signatures: checkTypes(ast).types,
    },
  }
}

