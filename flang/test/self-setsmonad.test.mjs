/**
 * РАЗЛИЧИЕ, РАДИ КОТОРОГО ВСЁ ОСТАЛЬНОЕ: «не нашли» — это не «нет».
 *
 * Одна программа даёт отказ, другая — молчание, и отличаются они не строгостью,
 * а тем, ЧТО ПРЕДЪЯВЛЕНО. У склейки предъявлен контрпример: два разных входа,
 * дающих один образ, — и это ошибка. У общей части без свидетеля не предъявлено
 * ничего: сетка конечна, а ненаписанных значений бесконечно много, — и это
 * «на веру», список `assumed`, из которого `flang check` не берёт ни строки.
 *
 * Проверяется на эталоне, а не на свидетеле: перепутай он два списка местами —
 * диагностик всё равно было бы ноль, и поймать подмену можно только так.
 */
test("«не нашли» уходит в веру, а «нет» — в отказ, и эталон их не путает", () => {
  const свидетеля = спросить(parse(БЕЗ_СВИДЕТЕЛЯ, "проба.flang"), множества, "Проверить законы множеств").итог
  assert.deepEqual(свидетеля.diagnostics, [], "общая часть без свидетеля не смеет быть отказом")
  assert.equal(свидетеля.checked.some((запись) => запись.intersection !== undefined), false)
  const вера = свидетеля.assumed.find((запись) => запись.intersection === "Срочные оплаченные")
  assert.ok(вера !== undefined, "общая часть без свидетеля обязана уйти в веру")
  assert.match(вера.why, /либо множества и правда не пересекаются, либо пример общего значения не написан/u)

  const склейка = спросить(parse(СКЛЕЙКА, "проба.flang"), множества, "Проверить законы множеств").итог
  assert.deepEqual(склейка.diagnostics.map((беда) => беда.code), ["FLANG_EMBED_NOT_INJECTIVE"])
  /* Контрпример предъявлен значениями: без них «не инъективно» заставляет
     искать их руками, а именно они и есть вся находка. */
  assert.match(склейка.diagnostics[0].message, /\{"номер":1\} и \{"номер":2\} дают \{"номер":0\}/u)

  /* И свидетель, когда он есть, тоже ПРЕДЪЯВЛЕН — значением, а не словом «да». */
  const рисунок = спросить(parse(РИСУНОК, "проба.flang"), множества, "Проверить законы множеств").итог
  assert.deepEqual(
    рисунок.checked.find((запись) => запись.intersection !== undefined),
    { intersection: "Срочные оплаченные", values: 4, witness: { номер: 2 } },
  )
})

