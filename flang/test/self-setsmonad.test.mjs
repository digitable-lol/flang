/**
 * ПОРЧА В ОДНО СЛОВО, И ОНА ОБЯЗАНА ПОПАСТЬ ТУДА, ГДЕ СЧИТАЮТ.
 *
 * У каждой порчи две половины: сперва утверждается, что замена ВООБЩЕ ЧТО-ТО
 * заменила (иначе устарела сама порча), потом — что сверка на настоящих
 * программах от неё покраснела. Краснеть тут можно двумя способами, и оба
 * считаются: недостача перестала быть пустой либо вердикт разошёлся со
 * свидетелем.
 */
const ИЗЪЯТИЯ_ОРАКУЛА_МНОЖЕСТВ = [
  ["вложение перестало звать свою функцию", '«Строка поля» от «узел» и "gives"', '«Строка поля» от «узел» и "give"'],
  ["сетка берётся не из примеров", '«Элементы поля» от «функция» и "examples"', '«Элементы поля» от «функция» и "example"'],
  ["отказ выдаётся за удачу", '«вышло» равным нет и «значение» равным («Узел ничто») и «беда» равным «сообщение»', '«вышло» равным да и «значение» равным («Узел ничто») и «беда» равным «сообщение»'],
]

test("ИЗЪЯТИЕ: испорченный в одно слово оракул множеств краснеет на настоящих программах", async (t) => {
  const целый = средаОракулаМножеств
  for (const [имя, было, стало] of ИЗЪЯТИЯ_ОРАКУЛА_МНОЖЕСТВ) {
    const испорчено = исходникОракулаМножеств.replace(было, стало)
    assert.notEqual(испорчено, исходникОракулаМножеств, `${имя}: порча ничего не заменила — сама порча устарела`)
    const { diagnostics: _беды, ...порченая } = await linkProgram(файлОракулаМножеств, испорчено, parse)
    средаОракулаМножеств = createRuntime(порченая, ШАГИ)
    try {
      const покраснело = сверкаОракулаМножеств.filter(({ имя: имяПрограммы, ast }) => {
        const { итог, нехватка } = множестваОракулом(ast)
        return нехватка.length > 0 || JSON.stringify(итог) !== целыеИтогиМножеств.get(имяПрограммы)
      })
      assert.ok(покраснело.length > 0, `${имя}: испорченный оракул прошёл незамеченным на всём корпусе`)
      t.diagnostic(`${имя}: покраснело программ ${покраснело.length} из ${сверкаОракулаМножеств.length}`)
    } finally {
      средаОракулаМножеств = целый
    }
  }
})
