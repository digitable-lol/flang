/**
 * ГЛАВНОЕ ДОКАЗАТЕЛЬСТВО ТОГО, ЧТО КРУГ ЗАМКНУЛСЯ.
 *
 * Вычислитель на flang ломается в ОДНОМ месте — всякое число сдвигается на
 * единицу, — и вердикт законов монады обязан разойтись со свидетелем. Пока
 * недостачу спроса закрывал JavaScript, эта порча не меняла бы ровно ничего:
 * сверка законов монады была бы зелёной на сломанном языке.
 *
 * Порядок обязателен: сначала на ЦЕЛОМ вычислителе расхождения нет — иначе
 * «поймано» ничего не значило бы.
 */
test("сверка законов монады краснеет, когда ломается вычислитель на flang", async (t) => {
  const пробы = [
    ...ЗАКОНЫ_БАТАРЕЯ.map(([имя, ast]) => ({ путь: имя, ast })),
    ...сМонадами,
  ]
  assert.ok(пробы.length > 2, "в корпусе нет программ с монадами — порче нечего ломать")

  const целые = пробы.map(({ ast }) => JSON.stringify(спросить(ast, монады, "Проверить законы монад").итог))
  for (const [номер, { путь, ast }] of пробы.entries()) {
    const свидетель = JSON.stringify(checkMonadLaws(structuredClone(ast)))
    assert.equal(расхождение(свидетель, целые[номер]), null, `${путь}: не сходится и на целом вычислителе`)
  }

  /* Мишень выбрана не наугад, и почему — стоит знать.
   *
   * Законы монады сравнивают ДВА ВЫЧИСЛЕНИЯ ОДНИХ И ТЕХ ЖЕ функций:
   * «связать(возврат(а), к)» против «к(а)». Ровная порча арифметики такие
   * равенства НЕ РВЁТ — обе стороны считаются одинаково сломанным вычислителем
   * и сходятся по-прежнему. Это свойство законов, а не слепота сверки, и
   * проверено руками: «sub → add» и «div → mul» проходят по монадам корпуса
   * незамеченными.
   *
   * Рвётся другое — ТЕКСТ нарушенного закона: он называет посчитанные значения.
   * Поэтому порча сдвигает всякое число на единицу (литерал и аргумент разом), и
   * программа со сломанной единицей начинает печатать другое число.
   */
  const испорчено = исходникСлоя.replace(
    'случай вариант «Скаляр число» с «значение» как «зн»\n      то вариант «Знач число» с «число» равным «зн»',
    'случай вариант «Скаляр число» с «значение» как «зн»\n      то вариант «Знач число» с «число» равным («зн» плюс 1)',
  )
  assert.notEqual(испорчено, исходникСлоя, "порча ничего не заменила — сама порча устарела")

  const целый = слойСейчас
  слойСейчас = await слойИз(испорчено)
  посчитанное.clear()
  try {
    const поймано = пробы.filter(({ ast }, номер) =>
      JSON.stringify(спросить(ast, монады, "Проверить законы монад").итог) !== целые[номер])
    assert.ok(поймано.length > 0, "испорченный вычислитель прошёл незамеченным")
    t.diagnostic(`порча «всякое число сдвинулось на единицу» поймана на ${поймано.length} программах из ${пробы.length}`)
  } finally {
    слойСейчас = целый
    посчитанное.clear()
  }
})

