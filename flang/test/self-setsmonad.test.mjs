/**
 * ГЛАВНОЕ СВОЙСТВО ПРОХОДА: программа БЕЗ блока `в монаде` проходит
 * разворачивание НЕИЗМЕННОЙ — байт в байт той же.
 *
 * Печать в C — часть самоприменения, её неподвижная точка сверяется побайтово,
 * и проход, изменивший хоть байт там, где монады нет, сломал бы сходимость.
 * Проверяется на настоящих программах корпуса, а не на выдуманной: выдуманная
 * доказывала бы, что так бывает.
 */
test("программа без блока `в монаде` проходит разворачивание НЕИЗМЕННОЙ", () => {
  const беды = []
  let счёт = 0
  for (const { путь, ast } of ПРОГРАММЫ) {
    const было = JSON.stringify(ast)
    const эталон = JSON.stringify(expandMonads(structuredClone(ast)))
    const наш = монады("Развернуть монады", { программа: значение(ast) })
    if (наш.variant !== "Развёрнуто") {
      беды.push(`${путь}: близнец отказал там, где эталон прошёл`)
      continue
    }
    const текст = JSON.stringify(изЗначения(наш.fields["программа"]))
    if (текст !== эталон) беды.push(`${путь}: ${расхождение(эталон, текст)}`)
    else if (текст !== было) беды.push(`${путь}: разворачивание тронуло программу, в которой трогать нечего`)
    else счёт += 1
  }
  assert.deepEqual(беды, [], `разворачивание разошлось на ${беды.length} программах`)
  assert.ok(счёт > 100, `программ прошло всего ${счёт}`)
})

