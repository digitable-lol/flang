/**
 * Пять объявленных свойств, написанные на самом flang — `flang/self/svoystva.flang`
 * и модули законов рядом с ним.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы вердикт
 * свойства на flang обязан совпасть с вердиктом свидетеля — те же диагностики, код
 * в код, текст в текст, место в место, ТЕ ЖЕ ЧИСЛА СЕТКИ и ТЕ ЖЕ РАЗРЕШЕНИЯ.
 * Сверка побайтовая, вместе с порядком ключей; расхождение печатается с номером
 * знака.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 * Эталона у пяти свойств не было ВОВСЕ: `flang/src/svoystva.mjs` (172 строки),
 * `commutative.mjs` (131), `distributive.mjs` (157), `idempotent.mjs` (196),
 * `partialorder.mjs` (241) и `monotone.mjs` (231) отвечали на корпусе в
 * одиночку. Мера этого — не «не реализовано», а число: в корпусе было 226
 * программ, объявленных свойств в них 12 на четырёх файлах (`flang/examples/cat`),
 * и записей отчёта эти двенадцать дают 24 — по свойствам это 8 коммутативности,
 * 8 идемпотентности, 4 частичного порядка, 2 дистрибутивности и 2 монотонности.
 * До этой работы все 24 считал только свидетель, и второго мнения о них не было ни
 * одного. Теперь их считают двое, и сверка ниже требует побайтового совпадения
 * всех 24 на каждом прогоне.
 *
 * ── Почему числа сетки важнее всего остального ──────────────────────────────
 * Пять свойств — проверки, которые НЕ ДОКАЗЫВАЮТСЯ. Равенство вычислений на всех
 * значениях носителя неразрешимо, поэтому у каждого закона есть предел сетки, и
 * ведомость печатает про них «сетка N значений», а не «доказано». Числа N
 * приезжают в ведомость отсюда — из `checked`. Значит эталон, дающий другое N,
 * не «слегка расходится»: он печатает в ведомости другое утверждение о том же
 * коде.
 *
 * ── Разрешения сверяются наравне с вердиктом ────────────────────────────────
 * `permits` — не украшение отчёта: это то, что компилятору позволено делать
 * после проверки и не было позволено до неё. Разрешение, выданное эталоном там,
 * где свидетель его не выдал, — расхождение той же цены, что потерянная
 * диагностика, и сверяется оно так же побайтово.
 *
 * ── Откуда берётся таблица вызовов, и ЧЕМ она посчитана ─────────────────────
 * Законам мало РАЗОБРАТЬ программу — им надо её ВЫПОЛНИТЬ. Языку flang нечем
 * передать функцию функцией (первого класса у него нет), поэтому вызовы
 * приезжают в эталона данными, и строит эту таблицу здешний оракул. Считает же
 * её вычислитель, написанный на flang, — `self/interpret.flang` через
 * `self-evaluator.mjs`. Отсюда проверка в конце файла: сломай вычислитель в одном
 * месте — вердикт свойств обязан разойтись с свидетелем.
 *
 * Оракул НЕ РЕШАЕТ ничего из того, что решает эталон. Он берёт все значения,
 * которые автор написал в примерах названных функций, без отбора и без предела —
 * отбор, порядок и предел сетки остаются за эталоном, — и вычисляет на них
 * замыкание тех вызовов, которые свидетель может сделать. Ошибиться так можно ровно
 * в одну сторону: недостающий вызов эталон назовёт вслух («вызова нет в
 * таблице»), и сверка от этого покраснеет, а не позеленеет. Отдельный тест ниже
 * стережёт, что этих слов не появилось ни разу.
 */
