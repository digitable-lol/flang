/**
 * КЛЮЧ ТИПА, И ОШИБКА СВИДЕТЕЛЯ, КОТОРУЮ ОН ПРЕДЪЯВЛЯЕТ.
 *
 * `ключТипа` свидетеля читает у списка поля `item` и `element`, а разборщик пишет
 * `of`. Ни одного узла с `item` в дереве нет, значит ключ ЛЮБОГО списка у
 * свидетеля — `list:null`, и `список числа` неотличим от `список строки`. Ошибка
 * названа, а не исправлена: эталон обязан отвечать то же самое, иначе разошёлся
 * бы молча и в пользу более правильного ответа — худший вид расхождения.
 */
test("ключ типа у эталона тот же, что у свидетеля, вместе с ошибкой свидетеля про список", () => {
  const типы = [
    { kind: "number" },
    { kind: "named", name: "Счётчики" },
    { kind: "string" },
    { kind: "boolean" },
    { kind: "list", of: { kind: "number" } },
    { kind: "list", of: { kind: "string" } },
    null,
  ]
  for (const тип of типы) {
    const наш = основа.среда.call("Ключ типа", { "тип": значение(тип) })
    assert.equal(наш, ключТипа(тип) ?? "", JSON.stringify(тип))
  }
  /* И само расхождение свидетеля с разбором — числом, а не словами. */
  assert.equal(ключТипа({ kind: "list", of: { kind: "number" } }), "list:null")
  assert.equal(ключТипа({ kind: "list", of: { kind: "string" } }), "list:null")
})
