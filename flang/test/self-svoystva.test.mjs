/**
 * СЧЁТ ОТВЕТОВ: чем посчитан каждый, и не осталось ли уступок.
 *
 * Улика, а не украшение отчёта: «свидетелем 0» обязано быть напечатано, иначе
 * «круг замкнут» нечем ни подтвердить, ни опровергнуть.
 */
const счёт = { свидетелем: 0, вычислителем: 0, вне: [] }

/** Слой вычислителя. Переменная — ради доказательства изъятием (см. конец файла). */
let слойВычислителя = средаСлоя

/** Аргумент в форме эталона: пустое место и `ничто` — разные аргументы. */
const аргументом = (з) =>
  з === undefined ? вариантЗначения("Нет аргумента") : вариантЗначения("Есть аргумент", { значение: значение(з) })

/**
 * Вызов вычислителя: имя функции и позиционные аргументы.
 *
 * Тот же путь, каким зовёт `звать` из `src/svoystva.mjs`: имена берутся из
 * `params` по порядку, лишние аргументы отбрасываются, недостающие приходят
 * пустым местом. Отказ вычисления — не исключение теста, а ответ: закон
 * проверить не на чем, и эталон обязан сказать об этом тем же текстом.
 */
function позвать(программа, наш, имя, аргументы) {
  const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
  if (!функция) return { нет: true }
  const назван = {}
  ;(функция.params ?? []).forEach((параметр, номер) => {
    назван[параметр.name] = аргументы[номер]
  })
  const ответ = наш.звать(имя, назван)
  if (ответ.вне !== undefined) {
    счёт.вне.push(`${имя}: ${ответ.вне}`)
    return { ошибка: ответ.вне }
  }
  счёт.вычислителем += 1
  return ответ.отказ === undefined ? { значение: ответ.значение } : { ошибка: ответ.отказ }
}

/**
 * Таблица вызовов одной программы.
 *
 * Ключ строит САМ ЭТАЛОН («Ключ вызова»): формат ключа — его дело, и вторая
 * его копия здесь разошлась бы с первой молча.
 */
function таблицаВызовов(программа) {
  const наш = вычислитель(программа, ШАГИ, слойВычислителя)
  const строки = new Map()
  const записать = (имя, аргументы) => {
    const ключ = основа.среда.call("Ключ вызова", { "имя": имя, "аргументы": аргументы.map(аргументом) })
    if (строки.has(ключ)) return строки.get(ключ)
    const итог = позвать(программа, наш, имя, аргументы)
    строки.set(ключ, итог)
    return итог
  }
  return { записать, строки }
}

/* Строка таблицы: имени, которого в программе нет, в таблице не место — про
   такое эталон отвечает сам, не заглядывая в неё. */
const строкиТаблицы = (строки) =>
  [...строки]
    .filter(([, итог]) => итог.нет !== true)
    .map(([ключ, итог]) => ({
      "ключ": ключ,
      "ответ":
        итог.ошибка === undefined
          ? вариантЗначения("Вызов дал", { "значение": значение(итог.значение) })
          : вариантЗначения("Вызов отказал", { "сообщение": итог.ошибка }),
    }))

/**
 * Предел числа значений, на которых оракул строит замыкание.
 *
 * Заведомо больше предела сетки: сетка эталона — начало этого списка, а
 * таблица обязана быть шире сетки, иначе недостающий вызов был бы виден только
 * как отсутствие.
 */
const ПРЕДЕЛ_ОРАКУЛА = ПРЕДЕЛ_СЕТКИ + 4

/* Повторы отсеиваются по печати значения — механически, а не по правилу
   эталона: эталон считает повтором большее (запись с теми же ключами в
   другом порядке), поэтому его сетка — подмножество этого списка. */
function безПовторов(значения) {
  const видели = new Set()
  const итог = []
  for (const з of значения) {
    if (з === undefined) continue
    const ключ = JSON.stringify(з)
    if (видели.has(ключ)) continue
    видели.add(ключ)
    итог.push(з)
  }
  return итог.slice(0, ПРЕДЕЛ_ОРАКУЛА)
}

/** Все значения, написанные автором в примерах названных функций. Отбора нет. */
function значенияПримеров(программа, имена, толькоВходы = false) {
  const собрано = []
  for (const имя of имена) {
    if (typeof имя !== "string" || имя === "") continue
    const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
    for (const пример of функция?.examples ?? []) {
      for (const з of Object.values(пример.args ?? {})) собрано.push(з)
      if (!толькоВходы) собрано.push(пример.expected)
    }
  }
  return собрано
}

const объявления = (программа, имя) =>
  (Array.isArray(программа.properties) ? программа.properties : []).filter((узел) => узел?.name === имя)

/**
 * Замыкание вызовов всех пяти свойств одной программы.
 *
 * Одна таблица на программу, а не пять: ключ у вызова один, и пять таблиц
 * разошлись бы там, где два свойства объявлены об одной операции — а это ровно
 * `flang/examples/cat/crdt-merge.flang`, где «Слить» объявлена и идемпотентной,
 * и коммутативной.
 */
function оракул(программа) {
  const свойства = Array.isArray(программа.properties) ? программа.properties : []
  if (свойства.length === 0) return []
  const { записать, строки } = таблицаВызовов(программа)

  const входов = (имя) =>
    ((программа.functions ?? []).find((кандидат) => кандидат.name === имя)?.params ?? []).length

  for (const узел of объявления(программа, "коммутативность")) {
    const значения = безПовторов(значенияПримеров(программа, [узел.operation]))
    for (const а of значения) for (const б of значения) записать(узел.operation, [а, б])
  }

  for (const узел of объявления(программа, "идемпотентность")) {
    const значения = безПовторов(значенияПримеров(программа, [узел.operation]))
    for (const х of значения) {
      if (входов(узел.operation) === 2) записать(узел.operation, [х, х])
      else записать(узел.operation, [записать(узел.operation, [х]).значение])
    }
  }

  /* Дистрибутивность кубична по сетке, и замыкание строится ровно теми
     вызовами, какие может сделать свидетель: сумма пары, свёрнутое произведение,
     оба произведения по частям и сумма частей — по разу на каждую сторону. */
  for (const узел of объявления(программа, "дистрибутивность")) {
    const значения = безПовторов(значенияПримеров(программа, [узел.operation, узел.over]))
    const умн = (а, б) => записать(узел.operation, [а, б])
    const слож = (а, б) => записать(узел.over, [а, б])
    for (const а of значения) {
      for (const б of значения) {
        for (const в of значения) {
          const сумма = слож(б, в).значение
          /* Свёрнутое произведение записывается ради следа в таблице: сравнивать
             его будет эталон, а не оракул. Части же складываются, и эта сумма —
             второй вызов второй операции, тот самый «раскрытым». */
          for (const [свёрнуто, первая, вторая] of [
            [() => умн(а, сумма), () => умн(а, б), () => умн(а, в)],
            [() => умн(сумма, а), () => умн(б, а), () => умн(в, а)],
          ]) {
            свёрнуто()
            слож(первая().значение, вторая().значение)
          }
        }
      }
    }
  }

  /* Порядок спрашивает отношение на ВСЕХ упорядоченных парах сетки: рефлексивность
     живёт на диагонали, антисимметрия — на обеих сторонах, транзитивность — на
     тех же парах. Замыкание на этом и кончается: третьего значения тройки в
     новый вызов не приходит. */
  for (const узел of объявления(программа, "частичный порядок")) {
    const значения = безПовторов(значенияПримеров(программа, [узел.operation], true))
    for (const а of значения) for (const б of значения) записать(узел.operation, [а, б])
  }

  /* Монотонность спрашивает ТРИ вещи: порядок домена на парах сетки, саму
     функцию на каждом значении и порядок кодомена на образах. Какой из
     объявленных порядков окажется доменным, решает эталон, а не оракул, —
     поэтому замыкание строится по КАЖДОМУ объявленному порядку. Так оракул
     остаётся заведомым надмножеством и не принимает ни одного решения сверки. */
  for (const узел of объявления(программа, "монотонность")) {
    const свои = значенияПримеров(программа, [узел.function], true)
    const порядки = объявления(программа, "частичный порядок")
    for (const домен of порядки) {
      const значения = безПовторов([...свои, ...значенияПримеров(программа, [домен.operation], true)])
      for (const а of значения) for (const б of значения) записать(домен.operation, [а, б])
      const образы = значения.map((х) => записать(узел.function, [х]).значение)
      /* Порядок кодомена — ЛЮБОЙ из объявленных, а не тот же, что доменный: у
         `flang/examples/cat/crdt-merge.flang` вход «Счётчики», а результат число,
         и порядки у них разные. Перебор по обоим спискам оставляет оракул
         надмножеством и не даёт ему решить за эталона, какой конец чей. */
      for (const кодомен of порядки) {
        for (const а of образы) for (const б of образы) записать(кодомен.operation, [а, б])
      }
    }
  }

  return строкиТаблицы(строки)
}

