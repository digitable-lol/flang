/**
 * ГЛАВНОЕ ДОКАЗАТЕЛЬСТВО ТОГО, ЧТО КРУГ ЗАМКНУЛСЯ.
 *
 * Вычислитель на flang ломается в ОДНОМ месте — вычитание становится сложением,
 * — и вердикт свойства обязан разойтись с свидетелем. Пока ответы вычислений
 * приезжали в эталона готовой таблицей, эта порча не меняла бы РОВНО НИЧЕГО.
 *
 * Порядок обязателен: сначала на ЦЕЛОМ вычислителе расхождения нет — иначе
 * «поймано» ничего не значило бы.
 */
