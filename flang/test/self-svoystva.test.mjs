/**
 * ИЗЪЯТИЕ: испорченный близнец обязан покраснеть НА НАСТОЯЩЕЙ ПРОГРАММЕ КОРПУСА.
 *
 * Порча одна и она в одном месте — счётчик пар растёт на два вместо одного, — а
 * судят её не рукописной пробой, а `flang/examples/cat/fold-by-cores.flang`:
 * файлом, который лежит в дереве и который считает настоящую свёртку по ядрам.
 * Сверка, краснеющая только на пробе, доказывала бы, что умеет краснеть, и не
 * доказывала бы, что смотрит на корпус.
 *
 * Порядок обязателен: сначала на ЦЕЛОМ близнеце расхождения нет.
 */
/**
 * Слой, собранный с испорченным файлом — своим или ввезённым.
 *
 * Порча идёт через чтение файлов при связывании, а не через дерево: испортить
 * можно и общую основу `svoystva.flang`, которую близнец ввозит, — а до неё иначе
 * не дотянуться, не тронув настоящих файлов.
 */
async function слойСПорчей(слой, файл, было, стало) {
  let заменено = 0
  const патч = (путь) => {
    const текст = readFileSync(путь, "utf8")
    if (!String(путь).endsWith(файл)) return текст
    const испорчено = текст.replace(было, стало)
    if (испорчено !== текст) заменено += 1
    return испорчено
  }
  const исходник = патч(слой.путь)
  const { diagnostics: _, ...порченая } = await linkProgram(слой.путь, исходник, parse, { readFile: патч })
  assert.equal(заменено, 1, `${файл}: порча заменила ${заменено} мест — сама порча устарела`)
  return createRuntime(порченая, ШАГИ)
}

const ИЗЪЯТИЯ = [
  [
    коммутативность,
    "commutative.flang",
    "flang/examples/cat/fold-by-cores.flang",
    () => расхождениеКоммутативности,
    "«пар» равным ((«ход».«пар») плюс 1)",
    "«пар» равным ((«ход».«пар») плюс 2)",
  ],
  [
    идемпотентность,
    "idempotent.flang",
    "flang/examples/cat/retry-safe.flang",
    () => расхождениеИдемпотентности,
    /* Порча в РАЗРЕШЕНИИ, а не в вердикте: разрешение — это то, что компилятору
       позволено после проверки, и подмена одного слова в нём меняет отчёт, не
       трогая ни одной диагностики. Сверка, смотрящая только на вердикт, прошла
       бы мимо. */
    "» безопасно: второе применение результата не меняет",
    "» можно: второе применение результата не меняет",
  ],
  [
    дистрибутивность,
    "distributive.flang",
    "flang/examples/cat/split-lines.flang",
    () => расхождениеДистрибутивности,
    /* Порча во ВТОРОЙ ОПЕРАЦИИ отчёта: закон говорит о совместном поведении
       двух, и запись, назвавшая вместо второй первую, — вердикт о другом
       утверждении при тех же числах сетки. */
    "и «по» равным «по» и «значений»",
    "и «по» равным «операция» и «значений»",
  ],
  [
    дистрибутивность,
    "svoystva.flang",
    "flang/examples/cat/split-lines.flang",
    () => расхождениеДистрибутивности,
    /* Порча в ОБЩЕЙ ОСНОВЕ, а не в законе: предел сетки объявлен один раз на
       пятерых, и разойтись в нём значит напечатать в ведомости другое
       утверждение о том же коде — «сетка 6» вместо «сетка 7». */
    "  пример «Двенадцать»\n    ожидается 12\n  12\n",
    "  пример «Двенадцать»\n    ожидается 12\n  6\n",
  ],
]

test("ИЗЪЯТИЕ: испорченный близнец краснеет на настоящей программе корпуса", async (t) => {
  for (const [слой, файл, путь, сверить, было, стало] of ИЗЪЯТИЯ) {
    const программа = parse(readFileSync(`${корень}${путь}`, "utf8"), путь)
    assert.equal(сверить()(программа), null, `${файл}: на целом близнеце ${путь} обязана сходиться`)

    const целая = слой.среда
    слой.среда = await слойСПорчей(слой, файл, было, стало)
    try {
      const беда = сверить()(программа)
      assert.match(беда ?? "", /разошлось на знаке \d+/u, `${файл}: испорченный близнец прошёл незамеченным`)
      t.diagnostic(`${файл} на ${путь}: ${беда.split("\n")[0]}`)
    } finally {
      слой.среда = целая
    }
  }
})

