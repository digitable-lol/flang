/**
 * Каждый закон — свой модуль, и собирается он своим слоем: `svoystva.flang`
 * общей основой не отменяет порознь лежащих законов, а держит у них общее.
 * Порознь они лежат по требованию владельца языка и по тому же доводу, по
 * какому порознь лежат `iso.flang` и `sets.flang`: следствие у каждого своё.
 */
const ШАГИ = { maxSteps: 40_000_000 }

async function слой(имя) {
  const путь = fileURLToPath(new URL(`../self/${имя}`, import.meta.url))
  const исходник = readFileSync(путь, "utf8")
  const свой = parse(исходник, `self/${имя}`)
  const { diagnostics: связка, ...программа } = await linkProgram(путь, исходник, parse)
  const типы = checkTypes(программа)
  const тотальность = checkTotality(программа)
  return {
    имя,
    путь,
    исходник,
    свой,
    программа,
    связка,
    типы,
    тотальность,
    среда: createRuntime(программа, ШАГИ),
  }
}

const основа = await слой("svoystva.flang")
const коммутативность = await слой("commutative.flang")

const СЛОИ = [основа, коммутативность]

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-laws.test.mjs`, и по той же причине: иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и эталон их различает. */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/** Диагностика на flang, приведённая к форме эталона (`{code, message, severity, span}`). */
const образцовая = (беда) => ({
  code: беда["код"],
  message: беда["сообщение"],
  severity: беда["важность"],
  span: беда["есть место"] ? { line: беда["строка"], column: беда["столбец"] } : null,
})

/** Пропуск и разрешение — форма у всех пяти одна. */
const допущение = (п) => ({
  property: п["свойство"],
  subject: п["есть предмет"] ? п["предмет"] : null,
  why: п["почему"],
})

const разрешение = (р) => ({
  permit: р["разрешение"],
  property: р["свойство"],
  subject: р["предмет"],
  says: р["говорит"],
})

/* ─────────────────────────── оракул вызовов ─────────────────────────── */

/**
 * СЧЁТ ОТВЕТОВ: чем посчитан каждый, и не осталось ли уступок.
 *
 * Улика, а не украшение отчёта: «эталоном 0» обязано быть напечатано, иначе
 * «круг замкнут» нечем ни подтвердить, ни опровергнуть.
 */
const счёт = { эталоном: 0, вычислителем: 0, вне: [] }

/** Слой вычислителя. Переменная — ради доказательства изъятием (см. конец файла). */
let слойВычислителя = средаСлоя

/** Аргумент в форме близнеца: пустое место и `ничто` — разные аргументы. */
const аргументом = (з) =>
  з === undefined ? вариантЗначения("Нет аргумента") : вариантЗначения("Есть аргумент", { значение: значение(з) })

/**
 * Вызов вычислителя: имя функции и позиционные аргументы.
 *
 * Тот же путь, каким зовёт `звать` из `src/svoystva.mjs`: имена берутся из
 * `params` по порядку, лишние аргументы отбрасываются, недостающие приходят
 * пустым местом. Отказ вычисления — не исключение теста, а ответ: закон
 * проверить не на чем, и близнец обязан сказать об этом тем же текстом.
 */
function позвать(программа, наш, имя, аргументы) {
  const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
  if (!функция) return { нет: true }
  const назван = {}
  ;(функция.params ?? []).forEach((параметр, номер) => {
    назван[параметр.name] = аргументы[номер]
  })
  const ответ = наш.звать(имя, назван)
  if (ответ.вне !== undefined) {
    счёт.вне.push(`${имя}: ${ответ.вне}`)
    return { ошибка: ответ.вне }
  }
  счёт.вычислителем += 1
  return ответ.отказ === undefined ? { значение: ответ.значение } : { ошибка: ответ.отказ }
}

/**
 * Таблица вызовов одной программы.
 *
 * Ключ строит САМ БЛИЗНЕЦ («Ключ вызова»): формат ключа — его дело, и вторая
 * его копия здесь разошлась бы с первой молча.
 */
function таблицаВызовов(программа) {
  const наш = вычислитель(программа, ШАГИ, слойВычислителя)
  const строки = new Map()
  const записать = (имя, аргументы) => {
    const ключ = основа.среда.call("Ключ вызова", { "имя": имя, "аргументы": аргументы.map(аргументом) })
    if (строки.has(ключ)) return строки.get(ключ)
    const итог = позвать(программа, наш, имя, аргументы)
    строки.set(ключ, итог)
    return итог
  }
  return { записать, строки }
}

/* Строка таблицы: имени, которого в программе нет, в таблице не место — про
   такое близнец отвечает сам, не заглядывая в неё. */
const строкиТаблицы = (строки) =>
  [...строки]
    .filter(([, итог]) => итог.нет !== true)
    .map(([ключ, итог]) => ({
      "ключ": ключ,
      "ответ":
        итог.ошибка === undefined
          ? вариантЗначения("Вызов дал", { "значение": значение(итог.значение) })
          : вариантЗначения("Вызов отказал", { "сообщение": итог.ошибка }),
    }))

/**
 * Предел числа значений, на которых оракул строит замыкание.
 *
 * Заведомо больше предела сетки: сетка близнеца — начало этого списка, а
 * таблица обязана быть шире сетки, иначе недостающий вызов был бы виден только
 * как отсутствие.
 */
const ПРЕДЕЛ_ОРАКУЛА = ПРЕДЕЛ_СЕТКИ + 4

/* Повторы отсеиваются по печати значения — механически, а не по правилу
   близнеца: близнец считает повтором большее (запись с теми же ключами в
   другом порядке), поэтому его сетка — подмножество этого списка. */
function безПовторов(значения) {
  const видели = new Set()
  const итог = []
  for (const з of значения) {
    if (з === undefined) continue
    const ключ = JSON.stringify(з)
    if (видели.has(ключ)) continue
    видели.add(ключ)
    итог.push(з)
  }
  return итог.slice(0, ПРЕДЕЛ_ОРАКУЛА)
}

/** Все значения, написанные автором в примерах названных функций. Отбора нет. */
function значенияПримеров(программа, имена, толькоВходы = false) {
  const собрано = []
  for (const имя of имена) {
    if (typeof имя !== "string" || имя === "") continue
    const функция = (программа.functions ?? []).find((кандидат) => кандидат.name === имя)
    for (const пример of функция?.examples ?? []) {
      for (const з of Object.values(пример.args ?? {})) собрано.push(з)
      if (!толькоВходы) собрано.push(пример.expected)
    }
  }
  return собрано
}

const объявления = (программа, имя) =>
  (Array.isArray(программа.properties) ? программа.properties : []).filter((узел) => узел?.name === имя)

/**
 * Замыкание вызовов всех пяти свойств одной программы.
 *
 * Одна таблица на программу, а не пять: ключ у вызова один, и пять таблиц
 * разошлись бы там, где два свойства объявлены об одной операции — а это ровно
 * `flang/examples/cat/crdt-merge.flang`, где «Слить» объявлена и идемпотентной,
 * и коммутативной.
 */
function оракул(программа) {
  const свойства = Array.isArray(программа.properties) ? программа.properties : []
  if (свойства.length === 0) return []
  const { записать, строки } = таблицаВызовов(программа)

  for (const узел of объявления(программа, "коммутативность")) {
    const значения = безПовторов(значенияПримеров(программа, [узел.operation]))
    for (const а of значения) for (const б of значения) записать(узел.operation, [а, б])
  }

  return строкиТаблицы(строки)
}

/* ─────────────────────────── сверка ─────────────────────────── */

/** Коммутативность на flang, приведённая к форме эталона. */
function нашаКоммутативность(программа, переведённая = значение(программа), таблица = оракул(программа)) {
  const итог = коммутативность.среда.call("Проверить коммутативность", {
    "программа": переведённая,
    "таблица": таблица,
  })
  return {
    diagnostics: итог["диагностики"].map(образцовая),
    checked: итог["проверено"].map((з) => ({
      property: з["свойство"],
      subject: з["предмет"],
      values: з["значений"],
      points: з["пар"],
      ...(з["нарушений"] === 0 ? {} : { violations: з["нарушений"] }),
      ...(з["оборвано"] === "" ? {} : { aborted: з["оборвано"] }),
    })),
    assumed: итог["допущено"].map(допущение),
    permits: итог["разрешено"].map(разрешение),
  }
}

/**
 * Побайтовое расхождение двух итогов — вместе с ПОРЯДКОМ КЛЮЧЕЙ.
 *
 * Номер знака в ответе обязателен: «не совпало» на записи в две тысячи знаков
 * заставляет искать разницу глазами, а найти её надо за один взгляд.
 */
function расхождение(эталон, наш) {
  const слева = JSON.stringify(эталон)
  const справа = JSON.stringify(наш)
  if (слева === справа) return null
  const знаки = [...слева]
  const место = знаки.findIndex((знак, номер) => знак !== справа[номер])
  const окно = (текст) => текст.slice(Math.max(0, место - 30), место + 70)
  return `разошлось на знаке ${место === -1 ? слева.length : место}:\n    эталон …${окно(слева)}…\n    наш    …${окно(справа)}…`
}

const расхождениеКоммутативности = (программа) => расхождение(checkCommutativity(программа), нашаКоммутативность(программа))

