/**
 * УЛИКА, названная числом: сколько функций оракула НЕ несёт обещания
 * тотальности и почему их нельзя свести к нулю.
 *
 * Это и есть настоящая цена переноса, и она не та, что была записана. Оракул
 * выполняет чужую программу; обещать её завершение значило бы обещать
 * разрешимость остановки. У пяти законов рядом обычных функций по-прежнему ноль
 * — граница проходит ровно по вызову вычислителя, а не размазана по слою.
 */
test("обычные функции оракула названы числом, и у пяти законов их по-прежнему ноль", (t) => {
  /* Считается СВОЙ файл, а не связанная программа: в связанную приезжают чужие
     модули со своими обычными функциями, и число вышло бы про них. */
  const обычных = (слой) => слой.свой.functions.filter((ф) => ф.total !== true).length
  t.diagnostic(`оракул: функций ${оракулСлой.свой.functions.length}, из них обычных ${обычных(оракулСлой)}`)
  assert.ok(обычных(оракулСлой) > 0, "у оракула не осталось обычных функций — значит он перестал звать вычислитель")
  for (const слой of СЛОИ) assert.equal(обычных(слой), 0, `${слой.имя}: обычная функция появилась у закона`)
})

