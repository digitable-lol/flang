/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-totality.test.mjs` и `self-laws.test.mjs`, и по той же причине: иначе
   тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и свидетель их различает
   (`node.kind === undefined` — это отдельная ветка обхода). */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/* ─────────────────── две стороны сверки ─────────────────── */

/** `paramsOf` свидетеля — тот же, что у всех четырёх слоёв, которые его зовут. */
function параметрыПрограммы(программа) {
  const функции = new Map()
  for (const фн of программа.functions ?? []) {
    if (!функции.has(фн.name)) функции.set(фн.name, (фн.params ?? []).map((п) => (typeof п === "string" ? п : п?.name)))
  }
  return (имя) => функции.get(имя) ?? null
}

/**
 * Итог свидетеля в сверяемом виде.
 *
 * Кроме имени и захваченного сверяются ОБА производных имени: ключ (по нему
 * вычислитель ищет тег в множестве известных) и имя варианта (под ним тег
 * уезжает наружу и печатается в код). Эталон, совпавший списком, но
 * разошедшийся ключом, ломал бы вычислитель молча.
 */
function свидетельТегов(программа) {
  const параметры = параметрыПрограммы(программа)
  return [...programTags(программа, параметры).values()].map((тег) => ({
    name: тег.name,
    captured: тег.captured,
    key: tagKey(тег.name, тег.captured),
    variant: tagVariant(тег.name, тег.captured),
  }))
}

/** Итог эталона, приведённый к той же форме. */
function нашиТеги(программа, переведённая = значение(программа), движок = среда) {
  const теги = движок.call("Все теги программы", { "программа": переведённая })
  return теги.map((тег) => ({
    name: тег["имя"],
    captured: тег["захвачено"],
    key: движок.call("Ключ тега", { "имя": тег["имя"], "захвачено": тег["захвачено"] }),
    variant: движок.call("Имя тега в значении", { "имя": тег["имя"], "захвачено": тег["захвачено"] }),
  }))
}

/**
 * Побайтовое расхождение двух итогов — вместе с ПОРЯДКОМ КЛЮЧЕЙ.
 *
 * Номер знака в ответе обязателен: «не совпало» на списке в тысячу знаков
 * заставляет искать разницу глазами, а найти её надо за один взгляд.
 */
function расхождение(свидетель, наш) {
  const слева = JSON.stringify(свидетель)
  const справа = JSON.stringify(наш)
  if (слева === справа) return null
  const знаки = [...слева]
  const место = знаки.findIndex((знак, номер) => знак !== справа[номер])
  const окно = (текст) => текст.slice(Math.max(0, место - 30), место + 70)
  return `разошлось на знаке ${место === -1 ? слева.length : место}:\n    свидетель …${окно(слева)}…\n    наш    …${окно(справа)}…`
}

