/**
 * Теги программы, написанные на самом flang — `flang/self/tags.flang`.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы список
 * тегов у эталона обязан совпасть со списком свидетеля `flang/src/tags.mjs` —
 * те же теги, в том же ПОРЯДКЕ, с тем же захваченным, с тем же ключом и с тем
 * же именем варианта. Сверка побайтовая, вместе с порядком ключей; расхождение
 * печатается с номером знака.
 *
 * ── Почему порядок и ключ важны не меньше самого списка ─────────────────────
 * Список тегов — это список СЛУЧАЕВ ДИСПЕТЧЕРА, и его читают четыре слоя:
 *
 *   • `totality.mjs` разворачивает по нему применение в рёбра графа вызовов и
 *     на этом доказывает завершение;
 *   • `interpret.mjs` по нему же отказывается применять тег, которого программа
 *     не строит, — и это единственная преграда перед комбинатором Ω, поданным
 *     снаружи;
 *   • `defunc.mjs` печатает по нему случаи `switch`, и ПОРЯДОК случаев там
 *     наблюдаем: он попадает в напечатанный код побайтово;
 *   • `types.mjs` разбирает по нему тег, пришедший значением.
 *
 * Разойдись список хоть на один тег или хоть на одну позицию — и доказанное
 * перестало бы соответствовать исполняемому. Поэтому сверяется не «нашлись ли
 * теги», а весь список целиком, вместе с ключом и именем варианта.
 *
 * ── Улика ДО, числом ────────────────────────────────────────────────────────
 * Корпус — 228 программ `.flang` репозитория. Тег строит РОВНО ОДНА форма
 * языка, и написана она сегодня в двух программах: `flang/stdlib/higher-order.flang`
 * (13 тегов) и `flang/proof/examples/corpus-hof.flang` (6). Остальные 226
 * обязаны давать ПУСТОЙ список — и это половина сверки, а не её отсутствие:
 * обход идёт по всему AST каждой программы, и лишний тег, найденный на пустом
 * месте, покраснеет ровно так же, как потерянный на месте настоящем.
 *
 * Чтобы «пусто у обоих» не стало единственным содержанием сверки, ниже стоит и
 * обратная половина: программ с непустым списком не меньше двух, а тегов в них
 * не меньше девятнадцати.
 *
 * ── Умеет ли сверка краснеть ────────────────────────────────────────────────
 * Отдельный раздел в конце: эталон собирается из НАРОЧНО ИСПОРЧЕННОГО
 * исходника — три порчи, по одной на каждое решение слоя, — и сверка обязана
 * покраснеть НА НАСТОЯЩЕЙ ПРОГРАММЕ КОРПУСА, а не на выдуманной. Сверка, не
 * умеющая краснеть, — не сверка.
 */
