/* ────────────────── умеет ли сверка краснеть: ИЗЪЯТИЕ ────────────────── */

/**
 * Порча — СМЫСЛОВАЯ: слой остаётся собираемым, типы сходятся, тотальность
 * доказана, и покраснеть обязана именно сверка, а не сборка. Каждая порча бьёт
 * по СВОЕМУ решению слоя.
 *
 * ── ЧТО КОРПУС ПОКАЗАТЬ НЕ МОЖЕТ, И ЭТО НАЗВАНО ЧИСЛОМ ──────────────────────
 * Тегов с захватом в корпусе СЕГОДНЯ НОЛЬ: все 19 тегов на 229 программах —
 * без частичного применения. Значит порча, бьющая по захвату (слово склейки,
 * порядок захваченного, отбор написанных полей), на настоящей программе
 * покраснеть НЕ МОЖЕТ — не потому, что сверка слаба, а потому, что корпус этой
 * формы не пишет. Проверено прогоном: две такие порчи прошли сверку на
 * `flang/stdlib/higher-order.flang` молча.
 *
 * Отсюда изъятия разделены честно, а не подогнаны:
 *   • по обходу и по опознанию узла — НА НАСТОЯЩЕЙ программе корпуса;
 *   • по захвату — на нарочных программах, и рядом сказано, почему иначе
 *     нельзя. Появится в корпусе первое частичное применение — эти две порчи
 *     обязаны покраснеть и на нём, и тогда их место здесь же.
 */
const НАСТОЯЩАЯ = "flang/stdlib/higher-order.flang"
const настоящая = parse(readFileSync(`${корень}${НАСТОЯЩАЯ}`, "utf8"), НАСТОЯЩАЯ)

async function испорченный(что, чем) {
  assert.ok(исходник.includes(что), `порча не нашла места: ${что}`)
  const текст = исходник.replace(что, чем)
  const { diagnostics: беды, ...программа } = await linkProgram(файл, текст, parse)
  assert.deepEqual(беды, [], "порча не должна ломать связывание — иначе краснеет сборка, а не сверка")
  return createRuntime(программа, ШАГИ)
}

test("изъятие: обход перестал спускаться в поля записи — сверка краснеет на настоящей программе", async () => {
  const движок = await испорченный(
    `      то свёртка («Поля узла» от «узел») начиная с («Отметить узел» от «программа» и «собрано» и «узел») как «текущее» и «поле» → («Обойти узел» от «программа» и «текущее» и («поле».«значение»))`,
    `      то «Отметить узел» от «программа» и «собрано» и «узел»`,
  )
  const беда = расхождение(свидетельТегов(настоящая), нашиТеги(настоящая, значение(настоящая), движок))
  assert.notEqual(беда, null, `${НАСТОЯЩАЯ}: порченый обход прошёл сверку`)
})

