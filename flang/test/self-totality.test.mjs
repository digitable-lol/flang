/**
 * Лимит шагов поднят с сорока миллионов до двухсот восьмидесяти, и поднят по
 * замеру, а не «чтобы прошло».
 *
 * Анализ — работа с целым AST сразу, и до 15 августа 2026 самой дорогой
 * программой репозитория был `flang/core/parser.flang` (280 функций после
 * связывания, 18 миллионов шагов); сорок миллионов были при нём двукратным
 * запасом. Сборка `work/svodka` влила с origin три слоя близнеца, и корпус
 * вырос вчетверо: `flang/self/monad.flang` — 1096 функций после связывания,
 * `flang/self/sets.flang` — 971. Замерено двоичным поиском по пределу:
 * monad укладывается в 131,6 млн шагов, sets — в 89,6 млн. Запас взят прежний,
 * двукратный, и не больше.
 *
 * Что при этом ПРОВЕРЕНО, а не просто разрешено: цена на функцию осталась того
 * же порядка — 64 тыс. шагов на функцию у `core/parser.flang`, 92 тыс. у
 * `self/sets.flang`, 120 тыс. у `self/monad.flang`. Рост объясняется размером
 * самих функций, а не сменой класса: обход остался линейным по числу узлов, а
 * разбор графа — линейным по числу рёбер. Поиск имени в области видимости,
 * ставший квадратичным по числу связок, упрётся в этот лимит и будет назван —
 * ровно за этим он и стоит.
 *
 * Глубина оставлена стандартной: рекурсия идёт по вложенности выражения, а
 * самая глубокая цепочка `если … иначе если …` в репозитории требует 29
 * кадров — на три порядка меньше штатного предела.
 */
const ШАГИ = { maxSteps: 280_000_000 }
const среда = createRuntime(программа, ШАГИ)
const вызвать = (имя, аргументы) => среда.call(имя, аргументы)

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Тот же, что в
   `self-emit-c.test.mjs`, и по той же причине: иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и эталон их различает. */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/** Диагностика на flang, приведённая к форме эталона (`{code, message, severity, span}`). */
const образцовая = (беда) => ({
  code: беда["код"],
  message: беда["сообщение"],
  severity: беда["важность"],
  span: беда["есть место"] ? { line: беда["строка"], column: беда["столбец"] } : null,
})

/** Анализ на flang для готового AST. */
function проверить(ast) {
  const итог = вызвать("Проверить тотальность", { "программа": значение(ast) })
  return {
    ok: итог["доказано"],
    diagnostics: итог["диагностики"].map(образцовая),
    total: итог["тотальные"],
  }
}

/** Обратный перевод «Значение» → JSON: тот же механический разбор, что выше. */
function изЗначения(узел) {
  if (узел.variant === "Значение списка") return узел.fields["элементы"].map(изЗначения)
  if (узел.variant === "Значение записи") {
    return Object.fromEntries(узел.fields["поля"].map((поле) => [поле["ключ"], изЗначения(поле["значение"])]))
  }
  const скаляр = узел.fields["скаляр"]
  return скаляр.variant === "Скаляр ничто" ? null : скаляр.fields["значение"]
}

/**
 * Отметка меры на flang против отметки эталона.
 *
 * Сверяется программа целиком и побайтово после сериализации: отметка — это
 * данные, которые читает понижение (`self/defunc.flang`, «Поставить
 * сторожей»), и разойтись в ней значит напечатать другой C. Здесь же видно и
 * главное свойство отметки: программа без числовой меры обязана пройти
 * насквозь неизменной, иначе печать разошлась бы там, где ничего не менялось.
 */
function расхождениеОтметок(ast) {
  const эталон = JSON.stringify(markMeasureGuards(ast))
  const наш = JSON.stringify(изЗначения(вызвать("Отметить меры", { "программа": значение(ast) })))
  if (эталон === наш) return null
  const слева = [...эталон]
  const место = слева.findIndex((знак, номер) => знак !== наш[номер])
  return `отметка разошлась на знаке ${место}:\n  эталон: ${эталон.slice(Math.max(0, место - 60), место + 120)}\n  наш:    ${наш.slice(Math.max(0, место - 60), место + 120)}`
}

/**
 * Сверка одной программы. Возвращает описание первого расхождения или null.
 * Сверяются все три составляющие вердикта: множество доказанных функций (в том
 * же порядке, в каком его отдаёт эталон), диагностики целиком и признак `ok`.
 */
function расхождение(ast, готовыйЭталон, готовыйНаш) {
  const эталон = готовыйЭталон ?? checkTotality(ast)
  const наш = готовыйНаш ?? проверить(ast)

  const ждём = [...эталон.total]
  if (JSON.stringify(ждём) !== JSON.stringify(наш.total)) {
    const лишние = наш.total.filter((имя) => !эталон.total.has(имя))
    const нехватка = ждём.filter((имя) => !наш.total.includes(имя))
    return `множество тотальных разошлось: лишние ${JSON.stringify(лишние)}, недостающие ${JSON.stringify(нехватка)}`
  }
  if (JSON.stringify(эталон.diagnostics) !== JSON.stringify(наш.diagnostics)) {
    for (const [индекс, беда] of эталон.diagnostics.entries()) {
      const есть = наш.diagnostics[индекс]
      if (JSON.stringify(беда) !== JSON.stringify(есть)) {
        return `диагностика ${индекс}: ${JSON.stringify(есть)} ≠ ${JSON.stringify(беда)}`
      }
    }
    return `лишняя диагностика: ${JSON.stringify(наш.diagnostics[эталон.diagnostics.length])}`
  }
  if (эталон.ok !== наш.ok) return `признак «доказано»: ${наш.ok} ≠ ${эталон.ok}`
  return null
}

