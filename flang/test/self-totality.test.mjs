test("totality.flang: отбор по номеру стоит постоянное время, а не длину списка", (t) => {
  /*
   * УЛИКА, РАДИ КОТОРОЙ ТЕСТ НАПИСАН. Три отбора по номеру («Имя по номеру»,
   * «Аргумент по номеру при анализе», «Узел по номеру при анализе») были
   * написаны СВЁРТКОЙ по всему списку: цена — длина списка при любом номере,
   * даже при нулевом. Замер витками ДО правки: 15 521 виток при 500 параметрах
   * и 124 021 при 4000, показатель роста 0,999 — линия. ПОСЛЕ, встроенной
   * формой `элемент N в СПИСОК`: 43 витка на обеих длинах, показатель 0,000.
   *
   * Меряются ВИТКИ, а не секунды: цена — наименьший бюджет шагов, при котором
   * вычисление доходит. Число целое, от загрузки машины не зависит, и по нему
   * видно КЛАСС, а не одну точку.
   *
   * Ответы при этом обязаны остаться прежними на всех номерах, включая те, где
   * встроенная форма отказала бы: вне списка, дробные, отрицательные и −0.
   * Заготовка «имени нет» им и достаётся — так же, как доставалась от свёртки.
   */
  const имена = (n) => Array.from({ length: n }, (_, к) => ({ есть: true, имя: `п${к}` }))
  const цена = (n) => {
    const доходит = (предел) => {
      try {
        evaluate(программа, "Имя по номеру", { параметры: имена(n), индекс: 0 }, { ...ШАГИ, maxSteps: предел })
        return true
      } catch (беда) {
        if (беда?.code === "FLANG_RECURSION_LIMIT") return false
        throw беда
      }
    }
    let низ = 1
    let верх = 1
    while (!доходит(верх)) {
      низ = верх + 1
      верх *= 2
      assert.ok(верх < 1e8, `«Имя по номеру» не доходит ни при каком бюджете на n=${n}`)
    }
    while (низ < верх) {
      const середина = Math.floor((низ + верх) / 2)
      if (доходит(середина)) верх = середина
      else низ = середина + 1
    }
    return низ
  }
  const малое = цена(500)
  const большое = цена(4000)
  const k = Math.log(большое / малое) / Math.log(8)
  t.diagnostic(`«Имя по номеру»: ${малое} витков при 500 параметрах, ${большое} при 4000 — показатель ${k.toFixed(3)}`)
  assert.ok(
    k < 0.3,
    `отбор подорожал с ${малое} до ${большое} при росте списка в 8 раз (показатель ${k.toFixed(3)}): ` +
      "номер снова ищется обходом всего списка",
  )

  /* Договор: где форма отказала бы, ответ обязан остаться заготовкой. */
  for (const [n, индекс, есть, имя] of [
    [0, 0, false, ""], [1, 0, true, "п0"], [3, 2, true, "п2"], [3, 3, false, ""],
    [3, -1, false, ""], [3, -0, false, ""], [3, 0.5, false, ""], [3, 1.5, false, ""],
  ]) {
    const ответ = evaluate(программа, "Имя по номеру", { параметры: имена(n), индекс }, ШАГИ)
    assert.equal(ответ["есть"], есть, `«Имя по номеру» n=${n}, индекс=${Object.is(индекс, -0) ? "-0" : индекс}`)
    assert.equal(ответ["имя"], имя, `«Имя по номеру» n=${n}, индекс=${Object.is(индекс, -0) ? "-0" : индекс}`)
  }
})

