/* ────────── очерёдность: мера в библиотеке и чтение меры анализом ────────── */

/**
 * Программа, у которой носитель обещания ровно один — ОБЪЯВЛЕННАЯ мера.
 *
 * Тот же двоичный поиск, что в списке выше стоит случаем «двоичный поиск по
 * сходящимся границам отвергается»: без строки `убывает` его отвергают оба
 * анализа, потому что `(низ плюс верх) делить на 2` не часть значения и не
 * постоянный шаг. Со строкой `убывает верх минус низ плюс 1` эталон его
 * доказывает — и доказывает единственным оставшимся способом.
 */
const пробаОбъявленнойМеры = программаИз([{
  name: "Половинить", total: true,
  params: [{ name: "низ", type: число }, { name: "верх", type: число }], returns: число,
  decreases: оп("add", оп("sub", пер("верх"), пер("низ")), лит(1)),
  body: {
    kind: "if", cond: оп("lte", пер("верх"), пер("низ")), then: пер("низ"),
    else: вызов("Половинить", оп("div", оп("add", пер("низ"), пер("верх")), лит(2)), пер("верх")),
  },
}])

/**
 * Очерёдность: `убывает` в библиотеке — не раньше, чем анализ близнеца научится
 * эту меру читать.
 *
 * `flang/stdlib/*.flang` входит в корпус неподвижной точки целиком, поэтому
 * библиотеке доступно ровно то подмножество языка, которое понимают ОБА
 * анализа — эталонный и самоприменённый. Объявленную меру сегодня понимает
 * только эталонный: `self/totality.flang` про неё не знает вовсе
 * (`flang/self/SPEC.md`, «Объявленной меры здесь нет»). Пока это так, `убывает`
 * в библиотеке означало бы, что слово `тотальная` значит в двух flang РАЗНОЕ:
 * у эталона функция доказана мерой и стережётся сторожем, у близнеца доказана
 * другим носителем либо не доказана совсем — и напечатанная им библиотека
 * уходит к пользователю без сторожа.
 *
 * Правило это до сих пор жило прозой (шапка двоичного поиска в
 * `flang/stdlib/lists.flang`), и цена прозы записана там же: когда меру внесли
 * в библиотеку раньше времени, покраснели семь проверок и ни одна не сказала
 * почему — сообщения были про байты («отметка разошлась на знаке 21599»).
 * Здесь то же самое сказано одним предложением и до прогона самораскрутки.
 *
 * СНИМАТЬ ЭТОТ ТЕСТ, КОГДА АНАЛИЗ НАУЧИТСЯ МЕРЕ, НЕ ПРИДЁТСЯ: левая половина
 * условия станет истинной, и правило начнёт выполняться само собой. Умение
 * близнеца спрашивается пробной программой, а не наличием слова в исходнике:
 * искать `decreases` в тексте `self/totality.flang` значило бы проверять
 * написание, а не способность.
 */
test("объявленная мера в библиотеке не опережает её чтение анализом близнеца", () => {
  /* Без этой строки сторож ослаб бы молча: стань проба доказуемой ДРУГИМ
     носителем, «близнец читает меру» стало бы истинным ни за что. */
  assert.ok(
    checkTotality(пробаОбъявленнойМеры).total.has("Половинить"),
    "проба обязана доказываться эталоном — и только объявленной мерой",
  )
  const читаетМеру = проверить(пробаОбъявленнойМеры).total.includes("Половинить")

  const модули = readdirSync(`${корень}flang/stdlib`).filter((имя) => имя.endsWith(".flang")).sort()
  assert.ok(модули.length >= 10, `модулей библиотеки всего ${модули.length}`)
  const сМерой = модули.filter((имя) => {
    const текст = readFileSync(`${корень}flang/stdlib/${имя}`, "utf8")
    return parse(текст, `flang/stdlib/${имя}`).functions.some((функция) => функция.decreases != null)
  })

  assert.ok(
    читаетМеру || сМерой.length === 0,
    `объявленная мера стоит в flang/stdlib/${сМерой.join(", flang/stdlib/")}, а самоприменённый анализ `
      + "(flang/self/totality.flang) её не читает. Эталон доказал бы эти функции мерой и поставил бы на них "
      + "сторожа, близнец — нет: «тотальная» стало бы значить в двух flang разное, а напечатанная близнецом "
      + "библиотека ушла бы без сторожа меры. Сначала объявленная мера как носитель в self/totality.flang, "
      + "и только потом мера в библиотеке",
  )
})

/* ───────────────────────────────── фаззинг ───────────────────────────────── */

/**
 * Случайные программы из тех же форм, что порождает парсер. Сид зафиксирован,
 * поэтому падение воспроизводится. Смысл здесь не в «а вдруг сломается», а в
 * покрытии сочетаний, которых нет ни в репозитории, ни в списке выше:
 * вложенные `разбор` внутри `свёртка` внутри `если`, циклы из трёх функций с
 * разными позициями убывания, вызовы с числом аргументов, не равным числу
 * параметров.
 */
test("фаззинг: случайные программы судятся так же, как эталоном", () => {
  let сид = 20240804
  const случайное = () => {
    сид = (сид * 1103515245 + 12345) % 2147483648
    return сид / 2147483648
  }
  const выбрать = (список) => список[Math.floor(случайное() * список.length)]
  const имена = ["А", "Б", "В"]

  const выражение = (глубина, связанные, свои) => {
    const простые = [
      () => лит(выбрать([0, 1, "т", null, true])),
      () => пер(выбрать(связанные)),
      () => пер("нет такого"),
    ]
    if (глубина <= 0) return выбрать(простые)()
    const составные = [
      () => оп(выбрать(["add", "sub", "mul", "gt"]), выражение(глубина - 1, связанные, свои), выражение(глубина - 1, связанные, свои)),
      () => ({ kind: "field", target: выражение(глубина - 1, связанные, свои), field: "поле" }),
      () => форма(выбрать(["хвост", "голова", "длина", "пусто", "добавить"]), выражение(глубина - 1, связанные, свои), выражение(глубина - 1, связанные, свои)),
      () => вызов(выбрать(имена.concat(["Нету"])), ...Array.from({ length: Math.floor(случайное() * 3) }, () => выражение(глубина - 1, связанные, свои))),
      () => ({ kind: "if", cond: выражение(глубина - 1, связанные, свои), then: выражение(глубина - 1, связанные, свои), else: выражение(глубина - 1, связанные, свои) }),
      () => ({ kind: "let", name: "п", value: выражение(глубина - 1, связанные, свои), in: выражение(глубина - 1, [...связанные, "п"], свои) }),
      () => ({ kind: "list", items: [выражение(глубина - 1, связанные, свои)] }),
      () => ({ kind: "construct", variant: "В", fields: { поле: выражение(глубина - 1, связанные, свои) } }),
      () => ({ kind: "record", type: "З", fields: { поле: выражение(глубина - 1, связанные, свои) } }),
      () => ({ kind: "fold", over: выражение(глубина - 1, связанные, свои), init: лит(0), acc: "акк", item: "эл", body: выражение(глубина - 1, [...связанные, "акк", "эл"], свои) }),
      () => ({ kind: выбрать(["map", "filter"]), over: выражение(глубина - 1, связанные, свои), item: "эл", body: выражение(глубина - 1, [...связанные, "эл"], свои) }),
      () => разбор(
        выражение(глубина - 1, связанные, свои),
        пустоСлучай(выражение(глубина - 1, связанные, свои)),
        головаИХвост("г", "х", выражение(глубина - 1, [...связанные, "г", "х"], свои)),
        { pattern: { kind: "variant", name: "Лист", bind: { поле: "в" } }, body: выражение(глубина - 1, [...связанные, "в"], свои) },
        { pattern: { kind: "any", bind: "всё" }, body: выражение(глубина - 1, [...связанные, "всё"], свои) },
      ),
    ]
    return выбрать(простые.concat(составные))()
  }

  for (let счёт = 0; счёт < 400; счёт += 1) {
    const сколько = 1 + Math.floor(случайное() * 3)
    const functions = Array.from({ length: сколько }, (_, индекс) => {
      const параметры = Array.from({ length: Math.floor(случайное() * 3) }, (_, номер) => ({ name: `п${номер}`, type: список(число) }))
      return {
        name: имена[индекс],
        total: случайное() < 0.8,
        params: параметры,
        returns: число,
        body: выражение(3, параметры.map((параметр) => параметр.name), имена),
      }
    })
    const ast = программаИз(functions)
    const беда = расхождение(ast)
    assert.equal(беда, null, `${беда}\n${JSON.stringify(ast)}`)
  }
})

