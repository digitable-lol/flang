/**
 * Анализ завершаемости, написанный на самом flang —
 * `flang/self/totality.flang`.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы вердикт
 * анализа на flang обязан совпасть с вердиктом эталона `flang/src/totality.mjs`
 * — то же множество доказанных функций и те же диагностики `FLANG_NOT_TOTAL`,
 * код в код, текст в текст, место в место.
 *
 * Слабее критерий делать нельзя, и не из перфекционизма: вердикт бинарный,
 * поэтому разойтись можно ровно в две стороны, и обе разрушают язык. Признать
 * тотальной функцию, которая может зациклиться, значит сломать факт-чекинг
 * (`flang/SPEC.md`, раздел 1: система, отвечающая «подтверждено или нет», не
 * имеет права зависнуть). Отвергнуть доказуемую значит без причины запретить
 * законную программу. Собственные тесты «на пару примеров» этого не ловят:
 * анализ обязан не «работать», а воспроизводить образец.
 *
 * Что покрывается сверх программ репозитория:
 *   • каждый `.flang` прогоняется дважды — связанным (импорты разрешены) и
 *     сырым (импортированные имена неизвестны). Второй прогон не искусственный:
 *     именно он даёт ветку «тотальная зовёт неизвестную функцию», которой на
 *     связанных программах не бывает ни разу;
 *   • нарочно сломанные программы, собранные руками по SPEC, раздел 5:
 *     рекурсия по неубывающему аргументу, по накопителю свёртки, взаимная
 *     рекурсия без общего убывания, убывание на разных позициях, убывание не на
 *     своей позиции, вызов обычной и вызов неизвестной; из числовых мер —
 *     нулевой и растущий шаг, шаг параметром, мера без базы, база-равенство при
 *     целом и дробном шаге, граница из чужой ветви, граница по чужому
 *     параметру, сравнение с параметром вместо литерала, деление пополам,
 *     остаток, отражение, ±бесконечность и NaN на месте границы;
 *   • то, что обязано проходить: хвост списка из образца и из встроенной формы,
 *     поле варианта, поле записи, элемент коллекции, взаимная рекурсия с общим
 *     убывающим аргументом; из мер — `н минус 1` при базе-неравенстве в обеих
 *     ветвях, литерал слева от имени, дробный шаг, `пусть` до `если`;
 *   • поимённые долги соседних слоёв — функции, названные нетотальными в
 *     `flang/self/SPEC.md`, обязаны быть нетотальными и здесь; а лексер, у
 *     которого долгов не осталось вовсе, обязан быть тотальным целиком.
 */
