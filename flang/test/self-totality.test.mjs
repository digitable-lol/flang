test("убывание не на своей позиции названо своим именем", () => {
  const итог = беда(программаИз([{
    name: "Перестановка", total: true, params: [{ name: "а", type: список(число) }, { name: "б", type: список(число) }], returns: число,
    body: разбор(пер("а"), пустоСлучай(лит(0)), головаИХвост("г", "х", вызов("Перестановка", пер("б"), пер("х")))),
  }]))
  /* Оба аргумента — части параметров, но каждый пришёл не на своё место:
     хвост «а» стоит вторым, а «б» целиком — первым. Цепочка частей одного
     значения не образуется ни на одной позиции. */
  assert.match(итог.message, /аргумент 1 \(«б»\) — часть параметра «б», а сравнивается с параметром «а» на своей позиции/u)
  assert.match(итог.message, /аргумент 2 \(«х»\) — часть параметра «а», а сравнивается с параметром «б» на своей позиции/u)
})

