/* ──────────────────────── гипотеза теоремы `дано` ───────────────────────── */

/**
 * Сверять гипотезу больше негде, и это не придирка к устройству теста.
 *
 * Теорем в дифференциальном корпусе (`flang/stdlib`, `flang/core`,
 * `flang/examples/leetcode`, `flang/self`) НОЛЬ: они живут в `flang/proof`, а
 * тот сюда не входит. Значит проход по гипотезам мог бы отсутствовать у
 * эталона целиком, и всё, что стоит выше, осталось бы зелёным — та же
 * слепота, что названа у отметок непустоты, и лечится она так же: своей
 * программой, а не надеждой на корпус.
 *
 * Обе половины обязательны. Дурная гипотеза обязана дать у обеих сторон один
 * код, один текст и одно место; верная — молчание у обеих. Без второй половины
 * сверялось бы наличие слова `дано`, а не тип того, что за ним написано.
 */
const ТЕОРЕМА = (гипотеза) => `модуль «М»
функция «Ф»
  принимает «н»: число
  возвращает число
  для всех «н» обеспечивает «п» результат не меньше 0
  «н»

теорема «п»
  дано «н»: число
${гипотеза === null ? "" : `  дано ${гипотеза}\n`}  утверждаем результат не меньше 0
  следовательно доказано
`

test("гипотеза теоремы: у эталона тот же отказ и то же молчание", () => {
  for (const гипотеза of ["5", '"строка"', '«н» плюс "строка"']) {
    const ast = разобрать(ТЕОРЕМА(гипотеза))
    assert.ok(checkTypes(ast).diagnostics.length > 0, `«${гипотеза}»: свидетель не нашёл ошибки`)
    const беда = расхождение(ast)
    assert.equal(беда, null, `дурная «${гипотеза}»: ${беда}`)
  }
  for (const гипотеза of [null, "«н» больше 0", "результат не меньше 0"]) {
    const ast = разобрать(ТЕОРЕМА(гипотеза))
    assert.deepEqual(checkTypes(ast).diagnostics, [], `верная «${String(гипотеза)}»: свидетель ругается`)
    const беда = расхождение(ast)
    assert.equal(беда, null, `верная «${String(гипотеза)}»: ${беда}`)
  }
})

