/**
 * `к числу или беда` — форма языка, а не выдумка: её знают лексер, разборщик и
 * все восемь рантаймов печати. Близнец проверки типов её НЕ ЗНАЛ, и всякая
 * программа с нею получала «неизвестная встроенная форма» там, где эталон
 * молчит.
 *
 * Корпус дыру не показывал и не мог: единственный файл дерева с этой формой
 * лежит в `flang/examples/errors/`, куда сверка выше не смотрит (она берёт
 * `stdlib`, `core`, `examples/leetcode` и `self`). Нашлось тем, что форму
 * позвал вычислитель на flang, — то есть чужой работой, а не этой проверкой.
 * Проба заведена, чтобы второй раз это стоило прогона, а не случайности.
 *
 * Проверяется и ТИП, а не только молчание: объявленный `«Исход числа»`
 * сходится с выведенным, значит форма отдаёт именно названный тип, а не
 * число, — а тип этот приписывает программе сам разбор.
 */
test("«к числу или беда» типизируется тем же именным типом, что у эталона", async () => {
  const ast = await собрать("исход.flang", `модуль «М»
функция «Разбор»
  принимает «т»: строка
  возвращает «Исход числа»
  к числу или беда «т»`)
  const беда = расхождение(ast)
  assert.equal(беда, null, String(беда))
  assert.equal(checkTypes(ast).diagnostics.length, 0, "эталон обязан принимать эту программу")
  /* И обратное: если бы форма отдавала число, объявление разошлось бы с телом
     у ОБЕИХ сторон — значит проба и правда меряет тип, а не одно молчание. */
  const число = await собрать("исход-число.flang", `модуль «М»
функция «Разбор»
  принимает «т»: строка
  возвращает число
  к числу или беда «т»`)
  assert.equal(расхождение(число), null)
  assert.ok(checkTypes(число).diagnostics.length > 0, "объявление числом обязано спорить с телом")
})

