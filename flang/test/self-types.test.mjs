/**
 * Проверка типов языка flang, написанная на самом flang — `flang/self/types.flang`.
 *
 * Проверка здесь одна и она дифференциальная: для каждой программы репозитория
 * множество диагностик, выданное слоем на flang, обязано совпасть с тем, что
 * даёт свидетельский `flang/src/types.mjs` — код, текст сообщения и место (строка и
 * столбец), в том же порядке. Не «ловит те же ошибки» и не «столько же
 * диагностик»: одинаковый набор кодов при разном тексте — это уже расхождение,
 * потому что текст диагностики и есть то, что читает человек.
 *
 * Чистых файлов мало для доказательства: на них верный ответ — «диагностик
 * нет», и его выдаёт любая функция, которая ничего не делает. Поэтому вторая
 * половина проверки — сломанные программы: в каждую внесена ровно одна типовая
 * ошибка (несовпадение типов, неполный разбор, неизвестное имя, неверная
 * арность, пример не того типа), и от слоя требуется та же диагностика в том же
 * месте. Третья — механические порчи настоящих файлов репозитория: у них ошибка
 * оказывается посреди большой программы, а не в трёх строках.
 */
import assert from "node:assert/strict"
import { readdirSync, readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { canonicalBuiltinName, СНИМАЮТСЯ_НЕПУСТОТОЙ } from "../src/builtins.mjs"
import { evaluate } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes, таблицаВхода } from "../src/types.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const файл = fileURLToPath(new URL("../self/types.flang", import.meta.url))
const исходник = readFileSync(файл, "utf8")

/* Свой разбор — чтобы знать, какие функции объявлены именно здесь, а какие
   приехали из «Печати JSON» и «Печати в C». Типы и тотальность считаются по
   связанной программе: без импорта имена соседних слоёв остались бы
   несвязанными. */
const свой = parse(исходник, "self/types.flang")
const связано = await linkProgram(файл, исходник, parse)
const { diagnostics: диагностикиСвязывания, ...программа } = связано
const типы = checkTypes(программа)
const тотальность = checkTotality(программа)

/**
 * Лимит шагов поднят с миллиона до четырёхсот. Проверка типов — работа с целым
 * AST сразу, и на самой большой программе репозитория (`flang/core/parser.flang`,
 * 150 КБ исходника) уходит порядка двухсот миллионов шагов: поиск сигнатуры,
 * записи и варианта идёт линейным перебором таблицы, потому что словаря в языке
 * нет. Запас взят двукратный и не больше — лимит здесь не формальность, он
 * ловит превращение проверки в перебор более высокого порядка.
 */
const ШАГИ = { maxSteps: 400_000_000, maxDepth: 20_000 }
const вызвать = (имя, аргументы) => evaluate(программа, имя, аргументы, ШАГИ)

/* ─────────────────── перевод AST в значения flang ─────────────────── */

/* Механический перевод JSON → «Значение» из `flang/core/json.flang`: повторяет
   форму и порядок ключей и ничего не решает сам. Иначе тест проверял бы себя. */
const вариантЗначения = (имя, поля = {}) => ({ variant: имя, fields: поля })

function скаляр(значение) {
  if (значение === null) return вариантЗначения("Скаляр ничто")
  if (typeof значение === "string") return вариантЗначения("Скаляр строка", { значение })
  if (typeof значение === "number") return вариантЗначения("Скаляр число", { значение })
  if (typeof значение === "boolean") return вариантЗначения("Скаляр признак", { значение })
  throw new Error(`не скаляр: ${String(значение)}`)
}

/* `undefined` пропускается ровно там, где его пропустил бы JSON.stringify:
   ключа нет — это не «ключ со значением ничто», и свидетель их различает. */
function значение(узел) {
  if (узел === undefined) return вариантЗначения("Значение скаляра", { скаляр: скаляр(null) })
  if (Array.isArray(узел)) return вариантЗначения("Значение списка", { элементы: узел.map(значение) })
  if (узел !== null && typeof узел === "object") {
    return вариантЗначения("Значение записи", {
      поля: Object.entries(узел)
        .filter(([, вложенное]) => вложенное !== undefined)
        .map(([ключ, вложенное]) => ({ ключ, значение: значение(вложенное) })),
    })
  }
  return вариантЗначения("Значение скаляра", { скаляр: скаляр(узел) })
}

/** Диагностика свидетеля и диагностика на flang, приведённые к одной форме. */
const образцовая = (д) => [д.code, д.message, д.span?.line ?? null, д.span?.column ?? null]
const наша = (д) => [
  д["код"],
  д["сообщение"],
  д["место"]["есть"] ? д["место"]["строка"] : null,
  д["место"]["есть"] ? д["место"]["столбец"] : null,
]

const проверить = (ast) => вызвать("Проверить типы", { программа: значение(ast) })

/**
 * Сверка одной программы. Возвращает описание первого расхождения или null.
 * Сравниваются код, текст и место каждой диагностики, вместе с их порядком.
 * Готовый итог можно передать: проверка больших программ стоит десятки секунд,
 * и гонять её дважды ради второго утверждения незачем.
 */
function расхождение(ast, готовое) {
  const свидетель = checkTypes(ast).diagnostics.map(образцовая)
  const итог = готовое ?? проверить(ast)
  const свои = итог["диагностики"].map(наша)
  if (итог["годно"] !== (свидетель.length === 0)) {
    return `«годно» ${итог["годно"]}, а диагностик у свидетеля ${свидетель.length}`
  }
  for (let индекс = 0; индекс < Math.max(свидетель.length, свои.length); индекс += 1) {
    if (свидетель[индекс] === undefined) return `лишняя диагностика ${индекс}: ${JSON.stringify(свои[индекс])}`
    if (свои[индекс] === undefined) return `нет диагностики ${индекс}: ${JSON.stringify(свидетель[индекс])}`
    const ждём = JSON.stringify(свидетель[индекс])
    const есть = JSON.stringify(свои[индекс])
    if (ждём !== есть) return `диагностика ${индекс}: ${есть} ≠ ${ждём}`
  }
  return null
}

/** Программа из текста: связывание, как это делает `flang check`. */
async function собрать(путь, текст) {
  const { diagnostics, ...ast } = await linkProgram(путь, текст, parse)
  return ast
}

/**
 * Сломанные программы разбираются без связывания: `linkProgram` выбрасывает
 * повторное объявление имени внутри одного файла молча, и «тип объявлен
 * дважды» до проверки типов не доехало бы. Импортов у них нет, поэтому разбора
 * достаточно.
 */
const разобрать = (текст) => parse(текст, "сломано.flang")

