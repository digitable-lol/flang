/*
 * Подстановка в тип с ДВУМЯ параметрами не переставляет аргументы.
 *
 * Дефект был ровно такой и жил незамеченным: `«Подставить в список»`
 * рекурсировала как «добавить голову к обработанному хвосту», а `добавить`
 * дописывает в КОНЕЦ, — список аргументов выходил перевёрнутым. На нуле и на
 * одном аргументе перестановка не видна, а типов с двумя параметрами в
 * репозитории не было ни одного, поэтому дифференциальная сверка молчала.
 *
 * Нашлось на `тип «Результат» от «Значение» и «Беда»` (flang/stdlib/result.flang):
 * эталон принимал модуль, а проверка на flang жаловалась «ожидался «Результат»
 * от строки и числа, получен «Результат» от числа и строки».
 *
 * Тест написан отдельно от корпуса нарочно: корпус покрывает это, только пока
 * result.flang остаётся двухпараметрическим, а исчезновение покрытия ничем бы
 * себя не выдало.
 */
test("подстановка в тип с двумя параметрами сохраняет порядок аргументов", () => {
  const итог = { kind: "named", name: "Итог", args: [{ kind: "number" }, { kind: "string" }] }
  const ast = {
    flang: 1,
    module: "М",
    types: [
      {
        kind: "sum",
        name: "Итог",
        typeParams: ["Значение", "Беда"],
        variants: [
          { name: "Успех", fields: [{ name: "значение", type: { kind: "named", name: "Значение" } }] },
          { name: "Отказ", fields: [{ name: "причина", type: { kind: "named", name: "Беда" } }] },
        ],
      },
    ],
    functions: [
      {
        name: "Взять",
        total: true,
        typeParams: ["Значение", "Беда"],
        params: [
          { name: "итог", type: { kind: "named", name: "Итог", args: [{ kind: "named", name: "Значение" }, { kind: "named", name: "Беда" }] } },
          { name: "запасное", type: { kind: "named", name: "Значение" } },
        ],
        returns: { kind: "named", name: "Значение" },
        body: { kind: "var", name: "запасное" },
      },
      {
        /* Вызов с аргументами В ОБЪЯВЛЕННОМ ПОРЯДКЕ: «Итог» от числа и строки.
           При перевёрнутой подстановке ожидание печаталось бы «от строки и
           числа» и вызов отвергался бы обеими сторонами по-разному. */
        name: "Через",
        total: true,
        params: [{ name: "итог", type: итог }],
        returns: { kind: "number" },
        body: {
          kind: "call",
          name: "Взять",
          args: [{ kind: "var", name: "итог" }, { kind: "literal", value: 0 }],
        },
      },
    ],
  }
  assert.deepEqual(checkTypes(ast).diagnostics, [], "эталон обязан принять программу")
  const беда = расхождение(ast)
  assert.equal(беда, null, String(беда))
  assert.deepEqual(проверить(ast)["диагностики"], [])
})

