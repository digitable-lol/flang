function случайныеПрограммы(сколько, сид) {
  const следующее = () => {
    сид = (сид * 1103515245 + 12345) % 2147483648
    return сид / 2147483648
  }
  const из = (список) => список[Math.floor(следующее() * список.length)]
  const шанс = (доля) => следующее() < доля
  const сколькоТо = (предел) => Math.floor(следующее() * предел)
  let строка = 0
  const место = () => ({ line: (строка += 1), column: 1 + сколькоТо(20) })
  const связки = (образец) => {
    if (образец.kind === "cons") return [образец.head, образец.tail]
    if (образец.kind === "variant") return Object.values(образец.bind ?? {})
    if (образец.kind === "any" && образец.bind !== undefined) return [образец.bind]
    return []
  }

  const образец = () => {
    switch (из(ОБРАЗЦЫ)) {
      case "empty": return { kind: "empty" }
      case "cons": return { kind: "cons", head: "г", tail: "х" }
      case "variant": return { kind: "variant", name: из(["А", "Б", "Нет"]), bind: шанс(0.5) ? { значение: "зн" } : {} }
      case "literal": return { kind: "literal", value: из([1, "а", true, null]) }
      default: return шанс(0.5) ? { kind: "any", bind: "все" } : { kind: "any" }
    }
  }

  const выражение = (глубина, имена) => {
    const вид = глубина <= 0
      ? из(["literal", "var", "var"])
      : из(["literal", "var", "field", "let", "if", "call", "binary", "construct", "record", "list", "match", "fold", "map", "filter", "builtin"])
    const где = шанс(0.85) ? { span: место() } : {}
    const дети = (сколько) => Array.from({ length: сколько }, () => выражение(глубина - 1, имена))
    switch (вид) {
      case "literal": return { kind: "literal", value: из([1, "а", true, null, 2.5]), ...где }
      case "var": return { kind: "var", name: имена.length > 0 && шанс(0.8) ? из(имена) : из(["нет", "х", "Р"]), ...где }
      case "field": return { kind: "field", target: выражение(глубина - 1, имена), field: из(["а", "б", "нет"]), ...где }
      case "let": {
        const имя = из(["п", "к", "т"])
        return {
          kind: "let",
          name: шанс(0.9) ? имя : undefined,
          value: выражение(глубина - 1, имена),
          in: выражение(глубина - 1, [...имена, имя]),
          ...где,
        }
      }
      case "if": return { kind: "if", cond: выражение(глубина - 1, имена), then: выражение(глубина - 1, имена), else: выражение(глубина - 1, имена), ...где }
      case "call": return { kind: "call", name: из(["Г", "Д", "Нет такой"]), args: дети(сколькоТо(3)), ...где }
      case "binary": return { kind: "binary", op: из(ОПЕРАЦИИ), left: выражение(глубина - 1, имена), right: выражение(глубина - 1, имена), ...где }
      case "construct": {
        const поля = {}
        if (шанс(0.7)) поля["значение"] = выражение(глубина - 1, имена)
        if (шанс(0.3)) поля["лишнее"] = выражение(глубина - 1, имена)
        return { kind: "construct", variant: из(["А", "Б", "Нет"]), fields: поля, ...где }
      }
      case "record": {
        const поля = {}
        if (шанс(0.8)) поля["а"] = выражение(глубина - 1, имена)
        if (шанс(0.5)) поля["б"] = выражение(глубина - 1, имена)
        if (шанс(0.2)) поля["в"] = выражение(глубина - 1, имена)
        return { kind: "record", type: из(["Р", "Нет такой"]), fields: поля, ...где }
      }
      case "list": return { kind: "list", items: дети(сколькоТо(3)), ...где }
      case "match": {
        const случаи = Array.from({ length: сколькоТо(4) }, () => {
          const о = образец()
          return { pattern: о, body: выражение(глубина - 1, [...имена, ...связки(о)]) }
        })
        return { kind: "match", target: выражение(глубина - 1, имена), cases: случаи, ...где }
      }
      case "fold": return {
        kind: "fold",
        over: выражение(глубина - 1, имена),
        init: выражение(глубина - 1, имена),
        acc: шанс(0.9) ? "акк" : undefined,
        item: шанс(0.9) ? "э" : undefined,
        body: выражение(глубина - 1, [...имена, "акк", "э"]),
        ...где,
      }
      case "map": case "filter": return {
        kind: вид,
        over: выражение(глубина - 1, имена),
        item: шанс(0.9) ? "э" : undefined,
        body: выражение(глубина - 1, [...имена, "э"]),
        ...где,
      }
      default: return { kind: "builtin", name: из(ФОРМЫ), args: дети(сколькоТо(4)), ...где }
    }
  }

  const программа = () => {
    строка = 0
    const типы = [
      { kind: "record", name: "Р", fields: [{ name: "а", type: из(ТИПЫ) }, { name: "б", type: из(ТИПЫ) }], span: место() },
      {
        kind: "sum",
        name: "Т",
        variants: [{ name: "А", fields: [{ name: "значение", type: из(ТИПЫ) }] }, { name: "Б", fields: [] }],
        span: место(),
      },
    ]
    if (шанс(0.3)) типы.push({ kind: "alias", name: "Псевдо", of: из(ТИПЫ), span: место() })
    if (шанс(0.15)) типы.push({ kind: "record", name: "Р", fields: [{ name: "в", type: { kind: "number" } }], span: место() })
    if (шанс(0.15)) типы.push({ kind: "sum", name: "У", variants: [{ name: "А", fields: [] }], span: место() })
    const функции = []
    for (const имя of ["Г", "Д", "Ф"]) {
      const параметры = Array.from({ length: сколькоТо(3) }, (_, номер) => ({ name: `п${номер}`, type: из(ТИПЫ), span: место() }))
      const примеры = шанс(0.4)
        ? [{
            name: "П",
            args: Object.fromEntries(параметры.filter(() => шанс(0.7)).map((п) => [п.name, из(ЗНАЧЕНИЯ)])),
            expected: из(ЗНАЧЕНИЯ),
            span: место(),
          }]
        : []
      if (шанс(0.2)) примеры.push({ name: "Лишний", args: { нет: 1 }, expected: 1, span: место() })
      функции.push({
        name: имя,
        total: шанс(0.5),
        params: параметры,
        returns: из(ТИПЫ),
        body: выражение(3, параметры.map((п) => п.name)),
        examples: примеры,
        span: место(),
      })
    }
    return { flang: 1, module: "М", types: типы, functions: функции }
  }

  return Array.from({ length: сколько }, программа)
}

