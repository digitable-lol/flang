/**
 * СЛУЖБА С ЖУРНАЛОМ — то, что нельзя показать прогоном по сети.
 *
 * `serve-durable.mjs` показывает, что перезапуск состояние не теряет: три
 * прогона, настоящий сокет, настоящий файл. Здесь проверяется другое — то, для
 * чего сокет не нужен и чего один сценарий показать не может:
 *
 *   1. ПЕРЕБОР. Успешный ответ на меняющий запрос выдаётся РОВНО в одной паре
 *      «состояние × отклик хозяина». Список откликов закрыт языком, состояний
 *      пять — перебор исчерпывающий, а не выборочный.
 *   2. РАЗВИЛКА ЧЕСТНА. Множество кодов, объявленных меняющими, СОВПАДАЕТ с
 *      множеством исходов, которые состояние и правда меняют. Это не читается
 *      глазами: проверяется сравнением хранилищ до и после.
 *   3. ВОССТАНОВЛЕНИЕ РАВНО ЖИЗНИ. На каждом префиксе сценария состояние,
 *      восстановленное из журнала, совпадает со состоянием живой службы.
 *   4. ЗУБЫ. Из развилки по очереди вынимается по одному коду — и от проверок
 *      требуется покраснеть.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import test from "node:test"

import { evaluate, variant } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const путьПлана = fileURLToPath(new URL("../examples/web/shortener/plan-durable.flang", import.meta.url))
const исходник = readFileSync(путьПлана, "utf8")

const собрать = async (текст) => {
  const связанный = await linkProgram(путьПлана, текст, parse)
  assert.deepEqual(связанный.diagnostics, [], "связывание плана с журналом и службой")
  const { diagnostics: _чисто, ...план } = связанный
  return план
}

const план = await собрать(исходник)
const зовём = (имя, доводы, где = план) => evaluate(где, имя, доводы, { maxSteps: 20_000_000 })

const ПУСТО = { записи: [], выдано: 0 }
const почтой = (тело) => `POST /ссылки HTTP/1.1\r\nContent-Length: ${[...тело].length}\r\n\r\n${тело}`

test("план с журналом: разбор, типы, тотальность — без единой диагностики", () => {
  assert.deepEqual(checkTypes(план).diagnostics ?? [], [], "диагностики типизации")
  assert.deepEqual(checkTotality(план).diagnostics ?? [], [], "диагностики тотальности")
})

/* ── 1. Перебор: подтверждение ровно в одном месте ────────────────────────── */

/** Все отклики хозяина — по одному на каждый вариант суммы «Отклик». */
const ОТКЛИКИ = [
  variant("Пока ничего", {}),
  variant("Прочитано", { содержимое: "" }),
  variant("Прочитано", { содержимое: "GET /здоровье HTTP/1.1\r\n\r\n" }),
  variant("Записано", { сколько: 7 }),
  variant("Ответ сети", { код: 200, тело: "" }),
  variant("Отметка времени", { миллисекунды: 0 }),
  variant("Выпало", { значение: 0 }),
  variant("Показано", {}),
  variant("Случилось", { откуда: "где-то", значение: "что-то" }),
  variant("Срок вышел", {}),
  variant("Перечислено", { имена: [] }),
  variant("Соединение открыто", { соединение: 7 }),
  variant("Сбой", { код: "FLANG_IO_WRITE", сообщение: "диск полон" }),
]

/* Старое и новое хранилища РАЗЛИЧИМЫ нарочно: иначе «состояние поехало
   дальше» и «состояние осталось прежним» выглядели бы одинаково. */
const СТАРОЕ = { записи: [], выдано: 0 }
const НОВОЕ = { записи: [{ код: "к1", адрес: "http://п", переходов: 0 }], выдано: 1 }
const СВЕЖИЕ = [{ номер: 1, тело: "аб" }]
const ОТВЕТ = "HTTP/1.1 201 Created\r\n\r\nк1"

const ХОДЫ = [
  variant("Читаем журнал", {}),
  variant("Ждём соединение", { хранилище: СТАРОЕ, записи: [], обслужено: 0 }),
  variant("Приняли соединение", { хранилище: СТАРОЕ, записи: [], обслужено: 0 }),
  variant("Читаем соединение", { хранилище: СТАРОЕ, записи: [], обслужено: 0, соединение: 7, накоплено: "" }),
  variant("Пишем журнал", {
    хранилище: СТАРОЕ, записи: [], новое: НОВОЕ, свежие: СВЕЖИЕ, ответ: ОТВЕТ, соединение: 7, обслужено: 0,
  }),
]

test("перебор: успешный ответ на меняющий запрос выдаётся РОВНО после отклика «Записано»", () => {
  const подтверждения = []
  for (const ход of ХОДЫ) {
    for (const отклик of ОТКЛИКИ) {
      const дальше = зовём("Дальше с журналом", { ход, отклик })
      if (дальше.variant !== "Сделать") continue
      const поручение = дальше.fields["поручение"]
      if (поручение.variant !== "Ответить в соединение") continue
      if (поручение.fields["содержимое"] !== ОТВЕТ) continue
      подтверждения.push({ ход: ход.variant, отклик: отклик.variant, потом: дальше.fields["потом"].fields })
    }
  }
  assert.equal(подтверждения.length, 1, "успешный ответ вышел не из одного места: " + JSON.stringify(подтверждения.map((п) => [п.ход, п.отклик])))
  assert.equal(подтверждения[0].ход, "Пишем журнал")
  assert.equal(подтверждения[0].отклик, "Записано")
  assert.deepEqual(подтверждения[0].потом["хранилище"], НОВОЕ, "новое хранилище не поехало дальше")
  assert.deepEqual(подтверждения[0].потом["записи"], СВЕЖИЕ, "новый журнал не поехал дальше")
})

test("перебор: на любом отклике, кроме «Записано», состояние остаётся СТАРЫМ", () => {
  const ход = ХОДЫ.at(-1)
  const отказ = зовём("Отказ журнала", {})
  for (const отклик of ОТКЛИКИ) {
    if (отклик.variant === "Записано") continue
    const дальше = зовём("Дальше с журналом", { ход, отклик })
    assert.equal(дальше.variant, "Сделать", `на отклике «${отклик.variant}» план не выдал поручения`)
    const поручение = дальше.fields["поручение"]
    assert.equal(поручение.variant, "Ответить в соединение")
    assert.equal(поручение.fields["содержимое"], отказ, `на отклике «${отклик.variant}» ушёл не отказ журнала`)
    assert.deepEqual(дальше.fields["потом"].fields["хранилище"], СТАРОЕ, `на отклике «${отклик.variant}» уехало новое хранилище`)
    assert.deepEqual(дальше.fields["потом"].fields["записи"], [], `на отклике «${отклик.variant}» уехал новый журнал`)
  }
})

test("перебор: пока журнал не записан, ни одно состояние не отдаёт нового хранилища", () => {
  for (const ход of ХОДЫ.slice(0, 4)) {
    for (const отклик of ОТКЛИКИ) {
      const дальше = зовём("Дальше с журналом", { ход, отклик })
      const строкой = JSON.stringify(дальше)
      assert.ok(!строкой.includes('"к1"') || ход.variant === "Читаем соединение", `состояние «${ход.variant}» на отклике «${отклик.variant}» выдало ссылку, не записав журнала`)
    }
  }
})

/* ── 2. Развилка честна: объявленное «меняет» совпадает с настоящим ───────── */

/**
 * По одному запросу на каждый из десяти исходов службы плюс неполный запрос.
 * Меняет состояние или нет — здесь НЕ ЗАПИСАНО, а вычисляется сравнением
 * хранилищ: ожидание, переписанное из кода, ничего не проверяет.
 */
const ЗАПРОСЫ = [
  ["здоровье", "GET /здоровье HTTP/1.1\r\n\r\n"],
  ["список", "GET /ссылки HTTP/1.1\r\n\r\n"],
  ["создание", почтой("адрес=https://пример.рф/док")],
  ["переход", "GET /с/к1 HTTP/1.1\r\n\r\n"],
  ["удаление", "DELETE /ссылки/к1 HTTP/1.1\r\n\r\n"],
  ["нет пути", "GET /админка HTTP/1.1\r\n\r\n"],
  ["метод не тот", "PUT /ссылки HTTP/1.1\r\n\r\n"],
  ["код занят", почтой("адрес=https://п.рф&код=к1")],
  ["адрес негоден", почтой("адрес=javascript:alert(1)")],
  ["тело велико", почтой("адрес=https://п.рф/" + "ы".repeat(3000))],
  ["две длины тела", "POST /ссылки HTTP/1.1\r\nContent-Length: 2\r\ncontent-length: 2\r\n\r\nаб"],
  ["неполный запрос", "GET /здор"],
]

/** Хранилища сравниваются как значения — иного равенства у них и нет. */
const тоЖе = (а, б) => JSON.stringify(а) === JSON.stringify(б)

test("развилка: «Надо в журнал» совпадает с «состояние и правда изменилось» на всех исходах", () => {
  /* Проверяется на ДВУХ хранилищах: пустом (где «переход» и «удаление»
     ничего не меняют, потому что кода нет) и с готовой ссылкой (где меняют). */
  const НАЧАЛА = [ПУСТО, { записи: [{ код: "к1", адрес: "http://п", переходов: 0 }], выдано: 1 }]
  const свод = []
  for (const начало of НАЧАЛА) {
    for (const [имя, текст] of ЗАПРОСЫ) {
      const решение = зовём("Обслужить", { хранилище: начало, текст })
      const изменилось = !тоЖе(решение["состояние"], начало)
      const объявлено = зовём("Надо в журнал", { код: решение["код"] })
      assert.equal(
        объявлено, изменилось,
        `«${имя}» (код ${решение["код"]}): объявлено «в журнал» = ${объявлено}, а состояние ${изменилось ? "изменилось" : "не изменилось"}`,
      )
      свод.push([имя, решение["код"], изменилось])
    }
  }
  assert.equal(свод.filter(([, , м]) => м).length, 5, "меняющих случаев в своде ожидалось пять")
})

/* ── 3. Восстановление равно жизни ───────────────────────────────────────── */

/**
 * Живая служба и восстановление из журнала — на КАЖДОМ префиксе сценария.
 *
 * Живое состояние строится последовательным «Обслужить»; журнал — теми же
 * запросами, но только меняющими. Совпасть обязаны на каждом шаге, а не только
 * в конце: расхождение, появившееся на третьем запросе и исчезнувшее на
 * пятом, проверкой одного конца не ловится.
 */
const СЦЕНАРИЙ = [
  "GET /здоровье HTTP/1.1\r\n\r\n",
  почтой("адрес=https://пример.рф/док"),
  "GET /с/к1 HTTP/1.1\r\n\r\n",
  "GET /ссылки HTTP/1.1\r\n\r\n",
  почтой("адрес=https://пример.рф/два&код=свой"),
  "GET /с/свой HTTP/1.1\r\n\r\n",
  "GET /с/свой HTTP/1.1\r\n\r\n",
  "DELETE /ссылки/к1 HTTP/1.1\r\n\r\n",
  "GET /с/к1 HTTP/1.1\r\n\r\n",
  почтой("адрес=javascript:alert(1)"),
  почтой("адрес=https://пример.рф/три"),
  "DELETE /ссылки/нету HTTP/1.1\r\n\r\n",
  "GET /здор",
]

/** Прогнать сценарий вживую, собирая заодно журнал. Возвращает шаги. */
function прожить(где = план) {
  let хранилище = ПУСТО
  let записи = []
  const шаги = []
  for (const текст of СЦЕНАРИЙ) {
    const решение = evaluate(где, "Обслужить", { хранилище, текст }, { maxSteps: 20_000_000 })
    const код = решение["код"]
    if (evaluate(где, "Надо в журнал", { код }, { maxSteps: 20_000_000 })) {
      записи = evaluate(где, "Журнал со свежей записью", { записи, что: текст }, { maxSteps: 20_000_000 })
    }
    хранилище = решение["состояние"]
    шаги.push({ текст, код, хранилище, записи })
  }
  return шаги
}

test("восстановление: на КАЖДОМ префиксе сценария журнал даёт то же хранилище, что живая служба", () => {
  const шаги = прожить()
  assert.equal(шаги.length, СЦЕНАРИЙ.length)
  for (const [и, шаг] of шаги.entries()) {
    const восстановлено = зовём("Восстановить", { записи: шаг.записи })
    assert.deepEqual(
      восстановлено, шаг.хранилище,
      `префикс ${и + 1}: восстановленное из журнала разошлось с живым состоянием`,
    )
  }
  const последний = шаги.at(-1)
  assert.equal(последний.записи.length, 7, "меняющих запросов в сценарии ожидалось семь")
  assert.equal(последний.хранилище.записи.length, 2, "живых ссылок в конце сценария ожидалось две")
})

test("восстановление: оборванный хвост журнала в состояние не переезжает", () => {
  const шаги = прожить()
  const целый = зовём("Напечатать журнал", { записи: шаги.at(-1).записи })
  /* Обрывается КАЖДЫЙ знак журнала — как в проверках самого журнала. */
  let сошлось = 0
  for (let сколько = 0; сколько <= [...целый].length; сколько += 1) {
    const кусок = [...целый].slice(0, сколько).join("")
    const итог = зовём("Прочитать журнал", { текст: кусок })
    const восстановлено = зовём("Восстановить", { записи: итог.записи })
    /* Восстановленное обязано совпасть с состоянием службы после РОВНО того
       числа меняющих запросов, сколько целых записей уцелело. */
    const целых = итог.записи.length
    const ожидаемое = целых === 0 ? ПУСТО : шаги.find((ш) => ш.записи.length === целых).хранилище
    assert.deepEqual(восстановлено, ожидаемое, `обрыв на ${сколько} знаках: восстановлено не то`)
    сошлось += 1
  }
  assert.equal(сошлось, [...целый].length + 1, "проверены не все обрывы журнала")
  assert.ok(сошлось > 300, "обрывов проверено подозрительно мало: " + сошлось)
})

/* ── 4. Зубы: изъятия обязаны краснеть ───────────────────────────────────── */

const РАЗВИЛКА = "(код равен 201) или (код равен 204) или (код равен 301)"

const ИЗЪЯТИЯ = [
  ["из развилки вынут переход (301)", "(код равен 201) или (код равен 204)"],
  ["из развилки вынуто удаление (204)", "(код равен 201) или (код равен 301)"],
  ["из развилки вынуто создание (201)", "(код равен 204) или (код равен 301)"],
]

for (const [имя, стало] of ИЗЪЯТИЯ) {
  test(`изъятие «${имя}» обязано покраснеть`, async () => {
    assert.ok(исходник.includes(РАЗВИЛКА), "изымаемое место в исходнике не найдено")
    const испорчен = await собрать(исходник.replace(РАЗВИЛКА, стало))
    let покраснело = false
    try {
      const шаги = прожить(испорчен)
      for (const шаг of шаги) {
        const восстановлено = evaluate(испорчен, "Восстановить", { записи: шаг.записи }, { maxSteps: 20_000_000 })
        if (JSON.stringify(восстановлено) !== JSON.stringify(шаг.хранилище)) покраснело = true
      }
    } catch {
      покраснело = true
    }
    assert.ok(покраснело, `изъятие «${имя}» прошло незамеченным — проверка ничего не держит`)
  })
}

/**
 * ЧЕТВЁРТОЕ ИЗЪЯТИЕ, КОТОРОЕ НЕ КРАСНЕЕТ, И ЭТО ЗАПИСАНО, А НЕ ЗАМЯТО.
 *
 * Добавь в развилку код 200 — и в журнал полезут запросы, ничего не менявшие.
 * Восстановление от этого НЕ ЛОМАЕТСЯ: лишняя запись при повторе даёт то же
 * хранилище, потому что «Обслужить» на чтении состояния не меняет. То есть
 * половина «в журнал не попадает лишнего» проверками выше НЕ ДЕРЖИТСЯ, и
 * держать её нечем — цена лишнего кода в развилке измеряется не правильностью,
 * а байтами журнала и числом поручений записи. Здесь названо, сколько это.
 */
test("лишний код в развилке правильности не ломает — он стоит записей в журнале", async () => {
  const щедрый = await собрать(исходник.replace(РАЗВИЛКА, РАЗВИЛКА + " или (код равен 200)"))
  const строгие = прожить()
  const щедрые = прожить(щедрый)
  for (const [и, шаг] of щедрые.entries()) {
    const восстановлено = evaluate(щедрый, "Восстановить", { записи: шаг.записи }, { maxSteps: 20_000_000 })
    assert.deepEqual(восстановлено, шаг.хранилище, `префикс ${и + 1}: щедрая развилка сломала восстановление`)
  }
  assert.equal(строгие.at(-1).записи.length, 7, "строгая развилка: записей в журнале")
  assert.equal(щедрые.at(-1).записи.length, 9, "щедрая развилка: записей в журнале")
})
