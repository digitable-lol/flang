/**
 * Согласие системы спек (`fspec/guard.flang`) — и проверка самой проверки.
 *
 * ── Почему этот файл лежит в `flang/test/`, а не отдельным шагом в CI ───────
 *
 * Потому что иначе проверка не просыпается. До 18 августа 2026 `spec:check` не
 * звал НИКТО: `.github/workflows/ci.yml` запускает `npm test`, а тот —
 * `node --test flang/test/*.test.mjs`, и `fspec/` в этот перечень не входил.
 * Проверка, которую не зовут, хуже отсутствующей: отсутствующая видна, а эта
 * создаёт впечатление покрытия.
 *
 * Отдельный шаг в GitHub Actions эту беду НЕ закрыл бы, и вот почему числом:
 * CI в этом дереве заведён на `push: tags: ["v*"]` и `workflow_dispatch` — на
 * каждый коммит он не ходит СОЗНАТЕЛЬНО (довод в шапке `ci.yml`: прогон идёт
 * около двух часов). Значит шагом в CI проверка просыпалась бы на теге, то есть
 * ПОСЛЕ того, как расходящаяся спека уже влита. Здесь же она идёт при каждом
 * `npm test` — и у разработчика на машине, и в `prepublishOnly`, и в CI.
 *
 * ── Что здесь на JavaScript, а что нет ─────────────────────────────────────
 *
 * Сама проверка написана на flang и живёт планом (`fspec/guard.flang`): она
 * перечисляет каталог, читает спеки, запускает компилятор и ставит код
 * возврата. Здесь остаётся только то, чего план про себя знать не может, —
 * ПОДЛОГ: разложить выдуманные спеки во временном каталоге, натравить на них
 * план и посмотреть, покраснеет ли он. Настройка плана (`settings.txt`, две
 * строки — путь к компилятору и каталог спек) заведена ровно ради этого: без
 * неё план ходил бы только по дереву, и проверить его было бы нечем.
 *
 * ── Три обязательства, и путать их нельзя ──────────────────────────────────
 *
 *   1. на дереве план ЧИСТ — обе спеки `fspec/spec/` доказаны и согласны;
 *   2. план ЛОВИТ — на подложенных случаях, по одному на каждое правило;
 *   3. план МОЛЧИТ там, где обязан молчать — и это здесь не украшение, а
 *      РЕГРЕССИЯ С ИМЕНЕМ. Проверка знала одно слово `"proved"` и отвергала
 *      спеку, доказанную ИНДУКЦИЕЙ (`proved-induction`), — печатала «не
 *      доказано» и следом цитировала отчёт: «доказано индукцией по «нат»».
 *      Дыра прожила до 18 августа именно потому, что проверять проверку было
 *      нечем. Случай «индукцией» ниже — замок на неё.
 */
import assert from "node:assert/strict"
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { позвать, путьДвоичного } from "../scripts/dvoichnyy.mjs"

const ПЛАН = new URL("../../fspec/guard.flang", import.meta.url).pathname
const ПОЛИТИКА = new URL("../../fspec/policy.flang", import.meta.url).pathname

/** Прогон плана: код возврата и всё, что он сказал, одной строкой. */
function прогнать(план) {
  const { код, вывод, ошибки } = позвать(["io", план])
  return { код, сказано: `${вывод}\n${ошибки}` }
}

/**
 * Подложенный каталог спек: кладём план рядом с политикой, пишем настройку,
 * раскладываем выдуманные спеки, зовём план, убираем за собой.
 */
function наПодложенных(файлы, дело) {
  const где = mkdtempSync(join(tmpdir(), "fspec-guard-"))
  try {
    copyFileSync(ПЛАН, join(где, "guard.flang"))
    copyFileSync(ПОЛИТИКА, join(где, "policy.flang"))
    writeFileSync(join(где, "settings.txt"), `${путьДвоичного()}\nspec\n`, "utf8")
    mkdirSync(join(где, "spec"))
    for (const [имя, текст] of Object.entries(файлы)) writeFileSync(join(где, "spec", имя), текст, "utf8")
    дело(прогнать(join(где, "guard.flang")))
  } finally {
    rmSync(где, { recursive: true, force: true })
  }
}

/* ── 0. сам план — программа языка, и проверяется как программа ───────────── */

test("план проверки — программа на flang: все функции тотальны, примеры сходятся", () => {
  const { код, вывод, ошибки } = позвать(["check", ПЛАН, "--proof", "--json"])
  assert.equal(код, 0, `flang check ${ПЛАН} → ${ошибки}`)
  const о = JSON.parse(вывод)
  assert.deepEqual(
    о.functions.filter((ф) => !ф.total).map((ф) => ф.name),
    [],
    "в проверке спек завелась нетотальная функция",
  )
})

/* ── 1. на дереве ─────────────────────────────────────────────────────────── */

test("на дереве спеки согласны: обе доказаны и ни одно утверждение не потеряно", () => {
  const { код, сказано } = прогнать(ПЛАН)
  assert.equal(код, 0, `план нашёл беду там, где дерево обязано быть чистым:\n${сказано}`)
  assert.match(сказано, /спек 2, утверждений 3/)
})

/* ── 2. план ловит ────────────────────────────────────────────────────────── */

test("ловит утверждение, которое объявлено, но не выведено", () => {
  наПодложенных(
    {
      "01-declared.flang": `модуль «Объявлено, не доказано»

тотальная функция «Скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не меньше 50» результат не меньше 50
  10
`,
    },
    ({ код, сказано }) => {
      assert.equal(код, 1, сказано)
      assert.match(сказано, /бед в системе спек: 1/)
      assert.match(сказано, /«скидка не меньше 50» функции «Скидка» не доказано — declared/)
    },
  )
})

test("ловит спеку без утверждений: ей не на чем разойтись", () => {
  наПодложенных(
    {
      "01-empty.flang": `модуль «Без утверждений»

тотальная функция «Просто»
  принимает н: число
  возвращает число
  н
`,
    },
    ({ код, сказано }) => {
      assert.equal(код, 1, сказано)
      assert.match(сказано, /01-empty\.flang: спека без утверждений/)
    },
  )
})

test("ловит пропажу утверждения предшественницы из отчёта наследницы", () => {
  наПодложенных(
    {
      "01-base.flang": `модуль «Спека 1»

тотальная функция «Потолок»
  принимает сумма: число
  возвращает число
  обеспечивает «потолок не больше 30» результат не больше 30
  30

тотальная функция «Пол»
  принимает сумма: число
  возвращает число
  обеспечивает «пол не меньше 0» результат не меньше 0
  0
`,
      /* Наследница берёт `только «Потолок»` — и утверждение «Пола» из её
         отчёта пропадает. Ровно так согласие и рвётся на деле: не
         переписыванием утверждения, а сужением того, что втянуто. */
      "02-heir.flang": `модуль «Спека 2»
  использует «Спека 1» из "./01-base.flang" только «Потолок»

тотальная функция «Скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не больше 30» результат не больше 30
  «Потолок» от сумма
`,
    },
    ({ код, сказано }) => {
      assert.equal(код, 1, сказано)
      assert.match(сказано, /бед в системе спек: 1/)
      assert.match(сказано, /«пол не меньше 0» функции «Пол» доказано у 01-base\.flang/)
    },
  )
})

test("ловит ненайденную предшественницу", () => {
  наПодложенных(
    {
      "01-orphan.flang": `модуль «Сирота»
  использует «Которой нет» из "./00-missing.flang"

тотальная функция «Скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не больше 30» результат не больше 30
  30
`,
    },
    ({ код, сказано }) => {
      /* Связывание не находит файл и отказывает раньше проверки — беда приходит
         от языка. Важно, что план при этом КРАСНЕЕТ, а не зеленеет молча. */
      assert.equal(код, 1, сказано)
      assert.match(сказано, /01-orphan\.flang: спека не проходит проверку языка/)
      assert.match(сказано, /FLANG_IMPORT_NOT_FOUND/)
    },
  )
})

test("ловит пустой каталог: проверка, которой нечего проверять, зеленеет всегда", () => {
  наПодложенных({}, ({ код, сказано }) => {
    assert.equal(код, 1, сказано)
    assert.match(сказано, /FLANG_SPEC_ПУСТО/)
  })
})

/* ── 3. план молчит там, где обязан ───────────────────────────────────────── */

test("МОЛЧИТ на утверждении, доказанном индукцией: `proved-induction` — это доказано", () => {
  наПодложенных(
    {
      "01-induction.flang": `модуль «Спека индукцией»

тотальная функция «Факториал»
  принимает н: нат
  возвращает число
  для всех н обеспечивает «факториал неотрицателен» результат не меньше 0
  если н не больше 1
    то 1
    иначе н умножить на («Факториал» от (н минус 1))

теорема «факториал неотрицателен»
  дано н: нат
  утверждаем результат не меньше 0
  индукция по н убывает н
    случай любое
      то по предположению
  следовательно доказано
`,
    },
    ({ код, сказано }) => {
      assert.equal(код, 0, `отвергнуто доказанное индукцией — вернулась дыра, ради которой написан этот случай:\n${сказано}`)
      assert.match(сказано, /спек 1, утверждений 1/)
    },
  )
})

/* ── 4. политика, записанная на самом языке ───────────────────────────────── */

/**
 * `fspec/policy.flang` решает, а `fspec/guard.flang` только называет решённое
 * словами. Проверки ниже держат политику живой: без них она стала бы ровно тем,
 * чем был `spec:check` до 18 августа, — вещью, которую никто не зовёт.
 */
test("политика на flang: семь функций, все тотальные, аксиом ноль", () => {
  const { код, вывод, ошибки } = позвать(["check", ПОЛИТИКА, "--proof", "--json"])
  assert.equal(код, 0, `политика не проходит проверку языка: ${ошибки}`)
  const о = JSON.parse(вывод)
  assert.equal(о.functions.length, 7)
  assert.deepEqual(
    о.functions.filter((ф) => !ф.total),
    [],
    "в политике завелась нетотальная функция",
  )
})

test("ловит противоречие ЧЕРЕЗ ФАЙЛ, которое `flang check` пропускает", () => {
  /* Сам компилятор на этой паре ЗЕЛЕНЕЕТ: «промо не меньше 50» при потолке 30
     он откладывает на рантайм словами «объявлено, не доказано», и код выхода у
     него 0. Ровно этот опыт и завёл `fspec/`. */
  const опыты = new URL("../../fspec/experiments/", import.meta.url).pathname
  const наследница = join(опыты, "spec-new-feature.flang")
  assert.equal(позвать(["check", наследница, "--proof"]).код, 0, "опыт перестал быть опытом: компилятор больше не зеленеет на нём")

  наПодложенных(
    {
      "01-legacy.flang": `модуль «Спека легаси: потолок скидки»

тотальная функция «Потолок скидки»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не больше 30» результат не больше 30
  30
`,
      "02-new.flang": `модуль «Спека новой фичи: промо»
  использует «Спека легаси: потолок скидки» из "./01-legacy.flang"

тотальная функция «Промо-скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «промо не меньше 50» результат не меньше 50
  «Потолок скидки» от сумма
`,
    },
    ({ код, сказано }) => {
      assert.equal(код, 1, `противоречие через файл пропущено — то самое, ради которого написана политика:\n${сказано}`)
      assert.match(сказано, /«промо не меньше 50» функции «Промо-скидка» не доказано — declared/)
    },
  )
})
