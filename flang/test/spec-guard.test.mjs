/**
 * Сторож совместности спек (`fspec/guard.mjs`) — и проверка САМОГО сторожа.
 *
 * ── Почему этот файл лежит в `flang/test/`, а не отдельным шагом в CI ───────
 *
 * Потому что иначе сторож не просыпается. До 18 августа 2026 `spec:check` не
 * звал НИКТО: `.github/workflows/ci.yml` запускает `npm test`, а тот —
 * `node --test flang/test/*.test.mjs`, и `fspec/` в этот перечень не входил.
 * Из двадцати четырёх скриптов `package.json` немым был ровно один, и это был
 * он. Проверка, которую не зовут, хуже отсутствующей: отсутствующая видна, а
 * эта создаёт впечатление покрытия.
 *
 * Отдельный шаг в GitHub Actions эту беду НЕ закрыл бы, и вот почему числом:
 * CI в этом дереве заведён на `push: tags: ["v*"]` и `workflow_dispatch` — на
 * каждый коммит он не ходит СОЗНАТЕЛЬНО (довод в шапке `ci.yml`: прогон идёт
 * около двух часов). Значит шагом в CI сторож просыпался бы на теге, то есть
 * ПОСЛЕ того, как расходящаяся спека уже влита. Здесь же он идёт при каждом
 * `npm test` — и у разработчика на машине, и в `prepublishOnly`, и в CI.
 *
 * Так устроены и остальные сторожа дерева: `claim-guard`, `count-guard`,
 * `code-guard`, `emit-guard` — у каждого свой `*-guard.test.mjs`. Этот файл
 * не заводит нового обычая, а возвращает `fspec/` в общий.
 *
 * ── Три обязательства, и путать их нельзя ──────────────────────────────────
 *
 *   1. на дереве сторож ЧИСТ — обе спеки `fspec/spec/` доказаны и согласны;
 *   2. сторож ЛОВИТ — на подложенных случаях, по одному на каждое из правил;
 *   3. сторож МОЛЧИТ там, где обязан молчать — и это здесь не украшение, а
 *      РЕГРЕССИЯ С ИМЕНЕМ. Сторож знал одно слово `"proved"` и отвергал
 *      спеку, доказанную ИНДУКЦИЕЙ (`proved-induction`), — печатал «не
 *      доказано» и следом цитировал ведомость: «доказано индукцией по «нат»».
 *      Дыра прожила до 18 августа именно потому, что проверять сторожа было
 *      нечем. Случай «индукцией» ниже — замок на неё.
 */
import assert from "node:assert/strict"
import { mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { КАТАЛОГ_СПЕК, проверить } from "../../fspec/guard.mjs"

/** Подложенный каталог спек: пишем файлы, зовём сторожа, убираем за собой. */
function наПодложенных(файлы, дело) {
  const каталог = mkdtempSync(join(tmpdir(), "fspec-guard-"))
  try {
    for (const [имя, текст] of Object.entries(файлы)) writeFileSync(join(каталог, имя), текст, "utf8")
    дело(проверить(каталог, каталог))
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

const роды = (итог) => итог.беды.map((б) => б.род)

/* ── 1. на дереве ─────────────────────────────────────────────────────────── */

test("на дереве сторож спек чист: обе спеки доказаны и согласны", () => {
  const итог = проверить(КАТАЛОГ_СПЕК)
  assert.deepEqual(итог.беды, [], "сторож нашёл беду там, где дерево обязано быть чистым")
  assert.equal(итог.спек, 2, "спек в fspec/spec/")
  assert.equal(итог.утверждений, 3, "утверждений во всех ведомостях")
})

/* ── 2. сторож ловит ──────────────────────────────────────────────────────── */

test("ловит утверждение, которое объявлено, но не выведено", () => {
  наПодложенных(
    {
      "01-declared.flang": `модуль «Объявлено, не доказано»

тотальная функция «Скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не меньше 50» результат не меньше 50
  10
`,
    },
    (итог) => {
      assert.equal(итог.беды.length, 1, `ждали одну беду, получили: ${JSON.stringify(роды(итог))}`)
      assert.match(итог.беды[0].род, /утверждение не доказано \(declared\)/)
    },
  )
})

test("ловит спеку без утверждений: ей не на чем разойтись", () => {
  наПодложенных(
    {
      "01-empty.flang": `модуль «Без утверждений»

тотальная функция «Просто»
  принимает н: число
  возвращает число
  н
`,
    },
    (итог) => {
      assert.deepEqual(роды(итог), ["спека без утверждений"])
    },
  )
})

test("ловит пропажу утверждения предшественницы из ведомости наследницы", () => {
  наПодложенных(
    {
      "01-base.flang": `модуль «Спека 1»

тотальная функция «Потолок»
  принимает сумма: число
  возвращает число
  обеспечивает «потолок не больше 30» результат не больше 30
  30

тотальная функция «Пол»
  принимает сумма: число
  возвращает число
  обеспечивает «пол не меньше 0» результат не меньше 0
  0
`,
      /* Наследница берёт `только «Потолок»` — и утверждение «Пола» из её
         ведомости пропадает. Ровно так согласие и рвётся на деле: не
         переписыванием утверждения, а сужением того, что втянуто. */
      "02-heir.flang": `модуль «Спека 2»
  использует «Спека 1» из "./01-base.flang" только «Потолок»

тотальная функция «Скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не больше 30» результат не больше 30
  «Потолок» от сумма
`,
    },
    (итог) => {
      assert.deepEqual(роды(итог), ["утверждение предшественницы пропало из ведомости"])
      assert.match(итог.беды[0].сказано, /Пол: пол не меньше 0/)
    },
  )
})

test("ловит ненайденную предшественницу", () => {
  наПодложенных(
    {
      "01-orphan.flang": `модуль «Сирота»
  использует «Которой нет» из "./00-missing.flang"

тотальная функция «Скидка»
  принимает сумма: число
  возвращает число
  обеспечивает «скидка не больше 30» результат не больше 30
  30
`,
    },
    (итог) => {
      /* Связывание не находит файл и отказывает раньше сторожа — беда приходит
         от языка. Важно, что сторож при этом КРАСНЕЕТ, а не зеленеет молча. */
      assert.equal(итог.беды.length, 1, `ждали одну беду, получили: ${JSON.stringify(роды(итог))}`)
      assert.match(итог.беды[0].род, /предшественница не найдена|спека не проходит проверку языка/)
    },
  )
})

/* ── 3. сторож молчит там, где обязан ─────────────────────────────────────── */

test("МОЛЧИТ на утверждении, доказанном индукцией: `proved-induction` — это доказано", () => {
  наПодложенных(
    {
      "01-induction.flang": `модуль «Спека индукцией»

тотальная функция «Факториал»
  принимает н: нат
  возвращает число
  для всех н обеспечивает «факториал неотрицателен» результат не меньше 0
  если н не больше 1
    то 1
    иначе н умножить на («Факториал» от (н минус 1))

теорема «факториал неотрицателен»
  дано н: нат
  утверждаем результат не меньше 0
  индукция по н убывает н
    случай любое
      то по предположению
  следовательно доказано
`,
    },
    (итог) => {
      assert.deepEqual(
        итог.беды,
        [],
        "сторож отверг доказанное индукцией — вернулась дыра, ради которой написан этот случай",
      )
      assert.equal(итог.утверждений, 1)
    },
  )
})
