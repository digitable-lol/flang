/**
 * Утверждения о библиотеке: что о ней сказано и чего сказать пока нельзя.
 *
 * ── Зачем этот файл ─────────────────────────────────────────────────────────
 * В `flang/stdlib/` двенадцать модулей, 4301 строка, 185 функций, и до этой
 * работы постусловий в них было НОЛЬ, теорем НОЛЬ. Тотальными доказаны 2196
 * функций корпуса, но тотальность — про завершение, а не про правильность: о
 * «Сортировать» было доказано, что она останавливается, и не сказано, что она не
 * теряет элементов.
 *
 * Здесь две части, и вторая важнее первой.
 *
 *   1. ЧТО ВЫСКАЗАНО. Пятнадцать утверждений о четырнадцати настоящих функциях
 *      `flang/stdlib/lists.flang` (из двадцати восьми) лежат в
 *      `flang/proof/examples/corpus-lists.flang` при ДОСЛОВНО перенесённых
 *      телах, и дословность сличает машина, а не глаз. Все пятнадцать стоят в
 *      ведомости словом «сетка», а не «доказано», и проверка ниже это
 *      закрепляет: слово нельзя поднять молча. Охват тоже назван числом —
 *      работа по библиотеке не закончена, и мерить её надо, а не описывать.
 *
 *   2. ЧТО ВЫСКАЗАТЬ ИЛИ ДОКАЗАТЬ НЕЛЬЗЯ, И ПОЧЕМУ — ИМЕНАМИ ОТКАЗОВ. Пять
 *      заказов, каждый — настоящая функция библиотеки, настоящая попытка
 *      доказательства и настоящий отказ с кодом. Это не список пожеланий: как
 *      только ядро (или поверхность) научится названному, соответствующая
 *      проверка ПОКРАСНЕЕТ и потребует перевести утверждение из сетки в
 *      доказанное. Тест, который не умеет краснеть, хуже отсутствующего —
 *      поэтому заказ записан исполняемым, а не прозой.
 *
 * ── Почему утверждения лежат не у самих функций ─────────────────────────────
 * `flang/stdlib` входит в корпус побайтовой неподвижной точки самоприменения
 * ЦЕЛИКОМ, а у восьми слов слоя доказательства нет продукции в
 * `flang/self/parser.flang`. Напиши `обеспечивает` у библиотечной функции — и
 * `flang/test/self-parser.test.mjs` покраснеет на сверке AST. Правило записано в
 * дереве прямым текстом и стережётся отдельной проверкой в
 * `flang/test/proof-kernel.test.mjs`.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgram, loadProgramFromSource } from "../bin/flang.mjs"
import { obligations, одинаковы } from "../src/obligations.mjs"
import { checkProofs, КОДЫ, СИЛА } from "../src/proofterm.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const УТВЕРЖДЕНИЯ = "flang/proof/examples/corpus-lists.flang"
const БИБЛИОТЕКА = "flang/stdlib/lists.flang"

/** Обязательства и вердикты ядра для текста — тем же путём, каким их считает оболочка. */
async function разобрать(исходник) {
  const программа = await loadProgramFromSource(исходник, "заказ.flang")
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, внешнее, об, ядро, первый: ядро.checked[0] ?? null }
}

