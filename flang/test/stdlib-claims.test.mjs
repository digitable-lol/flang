/**
 * «Абсолютное значение» — строка, вычеркнутая из заказа 15 августа 2026 не
 * потому, что ядро научилось, а потому, что просить было НЕЧЕГО.
 *
 * В `НЕ_БЕРЁТ` она стояла с такой причиной: «правило выбора требует
 * неотрицательности ОБЕИХ ветвей и не читает УСЛОВИЯ `если`; ветвь `0 минус
 * число` неотрицательна ровно потому, что стоит под условием `число меньше 0`».
 * Первая половина правды — ядро условия и правда не читает. Вторая половина —
 * «утверждение всё-таки ПРАВДА» — ЛОЖЬ, и вход стоит ниже:
 *
 *   «Абсолютное значение» от NaN даёт NaN, а `NaN не меньше 0` есть `нет`.
 *
 * И NaN здесь не выдумка проверяющего: литерала для него в языке нет, а
 * ВЫЧИСЛИТЬ его можно `0 делить на 0` — типизация пропускает это без единой
 * диагностики, потому что деление на ноль в flang даёт значение IEEE-754, а не
 * ошибку (`builtins.mjs`). Поэтому ниже NaN приходит не аргументом, а СЧЁТОМ:
 * ровно так, как он попал бы в настоящую программу.
 *
 * ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ ЯДРА. Сужение по условию (`если х … то <здесь
 * условие верно>`) в ветви `то` — приём законный: сравнение, давшее `да`,
 * исключает NaN само. В ветви `иначе` он ЛОЖЕН: сравнение, давшее `нет`, не
 * говорит ничего, потому что на NaN ложны ОБЕ стороны. А «Абсолютному значению»
 * нужна именно ветвь `иначе`. Замер того, что дало бы сужение обеих ветвей,
 * стоит в `flang/test/proof-kernel.test.mjs` («сужение по условию: цена
 * измерена») и равен ОДНОЙ цели на весь корпус — вот этой, то есть лжи.
 */
test("заказ: «Абсолютное значение» — утверждение ЛОЖНО, и NaN сюда ПОСЧИТАН, а не подан", async () => {
  const библиотека = await loadProgram(`${корень}flang/stdlib/numbers.flang`)
  const функция = функцияИз(библиотека, "Абсолютное значение")
  assert.ok(функция !== undefined, "функции в файле нет — список протух")

  /* Половина первая: ядро НЕ БЕРЁТ, и это по-прежнему так. */
  const сведение = берётЛиЯдро(функция, ЦЕЛЬ_ДНА, определенияМодуля(библиотека))
  assert.equal(
    сведение.ok,
    false,
    "ядро доказало «модуль числа неотрицателен» — а это ЛОЖЬ на NaN, см. ниже:"
      + " разбирайтесь с ядром, а не с этой строкой",
  )
  assert.ok(сведение.why.includes("неотрицательность по построению не проходит"), сведение.why)

  /* Половина вторая: утверждение НЕ правда, и вход посчитан языком. */
  const счётом = await loadProgramFromSource(
    `модуль «Не число счётом»\n\n`
      /* ДЕЛИТСЯ ПАРАМЕТР, А НЕ ЛИТЕРАЛ: у дерева появился сторож
         `FLANG_NOT_A_NUMBER`, который ловит `0 делить на 0` ПО ОПЕРАНДАМ и
         отвергает программу до всякого доказательства. Он ловит НАПИСАННОЕ, а
         улика здесь про ПОСЧИТАННОЕ — значение то же, а увидеть его заранее
         нечем. */
      + `тотальная функция «Модуль нуля на ноль»\n`
      + `  принимает делимое: число\n`
      + `  возвращает число\n`
      + `  пример «Ноль на ноль»\n`
      + `    дано делимое равно 0\n`
      + `    ожидается 0\n`
      + `  если (делимое делить на делимое) меньше 0`
      + ` то 0 минус (делимое делить на делимое) иначе (делимое делить на делимое)\n`,
    "нечисло.flang",
  )
  const внешнее = await externalChecks(счётом)
  assert.deepEqual(
    внешнее.diagnostics.filter((б) => б?.severity !== "warning"),
    [],
    "`0 делить на 0` перестало проходить типизацию — тогда перепишите объяснение выше",
  )
  const посчитано = evaluate(счётом, "Модуль нуля на ноль", { делимое: 0 })
  assert.ok(Number.isNaN(посчитано), `тело «Абсолютного значения» на посчитанном NaN дало ${посчитано}`)
  assert.equal(посчитано >= 0, false, "«результат не меньше 0» обязано оставаться ЛОЖЬЮ на NaN")

  /* И то же самое на самой библиотечной функции — чтобы речь шла о ней, а не о
     переписанном здесь теле. */
  assert.ok(Number.isNaN(evaluate(библиотека, "Абсолютное значение", { число: Number.NaN })))
})

