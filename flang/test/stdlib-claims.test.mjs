/**
 * Спросить у ядра ровно тем же способом, каким его спрашивает `proofterm.mjs`:
 * одна подстановка (тело функции на место `результат`) и один вызов `свести` с
 * объявлениями подписи и определениями модуля.
 *
 * Своей логики здесь нет ни строки — иначе заказ отвечал бы на свой вопрос, а не
 * на вопрос ядра.
 */
function берётЛиЯдро(функция, цель, определения) {
  const объявления = (функция.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
  return свести(подставить(цель, { результат: функция.body }), [], объявления, определения)
}

