/**
 * Полный перебор пар «F равна G от …» внутри каждого модуля библиотеки.
 *
 * Зачем он нужен рядом с переписью границ. Та отвечает на вопрос «сколько
 * функций библиотеки ядро берёт на числовую цель» и отвечает «одну». Эта
 * отвечает на другой, и без неё сказанное в отчёте («больше правил тождества у
 * библиотеки взять нечего») было бы утверждением на слово: перебираются ВСЕ
 * упорядоченные пары функций модуля и все наборы аргументов из параметров и
 * маленьких литералов, включая логические. Вопросов к ядру выходит около ста
 * тысяч, время — секунды, и находится РОВНО ПЯТЬ пар. Все пять написаны в
 * библиотеке этой работой, и список ниже — тот же самый.
 *
 * Тавтологий здесь нет и быть не может: ищется равенство тела ВЫЗОВУ ДРУГОЙ
 * функции, а не самому себе. Равенства вида «результат равен телу, записанному
 * второй раз» ядро тоже сводит — их находит перебор с подвыражениями тела, — но
 * они не утверждения, а повторение, и в библиотеке им места нет.
 *
 * Список исполняемый в обе стороны. Появится шестая пара — тест покраснеет и
 * потребует либо написать утверждение, либо объяснить, почему оно повторение.
 * Пропадёт одна из пяти — покраснеет тоже: значит ядро или библиотека изменились.
 */
test("перепись равенств: ядро сводит ровно пять пар функций библиотеки, и все пять написаны", async () => {
  const модули = [
    "dictionary", "hashmap", "higher-order", "lists", "logic", "numbers",
    "numtree", "optional", "result", "sets", "strings", "tree",
  ]
  const найдено = []
  let вопросов = 0
  for (const модуль of модули) {
    const путь = `flang/stdlib/${модуль}.flang`
    const свои = new Set((parse(текст(путь), путь).functions ?? []).map((ф) => ф.name))
    const программа = await loadProgram(`${корень}${путь}`)
    const определения = определенияМодуля(программа)
    const все = (программа.functions ?? []).filter(
      (ф) => свои.has(ф.name) && ф.body !== null && ф.body !== undefined,
    )
    for (const функция of все) {
      const объявления = (функция.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
      const листья = [
        ...(функция.params ?? []).map((п) => пер(п.name)),
        { kind: "literal", value: 0 },
        { kind: "literal", value: 1 },
        { kind: "literal", value: 2 },
        { kind: "literal", value: 3 },
        { kind: "literal", value: true },
        { kind: "literal", value: false },
      ]
      for (const другая of все) {
        if (другая.name === функция.name) continue
        const арность = (другая.params ?? []).length
        if (арность === 0 || арность > 2) continue
        const наборы = арность === 1
          ? листья.map((а) => [а])
          : листья.flatMap((а) => листья.map((б) => [а, б]))
        for (const набор of наборы) {
          вопросов += 1
          const цель = цельРавенства({ kind: "call", name: другая.name, args: набор })
          const итог = свести(подставить(цель, { результат: функция.body }), [], объявления, определения)
          if (!итог.ok) continue
          const доводы = набор.map((а) => (а.kind === "var" ? а.name : String(а.value))).join(" и ")
          найдено.push(`${путь} «${функция.name}» = «${другая.name}» от ${доводы}`)
          break
        }
      }
    }
  }
  assert.ok(вопросов > 100000, `вопросов к ядру всего ${вопросов} — перебор сузился, и «больше нечего» стало пустым словом`)
  assert.deepEqual(найдено.sort(), [
    "flang/stdlib/higher-order.flang «Возвести в квадрат» = «Умножить» от х и х",
    "flang/stdlib/higher-order.flang «Удвоить» = «Сложить» от х и х",
    "flang/stdlib/higher-order.flang «Утроить» = «Умножить» от х и 3",
    "flang/stdlib/logic.flang «Не так» = «Следует» от значение и false",
    "flang/stdlib/numbers.flang «Чётное» = «Делится на» от число и 2",
  ].sort(), "пары изменились: ядро выросло, библиотека изменилась — либо и то, и другое")

  /* И обратная половина: каждая найденная пара ДОЛЖНА быть написана у функции.
     Без неё список был бы поиском без последствий. */
  const написаны = new Set(НАПИСАНО.filter((з) => з.правило === "тождество после переписки допущением").map((з) => `${з.путь} «${з.функция}»`))
  for (const строка of найдено) {
    const где = строка.slice(0, строка.indexOf("» =") + 1)
    assert.ok(написаны.has(где), `${где}: ядро сводит равенство, а утверждения у функции нет`)
  }
})

