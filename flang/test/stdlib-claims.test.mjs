    почему:
      "правило выбора требует неотрицательности ОБЕИХ ветвей и не читает УСЛОВИЯ `если`."
      + " Здесь ветвь `0 минус число` неотрицательна ровно потому, что стоит под условием"
      + " `число меньше 0`, а условие ядру недоступно: оно не входит ни в допущения, ни в"
      + " объявления. Вдобавок вычитания в правиле дна нет и не будет — разность двух"
