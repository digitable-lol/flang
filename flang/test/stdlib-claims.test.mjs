/**
 * Обход ВСЕХ функций библиотеки с одним и тем же вопросом к ядру.
 *
 * Число здесь — главный ответ работы над `flang/stdlib`, и он неприятный: на
 * 185 функций двенадцати модулей ядро берёт цель «результат не меньше 0» у НУЛЯ
 * функций, а «результат не больше <литерал>» — у одной. Стоять это обязано в
 * исполняемом виде, потому что «почти нигде» — настроение, а «0 и 1 из 185» —
 * измерение, и вырасти оно может только от работы над ядром, а не от пересказа.
 *
 * Почему ноль по дну — видно из заказа выше: тела библиотеки собраны из свёрток,
 * разборов встроенного списка, остатков и умножений, а правило дна берёт
 * литерал, имя типа `нат`, допущение, их сумму и выбор из них. Ни одного `нат`
 * в подписях библиотеки при этом всего три, и все три стоят у функций, чьи тела
 * ядру не по зубам («Степень», «Факториал», «Поиск в диапазоне»).
 *
 * Утверждения, которые в библиотеке ВСЁ-ТАКИ написаны, этим числом не
 * считаются и не должны: четыре из шести — равенства, а перепись спрашивает про
 * границы. Обе цели заведены здесь порознь ровно поэтому.
 */
const ЦЕЛИ_ПЕРЕПИСИ = [
  ["не меньше 0", ЦЕЛЬ_ДНА],
  ["не больше 2^53−1", цельПотолка(9007199254740991)],
  ["не больше 1", цельПотолка(1)],
  ["не больше 100", цельПотолка(100)],
]

test("перепись: ядро берёт числовую цель ровно у этих функций библиотеки", async () => {
  const модули = [
    "dictionary", "hashmap", "higher-order", "lists", "logic", "numbers",
    "numtree", "optional", "result", "sets", "strings", "tree",
  ]
  const найдено = []
  let всего = 0
  for (const модуль of модули) {
    const путь = `flang/stdlib/${модуль}.flang`
    const свои = new Set((parse(текст(путь), путь).functions ?? []).map((ф) => ф.name))
    const программа = await loadProgram(`${корень}${путь}`)
    const определения = определенияМодуля(программа)
    for (const функция of программа.functions ?? []) {
      if (!свои.has(функция.name)) continue
      if (функция.body === null || функция.body === undefined) continue
      всего += 1
      /* Цели перебираются ВСЕ, без остановки на первой сошедшейся: границы
         разные, и «сошлась хоть одна» скрыло бы, какая именно. Перепись, у
         которой из трёх ответов виден один, — это перепись, которая молча
         меняется при смене порядка строк. */
      for (const [словами, цель] of ЦЕЛИ_ПЕРЕПИСИ) {
        if (!берётЛиЯдро(функция, цель, определения).ok) continue
        найдено.push(`${путь} «${функция.name}»: ${словами}`)
      }
    }
  }
  assert.equal(всего, 196, `функций библиотеки стало ${всего} — обход смотрит не туда либо библиотека выросла`)
  assert.deepEqual(
    найдено.sort(),
    [
      /* ШЕСТЬ СТРОК ПРИБАВИЛА СБОРКА `work/svodka3`, и все шесть — от одного
         правила: ядро научилось читать факт о результате ВСТРОЕННОЙ ФОРМЫ
         (`длина` объявлена `нат`) и об индукции свёртки (`work/kernel-builtins`).
         Это не «ядро выросло вообще»: каждая из шести — счётчик, чьё тело либо
         есть `длина`, либо свёртка с неотрицательным началом. */
      "flang/stdlib/dictionary.flang «Размер»: не меньше 0",
      "flang/stdlib/hashmap.flang «Размер словаря»: не меньше 0",
      "flang/stdlib/higher-order.flang «Считать где»: не меньше 0",
      "flang/stdlib/lists.flang «Считать вхождения»: не меньше 0",
      "flang/stdlib/numbers.flang «Знак»: не больше 1",
      "flang/stdlib/numbers.flang «Знак»: не больше 100",
      "flang/stdlib/numbers.flang «Знак»: не больше 2^53−1",
      "flang/stdlib/sets.flang «Размер множества»: не меньше 0",
      "flang/stdlib/strings.flang «Позиция подстроки»: не меньше 0",
      /* Приехала с `work/stdlib-grow`: «Сколько дополнить» получила в библиотеке
         обычный вид (`ширина минус длина` при `ширина не меньше длины`), и
         ПОТОЛОК у неё ядро берёт — разность ограниченного и неотрицательного не
         выходит за точную сетку. Дно оно по-прежнему не берёт, и это по делу:
         без предусловия разность бывает отрицательной. */
      "flang/stdlib/strings.flang «Сколько дополнить»: не больше 2^53−1",
    ].sort(),
    "перепись библиотеки изменилась: ядро выросло (тогда впишите новые строки и напишите"
      + " утверждения в библиотеке) или библиотека изменилась (тогда проверьте заказ)",
  )
})

