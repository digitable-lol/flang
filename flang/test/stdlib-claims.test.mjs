/**
 * Утверждения о СТАНДАРТНОЙ БИБЛИОТЕКЕ: что о ней сказано, что доказано и чего
 * сказать пока нельзя.
 *
 * ── Почему файл один, а частей две ──────────────────────────────────────────
 * Две ветки писали об одном и том же — о `flang/stdlib` — и обе завели файл с
 * этим именем: `work/svodka2` (утверждения о списке и высшем порядке,
 * перенесённые в `flang/proof/examples/corpus-*.flang`, и заказы 1–6) и
 * `work/claims-stdlib` (утверждения, написанные ПРЯМО в библиотеке, заказ
 * НЕ_БЕРЁТ и три переписи). При слиянии `work/kernel-conditions` они сведены в
 * один файл, а не в два: обе половины ссылаются на это имя из своей прозы
 * (`corpus-lists.flang`, `numbers.flang`, `logic.flang`, `SPEC.md`,
 * `corpus-claims.test.mjs` и ещё четыре места), и переименование любой из них
 * увело бы половину ссылок в пустоту. Ничего, кроме дублирующихся импортов и
 * второго `корень`, при сведении не тронуто.
 *
 * ── ЧАСТЬ ПЕРВАЯ (`work/svodka2`): что высказано и чего доказать нельзя ──────
 * В `flang/stdlib/` двенадцать модулей, 4301 строка, 185 функций, и до этой
 * работы постусловий в них было НОЛЬ, теорем НОЛЬ. Тотальными доказаны 2196
 * функций корпуса, но тотальность — про завершение, а не про правильность: о
 * «Сортировать» было доказано, что она останавливается, и не сказано, что она не
 * теряет элементов.
 *
 *   1. ЧТО ВЫСКАЗАНО И ЧТО ДОКАЗАНО. Двадцать одно утверждение о восемнадцати
 *      настоящих функциях библиотеки: пятнадцать о `flang/stdlib/lists.flang`
 *      (14 функций из 28) в `flang/proof/examples/corpus-lists.flang` и шесть о
 *      `flang/stdlib/higher-order.flang` (4 функции из 34) в `corpus-hof.flang`.
 *      Тела перенесены ДОСЛОВНО, и дословность сличает машина, а не глаз. ТРИ
 *      из них теперь ДОКАЗАНЫ индукцией по встроенному списку, восемнадцать
 *      по-прежнему стоят словом «сетка», и проверки ниже закрепляют И ТО, И
 *      ДРУГОЕ: ни поднять слово молча, ни уронить его молча нельзя.
 *
 *   2. ЧТО ДОКАЗАТЬ ПО-ПРЕЖНЕМУ НЕЛЬЗЯ, И ПОЧЕМУ — ИМЕНАМИ ОТКАЗОВ. Заказы,
 *      каждый — настоящая функция библиотеки, настоящая попытка доказательства
 *      и настоящий отказ с кодом. Это не список пожеланий: как только ядро (или
 *      поверхность) научится названному, соответствующая проверка ПОКРАСНЕЕТ и
 *      потребует перевести утверждение из сетки в доказанное. Тест, который не
 *      умеет краснеть, хуже отсутствующего — поэтому заказ записан исполняемым,
 *      а не прозой. Заказ 1 (начальная алгебра встроенного списка) ЗАКРЫТ, и на
 *      его месте стоит проверка того, что он закрыт, плюс разбор оставшихся
 *      двенадцати сеточных утверждений о списке ПО ПРИЧИНАМ: раньше причина
 *      была одна на все, теперь у каждого своя и названа числом.
 *
 * ── Почему утверждения части первой лежат не у самих функций ────────────────
 * `flang/stdlib` входит в корпус побайтовой неподвижной точки самоприменения
 * ЦЕЛИКОМ, а у восьми слов слоя доказательства нет продукции в
 * `flang/self/parser.flang`. Напиши ТЕОРЕМУ у библиотечной функции — и
 * `flang/test/self-parser.test.mjs` покраснеет на сверке AST. Правило записано в
 * дереве прямым текстом и стережётся отдельной проверкой в
 * `flang/test/proof-kernel.test.mjs`. (Постусловие `обеспечивает` продукцию
 * имеет, и часть вторая пишет его прямо в библиотеке — расхождения между двумя
 * шапками здесь нет, запрет всегда был про слова ТЕОРЕМЫ.)
 *
 * ── ЧАСТЬ ВТОРАЯ (`work/claims-stdlib`): граница того, что ядро берёт ────────
 *
 *   3. НАПИСАНО. Каждое утверждение библиотеки: доказано ядром (а не посчитано
 *      сеткой), названо правило, и утверждение ПРАВДА на враждебной выборке —
 *      не на примерах автора, которые ядро и так видело.
 *   4. ИЗЪЯТИЕ. Снимите строку — утверждения не станет вовсе.
 *   5. ЛОЖЬ. Испорченное на один знак утверждение ядро доказанным НЕ объявляет,
 *      ведомость говорит «НАРУШЕНО» с именем примера, а прогон отказывает кодом
 *      `FLANG_PROPERTY`. Здесь же измерена ГРАНИЦА МОЛЧАНИЯ: диагностики ядро не
 *      даёт — постусловие без теоремы, которое не свелось, не ошибка, — и это
 *      проверяется отбором по префиксу `FLANG_PROOF`, а не пересказом.
 *   6. ЗАКАЗ. Утверждения о библиотеке, которые ПРАВДА и которых ядро сегодня НЕ
 *      берёт, — с причиной у каждого, с дословным отказом ядра и с
 *      доказательством правды вычислением. Список исполняемый: научится ядро —
 *      строка покраснеет и потребует себя вычеркнуть.
 *   7. ИНДУКЦИЯ, КОТОРУЮ НЕЧЕМ ЗАКРЫТЬ. Отдельный случай заказа, и самый
 *      дорогой: у «Глубины словаря» из `hashmap.flang` СВОДЯТСЯ ВСЕ ЧЕТЫРЕ
 *      посылки принципа, а доказательства всё равно нет — две базы связывают
 *      имена полей, и закрыть их нечем ни `по примеру`, ни `по предположению`.
 *      Оба отказа сняты прогоном и стоят здесь дословно.
 *   8. ЗАКАЗ, ОКАЗАВШИЙСЯ ЛОЖЬЮ, и границы, снятые прогоном (разделы 5а и 5б).
 *      Строка заказа обязана уметь не только вычёркиваться, но и ОПРОВЕРГАТЬСЯ:
 *      у «Абсолютного значения» вторая половина («утверждение всё-таки правда»)
 *      не выдержала NaN, и вместо заказа там теперь стоит контрпример — ровно
 *      такой же, как у «Поиска в диапазоне». Рядом сняты прогоном границы
 *      `остаток от`, на которых держатся причины трёх оставшихся строк.
 *
 * Запуск: node --test flang/test/stdlib-claims.test.mjs
 */
