/**
 * Третий список, и он не про ядро.
 *
 * Три утверждения ниже ПРАВДА, и ядро доказывает каждое — измерено прямо здесь,
 * тем же `свести` и тем же правилом. Написать их в библиотеке всё равно нельзя:
 * функции лежат в РАЗНЫХ модулях, а модули `flang/stdlib` друг друга не
 * подключают. Решение это не случайное и записано в самой библиотеке
 * (`strings.flang`, шапка «Приписать строку в начало»): модули проверяются
 * ПООДИНОЧКЕ (`flang/test/stdlib.test.mjs` разбирает каждый файл сам по себе,
 * без связывания), и `использует «Списки»` сделал бы файл непроверяемым тем
 * тестом. Цена решения была названа там же в функциях («одна из трёх копий
 * приписывания — цена того, что библиотека сама себя не связывает»); здесь она
 * названа в УТВЕРЖДЕНИЯХ: три доказуемых факта, которые сегодня держатся
 * сеткой примеров в тестах.
 *
 * Самое дорогое из трёх — согласие двух хешей. `hashmap.flang` говорит о своём
 * «Хеш ключа»: «Побайтово та же функция, что „Хеш строки“ в `tree.flang`, и это
 * проверено сеткой в `flang/test/hashmap.test.mjs`: два модуля обязаны
 * согласиться, иначе два словаря библиотеки разошлись бы в том, какой ключ куда
 * попадает». Согласие это ДОКАЗУЕМО — и доказано быть не может, пока один модуль
 * не видит другого.
 *
 * Список исполняемый в обе стороны: перестань ядро брать хоть одно — покраснеет;
 * появись у библиотеки связывание — строку надо будет вычеркнуть и написать
 * утверждение у функции.
 */
const БЕЗ_СВЯЗЫВАНИЯ = [
  {
    путь: "flang/stdlib/numbers.flang",
    функция: "Минимум двух",
    чужой: "flang/stdlib/higher-order.flang",
    другая: "Меньшее",
    доводы: (д) => д,
    цель: () => цельРавенства(зов("Меньшее", пер("первое"), пер("второе"))),
    словами: "«Минимум двух» и «Меньшее» — одна функция, написанная дважды",
  },
  {
    путь: "flang/stdlib/numbers.flang",
    функция: "Максимум двух",
    чужой: "flang/stdlib/higher-order.flang",
    другая: "Большее",
    доводы: (д) => д,
    цель: () => цельРавенства(зов("Большее", пер("первое"), пер("второе"))),
    словами: "«Максимум двух» и «Большее» — одна функция, написанная дважды",
  },
  {
    путь: "flang/stdlib/hashmap.flang",
    функция: "Хеш ключа",
    чужой: "flang/stdlib/tree.flang",
    другая: "Хеш строки",
    доводы: (д) => ({ текст: д.ключ }),
    цель: () => цельРавенства(зов("Хеш строки", пер("ключ"))),
    словами: "два словаря библиотеки считают ОДИН хеш — сегодня это проверено сеткой",
  },
]

const ВЫБОРКА = {
  "Минимум двух": [{ первое: 0, второе: -0 }, { первое: 2, второе: 5 }, { первое: 5, второе: 2 }, { первое: -1e308, второе: 1e308 }, { первое: 2.5, второе: 2.5 }],
  "Максимум двух": [{ первое: 0, второе: -0 }, { первое: 2, второе: 5 }, { первое: 5, второе: 2 }, { первое: -1e308, второе: 1e308 }, { первое: 2.5, второе: 2.5 }],
  "Хеш ключа": [{ ключ: "" }, { ключ: "a" }, { ключ: "ab" }, { ключ: "имя" }, { ключ: "中" }, { ключ: "0123456789" }],
}

for (const запись of БЕЗ_СВЯЗЫВАНИЯ) {
  test(`без связывания: ${запись.словами}`, async () => {
    const своя = await loadProgram(`${корень}${запись.путь}`)
    const чужая = await loadProgram(`${корень}${запись.чужой}`)

    /* Половина первая: ЯДРО БЕРЁТ. Определения собраны из двух модулей — ровно
       то, что ядро увидело бы, свяжи библиотека себя сама. Своей логики здесь
       нет: тот же `свести`, та же подстановка. */
    const определения = new Map()
    for (const ф of [...(своя.functions ?? []), ...(чужая.functions ?? [])]) {
      if (!определения.has(ф.name)) определения.set(ф.name, ф)
    }
    const функция = функцияИз(своя, запись.функция)
    const объявления = (функция.params ?? []).map((п) => ({ name: п.name, type: п.type ?? null }))
    const итог = свести(подставить(запись.цель(), { результат: функция.body }), [], объявления, определения)
    assert.equal(итог.ok, true, `ядро перестало брать это утверждение: ${итог.why}`)
    assert.equal(итог.rule, "тождество после переписки допущением")

    /* Половина вторая: это ПРАВДА — сличением значений двух функций. */
    for (const доводы of ВЫБОРКА[запись.функция]) {
      const здесь = evaluate(своя, запись.функция, доводы)
      const там = evaluate(чужая, запись.другая, запись.доводы(доводы))
      assert.ok(
        Object.is(здесь, там),
        `на ${JSON.stringify(доводы)}: «${запись.функция}» дала ${здесь}, «${запись.другая}» — ${там}`,
      )
    }

    /* Половина третья: препятствие НАСТОЯЩЕЕ, а не выдуманное. Ни один модуль
       библиотеки никого не подключает — значит написать это утверждение у
       функции сегодня нечем. Появится связывание — эта строка покраснеет. */
    for (const путь of [запись.путь, запись.чужой]) {
      const разобрано = parse(текст(путь), путь)
      const подключения = (разобрано.legacy ?? [])
        .filter((узел) => узел?.construct === "moduleHeader")
        .flatMap((узел) => узел.value?.imports ?? [])
      assert.deepEqual(подключения, [], `${путь} начал подключать чужой модуль — вычеркните строку и напишите утверждение`)
    }
  })
}
