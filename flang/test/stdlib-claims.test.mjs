test("границы `остаток от` сняты прогоном: посылок у правила дна ДВЕ, а у потолка ТРИ", async () => {
  /* Причины у трёх строк заказа («В кольцо» дважды и «Хеш строки») держатся на
     том, чего `остаток от` НЕ обещает. Держаться это обязано на прогоне: «знак
     остатка повторяет знак делимого» — пересказ учебника, а строки ниже —
     ответы этого языка на этой машине.

     Считает всё сам язык, а не JavaScript: `остаток от` — форма flang, и
     спрашивать про неё JS-оператор `%` значило бы спрашивать не про неё. */
  const проба = await loadProgramFromSource(
    `модуль «Остаток»\n\n`
      + `тотальная функция «Остаток от трёх»\n`
      + `  принимает значение: число\n`
      + `  возвращает число\n`
      + `  пример «Пять»\n`
      + `    дано значение равно 5\n`
      + `    ожидается 2\n`
      + `  значение остаток от 3\n`,
    "остаток.flang",
  )
  const остаток = (значение) => evaluate(проба, "Остаток от трёх", { значение })

  /* 1. ЗНАК ОСТАТКА — ЗНАК ДЕЛИМОГО. Отсюда первая посылка правила дна. */
  assert.equal(остаток(5), 2)
  assert.equal(остаток(-5), -2, "остаток отрицательного отрицателен — правило дна без посылки о знаке ЛОЖНО")

  /* 2. КОНЕЧНОСТЬ — ВТОРАЯ ПОСЫЛКА, И ЕЁ В ЗАКАЗЕ НЕ БЫЛО. `бесконечность` не
        меньше нуля (истина!), а остаток от неё — не число. Значит одной
        неотрицательности делимого правилу МАЛО. */
  assert.equal(Number.POSITIVE_INFINITY >= 0, true, "посылка «делимое неотрицательно» на +∞ ИСТИННА")
  assert.ok(Number.isNaN(остаток(Number.POSITIVE_INFINITY)), "а остаток от +∞ — не число")
  assert.equal(остаток(Number.POSITIVE_INFINITY) >= 0, false, "и вывод правила на нём ЛОЖЕН")

  /* 3. МИНУС НОЛЬ контрпримером НЕ является, и это стоит проверить: на нём за
        сутки попадались трижды. `-0 остаток от 3` есть −0, а `-0 не меньше 0`
        истинно. Ломается на нём не порядок, а `равен` (Object.is). */
  assert.ok(Object.is(остаток(-0), -0), "минус ноль в остатке остаётся минус нулём")
  assert.equal(остаток(-0) >= 0, true, "и «не меньше 0» на нём ИСТИННО")
  assert.equal(Object.is(остаток(-0), 0), false, "а «равен 0» — ложно, и это разные вопросы")

  /* 4. ЦЕЛОСТЬ — третья посылка, нужная ПОТОЛКУ. `а остаток от м` меньше `м`
        всегда (при конечном `а`), но цель «В кольцо» просит м−1, а это верно
        только для целого делимого. */
  assert.equal(остаток(2.5), 2.5, "дробное делимое даёт дробный остаток")
  assert.equal(остаток(2.5) <= 2, false, "и он БОЛЬШЕ, чем м−1 = 2: граница м−1 держится на целости")
  assert.equal(остаток(1e308), 2, "а на большом |x| остаток точен: fmod не теряет битов")

  /* 5. И обратная половина: «В кольцо» из библиотеки все эти углы ЗАКРЫВАЕТ —
        поэтому обе строки заказа о ней остаются заказом, а не ложью. */
  const хешмап = await loadProgram(`${корень}flang/stdlib/hashmap.flang`)
  const углы = [0, -0, -1, -100000007, 2.5, -2.5, 1e308, -1e308, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY, Number.NaN]
  for (const значение of углы) {
    const вычет = evaluate(хешмап, "В кольцо", { значение })
    assert.ok(вычет >= 0, `«В кольцо» от ${значение} дала ${вычет} — утверждение о дне НЕ правда`)
    assert.ok(вычет <= 100000006, `«В кольцо» от ${значение} дала ${вычет} — утверждение о потолке НЕ правда`)
  }
})

