test("две доказаны индукцией по списку, тринадцать — сетка, и ни одно слово нельзя сдвинуть молча", async () => {
  /* Главная проверка первой части, и она стережёт обе стороны.

     СЕТКА не должна тихо стать «доказано»: постусловие без теоремы — это
     утверждение, посчитанное на примерах автора, и ведомость обязана называть
     его сеткой. Появись здесь «доказано» — значит кто-то либо написал теорему
     (тогда её надо перенести сюда и пересчитать свод), либо ослабил утверждение
     до того, что ядро глотает.

     «ДОКАЗАНО» не должно тихо стать сеткой: два утверждения о списке доказаны
     индукцией, и если завтра правило ядра ослабнет, это обязано покраснеть
     здесь, а не пройти как «ну, сетка тоже неплохо». Проверяется не слово, а
     вердикт ядра — и то, что носитель у него именно индукция по «список». */
  const программа = await loadProgram(join(корень, УТВЕРЖДЕНИЯ))
  const внешнее = await externalChecks(программа)
  assert.deepEqual(внешнее.diagnostics, [], JSON.stringify(внешнее.diagnostics))
  const об = obligations(программа, внешнее.results)
  assert.deepEqual(об.diagnostics, [], JSON.stringify(об.diagnostics))

  const постусловия = об.obligations.filter((о) => о.kind === "postcondition")
  assert.equal(постусловия.length, ВЫСКАЗАНО.length, "пятнадцать утверждений, ни одним больше")
  const ядро = checkProofs(программа, об.obligations)

  for (const запись of ВЫСКАЗАНО) {
    const цель = постусловия.find((о) => о.name === запись.утверждение)
    assert.ok(цель !== undefined, `нет утверждения «${запись.утверждение}»`)
    assert.equal(цель.of, запись.функция, `утверждение «${запись.утверждение}» приписано не той функции`)
    assert.ok(цель.grid > 0, `у «${запись.утверждение}» нет ни одного примера: это уже не сетка, а «объявлено»`)

    const вердикт = ядро.checked.find((з) => з.name === запись.утверждение) ?? null
    if (запись.доказано !== true) {
      assert.equal(цель.proof, null, `у «${запись.утверждение}» появилась теорема — свод надо пересчитать`)
      assert.equal(вердикт, null, `ядро проверило «${запись.утверждение}», а теоремы при нём нет`)
      continue
    }
    assert.ok(цель.proof !== null, `у «${запись.утверждение}» пропала теорема`)
    assert.ok(вердикт !== null, `ядро не проверило «${запись.утверждение}»`)
    assert.equal(вердикт.verdict, СИЛА.proved, вердикт.says)
    /* Носитель назван: не «доказано вообще», а доказано индукцией по списку,
       базой и шагом при допущении на ХВОСТЕ. */
    assert.equal(вердикт.induction.type, "список", вердикт.says)
    assert.equal(вердикт.induction.base, 1)
    assert.equal(вердикт.induction.step, 1)
    const шаг = вердикт.cases.find((с) => с.kind === "step")
    assert.deepEqual(шаг.parts, ["хвост"], "допущение — о хвосте, потому что хвост есть часть значения")
  }

  const доказанных = ВЫСКАЗАНО.filter((з) => з.доказано === true).length
  assert.equal(доказанных, 2, "доказано о lists.flang: «длина неотрицательна» и «индекс неотрицателен»")
  assert.equal(ядро.checked.length, доказанных, "ядру здесь проверять ровно доказанные, и ни одним больше")
})

/* Числа, ради которых закрывался заказ, — и разбор ОСТАВШИХСЯ по причинам.
 *
 * До этой работы у всех пятнадцати утверждений о списке причина была ОДНА:
 * начинать не с чего. Теперь начинать есть с чего, и каждое оставшееся упирается
 * в свою границу. Разбор считается тем же чтением, каким пользуется само ядро —
 * тело нормализуется и сличается с параметром квантора, вид цели читается с
 * узла, — чтобы у вопроса «почему не доказано» был один ответ, а не два.
 */
test("ЗАМЕР: почему остальные тринадцать всё ещё сетка — по причинам, а не одной строкой", async () => {
  const программа = await loadProgram(join(корень, УТВЕРЖДЕНИЯ))
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const постусловия = об.obligations.filter((о) => о.kind === "postcondition")

  let разбором = 0
  let подПравило = 0
  const поФункции = new Map(программа.functions.map((ф) => [ф.name, ф]))
  for (const цель of постусловия) {
    const функция = поФункции.get(цель.of)
    const тело = нормализовать(функция?.body ?? null)
    const это = тело?.kind === "match"
      && тело.target?.kind === "var"
      && тело.target.name === цель.forall?.name
    if (!это) continue
    разбором += 1
    /* Правил сведения два, и оба про особый правый край: «не меньше 0» и
       «равно». Читается это здесь тем же способом, каким читает `свести`. */
    const цельВыражение = цель.goal
    const годится = цельВыражение?.kind === "binary"
      && ((цельВыражение.op === "gte" && цельВыражение.right?.kind === "literal" && цельВыражение.right.value === 0)
        || цельВыражение.op === "eq")
    if (годится) подПравило += 1
  }

  assert.equal(постусловия.length, 15, "утверждений о lists.flang")
  assert.equal(разбором, 7, "у скольких тело — `разбор` параметра квантора: только с них индукция начинается")
  assert.equal(подПравило, 3, "у скольких при этом цель того вида, к которому у ядра есть правило сведения")
  /* Итого 15 = 2 доказано + 1 (заказ 2, развёртка определений в базе)
     + 4 (заказ 4, цель сравнивает не с нулём и не на равенство)
     + 8 (заказ 6, тело — свёртка или встроенная форма, а не `разбор`). */
  assert.equal(постусловия.length - разбором, 8, "заказ 6: тело — свёртка или встроенная форма")
  assert.equal(разбором - подПравило, 4, "заказ 4: цель сравнивает не с нулём и не на равенство")
})

