test("ЗАКАЗ 3: закрытое заключение закрывается примером, даже когда образец связывает имена", async () => {
  /* ТА ЖЕ ПОПРАВКА, ЧТО У ЗАКАЗА 2, И ПО ТОЙ ЖЕ ПРИЧИНЕ. Ветка требовала здесь
     «отвергнуто», потому что «Четвёрка» зовёт `«Больше из двух»`, а вызов не
     разворачивался. В собранном дереве он разворачивается (плоское
     определение), и с ним закрывается весь случай — а значит и «Гроздь»
     остаётся единственным отказом. */
  const { первый } = await разобрать(ГЛУБИНА_СЛОВАРЯ)
  assert.equal(первый.verdict, СИЛА.refused, первый.says)

  /* Два варианта из четырёх прошли, и «Одиночка» — тот самый, что раньше
     отвергался по НЕВЕРНОМУ доводу («образец связывает имена»). Тело его ветви
     — литерал `1`, связанных имён оно не употребляет, заключение выходит
     закрытым (`1 не меньше 0`), значение одно, и вычисление отвечает про весь
     случай. Это была не осторожность, а проверка не того. */
  for (const имя of ["Пустое место", "Одиночка"]) {
    const случай = первый.cases.find((с) => с.variant === имя)
    assert.equal(случай.verdict, СИЛА.proved, `«${имя}»: заключение закрыто, примером закрывается`)
  }

  /* Отвергнуты два, и причины у них РАЗНЫЕ — именно поэтому отказ печатает все
     места, а не первое.

     «Гроздь» — пример о другом значении: он задаёт словарь как «Одиночку», а
     случай разбирает «Гроздь». Правило «пример обязан быть образцом ЭТОГО
     случая» никуда не делось и стоит здесь уликой.
     «Четвёрка» — заказ 2: тело ветви зовёт «Больше из двух», а вызов ядро не
     разворачивает. */
  assert.equal(первый.cases.find((с) => с.variant === "Гроздь").verdict, СИЛА.refused)
  assert.equal(первый.cases.find((с) => с.variant === "Четвёрка").verdict, СИЛА.proved,
    "«Четвёрка» закрывается развёрткой «Больше из двух» — заказ 2 выполнен")
  assert.equal(первый.refusals.length, 1, JSON.stringify(первый.refusals))

  const гроздь = первый.refusals.find((о) => /база «Гроздь»/u.test(о.message))
  assert.ok(гроздь !== undefined, JSON.stringify(первый.refusals))
  assert.match(гроздь.message, /это утверждение о другом значении/u)

  assert.equal(первый.refusals.find((о) => /шаг «Четвёрка»/u.test(о.message)), undefined,
    "«Четвёрка» больше не отвергается: развёртка определения закрыла её")
})

