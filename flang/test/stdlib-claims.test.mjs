/* 4. ЗАМЕР ПО ВСЕМУ КОРПУСУ: чего не хватает КАЖДОМУ недоказанному    */
/* ================================================================== */

/**
 * Разложение ВСЕХ недоказанных утверждений дерева по причинам — числом.
 *
 * ── Зачем оно понадобилось отдельно от замера по `lists.flang` ──────────────
 * Замер выше считает пятнадцать утверждений одного модуля и называет заказ 4
 * («вид цели») на четырёх из них. Список этот составлялся ДО того, как у
 * встроенного списка появилась начальная алгебра, и с тех пор он неполон: пятое
 * такое утверждение лежит в `corpus-hof.flang` («позиция не выходит за список»),
 * и никакой замер его не считал. Здесь считается весь корпус разом, поэтому
 * пересчитывать вручную больше не придётся.
 *
 * ── ГЛАВНОЕ ЧИСЛО ЭТОГО ЗАМЕРА, и оно неожиданное ──────────────────────────
 * Утверждений с целью вида «не больше» при теле-`разбор` ПЯТЬ, и у ВСЕХ ПЯТИ
 * граница цели упоминает переменную индукции: `(«Длина» от элементы)`,
 * `(длина элементы)`, `(«Длина» от первые)`. А это значит, что одним видом цели
 * их не закрыть НИ ОДНОГО, и вот почему — не рассуждением, а тем, что ядро
 * строит:
 *
 *   заключение шага = цель, где переменная индукции заменена КОНСТРУКТОРОМ.
 *   Значит граница становится `«Длина» от (голова и хвост)` — вызовом по
 *   конструктору, — а допущение индукции говорит о `«Длина» от хвост`. Это два
 *   РАЗНЫХ непрозрачных терма, и связать их может только развёртка определения
 *   (заказ 2), которой у ядра нет.
 *
 * То есть заказ 4 не самостоятелен: он половина пары «развёртка + вид цели», и
 * связывающая половина — развёртка. Правило сравнения без неё верно и не
 * закрывает ни одного утверждения корпуса; развёртка без правила сравнения
 * упрётся в «нет вида цели» на первом же шаге. Ровно это и стоит здесь числом,
 * чтобы порядок работ выбирался по замеру, а не по тому, что раньше вспомнилось.
 *
 * Упоминание переменной в границе читается тем же `свободныеИмена` по
 * нормальной форме, каким ядро проверяет закрытость заключения, — чтобы у
 * вопроса «зависит ли граница от переменной» был один ответ на всё дерево.
 */
test("ЗАМЕР ПО КОРПУСУ: 19 недоказанных утверждений разложены по причинам, и вид цели — не узкое место", async () => {
  const каталог = join(корень, "flang/proof/examples")
  const разложение = { алгебры: [], тело: [], видЦели: [], развёртка: [] }
  let всего = 0
  let доказано = 0
  const границаОтПеременной = []

  for (const имя of readdirSync(каталог).sort()) {
    if (!имя.endsWith(".flang")) continue
    const программа = await loadProgram(join(каталог, имя))
    const внешнее = await externalChecks(программа)
    const об = obligations(программа, внешнее.results)
    const ядро = checkProofs(программа, об.obligations)
    const поФункции = new Map((программа.functions ?? []).map((ф) => [ф.name, ф]))
    const суммы = new Set((программа.types ?? []).filter((т) => т.kind === "sum").map((т) => т.name))

    for (const цель of об.obligations) {
      if (цель.kind !== "postcondition" && цель.kind !== "theorem") continue
      всего += 1
      const вердикт = ядро.checked.find((з) => з.name === цель.name) ?? null
      if (вердикт !== null && вердикт.verdict === СИЛА.proved) {
        доказано += 1
        continue
      }
      const запись = `${имя}: ${цель.name}`

      /* 1. Есть ли у переменной квантора начальная алгебра — то, с чего индукция
            вообще НАЧИНАЕТСЯ. У числа и признака конструкторов нет. */
      const переменная = (цель.vars ?? []).find((п) => п.name === цель.forall?.name)
      const тип = переменная?.type ?? null
      const алгебра = тип?.kind === "list" || (тип?.kind === "named" && суммы.has(тип.name))
      if (!алгебра) { разложение.алгебры.push(запись); continue }

      /* 2. Тело — `разбор` переменной квантора на верхнем уровне: иначе
            заключение посылки строить не из чего (заказ 6). */
      const тело = нормализовать(поФункции.get(цель.of)?.body ?? null)
      const разбором = тело?.kind === "match" && тело.target?.kind === "var" && тело.target.name === цель.forall.name
      if (!разбором) { разложение.тело.push(запись); continue }

      /* 3. Вид цели: у ядра правила на «не меньше 0» и «равно», и читается это
            здесь тем же способом, каким читает `свести`. */
      const г = цель.goal
      const подПравило = г?.kind === "binary"
        && ((г.op === "gte" && г.right?.kind === "literal" && г.right.value === 0) || г.op === "eq")
      if (!подПравило) {
        разложение.видЦели.push(запись)
        /* И сразу — упоминает ли граница переменную индукции. Упоминает — значит
           одним видом цели дело не кончится: в шаге она станет вызовом по
           конструктору. */
        const имена = свободныеИмена(нормализовать(г?.right ?? null))
        if ([...имена].includes(цель.forall.name)) границаОтПеременной.push(запись)
        continue
      }
      /* 4. Вид годится, разбор есть, а доказательства нет: значит упёрлось в
            развёртку определения (заказ 2) — вызов по конструктору. */
      разложение.развёртка.push(запись)
    }
  }

  console.log(
    `  замер по корпусу: утверждений ${всего}, доказано ядром ${доказано},`
    + ` без алгебры ${разложение.алгебры.length}, тело не разбор ${разложение.тело.length},`
    + ` вид цели ${разложение.видЦели.length}, развёртка ${разложение.развёртка.length}`,
  )
  /* ПЛЮС ЧЕТЫРЕ, И ВСЕ ЧЕТЫРЕ ДОКАЗАНЫ: `body-forms.flang` показывает три формы
     тела, за которые принцип научился цепляться (условие, свёртка, вызов).
     Разложение недоказанных при этом не сдвинулось ни на строку — и это тоже
     измерение: новые ходы закрыли то, ради чего писались, и ничего не сломали в
     соседних заказах. */
  assert.equal(всего, 97, "утверждений в корпусе")
  assert.equal(доказано, 79, "доказано ядром")
  /* БЫЛО ТРИ, СТАЛО ДВА, и уехавшее названо: «удвоенное неотрицательно» из
     `four-words.flang`. Начальной алгебры у него не появилось и появиться не
     могло — параметр объявлен обычным `число`, — а доказано оно всё равно, и
     этим строка стоит здесь особняком: отсутствие алгебры мешает ИНДУКЦИИ, а не
     доказательству. Закрыл его один ход `свести` — цель с подставленным телом
     сведена к предусловию правилом неотрицательности (случай умножения на
     положительный конечный литерал). То есть счёт «без алгебры» мерит, скольким
     недоказанным индукция недоступна, и вычитать из него «сколько ещё нельзя
     доказать» нельзя. */
  assert.equal(разложение.алгебры.length, 2, "у типа переменной квантора нет конструкторов вовсе")
  assert.equal(разложение.тело.length, 10, "заказ 6: тело — свёртка, встроенная форма или вызов")
  /* ПЯТЬ СТАЛО ЧЕТЫРЬМЯ, и уехавшее названо: «позиция не выходит за список» из
     `corpus-hof.flang` закрыто правилом 4 («порядок по построению», 18 августа
     2026) — граница у цели ТЕРМ, и до правила её читать было нечем. Остальные
     четыре стоят на месте: у них граница тоже терм, но известного о нём ядру не
     хватает, и это разные беды. */
  assert.equal(разложение.видЦели.length, 4, "заказ 4: вид цели вне четырёх правил — ЧЕТЫРЕ, а не пять")
  assert.equal(разложение.развёртка.length, 2, "заказ 2: развёртка определения функции")

  /* Четыре названы поимённо, чтобы «переехало» можно было сверять построчно. */
  assert.deepEqual(разложение.видЦели.sort(), [
    "corpus-lists.flang: взятие не удлиняет",
    "corpus-lists.flang: индекс не выходит за список",
    "corpus-lists.flang: отбрасывание не удлиняет",
    "corpus-lists.flang: сжатие не длиннее первого списка",
  ])

  /* И то самое число, ради которого замер и делался. */
  assert.equal(границаОтПеременной.length, 4, "у всех четырёх граница цели упоминает переменную индукции")
})
