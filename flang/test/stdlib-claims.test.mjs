/**
 * Утверждения о поведении в СТАНДАРТНОЙ БИБЛИОТЕКЕ — и граница того, что ядро
 * берёт у неё сегодня.
 *
 * ── Зачем отдельный файл, если есть `corpus-claims.test.mjs` ────────────────
 *
 * Тот проверяет КОРПУС целиком и меряет ОДНУ цель — «результат не меньше 0».
 * Здесь проверяется `flang/stdlib`: 185 функций, двенадцать модулей, и до
 * 15 августа 2026 в ведомости о них не стояло ни одной строки о поведении —
 * только о том, чем несётся обещание «тотальная». Разница между этими двумя
 * вопросами и есть всё содержание файла: «функция завершается» доказано у 181
 * функции библиотеки, «функция считает то, что обещает» не было доказано ни у
 * одной.
 *
 * ── Что здесь проверяется ───────────────────────────────────────────────────
 *
 *   1. НАПИСАНО. Каждое утверждение библиотеки: доказано ядром (а не посчитано
 *      сеткой), названо правило, и утверждение ПРАВДА на враждебной выборке —
 *      не на примерах автора, которые ядро и так видело.
 *   2. ИЗЪЯТИЕ. Снимите строку — утверждения не станет вовсе.
 *   3. ЛОЖЬ. Испорченное на один знак утверждение ядро доказанным НЕ объявляет,
 *      ведомость говорит «НАРУШЕНО» с именем примера, а прогон отказывает кодом
 *      `FLANG_PROPERTY`. Здесь же измерена ГРАНИЦА МОЛЧАНИЯ: диагностики ядро не
 *      даёт — постусловие без теоремы, которое не свелось, не ошибка, — и это
 *      проверяется отбором по префиксу `FLANG_PROOF`, а не пересказом.
 *   4. ЗАКАЗ. Утверждения о библиотеке, которые ПРАВДА и которых ядро сегодня НЕ
 *      берёт, — с причиной у каждого, с дословным отказом ядра и с
 *      доказательством правды вычислением. Список исполняемый: научится ядро —
 *      строка покраснеет и потребует себя вычеркнуть.
 *   5. ИНДУКЦИЯ, КОТОРУЮ НЕЧЕМ ЗАКРЫТЬ. Отдельный случай заказа, и самый
 *      дорогой: у «Глубины словаря» из `hashmap.flang` СВОДЯТСЯ ВСЕ ЧЕТЫРЕ
 *      посылки принципа, а доказательства всё равно нет — две базы связывают
 *      имена полей, и закрыть их нечем ни `по примеру`, ни `по предположению`.
 *      Оба отказа сняты прогоном и стоят здесь дословно.
 *
 * Запуск: node --test flang/test/stdlib-claims.test.mjs
 */
