/** Функции библиотеки, о которых сказано хоть что-то, — по именам, без повторов. */
const ФУНКЦИЙ_ОХВАЧЕНО = new Set(ВЫСКАЗАНО.map((з) => з.функция)).size

test("утверждения — о НАСТОЯЩИХ функциях lists.flang: тела совпадают деревом разбора", async () => {
  const свой = await loadProgram(join(корень, УТВЕРЖДЕНИЯ))
  const чужой = await loadProgram(join(корень, БИБЛИОТЕКА))
  for (const запись of ВЫСКАЗАНО) {
    const здесь = свой.functions.find((ф) => ф.name === запись.функция)
    const там = чужой.functions.find((ф) => ф.name === запись.функция)
    assert.ok(здесь !== undefined, `${УТВЕРЖДЕНИЯ}: нет «${запись.функция}»`)
    assert.ok(там !== undefined, `${БИБЛИОТЕКА}: нет «${запись.функция}»`)

    /* Тело — то, о чём утверждение. Сличается деревом разбора, а не текстом:
       `span` у двух файлов разный по определению. */
    assert.ok(
      одинаковы(здесь.body, там.body),
      `тело «${запись.функция}» разошлось с ${БИБЛИОТЕКА} — сказано о похожей функции, а не о той же`,
    )
    assert.ok(одинаковы(здесь.params, там.params), `подпись «${запись.функция}» разошлась с библиотекой`)
  }
})

test("охват lists.flang назван числом: 14 функций из 28 говорят о себе, остальные молчат", async () => {
  /* Число, а не слово «частично». Работа по библиотеке не закончена, и мерить
     её надо тем же способом, каким мерится всё остальное в этом дереве:
     сколько функций модуля сказали о себе хоть что-нибудь. Появится
     утверждение о пятнадцатой — это число обязано вырасти здесь же, а не
     остаться прозой в чьём-то отчёте. */
  const библиотека = await loadProgram(join(корень, БИБЛИОТЕКА))
  assert.equal(библиотека.functions.length, 28, "функций в lists.flang")
  assert.equal(ФУНКЦИЙ_ОХВАЧЕНО, 14, "функций lists.flang, о которых сказано хоть что-то")
})

test("пятнадцать утверждений стоят СЕТКОЙ, а не «доказано» — и слово нельзя поднять молча", async () => {
  /* Главная проверка первой части. Постусловие без теоремы — это утверждение,
     посчитанное на примерах автора, и ведомость обязана называть его сеткой.
     Появись здесь «доказано» — значит кто-то либо написал теорему (тогда её
     надо перенести в проверку ниже и пересчитать свод), либо ослабил
     утверждение до того, что ядро глотает. Обе эти вещи заметны отсюда. */
  const программа = await loadProgram(join(корень, УТВЕРЖДЕНИЯ))
  const внешнее = await externalChecks(программа)
  assert.deepEqual(внешнее.diagnostics, [], JSON.stringify(внешнее.diagnostics))
  const об = obligations(программа, внешнее.results)
  assert.deepEqual(об.diagnostics, [], JSON.stringify(об.diagnostics))

  const постусловия = об.obligations.filter((о) => о.kind === "postcondition")
  assert.equal(постусловия.length, ВЫСКАЗАНО.length, "пятнадцать утверждений, ни одним больше")
  for (const запись of ВЫСКАЗАНО) {
    const цель = постусловия.find((о) => о.name === запись.утверждение)
    assert.ok(цель !== undefined, `нет утверждения «${запись.утверждение}»`)
    assert.equal(цель.of, запись.функция, `утверждение «${запись.утверждение}» приписано не той функции`)
    assert.equal(цель.proof, null, `у «${запись.утверждение}» появилась теорема — свод надо пересчитать`)
    assert.ok(цель.grid > 0, `у «${запись.утверждение}» нет ни одного примера: это уже не сетка, а «объявлено»`)
  }

  const ядро = checkProofs(программа, об.obligations)
  assert.deepEqual(ядро.checked, [], "ядру здесь проверять нечего: теорем нет ни одной")
})

