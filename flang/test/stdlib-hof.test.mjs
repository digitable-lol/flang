/**
 * Стандартная библиотека на функциях-значениях — `flang/stdlib/higher-order.flang`.
 *
 * Тридцать четыре функции, все тотальные, пятьдесят пять примеров. Свёртка,
 * отображение, фильтр, поиск, сортировка и композиция принимают функцию
 * аргументом — то, ради чего пункт 5 плана (`flang/PLAN.md`) ждал пункта 2.
 *
 * ── Файл переехал, и вот почему это стоит записи ───────────────────────────
 *
 * До 7 августа 2026 модуль лежал ЗДЕСЬ, прямо в тесте, и рядом с ним стояла
 * улика: «self/parser.flang не понимает библиотеку». Причина была не в печати —
 * печать во все восемь целей работала с фазы 3 (`flang/cat/HOF.md»), — а во
 * втором контракте: `self/parser.flang` обязан разобрать КАЖДУЮ программу
 * репозитория побайтово так же, как эталон, а формы `функция из числа в число`
 * он не знал. Корпус собирается по маске каталога, поэтому первый же такой
 * файл в `flang/stdlib` ронял пять тестов.
 *
 * Улика покраснела: самоприменение научилось (фаза 5 в `HOF.md`, фаза 4 в
 * `POLY.md`) — разбор новых форм в `self/parser.flang`, вид типа «функция» и
 * вид «параметр» в `self/types.flang`, проход понижения в `self/defunc.flang`.
 * Модуль переехал в `flang/stdlib/higher-order.flang`, а этот файл стал тем,
 * чем должен был быть с самого начала, — обычным тестом библиотеки.
 *
 * ── Что здесь проверяется ──────────────────────────────────────────────────
 *
 *   1. слои: разбор, типы, тотальность каждой функции, все примеры;
 *   2. поведение: общие функции дают ровно то же, что девять
 *      специализированных из `stdlib/lists.flang`;
 *   3. печать: все восемь целей, диспетчер в напечатанном, сборка C под
 *      `-Werror -pedantic`, сверка с интерпретатором на сетке входов;
 *   4. названное в `HOF.md` расхождение на чужом теге — дословно.
 *
 * Выигрыш по ПОВЕДЕНИЮ измерен тестом «свёртки с функцией повторяют
 * специализированные функции lists.flang»: раньше отдельная функция писалась
 * под каждый ПРЕДИКАТ и каждое СРАВНЕНИЕ, теперь они передаются.
 *
 * Выигрыш по ТИПАМ взят 8 августа 2026 — фазой 2 в `POLY.md`. До неё здесь
 * стояли «Отобразить» и «Отобразить строки», «Отфильтровать» и «Отфильтровать
 * строки» — четыре функции с попарно одинаковыми телами, — и объяснение, почему
 * свести их нельзя: объявление с параметром `ф: функция из «А» в «Б»` проходило
 * разбор и типы, а ПРИМЕРЫ падали, потому что значение примера сверялось с
 * объявленным типом без подстановки. Теперь подстановка выводится из самих
 * значений примера, функций две, и сетка ниже гоняет ОДНО тело на двух
 * подстановках — на числах и на строках.
 *
 * Запуск: node --test flang/test/stdlib-hof.test.mjs
 */
