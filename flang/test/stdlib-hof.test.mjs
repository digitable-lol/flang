/* ═════════ 2. ради чего это написано: дублирование схлопывается ═══════════ */

/**
 * Специализированные функции `flang/stdlib/lists.flang` против той же работы
 * через переданную функцию.
 *
 * Это и есть измерение выигрыша: слева — функция, написанная руками под ОДИН
 * предикат или ОДНО сравнение, справа — общая с подставленным тегом.
 * Совпадение на сетке доказывает, что специализированные версии не несут
 * ничего сверх подстановки, то есть являются чистым дублированием.
 */
const СПИСКИ = parse(readFileSync(join(корень, "flang/stdlib/lists.flang"), "utf8"), "lists.flang")

const СЕТКА_СПИСКОВ = [[], [0], [1, 2, 3], [3, 1, 2], [5, 5, 4, 9, 1], [-4, 0, 7], [2, 2, 2], [1, -1, 2, -2]]

test("свёртки с функцией повторяют специализированные функции lists.flang", () => {
  let сверено = 0
  const сверить = (что, слева, справа) => {
    assert.deepEqual(
      слева,
      справа,
      `${что}: специализированная дала ${JSON.stringify(слева)}, общая — ${JSON.stringify(справа)}`,
    )
    сверено += 1
  }
  for (const элементы of СЕТКА_СПИСКОВ) {
    сверить("Сумма", evaluate(СПИСКИ, "Сумма", { элементы }), evaluate(программа, "Сумма", { элементы }))
    сверить("Произведение", evaluate(СПИСКИ, "Произведение", { элементы }), evaluate(программа, "Произведение", { элементы }))
    сверить("Минимум", evaluate(СПИСКИ, "Минимум", { элементы }), evaluate(программа, "Минимум", { элементы }))
    сверить("Максимум", evaluate(СПИСКИ, "Максимум", { элементы }), evaluate(программа, "Максимум", { элементы }))
    сверить(
      "Сортировать",
      evaluate(СПИСКИ, "Сортировать", { элементы }),
      evaluate(программа, "Сортировать", { убывание: false, элементы }),
    )
    /* «Все не меньше» и «Любой не меньше» — те самые две, у которых в
       lists.flang стоит объяснение «передать предикат некому». Порог сюда
       передаётся не тегом, а выбором предиката: захвата полей у тега пока нет
       (фаза 4 в HOF.md), поэтому сверяется порог 1 — он же «положительное». */
    сверить(
      "Все не меньше 1 ≡ Все «Положительное»",
      evaluate(СПИСКИ, "Все не меньше", { элементы, порог: 1 }),
      evaluate(программа, "Все", { условие: variant("Положительное", {}), элементы }),
    )
    сверить(
      "Любой не меньше 1 ≡ Любой «Положительное»",
      evaluate(СПИСКИ, "Любой не меньше", { элементы, порог: 1 }),
      evaluate(программа, "Любой", { условие: variant("Положительное", {}), элементы }),
    )
    сверить(
      "Сжать суммами ≡ Сжать функцией «Сложить»",
      evaluate(СПИСКИ, "Сжать суммами", { первые: элементы, вторые: [10, 20, 30] }),
      evaluate(программа, "Сжать", { ф: variant("Сложить", {}), первые: элементы, вторые: [10, 20, 30] }),
    )
  }
  assert.ok(сверено >= 60, `сетка слишком редкая: ${сверено}`)
  console.log(`дублирование: ${сверено} сверок специализированной функции с общей`)
})

