/* Имя экспорта — тот же `camel`, каким его считает бэкенд JS. */
const экспорт = (имя) => {
  const ident = camel(имя)
  return /^[A-Za-z_$]/u.test(ident) ? ident : `_${ident}`
}

/**
 * Значение интерпретатора в представлении напечатанного модуля.
 *
 * У модуля свой класс варианта, и `instanceof` чужой объект не признаёт — это
 * устройство бэкенда JS, а не следствие высшего порядка. Для тега это значит
 * ровно то, что обещала дефункционализация: тег строится ЭКСПОРТОМ
 * КОНСТРУКТОРА ВАРИАНТА, как любой другой вариант.
 */
function перенести(модуль) {
  const обход = (значение) => {
    if (Array.isArray(значение)) return значение.map(обход)
    if (значение !== null && typeof значение === "object") {
      if (вариантПохож(значение)) {
        const конструктор = модуль[pascal(значение.variant)]
        assert.equal(typeof конструктор, "function", `модуль не экспортирует конструктор «${значение.variant}»`)
        const поля = {}
        for (const [к, з] of Object.entries(значение.fields)) поля[к] = обход(з)
        return конструктор(поля)
      }
      const запись = {}
      for (const [к, з] of Object.entries(значение)) запись[к] = обход(з)
      return запись
    }
    return значение
  }
  return обход
}

test("напечатанная библиотека в JavaScript считает то же, что интерпретатор", async () => {
  const { файлы } = напечатать(emitJs)
  const путь = join(рабочий, `js-${счётчик}.mjs`)
  writeFileSync(путь, файлы[0].content, "utf8")
  const модуль = await import(pathToFileURL(путь).href)
  const перенос = перенести(модуль)

  СЕТКА.forEach(([имя, аргументы], и) => {
    const функция = модуль[экспорт(имя)]
    assert.equal(typeof функция, "function", `модуль не экспортирует «${имя}»`)
    const напечатанное = исход(() => функция(...аргументы.map(перенос)))
    assert.ok(
      тотЖеИсход(ЭТАЛОН_БИБЛИОТЕКИ[и], напечатанное),
      `JS: «${имя}» на входе ${JSON.stringify(аргументы.map(закодировать))}: ` +
        `интерпретатор дал ${описать(ЭТАЛОН_БИБЛИОТЕКИ[и])}, напечатанное дало ${описать(напечатанное)}`,
    )
  })
  console.log(`JavaScript: сверено ${СЕТКА.length} точек`)
})

test("чужой тег отвергают обе стороны — разными словами, и это записано", async () => {
  /*
   * Расхождение названо в `flang/cat/HOF.md`; здесь оно предъявляется на
   * библиотеке. «Утроить» — обычная тотальная функция `число → число`, то есть
   * тег «Утроить» законен по типам всюду, где ждут `функция из числа в число`.
   * Но НИ ОДНО место модуля эту функцию значением не берёт, значит случая у
   * диспетчера нет, и подать такой тег можно только снаружи.
   *
   * Отказывают обе стороны — разными словами, потому что «возбудить ошибку вот
   * с этим кодом и текстом» в языке невыразимо. В сетку это не поставлено
   * нарочно: расхождение должно быть пришпилено одним тестом, а не размазано
   * по ста восьмидесяти точкам.
   */
  const чужой = тег("Утроить")
  const наш = исход(() => evaluate(программа, "Отобразить", [чужой, [1, 2]]))
  assert.equal(наш.ok, false)
  assert.equal(наш.code, "FLANG_APPLY")
  assert.match(наш.message, /ни одно место программы не берёт эту функцию значением/u)

  /* В JS «построить чужой нечем» выполняется буквально: конструктора нет. */
  const { файлы } = напечатать(emitJs)
  const путь = join(рабочий, `js-чужой-${счётчик}.mjs`)
  writeFileSync(путь, файлы[0].content, "utf8")
  const модуль = await import(pathToFileURL(путь).href)
  assert.equal(модуль[pascal("Утроить")], undefined)
  const напечатанное = исход(() => модуль[экспорт("Отобразить")]({ variant: "Утроить", fields: {} }, [1, 2]))
  assert.equal(напечатанное.ok, false, "напечатанное обязано отвергнуть чужой тег")
  assert.notEqual(напечатанное.code, наш.code, "расхождение перестало быть расхождением — поправьте HOF.md")
})

