/** Все `.flang` каталога, вместе с подкаталогами. */
function файлыFlang(каталог) {
  const найдено = []
  for (const запись of readdirSync(каталог, { withFileTypes: true })) {
    const путь = join(каталог, запись.name)
    if (запись.isDirectory()) найдено.push(...файлыFlang(путь))
    else if (запись.name.endsWith(".flang")) найдено.push(путь)
  }
  return найдено
}

test("ни один .flang репозитория функций-значений не использует — правило соблюдено", () => {
  /* Та же проверка с другой стороны: в корпусе не должно быть ни одной
     программы, которую проход переписывает. Стоит здесь, а не в
     `hof-emit.test.mjs`, потому что нарушить правило проще всего именно тем,
     что делает этот файл, — новым модулем библиотеки. */
  let проверено = 0
  for (const путь of файлыFlang(join(корень, "flang"))) {
    let ast
    try {
      ast = parse(readFileSync(путь, "utf8"), путь)
    } catch {
      continue
    }
    assert.equal(defunctionalize(ast), ast, `${путь}: функции-значения в корпусе — неподвижная точка упадёт`)
    проверено += 1
  }
  assert.ok(проверено >= 50, `корпус подозрительно мал: ${проверено}`)
})
