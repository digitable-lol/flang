function вариантПохож(значение) {
  return (
    typeof значение === "object" &&
    значение !== null &&
    !Array.isArray(значение) &&
    typeof значение.variant === "string" &&
    typeof значение.fields === "object" &&
    значение.fields !== null
  )
}

/* Значения на проводе: числа строкой — JSON не знает ни NaN, ни −0. */
function закодировать(значение) {
  if (значение === null || значение === undefined) return null
  if (typeof значение === "boolean") return значение
  if (typeof значение === "number") return { n: Object.is(значение, -0) ? "-0" : String(значение) }
  if (typeof значение === "string") return { s: значение }
  if (Array.isArray(значение)) return { l: значение.map(закодировать) }
  if (вариантПохож(значение)) {
    return { v: значение.variant, f: Object.entries(значение.fields).map(([к, з]) => [к, закодировать(з)]) }
  }
  return { r: Object.entries(значение).map(([к, з]) => [к, закодировать(з)]) }
}

function раскодировать(узел) {
  if (узел === null) return null
  if (typeof узел === "boolean") return узел
  if (Object.hasOwn(узел, "n")) return Number(узел.n)
  if (Object.hasOwn(узел, "s")) return узел.s
  if (Object.hasOwn(узел, "l")) return узел.l.map(раскодировать)
  if (Object.hasOwn(узел, "r")) {
    const запись = {}
    for (const [к, з] of узел.r) запись[к] = раскодировать(з)
    return запись
  }
  if (Object.hasOwn(узел, "v")) {
    const поля = {}
    for (const [к, з] of узел.f ?? []) поля[к] = раскодировать(з)
    return variant(узел.v, поля)
  }
  throw new Error(`нечего раскодировать: ${JSON.stringify(узел)}`)
}

function тоЖеЗначение(левое, правое) {
  if (typeof левое !== "object" || левое === null || typeof правое !== "object" || правое === null) {
    return Object.is(левое, правое)
  }
  if (Array.isArray(левое) || Array.isArray(правое)) {
    if (!Array.isArray(левое) || !Array.isArray(правое) || левое.length !== правое.length) return false
    return левое.every((эл, и) => тоЖеЗначение(эл, правое[и]))
  }
  if (вариантПохож(левое) || вариантПохож(правое)) {
    if (!вариантПохож(левое) || !вариантПохож(правое)) return false
    return левое.variant === правое.variant && тоЖеЗначение(левое.fields, правое.fields)
  }
  const слева = Object.keys(левое).sort()
  const справа = Object.keys(правое).sort()
  if (слева.length !== справа.length || !слева.every((к, и) => к === справа[и])) return false
  return слева.every((к) => тоЖеЗначение(левое[к], правое[к]))
}

function исход(запуск) {
  try {
    return { ok: true, value: запуск() }
  } catch (беда) {
    return { ok: false, code: errorCode(беда), message: беда instanceof Error ? беда.message : String(беда) }
  }
}

function тотЖеИсход(левое, правое) {
  if (левое.ok !== правое.ok) return false
  if (левое.ok) return тоЖеЗначение(левое.value, правое.value)
  /* Код и текст — часть наблюдаемого поведения: вызывающий отличает нарушение
     свойства от поломки движка именно по ним. */
  return левое.code === правое.code && левое.message === правое.message
}

const описать = (и) => (и.ok ? `значение ${JSON.stringify(и.value) ?? String(и.value)}` : `${и.code}: ${и.message}`)

