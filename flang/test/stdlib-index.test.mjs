/**
 * Указатель библиотеки обязан совпадать с библиотекой.
 *
 * flang/stdlib/README.md печатается из самих модулей (scripts/build-stdlib-index.mjs),
 * и этот тест — вся причина, по которой печать имеет смысл. Написанный руками
 * указатель разошёлся бы с кодом при первой же новой функции, и разошёлся бы
 * молча: текст не исполняется, значит не ломается. За один день в этом
 * репозитории такое случилось шесть раз — с каталогом недостач, с шапками
 * модулей, с комментариями про бэкенды.
 *
 * Здесь молча не выйдет: добавил функцию, не перепечатав указатель — красный
 * тест с точным указанием, какой командой чинить.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { ПУТЬ_УКАЗАТЕЛЯ, собратьУказатель } from "../../scripts/build-stdlib-index.mjs"

test("указатель библиотеки совпадает с модулями", () => {
  assert.equal(
    readFileSync(ПУТЬ_УКАЗАТЕЛЯ, "utf8"),
    собратьУказатель(),
    "flang/stdlib/README.md разошёлся с модулями — перепечатайте: node scripts/build-stdlib-index.mjs",
  )
})

test("в указателе перечислен каждый модуль библиотеки", () => {
  /* Отдельная проверка, потому что предыдущая сравнивает целиком и в случае
     расхождения не скажет, ЧТО именно потерялось. */
  const указатель = readFileSync(ПУТЬ_УКАЗАТЕЛЯ, "utf8")
  for (const модуль of ["dictionary", "higher-order", "lists", "logic", "numbers", "numtree", "optional", "result", "sets", "strings", "tree"]) {
    assert.ok(указатель.includes(`${модуль}.flang`), `в указателе нет ${модуль}.flang`)
  }
})
