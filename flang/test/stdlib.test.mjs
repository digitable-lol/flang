/*
 * Вариант в примере: и на входе, и в ожидании, и ИМЯ варианта сравнивается.
 *
 * Тест закрепляет то, что однажды уже стоило дорого. В stdlib тринадцать
 * функций стояли без примеров, а рядом с каждой — объяснение: конструктор
 * варианта в примере записать нельзя, parseLiteralValue сворачивает его в
 * запись и теряет имя. То же было записано в каталоге недостач языка.
 *
 * Неправдой это оказалось целиком. Когда-то ограничение, видимо, было; его
 * сняли, а объяснение осталось — и шесть модулей жили без проверок по причине,
 * которой нет. Заметить такое нечем: отсутствие примеров ничего не роняет.
 *
 * Отсюда форма теста: он проверяет не «пример проходит» (это доказывало бы
 * слишком мало — совпасть могло бы и на потерянном имени), а что пример с
 * ЧУЖИМ именем варианта при тех же полях ПАДАЕТ. Только это и отличает
 * сравнение варианта от сравнения записи.
 */
test("вариант в примере: имя варианта участвует в сравнении", () => {
  const исходник = `модуль «Имя варианта»

тип «Итог»
  вариант «Успех» с «код»: число
  вариант «Отказ» с «код»: число

тотальная функция «Как есть»
  принимает итог: «Итог»
  возвращает «Итог»
  итог
`
  const программа = parse(исходник, "проба.flang")
  const успех = { variant: "Успех", fields: { код: 1 } }
  const отказ = { variant: "Отказ", fields: { код: 1 } }

  /* Вариант доезжает на вход и обратно, не теряя имени. */
  assert.ok(valuesEqual(evaluate(программа, "Как есть", { итог: успех }), reifyValue(успех)))
  /* Поля одинаковы, имена разные — значения обязаны различаться. Это и есть
     то единственное, что отличает сравнение варианта от сравнения записи. */
  assert.ok(!valuesEqual(evaluate(программа, "Как есть", { итог: успех }), reifyValue(отказ)))
})

test("stdlib: у функций с вариантами есть примеры, и они сходятся", () => {
  /* Пока объяснение «вариант в примере не записать» стояло в исходниках, эти
     модули проверялись только «скалярными парами» — то есть косвенно. Число
     примеров ниже — не украшение, а граница: упадёт, если кто-то снова решит,
     что вариант в примере невозможен, и удалит их. */
  for (const [файл, ожидается] of [["optional.flang", 21], ["result.flang", 25]]) {
    const исходник = readFileSync(new URL(`../stdlib/${файл}`, import.meta.url), "utf8")
    const программа = parse(исходник, файл)
    let сошлось = 0
    for (const функция of программа.functions) {
      for (const пример of функция.examples ?? []) {
        assert.ok(
          valuesEqual(evaluate(программа, функция.name, пример.args), reifyValue(пример.expected)),
          `${файл}: «${функция.name}» / «${пример.name}»`,
        )
        сошлось += 1
      }
    }
    assert.equal(сошлось, ожидается, `${файл}: примеров ${сошлось}, а было ${ожидается}`)
  }
})

/*
 * Законы логики — перебором, и перебор здесь ИСЧЕРПЫВАЮЩИЙ.
 *
 * Обычно проверка закона на наборе значений — только проверка: сетка конечна, а
 * тип бесконечен, и молчание сетки ничего не доказывает (так устроена проверка
 * моноидов в src/monoid.mjs, и там это сказано прямо). У признака значений
 * ровно два. Значит перебор всех троек — это все 8 троек, какие бывают, и
 * утверждение «операция ассоциативна» после него не «не нашли контрпримера», а
 * доказано разбором случаев.
 *
 * Отсюда и выбор законов: взяты те, на которые опираются, когда переписывают
 * условие, — де Морган и дистрибутивность. Ошибка в них не роняет программу, а
 * тихо меняет смысл проверки, и заметить это без перебора нечем.
 */
const ЛОГИКА = () => modules.get("logic.flang").program

const И = (a, b) => evaluate(ЛОГИКА(), "Оба верны", { первый: a, второй: b })
const ИЛИ = (a, b) => evaluate(ЛОГИКА(), "Хотя бы одно", { первый: a, второй: b })
const НЕ = (a) => evaluate(ЛОГИКА(), "Не так", { значение: a })

const ОБА_ЗНАЧЕНИЯ = [false, true]

test("logic.flang: конъюнкция и дизъюнкция ассоциативны — все 8 троек", () => {
  for (const a of ОБА_ЗНАЧЕНИЯ) {
    for (const b of ОБА_ЗНАЧЕНИЯ) {
      for (const c of ОБА_ЗНАЧЕНИЯ) {
        assert.equal(И(И(a, b), c), И(a, И(b, c)), `«Оба верны» на ${a}, ${b}, ${c}`)
        assert.equal(ИЛИ(ИЛИ(a, b), c), ИЛИ(a, ИЛИ(b, c)), `«Хотя бы одно» на ${a}, ${b}, ${c}`)
      }
    }
  }
})

test("logic.flang: единица у конъюнкции «да», у дизъюнкции «нет»", () => {
  /* Это те самые единицы, которыми свёртки в «Все верны» и «Есть верное»
     начинают счёт, — отсюда и поведение на пустом списке. */
  for (const a of ОБА_ЗНАЧЕНИЯ) {
    assert.equal(И(a, true), a)
    assert.equal(И(true, a), a)
    assert.equal(ИЛИ(a, false), a)
    assert.equal(ИЛИ(false, a), a)
  }
})

test("logic.flang: законы де Моргана держатся на всех четырёх парах", () => {
  for (const a of ОБА_ЗНАЧЕНИЯ) {
    for (const b of ОБА_ЗНАЧЕНИЯ) {
      assert.equal(НЕ(И(a, b)), ИЛИ(НЕ(a), НЕ(b)), `не(${a} и ${b})`)
      assert.equal(НЕ(ИЛИ(a, b)), И(НЕ(a), НЕ(b)), `не(${a} или ${b})`)
    }
  }
})

test("logic.flang: дистрибутивность в обе стороны — все 8 троек", () => {
  for (const a of ОБА_ЗНАЧЕНИЯ) {
    for (const b of ОБА_ЗНАЧЕНИЯ) {
      for (const c of ОБА_ЗНАЧЕНИЯ) {
        assert.equal(И(a, ИЛИ(b, c)), ИЛИ(И(a, b), И(a, c)), `и/или на ${a}, ${b}, ${c}`)
        assert.equal(ИЛИ(a, И(b, c)), И(ИЛИ(a, b), ИЛИ(a, c)), `или/и на ${a}, ${b}, ${c}`)
      }
    }
  }
})

test("logic.flang: «Следует» и «Ровно одно» совпадают со своими определениями", () => {
  /* Импликация ложна ровно в одном случае из четырёх, исключающее «или» — в
     двух. Проверяется не «похоже на правду», а полная таблица. */
  for (const a of ОБА_ЗНАЧЕНИЯ) {
    for (const b of ОБА_ЗНАЧЕНИЯ) {
      const следует = evaluate(ЛОГИКА(), "Следует", { посылка: a, следствие: b })
      assert.equal(следует, ИЛИ(НЕ(a), b), `«Следует» на ${a}, ${b}`)
      const ровно = evaluate(ЛОГИКА(), "Ровно одно", { первый: a, второй: b })
      assert.equal(ровно, И(ИЛИ(a, b), НЕ(И(a, b))), `«Ровно одно» на ${a}, ${b}`)
    }
  }
})

/*
 * Словарь из нескольких связей — здесь, а не примером в модуле.
 *
 * Причина не стилистическая: список из двух и более значений-вариантов в
 * литерале языка не записывается (недостача «список значений-вариантов длиннее
 * одного», улика в missing.test.mjs). Значит `дано словарь равно [связь, связь]`
 * написать нечем, и всё, что про словарь длиннее одной связи, проверяется
 * отсюда — построением через сами функции модуля.
 *
 * Так даже честнее: проверяется не литерал, а то, что словарь, СОБРАННЫЙ
 * языком, ведёт себя как словарь.
 */
const СЛОВАРЬ = () => modules.get("dictionary.flang").program

const положить = (словарь, ключ, значение) =>
  evaluate(СЛОВАРЬ(), "Положить", { словарь, ключ, значение })
const взять = (словарь, искомый, запасное = "нет такого") =>
  evaluate(СЛОВАРЬ(), "Взять или запасное", { словарь, искомый, запасное })
const размер = (словарь) => evaluate(СЛОВАРЬ(), "Размер", { словарь })

test("dictionary.flang: две связи кладутся и достаются по ключу", () => {
  const д = положить(положить([], "имя", "Марат"), "город", "Казань")
  assert.equal(размер(д), 2)
  assert.equal(взять(д, "имя"), "Марат")
  assert.equal(взять(д, "город"), "Казань")
  assert.equal(взять(д, "страна"), "нет такого")
})

test("dictionary.flang: повторный ключ вытесняет прежнее значение, а не дублируется", () => {
  /* Главное решение модуля: словарь не превращается в список пар с повторами.
     Если это сломается, «Взять» начнёт отдавать то первое, то последнее
     значение в зависимости от направления свёртки — ошибка, которую в рабочей
     программе ищут долго. */
  const д = положить(положить(положить([], "имя", "Марат"), "город", "Казань"), "имя", "Пётр")
  assert.equal(размер(д), 2, "связей стало больше — прежняя не вытеснилась")
  assert.equal(взять(д, "имя"), "Пётр")
  assert.equal(взять(д, "город"), "Казань")
})

test("dictionary.flang: убранного ключа больше нет, остальные целы", () => {
  const д = положить(положить([], "имя", "Марат"), "город", "Казань")
  const без = evaluate(СЛОВАРЬ(), "Убрать", { словарь: д, искомый: "имя" })
  assert.equal(размер(без), 1)
  assert.equal(evaluate(СЛОВАРЬ(), "Есть ключ", { словарь: без, искомый: "имя" }), false)
  assert.equal(взять(без, "город"), "Казань")
})

test("dictionary.flang: ключи и значения идут в одном порядке", () => {
  /* Порядок связей в словаре не обещан, но соответствие ключа значению —
     обещано. Проверяется именно оно: i-й ключ отвечает i-му значению. */
  const д = положить(положить(положить([], "а", "1"), "б", "2"), "в", "3")
  const ключи = evaluate(СЛОВАРЬ(), "Ключи", { словарь: д })
  const значения = evaluate(СЛОВАРЬ(), "Значения", { словарь: д })
  assert.equal(ключи.length, 3)
  assert.equal(значения.length, 3)
  for (let i = 0; i < ключи.length; i += 1) {
    assert.equal(взять(д, ключи[i]), значения[i], `ключ «${ключи[i]}» отвечает не своему значению`)
  }
})

/*
 * Множество обязано оставаться множеством.
 *
 * Модуль sets.flang обещает инвариант — повторов не бывает — и это обещание
 * стоит проверить отдельно от примеров. Пример показывает один случай и служит
 * документацией; инвариант же обязан держаться после ЛЮБОЙ операции, в том
 * числе после объединения множеств с общими элементами и после «Из списка» на
 * входе, где повторов больше, чем различных значений.
 *
 * Проверяется именно то, что легко потерять: достаточно один раз написать
 * «добавить» вместо «добавить, если ещё нет», и множество тихо станет списком.
 */
const МНОЖЕСТВА = () => modules.get("sets.flang").program

const безПовторов = (значения, где) => {
  assert.deepEqual(
    значения,
    [...new Set(значения)],
    `${где}: в множестве появились повторы — ${JSON.stringify(значения)}`,
  )
}

test("sets.flang: инвариант держится после каждой операции", () => {
  const из = (элементы) => evaluate(МНОЖЕСТВА(), "Из списка", { элементы })
  const первое = из(["а", "б", "а", "в", "б", "а"])
  безПовторов(первое, "«Из списка» на входе с повторами")
  assert.deepEqual(первое, ["а", "б", "в"], "порядок обязан совпадать с первыми вхождениями")

  const второе = из(["б", "в", "г", "г"])
  for (const [имя, аргументы] of [
    ["Объединение", { первое, второе }],
    ["Пересечение", { первое, второе }],
    ["Разность", { первое, второе }],
    ["Добавить в множество", { множество: первое, новое: "а" }],
    ["Убрать из множества", { множество: первое, лишнее: "б" }],
  ]) {
    безПовторов(evaluate(МНОЖЕСТВА(), имя, аргументы), `«${имя}»`)
  }
})

test("sets.flang: объединение и пересечение согласованы с принадлежностью", () => {
  /* Закон, а не случай: элемент лежит в объединении тогда и только тогда,
     когда он лежит хотя бы в одном из множеств, и в пересечении — когда в
     обоих. Проверяется на всех значениях, встречающихся хоть где-то. */
  const первое = ["а", "б", "в"]
  const второе = ["б", "в", "г"]
  const есть = (множество, искомое) => evaluate(МНОЖЕСТВА(), "Есть в множестве", { множество, искомое })
  const объединение = evaluate(МНОЖЕСТВА(), "Объединение", { первое, второе })
  const пересечение = evaluate(МНОЖЕСТВА(), "Пересечение", { первое, второе })
  const разность = evaluate(МНОЖЕСТВА(), "Разность", { первое, второе })

  for (const значение of ["а", "б", "в", "г", "я"]) {
    const вПервом = есть(первое, значение)
    const воВтором = есть(второе, значение)
    assert.equal(есть(объединение, значение), вПервом || воВтором, `объединение и «${значение}»`)
    assert.equal(есть(пересечение, значение), вПервом && воВтором, `пересечение и «${значение}»`)
    assert.equal(есть(разность, значение), вПервом && !воВтором, `разность и «${значение}»`)
  }
})

test("sets.flang: «Подмножество» согласовано с разностью", () => {
  /* Одно множество входит в другое ровно тогда, когда их разность пуста.
     Две функции, посчитанные разными путями, обязаны говорить одно и то же —
     иначе одна из них врёт. */
  const пары = [
    [["а", "б"], ["а", "б", "в"]],
    [["а", "я"], ["а", "б"]],
    [[], ["а"]],
    [["а"], []],
    [[], []],
  ]
  for (const [меньшее, большее] of пары) {
    const входит = evaluate(МНОЖЕСТВА(), "Подмножество", { меньшее, большее })
    const разность = evaluate(МНОЖЕСТВА(), "Разность", { первое: меньшее, второе: большее })
    assert.equal(входит, разность.length === 0, `${JSON.stringify(меньшее)} ⊆ ${JSON.stringify(большее)}`)
  }
})
