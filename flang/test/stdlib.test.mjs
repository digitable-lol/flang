test("tree.flang: «Строка раньше» — строгий линейный порядок, а не «почти»", () => {
  /*
   * Дерево поиска стоит на трёх свойствах порядка сразу, и сломайся любое —
   * оно молча начнёт терять ключи. Проверяются все три перебором по сетке, а
   * заодно четвёртое: порядок обязан совпадать с порядком кодовых точек, то
   * есть с тем, как строки сравнивает сам JavaScript по code points.
   */
  const сетка = ["", "а", "б", "аб", "аа", "абв", "Я", "я", "😀", "😀а", "é", "z", "zz"]
  const раньше = (первая, вторая) => evaluate(ДЕРЕВО(), "Строка раньше", { первая, вторая }, БОЛЬШОЕ)
  const поТочкам = (первая, вторая) => {
    const л = [...первая].map((з) => з.codePointAt(0))
    const п = [...вторая].map((з) => з.codePointAt(0))
    for (let к = 0; к < Math.min(л.length, п.length); к += 1) {
      if (л[к] !== п[к]) return л[к] < п[к]
    }
    return л.length < п.length
  }
  for (const первая of сетка) {
    assert.equal(раньше(первая, первая), false, `«${первая}» не может быть раньше самой себя`)
    for (const вторая of сетка) {
      assert.equal(раньше(первая, вторая), поТочкам(первая, вторая), `«${первая}» против «${вторая}»`)
      if (первая !== вторая) {
        assert.equal(
          раньше(первая, вторая) !== раньше(вторая, первая),
          true,
          `«${первая}» и «${вторая}»: порядок обязан быть строгим в обе стороны`,
        )
      }
      for (const третья of сетка) {
        if (раньше(первая, вторая) && раньше(вторая, третья)) {
          assert.ok(раньше(первая, третья), `нарушена транзитивность: ${первая} < ${вторая} < ${третья}`)
        }
      }
    }
  }
})

