/* ══════════ взятие по номеру: класс сложности, а не секунды ══════════ */

/*
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ТАК.
 *
 * Язык даёт встроенную форму `элемент N в СПИСОК`, и `flang/SPEC.md` обещает
 * за неё «обращение к массиву» у семи целей из восьми. Обещание про СТОИМОСТЬ
 * ничем не проверялось на стороне вычислителя, а библиотека формы не звала
 * вовсе: на 4301 строку `flang/stdlib` — ноль вызовов, и «Двоичный поиск»
 * брал середину обходом.
 *
 * Меряется КЛАСС, а не время. Цена — витки интерпретатора (наименьший бюджет
 * шагов, при котором вычисление доходит, — `шаговНа` выше): число целое, от
 * загрузки машины не зависит и от неё не шумит. Класс читается по двум точкам
 * показателем k = log(цена₂/цена₁) / log(n₂/n₁): у константы он 0, у линии 1.
 * Одна точка не измеряет ничего — по ней класс неотличим от константы.
 */
const рядЧисел = (n) => Array.from({ length: n }, (_, к) => к + 1)
const показательРоста = (мало, много, кратность) => Math.log(много / мало) / Math.log(кратность)

test("lists.flang: форма берёт по номеру за постоянное время, а обход — за линейное", (t) => {
  /*
   * Обе половины — одним прибором и на одних входах, берётся ПОСЛЕДНИЙ элемент:
   * для обхода это худший случай, для формы — такой же, как любой другой.
   *
   * Числа на 14 августа 2026 при n от 1000 до 16 000 (кратность 16):
   *   формой        6 →       6 витков, показатель 0,000
   *   обходом  18 993 → 303 993 витков, показатель 1,000
   *
   * Пороги 0,3 и 0,8 стоят по обе стороны от единственной границы, которая тут
   * есть, и измеренные значения отстоят от них дальше любого мыслимого шума
   * целого счётчика.
   */
  const проба = parse(
    "модуль «Проба»\n\nтотальная функция «Формой»\n" +
      "  принимает элементы: список числа, номер: число\n  возвращает число\n" +
      "  элемент номер в элементы\n",
    "проба.flang",
  )
  const списки = modules.get("lists.flang").program
  const формой = [1000, 16000].map((n) => шаговНа(проба, "Формой", { элементы: рядЧисел(n), номер: n }))
  const обходом = [1000, 16000].map((n) => шаговНа(списки, "Элемент", { элементы: рядЧисел(n), индекс: n }))
  t.diagnostic(`формой ${формой[0]} → ${формой[1]}, обходом ${обходом[0]} → ${обходом[1]} при росте n в 16 раз`)

  const kФормой = показательРоста(формой[0], формой[1], 16)
  const kОбходом = показательРоста(обходом[0], обходом[1], 16)
  assert.ok(kФормой < 0.3, `форма обязана быть постоянной, а её показатель ${kФормой.toFixed(3)} (${формой[0]} → ${формой[1]})`)
  assert.ok(kОбходом > 0.8, `обход обязан быть линейным, а его показатель ${kОбходом.toFixed(3)} (${обходом[0]} → ${обходом[1]})`)
})

test("lists.flang: двоичный поиск стоит логарифм, а не линию", (t) => {
  /*
   * УЛИКА, РАДИ КОТОРОЙ ТЕСТ НАПИСАН. «Поиск в диапазоне» брал середину
   * функцией «Элемент», которая обходит список звено за звеном: log₂n взятий
   * по цене n каждое дают линию — то есть двоичный поиск библиотеки стоил
   * ДОРОЖЕ, чем просто пройти список подряд.
   *
   * Витки на 14 августа 2026:
   *      n |       ДО | ПОСЛЕ
   *    500 |   76 726 |   945
   *   1000 |  171 795 |  1051
   *   2000 |  380 864 |  1157
   *   4000 |  836 933 |  1263
   *   8000 | 1 825 002 |  1369
   * Показатель на 500→8000: было 1,143, стало 0,134.
   *
   * Порог 0,5 лежит ровно между ними и не близок ни к одному: спутать логарифм
   * с линией на этом пороге нельзя. Точные числа не закрепляются — они поедут
   * от любой правки вычислителя; закрепляется КЛАСС.
   */
  const списки = modules.get("lists.flang").program
  const цена = (n) => шаговНа(списки, "Двоичный поиск", { элементы: рядЧисел(n), цель: n })
  const малое = цена(500)
  const большое = цена(8000)
  const k = показательРоста(малое, большое, 16)
  t.diagnostic(`двоичный поиск: ${малое} витков на 500, ${большое} на 8000 — показатель ${k.toFixed(3)}`)
  assert.ok(
    k < 0.5,
    `двоичный поиск подорожал с ${малое} до ${большое} при росте списка в 16 раз (показатель ${k.toFixed(3)}): ` +
      "середина снова берётся обходом, и поиск перестал быть двоичным",
  )
})

test("lists.flang: сторож перед формой не потерял ни одного прежнего ответа", () => {
  /*
   * ИЗЪЯТИЕ СМЫСЛА ПРАВКИ. Быстрый путь — встроенная форма, у которой договор
   * ДРУГОЙ: вне списка и на дробном номере она отказывает, а «Элемент» отдаёт
   * ноль и округляет вверх. Значит правка обязана доказать не только скорость,
   * но и что ответы не поехали ни на одном входе, включая те, ради которых
   * обход и оставлен.
   *
   * Сетка та же, что мерилась до правки: длины 0…33 на все интересные цели, и
   * отдельно — «Поиск в диапазоне» с ручными границами вне списка и с дробными
   * концами, то есть ровно там, где форма отказала бы, а обход не отказывает.
   */
  const списки = modules.get("lists.flang").program
  const поиск = (аргументы) => evaluate(списки, "Двоичный поиск", аргументы, БОЛЬШОЕ)
  for (const n of [0, 1, 2, 3, 7, 16, 33]) {
    const элементы = рядЧисел(n)
    for (const цель of [-1, 0, 1, Math.ceil(n / 2), n, n + 1]) {
      const ждём = цель >= 1 && цель <= n ? цель : 0
      assert.equal(поиск({ элементы, цель }), ждём, `«Двоичный поиск» n=${n}, цель=${цель}`)
    }
  }

  /*
   * Ручные границы. Ответы взяты ЗАМЕРОМ на версии ДО правки, а не выведены из
   * смысла: «Поиск в диапазоне» отдаёт НОМЕР СЕРЕДИНЫ, а не позицию в списке,
   * и при границах вне списка этот номер бывает отрицательным — так было и
   * так осталось. Каждая строка ниже — вход, на котором встроенная форма
   * ОТКАЗАЛА БЫ: номер вне списка либо дробный. Ради них обход и оставлен.
   */
  const вДиапазоне = (аргументы) => evaluate(списки, "Поиск в диапазоне", аргументы, БОЛЬШОЕ)
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 9, низ: 1, верх: 50, витков: 10 }), 0)
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 1, низ: -5, верх: 3, витков: 10 }), -1)
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 3, низ: 0, верх: 3, витков: 10 }), 3)
  /* Дробные концы дают дробную середину — тот самый вход, ради которого обход
     остался: форма на нём отказывает, а функция обязана оставаться тотальной. */
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 2, низ: 1.3, верх: 3.3, витков: 10 }), 2)
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 2, низ: 2.5, верх: 2.5, витков: 10 }), 2)
  /* И обычные границы — чтобы строки выше не оказались единственными. */
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 2, низ: 1, верх: 3, витков: 10 }), 2)
  assert.equal(вДиапазоне({ элементы: [1, 2, 3], цель: 1, низ: 1, верх: 0, витков: 10 }), 0)
  assert.equal(вДиапазоне({ элементы: [], цель: 1, низ: 1, верх: 0, витков: 5 }), 0)
  assert.equal(вДиапазоне({ элементы: [5], цель: 5, низ: 1, верх: 1, витков: 5 }), 1)
})
