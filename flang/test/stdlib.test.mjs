/* ─────────────────────── свойства, а не отдельные входы ─────────────────── */

test("lists.flang: «Обратить» дважды возвращает исходный список", () => {
  const { program } = modules.get("lists.flang")
  for (const входной of [[], [1], [1, 2, 3], [5, 5, 4, 9, 1]]) {
    const однажды = evaluate(program, "Обратить", { элементы: входной })
    const дважды = evaluate(program, "Обратить", { элементы: однажды })
    assert.ok(valuesEqual(дважды, входной), `${JSON.stringify(входной)} → ${JSON.stringify(дважды)}`)
  }
})

test("lists.flang: «Сортировать» сохраняет длину и упорядочивает", () => {
  const { program } = modules.get("lists.flang")
  const входной = [9, 1, 8, 2, 7, 3, 3, 0, -4]
  const отсортированный = evaluate(program, "Сортировать", { элементы: входной })
  assert.equal(отсортированный.length, входной.length)
  assert.deepEqual(отсортированный, [...входной].sort((a, b) => a - b))
})

/*
 * Две сортировки библиотеки обязаны давать один и тот же список.
 *
 * Это не «похоже на правду»: «Сортировать» в lists.flang — вставками, n²,
 * доказана структурой; «Сортировать деревом» в numtree.flang — обходом дерева,
 * n·log n на неупорядоченном входе, доказана тоже структурой. Разные алгоритмы,
 * разные модули, один ответ — иначе одна из них не сортировка. Сетка нарочно
 * включает повторы (дерево кладёт равные вправо; ошибись здесь — и повтор
 * потеряется молча) и уже упорядоченный вход (на нём дерево вырождается).
 */
test("numtree.flang: «Сортировать деревом» совпадает с «Сортировать» из lists.flang", () => {
  const списки = modules.get("lists.flang").program
  const деревья = modules.get("numtree.flang").program
  const сетка = [
    [],
    [1],
    [2, 1],
    [1, 2, 3, 4, 5],
    [5, 4, 3, 2, 1],
    [5, 3, 5, 1, 4, 1],
    [0, -5, 3, -5, 0],
    [9, 1, 8, 2, 7, 3, 3, 0, -4],
  ]
  for (const элементы of сетка) {
    const вставками = evaluate(списки, "Сортировать", { элементы })
    const деревом = evaluate(деревья, "Сортировать деревом", { элементы })
    assert.ok(
      valuesEqual(вставками, деревом),
      `${JSON.stringify(элементы)}: вставками ${JSON.stringify(вставками)}, деревом ${JSON.stringify(деревом)}`,
    )
    assert.deepEqual(деревом, [...элементы].sort((a, b) => a - b))
  }
})

