/**
 * Тот же интерфейс, что «surface-pair.mjs», подкреплённый «surface-pair.flang»
 * (пакет Ч385, задача 9960). Импортируйте этот файл ВМЕСТО «surface-pair.mjs»,
 * не трогая его.
 *
 * РАСХОЖДЕНИЕ ФОРМЫ, НАЗВАННОЕ ЯВНО: оригинальная «сверитьПоверхности»
 * возвращает `словари` — `Map` областей на `{туда, обратно}`, и
 * «связаноИмён» считает по ним сумму. Здесь план считает сумму САМ (внутри
 * flang, где словари живут своим — не JS-Map — представлением) и отдаёт уже
 * готовое число; «сверитьПоверхности» здесь возвращает лёгкую обёртку
 * `{связано}` вместо настоящего `Map`. Для `docs/site/surfaces-run.mjs`
 * (единственный настоящий вызывающий этой пары, не .test.mjs) это без
 * разницы: он передаёт `словари` только в «связаноИмён» и никуда больше
 * (проверено `grep`ом) — но если понадобится сам Map с парами имён, эта
 * обёртка его не даёт, и это стоит знать ДО переключения импорта.
 */
import { прогнатьПлан } from "./flang-bridge.mjs"

/**
 * Сверяет два разобранных дерева. Возвращает `{связано}` — то немногое, что
 * «связаноИмён» ниже умеет прочитать; бросает `Error` с путём до первого
 * расхождения, тем же текстом «путь: причина», что бросал оригинал.
 */
export function сверитьПоверхности(перваяПрограмма, втораяПрограмма) {
  const итог = прогнатьПлан("surface-pair.flang", "Сверить поверхности из файла", {
    лево: перваяПрограмма,
    право: втораяПрограмма,
  })
  if (!итог.ок) {
    throw new Error(`${итог.путь}: ${итог.причина}`)
  }
  return { связано: итог.связано }
}

/** Сколько имён связано всего. */
export function связаноИмён(словари) {
  return словари.связано
}
