/**
 * Сверка двух поверхностей одной программы — деревьями, а не глазами.
 *
 * ЗАЧЕМ. У языка две равноправные поверхности, и на Rosetta Code рядом с
 * русским листингом стоит английский. Читатель видит два текста и верит, что
 * это одна программа. Проверить это чтением нельзя: два файла, набранные
 * разными словами, глазами не сличаются, а правка одного из них не заметна во
 * втором вовсе. Через месяц на вики поедут две разные программы под видом
 * одной, и узнает об этом читатель, а не автор.
 *
 * ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Не «похоже», а: деревья совпадают с точностью до
 * ПЕРЕИМЕНОВАНИЯ, и переименование обязано быть взаимно однозначным. Позиции
 * (`span`) снимаются — они и не могут совпасть, файлы разной длины.
 *
 * ПОЧЕМУ ОБЛАСТИ ИМЁН, А НЕ ОДИН СЛОВАРЬ. Одно и то же слово в разных ролях —
 * это разные имена. В `fizzbuzz.flang` модуль и функция оба зовутся
 * «Физз-базз», а по-английски модуль называется «FizzBuzz in English», а
 * функция «FizzBuzz»; один общий словарь объявил бы это расхождением, хотя
 * расхождения нет. Поэтому словарей несколько: модули, функции, типы, поля,
 * имена примеров — и отдельный словарь локальных имён НА КАЖДУЮ функцию,
 * потому что область видимости у них ровно такая. Это в точности α-эквивалент-
 * ность плюс постоянство имён верхнего уровня.
 *
 * ПОЧЕМУ ПЕРЕИМЕНОВАНИЕ РАЗРЕШЕНО НЕ ВЕЗДЕ. Строки в дереве бывают не только
 * именами: `литерал.value` — это данные задачи («Fizz», "MCMXC"), `builtin.name`
 * — канонический идентификатор встроенной формы, один на обе поверхности,
 * `kind` и `op` — сам разбор. Всё это сверяется побуквенно, и слот, которого
 * нет в таблице ниже, тоже сверяется побуквенно: незнакомое расхождение обязано
 * стать ошибкой, а не молча превратиться в «переименование».
 */

/**
 * Слот дерева → область имён, в которой переименование считается законным.
 * `null` значит «сверять побуквенно».
 *
 * `путь` — дорога от корня с индексами массивов; `узел` — объект, которому
 * принадлежит ключ; `свои` — словарь локальных имён текущей функции.
 */
function областьСлота(путь, ключ, узел, свои) {
  /* Верхний уровень: у объявлений нет `kind`, поэтому их различает путь. */
  if (путь === "" && ключ === "module") return "модули"
  if (/^\.legacy\[\d+\]\.value$/u.test(путь) && ключ === "name") return "модули"
  if (/^\.functions\[\d+\]$/u.test(путь) && ключ === "name") return "функции"
  if (/^\.functions\[\d+\]\.params\[\d+\]$/u.test(путь) && ключ === "name") return свои
  if (/^\.functions\[\d+\]\.examples\[\d+\]$/u.test(путь) && ключ === "name") return "примеры"
  if (/^\.types\[\d+\]$/u.test(путь) && ключ === "name") return "типы"
  if (/^\.types\[\d+\]\.fields\[\d+\]$/u.test(путь) && ключ === "name") return "поля"

  /* Выражения: их различает `kind` — путь у них произвольной глубины. */
  switch (узел.kind) {
    case "builtin":
      return null
    case "call":
      return ключ === "name" ? "функции" : null
    case "named":
      return ключ === "name" ? "типы" : null
    case "record":
      /* Объявление записи несёт `name`, построение — `type`. */
      return ключ === "name" || ключ === "type" ? "типы" : null
    case "field":
      return ключ === "field" ? "поля" : null
    case "var":
    case "let":
      return ключ === "name" ? свои : null
    case "fold":
    case "map":
    case "filter":
      return ключ === "acc" || ключ === "item" ? свои : null
    case "cons":
      return ключ === "head" || ключ === "tail" ? свои : null
    default:
      return null
  }
}

/**
 * Сверяет два разобранных дерева. Возвращает словари связанных имён; бросает
 * `Error` с путём до первого расхождения.
 */
export function сверитьПоверхности(перваяПрограмма, втораяПрограмма) {
  const словари = new Map()
  const словарь = (область) => {
    if (!словари.has(область)) словари.set(область, { туда: new Map(), обратно: new Map() })
    return словари.get(область)
  }

  const связать = (область, слева, справа, путь) => {
    const { туда, обратно } = словарь(область)
    if (туда.has(слева) && туда.get(слева) !== справа) {
      throw new Error(`${путь}: «${слева}» уже отвечало «${туда.get(слева)}», а здесь «${справа}» (${область})`)
    }
    if (обратно.has(справа) && обратно.get(справа) !== слева) {
      throw new Error(`${путь}: «${справа}» уже отвечало «${обратно.get(справа)}», а здесь «${слева}» (${область})`)
    }
    туда.set(слева, справа)
    обратно.set(справа, слева)
  }

  /**
   * Данные примеров (`дано` и `ожидается`) — это значения, а не разбор.
   * Переименовывать в них можно ровно одно: имена полей записи, стоящие
   * ключами объекта. Всё остальное — условие задачи, и оно обязано совпасть
   * буква в букву: «Fizz» по-английски тоже «Fizz».
   */
  const данные = (слева, справа, путь) => {
    if (Array.isArray(слева) || Array.isArray(справа)) {
      if (!Array.isArray(слева) || !Array.isArray(справа)) throw new Error(`${путь}: список против не-списка`)
      if (слева.length !== справа.length) throw new Error(`${путь}: длина ${слева.length} ≠ ${справа.length}`)
      слева.forEach((_, номер) => данные(слева[номер], справа[номер], `${путь}[${номер}]`))
      return
    }
    if (слева && справа && typeof слева === "object" && typeof справа === "object") {
      const ключиСлева = Object.keys(слева)
      const ключиСправа = Object.keys(справа)
      if (ключиСлева.length !== ключиСправа.length) throw new Error(`${путь}: разный набор полей`)
      ключиСлева.forEach((ключ, номер) => {
        связать("поля", ключ, ключиСправа[номер], `${путь}: поле`)
        данные(слева[ключ], справа[ключиСправа[номер]], `${путь}.${ключ}`)
      })
      return
    }
    if (слева !== справа) {
      throw new Error(`${путь}: ${JSON.stringify(слева)} ≠ ${JSON.stringify(справа)} — это данные задачи, они обязаны совпасть`)
    }
  }

  const идти = (слева, справа, путь, свои) => {
    if (слева === null || справа === null || слева === undefined || справа === undefined) {
      if (слева !== справа) throw new Error(`${путь}: ${JSON.stringify(слева)} ≠ ${JSON.stringify(справа)}`)
      return
    }
    if (Array.isArray(слева) || Array.isArray(справа)) {
      if (!Array.isArray(слева) || !Array.isArray(справа)) throw new Error(`${путь}: список против не-списка`)
      if (слева.length !== справа.length) throw new Error(`${путь}: длина ${слева.length} ≠ ${справа.length}`)
      слева.forEach((_, номер) => идти(слева[номер], справа[номер], `${путь}[${номер}]`, свои))
      return
    }
    if (typeof слева === "object" || typeof справа === "object") {
      if (typeof слева !== "object" || typeof справа !== "object") throw new Error(`${путь}: узел против значения`)
      /* Каждая функция открывает свою область локальных имён. */
      const область = /^\.functions\[\d+\]$/u.test(путь) ? `имена ${путь}` : свои
      const ключиСлева = Object.keys(слева).filter((ключ) => ключ !== "span").sort()
      const ключиСправа = Object.keys(справа).filter((ключ) => ключ !== "span").sort()
      if (ключиСлева.join(",") !== ключиСправа.join(",")) {
        throw new Error(`${путь}: ключи [${ключиСлева.join(",")}] ≠ [${ключиСправа.join(",")}]`)
      }
      for (const ключ of ключиСлева) {
        const дальше = `${путь}.${ключ}`
        /* `дано` — объект, чьи КЛЮЧИ суть имена параметров, а значения —
           данные задачи. Порядок ключей есть порядок строк `дано`, и он один
           и тот же в обоих файлах. */
        if (ключ === "args" && /^\.functions\[\d+\]\.examples\[\d+\]$/u.test(путь)) {
          const именаСлева = Object.keys(слева.args)
          const именаСправа = Object.keys(справа.args)
          if (именаСлева.length !== именаСправа.length) throw new Error(`${дальше}: разное число аргументов`)
          именаСлева.forEach((имя, номер) => {
            связать(область, имя, именаСправа[номер], `${дальше}: имя аргумента`)
            данные(слева.args[имя], справа.args[именаСправа[номер]], `${дальше}.${имя}`)
          })
          continue
        }
        if (ключ === "expected" && /^\.functions\[\d+\]\.examples\[\d+\]$/u.test(путь)) {
          данные(слева.expected, справа.expected, дальше)
          continue
        }
        /* Построение записи: ключи — имена полей, значения — выражения. */
        if (ключ === "fields" && слева.kind === "record" && !Array.isArray(слева.fields)) {
          const поляСлева = Object.keys(слева.fields)
          const поляСправа = Object.keys(справа.fields)
          if (поляСлева.length !== поляСправа.length) throw new Error(`${дальше}: разное число полей`)
          поляСлева.forEach((поле, номер) => {
            связать("поля", поле, поляСправа[номер], `${дальше}: поле`)
            идти(слева.fields[поле], справа.fields[поляСправа[номер]], `${дальше}.${поле}`, область)
          })
          continue
        }
        const значениеСлева = слева[ключ]
        const значениеСправа = справа[ключ]
        if (typeof значениеСлева === "string" && typeof значениеСправа === "string") {
          if (значениеСлева === значениеСправа) continue
          const куда = областьСлота(путь, ключ, слева, область)
          if (!куда) {
            throw new Error(`${дальше}: «${значениеСлева}» ≠ «${значениеСправа}» — этот слот не именной`)
          }
          связать(куда, значениеСлева, значениеСправа, дальше)
          continue
        }
        идти(значениеСлева, значениеСправа, дальше, область)
      }
      return
    }
    if (слева !== справа) throw new Error(`${путь}: ${JSON.stringify(слева)} ≠ ${JSON.stringify(справа)}`)
  }

  идти(перваяПрограмма, втораяПрограмма, "", "имена вне функций")
  return словари
}

/** Сколько имён связано всего — числом удобно показывать, что сверка не пустая. */
export function связаноИмён(словари) {
  return [...словари.values()].reduce((всего, { туда }) => всего + туда.size, 0)
}
