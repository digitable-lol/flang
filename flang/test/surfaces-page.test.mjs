/**
 * Числа страницы `docs/surfaces.md` сверяются с прогоном, а не с памятью.
 *
 * Страница о четырёх поверхностях завела на сайт полтора десятка новых чисел:
 * слотов расхождения, связанных имён, понятий на четырёх поверхностях, байт у
 * четырёх файлов. Число, попавшее на сайт без сторожа, протухает — и протухает
 * молча, потому что предложение однажды написанное не исполняется.
 *
 * Здесь проверяется и то, что сторож УМЕЕТ КРАСНЕТЬ: страница портится в
 * памяти и на диске, и сторож обязан назвать беду поимённо.
 */
import assert from "node:assert/strict"
import { readFileSync, writeFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { ожидаемыеФразы, прогон, сверитьСтраницу } from "../../docs/site/surfaces-run.mjs"

const СТРАНИЦА = fileURLToPath(new URL("../../docs/surfaces.md", import.meta.url))

test("числа страницы поверхностей сходятся с прогоном", () => {
  assert.deepEqual(сверитьСтраницу(), [], "числа страницы разошлись с прогоном")
})

test("прогон четырёх записей: деревья совпадают побайтово после канонизации", () => {
  const р = прогон()
  assert.equal(р.совпалиПобайтово, true, "канонизированные деревья четырёх поверхностей разошлись")
  assert.equal(р.файлы.length, 4)
  assert.equal(р.сверки.length, 3, "сверок с образцом обязано быть три")
  // Расхождения сырых деревьев обязаны быть ОДИНАКОВЫ у всех трёх пар: они и
  // есть имена, а имён в программе столько же, сколько их на любой поверхности.
  const всего = new Set(р.сырые.map((с) => с.всего))
  assert.equal(всего.size, 1, `у трёх пар разное число расходящихся слотов: ${[...всего].join(", ")}`)
})

test("покрытие таблицы: части складываются в целое", () => {
  const т = прогон().таблица
  assert.equal(
    т.наЧетырёх + т.наТрёх + т.наДвух + т.наОдной,
    т.понятий,
    "части покрытия не складываются в число понятий таблицы",
  )
  assert.equal(т.дырявые.length, т.наТрёх + т.наДвух + т.наОдной)
})

test("КРАСНЕЕТ: число на странице подменили", () => {
  const было = readFileSync(СТРАНИЦА, "utf8")
  try {
    // Подменяем число понятий на всех четырёх — ровно то, что случится, когда
    // в таблицу добавят слово, а страницу не перепишут.
    //
    // Число берётся СО СТРАНИЦЫ образцом, а не пишется здесь литералом, и это
    // не украшение. Литерал «132» стоял здесь до 20 августа и сломал проверку в
    // тот день, когда двадцать первая встроенная форма подняла число до 133:
    // порча не находила образца, и проверка краснела с «образец для порчи не
    // найден» — то есть переставала проверять сторожа ровно тогда, когда сторож
    // и надо было проверить. Образец же держит и то, и другое: строка обязана
    // быть на месте, а её число может расти.
    const строка = было.match(/\| всех четырёх поверхностях \| \*\*(\d+)\*\* \|/u)
    assert.ok(строка, "строки «на всех четырёх поверхностях» на странице нет вовсе — проверку надо чинить, а не отключать")
    const порченая = было.replace(строка[0], `| всех четырёх поверхностях | **${Number(строка[1]) + 867}** |`)
    assert.notEqual(порченая, было, "образец для порчи не найден — проверку надо чинить, а не отключать")
    writeFileSync(СТРАНИЦА, порченая)
    const беды = сверитьСтраницу()
    assert.ok(беды.length > 0, "сторож НЕ покраснел на подменённом числе")
    assert.ok(
      беды.some((б) => б.includes("на всех четырёх")),
      `отказ обязан назвать беду поимённо, а сказал: ${беды.join(" / ")}`,
    )
  } finally {
    writeFileSync(СТРАНИЦА, было)
  }
  assert.deepEqual(сверитьСтраницу(), [], "после отката сторож обязан снова молчать")
})

test("КРАСНЕЕТ: дырявое понятие со страницы убрали", () => {
  const было = readFileSync(СТРАНИЦА, "utf8")
  try {
    writeFileSync(СТРАНИЦА, было.replaceAll("`ensures`", "`—снято—`"))
    const беды = сверитьСтраницу()
    assert.ok(
      беды.some((б) => б.includes("ensures")),
      `сторож не заметил, что понятие ensures со страницы пропало: ${беды.join(" / ")}`,
    )
  } finally {
    writeFileSync(СТРАНИЦА, было)
  }
  assert.deepEqual(сверитьСтраницу(), [], "после отката сторож обязан снова молчать")
})

test("собранных фраз не меньше, чем чисел на странице — сторож не выродился в одну проверку", () => {
  assert.ok(ожидаемыеФразы().length >= 12, `собранных фраз всего ${ожидаемыеФразы().length} — сторож обмелел`)
})
