/**
 * Поверхностей у языка больше двух — и это сверяется деревьями, а не глазами.
 *
 * ── Зачем отдельный файл ────────────────────────────────────────────────────
 * `flang/test/rosetta.test.mjs` уже сличает русский листинг с английским, но
 * сличает он ПАРУ и только внутри набора Rosetta Code: таблица `ПАРЫ` там
 * устроена как «файл и его -english», а поверхностей теперь четыре. Дописывать
 * третий и четвёртый столбец в чужую таблицу значило бы смешать два разных
 * утверждения: «задача с вики записана дважды» и «поверхность языка работает».
 *
 * Здесь проверяется второе. Одна и та же программа записана на русской,
 * эсперантской и китайской поверхностях, и требование то же, что у пары
 * Rosetta Code: деревья совпадают с точностью до взаимно однозначного
 * переименования (`flang/test/surface-pair.mjs`). Позиции снимаются, данные
 * задачи обязаны совпасть буква в букву — «2432902008176640000» не переводится.
 *
 * ── Почему сверка, а не «оно разбирается» ───────────────────────────────────
 * Разбор доказывает только то, что таблица слов не пуста. Он молчит, когда
 * `отфильтровать` перевели тем же словом, что `отобразить`, когда порядок
 * аргументов уехал, когда `не больше` стало `меньше`. Всё это — ровно те
 * ошибки, какие делает переводчик, а не программист, и ловит их только
 * сравнение деревьев.
 *
 * ── Чего этот файл НЕ утверждает ────────────────────────────────────────────
 * Не утверждает, что поверхность полна: в таблице есть понятия, у которых
 * эсперантского или китайского слова нет вовсе, и `factorial.eo.flang` честно
 * пишет `module` по-английски. Проверяется совпадение программ, а не покрытие
 * словаря; покрытие меряет `flang/test/self-lexer.test.mjs` по таблице.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { evaluate } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

import { связаноИмён, сверитьПоверхности } from "./surface-pair.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const прочесть = (путь) => readFileSync(`${корень}${путь}`, "utf8")

const ОБРАЗЕЦ = "/flang/examples/rosetta/factorial.flang"

/** Поверхность → файл, записанный на ней. Русский листинг — образец сверки. */
const ПОВЕРХНОСТИ = [
  ["эсперанто", "/flang/examples/surfaces/factorial.eo.flang"],
  ["китайская", "/flang/examples/surfaces/factorial.zh.flang"],
]

const русский = parse(прочесть(ОБРАЗЕЦ), ОБРАЗЕЦ)

for (const [поверхность, путь] of ПОВЕРХНОСТИ) {
  const исходник = прочесть(путь)
  const программа = parse(исходник, путь)

  test(`${поверхность} поверхность: разбор без диагностик, типы сходятся`, () => {
    assert.equal(программа.flang, 1)
    assert.deepEqual(checkTypes(программа).diagnostics, [])
    assert.deepEqual(checkTotality(программа).diagnostics, [])
    /* Детерминированность: повторный разбор даёт побайтово тот же AST. */
    assert.equal(JSON.stringify(parse(исходник, путь)), JSON.stringify(программа))
  })

  test(`${поверхность} поверхность: все примеры сходятся`, () => {
    let сошлось = 0
    for (const функция of программа.functions) {
      for (const пример of функция.examples ?? []) {
        assert.deepEqual(
          evaluate(программа, функция.name, пример.args),
          пример.expected,
          `${функция.name} / ${пример.name}`,
        )
        сошлось += 1
      }
    }
    assert.ok(сошлось >= 10, `примеров всего ${сошлось}`)
  })

  test(`${поверхность} поверхность и русская — одна программа, а не два похожих текста`, () => {
    const словари = сверитьПоверхности(русский, программа)
    assert.ok(связаноИмён(словари) > 0, "сверка не связала ни одного имени — она пустая")

    /* Граница тотальности — следствие совпадения деревьев, но ломается пусть
       отдельным сообщением: именно она попадёт в прозу о поверхности. */
    const границаРусского = new Set(checkTotality(русский).total ?? [])
    const границаЭтой = new Set(checkTotality(программа).total ?? [])
    assert.equal(русский.functions.length, программа.functions.length, "разное число функций")
    assert.equal(границаРусского.size, границаЭтой.size, "доказанность разошлась")
  })
}

test("сверка ловит расхождение и на этих поверхностях, а не только совпадение", () => {
  /* Проверка на проверку — тем же приёмом, что в `rosetta.test.mjs`: сверка,
     которая всё принимает, хуже отсутствующей. Правится ровно то, чем
     разъезжаются файлы при доработке одного из них. */
  const путь = "/flang/examples/surfaces/factorial.eo.flang"
  const исходник = прочесть(путь)
  const испорченный = исходник.replace(
    "alie n fojoj («Faktorialo» de (n minus 1))",
    "alie n fojoj («Faktorialo» de (n minus 2))",
  )
  assert.notEqual(испорченный, исходник, "правка не применилась — тест ничего не проверяет")
  assert.throws(() => сверитьПоверхности(русский, parse(испорченный, "порча")), /1 ≠ 2/u)
})

test("одно слово поверхности, переведённое дважды, ловится обратной однозначностью", () => {
  /* Ошибка переводчика, а не программиста: `отфильтровать` и `отобразить`
     назвали одним словом. Дерево при этом остаётся разбираемым, примеры могут
     даже сойтись — а программа уже другая. Ловит это требование ВЗАИМНОЙ
     однозначности словаря, ради которого сверка и написана. */
  const путь = "/flang/examples/surfaces/factorial.zh.flang"
  const исходник = прочесть(путь)
  /* «区间数列» — имя другой функции; после подмены две русские функции
     отвечают одному китайскому имени. */
  const испорченный = исходник.replace(/«乘积»/gu, "«区间数列»")
  assert.notEqual(испорченный, исходник, "правка не применилась — тест ничего не проверяет")
  assert.throws(() => сверитьПоверхности(русский, parse(испорченный, "порча")), /функции/u)
})
