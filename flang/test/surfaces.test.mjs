/**
 * Поверхностей у языка больше двух — и это сверяется деревьями, а не глазами.
 *
 * ── Зачем отдельный файл ────────────────────────────────────────────────────
 * `flang/test/rosetta.test.mjs` уже сличает русский листинг с английским, но
 * сличает он ПАРУ и только внутри набора Rosetta Code: таблица `ПАРЫ` там
 * устроена как «файл и его -english», а поверхностей теперь четыре. Дописывать
 * третий и четвёртый столбец в чужую таблицу значило бы смешать два разных
 * утверждения: «задача с вики записана дважды» и «поверхность языка работает».
 *
 * Здесь проверяется второе. Одна и та же программа записана на русской,
 * эсперантской и китайской поверхностях, и требование то же, что у пары
 * Rosetta Code: деревья совпадают с точностью до взаимно однозначного
 * переименования (`flang/test/surface-pair.mjs`). Позиции снимаются, данные
 * задачи обязаны совпасть буква в букву — «2432902008176640000» не переводится.
 *
 * ── Почему сверка, а не «оно разбирается» ───────────────────────────────────
 * Разбор доказывает только то, что таблица слов не пуста. Он молчит, когда
 * `отфильтровать` перевели тем же словом, что `отобразить`, когда порядок
 * аргументов уехал, когда `не больше` стало `меньше`. Всё это — ровно те
 * ошибки, какие делает переводчик, а не программист, и ловит их только
 * сравнение деревьев.
 *
 * ── Чего этот файл НЕ утверждает ────────────────────────────────────────────
 * Не утверждает, что поверхность полна: в таблице есть понятия, у которых
 * эсперантского или китайского слова нет вовсе, и `factorial.eo.flang` честно
 * пишет `module` по-английски. Проверяется совпадение программ, а не покрытие
 * словаря; покрытие меряет `flang/test/self-lexer.test.mjs` по таблице.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { evaluate } from "../src/interpret.mjs"
import { keywordId, SURFACE_ORDER, surfaceOfPhrase, surfaceOfTokens, tokenize, wordOn } from "../src/lexer.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

import { связаноИмён, сверитьПоверхности } from "./surface-pair.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const прочесть = (путь) => readFileSync(`${корень}${путь}`, "utf8")

const ОБРАЗЕЦ = "/flang/examples/rosetta/factorial.flang"

/** Поверхность → файл, записанный на ней. Русский листинг — образец сверки. */
const ПОВЕРХНОСТИ = [
  ["эсперанто", "/flang/examples/surfaces/factorial.eo.flang"],
  ["китайская", "/flang/examples/surfaces/factorial.zh.flang"],
]

const русский = parse(прочесть(ОБРАЗЕЦ), ОБРАЗЕЦ)

for (const [поверхность, путь] of ПОВЕРХНОСТИ) {
  const исходник = прочесть(путь)
  const программа = parse(исходник, путь)

  test(`${поверхность} поверхность: разбор без диагностик, типы сходятся`, () => {
    assert.equal(программа.flang, 1)
    assert.deepEqual(checkTypes(программа).diagnostics, [])
    assert.deepEqual(checkTotality(программа).diagnostics, [])
    /* Детерминированность: повторный разбор даёт побайтово тот же AST. */
    assert.equal(JSON.stringify(parse(исходник, путь)), JSON.stringify(программа))
  })

  test(`${поверхность} поверхность: все примеры сходятся`, () => {
    let сошлось = 0
    for (const функция of программа.functions) {
      for (const пример of функция.examples ?? []) {
        assert.deepEqual(
          evaluate(программа, функция.name, пример.args),
          пример.expected,
          `${функция.name} / ${пример.name}`,
        )
        сошлось += 1
      }
    }
    assert.ok(сошлось >= 10, `примеров всего ${сошлось}`)
  })

  test(`${поверхность} поверхность и русская — одна программа, а не два похожих текста`, () => {
    const словари = сверитьПоверхности(русский, программа)
    assert.ok(связаноИмён(словари) > 0, "сверка не связала ни одного имени — она пустая")

    /* Граница тотальности — следствие совпадения деревьев, но ломается пусть
       отдельным сообщением: именно она попадёт в прозу о поверхности. */
    const границаРусского = new Set(checkTotality(русский).total ?? [])
    const границаЭтой = new Set(checkTotality(программа).total ?? [])
    assert.equal(русский.functions.length, программа.functions.length, "разное число функций")
    assert.equal(границаРусского.size, границаЭтой.size, "доказанность разошлась")
  })
}

test("сверка ловит расхождение и на этих поверхностях, а не только совпадение", () => {
  /* Проверка на проверку — тем же приёмом, что в `rosetta.test.mjs`: сверка,
     которая всё принимает, хуже отсутствующей. Правится ровно то, чем
     разъезжаются файлы при доработке одного из них. */
  const путь = "/flang/examples/surfaces/factorial.eo.flang"
  const исходник = прочесть(путь)
  const испорченный = исходник.replace(
    "alie n fojoj («Faktorialo» de (n minus 1))",
    "alie n fojoj («Faktorialo» de (n minus 2))",
  )
  assert.notEqual(испорченный, исходник, "правка не применилась — тест ничего не проверяет")
  assert.throws(() => сверитьПоверхности(русский, parse(испорченный, "порча")), /1 ≠ 2/u)
})

/* ──────────────────────── полноширинная пунктуация ───────────────────────── */

/**
 * `：` `，` `（` — не украшение. В китайской раскладке той же клавишей
 * набирается именно полноширинный знак, а в китайском тексте между словами нет
 * пробелов, поэтому знак здесь ещё и единственная естественная граница токена:
 * `元素：列表` обязано разойтись на имя, знак и ключевое слово.
 */
test("полноширинный знак даёт тот же токен, что и узкий", () => {
  const узкие = "{}[]()<>:;,.?=|&+*%!"
  const широкие = [...узкие].map((знак) => String.fromCodePoint(знак.codePointAt(0) + 0xfee0)).join("")
  assert.equal(
    tokenize(`${широкие}\n`).map((т) => т.value).join(""),
    tokenize(`${узкие}\n`).map((т) => т.value).join(""),
    "поток от полноширинных знаков обязан совпасть с потоком от узких",
  )
  /* Значение токена — узкое: парсер сравнивает его с ":", ",", "(", и держать
     в контракте разбора две ширины одного знака значило бы удвоить каждое
     такое сравнение в парсере и во всех восьми целях печати. */
  const токены = tokenize("а：б，（ц）\n")
  assert.deepEqual(
    токены.filter((т) => т.kind === "punct").map((т) => т.value),
    [":", ",", "(", ")"],
  )
  /* И знак делит поток: без этого `а：б` осталось бы одним именем. */
  assert.deepEqual(токены.filter((т) => т.kind === "name").map((т) => т.value), ["а", "б", "ц"])
})

test("полноширинные скобки двигают глубину так же, как узкие", () => {
  /* Внутри скобок отступ не значим. Если бы глубину считали по букве, а не по
     узкому знаку, `（` открывала бы скобку, не закрываемую `）`, и первый же
     перенос строки внутри неё дал бы лишний `newline`. */
  assert.deepEqual(
    tokenize("［\n  1，\n  2\n］\n").map((т) => т.kind),
    tokenize("[\n  1,\n  2\n]\n").map((т) => т.kind),
  )
})

test("своя китайская пунктуация знаком не становится — это решение владельца", () => {
  /* `。` и `、` не двойники ASCII: что они значат в языке — точка доступа к
     полю? разделитель списка? — таблицей соответствий Unicode не решается. */
  for (const знак of ["。", "、"]) {
    assert.throws(() => tokenize(`а ${знак} б\n`), new RegExp(`недопустимый символ '${знак}'`, "u"))
  }
})

/* ─────────────────── диагностика цитирует поверхность файла ──────────────── */

/**
 * Сообщение «у 'если' нет ветки 'то'» верно ровно для того, кто писал `если`.
 * Автору китайского файла оно называет два слова, которых в его файле нет и
 * быть не может. Это не «непереведённая проза» — это указание не туда.
 *
 * Проза здесь остаётся русской нарочно: язык диагностики — решение владельца
 * языка, а не следствие того, что в таблицу дописали столбец. Проверяется
 * ровно то, что было неверно: цитата.
 */
const сломанный = {
  ru: "модуль «М»\n\nфункция «Ф»\n  возвращает число\n  если 1\n",
  en: "module «M»\n\nfunction «F»\n  returns number\n  if 1\n",
  eo: "module «M»\n\nfunkcio «F»\n  redonas nombro\n  se 1\n",
  zh: "模块 «М»\n\n函数 «Ф»\n  返回 数字\n  如果 1\n",
}

const сообщение = (исходник) => {
  try {
    parse(исходник, "проба")
  } catch (ошибка) {
    return ошибка.diagnostics?.[0]?.message ?? String(ошибка.message)
  }
  return null
}

test("поверхность файла определяется по его же словам", () => {
  assert.equal(surfaceOfTokens(tokenize(прочесть(ОБРАЗЕЦ))), "ru")
  assert.equal(surfaceOfTokens(tokenize(прочесть("/flang/examples/rosetta/factorial-english.flang"))), "en")
  assert.equal(surfaceOfTokens(tokenize(прочесть("/flang/examples/surfaces/factorial.eo.flang"))), "eo")
  assert.equal(surfaceOfTokens(tokenize(прочесть("/flang/examples/surfaces/factorial.zh.flang"))), "zh")
  /* Файл на эсперанто начинается с английского `module` — эсперантского слова
     у этого понятия нет. По ПЕРВОМУ слову поверхность определилась бы
     английской, поэтому она считается большинством. */
  assert.equal(surfaceOfPhrase("module"), "en")
})

test("диагностика называет слово той поверхности, на которой написан файл", () => {
  assert.equal(сообщение(сломанный.ru), "у 'если' нет ветки 'то'")
  assert.equal(сообщение(сломанный.en), "у 'if' нет ветки 'then'")
  assert.equal(сообщение(сломанный.eo), "у 'se' нет ветки 'tiam'")
  assert.equal(сообщение(сломанный.zh), "у '如果' нет ветки '那么'")
})

test("на русском файле текст диагностики не изменился ни на байт", () => {
  /* Тексты диагностик — поверхность совместимости: на них смотрят и тесты, и
     редактор. Перевод цитаты обязан быть тождественным там, где поверхность
     русская, иначе это не локализация, а переписывание. */
  const русские = [
    ["модуль «М»\n\nфункция «Ф»\n  возвращает число\n  разбор 1\n    1\n", "не разобрана конструкция: ожидалось 'случай'"],
    ["модуль «М»\n\nфункция «Ф»\n  возвращает число\n  свёртка [1] начиная с 0 х\n", "у 'свёртка' ожидалось 'как накопитель и элемент'"],
    ["модуль «М»\n\nфункция «Ф»\n  возвращает число\n  подстрока \"а\" 1\n", "у 'подстрока' ожидалось 'с'"],
  ]
  for (const [исходник, ждём] of русские) assert.equal(сообщение(исходник), ждём)
})

test("каждое цитируемое парсером понятие имеет слово на всех четырёх поверхностях", () => {
  /* Сторож связи «диагностика ↔ таблица». Понятие, которое парсер цитирует, а
     таблица на какой-то поверхности не называет, молча оставит в сообщении
     русское слово — и автор чужого файла увидит слово, которого не писал.
     Исключение ровно одно и оно названо: у `alias` («это») нет даже
     английского слова, и заводить его на других поверхностях значило бы
     решать за владельца языка. */
  const БЕЗ_ПАРЫ = new Set(["alias"])
  const парсер = readFileSync(`${корень}/flang/src/parser.mjs`, "utf8")
  const понятия = new Set()
  for (const цитата of парсер.matchAll(/'([^'\n]{1,40})'/gu)) {
    const id = keywordId(цитата[1])
    if (id !== null) понятия.add(id)
  }
  assert.ok(понятия.size >= 40, `цитируемых понятий всего ${понятия.size}`)
  for (const id of понятия) {
    if (БЕЗ_ПАРЫ.has(id)) continue
    for (const поверхность of SURFACE_ORDER) {
      assert.ok(
        wordOn(id, поверхность) !== null,
        `парсер цитирует «${id}», а на поверхности ${поверхность} слова у него нет`,
      )
    }
  }
})

test("одно слово поверхности, переведённое дважды, ловится обратной однозначностью", () => {
  /* Ошибка переводчика, а не программиста: `отфильтровать` и `отобразить`
     назвали одним словом. Дерево при этом остаётся разбираемым, примеры могут
     даже сойтись — а программа уже другая. Ловит это требование ВЗАИМНОЙ
     однозначности словаря, ради которого сверка и написана. */
  const путь = "/flang/examples/surfaces/factorial.zh.flang"
  const исходник = прочесть(путь)
  /* «区间数列» — имя другой функции; после подмены две русские функции
     отвечают одному китайскому имени. */
  const испорченный = исходник.replace(/«乘积»/gu, "«区间数列»")
  assert.notEqual(испорченный, исходник, "правка не применилась — тест ничего не проверяет")
  assert.throws(() => сверитьПоверхности(русский, parse(испорченный, "порча")), /функции/u)
})
