/**
 * Сокеты и часы у ВОСЬМИ целей печати — та их часть, которая является решением.
 *
 * ── Что здесь на самом деле проверяется ─────────────────────────────────────
 *
 * Предшественник посчитал сокеты и часы непереносимыми и назвал цену: 459 строк
 * узла на КАЖДУЮ цель, семь раз. Счёт был верный для того, что он считал, —
 * файла. Но в файле мир и решение лежали вперемешку, и мира там 42 строки из
 * 596: `createConnection`, `createServer`, `write`, `destroy`, `on`,
 * `setInterval`, `setTimeout`, `Date.now`. Всё остальное — решения О сокете и
 * О часах.
 *
 * Решение переносимо, и здесь это считается, а не утверждается. Машина
 * состояний связи (`flang/conc/link.flang`) печатается в каждую из восьми
 * целей, собирается настоящим тулчейном, запускается — и обязана на каждое
 * событие ответить тем же новым состоянием связи и тем же списком велений.
 *
 * ── Кто здесь свидетель и почему именно он ──────────────────────────────────
 *
 * Свидетель — `flang/conc/link.js`, напечатанный модуль цели JavaScript. Он
 * выбран не потому, что удобен, а потому, что он РАБОТАЕТ: настоящий узел
 * (`flang/conc/distributed.mjs`) зовёт именно его, и по нему зелены 13 прогонов
 * `flang/conc/distributed.test.mjs`, где два узла говорят по настоящим сокетам,
 * провод перекусывают и замораживают. То есть свидетель проверен не сверкой, а
 * работой.
 *
 * Оговорка названа прямо: сверка «напечатанное с напечатанным» доказывает
 * ПЕРЕНОСИМОСТЬ, а не правильность. Правильность держат прогоны по сокетам,
 * и держат они её у одной цели. Обещать здесь больше было бы враньём.
 *
 * ── Чего здесь нет ──────────────────────────────────────────────────────────
 *
 * Ни одного сокета и ни одних часов. Их у цели никто и не спрашивает: событие
 * приходит значением, отметка часов — числом в этом значении. Это и есть
 * граница, ради которой всё написано.
 *
 * Запуск: node --test flang/test/svyaz-celi.test.mjs
 */
