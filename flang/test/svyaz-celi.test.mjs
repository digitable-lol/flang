/* Состояния связи перебираются ПОЛНОСТЬЮ: пять признаков дают тридцать два
   сочетания, и все тридцать два берутся. Выбирать из них «осмысленные» значило
   бы решать за эталон, какие состояния достижимы, — а это ровно то, что должно
   быть видно из прогона, а не из мнения автора проверки. Пятый признак — «срок
   вышел»: появился вместе со сроком первого знакомства, и перебор вырос сам. */
const состояния = []
for (const готова of [false, true]) {
  for (const звоним of [false, true]) {
    for (const виделись of [false, true]) {
      for (const ждём of [false, true]) {
        for (const срокВышел of [false, true]) {
          for (const байт of [0, 1000]) {
            состояния.push(свидетель.svyazZanovo("учёт", готова, звоним, виделись, ждём, срокВышел, байт))
          }
        }
      }
    }
  }
}

