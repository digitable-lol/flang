/**
 * Напечатанный модуль связи не может разойтись со своим исходником на flang.
 *
 * ── Зачем напечатанное вообще лежит в дереве ────────────────────────────────
 *
 * Узел — РАБОТАЮЩАЯ программа, а не проверка. Печатать компилятором на старте
 * значило бы ввозить в узел весь компилятор, и цена этому уже посчитана в
 * соседней работе: хозяин вкладки, ввозивший три имени из второй реализации,
 * тянул за собой 1 683 164 байта. Поэтому модуль печатается ЗАРАНЕЕ
 * (`flang/scripts/pechat-svyazi.mjs`) и коммитится.
 *
 * ── Чем это не опасно ───────────────────────────────────────────────────────
 *
 * Коммит напечатанного опасен ровно одним: файл правят руками, и он тихо
 * перестаёт отвечать исходнику. Здесь это невозможно — прогон печатает заново и
 * сверяет ПОБАЙТОВО. Правка руками краснеет на первом же прогоне, а не на
 * первом же расхождении в работе узла.
 *
 * ── Почему сверяется ещё и то, что узел зовёт ───────────────────────────────
 *
 * Побайтовая сверка ловит расхождение файла с исходником, но не ловит другого:
 * узел ввозит имена, которых в напечатанном может не оказаться после
 * переименования на flang. Ввоз в ES-модулях проверяется при загрузке, значит
 * такое расхождение и так упало бы, — но упало бы в прогоне УЗЛА, где причина
 * неочевидна. Здесь она названа списком.
 *
 * Запуск: node --test flang/test/svyaz-pechat.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { НАПЕЧАТАННОЕ, ИСХОДНИК, напечататьСвязь } from "../scripts/pechat-svyazi.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))

test("напечатанный модуль связи совпадает с новой печатью побайтово", async () => {
  const лежит = readFileSync(корень + НАПЕЧАТАННОЕ, "utf8")
  const свежее = await напечататьСвязь()
  assert.equal(
    свежее,
    лежит,
    `«${НАПЕЧАТАННОЕ}» разошёлся с «${ИСХОДНИК}». Это не чинится правкой напечатанного: ` +
      "правьте исходник на flang и печатайте заново — node flang/scripts/pechat-svyazi.mjs",
  )
  console.log(`напечатанный модуль связи: ${Buffer.byteLength(лежит, "utf8")} байт, расхождений 0`)
})

test("узел зовёт из напечатанного ровно те имена, которые там объявлены", async () => {
  const модуль = await import("../conc/svyaz.js")
  /* Список — из самого узла, а не из памяти автора: расходиться должно быть
     негде. Читается исходник узла, потому что ввоз в нём один и списком. */
  const узел = readFileSync(корень + "flang/conc/distributed.mjs", "utf8")
  const ввоз = узел.match(/import \{([^}]*)\} from "\.\/svyaz\.js"/u)
  assert.notEqual(ввоз, null, "узел перестал ввозить напечатанный модуль связи")
  const имена = ввоз[1].split(",").map((это) => это.trim()).filter((это) => это !== "")
  assert.ok(имена.length >= 10, `узел ввозит ${имена.length} имён — подозрительно мало`)
  for (const имя of имена) {
    assert.equal(typeof модуль[имя], "function", `напечатанный модуль не отдаёт «${имя}»`)
  }
  console.log(`узел ввозит из напечатанного ${имена.length} имён, все на месте`)
})

test("веления эталона и веления, которые узел умеет исполнить, — одно множество", () => {
  /* Самая дорогая сверка здесь. Эталон объявляет закрытую сумму «Веление», узел
     разбирает её `switch`-ем, и разойтись они могут МОЛЧА в одну сторону: новый
     вариант в эталоне, которого нет у узла, доедет до `default` только тогда,
     когда сложится нужное стечение событий в сети. Поэтому множества сверяются
     ПО ИСХОДНИКАМ, а не ожиданием случая. */
  const эталон = readFileSync(корень + "flang/conc/svyaz.flang", "utf8")
  const кусок = эталон.slice(эталон.indexOf("тип «Веление»"))
  const конец = кусок.indexOf("\nобъект")
  const велят = [...кусок.slice(0, конец).matchAll(/вариант «([^»]+)»/gu)].map((это) => это[1])
  assert.ok(велят.length >= 7, `в эталоне нашлось ${велят.length} велений — разбор шапки сломался`)

  const узел = readFileSync(корень + "flang/conc/distributed.mjs", "utf8")
  const умеет = new Set([...узел.matchAll(/case "([^"]+)":/gu)].map((это) => это[1]))
  for (const веление of велят) {
    assert.ok(умеет.has(веление), `эталон велит «${веление}», а узел такого веления не исполняет`)
  }
  console.log(`велений в эталоне ${велят.length}, все исполняются узлом`)
})
