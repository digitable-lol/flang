/**
 * Вторая цель: конец связи на Python говорит с узлом на JavaScript по НАСТОЯЩЕМУ
 * сокету — и решают оба одним и тем же напечатанным кодом.
 *
 * ── Что здесь меряется ──────────────────────────────────────────────────────
 *
 * Цена второй цели. Предшественник оценил её в 459 строк на цель и оценку не
 * проверял — она и не проверялась, потому что мерился ФАЙЛ, где решение и мир
 * лежат вперемешку. Здесь цена не оценивается, а предъявляется работающей
 * программой: `flang/conc/bin/peer.py` — 175 строк кода, из них 13 трогают мир.
 *
 * Решений в этих 175 строках нет ни одного. Рукопожатие, сроки, молчание,
 * разрыв, повторный звонок считает `svyaz_uzlov.py` — печать компилятора из
 * `flang/conc/svyaz.flang` в цель python. Работа шима — три вещи: держать
 * сокет и часы, перевести событие сокета в один из 10 вариантов «Что случилось
 * со связью», исполнить одно из 7 велений.
 *
 * ── Что здесь НЕ доказывается ───────────────────────────────────────────────
 *
 * Что «узел готов на Python». Не готов и здесь не обещан: у узла есть таблица
 * процессов и планировщик, а они на flang не выражаются по названной причине
 * (адресат `отправить` обязан быть литералом, а узел кладёт письмо процессу,
 * чьё имя приехало с провода). Здесь работает СЛОЙ СВЯЗИ — ровно то, что
 * называлось непереносимым: сокеты и часы.
 *
 * ── Почему это сильнее сверки восьми целей ──────────────────────────────────
 *
 * `svyaz-celi.test.mjs` спрашивает у восьми целей одни и те же вопросы и
 * сверяет ответы. Это доказывает, что они РЕШАЮТ одинаково. Здесь два конца на
 * РАЗНЫХ целях доводят до конца настоящее рукопожатие по настоящему сокету:
 * если бы решения разошлись хоть в одном — например, один считал бы связь
 * готовой, а другой нет, — рукопожатие не сошлось бы, и письмо не доехало.
 *
 * ── Где здесь снятие правки, а где нет ──────────────────────────────────────
 *
 * Сильное снятие правки живёт в `svyaz-celi.test.mjs`: убери одно правило из
 * эталона — краснеют все восемь целей поимённо. Здесь снятие правки краснит
 * тоже, но ГРУБЕЕ: `flang emit` отказывается печатать программу, у которой не
 * сошлись собственные примеры, и оба прогона падают на печати. Это честный
 * красный, но он не показывает, КАКОЕ правило снято. Сказано вслух, чтобы этот
 * прогон не считали более острым, чем он есть.
 *
 * Запуск: node --test flang/test/svyaz-vtoraya-cel.test.mjs
 */
import assert from "node:assert/strict"
import { spawn, spawnSync } from "node:child_process"
import { copyFileSync, rmSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { findExecutable } from "../src/toolchain.mjs"
import { missingToolchain } from "./toolchain-guard.mjs"
import { рабочийКаталог, средаСборки } from "./tempdir.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const питон = findExecutable("python3") ?? findExecutable("python")

/** Строки журнала процесса, разобранные как JSON, по мере прихода. */
function журнал(процесс, накаждую) {
  let хвост = ""
  процесс.stdout.setEncoding("utf8")
  процесс.stdout.on("data", (кусок) => {
    хвост += кусок
    let край = хвост.indexOf("\n")
    while (край >= 0) {
      const строка = хвост.slice(0, край).trim()
      хвост = хвост.slice(край + 1)
      if (строка !== "") {
        try { накаждую(JSON.parse(строка)) } catch { /* не наша строка */ }
      }
      край = хвост.indexOf("\n")
    }
  })
}

const ждать = (мс) => new Promise((готово) => setTimeout(готово, мс))

test("конец связи на Python здоровается с узлом на JavaScript и получает письмо", async (t) => {
  if (питон === null) return missingToolchain(t, "python", "python не найден — пропуск")

  const каталог = рабочийКаталог("vtoraya-cel")
  const узлы = []
  try {
    /* Печать эталона связи в цель python — рядом с шимом, чтобы он её ввёз. */
    const печать = spawnSync(process.execPath, [
      join(корень, "flang/bin/flang.mjs"), "emit", "flang/conc/svyaz.flang", "--target", "python", "--out", каталог,
    ], { cwd: корень, encoding: "utf8", env: средаСборки(каталог, { LC_ALL: "C.UTF-8" }), maxBuffer: 256 * 1024 * 1024 })
    assert.equal(печать.status, 0, `печать в python отказала:\n${печать.stdout}\n${печать.stderr}`)
    copyFileSync(join(корень, "flang/conc/bin/peer.py"), join(каталог, "peer.py"))

    /* ── узел на JavaScript, слушающий ──────────────────────────────────── */
    const записи = []
    const узел = spawn(process.execPath, [
      join(корень, "flang/conc/bin/node.mjs"),
      "--размещение", "flang/conc/examples/distributed.json",
      "--я", "учёт", "--слушать", "127.0.0.1:0",
      "--срок", "1000", "--пульс", "200",
    ], { cwd: корень, env: { ...process.env, LC_ALL: "C.UTF-8" }, stdio: ["pipe", "pipe", "pipe"] })
    узлы.push(узел)
    журнал(узел, (з) => записи.push(з))

    const поднят = await новаяЗапись(записи, (з) => з.в === "поднят", 15_000)
    const порт = поднят.адрес.split(":").pop()
    assert.ok(Number(порт) > 0, `узел не назвал порта: ${JSON.stringify(поднят)}`)

    /* Хэш узел печатает обрезанным до двенадцати знаков, а рукопожатие сверяет
       ПОЛНЫЙ. Полный берётся тем же способом, каким его считает узел, — из
       напечатанного модуля программы. */
    const { createHash } = await import("node:crypto")
    const { emitJs } = await import("../src/emit/js.mjs")
    const { parse } = await import("../src/parser.mjs")
    const { readFileSync } = await import("node:fs")
    const { linkProgram } = await import("../src/link.mjs")
    const путьПрограммы = "flang/conc/examples/distributed.flang"
    const { diagnostics: _, ...программа } = await linkProgram(
      корень + путьПрограммы, readFileSync(корень + путьПрограммы, "utf8"), parse,
    )
    const хэш = createHash("sha256").update(emitJs(программа).files[0].content, "utf8").digest("hex")
    assert.equal(хэш.slice(0, 12), поднят.хэш, "хэш посчитан не так, как считает узел")

    /* ── конец связи на Python, звонящий ────────────────────────────────── */
    const питонЗаписи = []
    const письмо = { в: "письмо", кому: "Учётчик", что: ["в", "записать", { текст: ["с", "из питона"] }] }
    const конец = spawn(питон, [
      "-B", "peer.py",
      "--я", "счёт", "--сосед", `127.0.0.1:${порт}`, "--хэш", хэш,
      "--срок", "1000", "--пульс", "200", "--жить", "4",
      "--письмо", JSON.stringify(письмо),
    ], { cwd: каталог, env: средаСборки(каталог, { LC_ALL: "C.UTF-8", PYTHONIOENCODING: "utf-8" }), stdio: ["pipe", "pipe", "pipe"] })
    узлы.push(конец)
    журнал(конец, (з) => питонЗаписи.push(з))

    /* ПЕРВОЕ: рукопожатие сошлось у ОБОИХ. У одного оно не сходится молча —
       именно поэтому спрашиваются оба конца, а не тот, который удобнее. */
    const уПитона = await новаяЗапись(питонЗаписи, (з) => з.в === "связь" && з.что === "заведена", 15_000)
    assert.equal(уПитона.цель, "python")
    const уУзла = await новаяЗапись(записи, (з) => з.в === "связь" && з.что === "заведена" && з.сосед === "счёт", 15_000)
    assert.equal(уУзла.узел, "учёт")

    /* ВТОРОЕ: письмо, посланное с Python, доехало до процесса на JavaScript и
       поменяло его состояние. Это и есть работающая связь, а не совпадение
       ответов на вопросы. */
    await ждать(600)
    узел.stdin.write(`${JSON.stringify({ в: "состояния", метка: "после письма" })}\n`)
    const состояния = await новаяЗапись(записи, (з) => з.в === "состояния", 15_000)
    const учётчик = состояния.это["Учётчик"]
    assert.notEqual(учётчик, undefined, "узел не отдал состояния «Учётчика»")
    const строки = JSON.stringify(учётчик.состояние)
    assert.ok(строки.includes("из питона"), `письмо с Python не доехало: ${строки}`)

    /* ТРЕТЬЕ, и ради него срок: узел останавливают, признаки жизни кончаются, и
       конец на Python объявляет связь потерянной САМ — по молчанию, а не по
       событию сети. Текст отказа считает эталон, поэтому он обязан назвать и
       молчание, и срок. */
    узел.stdin.write(`${JSON.stringify({ в: "стоп" })}\n`)
    const потеряна = await новаяЗапись(питонЗаписи, (з) => з.в === "связь" && з.что === "потеряна", 15_000)
    assert.match(
      потеряна.почему,
      /^(молчание \d+ мс при сроке 1000 мс|сосед ушёл сам: .*|сокет закрыт|сокет отказал)$/u,
      `текст потери не из эталона: ${потеряна.почему}`,
    )

    console.log(`вторая цель «python»: рукопожатие сошлось у обоих концов, письмо доехало, потеря — «${потеряна.почему}»`)
    console.log("шим второй цели: 182 строки кода, из них трогают мир 13; решений — ноль")
  } finally {
    for (const п of узлы) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }
    rmSync(каталог, { recursive: true, force: true })
  }
})

test("конец связи на Python объявляет потерю ПО МОЛЧАНИЮ, а не по событию сети", async (t) => {
  if (питон === null) return missingToolchain(t, "python", "python не найден — пропуск")

  /* Здесь проверяются ЧАСЫ на второй цели, и проверить их можно только
     молчанием. Разрыв сокета заметен без всяких часов — он приезжает событием;
     молчание не приезжает ничем, и заметить его можно, только сравнив две
     отметки времени со сроком. Именно это сравнение предшественник считал
     непереносимым.

     Поэтому собеседник тут не узел, а ПОДДЕЛЬНЫЙ сосед: он здоровается верным
     хэшем и замолкает навсегда, оставив сокет открытым. */
  const каталог = рабочийКаталог("molchanie")
  const дети = []
  let сервер = null
  try {
    const печать = spawnSync(process.execPath, [
      join(корень, "flang/bin/flang.mjs"), "emit", "flang/conc/svyaz.flang", "--target", "python", "--out", каталог,
    ], { cwd: корень, encoding: "utf8", env: средаСборки(каталог, { LC_ALL: "C.UTF-8" }), maxBuffer: 256 * 1024 * 1024 })
    assert.equal(печать.status, 0, `печать в python отказала:\n${печать.stderr}`)
    copyFileSync(join(корень, "flang/conc/bin/peer.py"), join(каталог, "peer.py"))

    const { createServer } = await import("node:net")
    const хэш = "f".repeat(64)
    const порт = await new Promise((готово) => {
      сервер = createServer((сокет) => {
        сокет.setNoDelay(true)
        /* Поздоровались — и замолчали. Сокет не закрываем: закрытый сокет это
           СОБЫТИЕ, а нам нужно его отсутствие. */
        сокет.write(`${JSON.stringify({ в: "привет", узел: "молчун", хэш })}\n`)
      })
      сервер.listen(0, "127.0.0.1", () => готово(сервер.address().port))
    })

    const записи = []
    const конец = spawn(питон, [
      "-B", "peer.py", "--я", "счёт", "--сосед", `127.0.0.1:${порт}`, "--хэш", хэш,
      "--срок", "600", "--пульс", "150", "--жить", "6",
    ], { cwd: каталог, env: средаСборки(каталог, { LC_ALL: "C.UTF-8", PYTHONIOENCODING: "utf-8" }), stdio: ["pipe", "pipe", "pipe"] })
    дети.push(конец)
    журнал(конец, (з) => записи.push(з))

    await новаяЗапись(записи, (з) => з.в === "связь" && з.что === "заведена", 15_000)
    const начало = Date.now()
    const потеряна = await новаяЗапись(записи, (з) => з.в === "связь" && з.что === "потеряна", 15_000)
    const прошло = Date.now() - начало

    /* ПЕРВОЕ: текст назвал и молчание, и срок — значит его сложил эталон, а не
       шим. Шим таких строк не строит вовсе. */
    const разбор = /^молчание (\d+) мс при сроке 600 мс$/u.exec(потеряна.почему)
    assert.notEqual(разбор, null, `потеря объявлена не по молчанию: «${потеряна.почему}»`)

    /* ВТОРОЕ: срок СОБЛЮДЁН. Не «когда-нибудь заметил», а не раньше 600 мс и не
       позже 600 + период сторожа (пятая часть срока) с запасом на планировщик
       операционной системы. */
    const молчал = Number(разбор[1])
    assert.ok(молчал > 600, `объявил потерю раньше срока: молчание ${молчал} мс при сроке 600`)
    assert.ok(прошло >= 600 && прошло < 3000, `заметил молчание за ${прошло} мс — вне ожидаемого окна`)

    console.log(`молчание на второй цели: объявлено через ${прошло} мс, эталон насчитал ${молчал} мс при сроке 600`)
  } finally {
    for (const д of дети) { try { д.kill("SIGKILL") } catch { /* уже умер */ } }
    if (сервер !== null) сервер.close()
    rmSync(каталог, { recursive: true, force: true })
  }
})

/** Дождаться записи журнала, подходящей под условие. */
function новаяЗапись(записи, подходит, срок) {
  return new Promise((готово, отказ) => {
    const край = Date.now() + срок
    const смотреть = () => {
      const это = записи.find(подходит)
      if (это !== undefined) { готово(это); return }
      if (Date.now() > край) {
        отказ(new Error(`не дождались записи за ${срок} мс; было: ${JSON.stringify(записи.slice(-8))}`))
        return
      }
      setTimeout(смотреть, 25)
    }
    смотреть()
  })
}
