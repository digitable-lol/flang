/**
 * Сторож временных каталогов — и проверка САМОГО сторожа.
 *
 * Устройство и довод — в шапке `flang/scripts/tempdir-guard.mjs`. Обязательств
 * здесь четыре, и второе с третьим важнее первого:
 *
 *   1. на дереве каждый тест печати берёт каталог у помощника, а не сам:
 *      `mkdtemp(join(tmpdir(), …))` мимо `flang/test/tempdir.mjs` — это ровно
 *      тот каталог, который переживёт отказ;
 *   2. каталог исчезает, когда тест УПАЛ. Уборка, которая работает только на
 *      зелёном, возвращает беду в худший день — тот, когда что-то сломалось;
 *   3. каталог исчезает, когда процесс УБИТ сигналом. `after()` в этом случае
 *      не выполняется вовсе, и именно так копились сотни `flang-emit-*`;
 *   4. сторож КРАСНЕЕТ на оставленном каталоге и называет его имя. Сторож,
 *      который не умеет краснеть, не стережёт ничего.
 *
 * Второе, третье и четвёртое проверяются не рассуждением, а прогоном: тест
 * заводит настоящий каталог, роняет настоящий процесс и смотрит на диск.
 *
 * Запуск: node --test flang/test/tempdir-guard.test.mjs
 */
import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import test from "node:test"

import { СЛЕДЫ, поВидам, счёт } from "../scripts/tempdir-guard.mjs"
import { рабочийКаталог } from "./tempdir.mjs"

const каталогТестов = fileURLToPath(new URL(".", import.meta.url))
const помощник = fileURLToPath(new URL("./tempdir.mjs", import.meta.url))

/** Файлы печати, которым положено брать каталог у помощника. */
const файлыПечати = readdirSync(каталогТестов)
  .filter((имя) => /^(emit|self-emit)-.*\.test\.mjs$/u.test(имя))
  .sort()

test("ни один тест печати не заводит временный каталог мимо помощника", () => {
  const мимо = []
  for (const имя of файлыПечати) {
    const текст = readFileSync(new URL(имя, new URL(".", import.meta.url)), "utf8")
    if (/mkdtemp(Sync)?\(\s*join\(\s*tmpdir\(\)/u.test(текст)) мимо.push(имя)
  }
  assert.deepEqual(
    мимо,
    [],
    "каталог, заведённый мимо `flang/test/tempdir.mjs`, не убирается ни при отказе, ни при сигнале",
  )
})

test("файлы печати, зовущие чужой тулчейн, уводят его временное к себе", () => {
  /* Увод `TMPDIR` — единственное, чем чужому рантайму указывается место: .NET
     кладёт по пять каталогов на сборку туда, куда смотрит эта переменная, а не
     туда, куда ей велел тест. */
  const безУвода = []
  for (const имя of файлыПечати) {
    const текст = readFileSync(new URL(имя, new URL(".", import.meta.url)), "utf8")
    const зовётСборку = /\.\.\.process\.env/u.test(текст)
    if (зовётСборку && !/средаСборки\(/u.test(текст)) безУвода.push(имя)
  }
  assert.deepEqual(безУвода, [], "окружение сборки собирается вручную — временное чужого тулчейна уедет в /tmp")
})

test("каталог исчезает, когда тест УПАЛ", () => {
  const { статус, каталог } = жертвой("fail", `test("этот тест обязан упасть", () => {
  throw new Error("нарочный отказ")
})`)
  assert.notEqual(статус, 0, "жертва обязана была упасть — иначе проверяется не то")
  assert.equal(existsSync(каталог), false, `каталог пережил ОТКАЗ теста: ${каталог}`)
})

test("каталог исчезает, когда процесс УБИТ сигналом", () => {
  /* `after()` при сигнале не выполняется вовсе — здесь проверяется тот крючок,
     ради которого помощник вешает обработчики SIGTERM и соседей. */
  const { каталог } = жертвой("signal", `test("этот тест не доживёт до конца", async () => {
  process.kill(process.pid, "SIGTERM")
  await new Promise((дальше) => setTimeout(дальше, 30_000))
})`, ["--test-isolation=none"])
  assert.equal(existsSync(каталог), false, `каталог пережил СИГНАЛ: ${каталог}`)
})

test("сторож КРАСНЕЕТ на оставленном каталоге и называет его имя", () => {
  const корень = рабочийКаталог("guard-self")
  /* Каталог внутри корня прогона — ровно то, что оставляет за собой неубравший
     прогон. Помощник заводит `tmp/` для чужих тулчейнов, его и хватает. */
  const итог = счёт({ корень, имяКорня: корень.split("/").pop(), до: [], после: [] })
  assert.equal(итог.чисто, false, "сторож обязан покраснеть на непустом корне прогона")
  assert.deepEqual(итог.своё, ["tmp"], "имя оставленного каталога обязано быть названо")
})

test("сторож ЗЕЛЁН на пустом корне — и это не совпадение", () => {
  const корень = rmdirПустой(рабочийКаталог("guard-clean"))
  const итог = счёт({ корень, имяКорня: корень.split("/").pop(), до: [], после: [] })
  assert.equal(итог.чисто, true, "пустой корень прогона — это чистый прогон")
  assert.deepEqual(итог.своё, [])
})

test("след печати мимо корня узнаётся по имени — по всем четырём видам", () => {
  const виды = поВидам([
    "flang-emit-csharp-aB3xYz",
    "MSBuildTemp800loR",
    "NuGetScratchm",
    "go-build2078711404",
    "чужое-имя-которое-не-наше",
  ])
  assert.deepEqual(виды.map((в) => в.сколько), [1, 1, 1, 1], "каждый вид следа обязан быть узнан ровно раз")
  assert.equal(СЛЕДЫ.length, 4, "видов следа четыре — списку и проверке положено сойтись")
})

test("след МИМО корня считается, но не судит — пока не спросили строго", () => {
  /* Соседняя сессия, гоняющая непочиненное дерево, кладёт в /tmp ровно такие же
     имена. Сторожа, краснеющего от соседа, перестают читать — а он нужен читаемым
     ровно в тот день, когда сломалось что-то ещё. */
  const пустойКорень = rmdirПустой(рабочийКаталог("guard-mimo"))
  const мягко = счёт({
    корень: пустойКорень, имяКорня: "нет",
    до: [], после: ["MSBuildTempНОВЫЙ"],
  })
  assert.equal(мягко.чисто, true, "чужой след — счёт, а не приговор")
  assert.deepEqual(мягко.мимо.map((в) => в.сколько), [1], "но он обязан быть НАЗВАН числом")

  const строго = счёт({
    корень: пустойКорень, имяКорня: "нет",
    до: [], после: ["MSBuildTempНОВЫЙ"], строго: true,
  })
  assert.equal(строго.чисто, false, "на машине, где прогон один, тот же след — приговор")
})

test("чужой каталог, лежавший до прогона, сторожу не принадлежит", () => {
  /* Убирать чужое вслепую — та же беда со сменившимся виновником: каталог,
     заведённый минуту назад соседней сессией, может быть живым. */
  const итог = счёт({
    корень: "/несуществующий-корень-прогона",
    имяКорня: "нет",
    до: ["MSBuildTempСТАРЫЙ", "flang-emit-go-СТАРЫЙ"],
    после: ["MSBuildTempСТАРЫЙ", "flang-emit-go-СТАРЫЙ"],
  })
  assert.equal(итог.чисто, true, "то, что лежало ДО прогона, прогон не оставлял")
  assert.equal(итог.новых, 0)
})

/**
 * Прогнать нарочно гибнущий тест и вернуть его каталог.
 *
 * Путь каталога едет ФАЙЛОМ, а не через stdout: `node --test` буферизует вывод
 * ребёнка по-разному в зависимости от изоляции, и проверка уборки не имеет
 * права зависеть от того, успел ли вывод доехать до смерти процесса.
 */
function жертвой(метка, тело, ключи = []) {
  const жертва = `${каталогТестов}tempdir-victim-${метка}.test.mjs`
  const метка_файла = `${каталогТестов}tempdir-victim-${метка}.путь`
  writeFileSync(жертва, `import { writeFileSync } from "node:fs"
import test from "node:test"
import { рабочийКаталог } from ${JSON.stringify(помощник)}
const каталог = рабочийКаталог("victim-${метка}")
writeFileSync(${JSON.stringify(метка_файла)}, каталог)
${тело}
`)
  try {
    /* `node --test` отказывается запускать файлы, увидев себя в окружении
       («run() is being called recursively»), — а жертву надо гнать НАСТОЯЩИМ
       прогонщиком, иначе не проверяется ни `after()`, ни крючок сигнала. */
    const среда = { ...process.env }
    for (const ключ of Object.keys(среда)) if (ключ.startsWith("NODE_TEST")) delete среда[ключ]
    const итог = spawnSync(process.execPath, ["--test", ...ключи, жертва], {
      encoding: "utf8",
      timeout: 120_000,
      env: среда,
    })
    assert.equal(
      existsSync(метка_файла),
      true,
      `жертва не назвала каталог; код ${итог.status}, сигнал ${итог.signal}, вывод: ${итог.stdout?.slice(0, 400)}${итог.stderr?.slice(0, 400)}`,
    )
    return { статус: итог.status, каталог: readFileSync(метка_файла, "utf8") }
  } finally {
    spawnSync("rm", ["-f", жертва, метка_файла])
  }
}

function rmdirПустой(путь) {
  spawnSync("rm", ["-rf", `${путь}/tmp`])
  return путь
}
