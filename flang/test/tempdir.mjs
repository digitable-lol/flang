/**
 * Временный каталог прогона печати: один на файл теста, и он ОБЯЗАН исчезнуть.
 *
 * ── Что сломалось ───────────────────────────────────────────────────────────
 *
 * Тесты печати собирают напечатанное настоящими тулчейнами, и каждый заводил
 * себе `mkdtemp(join(tmpdir(), "flang-emit-…"))` с уборкой в `after()`. Уборка
 * работала — ровно в том случае, когда прогон доходил до конца. Дальше две дыры,
 * и обе стоили соседям измерений:
 *
 *   1. `after()` не выполняется, когда процесс убит сигналом (`node --test`
 *      гоняет каждый файл отдельным процессом и рассылает им SIGTERM, когда
 *      сдаётся сам) и когда прогон прерван снаружи. Каталог остаётся. Именно
 *      поэтому в /tmp лежали сотни `flang-emit-*`: они копились не в обычные
 *      дни, а в те, когда что-то ломалось, — то есть в худшие;
 *
 *   2. и главное — ЧУЖОЙ РАНТАЙМ. `dotnet build` кладёт временное не туда, куда
 *      ему велел тест, а туда, куда указывает `TMPDIR`. Переменная не
 *      выставлялась, и каждая сборка C# оставляла в /tmp ЧЕТЫРЕ новых каталога
 *      (два `MSBuildTemp######`, два из шести случайных букв — под
 *      `dotnet-sdk-advertising-temp`) плюс общий `NuGetScratch<пользователь>`.
 *      Их не убирает никто: ни .NET, ни тест, который о них не знает. Прогон
 *      корпуса — это десятки сборок, а /tmp здесь tmpfs с 1 048 576 инодами:
 *      место не кончается (192 ГБ свободно), кончаются иноды, и соседний прогон
 *      падает с ENOSPC на пустом диске.
 *
 *      Мера — числом, `strace -e trace=mkdir,mkdirat` на одной сборке:
 *      без `TMPDIR` — 5 каталогов прямо в /tmp; с `TMPDIR` — НОЛЬ в /tmp
 *      и 16 внутри своего каталога. Go добавляет по одному `go-build#` на
 *      вызов `go build` (сам обычно убирает, но не когда его убили);
 *      rustc, cargo, python3, gcc — ноль; javac и java трогают только общий
 *      `hsperfdata_<пользователь>`, один на пользователя.
 *
 * ── Как чинится ─────────────────────────────────────────────────────────────
 *
 * `рабочийКаталог(метка)` заводит каталог и вешает уборку ТРИЖДЫ, потому что
 * ни один из трёх путей не покрывает остальные:
 *
 *   • `after()` — обычный конец файла теста, в том числе с красными тестами;
 *   • `process.on("exit")` — синхронный `rmSync`: сюда приходит и обычный выход,
 *     и выход после необработанного исключения, и `process.exit()`;
 *   • обработчики SIGINT/SIGTERM/SIGHUP/SIGQUIT — снимают себя и передают
 *     сигнал дальше, чтобы код выхода остался честным.
 *
 * `средаСборки(каталог, добавки)` уводит временное ЧУЖИХ инструментов внутрь
 * этого же каталога: `TMPDIR`/`TMP`/`TEMP` (их читают .NET, Go, cargo, Python,
 * Erlang, gcc) и `GOTMPDIR`. Отдельно гасится переиспользование узлов MSBuild
 * (`MSBUILDDISABLENODEREUSE`): выживший с прошлой сборки узел работает со СТАРЫМ
 * окружением и пишет мимо нашего `TMPDIR`, да ещё и живёт после прогона.
 *
 * Итог: весь мусор прогона лежит в ОДНОМ каталоге и уезжает с ним целиком.
 *
 * ── Куда именно кладётся каталог ────────────────────────────────────────────
 *
 * По умолчанию — в `os.tmpdir()`. Если задан `FLANG_TEST_TMPDIR`, то в него:
 * так сторож `flang/scripts/tempdir-guard.flang` даёт всему прогону один корень и
 * потом считает, сколько в нём осталось. Это и есть единственная НЕДВУСМЫСЛЕННАЯ
 * мера мусора: на машине работают чужие сессии, и по общему счёту каталогов
 * в /tmp своё от чужого не отличить, а по своему корню — отличить.
 */
import { existsSync, mkdirSync, mkdtempSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { after } from "node:test"

/** Сигналы, после которых `after()` уже не позовут. */
const СИГНАЛЫ = ["SIGINT", "SIGTERM", "SIGHUP", "SIGQUIT"]

/** Заведённые этим процессом каталоги — всё, что предстоит убрать. */
const свои = new Set()

let крючкиПовешены = false

/** Куда класть каталоги прогона: корень сторожа, если он задан, иначе `os.tmpdir()`. */
export function корень() {
  const заданный = process.env.FLANG_TEST_TMPDIR
  if (заданный !== undefined && заданный !== "") {
    mkdirSync(заданный, { recursive: true })
    return заданный
  }
  return tmpdir()
}

/** Убрать всё своё. Синхронно и молча: зовётся в том числе из обработчика выхода. */
export function убратьЗаСобой() {
  for (const путь of свои) {
    try {
      rmSync(путь, { recursive: true, force: true, maxRetries: 3 })
    } catch {
      /* Уборка не имеет права уронить прогон: код выхода принадлежит тестам. */
    }
    свои.delete(путь)
  }
}

function повеситьКрючки() {
  if (крючкиПовешены) return
  крючкиПовешены = true

  /* Обычный конец файла теста — в том числе когда тесты КРАСНЫЕ: `after()`
     выполняется и после отказа, ради этого он и берётся. Каталог, взятый уже
     ВНУТРИ теста, вешать некуда — корневой набор запущен; там уборку держат
     крючок выхода и сигналы, и это не хуже: они срабатывают и там, где
     `after()` не позвали бы вовсе. */
  try {
    after(убратьЗаСобой)
  } catch {
    /* Прогон не имеет права упасть об устройство уборки. */
  }

  /* Выход мимо `after()`: необработанное исключение при разборе модуля,
     `process.exit()`, отказ на верхнем уровне. Только синхронное. */
  process.on("exit", убратьЗаСобой)

  /* Сигнал не даёт выполниться ни `after()`, ни `exit`-крючку, если его не
     перехватить. Перехватываем, убираем и передаём сигнал дальше — иначе код
     выхода соврёт, будто прогон завершился сам. */
  for (const сигнал of СИГНАЛЫ) {
    const крючок = () => {
      убратьЗаСобой()
      process.off(сигнал, крючок)
      process.kill(process.pid, сигнал)
    }
    process.on(сигнал, крючок)
  }
}

/**
 * Завести временный каталог прогона под именем `flang-<метка>-XXXXXX`.
 *
 * Каталог убирается при любом исходе: зелёном, красном и убитом сигналом.
 */
export function рабочийКаталог(метка) {
  повеситьКрючки()
  const путь = mkdtempSync(join(корень(), `flang-${метка}-`))
  свои.add(путь)
  mkdirSync(join(путь, "tmp"), { recursive: true })
  return путь
}

/** Подкаталог, куда уводится временное чужих инструментов. */
export function чужоеВремя(каталог) {
  const путь = join(каталог, "tmp")
  if (!existsSync(путь)) mkdirSync(путь, { recursive: true })
  return путь
}

/**
 * Окружение для сборки: `process.env` плюс увод чужого временного внутрь
 * `каталог`, плюс `добавки` теста (они сильнее — тест знает про свою цель).
 */
export function средаСборки(каталог, добавки = {}) {
  const время = чужоеВремя(каталог)
  return {
    ...process.env,
    /* Читают .NET/MSBuild, Go, cargo, Python, Erlang, gcc. */
    TMPDIR: время,
    TMP: время,
    TEMP: время,
    /* Go читает и его, и он старше TMPDIR. */
    GOTMPDIR: время,
    /* Узел MSBuild, выживший с прошлой сборки, несёт СТАРОЕ окружение и пишет
       мимо нашего TMPDIR — да ещё и живёт минутами после прогона. */
    MSBUILDDISABLENODEREUSE: "1",
    ...добавки,
  }
}
