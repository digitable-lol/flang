/**
 * Точку раскрутки печатает САМ ДВОИЧНЫЙ — и печатает то же, что лежит в дереве.
 *
 * ── Что здесь стережётся и почему отдельным файлом ──────────────────────────
 * Рядом, в `self-bootstrap.test.mjs`, стоит тест «точка раскрутки `bootstrap/`
 * совпадает с печатью текущих исходников»: он сверяет дерево с печатью
 * РЕАЛИЗАЦИИ НА JAVASCRIPT. Здесь сверяется то же дерево с печатью ДВОИЧНОГО.
 * Два сторожа на один артефакт дают ровно то, ради чего затевалась работа:
 *
 *   печать двоичного == bootstrap/ == печать реализации на JavaScript
 *
 * то есть две печати совпадают байт в байт, пока вторая жива. Когда её удалят,
 * этот файл останется единственным сторожем, и сверять он будет то, что и
 * должен: собирается ли дерево из своих исходников без Node.
 *
 * Отдельным файлом потому, что зависимости у них разные до противоположности.
 * Тому сторожу не нужен ни `cc`, ни `make`, и он идёт всегда, стоя секунды.
 * Этому нужен собранный двоичный, и стоит он минуты и гигабайты.
 *
 * ── Улика ДО, снятая прогоном 20 августа 2026 ───────────────────────────────
 * `env -i PATH=/usr/bin:/bin sh scripts/bootstrap-c.sh --check`: 7 файлов,
 * 15 641 371 байт, код 0 за 4 м 57 с. Все семь совпали с печатью реализации на
 * JavaScript байт в байт — `Makefile` 2 893, `compiler_flang.c` 12 353 351,
 * `compiler_flang.h` 2 525 322, `flang_cli.c` 49 020, `flang_repl.c` 499 612,
 * `flang_runtime.c` 150 606, `flang_runtime.h` 60 567.
 *
 * ── Почему по умолчанию ПРОПУСК, и почему это не тихий пропуск ──────────────
 * Печать двоичным берёт МНОГО памяти: вычислитель здесь написан на самом языке,
 * а арена не отдаёт ничего до конца запроса. Мерено на этом дереве прогоном:
 * точка на одной цели C — 8,3 ГБ и 5 м 37 с; точка на восьми целях — 11,3 ГБ и
 * дольше. На машине с 7 ГБ (обычный прогон CI на ubuntu-latest) это не
 * «медленно», а отказ по памяти, и включать такое по умолчанию значило бы
 * красить прогон за нехватку железа.
 *
 * ЗДЕСЬ БЫЛО «идёт, если двоичный уже лежит собранным», и это стало ОПАСНЫМ в
 * тот же день: соседняя работа над CI (`vypusk/ci-dvoichnyy`) добавила
 * `make -C bootstrap` перед общим прогоном — именно затем, чтобы проверки,
 * ходящие в двоичный, перестали пропускаться. То есть признак «двоичный есть»
 * теперь верен ровно там, где памяти меньше всего.
 *
 * Поэтому признак — ПАМЯТЬ, а не наличие файла, и число берётся у машины
 * (`os.totalmem()`), а не угадывается. Плюс прямая просьба
 * `FLANG_TOCHKA_DVOICHNYM=1`, которая перебивает всё: на машине, где мерили,
 * человек знает лучше.
 *
 * В остальных случаях тест говорит «НЕ ПРОВЕРЕНО» и называет, сколько памяти
 * нашлось, — а не молчит: «не смог проверить» и «проверил, всё хорошо» — разные
 * исходы, и их смешение в этом дереве уже однажды провезло ложь до пользователя
 * (`scripts/node-free-path.mjs`).
 */
import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { existsSync, readFileSync } from "node:fs"
import { totalmem } from "node:os"
import { join } from "node:path"
import { test } from "node:test"
import { fileURLToPath } from "node:url"

import { корень as корневойВременный } from "./tempdir.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))

/*
 * Имя каталога читается из рецепта на `sh`, а не берётся у
 * `scripts/bootstrap-c.mjs`, — и это не педантизм, а условие выживания этой
 * проверки. Она заведена ровно затем, чтобы остаться сторожем ПОСЛЕ удаления
 * реализации на JavaScript; импортируй она то, что удалят, — упала бы в тот же
 * день с «модуль не найден», то есть сломалась бы именно тогда, когда нужна.
 * Поэтому здесь нет ни одного импорта из `flang/src` и `scripts/*.mjs`.
 */
const РЕЦЕПТ = readFileSync(join(корень, "scripts/bootstrap-c.sh"), "utf8")
const изРецепта = (имя) => {
  const найдено = РЕЦЕПТ.match(new RegExp(`^${имя}='([^']*)'`, "mu"))
  assert.ok(найдено, `scripts/bootstrap-c.sh: не найдено ${имя} — рецепт печати разошёлся`)
  return найдено[1]
}
const КАТАЛОГ = изРецепта("FLANG_OUT")
const двоичный = join(корень, КАТАЛОГ, "flang")
const попросили = process.env.FLANG_TOCHKA_DVOICHNYM === "1"
const есть = (имя) => spawnSync("sh", ["-c", `command -v ${имя}`], { stdio: "ignore" }).status === 0

/* Мерено прогоном: 11,3 ГБ на восьмицелевой точке. Порог с запасом, потому что
   печать растёт вместе с компилятором, а промах по памяти стоит не «медленнее»,
   а убитого процесса. */
const НУЖНО_ГБ = 16
const памятиГБ = totalmem() / 1024 / 1024 / 1024
const хватаетПамяти = памятиГБ >= НУЖНО_ГБ

test("точка раскрутки: печать двоичного совпадает с деревом байт в байт", (t) => {
  if (!попросили && !хватаетПамяти) {
    t.diagnostic(
      `НЕ ПРОВЕРЕНО: печать двоичным берёт больше ${НУЖНО_ГБ} ГБ, а на этой машине ` +
        `${памятиГБ.toFixed(1)} ГБ. Это не «всё хорошо», а «не смог проверить». ` +
        "Гоните на машине с памятью или попросите прямо: FLANG_TOCHKA_DVOICHNYM=1",
    )
    t.skip(`памяти ${памятиГБ.toFixed(1)} ГБ из ${НУЖНО_ГБ} — печать двоичным не проверена`)
    return
  }
  if (!existsSync(двоичный)) {
    t.diagnostic(`НЕ ПРОВЕРЕНО: двоичного нет — соберите его: make -C ${КАТАЛОГ}`)
    t.skip("двоичный не собран — печать двоичным не проверена")
    return
  }
  if (!есть("make")) {
    t.diagnostic("НЕ ПРОВЕРЕНО: `make` не найден — двоичный не из чего собрать")
    t.skip("нет make")
    return
  }

  /* TMPDIR уводится в корень прогона: скрипт печатает во временный каталог, а
     сторож временных каталогов (`flang/scripts/tempdir-guard.mjs`) считает
     мусор именно по этому корню. Каталог на 15 МБ, заведённый мимо него,
     сторож назвал бы следом печати и не смог бы отличить от чужого. */
  const итог = spawnSync("sh", ["scripts/bootstrap-c.sh", "--check"], {
    cwd: корень,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    env: { ...process.env, TMPDIR: корневойВременный() },
  })
  assert.equal(
    итог.status,
    0,
    `печать двоичного разошлась с ${КАТАЛОГ}/:\n${итог.stdout ?? ""}\n${итог.stderr ?? ""}`,
  )
  const строка = (итог.stdout ?? "").split("\n").find((с) => с.includes("совпадает с печатью двоичного"))
  assert.ok(строка, `сверка не сказала, что совпало:\n${итог.stdout}\n${итог.stderr}`)
  t.diagnostic(строка.trim())
})
