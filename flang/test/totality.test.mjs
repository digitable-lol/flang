/* Числовая мера: принимается                                          */
/* ================================================================== */

/**
 * `тотальная функция «До нуля» … если н не больше 0 то 0 иначе «До нуля» от
 * (н минус 1)` — та самая программа, ради которой мера появилась.
 *
 * Разбирается из исходника, а не собирается руками: доказательство опирается на
 * ФОРМУ условия (`не больше` → `lte` → граница в ветви `иначе`), и собранный
 * руками AST проверял бы не то, что напишет человек.
 */
const счётДоНуля = (условие, ветви, шаг) => `модуль «Счёт»

тотальная функция «До нуля»
  принимает н: число
  возвращает число
  если ${условие}
    то ${ветви[0]}
    иначе ${ветви[1]}
`.replace("ШАГ", шаг)

const доказана = (source, имя = "До нуля") => {
  const result = checkTotality(parse(source))
  assert.deepEqual(result.diagnostics, [])
  assert.ok(result.total.has(имя), `«${имя}» не доказана`)
  return result
}

const отвергнута = (source) => {
  const result = checkTotality(parse(source))
  assert.deepEqual(коды(result), ["FLANG_NOT_TOTAL"])
  assert.deepEqual([...result.total], [])
  return result.diagnostics[0].message
}

test("счёт «н минус 1» с базой «не больше нуля» доказан тотальным", () => {
  доказана(счётДоНуля("н не больше 0", ["0", "ШАГ"], "«До нуля» от (н минус 1)"))
})

test("та же мера с рекурсией в ветви «то» и условием «больше нуля»", () => {
  доказана(счётДоНуля("н больше 0", ["ШАГ", "0"], "«До нуля» от (н минус 1)"))
})

test("литерал слева от имени читается как та же граница", () => {
  доказана(счётДоНуля("0 меньше н", ["ШАГ", "0"], "«До нуля» от (н минус 1)"))
})

/**
 * Дробный шаг принимается — и это решение, а не недосмотр. Опасен не дробный
 * шаг, а база-РАВЕНСТВО: `н минус 0.5` при базе `н равно 0` не завершается на
 * входе 0.75, но там же не завершается и `н минус 1` на входе 0.5. При базе
 * неравенством любой постоянный отрицательный шаг доводит до дна за
 * (н − K)/шаг вызовов, дробный в том числе.
 */
test("дробный шаг при базе-неравенстве доказывается наравне с целым", () => {
  доказана(счётДоНуля("н не больше 0", ["0", "ШАГ"], "«До нуля» от (н минус 0.5)"))
})

test("граница действует на всё, что выведено из того же параметра, включая «пусть» до «если»", () => {
  доказана(`модуль «Счёт»

тотальная функция «До нуля»
  принимает н: число
  возвращает число
  пусть убавленное равно (н минус 1)
  если н не больше 0
    то 0
    иначе «До нуля» от убавленное
`)
})

test("взаимная рекурсия по общей мере доказывается", () => {
  const result = доказана(`модуль «Счёт»

тотальная функция «Чётное»
  принимает н: число
  возвращает число
  если н не больше 0
    то 1
    иначе «Нечётное» от (н минус 1)

тотальная функция «Нечётное»
  принимает н: число
  возвращает число
  если н не больше 0
    то 0
    иначе «Чётное» от (н минус 1)
`, "Чётное")
  assert.deepEqual([...result.total].sort(), ["Нечётное", "Чётное"])
})

