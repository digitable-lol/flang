/**
 * Тесты анализа завершаемости flang.
 *
 * Каждая программа собрана руками по SPEC.md, раздел 5. Отвергнутые
 * программы проверяются не «отказом вообще», а кодом диагностики и тем,
 * что в сообщении названо конкретное место: без этого отказ бесполезен —
 * автор не узнает, какой именно вызов не убывает.
 *
 * Запуск: node --test flang/test/totality.test.mjs
 */
import assert from "node:assert/strict"
import { test } from "node:test"

import { createRuntime } from "../src/interpret.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality, markMeasureGuards } from "../src/totality.mjs"

/* ---- сокращения для AST ------------------------------------------- */

const число = { kind: "number" }
const список = (of) => ({ kind: "list", of })
const имя = (name) => ({ kind: "named", name })

const лит = (value) => ({ kind: "literal", value })
const пер = (name) => ({ kind: "var", name })
const оп = (op, left, right) => ({ kind: "binary", op, left, right })
const вызов = (name, ...args) => ({ kind: "call", name, args })
const форма = (name, ...args) => ({ kind: "builtin", name, args })
const разбор = (target, ...cases) => ({ kind: "match", target, cases })
const пусто = (body) => ({ pattern: { kind: "empty" }, body })
const голова_и_хвост = (head, tail, body) => ({ pattern: { kind: "cons", head, tail }, body })

const программа = (functions, types = []) => ({ flang: 1, module: "Тест", types, functions })
const коды = (result) => result.diagnostics.map((diagnostic) => diagnostic.code)

/** «Длина» из SPEC, раздел 4: убывание по хвосту списка. */
const длина = {
  name: "Длина",
  total: true,
  params: [{ name: "элементы", type: список(число) }],
  returns: число,
  body: разбор(
    пер("элементы"),
    пусто(лит(0)),
    голова_и_хвост("г", "х", оп("add", лит(1), вызов("Длина", пер("х")))),
  ),
}

/* ================================================================== */
/* Принимаются                                                         */
/* ================================================================== */

test("длина списка через хвост признаётся тотальной", () => {
  const result = checkTotality(программа([длина]))
  assert.deepEqual(result.diagnostics, [])
  assert.equal(result.ok, true)
  assert.deepEqual([...result.total], ["Длина"])
})

test("хвост через встроенную форму, а не через образец, тоже убывает", () => {
  const result = checkTotality(программа([{
    name: "Сумма",
    total: true,
    params: [{ name: "э", type: список(число) }],
    returns: число,
    body: {
      kind: "if",
      cond: форма("пусто", пер("э")),
      then: лит(0),
      else: оп("add", форма("голова", пер("э")), вызов("Сумма", форма("хвост", пер("э")))),
    },
  }]))
  assert.deepEqual(result.diagnostics, [])
  assert.deepEqual([...result.total], ["Сумма"])
})

/*
 * Индексный доступ и доказательство завершения. Вопрос, ради которого форма
 * `элемент N в СПИСОК` вообще проверялась здесь: не даёт ли она удобной записи,
 * на которой ничего не доказывается. Ответ измерен тремя проверками, и все три
 * обязаны стоять вместе — поодиночке каждая подтверждала бы половину.
 *
 * 1. Элемент — ЧАСТЬ списка, каким бы номер ни был, поэтому рекурсия вглубь по
 *    любому элементу доказывается наравне с `голова`. Это усиление: раньше
 *    «взять третью ветвь» выражалось только обходом.
 * 2. Проход по номеру ВНИЗ доказывается числовой мерой — без единой правки в
 *    анализе: шаг постоянен, дно даёт `не больше 0`.
 * 3. Проход ВВЕРХ не доказывается, и это не новая дыра: `н плюс 1` растёт, и
 *    та же диагностика приходила бы и без индексного доступа.
 */
test("элемент по номеру — часть списка: рекурсия вглубь по нему доказывается", () => {
  const result = checkTotality(программа(
    [{
      name: "Первая глубина",
      total: true,
      params: [{ name: "д", type: имя("Дерево") }],
      returns: число,
      body: разбор(
        пер("д"),
        { pattern: { kind: "variant", name: "Лист", bind: { значение: "з" } }, body: лит(1) },
        {
          pattern: { kind: "variant", name: "Узел", bind: { ветви: "в" } },
          body: оп("add", лит(1), вызов("Первая глубина", форма("элемент", лит(1), пер("в")))),
        },
      ),
    }],
    [{
      kind: "sum",
      name: "Дерево",
      variants: [
        { name: "Лист", fields: [{ name: "значение", type: число }] },
        { name: "Узел", fields: [{ name: "ветви", type: список(имя("Дерево")) }] },
      ],
    }],
  ))
  assert.deepEqual(result.diagnostics, [])
  assert.deepEqual([...result.total], ["Первая глубина"])
})

test("проход по номеру вниз доказывается мерой, вверх — нет", () => {
  const вниз = parse(
    "модуль «Сумма»\n\nтотальная функция «Сумма до»\n  принимает элементы: список числа, н: число\n" +
      "  возвращает число\n  если н не больше 0\n    то 0\n" +
      "    иначе (элемент н в элементы) плюс «Сумма до» от элементы и (н минус 1)\n",
  )
  const доказано = checkTotality(вниз)
  assert.deepEqual(доказано.diagnostics, [])
  assert.ok(доказано.total.has("Сумма до"), "проход вниз обязан доказываться")

  const вверх = parse(
    "модуль «Сумма»\n\nтотальная функция «Сумма от»\n  принимает элементы: список числа, н: число\n" +
      "  возвращает число\n  если н больше (длина элементы)\n    то 0\n" +
      "    иначе (элемент н в элементы) плюс «Сумма от» от элементы и (н плюс 1)\n",
  )
  const отказ = checkTotality(вверх)
  assert.deepEqual(коды(отказ), ["FLANG_NOT_TOTAL"])
  assert.match(отказ.diagnostics[0].message, /увеличивает параметр «н»/u)
})

