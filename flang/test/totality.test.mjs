/*
 * До сегодня доказательство по мере было верно для вещественных чисел и ложно
 * на части double: `x минус 1` при большом |x| равен x, спуск не идёт, а
 * `тотальная` уже пообещала завершение. Дыру закрывает не отказ от меры и не
 * выдуманная верхняя граница, а сторож: анализ помечает вызов, чьё завершение
 * держится на мере (`markMeasureGuards`), понижение ставит на отмеченном
 * аргументе проверку убывания (`defunc.mjs`), и не убывшая мера даёт отказ
 * `FLANG_MEASURE` вместо вечного цикла.
 *
 * Проверяется здесь ровно то, ради чего сторож заведён: доказательство НЕ
 * ослабло (те же программы тотальны), отказ приходит на входах, где шаг ничего
 * не изменил, и НЕ приходит там, где спуск идёт — пусть и медленно. Совпадение
 * отказа с напечатанным кодом проверяется дифференциально в `emit-c.test.mjs`;
 * побайтовое совпадение обеих реализаций понижения — в `self-emit-c.test.mjs`.
 */

const СЧЁТ_ДО_НУЛЯ = `модуль «Счёт»

тотальная функция «До нуля»
  принимает н: число
  возвращает число
  если н не больше 0
    то 0
    иначе «До нуля» от (н минус 1)
`

/** Беда, которой отказал вычислитель. Без отказа — падение с внятным текстом. */
function отказ(работа) {
  try {
    работа()
  } catch (беда) {
    return беда
  }
  return assert.fail("вычисление не отказало, а должно было")
}

/** Сколько шагов вычислителя стоит спуск: число точное, а не «примерно». */
function шаговНа(программа, н) {
  let низ = 1
  let верх = 1_000_000
  while (низ < верх) {
    const середина = Math.floor((низ + верх) / 2)
    try {
      createRuntime(программа, { maxSteps: середина }).call("До нуля", { н })
      верх = середина
    } catch (беда) {
      if (беда.code !== "FLANG_RECURSION_LIMIT") throw беда
      низ = середина + 1
    }
  }
  return низ
}

test("сторож ставится только там, где доказательство держится на мере", () => {
  const мерой = checkTotality(parse(СЧЁТ_ДО_НУЛЯ))
  assert.deepEqual([...мерой.total], ["До нуля"])
  assert.equal(мерой.guards.length, 1)
  assert.equal(мерой.guards[0].param, "н")

  /* Структурное убывание самодостаточно: список — конечное дерево, и дна ему
     не надо. Сторожить там нечего, и лишний сторож стоил бы витка на каждом
     шаге всякого обхода списка в языке. */
  const частью = checkTotality(программа([длина]))
  assert.deepEqual(частью.guards, [])
})

test("отметка невидима для программ без числовой меры: тот же объект", () => {
  const без = программа([длина])
  assert.equal(markMeasureGuards(без), без)
  const с = parse(СЧЁТ_ДО_НУЛЯ)
  assert.notEqual(markMeasureGuards(с), с)
})

test("доказательство не ослабло: программа со сторожем считает то же самое", () => {
  const среда = createRuntime(markMeasureGuards(parse(СЧЁТ_ДО_НУЛЯ)))
  assert.equal(среда.call("До нуля", { н: 0 }), 0)
  assert.equal(среда.call("До нуля", { н: 7 }), 0)
  assert.equal(среда.call("До нуля", { н: -3 }), 0)
  assert.equal(среда.call("До нуля", { н: 2.5 }), 0)
})

test("на входах, где шаг ничего не меняет, вместо зацикливания — отказ", () => {
  const среда = createRuntime(markMeasureGuards(parse(СЧЁТ_ДО_НУЛЯ)), { maxSteps: 100_000 })
  /* 2⁵⁴ + 4: выше 2⁵⁴ соседние double отстоят на 4, и единица в промежуток не
     помещается вовсе. Само это утверждение о double проверяется ниже
     вычислением на самом языке, а не верой. */
  for (const н of [18014398509481988, 1e308, Infinity, NaN]) {
    const беда = отказ(() => среда.call("До нуля", { н }))
    assert.equal(беда.code, "FLANG_MEASURE", `на входе ${н} отказ пришёл не от сторожа`)
    assert.match(беда.message, /мера не убыла/u)
    /* Текст обязан называть место: без имени функции и параметра человеку
       негде искать, а сторож стоит не там, где написан исходник. */
    assert.match(беда.message, /«До нуля»/u)
    assert.match(беда.message, /«н»/u)
  }
})

test("медленный спуск — не то же самое, что бесконечный: сторож его пропускает", () => {
  /* Разница между «доказательство ложно» и «доказательство верно, но шагов
     много» — единственное, что сторож обязан различать. На 100 000 спуск идёт
     каждым витком, и упирается программа в лимит шагов, а не в сторожа. */
  const среда = createRuntime(markMeasureGuards(parse(СЧЁТ_ДО_НУЛЯ)), { maxSteps: 10_000 })
  const беда = отказ(() => среда.call("До нуля", { н: 100_000 }))
  assert.equal(беда.code, "FLANG_RECURSION_LIMIT")
})

test("цена сторожа: витку прибавляется постоянное число шагов, а не множитель", () => {
  const голая = parse(СЧЁТ_ДО_НУЛЯ)
  const стережённая = markMeasureGuards(голая)
  const десять = шаговНа(стережённая, 10) - шаговНа(голая, 10)
  const сотня = шаговНа(стережённая, 100) - шаговНа(голая, 100)
  /* Прибавка обязана расти линейно по числу витков и ни на что больше не
     влиять: 10 шагов на виток — `пусть`, сравнение и ветка. Заметный рост
     здесь означал бы, что сторож попал внутрь чего-то, что считается дважды. */
  assert.equal(десять / 10, сотня / 100)
  assert.equal(сотня / 100, 10)
})

test("«н минус 1» на большом числе действительно ничего не меняет — считает сам язык", () => {
  /* Утверждение про арифметику проверяется там, где она живёт. Пока оно верно,
     сторож нужен; станет ложным — сторож станет мёртвым кодом, и это будет
     видно отсюда, а не из рассуждения. */
  const убавить = parse("модуль «Точность»\n\nтотальная функция «Убавить»\n  принимает н: число\n  возвращает число\n  н минус 1\n")
  const среда = createRuntime(убавить, { maxSteps: 1_000 })
  assert.equal(среда.call("Убавить", { н: 18014398509481988 }), 18014398509481988)
  assert.equal(среда.call("Убавить", { н: 1e308 }), 1e308)
})
