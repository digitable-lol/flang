/**
 * Смешивать способы убывания в одном цикле нельзя: цепочка частей значения и
 * цепочка чисел — разные порядки, и «часть на одном ребре, число на другом» не
 * складывается ни в один из них. В типизированной программе такого не бывает,
 * поэтому случай собран руками — анализ типов не читает и полагаться на них
 * не вправе.
 */
test("часть на одном ребре и мера на другом общей позиции не образуют", () => {
  const result = checkTotality(программа([
    {
      name: "А", total: true, params: [{ name: "х", type: список(число) }], returns: число,
      body: разбор(пер("х"), пусто(лит(0)), голова_и_хвост("г", "хв", вызов("Б", пер("хв")))),
    },
    {
      name: "Б", total: true, params: [{ name: "х", type: число }], returns: число,
      body: {
        kind: "if",
        cond: оп("lte", пер("х"), лит(0)),
        then: лит(0),
        else: вызов("А", оп("sub", пер("х"), лит(1))),
      },
    },
  ]))
  assert.deepEqual(коды(result), ["FLANG_NOT_TOTAL"])
  assert.match(result.diagnostics[0].message, /нет аргумента, который убывает на каждом вызове/u)
  assert.deepEqual([...result.total], [])
})

