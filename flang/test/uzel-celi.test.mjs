/**
 * ПОЛНЫЙ УЗЕЛ на каждой цели, у которой есть хозяин: не слой связи, а узел
 * целиком.
 *
 * ── Чем это отличается от соседнего прогона ─────────────────────────────────
 *
 * `svyaz-vtoraya-cel.test.mjs` предъявил на цели python КОНЕЦ СВЯЗИ: сокет,
 * часы, два срока. Его автор честно оговорил, чего в нём нет: «Этот файл НЕ
 * узел. У узла есть таблица процессов и планировщик, и они на flang не
 * выражаются по названной причине». Оговорка была верной для своего дня и
 * перестала быть верной: планировщик и таблица процессов написаны на flang
 * (`flang/conc/planirovshchik.flang`) и печатаются во все восемь целей
 * (`flang/test/planirovshchik-celi.test.mjs`, 67 744 сверки).
 *
 * Здесь на каждой цели работает УЗЕЛ: он несёт свои процессы, ведёт их ящики,
 * выбирает, кого пробежать, зовёт обработчик, разбирает его отклик, шлёт письма
 * своим и чужим и принимает письма с провода.
 *
 * ── Что здесь считается доказательством ─────────────────────────────────────
 *
 * Не «форма заведена» и не «ответы сошлись», а РАБОТА:
 *
 *   1. рукопожатие сошлось у ОБОИХ концов (у одного оно не сходится молча);
 *   2. письмо, посланное процессом на узле новой цели, доехало до процесса на
 *      узле ОПОРЫ и ПОМЕНЯЛО ЕГО СОСТОЯНИЕ;
 *   3. ответ вернулся и поменял состояние процесса НА УЗЛЕ НОВОЙ ЦЕЛИ.
 *
 * Третье — то, чего у соседа быть не могло: чтобы ответ поменял состояние,
 * принявшей стороне нужен процесс, ящик и планировщик, а не только сокет.
 *
 * ── Почему опора теперь python, а не js ─────────────────────────────────────
 *
 * Вторым концом каждой пары до 20 августа 2026 был узел на JavaScript. Он
 * ввозил разбор, печать и ПЛАНИРОВЩИК из `flang/src/` — реализации компилятора
 * на JavaScript, удалённой со ствола (`fe8e8a37`, 48 файлов). С тех пор он не
 * поднимается, и прогон НИЧЕГО НЕ ИЗМЕРЯЛ: все пары пропускались.
 *
 * Опорой взята цель, у которой хозяин написан по-новому — зовёт напечатанный
 * `uzel-zamer.flang`, а не повторяет его. Это `python`: ей не нужен тулчейн
 * сборки, и она проверена тремя предшественниками.
 *
 * Цель `js` из счёта поэтому УБРАНА. Приписывать её себе, когда ни одной пары с
 * ней не состоялось, значило бы соврать числом; вернуть её можно ровно одним
 * способом — написав `flang/conc/bin/node.js` тем же приёмом, каким написаны
 * `node.py`, `node.go`, `node.cs` и `node.ex`.
 *
 * ── Мера ───────────────────────────────────────────────────────────────────
 *
 * Прогон печатает её сам: «полный узел на N целях из 8». N — это число целей,
 * у которых есть ХОЗЯИН и чья пара сошлась; решения печатаются во все восемь и
 * сверены отдельно (`flang/test/planirovshchik-celi.test.mjs`,
 * `flang/test/svyaz-celi.test.mjs`). Путать эти два числа нельзя: первое про
 * работу, второе про переносимость.
 *
 * Запуск: node --test flang/test/uzel-celi.test.mjs
 */
