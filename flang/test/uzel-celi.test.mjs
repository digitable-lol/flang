/**
 * ПОЛНЫЙ УЗЕЛ на каждой цели, у которой есть хозяин: не слой связи, а узел
 * целиком.
 *
 * ── Чем это отличается от соседнего прогона ─────────────────────────────────
 *
 * `svyaz-vtoraya-cel.test.mjs` предъявил на цели python КОНЕЦ СВЯЗИ: сокет,
 * часы, два срока. Его автор честно оговорил, чего в нём нет: «Этот файл НЕ
 * узел. У узла есть таблица процессов и планировщик, и они на flang не
 * выражаются по названной причине». Оговорка была верной для своего дня и
 * перестала быть верной: планировщик и таблица процессов написаны на flang
 * (`flang/conc/planirovshchik.flang`) и печатаются во все восемь целей
 * (`flang/test/planirovshchik-celi.test.mjs`, 67 744 сверки).
 *
 * Здесь на каждой цели работает УЗЕЛ: он несёт свои процессы, ведёт их ящики,
 * выбирает, кого пробежать, зовёт обработчик, разбирает его отклик, шлёт письма
 * своим и чужим и принимает письма с провода.
 *
 * ── Что здесь считается доказательством ─────────────────────────────────────
 *
 * Не «форма заведена» и не «ответы сошлись», а РАБОТА:
 *
 *   1. рукопожатие сошлось у ОБОИХ концов (у одного оно не сходится молча);
 *   2. письмо, посланное процессом на узле новой цели, доехало до процесса на
 *      узле ОПОРЫ и ПОМЕНЯЛО ЕГО СОСТОЯНИЕ;
 *   3. ответ вернулся и поменял состояние процесса НА УЗЛЕ НОВОЙ ЦЕЛИ.
 *
 * Третье — то, чего у соседа быть не могло: чтобы ответ поменял состояние,
 * принявшей стороне нужен процесс, ящик и планировщик, а не только сокет.
 *
 * ── Почему опора теперь python, а не js ─────────────────────────────────────
 *
 * Вторым концом каждой пары до 20 августа 2026 был узел на JavaScript. Он
 * ввозил разбор, печать и ПЛАНИРОВЩИК из `flang/src/` — реализации компилятора
 * на JavaScript, удалённой со ствола (`fe8e8a37`, 48 файлов). С тех пор он не
 * поднимается, и прогон НИЧЕГО НЕ ИЗМЕРЯЛ: все пары пропускались.
 *
 * Опорой взята цель, у которой хозяин написан по-новому — зовёт напечатанный
 * `uzel-zamer.flang`, а не повторяет его. Это `python`: ей не нужен тулчейн
 * сборки, и она проверена тремя предшественниками.
 *
 * Цель `js` вернулась в счёт НЕ починкой `node.mjs`, а вторым хозяином —
 * `flang/conc/bin/node.js`, писанным тем же приёмом, что `node.py`, `node.go`,
 * `node.cs` и `node.ex`: он зовёт напечатанный `uzel-zamer.flang`. Переписывать
 * планировщик и надзор на JavaScript заново было нельзя — они уже выражены на
 * flang, и второй текст о том же разошёлся бы молча.
 *
 * ── Мера ───────────────────────────────────────────────────────────────────
 *
 * Прогон печатает её сам: «полный узел на N целях из 8». N — это число целей,
 * у которых есть ХОЗЯИН и чья пара сошлась; решения печатаются во все восемь и
 * сверены отдельно (`flang/test/planirovshchik-celi.test.mjs`,
 * `flang/test/svyaz-celi.test.mjs`). Путать эти два числа нельзя: первое про
 * работу, второе про переносимость.
 *
 * Запуск: node --test flang/test/uzel-celi.test.mjs
 */
import assert from "node:assert/strict"
import { rmSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"

import { позвать } from "../scripts/dvoichnyy.mjs"
import { findExecutable, missingToolchain } from "./toolchain-guard.mjs"
import { рабочийКаталог } from "./tempdir.mjs"

import {
  ОПОРА,
  ЦЕЛИ,
  журнал,
  корень,
  мираВФайле,
  напечатаннаяПрограмма,
  новаяЗапись,
  поднятьУзел,
  собратьУзел,
} from "./uzel-osnastka.mjs"

const целейРаботает = []

for (const цель of ЦЕЛИ) {
 test(`узел на ${цель.имя} и узел на ${ОПОРА.имя} ведут ОДНУ программу через настоящий провод`, async (t) => {
  const чем = цель.ищем.map((это) => findExecutable(это)).find((это) => это !== null)
  if (чем === undefined || чем === null) {
    return missingToolchain(t, цель.тулчейн, `тулчейн «${цель.тулчейн}» не найден — пропуск`)
  }
  const чемОпора = ОПОРА.ищем.map((это) => findExecutable(это)).find((это) => это !== null)
  if (чемОпора === undefined || чемОпора === null) {
    return missingToolchain(t, ОПОРА.тулчейн, `тулчейн опоры «${ОПОРА.тулчейн}» не найден — сверять не с чем`)
  }

  const каталог = рабочийКаталог(`uzel-${цель.имя}`)
  const каталогОпоры = рабочийКаталог(`uzel-opora-${цель.имя}`)
  const узлы = []
  try {
    собратьУзел(каталог, цель)
    собратьУзел(каталогОпоры, ОПОРА)

    /* ── узел опоры, слушающий, несёт «Учётчика» ──────────────────────────── */
    const хэш = (await import("node:crypto")).createHash("sha256")
      .update(напечатаннаяПрограмма(каталог), "utf8").digest("hex")

    const опора = поднятьУзел(ОПОРА, чемОпора, каталогОпоры, [
      "--я", "учёт", "--слушать", "127.0.0.1:0", "--хэш", хэш,
      "--план-файл", "plan.json",
      "--размещение", JSON.stringify({ "Счётчик": "счёт", "Учётчик": "учёт" }),
      "--срок", "2000", "--пульс", "200", "--жить", "9",
    ], узлы)

    const поднят = await новаяЗапись(опора.записи, (з) => з.в === "поднят", 20_000)
      .catch((беда) => { throw new Error(`${беда.message}\nstderr опоры:\n${опора.ошибки.текст}`) })
    const порт = String(поднят.порт)
    assert.ok(Number(порт) > 0, `узел опоры не назвал порта: ${JSON.stringify(поднят)}`)
    /* Оба конца обязаны предъявить ОДИН хэш программы, иначе рукопожатие не
       сойдётся, и это правильно. Здесь же проверяется, что узел считает его так
       же, как прогон: началом того же sha256. */
    assert.equal(хэш.slice(0, 12), поднят.хэш, "хэш посчитан не так, как считает узел")

    /* ── узел новой цели, звонящий, несёт «Счётчика» ──────────────────────── */
    const вброс = [{ кому: "Счётчик", что: ["в", "замерить", { сколько: ["ч", 2] }] }]
    const новый = поднятьУзел(цель, чем, каталог, [
      "--я", "счёт", "--слушать", "127.0.0.1:0", "--хэш", хэш,
      "--план-файл", "plan.json",
      "--размещение", JSON.stringify({
        "Счётчик": "счёт", "Учётчик": "учёт", звонить: { "учёт": `127.0.0.1:${порт}` },
      }),
      "--вбросить", JSON.stringify(вброс),
      "--срок", "2000", "--пульс", "200", "--жить", "6",
    ], узлы)

    /* ПЕРВОЕ: рукопожатие сошлось у ОБОИХ. */
    const уНового = await новаяЗапись(новый.записи, (з) => з.в === "связь" && з.что === "заведена", 20_000)
      .catch((беда) => { throw new Error(`${беда.message}\nstderr ${цель.имя}:\n${новый.ошибки.текст}`) })
    assert.equal(уНового.цель, цель.имя)
    const уОпоры = await новаяЗапись(опора.записи, (з) => з.в === "связь" && з.что === "заведена" && з.сосед === "счёт", 20_000)
    assert.equal(уОпоры.узел, "учёт")

    /* ВТОРОЕ и ТРЕТЬЕ считаются по итогу обоих узлов. Начальное письмо легло в
       ящик «Счётчика» на новой цели, тот посчитал и доложил «Учётчику» — а
       «Учётчик» живёт на другом узле; ответ вернулся обратно. */
    await новаяЗапись(новый.записи, (з) => з.в === "пробег" && з.кто === "Счётчик", 20_000)

    /* ТРЕТЬЕ, и ради него всё: ОТВЕТ вернулся и поменял состояние процесса на
       узле новой цели. Чтобы это случилось, принявшей стороне нужен процесс,
       ящик и планировщик, а не только сокет, — вот этого у слоя связи и не было. */
    const конецНового = await новаяЗапись(новый.записи, (з) => з.в === "конец", 20_000)
      .catch((беда) => { throw new Error(`${беда.message}\nstderr ${цель.имя}:\n${новый.ошибки.текст}`) })
    /* Состояния узел отдаёт ЗАКОДИРОВАННЫМИ — теми же метками, какими они едут
       по проводу. Сверяется поэтому закодированное, а не «похожее»: подстрока
       здесь солгала бы, а `deepEqual` называет и число, и его метку. */
    assert.deepEqual(
      конецНового.состояния["Счётчик"],
      ["з", { "всего": ["ч", 2], "подтверждено": ["ч", 1] }],
      `ответ с узла опоры не поменял состояния «Счётчика»: ${JSON.stringify(конецНового.состояния)}`,
    )

    /* ВТОРОЕ: письмо ушло с узла новой цели и поменяло состояние процесса на
       узле опоры. */
    const конецОпоры = await новаяЗапись(опора.записи, (з) => з.в === "конец", 20_000)
      .catch((беда) => { throw new Error(`${беда.message}\nstderr опоры:\n${опора.ошибки.текст}`) })
    assert.deepEqual(
      конецОпоры.состояния["Учётчик"],
      ["з", { "строки": ["л", [["с", "2"]]] }],
      `письмо с узла на ${цель.имя} не доехало до процесса на опоре: ${JSON.stringify(конецОпоры.состояния)}`,
    )

    целейРаботает.push(цель.имя)
    console.log(`полный узел: ${цель.имя} ↔ ${ОПОРА.имя}, рукопожатие у обоих, письмо и ответ доехали`)
    console.log(`  хозяин ${цель.хозяин}: ${мираВФайле(join(корень, `flang/conc/bin/${цель.хозяин}`), цель.знак, цель.комментарии ?? [цель.знак])}`)
  } finally {
    for (const п of узлы) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }
    rmSync(каталог, { recursive: true, force: true })
    rmSync(каталогОпоры, { recursive: true, force: true })
  }
 })
}

test("начальные состояния узла и программы — одно и то же, а не два похожих", async () => {
  /* Функцию без аргументов позвать через ввоз нельзя (проверено: «имя «пустой
     счёт» не связано» и с ключом «только», и без него), поэтому два начальных
     состояния выписаны в `uzel-zamer.flang` ЗАНОВО. Два источника правды об
     одном расходятся молча — вот проверка, которая молчать не даёт. */
  /* Считает ДВОИЧНЫЙ: вычислителя на JavaScript в дереве больше нет.
     `flang run --function` отдаёт значение JSON-ом, и сверять надо его текст. */
  const посчитать = (путь, имя) => {
    const итог = позвать(["run", корень + путь, "--function", имя])
    assert.equal(итог.код, 0, `«${имя}» из «${путь}» не вычислилось:\n${итог.вывод}\n${итог.ошибки}`)
    return итог.вывод.trim()
  }
  const пары = [
    ["Начальный счёт", "пустой счёт"],
    ["Начальные записи", "пустые записи"],
  ]
  for (const [уУзла, уПрограммы] of пары) {
    const узел = посчитать("flang/conc/uzel-zamer.flang", уУзла)
    const программа = посчитать("flang/conc/examples/distributed.flang", уПрограммы)
    assert.equal(узел, программа, `«${уУзла}» узла разошлось с «${уПрограммы}» программы`)
  }
  console.log(`начальных состояний сверено ${пары.length}, расхождений 0`)
})

test.after(() => {
  /* Опора считается работающей без отдельной пары: она — второй конец каждой
     пары выше, и без её работы ни одна пара не сошлась бы. Ровно поэтому её
     нельзя приписывать себе, когда пар НЕ БЫЛО. */
  if (целейРаботает.length === 0) {
    console.log("ПОЛНЫЙ УЗЕЛ: НЕ ИЗМЕРЕНО — ни одна пара не сошлась")
    return
  }
  const всего = целейРаботает.length + 1
  console.log(`ПОЛНЫЙ УЗЕЛ РАБОТАЕТ НА ${всего} ЦЕЛЯХ ИЗ 8: ${ОПОРА.имя}, ${целейРаботает.join(", ")}`)
  console.log("решения при этом печатаются во все восемь — это другое число и другой прогон")
})
