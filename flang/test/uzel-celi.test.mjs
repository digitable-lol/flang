/** Строки журнала процесса, разобранные как JSON, по мере прихода. */
function журнал(процесс, накаждую) {
  let хвост = ""
  процесс.stdout.setEncoding("utf8")
  процесс.stdout.on("data", (кусок) => {
    хвост += кусок
    let край = хвост.indexOf("\n")
    while (край >= 0) {
      const строка = хвост.slice(0, край).trim()
      хвост = хвост.slice(край + 1)
      if (строка !== "") {
        try { накаждую(JSON.parse(строка)) } catch { /* не наша строка */ }
      }
      край = хвост.indexOf("\n")
    }
  })
}

function новаяЗапись(записи, подходит, срок) {
  return new Promise((готово, отказ) => {
    const край = Date.now() + срок
    const смотреть = () => {
      const это = записи.find(подходит)
      if (это !== undefined) { готово(это); return }
      if (Date.now() > край) {
        отказ(new Error(`не дождались записи за ${срок} мс; было: ${JSON.stringify(записи.slice(-8))}`))
        return
      }
      setTimeout(смотреть, 25)
    }
    смотреть()
  })
}

/** Напечатанная в JavaScript программа примера — то, по чему считается хэш
 *  рукопожатия. Печать здесь нужна не ради цели js, а ради ОДНОГО ЧИСЛА,
 *  которое обе стороны обязаны предъявить друг другу: разные программы говорить
 *  не должны. */
function напечатаннаяПрограмма(каталог) {
  const куда = join(каталог, "программа-js")
  const печать = позвать(["emit", "flang/conc/examples/distributed.flang", "--target", "js", "--out", куда])
  assert.equal(печать.код, 0, `печать программы в js отказала:\n${печать.вывод}\n${печать.ошибки}`)
  const имя = globSync("*.js", { cwd: куда }).find((ф) => !ф.startsWith("flang_cli"))
  assert.ok(имя !== undefined, "печать программы не отдала модуля")
  return readFileSync(join(куда, имя), "utf8")
}

/** Напечатать узел в цель, положить рядом хозяина и собрать. */
function собратьУзел(каталог, цель) {
  const среда = средаСборки(каталог, { LC_ALL: "C.UTF-8" })
  const печать = позвать(["emit", "flang/conc/uzel-zamer.flang", "--target", цель.имя, "--out", каталог])
  assert.equal(печать.код, 0, `печать узла в ${цель.имя} отказала:\n${печать.вывод}\n${печать.ошибки}`)

  const собрать = цель.собрать === null ? null : цель.собрать(каталог)
  const куда = собрать === null ? каталог : join(каталог, собрать[2] ?? ".")
  mkdirSync(куда, { recursive: true })
  copyFileSync(join(корень, `flang/conc/bin/${цель.хозяин}`), join(куда, цель.хозяин))
  writeFileSync(join(каталог, "plan.json"), JSON.stringify(ПЛАН), "utf8")

  if (собрать !== null) {
    const итог = spawnSync(собрать[0], собрать[1], {
      cwd: каталог, encoding: "utf8", env: среда, maxBuffer: 256 * 1024 * 1024, timeout: 900_000,
    })
    assert.equal(итог.status, 0, `тулчейн ${цель.имя} не собрал узел:\n${итог.stdout}\n${итог.stderr}`)
  }
  return каталог
}

/** Поднять узел цели: собранный каталог, доводы, журнал и поток ошибок. */
function поднятьУзел(цель, чем, каталог, доводы, узлы) {
  const [чемЗвать, свои] = цель.запуск(каталог, чем)
  const процесс = spawn(чемЗвать, [...свои, ...доводы], {
    cwd: каталог,
    env: средаСборки(каталог, { LC_ALL: "C.UTF-8", ...цель.среда }),
    stdio: ["pipe", "pipe", "pipe"],
  })
  узлы.push(процесс)
  const записи = []
  журнал(процесс, (з) => записи.push(з))
  процесс.stderr.setEncoding("utf8")
  const ошибки = { текст: "" }
  процесс.stderr.on("data", (к) => { ошибки.текст += к })
  return { процесс, записи, ошибки }
}

