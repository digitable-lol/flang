/** Сколько строк хозяина трогают мир — байт в байт тот же текст, что раньше. */
export function мираВФайле(путь, знак, комментарии = [знак]) {
  const итог = прогнатьПлан("uzel-osnastka.flang", "Счёт мира", { путь, знак, комментарии })
  return итог.текст
}
