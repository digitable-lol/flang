/**
 * ПОЛНЫЙ УЗЕЛ на второй цели печати: не слой связи, а узел целиком.
 *
 * ── Чем это отличается от соседнего прогона ─────────────────────────────────
 *
 * `svyaz-vtoraya-cel.test.mjs` предъявил на цели python КОНЕЦ СВЯЗИ: сокет,
 * часы, два срока. Его автор честно оговорил, чего в нём нет: «Этот файл НЕ
 * узел. У узла есть таблица процессов и планировщик, и они на flang не
 * выражаются по названной причине». Оговорка была верной для своего дня и
 * перестала быть верной: планировщик и таблица процессов написаны на flang
 * (`flang/conc/planirovshchik.flang`) и печатаются во все восемь целей
 * (`flang/test/planirovshchik-celi.test.mjs`, 67 744 сверки).
 *
 * Здесь на второй цели работает УЗЕЛ: он несёт свои процессы, ведёт их ящики,
 * выбирает, кого пробежать, зовёт обработчик, разбирает его отклик, шлёт письма
 * своим и чужим и принимает письма с провода.
 *
 * ── Что здесь считается доказательством ─────────────────────────────────────
 *
 * Не «форма заведена» и не «ответы сошлись», а РАБОТА:
 *
 *   1. рукопожатие сошлось у ОБОИХ концов (у одного оно не сходится молча);
 *   2. письмо, посланное процессом на узле Python, доехало до процесса на узле
 *      JavaScript и ПОМЕНЯЛО ЕГО СОСТОЯНИЕ;
 *   3. ответ вернулся и поменял состояние процесса НА УЗЛЕ PYTHON.
 *
 * Третье — то, чего у соседа быть не могло: чтобы ответ поменял состояние,
 * принявшей стороне нужен процесс, ящик и планировщик, а не только сокет.
 *
 * ── Чего этот прогон НЕ доказывает ──────────────────────────────────────────
 *
 * Надзора у узла на Python нет: отказ процесса доезжает до журнала и там
 * остаётся. Это названо в шапке `flang/conc/bin/node.py`, а не спрятано.
 *
 * Запуск: node --test flang/test/uzel-vtoraya-cel.test.mjs
 */
import assert from "node:assert/strict"
import { spawn, spawnSync } from "node:child_process"
import { copyFileSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { findExecutable } from "../src/toolchain.mjs"
import { missingToolchain } from "./toolchain-guard.mjs"
import { рабочийКаталог, средаСборки } from "./tempdir.mjs"

const корень = fileURLToPath(new URL("../../", import.meta.url))
const питон = findExecutable("python3") ?? findExecutable("python")

/** План узла: имя процесса → начальное состояние и обработчик, оба ИМЕНАМИ.
 *
 * Именами, а не значениями, потому что вызвать функцию по имени, приехавшему
 * строкой, может только хозяин: это та же граница языка, из-за которой цикл
 * поручений принадлежит хозяину. План — данные узла, ровно как размещение. */
const ПЛАН = {
  процессы: [
    { имя: "Счётчик", начальное: "Начальный счёт", обработчик: "Обработчик счёта", ящик: null },
    { имя: "Учётчик", начальное: "Начальные записи", обработчик: "Обработчик учёта", ящик: null },
  ],
}

/** Строки журнала процесса, разобранные как JSON, по мере прихода. */
function журнал(процесс, накаждую) {
  let хвост = ""
  процесс.stdout.setEncoding("utf8")
  процесс.stdout.on("data", (кусок) => {
    хвост += кусок
    let край = хвост.indexOf("\n")
    while (край >= 0) {
      const строка = хвост.slice(0, край).trim()
      хвост = хвост.slice(край + 1)
      if (строка !== "") {
        try { накаждую(JSON.parse(строка)) } catch { /* не наша строка */ }
      }
      край = хвост.indexOf("\n")
    }
  })
}

function новаяЗапись(записи, подходит, срок) {
  return new Promise((готово, отказ) => {
    const край = Date.now() + срок
    const смотреть = () => {
      const это = записи.find(подходит)
      if (это !== undefined) { готово(это); return }
      if (Date.now() > край) {
        отказ(new Error(`не дождались записи за ${срок} мс; было: ${JSON.stringify(записи.slice(-8))}`))
        return
      }
      setTimeout(смотреть, 25)
    }
    смотреть()
  })
}

/** Напечатать узел в цель и положить рядом хозяина. Возвращает каталог. */
function собратьУзел(каталог, цель, хозяин) {
  const печать = spawnSync(process.execPath, [
    join(корень, "flang/bin/flang.mjs"), "emit", "flang/conc/uzel-zamer.flang", "--target", цель, "--out", каталог,
  ], { cwd: корень, encoding: "utf8", env: средаСборки(каталог, { LC_ALL: "C.UTF-8" }), maxBuffer: 256 * 1024 * 1024 })
  assert.equal(печать.status, 0, `печать узла в ${цель} отказала:\n${печать.stdout}\n${печать.stderr}`)
  copyFileSync(join(корень, `flang/conc/bin/${хозяин}`), join(каталог, хозяин))
  writeFileSync(join(каталог, "plan.json"), JSON.stringify(ПЛАН), "utf8")
  return каталог
}

test("узел на Python и узел на JavaScript ведут ОДНУ программу через настоящий провод", async (t) => {
  if (питон === null) return missingToolchain(t, "python", "python не найден — пропуск")

  const каталог = рабочийКаталог("uzel-vtoraya-cel")
  const узлы = []
  try {
    собратьУзел(каталог, "python", "node.py")

    /* ── узел на JavaScript, слушающий, несёт «Учётчика» ─────────────────── */
    const записи = []
    const узел = spawn(process.execPath, [
      join(корень, "flang/conc/bin/node.mjs"),
      "--размещение", "flang/conc/examples/distributed.json",
      "--я", "учёт", "--слушать", "127.0.0.1:0",
      "--срок", "2000", "--пульс", "200",
    ], { cwd: корень, env: { ...process.env, LC_ALL: "C.UTF-8" }, stdio: ["pipe", "pipe", "pipe"] })
    узлы.push(узел)
    журнал(узел, (з) => записи.push(з))

    const поднят = await новаяЗапись(записи, (з) => з.в === "поднят", 20_000)
    const порт = поднят.адрес.split(":").pop()
    assert.ok(Number(порт) > 0, `узел не назвал порта: ${JSON.stringify(поднят)}`)

    /* Хэш программы — тем же способом, каким его считает узел: sha256
       напечатанного модуля. Оба конца обязаны предъявить один, иначе
       рукопожатие не сойдётся, и это правильно: разные программы говорить не
       должны. */
    const { createHash } = await import("node:crypto")
    const { emitJs } = await import("../src/emit/js.mjs")
    const { parse } = await import("../src/parser.mjs")
    const { linkProgram } = await import("../src/link.mjs")
    const путьПрограммы = "flang/conc/examples/distributed.flang"
    const { diagnostics: _, ...программа } = await linkProgram(
      корень + путьПрограммы, readFileSync(корень + путьПрограммы, "utf8"), parse,
    )
    const хэш = createHash("sha256").update(emitJs(программа).files[0].content, "utf8").digest("hex")
    assert.equal(хэш.slice(0, 12), поднят.хэш, "хэш посчитан не так, как считает узел")

    /* ── узел на Python, звонящий, несёт «Счётчика» ──────────────────────── */
    const питонЗаписи = []
    const вброс = [{ кому: "Счётчик", что: ["в", "замерить", { сколько: ["ч", 2] }] }]
    const питонУзел = spawn(питон, [
      "-B", "node.py",
      "--я", "счёт", "--слушать", "127.0.0.1:0", "--хэш", хэш,
      "--план-файл", "plan.json",
      "--размещение", JSON.stringify({
        "Счётчик": "счёт", "Учётчик": "учёт", звонить: { "учёт": `127.0.0.1:${порт}` },
      }),
      "--вбросить", JSON.stringify(вброс),
      "--срок", "2000", "--пульс", "200", "--жить", "6",
    ], {
      cwd: каталог,
      env: средаСборки(каталог, { LC_ALL: "C.UTF-8", PYTHONIOENCODING: "utf-8" }),
      stdio: ["pipe", "pipe", "pipe"],
    })
    узлы.push(питонУзел)
    журнал(питонУзел, (з) => питонЗаписи.push(з))
    питонУзел.stderr.setEncoding("utf8")
    let питонОшибки = ""
    питонУзел.stderr.on("data", (к) => { питонОшибки += к })

    /* ПЕРВОЕ: рукопожатие сошлось у ОБОИХ. */
    const уПитона = await новаяЗапись(питонЗаписи, (з) => з.в === "связь" && з.что === "заведена", 20_000)
      .catch((беда) => { throw new Error(`${беда.message}\nstderr питона:\n${питонОшибки}`) })
    assert.equal(уПитона.цель, "python")
    const уУзла = await новаяЗапись(записи, (з) => з.в === "связь" && з.что === "заведена" && з.сосед === "счёт", 20_000)
    assert.equal(уУзла.узел, "учёт")

    /* ВТОРОЕ: письмо ушло с узла на Python и поменяло состояние процесса на
       узле JavaScript. Начальное письмо легло в ящик «Счётчика» на Python, тот
       посчитал и доложил «Учётчику» — а «Учётчик» живёт на другой цели. */
    await новаяЗапись(питонЗаписи, (з) => з.в === "пробег" && з.кто === "Счётчик", 20_000)
    await new Promise((готово) => setTimeout(готово, 800))
    узел.stdin.write(`${JSON.stringify({ в: "состояния", метка: "после письма" })}\n`)
    const состояния = await новаяЗапись(записи, (з) => з.в === "состояния", 20_000)
    const учётчик = состояния.это["Учётчик"]
    assert.notEqual(учётчик, undefined, "узел на JavaScript не отдал состояния «Учётчика»")
    /* Состояния узел отдаёт ЗАКОДИРОВАННЫМИ — теми же метками, какими они едут
       по проводу. Сверяется поэтому закодированное, а не «похожее»: подстрока
       здесь солгала бы, а `deepEqual` называет и число, и его метку. */
    assert.deepEqual(
      учётчик.состояние,
      ["з", { "строки": ["л", [["с", "2"]]] }],
      `письмо с узла на Python не доехало до процесса на JavaScript: ${JSON.stringify(учётчик.состояние)}`,
    )

    /* ТРЕТЬЕ, и ради него всё: ОТВЕТ вернулся и поменял состояние процесса на
       узле Python. Чтобы это случилось, принявшей стороне нужен процесс, ящик и
       планировщик, а не только сокет, — вот этого у слоя связи и не было. */
    const конец = await новаяЗапись(питонЗаписи, (з) => з.в === "конец", 20_000)
    assert.deepEqual(
      конец.состояния["Счётчик"],
      ["з", { "всего": ["ч", 2], "подтверждено": ["ч", 1] }],
      `ответ с узла на JavaScript не поменял состояния «Счётчика»: ${JSON.stringify(конец.состояния)}`,
    )

    console.log("полный узел на двух целях: python ↔ js, рукопожатие у обоих, письмо и ответ доехали")
    console.log(`узел на Python: ${мираВФайле(join(корень, "flang/conc/bin/node.py"))}`)
  } finally {
    for (const п of узлы) { try { п.kill("SIGKILL") } catch { /* уже умер */ } }
    rmSync(каталог, { recursive: true, force: true })
  }
})

/** Сколько строк хозяина трогают мир. Считается по пометке, а не на глаз: в
 *  `node.py` каждая такая строка помечена комментарием «# МИР», и пометка эта
 *  проверяемая — снимите её с настоящего вызова, и число здесь соврёт заметно. */
function мираВФайле(путь) {
  const строки = readFileSync(путь, "utf8").split("\n")
  const кода = строки.filter((это) => это.trim() !== "" && !это.trim().startsWith("#")).length
  const мира = строки.filter((это) => это.includes("# МИР")).length
  return `${строки.length} строк, ${кода} кода, мира ${мира}`
}

test("начальные состояния узла и программы — одно и то же, а не два похожих", async () => {
  /* Функцию без аргументов позвать через ввоз нельзя (проверено: «имя «пустой
     счёт» не связано» и с ключом «только», и без него), поэтому два начальных
     состояния выписаны в `uzel-zamer.flang` ЗАНОВО. Два источника правды об
     одном расходятся молча — вот проверка, которая молчать не даёт. */
  const { readFileSync: читать } = await import("node:fs")
  const { parse } = await import("../src/parser.mjs")
  const { linkProgram } = await import("../src/link.mjs")
  const { evaluate } = await import("../src/interpret.mjs")

  const посчитать = async (путь, имя) => {
    const { diagnostics: _, ...программа } = await linkProgram(корень + путь, читать(корень + путь, "utf8"), parse)
    return JSON.stringify(evaluate(программа, имя, {}).value)
  }
  const пары = [
    ["Начальный счёт", "пустой счёт"],
    ["Начальные записи", "пустые записи"],
  ]
  for (const [уУзла, уПрограммы] of пары) {
    const узел = await посчитать("flang/conc/uzel-zamer.flang", уУзла)
    const программа = await посчитать("flang/conc/examples/distributed.flang", уПрограммы)
    assert.equal(узел, программа, `«${уУзла}» узла разошлось с «${уПрограммы}» программы`)
  }
  console.log(`начальных состояний сверено ${пары.length}, расхождений 0`)
})
