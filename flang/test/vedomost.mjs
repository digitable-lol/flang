/**
 * ВЕДОМОСТЬ ДЛЯ ПРОВЕРОК — та же дверь, какой её зовёт рабочий путь.
 *
 * ── Что случилось с эталоном ────────────────────────────────────────────────
 *
 * `flang/src/proof.mjs` — ведомость доказательства, написанная на JavaScript, —
 * стёрт. Слой на flang (`flang/self/proof.flang`) считал её в рабочем пути с
 * 16 августа, сверенный побайтово на всех 226 программах дерева; эталон при
 * этом продолжал лежать в поставке и продолжал отвечать шестнадцати
 * потребителям — тринадцати проверкам и трём скриптам. Пока он там лежал,
 * «эталон языка — компилятор на самом языке» было верно про одну команду и
 * неверно про дерево.
 *
 * ── Почему дверь, а не переписывание каждой проверки ────────────────────────
 *
 * У эталона были две функции с синхронными подписями:
 *
 *   `proofLedger(программа, итоги)`       → ведомость значением
 *   `formatProofLedger(ведомость)`        → текст человеку
 *
 * Тринадцать проверок звали их шестьюдесятью вызовами. Переписать каждый вызов
 * значило бы ТРОНУТЬ шестьдесят мест и потерять право сказать «проверки те же»:
 * покрасневшая после такого проверка не отличима от проверки, сломанной
 * переписыванием. Здесь подписи повторены знак в знак, и в каждом файле
 * меняется РОВНО ОДНА строка — путь ввоза. Всё, что проверки утверждали про
 * эталон, они теперь утверждают про близнеца, ни строкой утверждения не
 * изменившись.
 *
 * ── Чем это отличается от старой сверки ─────────────────────────────────────
 *
 * Отличается сильно, и умалчивать об этом нельзя. Раньше проверки вроде
 * `zakon-*.test.mjs` спрашивали ведомость у ЭТАЛОНА, а `self-proof.test.mjs`
 * отдельно сличал близнеца с эталоном на 226 программах. Теперь ведомость
 * везде одна, и второй реализации, с которой её сличать, в дереве нет. Что
 * осталось свидетелем и чего это стоило — сказано в
 * `flang/test/self-proof.test.mjs`.
 *
 * ── Почему слой связывается здесь один раз ──────────────────────────────────
 *
 * Связывание близнеца стоит около полусекунды, и делать его на каждый вызов
 * значило бы утроить время всех тринадцати проверок. Слой берётся один на
 * процесс — ровно так же, как его берёт `flang/src/self.mjs` в рабочем пути.
 */
import { ведомостьСлоем, слойВедомости } from "../src/self.mjs"

/** Слой на flang, связанный один раз на процесс. */
const слой = await слойВедомости()

/**
 * Текст человеку — по значению ведомости, которое вернул `proofLedger`.
 *
 * Считает его слой, и считает по СВОЕЙ записи, а не по этому значению: у него
 * внутри запись богаче — в ней есть то, что в машинный вид не попадает. Поэтому
 * текст запоминается рядом со значением в момент сборки, а не пересчитывается
 * из него потом. Таблица слабая: значение, до которого никому нет дела,
 * уносит с собой и текст.
 */
const тексты = new WeakMap()

/**
 * Ведомость значением — тем же ответом и той же подписью, что у стёртого
 * `proofLedger` эталона.
 */
export function proofLedger(программа, результаты) {
  const всё = ведомостьСлоем(слой, программа, результаты)
  тексты.set(всё.значением, всё.словами)
  return всё.значением
}

/**
 * Ведомость словами — той же подписью, что у стёртого `formatProofLedger`.
 *
 * Аргументом принимается ровно то, что вернул `proofLedger`. Собранная руками
 * запись сюда не приходила никогда — все шестьдесят вызовов эталона кормили её
 * его же ответом, — и если придёт, это не молчаливый промах: текста для неё нет,
 * и вызов сорвётся с внятными словами вместо того, чтобы вернуть пустую строку
 * и позеленить проверку ни на чём.
 */
export function formatProofLedger(ведомость) {
  const текст = тексты.get(ведомость)
  if (текст === undefined) {
    throw new Error(
      "`formatProofLedger` позвали не с ответом `proofLedger`: слой печатает текст по своей записи, " +
        "и собрать его из чужого значения нечем — соберите ведомость через `proofLedger`",
    )
  }
  return текст
}
