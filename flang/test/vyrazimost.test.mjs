/* 5. Четвёртая дыра НЕ закрыта, и это сказано прогоном                */
/* ================================================================== */

test("ОСТАЛОСЬ НЕВЫРАЗИМЫМ: равенства на параметре типа по-прежнему нет", async () => {
  /* Не забыто и не спрятано: у значения параметрического типа сравнивать
     нечем, и это НЕ дыра разбора, которую можно занять, — это новое понятие в
     системе типов (какие типы сравнимы и чем), то есть решение владельца языка.
     Утверждение стоит здесь, чтобы день, когда оно покраснеет, был замечен. */
  const текст = await отказ(`модуль «Запасное»

тип «Возможно» от «А»
  вариант «Есть» содержит значение: «А»
  вариант «Нет»

тотальная функция «Значение или запасное» от «А»
  принимает опция: «Возможно» от «А», запасное: «А»
  возвращает «А»
  для всех опция обеспечивает «на нет отдаётся запасное» результат равен запасное
  разбор опция
    случай вариант «Есть» с значение как зн
      то зн
    случай «Нет»
      то запасное
`)
  assert.match(текст, /сравнивать на равенство можно только скаляры, а не «А»/)
})
