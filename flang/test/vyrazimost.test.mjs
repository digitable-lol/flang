/**
 * ВЫРАЗИМОСТЬ: правда, которую на языке НЕ БЫЛО ЧЕМ записать.
 *
 * ── Улика ДО, числом ────────────────────────────────────────────────────────
 *
 * Замер цены доказательства (`docs/benchmark-proof-cost-2.md`) разложил
 * восемнадцать неудач по названной причине отказа и отделил особый разряд:
 * **«на языке не выразить» — 4 случая из 20**. Это не «ядро не берёт»: тут
 * утверждение даже не доходило до ядра, потому что записать его было нечем, и
 * вместо правды в файлы замера вписаны заглушки вроде «длина ключа
 * неотрицательна», которые верны про любую функцию той же подписи.
 *
 * Три дыры из четырёх закрыты, и каждая — ФОРМОЙ, КОТОРУЮ РАЗБОР ПРЕЖДЕ
 * ОТВЕРГАЛ, то есть без единого нового слова в языке:
 *
 *   1. `дано число: число` не вводило переменную. Имя, совпавшее со словом
 *      языка, приезжает токеном `keyword`, а разбор теоремы спрашивал `atName`.
 *      Отказ был: `FLANG_UNKNOWN_NAME: имя «число» не связано`.
 *
 *   2. Проверки варианта выражением не было вовсе. Отказ был:
 *      `FLANG_PARSE: ожидался знак ')'`. Заведена запись
 *      `<выражение> это вариант «Имя»` — `это` и `вариант` ключевые давно.
 *
 *   3. Поле суммы из выражения. Отказ был: `FLANG_TYPE: доступ к полю «ключ»
 *      требует записи, а не «Связь»`. Разрешено у суммы ИЗ ОДНОГО ВАРИАНТА, где
 *      взятие поля тотально.
 *
 * Четвёртая — равенство на параметре типа — НЕ закрыта, и почему, сказано в
 * последнем утверждении этого файла.
 *
 * ── Что здесь проверяется, и чего здесь НЕ проверяется ──────────────────────
 *
 * Проверяется, что правда записывается И ДОКАЗЫВАЕТСЯ обо всех входах, а не
 * только «разбирается». Разобранное, но недоказуемое утверждение — половина
 * работы, и мерить её как целую значило бы польстить себе.
 *
 * На каждую форму стоит ПОДДЕЛКА: программа, пытающаяся сказать этой формой
 * ложь, обязана быть отвергнута, и отказ обязан её НАЗВАТЬ, а не промолчать.
 *
 * Запуск: node --test flang/test/vyrazimost.test.mjs
 */
import assert from "node:assert/strict"
import test from "node:test"

import { externalChecks, loadProgramFromSource } from "../bin/flang.mjs"
import { runExamples } from "../src/compat.mjs"
import { parse } from "../src/parser.mjs"
import { obligations } from "../src/obligations.mjs"
import { АКСИОМЫ, checkProofs } from "../src/proofterm.mjs"

/** Обязательства и вердикты ядра — тем же путём, каким их считает оболочка. */
async function разобрать(исходник, имя = "выразимость.flang") {
  const программа = await loadProgramFromSource(исходник, имя)
  const внешнее = await externalChecks(программа)
  const об = obligations(программа, внешнее.results)
  const ядро = checkProofs(программа, об.obligations)
  return { программа, внешнее, об, ядро }
}

const вердикт = (об, имя) =>
  об.obligations.find((о) => о.kind === "postcondition" && о.name === имя)?.discharge ?? null

/** Все беды прогона одной строкой: отказ обязан НАЗЫВАТЬ, и это тут читается. */
const беды = ({ внешнее, ядро }) =>
  [...внешнее.diagnostics, ...ядро.diagnostics].map((б) => `${б.code}: ${б.message}`).join("\n")

/**
 * Что скажет ПРОГОН примеров.
 *
 * Постусловие, которое ядро не доказало, считается при работе после каждого
 * возврата, и ложь ловится именно тут — а не проверкой типов, которой ложь
 * типизируется прекрасно. `externalChecks` примеров не запускает, поэтому
 * подделке нужен отдельный прогон.
 */
async function прогонПримеров(исходник) {
  const программа = await loadProgramFromSource(исходник, "подделка.flang")
  return runExamples(программа).results
    .map((и) => `${и.function}/${и.example}: ${и.passed ? "прошёл" : "красный"} ${и.code ?? ""} ${и.error ?? ""}`)
    .join("\n")
}

/** Отказ разбора или типов на программе, которая не должна проходить вовсе. */
async function отказ(исходник) {
  try {
    const итог = await разобрать(исходник)
    return беды(итог)
  } catch (беда) {
    return (беда.diagnostics ?? []).map((б) => `${б.code}: ${б.message}`).join("\n") || String(беда.message)
  }
}

/* ================================================================== */
/* 1. `дано <имя>: <тип>`, где имя совпало со словом языка             */
/* ================================================================== */

const ЧЁТНОЕ = `модуль «Чётное»

тотальная функция «Чётное»
  принимает число: число
  возвращает признак
  для всех число обеспечивает «чётность есть делимость на два» результат равен («Делится на» от число и 2)
  (число остаток от 2) равен 0

тотальная функция «Делится на»
  принимает делимое: число, делитель: число
  возвращает признак
  (делимое остаток от делитель) равен 0

теорема «чётность есть делимость на два»
  дано число: число
  утверждаем результат равен («Делится на» от число и 2)
  следовательно доказано
`

test("ИМЯ СО СЛОВОМ ЯЗЫКА: `дано число: число` вводит переменную теоремы", () => {
  const дерево = parse(ЧЁТНОЕ, "чётное.flang")
  const теорема = (дерево.theorems ?? []).find((т) => т.name === "чётность есть делимость на два")
  assert.notEqual(теорема, undefined, "теорема обязана разобраться")
  assert.deepEqual((теорема.vars ?? []).map((п) => п.name), ["число"],
    "переменная теоремы обязана называться «число» — до правки её не было вовсе")
  assert.equal(теорема.vars[0].type.kind, "number", "и приезжать с объявленным типом")
})

test("ИМЯ СО СЛОВОМ ЯЗЫКА: обычное имя разбирается ровно так же", () => {
  /* Правка не завела второго поведения для второго рода имён: `дано х: число`
     и `дано число: число` дают один и тот же узел, отличающийся только именем.
     Без этого утверждения расширение могло бы чинить один случай и ломать
     соседний молча. */
  const обычное = parse(`модуль «Чётное»

тотальная функция «Чётное»
  принимает х: число
  возвращает признак
  для всех х обеспечивает «чётность есть делимость на два» результат равен («Делится на» от х и 2)
  (х остаток от 2) равен 0

тотальная функция «Делится на»
  принимает делимое: число, делитель: число
  возвращает признак
  (делимое остаток от делитель) равен 0

теорема «чётность есть делимость на два»
  дано х: число
  утверждаем результат равен («Делится на» от х и 2)
  следовательно доказано
`, "обычное.flang")
  const переменные = обычное.theorems[0].vars
  assert.deepEqual(переменные.map((п) => п.name), ["х"])
  assert.equal(переменные[0].type.kind, "number")
})

test("ПОДДЕЛКА к имени со словом языка: тип переменной сверяется и назван", async () => {
  const текст = await отказ(ЧЁТНОЕ.replace("дано число: число", "дано число: строка"))
  assert.match(текст, /FLANG_PROOF_VAR_TYPE/)
  assert.match(текст, /вводит «число» как строка/)
  assert.match(текст, /этот параметр объявлен как число/)
})

/* ================================================================== */
/* 2. Проверка варианта выражением: `<выражение> это вариант «Имя»`    */
/* ================================================================== */

const УСПЕШНО = `модуль «Успешно»

тип «Результат» от «Значение» и «Беда»
  вариант «Успех» содержит значение: «Значение»
  вариант «Ошибка» содержит сообщение: «Беда»

тотальная функция «Успешно» от «Значение» и «Беда»
  принимает итог: «Результат» от «Значение» и «Беда»
  возвращает признак
  для всех итог обеспечивает «да ровно на успехе» результат равен (итог это вариант «Успех»)
  разбор итог
    случай вариант «Успех» с значение как зн
      то да
    случай вариант «Ошибка» с сообщение как текст
      то нет
`

test("ВАРИАНТ ВЫРАЖЕНИЕМ: это `разбор`, а не новый вид узла и не встроенная форма", () => {
  const дерево = parse(УСПЕШНО, "успешно.flang")
  const условие = дерево.functions[0].postconditions[0].expr.right
  assert.equal(условие.kind, "match", "новых видов узла заводить не нужно и не заведено")
  assert.deepEqual(условие.cases.map((с) => с.pattern.kind), ["variant", "any"])
  assert.equal(условие.cases[0].pattern.name, "Успех")
  assert.deepEqual(условие.cases.map((с) => с.body.value), [true, false])
})

test("ВАРИАНТ ВЫРАЖЕНИЕМ: полная правда о функции доказана обо ВСЕХ входах", async () => {
  const итог = await разобрать(УСПЕШНО)
  const д = вердикт(итог.об, "да ровно на успехе")
  assert.equal(д?.verdict, "доказано", беды(итог))
  assert.equal(д.by, "cases", "несёт это принцип индукции по объявленной сумме")
  assert.deepEqual(д.cases.map((с) => с.variant).sort(), ["Ошибка", "Успех"])
  assert.equal(итог.ядро.diagnostics.length, 0)
})

test("ПОДДЕЛКА к варианту выражением: несуществующий вариант назван", async () => {
  const текст = await отказ(УСПЕШНО.replace("вариант «Успех»)", "вариант «Небывалый»)"))
  assert.match(текст, /FLANG_UNKNOWN_NAME/)
  assert.match(текст, /неизвестный вариант «Небывалый»/)
})

test("ПОДДЕЛКА к варианту выражением: ложь ловится прогоном и названа", async () => {
  const ложь = УСПЕШНО
    .replace("«да ровно на успехе» результат равен (итог это вариант «Успех»)",
      "«да ровно на ошибке» результат равен (итог это вариант «Ошибка»)")
    .replace("  разбор итог", `  пример «Успех — да»
    дано итог равно вариант «Успех» с значение равным 5
    ожидается да
  разбор итог`)
  const текст = await прогонПримеров(ложь)
  assert.match(текст, /красный/)
  assert.match(текст, /нарушено свойство «да ровно на ошибке»/)
})

/* ================================================================== */
/* 3. Поле суммы из ОДНОГО варианта                                    */
/* ================================================================== */

const КЛЮЧ = `модуль «Ключ связи»

тип «Связь»
  вариант «Связь» содержит ключ: строка, значение: строка

тотальная функция «Ключ связи»
  принимает связь: «Связь»
  возвращает строка
  для всех связь обеспечивает «ключ и есть ключ» результат равен связь.ключ
  разбор связь
    случай вариант «Связь» с ключ как имя и значение как содержимое
      то имя
`

test("ПОЛЕ СУММЫ: у суммы из одного варианта поле берётся и правда доказана", async () => {
  const итог = await разобрать(КЛЮЧ)
  const д = вердикт(итог.об, "ключ и есть ключ")
  assert.equal(д?.verdict, "доказано", беды(итог))
  assert.deepEqual(д.cases.map((с) => с.variant), ["Связь"])
  assert.equal(итог.ядро.diagnostics.length, 0)
})

test("ПОДДЕЛКА к полю суммы: у суммы из двух вариантов отказ назван счётом", async () => {
  const текст = await отказ(`модуль «Ответ»

тип «Ответ»
  вариант «Да» содержит причина: строка
  вариант «Нет» содержит причина: строка

тотальная функция «Причина»
  принимает ответ: «Ответ»
  возвращает строка
  для всех ответ обеспечивает «причина и есть причина» результат равен ответ.причина
  разбор ответ
    случай вариант «Да» с причина как п
      то п
    случай вариант «Нет» с причина как п
      то п
`)
  assert.match(текст, /FLANG_TYPE/)
  assert.match(текст, /требует записи или суммы из одного варианта/)
  assert.match(текст, /у «Ответ» вариантов 2 — нужен разбор/)
})

test("ПОДДЕЛКА к полю суммы: несуществующее поле названо", async () => {
  const текст = await отказ(КЛЮЧ.replace("связь.ключ", "связь.небылица"))
  assert.match(текст, /сумма «Связь» из одного варианта не имеет поля «небылица»/)
})

test("ПОДДЕЛКА к полю суммы: ложь ловится прогоном и названа", async () => {
  const ложь = КЛЮЧ
    .replace("«ключ и есть ключ» результат равен связь.ключ",
      "«ключ и есть значение» результат равен связь.значение")
    .replace("  разбор связь", `  пример «Обычный ключ»
    дано связь равно вариант «Связь» с ключ равным "имя" и значение равным "Марат"
    ожидается "имя"
  разбор связь`)
  const текст = await прогонПримеров(ложь)
  assert.match(текст, /красный/)
  assert.match(текст, /нарушено свойство «ключ и есть значение»/)
})

/* ================================================================== */
/* 4. Две переписки ядра, без которых правда была бы недоказуема       */
/* ================================================================== */

test("ПЕРЕПИСКА ЯДРА: ветвь `случай любое` при известном конструкторе", async () => {
  /* Посылка «Ошибка» у «Успешно» закрывается ТОЛЬКО этой переписью: названной
     ветви для «Ошибка» в постусловии нет, есть `любое`. Снимите её — и случай
     «Ошибка» останется несведённым, а вердикт пропадёт целиком. */
  const итог = await разобрать(УСПЕШНО)
  const случай = вердикт(итог.об, "да ровно на успехе").cases.find((с) => с.variant === "Ошибка")
  assert.equal(случай?.verdict, "доказано")
})

test("ПЕРЕПИСКА ЯДРА: поле известного значения", async () => {
  /* Заключение посылки — `к равно (вариант «Связь» с ключ равным к и …).ключ`.
     Без переписки поля стороны синтаксически разные, и тождество не сходится. */
  const итог = await разобрать(КЛЮЧ)
  const д = вердикт(итог.об, "ключ и есть ключ")
  assert.equal(д.cases[0].verdict, "доказано")
  assert.equal(д.rule, "тождество после переписки допущением")
})

test("АКСИОМ НОЛЬ: список ядра пуст и после трёх новых форм", () => {
  assert.deepEqual(АКСИОМЫ, [], "аксиом у ядра ноль, и выразимость их не завела")
})

