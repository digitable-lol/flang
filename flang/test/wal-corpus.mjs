/**
 * КОРПУС журнала упреждающей записи — написан ДО кода, который он проверяет.
 *
 * ── Зачем корпус первым ─────────────────────────────────────────────────────
 *
 * Типы и завершаемость не видят целого класса бед: имя поля, совпавшее со
 * словом языка; признак, который печатается истиной при любом входе; разбор,
 * который «восстановился» на один знак дальше, чем имел право. Всё это —
 * поведение, и ловится оно входом с записанным заранее ответом, а не подписью.
 *
 * Поэтому здесь лежат ВХОДЫ И ОЖИДАНИЯ, и лежат они отдельно от модуля
 * `flang/examples/wal/write-ahead-log.flang`: ожидание, посчитанное тем же
 * кодом, который проверяют, — это тавтология, а не проверка. Ни одна строка
 * ниже не зовёт модуль и не повторяет его разбор; числа `съедено` посчитаны
 * рукой по правилу формата, а не программой.
 *
 * ── Формат записи, ради которого всё ────────────────────────────────────────
 *
 *     #<номер>:<длина>:<тело>;
 *
 *   • `#` — метка начала записи;
 *   • `<номер>` — десятичные цифры, от 1 до 15 знаков, без ведущего нуля
 *     (единственный законный ноль — сам «0»);
 *   • `:` — разделитель;
 *   • `<длина>` — те же правила, это число КОДОВЫХ ТОЧЕК тела;
 *   • `<тело>` — ровно `<длина>` кодовых точек, ЛЮБЫХ: `#`, `:`, `;`, перевод
 *     строки и эмодзи входят в тело наравне с буквами. Ради этого длина и
 *     стоит впереди — иначе журнал нельзя было бы отличить от своего же тела;
 *   • `;` — метка конца записи. Она не «на всякий случай»: без неё запись,
 *     объявившая длину меньше настоящей, читалась бы как целая.
 *
 * Журнал — записи подряд, без разделителей между ними.
 *
 * ── Что значит «съедено» ────────────────────────────────────────────────────
 *
 * `съедено` — сколько кодовых точек ОТ НАЧАЛА файла занято ЦЕЛЫМИ записями.
 * Это и есть то самое «до последней целой записи и не дальше»: остаток файла
 * (`длина входа − съедено`) читателем не истолкован никак.
 *
 * ── Отчего корпус двухчастный ───────────────────────────────────────────────
 *
 * `КОРПУС` — именованные входы, каждый со своим ответом. `ОБРЫВЫ` — эталонный
 * журнал и ВСЕ его обрывы подряд, от нулевой длины до полной: главное
 * утверждение говорит «на любом байте», и проверять его выборочными местами
 * значило бы проверять не его.
 */

/** Сколько кодовых точек в строке. Не `s.length`: суррогатная пара — одна точка. */
const точек = (текст) => [...текст].length

/**
 * Печать записи — ЗДЕСЬ, В КОРПУСЕ, и это не дубль модуля, а вторая запись
 * одного правила. Расхождение между ними и есть находка: корпус говорит, каким
 * формат объявлен, модуль — каким он вышел.
 */
const зап = (номер, тело) => `#${номер}:${точек(тело)}:${тело};`

