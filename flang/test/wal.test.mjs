/* ── Улика на сам корпус: ИЗЪЯТИЕ ────────────────────────────────────────── */

/**
 * Проверка, которая зеленеет, ничего не проверяя, — не проверка. Поэтому здесь
 * из модуля по очереди ВЫНИМАЕТСЯ по одному решению, и от корпуса требуется
 * покраснеть. Не покраснел — значит решение ничего не держит, и это надо знать
 * числом, а не догадкой.
 *
 * Изъятие делается над ТЕКСТОМ модуля и живёт только в памяти прогона: файл на
 * диске не трогается.
 */
const ИЗЪЯТИЯ = [
  {
    имя: "снят канон номера (приняты ведущие нули)",
    было: '(знак равен ":") и притом («Канон числа» от цифры)',
    стало: '(знак равен ":") и притом (не (пусто цифры))',
  },
  {
    имя: "снята метка конца записи (запись целая по одной длине)",
    было: 'то если знак равен ";"\n        то «Закрыть запись»',
    стало: 'то если не (знак равен "!")\n        то «Закрыть запись»',
  },
  {
    имя: "снята поглощаемость сбоя (журнал «чинится» после мусора)",
    было: "случай вариант «Сбились» с причина как причина\n      то чтение",
    стало:
      "случай вариант «Сбились» с причина как причина\n      то если знак равен \"#\"\n" +
      '        то «Идём дальше» от чтение и (вариант «Читаем номер» с цифры равным "")\n        иначе чтение',
  },
  {
    имя: "снята метка конца из ПЕЧАТИ записи",
    было: 'с (соединить пункт.«тело» с ";")',
    стало: 'с (соединить пункт.«тело» с "")',
  },
]

const исходникМодуля = readFileSync(путьМодуля, "utf8")

for (const изъятие of ИЗЪЯТИЯ) {
  test(`изъятие: ${изъятие.имя} — корпус обязан покраснеть`, () => {
    assert.ok(исходникМодуля.includes(изъятие.было), `образец изъятия не найден в модуле: ${изъятие.имя}`)
    const испорчен = parse(исходникМодуля.replace(изъятие.было, изъятие.стало), "изъятие.flang")
    let красных = 0
    for (const вход of КОРПУС) {
      let ответ
      try {
        ответ = evaluate(испорчен, "Прочитать журнал", { текст: вход.текст }, { maxSteps: 20_000_000 })
      } catch {
        /* Постусловие, сорвавшееся при работе, — тоже красный: утверждение
           поймало изъятие раньше, чем это сделала сверка ответа. */
        красных += 1
        continue
      }
      const записи = (ответ["записи"] ?? []).map((з) => ({ номер: з["номер"], тело: з["тело"] }))
      const ждали = вход.записи.map(записьЗначением)
      if (JSON.stringify(записи) !== JSON.stringify(ждали) || ответ["съедено"] !== вход.съедено) красных += 1
    }
    assert.ok(красных > 0, `изъятие «${изъятие.имя}» не покраснело ни на одном из ${КОРПУС.length} входов`)
  })
}

/**
 * ИЗЪЯТИЕ, КОТОРОЕ НЕ КРАСНЕЕТ, — И ЭТО ЗАПИСАНО, А НЕ ЗАМЯТО.
 *
 * Потолок накопления цифр (`длина цифры не больше 14` в «Шаге чтения») ответа
 * НЕ держит: за ответ отвечают «Канон числа» (пятнадцать знаков) и «Число из
 * знаков» (точная сетка double), и без потолка все 61 вход корпуса дают то же
 * самое. Держит он ПАМЯТЬ: без него строка цифр растёт вместе с мусором на
 * входе, и вход «пять тысяч цифр в номере» стоит в корпусе ради этого.
 *
 * Записано это проверкой, а не комментарием: изменись положение дел — и здесь
 * станет красно, а не тихо.
 */
test("измерено: потолок накопления цифр ответа не держит — он стережёт память", () => {
  const было = "если (длина цифры) не больше 14"
  assert.ok(исходникМодуля.includes(было))
  const испорчен = parse(исходникМодуля.replaceAll(было, "если (длина цифры) не больше 99"), "изъятие.flang")
  let красных = 0
  for (const вход of КОРПУС) {
    const ответ = evaluate(испорчен, "Прочитать журнал", { текст: вход.текст }, { maxSteps: 20_000_000 })
    const записи = (ответ["записи"] ?? []).map((з) => ({ номер: з["номер"], тело: з["тело"] }))
    if (JSON.stringify(записи) !== JSON.stringify(вход.записи.map(записьЗначением)) || ответ["съедено"] !== вход.съедено) красных += 1
  }
  assert.equal(красных, 0, "потолок накопления начал держать ответ — запись в шапке этой проверки протухла")
})
