/**
 * Служба REST, написанная на flang: `flang/examples/web/orders-api.flang`.
 *
 * Пример проверяет себя сам — 95 примеров сходятся вместе с примерами трёх
 * связанных модулей библиотеки. Здесь проверяется то, чего пример показать не
 * может, и ровно оно решает, годится ли язык для настоящей службы.
 *
 * 1. **Связывание четырёх модулей.** Словарь, множество, строки и сама служба
 *    собираются в одну программу. До сих пор `использует` работало только
 *    внутри `flang/self` и `flang/core`; здесь оно применяется так, как его
 *    будет применять всякий, кто пишет на языке программу больше одного файла.
 *
 * 2. **Обещание тотальности проверяется грубым входом.** Модуль заявляет, что
 *    служба доказано завершается на любом запросе. Заявление легко написать в
 *    комментарии, поэтому ниже стоит перебор нарочно кривых строк запроса:
 *    пустых, из одних разделителей, с ключами без значений, с повторами,
 *    длинных. Каждая обязана дать ОТВЕТ — не исключение, не зацикливание.
 *
 * 3. **404 и 405 — разные ответы.** Служба, отвечающая «нет такого пути» на
 *    неверный метод, стоит клиенту часа отладки; это тот случай, когда
 *    правильное поведение дешевле проверить, чем объяснить.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { createRuntime } from "../src/interpret.mjs"
import { linkProgram } from "../src/link.mjs"
import { parse } from "../src/parser.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const ПУТЬ = fileURLToPath(new URL("../examples/web/orders-api.flang", import.meta.url))
const { diagnostics: бедыСвязывания, ...служба } = await linkProgram(ПУТЬ, readFileSync(ПУТЬ, "utf8"), parse)
const среда = createRuntime(служба, { maxSteps: 5_000_000, maxDepth: 10_000 })

/** Ответ службы на запрос — пара «код, тело», как её видит хозяин. */
function ответить(метод, путь, хвостадреса) {
  const ответ = среда.call("Обработать запрос", { метод, путь, хвостадреса })
  return {
    код: среда.call("Код ответа", { ответ }),
    тело: среда.call("Тело ответа", { ответ }),
  }
}

test("четыре модуля связываются в одну программу без диагностик", () => {
  assert.deepEqual(бедыСвязывания, [], "связывание службы с библиотекой дало беды")
  assert.deepEqual(checkTypes(служба).diagnostics, [])
  assert.deepEqual(checkTotality(служба).diagnostics, [])
})

test("каждая функция службы помечена тотальной — и доказана", () => {
  const доказанные = checkTotality(служба).total
  const свои = служба.functions.filter((ф) => ф.total === true)
  assert.ok(свои.length >= 8, `тотальных функций всего ${свои.length}`)
  for (const функция of свои) {
    assert.ok(доказанные.has(функция.name), `«${функция.name}» помечена тотальной, но не доказана`)
  }
})

test("маршрутизация различает «нет такого пути» и «метод не поддержан»", () => {
  assert.equal(ответить("GET", "/склад", "").код, 404)
  assert.equal(ответить("DELETE", "/заказы", "").код, 405)
  /* Разные коды — не педантизм: 404 говорит клиенту «проверь адрес», 405 —
     «адрес верный, проверь метод». Слить их значит отправить искать не там. */
  assert.notEqual(ответить("GET", "/склад", "").код, ответить("DELETE", "/заказы", "").код)
})

test("кривой запрос даёт ответ, а не падение", () => {
  /* Вот ради чего пометка «тотальная» стоит в исходнике. Ни один из этих
     входов не встречается в примерах, и ни один не должен уронить службу. */
  const кривые = [
    "",
    "&",
    "&&&&&",
    "=",
    "=&=&=",
    "товар",
    "товар=",
    "=книга",
    "товар=книга&товар=перо",
    "товар=книга&&&товар=",
    "а=1&б=2&в=3&г=4&д=5&е=6&ж=7&з=8&и=9&к=10",
    "подпись=а=б=в=г",
    "товар=книга ",
    " товар=книга",
  ]
  for (const хвост of кривые) {
    const ответ = ответить("POST", "/заказы", хвост)
    assert.equal(typeof ответ.код, "number", `на «${хвост}» служба не ответила числом`)
    assert.ok(ответ.код === 201 || ответ.код === 400, `на «${хвост}» вышел код ${ответ.код}`)
    assert.equal(typeof ответ.тело, "string")
  }
})

test("повторный параметр берётся последним, а не удваивается", () => {
  /* Служба кладёт параметры в словарь, а словарь вытесняет прежнее значение.
     Значит «товар=книга&товар=перо» — это заказ пера. Решение спорное, но оно
     ОДНО и записано; хуже была бы служба, где ответ зависит от того, каким
     концом её обошли. */
  assert.deepEqual(ответить("POST", "/заказы", "товар=книга&товар=перо"), {
    код: 201,
    тело: "заказ принят: перо",
  })
})

test("знак равенства внутри значения не теряется", () => {
  /* Подписи и токены в адресах сплошь содержат «=». Служба, режущая значение по
     первому знаку, ломается на них молча — и ищут такое долго. */
  assert.deepEqual(ответить("POST", "/заказы", "товар=а=б=в"), {
    код: 201,
    тело: "заказ принят: а=б=в",
  })
})

test("нехватка полей названа поимённо", () => {
  /* Ответ «неверный запрос» без указания поля перекладывает работу на клиента.
     Служба обязана сказать, чего именно не хватает. */
  assert.deepEqual(ответить("POST", "/заказы", ""), {
    код: 400,
    тело: "не хватает полей: товар",
  })
  assert.deepEqual(ответить("GET", "/заказы", ""), {
    код: 400,
    тело: "не хватает полей: номер",
  })
})
