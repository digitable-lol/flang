/**
 * Замер занятости слова — и проверка САМОГО замера.
 *
 * Устройство и довод — в шапке `flang/scripts/word-occupancy.mjs`. Здесь три
 * обязательства, и путать их нельзя:
 *
 *   1. замер ЛОВИТ голое слово — на слове, которое в корпусе точно есть именем;
 *   2. замер МОЛЧИТ там, где вхождение безопасно, — в ёлочках, в строковом
 *      литерале, в комментарии;
 *   3. замер УЗНАЁТ уже занятое слово и говорит, какой конструкцией.
 *
 * Второе и третье написаны по той же причине, по какой они написаны у сторожа
 * утверждений: замер, который не может сказать «занято», выглядит ровно как
 * замер, по которому всё свободно. А цена ошибки здесь — сломанный корпус:
 * слово заводят в таблицу поверхностей, и программы, где оно стояло именем,
 * перестают разбираться.
 */
import assert from "node:assert/strict"
import { mkdtemp, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"

import { ФАЙЛЫ, занятость } from "../scripts/word-occupancy.mjs"

test("корпус читается целиком, а не наполовину", () => {
  assert.ok(ФАЙЛЫ.length > 100, `файлов в корпусе ${ФАЙЛЫ.length} — замер смотрит не туда`)
  assert.ok(ФАЙЛЫ.every((путь) => путь.endsWith(".flang")), "в корпус попало не то")
  assert.ok(
    !ФАЙЛЫ.includes("flang/self/bootstrap/compiler.flang"),
    "склеенный компилятор посчитал бы слова остальных файлов второй раз",
  )
})

test("замер ЛОВИТ голое слово: «предел» стоит в корпусе именем", () => {
  const итог = занятость("предел")
  assert.ok(итог.голым > 0, "слово, которым названы параметры stdlib, замер обязан видеть")
  assert.ok(итог.места.length > 0, "место занятости обязано называться — иначе число нечем перепроверить")
  assert.match(итог.места[0], /\.flang:\d+$/u, "место — это путь и строка")
})

test("замер УЗНАЁТ занятое слово и называет конструкцию", () => {
  const итог = занятость("число")
  assert.equal(итог.ключевое, "tNumber", "«число» — имя встроенного типа, и замер обязан это сказать")
})

test("свободное слово даёт ноль голых — и это ответ «можно»", () => {
  /* Слова здесь меняются по мере того, как язык их занимает, и это не
     обслуживание теста, а его смысл. «натуральное» и «целое» стояли тут ровно до
     того дня, когда замер сказал «можно» и точный натуральный тип их занял;
     теперь они стоят в корпусе голыми законно, именами типов, и ответом «можно»
     служат следующие свободные. Оставить занятое слово значило бы проверять
     замер тем, чего он уже не обещает. */
  for (const слово of ["количество", "неотрицательное"]) {
    const итог = занятость(слово)
    assert.equal(итог.голым, 0, `«${слово}» встретилось голым — таблицу поверхностей трогать нельзя`)
    assert.equal(итог.ключевое, null, `«${слово}» уже занято конструкцией «${итог.ключевое}»`)
  }
})

test("вхождение в ёлочках, в строке и в комментарии голым не считается", async (t) => {
  const каталог = await mkdtemp(join(tmpdir(), "flang-occupancy-"))
  t.after(() => rm(каталог, { recursive: true, force: true }))

  /* Одно и то же слово трижды в безопасных местах и НИ РАЗУ голым. Замер обязан
     насчитать три вхождения и ноль поломок: ровно так считали руками, заводя
     `убывает` («все 58 вхождений — комментарии, строковые литералы и имена в
     ёлочках»), и ровно этот счёт здесь и проверяется. */
  await writeFile(
    join(каталог, "проба.flang"),
    [
      "модуль «Проба»",
      "",
      "// слово шпунтик стоит в комментарии",
      "тотальная функция «шпунтик»",
      "  принимает «имя»: строка",
      "  возвращает строка",
      '  "шпунтик"',
      "",
    ].join("\n"),
    "utf8",
  )

  const итог = занятость("шпунтик", ["проба.flang"], каталог)
  assert.equal(итог.голым, 0, "ни одно из трёх вхождений не стоит голым — замер не вправе их считать")
  assert.equal(итог.вЁлочках, 1, "имя функции в ёлочках")
  assert.equal(итог.вСтроке, 1, "тело — строковый литерал")
  assert.equal(итог.вКомментарии, 1, "комментарий")
})

test("голое слово в подложенном файле считается — значит счёт не всегда ноль", async (t) => {
  const каталог = await mkdtemp(join(tmpdir(), "flang-occupancy-"))
  t.after(() => rm(каталог, { recursive: true, force: true }))

  await writeFile(
    join(каталог, "проба.flang"),
    [
      "модуль «Проба»",
      "",
      "тотальная функция «Взять»",
      "  принимает шпунтик: число",
      "  возвращает число",
      "  шпунтик",
      "",
    ].join("\n"),
    "utf8",
  )

  const итог = занятость("шпунтик", ["проба.flang"], каталог)
  assert.equal(итог.голым, 2, "имя параметра и его чтение в теле — два голых вхождения")
})

test("фраза проверяется как фраза, а не как первое её слово", async (t) => {
  const каталог = await mkdtemp(join(tmpdir(), "flang-occupancy-"))
  t.after(() => rm(каталог, { recursive: true, force: true }))

  /* Довод, по которому в языке появилась пара `код символа`: одинокое `код`
     занято, а пара — свободна. Замер обязан различать эти два вопроса, иначе
     он отвечает не на тот, который задан. */
  await writeFile(
    join(каталог, "проба.flang"),
    [
      "модуль «Проба»",
      "",
      "тотальная функция «Взять»",
      "  принимает шпунтик: число",
      "  возвращает число",
      "  шпунтик",
      "",
    ].join("\n"),
    "utf8",
  )

  const одно = занятость("шпунтик", ["проба.flang"], каталог)
  const пара = занятость("шпунтик малый", ["проба.flang"], каталог)
  assert.equal(одно.голым, 2, "одинокое слово занято")
  assert.equal(пара.голым, 0, "пары в корпусе нет — значит она свободна")
})
