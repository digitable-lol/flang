/**
 * Коммутативность: `а∘б = б∘а`.
 *
 * ── Улика, снятая прогоном ДО работы, и она с историей ──────────────────────
 *
 * Это не новая недостача, а ЗАПИСАННАЯ: `flang/cat/SPEC.md` называет множество
 * «моноидом, коммутативным», а сказать этого языком было нечем — в объявлении
 * моноида коммутативности нет. Прогон это подтверждал: моноид, чья операция
 * заведомо не коммутативна, проходил `flang check --proof` с вердиктом
 * «ассоциативность, нейтральность: нарушений не найдено», и о порядке
 * аргументов отчёт не говорил ничего.
 *
 * ── Что из этого следует ────────────────────────────────────────────────────
 *
 * Разрешение РАЗЛОЖИТЬ СВЁРТКУ ПО ЯДРАМ: ассоциативность разрешает менять
 * скобки, коммутативность — порядок, и разложить свёртку можно ровно при обеих.
 * И первое место, где объявленное свойство меняет вердикт о ЧУЖОЙ конструкции:
 * строка моноида в ведомости называет три закона вместо двух.
 *
 * Запуск: node --test flang/test/zakon-commutative.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { runExamples } from "../src/compat.mjs"
import { checkCommutativity } from "../src/commutative.mjs"
import { checkIdempotence } from "../src/idempotent.mjs"
import { checkMonoidLaws } from "../src/monoid.mjs"
import { parse } from "../src/parser.mjs"
import { formatProofLedger, proofLedger } from "./vedomost.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const разобрать = (исходник) => parse(исходник, "проба.flang")

function закон(исходник) {
  const итог = checkCommutativity(разобрать(исходник))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    checked: итог.checked,
    assumed: итог.assumed,
    permits: итог.permits,
  }
}

/* ── общая основа: моноид вычитания, который коммутативным не является ────── */

const ВЫЧИТАНИЕ = `модуль «Проба»

тотальная функция «Вычесть»
  принимает первое: число, второе: число
  возвращает число
  пример «пять минус три»
    дано первое равно 5
    дано второе равно 3
    ожидается 2
  первое минус второе
`

const СЛОЖЕНИЕ = `модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 5
  первое плюс второе

моноид «Сумма»
  носитель число
  операция «Сложить»
  единица 0

свойство «коммутативность»
  носитель число
  операция «Сложить»
`

/* ────────────────────────── улика: было молчание ─────────────────────────── */

test("УЛИКА ДО: моноид вычитания молчал о порядке аргументов", () => {
  /* Вычитание ассоциативным не является, и это моноид ловит. Значит улику надо
     снимать на операции, которая АССОЦИАТИВНА и при этом не коммутативна, —
     иначе улика была бы про другой закон. «Взять первое» — ровно такая. */
  const первое = `модуль «Проба»

тотальная функция «Взять первое»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 2
  первое
`
  const программа = разобрать(первое)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.equal(runExamples(программа).failed, 0)
  const ведомость = proofLedger(программа, { totality: checkTotality(программа) })
  assert.deepEqual(ведомость.laws, [], "закон нашёлся там, где законов не было")
  assert.match(formatProofLedger(ведомость), /нет объявленных законов/u)
})

/* ───────────────────────── закон: ПРОВЕРЯЕТСЯ на сетке ───────────────────── */

test("честная операция проходит, и размер сетки уезжает в отчёт", () => {
  const итог = закон(СЛОЖЕНИЕ)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked.length, 1)
  assert.ok(итог.checked[0].points > 0, "пар не перебрано ни одной")
  assert.equal(итог.permits.length, 1)
})

test("ПОДДЕЛКА: вычитание отвергается с предъявленной парой", () => {
  const итог = закон(`${ВЫЧИТАНИЕ}
свойство «коммутативность»
  носитель число
  операция «Вычесть»
`)
  assert.deepEqual(итог.коды, ["FLANG_NOT_COMMUTATIVE"])
  assert.match(итог.тексты.join("\n"), /не коммутативна/u)
  /* Контрпример предъявлен парой и обоими ответами, а не спрятан за вердиктом. */
  assert.match(итог.тексты.join("\n"), /на 5 и 3 вышло 2, а в обратном порядке — -2/u)
  assert.deepEqual(итог.permits, [], "разрешение выдано нарушенному свойству")
})

test("ПОДДЕЛКА: ассоциативная операция без коммутативности отвергается", () => {
  /* «Взять первое» ассоциативна и имеет левую единицу — моноидные законы её
     пропустили бы; краснеет ровно коммутативность. */
  const итог = закон(`модуль «Проба»

тотальная функция «Взять первое»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 2
  первое

свойство «коммутативность»
  носитель число
  операция «Взять первое»
`)
  assert.deepEqual(итог.коды, ["FLANG_NOT_COMMUTATIVE"])
})

test("операция одного входа коммутативной не бывает: устройство отвергается", () => {
  const итог = checkTypes(разобрать(`модуль «Проба»

тотальная функция «Удвоить»
  принимает вход: число
  возвращает число
  вход умножить на 2

свойство «коммутативность»
  носитель число
  операция «Удвоить»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_PROPERTY_SHAPE"])
  assert.match(итог.diagnostics[0].message, /принимает 1 арг., а обязана 2/u)
})

test("объявление без примеров уходит «на веру», а не молчит", () => {
  const итог = закон(`модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

свойство «коммутативность»
  носитель число
  операция «Сложить»
`)
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.deepEqual(итог.permits, [])
})

/* ────────── что из этого следует: моноид называет третий закон ───────────── */

test("МОНОИД НАЗЫВАЕТ ТРИ ЗАКОНА ВМЕСТО ДВУХ — недостача из cat/SPEC.md закрыта", () => {
  /* То, ради чего свойство и просили пятым. До этой работы строка моноида
     говорила «ассоциативность, нейтральность» и о порядке аргументов молчала. */
  const программа = разобрать(СЛОЖЕНИЕ)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    monoid: checkMonoidLaws(программа),
    commutative: checkCommutativity(программа),
  })
  const строка = ведомость.laws.find((з) => з.kind === "моноид")
  assert.equal(строка.laws, "ассоциативность, нейтральность, коммутативность")
  assert.match(formatProofLedger(ведомость), /моноид «Сумма» — .*коммутативность/u)
})

test("СЛОВО МОНОИДА БЕРЁТСЯ ИЗ ПОСЧИТАННОГО, а не из объявленного", () => {
  /* Объявить коммутативность и не пройти её — не значит получить третий закон.
     Иначе объявление продавалось бы за проверку. */
  const программа = разобрать(`${ВЫЧИТАНИЕ}
моноид «Разность»
  носитель число
  операция «Вычесть»
  единица 0

свойство «коммутативность»
  носитель число
  операция «Вычесть»
`)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    monoid: checkMonoidLaws(программа),
    commutative: checkCommutativity(программа),
  })
  const строка = ведомость.laws.find((з) => з.kind === "моноид")
  assert.ok(!/коммутативность/u.test(строка.laws), `моноид получил непосчитанный закон: ${строка.laws}`)
})

test("моноид без объявленного свойства говорит РОВНО ТО ЖЕ, что говорил", () => {
  /* Ведомость программы, где свойства не объявлено, обязана остаться прежней. */
  const программа = разобрать(`модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 5
  первое плюс второе

моноид «Сумма»
  носитель число
  операция «Сложить»
  единица 0
`)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    monoid: checkMonoidLaws(программа),
  })
  assert.equal(ведомость.laws.find((з) => з.kind === "моноид").laws, "ассоциативность, нейтральность")
  assert.equal(ведомость.permits, undefined)
})

test("моноид на ИМЕНОВАННОМ типе стал возможен — до правки не собирался ни один", () => {
  /* Побочная находка этой работы, и она про обещание `cat/SPEC.md`: «Вектор»,
     «Словарь» и «Очередь» обещаны моноидами, а носитель у них именованный —
     и такой моноид не собирался никогда, потому что сырой узел разбора не
     сходился с нормализованным типом параметра. */
  const программа = разобрать(`модуль «Проба»

объект «Куча»
  сколько является числом

тотальная функция «Слить кучи»
  принимает первая: «Куча», вторая: «Куча»
  возвращает «Куча»
  запись «Куча» с сколько равным (первая.сколько плюс вторая.сколько)

моноид «Кучи»
  носитель «Куча»
  операция «Слить кучи»
  единица запись «Куча» с сколько равным 0
`)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
})

/* ─────────────────── настоящая программа репозитория ─────────────────────── */

const ПРИМЕР = "flang/examples/cat/fold-by-cores.flang"
const исходникПримера = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

test("пример репозитория: обе операции коммутативны, разрешений два", () => {
  const программа = разобрать(исходникПримера)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = checkCommutativity(программа)
  assert.deepEqual(итог.diagnostics, [], итог.diagnostics.map((б) => б.message).join("\n"))
  assert.equal(итог.checked.length, 2)
  assert.equal(итог.permits.length, 2)
  assert.match(итог.permits[0].says, /разложить по ядрам/u)
})

test("пример репозитория: ИЗЪЯТИЕ разбора ничьей — краснеет одна коммутативность", () => {
  /* Ошибка, которую человек правда делает: ничья по времени разрешается «в
     пользу второго». Реплики от этого расходятся — результат зависит от того,
     кто с кем слился первым. И вот что важно: НИ ОДИН другой закон дерева этого
     не видит — типы сходятся, завершение доказано, все пять примеров зелены
     (включая пример про ничью: он написан так, что «второй» и есть ожидаемый),
     законы моноида чисты, идемпотентность чиста. */
  const порченый = исходникПримера.replace(
    "      иначе если первый.сколько больше второй.сколько то первый иначе второй",
    "      иначе второй",
  )
  assert.notEqual(порченый, исходникПримера, "место изъятия в файле не найдено")
  const программа = разобрать(порченый)
  assert.deepEqual(checkTypes(программа).diagnostics, [], "беду увидели типы")
  assert.deepEqual(checkTotality(программа).diagnostics ?? [], [], "беду увидело завершение")
  assert.equal(runExamples(программа).failed, 0, "беду увидели примеры")
  assert.deepEqual(checkMonoidLaws(программа).diagnostics, [], "беду увидел моноид")
  assert.deepEqual(checkIdempotence(программа).diagnostics, [], "беду увидела идемпотентность")
  const итог = checkCommutativity(программа)
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_NOT_COMMUTATIVE"])
  assert.match(итог.diagnostics[0].message, /"время":5,"сколько":1/u)
  assert.match(итог.diagnostics[0].message, /"время":5,"сколько":7/u)
  assert.equal(итог.permits.length, 1, "разрешение осталось у нарушенной операции")
})
