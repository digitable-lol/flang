/**
 * Дистрибутивность: `а×(б+в) = а×б + а×в`.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Программа, где одна и та же величина считается двумя дорогами — по целому и
 * по частям, — проходила `flang check --proof` со строкой «нет объявленных
 * законов». Обещание «считать можно как угодно, ответ один» ни во что не
 * превращалось: сказать его языку было нечем.
 *
 * ── Что из этого следует ────────────────────────────────────────────────────
 *
 * Разрешение ПЕРЕПИСЫВАТЬ ВЫРАЖЕНИЯ: свернуть строки в одну там, где дешевле
 * один вызов, разбить на части там, где сумма уже посчитана. Заменять одну
 * дорогу другой разрешено ровно тогда, когда обе дают один ответ.
 *
 * Запуск: node --test flang/test/zakon-distributive.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { runExamples } from "../src/compat.mjs"
import { checkCommutativity } from "../src/commutative.mjs"
import { checkDistributivity } from "../src/distributive.mjs"
import { parse } from "../src/parser.mjs"
import { formatProofLedger, proofLedger } from "../src/proof.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const разобрать = (исходник) => parse(исходник, "проба.flang")

function закон(исходник) {
  const итог = checkDistributivity(разобрать(исходник))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    checked: итог.checked,
    assumed: итог.assumed,
    permits: итог.permits,
  }
}

const ОСНОВА = `модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 5
  первое плюс второе
`

const УМНОЖИТЬ = `
тотальная функция «Умножить»
  принимает первое: число, второе: число
  возвращает число
  пример «два на три»
    дано первое равно 2
    дано второе равно 3
    ожидается 6
  первое умножить на второе
`

const ОБЪЯВЛЕНИЕ = `
свойство «дистрибутивность»
  носитель число
  операция «Умножить»
  по «Сложить»
`

/* ────────────────────────── улика: было молчание ─────────────────────────── */

test("УЛИКА ДО: сложение по умножению не дистрибутивно, и никто об этом не говорил", () => {
  /* Пара наоборот: `а + (б × в)` и `(а+б) × (а+в)` — не одно и то же. До этой
     работы такую программу нечем было даже спросить. */
  const программа = разобрать(`${ОСНОВА}${УМНОЖИТЬ}`)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.equal(runExamples(программа).failed, 0)
  const ведомость = proofLedger(программа, { totality: checkTotality(программа) })
  assert.deepEqual(ведомость.laws, [])
  assert.match(formatProofLedger(ведомость), /нет объявленных законов/u)
})

/* ─────────────── устройство: ДОКАЗЫВАЕТСЯ сличением объявлений ───────────── */

test("дистрибутивность без второй операции отвергается: не сказано, ПО ЧЕМУ раскрывать", () => {
  const итог = checkTypes(разобрать(`${ОСНОВА}${УМНОЖИТЬ}
свойство «дистрибутивность»
  носитель число
  операция «Умножить»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_PROPERTY_SHAPE"])
  assert.match(итог.diagnostics[0].message, /не сказано, ПО ЧЕМУ раскрывать/u)
})

test("вторая операция обязана быть объявлена и брать два входа носителя", () => {
  const итог = checkTypes(разобрать(`${ОСНОВА}${УМНОЖИТЬ}
свойство «дистрибутивность»
  носитель число
  операция «Умножить»
  по «Нету»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_UNKNOWN_NAME"])
  assert.match(итог.diagnostics[0].message, /вторая операция/u)
})

/* ───────────────────────── закон: ПРОВЕРЯЕТСЯ на сетке ───────────────────── */

test("умножение по сложению проходит, и тройки уезжают в отчёт", () => {
  const итог = закон(`${ОСНОВА}${УМНОЖИТЬ}${ОБЪЯВЛЕНИЕ}`)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked.length, 1)
  assert.equal(итог.checked[0].over, "Сложить")
  assert.ok(итог.checked[0].points > 0, "троек не перебрано ни одной")
  assert.equal(итог.permits.length, 1)
  assert.match(итог.permits[0].says, /переписывать в обе стороны/u)
})

test("ПОДДЕЛКА: сложение по умножению отвергается с обеими записями выражения", () => {
  const итог = закон(`${ОСНОВА}${УМНОЖИТЬ}
свойство «дистрибутивность»
  носитель число
  операция «Сложить»
  по «Умножить»
`)
  assert.deepEqual(итог.коды, ["FLANG_NOT_DISTRIBUTIVE"])
  assert.match(итог.тексты.join("\n"), /не дистрибутивна по «Умножить»/u)
  /* Контрпример предъявлен обеими записями и обоими ответами. */
  assert.match(итог.тексты.join("\n"), /× \(.+ \+ .+\) дало .+, а то же самое раскрытым — /u)
  assert.deepEqual(итог.permits, [])
})

test("СТОРОНА ЗАКОНА НАЗВАНА: у некоммутативной операции левая и правая — разные утверждения", () => {
  /* У некоммутативной операции `а×(б+в)` и `(б+в)×а` — два РАЗНЫХ утверждения,
     и проверив одно, о втором сказать нечего. Поэтому считаются оба, а
     сообщение обязано назвать, какое именно не сошлось: не назвав стороны,
     автор чинил бы не то место. */
  const итог = закон(`${ОСНОВА}${УМНОЖИТЬ}
свойство «дистрибутивность»
  носитель число
  операция «Сложить»
  по «Умножить»
`)
  assert.match(итог.тексты.join("\n"), /(левая|правая) сторона/u)
})

test("ОКРУГЛЕНИЕ ЛОМАЕТ ЗАКОН, И ПРОВЕРКА ЭТО ВИДИТ: сетка идёт по IEEE-754, а не по числам", () => {
  /* Находка соседней работы (`work/beskonechnost`), перенесённая сюда и
     проверенная своим законом: на десятичных дробях арифметика двойной
     точности перестаёт слушаться школьных правил, и ломает их НЕ бесконечность,
     а ОКРУГЛЕНИЕ. Там это измерено на ассоциативности сложения — 402 нарушения
     на тринадцати мелких десятичных; здесь то же самое видно на
     дистрибутивности умножения.

     Это не изъян проверки, а её точность: закон объявляется о ВЫЧИСЛЕНИЯХ
     программы, а вычисляет программа по IEEE-754. Проверка, которая закрыла бы
     на это глаза, разрешала бы переписывать выражение, меняющее ответ, — и
     разрешала бы молча. */
  const десятичные = `модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  пример «десятые»
    дано первое равно 0.1
    дано второе равно 0.2
    ожидается 0.30000000000000004
  пример «три десятых и семь»
    дано первое равно 0.3
    дано второе равно 0.7
    ожидается 1
  первое плюс второе

тотальная функция «Умножить»
  принимает первое: число, второе: число
  возвращает число
  пример «десятые»
    дано первое равно 0.1
    дано второе равно 0.2
    ожидается 0.020000000000000004
  первое умножить на второе
${ОБЪЯВЛЕНИЕ}`
  const итог = закон(десятичные)
  assert.deepEqual(итог.коды, ["FLANG_NOT_DISTRIBUTIVE"])
  /* Контрпример предъявлен целиком, и разница видна глазом в последнем знаке. */
  assert.match(итог.тексты.join("\n"), /0\.04000000000000001/u)
  assert.deepEqual(итог.permits, [], "разрешение переписывать выдано на арифметике, которая его не держит")
})

test("объявление без примеров у обеих операций уходит «на веру»", () => {
  const итог = закон(`модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

тотальная функция «Умножить»
  принимает первое: число, второе: число
  возвращает число
  первое умножить на второе
${ОБЪЯВЛЕНИЕ}`)
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.match(итог.assumed[0].why, /сетка пуста/u)
  assert.deepEqual(итог.permits, [])
})

test("СЕТКА БЕРЁТСЯ ИЗ ОБЕИХ ОПЕРАЦИЙ, а не из одной", () => {
  /* Краевые случаи автор пишет при той операции, где они краевые: ноль — при
     умножении. Возьми сетку только у «Умножить» — и «два и три» из примеров
     сложения в неё не попадёт, а закон ломается ровно на написанном. */
  const итог = закон(`${ОСНОВА}${УМНОЖИТЬ}${ОБЪЯВЛЕНИЕ}`)
  /* Значения сложения (2, 3, 5) и умножения (2, 3, 6) вместе дают 4 различных. */
  assert.equal(итог.checked[0].values, 4, "сетка собрана не из обеих операций")
})

/* ─────────────────── настоящая программа репозитория ─────────────────────── */

const ПРИМЕР = "flang/examples/cat/split-lines.flang"
const исходникПримера = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

test("пример репозитория: свойство посчитано, разрешение выдано", () => {
  const программа = разобрать(исходникПримера)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = checkDistributivity(программа)
  assert.deepEqual(итог.diagnostics, [], итог.diagnostics.map((б) => б.message).join("\n"))
  assert.equal(итог.checked.length, 1)
  assert.equal(итог.permits.length, 1)
})

test("пример репозитория: ИЗЪЯТИЕ — скидка на большой заказ ломает РОВНО дистрибутивность", () => {
  /* Ошибка, которую человек правда делает: «скидка сто рублей на заказы дороже
     тысячи». Автор, добавляя её, поправит и ожидаемое значение примера — и
     после этого не увидит беды нигде: типы сходятся, завершение доказано, все
     пять примеров зелены, КОММУТАТИВНОСТЬ «Стоимости» ОСТАЁТСЯ ЗЕЛЁНОЙ (скидка
     считается от произведения, а оно симметрично). Свидетель на месте: беду
     видит ровно дистрибутивность, а не «какая-нибудь проверка вообще». */
  const порченый = исходникПримера
    .replace(
      "  цена умножить на количество\n",
      "  пусть всего равно (цена умножить на количество)\n  если всего больше 1000 то всего минус 100 иначе всего\n",
    )
    .replace("    ожидается 1200", "    ожидается 1100")
  assert.notEqual(порченый, исходникПримера, "место изъятия в файле не найдено")
  const программа = разобрать(порченый)
  assert.deepEqual(checkTypes(программа).diagnostics, [], "беду увидели типы")
  assert.deepEqual(checkTotality(программа).diagnostics ?? [], [], "беду увидело завершение")
  assert.equal(runExamples(программа).failed, 0, "беду увидели примеры")
  assert.deepEqual(checkCommutativity(программа).diagnostics, [], "беду увидела коммутативность — свидетель испорчен")
  const итог = checkDistributivity(программа)
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_NOT_DISTRIBUTIVE"])
  assert.match(итог.diagnostics[0].message, /левая сторона/u)
  assert.deepEqual(итог.permits, [], "разрешение пережило нарушение")
})

test("пример репозитория: ИЗЪЯТИЕ объявления — закон уходит в молчание", () => {
  const без = исходникПримера.replace(
    /\nсвойство «дистрибутивность»\n {2}носитель[^\n]*\n {2}операция[^\n]*\n {2}по[^\n]*\n/u,
    "\n",
  )
  assert.notEqual(без, исходникПримера, "строк объявления в файле не найдено")
  const итог = checkDistributivity(разобрать(без))
  assert.deepEqual(итог.checked, [])
  assert.deepEqual(итог.permits, [])
})
