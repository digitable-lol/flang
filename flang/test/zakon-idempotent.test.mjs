/**
 * Идемпотентность: `х∘х = х` и `ф(ф(х)) = ф(х)`.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Программа с функцией, начисляющей бонус БЕЗ сторожа «уже начислен», проходила
 * `flang check --proof` молча: типы сходятся, завершение доказано, все примеры
 * зелены, а ведомость печатала «нет объявленных законов» и «законов на сетке: 0».
 * Повторная доставка того же сообщения начисляла бонус второй раз, и сказать об
 * этом языку было нечем: свойства «повтор безопасен» в нём не было вовсе.
 *
 * Улика воспроизводится здесь тестом «улика ДО», а не остаётся словами.
 *
 * ── Что здесь ДОКАЗЫВАЕТСЯ, а что ПРОВЕРЯЕТСЯ ───────────────────────────────
 *
 * Устройство — доказывается сличением объявлений, без единого вычисления:
 * функция объявлена, входов один или два, все носителя, результат из носителя не
 * выводит (`types.mjs`).
 *
 * Сам закон — проверяется на конечной сетке значений автора (`idempotent.mjs`)
 * и называется ровно так: ведомость печатает строку, оканчивающуюся словами
 * «Это не доказательство».
 *
 * ── Что из этого следует ────────────────────────────────────────────────────
 *
 * Разрешение ПОВТОРИТЬ — отдельной строкой ведомости, а не выводом читателя.
 * Разрешение выдаётся за чистый счёт на непустой сетке и ни за что иное:
 * нарушение — разрешения нет, пустая сетка — разрешения нет.
 *
 * Запуск: node --test flang/test/zakon-idempotent.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { runExamples } from "../src/compat.mjs"
import { checkIdempotence, повторБезопасен } from "../src/idempotent.mjs"
import { parse } from "../src/parser.mjs"
import { formatProofLedger, proofLedger } from "../src/proof.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

function разобрать(исходник) {
  return parse(исходник, "проба.flang")
}

function типы(исходник) {
  const итог = checkTypes(разобрать(исходник))
  return {
    коды: (итог.diagnostics ?? []).map((беда) => беда.code),
    тексты: (итог.diagnostics ?? []).map((беда) => беда.message),
  }
}

function закон(исходник) {
  const итог = checkIdempotence(разобрать(исходник))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    checked: итог.checked,
    assumed: итог.assumed,
    permits: итог.permits,
  }
}

/* ── общая основа: счёт клиента и начисление под сторожем ─────────────────── */

const ОСНОВА = `модуль «Проба»

объект «Счёт»
  начислено является числом
  бонус является признаком

тотальная функция «Начислить»
  принимает счёт: «Счёт»
  возвращает «Счёт»
  пример «первый раз»
    дано счёт равно запись «Счёт» с начислено равным 100 и бонус равным нет
    ожидается запись «Счёт» с начислено равным 150 и бонус равным да
`

const СТОРОЖ = `  если счёт.бонус
    то счёт
    иначе запись «Счёт» с начислено равным (счёт.начислено плюс 50) и бонус равным да
`

const БЕЗ_СТОРОЖА = `  запись «Счёт» с начислено равным (счёт.начислено плюс 50) и бонус равным да
`

const ОБЪЯВЛЕНИЕ = `
свойство «идемпотентность»
  носитель «Счёт»
  операция «Начислить»
`

const ЧЕСТНАЯ = `${ОСНОВА}${СТОРОЖ}${ОБЪЯВЛЕНИЕ}`
const ПОДДЕЛКА = `${ОСНОВА}${БЕЗ_СТОРОЖА}${ОБЪЯВЛЕНИЕ}`

/* ────────────────────────── улика: было молчание ─────────────────────────── */

test("УЛИКА ДО: без объявления свойства нарушение проходит молча", () => {
  /* Это и есть цена, которую платил язык до сегодняшнего дня. Программа без
     сторожа «уже начислен» — та самая, что при повторной доставке начислит
     бонус дважды, — проходит ВСЕ проверки дерева: типы, завершение, примеры.
     И ведомость печатает «нет объявленных законов». */
  const безСвойства = `${ОСНОВА}${БЕЗ_СТОРОЖА}`
  const программа = разобрать(безСвойства)
  assert.deepEqual(checkTypes(программа).diagnostics, [], "типы что-то сказали — улика не про них")
  assert.deepEqual(checkTotality(программа).diagnostics ?? [], [], "завершение что-то сказало")
  assert.equal(runExamples(программа).failed, 0, "пример упал — улика не про примеры")
  const ведомость = proofLedger(программа, { totality: checkTotality(программа) })
  assert.deepEqual(ведомость.laws, [], "закон нашёлся там, где законов не было")
  assert.equal(ведомость.permits, undefined, "разрешение выдано программе, которая ничего не объявляла")
  assert.match(formatProofLedger(ведомость), /нет объявленных законов/u)
})

/* ───────────────────────────────── форма ─────────────────────────────────── */

test("свойство попадает в AST отдельным ключом", () => {
  const программа = разобрать(ЧЕСТНАЯ)
  assert.equal(программа.properties.length, 1)
  assert.deepEqual(программа.properties[0].name, "идемпотентность")
  assert.deepEqual(программа.properties[0].operation, "Начислить")
})

test("ПРОГРАММА БЕЗ СВОЙСТВ НЕ ЗАДЕТА: ключа `properties` у неё не появляется", () => {
  /* Ключ последний и появляется только при непустом списке: порядок ключей —
     это байты канонического JSON, и вставить новый ключ значило бы переписать
     AST каждой программы репозитория. */
  const программа = разобрать(`${ОСНОВА}${СТОРОЖ}`)
  assert.equal("properties" in программа, false)
})

test("до этой работы `свойство` в начале строки было ошибкой разбора", () => {
  /* Ровно то, что занято: форма, которая раньше отвергалась. Проверяется не
     словами, а поведением — `свойство` внутри утилиты разбирается как
     разбиралось, и это соседняя строка ниже. */
  assert.throws(
    () => разобрать(`${ОСНОВА}${СТОРОЖ}\nсвойство «идемпотентность»\n  единица 0\n`),
    /не разобрана конструкция/u,
  )
})

test("`свойство` ВНУТРИ утилиты разбирается как разбиралось", () => {
  /* 70 таких строк в `.fts` репозитория. Занятие верхнего уровня не отняло у
     них ничего — иначе цена нового слова была бы не нулевой. */
  const модель = `утилита «Скидка»
  принимает «Заказ»
  возвращает число
  начинает с 0
  свойство «Скидка ограничена»
    результат не больше 100
`
  const программа = разобрать(модель)
  const утилита = (программа.legacy ?? []).find((узел) => узел.construct === "utility")
  assert.ok(утилита !== undefined, "утилита пропала из наследия")
  assert.equal(утилита.value.properties.length, 1)
  assert.equal("properties" in программа, false, "предел утилиты уехал в новый список")
})

test("свойство без операции и без функции отвергается разбором", () => {
  assert.throws(
    () => разобрать(`${ОСНОВА}${СТОРОЖ}\nсвойство «идемпотентность»\n  носитель «Счёт»\n`),
    /не назвало ни операции, ни функции/u,
  )
})

/* ─────────────── устройство: ДОКАЗЫВАЕТСЯ сличением объявлений ───────────── */

test("честное объявление проверку типов проходит", () => {
  assert.deepEqual(типы(ЧЕСТНАЯ).коды, [])
})

test("шестого свойства нет: неизвестное имя отвергается со списком пяти", () => {
  const итог = типы(`${ОСНОВА}${СТОРОЖ}\nсвойство «ассоциативность»\n  носитель «Счёт»\n  операция «Начислить»\n`)
  assert.deepEqual(итог.коды, ["FLANG_PROPERTY_UNKNOWN"])
  assert.match(итог.тексты.join("\n"), /их пять/u)
  assert.match(итог.тексты.join("\n"), /«идемпотентность»/u)
})

test("операция, названная несуществующей функцией, отвергается", () => {
  const итог = типы(`${ОСНОВА}${СТОРОЖ}\nсвойство «идемпотентность»\n  носитель «Счёт»\n  операция «Нету»\n`)
  assert.deepEqual(итог.коды, ["FLANG_UNKNOWN_NAME"])
})

test("вход операции обязан быть носителя, а не соседнего вида", () => {
  const итог = типы(`${ОСНОВА}${СТОРОЖ}\nсвойство «идемпотентность»\n  носитель число\n  операция «Начислить»\n`)
  assert.ok(итог.коды.includes("FLANG_TYPE"), итог.коды.join(", "))
  assert.match(итог.тексты.join("\n"), /носитель объявлен как число/u)
})

test("вторая операция есть только у дистрибутивности", () => {
  const итог = типы(`${ОСНОВА}${СТОРОЖ}\nсвойство «идемпотентность»\n  носитель «Счёт»\n  операция «Начислить»\n  по «Начислить»\n`)
  assert.deepEqual(итог.коды, ["FLANG_PROPERTY_SHAPE"])
  assert.match(итог.тексты.join("\n"), /вторая операция есть только у дистрибутивности/u)
})

test("два одинаковых объявления об одном и том же — второе отвергается", () => {
  const итог = типы(`${ЧЕСТНАЯ}${ОБЪЯВЛЕНИЕ}`)
  assert.deepEqual(итог.коды, ["FLANG_PROPERTY_TWICE"])
})

/* ───────────────────────── закон: ПРОВЕРЯЕТСЯ на сетке ───────────────────── */

test("честная функция проходит, и размер сетки уезжает в отчёт", () => {
  const итог = закон(ЧЕСТНАЯ)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked.length, 1)
  assert.ok(итог.checked[0].values > 0, "сетка пуста — проверять было не на чем")
  assert.equal(итог.checked[0].arity, 1)
  assert.deepEqual(итог.assumed, [])
})

test("ПОДДЕЛКА: забытый сторож «уже начислен» отвергается с контрпримером", () => {
  /* Ошибка, которую человек правда делает: начисление без проверки «уже
     начислено». Пример автора её НЕ ловит — он применяет функцию один раз. */
  const итог = закон(ПОДДЕЛКА)
  assert.deepEqual(итог.коды, ["FLANG_NOT_IDEMPOTENT"])
  assert.match(итог.тексты.join("\n"), /не идемпотентна/u)
  /* Контрпример предъявлен, а не спрятан за вердиктом: три числа — вход, первый
     результат и второй, — и именно они и есть вся находка. */
  assert.match(итог.тексты.join("\n"), /"начислено":100/u)
  assert.match(итог.тексты.join("\n"), /"начислено":150/u)
  assert.match(итог.тексты.join("\n"), /"начислено":200/u)
})

test("ПОДДЕЛКА: два входа — «сложить» идемпотентным не является", () => {
  /* `х ∘ х = х` на сложении: 2 + 2 = 4, а не 2. Форма с двумя входами
     проверяется своим законом, и контрпример у неё свой. */
  const исходник = `модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 5
  первое плюс второе

свойство «идемпотентность»
  носитель число
  операция «Сложить»
`
  const итог = закон(исходник)
  assert.deepEqual(итог.коды, ["FLANG_NOT_IDEMPOTENT"])
  assert.match(итог.тексты.join("\n"), /вышло 4, а обязано было выйти 2/u)
  assert.deepEqual(итог.permits, [], "разрешение выдано нарушенному свойству")
})

test("две формы закона различает ЧИСЛО ВХОДОВ, а не догадка", () => {
  const наибольшее = `модуль «Проба»

тотальная функция «Наибольшее»
  принимает первое: число, второе: число
  возвращает число
  пример «два и три»
    дано первое равно 2
    дано второе равно 3
    ожидается 3
  если первое больше второе то первое иначе второе

свойство «идемпотентность»
  носитель число
  операция «Наибольшее»
`
  const итог = закон(наибольшее)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked[0].arity, 2, "форма с двумя входами прочитана как форма с одним")
})

test("объявление без примеров уходит «на веру», а не молчит", () => {
  /* Сетка пуста — считать не на чем, и разрешения нет. Молчаливое «нарушений не
     найдено» о непосчитанном и есть та самая неправда. */
  const безПримеров = `модуль «Проба»

тотальная функция «Тождество»
  принимает вход: число
  возвращает число
  вход

свойство «идемпотентность»
  носитель число
  операция «Тождество»
`
  const итог = закон(безПримеров)
  assert.deepEqual(итог.коды, [])
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.match(итог.assumed[0].why, /сетка пуста/u)
  assert.deepEqual(итог.permits, [], "разрешение выдано на пустой сетке")
})

/* ───────────────────── что из этого следует: разрешение ──────────────────── */

test("ведомость называет закон сеткой и словами «Это не доказательство»", () => {
  const программа = разобрать(ЧЕСТНАЯ)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    idempotent: checkIdempotence(программа),
  })
  const строка = ведомость.laws.find((з) => з.kind === "идемпотентность")
  assert.ok(строка !== undefined, "закона свойства в ведомости нет вовсе")
  assert.equal(строка.name, "Начислить")
  assert.equal(строка.verdict, "grid")
  assert.match(строка.says, /Это не доказательство/u)
  assert.match(formatProofLedger(ведомость), /идемпотентность «Начислить» — сетка/u)
})

test("РАЗРЕШЕНИЕ выдано отдельной строкой, а не выведено читателем", () => {
  const программа = разобрать(ЧЕСТНАЯ)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    idempotent: checkIdempotence(программа),
  })
  assert.equal(ведомость.permits.length, 1)
  assert.equal(ведомость.permits[0].permit, "повторить")
  assert.equal(ведомость.permits[0].name, "Начислить")
  assert.match(ведомость.permits[0].says, /переслать ещё раз/u)
  assert.match(formatProofLedger(ведомость), /что из этого разрешено/u)
})

test("НАРУШЕНИЕ ОТБИРАЕТ РАЗРЕШЕНИЕ, и ведомость не говорит «нарушений не найдено»", () => {
  const программа = разобрать(ПОДДЕЛКА)
  const ведомость = proofLedger(программа, {
    totality: checkTotality(программа),
    idempotent: checkIdempotence(программа),
  })
  assert.equal(ведомость.permits, undefined, "разрешение пережило нарушение закона")
  const строка = ведомость.laws.find((з) => з.kind === "идемпотентность")
  assert.equal(строка.verdict, "broken")
  assert.match(строка.says, /НАРУШЕНО/u)
  assert.ok(!/нарушений не найдено/u.test(строка.says), "ведомость сказала о нарушенном «нарушений не найдено»")
})

test("вопрос «можно ли повторить» отвечается одной строкой и честно в обе стороны", () => {
  assert.equal(повторБезопасен(разобрать(ЧЕСТНАЯ), "Начислить"), true)
  assert.equal(повторБезопасен(разобрать(ПОДДЕЛКА), "Начислить"), false, "нарушенное свойство разрешило повтор")
  assert.equal(повторБезопасен(разобрать(`${ОСНОВА}${СТОРОЖ}`), "Начислить"), false, "не объявленное разрешило повтор")
  assert.equal(повторБезопасен(разобрать(ЧЕСТНАЯ), "Нету"), false)
})

/* ─────────────────── настоящая программа репозитория ─────────────────────── */

/* Тестом на строках проверяется, что конструкция РАБОТАЕТ; настоящим файлом —
   что ею можно ПОЛЬЗОВАТЬСЯ. Это разные утверждения. */
const ПРИМЕР = "flang/examples/cat/retry-safe.flang"
const исходникПримера = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

test("пример репозитория: два свойства объявлены и посчитаны, разрешений два", () => {
  const программа = разобрать(исходникПримера)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = checkIdempotence(программа)
  assert.deepEqual(итог.diagnostics, [], итог.diagnostics.map((б) => б.message).join("\n"))
  assert.equal(итог.checked.length, 2)
  assert.deepEqual(итог.checked.map((з) => з.arity), [1, 2], "обе формы закона на одном файле")
  assert.equal(итог.permits.length, 2)
  assert.deepEqual(итог.assumed, [])
})

test("пример репозитория: ИЗЪЯТИЕ сторожа — файл краснеет, и никто другой этого не видит", () => {
  /* Обещание из комментария самого файла, проверенное, а не стоящее словами.
     Забыть сторож «уже начислен» — ошибка, которую человек правда делает, и
     ловит её РОВНО это свойство: типы сходятся, завершение доказано, все
     оставшиеся примеры зелены. */
  const порченый = исходникПримера
    .replace(
      `  если счёт.бонус
    то счёт
    иначе запись «Счёт клиента» с начислено равным (счёт.начислено плюс 50) и бонус равным да`,
      "  запись «Счёт клиента» с начислено равным (счёт.начислено плюс 50) и бонус равным да",
    )
    .replace(
      `  пример «повторная доставка того же сообщения»
    дано счёт равно запись «Счёт клиента» с начислено равным 150 и бонус равным да
    ожидается запись «Счёт клиента» с начислено равным 150 и бонус равным да
`,
      "",
    )
  assert.notEqual(порченый, исходникПримера, "место изъятия в файле не найдено")
  const программа = разобрать(порченый)
  assert.deepEqual(checkTypes(программа).diagnostics, [], "беду увидели типы — свойство не при чём")
  assert.deepEqual(checkTotality(программа).diagnostics ?? [], [], "беду увидело завершение")
  assert.equal(runExamples(программа).failed, 0, "беду увидели примеры")
  const итог = checkIdempotence(программа)
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_NOT_IDEMPOTENT"])
  assert.equal(итог.permits.length, 1, "разрешение осталось у нарушенной операции")
})

