/**
 * Монотонность: `а ≤ б ⟹ ф(а) ≤ ф(б)`.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Функция «сколько осталось до предела», объявленная над растущим состоянием,
 * проходила `flang check --proof` со строкой «нет объявленных законов».
 * Состояние росло, ответ УБЫВАЛ — и кеш рядом отдавал бы старое значение как
 * «ещё верное». Сказать об этом языку было нечем.
 *
 * ── Что из этого следует ────────────────────────────────────────────────────
 *
 * Разрешение КЕШИРОВАТЬ: пока вход не убывает, сохранённый ответ остаётся
 * НИЖНЕЙ ГРАНИЦЕЙ нынешнего, и на ней можно строить. Без монотонности
 * сохранённый ответ не значит ничего: он мог стать и больше, и меньше.
 *
 * ── И здесь ОДНО СВОЙСТВО ОПИРАЕТСЯ НА ДРУГОЕ ───────────────────────────────
 *
 * Закон требует порядка на ОБОИХ концах функции, и берёт его только из
 * ПРОШЕДШИХ проверку. Сломанный порядок не даёт монотонности покраснеть — он
 * отправляет её строкой «на веру»: вердикт о монотонности относительно того,
 * что порядком не является, был бы утверждением ни о чём. Это проверено
 * отдельным тестом, а не оставлено словами.
 *
 * Запуск: node --test flang/test/zakon-monotone.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { runExamples } from "../src/compat.mjs"
import { checkCommutativity } from "../src/commutative.mjs"
import { checkIdempotence } from "../src/idempotent.mjs"
import { checkMonotonicity } from "../src/monotone.mjs"
import { parse } from "../src/parser.mjs"
import { checkPartialOrder } from "../src/partialorder.mjs"
import { formatProofLedger, proofLedger } from "./vedomost.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const разобрать = (исходник) => parse(исходник, "проба.flang")

function закон(исходник) {
  const итог = checkMonotonicity(разобрать(исходник))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    checked: итог.checked,
    assumed: итог.assumed,
    permits: итог.permits,
  }
}

/** Числовой порядок с примерами: сетка 0, 1, 2. */
const ПОРЯДОК = `
тотальная функция «Не больше»
  принимает первое: число, второе: число
  возвращает признак
  пример «ноль и один»
    дано первое равно 0
    дано второе равно 1
    ожидается да
  пример «один и два»
    дано первое равно 1
    дано второе равно 2
    ожидается да
  первое не больше второе

свойство «частичный порядок»
  носитель число
  операция «Не больше»
`

function сФункцией(тело) {
  return `модуль «Проба»

тотальная функция «Ответ»
  принимает вход: число
  возвращает число
${тело}
${ПОРЯДОК}
свойство «монотонность»
  функция «Ответ»
`
}

const ЧЕСТНАЯ = сФункцией("  вход умножить на 2")

/* ────────────────────────── улика: было молчание ─────────────────────────── */

test("УЛИКА ДО: убывающий ответ на растущем входе проходил молча", () => {
  const безСвойства = `модуль «Проба»

тотальная функция «Сколько осталось»
  принимает набрано: число
  возвращает число
  пример «набрано два»
    дано набрано равно 2
    ожидается 98
  100 минус набрано
`
  const программа = разобрать(безСвойства)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.equal(runExamples(программа).failed, 0)
  const ведомость = proofLedger(программа, { totality: checkTotality(программа) })
  assert.deepEqual(ведомость.laws, [])
  assert.match(formatProofLedger(ведомость), /нет объявленных законов/u)
})

/* ─────────────── устройство: ДОКАЗЫВАЕТСЯ сличением объявлений ───────────── */

test("монотонность объявляется ФУНКЦИЕЙ, а не операцией", () => {
  const итог = checkTypes(разобрать(`модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

свойство «монотонность»
  носитель число
  операция «Сложить»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_PROPERTY_SHAPE"])
  assert.match(итог.diagnostics[0].message, /монотонность объявляется строкой 'функция/u)
})

test("носитель у монотонности лишний: концы у функции свои", () => {
  const итог = checkTypes(разобрать(`модуль «Проба»

тотальная функция «Ответ»
  принимает вход: число
  возвращает число
  вход

свойство «монотонность»
  носитель число
  функция «Ответ»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_PROPERTY_SHAPE"])
  assert.match(итог.diagnostics[0].message, /носитель здесь лишний/u)
})

test("функция двух входов монотонной не объявляется", () => {
  const итог = checkTypes(разобрать(`модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

свойство «монотонность»
  функция «Сложить»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_PROPERTY_SHAPE"])
  assert.match(итог.diagnostics[0].message, /принимает 2 арг., а обязана один/u)
})

/* ───────────────────────── закон: ПРОВЕРЯЕТСЯ на сетке ───────────────────── */

test("честная функция проходит, и разрешение кешировать выдано", () => {
  const итог = закон(ЧЕСТНАЯ)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked.length, 1)
  assert.ok(итог.checked[0].comparable > 0, "сравнимых пар не нашлось — закон не проверялся")
  assert.equal(итог.permits.length, 1)
  assert.match(итог.permits[0].says, /нижней границей нынешнего/u)
})

test("ПОДДЕЛКА: убывающая функция отвергается с предъявленной парой и образами", () => {
  const итог = закон(сФункцией("  100 минус вход"))
  assert.deepEqual(итог.коды, ["FLANG_NOT_MONOTONE"])
  assert.match(итог.тексты.join("\n"), /не монотонна: 0 не больше 1 по «Не больше», а образы — 100 и 99/u)
  assert.match(итог.тексты.join("\n"), /Кешировать ответ такой функции нельзя/u)
  assert.deepEqual(итог.permits, [])
})

test("НЕСРАВНИМЫЕ ПАРЫ ЗАКОН НЕ ЗАДЕВАЮТ, и они посчитаны отдельным числом", () => {
  /* Посылка `а ≤ б` на несравнимой паре ложна, и закон о таких парах не
     утверждает ничего. Считать их проверенными значило бы завышать силу
     проверки ровно на них. */
  const итог = закон(ЧЕСТНАЯ)
  assert.ok(итог.checked[0].comparable < итог.checked[0].points,
    "сравнимых столько же, сколько пар — отдельное число ничего не различает")
})

/* ───────── сломанное свойство ОСТАНАВЛИВАЕТ зависящее от него ────────────── */

test("ПОРЯДКА НЕТ ВОВСЕ — монотонность уходит «на веру», а не молчит и не краснеет", () => {
  const безПорядка = `модуль «Проба»

тотальная функция «Ответ»
  принимает вход: число
  возвращает число
  пример «два»
    дано вход равно 2
    ожидается 4
  вход умножить на 2

свойство «монотонность»
  функция «Ответ»
`
  const итог = закон(безПорядка)
  assert.deepEqual(итог.коды, [])
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.match(итог.assumed[0].why, /здорового частичного порядка на входе/u)
  assert.deepEqual(итог.permits, [])
})

test("ПОРЯДОК ОБЪЯВЛЕН, НО НАРУШЕН — монотонность НЕ СЧИТАЕТСЯ: вердикт был бы ни о чём", () => {
  /* Второе обязательство работы целиком: сломанное свойство останавливает
     зависящие от него. Отношение «строго меньше» не рефлексивно, значит
     порядком не является; сказать «функция монотонна относительно него» —
     значит сказать утверждение о том, что порядком не является. */
  const сломанный = сФункцией("  вход умножить на 2").replace(
    "  первое не больше второе",
    "  первое меньше второе",
  )
  assert.deepEqual(checkPartialOrder(разобрать(сломанный)).diagnostics.map((б) => б.code),
    ["FLANG_ORDER_NOT_REFLEXIVE"], "подделка порядка не сработала — тест говорит не о том")
  const итог = закон(сломанный)
  assert.deepEqual(итог.коды, [], "монотонность покраснела на непорядке — это вердикт ни о чём")
  assert.deepEqual(итог.checked, [], "монотонность посчитана относительно того, что порядком не является")
  assert.equal(итог.assumed.length, 1)
  assert.match(итог.assumed[0].why, /порядок объявленный и нарушенный монотонности не годится/u)
  assert.deepEqual(итог.permits, [], "разрешение выдано относительно непорядка")
})

test("СРАВНИМЫХ ПАР НОЛЬ — это «на веру», а не «нарушений не найдено»", () => {
  /* Случай редкий и потому опасный: посылка `а ≤ б` не выполнилась НИ РАЗУ, и
     вердикт «нарушений не найдено» был бы утверждением ни о чём.

     Собирается он так. Отношение здорово на СВОЕЙ сетке (0, 1, 2), но выше двух
     не рефлексивно; у функции при этом двенадцать своих значений, и они
     упираются в предел сетки, вытесняя чужие целиком. Ни одна пара из
     оставшихся сравнимой не оказывается — и сказать об этом надо словами. */
  const примеры = Array.from({ length: 12 }, (_, номер) => {
    const вход = 100 + номер
    return `  пример «п${номер}»\n    дано вход равно ${вход}\n    ожидается ${вход * 2}\n`
  }).join("")
  const исходник = `модуль «Проба»

тотальная функция «Ответ»
  принимает вход: число
  возвращает число
${примеры}  вход умножить на 2

тотальная функция «Не больше и не выше двух»
  принимает первое: число, второе: число
  возвращает признак
  пример «ноль и один»
    дано первое равно 0
    дано второе равно 1
    ожидается да
  пример «один и два»
    дано первое равно 1
    дано второе равно 2
    ожидается да
  (первое не больше второе) и притом (второе не больше 2)

свойство «частичный порядок»
  носитель число
  операция «Не больше и не выше двух»

свойство «монотонность»
  функция «Ответ»
`
  assert.deepEqual(checkPartialOrder(разобрать(исходник)).diagnostics, [],
    "отношение оказалось не порядком — тест говорит не о том")
  const итог = закон(исходник)
  assert.deepEqual(итог.коды, [])
  assert.deepEqual(итог.checked, [], "непроверенное посчитано проверенным")
  assert.equal(итог.assumed.length, 1)
  assert.match(итог.assumed[0].why, /сравнимых пар не нашлось/u)
  assert.deepEqual(итог.permits, [], "разрешение выдано за ноль проверенных пар")
})

/* ─────────────────── настоящая программа репозитория ─────────────────────── */

const ПРИМЕР = "flang/examples/cat/crdt-merge.flang"
const исходникПримера = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

test("пример репозитория: чтение монотонно, разрешение кешировать выдано", () => {
  const программа = разобрать(исходникПримера)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = checkMonotonicity(программа)
  assert.deepEqual(итог.diagnostics, [], итог.diagnostics.map((б) => б.message).join("\n"))
  assert.equal(итог.checked.length, 1)
  assert.equal(итог.permits.length, 1)
  assert.equal(итог.checked[0].grids, 2, "сеток у монотонности две — домена и кодомена")
})

test("пример репозитория: ИЗЪЯТИЕ — «остаток» вместо «набрано» ломает РОВНО монотонность", () => {
  /* Ошибка, которую человек правда делает: обычная правка от продукта — на
     экране показывают остаток, а не набранное. Она молча переворачивает
     свойство, на котором стоит кеш. Типы, завершение, все девять примеров
     (автор поправит ожидаемые значения вместе с телом), порядок, слияние —
     всё зелено. */
  const порченый = исходникПримера
    .replace("  счётчики.первая плюс счётчики.вторая", "  100 минус (счётчики.первая плюс счётчики.вторая)")
    .replace("    ожидается 2\n", "    ожидается 98\n")
    .replace("    ожидается 10\n", "    ожидается 90\n")
  assert.notEqual(порченый, исходникПримера, "место изъятия в файле не найдено")
  const программа = разобрать(порченый)
  assert.deepEqual(checkTypes(программа).diagnostics, [], "беду увидели типы")
  assert.deepEqual(checkTotality(программа).diagnostics ?? [], [], "беду увидело завершение")
  assert.equal(runExamples(программа).failed, 0, "беду увидели примеры")
  assert.deepEqual(checkPartialOrder(программа).diagnostics, [], "беду увидел порядок")
  assert.deepEqual(checkIdempotence(программа).diagnostics, [], "беду увидела идемпотентность")
  assert.deepEqual(checkCommutativity(программа).diagnostics, [], "беду увидела коммутативность")
  const итог = checkMonotonicity(программа)
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_NOT_MONOTONE"])
  assert.match(итог.diagnostics[0].message, /образы — 98 и 90/u)
  assert.deepEqual(итог.permits, [], "разрешение кешировать пережило нарушение")
})

test("пример репозитория: сломай ПОРЯДОК — монотонность уходит «на веру», а не краснеет", () => {
  /* Обещание из комментария самого файла, проверенное, а не стоящее словами. */
  const порченый = исходникПримера.replace(
    "  (первый.первая не больше второй.первая) и притом (первый.вторая не больше второй.вторая)",
    "  первый.первая меньше второй.первая",
  )
  assert.notEqual(порченый, исходникПримера)
  const программа = разобрать(порченый)
  assert.deepEqual(checkPartialOrder(программа).diagnostics.map((б) => б.code), ["FLANG_ORDER_NOT_REFLEXIVE"])
  const итог = checkMonotonicity(программа)
  assert.deepEqual(итог.diagnostics, [])
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.deepEqual(итог.permits, [])
})
