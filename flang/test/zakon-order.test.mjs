/**
 * Частичный порядок: рефлексивность, антисимметрия, транзитивность.
 *
 * ── Улика, снятая прогоном ДО работы ────────────────────────────────────────
 *
 * Отношение «Не старше», написанное СТРОГИМ сравнением, проходило
 * `flang check --proof` со строкой «нет объявленных законов». Отношение, при
 * котором значение не сравнимо само с собой, порядком не является ни при каком
 * прочтении — а сказать это языку было нечем.
 *
 * ── Что из этого следует ────────────────────────────────────────────────────
 *
 * Разрешение СРАВНИВАТЬ СОСТОЯНИЯ — основание под состояниями, сходящимися без
 * блокировок. Из трёх законов следует, что согласие реплик не зависит от
 * порядка, в котором к ним приходили обновления. Без антисимметрии остаётся
 * ПРЕДПОРЯДОК, и на нём расхождение двух реплик становится законным.
 *
 * Запуск: node --test flang/test/zakon-order.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { runExamples } from "../src/compat.mjs"
import { checkCommutativity } from "../src/commutative.mjs"
import { checkIdempotence } from "../src/idempotent.mjs"
import { parse } from "../src/parser.mjs"
import { checkPartialOrder, здоровыеПорядки } from "../src/partialorder.mjs"
import { formatProofLedger, proofLedger } from "../src/proof.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"

const разобрать = (исходник) => parse(исходник, "проба.flang")

function закон(исходник) {
  const итог = checkPartialOrder(разобрать(исходник))
  return {
    коды: итог.diagnostics.map((беда) => беда.code),
    тексты: итог.diagnostics.map((беда) => беда.message),
    checked: итог.checked,
    assumed: итог.assumed,
    permits: итог.permits,
  }
}

/** Отношение на числах с телом автора и примерами, задающими сетку 0, 1, 2. */
function отношение(тело) {
  return `модуль «Проба»

тотальная функция «Не старше»
  принимает первое: число, второе: число
  возвращает признак
  пример «ноль и один»
    дано первое равно 0
    дано второе равно 1
    ожидается да
  пример «один и два»
    дано первое равно 1
    дано второе равно 2
    ожидается да
${тело}

свойство «частичный порядок»
  носитель число
  операция «Не старше»
`
}

const ЧЕСТНОЕ = отношение("  первое не больше второе")

/* ────────────────────────── улика: было молчание ─────────────────────────── */

test("УЛИКА ДО: строгое сравнение не рефлексивно, и никто об этом не говорил", () => {
  const безСвойства = `модуль «Проба»

тотальная функция «Не старше»
  принимает первое: число, второе: число
  возвращает признак
  пример «ноль и один»
    дано первое равно 0
    дано второе равно 1
    ожидается да
  первое меньше второе
`
  const программа = разобрать(безСвойства)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  assert.equal(runExamples(программа).failed, 0)
  const ведомость = proofLedger(программа, { totality: checkTotality(программа) })
  assert.deepEqual(ведомость.laws, [])
  assert.match(formatProofLedger(ведомость), /нет объявленных законов/u)
})

/* ─────────────── устройство: ДОКАЗЫВАЕТСЯ сличением объявлений ───────────── */

test("отношение обязано возвращать признак: возвращающее число отвергается", () => {
  const итог = checkTypes(разобрать(`модуль «Проба»

тотальная функция «Сравнить»
  принимает первое: число, второе: число
  возвращает число
  первое минус второе

свойство «частичный порядок»
  носитель число
  операция «Сравнить»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_TYPE"])
  assert.match(итог.diagnostics[0].message, /возвращает число, а обязана признак/u)
})

/* ───────────────────────── закон: ПРОВЕРЯЕТСЯ на сетке ───────────────────── */

test("честное «не больше» проходит все три закона", () => {
  const итог = закон(ЧЕСТНОЕ)
  assert.deepEqual(итог.коды, [])
  assert.equal(итог.checked.length, 1)
  assert.ok(итог.checked[0].points > 0)
  assert.equal(итог.permits.length, 1)
  assert.match(итог.permits[0].says, /не зависит от порядка/u)
})

test("ПОДДЕЛКА: строгое «меньше» не рефлексивно — с предъявленным значением", () => {
  const итог = закон(отношение("  первое меньше второе"))
  assert.deepEqual(итог.коды, ["FLANG_ORDER_NOT_REFLEXIVE"])
  assert.match(итог.тексты.join("\n"), /не рефлексивно: 0 не сравнимо с самим собой/u)
  assert.deepEqual(итог.permits, [])
})

test("ПОДДЕЛКА: «всегда да» — предпорядок, а не порядок: краснеет антисимметрия", () => {
  /* Рефлексивно и транзитивно, а порядком не является. Именно этот случай и
     есть та беда, ради которой антисимметрия проверяется отдельно: две
     разошедшиеся реплики объявляются взаимно «не старше». */
  const итог = закон(отношение("  да"))
  assert.deepEqual(итог.коды, ["FLANG_ORDER_NOT_ANTISYMMETRIC"])
  assert.match(итог.тексты.join("\n"), /сравнимы в обе стороны, но не равны/u)
  assert.match(итог.тексты.join("\n"), /предпорядок, а не порядок/u)
})

test("ПОДДЕЛКА: «отличаются не больше чем на единицу» — краснеет транзитивность", () => {
  /* Отношение обязано быть рефлексивным и АНТИСИММЕТРИЧНЫМ, иначе краснело бы
     не то: сломайся оно раньше третьего закона — и о транзитивности проверка
     промолчала бы по своему же правилу «сломанное останавливает остальные».
     «Не больше, и разница не больше единицы» подходит: 0 ≤ 1 ≤ 2, а 0 и 2 уже
     не сравнимы. */
  const итог = закон(отношение("  (первое не больше второе) и притом ((второе минус первое) не больше 1)"))
  assert.deepEqual(итог.коды, ["FLANG_ORDER_NOT_TRANSITIVE"])
  assert.match(итог.тексты.join("\n"), /не транзитивно: 0 не старше 1, 1 не старше 2, а 0 и 2 — нет/u)
})

test("СЛОМАННЫЙ ЗАКОН ОСТАНАВЛИВАЕТ ОСТАЛЬНЫЕ, а не считается заодно", () => {
  /* Отношение, оказавшееся не рефлексивным, порядком не является; всё, что о
     нём сказали бы антисимметрия и транзитивность, было бы утверждением о том,
     что порядком не является. Значит СТОП, и в отчёте это видно числом. */
  const итог = закон(отношение("  первое меньше второе"))
  assert.deepEqual(итог.коды, ["FLANG_ORDER_NOT_REFLEXIVE"])
  assert.equal(итог.checked.length, 1)
  assert.equal(итог.checked[0].points, 1, "после нарушения посчитали ещё что-то")
})

test("результат отношения обязан быть признаком и на СЕТКЕ, а не только по объявлению", () => {
  /* Объявление обещает признак, а вернуть значение иного вида на конкретном
     значении сетки функция всё же может — тогда закон не нарушен, а НЕ ПОСЧИТАН,
     и сказать надо именно это. */
  const итог = закон(ЧЕСТНОЕ)
  assert.equal(итог.checked[0].aborted, undefined)
})

test("объявление без примеров уходит «на веру», а не молчит", () => {
  const итог = закон(`модуль «Проба»

тотальная функция «Не старше»
  принимает первое: число, второе: число
  возвращает признак
  первое не больше второе

свойство «частичный порядок»
  носитель число
  операция «Не старше»
`)
  assert.deepEqual(итог.checked, [])
  assert.equal(итог.assumed.length, 1)
  assert.deepEqual(итог.permits, [])
})

test("сетка порядка берётся ТОЛЬКО ИЗ ВХОДОВ: признаки в неё не попадают", () => {
  /* Ожидаемое значение примера у отношения — `да`/`нет`, и положить его в сетку
     значений носителя значило бы считать порядок на признаках. */
  const итог = закон(ЧЕСТНОЕ)
  assert.equal(итог.checked[0].values, 3, "в сетке оказалось не три числа 0, 1, 2")
})

/* ────────── дверь для монотонности: здоровые порядки по носителю ─────────── */

test("здоровыеПорядки отдают ПРОШЕДШИЙ порядок по ключу типа", () => {
  const карта = здоровыеПорядки(разобрать(ЧЕСТНОЕ))
  assert.equal(карта.size, 1)
  assert.equal(карта.get("number")?.операция, "Не старше")
})

test("НАРУШЕННЫЙ ПОРЯДОК ИЗ ЗДОРОВЫХ ВЫПАДАЕТ — на нём монотонности сказать нечего", () => {
  assert.equal(здоровыеПорядки(разобрать(отношение("  первое меньше второе"))).size, 0)
})

/* ─────────────────── настоящая программа репозитория ─────────────────────── */

const ПРИМЕР = "flang/examples/cat/crdt-merge.flang"
const исходникПримера = readFileSync(new URL(`../../${ПРИМЕР}`, import.meta.url), "utf8")

test("пример репозитория: покомпонентный порядок посчитан, разрешение выдано", () => {
  const программа = разобрать(исходникПримера)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  const итог = checkPartialOrder(программа)
  assert.deepEqual(итог.diagnostics, [], итог.diagnostics.map((б) => б.message).join("\n"))
  assert.equal(итог.checked.length, 1)
  assert.equal(итог.permits.length, 1)
})

test("пример репозитория: ИЗЪЯТИЕ второй половины условия — краснеет одна антисимметрия", () => {
  /* Ошибка, которую человек правда делает: потерять вторую половину условия при
     копировании строки. И вот что здесь главное — она НЕ ЛОМАЕТ НИ ОДНОГО
     ПРИМЕРА автора: все три написаны на парах, где первый счётчик решает исход
     сам. Типы сходятся, завершение доказано, идемпотентность и коммутативность
     слияния чисты. Находка приходит на паре, которую автор нигде не писал:
     (1,1) и (1,5) взяты из РАЗНЫХ примеров и сведены вместе сеткой. */
  const порченый = исходникПримера.replace(
    "  (первый.первая не больше второй.первая) и притом (первый.вторая не больше второй.вторая)",
    "  первый.первая не больше второй.первая",
  )
  assert.notEqual(порченый, исходникПримера, "место изъятия в файле не найдено")
  const программа = разобрать(порченый)
  assert.deepEqual(checkTypes(программа).diagnostics, [], "беду увидели типы")
  assert.deepEqual(checkTotality(программа).diagnostics ?? [], [], "беду увидело завершение")
  assert.equal(runExamples(программа).failed, 0, "беду увидели примеры")
  assert.deepEqual(checkIdempotence(программа).diagnostics, [], "беду увидела идемпотентность")
  assert.deepEqual(checkCommutativity(программа).diagnostics, [], "беду увидела коммутативность")
  const итог = checkPartialOrder(программа)
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_ORDER_NOT_ANTISYMMETRIC"])
  assert.match(итог.diagnostics[0].message, /"первая":1,"вторая":1/u)
  assert.match(итог.diagnostics[0].message, /"первая":1,"вторая":5/u)
  assert.deepEqual(итог.permits, [], "разрешение пережило нарушение")
})

test("пример репозитория: ИЗЪЯТИЕ объявления — закон уходит в молчание", () => {
  const без = исходникПримера.replace(
    /\nсвойство «частичный порядок»\n {2}носитель[^\n]*\n {2}операция[^\n]*\n/u,
    "\n",
  )
  assert.notEqual(без, исходникПримера, "строк объявления в файле не найдено")
  const итог = checkPartialOrder(разобрать(без))
  assert.deepEqual(итог.checked, [])
  assert.deepEqual(итог.permits, [])
})
