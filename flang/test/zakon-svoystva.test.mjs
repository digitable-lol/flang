/**
 * Пять объявляемых свойств — то, что у них общее.
 *
 * Законы каждого проверяются своим файлом (`zakon-idempotent`,
 * `zakon-commutative`, `zakon-distributive`, `zakon-order`, `zakon-monotone`).
 * Здесь — то, что обязано быть верно про ВСЕ пятеро сразу и про их место в
 * языке:
 *
 *   1. АКСИОМ ПО-ПРЕЖНЕМУ НОЛЬ. Работа со слоем законов не имеет права
 *      добавить ядру ни одного решающего правила, и это проверяется числом, а
 *      не обещанием в шапке;
 *   2. свойств ровно пять, и словарь у разбора, проверки типов и ведомости
 *      ОДИН. Два списка разошлись бы молча;
 *   3. ни одно новое слово не занято: `свойство` на верхнем уровне было
 *      ошибкой разбора, а внутри утилиты работает как работало;
 *   4. программа без свойств не задета — ни в AST, ни в ведомости;
 *   5. у каждого свойства СВОЁ разрешение, и все пять различны. Пять
 *      одинаковых разрешений означали бы, что различать свойства незачем;
 *   6. все пять настоящих примеров дерева проходят полную проверку.
 *
 * Запуск: node --test flang/test/zakon-svoystva.test.mjs
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { externalChecks, loadProgram } from "../bin/flang.mjs"
import { checkCommutativity } from "../src/commutative.mjs"
import { checkDistributivity } from "../src/distributive.mjs"
import { checkIdempotence } from "../src/idempotent.mjs"
import { checkMonotonicity } from "../src/monotone.mjs"
import { parse } from "../src/parser.mjs"
import { checkPartialOrder } from "../src/partialorder.mjs"
import { formatProofLedger, proofLedger } from "./vedomost.mjs"
import { АКСИОМЫ } from "../src/proofterm.mjs"
import { СВОЙСТВА } from "../src/svoystva.mjs"
import { checkTotality } from "../src/totality.mjs"
import { checkTypes } from "../src/types.mjs"
/* Выборка своя, не из `node:fs`: тамошний `globSync` появился только в Node 22,
   а пакет обещает Node ≥ 20. Тот же довод, что у остальных сверок корпуса. */
import { globSync } from "./glob.mjs"

const корень = fileURLToPath(new URL("../..", import.meta.url))
const разобрать = (исходник) => parse(исходник, "проба.flang")

/** Пять настоящих программ репозитория, объявляющих свойства. */
const ПРИМЕРЫ = [
  "flang/examples/cat/retry-safe.flang",
  "flang/examples/cat/fold-by-cores.flang",
  "flang/examples/cat/split-lines.flang",
  "flang/examples/cat/crdt-merge.flang",
]

/* ─────────────────────────── 1. ядро не расширено ────────────────────────── */

test("ЯДРО НЕ РАСШИРЕНО: аксиом по-прежнему ноль", () => {
  /* Пять новых законов — это слой ЗАКОНОВ, а не решающих правил. Свойство,
     потребовавшее аксиомы, было бы не свойством, а допущением под чужим именем:
     из аксиомы ядро выводит, и вывод этот проверить нечем. Число здесь
     единственное честное — ноль. */
  assert.deepEqual(АКСИОМЫ, [], "у ядра появилась аксиома — работа со слоем законов её не вправе заводить")
})

test("ЯДРО НЕ РАСШИРЕНО: ни один из пяти модулей не трогает proofterm.mjs", () => {
  /* Второе полукольцо того же утверждения, и оно про зависимости, а не про
     список: модуль законов, импортирующий ядро, рано или поздно начнёт ему
     что-нибудь подсказывать. */
  for (const имя of ["idempotent", "commutative", "distributive", "partialorder", "monotone", "svoystva"]) {
    const исходник = readFileSync(join(корень, `flang/src/${имя}.mjs`), "utf8")
    assert.ok(!/from "\.\/proofterm\.mjs"/u.test(исходник), `${имя}.mjs импортирует ядро`)
    assert.ok(!/from "\.\/obligations\.mjs"/u.test(исходник), `${имя}.mjs импортирует обязательства`)
  }
})

/* ───────────────────────── 2. словарь один на всех ───────────────────────── */

test("свойств ровно пять, и словарь у всех один", () => {
  assert.deepEqual(Object.keys(СВОЙСТВА), [
    "дистрибутивность", "идемпотентность", "частичный порядок", "монотонность", "коммутативность",
  ])
  /* Проверка типов читает ТОТ ЖЕ словарь: шестое имя отвергается, и в тексте
     отказа перечислены все пять. Разойдись два списка — устройство сверялось бы
     по одному, а закон по другому. */
  const итог = checkTypes(разобрать(`модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе

свойство «ассоциативность»
  носитель число
  операция «Сложить»
`))
  assert.deepEqual(итог.diagnostics.map((б) => б.code), ["FLANG_PROPERTY_UNKNOWN"])
  for (const имя of Object.keys(СВОЙСТВА)) {
    assert.match(итог.diagnostics[0].message, new RegExp(`«${имя}»`, "u"))
  }
})

/* ────────────────── 3. ни одного нового слова: цена нулевая ──────────────── */

test("СЛОВО ЗАНЯТО ТАМ, ГДЕ БЫЛА ОШИБКА: верхнеуровневого `свойство` в дереве не было", () => {
  /* Замер, ради которого и написан `flang/scripts/word-occupancy.mjs`, — но
     здесь он исполняется, а не стоит в комментарии. Считается не текст, а
     СТРОКА, начинающаяся со слова: ключевым `свойство` было и раньше, менялось
     только место, где оно допустимо. */
  const файлы = [
    ...globSync("**/*.flang", { cwd: корень, exclude: (путь) => путь.includes("node_modules") }),
    ...globSync("**/*.fts", { cwd: корень, exclude: (путь) => путь.includes("node_modules") }),
  ]
  assert.ok(файлы.length >= 150, `корпус ужался до ${файлы.length} файлов`)
  let сверху = 0
  let внутри = 0
  const наши = new Set(ПРИМЕРЫ)
  for (const путь of файлы) {
    const текст = readFileSync(`${корень}${путь}`, "utf8")
    for (const строка of текст.split("\n")) {
      if (/^свойство\b/u.test(строка) && !наши.has(путь.replace(/^\//u, ""))) сверху += 1
      if (/^\s+свойство\s+«/u.test(строка)) внутри += 1
    }
  }
  assert.equal(сверху, 0, "верхнеуровневое `свойство` было занято чужой программой")
  assert.ok(внутри >= 60, `предел утилиты пропал из корпуса: ${внутри} строк`)
})

test("`свойство` ВНУТРИ утилиты разбирается как разбиралось", () => {
  const программа = разобрать(`утилита «Скидка»
  принимает «Заказ»
  возвращает число
  начинает с 0
  свойство «Скидка ограничена»
    результат не больше 100
`)
  const утилита = (программа.legacy ?? []).find((узел) => узел.construct === "utility")
  assert.equal(утилита.value.properties.length, 1)
  assert.equal("properties" in программа, false, "предел утилиты уехал в новый список")
})

/* ─────────────── 4. программа без свойств не задета ни в чём ─────────────── */

test("AST и ведомость программы без свойств остаются прежними", () => {
  const исходник = `модуль «Проба»

тотальная функция «Сложить»
  принимает первое: число, второе: число
  возвращает число
  первое плюс второе
`
  const программа = разобрать(исходник)
  assert.equal("properties" in программа, false)
  const ведомость = proofLedger(программа, { totality: checkTotality(программа) })
  assert.equal(ведомость.permits, undefined, "раздел разрешений появился у программы, ничего не объявлявшей")
  assert.ok(!/что из этого разрешено/u.test(formatProofLedger(ведомость)))
})

/* ────────────── 5. у каждого свойства СВОЁ разрешение, и они разные ──────── */

test("ПЯТЬ СВОЙСТВ — ПЯТЬ РАЗНЫХ РАЗРЕШЕНИЙ, а не пять строк одного вида", () => {
  /* Свойство, из которого следует то же, что из соседнего, языку не нужно:
     различать их было бы незачем. Значит слова разрешений обязаны быть
     различны, и это проверяется, а не подразумевается. */
  const собрано = new Set()
  for (const путь of ПРИМЕРЫ) {
    const программа = разобрать(readFileSync(join(корень, путь), "utf8"))
    for (const проверка of [checkIdempotence, checkCommutativity, checkDistributivity,
      checkPartialOrder, checkMonotonicity]) {
      for (const запись of проверка(программа).permits) собрано.add(запись.permit)
    }
  }
  assert.deepEqual([...собрано].sort(), ["кешировать", "повторить", "разложить", "переписать", "сравнить"].sort())
})

/* ──────── 6. минимум и максимум: не синтетика, а корпусный идиом ─────────── */

test("МИНИМУМ ВЫДЕРЖИВАЕТ ТРИ СВОЙСТВА ТАМ, ГДЕ СЛОЖЕНИЕ ЛОМАЕТСЯ — на тех же десятичных", () => {
  /* Довод соседней работы (`work/beskonechnost`), проверенный здесь своими
     законами. Сложение и умножение на десятичных дробях школьным правилам не
     подчиняются: они ВЫЧИСЛЯЮТ новое значение, и округление двойной точности
     ломает и ассоциативность (402 нарушения на тринадцати значениях — измерено
     там), и дистрибутивность (измерено здесь,
     `flang/test/zakon-distributive.test.mjs`).
     Минимум и максимум ведут себя иначе, и разница механическая: они не
     вычисляют, а ВЫБИРАЮТ операнд, значит округлять нечего. Поэтому носитель
     это честный, а не удобный: `если первое меньше второе то первое иначе
     второе` — ровно то тело, которым `stdlib/lists.flang` сворачивает
     «Минимум» и «Максимум», написанное руками и до всякой этой работы. */
  const крайние = `модуль «Проба»

тотальная функция «Наименьшее»
  принимает первое: число, второе: число
  возвращает число
  пример «десятые»
    дано первое равно 0.1
    дано второе равно 0.2
    ожидается 0.1
  пример «три десятых и семь»
    дано первое равно 0.3
    дано второе равно 0.7
    ожидается 0.3
  если первое меньше второе то первое иначе второе

тотальная функция «Не больше»
  принимает первое: число, второе: число
  возвращает признак
  пример «десятые»
    дано первое равно 0.1
    дано второе равно 0.2
    ожидается да
  пример «три десятых и семь»
    дано первое равно 0.3
    дано второе равно 0.7
    ожидается да
  первое не больше второе

свойство «идемпотентность»
  носитель число
  операция «Наименьшее»

свойство «коммутативность»
  носитель число
  операция «Наименьшее»

свойство «частичный порядок»
  носитель число
  операция «Не больше»
`
  const программа = разобрать(крайние)
  assert.deepEqual(checkTypes(программа).diagnostics, [])
  for (const [имя, проверка] of [
    ["идемпотентность", checkIdempotence],
    ["коммутативность", checkCommutativity],
    ["частичный порядок", checkPartialOrder],
  ]) {
    const итог = проверка(программа)
    assert.deepEqual(итог.diagnostics, [], `${имя}: ${итог.diagnostics.map((б) => б.message).join("\n")}`)
    assert.equal(итог.permits.length, 1, `${имя}: разрешения нет`)
  }
})

/* ──────────────── 7. все настоящие примеры проходят целиком ──────────────── */

test("все настоящие примеры дерева проходят полную проверку и печатают разрешения", async (t) => {
  let сверено = 0
  for (const путь of ПРИМЕРЫ) {
    const программа = await loadProgram(join(корень, путь))
    const внешнее = await externalChecks(программа)
    assert.deepEqual(
      внешнее.diagnostics.filter((б) => б?.severity !== "warning"),
      [],
      `${путь}: программа с отказом`,
    )
    const ведомость = proofLedger(программа, внешнее.results)
    assert.ok(Array.isArray(ведомость.permits) && ведомость.permits.length > 0,
      `${путь}: свойства объявлены, а разрешений нет ни одного`)
    /* Каждая строка закона обязана оканчиваться той самой оговоркой: сетка
       конечна, и продавать перебор за доказательство нельзя. */
    for (const закон of ведомость.laws) {
      assert.match(закон.says, /Это не доказательство$/u, `${путь}: закон «${закон.name}» без оговорки`)
    }
    assert.match(formatProofLedger(ведомость), /что из этого разрешено \(сетка конечна, разрешение — тоже\)/u)
    сверено += 1
  }
  t.diagnostic(`примеров сверено: ${сверено}`)
  assert.equal(сверено, ПРИМЕРЫ.length, "корпус примеров схлопнулся")
})
