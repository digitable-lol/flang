/**
 * ЗАПИСЬ ОТВЕТОВ ЯРУСА ОРАКУЛОВ ЗАМОРОЖЕНА ДО УДАЛЕНИЯ СВИДЕТЕЛЯ.
 *
 * На ярусе законов свидетеля стёрли, и вместе со сверкой ушли 36 порч: они
 * сравнивали два оракула, и без второго сравнивать стало не с чем. Здесь тот же
 * шаг делается в обратном порядке: сперва снята запись ответов
 * (`flang/scripts/snyat-zapis-oracula.mjs` -> `fixtures/zapis-oracula.json`),
 * и только потом можно удалять `src/setoid.mjs`, `src/sets.mjs`,
 * `src/factcheck.mjs`, `src/functor.mjs`.
 *
 * ЧТО ДЕРЖИТ ПРОВЕРКА СЕЙЧАС — пока свидетель ещё в дереве: свидетель обязан
 * отвечать ровно то, что записано. Односторонняя правка свидетеля краснеет.
 *
 * ЧТО ОНА БУДЕТ ДЕРЖАТЬ ПОСЛЕ УДАЛЕНИЯ: сторона на flang обязана отвечать то же
 * самое. Переключить проверку — значит поменять один импорт: вместо
 * `СВИДЕТЕЛИ` подставить вызовы слоя. Числа при этом трогать НЕЛЬЗЯ: они
 * заморожены раньше и в том и весь смысл.
 *
 * ЧЕГО ЗАПИСЬ НЕ ДЕЛАЕТ, и это надо помнить: она отвечает только про корпус дня
 * съёмки, не растёт вместе с языком и может быть переснята. Пересъёмка обязана
 * быть отдельным коммитом с названной причиной — отпечаток делает её видимой в
 * диффе одной строкой.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { СВИДЕТЕЛИ, канон, пусто, снять, файлыКорпуса } from "../scripts/snyat-zapis-oracula.mjs"

const записьФайл = fileURLToPath(new URL("./fixtures/zapis-oracula.json", import.meta.url))
const запись = JSON.parse(readFileSync(записьФайл, "utf8"))

/* Сверка идёт по списку путей САМОЙ ЗАПИСИ. Новая программа в стволе не
   краснит запись — она просто в неё не входит; про рост корпуса говорит
   отдельное утверждение ниже. */
const свежая = await снять(запись.пути)

test("запись снята НЕ на пустом корпусе: программ и свидетелей названо числом", (t) => {
  assert.ok(запись.программ >= 280, `программ в записи ${запись.программ}`)
  assert.equal(запись.свидетелей, Object.keys(СВИДЕТЕЛИ).length)
  assert.equal(запись.свидетелей, 4)
  assert.equal(типОтпечатка(запись.отпечаток), true, "отпечаток не похож на sha256")
  t.diagnostic(
    `запись: программ ${запись.программ}, свидетелей ${запись.свидетелей}, ` +
      `непустых ответов на ${запись.непустых} программах`,
  )
})

function типОтпечатка(строка) {
  return typeof строка === "string" && /^[0-9a-f]{64}$/u.test(строка)
}

test("ни одна записанная программа не исчезла из дерева", () => {
  assert.equal(
    свежая.программ,
    запись.программ,
    `разобралось сегодня ${свежая.программ} из записанных ${запись.программ} — программа исчезла или перестала разбираться`,
  )
})

/* Рост корпуса — не красный, а сведение: запись отвечает про свой список, и
   новые программы в неё не входят до пересъёмки. */
test("рост корпуса назван числом, а не принят за расхождение", (t) => {
  const сегодня = файлыКорпуса.length
  t.diagnostic(`корпус сегодня ${сегодня} файлов, в записи ${запись.пути.length} разобранных программ`)
  assert.ok(сегодня >= запись.пути.length, `корпус усох: ${сегодня} против ${запись.пути.length}`)
})

test("ОТПЕЧАТОК СОВПАДАЕТ: ответы яруса те же, что заморожены до удаления", () => {
  assert.equal(
    свежая.отпечаток,
    запись.отпечаток,
    "ответы яруса оракулов разошлись с замороженной записью.\n" +
      "Это НЕ повод переснять запись. Сначала назвать, что изменилось и почему;\n" +
      "пересъёмка — отдельный коммит с причиной, а не правка заодно.",
  )
})

test("непустые ответы совпадают пофайлово, а не только отпечатком", () => {
  const былиПути = Object.keys(запись.непустые).sort()
  const сталиПути = Object.keys(свежая.непустые).sort()
  assert.deepEqual(сталиПути, былиПути, "список программ с непустым ответом яруса изменился")
  for (const путь of былиПути) {
    assert.deepEqual(свежая.непустые[путь], запись.непустые[путь], `${путь}: ответ яруса разошёлся с записью`)
  }
})

/**
 * ПОРЧА: сверка обязана краснеть.
 *
 * Проверка, которая перестала сравнивать, зеленеет так же, как исправная, — и
 * это уже случалось в дереве семь раз за двое суток. Здесь порча ставится не в
 * свидетеля (его вот-вот не будет), а в саму запись: если подменить один
 * записанный ответ, сверка обязана назвать расхождение.
 */
test("ИЗЪЯТИЕ: подменённый ответ в записи краснеет", () => {
  const путь = Object.keys(запись.непустые)[0]
  assert.ok(путь, "в записи нет ни одного непустого ответа — сверять нечего")
  const порченая = JSON.parse(JSON.stringify(запись.непустые))
  порченая[путь] = { ...порченая[путь], setoid: { diagnostics: ["нарочно"], checked: [], assumed: [] } }
  assert.notDeepEqual(свежая.непустые[путь], порченая[путь], `${путь}: порча прошла незамеченной`)
})

test("ИЗЪЯТИЕ: отпечаток чувствителен к одному знаку", () => {
  const подменённый = запись.отпечаток.slice(0, -1) + (запись.отпечаток.endsWith("0") ? "1" : "0")
  assert.notEqual(подменённый, запись.отпечаток, "порча ничего не заменила — сама порча устарела")
  assert.notEqual(свежая.отпечаток, подменённый, "сверка отпечатка приняла подмену")
})

/**
 * Пустой ответ отделён от непустого не на глаз, а правилом, и правило проверено:
 * иначе в запись попали бы все 284 программы, и она стала бы нечитаемой ради
 * нуля сведений.
 */
test("правило пустоты отделяет «сказать нечего» от настоящего ответа", () => {
  assert.equal(пусто({ diagnostics: [], checked: [], assumed: [] }), true)
  assert.equal(пусто({ ok: true, results: [] }), true)
  assert.equal(пусто({ diagnostics: [{ code: "X" }], checked: [], assumed: [] }), false)
  assert.equal(пусто({ ok: false, results: [] }), false)
  assert.ok(запись.непустых < запись.программ, "непустыми оказались все — правило пустоты не сработало")
})

test("канон устойчив: порядок ключей ответа не меняет записи", () => {
  assert.equal(JSON.stringify(канон({ б: 1, а: 2 })), JSON.stringify(канон({ а: 2, б: 1 })))
  assert.ok(файлыКорпуса.length >= 280, `файлов корпуса ${файлыКорпуса.length}`)
})
