/**
 * ЗАПИСЬ ОТВЕТОВ СТЁРТОГО ЭТАЛОНА — свидетель побайтовой сверки ведомости.
 *
 * ── Чем это стало и чем было ────────────────────────────────────────────────
 *
 * Побайтовая сверка сравнивает ДВЕ реализации. `flang/src/proof.mjs` — ведомость
 * доказательства на JavaScript — стёрт по решению владельца, и сравнивать
 * близнеца стало не с чем: подставь сюда тот же слой на flang, и
 * `self-proof.test.mjs` сравнивал бы близнеца с самим собой, зеленея вечно и не
 * проверяя ничего. Это ровно тот дефект, из-за которого в этом дереве за сутки
 * нашли четырнадцать проверок, зеленевших впустую.
 *
 * Поэтому свидетелем стала ЗАПИСЬ: ответы эталона, снятые прогоном самой сверки
 * ДО удаления, сложены в `vedomost-etalona.json` и отдаются отсюда с теми же
 * подписями, что были у эталона. Ни одна строка утверждений в
 * `self-proof.test.mjs` не изменилась — изменилась одна строка ввоза.
 *
 * ── ЧЕГО ЭТО СТОИТ, ЧЕСТНО ──────────────────────────────────────────────────
 *
 * Запись — снимок, а не вторая реализация, и разница не косметическая:
 *
 *   1. ОБЩУЮ ОШИБКУ ЗАМЫСЛА она не ловит — но её не ловила и сверка двух
 *      реализаций: близнец писался ПО эталону.
 *   2. ЗАПИСЬ МОЖНО ПЕРЕСНЯТЬ. Сломай близнеца и пересними запись — сверка
 *      позеленеет. Эталон переписать так же тихо было нельзя: пришлось бы
 *      править 1 300 строк чужой реализации до того же неверного ответа.
 *      ЭТО ГЛАВНАЯ ПОТЕРЯ, и её не закрывает ничто, кроме дисциплины: пересъёмка
 *      обязана быть отдельным вливанием с названной причиной.
 *   3. НОВЫЙ ВОПРОС ОСТАЁТСЯ БЕЗ ОТВЕТА. Спросили то, чего в записи нет, —
 *      это КРАСНОЕ, а не «пропущено». Молчание запрещено ниже явно: промах
 *      срывает вызов, а не возвращает пустое.
 *
 * Чего запись НЕ теряет: она снята с ВХОДОВ, а не с выходов близнеца. Изменись
 * мост `итогиВедомости` в `flang/src/self.mjs` или разбор программы — ключ
 * поменяется, ответа не найдётся, и сверка покраснеет. То есть снос вокруг
 * ведомости запись видит.
 *
 * ── Как её пересобрать ──────────────────────────────────────────────────────
 *
 * Эталона в дереве больше нет, поэтому пересъёмка требует вернуть его из
 * истории:
 *
 *   git show <вливание-до-удаления>:flang/src/proof.mjs > flang/src/proof.mjs
 *   FLANG_ZAPIS_VEDOMOSTI=snyat node --test flang/test/self-proof.test.mjs
 *   FLANG_ZAPIS_VEDOMOSTI=snyat node --test flang/test/self-cli.test.mjs
 *   rm flang/src/proof.mjs
 *
 * СНИМАТЬ ФАЙЛЫ ПО ОДНОМУ, ДВУМЯ ПРОГОНАМИ — так и написано выше про
 * дополнение записи, но грабли стоит назвать прямо, потому что наступают на
 * них молча. `node --test` с двумя файлами разом запускает их РАЗНЫМИ
 * процессами; каждый читает запись при загрузке, дописывает своё и пишет файл
 * целиком — и тот, кто закончил вторым, затирает добавленное первым. Красное
 * от этого выглядит как «нет ответа на этот вопрос» у теста, который при
 * съёмке был зелёным, и ищется долго. Проверять после съёмки счётом:
 * `ОТВЕТОВ_В_ЗАПИСИ` обязан вырасти на столько вопросов, сколько их прибавилось.
 *
 * Вливание названо в `vedomost-etalona.json` полем «снято с».
 */
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const файлЗаписи = fileURLToPath(new URL("./vedomost-etalona.json", import.meta.url))

/** Режим съёмки: ответы считает вернувшийся эталон и они складываются в запись. */
const СНИМАЕМ = process.env.FLANG_ZAPIS_VEDOMOSTI === "snyat"

/**
 * Ключ вопроса — отпечаток ВХОДОВ, а не выходов.
 *
 * Берётся ровно то, что эталон получал аргументами. Ключ по выходу близнеца
 * сделал бы запись бесполезной: она соглашалась бы с любым его ответом.
 */
function ключ(программа, результаты) {
  const слепок = JSON.stringify([программа, результаты ?? {}])
  return createHash("sha256").update(слепок).digest("hex")
}

/* В СЪЁМКЕ запись ДОПОЛНЯЕТСЯ, а не заводится заново: снимают её две разные
   проверки разными прогонами, и чистый лист во втором прогоне стёр бы ответы
   первого молча. */
const запись = JSON.parse(readFileSync(файлЗаписи, "utf8"))

const эталон = СНИМАЕМ ? await import("../../src/proof.mjs") : null

/** Ведомость значением — той же подписью, что у стёртого эталона. */
export function proofLedger(программа, результаты) {
  const к = ключ(программа, результаты)
  if (СНИМАЕМ) {
    const ответ = эталон.proofLedger(программа, результаты)
    запись["ответов"][к] = { "значением": ответ, "словами": эталон.formatProofLedger(ответ) }
    сохранить()
    return ответ
  }
  const найдено = запись["ответов"][к]
  if (найдено === undefined) {
    throw new Error(
      `в записи эталона нет ответа на этот вопрос (${к.slice(0, 12)}): сверка спросила то, чего не спрашивала ` +
        "при съёмке. Это КРАСНОЕ, а не «пропущено»: либо изменились входы, либо появилась новая сверка — " +
        "пересними запись по указаниям в шапке flang/test/zapis/vedomost-etalona.mjs",
    )
  }
  тексты.set(найдено["значением"], найдено["словами"])
  return найдено["значением"]
}

/** Текст человеку — по значению, которое вернул `proofLedger`. */
const тексты = new WeakMap()

export function formatProofLedger(ведомость) {
  if (СНИМАЕМ) return эталон.formatProofLedger(ведомость)
  const текст = тексты.get(ведомость)
  if (текст === undefined) {
    throw new Error(
      "`formatProofLedger` позвали не с ответом `proofLedger`: запись хранит текст рядом со значением, " +
        "и собрать его из чужого значения нечем",
    )
  }
  return текст
}

function сохранить() {
  writeFileSync(файлЗаписи, `${JSON.stringify(запись, null, 1)}\n`, "utf8")
}

/**
 * ОТПЕЧАТОК вместо полного ответа — второй ярус записи, и он для широты.
 *
 * Полный ответ эталона весит около 19 КБ на программу. Двадцать шесть отобранных
 * программ `self-proof.test.mjs` в полном виде стоят 938 КБ и окупаются: по ним
 * видно, ГДЕ разошлось. Семьдесят одна программа `self-cli.test.mjs` в полном
 * виде стоила бы 10 МБ — за широту, которой у первой сверки нет, но такой ценой,
 * какой репозиторию её брать нельзя.
 *
 * Поэтому для широкого корпуса записан ОТПЕЧАТОК: sha256 машинного вида и
 * sha256 текста. Что теряется, названо прямо: расхождение краснеет, но показать
 * знак расхождения запись не может — за этим придётся вернуть эталон из истории.
 * Что не теряется: любое изменение хоть в одном знаке обоих видов краснеет.
 */
export function отпечатокЭталона(программа, результаты) {
  const к = ключ(программа, результаты)
  if (СНИМАЕМ) {
    const ответ = эталон.proofLedger(программа, результаты)
    запись["отпечатков"][к] = {
      "значением": отпечаток(JSON.stringify(ответ)),
      "словами": отпечаток(эталон.formatProofLedger(ответ)),
    }
    сохранить()
    return запись["отпечатков"][к]
  }
  const найдено = запись["отпечатков"][к]
  if (найдено === undefined) {
    throw new Error(
      `в записи эталона нет отпечатка на этот вопрос (${к.slice(0, 12)}): сверка спросила то, чего не ` +
        "спрашивала при съёмке. Это КРАСНОЕ, а не «пропущено» — пересними запись по указаниям в шапке",
    )
  }
  return найдено
}

/** Отпечаток одной строки. Тем же способом, каким считается ключ. */
export const отпечаток = (текст) => createHash("sha256").update(текст).digest("hex")

/** Сколько ответов лежит в записи. Наружу — ради утверждения «запись не пуста». */
export const ОТВЕТОВ_В_ЗАПИСИ = Object.keys(запись["ответов"]).length
export const ОТПЕЧАТКОВ_В_ЗАПИСИ = Object.keys(запись["отпечатков"]).length
