/**
 * Сторож спецификации слоя отказов — `docs/спецификации/слой-отказов.flang`.
 *
 * ── Зачем он есть ───────────────────────────────────────────────────────────
 * Спека без сторожа — это проза в другом синтаксисе, и расходится она с деревом
 * ровно так же молча. В этом дереве под расхождение прозы с деревом уже заведён
 * отдельный сторож (`npm run counts:check`), и он красный. Спека обязана
 * краснеть сама.
 *
 * Сводится ЧЕТЫРЕ вещи, и каждая — равенством множеств в обе стороны:
 *
 *   1. Виды отказа и коды. Правила утилиты «Код отказа» против `ВИДЫ_ОТКАЗА` и
 *      `КОДЫ_ОТКАЗА` из `src/failures.mjs`. Односторонняя проверка («всё, что в
 *      спеке, есть в дереве») пропустила бы одиннадцатый вид молча — а слой рос
 *      именно так: пятый вид приехал шагом А3, шестой — уже после того, как всё
 *      объявили сделанным.
 *   2. Частичные встроенные формы. Правила утилиты «Почему форма частична»
 *      против `ЧАСТИЧНЫЕ` — вместе с ПРИЧИНОЙ, а не только с именем.
 *   3. Объекты предметной области. Поля `объект`-ов спеки доезжают до проверки
 *      типов, и это единственная часть поверхности FTS, которая доезжает хоть
 *      до чего-нибудь.
 *   4. Сама спека остаётся живой программой: `flang check` зелёный, `flang test`
 *      зелёный, примеры действительно прогнаны.
 *
 * ── Что этот сторож НЕ стережёт, и это сказано, а не умолчано ───────────────
 * Утилиту FTS не исполняет никто: `свойство` и `пример` внутри неё не гоняются
 * ни одной командой языка (улика — последний тест файла и
 * `docs/спецификации/чего-не-хватает-fts.md`). Значит сторож сверяет ТАБЛИЦУ
 * правил как данные, а не поведение утилиты. Утверждать больше — значило бы
 * называть проверенным то, что никем не проверено.
 */
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { readFileSync } from "node:fs"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { ВИДЫ_ОТКАЗА, КОДЫ_ОТКАЗА, ЧАСТИЧНЫЕ } from "../src/failures.mjs"
import { parse } from "../src/parser.mjs"

const КОРЕНЬ = fileURLToPath(new URL("../..", import.meta.url))
const СПЕКА = fileURLToPath(new URL("../../docs/спецификации/слой-отказов.flang", import.meta.url))
const CLI = fileURLToPath(new URL("../bin/flang.mjs", import.meta.url))

const программа = parse(readFileSync(СПЕКА, "utf8"), "слой-отказов.flang")

/** Узел `ftsLegacy` вида `utility` по имени. */
function утилита(имя) {
  const узел = (программа.legacy ?? []).find((у) => у.construct === "utility" && у.value?.name === имя)
  assert.ok(узел, `в спеке нет утилиты «${имя}» — спека и сторож разошлись именами`)
  return узел.value
}

/**
 * Таблица правил утилиты как отображение «значение условия → значение действия».
 *
 * Форма правила закреплена намеренно: одно условие на равенство одного поля и
 * действие «результат равен литералу». Правило другой формы — не «немного
 * другое», а утверждение, которого этот сторож прочесть не умеет, и молча
 * пропустить его нельзя.
 */
function таблица(имяУтилиты, поле) {
  const итог = new Map()
  for (const правило of утилита(имяУтилиты).rules) {
    assert.equal(правило.when.length, 1, `правило «${правило.name}»: сторож читает ровно одно условие`)
    const условие = правило.when[0]
    assert.equal(условие.field, поле, `правило «${правило.name}»: условие не про поле «${поле}»`)
    assert.equal(условие.operator, "eq", `правило «${правило.name}»: сторож читает только равенство`)
    assert.equal(условие.value.kind, "value", `правило «${правило.name}»: слева от «равен» ожидается литерал`)
    assert.equal(правило.action.kind, "set", `правило «${правило.name}»: сторож читает только «результат равен …»`)
    assert.equal(правило.action.value.kind, "value", `правило «${правило.name}»: справа ожидается литерал`)
    assert.ok(!итог.has(условие.value.value), `правило «${правило.name}»: условие повторяется`)
    итог.set(условие.value.value, правило.action.value.value)
  }
  return итог
}

/** Разность множеств обеими сторонами — обе половины обязательны. */
function свести(что, вСпеке, вДереве) {
  const лишние = [...вСпеке].filter((к) => !вДереве.has(к))
  const недостача = [...вДереве].filter((к) => !вСпеке.has(к))
  assert.deepEqual(
    лишние,
    [],
    `${что}: спека называет то, чего в дереве нет — ${лишние.join(", ")}. ` +
      "Правьте спеку, а не сторожа: измеритель — это дерево.",
  )
  assert.deepEqual(
    недостача,
    [],
    `${что}: дерево знает то, чего в спеке нет — ${недостача.join(", ")}. ` +
      "Новый вид отказа обязан быть назван спекой, а не тихо проехать мимо неё.",
  )
}

test("виды отказа: спека и failures.mjs — одно и то же множество", () => {
  const вСпеке = таблица("Код отказа", "вид")
  const вДереве = new Set(Object.values(ВИДЫ_ОТКАЗА))
  свести("виды отказа", new Set(вСпеке.keys()), вДереве)
  assert.equal(вСпеке.size, вДереве.size, "число видов разошлось")
})

test("код каждого вида: спека и failures.mjs — тот же код", () => {
  const вСпеке = таблица("Код отказа", "вид")
  for (const [вид, код] of вСпеке)
    assert.equal(код, КОДЫ_ОТКАЗА[вид], `вид «${вид}»: спека обещает ${код}, дерево выдаёт ${КОДЫ_ОТКАЗА[вид]}`)
  /* И обратно: код дерева без вида в спеке — та же беда, только с другой
     стороны. `КОДЫ_ОТКАЗА` заведён ровно затем, чтобы вид без кода не проехал
     молча; здесь то же требование предъявляется спеке. */
  свести("коды отказа", new Set(вСпеке.values()), new Set(Object.values(КОДЫ_ОТКАЗА)))
})

test("частичные встроенные формы: спека и failures.mjs — то же множество и та же причина", () => {
  const вСпеке = таблица("Почему форма частична", "имя")
  свести("частичные формы", new Set(вСпеке.keys()), new Set(ЧАСТИЧНЫЕ.keys()))
  for (const [имя, причина] of вСпеке)
    assert.equal(причина, ЧАСТИЧНЫЕ.get(имя), `форма «${имя}»: спека называет причиной «${причина}»`)
  assert.equal(вСпеке.size, ЧАСТИЧНЫЕ.size, "число частичных форм разошлось")
})

test("объекты предметной области доезжают до проверки типов", () => {
  const типы = new Map(программа.types.map((т) => [т.name, т]))
  for (const имя of ["Отказ процесса", "Частичная форма"])
    assert.ok(типы.has(имя), `объект «${имя}» не стал типом — поверхность FTS разошлась с разборщиком`)
  const поля = типы.get("Отказ процесса").fields.map((п) => п.name)
  assert.deepEqual(поля, ["вид", "код", "покрыт"], "поля объекта «Отказ процесса» разошлись со спекой")
})

test("спека остаётся живой программой: check зелёный, примеры прогнаны", () => {
  const проверка = JSON.parse(execFileSync(process.execPath, [CLI, "check", СПЕКА], { cwd: КОРЕНЬ }).toString())
  assert.equal(проверка.valid, true)
  assert.equal(проверка.module, "Слой отказов")

  const прогон = JSON.parse(execFileSync(process.execPath, [CLI, "test", СПЕКА], { cwd: КОРЕНЬ }).toString())
  assert.equal(прогон.failed, 0, "примеры спеки не сошлись")
  assert.ok(прогон.passed > 0, "спека без единого прогнанного примера ничего не обещает")
})

/**
 * ДЫРА, названная прогоном, а не рассуждением.
 *
 * Внутри утилиты «Код отказа» объявлены `свойство` и `пример`. Ни то, ни другое
 * не исполняется: `flang test` считает только примеры настоящих функций. Тест
 * это ПРЕДЪЯВЛЯЕТ, а не обходит: он требует, чтобы число прогнанных примеров
 * равнялось числу примеров настоящих функций и НЕ включало примеров утилит.
 *
 * Если он покраснеет — это хорошая новость: язык научился исполнять утилиты
 * FTS. Тогда обновите спеку и снимите этот тест, а не наоборот.
 */
test("ДЫРА: примеры и свойства внутри утилиты FTS не исполняются ничем", () => {
  const примеровУФункций = программа.functions.reduce((с, ф) => с + (ф.examples?.length ?? 0), 0)
  const примеровУУтилит = (программа.legacy ?? [])
    .filter((у) => у.construct === "utility")
    .reduce((с, у) => с + у.value.examples.length, 0)
  const свойствУУтилит = (программа.legacy ?? [])
    .filter((у) => у.construct === "utility")
    .reduce((с, у) => с + у.value.properties.length, 0)
  assert.ok(примеровУУтилит > 0, "спека обязана держать хотя бы один пример утилиты — иначе дыру нечем показать")
  assert.ok(свойствУУтилит > 0, "то же про свойство утилиты")

  const прогон = JSON.parse(execFileSync(process.execPath, [CLI, "test", СПЕКА], { cwd: КОРЕНЬ }).toString())
  assert.equal(
    прогон.total,
    примеровУФункций,
    `прогнано ${прогон.total} примеров при ${примеровУФункций} у функций и ${примеровУУтилит} у утилит: ` +
      "если это покраснело — язык начал исполнять утилиты FTS, и спеку надо переписать на них",
  )
})
