# ПРИМЕРЫ `flang/self/` — обходчик и ведомость.
#
# ── Зачем он заведён ────────────────────────────────────────────────────────
#
# Примеров в `flang/self/**.flang` — 4445 штук в 61 файле, и до 5 сентября
# 2026 их не гонял НИКТО. Замер, а не догадка:
#
#   · шаг «Примеры stdlib и ядра» (`binary.yml`) зовёт `flang test` ровно на
#     `flang/stdlib/` и `flang/core/`. Каталога `flang/self/` в нём нет;
#   · единственная работа, которая дошла бы до него, — `korpus`
#     (`flang test . --ledger` внутри `обход-примеров.sh`). Она закрыта
#     условием «тег или рука», а на трёх последних тегах (v0.7.8, v0.7.9,
#     v0.7.10, 4 сентября 2026) ЖОБ `corpus-examples` УПАЛ, не дойдя до
#     сверки: прогон 33883535490 шёл 2 ч 26 мин и был снят раннером
#     («The runner has received a shutdown signal») посреди «Прогона примеров
#     исходников»;
#   · её ведомость `ведомость-примеров.txt` последний раз писалась 24 августа
#     (`0eec94a7`): она держит ТРИ числа в строке вместо нынешних ЧЕТЫРЁХ и
#     знает 41 файл `flang/self/` из 61. То есть разошлась бы на каждой строке,
#     если бы её вообще сверяли.
#
# Отсюда правило этого файла: он НЕ ходит по всему дереву и не зависит ни от
# тега, ни от руки. Он гоняет названный список файлов `flang/self/` на КАЖДОМ
# пуше и укладывается в измеренное время.
#
# ── Что сверяется, и почему четырьмя числами ────────────────────────────────
#
# `flang test <файл> --ledger` печатает строку `путь<TAB>всего прошло сорвалось
# СВОИХ`. Все четыре нужны, и вот зачем каждое:
#
#   всего/прошло/сорвалось — упавший пример. Голого кода возврата хватило бы,
#                            но только его;
#   СВОИХ                  — сколько примеров у САМОГО файла, а не ввезённых по
#                            «использует». Без него слой, потерявший все свои
#                            примеры, зеленеет чужими: строка «881 881 0» у
#                            `grid.flang` — это 857 чужих примеров и 24 своих,
#                            и потеря своих двадцати четырёх в ней не видна;
#   список путей целиком   — файл, который двоичный перестал брать, отдаёт ноль
#                            примеров и ноль отказов, то есть выглядит чистым.
#
# ── ПОЧЕМУ ПОФАЙЛОВО, А НЕ `flang test flang/self/` ─────────────────────────
#
# Потому что одним процессом каталог не идёт, и это замерено: `flang test
# flang/self/ --ledger` на 256-ядерной машине за 41 мин 55 с не напечатал НИ
# ОДНОЙ строки и занял 34,0 ГБ, после чего снят рукой. У раннера GitHub
# 15,61 ГиБ. Пофайлово пик держится на 6,7 ГиБ (`proofterm.flang`).
#
# ── Чего он НЕ сторожит, числом ─────────────────────────────────────────────
#
# Полный пофайловый обход стоит 2 ч 25 мин на шестидесяти файлах из 61 (замер
# 5 сентября 2026, эта машина, `/usr/bin/time` по каждому), а шестьдесят
# первый — `bootstrap/compiler.flang` — за 50 мин 46 с не ответил и занял до
# 33 ГБ, снят рукой. Столько на каждый пуш не кладут, поэтому под присмотром
# ЧАСТЬ, и она названа поимённо в ведомости: 55 мин 05 с на 43 файла
# (замер этого же обходчика ключом `--write`). Кто не под присмотром — там же,
# строкой «вне присмотра N», где N — число СВОИХ примеров файла.
#
# Отбор не на глаз: под присмотр взят файл, у которого свой пример стоит
# дешевле трёх секунд прогона, — и сверх того `proofterm.flang`, потому что
# именно его примеры и оказались мёртвыми, а увидеть это может только он сам.
#
# Дорого здесь НЕ проверка типов и НЕ прогон примеров по отдельности: `flang
# check` тех же файлов стоит столько же, сколько `flang test` (emit-c 59 с
# против 50 с, emit-csharp 91 с против 75 с). Дорог ПОВТОРНЫЙ разбор
# ввезённого замыкания: у `obligations.flang` своих примеров четыре, а прогон
# берёт 598 с, потому что вместе с ним едут 969 примеров ядра доказательства.
# Файлы, которые ввозят `proof-kernel.flang`/`proof-initial.flang`, стоят по
# 5–10 минут каждый — они и вынесены за присмотр первыми.
#
#   sh flang/проверки/обход-self.sh              — сверить с ведомостью
#   sh flang/проверки/обход-self.sh --write      — перезаписать ведомость
#   sh flang/проверки/обход-self.sh --подлог     — проба порчи, обе стороны
#
# ── Проба порчи ─────────────────────────────────────────────────────────────
#
# `--подлог` берёт КОПИЮ `flang/self/mcp.flang` во временный каталог ВНЕ
# дерева, ломает в ней один пример и требует от обходчика кода 1 и внятного
# слова; потом ту же копию без порчи — и требует кода 0. Дерево не портится ни
# на секунду: соседний прогон на общей машине увидел бы подлог и записал бы его
# как находку. Ввоз при этом разрешается по дереву, а не по каталогу файла, —
# проверено прогоном, копия вне дерева считается ровно так же.
set -eu
LC_ALL=C.UTF-8
export LC_ALL

root=$(cd "$(dirname "$0")/../.." && pwd)
# Имя выхода сборки — `flang`, именем языка. `flang_cli` принимается тоже: в
# дереве, где сборка была до переименования, он лежит с прежним именем.
tool=${FLANG_BIN:-"$root/bootstrap/flang"}
[ -x "$tool" ] || tool="$root/bootstrap/flang_cli"
ledger="$root/flang/проверки/ведомость-self.txt"

if [ ! -x "$tool" ]; then
  echo "обходчик self: нет двоичного «$tool». Собрать: make -C bootstrap" >&2
  exit 2
fi

# Число СВОИХ примеров файла — тем же образцом, каким его считает пятый прибор
# сторожа чисел прозы (`scripts/prose-numbers-guard.sh`, `primerov_v`).
svoih() { grep -ac '^ *пример «' "$1" 2>/dev/null || true; }

# ── Один проход: прогнать под присмотром, собрать ведомость ─────────────────
#
# $1 — файл ведомости, по которому берётся СПИСОК; $2 — куда писать новую.
# Пути читаются ИЗ ВЕДОМОСТИ, а не из каталога: ведомость и есть список того,
# что под присмотром, и второго места правды заводить незачем.
obojti() {
  vedomost=$1; kuda=$2
  : > "$kuda"
  while IFS='	' read -r put hvost; do
    [ -n "$put" ] || continue
    case $hvost in
      'вне присмотра'*)
        printf '%s\t%s %s\n' "$put" 'вне присмотра' "$(svoih "$root/$put")" >> "$kuda" ;;
      *)
        # Ненулевой код здесь ожидаем и не останавливает обход: упавший файл
        # обязан попасть в ведомость своей строкой, иначе разойдётся СПИСОК, а
        # не число, и отказ назовёт не ту беду.
        progon "$put" >> "$kuda" || true ;;
    esac
  done < "$vedomost"
}

# Один файл. Ключ `--ledger` печатает СТРОКУ ВЕДОМОСТИ и глотает разбор: у
# сорвавшегося примера остаётся третье число и ни слова о том, какой это был
# пример. Красный код без имени сломанного — половина сторожа, поэтому при
# ненулевом коде файл гоняется второй раз БЕЗ ключа, ради имени. Второй прогон
# бывает только на красном пути и цены зелёному не прибавляет.
progon() {
  kod=0
  ( cd "$root" && "$tool" test "$1" --ledger ) || kod=$?
  if [ "$kod" -ne 0 ]; then
    ( cd "$root" && "$tool" test "$1" >/dev/null ) || true
  fi
  return "$kod"
}

rezhim=${1:-}

# ── `--подлог`: обе стороны прогоном ────────────────────────────────────────
if [ "$rezhim" = "--подлог" ]; then
  obrazec=$root/flang/self/mcp.flang
  # Якорь — строка примера, а не номер строки: список примеров растёт, и
  # подлог, прибитый к числу, молча перестал бы собираться.
  yakor='    ожидается "flang"'
  if [ "$(grep -c -x -- "$yakor" "$obrazec" || true)" != "1" ]; then
    echo "ПОДЛОГ НЕ СОБРАЛСЯ: якоря «$yakor» в $obrazec уже нет или он не один — поправить подлог, сторож ни при чём" >&2
    exit 1
  fi
  TMP=$(mktemp -d "${FLANG_TMP:-${TMPDIR:-/tmp}}/self-podlog.XXXXXX")
  trap 'rm -rf "$TMP"' EXIT INT TERM
  cp "$obrazec" "$TMP/mcp.flang"

  echo '── сторона первая: пример испорчен, ждём код 1 ──'
  sed -i 's/^    ожидается "flang"$/    ожидается "flang-podlog"/' "$TMP/mcp.flang"
  if cmp -s "$obrazec" "$TMP/mcp.flang"; then
    echo "ПОДЛОГ НЕ СОБРАЛСЯ: копия не изменилась — поправить подлог, сторож ни при чём" >&2
    exit 1
  fi
  kod=0
  slovo=$( progon "$TMP/mcp.flang" 2>&1 ) || kod=$?
  printf '%s\n' "$slovo"
  if [ "$kod" -eq 0 ]; then
    echo 'СТОРОЖ ЗЕЛЁН НА ПОДЛОГЕ — он не проверяет ничего.' >&2
    exit 1
  fi
  [ "$kod" -eq 1 ] || { printf 'ждали код 1, получили %s\n' "$kod" >&2; exit 1; }
  # Красный код без имени сломанного примера — половина сторожа: по такому
  # отказу нельзя понять, что чинить.
  case $slovo in
    *'пример «Имя службы» функции «Имя службы MCP» не прошёл'*) : ;;
    *) echo 'СТОРОЖ ПОКРАСНЕЛ МОЛЧА — имени сломанного примера в отказе нет.' >&2; exit 1 ;;
  esac
  echo "код $kod, и сломанный пример назван по имени — краснеет, как и должен"

  echo
  echo '── сторона вторая: порча снята, ждём код 0 ──'
  cp "$obrazec" "$TMP/mcp.flang"
  kod=0
  ( cd "$root" && "$tool" test "$TMP/mcp.flang" --ledger ) || kod=$?
  [ "$kod" -eq 0 ] || { printf 'ждали код 0, получили %s\n' "$kod" >&2; exit 1; }
  echo "код $kod — зеленеет, как и должен"

  echo
  echo 'обе стороны показаны прогоном.'
  exit 0
fi

if [ ! -f "$ledger" ]; then
  echo "обходчик self: нет ведомости «$ledger»" >&2
  exit 2
fi

# ── СПИСОК ФАЙЛОВ ДЕРЕВА ПРОТИВ СПИСКА ВЕДОМОСТИ ────────────────────────────
#
# Новый файл в `flang/self/`, которого нет в ведомости, — это примеры, за
# которыми не смотрит никто, и молчать о них нельзя: ровно так каталог и
# оказался неохраняемым. Пропавший — тоже красно: ведомость стала неправдой.
derevo=$(mktemp); vved=$(mktemp); nov=$(mktemp)
trap 'rm -f "$derevo" "$vved" "$nov"' EXIT INT TERM

( cd "$root" && find flang/self -name '*.flang' | sort ) > "$derevo"
cut -f1 "$ledger" | sort > "$vved"

if [ "$rezhim" = "--write" ]; then
  # ПРИ ПЕРЕСЪЁМКЕ НОВЫЙ ФАЙЛ ПОПАДАЕТ ПОД ПРИСМОТР, А НЕ МИМО НЕГО. Умолчание
  # выбрано в ту сторону нарочно: каталог оказался неохраняемым ровно потому,
  # что попасть мимо сторожа можно было молча. Теперь молча можно только ПОД
  # него, а вынести файл из-под присмотра — отдельная правка руками, и она
  # видна диффом.
  spisok=$(mktemp)
  awk -F'\t' 'NR == FNR { est[$1] = $2; next }
       { print $1 "\t" (($1 in est) ? est[$1] : "0 0 0 0") }' "$ledger" "$derevo" > "$spisok"
  novyh=$(comm -13 "$vved" "$derevo" | wc -l | tr -d ' ')
  proshlyh=$(comm -23 "$vved" "$derevo" | wc -l | tr -d ' ')
  [ "$novyh" = "0" ] || { echo "обходчик self: НОВЫХ ФАЙЛОВ $novyh, взяты ПОД ПРИСМОТР:"; comm -13 "$vved" "$derevo" | sed 's|^|  · |'; }
  [ "$proshlyh" = "0" ] || { echo "обходчик self: ПРОПАЛО ИЗ ДЕРЕВА $proshlyh, строки убраны:"; comm -23 "$vved" "$derevo" | sed 's|^|  · |'; }
  obojti "$spisok" "$nov"
  rm -f "$spisok"
  sort -o "$nov" "$nov"
  cp "$nov" "$ledger"
  echo "обходчик self: ведомость записана"
  exit 0
fi

if ! propalo=$(diff "$vved" "$derevo"); then
  echo "$propalo"
  echo "обходчик self: СПИСОК ФАЙЛОВ РАЗОШЁЛСЯ — «<» пропал из дерева, «>» появился и ни в ведомости, ни под присмотром. Переснять: sh flang/проверки/обход-self.sh --write" >&2
  exit 1
fi

obojti "$ledger" "$nov"
sort -o "$nov" "$nov"
sort -o "$ledger.sorted" "$ledger" 2>/dev/null || cp "$ledger" "$ledger.sorted"
if ! diff -u "$ledger.sorted" "$nov"; then
  rm -f "$ledger.sorted"
  echo "обходчик self: ВЕДОМОСТЬ РАЗОШЛАСЬ — выше видно, какой файл потерял примеры или уронил их" >&2
  exit 1
fi
rm -f "$ledger.sorted"

# ── Итог: и то, что под присмотром, и долг ──────────────────────────────────
#
# Долг печатается ВСЕГДА и числом. Сторож, молчащий о своих границах, врёт
# самим фактом зелёного вывода.
#
# Долг меньше числа строк «вне присмотра», и это не поблажка: ПОЛНЫЙ ВВОЗ
# («использует «М»» и ничего после ёлочки) тянет за собой ВСЕ примеры
# зависимости, поэтому файл без своей строки всё же прогоняется, если его
# ввозит целиком кто-то поднадзорный. Проверено прогоном: `emit-elixir.flang`
# при своих 88 примерах отдаёт 224, потому что ввозит целиком `defunc.flang`
# со ста тридцатью четырьмя. Ввоз «только» так не считается: он берёт
# названные имена, а не файл, и примеры остальных функций не едут.
pod=$(awk -F'\t' '$2 !~ /^вне присмотра/' "$nov" | wc -l | tr -d ' ')
primerov=$(awk -F'\t' '$2 !~ /^вне присмотра/{split($2,p," "); s+=p[1]} END{print s+0}' "$nov")
proshlo=$(awk -F'\t' '$2 !~ /^вне присмотра/{split($2,p," "); s+=p[2]} END{print s+0}' "$nov")
svoih_pod=$(awk -F'\t' '$2 !~ /^вне присмотра/{split($2,p," "); s+=p[4]} END{print s+0}' "$nov")

# Карта «модуль → файл» и рёбра полного ввоза. Имя модуля стоит первой строкой
# файла — так требует язык, гадать не приходится.
graf=$(mktemp)
( cd "$root" && for f in $(find flang/self -name '*.flang' | sort); do
    m=$(sed -n '1s/^модуль «\(.*\)».*$/\1/p' "$f")
    [ -n "$m" ] && printf 'M\t%s\t%s\n' "$m" "$f"
    sed -n 's/^  использует «\([^»]*\)»[[:space:]]*$/\1/p' "$f" \
      | while IFS= read -r im; do printf 'E\t%s\t%s\n' "$f" "$im"; done
  done ) > "$graf"

itog=$(awk -F'\t' '
  FILENAME == ARGV[1] {
    if ($1 == "M") fajl[$2] = $3
    else if ($1 == "E") rebro[$2] = rebro[$2] "\t" $3
    next
  }
  {
    vse[$1] = 1
    split($2, p, " ")
    if ($2 ~ /^вне присмотра/) { svoih[$1] = p[3] }
    else { svoih[$1] = p[4]; pokryto[$1] = 1; ochered[++hvost] = $1 }
  }
  END {
    for (i = 1; i <= hvost; i++) {
      n = split(rebro[ochered[i]], im, "\t")
      for (j = 1; j <= n; j++) {
        t = fajl[im[j]]
        if (t != "" && !(t in pokryto)) { pokryto[t] = 1; ochered[++hvost] = t }
      }
    }
    for (f in vse) if (!(f in pokryto)) { nepokr++; dolg += svoih[f]; imena = imena " " f }
    printf "%d\t%d\t%s", nepokr + 0, dolg + 0, imena
  }' "$graf" "$nov")
rm -f "$graf"
nepokryto=$(printf '%s' "$itog" | cut -f1)
dolg=$(printf '%s' "$itog" | cut -f2)
kto=$(printf '%s' "$itog" | cut -f3)

echo "обходчик self: сошлось с ведомостью — под присмотром файлов $pod, прогнано примеров $primerov (своих $svoih_pod), прошло $proshlo"
echo "обходчик self: НЕ ПРОГОНЯЕТСЯ НИГДЕ — файлов $nepokryto, своих примеров в них $dolg:"
printf '%s\n' $kto | sed 's|^|  · |'
