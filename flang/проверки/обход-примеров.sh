# Обходчик ПРИМЕРОВ корпуса: зовёт `flang test` двоичного на каждом `.flang`
# дерева и сверяет полную ведомость — файл, число примеров, сколько прошло.
#
# ── Зачем он, если проверки уже написаны ────────────────────────────────────
#
# Затем, что написанное и выполняемое — разные вещи. Примеров в дереве тысячи,
# они объявлены внутри функций и проверяются ядром на месте; но до сегодняшнего
# дня выполнить их могла только команда `flang test` из инструментария на Node.
# С парой веток `work/binary-emit` и `work/binary-test-proof` она есть у
# двоичного, и переносить эти проверки не надо — надо их ПОЗВАТЬ. Этот файл их
# и зовёт.
#
# Считается тремя числами, и все три обязательны:
#   * СПИСОК ФАЙЛОВ целиком — diff с записанной ведомостью;
#   * число примеров у каждого файла — файл, потерявший половину своих примеров,
#     зеленеет так же, как целый;
#   * число прошедших.
# Двух первых нет ни у какого счётчика отказов: файл, который двоичный
# перестал брать, отдаёт ноль примеров и ноль отказов, то есть выглядит чисто.
#
#   sh flang/проверки/обход-примеров.sh          — сверить с ведомостью
#   sh flang/проверки/обход-примеров.sh --write  — перезаписать её
#
# Прогон длится около шести минут: два файла `flang/self` считаются десятками
# секунд каждый. Это не оснастка тормозит — это ядро проверяет самый большой
# исходник дерева.
#
# ── Что показал прогон, числами ────────────────────────────────────────────
#
#   файлов в дереве                                    771
#   двоичный взял                                      343
#   ПРОГНАЛ примеров                                  4382
#     сошлось                                         4365
#     не сошлось                                        17
#   двоичный не взял                                   428
#
# Семнадцать несошедшихся лежат в 13 файлах, и НИ ОДНОГО из них нет в корпусе:
# 15 — в выходах замера авторства (`benchmarks/model-authoring/out`: их писала
# модель, ломали нарочно, это фикстуры отказа), 1 — в задании замера стоимости
# доказательства (`docs/benchmark2/13-chyotnoe.flang`), 1 — в опыте `fspec/`
# `contradiction-one-function.flang`, где нарушенное свойство и есть предмет
# опыта. Корпус — `flang/`, `examples/`, `fspec/spec/` — зелен целиком.
#
# Первый счёт этой шапки говорил «4353, не сошлось 0», и он был НЕВЕРЕН: разбор
# сырого вывода читал только первую строку ответа, а у файла с провалившимся
# примером первой идёт строка провала, итог — последней. Такие файлы попадали в
# «отказ» вместо «прогнан с провалами». Ошибку нашла сама сверка ведомости на
# втором прогоне: строки поехали в сторону «отказ → 2 1 1». Оставлено записью,
# потому что это ровно тот случай, ради которого ведомость и сверяется целиком.
#
# Настоящий зазор — четыре файла, и он назван, чтобы его закрывали, а не искали:
#   flang/examples/monad/order-total.flang     27 примеров  FLANG_TYPE_PARAM
#   flang/examples/money/exact-decimal.flang   27 примеров  FLANG_UNKNOWN_NAME
#   flang/examples/paths/shortest-path.flang   22 примера   FLANG_UNKNOWN_NAME
#   flang/self/repl/repl.flang                 14 примеров  FLANG_RECURSION_LIMIT
# и `flang/self/bootstrap/compiler.flang` — тот же лимит шагов (40 000 000),
# примеров у него нет. Эталон на Node эти файлы берёт; двоичный пока нет.
set -eu
LC_ALL=C.UTF-8
export LC_ALL

root=$(cd "$(dirname "$0")/../.." && pwd)
# Имя выхода сборки — `flang`, именем языка. `flang_cli` принимается тоже: в
# дереве, где сборка была до переименования, он лежит с прежним именем, и
# обходчик не обязан из-за этого отказывать.
tool=${FLANG_BIN:-"$root/bootstrap/flang"}
[ -x "$tool" ] || tool="$root/bootstrap/flang_cli"
ledger="$root/flang/проверки/ведомость-примеров.txt"

if [ ! -x "$tool" ]; then
  echo "обходчик примеров: нет двоичного «$tool». Собрать: make -C bootstrap" >&2
  exit 2
fi

out=$(mktemp)
trap 'rm -f "$out"' EXIT

# Ищет `find` — оснастка, которая свидетеля ВОЗИТ. Проверяет ядро, и оно в
# двоичном. Ни одной строки на JavaScript тут нет и не нужно.
find "$root" -name '*.flang' -not -path '*/.git/*' -not -path '*/node_modules/*' \
  | sed "s#^$root/##" | LC_ALL=C sort | while IFS= read -r file; do
  reply=$("$tool" test "$root/$file" 2>&1 || true)
  nums=$(printf '%s' "$reply" | sed -n 's/.*примеров \([0-9]*\), прошло \([0-9]*\), не прошло \([0-9]*\).*/\1 \2 \3/p' | head -1)
  if [ -z "$nums" ]; then
    # Двоичный файл не взял: не разобрался, не свёл типы, не доказал завершение.
    # Это НЕ ноль примеров — это отказ, и он пишется в ведомость своим словом,
    # иначе пропажа файла из работы неотличима от файла без примеров.
    printf '%s\tотказ\n' "$file" >> "$out"
  else
    printf '%s\t%s\n' "$file" "$nums" >> "$out"
  fi
done

taken=$(grep -vc 'отказ$' "$out" || true)
refused=$(grep -c 'отказ$' "$out" || true)
examples=$(awk -F'\t' '$2!="отказ"{split($2,p," "); s+=p[1]} END{print s+0}' "$out")
passed=$(awk -F'\t' '$2!="отказ"{split($2,p," "); s+=p[2]} END{print s+0}' "$out")
failed=$(awk -F'\t' '$2!="отказ"{split($2,p," "); s+=p[3]} END{print s+0}' "$out")

if [ "${1:-}" = "--write" ]; then
  cp "$out" "$ledger"
  echo "обходчик примеров: ведомость записана — файлов $taken, примеров $examples"
  exit 0
fi

if [ ! -f "$ledger" ]; then
  echo "обходчик примеров: нет ведомости «$ledger». Записать: sh $0 --write" >&2
  exit 2
fi

if ! diff -u "$ledger" "$out"; then
  echo "обходчик примеров: ВЕДОМОСТЬ РАЗОШЛАСЬ — выше видно, какой файл пропал, прибыл или потерял примеры" >&2
  exit 1
fi

# Порога «ни одного провала» здесь НЕТ, и это не послабление. Провалы в дереве
# есть законные: выходы замера авторства писала модель, и часть их примеров не
# сходится — в этом замер и состоит. Порог «ноль» либо краснел бы всегда, либо
# потребовал бы списка исключений, а список исключений — это место, куда однажды
# допишут настоящую поломку. Ведомость строже порога: она держит ТОЧНОЕ число
# прошедших у КАЖДОГО файла, и переход 2 2 0 → 2 1 1 краснеет диффом выше.

echo "обходчик примеров: сошлось с ведомостью — файлов $taken (отказано $refused), примеров $examples, прошло $passed, не прошло $failed"
