# Обходчик ПРИМЕРОВ корпуса: зовёт `flang test` двоичного на каждом `.flang`
# дерева и сверяет полную ведомость — файл, число примеров, сколько прошло.
#
# ── Зачем он, если проверки уже написаны ────────────────────────────────────
#
# Затем, что написанное и выполняемое — разные вещи. Примеров в дереве тысячи,
# они объявлены внутри функций и проверяются ядром на месте; но до сегодняшнего
# дня выполнить их могла только команда `flang test` из инструментария на Node.
# С парой веток `work/binary-emit` и `work/binary-test-proof` она есть у
# двоичного, и переносить эти проверки не надо — надо их ПОЗВАТЬ. Этот файл их
# и зовёт.
#
# ⚠ ЗАПИСАННАЯ ВЕДОМОСТЬ ОТСТАЛА ОТ ФОРМАТА, И ЗАМЕТИТЬ ЭТО БЫЛО НЕКОМУ.
#
# Прогонщик считает ЧЕТЫРЬМЯ числами с коммита `6eea2b4f` («Прогонщик считает
# СВОИ примеры отдельно от ввезённых»): всего, прошло, сорвалось и СВОИХ.
# В `flang/проверки/ведомость-примеров.txt` четырёх чисел нет ни в одной строке
# — замер 30 августа 2026: 346 строк с ТРЕМЯ числами и 428 строк с одним словом
# («отказ»). Последняя правка файла — `0eec94a7` от 24 августа, и та была
# переименованием, а не пересъёмкой.
#
# Значит сверка `diff` разошлась бы на всех 346 численных строках сразу. Не
# разошлась она потому, что НЕ ЗАПУСКАЛАСЬ: работа `korpus` в
# `.github/workflows/binary.yml` закрыта условием
# `github.event_name == 'workflow_dispatch' || startsWith(github.ref, 'refs/tags/')`,
# то есть на пуш не ходит вовсе, а тега с 22 августа не было.
#
# Отсюда прямое следствие, и оно про предмет этого файла: ЧЕТВЁРТОЕ ЧИСЛО —
# «своих примеров» — в записанную ведомость не попадает, и болезнь «слой без
# своих примеров зеленеет чужими» этой сверкой не ловится ни у одного файла.
# Пересъёмка (`--write`) закроет формат, но проверять она начнёт только тогда,
# когда работу снимут с условия или позовут руками.
#
# Считается тремя числами, и все три обязательны:
#   * СПИСОК ФАЙЛОВ целиком — diff с записанной ведомостью;
#   * число примеров у каждого файла — файл, потерявший половину своих примеров,
#     зеленеет так же, как целый;
#   * число прошедших.
# Двух первых нет ни у какого счётчика отказов: файл, который двоичный
# перестал брать, отдаёт ноль примеров и ноль отказов, то есть выглядит чисто.
#
#   sh flang/проверки/обход-примеров.sh          — сверить с ведомостью
#   sh flang/проверки/обход-примеров.sh --write  — перезаписать её
#
# Прогон длится около шести минут: два файла `flang/self` считаются десятками
# секунд каждый. Это не оснастка тормозит — это ядро проверяет самый большой
# исходник дерева.
#
# ── Что показал прогон, числами ────────────────────────────────────────────
#
#   файлов в дереве                                    771
#   двоичный взял                                      343
#   ПРОГНАЛ примеров                                  4382
#     сошлось                                         4365
#     не сошлось                                        17
#   двоичный не взял                                   428
#
# Семнадцать несошедшихся лежат в 13 файлах, и НИ ОДНОГО из них нет в корпусе:
# 15 — в выходах замера авторства (`benchmarks/model-authoring/out`: их писала
# модель, ломали нарочно, это фикстуры отказа), 1 — в задании замера стоимости
# доказательства (`docs/benchmark2/13-even.flang`), 1 — в опыте `fspec/`
# `contradiction-one-function.flang`, где нарушенное свойство и есть предмет
# опыта. Корпус — `flang/`, `examples/`, `fspec/spec/` — зелен целиком.
#
# Первый счёт этой шапки говорил «4353, не сошлось 0», и он был НЕВЕРЕН: разбор
# сырого вывода читал только первую строку ответа, а у файла с провалившимся
# примером первой идёт строка провала, итог — последней. Такие файлы попадали в
# «отказ» вместо «прогнан с провалами». Ошибку нашла сама сверка ведомости на
# втором прогоне: строки поехали в сторону «отказ → 2 1 1». Оставлено записью,
# потому что это ровно тот случай, ради которого ведомость и сверяется целиком.
#
# Настоящий зазор — четыре файла, и он назван, чтобы его закрывали, а не искали:
#   examples/monad/order-total.flang     27 примеров  FLANG_TYPE_PARAM
#   examples/money/exact-decimal.flang   27 примеров  FLANG_UNKNOWN_NAME
#   examples/paths/shortest-path.flang   22 примера   FLANG_UNKNOWN_NAME
#   flang/self/repl/repl.flang                 14 примеров  FLANG_RECURSION_LIMIT
# и `flang/self/bootstrap/compiler.flang` — тот же лимит шагов (40 000 000),
# примеров у него нет. Свидетель на Node эти файлы берёт; двоичный пока нет.
# ── ЧЕМ ЭТОТ ОБХОДЧИК ЗАМЕНЯЕТСЯ, И ЧТО ДЛЯ ЭТОГО ОСТАЛОСЬ ─────────────────
#
# С 20 августа 2026 обход корпуса умеет САМ ДВОИЧНЫЙ: `flang test` берёт каталог
# и маску, а не только файл, и печатает свод — файлов, взято, отказано, примеров
# (и сколько из них СВОИХ), на чужих примерах, потеряно своих, прошло, не прошло,
# за сколько. Ключ `--json` даёт то же машине.
#
#   flang test .            весь корпус одним процессом вместо 771
#   flang test flang/stdlib/ --json
#
# То есть от этого файла заменяется всё, кроме поиска двоичного: `find`, цикл на
# 771 запуск процесса, разбор человеческого вывода регулярным выражением (тот
# самый, что однажды разъехался — см. выше) и счёт в `awk`. Это 35 строк
# исполняемой части из 135.
#
# Не заменено ОДНО, и это названо числом: у `flang test` нет вывода «по строке на
# файл», а ведомость здесь именно такая — `путь<TAB>всего прошло сорвалось` либо
# `путь<TAB>отказ`, 771 строка, и сверяется она диффом. `--json` даёт те же числа,
# но одной строкой, и дифф по ней бесполезен. Цена ключа `--ledger`, печатающего
# ведомость построчно, — около 25 строк на flang (`flang/self/bootstrap/corpus.flang`)
# и 6 строк на C (`flang/src/emit/c/flang_repl.c`). После него тело этого файла
# становится двумя строками: один вызов и `diff`.
#
# Пока ключа нет, обходчик остаётся как есть и работает. Переписывать его на
# `--json` без построчной ведомости нельзя: дифф одной строки на 800 файлов не
# показывает, КАКОЙ файл поехал, а весь смысл ведомости в этом.
set -eu
LC_ALL=C.UTF-8
export LC_ALL

root=$(cd "$(dirname "$0")/../.." && pwd)
# Имя выхода сборки — `flang`, именем языка. `flang_cli` принимается тоже: в
# дереве, где сборка была до переименования, он лежит с прежним именем, и
# обходчик не обязан из-за этого отказывать.
tool=${FLANG_BIN:-"$root/bootstrap/flang"}
[ -x "$tool" ] || tool="$root/bootstrap/flang_cli"
ledger="$root/flang/проверки/ведомость-примеров.txt"

if [ ! -x "$tool" ]; then
  echo "обходчик примеров: нет двоичного «$tool». Собрать: make -C bootstrap" >&2
  exit 2
fi

out=$(mktemp)
trap 'rm -f "$out"' EXIT

# ОБХОД, ОТБОР, ПОРЯДОК И СЧЁТ ЖИВУТ В САМОМ ДВОИЧНОМ и написаны на flang
# (`flang/self/bootstrap/corpus.flang`). Здесь остаётся ровно то, чем оснастка и
# была: найти двоичный, позвать его и сверить ведомость диффом. Ни `find`, ни
# цикла на 771 запуск процесса, ни разбора человеческого вывода регулярным
# выражением — того самого, что однажды разъехался (см. шапку).
#
# Ведомость: `путь<TAB>всего прошло сорвалось СВОИХ` у взятого файла и
# `путь<TAB>отказ СВОИХ` у невзятого. Четвёртое число — свои примеры файла, а не
# ввезённые по «использует»; без него строка «91 91 0» у слоя, все примеры
# которого чужие, неотличима от строки настоящего слоя с девяноста одной своей
# проверкой.
#
# Ненулевой код здесь ожидаем: в дереве есть законные провалы (см. ниже), а
# `flang test` отвечает единицей на любой из них.
( cd "$root" && "$tool" test . --ledger || true ) | sed 's#^\./##' > "$out"

taken=$(awk -F'\t' '$2 !~ /^отказ/' "$out" | wc -l | tr -d ' ')
refused=$(awk -F'\t' '$2 ~ /^отказ/' "$out" | wc -l | tr -d ' ')
examples=$(awk -F'\t' '$2 !~ /^отказ/{split($2,p," "); s+=p[1]} END{print s+0}' "$out")
passed=$(awk -F'\t' '$2 !~ /^отказ/{split($2,p," "); s+=p[2]} END{print s+0}' "$out")
failed=$(awk -F'\t' '$2 !~ /^отказ/{split($2,p," "); s+=p[3]} END{print s+0}' "$out")
own=$(awk -F'\t' '$2 !~ /^отказ/{split($2,p," "); s+=p[4]} END{print s+0}' "$out")
lost=$(awk -F'\t' '$2 ~ /^отказ/{split($2,p," "); s+=p[2]} END{print s+0}' "$out")

if [ "$(wc -l < "$out" | tr -d ' ')" -eq 0 ]; then
  echo "обходчик примеров: двоичный не отдал ни одной строки — ведомость сверять не с чем" >&2
  exit 1
fi

if [ "${1:-}" = "--write" ]; then
  cp "$out" "$ledger"
  echo "обходчик примеров: ведомость записана — файлов $taken, примеров $examples (своих $own)"
  exit 0
fi

if [ ! -f "$ledger" ]; then
  echo "обходчик примеров: нет ведомости «$ledger». Записать: sh $0 --write" >&2
  exit 2
fi

if ! diff -u "$ledger" "$out"; then
  echo "обходчик примеров: ВЕДОМОСТЬ РАЗОШЛАСЬ — выше видно, какой файл пропал, прибыл или потерял примеры" >&2
  exit 1
fi

# Порога «ни одного провала» здесь НЕТ, и это не послабление. Провалы в дереве
# есть законные: выходы замера авторства писала модель, и часть их примеров не
# сходится — в этом замер и состоит. Порог «ноль» либо краснел бы всегда, либо
# потребовал бы списка исключений, а список исключений — это место, куда однажды
# допишут настоящую поломку. Ведомость строже порога: она держит ТОЧНОЕ число
# прошедших и число СВОИХ у КАЖДОГО файла, и переход 2 2 0 2 → 2 1 1 2 краснеет
# диффом выше, а переход 91 91 0 91 → 91 91 0 0 (файл потерял все свои примеры,
# а число осталось прежним за счёт ввезённых) — тем же диффом.

echo "обходчик примеров: сошлось с ведомостью — файлов $taken (отказано $refused), примеров $examples (своих $own), прошло $passed, не прошло $failed, потеряно с отказами $lost"
