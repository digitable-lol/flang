# Обходчик проверок, написанных НА FLANG. Тонкий — и это не скромность, а
# граница, взятая из `fspec/README.md`: на flang пишется всё, что ПРОВЕРЯЕТ
# предъявленного свидетеля; оснасткой остаётся всё, что свидетеля ИЩЕТ или ВОЗИТ.
#
# Ищет здесь `sh` (перечисление каталога), возит `flang run` — двоичный из
# `bootstrap/`, а ПРОВЕРЯЕТ сама программа на flang. Node не участвует ни на
# одном шаге.
#
# Про уклад `fspec` здесь стояла поправка «правило годится, исполнение нет:
# ведомость `--proof` печатает только Node». Она СНЯТА стволом и оставлена
# записью, чтобы вывод не делали заново по памяти. Двоичный из ствола печатает
# ведомость и её же в JSON:
#
#   $ bootstrap/flang check fspec/spec/01-discount-cap.flang --proof --json
#   {"ledger":1,"module":"Спека 1: потолок скидки","functions":[…],"laws":[],…}
#
# То есть `fspec/guard.mjs` (285 строк) сегодня отделяет от двоичного одна
# переменная: он зовёт `bootstrap/flang check … --proof --json`, и
# ответ у двоичного той же формы. Ходить по каталогу и задавать код выхода —
# работа оснастки, и она остаётся; чем именно её писать, JavaScript-ом или `sh`,
# вопрос уже не принципа.
#
# Имена переменных здесь латиницей, и это не выбор: `sh` и `bash` принимают в
# имени переменной только ASCII. Слова взяты английские, а не русские латиницей.
#
# Считается двумя числами, и оба обязательны:
#   * СПИСОК ИМЁН целиком — diff с записанной ведомостью «ведомость.txt»;
#   * число сошедшихся.
# Одного числа мало: файл, упавший целиком, отдаёт ноль проверок и ноль отказов,
# то есть выглядит ровно как чистый. Diff имён это ловит, счётчик — нет.
#
#   sh flang/проверки/обход.sh           — сверить с записанной ведомостью
#   sh flang/проверки/обход.sh --write   — перезаписать её (после правки проверок)
#
# ── Раскладка базы проверок, ради которой этот каталог заведён ───────────────
#
# Замер 18 августа 2026 на этом дереве. Прогон `node --test flang/test/*.test.mjs`
# дошёл до конца: проверок 4348, сошлось 4339, отказов 9 (все девять были
# красными и ДО этого захода). Именам проверок сопоставлен файл, файлу — то, что
# проверка берёт от мира; выборка — 4314 имён, пришедших в TAP верхним уровнем.
#
# Разложено по ТЕЛУ проверки, то есть по тому, что нужно самому утверждению, а не
# прелюдии файла, которая свидетеля лишь подаёт:
#
#   чистые (миру не нужно ничего)                     1941
#   читающие дерево                                   2129
#       из них перечисляют каталог («Перечислить каталог»)              1122
#       из них читают только НАЗВАННЫЕ файлы                            1007
#         — этим новое поручение не нужно вовсе: «Прочитать файл» в
#           словаре `flang/src/io.mjs` есть с самого начала
#   запускающие процессы («Запустить процесс» + код выхода)              243
#   держащие сеть (свой HTTP-сервер, не запрос)                            1
#
# ОБА ПОРУЧЕНИЯ ЗАВЕДЕНЫ, и код выхода тоже: словарь `flang/src/io.mjs` знает
# «Перечислить каталог» и «Запустить процесс», а `flang io` отвечает 1, когда
# программа сдалась сама, и 3, когда сломался инструмент. Оценка была 63 + 109 +
# 50 = 222 строки, вышло 66 + 210 + 107 = 383 (`fspec/README.md`, столбец
# «вышло»). Открытыми эти 1365 проверок при этом ещё не стали: поручение
# ОТКРЫВАЕТ дорогу, а переносит проверки — отдельная работа, и она не начата.
#
# Тот же счёт, но с прелюдией файла (что нужно, чтобы проверка вообще СОСТОЯЛАСЬ
# в нынешнем виде): чистых остаётся 635. Разница в 1306 — это не работа языка, а
# работа по РАЗДЕЛЕНИЮ файлов: утверждение в них чистое, а корпус ему подаёт
# общая на файл прелюдия. Пока файл не разделён, чистая проверка едет вместе с
# ним.
#
# Взята самая большая чистая семья, которую можно перенести целиком и сегодня, —
# встроенные формы. Что в перенос НЕ вошло, названо в шапке
# «встроенные-формы.flang»: проверки, ждущие ОТКАЗА формы. Отказ роняет
# вычисление, значением он не выражается, и поймать его нечем.
#
# ── Самое дешёвое, что осталось, и оно дешевле всего переноса ────────────────
#
# Замер, ради которого стоило считать: на flang УЖЕ НАПИСАНО 3593 утверждения.
# Это объявления `пример` в 599 файлах `.flang` дерева — 484 в `flang/stdlib`,
# 460 в `flang/self`, остальные по корпусу. Ни одно из них не выдумывать не надо
# и переносить не надо: они написаны.
#
# Выполнить их сегодня может только `flang test`, а он живёт ТОЛЬКО в
# инструментарии на Node. Справка двоичного говорит это прямым текстом: «запуск
# примеров и проверка суждений живут в полном инструментарии, а ему нужен Node».
# То есть 3593 проверки на flang держит JavaScript — не тем, что они на нём
# написаны, а тем, что без него их нечем ЗАПУСТИТЬ.
#
# Цена снятия названа числом: `runExamples` в `flang/src/compat.mjs` — 105
# строк, и всё, что ей нужно, у двоичного уже есть (вычислитель зовёт `run`,
# сравнение значений и печать JSON — в рантайме). Против этого перенос
# 1941 чистой проверки руками стоит на два порядка дороже и даёт меньше.
#
# Порядок работ отсюда прямой:
#   1. `test` в двоичный (~105 строк) — открывает 3593 уже написанных проверки;
#   2. ✔ «Перечислить каталог» (оценка 63, вышло 66) — дорога к 1122 обходящим
#      дерево открыта;
#   3. ✔ «Запустить процесс» (109 → 210) и код выхода (50 → 107) — дорога к 243
#      запускающим открыта.
# Пункты 2 и 3 сделаны, пункт 1 — нет, и он же самый дешёвый из трёх.
set -eu
LC_ALL=C.UTF-8
export LC_ALL

root=$(cd "$(dirname "$0")/../.." && pwd)
# Имя выхода сборки — `flang`, именем языка. `flang_cli` принимается тоже: в
# дереве, где сборка была до переименования, он лежит с прежним именем, и
# обходчик не обязан из-за этого отказывать.
tool=${FLANG_BIN:-"$root/bootstrap/flang"}
[ -x "$tool" ] || tool="$root/bootstrap/flang_cli"
dir="$root/flang/проверки"
ledger="$dir/ведомость.txt"

if [ ! -x "$tool" ]; then
  echo "обходчик: нет двоичного «$tool». Собрать: make -C bootstrap" >&2
  exit 2
fi

out=$(mktemp)
trap 'rm -f "$out" "$out.names"' EXIT

# Расширений у программы четыре и они равноправны: `.flang`, `.fp`, `.фп`,
# `.фланг` (ADR-0016). Оболочка образец без совпадений оставляет собой, потому
# строка «нет такого файла» отсеивается тут же, как и раньше.
for file in "$dir"/*.flang "$dir"/*.fp "$dir"/*.фп "$dir"/*.фланг; do
  [ -e "$file" ] || continue
  # Имя точки входа не угадывается и не задаётся ключом: оно взято из самого
  # файла. Переименуют ведомость — обходчик найдёт её под новым именем; пропадёт
  # она вовсе — здесь пусто, и краснеет diff имён, а не молчит счётчик.
  entry=$(sed -n 's/^тотальная функция «\(Ведомость[^»]*\)».*/\1/p' "$file" | head -1)
  if [ -z "$entry" ]; then
    echo "обходчик: в «$file» нет тотальной функции «Ведомость…» — проверок в нём не видно" >&2
    exit 1
  fi
  "$tool" run "$file" --function "$entry" \
    | sed -e 's/^\[//' -e 's/\]$//' -e 's/","/\n/g' -e 's/^"//' -e 's/"$//' >> "$out"
done

total=$(wc -l < "$out" | tr -d ' ')
agreed=$(grep -c -- ' — да$' "$out" || true)
broken=$(grep -c -- ' — НЕТ$' "$out" || true)
sed -e 's/ — да$//' -e 's/ — НЕТ$//' "$out" > "$out.names"

# Каждая строка ведомости обязана нести вердикт. Строка без вердикта — это не
# «ни да ни нет», это разъехавшийся разбор вывода, и молчать о ней нельзя:
# счётчик сошедшихся тогда меньше числа проверок, а красного нет ни одного.
if [ "$total" -ne $((agreed + broken)) ]; then
  echo "обходчик: строк $total, а вердиктов $((agreed + broken)) — разбор вывода разъехался" >&2
  exit 1
fi

if [ "${1:-}" = "--write" ]; then
  cp "$out.names" "$ledger"
  echo "обходчик: ведомость записана — проверок $total"
  exit 0
fi

if [ ! -f "$ledger" ]; then
  echo "обходчик: нет записанной ведомости «$ledger». Записать: sh $0 --write" >&2
  exit 2
fi

if ! diff -u "$ledger" "$out.names"; then
  echo "обходчик: СПИСОК ПРОВЕРОК РАЗОШЁЛСЯ с записанным — выше видно, какие пропали или прибыли" >&2
  exit 1
fi

if [ "$broken" -ne 0 ]; then
  echo "обходчик: разошлось $broken из $total:" >&2
  grep -- ' — НЕТ$' "$out" >&2
  exit 1
fi

echo "обходчик: чисто — проверок $total, сошлись все $agreed"
