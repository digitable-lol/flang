/**
 * Сторож СОВМЕСТНОСТИ СПЕК: спека, написанная на flang, обязана быть доказана
 * из нуля аксиом, и следующая спека обязана оставить утверждения предыдущей
 * доказанными.
 *
 * ── Зачем он вообще нужен, если есть `flang check` ──────────────────────────
 *
 * Опыт, а не рассуждение (`fspec/experiments/`, числа в `fspec/README.md`): два
 * утверждения об одной функции, которые вместе НЕВЫПОЛНИМЫ — «результат не
 * больше 30» и «результат не меньше 50», — проходят `flang check --proof` с
 * КОДОМ ВЫХОДА 0. Ведомость пишет про второе «объявлено, не доказано» и
 * откладывает его на рантайм. То же и через файл: спека-наследница, зовущая
 * функцию спеки-предшественницы и обещающая обратное, зеленеет так же.
 *
 * Ядро тут не виновато и чинить его не надо. Оно отвечает на вопрос «выводится
 * ли это из нуля аксиом», а не на вопрос «совместны ли эти два утверждения», и
 * «не доказано» у него — не «ложно». Разница между вопросами и есть то, чего
 * не хватало: непротиворечивость системы спек — это ПОЛИТИКА над ведомостью, а
 * не новое правило в ядре.
 *
 * ── Политика, и почему именно такая ────────────────────────────────────────
 *
 * Спека принимается ТОЛЬКО с вердиктом «доказано» у каждого утверждения.
 * Довод прямой: в языке ноль аксиом, значит из системы доказанных утверждений
 * нельзя вывести ложь — не из чего. Ровно это владелец и называет «суммарно
 * нулевой суммой»: система спек остаётся непротиворечивой не потому, что кто-то
 * сверил их попарно, а потому, что каждая выведена, а не объявлена.
 *
 * Что от этого краснеет, чего сегодня не краснеет ничем:
 *   • «объявлено, не доказано» — утверждение, которое может оказаться ложным, и
 *     тогда система спек противоречива, а никто об этом не узнает;
 *   • «сетка N» — посчитано на значениях автора; это не утверждение обо всех
 *     входах, и сложить его с другим нельзя;
 *   • «НАРУШЕНО на примере» — ложь, найденная примером автора;
 *   • спека без утверждений вовсе. Проверка, которой не на чем разойтись,
 *     зеленеет так же, как сошедшаяся, — это правило дерева, не выдумка здесь.
 *
 * Цена политики названа честно: истинное, но НЕВЫВОДИМОЕ утверждение сторож
 * тоже отвергнет. Ядро неполно (пример в дереве — «Сколько дополнить» из
 * `flang/proof/examples/precondition.flang`: правда, которую сегодня закрыть
 * нечем). Значит спека, упёршаяся в неполноту ядра, — это ЗАЯВКА НА ПРАВИЛО, а
 * не повод ослабить сторожа порогом.
 *
 * ── Согласие с предыдущей спекой ───────────────────────────────────────────
 *
 * Спека ссылается на предшественницу словом `использует`. Связывание втягивает
 * её функции, и ведомость наследницы содержит утверждения обеих — это ПРОГОН,
 * а не обещание. Сторож требует: каждое имя утверждения предшественницы стоит
 * в ведомости наследницы и стоит со словом «доказано». Переименуют утверждение
 * предшественницы, снимут его, ослабят до «сетки» — краснеет здесь, а не
 * выясняется чтением.
 *
 * ── Почему это JavaScript в каталоге, который пишется на flang ─────────────
 *
 * Вопрос законный, и ответ на него — не «так вышло», а измеренная граница.
 *
 * Правила сторожа три, и они разного рода.
 *
 * Первые два — «утверждений не ноль» и «доказаны все» — на flang НЕ ПЕРЕЕЗЖАЮТ
 * по той причине, что они там УЖЕ. Ведомость доказательства написана на самом
 * языке (`flang/self/proof.flang`, слой шестой; эталон `flang/src/proof.mjs`,
 * сверка побайтовая — `flang/test/self-proof.test.mjs`), и в ней объявлен
 * `объект «Итоги утверждений»` с полями `«всего»` и `«доказано»`. В JSON это
 * `proof.totals.claims.{total,proved}`. Оба правила сторожа — сравнение этих
 * двух чисел, и ниже они именно так и записаны: два сравнения, а не два обхода.
 * Переписать их на flang нечего — можно только перестать считать их заново, что
 * и сделано.
 *
 * Третье правило — согласие с предшественницей — на flang выразимо (есть
 * `список`, `строка`, `объект`, есть `flang/stdlib/sets.flang`), но выразимо
 * ВПУСТУЮ: это сравнение ДВУХ ведомостей, а собрать пару может только тот, кто
 * ходит по файлам. Сам себе flang её не соберёт, и вот почему — числом:
 *
 *   • ПРЕПЯТСТВИЕ СНЯТО ДВУМЯ ТРЕТЯМИ. Словарь ввода-вывода языка — семь
 *     поручений (`flang/src/io.mjs`): «Прочитать файл», «Записать файл»,
 *     «Запросить», «Текущее время», «Случайное число», «Перечислить каталог»,
 *     «Запустить процесс». Перечисление каталога и запуск процесса из списка
 *     препятствий ВЫШЛИ, и код выхода тоже: `flang io` отвечает 1, когда
 *     программа сдалась сама, и 3, когда сломался инструмент. Осталось ОДНО —
 *     язык не читает JSON;
 *   • JSON язык умеет ПЕЧАТАТЬ, но не читать: `flang/core/json.flang` — это
 *     модуль «Печать JSON», все его функции зовутся «Печать …». Разбора нет.
 *     Пока это так, ведомость `--proof --json` разобрать нечем, и сторож
 *     остаётся здесь.
 *
 * Отсюда граница, и она в дереве уже проведена — не здесь и не впервые.
 * `flang/examples/io/link-report.flang` говорит о себе теми же словами: «Чего
 * здесь нет и не будет: самого HTTP. Он написан не на flang и не может быть
 * написан на flang — на flang написано то, ЧТО запросить и что сделать с
 * ответом, то есть ровно та часть, которую и надо проверять».
 *
 * Значит на flang — то, что ПРОВЕРЯЕТ предъявленное; оснасткой остаётся то, что
 * предъявляемое ищет и возит. Этот файл — целиком вторая половина: найти спеки,
 * позвать компилятор, прочитать ведомость, назвать беду и поставить код выхода.
 * Первой половины в нём не осталось ни строки — она в `flang/self/proof.flang`.
 *
 * Запуск: `node fspec/guard.mjs` (или `npm run spec:check`).
 *   `--file <путь>` — проверить одну названную спеку (тем же правилом).
 *
 * Своего теста у сторожа НЕТ, и это записано долгом в `fspec/README.md`:
 * сторож, который не умеет краснеть, выглядит ровно как сторож, у которого всё
 * хорошо. Сегодня краснота показана прогоном руками, а не тестом.
 */
import { execFileSync } from "node:child_process"
import { readFileSync, readdirSync, existsSync } from "node:fs"
import { dirname, extname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

export const КОРЕНЬ = fileURLToPath(new URL("..", import.meta.url))
export const КАТАЛОГ_СПЕК = join(КОРЕНЬ, "fspec", "spec")
const ФЛАНГ = join(КОРЕНЬ, "flang", "bin", "flang.mjs")

/**
 * Вердикты, при которых утверждение годится в систему спек.
 *
 * Их ДВА, а не один, и второй здесь не для полноты. `proved-induction` — это
 * утверждение обо всех входах, выведенное индукцией; ведомость считает его
 * доказанным наравне с выведенным цепочкой (`flang/src/proof.mjs`, счёт
 * `totals.claims.proved`, и там же довод: «доказанность у них одна и та же»).
 * Сторож, знавший одно слово `"proved"`, отвергал спеку, доказанную индукцией,
 * — то есть отвергал доказанное. Это и есть цена второго мнения, от которой
 * предостерегает шапка `ведомость()`: расходится оно молча и не там, где
 * смотрят.
 */
const ГОДНЫЕ = Object.freeze(new Set(["proved", "proved-induction"]))
const годен = (у) => ГОДНЫЕ.has(у.verdict)

/** Ведомости нет вовсе — считать нечего и не из чего. */
const ПУСТЫЕ_ИТОГИ = Object.freeze({ total: 0, proved: 0 })

/** Спеки каталога, по имени файла — порядок спек и есть порядок номеров. */
export function спеки(каталог = КАТАЛОГ_СПЕК) {
  if (!existsSync(каталог)) return []
  return readdirSync(каталог)
    .filter((имя) => extname(имя) === ".flang")
    .sort()
    .map((имя) => join(каталог, имя))
}

/**
 * Ведомость доказательства одной спеки — прогоном самого языка, а не разбором
 * текста. Спрашивают у того, кто считает, иначе сторож заведёт второе мнение,
 * которое разойдётся с первым.
 */
export function ведомость(путь) {
  let вывод
  try {
    вывод = execFileSync(process.execPath, [ФЛАНГ, "check", путь, "--proof", "--json"], {
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      /* Диагностику языка ловим, а не выпускаем в свой поток: беды называет
         сторож своими словами, иначе два голоса говорят об одном разом. */
      stdio: ["ignore", "pipe", "pipe"],
      env: { ...process.env, LC_ALL: "C.UTF-8" },
    })
  } catch (беда) {
    /* Ненулевой код — это отказ проверки: сама программа спеки не сошлась. */
    const текст = (беда.stdout ?? "") + (беда.stderr ?? "")
    return { отказ: текст.trim().slice(0, 4000), claims: [], итоги: ПУСТЫЕ_ИТОГИ, valid: false }
  }
  const о = JSON.parse(вывод)
  return {
    отказ: null,
    claims: о.proof?.claims ?? [],
    /* `totals.claims` — счёт САМОЙ ведомости, а не наш пересчёт по списку.
       На нём стоит решение сторожа; список утверждений ниже только объясняет,
       ЧТО именно не сошлось, и права решать не имеет. */
    итоги: о.proof?.totals?.claims ?? ПУСТЫЕ_ИТОГИ,
    valid: о.valid !== false,
    diagnostics: о.diagnostics ?? [],
  }
}

/** Кого спека называет предшественницей: пути из `использует … из "…"`. */
export function предшественницы(путь) {
  const текст = readFileSync(путь, "utf8")
  const из = []
  for (const м of текст.matchAll(/использует\s+«[^»]+»\s+из\s+"([^"]+)"/gu)) {
    из.push(resolve(dirname(путь), м[1]))
  }
  return из
}

/** Имена утверждений ведомости — то, чем спеки согласуются между собой. */
const имена = (claims) => claims.map((у) => `${у.of}: ${у.name}`)

export function проверить(каталог = КАТАЛОГ_СПЕК, корень = КОРЕНЬ) {
  const беды = []
  const свои = спеки(каталог)
  const ведомости = new Map()
  const отн = (п) => relative(корень, п).split("\\").join("/")

  for (const путь of свои) {
    const в = ведомость(путь)
    ведомости.set(путь, в)
    if (в.отказ !== null) {
      беды.push({ файл: отн(путь), род: "спека не проходит проверку языка", сказано: в.отказ })
      continue
    }
    /* ── Правило, и оно ЧИТАЕТСЯ, а не считается ─────────────────────────
       Оба условия ниже — сравнения двух чисел, которые ведомость посчитала
       сама (`«Итоги утверждений»`: `«всего»` и `«доказано»`). Пересчёт по
       списку был бы вторым мнением о том же, а шапка `ведомость()` выше сама
       запрещает заводить второе мнение. */
    if (в.итоги.total === 0) {
      беды.push({
        файл: отн(путь),
        род: "спека без утверждений",
        сказано:
          "ни одного `обеспечивает`. Спека, которой нечего утверждать, зеленеет всегда — " +
          "ровно так же, как сошедшаяся, и отличить их нечем",
      })
      continue
    }
    if (в.итоги.proved !== в.итоги.total) {
      /* Решение принято строкой выше. Обход списка только называет, ЧТО
         именно не сошлось: без имени утверждения беда нечитаема. */
      for (const у of в.claims) {
        if (годен(у)) continue
        беды.push({
          файл: отн(путь),
          род: `утверждение не доказано (${у.verdict})`,
          сказано: `${у.kind} «${у.name}» функции «${у.of}» — ${у.says}`,
        })
      }
    }
  }

  /* Согласие с предшественницей: её утверждения обязаны остаться в ведомости
     наследницы и остаться доказанными. */
  for (const путь of свои) {
    const в = ведомости.get(путь)
    if (в.отказ !== null) continue
    const мои = new Set(имена(в.claims))
    const доказано = new Set(в.claims.filter(годен).map((у) => `${у.of}: ${у.name}`))
    for (const предок of предшественницы(путь)) {
      if (!existsSync(предок)) {
        беды.push({ файл: отн(путь), род: "предшественница не найдена", сказано: предок })
        continue
      }
      const вп = ведомости.get(предок) ?? ведомость(предок)
      if (вп.отказ !== null) continue
      for (const имя of имена(вп.claims)) {
        if (!мои.has(имя)) {
          беды.push({
            файл: отн(путь),
            род: "утверждение предшественницы пропало из ведомости",
            сказано: `${имя} — есть у ${отн(предок)}, нет здесь`,
          })
        } else if (!доказано.has(имя)) {
          беды.push({
            файл: отн(путь),
            род: "утверждение предшественницы перестало быть доказанным",
            сказано: `${имя} — было доказано у ${отн(предок)}`,
          })
        }
      }
    }
  }
  return { беды, спек: свои.length, утверждений: [...ведомости.values()].reduce((н, в) => н + в.claims.length, 0) }
}

/* ── запуск из командной строки ─────────────────────────────────────────── */
if (import.meta.url === `file://${process.argv[1]}`) {
  const и = process.argv.indexOf("--file")
  const каталог = и >= 0 ? dirname(resolve(process.argv[и + 1])) : КАТАЛОГ_СПЕК
  const один = и >= 0 ? resolve(process.argv[и + 1]) : null
  const итог = проверить(каталог)
  const беды = один === null ? итог.беды : итог.беды.filter((б) => resolve(КОРЕНЬ, б.файл) === один)
  if (беды.length === 0) {
    console.log(
      `сторож спек: чисто — спек ${итог.спек}, утверждений ${итог.утверждений}, ` +
        "и каждое доказано из нуля аксиом",
    )
    process.exit(0)
  }
  console.error(`сторож спек: ${беды.length} бед(а/ы) в системе спек\n`)
  for (const б of беды) {
    console.error(`${б.файл}  ${б.род}`)
    console.error(`  ${б.сказано}`)
    console.error("")
  }
  console.error(
    "Спека принимается только доказанной. «Объявлено, не доказано» — это утверждение, " +
      "которое может оказаться ложным, и тогда система спек противоречива молча.",
  )
  process.exit(1)
}
