# Формула Homebrew для flang.
#
# ★ ПРАВКА ЭТОГО ФАЙЛА — НЕ КОНЕЦ РЕЛИЗА. `brew install` берёт формулу из
# ОТДЕЛЬНОГО репозитория-крана `digitable-lol/homebrew-tap`
# (`Formula/flang.rb`), не отсюда. После того, как метка реально дошла до
# публикации (`gh release view vX.Y.Z --json assets` показывает архив),
# синхронизировать РУКАМИ:
#   cp packaging/homebrew/flang.rb /srv/tmp/dokazuemyy/homebrew-tap/Formula/flang.rb
#   cd /srv/tmp/dokazuemyy/homebrew-tap && git add -A && git commit -m "..." && git push
# Забыто для 0.7.4–0.7.9 подряд (4 сентября 2026) — `brew install` тихо
# ставил протухшую 0.7.3, пока не заметили руками. Подробности: AGENTS.md,
# раздел «Релиз: тег — не конец, есть второй репозиторий».
#
# Ставится без Node — и это не оговорка, а суть. Компилятор языка написан на
# самом языке и печатается в C; релиз содержит уже напечатанный C99, поэтому
# формуле нужен только компилятор C, который в системе есть всегда.
#
# Так поступают самоприменяющиеся языки: Go долго возил сгенерированный C, Nim
# возит до сих пор. Проблема начальной загрузки остаётся только у того, кто
# развивает сам язык, — ему нужен Node, чтобы получить первый бинарник из
# исходников на flang. Тому, кто просто ставит flang, не нужен никто.
#
# Что получает поставивший: `flang check файл.flang` — разбор, типы и
# доказательство завершения с человеческой диагностикой; `flang repl` —
# интерактивная оболочка; `flang --help`, `flang --version`, `man flang`. Без
# аргументов бинарник по-прежнему прогонщик: JSON на входе, JSON на выходе.
#
# Релиз готовит `bootstrap/flang io scripts/release-in-c.flang`; он же проверяет сборку в
# окружении без Node, запускает собранный бинарник и прогоняет человеческие
# команды, чтобы битый архив не уехал.
#
# Установка из ещё не опубликованного релиза:
#   brew install --build-from-source ./packaging/homebrew/flang.rb
#
# ── ЧТО ЗДЕСЬ ПРОВЕРЕНО ПРОГОНОМ, А ЧТО НЕТ ─────────────────────────────────
# Честно, потому что раньше здесь всё выглядело рабочим и не работало ничего.
#
# ПРОВЕРЕНО прогоном 18 августа 2026 на чистом месте — во временном каталоге
# вне репозитория, куда распакован скачанный с GitHub архив:
#   • ссылка `url` отдаёт архив: HTTP 200, 929 817 байт (прежде — 404);
#   • `sha256` ниже сверен со скачанным файлом и совпал;
#   • сборка ровно той командой, что стоит в `install` ниже
#     (`make CFLAGS=-std=c99 -Wall -Wextra -Werror -pedantic -O2`) прошла за
#     50,5 с на `cc (Ubuntu 15.2.0-16ubuntu1) 15.2.0` без единого предупреждения;
#   • все семь утверждений блока `test do` ниже выполнены вручную по одному —
#     семь зелёных, ноль красных.
#
# ПРОВЕРЕНО прогоном 5 сентября 2026 — про девять целей печати (задача 7261):
#   • архив собран `bootstrap/flang io scripts/release-in-c.flang --timeout
#     1200000`: 41 файл, из них 32 — рантаймы девяти целей в `runtime/<цель>/`;
#   • тот же архив поставлен ПЛАГИНОМ asdf (`packaging/asdf/bin/install`), и из
#     установленного места все девять целей печатают без единого ключа: девять
#     зелёных, ноль красных. Напечатанное в C собрано `make` и запущено,
#     напечатанное в JS запущено `node` — оба ответили `{"ok":true,"n":"2"}`;
#   • раскладка `share/flang/<цель>` в установке — девять каталогов, среди них
#     `cpp/flang_cpp.hpp`, от которого зависит цель `cpp`;
#   • оба новых утверждения этой пробы (печать в `js`, счёт девяти каталогов)
#     выполнены на той установке напрямую через `ruby -e`: 9 и true, а на копии
#     без `share/flang/go` счёт даёт 8 — то есть проба краснеет, а не молчит;
#   • `ruby -c` на этом файле отвечает Syntax OK.
#
# НЕ ПРОВЕРЕНО: сам `brew`. В этом окружении Homebrew не установлен
# (`command -v brew` пуст), поэтому ни `brew install --build-from-source`, ни
# `brew audit --strict` здесь не запускались. Значит непроверенным остаётся то,
# что умеет только brew: `bin.install`, `man1.install`, `include.install`,
# `(share/"flang").install Dir["runtime/*"]` как перенос ДЕВЯТИ КАТАЛОГОВ (а не
# файлов), песочница сборки и стиль по audit. Эквивалент этого переноса —
# `cp -R runtime/* share/flang/` — прогнан плагином asdf и дал рабочие девять
# целей; но что ровно то же делает `install` у brew, здесь не проверял никто.
# Утверждать «ставится через Homebrew» на этом основании нельзя — можно
# утверждать ровно то, что перечислено выше.
class Flang < Formula
  desc "Проверяемый язык: исполняемая спецификация, печатается в восемь языков"
  homepage "https://github.com/digitable-lol/flang"
  url "https://github.com/digitable-lol/flang/releases/download/v0.7.12/flang-0.7.12-c.tar.gz"
  # Хеш архива, собранного `bootstrap/flang io scripts/release-in-c.flang` и упакованного
  # командой ниже. Пересчитывается при каждом релизе: brew сверяет его сам, и
  # расхождение остановит установку до распаковки.
  #
  # Команда записана целиком и не сокращается до «tar -czf», потому что простой
  # `tar -czf` даёт РАЗНЫЕ байты при одном и том же содержимом: он кладёт в архив
  # время правки файлов, их права и владельца, а печать заводит файлы заново при
  # каждом запуске. Проверено на этом самом архиве: две упаковки одного дерева,
  # между которыми файлу сменили время правки (`touch compiler_flang.c`), дали
  # ПОБАЙТОВО ОДИН И ТОТ ЖЕ файл и один sha256. Хеш, который нельзя повторить,
  # нельзя и проверить: ровно поэтому он и переезжал из релиза в релиз
  # непересчитанным.
  #
  # ДЕВЯТЬ имён перечислены поимённо, а не взяты точкой или звёздочкой: скрипт
  # СОБИРАЕТ напечатанное прямо в том же каталоге, и `tar -czf … .` уносит
  # пользователю ещё и flang_cli, *.o и libcompiler_flang.a — то есть бинарник
  # чужой машины вместо исходников. Проверено распаковкой: в архиве ровно девять
  # файлов, ни одного `.o`, ни одного собранного бинарника.
  #
  # ИМЕНА ДВУХ ИЗ ДЕВЯТИ СМЕНИЛИСЬ В 0.5.2: `kompilyator_flang.[ch]` стали
  # `compiler_flang.[ch]`. Имя файла печать берёт от имени модуля компилятора,
  # модуль звался «Компилятор flang» — и транслит в имени файла запрещён
  # `docs/guide/naming.ru.md`; чинилось это переименованием модуля в
  # «Compiler flang». Команда ниже — для 0.5.2 и новее; для 0.5.1 и старее в ней
  # стоят прежние два имени, всё остальное то же.
  #
  # С 0.5.3 имён ДЕСЯТЬ, а не девять: прибавился каталог рукописных исходников
  # рантайма, без которых `flang emit` не работает у поставившего (см. `install`
  # ниже). Кладётся он именем каталога, а не звёздочкой: `tar` берёт его со всем
  # содержимым, а звёздочка развернулась бы оболочкой и снова унесла бы в архив
  # всё, что рядом.
  #
  # С ВЫПУСКА, СЛЕДУЮЩЕГО ЗА 0.7.11, каталог зовётся `runtime`, а не `runtime-c`,
  # и внутри у него девять каталогов целей — 32 файла на 2 435 747 байт. Прежде
  # он вёз одну цель из девяти, и восемь остальных у поставившего не работали
  # (задача 7261). Число имён от этого не изменилось: каталог как был один, так и
  # остался, — но собирать архив прежней командой с именем `runtime-c` теперь
  # нельзя: `tar` промолчать не промолчит, а вот собранный без этой строки архив
  # снова вернёт беду 7261.
  #
  #   bootstrap/flang io scripts/release-in-c.flang
  #   tar --sort=name --format=ustar --owner=0 --group=0 --numeric-owner \
  #       --mtime=@0 --mode=u=rw,go=r,a+X -C output/release-c -cf - \
  #       LICENSE Makefile compiler_flang.c compiler_flang.h flang.1 \
  #       flang_cli.c flang_repl.c flang_runtime.c flang_runtime.h runtime \
  #     | gzip -9n > output/flang-0.6.2-c.tar.gz
  #
  # LICENSE стоит в списке первым и не забывается: пункт 1 BSD-2-Clause требует
  # сохранять уведомление при распространении исходников, а архив — это ровно
  # распространение исходников. Прежде этой строки в списке не было, хотя
  # scripts/release-in-c.flang файл кладёт: список и скрипт разошлись молча.
  #
  # БУКВА `X` В РЕЖИМЕ ОБЯЗАТЕЛЬНА, и стоила она сломанной установки. `u=rw,go=r`
  # снимает право входа и с КАТАЛОГОВ: `runtime-c` приезжал как `drw-r--r--`,
  # имена внутри видны, а открыть файл нельзя. `brew install` падал на
  # `Errno::ENOENT: runtime-c/flang_cli.c` — и падал у всех, начиная с той версии,
  # где каталог появился. `a+X` даёт право входа каталогам и не трогает файлы,
  # ровно как у chmod. Разбор — в `docs/zettel/a-tar-mode-for-files-locks-directories.md`.
  #
  # Нужен GNU tar: у bsdtar (macOS) нет `--sort` и `--mtime`, и байты выйдут
  # другими. На macOS это `gtar` из пакета `gnu-tar`.
  #
  # ЧИСЛО ОПИСЫВАЕТ ДЕРЕВО, А НЕ ВЕРСИЮ, и это надо знать, читая его. Архив
  # печатается из компилятора, компилятор меняется каждый день — значит хеш
  # верен ровно для того дерева, на котором его считали, и при теге его надо
  # пересчитать ещё раз этой же командой.
  #
  # Метки v0.7.1 и v0.7.2 не удались: у обеих ручная сборка архива не
  # совпала с тем, что собрал сам конвейер на теге (0.7.1 — расхождение
  # полное; 0.7.2 — 4 байта из 4 447 763, причина не разобрана). Оба тега
  # не удалялись (запись запрещена), просто пропущены. v0.7.3 дошла через
  # workflow_dispatch (сухой прогон ДО метки, число взято с конвейера).
  #
  # v0.7.4 — v0.7.9 не дошли ПОДРЯД: 4 сентября 2026 задача 8649 убрала
  # npm и переименовала файл (publish-npm.yml → release.yml), и по дороге
  # решили, что workflow_dispatch с ним ушёл — это оказалось НЕВЕРНО (см.
  # ниже), но выяснилось только после шести пропущенных тегов. Ловились
  # на: чужом хеше от прошлой версии (0.7.4), не совпавшей с конвейером
  # локальной сборке той же документированной командой — причина
  # разошлась не диагностирована (0.7.5), и собственных ошибках
  # координатора при копировании чисел между версиями (0.7.6, 0.7.9). Ни
  # разу ничего битого не вышло: конвейер каждый раз останавливался ДО
  # публикации и сам называл настоящий хеш в тексте ошибки. Ни один тег
  # не удалён, все просто пропущены — тот же принцип, что у v0.7.1/v0.7.2.
  #
  # НАСТОЯЩАЯ ПРИЧИНА, НАЙДЕННАЯ ТОЛЬКО НА СЕДЬМОЙ ПОПЫТКЕ: у release.yml
  # `workflow_dispatch:` НИКУДА НЕ ДЕВАЛСЯ — снят был только у СТАРОГО
  # publish-npm.yml. Шаг сверки тега с package.json гейтится `if:
  # startsWith(github.ref, 'refs/tags/v')` и на ручном прогоне НЕ звучит
  # — значит `gh workflow run <id> --ref main` собирает архив ТЕКУЩЕЙ
  # версии и честно называет её настоящий хеш, без сожжения тега. Число
  # ниже для v0.7.10 снято ровно так — конвейер подтвердил его дважды: в
  # сухом прогоне на main и (это число) на самой метке.
  #
  # Прежде здесь стояло ddf21617… от выпуска 0.7.0, чей архив был байт в
  # байт тем же кодом, но с #define FLANG_VERSION "0.6.2" — строкой,
  # которую забыли бампнуть вместе с package.json (хотфикс:
  # release-versions/9959.md; тот же класс беды снова нашёлся и починен
  # для 0.7.10 — задача 9983). b8d82b1c… от выпуска 0.6.2 стоял ещё раньше,
  # 2 995 862 байта.
  sha256 "e619e1d37b9f48c3ea5455e71d66b202390a9d10fc37e9465994cb1e125c8f9f" # снят с ОПУБЛИКОВАННОГО архива: скачан с гитхаба и сверен с собранным, 6 сентября 2026
  license "BSD-2-Clause"
  version "0.7.12"

  # Node не нужен: в архиве C99 и Makefile. Из внешнего нужен только `make` —
  # он и объявлен; всё остальное даёт компилятор C, который есть в системе
  # всегда. Прежде здесь стояло «ни каких-либо ещё зависимостей» рядом со
  # строкой, объявляющей зависимость, — прозе верили больше, чем коду.
  depends_on "make" => :build

  def install
    # Флаги — часть контракта бэкенда: напечатанный код обязан собираться без
    # единого предупреждения. Ослабить их здесь значило бы скрыть от себя же,
    # что печать испортилась.
    system "make", "CFLAGS=-std=c99 -Wall -Wextra -Werror -pedantic -O2"
    # У программы одно имя — `flang`, и с 0.5.1 его даёт уже сама сборка:
    # `make` кладёт рядом `flang`, а не `flang_cli`. Прежнее имя принимается
    # тоже, потому что архив релиза несёт СВОЙ Makefile: формула обязана
    # ставиться и на архив, собранный до переименования.
    собрано = File.exist?("flang") ? "flang" : "flang_cli"
    bin.install собрано => "flang"
    # Библиотека зовётся по имени модуля компилятора, а имя это менялось: до
    # 0.5.2 модуль звался «Компилятор flang», и печать давала
    # `libkompilyator_flang.a` — транслит в имени файла, запрещённый
    # `docs/guide/naming.ru.md`; с 0.5.2 модуль зовётся «Compiler flang», и
    # печать даёт `libcompiler_flang.a`. Формула ставит выпущенные версии, а
    # среди них есть и те и другие, поэтому имя ИЩЕТСЯ, а не пишется: берётся
    # любой архив, какой собрал `make`. Заголовки ставятся звёздочкой и потому
    # переименования не заметили вовсе.
    lib.install Dir["lib*.a"]
    include.install Dir["*.h"]
    # ИСХОДНИКИ РАНТАЙМА ВСЕХ ДЕВЯТИ ЦЕЛЕЙ — без них `flang emit --target <цель>`
    # не работает у поставившего вовсе. Печать кладёт файлы рантайма в вывод
    # ДОСЛОВНО, то есть читает их с диска, и ищет в `share/flang/<цель>` рядом с
    # бинарником (`emit_runtime_dir` в flang/src/emit/c/flang_repl.c).
    #
    # ДО 5 СЕНТЯБРЯ 2026 СТАВИЛАСЬ ОДНА ЦЕЛЬ ИЗ ДЕВЯТИ. Строка была
    # `(share/"flang/c").install Dir["runtime-c/*"]`, и поставивший через brew
    # получал рабочей ровно цель `c`; `--target js`, `--target go` и шесть
    # остальных отвечали ему «не найдены исходники рантайма», хотя обещаны и в
    # `man`, и в обоих README, и в справке двоичного. Владелец нашёл это живьём
    # на своей машине: в `share/flang` лежал один каталог `c` (задача 7261).
    #
    # Верхние файлы архива для этого НЕ ГОДЯТСЯ, хотя имена те же: наверху лежат
    # напечатанные копии — с шапкой «Сгенерировано flang» в первой строке, — и
    # печать их отвергает по делу, чтобы не приписывать шапку второй раз.
    # Рукописные оригиналы едут каталогом `runtime/<цель>/`; имя названо в
    # scripts/release-in-c.flang. Совпадение с ним стерегла проверка пути
    # установки в flang/test/self-bootstrap.test.mjs — она снята 20 августа 2026
    # коммитом `105943cd`; сегодня его стережёт проба ниже, гоняющая ВСЕ цели,
    # какие назовёт поставленный двоичный, — их девять.
    #
    # СТАВИТСЯ КАТАЛОГ ЦЕЛИКОМ В `share/flang`, А НЕ ПОЦЕЛЬНО, и это не лень:
    # у восьми целей поиск рантайма смотрит в каталог ЦЕЛИ (`share/flang/go`), а
    # у `cpp` — в КОРЕНЬ `share/flang`, потому что три файла из четырёх он берёт
    # из `c/`, и только своё «лицо» `cpp/flang_cpp.hpp` — из `cpp/`. Разложить
    # цели по отдельности и не завести общего корня значило бы сломать `--target
    # cpp` при верно лежащем всём остальном (это нашла задача 8460).
    #
    # Оба условия — не осторожность, а совместимость: формула ставит и выпущенные
    # версии, а в архивах 0.5.3—0.7.11 лежит `runtime-c` с одной целью, в архивах
    # до 0.5.3 нет и его.
    if Dir.exist?("runtime")
      (share/"flang").install Dir["runtime/*"]
    elsif Dir.exist?("runtime-c")
      (share/"flang/c").install Dir["runtime-c/*"]
    end
    # Страница руководства — не украшение. Человек, поставивший язык из brew,
    # ищет `man flang` раньше, чем README в интернете, и не найдя — решает, что
    # инструмента нет. Лежит она в корне архива, туда её кладёт
    # scripts/release-in-c.flang из packaging/flang.1.
    man1.install "flang.1"
  end

  test do
    # Проверяем не «запустился», а «понял язык»: подаём модуль и требуем, чтобы
    # компилятор насчитал в нём ровно одну связанную функцию. Это контракт
    # прогонщика, и он обязан остаться прежним — им живут скрипты, зовущие
    # программу на flang трубой.
    исходник = <<~FLANG
      модуль «Проба»

      тотальная функция «Два»
        возвращает число
        2
    FLANG
    запрос = {
      "fn" => "Число связанных функций",
      "args" => [
        { "l" => [{ "r" => [["путь", { "s" => "проба.flang" }], ["текст", { "s" => исходник }]] }] },
        { "s" => "проба.flang" },
      ],
    }.to_json
    ответ = pipe_output("#{bin}/flang", "#{запрос}\n")
    assert_match '"ok":true', ответ
    assert_match '"n":"1"', ответ

    # А это контракт человека, и проверять его надо отдельно: прежде бинарник
    # ПРИНИМАЛ `--help` и `check`, молчал в ответ и отвечал нулём. Формула,
    # смотревшая только на код возврата, такое бы пропустила — поэтому здесь
    # требуется непустой и осмысленный вывод.
    assert_match "flang #{version}", shell_output("#{bin}/flang --version")
    assert_match "flang check", shell_output("#{bin}/flang --help")
    assert_match "flang check", shell_output("#{bin}/flang -h")
    assert_match "flang #{version}", shell_output("#{bin}/flang -v")

    # Второй этаж справки: `flang <команда> --help` обязан отвечать про КОМАНДУ,
    # а не повторять общий перечень. Ключ, который есть у всех, до 0.5.1
    # отвечал «непонятный ключ» у каждой команды.
    подробно = shell_output("#{bin}/flang check --help")
    assert_match "--proof", подробно
    refute_match "flang test <файл>", подробно

    (testpath/"проба.flang").write(исходник)
    assert_match "проверено", shell_output("#{bin}/flang check проба.flang")

    # Сломанный файл обязан дать ненулевой код и назвать код беды: «всегда 0»
    # и «всегда 1» одинаково бесполезны, поэтому проверяются оба исхода.
    (testpath/"кривая.flang").write(<<~FLANG)
      модуль «Кривая»

      тотальная функция «Два»
        возвращает число
        "два"
    FLANG
    беда = shell_output("#{bin}/flang check кривая.flang 2>&1", 1)
    assert_match "FLANG_TYPE", беда

    # И ПЕЧАТЬ — то, ради чего половина ставит язык, и ровно то, что не
    # работало ни у одного поставившего: рукописного рантайма не было ни в
    # архиве, ни в `share/flang/c`, и `flang emit` отвечал «не найдены исходники
    # рантайма C». Формула, проверявшая только `check`, этого не видела.
    #
    # Каталог назван несуществующий нарочно: `emit` обязан завести его сам, как
    # это делает версия для Node.
    shell_output("#{bin}/flang emit проба.flang --target c --out печать/сюда 2>&1")
    assert_predicate testpath/"печать/сюда/flang_runtime.c", :exist?
    assert_predicate testpath/"печать/сюда/Makefile", :exist?

    # ЩУПАЮТСЯ ВСЕ ДЕВЯТЬ ЦЕЛЕЙ, И ЭТО ЗДЕСЬ ГЛАВНОЕ.
    #
    # До 5 сентября 2026 проба трогала ОДНУ цель `c` — и восемь остальных
    # отвалились молча: формула ставила рантайм одной цели из девяти, а проба
    # была зелена каждый раз и всегда была зелена (задача 7261). Потом целей
    # стало две, `c` и `js`, — и семь оставшихся по-прежнему могли отвалиться,
    # не покраснев. Порода беды одна: сторожат ровно то, что умеют посчитать.
    #
    # СПИСОК ЦЕЛЕЙ НЕ ВЫПИСАН ЗДЕСЬ, А СПРОШЕН У ПОСТАВЛЕННОГО ДВОИЧНОГО —
    # у той самой программы, которую проба и проверяет. Двоичный называет цели
    # сам, макросом `EMIT_TARGETS_WORDS` в flang_repl.c, и печатает их в
    # справке. Выписанная копия списка отстала бы молча при десятой цели:
    # формула ставила бы её, проба бы её не щупала, и всё повторилось бы.
    #
    # У БРАННОГО СПИСКА ПРОВЕРЯЕТСЯ ДЛИНА, и это не педантизм: справка, из
    # которой ничего не вычиталось, дала бы ПУСТОЙ список, цикл ниже не
    # выполнился бы ни разу, и проба зазеленела бы, не пощупав ничего. Ровно
    # тот способ соврать, ради которого весь этот блок и переписан.
    справка = shell_output("#{bin}/flang --help")
    строка_целей = справка.lines.find { |с| с.include?("--target") && с.include?("напечатать программу: ") }
    цели = строка_целей.to_s.split("напечатать программу: ").last.to_s.strip.split("|")
    assert_operator цели.length, :>=, 9,
                    "двоичный назвал целей печати #{цели.length}, а их девять: справка «#{строка_целей}»"

    # Каталог вывода назван несуществующий нарочно, как и у `c` выше: `emit`
    # обязан завести его сам. Проверяется не только код возврата, но и то, что
    # файлы легли: `emit`, отчитавшийся успехом и не положивший ничего, — это
    # ровно тот отказ, который поставивший увидит первым.
    цели.each do |цель|
      shell_output("#{bin}/flang emit проба.flang --target #{цель} --out печать-целей/#{цель} 2>&1")
      refute_empty Dir[testpath/"печать-целей/#{цель}/*"],
                   "flang emit --target #{цель} отчитался успехом, но файлов не положил"
    end

    # И сама раскладка: у каждой названной цели свой каталог под общим корнем.
    # Число проверялось и прежде, но ЧИСЛО НЕ ЕСТЬ СОСТАВ: девять каталогов с
    # чужими именами дали бы то же самое. Корень проверяется отдельным
    # утверждением, потому что от него — и только от него — отсчитывает пути
    # цель `cpp`, а её собственный каталог о ней не говорит ничего (8460).
    assert_predicate share/"flang/cpp/flang_cpp.hpp", :exist?
    цели.each do |цель|
      assert_predicate share/"flang/#{цель}", :directory?
    end
    assert_equal цели.length, Dir[share/"flang/*"].count { |путь| File.directory?(путь) }
  end
end
