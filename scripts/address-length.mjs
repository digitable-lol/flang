const КОРЕНЬ = new URL("..", import.meta.url).pathname
const БИТ_НА_ЗНАК = 5 /* base32: буквы и цифры без похожих друг на друга */

const сорт = (м) => [...м].sort((л, п) => л - п)
const мед = (м) => (м.length % 2 ? м[(м.length - 1) / 2] : (м[м.length / 2 - 1] + м[м.length / 2]) / 2)
const знаки = (бит) => Math.ceil(бит / БИТ_НА_ЗНАК)

/* ─────────────────── поток символов: обратимая развёртка ─────────────────── */

const OBJ = "<{>", OBJEND = "<}>", ARR = "<[>", ARREND = "<]>", TRUE = "<t>", FALSE = "<f>", NULL = "<n>"

function вПоток(значение, поток = []) {
  if (значение === null || значение === undefined) return поток.push(NULL), поток
  const род = typeof значение
  if (род === "boolean") return поток.push(значение ? TRUE : FALSE), поток
  if (род === "number") return поток.push(`i:${значение}`), поток
  if (род === "string") return поток.push(`s:${значение}`), поток
  if (Array.isArray(значение)) {
    поток.push(ARR)
    for (const элемент of значение) вПоток(элемент, поток)
    return поток.push(ARREND), поток
  }
  поток.push(OBJ)
  for (const ключ of Object.keys(значение).sort()) {
    поток.push(`k:${ключ}`)
    вПоток(значение[ключ], поток)
  }
  return поток.push(OBJEND), поток
}

function изПотока(поток) {
  let место = 0
  const шаг = () => {
    const символ = поток[место++]
    if (символ === NULL) return null
    if (символ === TRUE) return true
    if (символ === FALSE) return false
    if (символ.startsWith("i:")) return Number(символ.slice(2))
    if (символ.startsWith("s:")) return символ.slice(2)
    if (символ === ARR) {
      const массив = []
      while (поток[место] !== ARREND) массив.push(шаг())
      return место++, массив
    }
    if (символ === OBJ) {
      const объект = {}
      while (поток[место] !== OBJEND) {
        const ключ = поток[место++].slice(2)
        объект[ключ] = шаг()
      }
      return место++, объект
    }
    throw new Error(`неизвестный символ: ${JSON.stringify(символ)}`)
  }
  const итог = шаг()
  if (место !== поток.length) throw new Error(`хвост потока: ${место} из ${поток.length}`)
  return итог
}

/* ───────────────────────────── корпус ────────────────────────────────────── */

function собрать(каталог) {
  const записи = []
  for (const файл of readdirSync(`${КОРЕНЬ}${каталог}`).filter((и) => и.endsWith(".flang")).sort()) {
    let программа
    try {
      программа = parse(readFileSync(`${КОРЕНЬ}${каталог}/${файл}`, "utf8"), файл)
    } catch {
      continue /* файл-заготовка: в замер не идёт */
    }
    for (const [имя, свод] of адресаОпределений(программа).нормализованные) {
      const канон = каноническийJSON(свод)
      const поток = вПоток(свод)
      if (каноническийJSON(изПотока(поток)) !== канон) throw new Error(`поток необратим: ${файл}/${имя}`)
      записи.push({ файл, имя, поток, канон })
    }
  }
  return записи
}

/* ──────────────────── словарь языка и запись номерами ────────────────────── */

function словарьПо(записи, порог) {
  const счёт = new Map()
  for (const запись of записи) for (const символ of запись.поток) счёт.set(символ, (счёт.get(символ) ?? 0) + 1)
  return [...счёт.entries()]
    .filter(([, сколько]) => сколько >= порог)
    .sort((л, п) => п[1] - л[1] || (л[0] < п[0] ? -1 : 1))
    .map(([символ]) => символ)
}

/** Записыватель по словарю: частый символ — один байт, незнакомый — по буквам. */
function записыватель(СЛОВАРЬ) {
  const НОМЕР = new Map(СЛОВАРЬ.map((символ, номер) => [символ, номер]))
  const ESC = СЛОВАРЬ.length
  const число = (байты, значение) => {
    let н = значение
    while (н >= 0x80) байты.push((н & 0x7f) | 0x80), (н >>>= 7)
    байты.push(н)
  }
  const записать = (поток) => {
    const байты = []
    for (const символ of поток) {
      const номер = НОМЕР.get(символ)
      if (номер !== undefined) число(байты, номер)
      else {
        число(байты, ESC)
        const текст = Buffer.from(символ, "utf8")
        число(байты, текст.length)
        for (const байт of текст) байты.push(байт)
      }
    }
    return Buffer.from(байты)
  }
  const прочитать = (буфер) => {
    const поток = []
    let место = 0
    const число = () => {
      let значение = 0
      let сдвиг = 0
      while (буфер[место] & 0x80) (значение |= (буфер[место++] & 0x7f) << сдвиг), (сдвиг += 7)
      return значение | (буфер[место++] << сдвиг)
    }
    while (место < буфер.length) {
      const номер = число()
      if (номер !== ESC) поток.push(СЛОВАРЬ[номер])
      else {
        const длина = число()
        поток.push(буфер.subarray(место, место + длина).toString("utf8"))
        место += длина
      }
    }
    return поток
  }
  return { записать, прочитать, НОМЕР }
}

const сжать = (буфер) =>
  brotliCompressSync(буфер, {
    params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: буфер.length },
  })

/** Длина адреса в битах — и ПРОВЕРКА, что из адреса выходит ровно тот же код. */
function адрес(запись, инструмент) {
  const номера = инструмент.записать(запись.поток)
  const сжато = сжать(номера)
  const обратно = каноническийJSON(изПотока(инструмент.прочитать(brotliDecompressSync(сжато))))
  if (обратно !== запись.канон) throw new Error(`адрес не восстанавливает код: ${запись.файл}/${запись.имя}`)
  return сжато.length * 8
}

