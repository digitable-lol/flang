/**
 * ДЛИНА САМОДОСТАТОЧНОГО АДРЕСА — замер к `docs/self-contained-address-length.md`.
 *
 * Вопрос: если адрес не хеш, а САМ КОД, обратимо сжатый и записанный буквами,
 * то сколько в нём знаков? Тогда склад не нужен вовсе: адрес разворачивается
 * обратно в код у того, кто его получил.
 *
 * Здесь не рассуждают, а меряют, и обратимость ПРОВЕРЯЕТСЯ на каждой функции:
 * адрес → brotli → номера по словарю → поток символов → дерево → тот же
 * канонический JSON, что и на входе. Если хоть одна не сошлась — замер падает.
 *
 * Запуск: `node scripts/address-length.mjs`
 */
