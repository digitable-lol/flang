#!/bin/sh
# НОМЕР РЕШЕНИЯ ЗАНЯТ НЕ ОДНИМ РЕШЕНИЕМ — проверка.
#
#   sh scripts/adr-numbers-are-unique-guard.sh
#   sh scripts/adr-numbers-are-unique-guard.sh --подлог   проба на себе
#
# Код 0 — каждый номер занят ровно одним решением; 1 — нет, и каждый назван.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# У задачника такая проверка есть, и она ловит гонку номеров: 26 августа 2026
# три задачи разом взяли 0055, потому что номер выбирали взглядом на каталог.
# У решений (`docs/adr/`) её не было — и там уже задвоены ТРИ номера: 0005,
# 0007 и 0008. Ссылки при этом ведут по имени файла, поэтому беда не видна
# читателю и не мешает работать, пока кто-нибудь не сошлётся «на ADR-0008».
#
# Номер берётся из ЗАГОЛОВКА (`# ADR-NNNN.`), а не из имени файла: два решения
# в дереве заголовок несут, а номера в имени не имеют, и наоборот.
#
# ── Почему на оболочке ───────────────────────────────────────────────────────
# Проверка чисто текстовая: ни компилятора, ни семени, ни Node. Значит она
# работает и тогда, когда двоичный отстал, а перепечатка не доходит, — то есть
# ровно в те дни, когда всё остальное красно не по делу.
#
# Имена здесь латиницей, как в scripts/raskrutka.sh: ни dash, ни bash не
# принимают кириллицу в именах.
set -u

KATALOG=${KATALOG:-docs/adr}
VREMENNOE=${VREMENNOE:-/srv/tmp}
podlog=нет
[ "${1:-}" = "--подлог" ] && podlog=да

rabota=$KATALOG
if [ "$podlog" = "да" ]; then
  rabota=$(mktemp -d "$VREMENNOE/adr-podlog.XXXXXX") || exit 2
  cp "$KATALOG"/*.md "$rabota"/ 2>/dev/null
  # подкладываем заведомую двойню на свободный номер
  printf '# ADR-9999. Первое решение подлога\n' > "$rabota/9999-pervoe.md"
  printf '# ADR-9999. Второе решение подлога\n' > "$rabota/9999-vtoroe.md"
fi

spisok=$(for f in "$rabota"/*.md; do
  [ -f "$f" ] || continue
  n=$(head -5 "$f" | grep -oE 'ADR-[0-9]{4}' | head -1 | sed 's/ADR-//')
  [ -n "$n" ] && printf '%s\t%s\n' "$n" "$(basename "$f")"
done | sort)

vsego=$(printf '%s\n' "$spisok" | grep -c .)
dvojni=$(printf '%s\n' "$spisok" | cut -f1 | uniq -d)

if [ -z "$dvojni" ]; then
  printf 'номера решений: решений %s, задвоенных номеров нет\n' "$vsego"
  [ "$podlog" = "да" ] && { printf 'ПОДЛОГ НЕ ПОЙМАН — проверка сломана\n' >&2; rm -rf "$rabota"; exit 1; }
  exit 0
fi

printf 'номера решений: решений %s, ЗАДВОЕНЫ:\n' "$vsego"
for n in $dvojni; do
  printf '  ADR-%s занят не одним решением:\n' "$n"
  printf '%s\n' "$spisok" | awk -F'\t' -v n="$n" '$1==n {print "      " $2}'
done
if [ "$podlog" = "да" ]; then
  printf 'подлог пойман: ADR-9999 назван двумя файлами\n'
  rm -rf "$rabota"
  exit 1
fi
exit 1
