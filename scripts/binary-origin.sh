# Отказ судить двоичным, которого нельзя собрать из bootstrap/ этого дерева.
#
# ── ПОЧЕМУ ЭТОТ ФАЙЛ НА ОБОЛОЧКЕ, А НЕ НА flang ────────────────────────────
# Спрашиваемое здесь — сам двоичный. Программа на flang исполнялась бы ИМ ЖЕ,
# и подсудимый отвечал бы о себе: двоичный, несущий чужой код, одинаково
# способен и нести его, и сказать, что не несёт. Ровно тот же довод стоит у
# scripts/raskrutka.sh и scripts/new-binary-acceptance.sh. Долгом дерева этот
# файл поэтому не считается — scripts/tree-inventory.flang, довод «сверка
# двоичного и его печати».
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# 23 августа 2026 в двадцати рабочих копиях лежал bootstrap/flang с отпечатком
# 2e640f12, 14 068 248 байт, и им судили дерево. К 29 августа их стал 21 —
# двоичные разъезжаются по копиям сами собой, и в этом половина беды. Сборка из семени, лежащего в
# тех же копиях, давала другой двоичный — на 80 байт короче. Чтобы узнать, чем
# они различаются, пришлось перебрать все 5418 коммитов хранилища и собрать
# компилятор трижды.
#
# Разница оказалась в ОДНОЙ функции рантайма: `fl_name_same` — быстрое сравнение
# имён из ветки b/bystro-sravnenie-imyon (коммит b7f3bd5e). Двоичный собрали из
# рабочей копии, где сошлись ДВЕ невлитые ветки: ключ `--предел-шагов` из
# b/predel и `fl_name_same` из b/bystro-sravnenie-imyon. Такого дерева нет ни в
# одном из 5418 коммитов хранилища — проверено сплошным перебором.
#
# Снаружи не было видно НИЧЕГО. Замер 29 августа 2026, оба двоичных рядом:
# `--version` один и тот же; .rodata у обоих ровно 692 593 байта; строк с
# кириллицей в .rodata 12 157 у каждого, и это ОДНО И ТО ЖЕ множество — ни одной
# лишней, ни одной пропавшей. Расходились .text (на 384 байта), таблицы кадров
# (.eh_frame на 2880) и таблица имён — то, на что при сверке не смотрит никто.
#
# Все 80 байт разницы в размере файла — это две лишние записи в таблице имён
# (48 байт), сами имена (30 байт) и 2 байта выравнивания перед заголовками
# разделов. Разница в 384 байта кода и 2880 байт таблиц кадров до размера файла
# НЕ ДОШЛА вовсе: её съели зазоры выравнивания. Отсюда и вывод: судить о
# происхождении двоичного по размеру или по строкам нельзя, только по именам или
# побайтовой пересборкой.
#
# Двоичный, судивший язык с доказательствами, шесть суток нёс в себе код,
# которого в хранилище не лежало.
#
# Эта проверка смотрит именно туда, и быстрая её половина стоит полсекунды.
#
# ── Две сверки, и они разной силы. Обе нужны ────────────────────────────────
#
# БЫСТРАЯ (полсекунды, умолчание). Берёт из двоичного имена всех определённых в
# нём функций и переменных и требует, чтобы каждое имя встречалось в
# bootstrap/*.c и bootstrap/*.h. Имя, которого в семени нет, — это код, которого
# в дереве нет.
#
# Замер 29 августа 2026. У двоичного, собранного из семени, за пределами семени
# остаются ровно 17 имён, и все 17 — от компоновщика и запуска программы
# (_start, _init, frame_dummy и подобные); их список стоит ниже целиком, и после
# его вычитания не остаётся НИ ОДНОГО. У двоичного 23 августа остаются два:
# `fl_name_same` и `fl_max_steps_told` — по одному от каждой невлитой ветки.
#
# Замер 29 августа 2026 на этом дереве: 0,84 с вхолодную и 0,15 с, когда ответ
# уже запомнен (см. «Память ответа» ниже).
#
# ЧЕГО ОНА НЕ ЛОВИТ, и это надо знать, — всё, что не заводит НОВОГО ИМЕНИ:
#
#   * правку одного числа. Двоичный с поднятым потолком
#     (`#define FL_MAX_STEPS 40000000000`, 28 копий на машине) для неё
#     неотличим от обычного: изменилось число, а не имя;
#   * сборку из того же семени другими ключами (-O0 вместо -O2, без -flto):
#     код выйдет другой, имена — те же.
#
# И то и другое ловит только точная сверка. Быстрая отвечает на вопрос «есть ли
# в двоичном КОД, которого нет в дереве», и на него отвечает надёжно; вопрос
# «тот ли это в точности двоичный» — не её.
#
# ТОЧНАЯ. Собирает компилятор из bootstrap/ этого дерева во временный каталог и
# требует ПОБАЙТОВОГО совпадения с двоичным, который лежит в дереве. Это и есть
# полный ответ на вопрос «собирается ли он из того, что лежит в хранилище».
#
# Стоит она ровно столько же, сколько `make -C bootstrap`, потому что это она и
# есть. Замеры 29 августа 2026 на этой машине: 63 секунды на восьми ядрах при
# свободной машине и 187 секунд на ней же при загрузке 80. Число зависит от
# соседей, и обещать его нельзя; обещать можно, что дороже сборки она не станет.
#
# Для сравнения: `sh scripts/raskrutka.sh --check` отвечает на СОСЕДНИЙ вопрос
# (побайтово ли семя совпадает с печатью) и стоит 19 мин 58 с и 25,1 ГиБ — его
# и не звал никто. Здесь вопрос другой и цена другая.
#
# Побайтовое сравнение имеет смысл только потому, что сборка ПОВТОРЯЕМА, и это
# не предположение: двоичный, собранный 29 августа в другом каталоге, сошёлся
# байт в байт с собранным 23 августа (2e640f12, sha256 534ccc74…, 14 068 248
# байт) — другой день, другой каталог, другое число ветвей у make. Значит
# несовпадение здесь говорит об ИСХОДНИКАХ, а не о погоде.
#
# Оговорка, без которой сверка врёт: повторяемость эта — на одном и том же
# компиляторе C. Другой cc даст другие байты при тех же исходниках, поэтому его
# версия входит в память ответа, а при расхождении она названа в отказе.
#
# ── Память ответа, и чем она опасна ─────────────────────────────────────────
#
# Ответ ОБЕИХ сверок запоминается рядом с хранилищем (не в дереве, в каталоге
# .git) по четырём приметам: отпечаток двоичного, отпечаток шести файлов семени,
# отпечаток ЭТОГО ФАЙЛА и версия компилятора C. Сменилась любая — сверка идёт
# заново.
#
# Запоминается только СОШЁЛСЯ. Отказ не помнится никогда: иначе починенный
# двоичный не пустили бы по памяти о старом.
#
# Отпечаток самого файла попал в приметы не для красоты. Без него сверка верила
# бы ответу, записанному ПРЕЖНЕЙ её версией, — и это поймала её же
# самопроверка (`--подлог`) 29 августа 2026: нарочно ослеплённый сторож записал
# «сошлось» на подложную программу, а починенный пропустил ту же программу по
# этой записи. Всякая правка сторожа обесценивает все прежние ответы, и это
# правильная цена.
#
# ── Как звать ───────────────────────────────────────────────────────────────
#   sh scripts/binary-origin.sh                    быстрая сверка
#   sh scripts/binary-origin.sh --точно            точная (пересборка)
#   sh scripts/binary-origin.sh --чем "<имя>"      назвать, кто спрашивает
#   sh scripts/binary-origin.sh -- <команда…>      отказать или запустить
#   sh scripts/binary-origin.sh --подлог           проверить самого сторожа:
#                                                  два подлога, оба обязаны быть
#                                                  замечены (имя и пустота)
#
# Латиницей то же: --exact, --what, --forgery.
#
# Какой двоичный судится: FLANG_BINARY, иначе FLANG_BIN, иначе
# <корень>/bootstrap/flang. Два имени — не прихоть: первым зовут двоичный
# оснастка на Node, вторым — обходчики на оболочке, и сторожить надо оба.
#
# Коды: 0 — двоичный отвечает семени (или сработал ключ обхода);
#       1 — не отвечает, судить отказано;
#       2 — только у `--подлог`: часть самопроверки не снята (нет strip).
#           ЭТО НЕ ПРОЙДЕННАЯ ПРОВЕРКА;
#       3 — сверить не удалось вовсе (нет двоичного, нет readelf, снята таблица
#           имён). ЭТО ТОЖЕ НЕ ПРОЙДЕННАЯ ПРОВЕРКА.
#
# ── Где эта сверка стоит ────────────────────────────────────────────────────
#
# 1. scripts/seed-freshness.sh — перед каждым ярлыком о доказательствах, то есть
#    перед всяким ответом, который зависит от двоичного;
# 2. работа CI «Двоичный» (.github/workflows/binary.yml) — сразу после сборки.
#    Там ответ известен заранее, и стоит она ради самой себя: сторож, который
#    нигде не запускается, ломается тихо. Следом там же идёт `--подлог`.
#
# ── Ключ обхода ─────────────────────────────────────────────────────────────
#   FLANG_BINARY_UNKNOWN_OK=1 <та же команда>
#
# Он обязателен: тот, кто ЧИНИТ двоичный, обязан уметь прогнать им проверку до
# того, как починка доедет до дерева. Ключ не тихий — при обходе в поток бед
# уходит строка о том, чем судили.
#
# Имена переменных здесь латиницей: ни dash, ни bash не принимают кириллицу в
# именах переменных. Слова взяты английские, а не русские латиницей.

set -eu

# LC_ALL=C — не украшение, а условие правильности `comm`. `sort` под русской
# раскладкой раскладывает строки ПО ПРАВИЛАМ ЯЗЫКА, а `comm` сравнивает их ПО
# БАЙТАМ; при расхождении `comm` тихо теряет часть строк. Тот же довод записан
# в scripts/raskrutka.sh, там он стоил потерянной цели печати.
export LC_ALL=C

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
BYPASS=FLANG_BINARY_UNKNOWN_OK

err() { printf '%s\n' "$*" >&2; }

# Отпечаток файла. md5sum есть в GNU, `md5 -q` — в BSD и macOS; cksum обязателен
# по POSIX и остаётся последним доводом. Здесь отпечаток нужен как ИМЯ РАВЕНСТВА,
# а не как защита от подделки: равенство двоичных решает `cmp`, побайтово.
fingerprint() {
  if command -v md5sum >/dev/null 2>&1; then md5sum "$1" | cut -d' ' -f1
  elif command -v md5 >/dev/null 2>&1; then md5 -q "$1"
  else cksum "$1" | cut -d' ' -f1
  fi
}

# Размер файла. `stat` разошёлся между GNU и BSD доводами, `wc -c` — нет.
bytes() { wc -c < "$1" | tr -d ' '; }

# Сколько ветвей давать сборке. Взято как в `ярлык`: getconf есть в GNU, sysctl
# в BSD и macOS, четыре — если не ответил никто. На ответ сборки это не влияет:
# `-j8` и `-j1` дают один и тот же двоичный (замер 23 и 29 августа 2026), —
# влияет только на время.
cores() { (getconf _NPROCESSORS_ONLN 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 4) | tr -d ' '; }

what="эта проверка"
exact=0
forgery=0
while [ $# -gt 0 ]; do
  case $1 in
    --точно|--exact) exact=1; shift ;;
    --подлог|--forgery) forgery=1; shift ;;
    --чем|--what) [ $# -ge 2 ] || { err "--чем без имени"; exit 3; }; what=$2; shift 2 ;;
    --) shift; break ;;
    -*) err "неизвестный довод: $1"; exit 3 ;;
    *) break ;;
  esac
done

# Какой двоичный судить. Имён у этого в дереве ДВА, и оба настоящие:
# `FLANG_BINARY` смотрит оснастка на Node (flang/scripts/binary.mjs, docs/site/
# build.mjs) — им и печатаются ведомости доказательств; `FLANG_BIN` смотрят
# обходчики на оболочке (flang/проверки/обход.sh и обход-примеров.sh).
#
# Сверять надо ТОТ ЖЕ двоичный, которым потом судят, иначе сторож стережёт не то:
# при `FLANG_BINARY=/чужой/flang ./ярлык доказательства:ведомость` он проверил бы
# bootstrap/flang, а ведомость сняли бы чужим. Поэтому здесь смотрятся оба, и
# первым — тот, которым судит оснастка.
bin=${FLANG_BINARY:-${FLANG_BIN:-"$ROOT/bootstrap/flang"}}

# ── Обход по ключу: разрешаем, но вслух ─────────────────────────────────────
#
# Самопроверку (`--подлог`) он НЕ снимает, и это нарочно: она судит сторожа, а
# не двоичный, и зазеленеть от ключа обхода не имеет права. Стоит ключ выше
# самопроверки только потому, что `cannot_check` объявлен ниже, а вызывают его
# оба.
if [ -n "${FLANG_BINARY_UNKNOWN_OK:-}" ] && [ "$forgery" = 0 ]; then
  err "$BYPASS: судим двоичным без сверки с семенем по прямому указанию."
  err "Двоичный: $bin"
  if [ $# -gt 0 ]; then exec "$@"; fi
  exit 0
fi

cannot_check() {
  err "СВЕРИТЬ ДВОИЧНЫЙ НЕ УДАЛОСЬ — судить о доказательствах нельзя: $what"
  err ""
  err "$1"
  err ""
  err "Пропуск не есть пройденная проверка: судить всё равно —"
  err "  $BYPASS=1 <та же команда>"
  exit 3
}

[ -f "$bin" ] || cannot_check "двоичного нет вовсе: $bin
Соберите его: make -C bootstrap"
[ -x "$bin" ] || cannot_check "двоичный есть, но не запускается: $bin"

SEED_FILES='compiler_flang.c compiler_flang.h flang_cli.c flang_repl.c flang_runtime.c flang_runtime.h'
for f in $SEED_FILES; do
  [ -f "$ROOT/bootstrap/$f" ] || cannot_check "в дереве нет файла семени bootstrap/$f — сверять не с чем"
done

# ── ПОДЛОГ: сторож обязан уметь покраснеть ──────────────────────────────────
#
# Сторож, который не показали красным, ничего не стоит: он мог сломаться год
# назад и всё это время молча зеленеть. Здесь подкладывается программа, в
# которой ЗАВЕДОМО есть имя, которого в семени быть не может, и от быстрой
# сверки требуется отказ. Стоит это одну секунду и одного `cc`.
#
# Подкладывается настоящий двоичный ELF, а не порченый байт: сверка читает
# таблицу имён, и обрезанный файл проверил бы не то — он ушёл бы в «сверить не
# удалось», а нужен ОТКАЗ.
if [ "$forgery" = 1 ]; then
  command -v "${CC:-cc}" >/dev/null 2>&1 || cannot_check "нет ${CC:-cc} — подложить нечего"
  work=$(mktemp -d "${TMPDIR:-/tmp}/binary-origin-forgery.XXXXXX") \
    || cannot_check "не завёлся временный каталог"
  trap 'rm -rf "$work"' EXIT INT TERM HUP
  cat > "$work/forged.c" <<'FORGED'
int flang_binary_origin_forged_name(void) { return 0; }
int main(void) { return flang_binary_origin_forged_name(); }
FORGED
  "${CC:-cc}" -o "$work/forged" "$work/forged.c" 2>/dev/null \
    || cannot_check "подложную программу не удалось собрать"

  # Ключ обхода снимается НАРОЧНО: с ним внутренний прогон вернул бы 0, и
  # самопроверка объявила бы сторожа слепым на ровном месте — или, что хуже,
  # зеленела бы сама, стой она после обхода. Поэтому она стоит ДО него.
  out=$(FLANG_BINARY_UNKNOWN_OK= FLANG_BINARY_ORIGIN_NO_MEMORY=1 FLANG_BINARY= \
        FLANG_BIN="$work/forged" sh "$0" 2>&1) && code=0 || code=$?
  if [ "$code" != 1 ]; then
    err "СТОРОЖ СЛЕП: на подложенной программе он ответил кодом $code вместо 1."
    printf '%s\n' "$out" >&2
    exit 1
  fi
  case $out in
    *flang_binary_origin_forged_name*) ;;
    *) err "СТОРОЖ ОТКАЗАЛ, но не назвал подложное имя — отказ не по делу:"
       printf '%s\n' "$out" >&2
       exit 1 ;;
  esac
  echo "подлог именем: сторож покраснел и назвал имя — видит."

  # ВТОРОЙ ПОДЛОГ: снятая таблица имён. У такого двоичного остаётся `.dynsym` —
  # сотня имён libc, и все они в семени встречаются вызовами, поэтому сверка по
  # именам находит ноль чужих и зеленеет на пустоте. Ровно это она и делала
  # 29 августа 2026, пока подлог не показал. Требуется код 3 («сверить не
  # удалось»), а не 0 и не 1: сказать тут нечего, и молчать об этом нельзя.
  if ! command -v strip >/dev/null 2>&1; then
    err "ЧАСТЬ САМОПРОВЕРКИ НЕ СНЯТА: нет strip, подлог снятой таблицей имён не сделан."
    err "Пропуск не есть пройденная проверка."
    exit 2
  fi
  if ! cp "$bin" "$work/stripped" || ! strip "$work/stripped" 2>/dev/null; then
    cannot_check "снять таблицу имён с копии двоичного не удалось"
  fi

  out=$(FLANG_BINARY_UNKNOWN_OK= FLANG_BINARY_ORIGIN_NO_MEMORY=1 FLANG_BINARY= \
        FLANG_BIN="$work/stripped" sh "$0" 2>&1) && code=0 || code=$?
  if [ "$code" != 3 ]; then
    err "СТОРОЖ СЛЕП: на двоичном со снятой таблицей имён он ответил кодом $code вместо 3."
    printf '%s\n' "$out" >&2
    exit 1
  fi
  echo "подлог пустотой: сторож отказал кодом 3, а не зазеленел, — видит."
  exit 0
fi


# ── Память ответа ───────────────────────────────────────────────────────────
#
# Обе сверки помнят свой ответ, и обе помнят его по одному и тому же признаку:
# отпечаток двоичного, отпечаток шести файлов семени и версия компилятора C.
# Сменилось что угодно из трёх — сверка идёт заново.
#
# Лежит память в каталоге .git, а не в дереве: она про ЭТУ рабочую копию и
# коммититься не должна ни при каких обстоятельствах.
#
# Зачем она быстрой сверке, которая и так стоит меньше секунды: `ярлык` зовёт
# её перед КАЖДЫМ из двадцати ярлыков о доказательствах, и полсекунды на каждый
# складываются в десяток. Сторож, который заметно мешает, начинают обходить
# ключом, а обойдённый сторож не сторож.
# В примету входит и отпечаток САМОГО ЭТОГО ФАЙЛА, и это не украшение. Без него
# сверка верила бы ответу, записанному ПРЕЖНЕЙ, возможно испорченной, её
# версией. Поймано собственной самопроверкой (`--подлог`) 29 августа 2026:
# нарочно ослеплённый сторож записал «сошлось» на подложную программу, и
# следом ПОЧИНЕННЫЙ сторож пропустил её же по этой записи. Теперь всякая правка
# сторожа обесценивает все прежние ответы, и это правильная цена.
remember_key() {
  cat "$ROOT/bootstrap/compiler_flang.c" "$ROOT/bootstrap/compiler_flang.h" \
      "$ROOT/bootstrap/flang_cli.c" "$ROOT/bootstrap/flang_repl.c" \
      "$ROOT/bootstrap/flang_runtime.c" "$ROOT/bootstrap/flang_runtime.h" > "$1/seed-whole"
  printf '%s %s %s %s %s\n' "$2" "$(fingerprint "$bin")" "$(fingerprint "$1/seed-whole")" \
    "$(fingerprint "$0")" "$("${CC:-cc}" --version 2>/dev/null | head -1)"
  rm -f "$1/seed-whole"
}

# Самопроверка идёт БЕЗ памяти: она судит сторожа, а не двоичный, и ответ о
# подложной программе не должен ни читаться из памяти, ни попадать в неё.
memory=''
if [ -n "${FLANG_BINARY_ORIGIN_NO_MEMORY:-}" ]; then
  memory=''
elif git_dir=$(cd "$ROOT" && git rev-parse --git-dir 2>/dev/null); then
  case $git_dir in
    /*) memory=$git_dir/binary-origin.checked ;;
    *)  memory=$ROOT/$git_dir/binary-origin.checked ;;
  esac
fi

remembered() {
  [ -n "$memory" ] && [ -f "$memory" ] && grep -qxF "$1" "$memory"
}

# Память — удобство, а не правильность: не записалась, значит следующий раз
# сверим заново. Поэтому здесь ни одна беда не роняет прогон.
#
# Записи от ПРЕЖНИХ версий сторожа выбрасываются: они всё равно никогда больше не
# совпадут (отпечаток сторожа входит в примету), а лежать и расти будут вечно.
# Признак «своей» записи — тот же отпечаток файла, что у сторожа сейчас.
remember() {
  [ -n "$memory" ] || return 0
  mine=$(fingerprint "$0")
  if {
       if [ -f "$memory" ]; then
         awk -v mine="$mine" '$4 == mine' "$memory" | grep -vxF "$1" || true
       fi
       printf '%s\n' "$1"
     } > "$memory.tmp" 2>/dev/null
  then
    mv "$memory.tmp" "$memory" 2>/dev/null || rm -f "$memory.tmp"
  else
    rm -f "$memory.tmp"
  fi
  return 0
}

# `exec` подменяет процесс, и ловушка EXIT уже не сработает: убираем сами.
run_and_leave() {
  work_dir=$1; shift
  # Не `[ -n … ] && rm …`: под `set -eu` такая строка при пустом имени вернёт 1 и
  # уронит весь прогон вместо того, чтобы просто ничего не убирать.
  if [ -n "$work_dir" ]; then rm -rf "$work_dir"; fi
  trap - EXIT INT TERM HUP
  exec "$@"
}

# ── ТОЧНАЯ СВЕРКА ───────────────────────────────────────────────────────────
if [ "$exact" = 1 ]; then
  command -v make >/dev/null 2>&1 || cannot_check "нет make — пересобрать нечем"
  command -v "${CC:-cc}" >/dev/null 2>&1 || cannot_check "нет ${CC:-cc} — пересобрать нечем"

  work=$(mktemp -d "${TMPDIR:-/tmp}/binary-origin.XXXXXX") || cannot_check "не завёлся временный каталог"
  trap 'rm -rf "$work"' EXIT INT TERM HUP

  # В bootstrap/ ничего не пишется даже временно: он и есть предмет сверки.
  stamp=$(remember_key "$work" побайтово)
  cc_id=$("${CC:-cc}" --version 2>/dev/null | head -1)
  if remembered "$stamp"; then
    if [ $# -gt 0 ]; then run_and_leave "$work" "$@"; fi
    exit 0
  fi

  cp "$ROOT/bootstrap/Makefile" "$work/" 2>/dev/null || cannot_check "нет bootstrap/Makefile"
  for f in $SEED_FILES; do
    cp "$ROOT/bootstrap/$f" "$work/"
  done
  if ! (cd "$work" && make -j"$(cores)" >"$work/build.log" 2>&1); then
    err "сборка из семени не прошла — вот её конец:"
    tail -20 "$work/build.log" >&2
    cannot_check "собрать компилятор из bootstrap/ этого дерева не удалось"
  fi

  if cmp -s "$work/flang" "$bin"; then
    remember "$stamp"
    if [ $# -gt 0 ]; then run_and_leave "$work" "$@"; fi
    exit 0
  fi

  err "ОТКАЗЫВАЮСЬ СУДИТЬ: двоичный не собирается из семени этого дерева: $what"
  err ""
  err "  двоичный в дереве: $(fingerprint "$bin")  $(bytes "$bin") байт"
  err "  сборка из семени:  $(fingerprint "$work/flang")  $(bytes "$work/flang") байт"
  err "  собрано: ${CC:-cc} — $cc_id"
  err ""
  err "Это тот же случай, что 23 августа 2026: в двадцати рабочих копиях лежал"
  err "двоичный, собранный из невлитых веток. Отличий не было видно ни в номере"
  err "версии, ни в печатных строках — только в коде."
  err ""
  err "Чинится одним из двух:"
  err "  * пересобрать двоичный из дерева:  make -C bootstrap"
  err "  * или закоммитить то, из чего он на самом деле собран."
  err ""
  err "Судить всё равно, зная это: $BYPASS=1 <та же команда>"
  exit 1
fi

