/**
 * Точка раскрутки `bootstrap/`: имена, пределы печати и сверка байтов.
 *
 * ── Что это и чего здесь БОЛЬШЕ НЕТ ─────────────────────────────────────────
 * `bootstrap/` — компилятор flang, напечатанный в самодостаточный C99 и
 * закоммиченный в дерево. Он нужен ровно для одного: собрать работающий
 * компилятор, имея только `cc` и `make`.
 *
 * Печатал его ЭТОТ файл, и потому Node лежал на пути СБОРКИ, а не только в
 * проверках: удали реализацию на JavaScript — и восстановить компилятор из
 * `flang/self/*.flang` стало бы нечем. Печать переехала в `scripts/bootstrap-c.sh`,
 * где её делает САМ ДВОИЧНЫЙ (`bootstrap/flang emit --target c`), а 20 августа
 * 2026 реализация на JavaScript была удалена из дерева целиком. Функции
 * `напечатать()` и `записать()` вместе с режимом скрипта сняты отсюда тем же
 * заходом: они звали `flang/bin/flang.mjs`, которого больше нет.
 *
 * Осталось то, что от реализации языка не зависит вовсе и нужно другим:
 * имена и пределы (`ВХОД`, `КАТАЛОГ`, `ПРЕДЕЛЫ`, `НЕ_ТОЧКА`), список
 * закоммиченного (`именаЗамороженного`) и сверка байтов (`расхождения`).
 * Их берут `scripts/build-release-c.mjs` и проверки в `flang/test/`.
 *
 * ── Порядок обновления ──────────────────────────────────────────────────────
 * Точка раскрутки — АРТЕФАКТ, а не исходник. Править её руками нельзя: правка
 * потеряется при первой перепечатке, а проверка её и не пропустит. Обновляется
 * она в том же коммите, что и правка компилятора:
 *
 *   sh scripts/bootstrap-c.sh              перепечатать bootstrap/ двоичным
 *   sh scripts/bootstrap-c.sh --check      сверить закоммиченное с печатью
 *
 * ЧИСЛО, СНЯТОЕ ПОКА БЫЛО С ЧЕМ СВЕРЯТЬ. 20 августа 2026, на дереве от
 * `c3bebbf0`, в окружении без Node (`env -i PATH=/usr/bin:/bin`): двоичный
 * напечатал 7 файлов и 15 641 371 байт, и ВСЕ СЕМЬ совпали с печатью
 * реализации на JavaScript байт в байт — `Makefile` 2 893, `compiler_flang.c`
 * 12 353 351, `compiler_flang.h` 2 525 322, `flang_cli.c` 49 020,
 * `flang_repl.c` 499 612, `flang_runtime.c` 150 606, `flang_runtime.h` 60 567.
 * Печать двоичного стоила 5 м 37 с и 8,3 ГБ памяти против 3,4 с у Node.
 * Повторить эту сверку уже нельзя: вторую печать удалили.
 *
 * ── Почему каталог, а не один склеенный файл ────────────────────────────────
 * Потому что каталог — это РОВНО ТО, что печатает бэкенд, без единого
 * преобразования между печатью и деревом. Печать выдаёт эти файлы, включая
 * Makefile; склейка потребовала бы своего кода (порядок заголовков, снятие
 * `#include`), и этот код сам стал бы предметом, который надо проверять.
 * Проверка «закоммиченное совпадает с печатью» тогда сверяла бы не печать, а
 * склейку — то есть проверяла бы на одно звено меньше, чем обещает.
 *
 * Вторая причина — диффы: рантайм, прогонщик и оболочка — дословные копии
 * `flang/src/emit/c/*.c` с приписанной сверху шапкой. Они меняются от правок
 * рантайма, независимо от исходников компилятора, и отдельными файлами дают
 * читаемый дифф на десятки строк. В склейке любая правка — один блоб.
 *
 * Третья — `make`: отдельные единицы трансляции собираются параллельно и
 * перекомпилируются по отдельности.
 */
import { existsSync, readFileSync, readdirSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

export const корень = resolve(dirname(fileURLToPath(import.meta.url)), "..")

/**
 * Рецепт печати живёт в `scripts/bootstrap-c.sh`, а читается отсюда.
 *
 * Единственной записью был ЭТОТ файл, и это было верно ровно до тех пор, пока
 * перепечатать точку раскрутки можно было только реализацией на JavaScript.
 * Теперь её печатает сам двоичный (`sh scripts/bootstrap-c.sh`), и запись
 * обязана лежать там, где переживёт удаление JavaScript: пределы попадают прямо
 * в напечатанный байт (`#define FL_MAX_STEPS`), и вторая копия числа, от
 * которого зависит совпадение байт в байт, — это расхождение, ждущее своего дня.
 *
 * Разбор нарочно тупой — `ИМЯ='значение'` у левого края: файл читают `sh` и этот
 * разбор, и оба обязаны понимать его одинаково.
 */
const РЕЦЕПТ = readFileSync(resolve(dirname(fileURLToPath(import.meta.url)), "bootstrap-c.sh"), "utf8")
const изРецепта = (имя) => {
  const найдено = РЕЦЕПТ.match(new RegExp(`^${имя}='([^']*)'`, "mu"))
  if (найдено === null) throw new Error(`scripts/bootstrap-c.sh: не найдено ${имя} — рецепт печати разошёлся`)
  return найдено[1]
}

/** Связанный компилятор: шесть слоёв на flang плюс `core/json` и `stdlib/strings`. */
export const ВХОД = изРецепта("FLANG_ENTRY")

/** Каталог точки раскрутки, относительно корня репозитория. */
export const КАТАЛОГ = изРецепта("FLANG_OUT")

/**
 * Пределы, с которыми печатается САМ КОМПИЛЯТОР.
 *
 * Умолчания бэкенда (10⁶ шагов, 10⁴ глубины) верны для обычной программы, но
 * компилятор разбирает 119 тысяч токенов и упирается в них на «Связать вызовы»:
 * релиз с умолчаниями отвечает FLANG_RECURSION_LIMIT на любой настоящий вход.
 * Ровно так уехал v0.4.1.
 *
 * `repl: true` — оболочка `flang repl` печатается вместе с прогонщиком: у любой
 * другой напечатанной программы нет точек входа, которые оболочка зовёт. У
 * двоичного это ключи `--cli` и `--repl`, и стоят они в том же рецепте.
 */
export const ПРЕДЕЛЫ = {
  cli: true,
  repl: true,
  maxSteps: Number(изРецепта("FLANG_MAX_STEPS")),
  maxDepth: Number(изРецепта("FLANG_MAX_DEPTH")),
}

/**
 * Что в `bootstrap/` НЕ относится к точке раскрутки.
 *
 * Проза (`README.md`) — не печать, а объяснение. Остальное — продукты сборки:
 * `make -C bootstrap` кладёт объектные файлы и бинарник рядом с исходниками,
 * потому что напечатанный Makefile не знает про отдельный каталог сборки. Всё
 * это в `.gitignore`; здесь список повторён затем, чтобы сторож работал и на
 * дереве без `.git` — на dev дерево уезжает без него, и проверка, опирающаяся на
 * `git ls-files`, там пропустилась бы молча.
 */
export const НЕ_ТОЧКА = new Set(изРецепта("FLANG_NOT_EMITTED").split(" ").filter(Boolean))
const ПРОДУКТ_СБОРКИ = /\.(?:o|obj|a|d)$/u

/** Имена файлов точки раскрутки, лежащих в дереве: без прозы и продуктов сборки. */
export function именаЗамороженного() {
  const каталог = join(корень, КАТАЛОГ)
  if (!existsSync(каталог)) return []
  return readdirSync(каталог)
    .filter((имя) => !НЕ_ТОЧКА.has(имя) && !ПРОДУКТ_СБОРКИ.test(имя))
    .sort()
}

/**
 * Расхождения между печатью и закоммиченным — байтами, а не строками.
 *
 * Сверяется и НАБОР файлов: файл, оставшийся в `bootstrap/` от прошлой печати,
 * — такая же ложь, как разошедшееся содержимое, и `cc *.c` соберёт его вместе с
 * остальным. Сравнение через `Buffer.compare`, потому что обещано побайтовое
 * совпадение, а не совпадение строк после раскодирования UTF-8.
 */
export function расхождения(напечатанные) {
  const беды = []
  const ожидается = напечатанные.map((файл) => файл.path).sort()
  const лежит = именаЗамороженного()
  for (const имя of лежит) {
    if (!ожидается.includes(имя)) беды.push(`${КАТАЛОГ}/${имя}: лежит в дереве, но печать его не даёт — след прошлой перепечатки`)
  }
  for (const файл of напечатанные) {
    const путь = join(корень, КАТАЛОГ, файл.path)
    const ждём = Buffer.from(файл.content, "utf8")
    if (!existsSync(путь)) {
      беды.push(`${КАТАЛОГ}/${файл.path}: печать даёт ${ждём.length} байт, а в дереве файла нет`)
      continue
    }
    const есть = readFileSync(путь)
    if (Buffer.compare(есть, ждём) === 0) continue
    беды.push(
      `${КАТАЛОГ}/${файл.path}: ${где(есть, ждём)} — в дереве ${есть.length} байт, печать даёт ${ждём.length}`,
    )
  }
  return беды
}

/** Первое расхождение — байтом и строкой: без места дифф на 4.5 МБ бесполезен. */
function где(есть, ждём) {
  const предел = Math.min(есть.length, ждём.length)
  let байт = предел
  for (let i = 0; i < предел; i += 1) {
    if (есть[i] !== ждём[i]) {
      байт = i
      break
    }
  }
  const строка = есть.subarray(0, байт).toString("utf8").split("\n").length
  return `разошлись на байте ${байт}, строка ${строка}`
}
