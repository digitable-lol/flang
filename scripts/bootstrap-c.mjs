#!/usr/bin/env node
/**
 * Замороженная точка раскрутки: компилятор flang, напечатанный в C и
 * закоммиченный в дерево.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Компилятор языка написан на самом языке (`flang/self/`), и до сих пор собрать
 * его можно было ровно одним способом: взять свидетеля на JavaScript, напечатать им
 * C, собрать. То есть Node лежал на пути СБОРКИ, а не только в наборе тестов, и
 * «язык, который работает везде» означало «везде, где есть Node».
 *
 * Замороженной точки в дереве не было ВОВСЕ. `flang/self/bootstrap/compiler.flang`
 * — не она: это шестой слой на flang (связывание и точки входа), исходник, для
 * сборки которого нужен компилятор. Напечатанный C уходил в `output/`, а он в
 * `.gitignore`. Ближайшее к точке — релизный архив `flang-0.4.8-c.tar.gz`, но он
 * вне git и печатается вручную.
 *
 * Каталог `bootstrap/` эту дыру закрывает: там лежит печать компилятора в C99,
 * байт в байт та, что делает свидетель, и собирается она `cc` и `make` без Node.
 *
 * ── Почему каталог, а не один склеенный файл ────────────────────────────────
 * Потому что каталог — это РОВНО ТО, что печатает бэкенд, без единого
 * преобразования между печатью и деревом. `emitC` выдаёт семь файлов, включая
 * Makefile; склейка потребовала бы своего кода (порядок заголовков, снятие
 * `#include`), и этот код сам стал бы предметом, который надо стеречь. Сторож
 * «закоммиченное совпадает с печатью» тогда сверял бы не печать, а склейку —
 * то есть проверял бы на одно звено меньше, чем обещает.
 *
 * Вторая причина — диффы. Из 5 823 370 байт точки 313 515 (5.4 %) приходятся на
 * рантайм, прогонщик и оболочку: это дословные копии `flang/src/emit/c/*.c` с
 * приписанной сверху шапкой в 10—18 строк. Они меняются от правок рантайма,
 * независимо от исходников компилятора, и в виде отдельных файлов дают читаемый
 * дифф на десятки строк. В склейке любая правка — один блоб на 5.8 МБ.
 *
 * Третья — `make`: отдельные единицы трансляции собираются параллельно и
 * перекомпилируются по отдельности.
 *
 * ── Порядок обновления ──────────────────────────────────────────────────────
 * Точка раскрутки — АРТЕФАКТ, а не исходник. Править её руками нельзя: правка
 * потеряется при первой перепечатке, а сторож её и не пропустит. Обновляется она
 * одной командой в том же коммите, что и правка компилятора:
 *
 *   node scripts/bootstrap-c.mjs           перепечатать bootstrap/ из исходников
 *   node scripts/bootstrap-c.mjs --check   сверить закоммиченное с печатью
 *
 * Сторож, который краснеет при расхождении, — в `flang/test/self-bootstrap.test.mjs`
 * («точка раскрутки совпадает с печатью текущих исходников»). Компилятор C ему не
 * нужен: он сверяет байты, а не сборку, и поэтому идёт всегда.
 *
 * ── Единственное место, где записаны пределы печати ─────────────────────────
 * `ПРЕДЕЛЫ` ниже — те, с которыми свидетель запускает компилятор на самом себе.
 * Они попадают в `#define FL_MAX_STEPS`, то есть в напечатанный байт, и раньше
 * стояли тремя копиями: здесь, в `scripts/build-release-c.mjs` и в
 * `flang/test/self-bootstrap.test.mjs`, с комментарием «обе стороны обязаны
 * просить одинаково». Три копии числа, от которого зависит побайтовое
 * совпадение, — это расхождение, ждущее своего дня. Теперь копия одна, и
 * остальные её импортируют.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

export const корень = resolve(dirname(fileURLToPath(import.meta.url)), "..")

/** Связанный компилятор: шесть слоёв на flang плюс `core/json` и `stdlib/strings`. */
export const ВХОД = "flang/self/bootstrap/compiler.flang"

/** Каталог точки раскрутки, относительно корня репозитория. */
export const КАТАЛОГ = "bootstrap"

/**
 * Пределы, с которыми печатается САМ КОМПИЛЯТОР.
 *
 * Умолчания бэкенда (10⁶ шагов, 10⁴ глубины) верны для обычной программы, но
 * компилятор разбирает 119 тысяч токенов и упирается в них на «Связать вызовы»:
 * релиз с умолчаниями отвечает FLANG_RECURSION_LIMIT на любой настоящий вход.
 * Ровно так уехал v0.4.1.
 *
 * `repl: true` — оболочка `flang repl` печатается вместе с прогонщиком: у любой
 * другой напечатанной программы нет точек входа, которые оболочка зовёт.
 */
export const ПРЕДЕЛЫ = { cli: true, repl: true, maxSteps: 40_000_000, maxDepth: 20_000 }

/**
 * Что в `bootstrap/` НЕ относится к точке раскрутки.
 *
 * Проза (`README.md`) — не печать, а объяснение. Остальное — продукты сборки:
 * `make -C bootstrap` кладёт объектные файлы и бинарник рядом с исходниками,
 * потому что напечатанный Makefile не знает про отдельный каталог сборки. Всё
 * это в `.gitignore`; здесь список повторён затем, чтобы сторож работал и на
 * дереве без `.git` — на dev дерево уезжает без него, и проверка, опирающаяся на
 * `git ls-files`, там пропустилась бы молча.
 */
export const НЕ_ТОЧКА = new Set(["README.md", "flang", "flang.exe", "flang_cli", "flang_cli.exe", "libkompilyator_flang.a"])
const ПРОДУКТ_СБОРКИ = /\.(?:o|obj|a|d)$/u

/**
 * Печать компилятора в C из текущих исходников: `[{ path, content }]`, семь файлов.
 *
 * Печатается компилятор ЦЕЛИКОМ, без отбрасывания недостижимого, которое делает
 * `flang emit` (`flang/src/reachable.mjs`), — и это решение, а не пропуск.
 * Точки входа у этой программы не кончаются её собственными функциями: она
 * печатается с `repl: true`, а оболочка `flang_repl.c` зовёт по имени «Токены»
 * и «Диагностики», до которых от функций `compiler.flang` не дойти. Отбрось их
 * — и `.токены` в собранной оболочке ответит «не найдена функция». Мерено:
 * недостижимых от своих функций здесь 11 из 1662, то есть 489 строк и 24 353
 * байта из 5 710 203, — 0.4 %, и платить за них поломанной оболочкой незачем.
 */
export async function напечатать() {
  const { loadProgram } = await import(join(корень, "flang/bin/flang.mjs"))
  const { emitC } = await import(join(корень, "flang/src/emit/c.mjs"))
  const программа = await loadProgram(join(корень, ВХОД))
  return { программа, файлы: emitC(программа, ПРЕДЕЛЫ).files }
}

/** Имена файлов точки раскрутки, лежащих в дереве: без прозы и продуктов сборки. */
export function именаЗамороженного() {
  const каталог = join(корень, КАТАЛОГ)
  if (!existsSync(каталог)) return []
  return readdirSync(каталог)
    .filter((имя) => !НЕ_ТОЧКА.has(имя) && !ПРОДУКТ_СБОРКИ.test(имя))
    .sort()
}

/**
 * Расхождения между печатью и закоммиченным — байтами, а не строками.
 *
 * Сверяется и НАБОР файлов: файл, оставшийся в `bootstrap/` от прошлой печати,
 * — такая же ложь, как разошедшееся содержимое, и `cc *.c` соберёт его вместе с
 * остальным. Сравнение через `Buffer.compare`, потому что обещано побайтовое
 * совпадение, а не совпадение строк после раскодирования UTF-8.
 */
export function расхождения(напечатанные) {
  const беды = []
  const ожидается = напечатанные.map((файл) => файл.path).sort()
  const лежит = именаЗамороженного()
  for (const имя of лежит) {
    if (!ожидается.includes(имя)) беды.push(`${КАТАЛОГ}/${имя}: лежит в дереве, но печать его не даёт — след прошлой перепечатки`)
  }
  for (const файл of напечатанные) {
    const путь = join(корень, КАТАЛОГ, файл.path)
    const ждём = Buffer.from(файл.content, "utf8")
    if (!existsSync(путь)) {
      беды.push(`${КАТАЛОГ}/${файл.path}: печать даёт ${ждём.length} байт, а в дереве файла нет`)
      continue
    }
    const есть = readFileSync(путь)
    if (Buffer.compare(есть, ждём) === 0) continue
    беды.push(
      `${КАТАЛОГ}/${файл.path}: ${где(есть, ждём)} — в дереве ${есть.length} байт, печать даёт ${ждём.length}`,
    )
  }
  return беды
}

/** Первое расхождение — байтом и строкой: без места дифф на 4.5 МБ бесполезен. */
function где(есть, ждём) {
  const предел = Math.min(есть.length, ждём.length)
  let байт = предел
  for (let i = 0; i < предел; i += 1) {
    if (есть[i] !== ждём[i]) {
      байт = i
      break
    }
  }
  const строка = есть.subarray(0, байт).toString("utf8").split("\n").length
  return `разошлись на байте ${байт}, строка ${строка}`
}

/** Записывает печать в `bootstrap/`, отдаёт число записанных байт. */
export function записать(напечатанные) {
  const каталог = join(корень, КАТАЛОГ)
  mkdirSync(каталог, { recursive: true })
  let всего = 0
  for (const файл of напечатанные) {
    const путь = join(каталог, файл.path)
    mkdirSync(dirname(путь), { recursive: true })
    writeFileSync(путь, файл.content, "utf8")
    всего += Buffer.byteLength(файл.content, "utf8")
  }
  return всего
}

/* ── как скрипт ───────────────────────────────────────────────────────────── */

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const сверить = process.argv.includes("--check")
  const { программа, файлы } = await напечатать()
  console.log(`компилятор: ${ВХОД}`)
  console.log(`связано функций: ${программа.functions.length}, типов: ${программа.types.length}`)

  if (сверить) {
    const беды = расхождения(файлы)
    const всего = файлы.reduce((сумма, файл) => сумма + Buffer.byteLength(файл.content, "utf8"), 0)
    if (беды.length === 0) {
      console.log(`точка раскрутки ${КАТАЛОГ}/ совпадает с печатью: ${файлы.length} файлов, ${всего} байт`)
      process.exit(0)
    }
    console.error(`точка раскрутки ${КАТАЛОГ}/ разошлась с исходниками — расхождений ${беды.length}:`)
    for (const беда of беды) console.error(`  • ${беда}`)
    console.error(`\nПерепечатайте её в том же коммите, что и правку компилятора: node scripts/bootstrap-c.mjs`)
    process.exit(1)
  }

  const всего = записать(файлы)
  for (const файл of файлы) {
    console.log(`  ${файл.path}  ${Buffer.byteLength(файл.content, "utf8")} байт`)
  }
  console.log(`итого ${файлы.length} файлов, ${всего} байт (${(всего / 1024 / 1024).toFixed(2)} МБ) в ${КАТАЛОГ}/`)
  console.log(`сборка без Node: make -C ${КАТАЛОГ}`)
}
