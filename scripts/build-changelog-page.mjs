/**
 * Видно ли коммит читателю сайта — тем же правилом, что у `CHANGELOG.md`.
 *
 * Правило НЕ переписано здесь, а взято из `scripts/build-changelog.mjs`. Два
 * списка «что считается изменением языка» разошлись бы при первой же правке, и
 * тогда журнал и эта страница начали бы спорить друг с другом об одном и том же
 * коммите. Заодно это лечит настоящую беду: заголовок служебного коммита —
 * готовое утверждение о ТОГДАШНЕМ дереве («2 идут сеткой»), и сторож чисел
 * читает его как утверждение о СЕГОДНЯШНЕМ. Правило видимости убирает такие
 * заголовки со страницы по той же причине, по которой убирает их из журнала.
 */
function виденЛи(коммит) {
  return решение({ files: коммит.файлы, body: коммит.тело, subject: коммит.заголовок })
}

/** Корень пути по тому же правилу, по которому его берёт `видимостьПути`. */
function корниНеизвестных(пути) {
  const счёт = new Map()
  for (const путь of пути) {
    const части = путь.split("/")
    const корень = части[0] === "flang" && части.length > 1 ? `flang/${части[1]}` : части[0]
    счёт.set(корень, (счёт.get(корень) ?? 0) + 1)
  }
  return [...счёт]
    .sort((а, б) => б[1] - а[1] || а[0].localeCompare(б[0]))
    .map(([корень, путей]) => ({ корень, путей }))
}

/**
 * Снимок страницы: ствол, вливания, числа и их сдвиги.
 *
 * Вливание — шаг ствола, у которого больше одного родителя. Прямой коммит в
 * ствол вливанием не считается, но и не теряется: он попадает в список
 * `прямые` того же дня, иначе страница молчала бы о работе, приехавшей мимо
 * ветки.
 */
export function собратьСводку(ревизия = "HEAD") {
  const история = читатьИсторию(ревизия)
  const слияния = история.ствол.filter((к) => к.родители.length > 1)
  const мерить = [история.голова, ...слияния.map((к) => к.полная)]
  const числа = измеритьРевизии([...new Set(мерить)])

  const неклассифицированные = new Set()
  const отобрать = (коммиты) => {
    const записи = []
    let скрыто = 0
    for (const п of коммиты) {
      const р = виденЛи(п)
      for (const путь of р.неизвестные) неклассифицированные.add(путь)
      if (р.показывать) записи.push({ текст: р.текст, коммит: п.коротко })
      else скрыто += 1
    }
    return { записи, скрыто }
  }

  // Сдвиг считается против ПРЕДЫДУЩЕГО слияния — того, что ниже по стволу.
  const вливания = слияния.map((к, i) => {
    const было = i + 1 < слияния.length ? числа.get(слияния[i + 1].полная) : null
    const стало = числа.get(к.полная)
    const сдвиг = {}
    if (было) {
      for (const и of ИЗМЕРИТЕЛИ) {
        if (стало[и.ключ] !== было[и.ключ]) сдвиг[и.ключ] = { было: было[и.ключ], стало: стало[и.ключ] }
      }
    }
    const { записи, скрыто } = отобрать(к.приехали.filter((п) => п.полная !== к.полная))
    return {
      коммит: к.коротко,
      дата: к.дата,
      заголовок: к.заголовок,
      ветка: ветка(к.заголовок),
      приехало: к.приехали.length,
      записи,
      скрыто,
      числа: стало,
      сдвиг,
    }
  })

  const прямыеШаги = история.ствол.filter((к) => к.родители.length <= 1)
  const прямыеПоДням = new Map()
  for (const к of прямыеШаги) {
    if (!прямыеПоДням.has(к.дата)) прямыеПоДням.set(к.дата, [])
    прямыеПоДням.get(к.дата).push(к)
  }
  const прямые = [...прямыеПоДням].map(([дата, коммиты]) => ({ дата, ...отобрать(коммиты) }))

  // Дни в порядке ствола: сначала новые. Порядок берётся из истории, а не из
  // сортировки строк, — иначе день с переставленной датой уехал бы не туда.
  const дни = []
  const виденДень = new Set()
  for (const к of история.ствол) {
    if (виденДень.has(к.дата)) continue
    виденДень.add(к.дата)
    дни.push(к.дата)
  }

  const головаК = история.ствол[0]
  return {
    version: ВЕРСИЯ,
    голова: история.голова,
    головаКоротко: головаК.коротко,
    головаДата: головаК.дата,
    шаговСтвола: история.ствол.length,
    всегоКоммитов: история.всегоКоммитов,
    измерители: ИЗМЕРИТЕЛИ.map((и) => ({ ключ: и.ключ, имя: и.имя, считает: и.считает })),
    сейчас: числа.get(история.голова),
    /*
     * Корни, которых правило видимости не знает. Полный список путей сюда не
     * кладётся: их сотни, и все из каталогов увезённого 16 августа проекта
     * (`tools/`, `web/`, `src/`, `test/`). Коммит, у которого ВСЕ пути таковы,
     * `решение` прячет — и это верно для увезённого, но молча. Поэтому корни
     * названы: появится новый — снимок изменится, и сторож это покажет.
     */
    неизвестныеКорни: корниНеизвестных(неклассифицированные),
    дни,
    вливания,
    прямые,
  }
}

