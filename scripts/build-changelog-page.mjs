/** Нужно ли для измерителя содержимое файла, а не только его имя. */
const поСодержимому = (и) => и.поле !== null

/**
 * Считает числа по готовому дереву путей.
 *
 * `дерево` — массив `{ путь, шапка }`; `сводки` — карта шапки в её четыре
 * числа. Разделена с чтением нарочно: один и тот же файл лежит под одной
 * шапкой в десятках ревизий, и читать его заново на каждую значило бы гонять
 * сотни мегабайт вместо единиц.
 */
export function посчитать(дерево, сводки) {
  const итог = {}
  for (const и of ИЗМЕРИТЕЛИ) итог[и.ключ] = 0
  for (const { путь, шапка } of дерево) {
    for (const и of ИЗМЕРИТЕЛИ) {
      if (!и.образец.test(путь)) continue
      if (и.поле === null) {
        итог[и.ключ] += 1
        continue
      }
      const сводка = сводки.get(шапка)
      if (сводка === undefined) throw new Error(`объект не прочитан: ${шапка} (${путь})`)
      итог[и.ключ] += сводка[и.поле]
    }
  }
  return итог
}

/** Дерево ревизии: путь и шапка объекта у каждого файла. */
function дереворевизии(ревизия) {
  const сырое = гит(["ls-tree", "-r", "-z", "--format=%(objectname) %(path)", ревизия])
  const дерево = []
  for (const строка of сырое.split("\0")) {
    if (!строка) continue
    const пробел = строка.indexOf(" ")
    if (пробел < 0) continue
    дерево.push({ шапка: строка.slice(0, пробел), путь: строка.slice(пробел + 1) })
  }
  return дерево
}

/**
 * Меряет дерево у каждой из ревизий. Тела читаются ОДНОЙ пачкой на всё.
 *
 * Так вся история ста с лишним слияний обходится семью сотнями объектов: файл,
 * который не менялся, лежит в дереве под той же шапкой, и считать его заново на
 * каждую ревизию незачем.
 */
export function измеритьРевизии(ревизии) {
  const деревья = ревизии.map((р) => дереворевизии(р))
  const нужные = new Set()
  for (const дерево of деревья) {
    for (const { путь, шапка } of дерево) {
      if (ИЗМЕРИТЕЛИ.some((и) => поСодержимому(и) && и.образец.test(путь))) нужные.add(шапка)
    }
  }
  const сводки = читатьСводки([...нужные])
  const из = new Map()
  for (let i = 0; i < ревизии.length; i++) из.set(ревизии[i], посчитать(деревья[i], сводки))
  return из
}

