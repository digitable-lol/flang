/**
 * Печать страницы сайта «Журнал вливаний».
 *
 * ── Зачем отдельно от CHANGELOG.md ──────────────────────────────────────────
 *
 * `CHANGELOG.md` печатается по РЕЛИЗАМ. Тег в этом репозитории один на неделю
 * работы, а между тегами накапливаются сотни коммитов — и весь этот кусок
 * журнал показывает одной кучей «Не выпущено». Открыв такую страницу после
 * недели вливаний, движение увидеть нельзя: видно, что что-то было, и не видно
 * что именно.
 *
 * Здесь единица другая — ВЛИВАНИЕ: слияние ветки в ствол. Ветка в этом дереве
 * несёт связный кусок работы и вливается целиком, а заголовок слияния пишется
 * утверждением о том, что теперь правда. То есть единица уже размечена в
 * истории, и размечать её заново не нужно — надо прочитать.
 *
 * ── Почему рядом с записью стоят числа ──────────────────────────────────────
 *
 * Список заголовков отвечает на вопрос «над чем работали», а спрашивают другое:
 * «что изменилось». Разница видна на числе: «эталон на flang вырос с 54 210 до
 * 56 474» говорит про движение то, чего десять заголовков не скажут. Поэтому у
 * каждого вливания меряется дерево НА ЭТОМ КОММИТЕ, и печатается только то, что
 * сдвинулось: число, которое стоит на месте, — не новость.
 *
 * Меряется дерево у КАЖДОГО слияния, а не у последнего: иначе сдвиг не с чем
 * сравнивать. Измерители перечислены в ИЗМЕРИТЕЛИ ниже, и каждый назван так,
 * как считает, — «объявлений `тотальная функция`», а не «доказано тотальных».
 * Второе было бы враньём прибора: объявление и доказательство считаются разными
 * измерителями (`flang/scripts/proof-ledger.mjs`), и подменять одно другим тут
 * значило бы завести число, которое нечем проверить.
 *
 * ── Как это стережётся ──────────────────────────────────────────────────────
 *
 * Файлы `docs/site/changelog.md` и `docs/site/changelog.json` печатаются
 * отсюда и правятся ТОЛЬКО перепечаткой. Стережёт их
 * `flang/test/changelog-page.test.mjs`: он перепечатывает страницу заново из git и
 * краснеет при первом расхождении — тем же приёмом, что
 * `flang/test/changelog.test.mjs` стережёт `CHANGELOG.md`.
 *
 * Сверх того он краснеет на СТАРЕНИИ: если в ствол приехало слияние, о котором
 * страница не знает, — красный. Это ровно та беда, ради которой страница
 * заведена: страница про движение, которая молчит про движение, хуже, чем её
 * отсутствие.
 *
 * Запуск:
 *   node scripts/build-changelog-page.mjs           напечатать
 *   node scripts/build-changelog-page.mjs --check   сверить напечатанное с записанным
 */
