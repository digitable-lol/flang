const МЕСЯЦЫ = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
]

/** «2026-08-17» → «17 августа 2026». Без обращения к текущему времени. */
export function поЧеловечески(дата) {
  const м = /^(\d{4})-(\d{2})-(\d{2})$/u.exec(дата)
  if (!м) return дата
  return `${Number(м[3])} ${МЕСЯЦЫ[Number(м[2]) - 1]} ${м[1]}`
}

/** Имя ветки из заголовка слияния — в трёх видах, которые встречаются в дереве. */
export function ветка(заголовок) {
  const наш = /^Слияние\s+(\S+?):/u.exec(заголовок)
  if (наш) return наш[1]
  const чужой = /^Merge remote-tracking branch '(?:origin\/)?([^']+)'/u.exec(заголовок)
  if (чужой) return чужой[1]
  const простой = /^Merge branch '([^']+)'/u.exec(заголовок)
  if (простой) return простой[1]
  return null
}

/**
 * Разбор истории от `ревизия` вниз: ствол и раскладка всех коммитов по нему.
 *
 * Цепь первого родителя РАЗБИВАЕТ историю без остатка: каждый достижимый
 * коммит принадлежит ровно одному шагу ствола — тому, которым он в ствол
 * приехал. Это не соглашение, а свойство обхода, и на нём стоит проверка
 * полноты в стороже: сумма приехавших по всем шагам обязана совпасть с числом
 * коммитов в истории. Разойдётся — значит раскладка потеряла работу, и это
 * видно числом, а не на глаз.
 *
 * Обход идёт от СТАРОГО к новому: когда доходим до шага, всё, что приехало
 * раньше, уже разложено, и обход сам останавливается на разложенном.
 */
export function читатьИсторию(ревизия = "HEAD") {
  const сырое = гит([
    "log",
    "--topo-order",
    "--name-only",
    `--format=${ЗАПИСЬ}%H${РАЗДЕЛИТЕЛЬ}%h${РАЗДЕЛИТЕЛЬ}%P${РАЗДЕЛИТЕЛЬ}%ad${РАЗДЕЛИТЕЛЬ}%s${РАЗДЕЛИТЕЛЬ}%b${РАЗДЕЛИТЕЛЬ}`,
    "--date=short",
    ревизия,
  ])
  const коммиты = new Map()
  const порядок = []
  for (const кусок of сырое.split(ЗАПИСЬ)) {
    if (!кусок.trim()) continue
    const поля = кусок.split(РАЗДЕЛИТЕЛЬ)
    const [полная, коротко, родители, дата, заголовок = "", тело = "", файлы = ""] = поля
    коммиты.set(полная, {
      полная,
      коротко,
      родители: родители ? родители.split(" ").filter(Boolean) : [],
      дата,
      заголовок,
      тело,
      файлы: файлы.split("\n").map((с) => с.trim()).filter(Boolean),
      место: порядок.length,
    })
    порядок.push(полная)
  }

  const голова = гит(["rev-parse", ревизия]).trim()
  const ствол = []
  for (let текущий = голова; текущий; ) {
    const к = коммиты.get(текущий)
    if (!к) break
    ствол.push(к)
    текущий = к.родители[0] ?? null
  }

  // Раскладка: от старого к новому, обход останавливается на уже разложенном.
  const хозяин = new Map()
  for (let i = ствол.length - 1; i >= 0; i--) {
    const шаг = ствол[i]
    const стопка = [шаг.полная]
    const приехали = []
    while (стопка.length) {
      const имя = стопка.pop()
      if (хозяин.has(имя)) continue
      const к = коммиты.get(имя)
      if (!к) continue
      хозяин.set(имя, шаг.полная)
      приехали.push(к)
      for (const р of к.родители) стопка.push(р)
    }
    приехали.sort((а, б) => а.место - б.место)
    шаг.приехали = приехали
  }

  return { голова, ствол, коммиты, всегоКоммитов: порядок.length }
}

