/**
 * Вся ли история под рукой, чтобы сверять.
 *
 * Шагов ствола видно меньше, чем записано, — это клон без истории. Тот же
 * вопрос и теми же словами задаёт `flang/test/changelog-page.test.mjs`; ответ обязан
 * совпадать, иначе сверка и сторож разошлись бы в том, что считать бедой.
 */
export function историяПолна(снимок) {
  try {
    const видно = Number(гит(["rev-list", "--first-parent", "--count", "HEAD"]).trim())
    if (!Number.isFinite(видно) || видно < снимок.шаговСтвола) {
      return { полна: false, причина: `шагов ствола видно ${видно}, а в снимке ${снимок.шаговСтвола}` }
    }
    гит(["cat-file", "-e", `${снимок.голова}^{commit}`])
    return { полна: true, причина: null }
  } catch (беда) {
    return { полна: false, причина: `git не отвечает: ${беда.message}` }
  }
}

function напечатать() {
  const сводка = собратьСводку("HEAD")
  writeFileSync(ПУТЬ_MD, печатьMarkdown(сводка))
  writeFileSync(ПУТЬ_JSON, сериализовать(сводка))
  console.log(
    `Напечатано: вливаний ${сводка.вливания.length}, дней ${сводка.дни.length}, ` +
      `коммитов в истории ${сводка.всегоКоммитов}.`,
  )
  return 0
}

/**
 * Сверка — те же три вопроса, что задаёт `flang/test/changelog-page.test.mjs`, и
 * ровно в том же порядке.
 *
 * Печатать заново от HEAD и требовать совпадения было бы СТРОЖЕ теста — и
 * строже неправильно. Снимок записывается коммитом, и этот коммит в снимок уже
 * не попадает: страница, напечатанная и тут же закоммиченная, «отстаёт» на свой
 * собственный коммит. Требовать от неё догнать HEAD значит требовать
 * невозможного, а проверка, которую нельзя удовлетворить, перестаёт что-либо
 * значить. Поэтому сверяется то же, что в тесте: правда записанного, отсутствие
 * пропущенных вливаний и совпадение markdown со снимком.
 */
function сверить() {
  const беды = []
  let записанныйJson = null
  let записанныйMd = null
  try {
    записанныйJson = readFileSync(ПУТЬ_JSON, "utf8")
    записанныйMd = readFileSync(ПУТЬ_MD, "utf8")
  } catch (беда) {
    console.error(`Страница «Что изменилось» не читается: ${беда.message}`)
    console.error("\nЛечится одной командой: node scripts/build-changelog-page.mjs")
    return 1
  }
  const снимок = JSON.parse(записанныйJson)

  /* Неполный клон — не отставшая страница, а отсутствие того, с чем сверять.
     Ругаться на файл за то, что до него не доехала история, значило бы красить
     сверку в красный за чужую беду; та же оговорка стоит в стороже и в
     `changelog.test.mjs`. Сверка markdown со снимком git не требует и делается
     всё равно. */
  const полна = историяПолна(снимок)
  if (!полна.полна) {
    if (записанныйMd !== печатьMarkdown(снимок)) {
      console.error("changelog.md не совпадает с печатью из changelog.json — страницу правили руками")
      console.error("\nЛечится одной командой: node scripts/build-changelog-page.mjs")
      return 1
    }
    console.log(`Полная сверка пропущена: ${полна.причина}.`)
    console.log("Markdown со снимком сошёлся; в CI полная сверка чинится fetch-depth: 0 у actions/checkout.")
    return 0
  }

  const свежая = собратьСводку(снимок.голова)
  if (записанныйJson !== сериализовать(свежая)) беды.push("changelog.json разошёлся с историей")
  if (записанныйMd !== печатьMarkdown(свежая)) беды.push("changelog.md разошёлся с историей")

  const пропущенные = гит([
    "log",
    "--first-parent",
    "--merges",
    "--format=%h %s",
    `${снимок.голова}..HEAD`,
  ]).trim()
  if (пропущенные) {
    беды.push("в ствол приехали вливания, о которых страница молчит:")
    for (const с of пропущенные.split("\n")) беды.push(`    ${с}`)
  }

  if (беды.length) {
    console.error("Страница «Что изменилось» разошлась с историей:")
    for (const б of беды) console.error("  ✗ " + б)
    console.error("\nЛечится одной командой: node scripts/build-changelog-page.mjs")
    return 1
  }
  console.log(
    `Сверка прошла: вливаний ${снимок.вливания.length}, пропущенных 0, расхождений 0.`,
  )
  return 0
}

