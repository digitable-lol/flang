/* ── git ─────────────────────────────────────────────────────────────────── */

/* Тело коммита содержит переводы строки, а `--name-only` дописывает пути после
   формата. Значит разделять записи переводом строки нельзя, и разделители взяты
   служебные: в сообщениях коммитов таких байтов не бывает. Записаны они
   escape-последовательностью, а не самим байтом: невидимый символ в исходнике
   переживает любую правку и не читается глазом. */
const РАЗДЕЛИТЕЛЬ = "\u001f"
const ЗАПИСЬ = "\u001e"

/*
 * `core.quotepath=false` — не украшение. С настройкой по умолчанию git отдаёт
 * путь с кириллицей в кавычках и восьмеричных escape-ах:
 * `"benchmarks/…/\320\260/…"`. Такой путь начинается с кавычки, и правило
 * видимости по первому сегменту разбирает его как корень `"benchmarks` —
 * неизвестный. Ровно так 794 пути из `benchmarks/` объявились
 * неклассифицированными на первом же прогоне.
 */
function гит(доводы) {
  return execFileSync("git", ["-c", "core.quotepath=false", ...доводы], {
    cwd: КОРЕНЬ,
    encoding: "utf8",
    maxBuffer: 1 << 30,
    stdio: ["ignore", "pipe", "pipe"],
  })
}

/**
 * Сколько объектов читается одним заходом `git cat-file --batch`.
 *
 * Ограничение здесь не от беды, а на вырост, и вклад его ИЗМЕРЕН, а не
 * предположен. Пик памяти прогона проверки: 191 МБ, когда все 778 объектов
 * истории читались одним заходом, и 181 МБ при заходе на 64 — то есть заход
 * стоит десять мегабайт из ста восьмидесяти, а остальное держит сам разбор.
 * Врать про «починили память» на таком числе нельзя.
 *
 * Взято оно всё равно: размер одного захода ограничен числом объектов, а не
 * размером дерева, — значит выросшее дерево не превратит чтение в гигабайтный
 * буфер. Тела при этом наружу не отдаются вовсе: из каждого объекта сразу
 * считаются четыре числа, и дальше живут они, а не текст.
 */
const ЗАХОД = 64

/*
 * Начала объявлений. Считается СТРОКА, начинающаяся со слова, — поэтому образцы
 * взаимно исключающие уже сейчас: «тотальная функция «Х»» под `ФУНКЦИЯ` не
 * подходит, там слово стоит не первым. Порядок и `else` — оговорка на случай,
 * если образцы когда-нибудь ослабят, а не лечение сегодняшнего двойного счёта:
 * сегодня его нет.
 */
const ТОТАЛЬНАЯ = /^[\t ]*тотальная функция[\t ]/u
const ФУНКЦИЯ = /^[\t ]*функция[\t ]/u
const ТЕОРЕМА = /^[\t ]*теорема[\t ]/u

/** Четыре числа одного файла. Считаются один раз на объект, а не на ревизию. */
function сводкаБлоба(текст) {
  const строки = текст.split("\n")
  // Последний перевод строки не открывает новой строки: так же считает `wc -l`.
  if (строки.length > 0 && строки[строки.length - 1] === "") строки.pop()
  let тотальных = 0
  let обычных = 0
  let теорем = 0
  for (const с of строки) {
    if (ТОТАЛЬНАЯ.test(с)) тотальных += 1
    else if (ФУНКЦИЯ.test(с)) обычных += 1
    else if (ТЕОРЕМА.test(с)) теорем += 1
  }
  return { строк: строки.length, тотальных, обычных, теорем }
}

/** Читает объекты заходами и отдаёт по каждому только его числа. */
function читатьСводки(шапки) {
  const собрано = new Map()
  for (let с = 0; с < шапки.length; с += ЗАХОД) {
    const кусок = шапки.slice(с, с + ЗАХОД)
    const ответ = spawnSync("git", ["cat-file", "--batch"], {
      cwd: КОРЕНЬ,
      input: кусок.join("\n") + "\n",
      maxBuffer: 1 << 28,
    })
    if (ответ.status !== 0) throw new Error(`git cat-file --batch отказал: ${ответ.stderr}`)
    const поток = ответ.stdout
    let место = 0
    while (место < поток.length) {
      const конецШапки = поток.indexOf(0x0a, место)
      if (конецШапки < 0) break
      const шапка = поток.toString("utf8", место, конецШапки).split(" ")
      const размер = Number(шапка[2])
      const начало = конецШапки + 1
      собрано.set(шапка[0], сводкаБлоба(поток.toString("utf8", начало, начало + размер)))
      место = начало + размер + 1
    }
  }
  return собрано
}

