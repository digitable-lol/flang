export function печатьMarkdown(журнал) {
  const части = [...ШАПКА, ""]

  if (журнал.unreleased.entries.length > 0) {
    части.push("## Не выпущено", "")
    части.push(...строкиЗаписей(журнал.unreleased))
    части.push("")
  }

  for (const релиз of журнал.releases) {
    части.push(`## ${релиз.version} — ${релиз.human}`, "")
    if (релиз.title) части.push(`**${релиз.title}**`, "")
    for (const абзац of релиз.note) части.push(абзац, "")
    части.push(...строкиЗаписей(релиз))
    части.push("")
  }

  return `${части.join("\n").replace(/\n{3,}/gu, "\n\n").trimEnd()}\n`
}

function строкиЗаписей(раздел) {
  const строки = раздел.entries.map((запись) => `- ${запись.text} (\`${запись.commit}\`)`)
  if (раздел.entries.length === 0) строки.push("_Ни одной правки, меняющей язык снаружи._")
  if (раздел.hidden > 0) {
    строки.push("", `Ещё ${раздел.hidden} ${словоПравок(раздел.hidden)} языка снаружи не меняют.`)
  }
  return строки
}

/* Записи, которых в записанном журнале нет вовсе — по хешу коммита. Без этого
   списка проверка говорит «перепечатайте», не говоря, что именно уехало мимо. */
function чегоНеХватает(свежий, прежний) {
  const было = new Set(
    [...(прежний?.releases ?? []), прежний?.unreleased ?? { entries: [] }].flatMap((раздел) =>
      раздел.entries.map((запись) => запись.commit),
    ),
  )
  return [свежий.unreleased, ...свежий.releases]
    .flatMap((раздел) => раздел.entries)
    .filter((запись) => !было.has(запись.commit))
}

/* Русский счёт: 1 правка, 2 правки, 5 правок. Без этого журнал пишет «5 правки».
   Вывезено наружу: тем же счётом считает страницу вливаний
   `scripts/build-changelog-page.mjs`, а второй счёт разошёлся бы с этим. */
export function словоПравок(сколько) {
  const сотня = сколько % 100
  const десяток = сколько % 10
  if (сотня >= 11 && сотня <= 14) return "правок"
  if (десяток === 1) return "правка"
  if (десяток >= 2 && десяток <= 4) return "правки"
  return "правок"
}

