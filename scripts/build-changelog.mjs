export function поЧеловечески(iso) {
  const [год, месяц, день] = iso.slice(0, 10).split("-")
  return `${Number(день)} ${МЕСЯЦЫ[Number(месяц) - 1]} ${год}`
}

/**
 * Снимок журнала из разобранных тегов и коммитов. Функция чистая: git читается
 * отдельно, поэтому правила проверяются на выдуманной истории (--self-test), а
 * не «на том, что сегодня в main».
 */
export function собратьЖурнал({ теги, невыпущенные = [], версияПакета = null }) {
  const неклассифицированные = new Set()

  const разобрать = (коммиты) => {
    const записи = []
    let скрыто = 0
    for (const коммит of коммиты) {
      const вердикт = решение(коммит)
      for (const путь of вердикт.неизвестные) {
        неклассифицированные.add(путь.split("/").slice(0, путь.startsWith("flang/") ? 2 : 1).join("/"))
      }
      if (!вердикт.показывать) {
        скрыто += 1
        continue
      }
      записи.push({ text: вердикт.текст, commit: коммит.sha.slice(0, 7) })
    }
    return { записи, скрыто }
  }

  const релизы = []
  for (const тег of теги) {
    const { записи, скрыто } = разобрать(тег.commits)
    релизы.push({
      version: тег.version,
      tag: тег.tag,
      date: тег.date.slice(0, 10),
      human: поЧеловечески(тег.date),
      commit: тег.commit.slice(0, 7),
      title: тег.title,
      note: тег.note,
      entries: записи,
      hidden: скрыто,
    })
  }
  релизы.sort((левый, правый) => сравнитьВерсии(правый.version, левый.version))

  const свежие = разобрать(невыпущенные)

  return {
    version: 1,
    /* Имя пакета — то, под которым он лежит в реестре СЕГОДНЯ, а не то, под
       которым выходили релизы 0.4.x. Переименован 19 августа 2026 вместе с
       package.json: язык называется flang, а FTS — другой проект, вынесенный
       из репозитория. Номера версий у записей журнала свои и не меняются. */
    package: "@digitable-lol/flang",
    repository: "https://github.com/digitable-lol/flang",
    /*
     * Версия из package.json — не украшение, а вторая половина проверки. Тегов
     * в CI может не быть (`actions/checkout` без fetch-depth клонирует одну
     * ревизию), и тогда сверить журнал с историей нечем. Сверить его с
     * объявленной версией можно всегда: релиз, о котором журнал не знает, —
     * это и есть «журнал отстал».
     */
    declared: версияПакета,
    latest: релизы[0]?.version ?? null,
    unclassified: [...неклассифицированные].sort(),
    releases: релизы,
    /*
     * У «Не выпущено» счётчика скрытых нет, и это не забывчивость. Скрытая
     * правка меняла бы журнал, не добавляя в него ни строки, — а перепечатанный
     * журнал кладут коммитом, который сам скрыт, и он увеличивал бы счётчик
     * снова. Наступили на первом же обороте: после коммита с самим журналом
     * проверка потребовала третьего, тот — четвёртого. У выпущенного релиза
     * такой беды нет: он заморожен тегом и после выхода не меняется, поэтому
     * там число скрытых печатается и остаётся честным.
     */
    unreleased: { entries: свежие.записи },
  }
}

