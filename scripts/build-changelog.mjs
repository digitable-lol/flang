function самопроверка() {
  let провалов = 0
  const жалоба = (сообщение) => {
    console.error(`self-test: ${сообщение}`)
    провалов += 1
  }

  const журнал = собратьЖурнал(ВЫДУМКА)
  const тексты = журнал.releases.flatMap((релиз) => релиз.entries.map((запись) => запись.text))

  // Свежий релиз — первым: журнал читают сверху.
  if (журнал.releases[0]?.version !== "0.9.1") {
    жалоба(`свежим релизом оказался ${журнал.releases[0]?.version}, а должен 0.9.1`)
  }
  if (журнал.latest !== "0.9.1") жалоба(`последним релизом объявлен ${журнал.latest}`)
  if (журнал.releases[0]?.human !== "2 августа 2026") {
    жалоба(`дата релиза прочитана как «${журнал.releases[0]?.human}»`)
  }

  // Заголовок: номер убран, пустой заголовок остаётся пустым, а не «flang 0.9.1».
  if (журнал.releases[1]?.title !== "первая публикация") {
    жалоба(`заголовок релиза прочитан как «${журнал.releases[1]?.title}»`)
  }
  if (журнал.releases[0]?.title !== null) {
    жалоба(`сообщение тега без текста дало заголовок «${журнал.releases[0]?.title}»`)
  }
  if (журнал.releases[1]?.note.join("|") !== "Первый абзац.|Второй абзац.") {
    жалоба(`тело тега разобрано как ${JSON.stringify(журнал.releases[1]?.note)}`)
  }

  // Служебные пути не показываются, видимые показываются.
  if (!тексты.includes("Свёртка перестала терять последний элемент")) {
    жалоба("правка компилятора не попала в журнал")
  }
  if (тексты.includes("План языка догнал сделанное")) {
    жалоба("правка планов и заметок попала в журнал")
  }
  // Пометка «нет» сильнее видимого пути.
  if (тексты.includes("Сборка стала быстрее")) {
    жалоба("пометка «Пользователю: нет» не перебила видимый путь")
  }
  // Пометка текстом вытягивает служебный путь и заменяет заголовок.
  if (!тексты.includes("Пакет больше не приезжает без стандартной библиотеки")) {
    жалоба("пометка «Пользователю: <текст>» не показала коммит своим текстом")
  }
  // Журнал сам себя изменением языка не считает.
  if (тексты.includes("Журнал перепечатан")) жалоба("журнал посчитал себя видимой правкой")

  // Скрытые сосчитаны: в 0.9.0 один план, в 0.9.1 сборка и сам журнал.
  if (журнал.releases[1]?.hidden !== 1) жалоба(`скрытых в 0.9.0: ${журнал.releases[1]?.hidden}, а должна 1`)
  if (журнал.releases[0]?.hidden !== 2) жалоба(`скрытых в 0.9.1: ${журнал.releases[0]?.hidden}, а должно 2`)

  // Незнакомый корень обязан всплыть, а не молча стать невидимым.
  if (!журнал.unclassified.includes("turbo")) жалоба("незнакомый корень turbo не попал в unclassified")

  /*
   * Петля. Проверка ловит ровно то, на чём этот скрипт уже обжёгся: пока в
   * «Не выпущено» был счётчик скрытых, коммит с перепечатанным журналом сам
   * увеличивал его — и требовал следующего коммита, тот следующего, без конца.
   * Два условия: счётчика там нет, и коммит, тронувший один только журнал,
   * не меняет напечатанное ни на байт.
   */
  if (JSON.stringify(журнал.unreleased).includes("hidden")) {
    жалоба("счётчик скрытых попал в «Не выпущено» — он уведёт проверку в петлю")
  }
  const сЖурналом = собратьЖурнал({
    ...ВЫДУМКА,
    невыпущенные: [
      {
        sha: "9".repeat(40),
        date: "2026-08-03T09:00:00+00:00",
        subject: "Журнал перепечатан",
        body: "",
        files: ["CHANGELOG.md", "changelog.json"],
      },
      ...ВЫДУМКА.невыпущенные,
    ],
  })
  if (печатьMarkdown(сЖурналом) !== печатьMarkdown(журнал)) {
    жалоба("коммит с перепечатанным журналом изменил журнал — это петля")
  }

  // Порядок версий — числовой, а не строковый.
  const версии = ["0.4.10", "0.4.2", "0.5.0", "0.4.9"].sort(сравнитьВерсии)
  if (версии.join(" ") !== "0.4.2 0.4.9 0.4.10 0.5.0") жалоба(`версии упорядочены как ${версии.join(" ")}`)

  // Русский счёт правок: журнал не должен писать «5 правки».
  const счёт = [1, 2, 5, 11, 21, 22].map(словоПравок).join(" ")
  if (счёт !== "правка правки правок правок правка правки") жалоба(`счёт правок: ${счёт}`)

  // Разбор вывода git: тело с переводами строк не должно съедать список файлов.
  const разобранные = разобратьЛог(
    `${ЗАПИСЬ}${"1".repeat(40)}${ПОЛЕ}2026-08-07T10:00:00+00:00${ПОЛЕ}Заголовок${ПОЛЕ}` +
      `Тело\n\nв три\nстроки\n${КОНЕЦ_ТЕЛА}flang/src/lexer.mjs\nflang/stdlib/lists.flang\n`,
  )
  if (разобранные.length !== 1) жалоба(`из одного коммита получилось ${разобранные.length} записей`)
  else if (разобранные[0].files.length !== 2) {
    жалоба(`тело с переводами строк съело файлы: ${JSON.stringify(разобранные[0].files)}`)
  }

  // Печать в Markdown обязана называть версию, дату и запись.
  const текст = печатьMarkdown(журнал)
  for (const кусок of ["## 0.9.1 — 2 августа 2026", "Свёртка перестала терять последний элемент"]) {
    if (!текст.includes(кусок)) жалоба(`в напечатанном журнале нет «${кусок}»`)
  }
  if (текст.includes("## 0.9.1 — 2 августа 2026\n\n**")) жалоба("пустой заголовок релиза всё-таки напечатан")

  // Пустой репозиторий — не падение: журнал без релизов валиден.
  const пустой = собратьЖурнал({ теги: [], невыпущенные: [] })
  if (пустой.latest !== null || пустой.releases.length !== 0) {
    жалоба("репозиторий без тегов должен давать журнал без релизов")
  }

  if (провалов) process.exit(1)
  console.log("build-changelog: self-test ок")
}

