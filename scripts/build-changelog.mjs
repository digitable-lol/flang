/*
 * Заголовок релиза из первой строки сообщения тега. Номер версии из неё
 * убирается: он и так стоит в заголовке раздела, а «0.4.7 — flang 0.4.7 — …»
 * читается как заикание. Если после номера ничего не осталось — заголовка у
 * релиза нет, и врать про него нечем: так у `v0.4.2`, `v0.4.4` и `v0.4.5`,
 * где всё сообщение тега состоит из строки «flang 0.4.4».
 */
export function заголовокРелиза(перваяСтрока) {
  const без = (перваяСтрока || "").replace(/^\s*(?:flang\s+)?v?\d+\.\d+\.\d+\s*(?:[—–-]|:)?\s*/u, "")
  return без.trim() || null
}

/*
 * Тело сообщения тега — абзацами. Переводы строк внутри абзаца схлопываются в
 * пробелы: тела здесь свёрстаны под 72 колонки терминала, и в вебе такие
 * переносы рвут строку посреди фразы. Подпись GPG отрезается: у подписанного
 * тега она приезжает тем же полем и прозой не является.
 */
export function абзацыТега(тело) {
  return (тело || "")
    .split(/-----BEGIN PGP SIGNATURE-----/u)[0]
    .split(/\n\s*\n/u)
    .map((абзац) => абзац.replace(/\s*\n\s*/gu, " ").trim())
    .filter(Boolean)
}

/** Номер версии из имени тега; null — тег не про релиз. */
export function версияТега(имя) {
  const найдено = /^v(\d+\.\d+\.\d+(?:[-+][\w.]+)?)$/u.exec(имя)
  return найдено ? найдено[1] : null
}

/** Порядок релизов: по номеру, а не по строке — иначе 0.4.10 встанет перед 0.4.2. */
export function сравнитьВерсии(левая, правая) {
  const числа = (версия) => версия.split(/[-+]/u)[0].split(".").map(Number)
  const л = числа(левая)
  const п = числа(правая)
  for (let i = 0; i < 3; i += 1) {
    if ((л[i] ?? 0) !== (п[i] ?? 0)) return (л[i] ?? 0) - (п[i] ?? 0)
  }
  /* Предрелиз («0.5.0-rc.1») идёт перед своим релизом: так его и читают. */
  return левая < правая ? -1 : левая > правая ? 1 : 0
}

