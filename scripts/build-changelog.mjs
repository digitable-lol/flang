/**
 * Журнал изменений языка — печатается из тегов и коммитов.
 *
 * Запуск: node scripts/build-changelog.mjs             — перепечатать журнал
 *         node scripts/build-changelog.mjs --check      — журнал не отстал?
 *         node scripts/build-changelog.mjs --self-test  — правила разбора
 *
 * ПОЧЕМУ НЕ НАПИСАН РУКАМИ. Ровно по той же причине, по которой печатается
 * указатель библиотеки (scripts/build-stdlib-index.mjs): за один день в этом
 * репозитории шесть раз выяснилось, что прозаическое утверждение о коде
 * пережило сам код. Текст не исполняется, поэтому не ломается. Рукописный
 * CHANGELOG устарел бы в первый же день — и устарел бы молча.
 *
 * ЧТО СЧИТАЕТСЯ РЕЛИЗОМ. В отличие от портала, у языка релизы настоящие: теги
 * `v0.4.0`…`v0.4.7`, а по ним — архивы и публикация в npm. Поэтому изобретать
 * «срез» (portal: scripts/build-release-notes.mjs) здесь не нужно и нельзя:
 * человек спрашивает не «что поменялось за сутки», а «что появилось в 0.4.7
 * против 0.4.6», и ответ на этот вопрос уже размечен тегами.
 *
 * ОТКУДА ТЕКСТ — и почему из трёх возможных источников взяты два.
 *
 *   1. Тег даёт РАМКУ релиза: номер, дату и заголовок. Только рамку: из восьми
 *      сообщений тегов три (`v0.4.2`, `v0.4.4`, `v0.4.5`) состоят из одной
 *      строки «flang 0.4.4» и не говорят ни о чём. Тега одного не хватает.
 *
 *   2. Коммиты между тегами дают СОДЕРЖАНИЕ. Заголовок коммита здесь написан
 *      утверждением — «что теперь правда», а не «что я делал»: «Отказ „к числу“
 *      стал значением: столбец из строк складывается, не падая», «„тотальная“
 *      перестала обещать больше, чем доказано: сторож меры». Это готовые строки
 *      для человека, и переписывать их вручную значило бы завести вторую копию
 *      того же текста — то есть ровно ту прозу, которая переживает код.
 *
 *   3. Примечания к релизам на GitHub ОТВЕРГНУТЫ как источник, хотя написаны
 *      подробнее всего. Причина механическая, а не вкусовая: они лежат вне
 *      репозитория, и за ними надо ходить в сеть. Тогда ни `--check`, ни
 *      flang/test/changelog.test.mjs не воспроизвели бы файл — ни в CI, где
 *      сети к API GitHub может не быть и токена нет, ни на машине без доступа.
 *      Проверка, которую нельзя выполнить, не проверка. Из тега при этом
 *      берётся его собственное тело (у `v0.4.0` и `v0.4.1` оно содержательное),
 *      потому что тег — часть репозитория.
 *
 * ПРИЗНАК «ЭТО ВИДНО ТОМУ, КТО ПИШЕТ НА ЯЗЫКЕ» выводится из тронутых путей, а
 * не из пометок в сообщениях: пометку надо не забыть на каждом коммите, а путь
 * — побочный продукт работы. Правило опирается на факт: видно то, от чего
 * меняется сам язык или состав поставки — компилятор, библиотека, команды,
 * упаковка, схемы, подсветка для редакторов. Не видно то, что рассказывает о
 * языке или обслуживает разработку: планы, спецификации, тесты, скрипты, CI.
 *
 * Список корней закрыт с обеих сторон умышленно: незнакомый путь — не
 * «наверное, служебный», а повод остановиться, потому что молча пропущенная
 * видимая правка и есть та поломка, от которой журнал стережётся.
 *
 * ГДЕ ПРАВИЛО СОВРЁТ, и это известно заранее:
 *
 *   flang/SPEC.md   — нормативное описание языка. Правка спецификации вслед за
 *                     кодом приедет вместе с кодом, а правка одной только
 *                     спецификации будет скрыта. Это осознанно: журнал говорит,
 *                     что изменилось в ЯЗЫКЕ, а не в рассказе о нём.
 *   flang/src/      — правка комментария или сообщения теста пойдёт как видимая.
 *                     Ложное «видно»: шум на одну строку, и он заметен.
 *   package.json    — подъём версии виден, хотя сам по себе ничего не меняет.
 *                     Но там же живут `bin`, `exports` и `files`, то есть состав
 *                     поставки, и различить их по пути нельзя.
 *
 * ПОМЕТКА ВРУЧНУЮ перебивает правило — строкой в теле коммита:
 *
 *   Пользователю: нет            — не показывать, что бы ни говорили пути;
 *   Пользователю: да             — показать заголовком, даже если пути служебные;
 *   Пользователю: <любой текст>  — показать этим текстом.
 *
 * Пометка живёт в сообщении коммита, то есть задним числом её не поставить. Это
 * осознанный предел: журнал обязан печататься из одной только истории, иначе
 * рядом появляется второй источник правды, который чинят руками.
 *
 * ДВА ФАЙЛА ИЗ ОДНОЙ СТРУКТУРЫ. `CHANGELOG.md` читает человек, `changelog.json`
 * — тот, кто показывает журнал у себя (портал courses берёт его через
 * scripts/sync-flang-changelog.mjs и кладёт в свои данные). JSON нужен именно
 * поэтому: заставить чужой репозиторий разбирать нашу же прозу значило бы
 * завести второй разбор, который разойдётся с печатью при первой правке
 * оформления. Оба файла печатаются из одного снимка, и оба сверяются.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни даты генерации, ни имени машины, ни номера прогона: файл
 * обязан быть побайтово одинаковым у двух прогонов подряд, иначе проверка
 * «журнал не отстал» краснела бы от самого факта запуска.
 */
