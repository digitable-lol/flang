/**
 * Видимость одного пути: true — это меняет язык для того, кто им пользуется,
 * false — нет, null — корень не классифицирован, решать нельзя.
 */
export function видимостьПути(путь) {
  if (НЕ_ИЗМЕНЕНИЕ.has(путь)) return false
  const части = путь.split("/")
  /* Два сегмента для flang/, один для остального — см. комментарий к ВИДИМОСТЬ. */
  const ключ = части[0] === "flang" && части.length > 1 ? `flang/${части[1]}` : части[0]
  const известно = ВИДИМОСТЬ.get(ключ)
  return известно === undefined ? null : известно
}

/*
 * Пометка в теле коммита. Ищется строкой целиком, а не подстрокой: слово
 * «пользователю» встречается в прозе тел («пользователю это ничего не даёт»),
 * и подстрока превратила бы объяснение в приказ.
 */
const ПОМЕТКА = /^[ \t]*Пользователю[ \t]*:[ \t]*(.+?)[ \t]*$/mu
const ПОМЕТКА_НЕТ = new Set(["нет", "не видно", "не показывать", "скрыть"])
const ПОМЕТКА_ДА = new Set(["да", "видно", "показать"])

export function пометка(тело) {
  const найдено = ПОМЕТКА.exec(тело || "")
  if (!найдено) return null
  const значение = найдено[1].trim()
  const строчными = значение.toLowerCase()
  if (ПОМЕТКА_НЕТ.has(строчными)) return { показывать: false, текст: null }
  if (ПОМЕТКА_ДА.has(строчными)) return { показывать: true, текст: null }
  return { показывать: true, текст: значение }
}

/** Решение по одному коммиту: показывать ли и каким текстом. */
export function решение(коммит) {
  const файлы = коммит.files.filter((путь) => !НЕ_ИЗМЕНЕНИЕ.has(путь))
  const неизвестные = файлы.filter((путь) => видимостьПути(путь) === null)
  const метка = пометка(коммит.body)

  if (метка && !метка.показывать) return { показывать: false, неизвестные }
  const видно = метка?.показывать || файлы.some((путь) => видимостьПути(путь) === true)
  if (!видно) return { показывать: false, неизвестные }

  return { показывать: true, текст: метка?.текст ?? коммит.subject.trim(), неизвестные }
}

