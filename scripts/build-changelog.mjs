/*
 * Разделители — управляющие символы: в сообщениях коммитов и тегов их не
 * бывает, а любой печатный разделитель рано или поздно встретится в теле, где
 * цитируют и вывод команд, и куски кода.
 *
 * core.quotePath=false обязателен: без него git печатает пути с кириллицей
 * восьмеричными последовательностями в кавычках («"docs/…"»), и корень такого
 * пути читался бы как `"docs` — незнакомый, то есть проверка вставала бы на
 * ровном месте. В дереве таких файлов больше нет — материалы `docs/public/`
 * уехали из репозитория, — но журнал печатается по всей истории, и там они
 * остались навсегда.
 */
const ЗАПИСЬ = "\u0001"
const ПОЛЕ = "\u0002"
const КОНЕЦ_ТЕЛА = "\u0003"

const git = (...аргументы) =>
  execFileSync("git", ["-C", КОРЕНЬ, "-c", "core.quotePath=false", ...аргументы], {
    encoding: "utf8",
    maxBuffer: 128 * 1024 * 1024,
  })

export function разобратьЛог(вывод) {
  const коммиты = []
  for (const кусок of вывод.split(ЗАПИСЬ).slice(1)) {
    const [голова, хвост = ""] = кусок.split(КОНЕЦ_ТЕЛА)
    const [sha, date, subject, body = ""] = голова.split(ПОЛЕ)
    коммиты.push({
      sha,
      date,
      subject,
      body,
      files: хвост
        .split("\n")
        .map((строка) => строка.trim())
        .filter(Boolean),
    })
  }
  return коммиты
}

function читатьКоммиты(диапазон) {
  const формат = [ЗАПИСЬ, "%H", ПОЛЕ, "%aI", ПОЛЕ, "%s", ПОЛЕ, "%b", КОНЕЦ_ТЕЛА].join("")
  return разобратьЛог(git("log", "--no-merges", "--name-only", `--format=${формат}`, ...диапазон))
}

/**
 * Теги релизов с их сообщениями. `%(*objectname)` пуст у легковесного тега — у
 * такого тега нет ни своего сообщения, ни даты автора, и `%(contents)` вернул
 * бы сообщение коммита, то есть первую же запись журнала вторым голосом.
 * Поэтому у легковесного тега заголовок и тело считаются пустыми.
 */
export function читатьТеги() {
  const формат = [
    ЗАПИСЬ,
    "%(refname:short)",
    ПОЛЕ,
    "%(creatordate:iso-strict)",
    ПОЛЕ,
    "%(objectname)",
    ПОЛЕ,
    "%(*objectname)",
    ПОЛЕ,
    "%(contents:subject)",
    ПОЛЕ,
    "%(contents:body)",
    КОНЕЦ_ТЕЛА,
  ].join("")
  const вывод = git("for-each-ref", `--format=${формат}`, "refs/tags")

  const теги = []
  for (const кусок of вывод.split(ЗАПИСЬ).slice(1)) {
    const [голова] = кусок.split(КОНЕЦ_ТЕЛА)
    const [имя, дата, объект, коммитТега, строка = "", тело = ""] = голова.split(ПОЛЕ)
    const version = версияТега(имя.trim())
    if (!version) continue
    const аннотированный = Boolean(коммитТега.trim())
    теги.push({
      tag: имя.trim(),
      version,
      date: дата.trim(),
      commit: (аннотированный ? коммитТега : объект).trim(),
      title: аннотированный ? заголовокРелиза(строка) : null,
      note: аннотированный ? абзацыТега(тело) : [],
    })
  }
  теги.sort((левый, правый) => сравнитьВерсии(левый.version, правый.version))
  return теги
}

/** Полное чтение репозитория: теги, коммиты каждого релиза и хвост после последнего. */
export function читатьРепозиторий() {
  const теги = читатьТеги()
  let предыдущий = null
  for (const тег of теги) {
    тег.commits = читатьКоммиты(предыдущий ? [`${предыдущий.tag}..${тег.tag}`] : [тег.tag])
    предыдущий = тег
  }
  const последний = теги.at(-1)
  const невыпущенные = читатьКоммиты(последний ? [`${последний.tag}..HEAD`] : ["HEAD"])
  const версияПакета = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).version
  return { теги, невыпущенные, версияПакета }
}

