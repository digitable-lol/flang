#!/usr/bin/env node
/**
 * Сборка релизного C: компилятор flang, напечатанный в самодостаточный
 * исходник на C99.
 *
 * Зачем это существует. Компилятор языка написан на самом языке
 * (`flang/self/`), и печатается он в C. Значит его можно положить в релиз уже
 * напечатанным — и тогда пользователю не нужен ни Node, ни сам flang, чтобы
 * поставить flang: достаточно `cc` и `make`. Ровно так поступают
 * самоприменяющиеся языки; Go долго возил сгенерированный C, Nim возит до сих
 * пор.
 *
 * Это снимает проблему начальной загрузки для всех, кроме тех, кто развивает
 * сам язык: чтобы получить первый бинарник из исходников на flang, Node нужен,
 * а чтобы собрать из релиза — нет.
 *
 * Что кладётся в релиз:
 *
 *   flang_runtime.h   flang_runtime.c    рантайм: значения, арена, встроенные формы
 *   compiler_flang.h  compiler_flang.c   сам компилятор, шесть слоёв
 *   flang_cli.c                          прогонщик: JSON на входе и выходе
 *   flang_repl.c                         человеческий вход: --help, check, repl
 *   flang.1                              страница руководства (man flang)
 *   Makefile                             cc -std=c99 -Werror -pedantic
 *
 * Проверка на месте, а не на веру: напечатанное собирается прямо здесь, в
 * окружении без Node в PATH, и собранный бинарник вызывается. Если релиз не
 * собирается — скрипт падает, и битый релиз не уезжает. Человеческие команды
 * проверяются тем же способом и по той же причине: `flang --help`, который
 * молчит и отвечает нулём, ничем не отличается от отсутствующего, и узнать об
 * этом надо здесь, а не от человека после `brew install`.
 */
import { execFileSync, spawnSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { nodeДостижим, исполняемый, путьБезNode } from "./node-free-path.mjs"
import {
  РАНТАЙМ_В_АРХИВЕ,
  РАНТАЙМ_В_ДЕРЕВЕ,
  РАНТАЙМ_ПРИ_УСТАНОВКЕ,
  РАНТАЙМ_ФАЙЛЫ,
  ТОЧКА_РАСКРУТКИ,
  файлыТочкиРаскрутки,
} from "./release-layout.mjs"

const корень = resolve(dirname(fileURLToPath(import.meta.url)), "..")
/* Версия — из package.json, а не строкой рядом: релиз, называющий себя иначе,
   чем пакет, из которого собран, никому не объяснишь. */
const пакет = JSON.parse(readFileSync(join(корень, "package.json"), "utf8"))
const источник = join(корень, "flang/self/bootstrap/compiler.flang")
const каталог = process.argv[2] ?? join(корень, "output/release-c")

/*
 * АРХИВ — ЭТО ТОЧКА РАСКРУТКИ `bootstrap/`, а не вторая её печать.
 *
 * Раньше здесь печатали компилятор заново — тем же `напечатать()`, каким
 * печаталась точка раскрутки, — и архив совпадал с ней «потому что печатает
 * одна функция». Функция эта звала реализацию на JavaScript, а её удалили
 * (коммит fe8e8a37): путь оборвался, и релиз перестал собираться вовсе.
 *
 * Печатать теперь умеет только сам двоичный, и одна печать компилятора стоит
 * одиннадцать минут. Платить их здесь второй раз незачем: семь файлов берутся
 * из `bootstrap/` как есть, и совпадение архива с точкой раскрутки становится
 * не обещанием, а свойством — это один и тот же байт.
 *
 * Отдельный вопрос — не отстала ли САМА точка раскрутки от исходников. На него
 * отвечает `sh scripts/raskrutka.sh --check`, и звать его надо перед выпуском.
 * Смешивать эти два вопроса в одном шаге и значило платить одиннадцать минут за
 * ответ, который уже дан.
 *
 * Оттуда же, из `bootstrap/`, следует и раскладка: архив — это те же семь
 * файлов плюс `flang.1`, `LICENSE` и рукописный рантайм.
 */
const имена = файлыТочкиРаскрутки(корень)
const файлы = имена.map((имя) => ({
  path: имя,
  content: readFileSync(join(корень, ТОЧКА_РАСКРУТКИ, имя), "utf8"),
}))
console.log(`компилятор: ${источник}`)
console.log(`точка раскрутки: ${ТОЧКА_РАСКРУТКИ}/ — ${файлы.length} файлов`)
console.log(`свежесть точки раскрутки проверяется отдельно: sh scripts/raskrutka.sh --check`)
const напечатано = { files: файлы }

rmSync(каталог, { recursive: true, force: true })
mkdirSync(каталог, { recursive: true })
let всего = 0
for (const файл of напечатано.files) {
  const путь = join(каталог, файл.path)
  mkdirSync(dirname(путь), { recursive: true })
  writeFileSync(путь, файл.content, "utf8")
  всего += Buffer.byteLength(файл.content, "utf8")
  console.log(`  ${файл.path}  ${(Buffer.byteLength(файл.content, "utf8") / 1024).toFixed(0)} КБ`)
}
/*
 * Страница руководства кладётся рядом с исходниками, а не в подкаталог: формула
 * Homebrew ставит её строкой `man1.install "flang.1"` из корня распакованного
 * архива, и лишний уровень пришлось бы держать в голове обеим упаковкам.
 * Печатью она не порождается — это текст про фактический интерфейс, а не про
 * программу, — поэтому копируется из репозитория как есть.
 */
const страница = join(корень, "packaging/flang.1")
writeFileSync(join(каталог, "flang.1"), readFileSync(страница, "utf8"), "utf8")
console.log(`  flang.1  ${(readFileSync(страница).length / 1024).toFixed(0)} КБ (из packaging/)`)
/*
 * LICENSE в архив кладётся по той же причине, по которой шапки стоят в
 * рантайме: пункт 1 BSD-2-Clause требует сохранять уведомление при
 * распространении исходников, а архив — это ровно распространение исходников.
 * Шапку несут четыре файла из семи; `compiler_flang.[ch]` — это печать
 * нашего же компилятора, и своего копирайта в ней нет по правилу «перевод
 * программы принадлежит её автору». Уведомление на весь архив закрывает и их.
 */
const лицензия = join(корень, "LICENSE")
writeFileSync(join(каталог, "LICENSE"), readFileSync(лицензия, "utf8"), "utf8")
console.log(`  LICENSE  ${(readFileSync(лицензия).length / 1024).toFixed(0)} КБ (из корня)`)

/*
 * ИСХОДНИКИ РАНТАЙМА — то, без чего `flang emit --target c` не работает ни у
 * одного поставившего язык, и до 0.5.3 их в архиве не было вовсе.
 *
 * Что ломалось. Печать в C кладёт в вывод четыре файла рантайма ДОСЛОВНО, а
 * значит обязана прочитать их с диска (`emit_runtime_dir` в flang_repl.c).
 * Ищет она их в `--runtime`, в `$FLANG_RUNTIME_DIR` и в `share/flang/c` рядом с
 * установленным бинарником. Формула Homebrew и плагин asdf ставили `bin`, `lib`,
 * `include` — и ни один из них не клал `share/flang/c`. Человек получал
 * «не найдены исходники рантайма C» на любой попытке напечатать программу.
 *
 * Почему нельзя взять верхние файлы архива. Наверху лежат НАПЕЧАТАННЫЕ копии тех
 * же имён — с шапкой «Сгенерировано flang» в первой строке. Печать их отвергает
 * по делу: приписать шапку второй раз значило бы соврать о происхождении файла.
 * Поэтому рукописные оригиналы едут ОТДЕЛЬНЫМ каталогом, а не рядом: имена
 * совпадают, и в одном каталоге они бы затёрли друг друга.
 *
 * Имя каталога — `runtime-c`: его целиком переносят в `share/flang/c` и формула,
 * и плагин (`packaging/homebrew/flang.rb`, `packaging/asdf/bin/install`). Живёт
 * оно в `scripts/release-layout.mjs`, а не строкой здесь: тех, кто обязан знать
 * его одинаково, четверо, и разойтись им уже случалось.
 */
const рантаймИз = join(корень, РАНТАЙМ_В_ДЕРЕВЕ)
mkdirSync(join(каталог, РАНТАЙМ_В_АРХИВЕ), { recursive: true })
let рантаймБайт = 0
for (const имя of РАНТАЙМ_ФАЙЛЫ) {
  const текст = readFileSync(join(рантаймИз, имя), "utf8")
  /* Сторож происхождения: если сюда однажды попадёт напечатанная копия, печать у
     человека молча откажет, а узнать об этом надо здесь.
     Смотрится ШАПКА, а не весь файл: `flang_repl.c` сам эту строку и ищет
     (`emit_runtime_here`), и по всему тексту он отвергал бы сам себя. Шапка
     стоит в первых двухстах байтах и только там. */
  if (текст.slice(0, 400).includes("Сгенерировано flang")) {
    console.error(`${имя} в ${рантаймИз} — НАПЕЧАТАННАЯ копия, а не исходник: печать такую отвергает`)
    process.exit(1)
  }
  writeFileSync(join(каталог, РАНТАЙМ_В_АРХИВЕ, имя), текст, "utf8")
  рантаймБайт += Buffer.byteLength(текст, "utf8")
}
всего += рантаймБайт
console.log(`  ${РАНТАЙМ_В_АРХИВЕ}/  ${(рантаймБайт / 1024).toFixed(0)} КБ (${РАНТАЙМ_ФАЙЛЫ.length} исходника рантайма для «flang emit»)`)
console.log(`итого ${(всего / 1024 / 1024).toFixed(2)} МБ в ${каталог}`)

/* Сборка в окружении без Node: если релиз требует Node, обещание «нужен только
   cc» ложно, и узнать об этом надо здесь, а не от пользователя.

   PATH собирается ОТБОРОМ, а не зашитым списком. Прежде здесь стояло
   `PATH: "/usr/bin:/bin:/usr/local/bin"` со словами «PATH без Node» рядом — при
   том что node лежит ровно в /usr/local/bin. Сторож, заведённый ловить
   прокравшуюся зависимость от Node, не поймал бы её никогда. Почему нельзя
   просто выкинуть /usr/local/bin и почему отказ честнее тихого обхода —
   в scripts/node-free-path.mjs. */
const среда = путьБезNode({ нужны: ["make"] })
const компилятор = ["cc", "gcc", "clang"].find((имя) => среда.оставлены.some((к) => исполняемый(к, имя)))

if (!среда.годен || компилятор === undefined) {
  const рядомСNode = ["cc", "gcc", "clang", "make"].filter((имя) =>
    среда.выброшены.some((к) => исполняемый(к, имя)),
  )
  if (рядомСNode.length > 0) {
    console.error(`\nсборку без Node здесь проверить НЕЛЬЗЯ: ${среда.почему ?? "компилятор C нашёлся только там же, где node"}`)
    console.error(`каталоги, выброшенные из-за node: ${среда.выброшены.join(", ")}`)
    console.error(`инструменты, живущие рядом с node: ${рядомСNode.join(", ")}`)
    console.error("это не «всё хорошо», а «не смог проверить»: собрать с node под рукой и назвать")
    console.error("это проверкой сборки без Node значит соврать ровно там, где проверяют честность")
    process.exit(1)
  }
  console.log("компилятора C в системе нет — сборка релиза не проверена")
  process.exit(0)
}

/* Пояс поверх подтяжек: если node всё же достижим, отбор сломан, и собирать
   нельзя — иначе зелёная сборка снова ничего не будет значить. */
if (nodeДостижим(среда.путь)) {
  console.error(`отбор PATH сломан: node достижим на «${среда.путь}»`)
  process.exit(1)
}

console.log(`\nпроверка сборки (${компилятор}, PATH без Node: ${среда.путь})`)
if (среда.выброшены.length > 0) {
  console.log(`  выброшено из-за node: ${среда.выброшены.join(", ")}`)
}
execFileSync("make", ["-C", каталог], {
  stdio: "inherit",
  env: { PATH: среда.путь, HOME: process.env.HOME ?? "/tmp" },
})

/*
 * Имя выхода спрашивается у КАТАЛОГА, а не пишется здесь.
 *
 * Напечатанный Makefile зовёт выход по-разному, и зависит это от того, чья это
 * программа: у обычной напечатанной — `flang_cli` (JSON на входе и выходе), а у
 * самого компилятора, который печатается с `repl: true`, — `flang`, потому что
 * ровно это имя человек и набирает (`renderMakefile` в `flang/src/emit/c.mjs`).
 *
 * Здесь стояло жёсткое `flang_cli`, и после переименования выхода этот скрипт
 * падал строкой «сборка прошла, но flang_cli не появился» — при том что сборка
 * прошла и бинарник лежал рядом под именем `flang`. То есть релиз собрать было
 * НЕЛЬЗЯ, и узналось это не сторожем, а попыткой собрать релиз: скрипт зовут
 * руками перед тегом, и между переименованием и следующим тегом он никем не
 * прогонялся. Формула Homebrew и плагин asdf ту же развилку уже держат обоими
 * именами — здесь она была третьей копией знания и разошлась первой.
 */
const собрано = readdirSync(каталог)
/* ИМЯ ВЫХОДА — «flang», именем языка: у компилятора и у поставленного из brew
   файла обязано быть одно имя (коммит b517cc8f). Прежнее имя принимается тоже, и это
   не вежливость к старью: скрипт собирает Makefile ИЗ АРХИВА, а архив бывает
   старый — так собирают предыдущие выпуски, когда надо переснять улику.

   Проверка стояла на одном имени flang_cli и после переименования отказывала
   ВСЕГДА: «сборка прошла, но flang_cli не появился». То есть выпустить релиз
   было нельзя вовсе, и поймалось это только попыткой выпустить. Тот же приём,
   что в плагине asdf (packaging/asdf/bin/install), и по той же причине. */
const бинарник = ["flang", "flang_cli"].find((имя) => собрано.includes(имя))
if (бинарник === undefined) {
  console.error(`сборка прошла, но бинарника нет: в ${каталог} ни «flang», ни «flang_cli»`)
  console.error(`лежит: ${собрано.join(", ")}`)
  process.exit(1)
}

/* Прогон: бинарник обязан не просто собраться, а ответить. */
const запрос = JSON.stringify({
  fn: "Число связанных функций",
  args: [
    { l: [{ r: [["путь", { s: "проба.flang" }], ["текст", { s: 'модуль «Проба»\n\nтотальная функция «Два»\n  возвращает число\n  2\n' }]] }] },
    { s: "проба.flang" },
  ],
})
const ответ = execFileSync(join(каталог, бинарник), [], {
  input: `${запрос}\n`,
  env: { PATH: "/usr/bin:/bin" },
}).toString()
const итог = JSON.parse(ответ)
if (итог.ok !== true) {
  console.error(`собранный компилятор не отвечает: ${ответ}`)
  process.exit(1)
}
console.log(`\nсобранный компилятор ответил: ${ответ.trim()}`)

/* Проба выше слишком дешёвая: на трёхстрочном модуле не видно ни пределов, ни
   памяти. Настоящая проверка — дать бинарнику разобрать файл компилятора,
   то есть тот самый вход, на котором умолчания и обрывались. */
const тяжёлый = join(корень, "flang/self/parser.flang")
const тяжкийЗапрос = JSON.stringify({
  fn: "Число связанных функций",
  args: [
    { l: [{ r: [["путь", { s: "parser.flang" }], ["текст", { s: readFileSync(тяжёлый, "utf8") }]] }] },
    { s: "parser.flang" },
  ],
})
const тяжкийОтвет = execFileSync(join(каталог, бинарник), [], {
  input: `${тяжкийЗапрос}\n`,
  env: { PATH: "/usr/bin:/bin" },
  maxBuffer: 64 * 1024 * 1024,
}).toString()
const тяжкийИтог = JSON.parse(тяжкийОтвет)
if (тяжкийИтог.ok !== true) {
  console.error(`релиз не справился с настоящим входом (${тяжёлый}): ${тяжкийОтвет.slice(0, 200)}`)
  process.exit(1)
}
console.log(`разобрал self/parser.flang: функций ${тяжкийИтог.value.n}`)

/*
 * Человеческий вход: то, ради чего язык ставят из brew. Проверяется запуском, а
 * не наличием строк в исходнике, — потому что ровно этим бинарник и подвёл: он
 * ПРИНИМАЛ `--help` и `check` (аргументы никого не смущали), молчал в ответ и
 * отвечал нулём. Тест, который смотрит на код возврата, такое пропускает; тест,
 * который требует непустого вывода, — нет.
 */
const человек = (аргументы, вход = "") =>
  spawnSync(join(каталог, бинарник), аргументы, {
    input: вход,
    encoding: "utf8",
    env: { PATH: "/usr/bin:/bin", HOME: process.env.HOME ?? "/tmp" },
    maxBuffer: 16 * 1024 * 1024,
  })

const справка = человек(["--help"])
if (справка.status !== 0 || !справка.stdout.includes("flang check")) {
  console.error(`«flang --help» не рассказал о себе: код ${справка.status}, вывод ${JSON.stringify(справка.stdout)}`)
  process.exit(1)
}
const версия = человек(["--version"])
if (версия.status !== 0 || версия.stdout.trim() !== `flang ${пакет.version}`) {
  console.error(`«flang --version» назвал не ту версию: ${JSON.stringify(версия.stdout)}, ждали flang ${пакет.version}`)
  process.exit(1)
}

/* Проверка настоящего файла: годный обязан дать 0, сломанный — 1 и замечание с
   кодом. Оба случая, потому что «всегда 0» и «всегда 1» одинаково бесполезны. */
const проба = join(каталог, "проба.flang")
writeFileSync(проба, "модуль «Проба»\n\nтотальная функция «Два»\n  возвращает число\n  2\n", "utf8")
const годный = человек(["check", проба])
if (годный.status !== 0 || !годный.stdout.includes("проверено")) {
  console.error(`«flang check» не проверил годный файл: код ${годный.status}, ${годный.stdout}${годный.stderr}`)
  process.exit(1)
}
writeFileSync(проба, "модуль «Проба»\n\nтотальная функция «Два»\n  возвращает число\n  \"два\"\n", "utf8")
const сломанный = человек(["check", проба])
if (сломанный.status !== 1 || !сломанный.stderr.includes("FLANG_TYPE")) {
  console.error(`«flang check» не заметил ошибку типов: код ${сломанный.status}, ${сломанный.stderr}`)
  process.exit(1)
}
rmSync(проба)
console.log(`человеческий вход: ${версия.stdout.trim()}, справка ${справка.stdout.split("\n").length} строк, check отвечает 0 и 1`)

/*
 * ПУТЬ УСТАНОВКИ ЦЕЛИКОМ, а не архив по частям.
 *
 * За один день путь установки ломался четырежды, и каждый раз потому, что его
 * никто не проходил от начала до конца: архив собирался, бинарник отвечал,
 * формула ставила — а `flang emit --target c` у поставившего не работал, потому
 * что рукописного рантайма в архиве не было вовсе, и класть в `share/flang/c`
 * было нечего. Ни одна проверка выше этого не видит: они гоняют бинарник ТАМ,
 * ГДЕ ОН СОБРАН, а собран он рядом со своими исходниками.
 *
 * Поэтому здесь строится настоящий префикс — `bin`, `lib`, `include`,
 * `share/flang/c`, — ровно теми же файлами и по тем же путям, что кладут
 * формула Homebrew и плагин asdf, и печать зовётся ИЗ НЕГО. Каталог вывода
 * назван несуществующим нарочно: `emit` обязан завести его сам.
 */
const префикс = join(каталог, "проба-установки")
rmSync(префикс, { recursive: true, force: true })
for (const часть of ["bin", "lib", "include", РАНТАЙМ_ПРИ_УСТАНОВКЕ]) {
  mkdirSync(join(префикс, часть), { recursive: true })
}
writeFileSync(join(префикс, "bin/flang"), readFileSync(join(каталог, бинарник)))
execFileSync("chmod", ["0755", join(префикс, "bin/flang")])
for (const имя of собрано.filter((имя) => имя.startsWith("lib") && имя.endsWith(".a"))) {
  writeFileSync(join(префикс, "lib", имя), readFileSync(join(каталог, имя)))
}
for (const имя of собрано.filter((имя) => имя.endsWith(".h"))) {
  writeFileSync(join(префикс, "include", имя), readFileSync(join(каталог, имя)))
}
for (const имя of РАНТАЙМ_ФАЙЛЫ) {
  writeFileSync(join(префикс, РАНТАЙМ_ПРИ_УСТАНОВКЕ, имя), readFileSync(join(каталог, РАНТАЙМ_В_АРХИВЕ, имя)))
}

const пробаПечати = join(префикс, "проба.flang")
writeFileSync(пробаПечати, "модуль «Проба»\n\nтотальная функция «Два»\n  возвращает число\n  2\n", "utf8")
const кудаПечатать = join(префикс, "нет-такого/каталога")
const печать = spawnSync(join(префикс, "bin/flang"), ["emit", пробаПечати, "--target", "c", "--out", кудаПечатать], {
  encoding: "utf8",
  env: { PATH: "/usr/bin:/bin", HOME: process.env.HOME ?? "/tmp" },
  maxBuffer: 64 * 1024 * 1024,
})
if (печать.status !== 0) {
  console.error("установленный flang не печатает в C — путь установки сломан:")
  console.error(печать.stderr)
  console.error(`префикс: ${префикс}; рантайм ожидался в ${join(префикс, РАНТАЙМ_ПРИ_УСТАНОВКЕ)}`)
  process.exit(1)
}
const напечатаноФайлов = existsSync(кудаПечатать) ? readdirSync(кудаПечатать) : []
if (!напечатаноФайлов.includes("flang_runtime.c") || !напечатаноФайлов.includes("Makefile")) {
  console.error(`печать прошла, но файлов нет: ${напечатаноФайлов.join(", ") || "каталог не заведён"}`)
  process.exit(1)
}
console.log(`путь установки: flang из ${префикс}/bin напечатал ${напечатаноФайлов.length} файлов в несуществовавший каталог`)
/* Проба убирается: в каталоге релиза остаётся ровно то, что уезжает в архив. */
rmSync(префикс, { recursive: true, force: true })

/* Страница руководства обязана не просто лежать, а разбираться troff: битую
   заметит человек, набравший `man flang`, и заметит молча — man покажет мусор. */
const troff = ["groff", "nroff"].find((имя) => {
  try {
    execFileSync("which", [имя], { stdio: "ignore" })
    return true
  } catch {
    return false
  }
})
if (troff === undefined) {
  console.log("troff в системе нет — страница руководства не проверена")
} else {
  /* Жирное и подчёркнутое groff размечает управляющими последовательностями
     терминала: их снимает `man`, а нам они мешают искать слова. */
  const набрано = execFileSync(troff, ["-K", "utf8", "-man", "-Tutf8", join(каталог, "flang.1")], {
    encoding: "utf8",
    env: { PATH: "/usr/bin:/bin", HOME: process.env.HOME ?? "/tmp" },
  }).replace(/\[[0-9;]*m/gu, "")
  if (!набрано.includes("FLANG(1)") || !набрано.includes("flang check")) {
    console.error("страница руководства набралась, но это не страница про flang check")
    process.exit(1)
  }
  console.log(`страница руководства набирается ${troff}: ${набрано.split("\n").length} строк`)
}

console.log(existsSync(join(каталог, бинарник)) ? "релиз готов" : "релиз не готов")
