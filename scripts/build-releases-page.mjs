/**
 * Печать страницы «Выпуски» — обеих её половин, русской и английской.
 *
 *   node scripts/build-releases-page.mjs           напечатать
 *   node scripts/build-releases-page.mjs --check   сверить напечатанное с тегами
 *
 * ── Зачем ещё одна страница про изменения ───────────────────────────────────
 *
 * Их было две, и обе печатались из истории коммитов: журнал коммитов
 * (`CHANGELOG.md`) и журнал вливаний (`docs/site/changelog.md`). Заголовок
 * коммита в этом дереве пишется утверждением для КОМАНДЫ — «Порождённый C
 * перепечатан после языкового сервера», — и как запись рабочего дня он верен.
 * Читателю языка он не говорит ничего: чтобы понять из него, что изменилось в
 * языке, надо знать, что такое «порождённый C» и почему его перепечатывают.
 *
 * Единица здесь другая и та же, что у go, elixir и rust: ВЫПУСК. Тег `vX.Y.Z` —
 * это решение «вот эту версию наружу», и ровно её ставит читатель. Поэтому
 * страница печатается из тегов, а текст к каждому выпуску написан человеком и
 * лежит в `docs/release-notes.json` тремя ящиками: что появилось, что
 * изменилось, что сломалось.
 *
 * Оба журнала никуда не делись — они уехали в раздел для тех, кто развивает
 * язык, потому что там их и читают.
 *
 * ── Что здесь стережётся ────────────────────────────────────────────────────
 *
 * Тег без заметки — красный. Иначе первый же выпуск, о котором забыли написать,
 * молча выпал бы со страницы, и заметил бы это читатель, а не дерево. Заметка
 * без тега — тоже красный: это заявка на выпуск, которого нет.
 */
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

export const КОРЕНЬ = fileURLToPath(new URL("../", import.meta.url))
export const ПУТЬ_ЗАМЕТОК = fileURLToPath(new URL("../docs/release-notes.json", import.meta.url))
export const ПУТИ = {
  ru: fileURLToPath(new URL("../docs/site/releases.ru.md", import.meta.url)),
  en: fileURLToPath(new URL("../docs/site/releases.md", import.meta.url)),
}

/** Версия состава полей заметок. Растёт, когда меняется набор ящиков. */
export const ФОРМАТ = 1

const гит = (доводы) =>
  execFileSync("git", доводы, { cwd: КОРЕНЬ, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] })

/* ── Теги ────────────────────────────────────────────────────────────────── */

/** Только выпуски: `v1.2.3`. Ветки-архивы и метки возврата сюда не попадают. */
const ТЕГ_ВЫПУСКА = /^v(\d+)\.(\d+)\.(\d+)$/u

/** Порядок — по числам версии, а не по строкам: `0.4.10` старше `0.4.9`. */
const поВерсии = (а, б) => {
  const ча = а.split(".").map(Number)
  const чб = б.split(".").map(Number)
  for (let i = 0; i < 3; i++) if (ча[i] !== чб[i]) return чб[i] - ча[i]
  return 0
}

/** Выпуски дерева: версия и дата тега. Свежие первыми. */
export function выпуски() {
  const найдено = []
  for (const строка of гит(["tag", "-l"]).split("\n")) {
    const м = ТЕГ_ВЫПУСКА.exec(строка.trim())
    if (!м) continue
    const версия = `${м[1]}.${м[2]}.${м[3]}`
    const дата = гит(["log", "-1", "--format=%ad", "--date=short", строка.trim()]).trim()
    найдено.push({ версия, тег: строка.trim(), дата })
  }
  return найдено.sort((а, б) => поВерсии(а.версия, б.версия))
}

/* ── Заметки ─────────────────────────────────────────────────────────────── */

export function заметки() {
  const прочитано = JSON.parse(readFileSync(ПУТЬ_ЗАМЕТОК, "utf8"))
  if (прочитано.формат !== ФОРМАТ) {
    throw new Error(`docs/release-notes.json написан в формате ${прочитано.формат}, а ждали ${ФОРМАТ}`)
  }
  return прочитано.выпуски
}

/* ── Печать ──────────────────────────────────────────────────────────────── */

const МЕСЯЦЫ = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
]
const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
]

/** «2026-08-18» → «18 августа 2026» / «18 August 2026». Без обращения ко времени. */
export function датой(дата, язык) {
  const м = /^(\d{4})-(\d{2})-(\d{2})$/u.exec(дата)
  if (!м) return дата
  const день = Number(м[3])
  const месяц = язык === "en" ? MONTHS[Number(м[2]) - 1] : МЕСЯЦЫ[Number(м[2]) - 1]
  return `${день} ${месяц} ${м[1]}`
}

const ЯЩИКИ = ["появилось", "изменилось", "сломалось"]

const СЛОВА = {
  ru: {
    заголовок: "Выпуски",
    вступление:
      "Выпуск — это тег `vX.Y.Z`, а по нему архив и публикация пакета. " +
      "Страница печатается из тегов: сколько тегов, столько записей, пропустить выпуск нельзя.",
    ящики: "Ящика три: **что появилось**, **что изменилось**, **что сломалось**. Пустой ящик не печатается — «сломалось: ничего» на девяти выпусках подряд читателю ничего не сообщает.",
    подписи: { появилось: "Что появилось", изменилось: "Что изменилось", сломалось: "Что сломалось" },
    хвост:
      "Записи ниже написаны про язык, а не про работу над ним. Что приехало в ствол после " +
      "последнего выпуска, показывает [журнал вливаний](changelog.html); заголовки всех " +
      "коммитов — [журнал коммитов](journal.html).",
  },
  en: {
    заголовок: "Releases",
    вступление:
      "A release is a `vX.Y.Z` tag, and behind it an archive and a package publication. " +
      "This page is printed from the tags: as many entries as there are tags, and a release cannot be skipped.",
    ящики: "There are three boxes: **what appeared**, **what changed**, **what broke**. An empty box is not printed — \"broke: nothing\" nine releases in a row tells the reader nothing.",
    подписи: { появилось: "What appeared", изменилось: "What changed", сломалось: "What broke" },
    // `../` — потому что английская страница лежит в `en/`, а обоих журналов
    // английской половины нет: они печатаются из истории и не переводятся.
    хвост:
      "The entries below are about the language, not about the work on it. What has landed on " +
      "the trunk since the last release is shown by the [merge journal](../changelog.html) " +
      "(in Russian); every commit subject is in the [commit journal](../journal.html).",
  },
}

export function печать(язык, список, тексты) {
  const сл = СЛОВА[язык]
  const из = []
  const строка = (с = "") => из.push(с)

  строка(`# ${сл.заголовок}`)
  строка()
  строка(сл.вступление)
  строка()
  строка(сл.ящики)
  строка()
  строка(сл.хвост)
  строка()

  for (const выпуск of список) {
    const текст = тексты[выпуск.версия]?.[язык]
    строка(`## ${выпуск.версия} — ${датой(выпуск.дата, язык)}`)
    строка()
    if (текст.заголовок) {
      строка(`**${текст.заголовок}**`)
      строка()
    }
    for (const ящик of ЯЩИКИ) {
      const записи = текст[ящик] ?? []
      if (!записи.length) continue
      строка(`### ${сл.подписи[ящик]}`)
      строка()
      for (const з of записи) строка(`- ${з}`)
      строка()
    }
  }

  return из.join("\n").replace(/\n+$/u, "\n")
}

/* ── Сверка и запуск ─────────────────────────────────────────────────────── */

/** Тег без заметки и заметка без тега — обе беды, и обе называются поимённо. */
export function несоответствия(список, тексты) {
  const беды = []
  const естьТег = new Set(список.map((в) => в.версия))
  for (const в of список) {
    const т = тексты[в.версия]
    if (!т) {
      беды.push(`выпуск ${в.версия} есть тегом, а заметки о нём нет в docs/release-notes.json`)
      continue
    }
    for (const язык of ["ru", "en"]) {
      if (!т[язык]) беды.push(`у выпуска ${в.версия} нет половины «${язык}»`)
      else if (!ЯЩИКИ.some((я) => (т[язык][я] ?? []).length)) {
        беды.push(`у выпуска ${в.версия} половина «${язык}» пуста во всех трёх ящиках`)
      }
    }
  }
  for (const версия of Object.keys(тексты)) {
    if (!естьТег.has(версия)) беды.push(`заметка о выпуске ${версия} есть, а тега v${версия} в дереве нет`)
  }
  return беды
}

/**
 * Вся ли история под рукой. В клоне без тегов сверять не с чем, и краснеть за
 * это — красить чужую беду: та же оговорка стоит у журнала вливаний.
 */
function теговХватает(список, тексты) {
  return список.length >= Object.keys(тексты).length
}

function напечатать() {
  const тексты = заметки()
  const список = выпуски()
  const беды = несоответствия(список, тексты)
  if (беды.length) {
    console.error("Страница «Выпуски» не печатается:")
    for (const б of беды) console.error("  ✗ " + б)
    return 1
  }
  for (const язык of ["ru", "en"]) writeFileSync(ПУТИ[язык], печать(язык, список, тексты))
  console.log(`Напечатано: выпусков ${список.length}.`)
  return 0
}

function сверить() {
  const тексты = заметки()
  const список = выпуски()
  if (!теговХватает(список, тексты)) {
    console.log(`Сверка пропущена: тегов видно ${список.length}, заметок ${Object.keys(тексты).length} — клон без тегов.`)
    return 0
  }
  const беды = несоответствия(список, тексты)
  for (const язык of ["ru", "en"]) {
    if (readFileSync(ПУТИ[язык], "utf8") !== печать(язык, список, тексты)) {
      беды.push(`${язык === "ru" ? "releases.ru.md" : "releases.md"} разошёлся с тегами и заметками`)
    }
  }
  if (беды.length) {
    console.error("Страница «Выпуски» разошлась с деревом:")
    for (const б of беды) console.error("  ✗ " + б)
    console.error("\nЛечится одной командой: node scripts/build-releases-page.mjs")
    return 1
  }
  console.log(`Сверка прошла: выпусков ${список.length}, расхождений 0.`)
  return 0
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exit(process.argv.includes("--check") ? сверить() : напечатать())
}
