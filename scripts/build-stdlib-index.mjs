/**
 * Указатель стандартной библиотеки — печатается из самих модулей.
 *
 * ПОЧЕМУ НЕ НАПИСАН РУКАМИ. За один день в этом репозитории шесть раз
 * выяснилось, что прозаическое утверждение о коде пережило сам код: список
 * недостач наполовину состоял из починенного, шапка модуля описывала
 * ограничение, которого больше нет, комментарий про восемь бэкендов устарел
 * через час. Причина всегда одна — текст не исполняется, поэтому не ломается.
 *
 * Указатель библиотеки — ровно такой текст, и написанный руками он разошёлся бы
 * с кодом при первой же новой функции. Поэтому он ПЕЧАТАЕТСЯ отсюда, а
 * flang/test/stdlib-index.test.mjs требует, чтобы записанный файл совпадал с
 * напечатанным. Добавил функцию, не перепечатав указатель, — тест краснеет.
 *
 * Запуск: node scripts/build-stdlib-index.mjs        (печатает и записывает)
 *         node scripts/build-stdlib-index.mjs --check (только сверяет)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath, pathToFileURL } from "node:url"

import { parse } from "../flang/src/parser.mjs"

const КАТАЛОГ = fileURLToPath(new URL("../flang/stdlib/", import.meta.url))
const ФАЙЛ = fileURLToPath(new URL("../flang/stdlib/README.md", import.meta.url))

/*
 * Имя типа так, как его пишет автор в исходнике, а не так, как он назван в
 * дереве разбора. Разница не косметическая: указатель читает тот, кто будет
 * писать на языке, и «flag» вместо «признак» отправит его искать несуществующее
 * слово. Список требует родительного падежа — «список строки», а не «список
 * строка», — поэтому падежей два.
 */
const ИМЕНИТЕЛЬНЫЙ = new Map([
  ["string", "строка"],
  ["number", "число"],
  ["flag", "признак"],
  ["boolean", "признак"],
  ["null", "ничего"],
])

const РОДИТЕЛЬНЫЙ = new Map([
  ["string", "строки"],
  ["number", "числа"],
  ["flag", "признака"],
  ["boolean", "признака"],
  ["null", "ничего"],
])

function имяТипа(тип, падеж = ИМЕНИТЕЛЬНЫЙ) {
  if (!тип) return "—"
  if (тип.kind === "named") return `«${тип.name}»${аргументыТипа(тип)}`
  if (тип.kind === "list") return `список ${имяТипа(тип.of, РОДИТЕЛЬНЫЙ)}`
  if (тип.kind === "fn") return типФункции(тип)
  return падеж.get(тип.kind) ?? тип.name ?? тип.kind
}

/*
 * Аргументы применения — «Возможно» от числа, тем же оборотом, каким тип
 * пишется в исходнике (typeName в src/types.mjs печатает его так же).
 *
 * Без них указатель врал бы молча, и это не гипотеза: «Умножить значение»
 * принимает «Возможно» ОТ ЧИСЛА, а «Значение или запасное» — «Возможно» от «А»,
 * и после схлопывания типов (фаза 5 в flang/cat/POLY.md) обе строки печатались
 * бы одинаково — «опция: «Возможно»». Читатель указателя решил бы, что первая
 * тоже работает над любым типом.
 */
function аргументыТипа(тип) {
  const аргументы = тип.args ?? []
  if (аргументы.length === 0) return ""
  return ` от ${аргументы.map((аргумент) => имяТипа(аргумент, РОДИТЕЛЬНЫЙ)).join(" и ")}`
}

/*
 * Тип функции читается так же, как пишется: «функция из числа и числа в число».
 * До этой правки в указателе стояло `ф: fn` — ровно та беда, ради которой
 * заведены оба падежа выше: имя из дерева разбора вместо слова языка.
 */
function типФункции(тип) {
  const принимает = (тип.params ?? []).map((параметр) => имяТипа(параметр, РОДИТЕЛЬНЫЙ))
  const из = принимает.length === 0 ? "" : ` из ${принимает.join(" и ")}`
  /* «в строку», а не «в строка»: после `в` идёт винительный, и среди скаляров
     он отличается только у строки — то же правило в `accusative` (types.mjs). */
  const возвращает = тип.returns?.kind === "string" ? "строку" : имяТипа(тип.returns)
  return `функция${из} в ${возвращает}`
}

/** Параметры объявления: `от «А» и «Б»` — там, где они введены. */
const параметрыТипа = (объявление) =>
  (объявление.typeParams ?? []).length === 0
    ? ""
    : ` от ${объявление.typeParams.map((имя) => `«${имя}»`).join(" и ")}`

/**
 * Первая строка шапки модуля — та, что стоит до первой пустой строки
 * комментария. Именно она отвечает на вопрос «что это вообще такое», и только
 * она попадает в указатель: остальное объяснение живёт в самом модуле, где ему
 * и место.
 */
function первыйАбзац(исходник) {
  const строки = исходник.split("\n")
  const собранное = []
  for (const строка of строки) {
    const текст = строка.trim()
    if (текст.startsWith("модуль ")) continue
    if (текст === "") {
      if (собранное.length > 0) break
      continue
    }
    if (!текст.startsWith("//")) break
    const без = текст.replace(/^\/\/\s?/u, "")
    if (без === "") {
      if (собранное.length > 0) break
      continue
    }
    собранное.push(без)
  }
  return собранное.join(" ").trim()
}

export function собратьУказатель() {
  const файлы = readdirSync(КАТАЛОГ)
    .filter((имя) => имя.endsWith(".flang"))
    .sort()

  const части = [
    "# Стандартная библиотека flang",
    "",
    "<!-- Файл печатается `node scripts/build-stdlib-index.mjs` из самих модулей.",
    "     Править его руками бессмысленно: `flang/test/stdlib-index.test.mjs`",
    "     сверяет записанное с напечатанным и покраснеет при первом расхождении.",
    "     Меняйте модуль и перепечатывайте указатель. -->",
    "",
    "Всё, что здесь перечислено, написано на самом flang и проверяется тем же",
    "конвейером, что любая программа: разбор → типы → тотальность → примеры.",
    "Пометка «тотальная» означает, что завершение ДОКАЗАНО компилятором, а не",
    "обещано автором.",
    "",
  ]

  let всегоФункций = 0
  let всегоПримеров = 0
  const оглавление = []
  const разделы = []

  for (const файл of файлы) {
    const исходник = readFileSync(КАТАЛОГ + файл, "utf8")
    const программа = parse(исходник, файл)
    const якорь = программа.module.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "-")
    оглавление.push(`- [${программа.module}](#${якорь}) — \`${файл}\`, функций: ${программа.functions.length}`)

    const раздел = [`## ${программа.module}`, "", `Файл: \`flang/stdlib/${файл}\``, ""]
    const описание = первыйАбзац(исходник)
    if (описание) раздел.push(описание, "")

    if ((программа.types ?? []).length > 0) {
      раздел.push("Типы:", "")
      for (const тип of программа.types) {
        const варианты = (тип.variants ?? []).map((в) => `«${в.name}»`).join(", ")
        раздел.push(`- «${тип.name}»${параметрыТипа(тип)}${варианты ? ` — варианты: ${варианты}` : ""}`)
      }
      раздел.push("")
    }

    раздел.push("| функция | принимает | возвращает | примеров |", "| --- | --- | --- | --- |")
    for (const функция of программа.functions) {
      всегоФункций += 1
      const примеров = (функция.examples ?? []).length
      всегоПримеров += примеров
      const принимает =
        (функция.params ?? []).map((п) => `${п.name}: ${имяТипа(п.type)}`).join(", ") || "—"
      раздел.push(
        `| «${функция.name}»${параметрыТипа(функция)}${функция.total ? "" : " (не тотальная)"} | ${принимает} | ${имяТипа(функция.returns)} | ${примеров} |`,
      )
    }
    раздел.push("")
    разделы.push(раздел.join("\n"))
  }

  части.push(
    `Модулей: ${файлы.length}. Функций: ${всегоФункций}. Примеров: ${всегоПримеров}.`,
    "",
    "## Содержание",
    "",
    ...оглавление,
    "",
    ...разделы,
  )
  return части.join("\n").replace(/\n{3,}/gu, "\n\n").trimEnd() + "\n"
}

export const ПУТЬ_УКАЗАТЕЛЯ = ФАЙЛ

/* Печать — только при прямом запуске. Тест импортирует отсюда «собратьУказатель»
   и записанный путь; выполняйся печать при импорте, тест переписывал бы файл,
   который проверяет, и всегда был бы зелёным. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const указатель = собратьУказатель()
  if (process.argv.includes("--check")) {
    if (readFileSync(ФАЙЛ, "utf8") !== указатель) {
      console.error("указатель библиотеки разошёлся с модулями — перепечатайте его:")
      console.error("  node scripts/build-stdlib-index.mjs")
      process.exit(1)
    }
    console.log("указатель библиотеки совпадает с модулями")
  } else {
    writeFileSync(ФАЙЛ, указатель)
    console.log(`указатель напечатан: ${ФАЙЛ}`)
  }
}
