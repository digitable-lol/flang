#!/bin/sh
# Вся ли работа ячеек забрана в хранилище — или живёт только во временном каталоге.
#
# ЗАЧЕМ. 2 сентября 2026 замер дал: клонов ячеек с гитом 119, вершина есть в
# хранилище у 47, НЕТ у 72 — то есть 61 % работы жил только в /srv/tmp. Среди
# потерянных был прибор доли корпуса, которым меряется Г4, и коммиты-родители
# четырёх приборов, которых `git cat-file` не знал вовсе. В ту же ночь двенадцать
# ячеек умерли разом от предела сессии; их клоны уцелели случайно, а не по
# устройству. Разбор — tasks/9615.
#
# Правило оттуда: число, полученное прибором вне хранилища, — не замер, а слух.
#
# ЧТО ДЕЛАЕТ. Обходит клоны ячеек, спрашивает у хранилища, знает ли оно их
# вершину, и забирает незнакомые в refs/ячейки/<ячейка>/<ветка>. Это НЕ слияние
# и НЕ выкладывание: ни одна ветка не двигается, ни один коммит не вливается —
# забираются только объекты, чтобы их нельзя было потерять.
#
# Звать:
#   sh scripts/cell-work-preserved.sh              забрать незабранное
#   sh scripts/cell-work-preserved.sh --спросить   только спросить, ничего не брать
#
# Каталог ячеек берётся из FLANG_CELLS (по умолчанию /srv/tmp/dokazuemyy).
#
# КОДЫ ВОЗВРАТА. «Плохо» и «не проверено» — разное, и здесь это важнее обычного:
# сторож сохранности, молчащий оттого, что ему нечего смотреть, вреднее всего.
#   0  вся работа ячеек в хранилище
#   1  есть незабранная работа (в режиме --спросить), либо забрать не удалось
#   3  НЕ ПРОВЕРЕНО: каталога ячеек нет, или это не хранилище git
#   2  звать не умеют
set -u

# Имена переменных ЛАТИНИЦЕЙ: ни dash, ни bash не принимают кириллицу в именах
# (о том же — шапка scripts/raskrutka.sh). Ошибка эта молчаливая: `sh -n` её не
# ловит, строка разбирается как имя команды и падает только на прогоне.
CELLS=${FLANG_CELLS:-/srv/tmp/dokazuemyy}
ROOT=$(cd "$(dirname "$0")/.." 2>/dev/null && pwd) || ROOT=

SPROSIT=0
case "${1:-}" in
  '') ;;
  --спросить|--sprosit) SPROSIT=1 ;;
  *) echo "звать: sh scripts/cell-work-preserved.sh [--спросить]" >&2; exit 2 ;;
esac

# ХРАНИЛИЩЕ СПРАШИВАЕТСЯ У git, А НЕ У ФАЙЛОВОЙ СИСТЕМЫ. Проверка `[ -d .git ]`
# кажется очевидной и неверна: в рабочей выкладке (`git worktree`) `.git` — ФАЙЛ,
# а не каталог, и такой сторож отвечает «нет хранилища» на совершенно здоровом
# дереве. Это красное не по своему предмету: спрашивали про сохранность работы,
# ответили про вид файла. Поймано прогоном на выкладке ствола 2 сентября 2026.
[ -n "$ROOT" ] && /usr/bin/git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 || {
  echo "НЕ ПРОВЕРЕНО: рядом со скриптом нет хранилища git — $ROOT" >&2; exit 3; }
[ -d "$CELLS" ] || {
  echo "НЕ ПРОВЕРЕНО: каталога ячеек нет — $CELLS" >&2; exit 3; }

vsego=0; bylo=0; vzyato=0; ne_vzyato=0; spisok=''
for kl in "$CELLS"/Ч*/клон; do
  [ -d "$kl/.git" ] || continue
  vsego=$((vsego + 1))
  yach=$(basename "$(dirname "$kl")")
  t=$(/usr/bin/git -C "$kl" rev-parse HEAD 2>/dev/null) || continue
  if /usr/bin/git -C "$ROOT" cat-file -e "$t" 2>/dev/null; then
    bylo=$((bylo + 1)); continue
  fi
  vetka=$(/usr/bin/git -C "$kl" rev-parse --abbrev-ref HEAD 2>/dev/null)
  [ "$vetka" = HEAD ] && vetka="отцеплённая-$(echo "$t" | cut -c1-8)"
  if [ "$SPROSIT" = 1 ]; then
    ne_vzyato=$((ne_vzyato + 1)); spisok="$spisok
  $yach  $(echo "$t" | cut -c1-8)  $vetka"
    continue
  fi
  if /usr/bin/git -C "$ROOT" -c core.quotepath=false \
       fetch -q "$kl" "+HEAD:refs/ячейки/$yach/$vetka" 2>/dev/null; then
    vzyato=$((vzyato + 1))
  else
    ne_vzyato=$((ne_vzyato + 1)); spisok="$spisok
  $yach  $(echo "$t" | cut -c1-8)  $vetka  — ЗАБРАТЬ НЕ УДАЛОСЬ"
  fi
done

if [ "$vsego" -eq 0 ]; then
  echo "НЕ ПРОВЕРЕНО: в $CELLS нет ни одного клона ячейки — смотреть нечего" >&2
  echo "Это НЕ «всё сохранено»: пустой список и порядок неотличимы, если молчать." >&2
  exit 3
fi

echo "работа ячеек: клонов $vsego, было в хранилище $bylo, забрано сейчас $vzyato"
if [ "$ne_vzyato" -gt 0 ]; then
  if [ "$SPROSIT" = 1 ]; then
    echo "НЕ В ХРАНИЛИЩЕ: $ne_vzyato — их работа живёт только во временном каталоге:$spisok"
    echo "Забрать: sh scripts/cell-work-preserved.sh"
  else
    echo "ЗАБРАТЬ НЕ УДАЛОСЬ: $ne_vzyato$spisok"
  fi
  exit 1
fi
echo "вся работа ячеек в хранилище — потерять нечего"
exit 0
