# ЧТО ИМЕННО есть в исходнике и ещё нет в семени — поимённо, по функциям.
#
#   sh scripts/chto-otstalo-ot-semeni.sh            # сводка по файлам
#   sh scripts/chto-otstalo-ot-semeni.sh <файл>     # имена по одному файлу
#
# ── Чем это НЕ является ──────────────────────────────────────────────────────
# Это НЕ сторож свежести семени. Тот уже есть, работает и вшит в оболочку
# `ярлык`: scripts/seed-freshness.sh отвечает кодом 3 «сверить не удалось» и
# кодом 1 «отстало», и `./ярлык доказанное:проверка` через него не проходит.
# Этот прибор кода не даёт вовсе (всегда 0) и ничего не блокирует.
#
# Он отвечает на ДРУГОЙ вопрос. Сторож говорит «семя отстало» — да или нет.
# Здесь: «отстало ЧЕМ, назови поимённо». Разница не косметическая: 5 сентября
# 2026 четыре разбора подряд пришли к неверному выводу, и каждый раз потому,
# что правка была в исходнике и отсутствовала в семени, а узнать это можно было
# только гребом наугад по имени, которое ты уже подозреваешь:
#
#   9985  починка ключа кеша «Значение без мест рекурсивно» — 1 функция;
#         из-за неё все замеры кеша мерили СТАРЫЙ ключ;
#   9996  кеш казался объяснением разброса печатей, пока не выяснилось,
#         что его нет НИ В ОДНОМ из двух сёмен;
#   9997  печать «Строки объявленного правила» написана и вызывается —
#         1 функция, и её нет в семени; «никто её не видел» об этом;
#   10004 в шапке сторожа стояло «девятая цель ещё не перепечатана» —
#         семя перепечатали, примечание протухло молча.
#
# Обе беды, стоившие выводов, были размером в ОДНУ функцию: proofterm.flang 1
# из 287, zapis.flang 1 из 86. Сторож про такое говорит «отстало» — верно, но
# не помогает: отстало и без того почти всё, вопрос был какой именно правкой.
#
# ── Почему счёт идёт по ИМЕНАМ ФУНКЦИЙ, а не гребом фразы ────────────────────
# Греб фразы врёт, и это проверено на себе: `grep -ac 'по объявлению'` по семени
# даёт 54 попадания, из которых НИ ОДНО не есть искомая печать — это имена
# чужих теорем («Запись входа по объявлению» и подобные). Имя функции в ёлочках
# однозначно: печатник кладёт его в семя дословно.
#
# ── Чего прибор НЕ различает, и это важно ────────────────────────────────────
# Отсутствие имени в семени значит одно из двух, и он их НЕ РАЗДЕЛЯЕТ:
#   • функция новее семени (настоящее отставание), либо
#   • файл вообще не входит в замыкание компилятора — тогда его функций в
#     семени нет и не должно быть.
# Второе видно по доле: у файла вне замыкания отсутствует почти всё (conc.flang
# 220 из 237, sets.flang 88 из 90). Порог 80 % разделяет их в сводке — он
# подобран по сегодняшнему дереву и разделяет чисто: у файлов замыкания доля
# отставания 1…70 %, у файлов вне его — 88…100 %. Порог назван здесь, а не
# спрятан: если дерево сдвинется, его придётся пересмотреть.
set -u

KOREN=$(cd "$(dirname "$0")/.." && pwd)
SEMYA="$KOREN/bootstrap/compiler_flang.c"
[ -f "$SEMYA" ] || { echo "семени нет: $SEMYA" >&2; exit 2; }

ODIN=${1:-}

LC_ALL=C.UTF-8 python3 - "$KOREN" "$SEMYA" "$ODIN" <<'PY'
import re, sys, glob, os

koren, semya, odin = sys.argv[1], sys.argv[2], sys.argv[3]

# Всё, что стоит в семени в ёлочках. Один проход, файл читается целиком:
# кусками нельзя — имя на границе кусков потерялось бы и дало ложное отставание.
v_semeni = set(re.findall('«([^»]{1,120})»',
                          open(semya, encoding='utf-8', errors='replace').read()))

obyavlenie = re.compile(r'^(?:тотальная |частичная )?функция «([^»]+)»', re.M)
PORAG_VNE = 0.8

fajly = [odin] if odin else sorted(glob.glob(os.path.join(koren, 'flang/self/*.flang')))
vne, otstali, celyh = [], [], 0

for put in fajly:
    if not os.path.exists(put):
        print('файла нет:', put, file=sys.stderr); sys.exit(2)
    imena = obyavlenie.findall(open(put, encoding='utf-8').read())
    if not imena:
        continue
    net = [i for i in imena if i not in v_semeni]
    imya = os.path.basename(put)
    if not net:
        celyh += 1
    elif len(net) / len(imena) > PORAG_VNE:
        vne.append((imya, len(net), len(imena)))
    else:
        otstali.append((imya, len(net), len(imena), net))

if odin:
    for imya, n, vsego, net in otstali:
        print('%s: нет в семени %d из %d' % (imya, n, vsego))
        for i in net:
            print('  •', i)
    for imya, n, vsego in vne:
        print('%s: нет в семени %d из %d — файл вне замыкания компилятора'
              % (imya, n, vsego))
    if not otstali and not vne:
        print('всё на месте: сошлись все функции')
    sys.exit(0)

print('ОТСТАВАНИЕ СЕМЕНИ ОТ ИСХОДНИКА, поимённо по функциям')
print()
print('НАСТОЯЩЕЕ ОТСТАВАНИЕ — файл в замыкании, часть функций новее семени:')
if otstali:
    for imya, n, vsego, net in sorted(otstali, key=lambda x: -x[1]):
        print('  %-28s %4d из %4d   %s' % (imya, n, vsego, ', '.join(net[:2])[:52]))
    print('  ИТОГО: файлов %d, функций %d'
          % (len(otstali), sum(n for _, n, _, _ in otstali)))
else:
    print('  нет ни одного — семя догнало исходник')
print()
print('ВНЕ ЗАМЫКАНИЯ (отсутствует больше %d %%) — НЕ отставание:' % (PORAG_VNE * 100))
print('  файлов %d, функций %d' % (len(vne), sum(n for _, n, _ in vne)))
print()
print('файлов, сошедшихся полностью: %d' % celyh)
print()
print('Свежесть семени как ДА/НЕТ — не здесь: sh scripts/seed-freshness.sh')
PY
