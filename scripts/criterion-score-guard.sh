# Счёт «ВЗЯТО N ИЗ M» в документе-критерии пересчитывается по его же таблице.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# Заголовок «ВЗЯТО 2 ИЗ 7» — число, набранное руками, а рядом лежит таблица, из
# которой оно вычисляется целиком. Стоит одному ряду сменить состояние — и
# заголовок лжёт, а сказать об этом некому: заголовок с таблицей ничем не
# связан, кроме памяти писавшего. Здесь связь появляется.
#
# ── Что сверяется ────────────────────────────────────────────────────────────
#   • рядов в таблице ровно M;
#   • ряды пронумерованы Г1…ГM без пропусков и без повторов;
#   • рядов, чьё состояние — «взят» (а не «не взят» и не «снят»), ровно N.
#
# Слово «взят» узнаётся так: в ячейке состояния есть «взят» и НЕТ ни «не взят»,
# ни «снят», ни «пал». Ячейка, которую этим правилом не разобрать, красит сама:
# состояние гейта, которое нечем прочитать прогоном, — то же самое число из
# памяти.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/criterion-score-guard.sh ФАЙЛ
#
# Код 0 — заголовок сошёлся с таблицей. Код 1 — названо, что с чем разошлось.

set -eu

[ $# -eq 1 ] || { sed -n '5,27p' "$0"; exit 2; }
DOC=$1
[ -f "$DOC" ] || { printf 'нет файла %s\n' "$DOC" >&2; exit 2; }

LC_ALL=C.UTF-8 gawk '
  # Заголовок со счётом: «ВЗЯТО 2 ИЗ 7»
  /ВЗЯТО[ ]+[0-9]+[ ]+ИЗ[ ]+[0-9]+/ {
    if (match($0, /ВЗЯТО[ ]+[0-9]+[ ]+ИЗ[ ]+[0-9]+/)) {
      head = substr($0, RSTART, RLENGTH)
      cnt = split(head, num, /[^0-9]+/)
      k = 0
      for (i = 1; i <= cnt; i++) if (num[i] != "") { k++; if (k == 1) said_taken = num[i] + 0; else if (k == 2) said_all = num[i] + 0 }
      score_line = FNR
    }
  }
  # Ряд таблицы: | **Г3** имя | состояние | довод |
  /^\|[ ]*\*\*Г[0-9]+\*\*/ {
    if (match($0, /Г[0-9]+/)) g = substr($0, RSTART + 1, RLENGTH - 1) + 0
    split($0, fld, "|")
    st = fld[3]
    if (g in seen) { dup = dup " Г" g } else { seen[g] = FNR }
    rows++
    if (g > maxg) maxg = g
    yes = (st ~ /взят/)
    no  = (st ~ /не[ ]+взят/ || st ~ /СНЯТ/ || st ~ /снят/ || st ~ /пал/)
    if (yes && !no) { taken++; which = which " Г" g }
    else if (!yes && !no) { unreadable = unreadable " Г" g ":" FNR }
  }
  END {
    bad = 0
    if (score_line == 0) { print "в документе нет заголовка вида «ВЗЯТО N ИЗ M»" > "/dev/stderr"; exit 1 }
    if (rows != said_all) {
      bad++
      printf "%s:%d  заголовок говорит «из %d», а рядов в таблице %d\n", DOC, score_line, said_all, rows > "/dev/stderr"
    }
    for (i = 1; i <= said_all; i++) if (!(i in seen)) {
      bad++
      printf "%s:%d  ряда Г%d в таблице нет вовсе\n", DOC, score_line, i > "/dev/stderr"
    }
    if (dup != "") { bad++; printf "%s  ряд назван дважды:%s\n", DOC, dup > "/dev/stderr" }
    if (unreadable != "") {
      bad++
      printf "%s  состояние не разобрать прогоном (ни «взят», ни отрицание):%s\n", DOC, unreadable > "/dev/stderr"
    }
    if (taken != said_taken) {
      bad++
      printf "%s:%d  заголовок говорит «взято %d», таблица даёт %d —%s\n", DOC, score_line, said_taken, taken, (which == "" ? " ни одного" : which) > "/dev/stderr"
    }
    if (bad > 0) {
      printf "\nсчёт критерия: рядов %d, взято по таблице %d, расхождений %d\n", rows, taken, bad > "/dev/stderr"
      exit 1
    }
    printf "счёт критерия сошёлся: взято %d из %d, ряды Г1…Г%d на месте\n", taken, rows, maxg
  }
' DOC="$DOC" "$DOC"
