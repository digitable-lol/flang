# НАСТРОЙКИ ЧИТАЮТСЯ ТОЛЬКО ИЗ ДОЗВОЛЕННЫХ МЕСТ — проверка прогоном.
#
#   sh scripts/flangrc-guard.sh                    судить это дерево
#   sh scripts/flangrc-guard.sh --подлог           проба порчи: краснеет ли он вообще
#   sh scripts/flangrc-guard.sh --корень DIR       судить названное дерево
#   sh scripts/flangrc-guard.sh --читатель FILE    судить названного читателя
#
# Код 0 — оба обещания держатся; 1 — какое-то нарушено, и нарушение названо
# путями: что взято и что этим перекрыто.
#
# ── Два обещания, и они разные ──────────────────────────────────────────────
#
#   1. ВЫШЕ КОРНЯ НЕ СМОТРИМ. Ни один просмотренный каталог не лежит выше корня
#      проекта. Исключение ровно одно и оно названо: дом человека — место
#      именованное, а не найденное подъёмом.
#   2. БЛИЖНИЙ БЬЁТ ДАЛЬНИЙ. Из двух файлов настроек на одной ветке каталогов
#      побеждает тот, что ближе к началу поиска.
#
# Второе без первого ничего не стоит: поиск, не знающий границы, «ближайший»
# найдёт и за пределами дерева.
#
# ── Зачем это вообще ────────────────────────────────────────────────────────
# Поиск МОДУЛЕЙ обоих обещаний не держит, и это стоило беды: 8 сентября 2026
# сборка сайта взяла модуль «JSON» из чужого черновика выше корня репозитория и
# ответила кодом 0 (задача 3127). Настройки задевают больше модуля: подменённый
# `.flangrc` меняет язык, которым программа отвечает человеку, а такую подмену
# не видно ни в одном диффе.
#
# ── Почему это НЕ на flang ──────────────────────────────────────────────────
# По той же причине, что и `scripts/module-origin-guard.sh`: сторож на flang,
# лежащий в `scripts/`, ввозит соседей ПО ИМЕНИ и ищется тем же подъёмом
# вверх — то есть его самого можно подменить черновиком из общей зоны. Вторая
# причина — цена: сторож нужен и тогда, когда `bootstrap/flang` не собран.
# Здесь двоичный не зовётся вовсе: судится ВЫВОД читателя `--места`, а он
# считается одной оболочкой.
set -eu

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$KOREN"

SUD=$KOREN
CHITATEL=$KOREN/scripts/flangrc.sh
PODLOG=net

while [ $# -gt 0 ]; do
  case $1 in
    --корень) SUD=${2:?"--корень требует каталога"}; shift 2 ;;
    --читатель) CHITATEL=${2:?"--читатель требует файла"}; shift 2 ;;
    --подлог) PODLOG=da; shift ;;
    *) printf 'flangrc-guard: непонятный ключ «%s»\n' "$1" >&2; exit 2 ;;
  esac
done

# ── проба порчи ─────────────────────────────────────────────────────────────
# Настоящее дерево для пробы не годится в обе стороны: покрасить его — значит
# положить файл ВЫШЕ корня, в чужую рабочую зону; позеленить — значит убрать
# оттуда чужой файл, который сторожу не принадлежит. Поэтому проба строит
# игрушечное дерево и гоняет по нему ДВУХ читателей: целого и испорченного.
if [ "$PODLOG" = da ]; then
  RAB=$(mktemp -d "${TMPDIR:-/tmp}/flangrc-podlog.XXXXXX")
  trap 'rm -rf "$RAB"' EXIT INT TERM
  mkdir -p "$RAB/над/дерево/src" "$RAB/над/дом"
  # `.git` — примета корня игрушечного дерева. Без неё подъём ушёл бы вверх по
  # `/tmp`, где на этой машине лежит `/tmp/.git`, и проба судила бы не то.
  mkdir -p "$RAB/над/дерево/.git"
  printf 'язык = clingon\n' > "$RAB/над/чужой.flangrc"
  cp "$RAB/над/чужой.flangrc" "$RAB/над/.flangrc"

  # ИСПОРЧЕННЫЙ ЧИТАТЕЛЬ: у него вынут ровно обрыв подъёма на корне проекта.
  # Портится не номер строки, а названное условие целиком — съедет строка,
  # порча всё равно соберётся.
  #
  # Лежит он в ИГРУШЕЧНОМ `scripts/`, а рядом — ссылка на настоящий
  # `bootstrap/`. Без этого порченый читатель краснел бы не тем: свой корень он
  # считает от собственного пути, не нашёл бы двоичного и отказал бы ещё до
  # всякого подъёма. Проба, красная не по своему предмету, — холостая.
  mkdir -p "$RAB/дом-читателя/scripts"
  ln -s "$KOREN/bootstrap" "$RAB/дом-читателя/bootstrap"
  ln -s "$KOREN/scripts/settings-file.flang" "$RAB/дом-читателя/scripts/settings-file.flang"
  PORCHENYY_PUT=$RAB/дом-читателя/scripts/порченый.sh
  sed 's#if \[ -e "$kat/\.git" \] || \[ -f "$kat/flang\.package" \]; then#if false; then#' \
    "$CHITATEL" > "$PORCHENYY_PUT"
  if cmp -s "$CHITATEL" "$PORCHENYY_PUT"; then
    echo "ПОДЛОГ НЕ СОБРАЛСЯ: правка не изменила читателя — судить нечего" >&2
    exit 3
  fi

  set +e
  sh "$0" --корень "$RAB/над/дерево" --читатель "$CHITATEL" > "$RAB/целый.out" 2>&1
  CELYY=$?
  sh "$0" --корень "$RAB/над/дерево" --читатель "$PORCHENYY_PUT" > "$RAB/порченый.out" 2>&1
  PORCHENYY=$?
  set -e

  echo "ПРОБА ПОРЧИ: сторож мест файла настроек"
  echo
  echo "  целый читатель        код $CELYY  (ждали 0)"
  sed 's/^/    /' "$RAB/целый.out"
  echo
  echo "  читатель без обрыва   код $PORCHENYY  (ждали 1)"
  sed 's/^/    /' "$RAB/порченый.out"
  echo
  # Кода 1 мало: порченый читатель мог покраснеть по любой причине, и тогда
  # проба ничего не показала. Требуется ИМЕННО то нарушение, ради которого
  # сторож заведён, — и оно ищется в выводе словами.
  PO_DELU=net
  if grep -q "ВНЕ дерева" "$RAB/порченый.out"; then PO_DELU=da; fi
  if [ "$CELYY" = 0 ] && [ "$PORCHENYY" = 1 ] && [ "$PO_DELU" = da ]; then
    echo "проба сошлась: сторож зелен на целом и КРАСЕН на порченом — и красен по делу"
    exit 0
  fi
  if [ "$PO_DELU" = net ]; then
    echo "ПРОБА ХОЛОСТА: порченый читатель покраснел не тем — «ВНЕ дерева» в выводе нет" >&2
    exit 1
  fi
  echo "ПРОБА НЕ СОШЛАСЬ: сторож не различает целого читателя и порченого" >&2
  exit 1
fi

# ── суд над деревом ─────────────────────────────────────────────────────────
SUD=$(CDPATH= cd -- "$SUD" && pwd)
[ -f "$CHITATEL" ] || { printf 'flangrc-guard: нет читателя «%s»\n' "$CHITATEL" >&2; exit 2; }

RAB=$(mktemp -d "${TMPDIR:-/tmp}/flangrc-sud.XXXXXX")
trap 'rm -rf "$RAB"' EXIT INT TERM
DOM=$RAB/дом
mkdir -p "$DOM"

BEDA=0
echo "СТОРОЖ МЕСТ ФАЙЛА НАСТРОЕК"
printf '  дерево:   %s\n' "$SUD"
printf '  читатель: %s\n' "$CHITATEL"
echo

# ── обещание 1: выше корня не смотрим ───────────────────────────────────────
# Начала берутся не наугад: сам корень и каждый его подкаталог первого уровня,
# какие есть. Если бы судили только корень, обрыв подъёма ни разу бы не
# понадобился — он проверяется ровно там, где начало лежит ГЛУБЖЕ корня.
NACHALA=$SUD
for pod in "$SUD"/*/; do
  [ -d "$pod" ] || continue
  NACHALA="$NACHALA
${pod%/}"
done

echo "обещание 1: ни одно просмотренное место не лежит выше корня"
CHISLO_NACHAL=0
for nachalo in $NACHALA; do
  CHISLO_NACHAL=$((CHISLO_NACHAL+1))
  sh "$CHITATEL" --от "$nachalo" --дом "$DOM" --места > "$RAB/места.out" 2>"$RAB/места.err" || {
    printf '  КРАСНО  читатель отказал на начале %s\n' "$nachalo"
    sed 's/^/          /' "$RAB/места.err"
    BEDA=$((BEDA+1))
    continue
  }
  while IFS= read -r mesto; do
    case $mesto in
      остановка:*|дом:*|'') continue ;;
    esac
    case $mesto in
      "$SUD"|"$SUD"/*|"$DOM"|"$DOM"/*) ;;
      *)
        printf '  КРАСНО  начало %s: просмотрено место ВНЕ дерева — %s\n' "$nachalo" "$mesto"
        BEDA=$((BEDA+1))
        ;;
    esac
  done < "$RAB/места.out"
done
printf '  начал проверено: %s\n' "$CHISLO_NACHAL"

# ── обещание 2: ближний бьёт дальний ────────────────────────────────────────
# Судится не на настоящем дереве (класть в него файлы проверка не вправе), а на
# копии двух каталогов во временном месте. Судится ПУТЬ взятого файла, а не
# значение ключа: двоичный для этого не нужен, и проверка работает на дереве,
# где `bootstrap/flang` ещё не собран.
echo
echo "обещание 2: из двух файлов побеждает ближний к началу поиска"
mkdir -p "$RAB/дерево/вглубь/ещё" "$RAB/дерево/.git"
printf 'язык = zh\n' > "$RAB/дерево/.flangrc"
printf 'язык = eo\n' > "$RAB/дерево/вглубь/.flangrc"
OTVET=$(sh "$CHITATEL" --от "$RAB/дерево/вглубь/ещё" --дом "$DOM" --файл 2>/dev/null || true)
if [ "$OTVET" = "$RAB/дерево/вглубь/.flangrc" ]; then
  printf '  зелено  взят ближний файл: %s\n' "$OTVET"
else
  printf '  КРАСНО  дальний файл перекрыл ближний: ждали %s, взято «%s»\n' \
    "$RAB/дерево/вглубь/.flangrc" "$OTVET"
  BEDA=$((BEDA+1))
fi

# ── и та же пара, но чужой файл лежит ВЫШЕ корня ────────────────────────────
echo
echo "обещание 1, отдельно: чужой файл выше корня не берётся"
printf 'язык = clingon\n' > "$RAB/.flangrc"
rm -f "$RAB/дерево/.flangrc" "$RAB/дерево/вглубь/.flangrc"
OTVET=$(sh "$CHITATEL" --от "$RAB/дерево/вглубь/ещё" --дом "$DOM" --файл 2>/dev/null || true)
if [ -z "$OTVET" ]; then
  echo "  зелено  чужой файл выше корня не взят, проектного файла нет"
else
  printf '  КРАСНО  взято извне дерева: %s\n' "$OTVET"
  BEDA=$((BEDA+1))
fi

# ── значения, если двоичный есть ────────────────────────────────────────────
# Всё выше судит ПУТИ и обходится без двоичного. Этот кусок судит ответ
# целиком — от разбора файла до старшинства — и потому двоичного требует. Нет
# его — сказано вслух, а не пропущено молча: молчащая о своих границах проверка
# врёт самим фактом зелёного вывода.
echo
if [ -x "$KOREN/bootstrap/flang" ]; then
  echo "обещание 2, целиком: значение приезжает из ближнего файла"
  mkdir -p "$RAB/дерево/вглубь"
  printf 'язык = zh\n' > "$RAB/дерево/.flangrc"
  printf 'язык = eo\n' > "$RAB/дерево/вглубь/.flangrc"
  OTVET=$(sh "$CHITATEL" --от "$RAB/дерево/вглубь/ещё" --дом "$DOM" язык 2>/dev/null || true)
  if [ "$OTVET" = eo ]; then
    printf '  зелено  ответ «%s» — из ближнего файла\n' "$OTVET"
  else
    printf '  КРАСНО  ждали «eo», получили «%s»\n' "$OTVET"
    BEDA=$((BEDA+1))
  fi
else
  echo "НЕ ПРОВЕРЕНО: значения — нет bootstrap/flang, а собирать его эта"
  echo "  проверка не станет (5–6 минут). Пути проверены и без него."
fi

echo
if [ "$BEDA" -gt 0 ]; then
  printf 'КРАСНО: нарушений %s\n' "$BEDA" >&2
  exit 1
fi
echo "зелено: настройки читаются только из дерева и из дома, ближний файл побеждает"
exit 0
