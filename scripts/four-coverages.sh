# ЧЕТЫРЕ ПОКРЫТИЯ РАЗОМ — одним прибором, с датой и SHA.
#
#   sh scripts/four-coverages.sh
#
# ── Зачем ───────────────────────────────────────────────────────────────────
# В прозе жило ОДНО число — «650 из 650 = 100 %», — и его читали как «язык
# доказан». Оно не об этом. Пункт 11 внешнего аудита требует различать четыре
# разных покрытия и публиковать их ОТДЕЛЬНО:
#
#   1 покрытие собственных    доля мест в собственных записях доказательства
#     записей компилятора     компилятора, переигранных независимым проверяющим;
#   2 покрытие формализации   сколько правил вывода имеют лемму в Lean и
#                             сколько правил приёмка Lean не судит вовсе;
#   3 нарушения состоятельности  места, где две независимые проверки говорят
#                             разное, либо успех проверяющего не значит того,
#                             что читатель прочтёт;
#   4 покрытие трансляции     сколько опытов у сличителя перевода в C и сколько
#                             правил печати он сверяет с ИСХОДНИКОМ, а не только
#                             с протоколом.
#
# Врозь эти четыре смотрятся как одно, и высокое первое закрывает низкое
# четвёртое. Поэтому прибор печатает их ВМЕСТЕ и на одном экране.
#
# КОД ВОЗВРАТА: 0 — все четыре сняты; 2 — хоть одно снять не удалось (нет
# двоичного, нет Lean, отказал прогон). Код 1 здесь не бывает: прибор МЕРИТ, а
# не судит; порог и вердикт — дело scripts/доказуемость.sh.
#
# Имена переменных латиницей: ни dash, ни bash не принимают кириллицу в именах.
set -u

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$KOREN" || exit 2

NE_SNYATO=0
TMP=$(mktemp -d "${FLANG_TMP:-${TMPDIR:-/tmp}}/four-coverages.XXXXXX") || exit 2
trap 'rm -rf "$TMP"' EXIT INT TERM

sh "$KOREN/scripts/report-provenance.sh" || true

# ── 1. ПОКРЫТИЕ КОРПУСА ─────────────────────────────────────────────────────
# Числитель и знаменатель берутся у линейки прогоном, а не переписываются сюда.
echo "1. ПОКРЫТИЕ СОБСТВЕННЫХ ЗАПИСЕЙ ДОКАЗАТЕЛЬСТВА — доля их мест, переигранных независимым проверяющим"
LIN=$(sh flang/proof/corpus-share.sh --проигрыванием 2>&1)
DOLYA=$(printf '%s\n' "$LIN" | sed -n 's/^доля-проигрыванием = \([0-9]*\) \/ \([0-9]*\) = \([0-9.]*\) %.*/\1 из \2 = \3 %/p')
ZAPISEY=$(printf '%s\n' "$LIN" | sed -n 's/^записей в наборе  *\([0-9][0-9]*\).*/\1/p')
PORUCH=$(printf '%s\n' "$LIN" | sed -n 's/^записей в наборе.*чекер поручился \([0-9][0-9]*\),.*/\1/p')
NEDOST=$(printf '%s\n' "$LIN" | sed -n 's/^исключено мест  *\([0-9][0-9]*\).*/\1/p')
if [ -z "$DOLYA" ]; then
  echo "   НЕ СНЯТО: линейка доли не дала числа"; NE_SNYATO=1
else
  echo "   переиграно независимо        $DOLYA"
  echo "   записей в наборе             ${ZAPISEY:-?} (проверяющий поручился за ${PORUCH:-?})"
  echo "   мест вынесено из знаменателя ${NEDOST:-0} — записи, отвергнутые ЦЕЛИКОМ как заведомо ложные"
fi
# «ПРОВЕРЕНО ВПУСТУЮ»: код 0 при нуле доказанного. Число снимается тем же
# прибором, что и доля, но другим его разрезом, — поэтому отдельным прогоном.
PUSTO=$(sh flang/proof/corpus-share.sh --набор корпус 2>/dev/null \
        | sed -n 's/^ *из них ВПУСТУЮ[^	]*	\([0-9][0-9]*\).*/\1/p' | head -1)
echo "   из них ВПУСТУЮ (код 0, доказанным не числится ничего) ${PUSTO:-?}"
echo "   ЧЕГО НЕ ЗНАЧИТ: ни одной строки о ваших программах и ни одной о собранном двоичном."
echo

# ── 2. ПОКРЫТИЕ ФОРМАЛИЗАЦИИ ────────────────────────────────────────────────
# Пары «строка ведомости ↔ лемма» считаются тем же правилом, что в
# flang/proof/lean/run.sh (шаг 4): имя правила, имя с приставкой через дефис,
# у запрета — встречный пример «-запрет». Lean для этого не нужен: считается
# текст, а не доказательство. Блоки «вне приёмки» — нужен, и об этом сказано.
echo "2. ПОКРЫТИЕ ФОРМАЛИЗАЦИИ — сколько правил вывода судит второй, чужой судья (Lean 4)"
VED=flang/proof/tables/inference-rules.tsv
cat flang/proof/lean/Rules.lean flang/proof/lean/Term.lean > "$TMP/леммы.lean" 2>/dev/null
if [ ! -s "$TMP/леммы.lean" ] || [ ! -f "$VED" ]; then
  echo "   НЕ СНЯТО: нет ведомости правил либо файлов Lean"; NE_SNYATO=1
else
  awk -F'\t' '
    FNR == NR { if ($0 ~ /^theorem «/) { split($0, a, "«"); split(a[2], b, "»"); L[b[1]] = 1 } next }
    NF > 11 && $1 !~ /^#/ {
      r = $1; s++; if (index(r, "✗")) zap++; ok = 0
      if (index(r, "✗")) {
        k = r; if (!sub(/✗✗✗$/, "-запрет3", k)) if (!sub(/✗✗$/, "-запрет2", k)) sub(/✗/, "-запрет", k)
        ok = (k in L)
      } else if (r in L) ok = 1
      else for (x in L) if (index(x, r "-") == 1) { ok = 1; break }
      if (ok) e++; else net = net (net != "" ? ", " : "") r
    }
    END {
      printf "   строк перечня правил         %d (из них запретов %d — ими не выводится ничего)\n", s, zap
      printf "   имеют лемму в Lean           %d из %d%s\n", e, s, (net != "" ? " — без леммы: " net : "")
    }' "$TMP/леммы.lean" "$VED"

  # Приёмка Lean — закрытый список «правила» в Acceptance.lean. Правило вне него
  # Lean не судит: блок записи с таким шагом уходит «вне приёмки» целиком.
  awk '/^def «правила» : List/{f=1} f{buf = buf $0} f && /\]$/{print buf; exit}' \
    flang/proof/lean/Acceptance.lean | grep -o '\.«[^»]*»' | sed 's/\.«//; s/»//' \
    | LC_ALL=C sort -u > "$TMP/приёмка"
  awk -F'\t' 'NF > 11 && $1 !~ /^#/ && $1 !~ /✗/ {print $1}' "$VED" | LC_ALL=C sort -u > "$TMP/вывода"
  V_PRIEM=$(wc -l < "$TMP/приёмка" | tr -d ' ')
  V_VYVODA=$(wc -l < "$TMP/вывода" | tr -d ' ')
  VNE=$(LC_ALL=C comm -23 "$TMP/вывода" "$TMP/приёмка")
  V_VNE=$(printf '%s\n' "$VNE" | sed '/^$/d' | wc -l | tr -d ' ')
  echo "   в приёмке Lean (Acceptance.lean) $V_PRIEM правил из $V_VYVODA правил вывода"
  echo "   ВНЕ приёмки Lean              $V_VNE: $(printf '%s\n' "$VNE" | sed '/^$/d' | tr '\n' ' ')"
  echo "   блоков записи, ушедших «вне приёмки», — НЕ СНЯТО ЗДЕСЬ: нужен прогон Lean"
  echo "                                 (sh flang/proof/lean/run.sh, Lean по flang/proof/lean/lean-toolchain)"
  command -v "${LEAN:-lean}" >/dev/null 2>&1 || NE_SNYATO=1
fi
echo "   ЧЕГО НЕ ЗНАЧИТ: лемма на правило — не проверка ваших программ этим правилом."
echo

# ── 3. ИЗВЕСТНЫЕ НАРУШЕНИЯ СОСТОЯТЕЛЬНОСТИ ──────────────────────────────────
echo "3. ИЗВЕСТНЫЕ НАРУШЕНИЯ СОСТОЯТЕЛЬНОСТИ — открыто, поимённо"
NAR=flang/proof/tables/consistency-violations.tsv
if [ ! -f "$NAR" ]; then
  echo "   НЕ СНЯТО: нет $NAR"; NE_SNYATO=1
else
  awk -F'\t' '
    /^#/ { next } $1 == "ключ" { next } NF < 7 { next }
    {
      otkryto += ($7 == "открыто")
      if ($7 != "открыто") next
      printf "   · %s — %s\n", $1, $2
      printf "       где: %s\n", $3
      printf "       число: %s; чем снять: %s; задача: %s\n", $5, $4, $6
    }
    END { printf "   открытых нарушений: %d (ведомость %s)\n", otkryto+0, FILENAME }' "$NAR"
fi
echo "   ЧЕГО НЕ ЗНАЧИТ: список открытый — «других нет» он не утверждает."
echo

# ── 4. ПОКРЫТИЕ ТРАНСЛЯЦИИ ──────────────────────────────────────────────────
# Сличитель перевода (ADR-0030) переигрывает протокол печатника против
# напечатанного C. Вопрос покрытия здесь двойной: сколько ОПЫТОВ у прогона и
# сколько правил печати сверяются с ИСХОДНИКОМ, а не только с протоколом.
# Правило без якоря в исходнике сличитель проверяет «C против протокола» —
# согласованная пара может при этом расходиться с программой, которую написали.
echo "4. ПОКРЫТИЕ ТРАНСЛЯЦИИ — сверка перевода flang → C по протоколу печати (flang/translation)"
PR=flang/translation/PRINT-RULES.tsv
RUN=flang/translation/run.sh
if [ ! -f "$PR" ] || [ ! -f "$RUN" ]; then
  echo "   НЕ СНЯТО: нет $PR либо $RUN"; NE_SNYATO=1
else
  OPYTOV=$(grep -c '^opyt ' "$RUN" | tr -d ' ')
  VSEGO_PR=$(awk -F'\t' '!/^#/ && $1 != "имя" && NF {n++} END{print n+0}' "$PR")
  S_YAKOREM=$(awk -F'\t' '!/^#/ && $1 != "имя" && NF && $5 != "—" {n++} END{print n+0}' "$PR")
  BEZ_SLICH=$(awk -F'\t' '!/^#/ && $1 != "имя" && NF && $6 ~ /^НЕ переигрывается/ {n++} END{print n+0}' "$PR")
  echo "   опытов в run.sh              $OPYTOV"
  echo "   правил печати в списке       $VSEGO_PR"
  echo "   сверяются с ИСХОДНИКОМ       $S_YAKOREM из $VSEGO_PR (у остальных якоря в исходнике нет: сверка идёт C против протокола)"
  echo "   не переигрываются вовсе      $BEZ_SLICH из $VSEGO_PR (сличается только текст в составе файла)"
  ITOG=$(sh "$RUN" 2>&1 | sed -n 's/^ИТОГ: //p')
  if [ -n "$ITOG" ]; then echo "   прогон сличителя             $ITOG"
  else echo "   прогон сличителя             НЕ СНЯТ"; NE_SNYATO=1; fi
fi
echo "   ЧЕГО НЕ ЗНАЧИТ: сличитель судит ОДИН запуск печати, а не генератор кода целиком."
echo

if [ "$NE_SNYATO" -eq 0 ]; then
  echo "все четыре покрытия сняты"
  exit 0
fi
echo "СНЯТЫ НЕ ВСЕ ЧЕТЫРЕ — что и почему, названо выше строкой «НЕ СНЯТО»"
exit 2
