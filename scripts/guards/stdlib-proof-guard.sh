# ВЕДОМОСТЬ ДОКАЗАТЕЛЬСТВ СНИМАЕТСЯ С КАЖДОГО МОДУЛЯ БИБЛИОТЕКИ — прибором.
#
#   sh scripts/guards/stdlib-proof-guard.sh            сверка с ведомостью долга,
#                                                      код 1 при расхождении
#   sh scripts/guards/stdlib-proof-guard.sh --перепись  что отвечает каждый модуль,
#                                                      по строке на модуль
#   sh scripts/guards/stdlib-proof-guard.sh --скобки    дешёвая половина: искать по
#                                                      дереву ту же форму записи
#   sh scripts/guards/stdlib-proof-guard.sh --подлог    показать сторожу дерево
#                                                      из одного дурного модуля:
#                                                      обязан покраснеть (код 1)
#   sh scripts/guards/stdlib-proof-guard.sh --подлог-скобки   то же дешёвой половине
#
# ── Зачем ───────────────────────────────────────────────────────────────────
# Задача 8455. `flang check --proof flang/stdlib/math-classics.flang` выходил
# кодом 1 с ПУСТЫМ стандартным выводом: ведомости не печаталось ни строки, а в
# поток ошибок уходила одна строка про нарушенное обещание внутри самого
# компилятора. Обычный `flang check` того же файла был зелен, печать в C — тоже.
# Беда прожила незамеченной ровно потому, что НИ ОДНА проверка дерева не звала
# `--proof` по стандартной библиотеке: молчал только отчёт, и увидеть это мог
# лишь тот, кто отчёт позвал руками. Прогон 19 сентября показал, что модуля
# таких ДВА, а не один: тем же обещанием падал и `numbers.flang`.
#
# Предмет проверки — не «сколько доказано», а «ведомость вообще снимается»:
# код возврата 0 и непустой вывод. Долю доказанного меряет другой прибор
# (flang/proof/доля-корпуса.sh), и порог доли здесь ни при чём.
#
# ── ХРАПОВИК, А НЕ ПОРОГ ────────────────────────────────────────────────────
# «Код 0 у каждого» сегодня недостижимо, и молчать об этом нельзя. Модули, с
# которых ведомость не снимается, поимённо названы в ведомости долга
# scripts/ledgers/stdlib-proof-debt.tsv — с кодом и причиной. Сторож краснеет
# в ОБЕ стороны:
#
#   ПРИБАВИЛОСЬ — модуль отказал, а в ведомости долга его нет. Это новая беда.
#   НАДГРОБИЕ   — модуль в ведомости, а ведомость с него снимается. Долг закрыт,
#                 запись осталась: убрать строку, иначе она глушит проверку.
#
# Молчаливо расширять список допустимых кодов нечем: код 3 («НЕ ПРОВЕРЕНО —
# объявлено, не доказано N») здесь такой же отказ, как код 1.
#
# ── ДВЕ ПОЛОВИНЫ, И ОБЕ НУЖНЫ ───────────────────────────────────────────────
# `--скобки` — дешёвая (секунда, двоичного не надо): ищет по всем `.flang` и
# `.fscript` дерева форму `А или Б и притом В` без внешних скобок. `или` слабее
# `и притом` (уровни расписаны в parser.flang), поэтому такая запись читается
# `А или (Б и притом В)`, первая ветка отвечает за всё выражение, и ни разбор,
# ни типы на это не краснеют: беда всплывает проверкой при работе — то есть в
# чужой программе. Поверка прибора: на дереве до правки задачи 8455 он находит
# ровно одно место (zapis.flang:759), после правки — ноль.
#
# `--check` — дорогая: настоящий прогон `--proof`. Дешёвая половина ловит форму
# записи и стоит в хуке перед пушем; дорогая ловит ЛЮБУЮ беду отчёта и стоит в
# работе CI по расписанию.
#
# ── Цена ────────────────────────────────────────────────────────────────────
# Замер своим прогоном — в шапке .github/workflows/stdlib-proof.yml. Дороже
# пяти минут стенного времени вместе со сборкой семени, поэтому место сторожа —
# работа CI по расписанию, а НЕ хук перед пушем.
#
# ── ПОЧЕМУ ОБОЛОЧКА, А НЕ ПЛАН НА FLANG ─────────────────────────────────────
# Дерево не любит новых файлов вне flang и считает их отдельным долгом
# (docs/tree-inventory.md, потолок 63 файла; к этой работе долг уже 102, и
# `./ярлык опись:языки` из-за этого отказывается перепечатывать таблицу —
# состояние досталось по наследству, не заведено здесь). Этот файл прибавляет
# к долгу единицу, и довод такой.
#
# Прогон ОБЯЗАН идти разом. Замер 19 сентября 2026: 51 модуль по одному —
# 210 808 с машинного времени, то есть 58 часов. По восемь разом это
# укладывается в десятки минут. План на flang ведёт шаги ПО ОДНОМУ
# (`corpus-runner.fscript` — образец), и переписать сюда его значило бы
# получить проверку, которую нельзя позвать ни по расписанию, ни руками.
# Дешёвая половина (`--скобки`) плану поддалась бы, но разносить один сторож
# по двум языкам дороже, чем держать его в одном.
#
# ИМЕНА ПЕРЕМЕННЫХ ЛАТИНИЦЕЙ: ни dash, ни bash не принимают кириллицу в именах.
set -u

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
KATALOG=${KATALOG:-$KOREN/flang/stdlib}
VEDOMOST=${VEDOMOST:-$KOREN/scripts/ledgers/stdlib-proof-debt.tsv}
DEREVO=${DEREVO:-$KOREN}
PARALLEL=${PARALLEL:-8}
export LC_ALL=C.UTF-8
REZHIM=${1:---check}

# Каталог под временное: у раннера GitHub нет /srv/tmp, и молчаливый отказ
# mktemp вышел бы «сторож не смог посмотреть» на ровном месте. Работы CI
# передают FLANG_TMP=${{ runner.temp }}; это — запас на случай, если забудут.
VREMENNO=${FLANG_TMP:-/srv/tmp}
[ -d "$VREMENNO" ] || VREMENNO=${TMPDIR:-/tmp}

# Двоичный нужен не всякому режиму: дешёвая половина (--скобки) читает
# исходники и обходится python3. Требовать двоичного у неё значило бы выгнать
# её из хука перед пушем, где двоичного может не быть вовсе.
nuzhen_dvoichnyy() {
  [ -x "$FLANG" ] || { echo "нет двоичного: $FLANG — соберите: make -C bootstrap" >&2; exit 2; }
  [ -d "$KATALOG" ] || { echo "нет каталога библиотеки: $KATALOG" >&2; exit 2; }
}

# Прогон: печатает в $1 строки «модуль<TAB>код<TAB>секунды<TAB>байт вывода»,
# ошибки каждого модуля кладёт рядом файлом «модуль.err».
progon() { # $1 — рабочий каталог
  rab=$1
  # Одна проба — отдельным файлом-ответом: xargs не даёт кода каждой пробы,
  # а склеенный вывод нескольких прогонов перемешался бы построчно.
  cat > "$rab/odna.sh" <<'ODNA'
f=$1; rab=$2; flang=$3
b=$(basename "$f" .flang)
t0=$(date +%s)
"$flang" check --proof "$f" > "$rab/$b.out" 2> "$rab/$b.err"
kod=$?
t1=$(date +%s)
printf '%s\t%s\t%s\t%s\n' "$b" "$kod" "$((t1-t0))" "$(wc -c < "$rab/$b.out")" > "$rab/$b.tsv"
ODNA
  find "$KATALOG" -maxdepth 1 -name '*.flang' | sort \
    | xargs -P "$PARALLEL" -I{} sh "$rab/odna.sh" {} "$rab" "$FLANG"
  cat "$rab"/*.tsv > "$rab/vse.tsv" 2>/dev/null
  [ -s "$rab/vse.tsv" ] || { echo "прогон не дал ни строки — мерить нечем" >&2; return 2; }
  return 0
}

# Отказ ли это: код не 0 либо вывод пуст.
otkaz() { # код байт → 0, если отказ
  [ "$1" -ne 0 ] || [ "$2" -eq 0 ]
}

RAB=$(mktemp -d "$VREMENNO/stdlib-proof.XXXXXX") || exit 2
trap 'rm -rf "$RAB"' EXIT INT TERM

case "$REZHIM" in
  --скобки)
    python3 - "$DEREVO" <<'SKAN'
import io, os, re, sys
koren = sys.argv[1]
nahodki = []
for dp, dn, fn in os.walk(koren):
    dn[:] = [d for d in dn if d not in ('.git', 'node_modules')]
    for f in fn:
        if not (f.endswith('.flang') or f.endswith('.fscript')):
            continue
        put = os.path.join(dp, f)
        try:
            text = io.open(put, encoding='utf-8').read()
        except (OSError, UnicodeDecodeError):
            continue
        for n, stroka in enumerate(text.split('\n'), 1):
            if stroka.lstrip().startswith('//'):
                continue
            if ' или ' not in stroka or ' и притом ' not in stroka:
                continue
            # Строковые постоянные и имена в ёлочках снимаются: «одна или две»
            # внутри имени постусловия — слово, а не связка.
            chistaya = re.sub(r'"(\\.|[^"\\])*"', '""', stroka)
            chistaya = re.sub(r'«[^»]*»', '«»', chistaya)
            gl = 0; ili = []; ipr = []; i = 0
            while i < len(chistaya):
                c = chistaya[i]
                if c in '([':
                    gl += 1
                elif c in ')]':
                    gl -= 1
                elif gl == 0:
                    if chistaya.startswith(' и притом ', i):
                        ipr.append(i); i += 10; continue
                    if chistaya.startswith(' или ', i):
                        ili.append(i); i += 5; continue
                i += 1
            if ili and ipr and min(ili) < min(ipr):
                nahodki.append((os.path.relpath(put, koren), n, stroka.strip()))
for put, n, stroka in nahodki:
    print('СКОБКИ: %s:%d — «или» стоит левее «и притом» на одном уровне скобок,'
          ' поэтому читается «А или (Б и притом В)»: первая ветка отвечает за всё'
          ' выражение. Хотели именно этого — поставьте скобки явно.' % (put, n), file=sys.stderr)
    print('    ' + stroka[:190], file=sys.stderr)
if nahodki:
    print('мест без внешних скобок: %d' % len(nahodki), file=sys.stderr)
    sys.exit(1)
print('дизъюнкций без внешних скобок перед «и притом» в дереве нет')
SKAN
    exit $?
    ;;
  --перепись)
    nuzhen_dvoichnyy
    progon "$RAB" || exit 2
    sort -t"$(printf '\t')" -k3,3nr "$RAB/vse.tsv" \
      | awk -F'\t' '{printf "%-22s код %s  %5s с  %8s байт ведомости\n", $1, $2, $3, $4}'
    exit 0
    ;;
  --check)
    nuzhen_dvoichnyy
    [ -f "$VEDOMOST" ] || { echo "нет ведомости долга $VEDOMOST — сверять не с чем" >&2; exit 2; }
    progon "$RAB" || exit 2
    awk -F'\t' '!/^#/ && $1 != "модуль" && NF >= 3 {print $1}' "$VEDOMOST" | sort > "$RAB/dolg"
    bedy=0; vsego=0; otkazov=0
    while IFS="$(printf '\t')" read -r imya kod sek bayt; do
      vsego=$((vsego+1))
      if otkaz "$kod" "$bayt"; then
        otkazov=$((otkazov+1))
        if ! grep -qx "$imya" "$RAB/dolg"; then
          echo "ПРИБАВИЛОСЬ: $imya.flang — код $kod, ведомости $bayt байт, а в долге его нет; поток ошибок:" >&2
          sed 's/^/    /' "$RAB/$imya.err" >&2
          bedy=$((bedy+1))
        fi
      elif grep -qx "$imya" "$RAB/dolg"; then
        echo "НАДГРОБИЕ: $imya.flang стоит в $VEDOMOST, а ведомость с него снимается (код $kod, $bayt байт) — уберите строку, иначе она глушит проверку" >&2
        bedy=$((bedy+1))
      fi
    done < "$RAB/vse.tsv"
    dolgie=$(sort -t"$(printf '\t')" -k3,3nr "$RAB/vse.tsv" | head -3 | awk -F'\t' '{printf "%s %sс, ", $1, $3}')
    if [ "$bedy" -eq 0 ]; then
      echo "модулей библиотеки $vsego, ведомость снимается с $((vsego-otkazov)); не снимается с $otkazov, и все они названы в $VEDOMOST (дольше всех: ${dolgie%, })"
      exit 0
    fi
    echo "модулей библиотеки $vsego, отказов $otkazov, расхождений с ведомостью долга $bedy — названы выше" >&2
    exit 1
    ;;
  --подлог-скобки)
    # Дерево-подлог из одного файла: прибору показывают ту самую форму записи,
    # на которой стояла беда 8455. Проба ДОЛГОВЕЧНАЯ — она не зависит ни от
    # одного файла дерева и не станет холостой после перепечатки семени.
    KOP=$RAB/skobki
    mkdir -p "$KOP" || exit 2
    cat > "$KOP/подлог.flang" <<'PODLOG'
модуль «Подлог скобок»

тотальная функция «Подлог»
  принимает «строка»: строка
  возвращает признак
  («строка» начинается с "а") или («строка» начинается с "б") и притом («строка» содержит "в")
PODLOG
    grep -q 'и притом' "$KOP/подлог.flang" || {
      echo "ПОДЛОГ НЕ СОБРАЛСЯ: в подложенном файле нет связки — поправить подлог, сторож ни при чём" >&2
      exit 0
    }
    DEREVO=$KOP sh "$0" --скобки > "$RAB/out" 2>&1
    kod=$?
    if [ "$kod" -eq 0 ]; then
      echo "ПОДЛОГ НЕ ПОЙМАН — сторож сломан: дизъюнкция без внешних скобок прошла" >&2
      exit 0
    fi
    if [ "$kod" -ne 1 ]; then
      echo "ПРОБА ХОЛОСТА: сторож ответил кодом $kod, а не 1 — это не «поймал подлог», это «не смог посмотреть»" >&2
      sed 's/^/  /' "$RAB/out" >&2
      exit 0
    fi
    if ! grep -q 'СКОБКИ: подлог.flang:6' "$RAB/out"; then
      echo "ПРОБА ХОЛОСТА: сторож покраснел не на подлоге — ждали «СКОБКИ: подлог.flang:6», а сказано:" >&2
      sed 's/^/  /' "$RAB/out" >&2
      exit 0
    fi
    echo "подлог пойман: место названо файлом и строкой, код $kod"
    sed 's/^/  /' "$RAB/out"
    exit 1
    ;;
  --подлог)
    nuzhen_dvoichnyy
    # Каталог из ОДНОГО модуля, а не копия библиотеки: подложенный модуль ни
    # на кого не ссылается, а копия библиотеки удвоила бы цену работы — проба
    # стала бы дороже того, что проверяет, и её бы сняли.
    KOP=$RAB/podlog
    mkdir -p "$KOP" || exit 2
    # Подлог ДОЛГОВЕЧНЫЙ: обещание, которого тело не держит (н равно 0), —
    # ядро его не закроет ни сегодня, ни после перепечатки семени.
    # Подкладывать сюда беду задачи 8455 (заголовок нетотальной функции)
    # нельзя: она чинится, и проба стала бы холостой ровно в тот день, когда
    # правка доедет до двоичного.
    cat > "$KOP/подлог-сторожа.flang" <<'PODLOG'
модуль «Подлог сторожа ведомости»

тотальная функция «Подлог»
  принимает н: нат
  возвращает нат
  обеспечивает «подложное обещание» результат больше 0
  н
PODLOG
    [ -s "$KOP/подлог-сторожа.flang" ] || {
      echo "ПОДЛОГ НЕ СОБРАЛСЯ: подложенный модуль пуст — поправить подлог, сторож ни при чём" >&2
      exit 0
    }
    KATALOG=$KOP PARALLEL=$PARALLEL sh "$0" --check > "$RAB/out" 2>&1
    kod=$?
    if [ "$kod" -eq 0 ]; then
      echo "ПОДЛОГ НЕ ПОЙМАН — сторож сломан: модуль с необеспеченным обещанием прошёл" >&2
      exit 0
    fi
    if [ "$kod" -ne 1 ]; then
      echo "ПРОБА ХОЛОСТА: сторож ответил кодом $kod, а не 1 — это не «поймал подлог», это «не смог посмотреть»" >&2
      sed 's/^/  /' "$RAB/out" >&2
      exit 0
    fi
    if ! grep -q 'ПРИБАВИЛОСЬ: подлог-сторожа' "$RAB/out"; then
      echo "ПРОБА ХОЛОСТА: сторож покраснел не на подлоге — ждали «ПРИБАВИЛОСЬ: подлог-сторожа», а сказано:" >&2
      sed 's/^/  /' "$RAB/out" >&2
      exit 0
    fi
    echo "подлог пойман: модуль с необеспеченным обещанием назван поимённо, код $kod"
    grep 'ПРИБАВИЛОСЬ: подлог-сторожа' "$RAB/out" | sed 's/^/  /'
    exit 1
    ;;
  *)
    echo "сторож ведомости библиотеки: непонятный ключ «$REZHIM» (--check, --скобки, --перепись, --подлог, --подлог-скобки)" >&2
    exit 2
    ;;
esac
