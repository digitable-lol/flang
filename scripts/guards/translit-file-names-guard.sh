# ТРАНСЛИТА В ИМЕНАХ ФАЙЛОВ НЕ ПРИБАВЛЯЕТСЯ — храповик по закрытому списку слов.
#
#   sh scripts/guards/translit-file-names-guard.sh --check    сверить имена со списком слов и ведомостью, код 1 при беде
#   sh scripts/guards/translit-file-names-guard.sh --подлог   подмешать scripts/podlog-storozha.sh: обязан покраснеть (код 1)
#   sh scripts/guards/translit-file-names-guard.sh --список   имена с чужими словами, по одному в строке
#
# Имя файла — либо русское, либо английское; транслит — брак (задача 1428).
# Кириллицу судит сосед (cyrillic-file-names-guard.sh); здесь судятся ЛАТИНСКИЕ
# имена: каждое слово имени (разделители «-», «_», «.», без последнего
# расширения, числа не в счёт, регистр не в счёт) обязано стоять в закрытом
# списке scripts/ledgers/file-name-words.txt. Слово не из списка — либо
# транслит, либо новое английское слово, и тогда его вписывают в список ВМЕСТЕ
# с файлом: список закрыт нарочно, чтобы транслит не прошёл молча.
# Область — шесть путей, довод ниже отдельным разделом. Уже лежащие транслитные
# имена — в ведомости долга scripts/ledgers/translit-file-names-debt.txt, у
# каждого причина. Сверка В ОБЕ СТОРОНЫ: имя с чужим словом вне ведомости —
# красно; запись, пережившая файл или долг, — тоже красно.
# Судится имя файла, не каталог (как у соседа). Смотрятся ОТСЛЕЖИВАЕМЫЕ файлы
# (git ls-files): собранное и временное в счёт не идёт.
#
# ── ПОЧЕМУ ОБЛАСТЬ ИМЕННО ТАКАЯ ─────────────────────────────────────────────
# Раньше здесь стояло «Область — стек инструментов», и это было НАЗВАНИЕ, а не
# довод: почему в области docs/site/ и docs/zettel/, а весь остальной docs/,
# flang/src, flang/stdlib, fspec/ и packaging/ — нет, не было сказано ни здесь,
# ни в задаче 1428, ни в ADR. Образец, как надо, — сосед
# scripts/guards/no-package-json-guard.sh: он смотрит только корень и прямо
# пишет, почему остальные пять package.json остаются.
#
# ДОВОД. В области лежит то, чьё имя человек НАБИРАЕТ РУКОЙ в команде: пути
# сторожей и ярлыков (scripts/), оснастка языка (flang/scripts/), приборы
# прогонов (flang/test/), работы CI (.github/) — и две ветки docs/, у которых
# СВОЯ схема имён и свой сторож: docs/site/ собирается в сайт по именам файлов,
# docs/zettel/ держит 721 заметку с закреплённой схемой имени. Транслит здесь
# уезжает в командную строку, в работу CI и в ссылку сайта.
#
# flang/proof ВОШЁЛ В ОБЛАСТЬ 22 сентября 2026 (ADR-0046, задача 6421). Прежний довод
# исключения звучал так: «имя файла — КЛЮЧ записи доказательства, переименование рвёт
# ключ». Довод снят ПО СУЩЕСТВУ, а не росчерком: ключ не запрещает переименование — он
# требует двигать файл и строку манифеста ОДНИМ изменением. Каталог переведён тремя
# порциями, и после каждой набор проб давал «сошлось всё» с теми же числами (подделок
# 534, отвергнуто 448, честных 248).
#
# ПОЧЕМУ ОСТАЛЬНОЕ НЕ СУДИТСЯ — по каждому названа цена, а не умолчание:
#   flang/self/**    переименование стоит полной перепечатки семени (~10 часов):
#   bootstrap/**     имя набрано внутри ПЕЧАТАЕМОЙ части исходников. Два имени
#                    уже отложены по этой причине в ведомости долга.
#   docs/tasks/**    имя задачи цитируется в коммитах, ветках и журнале; из 199
#                    имён ниже 97 лежат здесь.
#   прочее docs/,    барьера нет, довода против нет — просто не сделано.
#   flang/translation/
#
# ЧТО ЗА ОБЛАСТЬЮ — ПЕРЕСЧИТАНО, А НЕ ОЦЕНЕНО. Ревизия дерева 21 сентября 2026
# (docs/tree-layout-audit.md) давала ≈185 по выборке 47 из 234. Перемер полным
# разбором, 21 сентября 2026, дерево 3684 файла:
#
#   отслеживаемых файлов вне области                                     2433
#   из них латинских имён                                                1656
#   из них со словом не из scripts/ledgers/file-name-words.txt            954
#   из них НЕСУЩИХ ТРАНСЛИТ РУССКОГО СЛОВА                                199
#
#   где: docs/tasks 97, flang/proof 67, docs/design 13, flang/self 9,
#        flang/translation 8, docs/examples 3, docs/flang 1, docs/ct 1
#
# Чем снято: все 1213 различных слов, не стоящих в закрытом списке, разобраны
# ПОИМЁННО — сначала пробой скелетов (латинское слово и каждое русское слово
# дерева приводятся к общему огрублённому виду), затем каждое слово-кандидат
# прочитано глазами в своём файле. 26 совпадений скелета оказались настоящими
# английскими словами (agent, audit, batch, format, median, minimum, modus,
# ponens, palindrome, plane, promo, repo, segment, setoid, signal, span, system,
# temp, uuid, nul и ещё шесть) — они НЕ в счёте. Обратная ошибка пробы дороже и
# ради неё счёт и переделан: проба не знает записи «ц» через «c» и пропустила 63
# слова (cena, celi, granica, indukcii, kolca, otricanie, stranicy, edinicy…) —
# оценка ≈185 занижала именно поэтому.
#
# РЕШЕНИЕ ЭТОГО ЗАХОДА: область НЕ расширяется. Сначала число и довод, потом
# решение — переименование без записанного правила перемешает беспорядок, а не
# снимет его (задача 1430, то же сказано в 6421). 199 имён — цена, названная
# вслух; кто берётся расширять, берёт её вместе с ведомостью долга.
set -u
KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
cd "$KOREN" || exit 2
SLOVA=scripts/ledgers/file-name-words.txt
VEDOMOST=scripts/ledgers/translit-file-names-debt.txt
# Шесть путей области; довод — раздел «ПОЧЕМУ ОБЛАСТЬ ИМЕННО ТАКАЯ» в шапке.
# Отслеживаемых файлов в области — 1251; что за областью, сосчитано там же.
# СНЯТО 2026-09-21 файлов scripts,flang/test,flang/scripts,docs/site,docs/zettel,.github = 1251
OBLAST="scripts flang/test flang/scripts flang/proof docs/site docs/zettel .github"
REZHIM=${1:---check}
RAB=${FLANG_TMP:-/srv/tmp}/translit-names.$$
mkdir -p "$RAB" || exit 2
trap 'rm -rf "$RAB"' EXIT INT TERM

[ -f "$SLOVA" ] || { echo "транслит в именах: нет списка слов $SLOVA" >&2; exit 2; }
[ -f "$VEDOMOST" ] || { echo "транслит в именах: нет ведомости $VEDOMOST" >&2; exit 2; }
grep -v '^#' "$SLOVA" | grep -v '^$' | LC_ALL=C sort -u > "$RAB/slova"
grep -v '^#' "$VEDOMOST" | grep -v '^$' | LC_ALL=C sort > "$RAB/vedomost"

# Латинские имена области, по одному пути в строке.
imena() {
  git -c core.quotepath=false ls-files -- $OBLAST | LC_ALL=C.UTF-8 grep -v -P '[А-Яа-яЁё][^/]*$'
}

# путь → «путь<TAB>чужие слова» для имён, где есть слово не из списка.
chuzhie() {
  LC_ALL=C.UTF-8 awk -v SLOVA="$RAB/slova" '
    BEGIN { while ((getline w < SLOVA) > 0) znaem[w] = 1 }
    {
      put = $0; imya = put; sub(/.*\//, "", imya); sub(/\.[^.]*$/, "", imya)
      n = split(tolower(imya), kuski, /[-_.]/); vyvod = ""
      for (i = 1; i <= n; i++) {
        s = kuski[i]
        if (s == "" || s ~ /^[0-9]+$/ || (s in znaem)) continue
        vyvod = vyvod (vyvod == "" ? "" : " ") s
      }
      if (vyvod != "") print put "\t" vyvod
    }'
}

case "$REZHIM" in
  --список) imena | chuzhie | cut -f1; exit 0 ;;
  --check) imena | chuzhie > "$RAB/chuzhie" ;;
  --подлог) { imena; echo 'scripts/podlog-storozha.sh'; } | chuzhie > "$RAB/chuzhie" ;;
  *) echo "транслит в именах: непонятный ключ «$REZHIM» (--check, --подлог, --список)" >&2; exit 2 ;;
esac

vsego=$(imena | wc -l | tr -d ' ')
cut -f1 "$RAB/chuzhie" | LC_ALL=C sort > "$RAB/derevo"
LC_ALL=C comm -23 "$RAB/derevo" "$RAB/vedomost" > "$RAB/novye"
LC_ALL=C comm -13 "$RAB/derevo" "$RAB/vedomost" > "$RAB/mertvye"
n=$(wc -l < "$RAB/novye" | tr -d ' ')
m=$(wc -l < "$RAB/mertvye" | tr -d ' ')
dolg=$(wc -l < "$RAB/derevo" | tr -d ' ')

if [ "$n" -eq 0 ] && [ "$m" -eq 0 ]; then
  if [ "$REZHIM" = --подлог ]; then
    echo "ПОДЛОГ НЕ ПОЙМАН — сторож сломан: подмешанное имя scripts/podlog-storozha.sh прошло" >&2
    exit 0
  fi
  echo "транслит в именах файлов: латинских имён $vsego, с чужими словами $dolg — все в ведомости, новых нет"
  exit 0
fi
if [ "$n" -gt 0 ]; then
  echo "СЛОВО НЕ ИЗ СПИСКА В ИМЕНИ ФАЙЛА — новых $n (имя файла — английскими словами, без транслита; задача 1428)."
  echo "Английское слово — впишите в $SLOVA; транслит — переименуйте:"
  LC_ALL=C sort "$RAB/chuzhie" | LC_ALL=C join -t "$(printf '\t')" - "$RAB/novye" | awk -F'\t' '{ printf "  · %s  (чужие слова: %s)\n", $1, $2 }'
fi
if [ "$m" -gt 0 ]; then
  echo "ЗАПИСЬ ВЕДОМОСТИ ПЕРЕЖИЛА ФАЙЛ ИЛИ ДОЛГ — $m; уберите строки из $VEDOMOST:"
  sed 's/^/  · /' "$RAB/mertvye"
fi
[ "$REZHIM" = --подлог ] && echo "подлог пойман"
exit 1
# ярлык «транслит:проверка» sh --check — транслита в латинских именах файлов не прибавилось
