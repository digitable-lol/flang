/**
 * Сторож словаря для читателя со стороны: внутреннее слово не имеет права
 * стоять в тексте, который читает человек, пришедший за языком.
 *
 *   node scripts/jargon-guard.mjs            проверить, напечатать отчёт
 *   node scripts/jargon-guard.mjs --list     заодно назвать каждое место
 *   node scripts/jargon-guard.mjs --write    переписать долг по нынешним числам
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * 18 августа 2026 владелец открыл опубликованный сайт и сказал: «все страницы
 * как какая-то твоя история, а не понятный гайд для разработчика о языке».
 * Замер подтвердил: в `docs/site/*.md` 711 вхождений внутренних слов —
 * «эталон» 190, «близнец» 130, «сторож» 124, «корпус» 113 и так далее.
 *
 * Слова эти завелись во внутренних заданиях, где они полезны: короче и точнее.
 * Утекли они не по злому умыслу, а потому что между внутренним текстом и
 * страницей сайта не стояло ничего. Теперь стоит.
 *
 * ── Кому запрет, а кому нет ─────────────────────────────────────────────────
 * Запрет ТОЛЬКО на текстах для читателя со стороны — их список в
 * `docs/jargon.json`, раздел `поверхности`: сайт, README, страница man,
 * руководство, спецификации, сообщения самого компилятора.
 *
 * Во внутренних текстах жаргон ЗАКОНЕН, и вычищать его не надо: база знаний
 * `docs/zettel/` — лабораторный журнал, комментарии в коде — разговор
 * разработчиков между собой, задания агентам — тем более. Ни один из них в
 * список поверхностей не входит, и вписывать их туда не надо.
 *
 * ── Два разных послабления, и путать их нельзя ──────────────────────────────
 * `исключения` — слово стоит ЗАКОННО, потому что тут же объяснено. Исключение
 *   обязано процитировать место, где объяснение стоит, и сторож проверяет, что
 *   цитата в файле есть и что до неё слово не встречается. Соврать нечем:
 *   сотрёте объяснение — сторож покраснеет снова.
 * `долг` — слово стоит НЕЗАКОННО, но текст ещё не переписан. Долг числом на
 *   файл: вырасти он не имеет права (это отказ), а упасть обязан заметно —
 *   упавший долг тоже отказ, с просьбой вписать новое число. Так число ползёт
 *   только вниз и всегда видно в диффе.
 *
 * ── Чтобы сторож не зеленел впустую ─────────────────────────────────────────
 * У каждого слова в `docs/jargon.json` лежат образцы `ловит` — строки, которые
 * образец ОБЯЗАН поймать, и `не ловит` — которые обязан пропустить. Их
 * проверяет `flang/test/jargon-guard.test.mjs`: ослабленный образец,
 * переставший ловить хоть что-нибудь, роняет тест. Там же стоит проверка
 * порчей: слово вписывается в настоящую страницу, и сторож обязан покраснеть
 * и назвать файл со строкой.
 */
import { execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { запущенНапрямую } from "../flang/scripts/direct-run.mjs"

export const КОРЕНЬ = resolve(fileURLToPath(new URL("..", import.meta.url)))
export const НАСТРОЙКА = "docs/jargon.json"

/** Читает список слов, поверхностей, исключений и долга. */
export function прочитатьНастройку(корень = КОРЕНЬ) {
  return JSON.parse(readFileSync(join(корень, НАСТРОЙКА), "utf8"))
}

/* ── Что из файла вообще читается ────────────────────────────────────────────
   Слово внутри команды, пути или имени файла — не проза, а название вещи:
   `proof-ledger.mjs` не переименовать текстовым запретом, и краснеть на нём
   значило бы заставить писать неправду. Поэтому у каждой поверхности объявлен
   ВИД, и для каждого вида сказано, что считается текстом для читателя.

   Затирается всё пробелами, а не вырезается: длины и переводы строк остаются
   на месте, и номер строки в отказе — настоящий номер строки файла. */

const пробелами = (кусок) => кусок.replace(/[^\n]/gu, " ")
const затереть = (текст, образец) => текст.replace(образец, пробелами)

/** Markdown: без блоков кода, без кода в строке, без адресов ссылок. */
function прозаМаркдауна(текст) {
  let т = затереть(текст, /^```[\s\S]*?^```/gmu)
  т = затереть(т, /^~~~[\s\S]*?^~~~/gmu)
  т = затереть(т, /<!--[\s\S]*?-->/gu)
  т = затереть(т, /`[^`\n]*`/gu)
  // Адрес ссылки — путь или имя страницы, не проза. Текст ссылки остаётся.
  т = т.replace(/\]\(([^)\n]*)\)/gu, (всё, цель) => "](" + пробелами(цель) + ")")
  т = т.replace(/\[\[([^\]\n]*)\]\]/gu, (всё, слаг) => "[[" + пробелами(слаг) + "]]")
  return т
}

/** roff: строки-комментарии наборщика читателю не показывают. */
function прозаРоффа(текст) {
  return затереть(текст, /^\.\\".*$/gmu)
}

/* Перед косой чертой стоит одно из этого — значит, дальше ЛИТЕРАЛ-ОБРАЗЕЦ, а не
   деление. Список — обычная эвристика разборщиков JavaScript, и в C она безвредна:
   выражения вида `= / …` там не бывает. */
const ПЕРЕД_ОБРАЗЦОМ = new Set(["(", ",", "=", ":", "[", "!", "&", "|", "?", "{", "}", ";", "+", "-", "*", "%", "~", "^", "<", ">", "\n"])
const СЛОВА_ПЕРЕД_ОБРАЗЦОМ = /(?:^|[^\p{L}$_])(?:return|typeof|instanceof|case|in|of|new|delete|void|do|else|yield|await)$/u

/**
 * Исходник: читателю видны ТОЛЬКО строковые литералы — из них печатается
 * справка и диагностика. Комментарии — разговор разработчиков, они законны.
 *
 * Разбор посимвольный, а не регулярками, и на то две измеренные причины.
 *
 * ПЕРВАЯ: две косые внутри «https://…» регулярка приняла бы за начало
 * комментария и съела бы половину настоящей строки.
 *
 * ВТОРАЯ, и она стоила бы всей проверки: литерал-образец с кавычкой внутри.
 * В разборщике на JavaScript стояло `message.replace(/'([^']{1,40})'/gu, …)` —
 * (файл `flang/src/parser.mjs` удалён вместе с той реализацией 20 августа 2026) —
 * разборщик, не знающий про образцы, принимает первую кавычку за начало строки
 * и с этого места читает КОД как текст для читателя. Дальше он находит жаргон в
 * комментариях (54 «находки» в одном парсере) и молчит о настоящих строках. Это
 * не ложная тревога, а сломанное сравнение: числа перестают что-либо значить.
 * Поэтому образцы разбираются наравне со строками и комментариями.
 */
function строкиИсходника(текст) {
  const из = Array.from(текст)
  const вывод = из.map((с) => (с === "\n" ? "\n" : " "))
  let i = 0
  let передЭтим = "" // последние значимые символы кода — по ним отличается образец от деления
  while (i < из.length) {
    const с = из[i]
    if (с === "/" && из[i + 1] === "/") {
      while (i < из.length && из[i] !== "\n") i++
      continue
    }
    if (с === "/" && из[i + 1] === "*") {
      i += 2
      while (i < из.length && !(из[i] === "*" && из[i + 1] === "/")) i++
      i += 2
      continue
    }
    if (с === "/") {
      const хвост = передЭтим.trimEnd()
      const образец = хвост === "" || ПЕРЕД_ОБРАЗЦОМ.has(хвост.at(-1)) || СЛОВА_ПЕРЕД_ОБРАЗЦОМ.test(хвост)
      if (образец) {
        i++
        let вКлассе = false
        while (i < из.length && из[i] !== "\n") {
          if (из[i] === "\\") {
            i += 2
            continue
          }
          if (из[i] === "[") вКлассе = true
          else if (из[i] === "]") вКлассе = false
          else if (из[i] === "/" && !вКлассе) break
          i++
        }
        i++ // закрывающая косая
        while (i < из.length && /\p{L}/u.test(из[i])) i++ // ключи образца
        передЭтим = "0" // образец — значение, после него косая означает деление
        continue
      }
      передЭтим += с
      i++
      continue
    }
    if (с === '"' || с === "'" || с === "`") {
      const кавычка = с
      i++
      while (i < из.length && из[i] !== кавычка) {
        if (из[i] === "\\") {
          i += 2
          continue
        }
        вывод[i] = из[i]
        i++
      }
      i++
      передЭтим = "0" // строка — тоже значение
      continue
    }
    передЭтим = (передЭтим + с).slice(-16)
    i++
  }
  return вывод.join("")
}

const ВИДЫ = {
  проза: прозаМаркдауна,
  рофф: прозаРоффа,
  строки: строкиИсходника,
}

/** Текст файла, приведённый к тому, что увидит читатель со стороны. */
export function читаемое(текст, вид) {
  const очистить = ВИДЫ[вид]
  if (!очистить) throw new Error(`неизвестный вид поверхности: ${вид}`)
  return очистить(текст)
}

/* ── Поиск ───────────────────────────────────────────────────────────────── */

export const образецСлова = (слово) => new RegExp(слово.образец, "giu")

/** Все вхождения слов в уже очищенный текст, с номерами строк. */
export function найти(очищенное, слова) {
  const находки = []
  for (const слово of слова) {
    for (const м of очищенное.matchAll(образецСлова(слово))) {
      const до = очищенное.slice(0, м.index)
      const строка = до.split("\n").length
      const началоСтроки = до.lastIndexOf("\n") + 1
      находки.push({
        слово: слово.имя,
        вместо: слово.вместо,
        строка,
        колонка: м.index - началоСтроки + 1,
        сдвиг: м.index,
        // Образец может лечь через перевод строки («неподвижная\nточка»). В
        // отказе он печатается одной строкой, иначе отчёт разъезжается.
        текст: м[0].replace(/\s+/gu, " "),
      })
    }
  }
  return находки.sort((а, б) => а.сдвиг - б.сдвиг)
}

/** Маска поверхности в регулярку: `*` не переходит через косую, `**` переходит. */
export function маскаВОбразец(маска) {
  const экранированная = маска.replace(/[.+^${}()|[\]\\]/gu, "\\$&")
  const собранная = экранированная
    .replace(/\*\*/gu, "\u0000")
    .replace(/\*/gu, "[^/]*")
    .replace(/\u0000/gu, ".*")
  return new RegExp("^" + собранная + "$", "u")
}

/** Разворачивает маски поверхностей в список файлов дерева. */
export function собратьФайлы(настройка, корень = КОРЕНЬ) {
  const всеФайлы = execSync("git -c core.quotepath=false ls-files -z", {
    cwd: корень,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
    .split("\u0000")
    .filter(Boolean)
  const собранные = []
  const виданные = new Set()

  /* «Вне запрета» — не украшение списка, а вычитание из него. Маска отсюда
     сильнее маски поверхности: `docs/site/*.md` берёт все страницы сайта, а
     `docs/site/changelog.md` из этого списка возвращает обратно ту, что
     печатается из тем вливаний и руками не правится. Маска, не подошедшая ни к
     одному файлу, — беда: список освобождений обязан протухать громко. */
  const освобождения = (настройка["вне запрета"] ?? []).map((о) => ({ ...о, образец: маскаВОбразец(о.маска) }))
  for (const о of освобождения) {
    if (!всеФайлы.some((ф) => о.образец.test(ф))) {
      собранные.push({ файл: null, беда: `«вне запрета»: маска «${о.маска}» не подошла ни к одному файлу дерева` })
    }
  }
  const освобождён = (файл) => освобождения.some((о) => о.образец.test(файл))

  for (const поверхность of настройка.поверхности) {
    const образец = маскаВОбразец(поверхность.маска)
    const подошли = всеФайлы.filter((ф) => образец.test(ф) && !освобождён(ф))
    if (подошли.length === 0) {
      собранные.push({
        файл: null,
        маска: поверхность.маска,
        беда: `маска «${поверхность.маска}» не подошла ни к одному файлу дерева`,
      })
      continue
    }
    for (const файл of подошли) {
      if (виданные.has(файл)) continue
      виданные.add(файл)
      собранные.push({ файл, вид: поверхность.вид, маска: поверхность.маска })
    }
  }
  return собранные
}

/**
 * Проверка целиком. Возвращает `{ беды, замечания, поФайлам, всего }`,
 * ничего не печатая: печать — дело `main`, а тесты читают результат.
 */
export function проверить(корень = КОРЕНЬ) {
  const настройка = прочитатьНастройку(корень)
  const беды = []
  const замечания = []
  const поФайлам = new Map()
  const долг = настройка.долг ?? {}
  const исключения = настройка.исключения ?? []
  const исключенияИспользованы = new Set()

  for (const слово of настройка.слова) {
    if (!Array.isArray(слово.ловит) || слово.ловит.length === 0) {
      беды.push(`слово «${слово.имя}»: нет ни одного образца «ловит» — образец нечем проверить, и он может ловить пустоту`)
    }
  }

  for (const запись of собратьФайлы(настройка, корень)) {
    if (запись.беда) {
      беды.push(запись.беда)
      continue
    }
    const исходный = readFileSync(join(корень, запись.файл), "utf8")
    const очищенное = читаемое(исходный, запись.вид)
    let находки = найти(очищенное, настройка.слова)

    /* Исключения двух видов, и ни одно из них не даётся на слово.
       `внутри` — слово стоит внутри ИМЕНИ вещи: имя функции на flang, ключ
         машинного вывода, путь. Переименовать такое текстовым запретом нельзя,
         и краснеть на нём значило бы заставить писать неправду. Исключение
         цитирует имя целиком, и снимается ровно то, что попало внутрь цитаты.
       `объяснено` — слово стоит в прозе, но тут же объяснено. Исключение
         цитирует объясняющую фразу, и сторож требует, чтобы она стояла НЕ
         ПОЗЖЕ первого употребления. */
    for (const [номер, исключение] of исключения.entries()) {
      if (исключение.файл !== запись.файл) continue

      if (исключение.внутри !== undefined) {
        const куски = []
        for (let м = исходный.indexOf(исключение.внутри); м >= 0; м = исходный.indexOf(исключение.внутри, м + 1)) {
          куски.push([м, м + исключение.внутри.length])
        }
        if (куски.length === 0) {
          беды.push(
            `${запись.файл}: исключение для «${исключение.слово}» цитирует имя, которого в файле нет: ` +
              `«${исключение.внутри.slice(0, 60)}…»`,
          )
          continue
        }
        const внутриКуска = (н) => куски.some(([от, до]) => н.сдвиг >= от && н.сдвиг < до)
        const снятые = находки.filter((н) => н.слово === исключение.слово && внутриКуска(н))
        if (снятые.length === 0) {
          замечания.push(`${запись.файл}: исключение для «${исключение.слово}» больше не нужно — внутри цитаты слова нет`)
        }
        исключенияИспользованы.add(номер)
        находки = находки.filter((н) => !(н.слово === исключение.слово && внутриКуска(н)))
        continue
      }

      if (исключение.объяснено.length < 20) {
        беды.push(
          `${запись.файл}: исключение для «${исключение.слово}» цитирует слишком короткий кусок — ` +
            "процитируйте фразу, которая объясняет, а не само слово",
        )
        continue
      }
      const место = исходный.indexOf(исключение.объяснено)
      if (место < 0) {
        беды.push(
          `${запись.файл}: исключение для «${исключение.слово}» цитирует объяснение, которого в файле нет: ` +
            `«${исключение.объяснено.slice(0, 60)}…»`,
        )
        continue
      }
      const свои = находки.filter((н) => н.слово === исключение.слово)
      if (свои.length === 0) {
        замечания.push(`${запись.файл}: исключение для «${исключение.слово}» больше не нужно — слова в файле нет`)
        исключенияИспользованы.add(номер)
        continue
      }
      /* Читатель идёт сверху вниз, поэтому послабление даётся ровно тогда, когда
         ПЕРВОЕ вхождение слова лежит ВНУТРИ процитированной фразы. Отсюда сразу
         две проверки, и обе нужны: цитата, в которой самого слова нет, ничего не
         объясняет; цитата, стоящая ниже первого употребления, объясняет тому,
         кто уже споткнулся. */
      const концОбъяснения = место + исключение.объяснено.length
      const первое = свои[0]
      if (первое.сдвиг < место) {
        беды.push(
          `${запись.файл}: «${исключение.слово}» встречается в строке ${первое.строка} РАНЬШЕ объяснения — ` +
            "читатель упирается в слово до того, как ему сказали, что оно значит",
        )
        continue
      }
      if (первое.сдвиг >= концОбъяснения) {
        беды.push(
          `${запись.файл}: исключение для «${исключение.слово}» цитирует фразу, в которой самого слова нет — ` +
            "процитируйте то место, где слово стоит и объясняется",
        )
        continue
      }
      исключенияИспользованы.add(номер)
      находки = находки.filter((н) => н.слово !== исключение.слово)
    }

    const потолок = долг[запись.файл] ?? 0
    поФайлам.set(запись.файл, { находки, потолок, вид: запись.вид })
    if (находки.length > потолок) {
      const лишние = находки.slice(потолок)
      беды.push(
        `${запись.файл}: внутренних слов ${находки.length}, дозволено ${потолок}. Лишние:\n` +
          лишние.map((н) => `      строка ${н.строка}: «${н.текст}» → ${н.вместо}`).join("\n"),
      )
    } else if (находки.length < потолок) {
      беды.push(
        `${запись.файл}: внутренних слов ${находки.length}, а в долге записано ${потолок}. ` +
          "Долг упал — впишите новое число: ./ярлык жаргон:долг",
      )
    }
  }

  for (const [номер, исключение] of исключения.entries()) {
    if (исключенияИспользованы.has(номер)) continue
    if (!поФайлам.has(исключение.файл)) {
      беды.push(`исключение для «${исключение.слово}» ссылается на ${исключение.файл} — этого файла нет среди поверхностей`)
    }
  }

  for (const файл of Object.keys(долг)) {
    if (!поФайлам.has(файл)) беды.push(`в долге записан ${файл}, но он не попадает ни под одну маску поверхностей`)
  }

  const всего = [...поФайлам.values()].reduce((с, з) => с + з.находки.length, 0)
  return { беды, замечания, поФайлам, всего, настройка }
}

/** Переписывает раздел `долг` по нынешним числам. */
export function записатьДолг(корень = КОРЕНЬ) {
  const настройка = прочитатьНастройку(корень)
  const прежний = настройка.долг ?? {}
  const итог = проверить(корень)
  const новый = {}
  for (const [файл, з] of [...итог.поФайлам].sort(([а], [б]) => (а < б ? -1 : а > б ? 1 : 0))) {
    if (з.находки.length > 0) новый[файл] = з.находки.length
  }
  настройка.долг = новый
  writeFileSync(join(корень, НАСТРОЙКА), JSON.stringify(настройка, null, 2) + "\n")
  return { прежний, новый }
}

/* ── Печать ──────────────────────────────────────────────────────────────── */

function main() {
  const ключи = new Set(process.argv.slice(2))
  if (ключи.has("--write")) {
    const { прежний, новый } = записатьДолг()
    const былоВсего = Object.values(прежний).reduce((с, ч) => с + ч, 0)
    const сталоВсего = Object.values(новый).reduce((с, ч) => с + ч, 0)
    console.log(`Долг переписан: файлов ${Object.keys(новый).length}, вхождений ${сталоВсего} (было ${былоВсего}).`)
    return 0
  }

  const { беды, замечания, поФайлам, всего } = проверить()
  const сДолгом = [...поФайлам].filter(([, з]) => з.находки.length > 0)

  if (ключи.has("--list")) {
    for (const [файл, з] of сДолгом) {
      console.log(`\n${файл} — ${з.находки.length}:`)
      for (const н of з.находки) console.log(`  строка ${н.строка}: «${н.текст}» → ${н.вместо}`)
    }
    console.log("")
  }

  for (const з of замечания) console.log("  · " + з)

  if (беды.length) {
    console.error("Сторож жаргона ОТКАЗЫВАЕТ. Беды:")
    for (const б of беды) console.error("  · " + б)
    console.error(`\nвсего бед: ${беды.length}`)
    return 1
  }

  /* Долг печатается и в ЗЕЛЁНОМ выводе, поимённо. Число, которое видно только
     при отказе, перестаёт быть работой и становится фоном: зелёная строка «всё
     хорошо» над тысячей невычищенных мест — ровно то, из-за чего они там и
     оказались. */
  console.log(
    `Сторож жаргона: поверхностей ${поФайлам.size}, внутренних слов ${всего} ` +
      `(долг по ${сДолгом.length} файлам, расти не имеет права), новых 0.`,
  )
  const крупнейшие = [...сДолгом].sort(([, а], [, б]) => б.находки.length - а.находки.length).slice(0, 5)
  if (крупнейшие.length > 0) {
    console.log(
      "  долг больше всего в: " + крупнейшие.map(([ф, з]) => `${ф} (${з.находки.length})`).join(", ") +
        (сДолгом.length > крупнейшие.length ? `, и ещё в ${сДолгом.length - крупнейшие.length} файлах` : ""),
    )
  }
  return 0
}

