# СТОРОЖ УМЕНИЙ ЯДРА: описание не должно быть беднее самого ядра.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# 22 августа 2026 второй, независимый проверяльщик доказательств
# (`flang/proof/малый-сводитель.flang`) сличили с ядром на 752 утверждениях в
# 257 файлах. Расхождений 31, из них ошибок второго — 3, а остальные 28 —
# СПОСОБНОСТИ ЯДРА, КОТОРЫХ НЕТ В ОПИСАНИИ. Ни одного места, где ядро было бы
# неправо, не нашлось: это долг описания, а не дыра в ядре.
#
# Беда не косметическая. Доверие к слою держится на восьми названных правилах;
# если ОПИСАНИЕ правил беднее самих правил, читающий описание не знает, чему
# верит. А всякий, кто напишет третий проверяльщик или возьмётся ядро сузить,
# упрётся в те же 28 мест и потратит на них день. Один уже потратил.
#
# ── Что стережётся ───────────────────────────────────────────────────────────
# Список умений лежит В ОДНОМ МЕСТЕ — `flang/proof/УМЕНИЯ.tsv`, — и на него
# ссылаются обе стороны. Сторож проверяет, что ссылки не разошлись; на каждую
# строку списка спрашивается ЧЕТЫРЕ вещи:
#
#   1. ЯДРО.     Якорь — дословный кусок текста отказа (или имя функции) —
#                стоит в `flang/self/proof-kernel.flang`. Пропал якорь — умение
#                из ядра ушло либо переписано, и список отстал ОТ ЯДРА.
#   2. ОПИСАНИЕ. Номер умения (`У7`) стоит в `flang/proof/SPEC.md`. Убери
#                способность из описания — сторож краснеет здесь.
#   3. УЛИКА.    Функция-улика стоит в `flang/proof/karta/umeniya.flang`.
#                Умение без прогона в список не идёт: числа в описании обязаны
#                быть проверяемыми.
#   4. СЧЁТ.     Строк списка ровно столько же, сколько утверждений в файле
#                улик. Дописал улику и забыл список — сторож краснеет.
#
# Чего сторож НЕ делает: он не доказывает, что умение работает. Это делает
# прогон файла улик, и звать его надо отдельно —
#
#   bootstrap/flang check --proof flang/proof/karta/umeniya.flang
#
# (замер 23 августа 2026: утверждений 28, доказано 28, сетка 0, код 0).
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/kernel-abilities-guard.sh
#
# Код 0 — описание и ядро сошлись. Код 1 — названо КАЖДОЕ разошедшееся место:
# номер умения, сторона, которая отстала, и чего именно на ней не нашлось.
set -u

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
SPISOK=$KOREN/flang/proof/УМЕНИЯ.tsv
YADRO=$KOREN/flang/self/proof-kernel.flang
OPISANIE=$KOREN/flang/proof/SPEC.md
ULIKI=$KOREN/flang/proof/karta/umeniya.flang

BEDY=0
STROK=0

for F in "$SPISOK" "$YADRO" "$OPISANIE" "$ULIKI"; do
  if [ ! -f "$F" ]; then
    echo "нет файла: $F"
    exit 1
  fi
done

while IFS='	' read -r NOMER PRAVILO UMENIE YAKOR ULIKA; do
  [ -z "${NOMER:-}" ] && continue
  STROK=$((STROK + 1))

  if [ -z "${YAKOR:-}" ] || [ -z "${ULIKA:-}" ] || [ -z "${PRAVILO:-}" ] || [ -z "${UMENIE:-}" ]; then
    echo "$NOMER: строка списка неполна — колонок должно быть пять"
    BEDY=$((BEDY + 1))
    continue
  fi

  if ! grep -qF -- "$YAKOR" "$YADRO"; then
    echo "$NOMER: ЯДРО отстало — якоря «$YAKOR» в proof-kernel.flang нет"
    BEDY=$((BEDY + 1))
  fi

  if ! grep -qF -- "$NOMER." "$OPISANIE"; then
    echo "$NOMER: ОПИСАНИЕ отстало — умения «$UMENIE» в flang/proof/SPEC.md нет"
    BEDY=$((BEDY + 1))
  fi

  if ! grep -qF -- "«$ULIKA»" "$ULIKI"; then
    echo "$NOMER: УЛИКИ нет — функции «$ULIKA» в karta/umeniya.flang нет"
    BEDY=$((BEDY + 1))
  fi

  if ! grep -qF -- "$PRAVILO" "$YADRO"; then
    echo "$NOMER: правило «$PRAVILO» ядро больше не называет"
    BEDY=$((BEDY + 1))
  fi
done < "$SPISOK"

UTVERZHDENIY=$(grep -c 'обеспечивает «У' "$ULIKI")
if [ "$STROK" -ne "$UTVERZHDENIY" ]; then
  echo "СЧЁТ разошёлся: строк списка $STROK, утверждений в уликах $UTVERZHDENIY"
  BEDY=$((BEDY + 1))
fi

if [ "$BEDY" -eq 0 ]; then
  echo "умений в списке: $STROK; ядро, описание и улики сошлись на всех"
  exit 0
fi

echo "разошлось мест: $BEDY"
exit 1
