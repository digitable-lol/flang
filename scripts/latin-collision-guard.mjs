//
//   node scripts/latin-collision-guard.mjs
//
// Код 0 — новых столкновений нет; 1 — есть, и каждое названо обоими именами,
// файлами, строками и общим идентификатором; 3 — судить нечем.
//
// ── Какой это вид, и какой НЕ этот ──────────────────────────────────────────
// Столкновений имён два вида, и они разные:
//   вид 1 — ОДНО И ТО ЖЕ имя объявлено дважды (FLANG_DUPLICATE_NAME).
//           Его смотрит scripts/type-collision-guard.mjs. ЗДЕСЬ ОН НЕ СМОТРИТСЯ.
//   вид 2 — ДВА РАЗНЫХ имени после «Змейки» дают один идентификатор.
//           Это он. Именно он 31 августа сжёг десять часов перепечатки: имена
//           «Обойти занятое целью C++» и «Обойти занятое целью C» обе давали
//           oboyti_zanyatoe_celyu_c.
// Зелёный ответ этого сторожа НЕ значит «столкновений нет вообще».
//
// ── Правило не переписано, а прочитано ──────────────────────────────────────
// Соблазн был вписать сюда таблицу замен своими руками. Так делать нельзя:
// второе воплощение правила расходится с компилятором молча, и разошедшийся
// сторож хуже отсутствующего — он врёт уверенно. Поэтому таблицы читаются ИЗ
// flang/self/emit-c.flang при каждом запуске:
//   • «Замены кириллицы» — 66 пар;
//   • «Словарные символы» — 62 знака;
//   • «Зарезервировано в C» — 49 слов, с которых печать НАЧИНАЕТ таблицу.
// Все три числа объявлены в самом исходнике строками «обеспечивает», и сторож
// сверяет прочитанное с объявленным: разошлось — код 3 «судить нечем», а не
// тихая работа по неверной таблице.
//
// Сам порядок «Змейки» (emit-c.flang:486) здесь всё-таки повторён — прочитать
// исполняемый порядок текстом нельзя. Он короток и держится на прочитанных
// таблицах: транслитерировать → разбить на слова по словарным символам →
// склеить подчёркиваниями → в нижний регистр; пусто → "value".
//
// ── ЧТО ИМЕННО ИДЁТ В «ЗМЕЙКУ»: ПРОСЬБЫ ПЕЧАТИ, А НЕ ОБЪЯВЛЕННЫЕ ИМЕНА ──────
// Печать сталкивает не объявления, а ПРОСЬБЫ («Просьбы имён», emit-c.flang), и
// вида их три:
//     функция  →  «Имя»
//     объект   →  «создать Имя»
//     вариант  →  «вариант Имя»
// Теоремы в просьбы не входят вовсе, а таблица засеяна сорока девятью словами
// «Зарезервировано в C» под ключом-самим-словом.
//
// Прежде сторож брал голое объявленное имя у всех четырёх видов, и потому
// расходился с печатью В ОБЕ СТОРОНЫ: пару «Создать заказ» (функция) и «Заказ»
// (объект) печать схлопывает в один `sozdat_zakaz`, а сторож её не видел;
// пару «Пара» (функция) и «Пара» (объект) сторож красил, хотя печати они не
// мешают. Варианты не смотрелись вовсе, а зарезервированные слова — тем более.
import { readFileSync, existsSync, readdirSync } from "node:fs"
import { resolve, dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const ИСТОЧНИК_ПРАВИЛА = join(КОРЕНЬ, "flang/self/emit-c.flang")
const ВХОД = join(КОРЕНЬ, "flang/self/bootstrap/compiler.flang")
const ВЕДОМОСТЬ = join(КОРЕНЬ, "scripts/latin-collision-guard-known.tsv")
const ПАПКИ = ["flang/self", "flang/self/bootstrap", "flang/stdlib", "flang/core"]

function нечем(причина) {
  console.error(`СУДИТЬ НЕЧЕМ: ${причина}`)
  console.error("Это не «столкновений нет» — это «смотреть нечем».")
  process.exit(3)
}

// ── таблицы из исходника ────────────────────────────────────────────────────
function таблицы() {
  if (!existsSync(ИСТОЧНИК_ПРАВИЛА)) нечем(`нет ${ИСТОЧНИК_ПРАВИЛА}`)
  const текст = readFileSync(ИСТОЧНИК_ПРАВИЛА, "utf8")
  const строки = текст.split("\n")

  const начало = строки.findIndex((s) => /^тотальная функция «Замены кириллицы»/.test(s))
  if (начало < 0) нечем("в emit-c.flang не найдена «Замены кириллицы»")
  const обещано = /равен (\d+)/.exec(строки.slice(начало, начало + 4).join("\n"))
  const замены = []
  for (let i = начало; i < строки.length; i += 1) {
    if (i > начало && /^тотальная функция |^функция /.test(строки[i])) break
    const m = /«что» равным "([^"]*)" и «чем» равным "([^"]*)"/.exec(строки[i])
    if (m) замены.push([m[1], m[2]])
  }
  if (!обещано) нечем("у «Замены кириллицы» не объявлено число замен")
  if (замены.length !== Number(обещано[1]))
    нечем(`замен прочитано ${замены.length}, а исходник обещает ${обещано[1]} — таблица разошлась`)

  const сНачала = строки.findIndex((s) => /^тотальная функция «Словарные символы»/.test(s))
  if (сНачала < 0) нечем("в emit-c.flang не найдена «Словарные символы»")
  const кусок = строки.slice(сНачала, сНачала + 6).join("\n")
  const словарь = /ожидается "([^"]+)"/.exec(кусок)
  const обещаноЗнаков = /равен (\d+)/.exec(кусок)
  if (!словарь || !обещаноЗнаков) нечем("у «Словарные символы» не прочитались знаки или их число")
  if (словарь[1].length !== Number(обещаноЗнаков[1]))
    нечем(`словарных знаков ${словарь[1].length}, а обещано ${обещаноЗнаков[1]}`)

  const зНачала = строки.findIndex((s) => /^тотальная функция «Зарезервировано в C»/.test(s))
  if (зНачала < 0) нечем("в emit-c.flang не найдено «Зарезервировано в C»")
  const обещаноСлов = /равен (\d+)/.exec(строки.slice(зНачала, зНачала + 4).join("\n"))
  const зарезервировано = []
  for (let i = зНачала; i < строки.length; i += 1) {
    if (i > зНачала && /^тотальная функция |^функция /.test(строки[i])) break
    for (const m of строки[i].matchAll(/"([^"]*)"/g)) зарезервировано.push(m[1])
  }
  if (!обещаноСлов) нечем("у «Зарезервировано в C» не объявлено число слов")
  if (зарезервировано.length !== Number(обещаноСлов[1]))
    нечем(`зарезервированных прочитано ${зарезервировано.length}, а исходник обещает ${обещаноСлов[1]} — список разошёлся`)

  return { замены, словарь: new Set([...словарь[1]]), зарезервировано }
}

// ── «Змейка», собранная на прочитанных таблицах ─────────────────────────────
function змейка(имя, { замены, словарь }) {
  let t = имя
  for (const [что, чем] of замены) t = t.split(что).join(чем)
  const слова = []
  let текущее = ""
  for (const знак of t) {
    if (словарь.has(знак)) текущее += знак
    else { if (текущее) слова.push(текущее); текущее = "" }
  }
  if (текущее) слова.push(текущее)
  return слова.length === 0 ? "value" : слова.join("_").toLowerCase()
}

// ── замыкание компилятора ───────────────────────────────────────────────────
function замыкание() {
  const модульФайл = new Map()
  for (const п of ПАПКИ) {
    const путь = join(КОРЕНЬ, п)
    if (!existsSync(путь)) continue
    for (const имя of readdirSync(путь)) {
      if (!имя.endsWith(".flang")) continue
      const ф = join(путь, имя)
      const первая = readFileSync(ф, "utf8").split("\n").find((s) => /^модуль «/.test(s))
      if (!первая) continue
      const м = /^модуль «([^»]+)»/.exec(первая)
      if (м && !модульФайл.has(м[1])) модульФайл.set(м[1], ф)
    }
  }
  if (!existsSync(ВХОД)) нечем(`нет ${ВХОД}`)
  const видели = new Set(), очередь = [ВХОД]
  while (очередь.length) {
    const ф = очередь.pop()
    if (видели.has(ф)) continue
    видели.add(ф)
    for (const s of readFileSync(ф, "utf8").split("\n")) {
      const u = /^\s*использует\s+«([^»]+)»/.exec(s)
      if (u) { const g = модульФайл.get(u[1]); if (g && !видели.has(g)) очередь.push(g) }
    }
  }
  return [...видели].sort()
}

// ── имена ───────────────────────────────────────────────────────────────────
// Четыре объявления читаются порознь, потому что в просьбу каждое едет по-своему
// (довод — в шапке). `вариант` объявляется ВНУТРИ `тип`, с отступом, поэтому у
// него свой разбор с признаком «мы в типе».
const ФУНКЦИЯ = /^(?:тотальная функция|функция)\s+«([^»]+)»/
const ОБЪЕКТ = /^объект\s+«([^»]+)»/
const ТИП = /^тип\s+«([^»]+)»/
const ВАРИАНТ = /^\s+вариант\s+«([^»]+)»/

function ведомость() {
  if (!existsSync(ВЕДОМОСТЬ)) return new Set()
  return new Set(
    readFileSync(ВЕДОМОСТЬ, "utf8").split("\n")
      .filter((s) => s.trim() && !s.startsWith("#"))
      .map((s) => s.split("\t")[0].trim()))
}

const правило = таблицы()

// ── самопроверка на примерах, объявленных в самом исходнике ─────────────────
// Таблицы прочитаны, но порядок «Змейки» здесь всё же повторён, и повтор может
// разойтись. Поэтому на каждом запуске сторож проверяет себя примерами, которые
// «Змейка» объявляет о себе сама (emit-c.flang, строки «пример»). Разошлось —
// код 3, а не тихая работа по неверному порядку.
function самопроверка() {
  const строки = readFileSync(ИСТОЧНИК_ПРАВИЛА, "utf8").split("\n")
  const н = строки.findIndex((s) => /^тотальная функция «Змейка»/.test(s))
  if (н < 0) нечем("в emit-c.flang не найдена «Змейка»")
  const примеры = []
  for (let i = н; i < строки.length; i += 1) {
    if (i > н && /^тотальная функция |^функция /.test(строки[i])) break
    const дано = /дано «значение» равно "([^"]*)"/.exec(строки[i])
    if (!дано) continue
    const ждём = /ожидается "([^"]*)"/.exec(строки[i + 1] ?? "")
    if (ждём) примеры.push([дано[1], ждём[1]])
  }
  if (!примеры.length) нечем("у «Змейки» не прочитался ни один пример — себя проверить нечем")
  const плохие = примеры.filter(([вход, ждём]) => змейка(вход, правило) !== ждём)
  if (плохие.length) {
    нечем(`порядок «Змейки» здесь разошёлся с исходником на ${плохие.length} из ${примеры.length} ` +
      `примеров: ` + плохие.map(([в, ж]) => `«${в}» дало ${змейка(в, правило)}, ждали ${ж}`).join("; "))
  }
  return примеры.length
}
const своихПримеров = самопроверка()
const файлы = замыкание()
const где = new Map()
const положить = (просьба, место) => {
  const ид = змейка(просьба, правило)
  if (!где.has(ид)) где.set(ид, new Map())
  if (!где.get(ид).has(просьба)) где.get(ид).set(просьба, место)
}

// Таблица засевается тем же, чем её засевает «Проверить столкновения»: ключ —
// само зарезервированное слово, значение — подпись, которую печать ставит в
// сообщение. Без засева сторож не видел бы столкновения модели с `static` или
// `result`, а печать его называет.
for (const слово of правило.зарезервировано)
  положить(`зарезервировано в целевом языке: ${слово}`, "flang/self/emit-c.flang «Зарезервировано в C»")
for (const слово of правило.зарезервировано) {
  const подпись = `зарезервировано в целевом языке: ${слово}`
  const мимо = где.get(змейка(подпись, правило))
  if (мимо) { мимо.delete(подпись); if (!мимо.size) где.delete(змейка(подпись, правило)) }
  if (!где.has(слово)) где.set(слово, new Map())
  if (!где.get(слово).has(подпись)) где.get(слово).set(подпись, "flang/self/emit-c.flang «Зарезервировано в C»")
}

for (const ф of файлы) {
  const строки = readFileSync(ф, "utf8").split("\n")
  const место = ф.slice(КОРЕНЬ.length + 1)
  let вТипе = false
  for (let i = 0; i < строки.length; i += 1) {
    const строка = строки[i]
    const функция = ФУНКЦИЯ.exec(строка)
    if (функция) { вТипе = false; положить(функция[1], `${место}:${i + 1}`); continue }
    const объект = ОБЪЕКТ.exec(строка)
    if (объект) { вТипе = false; положить(`создать ${объект[1]}`, `${место}:${i + 1}`); continue }
    if (ТИП.test(строка)) { вТипе = true; continue }
    if (/^\S/.test(строка)) { вТипе = false; continue }
    if (!вТипе) continue
    const вариант = ВАРИАНТ.exec(строка)
    if (вариант) положить(`вариант ${вариант[1]}`, `${место}:${i + 1}`)
  }
}

const известные = ведомость()
const находки = [...где.entries()].filter(([, имена]) => имена.size > 1).sort()
const новые = находки.filter(([ид]) => !известные.has(ид))

const просьб = [...где.values()].reduce((сумма, имена) => сумма + имена.size, 0)
console.log(`сторож латинских столкновений: файлов в замыкании ${файлы.length}, просьб имён ${просьб}, ` +
  `замен кириллицы ${правило.замены.length}, словарных знаков ${правило.словарь.size}, ` +
  `зарезервированных ${правило.зарезервировано.length}, самопроверка на ${своихПримеров} примерах исходника пройдена`)
if (находки.length && !новые.length)
  console.log(`известных по ведомости: ${находки.length} — не крашу`)
if (!новые.length) { console.log("новых столкновений нет"); process.exit(0) }

console.error(`НОВЫЕ СТОЛКНОВЕНИЯ ЛАТИНСКИХ ИМЁН: ${новые.length}`)
for (const [ид, имена] of новые) {
  console.error(`  ${ид} ←`)
  for (const [имя, место] of имена) console.error(`      «${имя}»  ${место}`)
}
console.error("Переименуйте одно из имён каждой пары либо внесите в scripts/latin-collision-guard-known.tsv с доводом.")
process.exit(1)
