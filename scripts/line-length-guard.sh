#!/bin/sh
# Храповик длины строки.
#
# Нужная компилятору глубина связывания равна длине самой длинной строки
# дерева в КОДОВЫХ ТОЧКАХ плюс два — закон снят на границе: отказ на 90 287,
# проход на 90 288. Одна машинно написанная строка в 90 286 точек
# (flang/self/emit-python.flang:3750, постусловие «поле вывод 2703», коммит
# 277035f4 от 25 августа) подняла требуемую глубину в 56 раз и сделала
# раскрутку незамкнутой: двоичный из свежего семени перестал печатать
# компилятор. Никто этого не заметил, потому что мерить было нечем.
#
# Этот храповик и есть «чем мерить». Он НЕ запрещает длинные строки — он
# запрещает делать их ДЛИННЕЕ молча. Разбор беды: tasks/9957.
#
# Коды: 0 — не выросло; 1 — выросло; 2 — смотреть нечем.
#
# Имена переменных латиницей: dash берёт имя только до первой кириллической
# буквы, и sh -n этого не ловит.
set -u
export LC_ALL=C.UTF-8
KOREN=$(cd "$(dirname "$0")/.." && pwd) || exit 2
DOLG="$KOREN/scripts/line-length-debt.txt"

if [ ! -f "$DOLG" ]; then
  printf 'сторож длины строки: нет мерки %s — смотреть нечем\n' "$DOLG" >&2
  exit 2
fi
BYLO=$(cat "$DOLG" 2>/dev/null) || exit 2
case "$BYLO" in ''|*[!0-9]*)
  printf 'сторож длины строки: мерка не число: %s\n' "$BYLO" >&2; exit 2;;
esac

SPISOK=$(find "$KOREN/flang" -name '*.flang' -type f 2>/dev/null)
if [ -z "$SPISOK" ]; then
  printf 'сторож длины строки: ни одного файла .flang — смотреть нечем\n' >&2
  exit 2
fi

STALO=$(printf '%s\n' "$SPISOK" | xargs awk '
  { n = length($0); if (n > max) { max = n; f = FILENAME; l = FNR } }
  END { printf "%d %s %d\n", max, f, l }')
CHISLO=${STALO%% *}
GDE=${STALO#* }

if [ "$CHISLO" -gt "$BYLO" ]; then
  printf 'сторож длины строки: было %s точек, стало %s\n' "$BYLO" "$CHISLO" >&2
  printf '  самая длинная: %s\n' "$GDE" >&2
  printf '  связывание потребует глубины %s; предел в scripts/raskrutka.sh\n' \
    "$((CHISLO + 2))" >&2
  printf '  разбейте строку ИЛИ поднимите мерку осознанно: разбор в tasks/9957\n' >&2
  exit 1
fi

if [ "$CHISLO" -lt "$BYLO" ]; then
  printf 'сторож длины строки: %s точек (было %s, стало короче — снимите мерку)\n' \
    "$CHISLO" "$BYLO"
else
  printf 'сторож длины строки: %s точек, не выросло\n' "$CHISLO"
fi
exit 0
