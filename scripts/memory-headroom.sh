#
# ── Зачем ───────────────────────────────────────────────────────────────────
# Снятие работы по памяти сегодня неотличимо от отказа по существу. Три случая
# за неделю, и каждый диагностировали по нескольку раз и по-разному:
#
#   flang check flang/self/parser.flang    37,1 ГиБ (замер 30.08.2026)  sborka
#   io scripts/name-splicing-guard.flang   31,6 ГиБ (замер 30.08.2026)  imena
#   io scripts/link-guard.flang            15,0 ГиБ (замер 30.08.2026)  links
#
# У раннера GitHub 15,61 ГиБ — число снято с самого раннера (`MemTotal`,
# прогон 33316181246 от 30 августа 2026), а не взято с рекламной страницы; из
# них 0,95 ГиБ держат сам агент, кэш и службы, так что прогону остаётся около
# 14,66. Первые два не влезали, и в журнале это выглядело так:
# печатается начало, дальше три минуты тишины и «The runner has received a
# shutdown signal» либо «Process completed with exit code 143». Ни кода
# возврата по существу, ни имени файла, ни слова про память. Отсюда и разнобой
# в диагнозах: обрыв читали то предельным временем, то бедой в семени.
#
# Третий, `link-guard`, считался зелёным — и был им 22 августа, когда в дереве
# было 571 файл. Сегодня ему нужно 15,02 ГиБ при 14,66 свободных, то есть
# запаса у него уже нет; узнать об этом было неоткуда, потому что `ci.yml`
# ходит только на тег, а последний тег — от 22 августа. Он и есть тот случай,
# ради которого этот сторож написан: пока запас есть, о нём никто не знает, а
# кончается он молча.
#
# ── Что этот сторож делает ──────────────────────────────────────────────────
# Он НЕ ставит предела и никого не снимает. Предел на адресное пространство у
# flang неверен: адресного ему нужно вдвое-впятеро больше занятого (замеры в
# шапке `/srv/flang-rabota/vorota/flang-vorota`), и такой предел снял бы то,
# что на самом деле влезает. Своей контрольной группы на раннере GitHub у нас
# нет.
#
# Он СМОТРИТ и НАЗЫВАЕТ:
#
#   1. `--следить` заводит наблюдателя, который раз в секунду читает
#      `MemAvailable` из `/proc/meminfo` и запоминает, до какого НИЗА тот
#      опускался и какой прогон `flang` держал в этот миг больше всех.
#      Наблюдатель отвязан от шага и живёт до конца работы.
#   2. `--отчёт` последним шагом (`if: always()`) кладёт итог в СВОДКУ прогона —
#      её видно на странице прогона, не открывая логов.
#
# Итог называет ЧЕТЫРЕ разных исхода, и в этом всё дело:
#
#   работа упала, свободной памяти оставалось мало   → НЕ ВЛЕЗЛО
#   работа упала, памяти было вдоволь                → упала ПО СУЩЕСТВУ
#   работа прошла, но впритык                        → влезла, и запас назван
#   работа прошла с запасом                          → строка с числами, тихо
#
# Второй исход не менее важен первого: он снимает подозрение с памяти, когда
# дело не в ней, и не даёт чинить не то.
#
# ── Чего сторож НЕ ловит, говорю прямо ──────────────────────────────────────
# * Раннера, убитого ЦЕЛИКОМ («The runner has received a shutdown signal»):
#   отчёт тогда выполнять некому и сводку никто не заберёт. Признак у этого
#   случая ровно один — сводка ПУСТА при красной работе. Это тоже сведение, и
#   оно названо здесь, чтобы читающий знал, что значит пустота.
# * Пика ОДНОГО шага: наблюдатель смотрит на машину целиком, а не на шаг.
#   Число, которое он называет, — «сколько машине оставалось», и это ровно то
#   число, по которому работу снимают.
# * `/usr/bin/time -f %M` тут не годится вовсе: снятый прогон не доживает до
#   печати, а в части песочниц `getrusage` отдаёт ноль — см. шапку
#   `flang/scripts/memory-guard.flang`, где ноль годами проходил за замер.
#
# ── Как звать ───────────────────────────────────────────────────────────────
#   sh scripts/memory-headroom.sh --следить                    в начале работы
#   sh scripts/memory-headroom.sh --отчёт --итог "$STATUS"     последним шагом
#   sh scripts/memory-headroom.sh --счёт                       спросить разом
#
# Где держать записи — переменная FLANG_TMP; на раннере это `runner.temp`, как
# у всех прочих проверок этого дерева. Умолчание `/srv/tmp` — для своей машины;
# на раннере такого каталога нет, и работа, забывшая FLANG_TMP, уже падала
# (`ci(binary)` от 30 августа 2026, коммит `c194a2a0`).
#
# Имена переменных здесь английские, а не переписанные с русского: кириллицу в
# именах не принимают ни dash, ни bash, а транслита в этом дереве не заводят.
# Доводы ключей кириллицей — как у `--подлог` в `scripts/overlong-string-guard.sh`
# и `--проза` в `scripts/published-vs-tree.sh`.

set -eu

TEMP_DIR=${FLANG_TMP:-/srv/tmp}
RECORD=$TEMP_DIR/memory-headroom.tsv
# Запас, ниже которого «влезло» перестаёт быть правдой. Гигабайт, а не ноль:
# сверх нашего прогона на раннере живут сам агент, кэш и службы, а последние
# сотни мегабайт машина отдаёт уже свопом, то есть молотьбой.
MARGIN=${FLANG_MARGIN_KB:-1048576}
PAUSE=${FLANG_WATCH_STEP:-1}
STATUS=''

err() { printf '%s\n' "$*" >&2; }
gib() { awk -v k="$1" 'BEGIN { printf "%.2f", k / 1048576 }'; }

# Мерка есть не везде (у macOS нет /proc вовсе). Нет её — говорим словами и
# уходим с кодом 0: отсутствие мерки не беда дерева, а свойство машины, и
# красить ею работу нельзя. Тот же довод записан в шапке
# `flang/scripts/memory-guard.flang`, где ноль от getrusage годами шёл за замер.
have_meter() { [ -r /proc/meminfo ]; }

free_kb() {
  # MemAvailable, а не MemFree: страничный кэш отдаётся, и MemFree занижает
  # свободное в разы.
  awk '/^MemAvailable:/ { print $2 }' /proc/meminfo
}
total_kb() { awk '/^MemTotal:/ { print $2 }' /proc/meminfo; }
# Крупнейший прогон flang в этот миг: имя процесса РОВНО «flang», чтобы не
# считать оболочки и редакторы, у которых слово попадает в строку запуска.
biggest_kb() {
  ps -eo comm=,rss= 2>/dev/null |
    awk '$1 == "flang" { if ($2 > m) m = $2 } END { print m + 0 }'
}

write_record() {
  printf '%s\t%s\t%s\t%s\n' "$TOTAL" "$LOWEST" "$PEAK" "$WHEN" > "$RECORD"
}

watch_loop() {
  TOTAL=$(total_kb)
  LOWEST=$(free_kb)
  PEAK=0
  WHEN=$(date -u '+%H:%M:%S')
  write_record
  while [ -r /proc/meminfo ]; do
    NOW=$(free_kb)
    BIG=$(biggest_kb)
    if [ "$BIG" -gt "$PEAK" ]; then PEAK=$BIG; fi
    if [ "$NOW" -lt "$LOWEST" ]; then
      LOWEST=$NOW
      WHEN=$(date -u '+%H:%M:%S')
    fi
    write_record
    sleep "$PAUSE"
  done
}

# Итог кладётся В ДВА МЕСТА, и это не дублирование ради красоты. Сводка
# прогона видна, не открывая логов, но её не забирают, когда раннера убили
# целиком; лог остаётся всегда и его можно грепать. Стоит это трёх строк.
say() {
  BUFFER=$(cat)
  printf '%s\n' "$BUFFER" >> "$OUT"
  [ "$OUT" = /dev/stdout ] || printf '%s\n' "$BUFFER"
}

report() {
  OUT=${GITHUB_STEP_SUMMARY:-/dev/stdout}
  if [ ! -s "$RECORD" ]; then
    {
      echo "## Память раннера"
      echo
      echo "Наблюдатель не оставил записи: либо шаг \`--следить\` не выполнялся,"
      echo "либо \`FLANG_TMP\` указывал не туда. Сказать, влезла работа или нет,"
      echo "**нечем** — и это сказано, а не замолчано."
    } | say
    return 0
  fi
  TOTAL=$(cut -f1 "$RECORD"); LOWEST=$(cut -f2 "$RECORD")
  PEAK=$(cut -f3 "$RECORD");  WHEN=$(cut -f4 "$RECORD")
  {
    echo "## Память раннера"
    echo
    echo "| что | сколько |"
    echo "|---|---|"
    echo "| всего у раннера | $(gib "$TOTAL") ГиБ |"
    echo "| меньше всего оставалось свободной | **$(gib "$LOWEST") ГиБ** (в $WHEN UTC) |"
    echo "| крупнейший прогон \`flang\` на пике | $(gib "$PEAK") ГиБ |"
    echo
  } | say
  TIGHT=no
  if [ "$LOWEST" -lt "$MARGIN" ]; then TIGHT=yes; fi
  case "$STATUS:$TIGHT" in
    failure:yes|cancelled:yes)
      {
        echo "### НЕ ВЛЕЗЛО"
        echo
        echo "Работа красная, и свободной памяти у раннера оставалось"
        echo "$(gib "$LOWEST") ГиБ из $(gib "$TOTAL") ГиБ. Это снятие ПО ПАМЯТИ, а не"
        echo "отказ по предмету: смотреть надо на вес шага, а не на то, что он проверял."
        echo "В журнале у такого снятия свои признаки — «exit code 143» или"
        echo "«The runner has received a shutdown signal», без кода возврата и без"
        echo "имени файла. Когда до отказа выделения доходит сам flang, он пишет"
        echo "\`FLANG_MEMORY: недостаточно памяти\` (\`FL_CODE_MEMORY\` в"
        echo "\`bootstrap/flang_runtime.h\`)."
        echo
        echo "Куда девать такой шаг: на раннер с большой памятью за переменной"
        echo "\`BOLSHAYA_PAMYAT=da\`, как \`sverka\` в \`reprint.yml\`."
      } | say
      echo "::error title=Не влезло::работа снята по памяти: свободной оставалось $(gib "$LOWEST") ГиБ из $(gib "$TOTAL") ГиБ"
      ;;
    failure:no|cancelled:no)
      {
        echo "### Упало ПО СУЩЕСТВУ, а не по памяти"
        echo
        echo "Работа красная, но памяти было вдоволь: в самый тесный миг свободной"
        echo "оставалось $(gib "$LOWEST") ГиБ. Причину искать в предмете шага."
      } | say
      ;;
    *:yes)
      {
        echo "### Влезло впритык"
        echo
        echo "Работа зелёная, но запас — $(gib "$LOWEST") ГиБ. Следующий рост дерева"
        echo "снимет её, и снимет молча. Место такому шагу — на раннере с большой"
        echo "памятью (\`BOLSHAYA_PAMYAT=da\`), как у \`sverka\` в \`reprint.yml\`."
      } | say
      echo "::warning title=Влезло впритык::свободной памяти оставалось $(gib "$LOWEST") ГиБ из $(gib "$TOTAL") ГиБ"
      ;;
  esac
  return 0
}

case "${1:---счёт}" in
  --следить)
    have_meter || { err "мерки нет: /proc/meminfo не читается — следить не за чем"; exit 0; }
    # Отвязываем от шага: работа идёт дальше, наблюдатель живёт до её конца.
    # Зовём через `/bin/sh "$0"`, а не `"$0"` прямо: файл могли положить без
    # права на исполнение (архив, `git apply`, чужая маска), и тогда прямой
    # запуск отказал бы молча, а наблюдателя бы не было.
    nohup /bin/sh "$0" --следить-внутри >/dev/null 2>&1 &
    echo "наблюдатель за памятью заведён; записи в $RECORD"
    ;;
  --следить-внутри) watch_loop ;;
  --отчёт)
    shift
    while [ $# -gt 0 ]; do
      case $1 in
        --итог) STATUS=$2; shift 2 ;;
        --итог=*) STATUS=${1#--итог=}; shift ;;
        *) err "неизвестный довод: $1"; exit 2 ;;
      esac
    done
    have_meter || {
      echo "мерки нет: /proc/meminfo не читается — сказать про память нечего" \
        >> "${GITHUB_STEP_SUMMARY:-/dev/stdout}"
      exit 0
    }
    report
    ;;
  --счёт)
    have_meter || { err "мерки нет: /proc/meminfo не читается"; exit 0; }
    printf 'память: всего %s ГиБ, свободно сейчас %s ГиБ, крупнейший flang %s ГиБ\n' \
      "$(gib "$(total_kb)")" "$(gib "$(free_kb)")" "$(gib "$(biggest_kb)")"
    ;;
  -h|--help|--помощь)
    awk 'NR < 4 { next } /^set -eu$/ { exit } { sub(/^# ?/, ""); print }' "$0"
    ;;
  *) err "неизвестный довод: $1 (см. --help)"; exit 2 ;;
esac
