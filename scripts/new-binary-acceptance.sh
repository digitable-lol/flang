#!/bin/sh
# ПРИЁМКА НОВОГО ДВОИЧНОГО ПОСЛЕ ПЕРЕПЕЧАТКИ СЕМЕНИ. Задача 0043.
#
#   sh scripts/new-binary-acceptance.sh [путь-к-дереву-перепечатки]
#   по умолчанию — /srv/flang-rabota/u-semya5
#
# Код 0 — все приметы сошлись; 1 — хоть одна нет, и каждая названа;
# 2 — двоичного нет вовсе, приёмка не состоялась («не проверено», а не «не принят»).
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# За сутки 24–25 августа 2026 перепечатка гибла ЧЕТЫРЕ раза, а один раз дошла и
# дала двоичный, который падал на первом же файле. «Печать кончилась кодом 0»
# само по себе не значит ничего, и решать это радостью нельзя.
#
# ── Почему на оболочке, а не на flang ────────────────────────────────────────
# Тот же довод, что в шапке scripts/raskrutka.sh: приёмка судит двоичный, и
# написать её на языке, который этим двоичным и исполняется, значит поставить
# судью в зависимость от подсудимого. Оболочка на путь сборки ничего нового не
# приносит: sh, make и cc там уже нужны.
#
# ── Чем это НЕ является ──────────────────────────────────────────────────────
# Приметы 1–3 говорят, что код НАПЕЧАТАЛСЯ: имя нашлось в таблице, строка есть
# в двоичном. Они не говорят, что он РАБОТАЕТ. Это говорит только прогон —
# приметы 4–6.
#
# ── Примета зелена только тогда, когда ей было ЧЕМ проверять ─────────────────
# 26 августа приёмку навели на дерево /srv/flang-rabota/w-predely — то самое,
# про чей двоичный задача 0043 пишет «было: FLANG_TYPE_ARGS, не читает». Примета
# 5 дала «✓ читает». Двоичный не менялся: сменилось дерево, а в его
# interpret.flang параметрических типов нет вовсе. Примета проверяла файл, в
# котором проверять было нечего, и зеленела от пустоты.
#
# Отсюда правило, по которому здесь написаны все приметы: примета, у которой не
# оказалось материала, обязана сказать «не снята», а не «сошлась».
set -u

D=${1:-/srv/flang-rabota/u-semya5}
DVOICHNYY="$D/bootstrap/flang"
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
PROBA=$ROOT/scripts/new-binary-acceptance-probe.flang
BED=0

# Волатильные каталоги на машине запрещены хуком, поэтому место под вывод
# прогонов берётся там же, где его берёт scripts/raskrutka.sh.
TMPD=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" new-binary-acceptance.XXXXXX)
trap 'rm -rf "$TMPD"' EXIT INT TERM

# Имена функций и переменных здесь ЛАТИНИЦЕЙ, как в scripts/raskrutka.sh, и по
# той же причине: ни dash, ни bash не принимают кириллицу в именах. Русский
# остался там, где он от оболочки не зависит, — в пояснениях и в выводе.
say()  { printf '\n=== %s\n' "$*"; }
bad()  { printf '  ✗ %s\n' "$*"; BED=$((BED+1)); }
good() { printf '  ✓ %s\n' "$*"; }

# Счёт вхождений так, чтобы «совпадений нет» не превращалось в две строки.
# `grep -c` при нуле совпадений ПЕЧАТАЕТ «0» И ВОЗВРАЩАЕТ 1, поэтому прежнее
# `$(grep -c … || echo 0)` давало «0\n0», а следом `[ … -gt 0 ]` ронял
# «Illegal number». Снято прогоном 26 августа на двоичном w-predely: примету 2
# и примету 3 — ровно те, у которых «было 0», — печатало с ошибкой оболочки.
skolko() { grep -c "$1" "$2" 2>/dev/null || true; }

# Прогон через ворота, вывод — в $TMPD/vyvod, код команды — в $KOD.
#
# ── ЗАЧЕМ НЕ КОНВЕЙЕР: задача 0042 ──────────────────────────────────────────
# Ворота, не дождавшись слота, отвечают кодом 75 (`EX_TEMPFAIL`) и одной
# строкой отказа. Прежде приёмка звала ворота внутри конвейера `… | grep`,
# то есть код терялся целиком, а строка отказа не подходила ни под один
# образец — и примета вставала «✗ ответ не распознан». Это отказ ВОРОТ, а не
# приговор двоичному, и путать их дорого: отказа приёмки ждут пятнадцать
# исполнителей, и ложное «НЕ ПРИНЯТ» стоит им дня.
progon() {
  pamyat=$1
  shift
  PAMYAT=$pamyat timeout 900 /srv/flang-rabota/vorota/flang-vorota -- "$@" \
    > "$TMPD/vyvod" 2>&1
  KOD=$?
  case $KOD in
    75)  bad "ворота не дали места (код 75) — ОТКАЗ ВОРОТ, а не приговор двоичному; повторить примету"
         sed 's/^/    /' "$TMPD/vyvod"
         return 1 ;;
    124) bad "прогон не уложился в 900 с — примета НЕ СНЯТА, судить по ней нельзя"
         return 1 ;;
  esac
  return 0
}

say "ЧЕМ КОНЧИЛАСЬ ПЕЧАТЬ"
tail -5 /srv/work/semya5.log 2>/dev/null || echo "  журнала печати нет"

# Журнал показывает ПОСЛЕДНИЕ строки, а не «кончилось ли». У начавшегося захода
# их всего шесть, и хвост печатает шапку — «все литералы закрыты», «пределы» —
# ту самую, которую легко принять за отчёт о конце. Поэтому спрашивается не
# журнал, а список процессов.
if pgrep -f 'scripts/raskrutka\.sh' >/dev/null 2>&1; then
  printf '\n  ⚠ ПЕРЕПЕЧАТКА ЕЩЁ ИДЁТ — строки выше это шапка захода, а не его итог.\n'
fi

# Нет двоичного — приёмка НЕ СОСТОЯЛАСЬ, и это не «НЕ ПРИНЯТ». Код 1 читается
# как приговор перепечатке («двоичный плох, чините печать»), а сказать тут
# нечего вовсе: подсудимого не принесли. Отсюда код 2 — «не проверено»
# (задача 1312; образец — scripts/identical-declarations.sh).
if [ ! -x "$DVOICHNYY" ]; then
  printf '\nПРИЁМКА НЕ СОСТОЯЛАСЬ: двоичного нет — %s\n' "$DVOICHNYY"
  printf 'Ни одна примета не снята; это не «НЕ ПРИНЯТ», это «принимать нечего».\n'
  printf 'Приёмку звать после того, как перепечатка дошла И СЕМЯ СОБРАНО:\n'
  printf '  make -C %s/bootstrap -j8      (минута, 1,05 ГиБ)\n' "$D"
  exit 2
fi
printf '\nдвоичный: %s\n' "$DVOICHNYY"
"$DVOICHNYY" --version 2>&1 | head -1

# ── ПРИМЕТА 1: печать конкурентности в C появилась ──────────────────────────
# Было: только elixir, js и java — ни одного имени с «_c». Без него
# многоядерность языка недоступна, хотя замерена: восемь процессов дают 7,92×.
say "ПРИМЕТА 1 — печать конкурентности в C"
IMENA=$(nm -a "$DVOICHNYY" 2>/dev/null | grep -o 'compiler_flang_[a-z_]*konkurentnost[a-z_]*' | sort -u)
printf '%s\n' "$IMENA" | sed 's/^/    /'
if printf '%s\n' "$IMENA" | grep -q '_c$'; then good "имя с «_c» есть"; else bad "имени с «_c» НЕТ (было так же)"; fi

# ── ПРИМЕТА 2: вердикт «доказано ПРИ УСЛОВИИ» появился ──────────────────────
# Было 0. Пока его нет, двоичный складывает условные в «доказано», и ВСЕ наши
# числа — верхняя оценка: при неполном обходе нашли 27 условных, то есть
# просядет не меньше чем на 6,6 % (задача 0044).
say "ПРИМЕТА 2 — вердикт «доказано ПРИ УСЛОВИИ»"
N=$(skolko 'ПРИ УСЛОВИИ' "$D/bootstrap/compiler_flang.c")
echo "    вхождений: ${N:-нет файла}   (было 0)"
if [ "${N:-0}" -gt 0 ] 2>/dev/null
  then good "вердикт появился"
  else bad "вердикта НЕТ — все числа дерева остаются верхней оценкой"
fi

# ── ПРИМЕТА 3: строка хода появилась (задача 0031) ──────────────────────────
say "ПРИМЕТА 3 — строка хода"
strings "$DVOICHNYY" > "$TMPD/stroki" 2>/dev/null || true
N=$(skolko 'шагов .* из .*, идёт' "$TMPD/stroki")
echo "    вхождений: ${N:-0}   (было 0)"
if [ "${N:-0}" -gt 0 ] 2>/dev/null
  then good "девятичасовая работа перестала быть слепой"
  else bad "строки хода НЕТ"
fi

# ── ПРИМЕТА 4: правила ядра РАБОТАЮТ, а не просто напечатались ──────────────
# Было: утверждений 4: доказано 0, сетка 0, объявлено, не доказано 4.
say "ПРИМЕТА 4 — правила ядра работают (прогон, а не таблица имён)"
# Проба сама говорит, чего ждёт: «все четыре обязаны стоять „объявлено, не
# доказано“ на старом двоичном и ХОТЯ БЫ ЧАСТЬ — „доказано“ на новом». Значит
# порог здесь — не четыре из четырёх, а «доказано больше нуля». Но и зелёное
# «правила ядра доехали» на одном доехавшем из четырёх — то самое «принять
# радостью», против которого задача 0043 и написана: число называется вслух.
#
# Число берётся якорем от начала строки, а не поиском подстроки «доказано»:
# в итоге ДВА таких слова — «доказано 11» и «не доказано 0», — и жадный образец
# читает второе.
if progon 45G "$DVOICHNYY" check "$PROBA" --proof; then
  ITOG=$(grep -E '^ *утверждений' "$TMPD/vyvod" | tail -1)
  echo "    ${ITOG:-(итога нет)}"
  echo "    было: утверждений 4: доказано 0, сетка 0, объявлено, не доказано 4"
  DOK=$(printf '%s\n' "$ITOG" | sed -n 's/^ *утверждений [0-9]*: доказано \([0-9][0-9]*\).*/\1/p')
  case "${DOK:-нет}" in
    нет) bad "проба не дала итога вовсе" ;;
    0)   bad "ни одно правило не заработало — семя не догнало исходники" ;;
    4)   good "все четыре правила ядра доехали" ;;
    *)   good "правил ядра доехало $DOK из 4 — часть, как проба и допускает; какие именно, смотреть в ведомости" ;;
  esac
fi

# ── ПРИМЕТА 5: двоичный читает свежие исходники ────────────────────────────
# Было: FLANG_TYPE_ARGS на «Узел хеша» от «З» (коммит bc07b7fe). Двоичный от
# (не новее 883fe9a9 от 23 августа 15:56; точной родословной у него нет)
# параметрических типов не понимает и self/interpret.flang не
# читает вовсе — а значит и proof-kernel.flang через него не проверить.
#
# ⚠ ФАЙЛ ДЛЯ ЭТОЙ ПРИМЕТЫ ОБЯЗАН СОДЕРЖАТЬ ПАРАМЕТРИЧЕСКИЙ ТИП. Иначе примета
# зелена ни от чего: прогон 26 августа навёл приёмку на /srv/flang-rabota/w-predely
# и получил «✓ читает» СТАРЫМ двоичным — тем самым, про который задача 0043
# пишет «было: FLANG_TYPE_ARGS — не читает». Примета перевернулась с ✗ на ✓ без
# единой правки двоичного, от одной смены дерева: в interpret.flang того дерева
# параметрических типов НЕТ ВОВСЕ (`Узел хеша» от` — 0 вхождений против 3 в стволе).
# Так же пусто и в дереве перепечатки /srv/flang-rabota/u-semya5 (0 вхождений,
# снято 26 августа), то есть по умолчанию примета была бы пустой и на нём.
#
# Поэтому образец выбирается по СОДЕРЖИМОМУ, а не по дереву, и если ни в одном
# файле искомого нет — примета не «✓», а «проверить нечем».
say "ПРИМЕТА 5 — двоичный читает исходники со свежими типами"
OBRAZ=
for kandidat in "$D/flang/self/interpret.flang" "$ROOT/flang/self/interpret.flang"; do
  [ -f "$kandidat" ] || continue
  skolkoNashlos=$(skolko 'Узел хеша» от' "$kandidat")
  [ "${skolkoNashlos:-0}" -gt 0 ] 2>/dev/null || continue
  OBRAZ=$kandidat
  break
done
if [ -z "$OBRAZ" ]; then
  bad "проверить НЕЧЕМ: параметрического типа нет ни в дереве перепечатки, ни в дереве приёмки — примета не снята"
else
  echo "    образец: $OBRAZ ($(skolko 'Узел хеша» от' "$OBRAZ") вхождений параметрического типа)"
  if progon 60G "$DVOICHNYY" check "$OBRAZ"; then
    OTVET=$(grep -E 'FLANG_TYPE_ARGS|замечаний нет' "$TMPD/vyvod" | head -1)
    echo "    ${OTVET:-(ответа нет)}"
    case "$OTVET" in
      *FLANG_TYPE_ARGS*) bad "параметрические типы по-прежнему не понимает" ;;
      *"замечаний нет"*) good "читает" ;;
      *) bad "ответ не распознан — смотреть руками, вывод целиком выше"
         tail -3 "$TMPD/vyvod" | sed 's/^/    /' ;;
    esac
  fi
fi

# ── ПРИМЕТА 6: не сломан ли он вовсе ───────────────────────────────────────
# Прошлый дошедший двоичный падал здесь: FLANG_PROPERTY, нарушено свойство
# «беды не убывают — Только диагностики».
say "ПРИМЕТА 6 — не сломан на живом файле"
if progon 45G "$DVOICHNYY" check "$D/flang/stdlib/hashmap.flang" --proof; then
  OTVET=$(tail -2 "$TMPD/vyvod")
  printf '%s\n' "$OTVET" | sed 's/^/    /'
  case "$OTVET" in
    *FLANG_PROPERTY*|*FLANG_INTERNAL*) bad "падает — принимать НЕЛЬЗЯ" ;;
    *утверждений*) good "считает" ;;
    *) bad "ответ не распознан" ;;
  esac
fi

say "ИТОГ"
if [ "$BED" -eq 0 ]; then
  echo "  все приметы сошлись. Дальше: sh scripts/raskrutka.sh --bystro —"
  echo "  сверить, что семя больше не отстаёт (было 41 расхождение)."
  echo "  ⛔ Приёмная коммиты с bootstrap/** из веток ОТВЕРГАЕТ: семя кладётся"
  echo "  в ствол не через неё. Спросить владельца приёмной, как именно."
  exit 0
fi
echo "  примет не сошлось: $BED. Двоичный НЕ ПРИНЯТ."
exit 1
