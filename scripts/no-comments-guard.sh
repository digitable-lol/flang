# Комментариев в .flang не прибавляется — храповик по файлу долга.
#
# ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
# Язык чистый функциональный и самодокументируемый: если функция не объясняет
# себя именем, типом, «обеспечивает» и «примером» — чинить надо КОД, а не
# приписывать к нему объяснение. Замеры, даты и «почему так решили» — знание, но
# лежащее не там: им место в docs/ и tasks/, а не в исходнике.
#
# Правило записано в .claude/skills/flang-code. Этот сторож его ПРИНУЖДАЕТ.
#
# ── ПОЧЕМУ ХРАПОВИК, А НЕ ЗАПРЕТ ────────────────────────────────────────────
# Запретить разом нельзя: в дереве 58 793 строки комментариев в 741 файле
# (замер 2 сентября 2026). Красный сторож на таком дереве красен всегда, а
# всегда красный сторож не проверяет ничего — на него перестают смотреть.
# Поэтому долг записан пофайлово и может только УБЫВАТЬ.
#
# ── ГРАНИЦА, названная числом ───────────────────────────────────────────────
# Считаются строки, начинающиеся с `//`. Блочные `/* */` НЕ считаются вовсе:
# их 252 открытия в 54 файлах (тот же замер). Сторож о них молчит, и это его
# граница, а не недосмотр.
#
# ── КАК ЗВАТЬ ───────────────────────────────────────────────────────────────
#   sh scripts/no-comments-guard.sh            спросить: не прибавилось ли
#   sh scripts/no-comments-guard.sh --снять    переписать долг ПОСЛЕ чистки
#
# `--снять` умеет только УМЕНЬШАТЬ. Если хоть в одном файле стало больше — он
# отказывает и называет файлы. Иначе храповик обходился бы одной командой, как
# обходился отпечаток семени до 2 сентября (tasks/9611): прибор, которым можно
# погасить собственную красноту, ничего не сторожит.
#
# ── КОДЫ ВОЗВРАТА — «плохо» и «не проверено» это разное ─────────────────────
#   0  не прибавилось (или долг переписан вниз)
#   1  прибавилось: файлы названы с числами
#   3  НЕ ПРОВЕРЕНО: файла долга нет, или .flang в дереве не найдено
#   2  звать не умеют
set -u

ROOT=$(cd "$(dirname "$0")/.." 2>/dev/null && pwd) || ROOT=
DOLG="$ROOT/scripts/no-comments-debt.tsv"

SNYAT=0
case "${1:-}" in
  '') ;;
  --снять|--snyat) SNYAT=1 ;;
  *) echo "звать: sh scripts/no-comments-guard.sh [--снять]" >&2; exit 2 ;;
esac

[ -n "$ROOT" ] || { echo "НЕ ПРОВЕРЕНО: не найден корень дерева" >&2; exit 3; }

TMP=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" bezkommentariev.XXXXXX) || {
  echo "НЕ ПРОВЕРЕНО: не создался каталог в ${FLANG_TMP:-/srv/tmp}" >&2; exit 3; }
trap 'rm -rf "$TMP"' EXIT INT TERM

# Считаем по ОТСЛЕЖИВАЕМЫМ файлам: неотслеживаемое — черновики, и долг по ним
# скакал бы туда-сюда.
( cd "$ROOT" && /usr/bin/git -c core.quotepath=false ls-files '*.flang' ) > "$TMP/spisok" 2>/dev/null
FAJLOV=$(wc -l < "$TMP/spisok" | tr -d ' ')
[ "${FAJLOV:-0}" -gt 0 ] || {
  echo "НЕ ПРОВЕРЕНО: отслеживаемых .flang не нашлось — считать нечего" >&2
  echo "Это НЕ «комментариев нет»: пустой список и порядок неотличимы, если молчать." >&2
  exit 3; }

while IFS= read -r f; do
  [ -f "$ROOT/$f" ] || continue
  n=$(LC_ALL=C.UTF-8 /usr/bin/grep -ac "^[[:space:]]*//" "$ROOT/$f" 2>/dev/null || true)
  [ "${n:-0}" -gt 0 ] && printf '%s\t%s\n' "$f" "$n"
done < "$TMP/spisok" | LC_ALL=C sort > "$TMP/nyne"

SEJCHAS=$(awk -F'\t' '{s+=$2} END{print s+0}' "$TMP/nyne")
S_FAJLOV=$(wc -l < "$TMP/nyne" | tr -d ' ')

if [ ! -f "$DOLG" ]; then
  if [ "$SNYAT" = 1 ]; then
    cp "$TMP/nyne" "$DOLG"
    echo "долг снят впервые: строк $SEJCHAS в $S_FAJLOV файлах"
    exit 0
  fi
  echo "НЕ ПРОВЕРЕНО: файла долга нет — $DOLG" >&2
  echo "Снять впервые: sh scripts/no-comments-guard.sh --снять" >&2
  exit 3
fi

BYLO=$(awk -F'\t' '{s+=$2} END{print s+0}' "$DOLG")

# Прибавка ищется ПОФАЙЛОВО: сумма может упасть, а в одном файле прибавиться.
LC_ALL=C join -t'	' -a1 -a2 -e 0 -o 0,1.2,2.2 "$DOLG" "$TMP/nyne" > "$TMP/oba" 2>/dev/null \
  || { echo "НЕ ПРОВЕРЕНО: не свести долг с деревом" >&2; exit 3; }
awk -F'\t' '$3 > $2 { printf "  %s: было %s, стало %s (+%s)\n", $1, $2, $3, $3-$2 }' "$TMP/oba" > "$TMP/rost"
ROSLO=$(wc -l < "$TMP/rost" | tr -d ' ')

if [ "$SNYAT" = 1 ]; then
  if [ "$ROSLO" -gt 0 ]; then
    echo "СНЯТЬ НЕЛЬЗЯ: комментариев прибавилось в $ROSLO файлах — храповик крутится только вниз." >&2
    cat "$TMP/rost" >&2
    echo "Сначала уберите прибавку, потом снимайте долг." >&2
    exit 1
  fi
  cp "$TMP/nyne" "$DOLG"
  echo "долг переписан вниз: было $BYLO, стало $SEJCHAS (убрано $((BYLO - SEJCHAS)))"
  exit 0
fi

if [ "$ROSLO" -gt 0 ]; then
  echo "КОММЕНТАРИЕВ ПРИБАВИЛОСЬ — в $ROSLO файлах:"
  cat "$TMP/rost"
  echo ""
  echo "В .flang комментариев не пишут: объясняйте именем, типом, «обеспечивает» и «примером»."
  echo "Замеры, даты и «почему так решили» — в docs/ и tasks/. Правило: .claude/skills/flang-code."
  exit 1
fi

echo "комментариев не прибавилось: строк $SEJCHAS в $S_FAJLOV файлах (долг был $BYLO)"
[ "$SEJCHAS" -lt "$BYLO" ] && echo "  убрано с прошлого снятия: $((BYLO - SEJCHAS)) — снимите долг: --снять"
exit 0
