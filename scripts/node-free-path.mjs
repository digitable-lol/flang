/**
 * PATH, на котором заведомо НЕТ Node, — и честный отказ, если такого не собрать.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Релиз обещает: чтобы поставить flang, нужны только `cc` и `make`, Node не
 * нужен. Проверяет это обещание scripts/build-release-c.mjs — он собирает
 * напечатанный C прямо у себя и обязан делать это в окружении без Node.
 *
 * До 18 августа 2026 он этого не делал, хотя писал, что делает. В коде стояло
 * `PATH: "/usr/bin:/bin:/usr/local/bin"`, а рядом печаталось «PATH без Node», —
 * при том что node лежит ровно в /usr/local/bin. Замер: на этом PATH
 * `command -v node` находит /usr/local/bin/node. То есть сторож, заведённый
 * ловить прокравшуюся зависимость от Node, не поймал бы её никогда: начни
 * напечатанный Makefile звать node — сборка прошла бы зелёной.
 *
 * ── Почему нельзя просто выкинуть /usr/local/bin ────────────────────────────
 * Потому что там же у многих лежат `make`, `gtar` и сам компилятор — особенно на
 * macOS с Homebrew. Слепое выкидывание сломало бы проверку там, где обещание как
 * раз верно. Поэтому каталоги отбираются по факту: выбрасываются те, в которых
 * ЕСТЬ node, и только они.
 *
 * ── И почему отказ, а не тихий обход ────────────────────────────────────────
 * Если после отбора нужного инструмента не осталось — значит node лежит с ним в
 * одном каталоге, и честного PATH без Node здесь не собрать. Тогда правильный
 * ответ — отказаться и сказать почему, а не собрать с node под рукой и назвать
 * это проверкой. «Не смог проверить» и «проверил, всё хорошо» — разные исходы;
 * их смешение в этом проекте уже однажды провезло ложь до пользователя.
 */
import { accessSync, constants } from "node:fs"
import { join } from "node:path"

/** Под какими именами встречается Node. `nodejs` — имя в пакетах Debian. */
export const ИМЕНА_NODE = ["node", "nodejs"]

/** Есть ли в каталоге исполняемый файл с таким именем. */
export const исполняемый = (каталог, имя) => {
  try {
    accessSync(join(каталог, имя), constants.X_OK)
    return true
  } catch {
    return false
  }
}

/**
 * Собирает PATH без Node из настоящего PATH разработчика.
 *
 * Берём именно его, а не жёсткий список: `cc`, `make` и `gtar` у всех лежат
 * по-разному, и зашитый список — это ровно та ошибка, которую чиним.
 *
 * @returns {{путь: string, оставлены: string[], выброшены: string[],
 *            пропали: string[], годен: boolean, почему: string|null}}
 */
export function путьБезNode({
  path = process.env.PATH ?? "",
  /* Пусто по умолчанию намеренно. Подмешивать сюда «/usr/bin:/bin» на всякий
     случай значило бы молча расширять PATH, который разработчик задал сам, — и
     заодно сделать отбор непроверяемым: на машине, где /usr/bin всегда чист,
     отказ не наступил бы никогда, чем бы PATH ни был. Пусто — значит считаем по
     тому PATH, который есть, и говорим правду о нём. */
  запасные = [],
  нужны = ["make"],
  найден = исполняемый,
} = {}) {
  const кандидаты = [...new Set([...path.split(":").filter(Boolean), ...запасные])]
  const выброшены = кандидаты.filter((к) => ИМЕНА_NODE.some((и) => найден(к, и)))
  const оставлены = кандидаты.filter((к) => !выброшены.includes(к))
  const пропали = нужны.filter((и) => !оставлены.some((к) => найден(к, и)))
  const гдеЖивёт = (и) => выброшены.filter((к) => найден(к, и))

  return {
    путь: оставлены.join(":"),
    оставлены,
    выброшены,
    пропали,
    годен: пропали.length === 0,
    почему:
      пропали.length === 0
        ? null
        : пропали
            .map((и) => {
              const рядом = гдеЖивёт(и)
              return рядом.length > 0
                ? `«${и}» нашёлся только там же, где node: ${рядом.join(", ")}`
                : `«${и}» не нашёлся ни в одном каталоге PATH`
            })
            .join("; "),
  }
}

/** Найден ли Node на уже собранном PATH. Пояс поверх подтяжек: если это вдруг
 *  вернёт true, значит отбор выше сломан, и собирать нельзя. */
export const nodeДостижим = (путь, найден = исполняемый) =>
  путь
    .split(":")
    .filter(Boolean)
    .some((к) => ИМЕНА_NODE.some((и) => найден(к, и)))
