# У СТРОКИ ОДНА МЕРА — проверка прогоном, а не обещанием.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# SPEC (раздел 5) обещает: все формы над строкой считают ЗНАКИ. Обещание это
# держится ровно до первой строки, которая не является правильным UTF-8: тогда
# «содержит», «начинается с» и «разделить» ходят по ОКТЕТАМ, а «длина»,
# «подстрока», «символ» и «разложить … на символы» — по знакам, и всякое
# утверждение, сшитое из форм разных мер, становится ложным.
#
# Замер 22 августа 2026 на точке раскрутки 55292de6, тем же способом, каким
# зовёт эта проверка:
#
#   «мама» содержит октеты BC D0     → да, хотя ни один знак «мамы» им не равен
#   «мама» начинается с октета D0    → да, хотя её первый знак «м»
#   разделить «маму» по октету D0    → пять кусков по половине знака
#   длина строки из октетов BC D0    → 1, а «разложить … на символы» → два куска
#                                       (второй писался за конец массива)
#
# ── Почему оболочка, а не план на flang ──────────────────────────────────────
# Негодные октеты в исходнике на flang не записываются: `\uXXXX` в литерале не
# разбирается, а `символ по коду` на суррогате отказывает. Приезжают они только
# СНАРУЖИ, и ближайший вход — доводы командной строки. Поэтому октеты кладёт
# printf, а считает их flang: `scripts/string-measure.flang`.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/one-string-measure-guard.sh          проверить bootstrap/flang
#   FLANG=<путь> sh scripts/one-string-measure-guard.sh   проверить другой
#
# Код 0 — мера одна. Код 1 — названы вход и то, какие формы разошлись.
set -u

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
PLAN=$KOREN/scripts/string-measure.flang
BEDY=0
VSEGO=0

zvat() { # функция, args
  LC_ALL=C.UTF-8 "$FLANG" run "$PLAN" --function "«$1»" --args "$2" 2>&1
}

sverit() { # имя, октеты текста, октеты части
  imya=$1
  args=$(printf '{"текст": "%b", "часть": "%b"}' "$2" "$3")
  VSEGO=$((VSEGO + 1))
  otvet=$(zvat 'Разлад мер' "$args")
  case "$otvet" in
    '""')
      printf 'мера одна   %s\n' "$imya" ;;
    *)
      BEDY=$((BEDY + 1))
      printf 'РАЗЛАД      %s: %s\n' "$imya" "$otvet" ;;
  esac
}

sklejka() { # имя, октеты левой, октеты правой, ждём: «сумма» либо «отказ»
  imya=$1
  args=$(printf '{"текст": "%b", "часть": "%b"}' "$2" "$3")
  zhdyom=$4
  VSEGO=$((VSEGO + 1))
  dlina=$(zvat 'Длина склейки' "$args")
  summa=$(zvat 'Сумма длин' "$args")
  case "$zhdyom" in
    сумма)
      if [ "$dlina" = "$summa" ]; then
        printf 'склейка складывается   %s: %s\n' "$imya" "$dlina"
      else
        BEDY=$((BEDY + 1))
        printf 'РАЗЛАД      %s: длина склейки %s, сумма длин %s\n' "$imya" "$dlina" "$summa"
      fi ;;
    отказ)
      case "$dlina" in
        FLANG_BUILTIN_ARGS*)
          printf 'стык отвергнут         %s\n' "$imya" ;;
        *)
          BEDY=$((BEDY + 1))
          printf 'РАЗЛАД      %s: стык слипает знаки, а склейка ответила «%s»\n' "$imya" "$dlina" ;;
      esac ;;
  esac
}

[ -x "$FLANG" ] || { echo "нет двоичного: $FLANG" >&2; exit 2; }
echo "проверка мер: $FLANG"

# Правильный UTF-8 — здесь меры совпадают и на стволе, и после починки.
sverit "пустая строка"                ""                      ""
sverit "один знак"                    "a"                     "a"
sverit "кириллица"                    "мама"                  "ам"
sverit "эмодзи, четыре октета"        "\0360\0237\0230\0200"  "\0360\0237\0230\0200"
sverit "знак замены U+FFFD"           "\0357\0277\0275"       "\0357\0277\0275"
sverit "одни пробелы"                 "    "                  " "
sverit "кавычка внутри"               "а\\\"б"                "\\\""
sverit "составной знак е + U+0301"    "\0320\0265\0314\0201"  "\0314\0201"
sverit "половина пары в WTF-8"        "\0355\0240\0275"       "\0355\0240\0275"
sverit "текст с половиной пары"       "мама\0355\0240\0275"   "\0355\0240\0275"

# Негодный UTF-8 — здесь ствол расходился, и ради этого проверка написана.
sverit "часть = хвост знака и лид"    "мама"                  "\0274\0320"
sverit "часть = ведущий октет знака"  "мама"                  "\0320"
sverit "часть = октет продолжения"    "мама"                  "\0274"
sverit "часть = хвост эмодзи"         "\0360\0237\0230\0200"  "\0237\0230\0200"
sverit "часть = ведущий октет эмодзи" "\0360\0237\0230\0200"  "\0360"
sverit "текст из хвоста и лида"       "\0274\0320"            "\0320"
sverit "текст из одних продолжений"   "\0237\0230\0200"       "\0237"
sverit "обрубленный эмодзи"           "\0360\0237"            "\0360"

# Склейка: длины обязаны складываться, а стык, слипающий знаки, — отказывать.
sklejka "буква и буква"               "а"                     "б"                    сумма
sklejka "эмодзи и буква"              "\0360\0237\0230\0200"  "я"                    сумма
sklejka "половина пары и половина"    "\0355\0240\0275"       "\0355\0260\0200"      сумма
sklejka "знак и октет продолжения"    "мама"                  "\0274"                отказ
sklejka "лид и его продолжение"       "\0320"                 "\0274"                отказ

echo "сверок $VSEGO, разладов $BEDY"
[ "$BEDY" -eq 0 ] || exit 1
