#
# ── Что случилось 29 августа 2026 ──────────────────────────────────────────
# Перепечатка семени дошла до конца впервые за заход: 6 ч 23 мин, код 0, семя
# 40,7 МБ. И напечатанное семя не собралось своим же Makefile:
#
#   bootstrap/compiler_flang.c:5944 — строковая постоянная в 4614 знаков
#   C99 (5.2.4.1) обязывает выдержать 4095, СЧИТАЯ ПОСЛЕ СКЛЕЙКИ СОСЕДНИХ
#   напечатанный Makefile сам просит `-std=c99 -pedantic -Werror`
#   make -C bootstrap упал за 37,30 с
#
# Семя при этом годное: без `-pedantic` оно собирается за 101,59 с и двоичный
# работает. Сломана ПАРА: печать выдаёт код, который отвергает её же
# напечатанный сборочный файл, вопреки его собственному обещанию.
#
# Строка пришла из `flang/self/proof-kernel.flang` — файла, который вырос в
# стволе (`918225f8`, `dd5dcf26`) и которого ветка перепечатки не касалась. У
# прошлого семени самая длинная постоянная — 2928 знаков, под пределом. То есть
# беда лежала в стволе давно и ждала, когда печать дойдёт достаточно далеко.
#
# ── Цена, ради которой этот сторож заведён ─────────────────────────────────
# Узнать про длинную строку стоило 6 ч 23 мин печати плюс 37,30 с сборки. Тот
# же ответ здесь стоит секунды, и получен он ТЕМ ЖЕ СПОСОБОМ — прогоном, а не
# рассуждением:
#
#   проба печатью (печать + сборка крошечной программы)   0,29 с
#   перепись входов печати                                меньше секунды
#   опрос компилятора о семени                            4,21 с
#
# ── Три вопроса, и они РАЗНЫЕ ──────────────────────────────────────────────
#
# 1. УМЕЕТ ЛИ ПЕЧАТЬ РЕЗАТЬ. Двоичный печатает крошечную программу, у которой
#    постоянная заведомо длиннее предела, и напечатанное собирается ЕГО ЖЕ
#    напечатанным Makefile — то есть теми флагами, которые печать сама и
#    обещает. Это проверка сквозная: ни предел, ни флаги здесь не переписаны
#    руками, оба берутся у предмета.
#
# 2. ЧТО ПОЕДЕТ В СЕМЯ. Входы печати названы не догадкой, а файлом
#    `scripts/otpechatok-semeni`, который печать снимает сама. Литерал длиннее
#    предела в любом из них — это будущее семя, которое не соберётся.
#
# 3. ЦЕЛО ЛИ СЕМЯ СЕЙЧАС. Спрашивается у компилятора, а не переписанным
#    разбором C: `cc -fsyntax-only -Woverlength-strings`. Компилятор считает
#    склейку соседних сам и отвечает про тот самый предел.
#
# ── Почему вопрос 1 нельзя заменить вопросом 2 ─────────────────────────────
# Потому что перепечатку ведёт СТАРЫЙ двоичный: печатью правит эмиттер,
# зашитый в него, а не исходники этого дерева. Починка `flang/self/emit-c.flang`
# доедет до печати только СЛЕДУЮЩИМ семенем. Пока не доехала — длинный литерал
# во входах печати ломает ближайшую перепечатку, и вопрос 2 обязан краснеть.
# Когда доедет, проба (вопрос 1) позеленеет, и вопрос 2 станет справкой.
# Ровно поэтому вердикт складывается из двух ответов, а не из одного.
#
# ── Почему склейка соседних НЕ ЛЕЧИТ, и это замер, а не мнение ─────────────
# Разрезать длинную постоянную на соседние (`"а" "б"`) — первое, что приходит в
# голову: в C соседние строковые постоянные склеиваются сами. НЕ ПОМОГАЕТ.
# Предел в C99 назван «после конкатенации», и оба компилятора считают именно
# так. Проверено 29 августа 2026 на постоянной в 4614 байт:
#
#   цельная                          gcc 15.2.0: ошибка, 4614 против 4095
#   разрезанная на три соседних      gcc 15.2.0: ТА ЖЕ ошибка, те же 4614
#   clang                            ошибка та же, слово в слово
#
# Работает другое — октетный массив: `static const unsigned char x[] = {…};` и
# указатель на него. Предела на список значений в инициализаторе нет.
#
# ── Как звать ──────────────────────────────────────────────────────────────
#   sh scripts/overlong-string-guard.sh          все три вопроса
#   sh scripts/overlong-string-guard.sh --подлог проба самого сторожа
#
# Ключи среды:
#   FLANG=<путь>     каким двоичным пробовать печать (умолчание bootstrap/flang)
#   FLANG_TMP=<кат>  где заводить временное (умолчание TMPDIR или /tmp)
#
# Код возврата: 0 — чисто; 1 — найдено; 2 — смотреть нечем (нет двоичного или
# нет компилятора C). «Мне нечем посмотреть» — это НЕ «замечаний нет», и код у
# него отдельный.
set -u

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
VREMENNOE=${FLANG_TMP:-${TMPDIR:-/tmp}}
CC=${CC:-cc}

# Предел C99, 5.2.4.1: «4095 знаков в строковой постоянной (после склейки)».
PREDEL=4095

# ── Перепись литералов в исходниках на flang ────────────────────────────────
#
# Считается в БАЙТАХ, потому что предел компилятор считает в байтах: постоянная
# из 2551 кириллического знака весит 4614 байт, и краснеет именно вес.
#
# Строки длиннее предела редки, и это используется: сначала грубый отсев по
# длине строки файла (в байтах, оттого LC_ALL=C), и только уцелевшие разбираются
# посимвольно. Иначе разбор 1116 файлов стоил бы секунды на ровном месте.
#
# Экранирование: `\uXXXX` считается за 3 байта (потолок для BMP), всякое другое
# `\x` — за один. Счёт получается НЕ МЕНЬШЕ настоящего, то есть сторож может
# поднять ложную тревогу, но пропустить длинную постоянную не может.
perepis() { # файлы…
  LC_ALL=C awk -v predel="$PREDEL" '
    length($0) < predel { next }              # короткая строка длинной постоянной не вместит
    {
      n = length($0); i = 1; v = 0; dlina = 0; nachalo = 0
      while (i <= n) {
        c = substr($0, i, 1)
        if (v == 0) {
          if (c == "\"") { v = 1; dlina = 0; nachalo = i }
          else if (c == "/" && substr($0, i+1, 1) == "/") break   # примечание до конца строки
          i++
        } else {
          if (c == "\\") {
            e = substr($0, i+1, 1)
            if (e == "u") { dlina += 3; i += 6 } else { dlina += 1; i += 2 }
          } else if (c == "\"") {
            if (dlina > predel) printf "%s:%d\t%d\n", FILENAME, FNR, dlina
            v = 0; i++
          } else { dlina++; i++ }
        }
      }
    }
  ' "$@" 2>/dev/null
}

# ── Вопрос 1: умеет ли печать резать ───────────────────────────────────────
#
# Программа заводится здесь, а не лежит в дереве файлом: длина её постоянной
# обязана быть привязана к ПРЕДЕЛУ, а не к числу, переписанному руками. Предел
# сменится — проба сменится вместе с ним.
proba_pechatyu() { # каталог для работы → 0 режет, 1 не режет, 2 смотреть нечем
  rab=$1
  [ -x "$FLANG" ] || return 2
  command -v "$CC" >/dev/null 2>&1 || return 2
  mkdir -p "$rab" || return 2

  kusok='цепь из слов, набранная до перелива предела C99 '
  dlinnaya=$kusok
  # Удвоение, пока не станет заведомо длиннее предела в байтах.
  while [ "$(printf '%s' "$dlinnaya" | wc -c)" -le "$PREDEL" ]; do
    dlinnaya=$dlinnaya$dlinnaya
  done

  {
    printf '%s\n\n' 'модуль «Проба длинной постоянной»'
    printf '%s\n' '// Заводится сторожем scripts/overlong-string-guard.sh. Постоянная здесь'
    printf '%s\n' '// заведомо длиннее предела C99: печать обязана выдать код, который'
    printf '%s\n' '// собирается её же напечатанным Makefile.'
    printf '%s\n' 'тотальная функция «Длинная постоянная»'
    printf '%s\n' '  возвращает строка'
    printf '  "%s"\n' "$dlinnaya"
  } > "$rab/proba.flang" || return 2

  rm -rf "$rab/vyvod"
  if ! "$FLANG" emit "$rab/proba.flang" --target c --out "$rab/vyvod" > "$rab/pechat.log" 2>&1; then
    echo "     печать отказалась печатать пробу:" >&2
    sed 's/^/     /' "$rab/pechat.log" >&2
    return 2
  fi
  [ -f "$rab/vyvod/Makefile" ] || return 2

  # Собирается ТЕМ Makefile, который напечатала сама печать: флаги не переписаны.
  #
  # Код возврата ставится ЯВНО, а не наследуется от make. `make` отвечает
  # двойкой на всякую неудачу сборки, а двойка здесь занята под «смотреть
  # нечем» — унаследованный код читался бы как отсутствие инструмента. Первый
  # прогон этого сторожа так и соврал: печать не резала, а сторож говорил
  # «нет двоичного», имея двоичный под рукой.
  if ( cd "$rab/vyvod" && make ) > "$rab/sborka.log" 2>&1; then
    return 0
  fi
  return 1
}

# ── Вопрос 3: цело ли семя сейчас ──────────────────────────────────────────
#
# Спрашивается у компилятора. Переписывать разбор строковых постоянных C своими
# руками значило бы завести вторую, расходящуюся мерку того самого предела,
# из-за которого всё и случилось.
opros_semeni() { # → 0 чисто, 1 найдено, 2 смотреть нечем
  command -v "$CC" >/dev/null 2>&1 || return 2
  ishodniki=$(ls "$KOREN"/bootstrap/*.c 2>/dev/null) || return 2
  [ -n "$ishodniki" ] || return 2
  najdeno=0
  for f in $ishodniki; do
    if "$CC" -std=c99 -fsyntax-only -Woverlength-strings "$f" 2>&1 |
         grep -a 'overlength-strings' > "$VREMENNOE/semya-$$.txt"; then
      sed 's/^/  /' "$VREMENNOE/semya-$$.txt"
      najdeno=1
    fi
  done
  rm -f "$VREMENNOE/semya-$$.txt"
  return $najdeno
}

# ── Подлог: краснеет ли сторож, когда есть на что ──────────────────────────
#
# Сторож, разучившийся краснеть, от чистого дерева неотличим. Здесь ему
# подкладывают ровно то, что он обязан находить, и молчание считается провалом.
if [ "${1:-}" = "--подлог" ]; then
  rab=$VREMENNOE/podlog-dlinnoy-$$
  mkdir -p "$rab" || { echo "подлог: негде работать" >&2; exit 2; }
  bedy=0

  dlinnaya=$(awk -v n=$((PREDEL + 200)) 'BEGIN { s=""; while (length(s) < n) s = s "щ"; print s }')

  printf 'тотальная функция «Проба»\n  возвращает строка\n  "%s"\n' "$dlinnaya" > "$rab/podlog.flang"
  if [ -z "$(perepis "$rab/podlog.flang")" ]; then
    echo "ПОДЛОГ НЕ ПОЙМАН: перепись смолчала на литерале длиннее предела" >&2
    bedy=$((bedy + 1))
  else
    echo "подлог пойман   перепись назвала длинный литерал"
  fi

  printf 'тотальная функция «Проба»\n  возвращает строка\n  "коротко"\n' > "$rab/chisto.flang"
  if [ -n "$(perepis "$rab/chisto.flang")" ]; then
    echo "ЛОЖНАЯ ТРЕВОГА: перепись назвала короткий литерал" >&2
    bedy=$((bedy + 1))
  else
    echo "чисто молчит    перепись смолчала на коротком литерале"
  fi

  # Примечание с кавычками внутри не должно читаться как постоянная.
  { printf '// а тут "кавычка" и ещё '; awk -v n=$((PREDEL + 200)) 'BEGIN { s=""; while (length(s) < n) s = s "щ"; print s }'; } > "$rab/primechanie.flang"
  if [ -n "$(perepis "$rab/primechanie.flang")" ]; then
    echo "ЛОЖНАЯ ТРЕВОГА: перепись приняла примечание за постоянную" >&2
    bedy=$((bedy + 1))
  else
    echo "чисто молчит    примечание за постоянную не принято"
  fi

  rm -rf "$rab"
  [ "$bedy" -eq 0 ] || exit 1
  echo "сторож краснеет там, где должен, и молчит там, где должен"
  exit 0
fi

# ── Прогон ─────────────────────────────────────────────────────────────────
echo "предел C99 (5.2.4.1): $PREDEL байт в строковой постоянной, после склейки соседних"
echo

RAB=$VREMENNOE/dlinnaya-postoyannaya-$$
BEDY=0
NECHEM=0

# 1. Умеет ли печать резать.
proba_pechatyu "$RAB"
REZHET=$?
case $REZHET in
  0) echo "1. печать РЕЖЕТ    напечатанное собралось своим же Makefile" ;;
  1) echo "1. печать НЕ РЕЖЕТ длинная постоянная уезжает в C как есть:"
     grep -a 'overlength-strings' "$RAB/sborka.log" 2>/dev/null | sed 's/^/     /' | head -3 ;;
  2) echo "1. СМОТРЕТЬ НЕЧЕМ  нет двоичного ($FLANG) или компилятора C"
     NECHEM=1 ;;
esac

# 2. Что поедет в семя.
OTPECHATOK=$KOREN/scripts/otpechatok-semeni
VHODY=
if [ -r "$OTPECHATOK" ]; then
  VHODY=$(awk '$2 ~ /\.flang$/ { print $2 }' "$OTPECHATOK" | sed "s|^|$KOREN/|")
fi
if [ -z "$VHODY" ]; then
  echo "2. СМОТРЕТЬ НЕЧЕМ  входы печати не названы ($OTPECHATOK)"
  NECHEM=1
else
  SPISOK=$(perepis $VHODY)
  SKOLKO=$(printf '%s' "$SPISOK" | grep -ac . || true)
  if [ -z "$SPISOK" ]; then
    echo "2. входы печати    ни одной постоянной свыше предела ($(printf '%s\n' $VHODY | grep -c .) файлов)"
  else
    echo "2. входы печати    постоянных свыше предела: $SKOLKO"
    printf '%s\n' "$SPISOK" | sed 's|^'"$KOREN"'/||' | sort -t"$(printf '\t')" -k2 -rn |
      awk -F'\t' '{ printf "     %5d байт  %s\n", $2, $1 }'
  fi
fi

# 3. Цело ли семя сейчас.
VYVOD=$(opros_semeni)
SEMYA=$?
case $SEMYA in
  0) echo "3. семя            постоянных свыше предела нет" ;;
  1) echo "3. СЕМЯ НЕ СОБЕРЁТСЯ строгими флагами своего же Makefile:"
     printf '%s\n' "$VYVOD" | sed 's/^/   /' ;;
  2) echo "3. СМОТРЕТЬ НЕЧЕМ  нет bootstrap/*.c или компилятора C"; NECHEM=1 ;;
esac

rm -rf "$RAB"
echo

# ── Вердикт ────────────────────────────────────────────────────────────────
# Семя красное — всегда беда: закоммиченное семя обязано собираться теми
# флагами, которые само же и просит.
[ "$SEMYA" = 1 ] && BEDY=$((BEDY + 1))

# Печать не режет И во входах есть что резать — ближайшая перепечатка выдаст
# семя, которое не соберётся. Шесть часов за этот ответ уже заплачено однажды.
if [ "$REZHET" = 1 ] && [ -n "${SPISOK:-}" ]; then
  BEDY=$((BEDY + 1))
  echo "ПЕРЕПЕЧАТКУ НАЧИНАТЬ НЕЛЬЗЯ: печать не режет длинные постоянные, а во"
  echo "входах печати они есть. Семя выйдет несобираемым, и узнается это через"
  echo "шесть часов. Разрежьте названные литералы в исходнике либо дождитесь"
  echo "семени, в котором эмиттер уже умеет резать."
fi

if [ "$REZHET" = 1 ] && [ -z "${SPISOK:-}" ]; then
  echo "печать резать не умеет, но резать нечего: во входах печати длинных"
  echo "постоянных нет. Умение приедет со следующим семенем."
fi

if [ "$BEDY" -eq 0 ] && [ "$NECHEM" != 0 ]; then
  echo "часть вопросов осталась без ответа — это не «замечаний нет»"
  exit 2
fi
[ "$BEDY" -eq 0 ] || exit 1
exit 0
