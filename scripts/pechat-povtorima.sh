# ПЕЧАТЬ ПОВТОРИМА: тот же двоичный, тот же вход, две разные среды — одни байты.
#
# ── Какой вопрос это закрывает, а какой нет ─────────────────────────────────
#
# Гейт Г6 просит две вещи разом:
#   (а) две перепечатки ОДНОГО дерева дают побайтово одно и то же;
#   (б) это проверяется АВТОМАТИЧЕСКИ, а не разово руками.
#
# (а) доказано 6 сентября 2026 на паре печатей с дерева d3b121b5 (16 404 с и
# 16 929 с, обе кодом 0): `scripts/two-prints-identical.sh` дал код 0 и
# «печати совпали побайтово: файлов 4, байт 1 229 825». Сверку позвали РУКОЙ,
# и потому (б) осталось открытым.
#
# Закрыть (б) той же парой нельзя: 2 x 4,6 ч машины на шаг CI не ставят. Этот
# прибор берёт от (а) ту часть, что стоит секунды, и НЕ ВРЁТ про остальное.
#
# ЧТО ОН ДОКАЗЫВАЕТ. Печать этого двоичного — чистая функция от входов: в
# напечатанные байты НЕ ТЕЧЁТ ни время, ни адреса, ни номер процесса, ни имя
# и длина временного каталога, ни имя и длина выходного каталога, ни часовой
# пояс, ни размер окружения. Это ровно та порода, из-за которой печать бывает
# невоспроизводима, и названа она теми же словами в сводке работы
# `dve-pechati`: «время, адреса, порядок обхода каталога».
#
# ЧЕГО ОН НЕ ДОКАЗЫВАЕТ — читать вслух, не пропускать:
#   · он печатает ОДИН МОДУЛЬ (по умолчанию flang/self/lexer.flang: 12,2 с,
#     399 МиБ пика, 7 файлов, 1 676 420 байт), а не замыкание компилятора
#     (4,6 ч, 35 ГиБ, 39,5 МБ). Порода, просыпающаяся только на масштабе —
#     арена рантайма под 35 ГиБ, порядок суда ядра по всему замыканию,
#     поведение при нехватке памяти, — здесь не затронута ВООБЩЕ;
#   · он ничего не говорит про `bootstrap/**`: сверяются две свежие печати
#     между собой, а не печать с закоммиченным семенем. Тот вопрос — за
#     `sh scripts/raskrutka.sh --check`, и он стоит 4,6 ч;
#   · значит Г6 им НЕ БЕРЁТСЯ ЦЕЛИКОМ. Он держит НЕОБХОДИМОЕ условие на
#     каждом пуше; остаток — полная пара печатей одного дерева — остаётся за
#     работой `dve-pechati` в .github/workflows/reprint.yml, а ей нужен
#     раннер, которого нет.
#
# ── Почему не `sh scripts/raskrutka.sh --telo`, хотя он стоит 0,15 с ────────
# Он сверяет `bootstrap/**` с отпечатком, который сняла ТА ЖЕ печать, что это
# `bootstrap/**` и положила. Снимок сходится со снимком тавтологически, и про
# повторимость это не говорит ничего. Так написано в самом raskrutka.sh:
#
#   «ЧЕГО НЕ ТРЕБУЕТ ЭТА ПОЛОВИНА, и это важно: побайтовой воспроизводимости
#    печати. Отпечаток записывает ФАКТИЧЕСКИЕ байты семени в миг съёмки, а не
#    то, что напечатали бы исходники. Две честные перепечатки могут дать
#    разные байты — сверку это не поколеблет… Вопрос «печатает ли дерево то же
#    самое дважды» остаётся за `--check`, и он другой.»
#
# То же сказано над обоими зовами отпечатка в .github/workflows/binary.yml
# (строки 205 и 771): «зелёное после него не значит «семя воспроизводимо»
# (гейт Г6), значит только «снимок равен снимку»».
#
# ── Цена, числами (замер 6 сентября 2026, эта машина, bootstrap/flang 0.7.11)
#   sh scripts/raskrutka.sh --telo         0,15 с   не тот вопрос
#   sh scripts/raskrutka.sh --otpechatok   0,73 с   не тот вопрос, и заслонён
#   sh scripts/raskrutka.sh --imena        0,35 с   не тот вопрос
#   sh scripts/raskrutka.sh --bystro       1,50 с   не тот вопрос
#   sh scripts/raskrutka.sh --тела         2,69 с   не тот вопрос
#   ЭТОТ прибор, вход по умолчанию        24,4 с    ЧАСТЬ того вопроса
#   ЭТОТ прибор, --подлог                 12,3 с    одна печать вместо двух
#   sh scripts/raskrutka.sh --check       ~4,6 ч    тот вопрос, но не для пуша
#   пара печатей (работа dve-pechati)     ~9,2 ч    тот вопрос целиком
#
# Цена печати круто растёт с входом — тем же прогоном, тем же двоичным:
#   flang/stdlib/result.flang    0,70 с    39 МиБ
#   flang/self/lexer.flang      12,21 с   399 МиБ   <- по умолчанию
#   flang/self/emit-c.flang     71,77 с   1,67 ГиБ
#   flang/self/parser.flang     >120 с    3,42 ГиБ  (убит по времени)
#   flang/self/types.flang      >120 с              (убит по времени)
# Вход выбран по этой лестнице: lexer — самый дорогой из тех, чья ПАРА печатей
# укладывается в полминуты. Ниже него порода ловится хуже, выше — шаг на пуш
# перестаёт быть дешёвым.
#
# ── Как звать ───────────────────────────────────────────────────────────────
#   sh scripts/pechat-povtorima.sh                  сверка
#   sh scripts/pechat-povtorima.sh --вход <файл>    сверка на другом входе
#   sh scripts/pechat-povtorima.sh --подлог         проба самого прибора
#
# Ключи среды: FLANG     — чем печатать (по умолчанию bootstrap/flang)
#              FLANG_TMP — где работать (по умолчанию /srv/tmp; /tmp в дереве
#                          запрещён хуком)
#
# ── Коды возврата ───────────────────────────────────────────────────────────
# «Плохо» и «не проверено» — РАЗНОЕ, и слитые в один код они врут в обе
# стороны: то поднимают тревогу на пустом месте, то прячут находку среди
# поломок машины. Тот же раздел кодов, что у two-prints-identical.sh.
#   0  печати совпали побайтово
#   1  РАЗОШЛИСЬ: печать невоспроизводима. Это НАХОДКА, а не поломка машины
#   2  звать не умеют (непонятный ключ, входа нет)
#   3  НЕ ПРОВЕРЕНО: печатать нечем, работать негде или печать отказала.
#      Про повторимость не сказано НИЧЕГО — ни «да», ни «нет»
set -u

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
RUNTIME=flang/src/emit/c
OTPECHATOK=scripts/otpechatok-semeni
VHOD_PO_UMOLCHANIYU=flang/self/lexer.flang

skazhi() { printf '%s\n' "$*"; }
beda()   { printf '%s\n' "$*" >&2; }

VHOD=$VHOD_PO_UMOLCHANIYU
PODLOG=net
while [ $# -gt 0 ]; do
  case $1 in
    --подлог) PODLOG=da ;;
    --вход)
      shift
      [ $# -gt 0 ] || { beda "--вход: не назван файл"; exit 2; }
      VHOD=$1 ;;
    *) beda "непонятный ключ: $1"
       beda "звать: sh scripts/pechat-povtorima.sh [--вход <файл>|--подлог]"
       exit 2 ;;
  esac
  shift
done

[ -f "$ROOT/$VHOD" ] || { beda "входа нет: $VHOD"; exit 2; }

# ── Чем печатать. Двоичного нет — это «не проверено», а не «сошлось»: молчание
#    в этом месте неотличимо от успеха, и ровно так уже терялись проверки,
#    переехавшие на двоичный (docs/zettel/a-check-moved-to-the-binary-drops-out-
#    of-ci-silently.md).
BINARY=${FLANG:-$ROOT/bootstrap/flang}
if [ ! -x "$BINARY" ]; then
  beda "НЕ ПРОВЕРЕНО: печатать нечем — $BINARY не исполняемый файл"
  beda "  Собрать: make -C bootstrap -j\"\$(nproc)\""
  exit 3
fi

# ── Пределы печати берутся ИЗ ОТПЕЧАТКА, а не переписываются сюда числом.
#    Второй список постоянных разошёлся бы с первым молча — этой породой в
#    дереве уже ломались (raskrutka.sh, про транслитерацию имён ядра).
PREDEL_SHAGOV=$(LC_ALL=C.UTF-8 /usr/bin/grep -a '^предел-шагов ' "$ROOT/$OTPECHATOK" 2>/dev/null | tail -1 | sed 's/^[^ ]* //')
PREDEL_GLUBINY=$(LC_ALL=C.UTF-8 /usr/bin/grep -a '^предел-глубины ' "$ROOT/$OTPECHATOK" 2>/dev/null | tail -1 | sed 's/^[^ ]* //')
if [ -z "$PREDEL_SHAGOV" ] || [ -z "$PREDEL_GLUBINY" ]; then
  beda "НЕ ПРОВЕРЕНО: в $OTPECHATOK нет пределов печати"
  beda "  Печатать с чужими пределами нельзя: это была бы другая печать."
  exit 3
fi

RAB=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" povtorima.XXXXXX) || {
  beda "НЕ ПРОВЕРЕНО: не создался каталог в ${FLANG_TMP:-/srv/tmp}"; exit 3; }
trap 'rm -rf "$RAB"' EXIT INT TERM

# ── Сверка двух каталогов побайтово ─────────────────────────────────────────
# Набор файлов сверяется ПЕРВЫМ: файл, появившийся только с одной стороны, —
# такое же расхождение, как разошедшееся содержимое, и молчать о нём нельзя.
# Тот же порядок, что у scripts/two-prints-identical.sh.
sverit() { # $1 первый каталог, $2 второй. 0 — сошлись, 1 — разошлись
  ( cd "$1" && ls -A ) | LC_ALL=C sort > "$RAB/spisok-1"
  ( cd "$2" && ls -A ) | LC_ALL=C sort > "$RAB/spisok-2"
  if ! LC_ALL=C cmp -s "$RAB/spisok-1" "$RAB/spisok-2"; then
    skazhi "РАЗОШЛИСЬ: наборы напечатанных файлов не совпадают"
    LC_ALL=C diff "$RAB/spisok-1" "$RAB/spisok-2" | sed 's/^/  /'
    return 1
  fi
  sv_fajlov=0; sv_bajt=0; sv_razoshlos=0
  while IFS= read -r f; do
    [ -f "$1/$f" ] || continue
    sv_fajlov=$((sv_fajlov + 1))
    sv_bajt=$((sv_bajt + $(wc -c < "$1/$f")))
    if ! LC_ALL=C cmp -s "$1/$f" "$2/$f"; then
      sv_razoshlos=$((sv_razoshlos + 1))
      skazhi "РАЗОШЁЛСЯ: $f"
      skazhi "  $(LC_ALL=C cmp "$1/$f" "$2/$f" 2>&1 | head -1)"
    fi
  done < "$RAB/spisok-1"
  if [ "$sv_razoshlos" -gt 0 ]; then
    skazhi "файлов сверено $sv_fajlov, разошлось $sv_razoshlos"
    return 1
  fi
  SVERENO_FAJLOV=$sv_fajlov
  SVERENO_BAJT=$sv_bajt
  return 0
}

# ── Одна печать. Среда задаётся ЦЕЛИКОМ доводами, а не наследуется молча:
#    вся суть прибора в том, что среды у двух заходов РАЗНЫЕ.
# $1 — выходной каталог, $2 — часовой пояс, $3 — временный каталог,
# $4 — набивка окружения (сдвигает адреса стека), $5 — журнал
pechat() {
  mkdir -p "$1" "$3" || return 3
  # Вывод В ФАЙЛ, а не в конвейер: после конвейера `$?` — это код последней
  # команды конвейера, и отказ печати потерялся бы (та же грабля, что
  # выписана в .github/workflows/reprint.yml над шагами печати).
  (
    cd "$ROOT" || exit 3
    TZ=$2 TMPDIR=$3 FLANG_TMP=$3 NABIVKA=$4 \
      "$BINARY" emit "$VHOD" --target c --out "$1" \
        --cli --repl --runtime "$ROOT/$RUNTIME" \
        --max-steps "$PREDEL_SHAGOV" --max-depth "$PREDEL_GLUBINY"
  ) > "$5" 2>&1
}

NABIVKA_1=x
NABIVKA_2=$(awk 'BEGIN { s = ""; while (length(s) < 4000) s = s "щ"; print s }')

# ── ПОДЛОГ: краснеет ли прибор, когда есть на что ───────────────────────────
#
# Сторож, разучившийся краснеть, от чистого дерева неотличим. За одни сутки
# 5 сентября 2026 эта порода поймана в дереве четыре раза, и ни разу прибором
# (scripts/storozha-bez-podloga.sh, шапка).
#
# Проба стоит ОДНУ печать, а не две: печатается один раз, и сверщику
# подкладывается ровно то, что он обязан находить.
#
# ЧТО ЭТА ПРОБА ПОКАЗЫВАЕТ: сверщик краснеет на изменённом байте и на пропавшем
# файле и молчит на дословной копии.
# ЧЕГО ОНА НЕ ПОКАЗЫВАЕТ: что прибор поймает НЕВОСПРОИЗВОДИМУЮ печать. Это
# другая проба, и она делается порчей семени с пересборкой двоичного — прогон
# записан в tasks/, а не здесь: пересборка стоит 4 минуты и в шаг CI не идёт.
if [ "$PODLOG" = da ]; then
  bedy=0
  # Код берётся СЛЕДУЮЩЕЙ СТРОКОЙ, а не внутри `if ! …`: там `$?` — это код
  # самого `!`, то есть всегда 0, и настоящий код печати потерялся бы.
  pechat "$RAB/proba" UTC "$RAB/t0" "$NABIVKA_1" "$RAB/proba.log"
  kod=$?
  if [ "$kod" -ne 0 ]; then
    beda "НЕ ПРОВЕРЕНО: печать пробы отказала (код $kod)"
    tail -20 "$RAB/proba.log" >&2
    exit 3
  fi

  cp -a "$RAB/proba" "$RAB/kopiya"
  if sverit "$RAB/proba" "$RAB/kopiya" >/dev/null; then
    skazhi "чисто молчит    дословная копия признана совпавшей"
  else
    beda "ЛОЖНАЯ ТРЕВОГА: сверщик развёл дословную копию"
    bedy=$((bedy + 1))
  fi

  # Порча ровно того рода, какой даёт сбитая печать: один байт в напечатанном.
  KOGO=$(cd "$RAB/kopiya" && ls -A | LC_ALL=C sort | head -1)
  [ -n "$KOGO" ] || { beda "НЕ ПРОВЕРЕНО: печать пробы не дала ни одного файла"; exit 3; }
  printf '/* подлог */\n' >> "$RAB/kopiya/$KOGO"
  if sverit "$RAB/proba" "$RAB/kopiya" >/dev/null; then
    beda "ПОДЛОГ НЕ ПОЙМАН: сверщик смолчал на изменённом байте в $KOGO"
    bedy=$((bedy + 1))
  else
    skazhi "подлог пойман   изменённый байт в $KOGO назван"
  fi

  rm -rf "$RAB/kopiya"; cp -a "$RAB/proba" "$RAB/kopiya"
  rm -f "$RAB/kopiya/$KOGO"
  if sverit "$RAB/proba" "$RAB/kopiya" >/dev/null; then
    beda "ПОДЛОГ НЕ ПОЙМАН: сверщик смолчал на пропавшем файле $KOGO"
    bedy=$((bedy + 1))
  else
    skazhi "подлог пойман   пропавший файл $KOGO назван"
  fi

  [ "$bedy" -eq 0 ] || exit 1
  skazhi "прибор краснеет там, где должен, и молчит там, где должен"
  exit 0
fi

# ── Сама сверка: две печати одного входа в РАЗНЫХ средах ────────────────────
#
# Что нарочно сделано разным и почему именно это. Каждый пункт — известный
# носитель невоспроизводимости, и другого способа спросить о нём, кроме как
# развести заходы, нет:
#   выходной каталог — имя и ДЛИНА разные: путь, утёкший в вывод, виден только
#                      при разной длине;
#   временный каталог — то же для FLANG_TMP/TMPDIR;
#   часовой пояс      — время, утёкшее в вывод, чаще всего утекает вместе с
#                      поясом; заходы вдобавок разнесены на 12 с настоящих;
#   набивка окружения — 4000 байт в окружении сдвигают стек и кучу; вместе с
#                      ASLR это разные адреса у второго захода.
skazhi "вход:      $VHOD"
skazhi "печатает:  $BINARY"
skazhi "пределы:   шагов $PREDEL_SHAGOV, глубины $PREDEL_GLUBINY"

# Код печати берётся СЛЕДУЮЩЕЙ СТРОКОЙ, а не внутри `if ! …`: там `$?` — код
# самого `!`, то есть всегда 0, и отказ печати прочитался бы как успех.
pechat "$RAB/pervaya" UTC "$RAB/t1" "$NABIVKA_1" "$RAB/pervaya.log"
kod=$?
if [ "$kod" -ne 0 ]; then
  beda "НЕ ПРОВЕРЕНО: первая печать отказала (код $kod)"
  beda "Это НЕ «разошлись»: сверять было нечего."
  tail -20 "$RAB/pervaya.log" >&2
  exit 3
fi
pechat "$RAB/vtoraya-pechat-togo-zhe-dereva" Pacific/Kiritimati \
       "$RAB/vremennyy-katalog-vtorogo-zahoda" "$NABIVKA_2" "$RAB/vtoraya.log"
kod=$?
if [ "$kod" -ne 0 ]; then
  beda "НЕ ПРОВЕРЕНО: вторая печать отказала (код $kod)"
  beda "Это НЕ «разошлись»: сверять было нечего."
  tail -20 "$RAB/vtoraya.log" >&2
  exit 3
fi

SVERENO_FAJLOV=0; SVERENO_BAJT=0
if sverit "$RAB/pervaya" "$RAB/vtoraya-pechat-togo-zhe-dereva"; then
  skazhi "печати совпали побайтово: файлов $SVERENO_FAJLOV, байт $SVERENO_BAJT"
  skazhi "Печать этого двоичного не зависит от времени, адресов, номера процесса,"
  skazhi "путей и часового пояса. Это НЕОБХОДИМОЕ условие Г6, и оно держится."
  skazhi "Достаточным оно не стало: полная пара печатей одного дерева — за"
  skazhi "работой dve-pechati в .github/workflows/reprint.yml."
  exit 0
fi

skazhi ""
skazhi "ПЕЧАТЬ НЕВОСПРОИЗВОДИМА. Это НАХОДКА, а не поломка машины."
skazhi "Один двоичный, один вход, два захода — и разные байты. Значит в вывод"
skazhi "течёт что-то, чего нет во входах. Гейт Г6 на этом дереве не берётся"
skazhi "ничем: полная пара печатей разойдётся тем же."
skazhi "Чинить надо печать, а не проверку: повтор даст то же самое."
exit 1
