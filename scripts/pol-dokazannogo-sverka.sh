#!/bin/sh
# СВЕРКА ВЕДОМОСТИ ДОКАЗАННОГО С ДЕРЕВОМ.
#
# ЗАЧЕМ. `scripts/proved-share-ledger.txt` — опись, из которой берут числа для
# Г7 и для доли доказанного. Прибора, который снимал бы её заново и сверял с
# деревом, в репозитории НЕ БЫЛО: числа 13 347 и 13 399 ходят по документам
# разовым проходом, который в дерево не переехал. Порода та же, что в задачах
# 7298 (сторожей считали рукой, и счёт был неверен в обе стороны) и 7855
# (прибор кругооборота лежит во времянке).
#
# ЧТО СВЕРЯЕТСЯ ТОЧНО, А ЧТО ТОЛЬКО ДАТИРУЕТСЯ. Разница не косметическая:
#
#   ЗНАМЕНАТЕЛЬ («написано», «без приговора») считается ПО ИСХОДНИКУ — это
#   строки `обеспечивает`, `требует`, `закон`. Двоичный для него не нужен,
#   счёт точен, и расхождение с описью есть ОШИБКА ОПИСИ здесь и сейчас.
#
#   ЧИСЛИТЕЛЬ («доказано», «сетка», «объявлено») — приговор ядра. Чтобы снять
#   его заново, надо прогнать двоичный по каждому файлу; на ядре доказательств
#   это часы и десятки гигабайт памяти (шапка описи: sets-oracle — 999 с и
#   16,6 ГиБ на один файл). Прибор его НЕ пересчитывает и не делает вида, что
#   пересчитал. Он делает другое: сверяет md5 исходника и тем ДАТИРУЕТ строку.
#   Разошёлся md5 — приговор в строке относится к файлу, которого уже нет.
#
# СВЕРЯЕТСЯ В ОБЕ СТОРОНЫ, по образцу flang/scripts/cli-keys-debt.json и
# scripts/storozha-bez-zova.json:
#   · файл дерева несёт обязательства, а строки в описи нет      — красно;
#   · строка описи есть, а файла в дереве нет                     — красно;
#   · строка описи есть, а обязательств в файле не осталось       — красно;
#   · «написано» в описи не сходится со счётом по исходнику       — красно;
#   · md5 разошёлся, а «написано» сошлось — НЕ красно: это протухший приговор,
#     он печатается числом и ждёт того, кто перемерит.
#
# ЗВАТЬ:  sh scripts/pol-dokazannogo-sverka.sh          сверка, код 1 при беде
#         sh scripts/pol-dokazannogo-sverka.sh --числа  только итоги, код 0
set -u
REZHIM=сверка
for d in "$@"; do
  case "$d" in
    --числа) REZHIM=числа ;;
    *) printf 'непонятный ключ: %s (знаю только --числа)\n' "$d" >&2; exit 2 ;;
  esac
done
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT" || exit 5
OPIS=scripts/proved-share-ledger.txt
[ -f "$OPIS" ] || { printf 'нет описи %s\n' "$OPIS" >&2; exit 5; }
RAB=${FLANG_TMP:-/srv/tmp}/pol-dokazannogo.$$
mkdir -p "$RAB" || exit 5
trap 'rm -rf "$RAB"' EXIT INT TERM

# ── дерево: md5, обеспечивает, требует, закон — по каждому .flang ────────────
# core.quotepath=false ОБЯЗАТЕЛЕН: без него git отдаёт кириллические пути в
# кавычках с восьмеричными кодами, и прибор молча пропускает 508 файлов из 955.
# Именно на этом первая редакция считала знаменатель по одним латинским именам.
git -c core.quotepath=false ls-files '*.flang' | while IFS= read -r f; do
  [ -f "$f" ] || continue
  # grep -c при нуле совпадений печатает 0 И ВЫХОДИТ КОДОМ 1. Поэтому «|| echo 0»
  # дописывал бы второй ноль и портил счёт; берём вывод как есть.
  # ДВЕ ФОРМЫ ОБЯЗАТЕЛЬСТВА, и первая редакция знала одну. Кроме голого
  # «обеспечивает» язык пишет обязательство с квантором:
  #     для всех элементы обеспечивает «длина неотрицательна» результат не меньше 0
  # Их в дереве 165 в 94 файлах, и 79 файлов несут ТОЛЬКО такую форму — прибор
  # считал их пустыми и объявлял их строки в описи лишними. Все 69 «лишних»
  # живых файлов оказались этой породы: врал прибор, а не опись.
  OB=$(LC_ALL=C.UTF-8 grep -acE '^ *(для всех [^ ]+ )?обеспечивает ' "$f" 2>/dev/null); OB=${OB:-0}
  TR=$(LC_ALL=C.UTF-8 grep -ac '^ *требует ' "$f" 2>/dev/null); TR=${TR:-0}
  ZA=$(LC_ALL=C.UTF-8 grep -ac '^ *закон ' "$f" 2>/dev/null); ZA=${ZA:-0}
  [ "$OB" = 0 ] && [ "$TR" = 0 ] && [ "$ZA" = 0 ] && continue
  printf '%s|%s|%s|%s|%s\n' "$(md5sum "$f" | cut -d' ' -f1)" "$OB" "$TR" "$ZA" "$f"
done > "$RAB/derevo"

LC_ALL=C.UTF-8 grep -av '^//' "$OPIS" | LC_ALL=C.UTF-8 grep -a '|' > "$RAB/opis"

awk -F'|' -v rezhim="$REZHIM" '
  FILENAME ~ /derevo$/ {
    d_md5[$5]=$1; d_ob[$5]=$2; d_tr[$5]=$3; d_za[$5]=$4; d_est[$5]=1; next
  }
  {
    p=$7; o_md5[p]=$1; o_nap[p]=$2; o_dok[p]=$3; o_set[p]=$4; o_obj[p]=$5; o_bez[p]=$6; o_est[p]=1
    strok++
    if($2!="×" && $2!="-") o_nap_sum+=$2
    if($3!="×" && $3!="-"){ o_dok_sum+=$3; s_vedom++ } else bez_vedom++
    if($4!="×" && $4!="-") o_set_sum+=$4
    if($5!="×" && $5!="-") o_obj_sum+=$5
    if($6!="×" && $6!="-") o_bez_sum+=$6
  }
  END{
    for(p in d_est){
      d_nap_sum += d_ob[p]; d_bez_sum += d_tr[p]+d_za[p]; d_fajlov++
      if(!(p in o_est)){ net_stroki[p]=d_ob[p]; net_n++; beda++ ; continue }
      if(o_nap[p]!="×" && o_nap[p]!="-" && o_nap[p]+0 != d_ob[p]+0){
        raz_nap[p]=o_nap[p]" против "d_ob[p]; raz_n++; beda++
      }
      if(o_md5[p]!=d_md5[p]){ prot[p]=1; prot_n++
        if(o_dok[p]!="×" && o_dok[p]!="-") prot_dok+=o_dok[p]
        if(o_nap[p]!="×" && o_nap[p]!="-") prot_nap+=o_nap[p]
      }
    }
    for(p in o_est){
      if(!(p in d_est)){ lishn[p]=1; lishn_n++; beda++ }
    }
    printf "ПОЛ ДОКАЗАННОГО: опись против дерева\n\n"
    printf "  ЗНАМЕНАТЕЛЬ — счёт по исходнику, точен\n"
    printf "    файлов с обязательствами в дереве   %d\n", d_fajlov
    printf "    строк в описи                        %d\n", strok
    printf "    «обеспечивает» по дереву             %d\n", d_nap_sum
    printf "    «написано» по описи                  %d\n", o_nap_sum
    printf "    «требует»+«закон» по дереву          %d\n", d_bez_sum
    printf "    «без приговора» по описи             %d\n", o_bez_sum
    printf "\n  ЧИСЛИТЕЛЬ — приговор ядра, прибор его НЕ пересчитывает\n"
    printf "    файлов с ведомостью                  %d\n", s_vedom
    printf "    файлов без ведомости (× или прочерк) %d\n", bez_vedom
    printf "    доказано                             %d\n", o_dok_sum
    printf "    на сетке                             %d\n", o_set_sum
    printf "    объявлено                            %d\n", o_obj_sum
    printf "\n  ПРОТУХЛОСТЬ — md5 исходника разошёлся с описью\n"
    printf "    строк протухло                       %d из %d\n", prot_n, strok
    printf "    из них несут «доказано»              %d\n", prot_dok
    printf "    и «написано»                         %d\n", prot_nap
    if(rezhim=="числа"){ exit 0 }
    if(beda==0){ printf "\nопись сходится с деревом\n"; exit 0 }
    printf "\n"
    for(p in net_stroki) printf "НЕТ СТРОКИ: %s несёт %d обязательств, а в описи его нет\n", p, net_stroki[p] > "/dev/stderr"
    for(p in lishn)      printf "ЛИШНЯЯ СТРОКА: %s есть в описи, а в дереве обязательств не несёт\n", p > "/dev/stderr"
    for(p in raz_nap)    printf "«НАПИСАНО» НЕ СХОДИТСЯ: %s — %s\n", p, raz_nap[p] > "/dev/stderr"
    printf "\nбед %d: нет строки %d, лишних %d, «написано» не сходится %d\n", beda, net_n+0, lishn_n+0, raz_n+0 > "/dev/stderr"
    exit 1
  }
' "$RAB/derevo" "$RAB/opis"
