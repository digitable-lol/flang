# ПРЕДЕЛ ПАМЯТИ НА ОДИН ПРОГОН — оболочка, за которой прогон не может съесть
# машину целиком.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# Ночь 21 августа 2026: машина стояла 87 минут (04:02:28 → 05:29:25), убийца
# памяти сработал двенадцать раз за пять часов, три раза по flang на 44,4 /
# 50,6 / 39,4 ГиБ. В каждой записи `constraint=CONSTRAINT_NONE` — кончилась
# ВСЯ память машины, а не предел какой-то группы. Снесло два пользовательских
# менеджера systemd (uid 1002 и 1003), журнал за окно аварии не записался
# вовсе: ядро само заткнуло свои hung-task предупреждения.
#
# Причина не в том, что flang жадный, а в том, что ЕГО НИКТО НЕ ДЕРЖИТ. Один
# `flang check` компилятора берёт 20–25 ГиБ (замерено), а ядер на машине 256:
# любой веер (`xargs -P 64`, `make -j$(nproc)`) умножает это на два порядка.
# 499 ГиБ ОЗУ и 4 ГиБ свопа такого веера не переживают.
#
# ── Что делает эта оболочка ─────────────────────────────────────────────────
# 1. ДО запуска смотрит, сколько памяти свободно, и если её меньше «предел +
#    запас» — НЕ ЗАПУСКАЕТ и говорит, чего именно не хватило. Это дешёвый счёт
#    (доли секунды), его же можно спросить отдельно: `--schet`.
# 2. Запускает команду в отдельной контрольной группе (cgroup v2) с жёстким
#    `memory.max`. Упор в предел бьёт по ЭТОЙ группе: ядро снимает самый
#    жирный процесс ВНУТРИ неё, а машина и чужие прогоны не замечают ничего.
#    Это `constraint=CONSTRAINT_MEMCG` вместо `CONSTRAINT_NONE`.
# 3. Своп группе запрещён (`MemorySwapMax=0`): при 4 ГиБ свопа на 499 ГиБ ОЗУ
#    свопиться значит уйти в молотьбу и утащить машину за собой. Лучше честно
#    упасть, чем медленно давить всех.
# 4. После падения ЧИТАЕТ счётчики группы и печатает внятное объяснение —
#    сколько было взято на пике, каким был предел и что делать дальше, — вместо
#    голого `Killed`, по которому не видно ничего.
#
# ── Чего оболочка НЕ ловит (говорю прямо) ───────────────────────────────────
# • Того, кто её не позвал. Это опора на дисциплину. Предел, который нельзя
#   обойти забывчивостью, ставится только правами root на срез пользователя
#   (`user-1000.slice` и соседние) — см. docs/pamyat-i-veera.md.
# • Суммы. Десять прогонов по 32 ГиБ под этой оболочкой — это 320 ГиБ, и
#   машина ляжет. Против суммы работает пункт 1 (не пускать, когда мало
#   свободно), но между «посмотрел» и «занял» есть щель: два прогона могут
#   пройти проверку одновременно и оба занять. Запас по умолчанию (48 ГиБ)
#   взят с учётом этой щели, но она есть.
# • Взрыва не по памяти: файловые описатели, место на диске, процессы.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   scripts/predel-pamyati.sh ./bootstrap/flang check flang/self/parser.flang
#   scripts/predel-pamyati.sh --predel 48G -- ./bootstrap/flang test flang/stdlib/
#   scripts/predel-pamyati.sh --schet          # только счёт, ничего не запускать
#
# Пределы можно задать и переменными среды: FLANG_PREDEL, FLANG_ZAPAS.
#
# ИМЕНА ЗДЕСЬ ЛАТИНИЦЕЙ, как в scripts/raskrutka.sh и в `ярлык`: ни dash, ни
# bash не принимают кириллицу в именах переменных.

set -eu

# ── Настройки по умолчанию ───────────────────────────────────────────────────
# Предел 32 ГиБ выбран замером, а не на глаз: самый тяжёлый ЗАКОННЫЙ одиночный
# прогон на этом дереве — `flang check flang/self/bootstrap/compiler.flang`,
# 23,5 ГиБ (замерено `ps -eo rss` 21 августа). Перепечатка семени — около
# 20 ГиБ. 32 ГиБ оставляет им запас в треть и при этом отсекает прогоны на
# 39–50 ГиБ, которыми машину и положили. Нужен больше — скажите `--predel`.
PREDEL=${FLANG_PREDEL:-32G}
# Запас: сколько памяти должно остаться СВЕРХ предела, иначе не пускаем.
ZAPAS=${FLANG_ZAPAS:-48G}
SCHET_ONLY=0
TIHO=0

err() { printf '%s\n' "$*" >&2; }

pomoshch() {
  sed -n '4,60p' "$0" | sed 's/^# \{0,1\}//'
}

# «32G» → байты. Принимает G/g, M/m, K/k и голое число (байты).
v_baytah() {
  case $1 in
    *[Gg]) echo $(( ${1%[Gg]} * 1024 * 1024 * 1024 )) ;;
    *[Mm]) echo $(( ${1%[Mm]} * 1024 * 1024 )) ;;
    *[Kk]) echo $(( ${1%[Kk]} * 1024 )) ;;
    *[!0-9]*) err "не понял размер: $1 (ждал 32G, 512M, 1024K или число байт)"; exit 2 ;;
    *) echo "$1" ;;
  esac
}

gib() { awk -v b="$1" 'BEGIN { printf "%.1f", b / 1073741824 }'; }

# ── Разбор доводов ───────────────────────────────────────────────────────────
while [ $# -gt 0 ]; do
  case $1 in
    --predel) PREDEL=$2; shift 2 ;;
    --predel=*) PREDEL=${1#--predel=}; shift ;;
    --zapas) ZAPAS=$2; shift 2 ;;
    --zapas=*) ZAPAS=${1#--zapas=}; shift ;;
    --schet) SCHET_ONLY=1; shift ;;
    --tiho) TIHO=1; shift ;;
    -h|--help|--pomoshch) pomoshch; exit 0 ;;
    --) shift; break ;;
    -*) err "неизвестный довод: $1 (см. --help)"; exit 2 ;;
    *) break ;;
  esac
done

PREDEL_B=$(v_baytah "$PREDEL")
ZAPAS_B=$(v_baytah "$ZAPAS")

# ── СЧЁТ: сколько сейчас идёт прогонов flang, сколько держат, сколько свободно ─
# Дешёвый: два чтения /proc — доли секунды. Дорогой счёт никто звать не станет.
schet() {
  # MemAvailable — оценка ядра «сколько можно занять без свопа». Именно она, а
  # не MemFree: страничный кэш отдаётся, и MemFree занижает свободное в разы.
  DOSTUPNO=$(awk '/^MemAvailable:/ { print $2 * 1024 }' /proc/meminfo)
  VSEGO=$(awk '/^MemTotal:/ { print $2 * 1024 }' /proc/meminfo)
  SWAP_VSEGO=$(awk '/^SwapTotal:/ { print $2 * 1024 }' /proc/meminfo)
  SWAP_SVOB=$(awk '/^SwapFree:/ { print $2 * 1024 }' /proc/meminfo)
  # Прогоны flang: имя процесса ровно `flang`, чтобы не считать редакторы и
  # оболочки, у которых слово встречается в строке запуска.
  set -- $(ps -eo comm=,rss=,user= | awk '$1 == "flang" { n++; s += $2 * 1024; if ($2 > m) { m = $2; mu = $3 } } END { print n + 0, s + 0, m * 1024 + 0, (mu == "" ? "-" : mu) }')
  PROGONOV=$1; DERZHAT=$2; KRUPNEISHIY=$3; CHEY=$4
}

schet

pokazat_schet() {
  printf 'память машины: всего %s ГиБ, доступно %s ГиБ, своп %s из %s ГиБ свободен\n' \
    "$(gib "$VSEGO")" "$(gib "$DOSTUPNO")" "$(gib "$SWAP_SVOB")" "$(gib "$SWAP_VSEGO")"
  printf 'прогонов flang сейчас: %s, держат %s ГиБ, крупнейший %s ГиБ (%s)\n' \
    "$PROGONOV" "$(gib "$DERZHAT")" "$(gib "$KRUPNEISHIY")" "$CHEY"
  printf 'этот прогон просит: предел %s ГиБ, запас сверх него %s ГиБ\n' \
    "$(gib "$PREDEL_B")" "$(gib "$ZAPAS_B")"
}

if [ "$SCHET_ONLY" = 1 ]; then
  pokazat_schet
  if [ "$DOSTUPNO" -lt $(( PREDEL_B + ZAPAS_B )) ]; then
    printf 'КРАСНО: свободно %s ГиБ, нужно %s ГиБ — прогон бы не начался\n' \
      "$(gib "$DOSTUPNO")" "$(gib $(( PREDEL_B + ZAPAS_B )))"
    exit 3
  fi
  printf 'ЗЕЛЕНО: места хватает\n'
  exit 0
fi

[ $# -gt 0 ] || { err 'нечего запускать: дайте команду после доводов (см. --help)'; exit 2; }

# ── Ворота: не пускаем, когда свободного мало ────────────────────────────────
# Красным, а не советом. Совет пропускают, отказ — нет.
if [ "$DOSTUPNO" -lt $(( PREDEL_B + ZAPAS_B )) ]; then
  err "ОТКАЗ: машине сейчас нечем платить за этот прогон."
  err ""
  pokazat_schet >&2
  err ""
  err "нужно $(gib $(( PREDEL_B + ZAPAS_B ))) ГиБ (предел + запас), доступно $(gib "$DOSTUPNO") ГиБ."
  err "что делать: дождаться, пока освободятся чужие прогоны (их сейчас $PROGONOV),"
  err "либо снизить предел (--predel 16G), либо, если знаете цену, --zapas 8G."
  exit 3
fi

# ── Где брать контрольную группу ─────────────────────────────────────────────
# systemd-run --user --scope заводит временную группу в срезе пользователя и
# сам её убирает. Пользовательский менеджер бывает не поднят (в ночь аварии
# его как раз снесло), поэтому XDG_RUNTIME_DIR выставляем сами, если пусто.
[ -n "${XDG_RUNTIME_DIR:-}" ] || XDG_RUNTIME_DIR=/run/user/$(id -u)
export XDG_RUNTIME_DIR

if ! systemctl --user is-system-running >/dev/null 2>&1; then
  err "ВНИМАНИЕ: пользовательский менеджер systemd не отвечает — предел памяти"
  err "поставить НЕЧЕМ. Прогон пойдёт БЕЗ предела; ворота по свободной памяти"
  err "выше он прошёл, но упор в потолок положит машину, а не прогон."
  err "поднять: systemctl --user start dbus.socket, либо loginctl enable-linger $(id -un)"
  [ "$TIHO" = 1 ] || err ""
  exec "$@"
fi

# ── Прогон под пределом ──────────────────────────────────────────────────────
# Внутри группы работает не только команда, но и маленькая оболочка: она
# переживает снятие (убийца выбирает самый жирный процесс группы, а это
# заведомо flang, а не sh на мегабайт) и потому может прочитать счётчики
# группы ПОСЛЕ падения и объяснить, что случилось.
VNUTRI='
  set -u
  CG=/sys/fs/cgroup$(sed -n "s/^0:://p" /proc/self/cgroup)
  "$@" || rc=$?
  rc=${rc:-0}
  if [ -r "$CG/memory.peak" ]; then PIK=$(cat "$CG/memory.peak"); else PIK=0; fi
  if [ -r "$CG/memory.events" ]; then
    OOM=$(awk "/^oom_kill /{print \$2}" "$CG/memory.events")
    OOM_GROUP=$(awk "/^oom_group_kill /{print \$2}" "$CG/memory.events")
  else OOM=0; OOM_GROUP=0; fi
  printf "%s\t%s\t%s\t%s\n" "$rc" "$PIK" "${OOM:-0}" "${OOM_GROUP:-0}" > "$ITOG"
  exit $rc
'

ITOG=$(mktemp -p /srv/tmp predel-pamyati.XXXXXX)
export ITOG
trap 'rm -f "$ITOG"' EXIT INT TERM

# OOMPolicy=continue — без него ничего не работает, и это проверено прогоном.
# По умолчанию systemd на снятие ядром ОСТАНАВЛИВАЕТ единицу целиком: ядро
# сняло flang (SIGKILL), а systemd следом послал SIGTERM оставшимся, то есть
# нашей объясняющей оболочке. Наружу выходило `Terminated` и код 143 — ровно то
# невнятное «Killed», от которого мы уходим. С `continue` systemd не трогает
# переживших, оболочка дочитывает счётчики и объясняет.
set +e
systemd-run --user --scope -q --collect \
  -p MemoryMax="$PREDEL" -p MemorySwapMax=0 -p OOMPolicy=continue \
  -- /bin/sh -c "$VNUTRI" sh "$@"
RC=$?
set -e

PIK=0; OOM=0
if [ -s "$ITOG" ]; then
  PIK=$(cut -f2 "$ITOG")
  OOM=$(cut -f3 "$ITOG")
fi

# ── Объяснение вместо «Killed» ───────────────────────────────────────────────
if [ "${OOM:-0}" -gt 0 ] || [ "$RC" = 137 ]; then
  err ""
  err "ПРЕДЕЛ ПАМЯТИ: прогон снят, машина цела."
  err ""
  err "  команда:   $*"
  err "  предел:    $(gib "$PREDEL_B") ГиБ (memory.max этой группы)"
  err "  взято:     $(gib "${PIK:-0}") ГиБ на пике"
  err "  снятий:    ${OOM:-1} (внутри группы; за её пределами не тронуто ничего)"
  err ""
  err "Это НЕ авария машины: убийца памяти бил по группе прогона"
  err "(constraint=CONSTRAINT_MEMCG), а не по всей машине (CONSTRAINT_NONE)."
  err "Чужие прогоны и системные службы не задеты."
  err ""
  err "Дальше: либо поднять предел (--predel $(( $(gib "$PREDEL_B" | cut -d. -f1) * 2 ))G),"
  err "либо разбить работу пофайлово — память освобождается после каждого файла"
  err "(см. приёмку пофайлово: цена падает с десятков ГиБ до сотен МиБ)."
  exit 137
fi

if [ "$TIHO" != 1 ]; then
  err "предел памяти: взято $(gib "${PIK:-0}") ГиБ из $(gib "$PREDEL_B") ГиБ, код возврата $RC"
fi
exit "$RC"
