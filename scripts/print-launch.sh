#!/bin/sh
# Оболочка ручного запуска перепечатки — та самая, что обязана дописать
# `ПЕЧАТЬ КОД=<код>` дословно (см. scripts/print-progress.sh, «ПРИЗНАК
# КОНЦА — ЕГО НЕ ПИШЕТ САМА ПЕЧАТЬ»: для ручного прогона это обязанность
# именно оболочки запуска, не raskrutka.sh и не самого прибора).
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Три ручных запуска подряд (pechat-dev, pechat-dev-2,
# pechat-dev-3 — задача 9988) писали `ПЕЧАТЬ dev КОД=0` / `ПЕЧАТЬ dev-2
# КОД=0` вместо дословного контракта: каждый был написан заново от руки,
# и метка для читаемости попадала ВНУТРЬ контрактной строки вместо
# отдельной строки рядом. print-progress.sh и two-prints-identical.sh
# ищут ТОЧНУЮ подстроку «ПЕЧАТЬ КОД=» — и оба молчали о готовой печати
# по 8-21 час, пока кто-то не заметил вручную. Четвёртый ручной запуск
# (Ч358-pechat-bez-suda/пуск.sh) контракт не нарушил — разница между
# верным и неверным была чистой случайностью, не правилом. Этот файл —
# правило: одна проверенная оболочка вместо новой самопальной на каждый
# запуск.
#
# ЗВАТЬ:  sh scripts/print-launch.sh <рабочий каталог> [метка]
#   <рабочий каталог> — то же, что BASE в прежних пуск.sh: внутри обязан
#     лежать подкаталог «клон» с деревом, из которого печатать.
#   [метка] — необязательная, для читаемости человеком (например «dev-4»).
#     Ложится ОТДЕЛЬНОЙ строкой, никогда не смешивается со строкой
#     контракта.
#
# Журнал: <рабочий каталог>/печать.log (дописывается, не перезаписывается).
set -u

BASE=${1:-}
METKA=${2:-}
[ -n "$BASE" ] || { echo "звать: sh scripts/print-launch.sh <рабочий каталог> [метка]" >&2; exit 2; }

KLON="$BASE/клон"
[ -d "$KLON" ] || { echo "нет каталога «клон» внутри $BASE" >&2; exit 2; }

LOG="$BASE/печать.log"
export LC_ALL=C.UTF-8
export FLANG_TMP="$BASE"
export TMPDIR="$BASE"

cd "$KLON" || exit 2

{
  if [ -n "$METKA" ]; then
    printf '=== начало %s (%s) ===\n' "$(date '+%d.%m %H:%M:%S')" "$METKA"
  else
    printf '=== начало %s ===\n' "$(date '+%d.%m %H:%M:%S')"
  fi
  printf 'коммит: %s\n' "$(git -c core.quotepath=false rev-parse HEAD 2>/dev/null || echo неизвестен)"
} >> "$LOG"

NACHALO=$(date +%s)
sh scripts/raskrutka.sh >> "$LOG" 2>&1
KOD=$?
KONETS=$(date +%s)

{
  [ -n "$METKA" ] && printf 'МЕТКА=%s\n' "$METKA"
  printf 'ПЕЧАТЬ КОД=%d\n' "$KOD"
  printf 'СЕКУНД ОБОЛОЧКИ=%d\n' "$((KONETS - NACHALO))"
  printf '=== конец %s ===\n' "$(date '+%d.%m %H:%M:%S')"
} >> "$LOG"

exit "$KOD"
