#!/bin/sh
# В каком состоянии перепечатка — по её собственному журналу.
#
# ЗАЧЕМ. Печать пишет «шагов N из 1 400 000 000 000 (30 %)», и по этой строке
# нельзя понять ничего: счётчик ОБНУЛЯЕТСЯ на каждой стадии, а знаменатель —
# потолок всей печати. Одна и та же цифра «30 %» стоит и в начале, и на
# двенадцатом часу. Из-за этого мы восемь часов не знали, где находимся, и
# дважды называли сроки, взятые из ничего.
#
# ЧТО ДЕЛАЕТ. Читает журнал, называет стадию, её номер из четырёх и место внутри
# неё — по отметкам, а не по шагам. Отметки кладутся по времени, поэтому их
# число и есть время.
#
# ── ОБРАЗЕЦ, и откуда он взят ────────────────────────────────────────────────
# Снят 2 сентября 2026 с прогона в /srv/tmp/dokazuemyy/Ч179-gotovnost-sverki
# (коммит af791d85), прошедшего три стадии из четырёх:
#
#     Связать исходники        17 отметок
#     Проверить тотальность     1
#     Суд ядра о программе   1469
#     Напечатать связанное    133 и продолжалась
#
# ЧЕТВЁРТАЯ СТАДИЯ В ОБРАЗЦЕ НЕ ДОСЧИТАНА, и потому её длина здесь — НИЖНЯЯ
# ГРАНИЦА, а не длина. Прибор об этом говорит вслух и не выдаёт догадку за
# замер. Переснять образец обязан первый же дошедший до конца прогон — иначе
# число протухнет молча, как протухли «двенадцать минут» в bootstrap/README.md
# и MEASURED_COST в scripts/raskrutka.sh.
#
# ── ОТКУДА БЕРУТСЯ СТРОКИ, ПО КОТОРЫМ ЭТОТ ПРИБОР СУДИТ ──────────────────────
# Проверено 2 сентября 2026, дерево /srv/tmp/dokazuemyy/peredacha, ветка dev,
# коммит 86cc5c86. У каждой строки назван источник — иначе прибор сторожит
# выдуманное, а это ровно тот отказ, каким болела прежняя редакция.
#
# ОТМЕТКИ ХОДА «шагов N из M (P %), идёт «<стадия>», <память>» — ПИШУТСЯ.
#   Источник: flang/src/emit/c/flang_repl.c:1540 («шагов ») и :1548 («, идёт «»),
#   строка собирается в `repl_hod_say` и уходит в stderr на flang_repl.c:1557
#   (`write(2, line, at)`). Печатается по будильнику SIGALRM раз в
#   REPL_HOD_SECONDS = 30 секунд (flang_repl.c:1501), пока идёт именованный шаг:
#   `repl_hod_start(name)` на flang_repl.c:1634 в `repl_call_within`, имя шага —
#   первый довод `repl_call`. Та же печать лежит НАПЕЧАТАННОЙ в семени:
#   bootstrap/flang_repl.c:1402, :1410, :1419, :1475.
#   Подтверждено на живом: три настоящих журнала печати
#   (`/usr/bin/grep -ac '^шагов '` / `-ac 'идёт «'`):
#       /srv/tmp/relizy/perepechatka.log                1191 / 1191
#       /srv/tmp/relizy/perepechatka-zahod1-ubita.log    413 /  413
#       /srv/tmp/relizy/perepechatka-zahod2-ubita.log    352 /  352
#   Обе строки — ОДНА строка журнала, потому числа и сходятся.
#   ВАЖНО: отметки идут в stderr, а не в stdout. Журнал обязан быть снят с
#   `2>&1` (или `2>журнал`), иначе отметок в нём не будет ни одной, и прибор
#   честно скажет «не проверено», а не «печать не начиналась».
#
# ПРИЗНАК КОНЦА — ЕГО НЕ ПИШЕТ САМА ПЕЧАТЬ.
#   `LC_ALL=C.UTF-8 /usr/bin/grep -arn 'ПЕЧАТЬ КОД' . --exclude-dir=.git` даёт
#   пять попаданий, и все пять — в этих двух приборах. В трёх журналах выше её
#   ноль, ноль и ноль. Прежняя редакция сторожила выдуманную строку и потому
#   не могла сказать «печать кончилась» НИКОГДА.
#   Теперь за конец принимаются две строки, и обе названы:
#     1) `ПЕЧАТЬ КОД=<код>` — ДОГОВОР. Дописать обязан тот, кто пустил печать:
#        для CI — работа `.github/workflows/reprint.yml`, для ручного прогона —
#        оболочка запуска. В дереве на 86cc5c86 её не пишет НИКТО.
#     2) `КОНЕЦ … код=<код>` — НАБЛЮДЕНИЕ: стоит в 3 журналах из 3, в двух
#        порядках слов, пишет её оболочка запуска, которой в дереве нет.
#        Одна она не довод: в …-zahod1-ubita.log стоит «КОНЕЦ … код=0» над
#        «Exit status: 143» — прогон убит, а строка объявляет успех. Поэтому
#        она сверяется с «Exit status:» от /usr/bin/time, и при расхождении
#        прибор выходит 3, назвав оба числа.
#   Нет ни одной из двух — прибор про конец МОЛЧИТ и читает отметки хода
#   дальше; «печать кончилась успехом» без строки конца он не скажет.
#
# Звать:  sh scripts/print-progress.sh <журнал печати>
#
# Коды возврата — «плохо» и «не проверено» это разное:
#   0  прочитано: стадия названа (или печать кончилась успехом — по строке конца)
#   1  печать кончилась НЕ успехом
#   3  НЕ ПРОВЕРЕНО: журнала нет, он пуст, отметок в нём ещё нет, стадия
#      образцу неизвестна или строка конца спорит с «Exit status:»
#   2  звать не умеют
set -u

OBRAZEC_SVYAZAT=17
OBRAZEC_TOTAL=1
OBRAZEC_SUD=1469
OBRAZEC_PECHAT=133          # нижняя граница: стадия не досчитана
OBRAZEC_VSEGO=1620          # сумма, тоже нижняя граница

[ $# -eq 1 ] || { echo "звать: sh scripts/print-progress.sh <журнал печати>" >&2; exit 2; }
LOG=$1
[ -f "$LOG" ] || { echo "НЕ ПРОВЕРЕНО: журнала нет — $LOG" >&2; exit 3; }
[ -s "$LOG" ] || { echo "НЕ ПРОВЕРЕНО: журнал пуст — $LOG" >&2; exit 3; }

# Конец печати — по двум строкам, названным в шапке. Договорная старше
# наблюдаемой: её пишет тот, кто знает код вышедшей печати.
KOD=""; OTKUDA=""
if LC_ALL=C.UTF-8 /usr/bin/grep -aq 'ПЕЧАТЬ КОД=[0-9]' "$LOG"; then
  OTKUDA='ПЕЧАТЬ КОД='
  KOD=$(LC_ALL=C.UTF-8 /usr/bin/grep -ao 'ПЕЧАТЬ КОД=[0-9][0-9]*' "$LOG" | tail -1 | sed 's/.*=//')
elif LC_ALL=C.UTF-8 /usr/bin/grep -aq '^КОНЕЦ' "$LOG"; then
  OTKUDA='КОНЕЦ … код='
  KOD=$(LC_ALL=C.UTF-8 /usr/bin/grep -a '^КОНЕЦ' "$LOG" \
        | LC_ALL=C.UTF-8 /usr/bin/grep -ao 'код=[0-9][0-9]*' | tail -1 | sed 's/.*=//')
  VYHOD=$(LC_ALL=C.UTF-8 /usr/bin/grep -a 'Exit status:' "$LOG" | tail -1 \
          | sed 's/.*Exit status:[[:space:]]*//')
  if [ -n "$KOD" ] && [ -n "$VYHOD" ] && [ "$VYHOD" != "$KOD" ]; then
    echo "НЕ ПРОВЕРЕНО: журнал сам себе противоречит — «КОНЕЦ … код=$KOD» против" >&2
    echo "  «Exit status: $VYHOD» ($LOG). Так соврал" >&2
    echo "  /srv/tmp/relizy/perepechatka-zahod1-ubita.log: код=0 на убитом прогоне." >&2
    echo "  Пусть допишет «ПЕЧАТЬ КОД=<код>» тот, кто печать пустил." >&2
    exit 3
  fi
fi
if [ -n "$KOD" ]; then
  if [ "$KOD" = 0 ]; then
    echo "ПЕЧАТЬ КОНЧИЛАСЬ УСПЕХОМ (по строке «$OTKUDA$KOD»)."
    echo "Переснять образец этого прибора — он устарел."
    exit 0
  fi
  echo "ПЕЧАТЬ КОНЧИЛАСЬ НЕ УСПЕХОМ: код $KOD (по строке «$OTKUDA»)" >&2
  exit 1
fi

# Отметки хода. Источник строки назван в шапке: flang_repl.c:1540 → stderr.
OTMETOK=$(LC_ALL=C.UTF-8 /usr/bin/grep -ac '^шагов ' "$LOG" || true)
[ "${OTMETOK:-0}" -gt 0 ] || {
  echo "НЕ ПРОВЕРЕНО: отметок «шагов … из …, идёт «…»» в журнале нет — $LOG" >&2
  echo "  Либо печать ещё не дошла до первого именованного шага (первая отметка" >&2
  echo "  встаёт через 30 с работы шага, flang_repl.c:1501), либо журнал снят БЕЗ" >&2
  echo "  stderr: отметки идут в дескриптор 2 (flang_repl.c:1557), и без «2>&1»" >&2
  echo "  их в журнале не будет ни одной." >&2
  echo "  Строки конца («ПЕЧАТЬ КОД=» или «КОНЕЦ … код=») тут тоже нет." >&2
  exit 3; }

# Имя стадии — первый довод `repl_call` (flang_repl.c:1634), в строку его
# кладёт flang_repl.c:1548. Стадий в журналах встречалось ПЯТЬ, а не четыре:
# кроме названных ниже, в /srv/tmp/relizy/perepechatka.log один раз стоит
# «Программа без снятых постусловий» (flang_repl.c:9364). Её длины никто не
# мерил, и потому она попадает в «образцу неизвестна» и даёт 3 — это честнее
# выдуманного числа.
STADIYA=$(LC_ALL=C.UTF-8 /usr/bin/grep -ao 'идёт «[^»]*»' "$LOG" | tail -1 | sed 's/^идёт «//;s/»$//')
V_STADII=$(LC_ALL=C.UTF-8 /usr/bin/grep -ac "идёт «$STADIYA»" "$LOG")

case "$STADIYA" in
  "Связать исходники")     NOMER=1; DLINA=$OBRAZEC_SVYAZAT; PROSHLO=0 ;;
  "Проверить тотальность") NOMER=2; DLINA=$OBRAZEC_TOTAL;   PROSHLO=$OBRAZEC_SVYAZAT ;;
  "Суд ядра о программе")  NOMER=3; DLINA=$OBRAZEC_SUD;     PROSHLO=$((OBRAZEC_SVYAZAT + OBRAZEC_TOTAL)) ;;
  "Напечатать связанное")  NOMER=4; DLINA=$OBRAZEC_PECHAT;  PROSHLO=$((OBRAZEC_SVYAZAT + OBRAZEC_TOTAL + OBRAZEC_SUD)) ;;
  *) echo "НЕ ПРОВЕРЕНО: стадия «$STADIYA» образцу неизвестна — образец устарел" >&2; exit 3 ;;
esac

echo "стадия $NOMER из 4: «$STADIYA»"
echo "  отметок в стадии: $V_STADII из ~$DLINA по образцу"
if [ "$V_STADII" -le "$DLINA" ]; then
  echo "  в стадии пройдено: ~$(( V_STADII * 100 / DLINA )) %"
else
  echo "  в стадии пройдено: БОЛЬШЕ образца ($V_STADII против $DLINA) — этот прогон дороже образцового"
fi
echo "  по всей печати:    ~$(( (PROSHLO + V_STADII) * 100 / OBRAZEC_VSEGO )) % (образец не досчитан, потому это ВЕРХНЯЯ оценка)"
[ "$NOMER" = 4 ] && echo "  ВНИМАНИЕ: длина четвёртой стадии в образце — нижняя граница, конца её никто не видел"
exit 0
