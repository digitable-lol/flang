# ЧИСЛО, НАБРАННОЕ В ПРОЗЕ РУКОЙ, ОБЯЗАНО СХОДИТЬСЯ С ДЕРЕВОМ СЕГОДНЯ.
#
# ── Порода беды, ради которой сторож заведён ────────────────────────────────
# Число, записанное рукой, верно в день записи и лжёт назавтра. Примеры из
# этого же дерева, снятые 31 августа 2026:
#
#   docs/tree-inventory.md   «seed-parses-sources-guard.sh | 83»      файл 195 строк
#   docs/tree-inventory.md   «оболочка | 66 | 6 305»                  69 файлов, 9549 строк
#   flang/cat/SPEC.md        «Восемнадцать поручений, набор закрыт»   поручений 22
#   flang/self/SPEC.md       «двадцать вариантов»                     вариантов 45
#   flang/PLAN.md            «Поручение, пять вариантов»              вариантов 22
#
# Ни одно из этих мест не сторожил никто. Опись `docs/tree-inventory.md` при
# этом стоит проверкой на каждый пуш — но та проверка следит за ДОЛГОМ (храповик
# «долг не вырос»), а не за числами в таблице. Сторож зелен, таблица врёт.
#
# ── Как это лечится ─────────────────────────────────────────────────────────
# Рядом с числом ставится ПРИМЕТА: чем и когда оно снято. Сторож берёт прибор,
# снимает число заново и сверяет с записанным — и с тем, что стоит в прозе.
#
#   СНЯТО ГГГГ-ММ-ДД <прибор> <довод> = <число>
#
# Примета живёт в комментарии того языка, на котором написан файл:
#
#   Markdown   <!-- СНЯТО 2026-08-31 строк scripts/test-remote.sh = 129 -->
#   оболочка   # СНЯТО 2026-08-31 файлов *.awk = 1
#   flang      // СНЯТО 2026-08-31 список flang/self/parser.flang:6440 = 22
#
# ПРИБОРОВ ПЯТЬ, И СПИСОК ЗАКРЫТ. Открытый список означал бы, что примета
# может позвать что угодно, — тогда сторож стал бы способом выполнить чужую
# команду из документа, а не прибором.
#
#   строк      ПУТЬ         сколько строк в файле                (wc -l)
#   файлов     ОБРАЗЕЦ[,…]  сколько файлов под учётом git        (git ls-files)
#   строк-в    ОБРАЗЕЦ[,…]  сколько строк во всех таких файлах
#   примеров-в ОБРАЗЕЦ[,…]  сколько примеров во всех таких файлах
#   список     ПУТЬ:НОМЕР   сколько «…» в списке на этой строке
#
# ПОЧЕМУ ЗАВЕДЁН «примеров-в». 5 сентября 2026 выяснилось, что шаг CI «Примеры
# stdlib и ядра» идёт 44 минуты при обещанных шапкой 53 секундах. Шаг не
# сломался — он ВЫРОС: примеров стало 2713 вместо 1216, вдвое за двенадцать
# дней. Рядом с числом файлов примета стояла и держала его верным; рядом с
# числом примеров приметы не было, и поставить её было НЕЧЕМ — прибора не
# существовало. Сторожили ровно то, что сторож умел посчитать (задача 3841).
#
# ПРИЗНАК ПРИМЕРА — строка, начинающаяся словом «пример «» после отступа.
# Якорь обязателен: без него в счёт попадают упоминания слова внутри
# комментариев. На сегодняшнем flang/stdlib это разница 2716 против 2713.
#
# ── К чему примета привязана ────────────────────────────────────────────────
# К СВОЕЙ строке, если число стоит на ней же (так удобно в таблице Markdown:
# комментарий внутри последней ячейки не печатается), иначе — к ближайшей
# строке выше в пределах трёх. Если числа нет ни там, ни там, сторож КРАСНЕЕТ:
# примета оторвалась от прозы, и через месяц они разойдутся молча.
#
# Пробелы внутри числа при сверке с прозой снимаются, поэтому «9 186» в тексте
# и «9186» в примете — одно и то же. В самой примете число пишется без пробелов.
#
# Число, написанное в прозе СЛОВОМ, сторож тоже узнаёт: «Их восемь», «двадцать
# два поручения». Корни слов даны без окончаний, чтобы падеж не мешал, и список
# их закрыт — 0…20, 30, 40, 50, 100. Составных («сорок пять») в нём нет: такое
# число в прозе пишите цифрами, иначе примета к нему не привяжется и сторож
# скажет об этом вслух, а не промолчит.
#
# ── Коды возврата ───────────────────────────────────────────────────────────
#   0   все приметы сошлись — и с деревом, и с прозой
#   1   хоть одна разошлась; каждое место названо файлом и номером строки
#   1   хоть одна разошлась ИЛИ хоть одна негодна (неизвестный прибор, нет
#       файла, кривая дата): негодная примета не стережёт того, что автор
#       думал, и чинится тем же движением, что и расхождение
#   2   нет git или дерево не под учётом — прибора нет
#   3   судить ВПРАВДУ нечем: примет в дереве нет вовсе, либо годных нет ни
#       одной. Третий исход, а не зелень.
#
# ── Чего сторож НЕ проверяет, и это названо прямо ───────────────────────────
# Утверждений без приметы он не видит вовсе. Он не ищет числа в прозе сам:
# отличить «файлов 68» от «в 1968 году» без разметки нельзя, а сторож, который
# гадает, хуже отсутствующего. Примету ставит тот, кто пишет число.
# Себя самого сторож из обхода исключает: в этой шапке приметы показаны как
# образец, а не как утверждение о дереве.
#
# ЗВАТЬ:
#   sh scripts/prose-numbers-guard.sh            сверить все приметы
#   sh scripts/prose-numbers-guard.sh --подлог   ПОДЛОЖИТЬ ошибку и убедиться,
#     что сторож её видит: первой примете число подкручивается на единицу, и
#     сторож ОБЯЗАН выйти ненулевым кодом, назвав файл и строку. Зелёный ответ
#     на подлоге значит, что сторож разучился краснеть и проверять им нечего.
#     Гонять ПЕРЕД настоящей сверкой, иначе сломанный сторож в ленте не отличим
#     от чистого дерева.
set -eu
export LC_ALL=C.UTF-8

KOREN=$(cd "$(dirname "$0")/.." && pwd)
cd "$KOREN"
SVOYO=scripts/prose-numbers-guard.sh

PODLOG=нет
if [ "${1:-}" = "--подлог" ]; then PODLOG=да; fi

command -v git >/dev/null 2>&1 || { echo "сторож чисел: git не найден — прибора нет" >&2; exit 2; }
git rev-parse --git-dir >/dev/null 2>&1 || { echo "сторож чисел: $KOREN не под учётом git" >&2; exit 2; }

echo "сторож чисел в прозе: сверяю приметы «СНЯТО» с деревом $KOREN"

SYROE=$(mktemp) || exit 2
PLOSKO=$(mktemp) || exit 2
NAHODKI=$(mktemp) || exit 2
trap 'rm -f "$SYROE" "$PLOSKO" "$NAHODKI"' EXIT INT TERM

# Приметы по всему дереву. Свой файл исключён: в его шапке они образец, а не
# утверждение о дереве.
git -c core.quotepath=false grep -n -I -e 'СНЯТО [0-9][0-9][0-9][0-9]-' -- . \
  | grep -v "^$SVOYO:" > "$SYROE" || true

# ЦИТАТА — НЕ ПРИМЕТА, И ОТЛИЧАТЬ ИХ ОБЯЗАН СТОРОЖ, А НЕ ПИШУЩИЙ.
#
# 5 сентября 2026 сторож дважды стоял ослеплённым, и оба раза никто не знал.
# Задача 3841 показывала в тексте, КАК будет выглядеть будущая примета, и
# цитировала чужую; задача 1800 наступила на то же, описывая эту же беду.
# Строки стояли в блоках кода и в обратных кавычках — то есть были цитатами по
# смыслу, но сторож брал «СНЯТО ГГГГ-» где угодно и считал их своими.
#
# Правило было записано в шапке этого файла с самого начала: «примета живёт в
# КОММЕНТАРИИ того языка, на котором написан файл». Сторож его обещал и не
# проверял. Теперь проверяет — для Markdown, где цитаты и случаются:
#
#   не примета: строка внутри тройных обратных кавычек
#   не примета: «СНЯТО …» вне <!-- … --> на своей строке
#
# ГРАНИЦА НАЗВАНА. Файлы кода (.mjs, .js, .flang, .c) остаются на прежнем
# правиле: там приметы живут и в «//», и внутри «/* … */» без звёздочки в
# начале строки (docs/site/sitemap.mjs:70), а отслеживать состояние блочного
# комментария ради беды, которой там не случалось, — цена без причины.
#
# ЧЕГО ЭТО СТОИТ. Настоящая примета, написанная в Markdown БЕЗ <!-- -->, теперь
# не стережёт ничего. Молча этого не происходит: такие строки считаются
# отдельно и печатаются сведением в итоге, но кода не портят — иначе всякая
# цитата краснила бы сторожа, и мы вернулись бы к тому, от чего ушли.
VNE=$(mktemp) || exit 2
trap 'rm -f "$SYROE" "$PLOSKO" "$NAHODKI" "$VNE"' EXIT INT TERM

for MDFAYL in $(awk -F: '$1 ~ /\.md$/ {print $1}' "$SYROE" | sort -u); do
  # ОГРАЖДЕНИЕ — ЭТО СТРОКА ИЗ ОДНИХ КАВЫЧЕК, А НЕ ВСЯКАЯ С НИМИ. Первая
  # редакция считала ограждением любую строку, начинающуюся с трёх кавычек, и
  # споткнулась о docs/course/README.md:61 — там ``` стоит ВНУТРИ обратных
  # кавычек как часть прозы. Чётность сбилась на весь файл, и две настоящие
  # приметы в таблице ниже (строки 171-172) выпали из-под присмотра. Правило
  # CommonMark: после открывающих кавычек в строке не должно быть новых.
  awk -v f="$MDFAYL" '
    /^[[:space:]]*```+[^`]*$/ { vnutri = !vnutri; print f ":" NR; next }
    vnutri { print f ":" NR }
  ' "$MDFAYL"
done | sort -u > "$VNE"

awk -F: -v vne="$VNE" -v citaty="$VNE.цитаты" -v primety="$VNE.приметы" '
  BEGIN { while ((getline l < vne) > 0) skip[l] = 1 }
  {
    klyuch = $1 ":" $2
    if (klyuch in skip) { print > citaty; next }
    if ($1 ~ /\.md$/) {
      telo = $0; sub(/^[^:]*:[^:]*:/, "", telo)
      do_primety = telo; sub(/СНЯТО [0-9][0-9][0-9][0-9]-.*/, "", do_primety)
      if (index(do_primety, "<!--") == 0) { print > citaty; next }
    }
    print > primety
  }' "$SYROE"

VNE_KOMMENTARIYA=0
[ -f "$VNE.цитаты" ] && VNE_KOMMENTARIYA=$(wc -l < "$VNE.цитаты" | tr -d ' ')
if [ -f "$VNE.приметы" ]; then cp "$VNE.приметы" "$SYROE"; else : > "$SYROE"; fi
rm -f "$VNE.цитаты" "$VNE.приметы"

# Разложить в плоский вид: ФАЙЛ<таб>СТРОКА<таб>ПРИМЕТА. На одной строке примет
# может быть несколько — в таблице их две, «файлов» и «строк».
awk -F: '
{
  fayl=$1; nomer=$2;
  telo=$0; sub(/^[^:]*:[^:]*:/,"",telo);
  s=telo; nashli=0;
  while (match(s, /СНЯТО [0-9-]+ [^ ]+ [^ ]+ = [0-9]+/)) {
    printf "%s\t%s\t%s\n", fayl, nomer, substr(s, RSTART, RLENGTH);
    s=substr(s, RSTART+RLENGTH); nashli++;
  }
  if (nashli==0) printf "%s\t%s\t\t%s\n", fayl, nomer, telo;
}' "$SYROE" > "$PLOSKO"

VSEGO=$(wc -l < "$PLOSKO" | tr -d " ")
if [ "$VSEGO" = "0" ]; then
  echo "сторож чисел: примет в дереве НЕТ — сверять нечего" >&2
  echo "это не зелень: ни одно число в прозе не под присмотром" >&2
  exit 3
fi

SOSHLOS=0
RAZOSHLOS=0
NEGODNYH=0
PODLOZHENO=нет

if [ "$PODLOG" = "да" ]; then
  echo "сторож чисел: ПОДЛОГ — первой примете число подкручено на единицу."
  echo "ждём КРАСНОГО. Зелёный ответ значит, что сторож слеп."
fi

# Образцы могут перекрываться (у git «*» переходит через «/»), поэтому список
# файлов ВСЕГДА обеззначивается: иначе один файл сосчитался бы дважды и сторож
# покраснел бы на правде.
spisok_faylov() {
  printf '%s' "$1" | tr ',' '\0' \
    | xargs -0 -I{} git -c core.quotepath=false ls-files -- "{}" \
    | LC_ALL=C sort -u
}
strok_v() {
  spisok_faylov "$1" | tr '\n' '\0' | xargs -0 --no-run-if-empty cat 2>/dev/null | wc -l | tr -d ' '
}
faylov() {
  spisok_faylov "$1" | wc -l | tr -d ' '
}
# grep отвечает единицей, когда не нашёл ничего, — при `set -e` это сняло бы
# сторожа целиком. Ноль он при этом ПЕЧАТАЕТ, поэтому `|| true` ничего не
# теряет: число уже вышло.
primerov_v() {
  spisok_faylov "$1" | tr '\n' '\0' | xargs -0 --no-run-if-empty cat 2>/dev/null \
    | { grep -ac '^ *пример «' || true; } | tr -d ' '
}

while IFS="	" read -r FAYL NOMER PRIMETA HVOST; do
  if [ -z "$PRIMETA" ]; then
    echo "$FAYL:$NOMER: ПРИМЕТА НЕГОДНА — не разбирается: $HVOST" >> "$NAHODKI"
    NEGODNYH=$((NEGODNYH + 1)); continue
  fi

  DATA=$(printf '%s\n' "$PRIMETA" | awk '{print $2}')
  PRIBOR=$(printf '%s\n' "$PRIMETA" | awk '{print $3}')
  DOVOD=$(printf '%s\n' "$PRIMETA" | awk '{print $4}')
  ZAPISANO=$(printf '%s\n' "$PRIMETA" | awk '{print $NF}')

  if [ "$PODLOG" = "да" ] && [ "$PODLOZHENO" = "нет" ]; then
    ZAPISANO=$((ZAPISANO + 1)); PODLOZHENO=да
  fi

  case $DATA in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) : ;;
    *) echo "$FAYL:$NOMER: ПРИМЕТА НЕГОДНА — дата «$DATA» не вида ГГГГ-ММ-ДД" >> "$NAHODKI"
       NEGODNYH=$((NEGODNYH + 1)); continue ;;
  esac

  SNYATO=""
  case $PRIBOR in
    строк)
      if [ ! -f "$DOVOD" ]; then
        echo "$FAYL:$NOMER: ПРИМЕТА НЕГОДНА — файла «$DOVOD» нет" >> "$NAHODKI"
        NEGODNYH=$((NEGODNYH + 1)); continue
      fi
      SNYATO=$(wc -l < "$DOVOD" | tr -d ' ') ;;
    файлов|строк-в|примеров-в)
      # ПУСТОЙ ОБРАЗЕЦ — НЕГОДНАЯ ПРИМЕТА, А НЕ НОЛЬ. Образец, под который не
      # подпадает ни один файл, даёт 0; напиши в прозе «0» — и примета зеленеет,
      # ничего при этом не стерегя. Проверено подделкой Ч129 (П3): примета
      # «файлов *.нетакого = 0» рядом с прозой «awk | 0» прошла мимо сторожа при
      # одном настоящем awk-файле в дереве. Пустой образец почти всегда опечатка.
      if [ "$(faylov "$DOVOD")" = "0" ]; then
        echo "$FAYL:$NOMER: ПРИМЕТА НЕГОДНА — под образец «$DOVOD» не подпадает ни один файл: стеречь нечего" >> "$NAHODKI"
        NEGODNYH=$((NEGODNYH + 1)); continue
      fi
      case $PRIBOR in
        файлов)     SNYATO=$(faylov "$DOVOD") ;;
        строк-в)    SNYATO=$(strok_v "$DOVOD") ;;
        примеров-в) SNYATO=$(primerov_v "$DOVOD") ;;
      esac ;;
    список)
      PUT=${DOVOD%:*}; LN=${DOVOD##*:}
      if [ ! -f "$PUT" ]; then
        echo "$FAYL:$NOMER: ПРИМЕТА НЕГОДНА — файла «$PUT» нет" >> "$NAHODKI"
        NEGODNYH=$((NEGODNYH + 1)); continue
      fi
      # Список считается ОТ строки НОМЕР до закрывающей скобки, а не только на
      # самой строке. Однострочный список (`["а", "б"]`) даёт то же число, что и
      # прежде: скобка открылась и закрылась тут же. Многострочный (массив имён
      # в `.js`) прежде давал 0 и стеречь его было нечем — а именно так написан
      # закрытый список поручений у исполнителя плана.
      SNYATO=$(awk -v n="$LN" '
        NR < n { next }
        {
          s = $0
          while (match(s, /"[^"]*"/)) { c++; s = substr(s, 1, RSTART - 1) substr(s, RSTART + RLENGTH) }
          m = split(s, ch, "")
          for (i = 1; i <= m; i++) { if (ch[i] == "[") d++; else if (ch[i] == "]") d-- }
          videli = 1
          if (d <= 0) { print c + 0; gotovo = 1; exit }
        }
        END { if (videli && ! gotovo) print c + 0 }' "$PUT")
      [ -n "$SNYATO" ] || SNYATO=0 ;;
    *)
      echo "$FAYL:$NOMER: ПРИМЕТА НЕГОДНА — прибор «$PRIBOR» не из пяти (строк, файлов, строк-в, примеров-в, список)" >> "$NAHODKI"
      NEGODNYH=$((NEGODNYH + 1)); continue ;;
  esac

  if [ "$SNYATO" != "$ZAPISANO" ]; then
    echo "$FAYL:$NOMER: РАЗОШЛОСЬ С ДЕРЕВОМ — $PRIBOR $DOVOD: в примете $ZAPISANO, снято сегодня $SNYATO (примета от $DATA)" >> "$NAHODKI"
    RAZOSHLOS=$((RAZOSHLOS + 1)); continue
  fi

  # К чему примета привязана: своя строка, иначе три выше.
  N1=$NOMER; N0=$((NOMER - 3)); [ "$N0" -lt 1 ] && N0=1
  proza=$(awk -v a="$N0" -v b="$N1" 'NR>=a && NR<=b' "$FAYL" | sed 's/СНЯТО [0-9-]* [^ ]* [^ ]* = [0-9]*//g')
  golo=$(printf '%s' "$proza" | sed 's/\xc2\xa0/ /g; s/\xe2\x80\xaf/ /g; s/\xe2\x80\x89/ /g' | sed ':a;s/\([0-9]\) \([0-9]\)/\1\2/g;ta')
  # ЧИСЛО В ПРОЗЕ ИЩЕТСЯ ЦЕЛИКОМ, А НЕ ВХОЖДЕНИЕМ. Прежде примета «= 1» была
  # довольна прозой «12», а «= 79» — прозой «793»: сверка шла подстрокой.
  # Проверено подделкой Ч129 (П4): «| awk | 12 | 793 |» при приметах 1 и 79
  # прошло мимо сторожа, и проза врала под зелёным сторожем.
  #
  # ЧИСЛО СЛОВОМ ИЩЕТСЯ ПО ГРАНИЦЕ СЛОВА. Прежде корень «дв» находился внутри
  # «двадцать», «тр» — внутри «быстро», «восем» — внутри «восемнадцать».
  # Проверено подделкой Ч129 (П5): проза «Поручений в словаре двадцать» при
  # примете «= 2» была сторожу мила. Теперь за корнем разрешено не больше трёх
  # русских букв окончания, и слева обязана стоять граница слова: «два», «двух»,
  # «двумя» проходят, «двадцать» и «двенадцать» — нет.
  #
  # Считает gawk: диапазоны вида «а-я» в этой среде отказывают
  # («Invalid collation character»), поэтому буквы перечислены поимённо.
  NASHLOS=нет
  KOREN_CHISLA=""
  case $ZAPISANO in
    0) KOREN_CHISLA="нол" ;;      1) KOREN_CHISLA="один|одн" ;;
    2) KOREN_CHISLA="дв" ;;       3) KOREN_CHISLA="тр" ;;
    4) KOREN_CHISLA="четыр" ;;    5) KOREN_CHISLA="пят" ;;
    6) KOREN_CHISLA="шест" ;;     7) KOREN_CHISLA="сем" ;;
    8) KOREN_CHISLA="восем|восьм" ;; 9) KOREN_CHISLA="девят" ;;
    10) KOREN_CHISLA="десят" ;;   11) KOREN_CHISLA="одиннадцат" ;;
    12) KOREN_CHISLA="двенадцат" ;; 13) KOREN_CHISLA="тринадцат" ;;
    14) KOREN_CHISLA="четырнадцат" ;; 15) KOREN_CHISLA="пятнадцат" ;;
    16) KOREN_CHISLA="шестнадцат" ;; 17) KOREN_CHISLA="семнадцат" ;;
    18) KOREN_CHISLA="восемнадцат" ;; 19) KOREN_CHISLA="девятнадцат" ;;
    20) KOREN_CHISLA="двадцат" ;; 30) KOREN_CHISLA="тридцат" ;;
    40) KOREN_CHISLA="сорок" ;;   50) KOREN_CHISLA="пятьдесят|пятидесят" ;;
    100) KOREN_CHISLA="ста|сто" ;;
  esac
  NASHLOS=$(printf '%s\n' "$golo" | awk -v n="$ZAPISANO" -v koren="$KOREN_CHISLA" '
    BEGIN {
      BUKVY = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
      VSE   = BUKVY "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
    }
    { tekst = tekst $0 " " }
    END {
      s = tekst
      while (match(s, /[0-9]+/)) {
        if (substr(s, RSTART, RLENGTH) == n) { print "да"; exit }
        s = substr(s, RSTART + RLENGTH)
      }
      if (koren != "") {
        t = " " tolower(tekst) " "
        gsub("[^" BUKVY "]", " ", t)
        if (t ~ (" (" koren ")[" BUKVY "]{0,3} ")) { print "да"; exit }
      }
      print "нет"
    }')
  if [ "$NASHLOS" = "нет" ]; then
    echo "$FAYL:$NOMER: ПРИМЕТА ОТОРВАЛАСЬ ОТ ПРОЗЫ — числа $ZAPISANO нет ни на этой строке, ни в трёх выше" >> "$NAHODKI"
    RAZOSHLOS=$((RAZOSHLOS + 1)); continue
  fi

  SOSHLOS=$((SOSHLOS + 1))
done < "$PLOSKO"

echo "примет $VSEGO: сошлось $SOSHLOS, разошлось $RAZOSHLOS, негодных $NEGODNYH"
if [ "${VNE_KOMMENTARIYA:-0}" -gt 0 ]; then
  echo "строк «СНЯТО» вне комментария — $VNE_KOMMENTARIYA: это цитаты, приметами не считаны"
fi

if [ -s "$NAHODKI" ]; then
  echo ""
  echo "───────────────────────────────────────────────────────────────────"
  sort "$NAHODKI"
  echo "───────────────────────────────────────────────────────────────────"
fi

# ПРИГОВОР РАЗВЕДЁН НА ДВА СЛУЧАЯ, И ПРЕЖДЕ ОНИ БЫЛИ СЛИТЫ.
#
# Было: любая негодная примета давала код 3 со словами «Судить нечем» — раньше,
# чем проверялось расхождение. Проверено 5 сентября 2026 подложенной парой
# «одна негодная примета + одно настоящее расхождение»:
#
#   примет 142: сошлось 140, разошлось 1, негодных 1
#   docs/…:3: РАЗОШЛОСЬ С ДЕРЕВОМ — в примете 999, снято сегодня 3
#   сторож чисел: НЕ ДОСМОТРЕНО — негодных примет 1. Судить нечем.
#
# Сторож ПРОСУДИЛ сто сорок примет и нашёл настоящую ложь — и назвал свой же
# приговор несостоявшимся. Читающий видит «судить нечем» и идёт чинить примету,
# а расхождение остаётся.
#
# Стало: «судить нечем» — только когда судить ВПРАВДУ нечем, то есть ни одной
# годной приметы не нашлось. Кривая примета — беда наравне с расхождением:
# она не стережёт того, что автор думал, и чинится тем же движением.
GODNYH=$((SOSHLOS + RAZOSHLOS))
if [ "$GODNYH" = "0" ] && [ "$NEGODNYH" -gt 0 ]; then
  echo "сторож чисел: НЕ ДОСМОТРЕНО — годных примет нет ни одной, негодных $NEGODNYH." >&2
  echo "это не зелень и не краснота: судить нечем." >&2
  exit 3
fi
if [ "$RAZOSHLOS" -gt 0 ] || [ "$NEGODNYH" -gt 0 ]; then
  [ "$RAZOSHLOS" -gt 0 ] && echo "сторож чисел: числа в прозе разошлись с деревом — мест $RAZOSHLOS" >&2
  [ "$NEGODNYH" -gt 0 ] && echo "сторож чисел: примет негодных — $NEGODNYH: они не стерегут ничего" >&2
  echo "почините число ИЛИ примету: у каждого числа есть прибор и дата." >&2
  exit 1
fi
if [ "$PODLOG" = "да" ]; then
  echo "сторож чисел: ПОДЛОГ ПРОШЁЛ МИМО — сторож не увидел подкрученного числа." >&2
  echo "проверять им нечего: он зеленеет на том, что заведомо неверно." >&2
  exit 1
fi
echo "сторож чисел: все $VSEGO примет сошлись с деревом"
exit 0
