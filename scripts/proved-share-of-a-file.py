#!/usr/bin/env python3
"""Доля САМОГО файла в ведомости `flang check <файл> --proof --json`.

Зачем отдельный счётчик. `check` судит файл ВМЕСТЕ со всем, что тот ввозит, и
строка «итог:» относится к замыканию, а не к файлу: сложение этих строк по
дереву завышает в 2,47 раза, на ядре доказательств — в 34,2, на proofterm —
в 12,9. Поэтому приговор относят к файлу ПО ИМЕНИ ФУНКЦИИ, объявленной в нём.

Второй, независимый счёт — строки исходника, первое слово которых
«обеспечивает». Оба обязаны сойтись; если не сошлись, файл в сумму не идёт и
об этом говорится вслух, а не молча.

Вердикт ядра читается по ТАБЛИЦЕ (`ПО_ВЕРДИКТУ` ниже), а не условием «proved
или всё прочее»: вердиктов у ядра семь, и два из них — доказанные. Незнакомый
вердикт останавливает счёт файла вслух, а не уходит молча в «объявлено».

«требует» и «закон» считаются отдельно и в приговор не входят: у предусловия
в выводе `check --proof --json` нет ни записи в obligations, ни строки в
claims — оно проверяется на месте вызова, а не доказывается. Проверено
29 августа 2026 на flang/proof/examples/precondition.flang: пять «требует» и
три «обеспечивает» дают ровно три приговора.

    python3 scripts/proved-share-of-a-file.py <файл.flang> <ведомость.json>
"""
import collections
import json
import re
import sys

ФУНКЦИЯ = re.compile(r'^\s*(?:тотальная\s+)?функция\s+«([^»]+)»')
# «для всех н обеспечивает …» — то же обязательство, написанное с явной
# переменной: строка начинается не со слова «обеспечивает», и счёт по первому
# слову теряет её. Таких в дереве 140 в 76 файлах — их нельзя не считать.
ПОСТУСЛОВИЕ = re.compile(r'^\s+(?:для всех .*?)?обеспечивает\b')
БЕЗ_ПРИГОВОРА = re.compile(r'^\s+(?:для всех .*?)?(требует|закон)\b')


def разобрать_исходник(путь):
    имена, постусловий, без_приговора = set(), 0, 0
    for строка in open(путь, encoding='utf-8', errors='replace'):
        if строка.lstrip().startswith('//'):
            continue
        совпало = ФУНКЦИЯ.match(строка)
        if совпало:
            имена.add(совпало.group(1))
        if ПОСТУСЛОВИЕ.match(строка):
            постусловий += 1
        if БЕЗ_ПРИГОВОРА.match(строка):
            без_приговора += 1
    return имена, постусловий, без_приговора


# ВЕРДИКТ ЯДРА → КУЧА СЧЁТА. Таблица названа поимённо, а не собрана условиями,
# потому что молчаливое «всё прочее — объявлено» уже стоило дереву числа:
# «proved-induction» попадал в НЕДОКАЗАННЫЕ, хотя доказанность у индукции та же,
# что у цепочки. Сам компилятор считает иначе — flang/self/proof.flang, функция
# «Сколько доказано»: `proved` плюс `proved-induction`, и ничего больше.
#
# Замер 30 августа 2026, двоичный `897ce840` (семя плюс рантайм дерева), файл
# docs/benchmark/02-node-key.flang: ведомость говорит `proved 1, induction 1,
# declared 0`, а этот счётчик говорил «доказано 0 из 1 = 0,0 %». По 443 файлам
# дерева таких приговоров 398 — они стояли в недоказанных, будучи доказанными.
#
# «proved-conditional» доказанным НЕ считается и здесь: терм принят ядром, но
# посылку он засчитал фактом, не доказав её. Компилятор держит его отдельным
# полем «условно» — держим и мы, отдельной кучей, а не в числителе.
ПО_ВЕРДИКТУ = {
    'proved': 'доказано',
    'proved-induction': 'доказано',
    'proved-conditional': 'условно',
    'grid': 'сетка',
    'declared': 'объявлено',
    'refused': 'отвергнуто',
    'violated': 'нарушено',
}


def счёт(исходник, ведомость):
    имена, постусловий, без_приговора = разобрать_исходник(исходник)
    свод = json.load(open(ведомость, encoding='utf-8'))
    свои, ввезённых, виды = collections.Counter(), 0, collections.Counter()
    for приговор in свод['claims']:
        if приговор.get('of') not in имена:
            ввезённых += 1
            continue
        вид = приговор.get('verdict')
        виды[вид] += 1
        куда = ПО_ВЕРДИКТУ.get(вид)
        if куда is not None:
            свои[куда] += 1
    return свои, ввезённых, постусловий, без_приговора, виды


def главное(доводы):
    if len(доводы) != 2:
        print(__doc__.strip().splitlines()[-1].strip(), file=sys.stderr)
        return 2
    исходник, ведомость = доводы
    свои, ввезённых, постусловий, без_приговора, виды = счёт(исходник, ведомость)
    чужие = {в: н for в, н in виды.items() if в not in ПО_ВЕРДИКТУ}
    всего = sum(виды.values())
    написано = постусловий + без_приговора
    print(f'{исходник}: написано {написано} '
          f'(постусловий {постусловий}, без приговора {без_приговора}); '
          f'приговоров своих {всего}, ввезённых {ввезённых}')
    print(f'  доказано {свои["доказано"]} '
          f'(цепочкой {виды["proved"]}, индукцией {виды["proved-induction"]}), '
          f'сетка {свои["сетка"]}, объявлено {свои["объявлено"]}')
    for куча in ('условно', 'отвергнуто', 'нарушено'):
        if свои[куча]:
            print(f'  {куча} {свои[куча]} — в числитель не идёт')
    if чужие:
        for вид, сколько in sorted(чужие.items()):
            print(f'  ВЕРДИКТ НЕИЗВЕСТЕН: {вид!r} — {сколько}; '
                  f'файл в сумму не идёт, пока вид не назван в ПО_ВЕРДИКТУ')
        return 1
    if всего != постусловий:
        print(f'  СЧЁТЫ НЕ СОШЛИСЬ: приговоров {всего} при постусловиях '
              f'{постусловий} — файл в сумму не идёт')
        return 1
    доля = 100 * свои['доказано'] / написано if написано else 0
    print(f'  два счёта сошлись: доказано {свои["доказано"]} из {написано} '
          f'= {доля:.1f} %'.replace('.', ','))
    return 0


if __name__ == '__main__':
    sys.exit(главное(sys.argv[1:]))
