  # двухбайтовую пару C2 BB, а не байт BB сам по себе, поэтому «л» не рвёт
  # поиск. Проверяется на объявлении с «л» внутри имени.
  delete cs
  find_calls("«Величина полного порядка» от «x»", cs)
