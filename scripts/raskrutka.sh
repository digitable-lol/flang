# ── Самопроверка: поиск на заведомо совпадающем примере с кириллицей ───────
# Правило из ЗАДАНИЯ.md — три грабли (подменённый grep, \b в JS, отрицающий
# класс sed по байтам) роднит одно: молчаливый неполный ответ вместо ошибки.
# Здесь то же самое проверяется на «Алгебра» (без «л» — граница слова «от») и
# на «Величина полного порядка» (с «л» — байт BB внутри D0 BB, та самая
