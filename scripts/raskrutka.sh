# Поэтому отпечаток состоит теперь из ДВУХ блоков, и вопросы у них разные:
#
#   входы  — файлы замыкания и рантайма. Сверяются с ТЕМ КОММИТОМ, из которого
#            семя объявлено напечатанным. Расхождение с рабочим деревом —
#            ОТСТАВАНИЕ, число, а не отказ: входы правят раз в десять минут, а
#            печать идёт восемь часов.
#   тело   — то, что печать положила в `bootstrap/`. Сверяется с РАБОЧИМ
