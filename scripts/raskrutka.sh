# ── --build: собрать названное семя и спросить его ──────────────────────────
#
# Тот же прибор, которым печать проверяет свой вывод, — но зовомый отдельно, на
# уже напечатанном каталоге. Затем и заведён: проверку, которую нельзя показать
# на негодном семени, не отличить от той, что описана и не исполняется.
# Показано на семени захода D (/srv/tmp/reprint-3/semya-zahoda-D): клеймо чужое,
# сборка отказывает, код 4.
#
# Собирается всегда в стороне: названный каталог не трогается вовсе — он бывает
# единственным следом шестичасовой работы.
if [ "$mode" = build ]; then
  WORK=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" build.XXXXXX) || {
    err "не создался рабочий каталог в ${FLANG_TMP:-/srv/tmp}"; exit 5; }
  trap 'rm -rf "$WORK"' EXIT INT TERM
  taken=0
  for f in "$SEED_DIR"/*; do
    [ -f "$f" ] || continue
    cp "$f" "$WORK/" || { err "не скопировать $f в $WORK"; exit 5; }
    taken=$((taken + 1))
  done
  [ "$taken" -gt 0 ] || { err "в $SEED_DIR нет ни одного файла — собирать нечего"; exit 5; }
  say "проба семени из $SEED_DIR: файлов $taken, собираю в стороне ($WORK)"
  verdict=0
  build_and_ask "$WORK" || verdict=$?
  if [ "$verdict" -eq 4 ]; then
    err ""
    err "СЕМЯ НЕГОДНО: $SEED_DIR"
  elif [ "$verdict" -ne 0 ]; then
    err ""
    err "ПРОВЕРИТЬ НЕ УДАЛОСЬ — про семя $SEED_DIR это не говорит ничего."
  fi
  exit "$verdict"
fi

