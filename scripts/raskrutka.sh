# Точка раскрутки: перепечатать её двоичным компилятором и сверить с деревом.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# В bootstrap/ лежит компилятор flang, напечатанный в C99 и закоммиченный. Это
# семя: из него одним `make` собирается двоичный компилятор, и больше для сборки
# ничего не нужно. Семя обязано совпадать с тем, что печатают текущие исходники,
# иначе дерево и точка раскрутки тихо разъедутся.
#
# Раньше перепечатывал scripts/bootstrap-c.mjs — он звал реализацию компилятора
# на JavaScript. Реализации больше нет (коммит fe8e8a37), и перепечатывает теперь
# сам двоичный: flang₁ печатает flang₂, и они обязаны совпасть байт в байт.
#
# ── Почему оболочка, а не цель в bootstrap/Makefile и не план на flang ───────
# Не bootstrap/Makefile: он САМ один из семи напечатанных файлов и сверяется
# байт в байт. Дописанная туда руками цель исчезнет при первой же перепечатке, а
# до этого будет валить сверку. Место, которое проверяют на совпадение, править
# руками нельзя.
#
# Не план на flang (`flang io`): тогда проверка двоичного зависела бы ещё и от
# его исполнителя планов — то есть от второй части той же программы, которую
# проверяем. Плюс сверка означала бы чтение 23 МБ в строки языка.
#
# Оболочка не приносит на путь сборки ничего нового: sh, make и cc там уже нужны,
# а cmp лежит рядом с make у всех. Node не нужен ни на одном шаге.
#
# ИМЕНА ЗДЕСЬ ЛАТИНИЦЕЙ, в отличие от остального дерева: ни dash, ни bash не
# принимают кириллицу в именах переменных и функций (проверено обоими). Русский
# остался там, где он от оболочки не зависит, — в пояснениях и в выводе.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/raskrutka.sh              перепечатать bootstrap/ из исходников
#   sh scripts/raskrutka.sh --check      сверить закоммиченное с печатью
#   sh scripts/raskrutka.sh --stroki     только быстрая проверка строк рантайма
#   sh scripts/raskrutka.sh --bystro     сверить, ТЕ ЛИ входы у печати (секунды)
#   sh scripts/raskrutka.sh --otpechatok снять отпечаток входов заново
#
# Ключи среды:
#   FLANG=<путь>   каким двоичным печатать (по умолчанию bootstrap/flang,
#                  а если его нет — собрать `make -C bootstrap`)

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
INPUT=flang/self/bootstrap/compiler.flang
DIR=bootstrap
RUNTIME=flang/src/emit/c

# Пределы печати САМОГО КОМПИЛЯТОРА. Они уезжают в напечатанный байт
# (#define FL_MAX_STEPS), то есть участвуют в побайтовом совпадении. Умолчания
# бэкенда (10^6 шагов, 10^4 глубины) для компилятора малы: он разбирает 119 тысяч
# токенов и упирается в них на связывании вызовов. Ровно так уехал v0.4.1.
#
# ── ПОЧЕМУ 200 МИЛЛИОНОВ, А НЕ 40: ЗАМЕР, А НЕ ПРИКИДКА ──────────────────────
# 20 августа 2026 в ствол влили восемь целей печати, и замыкание компилятора
# выросло с 4206 функций до 6389 — на 51,9 %. Раскрутка встала: печать зовёт
# проверку (разбор, типы, завершаемость, ядро), а ядро в 40 000 000 шагов
# перестало помещаться.
#
# Снято двоичным, собранным из этой же точки с поднятым потолком, — вычислитель
# кладёт число витков в отчёт, и вот сколько стоит каждый шаг НА СЕГОДНЯШНЕМ
# дереве:
#
#   Связать исходники     23 726 585   59 % от 40 000 000
#   Проверить типы         3 919 602   10 %
#   Проверить тотальность    222 863    0,6 %
#   Беды ядра             56 355 645   141 %  ← не помещается
#
# Отсюда два вывода, и второй важнее первого.
#
# 1. Убрать ядро из проверки перед печатью НЕ СПАСЛО БЫ. Связывание — шаг, к
#    ядру отношения не имеющий, — уже съедает 59 % предела. Цена обхода растёт
#    квадратом размера замыкания (показатель 2,04, мерено отдельно): следующий
#    рост той же величины умножает на 2,3, и связывание одно даст ~55 000 000.
#    То есть 40 000 000 обвалились бы и без всякой проверки, просто позже и
#    громче.
#
# 2. Новый предел взят от ИЗМЕРЕННОГО пика плюс один названный рост:
#    56 355 645 × 2,3 ≈ 130 000 000, округлено вверх до 200 000 000. Это
#    сегодняшний пик × 3,55: хватает на рост дерева ещё в полтора раза с запасом
#    в 54 % сверх того.
#
# ЧТО ЭТО СТОИТ, названо числом, а не словом «дольше». Скорость мерена тем же
# прогоном: 84 614 600 витков за 14 мин 04 с, то есть около 100 000 витков в
# секунду. Значит программа, которая НЕ ЗАВЕРШАЕТСЯ, теперь считается до
# остановки не ~6,7 минуты, а ~33 минуты. Предел ловит зацикливание, и поднимать
# его вслепую значит ослаблять эту ловлю — поэтому он поднят по замеру и ровно
# один раз, а не «с запасом на всякий случай».
#
# ── ГДЕ НАСТОЯЩАЯ ЦЕНА, ЕСЛИ КТО-ТО ЗАХОЧЕТ УБРАТЬ ЕЁ, А НЕ ОПЛАТИТЬ ─────────
# «Беды ядра» стоят 56 млн витков не потому, что доказывать дорого. Ядро зовёт
# «Прогоны для ядра» (flang/self/bootstrap/compiler.flang), а тот, если в
# программе есть ХОТЬ ОДНА теорема, прогоняет ВСЕ примеры программы целиком.
# Сверка: полный прогон примеров того же файла («flang test») стоит 84 614 600
# витков — тот же порядок. У компилятора теорем пять, а примеров сотни, и
# оплачиваются все.
#
# Ядру же нужны не все прогоны, а ровно те, на которые ссылается обоснование
# «по примеру» в самих теоремах (их в замыкании единицы: distributed.flang и
# hotswap.flang). Сузить «Прогоны для ядра» до названных пар «функция, пример» —
# это и есть настоящая починка: она убирает из ядра почти всю его цену и рвёт
# связь «в программе есть теорема» → «прогнать весь корпус примеров». Здесь она
# НЕ сделана: это правка компилятора на самом языке, отдельной работой.
#
# ЧТОБЫ ЭТОТ ДЕНЬ НЕ ПОВТОРИЛСЯ МОЛЧА: шаг проверки, съевший больше половины
# предела, теперь говорит об этом сам — строкой «ЗАПАС ШАГОВ НА ИСХОДЕ» с числом
# и именем шага (repl_call в flang/src/emit/c/flang_repl.c). Обрыв перестал быть
# бесшумным до самого дна.
#
# ── КАК ПОДНЯТЬ ПРЕДЕЛ, КОГДА ОН СНОВА КОНЧИТСЯ ─────────────────────────────
# Здесь курица и яйцо: чтобы напечатать точку раскрутки с новым пределом, нужен
# двоичный, который проходит собственную проверку, — а он собран со СТАРЫМ
# пределом и её уже не проходит. Развязывается это один раз и руками:
#
#   1. скопировать bootstrap/*.c и *.h в пустой каталог;
#   2. в копии flang_runtime.h поправить строку «#define FL_MAX_STEPS» на новое
#      число (в напечатанном заголовке она БЕЗУСЛОВНАЯ, и -D её не перебьёт);
#   3. make в этом каталоге — получится двоичный с поднятым потолком;
#   4. FLANG=<путь к нему> sh scripts/raskrutka.sh — он напечатает новую точку
#      раскрутки уже с новым числом внутри, и дальше она себя держит сама.
#
# ПУСТОЙ КАТАЛОГ ОБЯЗАН ЛЕЖАТЬ В ЭТОМ ЖЕ ДЕРЕВЕ — либо к шагу 4 добавляется
# FLANG_MODULE_DIR. Ввозы по имени («использует «Печать JSON»» без пути) ищутся
# в том числе в «<каталог двоичного>/../flang/stdlib» и «…/flang/core»; двоичный,
# положенный вне дерева (скажем, в /srv/tmp), библиотеки не находит, и печать
# отменяется на 7083 замечаниях FLANG_IMPORT_NOT_FOUND / FLANG_NOT_TOTAL после
# девятнадцати минут работы. Проверено 23 августа 2026 — этими самыми
# девятнадцатью минутами. Лечится строкой:
#
#   FLANG=<путь> FLANG_MODULE_DIR=<дерево>/flang/stdlib:<дерево>/flang/core \
#     sh scripts/raskrutka.sh
# ── 23 АВГУСТА 2026: 1 000 000 000 → 4 000 000 000, И СНОВА ПО ЗАМЕРУ ───────
#
# Предел кончился не у печати компилятора, а у ВЕДОМОСТИ БИБЛИОТЕКИ. Файл
# flang/stdlib/json.flang (60 обещаний, 35 функций) не считался вовсе:
#
#   flang check flang/stdlib/json.flang --proof
#   → ЗАПАС ШАГОВ НА ИСХОДЕ: «Ведомость исходников» съел 1000000001 витков
#     из 1000000000 (100 %)
#   → FLANG_RECURSION_LIMIT: функция «Шаг нормализации» исчерпала лимит шагов
#     (1000000000) на глубине вызовов 78
#   код 1, 5 мин 41 с
#
# СКОЛЬКО ЕМУ НАДО НА САМОМ ДЕЛЕ — СНЯТО, А НЕ ПРИКИНУТО. Тот же файл той же
# командой двоичным с потолком 39 000 000 000 (копия bootstrap/ с поднятым
# #define, шаги 1–3 рецепта ниже):
#
#   «Ведомость исходников» → 1 370 430 254 витка, 11 мин 31 с, 823 МиБ, код 0
#   ведомость: утверждений 60 — доказано 19 (индукцией 16), сетка 41
#
# То есть счёт ЗАВЕРШАЕТСЯ и даёт ответ; не хватало 37 %. Ни зацикливания, ни
# ухода в глубину нет: глубина на обрыве 78 из 20 000.
#
# ПОЧЕМУ НЕ ПОЧИНКА ЯДРА, ХОТЯ ПЕРЕРАСХОД ВИДЕН. Замерено по одному обещанию:
# каждое из 60 в отдельности считается само по себе (пик 17,9 млн витков,
# пустая ведомость того же файла — 2,57 млн), сумма всех шестидесяти по
# отдельности — 86,4 млн. Вместе они стоят 1 370 млн, то есть в 16 раз больше
# суммы: цена растёт с ЧИСЛОМ ФАКТОВ в области видимости, потому что
# «Переписать до неподвижной» (flang/self/proof-kernel.flang) делает по проходу
# на факт и повторяет проходы, а «Переписанное после меры» зовёт её дважды.
# Кривая снята прямо: 0 обещаний — 2,57 млн, 15 — 40,3 млн, 30 — 381,8 млн,
# 45 — 962,6 млн, 60 — 1 370,4 млн.
#
# Это настоящая неэффективность, и чинится она в ядре — но правка ядра меняет
# ЧТО именно доказывается у всей библиотеки, а не только цену. Отдельная работа
# с отдельной сверкой всех ведомостей. Здесь оплачено то, что уже считается.
#
# НОВОЕ ЧИСЛО — измеренный пик × 2,9, тем же способом, что и в прошлый раз
# (пик плюс один названный рост): 1 370 430 254 × 2,3 ≈ 3,15 млрд, округлено
# вверх до 4 000 000 000.
#
# ЧТО ЭТО СТОИТ, названо числом. Скорость мерена этим же прогоном:
# 1 370 430 254 витка за 691 с, то есть 1,98 млн витков в секунду. Значит
# программа, которая НЕ ЗАВЕРШАЕТСЯ, считается до остановки не ~8,4 минуты, а
# ~34 минуты. Предел ловит зацикливание, и это ослабление — цена, а не бонус.
#
# ⚠ 29 АВГУСТА 2026: 1,98 МЛН — ЭТО СКОРОСТЬ ВИТКОВ, А ДЕЛЯТ НА НЕЁ ШАГИ.
# Число снято со строки «ЗАПАС ШАГОВ НА ИСХОДЕ», которая печатала
# «repl_ctx.steps» и называла его витками. Витками он перестал быть 27 августа:
# «fl_charge» кладёт в тот же счётчик цену прохода по встроенной форме.
# Как скорость ВИТКОВ 1,98 млн верно — снятая скорость витков на семи прогонах
# идёт от 0,52 до 2,40 млн/с. Но MAX_STEPS считается в ШАГАХ, а их скорость на
# тех же прогонах — от 20,0 до 182,5 млн/с:
#
#   check flang/self/interpret.flang --proof   6 684 620 058 шагов за 334,27 с → 20,0 млн/с
#   check flang/self/parser.flang    --proof  11 484 602 915 шагов за 282,23 с → 40,7 млн/с
#   check flang/self/lexer.flang     --proof     759 564 194 шага  за   5,60 с → 135,6 млн/с
#
# Значит все оценки времени, посчитанные ниже делением потолка на 1,98 млн,
# завышены в 10–69 раз. Разбор целиком, с ведомостями и лестницей размеров:
# docs/zettel/the-step-ledger-showed-ticks-and-called-them-steps.md.
#
# ── 29 АВГУСТА 2026: ЧТО ЭТО ЧИСЛО НА САМОМ ДЕЛЕ ДЕЛАЕТ ─────────────────────
#
# Всё, что написано выше, читается так, будто MAX_STEPS ограничивает ЭТОТ
# прогон. НЕ ОГРАНИЧИВАЕТ. Ключ «--max-steps» у команды «emit» только КЛЕЙМИТ
# число в вывод, а сам прогон идёт под потолком того двоичного, который печатает.
#
# Снято прогоном, а не прочитано:
#
#   $ flang emit проба.flang --target c --out … --max-steps 1
#   напечатано файлов 6, байт 408042        ← прогон НЕ оборвался на первом витке
#   $ grep 'define FL_MAX_STEPS' …/flang_runtime.h
#   #define FL_MAX_STEPS 1                  ← а в вывод уехала единица
#
# Значит MAX_STEPS — это потолок СЛЕДУЮЩЕГО семени, а не этого захода. И тогда
# правило для него одно: он обязан быть не меньше цены той перепечатки, которую
# СЛЕДУЮЩЕМУ семени придётся выполнить. Иначе следующий заход умрёт на нём —
# ровно так, как умер заход 24 августа 2026 (/srv/work/semya2.log): двоичный был
# собран с потолком 4 000 000 000, и «Суд ядра о программе» съел 4 000 000 001
# виток за 3 ч 02 мин 13 с и 216,9 ГиБ. Впустую.
#
# ── ПОЧЕМУ ЗДЕСЬ НЕ «ПИК × ЗАПАС», КАК ВЫШЕ ────────────────────────────────
#
# Потому что ПИКА НЕТ: самый дорогой шаг печати ни разу не досчитан до конца.
# Измерено 29 августа 2026 (прогоны лежат в /srv/tmp/steps-probe):
#
#   «Связать исходники»       14 228 379 129 витков — ДОСЧИТАН
#                             (closure-check.out: «съел 14228379129 витков
#                              из 20000000000 (71 %)»)
#   «Суд ядра о программе»   >100 000 005 443 витка — НЕ ДОСЧИТАН
#                             (closure-high.out: «съел 100000005443 витков
#                              из 100000000000 (100 %)» — сто миллиардов
#                              кончились раньше шага)
#
# Отсюда число ниже выведено не из пика, а из ПОЛА — наибольшей измеренной
# нижней оценки, — и это сказано вслух, чтобы никто не принял его за верхнюю.
# Пол 100 000 005 443 × 3 ≈ 300 миллиардов. Запас втрое, а не вдвое: за неделю
# 22–29 августа требование выросло со ста миллионов до ста миллиардов, то есть
# в тысячу раз, и вдвое здесь не запас, а самообман.
#
# ЧТО ЭТО СТОИТ. Прежде здесь стояло «~42 часа вместо ~34 минут», и это было
# посчитано делением потолка на 1,98 млн — то есть на скорость ВИТКОВ, тогда
# как потолок считается в ШАГАХ (см. врезку выше). По снятой скорости шагов
# незавершающаяся программа под таким потолком считается до обрыва от 0,6 ч
# (135,6 млн шагов/с, лексер) до 4,2 ч (20,0 млн шагов/с, толкователь) — вместо
# 42 часов. Ослабление ловли зацикливания настоящее, но в десять с лишним раз
# меньше, чем здесь было написано, и оплачено оно сознательно: потолок, при
# котором перепечатка не доходит, ловит не зацикливание, а саму раскрутку.
#
# Пол POL_IZMERENNYY ниже пересчитывать НЕ надо: он снят двоичным, у которого
# «fl_charge» уже есть (/srv/tmp/steps-probe/measure-build), то есть с самого
# начала в шагах. Витков в том же прогоне 27 754 778 253 при 100 000 005 443
# шагах — будь пол снят витками, он назывался бы 27,8 млрд, а не сто.
#
# КОГДА ПИК НАКОНЕЦ ИЗМЕРЯТ — заменить пол пиком и запас сузить. Пока пик не
# измерен, «POL_IZMERENNYY» ниже держит нижнюю границу: печатать с потолком
# МЕНЬШЕ уже измеренного шага бессмысленно, и скрипт на это не соглашается.
POL_IZMERENNYY=100000005443
MAX_STEPS=300000000000
MAX_DEPTH=20000

# Отказ вместо шести часов впустую. Проверяется до всякой работы: заход с
# потолком ниже измеренного пола не дойдёт до конца, и знать это надо ДО того,
# как машина занята на ночь, а не после.
if [ "$MAX_STEPS" -lt "$POL_IZMERENNYY" ]; then
  printf '%s
' "MAX_STEPS=$MAX_STEPS ниже измеренного пола $POL_IZMERENNYY —" >&2
  printf '%s
' "семя с таким потолком не сможет перепечатать дерево. Правьте scripts/raskrutka.sh." >&2
  exit 2
fi

# Что в bootstrap/ НЕ относится к точке раскрутки: пояснение и продукты сборки.
# Список повторён здесь затем, чтобы сверка работала и на дереве без .git.
NOT_SEED="README.md flang flang.exe flang_cli flang_cli.exe libcompiler_flang.a"

# ── ОТПЕЧАТОК ВХОДОВ ПЕЧАТИ: чем сверять семя, когда печатать нечем ──────────
#
# `--check` сверяет побайтно и потому ПЕЧАТАЕТ ЗАНОВО. Цена — последний
# ДОШЕДШИЙ до конца заход, 24 августа 2026 (/srv/work/semya3.log, код 0):
# 5 ч 30 мин 07 с и 271 526 800 кБ пика, то есть 258,9 ГиБ, на 256 ядрах.
# Столько на каждое слияние не потратить, и оттого сверку не звал никто.
