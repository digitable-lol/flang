# файла), семя (compiler_flang.c), исключения (хвостовой самовызов, батут
# взаимной рекурсии, непроверенное постусловие), сравнение множеств вызовов.
#
# Мера — /srv/tmp/dokazuemyy/Ч61-tela/MERA.md. Здесь — только механизм.
#
# Звать:
#   LC_ALL=C awk -v k1=<ядро1> -v k2=<ядро2> -v k3=<ядро3> \
#     -f tela.awk <root>/bootstrap/compiler_flang.c
#
# Печатает те же числа и списки, что run() в tela.py, простым текстом с
# метками полей (kernel_names, semya_names, soshlos_names, razoshlos_count,
# RAZOSHLOS/BATUT/SPEC/SPEC_RECOVERED построчно, soshlos_ok_count) — сверено
# с tela.py числом и множествами, не угадано.
#
# SPEC_RECOVERED — то, чего у Ч61 не было (её третий исход целиком назывался
# «непроверено-постусловие»): функция с «обеспечивает», у которой печать НЕ
# вставила fl_post(...) в C-тело — значит постусловие доказано статически, и
# тело сравнивается по-настоящему (см. ниже «Возьмись за 268»).

BEGIN {
  # ── ёлочки как литеральные БАЙТЫ, не как классы символов ──────────────────
  # Родня грабли Ч59 (отрицающий класс режет по байтам): здесь классов нет
  # вовсе, только index()/substr() над точными байтовыми строками — то же
  # решение, каким Ч59 сама себя починила (sed → awk, «отрезание головы и
  # хвоста»). guL/guR — «/» по 2 байта (C2 AB / C2 BB), а не regex-класс.
  guL = sprintf("%c%c", 194, 171)
  guR = sprintf("%c%c", 194, 187)
  lguL = length(guL); lguR = length(guR)
  cyr1 = sprintf("%c", 208)   # ведущий байт D0 — первая половина кириллицы
  cyr2 = sprintf("%c", 209)   # ведущий байт D1 — вторая половина кириллицы
  lot = length("от")          # 4 байта, не 2 — тоже байтовая ловушка
  POSTMARK = "/* постусловие " guL   # метка проверки, которую печать ставит перед fl_post
  # «без проверок» — 24 БАЙТА, не 13 знаков. Ч64 отрезала хвост числом 11
  # (счёт знаков, как в Python-первоисточнике), а под LC_ALL=C length() и
  # substr() работают ПО БАЙТАМ — отрезание не срабатывало ни разу. Пока
  # специализации не попадали в сверяемую часть, дефект молчал; с разрезом
  # постусловия он вылез сразу (31 имя вида «Строка поля без проверок»).
  # Родня грабли Ч59: молчаливый неполный ответ вместо ошибки.
  BEZPR = " без проверок"; lbez = length(BEZPR)

  selftest()
  if (fatal) exit fatal

  n_kfiles = 3
  kfiles[1] = k1; kfiles[2] = k2; kfiles[3] = k3

  # ── Пасс 1: загрузить три файла ядра целиком построчно ────────────────────
  KN = 0
  for (fi = 1; fi <= n_kfiles; fi++) {
    if (kfiles[fi] == "") { print "ПРОВЕРИТЬ_НЕ_УДАЛОСЬ: файл ядра #" fi " не назван" > "/dev/stderr"; fatal = 5; continue }
    ln = 0
    while ((getline kl < kfiles[fi]) > 0) {
      ln++
      KN++
      kline[KN] = kl
      kfileidx[KN] = fi
    }
    close(kfiles[fi])
    if (ln == 0) { print "ПРОВЕРИТЬ_НЕ_УДАЛОСЬ: файл ядра " kfiles[fi] " пуст или не читается" > "/dev/stderr"; fatal = 5 }
    kfile_end[fi] = KN
  }
  if (fatal) exit fatal

  # ── Найти границы объявлений «функция «Имя»» / «тотальная функция «Имя»» ──
  # Как YADRO_AWK: отрезание головы и хвоста, без отрицающего класса.
  DK = 0
  for (i = 1; i <= KN; i++) {
    line = kline[i]
    if (line ~ /^(тотальная )?функция «/) {
      t = line
      sub(/^(тотальная )?функция «/, "", t)
      # строгая проверка, как DECL_RE: строка обязана КОНЧАТЬСЯ на »
      # (после отбрасывания хвостовых пробелов), иначе это не объявление.
      rt = t
      sub(/[ \t]+$/, "", rt)
      if (rt ~ /»$/) {
        name = rt
        sub(/»$/, "", name)
        DK++
        dk_name[DK] = name
        dk_pos[DK] = i
        dk_file[DK] = kfileidx[i]
        if (name in kernel_seen) { dup_names = dup_names ";" name }
        else { kernel_seen[name] = 1; kernel_names_n++ }
      }
    }
  }
  if (DK == 0) { print "ПРОВЕРИТЬ_НЕ_УДАЛОСЬ: в трёх файлах ядра нет ни одного имени" > "/dev/stderr"; fatal = 5; exit fatal }

  # Конец блока k-й декларации = следующая декларация ТОГО ЖЕ файла минус 1,
  # либо конец файла. Одновременно — есть ли в блоке строка «принимает» (для
  # нулевой арности) — see kernel_nullary ниже, вторым проходом по блоку.
  for (k = 1; k <= DK; k++) {
    startp = dk_pos[k]
    endp = kfile_end[dk_file[k]]
    for (k2 = k + 1; k2 <= DK; k2++) {
      if (dk_file[k2] == dk_file[k]) { endp = dk_pos[k2] - 1; break }
    }
    dk_end[k] = endp
    has_prinimaet = 0
    for (i = startp + 1; i <= endp; i++) {
      ts = kline[i]
      sub(/^[ \t]+/, "", ts)
      if (ts ~ /^принимает/) { has_prinimaet = 1; break }
    }
    if (!has_prinimaet) kernel_nullary[dk_name[k]] = 1
  }
}

# ── Пасс 2: одним проходом читаем bootstrap/compiler_flang.c ───────────────
# Строим: cline[] — весь файл в памяти (нужен для обратного счёта скобок);
# name_to_id / id_to_name — пары «Имя» ↔ compiler_flang_<id> по комментарию
# ` * Функция flang «Имя».`, приём Ч54/Ч59, взят дословно;
# any_def_startline — ЛЮБОЕ определение compiler_flang_*( (для батута/twin).
{
  cline[FNR] = $0
  cN = FNR

  if ($0 ~ /^ \* Функция flang «/) {
    t = $0
    sub(/^ \* Функция flang «/, "", t)
    sub(/»\.[ \t]*$/, "", t)
    pend_name = t
    pend_active = 1
    next
  }
  if (pend_active) {
    if ($0 ~ /^(static )?[A-Za-z_][A-Za-z0-9_]* ?\**compiler_flang_[A-Za-z0-9_]+\(/) {
      id = def_id($0)
      if (!(pend_name in name_to_id)) {
        name_to_id[pend_name] = id
        id_to_name[id] = pend_name
        name_to_startline[pend_name] = FNR
        if (!(pend_name in semya_seen)) { semya_seen[pend_name] = 1; semya_names_n++ }
      }
      pend_active = 0
    } else if ($0 ~ /^[ \t]*$/ || $0 ~ /^ \*/ || $0 ~ /^\/\*/) {
      # комментарий продолжается — ждём дальше
    } else {
      pend_active = 0
    }
  }
  if ($0 ~ /^(static )?[A-Za-z_][A-Za-z0-9_]* ?\**compiler_flang_[A-Za-z0-9_]+\(/) {
    id = def_id($0)
    # ОПРЕДЕЛЕНИЕ или ПРОТОТИП — здесь ещё не видно (сигнатура шага батута
    # занимает две строки), поэтому кандидат откладывается, а разбирается в
    # END по терминатору: «{» — определение, «;» — объявление. Ч69: шаги
    # батута ОБЪЯВЛЕНЫ наверху файла (иначе взаимная рекурсия не соберётся),
    # и «первое вхождение» — прототип; вырезание с него проскакивает до
    # ближайшей ЧУЖОЙ «{» и называет телом чужую функцию (поймано на всех
    # 68: каждый давал «compiler_flang_sozdat_token»).
    DC++; dc_line[DC] = FNR; dc_id[DC] = id
    # сигнатура нулевой арности печати: ровно (fl_ctx *ctx, fl_value *result, fl_error *error)
    if ($0 ~ /\(fl_ctx \*ctx, fl_value \*result, fl_error \*error\)/) semya_nullary[id] = 1
  }
}

function def_id(line,    s, i) {
  s = line
  i = index(s, "compiler_flang_")
  s = substr(s, i)
  i = index(s, "(")
  if (i > 0) s = substr(s, 1, i - 1)
  gsub(/[ \t*]/, "", s)
  return s
}

# ── Конец: пришли к последнему файлу (compiler_flang.c закончен) ───────────
END {
  if (fatal) exit fatal
  if (semya_names_n == 0) { print "ПРОВЕРИТЬ_НЕ_УДАЛОСЬ: в семени нет ни одного имени функции flang" > "/dev/stderr"; exit 5 }

