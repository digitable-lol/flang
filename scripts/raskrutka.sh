# Печатей в дереве две: этот файл и scripts/bootstrap-c.sh. Пределы уезжают в
# напечатанный байт (`#define FL_MAX_STEPS`), поэтому два пути с разными числами
# дают разный flang_runtime.h и ломают побайтовое совпадение.
#
# Правило «число одно на оба пути» записано в шапке scripts/bootstrap-c.sh с
# 23 августа 2026 — и до сих пор его не исполнял никто. В тот день числа
# разъехались (1 000 000 000 против 4 000 000 000), и заметил это не сторож, а
# человек, прочитавший вывод `--bystro` глазами. Здесь правило исполняется.
#
# Не нашлось имени — это тоже расхождение, а не пропуск: не подтверждённое
# совпадение и есть то самое молчание, неотличимое от успеха.
second_number() {
  LC_ALL=C sed -n "s/^$1=['\"]\{0,1\}\([0-9][0-9]*\)['\"]\{0,1\}[ 	]*\$/\1/p" \
    "$ROOT/$SECOND_PRINT" | head -1
}

same_numbers_in_second_print() {
  if [ ! -f "$ROOT/$SECOND_PRINT" ]; then
    say "второго пути печати нет ($SECOND_PRINT) — сверять числа не с чем"
    return 0
  fi
  differs=0
  for pair in "FLANG_MAX_STEPS:$MAX_STEPS" \
              "FLANG_MAX_DEPTH:$MAX_DEPTH" \
              "FLANG_MEASURED_COST:$MEASURED_COST"; do
    name=${pair%%:*}
    want=${pair#*:}
    has=$(second_number "$name")
    [ "$has" = "$want" ] && continue
    err "  • $SECOND_PRINT: $name=«$has», а здесь «$want»"
    differs=$((differs + 1))
  done
  [ "$differs" -eq 0 ] && return 0
  err ""
  err "ДВА ПУТИ ПЕЧАТИ РАЗЪЕХАЛИСЬ — расхождений $differs. Пределы уезжают в"
  err "напечатанный байт, и печать этими двумя путями даст разные семена."
  err "Приведите числа к одному; довод числа — над MAX_STEPS в этом файле."
  exit 2
}

# ── Будет ли чем проверить напечатанное: спрашивается ДО печати ─────────────
#
# Печать идёт шесть часов (заход 29 августа 2026: 6 ч 23 мин). Узнать в конце
# этих шести часов, что проверять нечем — нет `make`, нет `cc`, пропал файл
# пробы, — значит потратить их впустую. Тот же довод, что у проверки потолка
# в шапке: отказ до работы, а не после.
can_check() {
  missing=0
  command -v make >/dev/null 2>&1 || {
    err "нет make: собрать напечатанное будет нечем"; missing=$((missing + 1)); }
  command -v "${CC:-cc}" >/dev/null 2>&1 || {
    err "нет ${CC:-cc}: собрать напечатанное будет нечем"; missing=$((missing + 1)); }
  [ -f "$ROOT/$PROBE_FILE" ] || {
    err "нет файла пробы $PROBE_FILE: спрашивать собранный двоичный будет не о чем"
    missing=$((missing + 1)); }
  [ "$missing" -eq 0 ]
}

# ── Собрать напечатанное и спросить его ─────────────────────────────────────
#
# ЗАЧЕМ. До 29 августа 2026 печать кончалась строкой «сборка без Node:
# make -C bootstrap» — СОВЕТОМ ЧЕЛОВЕКУ, а не выполненным шагом. Поэтому заход
# того дня отработал 6 ч 23 мин, вернул код 0 и объявил успех на семени, которое
# не собирается: строковая постоянная в 4614 знаков при гарантированных C99 4095
# (5.2.4.1; предел считается ПОСЛЕ склейки, так что склейка не спасает). Поймано
# руками за 42,3 с — `cc -Werror=overlength-strings`, bootstrap/compiler_flang.c,
# строка 5944. Проверка была описана и не исполнялась, а её отсутствие
# неотличимо от её успеха.
#
# ЧТО СПРАШИВАЕТСЯ. Три вещи, и каждая падала на деле:
#
#   КЛЕЙМО. Печать вписывает MAX_STEPS в `#define FL_MAX_STEPS` напечатанного
#     заголовка — так сказано в пояснении к отпечатку, и до сих пор этого не
#     проверял никто. Семя с чужим клеймом соберётся и заработает, а следующая
#     перепечатка умрёт на его потолке: 24 августа 2026 — 3 ч 02 мин и 216,9 ГиБ
#     впустую на клейме 4 000 000 000.
#   СБОРКА. `make` на напечатанном — тем самым Makefile, который напечатан
#     рядом с ним, и теми самыми флагами, которые он обещает выдержать.
#   ОТВЕТ. Двоичный, который собрался и падает при первом же вызове, тоже не
#     годен. Спрашивается один небольшой файл дерева, ответ известен заранее.
#
# ГДЕ. Всегда в стороне от дерева, в каталоге, который скрипт завёл сам. Точка
# раскрутки получает напечатанное только ПОСЛЕ того, как оно проверено: пока
# проверка не прошла, в дереве лежит прежнее, рабочее семя.
#
# ПОЧЕМУ НЕ ЦЕЛЬЮ В bootstrap/Makefile: он сам напечатан и сверяется байт в
# байт, дописанное туда исчезнет при первой же перепечатке (довод в шапке).
#
# Коды: 0 — годно, 4 — семя негодно, 5 — проверить не удалось.
build_and_ask() {
  seed=$1
  bad=0

  [ -d "$seed" ] || { err "каталога с напечатанным нет: $seed"; return 5; }
  can_check || return 5

  # Клеймо. Берётся ПЕРВОЕ вхождение: в напечатанном заголовке их два —
  # безусловный блок настроек программы наверху и умолчание рантайма под
  # `#ifndef` ниже. Работает верхнее, оно же и клеймится.
  if [ ! -f "$seed/flang_runtime.h" ]; then
    err "  • flang_runtime.h не напечатан — клеймо потолка спросить не у чего"
    bad=$((bad + 1))
  else
    steps=$(LC_ALL=C awk '/^#define FL_MAX_STEPS /{ print $3; exit }' "$seed/flang_runtime.h")
    depth=$(LC_ALL=C awk '/^#define FL_MAX_DEPTH /{ print $3; exit }' "$seed/flang_runtime.h")
    if [ "$steps" != "$MAX_STEPS" ]; then
      err "  • клеймо потолка шагов в напечатанном «$steps», а печаталось с «$MAX_STEPS»"
      err "    Семя несёт не тот потолок, с которым его печатали: следующая"
      err "    перепечатка пойдёт под ним и умрёт, если он мал."
      bad=$((bad + 1))
    fi
    if [ "$depth" != "$MAX_DEPTH" ]; then
      err "  • клеймо потолка глубины в напечатанном «$depth», а печаталось с «$MAX_DEPTH»"
      bad=$((bad + 1))
    fi
  fi

  if [ ! -f "$seed/Makefile" ]; then
    err "  • Makefile не напечатан — собирать напечатанное нечем"
    bad=$((bad + 1))
  else
    say "собираю напечатанное: make -C $seed"
    say "  (замер 29 августа 2026: годное семя ствола — 66,0 с и 1,03 ГиБ на 8 ядрах)"
    if ( cd "$seed" && make -j"$(cores)" ) >&2; then
      [ -x "$seed/flang" ] || {
        err "  • make отработал, а двоичного $seed/flang нет"
        bad=$((bad + 1)); }
    else
      err "  • НАПЕЧАТАННОЕ НЕ СОБИРАЕТСЯ: make отказал (отказ выше дословно)"
      bad=$((bad + 1))
    fi
  fi

  # Спрашивать нечего, пока не собралось.
  if [ "$bad" -ne 0 ]; then
    err ""
    err "напечатанное не прошло проверку — замечаний $bad."
    return 4
  fi

  # Срок пробе. Двоичный несёт потолок в $MAX_STEPS шагов, и незавершающаяся
  # проба считалась бы под ним часами — после шести часов печати это худший из
  # исходов. Замер пробы: 0,63 с; срок 600 с — тысячекратный запас. Нет
  # `timeout` — проба идёт без срока, и это сказано вслух, а не умолчано.
  deadline=
  if command -v timeout >/dev/null 2>&1; then
    deadline='timeout 600'
  else
    say "  timeout не найден: у пробы не будет срока"
  fi

  say "спрашиваю собранный двоичный: check $PROBE_FILE"
  if answer=$( cd "$ROOT" \
      && FLANG_MODULE_DIR="$ROOT/flang/stdlib:$ROOT/flang/core" \
         $deadline "$seed/flang" check "$PROBE_FILE" 2>&1 ); then
    code=0
  else
    code=$?
  fi
  if [ "$code" -ne 0 ]; then
    err "  • собранный двоичный не проверил $PROBE_FILE: код $code"
    printf '%s\n' "$answer" | sed 's/^/      /' >&2
    return 4
  fi
  if ! printf '%s\n' "$answer" | LC_ALL=C grep -qF "$PROBE_ANSWER"; then
    err "  • собранный двоичный ответил не то, что обязан («$PROBE_ANSWER»):"
    printf '%s\n' "$answer" | sed 's/^/      /' >&2
    return 4
  fi
  say "  ответил: $(printf '%s\n' "$answer" | tail -1)"
  say "напечатанное собрано и отвечает."
  return 0
}

# ── Двоичный, которым печатаем ───────────────────────────────────────────────
pick_binary() {
  if [ -n "${FLANG:-}" ]; then
    [ -x "$FLANG" ] || { err "FLANG=$FLANG — не исполняемый файл"; exit 3; }
    printf '%s\n' "$FLANG"
    return
  fi
  own=$ROOT/$DIR/flang
  if [ ! -x "$own" ]; then
    err "двоичного нет — собираю из точки раскрутки: make -C $DIR"
    make -C "$ROOT/$DIR" -j"$(cores)" >&2
  fi
  printf '%s\n' "$own"
}

size_of() { wc -c < "$1" | tr -d ' \n'; }

# Имена файлов точки раскрутки, лежащих в дереве: без пояснения и продуктов сборки.
names_in_tree() {
  ( cd "$ROOT/$DIR" 2>/dev/null || exit 0
    for name in *; do
      [ -e "$name" ] || continue
      case " $NOT_SEED " in *" $name "*) continue ;; esac
      case "$name" in *.o|*.obj|*.a|*.d) continue ;; esac
      printf '%s\n' "$name"
    done | sort )
}

# ── Чем считать отпечаток ────────────────────────────────────────────────────
#
# Ровно sha256 и никак иначе. `cksum` дал бы на том же файле другое число, и
# отпечаток, снятый одной машиной, не сошёлся бы на другой — сверка краснела бы
# всегда и потому никого бы ни от чего не уберегла. Нет ни sha256sum, ни
# shasum — отказ вслух кодом 3, а не тихая подмена слабым.
hash_cmd() {
  if command -v sha256sum >/dev/null 2>&1; then
    printf 'sha256sum\n'
  elif command -v shasum >/dev/null 2>&1; then
    printf 'shasum -a 256\n'
  else
    err "нужен sha256sum или shasum: отпечаток входов печати нечем снять"
    exit 3
  fi
}

# ── Замыкание компилятора: какие .flang читает печать ────────────────────────
#
# Правила ровно те же, что у самого компилятора:
#   `использует «Имя» из "файл"` — берётся файл РЯДОМ с тем, кто ввозит;
#   `использует «Имя»` без пути  — ищется объявление `модуль «Имя»` по дереву,
#                                  как это делает repl_closure в
#                                  flang/src/emit/c/flang_repl.c.
#
# Имя, которое не нашлось, — ОТКАЗ кодом возврата, а не пропуск. Пропуск здесь и
# есть та самая болезнь: сторож столкновений имён обходил ввозы только по пути,
# упирался на первом же файле, докладывал «замыкание 1 файлов, столкновений 0» и
# был зелёным. Тридцать пять файлов из тридцати шести он не видел вовсе.
#
# LC_ALL=C — не украшение. Под русской раскладкой `sort -u` считает
# «Печать в C#» и «Печать в C» ОДНОЙ строкой (решётка не буква) и молча теряет
# целую цель печати: замыкание выходило 35 файлов вместо 36. Поймано прогоном
# 22 августа при первой же сверке с числом, посчитанным другим способом.
# ОТКАЗ ОБХОДА НЕ ПРЯЧЕТСЯ ЗА `sort`. Сперва так и было: обход стоял в
# конвейере перед сортировкой, конвейер отдавал код последнего звена, и
# непонятое имя ввоза уходило в ноль. Цена ошибки не в коде возврата, а в том,
# что за непонятым именем МОЛЧА пропадает всё, что оно тянуло: отпечаток вышел
# бы короче, сверка — зелёной, а половины замыкания в ней бы не было. Ровно эта
# болезнь и разбирается в пояснении выше. Поэтому обход считается отдельно, а
# сортируется уже посчитанное.
closure_files() {
  # Расширений у программы три и они равноправны: `.flang`, `.fp`, `.фп`
  # (ADR-0008). Замыкание печати ищет исходник под любым из трёх — иначе
  # ввезённый файл с русским расширением молча выпал бы из отпечатка, а
  # молчаливый пропуск в замыкании — ровно та болезнь, о которой пояснение выше.
  spisok=$( cd "$ROOT" && find flang \( -name '*.flang' -o -name '*.fp' -o -name '*.фп' \) -type f | LC_ALL=C sort |
    LC_ALL=C awk -v start="$INPUT" '
      { files[++nf] = $0 }
      END {
        for (i = 1; i <= nf; i++) {
          f = files[i]
          known[f] = 1
          havemod = 0
          while ((getline line < f) > 0) {
            if (!havemod && line ~ /^модуль «/) {
              nm = line
              sub(/^модуль «/, "", nm)
              sub(/».*$/, "", nm)
              havemod = 1
              if (!(nm in file_of)) file_of[nm] = f
              continue
            }
            if (line ~ /^ *использует «/) {
              nm = line
              sub(/^ *использует «/, "", nm)
              sub(/».*$/, "", nm)
              imports[f] = imports[f] SUBSEP nm
              if (line ~ /из *"/) {
                pp = line
                sub(/^.*из *"/, "", pp)
                sub(/".*$/, "", pp)
                paths[f] = paths[f] SUBSEP pp
              }
            }
          }
          close(f)
        }
        bad = 0
        qn = 1; q[1] = start; head = 1
        while (head <= qn) {
          f = q[head++]
          if (f in seen) continue
          seen[f] = 1
          if (!(f in known)) {
            printf "  • %s: ввезён, но такого файла в дереве нет\n", f > "/dev/stderr"
            bad = 1
            continue
          }
          dir = f
          if (!sub(/\/[^\/]*$/, "", dir)) dir = "."
          n = split(paths[f], pv, SUBSEP)
          for (k = 1; k <= n; k++) {
            if (pv[k] == "") continue
            q[++qn] = (pv[k] ~ /^\//) ? pv[k] : dir "/" pv[k]
          }
          n = split(imports[f], mv, SUBSEP)
          for (k = 1; k <= n; k++) {
            if (mv[k] == "") continue
            if (mv[k] in file_of) { q[++qn] = file_of[mv[k]]; continue }
            printf "  • %s: ввоз «%s» не объявлен ни одним модулем дерева\n", f, mv[k] > "/dev/stderr"
            bad = 1
          }
        }
        for (f in seen) print f
        exit bad
      }
    ' ) || return 1
  printf '%s\n' "$spisok" | LC_ALL=C sort
}

# ── Сам отпечаток ────────────────────────────────────────────────────────────
#
# Три вида строк, и каждый вид попадает в напечатанный байт:
#   исходник — файл замыкания компилятора;
#   рантайм  — то, что уезжает в вывод ДОСЛОВНО; список берётся не из головы, а
#              пересечением напечатанных имён с каталогом рантайма, поэтому
#              новый напечатанный файл рантайма подхватится сам;
#   предел   — MAX_STEPS и MAX_DEPTH: они уходят в `#define FL_MAX_STEPS`.
stamp_now() {
  HASH=$(hash_cmd)
  CLOSURE=$(closure_files) || exit 1
  RT=
  for name in $(names_in_tree); do
    [ -f "$ROOT/$RUNTIME/$name" ] && RT="$RT $RUNTIME/$name"
  done
  printf '# Отпечаток входов печати точки раскрутки. Руками не править:\n'
  printf '# снимается печатью (sh scripts/raskrutka.sh), сверяется --bystro.\n'
  printf 'предел-шагов %s\n' "$MAX_STEPS"
  printf 'предел-глубины %s\n' "$MAX_DEPTH"
  printf 'вход %s\n' "$INPUT"
  printf 'ключи --cli --repl\n'
  ( cd "$ROOT" && $HASH $CLOSURE $RT | LC_ALL=C sort -k 2 )
}

