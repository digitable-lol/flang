# поиск на заведомо совпадающих примерах с буквой «л» — и КАЖДЫЙ приём
# проверяется ОБОИМИ концами: находит положенное И не находит отсутствующего.
# Проверено поломкой: отключи разрез, отскок, разбор прототипа или отрезание
# хвоста по байтам — сторож падает (exit 6), а не находит меньше.
TELA_AWK='# -*- coding: utf-8 -*-
