# Имена файлов точки раскрутки, лежащих в дереве: без пояснения и продуктов сборки.
names_in_tree() {
  NROOT=${1:-$ROOT}
  ( cd "$NROOT/$DIR" 2>/dev/null || exit 0
    for name in *; do
      [ -e "$name" ] || continue
      case " $NOT_SEED " in *" $name "*) continue ;; esac
      case "$name" in *.o|*.obj|*.a|*.d) continue ;; esac
      printf '%s\n' "$name"
    done | sort )
}

# ── Чем считать отпечаток ────────────────────────────────────────────────────
#
# Ровно sha256 и никак иначе. `cksum` дал бы на том же файле другое число, и
# отпечаток, снятый одной машиной, не сошёлся бы на другой — сверка краснела бы
# всегда и потому никого бы ни от чего не уберегла. Нет ни sha256sum, ни
# shasum — отказ вслух кодом 3, а не тихая подмена слабым.
hash_cmd() {
  if command -v sha256sum >/dev/null 2>&1; then
    printf 'sha256sum\n'
  elif command -v shasum >/dev/null 2>&1; then
    printf 'shasum -a 256\n'
  else
    err "нужен sha256sum или shasum: отпечаток входов печати нечем снять"
    exit 3
  fi
}

# ── Замыкание компилятора: какие .flang читает печать ────────────────────────
#
# Правила ровно те же, что у самого компилятора:
#   `использует «Имя» из "файл"` — берётся файл РЯДОМ с тем, кто ввозит;
#   `использует «Имя»` без пути  — ищется объявление `модуль «Имя»` по дереву,
#                                  как это делает repl_closure в
#                                  flang/src/emit/c/flang_repl.c.
#
# Имя, которое не нашлось, — ОТКАЗ кодом возврата, а не пропуск. Пропуск здесь и
# есть та самая болезнь: сторож столкновений имён обходил ввозы только по пути,
# упирался на первом же файле, докладывал «замыкание 1 файлов, столкновений 0» и
# был зелёным. Тридцать пять файлов из тридцати шести он не видел вовсе.
#
# LC_ALL=C — не украшение. Под русской раскладкой `sort -u` считает
# «Печать в C#» и «Печать в C» ОДНОЙ строкой (решётка не буква) и молча теряет
# целую цель печати: замыкание выходило 35 файлов вместо 36. Поймано прогоном
# 22 августа при первой же сверке с числом, посчитанным другим способом.
# ОТКАЗ ОБХОДА НЕ ПРЯЧЕТСЯ ЗА `sort`. Сперва так и было: обход стоял в
# конвейере перед сортировкой, конвейер отдавал код последнего звена, и
# непонятое имя ввоза уходило в ноль. Цена ошибки не в коде возврата, а в том,
# что за непонятым именем МОЛЧА пропадает всё, что оно тянуло: отпечаток вышел
# бы короче, сверка — зелёной, а половины замыкания в ней бы не было. Ровно эта
# болезнь и разбирается в пояснении выше. Поэтому обход считается отдельно, а
# сортируется уже посчитанное.
closure_files() {
  CROOT=${1:-$ROOT}
  # Расширений у программы три и они равноправны: `.flang`, `.fp`, `.фп`
  # (ADR-0008). Замыкание печати ищет исходник под любым из трёх — иначе
  # ввезённый файл с русским расширением молча выпал бы из отпечатка, а
  # молчаливый пропуск в замыкании — ровно та болезнь, о которой пояснение выше.
  spisok=$( cd "$CROOT" && find flang \( -name '*.flang' -o -name '*.fp' -o -name '*.фп' \) -type f | LC_ALL=C sort |
    LC_ALL=C awk -v start="$INPUT" '
      { files[++nf] = $0 }
      END {
        for (i = 1; i <= nf; i++) {
          f = files[i]
          known[f] = 1
          havemod = 0
          while ((getline line < f) > 0) {
            if (!havemod && line ~ /^модуль «/) {
              nm = line
              sub(/^модуль «/, "", nm)
              sub(/».*$/, "", nm)
              havemod = 1
              if (!(nm in file_of)) file_of[nm] = f
              continue
            }
            if (line ~ /^ *использует «/) {
              nm = line
              sub(/^ *использует «/, "", nm)
              sub(/».*$/, "", nm)
              imports[f] = imports[f] SUBSEP nm
              if (line ~ /из *"/) {
                pp = line
                sub(/^.*из *"/, "", pp)
                sub(/".*$/, "", pp)
                paths[f] = paths[f] SUBSEP pp
              }
            }
          }
          close(f)
        }
        bad = 0
        qn = 1; q[1] = start; head = 1
        while (head <= qn) {
          f = q[head++]
          if (f in seen) continue
          seen[f] = 1
          if (!(f in known)) {
            printf "  • %s: ввезён, но такого файла в дереве нет\n", f > "/dev/stderr"
            bad = 1
            continue
          }
          dir = f
          if (!sub(/\/[^\/]*$/, "", dir)) dir = "."
          n = split(paths[f], pv, SUBSEP)
          for (k = 1; k <= n; k++) {
            if (pv[k] == "") continue
            q[++qn] = (pv[k] ~ /^\//) ? pv[k] : dir "/" pv[k]
          }
          n = split(imports[f], mv, SUBSEP)
          for (k = 1; k <= n; k++) {
            if (mv[k] == "") continue
            if (mv[k] in file_of) { q[++qn] = file_of[mv[k]]; continue }
            printf "  • %s: ввоз «%s» не объявлен ни одним модулем дерева\n", f, mv[k] > "/dev/stderr"
            bad = 1
          }
        }
        for (f in seen) print f
        exit bad
      }
    ' ) || return 1
  printf '%s\n' "$spisok" | LC_ALL=C sort
}

# ── КОММИТ, ИЗ КОТОРОГО СЕМЯ ОБЪЯВЛЕНО НАПЕЧАТАННЫМ ──────────────────────────
#
# Отпечаток без коммита отвечает на вопрос «отвечает ли семя НЫНЕШНИМ
# исходникам», а на живом дереве ответ на него почти всегда «нет», и не по
# нерадивости. Замер 31 августа 2026, приёмная /srv/priyom/stvol, первый
# родитель, 27–30 августа: входы печати трогают 70 сводов, промежуток между
# касаниями — медиана 10 минут, среднее 70 минут. Печать же идёт часами: заход 4
# (29–30 авг, ствол f9e67fa6) — 7 ч 50 мин 45 с, заход 5 (30 авг, ствол
# 1eb168da) — 8 ч 34 мин от сборки печатающего двоичного до записи напечатанного.
# Значит зелёное окно после самой удачной перепечатки живёт медианные десять
# минут, а старт, из которого заход длиной 8 ч 34 мин вообще успевает кончиться
# без касания входов, приходится на 27,2 % времени за четверо суток и на 6,8 %
# времени 30 августа. Сторож, который такое краснит, краснит устройство, а не
# дисциплину, и его перестают читать.
#
# Поэтому вопрос заменён на тот, на который ответ ЕСТЬ и он проверяем:
#
#   отвечает ли отпечаток тому коммиту, из которого семя объявлено напечатанным,
#   и является ли тот коммит предком HEAD.
#
# Это НЕ ослабление. Старый вопрос ловил ровно одно: тихий разъезд дерева и
# точки раскрутки. Новый ловит его же и вдобавок то, чего старый не ловил вовсе:
# отпечаток, снятый с правленого руками дерева, и отпечаток, снятый на ветке,
# которая в ствол так и не влилась. А само отставание не прячется — оно
# печатается ЧИСЛОМ на каждом прогоне (сколько файлов замыкания разошлись между
# названным коммитом и рабочим деревом) и потому видно, не будучи красным.
#
# Пределы печати (MAX_STEPS, MAX_DEPTH) и вход по-прежнему сверяются с НЫНЕШНИМ
# скриптом, а не с коммитом: они живут здесь, а не в замыкании, и уезжают в
# `#define FL_MAX_STEPS`. Поднятый предел без перепечатки — настоящий разъезд, и
# он остаётся красным.
have_git() {
  command -v git >/dev/null 2>&1 || return 1
  git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1
}

# Коммит рабочего дерева — но только если ВХОДЫ ПЕЧАТИ в нём не правлены руками.
# Правленое дерево коммитом назвать нельзя: отпечаток соврал бы про то, что
# лежит в приёмной. Проверяется тем же способом, что описан в
# docs/reprint-runs-start-from-a-clean-tree.md, — `git diff --quiet HEAD -- …`.
commit_of_tree() {
  have_git || { printf 'нет-git\n'; return 0; }
  if ! git -C "$ROOT" diff --quiet HEAD -- $1 2>/dev/null; then
    printf 'дерево-правлено\n'
    return 0
  fi
  git -C "$ROOT" rev-parse HEAD 2>/dev/null || printf 'нет-git\n'
}

stamp_commit_of() { LC_ALL=C awk '$1 == "коммит" { print $2; exit }' "$1"; }

# Тело семени: пути напечатанных файлов относительно корня. Список тот же, каким
# печать судит свой вывод (`names_in_tree`), — продукты сборки и проза из него
# уже вычтены списком NOT_SEED, и новый напечатанный файл подхватится сам.
seed_body_paths() {
  BROOT=${1:-$ROOT}
  for name in $(names_in_tree "$BROOT"); do printf '%s/%s\n' "$DIR" "$name"; done
}

