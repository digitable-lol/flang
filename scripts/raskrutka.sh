# Каталог печати ОБЯЗАН пережить перезагрузку и отключение питания: на этой
# машине волатильные каталоги запрещены хуком, а TMPDIR по умолчанию ведёт
# именно туда. Печать компилятора — 39 МБ и полдня работы (последний дошедший
# заход, 30 августа 2026: 8 ч 34 мин 02 с, 38 958 005 байт вывода; предыдущий,
# 29–30 августа, — 7 ч 50 мин 45 с и 27,7 ГиБ пика по пульсу печати; лестница
# замеров — docs/reprint-cost.md), терять её на ребуте нельзя. Каталог задаётся
# FLANG_TMP, по умолчанию /srv/tmp.
TMP=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" raskrutka.XXXXXX)
# Каталог убирается за собой, но НЕ при отказе: шесть часов работы нельзя
# выбрасывать вместе с приговором. При отказе он остаётся и называется — семя
# захода 29 августа спасли ровно так, руками, и руками же это делать не надо.
KEEP=no
cleanup() {
  if [ "$KEEP" = yes ]; then
    err "напечатанное НЕ УДАЛЕНО и лежит в $TMP"
  else
    rm -rf "$TMP"
  fi
}
trap cleanup EXIT INT TERM

# КОММИТ СНИМАЕТСЯ ДО ПЕЧАТИ, А НЕ ПОСЛЕ. Печать идёт часами; к её концу дерево
# уже могли подвинуть, и коммит, снятый в конце, назвал бы НЕ ТО, из чего
# печаталось. Именно так семя захода 5 (30 августа 2026) уехало в ствол без
# имени своего коммита: печаталось дерево `1eb168da` (12:30), а легло в
# `c15f669f` (22:18) — на 123 свода позже.
VHODY=$(stamp_paths "$ROOT" | tr '\n' ' ')
KOMMIT=$(commit_of_tree "$VHODY")

say "компилятор: $INPUT"
say "печатает:   $BINARY"
say "пределы:    шагов $MAX_STEPS, глубины $MAX_DEPTH"
say "коммит:     $KOMMIT"
case "$KOMMIT" in
  дерево-правлено)
    err ""
    err "ВХОДЫ ПЕЧАТИ В ЭТОМ ДЕРЕВЕ ПРАВЛЕНЫ РУКАМИ."
    err "Печать пойдёт от правленого входа, и назвать коммит будет нельзя — а"
    err "непроверяемое семя в дерево не кладётся. Заход пускают из чистой копии:"
    err "docs/reprint-runs-start-from-a-clean-tree.md"
