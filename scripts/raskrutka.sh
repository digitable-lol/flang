#    хвост занимает 24 байта. Отрезание не срабатывало НИ РАЗУ и молчало,
#    потому что специализации «без проверок» встречаются только в проверке
#    постусловия, которую Ч64 не сверяла. С разрезом дефект вылез сразу — 31
#    имя вида «Строка поля без проверок». Исправлено на length(" без
#    проверок") и закрыто самопроверкой.
#
# На дереве 47b4d0ef после обоих ходов: сошлось 1032, разошлось 7 (пять
# прежних БЕЗ ИЗМЕНЕНИЙ плюс два новых — «По порядку» и «Условие в записи»,
# оба из группы батута), не проверено 0. Сверено двумя приборами: этим awk и
# независимым /srv/tmp/dokazuemyy/Ч69-poslednie-tela/tela69.py — числа и
# списки совпали.
#
# ЦЕНА, ЧИСЛОМ: ~1,0 с на дереве 47b4d0ef (три файла ядра — 15 282 строки;
# compiler_flang.c — 600 839 строк, 32 383 400 байт). git не нужен вовсе:
# сверяются два состояния одного дерева, а не дерево с историей.
#
# ГРАБЛЯ ЗАДАНИЯ.md (отрицающий класс sed режет по байтам, найдена Ч59):
# здесь класса [^»] нет нигде — только index()/substr() над точными байтовыми
