#
# ПОЧЕМУ ТЕЛО КРАСНОЕ, А ВХОДЫ НЕТ — довод, а не вкус. Входы живут своей жизнью
# и обязаны уезжать вперёд семени: в этом весь смысл отставания. Тело семени
# своей жизни не имеет вовсе: его меняет РОВНО ОДНО событие — перепечатка, а
# перепечатка снимает отпечаток заново тем же прогоном (см. конец файла).
# Значит всякое расхождение тела с отпечатком означает одно из двух: семя
# правлено руками, либо перепечатка прошла, а отпечаток не сняли. Оба случая —
# «собранный двоичный работает не по тем правилам, что записаны здесь», и оба
# обязаны быть красными.
#
# ПОЧЕМУ ТЕЛО СВЕРЯЕТСЯ С ДЕРЕВОМ, А НЕ С КОММИТОМ. Коммит в отпечатке — это
# коммит ВХОДОВ, снятый ДО печати; семя ложится в дерево на восемь часов позже и
# коммитится ещё позже (заход 5: печаталось `1eb168da`, легло в `c15f669f`, на
# 123 свода дальше). Спросить у того коммита, каким было тело, нельзя: там лежит
# ПРЕДЫДУЩЕЕ семя. Поэтому тело сверяется с тем, что реально соберётся, — с
# рабочим деревом.
#
# ЧЕГО НЕ ТРЕБУЕТ ЭТА ПОЛОВИНА, и это важно: побайтовой воспроизводимости
# печати. Отпечаток записывает ФАКТИЧЕСКИЕ байты семени в миг съёмки, а не то,
# что напечатали бы исходники. Две честные перепечатки могут дать разные байты —
# сверку это не поколеблет, потому что каждая снимает отпечаток себе. Вопрос
# «печатает ли дерево то же самое дважды» остаётся за `--check`, и он другой.
#
# ЦЕНА, ЧИСЛОМ: 7 файлов, 38 972 956 байт, sha256 по ним — 0,19 с (замер
# 31 августа 2026, ствол 03fb4060). Всё `--bystro` стоило 2,1 с и стало 2,4 с.
#
# Подделать сам отпечаток руками по-прежнему можно, как любую запись, — но не
# молча: строку тела придётся править вместе с семенем, а это уже не
# забывчивость и не 103 байта в чужом файле, это правка файла с надписью
# «руками не править» в приёмной, которую читают глазами.
