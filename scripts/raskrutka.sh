  exit 0
fi

if [ "$mode" = fast ]; then
  if [ ! -f "$ROOT/$SEED_STAMP" ]; then
    err "отпечатка входов печати нет: $SEED_STAMP"
    err "Снять: sh scripts/raskrutka.sh --otpechatok (после того, как семя перепечатано)"
    exit 1
  fi

  SDIR=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" otpechatok.XXXXXX) || {
    err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: не создался каталог в ${FLANG_TMP:-/srv/tmp}"; exit 5; }
  trap 'rm -rf "$SDIR"' EXIT INT TERM

  KOMMIT=$(stamp_commit_of "$ROOT/$SEED_STAMP")

  # Отпечаток обязан говорить, из какого коммита семя напечатано. Отпечаток без
  # этой строки сверять не с чем: он описывает дерево, которого уже нет.
  if [ -z "$KOMMIT" ]; then
    err "В ОТПЕЧАТКЕ НЕТ СТРОКИ «коммит»."
    err ""
    err "Он не говорит, из какого коммита семя напечатано, и потому проверить"
    err "нечего: сверять его с нынешним деревом бессмысленно — печать идёт часами,"
    err "а входы печати трогают раз в десять минут по медиане (замер 31 августа"
    err "2026, приёмная, первый родитель, 27–30 августа, 70 касаний)."
    err "Снять заново на том коммите, из которого семя печаталось:"
    err "  git worktree add <кат> <коммит> && sh <кат>/scripts/raskrutka.sh --otpechatok"
    exit 1
  fi

  if [ "$KOMMIT" = дерево-правлено ]; then
    err "ОТПЕЧАТОК СНЯТ С ПРАВЛЕНОГО ДЕРЕВА."
    err ""
    err "Входы печати в том дереве отличались от его коммита, поэтому коммит и не"
    err "назван. Из чего напечатано семя — неизвестно, и узнать это уже неоткуда."
    err "Заход надо повторить из чистой копии:"
    err "  docs/reprint-runs-start-from-a-clean-tree.md"
    exit 1
  fi

  # ── Где взять «то, что было» ────────────────────────────────────────────────
  #
  # Обычный случай — у git. Распакованный выпуск git-а не имеет: там дерево
  # заморожено на том самом коммите, и сверка с рабочим деревом — это ровно та
  # же сверка. Разница названа вслух, чтобы зелёное из выпуска не путали с
  # зелёным из ствола.
  BEZ_GIT=no
  if [ "$KOMMIT" = нет-git ] || ! have_git; then
    BEZ_GIT=yes
  elif ! git -C "$ROOT" cat-file -e "$KOMMIT^{commit}" 2>/dev/null; then
    if [ "$(git -C "$ROOT" rev-parse --is-shallow-repository 2>/dev/null)" = true ]; then
      err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: клон обрезанный, коммита $KOMMIT в нём нет."
      err "Про семя это не говорит НИЧЕГО. Лечится fetch-depth: 0 у checkout."
      exit 5
    fi
    err "КОММИТ, НАЗВАННЫЙ ОТПЕЧАТКОМ, ДЕРЕВУ НЕИЗВЕСТЕН: $KOMMIT"
    err ""
    err "Семя напечатано из чего-то, чего в этой приёмной нет."
    exit 1
  fi

  if [ "$BEZ_GIT" = yes ]; then
    say "git недоступен: сверяю отпечаток с рабочим деревом."
    say "  (в распакованном выпуске дерево заморожено, и это та же сверка;"
    say "   в живом клоне это старый вопрос, на который ответ почти всегда «нет»)"
    stamp_now "$ROOT" "$KOMMIT" > "$SDIR/nyne"
    if LC_ALL=C cmp -s "$ROOT/$SEED_STAMP" "$SDIR/nyne"; then
      say "входы и тело те же: $(grep -c '^[0-9a-f]' "$SDIR/nyne") файлов, пределы совпали"
      exit 0
    fi
    err "ВХОДЫ ПЕЧАТИ РАЗОШЛИСЬ С СЕМЕНЕМ."
    err ""
    otlichiya "$ROOT/$SEED_STAMP" "$SDIR/nyne"
    exit 1
  fi

  # ── 1. Родство: тот коммит обязан быть предком HEAD ─────────────────────────
  #
  # Это то, чего старая проверка не ловила вовсе. Семя, напечатанное на ветке,
  # которая в ствол не влилась, старую проверку прошло бы ровно так же плохо,
  # как честное отставшее, — то есть красным, неотличимо. Здесь эти два случая
  # разведены: отставание зелёное с числом, чужая родословная — красная.
  if ! git -C "$ROOT" merge-base --is-ancestor "$KOMMIT" HEAD 2>/dev/null; then
    err "КОММИТ СЕМЕНИ НЕ ПРЕДОК HEAD: $KOMMIT"
    err ""
    err "Семя напечатано из дерева, которого в стволе нет: ветка не влита либо"
    err "история переписана. Такое семя собирается и работает по правилам, которых"
    err "в стволе никто не видел."
    exit 1
  fi

  # ── 2. Отпечаток обязан отвечать НАЗВАННОМУ коммиту ────────────────────────
  #
  # Дерево того коммита выгружается в сторону и хешируется теми же правилами.
  # Пределы и вход при этом берутся из НЫНЕШНЕГО скрипта (см. пояснение у
  # have_git): поднятый предел без перепечатки обязан краснить.
  mkdir -p "$SDIR/togda" || { err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: не создался $SDIR/togda"; exit 5; }
  if ! git -C "$ROOT" archive "$KOMMIT" flang bootstrap 2>/dev/null | tar -xf - -C "$SDIR/togda"; then
    err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: не выгрузить дерево коммита $KOMMIT"
    err "Про семя это не говорит ничего."
    exit 5
  fi
  stamp_now "$SDIR/togda" "$KOMMIT" только-входы > "$SDIR/togda.vhody"

  # Тело из сверки с коммитом ВЫЧИТАЕТСЯ, и это не послабление, а единственный
  # верный ход: в том коммите лежит ПРЕДЫДУЩЕЕ семя — новое печаталось из него
  # и легло в дерево часами позже. Спрашивать у него про тело значило бы красить
  # каждую честную перепечатку. Тело спрашивается ниже, у рабочего дерева.
  bez_tela "$ROOT/$SEED_STAMP" > "$SDIR/stamp.vhody"
  if ! LC_ALL=C cmp -s "$SDIR/stamp.vhody" "$SDIR/togda.vhody"; then
    err "ОТПЕЧАТОК НЕ ОТВЕЧАЕТ КОММИТУ, КОТОРЫЙ САМ ЖЕ НАЗЫВАЕТ: $KOMMIT"
    err ""
    otlichiya "$SDIR/stamp.vhody" "$SDIR/togda.vhody"
    err "Отпечаток правлен руками, либо пределы печати подняты после перепечатки."
    err "И то и другое значит: собранное семя работает не по тем правилам, что"
    err "записаны здесь."
    exit 1
  fi

  # ── 2а. ТЕЛО СЕМЕНИ: то, из чего соберётся двоичный ────────────────────────
  #
  # Здесь и только здесь спрашивается ВЫХОД печати, а не её вход. Вопрос:
  # совпадает ли `bootstrap/**` в этом дереве с тем, что записала печать, снявшая
  # отпечаток. Ответ «нет» красен всегда и без `--strogo`, потому что тело семени
  # меняет ровно одно событие — перепечатка, а она снимает отпечаток сама.
  #
  # ЗАЧЕМ ЭТО ЗАВЕДЕНО, числом: 103 байта C в `bootstrap/flang_repl.c` провели
  # подделку через ядро как доказанную, и старая проверка на том же дереве
  # говорила «отставание 0 файлов», код 0
  # (/srv/tmp/dokazuemyy/Ч5-pechat/NAHODKA-podmena.md, 31 августа 2026).
  stamp_now "$ROOT" "$KOMMIT" > "$SDIR/nyne"
  telo_semeni "$ROOT/$SEED_STAMP" > "$SDIR/telo.otp"
  telo_semeni "$SDIR/nyne"        > "$SDIR/telo.nyne"
  bez_tela    "$SDIR/nyne"        > "$SDIR/nyne.vhody"
  if [ ! -s "$SDIR/telo.otp" ]; then
    err "В ОТПЕЧАТКЕ НЕТ ТЕЛА СЕМЕНИ."
    err ""
    err "Он снят прибором старше 31 августа 2026: тот покрывал входы печати и не"
    err "покрывал её выход, и правка в $DIR/ проходила мимо него молча."
    err "Снять заново: sh scripts/raskrutka.sh --otpechatok"
    exit 1
  fi
  if ! LC_ALL=C cmp -s "$SDIR/telo.otp" "$SDIR/telo.nyne"; then
    err "ТЕЛО СЕМЕНИ РАЗОШЛОСЬ С ОТПЕЧАТКОМ."
    err ""
    otlichiya "$SDIR/telo.otp" "$SDIR/telo.nyne" семя семени
    err "Это НЕ отставание. Входам положено уезжать вперёд семени, телу — нет:"
    err "его меняет только перепечатка, а она снимает отпечаток тем же прогоном."
    err "Значит либо $DIR/ правлен руками, либо перепечатка прошла без отпечатка."
    err "И то и другое значит: соберётся не то, что записано здесь."
    err ""
    err "Если перепечатка была честной — снять отпечаток: sh scripts/raskrutka.sh --otpechatok"
    exit 1
  fi

  # ── 2б. ИМЕНА ЯДРА: то ли ЯДРО в моём двоичном ────────────────────────────
  #
  # КУДА ЭТУ ПРОВЕРКУ СТАВИТЬ, и почему пока сюда, а не в ворота сборки.
  #
  # По смыслу её место рядом со сверкой тела: тот же вопрос («то ли двоичный»),
  # та же цена (0,35 с против 0,17 с), git ей нужен только для второй стороны.
  # Ворота сборки — .github/workflows/binary.yml:117, `--telo` перед каждой
  # сборкой двоичного — её родной дом.
  #
  # Она туда пока НЕ поставлена, и это не забывчивость. На стволе ee3465cd
  # (31 августа 2026) `--imena` красен: 29 имён ядра есть в исходниках и нет в
  # семени. Красный он не по своей вине — он говорит правду, — но ворота,
  # красные с первого дня, снимают, а не чинят. Поэтому здесь `--strogo`:
  # он на том же дереве УЖЕ красен отставанием входов (12 файлов), значит
  # новой красноты не добавляется ни одной, а замороженное перед выпуском
  # дерево спрашивается о ядре наравне со входами.
  #
  # ПЕРЕЕЗД в `--telo` — одной строкой в binary.yml, в тот день, когда идущая
  # сейчас перепечатка ляжет в ствол и `--imena` на стволе станет зелёным.
  # Условие переезда проверяется той же командой, гадать не надо.
  if [ "$STROGO" = yes ]; then
    say ""
    sh "$0" --imena || exit 1
    say ""
  fi

  # ── 3. Отставание — число, а не приговор ───────────────────────────────────
  OTSTAVANIE=$(git -C "$ROOT" rev-list --count "$KOMMIT..HEAD" 2>/dev/null || echo '?')
  say "семя отвечает коммиту $(git -C "$ROOT" rev-parse --short "$KOMMIT"), и он предок HEAD:"
  say "  входов в отпечатке $(grep -c . "$SDIR/stamp.vhody" ), пределы совпали, сводов с тех пор $OTSTAVANIE"
  say "  тело семени сошлось с деревом: файлов $(grep -c . "$SDIR/telo.otp"), байт $(cd "$ROOT" && cat $(seed_body_paths "$ROOT" | tr '\n' ' ') | wc -c | tr -d ' ')"
  if LC_ALL=C cmp -s "$SDIR/togda.vhody" "$SDIR/nyne.vhody"; then
    say "  входы печати с тех пор не двигались: отставание 0 файлов"
    exit 0
  fi
  say ""
  say "ОТСТАВАНИЕ ВХОДОВ ПЕЧАТИ (это не отказ — это число, ради которого заводят перепечатку):"
  otlichiya_say "$SDIR/togda.vhody" "$SDIR/nyne.vhody"
  if [ "$STROGO" = yes ]; then
    err ""
    err "--strogo: требовалось нулевое отставание, а оно не нулевое."
    exit 1
  fi
  exit 0
fi

