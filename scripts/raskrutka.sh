#    иначе третий исход), его тело разворачивается, а каждое «bounce->next =
#    Y_step» считается зовом Y. Соседние шаги при этом НЕ разворачиваются: они
#    зовы, а не своё тело — иначе вся компонента связности (68 штук) станет
