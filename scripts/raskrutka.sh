#        <строки постусловия>  "  /* постусловие «…» */"  fl_post …
#        "  *result = <результат>;"  "  return FL_OK;"
#    Значит зовы выше границы — тело, ниже — проверка. Это РАЗРЕЗ ПО МЕСТУ, а
#    не вычитание множеств: имя, стоящее и в теле, и в постусловии, при
