# ── Быстрая проверка: все строковые литералы C закрыты ───────────────────────
#
# Рантайм, прогонщик и оболочка (flang/src/emit/c/*.c) уезжают в напечатанное
# ДОСЛОВНО. Буквальный перенос строки, попавший внутрь строки C, ломает сборку —
# но узнаётся это на четвёртой минуте работы компилятора C, а после перепечатки
# ещё и оседает в семени. Здесь то же самое ловится за секунду.
check_literals() {
  awk '
    FNR == 1 { state = 0; fajlov += 1 }
    {
      strok += 1
      line = $0
      n = length(line)
      i = 1
      while (i <= n) {
        c = substr(line, i, 1)
        d = substr(line, i + 1, 1)
        if (state == 0) {
          if (c == "/" && d == "/") break
          if (c == "/" && d == "*") { state = 3; i += 2; continue }
          if (c == "\"") state = 1
          else if (c == "\047") state = 2
        } else if (state == 1) {
          if (c == "\\") { i += 2; continue }
          if (c == "\"") state = 0
        } else if (state == 2) {
          if (c == "\\") { i += 2; continue }
          if (c == "\047") state = 0
        } else if (state == 3) {
          if (c == "*" && d == "/") { state = 0; i += 2; continue }
        }
        i += 1
      }
      if (state == 1 || state == 2) {
        # Перенос внутри литерала законен ровно тогда, когда строка кончается
        # нечётным числом обратных косых: это склейка строк препроцессором.
        tail = 0
        j = n
        while (j >= 1 && substr(line, j, 1) == "\\") { tail += 1; j -= 1 }
        if (tail % 2 == 0) {
          what = (state == 1) ? "строковый литерал не закрыт к концу строки" \
                              : "символьный литерал не закрыт к концу строки"
          printf "  %s:%d: %s\n", FILENAME, FNR, what > "/dev/stderr"
          bad = 1
          state = 0
        }
      }
    }
    # ЧИСЛО ПЕЧАТАЕТСЯ ВСЕГДА, и это не украшение вывода. Проверка звалась
    # `"$ROOT/$RUNTIME"/*.c "$ROOT/$RUNTIME"/*.h` — раскрытием оболочки. Каталог,
    # переименованный или опустевший, дал бы awk несуществующие имена, а «все
    # литералы закрыты» с кодом 0 читалось бы как «посмотрено». Названное число
    # отличает «посмотрел шесть файлов» от «не посмотрел ни одного».
    END {
      if (bad) exit 1
      # ЧИСЛО ТЕПЕРЬ НЕ ТОЛЬКО ПЕЧАТАЕТСЯ, НО И ПРОВЕРЯЕТСЯ. Пояснение выше
      # говорит, что названное число отличает «посмотрел шесть файлов» от «не
      # посмотрел ни одного». Отличал их, однако, только человек, читающий
      # вывод: ноль файлов при коде 0 читался как «проверено». Проверка,
      # не открывшая ничего, обязана краснеть сама.
      if (fajlov + 0 == 0) {
        printf "  ни одного файла рантайма не прочитано — проверять было нечего\n" > "/dev/stderr"
        exit 1
      }
      printf "  все литералы закрыты: файлов %d, строк %d\n", fajlov + 0, strok + 0
      exit 0
    }
  ' "$@"
}

