function num_keys(arr,   c, k) { c = 0; for (k in arr) c++; return c }

# ── Маска строковых литералов C99 — та же роль, что mask_string_literals ───
# в tela.py: не дать декоративной ёлочке внутри "..." сойти за настоящий зов.
function mask_strings(line,    out, n, i, c, instr, esc) {
  n = length(line)
  out = ""
  instr = 0
  i = 1
  while (i <= n) {
    c = substr(line, i, 1)
    if (!instr) {
      out = out c
      if (c == "\"") instr = 1
    } else {
      if (c == "\\") {
        out = out "_"
        i++
        if (i <= n) out = out "_"
      } else if (c == "\"") {
        out = out c
        instr = 0
      } else {
        out = out "_"
      }
    }
    i++
  }
  return out
}

function is_word_byte(b) {
  if (b == "") return 0
  if (b ~ /^[A-Za-z0-9_]$/) return 1
  if (b == cyr1 || b == cyr2) return 1
  return 0
}

# ── Найти все зовы в строке: «Имя» от … (граница слова — байтовая, ручная,
# не regex \b — та самая грабля ЗАДАНИЯ.md про \b рядом с кириллицей), плюс
# голые «Имя» для БЕЗАРГУМЕНТНЫХ имён (nullary_set).
function find_calls(line, callset,   s, i, rest, j, name, after, matched, k, tail) {
  s = line
  while (1) {
    i = index(s, guL)
    if (i == 0) break
    rest = substr(s, i + lguL)
    j = index(rest, guR)
    if (j == 0) break
    name = substr(rest, 1, j - 1)
    after = substr(rest, j + lguR)
    matched = 0
    if (after ~ /^ +от/) {
      k = index(after, "от")
      tail = substr(after, k + lot)
      if (!is_word_byte(substr(tail, 1, 1))) matched = 1
    }
    if (matched || (name in nullary_set)) callset[name] = 1
    s = after
  }
}

# ── Вырезать C-функцию с start_line (строка сигнатуры) по счёту { } и
# РАЗРЕЗАТЬ её на тело и проверку постусловия ─────────────────────────────
#
# Разрез — не догадка о печати, а её исходник: flang/self/emit-c.flang,
# «Тело с постусловиями» (стр. 4787) печатает РОВНО так:
#     <строки тела>
#     "  const fl_value <результат> = <значение тела>;"      ← ГРАНИЦА
#     <строки постусловия> "  /* постусловие «…» */" fl_post …
#     "  *result = <результат>;"  "  return FL_OK;"
# Значит вызовы выше границы — тело, ниже — проверка. Это РАЗРЕЗ ПО МЕСТУ,
# а не вычитание множеств: имя, которое стоит и в теле, и в постусловии,
# при вычитании пропало бы из тела молча.
#
# Границу ищем не по метке (она ниже проверочных строк), а так: взять
# идентификатор X из «*result = X;» ПОСЛЕ метки, найти единственную строку
# «const fl_value X = » ДО метки. Не нашлось или нашлось не один раз —
# третий исход с причиной (region_fail_why), а не «сошлось».
#
# Заодно снимаются: имя шага батута из первого довода fl_trampoline
# (region_tramp_step) и цели отскока «bounce->next = Y_step» — они кладутся
# в out_ids как обычные зовы, потому что это и есть зовы, только переданные
# значением.
function extract_region(start_line, own, out_ids, post_ids,
                        depth, started, i, l, t, endl, p, X, res_n, b_n, cutb, j, tgt, step, rr) {
  region_fail_why = ""
  region_tramp_step = ""
  region_had_mark = 0
  depth = 0; started = 0; endl = 0
  for (i = start_line; i <= cN; i++) {
    l = cline[i]
    depth += gsub_count(l, "{") - gsub_count(l, "}")
    if (!started && index(l, "{") > 0) started = 1
    if (started && depth <= 0) { endl = i; break }
    if (i - start_line > 20000) { region_fail_why = "регион не закрылся"; return 0 }
  }
  if (!endl) { region_fail_why = "регион не закрылся"; return 0 }

  # ── где метка постусловия ────────────────────────────────────────────────
  p = 0
  for (i = start_line; i <= endl; i++) if (index(cline[i], POSTMARK) > 0) { p = i; break }
  cutb = endl
  if (p > 0) {
    region_had_mark = 1
    X = ""; res_n = 0
    for (i = p; i <= endl; i++) {
      t = cline[i]; sub(/[ \t]+$/, "", t)
      if (t ~ /^[ \t]*\*result = [A-Za-z_][A-Za-z0-9_]*;$/) {
        res_n++
        X = t; sub(/^[ \t]*\*result = /, "", X); sub(/;$/, "", X)
      }
    }
    if (res_n != 1) { region_fail_why = "после метки постусловия «*result =» встретился " res_n " раз"; return 0 }
    b_n = 0
    for (i = start_line; i < p; i++) {
      t = cline[i]; sub(/^[ \t]+/, "", t)
      if (index(t, "const fl_value " X " = ") == 1) { b_n++; cutb = i }
    }
    if (b_n != 1) { region_fail_why = "строка-граница «const fl_value " X " =» встретилась " b_n " раз"; return 0 }
  }

  # Ч74: границы региона наружу — по ним второй проход снимает ПОРЯДОК зовов
  # и втекание значений. Первый проход (Ч69) не трогаю: её числа обязаны
  # воспроизвестись до единицы.
  region_endl = endl
  region_cutb = cutb

  # ── собрать зовы, кладя их по нужную сторону границы ─────────────────────
  for (i = start_line; i <= endl; i++) {
    l = cline[i]
    if (i <= cutb) collect_ids(l, out_ids); else collect_ids(l, post_ids)
    t = l; sub(/^[ \t]+/, "", t); sub(/[ \t]+$/, "", t)
    if (index(t, "bounce->next = ") == 1) {
      tgt = substr(t, length("bounce->next = ") + 1); sub(/;$/, "", tgt)
      if (length(tgt) <= 5 || substr(tgt, length(tgt) - 4) != "_step") {
        region_fail_why = "цель отскока не кончается на _step: " tgt; return 0
      }
      if (i <= cutb) out_ids[tgt] = 1; else post_ids[tgt] = 1
    }
    if (index(l, "fl_trampoline(") > 0) {
      rr = substr(l, index(l, "fl_trampoline(") + length("fl_trampoline("))
      if (index(rr, "ctx, ") != 1) { region_fail_why = "fl_trampoline без разбираемого довода"; return 0 }
      step = substr(rr, length("ctx, ") + 1)
      j = index(step, ",")
      if (j == 0) { region_fail_why = "fl_trampoline без разбираемого довода"; return 0 }
      step = substr(step, 1, j - 1)
      # МЕРА, п. 4: имя шага, вынутое из текста, обязано быть шагом ИМЕННО
      # этой функции. Не совпало — не разворачиваю, а называю причину.
      if (step != own "_step") { region_fail_why = "шаг батута не свой: " step; return 0 }
      if (!(step in any_def_startline)) { region_fail_why = "шаг батута не найден определением: " step; return 0 }
      region_tramp_step = step
    }
  }
  return 1
}

function gsub_count(s, ch,    c, p, idx) {
  c = 0; p = s
  while ((idx = index(p, ch)) > 0) { c++; p = substr(p, idx + length(ch)) }
  return c
}

# compiler_flang_<id>( — идентификатор ЛАТИНИЦЕЙ, обычный regex безопасен.
function collect_ids(line, out_ids,    rest, idpart, i, j, ch, nxt) {
  rest = line
  while ((i = index(rest, "compiler_flang_")) > 0) {
    rest = substr(rest, i)
    idpart = ""
    j = 1
    while (j <= length(rest)) {
      ch = substr(rest, j, 1)
      if (ch ~ /^[A-Za-z0-9_]$/) { idpart = idpart ch; j++ } else break
    }
    nxt = substr(rest, j, 1)
    if (nxt == "(") out_ids[idpart] = 1
    if (length(idpart) == 0) rest = substr(rest, 2)
    else rest = substr(rest, j)
  }
}
