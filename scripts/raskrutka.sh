# запуск и разбор её вывода в три обязательных исхода: СОШЛОСЬ, РАЗОШЛОСЬ,
# НЕ ПРОВЕРЕНО — каждый с числом, ни один не молчит (ЗАДАНИЕ.md: «сторож,
# который пропускает неизвестное, хуже отсутствующего»).
if [ "$mode" = tela ]; then
  for f in $YADRO_FILES; do
    [ -f "$ROOT/$f" ] || {
      err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: нет файла ядра $f"
      exit 5; }
  done
  [ -f "$ROOT/$DIR/compiler_flang.c" ] || {
    err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: нет $DIR/compiler_flang.c — напечатанного семени не видно"
    exit 5; }

  # shellcheck disable=SC2086
  set -- $YADRO_FILES
  # ПОД `set -eu` ПРИСВОЕНИЕ ИЗ ПОДСТАНОВКИ УБИВАЕТ СКРИПТ МОЛЧА (найдено Ч74).
  # Так было: «TELA_OUT=$(…)» отдельной строкой, следом «TELA_CODE=$?». Awk
  # падает самопроверкой с кодом 6 — и `set -e` кончает скрипт ПРЯМО ЗДЕСЬ,
  # до разбора кода. Человек видит НОЛЬ строк и код 6: названная беда съедена,
  # а ветка «if [ $TELA_CODE -eq 6 ]» ниже недостижима по построению. Ровно та
  # порода, что за сутки поймана десять раз: сторож молчит по своей причине.
  # Проверено поломкой приёма: до правки — пустой вывод, после — текст беды.
  # `|| TELA_CODE=$?` делает подстановку проверяемой командой, и `set -e` её
  # не трогает.
  TELA_CODE=0
  TELA_OUT=$( cd "$ROOT" && printf '%s' "$TELA_AWK" \
    | LC_ALL=C awk -v k1="$1" -v k2="$2" -v k3="$3" -f /dev/stdin "$DIR/compiler_flang.c" 2>&1 ) \
    || TELA_CODE=$?

  if [ "$TELA_CODE" -eq 6 ]; then
    err "САМОПРОВЕРКА ПОИСКА ПРОВАЛЕНА — поиск начал молчать (родня грабли Ч59),"
    err "сверке тел в этом виде верить нельзя. Вывод самопроверки:"
    printf '%s\n' "$TELA_OUT" | sed 's/^/  /' >&2
    exit 5
  fi
  if [ "$TELA_CODE" -ne 0 ]; then
    err "ПРОВЕРИТЬ НЕ УДАЛОСЬ (код $TELA_CODE):"
    printf '%s\n' "$TELA_OUT" | sed 's/^/  /' >&2
    exit 5
  fi

  KN=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^kernel_names //p')
  SN=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^semya_names //p')
  SOSH=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^soshlos_names //p')
  RZ=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^razoshlos_count //p')
  NU=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^proverit_ne_udalos_count //p')
  BT=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^batut_count //p')
  SP=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^spec_count //p')
  SPR=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^spec_recovered_count //p')
  BTR=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^batut_recovered_count //p')
  MRK=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^mark_count //p')
  RZC=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^razrez_count //p')
  RZO=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^razrez_ok_count //p')
  RZB=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^razrez_bad_count //p')
  OK=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^soshlos_ok_count //p')
  # ── Ч74: не только НАБОР имён, но их ЧИСЛО и ПОРЯДОК ─────────────────────
  C74=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^ch74_chislo_count //p')
  P74=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^ch74_poryadok_count //p')
  PR74=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^ch74_pairs //p')
  NS74=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^ch74_nested //p')
  NU74=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^ch74_nested_sud //p')
  SL74=$(printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^ch74_slepo //p')

  # Разбор не понял свой же вывод — не «зелёный», а «проверить не удалось»:
  # ноль по молчанию неотличим от настоящего нуля, значит нужен явный признак.
  if [ -z "$KN" ] || [ -z "$SOSH" ] || [ -z "$RZ" ] || [ -z "$NU" ] || \
     [ -z "$BT" ] || [ -z "$SP" ] || [ -z "$OK" ] || [ -z "$BTR" ] || \
     [ -z "$MRK" ] || [ -z "$RZC" ] || [ -z "$RZO" ] || [ -z "$RZB" ] || \
     [ -z "$C74" ] || [ -z "$P74" ] || [ -z "$PR74" ] || [ -z "$NS74" ] || \
     [ -z "$NU74" ] || [ -z "$SL74" ]; then
    err "ПРОВЕРИТЬ НЕ УДАЛОСЬ: разбор вывода TELA_AWK не нашёл ожидаемых полей."
    printf '%s\n' "$TELA_OUT" | sed 's/^/  /' >&2
    exit 5
  fi
  NEPROV=$((NU + BT + SP))

  say "тела ядра решений сверены с напечатанным видом: имён ядра $KN, в семени $SN, общих (--imena) $SOSH"
  say ""
  OK74=$((OK - C74 - P74))
  RZ74=$((RZ + C74 + P74))
  SUD74=$((PR74 - NS74 + NU74))

  say "СОШЛОСЬ: $OK74 из $SOSH — те же имена, столько же раз и в том же порядке."
  say "  Ч69 сверяла только НАБОР имён и говорила $OK: перестановка и дубликат ей"
  say "  были невидимы — её же слова. Единица Ч74 — имена + число + порядок, кроме"
  say "  перестановок, которые печать делает законно (довод считается раньше"
  say "  потребителя). Замер ДО выбора: строгая последовательность дала бы 549"
  say "  ложных тревог из 1039, эта единица — ноль."
  say "  Порядок судится на $SUD74 парах зовов из $PR74. Слепыми остаются $SL74: это пары,"
  say "  связанные вложенностью так, что перестановка их двух зовов прошла бы молча —"
  say "  либо имя стоит в теле не по разу (какое вхождение какому отвечает, неизвестно),"
  say "  либо связь идёт только через охрану if, а не через поток значений. Названо"
  say "  числом, а не замолчано. У Ч69 порядок не судился НИ НА ОДНОЙ паре из $PR74."
  say ""
  say "  прежней мерой (только набор имён) СОШЛОСЬ: $OK из $SOSH"
  say "  из них $SPR — с проверкой постусловия в напечатанном виде: она отрезана по"
  say "  границе «const fl_value <результат> =», и сравнивается ТЕЛО, а не проверка"
  say "  (Ч61 и Ч64 такие функции не проверяли вовсе);"
  say "  из них $BTR — через батут взаимной рекурсии: адресат отскока вынут из"
  say "  напечатанного «bounce->next = <сосед>_step», а не угадан."
  say ""
  say "  самопроверка разреза: у $RZC функций под границей есть зовы; из них $RZO не"
  say "  зовут НИЧЕГО сверх того, что стоит в «обеспечивает» исходника, $RZB зовут"
  say "  (разрез прошёл бы не там — тогда это число не ноль)."
  if [ "$RZB" -gt 0 ]; then
    printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^RAZREZ_BAD /    ! /p' >&2
  fi
  say ""
  if [ "$RZ74" -gt 0 ]; then
    err "РАЗОШЛОСЬ: $RZ74 из $SOSH — та же функция, другое поведение"
    err "  (именами $RZ, числом зовов $C74, порядком зовов $P74):"
    printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^RAZOSHLOS /  • имена | /p' >&2
    printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^CH74_CHISLO /  • число | /p' >&2
    printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^CH74_PORYADOK /  • порядок | /p' >&2
  else
    say "РАЗОШЛОСЬ: 0"
  fi
  say ""
  say "НЕ ПРОВЕРЕНО: $NEPROV из $SOSH — регион не закрылся, разрез постусловия не"
  say "  нашёлся, шаг батута не свой или незнакомый id: $NU; батут $BT, постусловие $SP."
  say "  Это НЕ «сошлось» — сказано вслух, а не смолчано (ЗАДАНИЕ.md, отпечаток входов)."
  if [ "$NEPROV" -gt 0 ]; then
    printf '%s\n' "$TELA_OUT" | LC_ALL=C sed -n 's/^NE_UDALOS /  ? /p' >&2
  fi

  if [ "$RZ74" -eq 0 ]; then
    exit 0
  else
    exit 1
  fi
fi

