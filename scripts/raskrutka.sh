#    «;» (сигнатура шага занимает две строки — смотрим вперёд до шести).
#
# 4. ВТОРОЙ ДЕФЕКТ ТОГО ЖЕ РОДА (родня грабли Ч59 из ЗАДАНИЯ.md). Отрезание
#    хвоста « без проверок» Ч64 делала числом 11 — это счёт ЗНАКОВ, взятый из
