# Точка раскрутки: перепечатать её двоичным компилятором и сверить с деревом.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# В bootstrap/ лежит компилятор flang, напечатанный в C99 и закоммиченный. Это
# семя: из него одним `make` собирается двоичный компилятор, и больше для сборки
# ничего не нужно. Семя обязано совпадать с тем, что печатают текущие исходники,
# иначе дерево и точка раскрутки тихо разъедутся.
#
# Раньше перепечатывал scripts/bootstrap-c.mjs — он звал реализацию компилятора
# на JavaScript. Реализации больше нет (коммит fe8e8a37), и перепечатывает теперь
# сам двоичный: flang₁ печатает flang₂, и они обязаны совпасть байт в байт.
#
# ── Почему оболочка, а не цель в bootstrap/Makefile и не план на flang ───────
# Не bootstrap/Makefile: он САМ один из семи напечатанных файлов и сверяется
# байт в байт. Дописанная туда руками цель исчезнет при первой же перепечатке, а
# до этого будет валить сверку. Место, которое проверяют на совпадение, править
# руками нельзя.
#
# Не план на flang (`flang io`): тогда проверка двоичного зависела бы ещё и от
# его исполнителя планов — то есть от второй части той же программы, которую
# проверяем. Плюс сверка означала бы чтение 23 МБ в строки языка.
#
# Оболочка не приносит на путь сборки ничего нового: sh, make и cc там уже нужны,
# а cmp лежит рядом с make у всех. Node не нужен ни на одном шаге.
#
# ИМЕНА ЗДЕСЬ ЛАТИНИЦЕЙ, в отличие от остального дерева: ни dash, ни bash не
# принимают кириллицу в именах переменных и функций (проверено обоими). Русский
# остался там, где он от оболочки не зависит, — в пояснениях и в выводе.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/raskrutka.sh              перепечатать bootstrap/ из исходников
#   sh scripts/raskrutka.sh --check      сверить закоммиченное с печатью
#   sh scripts/raskrutka.sh --stroki     только быстрая проверка строк рантайма
#   sh scripts/raskrutka.sh --bystro     сверить, ТЕ ЛИ входы у печати (секунды)
#   sh scripts/raskrutka.sh --otpechatok снять отпечаток входов заново
#
# Ключи среды:
#   FLANG=<путь>   каким двоичным печатать (по умолчанию bootstrap/flang,
#                  а если его нет — собрать `make -C bootstrap`)

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
INPUT=flang/self/bootstrap/compiler.flang
DIR=bootstrap
RUNTIME=flang/src/emit/c

# Пределы печати САМОГО КОМПИЛЯТОРА. Они уезжают в напечатанный байт
# (#define FL_MAX_STEPS), то есть участвуют в побайтовом совпадении. Умолчания
# бэкенда (10^6 шагов, 10^4 глубины) для компилятора малы: он разбирает 119 тысяч
# токенов и упирается в них на связывании вызовов. Ровно так уехал v0.4.1.
#
# ── ПОЧЕМУ 200 МИЛЛИОНОВ, А НЕ 40: ЗАМЕР, А НЕ ПРИКИДКА ──────────────────────
# 20 августа 2026 в ствол влили восемь целей печати, и замыкание компилятора
# выросло с 4206 функций до 6389 — на 51,9 %. Раскрутка встала: печать зовёт
# проверку (разбор, типы, завершаемость, ядро), а ядро в 40 000 000 шагов
# перестало помещаться.
#
# Снято двоичным, собранным из этой же точки с поднятым потолком, — вычислитель
# кладёт число витков в отчёт, и вот сколько стоит каждый шаг НА СЕГОДНЯШНЕМ
# дереве:
#
#   Связать исходники     23 726 585   59 % от 40 000 000
#   Проверить типы         3 919 602   10 %
#   Проверить тотальность    222 863    0,6 %
#   Беды ядра             56 355 645   141 %  ← не помещается
#
# Отсюда два вывода, и второй важнее первого.
#
# 1. Убрать ядро из проверки перед печатью НЕ СПАСЛО БЫ. Связывание — шаг, к
#    ядру отношения не имеющий, — уже съедает 59 % предела. Цена обхода растёт
#    квадратом размера замыкания (показатель 2,04, мерено отдельно): следующий
#    рост той же величины умножает на 2,3, и связывание одно даст ~55 000 000.
#    То есть 40 000 000 обвалились бы и без всякой проверки, просто позже и
#    громче.
#
# 2. Новый предел взят от ИЗМЕРЕННОГО пика плюс один названный рост:
#    56 355 645 × 2,3 ≈ 130 000 000, округлено вверх до 200 000 000. Это
#    сегодняшний пик × 3,55: хватает на рост дерева ещё в полтора раза с запасом
#    в 54 % сверх того.
#
# ЧТО ЭТО СТОИТ, названо числом, а не словом «дольше». Скорость мерена тем же
# прогоном: 84 614 600 витков за 14 мин 04 с, то есть около 100 000 витков в
# секунду. Значит программа, которая НЕ ЗАВЕРШАЕТСЯ, теперь считается до
# остановки не ~6,7 минуты, а ~33 минуты. Предел ловит зацикливание, и поднимать
# его вслепую значит ослаблять эту ловлю — поэтому он поднят по замеру и ровно
# один раз, а не «с запасом на всякий случай».
#
# ── ГДЕ НАСТОЯЩАЯ ЦЕНА, ЕСЛИ КТО-ТО ЗАХОЧЕТ УБРАТЬ ЕЁ, А НЕ ОПЛАТИТЬ ─────────
# «Беды ядра» стоят 56 млн витков не потому, что доказывать дорого. Ядро зовёт
# «Прогоны для ядра» (flang/self/bootstrap/compiler.flang), а тот, если в
# программе есть ХОТЬ ОДНА теорема, прогоняет ВСЕ примеры программы целиком.
# Сверка: полный прогон примеров того же файла («flang test») стоит 84 614 600
# витков — тот же порядок. У компилятора теорем пять, а примеров сотни, и
# оплачиваются все.
#
# Ядру же нужны не все прогоны, а ровно те, на которые ссылается обоснование
# «по примеру» в самих теоремах (их в замыкании единицы: distributed.flang и
# hotswap.flang). Сузить «Прогоны для ядра» до названных пар «функция, пример» —
# это и есть настоящая починка: она убирает из ядра почти всю его цену и рвёт
# связь «в программе есть теорема» → «прогнать весь корпус примеров». Здесь она
# НЕ сделана: это правка компилятора на самом языке, отдельной работой.
#
# ЧТОБЫ ЭТОТ ДЕНЬ НЕ ПОВТОРИЛСЯ МОЛЧА: шаг проверки, съевший больше половины
# предела, теперь говорит об этом сам — строкой «ЗАПАС ШАГОВ НА ИСХОДЕ» с числом
# и именем шага (repl_call в flang/src/emit/c/flang_repl.c). Обрыв перестал быть
# бесшумным до самого дна.
#
# ── КАК ПОДНЯТЬ ПРЕДЕЛ, КОГДА ОН СНОВА КОНЧИТСЯ ─────────────────────────────
# Здесь курица и яйцо: чтобы напечатать точку раскрутки с новым пределом, нужен
# двоичный, который проходит собственную проверку, — а он собран со СТАРЫМ
# пределом и её уже не проходит. Развязывается это один раз и руками:
#
#   1. скопировать bootstrap/*.c и *.h в пустой каталог;
#   2. в копии flang_runtime.h поправить строку «#define FL_MAX_STEPS» на новое
#      число (в напечатанном заголовке она БЕЗУСЛОВНАЯ, и -D её не перебьёт);
#   3. make в этом каталоге — получится двоичный с поднятым потолком;
#   4. FLANG=<путь к нему> sh scripts/raskrutka.sh — он напечатает новую точку
#      раскрутки уже с новым числом внутри, и дальше она себя держит сама.
MAX_STEPS=1000000000
MAX_DEPTH=20000

# Что в bootstrap/ НЕ относится к точке раскрутки: пояснение и продукты сборки.
# Список повторён здесь затем, чтобы сверка работала и на дереве без .git.
NOT_SEED="README.md flang flang.exe flang_cli flang_cli.exe libcompiler_flang.a"

# ── ОТПЕЧАТОК ВХОДОВ ПЕЧАТИ: чем сверять семя, когда печатать нечем ──────────
#
# `--check` сверяет побайтно и потому ПЕЧАТАЕТ ЗАНОВО. Замерено 22 августа 2026
# на этом дереве, а не прикинуто: 19 мин 58 с и 25,1 ГиБ пика (256 ядер; на
# раннере CI будет дольше). Столько на каждое слияние не потратить, и оттого
# сверку не звал никто.
# Итог известен: правку компилятора вливают, семя остаётся прежним, правило
# лежит в исходниках и в собранной программе НЕ РАБОТАЕТ. Трижды за сутки
# 21–22 августа 2026: оговорка о конечности, принцип индукции по строке,
# правило конъюнкции.
#
# Отпечаток стоит секунды, потому что ничего не печатает. Он записывает, ИЗ ЧЕГО
# печаталось: содержимое каждого файла замыкания компилятора, содержимое
# рантайма, уезжающего в вывод дословно, и пределы печати, попадающие в
# напечатанный байт. Совпало — семя отвечает нынешним исходникам. Разошлось —
# компилятор правили и не перепечатали.
#
# ЧЕГО ОН НЕ ДОКАЗЫВАЕТ, и это надо знать: побайтового совпадения семени с
# печатью. Его доказывает только `--check`. Отпечаток отвечает на более узкий
# вопрос — «те ли входы» — но именно этот вопрос стоял без ответа, и именно на
# нём мы трижды погорели.
#
# Подделать запись можно руками, как любую запись. Защита здесь от забывчивости,
# не от умысла, и от забывчивости она работает.
SEED_STAMP=scripts/otpechatok-semeni

say() { printf '%s\n' "$*"; }
err() { printf '%s\n' "$*" >&2; }

# ── Быстрая проверка: все строковые литералы C закрыты ───────────────────────
#
# Рантайм, прогонщик и оболочка (flang/src/emit/c/*.c) уезжают в напечатанное
# ДОСЛОВНО. Буквальный перенос строки, попавший внутрь строки C, ломает сборку —
# но узнаётся это на четвёртой минуте работы компилятора C, а после перепечатки
# ещё и оседает в семени. Здесь то же самое ловится за секунду.
check_literals() {
  awk '
    FNR == 1 { state = 0 }
    {
      line = $0
      n = length(line)
      i = 1
      while (i <= n) {
        c = substr(line, i, 1)
        d = substr(line, i + 1, 1)
        if (state == 0) {
          if (c == "/" && d == "/") break
          if (c == "/" && d == "*") { state = 3; i += 2; continue }
          if (c == "\"") state = 1
          else if (c == "\047") state = 2
        } else if (state == 1) {
          if (c == "\\") { i += 2; continue }
          if (c == "\"") state = 0
        } else if (state == 2) {
          if (c == "\\") { i += 2; continue }
          if (c == "\047") state = 0
        } else if (state == 3) {
          if (c == "*" && d == "/") { state = 0; i += 2; continue }
        }
        i += 1
      }
      if (state == 1 || state == 2) {
        # Перенос внутри литерала законен ровно тогда, когда строка кончается
        # нечётным числом обратных косых: это склейка строк препроцессором.
        tail = 0
        j = n
        while (j >= 1 && substr(line, j, 1) == "\\") { tail += 1; j -= 1 }
        if (tail % 2 == 0) {
          what = (state == 1) ? "строковый литерал не закрыт к концу строки" \
                              : "символьный литерал не закрыт к концу строки"
          printf "  %s:%d: %s\n", FILENAME, FNR, what > "/dev/stderr"
          bad = 1
          state = 0
        }
      }
    }
    END { exit bad ? 1 : 0 }
  ' "$@"
}

cores() { (getconf _NPROCESSORS_ONLN 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 4) | tr -d ' '; }

# ── Двоичный, которым печатаем ───────────────────────────────────────────────
pick_binary() {
  if [ -n "${FLANG:-}" ]; then
    [ -x "$FLANG" ] || { err "FLANG=$FLANG — не исполняемый файл"; exit 3; }
    printf '%s\n' "$FLANG"
    return
  fi
  own=$ROOT/$DIR/flang
  if [ ! -x "$own" ]; then
    err "двоичного нет — собираю из точки раскрутки: make -C $DIR"
    make -C "$ROOT/$DIR" -j"$(cores)" >&2
  fi
  printf '%s\n' "$own"
}

size_of() { wc -c < "$1" | tr -d ' \n'; }

# Имена файлов точки раскрутки, лежащих в дереве: без пояснения и продуктов сборки.
names_in_tree() {
  ( cd "$ROOT/$DIR" 2>/dev/null || exit 0
    for name in *; do
      [ -e "$name" ] || continue
      case " $NOT_SEED " in *" $name "*) continue ;; esac
      case "$name" in *.o|*.obj|*.a|*.d) continue ;; esac
      printf '%s\n' "$name"
    done | sort )
}

# ── Чем считать отпечаток ────────────────────────────────────────────────────
#
# Ровно sha256 и никак иначе. `cksum` дал бы на том же файле другое число, и
# отпечаток, снятый одной машиной, не сошёлся бы на другой — сверка краснела бы
# всегда и потому никого бы ни от чего не уберегла. Нет ни sha256sum, ни
# shasum — отказ вслух кодом 3, а не тихая подмена слабым.
hash_cmd() {
  if command -v sha256sum >/dev/null 2>&1; then
    printf 'sha256sum\n'
  elif command -v shasum >/dev/null 2>&1; then
    printf 'shasum -a 256\n'
  else
    err "нужен sha256sum или shasum: отпечаток входов печати нечем снять"
    exit 3
  fi
}

# ── Замыкание компилятора: какие .flang читает печать ────────────────────────
#
# Правила ровно те же, что у самого компилятора:
#   `использует «Имя» из "файл"` — берётся файл РЯДОМ с тем, кто ввозит;
#   `использует «Имя»` без пути  — ищется объявление `модуль «Имя»` по дереву,
#                                  как это делает repl_closure в
#                                  flang/src/emit/c/flang_repl.c.
#
# Имя, которое не нашлось, — ОТКАЗ кодом возврата, а не пропуск. Пропуск здесь и
# есть та самая болезнь: сторож столкновений имён обходил ввозы только по пути,
# упирался на первом же файле, докладывал «замыкание 1 файлов, столкновений 0» и
# был зелёным. Тридцать пять файлов из тридцати шести он не видел вовсе.
#
# LC_ALL=C — не украшение. Под русской раскладкой `sort -u` считает
# «Печать в C#» и «Печать в C» ОДНОЙ строкой (решётка не буква) и молча теряет
# целую цель печати: замыкание выходило 35 файлов вместо 36. Поймано прогоном
# 22 августа при первой же сверке с числом, посчитанным другим способом.
# ОТКАЗ ОБХОДА НЕ ПРЯЧЕТСЯ ЗА `sort`. Сперва так и было: обход стоял в
# конвейере перед сортировкой, конвейер отдавал код последнего звена, и
# непонятое имя ввоза уходило в ноль. Цена ошибки не в коде возврата, а в том,
# что за непонятым именем МОЛЧА пропадает всё, что оно тянуло: отпечаток вышел
# бы короче, сверка — зелёной, а половины замыкания в ней бы не было. Ровно эта
# болезнь и разбирается в пояснении выше. Поэтому обход считается отдельно, а
# сортируется уже посчитанное.
closure_files() {
  spisok=$( cd "$ROOT" && find flang -name '*.flang' -type f | LC_ALL=C sort |
    LC_ALL=C awk -v start="$INPUT" '
      { files[++nf] = $0 }
      END {
        for (i = 1; i <= nf; i++) {
          f = files[i]
          known[f] = 1
          havemod = 0
          while ((getline line < f) > 0) {
            if (!havemod && line ~ /^модуль «/) {
              nm = line
              sub(/^модуль «/, "", nm)
              sub(/».*$/, "", nm)
              havemod = 1
              if (!(nm in file_of)) file_of[nm] = f
              continue
            }
            if (line ~ /^ *использует «/) {
              nm = line
              sub(/^ *использует «/, "", nm)
              sub(/».*$/, "", nm)
              imports[f] = imports[f] SUBSEP nm
              if (line ~ /из *"/) {
                pp = line
                sub(/^.*из *"/, "", pp)
                sub(/".*$/, "", pp)
                paths[f] = paths[f] SUBSEP pp
              }
            }
          }
          close(f)
        }
        bad = 0
        qn = 1; q[1] = start; head = 1
        while (head <= qn) {
          f = q[head++]
          if (f in seen) continue
          seen[f] = 1
          if (!(f in known)) {
            printf "  • %s: ввезён, но такого файла в дереве нет\n", f > "/dev/stderr"
            bad = 1
            continue
          }
          dir = f
          if (!sub(/\/[^\/]*$/, "", dir)) dir = "."
          n = split(paths[f], pv, SUBSEP)
          for (k = 1; k <= n; k++) {
            if (pv[k] == "") continue
            q[++qn] = (pv[k] ~ /^\//) ? pv[k] : dir "/" pv[k]
          }
          n = split(imports[f], mv, SUBSEP)
          for (k = 1; k <= n; k++) {
            if (mv[k] == "") continue
            if (mv[k] in file_of) { q[++qn] = file_of[mv[k]]; continue }
            printf "  • %s: ввоз «%s» не объявлен ни одним модулем дерева\n", f, mv[k] > "/dev/stderr"
            bad = 1
          }
        }
        for (f in seen) print f
        exit bad
      }
    ' ) || return 1
  printf '%s\n' "$spisok" | LC_ALL=C sort
}

# ── Сам отпечаток ────────────────────────────────────────────────────────────
#
# Три вида строк, и каждый вид попадает в напечатанный байт:
#   исходник — файл замыкания компилятора;
#   рантайм  — то, что уезжает в вывод ДОСЛОВНО; список берётся не из головы, а
#              пересечением напечатанных имён с каталогом рантайма, поэтому
#              новый напечатанный файл рантайма подхватится сам;
#   предел   — MAX_STEPS и MAX_DEPTH: они уходят в `#define FL_MAX_STEPS`.
stamp_now() {
  HASH=$(hash_cmd)
  CLOSURE=$(closure_files) || exit 1
  RT=
  for name in $(names_in_tree); do
    [ -f "$ROOT/$RUNTIME/$name" ] && RT="$RT $RUNTIME/$name"
  done
  printf '# Отпечаток входов печати точки раскрутки. Руками не править:\n'
  printf '# снимается печатью (sh scripts/raskrutka.sh), сверяется --bystro.\n'
  printf 'предел-шагов %s\n' "$MAX_STEPS"
  printf 'предел-глубины %s\n' "$MAX_DEPTH"
  printf 'вход %s\n' "$INPUT"
  printf 'ключи --cli --repl\n'
  ( cd "$ROOT" && $HASH $CLOSURE $RT | LC_ALL=C sort -k 2 )
}

# ── Разбор доводов ───────────────────────────────────────────────────────────
mode=print
case "${1:-}" in
  --check) mode=verify ;;
  --stroki) mode=literals ;;
  --bystro) mode=fast ;;
  --otpechatok) mode=stamp ;;
  "") ;;
  *) err "неизвестный довод: $1"; err "звать: sh scripts/raskrutka.sh [--check|--stroki|--bystro|--otpechatok]"; exit 2 ;;
esac

say "строки рантайма $RUNTIME: проверяю, что все литералы закрыты"
if ! check_literals "$ROOT/$RUNTIME"/*.c "$ROOT/$RUNTIME"/*.h; then
  err ""
  err "литерал не закрыт — печатать нельзя: он уедет в точку раскрутки дословно."
  exit 1
fi
say "  все литералы закрыты"
[ "$mode" = literals ] && exit 0

# ── Отпечаток: снять или сверить. Двоичный тут не нужен и не зовётся ────────
#
# Порядок именно такой: сверка входов идёт ДО выбора двоичного. Иначе на дереве
# без собранного bootstrap/flang дешёвая проверка сначала собирала бы компилятор
# минуту, а могла бы ответить за секунду.
if [ "$mode" = stamp ]; then
  stamp_now > "$ROOT/$SEED_STAMP"
  say "отпечаток входов печати снят: $SEED_STAMP"
  say "  строк $(grep -c . "$ROOT/$SEED_STAMP")"
  exit 0
fi

if [ "$mode" = fast ]; then
  if [ ! -f "$ROOT/$SEED_STAMP" ]; then
    err "отпечатка входов печати нет: $SEED_STAMP"
    err "Снять: sh scripts/raskrutka.sh --otpechatok (после того, как семя перепечатано)"
    exit 1
  fi
  SDIR=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" otpechatok.XXXXXX)
  trap 'rm -rf "$SDIR"' EXIT INT TERM
  stamp_now > "$SDIR/nyne"
  if LC_ALL=C cmp -s "$ROOT/$SEED_STAMP" "$SDIR/nyne"; then
    say "входы печати те же, что при перепечатке семени: $(grep -c '^[0-9a-f]' "$SDIR/nyne") файлов, пределы совпали"
    exit 0
  fi
  err "ВХОДЫ ПЕЧАТИ РАЗОШЛИСЬ С СЕМЕНЕМ."
  err ""
  LC_ALL=C awk '
    NR == FNR {
      if ($1 ~ /^[0-9a-f][0-9a-f]*$/ && NF == 2) bylo[$2] = $1
      else if ($0 !~ /^#/) meta_b[++mb] = $0
      next
    }
    {
      if ($1 ~ /^[0-9a-f][0-9a-f]*$/ && NF == 2) { nyne[$2] = $1; poryadok[++np] = $2 }
      else if ($0 !~ /^#/) meta_n[++mn] = $0
    }
    END {
      n = 0
      for (i = 1; i <= (mb > mn ? mb : mn); i++)
        if (meta_b[i] != meta_n[i]) {
          printf "  • печать зовётся иначе: было «%s», стало «%s»\n", meta_b[i], meta_n[i] > "/dev/stderr"
          n++
        }
      for (i = 1; i <= np; i++) {
        f = poryadok[i]
        if (!(f in bylo)) { printf "  • %s: вошёл в замыкание после перепечатки\n", f > "/dev/stderr"; n++ }
        else if (bylo[f] != nyne[f]) { printf "  • %s: изменён после перепечатки\n", f > "/dev/stderr"; n++ }
      }
      for (f in bylo)
        if (!(f in nyne)) { printf "  • %s: выпал из замыкания после перепечатки\n", f > "/dev/stderr"; n++ }
      printf "\nрасхождений %d.\n", n > "/dev/stderr"
    }
  ' "$ROOT/$SEED_STAMP" "$SDIR/nyne"
  err "Компилятор правили, семя не перепечатали. Оно соберётся и будет работать"
  err "по СТАРЫМ правилам — правка в собранной программе не появится."
  err "Перепечатать: sh scripts/raskrutka.sh (замер: 20 минут, 25 ГиБ), затем закоммитить"
  err "bootstrap/ и $SEED_STAMP вместе с правкой."
  exit 1
fi

BINARY=$(pick_binary)

# Каталог печати ОБЯЗАН пережить перезагрузку и отключение питания: на этой
# машине волатильные каталоги запрещены хуком, а TMPDIR по умолчанию ведёт
# именно туда. Печать компилятора — 25 МБ и двадцать минут работы (замер
# 22 августа 2026: 19 мин 58 с, 25,1 ГиБ пика, 256 ядер), терять её на
# ребуте нельзя. Каталог задаётся FLANG_TMP, по умолчанию /srv/tmp.
TMP=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" raskrutka.XXXXXX)
trap 'rm -rf "$TMP"' EXIT INT TERM

say "компилятор: $INPUT"
say "печатает:   $BINARY"
say "пределы:    шагов $MAX_STEPS, глубины $MAX_DEPTH"
# `--runtime` НАЗЫВАЕТСЯ, а не оставляется на поиск. Рантайм, прогонщик и
# оболочка уезжают в вывод дословно, и печать читает их с диска; сама она ищет
# их рядом с СОБОЙ (`<каталог двоичного>/../flang/src/emit/c`, затем
# `share/flang/c`), а не рядом с исходником. Двоичный из `bootstrap/` попадает
# туда случайно — на один уровень выше как раз корень дерева. Любой другой не
# попадает: `FLANG=` на собранный в стороне двоичный отвечал
# «не найдены исходники рантайма C» кодом 2. Названный путь снимает эту
# случайность и делает рецепт полным.
( cd "$ROOT" && "$BINARY" emit "$INPUT" --target c --out "$TMP" \
    --cli --repl --runtime "$ROOT/$RUNTIME" \
    --max-steps "$MAX_STEPS" --max-depth "$MAX_DEPTH" ) >&2

PRINTED=$(cd "$TMP" && ls | sort)
TOTAL=0
COUNT=0
for name in $PRINTED; do
  TOTAL=$((TOTAL + $(size_of "$TMP/$name")))
  COUNT=$((COUNT + 1))
done

if [ "$mode" = verify ]; then
  BAD=0
  # Файл, оставшийся от прошлой печати, — такая же ложь, как разошедшееся
  # содержимое: `cc *.c` соберёт его вместе с остальным.
  for name in $(names_in_tree); do
    found=no
    for printed in $PRINTED; do [ "$printed" = "$name" ] && found=yes; done
    [ "$found" = yes ] && continue
    err "  • $DIR/$name: лежит в дереве, но печать его не даёт — след прошлой перепечатки"
    BAD=$((BAD + 1))
  done
  for name in $PRINTED; do
    target=$ROOT/$DIR/$name
    if [ ! -f "$target" ]; then
      err "  • $DIR/$name: печать даёт $(size_of "$TMP/$name") байт, а в дереве файла нет"
      BAD=$((BAD + 1))
      continue
    fi
    if ! where=$(LC_ALL=C cmp "$target" "$TMP/$name" 2>&1); then
      # Без места дифф на 19 МБ бесполезен, поэтому cmp зовётся ради «байт N,
      # строка M». Говорит он это двумя разными фразами — про несовпавший байт и
      # про оборвавшийся файл, — и обе переводятся здесь на русский.
      where=$(printf '%s' "$where" | sed -e 's/.*differ: char /разошлись на байте /' \
                                         -e 's/.*differ: byte /разошлись на байте /' \
                                         -e 's/.*after byte /один короче: оборвался на байте /' \
                                         -e 's/, line /, строка /')
      err "  • $DIR/$name: $where — в дереве $(size_of "$target") байт, печать даёт $(size_of "$TMP/$name")"
      BAD=$((BAD + 1))
    fi
  done
  if [ "$BAD" -eq 0 ]; then
    say "точка раскрутки $DIR/ совпадает с печатью: $COUNT файлов, $TOTAL байт"
    exit 0
  fi
  err ""
  err "точка раскрутки $DIR/ разошлась с исходниками — расхождений $BAD."
  err "Перепечатайте её в том же коммите, что и правку компилятора: sh scripts/raskrutka.sh"
  exit 1
fi

for name in $PRINTED; do
  cp "$TMP/$name" "$ROOT/$DIR/$name"
  say "  $name  $(size_of "$ROOT/$DIR/$name") байт"
done
say "итого $COUNT файлов, $TOTAL байт в $DIR/"

# Отпечаток снимается ЗДЕСЬ, а не отдельной командой, которую надо не забыть.
# Забывчивость — ровно та беда, ради которой всё это писалось; оставить снятие
# на человека значило бы повторить её этажом выше.
stamp_now > "$ROOT/$SEED_STAMP"
say "отпечаток входов печати снят: $SEED_STAMP"
say "сборка без Node: make -C $DIR"
