# ═══════════════ Ч74: единица «ПОРЯДОК И ЧИСЛО ЗОВОВ» ══════════════════════
#
# Ч69 назвала слабость своей сверки сама: единица — МНОЖЕСТВО имён, и
# «переставленные или продублированные зовы обеим сверкам невидимы».
# Здесь единица меняется на «те же имена + столько же раз + в том же порядке,
# кроме перестановок, которые печать делает ЗАКОННО».
#
# ЗАМЕР ПЕРЕД ВЫБОРОМ (Ч74/МЕРА.md, 1039 общих имён, дерево 036057a7):
# строгая последовательность даёт 556 расхождений (53,5 %), из них 549 —
# чистые перестановки; мультимножество — 7, те же семь. Значит строгую
# последовательность брать нельзя, а число повторов — даром.
#
# Печать переставляет законно потому, что исходник пишет потребителя ПЕРЕД
# доводом ( «f» от («g» …) ), а вычисляет довод ПЕРВЫМ. Отсюда два правила:
#   (а) обратный порядок в печати законен, только если ранний в печати
#       ВТЕКАЕТ в поздний — значением, охраной if/for или ячейками отскока;
#   (б) если значение первого попадает в доводы второго ЧИСТЫМ потоком
#       значений, то в исходнике первый обязан стоять ПОЗЖЕ. Иначе
#       вложенность подменена местами.
# Довод и охрана разведены нарочно: «если C то A» требует СОВПАДЕНИЯ порядка,
# а «f от (g …)» — ОБРАТНОГО. Смешать — 306 ложных тревог (померено).
# Именованная привязка (пусть — emit-c.flang:3463,4282; элемент обхода —
# 3936,3974) РЕЖЕТ поток доводов: за ней исходник пишет потребителя после
# поставщика. Без разреза — те же 306 ложных, с ним — 0.

# ── множество как строка «|3|7|12|» ───────────────────────────────────────
# Ни одного класса символов: index() над точными байтовыми парами — то же
# решение, каким Ч59 чинила себя (грабля «отрицающий класс режет по байтам»).
function s_est(a, x) { if (a == "") return 0; return index(a, "|" x "|") > 0 }
function s_dob(a, x) { if (a == "") a = "|"; if (index(a, "|" x "|") == 0) a = a x "|"; return a }
function s_obed(a, b,   n, t, i) {
  if (b == "" || b == "|") return a
  if (a == "") a = "|"
  n = split(substr(b, 2, length(b) - 1), t, "|")
  for (i = 1; i <= n; i++) if (t[i] != "" && index(a, "|" t[i] "|") == 0) a = a t[i] "|"
  return a
}

# ── те же зовы, что find_calls, но ПО ПОРЯДКУ и С ПОВТОРАМИ (в SS/SSn) ────
function find_calls_seq(line,   s, i, rest, j, name, after, matched, k, tail) {
  s = line
  while (1) {
    i = index(s, guL)
    if (i == 0) break
    rest = substr(s, i + lguL)
    j = index(rest, guR)
    if (j == 0) break
    name = substr(rest, 1, j - 1)
    after = substr(rest, j + lguR)
    matched = 0
    if (after ~ /^ +от/) {
      k = index(after, "от")
      tail = substr(after, k + lot)
      if (!is_word_byte(substr(tail, 1, 1))) matched = 1
    }
    if (matched || (name in nullary_set)) { SSn++; SS[SSn] = name }
    s = after
  }
}

# ── те же id, что collect_ids, но ПО ПОРЯДКУ (в LID/LIDn) ─────────────────
function collect_ids_seq(line,    rest, idpart, i, j, ch, nxt) {
  rest = line
  while ((i = index(rest, "compiler_flang_")) > 0) {
    rest = substr(rest, i)
    idpart = ""
    j = 1
    while (j <= length(rest)) {
      ch = substr(rest, j, 1)
      if (ch ~ /^[A-Za-z0-9_]$/) { idpart = idpart ch; j++ } else break
    }
    nxt = substr(rest, j, 1)
    if (nxt == "(") { LIDn++; LID[LIDn] = idpart }
    if (length(idpart) == 0) rest = substr(rest, 2)
    else rest = substr(rest, j)
  }
}

# ── имя переменной слева от «=» (или "" — присваивания нет / поле структуры)
function lhs_of(code,   t, i, pre, j, ch) {
  t = code
  sub(/^[ \t]+/, "", t)
  i = index(t, "=")
  if (i == 0) return ""
  if (substr(t, i + 1, 1) == "=") return ""
  ch = (i > 1 ? substr(t, i - 1, 1) : "")
  if (ch == "=" || ch == "!" || ch == "<" || ch == ">") return ""
  pre = substr(t, 1, i - 1)
  sub(/[ \t]+$/, "", pre)
  if (pre ~ /\]$/) sub(/\[[^]]*\]$/, "", pre)
  sub(/[ \t]+$/, "", pre)
  if (pre ~ /[-+*\/]$/) sub(/[-+*\/]$/, "", pre)
  sub(/[ \t]+$/, "", pre)
  if (pre !~ /[A-Za-z0-9_]$/) return ""
  j = length(pre)
  while (j > 0 && substr(pre, j, 1) ~ /^[A-Za-z0-9_]$/) j--
  if (j >= 2 && substr(pre, j - 1, 2) == "->") return ""
  if (j >= 1 && substr(pre, j, 1) == ".") return ""
  return substr(pre, j + 1)
}

function amp_defs(code, out,   rest, i, j, ch, name) {
  rest = code
  while ((i = index(rest, "&")) > 0) {
    rest = substr(rest, i + 1)
    name = ""
    j = 1
    while (j <= length(rest)) {
      ch = substr(rest, j, 1)
      if (ch ~ /^[A-Za-z0-9_]$/) { name = name ch; j++ } else break
    }
    if (name != "" && name ~ /^[A-Za-z_]/) out[name] = 1
    if (j <= 1) rest = substr(rest, 2); else rest = substr(rest, j)
  }
}

function idents(code, out,   n, t, i) {
  n = split(code, t, /[^A-Za-z0-9_]+/)
  for (i = 1; i <= n; i++) if (t[i] != "" && t[i] ~ /^[A-Za-z_]/) out[t[i]] = 1
}

# ── ВТОРОЙ ПРОХОД по региону: порядок зовов и два отношения втекания ──────
# Кладёт в OCC_ID[g] / OCC_BODY[g] / OND[g] (втекание любого рода) /
# ODD[g] (только поток значений). Возвращает, сколько зовов добавлено.
function scan_region_seq(start_line, endl, cutb, base,
                         i, l, code, ctaint, dinp, ninp, mine, k, v, g, cnt,
                         NTv, DTv, CLl, CTt, cn, depth, defs, uses, t, tgt, mb) {
  delete NTv; delete DTv; delete CLl; delete CTt
  cn = 0; depth = 0; cnt = 0
  for (i = start_line; i <= endl; i++) {
    l = cline[i]
    code = mask_strings(l)
    ctaint = ""
    for (k = 1; k <= cn; k++) ctaint = s_obed(ctaint, CTt[k])

    delete LID; LIDn = 0
    collect_ids_seq(code)
    t = code; sub(/^[ \t]+/, "", t); sub(/[ \t]+$/, "", t)
    mb = ""
    if (index(t, "bounce->next = ") == 1) {
      tgt = substr(t, length("bounce->next = ") + 1); sub(/;$/, "", tgt)
      if (length(tgt) > 5 && substr(tgt, length(tgt) - 4) == "_step") { LIDn++; LID[LIDn] = tgt; mb = tgt }
    }
    # НОВЫЙ отскок: ячейки доводов заводятся заново, иначе доводы отскока из
    # одной ветви натекут на отскок из другой и два соседа по взаимной
    # рекурсии окажутся «доводом» друг другу (померено: 8 ложных тревог).
    if (index(t, "bounce->args[0] = ") == 1) { DTv["@bounce"] = ""; NTv["@bounce"] = "" }

    delete defs; delete uses
    amp_defs(code, defs)
    v = lhs_of(code)
    if (v != "") defs[v] = 1
    idents(code, uses)
    if (index(code, "bounce->") > 0) { defs["@bounce"] = 1; uses["@bounce"] = 1 }

    dinp = ""
    for (v in uses) if (v in DTv) dinp = s_obed(dinp, DTv[v])
    ninp = s_obed(ctaint, dinp)
    for (v in uses) if (v in NTv) ninp = s_obed(ninp, NTv[v])

    mine = ""
    for (k = 1; k <= LIDn; k++) {
      g = base + cnt
      OCC_ID[g] = LID[k]
      OCC_BODY[g] = (i <= cutb) ? 1 : 0
      OND[g] = ninp
      ODD[g] = dinp
      mine = s_dob(mine, g)
      cnt++
    }
    for (v in defs) {
      NTv[v] = s_obed(s_obed(NTv[v], ninp), mine)
      # ИМЕНОВАННАЯ ПРИВЯЗКА РЕЖЕТ ПОТОК ДОВОДОВ (см. шапку).
      if (v ~ /^fl_t[0-9]+$/ || v == "@bounce") DTv[v] = s_obed(s_obed(DTv[v], dinp), mine)
      else DTv[v] = s_obed(DTv[v], mine)
    }
    if (mb != "") { DTv["@bounce"] = ""; NTv["@bounce"] = "" }

    depth += gsub_count(code, "{") - gsub_count(code, "}")
    while (cn > 0 && CLl[cn] > depth) cn--
    if (index(code, "{") > 0 && code ~ /^[ \t]*(\}[ \t]*else[ \t]+)?(if|for|while)[ \t]*\(/) {
      cn++; CLl[cn] = depth; CTt[cn] = s_obed(ninp, mine)
    }
  }
  return cnt
}

