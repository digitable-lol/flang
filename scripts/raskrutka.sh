  print "mark_count " mark_n
  print "razrez_count " razrez_n
  print "razrez_ok_count " razrez_ok
  print "razrez_bad_count " razrez_bad_n
  for (i = 1; i <= razrez_bad_n; i++) print "RAZREZ_BAD " razrez_bad[i]
