# ИМЯ ЯДРА — то, что объявлено строкой `функция «Имя»` или `тотальная функция
# «Имя»` в одном из трёх файлов. Ни зовы, ни объекты, ни типы именем ядра не
# считаются: спрашивается «какие правила ядро объявляет», а не «что оно поминает».
#
# ГРАБЛЯ, на которой эта строчка уже была сломана (31 августа 2026): отрицающий
# класс `[^ёлочка]` под LC_ALL=C режет по БАЙТАМ, а закрывающая ёлочка — это
# байты C2 BB; байт BB есть внутри буквы «л» (D0 BB), и потому «Алгебра» через
# такой класс не читается вовсе. Родня той же грабли, что `\b` рядом с
# кириллицей (ЗАДАНИЕ.md). Здесь отрицающего класса нет НАРОЧНО: имя берётся
# отрезанием головы и хвоста, и обе отрезки — дословные.
YADRO_AWK='
  /^(тотальная )?функция «/ {
    line = $0; sub(/^(тотальная )?функция «/, "", line); sub(/».*$/, "", line)
    print line }'
imena_yadra() {
  YROOT=${1:-$ROOT}
  ( cd "$YROOT" && cat $YADRO_FILES 2>/dev/null ) \
    | LC_ALL=C awk "$YADRO_AWK" | LC_ALL=C sort -u
}

# ИМЯ В СЕМЕНИ — блок-комментарий ` * Функция flang «Имя».`, за которым сразу
# идёт определение `compiler_flang_<транслит>(`. Признак найден ячейкой Ч54
# (/srv/tmp/dokazuemyy/Ч54-otkat/sem/pairs.awk) и взят здесь дословно: печать
# метит этим комментарием КАЖДУЮ функцию, которую вынесла в C, и другого места,
# где имя в ёлочках доживает до напечатанного байта, в семени нет.
#
# Транслитерация тут нарочно НЕ разбирается: она — дело печати, и повторять её
# правила в стороже значило бы завести второй список, который разойдётся с
# первым. Сверяются имена в ёлочках, которые печать написала сама.
imena_semeni() {
  MROOT=${1:-$ROOT}
  LC_ALL=C awk '
    /^ \* Функция flang «/ {
      line = $0; sub(/^ \* Функция flang «/, "", line); sub(/».*$/, "", line)
      nm = line; want = 1; next }
    want && /^(static )?[A-Za-z_][A-Za-z0-9_]* \**compiler_flang_[A-Za-z0-9_]+\(/ {
      print nm; want = 0; next }
  ' "$MROOT/$DIR/compiler_flang.c" 2>/dev/null | LC_ALL=C sort -u
}

