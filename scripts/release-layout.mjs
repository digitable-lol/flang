import { readdirSync } from "node:fs"
import { join } from "node:path"

/**
 * Раскладка релизного архива — в одном месте, потому что знать её обязаны
 * ЧЕТВЕРО: скрипт релиза (`scripts/build-release-c.mjs`), формула Homebrew
 * (`packaging/homebrew/flang.rb`), плагин asdf (`packaging/asdf/bin/install`) и
 * проверка пути установки (`flang/test/self-bootstrap.test.mjs`).
 *
 * Копий этого знания в дереве уже было три — имя бинарника, — и они разошлись
 * молча: скрипт релиза искал `flang_cli` после того, как печать стала звать
 * выход `flang`, и релиз перестал собираться вовсе. Здесь та же развилка решена
 * заранее: две упаковки — файлы на других языках и импортировать этот модуль не
 * могут, поэтому имена оттуда СВЕРЯЮТСЯ проверкой, а не переписываются на веру.
 *
 * ── ЗАЧЕМ В АРХИВЕ ВТОРАЯ КОПИЯ РАНТАЙМА ───────────────────────────────────
 * `flang emit --target c` кладёт в вывод четыре файла рантайма ДОСЛОВНО, а
 * значит читает их с диска. Наверху архива лежат НАПЕЧАТАННЫЕ копии тех же
 * четырёх имён — с шапкой «Сгенерировано flang» в первой строке, — и печать их
 * отвергает по делу: приписать шапку второй раз значило бы соврать о
 * происхождении файла. Поэтому рукописные оригиналы едут отдельным каталогом,
 * а обе упаковки переносят его целиком в `share/flang/c` рядом с бинарником —
 * ровно туда, где их ищет `emit_runtime_dir` в `flang/src/emit/c/flang_repl.c`.
 *
 * Без этого `flang emit --target c` не работал НИ У ОДНОГО поставившего язык:
 * ни через brew, ни через asdf. Отказ («не найдены исходники рантайма C»)
 * человек читал как поломку языка, а не как нехватку шести файлов.
 */

/** Каталог внутри архива, куда кладутся рукописные исходники рантайма. */
export const РАНТАЙМ_В_АРХИВЕ = "runtime-c"

/** Куда его переносят обе упаковки — относительно префикса установки. */
export const РАНТАЙМ_ПРИ_УСТАНОВКЕ = "share/flang/c"

/*
 * Что именно читает печать. Порядок — как в настройках бэкенда.
 *
 * Пятым и шестым здесь стоят файлы движка процессов. Читает их печать ВСЕГДА,
 * а кладёт в вывод только той программе, где объявлен хотя бы один `процесс`, —
 * и потому пропусти их здесь, и `flang emit --target c` у поставившего язык
 * отказал бы на ЛЮБОЙ программе, а не только на программе с процессами:
 * недостающий файл рантайма — это отказ вызова кодом 2, а не молчание.
 */
export const РАНТАЙМ_ФАЙЛЫ = [
  "flang_runtime.h",
  "flang_runtime.c",
  "flang_cli.c",
  "flang_repl.c",
  "flang_conc.h",
  "flang_conc.c",
]

/** Откуда они берутся в дереве репозитория (там же их ищет `--runtime`). */
export const РАНТАЙМ_В_ДЕРЕВЕ = "flang/src/emit/c"

/*
 * ── ТОЧКА РАСКРУТКИ И АРХИВ — ОДНИ И ТЕ ЖЕ БАЙТЫ ────────────────────────────
 *
 * Раньше скрипт релиза печатал компилятор заново и совпадал с `bootstrap/`
 * «потому что печатает одна функция». Печатал их свидетель на JavaScript, а его
 * больше нет (коммит fe8e8a37). Печатать умеет только сам двоичный, и одна
 * такая печать стоит одиннадцать минут — платить их дважды за один выпуск
 * незачем, да и совпадение по-прежнему держалось бы на обещании.
 *
 * Поэтому архив берёт семь файлов из `bootstrap/` как есть: совпадение стало
 * свойством, а не обещанием. Отдельный вопрос — не отстала ли сама точка
 * раскрутки от исходников; на него отвечает `sh scripts/raskrutka.sh --check`.
 */

/** Каталог замороженной точки раскрутки в дереве репозитория. */
export const ТОЧКА_РАСКРУТКИ = "bootstrap"

/**
 * Что в этом каталоге НЕ относится к точке: пояснение и продукты сборки.
 *
 * Тот же список записан в `scripts/raskrutka.sh` (NOT_SEED) — оболочка не умеет
 * ввозить модули JavaScript, и это единственная причина второй копии. Разойтись
 * им незаметно нельзя: сверка `--check` сравнивает НАБОР файлов дерева с
 * набором напечатанных, и лишнее имя она называет прямо.
 */
export const НЕ_ТОЧКА = new Set(["README.md", "flang", "flang.exe", "flang_cli", "flang_cli.exe", "libcompiler_flang.a"])
const ПРОДУКТ_СБОРКИ = /\.(?:o|obj|a|d)$/u

/** Имена файлов точки раскрутки, лежащих в дереве, по порядку. */
export function файлыТочкиРаскрутки(корень) {
  return readdirSync(join(корень, ТОЧКА_РАСКРУТКИ))
    .filter((имя) => !НЕ_ТОЧКА.has(имя) && !ПРОДУКТ_СБОРКИ.test(имя))
    .sort()
}
