/**
 * Раскладка релизного архива — в одном месте, потому что знать её обязаны
 * ЧЕТВЕРО: скрипт релиза (`scripts/build-release-c.mjs`), формула Homebrew
 * (`packaging/homebrew/flang.rb`), плагин asdf (`packaging/asdf/bin/install`) и
 * проверка пути установки (`flang/test/self-bootstrap.test.mjs`).
 *
 * Копий этого знания в дереве уже было три — имя бинарника, — и они разошлись
 * молча: скрипт релиза искал `flang_cli` после того, как печать стала звать
 * выход `flang`, и релиз перестал собираться вовсе. Здесь та же развилка решена
 * заранее: две упаковки — файлы на других языках и импортировать этот модуль не
 * могут, поэтому имена оттуда СВЕРЯЮТСЯ проверкой, а не переписываются на веру.
 *
 * ── ЗАЧЕМ В АРХИВЕ ВТОРАЯ КОПИЯ РАНТАЙМА ───────────────────────────────────
 * `flang emit --target c` кладёт в вывод четыре файла рантайма ДОСЛОВНО, а
 * значит читает их с диска. Наверху архива лежат НАПЕЧАТАННЫЕ копии тех же
 * четырёх имён — с шапкой «Сгенерировано flang» в первой строке, — и печать их
 * отвергает по делу: приписать шапку второй раз значило бы соврать о
 * происхождении файла. Поэтому рукописные оригиналы едут отдельным каталогом,
 * а обе упаковки переносят его целиком в `share/flang/c` рядом с бинарником —
 * ровно туда, где их ищет `emit_runtime_dir` в `flang/src/emit/c/flang_repl.c`.
 *
 * Без этого `flang emit --target c` не работал НИ У ОДНОГО поставившего язык:
 * ни через brew, ни через asdf. Отказ («не найдены исходники рантайма C»)
 * человек читал как поломку языка, а не как нехватку четырёх файлов.
 */

/** Каталог внутри архива, куда кладутся рукописные исходники рантайма. */
export const РАНТАЙМ_В_АРХИВЕ = "runtime-c"

/** Куда его переносят обе упаковки — относительно префикса установки. */
export const РАНТАЙМ_ПРИ_УСТАНОВКЕ = "share/flang/c"

/** Что именно читает печать. Порядок — как в настройках бэкенда. */
export const РАНТАЙМ_ФАЙЛЫ = ["flang_runtime.h", "flang_runtime.c", "flang_cli.c", "flang_repl.c"]

/** Откуда они берутся в дереве репозитория (там же их ищет `--runtime`). */
export const РАНТАЙМ_В_ДЕРЕВЕ = "flang/src/emit/c"
