# Отказ судить о доказательствах, пока семя отстало от исходников, а двоичный
# не собирается из семени.
#
# ДВЕ СВЕРКИ, И ОНИ О РАЗНОМ. Первая — «те ли ВХОДЫ у печати»: семя против
# исходников, о ней вся эта шапка. Вторая — «тот ли ДВОИЧНЫЙ»: двоичный против
# семени, она живёт в scripts/binary-origin.sh и зовётся отсюда. Одна другую не
# заменяет: 23 августа 2026 семя было в порядке, а двоичный собран из двух
# невлитых веток и шесть суток судил язык с доказательствами.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# Двоичный компилятор собран из bootstrap/ — из СЕМЕНИ. Правка в исходниках
# (flang/self/**, flang/src/emit/c/**) попадает в собранную программу только
# после перепечатки семени: `sh scripts/raskrutka.sh`. Пока перепечатки не было,
# двоичный судит по СТАРЫМ правилам и об этом не знает.
#
# Для проверки разбора, типов и примеров это не беда: она судит о программе,
# которую ей дали. Для проверки, судящей о ДОКАЗАТЕЛЬСТВАХ, это ложь: ведомость
# показывает состояние дерева, которого нет. 21–22 августа 2026 так трижды за
# сутки пролежали в стволе неработающими правило ядра «начинается с по
# построению», четвёртый вердикт «доказано при условии» и два поручения ввода-
# вывода: они были в исходниках, их не было в семени, а ведомости печатали
# зелёное. Каждый раз это находил случайный человек, а не проверка.
#
# `sh scripts/raskrutka.sh --bystro` умеет это ловить за полсекунды и весь тот
# день говорил «Компилятор правили, семя не перепечатали». Его не слушали —
# потому что он ничего не блокировал. Здесь он блокирует.
#
# ── Что блокируется, а что нет ───────────────────────────────────────────────
# Блокируется ровно то, чей ОТВЕТ зависит от семени: ведомости доказательств,
# сторожа подделок, сторож доказанного, `flang check --proof`. Список имён
# ярлыков живёт не здесь, а в `ярлыки.flang` («Ярлыки о доказательствах») —
# типизированным списком с примерами, а не строкой в оболочке.
#
# НЕ блокируется всё остальное: разбор, типы, примеры, ссылки, лицензии, сайт.
# Иначе отставшее семя останавливало бы работу целиком, и ключ обхода жали бы
# не глядя.
#
# ── Ключ обхода ──────────────────────────────────────────────────────────────
#   SEMYA_OTSTALO_ZNAYU=1 <та же команда>
#
# Он обязателен: без него перепечатку нечем проверить самой собой. Тот, кто
# перепечатывает семя, обязан уметь прогнать ведомость на дереве, где семя ещё
# отстало, — иначе он не узнает, что перепечатка что-то починила.
#
# Ключ не тихий: при обходе в поток бед уходит строка о том, что судили при
# отставшем семени, и число расхождений. Зелёный ответ, полученный обходом,
# остаётся зелёным, но перестаёт быть молчаливым.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/seed-freshness.sh                     только ответить: 0 или 1
#   sh scripts/seed-freshness.sh --chto "<имя>" ...  назвать, кто спрашивает
#   sh scripts/seed-freshness.sh -- <команда…>       отказать или запустить
#
# Коды: 0 — семя отвечает исходникам, двоичный отвечает семени (или сработал
#           ключ обхода);
#       1 — отстало либо двоичный чужой, судить отказано;
#       3 — сверить не удалось вовсе.
#
# Ключей обхода ДВА, и они разные: SEMYA_OTSTALO_ZNAYU снимает сверку семени с
# исходниками, FLANG_BINARY_UNKNOWN_OK — сверку двоичного с семенем. Одним
# заглушить обе нельзя, и это нарочно.
#
# ИМЕНА ЗДЕСЬ ЛАТИНИЦЕЙ, как в scripts/raskrutka.sh и в `ярлык`: ни dash, ни
# bash не принимают кириллицу в именах переменных.

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
BYPASS=SEMYA_OTSTALO_ZNAYU
FAST="sh scripts/raskrutka.sh --bystro"

err() { printf '%s\n' "$*" >&2; }

what="эта проверка"
while [ $# -gt 0 ]; do
  case $1 in
    --chto) [ $# -ge 2 ] || { err "--chto без имени"; exit 3; }; what=$2; shift 2 ;;
    --) shift; break ;;
    -*) err "неизвестный довод: $1"; exit 3 ;;
    *) break ;;
  esac
done

# Число файлов, разошедшихся с семенем. Строки отчёта --bystro о файлах все
# кончаются словом «перепечатки»; строка о том, что печать зовётся иначе, — нет.
skolko_faylov() { printf '%s\n' "$1" | grep -c 'перепечатки$' || true; }

# Слово «файл» в нужном числе. Отказ читает человек, и «на 1 файлов» в нём
# выглядит как недоделка — а недоделанному сторожу не верят.
fajlov() {
  case $1 in
    *1[1-4]) printf 'файлов' ;;
    *1) printf 'файл' ;;
    *[2-4]) printf 'файла' ;;
    *) printf 'файлов' ;;
  esac
}

# ── Двоичный обязан собираться из семени, лежащего рядом ─────────────────────
#
# Сверка ниже отвечает на вопрос «те ли ВХОДЫ у печати». Она не отвечает на
# вопрос «тот ли ДВОИЧНЫЙ», и 23 августа 2026 это стоило шести суток: в двадцати
# рабочих копиях лежал компилятор, собранный из двух невлитых веток, а семя в
# тех же копиях было в полном порядке. Ведомости печатали зелёное, и нашлось это
# не проверкой, а сплошным перебором коммитов вручную.
#
# Разбор и обе сверки — в scripts/binary-origin.sh. Быстрая стоит полсекунды.
#
# Стоит она НАРОЧНО ДО ключа SEMYA_OTSTALO_ZNAYU: тот ключ про отставшее семя, а
# не про чужой двоичный, и глушить им обе сверки разом нельзя. У сверки
# двоичного свой ключ — FLANG_BINARY_UNKNOWN_OK.
ORIGIN=$ROOT/scripts/binary-origin.sh
if [ -f "$ORIGIN" ]; then
  sh "$ORIGIN" --чем "$what" || exit $?
fi

# ── Обход по ключу: разрешаем, но вслух ──────────────────────────────────────
if [ -n "${SEMYA_OTSTALO_ZNAYU:-}" ]; then
  err "$BYPASS: судим при отставшем семени по прямому указанию."
  err "Ответ этой проверки — про дерево, собранное из СТАРОГО семени."
  if [ $# -gt 0 ]; then exec "$@"; fi
  exit 0
fi

# ── Сверка входов печати. Стоит полсекунды и двоичного не зовёт ─────────────
rc=0
out=$(cd "$ROOT" && $FAST 2>&1) || rc=$?
if [ "$rc" = 0 ]; then
  if [ $# -gt 0 ]; then exec "$@"; fi
  exit 0
fi

n=$(skolko_faylov "$out")

if [ "$n" = 0 ]; then
  err "СЕМЯ СВЕРИТЬ НЕ УДАЛОСЬ — судить о доказательствах нельзя: $what"
  err ""
  printf '%s\n' "$out" >&2
  err ""
  err "Сверка входов печати ответила кодом $rc и ни одного расхождения не назвала."
  err "Судить всё равно: $BYPASS=1 <та же команда>"
  exit 3
fi

err "ОТКАЗЫВАЮСЬ СУДИТЬ О ДОКАЗАТЕЛЬСТВАХ: $what"
err ""
err "семя отстало от исходников на $n $(fajlov "$n"), ведомость показывает состояние,"
err "которого нет; перепечатайте \`sh scripts/raskrutka.sh\`"
err ""
err "Двоичный собран из семени и знает СТАРЫЕ правила. Его зелёный ответ — про"
err "дерево, которого в этой копии нет: правка есть в исходнике и отсутствует в"
err "семени. Ровно так 21–22 августа 2026 трижды за сутки лежали в стволе"
err "неработающими правило ядра, четвёртый вердикт и два поручения ввода-вывода."
err ""
err "Что разошлось (весь список — \`$FAST\`):"
printf '%s\n' "$out" | grep '^  • ' | head -8 >&2
if [ "$n" -gt 8 ]; then err "  …и ещё $((n - 8))"; fi
err ""
err "Судить всё равно, зная это: $BYPASS=1 <та же команда>"
exit 1
