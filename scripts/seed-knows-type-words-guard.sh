#
# ── Что случилось 24 августа 2026 ──────────────────────────────────────────
# Имя типа «неотрицательное» ввели в исходники компилятора и там же сразу
# применили — одним изменением. Ствол перестал проверяться НИ ОДНИМ существующим
# двоичным:
#
#   $ flang check flang/self/builtins.flang
#   FLANG_UNKNOWN_NAME, строка 157: неизвестный тип «неотрицательное»
#
# Семя о слове не знает и узнать может только перепечаткой, а перепечатка читает
# эти же исходники. Круг замкнулся. Полдня ушло на откат в 52 местах, и откат
# вышел НЕПОЛНЫМ: 26 августа тем же способом, каким считает этот сторож, нашлось
# ещё 180 применений в 78 файлах — `e6795b02` тронул `flang/self`,
# `flang/stdlib`, `flang/conc` и `ярлыки.flang`, а `examples/**`, `fspec/**`,
# `flang/proof/**`, `docs/**`, `packaging/**`, `benchmarks/**` не тронул вовсе.
# Разбор — задача 0034.
#
# ── Правило, которое здесь принуждается ────────────────────────────────────
# Порядок трёхшаговый, и он же есть у Lean (там это `update-stage0`, а
# закоммиченный сгенерированный C лежит в `stage0/src` — в точности наш
# `bootstrap`):
#
#   1. ВВЕСТИ имя: научить компилятор новому слову, НЕ применяя его в позициях
#      типа. Слово попадает в таблицы и строки, и старое семя это разбирает.
#   2. ПЕРЕПЕЧАТАТЬ семя (`sh scripts/raskrutka.sh`). Теперь оно знает слово.
#   3. ПРИМЕНИТЬ: поставить новое имя в позиции типа.
#
# Шаги 1 и 3 в одном изменении — это и есть поломка. Сторож ловит ровно её.
#
# ── Почему он НЕ зовёт компилятор ──────────────────────────────────────────
# Замысел «гонять `flang check` с малым пределом шагов» проверен и отвергнут
# замером (задача 0034): неизвестное имя находится не при разборе, а при
# СВЯЗЫВАНИИ, и до связывания малый предел не доходит.
#
# ЧИСЛА НИЖЕ — С ИМЕНЕМ ФАЙЛА, ДВОИЧНОГО И ДНЯ, И ЭТО НЕ ПЕДАНТСТВО. Прежде
# здесь стояли три строки без единой приметы, и из-за них две шапки в этом
# дереве разошлись В ТРИСТА РАЗ: тут мерено на `flang/self/builtins.flang`
# (122 КБ, 4 файла вместе с ввозами), а у соседа
# `seed-parses-sources-guard.sh` — на `flang/self/types.flang` (932 КБ), и НИ
# ОДНА ИЗ ДВУХ ШАПОК ФАЙЛА НЕ НАЗВАЛА. Читатель сличить их не мог.
#
#   26 августа 2026, задача 0034, файл flang/self/builtins.flang:
#     предел 1 000 000    5,0 с   не ловит
#     предел 3 000 000   11,4 с   не ловит
#     предел 5 000 000   15,2 с   ЛОВИТ   → 15 с × 59 файлов = четверть часа
#
#   31 августа 2026, ТОТ ЖЕ файл, семя 05b2e008…ee95c (перепечатка c15f669f
#   от 30 августа), подделка — неизвестное имя типа в позиции типа:
#     предел     5 000 000   0,08 с   НЕ ЛОВИТ — умирает на РАЗБОРЕ
#     предел    50 000 000   0,7 с    не ловит
#     предел   300 000 000   4,5 с    не ловит
#     предел   600 000 000  11,5 с    не ловит — связыванию нужно 603 929 109
#     предел 1 000 000 000  26,4 с    ЛОВИТ
#     предел 2 000 000 000  27,1 с    ловит; шагов на весь прогон 1 097 563 504
#
# За пять дней порог вырос с 5 миллионов до 604 миллионов — В 121 РАЗ, и
# отвергнутый путь стал дороже, а не дешевле. Шаг — счётчик рантайма
# (`repl_ctx.max_steps`, в него кладёт `fl_charge`), и цена шага меняется при
# каждой перепечатке семени. ЧИСЛО В ШАГАХ БЕЗ ДАТЫ И БЕЗ ДВОИЧНОГО — НЕ ЗАМЕР,
# А СЛУХ: сверять его не с чем.
#
# Здесь взят второй путь, названный в той же задаче: снять у семени список слов,
# которые оно знает, и сверить со словами, встреченными в позициях типа. Ядро не
# запускается вовсе. Замер 31 августа 2026, семя 05b2e008…ee95c: 1173 файла
# за 2,0 секунды; сегодня в дереве 1272.
# СНЯТО 2026-09-06 файлов *.flang = 1272
# (29 августа здесь стояло «1116 файлов за 0,4 секунды» — файлы
# сосчитаны с опиской, а время устарело в пять раз.)
#
# ── Откуда берётся «что знает семя» ────────────────────────────────────────
# Из самого `bootstrap/*.c`, а не из списка в этом файле. Слова, которыми
# компилятор разбирает позицию типа, лежат у него в ДВУХ перечнях, и оба
# уезжают в напечатанный C дословными строками. Число слов ниже снимается
# прогоном, а не берётся из этого текста:
#
#   лексер      "…|число:tNumber|числа:tNumber|строка:tString|список:list|…"
#   типизатор   "|неотрицательное|нат|натуральное|nat|naturo|自然数|"
#                («Скаляр по имени», flang/self/types.flang)
#
# Сторож вынимает из семени ВСЕ перечни вида `|…|…|` и берёт их слова. Ничего не
# зашито: перепечатка меняет семя — меняется и словарь сторожа.
# Снято 31 августа 2026 семенем 05b2e008…ee95c: 816 слов, 1166 файлов,
# 41 386 слов в позициях типа, чужих семени 0, прогон 2,0 с.
# (29 августа здесь стояло «795 слов» — за два дня прибавился 21.)
#
# ── Чего сторож НЕ смотрит, и почему это не дыра ───────────────────────────
# Имён в ёлочках (`«Тип»`, `«Возможно» от «А»`). Их разбирает не таблица
# компилятора, а ОБЪЯВЛЕНИЕ — `объект «Тип»`, `тип «Возможно» от «А»`, — и
# объявление лежит в тех же исходниках, которые семя читает. Введённое и
# применённое в одном изменении имя в ёлочках семя разберёт: дисциплины семени
# оно не касается. Незнакомая ёлочка — обычный `FLANG_UNKNOWN_NAME`, его ловит
# любой двоичный и без сторожа.
#
# Поэтому сторож смотрит ГОЛЫЕ слова: ровно они приходят из таблиц компилятора,
# ровно на них и вышла беда 24 августа.
#
# ── Позиции типа, которые читаются ─────────────────────────────────────────
#   принимает н: ТИП, м: ТИП        подпись функции и теоремы
#   возвращает ТИП                  она же
#   дано н: ТИП                     посылка теоремы
#   «поле»: ТИП                     поле записи (`объект`)
#   «поле» является ТИП             оно же, словесной поверхностью
#   вариант «В» содержит п: ТИП     поле варианта (`тип`)
#   тип «Имя» является ТИП          псевдоним
#
# ── Звать ──────────────────────────────────────────────────────────────────
#   sh scripts/seed-knows-type-words-guard.sh            всё дерево
#   sh scripts/seed-knows-type-words-guard.sh ФАЙЛ…      только названные файлы
#   sh scripts/seed-knows-type-words-guard.sh --подлог   проба самого сторожа
#
# Код возврата: 0 — чисто; 1 — найдено применение, которого семя не знает;
# 2 — семени нет или оно нечитаемо.
set -eu

KOREN=$(cd "$(dirname "$0")/.." && pwd)
SEMYA=${SEMYA:-$KOREN/bootstrap}
PODLOG=0

case "${1-}" in
  --подлог|--podlog) PODLOG=1; shift ;;
esac

if [ ! -d "$SEMYA" ]; then
  echo "сторож слов: каталога семени нет — $SEMYA" >&2
  exit 2
fi

SLOVAR=$(mktemp -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" slova-semeni.XXXXXX)
NAJDENO=$(mktemp -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" primeneno.XXXXXX)
UBRAT="$SLOVAR $NAJDENO"
PORCHA=""
trap 'rm -f $UBRAT; [ -z "$PORCHA" ] || rm -rf "$PORCHA"' EXIT INT TERM

# ── 1. Словарь семени ──────────────────────────────────────────────────────
# Перечни `|…|…|` из напечатанного C. `слово:идентификатор` — форма лексера,
# берётся левая половина; `слово@ru` — пометка поверхности, снимается.
grep -ohE '\|[^"]+\|' "$SEMYA"/*.c 2>/dev/null \
  | tr '|' '\n' \
  | sed 's/:.*$//; s/@[a-z][a-z]$//' \
  | grep -v '^[[:space:]]*$' \
  | LC_ALL=C sort -u > "$SLOVAR"

SLOV=$(wc -l < "$SLOVAR" | tr -d ' ')
if [ "$SLOV" -lt 100 ]; then
  echo "сторож слов: в семени нашлось всего $SLOV слов — это не семя" >&2
  exit 2
fi

# ── 2. Слова в позициях типа ───────────────────────────────────────────────
CHITAT=$(mktemp -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" razbor.XXXXXX.awk)
UBRAT="$UBRAT $CHITAT"
cat > "$CHITAT" <<'KONEC_AWK'
# ЁЛОЧКИ ЗАМЕНЯЮТСЯ ОДНОБАЙТОВЫМИ МЕТКАМИ, и это не украшение. `«` и `»` —
# двухбайтовые, а у mawk (он же `awk` на Debian и Ubuntu, то есть на ленте)
# регулярки байтовые: `[^»]` там превращается в «любой байт, кроме \xC2 и \xBB»
# и режет посреди буквы. Мерено: на 200 файлах mawk дал 30 ЛОЖНЫХ находок
# («Отклик», «показател»), gawk — ноль. Сторож, краснеющий ложно, хуже
# отсутствующего, поэтому дальше в разборе ёлочек нет вовсе: только \001 и \002.
BEGIN { ZNAKI = "[][(){}<>:;,.!?|=+*/\\\\'\"\001\002-]" }

function chisto(s) {
  gsub(/"[^"]*"/, " ", s)
  sub(/\/\/.*$/, "", s)
  gsub(/«/, "\001", s)
  gsub(/»/, "\002", s)
  return s
}

# Голое слово типового выражения. Имена в ёлочках выброшены — их разбирает
# объявление, а не таблица компилятора.
function slova(vyr, poz,   n, i, a, w) {
  gsub(/\001[^\002]*\002/, " ", vyr)
  gsub(/[\001\002(),?"|]/, " ", vyr)
  gsub(/→/, " ", vyr)
  n = split(vyr, a, /[ \t]+/)
  for (i = 1; i <= n; i++) {
    w = a[i]
    if (w == "") continue
    # Кусок со знаком препинания — осечка разбора, а не применённое слово:
    # имя типа знаков не несёт. Молчать о нём правильнее, чем краснеть.
    if (w ~ ZNAKI) continue
    if (w ~ /^[0-9]+$/) continue
    print FILENAME "\t" FNR "\t" w "\t" poz
  }
}

# `имя: ТИП, имя: ТИП и имя: ТИП` — режется по «имя:», а не по запятой:
# разделителем бывает и `и`, а `и` живёт ещё и внутри типа («Разбор» от «З» и «Б»).
function podpis(s, poz,   n, i, a, t) {
  n = split(s, a, /(\001[^\002]*\002|[^ \t,:\001\002]+)[ \t]*:[ \t]*/)
  for (i = 2; i <= n; i++) {
    t = a[i]
    sub(/([ \t]*,|[ \t]+и)[ \t]*$/, "", t)
    slova(t, poz)
  }
}

FNR == 1 { blok = ""; komm = 0 }
{ s = chisto($0) }
s ~ /^[ \t]*\/\*/ { komm = 1 }
komm == 1 { if (s ~ /\*\//) komm = 0; next }
s ~ /^[ \t]*$/ || s ~ /^[ \t]*\/\// { next }

s ~ /^[^ \t]/ {
  blok = "прочее"
  if (s ~ /^объект \001/) blok = "объект"
  else if (s ~ /^тип \001/) {
    blok = "сумма"
    if (match(s, /[ \t](alias|является|is|=)[ \t]/)) {
      t = s; sub(/^.*[ \t](alias|является|is|=)[ \t]/, "", t)
      slova(t, "псевдоним"); blok = "прочее"
    }
  }
  else if (s ~ /^(тотальная |частичная )?функция \001/) blok = "функция"
  else if (s ~ /^теорема /) blok = "теорема"
  next
}

(blok == "функция" || blok == "теорема") && s ~ /^[ \t]+принимает / {
  sub(/^[ \t]+принимает /, "", s); podpis(s, "принимает"); next
}
(blok == "функция" || blok == "теорема") && s ~ /^[ \t]+возвращает / {
  sub(/^[ \t]+возвращает /, "", s); slova(s, "возвращает"); next
}
blok == "теорема" && s ~ /^[ \t]+дано [^\001]*:/ {
  sub(/^[ \t]+дано /, "", s); podpis(s, "дано"); next
}
blok == "объект" && s ~ /^[ \t]+\001[^\002]+\002[ \t]*:/ {
  sub(/^[ \t]+\001[^\002]+\002[ \t]*:[ \t]*/, "", s); slova(s, "поле"); next
}
blok == "объект" && s ~ /^[ \t]+\001[^\002]+\002[ \t]+(иногда[ \t]+)?является[ \t]/ {
  sub(/^[ \t]+\001[^\002]+\002[ \t]+(иногда[ \t]+)?является[ \t]+/, "", s); slova(s, "поле"); next
}
blok == "сумма" && s ~ /^[ \t]+вариант \001[^\002]+\002[ \t]+содержит[ \t]/ {
  sub(/^[ \t]+вариант \001[^\002]+\002[ \t]+содержит[ \t]+/, "", s); podpis(s, "вариант"); next
}
KONEC_AWK

# Кого читать: названные файлы, подлог или всё дерево.
SPISOK=$(mktemp -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" fajly.XXXXXX)
UBRAT="$UBRAT $SPISOK"

if [ "$PODLOG" -eq 1 ]; then
  PORCHA=$(mktemp -d -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" podlog-slova.XXXXXX)
  # Тип с выдуманным именем, применённый в позиции типа. Имя нарочно такое,
  # какого нет ни в одном перечне семени и быть не может.
  cat > "$PORCHA/podlog.flang" <<'KONEC_PODLOGA'
модуль «Подлог»

тотальная функция «Взять подлог»
  принимает н: невыдуманноеслово
  возвращает невыдуманноеслово
  н
KONEC_PODLOGA
  printf '%s\n' "$PORCHA/podlog.flang" > "$SPISOK"
  echo "сторож слов: ПОДЛОГ — применён выдуманный тип «невыдуманноеслово»"
elif [ "$#" -gt 0 ]; then
  printf '%s\n' "$@" > "$SPISOK"
else
  find "$KOREN" -name '*.flang' -not -path '*/.git/*' | LC_ALL=C sort > "$SPISOK"
fi

FAJLOV=$(wc -l < "$SPISOK" | tr -d ' ')
if [ "$FAJLOV" -eq 0 ]; then
  echo "сторож слов: читать нечего" >&2
  exit 2
fi

# xargs — потому что файлов больше тысячи, а длина строки запуска конечна.
tr '\n' '\0' < "$SPISOK" | xargs -0 env LC_ALL=C.UTF-8 awk -f "$CHITAT" > "$NAJDENO"

VSEGO=$(wc -l < "$NAJDENO" | tr -d ' ')

# ── 3. Разность ────────────────────────────────────────────────────────────
CHUZHIE=$(mktemp -p "${FLANG_TMP:-${TMPDIR:-/tmp}}" chuzhie.XXXXXX)
UBRAT="$UBRAT $CHUZHIE"
awk -F'\t' 'NR==FNR { znaet[$0]; next } !($3 in znaet)' "$SLOVAR" "$NAJDENO" > "$CHUZHIE"

BED=$(wc -l < "$CHUZHIE" | tr -d ' ')
echo "сторож слов: файлов $FAJLOV, слов в позициях типа $VSEGO, словарь семени $SLOV, чужих семени $BED"

if [ "$BED" -eq 0 ]; then
  exit 0
fi

echo "" >&2
awk -F'\t' -v k="$KOREN/" '{ f=$1; sub("^"k, "", f); printf "  %s:%s: применено «%s» (%s) — семя такого слова не знает\n", f, $2, $3, $4 }' "$CHUZHIE" >&2
echo "" >&2
awk -F'\t' '{ n[$3]++ } END { for (w in n) printf "  «%s» — применений: %d\n", w, n[w] }' "$CHUZHIE" | LC_ALL=C sort >&2

cat >&2 <<'KONEC'

СЛОВО ВВЕДЕНО И ПРИМЕНЕНО В ОДНОМ ИЗМЕНЕНИИ. Так нельзя: закоммиченное семя об
этом слове не знает, узнать может только перепечаткой, а перепечатка читает эти
же исходники. Дерево перестаёт проверяться любым существующим двоичным.

Порядок трёхшаговый:
  1. ввести слово в компилятор, НЕ применяя его в позициях типа;
  2. перепечатать семя  —  sh scripts/raskrutka.sh
  3. применить, отдельным изменением.

Сейчас надо откатить ТРЕТИЙ шаг — применение — и оставить первый.
KONEC
exit 1
