#!/bin/sh
# СТОРОЖ ДИСЦИПЛИНЫ СЕМЕНИ: закоммиченное семя обязано РАЗБИРАТЬ исходники,
# которые оно потом печатает.
#
# ЗАЧЕМ. 24 августа 2026 ствол перестал проверяться НИ ОДНИМ существующим
# двоичным. Имя типа «неотрицательное» ввели в исходники компилятора и там же
# сразу применили — одним изменением. Семя о новом имени не знает и узнать могло
# только перепечаткой, а перепечатка сама читает эти же исходники. Круг замкнулся:
#
#   $ flang check flang/self/builtins.flang
#   FLANG_UNKNOWN_NAME, строка 157: неизвестный тип «неотрицательное»
#
# Полдня ушло на откат применения в 52 файлах, чтобы дерево снова читалось.
#
# ПРАВИЛЬНЫЙ ПОРЯДОК ТРЁХШАГОВЫЙ, и он же есть у Lean (там это зовётся
# update-stage0, а закоммиченный C лежит в stage0/src — в точности наш bootstrap):
#
#   1. ВВЕСТИ имя: научить компилятор новому слову, НЕ применяя его в исходниках.
#      Семя ещё старое, но исходники оно читает — новое слово встречается только
#      в таблицах и строках, а не в позициях типа.
#   2. ПЕРЕПЕЧАТАТЬ семя: `sh scripts/raskrutka.sh`. Теперь семя знает слово.
#   3. ПРИМЕНИТЬ: заменить старое имя новым в позициях типа.
#
# Шаги 1 и 3 в одном изменении — это и есть поломка. Сторож ловит ровно её.
#
# КАК ОН ДЕШЁВ. Полная проверка `flang check` стоит минуты на файл: она гоняет
# ядро доказательства. Здесь ядро не нужно — нужен только РАЗБОР. Поэтому предел
# шагов ставится крошечный: разбор и связывание успевают, ядро упирается в предел
# и умирает, а нам этого и надо. Замер: 0,9–1,6 секунды и 137 МБ на файл вместо
# минут и десятков гигабайт.
#
# ЧТО СЧИТАЕТСЯ ПОЛОМКОЙ, а что нет:
#   FLANG_UNKNOWN_NAME, FLANG_LEX, FLANG_PARSE   семя НЕ ЧИТАЕТ исходник — отказ
#   FLANG_RECURSION_LIMIT, FLANG_CLI             упёрлись в наш же предел — норма
#
# ЗВАТЬ:
#   sh scripts/seed-parses-sources-guard.sh                 семенем из bootstrap/
#   FLANG=/путь/к/flang sh scripts/seed-parses-sources-guard.sh   чужим двоичным
set -eu

KOREN=$(cd "$(dirname "$0")/.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
PREDEL=${PREDEL:-300000}

if [ ! -x "$FLANG" ]; then
  echo "сторож семени: двоичного нет — $FLANG" >&2
  echo "соберите его: make -C bootstrap" >&2
  exit 2
fi

echo "сторож семени: разбирает ли $FLANG исходники компилятора"

fajlov=0
bed=0
for f in "$KOREN"/flang/self/*.flang "$KOREN"/flang/self/*/*.flang; do
  [ -e "$f" ] || continue
  fajlov=$((fajlov + 1))
  vyvod=$("$FLANG" check "$f" --предел-шагов "$PREDEL" 2>&1 || true)
  beda=$(printf '%s\n' "$vyvod" | grep -oE 'FLANG_(UNKNOWN_NAME|LEX|PARSE)[A-Z_]*' | head -1 || true)
  if [ -n "$beda" ]; then
    bed=$((bed + 1))
    echo "  ✗ ${f#$KOREN/}" >&2
    printf '%s\n' "$vyvod" | grep -E 'FLANG_(UNKNOWN_NAME|LEX|PARSE)' | head -3 | sed 's/^/      /' >&2
  fi
done

echo "сторож семени: файлов $fajlov, семя не читает $bed"

if [ "$bed" -gt 0 ]; then
  cat >&2 <<'KONEC'

СЕМЯ НЕ ЧИТАЕТ СВОИ ЖЕ ИСХОДНИКИ. Собрать компилятор из этого дерева нельзя.

Скорее всего в одном изменении и ВВЕЛИ новое слово, и ПРИМЕНИЛИ его. Так нельзя:
семя узнаёт слово только перепечаткой, а перепечатка читает эти же исходники.

Чинится откатом ПРИМЕНЕНИЯ (позиции типа: `возвращает`, `: тип`, `список тип`),
а введение слова — в таблицах и строках — остаётся. После перепечатки применение
возвращается отдельным изменением.
KONEC
  exit 1
fi
KONEC_NE_NUZHEN=""
