#!/bin/sh
# СТОРОЖ ДИСЦИПЛИНЫ СЕМЕНИ: закоммиченное семя обязано РАЗБИРАТЬ исходники,
# которые оно потом печатает.
#
# ЗАЧЕМ. 24 августа 2026 ствол перестал проверяться НИ ОДНИМ существующим
# двоичным. Имя типа «неотрицательное» ввели в исходники компилятора и там же
# сразу применили — одним изменением. Семя о новом имени не знает и узнать могло
# только перепечаткой, а перепечатка сама читает эти же исходники. Круг замкнулся:
#
#   $ flang check flang/self/builtins.flang
#   FLANG_UNKNOWN_NAME, строка 157: неизвестный тип «неотрицательное»
#
# Полдня ушло на откат применения в 52 файлах, чтобы дерево снова читалось.
#
# ПРАВИЛЬНЫЙ ПОРЯДОК ТРЁХШАГОВЫЙ, и он же есть у Lean (там это зовётся
# update-stage0, а закоммиченный C лежит в stage0/src — в точности наш bootstrap):
#
#   1. ВВЕСТИ имя: научить компилятор новому слову, НЕ применяя его в исходниках.
#      Семя ещё старое, но исходники оно читает — новое слово встречается только
#      в таблицах и строках, а не в позициях типа.
#   2. ПЕРЕПЕЧАТАТЬ семя: `sh scripts/raskrutka.sh`. Теперь семя знает слово.
#   3. ПРИМЕНИТЬ: заменить старое имя новым в позициях типа.
#
# Шаги 1 и 3 в одном изменении — это и есть поломка. Сторож ловит ровно её.
#
# КАК ОН ДЕШЁВ. Полная проверка `flang check` стоит минуты на файл: она гоняет
# ядро доказательства. Здесь ядро не нужно — нужен только РАЗБОР. Поэтому предел
# шагов ставится крошечный: разбор и связывание успевают, ядро упирается в предел
# и умирает, а нам этого и надо. Замер: 0,9–1,6 секунды и 137 МБ на файл вместо
# минут и десятков гигабайт.
#
# ЧТО СЧИТАЕТСЯ ПОЛОМКОЙ, а что нет:
#   FLANG_UNKNOWN_NAME, FLANG_LEX, FLANG_PARSE   семя НЕ ЧИТАЕТ исходник — отказ
#   FLANG_RECURSION_LIMIT, FLANG_CLI             судить нечем — см. ниже
#
# ── «УПЁРЛИСЬ В НАШ ЖЕ ПРЕДЕЛ» — ЭТО НЕ НОРМА, А СЛЕПОТА ──────────────────────
#
# 29 августа 2026, замер. Строка выше прежде кончалась словом «норма», и на нём
# держалась вся дешевизна сторожа. Слово неверное: когда проверка умирает на
# пределе, она НЕ ПЕЧАТАЕТ НИ ОДНОГО замечания — ни своего, ни чужого. Значит
# «замечаний нет» означает не «файл прочитан», а «мы не досмотрели».
#
# Показано прямой сверкой, а не рассуждением. В flang/self/types.flang внесена
# поломка того самого вида, ради которого сторож заведён, — неизвестное имя
# типа в позиции типа (строка 228). Два прогона под нынешним PREDEL=300000,
# чистый и порченый, слово в слово:
#
#     чистый:   flang/self/types.flang: не проверено — замечаний 1
#     порченый: flang/self/types.flang: не проверено — замечаний 1
#
# Весь остальной вывод совпал тоже, кроме одного числа в строке запаса
# (13 489 475 против 13 489 859 шагов — разница 384 на «Связать исходники»).
# FLANG_UNKNOWN_NAME не напечатано НИ РАЗУ. То же с грубой поломкой разбора:
# дописанная в конец файла строка, которая не разбирается вовсе, при пределах
# 300 000, 3 000 000 и 30 000 000 не даёт ни FLANG_LEX, ни FLANG_PARSE.
#
# СКОЛЬКО НАДО, ЧТОБЫ СТОРОЖ ВООБЩЕ СУДИЛ. Замечание печатается только когда
# `check` доходит до конца. Перебором предела на том же порченом файле: при
# 300 000 000 молчит, при 3 000 000 000 называет поломку. Снято ведомостью
# (FLANG_TICKS_OUT) на прогоне, который до поломки дошёл:
#
#     шагов всего   4 330 138 064      157 с, 3,7 ГБ — на ОДИН файл
#     витков всего    280 902 928
#
# То есть нынешние 300 000 малы в 14 434 раза по шагам, и в 936 раз по виткам.
# Сторож слеп не после перепечатки, а СЕГОДНЯ; перепечатка делает разрыв ещё в
# пятнадцать раз шире, потому что предел этот — счётчик рантайма
# (`repl_ctx.max_steps`, его задаёт «--предел-шагов»), а в него кладёт
# `fl_charge`. Сегодня семя ключа не знает и сторож выходит с кодом 3; после
# перепечатки ключ появится, сторож пойдёт по всем шестидесяти файлам и станет
# честно печатать «семя не читает 0» на любом дереве.
#
# ПОЧЕМУ ПРЕДЕЛ ЗДЕСЬ НЕ ПОДНЯТ ДО ИЗМЕРЕННОГО. Четыре с лишним миллиарда шагов
# — это 157 секунд и 3,7 ГБ на файл, снятые на types.flang, самом большом из
# шестидесяти; на чистом файле проверка идёт дольше, чем на порченом, потому что
# порченая обрывается на первом же неизвестном имени. Шестьдесят таких прогонов
# — это ночная работа, а не полторы секунды на файл, ради которых сторож
# заводился. Число, которым его поднимать, придётся снимать на всех шестидесяти
# файлах, и это отдельная работа с отдельным доводом. До тех пор сторож обязан
# не врать: ниже он считает недосмотренные файлы и отказывается судить.
#
# ЗВАТЬ:
#   sh scripts/seed-parses-sources-guard.sh                 семенем из bootstrap/
#   FLANG=/путь/к/flang sh scripts/seed-parses-sources-guard.sh   чужим двоичным
set -eu

KOREN=$(cd "$(dirname "$0")/.." && pwd)
FLANG=${FLANG:-$KOREN/bootstrap/flang}
PREDEL=${PREDEL:-300000}

if [ ! -x "$FLANG" ]; then
  echo "сторож семени: двоичного нет — $FLANG" >&2
  echo "соберите его: make -C bootstrap" >&2
  exit 2
fi

echo "сторож семени: разбирает ли $FLANG исходники компилятора"

# ── СТОРОЖ, КОТОРЫЙ НИЧЕГО НЕ ПРОВЕРЯЛ, 29 августа 2026 ─────────────────────
#
# Ключ «--предел-шагов» есть в ИСХОДНИКАХ компилятора и нет в СЕМЕНИ: семя
# старее ключа. Двоичный, собранный из дерева, отвечал на него одной строкой
#
#   flang check: непонятный ключ «--предел-шагов»
#
# и кодом 2 — ДО того, как взглянуть на файл. Строка эта не содержит ни
# FLANG_UNKNOWN_NAME, ни FLANG_LEX, ни FLANG_PARSE, поэтому проверка ниже
# считала файл прочитанным. Итог: «файлов 60, семя не читает 0» за 0,46 с при
# заявленных в этой же шапке 0,9–1,6 с НА ФАЙЛ. Зелено и пусто.
#
# Ключ теперь спрашивается один раз, до обхода, и незнание его — это ОТКАЗ
# ПРИБОРА, а не чистое дерево: код 3, «примета не снята».
#
# Почему не «пойти без ключа»: без него каждая проверка идёт под собственным
# потолком двоичного (миллиард витков) и стоит не секунду, а минуты — замер
# показал, что шестьдесят файлов так не кончаются и за десять минут. Дешевизна
# этого сторожа держалась ровно на крошечном пределе; без ключа он превращается
# в ночной прогон, и звать его перестанут. Правильный выход — не удешевить
# ответ, а починить прибор: собрать двоичный, который ключ знает.
if "$FLANG" check "$KOREN/flang/self/types.flang" --предел-шагов "$PREDEL" 2>&1 |
     grep -q 'непонятный ключ'; then
  echo "сторож семени: ПРИМЕТА НЕ СНЯТА — двоичный не знает ключа «--предел-шагов»" >&2
  echo "" >&2
  echo "Ключ есть в исходниках (flang/self/cli.flang) и нет в семени: семя старее" >&2
  echo "ключа. Двоичный отвечает «непонятный ключ» и кодом 2 ДО того, как взглянуть" >&2
  echo "на файл, — а прежняя редакция этого сторожа считала такой ответ чистым и" >&2
  echo "рапортовала «семя не читает 0» за полсекунды на шестьдесят файлов." >&2
  echo "" >&2
  echo "Чинится не здесь: нужен двоичный, который ключ знает, — то есть" >&2
  echo "перепечатанное семя либо сборка из исходников рантайма." >&2
  echo "Судить этим сторожем до тех пор нельзя: он ничего не проверяет." >&2
  exit 3
fi
KLYUCH="--предел-шагов $PREDEL"

fajlov=0
bed=0
nedosmotr=0
for f in "$KOREN"/flang/self/*.flang "$KOREN"/flang/self/*/*.flang; do
  [ -e "$f" ] || continue
  fajlov=$((fajlov + 1))
  # shellcheck disable=SC2086
  vyvod=$("$FLANG" check "$f" $KLYUCH 2>&1 || true)
  beda=$(printf '%s\n' "$vyvod" | grep -oE 'FLANG_(UNKNOWN_NAME|LEX|PARSE)[A-Z_]*' | head -1 || true)
  if [ -n "$beda" ]; then
    bed=$((bed + 1))
    echo "  ✗ ${f#$KOREN/}" >&2
    printf '%s\n' "$vyvod" | grep -E 'FLANG_(UNKNOWN_NAME|LEX|PARSE)' | head -3 | sed 's/^/      /' >&2
    continue
  fi
  # Молчание — не приговор. Если проверка умерла на нашем же пределе, замечаний
  # она не печатает вовсе, и «чисто» тут значит «не досмотрели». Такой файл
  # считается отдельно и в зелёный итог не идёт (замер — в шапке).
  if printf '%s\n' "$vyvod" | grep -qE 'FLANG_(RECURSION_LIMIT|CLI)'; then
    nedosmotr=$((nedosmotr + 1))
  fi
done

echo "сторож семени: файлов $fajlov, семя не читает $bed, не досмотрено $nedosmotr"

if [ "$bed" -gt 0 ]; then
  cat >&2 <<'KONEC'

СЕМЯ НЕ ЧИТАЕТ СВОИ ЖЕ ИСХОДНИКИ. Собрать компилятор из этого дерева нельзя.

Скорее всего в одном изменении и ВВЕЛИ новое слово, и ПРИМЕНИЛИ его. Так нельзя:
семя узнаёт слово только перепечаткой, а перепечатка читает эти же исходники.

Чинится откатом ПРИМЕНЕНИЯ (позиции типа: `возвращает`, `: тип`, `список тип`),
а введение слова — в таблицах и строках — остаётся. После перепечатки применение
возвращается отдельным изменением.
KONEC
  exit 1
fi

if [ "$nedosmotr" -gt 0 ]; then
  cat >&2 <<KONEC

СУДИТЬ НЕЧЕМ: из $fajlov файлов $nedosmotr умерли на нашем же пределе шагов
(PREDEL=$PREDEL), не напечатав ни одного замечания. «Семя не читает 0» про них
означает не «прочитано», а «не досмотрено», и зелёный итог здесь был бы враньём.

Замер 29 августа 2026: под этим пределом чистый и намеренно испорченный
flang/self/types.flang дают слово в слово один и тот же вывод. Чтобы проверка
дошла до замечания, ей нужно 4 330 138 064 шага (157 с и 3,7 ГБ на один файл);
предел здесь — 300 000, то есть в 14 434 раза меньше. Разбор — в шапке этого
файла.

Чинится не подкруткой этого числа наугад: нужен либо предел, снятый на всех
$fajlov файлах, либо способ остановить проверку после связывания, не гоняя ядро
доказательства.
KONEC
  exit 3
fi
KONEC_NE_NUZHEN=""
