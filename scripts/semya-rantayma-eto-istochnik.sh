#!/bin/sh
# СЕМЯ РАНТАЙМА — ЭТО ИСТОЧНИК ПЛЮС ШАПКА, И БОЛЬШЕ НИЧЕГО.
#
# ЗАЧЕМ. В дереве держат правило «источник ≠ семя»: правка в flang/self/**
# не значит ничего, пока не пройдёт перепечатка, а она идёт часами. За одни
# сутки на этом потеряли время пятеро — правили и мерили несобранное.
#
# Но на файлы РАНТАЙМА (flang/src/emit/c/*) правило не распространяется:
# печать копирует их дословно, приписывая сверху свою шапку. Значит правку
# в рантайме можно проверить в работе за минуты, не дожидаясь перепечатки:
#
#   n=$(этот сторож назовёт длину шапки)
#   { head -n "$n" bootstrap/ФАЙЛ; cat flang/src/emit/c/ФАЙЛ; } > /tmp/новое
#   mv /tmp/новое bootstrap/ФАЙЛ && make -C bootstrap
#
# Сторож проверяет, что приём ещё законен. Перестанет держаться — краснеет,
# и тогда приёмом пользоваться нельзя.
#
# ДВА РАЗНЫХ ВОПРОСА, И ПЕРВАЯ РЕДАКЦИЯ ИХ ПУТАЛА (нашёл работник T2):
#
#   «СЕМЯ ОТСТАЛО ОТ ИСТОЧНИКА» — норма. Так выглядит всякая незавершённая
#   правка рантайма: источник ушёл вперёд, семя догонит перепечаткой. Горячий
#   путь правят часто, и краснеть на это значит краснеть почти всегда.
#
#   «ПРАВИЛО КОПИРОВАНИЯ СЛОМАЛОСЬ» — беда. Печать перестала копировать
#   дословно, и приём «шапка + источник» больше не даёт того, что печать бы
#   напечатала. Вот на это краснеть обязательно.
#
# Отличить их можно: пока первая строка источника находится в семени и всё,
# что до неё, — шапка, приём законен, каким бы ни было расхождение тел.
# Расхождение тел — это отставание, и оно печатается СВЕДЕНИЕМ, не бедой.
#
# ЗАЧЕМ ТОГДА ВТОРОЙ ЛАД. Сразу после перепечатки семя обязано совпасть с
# источником ПОЛНОСТЬЮ — там отставанию взяться неоткуда. Ключ
# `--после-печати` требует именно этого и краснеет от любого расхождения,
# включая версию. Звать его — часть приёмки перепечатки, не повседневная.
#
# ЧЕГО СТОРОЖ НЕ ОБЕЩАЕТ. В обычном ладу он не говорит, что семя свежее.
# За тем, не отстаёт ли версия у ОТГРУЖАЕМОГО двоичного, смотрит задача 9111.
set -u
STROGO=0
for d in "$@"; do
  case "$d" in
    --после-печати) STROGO=1 ;;
    *) printf 'непонятный ключ: %s (знаю только --после-печати)\n' "$d" >&2; exit 2 ;;
  esac
done
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT" || exit 5
RAB=${FLANG_TMP:-/srv/tmp}/semya-rantayma.$$
mkdir -p "$RAB" || exit 5
trap 'rm -rf "$RAB"' EXIT INT TERM
BEDA=0
VERSIY=0
OTSTALO=0
for b in flang_repl.c flang_cli.c flang_runtime.c flang_runtime.h; do
  SEMYA=bootstrap/$b
  IST=flang/src/emit/c/$b
  if [ ! -f "$SEMYA" ] || [ ! -f "$IST" ]; then
    printf 'НЕТ ФАЙЛА: %s или %s\n' "$SEMYA" "$IST" >&2
    BEDA=$((BEDA+1)); continue
  fi
  PERV=$(head -1 "$IST")
  N=$(LC_ALL=C.UTF-8 grep -n -m1 -F -x -- "$PERV" "$SEMYA" | cut -d: -f1)
  if [ -z "$N" ]; then
    printf 'ПРИЁМ БОЛЬШЕ НЕ ЗАКОНЕН: %s — первой строки источника в семени нет вовсе\n' "$b" >&2
    BEDA=$((BEDA+1)); continue
  fi
  tail -n +"$N" "$SEMYA" > "$RAB/telo"
  diff "$RAB/telo" "$IST" > "$RAB/razn" 2>&1
  # Строки расхождения, кроме именованного послабления про версию.
  PROCHIE=$(LC_ALL=C.UTF-8 grep '^[<>]' "$RAB/razn" \
            | LC_ALL=C.UTF-8 grep -cv '^[<>] #define FLANG_VERSION ' || true)
  VER=$(LC_ALL=C.UTF-8 grep -c '^[<>] #define FLANG_VERSION ' "$RAB/razn" || true)
  VERSIY=$((VERSIY+VER))
  printf '%-18s шапка %2d строк, тело отстало на %s строк' "$b" "$((N-1))" "$PROCHIE"
  if [ "$VER" -gt 0 ]; then printf ', плюс версия'; fi
  printf '\n'
  OTSTALO=$((OTSTALO+PROCHIE+VER))
  # В обычном ладу отставание — СВЕДЕНИЕ: источник ушёл вперёд, семя догонит
  # перепечаткой. Бедой оно становится только сразу после печати, когда
  # отставанию взяться неоткуда.
  if [ "$STROGO" = 1 ] && [ "$((PROCHIE+VER))" -gt 0 ]; then
    LC_ALL=C.UTF-8 grep '^[<>]' "$RAB/razn" | head -20 >&2
    BEDA=$((BEDA+1))
  fi
done
if [ "$BEDA" -gt 0 ]; then
  if [ "$STROGO" = 1 ]; then
    printf '\nПОСЛЕ ПЕЧАТИ СЕМЯ ОБЯЗАНО СОВПАСТЬ С ИСТОЧНИКОМ, а разошлось в %d\n' "$BEDA" >&2
    printf 'файл(е/ах). Либо печать копирует уже не дословно, либо источник\n' >&2
    printf 'правили ПОСЛЕ того, как печать началась.\n' >&2
  else
    printf '\nПРИЁМ «ШАПКА + ИСТОЧНИК» БОЛЬШЕ НЕ ЗАКОНЕН: в %d файл(е/ах) первой\n' "$BEDA" >&2
    printf 'строки источника в семени нет вовсе. Значит печать копирует рантайм\n' >&2
    printf 'уже не дословно, и правку в нём без перепечатки проверить нельзя.\n' >&2
  fi
  exit 1
fi
printf '\nприём «шапка + источник» законен: первая строка источника найдена во всех четырёх'
if [ "$OTSTALO" -gt 0 ]; then
  printf '\nсемя отстало от источника на %d строк — это НОРМА посреди правки,' "$OTSTALO"
  printf '\nсойдётся перепечаткой; после неё звать с --после-печати'
else
  printf '\nсемя совпадает с источником полностью'
fi
printf '\n'
exit 0
