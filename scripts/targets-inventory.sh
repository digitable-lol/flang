#!/bin/sh
# ОПИСЬ ЦЕЛЕЙ: имя, код возврата, время, причина. Задача 0042.
#
#   sh scripts/targets-inventory.sh              все цели из «ярлыки.flang»
#   sh scripts/targets-inventory.sh имя имя …    только названные
#
# Печатает строки таблицы markdown в тот же вид, что docs/ci-inventory.md.
#
# ── Зачем сборщик, если опись снимали руками ─────────────────────────────────
# Опись `docs/ci-inventory.md` — 288 строк, снятых подряд человеком.
# СНЯТО 2026-08-31 строк docs/ci-inventory.md = 288 Снятая
# руками, она не повторяется: следующий снимет её иначе. А главное — поточный
# цикл `echo "$имя КОД=$?"` попадает в ловушку, ради которой заведена задача.
#
# ── ЛОВУШКА, И ОНА НЕ ТАМ, ГДЕ ЖДЁШЬ ────────────────────────────────────────
# Ворота памяти, не дождавшись места, отвечают кодом 75 (EX_TEMPFAIL) и команду
# НЕ ЗАПУСКАЮТ вовсе. Задача 0042 предполагает, что этого кода довольно для
# распознания: «настоящие коды команд с ним не пересекаются».
#
# ЭТО НЕВЕРНО, и вот прогон 26 августа 2026:
#
#   CHISLO=1 ZHDAT=2 flang-vorota -- sh -c 'echo ПРОГОН-ПОШЁЛ'   → код 75
#   flang-vorota -- sh -c 'exit 75'                              → код 75
#
# Первое — отказ ворот, команда не запускалась. Второе — команда отработала и
# сама вернула 75. Ворота пропускают код команды НАСКВОЗЬ, и по коду эти два
# события неразличимы. Различает их только строка в stderr:
#
#   ворота: за N с место не освободилось, прогон не начат
#
# Поэтому здесь проверяются ОБА признака, а не один.
#
# ── Имена латиницей ─────────────────────────────────────────────────────────
# Как в scripts/raskrutka.sh и по той же причине: ни dash, ни bash не принимают
# кириллицу в именах переменных и функций. Русский — в пояснениях и в выводе.
set -u

VOROTA=${VOROTA:-/srv/flang-rabota/vorota/flang-vorota}
PAMYAT=${PAMYAT:-45G}
export PAMYAT
OTKAZ_VOROT='место не освободилось, прогон не начат'
VYVOD=${VYVOD:-/srv/tmp/opis-celey}
mkdir -p "$VYVOD"

names() {
  if [ $# -gt 0 ]; then printf '%s\n' "$@"; return; fi
  sed -n 's/.*«имя» равным "\([^"]*\)".*/\1/p' ярлыки.flang
}

run_one() {
  imya=$1
  syroy="$VYVOD/$(printf '%s' "$imya" | tr '/:' '__').txt"
  nachalo=$(date +%s)
  # ЧЕРЕЗ ВОРОТА, как велит AGENTS.md: «Прогоны — через ворота, и не больше
  # двух разом». Ворота же и есть источник кода 75, ради которого всё это.
  "$VOROTA" -- ./ярлык "$imya" > "$syroy" 2>&1
  kod=$?
  sek=$(( $(date +%s) - nachalo ))
  # ДВА ПРИЗНАКА, А НЕ ОДИН: код 75 И строка отказа ворот в выводе.
  if [ "$kod" -eq 75 ] && grep -qF "$OTKAZ_VOROT" "$syroy"; then
    echo "переснять|$sek|ворота места не дали — прогон не запускался, это НЕ вердикт цели"
    return
  fi
  prichina=$(grep -oE 'FLANG_[A-Z_]+[^"]*' "$syroy" | head -1)
  echo "$kod|$sek|${prichina:-}"
}

printf '| # | цель | код | время | причина |\n|---:|---|---|---:|---|\n'
n=0
PERESNYAT=0
for imya in $(names "$@"); do
  n=$((n + 1))
  otvet=$(run_one "$imya")
  kod=${otvet%%|*}; ost=${otvet#*|}; sek=${ost%%|*}; prichina=${ost#*|}
  [ "$kod" = "переснять" ] && PERESNYAT=$((PERESNYAT + 1))
  printf '| %s | `%s` | %s | %s с | %s |\n' "$n" "$imya" "$kod" "$sek" "$prichina"
done
printf '\nЦелей снято: %s. Из них ждали слота дольше срока и требуют пересъёма: %s.\n' "$n" "$PERESNYAT"
printf 'Сырой вывод каждой цели: %s\n' "$VYVOD"
