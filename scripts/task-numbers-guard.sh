# НОМЕР ЗАДАЧИ НЕ ЗАНЯТ ДВАЖДЫ — и это спрашивается без двоичного.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
# 31 августа 2026 два коммита, `fc2d24ae` и `8756d9a0`, завели задачи с
# ОДИНАКОВЫМИ СЕМЬЮ номерами: 2072, 2256, 2915, 3902, 4717, 6545, 9790. Семь
# совпадений подряд — не случайность: номера раздаются по состоянию дерева, а
# второй клон был снят ДО первого коммита, и обе ветки считали одни и те же
# номера свободными.
#
# Дефект прожил до 1 сентября и нашёлся глазами. Разбор — задача 1308.
#
# ── Почему отдельный скрипт, а не одна проверка задачника ────────────────────
# Проверка `./ярлык задачник:проверка` двойные номера ловит и ловила всегда.
# Беда в том, ЧЕРЕЗ ЧТО её зовут: `bootstrap/flang io …`, то есть через
# двоичный, а его нет на свежем клоне. Оболочка `ярлык` тогда идёт его собирать
# и спрашивает у `scripts/raskrutka.sh --telo`, то ли соберётся, — а отпечаток
# семени в стволе снят прибором старше 31 августа 2026 и тела семени не несёт.
# Ответ: код 3, «В ОТПЕЧАТКЕ НЕТ ТЕЛА СЕМЕНИ». Проверка задачника при этом
# ни в чём не виновата и даже не запускалась.
#
# Вопрос «не занят ли номер дважды» стоит миллисекунды и не должен стоять за
# прибором, который может отказать по совсем другому поводу. Здесь он не стоит
# ни за чем: ни двоичного, ни git, ни отпечатка этой проверке не нужно.
#
# ── Что спрашивается ─────────────────────────────────────────────────────────
#   • номер из имени файла (первые четыре цифры) не занят второй задачей;
#   • номер в шапке (`номер:`) сходится с именем файла;
#   • номер — ровно четыре цифры.
#
# Файлы без четырёх цифр в начале имени (`README.md`) задачами не считаются —
# так же, как их не считает `flang/scripts/tasks.flang`.
#
# ── Как звать ────────────────────────────────────────────────────────────────
#   sh scripts/task-numbers-guard.sh            спросить
#   sh scripts/task-numbers-guard.sh --подлог   показать, что сторож краснеет
#
# `--подлог` заводит нарочный двойной номер во ВРЕМЕННОЙ копии каталога, ждёт
# кода 1, убирает и ждёт кода 0. Дерево при этом не трогается. Сторож, зелёный
# по построению, — та самая болезнь, которую здесь лечат (задача 1306), и
# потому проверка проверки обязательна, а не желательна.
#
# ── Коды возврата ────────────────────────────────────────────────────────────
#   0   номера целы
#   1   номер занят дважды ИЛИ шапка разошлась с именем файла — названо, где
#   2   судить нечем: каталога задач нет или в нём ни одной задачи

set -eu

# Локаль задаётся ЗДЕСЬ, а не снаружи: `sort` сравнивает по правилам локали, и
# порядок сравнения обязан быть свойством проверки, а не машины (задача 1312).
export LC_ALL=C.UTF-8

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
podlog=нет

case ${1:-} in
  --подлог) podlog=да ;;
  '') ;;
  *) printf 'неизвестный довод: %s\n' "$1" >&2
     printf 'звать: sh scripts/task-numbers-guard.sh [--подлог]\n' >&2
     exit 2 ;;
esac

# ── Само правило ────────────────────────────────────────────────────────────
#
# Вынесено в функцию, потому что `--подлог` зовёт его ДВАЖДЫ на разных каталогах
# и сравнивает ответы. Второе воплощение правила здесь было бы ровно тем
# «вторым читателем», который расходится с первым молча.
sudit() {
  kat=$1
  [ -d "$kat" ] || { printf 'НЕ СУДИЛ: нет каталога задач %s\n' "$kat" >&2; return 2; }

  spisok=$(ls -1 "$kat" 2>/dev/null | grep -E '^[0-9]{4}-.*\.md$' || true)
  [ -n "$spisok" ] || { printf 'НЕ СУДИЛ: в %s ни одной задачи вида NNNN-имя.md\n' "$kat" >&2; return 2; }

  bed=0

  # Двойники по имени файла.
  dvoyniki=$(printf '%s\n' "$spisok" | cut -c1-4 | sort | uniq -d)
  if [ -n "$dvoyniki" ]; then
    for n in $dvoyniki; do
      printf 'НОМЕР %s ЗАНЯТ НЕ ОДНОЙ ЗАДАЧЕЙ:\n' "$n" >&2
      printf '%s\n' "$spisok" | grep "^$n-" | sed 's|^|  · |' >&2
    done
    bed=1
  fi

  # Шапка против имени файла.
  for f in $spisok; do
    imya=$(printf '%s' "$f" | cut -c1-4)
    shapka=$(grep -m1 '^номер:' "$kat/$f" 2>/dev/null | sed 's/^номер:[[:space:]]*//' || true)
    if [ "$shapka" != "$imya" ]; then
      printf '%s: в шапке номер «%s», а имя файла говорит «%s»\n' "$f" "$shapka" "$imya" >&2
      bed=1
    fi
  done

  if [ "$bed" -eq 0 ]; then
    printf 'номера задач целы: задач %s, двойных номеров 0\n' "$(printf '%s\n' "$spisok" | grep -c .)"
  fi
  return "$bed"
}

# ── Обычный ход ─────────────────────────────────────────────────────────────
if [ "$podlog" = нет ]; then
  sudit "$ROOT/tasks"
  exit $?
fi

# ── `--подлог`: обе стороны прогоном ────────────────────────────────────────
#
# Копия каталога кладётся во временный каталог: дерево, в котором гоняют
# проверку, портить нельзя даже на секунду — соседний прогон увидит подлог и
# запишет его как находку.
TMP=$(mktemp -d "${FLANG_TMP:-${TMPDIR:-/tmp}}/nomera-zadach.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
cp -R "$ROOT/tasks" "$TMP/tasks"

echo '── сторона первая: подлог заведён, ждём код 1 ──'
obrazec=$(ls -1 "$TMP/tasks" | grep -E '^[0-9]{4}-.*\.md$' | head -1)
nomer=$(printf '%s' "$obrazec" | cut -c1-4)
cp "$TMP/tasks/$obrazec" "$TMP/tasks/$nomer-podlog-dvoynoy-nomer.md"
kod=0
sudit "$TMP/tasks" || kod=$?
if [ "$kod" -eq 0 ]; then
  echo 'СТОРОЖ ЗЕЛЁН НА ПОДЛОГЕ — он не проверяет ничего.' >&2
  exit 1
fi
[ "$kod" -eq 1 ] || { printf 'ждали код 1, получили %s\n' "$kod" >&2; exit 1; }
echo "код $kod — краснеет, как и должен"

echo
echo '── сторона вторая: подлог убран, ждём код 0 ──'
rm -f "$TMP/tasks/$nomer-podlog-dvoynoy-nomer.md"
kod=0
sudit "$TMP/tasks" || kod=$?
[ "$kod" -eq 0 ] || { printf 'ждали код 0, получили %s\n' "$kod" >&2; exit 1; }
echo "код $kod — зеленеет, как и должен"

echo
echo 'обе стороны показаны прогоном.'
