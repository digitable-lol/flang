#!/bin/sh
# Сверить ДВЕ печати одного дерева побайтово — это и есть вопрос гейта Г6.
#
# ПОЧЕМУ ОТДЕЛЬНЫМ ПРИБОРОМ. Г6 требует не «мы однажды сверили руками», а
# «проверяется автоматически». Разовая сверка руками не берёт гейт, даже если
# сошлась: её нельзя повторить, и никто не знает, что именно сверяли.
#
# ПОЧЕМУ ПИШЕТСЯ ДО РЕЗУЛЬТАТА. Прибор, написанный после того, как результат
# увиден, всегда подгоняется под него — не злым умыслом, а тем, что взгляд уже
# знает ответ. Этот написан, когда обе печати ещё идут.
#
# ЧТО СЧИТАЕТСЯ ОТВЕТОМ. Побайтовое совпадение ТЕЛА СЕМЕНИ — bootstrap/**.
# Не журналов, не отпечатков, не времени: тело, из которого соберётся двоичный.
#
# Звать:
#   sh scripts/two-prints-identical.sh <каталог-1> <каталог-2>
# Каталог — корень дерева, в котором прошла печать (в нём лежит bootstrap/).
#
# Коды возврата — по правилу дерева: «плохо» и «не проверено» это РАЗНОЕ.
#   0  печати совпали побайтово — Г6 на этой паре взят
#   1  печати разошлись: названы файлы и первое расхождение
#   3  НЕ ПРОВЕРЕНО: одна из печатей ещё не кончилась или её нет
#   2  звать не умеют (не два довода, не каталоги)
set -u

skazhi() { printf '%s\n' "$*"; }
beda()   { printf '%s\n' "$*" >&2; }

[ $# -eq 2 ] || { beda "звать: sh scripts/two-prints-identical.sh <каталог-1> <каталог-2>"; exit 2; }
A=$1; B=$2
for d in "$A" "$B"; do
  [ -d "$d" ] || { beda "не каталог: $d"; exit 2; }
done

# ── Готова ли печать. Спрашивать надо у ЖУРНАЛА печати, а не у файлов: файлы
#    `bootstrap/**` лежат в дереве и до печати — они закоммичены. Прибор,
#    спросивший «есть ли файл», ответит «готово» на дереве, где печать даже не
#    начиналась, и сверит закоммиченное семя с закоммиченным. Проверено: первая
#    редакция этого прибора так и сделала.
#
#    Признак конца — строка «ПЕЧАТЬ КОД=» в журнале, который печать пишет сама.
gotova() {
  ZH=$(ls -t "$1"/../*.log 2>/dev/null | head -1)
  [ -n "$ZH" ] || { NET="журнала печати рядом с $1 нет"; return 1; }
  if ! LC_ALL=C.UTF-8 /usr/bin/grep -aq 'ПЕЧАТЬ КОД=' "$ZH"; then
    NET="печать ещё идёт: $ZH"; return 1
  fi
  K=$(LC_ALL=C.UTF-8 /usr/bin/grep -ao 'ПЕЧАТЬ КОД=[0-9]*' "$ZH" | tail -1 | sed 's/.*=//')
  [ "$K" = 0 ] || { NET="печать кончилась НЕ УСПЕХОМ (код $K): $ZH"; return 1; }
  return 0
}

ne_gotovy=""; NET=""
gotova "$A" || ne_gotovy="$ne_gotovy
  $NET"
gotova "$B" || ne_gotovy="$ne_gotovy
  $NET"
if [ -n "$ne_gotovy" ]; then
  skazhi "НЕ ПРОВЕРЕНО: печать ещё не кончилась или кончилась не успехом:$ne_gotovy"
  skazhi "Это НЕ «разошлись». Повторить, когда обе печати кончатся."
  exit 3
fi

# ── Сверка. Список файлов тела берётся из ОБОИХ деревьев: файл, появившийся
#    только с одной стороны, — тоже расхождение, и молчать о нём нельзя.
# ЧТО СВЕРЯЕМ. Тело семени — это НАПЕЧАТАННЫЕ ИСХОДНИКИ, а не всё, что лежит в
# bootstrap/. Объектники и библиотека (.o, .a) — отходы сборки: они несут пути и
# время, расходятся всегда и к воспроизводимости печати отношения не имеют.
# Список берётся тем же правилом, что у самого дерева (seed_body_paths в
# raskrutka.sh): имена файлов рантайма из flang/src/emit/c.
spisok() { (cd "$1/flang/src/emit/c" 2>/dev/null && ls -A) | sort; }
# Временное — в FLANG_TMP, как везде в дереве: /tmp здесь запрещён хуком.
SDIR=$(mktemp -d -p "${FLANG_TMP:-/srv/tmp}" dve-pechati.XXXXXX) || {
  beda "ПРОВЕРИТЬ НЕ УДАЛОСЬ: не создался каталог в ${FLANG_TMP:-/srv/tmp}"; exit 3; }
trap 'rm -rf "$SDIR"' EXIT INT TERM
spisok "$A" > "$SDIR/a" 2>/dev/null
spisok "$B" > "$SDIR/b" 2>/dev/null

if ! LC_ALL=C cmp -s "$SDIR/a" "$SDIR/b"; then
  skazhi "РАЗОШЛИСЬ: наборы файлов в bootstrap/ не совпадают"
  LC_ALL=C diff "$SDIR/a" "$SDIR/b" | sed 's/^/  /'
  exit 1
fi

fajlov=0; bajt=0; razoshlos=0
while IFS= read -r f; do
  [ -f "$A/bootstrap/$f" ] || continue
  fajlov=$((fajlov + 1))
  bajt=$((bajt + $(wc -c < "$A/bootstrap/$f")))
  if ! LC_ALL=C cmp -s "$A/bootstrap/$f" "$B/bootstrap/$f"; then
    razoshlos=$((razoshlos + 1))
    skazhi "РАЗОШЁЛСЯ: bootstrap/$f"
    skazhi "  $(LC_ALL=C cmp "$A/bootstrap/$f" "$B/bootstrap/$f" 2>&1 | head -1)"
  fi
done < "$SDIR/a"

if [ "$razoshlos" -gt 0 ]; then
  skazhi ""
  skazhi "ПЕЧАТИ РАЗОШЛИСЬ: файлов сверено $fajlov, разошлось $razoshlos."
  skazhi "Значит печать НЕ воспроизводима, и Г6 на этой паре не взят."
  exit 1
fi

skazhi "печати совпали побайтово: файлов $fajlov, байт $bajt"
skazhi "  первая:  $A"
skazhi "  вторая:  $B"
skazhi "Г6 на ЭТОЙ паре взят. На гейт целиком этого мало: нужна пара из ОДНОГО"
skazhi "дерева и прибор, зовущийся сам, а не руками."
exit 0
