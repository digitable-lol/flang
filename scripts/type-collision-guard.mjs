/**
 * Сторож столкновений ТИПОВ (вид 1) — за секунды, БЕЗ собранного двоичного.
 *
 *   node scripts/type-collision-guard.mjs [вход.flang]
 *   node scripts/type-collision-guard.mjs --порча     самопроверка в обе стороны
 *
 * Код возврата: 0 — новых типовых столкновений нет (то, что уже стоит в
 * `scripts/type-collision-guard-known.tsv`, не красит); 1 — нашлось хоть одно
 * НЕ из ведомости, названо именем, обоими файлами и обеими строками; 3 — не
 * судил (замыкание пусто или часть ввозов не разрешена — список неполон).
 *
 * ЯЗЫК — JavaScript (`.mjs`), а не bash или flang: `замыкание`/`столкновения`
 * уже написаны, проверены и живут в `flang/scripts/link-collision-guard.mjs` —
 * этот файл их ЗОВЁТ, а не переписывает вторым разбором.
 *
 * ── ДВА ВИДА, И ЭТОТ СТОРОЖ ЛОВИТ ОДИН ─────────────────────────────────────
 *
 *   вид 1 — одно и то же русское имя ТИПА объявлено ДВАЖДЫ в замыкании
 *           (FLANG_DUPLICATE_NAME). Этот сторож ловит ровно его.
 *   вид 2 — ДВА РАЗНЫХ русских имени переводятся в одну латиницу. Этот сторож
 *           его НЕ ЛОВИТ ВООБЩЕ — он смотрит на русские имена в дереве разбора,
 *           до всякой транслитерации. Зелёный ответ здесь — не «столкновений
 *           нет», а «столкновений ВИДА 1 нет, кроме известных»; за вид 2
 *           отвечает другая мера.
 *
 * ── Откуда штатный сторож дерева не годится СЕЙЧАС ──────────────────────────
 *
 * `scripts/name-collision-guard.flang` (запускается `bootstrap/flang io
 * scripts/name-collision-guard.flang`) — полный, флаговый ответ на оба вида, но
 * ему нужен СОБРАННЫЙ двоичный: без него `bootstrap/flang` либо не запустится,
 * либо, как замерено на дереве `fa45f9ff`, уйдёт в 540 с молчания на 0 % плана
 * и код 124 (убито по времени). Это НЕ «столкновений нет» — это «не досчитал».
 * Здесь то же самое ловится ОБХОДОМ ТЕКСТА, безо всякого двоичного: сторож
 * обязан успеть ДО печати, иначе он повторяет то, что и так скажут, только
 * позже десяти часов.
 *
 * ── Модель — не с потолка, а из шапки самого штатного сторожа ───────────────
 *
 * `scripts/name-collision-guard.flang` и его прообраз
 * `flang/scripts/link-collision-guard.mjs` открываются одной строкой:
 * «связывание сливает объявления всех подключённых файлов в ОДНО ПЛОСКОЕ
 * пространство имён». Здесь ровно эта модель, суженная на один род объявлений
 * (типы: `тип`/`объект`/`запись`) и НАМЕРЕННО БЕЗ учёта видимости (`только`) —
 * пространство считается плоским по всему замыканию, а не по файлу. Владелец
 * задачи уже проверил файловую модель («имя видно из двух ввезённых модулей») и
 * отбросил её как слепую: на испорченном дереве она отвечает «0».
 *
 * Столкновения и замыкание СЧИТАЕТ `flang/scripts/link-collision-guard.mjs`
 * (функции `замыкание` и `столкновения`) — тот самый обход, что уже сверен с
 * настоящим связыванием (`flang/self/link.flang`) на 387 поддельных деревьях,
 * ноль расхождений. Здесь он не переписан заново: второй разбор `.flang` в
 * дереве заводить нельзя (см. шапку самого `link-collision-guard.mjs`), и
 * `scripts/identical-declarations.sh` берёт `замыкание` оттуда же и по той же
 * причине — «одно место на две работы: разойтись им нечем». Флаг
 * `безВидимости: true` в вызове `столкновения()` — это и есть «плоское, а не
 * суженное `только`» пространство; далее берётся ровно род `types`.
 *
 * ── Сверено с независимым прибором ───────────────────────────────────────────
 *
 * На дереве `884e2e42` независимый разбор строкой (`столкновения.py`, отдельная
 * реализация — свой обход `использует`, свой поиск модулей по каталогам
 * `flang/self`, `flang/self/bootstrap`, `flang/stdlib`, `flang/core`, регэксп
 * ТОЛЬКО на `объект|тип`, без `запись`) называет ТЕ ЖЕ 45 файлов замыкания и ТЕ
 * ЖЕ 9 столкнувшихся типов, теми же файлами и строками. Расхождений — ни
 * одного, включая отсутствие деклараций родом `запись` в найденных девяти (её
 * охват в `link-collision-guard.mjs` шире не проявился на этом дереве).
 *
 * ── Этот сторож БИНАРНОГО НЕ ЗОВЁТ, и это его достоинство ───────────────────
 *
 * Ни разу за весь прогон не запускается `bootstrap/flang` и вообще ничего
 * собранного — только чтение текста `.flang` с диска. Поэтому правило «нет
 * двоичного → код 3, а не тихая ложь» здесь ни при чём: тут нечему быть
 * отсутствующим. Код 3 у ЭТОГО сторожа означает другое — недоехавшее замыкание
 * (пустое или с нерешёнными ввозами), а не пропавший двоичный.
 *
 * ── Ведомость известных: сторож, красный ВСЕГДА, — не сторож ────────────────
 *
 * Плоская модель заведомо шире настоящего связывания (не учитывает `только`),
 * и на дереве `884e2e42` она называет девять пар, которые связывание никогда не
 * сливает. Отвечать на них кодом 1 каждый прогон значило бы завести сторожа,
 * который всегда красный, — на такой быстро перестают смотреть, и тогда он не
 * поймает НАСТОЯЩУЮ новую находку. Поэтому эти девять записаны поимённо (с
 * доводом, откуда взяты) в `scripts/type-collision-guard-known.tsv` — том же
 * приёме, что и `scripts/link-guard-known-not-a-path.tsv` /
 * `scripts/hand-written-lists-ledger.tsv`: код 1 только на том, чего в
 * ведомости НЕТ. Запись ведомости, переставшая находиться в дереве, — не
 * отказ, а отдельное сообщение «ведомость отстала»: так же, как у
 * `hand-written-lists-ledger.tsv`, ведомость, пережившая дерево, — та же
 * болезнь, ради которой она заведена. Довод и происхождение чисел — в шапке
 * самой ведомости, не здесь.
 */

