/**
 * Сторож столкновений ТИПОВ (вид 1) — за секунды, БЕЗ собранного двоичного.
 *
 *   node scripts/type-collision-guard.mjs [вход.flang]
 *   node scripts/type-collision-guard.mjs --порча     самопроверка в обе стороны
 *
 * Код возврата: 0 — типовых столкновений нет; 1 — нашлись, каждое названо
 * именем, обоими файлами и обеими строками; 3 — не судил (замыкание пусто или
 * часть ввозов не разрешена — список неполон, а не чист).
 *
 * ЯЗЫК — JavaScript (`.mjs`), а не bash или flang: `замыкание`/`столкновения`
 * уже написаны, проверены и живут в `flang/scripts/link-collision-guard.mjs` —
 * этот файл их ЗОВЁТ, а не переписывает вторым разбором.
 *
 * ── ДВА ВИДА, И ЭТОТ СТОРОЖ ЛОВИТ ОДИН ─────────────────────────────────────
 *
 *   вид 1 — одно и то же русское имя ТИПА объявлено ДВАЖДЫ в замыкании
 *           (FLANG_DUPLICATE_NAME). Этот сторож ловит ровно его.
 *   вид 2 — ДВА РАЗНЫХ русских имени переводятся в одну латиницу. Этот сторож
 *           его НЕ ЛОВИТ ВООБЩЕ — он смотрит на русские имена в дереве разбора,
 *           до всякой транслитерации. Зелёный ответ здесь — не «столкновений
 *           нет», а «столкновений ВИДА 1 нет»; за вид 2 отвечает другая мера.
 *
 * ── Откуда штатный сторож дерева не годится СЕЙЧАС ──────────────────────────
 *
 * `scripts/name-collision-guard.flang` (запускается `bootstrap/flang io
 * scripts/name-collision-guard.flang`) — полный, флаговый ответ на оба вида, но
 * ему нужен СОБРАННЫЙ двоичный: без него `bootstrap/flang` либо не запустится,
 * либо, как замерено на дереве `fa45f9ff`, уйдёт в 540 с молчания на 0 % плана
 * и код 124 (убито по времени). Это НЕ «столкновений нет» — это «не досчитал».
 * Здесь то же самое ловится ОБХОДОМ ТЕКСТА, безо всякого двоичного: сторож
 * обязан успеть ДО печати, иначе он повторяет то, что и так скажут, только
 * позже десяти часов.
 *
 * ── Модель — не с потолка, а из шапки самого штатного сторожа ───────────────
 *
 * `scripts/name-collision-guard.flang` и его прообраз
 * `flang/scripts/link-collision-guard.mjs` открываются одной строкой:
 * «связывание сливает объявления всех подключённых файлов в ОДНО ПЛОСКОЕ
 * пространство имён». Здесь ровно эта модель, суженная на один род объявлений
 * (типы: `тип`/`объект`/`запись`) и НАМЕРЕННО БЕЗ учёта видимости (`только`) —
 * пространство считается плоским по всему замыканию, а не по файлу. Владелец
 * задачи уже проверил файловую модель («имя видно из двух ввезённых модулей») и
 * отбросил её как слепую: на испорченном дереве она отвечает «0».
 *
 * Столкновения и замыкание СЧИТАЕТ `flang/scripts/link-collision-guard.mjs`
 * (функции `замыкание` и `столкновения`) — тот самый обход, что уже сверен с
 * настоящим связыванием (`flang/self/link.flang`) на 387 поддельных деревьях,
 * ноль расхождений. Здесь он не переписан заново: второй разбор `.flang` в
 * дереве заводить нельзя (см. шапку самого `link-collision-guard.mjs`), и
 * `scripts/identical-declarations.sh` берёт `замыкание` оттуда же и по той же
 * причине — «одно место на две работы: разойтись им нечем». Флаг
 * `безВидимости: true` в вызове `столкновения()` — это и есть «плоское, а не
 * суженное `только`» пространство; далее берётся ровно род `types`.
 *
 * ── Сверено с независимым прибором ───────────────────────────────────────────
 *
 * На дереве `884e2e42` независимый разбор строкой (`столкновения.py`, отдельная
 * реализация — свой обход `использует`, свой поиск модулей по каталогам
 * `flang/self`, `flang/self/bootstrap`, `flang/stdlib`, `flang/core`, регэксп
 * ТОЛЬКО на `объект|тип`, без `запись`) называет ТЕ ЖЕ 45 файлов замыкания и ТЕ
 * ЖЕ 9 столкнувшихся типов, теми же файлами и строками. Расхождений — ни
 * одного, включая отсутствие деклараций родом `запись` в найденных девяти (её
 * охват в `link-collision-guard.mjs` шире не проявился на этом дереве).
 *
 * ── Этот сторож БИНАРНОГО НЕ ЗОВЁТ, и это его достоинство ───────────────────
 *
 * Ни разу за весь прогон не запускается `bootstrap/flang` и вообще ничего
 * собранного — только чтение текста `.flang` с диска. Поэтому правило «нет
 * двоичного → код 3, а не тихая ложь» здесь ни при чём: тут нечему быть
 * отсутствующим. Код 3 у ЭТОГО сторожа означает другое — недоехавшее замыкание
 * (пустое или с нерешёнными ввозами), а не пропавший двоичный.
 *
 * ── Числа СЕГОДНЯ — это не «всё сломано» ────────────────────────────────────
 *
 * На стволе уже стоят девять таких пар (см. прогон ниже) — и сборка всё равно
 * идёт: часть из них расходится по `только`/видимости настоящих программ, и
 * связывание их не сливает НИКОГДА. Этот сторож смотрит НАМЕРЕННО шире связывания
 * (плоское пространство, не суженное) — мера в одну сторону завышена, а не
 * занижена, как и `identical-declarations.sh` про себя же говорит про свою
 * меру. Отсюда код возврата этого сторожа сегодня — 1, не 0, и это ЧЕСТНЫЙ
 * ответ про сегодняшнее дерево, а не повод его не заводить: ловит он НОВУЮ пару
 * ничуть не хуже, чем ЛЮБУЮ из старых, — порча ниже проверяет именно это.
 */

import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import {
  КОРЕНЬ,
  ВХОД_ПО_УМОЛЧАНИЮ,
  столкновения as столкновенияВсех,
} from "../flang/scripts/link-collision-guard.mjs"
import { запущенНапрямую } from "../flang/scripts/direct-run.mjs"

/** Столкновения, суженные до рода «types»: плоско по замыканию, без «только». */
export function типовыеСтолкновения(вход = ВХОД_ПО_УМОЛЧАНИЮ, настройки = {}) {
  const итог = столкновенияВсех(вход, { ...настройки, безВидимости: true })
  return { ...итог, типы: итог.столкновения.filter((с) => с.поле === "types") }
}

function блокНаходки(с) {
  return [
    `тип «${с.имя}» объявлен дважды в замыкании:`,
    `  ${с.первый.файл}:${с.первый.строка}`,
    `  ${с.второй.файл}:${с.второй.строка}`,
  ].join("\n")
}

/* ── самопроверка порчей, в обе стороны ─────────────────────────────────────
   Порча — ЧТЕНИЕМ, а не записью на диск: подменяется текст, который видит
   замыкание, дерево на диске остаётся нетронутым (тот же приём, что в
   `link-collision-guard.mjs`: `настройки.читать`). */

function сПодменойСтроки(корень, файл, изТекста, вТекст) {
  return (путь) => {
    const текст = readFileSync(resolve(корень, путь), "utf8")
    if (путь !== файл) return текст
    if (!текст.includes(изТекста)) {
      throw new Error(`порча не нашла в ${файл} строку: ${JSON.stringify(изТекста)}`)
    }
    return текст.replace(изТекста, вТекст)
  }
}

function сПереименованнойВторойСтороной(корень, с) {
  const файл = с.второй.файл
  const строка = с.второй.строка
  const текст = readFileSync(resolve(корень, файл), "utf8")
  const строки = текст.split("\n")
  const исходная = строки[строка - 1]
  const новая = исходная.replace(`«${с.имя}»`, `«${с.имя} (проба убрать)»`)
  if (новая === исходная) return null
  return (путь) => {
    if (путь !== файл) return readFileSync(resolve(корень, путь), "utf8")
    const копия = [...строки]
    копия[строка - 1] = новая
    return копия.join("\n")
  }
}

export function проверитьПорчей(корень = КОРЕНЬ) {
  const строки = []
  let сошлось = true
  const чисто = типовыеСтолкновения(ВХОД_ПО_УМОЛЧАНИЮ, { корень })
  строки.push(`чисто (без порчи): файлов ${чисто.файлов}, типов столкнулось ${чисто.типы.length}`)

  /* Проба «ДОБАВИТЬ» — отмена настоящей исторической починки `ef718648`:
     `объект «Сбор слов C»` (emit-c.flang) возвращается в `объект «Сбор слов»`,
     занятое `flang/stdlib/sha256.flang:70`. Это НЕ выдумка: ровно этот отказ
     ловила перепечатка компилятора до починки. */
  {
    const читать = сПодменойСтроки(
      корень,
      "flang/self/emit-c.flang",
      "объект «Сбор слов C»",
      "объект «Сбор слов»",
    )
    const итог = типовыеСтолкновения(ВХОД_ПО_УМОЛЧАНИЮ, { корень, читать })
    const новое = итог.типы.find((с) => с.имя === "Сбор слов")
    const ладно = итог.типы.length === чисто.типы.length + 1 && новое !== undefined
    сошлось = сошлось && ладно
    строки.push("")
    строки.push(`${ладно ? "СОШЛОСЬ" : "РАЗОШЛОСЬ"} — проба «добавить» (отмена ef718648: «Сбор слов C» → «Сбор слов»)`)
    строки.push(`  типов было ${чисто.типы.length}, стало ${итог.типы.length}`)
    строки.push(новое ? `  найдено: ${блокНаходки(новое).split("\n").join(" / ")}` : "  ОЖИДАЛИ новое имя «Сбор слов» — не найдено")
  }

  /* Проба «УБРАТЬ» — гасим ОДНО из уже стоящих на дереве столкновений,
     переименовав вторую сторону. Без неё «сходится» проверялось бы только тем,
     что сегодня и так растёт (пробой «добавить»): сторож обязан уметь и
     уменьшать счёт, когда пара действительно снята, а не быть счётчиком,
     который умеет только расти. */
  {
    if (чисто.типы.length === 0) {
      строки.push("")
      строки.push("ПРОПУЩЕНО — проба «убрать»: на дереве нет ни одного столкновения типов, гасить нечего")
    } else {
      const цель = чисто.типы[0]
      const читать = сПереименованнойВторойСтороной(корень, цель)
      if (читать === null) {
        сошлось = false
        строки.push("")
        строки.push(`РАЗОШЛОСЬ — проба «убрать»: строка ${цель.второй.строка} файла ${цель.второй.файл} не содержит «${цель.имя}» — подмена не удалась`)
      } else {
        const итог = типовыеСтолкновения(ВХОД_ПО_УМОЛЧАНИЮ, { корень, читать })
        const пропало = !итог.типы.some((с) => с.имя === цель.имя)
        const ладно = пропало && итог.типы.length === чисто.типы.length - 1
        сошлось = сошлось && ладно
        строки.push("")
        строки.push(`${ладно ? "СОШЛОСЬ" : "РАЗОШЛОСЬ"} — проба «убрать» (переименовано второе вхождение «${цель.имя}» в ${цель.второй.файл}:${цель.второй.строка})`)
        строки.push(`  типов было ${чисто.типы.length}, стало ${итог.типы.length}`)
        if (!пропало) строки.push(`  «${цель.имя}» всё ещё в списке — подмена не подействовала`)
      }
    }
  }

  строки.push("")
  строки.push(сошлось
    ? "Обе пробы сошлись: сторож видит и появление, и исчезновение столкновения типа."
    : "СТОРОЖ ОТВЕТИЛ НЕ ТО, ЧТО ОБЯЗАН.")
  return { сошлось, отчёт: строки.join("\n") }
}

function главная(аргументы) {
  if (аргументы.includes("--порча")) {
    const { сошлось, отчёт } = проверитьПорчей()
    process.stdout.write("── сторож столкновений типов: НАРОЧНАЯ ПОЛОМКА ──\n")
    process.stdout.write(отчёт + "\n")
    return сошлось ? 0 : 1
  }

  const позиционные = аргументы.filter((а) => !а.startsWith("--"))
  const вход = позиционные[0] ?? ВХОД_ПО_УМОЛЧАНИЮ

  const начало = Date.now()
  const итог = типовыеСтолкновения(вход)
  const мс = Date.now() - начало

  process.stdout.write("── сторож столкновений типов (вид 1; вид 2 — не его дело, см. шапку) ──\n")

  if (итог.файлов === 0) {
    process.stdout.write(`вход: ${вход}\n`)
    process.stderr.write("НЕ СУДИЛ: замыкание пусто — ни один файл не разобран.\n")
    process.stderr.write("Это не «столкновений нет», это «смотреть нечем».\n")
    return 3
  }

  process.stdout.write(`вход: ${вход}\n`)
  process.stdout.write(`замыкание: ${итог.файлов} файлов\n`)
  for (const п of итог.пропали) process.stdout.write(`НЕ НАЙДЕН модуль: ${п}\n`)
  for (const ц of итог.циклы) process.stdout.write(`циклический импорт: ${ц}\n`)
  for (const с of итог.споры) process.stdout.write(`ИМЯ НОСЯТ ДВА МОДУЛЯ: ${с}\n`)

  process.stdout.write(`типов, объявленных дважды: ${итог.типы.length}\n`)
  for (const с of итог.типы) {
    process.stdout.write("\n" + блокНаходки(с) + "\n")
  }
  process.stdout.write(`\nсчитано за ${мс} мс\n`)

  const неполно = итог.пропали.length > 0 || итог.циклы.length > 0 || итог.споры.length > 0

  if (итог.типы.length > 0) {
    process.stdout.write("\nГРАНИЦА: это вид 1 (одно имя дважды). Вид 2 (два разных имени → одна латиница) этот сторож НЕ проверяет.\n")
    return 1
  }
  if (неполно) {
    process.stderr.write("\nНЕ СУДИЛ ДО КОНЦА: часть ввозов не разрешена или есть цикл/спор об имени модуля — список неполон.\n")
    process.stderr.write("Это не «столкновений нет», это «досмотрено не всё».\n")
    return 3
  }
  process.stdout.write("\nЧисто по виду 1 (типы). ГРАНИЦА: вид 2 (два разных имени → одна латиница) этот сторож НЕ проверяет вовсе — это другая мера.\n")
  return 0
}

if (запущенНапрямую(import.meta.url)) process.exit(главная(process.argv.slice(2)))
