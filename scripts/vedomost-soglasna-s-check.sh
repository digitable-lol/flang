#!/bin/sh
# СОГЛАСИЕ ДВУХ ДОРОГ ОДНОГО ДВОИЧНОГО (задача 9712).
#
# `flang check <файл>` и `flang check <файл> --proof` идут разными дорогами:
# первая — тремя вызовами из `check_file()`, вторая — через слой на flang
# («Ведомость исходников»). Дороги обязаны сходиться в одном: где первая
# ОТВЕРГАЕТ или НЕДОСУЖИВАЕТ, вторая не вправе молча выдавать код 0 и печатать
# запись доказательства.
#
# ЧТО ИМЕННО СТОРОЖИТСЯ, и почему не «равенство кодов». Коды у двух дорог
# разные по смыслу и совпадать не обязаны: у `check` 2 значит «недосудил», у
# ведомости 2 значит «препятствие», 3 — «есть высказанное без доказательства».
# Сторожится одно: НУЛЬ ВЕДОМОСТИ ПРИ НЕНУЛЕ ПРОВЕРКИ. Это и есть сертификат
# тому, что не проверено.
#
# ПОЧЕМУ ЭТО НЕ ПРИДИРКА. До починки на четырнадцати подделках
# `flang/test/fixtures/binary-rules` расходились три, и худшая из них —
# `equality-not-symmetric`: `check` отвергал её кодом 1, НАЗВАВ правило
# FLANG_EQUALITY_NOT_SYMMETRIC на паре значений сетки, а ведомость на том же
# файле писала «ПРОВЕРЕНО САМОСТОЯТЕЛЬНО», код 0, и печатала запись. Сверщик
# записи принимал её кодом 0 — подделка проходила всю цепь.
#
# ЧЕСТНЫЙ ФАЙЛ ОБЯЗАН ОСТАТЬСЯ ЗЕЛЁНЫМ, и он проверяется здесь же: сторож,
# который краснеет на всём, не отличает подделку от работы.
set -eu

B=${FLANG:-./bootstrap/flang}
KAT=${KAT:-flang/test/fixtures/binary-rules}
ZELENYY=${ZELENYY:-scale-mismatch}

if [ ! -x "$B" ]; then
  echo "нет двоичного $B — собрать: make -C bootstrap"
  exit 2
fi

BED=0
VSEGO=0
printf '%-30s %6s %8s  %s\n' "файл" "check" "--proof" "приговор"
for f in "$KAT"/*.flang; do
  n=$(basename "$f" .flang)
  VSEGO=$((VSEGO + 1))
  set +e
  "$B" check "$f" >/dev/null 2>&1
  K1=$?
  "$B" check "$f" --proof >/dev/null 2>&1
  K2=$?
  set -e
  SLOVO="согласны"
  if [ "$K1" -ne 0 ] && [ "$K2" -eq 0 ]; then
    SLOVO="РАСХОЖДЕНИЕ: проверка отвергла, ведомость выдала сертификат"
    BED=$((BED + 1))
  fi
  if [ "$n" = "$ZELENYY" ] && { [ "$K1" -ne 0 ] || [ "$K2" -ne 0 ]; }; then
    SLOVO="РАСХОЖДЕНИЕ: честный файл покраснел"
    BED=$((BED + 1))
  fi
  printf '%-30s %6d %8d  %s\n' "$n" "$K1" "$K2" "$SLOVO"
done

echo
echo "файлов $VSEGO, расхождений $BED"
if [ "$BED" -gt 0 ]; then
  echo "ведомость выдаёт сертификат тому, что проверка отвергает — задача 9712"
  exit 1
fi
echo "две дороги согласны"
