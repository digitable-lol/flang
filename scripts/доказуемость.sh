# ДОКАЗУЕМ ЛИ ЯЗЫК — ОДНИМ СЛОВОМ, ПО ТРЁМ ЧИСЛАМ, А НЕ ПО ПРОЗЕ.
#
#   sh scripts/доказуемость.sh
#   ./ярлык доказуемость
#
# Печатает ДОКАЗУЕМ или НЕ ДОКАЗУЕМ. Слово это ходит по документам разовым
# суждением («язык формально-доказуем», «взято N из 7 гейтов»), и суждение
# устаревает молча. Здесь его СНИМАЕТ прибор: три проверки, у каждой число,
# и слово выводится из чисел, а не вписывается рукой.
#
# ДОКАЗУЕМ печатается ТОЛЬКО когда сходятся все три:
#   1. калькулятор `perepiskoy` СНЯТ из чекера (0 вхождений в сверщик.c);
#   2. доля корпуса, проверенного ПЕРЕИГРЫВАТЕЛЕМ, не ниже порога (95 %);
#   3. набор проб чекера цел (ни одна подделка не принята, ни одна честная
#      запись не отвергнута).
# Не сошлась хоть одна — НЕ ДОКАЗУЕМ, и названо, какая проверка провалила и
# каким числом.
#
# КОД ВОЗВРАТА НЕСЁТ ВЕРДИКТ:  0 — ДОКАЗУЕМ, 1 — НЕ ДОКАЗУЕМ, 2 — не смог
# измерить (нет исходника чекера, прогон проб не запустился). Так `./ярлык
# доказуемость && …` работает по существу, а не по слову вывода.
#
# ── Почему проверка 1 РЕШАЮЩАЯ и почему ответ короткий ──────────────────────
# `perepiskoy` — «калькулятор»: ход чекера, который ДОКАЗЫВАЕТ утверждение,
# ВЫЧИСЛЯЯ его, а не проигрывая записанные шаги. Пока он в чекере есть, доля
# доказанного держится вычислением — это дыра гейта Г7 (независимая проверка).
# Одного его наличия довольно, чтобы язык не был формально-доказуем, поэтому
# проверка 1 стоит первой и, провалившись, останавливает прибор коротко:
# гонять дорогой набор проб (проверка 3) незачем — вердикт уже известен.
#
# СЕГОДНЯ ОТВЕТ — НЕ ДОКАЗУЕМ, и это не поломка прибора, а честный замер:
# калькулятор на месте. Прибор зазеленеет сам, когда `perepiskoy` уйдёт из
# чекера, доля-проигрыванием дорастёт до порога и набор проб останется цел.
#
# ── Проверка 2: чем меряется доля-проигрыванием, и почему сегодня 0 ─────────
# Гейт Г7 требует ДОЛЮ корпуса, проверенную НЕЗАВИСИМО — проигрыванием
# записанных шагов, а не вычислением. Прибора, который разделил бы «проиграно»
# и «посчитано» и назвал долю проигранного, в дереве сегодня НЕТ:
# `flang/proof/доля-корпуса.sh` меряет разряды помех Р0–Р5 (крипто-привязка и
# места «на слово ядра»), а не долю-проигрыванием. Половина Б чекера (печать
# следов и их независимое проигрывание) не запущена — сквозь переигрыватель
# идёт 0 записей. Поэтому доля-проигрыванием здесь честно принята за 0: не
# «измерено 0 %», а «измерить сегодня нечем, и завышать нельзя». Появится
# прибор — сюда встанет его число.
#
# Имена переменных латиницей: ни dash, ни bash не берут кириллицу в именах.
set -eu
export LC_ALL=C.UTF-8

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$KOREN"

SVERSCHIK_C=flang/proof/чекер/сверщик.c
PROGON_PROB=flang/proof/чекер/пробы/прогон.sh
POROG=95

command -v git >/dev/null 2>&1 || { echo "не смог измерить: git не найден" >&2; exit 2; }
git rev-parse --git-dir >/dev/null 2>&1 || { echo "не смог измерить: $KOREN не под учётом git" >&2; exit 2; }
[ -f "$SVERSCHIK_C" ] || { echo "не смог измерить: нет $SVERSCHIK_C" >&2; exit 2; }

# ── ПРОВЕРКА 1 (РЕШАЮЩАЯ): калькулятор perepiskoy снят из чекера? ───────────
# `git grep -c` печатает «путь:ЧИСЛО» — строк с совпадением. Совпадений нет:
# grep выходит кодом 1 и не печатает ничего; sed отдаёт пусто, считаем за 0.
# Отпечаток берём через трубу (sed на конце всегда код 0), чтобы set -e не снял
# прибор на честном «ноль совпадений».
PEREPISKOY=$(git -c core.quotepath=false grep -c perepiskoy -- "$SVERSCHIK_C" 2>/dev/null | sed 's/^.*://')
[ -n "$PEREPISKOY" ] || PEREPISKOY=0

if [ "$PEREPISKOY" -gt 0 ]; then
  echo "НЕ ДОКАЗУЕМ"
  echo
  echo "проверка 1 (решающая) — калькулятор снят? НЕТ"
  echo "  perepiskoy в $SVERSCHIK_C: $PEREPISKOY (git grep -c)"
  echo "  пока калькулятор на месте — доказательства вычислением, дыра Г7 открыта"
  echo
  echo "проверки 2 и 3 не гонялись: вердикт решён проверкой 1"
  exit 1
fi

# ── ПРОВЕРКА 2: доля корпуса проигрыванием не ниже порога? ──────────────────
# Прибора нет (см. шапку) — доля-проигрыванием честно 0, а 0 < 95.
DOLYA_PROIGRYVANIEM=0

if [ "$DOLYA_PROIGRYVANIEM" -lt "$POROG" ]; then
  echo "НЕ ДОКАЗУЕМ"
  echo
  echo "проверка 1 — калькулятор снят? ДА (perepiskoy: 0)"
  echo "проверка 2 — доля проигрыванием не ниже ${POROG} %? НЕТ"
  echo "  доля-проигрыванием: ${DOLYA_PROIGRYVANIEM} % (< ${POROG} %)"
  echo "  прибора «проиграно против посчитано» в дереве нет: Половина Б не"
  echo "  запущена, сквозь переигрыватель идёт 0 записей"
  echo
  echo "проверка 3 не гонялась: вердикт решён проверкой 2"
  exit 1
fi

# ── ПРОВЕРКА 3: набор проб чекера цел? ─────────────────────────────────────
# Код 0 у прогона = ни одна подделка не принята, ни одна честная не отвергнута.
PROGON_VYVOD=$(sh "$PROGON_PROB" 2>&1) && PROGON_KOD=0 || PROGON_KOD=$?

PODDELOK=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/^ *подделок \([0-9][0-9]*\):.*/\1/p')
PRINYATO=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/.*ПРИНЯТО кодом 0 — \([0-9][0-9]*\).*/\1/p')
CHESTNYH=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/^ *честных  *\([0-9][0-9]*\):.*/\1/p')
OTVERGNUTO=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/.*честных.*/&/p' | sed -n 's/.*отвергнуто \([0-9][0-9]*\) (обязано быть 0).*/\1/p')

if [ "$PROGON_KOD" -gt 1 ]; then
  echo "не смог измерить: набор проб не запустился (код $PROGON_KOD)" >&2
  printf '%s\n' "$PROGON_VYVOD" >&2
  exit 2
fi

if [ "$PROGON_KOD" -ne 0 ]; then
  echo "НЕ ДОКАЗУЕМ"
  echo
  echo "проверка 1 — калькулятор снят? ДА (perepiskoy: 0)"
  echo "проверка 2 — доля проигрыванием не ниже ${POROG} %? ДА"
  echo "проверка 3 — набор проб цел? НЕТ"
  echo "  подделок ${PODDELOK:-?}: принято ${PRINYATO:-?} (обязано 0);" \
       "честных ${CHESTNYH:-?}: отвергнуто ${OTVERGNUTO:-?} (обязано 0)"
  exit 1
fi

echo "ДОКАЗУЕМ"
echo
echo "проверка 1 — калькулятор снят? ДА (perepiskoy: 0)"
echo "проверка 2 — доля проигрыванием не ниже ${POROG} %? ДА (${DOLYA_PROIGRYVANIEM} %)"
echo "проверка 3 — набор проб цел? ДА (подделок ${PODDELOK:-?}: принято ${PRINYATO:-?};" \
     "честных ${CHESTNYH:-?}: отвергнуто ${OTVERGNUTO:-?})"
exit 0
