# ДОКАЗУЕМ ЛИ ЯЗЫК — ОДНИМ СЛОВОМ, ПО ЧЕТЫРЁМ ЧИСЛАМ, А НЕ ПО ПРОЗЕ.
#
#   sh scripts/доказуемость.sh
#   ./ярлык доказуемость
#
# Печатает ДОКАЗУЕМ или НЕ ДОКАЗУЕМ. Слово это ходит по документам разовым
# суждением («язык формально-доказуем», «взято N из 7 гейтов»), и суждение
# устаревает молча. Здесь его СНИМАЕТ прибор: четыре проверки, у каждой число,
# и слово выводится из чисел, а не вписывается рукой.
#
# ДОКАЗУЕМ печатается ТОЛЬКО когда сходятся все четыре:
#   1. калькулятор СНЯТ из чекера — мерится ЛОВУШКОЙ, прогоном по живой паре
#      исходник+запись, а не грепом по имени функции;
#   2. доля корпуса, проверенного ПЕРЕИГРЫВАТЕЛЕМ, не ниже порога (95 %);
#   3. набор проб чекера пройден ЦЕЛИКОМ (ни одна подделка не принята, ни одна
#      честная запись не отвергнута, ни одна строка манифеста не потеряна);
#   4. набор подделок НЕ ОСЛАБ: строк манифеста и числителя набора не меньше,
#      чем записано в flang/proof/подделки/ХРАПОВИК.txt.
# Не сошлась хоть одна — НЕ ДОКАЗУЕМ, и названо, какая проверка провалила и
# каким числом.
#
# КОД ВОЗВРАТА НЕСЁТ ВЕРДИКТ:  0 — ДОКАЗУЕМ, 1 — НЕ ДОКАЗУЕМ, 2 — не смог
# измерить (нет исходника чекера, прогон проб не запустился, линейка доли не
# дала числа). Исходов ТРИ, а не два: «не смог измерить» — не «не доказуем», и
# проверки 3 и 4 печатаются числами даже в нём. Так `./ярлык
# доказуемость && …` работает по существу, а не по слову вывода.
#
# ── Почему проверка 1 РЕШАЮЩАЯ, но БОЛЬШЕ НЕ ЗАМЫКАЕТ ПРИБОР НАКОРОТКО ───────
# «Калькулятор» — ход чекера, который ДОКАЗЫВАЕТ утверждение, ВЫЧИСЛЯЯ его, а
# не проигрывая записанные шаги. Пока он в чекере есть, доля
# доказанного держится вычислением — это дыра гейта Г7 (независимая проверка).
# Одного его наличия довольно, чтобы язык не был формально-доказуем.
#
# До 8 сентября 2026 прибор на этом и останавливался: провалилась проверка 1 —
# проверки 2 и 3 не гонялись вовсе, провалилась 2 — не гонялась 3. Довод был
# «вердикт уже известен, зачем платить за дорогое». Пока подделки сидели в
# знаменателе доли, это было терпимо: порча записи роняла процент, и хоть
# какой-то сторож работал всегда. С решением ADR-0023 недостижимые места из
# знаменателя вынесены, и набор подделок стал ЕДИНСТВЕННЫМ, что стоит между
# долей и ложью. Сторож, который не гоняется, — не сторож: набор мог бы
# рассыпаться месяцами, и прибор молчал бы, потому что «вердикт и так красный».
# ПОЭТОМУ ВСЕ ЧЕТЫРЕ ПРОВЕРКИ ГОНЯЮТСЯ ВСЕГДА и печатаются числами всегда,
# каким бы ни был исход предыдущих. Цена замерена: прогон проб около 3 с,
# линейка доли около 5 с — это не «дорого», это цена одной страницы вывода.
#
# ── Почему НЕ ГРЕП ПО ИМЕНИ (задача 3781) ──────────────────────────────────
# До 8 сентября 2026 проверка 1 звучала так: `git grep -c -F 'перепиской('`
# обязан быть 0. Мерка негодная, и негодность её ПОМЕРЕНА, а не предположена:
#
#   · ПЕРЕИМЕНОВАНИЕ. `перепиской` → любое другое имя, и греп зелен, а
#     калькулятор на месте. Проверка, которую обходят правкой одной строки, не
#     проверка.
#   · ПЕРЕЕЗД. Опыт: вызов `перепиской` снят, чекер пересобран — и ту же работу
#     немедленно подхватила ДРУГАЯ функция (дверь 5 `половина_закрыта`,
#     `тождественны` на глубине 6). Греп при этом печатал 0.
#   · СТОРОЖ ВМЕСТЕ С ПРУВЕРОМ. В `перепиской` жили ДВЕ разные вещи: прувер
#     (доказать цель счётом) и сторож (поймать замкнутую ложь, выданную за
#     тождество). Греп требовал снести обе, а снос сторожа ослаблял поимку
#     подделки `Ч365 П7` с «НЕ СОШЛОСЬ» до «НЕ ПРОВЕРЕНО».
#
# ЧЕМ ЗАМЕНЕНО — ЛОВУШКОЙ. Прибор берёт живые пары исходник+запись из дерева по
# таблице flang/proof/чекер/пробы/ловушка/ВИДЫ.tsv. Две цели в ней «на слове» —
# доказуемы ТОЛЬКО переписыванием тела законами:
#
#   «сумма наоборот»      цель `результат равен (б плюс а)` при теле `а плюс б`
#   «длина растёт на один» цель `результат равен ((длина элементы) плюс 1)`
#                          при теле `длина (добавить эл к элементы)`
#
# Обе — ∀ по своим доводам, ходов в записи нет ни одного, принципа нет, посылок
# нет: проигрывать нечего. Чекер ОБЯЗАН оставить их на слове ядра и назвать
# поимённо. Снимет хоть одну — калькулятор в дереве есть, под каким бы именем и
# в какой бы функции он ни жил.
#
# И ЛОВУШКА ДВУСТОРОННЯЯ. Остальные строки таблицы — «снята»: по одной цели на
# КАЖДЫЙ вид обязательства, который чекер умеет переигрывать сегодня (К11,
# 9 сентября 2026; до того обратная половина была одна — «сумма трёх», тождество
# знак в знак). Виды сняты по коду чекера: узел «разбором по случаям» на
# носителях segment/algebra/fold и с объявления типа, разбор цели по условию,
# ходы под постусловием, шаги теоремы (по примеру, по свойству, вне случая, над
# списочным телом), вывод по семействам Н/П/Пред/Т/Разв/О/Д/С/СС/В/Ч,
# обязательство входа, тотальность composition/structure/step. Каждую такую цель
# чекер обязан ЗАКРЫТЬ законно: код сошёлся, имя цели в его выводе не названо,
# след вида стоит в записи, счётчик вида в сводке больше нуля. Без этой половины
# проверку 1 брал бы и чекер, сломанный до состояния «ничего не доказываю»: он
# тоже не снял бы ни одной ∀-цели. Вид, за который чекер перестал браться, красит
# проверку 1 своим именем; убыль строки таблицы ловит храповик
# (flang/proof/чекер/пробы/ловушка/ХРАПОВИК.txt). Цели ловушки лежат ВНЕ корпуса
# и доли не двигают (замер: 567/651 до и после К11).
#
# СЕГОДНЯ ОТВЕТ — НЕ ДОКАЗУЕМ, и это не поломка прибора, а честный замер.
# Проверка 1 с 8 сентября 2026 зелена: калькулятор снят, ловушка цела в обе
# стороны. Останавливает вердикт проверка 2: доля-проигрыванием при пороге
# 95 % его не берёт. Прибор зазеленеет сам, когда доля дорастёт до порога, а
# набор проб и храповик останутся целы.
#
# ── Проверка 2: чем меряется доля-проигрыванием ─────────────────────────────
# Гейт Г7 требует ДОЛЮ корпуса, проверенную НЕЗАВИСИМО — проигрыванием
# записанных шагов, а не вычислением. Прежде здесь стояло вписанное рукой
# `DOLYA_PROIGRYVANIEM=0` с доводом «прибора нет». Прибор появился:
# `flang/proof/доля-корпуса.sh --проигрыванием` разделяет «проиграно» и
# «посчитано» и печатает долю. Число берётся ПРОГОНОМ этого прибора, порог
# 95 % не меняется.
#
# ── Проверка 4: храповик набора ─────────────────────────────────────────────
# Набор, вынесенный из знаменателя доли, перестаёт быть виден в проценте, а
# невидимое ветшает. Храповик держит два числа: сколько подделок объявлено и
# сколько мест честных половин проиграно. Первое стережёт исчезновение
# подделки, второе — беду, которой счёт строк не видит: файл остался в
# манифесте, а его честная половина тихо перестала проигрываться. Крутится
# храповик только вверх и только руками, с доводом в коммите.
#
# Имена переменных латиницей: ни dash, ни bash не берут кириллицу в именах.
set -u
export LC_ALL=C.UTF-8

KOREN=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$KOREN"

SVERSCHIK_C=flang/proof/чекер/сверщик.c
SVERSCHIK=flang/proof/чекер/сверщик
PROGON_PROB=flang/proof/чекер/пробы/прогон.sh
LINEYKA=flang/proof/доля-корпуса.sh
HRAPOVIK=flang/proof/подделки/ХРАПОВИК.txt
LOVUSHKA_TSV=${LOVUSHKA_TSV:-flang/proof/чекер/пробы/ловушка/ВИДЫ.tsv}
LOVUSHKA_HRAP=${LOVUSHKA_HRAP:-flang/proof/чекер/пробы/ловушка/ХРАПОВИК.txt}
POROG=95

command -v git >/dev/null 2>&1 || { echo "не смог измерить: git не найден" >&2; exit 2; }
git rev-parse --git-dir >/dev/null 2>&1 || { echo "не смог измерить: $KOREN не под учётом git" >&2; exit 2; }
[ -f "$SVERSCHIK_C" ] || { echo "не смог измерить: нет $SVERSCHIK_C" >&2; exit 2; }

# ── ПРОВЕРКА 1 (РЕШАЮЩАЯ): калькулятор снят? МЕРИТСЯ ЛОВУШКОЙ ──────────────
# Ловушка — это ПРОГОН, а не чтение исходника, поэтому чекер нужен собранным.
# Собираем сами, если двоичного нет: у чекера один файл и ноль зависимостей
# вне libc (тем же вызовом, что в пробы/прогон.sh).
[ -f "$LOVUSHKA_TSV" ]  || { echo "не смог измерить: нет таблицы ловушки $LOVUSHKA_TSV" >&2; exit 2; }
[ -f "$LOVUSHKA_HRAP" ] || { echo "не смог измерить: нет храповика ловушки $LOVUSHKA_HRAP" >&2; exit 2; }
if [ ! -x "$SVERSCHIK" ]; then
  ${CC:-cc} -std=c99 -Wall -Wextra -Werror -pedantic -O2 -o "$SVERSCHIK" "$SVERSCHIK_C" 2>/dev/null \
    || { echo "не смог измерить: чекер не собрался" >&2; exit 2; }
fi

# К11: ловушка — ТАБЛИЦА (flang/proof/чекер/пробы/ловушка/ВИДЫ.tsv), по строке на
# цель. Две половины, и у каждой своё «ждём»:
#   «на слове» — ∀-цели, доказуемые ТОЛЬКО вычислением: чекер обязан оставить их
#                на слове ядра и назвать поимённо. Снял хоть одну — калькулятор в
#                дереве есть, под каким бы именем он ни жил. Это решающая половина.
#   «снята»    — по одной цели на КАЖДЫЙ вид обязательства, который чекер умеет
#                переигрывать: узел (segment/algebra/fold/объявление), разбор цели,
#                ходы, шаги теоремы, вывод по семействам, обязательство входа,
#                тотальность. Каждую он обязан переиграть: код сошёлся, имя цели в
#                выводе не названо, след вида стоит в записи, счётчик вида в сводке
#                больше нуля. Без этой половины проверку 1 брал бы и чекер,
#                сломанный до «ничего не доказываю»; до К11 она стерегла один вид.
# Девятая колонка «пометка» — чем запись отличается от печати ядра (рукотворная
# правка); прибор её не читает, читает человек: цель с пометкой — не вывод ядра.
# Отпечаток исходника подаётся ТРЕТЬИМ доводом: часть записей зовёт своим
# исходником путь вне дерева (мутанты, рождённые во времянках), и без отпечатка
# чекер честно откажется судить чужое дело.
TAB=$(printf '\t')
KALKULYATOR=0; NA_SLOVE=0; VIDOV=0; VIDOV_KRASNO=0; P1_BEDY=""
while IFS="$TAB" read -r vid zhdem ish zap cel sled priznak kod pometka; do
  [ -n "$vid" ] || continue
  [ -f "$ish" ] && [ -f "$zap" ] \
    || { echo "не смог измерить: у вида «$vid» нет пары $ish / $zap" >&2; exit 2; }
  otp=$(sha256sum "$ish" | cut -d' ' -f1)
  vyvod=$("$SVERSCHIK" "$ish" "$zap" "$otp" 2>&1); k=$?
  case "$zhdem" in
    "на слове")
      # Строка «НЕ ВЗЯЛСЯ» перечисляет ПОИМЁННО каждое место, оставшееся на слове
      # ядра. Имя цели в ней есть — место не снято; имени нет — снято, кем-то.
      NA_SLOVE=$((NA_SLOVE+1))
      printf '%s\n' "$vyvod" | /usr/bin/grep -qF "утверждение «$cel»: вердикт «доказано», а за узел не взялся" \
        || { KALKULYATOR=$((KALKULYATOR+1)); P1_BEDY="$P1_BEDY; вид «$vid»: цель «$cel» снята со слова ядра — вычислением"; } ;;
    снята)
      VIDOV=$((VIDOV+1)); beda=""
      [ "$k" -eq "$kod" ] || beda="код $k, ждали $kod"
      # Имя цели в выводе чекера — это либо беда, либо «на слове ядра»: и то, и
      # другое значит, что цель НЕ переиграна.
      if printf '%s\n' "$vyvod" | /usr/bin/grep -qF "«$cel»"; then beda="${beda:+$beda; }цель «$cel» названа чекером — не переиграна"; fi
      /usr/bin/grep -qF -- "$sled" "$zap" || beda="${beda:+$beda; }в записи нет следа «$sled» — цель больше не этого вида"
      if [ "$priznak" != "—" ] && ! printf '%s\n' "$vyvod" | /usr/bin/grep -qE -- "$priznak"; then
        beda="${beda:+$beda; }в сводке чекера нет признака «$priznak»"; fi
      [ -z "$beda" ] || { VIDOV_KRASNO=$((VIDOV_KRASNO+1)); P1_BEDY="$P1_BEDY; вид «$vid»: $beda"; } ;;
    *) echo "не смог измерить: в таблице ловушки неизвестное «ждём» — «$zhdem» (вид «$vid»)" >&2; exit 2 ;;
  esac
done <<LOVUSHKA_STROKI
$(awk -F'\t' '/^#/ { next } $1 == "вид" { next } NF == 9' "$LOVUSHKA_TSV")
LOVUSHKA_STROKI
P1_BEDY=${P1_BEDY#; }

# Храповик ловушки: видов и ∀-целей не меньше, чем записано. Убыль строки таблицы
# делала бы ловушку слепой на один вид — молча; здесь она красит проверку 1.
HR_VID=$(awk '/^видов /{print $2; exit}' "$LOVUSHKA_HRAP")
HR_NS=$(awk '/^на слове /{print $3; exit}' "$LOVUSHKA_HRAP")
case "${HR_VID:-}${HR_NS:-}" in *[!0-9]*|"") echo "не смог измерить: храповик ловушки $LOVUSHKA_HRAP не называет обоих чисел" >&2; exit 2 ;; esac

if [ "$KALKULYATOR" -gt 0 ]; then
  P1=НЕТ
  P1_SLOVO="∀-целей, снятых со слова ядра вычислением: $KALKULYATOR из $NA_SLOVE — $P1_BEDY; таблица $LOVUSHKA_TSV"
elif [ "$VIDOV_KRASNO" -gt 0 ]; then
  P1=НЕТ
  P1_SLOVO="обратная половина ловушки красна: видов не переиграно $VIDOV_KRASNO из $VIDOV — прибор мерит сломанный чекер, а не снятый калькулятор — $P1_BEDY"
elif [ "$VIDOV" -lt "$HR_VID" ] || [ "$NA_SLOVE" -lt "$HR_NS" ]; then
  P1=НЕТ
  P1_SLOVO="ловушка ослабла: видов $VIDOV при храповике $HR_VID, ∀-целей $NA_SLOVE при храповике $HR_NS — строка таблицы убрана, а храповик при ней нет"
else
  P1=ДА
  P1_SLOVO="ловушка: ∀-целей на слове ядра $NA_SLOVE из $NA_SLOVE, видов обязательства переиграно $VIDOV из $VIDOV (храповик $HR_VID/$HR_NS)"
fi

# ── ПРОВЕРКА 2: доля корпуса проигрыванием не ниже порога? ──────────────────
# Число берётся прогоном линейки. Линейка падает кодом 1 на несошедшемся
# балансе знаменателя — тогда числа нет, и врать про него нельзя.
LINEYKA_VYVOD=$(sh "$LINEYKA" --проигрыванием 2>&1) && LINEYKA_KOD=0 || LINEYKA_KOD=$?
DOLYA=$(printf '%s\n' "$LINEYKA_VYVOD" | sed -n 's/^доля-проигрыванием = \([0-9]*\) \/ \([0-9]*\) = \([0-9.]*\) %.*/\3/p')
DOLYA_CH=$(printf '%s\n' "$LINEYKA_VYVOD" | sed -n 's/^доля-проигрыванием = \([0-9]*\) \/ \([0-9]*\) = .*/\1/p')
DOLYA_ZN=$(printf '%s\n' "$LINEYKA_VYVOD" | sed -n 's/^доля-проигрыванием = \([0-9]*\) \/ \([0-9]*\) = .*/\2/p')
NEDOST=$(printf '%s\n' "$LINEYKA_VYVOD" | sed -n 's/^исключено мест  *\([0-9][0-9]*\).*/\1/p')
NAB_STROK=$(printf '%s\n' "$LINEYKA_VYVOD" | sed -n 's/^поймано \([0-9][0-9]*\) из \([0-9][0-9]*\) .*/\2/p')
NAB_CHISL=$(printf '%s\n' "$LINEYKA_VYVOD" | sed -n 's/.*числитель набора \([0-9][0-9]*\) .*/\1/p')
# Линейка отказала (несошедшийся баланс знаменателя, пустой корпус) — числа
# нет, и врать про него нельзя. Но это НЕ повод молчать о проверках 3 и 4:
# они гоняются и печатаются всё равно, а вердикт становится «не смог измерить».
NE_IZMERIL=0
if [ "$LINEYKA_KOD" -ne 0 ] || [ -z "$DOLYA" ]; then
  NE_IZMERIL=1; P2="НЕ ИЗМЕРЕНА"
  LINEYKA_BEDA=$(printf '%s\n' "$LINEYKA_VYVOD" | grep -m1 'РАСХОЖДЕНИЕ\|не смог\|нет ни одной записи')
  [ -n "$LINEYKA_BEDA" ] || LINEYKA_BEDA="линейка вышла кодом $LINEYKA_KOD и числа не дала"
else
  P2=$(awk -v d="$DOLYA" -v p="$POROG" 'BEGIN{ print (d+0 >= p+0) ? "ДА" : "НЕТ" }')
fi

# ── ПРОВЕРКА 3: набор проб чекера пройден целиком? ─────────────────────────
# ГОНЯЕТСЯ ВСЕГДА, каким бы ни был исход проверок 1 и 2 (см. шапку).
# Код 0 у прогона = ни одна подделка не принята, ни одна честная не отвергнута,
# ни одна строка манифеста не потеряна.
PROGON_VYVOD=$(sh "$PROGON_PROB" 2>&1) && PROGON_KOD=0 || PROGON_KOD=$?
if [ "$PROGON_KOD" -gt 1 ]; then
  echo "не смог измерить: набор проб не запустился (код $PROGON_KOD)" >&2
  printf '%s\n' "$PROGON_VYVOD" >&2
  exit 2
fi
PODDELOK=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/^ *подделок \([0-9][0-9]*\):.*/\1/p')
PRINYATO=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/.*ПРИНЯТО кодом 0 — \([0-9][0-9]*\).*/\1/p')
CHESTNYH=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/^ *честных  *\([0-9][0-9]*\):.*/\1/p')
OTVERGNUTO=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/.*честных.*/&/p' | sed -n 's/.*отвергнуто \([0-9][0-9]*\) (обязано быть 0).*/\1/p')
NAB_POYMANO=$(printf '%s\n' "$PROGON_VYVOD" | sed -n 's/^ *набор подделок: поймано \([0-9][0-9]*\) из \([0-9][0-9]*\).*/\1/p')
if [ "$PROGON_KOD" -eq 0 ]; then P3=ДА; else P3=НЕТ; fi

# ── ПРОВЕРКА 4: набор не ослаб (храповик)? ─────────────────────────────────
P4=ДА; P4_SLOVO=""
if [ ! -f "$HRAPOVIK" ]; then
  P4=НЕТ; P4_SLOVO="храповика нет — $HRAPOVIK потерян"
else
  HR_P=$(awk '/^подделок /{print $2; exit}' "$HRAPOVIK")
  HR_CH=$(awk '/^числитель /{print $2; exit}' "$HRAPOVIK")
  if [ -z "${HR_P:-}" ] || [ -z "${HR_CH:-}" ]; then
    P4=НЕТ; P4_SLOVO="храповик не называет обоих чисел"
  else
    [ -n "${NAB_STROK:-}" ] || NAB_STROK=0
    [ -n "${NAB_CHISL:-}" ] || NAB_CHISL=0
    if [ "$NAB_STROK" -lt "$HR_P" ]; then
      P4=НЕТ
      P4_SLOVO="подделок в манифесте $NAB_STROK при храповике $HR_P — набор ослаб на $((HR_P-NAB_STROK))"
    fi
    if [ "$NAB_CHISL" -lt "$HR_CH" ]; then
      P4=НЕТ
      if [ -n "$P4_SLOVO" ]; then P4_SLOVO="$P4_SLOVO; "; fi
      P4_SLOVO="${P4_SLOVO}числитель набора $NAB_CHISL при храповике $HR_CH — просело на $((HR_CH-NAB_CHISL)) мест"
    fi
  fi
fi

# ── ВЕРДИКТ ────────────────────────────────────────────────────────────────
# Печатаются ВСЕ ЧЕТЫРЕ строки с числами, независимо от того, какая провалила:
# «вердикт уже известен» — не довод молчать о трёх остальных сторожах.
if [ "$NE_IZMERIL" -eq 1 ]; then
  echo "НЕ СМОГ ИЗМЕРИТЬ"; ITOG=2
elif [ "$P1" = ДА ] && [ "$P2" = ДА ] && [ "$P3" = ДА ] && [ "$P4" = ДА ]; then
  echo "ДОКАЗУЕМ"; ITOG=0
else
  echo "НЕ ДОКАЗУЕМ"; ITOG=1
fi
echo
echo "проверка 1 — калькулятор снят? $P1 ($P1_SLOVO)"
if [ "$NE_IZMERIL" -eq 1 ]; then
  echo "проверка 2 — доля проигрыванием не ниже ${POROG} %? НЕ ИЗМЕРЕНА ($LINEYKA_BEDA)"
else
  echo "проверка 2 — доля проигрыванием не ниже ${POROG} %? $P2 (${DOLYA} %: ${DOLYA_CH} из ${DOLYA_ZN}; недостижимых мест вынесено ${NEDOST:-0})"
fi
echo "проверка 3 — набор проб пройден? $P3 (набор подделок ${NAB_POYMANO:-?} из ${NAB_STROK:-?}; проб на подлог ${PODDELOK:-?}, принято кодом 0 — ${PRINYATO:-?}; честных ${CHESTNYH:-?}, отвергнуто ${OTVERGNUTO:-?})"
if [ "$P4" = ДА ]; then
  echo "проверка 4 — набор не ослаб? ДА (в манифесте ${NAB_STROK:-?} при храповике ${HR_P:-?}; числитель ${NAB_CHISL:-?} при храповике ${HR_CH:-?})"
else
  echo "проверка 4 — набор не ослаб? НЕТ ($P4_SLOVO)"
fi
if [ "$P3" != ДА ]; then
  echo
  echo "чем провалился набор проб (проверка 3) — строками прогона:"
  printf '%s\n' "$PROGON_VYVOD" | grep '^ПРОВАЛ' | sed 's/^/  /'
fi
exit "$ITOG"
