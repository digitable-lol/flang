/**
 * Двунаправленные управляющие символы — общая проверка ВСЕХ бэкендов ftsc.
 *
 * Правило одно на все бэкенды обоих компиляторов репозитория: двунаправленные
 * управляющие символы Unicode (U+061C, U+200E, U+200F, U+202A…U+202E,
 * U+2066…U+2069) нельзя печатать в целевой код сырыми. Места они не занимают, а
 * раскладку текста меняют, поэтому файл читается не так, как исполняется, — это
 * «Trojan Source» (CVE-2021-42574).
 *
 * ── Почему этот тест появился отдельно ──────────────────────────────────────
 * Правило было записано в восьми бэкендах flang и НИ В ОДНОМ из восьми
 * бэкендов ftsc. Имя правила FTS с U+202E доезжало сырым сразу двумя путями:
 *
 *   1. в КОММЕНТАРИЙ — «правило «…»», «свойство «…»», подпись примера. Он не
 *      исполняется, и ровно поэтому опасен: его читают первым, а проверить
 *      исполнением не могут;
 *   2. в СТРОКОВЫЙ ЛИТЕРАЛ — System.out.println прогонщика примеров, имя
 *      примера в test/2 ExUnit, имя нарушенного свойства в тексте исключения.
 *
 * Чего это стоило на этой машине (проверено на фикстуре discount с именами,
 * в которые вставлены управляющие):
 *
 *   • elixirc 1.20.2 ОТКАЗЫВАЛСЯ разбирать модуль — «invalid bidirectional
 *     formatting character in comment», — то есть напечатанный проект не
 *     собирался вовсе;
 *   • rustc 1.96 — то же самое ошибкой сборки:
 *     `text_direction_codepoint_in_comment` deny-by-default;
 *   • javac 25 собирал молча даже под `-Xlint:all -Werror`, gcc 13 под
 *     `-Werror` молчал на ПАРНОЙ паре RLO…PDF (на непарной — ошибка). Молчание
 *     тулчейна здесь и есть беда, а не оправдание.
 *
 * ── Почему перебор по реестру ───────────────────────────────────────────────
 * Тест на бэкенд ловит только те бэкенды, о которых кто-то вспомнил, — ровно
 * поэтому правило и разошлось. Здесь перебор идёт ПО РЕЕСТРУ ЦЕЛЕЙ, а реестр —
 * сам каталог `src/emit` (`loadTargets()` из src/targets.mjs), тот же, по
 * которому работает `ftsc emit --target`. Девятая цель попадает под проверку
 * тем, что её модуль положили в каталог: списка целей, который можно забыть
 * пополнить, в этом файле нет. Сам файл подхватывается прогоном
 * `npm run test:tools` (`node --test tools/*/test/*.test.mjs`) — списка тестов,
 * который тоже можно забыть пополнить, там нет тоже.
 *
 * ── Что именно проверяется ──────────────────────────────────────────────────
 *   1. НИ ОДНОГО СЫРОГО СИМВОЛА ни в одном напечатанном файле — ни в коде, ни в
 *      комментарии, ни в имени файла;
 *   2. ЗНАЧЕНИЕ НЕ ИЗМЕНИЛОСЬ: напечатанное разбирается обратно в БАЙТЫ (у C
 *      экранирован каждый байт UTF-8 отдельно) и сверяется с именем из модели.
 *      Экранирование, потерявшее символ или подменившее кодовую точку, «чинит»
 *      предупреждение ценой чужой модели: имя правила в комментарии обязано
 *      читаться дословно, а имя примера в литерале — печататься при прогоне
 *      теми же байтами, что стоят в IR.
 *
 * Источник истины для имён — не константа в этом файле, а движок FTS
 * (`evaluateUtility` из dist/src, тот самый, которым пользуется сам ftsc в
 * src/self-check.mjs): он строит текст «нарушено свойство «…» утилиты «…»» из
 * имён модели, и ровно эти имена бэкенды печатают в комментарий и в литерал.
 * Сверять печать с переписанным от руки ожиданием значило бы проверять, что
 * автор теста и автор бэкенда одинаково поняли модель.
 *
 * Помощник проверки общий с тестом flang (bidi-guard.mjs): правило одно на оба
 * компилятора, и способ его проверить обязан быть один. Свои у этого теста —
 * программа (IR) и источник истины.
 *
 * Сырых двунаправленных в этом файле нет: они собраны из кодов, а не написаны
 * символами, — иначе тест воспроизводил бы ровно ту беду, от которой стережёт.
 */
import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { test } from "node:test"

import { evaluateUtility } from "../../../dist/src/index.js"
import { loadTargets } from "../src/targets.mjs"
import { BIDI_CONTROLS, bodiesBetween, decodeEscapes, emittedFiles, rawControls, УПРАВЛЯЮЩИЕ } from "./bidi-guard.mjs"

/* Бэкенды, существовавшие в день написания теста. Перебор идёт НЕ по этому
   списку, а по реестру: список держится только как нижняя граница.
   `loadTargets()` возвращает пустой список, если каталога нет (переехал,
   переименован), и без этой проверки перебор по пустому реестру выглядел бы
   успехом. */
const ИЗВЕСТНЫЕ = ["c", "csharp", "elixir", "go", "java", "python", "rust", "typescript"]

/* Якоря вокруг полезной нагрузки: чисто ASCII — их не экранирует ни одна цель,
   поэтому тело между ними находится в напечатанном файле без знания языка.
   Пробел в якорях обязателен: имя FTS попадает не только в текст, но и в
   идентификаторы целевого языка («Рассчитать скидку nameA … Zname» →
   RasschitatSkidkuNameAZname), и якорь без пробела нашёлся бы внутри
   идентификатора — с пустым телом между половинками, то есть тест ловил бы
   транслитерацию вместо экранирования. Закрывающий начинается с «Z»: это не
   шестнадцатеричная и не восьмеричная цифра, и к экранированию перед ним ничего
   не приклеится. */
const НАЧАЛО = "nameA "
const КОНЕЦ = " Zname"

/** Имя модели с двенадцатью управляющими внутри — собранное из кодов. */
const пометить = (имя) => `${имя} ${НАЧАЛО}${УПРАВЛЯЮЩИЕ}${КОНЕЦ}`

const ФИКСТУРА = fileURLToPath(new URL("./fixtures/discount.ir.json", import.meta.url))

/**
 * IR берётся из фикстуры, а не пишется здесь руками: она собрана make-fixtures
 * из настоящей модели репозитория тем же ядром FTS, и потому не разойдётся с
 * формой IR, которую бэкенды ждут на самом деле.
 *
 * Управляющие расставляются во ВСЕ имена, которые бэкенды печатают: категория
 * (она же имя модуля и часть пути к файлу), утилита, правило, свойство и
 * пример. Цель, экранировавшая только часть мест, здесь и падает.
 */
async function поместитьУправляющие() {
  const program = JSON.parse(await readFile(ФИКСТУРА, "utf8"))
  const entry = program.modules[0]
  entry.name = пометить(entry.name)
  entry.category = entry.name
  entry.document.category = entry.name
  program.order = [entry.name]

  const utility = entry.document.utilities[0]
  utility.name = пометить(utility.name)
  for (const rule of utility.rules) rule.name = пометить(rule.name)
  for (const property of utility.properties) property.name = пометить(property.name)
  for (const example of utility.examples) example.name = пометить(example.name)
  return { program, utility, example: utility.examples[0] }
}

test("ни один бэкенд ftsc не выводит двунаправленные управляющие сырыми", async (t) => {
  const { program, utility, example } = await поместитьУправляющие()

  /* Источник истины: движок FTS называет свойство и утилиту сам — из модели, а
     не из этого файла. Нарушение вызывается тем, что начальное значение утилиты
     уводится ниже нуля: первое свойство модели («скидка неотрицательна») этого
     не допускает, и движок обязан назвать его по имени. */
  const нарушающая = { ...utility, initial: -1 }
  let ошибка = null
  try {
    evaluateUtility(нарушающая, example.input)
  } catch (error) {
    ошибка = error
  }
  assert.ok(
    ошибка !== null && /нарушено свойство/u.test(ошибка.message),
    "движок FTS обязан отвергнуть отрицательную скидку: без этого имя свойства неоткуда взять",
  )
  assert.ok(
    ошибка.message.includes(utility.properties[0].name) && ошибка.message.includes(utility.name),
    "движок FTS называет свойство и утилиту дословно — печать обязана совпасть именно с этими именами",
  )
  const вИмени = [...utility.properties[0].name].filter((c) => BIDI_CONTROLS.includes(c.codePointAt(0)))
  assert.equal(вИмени.length, BIDI_CONTROLS.length, "в имени свойства обязаны быть все двенадцать управляющих")

  const targets = await loadTargets()
  const идентификаторы = targets.map((target) => target.id)
  for (const known of ИЗВЕСТНЫЕ) {
    assert.ok(идентификаторы.includes(known), `реестр целей потерял «${known}»: перебирать нечего, проверка не состоялась`)
  }

  for (const target of targets) {
    await t.test(`цель «${target.id}»`, () => {
      const files = emittedFiles(target.emit(program, { projectName: program.project }), target.id)

      const raw = rawControls(files)
      assert.deepEqual(
        raw,
        [],
        `бэкенд «${target.id}» печатает двунаправленные управляющие сырыми:\n  ${raw.join("\n  ")}\n` +
          "Экранировать их обязан весь вывод — имя FTS уезжает и в комментарий, и в строковый литерал. " +
          "Форма своя у каждого языка (\\NNN побайтно в C, \\uXXXX в Java, C#, Go, Python и TypeScript, " +
          "\\u{X…} в Rust и Elixir); общий фильтр на выходе emit() — escapeBidiInFiles из src/bidi.mjs",
      )

      /* Отсутствие сырых символов само по себе ещё не победа: бэкенд, потерявший
         их при печати, тоже «чист». Поэтому имена ищутся по якорям и
         разбираются обратно — в каждом месте, где напечатаны. */
      const имена = bodiesBetween(files, НАЧАЛО, КОНЕЦ)
      assert.ok(
        имена.length > 0,
        `бэкенд «${target.id}» нигде не напечатал имена модели: якорь «${НАЧАЛО}» не найден. Имя правила стоит ` +
          "в комментарии, имя примера — в литерале прогонщика; если их не стало, потерялась не проверка, а связь " +
          "напечатанного кода с моделью",
      )
      for (const { path, body } of имена) {
        assert.equal(
          decodeEscapes(body),
          УПРАВЛЯЮЩИЕ,
          `бэкенд «${target.id}», файл ${path}: имя модели напечатано не дословно — экранирование обязано ` +
            "восстанавливаться в те же кодовые точки и те же байты, что дал движок FTS",
        )
      }
    })
  }
})
