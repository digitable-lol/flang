/**
 * Двунаправленные управляющие в исходнике, который печатает ftsvm.
 *
 * Третья поверхность печати репозитория. Первые две — восемь бэкендов flang и
 * восемь бэкендов ftsc — правило соблюдают, и у каждой есть свой тест,
 * перебирающий реестр целей. Здесь реестра нет: цель одна, JavaScript, — и
 * ровно поэтому дыра тут и осталась. Правило жило в модулях бэкендов, а сюда
 * его никто не принёс.
 *
 * Чем это отличается от печати в файл: исходник ftsvm не сохраняется, а сразу
 * идёт в `new Function`. Отсюда соблазн решить, что комментарий в нём никто не
 * прочтёт. Прочтёт: `ftsvm source` печатает его на экран, и это отладочная
 * команда — то есть его читают именно тогда, когда что-то пошло не так и
 * доверия к глазам меньше всего.
 *
 * Форма `\uXXXX` работает по обе стороны и по разным причинам. В литерале это
 * настоящее экранирование, и значение не меняется — здесь это проверяется
 * прогоном примеров, а не рассуждением. В комментарии это шесть печатных
 * знаков, которые ничего не переставляют.
 */
import assert from "node:assert/strict"
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import test from "node:test"
import { fileURLToPath } from "node:url"

import { BIDI_CONTROLS } from "../../ftsc/src/bidi.mjs"
import { compileUtility, sourceOf } from "../src/jit.mjs"
import { loadProgram } from "../src/load-fts.mjs"

const РЕПОЗИТОРИЙ = fileURLToPath(new URL("../../../", import.meta.url))

/** Все двенадцать управляющих сразу: частичное экранирование обязано падать. */
const УПРАВЛЯЮЩИЕ = [...BIDI_CONTROLS].map((точка) => String.fromCodePoint(точка)).join("")

/**
 * Настоящая модель репозитория с управляющими, вписанными в имена.
 *
 * Именно модель, а не собранная руками структура: у правил и условий своя
 * форма, и подделка проверяла бы подделку. Имена — то место, где такие символы
 * попадают в печать законно: имя пишет человек, а не компилятор.
 */
function модельСУправляющими() {
  const источник = join(РЕПОЗИТОРИЙ, "examples/utilities/discount.fts")
  const текст = readFileSync(источник, "utf8")
    .replace("«Рассчитать скидку»", `«Рассчитать${УПРАВЛЯЮЩИЕ} скидку»`)
    .replace("«Большая покупка»", `«Большая${УПРАВЛЯЮЩИЕ} покупка»`)
  const каталог = mkdtempSync(join(tmpdir(), "ftsvm-bidi-"))
  const путь = join(каталог, "bidi.fts")
  writeFileSync(путь, текст, "utf8")
  return путь
}

test("напечатанный исходник не содержит ни одного сырого управляющего", async () => {
  const программа = await loadProgram([модельСУправляющими()], { project: "проба" })
  const модуль = программа.modules[0]
  const утилита = модуль.document.utilities[0]
  const исходник = sourceOf(программа, модуль.name, утилита.name)

  const найдено = []
  исходник.split("\n").forEach((строка, номер) => {
    ;[...строка].forEach((знак, столбец) => {
      if (BIDI_CONTROLS.has(знак.codePointAt(0))) {
        найдено.push(`строка ${номер + 1}, столбец ${столбец + 1}: U+${знак.codePointAt(0).toString(16).toUpperCase()}`)
      }
    })
  })
  assert.deepEqual(найдено, [], `сырые управляющие в исходнике ftsvm:\n  ${найдено.join("\n  ")}`)

  /* Символы обязаны быть НА МЕСТЕ, а не выброшены: потеря — тоже расхождение,
     просто менее заметное. Имя утилиты содержит их все, значит и экранированных
     последовательностей обязано быть столько же. */
  const экранированных = (исходник.match(/\\u[0-9a-f]{4}/gu) ?? []).filter((строка) =>
    BIDI_CONTROLS.has(Number.parseInt(строка.slice(2), 16)),
  )
  assert.ok(
    экранированных.length >= BIDI_CONTROLS.size,
    `экранированных последовательностей ${экранированных.length}, а управляющих в именах ${BIDI_CONTROLS.size}`,
  )
})

test("экранирование не меняет поведения: примеры модели сходятся", async () => {
  /* Главная проверка. Экранировать можно так, что исходник станет чистым, а
     значение изменится — и заметить это по глазам нельзя. Поэтому напечатанное
     собирается и прогоняется на примерах самой модели. */
  const программа = await loadProgram([модельСУправляющими()], { project: "проба" })
  const модуль = программа.modules[0]
  const утилита = модуль.document.utilities[0]
  const собранная = compileUtility(программа, модуль.name, утилита.name)

  let сошлось = 0
  for (const пример of утилита.examples) {
    assert.deepEqual(собранная(пример.input), пример.expected, пример.name)
    сошлось += 1
  }
  assert.ok(сошлось >= 3, `примеров всего ${сошлось}`)
})
