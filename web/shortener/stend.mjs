/**
 * stend.mjs — стенд, на котором приложение встречается с настоящей службой.
 *
 * Он делает ровно две вещи: отдаёт файлы дерева как есть и переводит запросы
 * браузера службе-сокращателю, написанной на flang
 * (`flang/examples/web/shortener/service.flang`). Прикладной логики здесь ноль:
 * ни одного решения о ссылках, кодах и переходах не принимается — их принимает
 * flang, функция «Обслужить», ровно как в `serve.mjs` рядом со службой.
 *
 * ── Почему это вообще понадобилось: пять расхождений, все измеренные ────────
 *
 * Служба писалась под хозяина Node, который говорит сырыми байтами. Браузер —
 * не такой клиент, и напрямую они не сходятся ни в одном из пяти мест:
 *
 *   1. ЗАГОЛОВКОВ CORS НЕТ НИ ОДНОГО. Весь набор заголовков ответа службы —
 *      `Content-Type` и, на переезде, `Location`
 *      (`service.flang`, «Заголовки решения»). Межисточниковый запрос браузер
 *      зарежет, а статики служба не отдаёт — то есть «того же источника»,
 *      откуда подать страницу, у неё нет вовсе.
 *   2. НА `OPTIONS` СЛУЖБА ОТВЕЧАЕТ 405. Предварительная проверка браузера
 *      («preflight») до службы даже не дойдёт.
 *   3. ПУТИ КИРИЛЛИЦЕЙ НУЖНЫ СЫРЫМИ БАЙТАМИ, А БРАУЗЕР ИХ КОДИРУЕТ ПРОЦЕНТАМИ.
 *      `GET /ссылки` сырыми байтами — 200; `GET /%D1%81%D1%81...` — 404:
 *      раскодирование процентов в `stdlib/http.flang` доводит до знака только
 *      коды 32…126. Обойти это из браузера нечем: ни `fetch`, ни `XHR` не дают
 *      послать путь мимо кодирования.
 *   4. `Content-Length` СЧИТАЕТСЯ ЗНАКАМИ, А НЕ БАЙТАМИ (`stdlib/http.flang`,
 *      «Напечатать ответ»; зазор назван и в `service.flang`). Тело
 *      `адрес=https://…` начинается с шести КИРИЛЛИЧЕСКИХ знаков — это 6 знаков
 *      и 11 байтов. Браузер поставит честную длину в байтах, служба сочтёт
 *      запрос неполным и будет ждать добавки.
 *   5. ОДНО СОЕДИНЕНИЕ — ОДИН ОБМЕН, при этом `Connection: close` не
 *      посылается. Браузер попробует переиспользовать соединение и получит
 *      закрытый сокет.
 *
 * Ни одно из пяти не про приложение и не про язык: это долг СЛУЖБЫ, написанной
 * до того, как у языка появился браузер. Стенд их переводит и тем самым
 * называет — каждое отдельной строкой кода, а не общими словами.
 *
 * ── Почему служба зовётся в памяти, а не по сети ────────────────────────────
 *
 * Тот же приём, что в `flang/examples/web/shortener/serve.mjs`: «Обслужить» —
 * ЧИСТАЯ функция «состояние и байты запроса → новое состояние и байты ответа»,
 * и сокет ей не нужен. Состояние передаётся из витка в виток значением. Так
 * стенд не заводит второго сервера рядом с первым и не заводит второй копии
 * службы: работает та самая, что лежит в дереве.
 *
 * Запуск:
 *   node web/shortener/stend.mjs            # 8912, из корня дерева
 *   node web/shortener/stend.mjs 9000        # свой порт
 */
import { createServer } from "node:http"
import { readFile } from "node:fs/promises"
import { extname, join, normalize, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { loadProgram } from "../../flang/bin/flang.mjs"
import { evaluateFlang } from "../../flang/src/compat.mjs"
import { emitJs } from "../../flang/src/emit/js.mjs"

const здесь = fileURLToPath(new URL(".", import.meta.url))
const корень = resolve(здесь, "../..")
const служба = resolve(корень, "flang/examples/web/shortener/service.flang")
const клиент = resolve(здесь, "klient.flang")
const порт = Number(process.argv[2] ?? process.env.ПОРТ ?? 8912)

/* Программа читается ОДИН раз, а не на каждый запрос — как и в настоящем
   сервере, где разбор исходника случается при запуске. */
const программа = await loadProgram(служба)

/*
 * Приложение ПЕЧАТАЕТСЯ при запуске стенда и отдаётся из памяти по адресу
 * `./klient.js`. Три довода, и ни один не про удобство:
 *
 *   • напечатанного файла нет в дереве — значит нечему устареть. Артефакт,
 *     который коммитят, расходится с исходником молча, и увидит это только тот,
 *     кто вспомнит его перепечатать;
 *   • вкладка везёт РЕЗУЛЬТАТ печати, а не компилятор. Печать случается ЗДЕСЬ,
 *     в Node, один раз за запуск стенда;
 *   • прогон в настоящем браузере (`probe.mjs`) поднимает стенд сам, значит
 *     проверяется всегда свежая печать.
 *
 * Прогонщик не печатается (`cli: false`): `flang_cli.js` — командная строка,
 * во вкладку она не едет.
 */
const напечатано = emitJs(await loadProgram(клиент), { cli: false }).files[0].content
console.log(`приложение: ${клиент} → ${[...напечатано].length} знаков напечатанного JavaScript`)

/** Хранилище ссылок. Одно на стенд: значение, а не база. */
let хранилище = { записи: [], выдано: 0 }

/** Пути, которые принадлежат службе, а не дереву файлов. */
const СЛУЖБЕ = ["/ссылки", "/с/", "/здоровье"]

const ТИПЫ = {
  ".html": "text/html; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".flang": "text/plain; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
}

/**
 * Один виток службы: байты запроса — байты ответа.
 *
 * `Content-Length` пересчитывается в ЗНАКИ (расхождение 4 выше). Считать
 * октеты служба не умеет: `длина` в языке считает знаки, и функции «сколько
 * байтов в строке UTF-8» в языке нет.
 */
function обслужить(способ, путь, тело) {
  const голова = `${способ} ${путь} HTTP/1.1\r\nHost: стенд\r\n`
  const текст =
    тело === "" ? `${голова}\r\n` : `${голова}Content-Length: ${[...тело].length}\r\n\r\n${тело}`
  const о = evaluateFlang(программа, "Обслужить", { хранилище, текст }, { maxSteps: 40_000_000 })
  хранилище = о["состояние"]
  return { код: о["код"], ответ: о["ответ"] ?? "" }
}

/** Разобрать сырой ответ службы в то, чем отвечает `node:http`. */
function разобрать(сырой) {
  const рубеж = сырой.indexOf("\r\n\r\n")
  if (рубеж < 0) return { заголовки: {}, тело: "" }
  const строки = сырой.slice(0, рубеж).split("\r\n").slice(1)
  const заголовки = {}
  for (const строка of строки) {
    const двоеточие = строка.indexOf(":")
    if (двоеточие <= 0) continue
    const имя = строка.slice(0, двоеточие).trim()
    const значение = строка.slice(двоеточие + 1).trim()
    /* Продолжение расхождения 3: служба кладёт в `Location` СЫРОЙ адрес, а он
       кириллический. Node такой заголовок не пропустит (`ERR_INVALID_CHAR`), и
       браузер бы не пропустил тоже: в заголовке допустимы только коды до 127.
       Кодируем процентами — единственное, что тут можно сделать честно. Стоило
       это одного упавшего перехода: было «500 Moved Permanently», то есть код
       500 при строке состояния от 301. */
    заголовки[имя] = /^[\x20-\x7e]*$/u.test(значение) ? значение : encodeURI(значение)
  }
  /* `Content-Length` службы посчитан в знаках и для Node неверен — считает его
     заново сам Node по телу. Расхождение 4, переведённое обратно. */
  delete заголовки["Content-Length"]
  return { заголовки, тело: сырой.slice(рубеж + 4) }
}

const служебный = (путь) => СЛУЖБЕ.some((начало) => путь === начало || путь.startsWith(начало))

createServer(async (запрос, ответ) => {
  const адрес = new URL(запрос.url, "http://стенд")
  /* Расхождение 3: браузер закодировал кириллицу процентами, служба ждёт сырых
     байтов. `pathname` возвращает закодированное, раскодируем обратно. */
  const путь = decodeURIComponent(адрес.pathname)

  /* Напечатанный модуль — из памяти, а не с диска: на диске его нет. */
  if (путь === "/web/shortener/klient.js") {
    ответ.writeHead(200, { "Content-Type": "text/javascript; charset=utf-8" })
    ответ.end(напечатано)
    return
  }

  if (служебный(путь)) {
    const куски = []
    for await (const кусок of запрос) куски.push(кусок)
    const тело = Buffer.concat(куски).toString("utf8")
    try {
      const { код, ответ: сырой } = обслужить(запрос.method, путь, тело)
      const { заголовки, тело: содержимое } = разобрать(сырой)
      /* Расхождение 1: заголовка о разрешённом источнике у службы нет. Здесь он
         не нужен — стенд и страница одного источника, — но переезд на чужой
         адрес браузер всё равно выполнит сам, и `Location` мы отдаём как есть. */
      ответ.writeHead(код === 0 ? 502 : код, заголовки)
      ответ.end(содержимое)
    } catch (беда) {
      ответ.writeHead(500, { "Content-Type": "text/plain; charset=utf-8" })
      ответ.end(String(беда?.message ?? беда))
    }
    return
  }

  /* Расхождение 2 снято тем, что предварительной проверки не случается вовсе:
     страница и служба одного источника. */
  const внутри = normalize(join(корень, путь === "/" ? "/web/shortener/index.html" : путь))
  if (!внутри.startsWith(корень)) {
    ответ.writeHead(403, { "Content-Type": "text/plain; charset=utf-8" })
    ответ.end("наружу дерева стенд не ходит")
    return
  }
  try {
    const байты = await readFile(внутри)
    ответ.writeHead(200, { "Content-Type": ТИПЫ[extname(внутри)] ?? "application/octet-stream" })
    ответ.end(байты)
  } catch {
    ответ.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" })
    ответ.end(`нет файла ${путь}`)
  }
}).listen(порт, "127.0.0.1", () => {
  console.log(`стенд: http://127.0.0.1:${порт}/web/shortener/index.html`)
  console.log(`служба: ${служба}`)
})
