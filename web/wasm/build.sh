#!/bin/sh
# Сборка программы на flang в WebAssembly через бэкенд C.
#
# Ничего специально «вебового» здесь нет и не понадобилось: бэкенд печатает
# переносимый C99, а wasm32-wasi — обычная тройка clang. Весь путь — две команды.
#
#   ./web/wasm/build.sh web/wasm/spusk.flang web/wasm/demo
#
# Нужен clang с целью wasm32 (в нём она есть всегда) и wasi-libc:
#   Ubuntu/Debian: apt install wasi-libc libclang-rt-21-dev-wasm32
#   иначе:         wasi-sdk, тогда WASI_SYSROOT указывает в него.
#
# Второй аргумент — куда положить .wasm; C печатается во временный каталог и
# не остаётся: он производная, а не исходник.
#
# Имена переменных — латиницей: POSIX sh (dash) кириллическое имя переменной
# не принимает, и скрипт обрывается на первой же строке присваивания.
set -eu

SOURCE=${1:?нужен файл .flang}
OUT=${2:-.}
SYSROOT=${WASI_SYSROOT:-/usr}

# ── Теневой стек: ОДНО число, и оно названо замером ────────────────────────
#
# Флага здесь ровно один, и это главное, что изменилось. Раньше их требовалось
# два — `-Wl,-z,stack-size` давал память, а `-DFL_STACK_ROOM_FALLBACK` сообщал о
# ней рантайму, — и стоило им разойтись, сторож считал по числу, которого нет.
# Разойтись они и разошлись: умолчание `wasm-ld` 64 КиБ против запасного
# мегабайта рантайма, шестнадцатикратно, и в окне между «сторож молчит» и «стек
# кончился» вкладка умирала. Теперь рантайм ЧИТАЕТ настоящие границы теневого
# стека из самого модуля (`fl_wasm_room` в flang_runtime.c), поэтому согласовать
# нечего: сколько отвёл компоновщик, столько сторож и видит.
#
# Почему именно 8 МиБ, а не больше и не меньше. Замер, Chrome 151.0.7922.34,
# «Обратный отсчёт» при объявленном пределе 10 000:
#
#   теневой стек   глубина     чем кончилось
#         64 КиБ        39     FLANG_RECURSION_LIMIT (умолчание wasm-ld)
#          1 МиБ       825     FLANG_RECURSION_LIMIT
#          8 МиБ     7 474     FLANG_RECURSION_LIMIT
#         16 МиБ         —     RangeError: Maximum call stack size exceeded
#         32 МиБ         —     RangeError: Maximum call stack size exceeded
#
# Выше 8 МиБ выигрывает стек ХОЗЯИНА, которого модуль не видит и видеть не
# может, — и правду про него говорит уже не сторож модуля, а тот, кто модуль
# завёл (в demo/index.html это сделано). Восемь мегабайт — то же число, что
# FL_STACK_MIN у обычной сборки, и последняя степень двойки, на которой сторож
# модуля ещё успевает первым.
#
# Модулю это не стоит почти ничего: этим же скриптом web/wasm/spusk.flang весит
# 221 969 байт при 64 КиБ и 221 971 при 8 МиБ — два байта, длина числа в разделе
# памяти. Теневой стек это диапазон адресов, а не данные в файле.
#
# У других сред потолок свой: wasmtime по умолчанию даёт 512 КиБ и поднимается
# `-W max-wasm-stack=8388608`. Кто собирает под неё, ставит FL_STACK_SIZE по её
# числу — и рантайм подхватит его сам, без второго флага.
STACK=${FL_STACK_SIZE:-8388608}

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

NAME=$(basename "$SOURCE" .flang)

"$ROOT/bootstrap/flang" emit "$SOURCE" --target c --out "$TMP" >/dev/null

mkdir -p "$OUT"
clang --target=wasm32-wasi --sysroot="$SYSROOT" -O2 -std=c99 \
  -Wl,-z,stack-size="$STACK" \
  -o "$OUT/$NAME.wasm" "$TMP"/*.c -lm

ls -l "$OUT/$NAME.wasm"
